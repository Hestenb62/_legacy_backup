<p class="ind"><span class="sc">Madame ma bien chère Sœur</span>,—Mes souvenirs de Windsor
sont de ceux dont aucun ne s'efface. Je n'oublie donc pas
une petite question qui m'a été si joliment adressée, <i>Where
is my gun?</i> et à présent j'en ai trouvé un qui serait indigne de
la destinée que je prie votre Majesté de me permettre de lui
