<p class="note1">Footnote 24: British Envoy at Athens.</p>
<p class="note1">Footnote 25: <i>See</i> Introductory Note for 1850, <i>post</i>, <a href="#pageii.231" style="font-weight: normal;" class="pginternal">p. 231</a>.</p>
