<h2 id="c4"> <span class="small">THE OLDER ROCKS</span></h2>
<p>The rocks which underlie Button Bay State Park can be seen along
the small creek which is located just south of the Park. It is suggested
that the visitor walk southward (to the right if approaching the road from
the lake front) along the main park road until the first culvert beneath
the road is reached. Looking down the creekbed toward the lake, one
can readily see the older rocks (see A, <a href="#fig11" class="pginternal">Figure 11</a>). <i>Fossils</i><a class="fn pginternal" href="#fn_18" id="fr_18">[18]</a> are found in
these tilted rocks which tilt or dip toward the northeast and “strike”
northwestward. Fossils date the rocks underlying Button Bay State
<span class="pb" id="Page_20">20</span>
Park as Middle <i>Ordovician</i>.<a class="fn pginternal" href="#fn_19" id="fr_19">[19]</a> The most abundant fossil is a trilobite,
<i>Triarthrus</i>, but, even this ancient <i>arthropod</i><a class="fn pginternal" href="#fn_20" id="fr_20">[20]</a> is not easily found in these
limestones and limy shales. A sketch of <i>Triarthrus</i> (that portion found
fossilized) appears in <a href="#imgx3" class="pginternal">Plate 1</a>. These rocks containing <i>Triarthrus beckii</i>
belong to the Stony Point formation and are of late Sherman Fall or
Denmarkian age.</p>
<p>One of the jobs of the geologist is to reconstruct the paleogeography
(ancient geography) of a region. The different kinds of rocks present and
their distribution patterns, together with the types of fossil plants and
animals found, tell the geologist of past lands and seas, warm and cold
climates. The rocks of the Stony Point formation (the rocks which underlie
most of the Park) tell of warm marine waters, a past sea, bordered
by relatively low land areas. The fossils contained in the Stony Point
formation attest to the presence of relatively shallow marine waters.
The fact that these Ordovician rocks are tilted and broken by faults
proves that <i>major earth movements</i><a class="fn pginternal" href="#fn_21" id="fr_21">[21]</a> took place sometime after their
lithification.</p>
