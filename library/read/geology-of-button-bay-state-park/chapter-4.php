<p>From the north boundary of the Park and along the Lake Champlain
shoreline older and older Ordovician rocks are <i>encountered</i>.<a class="fn pginternal" href="#fn_22" id="fr_22">[22]</a> The rocks
(see geologic map, <a href="#fig11" class="pginternal">Fig. 11</a>), primarily tilted marine limestones, display
a variety of fossils, some of which are illustrated in <a href="#imgx3" class="pginternal">Plate 1</a>. <a href="#fig12" class="pginternal">Figure 12</a> is a
view of the west side of Button Island showing an 18-inch thick reefy
zone in the Orwell limestone. The reefy zone is composed largely of
tumbled heads of colonial corals and stromatoporoids. A selected list of
reference books and articles, some of which contain plates picturing
Ordovician fossils, is found at the end of this section.</p>
<p>Ordovician and older rocks were lifted, folded and faulted during the
Taconic Disturbance. Dramatic evidence for this period of crustal instability
is seen in the Champlain Thrust, a major series of faults which
can be seen east of Button Bay State Park. The evidence for such a fault
system, which is more fully discussed in another pamphlet, is readily
seen on Mount Philo where older Cambrian rocks have overridden (been
thrust over) younger Ordovician ones.</p>
<p>As time passed in the Button Bay region younger and younger sediments
were deposited over the top of folded and eroded Ordovician
rocks. These sediments became rock and in turn slowly broke into fragments
which were transported to other areas where they were deposited
again as sediments. The glaciers passed over, leaving their rock debris
behind as they wasted northward. Marine clays were slowly deposited
from the waters of the Champlain Sea. Today only the marine clays
resting on the beveled edges of Middle Ordovician rocks can be seen in
the Park.</p>
<p>The history of the earth is open for all to read. Button Bay State
Park can tell us only the history which is recorded in its clays and underlying
rocks. As we have seen, there are certain giant geologic time gaps
in the Park area, but many of these do not exist in other places and in
other Parks. If this pamphlet has stimulated an interest in filling in
<span class="pb" id="Page_24">24</span>
these time gaps through your study of rocks in other places, then it has
fulfilled its purpose. The present interest in Space demands a good long
look at the Planet Earth. Good Hunting!</p>
