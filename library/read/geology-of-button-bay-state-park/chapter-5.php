<h2 id="c5"> <span class="small">SUGGESTED READING</span></h2>
<p class="revint"><i>Historical Geology</i>, by Carl O. Dunbar, John Wiley &amp; Sons, Inc., New
York, 1960. Good general treatment of what the rocks can and do
tell geologists about the history of the Earth.</p>
<p class="revint"><i>Handbook of Paleontology for Beginners and Amateurs</i>, Part 1, The
Fossils, by Winifred Goldring, New York State Museum Handbook
9 (obtainable from: Paleontological Research Institution, 190 Dearborn
Place, Ithaca, N. Y.).</p>
<p class="revint"><i>Fossils, An Introduction to Prehistoric Life</i>, by W. H. Matthews III,
1962, Barnes and Noble, Inc., New York. Earth history and paleontology,
a general guide for the amateur collector.</p>
<p class="revint"><i>Bedrock Geology of the Central Champlain Valley of Vermont</i>, by Charles
W. Welby, 1961. Vermont Geological Survey Bulletin 14. Standard
work for the geology in the region of Button Bay State Park.</p>
<p class="revint"><i>Paleontology of the Champlain Basin in Vermont</i>, by C. W. Welby,
Vermont Geology Series, Vermont Geological Survey. A treatise on
the paleontology of the Champlain Basin designed for the amateur.
In press.</p>
<p class="revint"><i>Index Fossils of North America</i>, by H. W. Shimer and R. R. Shrock, 1944,
John Wiley &amp; Sons, Inc., New York. Contains many plates depicting
several of the fossils found in and adjacent to Button Bay State Park.</p>
<h2 id="c6"> <span class="small">Footnotes</span></h2>
<div class="fnblock"><div class="fndef"><a class="fn pginternal" href="#fr_1" id="fn_1">[1]</a>Most of the information for this section was graciously supplied by Clara E.
Follette, Librarian and Museum Director, Vermont Historical Society, Montpelier,
Vermont, in a letter to the author dated April 26, 1961.
</div><div class="fndef"><a class="fn pginternal" href="#fr_2" id="fn_2">[2]</a>“The governors (and other gentlemen) appear to have included Sir Henry Moore,
Governor of New York, General Carleton, Governor of Quebec, Brig. General Philip
Schuyler (and Adolphus Benzel, map maker). The activities of these persons on the
lake at that time were evidently concerned with making observations, primarily to
determine boundaries.”
</div><div class="fndef"><a class="fn pginternal" href="#fr_3" id="fn_3">[3]</a>Seely, H. M., 1910, Preliminary Report of the Geology of Addison County;
Vermont State Geologist, 7th Biennial Report, p. 257-315.
</div><div class="fndef"><a class="fn pginternal" href="#fr_4" id="fn_4">[4]</a>Concretions consist of concentrations of certain chemical elements and compounds
into regular or irregular masses. Many times the center of a concretion consists of a
definite nucleus such as a grain of sand or shell fragment. For a general idea of the
size and shape of the concretions seen along the Button Bay State Park beach see
<a href="#fig3" class="pginternal">Fig. 3</a> and <a href="#imgx1" class="pginternal">cover picture</a>.
</div><div class="fndef"><a class="fn pginternal" href="#fr_5" id="fn_5">[5]</a>These clays were deposited from marine waters which flooded the Champlain
Valley after the final retreat of the glaciers which completely covered New England
during the “Great Ice Age” or Pleistocene Epoch. The Pleistocene Epoch began approximately
one million years ago and if the age of the Earth is considered to be five
billion (5,000 million) years, then, the clays do record recent geologic history.
</div><div class="fndef"><a class="fn pginternal" href="#fr_6" id="fn_6">[6]</a>As the weight of the ice was removed from the Hudson Valley region the earth’s
crust, in way of adjustment to this removal of weight, slowly began to rise. Some geologists
doubt whether the removal of ice weight alone can account for the crustal rise
and propose other internal forces as partly or wholly responsible. The fact remains
that the earth’s crust did rise in this area.
</div><div class="fndef"><a class="fn pginternal" href="#fr_7" id="fn_7">[7]</a>As the ice retreated, a succession of lakes formed in the Champlain Valley. Each
lake had a level waterline during its history and certain lakeshore features formed, as
they do in any present-day lake, with respect to each past level water-line. For example,
ridges of sand and gravel were heaped along the shoreline by lake waves.
Wave-cut and wave-built flat areas or terraces were formed along the margins of
lakes or along the sides of islands within a lake. Streams entering a lake built deltas
by depositing materials it had carried down from the surrounding highlands.
</div><div class="fndef"><a class="fn pginternal" href="#fr_8" id="fn_8">[8]</a>Elevation is measured in feet above the mean sea level of today, with mean sea
level being zero feet.
</div><div class="fndef"><a class="fn pginternal" href="#fr_9" id="fn_9">[9]</a>A most impressive view can be
gained from any one of the several lookout points
at the summit level of Mt. Philo. Looking to the west, toward Lake Champlain, and
south in the direction of Vergennes and Button Bay State Park, a three dimensional
view of an old lake (Lake Vermont) can be seen. In this view the present Lake Champlain
Lowlands represent the old lake bottom and the numerous hills rising above
this Lowland were once islands or near-islands which dotted the surface of the lake.
It takes very little imagination to place yourself on the “island of Mt. Philo” and to
visualize a boat tied to a dock just below the rocky cliffs on which you stand. A trip
to Mt. Philo with its spectacular view of the Champlain Lowlands (see <a href="#fig6" class="pginternal">Fig. 6</a>) is
recommended.
</div><div class="fndef"><a class="fn pginternal" href="#fr_10" id="fn_10">[10]</a>One word of caution, the Park authorities may import sand from other areas of
Vermont to improve the swimming facilities along the beach. In this case, the abundant
sand on the beach will not constitute the “natural beach composition” for
Button Bay State Park.
</div><div class="fndef"><a class="fn pginternal" href="#fr_11" id="fn_11">[11]</a>The blue color is due to the presence of ferrous iron (bivalent iron) together with
iron compounds in which iron has its higher chemical valence (ferric iron). This
ferrous iron demands a chemically reducing environment for its formation and indicates
that the clays were deposited in a shallow sea or that they remained for some
time beneath a stable water-table. They contained a fair quantity of decaying organic
material.
</div><div class="fndef"><a class="fn pginternal" href="#fr_12" id="fn_12">[12]</a>The brown color is due to the presence of the ferric hydroxide, goethite (HFeO₂).
</div><div class="fndef"><a class="fn pginternal" href="#fr_13" id="fn_13">[13]</a>This fossil whale is scientifically known as <i>Delphinapterus vermontanus</i> (<i>Thompson</i>).
</div><div class="fndef"><a class="fn pginternal" href="#fr_14" id="fn_14">[14]</a>The pelecypods found are scientifically known as <i>Macoma groenlandica</i> and
<i>Saxicava rugosa</i>.
</div><div class="fndef"><a class="fn pginternal" href="#fr_15" id="fn_15">[15]</a>The size limits of sand lie between 2mm in diameter (largest) and ¹/₁₆mm in
diameter (smallest). Two millimeters (mm) equals approximately ²/₂₅ inches. Fine
sand would fall between ¼mm and ⅛mm in diameter.
</div><div class="fndef"><a class="fn pginternal" href="#fr_16" id="fn_16">[16]</a>Convolute beds show their layers thrown into a series of folds (some quite irregular)
which result from the pressing weight of overlying sediments on highly plastic
layers beneath. Some feel that these folds were the result of actual flowage of the
layers in the direction of their tilt, and others credit the distorted bedding to the
pressing weight of large boulders. These dragged across the layers while still frozen to
overriding glacial ice.
</div><div class="fndef"><a class="fn pginternal" href="#fr_17" id="fn_17">[17]</a>The author noted both <i>Macoma groenlandica</i> and <i>Saxicava rugosa</i> (see <a href="#fig10" class="pginternal">Fig. 10</a> and
<a href="#imgx3" class="pginternal">Plate 1</a>, Sketches 3 and 4).
</div><div class="fndef"><a class="fn pginternal" href="#fr_18" id="fn_18">[18]</a>Fossils are the preserved evidence of past life (animal or plant) as found in rocks
or sediments, for example, the clams found in the clays. They may be direct evidence,
such as the actual shells or mineralogically replaced shells of long-dead animals; or
indirect evidence, such as the tracks or trails of animals now preserved in rocks.
</div><div class="fndef"><a class="fn pginternal" href="#fr_19" id="fn_19">[19]</a>Geologic time is divided into four Eras which are designated from oldest to youngest:
Precambrian, Paleozoic, Mesozoic, and Cenozoic. Each of these Eras is divided
into geologic Periods of time. The Ordovician Period is next to the oldest Period of
the Paleozoic Era. This Period began some 420 million years ago, and ended approximately
360 million years ago.
</div><div class="fndef"><a class="fn pginternal" href="#fr_20" id="fn_20">[20]</a>Present Arthropods include the insects, spiders and crabs. Arthropods, which
are invertebrate animals (without backbones), are characterized by jointed legs,
chitinous outer covering and segmented body parts. Trilobites were very numerous
in the early Paleozoic seas, but became extinct before the end of that Era.
</div><div class="fndef"><a class="fn pginternal" href="#fr_21" id="fn_21">[21]</a>The folding and the faulting of the Ordovician rocks took place sometime between
the closing phases of the Ordovician Period and the beginning of late Silurian time
(between 360 and 330 million years ago). Usually these earth movements are ascribed
to the Taconic Disturbance which took place at the end of the Ordovician Period.
</div><div class="fndef"><a class="fn pginternal" href="#fr_22" id="fn_22">[22]</a>A walk along the beach in the direction of Button Island or “sickle point” (west
and then south from the northern boundary of the Park) traverses the following
geologic formations: the Glens Falls limestone which can be seen on Ship Point
(actually an island off the northern end of the Park); the Orwell limestone, seen on
Button Island; the Valcour formation which makes up “sickle point”; and the Crown
Point limestone which is found on the Basin Harbor-side of “sickle point.” These
rock units belong to the Chazyan Stage (Crown Point limestone and Valcour formation)
and the next younger Mohawkian Stage (Orwell and Glens Falls limestones) of
the Middle Ordovician Champlainian Series.
