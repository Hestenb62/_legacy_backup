<h2 id="c3"> <span class="small">THE CLAYS OF BUTTON BAY STATE PARK</span></h2>
<p>The best location in the park for a good look at the clays which cover
the entire Park area is along the lake beach (see Figs. <a href="#fig4" class="pginternal">4</a> and <a href="#fig8" class="pginternal">8</a>). The bank
averages 23 feet in height measured from the beach to the top of the
bank. The width of the beach varies seasonally and during storms as
the water level of Lake Champlain fluctuates (see Figs. <a href="#fig4" class="pginternal">4</a> and <a href="#fig8" class="pginternal">8</a>). A walk
along the beach will reveal some interesting facts about the composition
of the beach and the adjacent clay banks.</p>
<p>One cannot help observing the scarcity of <i>sand</i><a class="fn pginternal" href="#fn_10" id="fr_10">[10]</a> on the beach. The
only adjacent material to build this beach is clay, which here contains a
small quantity of sand and some concretions containing lime. The sickle
shape of Button Bay keeps most foreign sand from the beach. The small
patches of sand present soon give way to <i>blue clay</i><a class="fn pginternal" href="#fn_11" id="fr_11">[11]</a> which, in many
places, forms the base of the beach. This blue clay can also be seen in
the base of the bank in the southern portion of the Park, where it underlies
and is therefore older than the <i>brown clay</i>.<a class="fn pginternal" href="#fn_12" id="fr_12">[12]</a></p>
<p>Actually very little of the blue clay is exposed in the Park. From other
locations along the shore of Lake Champlain and in the more inland
areas of the Champlain Lowlands geologists have found many clues to
help our understanding of its history.</p>
