<p>Remember from the previous discussion of Lake Vermont that as the
Champlain ice lobe retreated into Canada, fresh water from Lake Vermont
began to seep through the ice lobe into the St. Lawrence Valley.
This seepage caused a gradual lowering of the Lake Vermont water-level
until the lake reached a stage lower than the marine waters of the
St. Lawrence Sea. Soon the sea water began to flood Lake Vermont and
true marine conditions were reached. These marine waters reached as
<span class="pb" id="Page_18">18</span>
far south as Whitehall, New York, which is located near the southern
end of present-day Lake Champlain.</p>
<p>The maximum area covered by the Champlain Sea did not equal the
greatest size attained by the fresh waters of Lake Vermont. For instance,
the sea did not extend as far east as the Green Mountains except in the
very northernmost region of Vermont. In the vicinity of Button Bay
State Park these waters extended less than a mile east of Vergennes,
and the towns of Middlebury, Hinesburg and Charlotte would have been
entirely above water (see map, <a href="#fig7" class="pginternal">Fig. 7</a>B).</p>
<p>It has been postulated that marine waters extended throughout the
length of the Champlain Valley and into the Hudson Valley, forming a
continuous strip of marine water from the Gulf of St. Lawrence to the
Atlantic Ocean at the mouth of the Hudson River. If this were true,
New England would have been an island only a few years ago (geologically
speaking). The weight of evidence available today does not support
the prior existence of this connecting ribbon of sea water. Today Lake
Champlain contains fresh water again, and the marine conditions have
retreated back into the Gulf of St. Lawrence. What happened to permit
a return to fresh water conditions?</p>
<p>The lakes and lake-stages discussed are known from the presence of
various shoreline features, most of which are now “high and dry.” Each
lake or lake-stage has its own set of lake-level features. An interesting
fact emerges from a study of any one former lake. The present elevation
above sea level of delimiting lake-level features is <i>not</i> the same throughout.
To explain this more fully, the present elevation of those features
formed when the Champlain Sea was at its maximum extent will be
examined.</p>
<p>At Shelburne Falls the present elevation of these features is 300 feet,
at St. Albans 440 feet, and at Roxton, Quebec, 552 feet. It will be noted
that proceeding from south (Shelburne Falls) to north (Roxton) a difference
of over 250 feet is found between features formed at an identical
time in the past. The water in any lake is practically level. It therefore
follows that the present 300, 440 and 552 foot elevations of the
shoreline features are the result of subsequent tilting of the earth’s
surface. Perhaps the following reference to the water level of present
Lake Champlain will help in your understanding of this tilting.</p>
<p>The present-day average level of the water in Lake Champlain is
about 92 feet above the level of the Atlantic Ocean. This water-level
elevation is constant throughout the extent of Lake Champlain and <i>is
<span class="pb" id="Page_19">19</span>
not</i>, say, 92 feet at Button Bay and 192 feet at Burlington. Again, the
only way that features demonstrating past lake margins or levels could,
for any one lake or lake-stage, now exist at different elevations would
be if some earth movements took place after the formation of the features,
resulting in a change from their original elevations.</p>
<p>The earth’s crust has been tilted, higher in the north than in the south,
during recent times. This tilting provides the clue to the formation of
present-day Lake Champlain. Major tilting took place after the maximum
marine invasion. Tilting continued, at a decreasing rate, perhaps,
to the present day. This tilting, with greater relative rise in the northwest,
eventually reached a point where marine waters were excluded
from the Champlain Basin.</p>
<p>Fresh water slowly diluted the salty marine water. The lake gathered
more and more fresh water through rain and melting snow, and a new
outlet formed in the north, in the approximate location of the present
Richelieu River. The area of Lake Champlain slowly increased to its
present size, and the clays which once formed lake and sea bottom became
the “hard earth” of the Champlain Lowlands. Continued tilting
caused flooding of the streams, especially in the southern portion of
Lake Champlain, such as the now swampy Otter Creek and its tributary
Dead Creek (see map, <a href="#fig2" class="pginternal">Fig. 2</a>). This concludes the story of the Park
clays. From the rocks which crop out within a short walking distance of
Button Bay State Park a much older segment of geologic history can be
studied.</p>
