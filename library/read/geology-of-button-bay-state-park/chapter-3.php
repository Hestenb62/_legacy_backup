<p>In August 1849 the incomplete skeleton of a <i>whale</i><a class="fn pginternal" href="#fn_13" id="fr_13">[13]</a> was found in a
railroad cut being excavated for the Rutland and Burlington Railroad.
This cut was located approximately 12 miles south of Burlington and a
mile east of Lake Champlain. The significant fact about this “find” is
that these bones were found in the same type of blue clay that occurs
at the beach in Button Bay State Park. Clam and oyster shells (Pelecypods)
were found in association with the whale bones. These <i>pelecypod
shells</i><a class="fn pginternal" href="#fn_14" id="fr_14">[14]</a> and the whale bones show that these animals lived and died in
cold marine waters. Lake Champlain today is a fresh-water lake and
the fish and other organisms in it are those of fresh, not salty water.
Yet the blue clays (and we are soon to learn, the brown clays) hold
evidence proving the existence of sea water in an area where a fresh-water
lake is found today. Can this be explained?</p>
<p>The brown clay forms most of the Park’s clay banks (see Figs. <a href="#fig9" class="pginternal">9</a>A and
<a href="#imgx2" class="pginternal">9B</a>). It can be examined easily by the visitor. The bank is composed of
clay and variable amounts of <i>fine sand</i><a class="fn pginternal" href="#fn_15" id="fr_15">[15]</a> in thin lens-shaped bodies. The
hard dry outer clay, if rain has not just fallen, of the upper 15 feet of the
bank appears light brown or tan-white and commonly contains interspersed
white and blue streaks. In the section of the bank which was the
object of detailed study, two conspicuous <i>convoluted beds</i><a class="fn pginternal" href="#fn_16" id="fr_16">[16]</a> were found,
one 5 feet above the beach, the other nearly 2 feet above the first.</p>
<p>Shells of <i>pelecypods</i><a class="fn pginternal" href="#fn_17" id="fr_17">[17]</a> occur at two and perhaps three levels within the
bank. They can be seen easily in many slumped clay bodies along the
beach (see <a href="#fig10" class="pginternal">Fig. 10</a>, in which the shells are mainly <i>Macoma</i> and <i>Saxicava</i>).
These shells once belonged to living animals whose very close relatives
and identical younger generations are found living today in cold Arctic
<span class="pb" id="Page_17">17</span>
waters. Brown clays were deposited in a marine Champlain Sea. How
did these marine waters get into the Champlain Valley?</p>
