<p>Shortly after Coveville Lake Vermont reached its maximum size
(see map, <a href="#fig5" class="pginternal">Fig. 5</a>B), a southern gorge-outlet was formed at an elevation
lower than the previous Coveville outlet in the vicinity of Fort Ann,
New York (Fort Ann is located approximately 8 miles south of the
present southern extremity of Lake Champlain). The level of Lake
Vermont’s water dropped to the new Fort Ann Stage (see map, <a href="#fig7" class="pginternal">Fig. 7</a>A).
Evidence for this new lake level is seen on the slopes of Mt. Philo, Snake
Mountain and Cobble Hill. These lake-level features are parallel to and
found 100 feet below those of the Coveville Stage. These parallel features,
then, indicate that very little, if any, tilting of the earth’s crust had taken
place between the Coveville and Fort Ann lake stages.</p>
