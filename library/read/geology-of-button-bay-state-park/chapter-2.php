<p>This Champlain ice lobe continued to melt and retreat toward the
Canadian border and beyond. As the glacial front approached the St.
Lawrence valley, fresh water from Lake Vermont began to seep through
the retreating ice lobe and into the marine waters which filled the St.
Lawrence area. Several shoreline (lake-level) features are found at
different elevations below the Fort Ann Stage of Lake Vermont and
attest to a slow lowering of the lake level by the escape of fresh water
to the north.</p>
<div class="pb" id="Page_14">14</div>
<p>The conspicuous clays of Button Bay State Park were deposited during
the next episode in the history of the Champlain Valley, a development
heralded by continued retreat of the ice lobe and contact with the St.
Lawrence marine waters. Let’s take a look at the clays so well displayed
along the Button Bay State Park beach and see if we can piece together
their history.</p>
