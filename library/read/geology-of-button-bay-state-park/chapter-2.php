<h2 id="c2"> <span class="small">THE GEOLOGY OF BUTTON BAY STATE PARK</span></h2>
<p>If the visitor confines his wanderings to the State Park the most conspicuous
geological features, or clues to the Park’s past history, are concentrated
in the clay banks and adjacent beach which border Lake
Champlain (see <a href="#fig4" class="pginternal">Fig. 4</a>). The clays which cover the entire Park record
thousands of years of rather recent events, <i>geologically speaking</i><a class="fn pginternal" href="#fn_5" id="fr_5">[5]</a>, which
took place in the Champlain Valley. These clays also record a very significant
phase in the development of present Lake Champlain. Before
discussing the clays it will be necessary to outline some of the geological
events which preceded the deposition of the clays, that is, some of those
events which took place as the last glacial ice lobe slowly retreated up
the Champlain Valley and into Canada. The author has borrowed
heavily from an article by Donald H. Chapman entitled “Late-Glacial
and Post-glacial History of the Champlain Valley” which was published
<span class="pb" id="Page_7">7</span>
in the 1941-1942 “Report of the State Geologist on the Mineral Industries
and Geology of Vermont, twenty-third of (the) Series.”</p>
<div class="img" id="fig3">
