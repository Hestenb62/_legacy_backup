<p>The oldest lake recognized by the geologists is termed “Lake Albany”
and was confined to the Hudson Valley. At this time the area of present-day
Lake Champlain, north of the Hudson Valley, was still covered by
glacial ice which was slowly melting as the general regional climate
throughout New England became warmer and warmer. Soon the whole
Hudson Valley region began to <i>rise</i><a class="fn pginternal" href="#fn_6" id="fr_6">[6]</a> out from beneath the lake waters
<span class="pb" id="Page_9">9</span>
and “Lake Albany” shallowed. Eventually a rock ledge emerged just
south of Schuylerville, New York (actually at Coveville, New York)
over which the waters from a new lake, Lake Vermont, began to flow.</p>
<p>Lake Vermont, with its rock ledge dam at Coveville, began to expand
northward as the ice front retreated up the Champlain Valley. Several
distinct stages in its development are now recognized in <i>features</i><a class="fn pginternal" href="#fn_7" id="fr_7">[7]</a> demonstrating
past lake levels which are abundantly displayed close to
Button Bay State Park. The “lake-level indicators” or features tell us,
in addition to the number of distinct lake stages in a given area, something
about past earth movements. A “line of lake-level-<i>elevation</i>”<a class="fn pginternal" href="#fn_8" id="fr_8">[8]</a> is
drawn through those features outlining each past lake or lake stage
followed by a comparison of each line with those lines constructed for
older and younger lakes or lake stages. If, for any two lake-level lines
compared, these lines are not parallel, it can be assumed that the earth’s
crust was tilted during the time between the formation of their lake-level
features. This idea of tilting of the earth’s surface, which is supported
through the study of successive lake levels, has proven the key
to the present status of Lake Champlain.</p>
<p>At the beginning of its history Lake Vermont emptied to the south
through an outlet channel located in the vicinity of Coveville, New York
(see map, <a href="#fig5" class="pginternal">Fig. 5</a>A). This stage in the development of Lake Vermont, often
referred to as the Coveville Stage, saw lake waters fill the Champlain
Valley from the Green Mountains on the east to a position west of the
present New York-Lake Champlain shoreline. Such Vermont towns as
Middlebury, Vergennes, Hinesburg, Burlington and Colchester would
have been submerged beneath the lake waters (see map, <a href="#fig5" class="pginternal">Fig. 5</a>B). Certain
high areas such as Mount Philo, Pease Mountain and Cobble Hill show
lake-level features along their sides which prove that these areas were islands
rising above the level of this past lake. If you visit Mt. Philo State
Park, located approximately 11 miles north of Vergennes, one of these
lake-level features, a wave-cut terrace, can be seen at an elevation of 545
feet and on the south side of the hill (at the level of the second reverse
turn in your trip to the <i>summit area</i>).<a class="fn pginternal" href="#fn_9" id="fr_9">[9]</a></p>
