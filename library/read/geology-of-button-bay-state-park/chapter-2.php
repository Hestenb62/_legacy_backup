<p>During the final retreat of the last ice sheet to invade the New England
states (some 11,000 to 12,000 years ago) an ice lobe, which occupied the
Hudson-Champlain Valley, slowly wasted northward toward the Canadian
border. Melt-water derived from the melting glacial ice together
with atmospheric water (rain and snow) formed a succession of lakes
dammed on the north by the glacial ice. These lakes emptied to the south
through the Hudson Valley. This succession of lakes and intermediate
lake stages will be discussed in the following paragraphs.</p>
