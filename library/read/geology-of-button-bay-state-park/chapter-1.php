<h2 id="c1"> <span class="small">INTRODUCTION</span></h2>
<p>Button Bay State Park is located on the eastern shore of Lake Champlain
with lake frontage on Button Bay (see maps, Figs. <a href="#fig1" class="pginternal">1</a> and <a href="#fig2" class="pginternal">2</a>). This
Vermont State Park is reached from the nearest large town, Vergennes,
by proceeding southwest, toward Addison, on State Route 22A for .25
miles beyond the bridge over Otter Creek, thence, right on the Basin
Harbor-Panton road for another 1.4 miles to the first road entering from
the right. Turn right on this, the Basin Harbor road, and proceed for
4.5 miles, thence, left for 1.4 miles to Button Bay State Park (see map,
<a href="#fig2" class="pginternal">Fig. 2</a>, note arrows). A more direct road is planned to connect the Basin
Harbor Road with the Park, however, this route has still not been completed.</p>
<p>Prior to its present name, Button Bay, the “sickle-shaped bay” on
which Button Bay State Park is located was termed <i>Button Mould Bay</i><a class="fn pginternal" href="#fn_1" id="fr_1">[1]</a>.
In “The Journal of William Gilliland” which is found in the “Pioneer
History of the Champlain Valley” by Winslow C. Watson, Albany,
1863, and under the date of September 7, 1765, is found an entry which
speaks of “his (Gilliland) overtaking ‘<i>the Governors and other gentlemen</i>’<a class="fn pginternal" href="#fn_2" id="fr_2">[2]</a>
at Button Mould Bay, and going aboard their sloop.”</p>
<p>A book of charts by Captain William Chambers contains one entitled
“Baye du Roche Fendue (Split-Rock Bay) and the soundings taken in
August 1779.” At the upper corner of the chart is the name “Button
Mould Bay.” The first appearance of the shortened version, Button Bay,
seems to be in Whitelaw’s map of 1796 which was used as the frontispiece
of the Census volume, “Heads of Families, Vermont, 1800.”</p>
