<p>Why the name Button Bay? H. M. Seely (1910, p. 274)<a class="fn pginternal" href="#fn_3" id="fr_3">[3]</a> when discussing
the shoreline of this bay states, “Besides shells, <i>concretions</i><a class="fn pginternal" href="#fn_4" id="fr_4">[4]</a>, some
of strange imitative forms (many shaped like animals), are loosened
from the clay.” He goes on to say that a “form particularly abundant
in the banks of the bay (and on the beach) has the shape and size of a
turned wood button-mold (mold is commonly spelled ‘mould’ by the
British), a disc with a hole in the center, plane (flat) on one side and
convex on the other” (see <a href="#fig3" class="pginternal">Fig. 3</a> and <a href="#imgx1" class="pginternal">cover picture</a>). The abundance of
these button mold-shaped concretions obviously led to the older name,
Button Mould Bay which was later shortened to Button Bay.</p>
