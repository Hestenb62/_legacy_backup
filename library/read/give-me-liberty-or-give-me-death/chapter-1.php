<p>In March 1775, tension between the American colonies and the British Crown reached a boiling point. The British Parliament had passed the Coercive Acts (Intolerable Acts), and royal troops occupied Boston under General Thomas Gage. The royal governor of Virginia, Lord Dunmore, had dissolved the colonial legislature, forcing the delegates to convene at St. John's Episcopal Church in Richmond.</p>

<p>Conservative delegates urged patience, reconciliation, and respectful petitions to King George III. Patrick Henry arose from his pew and delivered an impassioned address that altered the course of American history. With soaring rhetorical cadence, Henry argued that all peaceful appeals had been exhausted, that British naval fleets and standing armies were already preparing for war, and that freedom demanded immediate defense.</p>

