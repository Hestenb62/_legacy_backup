    <section id="sec-2-4" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">&sect; 2.4</span>
            <h2 class="math-section-title">Even vs. Odd Parity &amp; Rectangular Arrays</h2>
        </div>

        <div class="math-def-box">
            <div class="math-def-header">
                <span class="math-def-badge"><i class="fas fa-check-double"></i> DEFINITION 2.4.1</span>
                <span class="math-def-domain">Topic: Parity Laws of Whole Numbers</span>
            </div>
            <div class="math-def-body">
                <ul>
                    <li><dfn class="math-term">Even Integer</dfn> &mdash; An integer divisible by $2$ with zero remainder. Can always be paired into two equal teams. Ends in $\{0, 2, 4, 6, 8\}$.</li>
                    <li><dfn class="math-term">Odd Integer</dfn> &mdash; An integer with a remainder of $1$ when paired into groups of $2$. Ends in $\{1, 3, 5, 7, 9\}$.</li>
                </ul>
                $$\text{Parity Laws: } \text{Even} + \text{Even} = \text{Even}, \quad \text{Odd} + \text{Odd} = \text{Even}, \quad \text{Even} + \text{Odd} = \text{Odd}$$
            </div>
        </div>

        <div class="math-formula-grid">
            <div class="math-formula-card">
                <div class="math-formula-meta">ALGEBRAIC FOUNDATION I</div>
                <div class="math-formula-title">Rectangular Array Formula</div>
                <div class="math-formula-latex">$$\text{Total Items} = \text{Rows } (R) \times \text{Columns } (C)$$</div>
                <div class="math-formula-desc">An orderly grid arranged in horizontal rows and vertical columns. $4 \text{ rows of } 5 = 20$.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-meta">ALGEBRAIC FOUNDATION II</div>
                <div class="math-formula-title">Repeated Addition Law</div>
                <div class="math-formula-latex">$$3 \text{ rows of } 6 = 6 + 6 + 6 = 18$$</div>
                <div class="math-formula-desc">Multiplication represents rapid repeated addition of equal-sized groups.</div>
            </div>
        </div>

        <div class="math-howto-box">
            <div class="math-howto-header"><i class="fas fa-th"></i> Student Guide: How to Model and Write Equations for Arrays</div>
            <div class="math-howto-steps">
                <div class="math-step-item">
                    <span class="math-step-badge">STEP 1: COUNT ROWS</span>
                    <div>Count how many horizontal rows go across (side to side). Let rows $= 3$.</div>
                </div>
                <div class="math-step-item">
                    <span class="math-step-badge">STEP 2: COUNT COLUMNS</span>
                    <div>Count how many items sit in each row (vertical columns). Let columns $= 4$.</div>
                </div>
                <div class="math-step-item">
                    <span class="math-step-badge">STEP 3: WRITE TWO EQUATIONS</span>
                    <div>By rows: $4 + 4 + 4 = 12$. By columns: $3 + 3 + 3 + 3 = 12$. Both equal $12$!</div>
                </div>
            </div>
        </div>
    </section>

