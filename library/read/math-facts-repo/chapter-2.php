    <section id="sec-2-2" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">&sect; 2.2</span>
            <h2 class="math-section-title">2-Digit &amp; 3-Digit Addition with Regrouping (Carrying)</h2>
        </div>

        <div class="math-def-box">
            <div class="math-def-header">
                <span class="math-def-badge"><i class="fas fa-sync-alt"></i> AXIOM 2.2.1</span>
                <span class="math-def-domain">Topic: The Column Carrying Principle</span>
            </div>
            <div class="math-def-body">
                <p><dfn class="math-term">Regrouping Axiom for Addition</dfn> &mdash; Because each place value column can hold at most a single digit ($0$ through $9$), whenever the column sum $S \ge 10$:</p>
                $$\text{Write } (S \bmod 10) \text{ in the column, and carry } \left\lfloor \frac{S}{10} \right\rfloor \text{ to the next place value on the left.}$$
                $$10 \text{ Ones} \longrightarrow 1 \text{ Ten}, \quad 10 \text{ Tens} \longrightarrow 1 \text{ Hundred}$$
            </div>
        </div>

        <div class="math-howto-box">
            <div class="math-howto-header"><i class="fas fa-list-ol"></i> Student Guide: The 3 Golden Rules of Column Addition</div>
            <div class="math-howto-steps">
                <div class="math-step-item">
                    <span class="math-step-badge">RULE 1: ALIGN</span>
                    <div>Always line up digits vertically by their place value columns (Ones directly over Ones, Tens over Tens, Hundreds over Hundreds).</div>
                </div>
                <div class="math-step-item">
                    <span class="math-step-badge">RULE 2: RIGHT-TO-LEFT</span>
                    <div>Always begin adding at the rightmost column (Ones). Never start adding from the left when using the standard algorithm!</div>
                </div>
                <div class="math-step-item">
                    <span class="math-step-badge">RULE 3: NEVER FORGET CARRIES</span>
                    <div>Write your carried digit neatly on the roof of the next column so you remember to add it into that column's total.</div>
                </div>
            </div>
        </div>

        <div class="math-example-box">
            <div class="math-ex-header">
                <span class="math-ex-badge"><i class="fas fa-pencil-alt"></i> EXEMPLUM 2.2</span>
                <span class="math-ex-title">3-Digit Addition with Double Regrouping</span>
            </div>
            <div class="math-ex-body">
                <p class="math-ex-problem"><strong>Problem:</strong> Calculate $368 + 275$ using the standard vertical algorithm.</p>
                <div class="math-ex-solution">
                    <div class="math-sol-step"><strong>Step 1 (Add Ones Column):</strong> $8 + 5 = 13 \text{ ones}$. Write down $3$ in the ones place, and carry $1$ ten above the tens column.</div>
                    <div class="math-sol-step"><strong>Step 2 (Add Tens Column):</strong> $1 \text{ (carried)} + 6 + 7 = 14 \text{ tens}$. Write down $4$ in the tens place, and carry $1$ hundred above the hundreds column.</div>
                    <div class="math-sol-step"><strong>Step 3 (Add Hundreds Column):</strong> $1 \text{ (carried)} + 3 + 2 = 6 \text{ hundreds}$. Write down $6$ in the hundreds place.</div>
                </div>
                <div class="math-ex-result">
                    <span><i class="fas fa-check-circle" style="color: #059669;"></i> <strong>Result:</strong> $368 + 275 = \mathbf{643}$.</span>
                    <span class="math-qed">&#9632; Q.E.D.</span>
                </div>
            </div>
        </div>
    </section>

