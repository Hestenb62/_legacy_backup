    <section id="sec-2-3" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">&sect; 2.3</span>
            <h2 class="math-section-title">Multi-Digit Subtraction with Regrouping (Decomposition)</h2>
        </div>

        <div class="math-caution-box">
            <div class="math-caution-header">
                <span class="math-caution-badge"><i class="fas fa-exclamation-triangle"></i> SCHOLASTIC WARNING</span>
                <span class="math-caution-title">More on the Floor? Go Next Door and Get 10 More!</span>
            </div>
            <div class="math-caution-body">
                If the top digit in a column is smaller than the bottom digit ($A_{\text{top}} &lt; B_{\text{bottom}}$), you <strong>cannot</strong> just flip the digits! You must decompose $1$ unit from the column to the left into $10$ units for the current column.
                $$53 - 28 \neq 35 \quad \text{(Error: subtracting } 8 - 3 \text{ is invalid!)}$$
                $$\text{Correct: Borrow } 1 \text{ ten from } 5 \implies (4 \text{ tens}, 13 \text{ ones}) - 28 = 25$$
            </div>
        </div>

        <div class="math-howto-box">
            <div class="math-howto-header"><i class="fas fa-cut"></i> Student Guide: How to Borrow Across Zeros ($500 - 247$)</div>
            <div class="math-howto-steps">
                <div class="math-step-item">
                    <span class="math-step-badge">STEP 1: INSPECT</span>
                    <div>You need to subtract $0 - 7$ in ones, but the tens place is also $0$! You cannot borrow from zero.</div>
                </div>
                <div class="math-step-item">
                    <span class="math-step-badge">STEP 2: GO TO HUNDREDS</span>
                    <div>Borrow $1$ from the $5$ hundreds. $5$ becomes $4$. The tens place receives $10$ tens.</div>
                </div>
                <div class="math-step-item">
                    <span class="math-step-badge">STEP 3: PASS TO ONES</span>
                    <div>Now borrow $1$ ten from the $10$ tens. The tens place becomes $9$, and the ones place receives $10$ ones.</div>
                </div>
                <div class="math-step-item">
                    <span class="math-step-badge">STEP 4: SUBTRACT</span>
                    <div>Ones: $10 - 7 = 3$. Tens: $9 - 4 = 5$. Hundreds: $4 - 2 = 2$. Total: $\mathbf{253}$!</div>
                </div>
            </div>
        </div>

        <div class="math-example-box">
            <div class="math-ex-header">
                <span class="math-ex-badge"><i class="fas fa-pencil-alt"></i> EXEMPLUM 2.3</span>
                <span class="math-ex-title">Standard Decomposition Across Columns</span>
            </div>
            <div class="math-ex-body">
                <p class="math-ex-problem"><strong>Problem:</strong> Calculate $724 - 386$.</p>
                <div class="math-ex-solution">
                    <div class="math-sol-step"><strong>Step 1 (Ones):</strong> $4 &lt; 6$. Borrow $1$ ten from $2$ (tens becomes $1$). Ones becomes $14$. $14 - 6 = 8$.</div>
                    <div class="math-sol-step"><strong>Step 2 (Tens):</strong> $1 &lt; 8$. Borrow $1$ hundred from $7$ (hundreds becomes $6$). Tens becomes $11$. $11 - 8 = 3$.</div>
                    <div class="math-sol-step"><strong>Step 3 (Hundreds):</strong> $6 - 3 = 3$.</div>
                    <div class="math-sol-step"><strong>Step 4 (Inverse Verification):</strong> Check by adding: $338 + 386 = 724$ &check;.</div>
                </div>
                <div class="math-ex-result">
                    <span><i class="fas fa-check-circle" style="color: #059669;"></i> <strong>Result:</strong> $724 - 386 = \mathbf{338}$.</span>
                    <span class="math-qed">&#9632; Q.E.D.</span>
                </div>
            </div>
        </div>
    </section>

