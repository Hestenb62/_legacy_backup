    <section id="sec-2-1" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">&sect; 2.1</span>
            <h2 class="math-section-title">3-Digit Place Value: Hundreds, Tens &amp; Ones</h2>
        </div>

        <div class="math-def-box">
            <div class="math-def-header">
                <span class="math-def-badge"><i class="fas fa-scroll"></i> DEFINITION 2.1.1</span>
                <span class="math-def-domain">Topic: Base-10 Positional Notation</span>
            </div>
            <div class="math-def-body">
                <p><dfn class="math-term">Positional Base-10 Decomposition</dfn> &mdash; Any 3-digit natural number $N$ represents a linear combination of Hundreds ($H$), Tens ($T$), and Ones ($O$):</p>
                $$N = (H \times 100) + (T \times 10) + (O \times 1)$$
                $$\text{Example: } 742 = (7 \times 100) + (4 \times 10) + (2 \times 1) = 700 + 40 + 2$$
            </div>
        </div>

        <div class="math-formula-grid">
            <div class="math-formula-card">
                <div class="math-formula-meta">NOTATION TYPE I</div>
                <div class="math-formula-title">Standard Form</div>
                <div class="math-formula-latex">$$583$$</div>
                <div class="math-formula-desc">Written directly using compact base-10 Hindu-Arabic numeral digits.</div>
            </div>
            <div class="math-formula-card">
                <div class="math-formula-meta">NOTATION TYPE II</div>
                <div class="math-formula-title">Expanded Form</div>
                <div class="math-formula-latex">$$500 + 80 + 3$$</div>
                <div class="math-formula-desc">Decomposes each digit into its explicit face value scaled by positional power.</div>
            </div>
            <div class="math-formula-card">
                <div class="math-formula-meta">NOTATION TYPE III</div>
                <div class="math-formula-title">Word Form (Orthographic)</div>
                <div class="math-formula-latex">\text{"Five hundred eighty-three"}</div>
                <div class="math-formula-desc">Formal linguistic representation without using colloquial "and".</div>
            </div>
        </div>

