                <div class="math-const-val">$$\left(\frac{a}{b}\right)^{-n} = \left(\frac{b}{a}\right)^n$$</div>
                <div class="math-const-desc">Flip the entire fraction to make the power positive! $\left(\frac{2}{3}\right)^{-3} = \left(\frac{3}{2}\right)^3 = \frac{27}{8}$.</div>
            </div>

            <div class="math-constant-card">
                <div class="math-const-sym"><i class="fas fa-cube" style="color: #9d174d;"></i> HACK IV</div>
