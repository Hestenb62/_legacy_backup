                <div class="math-const-val">$$V_{\text{cylinder}} = 3 \times V_{\text{cone}}$$</div>
                <div class="math-const-desc">It takes exactly 3 full cones of liquid to fill 1 cylinder of the same radius and height!</div>
            </div>
        </div>
