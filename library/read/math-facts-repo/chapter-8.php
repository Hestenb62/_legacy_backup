                <div class="math-const-sym"><i class="fas fa-triangle" style="color: #f59e0b;"></i> Hack #1</div>
                <div class="math-const-name">Pythagorean Triples Speed Memorizer</div>
                <div class="math-const-val">$$\mathbf{3-4-5} \quad | \quad \mathbf{5-12-13} \quad | \quad \mathbf{8-15-17} \quad | \quad \mathbf{7-24-25}$$</div>
                <div class="math-const-desc">Any scalar multiple is also a triple! ($6-8-10, 9-12-15$). If legs are $6$ and $8$, the hypotenuse is $10$ in $0.5$ seconds without squaring!</div>
            </div>

            <div class="math-constant-card">
                <div class="math-const-sym"><i class="fas fa-arrows-alt-v" style="color: #6366f1;"></i> Hack #2</div>
                <div class="math-const-name">"Rise over Run" Slope Mantra</div>
                <div class="math-const-val">$$m = \frac{\text{Change in } Y \text{ (Up/Down)}}{\text{Change in } X \text{ (Right)}}$$</div>
                <div class="math-const-desc">Always remember: $Y$ is high in the sky (numerator), $X$ runs along the tracks (denominator).</div>
            </div>

            <div class="math-constant-card">
                <div class="math-const-sym"><i class="fas fa-sliders-h" style="color: #10b981;"></i> Hack #3</div>
                <div class="math-const-name">Scientific Notation Decimal Slider</div>
                <div class="math-const-val">$$\text{Small Number } (< 1) \implies \text{Negative Exponent} \quad | \quad \text{Big Number } (> 10) \implies \text{Positive Exponent}$$</div>
                <div class="math-const-desc">Microscopic things (cells, atoms) always have negative powers: $10^{-6}$. Astronomical things (stars, light years) have positive powers: $10^{12}$.</div>
            </div>
