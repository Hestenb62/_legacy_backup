         Section 8.1: Real Numbers, Irrationals & Radicals
         ========================================================================== -->
    <section id="sec-8-1" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">&sect; 8.1</span>
            <h2 class="math-section-title">The Real Number Continuum: Rational vs. Irrational Numbers</h2>
        </div>

        <div class="math-def-box">
            <div class="math-def-header">
                <span class="math-def-badge"><i class="fas fa-scroll"></i> DEFINITION 8.1.1</span>
                <span class="math-def-domain">Topic: The Real Number System ($\mathbb{R}$)</span>
            </div>
            <div class="math-def-body">
                <ul>
                    <li><dfn class="math-term">Rational Number ($\mathbb{Q}$)</dfn> &mdash; Any number that can be expressed as a ratio of two integers $\frac{a}{b}$ ($b \neq 0$). Its decimal expansion either <strong>terminates</strong> (e.g. $0.75$) or <strong>repeats indefinitely</strong> (e.g. $0.\overline{3}$).</li>
                    <li><dfn class="math-term">Irrational Number ($\mathbb{R} \setminus \mathbb{Q}$)</dfn> &mdash; A real number that cannot be written as a simple fraction. Its decimal representation is <strong>infinite and non-repeating</strong> ($\sqrt{2} \approx 1.41421\dots, \pi \approx 3.14159\dots, e$).</li>
                </ul>
            </div>
        </div>

        <div class="math-formula-grid">
            <div class="math-formula-card">
                <div class="math-formula-meta">RADICAL PROPERTY I</div>
                <div class="math-formula-title">Square Roots ($\sqrt{x}$)</div>
                <div class="math-formula-latex">$$\sqrt{x} = y \iff y^2 = x \quad (y \ge 0)$$</div>
                <div class="math-formula-desc">Perfect squares: $\sqrt{1}=1, \sqrt{4}=2, \sqrt{9}=3, \dots, \sqrt{144}=12$.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-meta">RADICAL PROPERTY II</div>
                <div class="math-formula-title">Cube Roots ($\sqrt[3]{x}$)</div>
                <div class="math-formula-latex">$$\sqrt[3]{x} = y \iff y^3 = x$$</div>
                <div class="math-formula-desc">Can take cube roots of negative numbers: $\sqrt[3]{-8} = -2$ because $(-2)^3 = -8$.</div>
            </div>
        </div>
    </section>

