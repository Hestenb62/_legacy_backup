    <section id="sec-8-4" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">8.4</span>
            <h2 class="math-section-title">The Pythagorean Theorem &amp; Distance Formula</h2>
        </div>

        <div class="math-theorem-box">
            <div class="math-thm-header">
                <span class="math-thm-badge"><i class="fas fa-award"></i> Theorem 8.4</span>
                <span class="math-thm-title">The Pythagorean Theorem</span>
            </div>
            <div class="math-thm-body">
                In any right triangle with legs $a, b$ and hypotenuse $c$:
                $$a^2 + b^2 = c^2 \implies c = \sqrt{a^2 + b^2}$$
                <strong>Coordinate Distance Formula:</strong> $d = \sqrt{(x_2 - x_1)^2 + (y_2 - y_1)^2}$
            </div>
        </div>
    </section>

