        <div class="math-example-box">
            <div class="math-ex-header">
                <span class="math-ex-badge"><i class="fas fa-pencil-alt"></i> EXEMPLUM 8.4</span>
                <span class="math-ex-title">Solving a Linear System by Substitution</span>
            </div>
            <div class="math-ex-body">
                <p class="math-ex-problem"><strong>Problem:</strong> Solve the linear system: $\begin{cases} y = 2x + 1 \\ 3x + y = 16 \end{cases}$</p>
                <div class="math-ex-solution">
                    <div class="math-sol-step"><strong>Step 1 (Substitute for $y$):</strong> Replace $y$ with $(2x + 1)$ in the second equation: $3x + (2x + 1) = 16$.</div>
                    <div class="math-sol-step"><strong>Step 2 (Combine &amp; Solve for $x$):</strong> $5x + 1 = 16 \implies 5x = 15 \implies x = 3$.</div>
                    <div class="math-sol-step"><strong>Step 3 (Solve for $y$):</strong> $y = 2(3) + 1 = 6 + 1 = 7$.</div>
                    <div class="math-sol-step"><strong>Step 4 (Verify in Equation 2):</strong> $3(3) + 7 = 9 + 7 = 16$ &check;.</div>
                </div>
                <div class="math-ex-result">
                    <span><i class="fas fa-check-circle" style="color: #059669;"></i> <strong>Result:</strong> Unique Solution: $(x, y) = \mathbf{(3, 7)}$.</span>
                    <span class="math-qed">&#9632; Q.E.D.</span>
                </div>
            </div>
        </div>
    </section>

