                    <li>Slope-Intercept: $y = mx + b$</li>
                    <li>Point-Slope: $y - y_1 = m(x - x_1)$</li>
                    <li>Parallel: $m_1 = m_2$</li>
                    <li>Perpendicular: $m_1 \cdot m_2 = -1$</li>
