        </div>

        <div class="math-formula-grid">
            <div class="math-formula-card">
                <div class="math-formula-title">Volume of a Cylinder</div>
                <div class="math-formula-latex">$$V = \pi r^2 h$$</div>
                <div class="math-formula-desc">Base circle area $\pi r^2$ extruded through height $h$.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-title">Volume of a Cone</div>
                <div class="math-formula-latex">$$V = \frac{1}{3}\pi r^2 h$$</div>
                <div class="math-formula-desc">Exactly $\frac{1}{3}$ the volume of a cylinder with identical $r$ and $h$.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-title">Volume of a Sphere</div>
                <div class="math-formula-latex">$$V = \frac{4}{3}\pi r^3$$</div>
                <div class="math-formula-desc">Enclosed volume of a 3D sphere of radius $r$.</div>
            </div>
        </div>
