         Section 8.2: Exponent Laws & Scientific Notation
         ========================================================================== -->
    <section id="sec-8-2" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">&sect; 8.2</span>
            <h2 class="math-section-title">Axiomatic Exponent Laws &amp; Scientific Notation</h2>
        </div>

        <div class="math-formula-grid">
            <div class="math-formula-card">
                <div class="math-formula-meta">EXPONENT LAW I</div>
                <div class="math-formula-title">Product Rule</div>
                <div class="math-formula-latex">$$x^a \cdot x^b = x^{a+b}$$</div>
                <div class="math-formula-desc">$2^3 \cdot 2^4 = 2^7 = 128$. Add powers of common bases.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-meta">EXPONENT LAW II</div>
                <div class="math-formula-title">Quotient Rule</div>
                <div class="math-formula-latex">$$\frac{x^a}{x^b} = x^{a-b} \quad (x \neq 0)$$</div>
                <div class="math-formula-desc">$\frac{5^8}{5^5} = 5^{8-5} = 5^3 = 125$. Subtract powers.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-meta">EXPONENT LAW III</div>
                <div class="math-formula-title">Power of a Power</div>
                <div class="math-formula-latex">$$(x^a)^b = x^{a \cdot b}$$</div>
                <div class="math-formula-desc">$(3^2)^4 = 3^8 = 6,561$. Multiply outer exponent.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-meta">EXPONENT LAW IV</div>
                <div class="math-formula-title">Zero &amp; Negative Exponents</div>
                <div class="math-formula-latex">$$x^0 = 1 \quad \text{and} \quad x^{-n} = \frac{1}{x^n}$$</div>
                <div class="math-formula-desc">Any non-zero base to power 0 equals 1. Negative exponent flips to denominator.</div>
            </div>
        </div>

        <div class="math-def-box">
            <div class="math-def-header">
                <span class="math-def-badge"><i class="fas fa-atom"></i> DEFINITION 8.2.1</span>
                <span class="math-def-domain">Topic: Scientific Notation Standard</span>
            </div>
            <div class="math-def-body">
                $$N = a \times 10^b \quad \text{where } 1 \le |a| &lt; 10 \text{ and } b \in \mathbb{Z}$$
                $$\text{Multiplication: } (3 \times 10^4)(2 \times 10^5) = (3 \times 2) \times 10^{4+5} = \mathbf{6 \times 10^9}$$
            </div>
        </div>
    </section>

