        <div class="math-section-header">
            <span class="math-section-num">8.2</span>
            <h2 class="math-section-title">Linear Functions: Slope-Intercept Form ($y = mx + b$)</h2>
        </div>

        <div class="math-formula-grid">
            <div class="math-formula-card">
                <div class="math-formula-title">Slope Formula ($m$)</div>
                <div class="math-formula-latex">$$m = \frac{\Delta y}{\Delta x} = \frac{y_2 - y_1}{x_2 - x_1} = \frac{\text{Rise}}{\text{Run}}$$</div>
                <div class="math-formula-desc">Rate of change between two coordinates $(x_1, y_1)$ and $(x_2, y_2)$.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-title">Slope-Intercept Form</div>
                <div class="math-formula-latex">$$y = mx + b$$</div>
                <div class="math-formula-desc">$m = \text{slope (steepness)}, \quad b = y\text{-intercept } (0, b)$.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-title">Standard Form</div>
                <div class="math-formula-latex">$$Ax + By = C$$</div>
                <div class="math-formula-desc">Slope $m = -\frac{A}{B}, \quad y\text{-intercept} = \frac{C}{B}$.</div>
            </div>
        </div>
    </section>

