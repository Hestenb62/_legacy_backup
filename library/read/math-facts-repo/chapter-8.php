         Section 8.3: Linear Functions (y = mx + b)
         ========================================================================== -->
    <section id="sec-8-3" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">&sect; 8.3</span>
            <h2 class="math-section-title">Linear Functions: Slope ($m$) &amp; Slope-Intercept Form</h2>
        </div>

        <div class="math-formula-grid">
            <div class="math-formula-card">
                <div class="math-formula-meta">SLOPE (STEEPNESS)</div>
                <div class="math-formula-title">The Slope Formula ($m$)</div>
                <div class="math-formula-latex">$$m = \frac{\Delta y}{\Delta x} = \frac{y_2 - y_1}{x_2 - x_1} = \frac{\text{Rise}}{\text{Run}}$$</div>
                <div class="math-formula-desc">Rate of change between two coordinates $(x_1, y_1)$ and $(x_2, y_2)$.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-meta">FUNCTION EQUATION</div>
                <div class="math-formula-title">Slope-Intercept Form</div>
                <div class="math-formula-latex">$$y = mx + b$$</div>
                <div class="math-formula-desc">$m = \text{slope}, \quad b = y\text{-intercept at coordinate } (0, b)$.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-meta">POINT-SLOPE FORM</div>
                <div class="math-formula-title">Point-Slope Equation</div>
                <div class="math-formula-latex">$$y - y_1 = m(x - x_1)$$</div>
                <div class="math-formula-desc">Construct line directly from slope $m$ and any passing point $(x_1, y_1)$.</div>
            </div>
        </div>
    </section>

