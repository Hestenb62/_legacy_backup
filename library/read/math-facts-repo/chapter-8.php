    <section id="sec-8-1" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">8.1</span>
            <h2 class="math-section-title">Axiomatic Exponent Laws &amp; Scientific Notation</h2>
        </div>

        <div class="math-formula-grid">
            <div class="math-formula-card">
                <div class="math-formula-title">Product Rule</div>
                <div class="math-formula-latex">$$x^a \cdot x^b = x^{a+b}$$</div>
                <div class="math-formula-desc">Example: $2^3 \cdot 2^4 = 2^7 = 128$.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-title">Quotient Rule</div>
                <div class="math-formula-latex">$$\frac{x^a}{x^b} = x^{a-b} \quad (x \neq 0)$$</div>
                <div class="math-formula-desc">Example: $\frac{5^8}{5^5} = 5^3 = 125$.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-title">Power of a Power</div>
                <div class="math-formula-latex">$$(x^a)^b = x^{a \cdot b}$$</div>
                <div class="math-formula-desc">Example: $(3^2)^4 = 3^8 = 6,561$.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-title">Zero &amp; Negative Exponents</div>
                <div class="math-formula-latex">$$x^0 = 1 \quad \text{and} \quad x^{-n} = \frac{1}{x^n}$$</div>
                <div class="math-formula-desc">Example: $4^{-2} = \frac{1}{4^2} = \frac{1}{16}$.</div>
            </div>
        </div>

        <div class="math-def-box">
            <div class="math-def-header">
                <span class="math-def-badge"><i class="fas fa-atom"></i> Definition 8.1.1</span>
                <span class="math-def-domain">Scientific Notation</span>
            </div>
            <div class="math-def-body">
                A number written in the form:
                $$N = a \times 10^b \quad \text{where } 1 \leq |a| < 10 \text{ and } b \in \mathbb{Z}$$
                $$\text{Example: } 450,000,000 = 4.5 \times 10^8 \quad | \quad 0.000032 = 3.2 \times 10^{-5}$$
            </div>
        </div>
    </section>

