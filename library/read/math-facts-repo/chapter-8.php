                <div class="math-const-name">"Rise over Run" Slope Mantra</div>
                <div class="math-const-val">$$m = \frac{\Delta y}{\Delta x} = \frac{\text{Vertical Change}}{\text{Horizontal Change}}$$</div>
                <div class="math-const-desc">Remember: $Y$ flies high into the sky (numerator); $X$ runs on the train tracks (denominator).</div>
