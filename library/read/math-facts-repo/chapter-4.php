    <section id="sec-4-2" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">4.2</span>
            <h2 class="math-section-title">Long Division Algorithm &amp; The Division Theorem</h2>
        </div>

        <div class="math-theorem-box">
            <div class="math-thm-header">
                <span class="math-thm-badge"><i class="fas fa-award"></i> Theorem 4.2</span>
                <span class="math-thm-title">Division with Remainder Theorem</span>
            </div>
            <div class="math-thm-body">
                For any integer dividend $a$ and non-zero divisor $b$, there exist unique integers quotient $q$ and remainder $r$ such that:
                $$a = (b \times q) + r \quad \text{where } 0 \leq r < b$$
                $$\text{Example: } 257 \div 4 \implies 257 = (4 \times 64) + 1 \implies \mathbf{64 \text{ R } 1}$$
            </div>
        </div>
    </section>

