            <span class="math-section-num">4.4</span>
            <h2 class="math-section-title">Fraction Arithmetic: Like Denominators &amp; Mixed Numbers</h2>
        </div>

        <div class="math-formula-grid">
            <div class="math-formula-card">
                <div class="math-formula-title">Addition of Like Fractions</div>
                <div class="math-formula-latex">$$\frac{a}{d} + \frac{b}{d} = \frac{a + b}{d}$$</div>
                <div class="math-formula-desc">Add numerators; keep the denominator identical: $\frac{2}{7} + \frac{3}{7} = \frac{5}{7}$.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-title">Mixed Number $\leftrightarrow$ Improper Fraction</div>
                <div class="math-formula-latex">$$W \frac{a}{b} = \frac{(W \times b) + a}{b}$$</div>
                <div class="math-formula-desc">Example: $3 \frac{2}{5} = \frac{(3 \times 5) + 2}{5} = \frac{17}{5}$.</div>
            </div>
        </div>
    </section>

