        <div class="math-section-header">
            <span class="math-section-num">4.7</span>
            <h2 class="math-section-title">Grade 4 Divisibility Hacks &amp; Mental Arithmetic Shortcuts</h2>
        </div>

        <div class="math-constant-grid">
            <div class="math-constant-card">
                <div class="math-const-sym"><i class="fas fa-magic" style="color: #f59e0b;"></i> Hack #1</div>
                <div class="math-const-name">Divisibility by 3 and 9 (Sum of Digits)</div>
                <div class="math-const-val">$$4,842 \implies 4+8+4+2 = 18 \implies \text{Divisible by 3 and 9!}$$</div>
                <div class="math-const-desc">Add up all digits of any huge number. If the sum is a multiple of 3, the number divides by 3. If sum divides by 9, the number divides by 9!</div>
            </div>

            <div class="math-constant-card">
                <div class="math-const-sym"><i class="fas fa-bolt" style="color: #6366f1;"></i> Hack #2</div>
                <div class="math-const-name">Divisibility by 4 (Last Two Digits)</div>
                <div class="math-const-val">$$75,3\mathbf{24} \implies 24 \div 4 = 6 \implies \text{Divisible by 4!}$$</div>
                <div class="math-const-desc">Ignore all leading digits. Look only at the last two digits. If they divide by 4, the entire millions number divides by 4.</div>
            </div>

            <div class="math-constant-card">
                <div class="math-const-sym"><i class="fas fa-calculator" style="color: #10b981;"></i> Hack #3</div>
                <div class="math-const-name">Multiplying Any 2-Digit Number by 11</div>
                <div class="math-const-val">$$45 \times 11 \implies 4 \ [4+5] \ 5 \implies \mathbf{495}$$</div>
                <div class="math-const-desc">Spread the two digits apart, and insert their sum in the middle! ($27 \times 11 = 2 \ [2+7] \ 7 = 297$).</div>
            </div>

            <div class="math-constant-card">
                <div class="math-const-sym"><i class="fas fa-check-double" style="color: #ec4899;"></i> Study Hack</div>
                <div class="math-const-name">Division Check Inverse Check</div>
                <div class="math-const-val">$$\text{Check: } (\text{Quotient} \times \text{Divisor}) + \text{Remainder} = \text{Dividend}$$</div>
                <div class="math-const-desc">Always multiply your answer back before turning in any test. If it equals the starting dividend, your answer is 100% correct.</div>
            </div>
        </div>
    </section>

