         Section 4.3: Long Division Algorithm & Remainders
         ========================================================================== -->
    <section id="sec-4-3" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">&sect; 4.3</span>
            <h2 class="math-section-title">Long Division Algorithm &amp; The Division Theorem</h2>
        </div>

        <div class="math-def-box">
            <div class="math-def-header">
                <span class="math-def-badge"><i class="fas fa-award"></i> THEOREM 4.3.1</span>
                <span class="math-def-domain">Topic: The Division with Remainder Theorem</span>
            </div>
            <div class="math-def-body">
                For any integer dividend $a$ and non-zero divisor $b$, there exist unique integers quotient $q$ and remainder $r$ such that:
                $$a = (b \times q) + r \quad \text{where } 0 \le r &lt; b$$
                $$\text{Example: } 257 \div 4 \implies 257 = (4 \times 64) + 1 \implies \mathbf{64 \text{ R } 1}$$
            </div>
        </div>

        <div class="math-howto-box">
            <div class="math-howto-header"><i class="fas fa-step-forward"></i> The DMSB Division Cycle (Does McDonald's Serve Burgers?)</div>
            <div class="math-howto-steps">
                <div class="math-step-item">
                    <span class="math-step-badge">D: DIVIDE</span>
                    <div>How many times does the divisor fit into the current working digits without exceeding? Write digit in quotient.</div>
                </div>
                <div class="math-step-item">
                    <span class="math-step-badge">M: MULTIPLY</span>
                    <div>Multiply quotient digit by divisor. Write product underneath.</div>
                </div>
                <div class="math-step-item">
                    <span class="math-step-badge">S: SUBTRACT</span>
                    <div>Subtract product from working digits. Result must strictly be smaller than divisor!</div>
                </div>
                <div class="math-step-item">
                    <span class="math-step-badge">B: BRING DOWN</span>
                    <div>Bring down the next digit from the dividend. Repeat the cycle until all digits are processed.</div>
                </div>
            </div>
        </div>
    </section>

