        </div>

        <div class="math-def-box">
            <div class="math-def-header">
                <span class="math-def-badge"><i class="fas fa-scroll"></i> DEFINITION 4.1.1</span>
                <span class="math-def-domain">Topic: The 10-to-1 Metric Power Principle</span>
            </div>
            <div class="math-def-body">
                <p><dfn class="math-term">Positional Base-10 Law</dfn> &mdash; In any multi-digit numeral, a digit in one place represents exactly <strong>$10$ times</strong> as much as it represents in the place immediately to its right:</p>
                $$\text{Value}(\text{Position } k) = 10 \times \text{Value}(\text{Position } k-1)$$
                $$\text{In } 44,444: \text{The } 4 \text{ in the thousands place } (4,000) = 10 \times \text{the } 4 \text{ in the hundreds place } (400).$$
            </div>
        </div>

