        <div class="math-constant-grid">
            <div class="math-constant-card">
                <div class="math-const-sym"><i class="fas fa-magic" style="color: #b45309;"></i> HACK I</div>
                <div class="math-const-name">Multiplying by 11 Shortcut</div>
                <div class="math-const-val">$$35 \times 11 \implies 3 \ [3+5] \ 5 = \mathbf{385}$$</div>
                <div class="math-const-desc">Spread the two digits and place their sum in the middle! If sum $\ge 10$, carry $1$ to the left digit ($48 \times 11 = 528$).</div>
            </div>

            <div class="math-constant-card">
                <div class="math-const-sym"><i class="fas fa-coins" style="color: #1e3a8a;"></i> HACK II</div>
                <div class="math-const-name">Quarter Scaling (&times;25)</div>
                <div class="math-const-val">$$48 \times 25 = (48 \div 4) \times 100 = 12 \times 100 = \mathbf{1,200}$$</div>
                <div class="math-const-desc">Multiplying by 25 is dividing by 4 and appending two zeros! Think of counting quarters into dollar bills.</div>
            </div>

            <div class="math-constant-card">
                <div class="math-const-sym"><i class="fas fa-divide" style="color: #065f46;"></i> HACK III</div>
