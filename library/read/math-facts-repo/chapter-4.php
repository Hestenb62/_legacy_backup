            <h2 class="math-section-title">Factors, Multiples, Prime &amp; Composite Numbers</h2>
        </div>

        <div class="math-formula-grid">
            <div class="math-formula-card">
                <div class="math-formula-title">Prime Number Definition</div>
                <div class="math-formula-latex">$$p \in \mathbb{Z}^+, \ p > 1 \text{ with factors } \{1, p\}$$</div>
                <div class="math-formula-desc">Exactly two distinct positive divisors: $2, 3, 5, 7, 11, 13, 17, 19, 23 \dots$</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-title">Composite Number Definition</div>
                <div class="math-formula-latex">$$c > 1 \text{ having } \geq 3 \text{ positive factors}$$</div>
                <div class="math-formula-desc">Can be factored into smaller integers: $4, 6, 8, 9, 10, 12, 14, 15 \dots$</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-title">Special Status of 0 and 1</div>
                <div class="math-formula-latex">$$1 \text{ is NEITHER prime NOR composite}$$</div>
                <div class="math-formula-desc">1 is a unit. 2 is the ONLY even prime number in mathematics!</div>
            </div>
        </div>
    </section>

