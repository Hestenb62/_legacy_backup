    <section id="sec-4-2" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">&sect; 4.2</span>
            <h2 class="math-section-title">Multi-Digit Multiplication: Partial Products &amp; Standard Algorithm</h2>
        </div>

        <div class="math-def-box">
            <div class="math-def-header">
                <span class="math-def-badge"><i class="fas fa-th"></i> ALGORITHM 4.2.1</span>
                <span class="math-def-domain">Topic: Area Model (Partial Products)</span>
            </div>
            <div class="math-def-body">
                To multiply $24 \times 35$, decompose both numbers by expanded place value:
                $$24 \times 35 = (20 + 4) \times (30 + 5)$$
                $$= (20 \times 30) + (20 \times 5) + (4 \times 30) + (4 \times 5)$$
                $$= 600 + 100 + 120 + 20 = \mathbf{840}$$
            </div>
        </div>

        <div class="math-example-box">
            <div class="math-ex-header">
                <span class="math-ex-badge"><i class="fas fa-pencil-alt"></i> EXEMPLUM 4.2</span>
                <span class="math-ex-title">Standard 2-Digit by 2-Digit Multiplication</span>
            </div>
            <div class="math-ex-body">
                <p class="math-ex-problem"><strong>Problem:</strong> Calculate $63 \times 47$ using the standard vertical algorithm.</p>
                <div class="math-ex-solution">
                    <div class="math-sol-step"><strong>Step 1 (Multiply by Ones):</strong> $7 \times 63$: $7 \times 3 = 21$ (write $1$, carry $2$). $7 \times 6 = 42 + 2 = 44$. First partial product: $441$.</div>
                    <div class="math-sol-step"><strong>Step 2 (Place Zero &amp; Multiply Tens):</strong> Write $0$ in ones column. $4 \times 63$: $4 \times 3 = 12$ (write $2$, carry $1$). $4 \times 6 = 24 + 1 = 25$. Second partial product: $2,520$.</div>
                    <div class="math-sol-step"><strong>Step 3 (Add Partial Products):</strong> $441 + 2,520 = 2,961$.</div>
                </div>
                <div class="math-ex-result">
                    <span><i class="fas fa-check-circle" style="color: #059669;"></i> <strong>Result:</strong> $63 \times 47 = \mathbf{2,961}$.</span>
                    <span class="math-qed">&#9632; Q.E.D.</span>
                </div>
            </div>
        </div>
    </section>

