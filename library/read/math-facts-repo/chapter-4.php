            <h2 class="math-section-title">Fraction Operations: Addition, Subtraction &amp; Whole Scaling</h2>
        </div>

        <div class="math-formula-grid">
            <div class="math-formula-card">
                <div class="math-formula-meta">FRACTION LAW I</div>
                <div class="math-formula-title">Like Denominator Addition &amp; Subtraction</div>
                <div class="math-formula-latex">$$\frac{a}{d} \pm \frac{b}{d} = \frac{a \pm b}{d}$$</div>
                <div class="math-formula-desc">Operate strictly across numerators; keep the denominator identical: $\frac{3}{8} + \frac{2}{8} = \frac{5}{8}$.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-meta">FRACTION LAW II</div>
                <div class="math-formula-title">Whole Number &times; Unit Fraction</div>
                <div class="math-formula-latex">$$n \times \frac{a}{b} = \frac{n \times a}{b}$$</div>
                <div class="math-formula-desc">Scaling a fraction by whole number: $4 \times \frac{2}{3} = \frac{8}{3} = 2 \frac{2}{3}$.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-meta">FRACTION LAW III</div>
                <div class="math-formula-title">Mixed Number Deconversion</div>
                <div class="math-formula-latex">$$W \frac{a}{b} = \frac{(W \times b) + a}{b}$$</div>
                <div class="math-formula-desc">Example: $3 \frac{3}{4} = \frac{(3 \times 4) + 3}{4} = \frac{15}{4}$.</div>
            </div>
        </div>
    </section>

