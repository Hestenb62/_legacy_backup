                $$P(E) = \frac{\text{Number of Favorable Outcomes}}{\text{Total Number of Possible Outcomes}} \quad \text{where } 0 \le P(E) \le 1$$
                $$\text{Independent Events: } P(A \text{ and } B) = P(A) \times P(B)$$
