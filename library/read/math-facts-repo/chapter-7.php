                <span class="math-caution-badge"><i class="fas fa-exclamation-triangle"></i> MANDATORY INEQUALITY INVARIANT</span>
                <span class="math-caution-title">Multiplying or Dividing by a Negative Reverses the Direction!</span>
            </div>
            <div class="math-caution-body">
