            <span class="math-section-num">7.1</span>
            <h2 class="math-section-title">Signed Integer Arithmetic: The Four Operations</h2>
        </div>

        <div class="math-formula-grid">
            <div class="math-formula-card">
                <div class="math-formula-title">Addition Rules</div>
                <div class="math-formula-latex">$$\text{Same Signs: Add & Keep} \quad | \quad \text{Different Signs: Subtract & Keep Larger}$$</div>
                <div class="math-formula-desc">$(-4) + (-6) = -10 \quad | \quad (-8) + 12 = +4$.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-title">Subtraction Double Negative Rule</div>
                <div class="math-formula-latex">$$a - (-b) = a + b$$</div>
                <div class="math-formula-desc">Subtracting a negative is equivalent to adding a positive: $5 - (-3) = 5 + 3 = 8$.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-title">Multiplication &amp; Division Signs</div>
                <div class="math-formula-latex">$$(+) \times (+) = (+) \quad | \quad (-) \times (-) = (+) \quad | \quad (+) \times (-) = (-)$$</div>
                <div class="math-formula-desc">Like signs give positive product; unlike signs give negative product.</div>
            </div>
        </div>
    </section>

    <!-- Section 7.2 -->
    <section id="sec-7-2" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">7.2</span>
            <h2 class="math-section-title">Direct Proportions &amp; Constant of Proportionality ($k$)</h2>
        </div>

        <div class="math-def-box">
            <div class="math-def-header">
                <span class="math-def-badge"><i class="fas fa-link"></i> Theorem 7.2.1</span>
                <span class="math-def-domain">Direct Variation</span>
            </div>
            <div class="math-def-body">
                Two variables $x$ and $y$ are in a <strong>proportional relationship</strong> if their ratio is constant:
                $$y = kx \iff k = \frac{y}{x} \quad (k = \text{Constant of Proportionality / Unit Rate})$$
                <strong>Key Geometric Fact:</strong> The graph of a proportional relationship is always a <strong>straight line passing directly through the origin $(0, 0)$</strong>.
            </div>
        </div>
    </section>

