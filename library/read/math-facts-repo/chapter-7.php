            <h2 class="math-section-title">Inequalities &amp; The Golden Sign-Flip Rule</h2>
        </div>

        <div class="math-caution-box">
            <div class="math-caution-header">
                <span class="math-caution-badge"><i class="fas fa-exclamation-triangle"></i> Mandatory Inequality Law</span>
                <span class="math-caution-title">Multiplying or Dividing by a Negative Flips the Inequality!</span>
            </div>
            <div class="math-caution-body">
                Whenever you multiply or divide both sides of an inequality by a negative number:
                $$-2x < 10 \implies \text{Divide by } -2 \implies x \mathbf{>} -5$$
                $$-3x \geq 18 \implies x \mathbf{\leq} -6$$
            </div>
        </div>
