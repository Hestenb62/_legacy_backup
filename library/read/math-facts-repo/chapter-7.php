         Section 7.3: Multi-Step Percents & Simple Interest
         ========================================================================== -->
    <section id="sec-7-3" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">&sect; 7.3</span>
            <h2 class="math-section-title">Multi-Step Percents &amp; Simple Interest ($I = Prt$)</h2>
        </div>

        <div class="math-formula-grid">
            <div class="math-formula-card">
                <div class="math-formula-meta">PERCENT CHANGE</div>
                <div class="math-formula-title">Percent Increase / Decrease</div>
                <div class="math-formula-latex">$$\% \Delta = \frac{|\text{New} - \text{Original}|}{\text{Original}} \times 100\%$$</div>
                <div class="math-formula-desc">Always divide by the original starting baseline value!</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-meta">FINANCIAL ALGEBRA</div>
                <div class="math-formula-title">Simple Interest Formula</div>
                <div class="math-formula-latex">$$I = P \cdot r \cdot t \quad \text{and} \quad A = P + I$$</div>
                <div class="math-formula-desc">$I = \text{Interest}$, $P = \text{Principal}$, $r = \text{Annual rate (decimal)}$, $t = \text{Time in years}$, $A = \text{Total Balance}$.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-meta">SINGLE MULTIPLIER</div>
                <div class="math-formula-title">Efficient Tax &amp; Discount</div>
                <div class="math-formula-latex">$$\begin{aligned} \text{7% Tax: } &\text{Total} = \text{Price} \times 1.07 \\ \text{25% Off: } &\text{Sale} = \text{Price} \times 0.75 \end{aligned}$$</div>
                <div class="math-formula-desc">Calculate directly in 1 step without separate subtraction.</div>
            </div>
        </div>

        <div class="math-example-box">
            <div class="math-ex-header">
                <span class="math-ex-badge"><i class="fas fa-pencil-alt"></i> EXEMPLUM 7.3</span>
                <span class="math-ex-title">Simple Interest Loan Calculation</span>
            </div>
            <div class="math-ex-body">
                <p class="math-ex-problem"><strong>Problem:</strong> A student deposits $\$1,200$ in a savings bond earning $4.5\%$ annual simple interest for $3\text{ years}$. Find the interest earned and total final balance.</p>
                <div class="math-ex-solution">
                    <div class="math-sol-step"><strong>Step 1 (Convert Rate to Decimal):</strong> $r = 4.5\% = 0.045$.</div>
                    <div class="math-sol-step"><strong>Step 2 (Apply $I = Prt$):</strong> $I = 1,200 \times 0.045 \times 3 = 1,200 \times 0.135 = \$162$.</div>
                    <div class="math-sol-step"><strong>Step 3 (Calculate Total Balance):</strong> $A = P + I = \$1,200 + \$162 = \$1,362$.</div>
                </div>
                <div class="math-ex-result">
                    <span><i class="fas fa-check-circle" style="color: #059669;"></i> <strong>Result:</strong> Interest $= \mathbf{\$162}$; Total Balance $= \mathbf{\$1,362}$.</span>
                    <span class="math-qed">&#9632; Q.E.D.</span>
                </div>
            </div>
        </div>
    </section>

