         Section 7.1: Signed Rational Number Operations
         ========================================================================== -->
    <section id="sec-7-1" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">&sect; 7.1</span>
            <h2 class="math-section-title">Signed Rational Number Arithmetic</h2>
        </div>

        <div class="math-def-box">
            <div class="math-def-header">
                <span class="math-def-badge"><i class="fas fa-scroll"></i> AXIOM 7.1.1</span>
                <span class="math-def-domain">Topic: Additive Inverses &amp; Double Negatives</span>
            </div>
            <div class="math-def-body">
                <p><dfn class="math-term">Additive Inverse Law</dfn> &mdash; For every rational number $a$, there exists an opposite $-a$ such that:</p>
                $$a + (-a) = 0 \quad \text{and} \quad a - (-b) = a + b$$
                $$\text{Example: } 7 - (-4) = 7 + 4 = 11 \quad \vert \quad (-15) + 9 = -6$$
            </div>
        </div>

        <div class="math-formula-grid">
            <div class="math-formula-card">
                <div class="math-formula-meta">ADDITION RULES</div>
                <div class="math-formula-title">Same vs. Different Signs</div>
                <div class="math-formula-latex">$$\begin{aligned} (-a) + (-b) &= -(a + b) \\ (-a) + b &= b - a \end{aligned}$$</div>
                <div class="math-formula-desc">Same signs: Add absolute values and keep common sign. Different signs: Subtract smaller absolute value from larger, take larger's sign.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-meta">MULTIPLICATION &amp; DIVISION</div>
                <div class="math-formula-title">Product &amp; Quotient Signs</div>
                <div class="math-formula-latex">$$\begin{aligned} (+) \times (+) &= + \quad & (-) \times (-) &= + \\ (+) \times (-) &= - \quad & (-) \times (+) &= - \end{aligned}$$</div>
                <div class="math-formula-desc">An even count of negative factors yields POSITIVE; an odd count yields NEGATIVE.</div>
            </div>
        </div>
    </section>

