    <section id="sec-7-3" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">7.3</span>
            <h2 class="math-section-title">Percent Applications &amp; Simple Interest ($I = Prt$)</h2>
        </div>

        <div class="math-formula-grid">
            <div class="math-formula-card">
                <div class="math-formula-title">Percent Proportion</div>
                <div class="math-formula-latex">$$\frac{\text{Part}}{\text{Whole}} = \frac{\text{Percent}}{100} \implies \text{Part} = \text{Percent} \times \text{Whole}$$</div>
                <div class="math-formula-desc">Example: $15\%$ of $80 = 0.15 \times 80 = 12$.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-title">Percent of Change Formula</div>
                <div class="math-formula-latex">$$\% \text{ Change} = \frac{|\text{New Value} - \text{Original Value}|}{\text{Original Value}} \times 100\%$$</div>
                <div class="math-formula-desc">Always divide by the original starting baseline!</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-title">Simple Interest Formula</div>
                <div class="math-formula-latex">$$I = P \cdot r \cdot t$$</div>
                <div class="math-formula-desc">$I = \text{Interest}$, $P = \text{Principal (Starting \$)}$, $r = \text{Annual rate (decimal)}$, $t = \text{Time (years)}$.</div>
            </div>
        </div>
    </section>

    <!-- Section 7.4 -->
    <section id="sec-7-4" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">7.4</span>
            <h2 class="math-section-title">Solving Two-Step Algebraic Equations ($ax + b = c$)</h2>
        </div>

        <div class="math-theorem-box">
            <div class="math-thm-header">
                <span class="math-thm-badge"><i class="fas fa-list-ol"></i> Algorithm 7.4</span>
                <span class="math-thm-title">Reverse PEMDAS Strategy</span>
            </div>
            <div class="math-thm-body">
                To isolate variable $x$ in $ax + b = c$:
                $$\text{Step 1: Eliminate addition/subtraction by inverse operation: } ax = c - b$$
                $$\text{Step 2: Eliminate multiplication/division: } x = \frac{c - b}{a}$$
                $$\text{Example: } 3x - 7 = 14 \implies 3x = 14 + 7 = 21 \implies x = \frac{21}{3} = \mathbf{7}$$
            </div>
        </div>
    </section>

