    <section id="sec-7-2" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">&sect; 7.2</span>
            <h2 class="math-section-title">Direct Proportions &amp; Constant of Proportionality ($k$)</h2>
        </div>

        <div class="math-def-box">
            <div class="math-def-header">
                <span class="math-def-badge"><i class="fas fa-chart-line"></i> THEOREM 7.2.1</span>
                <span class="math-def-domain">Topic: Direct Variation Axioms</span>
            </div>
            <div class="math-def-body">
                <p><dfn class="math-term">Proportional Relationship</dfn> &mdash; Two variable quantities $x$ and $y$ are directly proportional if and only if their ratio is strictly invariant:</p>
                $$y = kx \iff k = \frac{y}{x} \quad (k = \text{Constant of Proportionality / Unit Rate})$$
                $$\text{Two Universal Tests: } \begin{cases} \text{1. Numerical: The ratio } \frac{y}{x} \text{ is identical for all data pairs.} \\ \text{2. Graphical: The line is strictly straight AND passes through origin } (0, 0). \end{cases}$$
            </div>
        </div>
    </section>

