        </div>

        <div class="math-formula-grid">
            <div class="math-formula-card">
                <div class="math-formula-meta">RELATIONAL AXIOM I</div>
                <div class="math-formula-title">Strict Inequality: Greater Than ($&gt;$)</div>
                <div class="math-formula-latex">$$a &gt; b \iff a \text{ exceeds } b \text{ in magnitude}$$</div>
                <div class="math-formula-desc">The open aperture of the symbol consistently faces the greater quantity: $18 &gt; 12$.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-meta">RELATIONAL AXIOM II</div>
                <div class="math-formula-title">Strict Inequality: Less Than ($&lt;$)</div>
                <div class="math-formula-latex">$$a &lt; b \iff a \text{ is subordinate to } b$$</div>
                <div class="math-formula-desc">The vertex (pointed apex) consistently addresses the smaller quantity: $9 &lt; 15$.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-meta">RELATIONAL AXIOM III</div>
                <div class="math-formula-title">Equivalence: Equal To ($=$)</div>
                <div class="math-formula-latex">$$a = b \iff \text{Both expressions denote identical value}$$</div>
                <div class="math-formula-desc">Represents numerical equilibrium across the fulcrum: $6 + 4 = 10$.</div>
            </div>
