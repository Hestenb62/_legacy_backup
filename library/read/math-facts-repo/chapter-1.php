        <div class="math-section-header">
            <span class="math-section-num">&sect; 1.2</span>
            <h2 class="math-section-title">Addition &amp; Subtraction (Within 20)</h2>
        </div>

        <div class="math-formula-grid">
            <div class="math-formula-card">
                <div class="math-formula-meta">ARITHMETIC LAW I</div>
                <div class="math-formula-title">Commutative Property of Addition</div>
                <div class="math-formula-latex">$$a + b = b + a$$</div>
                <div class="math-formula-desc">The spatial ordering of addends does not alter their combined sum. Example: $3 + 5 = 8$ and $5 + 3 = 8$.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-meta">ARITHMETIC LAW II</div>
                <div class="math-formula-title">Identity Property of Zero</div>
                <div class="math-formula-latex">$$a + 0 = a \quad \text{and} \quad a - 0 = a$$</div>
                <div class="math-formula-desc">The addition or subtraction of the zero element leaves any real magnitude invariant.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-meta">ARITHMETIC LAW III</div>
                <div class="math-formula-title">Inverse Addition/Subtraction Relation</div>
                <div class="math-formula-latex">$$\text{If } a + b = c, \text{ then } c - a = b \text{ and } c - b = a$$</div>
                <div class="math-formula-desc">Fact family bonds bind triplets of integers in mutual equilibrium: $\{4, 6, 10\}$.</div>
            </div>
        </div>

        <div class="math-example-box">
            <div class="math-ex-header">
                <span class="math-ex-badge"><i class="fas fa-pencil-alt"></i> EXEMPLUM 1.2</span>
                <span class="math-ex-title">Missing Addend Problem</span>
            </div>
            <div class="math-ex-body">
                <p class="math-ex-problem"><strong>Problem Statement:</strong> Maya possesses 7 apples. After gathering an additional quantity, she possesses 15 apples in total. What quantity did she gather?</p>
                <div class="math-ex-solution">
                    <div class="math-sol-step"><strong>Step 1 (Equation Formulation):</strong> Represent the unknown quantity by $\square$: $$7 + \square = 15$$</div>
                    <div class="math-sol-step"><strong>Step 2 (Inverse Subtraction Fact):</strong> Transform using the inverse operation: $$\square = 15 - 7$$</div>
                    <div class="math-sol-step"><strong>Step 3 (Bridge Through Ten Decomposition):</strong> Decompose $7$ into $5 + 2$: $$15 - 5 - 2 = 10 - 2 = 8$$</div>
                </div>
                <div class="math-ex-result">
                    <span><i class="fas fa-check-circle" style="color: #059669;"></i> <strong>Conclusion:</strong> Maya gathered precisely <strong>8 apples</strong> ($7 + 8 = 15$).</span>
                    <span class="math-qed">&#9632; Q.E.D.</span>
                </div>
            </div>
        </div>
    </section>

