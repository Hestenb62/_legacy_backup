    <section id="sec-1-7" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">&sect; 1.7</span>
            <h2 class="math-section-title">Scholia &amp; Computational Mental Math Hacks</h2>
        </div>

        <div class="math-constant-grid">
            <div class="math-constant-card">
                <div class="math-const-sym"><i class="fas fa-bolt" style="color: #b45309;"></i> HEURISTIC I</div>
                <div class="math-const-name">"Make a 10" Bridge Method</div>
                <div class="math-const-val">$$8 + 5 = (8 + 2) + 3 = 10 + 3 = 13$$</div>
                <div class="math-const-desc">Isolate complementary pairs to 10: $(9+1, 8+2, 7+3, 6+4, 5+5)$. Partition the minor addend to compose the anchor ten.</div>
            </div>

            <div class="math-constant-card">
                <div class="math-const-sym"><i class="fas fa-magic" style="color: #1e3a8a;"></i> HEURISTIC II</div>
                <div class="math-const-name">"Doubles &amp; Near-Doubles" Identity</div>
                <div class="math-const-val">$$6 + 7 = (6 + 6) + 1 = 12 + 1 = 13$$</div>
                <div class="math-const-desc">Anchor mental retrieval to symmetrical pairs ($6+6=12$). Derive contiguous sums instantaneously via $+1$ or $-1$ adjustment.</div>
            </div>

            <div class="math-constant-card">
                <div class="math-const-sym"><i class="fas fa-arrows-alt-h" style="color: #065f46;"></i> HEURISTIC III</div>
                <div class="math-const-name">"Counting On" Magnitude Heuristic</div>
                <div class="math-const-val">$$3 + 9 \implies \text{Index at } 9: 10, 11, 12$$</div>
                <div class="math-const-desc">Never count upward from the inferior addend. Initiate the sequence at the superior integer and increment by the minor addend.</div>
            </div>

            <div class="math-constant-card">
                <div class="math-const-sym"><i class="fas fa-shield-alt" style="color: #9d174d;"></i> SCHOLIA</div>
                <div class="math-const-name">Triadic Fact Family Bonds</div>
                <div class="math-const-val">$$\Delta(3, 8, 11) \iff 3+8=11, 8+3=11, 11-3=8, 11-8=3$$</div>
                <div class="math-const-desc">A single triadic relation simultaneously codifies two additive identities and two subtractive inverse deductions.</div>
            </div>
        </div>

        <div class="math-caution-box">
            <div class="math-caution-header">
                <span class="math-caution-badge"><i class="fas fa-exclamation-triangle"></i> SCHOLASTIC WARNING</span>
                <span class="math-caution-title">Non-Commutative Nature of Subtraction</span>
            </div>
            <div class="math-caution-body">
                Unlike addition, <strong>subtraction does NOT satisfy the commutative law</strong>!
                $$10 - 4 = 6 \quad \text{whereas} \quad 4 - 10 = -6 \neq 6$$
                In elementary arithmetic, computation must consistently commence with the whole (minuend) rather than the part (subtrahend).
            </div>
