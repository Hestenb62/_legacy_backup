        <div class="math-section-header">
            <span class="math-section-num">9.3</span>
            <h2 class="math-section-title">Special Factoring Identities (Core Formulas)</h2>
        </div>

        <div class="math-formula-grid">
            <div class="math-formula-card">
                <div class="math-formula-title">Difference of Two Squares</div>
                <div class="math-formula-latex">$$a^2 - b^2 = (a + b)(a - b)$$</div>
                <div class="math-formula-desc">Example: $9x^2 - 49 = (3x + 7)(3x - 7)$.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-title">Perfect Square Trinomial (+)</div>
                <div class="math-formula-latex">$$a^2 + 2ab + b^2 = (a + b)^2$$</div>
                <div class="math-formula-desc">Example: $x^2 + 10x + 25 = (x + 5)^2$.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-title">Perfect Square Trinomial (-)</div>
                <div class="math-formula-latex">$$a^2 - 2ab + b^2 = (a - b)^2$$</div>
                <div class="math-formula-desc">Example: $4x^2 - 12x + 9 = (2x - 3)^2$.</div>
            </div>
        </div>
    </section>

    <!-- Section 9.4 -->
    <section id="sec-9-4" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">9.4</span>
            <h2 class="math-section-title">The Quadratic Formula &amp; Discriminant Theory</h2>
        </div>

        <div class="math-theorem-box">
            <div class="math-thm-header">
                <span class="math-thm-badge"><i class="fas fa-gem"></i> Fundamental Formula</span>
                <span class="math-thm-title">The Quadratic Formula</span>
            </div>
            <div class="math-thm-body">
                For any quadratic equation $ax^2 + bx + c = 0$ with $a \neq 0$:
                $$x = \frac{-b \pm \sqrt{b^2 - 4ac}}{2a}$$
                The <strong>Discriminant</strong> is defined as: $\Delta = b^2 - 4ac$.
            </div>
        </div>

        <div class="ref-table-wrap">
            <table class="ref-table">
                <thead>
                    <tr>
                        <th>Discriminant ($\Delta$)</th>
                        <th>Nature of Roots</th>
                        <th>Parabola $x$-Intercepts</th>
                    </tr>
                </thead>
                <tbody>
                    <tr><td><strong>$\Delta > 0$ (Positive Perfect Square)</strong></td><td>Two distinct rational roots</td><td>Crosses $x$-axis twice at rational values</td></tr>
                    <tr><td><strong>$\Delta > 0$ (Non-Square)</strong></td><td>Two distinct irrational roots</td><td>Crosses $x$-axis twice with square roots</td></tr>
                    <tr><td><strong>$\Delta = 0$ (Zero)</strong></td><td>One repeated real root (double root)</td><td>Vertex touches $x$-axis tangentially</td></tr>
                    <tr><td><strong>$\Delta < 0$ (Negative)</strong></td><td>Two complex conjugate roots (No real roots)</td><td>Does NOT touch the $x$-axis</td></tr>
                </tbody>
            </table>
        </div>
    </section>

