    <section id="sec-9-2" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">9.2</span>
            <h2 class="math-section-title">Factoring Quadratics: The Master $ac$-Method</h2>
        </div>

        <div class="math-theorem-box">
            <div class="math-thm-header">
                <span class="math-thm-badge"><i class="fas fa-award"></i> Algorithm 9.2</span>
                <span class="math-thm-title">The $ac$-Method for Factoring $ax^2 + bx + c$</span>
            </div>
            <div class="math-thm-body">
                $$\text{Step 1: Compute product } P = a \cdot c \text{ and sum } S = b.$$
                $$\text{Step 2: Find two integer factors } m, n \text{ such that } m \cdot n = a \cdot c \text{ and } m + n = b.$$
                $$\text{Step 3: Split the middle term: } ax^2 + mx + nx + c \text{ and factor by grouping!}$$
                $$\text{Example: } 2x^2 + 7x + 3 \implies a \cdot c = 6 \implies \text{factors } (6, 1) \implies 2x^2 + 6x + 1x + 3 = (2x + 1)(x + 3)$$
            </div>
        </div>
    </section>

