    <section id="sec-9-7" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">9.7</span>
            <h2 class="math-section-title">Grade 9 Mental Math &amp; Factoring Shortcuts</h2>
        </div>

        <div class="math-constant-grid">
            <div class="math-constant-card">
                <div class="math-const-sym"><i class="fas fa-times" style="color: #f59e0b;"></i> Hack #1</div>
                <div class="math-const-name">The "X-Factor" Visual Diamond</div>
                <div class="math-const-val">$$\text{Top: } a \cdot c \quad | \quad \text{Bottom: } b \implies \text{Find sides } m, n$$</div>
                <div class="math-const-desc">Draw a large X. Put $ac$ on top and $b$ on the bottom. Filling the left and right wings gives your binomial factors instantly.</div>
            </div>

            <div class="math-constant-card">
                <div class="math-const-sym"><i class="fas fa-bolt" style="color: #6366f1;"></i> Hack #2</div>
                <div class="math-const-name">Vieta's Sum and Product of Roots Shortcut</div>
                <div class="math-const-val">$$r_1 + r_2 = -\frac{b}{a} \quad \text{and} \quad r_1 \cdot r_2 = \frac{c}{a}$$</div>
                <div class="math-const-desc">Never solve a quadratic just to find the sum or product of its roots on an exam. Read them directly off $-b/a$ and $c/a$!</div>
            </div>

            <div class="math-constant-card">
                <div class="math-const-sym"><i class="fas fa-crosshairs" style="color: #10b981;"></i> Hack #3</div>
                <div class="math-const-name">Elimination System Addition Multiplier</div>
                <div class="math-const-val">$$\text{Match coefficients with opposite signs} \implies \text{Add equations to kill } x \text{ or } y$$</div>
                <div class="math-const-desc">Multiply row 1 by $+3$ and row 2 by $-2$ so $6x + (-6x) = 0$. Solves $2 \times 2$ systems in 30 seconds.</div>
            </div>
        </div>
    </section>

