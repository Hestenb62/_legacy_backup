            <span class="math-section-num">5.4</span>
            <h2 class="math-section-title">3D Solid Geometry: Volume of Rectangular Prisms</h2>
        </div>

        <div class="math-formula-grid">
            <div class="math-formula-card">
                <div class="math-formula-title">Volume Formula (Standard)</div>
                <div class="math-formula-latex">$$V = \text{length} \times \text{width} \times \text{height} = l \times w \times h$$</div>
                <div class="math-formula-desc">Measured in cubic units ($\text{cubic units}, \text{cm}^3, \text{in}^3$).</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-title">Base Area Formula</div>
                <div class="math-formula-latex">$$V = B \times h \quad \text{where } B = l \times w$$</div>
                <div class="math-formula-desc">Base Area $B$ multiplied by height $h$.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-title">Volume of a Cube</div>
                <div class="math-formula-latex">$$V = s^3 = s \times s \times s$$</div>
                <div class="math-formula-desc">All 3 dimensions are equal to side length $s$.</div>
            </div>
        </div>
    </section>

