         Section 5.3: Unlike Fractions Addition & Subtraction
         ========================================================================== -->
    <section id="sec-5-3" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">&sect; 5.3</span>
            <h2 class="math-section-title">Fraction Arithmetic: Unlike Denominators &amp; Mixed Numbers</h2>
        </div>

        <div class="math-def-box">
            <div class="math-def-header">
                <span class="math-def-badge"><i class="fas fa-layer-group"></i> THEOREM 5.3.1</span>
                <span class="math-def-domain">Topic: Common Denominator (LCD) Axiom</span>
            </div>
            <div class="math-def-body">
                Fractions cannot be directly combined unless their parts are congruent in size. We must find the <strong>Least Common Multiple ($\text{LCM}$)</strong> of the denominators:
                $$\frac{a}{b} \pm \frac{c}{d} = \frac{a \cdot d}{b \cdot d} \pm \frac{c \cdot b}{b \cdot d} = \frac{ad \pm cb}{bd}$$
            </div>
        </div>

        <div class="math-example-box">
            <div class="math-ex-header">
                <span class="math-ex-badge"><i class="fas fa-pencil-alt"></i> EXEMPLUM 5.3</span>
                <span class="math-ex-title">Unlike Denominators with Mixed Numbers</span>
            </div>
            <div class="math-ex-body">
                <p class="math-ex-problem"><strong>Problem:</strong> Calculate $3 \frac{2}{3} + 1 \frac{3}{4}$.</p>
                <div class="math-ex-solution">
                    <div class="math-sol-step"><strong>Step 1 (Find LCD):</strong> $\text{LCM}(3, 4) = 12$.</div>
                    <div class="math-sol-step"><strong>Step 2 (Rename Fractions):</strong> $\frac{2}{3} = \frac{8}{12}$ and $\frac{3}{4} = \frac{9}{12}$.</div>
                    <div class="math-sol-step"><strong>Step 3 (Add Wholes &amp; Fractions):</strong> $(3 + 1) + \left(\frac{8}{12} + \frac{9}{12}\right) = 4 + \frac{17}{12}$.</div>
                    <div class="math-sol-step"><strong>Step 4 (Regroup Improper Fraction):</strong> $\frac{17}{12} = 1 \frac{5}{12} \implies 4 + 1 \frac{5}{12} = 5 \frac{5}{12}$.</div>
                </div>
                <div class="math-ex-result">
                    <span><i class="fas fa-check-circle" style="color: #059669;"></i> <strong>Result:</strong> $3 \frac{2}{3} + 1 \frac{3}{4} = \mathbf{5 \frac{5}{12}}$.</span>
                    <span class="math-qed">&#9632; Q.E.D.</span>
                </div>
            </div>
        </div>
    </section>

