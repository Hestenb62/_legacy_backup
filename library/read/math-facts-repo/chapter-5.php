         Section 5.4: Fraction Multiplication & Scaling
         ========================================================================== -->
    <section id="sec-5-4" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">&sect; 5.4</span>
            <h2 class="math-section-title">Fraction Multiplication: The Straight-Across Theorem</h2>
        </div>

        <div class="math-formula-grid">
            <div class="math-formula-card">
                <div class="math-formula-meta">MULTIPLICATION LAW</div>
                <div class="math-formula-title">Straight-Across Product</div>
                <div class="math-formula-latex">$$\frac{a}{b} \times \frac{c}{d} = \frac{a \times c}{b \times d}$$</div>
                <div class="math-formula-desc">Multiply numerators straight across; multiply denominators straight across.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-meta">OPTIMIZATION STRATEGY</div>
                <div class="math-formula-title">Cross-Cancellation Heuristic</div>
                <div class="math-formula-latex">$$\frac{3}{8} \times \frac{4}{9} = \frac{\cancel{3}^1}{\cancel{8}^2} \times \frac{\cancel{4}^1}{\cancel{9}^3} = \frac{1 \times 1}{2 \times 3} = \frac{1}{6}$$</div>
                <div class="math-formula-desc">Cancel greatest common factors across diagonals before multiplying.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-meta">SCALING CONCEPT</div>
                <div class="math-formula-title">Multiplication as Scaling</div>
                <div class="math-formula-latex">$$N \times \frac{a}{b} \begin{cases} &gt; N & \text{if } \frac{a}{b} &gt; 1 \\ = N & \text{if } \frac{a}{b} = 1 \\ &lt; N & \text{if } \frac{a}{b} &lt; 1 \end{cases}$$</div>
                <div class="math-formula-desc">Multiplying by a fraction $< 1$ shrinks the size of the original quantity!</div>
            </div>
        </div>
    </section>

    <!-- ==========================================================================
         Section 5.5: Fraction Division (KCF Rule)
         ========================================================================== -->
    <section id="sec-5-5" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">&sect; 5.5</span>
            <h2 class="math-section-title">Fraction Division &amp; The "Keep-Change-Flip" (KCF) Rule</h2>
        </div>

        <div class="math-def-box">
            <div class="math-def-header">
                <span class="math-def-badge"><i class="fas fa-sync-alt"></i> AXIOM 5.5.1</span>
                <span class="math-def-domain">Topic: The Reciprocal Division Axiom</span>
            </div>
            <div class="math-def-body">
                <p><dfn class="math-term">Division by a Fraction</dfn> &mdash; Division by any non-zero fraction $\frac{c}{d}$ is mathematically identical to multiplication by its multiplicative inverse (reciprocal) $\frac{d}{c}$:</p>
                $$\frac{a}{b} \div \frac{c}{d} = \frac{a}{b} \times \frac{d}{c} = \frac{a \cdot d}{b \cdot c}$$
                $$\text{Example: } \frac{1}{3} \div 4 = \frac{1}{3} \times \frac{1}{4} = \frac{1}{12} \quad \vert \quad 4 \div \frac{1}{3} = 4 \times \frac{3}{1} = 12$$
            </div>
        </div>

        <div class="math-howto-box">
            <div class="math-howto-header"><i class="fas fa-undo"></i> Student Guide: The 3 Letters of Fraction Division (K-C-F)</div>
            <div class="math-howto-steps">
                <div class="math-step-item">
                    <span class="math-step-badge">K: KEEP</span>
                    <div>Keep the first fraction exactly as it is written. Never change the dividend!</div>
                </div>
                <div class="math-step-item">
                    <span class="math-step-badge">C: CHANGE</span>
                    <div>Change the division sign ($\div$) into a multiplication sign ($\times$).</div>
                </div>
                <div class="math-step-item">
                    <span class="math-step-badge">F: FLIP</span>
                    <div>Flip the second fraction upside down to its reciprocal ($\frac{c}{d} \to \frac{d}{c}$). Multiply straight across!</div>
                </div>
            </div>
        </div>
    </section>

