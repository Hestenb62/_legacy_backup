            <h2 class="math-section-title">Decimal Arithmetic ($+ - \times \div$) &amp; Power of 10 Shifts</h2>
        </div>

        <div class="math-formula-grid">
            <div class="math-formula-card">
                <div class="math-formula-title">Addition &amp; Subtraction</div>
                <div class="math-formula-latex">$$\text{Line up decimals vertically: } 14.70 + 3.25 = 17.95$$</div>
                <div class="math-formula-desc">Fill in trailing zeros so decimal points align exactly.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-title">Multiplication Decimal Count Rule</div>
                <div class="math-formula-latex">$$0.4 \times 0.03 \implies 4 \times 3 = 12 \implies \mathbf{0.012}$$</div>
                <div class="math-formula-desc">Total decimal places in product = sum of decimal places in factors ($1 + 2 = 3$).</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-title">Power of 10 Shift Rule</div>
                <div class="math-formula-latex">$$3.45 \times 10^2 = 345 \quad | \quad 34.5 \div 10^2 = 0.345$$</div>
                <div class="math-formula-desc">$\times 10^k \implies$ shift decimal right $k$ places. $\div 10^k \implies$ shift left $k$ places.</div>
            </div>
        </div>
    </section>

