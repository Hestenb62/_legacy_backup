                <p class="math-ex-problem"><strong>Problem:</strong> An L-shaped concrete step is built from two non-overlapping rectangular blocks. Prism A has dimensions $4\text{ m} \times 2\text{ m} \times 3\text{ m}$. Prism B has dimensions $2\text{ m} \times 2\text{ m} \times 1\text{ m}$. What is the total volume?</p>
