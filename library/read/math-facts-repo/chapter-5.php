            <h2 class="math-section-title">Grade 5 Comprehensive Summary Cheat Sheet</h2>
        </div>

        <div class="math-summary-sheet">
            <div class="math-summary-col">
                <h4>Fraction Operations</h4>
                <ul>
                    <li>Multiply: $\frac{a}{b} \times \frac{c}{d} = \frac{ac}{bd}$</li>
                    <li>Divide: $\frac{a}{b} \div \frac{c}{d} = \frac{ad}{bc}$ (KCF)</li>
                    <li>Add/Sub: Common denominator required ($\text{LCM}$)</li>
                    <li>Reciprocal of $\frac{3}{7}$ is $\frac{7}{3}$</li>
                </ul>
            </div>

            <div class="math-summary-col">
                <h4>Decimal Shift Laws</h4>
                <ul>
                    <li>$\times 10 \implies \rightarrow 1$ place</li>
                    <li>$\times 100 \implies \rightarrow 2$ places</li>
                    <li>$\div 10 \implies \leftarrow 1$ place</li>
                    <li>$\div 100 \implies \leftarrow 2$ places</li>
                    <li>Align decimals for $+ -$ only!</li>
                </ul>
            </div>

            <div class="math-summary-col">
                <h4>Volume &amp; Order of Operations</h4>
                <ul>
                    <li>Volume $V = l \times w \times h$</li>
                    <li>Volume $V = B \times h$</li>
                    <li>$(x, y)$: $x = \text{horizontal}, y = \text{vertical}$</li>
                    <li>PEMDAS: Left-to-Right on $(M/D)$ and $(A/S)$</li>
                </ul>
            </div>
