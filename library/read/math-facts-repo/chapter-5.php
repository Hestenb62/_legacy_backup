                <div class="math-formula-title">Division by $10^k$</div>
                <div class="math-formula-latex">$$x \div 10^k \implies \text{Shift decimal } k \text{ places LEFT}$$</div>
                <div class="math-formula-desc">$48.2 \div 10^2 = 0.482$. Each step makes the number 10 times smaller ($\frac{1}{10}$).</div>
            </div>
