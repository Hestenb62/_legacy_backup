        <div class="math-formula-grid">
            <div class="math-formula-card">
                <div class="math-formula-meta">METRIC EXPONENT LAW I</div>
                <div class="math-formula-title">Multiplication by $10^k$</div>
                <div class="math-formula-latex">$$x \times 10^k \implies \text{Shift decimal } k \text{ places RIGHT}$$</div>
                <div class="math-formula-desc">$3.456 \times 10^2 = 345.6$. Each step makes the number 10 times larger.</div>
            </div>

