            <h2 class="math-section-title">The Cartesian Coordinate Plane (Quadrant I)</h2>
        </div>

        <div class="math-def-box">
            <div class="math-def-header">
                <span class="math-def-badge"><i class="fas fa-map-marker-alt"></i> Definition 5.5.1</span>
                <span class="math-def-domain">Ordered Pairs</span>
            </div>
            <div class="math-def-body">
                An ordered pair $(x, y)$ identifies a unique location on the coordinate grid:
                <ul>
                    <li><strong>Origin:</strong> $(0, 0)$, the intersection of the horizontal $x$-axis and vertical $y$-axis.</li>
                    <li><strong>$x$-coordinate (First):</strong> Distance moved horizontally <em>right</em> along the ground.</li>
                    <li><strong>$y$-coordinate (Second):</strong> Distance moved vertically <em>up</em> the ladder.</li>
                    <li><em>"Crawl before you climb: go across $x$, then up $y$!"</em></li>
                </ul>
            </div>
