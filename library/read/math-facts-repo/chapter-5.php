            </div>

            <div class="math-constant-card">
                <div class="math-const-sym"><i class="fas fa-undo" style="color: #1e3a8a;"></i> HACK II</div>
                <div class="math-const-name">Keep-Change-Flip (KCF)</div>
                <div class="math-const-val">$$\frac{a}{b} \div \frac{c}{d} = \frac{a}{b} \times \frac{d}{c}$$</div>
                <div class="math-const-desc">Division is multiplication by the reciprocal. Keep first, change to times, flip the second!</div>
            </div>

            <div class="math-constant-card">
