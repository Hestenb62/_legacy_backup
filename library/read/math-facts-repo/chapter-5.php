            <h2 class="math-section-title">Fraction Multiplication: The Straight-Across Theorem</h2>
        </div>

        <div class="math-formula-grid">
            <div class="math-formula-card">
                <div class="math-formula-title">Fraction Multiplication Law</div>
                <div class="math-formula-latex">$$\frac{a}{b} \times \frac{c}{d} = \frac{a \times c}{b \times d}$$</div>
                <div class="math-formula-desc">Multiply numerators together; multiply denominators together.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-title">Cross-Simplification Rule</div>
                <div class="math-formula-latex">$$\frac{3}{8} \times \frac{4}{9} = \frac{\cancel{3}^1}{\cancel{8}^2} \times \frac{\cancel{4}^1}{\cancel{9}^3} = \frac{1}{6}$$</div>
                <div class="math-formula-desc">Simplify before multiplying to avoid dealing with huge fractions!</div>
            </div>
        </div>
    </section>

    <!-- Section 5.2 -->
    <section id="sec-5-2" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">5.2</span>
            <h2 class="math-section-title">Fraction Division &amp; The "Keep-Change-Flip" (KCF) Rule</h2>
        </div>

        <div class="math-theorem-box">
            <div class="math-thm-header">
                <span class="math-thm-badge"><i class="fas fa-sync"></i> Axiom 5.2</span>
                <span class="math-thm-title">Division by a Fraction is Multiplication by its Reciprocal</span>
            </div>
            <div class="math-thm-body">
                For any non-zero fraction $\frac{c}{d}$, its reciprocal is $\frac{d}{c}$. Therefore:
                $$\frac{a}{b} \div \frac{c}{d} = \frac{a}{b} \times \frac{d}{c} = \frac{a \cdot d}{b \cdot c}$$
                $$\text{Example: } \frac{3}{4} \div \frac{2}{5} = \frac{3}{4} \times \frac{5}{2} = \frac{15}{8} = 1 \frac{7}{8}$$
            </div>
        </div>
    </section>

