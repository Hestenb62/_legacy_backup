            <span class="math-section-num">&sect; 5.2</span>
            <h2 class="math-section-title">Decimal Arithmetic Algorithms ($+ - \times \div$)</h2>
        </div>

        <div class="math-howto-box">
            <div class="math-howto-header"><i class="fas fa-tasks"></i> The Rules of Decimal Operations</div>
            <div class="math-howto-steps">
                <div class="math-step-item">
                    <span class="math-step-badge">ADDITION &amp; SUBTRACTION</span>
                    <div><strong>Line up the decimal points strictly!</strong> Annex trailing zeros so all numbers have identical length. Drop decimal straight down into the sum/difference.</div>
                </div>
                <div class="math-step-item">
                    <span class="math-step-badge">MULTIPLICATION</span>
                    <div>Do <strong>NOT</strong> line up decimals. Multiply as if whole numbers. Count total decimal places in both factors: place decimal point that many spots from the right. $0.4 \times 0.03 \implies 4 \times 3 = 12 \implies \mathbf{0.012}$ ($1+2=3$ places).</div>
                </div>
                <div class="math-step-item">
                    <span class="math-step-badge">DIVISION</span>
                    <div>Never divide by a decimal divisor! Shift the divisor's decimal right until it is a whole number; shift the dividend's decimal right the exact same number of spots. Pop the decimal straight up into the quotient.</div>
                </div>
            </div>
        </div>
    </section>

