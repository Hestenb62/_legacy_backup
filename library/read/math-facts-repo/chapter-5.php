    <section id="sec-5-1" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">&sect; 5.1</span>
            <h2 class="math-section-title">Decimal Place Value to Thousandths &amp; Metric Power Shifts</h2>
        </div>

        <div class="math-def-box">
            <div class="math-def-header">
                <span class="math-def-badge"><i class="fas fa-scroll"></i> DEFINITION 5.1.1</span>
                <span class="math-def-domain">Topic: The Negative Power Base-10 Expansion</span>
            </div>
            <div class="math-def-body">
                <p><dfn class="math-term">Decimal Positional Value</dfn> &mdash; Digits to the right of the decimal point represent negative integer powers of $10$:</p>
                $$N = d_0 + \left(d_{-1} \times \frac{1}{10}\right) + \left(d_{-2} \times \frac{1}{100}\right) + \left(d_{-3} \times \frac{1}{1,000}\right)$$
                $$\text{Example: } 4.735 = 4 + 0.7 + 0.03 + 0.005 = 4 + \frac{7}{10} + \frac{3}{100} + \frac{5}{1,000}$$
            </div>
        </div>

