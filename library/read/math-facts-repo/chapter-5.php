        <div class="math-constant-grid">
            <div class="math-constant-card">
                <div class="math-const-sym"><i class="fas fa-butterfly" style="color: #b45309;"></i> HACK I</div>
                <div class="math-const-name">The Fraction Butterfly Method</div>
                <div class="math-const-val">$$\frac{2}{3} + \frac{1}{4} \implies \frac{(2 \times 4) + (3 \times 1)}{3 \times 4} = \frac{8+3}{12} = \frac{11}{12}$$</div>
