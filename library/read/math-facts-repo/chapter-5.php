    <section id="sec-5-7" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">5.7</span>
            <h2 class="math-section-title">Grade 5 Mental Math Hacks &amp; Speed Tricks</h2>
        </div>

        <div class="math-constant-grid">
            <div class="math-constant-card">
                <div class="math-const-sym"><i class="fas fa-butterfly" style="color: #f59e0b;"></i> Hack #1</div>
                <div class="math-const-name">The "Fraction Butterfly" Method for Unlike Fractions</div>
                <div class="math-const-val">$$\frac{2}{3} + \frac{1}{4} \implies \frac{(2 \times 4) + (3 \times 1)}{3 \times 4} = \frac{8 + 3}{12} = \frac{11}{12}$$</div>
                <div class="math-const-desc">Cross-multiply wing diagonally for the top numerators, then multiply the bottoms for common denominator!</div>
            </div>

            <div class="math-constant-card">
                <div class="math-const-sym"><i class="fas fa-undo" style="color: #6366f1;"></i> Hack #2</div>
                <div class="math-const-name">"Keep-Change-Flip" (KCF) Mnemonic</div>
                <div class="math-const-val">$$\frac{a}{b} \div \frac{c}{d} \implies \text{Keep } \frac{a}{b}, \text{ Change } \div \to \times, \text{ Flip } \frac{c}{d} \to \frac{d}{c}$$</div>
                <div class="math-const-desc">Never divide fractions directly. Chant K-C-F: Keep, Change, Flip.</div>
            </div>

            <div class="math-constant-card">
                <div class="math-const-sym"><i class="fas fa-percentage" style="color: #10b981;"></i> Hack #3</div>
                <div class="math-const-name">Multiplying by 25: Divide by 4 and Add 00</div>
                <div class="math-const-val">$$48 \times 25 = (48 \div 4) \times 100 = 12 \times 100 = 1,200$$</div>
                <div class="math-const-desc">Because $25 = 100 \div 4$, divide the number by 4 and append two zeros. Instant mental calculation!</div>
            </div>
        </div>
    </section>

