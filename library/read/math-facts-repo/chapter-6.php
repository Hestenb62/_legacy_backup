            <h2 class="math-section-title">Grade 6 Mental Math &amp; Pre-Algebra Hacks</h2>
        </div>

        <div class="math-constant-grid">
            <div class="math-constant-card">
                <div class="math-const-sym"><i class="fas fa-crosshairs" style="color: #f59e0b;"></i> Hack #1</div>
                <div class="math-const-name">Cross-Multiply Ratio Resolver</div>
                <div class="math-const-val">$$\frac{a}{b} = \frac{x}{d} \implies x = \frac{a \times d}{b}$$</div>
                <div class="math-const-desc">Multiply the diagonal pair that are both numbers, then divide by the lone corner number! Instant 1-step resolution.</div>
            </div>

            <div class="math-constant-card">
                <div class="math-const-sym"><i class="fas fa-arrows-alt-h" style="color: #6366f1;"></i> Hack #2</div>
                <div class="math-const-name">Absolute Value as Geometric Distance</div>
                <div class="math-const-val">$$\text{Distance between } a \text{ and } b = |a - b|$$</div>
                <div class="math-const-desc">Distance between $-5$ and $8$: $|-5 - 8| = |-13| = 13\text{ units}$. Never get confused by negative signs again.</div>
            </div>

            <div class="math-constant-card">
                <div class="math-const-sym"><i class="fas fa-balance-scale" style="color: #10b981;"></i> Hack #3</div>
                <div class="math-const-name">Algebra Balance Scale Axiom</div>
                <div class="math-const-val">$$\text{What you do to one side, you MUST do to the other side!}$$</div>
                <div class="math-const-desc">If you subtract $7$ from the left side, subtract $7$ from the right side. The equals sign is a sacred balance.</div>
            </div>
        </div>
    </section>

