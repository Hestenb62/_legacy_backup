                <div class="math-const-val">$$10\% \text{ of } 75 = 7.5 \implies 5\% = 3.75, \ 20\% = 15$$</div>
                <div class="math-const-desc">Find 10% by shifting decimal left 1 spot. Then double for 20% or halve for 5%!</div>
            </div>

            <div class="math-constant-card">
                <div class="math-const-sym"><i class="fas fa-arrows-alt-h" style="color: #065f46;"></i> HACK III</div>
                <div class="math-const-name">Distance as Absolute Difference</div>
                <div class="math-const-val">$$\text{Distance} = |a - b|$$</div>
                <div class="math-const-desc">Distance between $-7$ and $5$: $|-7 - 5| = |-12| = 12\text{ units}$. Never get tripped up by negative coordinates.</div>
            </div>

            <div class="math-constant-card">
                <div class="math-const-sym"><i class="fas fa-shield-alt" style="color: #9d174d;"></i> HACK IV</div>
                <div class="math-const-name">Integer Multiplication Signs Rule</div>
                <div class="math-const-val">$$(+) \times (+) = + \quad \vert \quad (-) \times (-) = + \quad \vert \quad (+) \times (-) = -$$</div>
                <div class="math-const-desc">Same signs produce POSITIVE. Different signs produce NEGATIVE. True for multiplication and division.</div>
            </div>
