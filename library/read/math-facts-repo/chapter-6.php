    <section id="sec-6-3" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">6.3</span>
            <h2 class="math-section-title">One-Step Algebraic Equations &amp; Properties of Equality</h2>
        </div>

        <div class="math-formula-grid">
            <div class="math-formula-card">
                <div class="math-formula-title">Addition / Subtraction Inverse</div>
                <div class="math-formula-latex">$$x + a = b \implies x = b - a$$</div>
                <div class="math-formula-desc">Example: $x + 15 = 42 \implies x = 42 - 15 = 27$.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-title">Multiplication / Division Inverse</div>
                <div class="math-formula-latex">$$a \cdot x = b \implies x = \frac{b}{a} \quad (a \neq 0)$$</div>
                <div class="math-formula-desc">Example: $6x = 48 \implies x = \frac{48}{6} = 8$.</div>
            </div>
        </div>
    </section>

