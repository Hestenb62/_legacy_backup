    <section id="sec-6-4" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">6.4</span>
            <h2 class="math-section-title">Exponents &amp; Algebraic Expressions</h2>
        </div>

        <div class="math-def-box">
            <div class="math-def-header">
                <span class="math-def-badge"><i class="fas fa-superscript"></i> Definition 6.4.1</span>
                <span class="math-def-domain">Exponential Notation</span>
            </div>
            <div class="math-def-body">
                $$b^n = \underbrace{b \times b \times \dots \times b}_{n \text{ factors}}$$
                $$\text{Base } b = \text{number being multiplied}, \quad \text{Exponent } n = \text{number of times multiplied}$$
                $$\text{Example: } 2^5 = 2 \times 2 \times 2 \times 2 \times 2 = 32$$
            </div>
        </div>
    </section>

