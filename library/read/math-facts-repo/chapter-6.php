    <!-- ==========================================================================
         Section 6.3: Division of Fractions by Fractions
         ========================================================================== -->
    <section id="sec-6-3" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">&sect; 6.3</span>
            <h2 class="math-section-title">Division of Fractions by Fractions: Multiplicative Inverses</h2>
        </div>

        <div class="math-def-box">
            <div class="math-def-header">
                <span class="math-def-badge"><i class="fas fa-divide"></i> THEOREM 6.3.1</span>
                <span class="math-def-domain">Topic: Reciprocal Division Theorem</span>
            </div>
            <div class="math-def-body">
                $$\frac{a}{b} \div \frac{c}{d} = \frac{a}{b} \times \frac{d}{c} = \frac{a \cdot d}{b \cdot c} \quad (b, c, d \neq 0)$$
            </div>
        </div>

        <div class="math-example-box">
            <div class="math-ex-header">
                <span class="math-ex-badge"><i class="fas fa-pencil-alt"></i> EXEMPLUM 6.3</span>
                <span class="math-ex-title">Fraction Division in Context</span>
            </div>
            <div class="math-ex-body">
                <p class="math-ex-problem"><strong>Problem:</strong> A recipe calls for $\frac{3}{4}$ cup of flour. You only have a $\frac{1}{8}$ cup scoop. How many scoops are needed?</p>
                <div class="math-ex-solution">
                    <div class="math-sol-step"><strong>Step 1 (Formulate Equation):</strong> $\frac{3}{4} \div \frac{1}{8} = \square$.</div>
                    <div class="math-sol-step"><strong>Step 2 (Apply KCF):</strong> Keep $\frac{3}{4}$, Change $\div \to \times$, Flip $\frac{1}{8} \to \frac{8}{1}$.</div>
                    <div class="math-sol-step"><strong>Step 3 (Cross-Cancel &amp; Multiply):</strong> $\frac{3}{\cancel{4}^1} \times \frac{\cancel{8}^2}{1} = 3 \times 2 = 6$.</div>
                </div>
                <div class="math-ex-result">
                    <span><i class="fas fa-check-circle" style="color: #059669;"></i> <strong>Result:</strong> Exactly $\mathbf{6\text{ scoops}}$ are required.</span>
                    <span class="math-qed">&#9632; Q.E.D.</span>
                </div>
            </div>
        </div>
    </section>

