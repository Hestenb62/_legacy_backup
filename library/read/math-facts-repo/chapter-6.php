    <section id="sec-6-1" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">6.1</span>
            <h2 class="math-section-title">Ratios, Unit Rates &amp; Proportions</h2>
        </div>

        <div class="math-def-box">
            <div class="math-def-header">
                <span class="math-def-badge"><i class="fas fa-book"></i> Definition 6.1.1</span>
                <span class="math-def-domain">Proportional Reasoning</span>
            </div>
            <div class="math-def-body">
                A <strong>Ratio</strong> compares two quantities $a$ and $b$ using division ($b \neq 0$), written as:
                $$a : b \quad \text{or} \quad \frac{a}{b} \quad \text{or} \quad \text{"}a\text{ to }b\text{"}$$
                A <strong>Unit Rate</strong> is a ratio with a denominator of exactly $1$ unit:
                $$\text{Unit Rate} = \frac{\text{Quantity } A}{\text{Quantity } B} = \frac{\text{Miles}}{\text{Hour}} \quad \text{or} \quad \frac{\text{Price}}{\text{Ounce}}$$
            </div>
        </div>

        <div class="math-theorem-box">
            <div class="math-thm-header">
                <span class="math-thm-badge"><i class="fas fa-award"></i> Principle 6.1</span>
                <span class="math-thm-title">Cross-Product Property of Proportions</span>
            </div>
            <div class="math-thm-body">
                Two ratios form an equivalent proportion if and only if their cross products are equal:
                $$\frac{a}{b} = \frac{c}{d} \iff a \cdot d = b \cdot c$$
                $$\text{Example: } \frac{3}{5} = \frac{x}{20} \implies 5x = 3 \times 20 = 60 \implies x = 12$$
            </div>
        </div>
    </section>

