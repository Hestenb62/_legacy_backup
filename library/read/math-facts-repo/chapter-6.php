            <h2 class="math-section-title">Ratios, Rates &amp; Unit Rate Calculations</h2>
        </div>

        <div class="math-def-box">
            <div class="math-def-header">
                <span class="math-def-badge"><i class="fas fa-scroll"></i> DEFINITION 6.1.1</span>
                <span class="math-def-domain">Topic: Multiplicative Comparison</span>
            </div>
            <div class="math-def-body">
                <p><dfn class="math-term">Ratio</dfn> &mdash; A mathematical comparison of two quantities $a$ and $b$ ($b \neq 0$), expressed as $a : b$, $\frac{a}{b}$, or "$a$ to $b$".</p>
                <p><dfn class="math-term">Unit Rate</dfn> &mdash; A rate simplified so the denominator equals exactly $1$ unit:</p>
                $$\text{Unit Rate } r = \frac{\text{Quantity } A}{\text{Quantity } B} \implies \frac{\$18}{3 \text{ books}} = \$6.00 \text{ per book}$$
            </div>
        </div>

        <div class="math-howto-box">
            <div class="math-howto-header"><i class="fas fa-shopping-cart"></i> Student Guide: Solving Best Buy Unit Rates</div>
            <p><strong>Scenario:</strong> Brand A sells $16\text{ oz}$ of cereal for $\$3.20$. Brand B sells $24\text{ oz}$ for $\$4.32$. Which is the better buy?</p>
            <div class="math-howto-steps">
                <div class="math-step-item">
                    <span class="math-step-badge">BRAND A UNIT PRICE</span>
                    <div>$\frac{\$3.20}{16\text{ oz}} = \$0.20 \text{ per ounce}$.</div>
                </div>
                <div class="math-step-item">
                    <span class="math-step-badge">BRAND B UNIT PRICE</span>
                    <div>$\frac{\$4.32}{24\text{ oz}} = \$0.18 \text{ per ounce}$.</div>
                </div>
                <div class="math-step-item">
                    <span class="math-step-badge">COMPARE</span>
                    <div>Brand B costs $\$0.02$ less per ounce. Brand B is the superior buy!</div>
                </div>
            </div>
        </div>
    </section>

