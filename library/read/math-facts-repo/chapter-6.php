            <h2 class="math-section-title">2D Polygon Area &amp; 3D Surface Area Nets</h2>
        </div>

        <div class="math-formula-grid">
            <div class="math-formula-card">
                <div class="math-formula-title">Area of a Triangle</div>
                <div class="math-formula-latex">$$A = \frac{1}{2} b h = \frac{b \times h}{2}$$</div>
                <div class="math-formula-desc">Base $b$ and perpendicular height $h$.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-title">Area of a Parallelogram</div>
                <div class="math-formula-latex">$$A = b \times h$$</div>
                <div class="math-formula-desc">Base $b$ and vertical altitude $h$.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-title">Area of a Trapezoid</div>
                <div class="math-formula-latex">$$A = \frac{(b_1 + b_2) \cdot h}{2}$$</div>
                <div class="math-formula-desc">Average of parallel bases times height.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-title">Surface Area of a Rectangular Prism</div>
                <div class="math-formula-latex">$$SA = 2(lw + lh + wh)$$</div>
                <div class="math-formula-desc">Sum of areas of all 6 rectangular faces.</div>
            </div>
