        <div class="math-section-header">
            <span class="math-section-num">6.2</span>
            <h2 class="math-section-title">The Integer System ($\mathbb{Z}$) &amp; Absolute Value</h2>
        </div>

        <div class="math-formula-grid">
            <div class="math-formula-card">
                <div class="math-formula-title">Set of Integers ($\mathbb{Z}$)</div>
                <div class="math-formula-latex">$$\mathbb{Z} = \{\dots, -3, -2, -1, 0, 1, 2, 3, \dots\}$$</div>
                <div class="math-formula-desc">Includes positive whole numbers, zero, and negative opposites.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-title">Absolute Value ($|x|$)</div>
                <div class="math-formula-latex">$$|x| = \begin{cases} x & \text{if } x \geq 0 \\ -x & \text{if } x < 0 \end{cases}$$</div>
                <div class="math-formula-desc">Distance from zero on the number line. Always non-negative: $|-7| = 7$.</div>
            </div>
        </div>
    </section>

