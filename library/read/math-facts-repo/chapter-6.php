                <div class="math-const-sym"><i class="fas fa-crosshairs" style="color: #b45309;"></i> HACK I</div>
                <div class="math-const-name">Cross-Multiply Ratio Resolver</div>
                <div class="math-const-val">$$\frac{a}{b} = \frac{x}{d} \implies x = \frac{a \times d}{b}$$</div>
