    <section id="sec-3-6" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">&sect; 3.6</span>
            <h2 class="math-section-title">Geometric Mensuration: Area &amp; Perimeter</h2>
        </div>

        <div class="math-formula-grid">
            <div class="math-formula-card">
                <div class="math-formula-meta">MENSURATION FORMULA I</div>
                <div class="math-formula-title">Area of a Rectangle ($A$)</div>
                <div class="math-formula-latex">$$A = \text{length } (l) \times \text{width } (w)$$</div>
                <div class="math-formula-desc">Measures the 2D surface covered by square units ($\text{cm}^2, \text{m}^2, \text{sq ft}$).</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-meta">MENSURATION FORMULA II</div>
                <div class="math-formula-title">Perimeter of a Polygon ($P$)</div>
                <div class="math-formula-latex">$$P = 2l + 2w = 2(l + w)$$</div>
                <div class="math-formula-desc">Measures the continuous linear distance around the outer boundary ($\text{cm}, \text{m}, \text{ft}$).</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-meta">MENSURATION FORMULA III</div>
                <div class="math-formula-title">Square Mensuration</div>
                <div class="math-formula-latex">$$A = s^2 = s \times s \quad \vert \quad P = 4s$$</div>
                <div class="math-formula-desc">For a regular 4-sided polygon with side length $s$.</div>
            </div>
        </div>

        <div class="math-example-box">
            <div class="math-ex-header">
                <span class="math-ex-badge"><i class="fas fa-pencil-alt"></i> EXEMPLUM 3.6</span>
                <span class="math-ex-title">Distinguishing Area vs. Perimeter</span>
            </div>
            <div class="math-ex-body">
                <p class="math-ex-problem"><strong>Problem:</strong> A rectangular garden measures $6\text{ meters}$ long and $4\text{ meters}$ wide. Find both its area and its perimeter.</p>
                <div class="math-ex-solution">
                    <div class="math-sol-step"><strong>Step 1 (Calculate Area):</strong> $A = l \times w = 6\text{ m} \times 4\text{ m} = 24\text{ m}^2$ (Square Meters).</div>
                    <div class="math-sol-step"><strong>Step 2 (Calculate Perimeter):</strong> $P = 2(l + w) = 2(6 + 4) = 2(10) = 20\text{ meters}$ (Linear Meters).</div>
                </div>
                <div class="math-ex-result">
                    <span><i class="fas fa-check-circle" style="color: #059669;"></i> <strong>Result:</strong> Area $= \mathbf{24\text{ m}^2}$; Perimeter $= \mathbf{20\text{ m}}$.</span>
                    <span class="math-qed">&#9632; Q.E.D.</span>
                </div>
            </div>
        </div>
    </section>

