        <h3>3.3 Triangle Theorems</h3>
        <p><strong>Pythagorean Theorem:</strong> In a right triangle, \(a^2 + b^2 = c^2\) (where \(c\) is the hypotenuse).</p>
        <p><strong>Common Pythagorean Triples:</strong> (3,4,5), (5,12,13), (8,15,17), (7,24,25), (9,40,41), (6,8,10), (10,24,26)</p>
        <p><strong>Triangle Inequality:</strong> The sum of any two sides must exceed the third: \(a + b > c\)</p>
        <p><strong>Angle Sum:</strong> \(\alpha + \beta + \gamma = 180°\) for any triangle</p>
        <p><strong>Exterior Angle Theorem:</strong> An exterior angle equals the sum of the two non-adjacent interior angles.</p>
        <p><strong>Law of Sines:</strong> \[\dfrac{a}{\sin A} = \dfrac{b}{\sin B} = \dfrac{c}{\sin C} = 2R\]</p>
        <p><strong>Law of Cosines:</strong> \[c^2 = a^2 + b^2 - 2ab\cos C\]</p>
        <p><strong>Heron's Formula</strong> (area with sides \(a,b,c\)): \[A = \sqrt{s(s-a)(s-b)(s-c)}, \quad s = \dfrac{a+b+c}{2}\]</p>

        <h3>3.4 Circle Theorems</h3>
        <ul>
            <li>Inscribed angle = half the central angle subtending the same arc.</li>
            <li>Angle in a semicircle = 90°.</li>
            <li>Tangent to a circle is perpendicular to the radius at the point of tangency.</li>
            <li><strong>Power of a Point:</strong> If two chords intersect inside a circle: \(PA \cdot PB = PC \cdot PD\)</li>
        </ul>

        <h3>3.5 Trigonometric Ratios (SOH-CAH-TOA)</h3>
        <p>In a right triangle with hypotenuse \(c\), opposite side \(o\), adjacent side \(a\):</p>
        <p>\[\sin\theta = \frac{o}{c} \qquad \cos\theta = \frac{a}{c} \qquad \tan\theta = \frac{o}{a}\]</p>
        <p>\[\csc\theta = \frac{c}{o} \qquad \sec\theta = \frac{c}{a} \qquad \cot\theta = \frac{a}{o}\]</p>

