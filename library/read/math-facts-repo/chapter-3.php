        <div class="math-section-header">
            <span class="math-section-num">3.7</span>
            <h2 class="math-section-title">Grade 3 Mental Math Hacks &amp; Multiplication Shortcuts</h2>
        </div>

        <div class="math-constant-grid">
            <div class="math-constant-card">
                <div class="math-const-sym"><i class="fas fa-hand-paper" style="color: #f59e0b;"></i> Hack #1</div>
                <div class="math-const-name">9s Finger Magic &amp; Sum-to-9 Rule</div>
                <div class="math-const-val">$$9 \times 7 = 63 \implies 6 + 3 = 9$$</div>
                <div class="math-const-desc">For $9 \times n$: The tens digit is $(n - 1)$, and the ones digit is $9 - (n - 1)$. Put down your $n$-th finger to see the answer instantly!</div>
            </div>

            <div class="math-constant-card">
                <div class="math-const-sym"><i class="fas fa-clone" style="color: #6366f1;"></i> Hack #2</div>
                <div class="math-const-name">Double-Double Hack for &times;4 and &times;8</div>
                <div class="math-const-val">$$\times 4 \implies \text{Double, Double} \quad | \quad \times 8 \implies \text{Double, Double, Double}$$</div>
                <div class="math-const-desc">$7 \times 4 \implies 7 \times 2 = 14 \implies 14 \times 2 = 28$. $7 \times 8 \implies 28 \times 2 = 56$!</div>
            </div>

            <div class="math-constant-card">
                <div class="math-const-sym"><i class="fas fa-cut" style="color: #10b981;"></i> Hack #3</div>
                <div class="math-const-name">Multiplying by 5: Half and Add Zero</div>
                <div class="math-const-val">$$16 \times 5 = (16 \div 2) \times 10 = 8 \times 10 = 80$$</div>
                <div class="math-const-desc">For any even number times 5: Take half of the number, then append a $0$ at the end.</div>
            </div>

            <div class="math-constant-card">
                <div class="math-const-sym"><i class="fas fa-gem" style="color: #ec4899;"></i> Hack #4</div>
                <div class="math-const-name">The "Magic 56 = 7 &times; 8" Mnemonic</div>
                <div class="math-const-val">$$\mathbf{5, \ 6, \ 7, \ 8} \implies 56 = 7 \times 8$$</div>
                <div class="math-const-desc">Say the sequence in order: 5, 6, 7, 8. It immediately gives the most commonly missed math fact: $56 = 7 \times 8$.</div>
            </div>
        </div>
