         Section 3.3: Division & Fact Families
         ========================================================================== -->
    <section id="sec-3-3" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">&sect; 3.3</span>
            <h2 class="math-section-title">Division as Equal Sharing &amp; Inverse Fact Families</h2>
        </div>

        <div class="math-def-box">
            <div class="math-def-header">
                <span class="math-def-badge"><i class="fas fa-divide"></i> PRINCIPLE 3.3.1</span>
                <span class="math-def-domain">Topic: The Inverse Relationship</span>
            </div>
            <div class="math-def-body">
                <p><dfn class="math-term">Division</dfn> &mdash; Determines how many equal groups can be created, or the size of each share:</p>
                $$\text{Dividend } (A) \div \text{Divisor } (B) = \text{Quotient } (Q) \iff Q \times B = A \quad (B \neq 0)$$
                $$\text{Fact Family for } \{7, 8, 56\}: \quad 7 \times 8 = 56, \quad 8 \times 7 = 56, \quad 56 \div 7 = 8, \quad 56 \div 8 = 7$$
            </div>
        </div>

        <div class="math-caution-box">
            <div class="math-caution-header">
                <span class="math-caution-badge"><i class="fas fa-ban"></i> MATHEMATICAL FORBIDDEN OPERATION</span>
                <span class="math-caution-title">Division by Zero is Strictly Undefined</span>
            </div>
            <div class="math-caution-body">
                You can divide zero by any non-zero number ($0 \div 7 = 0$), but <strong>you can never divide by zero</strong>!
                $$\frac{8}{0} = \text{Undefined} \quad (\text{No number } Q \text{ satisfies } Q \times 0 = 8)$$
            </div>
        </div>
    </section>

