        <div class="math-section-header">
            <span class="math-section-num">3.3</span>
            <h2 class="math-section-title">Division as Equal Sharing &amp; Inverse Relation</h2>
        </div>

        <div class="math-def-box">
            <div class="math-def-header">
                <span class="math-def-badge"><i class="fas fa-divide"></i> Principle 3.3.1</span>
                <span class="math-def-domain">Division Architecture</span>
            </div>
            <div class="math-def-body">
                Division answers: <em>"How many groups of size $b$ fit inside total $a$?"</em>
                $$\text{Dividend } a \div \text{Divisor } b = \text{Quotient } q \iff q \times b = a$$
                $$\text{Example: } 48 \div 6 = 8 \iff 8 \times 6 = 48$$
            </div>
        </div>
    </section>

