         Section 3.2: Multiplication Properties
         ========================================================================== -->
    <section id="sec-3-2" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">&sect; 3.2</span>
            <h2 class="math-section-title">The Three Golden Properties of Multiplication</h2>
        </div>

        <div class="math-formula-grid">
            <div class="math-formula-card">
                <div class="math-formula-meta">ALGEBRAIC LAW I</div>
                <div class="math-formula-title">Commutative Property</div>
                <div class="math-formula-latex">$$a \times b = b \times a$$</div>
                <div class="math-formula-desc">The order of factors never alters the product. $7 \times 8 = 8 \times 7 = 56$.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-meta">ALGEBRAIC LAW II</div>
                <div class="math-formula-title">Associative Property</div>
                <div class="math-formula-latex">$$(a \times b) \times c = a \times (b \times c)$$</div>
                <div class="math-formula-desc">Grouping factors differently does not change the result: $(2 \times 3) \times 4 = 6 \times 4 = 24$.</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-meta">ALGEBRAIC LAW III</div>
                <div class="math-formula-title">Distributive Property</div>
                <div class="math-formula-latex">$$a \times (b + c) = (a \times b) + (a \times c)$$</div>
                <div class="math-formula-desc">Decompose difficult factors into friendly components: $7 \times 13 = 7(10 + 3) = 70 + 21 = 91$.</div>
            </div>
        </div>

        <div class="math-example-box">
            <div class="math-ex-header">
                <span class="math-ex-badge"><i class="fas fa-pencil-alt"></i> EXEMPLUM 3.2</span>
                <span class="math-ex-title">Decomposition Using the Distributive Property</span>
            </div>
            <div class="math-ex-body">
                <p class="math-ex-problem"><strong>Problem:</strong> Calculate $8 \times 14$ mentally using the distributive property.</p>
                <div class="math-ex-solution">
                    <div class="math-sol-step"><strong>Step 1 (Decompose 14):</strong> $14 = 10 + 4$.</div>
                    <div class="math-sol-step"><strong>Step 2 (Distribute 8):</strong> $8 \times (10 + 4) = (8 \times 10) + (8 \times 4)$.</div>
                    <div class="math-sol-step"><strong>Step 3 (Evaluate Partial Products):</strong> $80 + 32 = 112$.</div>
                </div>
                <div class="math-ex-result">
                    <span><i class="fas fa-check-circle" style="color: #059669;"></i> <strong>Result:</strong> $8 \times 14 = \mathbf{112}$.</span>
                    <span class="math-qed">&#9632; Q.E.D.</span>
                </div>
            </div>
        </div>
    </section>

