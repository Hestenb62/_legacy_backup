            <span class="math-section-num">3.6</span>
            <h2 class="math-section-title">Area &amp; Perimeter Geometric Formulas</h2>
        </div>

        <div class="math-formula-grid">
            <div class="math-formula-card">
                <div class="math-formula-title">Area of a Rectangle ($A$)</div>
                <div class="math-formula-latex">$$A = \text{length} \times \text{width} = l \times w$$</div>
                <div class="math-formula-desc">Measured in square units ($\text{sq units}, \text{cm}^2, \text{in}^2$).</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-title">Perimeter of a Rectangle ($P$)</div>
                <div class="math-formula-latex">$$P = 2l + 2w = 2(l + w)$$</div>
                <div class="math-formula-desc">Total distance around the outer boundary (linear units).</div>
            </div>

            <div class="math-formula-card">
                <div class="math-formula-title">Area of a Square</div>
                <div class="math-formula-latex">$$A = s^2 = s \times s \quad \text{and} \quad P = 4s$$</div>
                <div class="math-formula-desc">Where $s$ is the side length.</div>
            </div>
        </div>
    </section>

