        <h3>3.8 Coordinate Geometry Essentials</h3>
        <p><strong>Distance:</strong> \(d = \sqrt{(x_2-x_1)^2+(y_2-y_1)^2}\)</p>
        <p><strong>Midpoint:</strong> \(\left(\dfrac{x_1+x_2}{2},\; \dfrac{y_1+y_2}{2}\right)\)</p>
        <p><strong>Circle (center \((h,k)\), radius \(r\)):</strong> \((x-h)^2 + (y-k)^2 = r^2\)</p>
        <p><strong>Parabola (vertical):</strong> \(y = a(x-h)^2 + k\) &nbsp;&nbsp; vertex at \((h,k)\), focus at \(\left(h, k+\dfrac{1}{4a}\right)\)</p>
        <p><strong>Ellipse:</strong> \(\dfrac{(x-h)^2}{a^2} + \dfrac{(y-k)^2}{b^2} = 1\)</p>
        <p><strong>Hyperbola:</strong> \(\dfrac{(x-h)^2}{a^2} - \dfrac{(y-k)^2}{b^2} = 1\)</p>
