    <section id="sec-3-5" class="math-section">
        <div class="math-section-header">
            <span class="math-section-num">3.5</span>
            <h2 class="math-section-title">Equivalent Fractions &amp; Fraction Comparison</h2>
        </div>

        <div class="math-theorem-box">
            <div class="math-thm-header">
                <span class="math-thm-badge"><i class="fas fa-check-circle"></i> Theorem 3.5</span>
                <span class="math-thm-title">Equivalent Fraction Multiplier Rule</span>
            </div>
            <div class="math-thm-body">
                Multiplying or dividing both numerator and denominator by the same non-zero integer $k$ yields an identical fractional value:
                $$\frac{a}{b} = \frac{a \times k}{b \times k} \implies \frac{1}{2} = \frac{1 \times 2}{2 \times 2} = \frac{2}{4} = \frac{3}{6} = \frac{4}{8}$$
            </div>
        </div>
    </section>

