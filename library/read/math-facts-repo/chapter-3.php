        </div>

        <div class="math-def-box">
            <div class="math-def-header">
                <span class="math-def-badge"><i class="fas fa-percentage"></i> Definition 3.4.1</span>
                <span class="math-def-domain">Rational Fraction Structure</span>
            </div>
            <div class="math-def-body">
                A fraction $\frac{a}{b}$ denotes $a$ equal copies of the unit fraction $\frac{1}{b}$:
                $$\text{Fraction } \frac{a}{b} = \frac{\text{Numerator (Parts selected)}}{\text{Denominator (Total equal parts in 1 whole)}} \quad (b \neq 0)$$
            </div>
        </div>
    </section>

