<p>Between the Chin and Mount Mansfield Hotel are a number of
interesting trails. The Subway and Canyon trail on the west side of the
mountain follow, for part of the way, joints in the rock which have been
enlarged by the downhill slippage of the western block. <a href="#fig11" class="pginternal">Figure 11</a> shows
the nature of one of these passageways. On the east side of the mountain,
the Cliff trail passes through a similar joint called “Wall Street.” The
Cave of the Winds, reached by a trail just north of the Lower Lip, has
formed along another north-south joint. The block which has moved
downhill has tilted into the mountain and rubble has filled the gap at the
top to form the cave. <a href="#fig12" class="pginternal">Figure 12</a> shows the appearance of the cave as seen
from the eastern slope of the Chin. This photograph shows smaller joints
on the Chin which have just begun to be enlarged by slippage of the
downhill block. It is possible that some of these open joints date back and
partially owe their origin to glacial erosive action.</p>
<p>Drift Rock which is located along the Long Trail south of the Upper
<span class="pb" id="Page_26">26</span>
Lip has already been described as an erratic boulder moved by the glacier.
The glacial striae may be seen in the bedrock northwest of the boulders.
Garnet crystals are very abundant in these boulders and specimens of the
small red garnets may be obtained here.</p>
<p>The Nose is easily reached along the trail from Mount Mansfield
Hotel. From the summit the view is excellent to the south towards
Camels Hump, which is one of the prominent peaks of the Green Mountain
range. The mica-albite-quartz schist on top of the Nose has many
small folds and crenulations.</p>
<p>South of the Forehead along the Long Trail, cliffs of an albite-rich
variety of the mica-albite-quartz schist form obstacles which have been
surmounted cleverly by the Green Mountain trail-markers.</p>
<p>In the southern part of Mount Mansfield State Forest the Long Trail
passes through Nebraska Notch in the vicinity of Taylor Lodge. This
notch also was formed by the erosive action of an ancient river that
flowed across the mountain at this point, but which has long since been
abandoned.</p>
