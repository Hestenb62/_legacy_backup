<p>The Long Trail passes by Sterling Pond, where the Green Mountain
Club has erected a small cabin overlooking the pond. <a href="#fig9" class="pginternal">Figure 9</a> is the
picturesque view of Mount Mansfield taken from the cabin.</p>
<h3 id="c13"> <i>Smugglers Notch</i></h3>
<p>All of the rocks exposed at Smugglers Notch (<a href="#fig10" class="pginternal">Figure 10</a>) are the mica-albite-quartz
schist which locally contains garnet. The large rock
boulders in the Notch were derived from the cliffs forming the walls of
the Notch. The gradual processes of weathering and breaking up by
freezing cause large slabs of the rock to become loose and eventually
break off the cliff faces to careen down the mountainside to the valley
below, just as King Rock did within historical time. At the north end of
the Notch, the large accumulations of such boulders form a <i>talus slope</i>,
the name for rock accumulations at the base of a cliff. The irregular
stacking of these rocks have formed Smugglers Cave. Smaller openings
extend further back under the “rock pile” to where the ground is considerably
colder and where the heavier cold air has sunk. Drafts of this
air escaping at the foot of the talus is noticeably cool.</p>
<p>The Smuggler’s Face, Elephants Head, the Singing Bird, and the
Hunter and His Dog are freaks of nature and a product of man’s imagination.
Their existence is due to the haphazard nature in which the
rocks on the cliff faces have broken along joint surfaces.</p>
<p>The origin of the Notch is not completely known. The steep walls
and the narrowness of the Notch suggest that it could not have been
formed by the headward erosion of two streams or by glacial action. It
seems most likely that it was formed by the erosive action of an ancient
river that once flowed through the area. Because of the high elevation,
the only time when such a river could have existed is when the Champlain
Valley was filled with ice on the west side of Mount Mansfield, so that
the normal drainage of water to the west was blocked by the ice. It is
possible that the conditions were such that the water supplied by the
melting glacier could only drain to the south through the Notch. After
the ice retreated the drainage system was abandoned in favor of lower
outlets and eventually the drainage was developed to Lake Champlain
in the west. The Notch was modified by the headward erosion of the
present small streams. Except for the shape of the Notch, the only
evidence for this hypothesis is the occurrence of a weakly-bedded, well-sorted
deposit of sand at the north end of the Notch at an elevation of
2050 feet. Such a deposit of sand is characteristic of standing water,
which occurring at this elevation indicates that some vastly different
drainage system must have existed in the past.</p>
