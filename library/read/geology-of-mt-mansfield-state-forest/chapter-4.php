<h3 id="c14"> <i>Big Spring</i></h3>
<p>On the south side of the Smugglers Notch road at an elevation of
about 1800 feet is the Big Spring which furnishes a tremendous output of
cold spring water. The source of the water is not known although it is
likely that, like most springs, it is derived from an underground drainage
system. The spring probably originates by the seepage of water derived
from the winter snows and rainfall in Spruce Mountain through a joint
system within the mountain. No buried stream channels could be located
between the spring and the base of the massive overhead cliffs. The
belief that the spring is related to Sterling Pond is unfounded. It is
unlikely that surplus water could be drained from Sterling Pond because
it already maintains a delicate balance between the supply of water from
rain and snow and the output to the stream flowing to the north.</p>
<h3 id="c15"> <i>Mount Mansfield</i></h3>
<p>The summit of Mount Mansfield when viewed from a distance has the
resemblance of a face with an exaggerated distance between the nose and
upper lips. Accordingly, these peaks are named, from south to north, the
Forehead, Nose, Upper Lip, Lower Lip, Chin, and Adam’s Apple. All
these points are readily accessible by the Long Trail and the area of the
Nose may be reached by the Toll Road or the Ski Lift. From all the points
along the crest an excellent view may be obtained. On clear days Lake
Champlain and the Adirondack Mountains in New York State may be
seen to the west, and Mount Washington in New Hampshire may be
seen to the east.</p>
<p>Of the local structures, good exposures of the mica-albite-quartz
schist occur along the crest with magnetite and garnet locally abundant.
The rocks on Sunset Ridge, which extends west from the Chin, can be
seen clearly to be dipping at gentle angles to the west.</p>
<p>The Chin has an elevation of 4393 feet, which is the highest point in
Vermont. Most of the schist in this area is nearly horizontal or dipping
slightly to the west. However, minor folds are present everywhere and
<span class="pb" id="Page_24">24</span>
an average reading is difficult to obtain. At the summit much of the schist
contains large black grains of magnetite. The summit is reached by the
Long Trail along the crest of the mountain from the Toll Road, by the
Long Trail from Barnes Camp via Taft Lodge, or from the west by the
trail up Sunset Ridge. An excellent view of the Lake of the Clouds and
the Adam’s Apple is obtained a short distance north of the summit of
the Chin.</p>
