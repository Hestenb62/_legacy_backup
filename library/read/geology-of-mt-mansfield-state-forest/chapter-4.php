<p>Lake of the Clouds which lies north of the Adam’s Apple and Bear
Pond which lies north of Bear Head Mountain are both small shallow
<span class="pb" id="Page_25">25</span>
bodies of water. The slight depressions in which they occur were probably
scooped out by the erosive action of the glacier.</p>
