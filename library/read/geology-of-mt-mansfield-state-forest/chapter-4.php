<h2 id="c11"> <span class="small">DESCRIPTIONS OF INDIVIDUAL LOCALITIES</span></h2>
<h3 id="c12"> <i>Spruce Peak and Sterling Pond</i></h3>
<p>Spruce Peak is the mountain on the east side of Smugglers Notch. It
may be reached by several trails or the ski lift. An excellent view of
Smugglers Notch and the surrounding country is obtained from the
summit. Near the summit along the access road to the ski lift, unweathered
mica-albite-quartz schist is exposed and the folding can be
clearly seen.</p>
<p>Sterling Pond lies to the northeast of Spruce Peak in a shallow depression
along the divide of the mountain. This location is anomalous for a
pond because the amount of higher land around it is so small that only a
limited amount of drainage area is available for the accumulation of rain
and snow. Yet, the outflow of water is almost continuous during the
summer. The basin occupied by the pond was probably scoured out by
the glacier.</p>
<p>The Sterling Pond area contains talc deposits which probably would
be commercial if they were not so inaccessible for mining. These deposits
have been studied by A. H. Chidester of the United States Geological
Survey and a report is obtainable from the U. S. Government. The
occurrence of the talc, as mapped by Chidester, is shown in the sketch of
<a href="#fig8" class="pginternal">Figure 8</a>.</p>
<p>Talc has the composition of Mg₃Si₄O₁₀(OH)₂ and is a soft flaky white
mineral. The talc-bearing rocks in this area are white, light gray, or light
green and usually are irregularly stained yellow-brown by the weathering
of an iron-bearing mineral that occurs with the talc. Because of its
extremely soft nature, the talc does not form prominent rock exposures.
As shown by the figure, the talc can be most easily observed along the
shore of Sterling Pond, south of the Green Mountain Club cabin, or along
the trail to Smugglers Notch near the top of the first rise from the pond.
Here the talc is exposed in the trail as low, rounded, slippery knobs of
“messy looking” yellow-brown rock.</p>
<p>As part of the pond is underlain by talc, it is probable that the softness
of the talc was a factor in the differential erosion of the basin by the
continental glacier.</p>
<p>The talc is believed to have originated by the alteration of a body of
<i>ultramafic</i> igneous rock, which is characterized by having a low silica
content and a high magnesium content. Sometime during the mountain-building
period, the ultramafic igneous rock invaded the pre-existing
rocks from an unknown source within the earth’s crust. It is believed that
at a later date the original minerals in the igneous rock were altered to
talc and other minerals by the action of hot ascending solutions composed
principally of water.</p>
