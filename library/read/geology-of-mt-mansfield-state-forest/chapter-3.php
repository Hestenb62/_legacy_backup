<h2 id="c8"> <span class="small">GLACIAL HISTORY OF THE AREA</span></h2>
<h3 id="c9"> <i>Introduction</i></h3>
<p>The geologic time division previous to the present one is called the
Pleistocene or the “ice age.” During this time, large continental glaciers
advanced over the northern part of North America several times. The
cause of the ice age is not known with certainty and whether geologic
history will repeat itself is a matter of conjecture. However, it is established
that these vast ice sheets covered New England and that the last
ice sheet melted back from the Mansfield area about 12,000 years ago.</p>
<p>If one stands on the crest of Mount Mansfield and looks westward over
the Champlain Valley, it is difficult to visualize this entire valley completely
filled with ice of the continental glacier. Yet, the evidence shows
that the ice sheet was so thick that it completely covered Mount Mansfield
at one time.</p>
<h3 id="c10"> <i>Evidences of glaciation</i></h3>
<p>Two types of evidence, glacial striae and erratics, show that Mount
Mansfield was over-ridden by the continental glaciation. <i>Striae</i> are
<span class="pb" id="Page_17">17</span>
scratches in the bedrock which were produced by the sharp edges of
rocks protruding from the sole of the moving glacier. These scratches
show the direction in which the glacier was moving at a particular spot
and the average of many readings gives an accurate value as to the overall
direction of movement of the ice sheet. On the Long Trail between the
Mount Mansfield Hotel and the Chin on Mount Mansfield, striations
may be observed at a number of places. Some of the positions where readings
were made are indicated on the map by the triangular-pointed
arrows. Faint striae may be seen near the entrance of the Mount Mansfield
Hotel and more conspicuous ones are visible on the west side of the
roadbed of the secondary road that intersects the Toll Road just below
the Hotel. <a href="#fig7" class="pginternal">Figure 7</a> shows a photograph taken at Drift Rock in which the
striae are clearly visible.</p>
<p>The average trend of the striae on Mount Mansfield is about N. 50°
W. The movement of the ice is presumed to have been nearly north-south
down the Champlain Valley which was deepened by the erosive action
of the ice. These facts seem to suggest that the movement of ice over
Mount Mansfield was marginal and nearly 45° to the axis of the main
ice tongue.</p>
<p><i>Erratics</i> are boulders moved and deposited by glaciers. Often these
boulders are found in environments foreign to them. On the high parts of
Mount Mansfield, a few boulders other than the mica-albite-quartz
schist are found which have reached their present position by glacial
transportation. A particularly interesting erratic is Drift Rock. One may
note by referring again to <a href="#fig7" class="pginternal">Figure 7</a> that the glacial striae pass beneath the
large boulders indicating that the boulders were not at their present
position when the striae were formed. Thus, these boulders are aptly
named for they must be considered erratics even though their composition
is the same as the surrounding rocks. As a logical speculation
it is probable that they were plucked out of the bedrock just a short
distance to the northwest of their present position and it is possible that
these were the very boulders that formed the striae.</p>
<p>Other evidence of glaciation is the presence of <i>cirques</i> which are the
high mountain basins in which mountain glaciers originate. Small
mountain glaciers probably existed on Mount Mansfield, particularly
in the east side of the mountain where the topography has the suggestive
form of cirque-like walls and basins.</p>
<p>Melting of a continental glacier causes deposition of the sand and
gravel scooped up and transported by the glacier. Some of this material
<span class="pb" id="Page_18">18</span>
is plastered beneath the moving glacier, some is simply let down as a
blanket and terminal accumulations, and some is transported by streams
of melt water to form deposits in which the sands and gravels are somewhat
sorted in size by the action of the water.</p>
