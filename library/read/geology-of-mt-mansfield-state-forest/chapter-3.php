<p>The blanket type of glacial deposits probably were present over much
of the Mount Mansfield area at one time, but have been removed from
the upper mountain slopes by erosion. Such deposits are present at lower
elevations but are only rarely discernible because of the heavy vegetation
and soil cover. Sand and gravel deposits derived from post-glacial streams
are located in some of the lower valleys as, for instance, along the highway
north of Barnes Camp.</p>
<p>North of the old road and northeast of the camping area along one of
the main streams on the west side of Mount Mansfield, fine-grained,
sandy lake deposits occur at an elevation of about 1900 feet. The nature
of the deposits indicates that they were formed in ponds marginal to the
ice sheet when the continental glacier occupied the Champlain Valley but
did not extend over the crest of Mount Mansfield.</p>
