<h2 id="c1"> <span class="small">INTRODUCTION</span></h2>
<p>Included within Mount Mansfield State Forest are Mount Mansfield,
Smugglers Notch and a number of the mountains of the Green Mountain
range to the northeast and southwest of these famous landmarks. Because
much of the area is easily accessible by trails, ski lifts, and roads
(see the index map of <a href="#fig1" class="pginternal">Figure 1</a>), the visitor has ample opportunity to
observe the minerals, rocks, and mountains. Undoubtedly, these observations
have provoked questions which, for lack of sufficient information,
have gone unanswered in the mind of the observer. In the hopes of
remedying this situation—a very grievous situation in the eyes of a
geologist—this brief geologic pamphlet has been written to help the
visitor to the State Forest obtain a greater appreciation of the handiwork
of nature.</p>
<p>To begin with, <i>geology</i> can be defined as the study of the history of the
earth as recorded in the rocks. It includes the study of minerals, rocks,
fossils, the structure of the rocks, and the forms of the land. Although
only a few have been fortunate enough to choose this subject as a profession,
the field is wide open for amateurs.</p>
<p>This report is divided into four sections. The first describes the rocks;
the second deals with the detailed structure of the rocks and the mountains;
the third treats the glacial history of the area; and the fourth part
describes the geology that may be seen at various localities within the
park.</p>
