<h2 id="c2"> <span class="small">DESCRIPTION OF THE ROCKS</span></h2>
<h3 id="c3"> <i>Introduction</i></h3>
<p>With a few exceptions, the rock found in Mount Mansfield State Forest
is a mica-albite-quartz schist. This name indicates that it is a metamorphic
<span class="pb" id="Page_4">4</span>
rock<a class="fn pginternal" href="#fn_1" id="fr_1">[1]</a> of a particular composition and texture as described in
the following paragraphs. The schist forms the cliffs at Smugglers Notch
and the bare-rock faces exposed along the crests of the mountains and
elsewhere. It varies slightly in appearance because of variation in the
proportions of the different mineral constituents.</p>
