<p>Other varieties of the schist occur less abundantly in the area. These
contain the same minerals as the mica-albite-quartz schist but in different
proportions. If the mica is most abundant, as it is locally on Mount
Mansfield, the schist may be smooth or highly crinkled and have a very
shiny appearance. If the albite is most abundant the schist is more
uniform and granular in appearance and the rocks are more massive.
Small scale folding is usually absent. Such albite schists occur on the
west side of Mount Mansfield, particularly along the lower part of the
Maple Ridge Trail and in the cliffs south of the Forehead along the Long
Trail.</p>
<p>If the quartz is most abundant, but mica and albite are present in
considerable quantities, the rock may have a granular, layered appearance.
Locally some of the rocks consist almost entirely of quartz and are
classified as quartzite. These rocks have a dense, fine-grained, sugary
appearance and generally are gray to bluish gray in color. They are hard
rocks and often form minor ledges in cliff exposures or are the resistant
<span class="pb" id="Page_10">10</span>
rock at the top of small waterfalls in some of the creeks. Most of the
quartzite in the area occurs in narrow layers less than a foot thick.
Although these layers cannot be traced, they are most abundant on the
east side of Mount Mansfield at various localities about one-third of the
way up the mountain.</p>
<p>At places, vein-like masses of glassy, milky white quartz occur in the
schist. In these, the quartz is massive and without evidence of individual
grains and is often fractured unevenly. The quartz occurs as localized
lenses in the schist, particularly at the noses of the folds. The small,
white boulders of quartz of this type are conspicuous along some of the
trails.</p>
<p>A special and somewhat unique type of rock occurring at Sterling Pond
is described in the description of Spruce Peak and Sterling Pond.</p>
<h3 id="c7"> <i>Structure of the mountain and the rocks</i></h3>
<p>The position of the Green Mountains is a function of the structure of
the rocks and their resistance to erosion. At the same time that the mica-albite-quartz
schist was being developed under conditions of heat and
pressure the region was tightly folded by the same forces. It is likely
that this folding continued after the metamorphism during the declining
stages of mountain-making. This period of mountain-building probably
raised the rocks to a higher level but it was the later repeated uplifts and
erosion of the overlying rocks which finally produced the present mountain
topography.</p>
<p>It is postulated that the folding and crumpling of the schists were
accompanied by a westward movement of large masses of rock. That is,
segments of the earth’s crust are believed to have been pushed westward
by pressure from the east. Thus, it is believed by many geologists that
the rock which now occurs in the Green Mountains may have been
derived in early times from an area ten to forty miles to the east.</p>
<p>The basic structure of the Green Mountains is an anticlinorium, a
large complex fold. An <i>anticline</i> is an upward fold in which individual
rock layers if traced through the <i>structure</i> have a shape similar to that
of an arch; the opposite structure is a syncline in which the individual
layers are shaped like a trough or basin. An <i>anticlinorium</i> is a large
anticline upon which are superimposed many smaller anticlines and synclines.
<a href="#fig3" class="pginternal">Figure 3</a> is a diagrammatic sketch showing the relation of the
topography to the structure of the rocks in the Mount Mansfield area.
The structure of the rocks is reflected in the topography of Mount
Mansfield, but such correspondence is not necessary, for the form of any
hill or mountain is a function of its erosional history and resistance of
the rock to erosion. In some folded areas, the rock in the trough of a
syncline is so resistant to erosion, that it persists in hills or mountains
after neighboring anticlines have been more deeply eroded to form
valleys.</p>
