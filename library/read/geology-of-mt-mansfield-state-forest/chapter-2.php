<p>Another structural feature of the schists is the breakage of the rocks
along definite plane surfaces called <i>joints</i>. These usually occur in systems
formed by a number of parallel joints. The joints formed as a result of
stress and strain operating on the rocks during periods of mountain-making
and vertical uplifts. Information as to the nature of these forces
might be obtained if all the joints were carefully recorded and plotted on
a map.</p>
<p>On Mount Mansfield some of the prominent topographic features
appear to be controlled by joints. Much of the north-facing cliff on the
Nose is controlled by a joint trending N. 65° W., and a similar face on the
Lower Lip is controlled by a joint trending N. 60° W. Along the crest of
Mount Mansfield a number of joints trend about north-south. Joints of
this system in the steep cliffs on either side of the crest of Mount Mansfield
have been separated further by the tendency of the rocks to creep
down slope under the force of gravity. These joints form the canyons or
narrow passageways which are traversed by some of the trails. On Maple
Ridge at about 3300 foot elevation the trail crosses a joint trending
N. 50° E. which is conspicuous for its four-foot width and the extent and
the straightness of the break. A number of joints belonging to this system
are found along Maple Ridge.</p>
