<p>The smaller folds are like “little fleas on bigger fleas on bigger fleas”
in that many little folds may be superimposed on larger ones. These
anticlines and synclines range in amplitude from fractions of an inch to
thousands of feet. Many are miniature anticlinoria themselves and could
be used as scale models of the structure of the entire mountain range.
The small folds, or crenulations, in the schist have weathered differentially
so that the more resistant layers stand out in relief, emphasizing the
shape of the folds. The photograph in <a href="#fig4" class="pginternal">Figure 4</a> shows the small-scale
folding. It will be noted that the anticlinal folds are asymmetrical with
the west side dipping more steeply than the east side.</p>
<p>If a comparison is made between the structure of the mountain and
that of an asymmetrical arch, to carry the simile one step further, it
may be imagined that the axis of the arch may be either horizontal or
inclined. The chances that it is inclined are much greater than the
chance that it is exactly horizontal. Thus, most anticlines or anticlinoria
are inclined along their axes and the amount of the dip of the
line connecting the points along the crest of the fold is called the <i>plunge</i>.</p>
<p>Most of the folds in the Mount Mansfield area plunge about ten
degrees to the south. This plunge is expressed in the dip of the crests of
the minor folds, particularly in the crenulation of the mica layers.
Viewed at a distance the trace of the fold-crests form a series of parallel
lines on the smooth mica-rich surfaces. This type of structure is called
the <i>lineation</i> and is expressed on the geologic map by small arrows. The
dominant lineation is north-south. Although <a href="#fig5" class="pginternal">Figure 5</a> is a sketch of a
small fold showing the different structural elements, it might be taken as
a diagrammatic sketch of the regional structure.</p>
<p>Evidence that the structure of the rocks is even more complex is shown
locally by the presence of east-west lineations. The intersection of this
secondary lineation with the dominant south lineation produces a
checker board appearance on some rock surfaces. A system of east-west
trending folds is traced by some of the quartz lenses. The significance
of the east-west structures is hypothetical, but they are believed to
have been mostly obscured by the younger structural features.</p>
