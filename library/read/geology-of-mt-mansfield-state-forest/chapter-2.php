<p>The dip and strike are used to measure the position and attitude of
the layers of the rocks. In the case of the mica-albite-quartz schists these
planes are called <i>foliation</i> planes. If the structure of the rock is an anticline,
most of the strikes of the foliation are parallel, but the dips are in
different directions on either side of the crest. At the crest of the fold the
foliation is horizontal if the fold is not plunging. On Mount Mansfield
where the plunge is about ten degrees to the south, foliation along the
crest strikes about east-west and dips about 10° south. Away from the
crest, the dip of the sides of the anticline begin to be expressed in the
readings so that the strike directions “swing back” toward the north-south
direction. The majority of the layers on the east side of the mountain
strike northeast and dip to the east with the angle of dip increasing
away from the crest of the anticlinorium. On the west side of the mountain
they trend to the northwest and dip to the west with the dips becoming
steeper away from the crest. In addition to these variations in the dip
and strike over the anticlinal crest, the smaller folds give local abnormal
readings. For these reasons many of the dips and strikes shown on the
geologic map represent the averages of a number of readings, and those
of the minor folds and crinkles have been omitted in order to simplify
the picture.</p>
