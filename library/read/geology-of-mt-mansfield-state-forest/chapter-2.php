<p>With the description of the rocks completed, the question which arises
next is how to represent these three-dimensional contortions on the map.
<a href="#fig6" class="pginternal">Figure 6</a> illustrates how the attitude of a particular layer may be expressed
in terms of dip and strike. It is apparent that the <i>dip</i> of the rock
layer may vary from 0° to 90° and is measured as the angle between its
plane and a horizontal plane. Also, it is apparent that the trend of the
bed, or the <i>strike</i>, may correspond to any direction of the compass and
can be measured as the intersection of that plane and a horizontal plane.
The maximum dip is always at right angles to the direction of the strike.</p>
