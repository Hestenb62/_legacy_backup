<h3 id="c4"> <i>Origin of the schist</i></h3>
<p>An understanding of the origin of the schist is fundamental to understanding
the geology of the Mount Mansfield area. Many million years
before the formation of the Green Mountains, northwestern Vermont
was covered by a shallow sea into which fine-grained sediments were
transported by the ancient rivers. As these sandy and shaly deposits
accumulated on the bottom of the sea, they were buried by progressively
younger sediments of different types. Many of these sedimentary layers
<span class="pb" id="Page_5">5</span>
contained shells of the animals that lived and died in these seas, with the
shell remains of the older generations occurring in the bottom layers.
By the time the sea had retreated, the older sediments were deeply buried
beneath the younger sediments. During a period of mountain-making,
these materials were subjected to high pressures and high temperatures.
Physical-chemical changes took place within the sediments causing
recrystallization to form the mica-albite-quartz schist. In other words,
under conditions of heat and pressure the rocks became plastic and the
elements which were dispersed through the sediments as sand and clay
minerals reorganized into different and larger mineral grains. It is probable
that some material was added to the rocks and some was removed
by hot solutions migrating through the rocks. The overlying younger
sediments were also converted to metamorphic rocks. Because the
crystallization of the minerals occurred under the influence of pressure,
platy minerals developed with their long dimensions at right angles to
the pressure. Thus, the resulting rock developed a layered appearance
by the parallel arrangement of the minerals. Where this layering or banding,
which is called <i>foliation</i>, is coarse, the metamorphic rock is a <i>gneiss</i>;
where it is fine but pronounced, the rock is called a <i>schist</i>. If the original
rock was a limestone or sandstone, the metamorphic product is marble
or quartzite, respectively. In the process of, or following the formation
of the schists, the rocks were crumpled and folded by continued pressure.</p>
<p>During the 380 million years following the metamorphism and folding,
this area has been above sea level and has been subjected to erosion. At
various times the area was uplifted vertically which resulted in continued
erosion of progressively older rocks until the present day when the
overlying rocks have been removed to expose the mica-albite-quartz
schist.</p>
<h3 id="c5"> <i>Age of the mica-albite-quartz schist</i></h3>
<p>Some readers may wonder how the age of metamorphism can be stated
so specifically—380 million years seems like a long period to be determined
beyond a guess. Such a determination is based on a number of
different factors. Sedimentary rocks can be placed in their general age
sequence by their physical relationships—the rocks deposited on top
must be the youngest. A study of the fossils of successive layers shows
that they occur in a definite sequence with the simpler forms in the oldest
layers and generally the more complex ones in the youngest layers. On
the basis of the fossil evidence and the physical relations, the geologic
<span class="pb" id="Page_6">6</span>
sequence of the layers can be established for any given area and their
relative age can thus be indicated on the geologic time scale. Usually
such sequences are established for rather large areas as, for example,
northern Vermont or eastern New York State. In addition, actual age
determinations can be made for some rocks. Many igneous rocks contain
traces of uranium which has been decomposing at a known rate since its
formation. By comparing the remnants of uranium with the decomposition
products, one can assign an approximate age in terms of years to the
igneous rock. By observing the relationship between the dated igneous
rock and any sedimentary rocks in contact with it to determine their
relative ages, it may be possible to assign an approximate age to the
sedimentary rock and the fossils contained within it.</p>
<p>The general age of the original constituents of the mica-albite-quartz
schist of the Green Mountains can be determined only by comparison to
other rocks that can be dated. Any fossils present originally were destroyed
during metamorphism. Igneous rocks containing uranium do not occur
with the schist. However, elsewhere in Vermont, one can determine
that the schist lies beneath rocks containing fossils of Ordovician age
and lies above pre-Cambrian rocks known to be more than 500 million
years old. The Cambrian and Ordovician periods on the geologic time
scale are the oldest periods containing abundant fossils. The period of
the metamorphism is based on evidence at other localities where unfolded
rocks of known age lie over folded rocks. On the geologic time scale the
mica-albite-quartz schist on Mount Mansfield is said to be Cambro-Ordovician
in age, which may be from 380 to 500 million years ago.</p>
<p>In order that the geologist can talk about the sequences of rocks, layers
having a similar age and appearance are assigned a formation name. The
schists on Mount Mansfield closely resemble schists in southern Vermont
which belong to the Pinney Hollow formation. However, because they
can not be traced directly, it is possible that the two sequences are not
exactly equivalent. For this reason some geologists assign the rocks in
this area to the Camels Hump formation which has been named after
their abundant occurrence on Camels Hump Mountain, south of the
Mount Mansfield State Forest. Although it would be geologically correct
to use these formational names, they will be omitted in favor of continued
use of the name “mica-albite-quartz schist.”</p>
<p>The formation which lies over the mica-albite-quartz schist may be
seen in the vicinity of the village of Stowe where the rocks are either a
black, shiny schist or a fine-grained green schist. The formation which
<span class="pb" id="Page_7">7</span>
lies under the mica-albite-quartz schist is not exposed in the Mount
Mansfield area.</p>
<h3 id="c6"> <i>Description of the schist</i></h3>
<p>As the name implies, the mica-albite-quartz schist contains the
minerals mica, albite, and quartz. These mineral constituents are found
in all the schists in the area. Other minerals may be locally abundant or
present in small amounts.</p>
<p>When the schist is examined without a hand lens or microscope, <i>mica</i>
appears to be the most abundant mineral. It occurs as small colorless to
white flakes which sparkle and shine in the sunlight. You may recognize
this mineral as the one that is sometimes sold as artificial snow at
Christmas time. Its species name is muscovite, and it has a chemical composition
of KAl₂(AlSi₃)O₁₀(OH)₂. <i>Muscovite</i> is found in various proportions
in most of the rocks in the area. It is a deceptive mineral upon which
to make a percentage estimate because it appears to be more abundant
than it actually is. In most of the rocks it comprises less than 50 per cent
of the minerals. <i>Biotite</i> is the other important member of the mica group
and is distinguished from muscovite by its black or dark brown color.
Biotite occurs in minor proportions in the rocks of the area, being most
abundant on the western slope of Mount Mansfield. Like muscovite,
biotite occurs as small flakes with smooth flat surfaces.</p>
<p>The orientation of the mica flakes accounts for the pronounced layering
of most schists. All of the flakes are parallel and when folded and
crumpled they give the rock its structure. Where the muscovite is most
abundant, breakage along planes rich in mica produces smooth, shiny
surfaces which may give the rock a slippery appearance. The layers rich
in mica may show in a rather perfect manner the small-scale folding of
the schist.</p>
<p>Albite and quartz are also important constituents of the schists.
Together they are more abundant than mica in the average schist on
Mount Mansfield but because they are not so “showy” they are more
easily overlooked. Both minerals are white and granular. Quartz, which
consists of silica or SiO₂, is the principal constituent of most beach sands.
In the typical mica schist, quartz is glassy in appearance and occurs as
small rounded or irregular grains without plane surfaces. <i>Albite</i> is a
variety of plagioclase feldspar having the composition of NaAlSi₃O₈. It
has a white chalky appearance and occurs in small equidimensional
grains bounded by flat surfaces which break along plane surfaces that
<span class="pb" id="Page_8">8</span>
reflect light in certain positions. On the west side of Mount Mansfield
some of the rocks contain so much albite and so little mica that the rock
is granular in appearance.</p>
<p><i>Chlorite</i>, variety pennine, is an important mineral constituent of some
of the schist. Chlorite is characterized by its green color and small
amounts are responsible for giving a greenish cast to much of the schist.
Like mica it occurs as thin sheets which reflect the folding of the schist.</p>
<p>Garnet and magnetite are locally abundant minerals in the schist.
<i>Garnet</i> occurs as pink to red grains ranging from pin point to pea size.
Most of the grains are rounded although a few occur as equidimensional
crystals which have twelve equally developed faces. Garnet has a semitransparent,
glassy appearance and is harder than a knife blade. <i>Magnetite</i>
occurs as bluish-black metallic masses with about the same size range
as the garnet. Although most are rounded masses, crystal faces are
developed on some. Perfectly developed crystals occur as <i>octahedrons</i>
which is the form consisting of eight faces, as two four-sided pyramids
with their bases together. The larger grains of magnetite have sufficient
magnetic power to attract or deflect a compass needle. The garnet and
magnetite usually do not occur together, but each may form localized
concentrations as lenses or layers in the schist.</p>
<p>In smaller amounts, usually visible only with a hand lens or microscope,
the schist also contains a green mineral called epidote, a white
mineral apatite, and an elongated black mineral called tourmaline. Locally,
as on the Nose Dive ski run above the Toll Road on Mount Mansfield,
slender needles of tourmaline are visible in the schist.</p>
<p>When a piece of rock is sawed and ground to a thickness of 0.03 millimeters,
many of the minerals that appear opaque are found to be transparent.
By their color and their optical properties the minerals can be
accurately identified. On the basis of the amount of each present the
mineral and chemical composition of the rock can be determined. <a href="#fig2" class="pginternal">Figure 2</a>
shows the appearance of a thin section of the mica-albite-quartz schist
from the Forehead of Mount Mansfield. The parallel orientation of the
mineral grains is apparent even though the photomicrograph represents
a very small area of the schist.</p>
