<p>1. Yes.</p>

<p>2. Employs an overseer for that number of slaves, with few
exceptions.</p>

<p>3. &mdash;&mdash;</p>

<p>4. Not uncommonly the land; sometimes the slaves; very rarely
both together.</p>

<p>5. The common law, as in England, governs the relation between
land and debts; slaves are often sold under execution for debt;
the proportion to the whole cannot be great within a year, and
varies, of course, with the amount of debt and the urgency of
creditors.</p>

<p>6. Yes.</p>

<p>7-10. Instances are rare where the tobacco planters do not raise
their own provisions.</p>

<p>11. The proper comparison, not between the culture of tobacco and
that of sugar and cotton, but between each of these cultures and
that of provisions. The tobacco planter finds it cheaper to make
<span class='pagenum'><a name="Page_89" id="Page_89">[Pg 89]</a></span>them a part of his crop than to buy them. The cotton and sugar
planters to buy them, where this is the case, than to raise them.
The term, cheaper, embraces the comparative facility and
certainty of procuring the supplies.</p>

<p>12. Generally best clothed when from the household manufactures,
which are increasing.</p>

<p>14, 15. Slaves seldom employed in regular task work. They prefer
it only when rewarded with the surplus time gained by their
industry.</p>

<p>16. Not the practice to substitute an allowance of time for the
allowance of provisions.</p>

<p>17. Very many, and increasing with the progressive subdivisions
of property; the proportion cannot be stated.</p>

<p>18, 19. The fewer the slaves, and the fewer the holders of
slaves, the greater the indulgence and familiarity. In districts
composing (comprising?) large masses of slaves there is no
difference in their condition, whether held in small or large
numbers, beyond the difference in the dispositions of the owners,
and the greater strictness of attention where the number is
greater.</p>

<p>20. There is no general system of religious instruction. There
are few spots where religious worship is not within reach, and to
which they do not resort. Many are regular members of
Congregations, chiefly Baptist; and some Preachers also, though
rarely able to read.</p>

<p>21. Not common; but the instances are increasing.</p>

<p>22. The accommodation not unfrequent where the plantations are
very distant. The slaves prefer wives on a different plantation,
as affording occasions and pretexts for going abroad, and
exempting them on holidays from a share of the little calls to
which those at home are liable.</p>

<p>23. The remarkable increase of slaves, as shown by the census,
results from the comparative defect of moral and prudential
restraint on the sexual connexion; and from the absence, at the
same time, of that counteracting licentiousness of intercourse,
of which the worst examples are to be traced where the African
trade, as in the West Indies, kept the number of females less
than of the males.</p>

<p>24. The annual expense of food and raiment in rearing a child may
be stated at about 8, 9, or 10 dollars; and the age at which it
begins to be gainful to its owner about 9 or 10 years.</p>

<p>25. The practice here does not furnish data for a comparison of
cheapness between these two modes of cultivation.</p><p><span class='pagenum'><a name="Page_90" id="Page_90">[Pg 90]</a></span></p>

<p>26. They are sometimes hired for field labour in time of harvest,
and on other particular occasions.</p>

<p>27. The examples are too few to have established any such
relative prices.</p>

<p>28. See the census.</p>

<p>29. Rather increases.</p>

<p>30. &mdash;&mdash;&mdash;&mdash;&mdash;</p>

<p>31. More closely with the slaves, and more likely to side with
them in a case of insurrection.</p>

<p>32. Generally idle and depraved; appearing to retain the bad
qualities of the slaves, with whom they continue to associate,
without acquiring any of the good ones of the whites, from whom
(they) continued separated by prejudices against their colour,
and other peculiarities.</p>

<p>33. There are occasional instances in the present legal condition
of leaving the State.</p>

<p>34. None.</p>

