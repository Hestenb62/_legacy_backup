<p class="hang"><i>Songs and Tales from the Dark Continent, recorded from the
Singing and Sayings of C. Kamba Simango, Ndau Tribe, Portuguese
East Africa and Madikane Cele, Zulu Tribe, Natal, Zululand, South
Africa.</i> By <span class="smcap">Natalie Curtis Burlin.</span> New York, G. Schirmer, 1921.
Pp. 170.</p>

<p>This work as its title imports does not cover a wide field of
investigation and it was not done in Africa. The object of the author
is to introduce Europeans and Americans to the soul of the African,
who has too long been regarded merely as an object for exploitation.
Believing that in the folk-music of a people is imaged the real soul,
the author has made in this field researches, the results of which
have been herein set forth. The aim finally is to show that the human
family is near of kin and that basic emotions of love, of sorrow, of
rejoicing and of prayer, whether men be primitive or advanced, white,
yellow, red or black, are the same root-feelings planted in us all.</p>

<p>The book begins with a rather long introduction, discussing the
geography, history, and institutions of Africa. Much space is here
<span class='pagenum'><a name="Page_255" id="Page_255">[Pg 255]</a></span>given to spiritual beliefs as a stimulus to the development of music.
Then follows a discussion of song-poems and of the early music to
which they were set. The actual contents begin with a treatment of
songs, tales, and proverbs of the Ndau tribe by C. Kamba Simango. The
reader, if he has found the details of the contents mentioned above a
little tiresome, will have his interest quickened again by the
explanation of the <i>Song of the Rain Ceremony</i>, the <i>Spirit-Song</i>, the
<i>Love-Song</i>, the <i>Dance of Girls, Children's Songs, Laboring-Songs,
Mocking-Songs</i>, and the like. There are also such folk-tales as the
<i>Hare and the Tortoise</i>, the <i>Baboon, How the Animals dug their Well</i>,
the <i>Jackal and the Rooster, Death of the Hare</i>, the <i>Legend and Song
of the Daughter and the Slave</i>, and the <i>Sky-Maiden</i>.</p>

<p>After this portion of the book comes the Songs and Tales of the Zulu
Tribe, recorded from the singing and sayings of Madikane Cele, a Zulu
of royal blood. This includes such as the <i>Song of War</i>, <i>Song of
Children</i>, <i>Dance Songs</i>, <i>Love Songs</i> very much like those mentioned
above. It treats also of such folk-tales as the <i>Creation Story</i>. The
music to which these song poems have been set, doubtless will interest
most the student of music. Along with this appear keys to the
pronunciation of the dialects and translations of some of the songs.</p>

<p>The book is well printed and well illustrated with the art work of the
Africans portraying in different ways another phase of African life.</p>

