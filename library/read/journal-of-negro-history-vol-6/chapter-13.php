<p><span class='pagenum'><a name="Page_199" id="Page_199">[Pg 199]</a></span></p>

<p>Many Negroes used wisely the money which they obtained from these
businesses. Out of a free population of 50,000 Negroes, 5,447, or
about one in ten was in school during this period. In a pamphlet
entitled the <i>Present Condition of Free People of Color</i> published by
James Freeman Clarke in 1859, the author stated that they were no less
neat in person and attire than their white neighbors.<a name="FNanchor_30_319" id="FNanchor_30_319"></a><a href="#Footnote_30_319" class="fnanchor">[30]</a> One year
during the period from 1850 to 1860 Negroes of New York City invested
in business carried on by themselves $775,000; in businesses of
Brooklyn $76,000. That same year these free Negroes purchased real
estate in New York worth $733,000, and in Brooklyn $276,000.<a name="FNanchor_31_320" id="FNanchor_31_320"></a><a href="#Footnote_31_320" class="fnanchor">[31]</a></p>

<p>With complete freedom in New York, free Negroes made more efforts to
improve their condition. There were established several newspapers
which served not only to present their cause to the public but also as
economic factors. First of these must be mentioned a publication
called <i>Freedom's Journal</i> or <i>The Rights of All</i>. This paper, edited
by James B. Russworm, the first Negro college graduate in the United
States, and Rev. Samuel F. Cornish, was established in March,
1827.<a name="FNanchor_32_321" id="FNanchor_32_321"></a><a href="#Footnote_32_321" class="fnanchor">[32]</a> Another journal, styled <i>The Weekly Advocate</i>, changing its
name later to <i>The Colored American</i>, appeared in New York, March 4,
1837. The editor was Philip A. Bell. Later Charles Bennett Ray became
one of the proprietors and editors. Finally, mention must be made of
such journals of this period as <i>The Elevator</i>, of Albany, edited by
Stephen Myers; <i>The Genius of Freedom</i>, by David Ruggles; <i>People's
Press</i>, by Thomas Hamilton; and <i>North Star</i>, by Frederick Douglass.
Concerning the last named publication, it was generally said that it
was conducted on a higher plane than any of the others and that it was
among the first newspapers of the country.</p>

