<p><i>Dear Sir:</i></p>

<p>In connection with my letter to you of the 11th instant,
pertaining to the affidavit of Messrs. Miller and McKinlay
relative to the statement made by Mr. Francis Cardoza to them
concerning Mr. Sumner and Mr. Stevens, as published in <i>The
Journal of Negro History</i> for January, 1920, I respectfully
invite your attention to a copy of a letter from Dr. J. W.
Burgess, formerly of Columbia University. You will find him
listed in "Who's Who in America."</p><p><span class='pagenum'><a name="Page_247" id="Page_247">[Pg 247]</a></span></p>

<p>Dr. Burgess is the author of two books covering the Civil War and
the Reconstruction period, <i>The Civil War and the Constitution</i>
and <i>Reconstruction and the Constitution</i>, and evidently made a
thorough research in collecting the data for publication.</p>

<p>I regard this as a very important matter and the truth or falsity
of the statement should be established. It is only by publicity
that the facts can be established.</p>

<p>The names of Stevens and Sumner should be imperishable to the
Negro race and any reflection on their attitude during the
Reconstruction period should not go unchallenged.</p>

<p>A copy of letter from John W. Burgess follows:</p>

<p class="letterDate"><span class="smcap">Brookline, Mass.</span>,<br />
January 14, 1921.</p>

<p><span class="smcap">Mr. Henry A. Wallace:</span></p>

<p>Your favor of January 12, forwarded to me here, interests me
highly, and I thank you most sincerely for it. I am obliged to
reply, however, that the affidavit of Messrs Miller and McKinlay
astonished me very much. I cannot remember to have ever read
anything of the kind anywhere and like you, I am very skeptical
about it. I was in the world and a student at Amherst College in
the year 1867, and was even then collecting the material for my
history. I am pretty sure that I should have known of anything of
this kind had it existed. I am going to try to run this assertion
down, as I am here among the acquaintances and relatives of
Sumner.</p>

<p class="letterClose1">Very sincerely yours,</p>
<p class="right">Signed.&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;<span class="smcap">John W. Burgess.</span>
</p>

<p>I have written to Dr. Burgess to inform me as to the result of
his investigation and will let you know what he reports.</p>

<p class="letterClose1">Yours very truly,</p>
<p class="author">Henry A. Wallace.</p>

</blockquote>


