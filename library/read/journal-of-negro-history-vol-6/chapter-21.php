peculiarly severe against Africans.</p>

<p>Rhode-Island, Connecticut, Washington, Wilmington, Delaware,
Chester-town, Choptank, Virginia, Winchester, and Kentucky societies
transmitted no information.</p>


<p class="hang">VIII. <i>The progress made in extending to Africans the benefits of
instruction.</i></p>

<p><i>New-York.</i> House and lot for a school purchased by the society <span class='pagenum'><a name="Page_320" id="Page_320">[Pg 320]</a></span>since
January 1796&mdash;school has existed many years&mdash;more flourishing now than
ever&mdash;property of the society for its accommodation worth upwards of
three thousand five hundred dollars&mdash;annual expense of the school one
thousand dollars&mdash;has a master, usher and mistress&mdash;scholars taught
reading, penmanship, arithmetic, English grammar and geography&mdash;girls
(additionally) needle work&mdash;number one hundred and twenty-two&mdash;boys
sixty three girls fifty-nine&mdash;improve fast and behave as well as any
other children&mdash;evening school in the winter for free blacks,
adults&mdash;taught by the master and usher of the society's
school&mdash;number, forty-four&mdash;usher a black man.</p>

<p><i>New-Jersey.</i> Nothing done by the society&mdash;a bill is now pending
before the Legislature providing for the instruction of all children
in the state, which, if carried, will include the Africans as well as
the whites.</p>

<p><i>Pennsylvania.</i> Within the city and liberties of Philadelphia there
are at present seven schools for the education of people of colour; at
which perhaps near three hundred scholars of both sexes usually
attend&mdash;two other schools are about to be opened for the same purpose.</p>

<p><i>Maryland at Baltimore.</i> Several children of Africans and other people
of color now under a course of instruction&mdash;an academy (of which no
notice was given to the last convention) will be opened the ensuing
season, and suitable teachers provided.</p>

<p><i>Alexandria.</i> A Sunday school opened by this society in December,
1795, for the reception of Africans and their descendants&mdash;the number
of scholars who usually attend is one hundred and eight&mdash;they are
instructed in reading, penmanship and arithmetic.</p>

<p>From Rhode-Island, Connecticut, Washington, Wilmington, Delaware,
Chester-town, Choptank, Virginia, Winchester, and Kentucky
societies&mdash;no information received.</p>


