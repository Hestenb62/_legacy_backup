<p class="hang">IV. <i>An account of the proceedings of each society in relieving
persons unlawfully held in bondage.</i></p>

<p><i>New-York.</i> Since January 1796, have had complaints from ninety
<span class='pagenum'><a name="Page_318" id="Page_318">[Pg 318]</a></span>persons, Africans or of African descent&mdash;twenty-nine freed on the law
prohibiting importation&mdash;seven as free born&mdash;two unsuccessful&mdash;heavy
damages recovered in some instances&mdash;twenty-one cases now in
suit&mdash;nineteen under consideration.</p>

<p><i>New-Jersey, Society.</i> Many manumissions have been effected since
January 1796, but no precise information is yet received to what
number and under what circumstances.</p>

<p><i>Pennsylvania Society.</i> It appears from the minutes of the acting
committee of the society, that many hundreds of Africans have been
liberated through their aid since the institution of the society.</p>

<p><i>Wilmington Society.</i> Has sent a list of persons liberated by their
agency up to 1796, amounting to eighty since 1788.</p>

<p><i>Maryland Society at Baltimore.</i> A variety of suits were instituted
against the unlawful holders of slaves last year, and in consequence
many have been liberated&mdash;there are several suits now pending in law,
which are expected to have the like favorable issue.</p>

<p><i>Choptank Society.</i> This society has exerted itself in favor of the
Africans, for seven years; and been the instrument of liberating more
than sixty individuals, and has failed but in a single application to
a court of justice in their behalf.</p>

<p><i>Alexandria Society.</i> Twenty-six complaints made to the society&mdash;six
persons relieved on the law against importation; five will probably be
relieved, the other fourteen cases on which as well as on the above
suits are pending are doubtful. A suit in Norfolk court and one in
North Carolina now carrying on at the expense of this society.</p>

<p><i>Virginia Society.</i> Nothing of material importance since the
convention of 1796. Suits commenced before now pending in behalf of
between twenty and thirty persons.</p>

<p>Rhode-Island, Connecticut, Washington, Delaware, Chester-town,
Winchester, and Kentucky societies sent no account.</p>


<p class="hang">V. <i>A Statement of the condition of the blacks in each State both bond
and free, with respect to the property of the free, and the employment
and moral conduct of all.</i></p>

<p><i>New-York.</i> The number of people of color in the state of New-York not
known&mdash;exceeds two thousand&mdash;in the city names of one thousand
collected&mdash;of these more than half are free, employed as servants,
labourers, sailors, mechanics, &amp;c.&mdash;a few are small traders&mdash;condition
tolerable&mdash;many in town and country freeholders&mdash;several worth from
three hundred to thirteen hundred dollars&mdash;various associations among
the free blacks for mutual <span class='pagenum'><a name="Page_319" id="Page_319">[Pg 319]</a></span>support, benefit and improvement&mdash;one has
a lot for a burying ground and the site of a church worth fifteen
hundred dollars. In a state of progressive improvement.</p>

<p><i>New-Jersey.</i> Condition, as to enjoyments of life and respectability,
much the same as in New-York.</p>

<p><i>Pennsylvania.</i> Complied with in 1796. See the minutes of the
convention of that year&mdash;page 20 and 21.</p>

<p><i>Maryland at Baltimore &amp; Choptank.</i> The condition of the blacks from
the information this society has received is greatly ameliorated, and
some few of the free are enabled to provide for themselves without
manual labor&mdash;moral conduct equal to that of the whites in like
circumstances&mdash;minute information not yet obtained.</p>

<p><i>Alexandria.</i> Generally slaves&mdash;their treatment less rigourous than
formerly&mdash;moral conduct of the free generally good&mdash;as labourers
preferred to the whites.</p>

<p>From Rhode-Island, Connecticut, Washington, Wilmington, Delaware,
Chester-town, Virginia, Winchester and Kentucky Societies,&mdash;none sent.</p>


