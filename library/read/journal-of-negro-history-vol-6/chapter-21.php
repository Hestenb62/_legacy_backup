<p class="center sc">To the Senate and House of Representatives of the United<br />
States in Congress Assembled.<a name="FNanchor_8_418" id="FNanchor_8_418"></a><a href="#Footnote_8_418" class="fnanchor">[8]</a></p>

<p>The memorial and petition of the Delegates from the several Societies,
formed in different parts of the United States, for promoting the
abolition of slavery, in Convention assembled at Philadelphia, on the
first day of January, 1794.</p>

<p>&nbsp;&nbsp;&nbsp;&nbsp;<i>Respectfully shew</i>,</p>

<p><span class="smcap">That</span> your memorialists, having been appointed, by various Societies,
in different parts of the Union, for the benevolent purpose of
endeavouring to alleviate or suppress some of the miseries of their
fellow-creatures, deem it their duty to approach the Congress of the
United States with a respectful representation of certain evils,&mdash;the
unauthorised acts of a few, but injurious to the interest and
reputation of all.</p>

<p>America, dignified by being the first in modern times, to assert and
defend the equal rights of man, suffers her fame to be tarnished <span class='pagenum'><a name="Page_339" id="Page_339">[Pg 339]</a></span>and
her example to be weakened, by a cruel commerce, carried on from some
of her ports, for the supply of foreign nations with African slaves.</p>

<p>To enumerate the horrors incident to this inhuman traffic, of which
all the worst passions of mankind form the principal materials, would
be unnecessary, when we offer to prove its existence.</p>

<p>Nor is it requisite to consume much of your valuable time in the
endeavour to prove it a national injury.</p>

<p>While it exposes the lives and the morals of our seamen to peculiar
danger, it renders all complaints of retaliation unjust; for those who
deprive others of their liberty, for the benefit of foreign countries,
cannot reasonably murmur, if, by other foreign nations, they are
deprived of their own.</p>

<p>True it is, that the captivity at Algiers is not without a hope, and
that the slavery of the West-Indies terminates only with existence;
but, in proportion as that to which we are accessary is more severe,
the duty of desisting from it becomes more urgent.</p>

<p>Your memorialists observe, and mention with pleasure, that this venal
cruelty is at present confined to a few ports, and a few persons.
Hence it becomes more easy to destroy a degrading exception from the
general dignity of our commerce, and to restore our citizens to their
former fame, of preferring the spirit of freedom to the delusions of
interest.</p>

<p>An additional reason for the legislative interference, now requested,
arises from the natural consequence of the facts already suggested.</p>

<p>Foreigners, seduced by the example, and believing that they may commit
without reproach, what American citizens commit with impunity, avail
themselves of our ports to fit out their vessels for the same traffic.
Thus we become the accomplices of their offences, and partake of the
guilt without the miserable consolation of sharing its profits.</p>

<p>Your memorialists, therefore, trusting that a compliance with their
request, will not exceed the constitutional powers of Congress, nor
injure the interests or disturb the tranquility of any part of the
Union, respectfully pray, that a law may be passed prohibiting the
traffic carried on by citizens of the United States for the supply of
slaves to foreign nations, and preventing foreigners from fitting out
vessels for the slave-trade in the ports of the United States.</p>


