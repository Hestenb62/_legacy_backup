<p>The real and personal estate,—taking the property bequeathed
by the last codicil at a valuation of something less than two years'
purchase; and of course before payment of the legacies, the (inconsiderable)
debts, and the testamentary and other expenses,—amounted,
as nearly as may be calculated, to, £93,000.</p>
