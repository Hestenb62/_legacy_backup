from Rockingham—Private Theatricals—A Family Scene—Death
of Francis Jeffrey—Progress of <i>Copperfield</i>—A Run to Paris—Third
Daughter born—At Great Malvern—Macready's Farewell—The
Home at Shepherd's-bush—Death of John Dickens—Tribute by his
