        <h2>CHAPTER XX.</h2>
<h3>LAST YEARS IN DEVONSHIRE TERRACE.</h3>
<h3>1848-1851.</h3>
<div class="blockquot">Sentiment about Places—Personal Revelations—At his Sister's Sick-bed—Sister's
Death—Book to be written in First Person—Visiting
the Scene of a Tragedy—First sees Yarmouth—Birth of Sixth Son—Title
of <i>Copperfield</i> chosen—Difficulties of Opening—Memorable
Dinner—Rogers and Benedict—Wit of Fonblanque—Procter
and Macready—The Sheridans—Dinner to Halévy and Scribe—Expedition
with Lord Mulgrave—The Duke at Vauxhall—Carlyle
and Thackeray—Marryat's Delight with Children—Monckton
Milnes and Lord Lytton—Lords Dudley, Stuart, and Nugent—Kemble,
Harness, and Dyce—Mrs. Siddons and John Kemble—Mazzini
