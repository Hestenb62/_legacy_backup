</p>
<p class="drama">
FIRST VOICE<br>
My next move is Jesus.
</p>
<p class="drama">
SECOND VOICE<br>
St. Paul for you!
</p>
<p class="drama">
FIRST VOICE<br>
Yes, but St. Peter—
</p>
<p class="drama">
SECOND VOICE<br>
