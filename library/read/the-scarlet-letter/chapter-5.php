<h4>THE PRISON-DOOR.</h4>


<div class="initial">
<img alt="" src="https://www.gutenberg.org/cache/epub/25344/images/illu_051.jpg" style="width: 150px; height: 159px" title="" id="img_images_illu_051.jpg">
