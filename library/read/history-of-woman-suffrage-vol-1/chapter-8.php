<p>On reading the "Pastoral Letter," our Quaker poet, John Greenleaf
Whittier, poured out his indignation on the New England clergy in
thrilling denunciations. Mr. Whittier early saw that woman's only
protection against religious and social tyranny, could<span class='pagenum'><a name="Page_84" id="Page_84">[Pg 84]</a></span> be found in
political equality. In the midst of the fierce conflicts in the
Anti-Slavery Conventions of 1839 and '40, on the woman question <i>per
se</i>, Mr. Whittier remarked to Lucretia Mott, "<i>Give woman the right to
vote</i>, and you end all these persecutions by reform and church
organizations."</p>

