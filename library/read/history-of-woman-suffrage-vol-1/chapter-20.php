<h4>REPORT OF THE SELECT COMMITTEE OF THE OHIO SENATE, ON GIVING THE RIGHT
OF SUFFRAGE TO FEMALES.</h4>

<p class="ltr-date"><span class="sc">Columbus, 1858.</span></p>

<p>The following petition, numerously signed by both men and women,
citizens of this State, was, at the first session of the Legislature,
referred to the undersigned Select Committee:</p>

<p>"<span class="smcap">Whereas</span>, The women of the State of Ohio are disfranchised by the
Constitution solely on account of their sex;</p>

<p>"We do, respectfully, demand for them the right of suffrage&mdash;a right
which involves<span class='pagenum'><a name="Page_871" id="Page_871">[Pg 871]</a></span> all other rights of citizenship&mdash;one that can not,
justly, be withheld, as the following admitted principles of
government show:</p>

<p>"First. 'All men are born free and equal.'</p>

<p>"Second. 'Government derives its just power from the consent of the
governed.'</p>

<p>"Third. 'Taxation and representation are inseparable.'</p>

<p>"We, the undersigned, therefore, petition your honorable body to take
the necessary steps for a revision of the Constitution, so that all
citizens may enjoy equal political rights."</p>

<p>Your Committee have given the subject referred to them a careful
examination, and now</p>

<p class="heading"><span class="smcap">Report</span>.</p>

<p>Your Committee believe that the prayer of the petitioners ought to be
granted. Our opinion is based both upon grounds of principle and
expediency, which we will endeavor to present as briefly as is
consistent with a due consideration of this subject.</p>

<p>The founders of this Republic claimed and asserted with great
emphasis, the essential equality of human rights as a self-evident
truth. They scouted the venerable old dogma of the divine right of
kings and titled aristocracies to rule the submissive multitude. They
were equally explicit in their claim that "taxation and representation
are inseparable."</p>

<p>The House of Representatives of Massachusetts, 1764, declared, "That
the imposition of duties and taxes, by the Parliament of Great
Britain, upon a <i>people not represented</i> in the House of Commons, is
absolutely irreconcilable with their rights." A pamphlet entitled "The
Rights of the British Colonies Asserted," was sent to the agent of the
Colony in England, to show him the state of the public mind, and along
with it an energetic letter. "The silence of the province," said this
letter, alluding to the suggestion of the agent that he had taken
silence for consent, "should have been imputed to any cause&mdash;even to
despair&mdash;rather than be construed into a tacit cession of their
rights, or the acknowledgment of a right in the Parliament of Great
Britain, to impose duties and taxes on a people who are not
represented In the House of Commons." "<i>If we are not represented we
are slaves!</i>" Some of England's ablest jurists acknowledge the truth
of this doctrine. Chief Justice Pratt said: "My position is
this&mdash;taxation and representation are inseparable. The position is
founded in the law of nature. It is more; it is itself an eternal law
of nature." In defence of this doctrine they waged a seven years' war:
and yet, when they had wrung from the grasp of Great Britain the
Colonies she would not govern upon this principle, and undertook to
organize them according to their favorite theory, most of the
Colonies, by a single stroke of the pen, cut off one-half of the
people from any representation in the government which claimed their
obedience to its laws, the right to tax them for its support, and the
right to punish them for disobedience.</p>

<p>This disparity between their theory and practice does not seem to have
excited much, if any notice, at the time, nor until its bitter fruits
had long been eaten in obscurity and sorrow by thousands who suffered,
but did not complain. Indeed, so apathetic has been the public mind
upon this subject, that no one is surprised to see such a remark as
the following by a distinguished commentator upon American
institutions: "In the free States, except criminals and paupers,
<i>there is no class of persons</i> who do not exercise the elective
franchise." It seems women are not even a class of persons. They are
fairly dropped from the human race, and very naturally, since we have
grown accustomed to recognize as <i>universal</i> suffrage, that which
excludes by constitutional taboo one-half of the people. To declare
that a voice in the government is the right of <i>all</i>, and then give it
only to a <i>part</i>&mdash;and that the part to which the claimant himself
belongs&mdash;is to renounce even the appearance of principle. As ought to
have been foreseen, the class of persons thus cut off from the means
of self-protection, have become victims of unequal and oppressive
legislation, which runs through our whole code. We first bind the
hands, by the organic law, and then proceed with deliberate safety, by
the statute, to spoil the goods of the victim. Whatever palliation for
the past hoary custom, false theology, and narrow prejudice may
furnish, it is certainly time now to remedy those evils, and reduce to
practice our favorite theory of government.</p>

<p>The citizens thus robbed of a natural right complain of the injustice.
They protest<span class='pagenum'><a name="Page_872" id="Page_872">[Pg 872]</a></span> against taxation without representation. They claim that
all <i>just</i> government must derive its power from the consent of the
governed. A forcible female writer says: "Even this so-called free
government of the united States, as at present administered, is
nothing but a political, hereditary despotism to woman; she has no
instrumentality whatever in making the laws by which she is governed,
while her property is taxed <i>without</i> representation."</p>

<p>But this feeling, it is claimed, is entertained but by few women; on
the contrary, they generally disown such claim when made in their
behalf. Supposing the fact to be true to the fullest extent ever
asserted, if it proves that American women ought to remain as they
are, it proves exactly the same with respect to Asiatic women; for
they, too, instead of murmuring at their seclusion and at the
restraint imposed upon them, pride themselves on it, and are
astonished at the effrontery of women who receive visits from male
acquaintances, and are seen in the streets unveiled. Habits of
submission make women, as well as men, servile-minded. The vast
population of Asia do not desire or value&mdash;probably would not
accept&mdash;political liberty, nor the savages of the forest civilization;
which does not prove that either of these things is undesirable for
them, or that they will not, at some future time, enjoy it. Custom
hardens human beings to any kind of degradation, by deadening that
part of their nature which would resist it. And the case of woman is,
in this respect even, a peculiar one, for no other inferior caste that
we have heard of has been taught to regard its degradation as their,
its, honor. The argument, however, implies a secret consciousness that
the alleged preference of women for their dependent state is merely
apparent, and arises from their being allowed no choice; for, if the
preference be natural, there can be no necessity for enforcing it by
law. To make laws compelling people to follow their inclinations, has
not, hitherto, been thought necessary by any legislator.</p>

<p>The plea that women do not desire any change is the same that has been
urged, times out of mind, against the proposal of abolishing any
social evil. "There is no complaint," which is generally, and in this
case certainly not true, and when true, only so because there is not
that hope of success, without which complaint seldom makes itself
audible to unwilling ears. How does the objector know that women do
not desire equality of freedom? It would be very simple to suppose
that if they do desire it they will all say so. Their position is like
that of the tenants and laborers who vote against their own political
interests to please their landlords or employers, with the unique
admission that submission is inculcated in them from childhood, as the
peculiar attraction and grace of their character. They are taught to
think that to repel actively even an admitted injustice, done to
themselves, is somewhat unfeminine, and had better be left to some
male friend or protector. To be accused of rebelling against anything
which admits of being called an ordinance of society, they are taught
to regard as an imputation of a serious offence, to say the least,
against the propriety of their sex. It requires unusual moral courage,
as well as disinterestedness in a woman, to express opinions favorable
to woman's enfranchisement, until, at least, there is some prospect of
obtaining it.</p>

<p>The comfort of her individual life and her social consideration,
usually depend on the good-will of those who hold the undue power; and
to the possessors of power, any complaint, however bitter, of the
misuse of it, is scarcely a less flagrant act of insubordination than
to protest against the power itself. The professions of women in this
matter remind us of the State offenders of old, who, on the point of
execution, used to protest their love and devotion to the sovereign by
whose unjust mandate they suffered. Grlselda, himself, might be
matched from the speeches put by Shakespeare into the mouths of male
victims of kingly caprice and tyranny; the Duke of Buckingham, for
example, in "Henry VIII.," and even Wolsey.</p>

<p>The literary class of women are often ostentatious in disclaiming the
desire for equality of citizenship, and proclaiming their complete
satisfaction with the place which society assigns them; exercising in
this, as in many other respects, a most noxious influence over the
feelings and opinions of men, who unsuspectingly accept the
servilities of toadyism as concessions to the force of truth, not
considering that it is the personal interest of these women to profess
whatever opinions they expect will be agreeable to men. It is not
among men of talent, sprung from the people, and patronized and
flattered by the<span class='pagenum'><a name="Page_873" id="Page_873">[Pg 873]</a></span> aristocracy, that we look for the leaders of a
democratic movement. Successful literary women are just as unlikely to
prefer the cause of woman to their own social consideration. They
depend on men's opinion for their literary, as well as for their
feminine successes; and such is their bad opinion of men, that they
believe there is not more than one in a thousand who does not dislike
and fear strength, sincerity, and high spirit in a woman. They are,
therefore, anxious to earn pardon and toleration for whatever of these
qualities their writings may exhibit on other subjects, by a studied
display of submission on this; that they may give no occasion for
vulgar men to say&mdash;what nothing will prevent vulgar men from
saying&mdash;that learning makes woman unfeminine, and that literary ladies
are likely to be bad wives.</p>

<p>But even if a large majority of women do not desire any change in the
Constitution, that would be a very bad reason for withholding the
elective franchise from those who do desire it. Freedom of choice,
liberty to choose their own sphere, is what is asked. We have not
heard that the most ardent apostles of female suffrage propose to
compel any woman to make stump speeches against her will, or to march
a fainting sisterhood to the polls under a police, in Bloomer costume.
Women who condemn their sisters for discontent with the laws as they
are, have their prototype in those men of America who, in our
revolutionary struggle with England, vehemently denounced and
stigmatized as fanatics and rebels the leaders and malcontents of that
day. But neither their patriotism nor wisdom have ever been much
admired by the American people, perhaps not even by the English.</p>

<p>The objection urged against female suffrage with the greatest
confidence and by the greatest number, is that such a right is
incompatible with the refinement and delicacy of the sex. That it
would make them harsh and disputative, like male voters. This
objection loses most, if not all of its force, when it is compared
with the well-established usages of society as relates to woman. She
already fills places and discharges duties with the approbation of
most men, which are, to say the least, quite as dangerous to her
refinement and retiring modesty, as the act of voting or even holding
office would be. In our political campaigns all parties are anxious to
secure the co-operation of women. They are urged to attend our
political meetings, and even in our mass meetings, when whole acres of
men are assembled, they are importunately urged to take a conspicuous
part, sometimes as the representatives of the several States, and
sometimes as the donors of banners and flags, accompanied with
patriotic speeches by the fair donors. And in great moral questions,
such as temperance, for example, in the right disposition of which
woman is more interested than man, she often discharges a large amount
of the labor of the campaign; but yet, when it comes to the crowning
act of voting, she must stand aside&mdash;delicacy forbids&mdash;that is too
masculine, too public, too exposing, though it could be done, in most
cases, with as little difficulty and exposure as a letter can be taken
out or put in the post-office.</p>

<p>Then there is that large class of concert singers and readers of the
drama, who are eulogized and petted by those who are most shocked at
the idea of women submitting themselves to the exposure of voting. In
fact, the whole question of publicity is settled to the fullest
extent; at least every man must be silent who acquiesces in the
concert, the drama, or the opera. We need not dwell on the exposures
of the stage or the indelicacies of the ballet, but if Jenny Lind was
"an angel of purity and benevolence" for consenting to stand, chanting
and enchanting, before three thousand excited admirers; if Madame
Sontag could give a full-dress rehearsal (which does not commonly
imply a superfluity of apparel) for the special edification of the
clergy of Boston, and be rewarded with duplicate Bibles, it is
difficult to see why a woman may not vote on questions vitally
affecting the interests of herself, or children, or kindred.</p>

<p>But, with all our dainty notions of female proprieties, women are, by
common consent, dragged into court as witnesses, and subjected to the
most scrutinizing and often indelicate examinations and questions, if
either party imagines he can gain a sixpence, or dull the edge of a
criminal prosecution, by her testimony. The interest, convenience, and
prejudices of men, and not any true regard for the delicacy of the
sex, seem to be the standard by which woman's rights and duties are to
be measured. It is prejudice, custom, long-established usage, and not
reason, which demand the sacrifice of woman's natural<span class='pagenum'><a name="Page_874" id="Page_874">[Pg 874]</a></span> rights of
self-government; a relic of barbarism still lingering in all
political, and nearly all religions organizations. Among the purely
savage tribes, woman takes position as a domestic drudge&mdash;a mere beast
of burden, whilst the sensual civilization of Asia regard her more in
the light of a domestic luxury, to be jealously guarded from the
profane sight of all men but her husband. Both positions equally and
widely remote from the noble one God intended her to fill.</p>

<p>In Persia and Turkey women grossly offend the public taste if they
suffer their faces to be seen in the streets. In the latter country
they are prohibited by law, in common with "pigs, dogs, and other
unclean animals," as the law styles them, from so much as entering
their mosques. <i>Our</i> ideas of the proper sphere, duties, and
capabilities of woman do not differ from these so much in kind as
degree. They are all based upon the assumption that man has the right
to decide what are the rights, to point out the duties, and to fix the
boundaries of woman's sphere; which, taking for true, our cherished
theory of government, to wit: the <i>inalienability and equality of
human rights</i> can hardly be characterized by a milder term than that
of an impudent and oppressive usurpation. Who has authorized us,
whilst railing at miters, and crosiers, and scepters, and shouting in
the ears of the British Lion, as self-evident truths, "representation
and taxation are, and <i>shall</i> be, inseparable,"&mdash;"governments, to be
<i>just</i>, must have the consent of the governed;" to say woman, one-half
of the whole race, shall, nevertheless, be taxed without
representation and governed without her consent? Who hath made us a
judge betwixt her and her Maker?</p>

<p>It is said woman's mental and moral organization is peculiar,
differing widely from that of man. Perhaps so. She must then have a
peculiar fitness of qualification to judge what will be wise and just
government for her. Let her be free to choose for herself, in the
light of her peculiar organization, to what she is best adapted. She
is better qualified to judge of her proper sphere than man can be. She
knows her own wants and capabilities. Let us leave her, as God created
her, a free agent, accountable to Him for any violation of the laws of
her nature. He has mingled the sexes in the family relation; they are
associated on terms of equality in some churches. They are active
working and voting members of literary and benevolent societies. They
vote as share-holders in stock companies, and in countries where less
is said about freedom, and equality, and representation, they are
often called to, and fill, with distinguished ability, very important
positions, and often discharge the highest political trusts known to
their laws. Which of England's kings has shown more executive ability
than Elizabeth, or which has been more conscientious and discreet than
Annie and Victoria? Spain, too, had her Isabella, and France her Maid
of Orleans, her Madame Roland, yes, and her Charlotte Corday. Austria
and Hungary their Maria Theresa. Russia her Catharine; and even the
jealous Jewish Theocracy was judged forty years by a woman. It is too
late, by thirty centuries, to put in the plea of her incompetency in
political affairs.</p>

<p>But it is objected that it would not do for woman, particularly a
married woman, to be allowed to vote. It might bring discord into the
family if she differed from her husband. If this objection were worth
anything at all, it would lie with tenfold greater force against
religious than political organizations. No animosities are so bitter
and implacable as those growing out of religions disagreements; yet we
allow women to choose their religious creeds, attend their favorite
places of worship, and in some of them take an equal part in the
church business, and all this, though the husband is of another
religion, or of no religion, and no one this side of Turkey claims
that the law should compel woman to have no religion, or adopt that of
her husband. But, even if that objection were a good one, more than
half the adult women of the State are unmarried.</p>

<p>It is said, too, that as woman is not required to perform military
duty, and work on the roads, she ought not to vote. None but
"able-bodied" men, under a certain age, are required to do military
duty, and the effect is practically the same in regard to the two
days' work on the roads, whilst women pay tax for military and road
purposes the same as man. A <i>man's</i> right to vote does not depend on
his ability to perform physical labor, why should a <i>woman's?</i> By the
exclusion of woman from her due influence and voice in the government,
we lose that elevating and refining influence which she gives to
religious, social, and domestic life. Her presence at our political
meetings, all agree,<span class='pagenum'><a name="Page_875" id="Page_875">[Pg 875]</a></span> contributes greatly to their order, decorum, and
decency. Why should not the polls, also, be civilized by her presence?</p>

<p>Does not the morality of our politics demonstrate a great want of the
two qualities so characteristic of woman, heart and conscience? The
female element which works such miracles of reform in the rude manners
of men, in all the departments of life where she has the freedom to
go, is nowhere more needed than in our politics, or at the polls.</p>

<p>We have endeavored to show that the constitutional prohibition of
female suffrage is not only a violation of natural right, but equally
at war with the fundamental principles of the government. Let us now
look at the practical results of this organic wrong. After having
taken away from woman the means of protecting her person and property,
by the peaceable, but powerful ballot, how have we discharged the
self-imposed duty of legislating for her? By every principle of honor,
or even of common honesty, we are bound to see that her interests do
not suffer in our hands. That, if we depart at all from the principle
of strict equality, it should be in her favor. Let as see what are the
facts.</p>

<p>When a woman marries she becomes almost annihilated in the eyes of the
law, except as a subject of punishment. She loses the right to receive
and control the wages of her own labor. If she be an administratrix,
or executrix, she is counted as dead, and another must be appointed.
If she have children, they may be taken from her against her will, and
placed in the care of any one, no matter how unfit, whom the father
may select. He may even give them away by will. "The personal property
of the wife, such as money, goods, cattle, and other chattels, which
she had in possession at the time of her marriage, in her own right,
and not in the right of another, vest immediately in the husband, and
he can dispose of them as he pleases. On his death, they go to his
representatives, like the residue of his property. So, if any such
goods or chattels come to her possession in her own right, after the
marriage, they, in like manner, immediately vest in the husband."
"Such property of the wife, as bonds, notes, arrears of rent,
legacies, which are termed <i>choses in action</i>, do not vest in the
husband by mere operation of marriage. To entitle him to them, he must
first reduce them into possession, by recovering the money, or
altering the security, as by making them payable to himself. If the
husband appoint an attorney to receive a debt or claim due the wife,
and the attorney received it, or if he mortgaged the claim or debt, or
assign it for a valuable consideration, or recover judgment by suit,
in his own name, or if he release it, in all these cases the right of
the wife, upon the decease of the husband, is gone."</p>

<p>The real estate of the wife, such as houses and lands, is in nearly
the same state of subjection to the husband's will. He is entitled to
all the rents and profits while they both live, and the husband can
hold the estate during his life, even though the wife be dead. A woman
may thus be stripped of every available cent she ever had in the
world, and even see it squandered in ministering to the low appetite
or passions of a drunken debauchee of a husband. And when, by economy
and toil, she may have acquired the means of present subsistence,
this, too, may be <i>lawfully</i> taken from her, and applied to the same
base purpose. Even her Family Bible, the last gift of a dying mother,
her only remaining comfort, can be lawfully taken and sold by the
husband, to buy the means of intoxication. <i>This very thing has been
done.</i> Can any one believe that laws, so wickedly one-sided as these,
were ever honestly designed for the equal benefit of woman with man?
Yet wives are said to have quite a sufficient representation in the
government, through their husbands, to secure them protection.</p>

<p>But the cruel inequality of the laws relating to woman as wife are
quite outdone by those relating to her as widow. It is these stricken
and sorrowful victims, the law seems especially to have selected as
its prey. Upon the death of the husband, the law takes possession of
the whole of the estate. The smallest items of property must be turned
out for valuation, to be handled by strangers. The clothes that the
deceased had worn, the chair in which he sat, the bed on which he
died, all these sacred memorials of the dead, must undergo the cold
scrutiny of officers of the law. The widow is counted but as an alien,
and an incumbrance on the estate, the bulk of which is designed for
other hands. She is to have doled out to her, like a pauper, by paltry
sixes, the furniture of her own kitchen. "One table, six chairs, six
knives and forks, six plates, six tea-cups and saucers, one
sugar-dish, one milk-pail, one tea-pot, and <i>twelve</i> spoons!" All
this<span class='pagenum'><a name="Page_876" id="Page_876">[Pg 876]</a></span> munificent provision for, perhaps, a family of only a
dozen-persons. Think of it, ye widows, and learn to be grateful for
man's provident care of you in your hour of need!</p>

<p>Then comes the sale of "the effects of the deceased," as they are
called; and amid the fullness and freshness of her grief, the widow is
compelled to see sold into the hands of strangers, amid the coarse
jokes and levity of a public auction, articles to her beyond all
price, and around which so many tender memories cling. Experience
alone can fully teach the torture of this fiery ordeal. But this is
only the beginning of her sorrows. If she have children, the estate is
considered to belong to them, while she is but an "incumbrance" upon
it. She is to have the rents and profits of one-third part of the real
estate her lifetime, which, to the vast majority of cases, is so
unproductive as to compel her to leave that spot, endeared to her by
so many tender ties&mdash;the home of her early love, the birthplace of her
children&mdash;for a cheaper and less comfortable home. But, bereaved of
her husband and robbed of her property,</p>

<blockquote>
<div class="poem"><div class="stanza">
<span class="i0">"The law hath yet another hold on her."<br /></span>
</div></div>
</blockquote>

<p>Following up the insulting and injurious assumption of her
incompetency and untrustworthiness, implied in the denial of her right
of suffrage, the guardianship of her children is taken from her. Her
daughter, at the age of twelve, and her son, at fifteen, are to go
through the mockery of choosing for themselves a <i>competent</i>
guardian&mdash;a proceeding calculated to destroy the beautiful trust and
confidence in the wisdom and fitness of the mother to govern and
direct them, so natural and so essential to the happiness of children.
When the justifying pretext for the infliction of all this misery is
the benefit of the children, her maternal nature will struggle hard to
endure it with patience. But, until the passage of the law of 1863,
"regulating descents and distributions," when there were no children
of either parent, the law did not abate its rigor toward her, in the
disposition of the real estate, which is generally all that is left,
after paying the debts and costs of "settlement," though the whole of
the houses and lands might have been bought with her money, two-thirds
were immediately handed over to the relatives of the husband, however
above need; and though they might have been strangers, or even
enemies, to her. She had but a life estate in the other third, which,
at her death, also went, as the other, to her husband's heirs. She
could not indulge her benevolent feelings or gratify her friendships,
by devising by will, to approved charities or favorite friends, the
means she no longer needed. With a bitter sense of injustice and
despairing sorrow, she might well adopt the language of the unhappy
Jew:</p>

<blockquote>
<div class="poem"><div class="stanza">
<span class="i0">"Nay, take my life and all, pardon not that;<br /></span>
<span class="i0">You take my house, when you do take the prop<br /></span>
<span class="i0">That doth sustain my house; you take my life,<br /></span>
<span class="i0">When you do take the means whereby I live."<br /></span>
</div></div>
</blockquote>

<p>Such is the famous right of dower, which has been the subject of so
many stupid eulogies by lawyers and commentators.</p>

<p>Take an example of the effect of these laws upon an overburdened
heart, which occurred just before the passage of the Act of 1853. A
young couple, by their united means and patient industry, had secured
for themselves a small, but comfortable home. It furnished the means
of supplying all their simple wants. It was their own; doubly endeared
by the struggles and sacrifices it had cost them. They were content.
They had no children, but they had each other, and were happy in their
mutual love. Death seemed a great way off; and life&mdash;it was a real
joy. They knew little of the laws of estates. Owing nothing, they
feared no intrusion upon the sanctity of their home. But the husband
was killed by the falling of a tree; and, after some hours, was found
dead by the agonized wife. There was no will. The wrung heart of the
childless widow, in her utter bereavement, still clung to her home,
which, though blighted and desolate, was still dear to her. There, at
least, she would find shelter. But soon the inexorable law laid its
cold, unwelcome hand upon that darkened home. There must be letters of
administration had&mdash;an inventory of the "effects"&mdash;an appraisement.
Everything was explained by sympathizing counsel. The "right of dower"
set conspicuously in the foreground&mdash;"one equal third part"&mdash;at length
she comprehended it all. Her home<span class='pagenum'><a name="Page_877" id="Page_877">[Pg 877]</a></span> was to pass into other hands:
henceforth she was to be counted only as an incumbrance on it. Looking
from the misery of the present down the gloom of the future, she could
see only widowhood and penury. And whilst the appraisers were
performing their ungracious task of overhauling cupboards and drawers,
and estimating the value in cash of presents received in her
courtship, she, in her quiet despair at this last bitter drop added to
her full cup, arrayed herself in her best apparel (which the law
generously provides "she shall retain"), and, without uttering a word
of complaint or farewell, walked to the nearest water and drowned
herself.</p>

<p>If "oppression maketh even a wise man mad," ought we to wonder that a
woman, almost crazed by a sudden and terrible bereavement, upon
finding that her calamity, instead of giving her the jealous and
compassionate protection of the law, was to be made the pretext for
robbing her of what yet remained of earthly comforts, should, in the
madness of her despair, cast away the burden of a life no longer
tolerable? In India she would have been burned upon the funeral pile
of her dead husband; we drive her to madness and suicide by the
slower, but no less cruel torture, of starvation and a breaking heart.
Whilst persisting in such legislation, how could we expect to escape
the woe, denounced by the compassionate and long-suffering Saviour,
against the "hypocrites who devour widows' houses"?</p>

<p>It is said woman can accomplish any object of her desire better by
persuasion, by her smiles and tears and eloquence, than she could ever
compel by her vote. But with all her powers of coaxing and eloquence,
she has never yet coaxed her partner into doing her simple justice.
Shall we never get beyond the absurd theory that every woman is
legally and politically represented by her husband, and hence has an
adequate guarantee? The answer is, that she has been so represented
ever since representation began, and the result appears to be that,
among the Anglo-Saxon race generally, the entire system of laws in
regard to women is, at this moment, so utterly wrong, that Lord
Brougham is reported to have declared it useless to attempt to amend
it&mdash;"There must be a total reconstruction before a woman can have any
justice." The wrong lies not so much in any special statute as in the
fundamental theory of the law, yet no man can read the statutes on
this subject of the most enlightened nation, without admitting that
they were obviously made by man, not with a view to woman's interest,
but his own. Our Ohio laws may not be so bad as the law repealed in
Vermont in 1850, which <i>confiscated to the State</i> one-half the
property of every childless widow, unless the husband had other heirs.
But they must compel from every generous man the admission, that
neither justice nor gallantry has yet availed to procure anything like
impartiality in the legal provisions for the two sexes. With what
decent show of justice, then, can man, thus dishonored, claim a
continuance of this suicidal confidence? There is something
respectable in the frank barbarism of the old Russian nuptial
consecration, "Here, wolf, take thy lamb." But we can not easily
extend the same charity to the civilized wolf of England and America,
clad in the sheep's clothing of a volume of revised statutes,
caressing the person of the bride and devouring her property.</p>

<p>It is said the husband can, by will, provide against these cases of
hardship and injustice. True, he can, if he will, but does he? The
number is few, some of the more thoughtful and conscientious; but this
is only obtaining justice as a favor, and not as a natural right. But
it is a majority of husbands who make these laws, and they generally
have no desire to amend them by will. Besides, the will of the husband
is sometimes even worse than the law itself. Such cases are by no
means rare. Almost every man's memory may furnish one or more examples
that have fallen under his immediate notice. One or two only we will
mention. A woman, advanced in life, who owned a valuable farm in her
own right, in the border of a flourishing town, married a man who had
little or no property. The farm was soon cut up into town lots and
sold at high prices. In a few years the husband died, leaving no
children, but, by will, directed the division of nearly the whole of
the estate among his relatives, persons who the wife never saw. The
only remedy in this case was to fall back upon her right of dower, and
submit to the robbery of the law, in order to escape the worse robbery
of the will. This will was not the result of any disagreement between
the husband and the wife. It was only the natural outgrowth of the
whole policy of our laws as regards the property rights of woman.<span class='pagenum'><a name="Page_878" id="Page_878">[Pg 878]</a></span>
Permit us to notice one other case, which occurred in a neighboring
State. Many similar ones, no doubt, have occurred in our own, the law
in both States being the same.</p>

<p>A woman who had a fortune of fifty thousand dollars in "personal
property," married. All this, by the law, belonged absolutely to the
husband. In a year he died, leaving a will directing that the widow
should have the proceeds of a certain part of this money, <i>so long as
she remained unmarried</i>. If she married again, or at her death, it was
to go to his heirs.</p>

<p>How different in all these cases is the condition of the husband upon
the death of the wife. There in then no officious intermeddling of the
law in his domestic affairs. His house, sad and desolate though it be,
is still sacred and secure from the foot of unbidden guests. There is
no legal "settlement" to eat up his estate. He is not told that "one
equal third part" of all his lands and tenements shall be set apart
for his use during his lifetime. "He has all, everything, even his
wife's bridal presents too are his. If the wife had lands in her own
right, and if they have ever had a living child, he has a life estate
in the whole of it, not a beggarly 'third part.'"</p>

<p>Such is the result of man's government of woman without her consent.
Such is the protection he affords her. She now asks the means of
protecting herself, by the same instrumentality which man considers so
essential to his freedom and security, representation, political
equality&mdash;<span class="smcap">the right of suffrage</span>. The removal of this constitutional
restriction is of great consequence, because it casts upon woman a
stigma of inferiority, of incompetency, of unworthiness of trust. It
ranks her with criminals and madmen and idiots. It is essential to
her, practically, as being the key to all her rights, which will open
to her the door of equality and justice.</p>

<p>Does any one believe that if woman had possessed an equal voice in
making our laws, we should have standing on our statute books, for
generations, laws so palpably unequal and unjust toward her? The idea
is preposterous.</p>

<p>If our sense of natural justice and our theory of government both
agree, that the being who is to suffer under laws shall first
personally assent to them, and that the being whose industry the
government is to burden should have a voice in fixing the character
and amount of that burden, then, while woman is admitted to the
gallows, the jail, and the tax-list, <i>we have no right</i> to debar her
from the ballot-box.</p>

<p>Your Committee recommend the adoption of the following resolution:</p>

<p><i>Resolved</i>, That the Judiciary Committee be instructed to report to
the Senate, a bill to submit to the qualified electors at the next
election for senators and representatives, an amendment to the
Constitution whereby the elective franchise shall be extended to the
citizens of Ohio, without distinction of sex.</p>

<p class="author">
J. D. Cattell,<br />
H. Canfield.</p>

