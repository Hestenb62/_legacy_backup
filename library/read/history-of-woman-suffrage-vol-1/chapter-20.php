<h4>Resolutions at Rochester.</h4>

<p>The following resolutions, which had been separately discussed, were
again read. Amy Post moved their adoption by the meeting, which was
carried with but two or three dissenting voices:</p>

<p>1. <i>Resolved</i>, That we petition our State Legislature for our right to
the elective franchise, every year, until our prayer be granted.</p>

<p>2. <i>Resolved</i>, That it is an admitted principle of the American
Republic, that the only just power of the Government is derived from
the consent of the governed; and that taxation and representation are
inseparable; and, therefore, woman being taxed equally with man, ought
not to be deprived of an equal representation in the Government.</p>

<p>3. <i>Resolved</i>, That we deplore the apathy and indifference of woman in
regard to her rights, thus restricting her to an inferior position in
social, religious, and political life, and we urge her to claim an
equal right to act on all subjects that interest the human family.<span class='pagenum'><a name="Page_809" id="Page_809">[Pg 809]</a></span></p>

<p>4. <i>Resolved</i>, That the assumption of law to settle estates of men who
die without wills, having widows, is an insult to woman, and ought to
be regarded as such by every lover of right and equality.</p>

<p>5. <span class="smcap">Whereas</span>, The husband has the legal right to hire out his wife to
service, collect her wages, and appropriate it to his own exclusive
and independent benefit; and,</p>

<p><span class="smcap">Whereas</span>, This has contributed to establish that hideous custom, the
promise, of obedience in the marriage contract, effectually, though
insidiously, reducing her almost to the condition of a slave, whatever
freedom she may have in these respects being granted as a privilege,
not as a right; therefore,</p>

<p><i>Resolved</i>, That we will seek the overthrow of this barbarous and
unrighteous law; and conjure women no longer to promise obedience in
the marriage covenant.</p>

<p><i>Resolved</i>, That the universal doctrine of the inferiority of woman
has ever caused her to distrust her own powers, and paralyzed her
energies, and placed her in that degraded position from which the most
strenuous and unremitting effort can alone redeem her.</p>

<p>Only by faithful perseverance in the practical exercise of those
talents, so long "wrapped in a napkin and buried under the earth," she
will regain her long-lost equality with man.</p>

<p><i>Resolved</i>, That in the persevering and independent course of Miss
Blackwell, who recently attended a series of medical lectures in
Geneva, and has now gone to Europe to graduate as a physician, we see
a harbinger of the day when woman shall stand forth "redeemed and
disenthralled," and perform those important duties which are so truly
within her sphere.</p>

<p><i>Resolved</i>, That those who believe the laboring classes of women are
oppressed, ought to do all in their power to raise their wages,
beginning with their own household servants.</p>

<p><i>Resolved</i>, That it is the duty of woman, whatever her complexion, to
assume, as soon as possible, her true position of equality in the
social circle, the Church, and the State.</p>

<p><i>Resolved</i>, That we tender our grateful acknowledgment to the Trustees
of the Unitarian Church, who have kindly opened their doors for the
use of this Convention.</p>

<p><i>Resolved</i>, That we, the friends who are interested in this cause,
gratefully accept the kind offer from the Trustees of the use of
Protection Hall, to hold our meetings whenever we wish.</p>


