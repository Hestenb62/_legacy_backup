altar, is the power for woman to demand now and forever.</p>


<h3>WESTCHESTER CONVENTION.<br />
<small><i>June 2, 1852</i></small>.</h3>

<p>The first Woman's Rights Convention held in Pennsylvania was called in
the leafy month of June, in the quiet Quaker town of West Chester, in
one of the loveliest regions of that State. Chester County had long
been noted for its reform movements and flourishing schools, in which
the women generally took a deep interest.</p>

<p>It was among these beautiful hills that Bayard Taylor lived and wrote
his "Hannah Thurston," a most contemptible burlesque of his own
neighbors and the reforms they advocated.</p>

<p>Kennett Square and Longwood have for years been noted for their
liberal religious meetings, in which the leading reformers of the
nation have in turn been annually represented. In those gatherings of
the Progressive Friends, all the questions of the hour were freely
discussed, and their printed testimonies sent forth to enlighten the
people.</p>

<p>The Convention assembled at ten o'clock in Horticultural Hall, and was
called to order by Lucretia Mott, and the following officers chosen:</p>

