<p>At their next Convention in Kennett Square, another stirring appeal
was issued, and the following resolutions adopted:</p>

<blockquote><p><span class="smcap">Whereas</span>, The peace of our homes, the security of our property,
and our inalienable right to life, liberty, and the pursuit of
happiness, are all jeoparded by intemperance; and whereas, this
monstrous vice, with all its attendant train of evils, will
continue to spread its ravages over our fair country so long as
the traffic in intoxicating drinks is supported and sanctioned by
law; and,</p>

<p><span class="smcap">Whereas</span>, The people have the same right to be protected from the
desolations of this vice, that they have to be protected from the
depredations of the incendiary, the robber, and the murderer,
whose deeds are but too often instigated by it; therefore,<span class='pagenum'><a name="Page_349" id="Page_349">[Pg 349]</a></span></p>

<p><i>Resolved</i>, That we demand of the Representatives of the people,
