Utica, N. Y.; Lucretia Mott, of Philadelphia; Mary W. Magill, of
Buckingham, Pa.; Sarah Moore Grimk&eacute;, of Charleston, S. C.</p>

<p><span class="smcap">Secretaries</span>&mdash;Anne W. Weston, Martha V. Ball, of Boston; Juliana
A. Tappan, of New York; Sarah Lewis, of Philadelphia.</p>

<p><span class="smcap">Treasurer</span>&mdash;Sarah M. Douglass, of Philadelphia.</p>

<p><span class="smcap">Business Committee</span>&mdash;Sarah T. Smith, Sarah R. Ingraham, Margaret
Dye, Juliana A. Tappan, Martha W. Storrs, New York; Miriam
Hussey, Maine; Louisa Whipple, New Hampshire; Lucy N. Dodge,
Miriam B, Johnson, Maria Truesdell, Waity A. Spencer, Rebecca
Pittman, Rhode Island; Lucretia Mott, Mary Grew, Sarah M.
