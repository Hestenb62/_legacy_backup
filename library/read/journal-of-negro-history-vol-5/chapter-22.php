In a note on p. 35 of a paper in the <i>Transactions of the Royal
Society of Canada</i>, 1900, on <i>La Declaration de 1732</i> M. L'Abb&eacute;
Auguste Gosselin, Litt.D., F.R.S., Can., we read:
</p><p>
"On trouve dans le livre de Mgr. Tanguay <i>A travers les Registres</i>, p.
157, une notice sur l'Esclavage au Canada, avec un 'Tableau des
familles poss&eacute;dant des esclaves de la nation des Panis' L'esclavage ne
fut definitivement aboli par une loi, en Canada, qu'en 1833."
</p><p>
The learned author does not mean that there was legislation on slavery
in Canada in 1833, or that it was Canadian legislation which abolished
slavery; for such was not the case.</p></div>

