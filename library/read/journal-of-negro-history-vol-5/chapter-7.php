<p><i>Dear Sir</i>:</p>

<p>In reply to your letter requesting my assistance in getting data
relative to the Reconstruction Period in South Carolina, I have the
honor to submit the following:</p>

<p>It will be utterly impossible to give dates after a lapse of nearly
fifty years, especially with reference to the terms the legislators
served, unless I had access to the records. I was a boy when our
family returned to South Carolina in 1870, two years after the
adjournment of the Constitutional Convention. At that period I was not
especially interested in the trend of affairs. I was thinking more of
the splendid opportunities I had left behind in Canada.</p>

<p>I think it very important that all of the data possible should be
collected pertaining to the Constitutional Convening as I regard it
the most important Convention ever held in which colored men
participated. I was very fortunate in finding a copy of the
Proceedings of the Convention in the Public Library in this city. I
have given only such names as I could positively identify as colored.
No doubt some names have been omitted but not of any who took an
active or important part in political affairs.</p>

<p>F. B. Perry, of Greenville, S.C., was appointed Provisional Governor
of South Carolina by President Johnson in 1865.</p>

<p>Pursuant to a call for a convention of the people issued by Governor
Perry in obedience to the proclamation of President Johnson for the
purpose of organizing a State Government, the Convention assembled at
Columbia, S.C., September 13, 1865.</p>

<p>To show the intense bitter feeling of Governor Perry the following is
from his proclamation:</p>

<p>"It is a source of congratulation to know that the colored troops,
<span class='pagenum'><a name="Page_91" id="Page_91">[Pg 91]</a></span>whose atrocious conduct has disgraced the service and filled the
public mind with the most horrible apprehensions, have been withdrawn
from the interior of the State, and are to be placed in garrisons on
the coast where they can do no further mischief. In all of my personal
interviews with the President and in all of my dispatches to him I
urged this course most earnestly."</p>

<p>A Constitution was adopted by the Convention without being submitted
to the people for ratification.</p>

<p>The Constitution provided that only free white men were eligible for
membership in the Senate and House of Representatives; only free white
men were entitled to vote and that the appointment of members of the
House of Representatives among the several election districts of the
State should be in accordance with the number of white inhabitants in
each.</p>

<p>The Convention adjourned September 27, 1865.</p>

<p>Congress decided that it was no part of the prerogative of the
Executive to call conventions or to direct the adoption of
Constitutions.</p>

<p>J. L. Orr, of Anderson, S. C., was elected Provisional Governor,
October, 1865, to succeed Governor Perry.</p>

<p>Persuant to an Act of Congress of the United States entitled "An Act
to provide for the More Efficient Government of the Rebel States" an
election was held in South Carolina on November 19th and 20th, 1867,
and the electors of that State voted in favor of a Constitutional
Convention, and at the same time voted for delegates thereto.</p>

<p>Brevet Major-General E. R. S. Canby, Commanding 2d Military District
of South Carolina issued orders for the delegates to assemble in
convention at Charleston, S.C., January 14, 1868.</p>

<p>The Convention composed of 124 delegates, a large majority being
colored, met at Charleston, on the date named.</p>

<p>T. J. Robertson, white, was elected temporary President and Dr. A. G.
Mackey, white, was elected permanent President.</p>

<p>W. J. McKinlay and H. E. Hayne were elected temporary Secretary and
Assistant Secretary, respectively.</p>

<p>General Carlos J. Stalbrand, white, was elected permanent Secretary.
Josephus Woodruff, white, compiled the proceedings.</p>

<p>John R. Pinckney and Peter Miller were elected Sergeants-at-Arms.</p>

<p>F. L. Cardozo was Chairman of the Committee on Education.</p><p><span class='pagenum'><a name="Page_92" id="Page_92">[Pg 92]</a></span></p>

<p>S. A. Swails, Chairman of the Committee on Rules and Regulations.</p>

<p>Robert C. DeLarge, Chairman of the Committee on Franchise and
Elections.</p>

<p>Colored members were on all of the Committees, in most cases being in
the majority.</p>

<p>In looking over the proceedings I find that the following named
delegates took a very active part in all of the deliberations:</p>

<p>R. B. Elliott, R. C. DeLarge, F. L. Cardozo, J. J. Wright, W. J.
Whipper, W. J. McKinlay, S. A. Swails, A. J. Ransier, R. H. Cain, B.
F. Randolph, and W. B. Nash.</p>

<p>The Constitution provided for the election of Senators and
Representatives on April 14, 15 and 16, 1868, to assemble at Columbia,
May 12, 1868.</p>

<p>The Convention adjourned sine die March 14, 1868.</p>

<p>The Constitution adopted in 1868 stood unchanged until 1895 when a
Convention was called to meet at Columbia, on September 10, 1895, to
revise it.</p>

<p>The fact that the old Constitution stood for nineteen years after the
Democratic party came into power (1876) shows that there could not
have been anything objectionable in it to the Democrats or they would
have changed it immediately after regaining control. It speaks volumes
for the wisdom and foresight of the men of the Reconstruction Period.</p>

<p>In the Convention which met at Columbia in 1895, there were only five
colored delegates and they were all from Beaufort County, a county
which has very few white persons in it. The delegates were W. J.
Whipper, Robert Smalls, Thomas E. Miller, James Wigg, and L. R. Reed.
Of these, W. J. Whipper and Robert Smalls were delegates to the
Constitutional Convention which met at Charleston in 1868.</p>

<p>As General Smalls died only about two or three years ago what a wealth
of information he could have furnished pertaining to the
Reconstruction Period had your request been sent out before his death.</p>

<p>Inclosure 2 contains the names of State Senators and the counties they
represented. In several cases of Senators and also of Members of the
House of Representatives I cannot recall their initials.</p>

<p>There were 32 senators, the majority being colored, of whom the
<span class='pagenum'><a name="Page_93" id="Page_93">[Pg 93]</a></span>following were conspicuous for their activity on all important
legislation:</p>

<p>S. A. Swails, J. H. Rainey, R. H. Cain, W. H. Jones, W. B. Nash and H.
J. Maxwell.</p>

<p>Inclosure 3 contains names of members of the House of Representatives
at various times. Some served more than one term. The more prominent
were: R. B. Elliott, S.J. Lee, Dr. B.A. Bosemon, J. H. Rainey, R. C.
DeLarge, J. A. Bowley, W. J. Whipper, D. A. Straker, C. M. Wilder,
Prince Rivers, F. H. Frost, T. E. Miller, and W. H. Thomas.</p>

<p>The House of Representatives was composed of 124 members and colored
members were always in the majority.</p>

<p>Inclosure 4&mdash;Names of State Officers.</p>

<p>Inclosure 5&mdash;Names of Federal Office holders.</p>

<p>Inclosure 6&mdash;Names of Congressmen who represented South Carolina.</p>

<p>I shall never forget the scene in 1876 when Col. A. C. Haskell,
Chairman of the Democratic State Committee at the head of the
Democratic members of the legislature forced his way into the Hall of
the Representatives then occupied by the Republican members.
Pandemonium reigned for a time. There were two Houses, each having its
own officers trying to transact business at the same time. Finally the
U. S. soldiers were called upon and those Democrats who had no
certificate of election were ejected.</p>

<p>All of the Democratic members then withdrew and formed an organization
in another hall.</p>

<p>Three colored Republicans whose names I do not care to mention went
over to the Democrats, but the latter could do nothing without the
Senate which was admittedly Republican.</p>

<p>The struggle was kept up until Mr. Hayes was inaugurated President,
when he withdrew the U. S. troops, leaving the Republicans without any
protection.</p>

<p>Governor Chamberlain and the State Officers elected with him seeing
that they were deserted by the National Administration withdrew from
the contest, leaving Gen. Hampton who was the Democratic nominee for
Governor in possession.</p>

<p>The Democrats then organized the Senate and House of Representatives,
and in joint session elected Gen. M. C. Butler, U. S. Senator. D. T.
Corbin, who received the Republican votes, contested, but the Senate
which was Republican by a small majority seated<span class='pagenum'><a name="Page_94" id="Page_94">[Pg 94]</a></span> Butler. Senators Don
Cameron from Pennsylvania and John J. Patterson from South Carolina,
both Republicans, voted for Butler.</p>

<p>That there was no one killed or injured while the contest was going on
is remarkable when the great excitement during and after the "Red
Shirt" campaign is considered. It shows what absolute control the
gubernational candidates had over their followers. No doubt the
Democrats, who were assured that the U. S. soldiers would be
withdrawn, did not care to make a slip as Chamberlin was still
governor and the troops were practically under his orders.</p>

<p>Thus ended the Reconstruction Period in South Carolina.</p>

<br />

<p>At every step the Republican Party in South Carolina was betrayed by
Republicans.</p>

<p>Col. T. W. Parmele, white. Superintendent of the Penitentiary,
appointed as a Republican by Gov. Chamberlin, recognized an order from
Gen. Hampton for the pardon of a convict. Legal complications ensued
and the case was carried before Associate Justice Willard, white, of
the Supreme Court, a Republican elected by the legislature, and he
decided in favor of Hampton.</p>

<p>Three colored members of the legislature deserted to the Democrats,
which practically made the House Democratic.</p>

<p>Col. Parmele and Justice Willard were Northern white men.</p>

<p>This paper would not be complete without some reference to the
prominent colored men who helped to make history during that eventful
period.</p>

<p>Robert Brown Elliott&mdash;</p>

<blockquote><p>Born at Boston, Mass., August 11, 1842.</p>

<p>Entered High Holborn Academy, London, England, 1853.</p>

<p>Entered Eton College, 1855 and graduated in 1859. Studied law.</p>

<p>Member of the State Constitutional Convention.</p>

<p>Member of the House of Representatives of South Carolina,
1868-1870.</p>

<p>Assistant Adjutant General.</p>

<p>Elected to the 42nd Congress.</p>

<p>Resigned his seat in Congress and was elected to the House of
Representatives of S.C. for the second time, and was elected
Speaker of the House.</p>

<p>He came within a few votes of being elected U. S. Senator in
1874, but the powerful influence of the Pennsylvania R. R.<span class='pagenum'><a name="Page_95" id="Page_95">[Pg 95]</a></span> Co.,
was exerted in behalf of John J. Patterson, white, the successful
candidate. There was a colored majority in both branches of the
legislature at the time and had the colored members so desired
they could have elected Gen. Elliott.</p>

<p>In 1876 Gen. Elliott was the nominee on the Republican ticket for
Attorney General and was elected but was forced to withdraw with
the rest of the ticket.</p>

<p>He was Chairman of the State Republican Committee during the
campaign of 1876.</p>

<p>For scholarly attainments, legal acumen, political sagacity and
oratorical power, Robert Brown Elliott stands out as the most
brilliant figure of the Reconstruction Period.</p></blockquote>


<p>Joseph H. Rainey&mdash;</p>

<blockquote><p>Born at Georgetown, S.C., June 21, 1832.</p>

<p>Although debarred by law from attending school he acquired a good
education and further improved his mind by observation and
travel.</p>

<p>He was a barber by trade and followed that occupation at
Charleston, S.C., until 1862, when having been forced to work
upon the fortifications of the Confederates he escaped to the
West Indies, where he remained until the close of the war, when
he returned to his native town.</p>

<p>Delegate to the State Constitutional Convention.</p>

<p>State Senator from Georgetown County.</p>

<p>Elected to the 41st Congress, being the first colored man having
that distinction, and was re-elected to the 42nd, 43rd, 44th and
45th Congresses, five successive terms, the only colored man with
such a record.</p>

<p>He received a caucus nomination as Clerk of the House, from the
Republican members of Congress, the only colored man who has ever
been honored by a Republican caucus.</p>

<p>The House was Democratic.</p>

<p>He was a delegate to several National Republican Conventions.</p>

<p>Served as Special Agent for the Treasury Department.</p>

<p>Polished in his manners&mdash;a fluent and convincing speaker, he was
prominent in the Councils of the Republican Party.</p></blockquote><p><span class='pagenum'><a name="Page_96" id="Page_96">[Pg 96]</a></span></p>


<p>Gen. Robert Smalls&mdash;</p>

<blockquote><p>Born in South Carolina, at Beaufort, April 5, 1839.</p>

<p>Although debarred by Statute from attending school, he educated
himself with such limited advantages as he could secure.</p>

<p>Removed to Charleston, S.C., in 1851, worked as a rigger, leading
a sea-faring life.</p>

<p>Employed on the <i>Planter</i>, a steamer plying in Charleston harbor
as a transport, which he took over Charleston Bar in May, 1862,
and delivered her and his services to the U. S. Blockading
Squadron.</p>

<p>In recognition of his services was appointed Pilot in the U. S.
Navy, and served in that capacity on the monitor "Koekuk."</p>

<p>Promoted as Captain for gallant and meritorious conduct, December
1, 1863, and placed in command of the <i>Planter</i>, serving until
she was put out of commission in 1866.</p>

<p>Delegate to the State Constitutional Convention.</p>

<p>State Senator from Beaufort Co.</p>

<p>Elected to the 44th Congress, and re-elected to the 45th, 48th
and 49th Congresses.</p>

<p>Was a delegate to every National Republican Convention up to
within a short time of his death.</p>

<p>Collector of the Port of Beaufort, S. C.</p>

<p>Died two or three years ago, the last of the "Old Guard" in S. C.</p></blockquote>


<p>Alonzo J. Ransier&mdash;</p>

<blockquote><p>Born at Charleston, S.C., 1834.</p>

<p>Self educated. Employed as a shipping clerk in 1850 by leading
merchant, who was tried for violation of law "in having a colored
clerk" and fined one cent with costs.</p>

<p>Delegate to the State Constitutional Convention.</p>

<p>Member of the House of Representatives of S.C.</p>

<p>Elected Lieutenant Governor on ticket with Gov. R. K. Scott, in
1870.</p>

<p>President of Southern States Convention held at Columbia, S.C.,
in 1871.</p>

<p>Presidential Elector on Grant and Colfax ticket in 1868.</p>

<p>Delegate to National Republican Convention in 1872.</p>

<p>Elected to the 42 Congress.</p>

