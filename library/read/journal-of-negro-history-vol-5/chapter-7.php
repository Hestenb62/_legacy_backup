<p>There were many colored men who occupied positions of importance in
the different countries&mdash;positions such as Sheriff, Treasurer,
Auditor, Clerk of Court, Commissioner, Coroner and School
Commissioner.</p>

<p>I never heard of any of them being removed for incompetency,
dereliction of duty or malfeasance.</p>

<br />

<p>I regret very much that I cannot give you any information as to
whether the men mentioned were free or slaves, as the persons from
whom I could have gotten that information have all passed away. Had I
received such inquiry eight or ten years ago I could have furnished it
as there were several persons then living who, I know, were well
posted on that subject.</p>

<p>Of the names noted in this paper the following were from the North.</p>

<p>Some of them may have been from the South originally and returned
after the war: R. B. Elliott, D. A. Straker, Maj. M. R. Delaney, W. H.
Jones, Dr. B. A. Bosemon, W. H. Thomas, H. W. Purvis, R. H. Gleaves,
A. C. Jones, S. A. Swails, J. A. Bowley, J. E. Green.</p><p><span class='pagenum'><a name="Page_105" id="Page_105">[Pg 105]</a></span></p>

<p>The colored men of South Carolina played a more conspicuous part and
held more offices of a high grade during the Reconstruction Period
than the colored men of any other State.</p>

<br />

<p>South Carolina has the distinction of electing the first colored
Congressman, (Joseph H. Rainey) and the last (George W. Murray.)<a name="FNanchor_27_194" id="FNanchor_27_194"></a><a href="#Footnote_27_194" class="fnanchor">[27]</a></p>

<p>South Carolina was represented in Congress by eight colored
men&mdash;Rainey, Elliott, Ransier, Cain, Delarge, Smalls, Miller and
Murray.</p>

<p>Mr. Miller and Mr. Murray served after the Reconstruction Period and
most of Gen. Smalls' service was after that period.</p>

<br />

<p>When I compare the present political leaders in South Carolina with
those of the Reconstruction Period I must confess that we have
retrograted politically. They may be due to conditions. Not only in
South Carolina, but where would you find in any State at the present
time, political leaders who can measure up to the caliber of Elliott,
Rainey, Straker, Cardozo, Swails, DeLarge, Bosemon, Wright, Ransier,
Lee, McKinlay, Cain, Whipper and Wilder?</p>

<p>When the Negro race can again produce political leaders of the type
named then we may look forward with some degree of hope for a solution
of the Negro problem.</p>

<p>Your idea in collecting data relative to the Reconstruction Period is
a laudable one, and the wonder is, and the pity of it is, that it had
not been thought of long ere this. There are very few now left to tell
the tale, and that in a very unsatisfactory way.</p>

<p>Some of the data relative to the Congressmen I got from Congressional
Directories. To recall all names, dates and incidents pertaining to
the Reconstruction Period after a period of fifty years would require
the prodigious memory of a Macauley, even had I been an active
participant in political affairs at that time. There may be a few
errors but they are of a minor character. I am glad that I am <span class='pagenum'><a name="Page_106" id="Page_106">[Pg 106]</a></span>able to
be of some assistance to you in this matter, however, little, and I
can only say in the words of Macbeth,</p>

<div class="poem"><div class="stanza">
<span class="i0">"The service and the loyalty I owe,<br /></span>
<span class="i0">In doing it, pays itself."<br /></span>
</div></div>

