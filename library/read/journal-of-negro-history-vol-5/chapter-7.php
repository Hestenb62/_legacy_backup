Charleston, S. C., by President Grant and served four years with
entire satisfaction to the people of that city with honor and
credit to himself and the race.</p>

<p>Suave and polished he had a pleasing personality.</p>

<p>He had quite a large and lucrative practice in his profession.</p></blockquote>


<p>Charles McDuffie Wilder&mdash;</p>

<blockquote><p>Born in South Carolina. Delegate to the State Constitutional
