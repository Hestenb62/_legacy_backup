<p>Speaker of the House of Representatives for one term.</p>

<p>A lawyer of recognized ability.</p>

<p>An expert in parliamentary procedure.</p>

<p>A man of engaging address, of a genial disposition, a pleasing
speaker, he was the most popular presiding officer of that
period.</p></blockquote>


<p>D. Augustus Straker&mdash;</p>

