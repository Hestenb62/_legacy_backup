<p>Postmaster at Columbia, S. C. for sixteen years. Appointed by
President Grant two terms and one term each by Presidents
Garfield and Hayes.</p>

<p>There were two white applicants for the position after President
Garfield was inaugurated and Postmaster General James, who was
supposed to be friendly with one of them, sent a Post Office
Inspector to Columbia to find out the sentiment of the business
men. They were almost unanimously for Mr. Wilder. They stated
that he had served them efficiently for eight years and did not
approve of a change.</p><p><span class='pagenum'><a name="Page_101" id="Page_101">[Pg 101]</a></span></p>

<p>Generals Hampton and Butler represented the State in the U. S.
Senate at the time, Columbia being Senator Hampton's home and had
he objected Senatorial courtesy would have sustained him.</p>

<p>It shows in what estimation Mr. Wilder was held by his home
people.</p>

<p>Mr. Wilder's appointment of four successive terms to a
first-class post office is a record.</p>

<p>Mr. Wilder was a delegate to all of the National Republican
Conventions up to and including that of 1888.</p>

<p>Mr. Wilder was a man of good sound judgment, of great political
force and one of the few who had anything to show after the
political upheaval of 1876.</p></blockquote>


<p>Samuel J. Lee&mdash;of Aiken, S. C.</p>

