the entire Bar of the State.</p>

<p>He was pre-eminently fitted for the position.</p>

<p>He is the only colored man who has ever occupied such an exalted
judicial position in this country.</p></blockquote>


<p>Thomas E. Miller&mdash;</p>

<blockquote><p>Born at Ferrybeeville, Beaufort Co., June 17, 1849.</p><p><span class='pagenum'><a name="Page_100" id="Page_100">[Pg 100]</a></span></p>

