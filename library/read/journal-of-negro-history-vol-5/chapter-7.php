1875.</p>

<p>Elected to the House of Representatives of S. C., 1874-1876-1878.</p>

<p>Elected Senator from Beaufort Co., 1880.</p>

<p>Elected to the 51st Congress.</p>

<p>Elected to the House of Representatives of S. C., in 1866, and
