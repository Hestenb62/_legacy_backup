Colored Youth" established at Orangeburg, S. C., and on that
account was elected its first President.</p></blockquote>


<p>Dr. B. A. Bosemon&mdash;</p>

<blockquote><p>Born at Troy, N. Y.</p>

<p>Delegate to the State Constitutional Convention. Member of the
