<p>Was Adjutant General of the State most of the Reconstruction
Period.</p>

<p>He was a man without fear.</p>

<p>In the campaign of 1876 he went to Edgefield, the homes of
Generals Butler and Gary, the Democratic leaders, and regarded as
fire eaters and spoke on the campaign issues. He also went to
other parts of the State equally as dangerous and filled his
engagements.</p></blockquote>


<p>J. J. Wright&mdash;</p>

<blockquote><p>Delegate to the State Constitutional Convention.</p>

<p>On account of his great legal ability he was elected by the
