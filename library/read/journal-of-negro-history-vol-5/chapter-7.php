<p class="center sc">Cooperative Extension Work in Agriculture and Home Economics</p>

<blockquote>
<p class="letterDate"><span class="smcap">College Station, Texas</span><br />
<span class="smcap">Waco, Texas</span>, March 26, 1918.</p>

<p><span class="smcap">Prof. Monroe N. Work</span>, Tuskegee Inst. Ala.</p>

<p><i>Dear Mr. Work</i>:</p>

<p>I was elected in Nov. 1894 as representative for Colorado county and
was re-elected in 1896.</p>

<p>My majority in 1894 was 168 and in 1896 at the next election it was
450 as I recollect it.</p>

<p>I was appointed on the committee on education and on privilege and
election and on agriculture.</p>

<p>I introduced a bill restoring colored trustees which finally passed.</p>

<p>I fought a bill establishing separate waiting rooms for the races at
R. R. Station and killed it for four years.</p>

<p>I introduced a resolution inviting manufacturing cotton plants to come
to Texas. I introduced a resolution granting the use of the Hall of
the House of Representatives to the colored citizens of Austin to hold
their memorial services for Fred Douglas. When one understands the
race feeling in the South this was indeed a triumph. I introduced a
bill establishing a college course as a part of our curriculum at
Prairie View Normal which passed carrying with it a grant of fifty
thousand acres of land.</p>

<p>I worked hard to help carry a bill through making any peace officer
automatically lose his office whenever a lynching took place in his
county. This bill passed but was declared unconstitutional by the
supreme court. I was appointed by the speaker as a member of the
visiting board for Prairie View State Normal. As a member of the
committee on privileges and Election I single handed fought for a
colored man elected from Brazoria county, N. H. Haller by name who had
the nerve to contest the seat of a white man to whom the certificate
of election had been awarded. After a long and bitter fight in which
three times I carried in and presented a minority report we won and
Haller was seated. This isn't the only case of its kind that I know of
in this state.</p>

<p>Haller of course had able legal talent to take care of his case.</p>

<p>I voted for the purchase of the battle field of San Jacinto which is
in Harris country about twenty miles below Houston. It was on this
battlefield that Texas won her independence from Mexico in<span class='pagenum'><a name="Page_113" id="Page_113">[Pg 113]</a></span> 1836. It
is now a beautiful state park. For this action I was publicly thanked
by the Daughters of the Republic.</p>

<p class="letterClose">Respectfully</p>
<p class="author2">(Signed)&nbsp;&nbsp; <span class="smcap">R. L. Smith.</span></p>

<p>The legislatures which I served in were the 23d and 24th.</p>

<p>Charles A. Culberson, now U. S. senator was governor and our relations
were very cordial.</p>

<p>In 1902 I was tendered and accepted a position in the U. S. Marshal's
office for the Eastern Dist. of Texas by Pres. Roosevelt. Held same
until 1909. This was the most honorable and best paid federal position
ever held by a Negro in Texas except that held by Hon. N. W. Cuney who
was collector of the Post of Galveston. In 1915 I took charge of the
Extension Service work for Negroes in Texas which I now hold.</p>
</blockquote>

