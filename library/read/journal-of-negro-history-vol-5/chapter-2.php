<p>Apparently there is no effort in the South to supply high schools for
the Negro. The General Assembly of Georgia passed a bill to establish
high schools in all of the congressional districts of the State.
Eleven were established and supported by a fertilizer tax, most of
which was paid by the Negroes who numbered 45.1 per cent of the
population of the State, and 80 per cent of whom lived in the rural
districts.<span class='pagenum'><a name="Page_13" id="Page_13">[Pg 13]</a></span> None of these schools, however, were for members of the
Negro race.<a name="FNanchor_41_41" id="FNanchor_41_41"></a><a href="#Footnote_41_41" class="fnanchor">[41]</a></p>

<p>The founding of the two most important industrial schools has been
mentioned before. Hampton Institute which was founded by the American
Missionary Society in 1868 now consists of 113 buildings, including
the instructors' cottages.<a name="FNanchor_42_42" id="FNanchor_42_42"></a><a href="#Footnote_42_42" class="fnanchor">[42]</a> 76 of these buildings were erected by
student labor. There are 120 acres to the Home Farm and 600 acres to
Shellbanks, six miles from the Institute. The enrollment in 1910 was
875, or 1,399 including the Normal Practice School. Tuskegee Institute
which began with one hoe and a blind mule now possesses 2,000 acres of
land, 800 of which are cultivated each year by the young men of the
school. During 1903, 33 trades were taught to over 1,400 men and
women. By means of this work, the students pay more than one half of
their expenses. Of the sixty buildings, all but four were almost
wholly erected by students, even to the making of the bricks.<a name="FNanchor_43_43" id="FNanchor_43_43"></a><a href="#Footnote_43_43" class="fnanchor">[43]</a>
Although the average Negro was greatly antagonistic regarding this
training at the beginning of the work at these institutes and many
protests were heard from all sides, Mr. Washington stated in <i>The
Negro Problem</i> that it has been several years since they have received
a protest from parents against teaching industrial training.<a name="FNanchor_44_44" id="FNanchor_44_44"></a><a href="#Footnote_44_44" class="fnanchor">[44]</a> The
graduates of Tuskegee have established more than fifteen similar
schools in the South.<a name="FNanchor_45_45" id="FNanchor_45_45"></a><a href="#Footnote_45_45" class="fnanchor">[45]</a> Among those established are Voorhees
Industrial School, Robert Hungerford School, Snow Hill Normal and
Industrial Institute, Topeka Normal and Industrial Institute, Port
Royal Agricultural School, and Mt. Meigs Institute.</p>

<p>No one of the Negro institutions for higher learning has as yet become
a fully equipped university. No one of the institutions maintains a
graduate school. Howard University is the only one that has even
started graduate work.<a name="FNanchor_46_46" id="FNanchor_46_46"></a><a href="#Footnote_46_46" class="fnanchor">[46]</a><span class='pagenum'><a name="Page_14" id="Page_14">[Pg 14]</a></span> The real influence of the college has been
to prepare men to be leaders in education, as may be witnessed by the
fact that out of the 5,000 Negro college graduates in the United
States 54 per cent are teaching, while 20 per cent are preaching.<a name="FNanchor_47_47" id="FNanchor_47_47"></a><a href="#Footnote_47_47" class="fnanchor">[47]</a>
The following table shows the number of college graduates by
decades:<a name="FNanchor_48_48" id="FNanchor_48_48"></a><a href="#Footnote_48_48" class="fnanchor">[48]</a></p>


