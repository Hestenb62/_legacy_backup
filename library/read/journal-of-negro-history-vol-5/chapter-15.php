<h2><a name="No2_a5" id="No2_a5"></a>
CORRESPONDENCE</h2>


<p>The following letter written primarily to correct certain errors has
been productive of much good in bringing to light a number of facts
which the public should know:</p>

<blockquote>
<p class="letterDate"><span class="smcap">140 Cottage Street, New Haven, Conn.</span>, February 23, 1920.</p>
<p><span class="smcap">Dr. Carter G. Woodson</span>,<br />
&nbsp;&nbsp;1216 You Street, Washington.</p>

<p><i>My dear Dr. Woodson:</i></p>

<p>I find the latest number of your <i>Journal</i> most interesting and
permanently valuable, like those that have preceded. I think that
the publication is gaining a position in its particular field
which promises to make it an accepted authority on historical
questions. This makes it the more essential for manifest errors
to be carefully guarded against and eliminated from contributed
articles.</p>

<p>I observe on page 5 the designation "Tillston College" of The
American Missionary Association; the correct name is Tillotson
College, for the institution at Austin, Texas. The footnote gives
<i>Brawley</i> as authority. I do not have this book at hand but have
a suspicion that the erroneous spelling is found there also.</p>

<p>Another statement in the same article which seems to me erroneous
in a more serious matter is found at the bottom of page 4, where
it is assumed that in 1863 "only 5 per cent of the Negro
population was literate." In your book on <i>The Education of the
Negro Prior to 1861</i> you have stated very solid reasons for
believing 10 per cent to be about the right estimate. This
accords also with the U.S. Census figures of 1870, set forth in a
table of which I sent you a copy. Is it not a matter of vital
significance to our American history which of these statements is
to be accepted? Yesterday I saw posted on the wall of a New Haven
church the statement of <i>5 per cent</i>. It used to be considered
allowable to make wild statements on this subject when presenting
the claims of Southern education. Indeed I have known the
statement to be made in such a connection, that <i>none</i> of the
Negroes could read or write before the war. I yield to no one in
my estimate of the importance of the work of Northern teachers
and Northern schools in the education <span class='pagenum'><a name="Page_250" id="Page_250">[Pg 250]</a></span>of the colored people. But
their value is not magnified by such exaggerated and reckless
over-statement. Rather is it brought under serious question and
damaging suspicion.</p>

<p>You have done and are still doing most valuable work in the
interest of historical accuracy, and to clear away the fogs of
misconstruction and misapprehension concerning the Negro people
which have prevailed for at least a hundred years. I could wish
that you might see your way as an editor to insist on alteration
in a manuscript containing such a misstatement, or at least add
an editorial comment on the point.</p>

<p>Wishing for your <i>Journal</i> continued and increasing circulation
and popular support, I remain,</p>

<p class="letterDate">Faithfully, yours,</p>
<p class="author">G. S. Dickerman.</p>
</blockquote>

<p>The editor made the following reply:</p>

<blockquote>
<p class="letterDate">February 28 1920.</p>
<p><span class="smcap">Dr. G. S. Dickerman</span>,<br />
&nbsp;&nbsp;140 Cottage Street,<br />
&nbsp;&nbsp;&nbsp;&nbsp;New Haven, Conn.</p>

<p><i>My dear Dr. Dickerman:</i></p>

<p>I have your interesting letter in which you make a strong plea
for accuracy in the writing of history that the Negro may receive
justice at the hands of those represented as treating the records
of the race scientifically. You insist that, prior to the
emancipation of the race, more than five per cent of the Negro
population was literate, and refer to my <i>Education of the Negro
Prior to 1861</i> to support you in that statement. You must
observe, however, that I maintain that ten per cent of the adult
Negroes had the rudiments of education. It might, therefore, be
possible for some one to prove that less than ten per cent of the
whole Negro population was at that time able to read and write.</p>

<p>Thanking you for your interest in this work, I am</p>

<p class="letterClose">Yours very truly,</p>
<p class="author">C. G. Woodson,</p>
<p class="author-affl"><i>Director</i>.</p>
</blockquote>

<p>The tables to which Dr. Dickerman refers were sent to the editor with
a letter, both of which follow:</p><p><span class='pagenum'><a name="Page_251" id="Page_251">[Pg 251]</a></span></p>

<blockquote>
<p class="letterDate">140 <span class="smcap">Cottage Street, New Haven, Conn.</span>, July 14, 1917.</p>
<p><span class="smcap">Dr. Carter G. Woodson</span>,<br />
&nbsp;&nbsp;1216 You Street, N.W.<br />
&nbsp;&nbsp;&nbsp;&nbsp;Washington, D. C.</p>

<p><i>Dear Dr. Woodson:</i></p>

<p>In preparing a chapter on The History of Negro Education for Dr.
Jones, of the Phelps Stokes Foundation, I made a study of the
Ninth Census and prepared a table of figures which I suggested
for publication in a foot note. But my manuscript was so long
that it was thought best to eliminate about a third of it and
this table with much besides.</p>

<p>I have therefore thrown this Census study into form for
publication in an article by itself. If you like you may have it
for <i>Journal of Negro History</i>. Of course the Census is not
infallible and the Ninth Census has been especially charged with
inaccuracy. But it certainly has some meaning, and I think the
confirmation of your conclusions is worth noticing.</p>

<p>If you do not wish to use the article please return it to the
above address.</p>

<p class="letterClose">Very truly yours,</p>
<p class="author">G. S. Dickerman.</p>


<p class="center sc">The Ninth Census on Negro Illiteracy</p>

<p>The treatise of Dr. Carter Godwin Woodson on <i>The Education of
the Negro Prior to 1861</i> offers an impressive array of evidence
to show that there were many more Negroes than have usually been
supposed who had some literary knowledge while still under
slavery. Other evidence bearing on a subject of so great
importance cannot but have interest for historians of that
period.</p>

<p>Some of the statistics in the United States Census of 1870 are in
point: Figures are there given for the colored men of voting age,
that is for those over 21, who were unable to read and write.
There are also given the total numbers of colored men of voting
age in the several States. Subtracting the former from the latter
will then give the number of those able to read and write. The
results appear in the table presented below:</p><p><span class='pagenum'><a name="Page_252" id="Page_252">[Pg 252]</a></span></p>

