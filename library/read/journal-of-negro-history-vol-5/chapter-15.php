<p>This Census gives the figures for women of color over 21 years of
age who were unable to write; but not the whole number of women
of color over 21. If however we assume the proportion of all
Negro males to all Negro females to hold the same for those over
21 we arrive at the conclusion that the whole number of women of
color over 21 was 1,072,847 for the United States; of whom
946,332 were unable to write and 126,515 were able. That is, in
1870, there were approximately 126,515 women of color of 21 years
of age and upward who were able to read and write. This number
added to the 170,232, found for the number of literate men, gives
a total of 296,747 Negroes of 21 years of age and upward who were
able to read and write; which is 14 per cent of the whole number.
There must have been a considerable increase between 1863 and
1870, but one can hardly suppose it to have been over 4 per cent,
or 84,212, which substantiates the estimate of about 10 per cent
of the Negroes as able to read and write at the date of
emancipation. We may suppose that the number of those who were
able to read, but did not add to this the accomplishment of
writing, must have been much larger.</p>

<p>The existence of so large a body of Negroes who already had the
rudiments of an education goes far to account for the rapid
growth of schools as soon as the Negroes were made free, and
especially for that eagerness that was shown for advanced
learning <span class='pagenum'><a name="Page_253" id="Page_253">[Pg 253]</a></span>which made an almost immediate demand for secondary
schools and colleges at the more important centers of population
throughout the South. The people had received, in some way or
other, a love of education and a start in obtaining it under the
old slave system, so that when the new chance came they were
ready to make a good use of it.</p>

<p class="author">G. S. Dickerman.</p>
