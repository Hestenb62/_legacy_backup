<blockquote>
<p class="letterDate"><span class="smcap">London, Ont.</span> October 25/1918</p>
<p><span class="smcap">Dr. Carter G. Woodson</span>,<br />
&nbsp;&nbsp;<i>Journal of Negro History</i>,<br />
&nbsp;&nbsp;&nbsp;&nbsp;Washington, D. C.</p>

<p><i>Dear Dr. Woodson</i>,</p>

<p>I have been reading your "Century of Negro Migration" with
interest. On page 36 you speak of a change of attitude on the
part of Canadians towards the refugees. I do not know to what
this refers. The attitude of the Canadian government never
changed&mdash;it granted asylum and protection right up to the Civil
War and afterwards. From the very earliest days there was an
occasional show of prejudice but I doubt if this was greater in
1855 than in 1845 or 1835. The laws were administered fairly, the
Negro exercised his vote, could get land cheaply if he desired to
farm. The chief prejudice was shown in the schools though this
only in some places, this city for instance. But this was only
occasional, not general, and you are quite correct in saying that
"these British Americans never made the life of the Negro there
so intolerable as was the case in some of the free States."</p>

<p>On the same page there is a slight error in the use of the word
"towns" in connection with the settlements of refugees in
Southern Ontario.</p>

<p>"Dawn" was not a town but a farming community, "The Dawn
Settlement" "Colchester" was the same, it is the name now given
to a township in Essex county.</p><p><span class='pagenum'><a name="Page_463" id="Page_463">[Pg 463]</a></span></p>

<p>"Elgin" was not the name of a Settlement but of the association
which managed the settlement. Buxton was the settlement founded
by the Elgin association.</p>

<p>"Bush", <i>i.e.</i> "The Bush" is the term applied to a great tract of
country north of Toronto, bushland, in which there were some
Negro farmers.</p>

<p>"Wilberforce" was also a tract of land divided into farms and
termed the Wilberforce settlement. It is in Middlesex county,
near London.</p>

<p>"Riley" should be "Raleigh," it is the township in which the
Elgin association's settlement was located. It is in Kent County.</p>

<p>"Anderton" is also the name of a township in Essex county.</p>

<p>"Gonfield" should be "Gosfield." It is also a township in Essex
county.</p>

<p>These are only minor matters but you might desire to make the
change in another edition.</p>

<p>I think I shall write something dealing with the Canadian end of
your subject, from the economic standpoint. The <i>Journal</i> is a
publication of which as Editor you can be proud. It maintains a
high standard. I intend to have it added to the Western
University's list of periodicals this year.</p>

<p class="letterClose">Sincerely yours,</p>
<p class="author2">(Signed)&nbsp;&nbsp; <span class="smcap">Fred Landon</span>.</p>
</blockquote>

