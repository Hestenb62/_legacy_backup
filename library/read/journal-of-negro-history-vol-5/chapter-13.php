operation&mdash;they leave to the wisdom and provident forecast of the
General Assembly, the conception and the prosecution of the best
practicable scheme&mdash;but they would respectfully and earnestly ask that
the action of the laws passed to this effect be decisive, and the
means energetic&mdash;such as shall, with as much speed as may be, free our
country from this bane of its prosperity, morality and peace."&mdash;<i>The
Richmond Enquirer</i>, Oct. 21, 1831.</p></div>

