&nbsp;&nbsp;&nbsp;&nbsp;February 5, 1920</p>


<div class="footnotes"><h3>FOOTNOTE:</h3>

<div class="footnote"><p><a name="Footnote_1_593" id="Footnote_1_593"></a><a href="#FNanchor_1_593"><span class="label">[1]</span></a> I had with the late Hon. Warwick Hough of St. Louis,
Missouri, who had been an officer in the Southern Army, several
conversations on the subject of slavery. He gave it as his firm
conviction that, had the South succeeded in the Civil War, it would
shortly have itself abolished slavery and sought readmission to the
Union. His proposition was that the power and influence of the planter
class was waning, while the manufacturers, merchants and the like were
increasing in number and influence and they would have for their own
protection abolished slavery. I have not met a Northerner or a
Canadian who agreed with this view; but a few Southerners have
expressed to me their general concurrence with my friend's
proposition.</p></div>
