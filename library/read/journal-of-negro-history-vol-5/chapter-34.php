<p><i>Dear Mr. Work:</i></p>

<p>In looking through the last number of <i>The Journal of Negro
History</i>, I note that you are asking for information concerning
those Negroes who were members of the State Legislatures during
reconstruction days, just following the Civil War.</p>

<p>I do not know if it has already been called to your attention or
not, but my grandfather, Shandy Jones, was at that time a member
of the Alabama Legislature. I do not know the year, but think I
can get the dates for you if it is of interest to you.</p>

<p>His early life was spent in Tuscaloosa, Alabama. He was a very
successful business man, barber by trade. His later life was
actively spent in church work. He was presiding elder in the A.
M. E. Z. church and was nominated for bishop, but his age was an
obstacle.</p>

<p>He lived in Mobile, Alabama at the time of his death at 70 years.
He was still in the ministry at this time.</p>

<p class="letterClose">Very truly,</p>
<p class="author2">(Signed)&nbsp;&nbsp; <span class="smcap">Mrs. M. E. Richardson</span>.</p>
