        <h3>2.4 Periodic Trends</h3>
        <table class="ref-table">
            <thead>
                <tr><th>Periodic Property</th><th>Left to Right Across a Period</th><th>Top to Bottom Down a Group</th><th>Underlying Nuclear Mechanism</th></tr>
            </thead>
            <tbody>
                <tr><td><strong>Atomic Radius</strong></td><td>Decreases ($\rightarrow\downarrow$)</td><td>Increases ($\downarrow\uparrow$)</td><td>Effective nuclear charge ($Z_{\text{eff}}$) pulls electrons closer across; added shells increase distance down.</td></tr>
                <tr><td><strong>Ionization Energy</strong></td><td>Increases ($\rightarrow\uparrow$)</td><td>Decreases ($\downarrow\downarrow$)</td><td>Higher $Z_{\text{eff}}$ binds valence electrons tighter; electron shielding weakens grip down group.</td></tr>
                <tr><td><strong>Electronegativity</strong></td><td>Increases ($\rightarrow\uparrow$)</td><td>Decreases ($\downarrow\downarrow$)</td><td>Pauling scale: Fluorine is highest ($3.98$), Francium lowest ($0.7$).</td></tr>
                <tr><td><strong>Electron Affinity</strong></td><td>Generally increases ($\rightarrow\uparrow$)</td><td>Generally decreases ($\downarrow\downarrow$)</td><td>Energy released when an electron is attached to a neutral atom in gaseous state.</td></tr>
                <tr><td><strong>Metallic Character</strong></td><td>Decreases ($\rightarrow\downarrow$)</td><td>Increases ($\downarrow\uparrow$)</td><td>Propensity to lose electrons and form cations.</td></tr>
            </tbody>
        </table>

