        <div class="content-box">
            <h4>Fundamental Rules of Electron Filling</h4>
            <ul>
                <li><strong>Aufbau Principle:</strong> Electrons occupy the lowest-energy orbitals first ($1s < 2s < 2p < 3s < 3p < 4s < 3d < 4p \dots$).</li>
                <li><strong>Pauli Exclusion Principle:</strong> No two electrons in the same atom can share identical sets of four quantum numbers ($n, l, m_l, m_s$). Each orbital holds at most 2 electrons with opposite spins.</li>
                <li><strong>Hund's Rule:</strong> Every orbital in a subshell is singly occupied with parallel spins before any orbital is doubly occupied.</li>
            </ul>
        </div>

