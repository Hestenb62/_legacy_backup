        <div class="content-box">
            <h4>Quantitative pH Equations (at $25^\circ\text{C}$ / $298\text{K}$)</h4>
            <p>$$\text{pH} = -\log_{10}[\text{H}^+] \qquad \text{pOH} = -\log_{10}[\text{OH}^-] \qquad \text{pH} + \text{pOH} = 14$$</p>
            <p>$$\text{Ion-Product Constant of Water: } K_w = [\text{H}^+][\text{OH}^-] = 1.0 \times 10^{-14}$$</p>
            <p>$$\text{Henderson-Hasselbalch Buffer Equation: } \text{pH} = \text{p}K_a + \log_{10}\left(\frac{[\text{A}^-]}{[\text{HA}]}\right)$$</p>
