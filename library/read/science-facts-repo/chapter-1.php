        <h3>1.6 Momentum, Collisions &amp; Gravitation</h3>
        <table class="ref-table">
            <thead>
                <tr><th>Law / Concept</th><th>Equation</th><th>Physical Meaning</th></tr>
            </thead>
            <tbody>
                <tr><td><strong>Linear Momentum</strong></td><td>$\vec{p} = m\vec{v}$</td><td>Vector quantity conserved in isolated systems: $\sum \vec{p}_i = \sum \vec{p}_f$.</td></tr>
                <tr><td><strong>Impulse</strong></td><td>$\vec{J} = \int \vec{F}\,dt = \vec{F}_{\text{avg}}\Delta t = \Delta \vec{p}$</td><td>Change in momentum produced by a force over duration $\Delta t$.</td></tr>
                <tr><td><strong>Elastic Collision</strong></td><td>$\Delta K = 0 \quad\text{and}\quad \Delta\vec{p} = 0$</td><td>Both mechanical kinetic energy and linear momentum are conserved.</td></tr>
                <tr><td><strong>Inelastic Collision</strong></td><td>$\Delta K \neq 0 \quad (\text{kinetic energy lost to heat/sound})$</td><td>Momentum is strictly conserved; bodies stick together if perfectly inelastic.</td></tr>
                <tr><td><strong>Newton's Universal Gravitation</strong></td><td>$F_g = G \frac{m_1 m_2}{r^2}$</td><td>Inverse-square law of mutual attraction between masses.</td></tr>
                <tr><td><strong>Kepler's 3rd Law of Planetary Motion</strong></td><td>$T^2 = \left(\frac{4\pi^2}{G M}\right) a^3$</td><td>The square of orbital period is proportional to the cube of semi-major axis.</td></tr>
            </tbody>
        </table>

