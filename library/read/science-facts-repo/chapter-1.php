                <tr><td>$v = v_0 + at$</td><td>$v, v_0, a, t$</td><td>$\Delta x$ (Displacement)</td></tr>
                <tr><td>$\Delta x = v_0 t + \frac{1}{2}at^2$</td><td>$\Delta x, v_0, a, t$</td><td>$v$ (Final velocity)</td></tr>
                <tr><td>$v^2 = v_0^2 + 2a\Delta x$</td><td>$v, v_0, a, \Delta x$</td><td>$t$ (Elapsed time)</td></tr>
                <tr><td>$\Delta x = \frac{v_0 + v}{2}t$</td><td>$\Delta x, v_0, v, t$</td><td>$a$ (Acceleration)</td></tr>
                <tr><td>$\Delta x = vt - \frac{1}{2}at^2$</td><td>$\Delta x, v, a, t$</td><td>$v_0$ (Initial velocity)</td></tr>
