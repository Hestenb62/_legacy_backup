        <h3>1.3 Newton's Three Laws of Motion</h3>
        <table class="ref-table">
            <thead>
                <tr><th>Law</th><th>Formal Principle</th><th>Mathematical Statement</th><th>Physical Significance</th></tr>
            </thead>
            <tbody>
                <tr><td><strong>First Law</strong><br>(Inertia)</td><td>An object remains at rest or in uniform motion at constant velocity unless acted upon by a net external force.</td><td>$\sum \vec{F} = 0 \implies \vec{v} = \text{constant}$</td><td>Defines inertial reference frames; resistance of matter to acceleration.</td></tr>
                <tr><td><strong>Second Law</strong><br>(Force &amp; Acceleration)</td><td>The rate of change of linear momentum equals the net external force applied to the body.</td><td>$\vec{F}_{\text{net}} = \frac{d\vec{p}}{dt} = m\vec{a}$ (for constant $m$)</td><td>Quantifies dynamical motion; $1\text{ N} = 1\text{ kg}\cdot\text{m/s}^2$.</td></tr>
                <tr><td><strong>Third Law</strong><br>(Action-Reaction)</td><td>When one body exerts a force on a second body, the second body exerts an equal and opposite force on the first.</td><td>$\vec{F}_{A\rightarrow B} = -\vec{F}_{B\rightarrow A}$</td><td>Forces occur exclusively in simultaneous pairs across distinct bodies.</td></tr>
            </tbody>
        </table>

        <h3>1.4 Kinematic Equations for Constant Acceleration</h3>
        <p>For one-dimensional rectilinear motion with initial velocity $v_0$, final velocity $v$, acceleration $a$, displacement $\Delta x$, and elapsed time $t$:</p>
        <table class="ref-table">
            <thead>
                <tr><th>Equation</th><th>Variables Present</th><th>Variable Omitted</th></tr>
            </thead>
