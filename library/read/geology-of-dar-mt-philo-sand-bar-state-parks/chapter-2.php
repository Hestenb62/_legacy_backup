<p>The fact that these two units are not parallel could mean that the
Stony Point Shale was deposited, hardened into rock, uplifted, folded
and eroded, all prior to the deposition of the Monkton Quartzite. But,
first, what is the age of the underlying Stony Point Shale? If the story is
as listed above, the Stony Point Shale <i>must be older</i><a class="fn pginternal" href="#fn_12" id="fr_12">[12]</a>
than the overlying Monkton Quartzite. From the fossil animal remains found in the Stony
Point Shale, geologists have dated the Stony Point Shale as upper middle
Ordovician (see Standard Geologic Time Scale, <a href="#fig4" class="pginternal">Fig. 4</a>). And so, here
we have older rocks (Lower Cambrian) resting on younger (upper
middle Ordovician).</p>
