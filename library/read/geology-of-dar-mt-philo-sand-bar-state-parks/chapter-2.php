<p>A second type of rock is exposed in the south bank of the exit road
approximately 0.7 miles from the summit area. This is the <i>black</i><a class="fn pginternal" href="#fn_10" id="fr_10">[10]</a> to
bluish-black Stony Point Shale (see <a href="#fig10" class="pginternal">Fig. 10</a>), which underlies the Monkton
quartzite. This shale, or hardened limy mud, is thinbedded and shows
abundant <i>cleavage</i><a class="fn pginternal" href="#fn_11" id="fr_11">[11]</a> parallel to the layers or beds. At this outcrop the
<span class="pb" id="Page_22">22</span>
layers strike to the northeast and dip 20 to 40 degrees toward the southeast.
The dip and strike of the Monkton Quartzite (see <a href="#fig9" class="pginternal">above</a>) is not
similar to the dip and strike of the underlying Stony Point Shale. It
follows, that the layers of the Monkton Quartzite are not parallel to those
of the Stony Point Shale.</p>
