<h2 id="c7"> <span class="small">THE GEOLOGY OF MT. PHILO STATE FOREST PARK</span></h2>
<h3 id="c8">INTRODUCTION</h3>
<p>Mt. Philo State Forest Park, consisting of some 160 acres, is located
about 15 miles south of Burlington and 1 mile east of U.S. Route 7
(see map, <a href="#fig1" class="pginternal">Fig. 1</a>). This park is noted for its scenic views, especially of
the broad Champlain Valley and the rugged Adirondack Mountains beyond
(see <a href="#imgx2" class="pginternal">cover</a> picture and <a href="#imgx6" class="pginternal">Fig. 7a</a>). From a 46-foot high observation
tower a panoramic view is easily gained. Picnic facilities, including stone
fireplaces, fuel wood, piped spring water and sanitary facilities are available.
A large rustic lodge with porch and portico provides protection from
sudden showers. Tenting on the top of Mt. Philo is not allowed.</p>
<h3 id="c9">THE GEOLOGY OF THE PARK</h3>
<h4> <i>The Rocks</i></h4>
<p>The rocks of the Park which will probably first attract your attention
are those exposed at the main western Overlook which is located in the
summit area. This Overlook is found just northwest of the Park lodge
(see <a href="#fig8" class="pginternal">Fig. 8</a>). These rocks are light to dark red or purplish in color, are
<span class="pb" id="Page_20">20</span>
primarily <i>quartzite with minor dolostone</i><a class="fn pginternal" href="#fn_9" id="fr_9">[9]</a>
dipping approximately 35 degrees
to the northeast (for an explanation of dip, see <a href="#fig3" class="pginternal">Fig. 3</a> and text of
D.A.R. State Park, <a href="#Page_6" class="pginternal">page 6</a>) and striking toward the northwest (for an
explanation of strike, see <a href="#fn_1" class="pginternal">immediately preceding reference</a>).</p>
<p>A closer look at this Monkton Quartzite outcrop shows that it is
made up of several layers of rock (see <a href="#fig8" class="pginternal">Fig. 8</a>). These layers, strata, or
beds are not all of the same thickness, but are generally from 1 inch to
1 foot thick. If an individual layer is traced over the extent of the outcrop,
it is found that its thickness remains about the same throughout.
It is therefore said to be regularly bedded. Thin laminations of dark red
shale are abundant and commonly define individual layers. A magnified
look at a specimen of this quartzite, under a hand lens, shows that it is
composed of fine to coarse fragments of quartz. Some of these fragments
have rounded edges, but others are quite angular. The spaces between
the fragments are filled with silica (quartz). Therefore, the rock
is said to possess a silica cement.</p>
<p>In many places where this Monkton Quartzite has been studied, features
attesting to a shallow water origin have been found. Among these
features are mud cracks, which form under alternating wet and dry
conditions; ripple marks, which are usually found only on shallow water
bottoms; and cross-bedding, which commonly forms in shallow water
areas.</p>
<p>The Monkton Quartzite underlies approximately a third of the Park
(see Geologic map, <a href="#fig9" class="pginternal">Fig. 9</a>). This quartzite is between 250 and 300 feet
thick on Mt. Philo; however, the lower 50 feet or so consist predominantly
of white quartzite interbedded with dolostone. The age of the Monkton
Quartzite is considered to be Lower Cambrian (see Standard Geologic
Time Scale, <a href="#fig4" class="pginternal">Fig. 4</a>).</p>
