<h4> <i>Structural Geology</i></h4>
<p>How can we explain this inverted order of rock units? The geologic
evidence presented in the Park does not indicate that folding of the
rocks was responsible. From the surface distribution of the two rock
types (see Geologic map, <a href="#fig9" class="pginternal">Fig. 9</a>) and the nature of their contact with
each other, a fault relation is envisioned, in which older rocks were
thrust westward over the younger and thus to rest upon them (see <a href="#fig11" class="pginternal">Fig. 11</a>).</p>
<p>We know the ages of both rock units involved in this thrust fault but
what is the geologic age of the actual thrust movement? Both the Stony
Point Shale and the Monkton Quartzite were hard rock when this thrusting
took place, therefore, the thrusting would have occurred later than
upper middle Ordovician time, but before late Silurian time. Two other
fault systems are recognized in or near the Park (see Geologic map, <a href="#fig9" class="pginternal">Fig. 9</a>).
They are <i>high angle</i><a class="fn pginternal" href="#fn_13" id="fr_13">[13]</a>
faults which formed later than the thrust fault,
but still preceding late Silurian time.</p>
<div class="pb" id="Page_24">24</div>
<p>The Iberville Shale (this is not described in the section on “The
Rocks,” but is seen on the Geologic map, <a href="#fig9" class="pginternal">Fig. 9</a>), which is questionably
exposed on the south side of Mt. Philo, would be the youngest rock
found in the Park. This shale is about 390 million years old. The most
recent faulting took place no later than about 340 million years ago.
There are no rocks in the Park which give us any positive geological
clues to the Park’s history from the last episode of faulting to the Pleistocene
glaciers less than 1 million years ago. However, the fact that rocks
representing this interval of time are not present does indicate that the
area was above water during most of these 339 million years (this number
of years is very approximate). If any rocks were deposited during
this “rock-gap” period, they have since been washed away.</p>
<h4> <i>The Pleistocene Deposits</i></h4>
<p>Beginning between 60,000 and 70,000 years ago two glacial advances
and retreats took place in the Champlain Valley. This was during the
most recent or the Wisconsin Stage of the Pleistocene Epoch. Scratches
or striations were cut into the overridden rock by rock debris carried
along at the base of the ice as it advanced (note the arrow in (“br”)
area at overlook in <a href="#fig12" class="pginternal">Fig. 12</a>; this shows striation orientation, therefore,
the direction in which the glacier advanced). The glacial sediments found
on Mt. Philo were deposited during the final retreat of glacial ice, which
took place from 11,000 to 12,000 years ago. Most of the Park is covered
with these glacial deposits and by more recent soils.</p>
<p>Most of the glacial deposits found on Mt. Philo are classified as
glacial <i>till</i><a class="fn pginternal" href="#fn_14" id="fr_14">[14]</a>
(see Map of Glacial Deposits, <a href="#fig12" class="pginternal">Fig. 12</a>), but other glacial
deposits are also mapped. A <i>kame</i><a class="fn pginternal" href="#fn_15" id="fr_15">[15]</a>
(designated “K” in <a href="#fig12" class="pginternal">Fig. 12</a>) is a
glacial feature found in the southern part of the Park.</p>
