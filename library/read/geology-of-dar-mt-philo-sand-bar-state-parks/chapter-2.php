<p>With the slow retreat of the glacial ice front from the Mt. Philo
region, deposits were left which indicate that a series of lakes formed
in front of the wasting ice mass. There is also evidence just west of Mt.
Philo (see “bgm” in <a href="#fig12" class="pginternal">Fig. 12</a>) which indicates that just prior to the
formation of present-day Lake Champlain, an arm of the Atlantic Ocean
reached into the Champlain Valley from the St. Lawrence River region.
Lake-beach gravels (designated “bg” in <a href="#fig12" class="pginternal">Fig. 12</a>) are found on both
the east and west slopes of Mt. Philo. The interesting fact about these
beach gravels is that they occur almost 500 feet above the present-day
level of Lake Champlain. Lake sand (designated “ls” in <a href="#fig12" class="pginternal">Fig. 12</a>) is
found some 450 feet above Lake Champlain. This means that during a
<span class="pb" id="Page_26">26</span>
good portion of its recent geologic history, Mt. Philo was an island surrounded
by lake water. From the distribution of marine beach gravel
(designated “bgm” in <a href="#fig12" class="pginternal">Fig. 12</a>), it appears that the invasion of sea water
from the St. Lawrence region did not isolate Mt. Philo as an island.</p>
<p>The complete story of the lake series is still not known, but, for the
most up-to-date treatment of this subject see D. P. Stewart’s paper entitled
“The glacial geology of Vermont”: Vermont Geological Survey
Bulletin 19 (1961). Suggested also is C. H. Chapman’s article entitled
“Late glacial and postglacial history of the Champlain valley” in the
American Journal of Science, 5th series, volume 34, pages 89-124
(1937). Looking out over the Champlain lowlands from the summit of
Mt. Philo leaves little doubt in the visitor’s mind as to the prior existence
of lakes which surrounded Mt. Philo in the not too distant past (see
<a href="#imgx2" class="pginternal">Cover</a> picture).</p>
<h4> <i>Summary of the Geologic History</i></h4>
<p>During lower Cambrian time, the Monkton Quartzite and dolostone
followed by the Winooski Dolostone (not seen in the Park) were deposited
east of Mt. Philo State Forest Park. During late Cambrian and
early Ordovician, thick dolostones were deposited from the sea water
which covered the Mt. Philo area (not seen at the surface in the Park).</p>
<p>During middle Ordovician time, a series of shale, calcareous shale
and limestone was deposited from the sea water. Then, sometime between
the beginning of late Ordovician and late Silurian time, the eastern lower
Cambrian sequence was thrust westward over the middle Ordovician
rocks. This low-angle thrusting was succeeded by high angle faulting.</p>
<p>The Park rocks were subjected to weathering and erosion for over
300 million years or until glaciers advanced over the area less than
60,000 to 70,000 years ago. Advancing glaciers scoured the rock; retreating
or wasting glacial ice left deposits of clay, sand and gravel in
the Park. A series of lakes formed south of the northward wasting glacial
ice and deposits of beach-gravel and lake-sand formed along the slopes
of Mt. Philo, which was then an island. An arm of the sea next advanced
southward into the Champlain Valley leaving marine beach-gravels just
west of Mt. Philo. The marine waters retreated and present-day Lake
Champlain came into existence. The formation of the present soil cover
and the deposition of recent alluvium from presently flowing rivers and
streams concludes this brief summary of the Park’s geologic history.</p>
