<h3 id="c4">THE FOSSILS</h3>
<p>Many groups of invertebrates are represented in the fossils of D.A.R.
State Park. <a href="#imgx5" class="pginternal">Plate 1</a> will help you to identify these fossils. The name,
phylum (major group) and age of each fossil are provided in the explanation
of the plate. The following paragraphs describe each phylum
represented in the Park rocks.</p>
<div class="pb" id="Page_10">10</div>
<div class="img" id="imgx5">
