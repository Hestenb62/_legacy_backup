<p>Search the top of a few layers and you will notice many shell and
other animal impressions. Do they represent animals which lived hundreds
of millions of years ago or were they washed onto these rocks
from present-day Lake Champlain? If you try to make a collection of
the shell impressions you will see that they are a part of the rock and
therefore must represent remains of animals that were buried in the
<span class="pb" id="Page_8">8</span>
ancient lime muds. These preserved <i>remains</i><a class="fn pginternal" href="#fn_3" id="fr_3">[3]</a>
are called fossils. The
geologist who specializes in the study of fossils is called a <i>paleontologist</i>.
You may ask, “What can fossils tell me about the past?” In the first
place, fossils tell us at what time in the past the sediments in which they
are found were deposited. In this way, the <i>relative age</i><a class="fn pginternal" href="#fn_4" id="fr_4">[4]</a>
of the rock layers found in the Park can be learned. Secondly, the environment or
surroundings in which these ancient sediments were deposited can be
reconstructed from the types of fossils contained within them. Certain
animals living today are quite similar to those in the Park rocks and
their environment in today’s sea can be used to reconstruct the environment
of animals which lived in the past. The characteristics of the
rocks and their relation to adjacent rocks are considered in any reconstruction
of past environment. In the third place, the study of fossils is
a mainstay of the theory of evolution. That is to say, changes in fossil
forms collected from groups of successively younger rock layers document
the theory that life has evolved little by little since its first appearance
on Earth. Finally, it should be mentioned that some animals found
as fossils are not living today and have not lived, to the best of our
knowledge, for millions of years. Why did these forms of life die out?
What set of circumstances led to their extinction? The answers to these
questions are not easy to find and they are highly speculative.</p>
