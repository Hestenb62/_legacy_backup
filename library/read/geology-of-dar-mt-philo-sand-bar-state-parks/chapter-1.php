<h2 id="c1"> <span class="small">THE GEOLOGY OF D.A.R. STATE PARK</span></h2>
<h3 id="c2">INTRODUCTION</h3>
<p>D.A.R. State Park is located in western Vermont on State Highway
17, approximately 1 mile north of Lake Champlain (toll) Bridge (see
map, <a href="#fig1" class="pginternal">Fig. 1</a>). The park, which fronts on Lake Champlain, contains undeveloped
acres on the east side of the Highway. Tenting, leanto camping,
picnicking and swimming are adequately provided for during the
summer months.</p>
<p>This park, more than most others, not only awakens the visitor’s
curiosity about the past history of the Earth, but satisfies it. The story
of an ancient sea and the life which existed in it can be read from the
rocks exposed in D.A.R. State Park. You can read this story for yourselves.
This Pamphlet is designed as an aid to a more complete understanding
of the observations which you make. “Reading the rock record”
is not difficult, but the geologist does have the advantage of possessing
a certain trained scientific approach to these problems. This method
of approach, the “tools of the trade,” will now be passed on to you.</p>
<div class="pb" id="Page_6">6</div>
<h3 id="c3">THE GEOLOGY OF THE PARK</h3>
<p>The park beach is the ideal place to study the rocks of the park,
for here the rocks are best exposed and can be easily examined at close
range. The attitude of the rock layers can be seen on a walk down the
ramp. By attitude is meant their relationship to an imaginary horizontal
plane, which for our purposes is the level of the lake. Are the rock layers
parallel to the surface of Lake Champlain or do they slant or dip into
it? If the layers were parallel to the surface they would not “dip.” The
dip of the park strata (layers) is seen in <a href="#fig2" class="pginternal">Figure 2</a>. Dip is expressed in
the number of degrees <i>down</i> from the horizontal and here the dip is
toward the west and is measured to be between 8 and 11 degrees. The
dip is always measured perpendicular to an imaginary horizontal line
on a rock layer called a “strike line.” The average “strike,” or compass
direction of the “strike line” is 22 degrees east of <i>north</i>.<a class="fn pginternal" href="#fn_1" id="fr_1">[1]</a></p>
<p><i>Sedimentary rocks</i><a class="fn pginternal" href="#fn_2" id="fr_2">[2]</a> crop out on the park beach. These were originally
lime mud resting on the sea bottom. Under continued pressure from
the overlying sediments resulting from continued deposition and burial,
the muds were slowly compacted and cemented into the hard limestones
and limy shales which we see today. The many layers of rock were then
tilted. Tilted layers tell the geologist of giant earth movements which
took place since their formation. The story of these movements will be
developed later in this pamphlet.</p>
<p>As you look at the tilted rock layers from the ramp, can you tell
which layers are the oldest, that is, those first deposited as lime muds
on the sea bottom? A basic geologic law, the Law of Superposition,
states that if a series of sedimentary layers have <i>not</i> been overturned,
the oldest is on the bottom and the youngest on top. Assuming that the
layers which you are looking at have not been overturned, those on your
left (south) are the oldest and those on your right (north) the youngest.
Looking at <a href="#fig2" class="pginternal">Figure 2</a>, taken from the ramp-bottom toward the north, the
layers in the foreground are older than those in the distance. Let us take
a close look at the individual layers of rock and delve deeper into the
story that they have to tell.</p>
