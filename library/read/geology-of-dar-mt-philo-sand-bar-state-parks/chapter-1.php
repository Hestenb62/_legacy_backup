<p><i>Brachiopods.</i> Brachiopods are abundant in the Park rocks (see <a href="#imgx5" class="pginternal">Plate 1</a>,
4A, B; 5; 6; 9; 10; 11; 12). These invertebrates are small marine
animals which generally live in waters no deeper than 600 feet. The
two valves of their shell are joined at the back (posterior) end of the
body along a hingeline of interlocking teeth and sockets. The shell of
the brachiopod is opened or shut by muscles attached to the inside of
each valve. Brachiopods are found in the oldest rocks containing definite
and abundant fossils. Brachiopods are still living today.</p>
<div class="pb" id="Page_13">13</div>
<p><i>Bryozoans.</i> Bryozoans or “moss animals” are very small marine animals
which live in colonies. The bryozoans construct their mutual home
or colony of lime which is commonly preserved for the fossil record.
Large colonies of the fossil Prasopora (prah-sop-OR-ah) are commonly
seen on the weathered surfaces of many of the rock layers in the Park
(see <a href="#imgx5" class="pginternal">Plate 1</a>; 7A, B, C; 8 and <a href="#fig5" class="pginternal">Figure 5</a>). Individuals of one genus common
here, can be recognized by their chocolate drop shapes. Bryozoans
first appear in lower Paleozoic rocks and are still living today in clear
well-circulated shallow to deep marine water. Considering all of the
fossils found in the Park rocks, the past environment is thought to have
been a relatively shallow and warm sea.</p>
