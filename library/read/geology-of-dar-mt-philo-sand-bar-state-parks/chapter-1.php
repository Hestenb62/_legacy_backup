<h3 id="c5">THE ROCKS AND THEIR HISTORY</h3>
<p>Approximately 75 vertical feet of the Glens Falls Limestone occur
along the Park beach. The rocks are <i>black</i><a class="fn pginternal" href="#fn_8" id="fr_8">[8]</a> or blue-black on a fresh
surface, gray or grayish-white on a surface which has been exposed to
the weather. Most of the individual beds or layers are 5 to 7 inches
thick (see <a href="#fig6" class="pginternal">Fig. 6</a>) with the thickest being just under 5 feet. The beds are
separated by thin “partings” of rock, many of which contain abundant
fossils. The beds consist of massive limestone, shaly limestone or limy
shale; the partings are generally limy shale or shaly limestone.</p>
<div class="pb" id="Page_15">15</div>
<div class="box">
<p class="center"><b><span class="large"><i>Explanation for <a href="#fig7" class="pginternal">Figure 7</a></i></span></b></p>
<p>1. Glens Falls and younger sediments were deposited on the Ordovician sea floor.</p>
<p>2. Sediments hardened into Glens Falls Limestone and younger rocks.</p>
<p>3. Rocks were tilted during the late Ordovician Taconic Disturbance and the
younger rocks and part of the Glens Falls Limestone were removed by erosion.
Erosion continued for some 350 million years.</p>
<p>4. During the Pleistocene Epoch, which started some 1 million years ago, glacial
ice overrode the beveled layers of the Glens Falls Limestone. Hard rocks
frozen to the underside of the glacial ice produced scratches or striations in
the exposed layers of the Glens Falls Limestone.</p>
<p>5. Glacial lakes Vermont form as the glaciers retreat northward. In between the
glacial lakes Vermont and present Lake Champlain, marine waters flooded
the valley and formed an arm of the Atlantic Ocean. Clay, silt, sand and
gravel were deposited on glaciated Glens Falls Limestone (<a href="#imgx4" class="pginternal">Fig. 1a</a>).</p>
<p>6. Present-day Lake Champlain formed when relatively greater uplift in the
north dammed the Champlain valley.</p>
</div>
<p>The rock types found in the Park lead to certain conclusions regarding
the environment which existed during their formation. Most of
the rocks are composed of lime (limestone) or a mixture of lime, fine
sand and mud (limy shale or shaly limestone). The mineral pyrite
(FeS₂) is present in many of the rocks. Most of the rocks contain
abundant amounts of organic matter. The sediments which make up
these rocks were carried to the Ordovician sea by streams flowing primarily
from the east. As these streams entered the quiet sea waters the
larger followed by the smaller particles began to settle to the bottom.
Lime was slowly precipitated from the warm sea water and pyrite formed
under stagnant bottom conditions. Organic material accumulated on the
bottom and intermixed with the sediments. The poor life-sustaining
qualities of much of the bottom waters prevented rapid or complete
bacterial action on the accumulated debris and the sediments remained
“organic black” in color. Slowly, as the weight of overlying sediments
increased, the lower layers were compacted and cemented into the hard
limestone and shale which we see today.</p>
<div class="pb" id="Page_16">16</div>
<p>The tilt or dip of the Park rocks resulted from subsequent earth
movements. When were these rocks tilted? From the evidence presented
in the Park all that can be said is that they were tilted sometime after
hardening and before the Pleistocene glaciers overrode the region during
quite recent times (at least 10,000 years ago). Thus, there are some
350 million years of rock record missing in the Park. Can we tell what
happened during these “missing” years through a study of only the
Park rocks? The answer to this question is partially “yes,” but we must
look to the work done in adjacent areas for a more complete story.</p>
<p>The mere fact that there are no rocks representing these millions
of years tells us that the sea had withdrawn from the area and that
the previously deposited rocks were undergoing erosion during most or
all of the missing rock gap (the time not represented by rocks). Information
from adjacent areas, however, tells us that the Park rocks were
tilted during the Taconic Disturbance which occurred during the final
stages of the Ordovician Period. East of the Park, Taconic earth movements
are more dramatically exhibited. The rocks are tilted even more
than in the Park and are broken by faults or cracks in the earth’s crust.
Some of these faults, known as thrust faults, positioned giant slabs of
rock far from their original locations and placed older on top of
younger rocks.</p>
<p>Following these earth movements there occurred a long period of
erosion. Many of the rock layers were stripped off and carried piece by
piece by rivers to other regions. Hundreds of millions of years passed
and then, less than one million years ago the great glacial ice sheets
slowly advanced southward over the Park area. Pieces of hard rock
frozen to the underside of the ice sheets scratched and scraped the rock
surfaces leaving these scratches or striations for us to see today (near
the northern end of the Park beach these striations are common on the
outcropping rock). The retreating glaciers created a series of lakes in
which clay, silt, sand and gravel were deposited. Today these sediments
are found resting on the beveled edges of the Park rocks.</p>
<p>Present-day Lake Champlain owes its existence to a general uplift
of the earth’s surface, greater in the north than in the south, perhaps
due to the removal of the heavy glacial ice sheet from the area. The
greater uplift in the north dammed the Champlain valley which slowly
filled with water. For a diagrammatic picture of the geologic history of
D.A.R. State Park, see <a href="#fig7" class="pginternal">Figure 7</a>.</p>
