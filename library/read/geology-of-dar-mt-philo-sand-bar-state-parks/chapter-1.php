<p><i>Arthropods.</i> D.A.R. State Park rocks contain trilobites with the following
imposing names: <i>Cryptolithus tesselatus</i>
(crip-toe-LITH-us tessell-AH-tus<a class="fn pginternal" href="#fn_5" id="fr_5">[5]</a>),
<i>Isotelus gigas</i> (ice-so-TELL-us GIG-us) and <i>Flexicalymene
senaria</i> (flex-eye-cal-ah-Mean-ee sen-AREA). These fossils are
figured on <a href="#imgx5" class="pginternal">Plate 1</a>, 1-A, B, C, D; 2; 3. Within the Park <i>Cryptolithus
tesselatus</i> is very common wherever fossils occur. Generally only the
cephalon or head portion of this trilobite is preserved. The cephalon is
<span class="pb" id="Page_11">11</span>
easily recognized by three concentric rows of pits arranged around the
brim. <i>Cryptolithus</i> is an excellent <i>index fossil</i><a class="fn pginternal" href="#fn_6" id="fr_6">[6]</a>
for the Park rocks. The arthropod phylum is characterized by animals with jointed legs,
segmented bodies and a jointed outer armour of <i>chitin</i>.<a class="fn pginternal" href="#fn_7" id="fr_7">[7]</a> For examples, the
crabs, lobsters, spiders, scorpions and insects are arthropods. Trilobites
appear early in the fossil record but they did not survive beyond the
Paleozoic Era.</p>
