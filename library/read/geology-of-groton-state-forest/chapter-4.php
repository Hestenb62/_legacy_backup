<h2 id="c10"> <span class="small">GEOLOGY OF NEARBY AREAS</span></h2>
<h3 id="c11"> <i>Ricker Mills</i></h3>
<p>Just south of the park at Ricker Mills some of the oldest rocks in the
area are exposed in the railroad cut just north of the highway crossing.
These rocks belong to a thick sequence of similar rocks which are collectively
called the <i>Waits River formation</i>. Studies in other areas indicate
that these rocks belong to the portion of geologic time called the Ordovician
period which was more than 350 million years ago.</p>
<p>The Waits River formation represents a series of sediments which
accumulated at the bottom of a shallow sea during Ordovician time.
These sediments included both limy and sandy beds, and fossils may
originally have been preserved in some of the beds. Sediments of other
types later accumulated over the Waits River formation during a long
period of geologic time, so that eventually the formation became deeply
buried. (See <a href="#fig3" class="pginternal">Figure 3</a>.) The sea retreated and the rocks were subjected
to high pressure and temperatures during a period of mountain-building.
The rocks which had been sedimentary were folded and converted to
<i>metamorphic rocks</i> by partial melting and recrystallization of the components.
As a result the rocks became schists or marbles. Any fossils
which may have been present were destroyed or badly altered in the
process. This is unfortunate because valuable geologic information as
the age of the rocks can be determined from the type of fossils present.</p>
<p>The rocks of the Waits River formation at Ricker Mills are dominantly
mica schists with layers containing limy material. These are too impure
to be considered marble but enough lime is present so that they react
strongly with acid, a test for detecting the presence of lime. The schists
principally contain quartz, biotite, calcite (lime) with lesser amounts of
muscovite, feldspar and impurities. The rocks weather to dark colors;
the gray limy beds are particularly susceptible to weathering and turn
dark brown to black on the surface. When more lime is present, the rock
weathers to a deep brown porous rock which resembles decayed wood.
Some boulders of these altered limestones are found in the glacial deposits
in the State Forest.</p>
<p>An additional factor which makes the rocks in the railroad cut at
Ricker Mills look “messy” is the iron and manganese staining and the
formation of mineral crusts on the surface of the rocks through the action
of ground water. Rain water falling on the hills above passes through the
soils, dissolving minerals, and precipitating them where the water seeps
out and evaporates at the lower level of the railroad tracks.</p>
