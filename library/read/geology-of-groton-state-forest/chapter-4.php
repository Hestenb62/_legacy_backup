<p>The schists trend about N.80°W. and dip about 30° to the northeast.
Along the length of the rock exposures it can be seen that this dip
is not constant but varies from 10 to 30°. The variation in dip gives the
schists a wavy appearance.</p>
<p>At two places along the railroad cut, the schist has been intruded by
granite. As is shown in <a href="#fig6" class="pginternal">Figure 6</a>, which is a sketch of the rocks exposed
on the east side of the railroad, the granite forms vertical dikes. As the
schist ends abruptly at the contact of the granite, this indicates that the
granite formed after the schist. The granite is nearly the same as the
granite in Groton State Forest except that the mica is muscovite rather
than biotite. For this reason the granite is lighter in color on fresh
surfaces. In general the exterior is dark in color due to the staining of
iron from weathering of the mineral pyrite, an iron sulfide, which occurs
in small amounts in the granite.</p>
<h3 id="c12"> <i>Jerry Lund Mountain</i></h3>
<p>On top of Jerry Lund Mountain occur other outcrops of the Waits
River formation and granite. Their exact relationships cannot be seen
easily because of the thick vegetation. The Waits River formation on
Jerry Lund Mountain is composed principally of quartz mica schist.</p>
