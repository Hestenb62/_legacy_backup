<h2 id="c13"> <span class="small">TRIPS TO TAKE</span></h2>
<h3 id="c14"> <i>Hiking in the State Forest</i></h3>
<p>The hike from the end of the road to the top of Owlshead Mountain
takes only ten to fifteen minutes. A splendid view of the surrounding
area, particularly Groton and Kettle ponds, is obtained from here. If
possible, everyone who visits the park should take this short walk. The
granite is well-exposed at the summit and dikes of aplite and pegmatite
may be seen.</p>
<p>The more venturesome park visitor will want to make other trips
away from the “beaten path” into the wilderness of the Vermont woods.
The principal difficulty arises in that the wilderness is so real a person
may well become lost if he strays too far from the trails. Some of the
trails have become overgrown so that they are difficult to follow and
portions of others have been destroyed by the damming up of brooks by
the beavers. It is suggested that in planning hikes information be obtained
from the park superintendent about the condition of the various
trails.</p>
