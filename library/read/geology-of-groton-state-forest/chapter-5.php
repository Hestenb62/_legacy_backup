<p>An interesting hike can be made from Osmore Pond to Deer Mountain
but as the trail is poorly marked, one must maintain a sense of direction.
From the Osmore picnic area walk south near the shore of the pond to
its outlet into Osmore Brook. At this point turn left to the northeast and
follow the trail which parallels a wire marking the edge of the game
preserve. About three-fourths of a mile from Osmore Brook the trail
meets another trail at right angles. To the left the trail follows the game
preserve boundary northwestward. The trail to the right leads directly
to the top of Deer Mountain where a view may be obtained on the south
side of the summit. As an alternate route for returning, follow the trail
along the game preserve to the northwest. Some distance beyond a
shelter-lean-to the trail divides several times with the main trail leading
to Blake Hill and other trails to the left leading to the Osmore Pond road.</p>
<p>A hike along the trail on the north side of Kettle Pond to the shelter-lean-tos
makes a pleasant trip along the water. Also, the trail from Owlshead
Mountain to Osmore Pond is convenient for a short hike through
the woods, if the trail can be found.</p>
<h3 id="c15"> <i>Quarries at East Barre</i></h3>
<p>The granite quarries at East Barre are in nearly the same type of
rock as that which occurs at Groton State Forest. The quarry operations
are interesting and educational and the quarries afford a good opportunity
of seeing fresh, unaltered specimens of granite. Guide service is
offered at some of the quarries.</p>
