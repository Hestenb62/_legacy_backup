<h2 id="c16"> <span class="small">FOOTNOTES</span></h2>
<div class="fnblock"><div class="fndef"><a class="fn pginternal" href="#fr_1" id="fn_1">[1]</a><i>Granite</i> is a type of igneous rock consisting of large interlocking grains of light-colored
minerals. Rocks are classified as being either igneous, sedimentary, or metamorphic.
<i>Igneous</i> rocks form by the solidification of molten material; <i>sedimentary</i>
rocks form by the accumulation of sediments derived from older rocks; and <i>metamorphic</i>
rocks form by the recrystallization of older rocks under conditions of high
temperatures and pressures.
</div><div class="fndef"><a class="fn pginternal" href="#fr_2" id="fn_2">[2]</a><i>Dip</i> is the inclination of a surface as, for example, a joint surface described above.
</div><div class="fndef"><a class="fn pginternal" href="#fr_3" id="fn_3">[3]</a><i>Schist</i> is the name
given to rocks in which the minerals have a parallel alignment
due to reorganization of the rock constituents during a condition of high temperature
and pressure. The platy minerals, like mica, form at right angles to the pressure so
that the resulting rock may have a “bedded” appearance.
