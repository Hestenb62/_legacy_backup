<p>The <i>pegmatite</i> dikes are coarse-grained, in some cases consisting of
individual mineral grains as much as two to four inches in diameter. The
mineral composition of the pegmatites is nearly the same as the granite,
except that biotite is usually absent. Because of their larger grain size,
the minerals can be recognized more easily in pegmatites than in either
granite or aplite. Quartz is glassy and breaks with smooth curved fractures.
Feldspar is chalky white, or pink, and may occur as tabular crystals
with straight-line contacts. It tends to break along definite intersecting
planes which can be seen in their reflecting position. Muscovite occurs as
“books” of semi-transparent leaves. The large “books” of muscovite are
particularly interesting because of the fascinating fact that a mineral
sheet can be split along a given planar direction into thinner and thinner
sheets until they are too thin to handle. Theoretically the mineral might
be split into sheets only as thick as one layer of atoms. The ability of a
mineral to break along definite planes is related to its atomic structure
and is called <i>cleavage</i>. The cleavage in mica is perfect, whereas the
cleavage in feldspar is only poorly developed, and quartz does not possess
cleavage at all.</p>
<p>The <i>aplite</i> dikes are composed of nearly the same minerals as granite
except that the average grain size is smaller. They are characterized by
the absence of dark minerals and muscovite and by a high quartz content
which gives the rock a “sugary” appearance. Most of the aplite dikes are
less than six inches thick.</p>
<p>Inasmuch as the pegmatite and aplite dikes both cut through the
granite, they both must be younger in age than the granite. As is shown
by the relations between these two types on Owlshead (reproduced in
<a href="#fig5" class="pginternal">Figure 5</a>), the pegmatite dike is younger because it cuts across the aplite
dike. This is the general age relationship for these dikes in this age.</p>
