<h3 id="c7"> <i>Aplite and pegmatite</i></h3>
<p>Two other types of igneous rocks called aplite and pegmatite occur
sparingly in Groton State Forest. Both of these are productions of
crystallization of residual fluids or late stage magma related to the
granite. These were emplaced along cracks or planes of weakness in the
granite after the granite had solidified. When viewed from the surface
the aplite or pegmatite generally appear as bands cutting through the
granite. However, when the third-dimension is considered it is easily
realized that they are tabular or sheet-like in shape. Igneous rock masses
having these dimensions are called <i>dikes</i>. At Groton most of the dikes
are nearly vertical with a thickness ranging from less than an inch to
more than several feet and extending for considerable distances. On
Owlshead, one of these dikes is nearly three feet thick. The extent of
these dikes is not known because they are only partly exposed, in that
they extend beyond the limited areas of rock exposure.</p>
