<p>Joints are more conspicuous of the two types, and typically belong
to a general system so that at a given location they tend to be parallel.
On top of Owlshead, for example, the most prominent joints trend
N.25°W. (read: North twenty-five degrees to the west) with
dips<a class="fn pginternal" href="#fn_2" id="fr_2">[2]</a> that
are vertical or dipping steeply to the southwest. Another set of joints
trends N.10°E. with dips that are vertical or dipping steeply to the southwest.
Joints represent the breakage of the rock due to stress and strain.
Some joints result from tensional forces set up within the rock itself by
contraction due to cooling of the originally hot solidified rock. Other
<span class="pb" id="Page_7">7</span>
joints result from larger-scale forces within the earth’s crust which cause
earthquakes and general movement of land masses. An exhaustive study
of all the rocks in a large area would be required to determine conclusively
the origin of the joints on Owlshead.</p>
<p>In addition to the nearly vertical joints, a third set of nearly horizontal
joints may be observed on cliffs. These joints are called <i>sheeting</i> and apparently
are related to the depth from a former topographic surface
which existed at the time the sheeting originated. The vertical joints and
sheeting are important qualities of a rock to be considered in choosing
a rock for commercial quarrying. Not only do these factors effect the ease
of quarrying, but they also determine the amount of waste material
which would have to be removed and discarded because of poor size and
shape.</p>
<p>Exfoliation is the term for breakage due to the disintegration caused
by decomposition of the rock on surfaces exposed to the weather. It is
characterized by the scaling off of concentric shells of altered rock to
produce a convex surface. Rocks showing exfoliation surfaces are not
common at Groton. One of the best developed exfoliation surfaces, illustrated
in <a href="#fig2" class="pginternal">Figure 2</a>, occurs at the base of the cliffs on the south side of
Owlshead Mountain.</p>
<p>Once joints have formed, they are enlarged by weathering. In particular,
rocks are pushed apart by a “frost wedging.” When water freezes it
expands by about one-tenth of its volume. If it is confined it may exert
a pressure of as much as 138 tons per square foot. In this manner, huge
blocks may be pushed apart. If they are at the edge of a cliff, or part of
the cliff itself, they may eventually break off and fall to the slope below.
The accumulation of broken rock at the base of a cliff is called <i>talus</i>.</p>
<h3 id="c6"> <i>Origin and age of the granite</i></h3>
<p>The granite originated in the interior of the earth many million years
ago as a molten mass, called <i>magma</i>. This magma moved upward
through the earth’s crust by a process of melting the pre-existing rock
or by forcefully pushing it aside. When it reached its present position it
became cooler and minerals began to crystallize out. However, as is
shown in <a href="#fig3" class="pginternal">Figure 3</a>, it is important to understand that the surface of the
land was not in its present position and that the magma actually cooled
beneath a considerable thickness of other rocks. These overlying rocks,
now gone, acted as an insulator and prevented the magma from cooling
too quickly. If the magma had risen through these rocks and reached
<span class="pb" id="Page_8">8</span>
their upper surface, it would have formed a lava flow similar to those of
present-day volcanoes and would have cooled much more rapidly. Rocks
formed near the surface are characterized either by being fine-grained
without visible crystals or by having a few large crystals in a fine-grained
matrix; they never have a uniformly, medium-to-coarse-grained texture.
Thus, the texture of the granite at Groton State Forest proves that it
cooled slowly and indicates that, at the time of cooling, the granite was
not at the surface. This is a reasonable postulation because studies of
the regional geology indicate that a large amount of rock has been
removed from this area by erosion through the long periods of geologic
time.</p>
