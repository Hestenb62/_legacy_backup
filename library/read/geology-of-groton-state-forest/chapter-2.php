<p>Evidence that the granite was emplaced into the older rocks of the
earth’s crust can be seen at certain locations outside of the State Forest.
At Ricker Mills, for example, narrow bodies of granite can be seen cross
cutting the older rocks. A fuller description of the geology at Ricker
Mills is given in a later section of this report. Another type of evidence
showing that the granite came into older rocks is found in the occurrence
of fragments of older rock incorporated into the granite. These are called
<i>inclusions</i> and represent broken pieces of older rock which were enveloped
by the granite. Inclusions are like peach slices in jello in that the surrounding
material solidified after they were dropped in. Inclusions were
observed in rocks on top of Kettle and Jerry Lund Mountains.</p>
<p>Near the covered picnic shelter at Ricker Pond, one of the large
granite boulders deposited by the glacier contains inclusions. Although
this boulder has been moved from its original occurrence, it probably
has not moved far as it is composed of the white granite which is typical
of the area. It is cut by several pegmatitic dikes. The most interesting
feature is the occurrence of inclusions of elongate, layered bands of older
rocks of gray to dark gray <i>schist</i>.<a class="fn pginternal" href="#fn_3" id="fr_3">[3]</a>
These relations are shown in the sketch
of this boulder in <a href="#fig4" class="pginternal">Figure 4</a>. A careful examination of the schist inclusions
reveals that they contain small plates of biotite in a fine matrix of quartz
and more mica. The contact between the schist and granite is gradational
at places because when the rock was formed the hot molten granite was
in the process of melting the solid schist. The schist resembles the rock
which occurred in this area before the granite was intruded and which
occurs in nearby areas where no granite is exposed. Older rocks of somewhat
similar appearance can be seen at Ricker Mills and on top of Jerry
Lund Mountain.</p>
<p>The composition of the granite at Groton State Forest is nearly the
same as that which occurs throughout this region of Vermont. Incomplete
mapping suggests that the granite at Groton is part of a large mass
which extends to the southwest to the vicinity of East Barre. Undoubtedly
all the granitic rocks of this region are related although they
<span class="pb" id="Page_11">11</span>
are not continuous at the surface. They were all emplaced at about the
same time following a mountain-building episode in which the older
rocks were folded and metamorphosed. On the geologic time scale, the
granites were emplaced near the end of the Devonian period which is
estimated to be more than 300 million years ago.</p>
