<h2 id="c2"> <span class="small">GRANITE AND RELATED ROCKS</span></h2>
<h3 id="c3"> <i>Occurrence of the granite</i></h3>
<p>Ledges of light-colored granite occur at the summits of most of the
mountains and hills in the State Forest area and are found occasionally
at lower elevations. They are conspicuous on Owlshead, Silver Ledge,
Little Deer, Big Deer, Niggerhead and Spicer Mountains; smaller ledges
also occur on Kettle, and Little Spruce mountains, Hardwood Ridge and
the low hills east of Groton Pond. At lower elevations, granite is found
at the outlet of Groton Pond, along the railroad tracks west of Groton
Pond and at Stillwater Brook, along Osmore brook and at several other
minor locations. These locations are shown diagrammatically on the
map by a black dot. These dots indicate where the granite occurs but
nothing about the extent of the exposure. If every location of exposed
rock were marked with a dot, certain parts of the map, for instance, the
west side of Niggerhead, would be solid black and the contour lines
which show the elevation would be obscured completely.</p>
<p>All these rocks are presumably part of one large mass of granite which
extends deep below the surface of the earth. Most of this body of granite
is hidden by the soil and bouldery glacial deposits, so that its exact areal
extent is not known. It appears likely that it extends to the southwest
to the vicinity of East Barre.</p>
<h3 id="c4"> <i>Description of the granite</i></h3>
<p>The granite found at Groton State Forest is a gray to white, medium-grained
rock with the mineral grains all about the same size. Surfaces
exposed to weathering are generally darker in color and frequently are
<span class="pb" id="Page_5">5</span>
covered with scales of dark colored lichen. If the rock is broken to reveal
an unaltered surface close examination will disclose individual mineral
grains of mica, feldspar and quartz. <i>Mica</i> occurs as very small plates
which appear either white or colorless, called <i>muscovite</i>, or as black shiny
plates called <i>biotite</i>. The <i>feldspar</i>, which is the most abundant mineral
in the granite, has a chalky white appearance and may occur as tabular
grains which reflect light from their flat surfaces when held in the proper
position. <i>Quartz</i>, which contains only silicon and oxygen, the two most
common elements in the earth’s crust, is a transparent, glassy mineral
which has no flat surfaces. It may appear gray because one can look down
into the glassy mineral where there is no light source.</p>
<p>A specimen of granite from Owlshead was studied with a microscope
after it had been cut and ground to a thickness of only 0.03 millimeters.
Many minerals, which ordinarily appear to be opaque, are transparent
when ground this thin. By their various optical properties, the different
minerals can be identified and the composition of the rock can be determined.
<a href="#fig1" class="pginternal">Figure 1</a> shows a photograph, taken through a microscope, of one
of these thin sections of granite. By careful examination of the thin
section and by measuring the areal extent of the different minerals
present, the rock was determined to contain, by volume, 35 percent
quartz, 60 percent feldspar (in proportions of 25 percent <i>microcline</i>
feldspar, KAlSi₃O₈ and 35 percent <i>plagioclase</i> feldspar, NaAlSi₃O₈)
and 5 percent mica (in proportions of 4 percent biotite and 1 percent
muscovite). Although it is a member of the granite family, this rock
should, in strict terminology, be called a quartz monzonite rather than a
granite to indicate more precisely the mineral composition. Because of
slight differences in composition, granite from the same body may elsewhere
be correctly called granodiorite, quartz diorite or granite proper,
depending on the relative amounts of the two feldspars and quartz. In
this report these close distinctions have not been made and the rock is
simply called granite.</p>
<h3 id="c5"> <i>Cracks in the granite</i></h3>
<p>Two kinds of natural breaks, or cracks, occur in the granite in the
State Forest area. <i>Joints</i> are breaks which occur along plane surfaces and
<i>exfoliation</i> is the name given to the breakage along curved surfaces
related to the exposure of the rock. Granite, as contrasted with other
rocks, is characterized by its uniformity of texture and massiveness, so
that any cracks present are conspicuous.</p>
