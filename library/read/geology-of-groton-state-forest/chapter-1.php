<h2 id="c1"> <span class="small">INTRODUCTION</span></h2>
<p>Geology is the study of the history of the earth as recorded in its
rocks. This study explains why certain types of rocks and minerals occur
at one place and not another, why the forms of the land differ from one
region to another, and why particular animal and plant remains are
sometimes preserved as fossils in certain kinds of rocks. The professional
geologist makes these studies his business; the amateur finds these studies
a fascinating hobby; but the uninitiated person misses much of the
pleasure of travel. Anyone who notices the difference between rocks or
terrains and wonders “why?”, has a potential for geology. Many fall into
this class and it is for them that this booklet has been written. It is
hoped that with its aid, the traveler or vacationer may come to know
something about the geology of Groton State Forest. The author is confident
that those who come into the habit of observing nature and the
world around them will find more meaning in life itself. In any case,
those traveling with children may find answers to some of their questions
about minerals, rocks and mountains.</p>
<p>Groton State Forest is not a geologist’s paradise—as compared to
Yellowstone Park or the Grand Canyon—but it does contain interesting
rocks and land forms which can be explained geologically. In keeping
with the calm, subdued and mature atmosphere of the Vermont countryside,
the geology is unobtrusive. There are few jutting cliffs or bare rock
exposures; all is mantled with vegetation. If this vegetation could be
stripped away—admittedly, a postulation that would destroy the
wilderness and charm that belongs to Groton—boulders and gravelly
glacial deposits would be seen to fill the valleys. If in turn these boulders
and the soil could be stripped away, a continuous floor of rock would be
exposed. This would be a geologist’s paradise—square miles of bare rock
would be available for study. However, lacking the magic wand to perform
this feat, we must be satisfied to glean what information we can
from the existing rock exposures.</p>
<p>To use a pun, it can be said that almost all the rocks found at Groton
State Forest can be taken for granite. As well as has been determined,
<span class="pb" id="Page_4">4</span>
all the underlying rock is <i>granite</i><a class="fn pginternal" href="#fn_1" id="fr_1">[1]</a> and most of the boulders deposited by
glaciers of the last ice age are the same type of granite. To avoid confusion
in describing these rocks, the discussion has been divided into two
parts: the first deals with the granite of the bedrock, and the second
deals with the glaciation of the area and the deposits resulting from it. A
third section describes the geology in some of the nearby areas.</p>
