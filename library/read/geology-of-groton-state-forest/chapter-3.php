<h2 id="c8"> <span class="small">GLACIATION</span></h2>
<p>Although the causes of the ice ages remain a matter for conjecture, the
fact is established that the northern part of North America was covered
by a thick sheet of moving ice several different times beginning about a
million years ago. As the effect of the last glaciation erased much of the
evidence of previous glaciations, the present topography can be related
to that last one. Rather accurate dating by measuring the radioactive
decay of Carbon 14, indicates that the ice of the last glaciation retreated
from the area about 12,000 years ago. Because the climates between the
four glaciations were as warm, if not warmer, than our present-day
climate, geologists have speculated that the world may now be in a warm
period and that another ice age is scheduled to occur some time in the
distant future.</p>
<p>The effect of continental glaciation upon a land mass is twofold. First,
the glaciation acts as an erosive agent which tends to scoop out the areas
of softer rock and wear down the areas of more resistant rock. Secondly,
when the glacier begins to melt, it drops large quantities of gravel and
boulders which had become incorporated within the glacier. Most of this
material is picked up by the glacier as it moves over the land; some falls
onto the glacier where it occupies a valley. Some of the sand, gravel and
boulder deposits left by the glacier are distinctive in form and composition
and others are characterized by their complete lack of distinctive
shapes, and the utterly chaotic nature of the material deposited. The
deposits at Groton State Forest seem to be the latter type.</p>
<h3 id="c9"> <i>Erosion and deposition by the glacier</i></h3>
<p>The shape of Spicer, Owlshead, Little Deer and Big Deer mountains
are primarily the result of the erosive action of the glacier as it continually
moved southward over the land for a great number of years
during the last glaciation. When a continental glacier encounters a hill
or mountain of resistant rock, it tends to scour the rock on the up-ice
side of the hill and to “pluck out” the rocks on the leeward side. For this
reason these mountains have broad gentle slopes on the side from which
the glacier came and they drop off sharply on the side from which material
was removed by plucking action. The last part of <a href="#fig3" class="pginternal">Figure 3</a> illustrates
how these mountains may have been formed. Such prominent rock
exposures which have been subjected to glacial erosion originally showed
deep scratches, called <i>glacial striae</i>, cut by cobbles dragged along the
bottom of the glacier. Unfortunately, on most prominences in Groton
<span class="pb" id="Page_17">17</span>
State Forest exfoliation of the rock has erased these markings; but it is
possible that striae may be found on recently uncovered rock exposures.</p>
<p>The depressions in which Groton and Osmore ponds are located
probably represent areas in which the glacier scooped out material to
a greater depth than elsewhere either because of channeling of bottom
flow between topographically prominent features, or because of subtle
differences in rock hardness.</p>
<p>When the glacier retreated, that is when it was melting faster than it
was advancing, it dropped material in a helter-skelter manner. <i>End
moraines</i>, which are ridges of gravel formed where the front of the glacier
was stationary because of a close balance between rates of movement and
melting, are not evident in Groton State Forest. As far as can be determined,
the material was deposited irregularly over the entire area, so
that boulders dropped by the glacier are found everywhere. These are
particularly noticeable around the lakes where the fine material has been
removed and the soil and forest cover does not hide the boulders.</p>
<p>Almost all of the boulders deposited by the glacier are composed of
white granite similar to the rock which underlies the entire area. This
indicates that most of the boulders have not been transported very far.
However, occasionally boulders are found which are not characteristic
of the area and represent rocks brought in from the north. Such boulders
which are foreign to the area in which they are found are called <i>erratics</i>.
Most erratics in this area are dark-colored metamorphosed rocks in
which the minerals are oriented to give the rock a layered pattern. These
are called either <i>gneisses</i> or <i>schists</i> depending on whether the layering is
coarse or fine. Deposits of the glacier are exposed in two gravel or sand
pits near the Stillwater Camp site. These deposits are composed principally
of sand but contain scattered boulders of different sizes. A few
erratics are found in these deposits—particularly a variety of rock which
weathers to a soft, brown porous mass resembling decayed wood. These
sandy deposits probably were plastered onto the ground from the sole
of the creeping glacier or were simply let down as the glacier wasted
away.</p>
<p>Because of the irregular manner in which the glacier may deposit its
load of sand and gravel, the topography in such areas is uneven and
characterized by poor drainage. At a number of places in Groton swampy
areas occur at higher elevation which might normally be expected to be
well-drained. Some of these areas have become the sites of beaver dams
because they are ideal for damming up the water.</p>
