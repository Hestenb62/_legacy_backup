    <h2>Chapter 2: Syntax, Sentence Architecture &amp; Punctuation</h2>

    <div class="content-content">
        <p>Syntax is the study of how words are arranged to form meaningful sentences. Mastering sentence structure and punctuation rules is essential for precise communication, standardized testing, and academic writing.</p>

        <h3>2.1 Sentence Elements</h3>
        <table class="ref-table">
            <thead><tr><th>Element</th><th>Definition</th><th>Example</th></tr></thead>
            <tbody>
                <tr><td><strong>Subject</strong></td><td>Who or what the sentence is about</td><td><u>The committee</u> voted.</td></tr>
                <tr><td><strong>Predicate</strong></td><td>Everything said about the subject</td><td>The students <u>completed the assignment early.</u></td></tr>
                <tr><td><strong>Direct Object</strong></td><td>Receives the action of a transitive verb (what? whom?)</td><td>She wrote <u>a letter.</u></td></tr>
                <tr><td><strong>Indirect Object</strong></td><td>Receives the direct object (to whom? for whom?)</td><td>She wrote <u>him</u> a letter.</td></tr>
                <tr><td><strong>Object Complement</strong></td><td>Renames or describes the direct object</td><td>They named her <u>captain.</u></td></tr>
                <tr><td><strong>Subject Complement</strong></td><td>Follows a linking verb; renames or describes the subject</td><td>She is <u>a scholar.</u></td></tr>
                <tr><td><strong>Appositive</strong></td><td>Noun phrase that renames the adjacent noun</td><td>My mentor, <u>a retired professor</u>, advised me.</td></tr>
            </tbody>
        </table>

        <h3>2.2 Clause Types</h3>
        <table class="ref-table">
            <thead><tr><th>Type</th><th>Definition</th><th>Example</th></tr></thead>
            <tbody>
                <tr><td>Independent (Main)</td><td>Expresses a complete thought; can stand alone</td><td><em>She graduated with honors.</em></td></tr>
                <tr><td>Dependent (Subordinate)</td><td>Cannot stand alone; introduced by a subordinating conjunction or relative pronoun</td><td><em>because she studied every day</em></td></tr>
                <tr><td>Noun Clause</td><td>Functions as a noun (subject, object, complement)</td><td><em>What she said</em> surprised everyone.</td></tr>
                <tr><td>Adjective (Relative) Clause</td><td>Modifies a noun; introduced by who, whom, whose, which, that</td><td>The book <em>that she recommended</em> was outstanding.</td></tr>
                <tr><td>Adverb Clause</td><td>Modifies a verb, adjective, or adverb; introduced by subordinating conjunction</td><td>He left <em>before the meeting ended.</em></td></tr>
            </tbody>
        </table>

        <h3>2.3 Sentence Structures</h3>
        <table class="ref-table">
            <thead><tr><th>Structure</th><th>Definition</th><th>Example</th></tr></thead>
            <tbody>
                <tr><td>Simple</td><td>One independent clause</td><td><em>Birds sing.</em></td></tr>
                <tr><td>Compound</td><td>Two or more independent clauses joined by a coordinating conjunction or semicolon</td><td><em>Birds sing, and flowers bloom.</em></td></tr>
                <tr><td>Complex</td><td>One independent + one or more dependent clauses</td><td><em>Although it rained, the game continued.</em></td></tr>
                <tr><td>Compound-Complex</td><td>Two or more independent clauses + at least one dependent clause</td><td><em>Although it rained, the game continued, and the fans cheered.</em></td></tr>
            </tbody>
        </table>

        <h3>2.4 Phrase Types</h3>
        <table class="ref-table">
            <thead><tr><th>Phrase Type</th><th>Function</th><th>Example</th></tr></thead>
            <tbody>
                <tr><td>Noun Phrase</td><td>Functions as a noun</td><td><em>The old red barn</em> needs repair.</td></tr>
                <tr><td>Verb Phrase</td><td>Main verb + auxiliaries</td><td>She <em>has been studying</em> all night.</td></tr>
                <tr><td>Prepositional Phrase</td><td>Preposition + object; acts as adjective or adverb</td><td>The book <em>on the shelf</em> is rare.</td></tr>
                <tr><td>Participial Phrase</td><td>Participle + modifiers; acts as adjective</td><td><em>Exhausted from the race,</em> he collapsed.</td></tr>
                <tr><td>Gerund Phrase</td><td>Gerund + modifiers; acts as noun</td><td><em>Running a marathon</em> requires months of training.</td></tr>
                <tr><td>Infinitive Phrase</td><td>Infinitive + modifiers; acts as noun, adj., or adv.</td><td>She wanted <em>to finish early.</em></td></tr>
                <tr><td>Absolute Phrase</td><td>Noun + participle; modifies entire clause</td><td><em>His work completed,</em> he left the office.</td></tr>
            </tbody>
        </table>

        <h3>2.5 Sentence Errors to Avoid</h3>
        <table class="ref-table">
            <thead><tr><th>Error</th><th>Definition</th><th>Incorrect</th><th>Corrected</th></tr></thead>
            <tbody>
                <tr><td>Run-on</td><td>Two independent clauses joined without proper punctuation</td><td>I studied hard I passed the exam.</td><td>I studied hard; I passed the exam.</td></tr>
                <tr><td>Comma Splice</td><td>Two independent clauses joined with only a comma</td><td>She was tired, she kept working.</td><td>She was tired, yet she kept working.</td></tr>
                <tr><td>Fragment</td><td>Incomplete sentence lacking a subject or predicate</td><td>Running through the park.</td><td>She was running through the park.</td></tr>
                <tr><td>Dangling Modifier</td><td>Modifying phrase has no clear subject to modify</td><td>Walking home, the rain started.</td><td>Walking home, I got caught in the rain.</td></tr>
                <tr><td>Misplaced Modifier</td><td>Modifier positioned too far from what it modifies</td><td>He almost drove his children to school every day.</td><td>He drove his children to school almost every day.</td></tr>
                <tr><td>Faulty Parallelism</td><td>Items in a series are not grammatically parallel</td><td>She likes hiking, to swim, and biking.</td><td>She likes hiking, swimming, and biking.</td></tr>
            </tbody>
        </table>

        <h3>2.6 Punctuation Rules — Quick Reference</h3>

        <h4>Comma</h4>
        <ul>
            <li>After introductory elements: <em>After the storm, the sky cleared.</em></li>
            <li>Before coordinating conjunctions joining independent clauses: <em>She studied, but she was nervous.</em></li>
            <li>Between items in a series (Oxford/serial comma recommended): <em>red, white, and blue</em></li>
            <li>Around non-essential (nonrestrictive) clauses: <em>My brother, who lives in Chicago, called me.</em></li>
            <li>Between coordinate adjectives: <em>a long, difficult journey</em></li>
        </ul>

        <h4>Semicolon</h4>
        <ul>
            <li>Between independent clauses not joined by a conjunction: <em>The meeting ended; everyone left quickly.</em></li>
            <li>Before conjunctive adverbs (however, therefore): <em>She was late; however, she was prepared.</em></li>
            <li>In complex lists whose items contain commas: <em>Paris, France; Rome, Italy; and Athens, Greece.</em></li>
        </ul>

        <h4>Colon</h4>
        <ul>
            <li>After a complete clause to introduce a list or explanation: <em>She needed three things: patience, skill, and time.</em></li>
            <li>Before a formal quotation or elaboration: <em>His motto was simple: never quit.</em></li>
            <li><strong>Do not</strong> use a colon after a verb or preposition.</li>
        </ul>

        <h4>Dash (Em Dash —)</h4>
        <ul>
            <li>For strong parenthetical emphasis: <em>The result—after years of effort—was extraordinary.</em></li>
            <li>Before a summary or amplification: <em>She gave everything she had—her time, her money, her heart.</em></li>
        </ul>

        <h4>Apostrophe</h4>
        <ul>
            <li>Possession (singular): <em>the student's essay</em></li>
            <li>Possession (plural ending in s): <em>the students' essays</em></li>
            <li>Possession (plural not ending in s): <em>the children's books</em></li>
            <li>Contractions: <em>it's (it is), they're (they are), can't (cannot)</em></li>
            <li><strong>Never</strong> use an apostrophe for possessive pronouns: <em>its, hers, theirs, yours</em></li>
        </ul>

        <h4>Quotation Marks</h4>
        <ul>
            <li>Commas and periods go <strong>inside</strong> closing quotation marks (American English).</li>
            <li>Colons and semicolons go <strong>outside</strong> quotation marks.</li>
            <li>Use single quotes for a quotation within a quotation.</li>
        </ul>

        <h4>Hyphen vs. En Dash vs. Em Dash</h4>
        <table class="ref-table">
            <thead><tr><th>Mark</th><th>Use</th><th>Example</th></tr></thead>
            <tbody>
                <tr><td>Hyphen (-)</td><td>Compound modifiers before nouns; word division</td><td>well-known author, twenty-three</td></tr>
                <tr><td>En Dash (–)</td><td>Ranges of numbers, dates, scores</td><td>pages 10–25, 2001–2010</td></tr>
                <tr><td>Em Dash (—)</td><td>Parenthetical emphasis, abrupt break</td><td>She knew—without a doubt—it was true.</td></tr>
            </tbody>
        </table>
