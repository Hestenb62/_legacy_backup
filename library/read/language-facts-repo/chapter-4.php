    <h2>Chapter 4: Etymology, Greek &amp; Latin Roots &amp; Morphology</h2>

    <div class="content-content">
        <p>More than 60% of English words have Greek or Latin origins, rising to over 90% in scientific and academic vocabulary. Learning common roots, prefixes, and suffixes dramatically expands reading comprehension and vocabulary across all subjects.</p>

        <h3>4.1 Morphology — Word Formation Elements</h3>
        <table class="ref-table">
            <thead><tr><th>Term</th><th>Definition</th><th>Example</th></tr></thead>
            <tbody>
                <tr><td><strong>Root (Base)</strong></td><td>The core of the word carrying its fundamental meaning</td><td><em>port</em> (carry) → transport, portable, import</td></tr>
                <tr><td><strong>Prefix</strong></td><td>Added before the root to change or qualify meaning</td><td><em>un-</em> + happy = unhappy</td></tr>
                <tr><td><strong>Suffix</strong></td><td>Added after the root to change meaning or part of speech</td><td>teach + <em>-er</em> = teacher (noun)</td></tr>
                <tr><td><strong>Infix</strong></td><td>Element inserted within a word (rare in English)</td><td><em>-bloody-</em> in "abso-bloody-lutely" (informal intensification)</td></tr>
                <tr><td><strong>Free Morpheme</strong></td><td>Can stand alone as a word</td><td><em>book, run, happy</em></td></tr>
                <tr><td><strong>Bound Morpheme</strong></td><td>Cannot stand alone; must attach to another morpheme</td><td><em>-ness, un-, -ing</em></td></tr>
                <tr><td><strong>Compound Word</strong></td><td>Two or more free morphemes combined</td><td><em>sunlight, toothpaste, ice cream</em></td></tr>
            </tbody>
        </table>

