                <tr><td>Interrogative</td><td>who, whom, whose, which, what</td></tr>
                <tr><td>Relative</td><td>who, whom, whose, which, that</td></tr>
                <tr><td>Indefinite</td><td>anyone, each, few, many, none, several, somebody</td></tr>
                <tr><td>Reciprocal</td><td>each other, one another</td></tr>
            </tbody>
        </table>

        <h3>1.4 Verbs — Types &amp; Properties</h3>
        <table class="ref-table">
            <thead><tr><th>Property</th><th>Types / Description</th></tr></thead>
            <tbody>
                <tr><td>Action vs. Linking</td><td><em>Action:</em> run, write, think — <em>Linking:</em> be, seem, appear, become, feel, look, taste, smell, sound</td></tr>
                <tr><td>Transitive vs. Intransitive</td><td><em>Transitive:</em> takes a direct object — <em>Intransitive:</em> does not — <em>She kicked the ball</em> vs. <em>She laughed.</em></td></tr>
                <tr><td>Auxiliary (Helping)</td><td>be, am, is, are, was, were, been; have, has, had; do, does, did</td></tr>
                <tr><td>Modal Auxiliaries</td><td>can, could, may, might, must, shall, should, will, would, ought to</td></tr>
                <tr><td>Regular Verbs</td><td>Add <em>-ed</em> for past tense: walk → walked, talk → talked</td></tr>
                <tr><td>Irregular Verbs (common)</td><td>be→was/were, go→went, see→saw, take→took, write→wrote, bring→brought, think→thought, eat→ate, give→gave, come→came</td></tr>
                <tr><td>Verb Phrases</td><td>Auxiliary + main verb: <em>has been running, will have completed</em></td></tr>
            </tbody>
        </table>

        <h3>1.5 Adjective &amp; Adverb Degrees of Comparison</h3>
        <table class="ref-table">
            <thead><tr><th>Degree</th><th>Adjective (short)</th><th>Adjective (long)</th><th>Adverb</th></tr></thead>
            <tbody>
                <tr><td>Positive</td><td>fast</td><td>beautiful</td><td>quickly</td></tr>
                <tr><td>Comparative</td><td>faster</td><td>more beautiful</td><td>more quickly</td></tr>
                <tr><td>Superlative</td><td>fastest</td><td>most beautiful</td><td>most quickly</td></tr>
            </tbody>
        </table>
        <p><strong>Irregular comparatives:</strong> good → better → best &nbsp;|&nbsp; bad → worse → worst &nbsp;|&nbsp; little → less → least &nbsp;|&nbsp; many/much → more → most &nbsp;|&nbsp; far → farther/further → farthest/furthest</p>

        <h3>1.6 Conjunctions — Types</h3>
        <table class="ref-table">
            <thead><tr><th>Type</th><th>Examples</th><th>Use</th></tr></thead>
            <tbody>
                <tr><td>Coordinating (FANBOYS)</td><td>For, And, Nor, But, Or, Yet, So</td><td>Join grammatically equal elements</td></tr>
                <tr><td>Subordinating</td><td>although, because, since, unless, while, whereas, after, before, if, when, though</td><td>Introduce dependent clauses</td></tr>
                <tr><td>Correlative</td><td>both…and, either…or, neither…nor, not only…but also, whether…or</td><td>Used in pairs to connect equal elements</td></tr>
                <tr><td>Conjunctive Adverb</td><td>however, therefore, moreover, furthermore, consequently, nevertheless, nonetheless</td><td>Transition between independent clauses (requires semicolon before)</td></tr>
            </tbody>
        </table>

