    <h2>Chapter 1: Parts of Speech &amp; Grammatical Roles</h2>

    <div class="content-content">
        <p>Every word in the English language belongs to one of eight grammatical categories called <strong>parts of speech</strong>. Understanding the role each word plays is the foundation of clear, precise writing and reading comprehension.</p>

        <h3>1.1 The Eight Parts of Speech — Overview</h3>
        <table class="ref-table">
            <thead><tr><th>Part of Speech</th><th>Role</th><th>Key Questions</th><th>Examples</th></tr></thead>
            <tbody>
                <tr><td><strong>Noun</strong></td><td>Names a person, place, thing, or idea</td><td>Who? What?</td><td><em>teacher, city, freedom, justice</em></td></tr>
                <tr><td><strong>Pronoun</strong></td><td>Replaces a noun</td><td>Who? What? (substituted)</td><td><em>he, she, it, they, whom, this</em></td></tr>
                <tr><td><strong>Verb</strong></td><td>Expresses action or state of being</td><td>What does the subject do / be?</td><td><em>run, is, think, become, seem</em></td></tr>
                <tr><td><strong>Adjective</strong></td><td>Modifies a noun or pronoun</td><td>Which? What kind? How many?</td><td><em>tall, three, blue, ancient</em></td></tr>
                <tr><td><strong>Adverb</strong></td><td>Modifies a verb, adjective, or another adverb</td><td>How? When? Where? To what degree?</td><td><em>quickly, very, never, here</em></td></tr>
                <tr><td><strong>Preposition</strong></td><td>Shows relationship between a noun/pronoun and other words</td><td>Where? When? How related?</td><td><em>in, on, at, by, through, despite</em></td></tr>
                <tr><td><strong>Conjunction</strong></td><td>Connects words, phrases, or clauses</td><td>How are these connected?</td><td><em>and, but, or, although, because</em></td></tr>
                <tr><td><strong>Interjection</strong></td><td>Expresses emotion; grammatically independent</td><td>—</td><td><em>Oh! Wow! Alas! Indeed!</em></td></tr>
            </tbody>
        </table>

        <h3>1.2 Nouns — Types &amp; Properties</h3>
        <table class="ref-table">
            <thead><tr><th>Type</th><th>Definition</th><th>Examples</th></tr></thead>
            <tbody>
                <tr><td>Common</td><td>General names, not capitalized</td><td>dog, river, school</td></tr>
                <tr><td>Proper</td><td>Specific names, always capitalized</td><td>Rover, Mississippi, Harvard</td></tr>
                <tr><td>Abstract</td><td>Intangible ideas or concepts</td><td>love, justice, democracy</td></tr>
                <tr><td>Concrete</td><td>Physically perceivable things</td><td>chair, thunder, bread</td></tr>
                <tr><td>Collective</td><td>Groups treated as a unit</td><td>team, flock, jury, committee</td></tr>
                <tr><td>Count</td><td>Can be counted individually</td><td>apple(s), idea(s)</td></tr>
                <tr><td>Non-count (Mass)</td><td>Cannot be individually counted</td><td>water, air, information, advice</td></tr>
                <tr><td>Compound</td><td>Made of two or more words</td><td>toothbrush, ice cream, mother-in-law</td></tr>
                <tr><td>Gerund</td><td>Verb form functioning as a noun (-ing)</td><td><em>Swimming</em> is healthy.</td></tr>
            </tbody>
        </table>

        <h3>1.3 Pronouns — Types &amp; Cases</h3>
        <table class="ref-table">
            <thead><tr><th>Type</th><th>Examples</th></tr></thead>
            <tbody>
                <tr><td>Personal (Subjective)</td><td>I, you, he, she, it, we, they</td></tr>
                <tr><td>Personal (Objective)</td><td>me, you, him, her, it, us, them</td></tr>
