<h2><a name="No4_a4" id="No4_a4"></a>
LOTT CARY,<a name="FNanchor_1_439" id="FNanchor_1_439"></a><a href="#Footnote_1_439" class="fnanchor">[1]</a> THE COLONIZING MISSIONARY</h2>


<p>With Lott Cary and Colin Teague<a name="FNanchor_2_440" id="FNanchor_2_440"></a><a href="#Footnote_2_440" class="fnanchor">[2]</a> sailing for Africa in 1821, a new
era of missionary expansion was begun by Negro Baptists. The
distinctive feature of this epoch, which may be termed modern, is the
fact that behind these men was the Richmond African Baptist Missionary
Society, which gave them support, such as it was, and to which
periodic reports were made. True enough, Lott Cary was under
<span class='pagenum'><a name="Page_381" id="Page_381">[Pg 381]</a></span>appointment of the General Missionary Convention of the Baptist
Denomination in the United States of America but only that fact and
the sum of $200 in cash and $100 in books appropriated for his use up
to 1826<a name="FNanchor_3_441" id="FNanchor_3_441"></a><a href="#Footnote_3_441" class="fnanchor">[3]</a> could not be sufficient evidence to claim him wholly as a
missionary of the General Missionary Convention although he did
receive some advisory instructions from its board.<a name="FNanchor_4_442" id="FNanchor_4_442"></a><a href="#Footnote_4_442" class="fnanchor">[4]</a> Indeed, Lott
Cary was the first American Baptist missionary in Africa, the first
representative of a purely Negro missionary organization to labor
beyond the limits of the United States.</p>

<h3>Preparation for Africa</h3>

<p>Lott Cary was born on the estate of William A. Christian,<a name="FNanchor_5_443" id="FNanchor_5_443"></a><a href="#Footnote_5_443" class="fnanchor">[5]</a> in
Charles City County, Virginia,<a name="FNanchor_6_444" id="FNanchor_6_444"></a><a href="#Footnote_6_444" class="fnanchor">[6]</a> thirty miles from Richmond,<a name="FNanchor_7_445" id="FNanchor_7_445"></a><a href="#Footnote_7_445" class="fnanchor">[7]</a> about
four years after the signing of the Declaration of Independence. There
was no exact record kept of the time of his birth, although it appears
to have been about the year 1780.<a name="FNanchor_8_446" id="FNanchor_8_446"></a><a href="#Footnote_8_446" class="fnanchor">[8]</a></p>

<p>His mother and father lived together on the great plantation of their
master, centering their attention on Lott, their only child. His
mother gave no public profession of religion although she died giving
evidence that she accepted the Christian faith. His father, however,
was a pious man, a respected member of a Baptist church.<a name="FNanchor_9_447" id="FNanchor_9_447"></a><a href="#Footnote_9_447" class="fnanchor">[9]</a> As a
result, Lott received some early religious training which may have
influenced his later life.</p><p><span class='pagenum'><a name="Page_382" id="Page_382">[Pg 382]</a></span></p>

<p>But there were temptings in his life; there were battles in his soul.
Why should a slave boy hope? Could he ever become free? Why not drink
life to the dregs? The chief among his playmates, he became the
mischief-maker of the place. Profligate, profane, polluter was his
title. Lott Cary tried to reform but he was only able to control
himself a few days. Before long, in 1804,<a name="FNanchor_10_448" id="FNanchor_10_448"></a><a href="#Footnote_10_448" class="fnanchor">[10]</a> he was hired out by the
year as a common laborer<a name="FNanchor_11_449" id="FNanchor_11_449"></a><a href="#Footnote_11_449" class="fnanchor">[11]</a> in the Shochoe tobacco warehouse at
Richmond.<a name="FNanchor_12_450" id="FNanchor_12_450"></a><a href="#Footnote_12_450" class="fnanchor">[12]</a> There he grew more intemperate and profane and showed
little signs of reformation.</p>

<p>It was not reformation that he needed but regeneration as was
evidenced one Lord's day in 1807<a name="FNanchor_13_451" id="FNanchor_13_451"></a><a href="#Footnote_13_451" class="fnanchor">[13]</a> as he sat in the gallery of the
First Baptist Church<a name="FNanchor_14_452" id="FNanchor_14_452"></a><a href="#Footnote_14_452" class="fnanchor">[14]</a> and heard the minister preach. He was
hopefully converted and was baptized by Pastor John Courtney<a name="FNanchor_15_453" id="FNanchor_15_453"></a><a href="#Footnote_15_453" class="fnanchor">[15]</a> into
the fellowship of the church. There he heard a sermon on the third
chapter of the gospel of John which so inspired him that he obtained a
Testament in order that he might read for himself the Lord's interview
with Nicodemus. In a short time he knew the alphabet, and with very
little assistance from the men at the warehouse,<a name="FNanchor_16_454" id="FNanchor_16_454"></a><a href="#Footnote_16_454" class="fnanchor">[16]</a> he learned to
read this chapter and also to write.<a name="FNanchor_17_455" id="FNanchor_17_455"></a><a href="#Footnote_17_455" class="fnanchor">[17]</a></p>

<p>Cary was a changed man&mdash;industrious, thrifty, Christian. Whereas he
had been idle now he devoted his leisure time to reading and it is
said that one of the books that he read was Adam Smith's <i>Wealth of
Nations</i>.<a name="FNanchor_18_456" id="FNanchor_18_456"></a><a href="#Footnote_18_456" class="fnanchor">[18]</a> By his application to reading and writing he was able in
a little time to make dray tickets and to act as shipping clerk.<a name="FNanchor_19_457" id="FNanchor_19_457"></a><a href="#Footnote_19_457" class="fnanchor">[19]</a>
His <span class='pagenum'><a name="Page_383" id="Page_383">[Pg 383]</a></span>work in the warehouse was "such as no person, white or black, has
equalled in the same situation.... He could produce any one of the
hundreds of hogsheads of tobacco the instant it was called for."<a name="FNanchor_20_458" id="FNanchor_20_458"></a><a href="#Footnote_20_458" class="fnanchor">[20]</a>
For these services he was often given a five dollar note and the
privilege to sell small quantities of waste tobacco for his own
benefit.<a name="FNanchor_21_459" id="FNanchor_21_459"></a><a href="#Footnote_21_459" class="fnanchor">[21]</a> He saved the money obtained in this way, and with the aid
of a subscription among his employers accumulated by 1813 $850 with
which he purchased freedom for himself and his two children.<a name="FNanchor_22_460" id="FNanchor_22_460"></a><a href="#Footnote_22_460" class="fnanchor">[22]</a></p>

<p>The following extract of a letter from William Crane to the Rev.
Obadiah Brown of Washington City, which he forwarded to the
corresponding secretary of the Baptist Board of Foreign Missions,
corroborates, in the main, the foregoing statements as well as gives
some interesting sidelights on the lives of Cary and Teague:</p>

<blockquote>
<p class="letterDate"><i>Richmond, March 28</i>, 1819.</p>

<p>You will probably recollect, that I introduced you to two of our
colored brethren in this place, who are accustomed to speak in
public; one named Collin Teague, the other Lot Carey. Ever since
the missionary subject has been so much agitated in this country,
these two brethren, associated with many others, have been
wishing they could, in some way, aid their unhappy kindred in
Africa; and I suppose you have heard of their having formed a
missionary society for this sole purpose. Some letters published
in No. VI of the <i>Luminary</i> (written by Kizell, the Baptist
leader in Sherbro Island and by some others) have served to
awaken them effectually. They are now determined to go themselves
to Africa; and the only questions with them are, in what way will
it be best for them to proceed? and what previous steps are
requisite to be taken? They think it necessary to spend some time
in study first. They both possess industry and abilities, such
as, with the blessing of Providence, would soon make them rich.
It is but two or three years since either of them enjoyed
freedom; and both have paid large sums for their families. They
now possess but little, except <span class='pagenum'><a name="Page_384" id="Page_384">[Pg 384]</a></span>a zealous wish to go and do what
they can. Brother Lot has a wife, and several little children. He
has a place a little below Richmond, that cost him $1500, but
will probably not sell for more than $1000 at this time. Brother
Collin has a wife, a son 14 years of age, and a daughter of 11,
for whom he has paid $1300, and has scarcely any thing left. Both
their wives are Baptists; their children, amiable and docile,
have been to school considerably; and I hope, if they go, will
likewise be of service. Collin is a saddler and harness maker. He
had no early education. The little that he has gained, has been
by chance and peacemeal. He has judgment, and as much keenness of
penetration as almost any man. He can read, though he is not a
good reader, and can write so as to make out a letter. The little
knowledge he has of figures, has been gained by common
calculations in business. Lot was brought up on a farm; and for a
number of years has been chief manager among the labourers in the
largest tobacco ware house in this city. He has charge of
receiving, marking and shipping tobacco; and the circumstance
that he receives $700 a-year wages may help you to form an
estimate of the man. He reads better than Collin, and is in every
respect a better scholar. They have been trying to preach about
ten or eleven years, and are both about forty years of age.<a name="FNanchor_23_461" id="FNanchor_23_461"></a><a href="#Footnote_23_461" class="fnanchor">[23]</a></p></blockquote>

<p>Cary had been licensed to preach by the First Baptist Church,
Richmond, and he exercised his talent every Lord's day among the
colored people on plantations a few miles from Richmond.<a name="FNanchor_24_462" id="FNanchor_24_462"></a><a href="#Footnote_24_462" class="fnanchor">[24]</a> It was
not many months before he was the highly esteemed pastor of the
African Baptist Church in Richmond. As a preacher, Cary was not
polished, but "his ideas would sometimes burst upon you in their
native solemnity, and awaken deeper feelings than the most polished,
but less original" and artificial discourses.<a name="FNanchor_25_463" id="FNanchor_25_463"></a><a href="#Footnote_25_463" class="fnanchor">[25]</a></p>

<p>Lott Cary early exhibited the power of an organizer. In 1815, William
Crane, who was a member of the First Baptist Church, felt that his
ought to use his talent among the twelve hundred Negro members of that
congregation.<span class='pagenum'><a name="Page_385" id="Page_385">[Pg 385]</a></span> Consequently, he and David Roper<a name="FNanchor_26_464" id="FNanchor_26_464"></a><a href="#Footnote_26_464" class="fnanchor">[26]</a> gratuitously
opened a tri-weekly night school in the gallery of the old church with
Lott Cary, Colin Teague and fifteen or twenty leading members of the
church as pupils.<a name="FNanchor_27_465" id="FNanchor_27_465"></a><a href="#Footnote_27_465" class="fnanchor">[27]</a> Now Crane was able to inspire such a group to
practical missionary service, for he himself had been repeatedly urged
to become a missionary and had had close contact with Luther Rice as
one of the managers of the General Missionary Convention. But it was
left to Lott Cary to excite among the Negroes a strong interest in
behalf of Africa. The result was the formation of the Richmond African
Baptist Missionary Society in 1815. Crane was the president or
corresponding secretary.<a name="FNanchor_28_466" id="FNanchor_28_466"></a><a href="#Footnote_28_466" class="fnanchor">[28]</a> This was necessary, for since the various
uprisings of Negroes<a name="FNanchor_29_467" id="FNanchor_29_467"></a><a href="#Footnote_29_467" class="fnanchor">[29]</a> were making Virginia a hotbed of discontent,
the city of Richmond was wary of having Negro meetings unless they
were sponsored by white persons. Crane represented the Society in the
General Missionary Convention,<a name="FNanchor_30_468" id="FNanchor_30_468"></a><a href="#Footnote_30_468" class="fnanchor">[30]</a> formed in 1814, and remained its
delegate for about twenty years.</p>

<p>At the first triennial session of the Convention at Philadelphia, in
May, 1817, a letter was read from the corresponding secretary of the
Richmond African Baptist Missionary Society and it was unanimously</p>

<blockquote><p>Resolved, that the said letter be noticed on the minutes of the
Convention, and that the Board, if they find it practicable, be
advised to institute an African Mission, conformably to the
wishes of the said African Mission Society; and that the
Corresponding<span class='pagenum'><a name="Page_386" id="Page_386">[Pg 386]</a></span> Secretary of the Board be requested to communicate
this resolution together with an encouraging affectionate letter
to that society.<a name="FNanchor_31_469" id="FNanchor_31_469"></a><a href="#Footnote_31_469" class="fnanchor">[31]</a></p></blockquote>

<p>Feeling of sympathy for the African was high. Many slave-holding
Baptists felt that they owed the Negro a debt which they should
pay.<a name="FNanchor_32_470" id="FNanchor_32_470"></a><a href="#Footnote_32_470" class="fnanchor">[32]</a> Moreover, the board of the Convention felt that the interest
in Foreign missions manifested by the Negro Baptists of Richmond was a
providential plan whereby the slaves brought from Africa might be
converted and returned to evangelize that continent.<a name="FNanchor_33_471" id="FNanchor_33_471"></a><a href="#Footnote_33_471" class="fnanchor">[33]</a> Since,
therefore, mission work could be propagated in Africa in the English
language and for one quarter the expense required for other lands,<a name="FNanchor_34_472" id="FNanchor_34_472"></a><a href="#Footnote_34_472" class="fnanchor">[34]</a>
the Convention felt no hesitancy in acknowledging the claims of
Africa.</p>

<p>Luther Rice, while in Richmond during the winter of 1817, visited the
African Missionary Society. "It afforded me much pleasure, indeed," he
reported,<a name="FNanchor_35_473" id="FNanchor_35_473"></a><a href="#Footnote_35_473" class="fnanchor">[35]</a> "to observe the zeal, and intelligence and capacity, and
success, discovered in the African Mission Society."</p>

<p>As a matter of fact, the formation of the Richmond African Baptist
Society was an epochal event. The example was followed by the African
Baptist Church of Philadelphia<a name="FNanchor_36_474" id="FNanchor_36_474"></a><a href="#Footnote_36_474" class="fnanchor">[36]</a> and by the Baptists of Petersburg,
Virginia.<a name="FNanchor_37_475" id="FNanchor_37_475"></a><a href="#Footnote_37_475" class="fnanchor">[37]</a> The African mission spirit even permeated North Carolina
and Georgia, for during the years 1816 and 1817 the Negro Baptists of
those parts contributed $32.64 to the cause.<a name="FNanchor_38_476" id="FNanchor_38_476"></a><a href="#Footnote_38_476" class="fnanchor">[38]</a><span class='pagenum'><a name="Page_387" id="Page_387">[Pg 387]</a></span> This contribution
far outstripped the donation of the white Baptists to the same cause.
During the same time they contributed only $14.27, $12.27 of which was
given by the newly formed African Mite Society of Providence, Rhode
Island.<a name="FNanchor_39_477" id="FNanchor_39_477"></a><a href="#Footnote_39_477" class="fnanchor">[39]</a></p>

<p>Lott Cary resolved that it was his duty to go and preach the gospel in
benighted Africa. It was at Crane's night school that this intention
was made known. After Crane had reviewed the report of Burgess and
Mills, telling of their exploring tour on the coast of Africa, Lott
Cary said: "I have been determined for a long time to go to Africa and
at least to see the country for myself."<a name="FNanchor_40_478" id="FNanchor_40_478"></a><a href="#Footnote_40_478" class="fnanchor">[40]</a> There is no doubt that to
some extent Gary was awakened to a deep sense of responsibility for
his brethren in Africa by that part of this report which dealt with
John Kizell, the Baptist leader in Sherbro Island, the president of
the Friendly Society established by Paul Cuffee, the escort and guide
of Burgess and Mills on their exploring tour, the man directly
responsible for the beginning of the impractical scheme of deportation
on the continent of Africa by the American Colonization Society.<a name="FNanchor_41_479" id="FNanchor_41_479"></a><a href="#Footnote_41_479" class="fnanchor">[41]</a></p>

<p>But how was he to accomplish his object? Crane said,<a name="FNanchor_42_480" id="FNanchor_42_480"></a><a href="#Footnote_42_480" class="fnanchor">[42]</a> "I had
thought of addressing the Corresponding Secretary on their (Cary and
Teague) behalf, for the patronage of the American Baptist Mission
Society, but again thought, that the Colonization Society might be
pleased with taking them under their care, and that their mission
might bear a more imposing aspect under the auspices of this society
than it would with the Baptists alone." Lott Cary was received by the
Baptist Board of Foreign Missions, May 1, 1819, <span class='pagenum'><a name="Page_388" id="Page_388">[Pg 388]</a></span>and was accepted by
the American Colonization Society to work for them "without pay as
other engagements would permit."<a name="FNanchor_43_481" id="FNanchor_43_481"></a><a href="#Footnote_43_481" class="fnanchor">[43]</a></p>

<p>The treasurer of the General Missionary Convention reported $2 for
Africa received September 21, 1819, from a friend in Nashville
Tennessee. The next year the society appropriated $200 in cash and
$100 in books. Contrasted with this was the $483.25 paid April 17,
1820, by the Richmond African Baptist Missionary Society to the
General Missionary Convention to be appropriated for Africa.<a name="FNanchor_44_482" id="FNanchor_44_482"></a><a href="#Footnote_44_482" class="fnanchor">[44]</a> Thus
the Convention served only as a clearing house for the funds
contributed from Richmond. With this in mind we can more clearly
understand the following order voted by the Baptist Board of Foreign
Missions in 1820:</p>

<blockquote>
<p>
With African Mission Society, Richmond,<br />
To various exp. for Collin Teague and Lot Carey ... 500 25.<a name="FNanchor_45_483" id="FNanchor_45_483"></a><a href="#Footnote_45_483" class="fnanchor">[45]</a>
</p>
</blockquote>

<p>Furthermore, the historian of the Convention up to the year 1840<a name="FNanchor_46_484" id="FNanchor_46_484"></a><a href="#Footnote_46_484" class="fnanchor">[46]</a>
relates that the Richmond African Baptist Missionary Society, of which
Lott Cary was the recording secretary, appropriated to the cause of
African redemption $700, all of its funds collected during the first
five years of its existence. For many years thereafter the Society
collected and contributed annually from $100 to $150 to the mission in
Africa.<a name="FNanchor_47_485" id="FNanchor_47_485"></a><a href="#Footnote_47_485" class="fnanchor">[47]</a></p>

<p>Lott Cary was giving up much to be an apostle to his people&mdash;a
pastorate of nearly eight hundred members, a farm and house costing
$1,500 and a salary increase of $200 a year if he would stay.<a name="FNanchor_48_486" id="FNanchor_48_486"></a><a href="#Footnote_48_486" class="fnanchor">[48]</a> But
he must go. There were promptings big and great. Cary and Colin Teague
are said to have wished to be where their color would be no
<span class='pagenum'><a name="Page_389" id="Page_389">[Pg 389]</a></span>disparagement to their usefulness.<a name="FNanchor_49_487" id="FNanchor_49_487"></a><a href="#Footnote_49_487" class="fnanchor">[49]</a> "I am an African," he is
reported to have answered an intelligent minister who asked him why he
was leaving,<a name="FNanchor_50_488" id="FNanchor_50_488"></a><a href="#Footnote_50_488" class="fnanchor">[50]</a> "and, in this country, however meritorious my
conduct, and respectable my character, I cannot receive the credit due
to either. I wish to go to a country where I shall be estimated by my
merits, not by my complexion; and I feel bound to labor for my
suffering race."</p>

<p>It is highly probable that Cary possessed no such race consciousness
as is portrayed in the foregoing reports of Crane and Gurley. True
enough, the occasion for such sentiment was there in the institution
of slavery but had Cary imbibed the spirit? On the one hand, the free
Negro was not wanted in Virginia as is evidenced by an act which made
unlawful the permanent residence in the State of any slave set free
after May 1, 1806. But, on the other hand, this act was not generally
enforced because of the economic value of many of the freedmen.<a name="FNanchor_51_489" id="FNanchor_51_489"></a><a href="#Footnote_51_489" class="fnanchor">[51]</a>
Thus it is doubtful whether Cary, whose salary would be increased if
he remained in Virginia, and Teague, both effectual workmen whose
industry was needed, would have to go away to gain a higher status.</p>

<p>Let us examine the facts further. Crane was certainly enthusiastic for
African colonization and Gurley was the secretary of the American
Colonization Society. Thus these statements, as well as similar ones
which follow, seem like attempts on the part of the friends of
colonization to make Cary say to the other free Negroes that
colonization was a desirable thing. Certainly such an attitude would
be a timely rebuttal of the anti-colonization sentiment of the Negro
ministry in general.</p>

<p>Furthermore, this reason for going to Africa was not in accord with
the one given at Crane's night school. Then he wanted to see Africa
for himself; now he finds America no place for the Negro. He could
have changed his point <span class='pagenum'><a name="Page_390" id="Page_390">[Pg 390]</a></span>of view, but did he? If he did change his
view, he had changed again in less than two years (March 13, 1821)
when he wrote as follows to the corresponding secretary of the Board
of Foreign Missions:</p>

<blockquote><p>If you intend doing anything for Africa you must not wait for the
Colonization Society, nor for government, for neither of these
are in search of missionary grounds, but of colonizing grounds;
if it should not suit missionary needs, you cannot expect to
gather in a missionary crop. And, moreover, all of us who are
connected with the agents, who are under public instructions,
must be conformed to their laws, whether they militate against
missionary operation or not.<a name="FNanchor_52_490" id="FNanchor_52_490"></a><a href="#Footnote_52_490" class="fnanchor">[52]</a></p></blockquote>

<p>Thus if Cary made statements which favor colonization he was very
inconsistent, for it was he who was chiefly responsible for the
colonists openly defying the Colonization Society in 1824. Nor could
Cary write so well. It is most likely, therefore, that Lott Cary
wanted to go to Africa simply to see the country and to do missionary
work.</p>

<p>Prior to his public farewell, Lott Cary and Colin Teague were ordained
and they, with their wives, Joseph Langford and wife and Hilary
Teague, were organized in January, 1821, into a church. Lott Cary was
elected pastor. The constitution of this body which they were to plant
in Africa was modelled after the Samson Street Church of
Philadelphia.<a name="FNanchor_53_491" id="FNanchor_53_491"></a><a href="#Footnote_53_491" class="fnanchor">[53]</a></p>

<p>Cary's farewell sermon, preached in the meeting house of the First
Baptist Church, Richmond, was well ordered, without the rant common to
some preachers of that day, dignified and pathetic, and left a lasting
impression on the audience.<a name="FNanchor_54_492" id="FNanchor_54_492"></a><a href="#Footnote_54_492" class="fnanchor">[54]</a> Teague had often remarked to William
Crane, "Sir, I don't hear any of your white ministers that can preach
like Lott Cary." Crane was anxious to hear him and after listening to
his farewell message from Romans<span class='pagenum'><a name="Page_391" id="Page_391">[Pg 391]</a></span> 8:32&mdash;"He that spared not his own
Son, but delivered Him up for us all, how shall He not with Him also
freely give us all things?"&mdash;he did not hesitate to declare: "I have a
most vivid recollection of the manner in which, towards the close, he
dwelt upon the word 'freely.' With thrilling emphasis he exclaimed
over and over, 'He gave them freely!' He rang a succession of perhaps
a dozen changes upon the word, in a manner that would not have
dishonored Whitfield."<a name="FNanchor_55_493" id="FNanchor_55_493"></a><a href="#Footnote_55_493" class="fnanchor">[55]</a></p>

<p>Lott Gary closed his sermon with this thought:</p>

<blockquote><p>I am about to leave you and expect to see your faces no more. I
long to preach to the poor Africans the way of life and
salvation. I don't know what may befall me, whether I may find a
grave in the ocean, or among the savage men, or more savage wild
beasts on the Coast of Africa; nor am I anxious what may become
of me. I feel it my duty to go; and I very much fear that many of
those who preach the Gospel in this country, will blush when the
Saviour calls them to give an account of their labors in His
cause and tell them, "I commanded you to go into all the world,
and preach the Gospel to every creature;" (very emphatically he
exclaimed) the Saviour may ask where have you been? What have you
been doing? Have you endeavored to the utmost of your ability to
fulfill the commands I gave you, or have you sought your own
gratification, and your own ease, regardless of My commands?<a name="FNanchor_56_494" id="FNanchor_56_494"></a><a href="#Footnote_56_494" class="fnanchor">[56]</a></p></blockquote>

<p>A distinguished Presbyterian minister said to Gurley, "A sermon which
I heard from Lott Gary, shortly before he sailed for Africa, was the
best extemporaneous sermon I ever heard. It contained more original
and impressive thoughts, some of which are distinct in my memory, and
never can be forgotten."<a name="FNanchor_57_495" id="FNanchor_57_495"></a><a href="#Footnote_57_495" class="fnanchor">[57]</a> Elder John Bryce, assistant pastor of the
First Baptist Church, afterwards confessed that he had never been so
deeply interested in a sermon.<a name="FNanchor_58_496" id="FNanchor_58_496"></a><a href="#Footnote_58_496" class="fnanchor">[58]</a></p>


<h3>Readjustment on African Soil</h3>

<p>By the twenty-third of January, 1821, Gary and his <span class='pagenum'><a name="Page_392" id="Page_392">[Pg 392]</a></span>church were ready
to sail.<a name="FNanchor_59_497" id="FNanchor_59_497"></a><a href="#Footnote_59_497" class="fnanchor">[59]</a> At half past six in the morning<a name="FNanchor_60_498" id="FNanchor_60_498"></a><a href="#Footnote_60_498" class="fnanchor">[60]</a> the <i>Nautilus</i>,
carrying 28 colonists and a number of children, left Norfolk,
Virginia, en route to Sierra Leone.<a name="FNanchor_61_499" id="FNanchor_61_499"></a><a href="#Footnote_61_499" class="fnanchor">[61]</a></p>

<p>As the agents of the American Colonization Society, who made the
journey, had not completed their negotiations for the purchase of a
site for the settlers, the party remained at Freetown, Sierra Leone,
for some months.<a name="FNanchor_62_500" id="FNanchor_62_500"></a><a href="#Footnote_62_500" class="fnanchor">[62]</a> From there Cary wrote the Corresponding Secretary
of the Baptist Board of Foreign Missions, March 13th:</p>

<blockquote><p><i>Rev. and Dear Sir</i></p>

<p>I am happy that an opportunity is now afforded me, to inform the
Board through you, the only proper medium of communication with
them, that we all arrived safe in Africa. We had a long passage
of forty four days, yet we were wonderfully preserved by the
great Ruler of the winds and the seas....</p>

<p>I am truly sorry, that the hopes and expectations of the Board
cannot be realized, as to our missionary labours; for, as it
pleased you to have us connected with the Colonization Society,
and the agents of the Society upon their arrival here, finding
their prospects of getting lands very gloomy, so much so that
they disowned us as colonists; and the government's agent had
captured Africans for whom he was bound, by the laws of the
United States, to procure a place, in order to settle them, or
until there can be a more permanent settlement obtained, the
agent received us as labourers and mechanics, to be settled with
them in order to make preparations for the reception of others;
we are therefore bound to the government's agent. He has rented a
farm, and put us on it, and we must cultivate it for our support,
and for the support of these Africans; and pay as much of the
rent as we can. And as this obligation will last until lands are
purchased by the agents of the Colonization Society, I am greatly
afraid it will not end soon; and until it does end, our mission
labours will be very few. Jesus Christ, our Saviour, when he came
on his mission into this world, was found often with a broad axe
in his hand: and I believe that a good many corn field
missionaries would be a great blessing to <span class='pagenum'><a name="Page_393" id="Page_393">[Pg 393]</a></span>this country, that is
if they were not confined to the field by law and by necessity.
We are bound by both. I converse very freely with you on this
subject, because with me it is a very important one, and because
of the interest which the Board has taken in this mission.<a name="FNanchor_63_501" id="FNanchor_63_501"></a><a href="#Footnote_63_501" class="fnanchor">[63]</a></p></blockquote>

<p>Mrs. Cary, "a sensible woman and an exemplary Christian,"<a name="FNanchor_64_502" id="FNanchor_64_502"></a><a href="#Footnote_64_502" class="fnanchor">[64]</a> was sick
at this time and soon died, leaving her husband the care of their two
children.<a name="FNanchor_65_503" id="FNanchor_65_503"></a><a href="#Footnote_65_503" class="fnanchor">[65]</a> Despite this and the appalling circumstances of the
first settlers, they wrote to the Board rejoicing that they were in
the country of their forefathers and hoping that His gracious
approbation would crown their labors.<a name="FNanchor_66_504" id="FNanchor_66_504"></a><a href="#Footnote_66_504" class="fnanchor">[66]</a> Lott Cary kept constantly in
mind the great object of his mission. He not only preached as often as
opportunity would permit but he established a mission among the
Mandingoes.<a name="FNanchor_67_505" id="FNanchor_67_505"></a><a href="#Footnote_67_505" class="fnanchor">[67]</a></p>

<p>Nevertheless, there was danger for some time that the whole enterprise
would be abandoned. Whereupon, Captain Robert F. Stockton was sent to
Africa in the armed schooner <i>Alligator</i> with full powers from
President Monroe and the American Colonization Society to make
arrangements for a new and permanent settlement.<a name="FNanchor_68_506" id="FNanchor_68_506"></a><a href="#Footnote_68_506" class="fnanchor">[68]</a> On December 11,
he and Doctor Eli Ayres, the Society's agent, who had left America in
July, anchored off Cape Mesurado or Montserado and, with John Mills,
an English mulatto and slave dealer, as interpreter, made negotiations
with King Peter, the principal chief around the Cape, for the purchase
of a settlement. After much parleying and delay on the part of the
king and treachery on the part of Mills,<a name="FNanchor_69_507" id="FNanchor_69_507"></a><a href="#Footnote_69_507" class="fnanchor">[69]</a> they finally exchanged
gunpowder, tobacco, rum, iron pots, beads, looking glasses, "four
Hats, three Coats, three pair Shoes"<a name="FNanchor_70_508" id="FNanchor_70_508"></a><a href="#Footnote_70_508" class="fnanchor">[70]</a><span class='pagenum'><a name="Page_394" id="Page_394">[Pg 394]</a></span> and other minor articles not
worth more than $300 for that valuable tract of land<a name="FNanchor_71_509" id="FNanchor_71_509"></a><a href="#Footnote_71_509" class="fnanchor">[71]</a> which was the
nucleus of what is now the Republic of Liberia.<a name="FNanchor_72_510" id="FNanchor_72_510"></a><a href="#Footnote_72_510" class="fnanchor">[72]</a></p>

<p>Arrangements were made for the colonists to take possession of their
new home the 7th of February, 1822.<a name="FNanchor_73_511" id="FNanchor_73_511"></a><a href="#Footnote_73_511" class="fnanchor">[73]</a> The territory, finally
including ninety miles of coast lying between the Junk and Sesters
Rivers and extending nearly seventy miles into the interior,
presented, on the one hand, an excellent opportunity to work among the
Bassa, Vey, Dey and Kroo tribes,<a name="FNanchor_74_512" id="FNanchor_74_512"></a><a href="#Footnote_74_512" class="fnanchor">[74]</a> who numbered about 125,000, and
exhibited, on the other hand, many obstacles, for the natives were
hostile, and the rainy season was approaching, at the time when
provisions were scarce.</p>

<p>The condition of the colonists was so appalling that many proposed to
return to Sierra Leone. Just a few more hours and the Cape would have
been abandoned, but when the Agent went ashore to prepare for
departure he was informed by Lott Gary that he was determined not to
go. Nearly all the colonists were induced to follow his example.</p>

<p>In the event they suffered severely; nearly 1,000 natives attacked
them in November, 1822, but were repulsed. During this and similar
encounters with the natives, which lasted through the months of
November and December, Lott Cary cooperated wisely with the Agent,
Jehudi Ashmun,<a name="FNanchor_75_513" id="FNanchor_75_513"></a><a href="#Footnote_75_513" class="fnanchor">[75]</a> and, although several of the colonists were killed
and wounded, with only 37 men and boys he, on one occasion, drove back
with considerable loss 1,500 wild and exasperated natives who were
bent on extirpating the settlement. Lott Cary compared the little
company of disturbed settlers to the Jews, who "grasped a weapon in
one hand, while they labored with the other" to rebuild the city. But
he is said to have asserted: "There never has been an hour <span class='pagenum'><a name="Page_395" id="Page_395">[Pg 395]</a></span>or a
minute, no, not even when the balls were flying around my head, when I
could wish myself again in America."<a name="FNanchor_76_514" id="FNanchor_76_514"></a><a href="#Footnote_76_514" class="fnanchor">[76]</a></p>

<p>These colonists planted their church at Monrovia and soon had under
way the nucleus of a flourishing Sunday-school.<a name="FNanchor_77_515" id="FNanchor_77_515"></a><a href="#Footnote_77_515" class="fnanchor">[77]</a> Cary extended his
labors to communities far and near, and by 1823 had 6 converts.<a name="FNanchor_78_516" id="FNanchor_78_516"></a><a href="#Footnote_78_516" class="fnanchor">[78]</a>
The following resolution adopted by the General Missionary Convention
speaks for itself the sentiment of that body respecting the work of
Cary and Teague up to May 7, 1823:<a name="FNanchor_79_517" id="FNanchor_79_517"></a><a href="#Footnote_79_517" class="fnanchor">[79]</a></p>

<blockquote><p>The committee states that the present condition and prospects of
the mission are encouraging. Brethren Cary and Teague are at
present much occupied in aiding in the establishment of the
colony at Cape Mesurado. Their conduct has been good and that of
the former, in particular, has been specially commended by the
Agent of the Colonization Society. The committee recommends that
an able white missionary be stationed, as soon as practicable, at
Cape Mesurado. The mission has a double effect. While it tends to
introduce the gospel into Africa, a mission establishment on the
coast will essentially aid in the suppression of the slave trade.</p></blockquote>

<p>In spite of the fact that his associate, Colin Teague, had returned to
Freetown, Sierra Leone,<a name="FNanchor_80_518" id="FNanchor_80_518"></a><a href="#Footnote_80_518" class="fnanchor">[80]</a> Lott Cary was adding some few of the
natives to the church. In 1824, he baptized 9. One by the name of John
from Grand Cape Mount, a town about eighty miles distant, proved a
valuable helper by the good influence which he exerted. Some word from
Hector Peters<a name="FNanchor_81_519" id="FNanchor_81_519"></a><a href="#Footnote_81_519" class="fnanchor">[81]</a> had touched him and he came to the American
settlement for instruction and baptism. Without being asked, he
related his experience to the church.</p><p><span class='pagenum'><a name="Page_396" id="Page_396">[Pg 396]</a></span></p>

<p>"When me bin Sa' lone," he began, "me see all man go to church
house&mdash;me go too&mdash;me be very bad man too&mdash;suppose a man can cus
(curse) me&mdash;me can cus im too&mdash;suppose a man can fight me&mdash;me can
fight im too.&mdash;Well, me go to church house&mdash;the man speak, and one
word catch my heart (and at the same time laying his hand on his
breast)&mdash;I go to my home&mdash;my heart be very heavy&mdash;and trouble me
too&mdash;night time come&mdash;me fear me can't go to my bed for sleep&mdash;my
heart trouble me so&mdash;something tell me go pray to God&mdash;me fall down to
pray&mdash;no&mdash;my heart be too bad&mdash;I can't pray&mdash;I think so&mdash;I go die
now&mdash;suppose I die&mdash;I go to hell&mdash;me be very bad man&mdash;pass all turrer
(other) man&mdash;God be angry with me&mdash;soon I die&mdash;suppose man cus me this
time&mdash;me can't cus him no more&mdash;suppose man fight me&mdash;me can't fight
him no more&mdash;all the time my heart trouble me&mdash;all day&mdash;all night me
can't sleep&mdash;by and by my heart grow too big&mdash;me fall down this
time&mdash;now me can pray&mdash;me say Lord&mdash;have massey. Then light come in my
heart&mdash;make me glad&mdash;make me light&mdash;make me love the Son of God&mdash;make
me love everybody."</p>

<p>John was baptized the 20th of March, 1825. The church neatly dressed
him, gave him an extra suit, about $10.50, 3 Bibles and 2 hymn books
and sent him on his way rejoicing.<a name="FNanchor_82_520" id="FNanchor_82_520"></a><a href="#Footnote_82_520" class="fnanchor">[82]</a></p>

<p>The impetus received by the church was amazing. The membership by 1825
had increased to 60 or 70 and two or three pious emigrants were
assisting in the work. This same year, Lott Cary directed the building
of a substantial meeting house which would have been completed
immediately if nails and boards could have been procured.<a name="FNanchor_83_521" id="FNanchor_83_521"></a><a href="#Footnote_83_521" class="fnanchor">[83]</a> In a
letter from Monrovia,<a name="FNanchor_84_522" id="FNanchor_84_522"></a><a href="#Footnote_84_522" class="fnanchor">[84]</a> dated April 24, 1826, he wrote a <span class='pagenum'><a name="Page_397" id="Page_397">[Pg 397]</a></span>brother in
Norfolk: "We dedicated our meeting house last October; it was four
weeks from the time we raised it to the time it was dedicated. It is
quite a comfortable house, 30 &times; 20 feet, and ceiled inside nearly up
to the plates, with a decent pulpit and seats. I feel very grateful to
you for your services, and to the brethren and friends for their
liberal contribution."<a name="FNanchor_85_523" id="FNanchor_85_523"></a><a href="#Footnote_85_523" class="fnanchor">[85]</a></p>

<p>This progress of the church might, at first blush, seem to say that
everything was in a state of tranquility and peace. This is far from
being the case. In the face of the record of Lott Cary as a Christian,
a pastor, a representative of the Richmond African Baptist Missionary
Society and a church builder in Africa, it is interesting to note the
invective hurled against him by Governor Ashmun in 1823. The
Governor's phraseology is unique. "Wretched," "morose," "obstinate,"
"soured," "narrow," "disobliging," "moral desert," "a corroding
temper," and "destitute of natural affection," were some of the
epithets used as over against "more obliging," "affectionate husband,"
"display of tenderness," "sweet and profound humility," "promoter of
every commendable and pious design," "every laudable habit," "moral
renovation," "habit of holiness," and "redeemed" when an understanding
was perfected in 1824.<a name="FNanchor_86_524" id="FNanchor_86_524"></a><a href="#Footnote_86_524" class="fnanchor">[86]</a></p>

<p>The cause of the misunderstanding was of long standing. Agents of the
American Colonization Society prior to Ashmun's time were accused of
transmitting false reports to the board and of appropriating to their
own use the provisions and supplies of the colonists.<a name="FNanchor_87_525" id="FNanchor_87_525"></a><a href="#Footnote_87_525" class="fnanchor">[87]</a> It is also
known that a commercial company of Baltimore, whose business <span class='pagenum'><a name="Page_398" id="Page_398">[Pg 398]</a></span>it was
to prosecute the African slave trade, was jealous of the Society and
tried to undermine it. In addition, the trials and hardships
incidental to founding the colony had reduced many of the settlers to
want.<a name="FNanchor_88_526" id="FNanchor_88_526"></a><a href="#Footnote_88_526" class="fnanchor">[88]</a> The most ignorant could thus fathom their condition: "We
suffer: if the Society have means and does not apply them to our
relief, it is without benevolence; if it have not means, it wants
power and in either case is unworthy of our confidence."<a name="FNanchor_89_527" id="FNanchor_89_527"></a><a href="#Footnote_89_527" class="fnanchor">[89]</a></p>

<p>This lack of power showed itself in the helplessness of the government
to restrain the first vestiges of insubordination and to enforce the
law. Thereupon, the discontentment of Cary and one or two others
became widespread.<a name="FNanchor_90_528" id="FNanchor_90_528"></a><a href="#Footnote_90_528" class="fnanchor">[90]</a> Probably the manhood consciousness of Cary
would not have asserted itself so soon had not the occasion arisen
between August 31 and September 25, 1823, when the principal Agent
attempted to redistribute the town lots of the earliest colonists who
alleged that they held them under a former sanction of the Agent and
so refused to have them redistributed. They resolved to appeal to the
board of the American Colonization Society.<a name="FNanchor_91_529" id="FNanchor_91_529"></a><a href="#Footnote_91_529" class="fnanchor">[91]</a> Moreover, they openly
avowed that they would neither survey nor cultivate any of the lots
(thickly covered with undergrowth) assigned to them nor aid in any
public improvements<a name="FNanchor_92_530" id="FNanchor_92_530"></a><a href="#Footnote_92_530" class="fnanchor">[92]</a> until they should hear from the board. On the
13th of December, Ashmun published the announcement that there were in
the Colony more than a dozen healthy persons who would not receive any
more provisions out of the public store till they earned them. Six
days later the Agent ordered the rations of the offending persons to
be stopped. Next morning a few<a name="FNanchor_93_531" id="FNanchor_93_531"></a><a href="#Footnote_93_531" class="fnanchor">[93]</a> of the colonists assembled at the
Agency House and vociferously <span class='pagenum'><a name="Page_399" id="Page_399">[Pg 399]</a></span>demanded the Agent to rescind his
order. Ashmun was immovable. The colonists straightway hastened to the
storehouse where rations for the week were then being issued and each
seized a store of provisions and went home.<a name="FNanchor_94_532" id="FNanchor_94_532"></a><a href="#Footnote_94_532" class="fnanchor">[94]</a> Lott Cary had no small
influence and share in this seditious proceeding.<a name="FNanchor_95_533" id="FNanchor_95_533"></a><a href="#Footnote_95_533" class="fnanchor">[95]</a> Toward evening,
the Agent addressed a circular "to all the colonists" declaring that
the impropriety of the morning's act would be communicated to the
board. He further exhorted all to go to work and not to commit such an
offence again for their sakes in this world or in the one to come.
Lott Cary was not to perform any of his ministerial functions "till
time and circumstances shall have evidenced the deepness and sincerity
of his repentance."<a name="FNanchor_96_534" id="FNanchor_96_534"></a><a href="#Footnote_96_534" class="fnanchor">[96]</a> Gurley states that the leaders of the
sedition, led by Lott Cary, almost "immediately confessed and
deplored" their error.<a name="FNanchor_97_535" id="FNanchor_97_535"></a><a href="#Footnote_97_535" class="fnanchor">[97]</a></p>

<p>It seemed in 1824 that the affair of the previous year would be
repeated when, on March 17, the rations were reduced one half. The act
was viewed by the colonists as oppression and they openly reproached
Ashmun. Through all of this period, the spirit of disorganization was
working so that the colonists furnished little support towards
developing the government.<a name="FNanchor_98_536" id="FNanchor_98_536"></a><a href="#Footnote_98_536" class="fnanchor">[98]</a></p>

<p>In communicating the account of the disturbances to the board, Ashmun
wrote, March 15, that "the services rendered by Lott Cary in the
Colony, who has with very few (and those recent exceptions), done
honor to the selection of the Baptist Missionary Society, under whose
auspices he was sent out to Africa, entitle his agency in this affair,
to the most indulgent construction which it will bear. The hand which
records the lawless transaction, would long since have been cold in
the grave, had it not been for the unwearied and painful attentions of
this individual rendered <span class='pagenum'><a name="Page_400" id="Page_400">[Pg 400]</a></span>at all hours&mdash;of every description&mdash;and
continued several months."<a name="FNanchor_99_537" id="FNanchor_99_537"></a><a href="#Footnote_99_537" class="fnanchor">[99]</a></p>

<p>The General Missionary Convention was influenced very little, if any,
by the report, if, indeed, they had received it officially. At the
annual meeting of the Board of Managers, April, 1824, the committee on
the African mission had "no hesitation in recommending a careful
regard to this mission, which though it may seem to slumber for a
moment, in their opinion promises great and extensive usefulness." The
board recommended</p>

<blockquote><p>That a constant correspondence be kept up with the brethren there
by which their minds will be encouraged, and their hands
strengthened and through which information may be received of the
state of the Colony, the progress of the cause, and of the
earliest opportunities which may offer for introducing the Gospel
more extensively into the heart of Africa.<a name="FNanchor_100_538" id="FNanchor_100_538"></a><a href="#Footnote_100_538" class="fnanchor">[100]</a></p></blockquote>

<p>There is no further account of this misunderstanding other than that
from the pen of Ashmun. Mr. Taylor,<a name="FNanchor_101_539" id="FNanchor_101_539"></a><a href="#Footnote_101_539" class="fnanchor">[101]</a> the biographer of Lott Cary,
remarks: "He (Cary) was compelled, to some extent, to act the part of
a mediator between the rebellious colonists, who considered themselves
injured, and Mr. Ashmun, the Governor. While for a moment he might
seem to act injudiciously, he possessed too much noble and generous
feeling to be guilty of a dishonorable act." The Rev. G. Winfred
Hervey<a name="FNanchor_102_540" id="FNanchor_102_540"></a><a href="#Footnote_102_540" class="fnanchor">[102]</a> thinks that "in any controversy between mules and
muledrivers, the latter have several advantages among which one of the
most important is that they have the exclusive use of vocal attack and
defence. Cary was too prudent a man to publish an apology for
constructive sedition; and as he has not left us his own explanation
of any of the facts in the case, we have not all the materials on
which to base an impartial judgment."</p><p><span class='pagenum'><a name="Page_401" id="Page_401">[Pg 401]</a></span></p>

<p>The agitation at length had its effect. It was directly responsible
for the establishment, in 1824, of a new form of government which was
approved by Cary and his fellow-citizens and in which the colonists
had a full expression.<a name="FNanchor_103_541" id="FNanchor_103_541"></a><a href="#Footnote_103_541" class="fnanchor">[103]</a> Gurley<a name="FNanchor_104_542" id="FNanchor_104_542"></a><a href="#Footnote_104_542" class="fnanchor">[104]</a> and Ashmun both testified that
Cary readily entered into the spirit of the new government.<a name="FNanchor_105_543" id="FNanchor_105_543"></a><a href="#Footnote_105_543" class="fnanchor">[105]</a> Only
eight days, from August 14 to 22, were needed to organize a government
that should be energetic and feasible.<a name="FNanchor_106_544" id="FNanchor_106_544"></a><a href="#Footnote_106_544" class="fnanchor">[106]</a> "Beneath the thatched roof
of the first rude house for divine worship ever erected in the Colony
stood the little company of one hundred colored emigrants, who had
ventured all things to gain for themselves and children a home and
inheritance of liberty and before God pledged themselves to maintain
the Constitution of their choice, and prove faithful to the great
trust committed to their hands."<a name="FNanchor_107_545" id="FNanchor_107_545"></a><a href="#Footnote_107_545" class="fnanchor">[107]</a> Despite the seeming repetition
of the chagrin of past irregularities in September, 1824, however, the
board of the American Colonization Society passed a motion, April 2,
1825, to organize, on the 18th of the next month, a permanent
government for the colony.<a name="FNanchor_108_546" id="FNanchor_108_546"></a><a href="#Footnote_108_546" class="fnanchor">[108]</a></p>


<h3>Usefulness of the Man</h3>

<p>During these times Lott Cary continued to increase his popularity by
performing the pastoral duties of the Providence Baptist Church as
vigorously as he could.<a name="FNanchor_109_547" id="FNanchor_109_547"></a><a href="#Footnote_109_547" class="fnanchor">[109]</a> He preached several times each week, and,
in addition, gave religious instruction to many of the native
children. A day school of twenty-one pupils was begun April 18,
1825.<a name="FNanchor_110_548" id="FNanchor_110_548"></a><a href="#Footnote_110_548" class="fnanchor">[110]</a> By June, the number had increased to thirty-two, nineteen
of whom came from Grand Cape Mount, some miles distant.<a name="FNanchor_111_549" id="FNanchor_111_549"></a><a href="#Footnote_111_549" class="fnanchor">[111]</a><span class='pagenum'><a name="Page_402" id="Page_402">[Pg 402]</a></span> Cary was
handicapped in this work by the lack of funds, by the demoralizing gin
traffic of the Europeans, by Mohammedanism, by the deadly climate and
by degraded fetichism,<a name="FNanchor_112_550" id="FNanchor_112_550"></a><a href="#Footnote_112_550" class="fnanchor">[112]</a> yet, in the course of seven weeks, he
taught several children to read the Bible intelligently, although he
could not devote more than three hours a day to this work.<a name="FNanchor_113_551" id="FNanchor_113_551"></a><a href="#Footnote_113_551" class="fnanchor">[113]</a></p>

<p>In the meantime, in keeping with the report of the Board of Managers
of the General Missionary Convention in 1823, Governor Ashmun wrote to
the American Colonization Society, March 20, 1825, that "the natives
have universally a most affecting persuasion of the superiority of
white men.... I cannot hesitate to say that the missionary, or
principal of the proposed establishment (<i>i.e.</i>, a religious mission
for Africa), ought by preference to be a white man."<a name="FNanchor_114_552" id="FNanchor_114_552"></a><a href="#Footnote_114_552" class="fnanchor">[114]</a> The little
colony of near 400 souls was suffering for an adequate educational
program. Excepting Governor Ashmun, there was not an individual there
who had ever received a plain English education.<a name="FNanchor_115_553" id="FNanchor_115_553"></a><a href="#Footnote_115_553" class="fnanchor">[115]</a> Allowing that
and granting that there were few intelligent Negroes in the United
States,<a name="FNanchor_116_554" id="FNanchor_116_554"></a><a href="#Footnote_116_554" class="fnanchor">[116]</a> Ashmun would have appeared more hopeful of Negro
leadership had he made his request to the board more general.</p>

<p>Whether because of this appeal or not, it is singular to note that the
Rev. Calvin Holton, a graduate of Waterville College (now Colby
College), offered his service to the board the same year and, with 34
emigrants,<a name="FNanchor_117_555" id="FNanchor_117_555"></a><a href="#Footnote_117_555" class="fnanchor">[117]</a> sailed from Boston in the brig <i>Vine</i>, January 4,
1826. He was employed to establish and direct a Lancastrian system of
<span class='pagenum'><a name="Page_403" id="Page_403">[Pg 403]</a></span>education for (1) the children of the colonists, (2) for the native
children living in the settlement, (3) for the recaptured Africans who
numbered about 120, and (4) for the young men and women who were
teaching or preparing themselves for this profession.<a name="FNanchor_118_556" id="FNanchor_118_556"></a><a href="#Footnote_118_556" class="fnanchor">[118]</a> His work
was not of long duration for on the 2d of July, 1826, he died<a name="FNanchor_119_557" id="FNanchor_119_557"></a><a href="#Footnote_119_557" class="fnanchor">[119]</a> and
was succeeded early in 1827 by the Rev. G. M'Gill, "an intelligent and
experienced coloured Teacher from Baltimore."<a name="FNanchor_120_558" id="FNanchor_120_558"></a><a href="#Footnote_120_558" class="fnanchor">[120]</a></p>

<p>About this time the number of native boys who received instruction was
only 50. These were trained either to be interpreters to American and
European missionaries or religious teachers. Lott Cary had 45 scholars
enrolled in his school at Monrovia.<a name="FNanchor_121_559" id="FNanchor_121_559"></a><a href="#Footnote_121_559" class="fnanchor">[121]</a> He was assisted by a lad of
fourteen years and by the Rev. John N. Lewis, another missionary sent
out by the Richmond African Baptist Missionary Society, but who, from
lack of adequate support, turned to other business.<a name="FNanchor_122_560" id="FNanchor_122_560"></a><a href="#Footnote_122_560" class="fnanchor">[122]</a></p>

<p>Lott Cary had a large task to perform with this school. As a matter of
fact, "the hopes of the African tribes," said Ashmun,<a name="FNanchor_123_561" id="FNanchor_123_561"></a><a href="#Footnote_123_561" class="fnanchor">[123]</a> "from
Gallinas to Trade Town, are at present suspended upon it. Most of the
boys who attend it are sons of the principal individuals of the
country, and more than half can read the New Testament intelligently,
and understand the English language nearly as well as the <span class='pagenum'><a name="Page_404" id="Page_404">[Pg 404]</a></span>settlers of
the same age." The expense of a native boy was estimated at $25 and of
a girl at $20.<a name="FNanchor_124_562" id="FNanchor_124_562"></a><a href="#Footnote_124_562" class="fnanchor">[124]</a></p>

<p>Gurley believed that the schools were numerous enough and amply able
to afford instruction to every child in the colony. Although this
instruction was compulsory, it is not altogether evident, however,
that at any place save Monrovia a real educational program was begun.
Ashmun related that about six out of every ten emigrants were
illiterate and that just one pious individual assisted by two or three
utterly illiterate exhorters was the only instructor around the
settlement. "Not one in five of these people habitually attend, even
on Sundays, such religious instruction as they possess." Consequently,
he adds that the moral power exerted was not sufficient to offset "the
demoralizing influence of corrupt examples."<a name="FNanchor_125_563" id="FNanchor_125_563"></a><a href="#Footnote_125_563" class="fnanchor">[125]</a></p>

<p>The Richmond African Baptist Missionary Society and Lott Cary,
however, were expending their funds liberally on the schools. The
surplus funds in the colonial treasury plus the subscription of $1,400
from the colonists (including $300 subscribed by Ashmun) were spent
for education.<a name="FNanchor_126_564" id="FNanchor_126_564"></a><a href="#Footnote_126_564" class="fnanchor">[126]</a> Yet from all sources enough money could not be
raised to continue all the schools begun. Cary, in 1827, removed the
day school from Monrovia to Grand Cape Mount. He made appeal after
appeal to send the light to Africa. To prove that the natives would
sooner steal the light than miss it he gives the following incident
that occurred in removing the school establishment to Grand Cape
Mount:</p>

<p>"I had upwards of forty natives," he said,<a name="FNanchor_127_565" id="FNanchor_127_565"></a><a href="#Footnote_127_565" class="fnanchor">[127]</a> "to carry our baggage,
and they carried something like 250 bars ($187.50); a part of them
went on four days beforehand, and had every opportunity to commit
depredations, but of all the goods that were sent and carried there,
nothing was <span class='pagenum'><a name="Page_405" id="Page_405">[Pg 405]</a></span>lost except fifteen spelling books; five of them were
recovered again."</p>

<p>Mr. Cary's letter to Mr. Crane will explain somewhat the circumstances
of the school at Grand Cape Mount.</p>

<blockquote>
<p class="letterDate"><i>June 11, 1827.</i></p>

<p>On yesterday week, being our monthly meeting, I baptized one
young man, and after preaching in the afternoon, we had the
happiness to break bread together in the house of the Lord. I
don't like to be too sanguine, but I think he will be a blessing
to the church; his name is John Reavy (Revey)&mdash;came out in the
first expedition, and has been engaged in teaching a native
school on the Sherbro, with Nathaniel Brander, until the last two
years, which he has spent at Sierra Leone.</p>

<p>For I fear I may not have another opportunity to write you again
soon, I must again call your attention to the immediate
establishment of a school at Cape Mount. Since writing the fore
part of this letter, I have received an order for books from Cape
Mount, which I have sent. I requested, at the same time, the
native Brother, John,<a name="FNanchor_128_566" id="FNanchor_128_566"></a><a href="#Footnote_128_566" class="fnanchor">[128]</a> to come down immediately, and I would
try and arrange business so as to send up a teacher with him; and
on proposing the subject to Brother John Reavy, he is quite
willing to go up to commence the school as soon as the Brother
comes down. I expect to allow him $10.00 per month and find him.
My means at present will not justify these engagements, but I
know you will do what you can when there is an opportunity; if
you cannot send out tobacco or other articles, send out the
money. United States bank notes pass as well here as they do with
you. I shall try to keep the wheels going until you can send out
supplies. I want some writing paper and ink powder or ink, and
wish the Society (Richmond) would send me a bbl. of single nails.
You will please make my respects to all the brethren and friends,
and accept the same for yourself and the Board.</p>

<p class="author">Lott Cary.<a name="FNanchor_129_567" id="FNanchor_129_567"></a><a href="#Footnote_129_567" class="fnanchor">[129]</a><br />
</p></blockquote>
<p><span class='pagenum'><a name="Page_406" id="Page_406">[Pg 406]</a></span></p>

<p>After many months of delay<a name="FNanchor_130_568" id="FNanchor_130_568"></a><a href="#Footnote_130_568" class="fnanchor">[130]</a> the school was established November
10, 1827, at Big Town, Grand Cape Mount. John Revey was in charge.
"The school room," says Cary,<a name="FNanchor_131_569" id="FNanchor_131_569"></a><a href="#Footnote_131_569" class="fnanchor">[131]</a> "is nearly fifteen feet by thirty.
We made arrangements to have worship in it on the ensuing Lord's day,
and I had the honour to address a very attentive audience twice,
through brother John. After service I informed the congregation that I
should need their assistance the following day in preparing seats,
&amp;c., and they turned out like men, and performed more labour by eight
o'clock, than I expected to have accomplished in the whole day. We got
seats prepared for about 60 children by 4 o'clock, and gave notice
that as the school would be organized on the day following, at 9
o'clock, A.M., all persons wishing to have their children instructed
were requested to come at that time and have them entered, and the
number received was 37. I read and explained a short set of
regulations which I had drawn up; and as I had the king and his head
men present, I got them to sign the articles of agreement in the
presence of the whole congregation. For twelve months I think the
school will, of course, be expensive. The present arrangement is&mdash;I
agree to allow brother Revey $20 per month, and find him provisions,
washing, &amp;c."</p>

<p>Mr. Cary thought that by this arrangement the station at Grand Cape
Mount would net better results than the one at Monrovia. Neither he
nor the Richmond African Baptist Missionary Society were able to
maintain both. Some funds were received<a name="FNanchor_132_570" id="FNanchor_132_570"></a><a href="#Footnote_132_570" class="fnanchor">[132]</a> but it developed in about
a year that the school had to be given up for lack of funds and
assistants.<a name="FNanchor_133_571" id="FNanchor_133_571"></a><a href="#Footnote_133_571" class="fnanchor">[133]</a></p>

<p>Other duties, moreover, required some time. Lott Cary realized from
the beginning of the colony that a missionary in Africa ought to be
more than a corrector of moral ills <span class='pagenum'><a name="Page_407" id="Page_407">[Pg 407]</a></span>and a "doctor" of divinity; he
would be fortunate indeed if he could mend human bodies. As a result,
Cary was constrained to forego much of the joy which he had
anticipated from efforts to show men the living Christ by accepting
the position of Health Officer of the colony, August 31, 1822.<a name="FNanchor_134_572" id="FNanchor_134_572"></a><a href="#Footnote_134_572" class="fnanchor">[134]</a> He
had no medical schooling but with the use of home remedies, patent
medicines,<a name="FNanchor_135_573" id="FNanchor_135_573"></a><a href="#Footnote_135_573" class="fnanchor">[135]</a> and common sense, he was able to cure some. Until the
31st of August, 1823, he was practically the only physician in the
settlement (excepting Dr. Ayres who was present a part of the year
1822). After that Dr. Ayres returned on the <i>Oswego</i> in the late
spring of 1825.<a name="FNanchor_136_574" id="FNanchor_136_574"></a><a href="#Footnote_136_574" class="fnanchor">[136]</a> He and sixty emigrants who came with him were
soon suffering from the disease of the country and had to rely on the
medical experience of Cary. Eight emigrants died<a name="FNanchor_137_575" id="FNanchor_137_575"></a><a href="#Footnote_137_575" class="fnanchor">[137]</a> and by December,
Dr. Ayres was compelled to leave the colony. The climate was so
unhealthy that hardly any one escaped its pestilence.<a name="FNanchor_138_576" id="FNanchor_138_576"></a><a href="#Footnote_138_576" class="fnanchor">[138]</a> When, in
addition, the poor housing conditions, the inadequate sanitation and
the scanty hospital supplies<a name="FNanchor_139_577" id="FNanchor_139_577"></a><a href="#Footnote_139_577" class="fnanchor">[139]</a> are considered, it is remarkable
that so many escaped death.</p>

<p>Every ship<a name="FNanchor_140_578" id="FNanchor_140_578"></a><a href="#Footnote_140_578" class="fnanchor">[140]</a> that brought emigrants meant more work for Cary. On
February 13, 1824,<a name="FNanchor_141_579" id="FNanchor_141_579"></a><a href="#Footnote_141_579" class="fnanchor">[141]</a> one hundred and five emigrants arrived in the
ship <i>Cyrus</i> and in less than a month every one was prostrate with the
fever.<a name="FNanchor_142_580" id="FNanchor_142_580"></a><a href="#Footnote_142_580" class="fnanchor">[142]</a> "Astonishing," said Ashmun,<a name="FNanchor_143_581" id="FNanchor_143_581"></a><a href="#Footnote_143_581" class="fnanchor">[143]</a> "that in this atmosphere
should exist causes so universal in their operation, as amongst all
the varieties of age, sex and habit, not to leave one in the whole
number without disease, and that in less than four weeks; and stranger
still, that the blast should be so tempered <span class='pagenum'><a name="Page_408" id="Page_408">[Pg 408]</a></span>to the strength of the
constitution of every individual, as only to have swept off three
small children. Men may call these phenomena in human life, the
effects of the laws of nature; I choose to call them singular proofs
of the Providence of God over all his creatures."</p>

<p>When the brig <i>Hunter</i> arrived, March 13, 1825, with 66 settlers,
nearly all of whom were farmers,<a name="FNanchor_144_582" id="FNanchor_144_582"></a><a href="#Footnote_144_582" class="fnanchor">[144]</a> all were stricken during the
first month. Although Cary himself was confined to his house nursing a
severe injury, only a few children were fatally affected.<a name="FNanchor_145_583" id="FNanchor_145_583"></a><a href="#Footnote_145_583" class="fnanchor">[145]</a></p>

<p>Cary gratuitously spent about half of his time in caring for the sick
of the colony. This fact was a matter of course as no funds were
specially designated for this purpose. Cary was financially able to do
such a thing. He had defrayed no small share of his own expense<a name="FNanchor_146_584" id="FNanchor_146_584"></a><a href="#Footnote_146_584" class="fnanchor">[146]</a>
in equipment for Africa, and when the colonists were in need of
medical aid, he spent much of his means in this direction.<a name="FNanchor_147_585" id="FNanchor_147_585"></a><a href="#Footnote_147_585" class="fnanchor">[147]</a> In
1825 he still owned a house and lot near Richmond which he was
desirous of selling.<a name="FNanchor_148_586" id="FNanchor_148_586"></a><a href="#Footnote_148_586" class="fnanchor">[148]</a></p>

<p>Lott Cary was so occupied with caring for the sick that his
prospective trip to America in the spring of 1826 had to be
postponed.<a name="FNanchor_149_587" id="FNanchor_149_587"></a><a href="#Footnote_149_587" class="fnanchor">[149]</a> He was also physician to Governor Ashmun. The governor
was very ill in May after an exposure of four hours in attempting to
save the schooner <i>Catherine</i> from destruction. "The prescriptions of
our excellent and experienced assistant physician, the Rev. L. Cary,"
the Governor said,<a name="FNanchor_150_588" id="FNanchor_150_588"></a><a href="#Footnote_150_588" class="fnanchor">[150]</a> "under the blessing of Divine Providence, so
far succeeded as to afford complete relief, only leaving me in a very
emaciated and enfeebled state, about the end of the first week in
July."</p><p><span class='pagenum'><a name="Page_409" id="Page_409">[Pg 409]</a></span></p>

<p>All of this was just part of the work that Lott Cary had set himself
to accomplish. By his unselfish labors and untiring efforts he had won
the hearts of the natives. He had been indefatigable in his efforts to
uplift the colony. The morale of the settlement was greatly lifted.
Drunkenness, profanity and quarreling were unknown; the Sabbath was
observed with strictness.<a name="FNanchor_151_589" id="FNanchor_151_589"></a><a href="#Footnote_151_589" class="fnanchor">[151]</a> Nearly the whole adult population had
come under the influence of Christianity. On the site of a once
desolate forest consecrated to demon worship was erected the
commodious chapel which stood as a monument of the overthrow of
heathenism and as a tribute to the Son of God.<a name="FNanchor_152_590" id="FNanchor_152_590"></a><a href="#Footnote_152_590" class="fnanchor">[152]</a></p>

<p>But in the sight of this landmark of Christianity, the slave trade was
carried on extensively.<a name="FNanchor_153_591" id="FNanchor_153_591"></a><a href="#Footnote_153_591" class="fnanchor">[153]</a> In 1825 from eight to ten, even fifteen
traders were engaged at the same time off the coast. In July
"contracts were existing for eight hundred slaves to be furnished in
the short space of four months within eight miles of the Cape. Four
hundred of these were to be purchased for two American traders. During
the same season, a boat belonging to a Frenchman, having on board
twenty-six slaves, all in irons, was upset in the mouth of the St.
Paul River and twenty of their number perished."<a name="FNanchor_154_592" id="FNanchor_154_592"></a><a href="#Footnote_154_592" class="fnanchor">[154]</a> Between October,
1825, and April, 1826, no less than one hundred and eighty Negroes
were reclaimed from slave traders and taught the Scripture.<a name="FNanchor_155_593" id="FNanchor_155_593"></a><a href="#Footnote_155_593" class="fnanchor">[155]</a></p>

<p>When Gurley visited the colony in August, 1824, he found the state of
religion and morality hopeful, defenses adequate, quiet Sabbaths and
physical improvements which indicated that a considerable amount of
labor had been done. For twenty-two months following, the jails were
in disuse.<a name="FNanchor_156_594" id="FNanchor_156_594"></a><a href="#Footnote_156_594" class="fnanchor">[156]</a> By 1826 the people had developed from inexperienced
<span class='pagenum'><a name="Page_410" id="Page_410">[Pg 410]</a></span>immigrants to efficient citizens. No family was without ample food
and wearing apparel. Wages were high and employment could be found
everywhere. The common laborers were receiving from $.75 to $1.75 a
day, while the mechanics got $2 a day. Houses were built and a
telegraph system was soon to be installed. There were also two corps
of militia, an artillery battery of fifty men and forty infantrymen.
These had charge of the fifteen large carriages and three small pivot
guns.<a name="FNanchor_157_595" id="FNanchor_157_595"></a><a href="#Footnote_157_595" class="fnanchor">[157]</a></p>

<p>A printing press costing more than $1,000, in addition to the salary
of a printer, had been sent out. The citizens of Liberia expressed
their thanks by subscribing nearly $200 "toward the immediate issue
and support of a publick newspaper."<a name="FNanchor_158_596" id="FNanchor_158_596"></a><a href="#Footnote_158_596" class="fnanchor">[158]</a> One thousand volumes of
books, a complete set of the North American Review, a gift of Editor
Sparks, and many other useful things were on hand.<a name="FNanchor_159_597" id="FNanchor_159_597"></a><a href="#Footnote_159_597" class="fnanchor">[159]</a></p>

<p>Economic effort, however, did not at first play as conspicuous a part
in the missionary adventure of Lott Cary as it did in the lives of the
pioneers, George Liele and David George, who left this country
primarily to be able to make a living.<a name="FNanchor_160_598" id="FNanchor_160_598"></a><a href="#Footnote_160_598" class="fnanchor">[160]</a> Nevertheless, the economic
feature developed after a time. The agricultural progress of the
country was rapidly promoted. The sultry and moist climate greatly
accelerated<a name="FNanchor_161_599" id="FNanchor_161_599"></a><a href="#Footnote_161_599" class="fnanchor">[161]</a> the growth of coffee,<a name="FNanchor_162_600" id="FNanchor_162_600"></a><a href="#Footnote_162_600" class="fnanchor">[162]</a> rice and cassada. The Rev.
Colston M. Waring was the first to attempt farming on anything like a
large scale. His crop of rice and cassada on a ten acre farm failed
and checked so bold an example from all except Lott Cary. He, too,
lost a promising crop in 1825 on the same kind of land because of the
birds and the monkeys.<a name="FNanchor_163_601" id="FNanchor_163_601"></a><a href="#Footnote_163_601" class="fnanchor">[163]</a> This failure, however, showed him that
<span class='pagenum'><a name="Page_411" id="Page_411">[Pg 411]</a></span>either farming as the natives adopted (scratching the surface of the
ground with a sharp stick) or more improved methods of thoroughly
preparing the soil had to be tried.<a name="FNanchor_164_602" id="FNanchor_164_602"></a><a href="#Footnote_164_602" class="fnanchor">[164]</a> In the following year, Cary
enlarged his farm, had it cleared, dug it up with picks and hoes, and,
in June, sowed about three bushels of rice to the acre. At the first
cutting, on the 20th of October, it averaged 50 kroos (a measure
varying from 3 to 5 winchester gallons) per acre.<a name="FNanchor_165_603" id="FNanchor_165_603"></a><a href="#Footnote_165_603" class="fnanchor">[165]</a></p>

<p>In one letter, he says:<a name="FNanchor_166_604" id="FNanchor_166_604"></a><a href="#Footnote_166_604" class="fnanchor">[166]</a> "I have a promising little crop of rice
and cassada, and have planted about 180 coffee trees this week, a part
of which I expect, will produce next season, as they are now in bloom.
I think, sir, that in a very few years we shall send you coffee of a
better quality than you have ever seen brought into your market. We
find that trees of two species abound in great quantities on the
Cape."</p>

<p>On the 7th of July, 1825, Cary reported a discovery of gold in the
sand near little Cape Mount.<a name="FNanchor_167_605" id="FNanchor_167_605"></a><a href="#Footnote_167_605" class="fnanchor">[167]</a> The appearance of gold was certain
to develop the country commercially; some trade was already being
carried on. Endeavoring to participate therein, nine of the natives
built a ten ton schooner which carried from four to eight thousand
dollars' worth of goods each trip.<a name="FNanchor_168_606" id="FNanchor_168_606"></a><a href="#Footnote_168_606" class="fnanchor">[168]</a> Doctor Alexander<a name="FNanchor_169_607" id="FNanchor_169_607"></a><a href="#Footnote_169_607" class="fnanchor">[169]</a> relates
that between the first of January and the fifteenth of July, 1826,
fifteen vessels stopped at Monrovia.</p>

<p>Nevertheless, there were some anti-slavery leaders in America who
seriously questioned the permanent utility and moral influence of the
colony of Liberia. One of these anti-slavery groups, composed of free
Negroes of Philadelphia, was led by Richard Allen, the founder of the
African Methodist Episcopal Church.<a name="FNanchor_170_608" id="FNanchor_170_608"></a><a href="#Footnote_170_608" class="fnanchor">[170]</a> In a letter to a gentleman
<span class='pagenum'><a name="Page_412" id="Page_412">[Pg 412]</a></span>in Richmond, Lott Cary makes mention, September 24, 1827, of the
agitation carried on by these Negroes of Philadelphia. "Before I left
America," he said,<a name="FNanchor_171_609" id="FNanchor_171_609"></a><a href="#Footnote_171_609" class="fnanchor">[171]</a> "and ever since then, the coloured people in
about Philadelphia, have been making efforts in opposition to the
scheme of colonizing the free people in Africa; and as some of their
very recent publications have reached this place, I felt that in
justice to the cause, and my own feelings, I ought to undertake to
point out to them their situation."</p>

<p>Unfortunately the letter closes shortly after this but singularly
enough our sources supply an "Address, <i>By the Citizens of Monrovia</i>,
to the free coloured people of the United States,"<a name="FNanchor_172_610" id="FNanchor_172_610"></a><a href="#Footnote_172_610" class="fnanchor">[172]</a> which no doubt
is referred to in the letter. The name of Lott Cary is not attached to
this address, which boosts "the doings of the Colonization Society"
and which points out the political, social, economic, educational and
religious advantages enjoyed by the colonists. Nevertheless, the
document could not fully express the sentiments of the colonists
unless the feelings of the leaders were given. It is not too much to
presume that the address was gotten up by Lott Cary, the outstanding
leader of the colonists, but it is very doubtful whether he wrote it
in its present form. The correspondence of Cary reveals that he did
not express himself so clearly nor did he use so good English.<a name="FNanchor_173_611" id="FNanchor_173_611"></a><a href="#Footnote_173_611" class="fnanchor">[173]</a>
The antithetical style reminds one of the writing of Ashmun.<a name="FNanchor_174_612" id="FNanchor_174_612"></a><a href="#Footnote_174_612" class="fnanchor">[174]</a></p><p><span class='pagenum'><a name="Page_413" id="Page_413">[Pg 413]</a></span></p>

<p>Through all of the many affairs which Cary performed, he continued
pastor of the church at Monrovia. A missionary society was formed in
connection with the church in the spring of 1826. Cary was elected
president.<a name="FNanchor_175_613" id="FNanchor_175_613"></a><a href="#Footnote_175_613" class="fnanchor">[175]</a> At the first anniversary<a name="FNanchor_176_614" id="FNanchor_176_614"></a><a href="#Footnote_176_614" class="fnanchor">[176]</a> on Easter Monday, in
consequence of the failure of the Rev. Colin Teague to come from
Sierra Leone, Lott Cary preached the introductory sermon.<a name="FNanchor_177_615" id="FNanchor_177_615"></a><a href="#Footnote_177_615" class="fnanchor">[177]</a> This
society contributed $50 for mission work during the year 1827.<a name="FNanchor_178_616" id="FNanchor_178_616"></a><a href="#Footnote_178_616" class="fnanchor">[178]</a> By
the following year, the church contained one hundred members and two
ordained preachers, John Lewis and Colston M. Waring, besides
exhorters.<a name="FNanchor_179_617" id="FNanchor_179_617"></a><a href="#Footnote_179_617" class="fnanchor">[179]</a></p>


<h3>Final Work and Worth</h3>

<p>Lott Cary was none the less interested and active in the welfare of
the government. From the first settlement in Cape Montserado, he was
appointed Government Inspector at the same time he was selected Health
Officer<a name="FNanchor_180_618" id="FNanchor_180_618"></a><a href="#Footnote_180_618" class="fnanchor">[180]</a> and consequently he knew something of the working of the
government. In September, 1826, he was unanimously elected vice-agent
of the colony. The colonial agent had great confidence in his
judgments, decisions and loyalty<a name="FNanchor_181_619" id="FNanchor_181_619"></a><a href="#Footnote_181_619" class="fnanchor">[181]</a> and left the affairs of the
colony in Cary's charge when he was advised in 1828 to return to
America for his health.<a name="FNanchor_182_620" id="FNanchor_182_620"></a><a href="#Footnote_182_620" class="fnanchor">[182]</a></p>

<p>"I was able," Mr. Ashmun wrote to the board,<a name="FNanchor_183_621" id="FNanchor_183_621"></a><a href="#Footnote_183_621" class="fnanchor">[183]</a> "to arrange the
concerns of the Colony with Mr. Cary, even to the minutest
particulars, and I have the greatest confidence that his
administration will prove satisfactory, in a high degree, to the Board
and advantageous to the Colony."</p><p><span class='pagenum'><a name="Page_414" id="Page_414">[Pg 414]</a></span></p>

<p>During the first six months, Cary's task was to see to it that every
man and working family were self-supporting. "To effect this object,
they must be furnished with a few simple tools&mdash;to pay for them if
they can&mdash;if not, to receive them gratuitously. Their allowance must
be withheld if they neglect or negligently follow the improvement of
their lands, and the building of their houses. Much may be done by
visiting the people separately, getting at their intentions and
circumstances and spurring, advising or reproving as they may require.
I am persuaded it will be useful, and in most instances possible to
get at least all the men out of the public receptacles and on their
lands before the rains set in." Respecting the buildings of the United
States, those of the colony, the arms, forts, printing establishment,
farms, Millsburg settlement, finances, etc., other particular
regulations were suggested.<a name="FNanchor_184_622" id="FNanchor_184_622"></a><a href="#Footnote_184_622" class="fnanchor">[184]</a> Lott Cary kept Ashmun and the
American Colonization Society informed about the condition of the
colony.<a name="FNanchor_185_623" id="FNanchor_185_623"></a><a href="#Footnote_185_623" class="fnanchor">[185]</a> On his death bed, Ashmun again expressed his confidence
in Cary and urged that he should be permanently appointed to conduct
the affairs of the colony<a name="FNanchor_186_624" id="FNanchor_186_624"></a><a href="#Footnote_186_624" class="fnanchor">[186]</a> which now contained upwards of 1,200
settlers.<a name="FNanchor_187_625" id="FNanchor_187_625"></a><a href="#Footnote_187_625" class="fnanchor">[187]</a></p>

<p>The only trouble that Cary had while he was vice-agent was with the
natives.<a name="FNanchor_188_626" id="FNanchor_188_626"></a><a href="#Footnote_188_626" class="fnanchor">[188]</a> The factory belonging to the colony at Digby, a
settlement just north of Monrovia, was robbed by them and general
hostilities threatened when satisfaction was demanded and refused. A
letter of protest to a slave dealer who had stored his goods in the
house where stores of the colony had been deposited was intercepted
and destroyed by the natives. Immediately, Cary prepared to defend the
rights and property of the colony. He called out the militia and began
with others, in the evening of November 8, <span class='pagenum'><a name="Page_415" id="Page_415">[Pg 415]</a></span>to make cartridges in the
old agency house. In some manner, a candle was accidentally upset and
almost instantly the entire ammunition exploded, entirely destroying
the house. Eight people died; six of the number survived until the
next day; Lott Cary and one other until November 10, 1828.<a name="FNanchor_189_627" id="FNanchor_189_627"></a><a href="#Footnote_189_627" class="fnanchor">[189]</a></p>

<p>The unbelievable news of the death of Lott Cary spread like a mighty
conflagration to the organizations which he represented. The following
is the resolution read and adopted at the annual meeting of the
Richmond African Baptist Missionary Society in 1829:<a name="FNanchor_190_628" id="FNanchor_190_628"></a><a href="#Footnote_190_628" class="fnanchor">[190]</a></p>

<blockquote><p>The loss which has been sustained, cannot in our estimation, be
easily repaired. This excellent man seems to have been raised up
by divine providence, for the special purpose of taking an active
part in the management of the infant settlement. His
discriminating judgment, his honesty of heart, and decision of
character, qualified him eminently, for this service. But,
especially, in relation to your society is his death to be
sincerely lamented. It will be recollected, that he was a
principal instrument in the origin of this society, and for
several years acted as its recording secretary. A little more
than eight years ago, he received his appointment, and sailed, as
missionary, in company with brother Teage, for the land of their
forefathers. His exertions as a minister in that land have been
of the most devoted and untiring kind. In the communications
which have been received by the Board, he seemed to possess the
most anxious concern for the salvation of the perishing
multitudes around him. Through his instrumentality a considerable
church has been collected together which seems to be in a
prosperous and growing condition. Sabbath and week day schools
have been instituted for the instruction of native children and
the children of the colony, which have proved eminently useful.
We were looking forward with confidence to the more perfect
consummation of our wishes, when that moral desert should rejoice
and blossom as the rose; but God has seen fit to cross our
expectations, in calling from his station this laborious
missionary. It becomes us to bow with submission to the stroke,
and to realize the saying of the apostle, "how unsearchable are
his judgments, and his ways <span class='pagenum'><a name="Page_416" id="Page_416">[Pg 416]</a></span>past finding out." Although we were
not permitted to receive his dying testimony to the trust, we
have the fullest assurance that our loss is his unspeakable and
eternal gain.</p></blockquote>

<p>At the sixth triennial meeting of the General Missionary Convention,
1829, the committee on the African Mission made this report<a name="FNanchor_191_629" id="FNanchor_191_629"></a><a href="#Footnote_191_629" class="fnanchor">[191]</a> which
in some particulars was paradoxical:</p>

<blockquote><p>This excellent man (it began) went to Africa, under the patronage
of the American Colonization Society, as well as of this
convention.... Could he have devoted his whole time to our
service much good might have been expected to have resulted from
his labors. But he was under necessity to assist in its
government and defense, as well as to act as its physician.</p>

<p>It is a source of consolation to the friends of Mr. Cary that
though his life was terminated in an unexpected moment and in a
most distressing manner, the unwearied diligence and fidelity
with which he discharged the important trust confided to his
care&mdash;his zeal for the honor of religion, and the purity and
piety of his general conduct have gained him a reputation which
must live in grateful remembrance, as long as the interesting
colony exists, in whose service he lived and died.</p>

<p>Your committee cannot help expressing their regret that so small
a portion of benevolent feeling has been exercised towards this
mission, and that so little has been accomplished during the
eight years of its existence.</p></blockquote>

<p>The next item of this report is an appeal for "some brethren of
competent talents" to go and labor there.</p>

<p>There surely was ground for regret that so small a portion of
benevolent feeling was exercised towards this mission. Some
individuals did contribute now and then; "A Georgia Planter" sent a
part of $10;<a name="FNanchor_192_630" id="FNanchor_192_630"></a><a href="#Footnote_192_630" class="fnanchor">[192]</a> a "poor woman" of the Rev. H. Malcom's congregation
sent $3 for the African mission;<a name="FNanchor_193_631" id="FNanchor_193_631"></a><a href="#Footnote_193_631" class="fnanchor">[193]</a> "a friend to Africa avails of
jewelry for mission to Liberia, per Mr. E. Lincoln, $6";<a name="FNanchor_194_632" id="FNanchor_194_632"></a><a href="#Footnote_194_632" class="fnanchor">[194]</a> the<span class='pagenum'><a name="Page_417" id="Page_417">[Pg 417]</a></span>
Negroes connected with the First Baptist Church, Washington, sent
$15<a name="FNanchor_195_633" id="FNanchor_195_633"></a><a href="#Footnote_195_633" class="fnanchor">[195]</a> and, no doubt, some others contributed.</p>

<p>It is not quite clear, however, why William Crane, still representing
the Richmond African Baptist Missionary Society in the Convention and
the Rev. James B. Taylor, a delegate from Virginia and later the
biographer of Lott Cary, did not challenge the statement that so
little had been accomplished during the eight years of the existence
of the African mission.</p>

<p>The Convention then adopted the following recommendation of the
Committee:</p>

<blockquote><p><i>Resolved</i>, That this convention cherish a grateful recollection
of the self-denying labors of our late lamented missionary to
Africa, Rev. Lott Cary, and that we sympathize with his family,
the American Colonization Society, and the church at Monrovia, in
the loss they have sustained in his death.</p>

<p><i>Resolved</i>, That it be recommended to the Board to take measures
for supplying the vacancy occasioned by the death of Bro. Cary as
soon as possible by an able white missionary, and that they
endeavor to the utmost of their power to promote the success of
this mission, as one in which the convention feel a special
interest.</p>

<p class="author">S. Cornelius, Chairman.</p>

</blockquote>

<p>It was not until 1832 that the Convention saw the error of its
conclusion and declared that it must depend "principally on <i>colored
persons</i>, as missionaries and school teachers, in Africa."<a name="FNanchor_196_634" id="FNanchor_196_634"></a><a href="#Footnote_196_634" class="fnanchor">[196]</a>
Despite this color-phobia of the Baptists, nothing can explain away
the fact that Lott Cary had lived helpfully and died honorably.
Gurley<a name="FNanchor_197_635" id="FNanchor_197_635"></a><a href="#Footnote_197_635" class="fnanchor">[197]</a> and Hervey<a name="FNanchor_198_636" id="FNanchor_198_636"></a><a href="#Footnote_198_636" class="fnanchor">[198]</a> would make him a man of genius who, had he
possessed educational advantages, would have won a worldwide
reputation as preacher, as general or as chief magistrate. This
square-faced, keen-eyed, reserved, cautious black held nothing back.
From Charles City County to Richmond, from slave to freedman, from
profligate to prophet, from sinner to saint, is a record that might
have <span class='pagenum'><a name="Page_418" id="Page_418">[Pg 418]</a></span>gone unnoticed; but from America to Africa, from governed to
governor, from missionary to martyr is Lott Cary.</p>

<p>For over a score of years the little village of Carytown was the only
memento of the man. But in 1850, the Rev. Eli Ball, an agent of the
Southern Baptist Convention, while visiting all the Liberian Baptist
Mission stations, found with difficulty the final resting place of
Lott Cary. The next year a marble monument was sent out and placed
over his grave.<a name="FNanchor_199_637" id="FNanchor_199_637"></a><a href="#Footnote_199_637" class="fnanchor">[199]</a></p>


