<h2><a name="No1_a8" id="No1_a8"></a>
NOTES</h2>


<p>The annual meeting of the Association, held at Lynchburg on the 14th
and 15th of November, was the most successful conference hitherto held
by this organization. The proceedings appear elsewhere in this number.</p>

<p>At this meeting Prof. John R. Hawkins, for years a member of the
Executive Council, was elected President. A new Secretary-Treasurer,
Mr. S. W. Rutherford, was also elected. Mr. Rutherford is a well-known
business man in Washington. The Executive Council was reconstructed to
make it national. The following persons were added thereto: Bishop R.
A. Carter, R. R. Church, John W. Davis, Clement Richardson, and R. C.
Woods. Most of the former members of the Executive Council were
retained.</p>

<p>The Associated Publishers, Incorporated, Washington, D. C., have
brought out C. G. Woodson's <i>History of the Negro Church</i>. A review of
this work will appear in the next number. Another work, the <i>Negro in
Our History</i>, will be published some time in March.</p>

<p><i>The Journal of Negro History</i> has received for review Mason and
Furr's <i>With the Red Hand of France</i>, an account of a regiment of
Negro soldiers in France with the American Expeditionary Force.</p>

<p>A group of intelligent Negroes in North Carolina have formed a state
historical society to preserve the records of the race in that
commonwealth.</p>

<p>Dr. C. G. Woodson, the Director of the Association is now making a
study of slavery from the point of view of the slave himself. He has
sent out a searching questionnaire from which some results are being
obtained. He is also consulting local records and documents left by
slaves themselves and by those in a position to know their attitude
toward the institution. The cooperation of all interested in
unearthing the truth is earnestly solicited.</p>

<p>Professor A. A. Taylor, of the West Virginia Collegiate Institute, is
now making a scientific study of the influence of the Negro
congressmen on the legislation of Congress and on the general policy
of the country. He will appreciate any facts which may not be covered
by the public documents and books available.</p>

<p>Duffield and Company of Boston have published a new edition of
Benjamin Brawley's <i>The Negro in Literature and Art</i>.</p>



