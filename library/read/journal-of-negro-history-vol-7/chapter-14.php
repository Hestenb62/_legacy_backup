<p>This is a letter from a Negro farmer in the south:</p>

<blockquote><p><span class="smcap">Isaac P. Martin</span>&mdash;</p>

<p>Merryweather Co&mdash;near Stenson</p>

<p>Father belonged to Peter Martin near about 3 miles from where he
was born&mdash;never did own any land. Went to work planting at
9&mdash;Worked 9 to 25&mdash;Had six or eight months schooling&mdash;Went one
month in a year. School lasted about three months. Used Blue Back
Speller got as high as Baker; Got as far as subtraction&mdash;Did not
know anything outside of reading&mdash;Did not know what a newspaper
was.</p>

<p>Father taught us to work corn, cotton sweet potatoes&mdash;He was a
&mdash;&mdash; farmer&mdash;Had eleven children all worked&mdash;about 1880 they
began to grow up and leave the farm&mdash;go on some other
plantation&mdash;all married.</p>

<p>My older brother and all the younger children got more schooling
Brother next younger&mdash;Payne's Institute Ga.&mdash;finished preaching
in Americus Georgia. I had a cousin to come here&mdash;He wanted to
buy &mdash;&mdash; here&mdash;He was interested in machine shop&mdash;He was down in
Opelika. He met more boys on their way here, inquiring around to
get down this far and get in.</p>

<p>I had saved up $200 in the bank. I was going to buy land. Went
into day school a Preparatory about 800 or 900 students. The
first work was in harness &amp; shoe shop&mdash;Lewis Adams was in
charge&mdash;I came there walking. I wanted to get away from the farm.
Going around town I saw that everyone looked better than on the
farm&mdash;I wanted to be something. Went in twice a year. We had
plenty country churches. Rabbits, squirrels, ducks,
possums&mdash;Geography, reading, Wentworth's Arithmetic. Miss Hunt
and Miss Logan were one of my teachers. I read lots about
Hiawatha. There was a number of little boys in the shop&mdash;they
used to call me "Pop." They were ahead of me. Went to Blacksmith
Shop. Worked about four months. Then went to work in<span class='pagenum'><a name="Page_218" id="Page_218">[Pg 218]</a></span>
Wheelwright. I learn a good deal about blacksmith and wood work.
I find both these trade very handy.</p>

<p>I was here three weeks before I could eat in the dining room&mdash;had
to go to restaurant&mdash;I was ashamed.</p>

<p>I was here only one term. Came in 1895&mdash;left in 96&mdash;Never came
back until tonight. My mother sent for me&mdash;My mother was awful
sick. My class was so low that I was ashamed to come back. I
weighed 240 pounds. I went back home until 1898&mdash;on farm. I got
to read my newspapers. I subscribed for the semi-monthly Atlanta
Journal&mdash;I could read that.</p>

<p>I saw advertised and so much money paid out for wages&mdash;I thought
I would go into business. I started grocery store and meat
market&mdash;I had $2,500 made on farm. Father used to run us off the
farm at 20 so I rented some land.</p>

<p>I was born 1870. I had been working for myself for years. 1898 I
came to Birmingham. I failed in grocery business. "Credit." I
made a lot of friends all over town. <span class="spacious">.......................................</span>
They had lots of money but they
owed a lot. It take lot to feed them. Took three years and little
over to get all of money.</p>

<p>Worked for Tenn. Coal and Iron Co. I leased some land from the
Republic Iron and Steel Co. Leased 64 acres outside of Pratt City
and went to trucking. I bought two mules for $40. It was a sale.
They were old run down mules. They were blind&mdash;I worked there
until I grew something. Farm about a mile from Pretts. Paid $1.50
per acre&mdash;now I pay $7. The company would not sell. I peddle
vegetables to people here&mdash;ran two wagons&mdash;now I run three. Got
new feed for horses. By fall had lots of stuff. Married in
1900&mdash;year after went to Birmingham. Second year I was able to
buy two good mules&mdash;Had two good wagons made. Fall of second year
had another which made three. Running three now. I employ six
people&mdash;3 men and 3 women all the time. I drive the wholesale
wagon.</p>

<p>I raise between $3,500 and $4,000 worth of stuff each year. Have
since the second year. I sell about $2,000 a year above expenses.
Production increases every year. I learned all I know about
trucking since then. I have fifteen head of cattle. Eight milking
cows. I raise three crops. That is the highest. Third crop is not
worth so much. 90,000 cabbages this year. Got the plants from
South Carolina. I bought a piece of land in Oklahoma <span class='pagenum'><a name="Page_219" id="Page_219">[Pg 219]</a></span>for $3,000
outside of 22 miles from Muskogee. Land rents now for $300. I own
a lot in Red Bird. Have 2 children. 14 &amp; and 17. They go to
school.</p>

<p>Won county prize year before last&mdash;196 bushels&mdash;this year
received State prize 200 bushels. Plant eight and ten acres of
cotton, 14 acres corn. Raise all my fodder. Three-fourths acres
of new sugar cane, 150 gals. of syrup. I make butter $30 per
hundred. $40 retail. I take two or three little farm journals and
take the bulletin.</p></blockquote>

