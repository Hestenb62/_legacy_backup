<p class="hang"><i>The Wings of Oppression.</i> By <span class="smcap">Leslie Pinckney Hill.</span> The Stratford
Company, Publishers, Boston, Massachusetts. Price by mail, $2.15.</p>

<p>Bearing the certificate of the Lyric Muse, Mr. Leslie Pinckney Hill,
schoolmaster of Cheney, Pennsylvania, and authentic singer, is the
newest arrival on the slopes of Parnassus. A first glance tells that
he is an agile climber, sinewy, easy of movement, light of step, with
both grace and strength. Every indication in form and motion is for
some point far up toward the summit. Youthful is he, ambitious
plainly, and, in spite of a burden, buoyant. "Climber," I said. I will
drop the figure. Poets were never pedestrians. Mr. Hill comes not
afoot. If not on the wings of Pegasus, yet on wings he comes&mdash;<i>the
wings of oppression</i>. Sad wings! Yet it must be remarked that it is
commonly on such wings that poets of whatever race and time rise. And
Mr. Hill's race knows no other wings. On the wings of oppression the<span class='pagenum'><a name="Page_227" id="Page_227">[Pg 227]</a></span>
Negro poet and the Negro people are rising toward the summits of
Parnassus, Pisgah, and other peaks. This they know, too, and of it
they are justly proud.</p>

<p>In his <i>Foreword</i> Mr. Hill thus states the case of his people, and, by
implication, of himself:</p>

<blockquote><p>"Nothing in the life of the nation has seemed to me more
significant than that dark civilization which the colored man has
built up in the midst of a white society organized against it.
The Negro has been driven under all the burdens of oppression,
both material and spiritual, to the brink of desperation, but he
has always been saved by his philosophy of life. He has advanced
against all opposition by a certain elevation of his spirit. He
has been made strong in tribulation. He has constrained
oppression to give him wings."</p></blockquote>

<p>The significant thing about these wings, in a critical view, is that
they fulfill the proper function of wings&mdash;bear aloft and sustain in
flight through the azure depths. Mr. Hill's wings do bear aloft and
sustain: if not always, nor even ever, into the very empyrean of
poetry, yet invariably, seventy times, into the ampler air. Like all
his race, he has suffered much; and, like all his race still, he has
gathered wisdom from sorrow. As a true poet should have, he has
philosophy, also vision and imagination&mdash;vision for himself and his
people, imagination that sees facts in terms of beauty and presents
truths with vital imagery. Add thereto craftsmanship acquired in the
best traditions of English poetry and you have Hill the poet.</p>

<p>The merits of this book cannot be shown by the quoting of lines and
stanzas. As ever with true art, the merit lies in the effect of
complete poems. Still, we can here detach from this and that poem a
stanza or two, despite the wrong to art. The first and fourth stanzas
of the title-poem will indicate Mr. Hill's technique and philosophy:</p>

<div class="poem"><div class="stanza">
<span class="i0">I have a song that few will sing<br /></span>
<span class="i0">In honor of all suffering,<br /></span>
<span class="i0">A song to which my heart can bring<br /></span>
<span class="i0">The homage of believing&mdash;<br /></span>
<span class="i0">A song the heavy-laden hears<br /></span>
<span class="i0">Above the clamor of his fears,<br /></span>
<span class="i0">While still he walks with blinding tears,<br /></span>
<span class="i0">And drains the cap of grieving.<br /></span>
</div></div>
<p class="ellipsis">.&nbsp;.&nbsp;.&nbsp;.&nbsp;.&nbsp;.&nbsp;</p>
<p><span class='pagenum'><a name="Page_228" id="Page_228">[Pg 228]</a></span></p>
<div class="poem"><div class="stanza">
<span class="i0">So long as life is steeped in wrong,<br /></span>
<span class="i0">And nations cry: "How long, how long!"<br /></span>
<span class="i0">I look not to the wise and strong<br /></span>
<span class="i0">For peace and self-possession:<br /></span>
<span class="i0">But right will rise, and mercy shine,<br /></span>
<span class="i0">And justice lift her conquering sign<br /></span>
<span class="i0">Where lowly people starve and pine<br /></span>
<span class="i0">Beneath a world oppression.<br /></span>
</div></div>

<p>Significant as interpreting the character and temper of the Negro with
whom today the white world has to deal, are the following lines from
the blank verse poem entitled <i>Armageddon</i>:</p>

<div class="poem"><div class="stanza">
<span class="i0">Because ye schooled them in the arts of life,<br /></span>
<span class="i0">and gave to them your God, and poured your blood<br /></span>
<span class="i0">Into their veins to make them what they are,<br /></span>
<span class="i0">They shall not fail you in your hour of need,<br /></span>
<span class="i0">They hold in them enough of you to feel<br /></span>
<span class="i0">All that has made you masters in your time&mdash;<br /></span>
<span class="i0">The power of art and wealth, unending toil,<br /></span>
<span class="i0">Proud types of beauty, an unbounded will<br /></span>
<span class="i0">To triumph, wondrous science, and old law&mdash;<br /></span>
<span class="i0">These have they learned to value and to share.<br /></span>
</div></div>

<p>If these poems, taken collectively, do not declare "what is on the
Negro's mind," they yet truly reveal, to the reflecting person, what
has sunk deep into his heart. They are therefore a message to America,
a protest, an appeal, and a warning. They will penetrate, I predict,
through breast armor of <i>aes triplex</i> into the hearts of those whom
sermons and editorials fail to touch in the springs of action. Such is
the virtue of music wed to persuasive words.</p>

<p>A sonnet entitled <i>To a Caged Canary in a Negro Restaurant</i> will
present the poet's people and his own manner of poetic musing:</p>

<div class="poem"><div class="stanza">
<span class="i0">Thou little golden bird of happy song!<br /></span>
<span class="i0">A cage cannot restrain the rapturous joy<br /></span>
<span class="i0">Which thou dost shed abroad. Thou dost employ<br /></span>
<span class="i0">Thy bondage for high uses. Grievous wrong<br /></span>
<span class="i0">Is thine; yet in thy heart glows full and strong<br /></span>
<span class="i0">The tropic sun, though far beyond thy flight,<br /></span>
<span class="i0">And though thou flutterest there by day and night<br /></span>
<span class="i0">Above the clamor of a dusky throng.<br /></span>
<span class="i0">So let my will, albeit hedged about<br /></span>
<span class="i0">By creed and caste, feed on the light within;<br /></span>
<span class="i0">So let my song sing through the bars of doubt<br /></span>
<span class="i0">With light and healing where despair has been;<br /></span>
<span class="i0">So let my people bide their time and place,<br /></span>
<span class="i0">A hindered but a sunny-hearted race.<br /></span>
</div></div><p><span class='pagenum'><a name="Page_229" id="Page_229">[Pg 229]</a></span></p>

<p>It would be an injustice to this poet did I convey the idea that his
seventy-odd poems are exclusively occupied with race wrongs and
oppression. Not a few of them bear no stamp of an oppressed or
afflicted spirit, though of sorrow they may have been nurtured.</p>

<p>A lyric of pure loveliness is the following, entitled:</p>

<p class="center sc">To a Nobly-Gifted Singer</p>
<div class="poem"><div class="stanza">
<span class="i0">All the pleasance of her face<br /></span>
<span class="i0">Telleth of an inward grace;<br /></span>
<span class="i0">In her dark eyes I have seen<br /></span>
<span class="i0">Sorrows of the Nazarene;<br /></span>
<span class="i0">In the proud and perfect mould<br /></span>
<span class="i0">Of her body I behold,<br /></span>
<span class="i0">Rounded in a single view,<br /></span>
<span class="i0">The good, the beautiful, the true;<br /></span>
<span class="i0">And when her spirit goes up-winging<br /></span>
<span class="i0">On sweet air of artless singing,<br /></span>
<span class="i0">Surely the heavenly spheres rejoice<br /></span>
<span class="i0">In union with a kindred voice.<br /></span>
</div></div>

<p><i>The Wings of Oppression</i> strikes a high level of artistic expression
and makes a quite extraordinary appeal. It is intense poetry, lyrical
and meditative.</p>

<p>Here is that solid body of thought which, in addition to artistic
expression, is requisite to poetry that attains and holds a high place
of esteem. Great variety of form is also here; excellent blank verse
with a movement at once easy and restrained, an equable, strong flow,
bearing lofty meditations; sonnets after the manner of the masters;
octo-syllabics of sententious felicity; various apt lyrical stanzas.
Culture alone, of which there is abundant evidence, could not have
produced these poems. The poetic endowment, thoroughly disciplined,
was necessary. Mr. Leslie Pinckney Hill is a poet. His powers are
rich, varied, and developing. His second book will be better than this
excellent first.</p>

<p>But more than the merit that has been intimated there is in these
lyrics and measured musings a pathos, a restrained Laoco&ouml;n cry, that
must be to thousands an arresting revelation of the unimagined
sufferings of the cultured colored people of our land. Mr. Hill's
<i>Wings of Oppression</i> has a message in it for America.</p>

<p class="author">Robert T. Kerlin</p>
<p class="author-addr">Lexington, Va.</p>



