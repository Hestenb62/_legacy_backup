<p>Some interesting articles in various publications are: "Problems of
Race Assimilation," by Arthur C. Parker, in the January number of <i>The
American Indian Magazine</i>; The Cavalry Fight at Carrizal, by Louis S.
Morey, in <i>The Journal of the United States Cavalry</i><span class='pagenum'><a name="Page_333" id="Page_333">[Pg 333]</a></span> <i>Association</i>;
The Present Labor Situation, in the January number of <i>The Annals of
the American Academy of Political and Social Sciences</i>; Physic Factors
in the New American Race Situation, in <i>The Journal of Race
Development</i>, by George W. Ellis; and La Independencia de Tejas y la
Esclavitud, by Senor V. Salado Alvarez, in the Cuban journal <i>La
Reforma Social</i>.</p>

<p>Other such articles in this field are: Germany's Ambition in Central
Africa, by Emile Cammaerts, in the October number of <i>The National
Review</i>; The Present System of Education in Uganda, in the July number
of <i>Uganda Notes</i>; The Gold Coast: Some Consideration of its
Structures, People, and Natural History, by A. E. Kitson, in the July
number of the <i>Geographic Journal</i>.</p>

<hr class="short" />

<p>The arrangements for the biennial meeting of the Association for the
Study of Negro Life and History have been almost completed. A majority
of the members of the Executive Council desire that it be held on
Wednesday, the twenty-ninth of August, and have so ordered it. The
program has not yet been made up, but several persons of prominence
have promised to attend and speak. Among these are Mrs. Mary Church
Terrell, Dean Kelly Miller, Professor George E. Haynes, Dr. R. R.
Wright, Jr., Mr. Monroe N. Work, and Dr. Thomas J. Jones. Two of the
important topics will be <i>Some Values of Negro History</i> and <i>The Negro
in the World War</i>.</p>



