<div class="footnote"><p><a name="Footnote_97_97" id="Footnote_97_97"></a><a href="#FNanchor_97_97"><span class="label">[97]</span></a> The battle of Port Hudson, like the battle of New
Orleans, is almost too well known to be told of. It takes its place
naturally in history with desperate fights, reminding one somewhat of
the battles of Balaklava. It was early in the morning of May 27, 1863,
that the engagement began. The colored men in line numbered 1,080.
When the order for assault was given they charged the fort, which
belched forth its flame and shot and shell. The slaughter was
horrible, but the line never wavered. Into the mill of death the
colored troops hurled themselves. The colors were shot through and
almost severed from the staff; the color-sergeant, Anselmas
