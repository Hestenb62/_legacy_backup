<h2><a name="No4_a3" id="No4_a3"></a>
Three Negro Poets: Horton, Mrs. Harper, and Whitman<a name="FNanchor_477_477" id="FNanchor_477_477"></a><a href="#Footnote_477_477" class="fnanchor">[477]</a></h2>


<p>With the exception of a few noteworthy individuals, conscious literary
effort on the part of the Negro in America is, of course, a matter of
comparatively recent years. Decades before Emancipation, however,
there were those who yearned toward poetry as a means of artistic
expression, and sought in this form to give vent to their groping,
their striving, and their sorrow. Handicapped as they were, scores of
these black bards must forever remain unknown. Even after the Civil
War those who had gifts were frequently held back by insufficient
education or the lack of other advantages of culture. At least three
persons, however, in the long period between Phillis Wheatley and Paul
Dunbar, deserve not wholly to pass unnoticed. These were George Moses
Horton, Mrs. Frances Ellen Watkins Harper, and Albery A. Whitman. Each
one of these poets had faults and even severe limitations as an
artist. Each one had also, however, a spark of the divine fire that
occasionally even kindled a flame.</p>

<p>George M. Horton was born a slave in Chatham County, North Carolina,
in 1797. Later he became the property of one Hall Horton, son of
James, who, from all accounts, was a very hard master. George,
however, was permitted to hire his time out at Chapel Hill, the seat
of the University of North Carolina, where by some accounts he
received twenty-five cents a day for his labor, by others fifty cents.
He was very ambitious. He was fond of the melodies and hymns sung at
campmeetings, and learned to read largely by matching the words he
knew in the hymnal to those in a spelling-book. Many people of
distinction became interested in his abilities; several legends exist
as to<span class='pagenum'><a name="Page_385" id="Page_385">[Pg 385]</a></span> his instructors; and Dr. Caldwell, president of the University,
was for some years a special patron. George's earliest poetical
compositions, however, had to be written down for him by other people.
His work was infused with his desire for freedom, and much of it was
suggested by the common evangelical hymns, as were the following
lines:</p>

<div class="poem"><div class="stanza">
<span class="i0">Alas! and am I born for this,<br /></span>
<span class="i2">To wear this slavish chain?<br /></span>
<span class="i0">Deprived of all created bliss,<br /></span>
<span class="i2">Through hardship, toil, and pain?<br /></span>
</div><div class="stanza">
<span class="i0">How long have I in bondage lain,<br /></span>
<span class="i2">And languished to be free!<br /></span>
<span class="i0">Alas! and must I still complain,<br /></span>
<span class="i2">Deprived of liberty?<br /></span>
</div><div class="stanza">
<span class="i0">. . . . . . . . . . . . . . . . . . . . . . . . .<br /></span>
</div><div class="stanza">
<span class="i0">Come, Liberty, thou cheerful sound,<br /></span>
<span class="i2">Roll through my ravished ears;<br /></span>
<span class="i0">Come, let my grief in joys be drowned,<br /></span>
<span class="i2">And drive away my fears.<br /></span>
</div></div>

<p>Some of Horton's friends undertook to help him publish a volume of his
poems so that from the sale of these he might purchase his freedom and
go to the new colony of Liberia. The young man now became fired with
ambition and inspiration. Thrilled by the new hope he wrote</p>

<div class="poem"><div class="stanza">
<span class="i0">'Twas like the salutation of the dove,<br /></span>
<span class="i0">Borne on the zephyr through some lonesome grove,<br /></span>
<span class="i0">When spring returns, and winter's chill is past,<br /></span>
<span class="i0">And vegetation smiles above the blast.<br /></span>
</div></div>

<p>Horton's master, however, demanded for him an exorbitant price, and
when the booklet, <i>The Hope of Liberty</i>, appeared in 1829 it had
nothing of the sale that was hoped for. He lived for years as a
janitor at the University, executed small commissions for verse from
the students, who treated him kindly, and in later years even went to
Philadelphia; but his old dreams had faded. Several reprintings of his
poems were made, however, and one of these was bound with the 1838
edition of Phillis Wheatley's poems. He died in 1880 (by other
accounts 1883). A scholarly article about<span class='pagenum'><a name="Page_386" id="Page_386">[Pg 386]</a></span> him was written for the
<i>Southern Workman</i> of October, 1914, by Mr. Stephen B. Weeks, who in
turn owed much to the researches of Prof. George S. Wills.</p>

<p>Horton's work showed readily the influence of his models. He used
especially the meter of the common evangelical hymns, and cultivated
the vague personification of the poets of the eighteenth century. He
himself, however, was essentially a romantic poet, as was evinced by
his fondness for Byron and Marlowe. His common style is represented by
the following lines from his poem entitled <i>On the Evening and
Morning</i>:</p>

<div class="poem"><div class="stanza">
<span class="i0">When Evening bids the Sun to rest retire,<br /></span>
<span class="i0">Unwearied Ether sets her lamps on fire;<br /></span>
<span class="i0">Lit by one torch, each is supplied in turn,<br /></span>
<span class="i0">Till all the candles in the concave burn.<br /></span>
</div><div class="stanza">
<span class="i0">. . . . . . . . . . . . . . . . . . . . . . . . . . . . .<br /></span>
</div><div class="stanza">
<span class="i0">At length the silver queen begins to rise,<br /></span>
<span class="i0">And spread her glowing mantle in the skies,<br /></span>
<span class="i0">And from the smiling chambers of the east,<br /></span>
<span class="i0">Invites the eye to her resplendent feast.<br /></span>
</div></div>

<p>The passion in the heart of this man, his undoubted gifts as a poet,
and the bitter disappointment of his yearnings have all but added one
more to the long list of those who died with their ambitions blasted
and their most ardent hopes defeated.</p>

<p>In 1854 appeared the first edition of <i>Poems on Miscellaneous
Subjects</i>, by Frances Ellen Watkins, commonly known as Mrs. Frances E.
W. Harper, who was for many years before the public and who is even
now remembered by many friends. Mrs. Harper was a woman of strong
personality and could read her poems to advantage. Her verse was very
popular, not less than ten thousand copies of her booklets being sold.
It was decidedly lacking in technique, however, and much in the style
of Mrs. Hemans. <i>The Death of the Old Sea King</i>, for instance, is in
the ballad style cultivated by this poet and Longfellow; but it is not
a well-sustained effort. Mrs. Harper was best when most simple, as
when in writing of children she said:<span class='pagenum'><a name="Page_387" id="Page_387">[Pg 387]</a></span></p>

<div class="poem"><div class="stanza">
<span class="i0">I almost think the angels<br /></span>
<span class="i2">Who tend life's garden fair,<br /></span>
<span class="i0">Drop down the sweet white blossoms<br /></span>
<span class="i2">That bloom around us here.<br /></span>
</div></div>

<p>The secret of her popularity is to be seen in such lines as the
following from <i>Bury me in a Free Land</i>:</p>

<div class="poem"><div class="stanza">
<span class="i0">Make me a grave where'er you will,<br /></span>
<span class="i0">In a lowly plain or a lofty hill;<br /></span>
<span class="i0">Make it among earth's humblest graves,<br /></span>
<span class="i0">But not in a land where men are slaves.<br /></span>
</div><div class="stanza">
<span class="i0">I could not rest if around my grave<br /></span>
<span class="i0">I heard the steps of a trembling slave:<br /></span>
<span class="i0">His shadow above my silent tomb<br /></span>
<span class="i0">Would make it a place of fearful gloom.<br /></span>
</div><div class="stanza">
<span class="i0">. . . . . . . . . . . . . . . . . . . . . . . . .<br /></span>
</div><div class="stanza">
<span class="i0">I ask no monument, proud and high,<br /></span>
<span class="i0">To arrest the gaze of the passers-by;<br /></span>
<span class="i0">All that my yearning spirit craves<br /></span>
<span class="i0">Is bury me not in a land of slaves.<br /></span>
</div></div>

<p>Of the Emancipation Proclamation she wrote:</p>

<div class="poem"><div class="stanza">
<span class="i0">It shall flash through coming ages,<br /></span>
<span class="i2">It shall light the distant years;<br /></span>
<span class="i0">And eyes now dim with sorrow<br /></span>
<span class="i2">Shall be brighter through their tears.<br /></span>
</div></div>

<p>While Mrs. Harper was still prominently before the public appeared
Albery A. Whitman, a Methodist minister, whose important collection,
<i>Not a Man and Yet a Man</i>, appeared in 1877, and whose long and
ambitious poem, <i>Twasinta's Seminoles</i>, or <i>The Rape of Florida</i> (the
latter title being the one most used), was issued in 1884. This writer
had great love for his work. In the preface to his second volume he
wrote of poetry as follows: "I do not believe poetry is on the
decline. I do not believe that human advancement extinguishes the
torch of sentiment. I can not think that money-getting is the whole
business of man. Rather am I convinced that the world is approaching a
poetical revolution. The subtle evolution of thought must yet be
expressed in song. Poetry is the language of<span class='pagenum'><a name="Page_388" id="Page_388">[Pg 388]</a></span> universal sentiment.
Torch of the unresting mind, she kindles in advance of all progress.
Her waitings are on the threshold of the infinite, where, beckoning
man to listen, she interprets the leaves of immortality. Her voice is
the voice of Eternity dwelling in all great souls. Her aims are the
inducements of heaven, and her triumphs the survival of the Beautiful,
the True, and the Good. In her language there is no mistaking of that
liberal thought which is the health of mind. A secret interpreter, she
waits not for data, phenomena, and manifestations, but anticipates and
spells the wishes of Heaven."</p>

<p>The work of Whitman himself is exceedingly baffling. It is to his
credit that something about his work at once commands judgment by the
highest standards. If we consider it on this basis, we find that it is
diffuse, exhibits many lapses in taste, is faulty metrically, as if
done in haste, and shows imitation on every hand. It imitates
Whittier, Longfellow and Tennyson; Scott, Byron and Moore. <i>The Old
Sac Village</i> and <i>Nanawawa's Suitors</i> are very evidently <i>Hiawatha</i>
over again, and <i>Custer's Last Ride</i> is simply another version of <i>The
Charge of the Light Brigade</i>. And yet, whenever one has about decided
that Whitman is not worthy of consideration, the poet insists on a
revision of judgment; and he certainly could not have imitated so many
writers so readily, if he had not had some solid basis in
appreciation. The fact is that he shows a decided faculty for brisk,
though not sustained, narration. This may be seen in <i>The House of the
Aylors</i>. He has, moreover, a romantic lavishness of description that
in spite of all technical faults still has some degree of merit. The
following quotations, taken respectively from <i>The Mowers</i> and <i>The
Flight of Leeona</i>, with all their extravagance, will exemplify both
his weakness and his strength in description:</p>

<div class="poem"><div class="stanza">
<span class="i0">The tall forests swim in a crimson sea,<br /></span>
<span class="i0">Out of whose bright depths rising silently,<br /></span>
<span class="i0">Great golden spires shoot into the skies,<br /></span>
<span class="i0">Among the isles of cloudland high, that rise,<br /></span>
<span class="i0">Float, scatter, burst, drift off, and slowly fade,<span class='pagenum'><a name="Page_389" id="Page_389">[Pg 389]</a></span><br /></span>
<span class="i0">Deep in the twilight, shade succeeding shade.<br /></span>
</div><div class="stanza">
<span class="i0">. . . . . . . . . . . . . . . . . . . . . . . . . . . . . . .<br /></span>
</div><div class="stanza">
<span class="i0">And now she turns upon a mossy seat,<br /></span>
<span class="i0">Where sings a fern-bound stream beneath her feet,<br /></span>
<span class="i0">And breathes the orange in the swooning air;<br /></span>
<span class="i0">Where in her queenly pride the rose blooms fair,<br /></span>
<span class="i0">And sweet geranium waves her scented hair;<br /></span>
<span class="i0">There, gazing in the bright face of the stream,<br /></span>
<span class="i0">Her thoughts swim onward in a gentle dream.<br /></span>
</div></div>

<p>In <i>A Dream of Glory</i> occur the lines,</p>

<div class="poem"><div class="stanza">
<span class="i0">The fairest blooms are born of humble weeds,<br /></span>
<span class="i2">That faint and perish in the pathless wood;<br /></span>
<span class="i0">And out of bitter life grow noble deeds<br /></span>
<span class="i2">To pass unnoticed in the multitude.<br /></span>
</div></div>

<p><i>The Bards of England</i> discusses many poets. The following is the
passage on Byron:</p>

<div class="poem"><div class="stanza">
<span class="i0">To Missolonghi's chief of singers too,<br /></span>
<span class="i0">Unhappy Byron, is a tribute due&mdash;<br /></span>
<span class="i0">A wounded spirit, mournful and yet mad,<br /></span>
<span class="i0">A genius proud, defiant, gentle, sad;<br /></span>
<span class="i0">'Twas he whose Harold won his Nation's heart,<br /></span>
<span class="i0">And whose Reviewers made her fair cheeks smart;<br /></span>
<span class="i0">Whose uncurbed Juan hung her head for shame,<br /></span>
<span class="i0">And whose Mazeppa won unrivaled fame.<br /></span>
<span class="i0">Earth had no bound for him. Where'er he strode<br /></span>
<span class="i0">His restless genius found no fit abode.<br /></span>
</div></div>

<p>Whitman's shortcomings become readily apparent when he attempts
sustained work. <i>The Rape of Florida</i> is the longest poem yet written
by a Negro in America, and also the only attempt by a member of the
race to use the elaborate Spenserian stanza throughout a long piece of
work. The story is concerned with the capture of the Seminoles in
Florida through perfidy and the taking of them away to their new home
in the West. It centers around three characters, Palmecho, an old
chief, Ewald, his daughter, and Atlassa, a young Seminole who is
Ewald's lover. The poem is decidedly diffuse; there is too much
subjective description, too little strong characterization. Palmecho,
instead of being a stout warrior, is a "chief of peace and<span class='pagenum'><a name="Page_390" id="Page_390">[Pg 390]</a></span> kindly
deeds." Stanzas of merit, however, occasionally strike the eye. The
boat-song forces recognition as genuine poetry:</p>

<div class="poem"><div class="stanza">
<span class="i0">"Come now, my love, the moon is on the lake;<br /></span>
<span class="i0">Upon the waters is my light canoe;<br /></span>
<span class="i0">Come with me, love, and gladsome oars shall make<br /></span>
<span class="i0">A music on the parting wave for you,&mdash;<br /></span>
<span class="i0">Come o'er the waters deep and dark and blue:<br /></span>
<span class="i0">Come where the lilies in the marge have sprung,<br /></span>
<span class="i0">Come with me, love, for Oh, my love is true!"<br /></span>
<span class="i0">This is the song that on the lake was sung,<br /></span>
<span class="i0">The boatman sang it over when his heart was young.<br /></span>
</div></div>

<p>It is important to note in a consideration of Whitman's method that
while he is writing a story about Indians he frequently leaves this to
tell how he feels as a Negro. The following stanzas, however, are
pertinent to present-day discussion:</p>

<div class="poem"><div class="stanza">
<span class="i0">'Tis hard to judge if hatred of one's race,<br /></span>
<span class="i0">By those who deem themselves superior-born,<br /></span>
<span class="i0">Be worse than that quiescence in disgrace,<br /></span>
<span class="i0">Which only merits&mdash;and <i>should</i> only&mdash;scorn!<br /></span>
<span class="i0">Oh! let me see the Negro, night and morn,<br /></span>
<span class="i0"><i>Pressing</i> and fighting in, for place and power!<br /></span>
<span class="i0">If he a proud escutcheon would adorn,<br /></span>
<span class="i0">All earth is place&mdash;all time th' auspicious hour,<br /></span>
<span class="i0">While heaven leans forth to see, oh! can he quail or cower?<br /></span>
</div><div class="stanza">
<span class="i0">Ah! I abhor his protest and complaint!<br /></span>
<span class="i0">His pious looks and patience I despise!<br /></span>
<span class="i0">He can't evade the test, disguised as saint,<br /></span>
<span class="i0">The manly voice of freedom bids him rise,<br /></span>
<span class="i0">And shake himself before Philistine eyes!<br /></span>
<span class="i0">And, like a lion roused, no sooner than<br /></span>
<span class="i0">A foe dare come, play all his energies,<br /></span>
<span class="i0">And court the fray with fury if he can!<br /></span>
<span class="i0">For hell itself respects a fearless manly man.<br /></span>
</div></div>

<p>In 1890 Whitman brought out an edition of <i>Not a Man and Yet a Man</i>
and <i>The Rape of Florida</i>, adding to these a collection of
miscellaneous poems, <i>Drifted Leaves</i>, and in 1901 he published <i>An
Idyl of the South</i>, an epic poem in<span class='pagenum'><a name="Page_391" id="Page_391">[Pg 391]</a></span> two parts. It is to be regretted
that he did not have the training that comes from the best university
education. He had the taste and the talent to benefit from such
culture in the greatest degree.</p>

<p>This brief review of the work of three earnest members of the race
prompts a few reflections on the whole art of poetry as this is
cultivated by the Negro in America. If we may make any reasonable
deduction from the work of the poets studied, if we may arrive at any
conclusion from the work of Paul Laurence Dunbar and the younger
writers of the day, we should say that the genius of the race is
subjective and romantic rather than objective and classic. In poetry,
least of all arts, does the Negro conceal his individuality. This is
his great gift, but also in another way the spur to further
achievement. The race should in course of time produce many brilliant
lyric poets. Dunbar was a lyric poet; so was Pushkin. The drama and
the epic obviously call for more extended information, a more
objective point of view, and a broader basis in general culture than
many members of the race have so far had the time or the talent or the
inclination to give to them.</p>

<p>Again, has one ever asked himself why it is that so much of the poetry
of the Negro fails to reach the ultimate standards of art? It
certainly is not because of lack of imagination, for God has been
generous in the imagery with which he has endowed the race. First of
all, last of all, is it not the matter of technique? Many booklets of
verse that have been issued show that the writers had not mastered
even the ordinary fundamentals of English grammar. For one to think of
rivalling Tennyson with his classical tradition when he can not make a
clearcut English sentence is out of the question. Further, and this is
the most important point, the work of those in question almost never
exhibits imagination expressed in intense, condensed, vivid, and
suggestive phrase&mdash;such phrasing, for instance, as one will find in
"The Eve of St. Agnes," which I am not alone in considering the most
lavishly brilliant and successful brief effort in poetry in the
language. To all of this might be added a<span class='pagenum'><a name="Page_392" id="Page_392">[Pg 392]</a></span> refining of taste,
something all too frequently lacking and something that can come only
from the most arduous and diligent culture. When we further secure
such things as these the race may indeed possess not only a Horton, a
Harper, or a Whitman, but a Tennyson, a Keats, and even a Shakespeare.</p>

<p class="author">Benjamin Brawley</p>

