<h2><a name="No1_a9" id="No1_a9"></a>Notes</h2>


<p>Harrison and Sons, London, have published an "<i>Anthropological Report
on Sierra Leone</i>," by Northcote W. Thomas, in three parts. Part I
covers the law and customs of the Tinne and other tribes. Part II
consists of a "Tinne-English dictionary" and part III of a grammar and
stories.</p>

<p>This firm has also brought out "<i>Specimens of Languages from Sierra
Leone</i>" by the same author. This work contains tabular vocabularies
with short stories and notes on Tones, illustrated with the Staff
Notation.</p>

<p>Macmillan and Company have published the "<i>My Yoruba Alphabet</i>" by R.
E. Bennett.</p>

<p>"<i>M&acirc;liki Law</i>" by F. H. Buxton has appeared with the imprint of Luzac
and Company. This is a summary from French Translations of the
"<i>Mukhtasar of S&icirc;d&icirc; Khal&icirc;l</i>" by Captain Buxton of the Political
Department of Nigeria. It was published by order of Sir F. D. Sugard,
Governor-General of Nigeria.</p>

<p>"<i>Native Life in South Africa before and since the European War and
the Boer Rebellion</i>" by Sol. T. Plaatje has been published by P. S.
King. This work is especially valuable for students of Negro History
in that they may obtain from it the other side of the race problem in
that country. The author is an educated native who has served the
government as an interpreter, and now edits for a native syndicate
<i>Tsala ea Batho</i> (The People's Friend). The purpose of the writer is
to explain the grievances of the natives and especially that one
resulting from the Land Act of 1913.</p>

<p>Allen and Unwin have published the third volume of "<i>The History of
South Africa from 1795 to 1872</i>" by G. McCall Theal. The work is to be
completed in five volumes.</p>

<p>Among Putnam's recent publications is F. W. Seward's "<i>Reminiscences
of a War Time Statesman and Diplomat</i>," being his father William H.
Seward.</p>

<p>The University of Chicago Press has published "<i>Slavery in Germanic
Society during the Middle Ages</i>."<span class='pagenum'><a name="Page_103" id="Page_103">[Pg 103]</a></span></p>

<p>C. R. Hall has published through the Princeton University Press his
"<i>Andrew Johnson: Military Governor of Tennessee</i>."</p>

<p>Stokes has published J. A. B. Scherer's <i>Cotton as a World Power</i>.</p>

<p>Mr. Henry B. Rankin's "<i>Personal Recollections of Abraham Lincoln</i>"
has come from the press of the Putnams. This book is interesting and
valuable in that it is written by a man who studied law under Lincoln
and Herndon.</p>

<p>The Chicago Historical Society has published a booklet entitled "<i>The
Convention that nominated Lincoln</i>," giving its outward and local
aspects.</p>

<p>In C. J. Heatwole's <i>History of Education in Virginia</i>, published by
Macmillan, passing mention is given the effort to enlighten the
Negroes in that State. The writer is mainly concerned with the efforts
for the uplift of the Negro since emancipation. He seemed to be
ignorant of the many efforts at education put forth by the Negroes
with the help of their friends even before the Civil War.</p>

<p>E. S. Green's <i>History of the University of South Carolina</i> has been
published by the State Publishing Company at Columbia. In treating the
period during which the Negroes were in control of that institution
the author is adversely critical of the freedmen in general, but
mentions some colored graduates and pays a tribute to the high
character of Richard Theodore Greener, who served there as instructor.</p>

<p>"<i>The South To-day</i>" by John M. Moore has been published by the
Missionary Education Movement of the United States and Canada.</p>

<p>The <span class="smcap">Journal of Negro History</span> has received a copy of Charles E.
Benton's "<i>Troutbeck: A Dutchess County Homestead</i>," with an
introduction by John Borroughs. Among the beautiful illustrations in
this pamphlet is that of Webutuck River at Troutbeck during the
performance of the "Hiawatha Pageant" at the fifth Amenia Field Day,
August 15, 1914.</p>

<p>A. A. Schomburg's <i>Bibliographical Checklist of American Negro Poetry</i>
has been published as one of a series of monographs edited by Charles
F. Heartman of New York. It is a valuable work.<span class='pagenum'><a name="Page_104" id="Page_104">[Pg 104]</a></span></p>

<p>The Argosy Company, Georgetown, British Guiana, has recently published
a work entitled <i>Black Talk</i>. This book consists of notes on Negro
dialect compiled by C. G. Cruickshank. It is an interesting and
informing volume.</p>



