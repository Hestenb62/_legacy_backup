<h2><a name="No4_a11" id="No4_a11"></a>Notes</h2>


<p>Mr. A. E. Martin, of the Pennsylvania State College, will soon publish
through the Filson Club <i>The Anti-Slavery Movement in Kentucky to
1850</i>. Mr. Martin plans to bring this study down to 1870.</p>

<p>The New York Missionary Education Movement of the United States and
Canada has published <i>The Lure of Africa</i> by C. H. Patton.</p>

<p>W. M. Ramsay's <i>The Intermixture of Races in Asia Minor</i> has come from
the Oxford University Press.</p>

<p>The Harvard University Press has published <i>Ephod and Ark</i>, by W. R.
Arnold.</p>

<p>July number of <i>The Journal of Race Development</i> contains two
interesting articles: <i>On the Culture of White Folk</i>, by Dr. W. E. B.
DuBois, and <i>Psychic Factors in the New American Race Situation</i>, by
George W. Elliss, K.C., F.R.G.S.</p>

<p>The July number of the <i>American Journal of Sociology</i> contains a
rather misinforming article on <i>The Superiority of the Mulatto</i>, by
Mr. E. B. Reuter, and another on <i>Class and Caste</i>, by Edward Alsworth
Ross.</p>

<p>In the July number of the <i>South Atlantic Quarterly</i> appears <i>The
Black Codes</i>, by Prof. John M. Mecklin, of the University of
Pittsburgh.</p>

<p>Prof. Benjamin Brawley will soon publish a work to be known as <i>The
Genius of the Negro</i>.</p>

<p><i>La Revista Bimestre Cubana</i> has published Los <i>Negros Esclavos</i>, a
study in sociology and public law by Fernando Ortiz, professor in the
University of Havana.</p>

<p>The United States Bureau of Education in cooperation with the
Phelps-Stokes Fund has published in two volumes a report entitled
<i>Negro Education, a Study of the Private and Higher Schools for
Colored People in the United States</i>. This report was prepared under
the direction of Dr. Thomas Jesse Jones, specialist in the education
of racial groups. This work was undertaken to comply with<span class='pagenum'><a name="Page_441" id="Page_441">[Pg 441]</a></span> that
provision of the will of Miss Caroline Phelps-Stokes directing that
some portion of the income from a fund originally amounting to about
$900,000 be used for the education of Negroes and for research and
publication. In 1912 it was decided to prepare a report on Negro
education to furnish the public with valuable information as to
existing conditions throughout the South. The Bureau of Education
agreed to cooperate with the trustees of the Phelps-Stokes Fund,
bringing the work under the general supervision of the United States
Commissioner of Education. This report is the result of their
efficient cooperation.</p>

<p>On the thirtieth of August, there assembled at the request of the
United States Commissioner of Education a conference to discuss this
report. For two days practically all of the active white and colored
educators in Negro schools discussed the various phases of education
as brought out by this report and undertook to find a working basis
for a more extensive cooperation of all agencies in the uplift of the
Negro. The frank statements of several of the State Superintendents,
like that of Mr. Harris of Louisiana, showed how much good a report of
this kind may do in arousing the best white people of the South to a
realization that it pays to educate all citizens of the state whether
they be white or black. No definite decision was reached but the
conference was a success in leading men to study more seriously the
problems of Negro education.</p>



