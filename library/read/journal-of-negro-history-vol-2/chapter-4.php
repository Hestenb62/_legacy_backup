in business in Philadelphia. This man attracted the attention of his
friends because he declined the assistance offered him by persons
sufficiently wealthy to establish him in life, merely because they had
acquired their wealth by enslaving Negroes. He not only labored among
his own people for the liberation of the slaves, but boldly appealed
to others. He finally expressed his sentiments in a publication called
the "Mystery of Inquiry," a brief treatise on the evil of the
institution of slavery. The importance attached to this work is that
Sandiford published it and circulated it at his own expense despite
the fact that he had been threatened with prosecution by the judge.
This pamphlet was written in correct and energetic style, abounding
with facts, sentiments and quotations, which showed the virtue and
talents of the author and made a forceful appeal in behalf of the
blacks. See Clarkson's "History of the Abolition of the Slave Trade,"
Volume I, pp. 147-148.</p></div>

<div class="footnote"><p><a name="Footnote_24_24" id="Footnote_24_24"></a><a href="#FNanchor_24_24"><span class="label">[24]</span></a> Benjamin Lay, the next worker in this cause, lived at
Abington, not far from Philadelphia. He was a man of desirable class
and had access to the homes of some of the best people even when in
England. He was not long in this country before he championed the
cause of the slave. In 1737 he published his first treatise on
slavery, distributing it far and wide, especially among the members of
the rising generation. He traveled extensively through this country
and the West Indies and personally took up the question of abolition
with the governors of the slave colonies. It is doubtful, according to
Clarkson, that he rendered the cause great service by this mission.
This writer says that "in bearing what he believed to be his testimony
against this system of oppression, he adopted sometimes a singularity
of manner, by which, as conveying demonstration of a certain
eccentricity of character, he diminished in some degree his usefulness
to the cause which he had undertaken; as far indeed as this
eccentricity might have the effect of preventing others from joining
him in his pursuit, lest they should be thought singular also, so far
it must be allowed that he ceased to become beneficial. But there can
be no question, on the other hand, that his warm and enthusiastic
manners awakened the attention of many to the cause, and gave them
first impressions concerning it, which they never forgot, and which
rendered them useful to it in the subsequent part of their lives." See
Clarkson's "History of Abolition of the African Slave Trade," Vol. I,
pp. 148-150.</p></div>

<div class="footnote"><p><a name="Footnote_25_25" id="Footnote_25_25"></a><a href="#FNanchor_25_25"><span class="label">[25]</span></a> John Woolman shared with Anthony Benezet the honor of
being one of the two foremost workers in behalf of the oppressed race.
He was born in Burlington County in New Jersey in 1720. When quite a
youth he was deeply impressed with religion and resolved to live a
righteous life. He was therefore in his twenty-second year made a
minister of the gospel among the Quakers. Just prior to his entering
upon the ministry there happened an incident which set him against
slavery. Being a poor man he was working for wages as a bookkeeper in
a store. "My employer," said he, "having a Negro woman sold her, and
desired me to write a bill of sale, the man being waiting, who bought
her. The thing was sudden, and though the thought of writing an
instrument of slavery for one of my fellow-creatures made me feel
uneasy, yet I remembered I was hired by the year, that it was my
master who directed me to do it, and that it was an elderly man, a
member of our Society, who bought her. So through weakness I gave way
and wrote, but, at executing it, I was so afflicted in my mind, that I
said before my master and the friend, that I believed slave-keeping to
be a practice inconsistent with the Christian religion. This in some
degree abated my uneasiness; yet, as often as I reflected seriously
upon it, I thought I should have been clearer, if I had desired to
have been excused from it, as a thing against my conscience; for such
it was. And some time after this, a young man of our Society spoke to
me to write a conveyance of a slave to him, he having lately taken a
Negro into his house. I told him I was not easy to write it; for
though many of our meeting, and in other places kept slaves, I still
believed the practice was not right, and desired to be excused from
the writing. I spoke to him in good will; and he told me that keeping
slaves was not altogether agreeable to his mind, but that the slave
being a gift to his wife he had accepted her." Moved thus so early in
his life he developed into an ardent friend of the Negro and ever
labored thereafter to elevate and emancipate them. See Clarkson's
"History of the Abolition of the African Slave Trade."</p></div>

