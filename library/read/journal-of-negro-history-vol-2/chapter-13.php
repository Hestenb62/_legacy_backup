<span class="i0">Rash councils now, with each malignant plan,<br /></span>
<span class="i0">Each faction, that in evil hour began,<br /></span>
<span class="i0">At your approach are in confusion fled,<br /></span>
<span class="i0">Nor, while you rule, shall rear their dastard head.<br /></span>
<span class="i0">Alike the master and the slave shall fee<br /></span>
<span class="i0">Their neck reliev'd, the yoke unbound by thee.<br /></span>
<span class="i0">Ere now our guiltless isle, her wretched fate<br /></span>
<span class="i0">Had wept, and groan'd beneath th' oppressive weight<br /></span>
<span class="i0">Of Cruel woes; save thy victorious hand,<br /></span>
<span class="i0">Long fam'd in war, from Gallia's hostile land;<br /></span>
<span class="i0">And wreaths of fresh renown, with generous zeal,<br /></span>
<span class="i0">Had freely turn'd, to prop our sinking weal.<br /></span>
<span class="i0">Form'd as thou art, to serve <i>Britannia's</i> crown,<br /></span>
<span class="i0">While <i>Scotia</i> claims thee for her darling son;<br /></span>
<span class="i0">Oh! best of heroes, ablest to sustain<br /></span>
<span class="i0">A falling people, and relax their chain.<br /></span>
<span class="i0">Long as this isle shall grace the Western deep,<br /></span>
<span class="i0">From age to age, thy fame shall never sleep.<br /></span>
<span class="i0">Thee, her dread victor <i>Guadaloupe</i> shall own,<br /></span>
<span class="i0">Crusht by thy arm, her slaughter'd chiefs bemoan;<br /></span>
<span class="i0">View their proud tents all level'd in the dust,<br /></span>
<span class="i0">And, while she grieves, confess the cause was just.<br /></span>
<span class="i0">The golden <i>Iris</i> the sad scene will share,<span class='pagenum'><a name="Page_157" id="Page_157">[Pg 157]</a></span><br /></span>
<span class="i0">Will mourn her banners scattered in the air;<br /></span>
<span class="i0">Lament her vanquisht troops with many a sigh,<br /></span>
<span class="i0">Nor less to see her towns in ruin lie.<br /></span>
<span class="i0">Fav'rite of <i>Mars!</i> believe, th' attempt were vain,<br /></span>
<span class="i0">It is not mine to try the arduous strain.<br /></span>
<span class="i0">What! shall an <i>&AElig;thiop</i> touch the martial string,<br /></span>
<span class="i0">Of battles, leaders, great achievements sing?<br /></span>
<span class="i0">Ah no! <i>Minerva</i>, with th' indignant <i>Nine</i>,<br /></span>
<span class="i0">Restrain him, and forbid the bold design.<br /></span>
<span class="i0">To a <i>Buchanan</i> does the theme belong;<br /></span>
<span class="i0">A theme, that well deserves <i>Buchanan's</i> song,<br /></span>
<span class="i0">'Tis he, should swell the din of war's alarms,<br /></span>
<span class="i0">Record thee great in council, as in arms;<br /></span>
<span class="i0">Recite each conquest by thy valour won,<br /></span>
<span class="i0">And equal thee to great <i>Peleides'</i> son.<br /></span>
<span class="i0">That bard, his country's ornament and pride,<br /></span>
<span class="i0">Who e'en with <i>Maro</i> might the bays divide:<br /></span>
<span class="i0">Far worthier he, thy glories to rehearse,<br /></span>
<span class="i0">And paint thy deeds in his immortal verse.<br /></span>
<span class="i0">We live, alas! where the bright god of day,<br /></span>
<span class="i0">Full from the zenith whirls his torrid ray:<br /></span>
<span class="i0">Beneath the rage of his consuming fires,<br /></span>
<span class="i0">All fancy melts, all eloquence expires.<br /></span>
<span class="i0">Yet may you deign accept this humble song,<br /></span>
<span class="i0">Tho' wrapt in gloom, and from a faltering tongue;<br /></span>
<span class="i0">Tho' dark the stream on which the tribute flows,<br /></span>
<span class="i0">Not from the <i>skin</i>, but from the <i>heart</i> it rose.<br /></span>
<span class="i0">To all of human kind, benignant heaven<br /></span>
<span class="i0">(Since nought forbids) one common soul has given.<br /></span>
<span class="i0">This rule was 'stablish'd by th' Eternal Mind;<br /></span>
<span class="i0">Nor virtue's self, nor prudence are confin'd<br /></span>
<span class="i0">To colour; none imbues the honest heart;<br /></span>
<span class="i0">To science none belongs, and none to art.<br /></span>
<span class="i0">Oh! <i>Muse</i>, of blackest tint, why shrinks thy breast.<br /></span>
<span class="i0">Why fears t' approach the <i>C&aelig;sar</i> of the <i>West!</i><br /></span>
<span class="i0">Dispel thy doubts, with confidence ascend<br /></span>
<span class="i0">The regal dome, and hail him for thy friend:<br /></span>
<span class="i0">Nor blush, altho' in garb funereal drest,<br /></span>
<span class="i0"><i>Thy body's white, tho' clad in sable vest</i>.<br /></span>
<span class="i0">Manners unsullied, and the radiant glow<br /></span>
<span class="i0">Of genius, burning with desire to <i>know</i>;<br /></span>
<span class="i0">And learned speech, with modest accent worn,<br /></span>
<span class="i0">Shall best the sooty <i>African</i> adorn.<br /></span>
<span class="i0">An heart with wisdom fraught, a patriot flame.<br /></span>
<span class="i0">A love of virtue; these shall lift his name<br /></span>
<span class="i0">Conspicuous, far beyond his kindred race,<br /></span>
<span class="i0">Distinguish'd from them by the foremost place.<br /></span>
<span class="i0">In this prolific isle I drew my birth,<br /></span>
<span class="i0">And <i>Britain</i> nurs'd, illustrious through the earth;<span class='pagenum'><a name="Page_158" id="Page_158">[Pg 158]</a></span><br /></span>
<span class="i0">This, my lov'd isle, which never more shall grieve,<br /></span>
<span class="i0">Whilst you our common friend, our father live.<br /></span>
<span class="i0">Then this my pray'r&mdash;"My earth and heaven survey<br /></span>
<span class="i0">"A people ever blest, beneath your sway!"<br /></span>
</div></div>
</blockquote>

<p>The following translation of this poem has been supplied by Mr. E.J.
Chinock, M.A., LL.B.:</p>


<blockquote>
<p class="center">
A Poem in Honour of<br />
Sir George Haldane, Knt.,<br />
Amost virtuous and brave man,<br />
Governor of the island of Jamaica, on whom all the endowments of<br />
morals and of warlike virtues have been accumulated.</p>

<p>Since the Fates wish the year should come at last, all the joys
which are to be seen through a lengthened day are present. The
people having shaken off their anxieties, are prosperous under a
bright image, and the land flourishing under law. While thou art
ruler, the useless things which had been done by an ill-advising
mind will not return at thy appearance. Therefore, all the
people, even the rabble, will see that thou hast removed the yoke
clinging to their necks, and the ills which the guiltless island
has formerly endured with dreadful tortures. The burden would
have been excessively painful did not thy victorious hand,
previously renowned for valour, wish of its own accord to aid our
state going to ruin. The British King has no better servant than
thou art, whilst Scotland rejoices in thy talent. Thou are the
best of heroes to prop up the fall of a nation; while the island
survives, the memory of thee will also survive. Quadaloupe will
recognise thee as her conqueror, and will deservedly despise the
plundered camps of its governors. The golden Iris will weep for
her boastful standards, and together with her inhabitants will
groan for the conquered towns. Believe me, it is not in my power,
O man, dear to Mars! Minerva denies to an Ethiopian to celebrate
the wars of generals. Buchanan would sing thee in a poem, he
would describe thee as equal to Achilles in counsel and in war.
That famous poet, the honour of his country, is more worthy to
relate thy exploits, and is scarcely inferior to the majestic
Virgil. We live under an Apollo driving his own flame-bringing
team. Every kind of eloquence is lacking to slaves. Receive this
at any rate. Though poured forth from one very black, it is
valuable, coming from a sonorous mouth; not from his skin, but
from his heart. The bountiful Deity, with a hand powerfully and
firm, has given the same soul to men of all races, nothing
standing in his way. Virtue itself, and prudence, are free from
colour; there is no colour in an honourable mind, no colour in
skill. Why dost thou fear or doubt that the blackest Muse may
scale the lofty house of the western Caesar? Go and salute him,
and let it not be to thee a cause of shame that thou wearest a
white body in a black skin. Integrity of <i>morals</i> more adorns a
<i>Moor</i>, and ardour of intellect and sweet elegance in a learned
mouth. A wise heart and a love of his ancestral virtue the more
remove him from his comrades and make him conspicuous. The island
(of Jamaica) gave me birth; the renowned Britons brought me up;
the island which will not grieve while thou its father art well.
This I pray: O may earth and heaven see thee without end, ruling
a flourishing people.<a name="FNanchor_227_227" id="FNanchor_227_227"></a><a href="#Footnote_227_227" class="fnanchor">[227]</a></p></blockquote>
<p><span class='pagenum'><a name="Page_159" id="Page_159">[Pg 159]</a></span></p>

<p>Gardner quotes the line</p>

<div class="poem"><div class="stanza">
<span class="i0">"Candida quod nigra corpora pelle geris,"<br /></span>
</div></div>

<p>giving it an interpretation disparaging to Williams' racial
self-respect. With more understanding of the poet's surroundings it
may be taken rather to express the poet's desire to be marked as
distinct from the then condition of those who represented his race
round him, namely slaves.</p>

<p>The following lines especially deserve praise for the height in
emotion and manliness to which they ascend:</p>

<div class="poem"><div class="stanza">
<span class="i0">Pollenti stabilita manu, Deus almus, eandem<br /></span>
<span class="i2">Omnigenis animam, nil prohibente dedit.<br /></span>
<span class="i0">Ipsa coloris egens virtus, prudentia; honesto<br /></span>
<span class="i2">Nullus inest animo, nullus in arte color.<br /></span>
</div></div>

<p>Mr. Chinook's rendering conveys some of their stirring force, but they
deserve a better translation, and one reason for giving the whole poem
here is the hope that it may elicit another translation from some one
entering more feelingly and with equal lingual knowledge into the
poet's conception.</p>

