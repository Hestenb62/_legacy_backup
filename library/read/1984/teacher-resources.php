                    <p class="quiz-q"><strong>1.</strong> What are the four ministries of Oceania's government, and what is ironic about their respective names?</p>
                    <details class="tr-answer-key">
                        <summary><i class="fas fa-key"></i> View Verified Teacher Answer</summary>
                        <div class="answer-content">
                            <strong>Answer:</strong>
                            <ul>
                                <li><strong>Ministry of Truth (Minitrue):</strong> Responsible for news, entertainment, and education &mdash; in reality, systematically falsifies history and writes propaganda.</li>
                                <li><strong>Ministry of Peace (Minipax):</strong> Responsible for warfare &mdash; maintains perpetual conflict.</li>
                                <li><strong>Ministry of Love (Miniluv):</strong> Responsible for law, order, and interrogation &mdash; tortures dissidents in Room 101.</li>
                                <li><strong>Ministry of Plenty (Miniplenty):</strong> Responsible for economic affairs &mdash; orchestrates artificial shortages and rationing.</li>
                            </ul>
                            <span class="answer-ref">Reference: Part 1, Chapter 1</span>
                        </div>
                    </details>
                </div>

                <div class="tr-quiz-item">
                    <p class="quiz-q"><strong>2.</strong> How does the party define and enforce "Doublethink" (Crimestop)?</p>
                    <details class="tr-answer-key">
                        <summary><i class="fas fa-key"></i> View Verified Teacher Answer</summary>
                        <div class="answer-content">
                            <strong>Answer:</strong> Doublethink is the psychological capacity to hold two contradictory beliefs in one's mind simultaneously, and accept both as true. The party enforces it so that citizens can alter historical reality at a moment's notice while believing with total sincerity that the new fact was always true.
                            <span class="answer-ref">Reference: Part 1, Chapter 3 &amp; Goldstein's Book</span>
                        </div>
                    </details>
                </div>

                <div class="tr-quiz-item">
                    <p class="quiz-q"><strong>3.</strong> What is the significance of the coral paperweight Winston purchases in the junk shop?</p>
                    <details class="tr-answer-key">
                        <summary><i class="fas fa-key"></i> View Verified Teacher Answer</summary>
                        <div class="answer-content">
                            <strong>Answer:</strong> The glass paperweight represents Winston's desire to recover the lost past, an unaltered era of beauty and human emotion. The coral encased within glass symbolizes Winston and Julia enclosed in their temporary room, isolated from the Party's reach until it is brutally shattered during their arrest.
                            <span class="answer-ref">Reference: Part 1, Chapter 8; Part 2, Chapter 10</span>
                        </div>
                    </details>
