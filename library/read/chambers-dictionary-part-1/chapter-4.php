        <h3>EXPLANATIONS TO THE STUDENT.</h3>

  <p><b>The Arrangement of the Words.</b>—Every word is given in its
  <i>alphabetical</i> order, except in cases where, to save space,
  derivatives are given after and under the words from which they are
  derived. Each uncompounded verb has its participles, when irregular,
  placed after it. Exceptional plurals are also given. When a word stands
  after another, with no meaning given, its meanings can be at once formed
  from those of the latter, by adding the signification of the affix: thus
  the meanings of <i>Darkness</i> are obtained by prefixing the meaning of
  <i>ness</i>, <i>state of being</i>, to those of <i>Dark</i>.</p>

  <p>Many words from French and other tongues, current in English usage,
  but not yet fairly Anglicised, are inserted in the list of Foreign
  Phrases, &amp;c., at the end, rather than in the body of the
  Dictionary.</p>

  <p><b>The Pronunciation.</b>—The Pronunciation is given immediately
  after each word, by the word being spelled anew. In this new spelling,
  every consonant used has its ordinary unvarying sound, <i>no consonant
  being employed that has more than one sound</i>. The same sounds are
  always represented by the same letters, no matter how varied their actual
  spelling in the language. No consonant used has any mark attached to it,
  with the one exception of <i>th</i>, which is printed in common letters
  when sounded as in <i>thick</i>, but in italics when sounded as in
  <i>th</i>en. <i>Unmarked vowels</i> have always their short sounds, as in
  <i>lad</i>, <i>led</i>, <i>lid</i>, <i>lot</i>, <i>but</i>, <i>book</i>.
  The <i>marked vowels</i> are shown in the following line, which is
  printed at the top of each page:—</p>

<p class="cenhead">fāte, fär; mē, hėr; mīne; mōte; mūte; mōōn; <i>th</i>en.</p>

  <p>The vowel <i>u</i> when marked thus, <i>ü</i>, has the sound heard in
  Scotch <i>bluid</i>, <i>gude</i>, the French <i>du</i>, almost that of
  the German <i>ü</i> in <i>Müller</i>. Where more than one pronunciation
  of a word is given, that which is placed first is more accepted.</p>

  <p><b>The Spelling.</b>—When more than one form of a word is given,
  that which is placed first is the spelling in current English use.
  Unfortunately our modern spelling does not represent the English we
  actually speak, but rather the language of the 16th century, up to which
  period, generally speaking, English spelling was mainly phonetic, like
  the present German. The fundamental principle of all rational spelling is
  no doubt the representation of every sound by an invariable symbol, but
  in modern English the usage of pronunciation has drifted far from the
  conventional forms established by a traditional orthography, with the
  result that the present spelling of our written speech is to a large
  extent a mere exercise of memory, full of confusing anomalies and
  imperfections, and involving an enormous and unnecessary strain on the
  faculties of learners. Spelling reform is indeed an imperative necessity,
  but it must proceed with a wise moderation, for, in the words of Mr
  Sweet, 'nothing can be done without unanimity, and until the majority of
  the community are convinced of the superiority of some one system
  unanimity is impossible.' The true path of progress should follow such
  wisely moderate counsels as those of Dr J. A. H. Murray:—the
  dropping of the final or inflexional silent <i>e</i>; the restoration of
  the historical <i><span class="nw">-t</span></i> after breath consonants;
  uniformity in the employment of double consonants, as in <i>traveler</i>,
  &amp;c.; the discarding of <i>ue</i> in words like <i>demagogue</i> and
  <i>catalogue</i>; the uniform levelling of the agent <i><span class="nw">-our</span></i> into <i><span class="nw">-or</span></i>; the
  making of <i>ea = ĕ</i> short into <i>e</i> and the long <i>ie</i>
  into <i>ee</i>; the restoration of <i>some</i>, <i>come</i>,
  <i>tongue</i>, to their old English forms, <i>sum</i>, <i>cum</i>,
  <i>tung</i>; a more extended use of <i>z</i> in the body of words, as
  <i>chozen</i>, <i>praize</i>, <i>raize</i>; and the correction of the
  worst individual monstrosities, as <i>foreign</i>, <i>scent</i>,
  <i>scythe</i>, <i>ache</i>, <i>debt</i>, <i>people</i>,
  <i>parliament</i>, <i>court</i>, <i>would</i>, <i>sceptic</i>,
  <i>phthisis</i>, <i>queue</i>, <i>schedule</i>,
  <i>twopence-halfpenny</i>, <i>yeoman</i>, <i>sieve</i>, <i>gauge</i>,
  <i>barque</i>, <i>buoy</i>, <i>yacht</i>, &amp;c.</p>

  <p>Already in America a moderate degree of spelling reform may be said to
  be established in good usage, by the adoption of <i><span class="nw">-or</span></i> for <i><span class="nw">-our</span></i>, as
  <i>color</i>, <i>labor</i>, &amp;c.; of <i><span class="nw">-er</span></i> for <i><span class="nw">-re</span></i>, as
  <i>center</i>, <i>meter</i>, &amp;c.; <i><span class="nw">-ize</span></i>
  for <i><span class="nw">-ise</span></i>, as <i>civilize</i>, &amp;c.; the
  use of a uniform single consonant after an unaccented vowel, as
  <i>traveler</i> for <i>traveller</i>; the adoption of <i>e</i> for
  <i>œ</i> or <i>æ</i> in <i>hemorrhage</i>, <i>diarrhea</i>,
  &amp;c.</p>

  <p><b>The Meanings.</b>—The current and most important meaning of a
  word is usually given first. But in cases like <i>Clerk</i>,
  <i>Livery</i>, <i>Marshal</i>, where the force of the word can be made
  much clearer by tracing its history, the original meaning is also given,
  and the successive variations of its usage defined.</p>

  <p><b>The Etymology.</b>—The Etymology of each word is given after
  the meanings, within brackets. Where further information regarding a word
  is given elsewhere, it is so indicated by a reference. It must be noted
  under the etymology that whenever a word is printed thus, <b>Ban</b>,
  <b>Base</b>, the student is referred to it; also that here the
  sign—is always to be read as meaning 'derived from.' Examples are
  generally given of words that are cognate or correspond to the English
  words; but it must be remembered that they are inserted merely for
  illustration. Such words are usually separated from the rest by a
  semicolon. For instance, when an English word is traced to its
  Anglo-Saxon form, and then a German word is given, no one should suppose
  that our English word is derived from the German. German and Anglo-Saxon
  are alike branches from a common Teutonic stem, and have seldom borrowed
  from each other. Under each word the force of the prefix is usually
  given, though not the affix. For fuller explanation in such cases the
  student is referred to the list of Prefixes and Suffixes in the
  Appendix.</p>

