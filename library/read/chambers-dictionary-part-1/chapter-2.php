        <h3 style="letter-spacing: 0.2em;">PREFACE.</h3>

  <p>This is the third English Dictionary which the present Editor has
  prepared, and he may therefore lay claim to an unusually prolonged
  apprenticeship to his trade. It is surely unnecessary for him to say that
  he believes this to be the best book of the three, and he can afford to
  rest content if the Courteous Reader receive it with the indulgence
  extended to his Library Dictionary, published in the spring of 1898. It
  is based upon that work, but will be found to possess many serviceable
  qualities of its own. It is not much less in content, and its greater
  relative portability is due to smaller type, to thinner paper, and still
  more to a rigorous compression and condensation in the definitions, by
  means of which room has been found for many additional words.</p>

  <p>The aim has been to include all the common words in literary and
  conversational English, together with words obsolete save in the pages of
  Spenser, Shakespeare, Milton, and the Authorised Version of the Bible. An
  attempt has been made also to include the common terms of the sciences
  and the arts of life, the vocabulary of sport, those Scotch and
  provincial words which assert themselves in Burns, Scott, the Brontës,
  and George Eliot, and even the coinages of word-masters like Carlyle,
  Browning, and Meredith. Numberless compound idiomatic phrases have also
  been given a place, in each case under the head of the significant
  word.</p>

  <p>Correctness in technical matters has been ensured by consulting such
  books as Smyth's <i>Sailor's Word-Book</i>, Voyle's <i>Military
  Dictionary</i>, Wilson's <i>Stock-Exchange Glossary</i>, Lee's
  <i>Glossary of Liturgical and Ecclesiastical Terms</i>, &amp;c. Besides
  books of this class, the Editor has made constant use of special books
  such as Schmidt's <i>Shakespeare-Lexicon</i>, Calderwood's edition of
  Fleming's <i>Vocabulary of Philosophy</i>, Jamieson's <i>Scottish
  Dictionary</i>, the <i>Stanford Dictionary of Anglicised Words and
  Phrases</i>, Yule and Burnell's <i>Anglo-Indian Glossary</i>, Addis and
  Arnold's <i>Catholic Dictionary</i>, and the Dictionaries of the Bible of
  Sir William Smith and Dr Hastings.</p>

  <p>In Latin, his authority is Lewis and Short; in Greek, Liddell and
  Scott; in Romance Philology, Diez and Scheler; in French, Littré; in
  Spanish, Velazquez; in German, Weigand and Flügel; in Gaelic, Macleod and
  Dewar, and M'Bain; in Hebrew, Gesenius.</p>

  <p>In English etymology the Editor has consulted Professor Skeat's
  <i>Dictionary</i> and his <i>Principles of English
  Etymology</i>—First and Second Series; the magistral <i>New English
  Dictionary</i> of Dr James A. H. Murray and Mr Henry Bradley, so far as
  completed; and the only less valuable <i>English Dialect Dictionary</i>
  of Professor Wright (begun 1896).</p>

  <p>Two complete American <i>English Dictionaries</i> still hold the first
  place as works of reference, Professor Whitney's <i>Century
  Dictionary</i> and Funk and Wagnall's <i>Standard Dictionary</i>.</p>

  <p>The Editor has great pleasure in acknowledging his personal
  obligations to his brothers, the Rev. Robert P. Davidson, B.A., of
  Trinity College, Oxford, and David G. Davidson, M.D., Edinburgh; and to
  his equally capable and courteous colleagues, Mr J. R. Pairman and David
  Patrick, LL.D., Editor of <i>Chambers's Encyclopædia</i>.</p>

