<h3> <span class="smcap">Note V.</span></h3>

<p><span class="smcap">III.</span> 1. 120-122. Dr. A. Hunter (Harry Rowe) arranges these
lines as follows:</p>

<div class="poem"><div class="stanza">
<span class="i0">'But wail his fall whom I myself struck down:<br></span>
<span class="i0">For certain friends there are, both his and mine,<br></span>
<span class="i0">Whose loves I may not drop: and thence it is, &amp;c.'<br></span>
</div></div>


<h3> <span class="smcap">Note VI.</span></h3>

<p><span class="smcap">III.</span> 2. 29-35. In these lines we have followed the arrangement of
Steevens (1793), which with the exception of the fourth and fifth lines
is the same as that of the Folios. The Folios divide the fourth and
fifth lines thus:</p>

<div class="poem"><div class="stanza">
<span class="i0">'Vnsafe the while, that wee must laue<br></span>
<span class="i0">Our Honors in these flattering streames.'<br></span>
</div></div>

<p>Rowe read them:</p>

<div class="poem"><div class="stanza">
<span class="i0">'Unsafe the while, that we must lave our Honours<br></span>
<span class="i0">In these so flattering streams,<br></span>
<span class="i0">And make &amp;c.'<br></span>
</div></div>

<p>Pope:</p>

<div class="poem"><div class="stanza">
<span class="i0">'Unsafe the while, that we must lave our honours<br></span>
<span class="i0">In these so flatt'ring streams, and make our faces<br></span>
<span class="i0">Vizards t'our hearts, disguising what they are.<br></span>
</div></div>

<p>Capell rearranged the whole passage thus:</p>

<div class="poem"><div class="stanza">
<span class="i0">'So shall I, love;<br></span>
<span class="i0">And so, I pray, be you: let your remembrance<br></span>
<span class="i0">Apply to Banquo; present him eminence, both<br></span>
<span class="i0">With eye and tongue: Unsafe the while, that we<br></span>
<span class="i0">Must lave our honours in these flattering streams;<br></span>
<span class="i0">And make our faces vizards to our hearts.<br></span>
<span class="i0">Disguising what they are.'<br></span>
</div></div>

<p>Steevens suggested that something was omitted, and proposed to
read 'Unsafe the while it is for us, that we,' &amp;c.</p>


<h3> <span class="smcap">Note VII.</span></h3>

<p><span class="smcap">III.</span> 4. 124. 'Augure,' as was pointed out by Mr. Singer, was
used for 'augury.' In Florio's <i>World of Wordes</i>(1598), we find<span class="pagenum"><a id="Page_524">[Pg 524]</a></span>
'Augurio, an <i>augure</i>, a soothsaying, a prediction, a signe, a coniecture,
a divination, a bad or ill hap, a wishing of good hap, a forboding.'</p>


<h3> <span class="smcap">Note VIII.</span></h3>

<p><span class="smcap">IV.</span> 1. 43. Rowe, from Davenant's version, prints the song thus:</p>

<div class="poem"><div class="stanza">
<span class="i0">'Black Spirits and White,<br></span>
<span class="i0">Blue Spirits and Gray,<br></span>
<span class="i0">Mingle, mingle, mingle,<br></span>
<span class="i0">You that mingle may.'<br></span>
</div></div>

<p>In the second line Malone printed 'Red spirits,' &amp;c., following Middleton's
play of <i>The Witch</i>, Act <span class="smcap">V.</span> Sc. 2.</p>


<h3> <span class="smcap">Note IX.</span></h3>

<p><span class="smcap">V.</span> 1. 32. <i>Hell is murky.</i> Steevens printed these words with a
note of exclamation after them, with the following note. 'She certainly
imagines herself here talking to Macbeth, who, (she supposes,)
has just said, <i>Hell is murky</i>, (i.e. hell is a dismal place to go to in
consequence of such a deed,) and repeats his words in contempt of
his cowardice.'</p>

