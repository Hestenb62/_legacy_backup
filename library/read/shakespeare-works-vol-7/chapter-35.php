        <h2>NOTES.</h2>


<h3> <span class="smcap">Note I.</span></h3>

<p><span class="smcap">I.</span> 3. 21-24. Pope was the first to place the words 'Thus thou ...
undone' in inverted commas, and was followed substantially by all
subsequent editors with the exception of those we are about to mention.
Hanmer printed in italics 'This thou must do if thou have it'
only, and was followed by Capell and Mr. Staunton, except that
they restore the original reading 'Thus' for 'This.' Johnson proposed
to read 'me' for 'it' in line 22, printing in italics the same
words which Pope included in inverted commas. His reading was
adopted by Rann. Dr. A. Hunter (Harry Rowe) read:</p>

<div class="poem"><div class="stanza">
<span class="i0">'Thou'dst have, great Glamis,<br></span>
<span class="i0">That which cries, <i>Thus than must do, if thou have me,</i><br></span>
<span class="i0"><i>And that's what rather thou dost fear to do,</i><br></span>
<span class="i0"><i>Than wishest should be undone</i>.'<br></span>
</div></div>

<p>Mr. Joseph Hunter (<i>New Illustrations &amp;c. of Shakespeare</i>, <span class="smcap">II.</span> p. 172)
proposed to mark the words 'Thus thou must do' only as a quotation,
and to read line 22 thus:</p>

<div class="poem"><div class="stanza">
<span class="i0">'That which cries "Thus thou must do" if thou wouldst have it.'<br></span>
</div></div>


<h3> <span class="smcap">Note II.</span></h3>

<p><span class="smcap">II.</span> 1. 13, 14. The first Folio reads here:</p>

<div class="poem"><div class="stanza">
<span class="i0">'He hath beene in vnusuall Pleasure,<br></span>
<span class="i0">And sent forth great Largesse to your Offices.'<br></span>
</div></div>
<p><span class="pagenum"><a id="Page_522">[Pg 522]</a></span></p>
<p>The second, followed substantially by the third and fourth:</p>

<div class="poem"><div class="stanza">
<span class="i0">'He hath beene in unusuall pleasure.<br></span>
<span class="i0">And sent forth a great Largesse to your Offices.'<br></span>
</div></div>

<p>Rowe altered 'Offices' to 'Officers.'</p>

<p>Pope reads:</p>

<div class="poem"><div class="stanza">
<span class="i0">'He hath to-night been in unusual pleasure,<br></span>
<span class="i0">And sent great largess to your officers.'<br></span>
</div></div>

<p>'To-night' was first introduced in Davenant's Version.</p>

<p>This reading was adopted by subsequent editors down to Capell,
inclusive. Steevens (1773) has:</p>

<div class="poem"><div class="stanza">
<span class="i0">'He hath been in unusual pleasure;<br></span>
<span class="i0">Sent forth great largess to your officers.'<br></span>
</div></div>

<p>Jennens first adopted the arrangement given in our text, though he
retained Rowe's emendation 'officers.'</p>


<h3> <span class="smcap">Note III.</span></h3>

<p><span class="smcap">II.</span> 1. 24. After this line Jennens proposes to add the following to
Banquo's speech:</p>

<div class="poem"><div class="stanza">
<span class="i0">'Those lookers into fate, that hail'd you, <i>Cawdor</i>!<br></span>
<span class="i0">Did also hail you, king! and I do trust,<br></span>
<span class="i0">Most worthy <i>Thane</i>, you would <i>consent</i> to accept<br></span>
<span class="i0">What your deserts would grace, when offer'd you.'<br></span>
</div></div>


<h3> <span class="smcap">Note IV.</span></h3>

<p><span class="smcap">II.</span> 2. 35, 36. In the Folios and the earlier editors it is not clear
from the mode of printing where the words of the 'voice' ended.
Hanmer printed the whole in italics down to 'life's feast' in line 40,
omitting however line 37 with Pope. Johnson was the first to print
only the words 'Sleep no more! Macbeth doth murther sleep' as the cry
of the voice, supposing the remainder to be Macbeth's comment. In
lines 42, 43, where the printing of the earlier editions is equally indecisive,
Hanmer prints from 'Glamis' to 'Macbeth shall sleep no more'
in italics, while Johnson prints only 'Glamis hath murder'd sleep' as
the cry of the voice.</p>

