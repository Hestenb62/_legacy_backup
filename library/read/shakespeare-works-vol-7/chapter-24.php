<h3><span class="smcap">Scene IV.</span> <i>Another part of the same street, before the house</i>
<i>of Brutus.</i><a id="FNanchor_3154_3154"></a><a class="fnanchor pginternal" href="#Footnote_3154_3154">[3154]</a></h3>

<p class="directcenter"><i>Enter</i> <span class="smcap">Portia</span> <i>and</i> <span class="smcap">Lucius</span>.
</p>

<div class="poem"><div class="stanza">
<span class="i0"><i>Por.</i> I prithee, boy, run to the senate-house;<br></span>
<span class="i0">Stay not to answer me, but get thee gone.<br></span>
<span class="i0">Why dost thou stay?<br></span>
</div><div class="stanza">
<span class="i0"><i>Luc.</i>              To know my errand, madam.<br></span>
</div><div class="stanza">
<span class="i0"><i>Por.</i> I would have had thee there, and here again,<br></span>
<span class="i0">Ere I can tell thee what thou shouldst do there.                     <span class="linenum">5</span><br></span>
<span class="i0">O constancy, be strong upon my side!<a id="FNanchor_3155_3155"></a><a class="fnanchor pginternal" href="#Footnote_3155_3155">[3155]</a><br></span>
<span class="i0">Set a huge mountain 'tween my heart and tongue!<a class="fnanchor pginternal" href="#Footnote_3155_3155">[3155]</a><br></span>
<span class="i0">I have a man's mind, but a woman's might.<a class="fnanchor pginternal" href="#Footnote_3155_3155">[3155]</a><a id="FNanchor_3156_3156"></a><a class="fnanchor pginternal" href="#Footnote_3156_3156">[3156]</a><br></span>
<span class="i0">How hard it is for women to keep counsel!<a class="fnanchor pginternal" href="#Footnote_3155_3155">[3155]</a><br></span>
<span class="i0">Art thou here yet?<a class="fnanchor pginternal" href="#Footnote_3155_3155">[3155]</a><br></span>
</div><div class="stanza">
<span class="i0"><i>Luc.</i>             Madam, what should I do?                    <span class="linenum">10</span><br></span>
<span class="i0">Run to the Capitol, and nothing else?<br></span>
<span class="i0">And so return to you, and nothing else?<br></span>
</div><div class="stanza">
<span class="i0"><i>Por.</i> Yes, bring me word, boy, if thy lord look well,<a id="FNanchor_3157_3157"></a><a class="fnanchor pginternal" href="#Footnote_3157_3157">[3157]</a><br></span>
<span class="i0">For he went sickly forth: and take good note<br></span>
<span class="i0">What Cæsar doth, what suitors press to him.                         <span class="linenum">15</span><br></span>
