<span class="pagenum"><a id="Page_360">[Pg 360]</a></span></div><div class="stanza">
<span class="i0"><i>Por.</i> I must go in. Ay me, how weak a thing<a id="FNanchor_3167_3167"></a><a class="fnanchor pginternal" href="#Footnote_3167_3167">[3167]</a><br></span>
<span class="i0">The heart of woman is! O Brutus,<a id="FNanchor_3168_3168"></a><a class="fnanchor pginternal" href="#Footnote_3168_3168">[3168]</a><br></span>
<span class="i0">The heavens speed thee in thine enterprise!                         <span class="linenum">40</span><br></span>
<span class="i0">Sure, the boy heard me. Brutus hath a suit<br></span>
