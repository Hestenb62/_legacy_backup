<span class="i0"><i>Sooth.</i> None that I know will be, much that I fear may chance.<a id="FNanchor_3166_3166"></a><a class="fnanchor pginternal" href="#Footnote_3166_3166">[3166]</a><br></span>
<span class="i0">Good morrow to you. Here the street is narrow:<br></span>
<span class="i0">The throng that follows Cæsar at the heels,<br></span>
