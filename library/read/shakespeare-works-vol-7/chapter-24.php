<span class="i0">I heard a bustling rumour like a fray,<a id="FNanchor_3158_3158"></a><a class="fnanchor pginternal" href="#Footnote_3158_3158">[3158]</a><br></span>
<span class="i0">And the wind brings it from the Capitol.<br></span>
</div><div class="stanza">
<span class="i0"><i>Luc.</i> Sooth, madam, I hear nothing.<br></span>
</div></div>

