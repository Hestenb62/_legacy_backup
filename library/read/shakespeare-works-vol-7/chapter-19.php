<span class="i0">Whilst I have gold, I'll be his steward still.         <span class="directline">[<i>Exit.</i><span class="linenum">50</span><br></span></span>
</div></div>

<p><span class="pagenum"><a id="Page_268">[Pg 268]</a></span></p>
<h3><span class="smcap">Scene III.</span> <i>Woods and cave, near the sea-shore.</i><a id="FNanchor_2366_2366"></a><a class="fnanchor pginternal" href="#Footnote_2366_2366">[2366]</a></h3>

<p class="directcenter"><i>Enter</i> <span class="smcap">Timon</span>, <i>from the cave</i>.<a id="FNanchor_2367_2367"></a><a class="fnanchor pginternal" href="#Footnote_2367_2367">[2367]</a>
</p>

<div class="poem"><div class="stanza">
<span class="i0"><i>Tim.</i> O blessed breeding sun, draw from the earth<a id="FNanchor_2368_2368"></a><a class="fnanchor pginternal" href="#Footnote_2368_2368">[2368]</a><br></span>
<span class="i0">Rotten humidity; below thy sister's orb<br></span>
<span class="i0">Infect the air! Twinn'd brothers of one womb,<br></span>
<span class="i0">Whose procreation, residence and birth<br></span>
<span class="i0">Scarce is dividant, touch them with several fortunes,<a id="FNanchor_2369_2369"></a><a class="fnanchor pginternal" href="#Footnote_2369_2369">[2369]</a>          <span class="linenum">5</span><br></span>
<span class="i0">The greater scorns the lesser: not nature,<a id="FNanchor_2370_2370"></a><a class="fnanchor pginternal" href="#Footnote_2370_2370">[2370]</a><a id="FNanchor_2371_2371"></a><a class="fnanchor pginternal" href="#Footnote_2371_2371">[2371]</a><br></span>
<span class="i0">To whom all sores lay siege, can bear great fortune<a class="fnanchor pginternal" href="#Footnote_2371_2371">[2371]</a><br></span>
<span class="i0">But by contempt of nature.<a class="fnanchor pginternal" href="#Footnote_2371_2371">[2371]</a><a id="FNanchor_2372_2372"></a><a class="fnanchor pginternal" href="#Footnote_2372_2372">[2372]</a><br></span>
<span class="i0">Raise me this beggar and deny 't that lord,<a id="FNanchor_2373_2373"></a><a class="fnanchor pginternal" href="#Footnote_2373_2373">[2373]</a><br></span>
<span class="i0">The senator shall bear contempt hereditary,<a id="FNanchor_2374_2374"></a><a class="fnanchor pginternal" href="#Footnote_2374_2374">[2374]</a>                   <span class="linenum">10</span><br></span>
<span class="i0">The beggar native honour.<br></span>
<span class="i0">It is the pasture lards the rother's sides,<a id="FNanchor_2375_2375"></a><a class="fnanchor pginternal" href="#Footnote_2375_2375">[2375]</a><br></span>
<span class="i0">The want that makes him lean. Who dares, who dares,<a id="FNanchor_2376_2376"></a><a class="fnanchor pginternal" href="#Footnote_2376_2376">[2376]</a><br></span>
