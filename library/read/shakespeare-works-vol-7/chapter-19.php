<span class="i0">Poor honest lord, brought low by his own heart,<br></span>
<span class="i0">Undone by goodness! Strange, unusual blood,<a id="FNanchor_2359_2359"></a><a class="fnanchor pginternal" href="#Footnote_2359_2359">[2359]</a><br></span>
