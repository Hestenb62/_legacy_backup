</div></div>

<p class="directright">[<i>Servants embrace, and part several ways.</i></p>

<div class="poem"><div class="stanza">
<span class="i0">O, the fierce wretchedness that glory brings us!<a id="FNanchor_2354_2354"></a><a class="fnanchor pginternal" href="#Footnote_2354_2354">[2354]</a>              <span class="linenum">30</span><br></span>
<span class="i0">Who would not wish to be from wealth exempt,<br></span>
<span class="i0">Since riches point to misery and contempt?<br></span>
<span class="i0">Who would be so mock'd with glory? or to live<a id="FNanchor_2355_2355"></a><a class="fnanchor pginternal" href="#Footnote_2355_2355">[2355]</a><br></span>
<span class="i0">But in a dream of friendship?<a id="FNanchor_2356_2356"></a><a class="fnanchor pginternal" href="#Footnote_2356_2356">[2356]</a><br></span>
<span class="i0">To have his pomp and all what state compounds<a class="fnanchor pginternal" href="#Footnote_2356_2356">[2356]</a><a id="FNanchor_2357_2357"></a><a class="fnanchor pginternal" href="#Footnote_2357_2357">[2357]</a>          <span class="linenum">35</span><br></span>
