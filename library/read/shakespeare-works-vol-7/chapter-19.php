<span class="i0">Like empty purses pick'd; and his poor self,<br></span>
<span class="i0">A dedicated beggar to the air,<br></span>
<span class="i0">With his disease of all-shunn'd poverty,<a id="FNanchor_2347_2347"></a><a class="fnanchor pginternal" href="#Footnote_2347_2347">[2347]</a><br></span>
<span class="i0">Walks, like contempt, alone. More of our fellows.<a id="FNanchor_2348_2348"></a><a class="fnanchor pginternal" href="#Footnote_2348_2348">[2348]</a>             <span class="linenum">15</span><br></span>
</div></div>

<p class="directcenter"><i>Enter other</i> Servants.
</p>

<div class="poem"><div class="stanza">
<span class="i0"><i>Flav.</i> All broken implements of a ruin'd house.<br></span>
</div><div class="stanza">
<span class="i0"><i>Third Serv.</i> Yet do our hearts wear Timon's livery;<br></span>
<span class="i0">That see I by our faces; we are fellows still,<a id="FNanchor_2349_2349"></a><a class="fnanchor pginternal" href="#Footnote_2349_2349">[2349]</a><br></span>
<span class="i0">Serving alike in sorrow: leak'd is our bark,<br></span>
<span class="i0">And we, poor mates, stand on the dying deck,<a id="FNanchor_2350_2350"></a><a class="fnanchor pginternal" href="#Footnote_2350_2350">[2350]</a>                  <span class="linenum">20</span><br></span>
<span class="i0">Hearing the surges threat: we must all part<br></span>
<span class="i0">Into this sea of air.<a id="FNanchor_2351_2351"></a><a class="fnanchor pginternal" href="#Footnote_2351_2351">[2351]</a><br></span>
</div><div class="stanza">
<span class="i0"><i>Flav.</i>               Good fellows all,<br></span>
<span class="i0">The latest of my wealth I'll share amongst you.<br></span>
<span class="i0">Wherever we shall meet, for Timon's sake<br></span>
