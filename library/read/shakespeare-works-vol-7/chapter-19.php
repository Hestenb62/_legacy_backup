<span class="i0">And say 'This man's a flatterer'? if one be,<a id="FNanchor_2377_2377"></a><a class="fnanchor pginternal" href="#Footnote_2377_2377">[2377]</a>                  <span class="linenum">15</span><br></span><span class="pagenum"><a id="Page_269">[Pg 269]</a></span>
