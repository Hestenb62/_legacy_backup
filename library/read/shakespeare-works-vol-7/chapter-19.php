<span class="i0">Destruction fang mankind! Earth, yield me roots!<a id="FNanchor_2381_2381"></a><a class="fnanchor pginternal" href="#Footnote_2381_2381">[2381]</a>          <span class="directline">[<i>Digging.</i><br></span></span>
<span class="i0">Who seeks for better of thee, sauce his palate<br></span>
<span class="i0">With thy most operant poison! What is here?                         <span class="linenum">25</span><br></span>
<span class="i0">Gold? yellow, glittering, precious gold? No, gods,<a id="FNanchor_2382_2382"></a><a class="fnanchor pginternal" href="#Footnote_2382_2382">[2382]</a><br></span>
