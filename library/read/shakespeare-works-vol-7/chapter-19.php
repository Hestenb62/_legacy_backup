</div><div class="stanza">
<span class="i0"><i>Sec. Serv.</i>           As we do turn our backs<a id="FNanchor_2343_2343"></a><a class="fnanchor pginternal" href="#Footnote_2343_2343">[2343]</a><br></span>
<span class="i0">From our companion thrown into his grave,<a id="FNanchor_2344_2344"></a><a class="fnanchor pginternal" href="#Footnote_2344_2344">[2344]</a><br></span>
<span class="i0">So his familiars to his buried fortunes<a class="fnanchor pginternal" href="#Footnote_2344_2344">[2344]</a><a id="FNanchor_2345_2345"></a><a class="fnanchor pginternal" href="#Footnote_2345_2345">[2345]</a>                <span class="linenum">10</span><br></span>
