<span class="i0">Thus much of this will make black white, foul fair,<a class="fnanchor pginternal" href="#Footnote_2382_2382">[2382]</a><br></span>
<span class="i0">Wrong right, base noble, old young, coward valiant.<a class="fnanchor pginternal" href="#Footnote_2382_2382">[2382]</a><a id="FNanchor_2384_2384"></a><a class="fnanchor pginternal" href="#Footnote_2384_2384">[2384]</a><br></span>
<span class="i0">Ha, you gods! why this? what this, you gods? Why, this<a id="FNanchor_2385_2385"></a><a class="fnanchor pginternal" href="#Footnote_2385_2385">[2385]</a>        <span class="linenum">30</span><br></span>
<span class="i0">Will lug your priests and servants from your sides,<br></span>
<span class="i0">Pluck stout men's pillows from below their heads:<a id="FNanchor_2386_2386"></a><a class="fnanchor pginternal" href="#Footnote_2386_2386">[2386]</a><br></span>
<span class="i0">This yellow slave<br></span>
<span class="i0">Will knit and break religions; bless the accursed;<br></span>
<span class="i0">Make the hoar leprosy adored; place thieves,<a id="FNanchor_2387_2387"></a><a class="fnanchor pginternal" href="#Footnote_2387_2387">[2387]</a>                  <span class="linenum">35</span><br></span>
<span class="i0">And give them title, knee and approbation<br></span>
<span class="i0">With senators on the bench: this is it<a id="FNanchor_2388_2388"></a><a class="fnanchor pginternal" href="#Footnote_2388_2388">[2388]</a><br></span>
<span class="i0">That makes the wappen'd widow wed again;<a id="FNanchor_2389_2389"></a><a class="fnanchor pginternal" href="#Footnote_2389_2389">[2389]</a><br></span>
<span class="i0">She, whom the spital-house and ulcerous sores<a id="FNanchor_2390_2390"></a><a class="fnanchor pginternal" href="#Footnote_2390_2390">[2390]</a><a id="FNanchor_2391_2391"></a><a class="fnanchor pginternal" href="#Footnote_2391_2391">[2391]</a><br></span><span class="pagenum"><a id="Page_270">[Pg 270]</a></span>
<span class="i0">Would cast the gorge at, this embalms and spices<a class="fnanchor pginternal" href="#Footnote_2391_2391">[2391]</a><a id="FNanchor_2392_2392"></a><a class="fnanchor pginternal" href="#Footnote_2392_2392">[2392]</a>       <span class="linenum">40</span><br></span>
<span class="i0">To the April day again. Come, damned earth,<a id="FNanchor_2393_2393"></a><a class="fnanchor pginternal" href="#Footnote_2393_2393">[2393]</a><br></span>
<span class="i0">Thou common whore of mankind, that put'st odds<a id="FNanchor_2394_2394"></a><a class="fnanchor pginternal" href="#Footnote_2394_2394">[2394]</a><br></span>
<span class="i0">Among the rout of nations, I will make thee<br></span>
<span class="i0">Do thy right nature. [<i>March afar off.</i>] Ha! a drum?<br></span>
<span class="i10">Thou'rt quick,<a id="FNanchor_2395_2395"></a><a class="fnanchor pginternal" href="#Footnote_2395_2395">[2395]</a><br></span>
