        <h2>ACT IV.</h2>


<h3><span class="smcap">Scene I.</span> <i>Without the walls of Athens.</i><a id="FNanchor_2324_2324"></a><a class="fnanchor pginternal" href="#Footnote_2324_2324">[2324]</a></h3>

<p class="directcenter"><i>Enter</i> <span class="smcap">Timon</span>.
</p>

<div class="poem"><div class="stanza">
<span class="i0"><i>Tim</i>. Let me look back upon thee. O thou wall,<a id="FNanchor_2325_2325"></a><a class="fnanchor pginternal" href="#Footnote_2325_2325">[2325]</a><br></span>
<span class="i0">That girdlest in those wolves, dive in the earth,<a class="fnanchor pginternal" href="#Footnote_2325_2325">[2325]</a><a id="FNanchor_2326_2326"></a><a class="fnanchor pginternal" href="#Footnote_2326_2326">[2326]</a><br></span>
<span class="i0">And fence not Athens! Matrons, turn incontinent!<br></span>
<span class="i0">Obedience fail in children! Slaves and fools,<br></span>
<span class="i0">Pluck the grave wrinkled senate from the bench,                      <span class="linenum">5</span><br></span>
<span class="i0">And minister in their steads! To general filths<a id="FNanchor_2327_2327"></a><a class="fnanchor pginternal" href="#Footnote_2327_2327">[2327]</a><br></span>
<span class="i0">Convert o' the instant, green virginity!<a id="FNanchor_2328_2328"></a><a class="fnanchor pginternal" href="#Footnote_2328_2328">[2328]</a><br></span>
<span class="i0">Do't in your parents' eyes! Bankrupts, hold fast;<a id="FNanchor_2329_2329"></a><a class="fnanchor pginternal" href="#Footnote_2329_2329">[2329]</a><br></span>
<span class="i0">Rather than render back, out with your knives,<a class="fnanchor pginternal" href="#Footnote_2329_2329">[2329]</a><br></span>
<span class="i0">And cut your trusters' throats! Bound servants, steal!              <span class="linenum">10</span><br></span>
<span class="i0">Large-handed robbers your grave masters are<br></span>
<span class="i0">And pill by law. Maid, to thy master's bed!<br></span>
<span class="i0">Thy mistress is o' the brothel. Son of sixteen,<a id="FNanchor_2330_2330"></a><a class="fnanchor pginternal" href="#Footnote_2330_2330">[2330]</a><br></span>
<span class="i0">Pluck the lined crutch from thy old limping sire,<a id="FNanchor_2331_2331"></a><a class="fnanchor pginternal" href="#Footnote_2331_2331">[2331]</a><br></span>
<span class="i0">With it beat out his brains! Piety and fear,<a id="FNanchor_2332_2332"></a><a class="fnanchor pginternal" href="#Footnote_2332_2332">[2332]</a>                  <span class="linenum">15</span><br></span>
<span class="i0">Religion to the gods, peace, justice, truth,<br></span>
<span class="i0">Domestic awe, night-rest and neighbourhood,<br></span>
<span class="i0">Instruction, manners, mysteries and trades,<br></span>
<span class="i0">Degrees, observances, customs and laws,<br></span>
<span class="i0">Decline to your confounding contraries,                             <span class="linenum">20</span><br></span>
<span class="i0">And let confusion live! Plagues incident to men,<a id="FNanchor_2333_2333"></a><a class="fnanchor pginternal" href="#Footnote_2333_2333">[2333]</a><br></span><span class="pagenum"><a id="Page_265">[Pg 265]</a></span>
<span class="i0">Your potent and infectious fevers heap<br></span>
<span class="i0">On Athens, ripe for stroke! Thou cold sciatica,<br></span>
<span class="i0">Cripple our senators, that their limbs may halt<br></span>
<span class="i0">As lamely as their manners! Lust and liberty                        <span class="linenum">25</span><br></span>
<span class="i0">Creep in the minds and marrows of our youth,<br></span>
<span class="i0">That 'gainst the stream of virtue they may strive,<br></span>
<span class="i0">And drown themselves in riot! Itches, blains,<br></span>
<span class="i0">Sow all the Athenian bosoms, and their crop<br></span>
<span class="i0">Be general leprosy! Breath infect breath,                           <span class="linenum">30</span><br></span>
<span class="i0">That their society, as their friendship, may<br></span>
<span class="i0">Be merely poison! Nothing I'll bear from thee<br></span>
<span class="i0">But nakedness, thou detestable town!<a id="FNanchor_2334_2334"></a><a class="fnanchor pginternal" href="#Footnote_2334_2334">[2334]</a><br></span>
<span class="i0">Take thou that too, with multiplying bans!<a id="FNanchor_2335_2335"></a><a class="fnanchor pginternal" href="#Footnote_2335_2335">[2335]</a><br></span>
<span class="i0">Timon will to the woods, where he shall find                        <span class="linenum">35</span><br></span>
<span class="i0">The unkindest beast more kinder than mankind.<a id="FNanchor_2336_2336"></a><a class="fnanchor pginternal" href="#Footnote_2336_2336">[2336]</a><br></span>
<span class="i0">The gods confound—hear me, you good gods all!—<a id="FNanchor_2337_2337"></a><a class="fnanchor pginternal" href="#Footnote_2337_2337">[2337]</a><br></span>
<span class="i0">The Athenians both within and out that wall!<br></span>
<span class="i0">And grant, as Timon grows, his hate may grow<br></span>
<span class="i0">To the whole race of mankind, high and low!                         <span class="linenum">40</span><br></span>
<span class="i0">Amen.<a id="FNanchor_2338_2338"></a><a class="fnanchor pginternal" href="#Footnote_2338_2338">[2338]</a>                 <span class="directline">[<i>Exit.</i><br></span></span>
</div></div>


<h3><span class="smcap">Scene II.</span> <i>Athens. Timon's house.</i><a id="FNanchor_2339_2339"></a><a class="fnanchor pginternal" href="#Footnote_2339_2339">[2339]</a></h3>

<p class="directcenter"><i>Enter</i> <span class="smcap">Flavius</span>, <i>with two or three</i> Servants.
</p>

<div class="poem"><div class="stanza">
<span class="i0"><i>First Serv.</i> Hear you, master steward, where's our master?<a id="FNanchor_2340_2340"></a><a class="fnanchor pginternal" href="#Footnote_2340_2340">[2340]</a><br></span>
<span class="i0">Are we undone? cast off? nothing remaining?<br></span>
</div><div class="stanza">
<span class="i0"><i>Flav.</i> Alack, my fellows, what should I say to you?<br></span>
<span class="i0">Let me be recorded by the righteous gods,<br></span><span class="pagenum"><a id="Page_266">[Pg 266]</a></span>
<span class="i0">I am as poor as you.<a id="FNanchor_2341_2341"></a><a class="fnanchor pginternal" href="#Footnote_2341_2341">[2341]</a><br></span>
</div><div class="stanza">
<span class="i0"><i>First Serv.</i>        Such a house broke!<a id="FNanchor_2342_2342"></a><a class="fnanchor pginternal" href="#Footnote_2342_2342">[2342]</a>                  <span class="linenum">5</span><br></span>
<span class="i0">So noble a master fall'n! All gone! and not<a class="fnanchor pginternal" href="#Footnote_2342_2342">[2342]</a><br></span>
<span class="i0">One friend to take his fortune by the arm,<a class="fnanchor pginternal" href="#Footnote_2342_2342">[2342]</a><br></span>
