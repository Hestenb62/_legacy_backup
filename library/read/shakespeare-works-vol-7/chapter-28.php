<h3> <span class="smcap">Note IV.</span></h3>

<p><span class="smcap">III.</span> 2. 109. We transcribe a portion of Pope's note on this passage:</p>

<div class="poem"><div class="stanza">
<span class="i14">'"Cæsar has had great wrong.<br></span>
<span class="i0"><i>3 Pleb.</i> Cæsar had never wrong, but with just cause."<br></span>
</div></div>

<p>If ever there was such a line written by Shakespear, I shou'd fancy it
might have its place here, and very humorously in the character of a
Plebeian.' He refers to Ben Jonson's quotation in the <i>Sylva</i> or <i>Discoveries</i>,
which has been much discussed by the commentators on <span class="smcap">III.</span>
1. 47. Jonson's words are: 'Many times he [i.e. Shakespeare] fell
into those things, could not escape laughter: as when he said in the
person of Cæsar, one speaking to him, "Cæsar thou dost me wrong."
He replied "Cæsar did never wrong but with just cause," and such
like; which were ridiculous.' Vol. <span class="smcap">IX.</span> pp. 175, 176. ed. 1816. There is
another reference to Shakespeare's supposed blunder in the Induction
to Ben Jonson's <i>Staple of News</i>, first acted in 1625: '<i>Prologue</i>. Cry
you mercy, you never did wrong, but with just cause.' Vol. <span class="smcap">V.</span> p. 162.
Gifford in his note supposes that Metellus Cimber's speech and
Cæsar's reply, as they are found in the Folio of 1623, are due to the
'botchery of the players,' and that they originally stood thus:</p>

<div class="poem"><div class="stanza">
<span class="i0">'<i>Met.</i> Cæsar, thou dost me wrong.<br></span>
<span class="i0"><i>Cæs.</i> Cæsar did never wrong, but with just cause.'<br></span>
</div></div>

<p>But surely the first twelve lines of Cæsar's reply, to which Gifford
makes no allusion, cannot have been written by any other hand than
Shakespeare's. On the whole it seems more probable that Jonson,
quoting from memory, quoted wrong, than that the passage was
altered in consequence of his censure, which was first made, publicly,
in 1625.</p>


<h3> <span class="smcap">Note V.</span></h3>

<p><span class="smcap">III.</span> 2. 202. The arrangement given in the text, suggested by Mr
Grant White and Dr Delius, was first printed by us in the <i>Globe</i>
<i>Shakespeare</i> and has been adopted by Mr Dyce in his second edition.
The folios continue the words to the second citizen, thus:</p>

<div class="poem"><div class="stanza">
<span class="i0">'2. We will be reveng'd: Revenge<br></span>
<span class="i0">About, seeke, burne, fire, kill, slay,<br></span>
<span class="i0">Let not a Traitor live.'<br></span>
</div></div>

<p>See Coriolanus, Note (<span class="smcap">VII</span>). Perhaps the speech given to <i>Sec. Cit.</i>
lines 206, 207, should be also given to <i>All</i>, as Dr Delius has also suggested.
The same remark may apply to the speech of <i>Third Cit.</i> at
the end of Scene 3.</p>

