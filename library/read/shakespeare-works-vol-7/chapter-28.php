        <h2>NOTES.</h2>


<h3> <span class="smcap">Note I.</span></h3>

<p><span class="smcap">Dramatis Personæ.</span> Rowe has 'Artemidorus, a Soothsayer,'—'Artimedorus
a Sooth-sayer' in the first edition—which was altered
by Theobald, who described Artemidorus as 'a Sophist of Cnidos,'
and made the Soothsayer a separate person.</p>

<p>The Acts, but not the Scenes, are marked in the Folios.</p>


<h3> <span class="smcap">Note II.</span></h3>

<p><span class="smcap">II.</span> 1. 73. In both the editions of Pope this line is ludicrously
printed thus:</p>

<div class="poem"><div class="stanza">
<span class="i0">'No, Sir, their—are pluckt about their ears.'<br></span>
</div></div>

<p>He seems to have thought that 'hat' was an intolerable anachronism,
for in Coriolanus, <span class="smcap">II.</span> 3. 92 and 160, he has substituted 'cap.' In
this passage it would seem that he could not make up his mind and
left a blank accordingly. It is noticed in one of Theobald's letters to
Warburton (Nichols's <i>Illustrations</i>, Vol. <span class="smcap">II.</span> p. 493).</p>


<h3> <span class="smcap">Note III.</span></h3>

<p><span class="smcap">II.</span> 1. 189. Jennens quotes '<i>and</i> wildness' as the reading of Rowe's
Octavo. Two lines below he quotes 'laugh at <i>us</i> hereafter' as from
the same edition. In <span class="smcap">I.</span> 2. 110, he says that Rowe's Octavo reads 'we
arrive' for 'arrive;' in <span class="smcap">I.</span> 2. 163, that it reads 'would you' for 'you
would;' in <span class="smcap">I.</span> 2. 170, that it reads 'But' for 'Both;' in <span class="smcap">I.</span> 3. 85, that it
omits 'say;' in <span class="smcap">III.</span> 1. 207, that it reads 'Sing'd.' In none of these
cases does our copy of Rowe correspond with his statements.</p>

