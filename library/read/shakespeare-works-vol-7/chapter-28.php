<h3> <span class="smcap">Note VI.</span></h3>

<p><span class="smcap">IV.</span> 1. Rowe and Pope give 'Rome' for the Scene. Theobald
places it on 'a small Island near Mutina.' In his note he says,
'Shakespeare, I dare say, knew from <i>Plutarch</i>, that these Triumvirs
met, upon the Proscription, in a little Island: which <i>Appian</i>, who is
more particular, says, lay near <i>Mutina</i> upon the River <i>Lavinius</i>.'
Hanmer makes the scene at 'A small Island in the little River Rhenus
near Bononia.' Warburton cuts the knot by omitting to indicate
the scene. Johnson followed Theobald. Capell put 'A Room in
Antony's House,' which is adopted by Malone and modern editors
generally. Mr Knight says, 'The triumvirs, it is well known, did not
meet at Rome to settle their proscription. But it is evident that
Shakspere places his scene at Rome, by Lepidus being sent to Cæsar's
house, and told that he shall find his confederates "or here, or at the
Capitol."'</p>


<h3> <span class="smcap">Note VII.</span></h3>

<p><span class="smcap">IV.</span> 2. 50, 52. The ingenious alteration made by Mr Craik cures
the defective metre of line 50 and gets rid of the incongruous 'association
of an officer of rank and a servant boy' in line 52. We
have not however adopted it, because we are of opinion that the
error, such as it is, is due to the author and not to a transcriber. In
the first place, irregularities of metre are especially frequent, as Mr
Dyce and others have pointed out, where proper names occur; and,
secondly, an incongruity which was unnoticed by a long series of commentators
may well have escaped the observation of a writer among
whose merits minute accuracy cannot be ranked. Moreover in
Shakespeare's eyes Lucius was probably a page of gentle birth,
with whom Titinius might not unfitly be associated; and the office
of guarding a door is at least as suitable to him as that of carrying a
message to an army. In the next scene, both Lucius and Lucilius
are in attendance.</p>


<h3> <span class="smcap">Note VIII.</span></h3>

<p><span class="smcap">V.</span> 1. 69, 70. The stage directions given in the text are compounded
of that given in the Folios and that given by Rowe. The
Folios after 'hark, a word with you,' add <i>Lucillius and Messala stand</i>
<i>forth</i>, which Capell was the first to omit. Rowe retaining those words
added, <i>Brutus speaks apart to Lucilius</i>.</p>

