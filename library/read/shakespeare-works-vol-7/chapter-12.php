        <h2>NOTES.</h2>


<h3> <span class="smcap">Note I.</span></h3>

<p><span class="smcap">I.</span> 1. There is no division into Acts and Scenes in the Quartos,
nor any trace of division in the Folios, except the 'Actus Primus,
Scæna Prima' at the beginning of the play.</p>

<p>We wish to remind our readers that the symbol Qq signifies the
agreement of the second, third, fourth, and fifth Quartos.</p>


<h3> <span class="smcap">Note II.</span></h3>

<p><span class="smcap">I.</span> 2. 116. The first Quarto here has 'thrall,' the others 'debt,'
which though it makes a rhyme does not improve the sense. The next
two lines are not in the first Quarto. As, unlike the immediate context,
they also rhyme, while they are not particularly forcible, we incline to
think that some other hand than Shakespeare's inserted them.</p>


<h3> <span class="smcap">Note III.</span></h3>

<p><span class="smcap">II.</span> 1. 13. Pope was the first commentator who called attention to
the ballad which is alluded to in this passage, and it is remarkable that
with all his partiality for the first Quarto he did not adopt the reading
'trim,' found both there and in the ballad. Percy, in a note to the
ballad printed in his <i>Reliques</i>, conjectured that Shakespeare had
written 'trim,' not 'true,' apparently without knowing that the word
was found in the first Quarto. Capell, in his note, says that he had
retained 'true' in his text, owing to his not having observed the authority
for the other reading.</p>

<p><span class="pagenum"><a id="Page_137">[Pg 137]</a></span></p>


<h3> <span class="smcap">Note IV.</span></h3>

<p><span class="smcap">II.</span> 2. As there is no indication given in the Quartos and Folios of
Romeo's entrance here, it is not impossible that in the old arrangement
of the scene the wall was represented as dividing the stage, so that the
audience could see Romeo on one side and Mercutio on the other. If
this were the case it would tend to justify Capell's arrangement of
<i>Hen. VIII.</i> v. 2, though in the present instance he makes no allusion
to it. It is clear from the first line of Romeo's speech that he overhears
what Mercutio says, and though we have not altered the usual
arrangement, we cannot but feel that there is an awkwardness in thus
separating the two lines of a rhyming couplet.</p>


<h3> <span class="smcap">Note V.</span></h3>

<p><span class="smcap">II.</span> 2. 152. Malone erroneously attributes the reading 'suit' to the
Quarto of 1597. The words, 'To cease thy suit,' are found in Brooke's
<i>Tragicall Historye of Romeus and Iuliet</i>, p. 21 of the reprint in Mr
Collier's <i>Shakespeare's Library</i>.</p>


<h3> <span class="smcap">Note VI.</span></h3>

<p><span class="smcap">II.</span> 2. 184-II. 3. 5. This passage was printed substantially right in
the Quarto of 1597. The Quarto of 1599 inserted after the first line of
Romeo's speech the first four of the Friar's, repeating them in their
proper place. In Juliet's speech, the same edition by printing one
line as two, and mistaking the stage directions gave rise to a further
corruption in the Quarto of 1609.</p>

<p>In Q<sub>2</sub> (1599) the passage stands:</p>

<div class="poem"><div class="stanza">
<span class="i0">'Good night, good night.<br></span>
<span class="i0">Parting is such sweete sorrow,<br></span>
<span class="i0">That I shall say good night, till it be morrow.<br></span>
</div><div class="stanza">
<span class="i0"><i>Iu.</i> Sleep dwel vpon thine eyes, peace in thy breast.<br></span>
</div><div class="stanza">
<span class="i0"><i>Ro.</i> Would I were sleepe and peace so sweet to rest<br></span>
<span class="i0">The grey eyde morne smiles on the frowning night,<br></span>
<span class="i0">Checkring the Easterne Clouds with streaks of light,<br></span>
<span class="i0">And darknesse fleckted like a drunkard reeles,<br></span>
<span class="i0">From forth daies pathway, made by <i>Tytans</i> wheeles.<br></span>
<span class="i0">Hence will I to my ghostly Friers close cell,<br></span>
<span class="i0">His helpe to craue, and my deare hap to tell.<br></span>
</div></div>

<p class="right"><i>Exit.</i></p>

<p><span class="pagenum"><a id="Page_138">[Pg 138]</a></span></p>

<p class="directcenter"><i>Enter Frier alone with a basket.</i>
</p>

<div class="poem"><div class="stanza">
<span class="i0"><i>Fri.</i> The grey-eyed morne smiles on the frowning night,<br></span>
<span class="i0">Checking the Easterne clowdes with streaks of light:<br></span>
<span class="i0">And fleckeld darknesse like a drunkard reeles,<br></span>
<span class="i0">From forth daies path, and <i>Titans</i> burning wheeles:<br></span>
<span class="i0">Now ere &amp;c.'<br></span>
</div></div>

<p>In Q<sub>3</sub>(1609) we read:</p>

<div class="poem"><div class="stanza">
<span class="i0">'Good night, good night.<br></span>
</div><div class="stanza">
<span class="i0"><i>Ro.</i> Parting is such sweete sorrow,<br></span>
<span class="i0">That I shall say goodnight, till it be morrow.<br></span>
</div><div class="stanza">
<span class="i0"><i>Iu.</i> Sleepe dwell upon thine eyes, peace in thy breast.<br></span>
</div><div class="stanza">
<span class="i0"><i>Rom.</i> Would I were sleepe and peace so sweete to rest<br></span>
<span class="i0">The gray-eyde morne, &amp;c.'<br></span>
</div></div>

<p>For the rest Q<sub>3</sub> follows Q<sub>2</sub> without any material variation, except
that it reads 'fleckeld' for 'fleckted,' in the eighth line.</p>

<p>The fourth Quarto, undated, has ejected the intruding lines and
distributed the dialogue right. One error alone remains, viz. that
'Good night, good night ... sorrow' is divided still into two lines. The
fifth Quarto follows the fourth.</p>

<p>The first Folio follows the third Quarto as usual without any
variation of importance.</p>

<p>The second Folio, followed by the third and fourth, inserts, '<i>Exit</i>'
after the word 'breast,' adopts the reading of the first down to the
end of Romeo's speech, and makes the Friar's begin at line 5, thus:</p>

<div class="poem"><div class="stanza">
<span class="i0">'<i>Fri.</i> Now ere the Sun advance his burning eye, &amp;c.'<br></span>
</div></div>

<p>Pope restored the true arrangement. In the fourth line of the
Friar's speech he introduced 'pathway made by Titan's wheels' from
the passage as first given in Q<sub>2</sub> Q<sub>3</sub> F<sub>1</sub>.</p>


<h3> <span class="smcap">Note VII.</span></h3>

<p><span class="smcap">II.</span> 5. 15, 16. The second Quarto reads here:</p>

<div class="poem"><div class="stanza">
<span class="i0">'<i>M.</i> And his to me, but old folks, many fain as they wer dead,<br></span>
<span class="i0">Vnwieldie, slowe, heauie, and pale as lead.'<br></span>
</div></div>

<p>And this is followed with slight variations of spelling by the third.</p>

<p>The fourth and fifth omit the <i>M.</i>, as do the Folios, which give the
passage thus:</p>

<div class="poem"><div class="stanza">
<span class="i0">'And his to me, but old folkes,<br></span>
<span class="i0">Many faine as they were dead,<br></span>
<span class="i0">Vnwieldie, slow, heauy, and pale as lead.'<br></span>
</div></div>
<p><span class="pagenum"><a id="Page_139">[Pg 139]</a></span></p>
<p>Pope omits the lines 'But old folks ... lead,' thinking probably
that they are due to interpolation, a supposition which the unmeaning
'<i>M.</i>' in the earlier Quartos seems to confirm.</p>

<p>Mr Collier's MS. corrector has (Shakespeare, Ed. 2, Note ad
loc.):</p>

<div class="poem"><div class="stanza">
<span class="i0">'As his to me: but old folks seem as dead,<br></span>
<span class="i0">Unwieldy, slow, heavy, and dull as lead.'<br></span>
</div></div>

<p>This is not mentioned in his <i>Notes and Emendations</i>.</p>

<p>For 'many' Johnson substitutes 'marry;'</p>

<div class="poem"><div class="stanza">
<span class="i0">'But old folks, marry, feign as they were dead, &amp;c.'<br></span>
</div></div>


<h3> <span class="smcap">Note VIII.</span></h3>

<p><span class="smcap">III.</span> 3. 38-46. Instead of the lines which he put in the margin,
Pope inserted the following, copied with some alterations from the
first Quarto:</p>

<div class="poem"><div class="stanza">
<span class="i0">'But Romeo may not, he is banished!<br></span>
<span class="i0">O father, hadst thou no strong poison mixt,<br></span>
<span class="i0">No sharp ground knife, no present means of death,<br></span>
<span class="i0">But banishment to torture me withal?'<br></span>
</div></div>


<h3> <span class="smcap">Note IX.</span></h3>

<p><span class="smcap">III.</span> 3. 40-43. The Quarto of 1599 reads as follows:</p>

<div class="poem"><div class="stanza">
<span class="i0">'This may flyes do, when I from this must flie,<br></span>
<span class="i0">And sayest thou yet, that exile is not death?<br></span>
<span class="i0">But <i>Romeo</i> may not, he is banished.<br></span>
<span class="i0">Flies may do this, but I from this must flie:<br></span>
<span class="i0">They are freemen, but I am banished.'<br></span>
</div></div>

<p>The same order is followed in the subsequent Quartos. The reading
of the first Quarto will be seen in the reprint which follows the
play. The first Folio gives:</p>

<div class="poem"><div class="stanza">
<span class="i0">'This may Flies doe, when I from this must flie,<br></span>
<span class="i0">And saist thou yet, that exile is not death?<br></span>
<span class="i0">But <i>Romeo</i> may not, hee is banished.'<br></span>
</div></div>

<p>This reading is followed by the other Folios, Rowe, Theobald, Warburton,
and Johnson. Hanmer follows Pope in his text (see Note
<span class="smcap">VIII</span>), omitting altogether the lines which Pope put in the margin.</p>

<p><span class="pagenum"><a id="Page_140">[Pg 140]</a></span></p>

<p>Capell has:</p>

<div class="poem"><div class="stanza">
<span class="i0">'Flies may do this, but I from this must fly;<br></span>
<span class="i0">They are free men, but I am banished.'<br></span>
</div></div>

<p>Steevens (1773) reads:</p>

<div class="poem"><div class="stanza">
<span class="i0">'Flies may do this, when I from this must fly;<br></span>
<span class="i0">They are free men, but I am banished.<br></span>
<span class="i0">And say'st thou yet, that exile is not death?<br></span>
<span class="i0">But Romeo may not;—he is banished.'<br></span>
</div></div>

<p>In his note on the passage, in the edition of 1778, he conjectured
that the line 'But Romeo ... banished' should be inserted after 'their
own kisses sin;' an arrangement which was adopted by Malone and
by Steevens himself in his edition of 1793. Capell suggests that the
lines he retains 'were second thoughts of the poet, and their original
was meant for expunction.' This may possibly be true, but we have
adopted the reading given in our text because it retains, without
manifest absurdity, lines which are all undoubtedly Shakespeare's.
For a similar instance see Note <span class="smcap">XVIII.</span> on <i>Love's Labour's Lost</i>.</p>

<p>In <span class="smcap">IV. I. III</span>, of the present play we have omitted a line which
occurs in all the Quartos, except the first, and all the Folios, because
it could not be retained without absolute detriment to the sense.</p>


<h3> <span class="smcap">Note X.</span></h3>

<p><span class="smcap">III.</span> 5. 82-104. Instead of this passage Pope, printing, as he
says, 'more agreeably to the first edition,' gave as follows:</p>

<p>'<i>La. Cap.</i> Content thee girl. If I could find a man,
I soon would send to <i>Mantua</i> where he is,
And give him such an unaccustom'd dram
That he should soon keep <i>Tybalt</i> company.</p>

<p><i>Jul.</i> Find you the means, and I'll find such a man,
For while he lives, my heart shall ne'er be light
'Till I behold him—dead—is my poor heart,
Thus for a kinsman vext?</p>

<p><i>La. Cap.</i> Well, let that pass.
I come to bring thee joyful tidings, girl.'
</p>

<p>In this arbitrary change, he is followed, as usual, by Hanmer,
except that the latter puts a full stop at 'vext.'</p>


<h3> <span class="smcap">Note XI.</span></h3>

<p><span class="smcap">IV.</span> 3. 58. Mr Dyce conjectured that 'here's drink' was the corruption
of a stage direction, '<i>here drink</i>.'</p>

<p><span class="pagenum"><a id="Page_141">[Pg 141]</a></span></p>


<h3> <span class="smcap">Note XII.</span></h3>

<p><span class="smcap">IV.</span> 5. 36. Although 'see' was doubtless a conjectural insertion of
the editor of the second Folio in order to complete the metre, like his
addition of 'now' in the next line, yet, as the word occurs in the corresponding
passage of the first Quarto, we have decided on the whole
to retain it.</p>


<h3> <span class="smcap">Note XIII.</span></h3>

<p><span class="smcap">IV.</span> 5. 65-83. Instead of this speech Pope has the following:</p>

<div class="poem"><div class="stanza">
<span class="i0">'<i>Fri.</i> Oh peace for shame—<br></span>
<span class="i0">Your daughter lives in peace and happiness,<br></span>
<span class="i0">And it is vain to wish it otherwise.<br></span>
<span class="i0">Heav'n and yourself had part in this fair maid,<br></span>
<span class="i0">Now heav'n hath all—<br></span>
<span class="i0">Come stick your rosemary on this fair corpse,<br></span>
<span class="i0">And as the custom of our country is,<br></span>
<span class="i0">In all her best and sumptuous ornaments<br></span>
<span class="i0">Convey her where her ancestors lie tomb'd.'<br></span>
</div></div>

<p>The last three lines are verbatim from the Quarto of 1597. Hanmer
follows Pope, with a different arrangement in the first lines, which
he prints thus:</p>

<div class="poem"><div class="stanza">
<span class="i0">'Oh peace for shame—your daughter lives in peace<br></span>
<span class="i0">And happiness, and it is vain to wish<br></span>
<span class="i0">It otherwise. Heav'n and yourself had part<br></span>
<span class="i0">In this fair maid, now heaven hath her all—<br></span>
<span class="i0">Come &amp;c.'<br></span>
</div></div>


<h3> <span class="smcap">Note XIV.</span></h3>

<p><span class="smcap">V.</span> 3. 13-17. Instead of these five lines Pope inserts the four following,
from the first Quarto:</p>

<div class="poem"><div class="stanza">
<span class="i0">'Fair <i>Juliet</i>, that with angels dost remain,<br></span>
<span class="i0">Accept this latest favour at my hand,<br></span>
<span class="i0">That living honour'd thee, and being dead<br></span>
<span class="i0">With fun'ral obsequies adorn thy tomb.'<br></span>
</div></div>

<p>For lines 12-17 Steevens (1773) substituted the corresponding
lines of the first Quarto, except that he follows Pope in reading 'hand'
for 'hands.'</p>

<p><span class="pagenum"><a id="Page_142">[Pg 142]</a></span></p>


<h3> <span class="smcap">Note XV.</span></h3>

<p><span class="smcap">V.</span> 3. 108. The quarto of 1599 here reads:</p>

<div class="poem"><div class="stanza">
<span class="i0">'Depart againe, come lye thou in my arme,<br></span>
<span class="i0">Heer's to thy health, where ere thou tumblest in.<br></span>
<span class="i0">O true Appothecarie!<br></span>
<span class="i0">Thy drugs are quicke. Thus with a kisse I die.<br></span>
<span class="i0">Depart againe, here, here, will I remaine,<br></span>
<span class="i0">With wormes &amp;c.'<br></span>
</div></div>

<p>The third Quarto has the same reading, putting a semi-colon
after 'againe' in the fifth line, and is followed by the first Folio, except
that 'armes' is substituted for 'arme' in the first line. The later
Folios make no material change. The reading in our text is substantially
that of the fourth and fifth Quartos. Rowe follows the
Folios, and Pope prints:</p>

<div class="poem"><div class="stanza">
<span class="i0">'Depart again: come lye thou in my arms,<br></span>
<span class="i0">Here's to thy health.—O true apothecary!<br></span>
<span class="i0">Thy drugs are quick. Here, here will I remain,<br></span>
<span class="i0">With worms &amp;c.'<br></span>
</div></div>


