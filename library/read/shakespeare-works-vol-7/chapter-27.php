<div class="poem"><div class="stanza">
<span class="i0"><i>Oct.</i> Now, Antony, our hopes are answered:<br></span>
<span class="i0">You said the enemy would not come down,<br></span>
<span class="i0">But keep the hills and upper regions;<br></span>
<span class="i0">It proves not so: their battles are at hand;<br></span>
<span class="i0">They mean to warn us at Philippi here,<a id="FNanchor_3522_3522"></a><a class="fnanchor pginternal" href="#Footnote_3522_3522">[3522]</a>                         <span class="linenum">5</span><br></span>
