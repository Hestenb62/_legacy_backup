<h3><span class="smcap">Scene V.</span> <i>Another part of the field.</i><a id="FNanchor_3638_3638"></a><a class="fnanchor pginternal" href="#Footnote_3638_3638">[3638]</a></h3>

<p class="directcenter"><i>Enter</i> <span class="smcap">Brutus, Dardanius, Clitus, Strato</span>, <i>and</i> <span class="smcap">Volumnius</span>.
</p>

<div class="poem"><div class="stanza">
<span class="i0"><i>Bru.</i> Come, poor remains of friends, rest on this rock.<br></span>
</div><div class="stanza">
<span class="i0"><i>Cli.</i> Statilius show'd the torch-light, but, my lord,<br></span>
<span class="i0">He came not back: he is or ta'en or slain.<br></span>
</div><div class="stanza">
<span class="i0"><i>Bru.</i> Sit thee down, Clitus: slaying is the word;<br></span>
<span class="i0">It is a deed in fashion. Hark thee, Clitus.       <span class="directline">[<i>Whispering.</i><a id="FNanchor_3639_3639"></a><a class="fnanchor pginternal" href="#Footnote_3639_3639">[3639]</a><span class="linenum">5</span><br></span></span>
</div><div class="stanza">
<span class="i0"><i>Cli.</i> What, I, my lord? No, not for all the world.<br></span>
</div><div class="stanza">
<span class="i0"><i>Bru.</i> Peace then, no words.<br></span>
</div><div class="stanza">
<span class="i0"><i>Cli.</i>                        I'll rather kill myself.<br></span>
</div><div class="stanza">
<span class="i0"><i>Bru.</i> Hark thee, Dardanius.                    <span class="directline">[<i>Whispering.</i><br></span></span>
</div><div class="stanza">
<span class="i0"><i>Dar.</i>                        Shall I do such a deed?<a id="FNanchor_3640_3640"></a><a class="fnanchor pginternal" href="#Footnote_3640_3640">[3640]</a><br></span>
</div><div class="stanza">
<span class="i0"><i>Cli.</i> O Dardanius!<br></span>
</div><div class="stanza">
<span class="i0"><i>Dar.</i> O Clitus!                                               <span class="linenum">10</span><br></span>
</div><div class="stanza">
<span class="i0"><i>Cli.</i> What ill request did Brutus make to thee?<br></span>
</div><div class="stanza">
<span class="i0"><i>Dar.</i> To kill him, Clitus. Look, he meditates.<br></span>
</div><div class="stanza">
<span class="i0"><i>Cli.</i> Now is that noble vessel full of grief,<br></span>
<span class="i0">That it runs over even at his eyes.<br></span>
</div><div class="stanza">
<span class="i0"><i>Bru.</i> Come hither, good Volumnius; list a word.               <span class="linenum">15</span><br></span>
</div><div class="stanza">
<span class="i0"><i>Vol.</i> What says my lord?<br></span>
</div><div class="stanza">
<span class="i0"><i>Bru.</i>                     Why, this, Volumnius:<br></span>
<span class="i0">The ghost of Cæsar hath appear'd to me<br></span><span class="pagenum"><a id="Page_413">[Pg 413]</a></span>
