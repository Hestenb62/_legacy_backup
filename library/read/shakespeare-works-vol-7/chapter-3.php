        <h2>PREFACE.</h2>


<p>1. The first edition of <span class="smcap">Romeo and Juliet</span> was published
in 1597, with the following title:</p>

<div class="blockquot">

<p><span class="smcap">An | Excellent</span> | conceited Tragedie | <i>OF</i> | Romeo and
Iuliet, | As it hath been often (with great applause) | plaid publiquely,
by the right Ho-|nourable the L. of <i>Hunsdon</i> | his Seruants.
| <span class="smcap">London</span>, | Printed by Iohn Danter. | 1597. |</p></div>

<p>After Sig. D, a smaller type is used for the rest of the
play, and the running title is changed from 'The most
excellent Tragedie, of Romeo and Iuliet' to 'The excellent
Tragedie of Romeo and Iuliet.'</p>

<p>The text of this first Quarto differs so widely from that
of later and more perfect editions, that it is impossible to
record the results of a collation in footnotes: we have
therefore reprinted it. When we refer to it in the notes, it
is designated as (Q<sub>1</sub>), the marks of parenthesis being used
as in similar cases previously.</p>

<p>An opinion has been entertained by some critics that in
this earliest Quarto we have a fairly accurate version of
the play as it was at first written; and that in the interval
between the publication of the first and second Quartos,
the play was revised and recast by its author into the form
in which it appears in the edition of 1599. A careful
examination of the earlier text will, we think, prove this
notion to be untenable. Not to speak of minor errors, it
is impossible that Shakespeare should ever have given to
the world a composition containing so many instances of
imperfect sense, halting metre, bad grammar, and abrupt
dialogue. We believe that the play, as at first written,
was substantially the same as that given in the later<span class="pagenum"><a id="Page_viii">[Pg viii]</a></span>
editions; and that the defects of the first impression are
due, not to the author, but to the writer of the manuscript
from which that first impression was printed. That manuscript
was, in all probability, obtained from notes taken in
short-hand during the representation: a practice which we
know to have been common in those days. It is true that
the text of (Q<sub>1</sub>) is more accurate on the whole than might
have been expected from such an origin; but the short-hand
writer may have been a man of unusual intelligence
and skill, and may have been present at many representations
in order to correct his work; or possibly some of the
players may have helped him either from memory, or by
lending their parts in manuscript. But the examples of
omission and conjectural insertion are too frequent and too
palpable to allow of the supposition that the earliest text
is derived from a bona fide transcript of the author's MS.
The unusual precision of some stage directions in (Q<sub>1</sub>)
tends to confirm our view of its origin; a view which is
supported by the high authority of M. Tycho Mommsen.
The portions of the play omitted in (Q<sub>1</sub>), though necessary
to its artistic completeness and to its effect as a poem, are
for the most part passages which might be spared without
disturbing the consecutive and intelligible developement of
the action. It is possible therefore that the play as seen
by the short-hand writer was curtailed in the representation.</p>

<p>The second Quarto was in all likelihood an edition
authorized by Shakespeare and his 'fellows,' and intended
to supersede the surreptitious and imperfect edition of
1597. The play so published, we believe, as we have said,
to be substantially identical with the play as at first composed;
it seems however to have been revised by the
author. Here and there a passage appears to have been
rewritten. Compare, for example, (Q<sub>1</sub>) Sc. 10, lines 11-30
(p. <a href="#Page_169" class="pginternal">169</a> of the reprint) with the corresponding passages of
the later editions, Act II. Sc. 6, lines 16-36. In this place
assuredly the change must be attributed to the author;
but we know of no other passage of equal length where
the same can be affirmed with certainty. The words
'newly corrected, augmented, and amended,' found on the<span class="pagenum"><a id="Page_ix">[Pg ix]</a></span>
title-page of the second Quarto, may be accepted as the
statement of a fact, when thus confirmed by internal evidence.
Otherwise we know that the assertions in titlepages
or prefaces of that time are not to be relied on, nor
in this case would the words necessarily mean more than
that this second edition was more correct and more complete
than the first. In fact, the added matter amounts
nearly to a quarter of the whole.</p>

<p>The title-page of the second Quarto, Q<sub>2</sub>, is as follows:</p>

<div class="blockquot">

<p><span class="smcap">The | most ex</span>-| cellent and lamentable | Tragedie, of Romeo |
and <i>Iuliet</i>. | <i>Newly corrected, augmented, and | amended</i>: | As it
hath bene sundry times publiquely acted, by the | right Honourable
the Lord Chamberlaine | his Seruants | LONDON. | Printed
by Thomas Creede, for Cuthbert Burby, and are to | be sold at
his shop neare the Exchange. | 1599. |</p></div>

<p>This is unquestionably our best authority; nevertheless
in determining the text, (Q<sub>1</sub>) must in many places be taken
into account. For it is certain that Q<sub>2</sub> was not printed from
the author's MS., but from a transcript, the writer of which
was not only careless, but thought fit to take unwarrantable
liberties with the text. In passing through his hands,
many passages were thus transmuted from poetry to prose.
Pope felt this strongly, too strongly indeed, for he adopted
the text of the first Quarto in many places where Capell
and all subsequent editors have judiciously recurred to the
second. Nevertheless there is no editor who has not felt it
necessary occasionally to call in the aid of the first. We
think that M. Tycho Mommsen rates the authority of the
second Quarto too highly. Any rare form of word or
strange construction found in this edition alone, and corrected
in all that follow, may more probably be assigned
to the transcriber (or in some cases to the printer) than to
Shakespeare, whose language is singularly free from archaisms
and provincialisms.</p>

<p>The third Quarto, Q<sub>3</sub>, was published in 1609, with the
following title-page:</p>

<div class="blockquot">

<p><span class="smcap">The | most ex-cellent and</span> | Lamentable Tragedie, of | <i>Romeo</i>
<i>and Juliet</i>. | As it hath beene sundrie times publiquely Acted, |<span class="pagenum"><a id="Page_x">[Pg x]</a></span>
by the <span class="smcap">Kings</span> Maiesties Seruants | at the Globe. | Newly corrected,
augmented, and | amended: | <span class="smcap">London</span> | Printed for <span class="smcap">Iohn</span>
<span class="smcap">Smethvvick</span>, and are to be sold | at his Shop in Saint <i>Dunstanes</i>
Church-yard, | in Fleetestreete vnder the Dyall | 1609 |.</p></div>

<p>It was printed from Q<sub>2</sub>, from which it differs by a few
corrections, and more frequently by additional errors.</p>

<p>The next Quarto has no date.</p>

<p>Its title-page bears for the first time the name of the
author. After the word '<span class="smcap">GLOBE</span>' and in a separate line
we find the words: 'Written by W. <i>Shake-speare</i>.' Otherwise,
except in some slight variations of type and spelling,
the title-page of the undated Quarto does not differ from
that of Q<sub>3</sub>. It was also printed '<i>for Iohn Smethwicke</i>,'
without the mention of the printer's name.</p>

<p>Though this edition has no date, internal evidence conclusively
proves that it was printed from Q<sub>3</sub> and that the
Quarto of 1637 was printed from it. We therefore call
it Q<sub>4</sub>.</p>

<p>It contains some very important corrections of the text,
none however that an intelligent reader might not make
conjecturally and without reference to any other authority.
Indeed had the corrector been able to refer to any such
authority, he would not have left so many obviously corrupt
passages untouched.</p>

<p>The title-page of the fifth Quarto, our Q<sub>5</sub>, is substantially
identical with that of Q<sub>4</sub>, except that it is said to be printed
'by <i>R. Young</i> for <i>John Smethwicke</i>,' and dated, 1637.</p>

<p>It is printed, as we have said, from Q<sub>4</sub>. The punctuation
has been carefully regulated throughout, and the
spelling in many cases made uniform.</p>

<p>The symbol Qq signifies the agreement of Q<sub>2</sub>, Q<sub>3</sub>, Q<sub>4</sub>,
and Q<sub>5</sub>.</p>

<p>The text of the first Folio is taken from that of the
third Quarto. As usual there are a number of changes,
some accidental, some deliberate, but all generally for the
worse, excepting the changes in punctuation and in the
stage-directions. The punctuation, as a rule, is more
correct, and the stage-directions are more complete, in the
Folio.</p>

<p><span class="pagenum"><a id="Page_xi">[Pg xi]</a></span></p>

<p>The text of the second Folio is printed of course from
the first. In this play there are found in it a considerable
number of conjectural emendations, not generally happy,
and perhaps more than the usual number of errors.</p>

<p>A careful study of the text of <i>Romeo and Juliet</i> will
show how little we can rely upon having the true text, as
Shakespeare wrote it, in those plays for which the Folio is
our earliest authority.</p>

<p>M. Tycho Mommsen published in 1859 a reprint of the
first and second Quartos on opposite pages, and in the
footnotes a collation of the remaining Quartos (not quite
complete in the case of the fourth and fifth), the four
Folios, Rowe's first edition, and the new readings of Mr
Collier's MS. corrector. The volume is preceded by learned
and valuable 'Prolegomena,' and the collation, which we
have tested, is done with great care and accuracy. If our
collation, so far as it occupies the same ground, may claim
to be not less accurate, it must be remembered, first, that
we have not endeavoured to record every minute variation
of typography, but only such as were in our judgement
significant or otherwise noteworthy; secondly, that we
have had in all cases the original editions to refer to;
and thirdly, that we have had the advantage of comparing
our collation with his, and, wherever we found a discrepancy,
verifying by a reference to the old copies.</p>

<p>Of the many alterations of <i>Romeo and Juliet</i> we have
only had occasion to quote Otway's <i>Caius Marius</i>.</p>

<hr class="tb">

<p>2. <span class="smcap">Timon of Athens</span> was printed for the first time
in the Folio of 1623. It is called <i>The Life of Tymon of</i>
<i>Athens</i>; in the running titles, <i>Timon of Athens</i>; and occupies
twenty-one pages, from 80 to 98 inclusive, 81 and 82
being numbered twice over. After 98 the next page is
filled with <i>The Actors Names</i>, and the following page
is blank. The next page, the first of <i>Julius Cæsar</i>, is
numbered 109, and instead of beginning as it should
signature <i>ii</i>, the signature is <i>kk</i>. From this it may be
inferred that for some reason the printing of <i>Julius Cæsar</i>
was commenced before that of <i>Timon</i> was finished. It<span class="pagenum"><a id="Page_xii">[Pg xii]</a></span>
may be that the manuscript of <i>Timon</i> was imperfect, and
that the printing was stayed till it could be completed by
some playwright engaged for the purpose. This would
account for the manifest imperfections at the close of the
play. But it is difficult to conceive how the printer came
to miscalculate so widely the space required to be left.</p>

<p>The well-known carelessness of the printers of the Folio
in respect of metre will not suffice to account for the
deficiencies of <i>Timon</i>. The original play, on which Shakespeare
worked, must have been written, for the most part,
either in prose or in very irregular verse.</p>

<hr class="tb">

<p>3. <span class="smcap">Julius Cæsar</span> was published for the first time in
the Folio of 1623. It is more correctly printed than any
other play, and may perhaps have been (as the preface
falsely implied that all were) printed from the original
manuscript of the author.</p>

<p>The references to Jennens in the notes are to his edition
of <i>Julius Cæsar</i>, 'collated with the old and modern editions',
and published in 1774.</p>

<hr class="tb">

<p>4. <span class="smcap">Macbeth</span>, which follows next in order, was also
printed for the first time in that volume. Except that it is
divided into scenes as well as acts, it is one of the worst
printed of all the plays, especially as regards the metre,
and not a few passages are hopelessly corrupt.</p>

<p>'Davenant's version,' quoted in our notes, was published
in 1673. Jennen's edition was printed in 1773.
The edition of Macbeth by Harry Rowe is attributed to
Dr A. Hunter, and as such we have quoted it. Of this
we may remark that it is not always quite certain whether
the editor is in jest or earnest. 'Shakespeare restored' by
Mr Hastings Elwin is an edition of <i>Macbeth</i> with introduction
and notes, which was anonymously and privately
printed at Norwich in 1853.</p>

