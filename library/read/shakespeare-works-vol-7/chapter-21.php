        <h2>NOTES.</h2>


<h3> <span class="smcap">Note I.</span></h3>

<p><span class="smcap">Dramatis Personæ.</span> In the list given in the Folio <span class="smcap">Phrynia</span>,
<span class="smcap">Timandra</span>, and others are omitted. 'Timon's creditors' are termed
'usurers.' <span class="smcap">Ventidius</span> is called <span class="smcap">Ventigius, Philotus, Philo</span>, and
<span class="smcap">Hortensius, Hortensis. Varro</span> and <span class="smcap">Lucius</span> occur among the
names of the servants, and the latter has been retained by all editors
except Mr Dyce in his second edition. In the play the servants
address each other by the names of their respective masters: hence
the confusion. Perhaps all the names assigned to the servants
should be considered as names of their masters. 'Hortensius,' for
instance, has not a servile sound. Flaminius and Servilius may be
regarded rather as gentlemen in waiting than menials.</p>

<p>Sidney Walker suggests that <span class="smcap">Caphis</span> should be <span class="smcap">Capys</span>.</p>

<p>The list as given by modern editors contains successive additions
and alterations made by Rowe, Johnson and Capell, which it is unnecessary
to specify further.</p>

<p>With the exception of '<i>Actus Primus. Scæna Prima</i>' at the beginning,
there is in the Folios no indication of a division into Act or
Scene throughout the play.</p>


<h3> <span class="smcap">Note II.</span></h3>

<p><span class="smcap">I.</span> 1. 1, 2. This conjecture of Farmer's is given from his own MS.
in the copy of Johnson's Shakespeare which belonged to him, now in
the library of Emmanuel College. In a note found in the Variorum
edition, <i>ad loc.</i>, he makes a different suggestion:</p>

<div class="poem"><div class="stanza">
<span class="i0">'<i>Poet.</i> Good day.<br></span>
</div><div class="stanza">
<span class="i0"><i>Pain.</i> Good day, sir: I am glad you're well.'<br></span>
</div></div>


<h3> <span class="smcap">Note III.</span></h3>

<p><span class="smcap">I.</span> 2. 1-3. We have left this corrupt passage as it stands in the
Folios. Rowe made no change. Pope altered it to:</p>

<div class="poem"><div class="stanza">
<span class="i0">'Most honour'd Timon, it hath pleas'd the gods<br></span>
<span class="i0">To call my father's age unto long peace.'<br></span>
</div></div>
<p><span class="pagenum"><a id="Page_308">[Pg 308]</a></span></p>
<p>In this reading he was followed by Theobald, Hanmer and Warburton.
Johnson read:</p>

<div class="poem"><div class="stanza">
<span class="i0">'Most honour'd Timon, it hath pleas'd the Gods<br></span>
<span class="i0">To remember my father's age,<br></span>
<span class="i0">And call him to long peace.'<br></span>
</div></div>

<p>Capell has:</p>

<div class="poem"><div class="stanza">
<span class="i0">Most honour'd Timon,<br></span>
<span class="i0">'T hath pleas'd the gods in kindness to remember<br></span>
<span class="i0">My father's age, and call him to long peace.'<br></span>
</div></div>

<p>Steevens (1773) has:</p>

<div class="poem"><div class="stanza">
<span class="i0">'Most honour'd Timon, it hath pleas'd the Gods to remember<br></span>
<span class="i0">My father's age, and call him to long peace.'<br></span>
</div></div>

<p>In his edition of 1793 he read 'remember' for 'to remember.'</p>


<h3> <span class="smcap">Note IV.</span></h3>

<p><span class="smcap">I.</span> 2. 53-58. The Folios print Apemantus's speech as prose down
to 'Timon'; then as four lines of verse:</p>

<div class="poem"><div class="stanza">
<span class="i0">'Heere's that which is too weake to be a sinner,<br></span>
<span class="i0">Honest water, which nere left man i' th' mire:<br></span>
<span class="i0">This &amp;c.'<br></span>
</div></div>

<p>The second has 'mird' for 'mire.' The third and fourth follow the
first. Pope, whose arrangement we follow, prints as prose down to
'mire.' Capell prints the whole as verse thus:</p>

<div class="poem"><div class="stanza">
<span class="i0">'Flow this way!<br></span>
<span class="i0">A most brave fellow! he keeps his tides well. Timon,<br></span>
<span class="i0">Those healths will make thee, and thy state, look ill,'<br></span>
</div></div>

<p>following the Folios in the next four lines.</p>

<p>Steevens adopts this arrangement omitting 'most' in the second
line. Sidney Walker would divide the lines thus:</p>

<div class="poem"><div class="stanza">
<span class="i0">'Flow this way! a brave fellow!<br></span>
<span class="i0">He keeps his tides well. Timon, these healths will make<br></span>
<span class="i0">Thee, and thy state, look ill. Here's that which is<br></span>
<span class="i0">Too weak to be a sinner, honest water,<br></span>
<span class="i0">Which ne'er left man i' th' mire: &amp;c.'<br></span>
</div></div>


<h3> <span class="smcap">Note V.</span></h3>

<p><span class="smcap">I.</span> 2. 89-91. Mr Staunton suggests that one of the two clauses 'if
we should ne'er have need of 'em' and 'should we ne'er have use for
'em' was intended to be cancelled.</p>

