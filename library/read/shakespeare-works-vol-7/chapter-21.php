<h3> <span class="smcap">Note VI.</span></h3>

<p><span class="smcap">I.</span> 2. 113-118. The first Folio, followed substantially by the rest,
has:</p>

<div class="blockquot">

<p>'<i>Cap.</i> Haile to thee worthy <i>Timon</i> and to all that of his Bounties
taste: the fiue best Sences acknowledge thee their Patron, and come
freely to gratulate thy plentious bosome.</p></div>

<div class="poem"><div class="stanza">
<span class="i0">There tast, touch all, pleas'd from thy Table rise:<br></span>
<span class="i0">They onely now come but to Feast thine eies.'<br></span>
</div></div>

<p>Rowe made no material alteration except that he put a comma
after 'touch' in the last line but one.</p>

<p>Pope arranged thus:</p>

<div class="poem"><div class="stanza">
<span class="i0">'Hail to thee, worthy <i>Timon</i>, and to all<br></span>
<span class="i0">That of his bounties taste:<br></span>
<span class="i0">The five best senses acknowledge thee their patron, and come freely<br></span>
<span class="i0">To gratulate thy plenteous bosom.<br></span>
<span class="i0">There &amp;c.'<br></span>
</div></div>

<p>Theobald:</p>

<div class="poem"><div class="stanza">
<span class="i0">'Hail to thee, worthy <i>Timon</i>, and to all<br></span>
<span class="i0">That of his bounties taste! the five best Senses<br></span>
<span class="i0">Acknowledge thee their patron; and do come<br></span>
<span class="i0">Freely to gratulate thy plenteous bosom:<br></span>
<span class="i0">Th' Ear, Taste, Touch, Smell, pleas'd from thy Table rise,<br></span>
<span class="i0">These only now come but to feast thine eyes.'<br></span>
</div></div>

<p>and he adds in a note: 'The incomparable Emendation, with which
the Text is here supply'd, I owe to my ingenious Friend Mr <i>Warburton</i>.'
It was adopted by Hanmer and Johnson. Capell altered 'do
come' in line 3 to 'are come;' Steevens (1785) restored 'They' for
'These' in the last line, and Malone changed 'pleas'd' in the last
line but one to 'all pleas'd.'</p>

<p>Rann introduced the change which we have adopted in the text,
placing 'th' ear' at the end of the fourth line, and reading 'Taste,
touch <i>and</i> smell' in the fifth. Steevens, in his edition of 1793, followed
this arrangement, reading in the fifth line, 'Taste, touch, smell, all
pleas'd, &amp;c.'</p>


<h3> <span class="smcap">Note VII.</span></h3>

<p><span class="smcap">I.</span> 2. 171, 172. We have printed this passage as prose, as it is difficult
to say from the arrangement of the lines in the first and second<span class="pagenum"><a id="Page_310">[Pg 310]</a></span>
Folios, whether or not it was intended to be read as two lines of verse,
the first ending 'thee,' as it certainly is in the third and fourth Folios.
Pope printed it as prose. Capell eked out the metre thus:</p>

<div class="poem"><div class="stanza">
<span class="i0">'Me near? why, then another time I'll hear thee:<br></span>
<span class="i0">I pr'ythee, let us be provided now<br></span>
<span class="i0">To shew them entertainment.'<br></span>
</div></div>

<p>Steevens suggested 'provided <i>straight</i>' in the second line.</p>

<p>In many parts of this play it is difficult to say whether the lines are
intended to be read as irregular verse, or as rhythmical prose, and we
have therefore left them as they stand in the Folios.</p>


<h3> <span class="smcap">Note VIII.</span></h3>

<p><span class="smcap">II.</span> 2. 89-96. This and many other passages are printed in the
Folio as if they were intended to be irregular verse, where it is evident
that they can only be read as prose. In such cases it is not
always worth while to record how the lines were divided by the caprice
or negligence of the printer. Seymour has endeavoured throughout
the play to complete imperfect lines by the insertion of words, and
imperfect hemistichs by the addition of entire clauses, but he has in
this so far exceeded the license of conjecture that, except in the first
scene of the play, we have not recorded all his proposed alterations.</p>


<h3> <span class="smcap">Note IX.</span></h3>

<p><span class="smcap">III.</span> 2. 60-64. Pope altered these lines as follows:</p>

<div class="poem"><div class="stanza">
<span class="i0">'Why, this is the world's soul;<br></span>
<span class="i0">Of the same piece, is every flatterer's sport:<br></span>
<span class="i0">Who can call him his friend<br></span>
<span class="i0">That dips in the same dish? for in my knowing,<br></span>
<span class="i0"><i>Timon</i> has been to this lord as a father,<br></span>
<span class="i0">And kept his credit with his bounteous purse.'<br></span>
</div></div>

<p>Theobald follows Pope's arrangement, but reads 'spirit' for 'sport'
in the second line, an emendation which he first suggested in a letter
to Warburton, still unpublished, in the British Museum. Warburton's
conjecture 'coat,' which he made no allusion to in his own edition, is
mentioned by Theobald in the same letter. Hanmer gives the whole
passage thus:</p>

<div class="poem"><div class="stanza">
<span class="i0">'Why, this is the world's soul;<br></span>
<span class="i0">Of the same piece is every flatterer's spirit:<br></span><span class="pagenum"><a id="Page_311">[Pg 311]</a></span>
<span class="i0">Who can call him his friend that dips with him<br></span>
<span class="i0">In the same dish? for even in my knowing,<br></span>
<span class="i0"><i>Timon</i> has been to this Lord as a father,<br></span>
<span class="i0">And kept his credit with his bounteous purse.'<br></span>
</div></div>

<p>Johnson follows the Folios except that he gives the first lines thus:</p>

<div class="poem"><div class="stanza">
<span class="i0">'Why, this is the world's soul;<br></span>
<span class="i0">And just of the same piece is every flatterer's spirit:<br></span>
<span class="i0">Who can call him his friend,<br></span>
<span class="i0">That &amp;c.'<br></span>
</div></div>

<p>Steevens, in the edition of 1773, followed Johnson's arrangement,
but adopted in the first lines a transposition proposed by Upton:</p>

<div class="poem"><div class="stanza">
<span class="i0">'Why, this is the world's sport;<br></span>
<span class="i0">And just of the same piece is every flatterer's soul.'<br></span>
</div></div>

<p>In his edition of 1793 he read as follows:</p>

<div class="poem"><div class="stanza">
<span class="i0">'Why this<br></span>
<span class="i0">Is the world's soul; and just of the same piece<br></span>
<span class="i0">Is every flatterer's spirit. Who can call him<br></span>
<span class="i0">His friend, &amp;c.'<br></span>
</div></div>

<p>Following, in the rest, Capell's arrangement.</p>

<p>Malone arranged as follows:</p>

<div class="poem"><div class="stanza">
<span class="i0">'Why this is the world's soul, and just of the same piece<br></span>
<span class="i0">Is every flatterer's spirit. Who can call him his friend,<br></span>
<span class="i0">That dips in the same dish? for in my knowing<br></span>
<span class="i0">Timon has been this lord's father, and kept<br></span>
<span class="i0">His credit with his purse.'<br></span>
</div></div>

<p>In a note, however, he says, 'I do not believe this speech was
intended by the authour for verse.'</p>


<h3> <span class="smcap">Note X.</span></h3>

<p><span class="smcap">III.</span> 3. 8. Hanmer made here one of his audacious alterations:</p>

<div class="poem"><div class="stanza">
<span class="i0">'How? deny'd him?<br></span>
<span class="i0">Have Lucius and Ventidius and Lucullus<br></span>
<span class="i0">Deny'd him all? and does he send to me?<br></span>
<span class="i0">It shews &amp;c.'<br></span>
</div></div>

<p>Capell emulated him thus:</p>

<div class="poem"><div class="stanza">
<span class="i0">'How! have they deny'd him?<br></span>
<span class="i0">Has Lucius, and Ventidius, and Lucullus,<br></span>
<span class="i0">Deny'd him, say you? and does he send to me?<br></span><span class="pagenum"><a id="Page_312">[Pg 312]</a></span>
<span class="i0">Three? hum!<br></span>
<span class="i0">It shews &amp;c.'<br></span>
</div></div>


<h3> <span class="smcap">Note XI.</span></h3>

<p><span class="smcap">III.</span> 3. 19. Hanmer altered the passage thus:</p>

<div class="poem"><div class="stanza">
<span class="i0">'That I'll requite it last? so it may prove<br></span>
<span class="i0">An argument of laughter to the rest,<br></span>
<span class="i0">And amongst Lords I shall be thought a fool.'<br></span>
</div></div>

<p>Capell follows Hanmer, except that he replaces 'no' in the first
line.</p>

<p>Steevens (1793) follows Capell in the first two lines, reading in the
third:</p>

<div class="poem"><div class="stanza">
<span class="i0">'And I amongst the Lords be thought a fool.'<br></span>
</div></div>

<p>Mr. Staunton suggests that the passage once stood:</p>

<div class="poem"><div class="stanza">
<span class="i18">'So I may prove<br></span>
<span class="i0">An argument of laughter to the rest,<br></span>
<span class="i0">And amongst lords be thought a fool.'<br></span>
</div></div>

<p>Mr. Dyce, in his second edition proposes the following arrangement:</p>

<div class="poem"><div class="stanza">
<span class="i0">'That I'll requite it last? No: so it may prove<br></span>
<span class="i0">An argument of laughter to the rest,<br></span>
<span class="i0">And amongst lords I be thought a fool.'<br></span>
</div></div>


<h3> <span class="smcap">Note XII.</span></h3>

<p><span class="smcap">III.</span> 5. 14-18. The first Folio, followed substantially by the rest,
has:</p>

<div class="poem"><div class="stanza">
<span class="i0">'He is a Man (setting his Fate aside) of comely Vertues,<br></span>
<span class="i0">Nor did he soyle the fact with Cowardice,<br></span>
<span class="i0">(And Honour in him, which buyes out his fault)<br></span>
<span class="i0">But &amp;c.'<br></span>
</div></div>

<p>Rowe arranged the lines as follows:</p>

<div class="poem"><div class="stanza">
<span class="i0">'He is a Man, setting his Fate aside, of comely Virtues,<br></span>
<span class="i0">And Honour in him, which buys out his Fault;<br></span>
<span class="i0">Nor did he soil the Fact with Cowardise,<br></span>
<span class="i0">But &amp;c.'<br></span>
</div></div>

<p>Pope read:</p>

<div class="poem"><div class="stanza">
<span class="i0">'He is a man, setting his fault aside,<br></span>
<span class="i0">Of virtuous honour, which buys out his fault;<br></span>
<span class="i0">Nor did he soil the fact with cowardise,<br></span>
<span class="i0">But &amp;c.'<br></span>
</div></div>
<p><span class="pagenum"><a id="Page_313">[Pg 313]</a></span></p>
<p>Theobald follows Pope verbatim, and so Hanmer, except that he
reads 'setting this fact aside.' Warburton proposed 'setting this
fault aside.' Johnson read:</p>

<div class="poem"><div class="stanza">
<span class="i0">'He is a man, setting his fault aside,<br></span>
<span class="i0">Of comely virtues;<br></span>
<span class="i0">Nor did he soil the fact with cowardise,<br></span>
<span class="i0">An honour in him which buys out his fault,<br></span>
<span class="i0">But, &amp;c.'<br></span>
</div></div>

<p>Steevens, in his edition of 1773, restored 'his fate' from the Folios
in the first line, giving the reading we have adopted in the text.</p>


<h3> <span class="smcap">Note XIII.</span></h3>

<p><span class="smcap">III.</span> 5. 49-51. The first Folio has here:</p>

<div class="poem"><div class="stanza">
<span class="i0">'And the Asse, more Captaine then the Lyon?<br></span>
<span class="i0">The fellow loaden with Irons, wiser then the Iudge?<br></span>
<span class="i0">If Wisedome be in suffering, Oh my Lords,<br></span>
<span class="i6">&amp;c. &amp;c.'<br></span>
</div></div>

<p>The second Folio:</p>

<div class="poem"><div class="stanza">
<span class="i0">'And the Asse, more Captaine then the Lyon? the fellow<br></span>
<span class="i0">Loaden with Irons, wiser then the Iudge?<br></span>
<span class="i0">If Wisedome be in suffering. Oh my Lords,<br></span>
<span class="i6">&amp;c. &amp;c.'<br></span>
</div></div>

<p>The third and fourth Folios, spelling apart, follow the second.</p>

<p>Rowe placed a comma after 'Judge,' and this punctuation was
adopted by all subsequent editors.</p>

<p>Pope altered the passage thus:</p>

<div class="poem"><div class="stanza">
<span class="i0">'The ass, more than the lion; and the fellow<br></span>
<span class="i0">Loaden with irons, &amp;c.'<br></span>
</div></div>

<p>He was followed by Theobald, Hanmer and Warburton, and by
Johnson in his text; the last named however proposed a different
arrangement of the preceding line and the substitution of 'felon' for
'fellow' in line 49, thus:</p>

<div class="poem"><div class="stanza">
<span class="i14">'what make we<br></span>
<span class="i0">Abroad, why then the women are more valiant<br></span>
<span class="i0">That stay at home;<br></span>
<span class="i0">If bearing carry it, then is the ass<br></span>
<span class="i0">More captain than the lion, and the felon<br></span>
<span class="i0">Loaden with irons &amp;c.'<br></span>
</div></div>

<p>This suggestion was adopted substantially by Rann. The reading<span class="pagenum"><a id="Page_314">[Pg 314]</a></span>
'felon' had been independently proposed by Theobald (Nichols's
<i>Illustrations</i>, <span class="smcap">II</span>. 475).</p>

<p>Capell and Steevens (1773) followed Pope. Steevens (1778) read:</p>

<div class="poem"><div class="stanza">
<span class="i0">'The ass, more captain than the lion; and the fellow,<br></span>
<span class="i0">Loaden &amp;c.'<br></span>
</div></div>

<p>In 1793 he read:</p>

<div class="poem"><div class="stanza">
<span class="i0">'And th' ass, more captain than the lion; the felon,<br></span>
<span class="i0">Loaden &amp;c.'<br></span>
</div></div>

<p>This was followed in the Variorum Editions of 1803 and 1813.</p>

<p>Malone (1790) read:</p>

<div class="poem"><div class="stanza">
<span class="i0">'And the ass, more captain than the lion; the fellow,<br></span>
<span class="i0">Loaden &amp;c.'<br></span>
</div></div>

<p>and was followed by Boswell (1821).</p>

<p>Mr Knight (1839) returned to the arrangement and readings of the
first Folio. Singer (ed. 2) adopted this arrangement, but read 'felon'
for 'fellow.' In his first edition he followed the arrangement of the
second Folio, reading 'felon.'</p>

<p>Mitford suggests:</p>

<div class="poem"><div class="stanza">
<span class="i0">'The ass more than the lion, and the felon<br></span>
<span class="i0">Loaden &amp;c.'<br></span>
</div></div>

<p>or:</p>

<div class="poem"><div class="stanza">
<span class="i0">'And th' ass more than the lion, the felon<br></span>
<span class="i0">Loaden &amp;c.'<br></span>
</div></div>


<h3> <span class="smcap">Note XIV.</span></h3>

<p><span class="smcap">V.</span> 1. Johnson calls attention to the impropriety of placing the
entry of the Banditti in one act and that of the Poet and Painter in
another, when the latter were mentioned as within view when Apemantus
parted from Timon. 'It might be suspected,' he says, 'that
some scenes are transposed, for all these difficulties would be removed
by introducing the Poet and Painter first, and the thieves in this place.
Yet I am afraid the scenes must keep their present order, for the
Painter alludes to the Thieves, when he says, <i>he likewise enriched</i>
<i>poor straggling soldiers with great quantity</i>.'</p>


<h3> <span class="smcap">Note XV.</span></h3>

<p><span class="smcap">V.</span> 1. 59. After the word 'enough' in the first Folio a space has
slipped up, but there is no trace of any stop. The punctuation, as
Mr Dyce observes, is important to the sense of the preceding line.</p>

