<h3> <span class="smcap">Note XVI.</span></h3>

<p><span class="smcap">V.</span> 1. 131. The word 'canterisynge' for 'cauterizing,' is found very
frequently in an old surgical work, printed in 1541, of which the title
is 'The questyonary of Cyrurgyens.' The heading of one of the chapters
is, 'Here foloweth the fourthe partycle, where as be moued and
soyled other dyffycultees touchyng the maner of <i>canterisynge</i> or
searynge.' The instrument with which the operation is performed is
in the same book called a 'cantere.' The form of the word may have
been suggested by the false analogy of 'canterides,' <i>i.e.</i> cantharides,
which occurs in the same chapter.</p>


<h3> <span class="smcap">Note XVII.</span></h3>

<p><span class="smcap">V.</span> 3. 3, 4. Mr Staunton prints as follows:</p>

<div class="poem"><div class="stanza">
<span class="i0">[<i>Reads.</i>] <i><span class="smcap">TIMON IS DEAD!</span>—who hath outstretch'd his span,—</i><br></span>
<span class="i11"><i>Some beast—read this; there does not live a man.</i><br></span>
</div></div>

<p>He regards these lines as the only part of the inscription which the
soldier could read, the rest being in some different language. But
this explanation introduces a fresh difficulty. The difficulty would be
lessened by supposing the legible lines to be inscribed not on the
tomb but on the rock beside it, and the epitaph proper to be written
not in a different language but in a different character: a notion which
might be suggested to the author by the Gothic letters commonly
found on ancient monuments.</p>

<p>In the Globe edition we adopted the emendation 'rear'd' because,
with the change of a single letter, it yields something approaching to
a satisfactory sense. But we incline to think that the words were
originally intended as an epitaph to be read by the soldier. The
author may have changed his mind and forgotten to obliterate what
was inconsistent with the sequel, or the text may have been tampered
with by some less accomplished playwright. Anyhow the close of
the play bears marks of haste, or want of skill, and the clumsy device
of the wax cannot have been invented and would scarcely be adopted
by Shakespeare.</p>

<p>In the epitaph given in the next scene two inconsistent couplets
are combined into a quatrain.</p>


<h3> <span class="smcap">Note XVIII.</span></h3>

<p><span class="smcap">V.</span> 4. 62. Some editors attribute the conjecture 'render'd' to Mason;
but the earliest mention of it which we have remarked is in Lord
Chedworth's volume of <i>Notes</i> (1805).</p>

