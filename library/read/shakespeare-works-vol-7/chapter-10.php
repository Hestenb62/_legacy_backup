<p class="directcenter"><i>Enter</i> <span class="smcap">Friar Laurence</span> <i>and</i> <span class="smcap">Paris</span>.<a id="FNanchor_1171_1171"></a><a class="fnanchor pginternal" href="#Footnote_1171_1171">[1171]</a>
