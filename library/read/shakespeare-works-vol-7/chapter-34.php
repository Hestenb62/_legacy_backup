<h3><span class="smcap">Scene I.</span> <i>Dunsinane. Ante-room in the castle.</i></h3>

<p class="directcenter"><i>Enter a</i> Doctor of Physic <i>and a</i> Waiting-Gentlewoman.
</p>

<div class="poem"><div class="stanza">
<span class="i0"><i>Doct.</i> I have two nights watched with you, but can perceive<a id="FNanchor_4506_4506"></a><a class="fnanchor pginternal" href="#Footnote_4506_4506">[4506]</a><br></span>
