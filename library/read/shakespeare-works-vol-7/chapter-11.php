<div class="poem"><div class="stanza">
<span class="i0"><i>Fri. J.</i> Holy Franciscan friar! brother, ho!<a id="FNanchor_1428_1428"></a><a class="fnanchor pginternal" href="#Footnote_1428_1428">[1428]</a><br></span>
