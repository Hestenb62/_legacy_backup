<div class="poem"><div class="stanza">
<span class="i0">Well, Juliet, I will lie with thee to-night.<br></span>
<span class="i0">Let's see for means:—O mischief, thou art swift                    <span class="linenum">35</span><br></span>
<span class="i0">To enter in the thoughts of desperate men!<a id="FNanchor_1409_1409"></a><a class="fnanchor pginternal" href="#Footnote_1409_1409">[1409]</a><br></span>
<span class="i0">I do remember an apothecary,<br></span>
<span class="i0">And hereabouts a' dwells, which late I noted<a id="FNanchor_1410_1410"></a><a class="fnanchor pginternal" href="#Footnote_1410_1410">[1410]</a><br></span>
<span class="i0">In tatter'd weeds, with overwhelming brows,<br></span>
<span class="i0">Culling of simples; meagre were his looks;                          <span class="linenum">40</span><br></span>
<span class="i0">Sharp misery had worn him to the bones:<br></span>
<span class="i0">And in his needy shop a tortoise hung,<a id="FNanchor_1411_1411"></a><a class="fnanchor pginternal" href="#Footnote_1411_1411">[1411]</a><br></span><span class="pagenum"><a id="Page_119">[Pg 119]</a></span>
<span class="i0">An alligator stuff'd and other skins<br></span>
<span class="i0">Of ill-shaped fishes; and about his shelves<br></span>
<span class="i0">A beggarly account of empty boxes,<a id="FNanchor_1412_1412"></a><a class="fnanchor pginternal" href="#Footnote_1412_1412">[1412]</a>                            <span class="linenum">45</span><br></span>
