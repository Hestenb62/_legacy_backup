</div></div>


<h3><span class="smcap">Scene II.</span> <i>Friar Laurence's cell.</i><a id="FNanchor_1426_1426"></a><a class="fnanchor pginternal" href="#Footnote_1426_1426">[1426]</a></h3>

<p class="directcenter"><i>Enter</i> <span class="smcap">Friar John</span>.<a id="FNanchor_1427_1427"></a><a class="fnanchor pginternal" href="#Footnote_1427_1427">[1427]</a>
