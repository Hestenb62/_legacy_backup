</div><div class="stanza">
<span class="i0"><i>Par.</i> Sweet flower, with flowers thy bridal bed I strew,—<a id="FNanchor_1445_1445"></a><a class="fnanchor pginternal" href="#Footnote_1445_1445">[1445]</a><a id="FNanchor_1446_1446"></a><a class="fnanchor pginternal" href="#Footnote_1446_1446">[1446]</a><br></span>
