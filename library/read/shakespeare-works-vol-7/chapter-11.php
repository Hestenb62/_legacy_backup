<span class="i2">Or, wanting that, with tears distill'd by moans:<a class="fnanchor pginternal" href="#Footnote_1447_1447">[1447]</a>           <span class="linenum">15</span><br></span>
<span class="i0">The obsequies that I for thee will keep<a class="fnanchor pginternal" href="#Footnote_1447_1447">[1447]</a><br></span>
<span class="i0">Nightly shall be to strew thy grave and weep.<a class="fnanchor pginternal" href="#Footnote_1447_1447">[1447]</a><a id="FNanchor_1449_1449"></a><a class="fnanchor pginternal" href="#Footnote_1449_1449">[1449]</a><br></span>
</div></div>

