</div><div class="stanza">
<span class="i0"><i>Fri. J.</i> Brother, I'll go and bring it thee.<a id="FNanchor_1435_1435"></a><a class="fnanchor pginternal" href="#Footnote_1435_1435">[1435]</a>      <span class="directline">[<i>Exit.</i><br></span></span>
</div><div class="stanza">
