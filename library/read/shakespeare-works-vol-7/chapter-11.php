<span class="i0">To cross my obsequies and true love's rite?<a id="FNanchor_1451_1451"></a><a class="fnanchor pginternal" href="#Footnote_1451_1451">[1451]</a>                   <span class="linenum">20</span><br></span>
<span class="i0">What, with a torch! Muffle me, night, awhile.<a id="FNanchor_1452_1452"></a><a class="fnanchor pginternal" href="#Footnote_1452_1452">[1452]</a>       <span class="directline">[<i>Retires.</i><br></span></span>
</div></div>

<p class="directcenter"><i>Enter</i> <span class="smcap">Romeo</span> <i>and</i> <span class="smcap">Balthasar</span>, <i>with a torch, mattock, &amp;c.</i><a id="FNanchor_1453_1453"></a><a class="fnanchor pginternal" href="#Footnote_1453_1453">[1453]</a>
</p>

<div class="poem"><div class="stanza">
<span class="i0"><i>Rom.</i> Give me that mattock and the wrenching iron.<a id="FNanchor_1454_1454"></a><a class="fnanchor pginternal" href="#Footnote_1454_1454">[1454]</a><br></span>
