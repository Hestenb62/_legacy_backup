<span class="i0">I sell thee poison, thou hast sold me none.<br></span>
<span class="i0">Farewell: buy food, and get thyself in flesh.<a id="FNanchor_1425_1425"></a><a class="fnanchor pginternal" href="#Footnote_1425_1425">[1425]</a><br></span>
<span class="i0">Come, cordial and not poison, go with me                            <span class="linenum">85</span><br></span>
