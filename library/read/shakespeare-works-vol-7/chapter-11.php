<p class="directcenter"><i>Enter</i> <span class="smcap">Friar Laurence</span>.
</p>

<div class="poem"><div class="stanza">
<span class="i0"><i>Fri. L.</i> This same should be the voice of Friar John.<br></span>
<span class="i0">Welcome from Mantua: what says Romeo?<br></span><span class="pagenum"><a id="Page_121">[Pg 121]</a></span>
<span class="i0">Or, if his mind be writ, give me his letter.<a id="FNanchor_1429_1429"></a><a class="fnanchor pginternal" href="#Footnote_1429_1429">[1429]</a><br></span>
</div><div class="stanza">
<span class="i0"><i>Fri. J.</i> Going to find a bare-foot brother out,                <span class="linenum">5</span><br></span>
