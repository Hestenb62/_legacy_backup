<span class="i0">Remnants of packthread and old cakes of roses,<br></span>
<span class="i0">Were thinly scatter'd, to make up a show.<a id="FNanchor_1413_1413"></a><a class="fnanchor pginternal" href="#Footnote_1413_1413">[1413]</a><br></span>
<span class="i0">Noting this penury, to myself I said,<br></span>
<span class="i0">An if a man did need a poison now,<a id="FNanchor_1414_1414"></a><a class="fnanchor pginternal" href="#Footnote_1414_1414">[1414]</a>                            <span class="linenum">50</span><br></span>
