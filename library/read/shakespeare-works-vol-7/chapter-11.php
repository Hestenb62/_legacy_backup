<p class="directcenter"><i>Enter</i> Apothecary.
</p>

<div class="poem"><div class="stanza">
<span class="i0"><i>Ap.</i>                 Who calls so loud?<br></span>
</div><div class="stanza">
<span class="i0"><i>Rom.</i> Come hither, man. I see that thou art poor;<br></span>
<span class="i0">Hold, there is forty ducats: let me have<br></span>
<span class="i0">A dram of poison; such soon-speeding gear<a id="FNanchor_1417_1417"></a><a class="fnanchor pginternal" href="#Footnote_1417_1417">[1417]</a>                     <span class="linenum">60</span><br></span>
<span class="i0">As will disperse itself through all the veins,<br></span>
<span class="i0">That the life-weary taker may fall dead,<br></span>
<span class="i0">And that the trunk may be discharged of breath<br></span>
<span class="i0">As violently as hasty powder fired<br></span>
<span class="i0">Doth hurry from the fatal cannon's womb.                            <span class="linenum">65</span><br></span>
</div><div class="stanza">
<span class="i0"><i>Ap.</i> Such mortal drugs I have; but Mantua's law<br></span>
<span class="i0">Is death to any he that utters them.<br></span>
</div><div class="stanza">
<span class="i0"><i>Rom.</i> Art thou so bare and full of wretchedness,<br></span>
