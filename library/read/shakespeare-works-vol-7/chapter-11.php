<span class="i0">Need and oppression starveth in thy eyes,<a id="FNanchor_1419_1419"></a><a class="fnanchor pginternal" href="#Footnote_1419_1419">[1419]</a>                     <span class="linenum">70</span><br></span><span class="pagenum"><a id="Page_120">[Pg 120]</a></span>
<span class="i0">Contempt and beggary hangs upon thy back,<a id="FNanchor_1420_1420"></a><a class="fnanchor pginternal" href="#Footnote_1420_1420">[1420]</a><br></span>
<span class="i0">The world is not thy friend, nor the world's law:<br></span>
<span class="i0">The world affords no law to make thee rich;<br></span>
<span class="i0">Then be not poor, but break it, and take this.<br></span>
</div><div class="stanza">
<span class="i0"><i>Ap.</i> My poverty, but not my will, consents.                   <span class="linenum">75</span><br></span>
</div><div class="stanza">
<span class="i0"><i>Rom.</i> I pay thy poverty and not thy will.<a id="FNanchor_1421_1421"></a><a class="fnanchor pginternal" href="#Footnote_1421_1421">[1421]</a><br></span>
</div><div class="stanza">
<span class="i0"><i>Ap.</i> Put this in any liquid thing you will,<br></span>
<span class="i0">And drink it off; and, if you had the strength<br></span>
<span class="i0">Of twenty men, it would dispatch you straight.<br></span>
</div><div class="stanza">
<span class="i0"><i>Rom.</i> There is thy gold, worse poison to men's souls,<a id="FNanchor_1422_1422"></a><a class="fnanchor pginternal" href="#Footnote_1422_1422">[1422]</a>   <span class="linenum">80</span><br></span>
