<span class="i0">Here lives a caitiff wretch would sell it him.<br></span>
<span class="i0">O, this same thought did but forerun my need,<br></span>
<span class="i0">And this same needy man must sell it me.<br></span>
<span class="i0">As I remember, this should be the house:                            <span class="linenum">55</span><br></span>
