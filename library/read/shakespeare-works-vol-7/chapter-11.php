<h3><span class="smcap">Scene I.</span> <i>Mantua. A street.</i><a id="FNanchor_1393_1393"></a><a class="fnanchor pginternal" href="#Footnote_1393_1393">[1393]</a></h3>

<p class="directcenter"><i>Enter</i> <span class="smcap">Romeo</span>.
</p>

<div class="poem"><div class="stanza">
<span class="i0"><i>Rom.</i> If I may trust the flattering truth of sleep,<a id="FNanchor_1394_1394"></a><a class="fnanchor pginternal" href="#Footnote_1394_1394">[1394]</a><br></span>
<span class="i0">My dreams presage some joyful news at hand:<br></span>
<span class="i0">My bosom's lord sits lightly in his throne,<a id="FNanchor_1395_1395"></a><a class="fnanchor pginternal" href="#Footnote_1395_1395">[1395]</a><br></span>
<span class="i0">And all this day an unaccustom'd spirit<a id="FNanchor_1396_1396"></a><a class="fnanchor pginternal" href="#Footnote_1396_1396">[1396]</a><br></span>
<span class="i0">Lifts me above the ground with cheerful thoughts.                    <span class="linenum">5</span><br></span>
<span class="i0">I dreamt my lady came and found me dead—<br></span>
<span class="i0">Strange dream, that gives a dead man leave to think!—<a id="FNanchor_1397_1397"></a><a class="fnanchor pginternal" href="#Footnote_1397_1397">[1397]</a><br></span>
<span class="i0">And breathed such life with kisses in my lips<br></span>
<span class="i0">That I revived and was an emperor.<br></span>
<span class="i0">Ah me! how sweet is love itself possess'd,                          <span class="linenum">10</span><br></span>
