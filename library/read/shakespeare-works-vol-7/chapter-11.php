<p class="directcenter"><i>Enter</i> <span class="smcap">Balthasar</span>, <i>booted</i>.
</p>

<div class="poem"><div class="stanza">
<span class="i0">News from Verona! How now, Balthasar!<br></span>
<span class="i0">Dost thou not bring me letters from the friar?<br></span>
<span class="i0">How doth my lady? Is my father well?<br></span>
<span class="i0">How fares my Juliet? that I ask again;<a id="FNanchor_1399_1399"></a><a class="fnanchor pginternal" href="#Footnote_1399_1399">[1399]</a>                        <span class="linenum">15</span><br></span>
<span class="i0">For nothing can be ill, if she be well.<br></span>
<span class="pagenum"><a id="Page_118">[Pg 118]</a></span></div><div class="stanza">
<span class="i0"><i>Bal.</i> Then she is well, and nothing can be ill:<a id="FNanchor_1400_1400"></a><a class="fnanchor pginternal" href="#Footnote_1400_1400">[1400]</a><br></span>
<span class="i0">Her body sleeps in Capels' monument,<a id="FNanchor_1401_1401"></a><a class="fnanchor pginternal" href="#Footnote_1401_1401">[1401]</a><br></span>
<span class="i0">And her immortal part with angels lives.<a id="FNanchor_1402_1402"></a><a class="fnanchor pginternal" href="#Footnote_1402_1402">[1402]</a><br></span>
<span class="i0">I saw her laid low in her kindred's vault,                          <span class="linenum">20</span><br></span>
<span class="i0">And presently took post to tell it you:<br></span>
<span class="i0">O, pardon me for bringing these ill news,<br></span>
<span class="i0">Since you did leave it for my office, sir.<a id="FNanchor_1403_1403"></a><a class="fnanchor pginternal" href="#Footnote_1403_1403">[1403]</a><br></span>
</div><div class="stanza">
<span class="i0"><i>Rom.</i> Is it e'en so? then I defy you, stars!<a id="FNanchor_1404_1404"></a><a class="fnanchor pginternal" href="#Footnote_1404_1404">[1404]</a><br></span>
<span class="i0">Thou know'st my lodging: get me ink and paper,<a id="FNanchor_1405_1405"></a><a class="fnanchor pginternal" href="#Footnote_1405_1405">[1405]</a>                <span class="linenum">25</span><br></span>
<span class="i0">And hire post-horses; I will hence to-night.<br></span>
</div><div class="stanza">
<span class="i0"><i>Bal.</i> I do beseech you, sir, have patience:<a class="fnanchor pginternal" href="#Footnote_1400_1400">[1400]</a><a id="FNanchor_1406_1406"></a><a class="fnanchor pginternal" href="#Footnote_1406_1406">[1406]</a><br></span>
<span class="i0">Your looks are pale and wild, and do import<br></span>
<span class="i0">Some misadventure.<br></span>
</div><div class="stanza">
<span class="i0"><i>Rom.</i>             Tush, thou art deceived:<br></span>
<span class="i0">Leave me, and do the thing I bid thee do.                           <span class="linenum">30</span><br></span>
<span class="i0">Hast thou no letters to me from the friar?<br></span>
</div><div class="stanza">
<span class="i0"><i>Bal.</i> No, my good lord.<a class="fnanchor pginternal" href="#Footnote_1400_1400">[1400]</a><a id="FNanchor_1407_1407"></a><a class="fnanchor pginternal" href="#Footnote_1407_1407">[1407]</a><br></span>
</div><div class="stanza">
<span class="i0"><i>Rom.</i>                   No matter: get thee gone,<a id="FNanchor_1408_1408"></a><a class="fnanchor pginternal" href="#Footnote_1408_1408">[1408]</a><br></span>
<span class="i0">And hire those horses; I'll be with thee straight.<br></span>
</div></div>

