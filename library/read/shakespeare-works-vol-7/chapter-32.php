<span class="i0">Will come to know his destiny:<br></span>
<span class="i0">Your vessels and your spells provide,<br></span>
<span class="i0">Your charms and every thing beside.<br></span>
<span class="i0">I am for the air; this night I'll spend<a id="FNanchor_4281_4281"></a><a class="fnanchor pginternal" href="#Footnote_4281_4281">[4281]</a>                       <span class="linenum">20</span><br></span><span class="pagenum"><a id="Page_479">[Pg 479]</a></span>
<span class="i0">Unto a dismal and a fatal end:<a id="FNanchor_4282_4282"></a><a class="fnanchor pginternal" href="#Footnote_4282_4282">[4282]</a><br></span>
<span class="i0">Great business must be wrought ere noon:<br></span>
<span class="i0">Upon the corner of the moon<br></span>
<span class="i0">There hangs a vaporous drop profound;<br></span>
<span class="i0">I'll catch it ere it come to ground:                                <span class="linenum">25</span><br></span>
