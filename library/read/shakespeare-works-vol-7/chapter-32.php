<div class="poem"><div class="stanza">
<span class="i0"><i>First Witch.</i> Why, how now, Hecate! you look angerly.<br></span>
</div><div class="stanza">
<span class="i0"><i>Hec.</i> Have I not reason, beldams as you are,<a id="FNanchor_4276_4276"></a><a class="fnanchor pginternal" href="#Footnote_4276_4276">[4276]</a><a id="FNanchor_4277_4277"></a><a class="fnanchor pginternal" href="#Footnote_4277_4277">[4277]</a><br></span>
