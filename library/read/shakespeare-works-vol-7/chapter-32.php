<span class="i0">All which we pine for now: and this report<br></span>
<span class="i0">Hath so exasperate the king that he<a id="FNanchor_4309_4309"></a><a class="fnanchor pginternal" href="#Footnote_4309_4309">[4309]</a><br></span>
<span class="i0">Prepares for some attempt of war.<a id="FNanchor_4310_4310"></a><a class="fnanchor pginternal" href="#Footnote_4310_4310">[4310]</a><br></span>
</div><div class="stanza">
<span class="i0"><i>Len.</i>                            Sent he to Macduff?<br></span>
</div><div class="stanza">
<span class="i0"><i>Lord.</i> He did: and with an absolute 'Sir, not I,'<a class="fnanchor pginternal" href="#Footnote_4302_4302">[4302]</a>      <span class="linenum">40</span><br></span>
