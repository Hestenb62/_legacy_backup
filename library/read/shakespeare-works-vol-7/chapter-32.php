<h3><span class="smcap">Scene V.</span> <i>A heath.</i><a id="FNanchor_4275_4275"></a><a class="fnanchor pginternal" href="#Footnote_4275_4275">[4275]</a></h3>

<p class="directcenter"><i>Thunder.</i> <i>Enter the three</i> Witches, <i>meeting</i> <span class="smcap">Hecate</span>.
