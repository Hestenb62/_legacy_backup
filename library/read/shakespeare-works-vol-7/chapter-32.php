<div class="poem"><div class="stanza">
<span class="i0"><i>Len.</i> My former speeches have but hit your thoughts,<a id="FNanchor_4290_4290"></a><a class="fnanchor pginternal" href="#Footnote_4290_4290">[4290]</a><br></span>
