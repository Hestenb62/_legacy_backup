<h3><span class="smcap">Scene VI.</span> <i>Forres. The palace.</i><a id="FNanchor_4288_4288"></a><a class="fnanchor pginternal" href="#Footnote_4288_4288">[4288]</a></h3>

<p class="directcenter"><i>Enter</i> <span class="smcap">Lennox</span> <i>and another</i> Lord.<a id="FNanchor_4289_4289"></a><a class="fnanchor pginternal" href="#Footnote_4289_4289">[4289]</a>
