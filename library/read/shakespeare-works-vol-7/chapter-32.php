<span class="i0">Macduff lives in disgrace: sir, can you tell<br></span>
<span class="i0">Where he bestows himself?<br></span>
</div><div class="stanza">
<span class="i0"><i>Lord.</i>                   The son of Duncan,<a id="FNanchor_4302_4302"></a><a class="fnanchor pginternal" href="#Footnote_4302_4302">[4302]</a><a id="FNanchor_4303_4303"></a><a class="fnanchor pginternal" href="#Footnote_4303_4303">[4303]</a><br></span>
<span class="i0">From whom this tyrant holds the due of birth,                       <span class="linenum">25</span><br></span>
