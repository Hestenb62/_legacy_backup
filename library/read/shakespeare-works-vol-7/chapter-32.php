<span class="i0">Things have been strangely borne. The gracious Duncan<a id="FNanchor_4292_4292"></a><a class="fnanchor pginternal" href="#Footnote_4292_4292">[4292]</a><br></span><span class="pagenum"><a id="Page_480">[Pg 480]</a></span>
