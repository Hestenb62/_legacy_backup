</div></div>

<p class="directcenter"><i>Iuliet rises.</i>
</p>

<div class="poem"><div class="stanza">
<span class="i0">The Lady sturres.<a id="FNanchor_1595_1595"></a><a class="fnanchor pginternal" href="#Footnote_1595_1595">[1595]</a><br></span>
<span class="i0">Ah comfortable Fryer.                                              <span class="linenum">105</span><br></span>
<span class="i0">I doe remember well where I should be,<br></span>
<span class="i0">And what we talkt of: but yet I cannot see<br></span>
<span class="i0">Him for whose sake I vndertooke this hazard.<br></span>
</div><div class="stanza">
<span class="i0"><i>Fr</i>: Lady come foorth, I heare some noise at hand,<br></span>
<span class="i0">We shall be taken, <i>Paris</i> he is slaine,                      <span class="linenum">110</span><br></span>
<span class="i0">And <i>Romeo</i> dead: and if we heere be tane<br></span>
<span class="i0">We shall be thought to be as accessarie.<br></span>
<span class="i0">I will prouide for you in some close Nunery.<br></span>
</div><div class="stanza">
<span class="i0"><i>Iul</i>: Ah leaue me, leaue me, I will not from hence.<br></span>
</div><div class="stanza">
<span class="i0"><i>Fr</i>: I heare some noise, I dare not stay, come, come.        <span class="linenum">115</span><br></span>
</div><div class="stanza">
<span class="i0"><i>Iul</i>: Goe get thee gone.<br></span>
<span class="i0">Whats heere a cup closde in my louers hands?<br></span>
<span class="i0">Ah churle drinke all, and leaue no drop for me.<br></span>
</div></div>

<p class="directcenter"><i>Enter watch.</i>
</p>

<div class="poem"><div class="stanza">
<span class="i0"><i>Watch</i>: This way, this way.<br></span>
</div><div class="stanza">
<span class="i0"><i>Iul</i>: I, noise? then must I be resolute.                     <span class="linenum">120</span><br></span>
<span class="i0">O happy dagger thou shalt end my feare,<br></span>
<span class="i0">Rest in my bosome, thus I come to thee.<br></span>
</div></div>

<p class="directcenter"><i>She stabs herselfe and falles.</i></p>

<p class="directcenter"><i>Enter watch.</i>
</p>

<div class="poem"><div class="stanza">
<span class="i0"><i>Cap</i>: Come looke about, what weapons haue we heere?<br></span>
<span class="i0">See frends where <i>Iuliet</i> two daies buried,<br></span>
<span class="i0">New bleeding wounded, search and see who's neare,                  <span class="linenum">125</span><br></span>
<span class="i0">Attach and bring them to vs presently.<br></span>
</div></div>

<p class="directcenter"><i>Enter one with the Fryer.</i>
</p>

<div class="poem"><div class="stanza">
<span class="i0"><i>1.</i> Captaine heers a Fryer with tooles about him,<br></span>
<span class="i0">Fitte to ope a tombe.<br></span>
</div><div class="stanza">
<span class="i0"><i>Cap</i>: A great suspition, keep him safe.<br></span>
</div></div>

<p class="directcenter"><i>Enter one with Romeos man.</i>
</p>

<div class="poem"><div class="stanza">
<span class="i0"><i>1.</i> Heeres <i>Romeos</i> Man.                                <span class="linenum">130</span><br></span>
</div><div class="stanza">
<span class="i0"><i>Capt</i>: Keepe him to be examinde.<br></span>
</div></div>

<p class="directcenter"><i>Enter Prince with others.</i>
</p>

<div class="poem"><div class="stanza">
<span class="i0"><i>Prin</i>: What early mischiefe calls vs vp so soone.<br></span>
<span class="pagenum"><a id="Page_196">[Pg 196]</a></span></div><div class="stanza">
<span class="i0"><i>Capt</i>: O noble Prince, see here<br></span>
<span class="i0">Where <i>Juliet</i> that hath lyen intoombd two dayes,<br></span>
<span class="i0">Warme and fresh bleeding, <i>Romeo</i> and Countie <i>Paris</i>    <span class="linenum">135</span><br></span>
<span class="i0">Likewise newly slaine.<br></span>
</div><div class="stanza">
<span class="i0"><i>Prin</i>: Search seeke about to finde the murderers.<br></span>
</div></div>

<p class="directcenter"><i>Enter olde Capolet and his Wife.</i>
</p>

<div class="poem"><div class="stanza">
<span class="i0"><i>Capo</i>: What rumor's this that is so early vp?<br></span>
</div><div class="stanza">
<span class="i0"><i>Moth</i>: The people in the streetes crie <i>Romeo</i>,<br></span>
<span class="i0">And some on <i>Iuliet</i>: as if they alone                        <span class="linenum">140</span><br></span>
<span class="i0">Had been the cause of such a mutinie.<br></span>
</div><div class="stanza">
<span class="i0"><i>Capo</i>: See Wife, this dagger hath mistooke:<br></span>
<span class="i0">For (loe) the backe is emptie of yong <i>Mountague</i>,<br></span>
<span class="i0">And it is sheathed in our Daughters breast.<br></span>
</div></div>

<p class="directcenter"><i>Enter olde Montague.</i>
</p>

<div class="poem"><div class="stanza">
<span class="i0"><i>Prin</i>: Come <i>Mountague</i>, for thou art early vp,         <span class="linenum">145</span><br></span>
<span class="i0">To see thy Sonne and Heire more early downe.<br></span>
</div><div class="stanza">
<span class="i0"><i>Mount</i>: Dread Souereigne, my Wife is dead to night,<br></span>
<span class="i0">And yong <i>Benuolio</i> is deceased too:<br></span>
<span class="i0">What further mischiefe can there yet be found?<br></span>
</div><div class="stanza">
<span class="i0"><i>Prin</i>: First come and see, then speake.                      <span class="linenum">150</span><br></span>
</div><div class="stanza">
<span class="i0"><i>Mount</i>: O thou vntaught, what manners is in this<br></span>
<span class="i0">To presse before thy Father to a graue.<br></span>
</div><div class="stanza">
<span class="i0"><i>Prin</i>: Come seale your mouthes of outrage for a while,<br></span>
<span class="i0">And let vs seeke to finde the Authors out<br></span>
<span class="i0">Of such a hainous and seld seene mischaunce.                       <span class="linenum">155</span><br></span>
<span class="i0">Bring forth the parties in suspition.<br></span>
</div><div class="stanza">
<span class="i0"><i>Fr</i>: I am the greatest able to doo least.<br></span>
<span class="i0">Most worthie Prince, heare me but speake the truth.<br></span>
<span class="i0">And Ile informe you how these things fell out.<br></span>
<span class="i0"><i>Juliet</i> here slaine was married to that <i>Romeo</i>,        <span class="linenum">160</span><br></span>
<span class="i0">Without her Fathers or her Mothers grant:<br></span>
<span class="i0">The Nurse was priuie to the marriage.<br></span>
<span class="i0">The balefull day of this vnhappie marriage,<br></span>
<span class="i0">Was <i>Tybalts</i> doomesday: for which <i>Romeo</i><br></span>
<span class="i0">Was banished from hence to <i>Mantua</i>.                          <span class="linenum">165</span><br></span>
<span class="i0">He gone, her Father sought by foule constraint<br></span>
<span class="i0">To marrie her to <i>Paris</i>: But her Soule<br></span>
<span class="i0">(Loathing a second Contract) did refuse<br></span>
<span class="i0">To giue consent; and therefore did she vrge me<br></span>
<span class="i0">Either to finde a meanes she might auoyd                           <span class="linenum">170</span><br></span>
<span class="i0">What so her Father sought to force her too:<br></span>
<span class="i0">Or els all desperately she threatned<br></span>
<span class="i0">Euen in my presence to dispatch her selfe.<br></span>
<span class="i0">Then did I giue her, (tutord by mine arte)<br></span>
<span class="i0">A potion that should make her seeme as dead:                       <span class="linenum">175</span><br></span><span class="pagenum"><a id="Page_197">[Pg 197]</a></span>
<span class="i0">And told her that I would with all post speed<br></span>
<span class="i0">Send hence to <i>Mantua</i> for her <i>Romeo</i>,<br></span>
<span class="i0">That he might come and take her from the Toombe.<br></span>
<span class="i0">But he that had my Letters (Frier <i>John</i>)<br></span>
<span class="i0">Seeking a Brother to associate him,                                <span class="linenum">180</span><br></span>
<span class="i0">Whereas the sicke infection remaind,<br></span>
<span class="i0">Was stayed by the Searchers of the Towne,<br></span>
<span class="i0">But <i>Romeo</i> vnderstanding by his man,<br></span>
<span class="i0">That <i>Iuliet</i> was deceasde, returnde in post<br></span>
<span class="i0">Vnto <i>Verona</i> for to see his loue.                            <span class="linenum">185</span><br></span>
<span class="i0">What after happened touching <i>Paris</i> death,<br></span>
<span class="i0">Or <i>Romeos</i> is to me vnknowne at all.<br></span>
<span class="i0">But when I came to take the Lady hence,<br></span>
<span class="i0">I found them dead, and she awakt from sleep:<br></span>
<span class="i0">Whom faine I would haue taken from the tombe,                      <span class="linenum">190</span><br></span>
<span class="i0">Which she refused seeing R<i>omeo</i> dead.<br></span>
<span class="i0">Anone I heard the watch and then I fled,<br></span>
<span class="i0">What after happened I am ignorant of.<br></span>
<span class="i0">And if in this ought haue miscaried.<br></span>
<span class="i0">By me, or by my meanes let my old life                             <span class="linenum">195</span><br></span>
<span class="i0">Be sacrificd some houre before his time.<br></span>
<span class="i0">To the most strickest rigor of the Law.<br></span>
</div><div class="stanza">
<span class="i0"><i>Pry</i>: We still haue knowne thee for a holy man,<br></span>
<span class="i0">Wheres <i>Romeos</i> man, what can he say in this?<br></span>
</div><div class="stanza">
<span class="i0"><i>Balth</i>: I brought my maister word that shee was dead,        <span class="linenum">200</span><br></span>
<span class="i0">And then he poasted straight from <i>Mantua</i>,<br></span>
<span class="i0">Vnto this Toombe. These Letters he deliuered me,<br></span>
<span class="i0">Charging me early giue them to his Father.<br></span>
</div><div class="stanza">
<span class="i0"><i>Prin</i>: Lets see the Letters, I will read them ouer.<br></span>
<span class="i0">Where is the Counties Boy that calld the Watch?                    <span class="linenum">205</span><br></span>
</div><div class="stanza">
<span class="i0"><i>Boy</i>: I brought my Master vnto <i>Juliets</i> graue,<br></span>
<span class="i0">But one approaching, straight I calld my Master.<br></span>
<span class="i0">At last they fought, I ran to call the Watch.<br></span>
<span class="i0">And this is all that I can say or know.<br></span>
</div><div class="stanza">
<span class="i0"><i>Prin</i>: These letters doe make good the Fryers wordes,        <span class="linenum">210</span><br></span>
<span class="i0">Come <i>Capolet</i>, and come olde <i>Mountagewe</i>.<br></span>
<span class="i0">Where are these enemies? see what hate hath done.<br></span>
</div><div class="stanza">
<span class="i0"><i>Cap</i>: Come brother <i>Mountague</i> giue me thy hand,<br></span>
<span class="i0">There is my daughters dowry: for now no more<br></span>
<span class="i0">Can I bestowe on her, thats all I haue.                            <span class="linenum">215</span><br></span>
</div><div class="stanza">
<span class="i0"><i>Moun</i>: But I will giue them more, I will erect<br></span>
<span class="i0">Her statue of pure golde:<br></span>
<span class="i0">That while <i>Verona</i> by that name is knowne.<br></span>
<span class="i0">There shall no statue of such price be set,<br></span>
<span class="i0">As that of <i>Romeos</i> loued <i>Iuliet</i>.                      <span class="linenum">220</span><br></span>
</div><div class="stanza">
<span class="i0"><i>Cap</i>: As rich shall <i>Romeo</i> by his Lady lie.<br></span><span class="pagenum"><a id="Page_198">[Pg 198]</a></span>
<span class="i0">Poore Sacrifices to our Enmitie.<br></span>
</div><div class="stanza">
<span class="i0"><i>Prin</i>: A gloomie peace this day doth with it bring.<br></span>
<span class="i0">Come, let vs hence,<br></span>
<span class="i0">To haue more talke of these sad things.                            <span class="linenum">225</span><br></span>
<span class="i0">Some shall be pardoned and some punished:<br></span>
<span class="i0">For nere was heard a Storie of more woe,<br></span>
<span class="i0">Than this of <i>Iuliet</i> and her <i>Romeo</i>.<br></span>
</div></div>

<p class="directcenter"><i>FINIS.</i>
</p>

