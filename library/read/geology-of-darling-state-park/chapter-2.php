<p>While looking at some of the above-mentioned photographs, a second
family of rocks is discovered (Figs. <a href="#fig3" class="pginternal">3</a>, <a href="#fig5" class="pginternal">5</a>, <a href="#fig6" class="pginternal">6</a>, <a href="#fig7" class="pginternal">7</a>, and <a href="#fig8" class="pginternal">8</a>; also, Figs. <a href="#fig9" class="pginternal">9</a>, <a href="#fig10" class="pginternal">10</a>, <a href="#fig11" class="pginternal">11</a>,
and <a href="#fig16" class="pginternal">16</a>). In many places these rocks have a layered or banded appearance
and in other places large lath-like crystals are common in some of the
layers. In some areas these rocks are very heterogeneous in appearance
and display distorted layers and profuse development of lath-like crystals
(Figs. <a href="#fig12" class="pginternal">12</a> and <a href="#fig13" class="pginternal">13</a>). These rocks belong to the second major family of rocks,
the <i>Metamorphic</i> rocks. The metamorphic rocks<a class="fn pginternal" href="#fn_2" id="fr_2">[2]</a> seen in the park were
originally <i>sedimentary</i><a class="fn pginternal" href="#fn_3" id="fr_3">[3]</a>
rocks. These rocks belong to the Gile Mountain
<i>Formation</i><a class="fn pginternal" href="#fn_4" id="fr_4">[4]</a>
which was deposited during the <i>Devonian Period</i> some 300
million years ago (see Geologic Time Scale<a class="fn pginternal" href="#fn_5" id="fr_5">[5]</a>, <a href="#fig14" class="pginternal">Fig. 14</a>). So much for the two
major families of rocks present in the park, the igneous and metamorphic
rocks, and how to distinguish one from the other. Let us assume that you
can now distinguish between the granite and the metamorphic rocks.</p>
