<p>From these relationships, what can be said about the relative ages of
the two rock types? Which is the older, or first formed? Which is the last
formed? If you study the above relationships for a minute or so, it will
become obvious that the layered rock had to be formed <i>prior</i> to the emplacement
of the granite. Some of the minerals now seen in the layered
or banded metamorphic rocks were formed at the time of granite intrusion,
but the basic “stuff” or partially metamorphosed sedimentary rock
was present before the granite entered the area from beneath. So, the
<span class="pb" id="Page_13">13</span>
knowledge of the two rock types present and an understanding of their
relationship to one another tells us a story of at least two events which
occurred in the park area hundreds of millions of years ago.</p>
<div class="img" id="fig12">
<img class="img-fluid" style="max-width: 100%; height: auto;" alt="" height="548" src="https://www.gutenberg.org/cache/epub/60730/images/p06a.jpg" width="800" id="img_images_p06a.jpg">
<p class="pcap">Figure 12. Outcrop on south Lookout, summit of Burke Mountain. Distorted
layers of Gile Mountain metamorphic rock. Lath-like crystals developed along some of
these layers during the second period of metamorphism, that is, when the granite
invaded the metamorphic rocks. For scale, the hammer handle is about one foot long.</p>
</div>
<p>Can we find other facts in these rocks which might add to the above-mentioned
events? The answer to this question is, yes! The types of
minerals found in the metamorphic rocks coupled with the inherited
layered structure so common in these rocks, tells us that they were once
sedimentary rocks. There is other evidence which indicates that these
sedimentary rocks were slightly metamorphosed and folded prior to the
invasion of the granite. Added information indicates that these same
rocks were subjected to increasing temperatures with the invasion of the
granite and another metamorphic mineral change took place. Thus far,
the rocks have told us about four distinct events; the deposition and
hardening of the Gile Mountain Formation of sedimentary rocks, the
first period of wide-spread metamorphism, accompanied by broad folding,
the invasion of the granite, and a second phase of metamorphism
<span class="pb" id="Page_14">14</span>
with the increased temperatures produced by this invasion (see cross-sections
illustrating the geologic history of the park area, <a href="#fig17" class="pginternal">Fig. 17</a>).</p>
