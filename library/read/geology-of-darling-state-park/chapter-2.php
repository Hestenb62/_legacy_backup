<p>The four events which are mentioned in the preceding paragraph took
place hundreds of millions of years ago. What has happened in the park
since these events? Take a look at <a href="#fig15" class="pginternal">Figure 15</a>, which was taken along the
road to the summit of Burke Mountain (coming down from the summit,
this outcrop is located on your right, midway between the second and
third turns in the road). Here the granite exhibits linear scratches or striations
which trend about 40 degrees east of south (general direction in
which the hammer handle points). Again, just down the road from the
midway picnic and camping area, and on your right, striations can be
seen. Here they trend about 45 degrees east of south or approximately in
the same direction as the first series of striations mentioned. These
scratches or striations occur in many places throughout the park, and in
most cases their orientation is about the same. What caused these
numerous striations?</p>
