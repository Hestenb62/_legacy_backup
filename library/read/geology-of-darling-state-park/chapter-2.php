<div class="box">
<p class="revint">1. Deposition and hardening of the Gile Mountain Formation. At this stage the
layers of rock were more or less horizontal.</p>
<p class="revint">2. The horizontal and parallel layers of the Gile Mountain Formation were gently
and broadly folded and regionally metamorphosed. This is the first stage of
metamorphism in the park area.</p>
<p class="revint">3. Invasion by granite. This invasion was accompanied by local metamorphism of the
invaded rocks. This is the second stage of metamorphism in the park area. Note
the inclusions of first stage metamorphosed Gile Mountain rocks in the granite.</p>
<p class="revint">4. Many millions of years of erosion took place, the forces of nature finally exposing
the granitic rocks at the surface of the earth.</p>
<p class="revint">5. Continued erosion caused the metamorphically reenforced Gile Mountain rocks
to wear down more slowly than the surrounding weaker rocks. For this reason,
these strengthened rocks stand higher than the weaker rocks.</p>
<p class="revint">6. Less than one million years ago the glaciers advanced over the park area. The
glacial ice plucked and scratched (striated) the underlying rocks as it slowly
advanced southward. During the retreat (northward) certain deposits were left.
Present-day Burke Mountain is much the same as it was when the glaciers left,
but, some added erosion has taken place and, because of uplift, the Mountain
stands a bit higher than it did some 10,000 years ago. Some soil, much of which was
removed by the glaciers, has since formed on the mountain.</p>
</div>
<p>There are no rocks present in the park which were deposited during
this interval of time, therefore, no rock record. If no rocks representing
this time interval are present, one of two reasons must be responsible.
Either the park area was undergoing active erosion (wearing down)
during this period, or sediments were deposited during part or all of this
time interval and subsequently completely removed by erosion. Most
probably, the intervening time found the park area above the depositional
environment of the sea, when its rocks were being worn away by
the erosional forces of nature. Again, see <a href="#fig17" class="pginternal">Figure 17</a> for a diagrammatic
representation of the geologic history of the park.</p>
