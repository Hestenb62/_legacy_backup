<div class="pb" id="Page_17">17</div>
<p>Since they are still preserved in the rocks for us to see, they must have
been formed quite recently, that is, geologically speaking. What can
explain these striations and their common orientation? Did you ever
hear about the Great Ice Age, or the Pleistocene Epoch? Less than one
million years ago, in fact, some 12,000 years ago, an ice sheet many
thousands of feet thick rode over Burke Mountain in a southeastward
direction. The many boulders frozen to the underside of the ice sheet
tended to scratch the rocks over which they rode. The scratches or
striations seen in the park rocks were caused by these attached boulders.
The ice sheet also plucked and rounded Burke Mountain into the shape
it possesses today.</p>
<p>A look at <a href="#fig4" class="pginternal">Figure 4</a> shows still another event which occurred during
recent geological time. The prominent smooth fracture-surface seen to
slope or dip toward the road is called “sheeting structure” which has its
origin in post-glacial time. It is thought by many geologists that these
flat surfaces or <i>joints</i><a class="fn pginternal" href="#fn_6" id="fr_6">[6]</a>,
which are generally parallel to the ground surface,
were formed with the release of the weight of the overlying glacial ice
when the glacier retreated northward. So, here we have evidence displayed
in the rocks which tells of still another event in the park’s history.
It should be mentioned here, while still on the subject of joints, that
other joints do occur in the park rocks. <a href="#fig16" class="pginternal">Figure 16</a> shows joints which
were formed earlier than the “sheeting” and which are not parallel to the
surface of the ground. These joints were probably formed as a result of
the removal of the overlying rocks through erosion, thus releasing long-continued
pressures produced by the weight of the overlying rocks, and
movement of the earth’s crust. We now have the story of two main
episodes in the park’s geological history; one took place many millions
of years ago, the other within the last 12,000 years. What happened
between these two rock-documented episodes?</p>
