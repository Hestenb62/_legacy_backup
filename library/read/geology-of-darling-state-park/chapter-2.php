<p>Now, what is the relationship of one to the other? That is, where you
can see both of these rock types exposed together in one outcrop, can
you describe the physical contact of one with the other? For instance,
look at <a href="#fig6" class="pginternal">Figure 6</a>, which was taken about midway down the Bear Den
Trail, here you see the granite (the white speckled igneous rock which
cuts horizontally across the picture) cutting across the distinctly layered
or banded metamorphic rocks. The granite is said to have a cross-cutting
relationship to the metamorphic rocks. In some outcrops the granite is
more or less parallel to the layers of metamorphic rock (<a href="#fig7" class="pginternal">Fig. 7</a>). Here,
the granite is said to have a conformable relationship with the metamorphic
rocks. Still another relationship between the granite and the
metamorphic rock is seen in <a href="#fig8" class="pginternal">Figure 8</a>. Here, blocks of metamorphic rocks
are inclosed by granite. These inclosed blocks are called inclusions and
are pieces of invaded rock which fell into or were encircled by the invading
granite.</p>
