<h2 id="c3"> <span class="small">THE ROCKS AND THEIR HISTORY</span></h2>
<p>The most conspicuous rock found in the park is <i>granite</i>.<a class="fn pginternal" href="#fn_1" id="fr_1">[1]</a> Along the
road which winds to the summit of Burke Mountain you will see several
outcrops of the white or pinkish biotite granite (<a href="#fig4" class="pginternal">Fig. 4</a>). This granite is
well displayed in the summit parking area and along the trail to the
observation tower (Figs. <a href="#fig3" class="pginternal">3</a> and <a href="#fig5" class="pginternal">5</a>). A walk down the Bear Den Ski Trail
also shows an abundance of granite outcrops (Figs. <a href="#fig6" class="pginternal">6</a>, <a href="#fig7" class="pginternal">7</a>, and <a href="#fig8" class="pginternal">8</a>).</p>
