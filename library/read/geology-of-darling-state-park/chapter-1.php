<h1 title="">THE GEOLOGY OF DARLING STATE PARK</h1>
<p class="center"><i>By</i> HARRY W. DODGE, JR.</p>
<h2 id="c1"> <span class="small">INTRODUCTION</span></h2>
<p>Darling State Park, located in northeastern Vermont (see map, “Burke
Mountain,” <a href="#fig1" class="pginternal">Fig. 1</a>), offers outstanding opportunities to the camper,
picnicker, hiker, view-seeker and winter sportsman. On a clear day the
top of Burke Mountain offers a most spectacular view of northeastern
Vermont and such distant points as Mount Ascutney (located on the
Connecticut River, some 80 miles as the crow flies, to the south). Other
prominent peaks that may be seen are Camels Hump (50 miles southwest),
Mount Mansfield (44 miles west), Jay Peak (39 miles northwest),
and Mount Washington (the highest Peak in the New England States
and the northeast, which is located in New Hampshire some 47 miles
southeast of Burke Mountain). For the traveler, the view from Burke
Mountain reveals “where he has been” and where he might “next go.”
See <a href="#fig1" class="pginternal">Figure 1</a> for the location of points which can be seen from the overlooks
atop Burke Mountain.</p>
<p>Both the professional and amateur naturalist will find Darling State
Park extremely interesting. This pamphlet is devoted primarily to the
geology of the park, but the fauna and flora of this area present the
visitor with days of interesting studies. It is hoped that in the near future
pamphlets describing these aspects of Darling State Park will be published.</p>
<h2 id="c2"> <span class="small">THE GEOLOGY OF THE PARK</span></h2>
<p>Before discussing the more detailed aspects of the geology of Darling
State Park, certain basic geologic concepts must be explained. But, even
before such a discussion, it might be best to clarify the position of geology
among the many other, and oftentimes interrelated, sciences.</p>
<p>The basic reason for the science of geology might be said to be twofold;
one is economic, the other related to Man’s basic curiosity. In the first,
the geologist through the use of his knowledge of the earth’s rocks,
<span class="pb" id="Page_4">4</span>
locates those indispensable minerals and fuels without which our advanced
society and technology could not exist. In the second, the geologist
tries to unlock the many mysteries within the earth’s crust merely
to satisfy a thirst for knowledge and to pass such knowledge on to his
fellow man. These two basic reasons complement each other and allow
continued advancements in geology, both as a pure science and as a
primary economic aid to the nation.</p>
<p>As found in most spheres of present-day scientific endeavor, the geologist
relies heavily on other related sciences for insight into problems at
hand. A basic knowledge, and oftentimes an advanced knowledge, of
physics, chemistry, mathematics and zoology, to name only some, are
needed before the geologist can approach many of his own problems. It
might be obvious to you by now, but a geologist will be certainly included
in the first scientific party to journey to the moon and planets.</p>
<p>Within the general science of geology are several branches, to name
only a few; paleontology, sedimentology, mineralogy, petrology, stratigraphy,
petroleum geology, and structural geology. Each of these
branches or specialty-areas contributes basic data for the overall interpretation
of the past geologic history of any given geographic area. The
historical geologist takes all these clues and attempts to fit the pieces of
information together into a picture of past events.</p>
<p>The concept of Geologic Time must be understood before the history
of Darling State Park can be unraveled. Usually we think of time in
terms of minutes, hours, days, weeks, months and years. The geologist
thinks and talks in terms of millions or even billions of years. Time units
as short as hundreds of years are impossible to distinguish in the past
history of the Earth. When it is realized that the earth is probably 4 to 6
billion (4,000 to 6,000 million) years old, and the record of these years is
incomplete, it is easy to understand why the geologist speaks in terms of
millions of years instead of years. With modern methods of radioactive
dating the geologist hopes for finer time definitions in the future.</p>
<p>In short then, the geologist interprets and puts order into millions of
years of history which can only be “read” as recorded in the rocks beneath
our very feet. Of course, just looking at the rocks does not magically
open the book of geologic history. This pamphlet is designed to sharpen
your powers of observation and to help you in your interpretation of
these observations.</p>
