<h2 id="c5"> <span class="small">HIKES TO TAKE</span></h2>
<p>A very interesting hike, both geologically and for nature hunting in
general, is the old fire road which begins just above the old C.C.C. camp
and the present Bell Gardens. This trail cuts off to the right, if ascending
the summit road, and runs completely around the mountain. Shortly
after the fire trail intersects the Bear Den Ski Trail, and on the left,
granite with obvious drill holes is seen (<a href="#fig18" class="pginternal">Fig. 18</a>). Most of the granite used
as curb stones, culvert headers, and islands along the park summit road
was obtained from these small quarries. A few miles walk along this trail
proves quite rewarding to the adventurer; an old lean-to demonstrates
what a bear can do while sharpening his claws.</p>
<p>The Devil’s Den Trail leads down the east side of Burke Mountain
from the observation tower at the summit. This trail is rather poorly
marked past a certain point, but if you wish to strike off on your own
and see some wonderful country, a hike down this trail with a swing to
the north will bring you back to the summit road.</p>
<p>The several ski trails on Burke Mountain are all walkable during the
summer, but they will not appear as smooth as when covered with snow,
and the trip down will take considerably longer on foot than on “boards.”
The Bear Den Ski Trail is especially good for geological sightseeing.</p>
<h2 id="c6"> <span class="small">NEARBY AREAS TO VISIT</span></h2>
<p>While at Darling State Park a visit to Lake Willoughby is well worth
the trip (Figs. <a href="#fig19" class="pginternal">19</a>, <a href="#fig20" class="pginternal">20</a>). A glance at <a href="#fig1" class="pginternal">Figure 1</a> will show you its general
location. Once you visit this lake, you might ask “why so beautiful a
Lake Willoughby?” There is still some question as to the origin of the
lake basin, but a combination of oriented joints and recent glacial movement
seems to fit the picture. Deeper and faster weathering along parallel
joints together with glacial movement and scour in the same direction as
the joints probably dug the elongated trench which, when filled with
water, became Lake Willoughby.</p>
<p>It is hoped that this pamphlet has given you the desire to enlarge your
knowledge of the science of geology. Geology is all around you wherever
you might travel and a knowledge of geology will open new roads even
while traveling old ones. Here’s luck to you in your travels; try to <i>see</i>
what you look at.</p>
