<h2 id="c7"> <span class="small">SUGGESTED READING</span></h2>
<p class="revint">Leet, L. Don and Judson, S., 1965, <i>Physical Geology</i>, 3rd Edition, Prentice-Hall,
Inc., Englewood Cliffs, New Jersey. This is a starter for the
geology student.</p>
<p class="revint">Dunbar, C. O., 1959, <i>Historical Geology</i>, John Wiley and Sons, New York.
Also a beginning book, read after above book.</p>
<p class="revint">Dennis, John G., 1956, <i>The Geology of the Lyndonville Area, Vermont</i>,
Vermont Geological Survey Bulletin 8. This is for the more advanced
student and relates the geology of the area adjacent to Burke Mountain
and Darling State Park.</p>
<p class="revint">Jacobs, Elbridge C., 1941-42, <i>The Great Ice Age in Vermont</i>, Report of the
State Geologist, Vol. 23; pp. 27-47.</p>
<p class="revint">Stewart, David P., 1961, <i>The Glacial Geology of Vermont</i>, Vermont Geological
Survey, Bulletin No. 19.</p>
<p class="revint">Woodland, B. G., 1963, <i>A Petrographic study of Thermally Metamorphosed
Pelitic rocks in the Burke Area, Northeastern Vermont</i>, American Journal
of Science, volume 261, pages 354-375. For the advanced student.</p>
<p class="revint">Woodland, B. G., 1965, <i>The Geology of the Burke Quadrangle, Vermont</i>,
Vermont Geological Survey Bulletin No. 28. This is a comprehensive
study of the Burke Mountain area and a must for those interested in
Darling State Park.</p>
<h2 id="c8"> <span class="small">Footnotes</span></h2>
<div class="fnblock"><div class="fndef"><a class="fn pginternal" href="#fr_1" id="fn_1">[1]</a>The granite found
in Darling State Park is white or pinkish in color and most times
is speckled with shiny black mica flakes. On close inspection, grains of smoky to clear
color are seen within the rock. The white and pink grains are the mineral, feldspar;
the shiny black flakes, biotite mica; the smoky to clear grains, quartz or silica. A
magnified picture of a slice of granite (see <a href="#fig2" class="pginternal">Fig. 2</a>) shows the individual mineral grains
and their interlocking nature with each other. Granite belongs to a major family of
rocks, termed <i>Igneous rocks</i>. Igneous rocks are formed through the hardening or
lithification of molten rock-material when subjected to the cooler temperatures at or
near the earth’s surface. The molten rock material formed at some depth beneath the
surface of the earth, where temperatures were many hundreds of degrees hotter than
at the surface.
</div><div class="fndef"><a class="fn pginternal" href="#fr_2" id="fn_2">[2]</a>Metamorphic rocks are
either sedimentary (this, a third major family of rocks
which is characterized by a layered appearance that has been retained by many of the
altered park rocks) or igneous rocks (the granite) which have been under the influence
of pressure, heat, and chemically active fluids, oftentimes resulting in chemical and
structural changes. Most of the metamorphic rocks seen in the park are either schist,
phyllite, slate or quartzite. For the benefit of the more advanced student, the rocks of
the park area are considered a granite-hornfels complex (see Bertram G. Woodland’s
paper of 1963, “A Petrographic study of Thermally Metamorphosed Pelitic rocks in
the Burke Area, Northeastern Vermont,” in the American Journal of Science, volume
261, pages 354 to 375).
</div><div class="fndef"><a class="fn pginternal" href="#fr_3" id="fn_3">[3]</a>Sedimentary or layered rocks, the third major rock family, are composed of pieces,
grains and other materials from older metamorphic, igneous and sedimentary rocks.
These fragments have been carried by rivers and streams to some resting place at the
bottom of a sea, lake, or stream channel. This mud, sand and gravel, under the weight
of steadily increasing overburden, and the presence of cementing materials, slowly
hardened into rock which we now call limestone shale, sandstone, and conglomerate.
</div><div class="fndef"><a class="fn pginternal" href="#fr_4" id="fn_4">[4]</a>A geologic formation consists of a sequence of rock layers which were deposited
under essentially the same conditions, or a series of alternating conditions, and which
can be easily distinguished and mapped as a unit by geologists in the field.
</div><div class="fndef"><a class="fn pginternal" href="#fr_5" id="fn_5">[5]</a>Geologic time is divided into four
Eras which are designated from oldest to youngest:
Precambrian, Paleozoic, Mesozoic, and Cenozoic. Each of these Eras is divided
into geologic periods of time. The Devonian Period is in about the middle of the
Paleozoic Era and began some 330 million years ago and ended approximately 290
million years ago (see Geologic Time Scale, <a href="#fig14" class="pginternal">Fig. 14</a>).
</div><div class="fndef"><a class="fn pginternal" href="#fr_6" id="fn_6">[6]</a>A joint is a break in a rock mass
which interrupts its physical continuity. A group of
more or less parallel joints is known as a joint set.
</div>
