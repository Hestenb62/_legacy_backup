        <h2><a id="TEARAINBOW_PETE"></a>RAINBOW PETE<a id="FNanchor_13_13"></a><a class="fnanchor pginternal" href="#Footnote_13_13">[13]</a></h2>
<p class="c"><span class="smcap">By</span> RICHARD MATTHEWS HALLET</p>
<p class="c">From <i>The Pictorial Review</i></p>
<p>In pursuance of a policy to detain us on the island at Sick Dog until
the arrival of his daughter, Papa Isbister thought fit to tell us the
fate of Rainbow Pete, of whose physical deformity and thirst for gold we
knew something already. Rainbow Pete had come to Mushrat Portage,
playing his flute, at a time when preparations were being made to blast
a road-bed through the wilderness for the railroad.</p>
<p>Mushrat Portage had been but recently a willow clump, and a black rock
ledge hanging over a precipitous valley: the hand of the Indian could be
seen one day parting the leaves of the trail, and on the next, drills
came and tins of black powder, and hordes of greedy men, blind with a
burning zeal for "monkeying with powder" as our host of Sick Dog said.
They were strange men, hoarse men, unreasonable men who cast
sheep's-eyes at the dark woman from Regina, whose shack, rented of
Scarecrow Charlie, crowned the high point of the ledge. She was the only
woman on Mushrat, and at a time just before the blasting began, when
Rainbow Pete sauntered over the trail with his pick and his flute and
his dirty bag of rock specimens, she was hungrily watched and waited on
by the new inhabitants of that ancient portage—Mushrat, whose destinies
were soon to be so splendid, and whose skies were to be rocked and rent
by the thunders of men struggling with reluctant nature, monkeying with
powder.<span class="pagenum"><a id="Page_308">[Pg 308]</a></span></p>
<p>When Pete laid down his tools and guns on the table at Scarecrow
Charlie's, where the woman was employed, had he in his heart some
foreshadowing presentiment of the peril he was in, of the sharp
destroying fire of a resolute woman's eyes, which he was subjecting
himself to, in including her in his universal caress? Who knows? Perhaps
his flute had whispered tidings to him. He was, said Papa Isbister,
immensely proud of his plaything, this huge gaunt sailor, who had been
bent into the shape of a rainbow—the foot of a rainbow—by a chance
shot, which shattered his hip and gave him an impressive forward cant,
which appeared to women, it seemed—I quote my old friend—in the light
of an endearing droop.</p>
<p>The romantic visitation of this musical sailorman made the efforts of
all Mushrat as nothing. But Rainbow Pete seemed unaware of the fiery
jealousies glowing in the night on all sides of him when he fixed his
eyes on her for the first time—with that mellow assurance of a careless
master of the hearts and whims of women.</p>
<p>"What's this he said to her?" said our old friend. "It was skilful; it
was put like a notable question if she took it so."</p>
<p>"You don't want to go out to-night," he said to her, with his guns on
the table.</p>
<p>"No, I do not," she said to the man.</p>
<p>"There you will be taking the words out of my mouth to suit your heart,"
he went on saying to her. "Mark this, I'm making this a command to you.
You don't want to go out to-night. Do not do it."</p>
<p>This he told her was on account of stray bullets, because he was meaning
to shoot up that place.</p>
<p>Heh! It was a trick of his, to trap her into denying him when he had
made no offer.</p>
<p>Old Isbister laughed heartily at this picture of Pete in the days of his
triumph.</p>
<p>He was a captivating man, it appeared. He was tattooed. On his arms were
snakes and the like of that, daggers and the like of that, dragons and
the like of that.<span class="pagenum"><a id="Page_309">[Pg 309]</a></span> This was a romantic skin to the man; and his blue
eyes were like the diamond drills they were bringing to Mushrat.</p>
<p>"Oh my," said the woman, leaning at his table, "this is what will be
keeping me from mass, I shouldn't wonder."</p>
<p>This was a prairie woman from Regina; now mark, it was whispered to be
no credit to human nature that she had had to leave that town. No. She
was a full woman, very deep, with burning eyes. It was hard talking with
her, because of her lingering speech. Oh, she was a massive woman, for
the small shoes she wore. She was tall, as high as Rainbow Pete's
shoulder. She purchased scent for her hair. This I know, having seen it
standing in the bottles. She was a prairie woman.</p>
<p>This was a wild night we spent on Mushrat, after Pete's reproving the
woman there in Scarecrow Charlie's place. Smash McGregor, the little
doctor, was sitting between us in his yellow skull-cap; and Willis
Countryman was reading and drinking in one corner, listening to the
laughing men there. They were laughing, thinking of the fortunes there
would be here when blasting begun.</p>
<p>But Rainbow Pete was not one of the rockmen. No. He told them strange
tales of gold. Heh! He was athirst for gold. Strange tales he told of
gold. Once how in Australia he had hold of a lump of it as big as poor
McGregor's skull, but isn't it a perishing pity, oh my, this was just a
desert where he was, there was no water, he grew faint carrying the
nugget. Our mouths were open when the man told us he had dropped it in
the desert, with his name carved on it.</p>
<p>"There it is to this day, sinking in the sands," he said. Oh, the proud
woman from Regina. There she turned her dark eyes over our heads, never
looking at the plausible man at all; but she had heard him.</p>
<p>"Gold?" said Smash McGregor. "Why, there's gold enough in the world."</p>
<p>"Ay, there's comfort too, if you know where to take<span class="pagenum"><a id="Page_310">[Pg 310]</a></span> it," said Rainbow
Pete, twirling here at his mustache and looking at the woman.</p>
<p>"There's gold," said McGregor, "for any man."</p>
<p>"Yes, my hearty," said Pete, "it's twinkling in the river-beds, it
shines in the sands under your feet, but still it's hard to get in your
two fisties."</p>
<p>"Why," said Smash McGregor, "did you never hear there's a pot of gold at
the foot of every rainbow?"</p>
<p>Oh, my friend, as he went mentioning the rainbow, there was a
thunder-cap on the brow of that great sailor.</p>
<p>"So they call me—Rainbow Pete," he said.</p>
<p>"Look then," said McGregor, "take the pick, and strike the ground at
your feet."</p>
<p>Rainbow Pete was not hearing them.</p>
<p>"This is a man I have been following on many trails," he muttered, "This
man who made a rainbow of me. Mark this, he shall thirst, if I meet him.
Ay! He shall burn with these fingers at his throat. He shall have gold
poured into him like liquid, however."</p>
<p>It was plain he had no love for this man who had fashioned him in the
form of a rainbow.</p>
<p>"What is this man called?" said the little doctor.</p>
<p>"It's a dark man wearing a red cap, called Pal Yachy," said Rainbow
Pete. "He spends his time escaping me. Look, where he shot me in the
hip."</p>
<p>Now we shielded him, and he drew out his shirt showing the wound in the
thigh which made a rainbow of him; but stop, didn't McGregor discover
the strange business on his spine?</p>
<p>"What's this, however?" he said.</p>
<p>"This is a palm-tree," said the man. "Stand close about me."</p>
<p>Oh my, we stood close, watching the man twisting up his shirt, and here
we saw the palm-tree going up his spine, and every joint of his spine
was used for a joint of the tree, like; and the long blue leaves were
waving on his shoulder-blade when he would be rippling the skin. This
was a fine broad back like satin to be putting a<span class="pagenum"><a id="Page_311">[Pg 311]</a></span> palm-tree on. Look, as
I am lifting my head, here I see the dark woman silent at the bar,
burning up with curiosity at what we are hiding here. Listen, it's the
man's voice, under his shirt.</p>
<p>"This was done in the South Seas, when I was young," he said to us, "and
the bigger I grow, the bigger the tree is. And now what next?" Then he
put his shirt back, and stood up to be fixing an eye on the woman from
Regina.</p>
<p>He was first to be waited on at Scarecrow Charlie's. Yes, he was first.
This was a mystery of a man to that dark woman from Regina.</p>
<p>Now in these days before blasting began, they were fond of talking
marriage on Mushrat, thinking of this woman from Regina, who was at the
disposal of no man there. They were full of doubts and wonderments, when
they would be idling together in Scarecrow Charlie's. But now one
morning when they were idling there, Shoepack Sam must be yawning and
saying to them,</p>
<p>"Oh, my, this is the time now, before the sun is up, I'm glad I am not
married. It's a pleasure to be a single man at this hour."</p>
<p>Heh! Heh! As a usual thing we are not gratified at all for this favor of
heaven. A single man, Shoepack Sam was saying, would not have to be
looking at the wreck of his wife in the morning; and this is when women
were caught unawares in the gill-nets time is lowering for them.</p>
<p>"They are pale about the gills then," he said. "They are just drowned
fish. They have stayed in the nets too long."</p>
<p>"No, it's not certain," said Rainbow Pete. "She might be
pleasant-looking on the pillow with her hair adrift."</p>
<p>Then Shoepack told him that the salt water had leaked into his brains,
what with his voyages.</p>
<p>"Still, this is a beautiful cheek," said Pete, speaking low, because she
was moving about beyond the boards.<span class="pagenum"><a id="Page_312">[Pg 312]</a></span></p>
<p>"These things are purchased," said Shoepack, scraping his feet together
in yellow moosehides. "Listen to me, I have seen them in a long line, on
her shelf, with many odors."</p>
<p>So they were talking together, and Rainbow Pete was putting his fingers
to the flute and staring down the valley, where Throat River was
twisting like a rag.</p>
<p>"I could have had a wife for speaking at Kicking Horse," he said.</p>
<p>"There is one for speaking now," said Shoepack.</p>
<p>"In a few days I go North," Rainbow Pete went muttering. "There is gold
at Dungeon Creek. I have seen samples of this vein."</p>
<p>"She will be the less trouble to you then, if you are not satisfied on
this question," said Shoepack Sam.</p>
<p>Then Rainbow Pete said he was not so certain of her, on questioning
himself. He was a modest man.</p>
<p>"This palm-tree and the other designs you have not been speaking about
will be enticing her," said Shoepack Sam. "But do not speak to her of
going away at the time of asking her."</p>
<p>"This is wisdom," said Rainbow Pete, and he put his lips to the flute,
to be giving us a touch of music.</p>
<p>This was a light reason for marriage, disn't it seem? This was what
Willis Countryman called a marriage of convenience, in the fashion of
frogs. Ay! It was convenient to them to be married. He was a great
reader—Willis.</p>
<p>So they were married, I'm telling you, but it's impossible to know what
he said to her in speaking about it. They were married by the man called
Justice of the Peace on Mushrat. This was before the blasting, and it
was the first marriage on Mushrat.</p>
<p>Then they lived together in the little house she had chosen, sitting on
the black ledge above Scarecrow Charlie's eating-place. Now it was a
wonderment to Mushrat, to hear the sound of Rainbow Pete's old flute
dropping from the dark ledge, by night, when they were<span class="pagenum"><a id="Page_313">[Pg 313]</a></span> taking their
opinion of matrimony up there together, with a candle at the window.</p>
<p>But now look here, when Shoepack Sam came plucking him at the elbow,
saying, "Was I right or was I wrong?" then Rainbow Pete stared at him
with his eyes like drills, and he said to him, "You were curious and
nothing more." Oh my, isn't this the perversity of married men.</p>
<p>They bore him a grudge on Mushrat, for his silence, because, disn't it
seem, this was like a general marriage satisfying all men's souls. It
was treasonable. Oh my, it was sailor's mischief to be living on that
ledge, and dropping nothing but notes from his greasy flute. These are
sweet but they are hard to be turning into language.</p>
<p>Now one morning, when I saw him coming from the ledge with his bag of
specimens over his shoulder, I saw without speaking to him that he was
parching with his thirst for gold. He was going away into the bush,
thinking no more of his new wife. Oh, he was a casual man.</p>
<p>"How is this?" I said. "Can she be left alone on the ledge?"</p>
<p>"Can she not?" said Rainbow Pete. "Old fellow, this is a substantial
woman. She was alone before I came."</p>
<p>"This is not the same thing," I said.</p>
<p>"It is the same woman," said Rainbow Pete, "she will be missing nothing
but the flute."</p>
<p>Oh my, wasn't the flute a little thing to reckon with. He went North,
dreaming of gold, and here the matter they were thinking about was
locked in his heart. They were angry with the man on Mushrat. This was
not what they were looking for between friends. They were hoping to
learn the result of the experiment; but this was vain.</p>
<p>When he was gone, I saw her looking down into the valley, where the
first shots were being fired in the rock. Ay, the sun was dazzling her
eyes, but she dis not move,<span class="pagenum"><a id="Page_314">[Pg 314]</a></span> sitting as if her arms have been chopped
from the shoulders.</p>
<p>Now it was not many days after this that the blasting was begun on
Mushrat. Men came with instruments stamped by the government; these they
pointed down the trail and drove stakes into the ground. These were
great days on Mushrat. Oh yes, numbers of Swedes and Italians were in a
desperate way monkeying with powder. It's a fetching business. In a
week, look here, Scarecrow Charlie left his eating-place to go monkeying
with powder like the others, and disn't he get a bolt of iron through
his brain one morning? Oh, it's very much as if some one had pushed a
broom-handle through his skull.</p>
<p>That dark woman from Regina was not dismayed. She ran the eating-place
herself. This was a famous place: they heard of this as far West as
Regina and they came here to work and eat, attracted by her. She was
valuable to the contractors, bringing labor here. Disn't it seem an
achievement for a married woman? Still, Rainbow Pete was not remembered
after a time; and she was a dark beauty, with a reputation for not
saying much.</p>
<p>My, my, these were golden days for Smash McGregor. I ponder over them,
thinking what a business he had. He was paid by the contractors to be
sorting out arms and legs, putting the short ones together in one box,
and the long ones in another, marked with charcoal to be shipped. Oh,
they were just gathering up parts of mortals in packing cases,
dispatching them to Throat River Landing; and blood was leaking on the
decks every way in little lines. They were unlikely consignments.</p>
<p>Then, my friend, there came one night a dark man wearing a red cap and
here under his arm he had the instrument with strings. This was the
Chief Contractor under the Government in this region. He was rich; at
Winnipeg he had stabled many blood horses. Then they were clustering
about him at Scarecrow Charlie's, asking him his name. This, he said,
was Pal Yachy.</p>
<p>Oh my, now we knew him. This was the man who<span class="pagenum"><a id="Page_315">[Pg 315]</a></span> had given Pete his shape
of a rainbow. Disn't it seem an unfortunate thing for him to be coming
here? Still he did not know at first that this dark woman standing there
was the wife of Rainbow Pete.</p>
<p>He went flashing at her with his teeth, the dark musician. Ay, he was
better with the music than Rainbow Pete's old flute. He sang, plucking
this instrument, with a jolly face. Heh! Heh! She leaned over the bar,
looking at him, and dreaming of the prairies.</p>
<p>Then they told him that this woman was the wife of Rainbow Pete.</p>
<p>"Aha," he said, "but, my friends, a rainbow is not for very long. It is
beautiful, but look, it vanishes in air."</p>
<p>Was he afraid, without saying so? That I can not tell you. Still he
stayed on Mushrat. He was the destroyer of his countrymen. They blew
themselves to pieces in his service, coming in great numbers when he
crooked his finger.</p>
<p>Then my friend, he made himself noticeable to that dark woman. He took
his instrument to the ledge and sang to her.</p>
<p>This I know from Willis Countryman who lived near that place. He told me
that the man sang in the night a soft song and that the woman listened.
Ay, she listened in the window, looking down into the valley where
Throat River went roaring and the great Falls were like rags waving in
the dark. Ay, she sat watching the River come out of the North, where
Rainbow Pete was cruising after gold.</p>
<p>This Willis Countryman I'm telling you about was a fine man in his old
age for reading. Oh, it was not easy talking to the man, with his
muttering and muttering and his chin down firm intil the book. When he
had his shack on Mouse Island the fire jumped over from the wind-rows
they were burning in a right of way. What next? Disn't he put his furs
in a canoe to sink in the lee of the island, and there he went on
reading in the<span class="pagenum"><a id="Page_316">[Pg 316]</a></span> night with his chin out of water, and the light from his
house blazing and lighting up the book in his fist. Oh my, he was great
for reading, Willis.</p>
<p>Well, here, one night he came telling me about some queer women on a
beach, singing. "Ay! It was impossible to keep away from them while they
were at it. What is their name again?"</p>
<p>He made a prolonged effort to remember, sighed painfully, fixed his
gaze. I brought him back as if from a fit of epilepsy by the
interjection of the word, "Siren."</p>
<p>"Ay," he said, slowly and sadly. "The men put wax in their ears—" Now
mark this. The day after I was hearing this of Willis, the woman put her
hand on my arm as I was passing the ledge.</p>
<p>"You are a friend of my husband's," she whispered to me.</p>
<p>"What now?" I said.</p>
<p>"Will he come back to me, I wonder?" she said, looking in the valley.</p>
<p>"This is a long business, searching for gold," I went muttering.</p>
<p>"No man can say I have been unfaithful to him," she said to me, the
fierce woman, breathing through her teeth. "I have been speaking to no
man."</p>
<p>"This is certain," I said to her.</p>
<p>"If he dis not come according to my dream I am a lost woman, by this way
of going on," she said to me.</p>
<p>How is this? There were tears flowing on the face, while she was telling
me she was bewitched by the singing of Pal Yachy.</p>
<p>Oh, at first she would just lie listening there, but now the man with
his sweet voice was drawing her from her bed, to come putting aside the
scented bottles and leaning in the window.</p>
<p>Now I said, "My good woman, I am an old man with knowledge of the world.
This man is a—what's this again—siren. He has a fatal voice. You must
simply put wax in your ears not to hear it when he comes."<span class="pagenum"><a id="Page_317">[Pg 317]</a></span></p>
<p>What next? Disn't she confess to me that she has listened to him too
many times to be deaf to him. No, she must watch the valley when he
comes singing his rich song; her cheeks were wet then, and the wind went
shaking her. No, this was not a moment for wax. I was an old man. She
prevailed upon me to sit outside her window in a chair, watching for
him.</p>
<p>"Oh, I am afraid," she whispered to me, "being alone so high out of the
valley."</p>
<p>There I sat by night, hearing sounds of thunder below this crag. Pebbles
came rattling on the window, the rapid was choked with flying rock. They
were growing rich, these madmen monkeying with powder. The government
sent them gold in sacks, to pay those who were left for the lives that
had been lost.</p>
<p>They were mad; they tumbled champagne out of bottles into tubs, frisking
about in it. They had heard that this was done with money.</p>
<p>But Pal Yachy was more foolish. He came singing; oh my, this was a
powerful song, ringing against the ledges. This was a fantastic Italian,
singing like an angel to the deserted woman. Her eyes were dark; the
breast heaved. Oh, these sweet notes were never lost on her.</p>
<p>Now at this time, too, Pal Yachy offered a great prize for the first
child to be born on Mushrat. He came grinning under his red cap, saying
to us, "There are so many dying, should there not be a prize offered for
new life?"</p>
<p>He had learned what manner the woman had of surprising Rainbow Pete. It
was a great prize he offered. When the child was born, he stopped the
monkeying with powder in the valley for that day, though this too was a
great loss in money. The woman pleased him.</p>
<p>Then, my friend, on the night of the day when this child was born,
Rainbow Pete came back into the valley. Oh my, it's plain to us, looking
at the man under the stars, he has been toughing it. Ay! His beard was<span class="pagenum"><a id="Page_318">[Pg 318]</a></span>
tangled, the great bones were rising on his bare chest, his fingers
twitched as he was drooping over us. Now I'm telling you his eyes were
dim, and the sun had bleached his mustache the color of a lemon. There
he stood before us, holding the bag over his shoulder, while he went
scratching his bold nose like the picture of a pirate. Still he was
gentle in the eye; he was mild in misfortune. Oh, this sailorman was
just used to toughing it.</p>
<p>Look here, there he stopped, in the shadow of this great rock I'm
speaking of, and these men of Mushrat came asking him if he had made the
grade. They were fresh from dipping their carcasses in champagne. They
were sparkling men, not accountable to themselves.</p>
<p>"Have you made the grade?" they went bawling to him. This is to say, had
he struck gold?</p>
<p>"Oh, there's gold enough," Pete went rumbling at them, "but it's too far
to the North, mate. There's no taickle made for getting purchase on it."</p>
<p>"So I am thinking," said the little medicine-man, McGregor. "It lies
still at the foot of the rainbow."</p>
<p>"Ay," said Rainbow Pete; but with this word we went thinking of Pal
Yachy. Still we did not speak the name of that Italian. No, this would
be stronger in the ear of that sailorman than gunpowder in the valley.</p>
<p>"Look you here," said Rainbow Pete. "I am starving. I have not eaten in
two days. This is the curse falling on me for hunting gold."</p>
<p>Then they laughed, these mad rockmen, mocking him with their eyes. Their
eyes were twitching; there was powder in the corners of them.</p>
<p>"Are you not master of the eating-place?" they howled at him. "Look,
there it stands; is not your wife alone in it?"</p>
<p>"Oh my, oh my, he stood looking at them with a ghastly face. Disn't he
seem the casual man? It's as if he had forgotten that woman. He had no
memories at all.</p>
<p>"My wife," said the rainbow-man.<span class="pagenum"><a id="Page_319">[Pg 319]</a></span></p>
<p>"Look," said Shoepack Sam—oh, he remembered treason well—"he is
forgetful that he has a wife on Mushrat."</p>
<p>This was so appearedly. There he stood in the blue star-shine, fingering
his flute to bring her back to mind. Now, I thought, he will be asking
what description of wife is this answering to my name on Mushrat? Oh,
man is careless in appointing himself among various women.</p>
<p>Now, my friend, Rainbow Pete, blew a note on his flute to settle the
thing clear in his mind. Oh, he was not too brisk in looking up at the
black ledge, with the candle in the window. Now he was taken by the
knees. This is not the convenient part of a marriage of convenience. No.
But Shoepack Sam was waving a hand to us to be telling the man nothing
of destiny at that moment.</p>
<p>"Come," he said, "the flute is nothing now. There must be more song than
this, by what is going on."</p>
<p>Here he took Rainbow by the elbow, telling him to come and eat at
Scarecrow Charlie's, for he will need his strength.</p>
<p>"I am in charge here for the day," said Shoepack.</p>
<p>"How is this?" said Rainbow, whispering.</p>
<p>They went laughing on all sides of him. Oh the demons, they were
cackling while he sat devouring a great moose joint, until he was close
to braining them with the yellow ball of the joint. He went eating like
a timber-wolf from Great Bear.</p>
<p>"This is the palm-tree man," they sang in his ear. "Oh, why is it he
grew no cocoanuts stumbling on that lost trail? Isn't it convenient for
the man he is married this night?"</p>
<p>Oh, they were full of mischief with him, remembering the secret face he
had for them in the days of his experiment.</p>
<p>"Drink this," said Shoepack Sam. There he put champagne in a glass
before him. Oh, they were careful of the man.<span class="pagenum"><a id="Page_320">[Pg 320]</a></span></p>
<p>"Here, take my hand, and let me see if strength is coming back," said
Shoepack. "What is a rainbow without colors?"</p>
<p>Then the little medicine-man took his pulse, kneeling on the floor
beside him. Oh, the great sailor was puzzled. Still he drank what was in
the glass before him and after this he put his mustache into his mouth,
sipping it by chance.</p>
<p>"What is this you are preparing?" he said, pointing his bold nose to
them. Oh, the eyes were like a dreamer's: he was a child to appearances.</p>
<p>Then they went speaking to him of the stringed instrument they had heard
humming on the ledge, speaking another language than his own.</p>
<p>"This is a wife to be defended," said Shoepack Sam, padding there with
his yellow shoepacks bringing another drink. But still there was no word
of Pal Yachy. That black Italian was not popular at Throat River.</p>
<p>"Now I see you are speaking of another man," said Rainbow Pete. Then
Shoepack Sam went roaring, it was time for honest men to speak, when an
honest woman was being taken by a voice.</p>
<p>"Wait," said Rainbow Pete, with his thumb in the foam, "this is unlikely
she will want me cruising in, with another man singing in her ear."</p>
<p>Oh my, he was a considerate man, he was a natural husband, thinking of
his wife's feelings.</p>
<p>"Are you a man?" said Smash McGregor. "Here she has fed you when you
were starving—this is her food you have been eating. Will you pass this
ledge, leaving her to fortune?"</p>
<p>Rainbow Pete went putting the edge of the cruiser's ax to his twisted
thumb.</p>
<p>"I come to her in my shoes only," he said. "This is not what she will be
wanting. I have no gold."</p>
<p>They were shouting to him to have no thought of that, those mad rockmen.
There would be gold in plenty. There would be gold. Only go up on the
ledge.<span class="pagenum"><a id="Page_321">[Pg 321]</a></span></p>
<p>"Heard you nothing of the prize?" they bawled to him, the mischief
makers. "Oh, there will be no lack of money."</p>
<p>"How is this?" said Rainbow Pete. But they would not be answering him.
No! No! They went tumbling him out of Scarecrow Charlie's place, and
making for the ledge with him. Oh my, the mystified man. This was a
great shameface he had behind his mustache.</p>
<p>"I am much altered for the worse," he went muttering to us. "She will
think nothing of me now."</p>
<p>"There is still time for constancy," said Shoepack Sam. "Do not lose
hope."</p>
<p>Then he told them to be quiet, looking up at the dark ledge where the
woman lay.</p>
<p>"Old Greyback," said Rainbow Pete, whispering to me, "I am mistrustful
of this moment."</p>
<p>"Hist!" said McGregor, "that was the sound of his string. He will be
beginning now."</p>
<p>Ay, the voice began. We were wooden men, in rows, listening to this
Italian singing here a golden dream between his teeth.</p>
<p>"Who is this man?" said Rainbow Pete. Heh! Heh! Had he not heard this
voice before? We were dumb. Oh, this was wild, this was sweet, the long
cry of the man over the deep valley. He sang in his throat, saying to
the woman there would be no returning. The night was blue. I'm telling
you. He was a cunning beggar, Pal Yachy, for making the stars burn in
their sockets.</p>
<p>Now I saw him lift his arm to his head, the wicked sailor, listening to
the tune of his enemy. Ay, this was the man who had fashioned him in the
form of a rainbow. Still he did not know it, dreaming on his feet. He
went swaying like a poplar.</p>
<p>Look, I am an old man, but I stood thinking of my airly days. Yes, yes.
My brain was heavy. Oh, it was a sweet dagger here twisting in the soul
of man. I went picturing the deep snow to me, and the dark spruces of<span class="pagenum"><a id="Page_322">[Pg 322]</a></span>
the North; oh, the roses are speaking to me again from this cheek that
has been gone from me so long.</p>
<p>Heh! Heh! I should not be speaking of this. It was a sorrowful harp, the
voice of that fiend. It was like the wind following the eddy into
Lookout Cavern. Now it went choking that great sailor at the throat;
look, he was mild, he was a simple man for crying. The tears rolled in
his cheek, they sparkled there like the champagne.</p>
<p>Oh my, the song was done.</p>
<p>He was dumb, the great sailor, twisting his mustache.</p>
<p>"Come now," said McGregor, "quick, he will be going into the house."</p>
<p>They were gulls for diving at the ledge; but Rainbow Pete held out his
arm, stopping them.</p>
<p>"Stand away," he said, "I will be going into my house with old Greyback
here and no other."</p>
<p>This arm was not yet withered he had. No! They stayed in their tracks,
as we were going up the ledge.</p>
<p>The door was open of that house; the stringed instrument was laid
against it. Ay, the strings were humming still, the song was spinning
round like a leaf in the cavern of it; but the black Italian was inside.</p>
<p>Yes, he had gone before into the chamber where she was lying, with his
beautiful smile.</p>
<p>The door here was open. Look, by candle-light I saw her lying in a red
blanket, staring at the notable singer. Yes, I saw the bottles
containing odors standing in a row. There was scent in the room. Now she
closed her eyes, this prairie woman, lying under him like death. My
friend, there is no doubt she was beautiful upon the pillow without the
aid of scented bottles.</p>
<p>Heh! I felt him quiver, this great sailor, when he saw Pal Yachy
standing there, but I put my arms about him whispering to him to wait.
It was dark where we were, there was a light from the stove only.</p>
<p>Oh my, there the dark Italian was glittering and heaving; he went
holding in his fist a canvas sack stamped<span class="pagenum"><a id="Page_323">[Pg 323]</a></span> by the Government, containing
the proper weight of gold.</p>
<p>"This is his weight in gold," he said, and there he laid it at her
knees. Still her eyes were closed against that demon of a singer, as he
went saying, "But now my dear one, there must be no more talk of
husbands. Ha! ha! they are like smoke, these husbands. When it has
drifted, there must be new fire. So they say in my country."</p>
<p>She lay, not speaking to him, with the sack of gold heavy against her
knees.</p>
<p>"Is this plain?" said that Italian. Look now, Rainbow Pete is in his
very shadow. Ay, in the shadow of this man who had fashioned him like a
rainbow.</p>
<p>"This is a great sum," said Pal Yachy, never looking behind him. "To
this must be added the silence of one day in the valley."</p>
<p>"The silence," she went whispering, "the silence."</p>
<p>Ha! ha! this was not so dangerous as song. She was leaning on her elbow,
clutching the red blanket to her throat, with her long fingers twisting
at the bag. Now my heart stumbled. Oh now, I thought, the gold is heavy
against her; this is a misfortunate time to be forsaking her husband,
isn't it? Look, the shadow was deeper in the cheek of this sailor. He
saw nothing, I fancied, but the gold lying on the blanket.</p>
<p>What next I knew? Here was McGregor in his yellow skull, whispering,</p>
<p>"Is this the gold then at the foot of the rainbow? This is fool's gold
where the heart is concerned."</p>
<p>Then, my friend, she threw it clear of the bed. Ay! I heard it falling
on the ledge there, but at this time she did not know that Rainbow Pete
was in the room.</p>
<p>When she had thrown it, then she saw him, standing behind that demon of
a singer. Her eyes were strange then. By the expression of her eyes Pal
Yachy saw that he was doomed. He was like a frozen man.</p>
<p>"Wait now," said Rainbow Pete, "am I in my house here?"<span class="pagenum"><a id="Page_324">[Pg 324]</a></span></p>
<p>"Am I not your wife?" cried the dark woman from Regina.</p>
<p>Oh, the pleasant sailor. The song had touched him.</p>
<p>"Look now," he said to Pal Yachy, "you made a rainbow of me in the
beginning. Do you bring gold here now to plant at my feet, generous
man?"</p>
<p>My, my, this fantastic Italian knew that words were wasted now. He was
like a snake with his sting. But Rainbow Pete was not an easy man. He
broke the arm with one twist, look, the knife went spinning on the
ledge. And at this moment the blasting in the rock began again below the
ledge. They were at it again, monkeying with powder. Oh, it was death
they were speaking to down there. It was like a battle between giants
going on, there were thunders and red gleams in the black valley; and
the candle-flame went shivering with the great noises.</p>
<p>"Here," said Rainbow Pete, "I will scatter you like the rocks of the
valley."</p>
<p>Oh, the righteous man. Isn't it a strange consideration, the voice of
Pal Yachy moving this crooked sailor to good deeds? Ay! He was a noble
man, hurling the Italian from the house by his ears. Oh, it's a
circumstance to be puzzling over. He threw the gold after him. Ay, the
gold after—like dirt; and here the clothes hung loose on his own body
where he had been starving in the search for bags like that.</p>
<p>Now, as he went kneeling by his wife, he discovered his son, by the
crowing under the blanket.</p>
<p>"Look here at the little nipper, old Greyback," he said, "come a little
way into the room. Look now, at the fat back for putting a little
palm-tree on, while he is young. This is truth, old fellow, here is true
gold lying at the foot of the rainbow, according to the prophecy."</p>
<p>Our old friend stopped to breathe and blink.</p>
<p>"He had staked this claim but he had never worked it," he said solemnly.
But isn't it strange, the same man who had been fashioning him like a
rainbow, should be<span class="pagenum"><a id="Page_325">[Pg 325]</a></span> pointing out the gold to him. Oh, there's no doubt
Pal Yachy was defeated in the end by his own voice—</p>
<p>He went away that night, leaving all to the sub-contractors. Heh! He was
not seen on Mushrat again. Still he had a remarkable voice. Many times
afterward I have heard Rainbow Pete playing on his flute—this is in the
evening when the ledge is quiet—but this is not the same thing. No, no,
he could never bewitch her with his music, she must love him for his
intention only, to be charming her. Ay! This is safer.<span class="pagenum"><a id="Page_326">[Pg 326]</a></span></p>
