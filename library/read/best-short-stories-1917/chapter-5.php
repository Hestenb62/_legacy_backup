        <h2><a id="ONNIE"></a>ONNIE<a id="FNanchor_3_3"></a><a class="fnanchor pginternal" href="#Footnote_3_3">[3]</a></h2>
<p class="c"><span class="smcap">By</span> THOMAS BEER</p>
<p class="c">From <i>The Century Magazine</i></p>
<p>Mrs. Rawling ordered Sanford to take a bath, and with the clear vision
of seven years Sanford noted that no distinct place for this process had
been recommended. So he retired to a sun-warmed tub of rain-water behind
the stables, and sat comfortably armpit deep therein, whirring a rattle
lately worn by a snake, and presented to him by one of the Varian tribe,
sons of his father's foreman. Soaking happily, Sanford admired his
mother's garden, spread up along the slope toward the thick cedar
forest, and thought of the mountain strawberries ripening in this hot
Pennsylvania June. His infant brother Peter yelled viciously in the big
gray-stone house, and the great sawmill snarled half a mile away, while
he waited patiently for the soapless water to remove all plantain stains
from his brown legs, the cause of this immersion.</p>
<p>A shadow came between him and the sun, and Sanford abandoned the rattles
to behold a monstrous female, unknown, white-skinned, moving on majestic
feet to his seclusion. He sat deeper in the tub, but she seemed
unabashed, and stood with a red hand on each hip, a grin rippling the
length of her mouth.</p>
<p>"Herself says you'll be comin' to herself now, if it's you that's Master
San," she said.<span class="pagenum"><a id="Page_21">[Pg 21]</a></span></p>
<p>Sanford speculated. He knew that all things have an office in this
world, and tried to locate this preposterous, lofty creature while she
beamed upon him.</p>
<p>"I'm San. Are you the new cook?" he asked.</p>
<p>"I am the same," she admitted.</p>
<p>"Are you a <i>good</i> cook?" he continued. "Aggie wasn't. She drank."</p>
<p>"God be above us all! And whatever did herself do with a cook that drank
in this place?"</p>
<p>"I don't know. Aggie got married. Cooks <i>do</i>," said Sanford, much
entertained by this person. Her deep voice was soft, emerging from the
largest, reddest mouth he had ever seen. The size of her feet made him
dubious as to her humanity. "Anyhow," he went on, "tell mother I'm not
clean yet. What's your name?"</p>
<p>"Onnie," said the new cook. "An' would this be the garden?"</p>
<p>"Silly, what did you think?"</p>
<p>"I'm a stranger in this place, Master San, an' I know not which is why
nor forever after."</p>
<p>Sanford's brain refused this statement entirely, and he blinked.</p>
<p>"I guess you're Irish," he meditated.</p>
<p>"I am. Do you be gettin' out of your tub now, an' Onnie'll dry you," she
offered.</p>
<p>"I can't," he said firmly; "you're a lady."</p>
<p>"A lady? Blessed Mary save us from sin! A lady? Myself? I'm no such
thing in this world at all; I'm just Onnie Killelia."</p>
<p>She appeared quite horrified, and Sanford was astonished. She seemed to
be a woman, for all her height and the extent of her hands.</p>
<p>"Are you sure?" he asked.</p>
<p>"As I am a Christian woman," said Onnie. "I never was a lady, nor could
I ever be such a thing."</p>
<p>"Well," said Sanford, "I don't know, but I suppose you can dry me."</p>
<p>He climbed out of his tub, and this novel being paid<span class="pagenum"><a id="Page_22">[Pg 22]</a></span> kind attention to
his directions. He began to like her, especially as her hair was of a
singular, silky blackness, suggesting dark mulberries, delightful to the
touch. He allowed her to kiss him and to carry him, clothed, back to the
house on her shoulders, which were as hard as a cedar trunk, but covered
with green cloth sprinkled with purple dots.</p>
<p>"And herself's in the libr'y drinkin' tea," said his vehicle, depositing
him on the veranda. "An' what might that be you'd be holdin'?"</p>
<p>"Just a rattle off a snake."</p>
<p>She examined the six-tiered, smoky rattle with a positive light in her
dull, black eyes and crossed herself.</p>
<p>"A queer country, where they do be bellin' the snakes! I heard the like
in the gover'ment school before I did come over the west water, but I
misbelieved the same. God's ways is strange, as the priests will be
sayin'."</p>
<p>"You can have it," said Sanford, and ran off to inquire of his mother
the difference between women and ladies.</p>
<p>Rawling, riding slowly, came up the driveway from the single lane of his
village, and found the gigantic girl sitting on the steps so absorbed in
this sinister toy that she jumped with a little yelp when he dismounted.</p>
<p>"What have you there?" he asked, using his most engaging smile.</p>
<p>"'Tis a snake's bell, your Honor, which Master San did be givin' me.
'Tis welcome indeed, as I lost off my holy medal, bein' sick, forever on
the steamship crossin' the west water."</p>
<p>"But—can you use a rattle for a holy medal?" said Rawling.</p>
<p>"The gifts of children are the blessin's of Mary's self," Onnie
maintained. She squatted on the gravel and hunted for one of the big
hair-pins her jump had loosened, then used it to pierce the topmost
shell.<span class="pagenum"><a id="Page_23">[Pg 23]</a></span> Rawling leaned against his saddle, watching the huge hands, and
Pat Sheehan, the old coachman, chuckled, coming up for the tired horse.</p>
<p>"You'll be from the West," he said, "where they string sea-shells."</p>
<p>"I am, an' you'll be from Dublin, by the sound of your speakin'. So was
my father, who is now drowned forever, and with his wooden leg," she
added mournfully, finding a cord in some recess of her pocket, entangled
there with a rosary and a cluster of small fishhooks. She patted the odd
scapular into the cleft of her bosom and smiled at Rawling. "Them in the
kitchen are tellin' me you'll be ownin' this whole country an' sixty
miles of it, all the trees an' hills. You'll be no less than a
President's son, then, your Honor."</p>
<p>Pat led the horse off hastily, and Rawling explained that his lineage
was not so interesting. The girl had arrived the night before, sent on
by an Oil City agency, and Mrs. Rawling had accepted the Amazon as
manna-fall. The lumber valley was ten miles above a tiny railroad
station, and servants had to be tempted with triple wages, were
transient, or married an employee before a month could pass. The valley
women regarded Rawling as their patron, heir of his father, and as
temporary aid gave feudal service on demand; but for the six months of
his family's residence each year house servants must be kept at any
price. He talked of his domain, and the Irish girl nodded, the rattles
whirring when she breathed, muffled in her breast, as if a snake were
crawling somewhere near.</p>
<p>"When my father came here," he said, "there wasn't any railroad, and
there were still Indians in the woods."</p>
<p>"Red Indians? Would they all be dead now? My brother Hyacinth is fair
departed his mind readin' of red Indians. Him is my twin."</p>
<p>"How many of you are there?"</p>
<p>"Twelve, your Honor," said Onnie, "an' me the first to go off, bein'
that I'm not so pretty a man would be<span class="pagenum"><a id="Page_24">[Pg 24]</a></span> marryin' me that day or this. An'
if herself is content, I am pleased entirely."</p>
<p>"You're a good cook," said Rawling, honestly. "How old are you?"</p>
<p>He had been puzzling about this; she was so wonderfully ugly that age
was difficult to conjecture. But she startled him.</p>
<p>"I'll be sixteen next Easter-time, your Honor."</p>
<p>"That's very young to leave home," he sympathized.</p>
<p>"Who'd be doin' the like of me any hurt? I'd trample the face off his
head," she laughed.</p>
<p>"I think you could. And now what do you think of my big son?"</p>
<p>The amazing Onnie gurgled like a child, clasping her hands.</p>
<p>"Sure, Mary herself bore the like among the Jew men, an' no one since
that day, or will forever. An' I must go to my cookin', or Master San
will have no dinner fit for him."</p>
<p>Rawling looked after her pink flannel petticoat, greatly touched and
pleased by this eulogy. Mrs. Rawling strolled out of the hall and
laughed at the narrative.</p>
<p>"She's appalling to look at, and she frightens the other girls, but
she's clean and teachable. If she likes San, she may not marry one of
the men—for a while."</p>
<p>"He'd be a bold man. She's as big as Jim Varian. If we run short of
hands, I'll send her up to a cutting. Where's San?"</p>
<p>"In the kitchen. He likes her. Heavens! if she'll only stay, Bob!"</p>
<p>Onnie stayed, and Mrs. Rawling was gratified by humble obedience and
excellent cookery. Sanford was gratified by her address, strange to him.
He was the property of his father's lumbermen, and their wives called
him everything from "heart's love" to "little cabbage," as their origin
might dictate; but no one had ever called him "Master San." He was San
to the<span class="pagenum"><a id="Page_25">[Pg 25]</a></span> whole valley, the first-born of the owner who gave their
children schools and stereopticon lectures in the union chapel, as his
father had before him. He went where he pleased, safe except from blind
nature and the unfriendly edges of whirling saws. Men fished him out of
the dammed river, where logs floated, waiting conversion into
merchantable planking, and the Varian boys, big, tawny youngsters, were
his body-guard. These perplexed Onnie Killelia in her first days at
Rawling's Hope.</p>
<p>"The agent's lads are whistlin' for Master San," she reported to Mrs.
Rawling. "Shall I be findin' him?"</p>
<p>"The agent's lads? Do you mean the Varian boys?"</p>
<p>"Them's them. Wouldn't Jim Varian be his honor's agent? Don't he be
payin' the tenantry an' sayin' where is the trees to be felled? I forbid
them to come in, as Miss Margot—which is a queer name!—is asleep
sound, an' Master Pete."</p>
<p>"Jim Varian came here with his honor's father, and taught his honor to
shoot and swim, also his honor's brother Peter, in New York, where we
live in winter. Yes, I suppose you'd call Jim Varian his honor's agent.
The boys take care of Master San almost as well as you do."</p>
<p>Onnie sniffed, balancing from heel to heel.</p>
<p>"Fine care! An' Bill Varian lettin' him go romping by the poison-ivy,
which God lets grow in this place like weeds in a widow's garden. An'
his honor, they do be sayin', sends Bill to a fine school, and will the
others after him, and to a college like Dublin has after. An' they
callin' himself San like he was their brother!"</p>
<p>As a volunteer nurse-maid Onnie was quite miraculous to her mistress.
Apparently she could follow Sanford by scent, for his bare soles left no
traces in the wild grass, and he moved rapidly, appearing at home
exactly when his stomach suggested. He was forbidden only the slate
ledges beyond the log basin, where rattlesnakes<span class="pagenum"><a id="Page_26">[Pg 26]</a></span> took the sun, and the
trackless farther reaches of the valley, bewildering to a small boy,
with intricate brooks and fallen cedar or the profitable yellow pine.
Onnie, crying out on her saints, retrieved him from the turn-table-pit
of the narrow-gauge logging-road, and pursued his fair head up the
blue-stone crags behind the house, her vast feet causing avalanches
among the garden beds. She withdrew him with railings from the
enchanting society of louse-infested Polish children, and danced
hysterically on the shore of the valley-wide, log-stippled pool when the
Varians took him to swim. She bore him off to bed, lowering at the
actual nurse. She filled his bath, she cut his toe-nails. She sang him
to sleep with "Drolien" and the heart-shattering lament for Gerald. She
prayed all night outside his door when he had a brief fever. When
trouble was coming, she said the "snake's bells" told her, talking
loudly; and petty incidents confirmed her so far that, after she found
the child's room ablaze from one of Rawling's cigarettes, they did not
argue, and grew to share half-way her superstition.</p>
<p>Women were scarce in the valley, and the well-fed, well-paid men needed
wives; and, as time went on, Honora Killelia was sought in marriage by
tall Scots and Swedes, who sat dumbly passionate on the back veranda,
where she mended Sanford's clothes. Even hawk-nosed Jim Varian, nearing
sixty, made cautious proposals, using Bill as messenger, when Sanford
was nine.</p>
<p>"God spare us from purgatory!" she shouted. "Me to sew for the eight of
you? Even in the fine house his honor did be givin' the agent I could
not stand the noise of it. An' who'd be mendin' Master San's clothes? Be
out of this kitchen, Bill Varian!"</p>
<p>Rawling, suffocated with laughter, reeled out of the pantry and fled to
his pretty wife.</p>
<p>"She thinks San's her own kid!" he gasped.</p>
<p>"She's perfectly priceless. I wish she'd be as careful<span class="pagenum"><a id="Page_27">[Pg 27]</a></span> of Margot and
Pete. I wish we could lure her to New York. She's worth twenty city
servants."</p>
<p>"Her theory is that if she stays here there's some one to see that Pat
Sheehan doesn't neglect—what does she call San's pony?" Rawling asked.</p>
<p>"The little horse. Yes, she told me she'd trample the face off Pat if
Shelty came to harm. She keeps the house like silver, too; and it's
heavenly to find the curtains put up when we get here. Heavens! listen!"</p>
<p>They were in Rawling's bedroom, and Onnie came up the curved stairs.
Even in list house-slippers she moved like an elephant, and Sanford had
called her, so the speed of her approach shook the square upper hall,
and the door jarred a little way open with the impact of her feet.</p>
<p>"Onnie, I'm not sleepy. Sing Gerald," he commanded.</p>
<p>"I will do that same if you'll be lyin' down still, Master San. Now,
this is what Conia sang when she found her son all dead forever in the
sands of the west water."</p>
<p>By the sound Onnie sat near the bed crooning steadily, her soft
contralto filling both stories of the happy house. Rawling went across
the hall to see, and stood in the boy's door. He loved Sanford as
imaginative men can who are still young, and the ugly girl's idolatry
seemed natural. Yet this was very charming, the simple room, the drowsy,
slender child, curled in his sheets, surrounded with song.</p>
<p>"Thank you, Onnie," said Sanford. "I suppose she loved him a lot. It's a
nice song. Goo' night."</p>
<p>As Onnie passed her master, he saw the stupid eyes full of tears.</p>
<p>"Now, why'll he be thankin' me," she muttered—"me that 'u'd die an'
stay in hell forever for him? Now I must go mend up the fish-bag your
Honor's brother's wife was for sendin' him an' which no decent fish
would be dyin' in."<span class="pagenum"><a id="Page_28">[Pg 28]</a></span></p>
<p>"Aren't you going to take Jim Varian?" asked Rawling.</p>
<p>"I wouldn't be marryin' with Roosyvelt himself, that's President, an'
has his house built all of gold! Who'd be seein' he gets his meals, an'
no servants in the sufferin' land worth the curse of a heretic? Not the
agent, nor fifty of him," Onnie proclaimed, and marched away.</p>
<p> </p>
<p>Sanford never came to scorn his slave or treat her as a servant. He was
proud of Onnie. She did not embarrass him by her all-embracing
attentions, although he weaned her of some of them as he grew into a
wood-ranging, silent boy, studious, and somewhat shy outside the feudal
valley. The Varian boys were sent, as each reached thirteen, to
Lawrenceville, and testified their gratitude to the patron by diligent
careers. They were Sanford's summer companions, with occasional visits
from his cousin Denis, whose mother disapproved of the valley and Onnie.</p>
<p>"I really don't see how Sanford can let the poor creature fondle him,"
she said. "Denny tells me she simply wails outside San's door if he
comes home wet or has a bruise. It's rather ludicrous, now that San's
fourteen. She writes to him at Saint Andrew's."</p>
<p>"I told her Saint Andrew's wasn't far from Boston, and she offered to
get her cousin Dermot—he's a bellhop at the Touraine—to valet him.
Imagine San with a valet at Saint Andrew's!" Rawling laughed.</p>
<p>"But San isn't spoiled," Peter observed, "and he's the idol of the
valley, Bob, even more than you are. Varian, McComas, Jansen—the whole
gang and their cubs. They'd slaughter any one who touched San."</p>
<p>"I don't see how you stand the place," said Mrs. Peter. "Even if the men
are respectful, they're so familiar. And anything could happen there.
Denny tells me you have Poles and Russians—all sorts of dreadful
people."<span class="pagenum"><a id="Page_29">[Pg 29]</a></span></p>
<p>Her horror tinkled prettily in the Chinese drawing-room, but Rawling
sighed.</p>
<p>"We can't get the old sort—Scotch, Swedes, the <i>good</i> Irish. We get any
old thing. Varian swears like a trooper, but he has to fire them right
and left all summer through. We've a couple of hundred who are there to
stay, some of them born there; but God help San when he takes it over!"</p>
<p>Sanford learned to row at Saint Andrew's, and came home in June with
new, flat bands of muscle in his chest, and Onnie worshiped with loud
Celtic exclamations, and bade small Pete grow up like Master San. And
Sanford grew two inches before he came home for the next summer,
reverting to bare feet, corduroys, and woolen shirts as usual. Onnie
eyed him dazedly when he strode into her kitchen for sandwiches against
an afternoon's fishing.</p>
<p>"O Master San, you're all grown up sudden'!"</p>
<p>"Just five foot eight, Onnie. Ling Varian's five foot nine; so's Cousin
Den."</p>
<p>"But don't you be goin' round the cuttin' camps up valley, neither.
You're too young to be hearin' the awful way these news hands do talk.
It's a sin to hear how they curse an' swear."</p>
<p>"The wumman's right," said Cameron, the smith, who was courting her
while he mended the kitchen range. "They're foul as an Edinburgh
fishwife—the new men. Go no place wi'out a Varian, two Varians, or one
of my lads."</p>
<p>"Good Lord! I'm not a kid, Ian!"</p>
<p>"Ye're no' a mon, neither. An' ye're the owner's first," said Cameron
grimly.</p>
<p>Rawling nodded when Sanford told him this.</p>
<p>"Jim carries an automatic in his belt, and we've had stabbings. Keep
your temper if they get fresh. We're in hot water constantly, San. Look
about the trails for whisky-caches. These rotten stevedores who come
floating in bother the girls and bully the kids. You're<span class="pagenum"><a id="Page_30">[Pg 30]</a></span> fifteen, and I
count on you to help keep the property decent. The boys will tell you
the things they hear. Use the Varians; Ling and Reuben are clever. I pay
high enough wages for this riffraff. I'll pay anything for good hands;
and we get dirt!"</p>
<p>Sanford enjoyed being a detective, and kept the Varians busy. Bill,
acting as assistant doctor of the five hundred, gave him advice on the
subject of cocaine symptoms and alcoholic eyes. Onnie raved when he
trotted in one night with Ling and Reuben at heel, their clothes rank
with the evil whiskey they had poured from kegs hidden in a cavern near
the valley-mouth.</p>
<p>"You'll be killed forever with some Polack beast! O Master San, it's not
you that's the polis. 'Tis not fit for him, your Honor. Some Irish pig
will be shootin' him, or a sufferin' Bohemyun."</p>
<p>"But it's the property, Onnie," the boy faltered. "Here's his honor
worked to death, and Uncle Jim. I've got to do something. They sell good
whisky at the store, and just smell me."</p>
<p>But Onnie wept, and Rawling, for sheer pity, sent her out of the
dining-room.</p>
<p>"She—she scares me!" Sanford said. "It's not natural, Dad, d' you
think?"</p>
<p>He was sitting on his bed, newly bathed and pensive, reviewing the day.</p>
<p>"Why not? She's alone here, and you're the only thing she's fond of.
Stop telling her about things or she'll get sick with worry."</p>
<p>"She's fond of Margot and Pete, but she's just idiotic about me. She did
scare me!"</p>
<p>Rawling looked at his son and wondered if the boy knew how attractive
were his dark, blue eyes and his plain, grave face. The younger children
were beautiful; but Sanford, reared more in the forest, had the forest
depth in his gaze and an animal litheness in his hard young body.<span class="pagenum"><a id="Page_31">[Pg 31]</a></span></p>
<p>"She's like a dog," Sanford reflected. "Only she's a woman. It's sort
of—"</p>
<p>"Pathetic?"</p>
<p>"I suppose that's the word. But I <i>do</i> love the poor old thing. Her
letters are rich. She tells me about all the new babies and who's
courting who and how the horses are. It <i>is</i> pathetic."</p>
<p> </p>
<p>He thought of Onnie often the next winter, and especially when she wrote
a lyric of thanksgiving after the family had come to Rawling's Hope in
April, saying that all would be well and trouble would cease. But his
father wrote differently:</p>
<p>"You know there is a strike in the West Virginia mines, and it has sent
a mass of ruffians out looking for work. We need all the people we can
get, but they are a pestiferous outfit. I am opening up a camp in Bear
Run, and our orders are enormous already, but I hate littering the
valley with these swine. They are as insolent and dirty as Turks. Pete
says the village smells, and has taken to the woods. Onnie says the new
Irish are black scum of Limerick, and Jim Varian's language isn't
printable. The old men are complaining, and altogether I feel like Louis
XVI in 1789. About every day I have to send for the sheriff and have
some thug arrested. A blackguard from Oil City has opened a dive just
outside the property, on the road to the station, and Cameron tells me
all sorts of dope is for sale in the hoarding-houses. We have
cocaine-inhalers, opium-smokers, and all the other vices."</p>
<p>After this outburst Sanford was not surprised when he heard from Onnie
that his father now wore a revolver, and that the overseers of the
sawmill did the same.</p>
<p>On the first of June Rawling posted signs at the edge of his valley and
at the railroad stations nearest, saying that he needed no more labor.
The tide of applicants ceased, but Mrs. Rawling was nervous. Pete
declared his intention of running away, and riding home in the<span class="pagenum"><a id="Page_32">[Pg 32]</a></span> late
afternoon, Margot was stopped by a drunken, babbling man, who seized her
pony's bridle, with unknown words. She galloped free, but next day
Rawling sent his wife and children to the seaside and sat waiting
Sanford's coming to cheer his desolate house, the new revolver cold on
his groin.</p>
<p>Sanford came home a day earlier than he had planned, and drove in a
borrowed cart from the station, furious when an old cottage blazed in
the rainy night, just below the white posts marking his heritage, and
shrill women screamed invitation at the horse's hoof-beats. He felt the
valley smirched, and his father's worn face angered him when they met.</p>
<p>"I almost wish you'd not come, Sonny. We're in rotten shape for a hard
summer. Go to bed, dear, and get warm."</p>
<p>"Got a six-shooter for me?"</p>
<p>"You? Who'd touch you? Some one would kill him. I let Bill have a gun,
and some other steady heads. You must keep your temper. You always have.
Ling Varian got into a splendid row with some hog who called Uncle
Jim—the usual name. Ling did him up. Ah, here's Onnie. Onnie, here's—"</p>
<p>The cook rushed down the stairs, a fearful and notable bed-gown covering
her night-dress, and the rattles chattering loudly.</p>
<p>"God's kind to us. See the chest of him! Master San! Master San!"</p>
<p>"Good Lord, Onnie. I wasn't dead, you know! Don't <i>kill</i> a fellow!"</p>
<p>For the first time her embrace was an embarrassment; her mouth on his
cheek made him flush. She loved him so desperately, this poor stupid
woman, and he could only be fond of her, give her a sort of tolerant
affection. Honesty reddened his face.</p>
<p>"Come on and find me a hard-boiled egg, there's a—"</p>
<p>"A hard-boiled egg? Listen to that, your Honor!<span class="pagenum"><a id="Page_33">[Pg 33]</a></span> An' it's near the
middle of the night! No, I'll not be findin' hard-boiled eggs for
you—oh, he's laughin' at me! Now you come into the dinin'-room, an'
I'll be hottin' some milk for you, for you're wet as any drowned little
cat. An' the mare's fine, an' I've the fishin'-sticks all dusted, an'
your new bathin'-tub's to your bath-room, though ill fate follow that
English pig Percival that put it in, for he dug holes with his heels!
An' would you be wantin' a roast-beef sandwidge?"</p>
<p>"She's nearly wild," said Rawling as the pantry door slammed. "You must
be careful, San, and not get into any rows. She'd have a fit. What is
it?"</p>
<p>"What do you do when you can't—care about a person as much as they care
about you?"</p>
<p>"Put up with it patiently." Rawling shrugged. "What else <i>can</i> you do?"</p>
<p>"I'm sixteen. She keeps on as if I were six. S-suppose she fell in love
with me? She's not old—very old."</p>
<p>"It's another sort of thing, Sonny. Don't worry," said Rawling, gravely,
and broke off the subject lest the boy should fret.</p>
<p>Late next afternoon Sanford rode down a trail from deep forest, lounging
in the saddle, and flicking brush aside with a long dog-whip. There was
a rain-storm gathering, and the hot air swayed no leaf. A rabbit,
sluggish and impertinent, hopped across his path and wandered up the
side trail toward Varian's cottage. Sanford halted the mare and
whistled. His father needed cheering, and Ling Varian, if obtainable,
would make a third at dinner. His intimate hurtled down the tunnel of
mountain ash directly and assented.</p>
<p>"Wait till I go back and tell Reuben, though. I'm cooking this week.
Wish Onnie 'd marry dad. Make her, can't you? Hi, Reu! I'm eating at the
house. The beef's on, and dad wants fried onions. Why won't she have
dad? <i>You're</i> grown up."</p>
<p>He trotted beside the mare noiselessly, chewing a birch spray, a hand on
his friend's knee.<span class="pagenum"><a id="Page_34">[Pg 34]</a></span></p>
<p>"She says she won't get married. I expect she'll stay here as long as
she lives."</p>
<p>"I suppose so, but I wish she'd marry dad," said Ling. "All this
trouble's wearing him out, and he won't have a hired girl if we could
catch one. There's a pile of trouble, San. He has rows every day. Had a
hell of a row with Percival yesterday."</p>
<p>"Who's this Percival? Onnie was cursing him out last night," Sanford
recollected.</p>
<p>"He's an awful big hog who's pulling logs at the runway. Used to be a
plumber in Australia. Swears like a sailor. He's a—what d' you call
'em? You know, a London mucker?"</p>
<p>"Cockney?"</p>
<p>"Yes, that's it. He put in your new bath-tub, and Onnie jumped him for
going round the house looking at things. Dad's getting ready to fire
him. He's the worst hand in the place. I'll point him out to you."</p>
<p>The sawmill whistle blew as the trail joined open road, and they passed
men, their shirts sweat-stained, nodding or waving to the boys as they
spread off to their houses and the swimming-place at the river bridge.</p>
<p>A group gathered daily behind the engine-yard to play horseshoe quoits,
and Sanford pulled the mare to a walk on the fringes of this half-circle
as old friends hailed him and shy lads with hair already sun-bleached
wriggled out of the crowd to shake hands, Camerons, Jansens, Nattiers,
Keenans, sons of the faithful. Bill Varian strolled up, his medical case
under an arm.</p>
<p>"I'm eating with you. The boss asked me. He feels better already. Come
in and speak to dad. He's hurt because <i>he's</i> not seen you, and you
stopped to see Ian at the forge. Hi, Dad!" he called over the felt hats
of the ring, "here's San."</p>
<p>"Fetch him in, then," cried the foreman.</p>
<p>Bill and Ling led the nervous mare through the group of pipe-smoking,
friendly lumbermen, and Varian hugged his fosterling's son.<span class="pagenum"><a id="Page_35">[Pg 35]</a></span></p>
<p>"Stop an' watch," he whispered. "They'll like seein' you, San. Onnie's
been tellin' the women you've growed a yard."</p>
<p>Sanford settled to the monotony of the endless sport, saluting known
brown faces and answering yelps of pleasure from the small boys who
squatted against the high fence behind the stake.</p>
<p>"That's Percival," said Ling, as a man swaggered out to the
pitching-mark.</p>
<p>"Six foot three," Bill said, "and strong as an ox. Drinks all the time.
Think he dopes, too."</p>
<p>Sanford looked at the fellow with a swift dislike for his vacant, heavy
face and his greasy, saffron hair. His bare arms were tattooed boldly
and in many colors, distorted with ropes of muscle. He seemed a little
drunk, and the green clouds cast a copper shade into his lashless eyes.</p>
<p>"Can't pitch for beans," said Ling as the first shoe went wide. When the
second fell beside it, the crowd laughed.</p>
<p>"Now," said Ian Cameron, "he'll be mad wi' vainglory. He's a camstearlie
ring' it an' a claverin' fu'."</p>
<p>"Ho! larf ahead!" snapped the giant. "'Ow's a man to 'eave a bloody
thing at a bloody stike?"</p>
<p>The experts chuckled, and he ruffled about the ring, truculent,
sneering, pausing before Varian, with a glance at Sanford.</p>
<p>"Give me something with some balance. Hi can show yer. Look!"</p>
<p>"I'm looking," said the foreman; "an' I ain't deaf, neither."</p>
<p>"'Ere's wot you blighters carn't 'eave. Learned it in Auckland, where
there's <i>real</i> men." He fumbled in his shirt, and the mare snorted as
the eight-inch blade flashed out of its handle under her nose. "See?
That's the lidy! Now watch! There's a knot-'ole up the palings there."</p>
<p>The crowd fixed a stare on the green, solid barrier,<span class="pagenum"><a id="Page_36">[Pg 36]</a></span> and the knife
soared a full twenty yards, but missed the knot-hole and rattled down.
There was flat derision in the following laughter, and Percival dug his
heel in the sod.</p>
<p>"Larf ahead! Hany one else try 'er?"</p>
<p>"Oh, shut up!" said some one across the ring. "We're pitchin' shoes."</p>
<p>Percival slouched off after his knife, and the frieze of small boys
scattered except a lint-haired Cameron who was nursing a stray cat
busily, cross-legged against the green boarding.</p>
<p>"Yon's Robert Sanford Cameron," said the smith. "He can say half his
catechism."</p>
<p>"Good kid," said Sanford. "I never could get any—"</p>
<p>Percival had wandered back and stood a yard off, glaring at Bill as the
largest object near.</p>
<p>"Think I can't, wot?"</p>
<p>"I'm not interested, and you're spoiling the game," said Bill, who
feared nothing alive except germs, and could afford to disregard most of
these. Sanford's fingers tightened on his whip.</p>
<p>"Ho!" coughed the cockney. "See! You—there!"</p>
<p>Robert Cameron looked up at the shout. The blade shot between the
child's head and the kitten and hummed gently, quivering in the wood.</p>
<p>"Hi could 'a' cut 'is throat," said Percival so complacently that
Sanford boiled.</p>
<p>"You scared him stiff," he choked. "You hog! Don't—"</p>
<p>"'Ello, 'oo's the young dook?"</p>
<p>"Look out," said a voice. "That's San, the—"</p>
<p>"Ho! 'Im with the Hirish gal to 'elp 'im tike 'is bloody barth nights?
'Oo's <i>he</i>? She's a—"</p>
<p>A second later Sanford knew that he had struck the man over the face
with his whip, cutting the phrase. The mare plunged and the whole crowd
congested about the bellowing cockney as Bill held Cameron back, and
huge Jansen planted a hand on Rawling's chest.<span class="pagenum"><a id="Page_37">[Pg 37]</a></span></p>
<p>"No worry," he said genially. "Yim an' us, Boss, our job."</p>
<p>Varian had wedged his hawk face close to the cockney's, now purple
blotched with wrath, and Rawling waited.</p>
<p>"Come to the office an' get your pay. You hear? Then you clear out. If
you ain't off the property in an hour you'll be dead. You hear?"</p>
<p>"He ought to," muttered Ling, leading the mare away. "Dad hasn't yelled
that loud since that Dutchman dropped the kid in the—hello, it's
raining!"</p>
<p>"Come on home, Sonny," said Rawling, "and tell us all about it. I didn't
see the start."</p>
<p>But Sanford was still boiling, and the owner had recourse to his godson.
Ling told the story, unabridged, as they mounted toward the house.</p>
<p>"Onnie'll hear of it," sighed Rawling. "Look, there she is by the
kitchen, and that's Jennie Cameron loping 'cross lots. Never mind, San.
You did the best you could; don't bother. Swine are swine."</p>
<p>The rain was cooling Sanford's head, and he laughed awkwardly.</p>
<p>"Sorry I lost my temper."</p>
<p>"I'm not. Jennie's telling Onnie. Hear?"</p>
<p>The smith's long-legged daughter was gesticulating at the kitchen
trellis, and Onnie's feet began a sort of war-dance in the wet grass as
Rawling approached.</p>
<p>"Where is this sufferin' pig, could your honor be tellin' me? God be
above us all! With my name in his black, ugly mouth! I <i>knew</i> there'd be
trouble; the snake's bells did be sayin' so since the storm was comin'.
An' him three times the bigness of Master San! Where'd he be now?"</p>
<p>"Jim gave him an hour to be off the property, Onnie."</p>
<p>"God's mercy he had no knife in his hand, then, even with the men by an'
Master San on his horse. Blessed Mary! I will go wait an' have speech
with this Englishman on the road."<span class="pagenum"><a id="Page_38">[Pg 38]</a></span></p>
<p>"You'll go get dinner, Onnie Killelia," said Rawling. "Master San is
tired, Bill and Ling are coming—and look there!"</p>
<p>The faithful were marching Percival down the road to the valley-mouth in
the green dusk. He walked between Jansen and Bill, a dozen men behind,
and a flying scud of boys before.</p>
<p>"An' Robbie's not hurt," said Miss Cameron, "an' San ain't, neither; so
don't you worry, Onnie. It's all right."</p>
<p>Onnie laughed.</p>
<p>"I'd like well to have seen the whip fly, your Honor. The arm of him!
Will he be wantin' waffles to his dinner? Heyah! more trouble yet!" The
rattles had whirred, and she shook her head. "A forest fire likely now?
Or a child bein' born dead?"</p>
<p>"Father says she's fëy," Jennie observed as the big woman lumbered off.</p>
<p>"You mean she has second sight? Perhaps. Here's a dollar for Robbie, and
tell Ian he's lucky."</p>
<p> </p>
<p>Bill raced up as the rain began to fall heavily in the windless gray of
six o'clock. He reported the cockney gone and the men loud in admiration
of Sanford; so dinner was cheerful enough, although Sanford felt limp
after his first attack of killing rage. Onnie's name on this animal's
tongue had maddened him, the reaction made him drowsy; but Ling's winter
at Lawrenceville and Bill's in New York needed hearing. Rawling left the
three at the hall fireplace while he read a new novel in the library.
The rain increased, and the fall became a continuous throbbing so steady
that he hardly heard the telephone ring close to his chair; but old
Varian's voice came clear along the wire.</p>
<p>"Is that you, Bob? Now, listen. One of them girls at that place down the
station road was just talkin' to me. She's scared. She rung me up an'
Cameron. That dam' Englishman's gone out o' there bile drunk,<span class="pagenum"><a id="Page_39">[Pg 39]</a></span> swearin'
he'll cut San's heart out, the pup! He's gone off wavin' his knife. Now,
he knows the house, an' he ain't afraid of nothin'—when he's drunk. He
might get that far an' try breakin' in. You lock up—"</p>
<p>"Lock up? What with?" asked Rawling. "There's not a lock in the place.
Father never had them put in, and I haven't."</p>
<p>"Well, don't worry none. Ian's got out a dozen men or so with lights an'
guns, an' Bill's got his. You keep Bill an' Ling to sleep down-stairs.
Ian's got the men round the house by this. The hog'll make noise enough
to wake the dead."</p>
<p>"Nice, isn't it, Uncle Jim, having this whelp out gunning for San! I'll
keep the boys. Good-night," he said hastily as a shadow on the rug
engulfed his feet. The rattles spoke behind him.</p>
<p>"There's a big trouble sittin' on my soul," said Onnie. "Your Honor
knows there's nothing makes mortal flesh so wild mad as a whipping, an'
this dog does know the way of the house. Do you keep the agent's lads
to-night in this place with guns to hand. The snake's bells keep
ringin'."</p>
<p>"My God! Onnie, you're making me believe in your rattles! Listen.
Percival's gone out of that den down the road, swearin' he'll kill San.
He's drunk, and Cameron's got men out."</p>
<p>"That 'u'd be the why of the lanterns I was seein' down by the forge.
But it's black as the bowels of purgatory, your Honor, an' him a strong,
wicked devil, cruel an' angry. God destroy him! If he'd tread on a
poison snake! No night could be so black as his heart."</p>
<p>"Steady, Onnie!"</p>
<p>"I'm speakin' soft. Himself's not able to hear," she said, her eyes half
shut. She rocked slowly on the amazing feet. "Give me a pistol, your
Honor. I'll be for sleepin' outside his door this night."<span class="pagenum"><a id="Page_40">[Pg 40]</a></span></p>
<p>"You'll go to bed and keep your door open. If you hear a sound, yell
like perdition. Send Bill in here. Say I want him. That's all. There's
no danger, Onnie; but I'm taking no chances."</p>
<p>"We'll take no chances, your Honor."</p>
<p>She turned away quietly, and Rawling shivered at this cool fury. The
rattles made his spine itch, and suddenly his valley seemed like a place
of demons. The lanterns circling on the lawn seemed like frail
glow-worms, incredibly useless, and he leaned on the window-pane
listening with fever to the rain.</p>
<p>"All right," said Bill when he had heard. "'Phone the sheriff. The man's
dangerous, sir. I doctored a cut he had the other day, and he tells me
he can see at night. That's a lie, of course, but he's light on his
feet, and he's a devil. I've seen some rotten curs in the hospitals, but
he's worse."</p>
<p>"Really, Billy, you sound as fierce as Onnie. She wanted a gun."</p>
<p>The handsome young man bit a lip, and his great body shook.</p>
<p>"This is San," he said, "and the men would kill any one who touched you,
and they'd burn any one who touched San. Sorry if I'm rude."</p>
<p>"We mustn't lose our heads." Rawling talked against his fear. "The man's
drunk. He'll never get near here, and he's got four miles to come in a
cold rain. But—"</p>
<p>"May I sleep in San's room?"</p>
<p>"Then he'll know. I don't want him to, or Ling, either; they're
imaginative kids. This is a vile mess, Billy."</p>
<p>"Hush! Then I'll sleep outside his door. I <i>will</i>, sir!"</p>
<p>"All right, old man. Thanks. Ling can sleep in Pete's room. Now I'll
'phone Mackintosh."</p>
<p>But the sheriff did not answer, and his deputy was ill. Rawling
shrugged, but when Varian telephoned that<span class="pagenum"><a id="Page_41">[Pg 41]</a></span> there were thirty men
searching, he felt more comfortable.</p>
<p>"You're using the wires a lot, Dad," said Sanford, roaming in. "Anything
wrong? Where's Ling to sleep?"</p>
<p>"In Pete's room. Good-night, Godson. No, nothing wrong."</p>
<p>But Sanford was back presently, his eyes wide.</p>
<p>"I say, Onnie's asleep front of my door and I can't get over her. What's
got into the girl?"</p>
<p>"She's worried. Her snake's bells are going, and she thinks the house'll
burn down. Let her be. Sleep with me, and keep my feet warm, Sonny."</p>
<p>"Sure," yawned Sanford. "'Night, Billy."</p>
<p>"Well," said Bill, "that settles that, sir. She'd hear anything, or I
will, and you're a light sleeper. Suppose we lock up as much as we can
and play some checkers?"</p>
<p>They locked the doors, and toward midnight Cameron rapped at the library
window, his rubber coat glistening.</p>
<p>"Not a print of the wastrel loon, sir; but the lads will bide out the
night. They've whusky an' biscuits an' keep moving."</p>
<p>"I'll come out myself," Rawling began, but the smith grunted.</p>
<p>"Ye're no stirrin' oot yer hoos, Robert Rawling! Ye're daft! Gin you met
this ganglin' assassinator, wha'd be for maister? San's no to lack a
father. Gae to yer bit bed!"</p>
<p>"Gosh!" said Bill, shutting the window, "<i>he's</i> in earnest. He forgot to
try to talk English even. I feel better. The hog's fallen into a hole
and gone to sleep. Let's go up."</p>
<p>"I suppose if I tell Onnie San's with me, she'll just change to my
door," Rawling considered; "but I'll try. Poor girl, she's faithful as a
dog!"</p>
<p>They mounted softly and beheld her, huddled in a blanket, mountainous,
curled outside Sanford's closed door, just opposite the head of the
stairs. Rawling<span class="pagenum"><a id="Page_42">[Pg 42]</a></span> stooped over the heap and spoke to the tangle of
blue-shadowed hair.</p>
<p>"Onnie Killelia, go to bed."</p>
<p>"Leave me be, your Honor. I'm—"</p>
<p>Sleep cut the protest. The rattles sounded feebly, and Rawling stood up.</p>
<p>"Just like a dog," whispered Bill, stealing off to a guest-room. "I'll
leave my door open." He patted the revolver in his jacket and grinned
affectionately. "Good-night, Boss."</p>
<p>Rawling touched the switch inside his own door, and the big globe set in
the hall ceiling blinked out. They had decided that, supposing the
cockney got so far, a lightless house would perplex his feet, and he
would be the noisier. Rawling could reach this button from his bed, and
silently undressed in the blackness, laying the automatic on the bedside
table, reassured by all these circling folk, Onnie, stalwart Bill, and
the loyal men out in the rain. Here slept Sanford, breathing happily, so
lost that he only sighed when his father crept in beside him, and did
not rouse when Rawling thrust an arm under his warm weight to bring him
closer, safe in the perilous night.</p>
<p>The guest-room bed creaked beneath Bill's two hundred pounds of muscle,
and Ling snored in Peter's room. Rawling's nerves eased on the mattress,
and hypnotic rain began to deaden him, against his will. He saw Percival
sodden in some ditch, his knife forgotten in brandy's slumbers. No shout
came from the hillside. His mind edged toward vacancy, bore back when
the boy murmured once, then he gained a mid-state where sensation was
not, a mist.</p>
<p> </p>
<p>He sat up, tearing the blankets back, because some one moved in the
house, and the rain could be heard more loudly, as if a new window were
open. He swung his legs free. Some one breathed heavily in the hall.<span class="pagenum"><a id="Page_43">[Pg 43]</a></span>
Rawling clutched his revolver, and the cold of it stung. This might be
Onnie, any one; but he put his finger on the switch.</p>
<p>"Straight hover—hover the way it was," said a thick, puzzled voice.
"There, that one! 'Is bloody barth!"</p>
<p>The rattles whirred as if their first owner lived. Rawling pressed the
switch.</p>
<p>"Your Honor!" Onnie screamed. "Your Honor! Master San! Be lockin' the
door inside, Master San! Out of this, you! You!"</p>
<p>Rawling's foot caught in the doorway of the bright hall, and he
stumbled, the light dazzling on the cockney's wet bulk hurling itself
toward the great woman where she stood, her arms flung cruciform,
guarding the empty room. The bodies met with a fearful jar as Rawling
staggered up, and there came a crisp explosion before he could raise his
hand. Bill's naked shoulder cannoned into him, charging, and Bill's
revolver clinked against his own. Rawling reeled to the stair-head,
aiming as Bill caught at the man's shirt; but the cockney fell backward,
crumpling down, his face purple, his teeth displayed.</p>
<p>"In the head!" said Bill, and bent to look, pushing the plastered curls
from a temple. The beast whimpered and died; the knife rattled on the
planks.</p>
<p>"Dad," cried Sanford, "what on—"</p>
<p>"Stay where you are!" Rawling gasped, sick of this ugliness, dizzy with
the stench of powder and brandy. Death had never seemed so vile. He
looked away to the guardian where she knelt at her post, her hands
clasped on the breast of her coarse white robe as if she prayed, the
hair hiding her face.</p>
<p>"I'll get a blanket," Bill said, rising. "There come the men! That you,
Ian?"</p>
<p>The smith and a crowd of pale faces crashed up the stairs.<span class="pagenum"><a id="Page_44">[Pg 44]</a></span></p>
<p>"God forgie us! We let him by—the garden, sir. Alec thought he—"</p>
<p>"Gosh, Onnie!" said Bill, "excuse <i>me</i>! I'll get some clothes on. Here,
Ian—"</p>
<p>"Onnie," said Sanford, in the doorway—"Onnie, what's the matter?"</p>
<p>As if to show him this, her hands, unclasping, fell from the dead bosom,
and a streak of heart's blood widened from the knife-wound like the
ribbon of some very noble order.<span class="pagenum"><a id="Page_45">[Pg 45]</a></span></p>
