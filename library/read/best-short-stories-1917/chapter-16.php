        <h2><a id="GET_READY_THE_WREATHS14"></a>GET READY THE WREATHS<a id="FNanchor_14_14"></a><a class="fnanchor pginternal" href="#Footnote_14_14">[14]</a></h2>
<p class="c"><span class="smcap">By</span> FANNIE HURST</p>
<p class="c">From <i>The Cosmopolitan Magazine</i></p>
<p><span class="smcap">Where</span> St. Louis begins to peter out into brick-and limestone-kilns and
great scars of unworked and overworked quarries, the first and more
unpretentious of its suburbs take up—Benson, Maplehurst, and Ridgeway
Heights intervening with one-story brick cottages and two-story
packing-cases—between the smoke of the city and the carefully parked
Queen Anne quietude of Glenwood and Croton Grove.</p>
<p>Over Benson hangs a white haze of limestone, gritty with train and
foundry smoke. At night, the lime-kilns, spotted with white deposits,
burn redly, showing through their open doors like great, inflamed
diphtheretic throats, tongues of flame bursting and licking-out.</p>
<p>Winchester Road, which runs out from the heart of the city to string
these towns together, is paved with brick, and its traffic, for the most
part, is the great tin-tired dump-carts of the quarries and steel
interurban electric cars, which hum so heavily that even the windows of
outlying cottages titillate.</p>
<p>For blocks, from Benson to Maplehurst and from Maplehurst to Ridgeway
Heights, Winchester Road repeats itself in terms of the butcher, the
baker, the corner saloon. A feed store. A monument-and stone-cutter. A
confectioner. A general-merchandise store, with a glass case of men's
collars outside the entrance. The butcher, the baker, the corner saloon.</p>
<p>At Benson, where this highway cuts through, the city,<span class="pagenum"><a id="Page_327">[Pg 327]</a></span> wreathed in
smoke, and a great oceanic stretch of roofs are in easy view, and at
closer range, an outlying section of public asylums for the city's
discard of its debility and its senility.</p>
<p>Jutting a story above the one-storied march of Winchester Road, The
Convenience Merchandise Corner, Benson, overlooks, from the southeast
up-stairs window, a remote view of the City Hospital, the Ferris wheel
of an amusement-park, and on clear days, the oceanic waves of roof.
Below, within the store, that view is entirely obliterated by a brace of
shelves built across the corresponding window and brilliantly stacked
with ribbons of a score of colors and as many widths. A considerable
flow of daylight thus diverted, The Convenience Merchandise Corner, even
of early afternoon, fades out into half-discernible corners; a rear-wall
display of overalls and striped denim coats crowded back into
indefinitude, the haberdashery counter, with a giant gilt shirt-stud
suspended above, hardly more outstanding.</p>
<p>Even the notions and dry-goods, flanking the right wall in stacks and
bolts, merge into blur, the outline of a white-sateen and corseted
woman's torso surmounting the top-most of the shelves with bold
curvature.</p>
<p>With spring sunshine even hot against the steel rails of Winchester
Road, and awnings drawn against its inroads into the window display,
Mrs. Shila Coblenz, routing gloom, reached up tiptoe across the
haberdashery counter for the suspended chain of a cluster of bulbs, the
red of exertion rising up the taut line of throat and lifted chin.</p>
<p>"A little light on the subject, Milt."</p>
<p>"Let me, Mrs. C."</p>
<p>Facing her from the outer side of the counter, Mr. Milton Bauer
stretched also, his well-pressed, pin-checked coat crawling up.</p>
<p>All things swam out into the glow. The great suspended stud; the
background of shelves and boxes; the scissors-like overalls against the
wall; a clothes-line of children's factory-made print frocks; a
center-bin of<span class="pagenum"><a id="Page_328">[Pg 328]</a></span> women's untrimmed hats; a headless dummy beside the door,
enveloped in a long-sleeved gingham apron.</p>
<p>Beneath the dome of the wooden stud, Mrs. Shila Coblenz, of not too
fulsome but the hour-glass proportions of two decades ago, smiled, her
black eyes, ever so quick to dart, receding slightly as the cheeks
lifted.</p>
<p>"Two twenty-five, Milt, for those ribbed assorted sizes and reenforced
heels. Leave or take. Bergdorff &amp; Sloan will quote me the whole mill at
that price."</p>
<p>With his chest across the counter and legs out violently behind, Mr.
Bauer flung up a glance from his order-pad.</p>
<p>"Have a heart, Mrs. C. I'm getting two forty for that stocking from
every house in town. The factory can't turn out the orders fast enough
at that price. An up-to-date woman like you mustn't make a noise like
before the war."</p>
<p>"Leave or take."</p>
<p>"You could shave an egg," he said.</p>
<p>"And rush up those printed lawns. There was two in this morning,
sniffing around for spring dimities."</p>
<p>"Any cotton goods? Next month this time, you'll be paying an advance of
four cents on percales."</p>
<p>"Stocked."</p>
<p>"Can't tempt you with them wash silks, Mrs. C.? Neatest little article
on the market to-day."</p>
<p>"No demand. They finger it up, and then buy the cotton stuffs. Every
time I forget my trade hacks rock instead of clips bonds for its
spending-money, I get stung."</p>
<p>"This here wash silk, Mrs. C., would—"</p>
<p>"Send me up a dress-pattern off this coral-pink sample for Selene."</p>
<p>"This here dark mulberry, Mrs. C., would suit you something immense."</p>
<p>"That'll be about all."</p>
<p>He flopped shut his book, snapping a rubber band about it and inserting
it in an inner coat pocket.</p>
<p>"You ought to stick to them dark, winy shades,<span class="pagenum"><a id="Page_329">[Pg 329]</a></span> Mrs. C. With your
coloring and black hair and eyes, they bring you out like a Gipsy. Never
seen you look better than at the Y. M. H. A. entertainment."</p>
<p>Quick color flowed down her open throat and into her shirtwaist. It was
as if the platitude merged with the very corpuscles of a blush that sank
down into thirsty soil.</p>
<p>"You boys," she said, "come out here and throw in a jolly with every
bill of goods. I'll take a good fat discount instead."</p>
<p>"Fact. Never seen you look better. When you got out on the floor in that
stamp-your-foot kind of dance with old man Shulof, your hand on your hip
and your head jerking it up, there wasn't a girl on the floor, your own
daughter included, could touch you, and I'm giving it to you straight."</p>
<p>"That old thing! It's a Russian folk-dance my mother taught me the first
year we were in this country. I was three years old then, and, when she
got just crazy with homesickness, we used to dance it to each other
evenings on the kitchen floor."</p>
<p>"Say, have you heard the news?"</p>
<p>"No."</p>
<p>"Guess."</p>
<p>"Can't."</p>
<p>"Hammerstein is bringing over the crowned heads of Europe for
vaudeville."</p>
<p>Mrs. Coblenz moved back a step, her mouth falling open.</p>
<p>"Why—Milton Bauer—in the old country a man could be strung up for
saying less than that!"</p>
<p>"That didn't get across. Try another. A Frenchman and his wife were
traveling in Russia, and—"</p>
<p>"If—if you had an old mother like mine upstairs, Milton, eating out her
heart and her days and her weeks and her months over a husband's grave
somewhere in Siberia and a son's grave somewhere in Kishinef, you
wouldn't see the joke, neither."<span class="pagenum"><a id="Page_330">[Pg 330]</a></span></p>
<p>Mr. Bauer executed a self-administered pat sharply against the back of
his hand.</p>
<p>"Keeper," he said, "put me in the brain-ward. I—I'm sorry, Mrs. C., so
help me! Didn't mean to. How is your mother, Mrs. C.? Seems to me, at
the dance the other night, Selene said she was fine and dandy."</p>
<p>"Selene ain't the best judge of her poor old grandmother. It's hard for
a young girl to have patience for old age sitting and chewing all day
over the past. It's right pitiful the way her grandmother knows it, too,
and makes herself talk English all the time to please the child and
tries to perk up for her. Selene, thank God, ain't suffered, and can't
sympathize!"</p>
<p>"What's ailing her, Mrs. C.? I kinda miss seeing the old lady sitting
down here in the store."</p>
<p>"It's the last year or so, Milt. Just like all of a sudden, a woman as
active as mamma always was, her health and—her mind kind of went off
with a pop."</p>
<p>"Thu! Thu!"</p>
<p>"Doctor says with care she can live for years, but—but it seems
terrible the way her—poor mind keeps skipping back. Past all these
thirty years in America to—even weeks before I was born. The night
they—took my father off to Siberia, with his bare feet in the snow—for
distributing papers they found on him—papers that used the word
'<i>svoboda</i>'—'freedom.' And the time, ten years later—they shot down my
brother right in front of her for—the same reason. She keeps living it
over—living it over till I—could die."</p>
<p>"Say, ain't that just a shame, though!"</p>
<p>"Living it, and living it, and living it! The night with me, a heavy
three-year-old, in her arms that she got us to the border, dragging a
pack of linens with her! The night my father's feet were bleeding in the
snow, when they took him! How with me a kid in the crib, my—my
brother's face was crushed in—with a heel and a spur—all night,
sometimes, she cries in her sleep—begging to go back to find the
graves. All day she<span class="pagenum"><a id="Page_331">[Pg 331]</a></span> sits making raffia wreaths to take back—making
wreaths—making wreaths!"</p>
<p>"Say, ain't that tough!"</p>
<p>"It's a godsend she's got the eyes to do it. It's wonderful the way she
reads—in English, too. There ain't a daily she misses. Without them and
the wreaths—I dunno—I just dunno. Is—is it any wonder, Milt, I—I
can't see the joke?"</p>
<p>"My God, no!"</p>
<p>"I'll get her back, though."</p>
<p>"Why, you—she can't get back there, Mrs. C."</p>
<p>"There's a way. Nobody can tell me there's not. Before the war—before
she got like this, seven hundred dollars would have done it for both of
us—and it will again, after the war. She's got the bank-book, and every
week that I can squeeze out above expenses, she sees the entry for
herself. I'll get her back. There's a way lying around somewhere. God
knows why she should eat out her heart to go back—but she wants it.
God, how she wants it!"</p>
<p>"Poor old dame!"</p>
<p>"You boys guy me with my close-fisted buying these last two years. It's
up to me, Milt, to squeeze this old shebang dry. There's not much more
than a living in it at best, and now with Selene grown up and naturally
wanting to have it like other girls, it ain't always easy to see my way
clear. But I'll do it, if I got to trust the store for a year to a child
like Selene. I'll get her back."</p>
<p>"You can call on me, Mrs. C., to keep my eye on things while you're
gone."</p>
<p>"You boys are one crowd of true blues, all right. There ain't a city
salesman comes out here I wouldn't trust to the limit."</p>
<p>"You just try me out."</p>
<p>"Why, just to show you how a woman don't know many real friends she has
got, why—even Mark Haas, of the Mound City Silk Company, a firm I don't
do two hundred dollars' worth of business with a year,<span class="pagenum"><a id="Page_332">[Pg 332]</a></span> I wish you could
have heard him the other night at the Y. M. H. A., a man you know for
yourself just comes here to be sociable with the trade."</p>
<p>"Fine fellow, Mark Haas!"</p>
<p>"'When the time comes, Mrs. Coblenz,' he says, 'that you want to make
that trip, just you let me know. Before the war there wasn't a year I
didn't cross the water twice, maybe three times, for the firm. I don't
know there's much I can do; it ain't so easy to arrange for Russia, but,
just the same, you let me know when you're ready to make that trip.'
Just like that he said it. That from Mark Haas!"</p>
<p>"And a man like Haas don't talk that way if he don't mean it."</p>
<p>"Mind you, not a hundred dollars a year business with him. I haven't got
the demands for silks."</p>
<p>"That wash silk I'm telling you about though, Mrs. C., does up like a—"</p>
<p>"There's ma thumping with the poker on the upstairs floor. When it's
closing-time, she begins to get restless. I—I wish Selene would come
in. She went out with Lester Goldmark in his little flivver, and I get
nervous about automobiles."</p>
<p>Mr. Bauer slid an open-face watch from his waistcoat.</p>
<p>"Good Lord, five-forty, and I've just got time to sell the Maplehurst
Emporium a bill of goods!"</p>
<p>"Good-night, Milt; and mind you put up that order of assorted neckwear
yourself. Greens in ready-tieds are good sellers for this time of the
year, and put in some reds and purples for the teamsters."</p>
<p>"No sooner said than done."</p>
<p>"And come out for supper some Sunday night, Milt. It does mamma good to
have young people around."</p>
<p>"I'm yours."</p>
<p>"Good-night, Milt."</p>
<p>He reached across the counter, placing his hand over hers.</p>
<p>"Good-night, Mrs. C.," he said, a note lower in his<span class="pagenum"><a id="Page_333">[Pg 333]</a></span> throat; "and
remember, that call-on-me stuff wasn't just conversation."</p>
<p>"Good-night, Milt," said Mrs. Coblenz, a coating of husk over her own
voice and sliding her hand out from beneath, to top his. "You—you're
all right!"</p>
<p> </p>
<p>Upstairs, in a too tufted and too crowded room directly over the frontal
half of the store, the window overlooking the remote sea of city was
turning taupe, the dusk of early spring, which is faintly tinged with
violet, invading. Beside the stove, a base-burner with faint fire
showing through its mica, the identity of her figure merged with the fat
upholstery of the chair, except where the faint pink through the mica
lighted up old flesh, Mrs. Miriam Horowitz, full of years and senile
with them, wove with grasses, the écru of her own skin, wreaths that had
mounted to a great stack in a bedroom cupboard.</p>
<p>A clock, with a little wheeze and burring attached to each chime, rang
six, and upon it, Mrs. Coblenz, breathing from a climb, opened the door.</p>
<p>"Ma, why didn't you rap for Katie to come up and light the gas? You'll
ruin your eyes, dearie."</p>
<p>She found out a match, immediately lighting two jets of a
center-chandelier, turning them down from singing, drawing the shades of
the two front and the southeast windows, stooping over the upholstered
chair to imprint a light kiss.</p>
<p>"A fine day, mamma. There'll be an entry this week. Fifty dollars and
thirteen cents and another call for garden implements. I think I'll lay
in a hardware line after we—we get back. I can use the lower shelf of
the china-table, eh, ma?"</p>
<p>Mrs. Horowitz, whose face, the color of old linen in the yellowing,
emerged rather startling from the still black hair strained back from
it, lay back in her chair, turning her profile against the upholstered
back, half a wreath and a trail of raffia sliding to the floor. It was
as<span class="pagenum"><a id="Page_334">[Pg 334]</a></span> if age had sapped from beneath the skin, so that every curve had
collapsed to bagginess, the cheeks and the underchin sagging with too
much skin. Even the hands were crinkled like too large gloves, a wide,
curiously etched marriage band hanging loosely from the third finger.</p>
<p>Mrs. Coblenz stooped, recovering the wreath.</p>
<p>"Say, mamma, this one is a beauty! That's a new weave, ain't it? Here,
work some more, dearie—till Selene comes with your evening papers."</p>
<p>With her profile still to the chair-back, a tear oozed down the
corrugated surface of Mrs. Horowitz's cheek. Another.</p>
<p>"Now, mamma! Now, mamma!"</p>
<p>"I got a heaviness—here—inside. I got a heaviness—"</p>
<p>Mrs. Coblenz slid down to her knees beside the chair.</p>
<p>"Now, mamma; shame on my little mamma! Is that the way to act when Shila
comes up after a good day? Ain't we got just lots to be thankful for,
the business growing and the bank-book growing, and our Selene on top?
Shame on mamma!"</p>
<p>"I got a heaviness—here—inside—here."</p>
<p>Mrs. Coblenz reached up for the old hand, patting it.</p>
<p>"It's nothing, mamma—a little nervousness."</p>
<p>"I'm an old woman. I—"</p>
<p>"And just think, Shila's mamma, Mark Haas is going to get us letters and
passports and—"</p>
<p>"My son—my boy—his father before him—"</p>
<p>"Mamma—mamma, please don't let a spell come on! It's all right. Shila's
going to fix it. Any day now, maybe—"</p>
<p>"You'm a good girl. You'm a good girl, Shila." Tears were coursing down
to a mouth that was constantly wry with the taste of them.</p>
<p>"And you're a good mother, mamma. Nobody knows better than me how good."</p>
<p>"You'm a good girl, Shila."<span class="pagenum"><a id="Page_335">[Pg 335]</a></span></p>
<p>"I was thinking last night, mamma, waiting up for Selene—just thinking
how all the good you've done ought to keep your mind off the spells,
dearie."</p>
<p>"My son—"</p>
<p>"Why, a woman with as much good to remember as you've got oughtn't to
have time for spells. I got to thinking about Coblenz to-day, mamma,
how—you never did want him, and when I—I went and did it anyway, and
made my mistake, you stood by me to—to the day he died. Never throwing
anything up to me! Never nothing but my good little mother, working her
hands to the bone after he got us out here to help meet the debts he
left us. Ain't that a satisfaction for you to be able to sit and think,
mamma, how you helped—"</p>
<p>"His feet—blood from my heart in the snow—blood from my heart!"</p>
<p>"The past is gone, darling. What's the use tearing yourself to pieces
with it? Them years in New York, when it was a fight even for bread, and
them years here trying to raise Selene and get the business on a
footing, you didn't have time to brood then, mamma. That's why, dearie,
if only you'll keep yourself busy with something—the wreaths—the—"</p>
<p>"His feet—blood from my—"</p>
<p>"But I'm going to take you back, mamma. To papa's grave. To Aylorff's.
But don't eat your heart out until it comes, darling. I'm going to take
you back, mamma, with every wreath in the stack; only, you mustn't eat
out your heart in spells. You mustn't, mamma; you mustn't."</p>
<p>Sobs rumbled up through Mrs. Horowitz, which her hand to her mouth tried
to constrict.</p>
<p>"For his people he died. The papers—I begged he should burn them—he
couldn't—I begged he should keep in his hate—he couldn't—in the
square he talked it—the soldiers—he died for his people—they got
him—the soldiers—his feet in the snow when they took him—the blood in
the snow—O my God—my—God!"<span class="pagenum"><a id="Page_336">[Pg 336]</a></span></p>
<p>"Mamma, darling, please don't go over it all again. What's the use
making yourself sick? Please!"</p>
<p>She was well forward in her chair now, winding her dry hands one over
the other with a small rotary motion.</p>
<p>"I was rocking—Shila-baby in my lap—stirring on the fire black lentils
for my boy—black lentils—he—"</p>
<p>"Mamma!"</p>
<p>"My boy. Like his father before him. My—"</p>
<p>"Mamma, please! Selene is coming any minute now. You know how she hates
it. Don't let yourself think back, mamma. A little will-power, the
doctor says, is all you need. Think of to-morrow, mamma; maybe, if you
want, you can come down and sit in the store awhile and—"</p>
<p>"I was rocking. O my God, I was rocking, and—"</p>
<p>"Don't get to it—mamma, please! Don't rock yourself that way! You'll
get yourself dizzy. Don't, ma; don't!"</p>
<p>"Outside—my boy—the holler—O God, in my ears all my life! My boy—the
papers—the swords—Aylorff—Aylorff—"</p>
<p>"Shh-h-h—mamma—"</p>
<p>"It came through his heart out the back—a blade with two sides—out the
back when I opened the door—the spur in his face when he
fell—Shila—the spur in his face—the beautiful face of my boy—my
Aylorff—my husband before him—that died to make free!" And fell back,
bathed in the sweat of the terrific hiccoughing of sobs.</p>
<p>"Mamma, mamma—my God! What shall we do? These spells! You'll kill
yourself, darling. I'm going to take you back, dearie—ain't that
enough? I promise. I promise. You mustn't, mamma! These spells—- they
ain't good for a young girl like Selene to hear. Mamma, ain't you got
your own Shila—your own Selene? Ain't that something? Ain't it? Ain't
it?"</p>
<p>Large drops of sweat had come out and a state<span class="pagenum"><a id="Page_337">[Pg 337]</a></span> of exhaustion that swept
completely over, prostrating the huddled form in the chair.</p>
<p>With her arms twined about the immediately supporting form of her
daughter, her entire weight relaxed, and footsteps that dragged without
lift, one after the other, Mrs. Horowitz groped out, one hand feeling in
advance, into the gloom of a room adjoining.</p>
<p>"Rest! O my God, rest!"</p>
<p>"Yes, yes, mamma; lean on me."</p>
<p>"My—bed."</p>
<p>"Yes, yes, darling."</p>
<p>"Bed."</p>
<p>Her voice had died now to a whimper that lay on the room after she had
passed out of it.</p>
<p> </p>
<p>When Selene Coblenz, with a gust that swept the room, sucking the lace
curtains back against the panes, flung open the door upon that chromatic
scene, the two jets of gas were singing softly into its silence, and,
within the nickel-trimmed base-burner, the pink mica had cooled to gray.
Sweeping open that door, she closed it softly, standing for the moment
against it, her hand crossed in back and on the knob. It was as if
standing there with her head cocked and beneath a shadowy blue
sailor-hat, a smile coming out, something within her was playing,
sweetly insistent to be heard. Philomela, at the first sound of her
nightingale self, must have stood thus, trembling with melody. Opposite
her, above the crowded mantelpiece and surmounted by a raffia wreath,
the enlarged-crayon gaze of her deceased maternal grandparent, abetted
by a horrible device of photography, followed her, his eyes focusing the
entire room at a glance. Impervious to that scrutiny, Miss Coblenz moved
a tiptoe step or two further into the room, lifting off her hat, staring
and smiling through a three-shelved cabinet of knick-knacks at what she
saw far beyond. Beneath the two jets, high lights in her hair came out,
bronze showing<span class="pagenum"><a id="Page_338">[Pg 338]</a></span> through the brown waves and the patches of curls brought
out over her cheeks.</p>
<p>In her dark-blue dress with the row of silver buttons down what was hip
before the hipless age, the chest sufficiently concave and the
silhouette a mere stroke of hard pencil, Miss Selene Coblenz measured up
and down to America's Venus de Milo, whose chief curvature is of the
spine. Slim-etched, and that slimness enhanced by a conscious kind of
collapse beneath the blue-silk girdle that reached up halfway to her
throat, hers were those proportions which strong women, eschewing the
sweetmeat, would earn by the sweat of the Turkish bath.</p>
<p>When Miss Coblenz caught her eye in the square of mirror above the
mantelpiece, her hands flew to her cheeks to feel of their redness. They
were soft cheeks, smooth with the pollen of youth, and hands still
casing them, she moved another step toward the portièred door.</p>
<p>"Mamma!"</p>
<p>Mrs. Coblenz emerged immediately, finger up for silence, kissing her
daughter on the little spray of cheek-curls.</p>
<p>"Shh-h-h! Gramaw just had a terrible spell."</p>
<p>She dropped down into the upholstered chair beside the base-burner, the
pink and moisture of exertion out in her face, took to fanning herself
with the end of a face-towel flung across her arm.</p>
<p>"Poor gramaw!" she said. "Poor gramaw!"</p>
<p>Miss Coblenz sat down on the edge of a slim, home-gilded chair, and took
to gathering the blue-silk dress into little plaits at her knee.</p>
<p>"Of course—if you don't want to know where I've been—or anything—"</p>
<p>Mrs. Coblenz jerked herself to the moment.</p>
<p>"Did mamma's girl have a good time? Look at your dress all dusty! You
oughtn't to wear you best in that little flivver."</p>
<p>Suddenly Miss Coblenz raised her eyes, her red mouth bunched, her eyes
all iris.<span class="pagenum"><a id="Page_339">[Pg 339]</a></span></p>
<p>"Of course—if you don't want to know—anything."</p>
<p>At that large, brilliant gaze, Mrs. Coblenz leaned forward, quickened.</p>
<p>"Why, Selene!"</p>
<p>"Well, why—why don't you ask me something?"</p>
<p>"Why I—I dunno, honey, did—did you and Lester have a nice ride?"</p>
<p>There hung a slight pause, and then a swift moving and crumpling-up of
Miss Coblenz on the floor beside her mother's knee.</p>
<p>"You know—only, you won't ask."</p>
<p>With her hand light upon her daughter's hair, Mrs. Coblenz leaned
forward, her bosom rising to faster breathing.</p>
<p>"Why—Selene—I why—"</p>
<p>"We—we were speeding along and—all of a sudden—out of a clear
sky—he—he popped. He wants it in June—so we can make it our honeymoon
to his new territory out in Oklahoma. He knew he was going to pop, he
said, ever since the first night he saw me at the Y. M. H. A. He says to
his uncle Mark, the very next day in the store, he says to him, 'Uncle
Mark,' he says, 'I've met <i>the</i> little girl.' He says he thinks more of
my little finger than all of his regular crowd of girls in town put
together. He wants to live in one of the built-in-bed flats on Wasserman
Avenue, like all the swell young marrieds. He's making twenty-six
hundred now, mamma, and if he makes good in the new Oklahoma territory,
his uncle Mark is—is going to take care of him better. Ain't it like a
dream, mamma—your little Selene all of a sudden in with—the
somebodys?"</p>
<p>Immediately tears were already finding staggering procession down Mrs.
Coblenz' face, her hovering arms completely encircling the slight figure
at her feet.</p>
<p>"My little girl! My little Selene! My all!"</p>
<p>"I'll be marrying into one of the best families in town, ma. A girl who
marries a nephew of Mark Haas can<span class="pagenum"><a id="Page_340">[Pg 340]</a></span> hold up her head with the best of
them. There's not a boy in town with a better future than Lester. Like
Lester says, everything his uncle Mark touches turns to gold, and he's
already touched Lester. One of the best known men on Washington Avenue
for his blood-uncle, and on his poor dead father's side related to the
Katz &amp; Harberger Harbergers. Was I right, mamma, when I said if you'd
only let me stop school, I'd show you? Was I right, momsie?"</p>
<p>"My baby! It's like I can't realize it. So young!"</p>
<p>"He took the measure of my finger, mamma, with a piece of string. A
diamond, he says, not too flashy, but neat."</p>
<p>"We have 'em, and we suffer for 'em, and we lose 'em."</p>
<p>"He's going to trade in the flivver for a chummy roadster, and—"</p>
<p>"Oh, darling, it's like I can't bear it!"</p>
<p>At that, Miss Coblenz sat back on her tall wooden heels, mauve spats
crinkling.</p>
<p>"Well, you're a merry little future mother-in-law, momsie."</p>
<p>"It ain't that, baby. I'm happy that my girl has got herself up in the
world with a fine upright boy like Lester; only—you can't understand,
babe, till you've got something of your own flesh and blood that belongs
to you, that I—I couldn't feel anything except that a piece of my heart
was going if—if it was a king you was marrying."</p>
<p>"Now, momsie, it's not like I was moving a thousand miles away. You can
be glad I don't have to go far, to New York or to Cleveland, like Alma
Yawitz."</p>
<p>"I am! I am!"</p>
<p>"Uncle—Uncle Mark, I guess, will furnish us up like he did Leon and
Irma—only, I don't want mahogany—I want Circassian walnut. He gave
them their flat-silver, too, Puritan design, for an engagement present.
Think of it, mamma, me having that stuck-up Irma<span class="pagenum"><a id="Page_341">[Pg 341]</a></span> Sinsheimer for a
relation! It always made her sore when I got chums with Amy at school
and got my nose in it with the Acme crowd, and—and she'll change her
tune now, I guess, me marrying her husband's second cousin."</p>
<p>"Didn't Lester want to—to come in for a while, Selene, to—to see—me?"</p>
<p>Sitting there on her heels, Miss Coblenz looked away, answering with her
face in profile.</p>
<p>"Yes; only—I—well if you want to know it, mamma, it's no fun for a
girl to bring a boy like Lester up here in—in this crazy room all hung
up with gramaw's wreaths and half the time her sitting out there in the
dark looking in at us through the door and talking to herself."</p>
<p>"Gramaw's an old—"</p>
<p>"Is—it any wonder I'm down at Amy's half the time. How—do you think a
girl feels to have gramaw keep hanging onto that old black wig of hers
and not letting me take the crayons or wreaths down off the wall. In
Lester's crowd, they don't know—nothing about Revolutionary stuff
and—and persecutions. Amy's grandmother don't even talk with an accent,
and Lester says his grandmother came from Alsace-Lorraine. That's
French. They think only tailors and old-clothes men and—"</p>
<p>"Selene!"</p>
<p>"Well, they do. You—you're all right, mamma, as up to date as any of
them, but how do you think a girl feels with gramaw always harping right
in front of everybody the—the way granpa was a revolutionist and
was—was hustled off barefooted to Siberia like—like a tramp. And the
way she was cooking black beans when—my uncle—died. Other girls'
grandmothers don't tell everything they know. Alma Yawitz's grandmother
wears lorgnettes, and you told me yourself they came from nearly the
same part of the Pale as gramaw. But you don't hear them remembering it.
Alma Yawitz says she's Alsace-Lorraine on both sides. People
don't—tell<span class="pagenum"><a id="Page_342">[Pg 342]</a></span> everything they know. Anyway—where a girl's got herself as
far as I have."</p>
<p>Through sobs that rocked her, Mrs. Coblenz looked down upon her
daughter.</p>
<p>"Your poor old grandmother don't deserve that from you! In her day, she
worked her hands to the bone for you. With—the kind of father you had,
we—we might have died in the gutter but—for how she helped to keep us
out, you ungrateful girl—your poor old grandmother that's suffered so
terrible!"</p>
<p>"I know it, mamma, but so have other people suffered."</p>
<p>"She's old, Selene—old."</p>
<p>"I tell you it's the way you indulge her, mamma. I've seen her sitting
here as perk as you please, and the minute you come in the room, down
goes her head like—like she was dying."</p>
<p>"It's her mind, Selene—that's going. That's why I feel if I could only
get her back. She ain't old, gramaw ain't. If I could only get her back
where she—could see for herself—the graves—is all she needs. All old
people think of—the grave. It's eating her—eating her mind. Mark Haas
is going to fix it for me after the war—maybe before—if he can. That's
the only way poor gramaw can live—or die—happy, Selene. Now—now that
my—my little girl ain't any longer my responsibility, I—I'm going to
take her back—my little—girl"—her hand reached out, caressing the
smooth head, her face projected forward and the eyes yearning down—"my
all."</p>
<p>"It's you will be my responsibility now, ma."</p>
<p>"No! No!"</p>
<p>"The first thing Lester says was a flat on Wasserman and a spare room
for mother Coblenz when she wants to come down. Wasn't it sweet for him
to put it that way right off, ma. 'Mother Coblenz,' he says."</p>
<p>"He's a good boy, Selene. It'll be a proud day for<span class="pagenum"><a id="Page_343">[Pg 343]</a></span> me and gramaw.
Gramaw mustn't miss none of it. He's a good boy and a fine family."</p>
<p>"That's why, mamma, we—got to—to do it up right."</p>
<p>"Lester knows, child, he's not marrying a rich girl."</p>
<p>"A girl don't have to—be rich to get married right."</p>
<p>"You'll have as good as mamma can afford to give it to her girl."</p>
<p>"It—it would be different if Lester's uncle and all wasn't in the Acme
Club crowd, and if I hadn't got in with all that bunch. It's the last
expense I'll ever be to you, mamma."</p>
<p>"Oh, baby, don't say that!"</p>
<p>"I—me and Lester—Lester and me were talking, mamma—when the
engagement's announced next week—a reception—"</p>
<p>"We can clear out this room, move the bed out of gramaw's room into
ours, and serve the ice-cream and cake in—"</p>
<p>"Oh, mamma, I don't mean—that!"</p>
<p>"What?"</p>
<p>"Who ever heard of having a reception <i>here</i>! People won't come from
town way out to this old—cabbage patch. Even Gertie Wolf with their big
house on West Pine Boulevard had her reception at the Walsingham Hotel.
You—we—can't expect Mark Haas and all the relations—the
Sinsheimers—and—all to come out here. I'd rather not have any."</p>
<p>"But, Selene, everybody knows we ain't millionaires, and that you got in
with that crowd through being friends at school with Amy Rosen. All the
city salesmen and the boys on Washington Avenue, even Mark Haas himself,
that time he was in the store with Lester, knows the way we live. You
don't need to be ashamed of your little home, Selene, even if it ain't
on West Pine Boulevard."</p>
<p>"It'll be—your last expense, mamma. The Walsingham,<span class="pagenum"><a id="Page_344">[Pg 344]</a></span> that's where the
girl that Lester Goldmark marries is expected to have her reception."</p>
<p>"But, Selene, mamma can't afford nothing like that."</p>
<p>Pink swam up into Miss Coblenz's face, and above the sheer-white collar
there was a little beating movement at the throat, as if something were
fluttering within.</p>
<p>"I—I'd just as soon not get married as—as not to have it like other
girls."</p>
<p>"But, Selene—"</p>
<p>"If I—can't have a trousseau like other girls and the things that go
with marrying into a—a family like Lester's—I—then—there's no use.
I—I can't! I—wouldn't!"</p>
<p>She was fumbling now for a handkerchief against tears that were
imminent.</p>
<p>"Why, baby, a girl couldn't have a finer trousseau than the old linens
back yet from Russia that me and gramaw got saved up for our girl—linen
that can't be bought these days. Bed-sheets that gramaw herself carried
to the border, and—"</p>
<p>"Oh, I know. I knew you'd try to dump that stuff on me. That old
worm-eaten stuff in gramaw's chest."</p>
<p>"It's hand-woven, Selene, with—"</p>
<p>"I wouldn't have that yellow old stuff—that old-fashioned junk—if I
didn't have any trousseau. If I can't afford monogrammed up-to-date
linens, like even Alma Yawitz, and a—a pussy-willow-taffeta reception
dress, I wouldn't have any. I wouldn't." Her voice crowded with passion
and tears rose to the crest of a sob. "I—I'd die first!"</p>
<p>"Selene, Selene, mamma ain't got the money. If she had it, wouldn't she
be willing to take the very last penny to give her girl the kind of a
wedding she wants? A trousseau like Alma's cost a thousand dollars if it
cost a cent. Her table-napkins alone they say cost thirty-six dollars a
dozen, unmonogrammed. A reception at the Walsingham costs two hundred
dollars if it costs a cent.<span class="pagenum"><a id="Page_345">[Pg 345]</a></span> Selene, mamma will make for you every
sacrifice she can afford, but she ain't got the money."</p>
<p>"You—have got the money!"</p>
<p>"So help me God, Selene! You know, with the quarries shut down, what
business has been. You know how—sometimes even to make ends meet, it is
a pinch. You're an ungrateful girl, Selene, to ask what I ain't able to
do for you. A child like you that's been indulged, that I ain't even
asked ever in her life to help a day down in the store. If I had the
money, God knows you should be married in real lace, with the finest
trousseau a girl ever had. But I ain't got the money—I ain't got the
money."</p>
<p>"You have got the money! The book in gramaw's drawer is seven hundred
and forty. I guess I ain't blind. I know a thing or two."</p>
<p>"Why Selene—that's gramaw's—to go back—"</p>
<p>"You mean the bank-book's hers?"</p>
<p>"That's gramaw's to go back—home on. That's the money for me to take
gramaw and her wreaths back home on."</p>
<p>"There you go—talking loony."</p>
<p>"Selene!"</p>
<p>"Well, I'd like to know what else you'd call it, kidding yourself along
like that."</p>
<p>"You—"</p>
<p>"All right. If you think gramaw, with her life all lived, comes first
before me, with all my life to live—all right!"</p>
<p>"Your poor old—"</p>
<p>"It's always been gramaw first in this house, anyway. I couldn't even
have company since I'm grown up because the way she's always allowed
around. Nobody can say I ain't good to gramaw; Lester say it's beautiful
the way I am with her, remembering always to bring the newspapers and
all, but just the same I know when right's right and wrong's wrong. If
my life ain't more<span class="pagenum"><a id="Page_346">[Pg 346]</a></span> important than gramaw's, with hers all lived, all
right. Go ahead!"</p>
<p>"Selene, Selene, ain't it coming to gramaw, after all her years' hard
work helping us that—she should be entitled to go back with her wreaths
for the graves? Ain't she entitled to die with that off her poor old
mind? You bad, ungrateful girl, you, it's coming to a poor old woman
that's suffered as terrible as gramaw that I should find a way to take
her back."</p>
<p>"Take her back. Where—to jail? To prison in Siberia herself—"</p>
<p>"There's a way—"</p>
<p>"You know gramaw's too old to take a trip like that. You know in your
own heart she won't ever see that day. Even before the war, much less
now, there wasn't a chance for her to get passports back there. I don't
say it ain't all right to kid her along, but when it comes to—to
keeping me out of the—the biggest thing that can happen to a girl—when
gramaw wouldn't know the difference if you keep showing her the
bank-book—it ain't right. That's what it ain't. It ain't right!"</p>
<p>In the smallest possible compass, Miss Coblenz crouched now upon the
floor, head down somewhere in her knees, and her curving back racked
with rising sobs.</p>
<p>"Selene—but some day—"</p>
<p>"Some day nothing! A woman like gramaw can't do much more than go
down-town once a year, and then you talk about taking her to Russia! You
can't get in there, I—tell you—no way you try to fix it after—the way
gramaw—had—to leave. Even before the war, Ray Letsky's father couldn't
get back on business. There's nothing for her there even after she gets
there. In thirty years do you think you can find those graves? Do you
know the size of Siberia? No! But I got to pay—I got to pay for
gramaw's nonsense. But I won't. I won't go to Lester, if I can't go
right. I—"</p>
<p>"Baby, don't cry so—for God's sake don't cry so!</p>
<p>"I wish I was dead."<span class="pagenum"><a id="Page_347">[Pg 347]</a></span></p>
<p>"Sh-h-h—you'll wake gramaw."</p>
<p>"I do!"</p>
<p>"O God, help me to do the right thing!"</p>
<p>"If gramaw could understand, she'd be the first one to tell you the
right thing. Anybody would."</p>
<p>"No! No! That little bank-book and its entries are her life—her life."</p>
<p>"She don't need to know, mamma. I'm not asking that. That's the way they
always do with old people to keep them satisfied. Just humor 'em. Ain't
I the one with life before me—ain't I, mamma?"</p>
<p>"O God, show me the way!"</p>
<p>"If there was a chance, you think I'd be spoiling things for gramaw? But
there ain't, mamma—not one."</p>
<p>"I keep hoping if not before, then after the war. With the help of Mark
Haas—"</p>
<p>"With the book in her drawer like always, and the entries changed once
in a while, she'll never know the difference. I swear to God she'll
never know the difference, mamma!"</p>
<p>"Poor gramaw!"</p>
<p>"Mamma, promise me—your little Selene. Promise me?"</p>
<p>"Selene, Selene, can we keep it from her?"</p>
<p>"I swear we can, mamma."</p>
<p>"Poor, poor gramaw!"</p>
<p>"Mamma? Mamma darling?"</p>
<p>"O God, show me the way!"</p>
<p>"Ain't it me that's got life before me? My whole life?"</p>
<p>"Yes—Selene."</p>
<p>"Then, mamma, please—you will—you will—darling?"</p>
<p>"Yes, Selene."</p>
<p> </p>
<p>In a large, all-frescoed, seventy-five dollars an evening with lights
and cloak-room service ballroom of the Hotel Walsingham, a family
hostelry in that family circle of<span class="pagenum"><a id="Page_348">[Pg 348]</a></span> St. Louis known as its West End, the
city holds not a few of its charity-whists and benefit musicales; on a
dais which can be carried in for the purpose, morning readings of
"Little Moments from Little Plays," and with the introduction of a
throne-chair, the monthly lodge-meetings of the Lady Mahadharatas of
America. For weddings and receptions, a lane of red carpet leads up to
the slight dais; and, lined about the brocade and paneled walls,
gilt-and-brocade chairs, with the crest of Walsingham in padded
embroidery on the backs. Crystal chandeliers, icicles of dripping light,
glow down upon a scene of parquet floor, draped velours, and mirrors
wreathed in gilt.</p>
<p>At Miss Selene Coblenz's engagement reception, an event properly
festooned with smilax and properly jostled with the elbowing figures of
waiters tilting their plates of dark-meat chicken salad, two olives, and
a finger-roll in among the crowd, a stringed three-piece orchestra,
faintly seen and still more faintly heard, played into the babel.</p>
<p>Light, glitteringly filtered through the glass prisms, flowed down upon
the dais; upon Miss Selene Coblenz, in a taffeta that wrapped her flat
waist and chest like a calyx and suddenly bloomed into the full inverted
petals of a skirt; upon Mr. Lester Goldmark, his long body barely
knitted yet to man's estate, and his complexion almost clear, standing
omnivorous, omnipotent, omnipresent, his hair so well brushed that it
lay like black japanning, a white carnation at his silk lapel, and his
smile slightly projected by a rush of very white teeth to the very
front. Next in line, Mrs. Coblenz, the red of a fervent moment high in
her face, beneath the maroon-net bodice the swell of her bosom fast, and
her white-gloved hands constantly at the opening and shutting of a
lace-and-spangled fan. Back, and well out of the picture, a potted
hydrangea beside the Louis Quinze armchair, her hands in silk mitts laid
out along the gold-chair sides, her head quavering in a kind of mild
palsy, Mrs. Miriam Horowitz, smiling and quivering her state of
bewilderment.<span class="pagenum"><a id="Page_349">[Pg 349]</a></span></p>
<p>With an unfailing propensity to lay hold of to whomsoever he spake, Mr.
Lester Goldmark placed his white-gloved hand upon the white-gloved arm
of Mrs. Coblenz.</p>
<p>"Say, mother Coblenz, ain't it about time this little girl of mine was
resting her pink-satin double A's? She's been on duty up here from four
to seven. No wonder uncle Mark bucked."</p>
<p>Mrs. Coblenz threw her glance out over the crowded room, surging with a
wave of plumes and clipped heads like a swaying bucket of water which
crowds but does not lap over its sides.</p>
<p>"I guess the crowd is finished coming in by now. You tired, Selene?"</p>
<p>Miss Coblenz turned her glowing glance.</p>
<p>"Tired! This is the swellest engagement-party I ever had."</p>
<p>Mrs. Coblenz shifted her weight from one slipper to the other, her
maroon-net skirts lying in a swirl around them.</p>
<p>"Just look at gramaw, too! She holds up her head with the best of them.
I wouldn't have had her miss this, not for the world."</p>
<p>"Sure one fine old lady! Ought to have seen her shake my hand, mother
Coblenz. I nearly had to holler, 'Ouch!'"</p>
<p>"Mamma, here comes Sara Suss and her mother. Take my arm, Lester honey.
People mamma used to know." Miss Coblenz leaned forward beyond the dais
with the frail curve of a reed.</p>
<p>"Howdado, Mrs. Suss.... Thank you. Thanks. Howdado, Sara. Meet my
<i>fiancé</i>, Lester Haas Goldmark; Mrs. Suss and Sara Suss, my <i>fiancé</i>....
That's right; better late than never. There's plenty left.... We think
he is, Mrs. Suss. Aw, Lester honey, quit! Mamma, here's Mrs. Suss and
Sadie."</p>
<p>"Mrs. Suss! Say—if you hadn't come, I was going to lay it up against
you. If my new ones can come on a day like this, it's a pity my old
friends can't come, too.<span class="pagenum"><a id="Page_350">[Pg 350]</a></span></p>
<p>"Well, Sadie, it's your turn next, eh?... I know better than that. With
them pink cheeks and black eyes, I wish I had a dime for every chance."
(<i>Sotto.</i>) "Do you like it, Mrs. Suss? Pussy-willow taffeta.... Say, it
ought to be. An estimate dress from Madame Murphy—sixty-five with
findings. I'm so mad, Sara, you and your mamma couldn't come to the
house that night to see her things. If I say so myself, Mrs. Suss,
everybody who seen it says Jacob Sinsheimer's daughter herself didn't
have a finer. Maybe not so much, but every stitch, Mrs. Suss, made by
the same sisters in the same convent that made hers.... Towels! I tell
her it's a shame to expose them to the light, much less wipe on them.
Ain't it?... The goodness looks out from his face. And such a love-pair!
Lunatics, I call them. He can't keep his hands off. It ain't nice, I
tell him.... Me? Come close. I dyed the net myself. Ten cents' worth of
maroon color. Don't it warm your heart, Mrs. Suss? This morning, after
we got her in Lester's uncle Mark's big automobile, I says to her, I
says, 'Mamma, you sure it ain't too much.' Like her old self for a
minute, Mrs. Suss, she hit me on the arm. 'Go 'way,' she said, 'on my
grandchild's engagement-day anything should be too much? Here, waiter,
get these two ladies some salad. Good measure, too. Over there by the
window, Mrs. Suss. Help yourselves."</p>
<p>"Mamma, sh-h-h, the waiters know what to do."</p>
<p>Mrs. Coblenz turned back, the flush warm to her face.</p>
<p>"Say, for an old friend, I can be my own self."</p>
<p>"Can we break the receiving-line now, Lester honey, and go down with
everybody? The Sinsheimers and their crowd over there by themselves, we
ought to show we appreciate their coming."</p>
<p>Mr. Goldmark twisted high in his collar, cupping her small bare elbow in
his hand.</p>
<p>"That's what I say, lovey; let's break. Come, mother Coblenz, let's step
down on high society's corns."</p>
<p>"Lester!"<span class="pagenum"><a id="Page_351">[Pg 351]</a></span></p>
<p>"You and Selene go down with the crowd, Lester. I want to take gramaw to
rest for a while before we go home. The manager says we can have room
fifty-six by the elevator for her to rest in."</p>
<p>"Get her some newspapers, ma, and I brought her a wreath down to keep
her quiet. It's wrapped in her shawl."</p>
<p>Her skirts delicately lifted, Miss Coblenz stepped down off the dais.
With her cloud of gauze scarf enveloping her, she was like a
tulle-clouded "Springtime," done in the key of Botticelli.</p>
<p>"Oop-si-lah, lovey-dovey!" said Mr. Goldmark, tilting her elbow for the
downward step.</p>
<p>"Oop-si-lay, dovey-lovey!" said Miss Coblenz, relaxing to the support.</p>
<p>Gathering up her plentiful skirts, Mrs. Coblenz stepped off, too, but
back toward the secluded chair beside the potted hydrangea. A fine line
of pain, like a cord tightening, was binding her head, and she put up
two fingers to each temple, pressing down the throb.</p>
<p>"Mrs. Coblenz, see what I got for you!" She turned, smiling. "You don't
look like you need salad and green ice-cream. You look like you needed
what I wanted—a cup of coffee."</p>
<p>"Aw, Mr. Haas—now where in the world—aw, Mr. Haas!"</p>
<p>With a steaming cup outheld and carefully out of collision with the
crowd, Mr. Haas unflapped a napkin with his free hand, inserting his
foot in the rung of a chair and dragging it toward her.</p>
<p>"Now," he cried, "sit and watch me take care of you!"</p>
<p>There comes a tide in the affairs of men when the years lap softly,
leaving no particular inundations on the celebrated sands of time.
Between forty and fifty, that span of years which begin the first slight
gradations from the apex of life, the gray hair, upstanding like a
thick-bristled brush off Mr. Haas's brow, had not so much as<span class="pagenum"><a id="Page_352">[Pg 352]</a></span> whitened,
or the slight paunchiness enhanced even the moving-over of a button.
When Mr. Haas smiled, his mustache, which ended in a slight but not
waxed flourish, lifted to reveal a white-and-gold smile of the artistry
of careful dentistry, and when, upon occasion, he threw back his head to
laugh, the roof of his mouth was his own.</p>
<p>He smiled now, peering through gold-rimmed spectacles attached by a
chain to a wire-encircled left ear.</p>
<p>"Sit," he cried, "and let me serve you!"</p>
<p>Standing there with a diffidence which she could not crowd down, Mrs.
Coblenz smiled through closed lips that would pull at the corners.</p>
<p>"The idea, Mr. Haas—going to all that trouble!"</p>
<p>"'Trouble,' she says! After two hours hand-shaking in a swallowtail, a
man knows what real trouble is!"</p>
<p>She stirred around and around the cup, supping up spoonfuls gratefully.</p>
<p>"I'm sure much obliged. It touches the right spot."</p>
<p>He pressed her down to the chair, seating himself on the low edge of the
dais.</p>
<p>"Now you sit right here and rest your bones."</p>
<p>"But my mother, Mr. Haas. Before it's time for the ride home, she must
rest in a quiet place."</p>
<p>"My car'll be here and waiting five minutes after I telephone."</p>
<p>"You—sure have been grand, Mr. Haas!"</p>
<p>"I shouldn't be grand yet to my—let's see what relation is it I am to
you?"</p>
<p>"Honest, you're a case, Mr. Haas—always making fun!"</p>
<p>"My poor dead sister's son marries your daughter. That makes you
my—nothing-in-law."</p>
<p>"Honest, Mr. Haas, if I was around you, I'd get fat laughing."</p>
<p>"I wish you was."</p>
<p>"Selene would have fits. 'Never get fat, mamma,' <span class="pagenum"><a id="Page_353">[Pg 353]</a></span>she says, 'if you
don't want——'"</p>
<p>"I don't mean that."</p>
<p>"What?"</p>
<p>"I mean I wish you was around me."</p>
<p>She struck him then with her fan, but the color rose up into the mound
of her carefully piled hair.</p>
<p>"I always say I can see where Lester gets his comical ways. Like his
uncle, that boy keeps us all laughing."</p>
<p>"Gad, look at her blush! I know women your age would give fifty dollars
a blush to do it that way."</p>
<p>She was looking away again, shoulders heaving to silent laughter, the
blush still stinging.</p>
<p>"It's been so—so long, Mr. Haas, since I had compliments made to
me—you make me feel so—silly."</p>
<p>"I know it, you nice, fine woman, you, and it's a darn shame!"</p>
<p>"Mr.—Haas!"</p>
<p>"I mean it. I hate to see a fine woman not get her dues. Anyways, when
she's the finest woman of them all!"</p>
<p>"I—the woman that lives to see a day like this—her daughter the
happiest girl in the world with the finest boy in the world—is getting
her dues all right, Mr. Haas."</p>
<p>"She's a fine girl, but she ain't worth her mother's little finger
nail."</p>
<p>"Mr.—Haas!"</p>
<p>"No, sir-ee!"</p>
<p>"I must be going now, Mr. Haas—my mother—"</p>
<p>"That's right. The minute a man tries to break the ice with this little
lady, it's a freeze-out. Now, what did I say so bad? In business, too.
Never seen the like. It's like trying to swat a fly to come down on you
at the right minute. But now, with you for a nothing-in-law, I got
rights."</p>
<p>"If—you ain't the limit, Mr. Haas!"</p>
<p>"Don't mind saying it, Mrs. C., and, for a bachelor, they tell me I'm
not the worst judge in the world, but there's not a woman on the floor
stacks up like you do."<span class="pagenum"><a id="Page_354">[Pg 354]</a></span></p>
<p>"Well—of all things!"</p>
<p>"Mean it."</p>
<p>"My mother, Mr. Haas, she—"</p>
<p>"And if anybody should ask you if I've got you on my mind or not, well
I've already got the letters out on that little matter of the passports
you spoke to me about. If there's a way to fix that up for you, and
leave it to me to find it, I—"</p>
<p>She sprang now, trembling, to her feet, all the red of the moment
receding.</p>
<p>"Mr. Haas, I—I must go now. My—mother—"</p>
<p>He took her arm, winding her in and out among crowded-out chairs behind
the dais.</p>
<p>"I wish it to every mother to have a daughter like you, Mrs. C."</p>
<p>"No! No!" she said, stumbling rather wildly through the chairs. "No! No!
No!"</p>
<p>He forged ahead, clearing her path of them.</p>
<p>Beside the potted hydrangea, well back and yet within an easy view, Mrs.
Horowitz, her gilt armchair well cushioned for the occasion, and her
black grenadine spread decently about her, looked out upon the scene,
her slightly palsied head well forward.</p>
<p>"Mamma, you got enough? You wouldn't have missed it, eh? A crowd of
people we can be proud to entertain, not? Come; sit quiet in another
room for a while, and then Mr. Haas, with his nice big car, will drive
us all home again. You know Mr. Haas, dearie—Lester's uncle that had us
drove so careful in his fine big car. You remember, dearie—Lester's
uncle?"</p>
<p>Mrs. Horowitz looked up, her old face cracking to smile.</p>
<p>"My grandchild! My grandchild! She'm a fine one. Not? My grandchild! My
grandchild!"</p>
<p>"You—mustn't mind, Mr. Haas. That's—the way she's done since—since
she's—sick. Keeps repeating—"</p>
<p>"My grandchild! From a good mother and a bad<span class="pagenum"><a id="Page_355">[Pg 355]</a></span> father comes a good
grandchild. My grandchild! She'm a good one. My—"</p>
<p>"Mamma, dearie, Mr. Haas is in a hurry. He's come to help me walk you
into a little room to rest before we go home in Mr. Haas's big fine
auto. Where you can go and rest, mamma, and read the newspapers. Come."</p>
<p>"My back—<i>ach</i>—my back!"</p>
<p>"Yes, yes, mamma; we'll fix it. Up! So—la!"</p>
<p>They raised her by the crook of each arm, gently.</p>
<p>"So! Please, Mr. Haas, the pillows. Shawl. There!"</p>
<p>Around a rear hallway, they were almost immediately into a blank,
staring hotel bedroom, fresh towels on the furniture-tops only enhancing
its staleness.</p>
<p>"Here we are. Sit her here, Mr. Haas, in this rocker."</p>
<p>They lowered her almost inch by inch, sliding down pillows against the
chair-back.</p>
<p>"Now, Shila's little mamma, want to sleep?"</p>
<p>"I got—no rest—no rest."</p>
<p>"You're too excited, honey, that's all."</p>
<p>"No rest."</p>
<p>"Here—here's a brand-new hotel Bible on the table, dearie. Shall Shila
read it to you?"</p>
<p>"Aylorff—"</p>
<p>"Now, now, mamma. Now, now; you mustn't! Didn't you promise Shila? Look!
See, here's a wreath wrapped in your shawl for Shila's little mamma to
work on. Plenty of wreaths for us to take back. Work awhile, dearie, and
then we'll get Selene and Lester, and, after all the nice company goes
away, we'll go home in the auto."</p>
<p>"I begged he should keep in his hate—his feet in the——"</p>
<p>"I know! The papers. That's what little mamma wants. Mr. Haas, that's
what she likes better than anything—the evening papers."</p>
<p>"I'll go down and send 'em right up with a boy, and telephone for the
car. The crowd's beginning to pour<span class="pagenum"><a id="Page_356">[Pg 356]</a></span> out now. Just hold your horses
there, Mrs. C., and I'll have those papers up here in a jiffy."</p>
<p>He was already closing the door after him, letting in and shutting out a
flare of music.</p>
<p>"See, mamma, nice Mr. Haas is getting us the papers. Nice evening papers
for Shila's mamma." She leaned down into the recesses of the black
grenadine, withdrawing from one of the pockets a pair of silver-rimmed
spectacles, adjusting them with some difficulty to the nodding head.
"Shila's—little mamma! Shila's mamma!"</p>
<p>"Aylorff, the littlest wreath for—Aylorff—<i>Meine Kräntze</i>—"</p>
<p>"Yes, yes."</p>
<p>"<i>Mein Mann. Mein Sühn.</i>"</p>
<p>"Ssh-h-h, dearie!"</p>
<p>"Aylorff—<i>der klenste Kranz far ihm</i>!"</p>
<p>"Ssh-h-h, dearie—talk English, like Selene wants. Wait till we get on
the ship—the beautiful ship to take us back. Mamma, see out the window!
Look! That's the beautiful Forest Park, and this is the fine Hotel
Walsingham just across—see out—Selene is going to have a flat on—"</p>
<p>"<i>Sey hoben gestorben far Freiheit. Sey hoben</i>—"</p>
<p>"There, that's the papers!"</p>
<p>To a succession of quick knocks, she flew to the door, returning with
the folded evening editions under her arm.</p>
<p>"Now," she cried, unfolding and inserting the first of them into the
quivering hands, "now, a shawl over my little mamma's knees and we're
fixed!"</p>
<p>With a series of rapid movements, she flung open one of the
black-cashmere shawls across the bed, folding it back into a triangle.
Beside the table, bare except for the formal, unthumbed Bible, Mrs.
Horowitz rattled out her paper, her near-sighted eyes traveling back and
forth across the page.</p>
<p>Music from the ferned-in orchestra came in drifts, faint, not so faint.
From somewhere, then immediately<span class="pagenum"><a id="Page_357">[Pg 357]</a></span> from everywhere, beyond, below,
without, the fast shouts of newsboys mingling.</p>
<p>Suddenly and of her own volition, and with a cry that shot up through
the room, rending it like a gash, Mrs. Horowitz, who moved by inches,
sprang to her supreme height, her arms, the crooks forced out, flung up.</p>
<p>"My darlings—what died—for it! My darlings what died for it—my
darlings—Aylorff—my husband!" There was a wail rose up off her words,
like the smoke of incense curling, circling around her. "My darlings
what died to make free!"</p>
<p>"Mamma—darling—mamma—Mr. Haas! Help! Mamma! My God!"</p>
<p>"Aylorff—my husband—I paid with my blood to make free—my blood—my
son—my—own—" Immovable there, her arms flung up and tears so heavy
that they rolled whole from her face down to the black grenadine, she
was as sonorous as the tragic meter of an Alexandrian line; she was like
Ruth, ancestress of heroes and progenitor of kings. "My boy—my
own—they died for it! <i>Mein Mann! Mein Sühn!</i>"</p>
<p>On her knees, frantic to press her down once more into the chair,
terrified at the rigid immobility of the upright figure, Mrs. Coblenz
paused then, too, her clasp falling away, and leaned forward to the open
sheet of the newspaper, its black headlines facing her:</p>
<p class="c">RUSSIA FREE</p>
<p class="c"><span class="smcap">bans down<br>
100,000 siberian prisoners liberated</span>
</p>
<p>In her ears a ringing silence, as if a great steel disk had clattered
down into the depths of her consciousness. There on her knees, trembling
seized her, and she hugged herself against it, leaning forward to
corroborate her gaze.<span class="pagenum"><a id="Page_358">[Pg 358]</a></span></p>
<p class="c"><span class="smcap">most rigid autocracy in the world<br>
overthrown</span></p>
<p class="c">RUSSIA REJOICES</p>
<p>"Mamma! Mamma! My God, Mamma!"</p>
<p>"Home, Shila; home! My husband who died for it—Aylorff! Home now,
quick! My wreaths! My wreaths!"</p>
<p>"O my God, Mamma!"</p>
<p>"Home!"</p>
<p>"Yes—darling—yes—"</p>
<p>"My wreaths!"</p>
<p>"Yes, yes, darling; your wreaths. Let—let me think. Freedom!—O my God,
help me to find a way! O my God!"</p>
<p>"My wreaths!"</p>
<p>"Here—darling—here!"</p>
<p>From the floor beside her, the raffia wreath half in the making, Mrs.
Coblenz reached up, pressing it flat to the heaving old bosom.</p>
<p>"There, darling, there!"</p>
<p>"I paid with my blood—"</p>
<p>"Yes, yes, mamma; you—paid with your blood. Mamma—sit, please. Sit
and—let's try to think. Take it slow, darling—it's like we can't take
it in all at once. I—we—sit down, darling. You'll make yourself
terrible sick. Sit down, darling, you—you're slipping."</p>
<p>"My wreaths—"</p>
<p>Heavily, the arm at the waist gently sustaining, Mrs. Horowitz sank
rather softly down, her eyelids fluttering for the moment. A smile had
come out on her face, and, as her head sank back against the rest, the
eyes resting at the downward flutter, she gave out a long breath, not
taking it in again.</p>
<p>"Mamma! You're fainting!" She leaned to her, shaking the relaxed figure
by the elbows, her face almost touching the tallowlike one with the
smile lying so deeply<span class="pagenum"><a id="Page_359">[Pg 359]</a></span> into it. "Mamma! My God, darling, wake up! I'll
take you back. I'll find a way to take you. I'm a bad girl, darling, but
I'll find a way to take you. I'll take you if—if I kill for it. I
promise before God I'll take you. To-morrow—now—nobody can keep me
from taking you. The wreaths, mamma! Get ready the wreaths! Mamma,
darling, wake up. Get ready the wreaths! The wreaths!" Shaking at that
quiet form, sobs that were full of voice, tearing raw from her throat,
she fell to kissing the sunken face, enclosing it, stroking it, holding
her streaming gaze closely and burningly against the closed lids.
"Mamma, I swear to God I'll take you! Answer me, mamma! The
bank-book—you've got it! Why don't you wake up—mamma? Help!"</p>
<p>Upon that scene, the quiet of the room so raucously lacerated, burst Mr.
Haas, too breathless for voice.</p>
<p>"Mr. Haas my mother—help—my mother! It's a faint, ain't it? A faint?"</p>
<p>He was beside her at two bounds, feeling of the limp wrists, laying his
ear to the grenadine bosom, lifting the reluctant lids, touching the
flesh that yielded so to touch.</p>
<p>"It's a faint, ain't it, Mr. Haas? Tell her I'll take her back. Wake her
up, Mr. Haas! Tell her I'm a bad girl, but I—I'm going to take her
back. Now! Tell her! Tell her, Mr. Haas, I've got the bank-book. Please!
Please! O my God!"</p>
<p>He turned to her, his face working to keep down compassion.</p>
<p>"We must get a doctor, little lady."</p>
<p>She threw out an arm.</p>
<p>"No! No! I see! My old mother—my old mother—all her life a nobody—she
helped—she gave it to them—my mother—a poor little widow nobody—she
bought with her blood that freedom—she—"</p>
<p>"God, I just heard it downstairs—it's the tenth wonder of the world.
It's too big to take in. I was afraid—"<span class="pagenum"><a id="Page_360">[Pg 360]</a></span></p>
<p>"Mamma darling, I tell you, wake up! I'm a bad girl, but I'll take you
back. Tell her, Mr. Haas, I'll take her back. Wake up, darling! I swear
to God—I'll take you!"</p>
<p>"Mrs. Coblenz, my—poor little lady—your mother don't need you to take
her back. She's gone back where—where she wants to be. Look at her
face, little lady; can't you see she's gone back?"</p>
<p>"No! No! Let me go. Let me touch her. No! No! Mamma darling!"</p>
<p>"Why, there wasn't a way, little lady, you could have fixed it for that
poor—old body. She's beyond any of the poor fixings we could do for
her. You never saw her face like that before. Look!"</p>
<p>"The wreaths—- the wreaths!"</p>
<p>He picked up the raffia circle, placing it back again against the quiet
bosom.</p>
<p>"Poor little lady!" he said. "Shila—that's left for us to do. You and
me, Shila—we'll take the wreaths back for her."</p>
<p>"My darling—my darling mother! I'll take them back for you! I'll take
them back for you!"</p>
<p>"<i>We'll</i> take them back for her—Shila."</p>
<p>"I'll—"</p>
<p>"<i>We'll</i> take them back for her—Shila."</p>
<p>"<i>We'll</i> take them back for you, mamma. We'll take them back for you,
darling!"<span class="pagenum"><a id="Page_361">[Pg 361]</a></span></p>
