        <h2><a id="THE_EMPEROR_OF_ELAM"></a>THE EMPEROR OF ELAM<a id="FNanchor_8_8"></a><a class="fnanchor pginternal" href="#Footnote_8_8">[8]</a></h2>
<p class="c"><span class="smcap">By</span> H. G. DWIGHT</p>
<p class="c">From <i>The Century Magazine</i>.</p>
<div class="blockquot2">
<p><i>I returned, and saw under the sun, that the race is not to the swift,
nor the battle to the strong, neither yet bread to the wise, nor yet
riches to men of understanding, nor yet favour to men of skill; but time
and chance happeneth to them all.</i></p>
<p class="r"><i>Ecclesiastes</i>, ix, 11.</p>
