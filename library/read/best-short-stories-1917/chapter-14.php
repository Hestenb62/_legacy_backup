        <h2><a id="THE_BUNKER_MOUSE12"></a>THE BUNKER MOUSE<a id="FNanchor_12_12"></a><a class="fnanchor pginternal" href="#Footnote_12_12">[12]</a></h2>
<p class="c">By FREDERICK STUART GREENE</p>
<p class="c">From <i>The Century Magazine</i></p>
<p><span class="smcap">Larry Walsh</span> slowly climbed the stairs of a house near the waterfront, in
a run-down quarter of old New York. He halted on the top floor, blinking
in the dim light that struggled through the grime-coated window of the
hallway. After a time he knocked timidly on the door before him.</p>
<p>There was nothing in the pleasant "Come in" to alarm the small man; he
started to retreat, but stopped when the door was thrown wide.</p>
<p>"Then it's yourself, Mouse! It's good for the eyes just to look at you."</p>
<p>The woman who greeted Walsh was in striking contrast to her shabby
surroundings. Everything about the old-fashioned house, one floor of
which was her home, spoke of neglected age. This girl, from the heavy,
black braids encircling her head to the soles of her shoes, vibrated
youth. Her cheeks glowed with the color of splendid health; her blue
Irish eyes were bright with it. Friendliness had rung in the tones of
her rich brogue, and showed now in her smile as she waited for her
visitor to answer.</p>
<p>Larry stood before her too shy to speak.</p>
<p>"Is it word from Dan you're bringin' me?" she encouraged. "But there,
now, I'm forgettin' me manners! Come in, an' I'll be makin' you a cup of
tea." She took<span class="pagenum"><a id="Page_284">[Pg 284]</a></span> his arm impulsively, with the frank comradeship of a
young woman for a man much older than herself, and led him to a chair.</p>
<p>Larry sat ready for flight, his cap held stiffly across his knees. He
watched every movement of the girl, a look of pathetic meekness in his
eyes.</p>
<p>"You're right, Mrs. Sullivan," he said after an effort; "Dan was askin'
me to step in on my way to the ship."</p>
<p>She turned quickly from the stove.</p>
<p>"You're not tellin' me now Dan ain't comin' himself, an' the boat
leavin' this night?"</p>
<p>Larry was plainly uneasy.</p>
<p>"Well, you see—it's—now it's just like I'm tellin' you, Mrs. Sullivan;
he's that important to the chief, is Dan, they can't get on without him
to-day at all."</p>
<p>"Then bad luck, I say, to the chief! Look at the grand supper I'm after
fixin' for Dan!"</p>
<p>"Oh, Mary—Mrs. Sullivan, don't be speakin' disrespectful' of the chief,
an' him thinkin' so highly of Dan!"</p>
<p>Mary's blue eyes flashed.</p>
<p>"An' why wouldn't he! It's not every day he'll find the likes of Dan,
with the strong arms an' the great legs of him, not to mention his grand
looks." She crossed to Larry, her face aglow. "Rest easy now while you
drink your tea," she urged kindly, "an' tell me what the chief be
wantin' him for."</p>
<p>She drew her chair close to Larry, but the small man turned shyly from
her searching gaze.</p>
<p>"Well, you see, Mrs.—"</p>
<p>"Call me Mary. It's a year an' more now since the first time you brought
Dan home to me." A sudden smile lighted her face. "Well I remember how
frightened you looked when first you set eyes on me. Was you thinkin' to
find Dan's wife a slip of a girl?"</p>
<p>"No; he told me you was a fine, big lass." He looked from Mary to the
picture of an older woman that hung above the mantel. "That'll be your
mother, I'm<span class="pagenum"><a id="Page_285">[Pg 285]</a></span> thinkin'." Then, with abrupt change, "When did you leave
the old country, Mary?"</p>
<p>"A little more'n a year before I married Dan. But tell me, Mouse, about
the chief wantin' him."</p>
<p>"We'll you see, Dan's that handy-like—"</p>
<p>"That's the blessed truth you're speakin'," she interupted, her face
lovely with its flush of pride. "But tell me more, that's a darlin'."</p>
<p>Larry thought rapidly before he spoke again.</p>
<p>"Only the last trip I was hearin' the chief say: 'Dan,' says he, 'it's
not long now you'll be swingin' the shovel. I'll be makin' you
water-tender soon.'"</p>
<p>Mary leaned nearer, and caught both of Larry's hands in hers.</p>
<p>"Them's grand words you're sayin'; they fair makes my heart jump." She
paused; the gladness faded quickly from her look. "Then the chief don't
know Dan sometimes takes a drop?"</p>
<p>"Ain't the chief Irish himself? Every man on the boilers takes his
dram." Her wistful eyes spurred him on. "Sure's I'm sittin' here, Dan's
the soberest of the lot."</p>
<p>Mary shook her head sadly.</p>
<p>"Good reason I have to fear the drink; 't was that spoiled my mother's
life."</p>
<p>Larry rose quickly.</p>
<p>"Your mother never drank!"</p>
<p>"No; the saints preserve us!" She looked up in surprise at Larry's
startled face. "It was my father. I don't remember only what mother told
me; he left her one night, ravin' drunk, an' never come back."</p>
<p>Larry hastily took up his cap.</p>
<p>"I must be goin' back to the ship now," he said abruptly. "An' thank
you, Mary, for the tea." He hurried from the room.</p>
<p>When Larry reached the ground floor he heard Mary's door open again.</p>
<p>"Can I be troublin' you, Mouse, to take something to<span class="pagenum"><a id="Page_286">[Pg 286]</a></span> Dan?" She came
down the stairs, carrying a dinner-pail. "I'd thought to be eatin' this
supper along with him," Mary said, disappointment in her tone. She
followed Larry to the outer landing. "It's the true word you was sayin',
he'll be makin' Dan water-tender?"</p>
<p>Larry forced himself to look into her anxious eyes.</p>
<p>"Sure; it's just as I said, Mary."</p>
<p>"Then I'll pray this night to the Mother of God for that chief; for
soon"—Mary hesitated; a light came to her face that lifted the girl
high above her squalid surroundings—"the extra pay'll be comin' handy
soon," she ended, her voice as soft as a Killarney breeze.</p>
<p>Larry, as he looked at the young wife standing between the scarred
columns of the old doorway, was stirred to the farthest corner of his
heart.</p>
<p>"They only smile like that to the angels," he thought. Then aloud: "Bad
cess to me! I was forgettin' entirely! Dan said to leave this with you."
He pushed crumpled, coal-soiled money into her hand, and fled down the
steps.</p>
<p>When Larry heard the door close creakily behind him, he looked back to
where Mary had stood, his eyes blinking rapidly. After some moments he
walked slowly on toward the wharves. In the distance before him the
spars and funnels of ships loomed through the dusk, their outlines
rapidly fading into the sky beyond—a late September sky, now fast
turning to a burned-out sheet of dull gray.</p>
<p>Larry went aboard his ship, and, going to the forecastle, peered into an
upper bunk.</p>
<p>"Your baby's not to home, Mouse," a voice jeered. "I saw him over to
Flanagan's awhile ago."</p>
<p>A hopeless look crossed Larry's face.</p>
<p>"Give me a hand up the side, like a good lad, Jim, when I come aboard
again."</p>
<p>A few minutes later the little man was making his way back to the
steamer, every step of his journey harassed by derisive shouts as he
dodged between the lines<span class="pagenum"><a id="Page_287">[Pg 287]</a></span> of belated trucks that jammed West Street from
curb to string-piece. He pushed a wheelbarrow before him, his knees
bending under the load it held. Across the barrow, legs and head
dangling over the sides, lay an unconscious heap that when sober
answered to the name of Dan Sullivan.</p>
<p> </p>
<p>Larry Walsh, stoker on the coastwise freighter <i>San Gardo</i>, was the butt
of the ship; every man of the crew imposed on his good nature. He was
one of those persons "just fool enough to do what he's told to do." For
thirty of his fifty years he had been a seaman, and the marks of a
sailor's life were stamped hard on his face. His weathered cheeks were
plowed by wrinkles that stretched, deep furrowed, from his red-gray hair
to the corners of his mouth. From under scant brows he peered out on the
world with near-sighted eyes; but whenever a smile broadened his wide
mouth, his eyes would shine with a kindly light.</p>
<p>Larry's defective sight had led to his banishment as a sailor from the
decks. During a storm off Hatteras a stoker had fallen and died on the
boiler-room plates.</p>
<p>"It don't take no eyes at all to see clean to the back of a Scotch
boiler," the boatswain had told the chief engineer. "I can give you that
little squint-eyed feller." So, at the age of forty or thereabouts,
Larry left the cool, wind-swept deck to take up work new to him in the
superheated, gas-stifling air of the fire-room. Though entered on the
ship's papers as a sailor, he had gone without complaint down the
straight ladders to the very bottom of the hull. Bidden to take the dead
stoker's place, "he was just fool enough to do what he was told to do."</p>
<p>Larry was made the coal-passer of that watch, and began at once the
back-breaking task of shoveling fuel from the bunkers to the floor
outside, ready for the stokers to heave into the boilers. He had been
passing less than an hour during his first watch when the coal<span class="pagenum"><a id="Page_288">[Pg 288]</a></span> ran
short in the lower bunker. He speared with a slice-bar in the bunker
above. The fuel rested at a steeper angle than his weak eyes could see,
and his bar dislodged a wedged lump; an instant later the new passer was
half buried under a heap of sliding coal. Bewildered, but unhurt, he
crawled to the boiler-room, shaking the coal from his back and
shoulders. Through dust-filled ears he heard the general laugh at his
plight.</p>
<p>"Look at the nigger Irishman!" a stoker called.</p>
<p>"Irishman!" came the answer. "It's no man at all; it's a mouse you're
seein'—a bunker mouse."</p>
<p>From that moment the name Larry Walsh was forgotten.</p>
<p> </p>
<p>The <i>San Gardo</i> was late getting away that night; two bells of the
evening watch had sounded when at last she backed from her pier into the
North River and began the first mile of her trip to Galveston. Though
she showed a full six inches of the red paint below her water-line, the
loading of her freight had caused the delay. In the hold lay many parts
of sawmill machinery. When the last of this clumsy cargo had settled to
its allotted place, there was left an unusual void of empty blackness
below the deck hatches.</p>
<p>"It's up to you now, Matie," the stevedore had said to the impatient
first officer. "My job's done right, but she'll roll her sticks out if
it's rough outside."</p>
<p>"That's nice; hand me all the cheerful news you have when you know they
hung out storm-warnings at noon," the officer had growled as the
stevedore went ashore.</p>
<p>Signs that both the Government and the stevedore had predicted correctly
began to show as soon as the vessel cleared the Hook. The wind was
blowing half a gale from the southeast and had already kicked up a
troublesome sea. The ship, resenting her half-filled hold, pitched with
a viciousness new to the crew.</p>
<p>There was unusual activity on board the <i>San Gardo</i> that night. Long
after the last hatch-cover had been<span class="pagenum"><a id="Page_289">[Pg 289]</a></span> placed the boatswain continued to
inspect, going over the deck from bow to stern to see that every movable
thing was lashed fast.</p>
<p>In the engine-room as well, extra precautions were taken. It was Robert
Neville's watch below; he was the first of the three assistant
engineers. Neville, a young man, was unique in that most undemocratic
institution, a ship's crew, for he apparently considered the stokers
under him as human beings. For one of his fire-room force he had an
actual liking.</p>
<p>"Why do you keep that fellow they call Bunker Mouse in your watch?" the
chief once asked.</p>
<p>"Because he's willing and the handiest man I have," Neville answered
promptly.</p>
<p>"Well, suit yourself; but that brute Sullivan will kill him some day, I
hear."</p>
<p>"I don't know about that, Chief. The Mouse is game."</p>
<p>"So's a trout; but it's got a damn poor show against a shark," the chief
had added with a shrug.</p>
<p>Neville's watch went on duty shortly after the twin lights above Sandy
Hook had dropped astern. The ship was then rolling heavily enough to
make walking difficult on the oily floor of the engine-room; in the
boiler-room, lower by three feet, to stand steady even for a moment was
impossible. Here, in this badly lighted quarter of the ship, ill humor
hung in the air thicker than the coal-gas.</p>
<p>Dan Sullivan, partly sobered, fired his boiler, showing ugly readiness
for a fight. Larry, stoking next to him, kept a weather-eye constantly
on his fellow-laborer.</p>
<p>Neville's men had been on duty only a few minutes when the engineer came
to the end of the passage and called Larry.</p>
<p>"That's right," Dan growled; "run along, you engineer's pet, leavin'
your work for me to do!"</p>
<p>Larry gave him no answer as he hurried away.</p>
<p>"Make fast any loose thing you see here," Neville ordered.<span class="pagenum"><a id="Page_290">[Pg 290]</a></span></p>
<p>Larry went about the machinery-crowded room securing every object that a
lurching ship might send flying from its place. When he returned to the
fire-room he heard the water-tender shouting:</p>
<p>"Sullivan, you're loafin' on your job! Get more fire under that boiler!"</p>
<p>"An' ain't I doin' double work, with that damn Mouse forever sneakin' up
to the engine-room?"</p>
<p>Larry, giving no sign that he had heard Dan's growling answer, drove his
scoop into the coal, and with a swinging thrust spread its heaped load
evenly over the glowing bed in the fire-box. He closed the fire-door
with a quick slam, for in a pitching boiler-room burning coal can fall
from an open furnace as suddenly as new coal can be thrown into it.</p>
<p>"So, you're back," Dan sneered. "It's a wonder you wouldn't stay the
watch up there with your betters."</p>
<p>Larry went silently on with his work.</p>
<p>"Soft, ain't it, you jellyfish, havin' me do your job? You eel, you—."
Dan poured out a stream of abusive oaths.</p>
<p>Still Larry did not answer.</p>
<p>"Dan's ravin' mad," a man on the port boilers said. "Will he soak the
Mouse to-night, I wonder."</p>
<p>"Sure," the stoker beside him answered. "An' it's a dirty shame for a
big devil like him to smash the little un."</p>
<p>"You're new on this ship; you don't know 'em. The Mouse is a regular
mother to that booze-fighter, an' small thanks he gets. But wait, an'
you'll see somethin' in a minute."</p>
<p>Dan's temper, however, was not yet at fighting heat. He glared a moment
longer at Larry, then turned sullenly to his boiler. He was none too
steady on his legs, and this, with the lurching of the ship, made his
work ragged. After a few slipshod passes he struck the door-frame
squarely with his scoop, spilling the coal to the floor.</p>
<p>"Damn your squint eyes!" he yelled. "You done<span class="pagenum"><a id="Page_291">[Pg 291]</a></span> that, Mouse! You shoved
ag'in' me. Now scrape it all up, an' be quick about it!"</p>
<p>Without a word, while his tormentor jeered and cursed him, Larry did as
he was told.</p>
<p>"Ain't you got no fight at all in your shriveled-up body?" Dan taunted
as Larry finished. "You're a disgrace to Ireland, that's what you are."</p>
<p>Larry, still patient, turned away. Dan sprang to him and spun the little
man about.</p>
<p>"Where's the tongue in your ugly mouth?" Dan was shaking with rage.
"I'll not be havin' the likes of you followin' me from ship to ship, an'
sniffin' at my heels ashore. I won't stand for it no longer, do you
hear? Do you think I need a nurse? Now say you'll leave this ship when
we makes port, or I'll break every bone in you."</p>
<p>Dan towered above Larry, his arm drawn back ready to strike. Every man
in the room stopped work to watch the outcome of the row.</p>
<p>At the beginning of the tirade Larry's thin shoulders had straightened;
he raised his head; his lower jaw, undershot, was set hard. The light
from the boiler showed his near-sighted eyes steady on Sullivan,
unafraid.</p>
<p>"Get on with your work, an' don't be a fool, Dan," he said quietly.</p>
<p>"A fool, am I!"</p>
<p>Dan's knotted fist flashed to within an inch of Larry's jaw. The Bunker
Mouse did not flinch. For a moment the big stoker's arm quivered to
strike, then slowly fell.</p>
<p>"You ain't worth smashin'," Sullivan snarled, and turned away.</p>
<p>"Well, what d'yer know about that!" the new stoker cried.</p>
<p>"It's that way all the time," he was answered; "there ain't a trip Dan
don't ball the Mouse out to a fare-you-well; but he never lays hand to
'im. None of us knows why."</p>
<p>"You don't? Well, I do. The big slob's yeller, an'<span class="pagenum"><a id="Page_292">[Pg 292]</a></span> I'll show 'im up."
The stoker crossed to Sullivan. "See here, Bo, why don't you take on a
man your size?" He thrust his face close to Dan's and shouted the answer
to his question: "I'll tell you why. You ain't got sand enough."</p>
<p>Dan's teeth snapped closed, then parted to grin at his challenger.</p>
<p>"Do you think you're big enough?" The joy of battle was in his growl.</p>
<p>"Yes, I do." The man put up his hands.</p>
<p>Instantly Dan's left broke down the guard; his right fist landed
squarely on the stoker's jaw, sending him reeling to the bunker wall,
where he fell. It was a clean knock-out.</p>
<p>"Go douse your friend with a pail of water, Mouse." Dan, still grinning,
picked up his shovel and went to work.</p>
<p> </p>
<p>When Neville's watch went off duty, Larry found the sea no rougher than
on countless other runs he had made along the Atlantic coast. The wind
had freshened to a strong gale, but he reached the forecastle with no
great difficulty.</p>
<p>Without marked change the <i>San Gardo</i> carried the same heavy weather
from Barnegat Light to the Virginia capes. Beyond Cape Henry the blow
began to stiffen and increased every hour as the freighter plowed
steadily southward. Bucking head seas every mile of the way, she picked
up Diamond Shoals four hours behind schedule. As she plunged past the
tossing light-ship, Larry, squinting through a forecastle port, wondered
how long its anchor chains would hold. The <i>San Gardo</i> was off Jupiter
by noon the third day out, running down the Florida coast; the wind-bent
palms showed faintly through the driving spray.</p>
<p>Neville's watch went on duty that night at eight. As his men left the
forecastle a driving rain beat against their backs, and seas broke over
the port bow at every<span class="pagenum"><a id="Page_293">[Pg 293]</a></span> downward plunge of the ship. To gain the
fire-room door, they clung to rail or stanchion to save themselves from
being swept overboard. They held on desperately as each wave flooded the
deck, watched their chance, then sprang for the next support. On
freighters no cargo space is wasted below decks in passageways for the
crew.</p>
<p>When Larry reached the fire-room there was not a dry inch of cloth
covering his wiry body. He and his fellow-stokers took up immediately
the work of the men they had relieved, and during the first hours of
their watch fired the boilers with no more difficulty than is usual in
heavy weather.</p>
<p>At eleven o'clock the speaking-tube whistled, and a moment later Neville
came to the end of the passage.</p>
<p>"What are you carrying?" he shouted to the water-tender. "We've got to
keep a full head of steam on her to-night."</p>
<p>"We've got it, Mr. Neville—one hundred and sixty, an' we've held
between that and sixty-five ever since I've been on."</p>
<p>"The captain says we've made Tortugas. We lost three hours on the run
from Jupiter," Neville answered, and went back to his engine.</p>
<p>During the next hour no one on deck had to tell these men, toiling far
below the water-line, that wind and sea had risen. They had warnings
enough. Within their steel-incased quarters every bolt and rivet sounded
the overstrain forced upon it. In the engine-room the oiler could no
longer move from the throttle. Every few minutes now, despite his
watchfulness, a jarring shiver spread through the hull as the propeller,
thrown high, raced wildly in mid-air before he could shut off steam.</p>
<p>At eleven-thirty the indicator clanged, and its arrow jumped to
half-speed ahead. A moment later the men below decks "felt the rudder"
as the <i>San Gardo</i>, abandoning further attempts to hold her course,
swung about to meet the seas head on.</p>
<p>Eight bells—midnight—struck, marking the end of<span class="pagenum"><a id="Page_294">[Pg 294]</a></span> the shift; but no one
came down the ladders to relieve Neville's watch. The growls of the
tired men rose above the noise in the fire-room. Again Neville came
through the passage.</p>
<p>"The tube to the bridge is out of commission," he called, "but I can
raise the chief. He says no man can live on deck; one's gone overboard
already. The second watch can't get out of the forecastle. It's up to
us, men, to keep this ship afloat, and steam's the only thing that'll do
it."</p>
<p>For the next hour and the next the fire-room force and the two men in
the engine-room stuck doggedly to their work. They knew that the <i>San
Gardo</i> was making a desperate struggle, that it was touch and go whether
the ship would live out the hurricane or sink to the bottom. They knew
also, to the last man of them, that if for a moment the ship fell off
broadside to the seas, the giant waves would roll her over and over like
an empty barrel in a mill-race. The groaning of every rib and plate in
the hull, the crash of seas against the sides, the thunder of waves
breaking on deck, drowned the usual noises below.</p>
<p>The color of the men's courage began to show. Some kept grimly at their
work, dumb from fear. Others covered fright with profanity, cursing the
storm, the ship, their mates, cursing themselves. Larry, as he threw
coal steadily through his fire-doors, hummed a broken tune. He gave no
heed to Dan, who grew more savage as the slow hours of overtoil dragged
by.</p>
<p>About four in the morning Neville called Larry to the engine-room. On
his return Dan blazed out at him:</p>
<p>"Boot-lickin' Neville ag'in, was you? I'd lay you out, you shrimp, only
I want you to do your work."</p>
<p>Larry took up his shovel; as usual his silence enraged Sullivan.</p>
<p>"You chicken-livered wharf-rat, ain't you got no spunk to answer wid?"
Dan jerked a slice-bar from the fire and hurled it to the floor at
Larry's feet. The little man<span class="pagenum"><a id="Page_295">[Pg 295]</a></span> leaped in the air; the white-hot end of
the bar, bounding from the floor, missed his legs by an inch.</p>
<p>Larry's jaw shot out; he turned on Sullivan, all meekness gone.</p>
<p>"Dan," he cried shrilly, "if you try that again—"</p>
<p>"Great God! what's that!"</p>
<p>Dan's eyes were staring; panic showed on every face in the room. The
sound of an explosion had come from the forward hold. Another followed,
and another, a broadside of deafening reports. The terrifying sounds
came racing aft. They reached the bulkhead nearest them, and tore
through the fire-room, bringing unmasked fear to every man of the watch.
The crew stood for a moment awed, then broke, and, rushing for the
ladder, fought for a chance to escape this new, unknown madness of the
storm.</p>
<p>Only Larry kept his head.</p>
<p>"Stop! Come back!" His shrill voice carried above the terrifying noise.
"It's the plates bucklin' between the ribs."</p>
<p>"Plates! Hell! she's breakin' up!"</p>
<p>Neville rushed in from the engine-room.</p>
<p>"Back to your fires, men, or we'll all drown! Steam, keep up—" He was
shouting at full-lung power, but his cries were cut short. Again the
deafening reports started at the bows. Again, crash after crash, the
sounds came tearing aft as if a machine-gun were raking the vessel from
bow to stern. At any time these noises would bring terror to men locked
below decks; but now, in the half-filled cargo spaces, each crashing
report was like the bursting of a ten-inch shell.</p>
<p>Neville went among the watch, urging, commanding, assuring them that
these sounds meant no real danger to the ship. He finally ended the
panic by beating the more frightened ones back to their boilers.</p>
<p>Then for hours, at every plunge of the ship, the deafening boom of
buckling plates continued until the watch was crazed by the sound.<span class="pagenum"><a id="Page_296">[Pg 296]</a></span></p>
<p>This new terror began between four and five in the morning, when the men
had served double time under the grueling strain. At sunrise another
misery was added to their torture: the rain increased suddenly, and fell
a steady cataract to the decks. This deluge and the flying spray sent
gallons of water down the stack; striking the breeching-plates, it was
instantly turned to steam and boiling water. As the fagged stokers bent
before the boilers, the hot water, dripping from the breeching, washed
scalding channels through the coal-dust down their bare backs. They
hailed this new torment with louder curses, but continued to endure it
for hours, while outside the hurricane raged, no end, no limit, to its
power.</p>
<p>Since the beginning of the watch the bilge-pumps had had all they could
do to handle the leakage coming from the seams of the strained hull.
Twice Neville had taken the throttle and sent his oiler to clear the
suctions. The violent lurching of the ship had churned up every ounce of
sediment that had lain undisturbed beneath the floor-plates since the
vessel's launching. Sometime between seven and eight all the bilge-pumps
clogged at the same moment, and the water began rising at a rate that
threatened the fires. It became a question of minutes between life and
death for all hands. Neville, working frantically to clear the pumps,
yelled to the oiler to leave the throttle and come to him. The water,
gaining fast, showed him that their combined efforts were hopeless. He
ran to the boiler-room for more aid. Here the water had risen almost to
the fires; as the ship rolled, it slushed up between the floor-plates
and ran in oily streams about the men's feet. Again panic seized the
crew.</p>
<p>"Come on, lads!" Sullivan shouted above the infernal din. "We'll be
drowned in this hell-hole!"</p>
<p>In the next second he was half-way up the ladder, below him, clinging to
the rungs like frightened apes, hung other stokers.<span class="pagenum"><a id="Page_297">[Pg 297]</a></span></p>
<p>"Come back, you fool!" Neville shouted. "Open that deck-door, and you'll
swamp the ship!"</p>
<p>Dan continued to climb.</p>
<p>"Come down or I'll fire!"</p>
<p>"Shoot an' be damned to you!" Dan called back.</p>
<p>The report of Neville's revolver was lost in the noise; but the bullet,
purposely sent high, spattered against the steel plate above Dan's head.
He looked down. Neville, swaying with the pitching floor, was aiming
true for his second shot. Cursing at the top of his voice, Dan scrambled
down the ladder, pushing the men below him to the floor.</p>
<p>"Back to your boilers!" Neville ordered; but the stokers, huddled in a
frightened group, refused to leave the ladder.</p>
<p>It was only a matter of seconds now before the fires would be drenched.
Bilge-water was splashing against the under boiler-plates, filling the
room with dense steam. Neville left the men and raced for the
engine-room. He found Larry and the oiler working desperately at the
valve-wheel of the circulating pump. Neville grasped the wheel, and gave
the best he had to open the valve. This manifold, connecting the pump
with the bilges, was intended only for emergency use. It had not been
opened for months, and was now rusted tight. The three men, straining
every muscle, failed to budge the wheel. After the third hopeless
attempt, Larry let go, and without a word bolted through the passage to
the fire-room.</p>
<p>"You miserable quitter!" Neville screamed after him, and bent again to
the wheel.</p>
<p>As he looked up, despairing of any chance to loosen the rusted valve,
Larry came back on the run, carrying a coal-pick handle. He thrust it
between the spokes of the wheel.</p>
<p>"Now, Mr. Neville, all together!" His Celtic jaw was set hard.<span class="pagenum"><a id="Page_298">[Pg 298]</a></span></p>
<p>All three threw their weight against the handle. The wheel stirred.</p>
<p>As they straightened for another effort, a louder noise of hissing steam
sounded from the boilers, and the fire-room force, mad with fright, came
crowding through the passage to the higher floor of the engine-room.</p>
<p>"Quick! Together!" Neville gasped.</p>
<p>The wheel moved an inch.</p>
<p>"Once more! <i>Now!</i>"</p>
<p>The wheel turned and did not stop. The three men dropped the lever,
seized the wheel, and threw the valve wide open.</p>
<p>"Good work, men!" Neville cried, and fell back exhausted.</p>
<p>The centrifugal pump was thrown in at the last desperate moment. When
the rusted valve finally opened, water had risen to the lower grate-bars
under every boiler in the fire-room. But once in action, the twelve-inch
suction of the giant pump did its work with magic swiftness. In less
than thirty seconds the last gallon of water in the bilges had been
lifted and sent, rushing through the discharge, overboard.</p>
<p>Neville faced the boiler-room crew sternly.</p>
<p>"Now, you cowards, get to your fires!" he said.</p>
<p>As the men slunk back through the passage Dan growled:</p>
<p>"May that man some day burn in hell!"</p>
<p>"Don't be wishin' him no such luck," an angry voice answered; "wish him
down here wid us."</p>
<p> </p>
<p>The morning dragged past; noon came, marking the sixteenth hour that the
men, imprisoned below the sea-swept decks, had struggled to save the
ship. Sundown followed, and the second night of their unbroken toil
began. They stuck to it, stood up somehow under the racking grind, their
nerves quivering, their bodies craving food, their eyes gritty from the
urge of sleep, while always the hideous noises of the gale screamed in
their<span class="pagenum"><a id="Page_299">[Pg 299]</a></span> ears. The machine-gun roar of buckling plates, raking battered
hull, never ceased.</p>
<p>With each crawling minute the men grew more silent, more desperate. Dan
Sullivan let no chance pass to vent his spleen on Larry. Twice during
the day his fellow-stokers, watching the familiar scene, saw the big man
reach the point of crushing the small one; but the ever-expected blow
did not fall.</p>
<p>Shortly after midnight the first hope came to the exhausted men that
their fight might not be in vain. Though the buckling plates still
thundered, though the floor under their feet still pitched at crazy
angles, there was a "feel" in the fire-room that ribs and beams and
rivets were not so near the breaking-point.</p>
<p>Neville came to the end of the passage.</p>
<p>"The hurricane's blowing itself to death," he shouted. "Stick to it,
boys, for an hour longer; the second watch can reach us by then."</p>
<p>The hour passed, but no relief came. The wind had lost some force, but
the seas still broke over the bows, pouring tons of water to the deck.
The vessel pitched as high, rolled as deep, as before.</p>
<p>As the men fired their boilers they rested the filled scoops on the
floor and waited for the ship to roll down. Then a quick jerk of the
fire-door chain, a quick heave of the shovel, and the door was snapped
shut before the floor rolled up again. Making one of these hurried
passes, Larry swayed on tired legs. He managed the toss and was able to
close the door before he fell hard against Dan. His sullen enemy
instantly launched a new tirade, fiercer, more blasphemous, than any
before. He ended a stream of oaths, and rested the scoop ready for his
throw.</p>
<p>"I'll learn yuh, yuh snivelin'—" The ship rolled deep. Dan jerked the
fire-door open—"yuh snivelin' shrimp!" He glared at Larry as he made
the pass. He missed the opening. His shovel struck hard against the
boiler front. The jar knocked Dan to the floor, pitched that<span class="pagenum"><a id="Page_300">[Pg 300]</a></span> moment at
its steepest angle. He clutched desperately to gain a hold on the
smooth-worn steel plates, his face distorted by fear as he slid down to
the fire.</p>
<p>Larry, crying a shrill warning, sprang between Sullivan and the open
furnace. He stooped, and with all the strength he could gather shoved
the big stoker from danger. Then above the crashing sounds a shriek tore
the steam-clouded air of the fire-room. Larry had fallen!</p>
<p>As his feet struck the ash-door, the ship rolled up. A cascade falling
from Dan's fire had buried Larry's legs to the knees under a bed of
white-hot coals. He shrieked again the cry of the mortally hurt as Dan
dragged him too late from before the open door.</p>
<p>"Mouse! Mouse!" Horror throbbed in Sullivan's voice. "You're hurted
bad!" He knelt, holding Larry in his arms, while others threw water on
the blazing coals.</p>
<p>"Speak, lad!" Dan pleaded. "Speak to me!"</p>
<p>The fire-room force stood over them silenced. Accident, death even, they
always expected; but to see Dan Sullivan show pity for any living thing,
and above all, for the Bunker Mouse—</p>
<p>The lines of Larry's tortured face eased.</p>
<p>"It's the last hurt I'll be havin', Dan," he said before he fainted.</p>
<p>"Don't speak the word, Mouse, an' you just after savin' me life!" Then
the men in the fire-room saw a miracle: tears filled the big stoker's
eyes.</p>
<p>Neville had heard Larry's cry and rushed to the boiler-room.</p>
<p>"For God's sake! what's happened now?"</p>
<p>Dan pointed a shaking finger. Neville looked once at what only a moment
before had been the legs and feet of a man. As he turned quickly from
the sight the engineer's face was like chalk.</p>
<p>"Here, two of you," he called unsteadily, "carry him to the
engine-room."<span class="pagenum"><a id="Page_301">[Pg 301]</a></span></p>
<p>Dan threw the men roughly aside.</p>
<p>"Leave him be," he growled. "Don't a one of you put hand on him!" He
lifted Larry gently and, careful of each step, crossed the swaying
floor.</p>
<p>"Lay him there by the dynamo," Neville ordered when they had reached the
engine-room.</p>
<p>Dan hesitated.</p>
<p>"'T ain't fittin', sir, an' him so bad' hurt. Let me be takin' him to
the store-room."</p>
<p>Neville looked doubtfully up the narrow stairs.</p>
<p>"We can't get him there with this sea running."</p>
<p>Sullivan spread his legs wide, took both of Larry's wrists in one hand,
and swung the unconscious man across his back. He strode to the iron
stairs and began to climb. As he reached the first grating Larry
groaned. Dan stopped dead; near him the great cross-heads were plunging
steadily up and down.</p>
<p>"God, Mr. Neville, did he hit ag'in' somethin'?" The sweat of strain and
fear covered his face.</p>
<p>The vessel leaped to the crest of a wave, and dropped sheer into the
trough beyond.</p>
<p>"No; but for God's sake, man, go on! You'll pitch with him to the floor
if she does that again!"</p>
<p>Dan, clinging to the rail with his free hand, began climbing the second
flight.</p>
<p>At the top grating Neville sprang past him to the store-room door.</p>
<p>"Hold him a second longer," he called, and spread an armful of cotton
waste on the vise bench.</p>
<p>Dan laid Larry on the bench. He straightened his own great body for a
moment, then sat down on the floor and cried.</p>
<p>Neville, pretending not to see Dan's distress, brought more waste. As he
placed it beneath his head Larry groaned. Dan, still on the floor, wrung
his hands, calling on the saints and the Virgin to lighten the pain of
this man it had been his joy to torture.</p>
<p>Neville turned to him.<span class="pagenum"><a id="Page_302">[Pg 302]</a></span></p>
<p>"Get up from there!" he cried sharply. "Go see what you can find to help
him."</p>
<p>Dan left the room, rubbing his red-flanneled arm across his eyes. He
returned quickly with a can of cylinder oil, and poured it slowly over
the horribly burned limbs.</p>
<p>"There ain't no bandages, sir; only this." He held out a shirt belonging
to the engineer; his eyes pleaded his question. Neville nodded, and Dan
tore the shirt in strips. When he finished the task, strange to his
clumsy hands, Larry had regained consciousness and lay trying pitifully
to stifle his moans.</p>
<p>"Does it make you feel aisier, Mouse?" Dan leaned close to the quivering
lips to catch the answer.</p>
<p>"It helps fine," Larry answered, and fainted again.</p>
<p>"You'll be leavin' me stay wid him, sir?" Dan begged. "'T was for me
he's come to this."</p>
<p>Neville gave consent and left the two men together.</p>
<p> </p>
<p>Between four and five in the morning, when Neville's watch had lived
through thirty-three unbroken hours of the fearful grind, a shout that
ended in a screaming laugh ran through the fire-room. High above the
toil-crazed men a door had opened and closed. A form, seen dimly through
the smoke and steam, was moving backward down the ladder. Again the door
opened; another man came through. Every shovel in the room fell to the
steel floor; every man in the room shouted or laughed or cried.</p>
<p>The engine-room door, too, had opened, admitting the chief and his
assistant. Not until he had examined each mechanical tragedy below did
the chief give time to the human one above.</p>
<p>"Where's that man that's hurt?" he asked as he came, slowly, from an
inspection of the burned-out bearings down the shaft alley.</p>
<p>Neville went with him to the store-room.<span class="pagenum"><a id="Page_303">[Pg 303]</a></span> Dan, sagging under fatigue,
clung to the bench where Larry lay moaning.</p>
<p>"You can go now, Sullivan," Neville told him.</p>
<p>Dan raised his head, remorse, entreaty, stubbornness in his look.</p>
<p>"Let me be! I'll not leave him!"</p>
<p>The chief turned to Neville.</p>
<p>"What's come over that drunk?" he asked.</p>
<p>"Ever since the Mouse got hurt, Sullivan's acted queer, just like a
woman."</p>
<p>"Get to your quarters, Sullivan," the chief ordered. "We'll take care of
this man."</p>
<p>Dan's hands closed; for an instant he glared rebellion from blood-shot
eyes. Then the iron law of sea discipline conquering, he turned to
Larry.</p>
<p>"The Blessed Virgin aise you, poor Mouse!" he mumbled huskily and
slouched out through the door.</p>
<p> </p>
<p>At midday the <i>San Gardo's</i> captain got a shot at the sun. Though his
vessel had been headed steadily northeast for more than thirty hours,
the observation showed that she had made twenty-eight miles sternway to
the southwest. By two in the afternoon the wind had dropped to half a
gale, making a change of course possible. The captain signaled full
speed ahead, and the ship, swinging about, began limping across the
gulf, headed once more toward Galveston.</p>
<p>Neville, who had slept like a stone, came on deck just before sunset.
The piled-up seas, racing along the side, had lost their breaking
crests; the ship rose and fell with some degree of regularity. He called
the boatswain and went to the store-room.</p>
<p>They found Larry in one of his conscious moments.</p>
<p>"Well, Mouse, we're going to fix you in a better place," the engineer
called with what heart he could show.</p>
<p>"Thank you kindly, sir," Larry managed to answer;<span class="pagenum"><a id="Page_304">[Pg 304]</a></span> "but 't is my last
voyage, Mr. Neville." And the grit that lay hidden in the man's soul
showed in his pain-twisted smile.</p>
<p>They carried him up the last flight of iron stairs to the deck. Clear of
the engine-room, the boatswain turned toward the bow.</p>
<p>"No. The other way, Boson," Neville ordered.</p>
<p>The chief, passing them, stopped.</p>
<p>"Where are you taking him, Mr. Neville?"</p>
<p>"The poor fellow's dying, sir," Neville answered in a low voice.</p>
<p>"Well, where are you taking him?" the chief persisted.</p>
<p>"I'd like to put him in my room, sir."</p>
<p>"A stoker in officers' quarters!" The chief frowned. "Sunday-school
discipline!" He disappeared through the engine-room door, slamming it
after him.</p>
<p>They did what they could, these seamen, for the injured man; on
freighters one of the crew has no business to get hurt. They laid Larry
in Neville's berth and went out, leaving a sailor to watch over him.</p>
<p>The sun rose the next day in a cloudless sky, and shone on a brilliant
sea of tumbling, white-capped waves. Far off the starboard bow floated a
thin line of smoke from a tug's funnel, the first sign to the crew since
the hurricane that the world was not swept clean of ships. Two hours
later the tug was standing by, her captain hailing the <i>San Gardo</i>
through a megaphone.</p>
<p>"Run in to New Orleans!" he shouted.</p>
<p>"I cleared for Galveston, and I'm going there," the <i>San Gardo's</i>
captain called back.</p>
<p>"No, you ain't neither."</p>
<p>"I'd like to know why, I won't."</p>
<p>"Because you can't,"—the answer carried distinctly across the
waves,—"there ain't no such place. It's been washed clean off the
earth."</p>
<p>The <i>San Gardo</i> swung farther to the west and with<span class="pagenum"><a id="Page_305">[Pg 305]</a></span> her engine pounding
at every stroke, limped on toward the Mississippi.</p>
<p>At five o'clock a Port Eads pilot climbed over the side, and taking the
vessel through South Pass, straightened her in the smooth, yellow waters
of the great river for the hundred-mile run to New Orleans.</p>
<p>When the sun hung low over the sugar plantations that stretch in flat
miles to the east and west beyond the levees, when all was quiet on land
and water and ship, Neville walked slowly to the forecastle.</p>
<p>"Sullivan," he called, "come with me."</p>
<p>Dan climbed down from his bunk and came to the door; the big stoker
searched Neville's face with a changed, sobered look.</p>
<p>"I've been wantin' all this time to go to 'im. How's he now, sir?"</p>
<p>"He's dying, Sullivan, and has asked for you."</p>
<p>Outside Neville's quarters Dan took off his cap and went quietly into
the room.</p>
<p>Larry lay with closed eyes, his face ominously white.</p>
<p>Dan crept clumsily to the berth and put his big hand on Larry's
shoulder.</p>
<p>"It's me, Mouse. They wouldn't leave me come no sooner."</p>
<p>Larry's head moved slightly; his faded eyes opened.</p>
<p>Dan stooped in awkward embarrassment until his face was close to Larry.</p>
<p>"I come to ask you—" Dan stopped. The muscles of his thick neck moved
jerkily—"to ask you, Mouse, before—to forgit the damn mean things—I
done to you, Mouse."</p>
<p>Larry made no answer; he kept his failing sight fixed on Dan.</p>
<p>After a long wait Sullivan spoke again.</p>
<p>"An' to think you done it, Mouse, for me!"</p>
<p>A light sprang to Larry's eyes, flooding his near-sighted gaze with
sudden anger.<span class="pagenum"><a id="Page_306">[Pg 306]</a></span></p>
<p>"For you!" The cry came from his narrow chest with jarring force. "You!
<i>You!</i>" he repeated in rising voice. "It's always of yourself you're
thinkin', Dan Sullivan!" He stopped, his face twitching in pain; then
with both hands clenched he went on, his breast heaving at each word
hurled at Dan:</p>
<p>"Do you think I followed you from ship to ship, dragged you out of every
rum-hole in every port, for your own sake!"</p>
<p>He lay back exhausted, his chest rising and falling painfully, his
eyelids fluttering over his burning eyes.</p>
<p>Dan stepped back, and, silenced, stared at the dying man.</p>
<p>Larry clung to his last moments of life, fighting for strength to
finish. He struggled, and raised himself on one elbow.</p>
<p>"For you!" he screamed. "No, for Mary! For Mary, my own flesh and
blood—Mary, the child of the woman I beat when I was drunk an' left to
starve when I got ready!"</p>
<p>Through the stateroom door the sun's flat rays struck full on Larry's
inspired face. He swayed on his elbow; his head fell forward. By a final
effort he steadied himself. His last words came in ringing command.</p>
<p>"Go back! Go—" he faltered, gasping for breath—"go home sober to Mary
an' the child that's comin'!"</p>
<p>The fire of anger drifted slowly from Larry's dying gaze. The little man
fell back. The Bunker Mouse went out, all man, big at the end.<span class="pagenum"><a id="Page_307">[Pg 307]</a></span></p>
