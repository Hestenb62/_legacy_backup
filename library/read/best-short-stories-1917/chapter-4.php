        <h2><a id="THE_EXCURSION"></a>THE EXCURSION<a id="FNanchor_2_2"></a><a class="fnanchor pginternal" href="#Footnote_2_2">[2]</a></h2>
<p class="c"><span class="smcap">By</span> EDWINA STANTON BABCOCK</p>
<p class="c">From <i>The Pictorial Review</i></p>
<p>Mrs. Tuttle arrived breathless, bearing a large gilt parrot-cage. She
swept up the gangway of the <i>Fall of Rome</i> and was enthusiastically
received. There were, however, concealed titterings and suppressed
whispers. "My sakes! She's went and brought that bird."</p>
<p>"I won't believe it till I see it."</p>
<p>"There he sets in his gold coop."</p>
<p>Mrs. Turtle brought Romeo to the excursion with the same assurance that
a woman of another stamp brings her Pekingese dog to a restaurant table.
While the <i>Fall of Rome</i> sounded a warning whistle, and hawsers were
loosed she adjusted her veil and took cognizance of fellow passengers.</p>
<p>In spite of wealth and "owning her own automobile," Mrs. Turtle's fetish
was democratic popularity. She greeted one after another.</p>
<p>"How do, Mis' Bridge, and Mister, too! Who's keeping store while you're
away?</p>
<p>"Carrie Turpin! You here? Where's Si? Couldn't come? Now that's too
bad!" After a long stare, "You're some fleshier, ain't you, Carrie?"</p>
<p>A large woman in a tan-colored linen duster came slowly down the deck, a
camp-stool in either hand. Her portly advance was intercepted by Mrs.
Tuttle.<span class="pagenum"><a id="Page_2">[Pg 2]</a></span></p>
<p>"Mis' Tinneray! Same as ever!"</p>
<p>Mrs. Tinneray dropped the camp-stools and adjusted her smoked glasses;
she gave a start and the two ladies embraced.</p>
<p>Mrs. Tuttle said that "it beat all," and Mrs. Tinneray said "she never!"</p>
<p>Mrs. Tuttle, emerged from the embrace, re-adjusting her hat with
many-ringed fingers, inquiring, "How's the folks?"</p>
<p>Up lumbered Mr. Tinneray, a large man with a chuckle and pale eyes, who
was introduced by the well-known formula, "Mis' Tuttle, Mr. Tinneray,
Mr. Tinneray, Mis' Tuttle."</p>
<p>The Tinnerays said, "So you brought the bird along, hey?" Then, without
warning, all conversation ceased. The <i>Fall of Rome</i>, steaming slowly
away from the pier, whistled a sodden whistle, the flags flapped, every
one realized that the excursion had really begun.</p>
<p>This excursion was one of the frank displays of human hopes, yearnings,
and vanities, that sometimes take place on steamboats. Feathers had a
hectic brilliancy that proved secret, dumb longings. Pendants known as
"lavaleers" hung from necks otherwise innocent of the costly fopperies
of Versailles. Old ladies clad in princess dresses with yachting caps
worn rakishly on their grey hair, vied with other old ladies in
automobile bonnets, who, with opera glasses, searched out the meaning of
every passing buoy. Young girls carrying "mesh-bags," that subtle
connotation of the feminine character, extracted tooth-picks from them
or searched for bits of chewing gum among their over scented treasures.</p>
<p>As it was an excursion, the <i>Fall of Rome</i> carried a band and booths
laden with many delicious superfluities such as pop-corn and the
misleading compound known as "salt-water taffy." There were, besides,
the blue and red pennants that always go on excursions, and the yellow
and pink fly-flappers that always come home from them; also there were
stacks of whistle-whips and slender<span class="pagenum"><a id="Page_3">[Pg 3]</a></span> canes with ivory heads with little
holes pierced through. These canes were bought only by cynical young men
whose new straw hats were fastened to their persons by thin black
strings. Each young man, after purchasing an ivory-headed cane retired
to privacy to squint through it undisturbed. Emerging from this privacy
the young man would then confer with other young men. What these joyless
young men saw when they squinted they never revealed. But among their
elders they spread the strong impression that it was the Capital at
Washington or Bunker Hill Monument.</p>
<p>Besides bottled soda and all soft drinks the <i>Fall of Rome</i> carried
other stimuli in the shape of comic gentlemen—such beings, as, more or
less depressed in their own proper environment, on excursions suddenly
see themselves in their true light, irresistibly facetious. These funny
gentlemen, mostly husbands, seated themselves near to large groups of
indulgent women and kept up an exquisite banter directed at each other's
personal defects, or upon the idiosyncrasies of any bachelor or spinster
near. These funny gentlemen kept alluding to the excursion as the
"Exertion." If the boat rolled a little they said, "Now, Mother, don't
rock the boat."</p>
<p>"Here, girls, sit up close, we'll all go down together."</p>
<p>"Hold on to yer beau, Minnie. He'll fall overboard and where'll you git
another?"</p>
<p>The peals of laughter at these sallies were unfailing. The crunch of
peanuts was unfailing. The band, with a sort of plethoric indulgence,
played slow waltzes in which the bass instruments frequently misapplied
notes, but to the allure of which came youthful dancers lovely in proud
awkward poses.</p>
<p>Mrs. Tuttle meanwhile was the social center, demonstrating that
mysterious psychic force known as being the "life of the party." She
advanced upon a tall sallow woman in mourning, challenging, "Now Mis'
Mealer, why don't you just set and take a little comfort,<span class="pagenum"><a id="Page_4">[Pg 4]</a></span> it won't cost
you nothing? Ain't that your girl over there by the coffee fountain? I
should ha' known her by the reesemblance to you; she's rill refined
lookin'."</p>
<p>Mrs. Mealer, a tall, sallow widow with carefully maintained mourning
visage, admitted that this was so. Refinement, she averred, was in the
family, but she hinted at some obscure ailment which, while it made Emma
refined, kept her "mizzable."</p>
<p>"I brought her along," sighed Mrs. Mealer, "tain't as if neither of us
could take much pleasure into it, both of us being so deep in black fer
her Popper, but the styles is bound to do her good. Emma is such a great
hand for style."</p>
<p>"Yuess?" replied Mrs. Tuttle blandly. This lady in blue was not nearly
so interested in Emma as in keeping a circle of admirers hanging around
her cerulean presence, but even slightly encouraged, Mrs. Mealer warmed
to her topic.</p>
<p>"Style?" she repeated impressively, "style? Seems like Emma couldn't
never have enough of it. Where she got it I don't know. I wasn't never
much for dress, and give her Popper coat and pants, twuz all <i>he</i>
wanted. But Emma—ef you want to make her happy tie a bow onto suthin'."</p>
<p>Mrs. Tuttle nodded with ostentatious understanding. Rising, she seized
Romeo's cage and placed it more conspicuously near her. She was
critically watched by the older women. They viewed the thing with
mingled feelings, one or two going so far as to murmur darkly, "Her and
her parrot!"</p>
<p>Still, the lady's elegance and the known fact that she owned and
operated her own automobile cast a spell over most of her observers, and
many faces, as Mrs. Tuttle proceeded to draw out her pet, were screwed
into watchful and ingratiating benevolence.</p>
<p>Romeo, a blasé bird with the air of having bitter memories, affected for
a long time not to hear his mistress's blandishments. After looking
contemptuously<span class="pagenum"><a id="Page_5">[Pg 5]</a></span> into his seed-cup, he crept slowly around the sides of
his cage, fixing a cynical eye upon all observers.</p>
<p>"How goes it, Romeo?" appealed Mrs. Tuttle. Making sounds supposed to be
appreciated by birds, the lady put her feathered head down, suggesting,
"Ah there, Romeo?"</p>
<p>"Rubberneck," returned Romeo sullenly. To show general scorn, the bird
revolved on one claw round and round his swing; he looked dangerous,
repeating, "Rubberneck."</p>
<p>At this an interested group gathered around Mrs. Tuttle, who, affable
and indulgent, attempted by coaxings and flirtings of a fat bediamonded
finger to show Romeo off, but the pampered bird saw further opportunity
to offend.</p>
<p>"Rubberneck," screamed Romeo again. He ruffled up his neck feathers,
repeating "Rubberneck, I'm cold as the deuce; what's the matter with
Hannah; let 'em all go to grass."</p>
<p>Several of the youths with ivory-headed canes now forsook their
contemplations to draw near, grinning, to the parrot-cage.</p>
<p>Stimulated by these youths, Romeo reeled off more ribald remarks, things
that created a sudden chill among the passengers on the <i>Fall of Rome</i>.
Mrs. Tinneray, looked upon as a leader, called up a shocked face and
walked away; Mrs. Mealer after a faint "Excuse <i>me</i>," also abandoned the
parrot-cage; and Mrs. Bean, a small stout woman with a brown false
front, followed the large lady with blue spectacles and the tan linen
duster. On some mysterious pretext of washing their hands, these two
left the upper deck and sought the calm of the white and gold passenger
saloon. Here they trod as in the very sanctities of luxury.</p>
<p>"These carpets is nice, ain't they?" remarked Mrs. Bean.</p>
<p>Then alluding to the scene they had just left: "Ain't it comical how she
idolizes that there bird?"<span class="pagenum"><a id="Page_6">[Pg 6]</a></span></p>
<p>Mrs. Tinneray sniffed. "And what she spends on him! 'Nitials on his
seed-cup—and some says the cage itself is true gold."</p>
<p>Mrs. Bean, preparing to wash her hands, removed her black skirt and
pinned a towel around her waist. "This here liquid soap is
nice"—turning the faucets gingerly—"and don't the boat set good onto
the water?" Then returning to the rich topic of Mrs. Tuttle and her
pampered bird, "Where's she get all her money for her ottermobile and
her gold cage?"</p>
<p>Mrs. Tinneray at an adjacent basin raised her head sharply, "You ain't
heard about the Tuttle money? You don't know how Mabel Hutch that was,
was hair to everything?"</p>
<p>Mrs. Bean confessed that she had not heard, but she made it evident that
she thirsted for information. So the two ladies, exchanging remarks
about sunburn and freckles, finished their hand-washing and proceeded to
the dark-green plush seats of the saloon, where with appropriate looks
of horror and incredulity Mrs. Bean listened to the story of the hairs
to the Hutches' money.</p>
<p>"Mabel was the favorite; her Pa set great store by her. There was
another sister—consumpted—she should have been a hair, but she died.
Then the youngest one, Hetty, she married my second cousin Hen
Cronney—well it seemed like they hadn't nothing but bad luck and her Pa
and Mabel sort of took against Hetty."</p>
<p>Mrs. Bean, herself chewing calculatingly, handed Mrs. Tinneray a bit of
sugared calamus-root.</p>
<p>"Is your cousin Hen dark-complexioned like your folks?" she asked
scientifically.</p>
<p>Mrs. Tinneray, narrowing both eyes, considered. "More auburn-inclined, I
should say—he ain't rill smart, Hen ain't, he gets took with spells now
and then, but I never held <i>that</i> against him."</p>
<p>"Uh-huh!" agreed Mrs. Bean sympathetically.</p>
<p>"Well, then, Mabel Hutch and her Popper took against poor little Hetty.
Old man Hutch he died and<span class="pagenum"><a id="Page_7">[Pg 7]</a></span> left everything to Mabel, and she never goes
near her own sister!"</p>
<p>Mrs. Bean raised gray-cotton gloved hands signifying horror.</p>
<p>"St—st—st——!" she deplored. She searched in her reticule for more
calamus-root. "He didn't leave her <i>nothing</i>?"</p>
<p>"No, ma'am! This one!" With a jerk of the head, Mrs. Tinneray indicated
a dashing blue feather seen through a distant saloon window. "This one's
got it all; hair to everything."</p>
<p>"And what did she do—married a traveling salesman and built a tony
brick house. They never had no children, but when he was killed into a
railway accident she trimmed up that parrot's cage with crape—and
now,"—Mrs. Tinneray with increasing solemnity chewed her
calamus-root—"<i>now</i> she's been and bought one of them ottermobiles and
runs it herself like you'd run your sewin'-machine, just as
<i>shameless</i>—"</p>
<p>Both of the ladies glared condemnation at the distant blue feather.</p>
<p>Mrs. Tinneray continued, "Hetty Cronney's worth a dozen of her. When I
think of that there bird goin' on this excursion and Hetty Cronney
stayin' home because she's too poor, I get <i>nesty</i>, Mrs. Bean, yes, I
do!"</p>
<p>"Don't your cousin Hetty live over to Chadwick's Harbor," inquired Mrs.
Bean, "and don't this boat-ride stop there to take on more folks?"</p>
<p>Mrs. Tinneray, acknowledging that these things were so, uncorked a small
bottle of cologne and poured a little of it on a handkerchief
embroidered in black forget-me-nots. She handed the bottle to Mrs. Bean
who took three polite sniffs and closed her eyes. The two ladies sat
silent for a moment. They experienced a detachment of luxurious abandon
filled with the poetry of the steamboat saloon. Psychically they were
affected as by ecclesiasticism. The perfume of the cologne and the throb
of the engines swept them with a sense of esthetic<span class="pagenum"><a id="Page_8">[Pg 8]</a></span> reverie, the thrill
of travel, and the atmosphere of elegance. Moreover, the story of the
Hutch money and the Hutch hairs had in some undefined way affiliated the
two. At last by tacit consent they rose, went out on deck and, holding
their reticules tight, walked majestically up and down. When they passed
Mrs. Turtle's blue feathers and the gold parrot-cage they smiled
meaningly and looked at each other.</p>
<p> </p>
<p>As the <i>Fall of Rome</i> approached Chadwick's Landing more intimate groups
formed. The air was mild, the sun warm and inviting, and the water an
obvious and understandable blue. Some serious-minded excursionists sat
well forward on their camp-stools discussing deep topics over
half-skinned bananas.</p>
<p>"Give me the Vote," a lady in a purple raincoat was saying, "Give me the
Vote and I undertake to close up every rum-hole in God's World."</p>
<p>A mild-mannered youth with no chin, upon hearing this, edged away. He
went to the stern, looking down for a long time upon the white path of
foam left in the wake of the <i>Fall of Rome</i> and taking a harmonica from
his waistcoat pocket began to play, "Darling, I Am Growing Old." This
tune, played with emotional throbbings managed by spasmodic movements of
the hands over the sides of the mouth, seemed to convey anything but age
to Miss Mealer, the girl who was so refined. She also sat alone in the
stern, also staring down at the white water. As the wailings of the
harmonica ceased, she put up a thin hand and furtively controlled some
waving strands of hair. Suddenly with scarlet face the mild-mannered
youth moved up his camp-stool to her side.</p>
<p>"They're talkin' about closing up the rum-holes." He indicated the group
dominated by the lady in the purple raincoat. "They don't know what
they're talking about. Some rum-holes is real refined and tasty, some of
them have got gramophones you can hear for nothin'."</p>
<p>"Is that so?" responded the refined Miss Mealer.<span class="pagenum"><a id="Page_9">[Pg 9]</a></span> She smoothed her
gloves. She opened her "mesh" bag and took out an intensely perfumed
handkerchief. The mild-mannered youth put his harmonica in his pocket
and warmed to the topic.</p>
<p>"Many's the time I've set into a saloon listening to that Lady that
sings high up—higher than any piano can go. I've set and listened till
I didn't know where I was settin'—of course I had to buy a drink, you
understand, or I couldn't 'a' set."</p>
<p>"And they call that <i>vice</i>," remarked Miss Mealer with languid
criticism.</p>
<p>The mild-mannered youth looked at her gratefully. The light of reason
and philosophy seemed to him to shine in her eyes.</p>
<p>"You've got a piano to your house," he said boldly, "can you—ahem—play
classic pieces, can you play—ahem—'Asleep on the Deep'?"</p>
<p>In another group where substantial sandwiches were being eaten, the main
theme was religion and psychic phenomena with a strong leaning toward
death-bed experiences.</p>
<p>"And then, my sister's mother-in-law, she set up, and she says, 'Where
am I?' she says, like she was in a store or somethin', and she told how
she seen all white before her eyes and all like gentlemen in high silk
hats walkin' around."</p>
<p>There were sighs of comprehension, gasps of dolorous interest.</p>
<p>"The same with my Christopher!"</p>
<p>"Just like my aunt's step-sister afore she went!"</p>
<p>Mrs. Tuttle did not favor the grave character of these symposia.</p>
<p>With the assured manner peculiar to her, she swept into such circles
bearing a round box of candy, upon which was tied a large bow of satin
ribbon of a convivial shade of heliotrope. Opening this box she handed
it about, commanding, "Help yourself."</p>
<p>At first it was considered refined to refuse. One or<span class="pagenum"><a id="Page_10">[Pg 10]</a></span> two excursionists,
awed by the superfluity of heliotrope ribbon, said feebly, "Don't rob
yourself."</p>
<p>But Mrs. Tuttle met this restraint with practised raillery. "What you
all afraid of? It ain't poisoned! I got more where this come from." She
turned to the younger people. "Come one, come all! It's French-mixed."</p>
<p>Meanwhile Mrs. Bean and Mrs. Tinneray, still aloof and enigmatic, paced
the deck. Mrs. Tuttle, blue feathers streaming, teetered on her high
heels in their direction. Again she proffered the box. One of the
cynical youths with the ivory-headed canes was following her, demanding
that the parrot be fed a caramel. Once more the sky-blue figure bent
over the ornate cage; then little Mrs. Bean looked at Mrs. Tinneray with
a gesture of utter repudiation.</p>
<p>"Ain't she <i>terrible</i>?"</p>
<p>As the steamboat approached the wharf and the dwarf pines and yellow
sand-banks of Chadwick's Landing, a whispered consultation between these
two ladies resulted in one desperate attempt to probe the heart of Mabel
Hutch that was. Drawing camp-stools up near the vicinity of the parrot's
cage, they began with what might to a suspicious nature have seemed
rather pointed speculation, to wonder who might or might not be at the
wharf when the <i>Fall of Rome</i> got in.</p>
<p>Once more the bottle of cologne was produced and handkerchiefs genteelly
dampened. Mrs. Bean, taking off her green glasses, polished them and
held them up to the light, explaining, "This here sea air makes 'em all
of a muck."</p>
<p>Suddenly she leaned over to Mrs. Tuttle with an air of sympathetic
interest.</p>
<p>"I suppose—er—your sister Hetty'll be comin' on board when we get to
Chadwick's Landing—her and her husband?"</p>
<p>Mrs. Tuttle fidgeted. She covered Romeo's cage with a curious
arrangement like an altar-cloth on which gay<span class="pagenum"><a id="Page_11">[Pg 11]</a></span> embroidered parrakeets of
all colors were supposed to give Romeo, when lonely, a feeling of
congenial companionship.</p>
<p>Mrs. Bean, thus evaded, screwed up her eyes tight, then opened them wide
at Mrs. Tinneray, who sat rigid, her gaze riveted upon far-off horizons,
humming between long sighs a favorite hymn. Finally, however, the
last-named lady leaned past Mrs. Bean and touched Mrs. Turtle's silken
knee, volunteering,</p>
<p>"Your sister Hetty likes the water, I know. You remember them days, Mis'
Tuttle, when we all went bathin' together down to old Chadwick's Harbor,
afore they built the new wharf?"</p>
<p>Mrs. Tinneray continued reminiscently.</p>
<p>"You remember them old dresses we wore—no classy bathin'-suits
then—but my—the mornings used to smell good! That path to the shore
was all wild roses and we used to find blueberries in them woods. Us
girls was always teasin' Hetty, her bathin'-dress was white muslin and
when it was wet it stuck to her all over, she showed through—my, how
we'd laugh, but yet for all," concluded Mrs. Tinneray sentimentally,
"she looked lovely—just like a little wet angel."</p>
<p>Mrs. Tuttle carefully smoothed her blue mitts, observing nervously,
"Funny how Mis' Tinneray could remember so far back."</p>
<p>"Is Hetty your sister by rights," suavely inquired Mrs. Bean, "or ony by
your Pa's second marriage, as it were?"</p>
<p>The owner of the overestimated parrot roused herself.</p>
<p>"By rights," she admitted indifferently, "I don't see much of her—she
married beneath her."</p>
<p>The tip of Mrs. Tinneray's nose, either from cologne inhalings or
sunburn, grew suddenly scarlet. However she still regarded the far-off
horizons and repeated the last stanza of her hymn, which stanza, sung
with much quavering and sighing was a statement to the effect that Mrs.
Tinneray would "cling to the old rugged cross."<span class="pagenum"><a id="Page_12">[Pg 12]</a></span> Suddenly, however, she
remarked to the surrounding Summer air,</p>
<p><i>"Hen Cronney is my second cousin on the mother's side. Some thought he
was pretty smart until troubles come and his wife was done out of her
rights.</i>"</p>
<p>The shaft, carefully aimed, went straight into Mrs. Turtle's blue bosom
and stuck there. Her eyes, not overintelligent, turned once in her
complacent face, then with an air of grandiose detachment, she occupied
herself with the ends of her sky-blue automobile veil.</p>
<p>"I'll have to fix this different," she remarked unconcernedly, "or else
my waves'll come out. Well, I presume we'll soon be there. I better go
down-stairs and primp up some." The high heels clattered away. Mrs. Bean
fixed a long look of horror on Mrs. Tinneray, who silently turned her
eyes up to heaven!</p>
<p>As the <i>Fall of Rome</i> churned its way up to the sunny wharf of
Chadwick's Landing, the groups already on the excursion bristled with
excitement. Children were prepared to meet indulgent grandparents,
lovers their sweethearts, and married couples old school friends they
had not seen for years. From time to time these admonished their
offspring.</p>
<p>"Hypatia Smith, you're draggin' your pink sash, leave Mommer fix it.
There now, don't you dare to set down so Grammer can see you lookin'
good."</p>
<p>"Lionel Jones, you throw that old pop-corn overboard. Do you want to eat
it after you've had it on the floor?"</p>
<p>"Does your stomach hurt you, dear? Well, here don't cry Mommer'll give
you another cruller."</p>
<p>With much shouting of jocular advice from the male passengers the <i>Fall
of Rome</i> was warped into Chadwick's Landing and the waiting groups came
aboard. As they streamed on, bearing bundles and boxes and all the
impedimenta of excursions, those already on board congregated on the
after-deck to distinguish familiar faces. A few persons had come down to
the landing merely to look upon the embarkation.<span class="pagenum"><a id="Page_13">[Pg 13]</a></span></p>
<p>These, not going themselves on the excursion, maintained an air of
benevolent superiority that could not conceal vivid curiosity. Among
them, eagerly scanning the faces on deck was a very small thin woman
clad in a gingham dress, on her head a battered straw hat of accentuated
by-gone mode, and an empty provision-basket swinging on her arm. Mrs.
Tinneray peering down on her through smoked glasses, suddenly started
violently. "My sakes," she ejaculated, "my sakes," then as the dramatic
significance of the thing gripped her, "My—my—my, ain't that
<i>terrible</i>?"</p>
<p>Solemnly, with prunella portentousness, Mrs. Tinneray stole back of the
other passengers leaning over the rail up to Mrs. Bean, who turned to
her animatedly, exclaiming,</p>
<p>"They've got a new schoolhouse. I can just see the cupola—there's some
changes since I was here. They tell me there's a flag sidewalk in front
of the Methodist church and that young Baxter the express agent has
growed a mustache, and's got married."</p>
<p>Mrs. Tinneray did not answer. She laid a compelling hand on Mrs. Bean's
shoulder and turned her so that she looked straight at the small group
of home-stayers down on the wharf. She pointed a sepulchral finger,</p>
<p>"<i>That there, in the brown with the basket, is Hetty Cronney, own sister
to Mis' Josiah Tuttle.</i>"</p>
<p>Mrs. Bean clutched her reticule and leaned over the rail, gasping with
interest.</p>
<p>"Ye don't say—that's her? My! My! My!"</p>
<p>In solemn silence the two regarded the little brown woman so unconscious
of their gaze. By the piteous wizened face screwed up in the sunlight,
by the faded hair, nut-cracker jaws, and hollow eyes they utterly
condemned Mrs. Tuttle, who, blue feathers floating, was also absorbed in
watching the stream of embarking excursionists.</p>
<p>Mrs. Tinneray, after a whispered consultation with<span class="pagenum"><a id="Page_14">[Pg 14]</a></span> Mrs. Bean went up
and nudged her; without ceremony she pointed,</p>
<p>"Your sister's down there on the wharf," she announced flatly, "come on
over where we are and you can see her."</p>
<p>Frivolous Mrs. Tuttle turned and encountered a pair of eyes steely in
their determination. Re-adjusting the gold cage more comfortably on its
camp-stool and murmuring a blessing on the hooked-beak occupant, the
azure lady tripped off in the wake of her flat-heeled friend.</p>
<p>Meanwhile Mr. Tinneray, standing well aft, was calling cheerfully down
to the little figure on the wharf.</p>
<p>"Next Summer you must git your nerve up and come along. Excursions is
all the rage nowadays. My wife's took in four a'ready."</p>
<p>But little Mrs. Cronney did not answer. Shading her eyes from the sun
glare, she was establishing recognizance with her cerulean relative who,
waving a careless blue-mitted hand, called down in girlish greeting,</p>
<p>"Heigho, Hetty, how's Cronney? Why ain't you to the excursion?"</p>
<p>The little woman on the wharf was seen to wince slightly. She shifted
her brown basket to the other arm, ignoring the second question.</p>
<p>"Oh, Cronney's good—ony he's low-spirited—seems as tho he couldn't get
no work."</p>
<p>"Same old crooked stick, hey?" Mrs. Tuttle called down facetiously.</p>
<p>Mrs. Bean and Mrs. Tinneray stole horrified glances at each other. One
planted a cotton-gloved hand over an opening mouth. But little Mrs.
Cronney, standing alone on the pier was equal to the occasion. She shook
out a small and spotless handkerchief, blowing her nose with elegant
deliberation before she replied,</p>
<p>"Well—I don't know as he needs to work <i>all</i> the time; Cronney is
<i>peculiar</i>, you know, he's one of them that is high-toned and nifty
about money—he ain't like <i>some</i>, clutching onto every penny!"<span class="pagenum"><a id="Page_15">[Pg 15]</a></span></p>
<p>By degrees, other excursionists, leaning over the railing, began to
catch at something spicy in the situation of these two sisters brought
face to face. At Mrs. Cronney's sally, one of the funny men guffawed his
approval. Groups of excursionists explained to each other that that lady
down there, her on the wharf, in the brown, was own sister to Mrs.
Josiah Tuttle!</p>
<p>The whistle of the <i>Fall of Rome</i> now sounded for all aboard. It was a
dramatic moment, the possibilities of which suddenly gripped Mrs.
Tinneray. She clasped her hands in effortless agony. This lady, as she
afterward related to Mrs. Bean, felt mean! She could see in her mind's
eye, she said, how it all looked to Hetty Cronney, the <i>Fall of Rome</i>
with its opulent leisurely class of excursionists steaming away from her
lonely little figure on the wharf; while Mabel Tuttle, selfish devourer
of the Hutches' substance and hair to everything, would still be handing
aroun' her boxes of French-mixed and talking baby talk to that there
bird!</p>
<p>At the moment, Mrs. Tinneray's mind, dwelling upon the golden cage and
its over-estimated occupant, became a mere boiling of savage desires.
Suddenly the line of grim resolution hardened on her face. This look,
one that the Tinneray children invariably connected with the switch
hanging behind the kitchen door, Mr. Tinneray also knew well. Seeing it
now, he hastened to his wife.</p>
<p>"What's the matter, Mother, seasick? Here I'll git you a lemon."</p>
<p>Mrs. Tinneray, jaw set, eyes rolling, was able to intimate that she
needed no lemon, but she drew her husband mysteriously aside. She fixed
him with a foreboding glare, she said it was a wonder the Lord didn't
sink the boat! Then she rapidly sketched the tragedy—Mrs. Tuttle serene
and pampered on the deck, and Hetty Cronney desolate on the wharf! She
pronounced verdict.</p>
<p>"It's <i>terrible</i>—that's what it is!"</p>
<p>Mr. Tinneray with great sagacity said he'd like to show<span class="pagenum"><a id="Page_16">[Pg 16]</a></span> Mabel Tuttle
her place—then he nudged his wife and chuckled admiringly,</p>
<p>"But yet for all, Hetty's got her tongue in her head yet—say, ain't she
the little stinger?"</p>
<p><i>Sotto voce</i> Mr. Tinneray related to his spouse how Mabel Tuttle was
bragging about her brick house and her shower-bath and her automobile
and her hired girl, and how she'd druv herself and that there bird down
to Boston and back.</p>
<p>"Hetty, she just stands there, just as easy, and hollers back that
Cronney has bought a gramophone and how they sets by it day and night
listening, and how it's son and daughter to 'em. Then she calls up to
Mabel Tuttle, 'I should think you'd be afraid of meddlin' with them
ottermobiles, <i>your</i> time of life.'"</p>
<p>Mr. Tinneray choked over his own rendition of this audacity, but his
wife sniffed hopelessly.</p>
<p>"<i>They</i> ain't got no gramophone—<i>her</i>, with that face and hat?—Cronney
don't make nothing; they two could <i>live</i> on what that Blue Silk Quilt
feeds that stinkin' parrot."</p>
<p>But Mr. Tinneray chuckled again, he seemed to be possessed with the
humor of some delightful secret. Looking carefully around him and seeing
every one absorbed in other things he leaned closer to his wife.</p>
<p>"She's liable to lose that bird," he whispered. "Them young fellers with
the canes—they're full of their devilment—well, they wanted I
shouldn't say nothing and I ain't sayin' nothing—only—"</p>
<p>Fat Mr. Tinneray, pale eyes rolling in merriment, pointed to the
camp-stool where once the parrot's cage had rested and where now no
parrot-cage was to be seen.</p>
<p>"As fur as I can see," he nudged his wife again, "that bird's liable to
get left ashore."</p>
<p>For a moment Mrs. Tinneray received this news stolidly, then a look of
comprehension flashed over her face. "What you talkin' about, Henry?"
she demanded. "Say, ain't you never got grown up? Where's Manda Bean?"<span class="pagenum"><a id="Page_17">[Pg 17]</a></span></p>
<p>Having located Mrs. Bean, the two ladies indulged in a rapid whispered
conversation. Upon certain revelations made by Mrs. Bean, Mrs. Tinneray
turned and laid commands upon her husband.</p>
<p>"Look here," she said, "that what you told me is true—them young
fellers—" she fixed Mr. Tinneray with blue-glassed significant eyes,
adding <i>sotto voce</i>, "<i>You keep Mabel Tuttle busy</i>."</p>
<p>Fat Mr. Tinneray, chuckling anew, withdrew to the after-rail where the
azure lady still stood, chained as it were in a sort of stupor induced
by the incisive thrusts of the forlorn little woman on the wharf. He
joined in the conversation.</p>
<p>"So yer got a gramophone, hey," he called down kindly—"Say, that's
nice, ain't it?—that's company fer you and Cronney." He appealed to
Mrs. Tuttle in her supposed part of interested relative. "Keeps 'em from
gettin' lonesome and all," he explained.</p>
<p>That lady looking a pointed unbelief, could not, with the other
excursionists watching, but follow his lead.</p>
<p>"Why—er—ye-ess, that's rill nice," she agreed, with all the patronage
of the wealthy relative.</p>
<p>Little Mrs. Cronney's eyes glittered. The steamboat hands had begun
lifting the hawsers from the wharf piles and her time was short. She was
not going to be pitied by the opulent persons on the excursion. Getting
as it were into her stride, she took a bolder line of imagery.</p>
<p>"And the telephone," looking up at Mr. Tinneray. "I got friends in
Quahawg Junction and Russell Center—we're talkin' sometimes till nine
o'clock at night. I can pick up jelly receipts and dress-patterns just
so easy."</p>
<p>But Mrs. Tuttle now looked open incredulity. She turned to such
excursionists as stood by and registered emphatic denial. "Uh-huh?" she
called down in apparent acceptance of these lurid statements, at the
same time remarking baldly to Mr. Tinneray, who had placed himself at
her side,<span class="pagenum"><a id="Page_18">[Pg 18]</a></span></p>
<p>"<i>She</i> ain't got no telephone!"</p>
<p>At this moment something seemed to occur to little Mrs. Cronney. As she
gave a parting defiant scrutiny to her opulent sister her black eyes
snapped in hollow reminiscence and she called out,</p>
<p>"Say—how's your parrot? How's your beau—Ro-me-o?"</p>
<p>At this, understood to be a parting shot, the crowd strung along the
rail of the <i>Fall of Rome</i> burst into an appreciative titter. Mrs.
Tuttle, reddening, made no answer, but Mr. Tinneray, standing by and
knowing what he knew, seized this opportunity to call down vociferously,</p>
<p>"Oh—he's good, Romeo is. But your sister's had him to the excursion and
he's got just a little seasick comin' over. Mis' Tuttle, yer sister, is
going to leave him with you, till she can come and take him home, by
land, ye know, in her ottermobile—she's coming to get you too, fer a
visit, ye know."</p>
<p>There was an effect almost as of panic on the <i>Fall of Rome</i>. Not only
did the big whistle for "all aboard" blow, but some one's new hat went
overboard and while every one crowded to one side to see it rescued, it
was not discovered that Romeo's cage had disappeared! In the confusion
of a band of desperadoes composed of the entire group of cynical young
men with ivory-headed canes, seized upon an object covered with
something like an altar-cloth and ran down the gangplank with it.</p>
<p>Going in a body to little Mrs. Cronney, these young men deposited a
glittering burden, the gold parrot-cage with the green bird sitting
within, in her surprised and gratified embrace. Like flashes these agile
young men jumped back upon the deck of the <i>Fall of Rome</i> just before
the space between wharf and deck became too wide to jump. Meanwhile on
the upper deck, before the petrified Mrs. Tuttle could open her mouth,
Mr. Tinneray shouted instructions,</p>
<p>"Your sister wants you should keep him," he roared,<span class="pagenum"><a id="Page_19">[Pg 19]</a></span> "till she comes
over to see you in her
ottermobile—to—fetch—him—and—git—you—for—a—visit!"</p>
<p>Suddenly the entire crowd of excursionists on the after-deck of the
<i>Fall of Rome</i> gave a rousing cheer. The gratified young men with the
ivory-headed canes suddenly saw themselves of the age of chivalry and
burst into ragtime rapture; the excursion, a mass of waving flags and
hats and automobile veils, made enthusiastic adieu to one faded little
figure on the wharf, who proud and happy gently waved back a gleaming
parrot's cage!</p>
<p>It was Mr. Tinneray, dexterous in all such matters, that caught at a
drooping cerulean form as it toppled over.</p>
<p>"I know'd she'd faint," the pale-eyed gentleman chuckled. He manfully
held his burden until Mrs. Tinneray and Mrs. Bean relieved him. These
ladies, practised in all smelling-bottle and cologne soothings, supplied
also verbal comfort.</p>
<p>"Them young fellows," they explained to Mrs. Tuttle, "is full of their
devilment and you can't never tell what they'll do next. But ain't it
<i>lucky</i>, Mis' Tuttle, that it's your own sister has charge of that
bird?"</p>
<p>When at last a pale and interesting lady in blue appeared feebly on
deck, wiping away recurrent tears, she was received with the most
perfect sympathy tempered with congratulations. There may have been a
few winks and one or two nods of understanding which she did not see,
but Mrs. Tuttle herself was petted and soothed like a queen of the
realm, only, to her mind was brought a something of obligation—the
eternal obligation of those who greatly possess—for every excursionist
said,</p>
<p>"My, yes! No need to worry—your sister will take care of that bird like
he was one of her own, and then you can go over in yer ottermobile to
git him—and when you fetch him you can take her home with yer—fer a
visit."<span class="pagenum"><a id="Page_20">[Pg 20]</a></span></p>
