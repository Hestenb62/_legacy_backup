Charles Lenox Remond, Frederick Douglass, Lucy Stone, Henry B.
Blackwell, Rev. Olympia Brown, Sojourner Truth (Mrs. Stowe's "Lybian
Sybil"), Rev. Samuel J. May, and others.
</p>
