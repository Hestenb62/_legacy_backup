by different members to reply to various objections that readily
suggested themselves. Among others, Mr. Greeley said: "Ladies, you
will please remember that the bullet and ballot go together. If you
vote, are you ready to fight?" "Certainly," was the prompt reply. "We
are ready to fight, sir, just as you fought in the late war, by
sending our substitutes." The colloquy between the members and the
ladies, prolonged until a late hour, was both spicy and
instructive.<a name="FNanchor_97_97" id="FNanchor_97_97"></a><a href="#Footnote_97_97" class="fnanchor">[97]</a> On the 10th of July a hearing was granted to Lucy
Stone,<a name="FNanchor_98_98" id="FNanchor_98_98"></a><a href="#Footnote_98_98" class="fnanchor">[98]</a> which called out deep interest and consideration from the
members of that body. Later still, George Francis Train<a name="FNanchor_99_99" id="FNanchor_99_99"></a><a href="#Footnote_99_99" class="fnanchor">[99]</a> was most
cordially received by the Convention.<span class="pagenum"><a name="Page_285" id="Page_285">[Pg 285]</a></span></p>

<blockquote><p><span class="smcap">C. C. Dwight</span>, June 26th, offered a resolution that "The Standing
Committee on the Right of Suffrage be instructed to provide for
women to vote as to whether they wanted the right to vote after
the adoption of the New Constitution.</p>

<p>Mr. <span class="smcap">Merritt</span>, July 11th, moved that "The question of Woman
