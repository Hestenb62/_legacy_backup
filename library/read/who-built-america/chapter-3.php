<div class="cdn-book-reader-content">
	<div class="content-content">
		<p>In 1492, the Genoese-born sea captain Christopher Columbus and his Spanish crewmen landed on a small island
			in the Bahamas after a two-month Atlantic voyage, meeting the Taíno people, who called the island Guanahaní.
			Leaving a Spanish encampment on Ayti (Haiti), a large nearby island he had renamed “Hispaniola,” he captured
			six Indigenous men and brought them back with him to Spain. Columbus’s appropriation of these men and of the
			territories he encountered indicated the European intention to gain wealth and power from overseas
			exploration.</p>
		<p>Columbus had sailed in the service of King Ferdinand and Queen Isabella of Spain, searching for a western
			route to the Indies, the Asian source of spices and other valuable goods. Thinking he had reached the
			Indies, Columbus and Europeans after him called the Native inhabitants&nbsp; “Indians.” Columbus made three
			subsequent voyages and apparently believed to his death, in 1506, that he had reached Asia. But other
			explorers had already questioned this belief. One of them, Amerigo Vespucci, calculated that these lands
			were part of a continent unknown to Europeans. In 1507, in Vespucci’s honor, a German mapmaker named this
			continent “America.”</p>
		<p>Columbus and his crew were not, in fact, the first Europeans in America. In the eleventh century,
			Scandinavians had reached Labrador and Newfoundland, where they built a short-lived settlement. But other
			Europeans had no knowledge of that venture; to them, Columbus’s 1492 voyage marked the “discovery” of a “New
			World” that they would compete avidly with Native polities and with each other to possess. Seeking wealth or
			land, they commenced a process of conquest and settlement that would alter or destroy the lives of the
			peoples who already lived there. To Native Americans it marked the beginning of a long invasion during which
			many were colonized, enslaved, and in many places almost wiped out.</p>
		<p>Tragedy tinged even the first contacts. Columbus took his six captives to the royal court at Barcelona, where
			they excited much curiosity, were baptized into the Catholic Church, and were given Spanish names. But they
			did not live long in Spain. Some were taken back to the Caribbean; one man became a page at court but soon
			died. Columbus, meanwhile, returned to Hispaniola to find his crewmen vanished. Disease, malnutrition,
			violence, murder, and destruction would in places reach catastrophic proportions.</p>
		<p>Europe’s encounter with the Americas would transform both continents, and soon would involve Africa, too.
			Traders, warriors, missionaries, and adventurers would forge commercial, political, and religious changes on
			all three continents, bringing new wealth to some people and exposing others to great brutality and misery.
			Even in Europe, the chief beneficiary of contact with the New World, conquest and colonization would
			contribute to inequality and social conflict.</p>
		<p>Europeans dreamed of finding wealth in the New World, but knew that to do so they would need much labor.
			Columbus predicted that the Native peoples he encountered “should be good and intelligent servants.” The
			history of the Americas would be shaped by the efforts of conquerors and settlers to use first Native
			American, and then European and African labor to exploit the continent’s riches. In the process most of
			these laborers had to endure poverty and untimely death, but they were the people who built America.</p>
			<a href="#slug-peoples_of_the_new_world">
				<h2 id="slug-peoples_of_the_new_world">Peoples of the New World</h2>
			</a>
		<div class="content-content">
			<p>None of those involved in the encounter between Europe, the Americas, and Africa were a single people.
				Most varied of all were the inhabitants of the Americas. Evidence about their origins is thin and
				uneven, and archaeologists continue to debate it hotly. Until recently it was conventional to trace the
				earliest Americans to a period approximately 13,000 years ago, late in the last Ice Age, when groups
				from Siberia migrated across the dry land that linked Asia with Alaska before rising sea levels
				separated the continents. Recent findings suggest that people may also have reached the Americas by sea
				from South East Asia via Polynesia as much as 20,000 or more years ago, and that several different
				migrations populated the continent before about 4,000 BCE. At any event, migrants and their descendants
				spread across North and South America and to the Caribbean islands, building a vast array of cultures
				and languages. By 1492, there may have been as many as 50 or 100 million people in the Americas, perhaps
				one-seventh of the world’s population. But their isolation from the rest of the world—particularly their
				lack of immunity to European diseases—left them vulnerable as Europeans started coming to the Americas
				in the late fifteenth century.</p>
		</div>
		<a href="#slug-centralized_empires_in_central_and_south_america">
			<h3 id="slug-centralized_empires_in_central_and_south_america">Centralized Empires in Central and South
				America</h3>
		</a>
		<div class="content-content">
			<p>Some Central and South American&nbsp;societies had developed strong states. That of the Incas, centered
				in present-day Peru and Bolivia, had expanded in the fifteenth century into an empire stretching far
				along the Andes mountains and South America’s western coast. Common peoples’ obligatory labor supported
				a royal family surrounded by aristocrats. Women wove cloth that was prized in commerce and religious
				ritual. Inca women also contributed to tending and harvesting. Men grew crops and built extensive road
				and canal systems that united the empire and irrigated arid land.</p>
			<p>The Aztecs of Mexico, too, forged a loosely confederated empire during the fifteenth century, conquering
				the descendants of earlier Olmec, Mayan, and Toltec empires and exacting tribute payments from outlying
				nations. Fifteen to twenty million strong, the Aztecs boasted impressive achievements in irrigation,
				metallurgy, and city-building. Tenochtitlán, the capital, had over a quarter of a million inhabitants.
				Aztec society was based on clans that organized farming, much of it on communal lands. Its upper ranks,
				headed by a figure the Spanish would call an “emperor,” included priests, generals, and wealthy
				merchants. But most Aztec people were craft-workers, farmers, laborers, soldiers, or enslaved persons.
			</p>
		</div>
		<a href="#slug-dispersed_societies_to_the_north">
			<h3 id="slug-dispersed_societies_to_the_north">Dispersed Societies to the North</h3>
		</a>
		<div class="content-content">
			<p>America north of Mexico was more sparsely populated. Archaeologists disagree as to how many people
				inhabited its vast land area. Estimates vary from one to eighteen million, but most suggest that there
				were around five million in 1500. These groups, smaller than those further south, spoke some 375
				different languages, many of which also had mutually unintelligible dialects. Native American societies
				had long been based on hunting, fishing, and gathering wild plant foods. Starting around 3000 bce in the
				Southwest, and spreading northward and eastward over nearly three thousand years, the cultivation of
				maize (corn) and other crops had also evolved. In most cases, women performed the main tasks of raising
				and preparing food. The Hohokam culture (300 bce to 800 ce) of present-day Arizona, and the later Pueblo
				peoples of the highlands north of Mexico, built irrigation systems not unlike those that the Incas and
				Aztecs would subsequently construct.</p>
			<p>Farming meant more dependable food supplies and population growth. Groups that cultivated crops became
				more stable and often more powerful than neighbors who primarily relied on hunting and gathering. Pueblo
				societies of the Southwest were among the most complex. By the twelfth century, the inhabitants of Chaco
				Canyon had twelve towns and over two hundred villages, each built of contiguous rooms, that altogether
				housed 15,000 people. Corn-cultivating societies in the Mississippi Valley also built urban centers and
				became socially stratified. The largest town, at Cahokia near present-day St. Louis, covered around six
				square miles and housed at least 10,000 people before it went into decline in the thirteenth century.
			</p>
			<p>Some groups, like the Jumanos of the Southwest and the (Odawas) Ottawas of the Great Lakes region, were
				known as traders. On the plains and prairies of the West, groups hunted buffalo; some, like the Chaticks
				Si Chaticks (Pawnees), exchanged meat for grain with corn-growing societies nearby. Eastward to the
				Atlantic coast, where most early encounters with Europeans took place, people combined horticulture,
				hunting, and trade.</p>
		</div>

		<a href="#slug-eastern_woodland_native_peoples">
			<h3 id="slug-eastern_woodland_native_peoples">Eastern Woodland Native Peoples</h3>
		</a>
		<div class="content-content">
			<p>Most Eastern woodland peoples lived in family-based societies with little organized hierarchy. Except in
				the far Northeast, where poor soil and climate prevented farming, they relied on cultivated
				crops—typically corn, beans, and squashes—for half or more of their food. Women worked the fields,
				located close to villages so that they could coordinate crop raising with other tasks. Villages, each
				with up to a few hundred inhabitants, contained easily moved shelters, and could relocate according to
				seasonal and ecological changes. Strong kinship ties bound individuals to one another. Land and water
				were the common property of each village, and all shared in the yield of hunt and harvest. “Every
				proprietor knows his own,” an English observer noted, “yet all things . . . are used in common amongst
				them.”</p>
			<p>The absence of accumulated personal property ensured a roughly equal distribution of wealth.
				Haudenosaunees, wrote a French missionary, had no poorhouses “because there are neither mendicants nor
				paupers. . . . A whole village must be without corn before any individual can be obliged to endure
				privation.” Sharing goods reinforced individuals’ sense of group belonging, and there were strong
				sanctions against unacceptable behavior, from public disapproval or ridicule to expulsion and exile.</p>
			<p>Many groups were matrilineal; identity and status descended from mothers to children. Eastern woodland
				groups tended also to be matrilocal—after marriage men moved into their wives’ households. Here,
				leadership was not restricted to men. Some women enjoyed a degree of personal independence and power.
				Prominent Haudenosaunee&nbsp;women controlled their own homes and fields, could divorce at will, and had
				the right to choose leaders from among their menfolk. They supervised their appointees and could remove
				them for misdeeds or incompetence.</p>
		</div>
		<a href="#slug-america_s_peoples_at_contact">
			<h3 id="slug-america_s_peoples_at_contact">America’s Peoples at Contact</h3>
		</a>
		<div class="content-content">
			<p>Native American societies were not static, but had faced long periods of change and conflict. Between the
				twelfth and fifteenth centuries, large settlements like Chaco Canyon and Cahokia declined and their
				populations dispersed to villages. Wars erupted over access to land and resources. Five nations in the
				Northeast (the&nbsp;Kanien'kehá:kas [Mohawks], Onyota'á:kas [Oneidas], Gayogo̱hó꞉nǫʼs [Cayugas],
				Onoñda’gegas [Onondagas], and Onöndowa’ga:’s [Senecas]) formed the Haudenosaunee&nbsp;Confederacy in the
				fifteenth century, apparently to reduce such conflicts between them. The Confederacy, though, aggravated
				tensions with other groups. Martial prowess became so prized that Haudenosaunee&nbsp;leadership commonly
				passed to those reputed to be the best warriors.</p>
			<p>Two common factors influenced the terms on which Indigenous societies would face contact with Europeans.
				The fact that no society north of Mexico had an overarching state like those of the Aztecs and Incas had
				advantages and disadvantages. When the Spanish invaded Central and South America after 1518, they had
				quickly toppled the Aztec and Inca empires. Few North American groups faced such rapid collapse.
				However, their dispersion and disunity made cohesive response or resistance to invasion difficult to
				attain.</p>
			<p>A second factor was the process that scholars now call the Columbian Exchange. European contact with
				Africa and the Americas initiated an exchange of flora, fauna, and microorganisms hitherto isolated from
				one another. New World crop seeds were carried to Europe, along with diseases such as syphilis, which
				spread there rapidly after arriving in the 1520s. But the effect of European organisms on America was
				more dramatic. Newly introduced grasses drove out existing species, and domesticated livestock
				flourished on a continent where they had been unknown. Most damaging was the fact that new human
				diseases had disastrous effects on populations who initially lacked immunity to them. In some areas,
				typhus, influenza, measles, and smallpox wiped out ninety percent of Native peoples by 1600. Such
				devastation—by reducing Native populations and undermining their societies—would help conquerors and
				settlers shape their colonies to serve their own purposes.</p>
		</div>
		<a href="#slug-the_background_to_overseas_expansion_europe_and_africa">
			<h2 id="slug-the_background_to_overseas_expansion_europe_and_africa">The Background to Overseas Expansion: Europe and Africa</h2>
		</a>
		<div class="content-content">
			<p>Led by Hernán Cortés, a Spanish expedition set out in 1518 to conquer Mexico. Successive waves of
				conquistadores followed. One wrote that he did so “for King, God, and Gold,” summing up the motivations
				that drove Europeans to explore and seize overseas territory. Changes in Europe over the centuries
				before 1500 had initiated political consolidation, religious division, and commercial development. These
				in turn fostered overseas trade and conquest, which first led to closer links between Europe and West
				Africa and to the colonization of Atlantic islands. As Europe’s interest in the Americas deepened, it
				drew Africa more tightly into the process.</p>
		</div>
		<a href="#slug-politics_religion_and_commerce_in_western_europe">
			<h3 id="slug-politics_religion_and_commerce_in_western_europe">Politics, Religion, and Commerce in Western Europe</h3>
		</a>
		<div class="content-content">
			<p>Early in the fourteenth century, European population growth peaked. Wars and changes in climate hampered
				food production just as growing populations stretched resources to their limits. The consequent famine
				was followed in the 1340s by plague—The Black Death—that ravaged many parts of the continent, so that
				between 1300 and 1400 Europe lost two-fifths or more of its people.</p>
			<p>Aristocratic landlords held most land in Europe, and they controlled the labor of peasant serfs legally
				bound to the land. Population loss weakened these feudal ties between landlords and serfs, and
				challenged or toppled monarchical dynasties. As population and wealth grew again in the fifteenth
				century, however, some monarchs created new military and administrative structures that asserted their
				power over unruly nobles. The uniting of the crowns of Aragon and Castile in 1469 created a strong
				Spanish monarchy, while the ascent of the Tudor dynasty in England in 1485 ended the long baronial
				feuding known as the Wars of the Roses and began a consolidation of royal administration. Such “new
				monarchies” formed nation states that would soon compete for wealth and territory overseas.</p>
			<p>As monarchies consolidated, Roman Christendom began to fragment. Discontent with the wealth and
				corruption of the papacy and clergy fostered religious dissent in some regions, and efforts at church
				renewal and reform elsewhere. Spain produced a revitalized Catholicism symbolized by the piety of King
				Ferdinand and Queen Isabella, but in Germany and other parts of northern Europe from 1517 on Martin
				Luther and other reformers sparked a revolt, known as the Protestant Reformation, that led many churches
				to break with Rome. In Sweden and many German principalities, the Reformation secured the adherence of
				rulers who saw religion as a vehicle for state power. The English king Henry VIII, too, severed ties
				with Rome in 1534 in a clash with the papacy over his wish for a divorce, and declared himself head of a
				separate Church of England. From mid-century on, as Catholic reform turned into an effort to regain lost
				ground, wars between Protestants and Catholics wracked France, Germany, and the Netherlands.</p>
			<p>This turmoil added a religious dimension to overseas exploration and colonization. Especially in Catholic
				Europe, the pursuit of territory was clothed in the imperative to convert “heathen” Indigenous peoples
				to Catholicism. Spain revitalized religious orders such as the Franciscans and Dominicans making them
				spearheads of the Faith in the New World. Struggles against Protestantism spurred a redoubling of
				efforts to save souls overseas, as priests belonging to new orders, such as the Society of Jesus
				(Jesuits), also became missionaries.</p>
			<p>Political and religious impulses for expansion were underpinned by developments in trade and shipping
				that marked Europe’s recovery from the crisis of the Black Death. Banking spread to northern Europe from
				its origins in Italy, strengthening a commercial revival that accompanied the growth of urban
				populations from 1400 onward. Merchants accumulated capital to invest in the rich trade in luxury goods
				from Asia. But the expansion of the Islamic Ottoman empire and the dominance over the Asian trade of
				states such as Venice hampered their efforts. Accordingly, they sought alternative routes to the sources
				of this trade and of the gold and silver that could purchase the goods. Monarchs wanting to pay for
				their new governments and armies were also eager for new sources of wealth.</p>
		</div>
		<a href="#slug-society_and_trade_in_west_africa">
			<h3 id="slug-society_and_trade_in_west_africa">Society and Trade in West Africa</h3>
		</a>
		<div class="content-content">
			<p>The search for wealth first drew Europeans into increasing contact with trading societies in Africa.
				Africa’s total population may have exceeded eighty million, four-fifths of it located south of the
				Sahara. From the Islamic traders of the Indian Ocean port of Mombasa, to the farmers of the fertile
				forest regions of what is now Nigeria, to the food-collecting San and cattle-keeping Khoi-Khoi of the
				south, the continent contained a wide diversity of cultures and economies. In complexity and prosperity,
				many African societies compared with those of Europe and Central America.</p>
			<p>West Africa, which would have the most importance for New World developments, had roughly eleven million
				inhabitants in 1500. Towns such as Timbuktu, Gao, and Benin were significant trading centers, home to
				merchants, craftsmen, scholars, and priests, and to handicrafts, the arts, education, and legal systems.
				Most West Africans, however, were rural dwellers, belonging to groups organized around kinship networks.
				Families raised livestock, and cultivated crops with iron tools made in the region for more than a
				thousand years.</p>
			<p>Kin groups owned land communally, and households often cooperated to produce food. Women dominated food
				production, and were active in the marketplaces, where they sold surplus produce. Polygyny, whereby one
				man had several wives, was common, especially among the wealthy. Family and clan leaders exercised
				authority in the collective leadership of villages and larger political confederations. Religious
				beliefs varied from place to place, but most West Africans believed they were part of a spiritual world
				shaped by the cycles of nature, the legacy of ancestors, and an all-knowing Creator. In the towns and
				grasslands south of the Sahara, there was growing adherence to Islam.</p>
			<p>Enslaved labor often supplemented that of family members. Slavery was an ancient system, with roots in
				ancient Greece and Rome, in Africa and Byzantium, under Islam and under Christianity. It had largely
				died out in Western Europe but was common in West Africa, where the enslaved were attached to kinship or
				family groups and worked in the fields or at household tasks. Some enslaved persons had been captured in
				warfare, some were debtors, others criminals. Many enslaved persons had some rights, and enslavement
				status rarely passed from parent to child. Some could work for their freedom; some married into the
				families that held them; some even owned property. But slavery had harsher aspects too. Some societies
				put the enslaved to sacrificial death, and there was a growing enslavement trade with trans-Saharan and
				Indian Ocean markets, where women and children, especially, were in demand for their labor or for sexual
				purposes.</p>
			<p>Most West African societies were stateless, but warfare and slavery had led villages and kin groups to
				increase reliance on kingdoms, whose rulers offered protection and fostered commerce in return for
				tribute and taxes. The Mali empire, centered on the Niger river valley, was one of the world’s largest
				in the early fifteenth century, but then was eclipsed first by the Songhai empire and later by smaller
				but powerful kingdoms—Benin, Dahomey, and Kongo—that rose to prominence after 1600.</p>
			<p>Such states encouraged West Africa’s important trading networks. Commercial towns exported gold, ivory,
				cotton goods, leather, spices, and enslaved persons, to markets in North Africa, the Middle East, and
				Europe. A European visitor to Benin city found a rich array of goods in its markets:</p>
			<blockquote>
				<p>Pepper and elephant teeth, oil of palm, cloth made of cotton wool very curiously woven, and cloth
					made of the bark of palm trees . . . iron works of sundry sorts, Manillos or bracelets of copper,
					glass beads and coral. . . . They have good store of soap . . . also many pretty fine mats and
					baskets that they make, and spoons of elephant’s teeth very curiously wrought with divers
					proportions of fowls and beasts made upon them.</p>
				<p><i><b>Source:</b> Who Built America?</i></p>
			</blockquote>
			<p>Looking for the goods that West Africa’s trading networks had to offer, Portuguese sea captains ventured
				down its coast. In 1470 they reached the Gold Coast (now mostly in Ghana), later establishing a trading
				post at Elmina, and fortifying it against European rivals. Before 1492, trade with the Gold Coast
				provided two-thirds of Europe’s gold supply. By 1600, Portugal was shipping out 170,000 gold coins each
				year, obtained in payment for wheat, cloth, and metal goods.</p>
			<p>West African societies’ strength and commercial sophistication enabled them to trade with Europeans while
				confining them largely to river and coastal centers. The disease-riddled environment also proved harsh
				for Europeans, who succumbed at alarming rates to malaria and other fatal tropical afflictions.
				Consequently Europeans made little effort to establish extensive colonial settlements in West Africa.
				But they did use African commerce and slavery as instruments in their encounters with the newly-found
				Americas.</p>
		</div>
		<a href="#slug-the_invasion_of_the_americas_begins_portugal_spain_and_the_need_for_labor_">
			<h2 id="slug-the_invasion_of_the_americas_begins_portugal_spain_and_the_need_for_labor_">The Invasion of the
				Americas Begins: Portugal, Spain, and the Need for Labor </h2>
		</a>
		<div class="content-content">
			<p>The immediate cause of Europeans’ interest in the Americas lay in developments in Spain and Portugal.
				Since early in the fifteenth century, Portuguese fishing and trading vessels had probed the Atlantic. In
				time, they established the island colonies of Madeira, the Cape Verde Islands, and the island of São
				Tomé off the African coast. Navigational experience and trade with West Africa after 1470 led to a
				concerted effort to reach the East Indies. In 1487 a voyage led by Bartholomeu Dias rounded southern
				Africa; ten years later Vasco da Gama and his crew sailed all the way to India.</p>
			<p>The Spanish empire grew out of conquest at home. On and off since the twelfth century, Spain’s Catholic
				rulers and nobles had attempted to drive out or convert Islamic settlers in the south of Spain. This
				<em>reconquista</em>, renewed around 1450, culminated in the Spanish monarchy’s defeat of the kingdom of
				Granada in 1492, and the expulsion or forced conversion of its Muslim and Jewish population. From the
				1470s to 1496, Spanish troops also fought to create a colony in the Canary Islands, exploiting
				Indigenous labor and annihilating the inhabitants in the process.
			</p>
			<p>Both Spain and Portugal commenced practices that they would carry to the New World. As early as 1444,
				Portuguese traders were purchasing enslaved persons in West Africa for transport to Portugal as lifelong
				domestic servants. After they established settlements on Madeira and other islands off the African
				coast, the Portuguese took enslaved persons there too, and as settlers developed plantations for growing
				sugar cane, they purchased enslaved Africans to work them, building a prototype for forced labor in the
				growing Atlantic economy.</p>
		</div>
		<a href="#slug-overseas_expansion_and_conquest">
			<h3 id="slug-overseas_expansion_and_conquest">Overseas Expansion and Conquest</h3>
		</a>
		<div class="content-content">
			<p>King Ferdinand and Queen Isabella authorized Columbus’s voyage just after the fall of Granada. Their aim
				was to extend westward the militancy that Spain had successfully employed at home. Landing on Guanahaní,
				Columbus at once claimed the island as a Spanish possession and gave it a Spanish name (San Salvador)—an
				act he and other Spaniards would repeat whenever they came across new territory.</p>
			<p>Columbus’s voyage spurred exploration and its associated mission of Christian conversion. In 1493, Pope
				Alexander VI granted Spain the right to spread the gospels in the Americas. The next year Spain and
				Portugal signed the treaty of Tordesillas in which they divided the entire world between them, an act of
				arrogance soon marred for Spain when Brazil was discovered in the Portuguese zone. In 1500 Portugal laid
				claim to Brazil and over the next half-century prepared to extend its Atlantic-island plantation labor
				system to South America.</p>
			<p>Spain, meanwhile, extended its exploration of the Caribbean. In 1502, Spanish families were settled on
				Hispaniola, and soon were colonizing Cuba, Puerto Rico, Jamaica, and other islands. After 1508 there
				were ventures onto the Central American mainland, and in 1513 Vasco Núñez de Balboa crossed the Isthmus
				of Panama, became the first European to see the Pacific Ocean, and confirmed that the Americas were a
				separate continent. The Aztec emperor learned promptly of this Spanish activity, but punished
				priest-diviners who foretold an invasion of Mexico. Within a few years, however, Hernán Cortés and his
				troops marched on Tenochtitlán and captured it.</p>
			<p>Spanish slaughtering and looting provoked a revolt, and the Aztecs drove Cortés and his men back. But
				they recaptured Tenochtitlán in 1521, assisted by fire and disease, which killed or dispersed much of
				the population. The capital’s fall started the collapse of the Aztec empire itself, a process hastened
				by revolts among nations the Aztecs had subdued. The conquerors soon established Spanish rule, put
				ordinary men and women to forced labor, hunted down nobles and priests, and set about destroying the
				knowledge and learning that had sustained what the Spaniards considered a “heathen” civilization.</p>
			<p>Moving beyond the valley of Mexico, the invaders conquered the Maya of the Yucatan and pressed into South
				America. From 1524 onward, Francisco Pizarro led explorations of the Pacific coast, and in 1532–1533
				invaded the Incas’ heartland in the Peruvian Andes. The capture of the Inca capital, Cuzco, provoked a
				political collapse, and despite rebellions against the invaders, the Inca empire folded as rapidly as
				that of the Aztecs.</p>
			<p>If conquistadors fought for “King” and “God,” they also envied Portuguese access to African gold and
				wanted their own. Rumors abounded of fabulous wealth in the Americas. “Those lands do not produce bread
				or wine,” claimed a Spanish writer, “but they do produce large quantities of gold, in which lordship
				consists.” The Spanish first looted the treasures from Aztec and Inca temples and palaces, but soon
				exhausted these riches and began searching for new sources. In 1545, they discovered huge silver ore
				deposits at Potosí in the Bolivian Andes; they found smaller ore fields in northern Mexico and
				elsewhere. The Spanish forced many thousands of Indigenous peoples to work in these mines, to send a
				flow of precious metals into Spanish coffers. Between 1500 and 1650 more than 180 tons of gold and
				16,000 tons of silver extracted by Spain from the Americas significantly augmented the supply of capital
				available in Europe.</p>
			<p>The search for gold also took the Spanish northward from Mexico. Two military expeditions around 1540
				failed to find any riches, but soldiers brutally attacked the Native people who resisted them. Francisco
				Vásquez de Coronado explored from New Mexico as far as Kansas and the Arkansas River. Hernando de Soto
				pushed into Florida, the Southeast, and the lower Mississippi valley, fighting one pitched battle in
				which thousands of Native and Spanish combatants died. These incursions and the diseases they introduced
				weakened the Native groups the Spaniards encountered. In central Arkansas, Coronado found thriving towns
				that, by the time French explorers reached the region in the 1670s, had disappeared.</p>
			<p>Spain then ignored the North until others took an interest in it. In 1562 some French Protestants settled
				on the Florida coast, but they had withdrawn again by the time the Spanish, fearing attacks on their
				treasure fleets, sent a force to remove them. In 1565 Spain founded the town of St. Augustine, now the
				oldest continually occupied European settlement in the United States. Subsequently they explored as far
				as the Chesapeake, and in northern Florida Spanish soldiers and priests established nearly forty mission
				stations. By 1600 they were making similar efforts further westward, pushing into what they named New
				Mexico, building forts and missions to subdue and convert Pueblos, and, in 1608, founding the town of
				Santa Fe.</p>
		</div>
		<a href="#slug-the_need_for_labor">
			<h3 id="slug-the_need_for_labor">The Need for Labor</h3>
		</a>
		<div class="content-content">
			<p>New territory could enhance a nation’s power and prestige. Conquered peoples could be converted to
				Christianity. New land could provide wealth from mining, farming, or trade for governments, investors,
				and settlers. The Spanish crown, keen to use colonization as a means of rewarding, and thus controlling,
				Spain’s lesser nobility, placed the conduct of overseas conquest under central control, creating the
				Council of the Indies in 1524 to administer the whole Spanish empire from the port city of Seville. But
				success depended on obtaining and directing the labor of millions of people.</p>
		</div>
		<div class="content-content">
			<p>Conquistadors and noble settlers did not intend to do any work themselves, nor could they attract
				sufficient emigrants from Spain or Portugal to work for them in the Americas. From Columbus onward they
				hoped labor would be extracted from Native peoples who could be forced to work for their new masters.
				Whether they were priests seeking souls to convert, planters seeking crops to export, or officials
				seeking taxes to collect, forced labor helped to give them what they wanted.</p>
			<p>Adapting practices both from southern Spain and the Canary islands and from Aztec society, the Spanish
				crown granted conquistadors in Mexico and Peru rights to share in the forced labor of Native
				settlements. Cortés alone had 23,000 workers under this <em>encomienda</em> system by the mid-1520s, and
				in parts of Spanish America it was used until the late seventeenth century to provide labor for
				missions, mines, and large farms. In Florida and New Mexico, missionaries resettled Native people into
				peasant communities, forcing them to work erecting buildings and growing crops. The missions in Florida,
				with just seventy priests between them, claimed to have over 25,000 Native Christian converts working
				for them by the mid-seventeenth century. Colonial governors exploited Native labor to obtain private
				income. Church and government disputed over the right to put Native inhabitants to work. In the
				Southwest, Pueblo peoples came into the missions in part to evade harassment by marauding Spanish
				soldiers.</p>
			<p>But Native labor frequently did not fulfill colonists’ hopes, even though distance from colonial
				authority often enabled them to treat Indigenous populations mercilessly with little fear of restraint.
				Disease and the harsh demands of forced labor killed large numbers of Native people in Spanish America
				throughout the sixteenth century. The Timucuans of Florida were about 350,000 strong in 1500, but a
				century later only 7,000 remained; four out of every five New Mexican pueblos or villages were abandoned
				as populations declined. The <em>encomienda</em> provoked Native resistance, and from the 1570s on the
				Spanish partly replaced it with a less harsh system, known as the <em>repartimiento</em>, that obliged
				Native people to provide involuntary, but compensated, labor on public works.</p>
			<p>Some Spaniards criticized forced labor. In 1511, the Dominican priest Antonio Montesinos challenged the
				exploitation of Native people, asking conquistadors “with what right and with what justice do you keep
				these poor Indians in such cruel and horrible servitude?” He influenced another priest, Bartolomé de Las
				Casas, who for half a century denounced the slaughter and ill-treatment of Native peoples and the common
				Spanish assumption that Native people were “slaves by nature.”</p>
			<p>Yet Las Casas knew that the work in the colonies had to be done, and that Europeans could not be found to
				do it. For him, and for many other Spanish and Portuguese, the solution was to import enslaved persons
				from Africa instead. As they opened up Brazil in the sixteenth century, the Portuguese adapted the
				sugar-plantation system they had established in Madeira and the Cape Verde islands. Finding the
				Indigenous people of Brazil difficult to control, they drove them deep into the tropical forests and
				brought laborers from Africa and the islands to work for them. The Spanish had also begun substituting
				Africans for Native American labor. So began a transatlantic trade in enslaved persons that would last
				for almost four centuries.</p>
		</div>
		<a href="#slug-africa_and_the_american_slave_trade">
			<h3 id="slug-africa_and_the_american_slave_trade">Africa and the American Slave Trade</h3>
		</a>
		<div class="content-content">
			<p>To Europeans, enslaved persons purchased in West Africa were an ideal solution to their New World labor
				problems. In 1510 the Spanish crown legalized the sale of Africans in the Americas, and eight years
				later a Spanish ship carried the first full cargo of Africans across the Atlantic. By the 1540s enslaved
				persons were distributed around all the Spanish and Portuguese colonies. Cortés himself had sixty-eight
				in 1547, in addition to 169 enslaved Mexicans. A century later, there were 30,000 enslaved Africans
				working in the valleys around Lima in Peru, and more in the mines of Mexico. But enslaved persons would
				be used most in the plantation economies of Brazil and the Caribbean. By 1600 the Spanish and Portuguese
				had forcibly removed over 250,000 Africans to the Americas, and the numbers grew rapidly as French,
				English, and Dutch merchants also entered the slave trade.</p>
			<p>Slave trading would prove extremely lucrative, becoming part of a larger commerce—referred to as the
				triangular trade—that took European goods to Africa, enslaved persons to America, and New World produce
				back to Europe. But the Europeans who were involved did not share the rich pickings equally. Many
				rulers, merchants, and shipowners made money, but most minor officials and ships’ crews endured poor pay
				and harsh conditions. Of Dutch West India Company employees in the slave trade, for instance, only one
				in twenty made a fortune and another two made more modest profits; the rest made little or nothing.</p>
			<p>Some West African rulers, such as the <em>obas</em> (kings) of Benin after 1550, used their power to curb
				the American slave trade. Resistance to the trade fostered revolts, such as the one headed by Muslim
				inhabitants on the Senegal River around 1670. But many rulers willingly took part. From Senegal to
				Angola they organized the capture of people, usually from the interior and from ethnic groups other than
				their own, for delivery to European traders on the coast. They purchased European guns to help fight
				wars and augment the number of their captives. The Ashanti and the king of Dahomey increased their power
				and wealth as a result. Some African merchants also did well: Abee Coffu Jantie Seniees, the leading
				trader of Cape Coast, and John Kabes, the main middleman between the Ashanti and the port of Komenda,
				made fortunes selling enslaved persons in the seventeenth century.</p>
			<p>European nations competed fiercely for a share in the slave trade, but strong local rulers prevented any
				of them from monopolizing it. At Ouidah in the kingdom of Dahomey, the king’s powerful viceroy kept the
				port open to all Europeans equally, setting rules by which they could do business. The Dahomian state
				relied on the slave trade, both for the exercise of policy and as a source of revenue.</p>
			<p>However, in the long run the slave trade debilitated West Africa. Up to twelve million people were sold
				to Europeans and shipped to the Americas between the fifteenth and nineteenth centuries. European goods
				imported to pay for enslaved persons drove local artisans out of business, and people fled coastal
				regions to avoid slave hunters, ruining Africa’s trading economies. Slave traders primarily sought
				young, healthy men who could be sold in the Americas as field hands, so in time women came to outnumber
				men in West Africa, altering family and marriage patterns and causing populations to fall. Meanwhile,
				local demand for labor from enslaved women increased, so the Atlantic slave trade strengthened African,
				as well as American, slavery.</p>
		</div><a href="#slug-captivity_and_the_middle_passage">
			<h3 id="slug-captivity_and_the_middle_passage">Captivity and the Middle Passage</h3>
		</a>
		<div class="content-content">
			<p>Local traders seized most enslaved persons inland and marched them, enchained, for as long as a year to
				the coastal forts. Hunger, sickness, or exhaustion killed many on the way. Survivors reaching the coast
				were locked up to await shipment in prisons known as <em>barracoons</em>, slaveholds, or trunks. At the
				English fort of Cape Coast these were underground caves, able to hold a thousand or more people each. A
				French trader, Jean Barbot, described the slave pens at Ouidah in the 1680s:</p>
			<blockquote>
				<p>[T]he slaves . . . are put into a booth or prison, built for that purpose near the beach, all of them
					together; and when the Europeans are to receive them, they are brought out into a large plain, where
					the ships’ surgeons examine every one of them, to the smallest member, men and women being all stark
					naked. Such as are allowed [judged] good and sound are set on one side . . . [each] is marked on the
					breast with a red-hot iron, imprinting the mark of the French, English, or Dutch companies so that
					each nation may distinguish their own property, and so as to prevent their being changed by the
					sellers for others that are worse.</p>
			</blockquote>
			<p>Branded by their new owners, captives were chained below-decks in ships designed to carry the largest
				number of people in the smallest possible space for the transatlantic voyages that became known as the
				“Middle Passage.” A German ship’s surgeon noted that “some of these poor people obeyed . . . without . .
				. any resistance,” but “others . . . filled the air with heartrending cries which . . . cut me to the
				quick.” Barbot recalled one man, a <em>marabou</em> or Muslim teacher, who spoke not one word on the
				two-month Atlantic crossing, “so deep was his sorrow.” (He sold him in the Caribbean.)</p>
			<p>Shipboard conditions were ghastly. Men, women, and children were crammed together among their own
				excrement; it was said that a slave ship could be smelled downwind long before it came into sight.
				Traders accepted that perhaps one in six enslaved persons would die from disease, malnutrition, or
				suicide during the voyage. Occasionally they died in shipboard revolts that the European crews brutally
				suppressed. Sailors lived barely more comfortably than the enslaved they carried, and their death rates
				from disease could be even higher.</p>
			<p>Enslaved persons began their journey to the Americas not as “Africans,” but as members of many different
				societies and ethnic groups, speaking an array of languages and holding to a variety of customs and
				beliefs. Even in the 1540s, Cortés’s enslaved persons came from many places, from Gambia to Mozambique.
				Shippers often mixed captives from different places to reduce the risk of mutiny. Still, many enslaved
				persons shared common skills, and assumptions about religion, kinship, and social life. Many had some
				connections with the trading cultures of the African seaboard, and some shared knowledge of trading
				languages. Aboard ship the things they had in common enabled them to begin to cooperate, despite the
				differences among them. Forced across the ocean, they became “African,” and started a long, painful
				transition to a distinctly African American culture that would help shape the New World.</p>
		</div><a href="#slug-early_colonization_efforts_in_north_america">
			<h2 id="slug-early_colonization_efforts_in_north_america">Early Colonization Efforts in North America</h2>
		</a>
		<div class="content-content">
			<p>Spain’s colonization of Central and South America extended to the Americas the process of formal conquest
				that had occurred in Spain itself in previous centuries. In contrast, northwestern Europeans’ ventures
				in America grew out of fishing and commerce, and initially made a more tentative impact on the
				continent. There were no powerful empires to be conquered, as Spain had overrun the Aztecs or the Incas.
				French, Dutch, and English explorers and traders pursued varied ambitions. During the seventeenth
				century, however, they established settlements that transformed this part of the continent as surely as
				the Spanish did further south.</p>
		</div><a href="#slug-exploration">
			<h3 id="slug-exploration">Exploration</h3>
		</a>
		<div class="content-content">
			<p>Early European contact with North America came with voyages of exploration. A French-sponsored venture
				under Giovanni da Verrazano in 1524 sailed the East Coast from the Carolinas to Maine (where, Verrazano
				wrote, some Abenakis “made all the signs of scorn and shame . . . such as showing their buttocks and
				laughing”). A decade later the Frenchman Jacques Cartier explored the St. Lawrence River. French and
				Dutch ventures looked for furs and other trade goods. The English began their contact as state-licensed
				pirates, attacking Spanish shipping in the hope of seizing some of the New World’s wealth for
				themselves.</p>
			<p>The first settlements arose from fishing. From the French and English coasts, men braved the Atlantic to
				catch cod in the rich fishing grounds off Newfoundland. They established semi-permanent camps ashore,
				for shelter and to process their catches. By 1620 these camps dotted the coastline from Newfoundland
				southwestward to what would become New England.</p>
			<p>Meanwhile, English adventurers sought more permanent North American settlements. In 1583, Sir Humphrey
				Gilbert, who had already helped found colonies in Ireland, claimed Newfoundland for England before his
				ship sank, with all hands, on its way home. The next year Sir Walter Raleigh planned a base from which
				to conduct raids on Spanish treasure fleets, and sent a small force of soldiers to Roanoke Island on
				North Carolina’s outer banks. In 1587, over one hundred people arrived to start a colony at Roanoke, but
				war with Spain delayed a ship bringing supplies to them. By the time it arrived in 1590 the settlers had
				disappeared without trace.</p>
			<p>Warfare continued to hinder ventures to North America until, after a peace settlement in 1604, the
				French, Dutch, and English resumed efforts to create permanent colonies. The English established a
				precarious settlement at Jamestown, Virginia, in 1607. The following year the French founded Quebec,
				which would become the center of their colony of New France; and in 1614 the Dutch established Fort
				Orange (Albany) on the Hudson River. In 1620, English religious dissenters known as the Pilgrims
				arrived, in the <em>Mayflower</em>, at what became Plymouth, Massachusetts. Ten years later, the first
				fleet of English Puritans, who were also seeking to establish a religious colony, sailed into
				Massachusetts Bay. By this time, several thousand English settlers were living on the shores of
				Chesapeake Bay in Virginia. By 1640 tens of thousands more had come to both Massachusetts and the
				Chesapeake. The English, French, and Dutch competed to secure their claims to parts of North America.
			</p>
		</div>
		<a href="#slug-the_french_and_dutch">
			<h3 id="slug-the_french_and_dutch">The French and Dutch</h3>
		</a>
		<div class="content-content">
			<p>In some respects French and Dutch colonization efforts differed. France aimed to dominate a vast sweep of
				territory from the St. Lawrence River valley through the Great Lakes region and down the Mississippi
				River. The French state backed merchants and missionaries who penetrated far into the backcountry,
				establishing close relationships with Native Americans and converting many to Catholicism. Dutch
				interest, primarily commercial and organized by the Dutch West India Company, focused on the
				Mid-Atlantic region, especially the Hudson River valley. Dutch merchants and settlers stayed closer to
				the coast. They brought their Protestant churches with them, but with a lesser commitment to missions
				Dutch religious beliefs had smaller impact on Native peoples lives than those of the French.</p>
			<p>In other ways, however, French and Dutch efforts were comparable. Both established agricultural
				settlements, but though the French government and the Dutch West India Company tried hard to recruit
				colonists, social conditions in France and Holland did not induce large numbers of people to want to
				become farmers in America. Half of the Dutch population were town-dwellers, many of them sharing in
				Holland’s considerable commercial prosperity. France was poorer, and mainly rural, but had low rates of
				internal migration, and hence relatively few potential overseas emigrants. There were only three
				thousand French people in New France by the early 1660s.</p>
			<p>More important to both countries was the fur trade. Dutch traders stayed close to their posts at Fort
				Orange and Nieuw Amsterdam (later New York City), but they obtained large quantities of furs in trade
				with the Haudenosaunees (Iroquois) and other Native nations. French fur traders and scouts (known as
				<em>coureurs de bois</em> or “forest runners”) traveled far into the interior. The fur trade
				overwhelmingly employed men, many of whom intermarried with Native people to create a substantial
				mixed-race (<em>méti</em>) population.
			</p>
			<p>French and Dutch colonization efforts significantly influenced North American development. Dutch
				families, legal structures, place names, and expressions helped shape early New York. The French
				presence in the Great Lakes region and the Mississippi Valley is still marked by hundreds of place
				names, while the descendants of French settlers still retain their distinct identity in Quebec and other
				parts of Canada. But the most lasting North American colonies would be English.</p>
			<p>Though the English took part in fishing and the fur trade, they became more concerned than the French or
				the Dutch with establishing settlements that occupied and cultivated the land. After the English
				captured New Netherland and renamed it New York in 1664 during one of several wars against Holland’s
				commercial empire, the Dutch relinquished their colony to secure more valuable territories elsewhere.
				Similarly, when British forces seized New France a century later in the French and Indian War (see
				Chapter 4), the French chose to give it up in return for keeping wealthier Caribbean sugar islands.</p>
		</div>
		<a href="#slug-the_english_colonial_experience">
			<h2 id="slug-the_english_colonial_experience">The English Colonial Experience</h2>
		</a>
		<div class="content-content">
			<p>The English colonies that came to occupy North America’s eastern seaboard were more than just land claims
				or commercial outposts. They became permanent homes for streams of migrants from the British Isles and
				elsewhere. Between 1620 and 1640 alone, almost forty thousand men and women left England to live in
				North America. Some English colonists, including the merchants who organized and financed expeditions,
				sought to make their fortunes. But a majority probably had more modest hopes: to achieve economic
				independence, or religious or political freedoms denied them at home. All were influenced by changes
				that had been taking place in England over the previous two centuries. The conditions that impelled them
				to leave for the New World shaped the character of English colonies, and the variations among them.</p>
		</div>
		<a href="#slug-the_roots_of_english_migration_to_america">
			<h3 id="slug-the_roots_of_english_migration_to_america">The Roots of English Migration to America</h3>
		</a>
		<div class="content-content">
			<p>In England, as elsewhere in Europe, the Black Death caused a catastrophic population decline in the
				fourteenth century. The resultant shortage of labor led, in time, to the collapse of English serfdom.
				Feudal landlords could no longer compel labor services from peasants, who resisted or fled to the
				comparative freedom of the towns. Lacking labor, landlords divided their fields, rented out plots to
				peasants, and began to live on the rents. Hired laborers benefited from rising wages. Though still
				dogged by poverty and disease, people working on the land were supported by a web of customary rights,
				including access to common land, where they might graze livestock, grow vegetables, or cut timber.
				Markets were also regulated, so profiteering was restricted and the price of bread controlled during
				times of shortage.</p>
			<p>But changing circumstances once more undermined peasants’ security. Population growth resumed in the
				fifteenth century. By 1500, landlords were demanding higher rents, usually in cash, and evicting tenants
				who could not pay. When Henry VIII broke with the Roman Church in the 1530s, he confiscated vast amounts
				of church land and granted it to his supporters among the aristocracy and gentry. Henry and—later—his
				daughter Elizabeth I also enhanced the lawmaking powers of Parliament, in which many nobles and gentry
				sat. Large landowners found their wealth and status increasing.</p>
			<p>They also had opportunities to squeeze higher earnings from their lands. As the textile industry
				expanded, wool-growing became more profitable, so many landlords evicted tenants to make room for sheep,
				or—by a practice called “enclosure”—fenced off common land on which tenants had relied for part of their
				livelihoods. Smallholders in Kent petitioned that “they were greatly relieved by [their] common and
				would be utterly undone if it should be unjustly taken from them.” Some tenants moved to woodland or
				upland areas where they could eke out a living. Thousands more became hired farmhands or weavers, left
				the land for the towns, or went to work as miners, sailors, or soldiers. Many single women were obliged
				to spin wool into yarn in isolated drudgery. By 1600, forty percent of English people were working for
				wages.</p>
			<p>Between 1520 and 1580 alone, England’s population grew from 2.5 million to 3.5 million, helping keep
				wages low. Yet prices for food, rent, and fuel rose fivefold between 1530 and 1640, an inflation helped
				by the influx of Spanish American gold and silver. War in the 1590s disrupted the cloth trade, throwing
				many out of work in textile districts, and poor harvests in the 1590s and 1620s caused hunger, even
				famine in a few places. Men and women tramped the countryside or flocked to towns, seeking work.
				London’s population quadrupled between 1500 and 1600, reaching at least 200,000. A clergyman wrote in
				1622 that the city was crowded with “people who rose early, worked all day and went late to bed, yet
				were scarce able to put bread in their mouths . . . [or] clothes on their backs.” In the view of
				England’s governing classes, poverty threatened to bring social disorder. Laws prohibited vagrancy, or
				punished “idleness” with imprisonment or public whipping, effectively compelling the poor to work for
				low pay and long hours in harsh conditions.</p>
			<p>Widespread poverty contrasted with the prosperity, not just of landowners but of urban merchants who had
				grown rich from textile manufacture or trade, and were willing to invest in new ventures. In return for
				supporting the monarchy, groups of merchants were granted special privileges, including monopolies of
				trade with particular parts of the world. Beneficiaries included the founders of the Muscovy Company
				(1553), the Spanish Company (1577), the Senegal Adventurers (1588), the East India Company (1600), the
				Virginia Company (1607), and the Massachusetts Bay Company (1629). These companies organized exploration
				and trade, and some began also to sponsor attempts at overseas settlement.</p>
			<p>From the 1560s onward the government had promoted English and Scottish “plantations” in parts of Ireland,
				displacing Catholic peasants from fertile land to make way for Protestant settlers. Some commentators
				came to see overseas colonization as a solution to English poverty. The poet John Donne suggested that
				it would “sweep your streets, and wash your doors, from idle persons, and the children of idle persons,
				and employ them,” while Sir Francis Bacon saw it as a cure for “rebellions of the belly” brought on by
				the reorganization of agriculture.</p>
			<p>By the early seventeenth century, the elements of English overseas colonization were in place: merchants,
				shipowners, and landholders ready to seek out new sources of profit; a Crown prepared to grant special
				rights to promote English and Protestant expansion; and a sizable population of mobile poor, who might
				provide the labor for schemes of settlement. Poor people migrating to towns in search of work
				encountered promoters who offered passage to the New World in exchange for a few years’ labor. Many men
				and some women opted to travel to North America as “indentured servants” (bound to labor by contracts
				called indentures). They took with them a legacy of hardship and injustice, a suspicion of landlords,
				hope for some land of their own, and a determination to defend popular rights.</p>
		</div>
		<a href="#slug-colonizing_the_chesapeake">
			<h3 id="slug-colonizing_the_chesapeake">Colonizing the Chesapeake</h3>
		</a>
		<div class="content-content">
			<p>The first English settlement at Jamestown, Virginia, established in 1607 by the Virginia Company of
				London, mimicked the fantasies of easy wealth that had first driven the Spanish to the Americas.
				Virginia, its promoters hoped, would furnish precious metals or valuable plants. Explorers’ accounts
				misled settlers into expecting a paradise where they could gather food without effort, need little
				clothing or shelter, and make docile Native people work for them. The one hundred and four men and boys
				who founded Jamestown had no idea how to build a permanent farming settlement. About one in five were
				“gentlemen,” who considered manual labor to be beneath them. Most of the rest were unskilled laborers,
				military recruits, and servants. The few craftsmen included clockmakers, jewelers, and gentlemen’s
				perfumers.</p>
			<p>Instead of the paradise they had expected, they found a harsh, disease-ridden place. One of its leaders,
				John Smith, remarked that early Jamestown was “a miserie, a ruine, a death, a hell.” Supplies dwindled
				and fields remained uncultivated while starving gentlemen passed the time playing bowls. Far from being
				willing to work for them, watching Native people waited for the English intruders to die. Most did. The
				thirty-five who survived until spring 1608 were about to abandon the colony when new settlers and
				supplies arrived.</p>
			<p>For the next decade, Virginia Company officers sought to impose order. They introduced harsh military
				discipline, divided servants into work gangs and viciously punished infractions of the rules.
				Punishments varied according to rank. For lesser crimes, the wealthy paid fines while the poor were
				whipped, branded, or had body parts cut off. Serious offenses were punished by death, and servants were
				often mutilated before and after execution. Men worked in the fields while the handful of women, such as
				Ann Leyden and June Wright, stitched shirts and performed other household tasks. When their work was
				judged inadequate, an eyewitness recorded, the women were “whipped, and Ann Leyden being then with
				child, the same night thereof miscarried.” Settlers could not return to England without permission, and
				their often pitiful letters home were censored. Coercive methods maintained the colony in a bleak,
				precarious existence, setting precedents for the later introduction of slavery.</p>
			<p>Soon, however, the Virginia Company found that it could use its servants to make money. In 1611 the
				company began to grow tobacco, which had become popular in England for its supposed medicinal
				properties. Demand soared. Within a few years the company, and those who acquired land from it, turned
				wholeheartedly to tobacco cultivation. Virginia’s fertile soil and long growing season were suited to
				tobacco. Tidal rivers made the interior accessible to the vessels that would carry the crop across the
				Atlantic. The colony boomed. Tobacco exports rose from 2,000 pounds in 1615 to 1.5 million pounds just
				fifteen years later.</p>
			<p>To entice more people to go to Virginia and grow tobacco, the Virginia Company offered land in return for
				labor or other services. Skilled artisans would receive “a house and four acres as long as they plied
				their trades.” A man willing to cultivate new land could receive fifty acres for himself and another
				fifty for every person he brought to the colony. Indentured servants were promised land at the end of
				their terms of service. For a settlement whose population was overwhelmingly male, young, and single,
				the company shipped in women to sell as wives to men who could pay 120 pounds of tobacco for them.</p>
			<p>The company also took steps to foster support from landowning settlers. It softened martial law. In 1619
				it set up the House of Burgesses, an assembly to which all adult freemen could elect representatives to
				share government with company officers. Between 1619 and 1625 nearly 5,000 new settlers arrived. But
				such numbers outgrew the Virginia Company’s military organization, and in 1624 King James I dissolved
				the company, making Virginia a royal colony under his direct supervision.</p>
			<p>Early Virginia was an armed camp where individualism, competition, and fear prevailed. Men scrambling for
				wealth had little time for public spirit or civic cooperation. Rather than building towns or villages,
				tobacco planters scattered along the navigable rivers. The most successful owned hundreds of acres, but
				most lived like their servants in crude shacks, miles from neighbors. Planters abused servants with
				“intolerable oppression and hard usage.” Death rates stayed high. Over seven thousand people migrated to
				Virginia between 1607 and 1625, but the colony’s population was only 1,200 when the Virginia Company was
				abolished.</p>
			<p>As well as hunger and disease, settlers faced the risk of attacks by the Powhatans. The first colonists
				had provoked the local Algonquian-speakers by stealing food from them, and within two years, their&nbsp;
				leader, Powhatan, declared war, noting that the English “comming hither is not for trade, but to invade
				my people, and possesse my country.”&nbsp;In the diplomacy that patched up this dispute in 1614,
				Powhatan permitted his daughter Pocahontas to marry the Englishman John Rolfe, though she fell ill and
				died while visiting England in 1617. Meanwhile, the Virginia colony continued to grow, and so too did
				its demand for land. Conflicts twice more erupted into war, as Powhatan’s brother and successor
				Opechancanough led campaigns against the settlers. During the first, in 1622, his men killed 347
				colonists, prompting the English to promise not to encroach on tribal land. But by 1644, with the
				Virginia colony’s population at 8,000, settlers’ encroachments again caused hostilities. More than five
				hundred colonists died in the struggle before Opechancanough was captured and killed in 1646, and the
				Powhatans signed a treaty acknowledging English authority.</p>
			<p>By this time, the colony of Maryland had been founded adjacent to Virginia in the upper part of
				Chesapeake Bay, under a royal charter granted in the early 1630s to the Earl of Baltimore. Baltimore, a
				Catholic convert, sought a refuge for fellow Catholics facing persecution in England. His family planned
				to establish feudal manors, with land leased to tenant farmers. But the promise of land and of profits
				from tobacco cultivation attracted migrants, both Protestant and Catholic. To obtain support, the
				proprietors had to modify their plans, offering land to own as well as rent, and permitting the
				formation of a representative assembly of freemen. Migration to both Chesapeake colonies continued to
				grow. By 1660, about 50,000 people had crossed the Atlantic to settle there.</p>
		</div>
		<a href="#slug-colonizing_new_england">
			<h3 id="slug-colonizing_new_england">Colonizing New England</h3>
		</a>
		<div class="content-content">
			<p>The Virginia Company had hoped to attract members of the English gentry to America, and recruited
				servants from among the poor, single, and young. But many among the “middling sort,” too, were
				discontented in England. The Protestant reformers known as Puritans, especially, distrusted the policies
				of the Stuart kings James I and Charles I and faced a measure of persecution.</p>
			<p>Puritans included gentry, village craftsmen and small landowners, urban merchants and artisans. Their
				difficulties arose from theological disputes thrown up by the Reformation. They followed the doctrine of
				John Calvin, that one’s fate after death was predestined by God, rejecting the “Arminian” doctrine
				(named for a Dutch theologian, Jacobus Arminius) that human actions could influence whether one was
				saved or damned. Although most Puritans worshiped in the Church of England, they objected to its
				ornateness, its ritual, and the authority of Arminian bishops. They emphasized the authority of God’s
				Word in the Bible, and feared that the Stuarts were leading a return to Catholicism.</p>
			<p>Puritans loathed England’s disorder, its extremes of wealth and poverty, and what they saw as its
				sinfulness. Regarding churches as communities of the godly, they assembled for preaching, not ritual,
				and sought to choose their own ministers. Some who advocated separation from the English church had
				already faced persecution. These included the Pilgrims, who had spent ten years’ voluntary exile in
				Holland before sailing to New England in 1620. After 1625, Archbishop of Canterbury William Laud pressed
				for conformity in the Church, and other Puritans began to look for a place where they could avoid
				England’s evils, and build their own godly society for the world to see.</p>
			<p>When investors formed the Massachusetts Bay Company in 1629, a group of Puritans led by John Winthrop
				turned it into a vehicle for their plans. The company’s charter granted it political and economic rights
				in New England and, unusually, failed to require that company meetings be held in England. Taking
				advantage of this technicality, Winthrop and his recruits sailed in 1630 to found a colony in
				Massachusetts armed with the right to govern their own affairs. The charter would remain the colony’s
				legal basis until 1684.</p>
			<p>Once arrived in Massachusetts, Winthrop and his followers abandoned the plan to make profits, closed
				membership in the Massachusetts Bay Company to investors, and reserved it instead for male members of an
				organized Puritan church. The political leadership of Massachusetts comprised Winthrop, the colony’s
				governor, and the General Court, its governing body. A tax protest in 1632 obliged Winthrop to make the
				General Court a representative body. Over the next decade, more than twenty thousand English migrants,
				mainly Puritan families with their children and servants, arrived to establish new farms and communities
				on New England’s rocky soils, aiming to build for themselves a way of life that England denied them.</p>
			<p>Winthrop and his followers began by establishing Boston and a ring of towns around it. They incorporated
				ramshackle camps previously set up on the coast by English fishing crews, forming towns such as Salem,
				Marblehead, and Gloucester. They also made connections with the Pilgrims’ Plymouth Colony, which would
				remain separate from Massachusetts Bay until 1691.</p>
			<p>By the mid-1630s political disputes and growing numbers led the Puritan colonists to expand their
				settlements to the south and west. When the government expelled him in 1635 for questioning its
				authority, the minister Roger Williams led followers into nearby Rhode Island to found a colony that
				would become a haven for exiles from Puritan orthodoxy. Migrants from Plymouth and Massachusetts
				established the separate colonies of Connecticut and New Haven. Outbreaks of smallpox in 1633 had
				devastated Native populations in these areas. “It pleased God to visite these Indians with a great
				sickness,” wrote Plymouth governor William Bradford; so many died that “many of them did rott above
				ground for want of buriall.”</p>
			<p>More than profits, Puritans were pursuing religious and community ideals. They were attached to owning
				their own property, but they set up community institutions to regulate one another.&nbsp; For most of
				these hardworking men and women, the ideal society revolved around cooperation rather than
				individualism. When two Puritan noblemen inquired in 1635 about migrating to Massachusetts, they were
				told that they would be welcome but would receive no special privileges. Neither came. Establishing
				their towns and farms in a land they saw as a “wilderness,” New Englanders created one of the important
				templates for early American society in the northern colonies.</p>
		</div>
		<a href="#slug-the_english_revolution_and_its_effects_on_the_colonies">
			<h3 id="slug-the_english_revolution_and_its_effects_on_the_colonies">The English Revolution and Its Effects
				on the Colonies</h3>
		</a>
		<div class="content-content">
			<p>In England, meanwhile, economic dislocation, religious conflict, and political instability were
				deepening, and by 1642 brought on a civil war, a period of upheaval called the English Revolution that
				was to have important ramifications both in England and in the colonies. Since 1629 Charles I had ruled
				without calling Parliament into session, asserting a monarch’s “divine right” to govern and levy taxes.
				Puritans were among many in England who opposed such arbitrary rule and insisted that Parliament be
				consulted. Forced to recall Parliament in 1640 to raise taxes in order to quell a rebellion in Scotland,
				Charles found it resistant and within two years had provoked open warfare by attempting to suppress it.
				After two periods of bitter fighting, the king was arrested and, in early 1649, executed. England became
				a republic, led by the Puritan Oliver Cromwell until his death in 1658.</p>
			<p>The Civil War brought social upheaval and an upsurge of religious and political debate in England. As it
				began Puritans stopped leaving for Massachusetts, and some returned home from the colony, since England
				itself might now become (as one minister put it) “a land of saints and a pattern of holiness to all the
				world.” Radicals questioned almost every facet of established society. Poor and middling men and women,
				calling themselves Levellers, Diggers, Seekers, or Ranters, attacked the Church’s right to levy tithes
				(a one-tenth share of crops or income), and questioned enclosures, wage labor, and even property itself.
				They asked why more people should not have the vote, and whether heaven and hell were inventions of the
				rich to keep the poor in subjection. A growing sect known as Quakers, who stressed the authority of the
				divine “inner light” in all believers, condemned religious, civil, and social hierarchy. Quaker women as
				well as men preached and prophesied.</p>
			<p>Faced with what they saw as expressions of anarchy, England’s propertied classes brushed aside many of
				these radical voices and, after Cromwell’s death, closed ranks to arrange for the restoration of the
				monarchy under Charles II in 1660. But the English Revolution left a rich legacy of ideas for those who,
				in the future, would criticize monarchy or rule by the rich. Even as they put a king back on the throne,
				English elites recognized that rulers had obligations to their people, and that a people could
				justifiably depose a monarch who failed to honor these. English people who shared such attitudes,
				including many Quakers, were among those who took passage to America later in the seventeenth century.
			</p>
			<p>The Revolution also accelerated England’s commercial development and social polarization. It limited the
				monarch’s taxing power and abolished many aspects of feudal land-ownership, but it confirmed the
				property rights of landowners and cleared the way for further enclosure and agricultural improvement,
				strengthening ties between agriculture, commerce, and monied interests.</p>
			<p>Both Cromwell and the restored monarchy pursued vigorous policies to regulate trade, promote colonies,
				and fight wars with commercial rivals, particularly the Dutch. Guided by economic doctrines loosely
				known as “mercantilism,” which held that overall wealth was roughly fixed, and that states could only
				enrich themselves by diverting flows of income from rival nations, English governments passed trade
				laws, including the Navigation Acts, aimed at ensuring a net inflow of wealth into the country. Overseas
				colonies would be an important source of commodities and raw materials for England’s development. Later
				policies would also seek to expand colonial markets for English goods, again with the aim of assuring
				profits for the mother country.</p>
		</div>
		<a href="#slug-native_americans_decline_resistance_exchange">
			<h2 id="slug-native_americans_decline_resistance_exchange">Native Americans: Decline, Resistance, Exchange
			</h2>
		</a>
		<div class="content-content">
			<p>English attitudes to American colonization had been shaped by their earlier conquest and settlement of
				parts of Ireland. “Planters” in Ireland disdained the Gaelic Irish peasants whose land they occupied,
				considering them to be “savages.”&nbsp; Some early settlers in America compared the Native peoples they
				encountered favorably with the hated Irish, but often the settlers’ view of the Irish prepared them to
				hold similar contempt for Native Americans.</p>
			<p>Many Virginians and New Englanders perceived Native Americans as inferior because they spoke in strange
				tongues, cultivated with hoes rather than plows, and had no concept of property accumulation. William
				Simmonds wrote of Virginia in 1612 that “we found only an idle, improvident, scattered people, ignorant
				of the knowledge of gold, or silver, or any commodities; and carelesse of anything but from hand to
				mouth.” To the English such attitudes justified misunderstandings over theft, the seizure of Native
				land, and the subjugation or expulsion of Native peoples they found in their way. They also influenced
				reactions to the destruction of Native people by disease. Local inhabitants, wrote one of the first
				Massachusetts settlers in 1630, “above twelve years since were swept away by a great &amp; grievous
				Plague . . . so that there are verie few left.” Like many Puritans he saw the epidemic as part of God’s
				design to clear the land for His chosen people.</p>
			<p>Yet Native poeples were not simply victims of disease and conquest. What happened to Native Americans
				depended not only on what settlers demanded of them, but also on their own actions and the character of
				their own societies. Even on North America’s eastern seaboard, where Native cultures were targeted early
				on by the nineteenth century, over two hundred years of conflict and negotiation followed European
				contact.</p>
		</div>
		<a href="#slug-adaptation_and_negotiation">
			<h3 id="slug-adaptation_and_negotiation">Adaptation and Negotiation</h3>
		</a>
		<div class="content-content">
			<p>Native peoples first tried to incorporate settlers into their own systems of authority. At Jamestown in
				1607 and 1608, Powhatan treated Virginia leaders just like the other local chiefs who owed allegiance to
				him, and his offer of Pocahontas in marriage to John Rolfe in 1614 was part of an effort to control the
				English. Opechancanough’s challenges to the growing Virginia settlements aimed to set bounds on the
				colony’s expansion and on unreasonable English behavior. A Wicomesse leader told Maryland’s governor in
				1633 that “since . . . you are heere strangers and come into our Countrey, you should rather confine
				yourselves to the Customes of our Countrey, than impose yours upon us.”</p>
			<p>To some groups, neighboring nations posed more problems than Europeans, and they saw settlers as allies
				in their rivalries with them. Ndé (Apache) peoples&nbsp;attacking Pueblos in the Southwest made them
				more vulnerable to Spanish domination. Algonquian-speakers in the St. Lawrence valley, under pressure
				from hostile Haudenosaunees, turned to the French for help and built an alliance that enabled the
				Algonquians to hold&nbsp;Haudenosaunees back and reach a settlement with them in the 1690s. English
				settlers found themselves used for similar ends.</p>
			<p>Yet the growth of European settlements did oblige Native cultures to adapt. From bands based on kinship
				they formed more structured “tribes” and/or "nations." The fur trade brought irreversible changes. The
				Mi'kmaqs&nbsp;(Micmacs)&nbsp;of Nova Scotia found themselves trapped by it. Dependent entirely on
				hunting and fishing,&nbsp;Mi'kmaqs&nbsp;ensured their survival by avoiding overhunting. But when
				European traders offered guns, cloth, ironware, and alcohol, they increased their hunting to obtain the
				pelts to trade for these goods. Soon their beaver were gone, the traders and their goods moved on, and
				Mi'kmaqs unable to support themselves.</p>
			<p>As hunters depleted beaver populations in coastal regions, they moved inland to search for fresh
				supplies, in the process colliding with other groups. Demand for pelts set nations against nations, and
				competing Europeans were usually pleased to sell arms to the rivals.&nbsp;Along the Hudson River, Dutch
				traders at first obtained furs from local Mohicans<strong>&nbsp;</strong>(Mahicans). But as their beaver
				dwindled, Mohicans were pushed aside by Kanien'kehá:kas (Mohawks), who set up a regular supply of furs
				from the Haudenosaunee interior.</p>
			<p>Wars among Native polities not only caused many deaths, but also reshaped Native polities’ territories
				and alliances. Greater reliance on hunting and warfare widened the gap between male and female roles,
				reducing the importance of agriculture, strengthening the power of men at the expense of women, and
				enhancing the claims of hunters and warriors to leadership.</p>
			<p>Such changes often left Native peoples with stark alternatives. They could labor for their European
				conquerors, or they could (like some Mohicans and Susquehannocks) move inland and be assimilated into
				more powerful groups that might successfully resist European encroachment. Wampanoags of Nantucket
				Island took the first path. Puritan traders advanced them goods, but they fell into debt, which they
				were obliged to work off by going to sea as crewmen on fishing vessels or whaleboats. But they found
				that they could never earn enough to settle their accounts, and were trapped in a cycle of debt and
				forced labor that weakened their community. In 1600 they were about 2,500 strong; two centuries later
				only 22 of them remained.&nbsp; The Catawba of the Carolinas negotiated their survival by making
				themselves useful to colonists, accepting in the process significant changes to their own culture and
				forming alliances with the English against neighboring nations.</p>
		</div>
		<a href="#slug-resistance_and_warfare">
			<h3 id="slug-resistance_and_warfare">Resistance and Warfare</h3>
		</a>
		<div class="content-content">
			<p>Few coastal peoples managed to resist colonial encroachment successfully. Their groups were small and
				fragmented. On the southern New England coast, the Pequots were at first strengthened by European
				contact. They traded furs from the interior to Dutch and English shippers and built up their military
				power. The 1630s, however, brought epidemics and then encroachment by English settlers moving west from
				Massachusetts Bay. To resist the English, the Pequots joined with other nations and attacked colonists’
				farms and towns. But the English made their own alliances with the Pequots’ rivals, including the
				Narragansetts. Attacking a Pequot village in 1637, English soldiers burned or hacked to death more than
				four hundred men, women, and children, while their Native allies encircled the site to prevent any
				Pequots from escaping. When the Pequot War ended, the English executed many captured warriors, sold
				women and children into slavery, and dispersed the remaining Pequots to other Native nations.</p>
			<p>The Narragansetts, who had helped the English destroy the Pequots, soon began to ponder their own
				prospects for survival. One leader, Miantonomoh (Miantonomi), traveled across southern New England and
				Long Island in the early 1640s to arrange a pact, warning of what would be lost if the English were not
				turned back. But the colonists, helped by Mohegan allies, silenced Miantonomoh. The Mohegans captured
				him, delivered him to a Massachusetts court for trial on a trumped-up murder charge, and then executed
				him when the court convicted him and returned him to them for punishment.</p>
			<p>Other Native peoples sought greater association with the colonists. Puritan missionaries in Massachusetts
				established towns for “praying Indians,” who were converted to Christianity and settled on farms. There
				were fourteen such towns by the early 1670s. Yet even these converts never allayed English suspicion of
				Native peoples. In time the choice of the “praying Indians” to seek a form of assimilation with the
				colonists would help little to preserve their own communities.</p>
			<p>Wampanoags, who had so far maintained cordial relations with both the Massachusetts and Plymouth
				colonies, came under pressure from new settlements in the 1650s and 1660s. Under their leader Metacom,
				whom the English called “King Philip,” they sought decisively to reverse such encroachment. After
				repeated provocations, Wampanoags began attacking outlying eastern Massachusetts towns in 1675, at first
				acting alone, then in alliance with the Nipmucks of the Connecticut Valley and with the Abenaki and
				others on the Maine coast. When colonial soldiers searching for Wampanoags massacred three hundred
				people, mostly women and children, in Narragansett settlements, they pushed the Narragansetts into
				Metacom’s alliance, too. Colonists suffered heavily in consequence. Of their ninety towns, twelve were
				wiped out and forty more damaged. One-tenth of New England’s adult white male population was killed or
				captured. It looked as if Metacom might succeed in turning back English settlement.</p>
			<p>Yet the colonists proved too well-established to dislodge. New Englanders forged their own alliances and
				took harsh measures. Distrusting even the “praying Indians” the Massachusetts government forcibly
				interned them on an island in Boston Harbor. Kanien'kehá:kas (Mohawks) allied with the colonists
				weakened Metacom’s forces in battle, and in 1676, colonial fighters cornered Metacom in a swamp and
				killed him. Most Native resistance then collapsed, although in Maine the Abenakis sustained their
				attacks into 1677. “King Philip’s War,” as the English called it, marked the defeat of armed Native
				resistance in eastern and southern New England, though conflicts continued in the region’s interior for
				some decades to come.</p>
			<p>In the Spanish territories, extreme labor demands and missionary efforts provoked more successful
				resistance. Florida nations rebelled against missions repeatedly from the 1590s to the 1650s. Although
				it was difficult to coordinate their attacks, the nations nevertheless survived in the swamps and, after
				1680, even began to drive the missions out. Pueblos in the New Mexico region only partially submitted to
				Spanish conversion efforts and demands for forced labor. Some Christian “converts” covertly adhered to
				their Native beliefs. Sporadic revolts from the 1630s onward took advantage of the Spanish remoteness
				from their Mexican bases and the rivalry between missions and farming estates.</p>
			<p>In 1680, under a leader called El Popé, a concerted uprising swept the eastern Pueblo villages, killing
				settlers and priests and driving the Spanish out of New Mexico in panic.&nbsp;For over a decade the
				Pueblos were free from intrusion, until a campaign in 1692–1693 reconquered them. Even then, Pueblos
				continued to resist, rebelling when participants in the revolt were executed, preventing the
				reimposition of the <em>encomienda</em> system, and so obliging Spanish settlers to take up ranching
				rather than farming. Pueblos, now weakened by population decline and by Ndé and Numunuu (Comanche) raids
				from the north, worked out a way of coexisting with the Spanish that largely preserved their own
				identity.</p>
		</div>
		<a href="#slug-coexistence_on_the_middle_ground">
			<h3 id="slug-coexistence_on_the_middle_ground">Coexistence on the Middle Ground</h3>
		</a>
		<div class="content-content">
			<p>Coexistence, rather than collapse or resistance was, indeed, common for Native peoples whose lands were
				not directly subject to European settlement. Among the most successful at holding settlers at arm’s
				length were the Haudenosaunees, whose organization and coherence increased under European pressure.
				Until the mid-eighteenth century, much of upland eastern North America, the Great Lakes, and Mississippi
				Valley formed an arena of exchange and interaction between Native people and Europeans which historians
				now term “the middle ground.” After early setbacks and consolidations, some nations stabilized control
				over their fields and hunting grounds, and probably even achieved modest population growth. Many
				regarded themselves as superior to the invading Europeans, whose actions they saw as uncivilized. In
				these societies, too, women initially retained much of their status and authority.</p>
			<p>The fur trade with English, French, or Dutch merchants provided Native peoples with metalwares, guns,
				blankets, or rum. These exchanges could lead to dependency, and many Europeans and some Native leaders
				saw alcohol especially as a source of exploitation. Settlers enjoyed stories of Native people accepting
				trinkets in payment for furs or even land. But trade was often not as one-sided as it appeared. Native
				peoples sought goods that were useful to them; knives, guns, pans, and cloth made hunting or survival
				easier. And Europeans could seem naive. “[T]he English have no sense,” laughed a member of the Innus
				(Montagnais)&nbsp;on the St. Lawrence River; “they give us twenty knives for this one beaver skin.”
				Although frontier exchange could provoke antagonism and conflict, Native peoples conducted their
				dealings with white people as equals or superiors, and demanded a measure of deference from them. Until
				circumstances changed, many Native people would hold their ground.</p>

		</div>
		<a href="#slug-conclusion_the_remaking_of_three_worlds">
			<h2 id="slug-conclusion_the_remaking_of_three_worlds">Conclusion: The Remaking of Three Worlds</h2>
		</a>
		<div class="content-content">
			<p>Europeans’ intrusion into the Americas profoundly altered the ways of life of three previously
				independent worlds. New World exploration, trade, and settlement linked the peoples of Europe, Africa,
				and the Americas in patterns of commerce, conflict, and labor coercion.</p>
			<p>Africa was the most evident loser. The slave trade, with its grievous drain of population and cultural
				dislocation, profited some powerful Africans, but few others except Europeans benefited. It impoverished
				much of the African continent, disrupted trade, and altered political structures. Before 1500, West
				African economies had living standards comparable with much of Europe. Slavery, external and internal,
				greatly weakened them, leaving Africa susceptible to colonization by European powers in the nineteenth
				century. The forced movement of enslaved persons from Africa to the Americas long exceeded the scale of
				European transatlantic migration. Until about 1800 six out of every seven people arriving in the
				Americas were enslaved Africans. Most were taken to Brazil, Central America, or the West Indies. Only
				about five percent went to British North America.</p>
			<p>On the Americas themselves, the European impact was mixed. Major Central and South American empires
				collapsed and were rapidly incorporated into colonial societies. As Europeans established new
				settlements, vast numbers of Native Americans were killed by disease or war, or driven to find new
				places to live. In North America, most eastern seaboard groups declined or retreated in the face of
				invasion, disease, and dispossession. Those in the interior or in the Spanish borderlands had some
				success in resisting deeper invasion, and at adapting their cultures to the new situation. But even
				peoples who had little direct contact with Europeans felt their influence.</p>
			<p>Not surprisingly, Europeans were the main beneficiaries of colonization. To notables who received land
				grants, absentee planters who controlled crop production, and merchants in the Atlantic trade, it
				brought new wealth, though this also sustained social divisions in European societies. Colonial goods
				changed European tastes. Sugar from the Caribbean and Brazil brought confections to Europeans of
				middling rank that were once enjoyed only by the very wealthy. Virginia tobacco swept Holland and
				England early in the seventeenth century, and its popularity continued to mount. The period of early
				colonial settlement initiated a lasting dependence on overseas commodities that would affect all levels
				of European society in the centuries to come.</p>
			<p>Profits from colonial trade helped to transform European economies. By 1600, two hundred ships each year
				were arriving in Spain, laden with treasure from the Spanish empire. This increasingly found its way to
				the trading cities of northern Europe, inflating prices but boosting commerce and urban growth, and
				helping to finance further overseas expansion. Spain, France, and Britain all saw North America as an
				arena for territorial acquisition and rivalry; throughout the eighteenth century they would fight wars
				to gain greater control of the continent.</p>
			<p>White settlers in Spanish, French, and English America, meanwhile, built an array of new societies. All
				started to see their interests as different from those of the countries they had come from. In Spanish
				colonies, where high officials rotated through offices in order to make careers back home, distinctions
				emerged between Spanish-born <em>peninsulares</em> and American-born <em>criollos</em> (creoles).
				Settlers and Native Americans intermarried at a high rate. Mixed-race mestizos outnumbered the Spanish
				in Mexico after 1650 and among the “Spanish” who migrated northward into New Mexico.</p>
			<p>In the English colonies the distinction between English- and American-born settlers was never as formal
				as in the Spanish empire. English-Native American intermarriage was also much rarer. Still, population
				growth and migration increased the proportion of American-born “English” people with no direct ties to
				England. In the context of colonial rivalry and wars from the mid-eighteenth century on, these
				American-born colonists would radically alter their relationships both with England and with Native
				Americans.</p>
			<p>The settlers of North America continued, above all, to need labor. The differences in the ways they
				procured it would have profound implications for the future. This was particularly true of the different
				labor patterns that developed in the northern and southern colonies of British North America.</p>
		</div>
