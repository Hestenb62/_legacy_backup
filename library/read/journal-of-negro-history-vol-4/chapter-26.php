<h2><a name="No4_a8" id="No4_a8"></a>
NOTES</h2>


<p>To facilitate the study of Negro history in clubs and schools, Dr. C.
G. Woodson has prepared an illustrated text-book entitled <i>The Negro
in our History</i>. It has been sent to the publishers and is expected
from the press the first of the year. The book has a topical
arrangement but the matter is so organized as to show the evolution of
the Negro in America from the introduction of slavery in 1619 to the
present day. The topics are: <i>The Negro in Africa</i>, <i>The Enslavement
of the Negro</i>, <i>Slavery in its Mild Form</i>, <i>The Negro and the Rights
of Man</i>, <i>The Reaction</i>, <i>Economic Slavery</i>, <i>The Free Negro</i>,
<i>Abolition</i>, <i>Colonization</i>, <i>Slavery and the Constitution</i>, <i>The
Negro in the Civil War</i>, <i>The Reconstruction</i>, <i>Finding a way of
Escape</i>, <i>Achievements in Freedom</i>, <i>The Negro in the World War</i>, and
<i>The Negro and Social Justice</i>.</p>

<p>The aim of the author is to meet the long felt need of a book of
fundamental facts with references and suggestions for more intensive
study. While it is adapted for use in the senior high school and
freshman college classes, it will serve as a guide for persons
prosecuting the study more seriously.</p>

<p>Just as soon as this book has come from the press the Association will
send to all Negro schools of secondary and college grade a field agent
to interest them in the effort to inculcate in the mind of the youth
of African blood an appreciation of what their race has thought and
felt and done. The cooperation of all persons taking seriously the
effort to publish the records of the Negro that the race may not
become a negligible factor in the thought of the world, is earnestly
solicited. Any suggestions as to how this work may be more
successfully prosecuted and as to extending it into inviting fields,
will be appreciated.</p>


<p>Dr. W. E. B. DuBois and his coworkers are preparing a History of the
Negro in the World War to be published about October.</p>



