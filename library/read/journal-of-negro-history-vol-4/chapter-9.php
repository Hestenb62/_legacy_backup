<h2><a name="No1_a13" id="No1_a13"></a>
NOTES</h2>


<p>Within a few years from the time the United States army will be
reduced to a peace status, the Association for the Study of Negro Life
and History will publish a scientific history of the Negro soldiers in
the great war. As this effort will require a large outlay, it is
earnestly desired that persons interested in the propagation of the
truth will give this movement their support. A campaign for funds has
begun and the encouragement hitherto received indicates that the
amount necessary to finance this enterprise will be secured.</p>

<p>At present it is impossible to indicate exactly the extent of this
work. It will be first necessary to make an extensive research into
all of the sources of information as to the Negroes' participation in
the war and when the data thus collected will have been properly
digested, a more detailed description of the work may be forecasted.
It is safe to say, however, that the work will consist of several
volumes written by the Director of Research.</p>

<hr class="short" />

<p>This same interest is set forth, as follows, in an item appearing in
the December number of the <i>Crisis</i>:</p>

<blockquote><p>"The National Association for the Advancement of Colored People
has appropriated funds and commissioned the Director of
Publications and Research to collect the data and compile a
history of the Negro in the Great War.</p>

<p>"Dr. DuBois has invited a number of Negro scholars, soldiers and
officials to form an Editorial Board, which will be able to issue
an authentic, scientific and definitive history of our part in
this war.</p>

<p>"The personnel of this board will be announced later. Meantime,
we want the active co&ouml;peration of every person who can and will
help. We want facts, letters and documents, narratives and
clippings. Let us all unite to make the record complete.
Correspondence may be directed to this office."</p></blockquote><p><span class='pagenum'><a name="Page_109" id="Page_109">[Pg 109]</a></span></p>

<p>The following important announcement appeared in the December number
of the <i>Crisis</i>:</p>


<p class="center sc">Tercentenary</p>

<p>The husband of Pocahontas wrote in 1619: "<i>About the last of August
came a Dutch man of warre that sold us twenty Negars</i>." From this
beginning sprang the present twelve million Americans of Negro
descent.</p>

<p>Next August will mark the Three Hundredth Anniversary of this vast
transplantation of a race, which ranks easily as one of the most
significant movements of mankind. Such an event can hardly be
"celebrated," for it connoted too much of misery and human sorrow. On
the other hand, it is too stern and meaningful a happening to be
forgotten. For this reason, a group of thirty-three colored men met in
New York, October 19, 1918, at the invitation of a committee appointed
by the National Association for the Advancement of Colored People.</p>

<p>They determined to inaugurate "A Solemn Memorial of the Tercentenary
of the Transplanting of the Negro race to the United States." In
order, however, to give all sections and interests of the Negro race
adequate voice and representation in these plans, this committee set
about choosing a Committee of "Three Hundred and More," in whose hands
the Memorial will take final shape. This Committee is now being chosen
and will meet in New York early in January, 1919.</p>

<hr class="short" />

<p>The <i>Linchoten Vereeniging</i> has published for Mr. E. C. Godee
Mossbergen two volumes of <i>Reizen in Zuid-Afrika in de Hollandse
Tijd</i>.</p>

<hr class="short" />

<p>From the press of Longsman two volumes bearing on Africa have been
published. One is by Sir Hugh Clifford, entitled the <i>German
Colonies</i>, with special relation to the native population of Africa.
The other, by H. C. O'Neill, is the <i>War in Africa and the Far East</i>,
dealing largely with the conquest of the German colonies.</p>

<hr class="short" />

<p>Houghton, Mifflin and Company have published a study entitled <i>Lincoln
in Illinois</i> by Miss Octavia Roberts. This work is largely a
compilation of the recollections of his contemporaries.<span class='pagenum'><a name="Page_110" id="Page_110">[Pg 110]</a></span></p>

<hr class="short" />

<p>To extend the work of the Association the Director of Research is now
making an effort to secure the cooperation of five persons who, like
Mr. Julius Rosenwald, will contribute $400 annually to the support of
this cause. Mr. Moorfield Storey and Mr. Cleveland H. Dodge have each
pledged themselves to give this amount. It is earnestly hoped that
other philanthropists will subscribe.</p>

