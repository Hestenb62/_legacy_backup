<p><i>Dear Pastor:</i> I have join the church up here and I authorize the
church to write for my letter of dismission but they say they
have not heard enything from the church at all. Sister &mdash;&mdash;
&mdash;&mdash; wrote to you she ask for my letter so I can join here in full
and if the church hold me for enything on why say to them I will
know what to do. I have never herd eny thing from my credental
from<span class='pagenum'><a name="Page_464" id="Page_464">[Pg 464]</a></span> old man Bonnett. I sent him a letter and also credencil for
him to sign and sent stamps for him send them and he fail to let
me here fum him at all, so I thought you would here fum him
befour know &amp; got him to tend to it for me so dear pastor let me
here from you and be shure to send me my letter of dismission By
Return mail my famil send they regaurd to you and wife they
planning to send some on they salary love to who may ask about
