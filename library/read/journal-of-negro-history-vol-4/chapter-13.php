<h2><a name="No2_a4" id="No2_a4"></a>
NOTES</h2>


<p>To increase our circulation and the membership of the Association the
management has employed as Field Agent Mr. J. E. Ormes, formerly
connected with the business department of Wilberforce University. Mr.
Ormes will appoint agents to sell books and solicit subscriptions to
the <span class="smcap">Journal of Negro History</span>. He will also organize clubs for the
study of Negro life and history.</p>

<p>Any five persons desiring to prosecute studies in this field
intensively may organize a club and upon the payment of two dollars
each will be entitled not only to receive free of further charge the
<span class="smcap">Journal of Negro History</span>, but may call on the Director for such
instruction as can be given by mail. Members will be supplied with a
quarterly outline study of the current numbers of the <span class="smcap">Journal of Negro
History</span> and with a topical outline of the contents of the back
numbers.</p>

<p>Clubs will be left free to work out their own organization and plans.
The management, however, follows the plan of a group working under the
simplest restrictions. There should be elected a president, a
secretary, a treasurer, and an instructor. The last named official
should be the most intelligent and the best informed member of the
group.</p>

<hr class="short" />

<p>E. Payen's <i>Belgique et Congo</i> and P. Daye's <i>Les Conquetes
Africaniques des Belge</i> have been published by Berger-Levrault in
Paris.</p>

<p>The Cornhill Publishing Company has brought out <i>Twenty-five Years in
the Black Belt</i> by W. J. Edwards.</p>

<p>P. A. Means has published through Marshall Jones <i>Racial Factors in a
Democracy</i>.</p>

<p>The following significant articles have appeared in recent numbers of
periodicals: <i>The Worth of an African</i>, by R. Keable in the July
number of the International Review of Missions; <i>How Germany treats
the Natives</i> by Evans Lewis and M. Montgomery-Campbell; <i>Germany and
Africa</i> by Ethel Jollie in the June number<span class='pagenum'><a name="Page_238" id="Page_238">[Pg 238]</a></span> of the United Empire;
<i>International Interference in African Affairs</i> by Sir. H. H. Johnson
in the April number of the Journal of Comparative Legislation and
International Law; <i>The Native Question in British East Africa</i> in the
April number of the Contemporary Review; and <i>The Christian Occupation
of Africa</i> in the Proceedings of the African Conference.</p>

