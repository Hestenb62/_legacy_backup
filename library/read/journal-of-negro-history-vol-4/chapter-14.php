Negroes. In 1828, death was declared the penalty for inciting
insurrection among the slaves and in 1840 there was passed an act
prohibiting the use of firearms by Negroes. In Virginia as early as
1748 there was enacted a measure declaring that even the free Negroes
and Indians enlisted in the militia should appear without arms; but in
1806 the law was modified to provide that free Negroes should not
carry arms without first obtaining a license from the county or
corporation court. One who was caught with firearms in spite of this
act was to forfeit the weapon to the informer and receive thirty-nine
lashes at the whipping-post. Hening, <i>Statutes-at-Large</i>, Vol. V, p.
17; Vol. XVI, p. 274.</p></div>

