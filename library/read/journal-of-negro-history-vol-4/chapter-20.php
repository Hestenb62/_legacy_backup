<h2><a name="No3_a8" id="No3_a8"></a>
NOTES</h2>


<p>At the close of this the fourth year of its existence the Association
for the Study of Negro Life and History convened in biennial session
in Washington, D. C., on the 17th and 18th of June at the 12th Street
Branch Y. M. C. A. The reports for the year were heard, new officers
were elected, and the plans for the coming year were formulated. The
proceedings in full will appear in the October number.</p>

<p>The chief interest of the meeting centered around the informing
addresses on the <i>Negro in the World War</i>. Every phase of the war
history which the Negro helped to make was treated.</p>

<p>The Association worked out also the plans by which it will collect
data to write a scientific <i>History of the Negro in the World War</i>
just as soon as the treaty of peace is signed and documents now
inaccessible because of the proximity to the conflict become
available. The co&ouml;peration of all seekers after the truth is earnestly
solicited.</p>

<p>During the past two years the Association has been able to move
steadily forward in spite of the difficulties incident to the war. The
subscriptions to the <span class="smcap">Journal of Negro History</span> have gradually increased
and a number of philanthropists have liberally contributed to the fund
now being used to extend the work into all parts of the country. This
work is being done by a Field Agent who organizes clubs for the study
of Negro life and history and, through local agents, sells the
publications of the Association and solicits subscriptions to the
<span class="smcap">Journal of Negro History</span>.</p>

<p>In addition to publishing for four years the <span class="smcap">Journal of Negro History</span>,
a repository of truth now available in bound form, the association has
brought out also <i>Slavery in Kentucky</i>, an interesting portraiture of
the institution in that State; <i>The Royal Adventurers Trading into
Africa</i>, one of the best studies of the early slave trade; and <i>A
Century of Negro Migration</i>, the only scientific treatment of this
movement hitherto published.</p>

<p>The circulation of these publications has been extensive. They are
read in North America, South America, Europe, Asia, and Africa; they
reach more than three hundred college and public<span class='pagenum'><a name="Page_348" id="Page_348">[Pg 348]</a></span> libraries; they are
found in all Negro homes where learning is an objective; they are used
by most social workers to get light on the solution of the problems of
humanity; they are referred to by students and professors conducting
classes carrying on research; and they reach members of the cabinet
and the President of the United States.</p>

<hr class="short" />

<p>Carter G. Woodson is not a contributor to the <i>Official History of the
Negro in the World War</i> by Mr. Emmett J. Scott as has been reported
throughout the country. He has given the author several suggestions,
however, and such editorial assistance as the many tasks and
obligations of the Director permitted.</p>

