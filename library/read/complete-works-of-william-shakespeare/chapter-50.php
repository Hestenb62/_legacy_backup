<h2> <b>ACT III</b></h2>

<h3> <a id="sceneIII_9.1"></a><b>SCENE I. Bangor. A Room in the Archdeacon’s House.</b></h3>

<p class="scenedesc">Enter <span class="charname">Hotspur, Worcester, Mortimer</span> and
<span class="charname">Glendower</span>.
</p>

<p class="drama">
MORTIMER.<br>
These promises are fair, the parties sure,<br>
And our induction full of prosperous hope.
</p>

<p class="drama">
HOTSPUR.<br>
Lord Mortimer and cousin Glendower,<br>
Will you sit down? And uncle Worcester,<br>
A plague upon it! I have forgot the map.
</p>

<p class="drama">
GLENDOWER.<br>
No, here it is.<br>
Sit, cousin Percy, sit, good cousin Hotspur;<br>
For by that name as oft as Lancaster doth speak of you<br>
His cheek looks pale, and with a rising sigh<br>
He wisheth you in heaven.
</p>

<p class="drama">
HOTSPUR.<br>
And you in hell,<br>
As oft as he hears Owen Glendower spoke of.
</p>

<p class="drama">
GLENDOWER.<br>
I cannot blame him. At my nativity<br>
The front of heaven was full of fiery shapes,<br>
Of burning cressets, and at my birth<br>
The frame and huge foundation of the Earth<br>
Shaked like a coward.
</p>

<p class="drama">
HOTSPUR.<br>
Why, so it would have done<br>
At the same season, if your mother’s cat<br>
Had but kitten’d, though yourself had never been born.
</p>

<p class="drama">
GLENDOWER.<br>
I say the Earth did shake when I was born.
</p>

<p class="drama">
HOTSPUR.<br>
And I say the Earth was not of my mind,<br>
If you suppose as fearing you it
shook.
</p>

<p class="drama">
GLENDOWER.<br>
The heavens were all on fire, the Earth did tremble.
</p>

<p class="drama">
HOTSPUR.<br>
O, then th’ Earth shook to see the heavens on fire,<br>
And not in fear of your nativity.<br>
Diseased nature oftentimes breaks forth<br>
In strange eruptions; oft the teeming Earth<br>
Is with a kind of colic pinch’d and vex’d<br>
By the imprisoning of unruly wind<br>
Within her womb, which for enlargement striving,<br>
Shakes the old beldam Earth, and topples down<br>
Steeples and moss-grown towers. At your birth<br>
Our grandam Earth, having this distemp’rature,<br>
In passion shook.
</p>

<p class="drama">
GLENDOWER.<br>
Cousin, of many men<br>
I do not bear these crossings. Give me leave<br>
To tell you once again that at my birth<br>
The front of heaven was full of fiery shapes,<br>
The goats ran from the mountains, and the herds<br>
Were strangely clamorous to the frighted fields.<br>
These signs have mark’d me extraordinary,<br>
And all the courses of my life do show<br>
I am not in the roll of common men.<br>
Where is he living, clipp’d in with the sea<br>
That chides the banks of England, Scotland, Wales,<br>
Which calls me pupil or hath read to me?<br>
And bring him out that is but woman’s son<br>
Can trace me in the tedious ways of art,<br>
And hold me pace in deep experiments.
</p>

<p class="drama">
HOTSPUR.<br>
I think there is no man speaks better Welsh.<br>
I’ll to dinner.
</p>

<p class="drama">
MORTIMER.<br>
Peace, cousin Percy, you will make him mad.
</p>

<p class="drama">
GLENDOWER.<br>
I can call spirits from the vasty deep.
</p>

<p class="drama">
HOTSPUR.<br>
Why, so can I, or so can any man,<br>
But will they come when you do call for them?
</p>

<p class="drama">
GLENDOWER.<br>
Why, I can teach you, cousin, to command the devil.
</p>

<p class="drama">
HOTSPUR.<br>
And I can teach thee, coz, to shame the devil<br>
By telling truth; tell truth, and shame the devil.<br>
If thou have power to raise him, bring him hither,<br>
And I’ll be sworn I have power to shame him hence.<br>
O, while you live, tell truth, and shame the devil!
</p>

<p class="drama">
MORTIMER.<br>
Come, come, no more of this unprofitable chat.
</p>

<p class="drama">
GLENDOWER.<br>
Three times hath Henry Bolingbroke made head<br>
Against my power; thrice from the banks of Wye<br>
And sandy-bottom’d Severn have I sent him<br>
Bootless home and weather-beaten back.
</p>

<p class="drama">
HOTSPUR.<br>
Home without boots, and in foul weather too!<br>
How ’scapes he agues, in the devil’s name!
</p>

<p class="drama">
GLENDOWER.<br>
Come, here’s the map, shall we divide our right<br>
According to our threefold order ta’en?
</p>

<p class="drama">
MORTIMER.<br>
The archdeacon hath divided it<br>
Into three limits very equally:<br>
England, from Trent and Severn hitherto,<br>
By south and east is to my part assign’d:<br>
All westward, Wales beyond the Severn shore,<br>
And all the fertile land within that bound,<br>
To Owen Glendower: and, dear coz, to you<br>
The remnant northward lying off from Trent.<br>
And our indentures tripartite are drawn,<br>
Which being sealed interchangeably,<br>
A business that this night may execute,<br>
Tomorrow, cousin Percy, you and I,<br>
And my good Lord of Worcester will set forth<br>
To meet your father and the Scottish power,<br>
As is appointed us, at Shrewsbury.<br>
My father Glendower is not ready yet,<br>
Nor shall we need his help these fourteen days.<br>
[<i>To Glendower.</i>] Within that space you may have drawn together<br>
Your tenants, friends, and neighbouring gentlemen.
</p>

<p class="drama">
GLENDOWER.<br>
A shorter time shall send me to you, lords,<br>
And in my conduct shall your ladies come,<br>
From whom you now must steal, and take no leave,<br>
For there will be a world of water shed<br>
Upon the parting of your wives and you.
</p>

<p class="drama">
HOTSPUR.<br>
Methinks my moiety, north from Burton here,<br>
In quantity equals not one of yours.<br>
See how this river comes me cranking in,<br>
And cuts me from the best of all my land<br>
A huge half-moon, a monstrous cantle out.<br>
I’ll have the current in this place dammed up,<br>
And here the smug and silver Trent shall run<br>
In a new channel, fair and evenly.<br>
It shall not wind with such a deep indent,<br>
To rob me of so rich a bottom here.
</p>

<p class="drama">
GLENDOWER.<br>
Not wind? It shall, it must. You see it doth.
</p>

<p class="drama">
MORTIMER.<br>
Yea, but mark how he bears his course, and runs me up<br>
With like advantage on the other side,<br>
Gelding the opposed continent as much<br>
As on the other side it takes from you.
</p>

<p class="drama">
WORCESTER.<br>
Yea, but a little charge will trench him here,<br>
And on this north side win this cape of land,<br>
And then he runs straight and even.
</p>

<p class="drama">
HOTSPUR.<br>
I’ll have it so, a little charge will do it.
</p>

<p class="drama">
GLENDOWER.<br>
I’ll not have it altered.
</p>

<p class="drama">
HOTSPUR.<br>
Will not you?
</p>

<p class="drama">
GLENDOWER.<br>
No, nor you shall not.
</p>

<p class="drama">
HOTSPUR.<br>
Who shall say me nay?
</p>

<p class="drama">
GLENDOWER.<br>
Why, that will I.
</p>

<p class="drama">
HOTSPUR.<br>
Let me not understand you, then; speak it in Welsh.
</p>

<p class="drama">
GLENDOWER.<br>
I can speak English, lord, as well as you,<br>
For I was train’d up in the English Court,<br>
Where being but young I framed to the harp<br>
Many an English ditty lovely well,<br>
And gave the tongue a helpful ornament—<br>
A virtue that was never seen in you.
</p>

<p class="drama">
HOTSPUR.<br>
Marry, and I am glad of it with all my heart.<br>
I had rather be a kitten, and cry “mew”<br>
Than one of these same metre ballad-mongers;<br>
I had rather hear a brazen canstick turn’d,<br>
Or a dry wheel grate on the axletree,<br>
And that would set my teeth nothing on edge,<br>
Nothing so much as mincing poetry.<br>
’Tis like the forced gait of a shuffling nag.
</p>

<p class="drama">
GLENDOWER.<br>
Come, you shall have Trent turn’d.
</p>

<p class="drama">
HOTSPUR.<br>
I do not care. I’ll give thrice so much land<br>
To any well-deserving friend;<br>
But in the way of bargain, mark ye me,<br>
I’ll cavil on the ninth part of a hair.<br>
Are the indentures drawn? Shall we be gone?
</p>

<p class="drama">
GLENDOWER.<br>
The moon shines fair, you may away by night.<br>
I’ll haste the writer, and withal<br>
Break with your wives of your departure hence.<br>
I am afraid my daughter will run mad,<br>
So much she doteth on her Mortimer.
</p>

<p class="right">[<i>Exit.</i>]
</p>

<p class="drama">
MORTIMER.<br>
Fie, cousin Percy, how you cross my father!
</p>

<p class="drama">
HOTSPUR.<br>
I cannot choose. Sometimes he angers me<br>
With telling me of the moldwarp and the ant,<br>
Of the dreamer Merlin and his prophecies,<br>
And of a dragon and a finless fish,<br>
A clip-wing’d griffin and a moulten raven,<br>
A couching lion and a ramping cat,<br>
And such a deal of skimble-skamble stuff<br>
As puts me from my faith. I tell you what—<br>
He held me last night at least nine hours<br>
In reckoning up the several devils’ names<br>
That were his lackeys: I cried “Hum,” and “Well, go to,”<br>
But mark’d him not a word. O, he is as tedious<br>
As a tired horse, a railing wife,<br>
Worse than a smoky house. I had rather live<br>
With cheese and garlic in a windmill, far,<br>
Than feed on cates and have him talk to me<br>
In any summer house in Christendom.
</p>

<p class="drama">
MORTIMER.<br>
In faith, he is a worthy gentleman,<br>
Exceedingly well read, and profited<br>
In strange concealments, valiant as a lion,<br>
And wondrous affable, and as bountiful<br>
As mines of India. Shall I tell you, cousin?<br>
He holds your temper in a high respect<br>
And curbs himself even of his natural scope<br>
When you come cross his humour, faith, he does.<br>
I warrant you that man is not alive<br>
Might so have tempted him as you have done<br>
Without the taste of danger and reproof:<br>
But do not use it oft, let me entreat you.
</p>

<p class="drama">
WORCESTER.<br>
In faith, my lord, you are too wilful-blame,<br>
And since your coming hither have done enough<br>
To put him quite besides his patience.<br>
You must needs learn, lord, to amend this fault.<br>
Though sometimes it show greatness, courage, blood—<br>
And that’s the dearest grace it renders you—<br>
Yet oftentimes it doth present harsh rage,<br>
Defect of manners, want of government,<br>
Pride, haughtiness, opinion, and disdain,<br>
The least of which haunting a nobleman<br>
Loseth men’s hearts and leaves behind a stain<br>
Upon the beauty of all parts besides,<br>
Beguiling them of commendation.
</p>

<p class="drama">
HOTSPUR.<br>
Well, I am school’d. Good manners be your speed!<br>
Here come our wives, and let us take our leave.
</p>

<p class="scenedesc">Enter <span class="charname">Glendower</span> with
<span class="charname">Lady Mortimer</span> and <span class="charname">Lady Percy</span>.
</p>

<p class="drama">
MORTIMER.<br>
This is the deadly spite that angers me,<br>
My wife can speak no English, I no Welsh.
</p>

<p class="drama">
GLENDOWER.<br>
My daughter weeps, she’ll not part with you,<br>
She’ll be a soldier too, she’ll to the wars.
</p>

<p class="drama">
MORTIMER.<br>
Good father, tell her that she and my aunt Percy<br>
Shall follow in your conduct speedily.
</p>

<p class="right">[<i><span class="charname">Glendower</span> speaks to
<span class="charname">Lady Mortimer</span> in Welsh, and she answers him in
the same.</i>]
</p>

<p class="drama">
GLENDOWER.<br>
She is desperate here, a peevish self-willed harlotry,<br>
One that no persuasion can do good upon.
</p>

<p class="right">[<i><span class="charname">Lady Mortimer</span> speaks to
<span class="charname">Mortimer</span> in Welsh.</i>]
</p>

<p class="drama">
MORTIMER.<br>
I understand thy looks, that pretty Welsh<br>
Which thou pourest down from these swelling heavens<br>
I am too perfect in, and but for shame<br>
In such a parley should I answer thee.
</p>

<p class="right">[<i><span class="charname">Lady Mortimer</span> speaks to
him again in Welsh.</i>]
</p>

<p class="drama">
I understand thy kisses, and thou mine,<br>
And that’s a feeling disputation,<br>
But I will never be a truant, love,<br>
Till I have learnt thy language; for thy tongue<br>
Makes Welsh as sweet as ditties highly penn’d,<br>
Sung by a fair queen in a summer’s bower,<br>
With ravishing division, to her lute.
</p>

<p class="drama">
GLENDOWER.<br>
Nay, if you melt, then will she run mad.
</p>

<p class="right">[<i><span class="charname">Lady Mortimer</span> speaks to
<span class="charname">Mortimer</span> again in Welsh.</i>]
</p>

<p class="drama">
MORTIMER.<br>
O, I am ignorance itself in this!
</p>

<p class="drama">
GLENDOWER.<br>
She bids you on the wanton rushes lay you down,<br>
And rest your gentle head upon her lap,<br>
And she will sing the song that pleaseth you,<br>
And on your eyelids crown the god of sleep,<br>
Charming your blood with pleasing heaviness,<br>
Making such difference ’twixt wake and sleep<br>
As is the difference betwixt day and night,<br>
The hour before the heavenly-harness’d team<br>
Begins his golden progress in the east.
</p>

<p class="drama">
MORTIMER.<br>
With all my heart I’ll sit and hear her sing,<br>
By that time will our book, I think, be drawn.
</p>

<p class="drama">
GLENDOWER.<br>
Do so, and those musicians that shall play to you<br>
Hang in the air a thousand leagues from hence,<br>
And straight they shall be here: sit, and attend.
</p>

<p class="drama">
HOTSPUR.<br>
Come, Kate, thou art perfect in lying down.<br>
Come, quick, quick, that I may lay
my head in thy lap.
</p>

<p class="drama">
LADY PERCY.<br>
Go, ye giddy goose.
</p>

<p class="right">[<i>The music plays.</i>]
</p>

<p class="drama">
HOTSPUR.<br>
Now I perceive the devil understands Welsh,<br>
And ’tis no marvel he’s so humorous.<br>
By’r Lady, he’s a good musician.
</p>

<p class="drama">
LADY PERCY.<br>
Then should you be nothing but musical,<br>
For you are altogether governed by humours.<br>
Lie still, ye thief, and hear the lady sing in Welsh.
</p>

<p class="drama">
HOTSPUR.<br>
I had rather hear Lady, my brach, howl in Irish.
</p>

<p class="drama">
LADY PERCY.<br>
Wouldst thou have thy head broken?
</p>

<p class="drama">
HOTSPUR.<br>
No.
</p>

<p class="drama">
LADY PERCY.<br>
Then be still.
</p>

<p class="drama">
HOTSPUR.<br>
Neither; ’tis a woman’s fault.
</p>

<p class="drama">
LADY PERCY.<br>
Now God help thee!
</p>

<p class="drama">
HOTSPUR.<br>
To the Welsh lady’s bed.
</p>

<p class="drama">
LADY PERCY.<br>
What’s that?
</p>

<p class="drama">
HOTSPUR.<br>
Peace, she sings.
</p>

<p class="right">[<i>Here the lady sings a Welsh song.</i>]
</p>

<p class="drama">
Come, Kate, I’ll have your song too.
</p>

<p class="drama">
LADY PERCY.<br>
Not mine, in good sooth.
</p>

<p class="drama">
HOTSPUR.<br>
Not yours, in good sooth! Heart! you swear like a comfit-maker’s wife!
“Not you, in good sooth,” and “As true as I live,” and
“As God shall mend me,” and “As sure as day”<br>
And givest such sarcenet surety for thy oaths<br>
As if thou never walk’dst further than Finsbury.<br>
Swear me, Kate, like a lady as thou art,<br>
A good mouth-filling oath, and leave “In sooth,”<br>
And such protest of pepper-gingerbread,<br>
To velvet-guards and Sunday citizens.<br>
Come, sing.
</p>

<p class="drama">
LADY PERCY.<br>
I will not sing.
</p>

<p class="drama">
HOTSPUR.<br>
’Tis the next way to turn tailor, or be redbreast-teacher. An the
indentures be drawn, I’ll away within these two hours; and so come in
when ye will.
</p>

<p class="right">[<i>Exit.</i>]
</p>

<p class="drama">
GLENDOWER.<br>
Come, come, Lord Mortimer, you are as slow<br>
As hot Lord Percy is on fire to go.<br>
By this our book is drawn. We’ll but seal,<br>
And then to horse immediately.
</p>

<p class="drama">
MORTIMER.<br>
With all my heart.
</p>

<p class="right">[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneIII_9.2"></a><b>SCENE II. London. A Room in the Palace.</b></h3>

<p class="scenedesc">Enter <span class="charname">King Henry, Prince Henry</span> and Lords.
</p>

<p class="drama">
KING.<br>
Lords, give us leave; the Prince of Wales and I<br>
Must have some private conference: but be near at hand,<br>
For we shall presently have need of you.
</p>

<p class="right">[<i>Exeunt Lords.</i>]
</p>

<p class="drama">
I know not whether God will have it so<br>
For some displeasing service I have done,<br>
That, in His secret doom, out of my blood<br>
He’ll breed revengement and a scourge for me;<br>
But thou dost in thy passages of life<br>
Make me believe that thou art only mark’d<br>
For the hot vengeance and the rod of heaven<br>
To punish my mistreadings. Tell me else,<br>
Could such inordinate and low desires,<br>
Such poor, such bare, such lewd, such mean attempts,<br>
Such barren pleasures, rude society,<br>
As thou art match’d withal, and grafted to,<br>
Accompany the greatness of thy blood,<br>
And hold their level with thy princely heart?
</p>

<p class="drama">
PRINCE.<br>
So please your Majesty, I would I could<br>
Quit all offences with as clear excuse<br>
As well as I am doubtless I can purge<br>
Myself of many I am charged withal.<br>
Yet such extenuation let me beg<br>
As, in reproof of many tales devised,<br>
By smiling pickthanks and base newsmongers,<br>
Which oft the ear of greatness needs must hear,<br>
I may for some things true, wherein my youth<br>
Hath faulty wander’d and irregular,<br>
Find pardon on my true submission.
</p>

<p class="drama">
KING.<br>
God pardon thee! Yet let me wonder, Harry,<br>
At thy affections, which do hold a wing<br>
Quite from the flight of all thy ancestors.<br>
Thy place in Council thou hast rudely lost,<br>
Which by thy younger brother is supplied,<br>
And art almost an alien to the hearts<br>
Of all the court and princes of my blood.<br>
The hope and expectation of thy time<br>
Is ruin’d, and the soul of every man<br>
Prophetically do forethink thy fall.<br>
Had I so lavish of my presence been,<br>
So common-hackney’d in the eyes of men,<br>
So stale and cheap to vulgar company,<br>
Opinion, that did help me to the crown,<br>
Had still kept loyal to possession,<br>
And left me in reputeless banishment,<br>
A fellow of no mark nor likelihood.<br>
By being seldom seen, I could not stir<br>
But like a comet I was wonder’d at,<br>
That men would tell their children, “This is he.”<br>
Others would say, “Where, which is Bolingbroke?”<br>
And then I stole all courtesy from heaven,<br>
And dress’d myself in such humility<br>
That I did pluck allegiance from men’s hearts,<br>
Loud shouts and salutations from their mouths,<br>
Even in the presence of the crowned King.<br>
Thus did I keep my person fresh and new,<br>
My presence, like a robe pontifical,<br>
Ne’er seen but wonder’d at, and so my state,<br>
Seldom but sumptuous, showed like a feast,<br>
And won by rareness such solemnity.<br>
The skipping King, he ambled up and down<br>
With shallow jesters and rash bavin wits,<br>
Soon kindled and soon burnt; carded his state,<br>
Mingled his royalty, with cap’ring fools,<br>
Had his great name profaned with their scorns,<br>
And gave his countenance, against his name,<br>
To laugh at gibing boys, and stand the push<br>
Of every beardless vain comparative;<br>
Grew a companion to the common streets,<br>
Enfeoff’d himself to popularity,<br>
That, being daily swallow’d by men’s eyes,<br>
They surfeited with honey, and began<br>
To loathe the taste of sweetness, whereof a little<br>
More than a little is by much too much.<br>
So, when he had occasion to be seen,<br>
He was but as the cuckoo is in June,<br>
Heard, not regarded; seen, but with such eyes<br>
As, sick and blunted with community,<br>
Afford no extraordinary gaze,<br>
Such as is bent on sun-like majesty<br>
When it shines seldom in admiring eyes,<br>
But rather drowsed and hung their eyelids down,<br>
Slept in his face, and render’d such aspect<br>
As cloudy men use to their adversaries,<br>
Being with his presence glutted, gorged, and full.<br>
And in that very line, Harry, standest thou,<br>
For thou hast lost thy princely privilege<br>
With vile participation. Not an eye<br>
But is a-weary of thy common sight,<br>
Save mine, which hath desired to see thee more,<br>
Which now doth that I would not have it do,<br>
Make blind itself with foolish tenderness.
</p>

<p class="drama">
PRINCE.<br>
I shall hereafter, my thrice gracious lord,<br>
Be more myself.
</p>

<p class="drama">
KING.<br>
For all the world<br>
As thou art to this hour was Richard then<br>
When I from France set foot at Ravenspurgh,<br>
And even as I was then is Percy now.<br>
Now, by my sceptre, and my soul to boot,<br>
He hath more worthy interest to the state<br>
Than thou, the shadow of succession.<br>
For of no right, nor colour like to right,<br>
He doth fill fields with harness in the realm,<br>
Turns head against the lion’s armed jaws,<br>
And, being no more in debt to years than thou,<br>
Leads ancient lords and reverend bishops on<br>
To bloody battles and to bruising arms.<br>
What never-dying honour hath he got<br>
Against renowned Douglas! whose high deeds,<br>
Whose hot incursions and great name in arms,<br>
Holds from all soldiers chief majority<br>
And military title capital<br>
Through all the kingdoms that acknowledge Christ.<br>
Thrice hath this Hotspur, Mars in swathing clothes,<br>
This infant warrior, in his enterprises<br>
Discomfited great Douglas, ta’en him once,<br>
Enlarged him, and made a friend of him,<br>
To fill the mouth of deep defiance up,<br>
And shake the peace and safety of our throne.<br>
And what say you to this? Percy, Northumberland,<br>
The Archbishop’s Grace of York, Douglas, Mortimer,<br>
Capitulate against us and are up.<br>
But wherefore do I tell these news to thee?<br>
Why, Harry, do I tell thee of my foes,<br>
Which art my nearest and dearest enemy?<br>
Thou that art like enough, through vassal fear,<br>
Base inclination, and the start of spleen,<br>
To fight against me under Percy’s pay,<br>
To dog his heels, and curtsy at his frowns,<br>
To show how much thou art degenerate.
</p>

<p class="drama">
PRINCE.<br>
Do not think so, you shall not find it so.<br>
And God forgive them that so much have sway’d<br>
Your Majesty’s good thoughts away from me!<br>
I will redeem all this on Percy’s head,<br>
And, in the closing of some glorious day,<br>
Be bold to tell you that I am your son,<br>
When I will wear a garment all of blood,<br>
And stain my favours in a bloody mask,<br>
Which, wash’d away, shall scour my shame with it.<br>
And that shall be the day, whene’er it lights,<br>
That this same child of honour and renown,<br>
This gallant Hotspur, this all-praised knight,<br>
And your unthought-of Harry chance to meet.<br>
For every honour sitting on his helm,<br>
Would they were multitudes, and on my head<br>
My shames redoubled! For the time will come,<br>
That I shall make this northern youth exchange<br>
His glorious deeds for my indignities.<br>
Percy is but my factor, good my lord,<br>
To engross up glorious deeds on my behalf,<br>
And I will call him to so strict account<br>
That he shall render every glory up,<br>
Yea, even the slightest worship of his time,<br>
Or I will tear the reckoning from his heart.<br>
This in the name of God I promise here,<br>
The which if He be pleased I shall perform,<br>
I do beseech your Majesty may salve<br>
The long-grown wounds of my intemperance.<br>
If not, the end of life cancels all bands,<br>
And I will die a hundred thousand deaths<br>
Ere break the smallest parcel of this vow.
</p>

<p class="drama">
KING.<br>
A hundred thousand rebels die in this.<br>
Thou shalt have charge and sovereign trust herein.
</p>

<p class="scenedesc">Enter <span class="charname">Sir Walter Blunt</span>.
</p>

<p class="drama">
How now, good Blunt? Thy looks are full of speed.
</p>

<p class="drama">
BLUNT.<br>
So hath the business that I come to speak of.<br>
Lord Mortimer of Scotland hath sent word<br>
That Douglas and the English rebels met<br>
The eleventh of this month at Shrewsbury.<br>
A mighty and a fearful head they are,<br>
If promises be kept on every hand,<br>
As ever offer’d foul play in a state.
</p>

<p class="drama">
KING.<br>
The Earl of Westmoreland set forth today,<br>
With him my son, Lord John of Lancaster,<br>
For this advertisement is five days old.<br>
On Wednesday next you, Harry, shall set forward,<br>
On Thursday we ourselves will march.<br>
Our meeting is Bridgenorth. And, Harry, you<br>
Shall march through Gloustershire; by which account,<br>
Our business valued, some twelve days hence<br>
Our general forces at Bridgenorth shall meet.<br>
Our hands are full of business. Let’s away,<br>
Advantage feeds him fat while men delay.
</p>

<p class="right">[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneIII_9.3"></a><b>SCENE III. Eastcheap. A Room in the Boar’s Head Tavern.</b></h3>

<p class="scenedesc">Enter <span class="charname">Falstaff</span> and
<span class="charname">Bardolph</span>.
</p>

<p class="drama">
FALSTAFF.<br>
Bardolph, am I not fallen away vilely since this last action? Do I not bate? Do
I not dwindle? Why, my skin hangs about me like an old lady’s loose gown.
I am withered like an old apple-john. Well, I’ll repent, and that
suddenly, while I am in some liking. I shall be out of heart shortly, and then
I shall have no strength to repent. An I have not forgotten what the inside of
a church is made of, I am a peppercorn, a brewer’s horse. The inside of a
church! Company, villainous company, hath been the spoil of me.
</p>

<p class="drama">
BARDOLPH.<br>
Sir John, you are so fretful, you cannot live long.
</p>

<p class="drama">
FALSTAFF.<br>
Why, there is it. Come, sing me a song, make me merry. I was as virtuously
given as a gentleman need to be, virtuous enough; swore little; diced not above
seven times—a week; went to a bawdy house not above once in a
quarter—in an hour; paid money that I borrowed—three or four times;
lived well and in good compass; and now I live out of all order, out of all
compass.
</p>

<p class="drama">
BARDOLPH.<br>
Why, you are so fat, Sir John, that you must needs be out of all compass, out
of all reasonable compass, Sir John.
</p>

<p class="drama">
FALSTAFF.<br>
Do thou amend thy face, and I’ll amend my life. Thou art our admiral,
thou bearest the lantern in the poop, but ’tis in the nose of thee. Thou
art the Knight of the Burning Lamp.
</p>

<p class="drama">
BARDOLPH.<br>
Why, Sir John, my face does you no harm.
</p>

<p class="drama">
FALSTAFF.<br>
No, I’ll be sworn, I make as good use of it as many a man doth of a
death’s-head or a <i>memento mori</i>. I never see thy face but I think
upon hell-fire, and Dives that lived in purple, for there he is in his robes,
burning, burning. If thou wert any way given to virtue, I would swear by thy
face. My oath should be, “By this fire, that’s God’s
angel.” But thou art altogether given over; and wert indeed, but for the
light in thy face, the son of utter darkness. When thou ran’st up
Gad’s Hill in the night to catch my horse, if I did not think thou hadst
been an <i>ignis fatuus</i> or a ball of wildfire, there’s no purchase in
money. O, thou art a perpetual triumph, an everlasting bonfire-light! Thou hast
saved me a thousand marks in links and torches, walking with thee in the night
betwixt tavern and tavern: but the sack that thou hast drunk me would have
bought me lights as good cheap at the dearest chandler’s in Europe. I
have maintained that salamander of yours with fire any time this two-and-thirty
years, God reward me for it!
</p>

<p class="drama">
BARDOLPH.<br>
’Sblood, I would my face were in your belly!
</p>

<p class="drama">
FALSTAFF.<br>
God-a-mercy! so should I be sure to be heartburnt.
</p>

<p class="scenedesc">Enter the <span class="charname">Hostess</span>.
</p>

<p class="drama">
How now, Dame Partlet the hen, have you enquired yet who picked my pocket?
</p>

<p class="drama">
HOSTESS.<br>
Why, Sir John, what do you think, Sir John, do you think I keep thieves in my
house? I have searched, I have enquired, so has my husband, man by man, boy by
boy, servant by servant. The tithe of a hair was never lost in my house before.
</p>

<p class="drama">
FALSTAFF.<br>
Ye lie, hostess. Bardolph was shaved and lost many a hair, and I’ll be
sworn my pocket was picked. Go to, you are a woman, go.
</p>

<p class="drama">
HOSTESS.<br>
Who, I? No; I defy thee: God’s light, I was never called so in mine own
house before.
</p>

<p class="drama">
FALSTAFF.<br>
Go to, I know you well enough.
</p>

<p class="drama">
HOSTESS.<br>
No, Sir John, you do not know me, Sir John. I know you, Sir John, you owe me
money, Sir John, and now you pick a quarrel to beguile me of it. I bought you a
dozen of shirts to your back.
</p>

<p class="drama">
FALSTAFF.<br>
Dowlas, filthy dowlas. I have given them away to bakers’ wives; and they
have made bolters of them.
</p>

<p class="drama">
HOSTESS.<br>
Now, as I am a true woman, holland of eight shillings an ell. You owe money
here besides, Sir John, for your diet and by-drinkings, and money lent you,
four-and-twenty pound.
</p>

<p class="drama">
FALSTAFF.<br>
He had his part of it, let him pay.
</p>

<p class="drama">
HOSTESS.<br>
He? Alas, he is poor, he hath nothing.
</p>

<p class="drama">
FALSTAFF.<br>
How? Poor? Look upon his face. What call you rich? Let them coin his nose, let
them coin his cheeks. I’ll not pay a denier. What, will you make a
younker of me? Shall I not take mine ease in mine inn but I shall have my
pocket picked? I have lost a seal-ring of my grandfather’s worth
forty mark.
</p>

<p class="drama">
HOSTESS.<br>
O Jesu, I have heard the Prince tell him, I know not how oft, that that ring
was copper.
</p>

<p class="drama">
FALSTAFF.<br>
How? The Prince is a Jack, a sneak-up. ’Sblood, an he were here, I would
cudgel him like a dog if he would say so.
</p>

<p class="scenedesc">Enter <span class="charname">Prince Henry</span> with
<span class="charname">Peto,</span> marching. <span class="charname">Falstaff</span>
meets him, playing on his truncheon like a fife.
</p>

<p class="drama">
How now, lad? Is the wind in that door, i’faith? Must we all
march?
</p>

<p class="drama">
BARDOLPH.<br>
Yea, two and two, Newgate fashion.
</p>

<p class="drama">
HOSTESS.<br>
My lord, I pray you, hear me.
</p>

<p class="drama">
PRINCE.<br>
What say’st thou, Mistress Quickly? How doth thy husband? I love him
well; he is an honest man.
</p>

<p class="drama">
HOSTESS.<br>
Good my lord, hear me.
</p>

<p class="drama">
FALSTAFF.<br>
Prithee, let her alone, and list to me.
</p>

<p class="drama">
PRINCE.<br>
What say’st thou, Jack?
</p>

<p class="drama">
FALSTAFF.<br>
The other night I fell asleep here, behind the arras, and had my pocket
picked. This house is turned bawdy-house; they pick pockets.
</p>

<p class="drama">
PRINCE.<br>
What didst thou lose, Jack?
</p>

<p class="drama">
FALSTAFF.<br>
Wilt thou believe me, Hal, three or four bonds of forty pound apiece and a
seal-ring of my grandfather’s.
</p>

<p class="drama">
PRINCE.<br>
A trifle, some eightpenny matter.
</p>

<p class="drama">
HOSTESS.<br>
So I told him, my lord, and I said I heard your Grace say so. And, my lord, he
speaks most vilely of you, like a foul-mouthed man as he is, and said he
would cudgel you.
</p>

<p class="drama">
PRINCE.<br>
What! he did not?
</p>

<p class="drama">
HOSTESS.<br>
There’s neither faith, truth, nor womanhood in me else.
</p>

<p class="drama">
FALSTAFF.<br>
There’s no more faith in thee than in a stewed prune, nor no more
truth in thee than in a drawn fox; and, for woman-hood, Maid Marian may be the
deputy’s wife of the ward to thee. Go, you thing, go.
</p>

<p class="drama">
HOSTESS.<br>
Say, what thing, what thing?
</p>

<p class="drama">
FALSTAFF.<br>
What thing? Why, a thing to thank God on.
</p>

<p class="drama">
HOSTESS.<br>
I am no thing to thank God on, I would thou shouldst know it! I am an honest
man’s wife, and, setting thy knighthood aside, thou art a knave to call
me so.
</p>

<p class="drama">
FALSTAFF.<br>
Setting thy womanhood aside, thou art a beast to say otherwise.
</p>

<p class="drama">
HOSTESS.<br>
Say, what beast, thou knave, thou?
</p>

<p class="drama">
FALSTAFF.<br>
What beast? Why, an otter.
</p>

<p class="drama">
PRINCE.<br>
An otter, Sir John? Why an otter?
</p>

<p class="drama">
FALSTAFF.<br>
Why, she’s neither fish nor flesh; a man knows not where to have her.
</p>

<p class="drama">
HOSTESS.<br>
Thou art an unjust man in saying so, thou or any man knows where to have me,
thou knave, thou.
</p>

<p class="drama">
PRINCE.<br>
Thou say’st true, hostess, and he slanders thee most grossly.
</p>

<p class="drama">
HOSTESS.<br>
So he doth you, my lord, and said this other day you ought him a thousand
pound.
</p>

<p class="drama">
PRINCE.<br>
Sirrah, do I owe you a thousand pound?
</p>

<p class="drama">
FALSTAFF.<br>
</p>

<p class="drama">
A thousand pound, Hal? A million. Thy love is worth a million; thou owest me
thy love.
</p>

<p class="drama">
HOSTESS.<br>
Nay, my lord, he call’d you Jack, and said he would cudgel you.
</p>

<p class="drama">
FALSTAFF.<br>
Did I, Bardolph?
</p>

<p class="drama">
BARDOLPH.<br>
Indeed, Sir John, you said so.
</p>

<p class="drama">
FALSTAFF.<br>
Yea, if he said my ring was copper.
</p>

<p class="drama">
PRINCE.<br>
I say ’tis copper. Darest thou be as good as thy word now?
</p>

<p class="drama">
FALSTAFF.<br>
Why, Hal, thou knowest, as thou art but man, I dare, but as thou art prince, I
fear thee as I fear the roaring of the lion’s whelp.
</p>

<p class="drama">
PRINCE.<br>
And why not as the lion?
</p>

<p class="drama">
FALSTAFF.<br>
The King himself is to be feared as the lion. Dost thou think I’ll fear
thee as I fear thy father? Nay, an I do, I pray God my girdle break.
</p>

<p class="drama">
PRINCE.<br>
O, if it should, how would thy guts fall about thy knees! But, sirrah,
there’s no room for faith, truth, nor honesty in this bosom of thine; it
is all filled up with midriff. Charge an honest woman with picking thy pocket!
Why, thou whoreson, impudent, embossed rascal, if there were anything in thy
pocket but tavern reckonings, memorandums of bawdy houses, and one poor
pennyworth of sugar-candy to make thee long-winded, if thy pocket were enriched
with any other injuries but these, I am a villain. And yet you will stand to
it, you will not pocket up wrong. Art thou not ashamed!
</p>

<p class="drama">
FALSTAFF.<br>
Dost thou hear, Hal? Thou knowest in the state of innocency Adam fell, and what
should poor Jack Falstaff do in the days of villainy? Thou seest I have more
flesh than another man and therefore more frailty. You confess, then, you
picked my pocket?
</p>

<p class="drama">
PRINCE.<br>
It appears so by the story.
</p>

<p class="drama">
FALSTAFF.<br>
Hostess, I forgive thee. Go make ready breakfast, love thy husband, look to thy
servants, cherish thy guests. Thou shalt find me tractable to any honest
reason. Thou seest I am pacified still. Nay, prithee, be gone.
</p>

<p class="right">[<i>Exit <span class="charname">Hostess</span>.</i>]
</p>

<p class="drama">
Now, Hal, to the news at court. For the robbery, lad, how is that
answered?
</p>

<p class="drama">
PRINCE.<br>
O, my sweet beef, I must still be good angel to thee. The money is paid back
again.
</p>

<p class="drama">
FALSTAFF.<br>
O, I do not like that paying back, ’tis a double labour.
</p>

<p class="drama">
PRINCE.<br>
I am good friends with my father, and may do anything.
</p>

<p class="drama">
FALSTAFF.<br>
Rob me the exchequer the first thing thou dost, and do it with unwashed hands
too.
</p>

<p class="drama">
BARDOLPH.<br>
Do, my lord.
</p>

<p class="drama">
PRINCE.<br>
I have procured thee, Jack, a charge of foot.
</p>

<p class="drama">
FALSTAFF.<br>
I would it had been of horse. Where shall I find one that can steal well? O,
for a fine thief, of the age of two-and-twenty or thereabouts! I am heinously
unprovided. Well, God be thanked for these rebels; they offend none but the
virtuous. I laud them, I praise them.
</p>

<p class="drama">
PRINCE.<br>
Bardolph!
</p>

<p class="drama">
BARDOLPH.<br>
My lord?
</p>

<p class="drama">
PRINCE.<br>
Go bear this letter to Lord John of Lancaster,<br>
To my brother John; this to my Lord of Westmoreland.
</p>

<p class="right">[<i>Exit <span class="charname">Bardolph</span>.</i>]
</p>

<p class="drama">
Go, Peto, to horse, to horse, for thou and I<br>
Have thirty miles to ride yet ere dinner-time.
</p>

<p class="right">[<i>Exit <span class="charname">Peto</span>.</i>]
</p>

<p class="drama">
Jack, meet me tomorrow in the Temple hall<br>
At two o’clock in the afternoon;<br>
There shalt thou know thy charge, and there receive<br>
Money and order for their furniture.<br>
The land is burning, Percy stands on high,<br>
And either we or they must lower lie.
</p>

<p class="right">[<i>Exit.</i>]
</p>

<p class="drama">
FALSTAFF.<br>
Rare words! Brave world!—Hostess, my breakfast, come.—<br>
O, I could wish this tavern were my drum.
</p>

<p class="right">[<i>Exit.</i>]
</p>

