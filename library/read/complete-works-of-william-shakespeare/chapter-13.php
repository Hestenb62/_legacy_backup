<h2> <a id="sceneII_3.1"></a><b>ACT II</b></h2>

<h3> <b>SCENE I. Messina. A Room in Pompey’s house.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Pompey, Menecrates</span> and <span class="charname">Menas</span> in warlike manner.
</p>

<p class="drama">
POMPEY.<br>
If the great gods be just, they shall assist<br>
The deeds of justest men.
</p>

<p class="drama">
MENECRATES.<br>
Know, worthy Pompey,<br>
That what they do delay they not deny.
</p>

<p class="drama">
POMPEY.<br>
Whiles we are suitors to their throne, decays<br>
The thing we sue for.
</p>

<p class="drama">
MENECRATES.<br>
We, ignorant of ourselves,<br>
Beg often our own harms, which the wise powers<br>
Deny us for our good; so find we profit<br>
By losing of our prayers.
</p>

<p class="drama">
POMPEY.<br>
I shall do well.<br>
The people love me, and the sea is mine;<br>
My powers are crescent, and my auguring hope<br>
Says it will come to th’ full. Mark Antony<br>
In Egypt sits at dinner, and will make<br>
No wars without doors. Caesar gets money where<br>
He loses hearts. Lepidus flatters both,<br>
Of both is flattered; but he neither loves<br>
Nor either cares for him.
</p>

<p class="drama">
MENAS.<br>
Caesar and Lepidus<br>
Are in the field. A mighty strength they carry.
</p>

<p class="drama">
POMPEY.<br>
Where have you this? ’Tis false.
</p>

<p class="drama">
MENAS.<br>
From Silvius, sir.
</p>

<p class="drama">
POMPEY.<br>
He dreams. I know they are in Rome together,<br>
Looking for Antony. But all the charms of love,<br>
Salt Cleopatra, soften thy waned lip!<br>
Let witchcraft join with beauty, lust with both;<br>
Tie up the libertine in a field of feasts;<br>
Keep his brain fuming. Epicurean cooks<br>
Sharpen with cloyless sauce his appetite,<br>
That sleep and feeding may prorogue his honour<br>
Even till a Lethe’d dullness—
</p>

<p class="scenedesc">
Enter <span class="charname">Varrius</span>.
</p>

<p class="drama">
How now, Varrius!
</p>

<p class="drama">
VARRIUS.<br>
This is most certain that I shall deliver:<br>
Mark Antony is every hour in Rome<br>
Expected. Since he went from Egypt ’tis<br>
A space for farther travel.
</p>

<p class="drama">
POMPEY.<br>
I could have given less matter<br>
A better ear.—Menas, I did not think<br>
This amorous surfeiter would have donned his helm<br>
For such a petty war. His soldiership<br>
Is twice the other twain. But let us rear<br>
The higher our opinion, that our stirring<br>
Can from the lap of Egypt’s widow pluck<br>
The ne’er lust-wearied Antony.
</p>

<p class="drama">
MENAS.<br>
I cannot hope<br>
Caesar and Antony shall well greet together.<br>
His wife that’s dead did trespasses to Caesar;<br>
His brother warred upon him, although I think,<br>
Not moved by Antony.
</p>

<p class="drama">
POMPEY.<br>
I know not, Menas,<br>
How lesser enmities may give way to greater.<br>
Were’t not that we stand up against them all,<br>
’Twere pregnant they should square between themselves,<br>
For they have entertained cause enough<br>
To draw their swords. But how the fear of us<br>
May cement their divisions, and bind up<br>
The petty difference, we yet not know.<br>
Be’t as our gods will have’t! It only stands<br>
Our lives upon to use our strongest hands.<br>
Come, Menas.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneII_3.2"></a><b>SCENE II. Rome. A Room in the House of
Lepidus.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Enobarbus</span> and <span class="charname">Lepidus</span>.
</p>

<p class="drama">
LEPIDUS.<br>
Good Enobarbus, ’tis a worthy deed,<br>
And shall become you well, to entreat your captain<br>
To soft and gentle speech.
</p>

<p class="drama">
ENOBARBUS.<br>
I shall entreat him<br>
To answer like himself. If Caesar move him,<br>
Let Antony look over Caesar’s head<br>
And speak as loud as Mars. By Jupiter,<br>
Were I the wearer of Antonius’ beard,<br>
I would not shave’t today.
</p>

<p class="drama">
LEPIDUS.<br>
’Tis not a time<br>
For private stomaching.
</p>

<p class="drama">
ENOBARBUS.<br>
Every time<br>
Serves for the matter that is then born in’t.
</p>

<p class="drama">
LEPIDUS.<br>
But small to greater matters must give way.
</p>

<p class="drama">
ENOBARBUS.<br>
Not if the small come first.
</p>

<p class="drama">
LEPIDUS.<br>
Your speech is passion;<br>
But pray you stir no embers up. Here comes<br>
The noble Antony.
</p>

<p class="scenedesc">
Enter <span class="charname">Antony</span> and <span class="charname">Ventidius</span>.
</p>

<p class="drama">
ENOBARBUS.<br>
And yonder Caesar.
</p>

<p class="scenedesc">
Enter <span class="charname">Caesar, Maecenas</span> and <span class="charname">Agrippa</span>.
</p>

<p class="drama">
ANTONY.<br>
If we compose well here, to Parthia.<br>
Hark, Ventidius.
</p>

<p class="drama">
CAESAR.<br>
I do not know, Maecenas. Ask Agrippa.
</p>

<p class="drama">
LEPIDUS.<br>
Noble friends,<br>
That which combined us was most great, and let not<br>
A leaner action rend us. What’s amiss,<br>
May it be gently heard. When we debate<br>
Our trivial difference loud, we do commit<br>
Murder in healing wounds. Then, noble partners,<br>
The rather for I earnestly beseech,<br>
Touch you the sourest points with sweetest terms,<br>
Nor curstness grow to th’ matter.
</p>

<p class="drama">
ANTONY.<br>
’Tis spoken well.<br>
Were we before our armies, and to fight,<br>
I should do thus.
</p>

<p class="drama">
CAESAR.<br>
Welcome to Rome.
</p>

<p class="drama">
ANTONY.<br>
Thank you.
</p>

<p class="drama">
CAESAR.<br>
Sit.
</p>

<p class="drama">
ANTONY.<br>
Sit, sir.
</p>

<p class="drama">
CAESAR.<br>
Nay, then.
</p>

<p class="drama">
ANTONY.<br>
I learn you take things ill which are not so,<br>
Or being, concern you not.
</p>

<p class="drama">
CAESAR.<br>
I must be laughed at<br>
If, or for nothing or a little, I<br>
Should say myself offended, and with you<br>
Chiefly i’ th’ world; more laughed at that I should<br>
Once name you derogately when to sound your name<br>
It not concerned me.
</p>

<p class="drama">
ANTONY.<br>
My being in Egypt, Caesar,<br>
What was’t to you?
</p>

<p class="drama">
CAESAR.<br>
No more than my residing here at Rome<br>
Might be to you in Egypt. Yet if you there<br>
Did practise on my state, your being in Egypt<br>
Might be my question.
</p>

<p class="drama">
ANTONY.<br>
How intend you, practised?
</p>

<p class="drama">
CAESAR.<br>
You may be pleased to catch at mine intent<br>
By what did here befall me. Your wife and brother<br>
Made wars upon me, and their contestation<br>
Was theme for you; you were the word of war.
</p>

<p class="drama">
ANTONY.<br>
You do mistake your business. My brother never<br>
Did urge me in his act. I did inquire it,<br>
And have my learning from some true reports<br>
That drew their swords with you. Did he not rather<br>
Discredit my authority with yours,<br>
And make the wars alike against my stomach,<br>
Having alike your cause? Of this my letters<br>
Before did satisfy you. If you’ll patch a quarrel,<br>
As matter whole you have not to make it with,<br>
It must not be with this.
</p>

<p class="drama">
CAESAR.<br>
You praise yourself<br>
By laying defects of judgment to me; but<br>
You patched up your excuses.
</p>

<p class="drama">
ANTONY.<br>
Not so, not so.<br>
I know you could not lack—I am certain on’t—<br>
Very necessity of this thought, that I,<br>
Your partner in the cause ’gainst which he fought,<br>
Could not with graceful eyes attend those wars<br>
Which fronted mine own peace. As for my wife,<br>
I would you had her spirit in such another.<br>
The third o’ th’ world is yours, which with a snaffle<br>
You may pace easy, but not such a wife.
</p>

<p class="drama">
ENOBARBUS.<br>
Would we had all such wives, that the men<br>
Might go to wars with the women.
</p>

<p class="drama">
ANTONY.<br>
So much uncurbable, her garboils, Caesar,<br>
Made out of her impatience—which not wanted<br>
Shrewdness of policy too—I grieving grant<br>
Did you too much disquiet. For that you must<br>
But say I could not help it.
</p>

<p class="drama">
CAESAR.<br>
I wrote to you<br>
When rioting in Alexandria; you<br>
Did pocket up my letters, and with taunts<br>
Did gibe my missive out of audience.
</p>

<p class="drama">
ANTONY.<br>
Sir,<br>
He fell upon me ere admitted, then.<br>
Three kings I had newly feasted, and did want<br>
Of what I was i’ th’ morning. But next day<br>
I told him of myself, which was as much<br>
As to have asked him pardon. Let this fellow<br>
Be nothing of our strife; if we contend,<br>
Out of our question wipe him.
</p>

<p class="drama">
CAESAR.<br>
You have broken<br>
The article of your oath, which you shall never<br>
Have tongue to charge me with.
</p>

<p class="drama">
LEPIDUS.<br>
Soft, Caesar!
</p>

<p class="drama">
ANTONY.<br>
No, Lepidus, let him speak.<br>
The honour is sacred which he talks on now,<br>
Supposing that I lacked it. But on, Caesar:<br>
The article of my oath?
</p>

<p class="drama">
CAESAR.<br>
To lend me arms and aid when I required them,<br>
The which you both denied.
</p>

<p class="drama">
ANTONY.<br>
Neglected, rather;<br>
And then when poisoned hours had bound me up<br>
From mine own knowledge. As nearly as I may<br>
I’ll play the penitent to you. But mine honesty<br>
Shall not make poor my greatness, nor my power<br>
Work without it. Truth is that Fulvia,<br>
To have me out of Egypt, made wars here,<br>
For which myself, the ignorant motive, do<br>
So far ask pardon as befits mine honour<br>
To stoop in such a case.
</p>

<p class="drama">
LEPIDUS.<br>
’Tis noble spoken.
</p>

<p class="drama">
MAECENAS.<br>
If it might please you to enforce no further<br>
The griefs between ye; to forget them quite<br>
Were to remember that the present need<br>
Speaks to atone you.
</p>

<p class="drama">
LEPIDUS.<br>
Worthily spoken, Maecenas.
</p>

<p class="drama">
ENOBARBUS.<br>
Or, if you borrow one another’s love for the instant, you may, when you hear no
more words of Pompey, return it again. You shall have time to wrangle in when
you have nothing else to do.
</p>

<p class="drama">
ANTONY.<br>
Thou art a soldier only. Speak no more.
</p>

<p class="drama">
ENOBARBUS.<br>
That truth should be silent I had almost forgot.
</p>

<p class="drama">
ANTONY.<br>
You wrong this presence; therefore speak no more.
</p>

<p class="drama">
ENOBARBUS.<br>
Go to, then. Your considerate stone!
</p>

<p class="drama">
CAESAR.<br>
I do not much dislike the matter, but<br>
The manner of his speech; for’t cannot be<br>
We shall remain in friendship, our conditions<br>
So differing in their acts. Yet if I knew<br>
What hoop should hold us staunch, from edge to edge<br>
O’ th’ world I would pursue it.
</p>

<p class="drama">
AGRIPPA.<br>
Give me leave, Caesar.
</p>

<p class="drama">
CAESAR.<br>
Speak, Agrippa.
</p>

<p class="drama">
AGRIPPA.<br>
Thou hast a sister by the mother’s side,<br>
Admired Octavia. Great Mark Antony<br>
Is now a widower.
</p>

<p class="drama">
CAESAR.<br>
Say not so, Agrippa.<br>
If Cleopatra heard you, your reproof<br>
Were well deserved of rashness.
</p>

<p class="drama">
ANTONY.<br>
I am not married, Caesar. Let me hear<br>
Agrippa further speak.
</p>

<p class="drama">
AGRIPPA.<br>
To hold you in perpetual amity,<br>
To make you brothers, and to knit your hearts<br>
With an unslipping knot, take Antony<br>
Octavia to his wife; whose beauty claims<br>
No worse a husband than the best of men;<br>
Whose virtue and whose general graces speak<br>
That which none else can utter. By this marriage<br>
All little jealousies, which now seem great,<br>
And all great fears, which now import their dangers,<br>
Would then be nothing. Truths would be tales,<br>
Where now half-tales be truths. Her love to both<br>
Would each to other, and all loves to both,<br>
Draw after her. Pardon what I have spoke,<br>
For ’tis a studied, not a present thought,<br>
By duty ruminated.
</p>

<p class="drama">
ANTONY.<br>
Will Caesar speak?
</p>

<p class="drama">
CAESAR.<br>
Not till he hears how Antony is touched<br>
With what is spoke already.
</p>

<p class="drama">
ANTONY.<br>
What power is in Agrippa,<br>
If I would say “Agrippa, be it so,”<br>
To make this good?
</p>

<p class="drama">
CAESAR.<br>
The power of Caesar, and<br>
His power unto Octavia.
</p>

<p class="drama">
ANTONY.<br>
May I never<br>
To this good purpose, that so fairly shows,<br>
Dream of impediment! Let me have thy hand.<br>
Further this act of grace; and from this hour<br>
The heart of brothers govern in our loves<br>
And sway our great designs!
</p>

<p class="drama">
CAESAR.<br>
There’s my hand.<br>
A sister I bequeath you, whom no brother<br>
Did ever love so dearly. Let her live<br>
To join our kingdoms and our hearts; and never<br>
Fly off our loves again!
</p>

<p class="drama">
LEPIDUS.<br>
Happily, amen!
</p>

<p class="drama">
ANTONY.<br>
I did not think to draw my sword ’gainst Pompey,<br>
For he hath laid strange courtesies and great<br>
Of late upon me. I must thank him only,<br>
Lest my remembrance suffer ill report;<br>
At heel of that, defy him.
</p>

<p class="drama">
LEPIDUS.<br>
Time calls upon ’s.<br>
Of us must Pompey presently be sought,<br>
Or else he seeks out us.
</p>

<p class="drama">
ANTONY.<br>
Where lies he?
</p>

<p class="drama">
CAESAR.<br>
About the Mount Misena.
</p>

<p class="drama">
ANTONY.<br>
What is his strength by land?
</p>

<p class="drama">
CAESAR.<br>
Great and increasing; but by sea<br>
He is an absolute master.
</p>

<p class="drama">
ANTONY.<br>
So is the fame.<br>
Would we had spoke together! Haste we for it.<br>
Yet, ere we put ourselves in arms, dispatch we<br>
The business we have talked of.
</p>

<p class="drama">
CAESAR.<br>
With most gladness,<br>
And do invite you to my sister’s view,<br>
Whither straight I’ll lead you.
</p>

<p class="drama">
ANTONY.<br>
Let us, Lepidus, not lack your company.
</p>

<p class="drama">
LEPIDUS.<br>
Noble Antony, not sickness should detain me.
</p>

<p class="right">
[<i>Flourish. Exeunt all except <span class="charname">Enobarbus,
Agrippa</span> and <span class="charname">Maecenas</span>.</i>]
</p>

<p class="drama">
MAECENAS.<br>
Welcome from Egypt, sir.
</p>

<p class="drama">
ENOBARBUS.<br>
Half the heart of Caesar, worthy Maecenas! My honourable friend, Agrippa!
</p>

<p class="drama">
AGRIPPA.<br>
Good Enobarbus!
</p>

<p class="drama">
MAECENAS.<br>
We have cause to be glad that matters are so well digested. You stayed well by
’t in Egypt.
</p>

<p class="drama">
ENOBARBUS.<br>
Ay, sir, we did sleep day out of countenance and made the night light with
drinking.
</p>

<p class="drama">
MAECENAS.<br>
Eight wild boars roasted whole at a breakfast, and but twelve persons there. Is
this true?
</p>

<p class="drama">
ENOBARBUS.<br>
This was but as a fly by an eagle. We had much more monstrous matter of feast,
which worthily deserved noting.
</p>

<p class="drama">
MAECENAS.<br>
She’s a most triumphant lady, if report be square to her.
</p>

<p class="drama">
ENOBARBUS.<br>
When she first met Mark Antony, she pursed up his heart upon the river of
Cydnus.
</p>

<p class="drama">
AGRIPPA.<br>
There she appeared indeed, or my reporter devised well for her.
</p>

<p class="drama">
ENOBARBUS.<br>
I will tell you.<br>
The barge she sat in, like a burnished throne,<br>
Burned on the water. The poop was beaten gold;<br>
Purple the sails, and so perfumed that<br>
The winds were love-sick with them; the oars were silver,<br>
Which to the tune of flutes kept stroke, and made<br>
The water which they beat to follow faster,<br>
As amorous of their strokes. For her own person,<br>
It beggared all description: she did lie<br>
In her pavilion, cloth-of-gold of tissue,<br>
O’erpicturing that Venus where we see<br>
The fancy outwork nature. On each side her<br>
Stood pretty dimpled boys, like smiling Cupids,<br>
With divers-coloured fans, whose wind did seem<br>
To glow the delicate cheeks which they did cool,<br>
And what they undid did.
</p>

<p class="drama">
AGRIPPA.<br>
O, rare for Antony!
</p>

<p class="drama">
ENOBARBUS.<br>
Her gentlewomen, like the Nereides,<br>
So many mermaids, tended her i’ th’ eyes,<br>
And made their bends adornings. At the helm<br>
A seeming mermaid steers. The silken tackle<br>
Swell with the touches of those flower-soft hands<br>
That yarely frame the office. From the barge<br>
A strange invisible perfume hits the sense<br>
Of the adjacent wharfs. The city cast<br>
Her people out upon her, and Antony,<br>
Enthroned i’ th’ market-place, did sit alone,<br>
Whistling to th’ air, which, but for vacancy,<br>
Had gone to gaze on Cleopatra too,<br>
And made a gap in nature.
</p>

<p class="drama">
AGRIPPA.<br>
Rare Egyptian!
</p>

<p class="drama">
ENOBARBUS.<br>
Upon her landing, Antony sent to her,<br>
Invited her to supper. She replied<br>
It should be better he became her guest,<br>
Which she entreated. Our courteous Antony,<br>
Whom ne’er the word of “No” woman heard speak,<br>
Being barbered ten times o’er, goes to the feast,<br>
And, for his ordinary, pays his heart<br>
For what his eyes eat only.
</p>

<p class="drama">
AGRIPPA.<br>
Royal wench!<br>
She made great Caesar lay his sword to bed.<br>
He ploughed her, and she cropped.
</p>

<p class="drama">
ENOBARBUS.<br>
I saw her once<br>
Hop forty paces through the public street<br>
And, having lost her breath, she spoke and panted,<br>
That she did make defect perfection,<br>
And, breathless, pour breath forth.
</p>

<p class="drama">
MAECENAS.<br>
Now Antony must leave her utterly.
</p>

<p class="drama">
ENOBARBUS.<br>
Never. He will not.<br>
Age cannot wither her, nor custom stale<br>
Her infinite variety. Other women cloy<br>
The appetites they feed, but she makes hungry<br>
Where most she satisfies. For vilest things<br>
Become themselves in her, that the holy priests<br>
Bless her when she is riggish.
</p>

<p class="drama">
MAECENAS.<br>
If beauty, wisdom, modesty can settle<br>
The heart of Antony, Octavia is<br>
A blessed lottery to him.
</p>

<p class="drama">
AGRIPPA.<br>
Let us go.<br>
Good Enobarbus, make yourself my guest<br>
Whilst you abide here.
</p>

<p class="drama">
ENOBARBUS.<br>
Humbly, sir, I thank you.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneII_3.3"></a><b>SCENE III. Rome. A Room in Caesar’s
House.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Antony, Caesar, Octavia</span> between them.
</p>

<p class="drama">
ANTONY.<br>
The world and my great office will sometimes<br>
Divide me from your bosom.
</p>

<p class="drama">
OCTAVIA.<br>
All which time<br>
Before the gods my knee shall bow my prayers<br>
To them for you.
</p>

<p class="drama">
ANTONY.<br>
Good night, sir.—My Octavia,<br>
Read not my blemishes in the world’s report.<br>
I have not kept my square, but that to come<br>
Shall all be done by th’ rule. Good night, dear lady.
</p>

<p class="drama">
OCTAVIA.<br>
Good night, sir.
</p>

<p class="drama">
CAESAR.<br>
Good night.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Caesar</span> and <span class="charname">Octavia</span>.</i>]
</p>

<p class="scenedesc">
Enter <span class="charname">Soothsayer</span>.
</p>

<p class="drama">
ANTONY.<br>
Now, sirrah, you do wish yourself in Egypt?
</p>

<p class="drama">
SOOTHSAYER.<br>
Would I had never come from thence, nor you thither!
</p>

<p class="drama">
ANTONY.<br>
If you can, your reason.
</p>

<p class="drama">
SOOTHSAYER.<br>
I see it in my motion, have it not in my tongue.<br>
But yet hie you to Egypt again.
</p>

<p class="drama">
ANTONY.<br>
Say to me,<br>
Whose fortunes shall rise higher, Caesar’s or mine?
</p>

<p class="drama">
SOOTHSAYER.<br>
Caesar’s.<br>
Therefore, O Antony, stay not by his side.<br>
Thy dæmon—that thy spirit which keeps thee—is<br>
Noble, courageous, high, unmatchable,<br>
Where Caesar’s is not. But near him, thy angel<br>
Becomes afeard, as being o’erpowered. Therefore<br>
Make space enough between you.
</p>

<p class="drama">
ANTONY.<br>
Speak this no more.
</p>

<p class="drama">
SOOTHSAYER.<br>
To none but thee; no more but when to thee.<br>
If thou dost play with him at any game,<br>
Thou art sure to lose; and of that natural luck<br>
He beats thee ’gainst the odds. Thy lustre thickens<br>
When he shines by. I say again, thy spirit<br>
Is all afraid to govern thee near him;<br>
But, he away, ’tis noble.
</p>

<p class="drama">
ANTONY.<br>
Get thee gone.<br>
Say to Ventidius I would speak with him.
</p>

<p class="right">
[<i>Exit <span class="charname">Soothsayer</span>.</i>]
</p>

<p class="drama">
He shall to Parthia. Be it art or hap,<br>
He hath spoken true. The very dice obey him,<br>
And in our sports my better cunning faints<br>
Under his chance. If we draw lots, he speeds;<br>
His cocks do win the battle still of mine<br>
When it is all to naught, and his quails ever<br>
Beat mine, inhooped, at odds. I will to Egypt:<br>
And though I make this marriage for my peace,<br>
I’ th’ East my pleasure lies.
</p>

<p class="scenedesc">
Enter <span class="charname">Ventidius</span>.
</p>

<p class="drama">
O, come, Ventidius,<br>
You must to Parthia. Your commission’s ready.<br>
Follow me and receive ’t.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneII_3.4"></a><b>SCENE IV. Rome. A street.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Lepidus, Maecenas</span> and <span class="charname">Agrippa</span>.
</p>

<p class="drama">
LEPIDUS.<br>
Trouble yourselves no further. Pray you hasten<br>
Your generals after.
</p>

<p class="drama">
AGRIPPA.<br>
Sir, Mark Antony<br>
Will e’en but kiss Octavia, and we’ll follow.
</p>

<p class="drama">
LEPIDUS.<br>
Till I shall see you in your soldier’s dress,<br>
Which will become you both, farewell.
</p>

<p class="drama">
MAECENAS.<br>
We shall,<br>
As I conceive the journey, be at the Mount<br>
Before you, Lepidus.
</p>

<p class="drama">
LEPIDUS.<br>
Your way is shorter;<br>
My purposes do draw me much about.<br>
You’ll win two days upon me.
</p>

<p class="drama">
BOTH.<br>
Sir, good success!
</p>

<p class="drama">
LEPIDUS.<br>
Farewell.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneII_3.5"></a><b>SCENE V. Alexandria. A Room in the
Palace.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Cleopatra, Charmian, Iras, Alexas</span>.
</p>

<p class="drama">
CLEOPATRA.<br>
Give me some music—music, moody food<br>
Of us that trade in love.
</p>

<p class="drama">
ALL.<br>
The music, ho!
</p>

<p class="scenedesc">
Enter <span class="charname">Mardian</span>, the eunuch.
</p>

<p class="drama">
CLEOPATRA.<br>
Let it alone. Let’s to billiards. Come, Charmian.
</p>

<p class="drama">
CHARMIAN.<br>
My arm is sore. Best play with Mardian.
</p>

<p class="drama">
CLEOPATRA.<br>
As well a woman with an eunuch played<br>
As with a woman. Come, you’ll play with me, sir?
</p>

<p class="drama">
MARDIAN.<br>
As well as I can, madam.
</p>

<p class="drama">
CLEOPATRA.<br>
And when good will is showed, though’t come too short,<br>
The actor may plead pardon. I’ll none now.<br>
Give me mine angle; we’ll to the river. There,<br>
My music playing far off, I will betray<br>
Tawny-finned fishes. My bended hook shall pierce<br>
Their slimy jaws, and as I draw them up<br>
I’ll think them every one an Antony,<br>
And say “Ah, ha! You’re caught.”
</p>

<p class="drama">
CHARMIAN.<br>
’Twas merry when<br>
You wagered on your angling; when your diver<br>
Did hang a salt fish on his hook, which he<br>
With fervency drew up.
</p>

<p class="drama">
CLEOPATRA.<br>
That time?—O times!—<br>
I laughed him out of patience; and that night<br>
I laughed him into patience, and next morn,<br>
Ere the ninth hour, I drunk him to his bed,<br>
Then put my tires and mantles on him, whilst<br>
I wore his sword Philippan.
</p>

<p class="scenedesc">
Enter <span class="charname">Messenger</span>.
</p>

<p class="drama">
O! from Italy!<br>
Ram thou thy fruitful tidings in mine ears,<br>
That long time have been barren.
</p>

<p class="drama">
MESSENGER.<br>
Madam, madam—
</p>

<p class="drama">
CLEOPATRA.<br>
Antony’s dead! If thou say so, villain,<br>
Thou kill’st thy mistress. But well and free,<br>
If thou so yield him, there is gold, and here<br>
My bluest veins to kiss, a hand that kings<br>
Have lipped, and trembled kissing.
</p>

<p class="drama">
MESSENGER.<br>
First, madam, he’s well.
</p>

<p class="drama">
CLEOPATRA.<br>
Why, there’s more gold.<br>
But sirrah, mark, we use<br>
To say the dead are well. Bring it to that,<br>
The gold I give thee will I melt and pour<br>
Down thy ill-uttering throat.
</p>

<p class="drama">
MESSENGER.<br>
Good madam, hear me.
</p>

<p class="drama">
CLEOPATRA.<br>
Well, go to, I will.<br>
But there’s no goodness in thy face if Antony<br>
Be free and healthful. So tart a favour<br>
To trumpet such good tidings! If not well,<br>
Thou shouldst come like a Fury crowned with snakes,<br>
Not like a formal man.
</p>

<p class="drama">
MESSENGER.<br>
Will’t please you hear me?
</p>

<p class="drama">
CLEOPATRA.<br>
I have a mind to strike thee ere thou speak’st.<br>
Yet if thou say Antony lives, is well,<br>
Or friends with Caesar, or not captive to him,<br>
I’ll set thee in a shower of gold and hail<br>
Rich pearls upon thee.
</p>

<p class="drama">
MESSENGER.<br>
Madam, he’s well.
</p>

<p class="drama">
CLEOPATRA.<br>
Well said.
</p>

<p class="drama">
MESSENGER.<br>
And friends with Caesar.
</p>

<p class="drama">
CLEOPATRA.<br>
Th’ art an honest man.
</p>

<p class="drama">
MESSENGER.<br>
Caesar and he are greater friends than ever.
</p>

<p class="drama">
CLEOPATRA.<br>
Make thee a fortune from me.
</p>

<p class="drama">
MESSENGER.<br>
But yet, madam—
</p>

<p class="drama">
CLEOPATRA.<br>
I do not like “But yet”, it does allay<br>
The good precedence. Fie upon “But yet”!<br>
“But yet” is as a gaoler to bring forth<br>
Some monstrous malefactor. Prithee, friend,<br>
Pour out the pack of matter to mine ear,<br>
The good and bad together: he’s friends with Caesar,<br>
In state of health, thou say’st; and, thou say’st, free.
</p>

<p class="drama">
MESSENGER.<br>
Free, madam? No. I made no such report.<br>
He’s bound unto Octavia.
</p>

<p class="drama">
CLEOPATRA.<br>
For what good turn?
</p>

<p class="drama">
MESSENGER.<br>
For the best turn i’ th’ bed.
</p>

<p class="drama">
CLEOPATRA.<br>
I am pale, Charmian.
</p>

<p class="drama">
MESSENGER.<br>
Madam, he’s married to Octavia.
</p>

<p class="drama">
CLEOPATRA.<br>
The most infectious pestilence upon thee!
</p>

<p class="right">
[<i>Strikes him down.</i>]
</p>

<p class="drama">
MESSENGER.<br>
Good madam, patience.
</p>

<p class="drama">
CLEOPATRA.<br>
What say you?
</p>

<p class="right">
[<i>Strikes him again.</i>]
</p>

<p class="drama">
Hence, horrible villain, or I’ll spurn thine eyes<br>
Like balls before me! I’ll unhair thy head!
</p>

<p class="right">
[<i>She hales him up and down.</i>]
</p>

<p class="drama">
Thou shalt be whipped with wire and stewed in brine,<br>
Smarting in ling’ring pickle.
</p>

<p class="drama">
MESSENGER.<br>
Gracious madam,<br>
I that do bring the news made not the match.
</p>

<p class="drama">
CLEOPATRA.<br>
Say ’tis not so, a province I will give thee,<br>
And make thy fortunes proud. The blow thou hadst<br>
Shall make thy peace for moving me to rage,<br>
And I will boot thee with what gift beside<br>
Thy modesty can beg.
</p>

<p class="drama">
MESSENGER.<br>
He’s married, madam.
</p>

<p class="drama">
CLEOPATRA.<br>
Rogue, thou hast lived too long.
</p>

<p class="right">
[<i>Draws a knife.</i>]
</p>

<p class="drama">
MESSENGER.<br>
Nay then I’ll run.<br>
What mean you, madam? I have made no fault.
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="drama">
CHARMIAN.<br>
Good madam, keep yourself within yourself.<br>
The man is innocent.
</p>

<p class="drama">
CLEOPATRA.<br>
Some innocents ’scape not the thunderbolt.<br>
Melt Egypt into Nile, and kindly creatures<br>
Turn all to serpents! Call the slave again.<br>
Though I am mad, I will not bite him. Call!
</p>

<p class="drama">
CHARMIAN.<br>
He is afeard to come.
</p>

<p class="drama">
CLEOPATRA.<br>
I will not hurt him.
</p>

<p class="right">
[<i>Exit <span class="charname">Charmian</span>.</i>]
</p>

<p class="drama">
These hands do lack nobility that they strike<br>
A meaner than myself, since I myself<br>
Have given myself the cause.
</p>

<p class="scenedesc">
Enter the <span class="charname">Messenger</span> again with <span class="charname">Charmian</span>.
</p>

<p class="drama">
Come hither, sir.<br>
Though it be honest, it is never good<br>
To bring bad news. Give to a gracious message<br>
An host of tongues, but let ill tidings tell<br>
Themselves when they be felt.
</p>

<p class="drama">
MESSENGER.<br>
I have done my duty.
</p>

<p class="drama">
CLEOPATRA.<br>
Is he married?<br>
I cannot hate thee worser than I do<br>
If thou again say “Yes.”
</p>

<p class="drama">
MESSENGER.<br>
He’s married, madam.
</p>

<p class="drama">
CLEOPATRA.<br>
The gods confound thee! Dost thou hold there still!
</p>

<p class="drama">
MESSENGER.<br>
Should I lie, madam?
</p>

<p class="drama">
CLEOPATRA.<br>
O, I would thou didst,<br>
So half my Egypt were submerged and made<br>
A cistern for scaled snakes! Go, get thee hence.<br>
Hadst thou Narcissus in thy face, to me<br>
Thou wouldst appear most ugly. He is married?
</p>

<p class="drama">
MESSENGER.<br>
I crave your highness’ pardon.
</p>

<p class="drama">
CLEOPATRA.<br>
He is married?
</p>

<p class="drama">
MESSENGER.<br>
Take no offence that I would not offend you.<br>
To punish me for what you make me do<br>
Seems much unequal. He’s married to Octavia.
</p>

<p class="drama">
CLEOPATRA.<br>
O, that his fault should make a knave of thee<br>
That art not what thou’rt sure of! Get thee hence!<br>
The merchandise which thou hast brought from Rome<br>
Are all too dear for me. Lie they upon thy hand,<br>
And be undone by ’em!
</p>

<p class="right">
[<i>Exit <span class="charname">Messenger</span>.</i>]
</p>

<p class="drama">
CHARMIAN.<br>
Good your highness, patience.
</p>

<p class="drama">
CLEOPATRA.<br>
In praising Antony I have dispraised Caesar.
</p>

<p class="drama">
CHARMIAN.<br>
Many times, madam.
</p>

<p class="drama">
CLEOPATRA.<br>
I am paid for’t now.<br>
Lead me from hence;<br>
I faint. O Iras, Charmian! ’Tis no matter.<br>
Go to the fellow, good Alexas, bid him<br>
Report the feature of Octavia, her years,<br>
Her inclination; let him not leave out<br>
The colour of her hair. Bring me word quickly.
</p>

<p class="right">
[<i>Exit <span class="charname">Alexas</span>.</i>]
</p>

<p class="drama">
Let him for ever go—let him not, Charmian.<br>
Though he be painted one way like a Gorgon,<br>
The other way ’s a Mars. [<i>To Mardian</i>] Bid you Alexas<br>
Bring me word how tall she is. Pity me, Charmian,<br>
But do not speak to me. Lead me to my chamber.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneII_3.6"></a><b>SCENE VI. Near Misenum.</b></h3>

<p class="scenedesc">
Flourish. Enter <span class="charname">Pompey</span> and <span class="charname">Menas</span> at one door, with drum and trumpet; at another,
<span class="charname">Caesar, Lepidus, Antony, Enobarbus, Maecenas,
Agrippa,</span> with Soldiers marching.
</p>

<p class="drama">
POMPEY.<br>
Your hostages I have, so have you mine,<br>
And we shall talk before we fight.
</p>

<p class="drama">
CAESAR.<br>
Most meet<br>
That first we come to words, and therefore have we<br>
Our written purposes before us sent,<br>
Which if thou hast considered, let us know<br>
If ’twill tie up thy discontented sword<br>
And carry back to Sicily much tall youth<br>
That else must perish here.
</p>

<p class="drama">
POMPEY.<br>
To you all three,<br>
The senators alone of this great world,<br>
Chief factors for the gods: I do not know<br>
Wherefore my father should revengers want,<br>
Having a son and friends, since Julius Caesar,<br>
Who at Philippi the good Brutus ghosted,<br>
There saw you labouring for him. What was’t<br>
That moved pale Cassius to conspire? And what<br>
Made the all-honoured, honest Roman, Brutus,<br>
With the armed rest, courtiers of beauteous freedom,<br>
To drench the Capitol, but that they would<br>
Have one man but a man? And that is it<br>
Hath made me rig my navy, at whose burden<br>
The angered ocean foams, with which I meant<br>
To scourge th’ ingratitude that despiteful Rome<br>
Cast on my noble father.
</p>

<p class="drama">
CAESAR.<br>
Take your time.
</p>

<p class="drama">
ANTONY.<br>
Thou canst not fear us, Pompey, with thy sails.<br>
We’ll speak with thee at sea. At land thou know’st<br>
How much we do o’ercount thee.
</p>

<p class="drama">
POMPEY.<br>
At land indeed<br>
Thou dost o’ercount me of my father’s house;<br>
But since the cuckoo builds not for himself,<br>
Remain in’t as thou mayst.
</p>

<p class="drama">
LEPIDUS.<br>
Be pleased to tell us—<br>
For this is from the present—how you take<br>
The offers we have sent you.
</p>

<p class="drama">
CAESAR.<br>
There’s the point.
</p>

<p class="drama">
ANTONY.<br>
Which do not be entreated to, but weigh<br>
What it is worth embraced.
</p>

<p class="drama">
CAESAR.<br>
And what may follow<br>
To try a larger fortune.
</p>

<p class="drama">
POMPEY.<br>
You have made me offer<br>
Of Sicily, Sardinia; and I must<br>
Rid all the sea of pirates; then to send<br>
Measures of wheat to Rome. This ’greed upon,<br>
To part with unhacked edges and bear back<br>
Our targes undinted.
</p>

<p class="drama">
CAESAR, ANTONY, and LEPIDUS.<br>
That’s our offer.
</p>

<p class="drama">
POMPEY.<br>
Know, then,<br>
I came before you here a man prepared<br>
To take this offer. But Mark Antony<br>
Put me to some impatience. Though I lose<br>
The praise of it by telling, you must know<br>
When Caesar and your brother were at blows,<br>
Your mother came to Sicily and did find<br>
Her welcome friendly.
</p>

<p class="drama">
ANTONY.<br>
I have heard it, Pompey,<br>
And am well studied for a liberal thanks<br>
Which I do owe you.
</p>

<p class="drama">
POMPEY.<br>
Let me have your hand.<br>
I did not think, sir, to have met you here.
</p>

<p class="drama">
ANTONY.<br>
The beds i’ th’ East are soft; and thanks to you,<br>
That called me timelier than my purpose hither,<br>
For I have gained by ’t.
</p>

<p class="drama">
CAESAR.<br>
Since I saw you last,<br>
There is a change upon you.
</p>

<p class="drama">
POMPEY.<br>
Well, I know not<br>
What counts harsh Fortune casts upon my face,<br>
But in my bosom shall she never come<br>
To make my heart her vassal.
</p>

<p class="drama">
LEPIDUS.<br>
Well met here.
</p>

<p class="drama">
POMPEY.<br>
I hope so, Lepidus. Thus we are agreed.<br>
I crave our composition may be written<br>
And sealed between us.
</p>

<p class="drama">
CAESAR.<br>
That’s the next to do.
</p>

<p class="drama">
POMPEY.<br>
We’ll feast each other ere we part, and let’s<br>
Draw lots who shall begin.
</p>

<p class="drama">
ANTONY.<br>
That will I, Pompey.
</p>

<p class="drama">
POMPEY.<br>
No, Antony, take the lot.<br>
But, first or last, your fine Egyptian cookery<br>
Shall have the fame. I have heard that Julius Caesar<br>
Grew fat with feasting there.
</p>

<p class="drama">
ANTONY.<br>
You have heard much.
</p>

<p class="drama">
POMPEY.<br>
I have fair meanings, sir.
</p>

<p class="drama">
ANTONY.<br>
And fair words to them.
</p>

<p class="drama">
POMPEY.<br>
Then so much have I heard.<br>
And I have heard Apollodorus carried—
</p>

<p class="drama">
ENOBARBUS.<br>
No more of that. He did so.
</p>

<p class="drama">
POMPEY.<br>
What, I pray you?
</p>

<p class="drama">
ENOBARBUS.<br>
A certain queen to Caesar in a mattress.
</p>

<p class="drama">
POMPEY.<br>
I know thee now. How far’st thou, soldier?
</p>

<p class="drama">
ENOBARBUS.<br>
Well;<br>
And well am like to do, for I perceive<br>
Four feasts are toward.
</p>

<p class="drama">
POMPEY.<br>
Let me shake thy hand.<br>
I never hated thee. I have seen thee fight<br>
When I have envied thy behaviour.
</p>

<p class="drama">
ENOBARBUS.<br>
Sir,<br>
I never loved you much, but I ha’ praised ye<br>
When you have well deserved ten times as much<br>
As I have said you did.
</p>

<p class="drama">
POMPEY.<br>
Enjoy thy plainness;<br>
It nothing ill becomes thee.<br>
Aboard my galley I invite you all.<br>
Will you lead, lords?
</p>

<p class="drama">
CAESAR, ANTONY, and LEPIDUS.<br>
Show’s the way, sir.
</p>

<p class="drama">
POMPEY.<br>
Come.
</p>

<p class="right">
[<i>Exeunt all but <span class="charname">Enobarbus</span> and <span class="charname">Menas</span>.</i>]
</p>

<p class="drama">
MENAS.<br>
[<i>Aside</i>.] Thy father, Pompey, would ne’er have made this treaty.—<br>
You and I have known, sir.
</p>

<p class="drama">
ENOBARBUS.<br>
At sea, I think.
</p>

<p class="drama">
MENAS.<br>
We have, sir.
</p>

<p class="drama">
ENOBARBUS.<br>
You have done well by water.
</p>

<p class="drama">
MENAS.<br>
And you by land.
</p>

<p class="drama">
ENOBARBUS.<br>
I will praise any man that will praise me, though it cannot be denied what I
have done by land.
</p>

<p class="drama">
MENAS.<br>
Nor what I have done by water.
</p>

<p class="drama">
ENOBARBUS.<br>
Yes, something you can deny for your own safety: you have been a great thief by
sea.
</p>

<p class="drama">
MENAS.<br>
And you by land.
</p>

<p class="drama">
ENOBARBUS.<br>
There I deny my land service. But give me your hand, Menas. If our eyes had
authority, here they might take two thieves kissing.
</p>

<p class="drama">
MENAS.<br>
All men’s faces are true, whatsome’er their hands are.
</p>

<p class="drama">
ENOBARBUS.<br>
But there is never a fair woman has a true face.
</p>

<p class="drama">
MENAS.<br>
No slander. They steal hearts.
</p>

<p class="drama">
ENOBARBUS.<br>
We came hither to fight with you.
</p>

<p class="drama">
MENAS.<br>
For my part, I am sorry it is turned to a drinking. Pompey doth this day laugh
away his fortune.
</p>

<p class="drama">
ENOBARBUS.<br>
If he do, sure he cannot weep ’t back again.
</p>

<p class="drama">
MENAS.<br>
You have said, sir. We looked not for Mark Antony here. Pray you, is he married
to Cleopatra?
</p>

<p class="drama">
ENOBARBUS.<br>
Caesar’s sister is called Octavia.
</p>

<p class="drama">
MENAS.<br>
True, sir. She was the wife of Caius Marcellus.
</p>

<p class="drama">
ENOBARBUS.<br>
But she is now the wife of Marcus Antonius.
</p>

<p class="drama">
MENAS.<br>
Pray you, sir?
</p>

<p class="drama">
ENOBARBUS.<br>
’Tis true.
</p>

<p class="drama">
MENAS.<br>
Then is Caesar and he for ever knit together.
</p>

<p class="drama">
ENOBARBUS.<br>
If I were bound to divine of this unity, I would not prophesy so.
</p>

<p class="drama">
MENAS.<br>
I think the policy of that purpose made more in the marriage than the love of
the parties.
</p>

<p class="drama">
ENOBARBUS.<br>
I think so too. But you shall find the band that seems to tie their friendship
together will be the very strangler of their amity. Octavia is of a holy, cold,
and still conversation.
</p>

<p class="drama">
MENAS.<br>
Who would not have his wife so?
</p>

<p class="drama">
ENOBARBUS.<br>
Not he that himself is not so; which is Mark Antony. He will to his Egyptian
dish again. Then shall the sighs of Octavia blow the fire up in Caesar, and, as
I said before, that which is the strength of their amity shall prove the
immediate author of their variance. Antony will use his affection where it is.
He married but his occasion here.
</p>

<p class="drama">
MENAS.<br>
And thus it may be. Come, sir, will you aboard? I have a health for you.
</p>

<p class="drama">
ENOBARBUS.<br>
I shall take it, sir. We have used our throats in Egypt.
</p>

<p class="drama">
MENAS.<br>
Come, let’s away.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneII_3.7"></a><b>SCENE VII. On board Pompey’s Galley, lying
near Misenum.</b></h3>

<p class="scenedesc">
Music. Enter two or three <span class="charname">Servants</span> with a
banquet.
</p>

<p class="drama">
FIRST SERVANT.<br>
Here they’ll be, man. Some o’ their plants are ill-rooted already; the least
wind i’ th’ world will blow them down.
</p>

<p class="drama">
SECOND SERVANT.<br>
Lepidus is high-coloured.
</p>

<p class="drama">
FIRST SERVANT.<br>
They have made him drink alms-drink.
</p>

<p class="drama">
SECOND SERVANT.<br>
As they pinch one another by the disposition, he cries out “no more”,
reconciles them to his entreaty and himself to th’ drink.
</p>

<p class="drama">
FIRST SERVANT.<br>
But it raises the greater war between him and his discretion.
</p>

<p class="drama">
SECOND SERVANT.<br>
Why, this it is to have a name in great men’s fellowship. I had as lief have a
reed that will do me no service as a partisan I could not heave.
</p>

<p class="drama">
FIRST SERVANT.<br>
To be called into a huge sphere, and not to be seen to move in ’t, are the
holes where eyes should be, which pitifully disaster the cheeks.
</p>

<p class="scenedesc">
A sennet sounded. Enter <span class="charname">Caesar, Antony, Pompey, Lepidus,
Agrippa, Maecenas, Enobarbus, Menas</span> with other Captains.
</p>

<p class="drama">
ANTONY.<br>
[<i>To Caesar</i>.] Thus do they, sir: they take the flow o’ th’ Nile<br>
By certain scales i’ th’ pyramid; they know<br>
By th’ height, the lowness, or the mean, if dearth<br>
Or foison follow. The higher Nilus swells,<br>
The more it promises. As it ebbs, the seedsman<br>
Upon the slime and ooze scatters his grain,<br>
And shortly comes to harvest.
</p>

<p class="drama">
LEPIDUS.<br>
You’ve strange serpents there?
</p>

<p class="drama">
ANTONY.<br>
Ay, Lepidus.
</p>

<p class="drama">
LEPIDUS.<br>
Your serpent of Egypt is bred now of your mud by the operation of your sun; so
is your crocodile.
</p>

<p class="drama">
ANTONY.<br>
They are so.
</p>

<p class="drama">
POMPEY.<br>
Sit, and some wine! A health to Lepidus!
</p>

<p class="drama">
LEPIDUS.<br>
I am not so well as I should be, but I’ll ne’er out.
</p>

<p class="drama">
ENOBARBUS.<br>
Not till you have slept. I fear me you’ll be in till then.
</p>

<p class="drama">
LEPIDUS.<br>
Nay, certainly, I have heard the Ptolemies’ pyramises are very goodly things.
Without contradiction I have heard that.
</p>

<p class="drama">
MENAS.<br>
[<i>Aside to Pompey</i>.] Pompey, a word.
</p>

<p class="drama">
POMPEY.<br>
[<i>Aside to Menas</i>.] Say in mine ear what is ’t?
</p>

<p class="drama">
MENAS.<br>
[<i>Whispers in ’s ear.</i>] Forsake thy seat, I do beseech thee, captain,<br>
And hear me speak a word.
</p>

<p class="drama">
POMPEY.<br>
[<i>Aside to Menas.</i>] Forbear me till anon.—<br>
This wine for Lepidus!
</p>

<p class="drama">
LEPIDUS.<br>
What manner o’ thing is your crocodile?
</p>

<p class="drama">
ANTONY.<br>
It is shaped, sir, like itself, and it is as broad as it hath breadth. It is
just so high as it is, and moves with it own organs. It lives by that which
nourisheth it, and the elements once out of it, it transmigrates.
</p>

<p class="drama">
LEPIDUS.<br>
What colour is it of?
</p>

<p class="drama">
ANTONY.<br>
Of its own colour too.
</p>

<p class="drama">
LEPIDUS.<br>
’Tis a strange serpent.
</p>

<p class="drama">
ANTONY.<br>
’Tis so, and the tears of it are wet.
</p>

<p class="drama">
CAESAR.<br>
Will this description satisfy him?
</p>

<p class="drama">
ANTONY.<br>
With the health that Pompey gives him, else he is a very epicure.
</p>

<p class="drama">
POMPEY.<br>
[<i>Aside to Menas.</i>] Go hang, sir, hang! Tell me of that? Away!<br>
Do as I bid you.—Where’s this cup I called for?
</p>

<p class="drama">
MENAS.<br>
[<i>Aside to Pompey</i>.] If for the sake of merit thou wilt hear me,<br>
Rise from thy stool.
</p>

<p class="drama">
POMPEY.<br>
[<i>Aside to Menas</i>.] I think thou’rt mad.
</p>

<p class="right">
[<i>Rises and walks aside.</i>]
</p>

<p class="drama">
The matter?
</p>

<p class="drama">
MENAS.<br>
I have ever held my cap off to thy fortunes.
</p>

<p class="drama">
POMPEY.<br>
Thou hast served me with much faith. What’s else to say?—<br>
Be jolly, lords.
</p>

<p class="drama">
ANTONY.<br>
These quicksands, Lepidus,<br>
Keep off them, for you sink.
</p>

<p class="drama">
MENAS.<br>
Wilt thou be lord of all the world?
</p>

<p class="drama">
POMPEY.<br>
What sayst thou?
</p>

<p class="drama">
MENAS.<br>
Wilt thou be lord of the whole world?<br>
That’s twice.
</p>

<p class="drama">
POMPEY.<br>
How should that be?
</p>

<p class="drama">
MENAS.<br>
But entertain it,<br>
And though you think me poor, I am the man<br>
Will give thee all the world.
</p>

<p class="drama">
POMPEY.<br>
Hast thou drunk well?
</p>

<p class="drama">
MENAS.<br>
No, Pompey, I have kept me from the cup.<br>
Thou art, if thou dar’st be, the earthly Jove.<br>
Whate’er the ocean pales or sky inclips<br>
Is thine, if thou wilt have’t.
</p>

<p class="drama">
POMPEY.<br>
Show me which way.
</p>

<p class="drama">
MENAS.<br>
These three world-sharers, these competitors,<br>
Are in thy vessel. Let me cut the cable,<br>
And when we are put off, fall to their throats.<br>
All then is thine.
</p>

<p class="drama">
POMPEY.<br>
Ah, this thou shouldst have done<br>
And not have spoke on ’t! In me ’tis villainy;<br>
In thee ’t had been good service. Thou must know<br>
’Tis not my profit that does lead mine honour;<br>
Mine honour it. Repent that e’er thy tongue<br>
Hath so betray’d thine act. Being done unknown,<br>
I should have found it afterwards well done,<br>
But must condemn it now. Desist, and drink.
</p>

<p class="drama">
MENAS.<br>
[<i>Aside</i>.] For this,<br>
I’ll never follow thy palled fortunes more.<br>
Who seeks, and will not take when once ’tis offered,<br>
Shall never find it more.
</p>

<p class="drama">
POMPEY.<br>
This health to Lepidus!
</p>

<p class="drama">
ANTONY.<br>
Bear him ashore. I’ll pledge it for him, Pompey.
</p>

<p class="drama">
ENOBARBUS.<br>
Here’s to thee, Menas!
</p>

<p class="drama">
MENAS.<br>
Enobarbus, welcome!
</p>

<p class="drama">
POMPEY.<br>
Fill till the cup be hid.
</p>

<p class="drama">
ENOBARBUS.<br>
There’s a strong fellow, Menas.
</p>

<p class="right">
[<i>Pointing to the servant who carries off <span class="charname">Lepidus</span>.</i>]
</p>

<p class="drama">
MENAS.<br>
Why?
</p>

<p class="drama">
ENOBARBUS.<br>
’A bears the third part of the world, man. Seest not?
</p>

<p class="drama">
MENAS.<br>
The third part, then, is drunk. Would it were all,<br>
That it might go on wheels!
</p>

<p class="drama">
ENOBARBUS.<br>
Drink thou. Increase the reels.
</p>

<p class="drama">
MENAS.<br>
Come.
</p>

<p class="drama">
POMPEY.<br>
This is not yet an Alexandrian feast.
</p>

<p class="drama">
ANTONY.<br>
It ripens towards it. Strike the vessels, ho!<br>
Here is to Caesar!
</p>

<p class="drama">
CAESAR.<br>
I could well forbear’t.<br>
It’s monstrous labour when I wash my brain<br>
And it grows fouler.
</p>

<p class="drama">
ANTONY.<br>
Be a child o’ the time.
</p>

<p class="drama">
CAESAR.<br>
Possess it, I’ll make answer.<br>
But I had rather fast from all, four days,<br>
Than drink so much in one.
</p>

<p class="drama">
ENOBARBUS.<br>
[<i>To Antony</i>.] Ha, my brave emperor,<br>
Shall we dance now the Egyptian Bacchanals<br>
And celebrate our drink?
</p>

<p class="drama">
POMPEY.<br>
Let’s ha’t, good soldier.
</p>

<p class="drama">
ANTONY.<br>
Come, let’s all take hands<br>
Till that the conquering wine hath steeped our sense<br>
In soft and delicate Lethe.
</p>

<p class="drama">
ENOBARBUS.<br>
All take hands.<br>
Make battery to our ears with the loud music,<br>
The while I’ll place you; then the boy shall sing.<br>
The holding every man shall beat as loud<br>
As his strong sides can volley.
</p>

<p class="scenedesc">
Music plays. <span class="charname">Enobarbus</span> places them hand in hand.
</p>

<p class="drama">
       THE SONG.<br>
  Come, thou monarch of the vine,<br>
  Plumpy Bacchus with pink eyne!<br>
  In thy vats our cares be drowned,<br>
  With thy grapes our hairs be crowned.<br>
  Cup us till the world go round,<br>
  Cup us till the world go round!
</p>

<p class="drama">
CAESAR.<br>
What would you more? Pompey, good night. Good brother,<br>
Let me request you off. Our graver business<br>
Frowns at this levity.—Gentle lords, let’s part.<br>
You see we have burnt our cheeks. Strong Enobarb<br>
Is weaker than the wine, and mine own tongue<br>
Splits what it speaks. The wild disguise hath almost<br>
Anticked us all. What needs more words. Good night.<br>
Good Antony, your hand.
</p>

<p class="drama">
POMPEY.<br>
I’ll try you on the shore.
</p>

<p class="drama">
ANTONY.<br>
And shall, sir. Give’s your hand.
</p>

<p class="drama">
POMPEY.<br>
O Antony,<br>
You have my father’s house.<br>
But, what? We are friends. Come, down into the boat.
</p>

<p class="drama">
ENOBARBUS.<br>
Take heed you fall not.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Pompey, Caesar, Antony</span> and
Attendants.</i>]
</p>

<p class="drama">
Menas, I’ll not on shore.
</p>

<p class="drama">
MENAS.<br>
No, to my cabin. These drums, these trumpets, flutes! What!<br>
Let Neptune hear we bid a loud farewell<br>
To these great fellows. Sound and be hanged, sound out!
</p>

<p class="right">
[<i>Sound a flourish with drums.</i>]
</p>

<p class="drama">
ENOBARBUS.<br>
Hoo, says ’a! There’s my cap!
</p>

<p class="drama">
MENAS.<br>
Hoo! Noble captain, come.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

