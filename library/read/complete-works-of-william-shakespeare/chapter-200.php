<h2> <a id="sceneII_32.1"></a><b>ACT II</b></h2>

<h3> <b>SCENE I. Another part of the island.</b></h3>

<p class="scenedesc">Enter <span class="charname">Alonso, Sebastian, Antonio, Gonzalo,
Adrian, Francisco</span> and others.</p>

<p class="drama">
GONZALO.<br>
Beseech you, sir, be merry; you have cause,<br>
So have we all, of joy; for our escape<br>
Is much beyond our loss. Our hint of woe<br>
Is common; every day, some sailor’s wife,<br>
The masters of some merchant and the merchant,<br>
Have just our theme of woe; but for the miracle,<br>
I mean our preservation, few in millions<br>
Can speak like us: then wisely, good sir, weigh<br>
Our sorrow with our comfort.
</p>

<p class="drama">
ALONSO.<br>
Prithee, peace.
</p>

<p class="drama">
SEBASTIAN.<br>
He receives comfort like cold porridge.
</p>

<p class="drama">
ANTONIO.<br>
The visitor will not give him o’er so.
</p>

<p class="drama">
SEBASTIAN.<br>
Look, he’s winding up the watch of his wit; by and by it will strike.
</p>

<p class="drama">
GONZALO.<br>
Sir,—
</p>

<p class="drama">
SEBASTIAN.<br>
One: tell.
</p>

<p class="drama">
GONZALO.<br>
When every grief is entertain’d that’s offer’d,<br>
Comes to the entertainer—
</p>

<p class="drama">
SEBASTIAN.<br>
A dollar.
</p>

<p class="drama">
GONZALO.<br>
Dolour comes to him, indeed: you have spoken truer than you purposed.
</p>

<p class="drama">
SEBASTIAN.<br>
You have taken it wiselier than I meant you should.
</p>

<p class="drama">
GONZALO.<br>
Therefore, my lord,—
</p>

<p class="drama">
ANTONIO.<br>
Fie, what a spendthrift is he of his tongue!
</p>

<p class="drama">
ALONSO.<br>
I prithee, spare.
</p>

<p class="drama">
GONZALO.<br>
Well, I have done: but yet—
</p>

<p class="drama">
SEBASTIAN.<br>
He will be talking.
</p>

<p class="drama">
ANTONIO.<br>
Which, of he or Adrian, for a good wager, first begins to crow?
</p>

<p class="drama">
SEBASTIAN.<br>
The old cock.
</p>

<p class="drama">
ANTONIO.<br>
The cockerel.
</p>

<p class="drama">
SEBASTIAN.<br>
Done. The wager?
</p>

<p class="drama">
ANTONIO.<br>
A laughter.
</p>

<p class="drama">
SEBASTIAN.<br>
A match!
</p>

<p class="drama">
ADRIAN.<br>
Though this island seem to be desert,—
</p>

<p class="drama">
ANTONIO.<br>
Ha, ha, ha!
</p>

<p class="drama">
SEBASTIAN.<br>
So. You’re paid.
</p>

<p class="drama">
ADRIAN.<br>
Uninhabitable, and almost inaccessible,—
</p>

<p class="drama">
SEBASTIAN.<br>
Yet—
</p>

<p class="drama">
ADRIAN.<br>
Yet—
</p>

<p class="drama">
ANTONIO.<br>
He could not miss ’t.
</p>

<p class="drama">
ADRIAN.<br>
It must needs be of subtle, tender, and delicate temperance.
</p>

<p class="drama">
ANTONIO.<br>
Temperance was a delicate wench.
</p>

<p class="drama">
SEBASTIAN.<br>
Ay, and a subtle; as he most learnedly delivered.
</p>

<p class="drama">
ADRIAN.<br>
The air breathes upon us here most sweetly.
</p>

<p class="drama">
SEBASTIAN.<br>
As if it had lungs, and rotten ones.
</p>

<p class="drama">
ANTONIO.<br>
Or, as ’twere perfum’d by a fen.
</p>

<p class="drama">
GONZALO.<br>
Here is everything advantageous to life.
</p>

<p class="drama">
ANTONIO.<br>
True; save means to live.
</p>

<p class="drama">
SEBASTIAN.<br>
Of that there’s none, or little.
</p>

<p class="drama">
GONZALO.<br>
How lush and lusty the grass looks! how green!
</p>

<p class="drama">
ANTONIO.<br>
The ground indeed is tawny.
</p>

<p class="drama">
SEBASTIAN.<br>
With an eye of green in’t.
</p>

<p class="drama">
ANTONIO.<br>
He misses not much.
</p>

<p class="drama">
SEBASTIAN.<br>
No; he doth but mistake the truth totally.
</p>

<p class="drama">
GONZALO.<br>
But the rarity of it is,—which is indeed almost beyond credit,—
</p>

<p class="drama">
SEBASTIAN.<br>
As many vouch’d rarities are.
</p>

<p class="drama">
GONZALO.<br>
That our garments, being, as they were, drenched in the sea, hold
notwithstanding their freshness and glosses, being rather new-dyed than
stained with salt water.
</p>

<p class="drama">
ANTONIO.<br>
If but one of his pockets could speak, would it not say he lies?
</p>

<p class="drama">
SEBASTIAN.<br>
Ay, or very falsely pocket up his report.
</p>

<p class="drama">
GONZALO.<br>
Methinks our garments are now as fresh as when we put them on first in Afric,
at the marriage of the King’s fair daughter Claribel to the King of
Tunis.
</p>

<p class="drama">
SEBASTIAN.<br>
’Twas a sweet marriage, and we prosper well in our return.
</p>

<p class="drama">
ADRIAN.<br>
Tunis was never graced before with such a paragon to their Queen.
</p>

<p class="drama">
GONZALO.<br>
Not since widow Dido’s time.
</p>

<p class="drama">
ANTONIO.<br>
Widow! a pox o’ that! How came that widow in? Widow Dido!
</p>

<p class="drama">
SEBASTIAN.<br>
What if he had said, widower Aeneas too?<br>
Good Lord, how you take it!
</p>

<p class="drama">
ADRIAN.<br>
Widow Dido said you? You make me study of that; she was of Carthage, not of
Tunis.
</p>

<p class="drama">
GONZALO.<br>
This Tunis, sir, was Carthage.
</p>

<p class="drama">
ADRIAN.<br>
Carthage?
</p>

<p class="drama">
GONZALO.<br>
I assure you, Carthage.
</p>

<p class="drama">
ANTONIO.<br>
His word is more than the miraculous harp.
</p>

<p class="drama">
SEBASTIAN.<br>
He hath rais’d the wall, and houses too.
</p>

<p class="drama">
ANTONIO.<br>
What impossible matter will he make easy next?
</p>

<p class="drama">
SEBASTIAN.<br>
I think he will carry this island home in his pocket, and give it his son for
an apple.
</p>

<p class="drama">
ANTONIO.<br>
And, sowing the kernels of it in the sea, bring forth more islands.
</p>

<p class="drama">
ALONSO.<br>
Ay.
</p>

<p class="drama">
ANTONIO.<br>
Why, in good time.
</p>

<p class="drama">
GONZALO.<br>
[<i>To Alonso.</i>] Sir, we were talking that our garments seem now as fresh as when
we were at Tunis at the marriage of your daughter, who is now Queen.
</p>

<p class="drama">
ANTONIO.<br>
And the rarest that e’er came there.
</p>

<p class="drama">
SEBASTIAN.<br>
Bate, I beseech you, widow Dido.
</p>

<p class="drama">
ANTONIO.<br>
O! widow Dido; ay, widow Dido.
</p>

<p class="drama">
GONZALO.<br>
Is not, sir, my doublet as fresh as the first day I wore it? I mean, in a sort.
</p>

<p class="drama">
ANTONIO.<br>
That sort was well fish’d for.
</p>

<p class="drama">
GONZALO.<br>
When I wore it at your daughter’s marriage?
</p>

<p class="drama">
ALONSO.<br>
You cram these words into mine ears against<br>
The stomach of my sense. Would I had never<br>
Married my daughter there! for, coming thence,<br>
My son is lost; and, in my rate, she too,<br>
Who is so far from Italy removed,<br>
I ne’er again shall see her. O thou mine heir<br>
Of Naples and of Milan, what strange fish<br>
Hath made his meal on thee?
</p>

<p class="drama">
FRANCISCO.<br>
Sir, he may live:<br>
I saw him beat the surges under him,<br>
And ride upon their backs. He trod the water,<br>
Whose enmity he flung aside, and breasted<br>
The surge most swoln that met him. His bold head<br>
’Bove the contentious waves he kept, and oared<br>
Himself with his good arms in lusty stroke<br>
To th’ shore, that o’er his wave-worn basis bowed,<br>
As stooping to relieve him. I not doubt<br>
He came alive to land.
</p>

<p class="drama">
ALONSO.<br>
No, no, he’s gone.
</p>

<p class="drama">
SEBASTIAN.<br>
Sir, you may thank yourself for this great loss,<br>
That would not bless our Europe with your daughter,<br>
But rather lose her to an African;<br>
Where she, at least, is banish’d from your eye,<br>
Who hath cause to wet the grief on ’t.
</p>

<p class="drama">
ALONSO.<br>
Prithee, peace.
</p>

<p class="drama">
SEBASTIAN.<br>
You were kneel’d to, and importun’d otherwise<br>
By all of us; and the fair soul herself<br>
Weigh’d between loathness and obedience at<br>
Which end o’ th’ beam should bow. We have lost your son,<br>
I fear, for ever: Milan and Naples have<br>
More widows in them of this business’ making,<br>
Than we bring men to comfort them.<br>
The fault’s your own.
</p>

<p class="drama">
ALONSO.<br>
So is the dear’st o’ th’ loss.
</p>

<p class="drama">
GONZALO.<br>
My lord Sebastian,<br>
The truth you speak doth lack some gentleness<br>
And time to speak it in. You rub the sore,<br>
When you should bring the plaster.
</p>

<p class="drama">
SEBASTIAN.<br>
Very well.
</p>

<p class="drama">
ANTONIO.<br>
And most chirurgeonly.
</p>

<p class="drama">
GONZALO.<br>
It is foul weather in us all, good sir,<br>
When you are cloudy.
</p>

<p class="drama">
SEBASTIAN.<br>
Foul weather?
</p>

<p class="drama">
ANTONIO.<br>
Very foul.
</p>

<p class="drama">
GONZALO.<br>
Had I plantation of this isle, my lord,—
</p>

<p class="drama">
ANTONIO.<br>
He’d sow ’t with nettle-seed.
</p>

<p class="drama">
SEBASTIAN.<br>
Or docks, or mallows.
</p>

<p class="drama">
GONZALO.<br>
And were the King on’t, what would I do?
</p>

<p class="drama">
SEBASTIAN.<br>
’Scape being drunk for want of wine.
</p>

<p class="drama">
GONZALO.<br>
I’ th’ commonwealth I would by contraries<br>
Execute all things; for no kind of traffic<br>
Would I admit; no name of magistrate;<br>
Letters should not be known; riches, poverty,<br>
And use of service, none; contract, succession,<br>
Bourn, bound of land, tilth, vineyard, none;<br>
No use of metal, corn, or wine, or oil;<br>
No occupation; all men idle, all;<br>
And women too, but innocent and pure;<br>
No sovereignty,—
</p>

<p class="drama">
SEBASTIAN.<br>
Yet he would be King on’t.
</p>

<p class="drama">
ANTONIO.<br>
The latter end of his commonwealth forgets the beginning.
</p>

<p class="drama">
GONZALO.<br>
All things in common nature should produce<br>
Without sweat or endeavour; treason, felony,<br>
Sword, pike, knife, gun, or need of any engine,<br>
Would I not have; but nature should bring forth,<br>
Of it own kind, all foison, all abundance,<br>
To feed my innocent people.
</p>

<p class="drama">
SEBASTIAN.<br>
No marrying ’mong his subjects?
</p>

<p class="drama">
ANTONIO.<br>
None, man; all idle; whores and knaves.
</p>

<p class="drama">
GONZALO.<br>
I would with such perfection govern, sir,<br>
T’ excel the Golden Age.
</p>

<p class="drama">
SEBASTIAN.<br>
Save his Majesty!
</p>

<p class="drama">
ANTONIO.<br>
Long live Gonzalo!
</p>

<p class="drama">
GONZALO.<br>
And,—do you mark me, sir?
</p>

<p class="drama">
ALONSO.<br>
Prithee, no more: thou dost talk nothing to me.
</p>

<p class="drama">
GONZALO.<br>
I do well believe your highness; and did it to minister occasion to these
gentlemen, who are of such sensible and nimble lungs that they always use to
laugh at nothing.
</p>

<p class="drama">
ANTONIO.<br>
’Twas you we laughed at.
</p>

<p class="drama">
GONZALO.<br>
Who in this kind of merry fooling am nothing to you. So you may continue, and
laugh at nothing still.
</p>

<p class="drama">
ANTONIO.<br>
What a blow was there given!
</p>

<p class="drama">
SEBASTIAN.<br>
An it had not fallen flat-long.
</p>

<p class="drama">
GONZALO.<br>
You are gentlemen of brave mettle. You would lift the moon out of her sphere,
if she would continue in it five weeks without changing.
</p>

<p class="scenedesc">Enter <span class="charname">Ariel,</span> invisible,
playing solemn music.
</p>

<p class="drama">
SEBASTIAN.<br>
We would so, and then go a-bat-fowling.
</p>

<p class="drama">
ANTONIO.<br>
Nay, good my lord, be not angry.
</p>

<p class="drama">
GONZALO.<br>
No, I warrant you; I will not adventure my discretion so weakly. Will you laugh
me asleep, for I am very heavy?
</p>

<p class="drama">
ANTONIO.<br>
Go sleep, and hear us.
</p>

<p class="right"> [<i>All sleep but Alonso, Sebastian and Antonio.</i>]</p>

<p class="drama">
ALONSO.<br>
What, all so soon asleep! I wish mine eyes<br>
Would, with themselves, shut up my thoughts: I find<br>
They are inclin’d to do so.
</p>

<p class="drama">
SEBASTIAN.<br>
Please you, sir,<br>
Do not omit the heavy offer of it:<br>
It seldom visits sorrow; when it doth,<br>
It is a comforter.
</p>

<p class="drama">
ANTONIO.<br>
We two, my lord,<br>
Will guard your person while you take your rest,<br>
And watch your safety.
</p>

<p class="drama">
ALONSO.<br>
Thank you. Wondrous heavy!
</p>

<p class="right"> [<i><span class="charname">Alonso</span> sleeps. Exit <span class="charname">Ariel</span>.</i>]</p>

<p class="drama">
SEBASTIAN.<br>
What a strange drowsiness possesses them!
</p>

<p class="drama">
ANTONIO.<br>
It is the quality o’ th’ climate.
</p>

<p class="drama">
SEBASTIAN.<br>
Why<br>
Doth it not then our eyelids sink? I find not<br>
Myself dispos’d to sleep.
</p>

<p class="drama">
ANTONIO.<br>
Nor I. My spirits are nimble.<br>
They fell together all, as by consent;<br>
They dropp’d, as by a thunder-stroke. What might,<br>
Worthy Sebastian? O, what might?—No more.<br>
And yet methinks I see it in thy face,<br>
What thou shouldst be. Th’ occasion speaks thee; and<br>
My strong imagination sees a crown<br>
Dropping upon thy head.
</p>

<p class="drama">
SEBASTIAN.<br>
What, art thou waking?
</p>

<p class="drama">
ANTONIO.<br>
Do you not hear me speak?
</p>

<p class="drama">
SEBASTIAN.<br>
I do; and surely<br>
It is a sleepy language, and thou speak’st<br>
Out of thy sleep. What is it thou didst say?<br>
This is a strange repose, to be asleep<br>
With eyes wide open; standing, speaking, moving,<br>
And yet so fast asleep.
</p>

<p class="drama">
ANTONIO.<br>
Noble Sebastian,<br>
Thou let’st thy fortune sleep—die rather; wink’st<br>
Whiles thou art waking.
</p>

<p class="drama">
SEBASTIAN.<br>
Thou dost snore distinctly:<br>
There’s meaning in thy snores.
</p>

<p class="drama">
ANTONIO.<br>
I am more serious than my custom; you<br>
Must be so too, if heed me; which to do<br>
Trebles thee o’er.
</p>

<p class="drama">
SEBASTIAN.<br>
Well, I am standing water.
</p>

<p class="drama">
ANTONIO.<br>
I’ll teach you how to flow.
</p>

<p class="drama">
SEBASTIAN.<br>
Do so: to ebb,<br>
Hereditary sloth instructs me.
</p>

<p class="drama">
ANTONIO.<br>
O,<br>
If you but knew how you the purpose cherish<br>
Whiles thus you mock it! how, in stripping it,<br>
You more invest it! Ebbing men indeed,<br>
Most often, do so near the bottom run<br>
By their own fear or sloth.
</p>

<p class="drama">
SEBASTIAN.<br>
Prithee, say on:<br>
The setting of thine eye and cheek proclaim<br>
A matter from thee, and a birth, indeed<br>
Which throes thee much to yield.
</p>

<p class="drama">
ANTONIO.<br>
Thus, sir:<br>
Although this lord of weak remembrance, this<br>
Who shall be of as little memory<br>
When he is earth’d, hath here almost persuaded,—<br>
For he’s a spirit of persuasion, only<br>
Professes to persuade,—the King his son’s alive,<br>
’Tis as impossible that he’s undrown’d<br>
As he that sleeps here swims.
</p>

<p class="drama">
SEBASTIAN.<br>
I have no hope<br>
That he’s undrown’d.
</p>

<p class="drama">
ANTONIO.<br>
O, out of that “no hope”<br>
What great hope have you! No hope that way is<br>
Another way so high a hope, that even<br>
Ambition cannot pierce a wink beyond,<br>
But doubts discovery there. Will you grant with me<br>
That Ferdinand is drown’d?
</p>

<p class="drama">
SEBASTIAN.<br>
He’s gone.
</p>

<p class="drama">
ANTONIO.<br>
Then tell me,<br>
Who’s the next heir of Naples?
</p>

<p class="drama">
SEBASTIAN.<br>
Claribel.
</p>

<p class="drama">
ANTONIO.<br>
She that is Queen of Tunis; she that dwells<br>
Ten leagues beyond man’s life; she that from Naples<br>
Can have no note, unless the sun were post—<br>
The Man i’ th’ Moon’s too slow—till newborn chins<br>
Be rough and razorable; she that from whom<br>
We all were sea-swallow’d, though some cast again,<br>
And by that destiny, to perform an act<br>
Whereof what’s past is prologue, what to come<br>
In yours and my discharge.
</p>

<p class="drama">
SEBASTIAN.<br>
What stuff is this! How say you?<br>
’Tis true, my brother’s daughter’s Queen of Tunis;<br>
So is she heir of Naples; ’twixt which regions<br>
There is some space.
</p>

<p class="drama">
ANTONIO.<br>
A space whose ev’ry cubit<br>
Seems to cry out “How shall that Claribel<br>
Measure us back to Naples? Keep in Tunis,<br>
And let Sebastian wake.” Say this were death<br>
That now hath seiz’d them; why, they were no worse<br>
Than now they are. There be that can rule Naples<br>
As well as he that sleeps; lords that can prate<br>
As amply and unnecessarily<br>
As this Gonzalo. I myself could make<br>
A chough of as deep chat. O, that you bore<br>
The mind that I do! What a sleep were this<br>
For your advancement! Do you understand me?
</p>

<p class="drama">
SEBASTIAN.<br>
Methinks I do.
</p>

<p class="drama">
ANTONIO.<br>
And how does your content<br>
Tender your own good fortune?
</p>

<p class="drama">
SEBASTIAN.<br>
I remember<br>
You did supplant your brother Prospero.
</p>

<p class="drama">
ANTONIO.<br>
True.<br>
And look how well my garments sit upon me;<br>
Much feater than before; my brother’s servants<br>
Were then my fellows; now they are my men.
</p>

<p class="drama">
SEBASTIAN.<br>
But, for your conscience.
</p>

<p class="drama">
ANTONIO.<br>
Ay, sir; where lies that? If ’twere a kibe,<br>
’Twould put me to my slipper: but I feel not<br>
This deity in my bosom: twenty consciences<br>
That stand ’twixt me and Milan, candied be they<br>
And melt ere they molest! Here lies your brother,<br>
No better than the earth he lies upon,<br>
If he were that which now he’s like, that’s dead;<br>
Whom I, with this obedient steel, three inches of it,<br>
Can lay to bed for ever; whiles you, doing thus,<br>
To the perpetual wink for aye might put<br>
This ancient morsel, this Sir Prudence, who<br>
Should not upbraid our course. For all the rest,<br>
They’ll take suggestion as a cat laps milk.<br>
They’ll tell the clock to any business that<br>
We say befits the hour.
</p>

<p class="drama">
SEBASTIAN.<br>
Thy case, dear friend,<br>
Shall be my precedent: as thou got’st Milan,<br>
I’ll come by Naples. Draw thy sword: one stroke<br>
Shall free thee from the tribute which thou payest,<br>
And I the King shall love thee.
</p>

<p class="drama">
ANTONIO.<br>
Draw together,<br>
And when I rear my hand, do you the like,<br>
To fall it on Gonzalo.
</p>

<p class="drama">
SEBASTIAN.<br>
O, but one word.
</p>

<p class="right"> [<i>They converse apart.</i>]</p>

<p class="scenedesc">Music. Re-enter <span class="charname">Ariel,</span> invisible.</p>

<p class="drama">
ARIEL.<br>
My master through his art foresees the danger<br>
That you, his friend, are in; and sends me forth—<br>
For else his project dies—to keep them living.
</p>

<p class="drama">
[<i>Sings in Gonzalo’s ear.</i>]<br>
<i>While you here do snoring lie,<br>
Open-ey’d conspiracy<br>
    His time doth take.<br>
If of life you keep a care,<br>
Shake off slumber, and beware.<br>
    Awake! awake!</i>
</p>

<p class="drama">
ANTONIO.<br>
Then let us both be sudden.
</p>

<p class="drama">
GONZALO.<br>
Now, good angels<br>
Preserve the King!
</p>

<p class="right"> [<i>They wake.</i>]</p>

<p class="drama">
ALONSO.<br>
Why, how now! Ho, awake! Why are you drawn?<br>
Wherefore this ghastly looking?
</p>

<p class="drama">
GONZALO.<br>
What’s the matter?
</p>

<p class="drama">
SEBASTIAN.<br>
Whiles we stood here securing your repose,<br>
Even now, we heard a hollow burst of bellowing<br>
Like bulls, or rather lions; did ’t not wake you?<br>
It struck mine ear most terribly.
</p>

<p class="drama">
ALONSO.<br>
I heard nothing.
</p>

<p class="drama">
ANTONIO.<br>
O! ’twas a din to fright a monster’s ear,<br>
To make an earthquake. Sure, it was the roar<br>
Of a whole herd of lions.
</p>

<p class="drama">
ALONSO.<br>
Heard you this, Gonzalo?
</p>

<p class="drama">
GONZALO.<br>
Upon mine honour, sir, I heard a humming,<br>
And that a strange one too, which did awake me.<br>
I shak’d you, sir, and cried; as mine eyes open’d,<br>
I saw their weapons drawn:—there was a noise,<br>
That’s verily. ’Tis best we stand upon our guard,<br>
Or that we quit this place: let’s draw our weapons.
</p>

<p class="drama">
ALONSO.<br>
Lead off this ground, and let’s make further search<br>
For my poor son.
</p>

<p class="drama">
GONZALO.<br>
Heavens keep him from these beasts!<br>
For he is, sure, i’ th’ island.
</p>

<p class="drama">
ALONSO.<br>
Lead away.
</p>

<p class="right"> [<i>Exit with the others.</i>]</p>

<p class="drama">
ARIEL.<br>
Prospero my lord shall know what I have done:<br>
So, King, go safely on to seek thy son.
</p>

<p class="right"> [<i>Exit.</i>]</p>

<h3> <a id="sceneII_32.2"></a><b>SCENE II. Another part of the island.</b></h3>

<p class="scenedesc">Enter <span class="charname">Caliban</span> with a burden
of wood. A noise of thunder heard.
</p>

<p class="drama">
CALIBAN.<br>
All the infections that the sun sucks up<br>
From bogs, fens, flats, on Prosper fall, and make him<br>
By inch-meal a disease! His spirits hear me,<br>
And yet I needs must curse. But they’ll nor pinch,<br>
Fright me with urchin-shows, pitch me i’ the mire,<br>
Nor lead me, like a firebrand, in the dark<br>
Out of my way, unless he bid ’em; but<br>
For every trifle are they set upon me,<br>
Sometime like apes that mow and chatter at me,<br>
And after bite me; then like hedgehogs which<br>
Lie tumbling in my barefoot way, and mount<br>
Their pricks at my footfall; sometime am I<br>
All wound with adders, who with cloven tongues<br>
Do hiss me into madness.
</p>

<p class="scenedesc">Enter <span class="charname">Trinculo</span>.
</p>

<p class="drama">
Lo, now, lo!<br>
Here comes a spirit of his, and to torment me<br>
For bringing wood in slowly. I’ll fall flat;<br>
Perchance he will not mind me.
</p>

<p class="drama">
TRINCULO.<br>
Here’s neither bush nor shrub to bear off any weather at all, and another
storm brewing; I hear it sing i’ th’ wind. Yond same black cloud,
yond huge one, looks like a foul bombard that would shed his liquor. If it
should thunder as it did before, I know not where to hide my head: yond same
cloud cannot choose but fall by pailfuls. What have we here? a man or a fish?
dead or alive? A fish: he smells like a fish; a very ancient and fish-like
smell; a kind of not of the newest Poor-John. A strange fish! Were I in England
now, as once I was, and had but this fish painted, not a holiday fool there but
would give a piece of silver: there would this monster make a man; any strange
beast there makes a man. When they will not give a doit to relieve a lame
beggar, they will lay out ten to see a dead Indian. Legg’d like a man,
and his fins like arms! Warm, o’ my troth! I do now let loose my opinion,
hold it no longer: this is no fish, but an islander, that hath lately suffered
by thunderbolt. [<i>Thunder.</i>] Alas, the storm is come again! My best way is
to creep under his gaberdine; there is no other shelter hereabout: misery
acquaints a man with strange bed-fellows. I will here shroud till the dregs of
the storm be past.
</p>

<p class="scenedesc">Enter <span class="charname">Stephano</span> singing; a
bottle in his hand.
</p>

<p class="drama">
STEPHANO.<br>
<i>I shall no more to sea, to sea,<br>
Here shall I die ashore—</i>
</p>

<p class="drama">
This is a very scurvy tune to sing at a man’s funeral.<br>
Well, here’s my comfort.
</p>

<p class="right"> [<i>Drinks.</i>]</p>

<p class="drama">
<i>The master, the swabber, the boatswain, and I,<br>
    The gunner, and his mate,<br>
Lov’d Mall, Meg, and Marian, and Margery,<br>
    But none of us car’d for Kate:<br>
    For she had a tongue with a tang,<br>
    Would cry to a sailor “Go hang!”<br>
She lov’d not the savour of tar nor of pitch,<br>
Yet a tailor might scratch her where’er she did itch.<br>
    Then to sea, boys, and let her go hang.</i>
</p>

<p class="drama">
This is a scurvy tune too: but here’s my comfort.
</p>

<p class="right"> [<i>Drinks.</i>]</p>

<p class="drama">
CALIBAN.<br>
Do not torment me: O!
</p>

<p class="drama">
STEPHANO.<br>
What’s the matter? Have we devils here? Do you put tricks upon ’s
with savages and men of Ind? Ha? I have not scap’d drowning, to be
afeard now of your four legs; for it hath been said, As proper a man as ever
went on four legs cannot make him give ground; and it shall be said so again,
while Stephano breathes at’ nostrils.
</p>

<p class="drama">
CALIBAN.<br>
The spirit torments me: O!
</p>

<p class="drama">
STEPHANO.<br>
This is some monster of the isle with four legs, who hath got, as I take it, an
ague. Where the devil should he learn our language? I will give him some
relief, if it be but for that. If I can recover him and keep him tame, and get
to Naples with him, he’s a present for any emperor that ever trod on
neat’s-leather.
</p>

<p class="drama">
CALIBAN.<br>
Do not torment me, prithee; I’ll bring my wood home faster.
</p>

<p class="drama">
STEPHANO.<br>
He’s in his fit now, and does not talk after the wisest. He shall taste
of my bottle: if he have never drunk wine afore, it will go near to remove his
fit. If I can recover him, and keep him tame, I will not take too much for him.
He shall pay for him that hath him, and that soundly.
</p>

<p class="drama">
CALIBAN.<br>
Thou dost me yet but little hurt; thou wilt anon,<br>
I know it by thy trembling: now Prosper works upon thee.
</p>

<p class="drama">
STEPHANO.<br>
Come on your ways. Open your mouth; here is that which will give language to
you, cat. Open your mouth. This will shake your shaking, I can tell you, and
that soundly. [<i>gives Caliban a drink</i>] You cannot tell who’s your
friend: open your chaps again.
</p>

<p class="drama">
TRINCULO.<br>
I should know that voice: it should be—but he is drowned; and these are
devils. O, defend me!
</p>

<p class="drama">
STEPHANO.<br>
Four legs and two voices; a most delicate monster! His forward voice now is to
speak well of his friend; his backward voice is to utter foul speeches and to
detract. If all the wine in my bottle will recover him, I will help his ague.
Come. Amen! I will pour some in thy other mouth.
</p>

<p class="drama">
TRINCULO.<br>
Stephano!
</p>

<p class="drama">
STEPHANO.<br>
Doth thy other mouth call me? Mercy! mercy!<br>
This is a devil, and no monster: I will leave him; I<br>
have no long spoon.
</p>

<p class="drama">
TRINCULO.<br>
Stephano! If thou beest Stephano, touch me, and speak to me; for I am
Trinculo—be not afeared—thy good friend Trinculo.
</p>

<p class="drama">
STEPHANO.<br>
If thou beest Trinculo, come forth. I’ll pull thee by the lesser legs: if
any be Trinculo’s legs, these are they. Thou art very Trinculo indeed!
How cam’st thou to be the siege of this moon-calf? Can he vent Trinculos?
</p>

<p class="drama">
TRINCULO.<br>
I took him to be kill’d with a thunderstroke. But art thou not
drown’d, Stephano? I hope now thou are not drown’d. Is the storm
overblown? I hid me under the dead moon-calf’s gaberdine for fear of the
storm. And art thou living, Stephano? O Stephano, two Neapolitans scap’d!
</p>

<p class="drama">
STEPHANO.<br>
Prithee, do not turn me about. My stomach is not constant.
</p>

<p class="drama">
CALIBAN.<br>
[<i>Aside.</i>] These be fine things, an if they be not sprites.<br>
That’s a brave god, and bears celestial liquor.<br>
I will kneel to him.
</p>

<p class="drama">
STEPHANO.<br>
How didst thou scape? How cam’st thou hither? Swear by  this bottle how
thou cam’st hither—I escaped upon a butt of sack, which the sailors
heaved o’erboard, by this bottle! which I made of the bark of a tree with
mine own hands, since I was cast ashore.
</p>

<p class="drama">
CALIBAN.<br>
I’ll swear upon that bottle to be thy true subject, for the liquor is not
earthly.
</p>

<p class="drama">
STEPHANO.<br>
Here. Swear then how thou escapedst.
</p>

<p class="drama">
TRINCULO.<br>
Swum ashore, man, like a duck: I can swim like a duck, I’ll be sworn.
</p>

<p class="drama">
STEPHANO.<br>
Here, kiss the book. Though thou canst swim like a duck, thou art made like a
goose.
</p>

<p class="drama">
TRINCULO.<br>
O Stephano, hast any more of this?
</p>

<p class="drama">
STEPHANO.<br>
The whole butt, man: my cellar is in a rock by th’ seaside, where my wine
is hid. How now, moon-calf! How does thine ague?
</p>

<p class="drama">
CALIBAN.<br>
Hast thou not dropped from heaven?
</p>

<p class="drama">
STEPHANO.<br>
Out o’ the moon, I do assure thee: I was the Man in the Moon, when time
was.
</p>

<p class="drama">
CALIBAN.<br>
I have seen thee in her, and I do adore thee. My mistress showed me thee, and
thy dog, and thy bush.
</p>

<p class="drama">
STEPHANO.<br>
Come, swear to that. Kiss the book. I will furnish it anon with new contents.
Swear.
</p>

<p class="drama">
TRINCULO.<br>
By this good light, this is a very shallow monster. I afeard of him? A very
weak monster. The Man i’ the Moon! A most poor credulous monster! Well
drawn, monster, in good sooth!
</p>

<p class="drama">
CALIBAN.<br>
I’ll show thee every fertile inch o’ the island; and I will kiss
thy foot. I prithee, be my god.
</p>

<p class="drama">
TRINCULO.<br>
By this light, a most perfidious and drunken monster. When ’s god’s
asleep, he’ll rob his bottle.
</p>

<p class="drama">
CALIBAN.<br>
I’ll kiss thy foot. I’ll swear myself thy subject.
</p>

<p class="drama">
STEPHANO.<br>
Come on, then; down, and swear.
</p>

<p class="drama">
TRINCULO.<br>
I shall laugh myself to death at this puppy-headed monster. A most scurvy
monster! I could find in my heart to beat him,—
</p>

<p class="drama">
STEPHANO.<br>
Come, kiss.
</p>

<p class="drama">
TRINCULO.<br>
But that the poor monster’s in drink. An abominable monster!
</p>

<p class="drama">
CALIBAN.<br>
I’ll show thee the best springs; I’ll pluck thee berries;<br>
I’ll fish for thee, and get thee wood enough.<br>
A plague upon the tyrant that I serve!<br>
I’ll bear him no more sticks, but follow thee,<br>
Thou wondrous man.
</p>

<p class="drama">
TRINCULO.<br>
A most ridiculous monster, to make a wonder of a poor drunkard!
</p>

<p class="drama">
CALIBAN.<br>
I prithee, let me bring thee where crabs grow;<br>
And I with my long nails will dig thee pig-nuts;<br>
Show thee a jay’s nest, and instruct thee how<br>
To snare the nimble marmoset; I’ll bring thee<br>
To clustering filberts, and sometimes I’ll get thee<br>
Young scamels from the rock. Wilt thou go with me?
</p>

<p class="drama">
STEPHANO.<br>
I prithee now, lead the way without any more talking. Trinculo, the King and
all our company else being drowned, we will inherit here. Here, bear my bottle.
Fellow Trinculo, we’ll fill him by and by again.
</p>

<p class="drama">
CALIBAN.<br>
[<i>Sings drunkenly.</i>] <i>Farewell, master; farewell, farewell!</i>
</p>

<p class="drama">
TRINCULO.<br>
A howling monster, a drunken monster.
</p>

<p class="drama">
CALIBAN.<br>
<i>No more dams I’ll make for fish;<br>
Nor fetch in firing<br>
At requiring,<br>
Nor scrape trenchering, nor wash dish;<br>
’Ban ’Ban, Cacaliban,<br>
Has a new master—Get a new man.</i><br>
Freedom, high-day! high-day, freedom! freedom,<br>
high-day, freedom!
</p>

<p class="drama">
STEPHANO.<br>
O brave monster! lead the way.
</p>

<p class="right"> [<i>Exeunt.</i>]</p>

