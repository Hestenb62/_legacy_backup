<h2> <a id="sceneIV_32.1"></a><b>ACT IV</b></h2>

<h3> <b>SCENE I. Before Prospero’s cell.</b></h3>

<p class="scenedesc">Enter <span class="charname">Prospero, Ferdinand</span> and
<span class="charname">Miranda</span>.</p>

<p class="drama">
PROSPERO.<br>
If I have too austerely punish’d you,<br>
Your compensation makes amends: for I<br>
Have given you here a third of mine own life,<br>
Or that for which I live; who once again<br>
I tender to thy hand: all thy vexations<br>
Were but my trials of thy love, and thou<br>
Hast strangely stood the test: here, afore Heaven,<br>
I ratify this my rich gift. O Ferdinand,<br>
Do not smile at me that I boast her off,<br>
For thou shalt find she will outstrip all praise,<br>
And make it halt behind her.
</p>

<p class="drama">
FERDINAND.<br>
I do believe it<br>
Against an oracle.
</p>

<p class="drama">
PROSPERO.<br>
Then, as my gift and thine own acquisition<br>
Worthily purchas’d, take my daughter: but<br>
If thou dost break her virgin knot before<br>
All sanctimonious ceremonies may<br>
With full and holy rite be minister’d,<br>
No sweet aspersion shall the heavens let fall<br>
To make this contract grow; but barren hate,<br>
Sour-ey’d disdain, and discord shall bestrew<br>
The union of your bed with weeds so loathly<br>
That you shall hate it both: therefore take heed,<br>
As Hymen’s lamps shall light you.
</p>

<p class="drama">
FERDINAND.<br>
As I hope<br>
For quiet days, fair issue, and long life,<br>
With such love as ’tis now, the murkiest den,<br>
The most opportune place, the strong’st suggestion<br>
Our worser genius can, shall never melt<br>
Mine honour into lust, to take away<br>
The edge of that day’s celebration,<br>
When I shall think, or Phoebus’ steeds are founder’d,<br>
Or Night kept chain’d below.
</p>

<p class="drama">
PROSPERO.<br>
Fairly spoke:<br>
Sit, then, and talk with her, she is thine own.<br>
What, Ariel! my industrious servant, Ariel!
</p>

<p class="scenedesc">Enter <span class="charname">Ariel</span>.
</p>

<p class="drama">
ARIEL.<br>
What would my potent master? here I am.
</p>

<p class="drama">
PROSPERO.<br>
Thou and thy meaner fellows your last service<br>
Did worthily perform; and I must use you<br>
In such another trick. Go bring the rabble,<br>
O’er whom I give thee power, here to this place.<br>
Incite them to quick motion; for I must<br>
Bestow upon the eyes of this young couple<br>
Some vanity of mine art: it is my promise,<br>
And they expect it from me.
</p>

<p class="drama">
ARIEL.<br>
Presently?
</p>

<p class="drama">
PROSPERO.<br>
Ay, with a twink.
</p>

<p class="drama">
ARIEL.<br>
Before you can say “Come” and “Go,”<br>
And breathe twice, and cry “so, so,”<br>
Each one, tripping on his toe,<br>
Will be here with mop and mow.<br>
Do you love me, master? no?
</p>

<p class="drama">
PROSPERO.<br>
Dearly, my delicate Ariel. Do not approach<br>
Till thou dost hear me call.
</p>

<p class="drama">
ARIEL.<br>
Well, I conceive.
</p>

<p class="right"> [<i>Exit.</i>]</p>

<p class="drama">
PROSPERO.<br>
Look thou be true; do not give dalliance<br>
Too much the rein: the strongest oaths are straw<br>
To th’ fire i’ the blood: be more abstemious,<br>
Or else good night your vow!
</p>

<p class="drama">
FERDINAND.<br>
I warrant you, sir;<br>
The white cold virgin snow upon my heart<br>
Abates the ardour of my liver.
</p>

<p class="drama">
PROSPERO.<br>
Well.<br>
Now come, my Ariel! bring a corollary,<br>
Rather than want a spirit: appear, and pertly.<br>
No tongue! all eyes! be silent.
</p>

<p class="right"> [<i>Soft music.</i>]</p>

<p class="scenedesc">A Masque. Enter <span class="charname">Iris</span>.
</p>

<p class="drama">
IRIS.<br>
Ceres, most bounteous lady, thy rich leas<br>
Of wheat, rye, barley, vetches, oats, and peas;<br>
Thy turfy mountains, where live nibbling sheep,<br>
And flat meads thatch’d with stover, them to keep;<br>
Thy banks with pioned and twilled brims,<br>
Which spongy April at thy hest betrims,<br>
To make cold nymphs chaste crowns; and thy broom groves,<br>
Whose shadow the dismissed bachelor loves,<br>
Being lass-lorn; thy pole-clipt vineyard;<br>
And thy sea-marge, sterile and rocky-hard,<br>
Where thou thyself dost air: the Queen o’ th’ sky,<br>
Whose wat’ry arch and messenger am I,<br>
Bids thee leave these; and with her sovereign grace,<br>
Here on this grass-plot, in this very place,<br>
To come and sport; her peacocks fly amain:<br>
Approach, rich Ceres, her to entertain.
</p>

<p class="scenedesc">Enter <span class="charname">Ceres</span>.
</p>

<p class="drama">
CERES.<br>
Hail, many-colour’d messenger, that ne’er<br>
Dost disobey the wife of Jupiter;<br>
Who with thy saffron wings upon my flowers<br>
Diffusest honey drops, refreshing showers;<br>
And with each end of thy blue bow dost crown<br>
My bosky acres and my unshrubb’d down,<br>
Rich scarf to my proud earth; why hath thy queen<br>
Summon’d me hither to this short-grass’d green?
</p>

<p class="drama">
IRIS.<br>
A contract of true love to celebrate,<br>
And some donation freely to estate<br>
On the blest lovers.
</p>

<p class="drama">
CERES.<br>
Tell me, heavenly bow,<br>
If Venus or her son, as thou dost know,<br>
Do now attend the queen? Since they did plot<br>
The means that dusky Dis my daughter got,<br>
Her and her blind boy’s scandal’d company<br>
I have forsworn.
</p>

<p class="drama">
IRIS.<br>
Of her society<br>
Be not afraid. I met her deity<br>
Cutting the clouds towards Paphos, and her son<br>
Dove-drawn with her. Here thought they to have done<br>
Some wanton charm upon this man and maid,<br>
Whose vows are, that no bed-right shall be paid<br>
Till Hymen’s torch be lighted; but in vain.<br>
Mars’s hot minion is return’d again;<br>
Her waspish-headed son has broke his arrows,<br>
Swears he will shoot no more, but play with sparrows,<br>
And be a boy right out.
</p>

<p class="drama">
CERES.<br>
Highest queen of State,<br>
Great Juno comes; I know her by her gait.
</p>

<p class="scenedesc">Enter <span class="charname">Juno</span>.
</p>

<p class="drama">
JUNO.<br>
How does my bounteous sister? Go with me<br>
To bless this twain, that they may prosperous be,<br>
And honour’d in their issue.
</p>

<p class="right"> [<i>They sing.</i>]</p>

<p class="drama">
JUNO.<br>
<i>Honour, riches, marriage-blessing,<br>
Long continuance, and increasing,<br>
Hourly joys be still upon you!<br>
Juno sings her blessings on you.</i>
</p>

<p class="drama">
CERES.<br>
<i>Earth’s increase, foison plenty,<br>
Barns and garners never empty;<br>
Vines with clust’ring bunches growing;<br>
Plants with goodly burden bowing;<br>
Spring come to you at the farthest<br>
In the very end of harvest!<br>
Scarcity and want shall shun you;<br>
Ceres’ blessing so is on you.</i>
</p>

<p class="drama">
FERDINAND.<br>
This is a most majestic vision, and<br>
Harmonious charmingly. May I be bold<br>
To think these spirits?
</p>

<p class="drama">
PROSPERO.<br>
Spirits, which by mine art<br>
I have from their confines call’d to enact<br>
My present fancies.
</p>

<p class="drama">
FERDINAND.<br>
Let me live here ever.<br>
So rare a wonder’d father and a wise,<br>
Makes this place Paradise.
</p>

<p class="right"> [<i><span class="charname">Juno</span> and
<span class="charname">Ceres</span> whisper, and send
<span class="charname">Iris</span> on employment.</i>]</p>

<p class="drama">
PROSPERO.<br>
Sweet now, silence!<br>
Juno and Ceres whisper seriously,<br>
There’s something else to do: hush, and be mute,<br>
Or else our spell is marr’d.
</p>

<p class="drama">
IRIS.<br>
You nymphs, call’d Naiads, of the windring brooks,<br>
With your sedg’d crowns and ever-harmless looks,<br>
Leave your crisp channels, and on this green land<br>
Answer your summons; Juno does command.<br>
Come, temperate nymphs, and help to celebrate<br>
A contract of true love. Be not too late.
</p>

<p class="scenedesc">Enter certain <span class="charname">Nymphs</span>.
</p>

<p class="drama">
You sun-burn’d sicklemen, of August weary,<br>
Come hither from the furrow, and be merry:<br>
Make holiday: your rye-straw hats put on,<br>
And these fresh nymphs encounter every one<br>
In country footing.
</p>

<p class="scenedesc">Enter certain Reapers, properly habited: they join with
the Nymphs in a graceful dance; towards the end whereof <span class="charname">Prospero</span> starts suddenly, and speaks; after which, to a
strange, hollow, and confused noise, they heavily vanish.
</p>

<p class="drama">
PROSPERO.<br>
[<i>Aside.</i>] I had forgot that foul conspiracy<br>
Of the beast Caliban and his confederates<br>
Against my life: the minute of their plot<br>
Is almost come. [<i>To the Spirits.</i>] Well done! avoid; no<br>
more!
</p>

<p class="drama">
FERDINAND.<br>
This is strange: your father’s in some passion<br>
That works him strongly.
</p>

<p class="drama">
MIRANDA.<br>
Never till this day<br>
Saw I him touch’d with anger so distemper’d.
</p>

<p class="drama">
PROSPERO.<br>
You do look, my son, in a mov’d sort,<br>
As if you were dismay’d: be cheerful, sir:<br>
Our revels now are ended. These our actors,<br>
As I foretold you, were all spirits and<br>
Are melted into air, into thin air:<br>
And, like the baseless fabric of this vision,<br>
The cloud-capp’d towers, the gorgeous palaces,<br>
The solemn temples, the great globe itself,<br>
Yea, all which it inherit, shall dissolve,<br>
And, like this insubstantial pageant faded,<br>
Leave not a rack behind. We are such stuff<br>
As dreams are made on, and our little life<br>
Is rounded with a sleep. Sir, I am vex’d:<br>
Bear with my weakness; my old brain is troubled.<br>
Be not disturb’d with my infirmity.<br>
If you be pleas’d, retire into my cell<br>
And there repose: a turn or two I’ll walk,<br>
To still my beating mind.
</p>

<p class="drama">
FERDINAND, MIRANDA.<br>
We wish your peace.
</p>

<p class="right"> [<i>Exeunt.</i>]</p>

<p class="drama">
PROSPERO.<br>
Come, with a thought. I thank thee, Ariel. Come!
</p>

<p class="scenedesc">Enter <span class="charname">Ariel</span>.
</p>

<p class="drama">
ARIEL.<br>
Thy thoughts I cleave to. What’s thy pleasure?
</p>

<p class="drama">
PROSPERO.<br>
Spirit,<br>
We must prepare to meet with Caliban.
</p>

<p class="drama">
ARIEL.<br>
Ay, my commander. When I presented Ceres,<br>
I thought to have told thee of it; but I fear’d<br>
Lest I might anger thee.
</p>

<p class="drama">
PROSPERO.<br>
Say again, where didst thou leave these varlets?
</p>

<p class="drama">
ARIEL.<br>
I told you, sir, they were red-hot with drinking;<br>
So full of valour that they smote the air<br>
For breathing in their faces; beat the ground<br>
For kissing of their feet; yet always bending<br>
Towards their project. Then I beat my tabor;<br>
At which, like unback’d colts, they prick’d their ears,<br>
Advanc’d their eyelids, lifted up their noses<br>
As they smelt music: so I charm’d their ears,<br>
That calf-like they my lowing follow’d through<br>
Tooth’d briers, sharp furzes, pricking goss, and thorns,<br>
Which enter’d their frail shins: at last I left them<br>
I’ th’ filthy-mantled pool beyond your cell,<br>
There dancing up to th’ chins, that the foul lake<br>
O’erstunk their feet.
</p>

<p class="drama">
PROSPERO.<br>
This was well done, my bird.<br>
Thy shape invisible retain thou still:<br>
The trumpery in my house, go bring it hither<br>
For stale to catch these thieves.
</p>

<p class="drama">
ARIEL.<br>
I go, I go.
</p>

<p class="right"> [<i>Exit.</i>]</p>

<p class="drama">
PROSPERO.<br>
A devil, a born devil, on whose nature<br>
Nurture can never stick; on whom my pains,<br>
Humanely taken, all, all lost, quite lost;<br>
And as with age his body uglier grows,<br>
So his mind cankers. I will plague them all,<br>
Even to roaring.
</p>

<p class="scenedesc">Re-enter <span class="charname">Ariel,</span>
loaden with glistering apparel, &amp;c.</p>

<p class="drama">
Come, hang them on this line.
</p>

<p class="scenedesc"><span class="charname">Prospero</span> and
<span class="charname">Ariel</span> remain invisible. Enter
<span class="charname">Caliban, Stephano</span> and <span class="charname">Trinculo
all wet</span>.</p>

<p class="drama">
CALIBAN.<br>
Pray you, tread softly, that the blind mole may not<br>
Hear a foot fall: we now are near his cell.
</p>

<p class="drama">
STEPHANO.<br>
Monster, your fairy, which you say is a harmless fairy, has done little better
than played the Jack with us.
</p>

<p class="drama">
TRINCULO.<br>
Monster, I do smell all horse-piss; at which my nose is in great indignation.
</p>

<p class="drama">
STEPHANO.<br>
So is mine. Do you hear, monster? If I should take a displeasure against you,
look you,—
</p>

<p class="drama">
TRINCULO.<br>
Thou wert but a lost monster.
</p>

<p class="drama">
CALIBAN.<br>
Good my lord, give me thy favour still.<br>
Be patient, for the prize I’ll bring thee to<br>
Shall hoodwink this mischance: therefore speak softly.<br>
All’s hush’d as midnight yet.
</p>

<p class="drama">
TRINCULO.<br>
Ay, but to lose our bottles in the pool!
</p>

<p class="drama">
STEPHANO.<br>
There is not only disgrace and dishonour in that, monster, but an infinite
loss.
</p>

<p class="drama">
TRINCULO.<br>
That’s more to me than my wetting: yet this is your harmless fairy,
monster.
</p>

<p class="drama">
STEPHANO.<br>
I will fetch off my bottle, though I be o’er ears for my labour.
</p>

<p class="drama">
CALIBAN.<br>
Prithee, my King, be quiet. Seest thou here,<br>
This is the mouth o’ th’ cell: no noise, and enter.<br>
Do that good mischief which may make this island<br>
Thine own for ever, and I, thy Caliban,<br>
For aye thy foot-licker.
</p>

<p class="drama">
STEPHANO.<br>
Give me thy hand. I do begin to have bloody thoughts.
</p>

<p class="drama">
TRINCULO.<br>
O King Stephano! O peer! O worthy Stephano!<br>
Look what a wardrobe here is for thee!
</p>

<p class="drama">
CALIBAN.<br>
Let it alone, thou fool; it is but trash.
</p>

<p class="drama">
TRINCULO.<br>
O, ho, monster! we know what belongs to a frippery. O King Stephano!
</p>

<p class="drama">
STEPHANO.<br>
Put off that gown, Trinculo; by this hand, I’ll have that gown.
</p>

<p class="drama">
TRINCULO.<br>
Thy Grace shall have it.
</p>

<p class="drama">
CALIBAN.<br>
The dropsy drown this fool! What do you mean<br>
To dote thus on such luggage? Let’t alone,<br>
And do the murder first. If he awake,<br>
From toe to crown he’ll fill our skins with pinches,<br>
Make us strange stuff.
</p>

<p class="drama">
STEPHANO.<br>
Be you quiet, monster. Mistress line, is not this my jerkin? Now is the jerkin
under the line: now, jerkin, you are like to lose your hair, and prove a bald
jerkin.
</p>

<p class="drama">
TRINCULO.<br>
Do, do: we steal by line and level, an’t like your Grace.
</p>

<p class="drama">
STEPHANO.<br>
I thank thee for that jest. Here’s a garment for ’t: wit shall not
go unrewarded while I am King of this country. “Steal by line and
level,” is an excellent pass of pate. There’s another garment
for ’t.
</p>

<p class="drama">
TRINCULO.<br>
Monster, come, put some lime upon your fingers, and away with the rest.
</p>

<p class="drama">
CALIBAN.<br>
I will have none on’t. We shall lose our time,<br>
And all be turn’d to barnacles, or to apes<br>
With foreheads villainous low.
</p>

<p class="drama">
STEPHANO.<br>
Monster, lay-to your fingers: help to bear this away where my hogshead of wine
is, or I’ll turn you out of my kingdom. Go to, carry this.
</p>

<p class="drama">
TRINCULO.<br>
And this.
</p>

<p class="drama">
STEPHANO.<br>
Ay, and this.
</p>

<p class="scenedesc">A noise of hunters heard. Enter divers Spirits, in shape
of dogs and hounds, and hunt them about; <span class="charname">Prospero</span>
and <span class="charname">Ariel</span> setting them on.</p>

<p class="drama">
PROSPERO.<br>
Hey, Mountain, hey!
</p>

<p class="drama">
ARIEL.<br>
Silver! there it goes, Silver!
</p>

<p class="drama">
PROSPERO.<br>
Fury, Fury! There, Tyrant, there! hark, hark!
</p>

<p class="right"> [<i><span class="charname">Caliban, Stephano</span> and
<span class="charname">Trinculo</span> are driven out.</i>]</p>

<p class="drama">
Go, charge my goblins that they grind their joints<br>
With dry convulsions; shorten up their sinews<br>
With aged cramps, and more pinch-spotted make them<br>
Than pard, or cat o’ mountain.
</p>

<p class="drama">
ARIEL.<br>
Hark, they roar.
</p>

<p class="drama">
PROSPERO.<br>
Let them be hunted soundly. At this hour<br>
Lies at my mercy all mine enemies.<br>
Shortly shall all my labours end, and thou<br>
Shalt have the air at freedom. For a little<br>
Follow, and do me service.
</p>

<p class="right"> [<i>Exeunt.</i>]</p>

