<h2> <a id="sceneI_19.1"></a><b>ACT I</b></h2>

<h3> <b>SCENE I. The King of Navarre’s park</b></h3>

<p class="scenedesc">
Enter Ferdinand, <span class="charname">King of Navarre, Berowne,
Longaville</span> and <span class="charname">Dumaine</span>.
</p>

<p class="drama">
KING.<br>
Let fame, that all hunt after in their lives,<br>
Live registered upon our brazen tombs,<br>
And then grace us in the disgrace of death;<br>
When, spite of cormorant devouring time,<br>
Th’ endeavour of this present breath may buy<br>
That honour which shall bate his scythe’s keen edge,<br>
And make us heirs of all eternity.<br>
Therefore, brave conquerors, for so you are<br>
That war against your own affections<br>
And the huge army of the world’s desires,<br>
Our late edict shall strongly stand in force.<br>
Navarre shall be the wonder of the world;<br>
Our court shall be a little academe,<br>
Still and contemplative in living art.<br>
You three, Berowne, Dumaine and Longaville,<br>
Have sworn for three years’ term to live with me,<br>
My fellow-scholars, and to keep those statutes<br>
That are recorded in this schedule here.<br>
Your oaths are passed, and now subscribe your names,<br>
That his own hand may strike his honour down<br>
That violates the smallest branch herein.<br>
If you are armed to do as sworn to do,<br>
Subscribe to your deep oaths, and keep it too.
</p>

<p class="drama">
LONGAVILLE.<br>
I am resolved. ’Tis but a three years’ fast.<br>
The mind shall banquet, though the body pine.<br>
Fat paunches have lean pates, and dainty bits<br>
Make rich the ribs, but bankrupt quite the wits.
</p>

<p class="right">[<i>He signs.</i>]</p>

<p class="drama">
DUMAINE.<br>
My loving lord, Dumaine is mortified.<br>
The grosser manner of these world’s delights<br>
He throws upon the gross world’s baser slaves.<br>
To love, to wealth, to pomp, I pine and die,<br>
With all these living in philosophy.
</p>

<p class="right">[<i>He signs.</i>]</p>

<p class="drama">
BEROWNE.<br>
I can but say their protestation over.<br>
So much, dear liege, I have already sworn,<br>
That is, to live and study here three years.<br>
But there are other strict observances:<br>
As not to see a woman in that term,<br>
Which I hope well is not enrolled there;<br>
And one day in a week to touch no food,<br>
And but one meal on every day beside,<br>
The which I hope is not enrolled there;<br>
And then to sleep but three hours in the night,<br>
And not be seen to wink of all the day,<br>
When I was wont to think no harm all night,<br>
And make a dark night too of half the day,<br>
Which I hope well is not enrolled there.<br>
O, these are barren tasks, too hard to keep,<br>
Not to see ladies, study, fast, not sleep.
</p>

<p class="drama">
KING.<br>
Your oath is passed to pass away from these.
</p>

<p class="drama">
BEROWNE.<br>
Let me say no, my liege, an if you please.<br>
I only swore to study with your Grace<br>
And stay here in your court for three years’ space.
</p>

<p class="drama">
LONGAVILLE.<br>
You swore to that, Berowne, and to the rest.
</p>

<p class="drama">
BEROWNE.<br>
By yea and nay, sir, then I swore in jest.<br>
What is the end of study, let me know?
</p>

<p class="drama">
KING.<br>
Why, that to know which else we should not know.
</p>

<p class="drama">
BEROWNE.<br>
Things hid and barred, you mean, from common sense?
</p>

<p class="drama">
KING.<br>
Ay, that is study’s god-like recompense.
</p>

<p class="drama">
BEROWNE.<br>
Come on, then, I will swear to study so,<br>
To know the thing I am forbid to know:<br>
As thus, to study where I well may dine,<br>
    When I to feast expressly am forbid;<br>
Or study where to meet some mistress fine,<br>
    When mistresses from common sense are hid;<br>
Or, having sworn too hard-a-keeping oath,<br>
Study to break it, and not break my troth.<br>
If study’s gain be thus, and this be so,<br>
Study knows that which yet it doth not know.<br>
Swear me to this, and I will ne’er say no.
</p>

<p class="drama">
KING.<br>
These be the stops that hinder study quite,<br>
And train our intellects to vain delight.
</p>

<p class="drama">
BEROWNE.<br>
Why, all delights are vain, but that most vain<br>
Which, with pain purchased, doth inherit pain:<br>
As painfully to pore upon a book<br>
    To seek the light of truth, while truth the while<br>
Doth falsely blind the eyesight of his look.<br>
    Light seeking light doth light of light beguile;<br>
So, ere you find where light in darkness lies,<br>
Your light grows dark by losing of your eyes.<br>
Study me how to please the eye indeed<br>
    By fixing it upon a fairer eye,<br>
Who dazzling so, that eye shall be his heed,<br>
    And give him light that it was blinded by.<br>
Study is like the heaven’s glorious sun,<br>
    That will not be deep-searched with saucy looks;<br>
Small have continual plodders ever won,<br>
    Save base authority from others’ books.<br>
These earthly godfathers of heaven’s lights,<br>
    That give a name to every fixed star,<br>
Have no more profit of their shining nights<br>
    Than those that walk and wot not what they are.<br>
Too much to know is to know naught but fame,<br>
And every godfather can give a name.
</p>

<p class="drama">
KING.<br>
How well he’s read, to reason against reading.
</p>

<p class="drama">
DUMAINE.<br>
Proceeded well, to stop all good proceeding.
</p>

<p class="drama">
LONGAVILLE.<br>
He weeds the corn, and still lets grow the weeding.
</p>

<p class="drama">
BEROWNE.<br>
The spring is near when green geese are a-breeding.
</p>

<p class="drama">
DUMAINE.<br>
How follows that?
</p>

<p class="drama">
BEROWNE.<br>
Fit in his place and time.
</p>

<p class="drama">
DUMAINE.<br>
In reason nothing.
</p>

<p class="drama">
BEROWNE.<br>
Something then in rhyme.
</p>

<p class="drama">
LONGAVILLE.<br>
Berowne is like an envious sneaping frost<br>
That bites the first-born infants of the spring.
</p>

<p class="drama">
BEROWNE.<br>
Well, say I am. Why should proud summer boast<br>
Before the birds have any cause to sing?<br>
Why should I joy in any abortive birth?<br>
At Christmas I no more desire a rose<br>
Than wish a snow in May’s new-fangled shows,<br>
But like of each thing that in season grows.<br>
So you, to study now it is too late,<br>
Climb o’er the house to unlock the little gate.
</p>

<p class="drama">
KING.<br>
Well, sit you out. Go home, Berowne. Adieu.
</p>

<p class="drama">
BEROWNE.<br>
No, my good lord, I have sworn to stay with you,<br>
And though I have for barbarism spoke more<br>
    Than for that angel knowledge you can say,<br>
Yet confident I’ll keep what I have sworn<br>
    And bide the penance of each three years’ day.<br>
Give me the paper, let me read the same,<br>
And to the strictest decrees I’ll write my name.
</p>

<p class="drama">
KING.<br>
How well this yielding rescues thee from shame.
</p>

<p class="drama">
BEROWNE.<br>
[<i>Reads</i>.] <i>Item, That no woman shall come within a mile of my court.</i>
Hath this been proclaimed?
</p>

<p class="drama">
LONGAVILLE.<br>
Four days ago.
</p>

<p class="drama">
BEROWNE.<br>
Let’s see the penalty. [<i>Reads</i>.] <i>On pain of losing her tongue.</i> Who
devised this penalty?
</p>

<p class="drama">
LONGAVILLE.<br>
Marry, that did I.
</p>

<p class="drama">
BEROWNE.<br>
Sweet lord, and why?
</p>

<p class="drama">
LONGAVILLE.<br>
To fright them hence with that dread penalty.
</p>

<p class="drama">
BEROWNE.<br>
A dangerous law against gentility.<br>
[<i>Reads</i>.] <i>Item, If any man be seen to talk with a woman within the
term of three years, he shall endure such public shame as the rest of the court
can possibly devise.</i><br>
This article, my liege, yourself must break,<br>
    For well you know here comes in embassy<br>
The French King’s daughter, with yourself to speak—<br>
    A mild of grace and complete majesty—<br>
About surrender up of Aquitaine<br>
    To her decrepit, sick, and bedrid father.<br>
Therefore this article is made in vain,<br>
    Or vainly comes th’ admired Princess hither.
</p>

<p class="drama">
KING.<br>
What say you, lords? Why, this was quite forgot.
</p>

<p class="drama">
BEROWNE.<br>
So study evermore is overshot.<br>
While it doth study to have what it would,<br>
It doth forget to do the thing it should;<br>
And when it hath the thing it hunteth most,<br>
’Tis won as towns with fire: so won, so lost.
</p>

<p class="drama">
KING.<br>
We must of force dispense with this decree.<br>
She must lie here on mere necessity.
</p>

<p class="drama">
BEROWNE.<br>
Necessity will make us all forsworn<br>
Three thousand times within this three years’ space;<br>
For every man with his affects is born,<br>
Not by might mastered, but by special grace.<br>
If I break faith, this word shall speak for me:<br>
I am forsworn on mere necessity.<br>
So to the laws at large I write my name,<br>
And he that breaks them in the least degree<br>
Stands in attainder of eternal shame.<br>
Suggestions are to other as to me;<br>
But I believe, although I seem so loath,<br>
I am the last that will last keep his oath.
</p>

<p class="right">[<i>He signs.</i>]</p>

<p class="drama">
But is there no quick recreation granted?
</p>

<p class="drama">
KING.<br>
Ay, that there is. Our court, you know, is haunted<br>
With a refined traveller of Spain,<br>
A man in all the world’s new fashion planted,<br>
That hath a mint of phrases in his brain;<br>
One who the music of his own vain tongue<br>
Doth ravish like enchanting harmony,<br>
A man of complements, whom right and wrong<br>
Have chose as umpire of their mutiny.<br>
This child of fancy, that Armado hight,<br>
For interim to our studies shall relate<br>
In high-born words the worth of many a knight<br>
From tawny Spain lost in the world’s debate.<br>
How you delight, my lords, I know not, I,<br>
But I protest I love to hear him lie,<br>
And I will use him for my minstrelsy.
</p>

<p class="drama">
BEROWNE.<br>
Armado is a most illustrious wight,<br>
A man of fire-new words, fashion’s own knight.
</p>

<p class="drama">
LONGAVILLE.<br>
Costard the swain and he shall be our sport,<br>
And so to study three years is but short.
</p>

<p class="scenedesc">
Enter <span class="charname">Dull</span>, a Constable, with a letter, and
<span class="charname">Costard</span>.
</p>

<p class="drama">
DULL.<br>
Which is the Duke’s own person?
</p>

<p class="drama">
BEROWNE.<br>
This, fellow. What wouldst?
</p>

<p class="drama">
DULL.<br>
I myself reprehend his own person, for I am his Grace’s farborough. But I
would see his own person in flesh and blood.
</p>

<p class="drama">
BEROWNE.<br>
This is he.
</p>

<p class="drama">
DULL.<br>
Signior Arm… Arm… commends you. There’s villainy abroad. This letter will tell
you more.
</p>

<p class="drama">
COSTARD.<br>
Sir, the contempts thereof are as touching me.
</p>

<p class="drama">
KING.<br>
A letter from the magnificent Armado.
</p>

<p class="drama">
BEROWNE.<br>
How long soever the matter, I hope in God for high words.
</p>

<p class="drama">
LONGAVILLE.<br>
A high hope for a low heaven. God grant us patience!
</p>

<p class="drama">
BEROWNE.<br>
To hear, or forbear laughing?
</p>

<p class="drama">
LONGAVILLE.<br>
To hear meekly, sir, and to laugh moderately, or to forbear both.
</p>

<p class="drama">
BEROWNE.<br>
Well, sir, be it as the style shall give us cause to climb in the merriness.
</p>

<p class="drama">
COSTARD.<br>
The matter is to me, sir, as concerning Jaquenetta. The manner of it is, I was
taken with the manner.
</p>

<p class="drama">
BEROWNE.<br>
In what manner?
</p>

<p class="drama">
COSTARD.<br>
In manner and form following, sir, all those three. I was seen with her in the
manor-house, sitting with her upon the form, and taken following her into the
park, which, put together, is “in manner and form following”. Now, sir, for the
manner. It is the manner of a man to speak to a woman. For the form—in some
form.
</p>

<p class="drama">
BEROWNE.<br>
For the “following”, sir?
</p>

<p class="drama">
COSTARD.<br>
As it shall follow in my correction, and God defend the right!
</p>

<p class="drama">
KING.<br>
Will you hear this letter with attention?
</p>

<p class="drama">
BEROWNE.<br>
As we would hear an oracle.
</p>

<p class="drama">
COSTARD.<br>
Such is the simplicity of man to hearken after the flesh.
</p>

<p class="drama">
KING.<br>
[<i>Reads</i>.] <i>Great deputy, the welkin’s vicegerent and sole dominator of<br>
Navarre, my soul’s earth’s god and body’s fostering patron—</i>
</p>

<p class="drama">
COSTARD.<br>
Not a word of Costard yet.
</p>

<p class="drama">
KING.<br>
[<i>Reads</i>.] <i>So it is—</i>
</p>

<p class="drama">
COSTARD.<br>
It may be so; but if he say it is so, he is, in telling true, but so.
</p>

<p class="drama">
KING.<br>
Peace!
</p>

<p class="drama">
COSTARD.<br>
Be to me, and every man that dares not fight.
</p>

<p class="drama">
KING.<br>
No words!
</p>

<p class="drama">
COSTARD.<br>
Of other men’s secrets, I beseech you.
</p>

<p class="drama">
KING.<br>
[<i>Reads</i>.] <i>So it is, besieged with sable-coloured melancholy, I did
commend the black-oppressing humour to the most wholesome physic of thy
health-giving air; and, as I am a gentleman, betook myself to walk. The time
when? About the sixth hour, when beasts most graze, birds best peck, and men
sit down to that nourishment which is called supper. So much for the time when.
Now for the ground which? Which, I mean, I walked upon. It is ycleped thy park.
Then for the place, where? Where, I mean, I did encounter that obscene and most
preposterous event that draweth from my snow-white pen the ebon-coloured ink,
which here thou viewest, beholdest, surveyest, or seest. But to the place
where? It standeth north-north-east and by east from the west corner of thy
curious-knotted garden. There did I see that low-spirited swain, that base
minnow of thy mirth—</i>
</p>

<p class="drama">
COSTARD.<br>
Me?
</p>

<p class="drama">
KING.<br>
[<i>Reads</i>.] <i>That unlettered small-knowing soul—</i>
</p>

<p class="drama">
COSTARD.<br>
Me?
</p>

<p class="drama">
KING.<br>
[<i>Reads</i>.] <i>That shallow vassal—</i>
</p>

<p class="drama">
COSTARD.<br>
Still me?
</p>

<p class="drama">
KING.<br>
[<i>Reads</i>.] <i>Which, as I remember, hight Costard—</i>
</p>

<p class="drama">
COSTARD.<br>
O me!
</p>

<p class="drama">
KING.<br>
[<i>Reads</i>.] <i>Sorted and consorted, contrary to thy established proclaimed
edict and continent canon, which with, O, with—but with this I passion to say
wherewith—</i>
</p>

<p class="drama">
COSTARD.<br>
With a wench.
</p>

<p class="drama">
KING.<br>
[<i>Reads</i>.] <i>With a child of our grandmother Eve, a female; or, for thy
more sweet understanding, a woman. Him, I, as my ever-esteemed duty pricks me
on, have sent to thee, to receive the meed of punishment, by thy sweet Grace’s
officer, Antony Dull, a man of good repute, carriage, bearing, and
estimation.</i>
</p>

<p class="drama">
DULL.<br>
Me, an’t shall please you; I am Antony Dull.
</p>

<p class="drama">
KING.<br>
[<i>Reads</i>.] <i>For Jaquenetta, so is the weaker vessel called which I
apprehended with the aforesaid swain, I keep her as a vessel of thy law’s fury,
and shall, at the least of thy sweet notice, bring her to trial. Thine, in all
compliments of devoted and heartburning heat of duty,<br>
                    Don Adriano de Armado.</i>
</p>

<p class="drama">
BEROWNE.<br>
This is not so well as I looked for, but the best that ever I heard.
</p>

<p class="drama">
KING.<br>
Ay, the best for the worst. But, sirrah, what say you to this?
</p>

<p class="drama">
COSTARD.<br>
Sir, I confess the wench.
</p>

<p class="drama">
KING.<br>
Did you hear the proclamation?
</p>

<p class="drama">
COSTARD.<br>
I do confess much of the hearing it, but little of the marking of it.
</p>

<p class="drama">
KING.<br>
It was proclaimed a year’s imprisonment to be taken with a wench.
</p>

<p class="drama">
COSTARD.<br>
I was taken with none, sir. I was taken with a damsel.
</p>

<p class="drama">
KING.<br>
Well, it was proclaimed “damsel”.
</p>

<p class="drama">
COSTARD.<br>
This was no damsel neither, sir; she was a virgin.
</p>

<p class="drama">
KING.<br>
It is so varied too, for it was proclaimed “virgin”.
</p>

<p class="drama">
COSTARD.<br>
If it were, I deny her virginity. I was taken with a maid.
</p>

<p class="drama">
KING.<br>
This maid will not serve your turn, sir.
</p>

<p class="drama">
COSTARD.<br>
This maid will serve my turn, sir.
</p>

<p class="drama">
KING.<br>
Sir, I will pronounce your sentence: you shall fast a week with bran and water.
</p>

<p class="drama">
COSTARD.<br>
I had rather pray a month with mutton and porridge.
</p>

<p class="drama">
KING.<br>
And Don Armado shall be your keeper.<br>
My Lord Berowne, see him delivered o’er;<br>
And go we, lords, to put in practice that<br>
Which each to other hath so strongly sworn.
</p>

<p class="right">
[<i>Exeunt <span class="charname">King, Longaville</span> and
<span class="charname">Dumaine</span>.</i>]
</p>

<p class="drama">
BEROWNE.<br>
I’ll lay my head to any good man’s hat<br>
These oaths and laws will prove an idle scorn.<br>
Sirrah, come on.
</p>

<p class="drama">
COSTARD.<br>
I suffer for the truth, sir; for true it is I was taken with Jaquenetta, and
Jaquenetta is a true girl. And therefore welcome the sour cup of prosperity!
Affliction may one day smile again, and till then, sit thee down, sorrow.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneI_19.2"></a><b>SCENE II. The park</b></h3>

<p class="scenedesc">
Enter <span class="charname">Armado</span> and
<span class="charname">Moth</span>, his Page.
</p>

<p class="drama">
ARMADO.<br>
Boy, what sign is it when a man of great spirit grows melancholy?
</p>

<p class="drama">
MOTH.<br>
A great sign, sir, that he will look sad.
</p>

<p class="drama">
ARMADO.<br>
Why, sadness is one and the selfsame thing, dear imp.
</p>

<p class="drama">
MOTH.<br>
No, no, O Lord, sir, no.
</p>

<p class="drama">
ARMADO.<br>
How canst thou part sadness and melancholy, my tender juvenal?
</p>

<p class="drama">
MOTH.<br>
By a familiar demonstration of the working, my tough signior.
</p>

<p class="drama">
ARMADO.<br>
Why tough signior? Why tough signior?
</p>

<p class="drama">
MOTH.<br>
Why tender juvenal? Why tender juvenal?
</p>

<p class="drama">
ARMADO.<br>
I spoke it, tender juvenal, as a congruent epitheton appertaining to thy young
days, which we may nominate tender.
</p>

<p class="drama">
MOTH.<br>
And I, tough signior, as an appertinent title to your old time, which we may
name tough.
</p>

<p class="drama">
ARMADO.<br>
Pretty and apt.
</p>

<p class="drama">
MOTH.<br>
How mean you, sir? I pretty and my saying apt, or I apt, and my saying pretty?
</p>

<p class="drama">
ARMADO.<br>
Thou pretty, because little.
</p>

<p class="drama">
MOTH.<br>
Little pretty, because little. Wherefore apt?
</p>

<p class="drama">
ARMADO.<br>
And therefore apt, because quick.
</p>

<p class="drama">
MOTH.<br>
Speak you this in my praise, master?
</p>

<p class="drama">
ARMADO.<br>
In thy condign praise.
</p>

<p class="drama">
MOTH.<br>
I will praise an eel with the same praise.
</p>

<p class="drama">
ARMADO.<br>
What, that an eel is ingenious?
</p>

<p class="drama">
MOTH.<br>
That an eel is quick.
</p>

<p class="drama">
ARMADO.<br>
I do say thou art quick in answers. Thou heat’st my blood.
</p>

<p class="drama">
MOTH.<br>
I am answered, sir.
</p>

<p class="drama">
ARMADO.<br>
I love not to be crossed.
</p>

<p class="drama">
MOTH.<br>
[<i>Aside</i>.] He speaks the mere contrary; crosses love not him.
</p>

<p class="drama">
ARMADO.<br>
I have promised to study three years with the Duke.
</p>

<p class="drama">
MOTH.<br>
You may do it in an hour, sir.
</p>

<p class="drama">
ARMADO.<br>
Impossible.
</p>

<p class="drama">
MOTH.<br>
How many is one thrice told?
</p>

<p class="drama">
ARMADO.<br>
I am ill at reckoning. It fitteth the spirit of a tapster.
</p>

<p class="drama">
MOTH.<br>
You are a gentleman and a gamester, sir.
</p>

<p class="drama">
ARMADO.<br>
I confess both. They are both the varnish of a complete man.
</p>

<p class="drama">
MOTH.<br>
Then I am sure you know how much the gross sum of deuce-ace amounts to.
</p>

<p class="drama">
ARMADO.<br>
It doth amount to one more than two.
</p>

<p class="drama">
MOTH.<br>
Which the base vulgar do call three.
</p>

<p class="drama">
ARMADO.<br>
True.
</p>

<p class="drama">
MOTH.<br>
Why, sir, is this such a piece of study? Now here’s three studied ere ye’ll
thrice wink. And how easy it is to put “years” to the word “three”, and study
three years in two words, the dancing horse will tell you.
</p>

<p class="drama">
ARMADO.<br>
A most fine figure!
</p>

<p class="drama">
MOTH.<br>
[<i>Aside</i>.] To prove you a cipher.
</p>

<p class="drama">
ARMADO.<br>
I will hereupon confess I am in love; and as it is base for a soldier to love,
so am I in love with a base wench. If drawing my sword against the humour of
affection would deliver me from the reprobate thought of it, I would take
desire prisoner, and ransom him to any French courtier for a new-devised
curtsy. I think scorn to sigh; methinks I should outswear Cupid. Comfort me,
boy. What great men have been in love?
</p>

<p class="drama">
MOTH.<br>
Hercules, master.
</p>

<p class="drama">
ARMADO.<br>
Most sweet Hercules! More authority, dear boy, name more; and, sweet my child,
let them be men of good repute and carriage.
</p>

<p class="drama">
MOTH.<br>
Samson, master. He was a man of good carriage, great carriage, for he carried
the town gates on his back like a porter, and he was in love.
</p>

<p class="drama">
ARMADO.<br>
O well-knit Samson, strong-jointed Samson! I do excel thee in my rapier as much
as thou didst me in carrying gates. I am in love too. Who was Samson’s love, my
dear Moth?
</p>

<p class="drama">
MOTH.<br>
A woman, master.
</p>

<p class="drama">
ARMADO.<br>
Of what complexion?
</p>

<p class="drama">
MOTH.<br>
Of all the four, or the three, or the two, or one of the four.
</p>

<p class="drama">
ARMADO.<br>
Tell me precisely of what complexion.
</p>

<p class="drama">
MOTH.<br>
Of the sea-water green, sir.
</p>

<p class="drama">
ARMADO.<br>
Is that one of the four complexions?
</p>

<p class="drama">
MOTH.<br>
As I have read, sir; and the best of them too.
</p>

<p class="drama">
ARMADO.<br>
Green indeed is the colour of lovers. But to have a love of that colour,
methinks Samson had small reason for it. He surely affected her for her wit.
</p>

<p class="drama">
MOTH.<br>
It was so, sir, for she had a green wit.
</p>

<p class="drama">
ARMADO.<br>
My love is most immaculate white and red.
</p>

<p class="drama">
MOTH.<br>
Most maculate thoughts, master, are masked under such colours.
</p>

<p class="drama">
ARMADO.<br>
Define, define, well-educated infant.
</p>

<p class="drama">
MOTH.<br>
My father’s wit and my mother’s tongue assist me!
</p>

<p class="drama">
ARMADO.<br>
Sweet invocation of a child, most pretty, and pathetical!
</p>

<p class="drama">
MOTH.<br>
  If she be made of white and red,<br>
     Her faults will ne’er be known;<br>
  For blushing cheeks by faults are bred,<br>
     And fears by pale white shown.<br>
  Then if she fear, or be to blame,<br>
     By this you shall not know,<br>
  For still her cheeks possess the same<br>
     Which native she doth owe.<br>
A dangerous rhyme, master, against the reason of white and red.
</p>

<p class="drama">
ARMADO.<br>
Is there not a ballad, boy, of the King and the Beggar?
</p>

<p class="drama">
MOTH.<br>
The world was very guilty of such a ballad some three ages since, but I think
now ’tis not to be found; or if it were, it would neither serve for the writing
nor the tune.
</p>

<p class="drama">
ARMADO.<br>
I will have that subject newly writ o’er, that I may example my digression by
some mighty precedent. Boy, I do love that country girl that I took in the park
with the rational hind Costard. She deserves well.
</p>

<p class="drama">
MOTH.<br>
[<i>Aside</i>.] To be whipped: and yet a better love than my master.
</p>

<p class="drama">
ARMADO.<br>
Sing, boy. My spirit grows heavy in love.
</p>

<p class="drama">
MOTH.<br>
And that’s great marvel, loving a light wench.
</p>

<p class="drama">
ARMADO.<br>
I say, sing.
</p>

<p class="drama">
MOTH.<br>
Forbear till this company be past.
</p>

<p class="scenedesc">
Enter <span class="charname">Costard</span> the Clown,
<span class="charname">Dull</span> the Constable and
<span class="charname">Jaquenetta</span> a Wench.
</p>

<p class="drama">
DULL.<br>
Sir, the Duke’s pleasure is that you keep Costard safe; and you must suffer
him to take no delight, nor no penance, but he must fast three days a week. For
this damsel, I must keep her at the park. She is allowed for the dey-woman.
Fare you well.
</p>

<p class="drama">
ARMADO.<br>
I do betray myself with blushing.—Maid.
</p>

<p class="drama">
JAQUENETTA.<br>
Man.
</p>

<p class="drama">
ARMADO.<br>
I will visit thee at the lodge.
</p>

<p class="drama">
JAQUENETTA.<br>
That’s hereby.
</p>

<p class="drama">
ARMADO.<br>
I know where it is situate.
</p>

<p class="drama">
JAQUENETTA.<br>
Lord, how wise you are!
</p>

<p class="drama">
ARMADO.<br>
I will tell thee wonders.
</p>

<p class="drama">
JAQUENETTA.<br>
With that face?
</p>

<p class="drama">
ARMADO.<br>
I love thee.
</p>

<p class="drama">
JAQUENETTA.<br>
So I heard you say.
</p>

<p class="drama">
ARMADO.<br>
And so, farewell.
</p>

<p class="drama">
JAQUENETTA.<br>
Fair weather after you!
</p>

<p class="drama">
DULL.<br>
Come, Jaquenetta, away.
</p>

<p class="right">[<i>Exeunt <span class="charname">Dull</span> and
<span class="charname">Jaquenetta</span>.</i>]</p>

<p class="drama">
ARMADO.<br>
Villain, thou shalt fast for thy offences ere thou be pardoned.
</p>

<p class="drama">
COSTARD.<br>
Well, sir, I hope when I do it I shall do it on a full stomach.
</p>

<p class="drama">
ARMADO.<br>
Thou shalt be heavily punished.
</p>

<p class="drama">
COSTARD.<br>
I am more bound to you than your fellows, for they are but lightly rewarded.
</p>

<p class="drama">
ARMADO.<br>
Take away this villain. Shut him up.
</p>

<p class="drama">
MOTH.<br>
Come, you transgressing slave, away!
</p>

<p class="drama">
COSTARD.<br>
Let me not be pent up, sir. I will fast being loose.
</p>

<p class="drama">
MOTH.<br>
No, sir, that were fast and loose. Thou shalt to prison.
</p>

<p class="drama">
COSTARD.<br>
Well, if ever I do see the merry days of desolation that I have seen, some
shall see.
</p>

<p class="drama">
MOTH.<br>
What shall some see?
</p>

<p class="drama">
COSTARD.<br>
Nay, nothing, Master Moth, but what they look upon. It is not for prisoners to
be too silent in their words, and therefore I will say nothing. I thank God I
have as little patience as another man, and therefore I can be quiet.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Moth</span> and
<span class="charname">Costard</span>.</i>]
</p>

<p class="drama">
ARMADO.<br>
I do affect the very ground, which is base, where her shoe, which is baser,
guided by her foot, which is basest, doth tread. I shall be forsworn, which is
a great argument of falsehood, if I love. And how can that be true love which
is falsely attempted? Love is a familiar; Love is a devil. There is no evil
angel but Love. Yet was Samson so tempted, and he had an excellent strength;
yet was Solomon so seduced, and he had a very good wit. Cupid’s butt-shaft is
too hard for Hercules’ club, and therefore too much odds for a Spaniard’s
rapier. The first and second cause will not serve my turn; the <i>passado</i>
he respects not, the <i>duello</i> he regards not. His disgrace is to be called
boy, but his glory is to subdue men. Adieu, valour; rust, rapier; be still,
drum, for your manager is in love. Yea, he loveth. Assist me, some extemporal
god of rhyme, for I am sure I shall turn sonnet. Devise, wit; write, pen; for I
am for whole volumes in folio.
</p>

<p class="right">[<i>Exit.</i>]</p>

