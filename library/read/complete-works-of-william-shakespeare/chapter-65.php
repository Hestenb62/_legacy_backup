<h2> <a id="sceneIII_11.0"></a><b>ACT III</b></h2>

<p class="scenedesc"> Flourish. Enter <span class="charname">Chorus</span>.</p>

<p>CHORUS.<br>
Thus with imagin’d wing our swift scene flies,<br>
In motion of no less celerity<br>
Than that of thought. Suppose that you have seen<br>
The well-appointed king at Hampton pier<br>
Embark his royalty, and his brave fleet<br>
With silken streamers the young Phoebus fanning.<br>
Play with your fancies; and in them behold<br>
Upon the hempen tackle ship-boys climbing;<br>
Hear the shrill whistle which doth order give<br>
To sounds confus’d; behold the threaden sails,<br>
Borne with the invisible and creeping wind,<br>
Draw the huge bottoms through the furrow’d sea,<br>
Breasting the lofty surge. O, do but think<br>
You stand upon the rivage and behold<br>
A city on the inconstant billows dancing;<br>
For so appears this fleet majestical,<br>
Holding due course to Harfleur. Follow, follow!<br>
Grapple your minds to sternage of this navy,<br>
And leave your England, as dead midnight still,<br>
Guarded with grandsires, babies, and old women,<br>
Either past or not arriv’d to pith and puissance.<br>
For who is he, whose chin is but enrich’d<br>
With one appearing hair, that will not follow<br>
These cull’d and choice-drawn cavaliers to France?<br>
Work, work your thoughts, and therein see a siege;<br>
Behold the ordnance on their carriages,<br>
With fatal mouths gaping on girded Harfleur.<br>
Suppose the ambassador from the French comes back,<br>
Tells Harry that the King doth offer him<br>
Katharine his daughter, and with her, to dowry,<br>
Some petty and unprofitable dukedoms.<br>
The offer likes not; and the nimble gunner<br>
With linstock now the devilish cannon touches,
</p>

<p class="right"> [<i>Alarum, and chambers go off.</i>]</p>

<p>And down goes all before them. Still be kind,<br>
And eke out our performance with your mind.
</p>

<p class="right"> [<i>Exit.</i>]</p>

<h3> <a id="sceneIII_11.1"></a><b>SCENE I. France. Before Harfleur.</b></h3>

<p class="scenedesc"> Alarum. Enter <span class="charname">King Henry, Exeter,
Bedford, Gloucester</span> and Soldiers, with scaling-ladders.</p>

<p>KING HENRY.<br>
Once more unto the breach, dear friends, once more,<br>
Or close the wall up with our English dead.<br>
In peace there’s nothing so becomes a man<br>
As modest stillness and humility;<br>
But when the blast of war blows in our ears,<br>
Then imitate the action of the tiger;<br>
Stiffen the sinews, summon up the blood,<br>
Disguise fair nature with hard-favour’d rage;<br>
Then lend the eye a terrible aspect;<br>
Let it pry through the portage of the head<br>
Like the brass cannon; let the brow o’erwhelm it<br>
As fearfully as does a galled rock<br>
O’erhang and jutty his confounded base,<br>
Swill’d with the wild and wasteful ocean.<br>
Now set the teeth and stretch the nostril wide,<br>
Hold hard the breath, and bend up every spirit<br>
To his full height. On, on, you noblest English,<br>
Whose blood is fet from fathers of war-proof!<br>
Fathers that, like so many Alexanders,<br>
Have in these parts from morn till even fought,<br>
And sheath’d their swords for lack of argument.<br>
Dishonour not your mothers; now attest<br>
That those whom you call’d fathers did beget you.<br>
Be copy now to men of grosser blood,<br>
And teach them how to war. And you, good yeomen,<br>
Whose limbs were made in England, show us here<br>
The mettle of your pasture; let us swear<br>
That you are worth your breeding, which I doubt not;<br>
For there is none of you so mean and base,<br>
That hath not noble lustre in your eyes.<br>
I see you stand like greyhounds in the slips,<br>
Straining upon the start. The game’s afoot!<br>
Follow your spirit, and upon this charge<br>
Cry, “God for Harry! England and Saint George!”
</p>

<p class="right"> [<i>Exeunt. Alarum, and chambers go off.</i>]</p>

<h3> <a id="sceneIII_11.2"></a><b>SCENE II. The same.</b></h3>

<p class="scenedesc"> Enter <span class="charname">Nym, Bardolph, Pistol</span>
and <span class="charname">Boy</span>.</p>

<p>BARDOLPH.<br>
On, on, on, on, on! To the breach, to the breach!
</p>

<p>NYM.<br>
Pray thee, corporal, stay. The knocks are too hot; and, for mine own part, I
have not a case of lives. The humour of it is too hot; that is the very
plain-song of it.
</p>

<p>PISTOL.<br>
The plain-song is most just, for humours do abound.<br>
Knocks go and come; God’s vassals drop and die;<br>
    And sword and shield,<br>
    In bloody field,<br>
    Doth win immortal fame.
</p>

<p>BOY.<br>
Would I were in an alehouse in London! I would give all my fame for a pot of
ale and safety.
</p>

<p>PISTOL.<br>
And I.<br>
    If wishes would prevail with me,<br>
    My purpose should not fail with me,<br>
    But thither would I hie.
</p>

<p>BOY.<br>
    As duly,<br>
    But not as truly,<br>
    As bird doth sing on bough.
</p>

<p class="scenedesc"> Enter <span class="charname">Fluellen</span>.</p>

<p>FLUELLEN.<br>
Up to the breach, you dogs! Avaunt, you cullions!
</p>

<p class="right"> [<i>Driving them forward.</i>]</p>

<p>PISTOL.<br>
Be merciful, great Duke, to men of mould.<br>
Abate thy rage, abate thy manly rage,<br>
Abate thy rage, great Duke!<br>
Good bawcock, bate thy rage; use lenity, sweet chuck!
</p>

<p>NYM.<br>
These be good humours! Your honour wins bad humours.
</p>

<p class="right"> [<i>Exeunt all but <span class="charname">Boy</span>.</i>]</p>

<p>BOY.<br>
As young as I am, I have observ’d these three swashers. I am boy to them
all three; but all they three, though they would serve me, could not be man to
me; for indeed three such antics do not amount to a man. For Bardolph, he is
white-liver’d and red-fac’d; by the means whereof ’a faces it
out, but fights not. For Pistol, he hath a killing tongue and a quiet sword; by
the means whereof ’a breaks words, and keeps whole weapons. For Nym, he
hath heard that men of few words are the best men; and therefore he scorns to
say his prayers, lest ’a should be thought a coward. But his few bad
words are match’d with as few good deeds; for ’a never broke any
man’s head but his own, and that was against a post when he was drunk.
They will steal anything, and call it purchase. Bardolph stole a lute-case,
bore it twelve leagues, and sold it for three half-pence. Nym and Bardolph are
sworn brothers in filching, and in Calais they stole a fire-shovel. I knew by
that piece of service the men would carry coals. They would have me as familiar
with men’s pockets as their gloves or their handkerchers; which makes
much against my manhood, if I should take from another’s pocket to put
into mine; for it is plain pocketing up of wrongs. I must leave them, and seek
some better service. Their villainy goes against my weak stomach, and therefore
I must cast it up.
</p>

<p class="right"> [<i>Exit.</i>]</p>

<p class="scenedesc"> Enter <span class="charname">Gower</span> and <span class="charname">Fluellen</span>.</p>

<p>GOWER.<br>
Captain Fluellen, you must come presently to the mines.<br>
The Duke of Gloucester would speak with you.
</p>

<p>FLUELLEN.<br>
To the mines! Tell you the Duke, it is not so good to come to the mines; for,
look you, the mines is not according to the disciplines of the war. The
concavities of it is not sufficient; for, look you, the athversary, you may
discuss unto the Duke, look you, is digt himself four yard under the
countermines. By Cheshu, I think ’a will plow up all, if there is not
better directions.
</p>

<p>GOWER.<br>
The Duke of Gloucester, to whom the order of the siege is given, is altogether
directed by an Irishman, a very valiant gentleman, i’ faith.
</p>

<p>FLUELLEN.<br>
It is Captain Macmorris, is it not?
</p>

<p>GOWER.<br>
I think it be.
</p>

<p>FLUELLEN.<br>
By Cheshu, he is an ass, as in the world. I will verify as much in his beard.
He has no more directions in the true disciplines of the wars, look you, of the
Roman disciplines, than is a puppy-dog.
</p>

<p class="scenedesc"> Enter <span class="charname">Macmorris</span> and <span class="charname">Captain Jamy</span>.</p>

<p>GOWER.<br>
Here ’a comes; and the Scots captain, Captain Jamy, with him.
</p>

<p>FLUELLEN.<br>
Captain Jamy is a marvellous falorous gentleman, that is certain; and of great
expedition and knowledge in the anchient wars, upon my particular knowledge of
his directions. By Cheshu, he will maintain his argument as well as any
military man in the world, in the disciplines of the pristine wars of the
Romans.
</p>

<p>JAMY.<br>
I say gud-day, Captain Fluellen.
</p>

<p>FLUELLEN.<br>
God-den to your worship, good Captain James.
</p>

<p>GOWER.<br>
How now, Captain Macmorris! have you quit the mines?<br>
Have the pioneers given o’er?
</p>

<p>MACMORRIS.<br>
By Chrish, la! ’tish ill done! The work ish give over, the trompet sound
the retreat. By my hand I swear, and my father’s soul, the work ish ill
done; it ish give over. I would have blowed up the town, so Chrish save me, la!
in an hour. O, ’tish ill done, ’tish ill done; by my hand,
’tish ill done!
</p>

<p>FLUELLEN.<br>
Captain Macmorris, I beseech you now, will you voutsafe me, look you, a few
disputations with you, as partly touching or concerning the disciplines of the
war, the Roman wars, in the way of argument, look you, and friendly
communication; partly to satisfy my opinion, and partly for the satisfaction,
look you, of my mind, as touching the direction of the military discipline;
that is the point.
</p>

<p>JAMY.<br>
It sall be vary gud, gud feith, gud captains bath: and I sall quit you with gud
leve, as I may pick occasion; that sall I, marry.
</p>

<p>MACMORRIS.<br>
It is no time to discourse, so Chrish save me. The day is hot, and the weather,
and the wars, and the King, and the Dukes. It is no time to discourse. The town
is beseech’d, and the trumpet call us to the breach, and we talk, and, be
Chrish, do nothing. ’Tis shame for us all. So God sa’ me,
’tis shame to stand still; it is shame, by my hand; and there is throats
to be cut, and works to be done; and there ish nothing done, so Chrish
sa’ me, la!
</p>

<p>JAMY.<br>
By the mess, ere theise eyes of mine take themselves to slomber, I’ll de
gud service, or I’ll lig i’ the grund for it; ay, or go to death;
and I’ll pay’t as valorously as I may, that sall I suerly do, that
is the breff and the long. Marry, I wad full fain heard some question
’tween you tway.
</p>

<p>FLUELLEN.<br>
Captain Macmorris, I think, look you, under your correction, there is not many
of your nation—
</p>

<p>MACMORRIS.<br>
Of my nation! What ish my nation? Ish a villain, and a bastard, and a knave,
and a rascal? What ish my nation? Who talks of my nation?
</p>

<p>FLUELLEN.<br>
Look you, if you take the matter otherwise than is meant, Captain Macmorris,
peradventure I shall think you do not use me with that affability as in
discretion you ought to use me, look you, being as good a man as yourself, both
in the disciplines of war, and in the derivation of my birth, and in other
particularities.
</p>

<p>MACMORRIS.<br>
I do not know you so good a man as myself. So Chrish save me,<br>
I will cut off your head.
</p>

<p>GOWER.<br>
Gentlemen both, you will mistake each other.
</p>

<p>JAMY.<br>
Ah! that’s a foul fault.
</p>

<p class="right"> [<i>A parley sounded.</i>]</p>

<p>GOWER.<br>
The town sounds a parley.
</p>

<p>FLUELLEN.<br>
Captain Macmorris, when there is more better opportunity to be required, look
you, I will be so bold as to tell you I know the disciplines of war; and there
is an end.
</p>

<p class="right"> [<i>Exeunt.</i>]</p>

<h3> <a id="sceneIII_11.3"></a><b>SCENE III. Before the gates.</b></h3>

<p class="scenedesc"> The <span class="charname">Governor</span> and some
citizens on the walls; the English forces below. Enter <span class="charname">King Henry</span> and his train.</p>

<p>KING HENRY.<br>
How yet resolves the governor of the town?<br>
This is the latest parle we will admit;<br>
Therefore to our best mercy give yourselves,<br>
Or like to men proud of destruction<br>
Defy us to our worst; for, as I am a soldier,<br>
A name that in my thoughts becomes me best,<br>
If I begin the battery once again,<br>
I will not leave the half-achieved Harfleur<br>
Till in her ashes she lie buried.<br>
The gates of mercy shall be all shut up,<br>
And the flesh’d soldier, rough and hard of heart,<br>
In liberty of bloody hand shall range<br>
With conscience wide as hell, mowing like grass<br>
Your fresh fair virgins and your flow’ring infants.<br>
What is it then to me, if impious War,<br>
Array’d in flames like to the prince of fiends,<br>
Do with his smirch’d complexion all fell feats<br>
Enlink’d to waste and desolation?<br>
What is’t to me, when you yourselves are cause,<br>
If your pure maidens fall into the hand<br>
Of hot and forcing violation?<br>
What rein can hold licentious wickedness<br>
When down the hill he holds his fierce career?<br>
We may as bootless spend our vain command<br>
Upon the enraged soldiers in their spoil<br>
As send precepts to the leviathan<br>
To come ashore. Therefore, you men of Harfleur,<br>
Take pity of your town and of your people,<br>
Whiles yet my soldiers are in my command,<br>
Whiles yet the cool and temperate wind of grace<br>
O’erblows the filthy and contagious clouds<br>
Of heady murder, spoil, and villainy.<br>
If not, why, in a moment look to see<br>
The blind and bloody soldier with foul hand<br>
Defile the locks of your shrill-shrieking daughters;<br>
Your fathers taken by the silver beards,<br>
And their most reverend heads dash’d to the walls;<br>
Your naked infants spitted upon pikes,<br>
Whiles the mad mothers with their howls confus’d<br>
Do break the clouds, as did the wives of Jewry<br>
At Herod’s bloody-hunting slaughtermen.<br>
What say you? Will you yield, and this avoid,<br>
Or, guilty in defence, be thus destroy’d?
</p>

<p>GOVERNOR.<br>
Our expectation hath this day an end.<br>
The Dauphin, whom of succours we entreated,<br>
Returns us that his powers are yet not ready<br>
To raise so great a siege. Therefore, great King,<br>
We yield our town and lives to thy soft mercy.<br>
Enter our gates; dispose of us and ours;<br>
For we no longer are defensible.
</p>

<p>KING HENRY.<br>
Open your gates. Come, uncle Exeter,<br>
Go you and enter Harfleur; there remain,<br>
And fortify it strongly ’gainst the French.<br>
Use mercy to them all. For us, dear uncle,<br>
The winter coming on, and sickness growing<br>
Upon our soldiers, we will retire to Calais.<br>
Tonight in Harfleur will we be your guest;<br>
Tomorrow for the march are we addrest.
</p>

<p class="scenedesc"> Flourish. The <span class="charname">King</span> and his
train enter the town.</p>

<h3> <a id="sceneIII_11.4"></a><b>SCENE IV. The French King’s palace.</b></h3>

<p class="scenedesc"> Enter <span class="charname">Katharine</span> and <span class="charname">Alice</span>, an old Gentlewoman.</p>

<p>KATHARINE.<br>
<i>Alice, tu as été en Angleterre, et tu parles bien le langage.</i>
</p>

<p>ALICE.<br>
<i>Un peu, madame.</i>
</p>

<p>KATHARINE.<br>
<i>Je te prie, m’enseignez; il faut que j’apprenne à parler.<br>
Comment appelez-vous la main en anglais?</i>
</p>

<p>ALICE.<br>
<i>La main? Elle est appelée</i> de hand.
</p>

<p>KATHARINE.<br>
De hand. <i>Et les doigts?</i>
</p>

<p>ALICE.<br>
<i>Les doigts? Ma foi, j’oublie les doigts; mais je me souviendrai. Les
doigts? Je pense qu’ils sont appelés</i> de fingres; <i>oui</i>, de
fingres.
</p>

<p>KATHARINE.<br>
<i>La main</i>, de hand; <i>les doigts</i>, de fingres. <i>Je pense que je suis
le bon écolier; j’ai gagné deux mots d’anglais vitement. Comment
appelez-vous les ongles?</i>
</p>

<p>ALICE.<br>
<i>Les ongles? Nous les appelons</i> de nails.
</p>

<p>KATHARINE.<br>
De nails. <i>Écoutez; dites-moi, si je parle bien:</i> de hand, de fingres,
<i>et</i> de nails.
</p>

<p>ALICE.<br>
<i>C’est bien dit, madame; il est fort bon anglais.</i>
</p>

<p>KATHARINE.<br>
<i>Dites-moi l’anglais pour le bras.</i>
</p>

<p>ALICE.<br>
De arm, <i>madame.</i>
</p>

<p>KATHARINE.<br>
<i>Et le coude?</i>
</p>

<p>ALICE.<br>
D’elbow.
</p>

<p>KATHARINE.<br>
D’elbow. <i>Je m’en fais la répétition de tous les mots que vous
m’avez appris dès à présent.</i>
</p>

<p>ALICE.<br>
<i>Il est trop difficile, madame, comme je pense.</i>
</p>

<p>KATHARINE.<br>
<i>Excusez-moi, Alice. Écoutez:</i> d’hand, de fingres, de nails,
d’arm, de bilbow.
</p>

<p>ALICE.<br>
D’elbow, <i>madame.</i>
</p>

<p>KATHARINE.<br>
<i>O Seigneur Dieu, je m’en oublie!</i> D’elbow.<br>
<i>Comment appelez-vous le col?</i>
</p>

<p>ALICE.<br>
De nick, <i>madame.</i>
</p>

<p>KATHARINE.<br>
De nick. <i>Et le menton?</i>
</p>

<p>ALICE.<br>
De chin.
</p>

<p>KATHARINE.<br>
De sin. <i>Le col</i>, de nick; <i>le menton</i>, de sin.
</p>

<p>ALICE.<br>
<i>Oui. Sauf votre honneur, en vérité, vous prononcez les mots aussi droit que
les natifs d’Angleterre.</i>
</p>

<p>KATHARINE.<br>
<i>Je ne doute point d’apprendre, par la grâce de Dieu, et en peu de
temps.</i>
</p>

<p>ALICE.<br>
<i>N’avez-vous pas déjà oublié ce que je vous ai enseigné?</i>
</p>

<p>KATHARINE.<br>
<i>Non, je réciterai à vous promptement:</i> d’hand, de fingres, de
mails,—
</p>

<p>ALICE.<br>
De nails, <i>madame.</i>
</p>

<p>KATHARINE.<br>
De nails, de arm, de ilbow.
</p>

<p>ALICE.<br>
<i>Sauf votre honneur</i>, de elbow.
</p>

<p>KATHARINE.<br>
<i>Ainsi dis-je</i>, d’elbow, de nick, <i>et</i> de sin. <i>Comment
appelez-vous le pied et la robe?</i>
</p>

<p>ALICE.<br>
De foot, <i>madame; et</i> de coun.
</p>

<p>KATHARINE.<br>
De foot <i>et</i> de coun! <i>O Seigneur Dieu! ils sont les mots de son
mauvais, corruptible, gros, et impudique, et non pour les dames d’honneur
d’user. Je ne voudrais prononcer ces mots devant les seigneurs de France
pour tout le monde. Foh!</i> le foot <i>et</i> le coun! <i>Néanmoins, je
réciterai une autre fois ma leçon ensemble:</i> d’hand, de fingres, de
nails, d’arm, d’elbow, de nick, de sin, de foot, de coun.
</p>

<p>ALICE.<br>
<i>Excellent, madame!</i>
</p>

<p>KATHARINE.<br>
<i>C’est assez pour une fois. Allons-nous à dîner.</i>
</p>

<p class="right"> [<i>Exeunt.</i>]</p>

<h3> <a id="sceneIII_11.5"></a><b>SCENE V. The same.</b></h3>

<p class="scenedesc"> Enter the <span class="charname">King of France, the
Dauphin, the Duke of Bourbon, the Constable of France</span> and others.</p>

<p>FRENCH KING.<br>
’Tis certain he hath pass’d the river Somme.
</p>

<p>CONSTABLE.<br>
And if he be not fought withal, my lord,<br>
Let us not live in France; let us quit all<br>
And give our vineyards to a barbarous people.
</p>

<p>DAUPHIN.<br>
<i>O Dieu vivant</i>! shall a few sprays of us,<br>
The emptying of our fathers’ luxury,<br>
Our scions put in wild and savage stock,<br>
Spirt up so suddenly into the clouds,<br>
And overlook their grafters?
</p>

<p>BOURBON.<br>
Normans, but bastard Normans, Norman bastards!<br>
<i>Mort de ma vie</i>, if they march along<br>
Unfought withal, but I will sell my dukedom,<br>
To buy a slobbery and a dirty farm<br>
In that nook-shotten isle of Albion.
</p>

<p>CONSTABLE.<br>
<i>Dieu de batailles</i>, where have they this mettle?<br>
Is not their climate foggy, raw, and dull,<br>
On whom, as in despite, the sun looks pale,<br>
Killing their fruit with frowns? Can sodden water,<br>
A drench for sur-rein’d jades, their barley-broth,<br>
Decoct their cold blood to such valiant heat?<br>
And shall our quick blood, spirited with wine,<br>
Seem frosty? O, for honour of our land,<br>
Let us not hang like roping icicles<br>
Upon our houses’ thatch, whiles a more frosty people<br>
Sweat drops of gallant youth in our rich fields!<br>
Poor we may call them in their native lords.
</p>

<p>DAUPHIN.<br>
By faith and honour,<br>
Our madams mock at us, and plainly say<br>
Our mettle is bred out, and they will give<br>
Their bodies to the lust of English youth<br>
To new-store France with bastard warriors.
</p>

<p>BOURBON.<br>
They bid us to the English dancing-schools,<br>
And teach lavoltas high, and swift corantos;<br>
Saying our grace is only in our heels,<br>
And that we are most lofty runaways.
</p>

<p>FRENCH KING.<br>
Where is Montjoy the herald? Speed him hence.<br>
Let him greet England with our sharp defiance.<br>
Up, princes! and, with spirit of honour edged<br>
More sharper than your swords, hie to the field!<br>
Charles Delabreth, High Constable of France;<br>
You Dukes of Orleans, Bourbon, and of Berry,<br>
Alençon, Brabant, Bar, and Burgundy;<br>
Jacques Chatillon, Rambures, Vaudemont,<br>
Beaumont, Grandpré, Roussi, and Fauconbridge,<br>
Foix, Lestrale, Boucicault, and Charolois;<br>
High dukes, great princes, barons, lords, and knights,<br>
For your great seats now quit you of great shames.<br>
Bar Harry England, that sweeps through our land<br>
With pennons painted in the blood of Harfleur.<br>
Rush on his host, as doth the melted snow<br>
Upon the valleys, whose low vassal seat<br>
The Alps doth spit and void his rheum upon.<br>
Go down upon him, you have power enough,<br>
And in a captive chariot into Rouen<br>
Bring him our prisoner.
</p>

<p>CONSTABLE.<br>
This becomes the great.<br>
Sorry am I his numbers are so few,<br>
His soldiers sick and famish’d in their march;<br>
For I am sure, when he shall see our army,<br>
He’ll drop his heart into the sink of fear<br>
And for achievement offer us his ransom.
</p>

<p>FRENCH KING.<br>
Therefore, Lord Constable, haste on Montjoy,<br>
And let him say to England that we send<br>
To know what willing ransom he will give.<br>
Prince Dauphin, you shall stay with us in Rouen.
</p>

<p>DAUPHIN.<br>
Not so, I do beseech your Majesty.
</p>

<p>FRENCH KING.<br>
Be patient, for you shall remain with us.<br>
Now forth, Lord Constable and princes all,<br>
And quickly bring us word of England’s fall.
</p>

<p class="right"> [<i>Exeunt.</i>]</p>

<h3> <a id="sceneIII_11.6"></a><b>SCENE VI. The English camp in Picardy.</b></h3>

<p class="scenedesc"> Enter <span class="charname">Gower</span> and <span class="charname">Fluellen</span>, meeting.</p>

<p>GOWER.<br>
How now, Captain Fluellen! come you from the bridge?
</p>

<p>FLUELLEN.<br>
I assure you, there is very excellent services committed at the bridge.
</p>

<p>GOWER.<br>
Is the Duke of Exeter safe?
</p>

<p>FLUELLEN.<br>
The Duke of Exeter is as magnanimous as Agamemnon; and a man that I love and
honour with my soul, and my heart, and my duty, and my life, and my living, and
my uttermost power. He is not—God be praised and blessed!—any hurt
in the world; but keeps the bridge most valiantly, with excellent discipline.
There is an anchient lieutenant there at the pridge, I think in my very
conscience he is as valiant a man as Mark Antony; and he is a man of no
estimation in the world, but I did see him do as gallant service.
</p>

<p>GOWER.<br>
What do you call him?
</p>

<p>FLUELLEN.<br>
He is call’d Anchient Pistol.
</p>

<p>GOWER.<br>
I know him not.
</p>

<p class="scenedesc"> Enter <span class="charname">Pistol</span>.</p>

<p>FLUELLEN.<br>
Here is the man.
</p>

<p>PISTOL.<br>
Captain, I thee beseech to do me favours.<br>
The Duke of Exeter doth love thee well.
</p>

<p>FLUELLEN.<br>
Ay, I praise God; and I have merited some love at his hands.
</p>

<p>PISTOL.<br>
Bardolph, a soldier, firm and sound of heart,<br>
And of buxom valour, hath by cruel fate<br>
And giddy Fortune’s furious fickle wheel,<br>
That goddess blind,<br>
That stands upon the rolling restless stone—
</p>

<p>FLUELLEN.<br>
By your patience, Anchient Pistol. Fortune is painted blind, with a muffler
afore his eyes, to signify to you that Fortune is blind; and she is painted
also with a wheel, to signify to you, which is the moral of it, that she is
turning, and inconstant, and mutability, and variation; and her foot, look you,
is fixed upon a spherical stone, which rolls, and rolls, and rolls. In good
truth, the poet makes a most excellent description of it. Fortune is an
excellent moral.
</p>

<p>PISTOL.<br>
Fortune is Bardolph’s foe, and frowns on him;<br>
For he hath stolen a pax, and hanged must ’a be,—<br>
A damned death!<br>
Let gallows gape for dog; let man go free,<br>
And let not hemp his windpipe suffocate.<br>
But Exeter hath given the doom of death<br>
For pax of little price.<br>
Therefore, go speak; the Duke will hear thy voice;<br>
And let not Bardolph’s vital thread be cut<br>
With edge of penny cord and vile reproach.<br>
Speak, captain, for his life, and I will thee requite.
</p>

<p>FLUELLEN.<br>
Anchient Pistol, I do partly understand your meaning.
</p>

<p>PISTOL.<br>
Why then, rejoice therefore.
</p>

<p>FLUELLEN.<br>
Certainly, anchient, it is not a thing to rejoice at; for if, look you, he were
my brother, I would desire the Duke to use his good pleasure, and put him to
execution; for discipline ought to be used.
</p>

<p>PISTOL.<br>
Die and be damn’d! and <i>fico</i> for thy friendship!
</p>

<p>FLUELLEN.<br>
It is well.
</p>

<p>PISTOL.<br>
The fig of Spain.
</p>

<p class="right"> [<i>Exit.</i>]</p>

<p>FLUELLEN.<br>
Very good.
</p>

<p>GOWER.<br>
Why, this is an arrant counterfeit rascal. I remember him now; a bawd, a
cutpurse.
</p>

<p>FLUELLEN.<br>
I’ll assure you, ’a uttered as prave words at the pridge as you
shall see in a summer’s day. But it is very well; what he has spoke to
me, that is well, I warrant you, when time is serve.
</p>

<p>GOWER.<br>
Why, ’t is a gull, a fool, a rogue, that now and then goes to the wars,
to grace himself at his return into London under the form of a soldier. And
such fellows are perfect in the great commanders’ names; and they will
learn you by rote where services were done; at such and such a sconce, at such
a breach, at such a convoy; who came off bravely, who was shot, who
disgrac’d, what terms the enemy stood on; and this they con perfectly in
the phrase of war, which they trick up with new-tuned oaths: and what a beard
of the general’s cut and a horrid suit of the camp will do among foaming
bottles and ale-wash’d wits, is wonderful to be thought on. But you must
learn to know such slanders of the age, or else you may be marvellously
mistook.
</p>

<p>FLUELLEN.<br>
I tell you what, Captain Gower; I do perceive he is not the man that he would
gladly make show to the world he is. If I find a hole in his coat, I will tell
him my mind. [<i>Drum heard.</i>] Hark you, the King is coming, and I must
speak with him from the pridge.
</p>

<p class="scenedesc"> Drum and colours. Enter <span class="charname">King
Henry, Gloucester</span> and his poor soldiers.</p>

<p>God bless your Majesty!</p>

<p>KING HENRY.<br>
How now, Fluellen! cam’st thou from the bridge?
</p>

<p>FLUELLEN.<br>
Ay, so please your Majesty. The Duke of Exeter has very gallantly
maintain’d the pridge. The French is gone off, look you; and there is
gallant and most prave passages. Marry, th’ athversary was have
possession of the pridge; but he is enforced to retire, and the Duke of Exeter
is master of the pridge. I can tell your Majesty, the Duke is a prave man.
</p>

<p>KING HENRY.<br>
What men have you lost, Fluellen?
</p>

<p>FLUELLEN.<br>
The perdition of the athversary hath been very great, reasonable great. Marry,
for my part, I think the Duke hath lost never a man, but one that is like to be
executed for robbing a church, one Bardolph, if your Majesty know the man. His
face is all bubukles, and whelks, and knobs, and flames o’ fire; and his
lips blows at his nose, and it is like a coal of fire, sometimes plue and
sometimes red; but his nose is executed, and his fire’s out.
</p>

<p>KING HENRY.<br>
We would have all such offenders so cut off; and we give express charge, that
in our marches through the country, there be nothing compell’d from the
villages, nothing taken but paid for, none of the French upbraided or abused in
disdainful language; for when lenity and cruelty play for a kingdom, the
gentler gamester is the soonest winner.
</p>

<p class="scenedesc"> Tucket. Enter <span class="charname">Montjoy</span>.</p>

<p>MONTJOY.<br>
You know me by my habit.
</p>

<p>KING HENRY.<br>
Well then I know thee. What shall I know of thee?
</p>

<p>MONTJOY.<br>
My master’s mind.
</p>

<p>KING HENRY.<br>
Unfold it.
</p>

<p>MONTJOY.<br>
Thus says my King: Say thou to Harry of England: Though we seem’d dead,
we did but sleep; advantage is a better soldier than rashness. Tell him we
could have rebuk’d him at Harfleur, but that we thought not good to
bruise an injury till it were full ripe. Now we speak upon our cue, and our
voice is imperial. England shall repent his folly, see his weakness, and admire
our sufferance. Bid him therefore consider of his ransom; which must proportion
the losses we have borne, the subjects we have lost, the disgrace we have
digested; which in weight to re-answer, his pettishness would bow under. For
our losses, his exchequer is too poor; for the effusion of our blood, the
muster of his kingdom too faint a number; and for our disgrace, his own person,
kneeling at our feet, but a weak and worthless satisfaction. To this add
defiance; and tell him, for conclusion, he hath betrayed his followers, whose
condemnation is pronounc’d. So far my King and master; so much my office.
</p>

<p>KING HENRY.<br>
What is thy name? I know thy quality.
</p>

<p>MONTJOY.<br>
Montjoy.
</p>

<p>KING HENRY.<br>
Thou dost thy office fairly. Turn thee back,<br>
And tell thy King I do not seek him now,<br>
But could be willing to march on to Calais<br>
Without impeachment; for, to say the sooth,<br>
Though ’tis no wisdom to confess so much<br>
Unto an enemy of craft and vantage,<br>
My people are with sickness much enfeebled,<br>
My numbers lessen’d, and those few I have<br>
Almost no better than so many French;<br>
Who when they were in health, I tell thee, herald,<br>
I thought upon one pair of English legs<br>
Did march three Frenchmen. Yet, forgive me, God,<br>
That I do brag thus! This your air of France<br>
Hath blown that vice in me. I must repent.<br>
Go therefore, tell thy master here I am;<br>
My ransom is this frail and worthless trunk,<br>
My army but a weak and sickly guard;<br>
Yet, God before, tell him we will come on,<br>
Though France himself and such another neighbour<br>
Stand in our way. There’s for thy labour, Montjoy.<br>
Go, bid thy master well advise himself.<br>
If we may pass, we will; if we be hind’red,<br>
We shall your tawny ground with your red blood<br>
Discolour; and so, Montjoy, fare you well.<br>
The sum of all our answer is but this:<br>
We would not seek a battle, as we are;<br>
Nor, as we are, we say we will not shun it.<br>
So tell your master.
</p>

<p>MONTJOY.<br>
I shall deliver so. Thanks to your Highness.
</p>

<p class="right"> [<i>Exit.</i>]</p>

<p>GLOUCESTER.<br>
I hope they will not come upon us now.
</p>

<p>KING HENRY.<br>
We are in God’s hands, brother, not in theirs.<br>
March to the bridge; it now draws toward night.<br>
Beyond the river we’ll encamp ourselves,<br>
And on tomorrow bid them march away.
</p>

<p class="right"> [<i>Exeunt.</i>]</p>

<h3> <a id="sceneIII_11.7"></a><b>SCENE VII. The French camp, near Agincourt.</b></h3>

<p class="scenedesc"> Enter the <span class="charname">Constable of France, the
Lord Rambures, Orleans, Dauphin</span> with others.</p>

<p>CONSTABLE.<br>
Tut! I have the best armour of the world.<br>
Would it were day!
</p>

<p>ORLEANS.<br>
You have an excellent armour; but let my horse have his due.
</p>

<p>CONSTABLE.<br>
It is the best horse of Europe.
</p>

<p>ORLEANS.<br>
Will it never be morning?
</p>

<p>DAUPHIN.<br>
My Lord of Orleans, and my Lord High Constable, you talk of horse and armour?
</p>

<p>ORLEANS.<br>
You are as well provided of both as any prince in the world.
</p>

<p>DAUPHIN.<br>
What a long night is this! I will not change my horse with any that treads but
on four pasterns. Ch’ha! He bounds from the earth, as if his entrails
were hairs; <i>le cheval volant</i>, the Pegasus, <i>qui a les narines de
feu!</i> When I bestride him, I soar, I am a hawk. He trots the air; the earth
sings when he touches it; the basest horn of his hoof is more musical than the
pipe of Hermes.
</p>

<p>ORLEANS.<br>
He’s of the colour of the nutmeg.
</p>

<p>DAUPHIN.<br>
And of the heat of the ginger. It is a beast for Perseus. He is pure air and
fire; and the dull elements of earth and water never appear in him, but only in
patient stillness while his rider mounts him. He is indeed a horse, and all
other jades you may call beasts.
</p>

<p>CONSTABLE.<br>
Indeed, my lord, it is a most absolute and excellent horse.
</p>

<p>DAUPHIN.<br>
It is the prince of palfreys; his neigh is like the bidding of a monarch, and
his countenance enforces homage.
</p>

<p>ORLEANS.<br>
No more, cousin.
</p>

<p>DAUPHIN.<br>
Nay, the man hath no wit that cannot, from the rising of the lark to the
lodging of the lamb, vary deserved praise on my palfrey. It is a theme as
fluent as the sea; turn the sands into eloquent tongues, and my horse is
argument for them all. ’Tis a subject for a sovereign to reason on, and
for a sovereign’s sovereign to ride on; and for the world, familiar to us
and unknown, to lay apart their particular functions and wonder at him. I once
writ a sonnet in his praise and began thus: “Wonder of
nature,”—
</p>

<p>ORLEANS.<br>
I have heard a sonnet begin so to one’s mistress.
</p>

<p>DAUPHIN.<br>
Then did they imitate that which I compos’d to my courser, for my horse
is my mistress.
</p>

<p>ORLEANS.<br>
Your mistress bears well.
</p>

<p>DAUPHIN.<br>
Me well; which is the prescript praise and perfection of a good and particular
mistress.
</p>

<p>CONSTABLE.<br>
Nay, for methought yesterday your mistress shrewdly shook your back.
</p>

<p>DAUPHIN.<br>
So perhaps did yours.
</p>

<p>CONSTABLE.<br>
Mine was not bridled.
</p>

<p>DAUPHIN.<br>
O then belike she was old and gentle; and you rode, like a kern of Ireland,
your French hose off, and in your strait strossers.
</p>

<p>CONSTABLE.<br>
You have good judgment in horsemanship.
</p>

<p>DAUPHIN.<br>
Be warn’d by me, then; they that ride so and ride not warily, fall into
foul bogs. I had rather have my horse to my mistress.
</p>

<p>CONSTABLE.<br>
I had as lief have my mistress a jade.
</p>

<p>DAUPHIN.<br>
I tell thee, Constable, my mistress wears his own hair.
</p>

<p>CONSTABLE.<br>
I could make as true a boast as that, if I had a sow to my mistress.
</p>

<p>DAUPHIN.<br>
“<i>Le chien est retourné à son propre vomissement, et la truie lavée au
bourbier</i>.” Thou mak’st use of anything.
</p>

<p>CONSTABLE.<br>
Yet do I not use my horse for my mistress, or any such proverb so little kin to
the purpose.
</p>

<p>RAMBURES.<br>
My Lord Constable, the armour that I saw in your tent tonight, are those stars
or suns upon it?
</p>

<p>CONSTABLE.<br>
Stars, my lord.
</p>

<p>DAUPHIN.<br>
Some of them will fall tomorrow, I hope.
</p>

<p>CONSTABLE.<br>
And yet my sky shall not want.
</p>

<p>DAUPHIN.<br>
That may be, for you bear a many superfluously, and ’twere more honour
some were away.
</p>

<p>CONSTABLE.<br>
Even as your horse bears your praises; who would trot as well, were some of
your brags dismounted.
</p>

<p>DAUPHIN.<br>
Would I were able to load him with his desert! Will it never be day? I will
trot tomorrow a mile, and my way shall be paved with English faces.
</p>

<p>CONSTABLE.<br>
I will not say so, for fear I should be fac’d out of my way. But I would
it were morning; for I would fain be about the ears of the English.
</p>

<p>RAMBURES.<br>
Who will go to hazard with me for twenty prisoners?
</p>

<p>CONSTABLE.<br>
You must first go yourself to hazard, ere you have them.
</p>

<p>DAUPHIN.<br>
’Tis midnight; I’ll go arm myself.
</p>

<p class="right"> [<i>Exit.</i>]</p>

<p>ORLEANS.<br>
The Dauphin longs for morning.
</p>

<p>RAMBURES.<br>
He longs to eat the English.
</p>

<p>CONSTABLE.<br>
I think he will eat all he kills.
</p>

<p>ORLEANS.<br>
By the white hand of my lady, he’s a gallant prince.
</p>

<p>CONSTABLE.<br>
Swear by her foot that she may tread out the oath.
</p>

<p>ORLEANS.<br>
He is simply the most active gentleman of France.
</p>

<p>CONSTABLE.<br>
Doing is activity; and he will still be doing.
</p>

<p>ORLEANS.<br>
He never did harm, that I heard of.
</p>

<p>CONSTABLE.<br>
Nor will do none tomorrow. He will keep that good name still.
</p>

<p>ORLEANS.<br>
I know him to be valiant.
</p>

<p>CONSTABLE.<br>
I was told that by one that knows him better than you.
</p>

<p>ORLEANS.<br>
What’s he?
</p>

<p>CONSTABLE.<br>
Marry, he told me so himself; and he said he car’d not who knew it.
</p>

<p>ORLEANS.<br>
He needs not; it is no hidden virtue in him.
</p>

<p>CONSTABLE.<br>
By my faith, sir, but it is; never anybody saw it but his lackey. ’Tis a
hooded valour; and when it appears, it will bate.
</p>

<p>ORLEANS.<br>
“Ill will never said well.”
</p>

<p>CONSTABLE.<br>
I will cap that proverb with “There is flattery in friendship.”
</p>

<p>ORLEANS.<br>
And I will take up that with “Give the devil his due.”
</p>

<p>CONSTABLE.<br>
Well plac’d. There stands your friend for the devil; have at the very eye
of that proverb with “A pox of the devil.”
</p>

<p>ORLEANS.<br>
You are the better at proverbs, by how much “A fool’s bolt is soon
shot.”
</p>

<p>CONSTABLE.<br>
You have shot over.
</p>

<p>ORLEANS.<br>
’Tis not the first time you were overshot.
</p>

<p class="scenedesc"> Enter a <span class="charname">Messenger</span>.</p>

<p>MESSENGER.<br>
My Lord High Constable, the English lie within fifteen hundred paces of your
tents.
</p>

<p>CONSTABLE.<br>
Who hath measur’d the ground?
</p>

<p>MESSENGER.<br>
The Lord Grandpré.
</p>

<p>CONSTABLE.<br>
A valiant and most expert gentleman. Would it were day! Alas, poor Harry of
England, he longs not for the dawning as we do.
</p>

<p>ORLEANS.<br>
What a wretched and peevish fellow is this King of England, to mope with his
fat-brain’d followers so far out of his knowledge!
</p>

<p>CONSTABLE.<br>
If the English had any apprehension, they would run away.
</p>

<p>ORLEANS.<br>
That they lack; for if their heads had any intellectual armour, they could
never wear such heavy head-pieces.
</p>

<p>RAMBURES.<br>
That island of England breeds very valiant creatures. Their mastiffs are of
unmatchable courage.
</p>

<p>ORLEANS.<br>
Foolish curs, that run winking into the mouth of a Russian bear and have their
heads crush’d like rotten apples! You may as well say, that’s a
valiant flea that dare eat his breakfast on the lip of a lion.
</p>

<p>CONSTABLE.<br>
Just, just; and the men do sympathize with the mastiffs in robustious and rough
coming on, leaving their wits with their wives; and then, give them great meals
of beef and iron and steel, they will eat like wolves and fight like devils.
</p>

<p>ORLEANS.<br>
Ay, but these English are shrewdly out of beef.
</p>

<p>CONSTABLE.<br>
Then shall we find tomorrow they have only stomachs to eat and none to fight.
Now is it time to arm. Come, shall we about it?
</p>

<p>ORLEANS.<br>
It is now two o’clock; but, let me see, by ten<br>
We shall have each a hundred Englishmen.
</p>

<p class="right"> [<i>Exeunt.</i>]</p>

