<h2> <a id="sceneIV_17.1"></a><b>ACT IV</b></h2>

<h3> <b>SCENE I. Rome. A room in Antony’s house.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Antony, Octavius</span> and <span class="charname">Lepidus,</span> seated at a table.
</p>

<p class="drama">
ANTONY.<br>
These many then shall die; their names are prick’d.
</p>

<p class="drama">
OCTAVIUS.<br>
Your brother too must die; consent you, Lepidus?
</p>

<p class="drama">
LEPIDUS.<br>
I do consent,—
</p>

<p class="drama">
OCTAVIUS.<br>
Prick him down, Antony.
</p>

<p class="drama">
LEPIDUS.<br>
Upon condition Publius shall not live,<br>
Who is your sister’s son, Mark Antony.
</p>

<p class="drama">
ANTONY.<br>
He shall not live; look, with a spot I damn him.<br>
But, Lepidus, go you to Caesar’s house;<br>
Fetch the will hither, and we shall determine<br>
How to cut off some charge in legacies.
</p>

<p class="drama">
LEPIDUS.<br>
What, shall I find you here?
</p>

<p class="drama">
OCTAVIUS.<br>
Or here, or at the Capitol.
</p>

<p class="right">
[<i>Exit <span class="charname">Lepidus</span>.</i>]
</p>

<p class="drama">
ANTONY.<br>
This is a slight unmeritable man,<br>
Meet to be sent on errands. Is it fit,<br>
The three-fold world divided, he should stand<br>
One of the three to share it?
</p>

<p class="drama">
OCTAVIUS.<br>
So you thought him,<br>
And took his voice who should be prick’d to die<br>
In our black sentence and proscription.
</p>

<p class="drama">
ANTONY.<br>
Octavius, I have seen more days than you;<br>
And though we lay these honours on this man,<br>
To ease ourselves of divers sland’rous loads,<br>
He shall but bear them as the ass bears gold,<br>
To groan and sweat under the business,<br>
Either led or driven, as we point the way;<br>
And having brought our treasure where we will,<br>
Then take we down his load, and turn him off,<br>
Like to the empty ass, to shake his ears,<br>
And graze in commons.
</p>

<p class="drama">
OCTAVIUS.<br>
You may do your will;<br>
But he’s a tried and valiant soldier.
</p>

<p class="drama">
ANTONY.<br>
So is my horse, Octavius; and for that<br>
I do appoint him store of provender.<br>
It is a creature that I teach to fight,<br>
To wind, to stop, to run directly on,<br>
His corporal motion govern’d by my spirit.<br>
And, in some taste, is Lepidus but so:<br>
He must be taught, and train’d, and bid go forth:<br>
A barren-spirited fellow; one that feeds<br>
On objects, arts, and imitations,<br>
Which, out of use and stal’d by other men,<br>
Begin his fashion. Do not talk of him<br>
But as a property. And now, Octavius,<br>
Listen great things. Brutus and Cassius<br>
Are levying powers; we must straight make head.<br>
Therefore let our alliance be combin’d,<br>
Our best friends made, our means stretch’d;<br>
And let us presently go sit in council,<br>
How covert matters may be best disclos’d,<br>
And open perils surest answered.
</p>

<p class="drama">
OCTAVIUS.<br>
Let us do so: for we are at the stake,<br>
And bay’d about with many enemies;<br>
And some that smile have in their hearts, I fear,<br>
Millions of mischiefs.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneIV_17.2"></a><b>SCENE II. Before Brutus’ tent, in the camp
near Sardis.</b></h3>

<p class="scenedesc">
Drum. Enter <span class="charname">Brutus, Lucilius, Titinius</span> and <span class="charname">Soldiers; Pindarus</span> meeting them; <span class="charname">Lucius</span> at some distance.
</p>

<p class="drama">
BRUTUS.<br>
Stand, ho!
</p>

<p class="drama">
LUCILIUS.<br>
Give the word, ho! and stand.
</p>

<p class="drama">
BRUTUS.<br>
What now, Lucilius! is Cassius near?
</p>

<p class="drama">
LUCILIUS.<br>
He is at hand, and Pindarus is come<br>
To do you salutation from his master.
</p>

<p class="right">
[<i><span class="charname">Pindarus</span> gives a letter to <span class="charname">Brutus</span>.</i>]
</p>

<p class="drama">
BRUTUS.<br>
He greets me well. Your master, Pindarus,<br>
In his own change, or by ill officers,<br>
Hath given me some worthy cause to wish<br>
Things done, undone: but, if he be at hand,<br>
I shall be satisfied.
</p>

<p class="drama">
PINDARUS.<br>
I do not doubt<br>
But that my noble master will appear<br>
Such as he is, full of regard and honour.
</p>

<p class="drama">
BRUTUS.<br>
He is not doubted. A word, Lucilius;<br>
How he received you, let me be resolv’d.
</p>

<p class="drama">
LUCILIUS.<br>
With courtesy and with respect enough,<br>
But not with such familiar instances,<br>
Nor with such free and friendly conference,<br>
As he hath us’d of old.
</p>

<p class="drama">
BRUTUS.<br>
Thou hast describ’d<br>
A hot friend cooling. Ever note, Lucilius,<br>
When love begins to sicken and decay<br>
It useth an enforced ceremony.<br>
There are no tricks in plain and simple faith;<br>
But hollow men, like horses hot at hand,<br>
Make gallant show and promise of their mettle;
</p>

<p class="right">
[<i>Low march within.</i>]
</p>

<p class="drama">
But when they should endure the bloody spur,<br>
They fall their crests, and like deceitful jades<br>
Sink in the trial. Comes his army on?
</p>

<p class="drama">
LUCILIUS.<br>
They meant this night in Sardis to be quarter’d;<br>
The greater part, the horse in general,<br>
Are come with Cassius.
</p>

<p class="scenedesc">
Enter <span class="charname">Cassius</span> and <span class="charname">Soldiers</span>.
</p>

<p class="drama">
BRUTUS.<br>
Hark! he is arriv’d.<br>
March gently on to meet him.
</p>

<p class="drama">
CASSIUS.<br>
Stand, ho!
</p>

<p class="drama">
BRUTUS.<br>
Stand, ho! Speak the word along.
</p>

<p class="drama">
FIRST SOLDIER.<br>
Stand!
</p>

<p class="drama">
SECOND SOLDIER.<br>
Stand!
</p>

<p class="drama">
THIRD SOLDIER.<br>
Stand!
</p>

<p class="drama">
CASSIUS.<br>
Most noble brother, you have done me wrong.
</p>

<p class="drama">
BRUTUS.<br>
Judge me, you gods; wrong I mine enemies?<br>
And if not so, how should I wrong a brother?
</p>

<p class="drama">
CASSIUS.<br>
Brutus, this sober form of yours hides wrongs;<br>
And when you do them—
</p>

<p class="drama">
BRUTUS.<br>
Cassius, be content.<br>
Speak your griefs softly, I do know you well.<br>
Before the eyes of both our armies here,<br>
Which should perceive nothing but love from us,<br>
Let us not wrangle. Bid them move away;<br>
Then in my tent, Cassius, enlarge your griefs,<br>
And I will give you audience.
</p>

<p class="drama">
CASSIUS.<br>
Pindarus,<br>
Bid our commanders lead their charges off<br>
A little from this ground.
</p>

<p class="drama">
BRUTUS.<br>
Lucilius, do you the like; and let no man<br>
Come to our tent till we have done our conference.<br>
Lucius and Titinius, guard our door.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneIV_17.3"></a><b>SCENE III. Within the tent of
Brutus.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Brutus</span> and <span class="charname">Cassius</span>.
</p>

<p class="drama">
CASSIUS.<br>
That you have wrong’d me doth appear in this:<br>
You have condemn’d and noted Lucius Pella<br>
For taking bribes here of the Sardians;<br>
Wherein my letters, praying on his side<br>
Because I knew the man, were slighted off.
</p>

<p class="drama">
BRUTUS.<br>
You wrong’d yourself to write in such a case.
</p>

<p class="drama">
CASSIUS.<br>
In such a time as this it is not meet<br>
That every nice offence should bear his comment.
</p>

<p class="drama">
BRUTUS.<br>
Let me tell you, Cassius, you yourself<br>
Are much condemn’d to have an itching palm,<br>
To sell and mart your offices for gold<br>
To undeservers.
</p>

<p class="drama">
CASSIUS.<br>
I an itching palm!<br>
You know that you are Brutus that speak this,<br>
Or, by the gods, this speech were else your last.
</p>

<p class="drama">
BRUTUS.<br>
The name of Cassius honours this corruption,<br>
And chastisement doth therefore hide his head.
</p>

<p class="drama">
CASSIUS.<br>
Chastisement!
</p>

<p class="drama">
BRUTUS.<br>
Remember March, the Ides of March remember:<br>
Did not great Julius bleed for justice’ sake?<br>
What villain touch’d his body, that did stab,<br>
And not for justice? What! Shall one of us,<br>
That struck the foremost man of all this world<br>
But for supporting robbers, shall we now<br>
Contaminate our fingers with base bribes,<br>
And sell the mighty space of our large honours<br>
For so much trash as may be grasped thus?<br>
I had rather be a dog, and bay the moon,<br>
Than such a Roman.
</p>

<p class="drama">
CASSIUS.<br>
Brutus, bait not me,<br>
I’ll not endure it. You forget yourself,<br>
To hedge me in. I am a soldier, I,<br>
Older in practice, abler than yourself<br>
To make conditions.
</p>

<p class="drama">
BRUTUS.<br>
Go to; you are not, Cassius.
</p>

<p class="drama">
CASSIUS.<br>
I am.
</p>

<p class="drama">
BRUTUS.<br>
I say you are not.
</p>

<p class="drama">
CASSIUS.<br>
Urge me no more, I shall forget myself;<br>
Have mind upon your health, tempt me no farther.
</p>

<p class="drama">
BRUTUS.<br>
Away, slight man!
</p>

<p class="drama">
CASSIUS.<br>
Is’t possible?
</p>

<p class="drama">
BRUTUS.<br>
Hear me, for I will speak.<br>
Must I give way and room to your rash choler?<br>
Shall I be frighted when a madman stares?
</p>

<p class="drama">
CASSIUS.<br>
O ye gods, ye gods! Must I endure all this?
</p>

<p class="drama">
BRUTUS.<br>
All this? ay, more: fret till your proud heart break;<br>
Go show your slaves how choleric you are,<br>
And make your bondmen tremble. Must I budge?<br>
Must I observe you? Must I stand and crouch<br>
Under your testy humour? By the gods,<br>
You shall digest the venom of your spleen,<br>
Though it do split you; for, from this day forth,<br>
I’ll use you for my mirth, yea, for my laughter,<br>
When you are waspish.
</p>

<p class="drama">
CASSIUS.<br>
Is it come to this?
</p>

<p class="drama">
BRUTUS.<br>
You say you are a better soldier:<br>
Let it appear so; make your vaunting true,<br>
And it shall please me well. For mine own part,<br>
I shall be glad to learn of noble men.
</p>

<p class="drama">
CASSIUS.<br>
You wrong me every way, you wrong me, Brutus.<br>
I said, an elder soldier, not a better:<br>
Did I say better?
</p>

<p class="drama">
BRUTUS.<br>
If you did, I care not.
</p>

<p class="drama">
CASSIUS.<br>
When Caesar liv’d, he durst not thus have mov’d me.
</p>

<p class="drama">
BRUTUS.<br>
Peace, peace! you durst not so have tempted him.
</p>

<p class="drama">
CASSIUS.<br>
I durst not?
</p>

<p class="drama">
BRUTUS.<br>
No.
</p>

<p class="drama">
CASSIUS.<br>
What? durst not tempt him?
</p>

<p class="drama">
BRUTUS.<br>
For your life you durst not.
</p>

<p class="drama">
CASSIUS.<br>
Do not presume too much upon my love.<br>
I may do that I shall be sorry for.
</p>

<p class="drama">
BRUTUS.<br>
You have done that you should be sorry for.<br>
There is no terror, Cassius, in your threats,<br>
For I am arm’d so strong in honesty,<br>
That they pass by me as the idle wind,<br>
Which I respect not. I did send to you<br>
For certain sums of gold, which you denied me;<br>
For I can raise no money by vile means:<br>
By Heaven, I had rather coin my heart,<br>
And drop my blood for drachmas, than to wring<br>
From the hard hands of peasants their vile trash<br>
By any indirection. I did send<br>
To you for gold to pay my legions,<br>
Which you denied me: was that done like Cassius?<br>
Should I have answer’d Caius Cassius so?<br>
When Marcus Brutus grows so covetous,<br>
To lock such rascal counters from his friends,<br>
Be ready, gods, with all your thunderbolts,<br>
Dash him to pieces!
</p>

<p class="drama">
CASSIUS.<br>
I denied you not.
</p>

<p class="drama">
BRUTUS.<br>
You did.
</p>

<p class="drama">
CASSIUS.<br>
I did not. He was but a fool<br>
That brought my answer back. Brutus hath riv’d my heart.<br>
A friend should bear his friend’s infirmities;<br>
But Brutus makes mine greater than they are.
</p>

<p class="drama">
BRUTUS.<br>
I do not, till you practise them on me.
</p>

<p class="drama">
CASSIUS.<br>
You love me not.
</p>

<p class="drama">
BRUTUS.<br>
I do not like your faults.
</p>

<p class="drama">
CASSIUS.<br>
A friendly eye could never see such faults.
</p>

<p class="drama">
BRUTUS.<br>
A flatterer’s would not, though they do appear<br>
As huge as high Olympus.
</p>

<p class="drama">
CASSIUS.<br>
Come, Antony, and young Octavius, come,<br>
Revenge yourselves alone on Cassius,<br>
For Cassius is a-weary of the world:<br>
Hated by one he loves; brav’d by his brother;<br>
Check’d like a bondman; all his faults observ’d,<br>
Set in a note-book, learn’d and conn’d by rote,<br>
To cast into my teeth. O, I could weep<br>
My spirit from mine eyes! There is my dagger,<br>
And here my naked breast; within, a heart<br>
Dearer than Plutus’ mine, richer than gold:<br>
If that thou be’st a Roman, take it forth.<br>
I, that denied thee gold, will give my heart:<br>
Strike as thou didst at Caesar; for I know,<br>
When thou didst hate him worst, thou lovedst him better<br>
Than ever thou lovedst Cassius.
</p>

<p class="drama">
BRUTUS.<br>
Sheathe your dagger.<br>
Be angry when you will, it shall have scope;<br>
Do what you will, dishonour shall be humour.<br>
O Cassius, you are yoked with a lamb<br>
That carries anger as the flint bears fire,<br>
Who, much enforced, shows a hasty spark,<br>
And straight is cold again.
</p>

<p class="drama">
CASSIUS.<br>
Hath Cassius liv’d<br>
To be but mirth and laughter to his Brutus,<br>
When grief and blood ill-temper’d vexeth him?
</p>

<p class="drama">
BRUTUS.<br>
When I spoke that, I was ill-temper’d too.
</p>

<p class="drama">
CASSIUS.<br>
Do you confess so much? Give me your hand.
</p>

<p class="drama">
BRUTUS.<br>
And my heart too.
</p>

<p class="drama">
CASSIUS.<br>
O Brutus!
</p>

<p class="drama">
BRUTUS.<br>
What’s the matter?
</p>

<p class="drama">
CASSIUS.<br>
Have not you love enough to bear with me,<br>
When that rash humour which my mother gave me<br>
Makes me forgetful?
</p>

<p class="drama">
BRUTUS.<br>
Yes, Cassius; and from henceforth,<br>
When you are over-earnest with your Brutus,<br>
He’ll think your mother chides, and leave you so.
</p>

<p class="scenedesc">
Enter <span class="charname">Poet,</span> followed by <span class="charname">Lucilius, Titinius</span> and <span class="charname">Lucius</span>.
</p>

<p class="drama">
POET.<br>
[<i>Within.</i>] Let me go in to see the generals,<br>
There is some grudge between ’em; ’tis not meet<br>
They be alone.
</p>

<p class="drama">
LUCILIUS.<br>
[<i>Within.</i>] You shall not come to them.
</p>

<p class="drama">
POET.<br>
[<i>Within.</i>] Nothing but death shall stay me.
</p>

<p class="drama">
CASSIUS.<br>
How now! What’s the matter?
</p>

<p class="drama">
POET.<br>
For shame, you generals! What do you mean?<br>
Love, and be friends, as two such men should be;<br>
For I have seen more years, I’m sure, than ye.
</p>

<p class="drama">
CASSIUS.<br>
Ha, ha! How vilely doth this cynic rhyme!
</p>

<p class="drama">
BRUTUS.<br>
Get you hence, sirrah. Saucy fellow, hence!
</p>

<p class="drama">
CASSIUS.<br>
Bear with him, Brutus; ’tis his fashion.
</p>

<p class="drama">
BRUTUS.<br>
I’ll know his humour when he knows his time.<br>
What should the wars do with these jigging fools?<br>
Companion, hence!
</p>

<p class="drama">
CASSIUS.<br>
Away, away, be gone!
</p>

<p class="right">
[<i>Exit <span class="charname">Poet</span>.</i>]
</p>

<p class="drama">
BRUTUS.<br>
Lucilius and Titinius, bid the commanders<br>
Prepare to lodge their companies tonight.
</p>

<p class="drama">
CASSIUS.<br>
And come yourselves and bring Messala with you<br>
Immediately to us.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Lucilius</span> and <span class="charname">Titinius</span>.</i>]
</p>

<p class="drama">
BRUTUS.<br>
Lucius, a bowl of wine.
</p>

<p class="right">
[<i>Exit <span class="charname">Lucius</span>.</i>]
</p>

<p class="drama">
CASSIUS.<br>
I did not think you could have been so angry.
</p>

<p class="drama">
BRUTUS.<br>
O Cassius, I am sick of many griefs.
</p>

<p class="drama">
CASSIUS.<br>
Of your philosophy you make no use,<br>
If you give place to accidental evils.
</p>

<p class="drama">
BRUTUS.<br>
No man bears sorrow better. Portia is dead.
</p>

<p class="drama">
CASSIUS.<br>
Ha? Portia?
</p>

<p class="drama">
BRUTUS.<br>
She is dead.
</p>

<p class="drama">
CASSIUS.<br>
How ’scap’d I killing, when I cross’d you so?<br>
O insupportable and touching loss!<br>
Upon what sickness?
</p>

<p class="drama">
BRUTUS.<br>
Impatient of my absence,<br>
And grief that young Octavius with Mark Antony<br>
Have made themselves so strong; for with her death<br>
That tidings came. With this she fell distract,<br>
And, her attendants absent, swallow’d fire.
</p>

<p class="drama">
CASSIUS.<br>
And died so?
</p>

<p class="drama">
BRUTUS.<br>
Even so.
</p>

<p class="drama">
CASSIUS.<br>
O ye immortal gods!
</p>

<p class="scenedesc">
Enter <span class="charname">Lucius,</span> with wine and a taper.
</p>

<p class="drama">
BRUTUS.<br>
Speak no more of her. Give me a bowl of wine.<br>
In this I bury all unkindness, Cassius.
</p>

<p class="right">
[<i>Drinks.</i>]
</p>

<p class="drama">
CASSIUS.<br>
My heart is thirsty for that noble pledge.<br>
Fill, Lucius, till the wine o’erswell the cup.<br>
I cannot drink too much of Brutus’ love.
</p>

<p class="right">
[<i>Drinks.</i>]
</p>

<p class="right">
[<i>Exit <span class="charname">Lucius</span>.</i>]
</p>

<p class="scenedesc">
Enter <span class="charname">Titinius</span> and <span class="charname">Messala</span>.
</p>

<p class="drama">
BRUTUS.<br>
Come in, Titinius!<br>
Welcome, good Messala.<br>
Now sit we close about this taper here,<br>
And call in question our necessities.
</p>

<p class="drama">
CASSIUS.<br>
Portia, art thou gone?
</p>

<p class="drama">
BRUTUS.<br>
No more, I pray you.<br>
Messala, I have here received letters,<br>
That young Octavius and Mark Antony<br>
Come down upon us with a mighty power,<br>
Bending their expedition toward Philippi.
</p>

<p class="drama">
MESSALA.<br>
Myself have letters of the selfsame tenor.
</p>

<p class="drama">
BRUTUS.<br>
With what addition?
</p>

<p class="drama">
MESSALA.<br>
That by proscription and bills of outlawry<br>
Octavius, Antony, and Lepidus<br>
Have put to death an hundred Senators.
</p>

<p class="drama">
BRUTUS.<br>
Therein our letters do not well agree.<br>
Mine speak of seventy Senators that died<br>
By their proscriptions, Cicero being one.
</p>

<p class="drama">
CASSIUS.<br>
Cicero one!
</p>

<p class="drama">
MESSALA.<br>
Cicero is dead,<br>
And by that order of proscription.<br>
Had you your letters from your wife, my lord?
</p>

<p class="drama">
BRUTUS.<br>
No, Messala.
</p>

<p class="drama">
MESSALA.<br>
Nor nothing in your letters writ of her?
</p>

<p class="drama">
BRUTUS.<br>
Nothing, Messala.
</p>

<p class="drama">
MESSALA.<br>
That, methinks, is strange.
</p>

<p class="drama">
BRUTUS.<br>
Why ask you? Hear you aught of her in yours?
</p>

<p class="drama">
MESSALA.<br>
No, my lord.
</p>

<p class="drama">
BRUTUS.<br>
Now as you are a Roman, tell me true.
</p>

<p class="drama">
MESSALA.<br>
Then like a Roman bear the truth I tell,<br>
For certain she is dead, and by strange manner.
</p>

<p class="drama">
BRUTUS.<br>
Why, farewell, Portia. We must die, Messala.<br>
With meditating that she must die once,<br>
I have the patience to endure it now.
</p>

<p class="drama">
MESSALA.<br>
Even so great men great losses should endure.
</p>

<p class="drama">
CASSIUS.<br>
I have as much of this in art as you,<br>
But yet my nature could not bear it so.
</p>

<p class="drama">
BRUTUS.<br>
Well, to our work alive. What do you think<br>
Of marching to Philippi presently?
</p>

<p class="drama">
CASSIUS.<br>
I do not think it good.
</p>

<p class="drama">
BRUTUS.<br>
Your reason?
</p>

<p class="drama">
CASSIUS.<br>
This it is:<br>
’Tis better that the enemy seek us;<br>
So shall he waste his means, weary his soldiers,<br>
Doing himself offence, whilst we, lying still,<br>
Are full of rest, defence, and nimbleness.
</p>

<p class="drama">
BRUTUS.<br>
Good reasons must of force give place to better.<br>
The people ’twixt Philippi and this ground<br>
Do stand but in a forced affection;<br>
For they have grudg’d us contribution.<br>
The enemy, marching along by them,<br>
By them shall make a fuller number up,<br>
Come on refresh’d, new-added, and encourag’d;<br>
From which advantage shall we cut him off<br>
If at Philippi we do face him there,<br>
These people at our back.
</p>

<p class="drama">
CASSIUS.<br>
Hear me, good brother.
</p>

<p class="drama">
BRUTUS.<br>
Under your pardon. You must note besides,<br>
That we have tried the utmost of our friends,<br>
Our legions are brim-full, our cause is ripe.<br>
The enemy increaseth every day;<br>
We, at the height, are ready to decline.<br>
There is a tide in the affairs of men,<br>
Which, taken at the flood, leads on to fortune;<br>
Omitted, all the voyage of their life<br>
Is bound in shallows and in miseries.<br>
On such a full sea are we now afloat,<br>
And we must take the current when it serves,<br>
Or lose our ventures.
</p>

<p class="drama">
CASSIUS.<br>
Then, with your will, go on:<br>
We’ll along ourselves, and meet them at Philippi.
</p>

<p class="drama">
BRUTUS.<br>
The deep of night is crept upon our talk,<br>
And nature must obey necessity,<br>
Which we will niggard with a little rest.<br>
There is no more to say?
</p>

<p class="drama">
CASSIUS.<br>
No more. Good night:<br>
Early tomorrow will we rise, and hence.
</p>

<p class="scenedesc">
Enter <span class="charname">Lucius</span>.
</p>

<p class="drama">
BRUTUS.<br>
Lucius! My gown.
</p>

<p class="right">
[<i>Exit <span class="charname">Lucius</span>.</i>]
</p>

<p class="drama">
Farewell now, good Messala.<br>
Good night, Titinius. Noble, noble Cassius,<br>
Good night, and good repose.
</p>

<p class="drama">
CASSIUS.<br>
O my dear brother!<br>
This was an ill beginning of the night.<br>
Never come such division ’tween our souls!<br>
Let it not, Brutus.
</p>

<p class="scenedesc">
Enter <span class="charname">Lucius</span> with the gown.
</p>

<p class="drama">
BRUTUS.<br>
Everything is well.
</p>

<p class="drama">
CASSIUS.<br>
Good night, my lord.
</p>

<p class="drama">
BRUTUS.<br>
Good night, good brother.
</p>

<p class="drama">
TITINIUS and MESSALA.<br>
Good night, Lord Brutus.
</p>

<p class="drama">
BRUTUS.<br>
Farewell, everyone.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Cassius, Titinius</span> and <span class="charname">Messala</span>.</i>]
</p>

<p class="drama">
Give me the gown. Where is thy instrument?
</p>

<p class="drama">
LUCIUS.<br>
Here in the tent.
</p>

<p class="drama">
BRUTUS.<br>
What, thou speak’st drowsily?<br>
Poor knave, I blame thee not, thou art o’er-watch’d.<br>
Call Claudius and some other of my men;<br>
I’ll have them sleep on cushions in my tent.
</p>

<p class="drama">
LUCIUS.<br>
Varro and Claudius!
</p>

<p class="scenedesc">
Enter <span class="charname">Varro</span> and <span class="charname">Claudius</span>.
</p>

<p class="drama">
VARRO.<br>
Calls my lord?
</p>

<p class="drama">
BRUTUS.<br>
I pray you, sirs, lie in my tent and sleep;<br>
It may be I shall raise you by-and-by<br>
On business to my brother Cassius.
</p>

<p class="drama">
VARRO.<br>
So please you, we will stand and watch your pleasure.
</p>

<p class="drama">
BRUTUS.<br>
I will not have it so; lie down, good sirs,<br>
It may be I shall otherwise bethink me.<br>
Look, Lucius, here’s the book I sought for so;<br>
I put it in the pocket of my gown.
</p>

<p class="right">
[<i><span class="charname">Servants</span> lie down.</i>]
</p>

<p class="drama">
LUCIUS.<br>
I was sure your lordship did not give it me.
</p>

<p class="drama">
BRUTUS.<br>
Bear with me, good boy, I am much forgetful.<br>
Canst thou hold up thy heavy eyes awhile,<br>
And touch thy instrument a strain or two?
</p>

<p class="drama">
LUCIUS.<br>
Ay, my lord, an’t please you.
</p>

<p class="drama">
BRUTUS.<br>
It does, my boy.<br>
I trouble thee too much, but thou art willing.
</p>

<p class="drama">
LUCIUS.<br>
It is my duty, sir.
</p>

<p class="drama">
BRUTUS.<br>
I should not urge thy duty past thy might;<br>
I know young bloods look for a time of rest.
</p>

<p class="drama">
LUCIUS.<br>
I have slept, my lord, already.
</p>

<p class="drama">
BRUTUS.<br>
It was well done, and thou shalt sleep again;<br>
I will not hold thee long. If I do live,<br>
I will be good to thee.
</p>

<p class="right">
[<i><span class="charname">Lucius</span> plays and sings till he falls
asleep.</i>]
</p>

<p class="drama">
This is a sleepy tune. O murd’rous slumber,<br>
Layest thou thy leaden mace upon my boy,<br>
That plays thee music? Gentle knave, good night;<br>
I will not do thee so much wrong to wake thee.<br>
If thou dost nod, thou break’st thy instrument;<br>
I’ll take it from thee; and, good boy, good night.<br>
Let me see, let me see; is not the leaf turn’d down<br>
Where I left reading? Here it is, I think.
</p>

<p class="scenedesc">
Enter the <span class="charname">Ghost of Caesar</span>.
</p>

<p class="drama">
How ill this taper burns! Ha! who comes here?<br>
I think it is the weakness of mine eyes<br>
That shapes this monstrous apparition.<br>
It comes upon me. Art thou anything?<br>
Art thou some god, some angel, or some devil,<br>
That mak’st my blood cold and my hair to stare?<br>
Speak to me what thou art.
</p>

<p class="drama">
GHOST.<br>
Thy evil spirit, Brutus.
</p>

<p class="drama">
BRUTUS.<br>
Why com’st thou?
</p>

<p class="drama">
GHOST.<br>
To tell thee thou shalt see me at Philippi.
</p>

<p class="drama">
BRUTUS.<br>
Well; then I shall see thee again?
</p>

<p class="drama">
GHOST.<br>
Ay, at Philippi.
</p>

<p class="drama">
BRUTUS.<br>
Why, I will see thee at Philippi then.
</p>

<p class="right">
[<i><span class="charname">Ghost</span> vanishes.</i>]
</p>

<p class="drama">
Now I have taken heart, thou vanishest.<br>
Ill spirit, I would hold more talk with thee.<br>
Boy! Lucius! Varro! Claudius! Sirs, awake! Claudius!
</p>

<p class="drama">
LUCIUS.<br>
The strings, my lord, are false.
</p>

<p class="drama">
BRUTUS.<br>
He thinks he still is at his instrument.<br>
Lucius, awake!
</p>

<p class="drama">
LUCIUS.<br>
My lord?
</p>

<p class="drama">
BRUTUS.<br>
Didst thou dream, Lucius, that thou so criedst out?
</p>

<p class="drama">
LUCIUS.<br>
My lord, I do not know that I did cry.
</p>

<p class="drama">
BRUTUS.<br>
Yes, that thou didst. Didst thou see anything?
</p>

<p class="drama">
LUCIUS.<br>
Nothing, my lord.
</p>

<p class="drama">
BRUTUS.<br>
Sleep again, Lucius. Sirrah Claudius!<br>
Fellow thou, awake!
</p>

<p class="drama">
VARRO.<br>
My lord?
</p>

<p class="drama">
CLAUDIUS.<br>
My lord?
</p>

<p class="drama">
BRUTUS.<br>
Why did you so cry out, sirs, in your sleep?
</p>

<p class="drama">
VARRO. CLAUDIUS.<br>
Did we, my lord?
</p>

<p class="drama">
BRUTUS.<br>
Ay. Saw you anything?
</p>

<p class="drama">
VARRO.<br>
No, my lord, I saw nothing.
</p>

<p class="drama">
CLAUDIUS.<br>
Nor I, my lord.
</p>

<p class="drama">
BRUTUS.<br>
Go and commend me to my brother Cassius;<br>
Bid him set on his powers betimes before,<br>
And we will follow.
</p>

<p class="drama">
VARRO. CLAUDIUS.<br>
It shall be done, my lord.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

