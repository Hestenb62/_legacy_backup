<h2><a id="sceneV_13.1"></a>ACT V</h2>

<h3> <b>SCENE I. Fields between Dartford and Blackheath</b></h3>

<p class="scenedesc">Enter <span class="charname">York</span> and his army of
Irish, with drum and colours.</p>

<p class="drama">
YORK.<br>
From Ireland thus comes York to claim his right<br>
And pluck the crown from feeble Henry’s head.<br>
Ring, bells, aloud; burn, bonfires, clear and bright,<br>
To entertain great England’s lawful king.<br>
Ah, <i>sancta majestas</i>, who would not buy thee dear?<br>
Let them obey that knows not how to rule.<br>
This hand was made to handle nought but gold.<br>
I cannot give due action to my words<br>
Except a sword or sceptre balance it.<br>
A sceptre shall it have, have I a soul,<br>
On which I’ll toss the fleur-de-luce of France.
</p>

<p class="scenedesc">Enter <span class="charname">Buckingham</span>.</p>

<p class="drama">
Whom have we here? Buckingham, to disturb me?<br>
The King hath sent him, sure. I must dissemble.
</p>

<p class="drama">
BUCKINGHAM.<br>
York, if thou meanest well, I greet thee well.
</p>

<p class="drama">
YORK.<br>
Humphrey of Buckingham, I accept thy greeting.<br>
Art thou a messenger, or come of pleasure?
</p>

<p class="drama">
BUCKINGHAM.<br>
A messenger from Henry, our dread liege,<br>
To know the reason of these arms in peace;<br>
Or why thou, being a subject as I am,<br>
Against thy oath and true allegiance sworn,<br>
Should raise so great a power without his leave,<br>
Or dare to bring thy force so near the court.
</p>

<p class="drama">
YORK.<br>
[<i>Aside</i>.] Scarce can I speak, my choler is so great.<br>
O, I could hew up rocks and fight with flint,<br>
I am so angry at these abject terms;<br>
And now, like Ajax Telamonius,<br>
On sheep or oxen could I spend my fury.<br>
I am far better born than is the King,<br>
More like a king, more kingly in my thoughts.<br>
But I must make fair weather yet awhile,<br>
Till Henry be more weak and I more strong.—<br>
Buckingham, I prithee, pardon me,<br>
That I have given no answer all this while;<br>
My mind was troubled with deep melancholy.<br>
The cause why I have brought this army hither<br>
Is to remove proud Somerset from the King,<br>
Seditious to his grace and to the state.
</p>

<p class="drama">
BUCKINGHAM.<br>
That is too much presumption on thy part;<br>
But if thy arms be to no other end,<br>
The King hath yielded unto thy demand:<br>
The Duke of Somerset is in the Tower.
</p>

<p class="drama">
YORK.<br>
Upon thine honour, is he prisoner?
</p>

<p class="drama">
BUCKINGHAM.<br>
Upon mine honour, he is prisoner.
</p>

<p class="drama">
YORK.<br>
Then, Buckingham, I do dismiss my powers.<br>
Soldiers, I thank you all; disperse yourselves;<br>
Meet me tomorrow in Saint George’s field,<br>
You shall have pay and everything you wish.
</p>

<p class="right">[<i>Exeunt <span class="charname">Soldiers</span>.</i>]</p>

<p class="drama">
And let my sovereign, virtuous Henry,<br>
Command my eldest son, nay, all my sons,<br>
As pledges of my fealty and love,<br>
I’ll send them all as willing as I live.<br>
Lands, goods, horse, armour, anything I have<br>
Is his to use, so Somerset may die.
</p>

<p class="drama">
BUCKINGHAM.<br>
York, I commend this kind submission.<br>
We twain will go into his highness’ tent.
</p>

<p class="scenedesc">Enter <span class="charname">King</span>
and Attendants.</p>

<p class="drama">
KING HENRY.<br>
Buckingham, doth York intend no harm to us<br>
That thus he marcheth with thee arm in arm?
</p>

<p class="drama">
YORK.<br>
In all submission and humility<br>
York doth present himself unto your highness.
</p>

<p class="drama">
KING HENRY.<br>
Then what intends these forces thou dost bring?
</p>

<p class="drama">
YORK.<br>
To heave the traitor Somerset from hence<br>
And fight against that monstrous rebel Cade,<br>
Who since I heard to be discomfited.
</p>

<p class="scenedesc">Enter <span class="charname">Iden</span> with
<span class="charname">Cade’s</span> head.</p>

<p class="drama">
IDEN.<br>
If one so rude and of so mean condition<br>
May pass into the presence of a king,<br>
Lo, I present your grace a traitor’s head,<br>
The head of Cade, whom I in combat slew.
</p>

<p class="drama">
KING HENRY.<br>
The head of Cade! Great God, how just art Thou!<br>
O, let me view his visage, being dead,<br>
That living wrought me such exceeding trouble.<br>
Tell me, my friend, art thou the man that slew him?
</p>

<p class="drama">
IDEN.<br>
I was, an ’t like your majesty.
</p>

<p class="drama">
KING HENRY.<br>
How art thou called? And what is thy degree?
</p>

<p class="drama">
IDEN.<br>
Alexander Iden, that’s my name;<br>
A poor esquire of Kent, that loves his King.
</p>

<p class="drama">
BUCKINGHAM.<br>
So please it you, my lord, ’twere not amiss<br>
He were created knight for his good service.
</p>

<p class="drama">
KING HENRY.<br>
Iden, kneel down. [<i>He kneels</i>.] Rise up a knight.<br>
We give thee for reward a thousand marks,<br>
And will that thou henceforth attend on us.
</p>

<p class="drama">
IDEN.<br>
May Iden live to merit such a bounty,<br>
And never live but true unto his liege!
</p>

<p class="right">[<i>Rises.</i>]</p>

<p class="scenedesc">Enter <span class="charname">Queen</span> and
<span class="charname">Somerset</span>.</p>

<p class="drama">
KING HENRY.<br>
See, Buckingham, Somerset comes with the Queen.<br>
Go, bid her hide him quickly from the Duke.
</p>

<p class="drama">
QUEEN MARGARET.<br>
For thousand Yorks he shall not hide his head,<br>
But boldly stand and front him to his face.
</p>

<p class="drama">
YORK.<br>
How now? Is Somerset at liberty?<br>
Then, York, unloose thy long-imprisoned thoughts,<br>
And let thy tongue be equal with thy heart.<br>
Shall I endure the sight of Somerset?<br>
False king, why hast thou broken faith with me,<br>
Knowing how hardly I can brook abuse?<br>
“King” did I call thee? No, thou art not king,<br>
Not fit to govern and rule multitudes,<br>
Which dar’st not, no, nor canst not rule a traitor.<br>
That head of thine doth not become a crown;<br>
Thy hand is made to grasp a palmer’s staff,<br>
And not to grace an awful princely sceptre.<br>
That gold must round engirt these brows of mine,<br>
Whose smile and frown, like to Achilles’ spear,<br>
Is able with the change to kill and cure.<br>
Here is a hand to hold a sceptre up<br>
And with the same to act controlling laws.<br>
Give place! By heaven, thou shalt rule no more<br>
O’er him whom heaven created for thy ruler.
</p>

<p class="drama">
SOMERSET.<br>
O monstrous traitor! I arrest thee, York,<br>
Of capital treason ’gainst the King and crown.<br>
Obey, audacious traitor, kneel for grace.
</p>

<p class="drama">
YORK.<br>
Wouldst have me kneel? First let me ask of these<br>
If they can brook I bow a knee to man.<br>
Sirrah, call in my sons to be my bail.
</p>

<p class="right">[<i>Exit <span class="charname">Attendant</span>.</i>]</p>

<p class="drama">
I know, ere they will have me go to ward,<br>
They’ll pawn their swords for my enfranchisement.
</p>

<p class="drama">
QUEEN MARGARET.<br>
Call hither Clifford; bid him come amain,<br>
To say if that the bastard boys of York<br>
Shall be the surety for their traitor father.
</p>

<p class="right">[<i>Exit <span class="charname">Buckingham</span>.</i>]</p>

<p class="drama">
YORK.<br>
O blood-bespotted Neapolitan,<br>
Outcast of Naples, England’s bloody scourge!<br>
The sons of York, thy betters in their birth,<br>
Shall be their father’s bail; and bane to those<br>
That for my surety will refuse the boys!
</p>

<p class="scenedesc">Enter <span class="charname">Edward</span> and
<span class="charname">Richard</span>.</p>

<p class="drama">
See where they come; I’ll warrant they’ll make it good.
</p>

<p class="scenedesc">Enter old <span class="charname">Clifford</span> and his
<span class="charname">Son</span>.</p>

<p class="drama">
QUEEN MARGARET.<br>
And here comes Clifford to deny their bail.
</p>

<p class="drama">
CLIFFORD.<br>
Health and all happiness to my lord the King.
</p>

<p class="right">[<i>Rises.</i>]</p>

<p class="drama">
YORK.<br>
I thank thee, Clifford. Say, what news with thee?<br>
Nay, do not fright us with an angry look.<br>
We are thy sovereign, Clifford, kneel again.<br>
For thy mistaking so, we pardon thee.
</p>

<p class="drama">
CLIFFORD.<br>
This is my king, York, I do not mistake;<br>
But thou mistakes me much to think I do.<br>
To Bedlam with him! Is the man grown mad?
</p>

<p class="drama">
KING HENRY.<br>
Ay, Clifford; a bedlam and ambitious humour<br>
Makes him oppose himself against his king.
</p>

<p class="drama">
CLIFFORD.<br>
He is a traitor; let him to the Tower,<br>
And chop away that factious pate of his.
</p>

<p class="drama">
QUEEN MARGARET.<br>
He is arrested, but will not obey;<br>
His sons, he says, shall give their words for him.
</p>

<p class="drama">
YORK.<br>
Will you not, sons?
</p>

<p class="drama">
EDWARD.<br>
Ay, noble father, if our words will serve.
</p>

<p class="drama">
RICHARD.<br>
And if words will not, then our weapons shall.
</p>

<p class="drama">
CLIFFORD.<br>
Why, what a brood of traitors have we here!
</p>

<p class="drama">
YORK.<br>
Look in a glass, and call thy image so.<br>
I am thy king, and thou a false-heart traitor.<br>
Call hither to the stake my two brave bears,<br>
That with the very shaking of their chains<br>
They may astonish these fell-lurking curs.<br>
Bid Salisbury and Warwick come to me.
</p>

<p class="scenedesc">Enter the <span class="charname">Earls of Warwick</span> and
<span class="charname">Salisbury</span>.</p>

<p class="drama">
CLIFFORD.<br>
Are these thy bears? We’ll bait thy bears to death<br>
And manacle the bearherd in their chains,<br>
If thou dar’st bring them to the baiting-place.
</p>

<p class="drama">
RICHARD.<br>
Oft have I seen a hot o’erweening cur<br>
Run back and bite because he was withheld,<br>
Who, being suffered with the bear’s fell paw,<br>
Hath clapped his tail between his legs and cried;<br>
And such a piece of service will you do<br>
If you oppose yourselves to match Lord Warwick.
</p>

<p class="drama">
CLIFFORD.<br>
Hence, heap of wrath, foul indigested lump,<br>
As crooked in thy manners as thy shape!
</p>

<p class="drama">
YORK.<br>
Nay, we shall heat you thoroughly anon.
</p>

<p class="drama">
CLIFFORD.<br>
Take heed, lest by your heat you burn yourselves.
</p>

<p class="drama">
KING HENRY.<br>
Why, Warwick, hath thy knee forgot to bow?<br>
Old Salisbury, shame to thy silver hair,<br>
Thou mad misleader of thy brainsick son!<br>
What, wilt thou on thy deathbed play the ruffian,<br>
And seek for sorrow with thy spectacles?<br>
O, where is faith? O, where is loyalty?<br>
If it be banished from the frosty head,<br>
Where shall it find a harbour in the earth?<br>
Wilt thou go dig a grave to find out war,<br>
And shame thine honourable age with blood?<br>
Why art thou old, and want’st experience?<br>
Or wherefore dost abuse it, if thou hast it?<br>
For shame, in duty bend thy knee to me<br>
That bows unto the grave with mickle age.
</p>

<p class="drama">
SALISBURY.<br>
My lord, I have considered with myself<br>
The title of this most renowned duke,<br>
And in my conscience do repute his grace<br>
The rightful heir to England’s royal seat.
</p>

<p class="drama">
KING HENRY.<br>
Hast thou not sworn allegiance unto me?
</p>

<p class="drama">
SALISBURY.<br>
I have.
</p>

<p class="drama">
KING HENRY.<br>
Canst thou dispense with heaven for such an oath?
</p>

<p class="drama">
SALISBURY.<br>
It is great sin to swear unto a sin,<br>
But greater sin to keep a sinful oath.<br>
Who can be bound by any solemn vow<br>
To do a murderous deed, to rob a man,<br>
To force a spotless virgin’s chastity,<br>
To reave the orphan of his patrimony,<br>
To wring the widow from her customed right,<br>
And have no other reason for this wrong<br>
But that he was bound by a solemn oath?
</p>

<p class="drama">
QUEEN MARGARET.<br>
A subtle traitor needs no sophister.
</p>

<p class="drama">
KING HENRY.<br>
Call Buckingham, and bid him arm himself.
</p>

<p class="drama">
YORK.<br>
Call Buckingham, and all the friends thou hast,<br>
I am resolved for death or dignity.
</p>

<p class="drama">
CLIFFORD.<br>
The first I warrant thee, if dreams prove true.
</p>

<p class="drama">
WARWICK.<br>
You were best to go to bed and dream again,<br>
To keep thee from the tempest of the field.
</p>

<p class="drama">
CLIFFORD.<br>
I am resolved to bear a greater storm<br>
Than any thou canst conjure up today;<br>
And that I’ll write upon thy burgonet,<br>
Might I but know thee by thy household badge.
</p>

<p class="drama">
WARWICK.<br>
Now, by my father’s badge, old Neville’s crest,<br>
The rampant bear chained to the ragged staff,<br>
This day I’ll wear aloft my burgonet,<br>
As on a mountain top the cedar shows<br>
That keeps his leaves in spite of any storm,<br>
Even to affright thee with the view thereof.
</p>

<p class="drama">
CLIFFORD.<br>
And from thy burgonet I’ll rend thy bear<br>
And tread it under foot with all contempt,<br>
Despite the bearherd that protects the bear.
</p>

<p class="drama">
YOUNG CLIFFORD.<br>
And so to arms, victorious father,<br>
To quell the rebels and their complices.
</p>

<p class="drama">
RICHARD.<br>
Fie, charity, for shame! Speak not in spite,<br>
For you shall sup with Jesu Christ tonight.
</p>

<p class="drama">
YOUNG CLIFFORD.<br>
Foul stigmatic, that’s more than thou canst tell.
</p>

<p class="drama">
RICHARD.<br>
If not in heaven, you’ll surely sup in hell.
</p>

<p class="right">[<i>Exeunt severally.</i>]</p>

<h3> <a id="sceneV_13.2"></a><b>SCENE II. Saint Albans</b></h3>

<p class="scenedesc">The sign of the Castle Inn is displayed. Alarums to the
battle. Enter <span class="charname">Warwick</span>.</p>

<p class="drama">
WARWICK.<br>
Clifford of Cumberland, ’tis Warwick calls;<br>
An if thou dost not hide thee from the bear,<br>
Now, when the angry trumpet sounds alarum<br>
And dead men’s cries do fill the empty air,<br>
Clifford, I say, come forth and fight with me!<br>
Proud northern lord, Clifford of Cumberland,<br>
Warwick is hoarse with calling thee to arms.
</p>

<p class="scenedesc">Enter <span class="charname">York</span>.</p>

<p class="drama">
How now, my noble lord? What, all afoot?
</p>

<p class="drama">
YORK.<br>
The deadly-handed Clifford slew my steed,<br>
But match to match I have encountered him<br>
And made a prey for carrion kites and crows<br>
Even of the bonny beast he loved so well.
</p>

<p class="scenedesc">Enter old <span class="charname">Clifford</span>.</p>

<p class="drama">
WARWICK.<br>
Of one or both of us the time is come.
</p>

<p class="drama">
YORK.<br>
Hold, Warwick, seek thee out some other chase,<br>
For I myself must hunt this deer to death.
</p>

<p class="drama">
WARWICK.<br>
Then, nobly, York; ’tis for a crown thou fight’st.<br>
As I intend, Clifford, to thrive today,<br>
It grieves my soul to leave thee unassailed.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
CLIFFORD.<br>
What seest thou in me, York? Why dost thou pause?
</p>

<p class="drama">
YORK.<br>
With thy brave bearing should I be in love,<br>
But that thou art so fast mine enemy.
</p>

<p class="drama">
CLIFFORD.<br>
Nor should thy prowess want praise and esteem,<br>
But that ’tis shown ignobly and in treason.
</p>

<p class="drama">
YORK.<br>
So let it help me now against thy sword<br>
As I in justice and true right express it!
</p>

<p class="drama">
CLIFFORD.<br>
My soul and body on the action both!
</p>

<p class="drama">
YORK.<br>
A dreadful lay! Address thee instantly.
</p>

<p class="right">[<i>They fight and <span class="charname">Clifford</span>
falls.</i>]</p>

<p class="drama">
CLIFFORD.<br>
<i>La fin couronne les oeuvres.</i>
</p>

<p class="right">[<i>Dies.</i>]</p>

<p class="drama">
YORK.<br>
Thus war hath given thee peace, for thou art still.<br>
Peace with his soul, heaven, if it be thy will!
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="scenedesc">Enter young <span class="charname">Clifford</span>.</p>

<p class="drama">
YOUNG CLIFFORD.<br>
Shame and confusion! All is on the rout,<br>
Fear frames disorder, and disorder wounds<br>
Where it should guard. O war, thou son of hell,<br>
Whom angry heavens do make their minister,<br>
Throw in the frozen bosoms of our part<br>
Hot coals of vengeance! Let no soldier fly.<br>
He that is truly dedicate to war<br>
Hath no self-love; nor he that loves himself<br>
Hath not essentially but by circumstance,<br>
The name of valour. [<i>Sees his dead father</i>.] O, let the vile world end<br>
And the premised flames of the last day<br>
Knit earth and heaven together!<br>
Now let the general trumpet blow his blast,<br>
Particularities and petty sounds<br>
To cease! Wast thou ordained, dear father,<br>
To lose thy youth in peace, and to achieve<br>
The silver livery of advised age,<br>
And, in thy reverence and thy chair-days, thus<br>
To die in ruffian battle? Even at this sight<br>
My heart is turned to stone, and while ’tis mine<br>
It shall be stony. York not our old men spares;<br>
No more will I their babes; tears virginal<br>
Shall be to me even as the dew to fire,<br>
And beauty, that the tyrant oft reclaims,<br>
Shall to my flaming wrath be oil and flax.<br>
Henceforth I will not have to do with pity.<br>
Meet I an infant of the house of York,<br>
Into as many gobbets will I cut it<br>
As wild Medea young Absyrtus did.<br>
In cruelty will I seek out my fame.
</p>

<p class="right">[<i>He takes him up on his back.</i>]</p>

<p class="drama">
Come, thou new ruin of old Clifford’s house;<br>
As did Aeneas old Anchises bear,<br>
So bear I thee upon my manly shoulders;<br>
But then Aeneas bare a living load,<br>
Nothing so heavy as these woes of mine.
</p>

<p class="right">[<i>Exit, bearing off his father.</i>]</p>

<p class="scenedesc">Enter <span class="charname">Richard</span> and <span class="charname">Somerset</span> to fight. <span class="charname">Somerset</span> is killed.
</p>

<p class="drama">
RICHARD.<br>
So, lie thou there;<br>
For underneath an alehouse’ paltry sign,<br>
The Castle in Saint Albans, Somerset<br>
Hath made the wizard famous in his death.<br>
Sword, hold thy temper; heart, be wrathful still!<br>
Priests pray for enemies, but princes kill.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="scenedesc">Fight. Excursions. Enter <span class="charname">King, Queen</span>
and others.</p>

<p class="drama">
QUEEN MARGARET.<br>
Away, my lord! You are slow, for shame, away!
</p>

<p class="drama">
KING HENRY.<br>
Can we outrun the heavens? Good Margaret, stay.
</p>

<p class="drama">
QUEEN MARGARET.<br>
What are you made of? You’ll nor fight nor fly.<br>
Now is it manhood, wisdom, and defence<br>
To give the enemy way, and to secure us<br>
By what we can, which can no more but fly.
</p>

<p class="right">[<i>Alarum afar off.</i>]</p>

<p class="drama">
If you be ta’en, we then should see the bottom<br>
Of all our fortunes; but if we haply scape,<br>
As well we may, if not through your neglect,<br>
We shall to London get, where you are loved<br>
And where this breach now in our fortunes made<br>
May readily be stopped.
</p>

<p class="scenedesc">Enter young <span class="charname">Clifford</span>.</p>

<p class="drama">
YOUNG CLIFFORD.<br>
But that my heart’s on future mischief set,<br>
I would speak blasphemy ere bid you fly;<br>
But fly you must; uncurable discomfit<br>
Reigns in the hearts of all our present parts.<br>
Away, for your relief! And we will live<br>
To see their day and them our fortune give.<br>
Away, my lord, away!
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneV_13.3"></a><b>SCENE III. Fields near Saint Albans</b></h3>

<p class="scenedesc">Alarum. Retreat. Enter <span class="charname">York,
Richard, Warwick</span> and Soldiers with drum and colours.</p>

<p class="drama">
YORK.<br>
Of Salisbury, who can report of him,<br>
That winter lion, who in rage forgets<br>
Aged contusions and all brush of time,<br>
And, like a gallant in the brow of youth,<br>
Repairs him with occasion? This happy day<br>
Is not itself, nor have we won one foot,<br>
If Salisbury be lost.
</p>

<p class="drama">
RICHARD.<br>
My noble father,<br>
Three times today I holp him to his horse,<br>
Three times bestrid him; thrice I led him off,<br>
Persuaded him from any further act;<br>
But still, where danger was, still there I met him,<br>
And like rich hangings in a homely house,<br>
So was his will in his old feeble body.<br>
But, noble as he is, look where he comes.
</p>

<p class="scenedesc">Enter <span class="charname">Salisbury</span>.</p>

<p class="drama">
Now, by my sword, well hast thou fought today.
</p>

<p class="drama">
SALISBURY.<br>
By th’ mass, so did we all. I thank you, Richard.<br>
God knows how long it is I have to live,<br>
And it hath pleased him that three times today<br>
You have defended me from imminent death.<br>
Well, lords, we have not got that which we have;<br>
’Tis not enough our foes are this time fled,<br>
Being opposites of such repairing nature.
</p>

<p class="drama">
YORK.<br>
I know our safety is to follow them;<br>
For, as I hear, the King is fled to London<br>
To call a present court of parliament.<br>
Let us pursue him ere the writs go forth.<br>
What says Lord Warwick? Shall we after them?
</p>

<p class="drama">
WARWICK.<br>
After them? Nay, before them, if we can.<br>
Now, by my hand, lords, ’twas a glorious day.<br>
Saint Albans battle won by famous York<br>
Shall be eternized in all age to come.<br>
Sound drums and trumpets, and to London all;<br>
And more such days as these to us befall!
</p>

<p class="right">[<i>Exeunt.</i>]</p>

