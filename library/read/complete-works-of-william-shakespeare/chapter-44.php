<h2> <a id="sceneIII_8.1"></a><b>ACT III</b></h2>

<h3> <b>SCENE I. A room in the Castle.</b></h3>

<p class="scenedesc">
Enter <span class="charname">King, Queen, Polonius, Ophelia, Rosencrantz</span>
and <span class="charname">Guildenstern</span>.
</p>

<p class="drama">
KING.<br>
And can you by no drift of circumstance<br>
Get from him why he puts on this confusion,<br>
Grating so harshly all his days of quiet<br>
With turbulent and dangerous lunacy?<br>
</p>

<p class="drama">
ROSENCRANTZ.<br>
He does confess he feels himself distracted,<br>
But from what cause he will by no means speak.<br>
</p>

<p class="drama">
GUILDENSTERN.<br>
Nor do we find him forward to be sounded,<br>
But with a crafty madness keeps aloof<br>
When we would bring him on to some confession<br>
Of his true state.<br>
</p>

<p class="drama">
QUEEN.<br>
Did he receive you well?<br>
</p>

<p class="drama">
ROSENCRANTZ.<br>
Most like a gentleman.<br>
</p>

<p class="drama">
GUILDENSTERN.<br>
But with much forcing of his disposition.<br>
</p>

<p class="drama">
ROSENCRANTZ.<br>
Niggard of question, but of our demands,<br>
Most free in his reply.<br>
</p>

<p class="drama">
QUEEN.<br>
Did you assay him to any pastime?<br>
</p>

<p class="drama">
ROSENCRANTZ.<br>
Madam, it so fell out that certain players<br>
We o’er-raught on the way. Of these we told him,<br>
And there did seem in him a kind of joy<br>
To hear of it. They are about the court,<br>
And, as I think, they have already order<br>
This night to play before him.<br>
</p>

<p class="drama">
POLONIUS.<br>
’Tis most true;<br>
And he beseech’d me to entreat your Majesties<br>
To hear and see the matter.<br>
</p>

<p class="drama">
KING.<br>
With all my heart; and it doth much content me<br>
To hear him so inclin’d.<br>
Good gentlemen, give him a further edge,<br>
And drive his purpose on to these delights.<br>
</p>

<p class="drama">
ROSENCRANTZ.<br>
We shall, my lord.<br>
</p>

<p class="right">
[<i>Exeunt <span class="charname">Rosencrantz</span> and <span class="charname">Guildenstern</span>.</i>]
</p>

<p class="drama">
KING.<br>
Sweet Gertrude, leave us too,<br>
For we have closely sent for Hamlet hither,<br>
That he, as ’twere by accident, may here<br>
Affront Ophelia.<br>
Her father and myself, lawful espials,<br>
Will so bestow ourselves that, seeing unseen,<br>
We may of their encounter frankly judge,<br>
And gather by him, as he is behav’d,<br>
If’t be th’affliction of his love or no<br>
That thus he suffers for.<br>
</p>

<p class="drama">
QUEEN.<br>
I shall obey you.<br>
And for your part, Ophelia, I do wish<br>
That your good beauties be the happy cause<br>
Of Hamlet’s wildness: so shall I hope your virtues<br>
Will bring him to his wonted way again,<br>
To both your honours.<br>
</p>

<p class="drama">
OPHELIA.<br>
Madam, I wish it may.<br>
</p>

<p class="right">
[<i>Exit <span class="charname">Queen</span>.</i>]
</p>

<p class="drama">
POLONIUS.<br>
Ophelia, walk you here.—Gracious, so please you,<br>
We will bestow ourselves.—[<i>To Ophelia.</i>] Read on this book,<br>
That show of such an exercise may colour<br>
Your loneliness.—We are oft to blame in this,<br>
’Tis too much prov’d, that with devotion’s visage<br>
And pious action we do sugar o’er<br>
The devil himself.<br>
</p>

<p class="drama">
KING.<br>
[<i>Aside.</i>] O ’tis too true!<br>
How smart a lash that speech doth give my conscience!<br>
The harlot’s cheek, beautied with plastering art,<br>
Is not more ugly to the thing that helps it<br>
Than is my deed to my most painted word.<br>
O heavy burden!<br>
</p>

<p class="drama">
POLONIUS.<br>
I hear him coming. Let’s withdraw, my lord.<br>
</p>

<p class="right">
[<i>Exeunt <span class="charname">King</span> and <span class="charname">Polonius</span>.</i>]
</p>

<p class="scenedesc">
Enter <span class="charname">Hamlet</span>.
</p>

<p class="drama">
HAMLET.<br>
To be, or not to be, that is the question:<br>
Whether ’tis nobler in the mind to suffer<br>
The slings and arrows of outrageous fortune,<br>
Or to take arms against a sea of troubles,<br>
And by opposing end them? To die—to sleep,<br>
No more; and by a sleep to say we end<br>
The heart-ache, and the thousand natural shocks<br>
That flesh is heir to: ’tis a consummation<br>
Devoutly to be wish’d. To die, to sleep.<br>
To sleep, perchance to dream—ay, there’s the rub,<br>
For in that sleep of death what dreams may come,<br>
When we have shuffled off this mortal coil,<br>
Must give us pause. There’s the respect<br>
That makes calamity of so long life.<br>
For who would bear the whips and scorns of time,<br>
The oppressor’s wrong, the proud man’s contumely,<br>
The pangs of dispriz’d love, the law’s delay,<br>
The insolence of office, and the spurns<br>
That patient merit of the unworthy takes,<br>
When he himself might his quietus make<br>
With a bare bodkin? Who would these fardels bear,<br>
To grunt and sweat under a weary life,<br>
But that the dread of something after death,<br>
The undiscover’d country, from whose bourn<br>
No traveller returns, puzzles the will,<br>
And makes us rather bear those ills we have<br>
Than fly to others that we know not of?<br>
Thus conscience does make cowards of us all,<br>
And thus the native hue of resolution<br>
Is sicklied o’er with the pale cast of thought,<br>
And enterprises of great pith and moment,<br>
With this regard their currents turn awry<br>
And lose the name of action. Soft you now,<br>
The fair Ophelia! Nymph, in thy orisons<br>
Be all my sins remember’d.<br>
</p>

<p class="drama">
OPHELIA.<br>
Good my lord,<br>
How does your honour for this many a day?<br>
</p>

<p class="drama">
HAMLET.<br>
I humbly thank you; well, well, well.<br>
</p>

<p class="drama">
OPHELIA.<br>
My lord, I have remembrances of yours<br>
That I have longed long to re-deliver.<br>
I pray you, now receive them.<br>
</p>

<p class="drama">
HAMLET.<br>
No, not I.<br>
I never gave you aught.<br>
</p>

<p class="drama">
OPHELIA.<br>
My honour’d lord, you know right well you did,<br>
And with them words of so sweet breath compos’d<br>
As made the things more rich; their perfume lost,<br>
Take these again; for to the noble mind<br>
Rich gifts wax poor when givers prove unkind.<br>
There, my lord.<br>
</p>

<p class="drama">
HAMLET.<br>
Ha, ha! Are you honest?<br>
</p>

<p class="drama">
OPHELIA.<br>
My lord?<br>
</p>

<p class="drama">
HAMLET.<br>
Are you fair?<br>
</p>

<p class="drama">
OPHELIA.<br>
What means your lordship?<br>
</p>

<p class="drama">
HAMLET.<br>
That if you be honest and fair, your honesty should admit no discourse to your
beauty.
</p>

<p class="drama">
OPHELIA.<br>
Could beauty, my lord, have better commerce than with honesty?<br>
</p>

<p class="drama">
HAMLET.<br>
Ay, truly; for the power of beauty will sooner transform honesty from what it
is to a bawd than the force of honesty can translate beauty into his likeness.
This was sometime a paradox, but now the time gives it proof. I did love you
once.
</p>

<p class="drama">
OPHELIA.<br>
Indeed, my lord, you made me believe so.<br>
</p>

<p class="drama">
HAMLET.<br>
You should not have believed me; for virtue cannot so inoculate our old stock
but we shall relish of it. I loved you not.
</p>

<p class="drama">
OPHELIA.<br>
I was the more deceived.<br>
</p>

<p class="drama">
HAMLET.<br>
Get thee to a nunnery. Why wouldst thou be a breeder of sinners? I am myself
indifferent honest; but yet I could accuse me of such things that it were
better my mother had not borne me. I am very proud, revengeful, ambitious, with
more offences at my beck than I have thoughts to put them in, imagination to
give them shape, or time to act them in. What should such fellows as I do
crawling between earth and heaven? We are arrant knaves all, believe none of
us. Go thy ways to a nunnery. Where’s your father?
</p>

<p class="drama">
OPHELIA.<br>
At home, my lord.<br>
</p>

<p class="drama">
HAMLET.<br>
Let the doors be shut upon him, that he may play the fool nowhere but in’s own
house. Farewell.
</p>

<p class="drama">
OPHELIA.<br>
O help him, you sweet heavens!<br>
</p>

<p class="drama">
HAMLET.<br>
If thou dost marry, I’ll give thee this plague for thy dowry. Be thou as chaste
as ice, as pure as snow, thou shalt not escape calumny. Get thee to a nunnery,
go: farewell. Or if thou wilt needs marry, marry a fool; for wise men know well
enough what monsters you make of them. To a nunnery, go; and quickly too.
Farewell.
</p>

<p class="drama">
OPHELIA.<br>
O heavenly powers, restore him!<br>
</p>

<p class="drama">
HAMLET.<br>
I have heard of your paintings too, well enough. God hath given you one face,
and you make yourselves another. You jig, you amble, and you lisp, and nickname
God’s creatures, and make your wantonness your ignorance. Go to, I’ll no more
on’t, it hath made me mad. I say, we will have no more marriages. Those that
are married already, all but one, shall live; the rest shall keep as they are.
To a nunnery, go.
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="drama">
OPHELIA.<br>
O, what a noble mind is here o’erthrown!<br>
The courtier’s, soldier’s, scholar’s, eye, tongue, sword,<br>
Th’expectancy and rose of the fair state,<br>
The glass of fashion and the mould of form,<br>
Th’observ’d of all observers, quite, quite down!<br>
And I, of ladies most deject and wretched,<br>
That suck’d the honey of his music vows,<br>
Now see that noble and most sovereign reason,<br>
Like sweet bells jangled out of tune and harsh,<br>
That unmatch’d form and feature of blown youth<br>
Blasted with ecstasy. O woe is me,<br>
T’have seen what I have seen, see what I see.<br>
</p>

<p class="scenedesc">
Enter <span class="charname">King</span> and <span class="charname">Polonius</span>.
</p>

<p class="drama">
KING.<br>
Love? His affections do not that way tend,<br>
Nor what he spake, though it lack’d form a little,<br>
Was not like madness. There’s something in his soul<br>
O’er which his melancholy sits on brood,<br>
And I do doubt the hatch and the disclose<br>
Will be some danger, which for to prevent,<br>
I have in quick determination<br>
Thus set it down: he shall with speed to England<br>
For the demand of our neglected tribute:<br>
Haply the seas and countries different,<br>
With variable objects, shall expel<br>
This something settled matter in his heart,<br>
Whereon his brains still beating puts him thus<br>
From fashion of himself. What think you on’t?<br>
</p>

<p class="drama">
POLONIUS.<br>
It shall do well. But yet do I believe<br>
The origin and commencement of his grief<br>
Sprung from neglected love. How now, Ophelia?<br>
You need not tell us what Lord Hamlet said,<br>
We heard it all. My lord, do as you please,<br>
But if you hold it fit, after the play,<br>
Let his queen mother all alone entreat him<br>
To show his grief, let her be round with him,<br>
And I’ll be plac’d, so please you, in the ear<br>
Of all their conference. If she find him not,<br>
To England send him; or confine him where<br>
Your wisdom best shall think.<br>
</p>

<p class="drama">
KING.<br>
It shall be so.<br>
Madness in great ones must not unwatch’d go.<br>
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3><a id="sceneIII_8.2"></a> <b>SCENE II. A hall in the
Castle.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Hamlet</span> and certain <span class="charname">Players</span>.
</p>

<p class="drama">
HAMLET.<br>
Speak the speech, I pray you, as I pronounced it to you, trippingly on the
tongue. But if you mouth it, as many of your players do, I had as lief the
town-crier spoke my lines. Nor do not saw the air too much with your hand,
thus, but use all gently; for in the very torrent, tempest, and, as I may say,
whirlwind of passion, you must acquire and beget a temperance that may give it
smoothness. O, it offends me to the soul to hear a robustious periwig-pated
fellow tear a passion to tatters, to very rags, to split the ears of the
groundlings, who, for the most part, are capable of nothing but inexplicable
dumb shows and noise. I would have such a fellow whipped for o’erdoing
Termagant. It out-Herods Herod. Pray you avoid it.
</p>

<p class="drama">
FIRST PLAYER.<br>
I warrant your honour.<br>
</p>

<p class="drama">
HAMLET.<br>
Be not too tame neither; but let your own discretion be your tutor. Suit the
action to the word, the word to the action, with this special observance, that
you o’erstep not the modesty of nature; for anything so overdone is from the
purpose of playing, whose end, both at the first and now, was and is, to hold
as ’twere the mirror up to nature; to show virtue her own feature, scorn her
own image, and the very age and body of the time his form and pressure. Now,
this overdone, or come tardy off, though it make the unskilful laugh, cannot
but make the judicious grieve; the censure of the which one must in your
allowance o’erweigh a whole theatre of others. O, there be players that I have
seen play—and heard others praise, and that highly—not to speak it profanely,
that, neither having the accent of Christians, nor the gait of Christian,
pagan, nor man, have so strutted and bellowed that I have thought some of
Nature’s journeymen had made men, and not made them well, they imitated
humanity so abominably.
</p>

<p class="drama">
FIRST PLAYER.<br>
I hope we have reform’d that indifferently with us, sir.<br>
</p>

<p class="drama">
HAMLET.<br>
O reform it altogether. And let those that play your clowns speak no more than
is set down for them. For there be of them that will themselves laugh, to set
on some quantity of barren spectators to laugh too, though in the meantime some
necessary question of the play be then to be considered. That’s villainous, and
shows a most pitiful ambition in the fool that uses it. Go make you ready.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Players</span>.</i>]
</p>

<p class="scenedesc">
Enter <span class="charname">Polonius, Rosencrantz</span> and <span class="charname">Guildenstern</span>.
</p>

<p class="drama">
How now, my lord?<br>
Will the King hear this piece of work?
</p>

<p class="drama">
POLONIUS.<br>
And the Queen too, and that presently.<br>
</p>

<p class="drama">
HAMLET.<br>
Bid the players make haste.<br>
</p>

<p class="right">
[<i>Exit <span class="charname">Polonius</span>.</i>]
</p>

<p class="drama">
Will you two help to hasten them?
</p>

<p class="drama">
ROSENCRANTZ and GUILDENSTERN.<br>
We will, my lord.<br>
</p>

<p class="right">
[<i>Exeunt <span class="charname">Rosencrantz</span> and <span class="charname">Guildenstern</span>.</i>]
</p>

<p class="drama">
HAMLET.<br>
What ho, Horatio!<br>
</p>

<p class="scenedesc">
Enter <span class="charname">Horatio</span>.
</p>

<p class="drama">
HORATIO.<br>
Here, sweet lord, at your service.<br>
</p>

<p class="drama">
HAMLET.<br>
Horatio, thou art e’en as just a man<br>
As e’er my conversation cop’d withal.<br>
</p>

<p class="drama">
HORATIO.<br>
O my dear lord.<br>
</p>

<p class="drama">
HAMLET.<br>
Nay, do not think I flatter;<br>
For what advancement may I hope from thee,<br>
That no revenue hast, but thy good spirits<br>
To feed and clothe thee? Why should the poor be flatter’d?<br>
No, let the candied tongue lick absurd pomp,<br>
And crook the pregnant hinges of the knee<br>
Where thrift may follow fawning. Dost thou hear?<br>
Since my dear soul was mistress of her choice,<br>
And could of men distinguish, her election<br>
Hath seal’d thee for herself. For thou hast been<br>
As one, in suffering all, that suffers nothing,<br>
A man that Fortune’s buffets and rewards<br>
Hast ta’en with equal thanks. And blessed are those<br>
Whose blood and judgement are so well co-mingled<br>
That they are not a pipe for Fortune’s finger<br>
To sound what stop she please. Give me that man<br>
That is not passion’s slave, and I will wear him<br>
In my heart’s core, ay, in my heart of heart,<br>
As I do thee. Something too much of this.<br>
There is a play tonight before the King.<br>
One scene of it comes near the circumstance<br>
Which I have told thee, of my father’s death.<br>
I prithee, when thou see’st that act a-foot,<br>
Even with the very comment of thy soul<br>
Observe mine uncle. If his occulted guilt<br>
Do not itself unkennel in one speech,<br>
It is a damned ghost that we have seen;<br>
And my imaginations are as foul<br>
As Vulcan’s stithy. Give him heedful note;<br>
For I mine eyes will rivet to his face;<br>
And after we will both our judgements join<br>
In censure of his seeming.<br>
</p>

<p class="drama">
HORATIO.<br>
Well, my lord.<br>
If he steal aught the whilst this play is playing,<br>
And ’scape detecting, I will pay the theft.<br>
</p>

<p class="drama">
HAMLET.<br>
They are coming to the play. I must be idle.<br>
Get you a place.<br>
</p>

<p class="scenedesc">
Danish march. A flourish. Enter <span class="charname">King, Queen, Polonius,
Ophelia, Rosencrantz, Guildenstern</span> and others.
</p>

<p class="drama">
KING.<br>
How fares our cousin Hamlet?<br>
</p>

<p class="drama">
HAMLET.<br>
Excellent, i’ faith; of the chameleon’s dish: I eat the air, promise-crammed:
you cannot feed capons so.
</p>

<p class="drama">
KING.<br>
I have nothing with this answer, Hamlet; these words are not mine.
</p>

<p class="drama">
HAMLET.<br>
No, nor mine now. [<i>To Polonius.</i>] My lord, you play’d once i’
th’university, you say?
</p>

<p class="drama">
POLONIUS.<br>
That did I, my lord, and was accounted a good actor.<br>
</p>

<p class="drama">
HAMLET.<br>
What did you enact?<br>
</p>

<p class="drama">
POLONIUS.<br>
I did enact Julius Caesar. I was kill’d i’ th’ Capitol. Brutus killed me.
</p>

<p class="drama">
HAMLET.<br>
It was a brute part of him to kill so capital a calf there. Be the players
ready?
</p>

<p class="drama">
ROSENCRANTZ.<br>
Ay, my lord; they stay upon your patience.<br>
</p>

<p class="drama">
QUEEN.<br>
Come hither, my dear Hamlet, sit by me.<br>
</p>

<p class="drama">
HAMLET.<br>
No, good mother, here’s metal more attractive.<br>
</p>

<p class="drama">
POLONIUS.<br>
[<i>To the King.</i>] O ho! do you mark that?<br>
</p>

<p class="drama">
HAMLET.<br>
Lady, shall I lie in your lap?<br>
</p>

<p class="right">
[<i>Lying down at <span class="charname">Ophelia’s</span> feet.</i>]
</p>

<p class="drama">
OPHELIA.<br>
No, my lord.<br>
</p>

<p class="drama">
HAMLET.<br>
I mean, my head upon your lap?<br>
</p>

<p class="drama">
OPHELIA.<br>
Ay, my lord.<br>
</p>

<p class="drama">
HAMLET.<br>
Do you think I meant country matters?<br>
</p>

<p class="drama">
OPHELIA.<br>
I think nothing, my lord.<br>
</p>

<p class="drama">
HAMLET.<br>
That’s a fair thought to lie between maids’ legs.<br>
</p>

<p class="drama">
OPHELIA.<br>
What is, my lord?<br>
</p>

<p class="drama">
HAMLET.<br>
Nothing.<br>
</p>

<p class="drama">
OPHELIA.<br>
You are merry, my lord.<br>
</p>

<p class="drama">
HAMLET.<br>
Who, I?<br>
</p>

<p class="drama">
OPHELIA.<br>
Ay, my lord.<br>
</p>

<p class="drama">
HAMLET.<br>
O God, your only jig-maker! What should a man do but be merry? For look you how
cheerfully my mother looks, and my father died within’s two hours.
</p>

<p class="drama">
OPHELIA.<br>
Nay, ’tis twice two months, my lord.<br>
</p>

<p class="drama">
HAMLET.<br>
So long? Nay then, let the devil wear black, for I’ll have a suit of sables. O
heavens! die two months ago, and not forgotten yet? Then there’s hope a great
man’s memory may outlive his life half a year. But by’r lady, he must build
churches then; or else shall he suffer not thinking on, with the hobby-horse,
whose epitaph is ‘For, O, for O, the hobby-horse is forgot!’
</p>

<p class="scenedesc">
Trumpets sound. The dumb show enters.
</p>

<p class="drama">
<i>Enter a King and a Queen very lovingly; the Queen embracing him and he her.
She kneels, and makes show of protestation unto him. He takes her up, and
declines his head upon her neck. Lays him down upon a bank of flowers. She,
seeing him asleep, leaves him. Anon comes in a fellow, takes off his crown,
kisses it, pours poison in the King’s ears, and exits. The Queen returns, finds
the King dead, and makes passionate action. The Poisoner with some three or
four Mutes, comes in again, seeming to lament with her. The dead body is
carried away. The Poisoner woos the Queen with gifts. She seems loth and
unwilling awhile, but in the end accepts his love.</i>
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<p class="drama">
OPHELIA.<br>
What means this, my lord?<br>
</p>

<p class="drama">
HAMLET.<br>
Marry, this is miching mallecho; it means mischief.<br>
</p>

<p class="drama">
OPHELIA.<br>
Belike this show imports the argument of the play.<br>
</p>

<p class="scenedesc">
Enter <span class="charname">Prologue</span>.
</p>

<p class="drama">
HAMLET.<br>
We shall know by this fellow: the players cannot keep counsel; they’ll tell
all.
</p>

<p class="drama">
OPHELIA.<br>
Will they tell us what this show meant?<br>
</p>

<p class="drama">
HAMLET.<br>
Ay, or any show that you’ll show him. Be not you ashamed to show, he’ll not
shame to tell you what it means.
</p>

<p class="drama">
OPHELIA.<br>
You are naught, you are naught: I’ll mark the play.<br>
</p>

<p class="drama">
PROLOGUE.<br>
   <i>For us, and for our tragedy,<br>
   Here stooping to your clemency,<br>
   We beg your hearing patiently.</i><br>
</p>

<p class="drama">
HAMLET.<br>
Is this a prologue, or the posy of a ring?<br>
</p>

<p class="drama">
OPHELIA.<br>
’Tis brief, my lord.<br>
</p>

<p class="drama">
HAMLET.<br>
As woman’s love.<br>
</p>

<p class="scenedesc">
Enter a <span class="charname">King</span> and a <span class="charname">Queen</span>.
</p>

<p class="drama">
PLAYER KING.<br>
Full thirty times hath Phoebus’ cart gone round<br>
Neptune’s salt wash and Tellus’ orbed ground,<br>
And thirty dozen moons with borrow’d sheen<br>
About the world have times twelve thirties been,<br>
Since love our hearts, and Hymen did our hands<br>
Unite commutual in most sacred bands.<br>
</p>

<p class="drama">
PLAYER QUEEN.<br>
So many journeys may the sun and moon<br>
Make us again count o’er ere love be done.<br>
But, woe is me, you are so sick of late,<br>
So far from cheer and from your former state,<br>
That I distrust you. Yet, though I distrust,<br>
Discomfort you, my lord, it nothing must:<br>
For women’s fear and love holds quantity,<br>
In neither aught, or in extremity.<br>
Now what my love is, proof hath made you know,<br>
And as my love is siz’d, my fear is so.<br>
Where love is great, the littlest doubts are fear;<br>
Where little fears grow great, great love grows there.<br>
</p>

<p class="drama">
PLAYER KING.<br>
Faith, I must leave thee, love, and shortly too:<br>
My operant powers their functions leave to do:<br>
And thou shalt live in this fair world behind,<br>
Honour’d, belov’d, and haply one as kind<br>
For husband shalt thou—<br>
</p>

<p class="drama">
PLAYER QUEEN.<br>
O confound the rest.<br>
Such love must needs be treason in my breast.<br>
In second husband let me be accurst!<br>
None wed the second but who kill’d the first.<br>
</p>

<p class="drama">
HAMLET.<br>
[<i>Aside.</i>] Wormwood, wormwood.<br>
</p>

<p class="drama">
PLAYER QUEEN.<br>
The instances that second marriage move<br>
Are base respects of thrift, but none of love.<br>
A second time I kill my husband dead,<br>
When second husband kisses me in bed.<br>
</p>

<p class="drama">
PLAYER KING.<br>
I do believe you think what now you speak;<br>
But what we do determine, oft we break.<br>
Purpose is but the slave to memory,<br>
Of violent birth, but poor validity:<br>
Which now, like fruit unripe, sticks on the tree,<br>
But fall unshaken when they mellow be.<br>
Most necessary ’tis that we forget<br>
To pay ourselves what to ourselves is debt.<br>
What to ourselves in passion we propose,<br>
The passion ending, doth the purpose lose.<br>
The violence of either grief or joy<br>
Their own enactures with themselves destroy.<br>
Where joy most revels, grief doth most lament;<br>
Grief joys, joy grieves, on slender accident.<br>
This world is not for aye; nor ’tis not strange<br>
That even our loves should with our fortunes change,<br>
For ’tis a question left us yet to prove,<br>
Whether love lead fortune, or else fortune love.<br>
The great man down, you mark his favourite flies,<br>
The poor advanc’d makes friends of enemies;<br>
And hitherto doth love on fortune tend:<br>
For who not needs shall never lack a friend,<br>
And who in want a hollow friend doth try,<br>
Directly seasons him his enemy.<br>
But orderly to end where I begun,<br>
Our wills and fates do so contrary run<br>
That our devices still are overthrown.<br>
Our thoughts are ours, their ends none of our own.<br>
So think thou wilt no second husband wed,<br>
But die thy thoughts when thy first lord is dead.<br>
</p>

<p class="drama">
PLAYER QUEEN.<br>
Nor earth to me give food, nor heaven light,<br>
Sport and repose lock from me day and night,<br>
To desperation turn my trust and hope,<br>
An anchor’s cheer in prison be my scope,<br>
Each opposite that blanks the face of joy,<br>
Meet what I would have well, and it destroy!<br>
Both here and hence pursue me lasting strife,<br>
If, once a widow, ever I be wife.<br>
</p>

<p class="drama">
HAMLET.<br>
[<i>To Ophelia.</i>] If she should break it now.<br>
</p>

<p class="drama">
PLAYER KING.<br>
’Tis deeply sworn. Sweet, leave me here awhile.<br>
My spirits grow dull, and fain I would beguile<br>
The tedious day with sleep.<br>
[<i>Sleeps.</i>]<br>
</p>

<p class="drama">
PLAYER QUEEN.<br>
Sleep rock thy brain,<br>
And never come mischance between us twain.<br>
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="drama">
HAMLET.<br>
Madam, how like you this play?<br>
</p>

<p class="drama">
QUEEN.<br>
The lady protests too much, methinks.<br>
</p>

<p class="drama">
HAMLET.<br>
O, but she’ll keep her word.<br>
</p>

<p class="drama">
KING.<br>
Have you heard the argument? Is there no offence in’t?<br>
</p>

<p class="drama">
HAMLET.<br>
No, no, they do but jest, poison in jest; no offence i’ th’ world.
</p>

<p class="drama">
KING.<br>
What do you call the play?<br>
</p>

<p class="drama">
HAMLET.<br>
<i>The Mousetrap.</i> Marry, how? Tropically. This play is the image of a
murder done in Vienna. Gonzago is the Duke’s name, his wife Baptista: you shall
see anon; ’tis a knavish piece of work: but what o’ that? Your majesty, and we
that have free souls, it touches us not. Let the gall’d jade wince; our withers
are unwrung.
</p>

<p class="scenedesc">
Enter <span class="charname">Lucianus</span>.
</p>

<p class="drama">
This is one Lucianus, nephew to the King.
</p>

<p class="drama">
OPHELIA.<br>
You are a good chorus, my lord.<br>
</p>

<p class="drama">
HAMLET.<br>
I could interpret between you and your love, if I could see the puppets
dallying.
</p>

<p class="drama">
OPHELIA.<br>
You are keen, my lord, you are keen.<br>
</p>

<p class="drama">
HAMLET.<br>
It would cost you a groaning to take off my edge.<br>
</p>

<p class="drama">
OPHELIA.<br>
Still better, and worse.<br>
</p>

<p class="drama">
HAMLET.<br>
So you mistake your husbands.—Begin, murderer. Pox, leave thy damnable faces,
and begin. Come, the croaking raven doth bellow for revenge.
</p>

<p class="drama">
LUCIANUS.<br>
Thoughts black, hands apt, drugs fit, and time agreeing,<br>
Confederate season, else no creature seeing;<br>
Thou mixture rank, of midnight weeds collected,<br>
With Hecate’s ban thrice blasted, thrice infected,<br>
Thy natural magic and dire property<br>
On wholesome life usurp immediately.<br>
</p>

<p class="right">
[<i>Pours the poison into the sleeper’s ears.</i>]
</p>

<p class="drama">
HAMLET.<br>
He poisons him i’ th’garden for’s estate. His name’s Gonzago. The story is
extant, and written in very choice Italian. You shall see anon how the murderer
gets the love of Gonzago’s wife.
</p>

<p class="drama">
OPHELIA.<br>
The King rises.<br>
</p>

<p class="drama">
HAMLET.<br>
What, frighted with false fire?<br>
</p>

<p class="drama">
QUEEN.<br>
How fares my lord?<br>
</p>

<p class="drama">
POLONIUS.<br>
Give o’er the play.<br>
</p>

<p class="drama">
KING.<br>
Give me some light. Away.<br>
</p>

<p class="drama">
All.<br>
Lights, lights, lights.<br>
</p>

<p class="right">
[<i>Exeunt all but <span class="charname">Hamlet</span> and <span class="charname">Horatio</span>.</i>]
</p>

<p class="drama">
HAMLET.<br>
   Why, let the strucken deer go weep,<br>
     The hart ungalled play;<br>
   For some must watch, while some must sleep,<br>
     So runs the world away.<br>
Would not this, sir, and a forest of feathers, if the rest of my fortunes turn
Turk with me; with two Provincial roses on my razed shoes, get me a fellowship
in a cry of players, sir?
</p>

<p class="drama">
HORATIO.<br>
Half a share.<br>
</p>

<p class="drama">
HAMLET.<br>
A whole one, I.<br>
   For thou dost know, O Damon dear,<br>
     This realm dismantled was<br>
   Of Jove himself, and now reigns here<br>
     A very, very—pajock.<br>
</p>

<p class="drama">
HORATIO.<br>
You might have rhymed.<br>
</p>

<p class="drama">
HAMLET.<br>
O good Horatio, I’ll take the ghost’s word for a thousand pound. Didst
perceive?
</p>

<p class="drama">
HORATIO.<br>
Very well, my lord.<br>
</p>

<p class="drama">
HAMLET.<br>
Upon the talk of the poisoning?<br>
</p>

<p class="drama">
HORATIO.<br>
I did very well note him.<br>
</p>

<p class="drama">
HAMLET.<br>
Ah, ha! Come, some music. Come, the recorders.<br>
   For if the king like not the comedy,<br>
   Why then, belike he likes it not, perdie.<br>
Come, some music.<br>
</p>

<p class="scenedesc">
Enter <span class="charname">Rosencrantz</span> and <span class="charname">Guildenstern</span>.
</p>

<p class="drama">
GUILDENSTERN.<br>
Good my lord, vouchsafe me a word with you.<br>
</p>

<p class="drama">
HAMLET.<br>
Sir, a whole history.<br>
</p>

<p class="drama">
GUILDENSTERN.<br>
The King, sir—<br>
</p>

<p class="drama">
HAMLET.<br>
Ay, sir, what of him?<br>
</p>

<p class="drama">
GUILDENSTERN.<br>
Is in his retirement, marvellous distempered.<br>
</p>

<p class="drama">
HAMLET.<br>
With drink, sir?<br>
</p>

<p class="drama">
GUILDENSTERN.<br>
No, my lord; rather with choler.<br>
</p>

<p class="drama">
HAMLET.<br>
Your wisdom should show itself more richer to signify this to the doctor, for
me to put him to his purgation would perhaps plunge him into far more choler.
</p>

<p class="drama">
GUILDENSTERN.<br>
Good my lord, put your discourse into some frame, and start not so wildly from
my affair.
</p>

<p class="drama">
HAMLET.<br>
I am tame, sir, pronounce.<br>
</p>

<p class="drama">
GUILDENSTERN.<br>
The Queen your mother, in most great affliction of spirit, hath sent me to you.
</p>

<p class="drama">
HAMLET.<br>
You are welcome.<br>
</p>

<p class="drama">
GUILDENSTERN.<br>
Nay, good my lord, this courtesy is not of the right breed. If it shall please
you to make me a wholesome answer, I will do your mother’s commandment; if not,
your pardon and my return shall be the end of my business.
</p>

<p class="drama">
HAMLET.<br>
Sir, I cannot.<br>
</p>

<p class="drama">
GUILDENSTERN.<br>
What, my lord?<br>
</p>

<p class="drama">
HAMLET.<br>
Make you a wholesome answer. My wit’s diseased. But, sir, such answer as I can
make, you shall command; or rather, as you say, my mother. Therefore no more,
but to the matter. My mother, you say,—
</p>

<p class="drama">
ROSENCRANTZ.<br>
Then thus she says: your behaviour hath struck her into amazement and
admiration.
</p>

<p class="drama">
HAMLET.<br>
O wonderful son, that can so stonish a mother! But is there no sequel at the
heels of this mother’s admiration?
</p>

<p class="drama">
ROSENCRANTZ.<br>
She desires to speak with you in her closet ere you go to bed.<br>
</p>

<p class="drama">
HAMLET.<br>
We shall obey, were she ten times our mother. Have you any further trade with
us?
</p>

<p class="drama">
ROSENCRANTZ.<br>
My lord, you once did love me.<br>
</p>

<p class="drama">
HAMLET.<br>
And so I do still, by these pickers and stealers.<br>
</p>

<p class="drama">
ROSENCRANTZ.<br>
Good my lord, what is your cause of distemper? You do surely bar the door upon
your own liberty if you deny your griefs to your friend.
</p>

<p class="drama">
HAMLET.<br>
Sir, I lack advancement.<br>
</p>

<p class="drama">
ROSENCRANTZ.<br>
How can that be, when you have the voice of the King himself for your
succession in Denmark?
</p>

<p class="drama">
HAMLET.<br>
Ay, sir, but while the grass grows—the proverb is something musty.
</p>

<p class="scenedesc">
Re-enter the <span class="charname">Players</span> with recorders.
</p>

<p class="drama">
O, the recorders. Let me see one.—To withdraw with you, why do you go about to
recover the wind of me, as if you would drive me into a toil?
</p>

<p class="drama">
GUILDENSTERN.<br>
O my lord, if my duty be too bold, my love is too unmannerly.<br>
</p>

<p class="drama">
HAMLET.<br>
I do not well understand that. Will you play upon this pipe?<br>
</p>

<p class="drama">
GUILDENSTERN.<br>
My lord, I cannot.<br>
</p>

<p class="drama">
HAMLET.<br>
I pray you.<br>
</p>

<p class="drama">
GUILDENSTERN.<br>
Believe me, I cannot.<br>
</p>

<p class="drama">
HAMLET.<br>
I do beseech you.<br>
</p>

<p class="drama">
GUILDENSTERN.<br>
I know no touch of it, my lord.<br>
</p>

<p class="drama">
HAMLET.<br>
’Tis as easy as lying: govern these ventages with your finger and thumb, give
it breath with your mouth, and it will discourse most eloquent music. Look you,
these are the stops.
</p>

<p class="drama">
GUILDENSTERN.<br>
But these cannot I command to any utterance of harmony. I have not the skill.
</p>

<p class="drama">
HAMLET.<br>
Why, look you now, how unworthy a thing you make of me! You would play upon me;
you would seem to know my stops; you would pluck out the heart of my mystery;
you would sound me from my lowest note to the top of my compass; and there is
much music, excellent voice, in this little organ, yet cannot you make it
speak. ’Sblood, do you think I am easier to be played on than a pipe? Call me
what instrument you will, though you can fret me, you cannot play upon me.
</p>

<p class="scenedesc">
Enter <span class="charname">Polonius</span>.
</p>

<p class="drama">
God bless you, sir.
</p>

<p class="drama">
POLONIUS.<br>
My lord, the Queen would speak with you, and presently.<br>
</p>

<p class="drama">
HAMLET.<br>
Do you see yonder cloud that’s almost in shape of a camel?<br>
</p>

<p class="drama">
POLONIUS.<br>
By the mass, and ’tis like a camel indeed.<br>
</p>

<p class="drama">
HAMLET.<br>
Methinks it is like a weasel.<br>
</p>

<p class="drama">
POLONIUS.<br>
It is backed like a weasel.<br>
</p>

<p class="drama">
HAMLET.<br>
Or like a whale.<br>
</p>

<p class="drama">
POLONIUS.<br>
Very like a whale.<br>
</p>

<p class="drama">
HAMLET.<br>
Then will I come to my mother by and by.—They fool me to the top of my bent.—I
will come by and by.
</p>

<p class="drama">
POLONIUS.<br>
I will say so.<br>
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="drama">
HAMLET.<br>
By and by is easily said. Leave me, friends.
</p>

<p class="right">
[<i>Exeunt all but <span class="charname">Hamlet</span>.</i>]
</p>

<p class="drama">
’Tis now the very witching time of night,<br>
When churchyards yawn, and hell itself breathes out<br>
Contagion to this world. Now could I drink hot blood,<br>
And do such bitter business as the day<br>
Would quake to look on. Soft now, to my mother.<br>
O heart, lose not thy nature; let not ever<br>
The soul of Nero enter this firm bosom:<br>
Let me be cruel, not unnatural.<br>
I will speak daggers to her, but use none;<br>
My tongue and soul in this be hypocrites.<br>
How in my words somever she be shent,<br>
To give them seals never, my soul, consent.<br>
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<h3><a id="sceneIII_8.3"></a> <b>SCENE III. A room in the
Castle.</b></h3>

<p class="scenedesc">
Enter <span class="charname">King, Rosencrantz</span> and <span class="charname">Guildenstern</span>.
</p>

<p class="drama">
KING.<br>
I like him not, nor stands it safe with us<br>
To let his madness range. Therefore prepare you,<br>
I your commission will forthwith dispatch,<br>
And he to England shall along with you.<br>
The terms of our estate may not endure<br>
Hazard so near us as doth hourly grow<br>
Out of his lunacies.<br>
</p>

<p class="drama">
GUILDENSTERN.<br>
We will ourselves provide.<br>
Most holy and religious fear it is<br>
To keep those many many bodies safe<br>
That live and feed upon your Majesty.<br>
</p>

<p class="drama">
ROSENCRANTZ.<br>
The single and peculiar life is bound<br>
With all the strength and armour of the mind,<br>
To keep itself from ’noyance; but much more<br>
That spirit upon whose weal depend and rest<br>
The lives of many. The cease of majesty<br>
Dies not alone; but like a gulf doth draw<br>
What’s near it with it. It is a massy wheel<br>
Fix’d on the summit of the highest mount,<br>
To whose huge spokes ten thousand lesser things<br>
Are mortis’d and adjoin’d; which when it falls,<br>
Each small annexment, petty consequence,<br>
Attends the boist’rous ruin. Never alone<br>
Did the King sigh, but with a general groan.<br>
</p>

<p class="drama">
KING.<br>
Arm you, I pray you, to this speedy voyage;<br>
For we will fetters put upon this fear,<br>
Which now goes too free-footed.<br>
</p>

<p class="drama">
ROSENCRANTZ and GUILDENSTERN.<br>
We will haste us.<br>
</p>

<p class="right">
[<i>Exeunt <span class="charname">Rosencrantz</span> and <span class="charname">Guildenstern</span>.</i>]
</p>

<p class="scenedesc">
Enter <span class="charname">Polonius</span>.
</p>

<p class="drama">
POLONIUS.<br>
My lord, he’s going to his mother’s closet.<br>
Behind the arras I’ll convey myself<br>
To hear the process. I’ll warrant she’ll tax him home,<br>
And as you said, and wisely was it said,<br>
’Tis meet that some more audience than a mother,<br>
Since nature makes them partial, should o’erhear<br>
The speech of vantage. Fare you well, my liege,<br>
I’ll call upon you ere you go to bed,<br>
And tell you what I know.<br>
</p>

<p class="drama">
KING.<br>
Thanks, dear my lord.<br>
</p>

<p class="right">
[<i>Exit <span class="charname">Polonius</span>.</i>]
</p>

<p class="drama">
O, my offence is rank, it smells to heaven;<br>
It hath the primal eldest curse upon’t,—<br>
A brother’s murder! Pray can I not,<br>
Though inclination be as sharp as will:<br>
My stronger guilt defeats my strong intent,<br>
And, like a man to double business bound,<br>
I stand in pause where I shall first begin,<br>
And both neglect. What if this cursed hand<br>
Were thicker than itself with brother’s blood,<br>
Is there not rain enough in the sweet heavens<br>
To wash it white as snow? Whereto serves mercy<br>
But to confront the visage of offence?<br>
And what’s in prayer but this twofold force,<br>
To be forestalled ere we come to fall,<br>
Or pardon’d being down? Then I’ll look up.<br>
My fault is past. But O, what form of prayer<br>
Can serve my turn? Forgive me my foul murder!<br>
That cannot be; since I am still possess’d<br>
Of those effects for which I did the murder,—<br>
My crown, mine own ambition, and my queen.<br>
May one be pardon’d and retain th’offence?<br>
In the corrupted currents of this world<br>
Offence’s gilded hand may shove by justice,<br>
And oft ’tis seen the wicked prize itself<br>
Buys out the law. But ’tis not so above;<br>
There is no shuffling, there the action lies<br>
In his true nature, and we ourselves compell’d<br>
Even to the teeth and forehead of our faults,<br>
To give in evidence. What then? What rests?<br>
Try what repentance can. What can it not?<br>
Yet what can it, when one cannot repent?<br>
O wretched state! O bosom black as death!<br>
O limed soul, that struggling to be free,<br>
Art more engag’d! Help, angels! Make assay:<br>
Bow, stubborn knees; and heart with strings of steel,<br>
Be soft as sinews of the new-born babe.<br>
All may be well.<br>
</p>

<p class="right">
[<i>Retires and kneels.</i>]
</p>

<p class="scenedesc">
Enter <span class="charname">Hamlet</span>.
</p>

<p class="drama">
HAMLET.<br>
Now might I do it pat, now he is praying.<br>
And now I’ll do’t. And so he goes to heaven;<br>
And so am I reveng’d. That would be scann’d:<br>
A villain kills my father, and for that<br>
I, his sole son, do this same villain send<br>
To heaven. O, this is hire and salary, not revenge.<br>
He took my father grossly, full of bread,<br>
With all his crimes broad blown, as flush as May;<br>
And how his audit stands, who knows save heaven?<br>
But in our circumstance and course of thought,<br>
’Tis heavy with him. And am I then reveng’d,<br>
To take him in the purging of his soul,<br>
When he is fit and season’d for his passage? No.<br>
Up, sword, and know thou a more horrid hent:<br>
When he is drunk asleep; or in his rage,<br>
Or in th’incestuous pleasure of his bed,<br>
At gaming, swearing; or about some act<br>
That has no relish of salvation in’t,<br>
Then trip him, that his heels may kick at heaven,<br>
And that his soul may be as damn’d and black<br>
As hell, whereto it goes. My mother stays.<br>
This physic but prolongs thy sickly days.<br>
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="scenedesc">
The <span class="charname">King</span> rises and advances.
</p>

<p class="drama">
KING.<br>
My words fly up, my thoughts remain below.<br>
Words without thoughts never to heaven go.<br>
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<h3><a id="sceneIII_8.4"></a> <b>SCENE IV. Another room in
the Castle.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Queen</span> and <span class="charname">Polonius</span>.
</p>

<p class="drama">
POLONIUS.<br>
He will come straight. Look you lay home to him,<br>
Tell him his pranks have been too broad to bear with,<br>
And that your Grace hath screen’d and stood between<br>
Much heat and him. I’ll silence me e’en here.<br>
Pray you be round with him.<br>
</p>

<p class="drama">
HAMLET.<br>
[<i>Within.</i>] Mother, mother, mother.<br>
</p>

<p class="drama">
QUEEN.<br>
I’ll warrant you, Fear me not.<br>
Withdraw, I hear him coming.
</p>

<p class="right">
[<i><span class="charname">Polonius</span> goes behind the arras.</i>]
</p>

<p class="scenedesc">
Enter <span class="charname">Hamlet</span>.
</p>

<p class="drama">
HAMLET.<br>
Now, mother, what’s the matter?<br>
</p>

<p class="drama">
QUEEN.<br>
Hamlet, thou hast thy father much offended.<br>
</p>

<p class="drama">
HAMLET.<br>
Mother, you have my father much offended.<br>
</p>

<p class="drama">
QUEEN.<br>
Come, come, you answer with an idle tongue.<br>
</p>

<p class="drama">
HAMLET.<br>
Go, go, you question with a wicked tongue.<br>
</p>

<p class="drama">
QUEEN.<br>
Why, how now, Hamlet?<br>
</p>

<p class="drama">
HAMLET.<br>
What’s the matter now?<br>
</p>

<p class="drama">
QUEEN.<br>
Have you forgot me?<br>
</p>

<p class="drama">
HAMLET.<br>
No, by the rood, not so.<br>
You are the Queen, your husband’s brother’s wife,<br>
And, would it were not so. You are my mother.<br>
</p>

<p class="drama">
QUEEN.<br>
Nay, then I’ll set those to you that can speak.<br>
</p>

<p class="drama">
HAMLET.<br>
Come, come, and sit you down, you shall not budge.<br>
You go not till I set you up a glass<br>
Where you may see the inmost part of you.<br>
</p>

<p class="drama">
QUEEN.<br>
What wilt thou do? Thou wilt not murder me?<br>
Help, help, ho!<br>
</p>

<p class="drama">
POLONIUS.<br>
[<i>Behind.</i>] What, ho! help, help, help!<br>
</p>

<p class="drama">
HAMLET.<br>
How now? A rat? [<i>Draws.</i>]<br>
Dead for a ducat, dead!<br>
</p>

<p class="right">
[<i>Makes a pass through the arras.</i>]
</p>

<p class="drama">
POLONIUS.<br>
[<i>Behind.</i>] O, I am slain!<br>
</p>

<p class="right">
[<i>Falls and dies.</i>]
</p>

<p class="drama">
QUEEN.<br>
O me, what hast thou done?<br>
</p>

<p class="drama">
HAMLET.<br>
Nay, I know not. Is it the King?<br>
</p>

<p class="right">
[<i>Draws forth <span class="charname">Polonius</span>.</i>]
</p>

<p class="drama">
QUEEN.<br>
O what a rash and bloody deed is this!<br>
</p>

<p class="drama">
HAMLET.<br>
A bloody deed. Almost as bad, good mother,<br>
As kill a king and marry with his brother.<br>
</p>

<p class="drama">
QUEEN.<br>
As kill a king?<br>
</p>

<p class="drama">
HAMLET.<br>
Ay, lady, ’twas my word.—<br>
[<i>To Polonius.</i>] Thou wretched, rash, intruding fool, farewell!<br>
I took thee for thy better. Take thy fortune,<br>
Thou find’st to be too busy is some danger.—<br>
Leave wringing of your hands. Peace, sit you down,<br>
And let me wring your heart, for so I shall,<br>
If it be made of penetrable stuff;<br>
If damned custom have not braz’d it so,<br>
That it is proof and bulwark against sense.<br>
</p>

<p class="drama">
QUEEN.<br>
What have I done, that thou dar’st wag thy tongue<br>
In noise so rude against me?<br>
</p>

<p class="drama">
HAMLET.<br>
Such an act<br>
That blurs the grace and blush of modesty,<br>
Calls virtue hypocrite, takes off the rose<br>
From the fair forehead of an innocent love,<br>
And sets a blister there. Makes marriage vows<br>
As false as dicers’ oaths. O such a deed<br>
As from the body of contraction plucks<br>
The very soul, and sweet religion makes<br>
A rhapsody of words. Heaven’s face doth glow,<br>
Yea this solidity and compound mass,<br>
With tristful visage, as against the doom,<br>
Is thought-sick at the act.<br>
</p>

<p class="drama">
QUEEN.<br>
Ay me, what act,<br>
That roars so loud, and thunders in the index?<br>
</p>

<p class="drama">
HAMLET.<br>
Look here upon this picture, and on this,<br>
The counterfeit presentment of two brothers.<br>
See what a grace was seated on this brow,<br>
Hyperion’s curls, the front of Jove himself,<br>
An eye like Mars, to threaten and command,<br>
A station like the herald Mercury<br>
New lighted on a heaven-kissing hill:<br>
A combination and a form indeed,<br>
Where every god did seem to set his seal,<br>
To give the world assurance of a man.<br>
This was your husband. Look you now what follows.<br>
Here is your husband, like a mildew’d ear<br>
Blasting his wholesome brother. Have you eyes?<br>
Could you on this fair mountain leave to feed,<br>
And batten on this moor? Ha! have you eyes?<br>
You cannot call it love; for at your age<br>
The hey-day in the blood is tame, it’s humble,<br>
And waits upon the judgement: and what judgement<br>
Would step from this to this? Sense sure you have,<br>
Else could you not have motion; but sure that sense<br>
Is apoplex’d, for madness would not err<br>
Nor sense to ecstacy was ne’er so thrall’d<br>
But it reserv’d some quantity of choice<br>
To serve in such a difference. What devil was’t<br>
That thus hath cozen’d you at hoodman-blind?<br>
Eyes without feeling, feeling without sight,<br>
Ears without hands or eyes, smelling sans all,<br>
Or but a sickly part of one true sense<br>
Could not so mope. O shame! where is thy blush?<br>
Rebellious hell,<br>
If thou canst mutine in a matron’s bones,<br>
To flaming youth let virtue be as wax,<br>
And melt in her own fire. Proclaim no shame<br>
When the compulsive ardour gives the charge,<br>
Since frost itself as actively doth burn,<br>
And reason panders will.<br>
</p>

<p class="drama">
QUEEN.<br>
O Hamlet, speak no more.<br>
Thou turn’st mine eyes into my very soul,<br>
And there I see such black and grained spots<br>
As will not leave their tinct.<br>
</p>

<p class="drama">
HAMLET.<br>
Nay, but to live<br>
In the rank sweat of an enseamed bed,<br>
Stew’d in corruption, honeying and making love<br>
Over the nasty sty.<br>
</p>

<p class="drama">
QUEEN.<br>
O speak to me no more;<br>
These words like daggers enter in mine ears;<br>
No more, sweet Hamlet.<br>
</p>

<p class="drama">
HAMLET.<br>
A murderer and a villain;<br>
A slave that is not twentieth part the tithe<br>
Of your precedent lord. A vice of kings,<br>
A cutpurse of the empire and the rule,<br>
That from a shelf the precious diadem stole<br>
And put it in his pocket!<br>
</p>

<p class="drama">
QUEEN.<br>
No more.<br>
</p>

<p class="drama">
HAMLET.<br>
A king of shreds and patches!—<br>
</p>

<p class="scenedesc">
Enter <span class="charname">Ghost</span>.
</p>

<p class="drama">
Save me and hover o’er me with your wings,<br>
You heavenly guards! What would your gracious figure?<br>
</p>

<p class="drama">
QUEEN.<br>
Alas, he’s mad.<br>
</p>

<p class="drama">
HAMLET.<br>
Do you not come your tardy son to chide,<br>
That, laps’d in time and passion, lets go by<br>
The important acting of your dread command?<br>
O say!<br>
</p>

<p class="drama">
GHOST.<br>
Do not forget. This visitation<br>
Is but to whet thy almost blunted purpose.<br>
But look, amazement on thy mother sits.<br>
O step between her and her fighting soul.<br>
Conceit in weakest bodies strongest works.<br>
Speak to her, Hamlet.<br>
</p>

<p class="drama">
HAMLET.<br>
How is it with you, lady?<br>
</p>

<p class="drama">
QUEEN.<br>
Alas, how is’t with you,<br>
That you do bend your eye on vacancy,<br>
And with the incorporal air do hold discourse?<br>
Forth at your eyes your spirits wildly peep,<br>
And, as the sleeping soldiers in the alarm,<br>
Your bedded hairs, like life in excrements,<br>
Start up and stand an end. O gentle son,<br>
Upon the heat and flame of thy distemper<br>
Sprinkle cool patience. Whereon do you look?<br>
</p>

<p class="drama">
HAMLET.<br>
On him, on him! Look you how pale he glares,<br>
His form and cause conjoin’d, preaching to stones,<br>
Would make them capable.—Do not look upon me,<br>
Lest with this piteous action you convert<br>
My stern effects. Then what I have to do<br>
Will want true colour; tears perchance for blood.<br>
</p>

<p class="drama">
QUEEN.<br>
To whom do you speak this?<br>
</p>

<p class="drama">
HAMLET.<br>
Do you see nothing there?<br>
</p>

<p class="drama">
QUEEN.<br>
Nothing at all; yet all that is I see.<br>
</p>

<p class="drama">
HAMLET.<br>
Nor did you nothing hear?<br>
</p>

<p class="drama">
QUEEN.<br>
No, nothing but ourselves.<br>
</p>

<p class="drama">
HAMLET.<br>
Why, look you there! look how it steals away!<br>
My father, in his habit as he liv’d!<br>
Look where he goes even now out at the portal.<br>
</p>

<p class="right">
[<i>Exit <span class="charname">Ghost</span>.</i>]
</p>

<p class="drama">
QUEEN.<br>
This is the very coinage of your brain.<br>
This bodiless creation ecstasy<br>
Is very cunning in.<br>
</p>

<p class="drama">
HAMLET.<br>
Ecstasy!<br>
My pulse as yours doth temperately keep time,<br>
And makes as healthful music. It is not madness<br>
That I have utter’d. Bring me to the test,<br>
And I the matter will re-word; which madness<br>
Would gambol from. Mother, for love of grace,<br>
Lay not that flattering unction to your soul<br>
That not your trespass, but my madness speaks.<br>
It will but skin and film the ulcerous place,<br>
Whilst rank corruption, mining all within,<br>
Infects unseen. Confess yourself to heaven,<br>
Repent what’s past, avoid what is to come;<br>
And do not spread the compost on the weeds,<br>
To make them ranker. Forgive me this my virtue;<br>
For in the fatness of these pursy times<br>
Virtue itself of vice must pardon beg,<br>
Yea, curb and woo for leave to do him good.<br>
</p>

<p class="drama">
QUEEN.<br>
O Hamlet, thou hast cleft my heart in twain.<br>
</p>

<p class="drama">
HAMLET.<br>
O throw away the worser part of it,<br>
And live the purer with the other half.<br>
Good night. But go not to mine uncle’s bed.<br>
Assume a virtue, if you have it not.<br>
That monster custom, who all sense doth eat,<br>
Of habits evil, is angel yet in this,<br>
That to the use of actions fair and good<br>
He likewise gives a frock or livery<br>
That aptly is put on. Refrain tonight,<br>
And that shall lend a kind of easiness<br>
To the next abstinence. The next more easy;<br>
For use almost can change the stamp of nature,<br>
And either curb the devil, or throw him out<br>
With wondrous potency. Once more, good night,<br>
And when you are desirous to be bles’d,<br>
I’ll blessing beg of you. For this same lord<br>
[<i>Pointing to Polonius.</i>]<br>
I do repent; but heaven hath pleas’d it so,<br>
To punish me with this, and this with me,<br>
That I must be their scourge and minister.<br>
I will bestow him, and will answer well<br>
The death I gave him. So again, good night.<br>
I must be cruel, only to be kind:<br>
Thus bad begins, and worse remains behind.<br>
One word more, good lady.<br>
</p>

<p class="drama">
QUEEN.<br>
What shall I do?<br>
</p>

<p class="drama">
HAMLET.<br>
Not this, by no means, that I bid you do:<br>
Let the bloat King tempt you again to bed,<br>
Pinch wanton on your cheek, call you his mouse,<br>
And let him, for a pair of reechy kisses,<br>
Or paddling in your neck with his damn’d fingers,<br>
Make you to ravel all this matter out,<br>
That I essentially am not in madness,<br>
But mad in craft. ’Twere good you let him know,<br>
For who that’s but a queen, fair, sober, wise,<br>
Would from a paddock, from a bat, a gib,<br>
Such dear concernings hide? Who would do so?<br>
No, in despite of sense and secrecy,<br>
Unpeg the basket on the house’s top,<br>
Let the birds fly, and like the famous ape,<br>
To try conclusions, in the basket creep<br>
And break your own neck down.<br>
</p>

<p class="drama">
QUEEN.<br>
Be thou assur’d, if words be made of breath,<br>
And breath of life, I have no life to breathe<br>
What thou hast said to me.<br>
</p>

<p class="drama">
HAMLET.<br>
I must to England, you know that?<br>
</p>

<p class="drama">
QUEEN.<br>
Alack,<br>
I had forgot. ’Tis so concluded on.<br>
</p>

<p class="drama">
HAMLET.<br>
There’s letters seal’d: and my two schoolfellows,<br>
Whom I will trust as I will adders fang’d,—<br>
They bear the mandate, they must sweep my way<br>
And marshal me to knavery. Let it work;<br>
For ’tis the sport to have the enginer<br>
Hoist with his own petard, and ’t shall go hard<br>
But I will delve one yard below their mines<br>
And blow them at the moon. O, ’tis most sweet,<br>
When in one line two crafts directly meet.<br>
This man shall set me packing.<br>
I’ll lug the guts into the neighbour room.<br>
Mother, good night. Indeed, this counsellor<br>
Is now most still, most secret, and most grave,<br>
Who was in life a foolish prating knave.<br>
Come, sir, to draw toward an end with you.<br>
Good night, mother.<br>
</p>

<p class="right">
[<i>Exit <span class="charname">Hamlet</span> dragging out <span class="charname">Polonius</span>.</i>]
</p>

