<h2> <a id="sceneV_12.1"></a><b>ACT V</b></h2>

<h3> <b>SCENE I. London. The Palace.</b></h3>

<p class="scenedesc">Sennet. Enter <span class="charname">King, Gloucester</span> and
<span class="charname">Exeter</span>.</p>

<p class="drama">
KING HENRY.<br>
Have you perused the letters from the Pope,<br>
The Emperor, and the Earl of Armagnac?
</p>

<p class="drama">
GLOUCESTER.<br>
I have, my lord; and their intent is this:<br>
They humbly sue unto your Excellence<br>
To have a godly peace concluded of<br>
Between the realms of England and of France.
</p>

<p class="drama">
KING HENRY.<br>
How doth your Grace affect their motion?
</p>

<p class="drama">
GLOUCESTER.<br>
Well, my good lord, and as the only means<br>
To stop effusion of our Christian blood<br>
And stablish quietness on every side.
</p>

<p class="drama">
KING HENRY.<br>
Ay, marry, uncle, for I always thought<br>
It was both impious and unnatural<br>
That such immanity and bloody strife<br>
Should reign among professors of one faith.
</p>

<p class="drama">
GLOUCESTER.<br>
Beside, my lord, the sooner to effect<br>
And surer bind this knot of amity,<br>
The Earl of Armagnac, near knit to Charles,<br>
A man of great authority in France,<br>
Proffers his only daughter to your Grace<br>
In marriage, with a large and sumptuous dowry.
</p>

<p class="drama">
KING HENRY.<br>
Marriage, uncle! Alas, my years are young!<br>
And fitter is my study and my books<br>
Than wanton dalliance with a paramour.<br>
Yet call th’ ambassadors; and, as you please,<br>
So let them have their answers every one.<br>
I shall be well content with any choice<br>
Tends to God’s glory and my country’s weal.
</p>

<p class="scenedesc">Enter <span class="charname">Winchester</span> in
Cardinal’s habit, a  <span class="charname">Legate</span> and two
Ambassadors.</p>

<p class="drama">
EXETER.<br>
What, is my Lord of Winchester install’d<br>
And call’d unto a cardinal’s degree?<br>
Then I perceive that will be verified<br>
Henry the Fifth did sometime prophesy:<br>
“If once he come to be a cardinal,<br>
He’ll make his cap co-equal with the crown.”
</p>

<p class="drama">
KING HENRY.<br>
My Lords Ambassadors, your several suits<br>
Have been consider’d and debated on.<br>
Your purpose is both good and reasonable;<br>
And therefore are we certainly resolved<br>
To draw conditions of a friendly peace,<br>
Which by my Lord of Winchester we mean<br>
Shall be transported presently to France.
</p>

<p class="drama">
GLOUCESTER.<br>
And for the proffer of my lord your master,<br>
I have inform’d his Highness so at large,<br>
As liking of the lady’s virtuous gifts,<br>
Her beauty and the value of her dower,<br>
He doth intend she shall be England’s Queen.
</p>

<p class="drama">
KING HENRY.<br>
In argument and proof of which contract,<br>
Bear her this jewel, pledge of my affection.<br>
And so, my Lord Protector, see them guarded<br>
And safely brought to Dover; where inshipp’d,<br>
Commit them to the fortune of the sea.
</p>

<p class="right">[<i>Exeunt all but <span class="charname">Winchester</span> and
<span class="charname">Legate</span>.</i>]</p>

<p class="drama">
WINCHESTER.<br>
Stay my lord legate; you shall first receive<br>
The sum of money which I promised<br>
Should be deliver’d to his Holiness<br>
For clothing me in these grave ornaments.
</p>

<p class="drama">
LEGATE.<br>
I will attend upon your lordship’s leisure.
</p>

<p class="drama">
WINCHESTER.<br>
[<i>Aside</i>.] Now Winchester will not submit, I trow,<br>
Or be inferior to the proudest peer.<br>
Humphrey of Gloucester, thou shalt well perceive<br>
That neither in birth or for authority,<br>
The Bishop will be overborne by thee.<br>
I’ll either make thee stoop and bend thy knee,<br>
Or sack this country with a mutiny.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneV_12.2"></a><b>SCENE II. France. Plains in Anjou.</b></h3>

<p class="scenedesc">Enter <span class="charname">Charles, Burgundy, Alençon,
Bastard, Reignier, La Pucelle</span> and forces.</p>

<p class="drama">
CHARLES.<br>
These news, my lords, may cheer our drooping spirits:<br>
’Tis said the stout Parisians do revolt<br>
And turn again unto the warlike French.
</p>

<p class="drama">
ALENÇON.<br>
Then march to Paris, royal Charles of France,<br>
And keep not back your powers in dalliance.
</p>

<p class="drama">
PUCELLE.<br>
Peace be amongst them, if they turn to us;<br>
Else ruin combat with their palaces!
</p>

<p class="scenedesc">Enter <span class="charname">Scout</span>.</p>

<p class="drama">
SCOUT.<br>
Success unto our valiant general,<br>
And happiness to his accomplices!
</p>

<p class="drama">
CHARLES.<br>
What tidings send our scouts? I prithee, speak.
</p>

<p class="drama">
SCOUT.<br>
The English army, that divided was<br>
Into two parties, is now conjoin’d in one,<br>
And means to give you battle presently.
</p>

<p class="drama">
CHARLES.<br>
Somewhat too sudden, sirs, the warning is;<br>
But we will presently provide for them.
</p>

<p class="drama">
BURGUNDY.<br>
I trust the ghost of Talbot is not there.<br>
Now he is gone, my lord, you need not fear.
</p>

<p class="drama">
PUCELLE.<br>
Of all base passions, fear is most accursed.<br>
Command the conquest, Charles, it shall be thine;<br>
Let Henry fret and all the world repine.
</p>

<p class="drama">
CHARLES.<br>
Then on, my lords; and France be fortunate!
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneV_12.3"></a><b>SCENE III. Before Angiers.</b></h3>

<p class="scenedesc">Alarum. Excursions. Enter <span class="charname">La Pucelle</span>.</p>

<p class="drama">
PUCELLE.<br>
The Regent conquers, and the Frenchmen fly.<br>
Now help, ye charming spells and periapts;<br>
And ye choice spirits that admonish me,<br>
And give me signs of future accidents. [<i>Thunder</i>]<br>
You speedy helpers, that are substitutes<br>
Under the lordly monarch of the north,<br>
Appear and aid me in this enterprise.
</p>

<p class="scenedesc">Enter <span class="charname">Fiends</span>.</p>

<p class="drama">
This speed and quick appearance argues proof<br>
Of your accustom’d diligence to me.<br>
Now, ye familiar spirits that are cull’d<br>
Out of the powerful regions under earth,<br>
Help me this once, that France may get the field.
</p>

<p class="right">[<i>They walk and speak not.</i>]</p>

<p class="drama">
O, hold me not with silence over-long!<br>
Where I was wont to feed you with my blood,<br>
I’ll lop a member off and give it you<br>
In earnest of a further benefit,<br>
So you do condescend to help me now.
</p>

<p class="right">[<i>They hang their heads.</i>]</p>

<p class="drama">
No hope to have redress? My body shall<br>
Pay recompense if you will grant my suit.
</p>

<p class="right">[<i>They shake their heads.</i>]</p>

<p class="drama">
Cannot my body nor blood-sacrifice<br>
Entreat you to your wonted furtherance?<br>
Then take my soul; my body, soul and all,<br>
Before that England give the French the foil.
</p>

<p class="right">[<i>They depart.</i>]</p>

<p class="drama">
See, they forsake me. Now the time is come<br>
That France must vail her lofty-plumed crest<br>
And let her head fall into England’s lap.<br>
My ancient incantations are too weak,<br>
And hell too strong for me to buckle with.<br>
Now, France, thy glory droopeth to the dust.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="scenedesc">Excursions. <span class="charname">Burgundy</span> and
<span class="charname">York</span> fight hand to hand. The French fly. <span class="charname"> La Pucelle</span> is taken.</p>

<p class="drama">
YORK.<br>
Damsel of France, I think I have you fast.<br>
Unchain your spirits now with spelling charms,<br>
And try if they can gain your liberty.<br>
A goodly prize, fit for the devil’s grace!<br>
See, how the ugly witch doth bend her brows,<br>
As if with Circe she would change my shape!
</p>

<p class="drama">
PUCELLE.<br>
Chang’d to a worser shape thou canst not be.
</p>

<p class="drama">
YORK.<br>
O, Charles the Dauphin is a proper man;<br>
No shape but his can please your dainty eye.
</p>

<p class="drama">
PUCELLE.<br>
A plaguing mischief light on Charles and thee!<br>
And may ye both be suddenly surprised<br>
By bloody hands, in sleeping on your beds!
</p>

<p class="drama">
YORK.<br>
Fell banning hag, enchantress, hold thy tongue!
</p>

<p class="drama">
PUCELLE.<br>
I prithee, give me leave to curse awhile.
</p>

<p class="drama">
YORK.<br>
Curse, miscreant, when thou com’st to the stake.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<p class="scenedesc">Alarum. Enter <span class="charname">Suffolk</span> with
<span class="charname">Margaret</span> in his hand.</p>

<p class="drama">
SUFFOLK.<br>
Be what thou wilt, thou art my prisoner.
</p>

<p class="right">[<i>Gazes on her.</i>]</p>

<p class="drama">
O fairest beauty, do not fear nor fly!<br>
For I will touch thee but with reverent hands,<br>
I kiss these fingers for eternal peace,<br>
And lay them gently on thy tender side.<br>
Who art thou? Say, that I may honour thee.
</p>

<p class="drama">
MARGARET.<br>
Margaret my name, and daughter to a king,<br>
The King of Naples, whosoe’er thou art.
</p>

<p class="drama">
SUFFOLK.<br>
An earl I am, and Suffolk am I call’d.<br>
Be not offended, nature’s miracle,<br>
Thou art allotted to be ta’en by me.<br>
So doth the swan her downy cygnets save,<br>
Keeping them prisoner underneath her wings.<br>
Yet, if this servile usage once offend,<br>
Go and be free again as Suffolk’s friend.
</p>

<p class="right">[<i>She is going.</i>]</p>

<p class="drama">
O, stay! I have no power to let her pass;<br>
My hand would free her, but my heart says no.<br>
As plays the sun upon the glassy streams,<br>
Twinkling another counterfeited beam,<br>
So seems this gorgeous beauty to mine eyes.<br>
Fain would I woo her, yet I dare not speak.<br>
I’ll call for pen and ink, and write my mind.<br>
Fie, de la Pole, disable not thyself;<br>
Hast not a tongue? Is she not here?<br>
Wilt thou be daunted at a woman’s sight?<br>
Ay, beauty’s princely majesty is such<br>
Confounds the tongue and makes the senses rough.
</p>

<p class="drama">
MARGARET.<br>
Say, Earl of Suffolk, if thy name be so,<br>
What ransom must I pay before I pass?<br>
For I perceive I am thy prisoner.
</p>

<p class="drama">
SUFFOLK.<br>
How canst thou tell she will deny thy suit,<br>
Before thou make a trial of her love?
</p>

<p class="drama">
MARGARET.<br>
Why speak’st thou not? What ransom must I pay?
</p>

<p class="drama">
SUFFOLK.<br>
She’s beautiful, and therefore to be woo’d;<br>
She is a woman, therefore to be won.
</p>

<p class="drama">
MARGARET.<br>
Wilt thou accept of ransom, yea, or no?
</p>

<p class="drama">
SUFFOLK.<br>
Fond man, remember that thou hast a wife;<br>
Then how can Margaret be thy paramour?
</p>

<p class="drama">
MARGARET.<br>
I were best leave him, for he will not hear.
</p>

<p class="drama">
SUFFOLK.<br>
There all is marr’d; there lies a cooling card.
</p>

<p class="drama">
MARGARET.<br>
He talks at random; sure, the man is mad.
</p>

<p class="drama">
SUFFOLK.<br>
And yet a dispensation may be had.
</p>

<p class="drama">
MARGARET.<br>
And yet I would that you would answer me.
</p>

<p class="drama">
SUFFOLK.<br>
I’ll win this Lady Margaret. For whom?<br>
Why, for my king. Tush, that’s a wooden thing!
</p>

<p class="drama">
MARGARET.<br>
He talks of wood. It is some carpenter.
</p>

<p class="drama">
SUFFOLK.<br>
Yet so my fancy may be satisfied,<br>
And peace established between these realms.<br>
But there remains a scruple in that too;<br>
For though her father be the King of Naples,<br>
Duke of Anjou and Maine, yet is he poor,<br>
And our nobility will scorn the match.
</p>

<p class="drama">
MARGARET.<br>
Hear ye, captain, are you not at leisure?
</p>

<p class="drama">
SUFFOLK.<br>
It shall be so, disdain they ne’er so much.<br>
Henry is youthful and will quickly yield.<br>
Madam, I have a secret to reveal.
</p>

<p class="drama">
MARGARET.<br>
What though I be enthrall’d? He seems a knight,<br>
And will not any way dishonour me.
</p>

<p class="drama">
SUFFOLK.<br>
Lady, vouchsafe to listen what I say.
</p>

<p class="drama">
MARGARET.<br>
Perhaps I shall be rescued by the French;<br>
And then I need not crave his courtesy.
</p>

<p class="drama">
SUFFOLK.<br>
Sweet madam, give me hearing in a cause.
</p>

<p class="drama">
MARGARET.<br>
Tush, women have been captivate ere now.
</p>

<p class="drama">
SUFFOLK.<br>
Lady, wherefore talk you so?
</p>

<p class="drama">
MARGARET.<br>
I cry you mercy, ’tis but <i>quid</i> for <i>quo</i>.
</p>

<p class="drama">
SUFFOLK.<br>
Say, gentle princess, would you not suppose<br>
Your bondage happy, to be made a queen?
</p>

<p class="drama">
MARGARET.<br>
To be a queen in bondage is more vile<br>
Than is a slave in base servility;<br>
For princes should be free.
</p>

<p class="drama">
SUFFOLK.<br>
And so shall you,<br>
If happy England’s royal king be free.
</p>

<p class="drama">
MARGARET.<br>
Why, what concerns his freedom unto me?
</p>

<p class="drama">
SUFFOLK.<br>
I’ll undertake to make thee Henry’s queen,<br>
To put a golden scepter in thy hand<br>
And set a precious crown upon thy head,<br>
If thou wilt condescend to be my—
</p>

<p class="drama">
MARGARET.<br>
What?
</p>

<p class="drama">
SUFFOLK.<br>
His love.
</p>

<p class="drama">
MARGARET.<br>
I am unworthy to be Henry’s wife.
</p>

<p class="drama">
SUFFOLK.<br>
No, gentle madam, I unworthy am<br>
To woo so fair a dame to be his wife,<br>
And have no portion in the choice myself.<br>
How say you, madam, are ye so content?
</p>

<p class="drama">
MARGARET.<br>
An if my father please, I am content.
</p>

<p class="drama">
SUFFOLK.<br>
Then call our captains and our colours forth.<br>
And, madam, at your father’s castle walls<br>
We’ll crave a parley, to confer with him.
</p>

<p class="scenedesc">A parley sounded. Enter
<span class="charname">Reignier</span> on the walls.</p>

<p class="drama">
See, Reignier, see, thy daughter prisoner!
</p>

<p class="drama">
REIGNIER.<br>
To whom?
</p>

<p class="drama">
SUFFOLK.<br>
To me.
</p>

<p class="drama">
REIGNIER.<br>
Suffolk, what remedy?<br>
I am a soldier, and unapt to weep<br>
Or to exclaim on fortune’s fickleness.
</p>

<p class="drama">
SUFFOLK.<br>
Yes, there is remedy enough, my lord:<br>
Consent, and for thy honour give consent,<br>
Thy daughter shall be wedded to my king,<br>
Whom I with pain have woo’d and won thereto;<br>
And this her easy-held imprisonment<br>
Hath gain’d thy daughter princely liberty.
</p>

<p class="drama">
REIGNIER.<br>
Speaks Suffolk as he thinks?
</p>

<p class="drama">
SUFFOLK.<br>
Fair Margaret knows<br>
That Suffolk doth not flatter, face, or feign.
</p>

<p class="drama">
REIGNIER.<br>
Upon thy princely warrant, I descend<br>
To give thee answer of thy just demand.
</p>

<p class="right">[<i>Exit from the walls.</i>]</p>

<p class="drama">
SUFFOLK.<br>
And here I will expect thy coming.
</p>

<p class="scenedesc">Trumpets sound. Enter
<span class="charname">Reignier</span>, below.</p>

<p class="drama">
REIGNIER.<br>
Welcome, brave earl, into our territories.<br>
Command in Anjou what your honour pleases.
</p>

<p class="drama">
SUFFOLK.<br>
Thanks, Reignier, happy for so sweet a child,<br>
Fit to be made companion with a king.<br>
What answer makes your Grace unto my suit?
</p>

<p class="drama">
REIGNIER.<br>
Since thou dost deign to woo her little worth<br>
To be the princely bride of such a lord,<br>
Upon condition I may quietly<br>
Enjoy mine own, the country Maine and Anjou,<br>
Free from oppression or the stroke of war,<br>
My daughter shall be Henry’s, if he please.
</p>

<p class="drama">
SUFFOLK.<br>
That is her ransom; I deliver her;<br>
And those two counties I will undertake<br>
Your Grace shall well and quietly enjoy.
</p>

<p class="drama">
REIGNIER.<br>
And I again, in Henry’s royal name,<br>
As deputy unto that gracious king,<br>
Give thee her hand for sign of plighted faith.
</p>

<p class="drama">
SUFFOLK.<br>
Reignier of France, I give thee kingly thanks,<br>
Because this is in traffic of a king.<br>
[<i>Aside</i>.] And yet, methinks, I could be well content<br>
To be mine own attorney in this case.<br>
I’ll over then to England with this news,<br>
And make this marriage to be solemnized.<br>
So, farewell, Reignier; set this diamond safe<br>
In golden palaces, as it becomes.
</p>

<p class="drama">
REIGNIER.<br>
I do embrace thee as I would embrace<br>
The Christian prince, King Henry, were he here.
</p>

<p class="drama">
MARGARET.<br>
Farewell, my lord; good wishes, praise, and prayers<br>
Shall Suffolk ever have of Margaret. [<i>Going</i>].
</p>

<p class="drama">
SUFFOLK.<br>
Farewell, sweet madam; but hark you, Margaret,<br>
No princely commendations to my king?
</p>

<p class="drama">
MARGARET.<br>
Such commendations as becomes a maid,<br>
A virgin and his servant, say to him.
</p>

<p class="drama">
SUFFOLK.<br>
Words sweetly placed and modestly directed.<br>
But, madam, I must trouble you again:<br>
No loving token to his Majesty?
</p>

<p class="drama">
MARGARET.<br>
Yes, my good lord; a pure unspotted heart,<br>
Never yet taint with love, I send the King.
</p>

<p class="drama">
SUFFOLK.<br>
And this withal. [<i>Kisses her</i>.]
</p>

<p class="drama">
MARGARET.<br>
That for thyself. I will not so presume<br>
To send such peevish tokens to a king.
</p>

<p class="right">[<i>Exeunt <span class="charname">Reignier</span> and
<span class="charname">Margaret</span>.</i>]</p>

<p class="drama">
SUFFOLK.<br>
O, wert thou for myself! But, Suffolk, stay;<br>
Thou mayst not wander in that labyrinth.<br>
There Minotaurs and ugly treasons lurk.<br>
Solicit Henry with her wondrous praise.<br>
Bethink thee on her virtues that surmount,<br>
And natural graces that extinguish art;<br>
Repeat their semblance often on the seas,<br>
That, when thou com’st to kneel at Henry’s feet,<br>
Thou mayst bereave him of his wits with wonder.
</p>

<p class="right">[<i>Exit.</i>]</p>

<h3> <a id="sceneV_12.4"></a><b>SCENE IV. Camp of the Duke of York in Anjou.</b></h3>

<p class="scenedesc">Enter <span class="charname">York, Warwick</span> and others.</p>

<p class="drama">
YORK.<br>
Bring forth that sorceress condemn’d to burn.
</p>

<p class="scenedesc">Enter <span class="charname">La Pucelle</span>, guarded, and a
<span class="charname">Shepherd</span>.</p>

<p class="drama">
SHEPHERD.<br>
Ah, Joan, this kills thy father’s heart outright!<br>
Have I sought every country far and near,<br>
And, now it is my chance to find thee out,<br>
Must I behold thy timeless cruel death?<br>
Ah, Joan, sweet daughter Joan, I’ll die with thee!
</p>

<p class="drama">
PUCELLE.<br>
Decrepit miser, base ignoble wretch!<br>
I am descended of a gentler blood.<br>
Thou art no father nor no friend of mine.
</p>

<p class="drama">
SHEPHERD.<br>
Out, out! My lords, as please you, ’tis not so;<br>
I did beget her, all the parish knows.<br>
Her mother liveth yet, can testify<br>
She was the first fruit of my bachelorship.
</p>

<p class="drama">
WARWICK.<br>
Graceless, wilt thou deny thy parentage?
</p>

<p class="drama">
YORK.<br>
This argues what her kind of life hath been,<br>
Wicked and vile; and so her death concludes.
</p>

<p class="drama">
SHEPHERD.<br>
Fie, Joan, that thou wilt be so obstacle!<br>
God knows thou art a collop of my flesh;<br>
And for thy sake have I shed many a tear.<br>
Deny me not, I prithee, gentle Joan.
</p>

<p class="drama">
PUCELLE.<br>
Peasant, avaunt! You have suborn’d this man<br>
Of purpose to obscure my noble birth.
</p>

<p class="drama">
SHEPHERD.<br>
’Tis true, I gave a noble to the priest<br>
The morn that I was wedded to her mother.<br>
Kneel down and take my blessing, good my girl.<br>
Wilt thou not stoop? Now cursed be the time<br>
Of thy nativity! I would the milk<br>
Thy mother gave thee when thou suck’dst her breast<br>
Had been a little ratsbane for thy sake!<br>
Or else, when thou didst keep my lambs a-field,<br>
I wish some ravenous wolf had eaten thee!<br>
Dost thou deny thy father, cursed drab?<br>
O, burn her, burn her! Hanging is too good.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
YORK.<br>
Take her away, for she hath lived too long,<br>
To fill the world with vicious qualities.
</p>

<p class="drama">
PUCELLE.<br>
First, let me tell you whom you have condemn’d:<br>
Not one begotten of a shepherd swain,<br>
But issued from the progeny of kings;<br>
Virtuous and holy, chosen from above,<br>
By inspiration of celestial grace,<br>
To work exceeding miracles on earth.<br>
I never had to do with wicked spirits.<br>
But you, that are polluted with your lusts,<br>
Stain’d with the guiltless blood of innocents,<br>
Corrupt and tainted with a thousand vices,<br>
Because you want the grace that others have,<br>
You judge it straight a thing impossible<br>
To compass wonders but by help of devils.<br>
No, misconceived! Joan of Arc hath been<br>
A virgin from her tender infancy,<br>
Chaste and immaculate in very thought;<br>
Whose maiden blood, thus rigorously effused,<br>
Will cry for vengeance at the gates of heaven.
</p>

<p class="drama">
YORK.<br>
Ay, ay; away with her to execution!
</p>

<p class="drama">
WARWICK.<br>
And hark ye, sirs; because she is a maid,<br>
Spare for no faggots, let there be enow.<br>
Place barrels of pitch upon the fatal stake,<br>
That so her torture may be shortened.
</p>

<p class="drama">
PUCELLE.<br>
Will nothing turn your unrelenting hearts?<br>
Then, Joan, discover thine infirmity,<br>
That warranteth by law to be thy privilege:<br>
I am with child, ye bloody homicides.<br>
Murder not then the fruit within my womb,<br>
Although ye hale me to a violent death.
</p>

<p class="drama">
YORK.<br>
Now heaven forfend! The holy maid with child?
</p>

<p class="drama">
WARWICK.<br>
The greatest miracle that e’er ye wrought!<br>
Is all your strict preciseness come to this?
</p>

<p class="drama">
YORK.<br>
She and the Dauphin have been juggling.<br>
I did imagine what would be her refuge.
</p>

<p class="drama">
WARWICK.<br>
Well, go to; we’ll have no bastards live,<br>
Especially since Charles must father it.
</p>

<p class="drama">
PUCELLE.<br>
You are deceived; my child is none of his.<br>
It was Alençon that enjoy’d my love.
</p>

<p class="drama">
YORK.<br>
Alençon, that notorious Machiavel!<br>
It dies and if it had a thousand lives.
</p>

<p class="drama">
PUCELLE.<br>
O, give me leave, I have deluded you.<br>
’Twas neither Charles nor yet the Duke I named,<br>
But Reignier, King of Naples, that prevail’d.
</p>

<p class="drama">
WARWICK.<br>
A married man! That’s most intolerable.
</p>

<p class="drama">
YORK.<br>
Why, here’s a girl! I think she knows not well—<br>
There were so many—whom she may accuse.
</p>

<p class="drama">
WARWICK.<br>
It’s sign she hath been liberal and free.
</p>

<p class="drama">
YORK.<br>
And yet, forsooth, she is a virgin pure!<br>
Strumpet, thy words condemn thy brat and thee.<br>
Use no entreaty, for it is in vain.
</p>

<p class="drama">
PUCELLE.<br>
Then lead me hence, with whom I leave my curse:<br>
May never glorious sun reflex his beams<br>
Upon the country where you make abode;<br>
But darkness and the gloomy shade of death<br>
Environ you, till mischief and despair<br>
Drive you to break your necks or hang yourselves!
</p>

<p class="right">[<i>Exit, guarded.</i>]</p>

<p class="drama">
YORK.<br>
Break thou in pieces and consume to ashes,<br>
Thou foul accursed minister of hell!
</p>

<p class="scenedesc">Enter <span class="charname">Bishop of
Winchester</span> as Cardinal, attended.</p>

<p class="drama">
WINCHESTER.<br>
Lord Regent, I do greet your Excellence<br>
With letters of commission from the King.<br>
For know, my lords, the states of Christendom,<br>
Moved with remorse of these outrageous broils,<br>
Have earnestly implored a general peace<br>
Betwixt our nation and the aspiring French;<br>
And here at hand the Dauphin and his train<br>
Approacheth to confer about some matter.
</p>

<p class="drama">
YORK.<br>
Is all our travail turn’d to this effect?<br>
After the slaughter of so many peers,<br>
So many captains, gentlemen and soldiers,<br>
That in this quarrel have been overthrown<br>
And sold their bodies for their country’s benefit,<br>
Shall we at last conclude effeminate peace?<br>
Have we not lost most part of all the towns,<br>
By treason, falsehood, and by treachery,<br>
Our great progenitors had conquered?<br>
O, Warwick, Warwick! I foresee with grief<br>
The utter loss of all the realm of France.
</p>

<p class="drama">
WARWICK.<br>
Be patient, York; if we conclude a peace,<br>
It shall be with such strict and severe covenants<br>
As little shall the Frenchmen gain thereby.
</p>

<p class="scenedesc">Enter <span class="charname">Charles, Alençon, Bastard,
Reignier</span> and others.</p>

<p class="drama">
CHARLES.<br>
Since, lords of England, it is thus agreed<br>
That peaceful truce shall be proclaim’d in France,<br>
We come to be informed by yourselves<br>
What the conditions of that league must be.
</p>

<p class="drama">
YORK.<br>
Speak, Winchester, for boiling choler chokes<br>
The hollow passage of my poison’d voice<br>
By sight of these our baleful enemies.
</p>

<p class="drama">
WINCHESTER.<br>
Charles, and the rest, it is enacted thus:<br>
That, in regard King Henry gives consent,<br>
Of mere compassion and of lenity,<br>
To ease your country of distressful war,<br>
And suffer you to breathe in fruitful peace,<br>
You shall become true liegemen to his crown.<br>
And, Charles, upon condition thou wilt swear<br>
To pay him tribute and submit thyself,<br>
Thou shalt be placed as viceroy under him,<br>
And still enjoy the regal dignity.
</p>

<p class="drama">
ALENÇON.<br>
Must he be then as shadow of himself?<br>
Adorn his temples with a coronet,<br>
And yet, in substance and authority,<br>
Retain but privilege of a private man?<br>
This proffer is absurd and reasonless.
</p>

<p class="drama">
CHARLES.<br>
’Tis known already that I am possess’d<br>
With more than half the Gallian territories,<br>
And therein reverenced for their lawful king.<br>
Shall I, for lucre of the rest unvanquish’d,<br>
Detract so much from that prerogative<br>
As to be call’d but viceroy of the whole?<br>
No, lord ambassador, I’ll rather keep<br>
That which I have than, coveting for more,<br>
Be cast from possibility of all.
</p>

<p class="drama">
YORK.<br>
Insulting Charles! Hast thou by secret means<br>
Used intercession to obtain a league,<br>
And, now the matter grows to compromise,<br>
Stand’st thou aloof upon comparison?<br>
Either accept the title thou usurp’st,<br>
Of benefit proceeding from our king<br>
And not of any challenge of desert,<br>
Or we will plague thee with incessant wars.
</p>

<p class="drama">
REIGNIER.<br>
My lord, you do not well in obstinacy<br>
To cavil in the course of this contract.<br>
If once it be neglected, ten to one<br>
We shall not find like opportunity.
</p>

<p class="drama">
ALENÇON.<br>
To say the truth, it is your policy<br>
To save your subjects from such massacre<br>
And ruthless slaughters as are daily seen<br>
By our proceeding in hostility;<br>
And therefore take this compact of a truce,<br>
Although you break it when your pleasure serves.
</p>

<p class="drama">
WARWICK.<br>
How say’st thou, Charles? Shall our condition stand?
</p>

<p class="drama">
CHARLES.<br>
It shall; only reserv’d you claim no interest<br>
In any of our towns of garrison.
</p>

<p class="drama">
YORK.<br>
Then swear allegiance to his Majesty,<br>
As thou art knight, never to disobey<br>
Nor be rebellious to the crown of England,<br>
Thou, nor thy nobles, to the crown of England.
</p>

<p class="right">[<i><span class="charname">Charles</span> and the rest give
tokens of fealty.</i>]</p>

<p class="drama">
So, now dismiss your army when ye please;<br>
Hang up your ensigns, let your drums be still,<br>
For here we entertain a solemn peace.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneV_12.5"></a><b>SCENE V. London. The royal palace.</b></h3>

<p class="scenedesc">Enter <span class="charname">Suffolk</span> in conference
with the <span class="charname">King, Gloucester</span> and <span class="charname">Exeter</span>.</p>

<p class="drama">
KING HENRY.<br>
Your wondrous rare description, noble earl,<br>
Of beauteous Margaret hath astonish’d me.<br>
Her virtues graced with external gifts<br>
Do breed love’s settled passions in my heart,<br>
And like as rigor of tempestuous gusts<br>
Provokes the mightiest hulk against the tide,<br>
So am I driven by breath of her renown<br>
Either to suffer shipwreck or arrive<br>
Where I may have fruition of her love.
</p>

<p class="drama">
SUFFOLK.<br>
Tush, my good lord, this superficial tale<br>
Is but a preface of her worthy praise;<br>
The chief perfections of that lovely dame,<br>
Had I sufficient skill to utter them,<br>
Would make a volume of enticing lines,<br>
Able to ravish any dull conceit;<br>
And, which is more, she is not so divine,<br>
So full replete with choice of all delights,<br>
But with as humble lowliness of mind<br>
She is content to be at your command;<br>
Command, I mean, of virtuous chaste intents,<br>
To love and honour Henry as her lord.
</p>

<p class="drama">
KING HENRY.<br>
And otherwise will Henry ne’er presume.<br>
Therefore, my Lord Protector, give consent<br>
That Margaret may be England’s royal queen.
</p>

<p class="drama">
GLOUCESTER.<br>
So should I give consent to flatter sin.<br>
You know, my lord, your Highness is betroth’d<br>
Unto another lady of esteem.<br>
How shall we then dispense with that contract,<br>
And not deface your honour with reproach?
</p>

<p class="drama">
SUFFOLK.<br>
As doth a ruler with unlawful oaths;<br>
Or one that, at a triumph having vow’d<br>
To try his strength, forsaketh yet the lists<br>
By reason of his adversary’s odds.<br>
A poor earl’s daughter is unequal odds,<br>
And therefore may be broke without offence.
</p>

<p class="drama">
GLOUCESTER.<br>
Why, what, I pray, is Margaret more than that?<br>
Her father is no better than an earl,<br>
Although in glorious titles he excel.
</p>

<p class="drama">
SUFFOLK.<br>
Yes, my lord, her father is a king,<br>
The King of Naples and Jerusalem;<br>
And of such great authority in France<br>
As his alliance will confirm our peace,<br>
And keep the Frenchmen in allegiance.
</p>

<p class="drama">
GLOUCESTER.<br>
And so the Earl of Armagnac may do,<br>
Because he is near kinsman unto Charles.
</p>

<p class="drama">
EXETER.<br>
Beside, his wealth doth warrant a liberal dower,<br>
Where Reignier sooner will receive than give.
</p>

<p class="drama">
SUFFOLK.<br>
A dower, my lords? Disgrace not so your king,<br>
That he should be so abject, base, and poor,<br>
To choose for wealth and not for perfect love.<br>
Henry is able to enrich his queen,<br>
And not to seek a queen to make him rich;<br>
So worthless peasants bargain for their wives,<br>
As market-men for oxen, sheep, or horse.<br>
Marriage is a matter of more worth<br>
Than to be dealt in by attorneyship;<br>
Not whom we will, but whom his Grace affects,<br>
Must be companion of his nuptial bed.<br>
And therefore, lords, since he affects her most,<br>
Most of all these reasons bindeth us<br>
In our opinions she should be preferr’d.<br>
For what is wedlock forced but a hell,<br>
An age of discord and continual strife?<br>
Whereas the contrary bringeth bliss,<br>
And is a pattern of celestial peace.<br>
Whom should we match with Henry, being a king,<br>
But Margaret, that is daughter to a king?<br>
Her peerless feature, joined with her birth,<br>
Approves her fit for none but for a king;<br>
Her valiant courage and undaunted spirit,<br>
More than in women commonly is seen,<br>
Will answer our hope in issue of a king;<br>
For Henry, son unto a conqueror,<br>
Is likely to beget more conquerors,<br>
If with a lady of so high resolve<br>
As is fair Margaret he be link’d in love.<br>
Then yield, my lords; and here conclude with me<br>
That Margaret shall be queen, and none but she.
</p>

<p class="drama">
KING HENRY.<br>
Whether it be through force of your report,<br>
My noble Lord of Suffolk, or for that<br>
My tender youth was never yet attaint<br>
With any passion of inflaming love,<br>
I cannot tell; but this I am assured,<br>
I feel such sharp dissension in my breast,<br>
Such fierce alarums both of hope and fear,<br>
As I am sick with working of my thoughts.<br>
Take therefore shipping; post, my lord, to France;<br>
Agree to any covenants, and procure<br>
That Lady Margaret do vouchsafe to come<br>
To cross the seas to England and be crown’d<br>
King Henry’s faithful and anointed queen.<br>
For your expenses and sufficient charge,<br>
Among the people gather up a tenth.<br>
Be gone, I say; for till you do return,<br>
I rest perplexed with a thousand cares.<br>
And you, good uncle, banish all offence.<br>
If you do censure me by what you were,<br>
Not what you are, I know it will excuse<br>
This sudden execution of my will.<br>
And so conduct me where, from company,<br>
I may revolve and ruminate my grief.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
GLOUCESTER.<br>
Ay, grief, I fear me, both at first and last.
</p>

<p class="right">[<i>Exeunt <span class="charname">Gloucester</span> and
<span class="charname">Exeter</span>.</i>]</p>

<p class="drama">
SUFFOLK.<br>
Thus Suffolk hath prevail’d; and thus he goes,<br>
As did the youthful Paris once to Greece,<br>
With hope to find the like event in love,<br>
But prosper better than the Troyan did.<br>
Margaret shall now be queen, and rule the King;<br>
But I will rule both her, the King, and realm.
</p>

<p class="right">[<i>Exit.</i>]</p>

