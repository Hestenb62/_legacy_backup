<h2><a id="sceneI_10.1"></a>ACT I</h2>

<h3> <b>SCENE I. The same.</b></h3>

<p class="scenedesc">Enter <span class="charname">Lord Bardolph</span>.</p>

<p class="drama">
LORD BARDOLPH.<br>
Who keeps the gate here, ho?
</p>

<p class="scenedesc">The <span class="charname">Porter</span> opens the gate.</p>

<p class="drama">
Where is the Earl?
</p>

<p class="drama">
PORTER.<br>
What shall I say you are?
</p>

<p class="drama">
LORD BARDOLPH.<br>
Tell thou the Earl<br>
That the Lord Bardolph doth attend him here.
</p>

<p class="drama">
PORTER.<br>
His lordship is walk’d forth into the orchard.<br>
Please it your honour knock but at the gate,<br>
And he himself will answer.
</p>

<p class="scenedesc">Enter <span class="charname">Northumberland</span>.</p>

<p class="drama">
LORD BARDOLPH.<br>
Here comes the Earl.
</p>

<p class="right"> [<i>Exit <span class="charname">Porter</span>.</i>]</p>

<p class="drama">
NORTHUMBERLAND.<br>
What news, Lord Bardolph? Every minute now<br>
Should be the father of some stratagem.<br>
The times are wild; contention, like a horse<br>
Full of high feeding, madly hath broke loose<br>
And bears down all before him.
</p>

<p class="drama">
LORD BARDOLPH.<br>
Noble earl,<br>
I bring you certain news from Shrewsbury.
</p>

<p class="drama">
NORTHUMBERLAND.<br>
Good, an God will!
</p>

<p class="drama">
LORD BARDOLPH.<br>
As good as heart can wish.<br>
The King is almost wounded to the death;<br>
And, in the fortune of my lord your son,<br>
Prince Harry slain outright; and both the Blunts<br>
Kill’d by the hand of Douglas; young Prince John<br>
And Westmoreland and Stafford fled the field;<br>
And Harry Monmouth’s brawn, the hulk Sir John,<br>
Is prisoner to your son. O, such a day,<br>
So fought, so follow’d and so fairly won,<br>
Came not till now to dignify the times<br>
Since Caesar’s fortunes!
</p>

<p class="drama">
NORTHUMBERLAND.<br>
How is this derived?<br>
Saw you the field? Came you from Shrewsbury?
</p>

<p class="drama">
LORD BARDOLPH.<br>
I spake with one, my lord, that came from thence,<br>
A gentleman well bred and of good name,<br>
That freely render’d me these news for true.
</p>

<p class="drama">
NORTHUMBERLAND.<br>
Here comes my servant Travers, whom I sent<br>
On Tuesday last to listen after news.
</p>

<p class="scenedesc">Enter <span class="charname">Travers</span>.</p>

<p class="drama">
LORD BARDOLPH.<br>
My lord, I over-rode him on the way,<br>
And he is furnish’d with no certainties<br>
More than he haply may retail from me.
</p>

<p class="drama">
NORTHUMBERLAND.<br>
Now, Travers, what good tidings comes with you?
</p>

<p class="drama">
TRAVERS.<br>
My lord, Sir John Umfrevile turn’d me back<br>
With joyful tidings, and, being better horsed,<br>
Out-rode me. After him came spurring hard<br>
A gentleman, almost forspent with speed,<br>
That stopp’d by me to breathe his bloodied horse.<br>
He ask’d the way to Chester, and of him<br>
I did demand what news from Shrewsbury.<br>
He told me that rebellion had bad luck<br>
And that young Harry Percy’s spur was cold.<br>
With that he gave his able horse the head,<br>
And bending forward struck his armed heels<br>
Against the panting sides of his poor jade<br>
Up to the rowel-head, and starting so<br>
He seem’d in running to devour the way,<br>
Staying no longer question.
</p>

<p class="drama">
NORTHUMBERLAND.<br>
Ha? Again:<br>
Said he young Harry Percy’s spur was cold?<br>
Of Hotspur, Coldspur? That rebellion<br>
Had met ill luck?
</p>

<p class="drama">
LORD BARDOLPH.<br>
My lord, I’ll tell you what:<br>
If my young lord your son have not the day,<br>
Upon mine honour, for a silken point<br>
I’ll give my barony, never talk of it.
</p>

<p class="drama">
NORTHUMBERLAND.<br>
Why should that gentleman that rode by Travers<br>
Give then such instances of loss?
</p>

<p class="drama">
LORD BARDOLPH.<br>
Who, he?<br>
He was some hilding fellow that had stolen<br>
The horse he rode on, and, upon my life,<br>
Spoke at a venture. Look, here comes more news.
</p>

<p class="scenedesc">Enter <span class="charname">Morton</span>.</p>

<p class="drama">
NORTHUMBERLAND.<br>
Yea, this man’s brow, like to a title-leaf,<br>
Foretells the nature of a tragic volume.<br>
So looks the strand whereon the imperious flood<br>
Hath left a witness’d usurpation.<br>
Say, Morton, didst thou come from Shrewsbury?
</p>

<p class="drama">
MORTON.<br>
I ran from Shrewsbury, my noble lord,<br>
Where hateful death put on his ugliest mask<br>
To fright our party.
</p>

<p class="drama">
NORTHUMBERLAND.<br>
How doth my son and brother?<br>
Thou tremblest, and the whiteness in thy cheek<br>
Is apter than thy tongue to tell thy errand.<br>
Even such a man, so faint, so spiritless,<br>
So dull, so dread in look, so woe-begone,<br>
Drew Priam’s curtain in the dead of night,<br>
And would have told him half his Troy was burnt;<br>
But Priam found the fire ere he his tongue,<br>
And I my Percy’s death ere thou report’st it.<br>
This thou wouldst say: “Your son did thus and thus;<br>
Your brother thus; so fought the noble Douglas”<br>
Stopping my greedy ear with their bold deeds:<br>
But in the end, to stop my ear indeed,<br>
Thou hast a sigh to blow away this praise,<br>
Ending with “Brother, son, and all are dead.”
</p>

<p class="drama">
MORTON.<br>
Douglas is living, and your brother, yet;<br>
But, for my lord your son—
</p>

<p class="drama">
NORTHUMBERLAND.<br>
Why, he is dead.<br>
See what a ready tongue suspicion hath!<br>
He that but fears the thing he would not know<br>
Hath by instinct knowledge from others’ eyes<br>
That what he fear’d is chanced. Yet speak, Morton;<br>
Tell thou an earl his divination lies,<br>
And I will take it as a sweet disgrace<br>
And make thee rich for doing me such wrong.
</p>

<p class="drama">
MORTON.<br>
You are too great to be by me gainsaid,<br>
Your spirit is too true, your fears too certain.
</p>

<p class="drama">
NORTHUMBERLAND.<br>
Yet, for all this, say not that Percy’s dead.<br>
I see a strange confession in thine eye.<br>
Thou shakest thy head and hold’st it fear or sin<br>
To speak a truth. If he be slain, say so.<br>
The tongue offends not that reports his death;<br>
And he doth sin that doth belie the dead,<br>
Not he which says the dead is not alive.<br>
Yet the first bringer of unwelcome news<br>
Hath but a losing office, and his tongue<br>
Sounds ever after as a sullen bell,<br>
Remember’d tolling a departing friend.
</p>

<p class="drama">
LORD BARDOLPH.<br>
I cannot think, my lord, your son is dead.
</p>

<p class="drama">
MORTON.<br>
I am sorry I should force you to believe<br>
That which I would to God I had not seen;<br>
But these mine eyes saw him in bloody state,<br>
Rend’ring faint quittance, wearied and outbreathed,<br>
To Harry Monmouth, whose swift wrath beat down<br>
The never-daunted Percy to the earth,<br>
From whence with life he never more sprung up.<br>
In few, his death, whose spirit lent a fire<br>
Even to the dullest peasant in his camp,<br>
Being bruited once, took fire and heat away<br>
From the best-temper’d courage in his troops;<br>
For from his metal was his party steel’d,<br>
Which once in him abated, all the rest<br>
Turn’d on themselves, like dull and heavy lead.<br>
And as the thing that’s heavy in itself<br>
Upon enforcement flies with greatest speed,<br>
So did our men, heavy in Hotspur’s loss,<br>
Lend to this weight such lightness with their fear<br>
That arrows fled not swifter toward their aim<br>
Than did our soldiers, aiming at their safety,<br>
Fly from the field. Then was that noble Worcester<br>
Too soon ta’en prisoner; and that furious Scot,<br>
The bloody Douglas, whose well-labouring sword<br>
Had three times slain th’ appearance of the King,<br>
Gan vail his stomach and did grace the shame<br>
Of those that turn’d their backs, and in his flight,<br>
Stumbling in fear, was took. The sum of all<br>
Is that the King hath won, and hath sent out<br>
A speedy power to encounter you, my lord,<br>
Under the conduct of young Lancaster<br>
And Westmoreland. This is the news at full.
</p>

<p class="drama">
NORTHUMBERLAND.<br>
For this I shall have time enough to mourn.<br>
In poison there is physic; and these news,<br>
Having been well, that would have made me sick,<br>
Being sick, have in some measure made me well.<br>
And as the wretch, whose fever-weaken’d joints,<br>
Like strengthless hinges, buckle under life,<br>
Impatient of his fit, breaks like a fire<br>
Out of his keeper’s arms, even so my limbs,<br>
Weaken’d with grief, being now enraged with grief,<br>
Are thrice themselves. Hence, therefore, thou nice crutch!<br>
A scaly gauntlet now with joints of steel<br>
Must glove this hand. And hence, thou sickly coif!<br>
Thou art a guard too wanton for the head<br>
Which princes, flesh’d with conquest, aim to hit.<br>
Now bind my brows with iron, and approach<br>
The ragged’st hour that time and spite dare bring<br>
To frown upon th’ enraged Northumberland!<br>
Let heaven kiss earth! Now let not Nature’s hand<br>
Keep the wild flood confined! Let order die!<br>
And let this world no longer be a stage<br>
To feed contention in a lingering act;<br>
But let one spirit of the first-born Cain<br>
Reign in all bosoms, that, each heart being set<br>
On bloody courses, the rude scene may end,<br>
And darkness be the burier of the dead!
</p>

<p class="drama">
LORD BARDOLPH.<br>
This strained passion doth you wrong, my lord.
</p>

<p class="drama">
MORTON.<br>
Sweet earl, divorce not wisdom from your honour.<br>
The lives of all your loving complices<br>
Lean on your health; the which, if you give o’er<br>
To stormy passion, must perforce decay.<br>
You cast th’ event of war, my noble lord,<br>
And summ’d the account of chance, before you said<br>
“Let us make head.” It was your presurmise<br>
That in the dole of blows your son might drop.<br>
You knew he walk’d o’er perils, on an edge,<br>
More likely to fall in than to get o’er.<br>
You were advised his flesh was capable<br>
Of wounds and scars, and that his forward spirit<br>
Would lift him where most trade of danger ranged.<br>
Yet did you say “Go forth;” and none of this,<br>
Though strongly apprehended, could restrain<br>
The stiff-borne action. What hath then befall’n,<br>
Or what hath this bold enterprise brought forth,<br>
More than that being which was like to be?
</p>

<p class="drama">
LORD BARDOLPH.<br>
We all that are engaged to this loss<br>
Knew that we ventured on such dangerous seas<br>
That if we wrought out life ’twas ten to one;<br>
And yet we ventured, for the gain proposed<br>
Choked the respect of likely peril fear’d;<br>
And since we are o’erset, venture again.<br>
Come, we will put forth, body and goods.
</p>

<p class="drama">
MORTON.<br>
’Tis more than time. And, my most noble lord,<br>
I hear for certain, and dare speak the truth:<br>
The gentle Archbishop of York is up<br>
With well-appointed powers. He is a man<br>
Who with a double surety binds his followers.<br>
My lord your son had only but the corpse,<br>
But shadows and the shows of men, to fight;<br>
For that same word, “rebellion” did divide<br>
The action of their bodies from their souls,<br>
And they did fight with queasiness, constrain’d,<br>
As men drink potions, that their weapons only<br>
Seem’d on our side; but, for their spirits and souls,<br>
This word, “rebellion,” it had froze them up,<br>
As fish are in a pond. But now the bishop<br>
Turns insurrection to religion.<br>
Supposed sincere and holy in his thoughts,<br>
He’s follow’d both with body and with mind,<br>
And doth enlarge his rising with the blood<br>
Of fair King Richard, scraped from Pomfret stones;<br>
Derives from heaven his quarrel and his cause;<br>
Tells them he doth bestride a bleeding land,<br>
Gasping for life under great Bolingbroke;<br>
And more and less do flock to follow him.
</p>

<p class="drama">
NORTHUMBERLAND.<br>
I knew of this before; but, to speak truth,<br>
This present grief had wiped it from my mind.<br>
Go in with me, and counsel every man<br>
The aptest way for safety and revenge.<br>
Get posts and letters, and make friends with speed.<br>
Never so few, and never yet more need.
</p>

<p class="right"> [<i>Exeunt.</i>]</p>

<h3> <a id="sceneI_10.2"></a><b>SCENE II. London. A street.</b></h3>

<p class="scenedesc">Enter <span class="charname">Falstaff</span>, with his
<span class="charname">Page</span> bearing his sword and buckler.</p>

<p class="drama">
FALSTAFF.<br>
Sirrah, you giant, what says the doctor to my water?
</p>

<p class="drama">
PAGE.<br>
He said, sir, the water itself was a good healthy water; but, for the party
that owed it, he might have moe diseases than he knew for.
</p>

<p class="drama">
FALSTAFF.<br>
Men of all sorts take a pride to gird at me. The brain of this
foolish-compounded clay, man, is not able to invent anything that tends to
laughter more than I invent, or is invented on me. I am not only witty in
myself, but the cause that wit is in other men. I do here walk before thee like
a sow that hath overwhelmed all her litter but one. If the Prince put thee into
my service for any other reason than to set me off, why then I have no
judgement. Thou whoreson mandrake, thou art fitter to be worn in my cap than to
wait at my heels. I was never manned with an agate till now, but I will inset
you neither in gold nor silver, but in vile apparel, and send you back again to
your master, for a jewel,—the juvenal, the Prince your master, whose chin
is not yet fledge. I will sooner have a beard grow in the palm of my hand than
he shall get one off his cheek; and yet he will not stick to say his face is a
face-royal. God may finish it when He will, ’tis not a hair amiss yet. He
may keep it still at a face-royal, for a barber shall never earn sixpence out
of it. And yet he’ll be crowing as if he had writ man ever since his
father was a bachelor. He may keep his own grace, but he’s almost out of
mine, I can assure him. What said Master Dommelton about the satin for my short
cloak and my slops?
</p>

<p class="drama">
PAGE.<br>
He said, sir, you should procure him better assurance than Bardolph. He would
not take his band and yours, he liked not the security.
</p>

<p class="drama">
FALSTAFF.<br>
Let him be damned like the glutton! Pray God his tongue be hotter! A whoreson
Achitophel! A rascally yea-forsooth knave, to bear a gentleman in hand, and
then stand upon security! The whoreson smooth-pates do now wear nothing but
high shoes and bunches of keys at their girdles; and if a man is through with
them in honest taking up, then they must stand upon security. I had as lief
they would put ratsbane in my mouth as offer to stop it with security. I looked
he should have sent me two and twenty yards of satin, as I am a true knight,
and he sends me “security”. Well, he may sleep in security, for he hath the
horn of abundance, and the lightness of his wife shines through it; and yet
cannot he see, though he have his own lanthorn to light him. Where’s Bardolph?
</p>

<p class="drama">
PAGE.<br>
He’s gone into Smithfield to buy your worship a horse.
</p>

<p class="drama">
FALSTAFF.<br>
I bought him in Paul’s, and he’ll buy me a horse in Smithfield. An
I could get me but a wife in the stews, I were manned, horsed, and wived.
</p>

<p class="scenedesc">Enter the <span class="charname">Lord Chief Justice</span> and
<span class="charname">Servant</span>.</p>

<p class="drama">
PAGE.<br>
Sir, here comes the nobleman that committed the Prince for striking him about
Bardolph.
</p>

<p class="drama">
FALSTAFF.<br>
Wait close, I will not see him.
</p>

<p class="drama">
CHIEF JUSTICE.<br>
What’s he that goes there?
</p>

<p class="drama">
SERVANT.<br>
Falstaff, an ’t please your lordship.
</p>

<p class="drama">
CHIEF JUSTICE.<br>
He that was in question for the robbery?
</p>

<p class="drama">
SERVANT.<br>
He, my lord; but he hath since done good service at Shrewsbury, and, as I hear,
is now going with some charge to the Lord John of Lancaster.
</p>

<p class="drama">
CHIEF JUSTICE.<br>
What, to York? Call him back again.
</p>

<p class="drama">
SERVANT.<br>
Sir John Falstaff!
</p>

<p class="drama">
FALSTAFF.<br>
Boy, tell him I am deaf.
</p>

<p class="drama">
PAGE.<br>
You must speak louder, my master is deaf.
</p>

<p class="drama">
CHIEF JUSTICE.<br>
I am sure he is, to the hearing of anything good.<br>
Go pluck him by the elbow, I must speak with him.
</p>

<p class="drama">
SERVANT.<br>
Sir John!
</p>

<p class="drama">
FALSTAFF.<br>
What! A young knave, and begging! Is there not wars? Is there not employment?
Doth not the King lack subjects? Do not the rebels need soldiers? Though it be
a shame to be on any side but one, it is worse shame to beg than to be on the
worst side, were it worse than the name of rebellion can tell how to make it.
</p>

<p class="drama">
SERVANT.<br>
You mistake me, sir.
</p>

<p class="drama">
FALSTAFF.<br>
Why, sir, did I say you were an honest man? Setting my knighthood and my
soldiership aside, I had lied in my throat if I had said so.
</p>

<p class="drama">
SERVANT.<br>
I pray you, sir, then set your knighthood and your soldiership aside, and give
me leave to tell you, you lie in your throat, if you say I am any other than an
honest man.
</p>

<p class="drama">
FALSTAFF.<br>
I give thee leave to tell me so? I lay aside that which grows to me? If thou
get’st any leave of me, hang me; if thou tak’st leave, thou wert
better be hanged. You hunt counter. Hence! Avaunt!
</p>

<p class="drama">
SERVANT.<br>
Sir, my lord would speak with you.
</p>

<p class="drama">
CHIEF JUSTICE.<br>
Sir John Falstaff, a word with you.
</p>

<p class="drama">
FALSTAFF.<br>
My good lord! God give your lordship good time of day. I am glad to see your
lordship abroad. I heard say your lordship was sick. I hope your lordship goes
abroad by advice. Your lordship, though not clean past your youth, hath yet
some smack of age in you, some relish of the saltness of time; and I most
humbly beseech your lordship to have a reverend care of your health.
</p>

<p class="drama">
CHIEF JUSTICE.<br>
Sir John, I sent for you before your expedition to Shrewsbury.
</p>

<p class="drama">
FALSTAFF.<br>
An ’t please your lordship, I hear his Majesty is returned with some
discomfort from Wales.
</p>

<p class="drama">
CHIEF JUSTICE.<br>
I talk not of his Majesty. You would not come when I sent for you.
</p>

<p class="drama">
FALSTAFF.<br>
And I hear, moreover, his Highness is fallen into this same whoreson apoplexy.
</p>

<p class="drama">
CHIEF JUSTICE.<br>
Well, God mend him! I pray you let me speak with you.
</p>

<p class="drama">
FALSTAFF.<br>
This apoplexy, as I take it, is a kind of lethargy, an ’t please your
lordship, a kind of sleeping in the blood, a whoreson tingling.
</p>

<p class="drama">
CHIEF JUSTICE.<br>
What tell you me of it? Be it as it is.
</p>

<p class="drama">
FALSTAFF.<br>
It hath it original from much grief, from study and perturbation of the brain.
I have read the cause of his effects in Galen. It is a kind of deafness.
</p>

<p class="drama">
CHIEF JUSTICE.<br>
I think you are fallen into the disease, for you hear not what I say to you.
</p>

<p class="drama">
FALSTAFF.<br>
Very well, my lord, very well. Rather, an ’t please you, it is the
disease of not listening, the malady of not marking, that I am troubled withal.
</p>

<p class="drama">
CHIEF JUSTICE.<br>
To punish you by the heels would amend the attention of your ears, and I care
not if I do become your physician.
</p>

<p class="drama">
FALSTAFF.<br>
I am as poor as Job, my lord, but not so patient. Your lordship may minister
the potion of imprisonment to me in respect of poverty; but how I should be
your patient to follow your prescriptions, the wise may make some dram of a
scruple, or indeed a scruple itself.
</p>

<p class="drama">
CHIEF JUSTICE.<br>
I sent for you, when there were matters against you for your life, to come
speak with me.
</p>

<p class="drama">
FALSTAFF.<br>
As I was then advised by my learned counsel in the laws of this land-service, I
did not come.
</p>

<p class="drama">
CHIEF JUSTICE.<br>
Well, the truth is, Sir John, you live in great infamy.
</p>

<p class="drama">
FALSTAFF.<br>
He that buckles himself in my belt cannot live in less.
</p>

<p class="drama">
CHIEF JUSTICE.<br>
Your means are very slender, and your waste is great.
</p>

<p class="drama">
FALSTAFF.<br>
I would it were otherwise, I would my means were greater and my waist
slenderer.
</p>

<p class="drama">
CHIEF JUSTICE.<br>
You have misled the youthful prince.
</p>

<p class="drama">
FALSTAFF.<br>
The young prince hath misled me. I am the fellow with the great belly, and he
my dog.
</p>

<p class="drama">
CHIEF JUSTICE.<br>
Well, I am loath to gall a new-healed wound. Your day’s service at
Shrewsbury hath a little gilded over your night’s exploit on
Gad’s Hill. You may thank th’ unquiet time for your quiet
o’er-posting that action.
</p>

<p class="drama">
FALSTAFF.<br>
My lord!
</p>

<p class="drama">
CHIEF JUSTICE.<br>
But since all is well, keep it so: wake not a sleeping wolf.
</p>

<p class="drama">
FALSTAFF.<br>
To wake a wolf is as bad as smell a fox.
</p>

<p class="drama">
CHIEF JUSTICE.<br>
What! You are as a candle, the better part burnt out.
</p>

<p class="drama">
FALSTAFF.<br>
A wassail candle, my lord, all tallow. If I did say of wax, my growth would
approve the truth.
</p>

<p class="drama">
CHIEF JUSTICE.<br>
There is not a white hair in your face but should have his effect of gravity.
</p>

<p class="drama">
FALSTAFF.<br>
His effect of gravy, gravy, gravy.
</p>

<p class="drama">
CHIEF JUSTICE.<br>
You follow the young prince up and down, like his ill angel.
</p>

<p class="drama">
FALSTAFF.<br>
Not so, my lord, your ill angel is light, but I hope he that looks upon me will
take me without weighing. And yet in some respects, I grant, I cannot go. I
cannot tell. Virtue is of so little regard in these costermongers’ times
that true valour is turned bearherd; pregnancy is made a tapster, and hath his
quick wit wasted in giving reckonings. All the other gifts appertinent to man,
as the malice of this age shapes them, are not worth a gooseberry. You that are
old consider not the capacities of us that are young; you do measure the heat
of our livers with the bitterness of your galls, and we that are in the vaward
of our youth, I must confess, are wags too.
</p>

<p class="drama">
CHIEF JUSTICE.<br>
Do you set down your name in the scroll of youth, that are written down old
with all the characters of age? Have you not a moist eye, a dry hand, a yellow
cheek, a white beard, a decreasing leg, an increasing belly? Is not your voice
broken, your wind short, your chin double, your wit single, and every part
about you blasted with antiquity? And will you yet call yourself young? Fie,
fie, fie, Sir John!
</p>

<p class="drama">
FALSTAFF.<br>
My lord, I was born about three of the clock in the afternoon, with a white
head and something a round belly. For my voice, I have lost it with halloing
and singing of anthems. To approve my youth further, I will not. The truth is,
I am only old in judgement and understanding; and he that will caper with me
for a thousand marks, let him lend me the money, and have at him! For the box
of the ear that the Prince gave you, he gave it like a rude prince, and you
took it like a sensible lord. I have checked him for it, and the young lion
repents. Marry, not in ashes and sackcloth, but in new silk and old sack.
</p>

<p class="drama">
CHIEF JUSTICE.<br>
Well, God send the Prince a better companion!
</p>

<p class="drama">
FALSTAFF.<br>
God send the companion a better prince! I cannot rid my hands of him.
</p>

<p class="drama">
CHIEF JUSTICE.<br>
Well, the King hath severed you and Prince Harry. I hear you are going with
Lord John of Lancaster against the Archbishop and the Earl of Northumberland.
</p>

<p class="drama">
FALSTAFF.<br>
Yea, I thank your pretty sweet wit for it. But look you pray, all you that kiss
my lady Peace at home, that our armies join not in a hot day; for, by the Lord,
I take but two shirts out with me, and I mean not to sweat extraordinarily. If
it be a hot day, and I brandish anything but a bottle, I would I might never
spit white again. There is not a dangerous action can peep out his head but I
am thrust upon it. Well, I cannot last ever. But it was alway yet the trick of
our English nation, if they have a good thing, to make it too common. If ye
will needs say I am an old man, you should give me rest. I would to God my name
were not so terrible to the enemy as it is. I were better to be eaten to death
with a rust than to be scoured to nothing with perpetual motion.
</p>

<p class="drama">
CHIEF JUSTICE.<br>
Well, be honest, be honest, and God bless your expedition!
</p>

<p class="drama">
FALSTAFF.<br>
Will your lordship lend me a thousand pound to furnish me forth?
</p>

<p class="drama">
CHIEF JUSTICE.<br>
Not a penny, not a penny; you are too impatient to bear crosses. Fare you well:
commend me to my cousin Westmoreland.
</p>

<p class="right"> [<i>Exeunt <span class="charname">Chief Justice</span> and
<span class="charname">Servant</span>.</i>]</p>

<p class="drama">
FALSTAFF.<br>
If I do, fillip me with a three-man beetle. A man can no more separate age and
covetousness than he can part young limbs and lechery: but the gout galls
the one, and the pox pinches the other; and so both the degrees prevent my
curses. Boy!
</p>

<p class="drama">
PAGE.<br>
Sir?
</p>

<p class="drama">
FALSTAFF.<br>
What money is in my purse?
</p>

<p class="drama">
PAGE.<br>
Seven groats and two pence.
</p>

<p class="drama">
FALSTAFF.<br>
I can get no remedy against this consumption of the purse. Borrowing only
lingers and lingers it out, but the disease is incurable. Go bear this letter
to my Lord of Lancaster; this to the Prince; this to the Earl of Westmoreland;
and this to old Mistress Ursula, whom I have weekly sworn to marry since I
perceived the first white hair of my chin. About it. You know where to find me.
[<i>Exit Page</i>.] A pox of this gout! or a gout of this pox! for the one or the
other plays the rogue with my great toe. ’Tis no matter if I do halt; I
have the wars for my colour, and my pension shall seem the more reasonable. A
good wit will make use of anything. I will turn diseases to commodity.
</p>

<p class="right"> [<i>Exit.</i>]</p>

<h3> <a id="sceneI_10.3"></a><b>SCENE III. York. The Archbishop’s palace.</b></h3>

<p class="scenedesc">Enter the <span class="charname">Archbishop, the Lords
Hastings, Mowbray</span> and <span class="charname">Bardolph</span>.</p>

<p class="drama">
ARCHBISHOP.<br>
Thus have you heard our cause and known our means,<br>
And, my most noble friends, I pray you all<br>
Speak plainly your opinions of our hopes.<br>
And first, Lord Marshal, what say you to it?
</p>

<p class="drama">
MOWBRAY.<br>
I well allow the occasion of our arms,<br>
But gladly would be better satisfied<br>
How in our means we should advance ourselves<br>
To look with forehead bold and big enough<br>
Upon the power and puissance of the King.
</p>

<p class="drama">
HASTINGS.<br>
Our present musters grow upon the file<br>
To five and twenty thousand men of choice;<br>
And our supplies live largely in the hope<br>
Of great Northumberland, whose bosom burns<br>
With an incensed fire of injuries.
</p>

<p class="drama">
LORD BARDOLPH.<br>
The question then, Lord Hastings, standeth thus:<br>
Whether our present five and twenty thousand<br>
May hold up head without Northumberland.
</p>

<p class="drama">
HASTINGS.<br>
With him we may.
</p>

<p class="drama">
LORD BARDOLPH.<br>
Yea, marry, there’s the point:<br>
But if without him we be thought too feeble,<br>
My judgement is, we should not step too far<br>
Till we had his assistance by the hand;<br>
For in a theme so bloody-faced as this<br>
Conjecture, expectation, and surmise<br>
Of aids incertain should not be admitted.
</p>

<p class="drama">
ARCHBISHOP.<br>
’Tis very true, Lord Bardolph, for indeed<br>
It was young Hotspur’s case at Shrewsbury.
</p>

<p class="drama">
LORD BARDOLPH.<br>
It was, my lord; who lined himself with hope,<br>
Eating the air on promise of supply,<br>
Flatt’ring himself in project of a power<br>
Much smaller than the smallest of his thoughts,<br>
And so, with great imagination<br>
Proper to madmen, led his powers to death<br>
And winking leap’d into destruction.
</p>

<p class="drama">
HASTINGS.<br>
But, by your leave, it never yet did hurt<br>
To lay down likelihoods and forms of hope.
</p>

<p class="drama">
LORD BARDOLPH.<br>
Yes, if this present quality of war—<br>
Indeed the instant action, a cause on foot—<br>
Lives so in hope, as in an early spring<br>
We see th’ appearing buds; which to prove fruit<br>
Hope gives not so much warrant as despair<br>
That frosts will bite them. When we mean to build,<br>
We first survey the plot, then draw the model,<br>
And when we see the figure of the house,<br>
Then we must rate the cost of the erection,<br>
Which if we find outweighs ability,<br>
What do we then but draw anew the model<br>
In fewer offices, or at least desist<br>
To build at all? Much more, in this great work,<br>
Which is almost to pluck a kingdom down<br>
And set another up, should we survey<br>
The plot of situation and the model,<br>
Consent upon a sure foundation,<br>
Question surveyors, know our own estate,<br>
How able such a work to undergo,<br>
To weigh against his opposite; or else<br>
We fortify in paper and in figures,<br>
Using the names of men instead of men,<br>
Like one that draws the model of a house<br>
Beyond his power to build it, who, half through,<br>
Gives o’er and leaves his part-created cost<br>
A naked subject to the weeping clouds<br>
And waste for churlish winter’s tyranny.
</p>

<p class="drama">
HASTINGS.<br>
Grant that our hopes, yet likely of fair birth,<br>
Should be still-born, and that we now possess’d<br>
The utmost man of expectation,<br>
I think we are a body strong enough,<br>
Even as we are, to equal with the King.
</p>

<p class="drama">
LORD BARDOLPH.<br>
What, is the King but five and twenty thousand?
</p>

<p class="drama">
HASTINGS.<br>
To us no more; nay, not so much, Lord Bardolph;<br>
For his divisions, as the times do brawl,<br>
Are in three heads: one power against the French,<br>
And one against Glendower; perforce a third<br>
Must take up us. So is the unfirm king<br>
In three divided, and his coffers sound<br>
With hollow poverty and emptiness.
</p>

<p class="drama">
ARCHBISHOP.<br>
That he should draw his several strengths together<br>
And come against us in full puissance<br>
Need not be dreaded.
</p>

<p class="drama">
HASTINGS.<br>
If he should do so,<br>
He leaves his back unarm’d, the French and Welsh<br>
Baying him at the heels: never fear that.
</p>

<p class="drama">
LORD BARDOLPH.<br>
Who is it like should lead his forces hither?
</p>

<p class="drama">
HASTINGS.<br>
The Duke of Lancaster and Westmoreland;<br>
Against the Welsh, himself and Harry Monmouth;<br>
But who is substituted ’gainst the French<br>
I have no certain notice.
</p>

<p class="drama">
ARCHBISHOP.<br>
Let us on,<br>
And publish the occasion of our arms.<br>
The commonwealth is sick of their own choice;<br>
Their over-greedy love hath surfeited.<br>
An habitation giddy and unsure<br>
Hath he that buildeth on the vulgar heart.<br>
O thou fond many, with what loud applause<br>
Didst thou beat heaven with blessing Bolingbroke,<br>
Before he was what thou wouldst have him be!<br>
And being now trimm’d in thine own desires,<br>
Thou, beastly feeder, art so full of him<br>
That thou provok’st thyself to cast him up.<br>
So, so, thou common dog, didst thou disgorge<br>
Thy glutton bosom of the royal Richard;<br>
And now thou wouldst eat thy dead vomit up,<br>
And howl’st to find it. What trust is in these times?<br>
They that, when Richard lived, would have him die<br>
Are now become enamour’d on his grave.<br>
Thou that threw’st dust upon his goodly head<br>
When through proud London he came sighing on<br>
After th’ admired heels of Bolingbroke,<br>
Criest now “O earth, yield us that king again,<br>
And take thou this!” O thoughts of men accursed!<br>
Past and to come seems best; things present, worst.
</p>

<p class="drama">
MOWBRAY.<br>
Shall we go draw our numbers, and set on?
</p>

<p class="drama">
HASTINGS.<br>
We are time’s subjects, and time bids be gone.
</p>

<p class="right"> [<i>Exeunt.</i>]</p>

