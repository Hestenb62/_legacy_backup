<h2> <a id="sceneIV_29.1"></a><b>ACT IV</b></h2>

<h3> <b>SCENE I. London. Before the Tower</b></h3>

<p class="scenedesc">Enter <span class="charname">Queen Elizabeth</span>, the
<span class="charname">Duchess of York</span> and <span class="charname">Marquess of Dorset</span>, at one door; <span class="charname">Anne Duchess of Gloucester</span> with Clarence’s young <span class="charname">Daughter</span> at another door.</p>

<p class="drama">
DUCHESS.<br>
Who meets us here? My niece Plantagenet<br>
Led in the hand of her kind aunt of Gloucester?<br>
Now, for my life, she’s wandering to the Tower,<br>
On pure heart’s love, to greet the tender Prince.<br>
Daughter, well met.
</p>

<p class="drama">
ANNE.<br>
God give your Graces both<br>
A happy and a joyful time of day.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
As much to you, good sister. Whither away?
</p>

<p class="drama">
ANNE.<br>
No farther than the Tower, and, as I guess,<br>
Upon the like devotion as yourselves,<br>
To gratulate the gentle Princes there.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
Kind sister, thanks; we’ll enter all together.
</p>

<p class="scenedesc">Enter <span class="charname">Brakenbury</span>.</p>

<p class="drama">
And in good time, here the Lieutenant comes.<br>
Master Lieutenant, pray you, by your leave,<br>
How doth the Prince and my young son of York?
</p>

<p class="drama">
BRAKENBURY.<br>
Right well, dear madam. By your patience,<br>
I may not suffer you to visit them.<br>
The King hath strictly charged the contrary.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
The King? Who’s that?
</p>

<p class="drama">
BRAKENBURY.<br>
I mean the Lord Protector.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
The Lord protect him from that kingly title!<br>
Hath he set bounds between their love and me?<br>
I am their mother; who shall bar me from them?
</p>

<p class="drama">
DUCHESS.<br>
I am their father’s mother. I will see them.
</p>

<p class="drama">
ANNE.<br>
Their aunt I am in law, in love their mother.<br>
Then bring me to their sights. I’ll bear thy blame,<br>
And take thy office from thee, on my peril.
</p>

<p class="drama">
BRAKENBURY.<br>
No, madam, no. I may not leave it so.<br>
I am bound by oath, and therefore pardon me.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="scenedesc">Enter <span class="charname">Stanley</span>.</p>

<p class="drama">
STANLEY.<br>
Let me but meet you, ladies, one hour hence,<br>
And I’ll salute your Grace of York as mother<br>
And reverend looker-on of two fair queens.<br>
[<i>To Anne.</i>] Come, madam, you must straight to Westminster,<br>
There to be crowned Richard’s royal queen.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
Ah, cut my lace asunder<br>
That my pent heart may have some scope to beat,<br>
Or else I swoon with this dead-killing news!
</p>

<p class="drama">
ANNE.<br>
Despiteful tidings! O unpleasing news!
</p>

<p class="drama">
DORSET.<br>
Be of good cheer, mother. How fares your Grace?
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
O Dorset, speak not to me; get thee gone.<br>
Death and destruction dog thee at thy heels;<br>
Thy mother’s name is ominous to children.<br>
If thou wilt outstrip death, go, cross the seas,<br>
And live with Richmond, from the reach of hell.<br>
Go, hie thee, hie thee from this slaughter-house,<br>
Lest thou increase the number of the dead,<br>
And make me die the thrall of Margaret’s curse,<br>
Nor mother, wife, nor England’s counted Queen.
</p>

<p class="drama">
STANLEY.<br>
Full of wise care is this your counsel, madam.<br>
Take all the swift advantage of the hours;<br>
You shall have letters from me to my son<br>
In your behalf, to meet you on the way.<br>
Be not ta’en tardy by unwise delay.
</p>

<p class="drama">
DUCHESS.<br>
O ill-dispersing wind of misery!<br>
O my accursed womb, the bed of death!<br>
A cockatrice hast thou hatched to the world,<br>
Whose unavoided eye is murderous.
</p>

<p class="drama">
STANLEY.<br>
Come, madam, come. I in all haste was sent.
</p>

<p class="drama">
ANNE.<br>
And I with all unwillingness will go.<br>
O, would to God that the inclusive verge<br>
Of golden metal that must round my brow<br>
Were red-hot steel, to sear me to the brains.<br>
Anointed let me be with deadly venom,<br>
And die ere men can say “God save the Queen.”
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
Go, go, poor soul; I envy not thy glory.<br>
To feed my humour, wish thyself no harm.
</p>

<p class="drama">
ANNE.<br>
No? Why? When he that is my husband now<br>
Came to me as I followed Henry’s corse,<br>
When scarce the blood was well washed from his hands<br>
Which issued from my other angel husband,<br>
And that dear saint which then I weeping followed;<br>
O, when, I say, I looked on Richard’s face,<br>
This was my wish: “Be thou,” quoth I, “accursed<br>
For making me, so young, so old a widow;<br>
And when thou wedd’st, let sorrow haunt thy bed;<br>
And be thy wife, if any be so mad, <br>
More miserable by the life of thee<br>
Than thou hast made me by my dear lord’s death.”<br>
Lo, ere I can repeat this curse again,<br>
Within so small a time, my woman’s heart<br>
Grossly grew captive to his honey words,<br>
And proved the subject of mine own soul’s curse,<br>
Which hitherto hath held my eyes from rest;<br>
For never yet one hour in his bed<br>
Did I enjoy the golden dew of sleep,<br>
But with his timorous dreams was still awaked.<br>
Besides, he hates me for my father Warwick,<br>
And will, no doubt, shortly be rid of me.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
Poor heart, adieu; I pity thy complaining.
</p>

<p class="drama">
ANNE.<br>
No more than with my soul I mourn for yours.
</p>

<p class="drama">
DORSET.<br>
Farewell, thou woeful welcomer of glory.
</p>

<p class="drama">
ANNE.<br>
Adieu, poor soul, that tak’st thy leave of it.
</p>

<p class="drama">
DUCHESS.<br>
[<i>To Dorset.</i>] Go thou to Richmond, and good fortune guide thee.<br>
[<i>To Anne.</i>] Go thou to Richard, and good angels tend thee.<br>
[<i>To Queen Elizabeth.</i>] Go thou to sanctuary, and good thoughts possess thee.<br>
I to my grave, where peace and rest lie with me.<br>
Eighty odd years of sorrow have I seen,<br>
And each hour’s joy wracked with a week of teen.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
Stay, yet look back with me unto the Tower.<br>
Pity, you ancient stones, those tender babes<br>
Whom envy hath immured within your walls—<br>
Rough cradle for such little pretty one,<br>
Rude ragged nurse, old sullen playfellow<br>
For tender princes, use my babies well.<br>
So foolish sorrows bids your stones farewell.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneIV_29.2"></a><b>SCENE II. London. A Room of State in the Palace</b></h3>

<p class="scenedesc">The trumpets sound a sennet. Enter <span class="charname">Richard</span> in pomp, <span class="charname">Buckingham,
Catesby, Ratcliffe, Lovell</span>, a Page and others.</p>

<p class="drama">
KING RICHARD.<br>
Stand all apart. Cousin of Buckingham!
</p>

<p class="drama">
BUCKINGHAM.<br>
My gracious sovereign!
</p>

<p class="drama">
KING RICHARD.<br>
Give me thy hand.
</p>

<p class="right">[<i>Here he ascendeth the throne. Sound trumpets.</i>]</p>

<p class="drama">
Thus high, by thy advice<br>
And thy assistance is King Richard seated.<br>
But shall we wear these glories for a day,<br>
Or shall they last, and we rejoice in them?
</p>

<p class="drama">
BUCKINGHAM.<br>
Still live they, and for ever let them last!
</p>

<p class="drama">
KING RICHARD.<br>
Ah, Buckingham, now do I play the touch,<br>
To try if thou be current gold indeed.<br>
Young Edward lives; think now what I would speak.
</p>

<p class="drama">
BUCKINGHAM.<br>
Say on, my loving lord.
</p>

<p class="drama">
KING RICHARD.<br>
Why, Buckingham, I say I would be King.
</p>

<p class="drama">
BUCKINGHAM.<br>
Why, so you are, my thrice-renowned lord.
</p>

<p class="drama">
KING RICHARD.<br>
Ha! Am I King? ’Tis so—but Edward lives.
</p>

<p class="drama">
BUCKINGHAM.<br>
True, noble Prince.
</p>

<p class="drama">
KING RICHARD.<br>
O bitter consequence,<br>
That Edward still should live “true noble prince!”<br>
Cousin, thou wast not wont to be so dull.<br>
Shall I be plain? I wish the bastards dead,<br>
And I would have it suddenly performed.<br>
What sayst thou now? Speak suddenly, be brief.
</p>

<p class="drama">
BUCKINGHAM.<br>
Your Grace may do your pleasure.
</p>

<p class="drama">
KING RICHARD.<br>
Tut, tut, thou art all ice; thy kindness freezes.<br>
Say, have I thy consent that they shall die?
</p>

<p class="drama">
BUCKINGHAM.<br>
Give me some little breath, some pause, dear lord,<br>
Before I positively speak in this.<br>
I will resolve you herein presently.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
CATESBY.<br>
[<i>Aside</i>.] The King is angry. See, he gnaws his lip.
</p>

<p class="drama">
KING RICHARD.<br>
[<i>Aside</i>.] I will converse with iron-witted fools<br>
And unrespective boys; none are for me<br>
That look into me with considerate eyes.<br>
High-reaching Buckingham grows circumspect.<br>
Boy!
</p>

<p class="drama">
PAGE.<br>
My lord?
</p>

<p class="drama">
KING RICHARD.<br>
Know’st thou not any whom corrupting gold<br>
Will tempt unto a close exploit of death?
</p>

<p class="drama">
PAGE.<br>
I know a discontented gentleman<br>
Whose humble means match not his haughty spirit.<br>
Gold were as good as twenty orators,<br>
And will, no doubt, tempt him to anything.
</p>

<p class="drama">
KING RICHARD.<br>
What is his name?
</p>

<p class="drama">
PAGE.<br>
His name, my lord, is Tyrrel.
</p>

<p class="drama">
KING RICHARD.<br>
I partly know the man. Go, call him hither, boy.
</p>

<p class="right">[<i>Exit <span class="charname">Page</span>.</i>]</p>

<p class="drama">
[<i>Aside</i>.] The deep-revolving witty Buckingham<br>
No more shall be the neighbour to my counsels.<br>
Hath he so long held out with me, untired,<br>
And stops he now for breath? Well, be it so.
</p>

<p class="scenedesc">Enter <span class="charname">Stanley</span>.</p>

<p class="drama">
How now, Lord Stanley, what’s the news?
</p>

<p class="drama">
STANLEY.<br>
Know, my loving lord,<br>
The Marquess Dorset, as I hear, is fled<br>
To Richmond, in the parts where he abides.
</p>

<p class="drama">
KING RICHARD.<br>
Come hither, Catesby. Rumour it abroad<br>
That Anne my wife is very grievous sick;<br>
I will take order for her keeping close.<br>
Inquire me out some mean poor gentleman,<br>
Whom I will marry straight to Clarence’ daughter.<br>
The boy is foolish, and I fear not him.<br>
Look how thou dream’st! I say again, give out<br>
That Anne, my Queen, is sick and like to die.<br>
About it, for it stands me much upon<br>
To stop all hopes whose growth may damage me.
</p>

<p class="right">[<i>Exit <span class="charname">Catesby</span>.</i>]</p>

<p class="drama">
I must be married to my brother’s daughter,<br>
Or else my kingdom stands on brittle glass.<br>
Murder her brothers, and then marry her—<br>
Uncertain way of gain! But I am in<br>
So far in blood that sin will pluck on sin.<br>
Tear-falling pity dwells not in this eye.
</p>

<p class="scenedesc">Enter <span class="charname">Tyrrel</span>.</p>

<p class="drama">
Is thy name Tyrrel?
</p>

<p class="drama">
TYRREL.<br>
James Tyrrel, and your most obedient subject.
</p>

<p class="drama">
KING RICHARD.<br>
Art thou indeed?
</p>

<p class="drama">
TYRREL.<br>
Prove me, my gracious lord.
</p>

<p class="drama">
KING RICHARD.<br>
Dar’st thou resolve to kill a friend of mine?
</p>

<p class="drama">
TYRREL.<br>
Please you. But I had rather kill two enemies.
</p>

<p class="drama">
KING RICHARD.<br>
Why then thou hast it; two deep enemies,<br>
Foes to my rest, and my sweet sleep’s disturbers,<br>
Are they that I would have thee deal upon.<br>
Tyrell, I mean those bastards in the Tower.
</p>

<p class="drama">
TYRREL.<br>
Let me have open means to come to them,<br>
And soon I’ll rid you from the fear of them.
</p>

<p class="drama">
KING RICHARD.<br>
Thou sing’st sweet music. Hark, come hither, Tyrrel.<br>
Go, by this token. Rise, and lend thine ear.<br>
[<i>Whispers</i>.] There is no more but so. Say it is done,<br>
And I will love thee, and prefer thee for it.
</p>

<p class="drama">
TYRREL.<br>
I will dispatch it straight.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="scenedesc">Enter <span class="charname">Buckingham</span>.</p>

<p class="drama">
BUCKINGHAM.<br>
My lord, I have considered in my mind<br>
The late request that you did sound me in.
</p>

<p class="drama">
KING RICHARD.<br>
Well, let that rest. Dorset is fled to Richmond.
</p>

<p class="drama">
BUCKINGHAM.<br>
I hear the news, my lord.
</p>

<p class="drama">
KING RICHARD.<br>
Stanley, he is your wife’s son. Well, look unto it.
</p>

<p class="drama">
BUCKINGHAM.<br>
My lord, I claim the gift, my due by promise,<br>
For which your honour and your faith is pawned:<br>
Th’ earldom of Hereford, and the movables<br>
Which you have promised I shall possess.
</p>

<p class="drama">
KING RICHARD.<br>
Stanley, look to your wife. If she convey<br>
Letters to Richmond, you shall answer it.
</p>

<p class="drama">
BUCKINGHAM.<br>
What says your Highness to my just request?
</p>

<p class="drama">
KING RICHARD.<br>
I do remember me, Henry the Sixth<br>
Did prophesy that Richmond should be King,<br>
When Richmond was a little peevish boy.<br>
A king perhaps—
</p>

<p class="drama">
BUCKINGHAM.<br>
My lord—
</p>

<p class="drama">
KING RICHARD.<br>
How chance the prophet could not at that time<br>
Have told me, I being by, that I should kill him?
</p>

<p class="drama">
BUCKINGHAM.<br>
My lord, your promise for the earldom—
</p>

<p class="drama">
KING RICHARD.<br>
Richmond! When last I was at Exeter,<br>
The Mayor in courtesy showed me the castle<br>
And called it Rougemount, at which name I started,<br>
Because a bard of Ireland told me once<br>
I should not live long after I saw Richmond.
</p>

<p class="drama">
BUCKINGHAM.<br>
My lord—
</p>

<p class="drama">
KING RICHARD.<br>
Ay, what’s o’clock?
</p>

<p class="drama">
BUCKINGHAM.<br>
I am thus bold to put your Grace in mind<br>
Of what you promised me.
</p>

<p class="drama">
KING RICHARD.<br>
Well, but what’s o’clock?
</p>

<p class="drama">
BUCKINGHAM.<br>
Upon the stroke of ten.
</p>

<p class="drama">
KING RICHARD.<br>
Well, let it strike.
</p>

<p class="drama">
BUCKINGHAM.<br>
Why let it strike?
</p>

<p class="drama">
KING RICHARD.<br>
Because that, like a jack, thou keep’st the stroke<br>
Betwixt thy begging and my meditation.<br>
I am not in the giving vein today.
</p>

<p class="drama">
BUCKINGHAM.<br>
Why then, resolve me whether you will or no.
</p>

<p class="drama">
KING RICHARD.<br>
Thou troublest me; I am not in the vein.
</p>

<p class="right">[<i>Exit followed by all save
<span class="charname">Buckingham</span>.</i>]</p>

<p class="drama">
BUCKINGHAM.<br>
And is it thus? Repays he my deep service<br>
With such contempt? Made I him King for this?<br>
O, let me think on Hastings, and be gone<br>
To Brecknock while my fearful head is on!
</p>

<p class="right">[<i>Exit.</i>]</p>

<h3> <a id="sceneIV_29.3"></a><b>SCENE III. London. Another Room in the Palace</b></h3>

<p class="scenedesc">Enter <span class="charname">Tyrrel</span>.</p>

<p class="drama">
TYRREL.<br>
The tyrannous and bloody act is done,<br>
The most arch deed of piteous massacre<br>
That ever yet this land was guilty of.<br>
Dighton and Forrest, who I did suborn<br>
To do this piece of ruthless butchery,<br>
Albeit they were fleshed villains, bloody dogs,<br>
Melted with tenderness and mild compassion,<br>
Wept like two children in their deaths’ sad story.<br>
“O, thus,” quoth Dighton, “lay the gentle babes;”<br>
“Thus, thus,” quoth Forrest, “girdling one another<br>
Within their alabaster innocent arms.<br>
Their lips were four red roses on a stalk,<br>
And in their summer beauty kissed each other.<br>
A book of prayers on their pillow lay,<br>
Which once,” quoth Forrest, “almost changed my mind.<br>
But, O, the devil—” There the villain stopped;<br>
When Dighton thus told on: “We smothered<br>
The most replenished sweet work of nature<br>
That from the prime creation e’er she framed.”<br>
Hence both are gone with conscience and remorse<br>
They could not speak; and so I left them both<br>
To bear this tidings to the bloody King.
</p>

<p class="scenedesc">Enter <span class="charname">King Richard</span>.</p>

<p class="drama">
And here he comes. All health, my sovereign lord.
</p>

<p class="drama">
KING RICHARD.<br>
Kind Tyrrel, am I happy in thy news?
</p>

<p class="drama">
TYRREL.<br>
If to have done the thing you gave in charge<br>
Beget your happiness, be happy then,<br>
For it is done.
</p>

<p class="drama">
KING RICHARD.<br>
But didst thou see them dead?
</p>

<p class="drama">
TYRREL.<br>
I did, my lord.
</p>

<p class="drama">
KING RICHARD.<br>
And buried, gentle Tyrrel?
</p>

<p class="drama">
TYRREL.<br>
The chaplain of the Tower hath buried them,<br>
But where, to say the truth, I do not know.
</p>

<p class="drama">
KING RICHARD.<br>
Come to me, Tyrrel, soon, at after-supper,<br>
When thou shalt tell the process of their death.<br>
Meantime, but think how I may do thee good,<br>
And be inheritor of thy desire.<br>
Farewell till then.
</p>

<p class="drama">
TYRREL.<br>
I humbly take my leave.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
KING RICHARD.<br>
The son of Clarence have I pent up close;<br>
His daughter meanly have I matched in marriage;<br>
The sons of Edward sleep in Abraham’s bosom,<br>
And Anne my wife hath bid the world good night.<br>
Now, for I know the Breton Richmond aims<br>
At young Elizabeth, my brother’s daughter,<br>
And by that knot looks proudly on the crown,<br>
To her go I, a jolly thriving wooer.
</p>

<p class="scenedesc">Enter <span class="charname">Ratcliffe</span>.</p>

<p class="drama">
RATCLIFFE.<br>
My lord!
</p>

<p class="drama">
KING RICHARD.<br>
Good or bad news, that thou com’st in so bluntly?
</p>

<p class="drama">
RATCLIFFE.<br>
Bad news, my lord. Morton is fled to Richmond,<br>
And Buckingham, backed with the hardy Welshmen,<br>
Is in the field, and still his power increaseth.
</p>

<p class="drama">
KING RICHARD.<br>
Ely with Richmond troubles me more near<br>
Than Buckingham and his rash-levied strength.<br>
Come, I have learned that fearful commenting<br>
Is leaden servitor to dull delay;<br>
Delay leads impotent and snail-paced beggary;<br>
Then fiery expedition be my wing,<br>
Jove’s Mercury, and herald for a king!<br>
Go, muster men. My counsel is my shield.<br>
We must be brief when traitors brave the field.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneIV_29.4"></a><b>SCENE IV. London. Before the Palace</b></h3>

<p class="scenedesc">Enter old <span class="charname">Queen Margaret</span>.</p>

<p class="drama">
QUEEN MARGARET.<br>
So now prosperity begins to mellow,<br>
And drop into the rotten mouth of death.<br>
Here in these confines slily have I lurked<br>
To watch the waning of mine enemies.<br>
A dire induction am I witness to,<br>
And will to France, hoping the consequence<br>
Will prove as bitter, black, and tragical.<br>
Withdraw thee, wretched Margaret. Who comes here?
</p>

<p class="right">[<i>Retires.</i>]</p>

<p class="scenedesc">Enter <span class="charname">Duchess of York</span> and
<span class="charname">Queen Elizabeth</span>.</p>

<p class="drama">
QUEEN ELIZABETH.<br>
Ah, my poor Princes! Ah, my tender babes,<br>
My unblown flowers, new-appearing sweets!<br>
If yet your gentle souls fly in the air<br>
And be not fixed in doom perpetual,<br>
Hover about me with your airy wings<br>
And hear your mother’s lamentation.
</p>

<p class="drama">
QUEEN MARGARET.<br>
[<i>Aside</i>.] Hover about her; say that right for right<br>
Hath dimmed your infant morn to aged night.
</p>

<p class="drama">
DUCHESS.<br>
So many miseries have crazed my voice<br>
That my woe-wearied tongue is still and mute.<br>
Edward Plantagenet, why art thou dead?
</p>

<p class="drama">
QUEEN MARGARET.<br>
[<i>Aside</i>.] Plantagenet doth quit Plantagenet;<br>
Edward for Edward pays a dying debt.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
Wilt thou, O God, fly from such gentle lambs,<br>
And throw them in the entrails of the wolf?<br>
When didst Thou sleep when such a deed was done?
</p>

<p class="drama">
QUEEN MARGARET.<br>
[<i>Aside</i>.] When holy Harry died, and my sweet son.
</p>

<p class="drama">
DUCHESS.<br>
Dead life, blind sight, poor mortal living ghost,<br>
Woe’s scene, world’s shame, grave’s due by life
usurped,<br>
Brief abstract and record of tedious days,<br>
Rest thy unrest on England’s lawful earth,<br>
[<i>Sitting</i>.] Unlawfully made drunk with innocent blood.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
Ah, that thou wouldst as soon afford a grave<br>
As thou canst yield a melancholy seat,<br>
Then would I hide my bones, not rest them here.<br>
[<i>Sitting</i>.] Ah, who hath any cause to mourn but we?
</p>

<p class="drama">
QUEEN MARGARET.
</p>

<p class="right">[<i>Coming forward.</i>]</p>

<p class="drama">
If ancient sorrow be most reverend,<br>
Give mine the benefit of seigniory,<br>
And let my griefs frown on the upper hand.<br>
If sorrow can admit society,
</p>

<p class="right">[<i>Sitting down with them.</i>]</p>

<p class="drama">
Tell o’er your woes again by viewing mine.<br>
I had an Edward, till a Richard killed him;<br>
I had a husband, till a Richard killed him.<br>
Thou hadst an Edward, till a Richard killed him;<br>
Thou hadst a Richard, till a Richard killed him.
</p>

<p class="drama">
DUCHESS.<br>
I had a Richard too, and thou didst kill him;<br>
I had a Rutland too; thou holp’st to kill him.
</p>

<p class="drama">
QUEEN MARGARET.<br>
Thou hadst a Clarence too, and Richard killed him.<br>
From forth the kennel of thy womb hath crept<br>
A hell-hound that doth hunt us all to death:<br>
That dog, that had his teeth before his eyes,<br>
To worry lambs and lap their gentle blood;<br>
That excellent grand tyrant of the earth,<br>
That reigns in galled eyes of weeping souls;<br>
That foul defacer of God’s handiwork<br>
Thy womb let loose to chase us to our graves.<br>
O upright, just, and true-disposing God,<br>
How do I thank thee that this carnal cur<br>
Preys on the issue of his mother’s body,<br>
And makes her pew-fellow with others’ moan!
</p>

<p class="drama">
DUCHESS.<br>
O Harry’s wife, triumph not in my woes!<br>
God witness with me, I have wept for thine.
</p>

<p class="drama">
QUEEN MARGARET.<br>
Bear with me. I am hungry for revenge,<br>
And now I cloy me with beholding it.<br>
Thy Edward he is dead, that killed my Edward;<br>
The other Edward dead, to quit my Edward;<br>
Young York, he is but boot, because both they<br>
Matched not the high perfection of my loss.<br>
Thy Clarence he is dead that stabbed my Edward;<br>
And the beholders of this frantic play,<br>
Th’ adulterate Hastings, Rivers, Vaughan, Grey,<br>
Untimely smothered in their dusky graves.<br>
Richard yet lives, hell’s black intelligencer,<br>
Only reserved their factor to buy souls<br>
And send them thither. But at hand, at hand<br>
Ensues his piteous and unpitied end.<br>
Earth gapes, hell burns, fiends roar, saints pray,<br>
To have him suddenly conveyed from hence.<br>
Cancel his bond of life, dear God, I pray,<br>
That I may live to say “The dog is dead.”
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
O, thou didst prophesy the time would come<br>
That I should wish for thee to help me curse<br>
That bottled spider, that foul bunch-backed toad!
</p>

<p class="drama">
QUEEN MARGARET.<br>
I called thee then, vain flourish of my fortune;<br>
I called thee then, poor shadow, painted queen,<br>
The presentation of but what I was,<br>
The flattering index of a direful pageant;<br>
One heaved a-high to be hurled down below,<br>
A mother only mocked with two fair babes;<br>
A dream of what thou wast; a garish flag,<br>
To be the aim of every dangerous shot;<br>
A sign of dignity, a breath, a bubble;<br>
A queen in jest, only to fill the scene.<br>
Where is thy husband now? Where be thy brothers?<br>
Where are thy two sons? Wherein dost thou joy?<br>
Who sues, and kneels, and says, “God save the Queen?”<br>
Where be the bending peers that flattered thee?<br>
Where be the thronging troops that followed thee?<br>
Decline all this, and see what now thou art:<br>
For happy wife, a most distressed widow;<br>
For joyful mother, one that wails the name;<br>
For one being sued to, one that humbly sues;<br>
For Queen, a very caitiff crowned with care;<br>
For she that scorned at me, now scorned of me;<br>
For she being feared of all, now fearing one;<br>
For she commanding all, obeyed of none.<br>
Thus hath the course of justice wheeled about<br>
And left thee but a very prey to time,<br>
Having no more but thought of what thou wast<br>
To torture thee the more, being what thou art.<br>
Thou didst usurp my place, and dost thou not<br>
Usurp the just proportion of my sorrow?<br>
Now thy proud neck bears half my burdened yoke,<br>
From which even here I slip my weary head,<br>
And leave the burden of it all on thee.<br>
Farewell, York’s wife, and Queen of sad mischance.<br>
These English woes shall make me smile in France.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
O thou well skilled in curses, stay awhile,<br>
And teach me how to curse mine enemies.
</p>

<p class="drama">
QUEEN MARGARET.<br>
Forbear to sleep the night, and fast the days;<br>
Compare dead happiness with living woe;<br>
Think that thy babes were sweeter than they were,<br>
And he that slew them fouler than he is.<br>
Bettering thy loss makes the bad-causer worse.<br>
Revolving this will teach thee how to curse.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
My words are dull. O, quicken them with thine!
</p>

<p class="drama">
QUEEN MARGARET.<br>
Thy woes will make them sharp and pierce like mine.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
DUCHESS.<br>
Why should calamity be full of words?
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
Windy attorneys to their clients’ woes,<br>
Airy succeeders of intestate joys,<br>
Poor breathing orators of miseries,<br>
Let them have scope, though what they do impart<br>
Help nothing else, yet do they ease the heart.
</p>

<p class="drama">
DUCHESS.<br>
If so, then be not tongue-tied. Go with me,<br>
And in the breath of bitter words let’s smother<br>
My damned son, that thy two sweet sons smothered.
</p>

<p class="right">[<i>A trumpet sounds.</i>]</p>

<p class="drama">
The trumpet sounds. Be copious in exclaims.
</p>

<p class="scenedesc">Enter <span class="charname">King Richard</span> and his
Train, including <span class="charname">Catesby</span>, marching.</p>

<p class="drama">
KING RICHARD.<br>
Who intercepts me in my expedition?
</p>

<p class="drama">
DUCHESS.<br>
O, she that might have intercepted thee,<br>
By strangling thee in her accursed womb,<br>
From all the slaughters, wretch, that thou hast done.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
Hid’st thou that forehead with a golden crown<br>
Where should be branded, if that right were right,<br>
The slaughter of the Prince that owed that crown,<br>
And the dire death of my poor sons and brothers?<br>
Tell me, thou villain-slave, where are my children?
</p>

<p class="drama">
DUCHESS.<br>
Thou toad, thou toad, where is thy brother Clarence,<br>
And little Ned Plantagenet his son?
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
Where is the gentle Rivers, Vaughan, Grey?
</p>

<p class="drama">
DUCHESS.<br>
Where is kind Hastings?
</p>

<p class="drama">
KING RICHARD.<br>
A flourish, trumpets! Strike alarum, drums!<br>
Let not the heavens hear these tell-tale women<br>
Rail on the Lord’s anointed. Strike, I say!
</p>

<p class="right">[<i>Flourish. Alarums.</i>]</p>

<p class="drama">
Either be patient and entreat me fair,<br>
Or with the clamorous report of war<br>
Thus will I drown your exclamations.
</p>

<p class="drama">
DUCHESS.<br>
Art thou my son?
</p>

<p class="drama">
KING RICHARD.<br>
Ay, I thank God, my father, and yourself.
</p>

<p class="drama">
DUCHESS.<br>
Then patiently hear my impatience.
</p>

<p class="drama">
KING RICHARD.<br>
Madam, I have a touch of your condition,<br>
That cannot brook the accent of reproof.
</p>

<p class="drama">
DUCHESS.<br>
O, let me speak!
</p>

<p class="drama">
KING RICHARD.<br>
Do then, but I’ll not hear.
</p>

<p class="drama">
DUCHESS.<br>
I will be mild and gentle in my words.
</p>

<p class="drama">
KING RICHARD.<br>
And brief, good mother, for I am in haste.
</p>

<p class="drama">
DUCHESS.<br>
Art thou so hasty? I have stayed for thee,<br>
God knows, in torment and in agony.
</p>

<p class="drama">
KING RICHARD.<br>
And came I not at last to comfort you?
</p>

<p class="drama">
DUCHESS.<br>
No, by the Holy Rood, thou know’st it well<br>
Thou cam’st on earth to make the earth my hell.<br>
A grievous burden was thy birth to me;<br>
Tetchy and wayward was thy infancy;<br>
Thy school-days frightful, desp’rate, wild, and furious;<br>
Thy prime of manhood daring, bold, and venturous;<br>
Thy age confirmed, proud, subtle, sly, and bloody,<br>
More mild, but yet more harmful, kind in hatred.<br>
What comfortable hour canst thou name<br>
That ever graced me with thy company?
</p>

<p class="drama">
KING RICHARD.<br>
Faith, none but Humphrey Hower, that called your Grace<br>
To breakfast once, forth of my company.<br>
If I be so disgracious in your eye,<br>
Let me march on and not offend you, madam.<br>
Strike up the drum.
</p>

<p class="drama">
DUCHESS.<br>
I prithee, hear me speak.
</p>

<p class="drama">
KING RICHARD.<br>
You speak too bitterly.
</p>

<p class="drama">
DUCHESS.<br>
Hear me a word,<br>
For I shall never speak to thee again.
</p>

<p class="drama">
KING RICHARD.<br>
So.
</p>

<p class="drama">
DUCHESS.<br>
Either thou wilt die by God’s just ordinance<br>
Ere from this war thou turn a conqueror,<br>
Or I with grief and extreme age shall perish<br>
And never more behold thy face again.<br>
Therefore take with thee my most grievous curse,<br>
Which in the day of battle tire thee more<br>
Than all the complete armour that thou wear’st.<br>
My prayers on the adverse party fight;<br>
And there the little souls of Edward’s children<br>
Whisper the spirits of thine enemies<br>
And promise them success and victory.<br>
Bloody thou art; bloody will be thy end.<br>
Shame serves thy life and doth thy death attend.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
QUEEN ELIZABETH.<br>
Though far more cause, yet much less spirit to curse<br>
Abides in me, I say amen to her.
</p>

<p class="drama">
KING RICHARD.<br>
Stay, madam, I must talk a word with you.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
I have no more sons of the royal blood<br>
For thee to slaughter. For my daughters, Richard,<br>
They shall be praying nuns, not weeping queens,<br>
And therefore level not to hit their lives.
</p>

<p class="drama">
KING RICHARD.<br>
You have a daughter called Elizabeth,<br>
Virtuous and fair, royal and gracious.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
And must she die for this? O, let her live,<br>
And I’ll corrupt her manners, stain her beauty,<br>
Slander myself as false to Edward’s bed,<br>
Throw over her the veil of infamy.<br>
So she may live unscarred of bleeding slaughter,<br>
I will confess she was not Edward’s daughter.
</p>

<p class="drama">
KING RICHARD.<br>
Wrong not her birth; she is a royal princess.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
To save her life I’ll say she is not so.
</p>

<p class="drama">
KING RICHARD.<br>
Her life is safest only in her birth.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
And only in that safety died her brothers.
</p>

<p class="drama">
KING RICHARD.<br>
Lo, at their births good stars were opposite.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
No, to their lives ill friends were contrary.
</p>

<p class="drama">
KING RICHARD.<br>
All unavoided is the doom of destiny.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
True, when avoided grace makes destiny.<br>
My babes were destined to a fairer death,<br>
If grace had blessed thee with a fairer life.
</p>

<p class="drama">
KING RICHARD.<br>
You speak as if that I had slain my cousins.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
Cousins, indeed, and by their uncle cozened<br>
Of comfort, kingdom, kindred, freedom, life.<br>
Whose hand soever lanced their tender hearts,<br>
Thy head, all indirectly, gave direction.<br>
No doubt the murd’rous knife was dull and blunt<br>
Till it was whetted on thy stone-hard heart,<br>
To revel in the entrails of my lambs.<br>
But that still use of grief makes wild grief tame,<br>
My tongue should to thy ears not name my boys<br>
Till that my nails were anchored in thine eyes,<br>
And I, in such a desp’rate bay of death,<br>
Like a poor bark of sails and tackling reft,<br>
Rush all to pieces on thy rocky bosom.
</p>

<p class="drama">
KING RICHARD.<br>
Madam, so thrive I in my enterprise<br>
And dangerous success of bloody wars,<br>
As I intend more good to you and yours<br>
Than ever you or yours by me were harmed!
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
What good is covered with the face of heaven,<br>
To be discovered, that can do me good?
</p>

<p class="drama">
KING RICHARD.<br>
Th’ advancement of your children, gentle lady.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
Up to some scaffold, there to lose their heads.
</p>

<p class="drama">
KING RICHARD.<br>
Unto the dignity and height of fortune,<br>
The high imperial type of this earth’s glory.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
Flatter my sorrows with report of it.<br>
Tell me what state, what dignity, what honour,<br>
Canst thou demise to any child of mine?
</p>

<p class="drama">
KING RICHARD.<br>
Even all I have—ay, and myself and all<br>
Will I withal endow a child of thine;<br>
So in the Lethe of thy angry soul<br>
Thou drown the sad remembrance of those wrongs<br>
Which thou supposest I have done to thee.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
Be brief, lest that the process of thy kindness<br>
Last longer telling than thy kindness’ date.
</p>

<p class="drama">
KING RICHARD.<br>
Then know, that from my soul I love thy daughter.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
My daughter’s mother thinks it with her soul.
</p>

<p class="drama">
KING RICHARD.<br>
What do you think?
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
That thou dost love my daughter from thy soul.<br>
So from thy soul’s love didst thou love her brothers,<br>
And from my heart’s love I do thank thee for it.
</p>

<p class="drama">
KING RICHARD.<br>
Be not so hasty to confound my meaning.<br>
I mean that with my soul I love thy daughter,<br>
And do intend to make her Queen of England.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
Well, then, who dost thou mean shall be her king?
</p>

<p class="drama">
KING RICHARD.<br>
Even he that makes her Queen. Who else should be?
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
What, thou?
</p>

<p class="drama">
KING RICHARD.<br>
Even so. How think you of it?
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
How canst thou woo her?
</p>

<p class="drama">
KING RICHARD.<br>
That would I learn of you,<br>
As one being best acquainted with her humour.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
And wilt thou learn of me?
</p>

<p class="drama">
KING RICHARD.<br>
Madam, with all my heart.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
Send to her, by the man that slew her brothers,<br>
A pair of bleeding hearts; thereon engrave<br>
“Edward” and “York.” Then haply will she weep.<br>
Therefore present to her—as sometimes Margaret<br>
Did to thy father, steeped in Rutland’s blood—<br>
A handkerchief, which, say to her, did drain<br>
The purple sap from her sweet brothers’ body,<br>
And bid her wipe her weeping eyes withal.<br>
If this inducement move her not to love,<br>
Send her a letter of thy noble deeds;<br>
Tell her thou mad’st away her uncle Clarence,<br>
Her uncle Rivers, ay, and for her sake<br>
Mad’st quick conveyance with her good aunt Anne.
</p>

<p class="drama">
KING RICHARD.<br>
You mock me, madam; this is not the way<br>
To win your daughter.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
There is no other way,<br>
Unless thou couldst put on some other shape,<br>
And not be Richard, that hath done all this.
</p>

<p class="drama">
KING RICHARD.<br>
Say that I did all this for love of her?
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
Nay, then indeed she cannot choose but hate thee,<br>
Having bought love with such a bloody spoil.
</p>

<p class="drama">
KING RICHARD.<br>
Look what is done cannot be now amended.<br>
Men shall deal unadvisedly sometimes,<br>
Which after-hours gives leisure to repent.<br>
If I did take the kingdom from your sons,<br>
To make amends I’ll give it to your daughter.<br>
If I have killed the issue of your womb,<br>
To quicken your increase I will beget<br>
Mine issue of your blood upon your daughter.<br>
A grandam’s name is little less in love<br>
Than is the doting title of a mother;<br>
They are as children but one step below,<br>
Even of your mettle, of your very blood;<br>
Of all one pain, save for a night of groans<br>
Endured of her, for whom you bid like sorrow.<br>
Your children were vexation to your youth,<br>
But mine shall be a comfort to your age.<br>
The loss you have is but a son being King,<br>
And by that loss your daughter is made Queen.<br>
I cannot make you what amends I would;<br>
Therefore accept such kindness as I can.<br>
Dorset your son, that with a fearful soul<br>
Leads discontented steps in foreign soil,<br>
This fair alliance quickly shall call home<br>
To high promotions and great dignity.<br>
The King, that calls your beauteous daughter wife,<br>
Familiarly shall call thy Dorset brother;<br>
Again shall you be mother to a king,<br>
And all the ruins of distressful times<br>
Repaired with double riches of content.<br>
What, we have many goodly days to see.<br>
The liquid drops of tears that you have shed<br>
Shall come again, transformed to orient pearl,<br>
Advantaging their loan with interest<br>
Of ten times double gain of happiness.<br>
Go then, my mother, to thy daughter go.<br>
Make bold her bashful years with your experience;<br>
Prepare her ears to hear a wooer’s tale;<br>
Put in her tender heart th’ aspiring flame<br>
Of golden sovereignty; acquaint the Princess<br>
With the sweet silent hours of marriage joys,<br>
And when this arm of mine hath chastised<br>
The petty rebel, dull-brained Buckingham,<br>
Bound with triumphant garlands will I come<br>
And lead thy daughter to a conqueror’s bed;<br>
To whom I will retail my conquest won,<br>
And she shall be sole victoress, Caesar’s Caesar.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
What were I best to say? Her father’s brother<br>
Would be her lord? Or shall I say her uncle?<br>
Or he that slew her brothers and her uncles?<br>
Under what title shall I woo for thee,<br>
That God, the law, my honour, and her love<br>
Can make seem pleasing to her tender years?
</p>

<p class="drama">
KING RICHARD.<br>
Infer fair England’s peace by this alliance.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
Which she shall purchase with still-lasting war.
</p>

<p class="drama">
KING RICHARD.<br>
Tell her the King, that may command, entreats.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
That at her hands, which the King’s King forbids.
</p>

<p class="drama">
KING RICHARD.<br>
Say she shall be a high and mighty queen.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
To vail the title, as her mother doth.
</p>

<p class="drama">
KING RICHARD.<br>
Say I will love her everlastingly.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
But how long shall that title “ever” last?
</p>

<p class="drama">
KING RICHARD.<br>
Sweetly in force unto her fair life’s end.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
But how long fairly shall her sweet life last?
</p>

<p class="drama">
KING RICHARD.<br>
As long as heaven and nature lengthens it.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
As long as hell and Richard likes of it.
</p>

<p class="drama">
KING RICHARD.<br>
Say I, her sovereign, am her subject low.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
But she, your subject, loathes such sovereignty.
</p>

<p class="drama">
KING RICHARD.<br>
Be eloquent in my behalf to her.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
An honest tale speeds best being plainly told.
</p>

<p class="drama">
KING RICHARD.<br>
Then plainly to her tell my loving tale.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
Plain and not honest is too harsh a style.
</p>

<p class="drama">
KING RICHARD.<br>
Your reasons are too shallow and too quick.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
O no, my reasons are too deep and dead—<br>
Too deep and dead, poor infants, in their graves.
</p>

<p class="drama">
KING RICHARD.<br>
Harp not on that string, madam; that is past.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
Harp on it still shall I till heart-strings break.
</p>

<p class="drama">
KING RICHARD.<br>
Now, by my George, my Garter, and my crown—
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
Profaned, dishonoured, and the third usurped.
</p>

<p class="drama">
KING RICHARD.<br>
I swear—
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
By nothing, for this is no oath.<br>
Thy George, profaned, hath lost his lordly honour;<br>
Thy Garter, blemished, pawned his knightly virtue;<br>
Thy crown, usurped, disgraced his kingly glory.<br>
If something thou wouldst swear to be believed,<br>
Swear then by something that thou hast not wronged.
</p>

<p class="drama">
KING RICHARD.<br>
Now, by the world—
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
’Tis full of thy foul wrongs.
</p>

<p class="drama">
KING RICHARD.<br>
My father’s death—
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
Thy life hath that dishonoured.
</p>

<p class="drama">
KING RICHARD.<br>
Then, by myself—
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
Thyself is self-misused.
</p>

<p class="drama">
KING RICHARD.<br>
Why, then, by God—
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
God’s wrong is most of all.<br>
If thou didst fear to break an oath with Him,<br>
The unity the King my husband made<br>
Thou hadst not broken, nor my brothers died.<br>
If thou hadst feared to break an oath by Him,<br>
Th’ imperial metal circling now thy head<br>
Had graced the tender temples of my child,<br>
And both the Princes had been breathing here,<br>
Which now, two tender bedfellows for dust,<br>
Thy broken faith hath made a prey for worms.<br>
What canst thou swear by now?
</p>

<p class="drama">
KING RICHARD.<br>
The time to come.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
That thou hast wronged in the time o’erpast;<br>
For I myself have many tears to wash<br>
Hereafter time, for time past wronged by thee.<br>
The children live whose fathers thou hast slaughtered,<br>
Ungoverned youth, to wail it in their age;<br>
The parents live whose children thou hast butchered,<br>
Old barren plants, to wail it with their age.<br>
Swear not by time to come, for that thou hast<br>
Misused ere used, by times ill-used o’erpast.
</p>

<p class="drama">
KING RICHARD.<br>
As I intend to prosper and repent,<br>
So thrive I in my dangerous affairs<br>
Of hostile arms! Myself myself confound!<br>
Heaven and fortune bar me happy hours!<br>
Day, yield me not thy light, nor, night, thy rest!<br>
Be opposite all planets of good luck<br>
To my proceeding if with dear heart’s love,<br>
Immaculate devotion, holy thoughts,<br>
I tender not thy beauteous princely daughter.<br>
In her consists my happiness and thine;<br>
Without her follows to myself and thee,<br>
Herself, the land, and many a Christian soul,<br>
Death, desolation, ruin, and decay.<br>
It cannot be avoided but by this;<br>
It will not be avoided but by this.<br>
Therefore, dear mother—I must call you so—<br>
Be the attorney of my love to her;<br>
Plead what I will be, not what I have been;<br>
Not my deserts, but what I will deserve.<br>
Urge the necessity and state of times,<br>
And be not peevish found in great designs.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
Shall I be tempted of the devil thus?
</p>

<p class="drama">
KING RICHARD.<br>
Ay, if the devil tempt you to do good.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
Shall I forget myself to be myself?
</p>

<p class="drama">
KING RICHARD.<br>
Ay, if your self’s remembrance wrong yourself.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
Yet thou didst kill my children.
</p>

<p class="drama">
KING RICHARD.<br>
But in your daughter’s womb I bury them,<br>
Where, in that nest of spicery, they will breed<br>
Selves of themselves, to your recomforture.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
Shall I go win my daughter to thy will?
</p>

<p class="drama">
KING RICHARD.<br>
And be a happy mother by the deed.
</p>

<p class="drama">
QUEEN ELIZABETH.<br>
I go. Write to me very shortly,<br>
And you shall understand from me her mind.
</p>

<p class="drama">
KING RICHARD.<br>
Bear her my true love’s kiss; and so, farewell.
</p>

<p class="right">[<i>Kissing her. Exit <span class="charname">Queen Elizabeth</span>.</i>]</p>

<p class="drama">
Relenting fool, and shallow, changing woman!
</p>

<p class="scenedesc">Enter <span class="charname">Ratcliffe</span>.</p>

<p class="drama">
How now, what news?
</p>

<p class="drama">
RATCLIFFE.<br>
Most mighty sovereign, on the western coast<br>
Rideth a puissant navy; to our shores<br>
Throng many doubtful hollow-hearted friends,<br>
Unarmed, and unresolved to beat them back.<br>
’Tis thought that Richmond is their admiral;<br>
And there they hull, expecting but the aid<br>
Of Buckingham to welcome them ashore.
</p>

<p class="drama">
KING RICHARD.<br>
Some light-foot friend post to the Duke of Norfolk.<br>
Ratcliffe, thyself, or Catesby. Where is he?
</p>

<p class="drama">
CATESBY.<br>
Here, my good lord.
</p>

<p class="drama">
KING RICHARD.<br>
Catesby, fly to the Duke.
</p>

<p class="drama">
CATESBY.<br>
I will my lord, with all convenient haste.
</p>

<p class="drama">
KING RICHARD.<br>
Ratcliffe, come hither. Post to Salisbury.<br>
When thou com’st thither—<br>
[<i>To Catesby.</i>] Dull, unmindful villain,<br>
Why stay’st thou here, and go’st not to the Duke?
</p>

<p class="drama">
CATESBY.<br>
First, mighty liege, tell me your Highness’ pleasure,<br>
What from your Grace I shall deliver to him.
</p>

<p class="drama">
KING RICHARD.<br>
O, true, good Catesby. Bid him levy straight<br>
The greatest strength and power that he can make,<br>
And meet me suddenly at Salisbury.
</p>

<p class="drama">
CATESBY.<br>
I go.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
RATCLIFFE.<br>
What, may it please you, shall I do at Salisbury?
</p>

<p class="drama">
KING RICHARD.<br>
Why, what wouldst thou do there before I go?
</p>

<p class="drama">
RATCLIFFE.<br>
Your Highness told me I should post before.
</p>

<p class="drama">
KING RICHARD.<br>
My mind is changed.
</p>

<p class="scenedesc">Enter <span class="charname">Stanley</span> Earl of Derby.</p>

<p class="drama">
Stanley, what news with you?
</p>

<p class="drama">
STANLEY.<br>
None good, my liege, to please you with the hearing;<br>
Nor none so bad but well may be reported.
</p>

<p class="drama">
KING RICHARD.<br>
Hoyday, a riddle! Neither good nor bad.<br>
What need’st thou run so many miles about<br>
When thou mayst tell thy tale the nearest way?<br>
Once more, what news?
</p>

<p class="drama">
STANLEY.<br>
Richmond is on the seas.
</p>

<p class="drama">
KING RICHARD.<br>
There let him sink, and be the seas on him!<br>
White-livered runagate, what doth he there?
</p>

<p class="drama">
STANLEY.<br>
I know not, mighty sovereign, but by guess.
</p>

<p class="drama">
KING RICHARD.<br>
Well, as you guess?
</p>

<p class="drama">
STANLEY.<br>
Stirred up by Dorset, Buckingham, and Morton,<br>
He makes for England, here to claim the crown.
</p>

<p class="drama">
KING RICHARD.<br>
Is the chair empty? Is the sword unswayed?<br>
Is the King dead? The empire unpossessed?<br>
What heir of York is there alive but we?<br>
And who is England’s King but great York’s heir?<br>
Then tell me, what makes he upon the seas?
</p>

<p class="drama">
STANLEY.<br>
Unless for that, my liege, I cannot guess.
</p>

<p class="drama">
KING RICHARD.<br>
Unless for that he comes to be your liege,<br>
You cannot guess wherefore the Welshman comes.<br>
Thou wilt revolt and fly to him, I fear.
</p>

<p class="drama">
STANLEY.<br>
No, my good lord; therefore mistrust me not.
</p>

<p class="drama">
KING RICHARD.<br>
Where is thy power, then, to beat him back?<br>
Where be thy tenants and thy followers?<br>
Are they not now upon the western shore,<br>
Safe-conducting the rebels from their ships?
</p>

<p class="drama">
STANLEY.<br>
No, my good lord, my friends are in the north.
</p>

<p class="drama">
KING RICHARD.<br>
Cold friends to me. What do they in the north,<br>
When they should serve their sovereign in the west?
</p>

<p class="drama">
STANLEY.<br>
They have not been commanded, mighty King.<br>
Pleaseth your Majesty to give me leave,<br>
I’ll muster up my friends, and meet your Grace<br>
Where and what time your Majesty shall please.
</p>

<p class="drama">
KING RICHARD.<br>
Ay, ay, thou wouldst be gone to join with Richmond.<br>
But I’ll not trust thee.
</p>

<p class="drama">
STANLEY.<br>
Most mighty sovereign,<br>
You have no cause to hold my friendship doubtful.<br>
I never was nor never will be false.
</p>

<p class="drama">
KING RICHARD.<br>
Go then, and muster men, but leave behind<br>
Your son George Stanley. Look your heart be firm,<br>
Or else his head’s assurance is but frail.
</p>

<p class="drama">
STANLEY.<br>
So deal with him as I prove true to you.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="scenedesc">Enter a <span class="charname">Messenger</span>.</p>

<p class="drama">
MESSENGER.<br>
My gracious sovereign, now in Devonshire,<br>
As I by friends am well advertised,<br>
Sir Edward Courtney, and the haughty prelate,<br>
Bishop of Exeter, his elder brother,<br>
With many more confederates, are in arms.
</p>

<p class="scenedesc">Enter another <span class="charname">Messenger</span>.</p>

<p class="drama">
SECOND MESSENGER.<br>
In Kent, my liege, the Guilfords are in arms,<br>
And every hour more competitors<br>
Flock to the rebels, and their power grows strong.
</p>

<p class="scenedesc">Enter another <span class="charname">Messenger</span>.</p>

<p class="drama">
THIRD MESSENGER.<br>
My lord, the army of great Buckingham—
</p>

<p class="drama">
KING RICHARD.<br>
Out on you, owls! Nothing but songs of death?
</p>

<p class="right">[<i>He strikes him.</i>]</p>

<p class="drama">
There, take thou that till thou bring better news.
</p>

<p class="drama">
THIRD MESSENGER.<br>
The news I have to tell your Majesty<br>
Is, that by sudden floods and fall of waters,<br>
Buckingham’s army is dispersed and scattered,<br>
And he himself wandered away alone,<br>
No man knows whither.
</p>

<p class="drama">
KING RICHARD.<br>
I cry thee mercy.<br>
There is my purse to cure that blow of thine.<br>
Hath any well-advised friend proclaimed<br>
Reward to him that brings the traitor in?
</p>

<p class="drama">
THIRD MESSENGER.<br>
Such proclamation hath been made, my lord.
</p>

<p class="scenedesc">Enter another <span class="charname">Messenger</span>.</p>

<p class="drama">
FOURTH MESSENGER.<br>
Sir Thomas Lovell and Lord Marquess Dorset,<br>
’Tis said, my liege, in Yorkshire are in arms.<br>
But this good comfort bring I to your Highness:<br>
The Breton navy is dispersed by tempest.<br>
Richmond, in Dorsetshire, sent out a boat<br>
Unto the shore, to ask those on the banks<br>
If they were his assistants, yea or no?—<br>
Who answered him they came from Buckingham<br>
Upon his party. He, mistrusting them,<br>
Hoised sail, and made his course again for Brittany.
</p>

<p class="drama">
KING RICHARD.<br>
March on, march on, since we are up in arms,<br>
If not to fight with foreign enemies,<br>
Yet to beat down these rebels here at home.
</p>

<p class="scenedesc">Enter <span class="charname">Catesby</span>.</p>

<p class="drama">
CATESBY.<br>
My liege, the Duke of Buckingham is taken.<br>
That is the best news. That the Earl of Richmond<br>
Is with a mighty power landed at Milford<br>
Is colder tidings, yet they must be told.
</p>

<p class="drama">
KING RICHARD.<br>
Away towards Salisbury! While we reason here<br>
A royal battle might be won and lost.<br>
Someone take order Buckingham be brought<br>
To Salisbury; the rest march on with me.
</p>

<p class="right">[<i>Flourish. Exeunt.</i>]</p>

<h3> <a id="sceneIV_29.5"></a><b>SCENE V. A Room in Lord Stanley’s house</b></h3>

<p class="scenedesc">Enter <span class="charname">Stanley</span> Earl of Derby and
<span class="charname">Sir Christopher Urswick</span>.</p>

<p class="drama">
STANLEY.<br>
Sir Christopher, tell Richmond this from me:<br>
That in the sty of the most deadly boar<br>
My son George Stanley is franked up in hold;<br>
If I revolt, off goes young George’s head;<br>
The fear of that holds off my present aid.<br>
So get thee gone. Commend me to thy lord;<br>
Withal say that the Queen hath heartily consented<br>
He should espouse Elizabeth her daughter.<br>
But tell me, where is princely Richmond now?
</p>

<p class="drama">
CHRISTOPHER.<br>
At Pembroke, or at Ha’rfordwest in Wales.
</p>

<p class="drama">
STANLEY.<br>
What men of name resort to him?
</p>

<p class="drama">
CHRISTOPHER.<br>
Sir Walter Herbert, a renowned soldier;<br>
Sir Gilbert Talbot, Sir William Stanley,<br>
Oxford, redoubted Pembroke, Sir James Blunt,<br>
And Rice ap Thomas, with a valiant crew,<br>
And many other of great name and worth;<br>
And towards London do they bend their power,<br>
If by the way they be not fought withal.
</p>

<p class="drama">
STANLEY.<br>
Well, hie thee to thy lord; I kiss his hand.<br>
My letter will resolve him of my mind.<br>
Farewell.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

