<h2> <a id="sceneV_21.1"></a><b>ACT V</b></h2>

<h3> <b>SCENE I. A public place near the city gate.</b></h3>

<p class="scenedesc">
Enter at several doors <span class="charname">Duke,
Varrius,</span> Lords; <span class="charname">Angelo, Escalus, Lucio,
Provost,</span> Officers and Citizens.
</p>

<p class="drama">
DUKE.<br>
My very worthy cousin, fairly met.<br>
Our old and faithful friend, we are glad to see you.
</p>

<p class="drama">
ANGELO and ESCALUS.<br>
Happy return be to your royal grace!
</p>

<p class="drama">
DUKE.<br>
Many and hearty thankings to you both.<br>
We have made inquiry of you, and we hear<br>
Such goodness of your justice that our soul<br>
Cannot but yield you forth to public thanks,<br>
Forerunning more requital.
</p>

<p class="drama">
ANGELO.<br>
You make my bonds still greater.
</p>

<p class="drama">
DUKE.<br>
O, your desert speaks loud, and I should wrong it<br>
To lock it in the wards of covert bosom,<br>
When it deserves with characters of brass<br>
A forted residence ’gainst the tooth of time<br>
And rasure of oblivion. Give me your hand<br>
And let the subject see, to make them know<br>
That outward courtesies would fain proclaim<br>
Favours that keep within.—Come, Escalus,<br>
You must walk by us on our other hand.<br>
And good supporters are you.
</p>

<p class="scenedesc">
Enter <span class="charname">Friar Peter</span> and
<span class="charname">Isabella</span>.
</p>

<p class="drama">
FRIAR PETER.<br>
Now is your time. Speak loud, and kneel before him.
</p>

<p class="drama">
ISABELLA.<br>
Justice, O royal Duke! Vail your regard<br>
Upon a wronged—I would fain have said, a maid.<br>
O worthy prince, dishonour not your eye<br>
By throwing it on any other object<br>
Till you have heard me in my true complaint,<br>
And given me justice, justice, justice, justice!
</p>

<p class="drama">
DUKE.<br>
Relate your wrongs. In what? By whom? Be brief.<br>
Here is Lord Angelo shall give you justice.<br>
Reveal yourself to him.
</p>

<p class="drama">
ISABELLA.<br>
O worthy Duke,<br>
You bid me seek redemption of the devil.<br>
Hear me yourself, for that which I must speak<br>
Must either punish me, not being believed,<br>
Or wring redress from you. Hear me, O hear me, here!
</p>

<p class="drama">
ANGELO.<br>
My lord, her wits, I fear me, are not firm.<br>
She hath been a suitor to me for her brother,<br>
Cut off by course of justice.
</p>

<p class="drama">
ISABELLA.<br>
By course of justice!
</p>

<p class="drama">
ANGELO.<br>
And she will speak most bitterly and strange.
</p>

<p class="drama">
ISABELLA.<br>
Most strange, but yet most truly will I speak.<br>
That Angelo’s forsworn, is it not strange?<br>
That Angelo’s a murderer, is’t not strange?<br>
That Angelo is an adulterous thief,<br>
An hypocrite, a virgin-violator,<br>
Is it not strange and strange?
</p>

<p class="drama">
DUKE.<br>
Nay, it is ten times strange.
</p>

<p class="drama">
ISABELLA.<br>
It is not truer he is Angelo<br>
Than this is all as true as it is strange.<br>
Nay, it is ten times true, for truth is truth<br>
To th’ end of reckoning.
</p>

<p class="drama">
DUKE.<br>
Away with her. Poor soul,<br>
She speaks this in th’ infirmity of sense.
</p>

<p class="drama">
ISABELLA.<br>
O Prince, I conjure thee, as thou believ’st<br>
There is another comfort than this world,<br>
That thou neglect me not with that opinion<br>
That I am touched with madness. Make not impossible<br>
That which but seems unlike. ’Tis not impossible<br>
But one, the wicked’st caitiff on the ground,<br>
May seem as shy, as grave, as just, as absolute,<br>
As Angelo; even so may Angelo,<br>
In all his dressings, characts, titles, forms,<br>
Be an arch-villain. Believe it, royal Prince,<br>
If he be less, he’s nothing; but he’s more,<br>
Had I more name for badness.
</p>

<p class="drama">
DUKE.<br>
By mine honesty,<br>
If she be mad, as I believe no other,<br>
Her madness hath the oddest frame of sense,<br>
Such a dependency of thing on thing,<br>
As e’er I heard in madness.
</p>

<p class="drama">
ISABELLA.<br>
O gracious Duke,<br>
Harp not on that; nor do not banish reason<br>
For inequality; but let your reason serve<br>
To make the truth appear where it seems hid,<br>
And hide the false seems true.
</p>

<p class="drama">
DUKE.<br>
Many that are not mad<br>
Have, sure, more lack of reason. What would you say?
</p>

<p class="drama">
ISABELLA.<br>
I am the sister of one Claudio,<br>
Condemned upon the act of fornication<br>
To lose his head; condemned by Angelo.<br>
I, in probation of a sisterhood,<br>
Was sent to by my brother; one Lucio<br>
As then the messenger.
</p>

<p class="drama">
LUCIO.<br>
That’s I, an’t like your Grace.<br>
I came to her from Claudio and desired her<br>
To try her gracious fortune with Lord Angelo<br>
For her poor brother’s pardon.
</p>

<p class="drama">
ISABELLA.<br>
That’s he, indeed.
</p>

<p class="drama">
DUKE.<br>
You were not bid to speak.
</p>

<p class="drama">
LUCIO.<br>
No, my good lord,<br>
Nor wished to hold my peace.
</p>

<p class="drama">
DUKE.<br>
I wish you now, then;<br>
Pray you take note of it; and when you have<br>
A business for yourself, pray heaven you then<br>
Be perfect.
</p>

<p class="drama">
LUCIO.<br>
I warrant your honour.
</p>

<p class="drama">
DUKE.<br>
The warrant’s for yourself. Take heed to it.
</p>

<p class="drama">
ISABELLA.<br>
This gentleman told somewhat of my tale.
</p>

<p class="drama">
LUCIO.<br>
Right.
</p>

<p class="drama">
DUKE.<br>
It may be right, but you are i’ the wrong<br>
To speak before your time.—Proceed.
</p>

<p class="drama">
ISABELLA.<br>
I went<br>
To this pernicious caitiff deputy.
</p>

<p class="drama">
DUKE.<br>
That’s somewhat madly spoken.
</p>

<p class="drama">
ISABELLA.<br>
Pardon it;<br>
The phrase is to the matter.
</p>

<p class="drama">
DUKE.<br>
Mended again. The matter; proceed.
</p>

<p class="drama">
ISABELLA.<br>
In brief, to set the needless process by:<br>
How I persuaded, how I prayed and kneeled,<br>
How he refelled me, and how I replied—<br>
For this was of much length—the vile conclusion<br>
I now begin with grief and shame to utter.<br>
He would not, but by gift of my chaste body<br>
To his concupiscible intemperate lust,<br>
Release my brother; and after much debatement,<br>
My sisterly remorse confutes mine honour,<br>
And I did yield to him. But the next morn betimes,<br>
His purpose surfeiting, he sends a warrant<br>
For my poor brother’s head.
</p>

<p class="drama">
DUKE.<br>
This is most likely!
</p>

<p class="drama">
ISABELLA.<br>
O, that it were as like as it is true!
</p>

<p class="drama">
DUKE.<br>
By heaven, fond wretch, thou know’st not what thou speak’st,<br>
Or else thou art suborned against his honour<br>
In hateful practice. First, his integrity<br>
Stands without blemish; next, it imports no reason<br>
That with such vehemency he should pursue<br>
Faults proper to himself. If he had so offended,<br>
He would have weighed thy brother by himself,<br>
And not have cut him off. Someone hath set you on.<br>
Confess the truth, and say by whose advice<br>
Thou cam’st here to complain.
</p>

<p class="drama">
ISABELLA.<br>
And is this all?<br>
Then, O you blessed ministers above,<br>
Keep me in patience, and with ripened time<br>
Unfold the evil which is here wrapt up<br>
In countenance! Heaven shield your Grace from woe,<br>
As I, thus wronged, hence unbelieved go.
</p>

<p class="drama">
DUKE.<br>
I know you’d fain be gone. An officer!<br>
To prison with her! Shall we thus permit<br>
A blasting and a scandalous breath to fall<br>
On him so near us? This needs must be a practice.<br>
Who knew of your intent and coming hither?
</p>

<p class="drama">
ISABELLA.<br>
One that I would were here, Friar Lodowick.
</p>

<p class="right">
[<i>Exeunt Officer with <span class="charname">Isabella</span>.</i>]
</p>

<p class="drama">
DUKE.<br>
A ghostly father, belike. Who knows that Lodowick?
</p>

<p class="drama">
LUCIO.<br>
My lord, I know him. ’Tis a meddling friar.<br>
I do not like the man. Had he been lay, my lord,<br>
For certain words he spake against your Grace<br>
In your retirement, I had swinged him soundly.
</p>

<p class="drama">
DUKE.<br>
Words against me? This’s a good friar, belike.<br>
And to set on this wretched woman here<br>
Against our substitute! Let this friar be found.
</p>

<p class="drama">
LUCIO.<br>
But yesternight, my lord, she and that friar,<br>
I saw them at the prison. A saucy friar,<br>
A very scurvy fellow.
</p>

<p class="drama">
FRIAR PETER.<br>
Blessed be your royal Grace!<br>
I have stood by, my lord, and I have heard<br>
Your royal ear abused. First hath this woman<br>
Most wrongfully accused your substitute,<br>
Who is as free from touch or soil with her<br>
As she from one ungot.
</p>

<p class="drama">
DUKE.<br>
We did believe no less.<br>
Know you that Friar Lodowick that she speaks of?
</p>

<p class="drama">
FRIAR PETER.<br>
I know him for a man divine and holy,<br>
Not scurvy, nor a temporary meddler,<br>
As he’s reported by this gentleman;<br>
And, on my trust, a man that never yet<br>
Did, as he vouches, misreport your Grace.
</p>

<p class="drama">
LUCIO.<br>
My lord, most villainously; believe it.
</p>

<p class="drama">
FRIAR PETER.<br>
Well, he in time may come to clear himself;<br>
But at this instant he is sick, my lord,<br>
Of a strange fever. Upon his mere request,<br>
Being come to knowledge that there was complaint<br>
Intended ’gainst Lord Angelo, came I hither<br>
To speak, as from his mouth, what he doth know<br>
Is true and false; and what he with his oath<br>
And all probation will make up full clear<br>
Whensoever he’s convented. First, for this woman,<br>
To justify this worthy nobleman,<br>
So vulgarly and personally accused,<br>
Her shall you hear disproved to her eyes,<br>
Till she herself confess it.
</p>

<p class="drama">
DUKE.<br>
Good friar, let’s hear it.<br>
Do you not smile at this, Lord Angelo?<br>
O heaven, the vanity of wretched fools!<br>
Give us some seats.—Come, cousin Angelo,<br>
In this I’ll be impartial. Be you judge<br>
Of your own cause.
</p>

<p class="scenedesc">
Enter <span class="charname">Mariana,</span> veiled.
</p>

<p class="drama">
Is this the witness, friar?<br>
First let her show her face, and after speak.
</p>

<p class="drama">
MARIANA.<br>
Pardon, my lord; I will not show my face<br>
Until my husband bid me.
</p>

<p class="drama">
DUKE.<br>
What, are you married?
</p>

<p class="drama">
MARIANA.<br>
No, my lord.
</p>

<p class="drama">
DUKE.<br>
Are you a maid?
</p>

<p class="drama">
MARIANA.<br>
No, my lord.
</p>

<p class="drama">
DUKE.<br>
A widow, then?
</p>

<p class="drama">
MARIANA.<br>
Neither, my lord.
</p>

<p class="drama">
DUKE.<br>
Why, you are nothing then, neither maid, widow, nor wife?
</p>

<p class="drama">
LUCIO.<br>
My lord, she may be a punk; for many of them are neither maid, widow, nor wife.
</p>

<p class="drama">
DUKE.<br>
Silence that fellow. I would he had some cause to prattle for himself.
</p>

<p class="drama">
LUCIO.<br>
Well, my lord.
</p>

<p class="drama">
MARIANA.<br>
My lord, I do confess I ne’er was married,<br>
And I confess besides, I am no maid.<br>
I have known my husband; yet my husband<br>
Knows not that ever he knew me.
</p>

<p class="drama">
LUCIO.<br>
He was drunk, then, my lord; it can be no better.
</p>

<p class="drama">
DUKE.<br>
For the benefit of silence, would thou wert so too.
</p>

<p class="drama">
LUCIO.<br>
Well, my lord.
</p>

<p class="drama">
DUKE.<br>
This is no witness for Lord Angelo.
</p>

<p class="drama">
MARIANA.<br>
Now I come to’t, my lord.<br>
She that accuses him of fornication<br>
In self-same manner doth accuse my husband,<br>
And charges him, my lord, with such a time<br>
When I’ll depose I had him in mine arms<br>
With all th’ effect of love.
</p>

<p class="drama">
ANGELO.<br>
Charges she more than me?
</p>

<p class="drama">
MARIANA.<br>
Not that I know.
</p>

<p class="drama">
DUKE.<br>
No? You say your husband.
</p>

<p class="drama">
MARIANA.<br>
Why, just, my lord, and that is Angelo,<br>
Who thinks he knows that he ne’er knew my body,<br>
But knows, he thinks, that he knows Isabel’s.
</p>

<p class="drama">
ANGELO.<br>
This is a strange abuse. Let’s see thy face.
</p>

<p class="drama">
MARIANA.<br>
My husband bids me; now I will unmask. [<i>Unveiling</i>.]<br>
This is that face, thou cruel Angelo,<br>
Which once thou swor’st was worth the looking on.<br>
This is the hand which, with a vowed contract,<br>
Was fast belocked in thine. This is the body<br>
That took away the match from Isabel<br>
And did supply thee at thy garden-house<br>
In her imagined person.
</p>

<p class="drama">
DUKE.<br>
Know you this woman?
</p>

<p class="drama">
LUCIO.<br>
Carnally, she says.
</p>

<p class="drama">
DUKE.<br>
Sirrah, no more.
</p>

<p class="drama">
LUCIO.<br>
Enough, my lord.
</p>

<p class="drama">
ANGELO.<br>
My lord, I must confess I know this woman;<br>
And five years since there was some speech of marriage<br>
Betwixt myself and her; which was broke off,<br>
Partly for that her promised proportions<br>
Came short of composition; but in chief<br>
For that her reputation was disvalued<br>
In levity. Since which time of five years<br>
I never spake with her, saw her, nor heard from her,<br>
Upon my faith and honour.
</p>

<p class="drama">
MARIANA.<br>
Noble Prince,<br>
As there comes light from heaven and words from breath,<br>
As there is sense in truth and truth in virtue,<br>
I am affianced this man’s wife as strongly<br>
As words could make up vows. And, my good lord,<br>
But Tuesday night last gone, in’s garden-house,<br>
He knew me as a wife. As this is true,<br>
Let me in safety raise me from my knees,<br>
Or else for ever be confixed here,<br>
A marble monument!
</p>

<p class="drama">
ANGELO.<br>
I did but smile till now.<br>
Now, good my lord, give me the scope of justice.<br>
My patience here is touched. I do perceive<br>
These poor informal women are no more<br>
But instruments of some more mightier member<br>
That sets them on. Let me have way, my lord,<br>
To find this practice out.
</p>

<p class="drama">
DUKE.<br>
Ay, with my heart;<br>
And punish them to your height of pleasure.<br>
Thou foolish friar, and thou pernicious woman,<br>
Compact with her that’s gone, think’st thou thy oaths,<br>
Though they would swear down each particular saint,<br>
Were testimonies against his worth and credit,<br>
That’s sealed in approbation? You, Lord Escalus,<br>
Sit with my cousin; lend him your kind pains<br>
To find out this abuse, whence ’tis derived.<br>
There is another friar that set them on;<br>
Let him be sent for.
</p>

<p class="drama">
FRIAR PETER.<br>
Would he were here, my lord; for he indeed<br>
Hath set the women on to this complaint.<br>
Your Provost knows the place where he abides,<br>
And he may fetch him.
</p>

<p class="drama">
DUKE.<br>
Go, do it instantly.
</p>

<p class="right">[<i>Exit <span class="charname">Provost</span>.</i>]</p>

<p class="drama">
And you, my noble and well-warranted cousin,<br>
Whom it concerns to hear this matter forth,<br>
Do with your injuries as seems you best<br>
In any chastisement. I for a while<br>
Will leave you; but stir not you till you have<br>
Well determined upon these slanderers.
</p>

<p class="drama">
ESCALUS.<br>
My lord, we’ll do it throughly.
</p>

<p class="right">[<i>Exit <span class="charname">Duke</span>.</i>]</p>

<p class="drama">
Signior Lucio, did not you say you knew that Friar Lodowick to be a
dishonest person?</p>

<p class="drama">
LUCIO.<br>
<i>Cucullus non facit monachum</i>, honest in nothing but in his clothes, and
one that hath spoke most villainous speeches of the Duke.
</p>

<p class="drama">
ESCALUS.<br>
We shall entreat you to abide here till he come, and enforce them against him.
We shall find this friar a notable fellow.</p>

<p class="drama">
LUCIO.<br>
As any in Vienna, on my word.
</p>

<p class="drama">
ESCALUS.<br>
Call that same Isabel here once again. I would speak with her.
</p>

<p class="right">[<i>Exit an <span class="charname">Attendant</span>.</i>]</p>

<p class="drama">
Pray you, my lord, give me leave to question; you shall see how I’ll handle her.
</p>

<p class="drama">
LUCIO.<br>
Not better than he, by her own report.
</p>

<p class="drama">
ESCALUS.<br>
Say you?
</p>

<p class="drama">
LUCIO.<br>
Marry, sir, I think, if you handled her privately, she would sooner confess;
perchance, publicly, she’ll be ashamed.</p>

<p class="scenedesc">
Enter at several doors <span class="charname">Duke</span> as a friar,
<span class="charname">Provost</span> and <span class="charname">Isabella</span>
with Officers.
</p>

<p class="drama">
ESCALUS.<br>
I will go darkly to work with her.
</p>

<p class="drama">
LUCIO.<br>
That’s the way; for women are light at midnight.
</p>

<p class="drama">
ESCALUS.<br>
[<i>To Isabella</i>.] Come on, mistress, here’s a gentlewoman denies all that you
have said.
</p>

<p class="drama">
LUCIO.<br>
My lord, here comes the rascal I spoke of, here with the Provost.
</p>

<p class="drama">
ESCALUS.<br>
In very good time. Speak not you to him till we call upon you.
</p>

<p class="drama">
LUCIO.<br>
Mum.
</p>

<p class="drama">
ESCALUS.<br>
Come, sir, did you set these women on to slander Lord Angelo? They have
confessed you did.</p>

<p class="drama">
DUKE.<br>
’Tis false.
</p>

<p class="drama">
ESCALUS.<br>
How! Know you where you are?
</p>

<p class="drama">
DUKE.<br>
Respect to your great place; and let the devil<br>
Be sometime honoured for his burning throne.<br>
Where is the Duke? ’Tis he should hear me speak.
</p>

<p class="drama">
ESCALUS.<br>
The Duke’s in us; and we will hear you speak.<br>
Look you speak justly.
</p>

<p class="drama">
DUKE.<br>
Boldly, at least. But, O, poor souls,<br>
Come you to seek the lamb here of the fox,<br>
Good night to your redress! Is the Duke gone?<br>
Then is your cause gone too. The Duke’s unjust<br>
Thus to retort your manifest appeal,<br>
And put your trial in the villain’s mouth<br>
Which here you come to accuse.
</p>

<p class="drama">
LUCIO.<br>
This is the rascal; this is he I spoke of.
</p>

<p class="drama">
ESCALUS.<br>
Why, thou unreverend and unhallowed friar,<br>
Is’t not enough thou hast suborned these women<br>
To accuse this worthy man, but, in foul mouth,<br>
And in the witness of his proper ear,<br>
To call him villain? And then to glance from him<br>
To th’ Duke himself, to tax him with injustice?<br>
Take him hence! To th’ rack with him! We’ll touse you<br>
Joint by joint, but we will know his purpose.<br>
What! Unjust?
</p>

<p class="drama">
DUKE.<br>
Be not so hot. The Duke<br>
Dare no more stretch this finger of mine than he<br>
Dare rack his own. His subject am I not,<br>
Nor here provincial. My business in this state<br>
Made me a looker-on here in Vienna,<br>
Where I have seen corruption boil and bubble<br>
Till it o’errun the stew. Laws for all faults,<br>
But faults so countenanced that the strong statutes<br>
Stand like the forfeits in a barber’s shop,<br>
As much in mock as mark.
</p>

<p class="drama">
ESCALUS.<br>
Slander to the state! Away with him to prison!
</p>

<p class="drama">
ANGELO.<br>
What can you vouch against him, Signior Lucio?<br>
Is this the man that you did tell us of?
</p>

<p class="drama">
LUCIO.<br>
’Tis he, my lord. Come hither, goodman Baldpate.<br>
Do you know me?
</p>

<p class="drama">
DUKE.<br>
I remember you, sir, by the sound of your voice. I met you at the prison, in
the absence of the Duke.
</p>

<p class="drama">
LUCIO.<br>
O did you so? And do you remember what you said of the Duke?
</p>

<p class="drama">
DUKE.<br>
Most notedly, sir.
</p>

<p class="drama">
LUCIO.<br>
Do you so, sir? And was the Duke a fleshmonger, a fool, and a coward, as you
then reported him to be?</p>

<p class="drama">
DUKE.<br>
You must, sir, change persons with me ere you make that my report. You indeed
spoke so of him, and much more, much worse.
</p>

<p class="drama">
LUCIO.<br>
O thou damnable fellow! Did not I pluck thee by the nose for thy speeches?</p>

<p class="drama">
DUKE.<br>
I protest I love the Duke as I love myself.
</p>

<p class="drama">
ANGELO.<br>
Hark how the villain would close now, after his treasonable abuses!</p>

<p class="drama">
ESCALUS.<br>
Such a fellow is not to be talked withal. Away with him to prison! Where is the
provost? Away with him to prison! Lay bolts enough upon him. Let him speak no
more. Away with those giglets too, and with the other confederate companion!
</p>

<p class="right">
[<i>The <span class="charname">Provost</span> lays hands on the
<span class="charname">Duke</span>.</i>]
</p>

<p class="drama">
DUKE.<br>
Stay, sir, stay a while.
</p>

<p class="drama">
ANGELO.<br>
What, resists he? Help him, Lucio.
</p>

<p class="drama">
LUCIO.<br>
Come, sir, come, sir, come, sir. Foh, sir! Why, you bald-pated lying rascal!
You must be hooded, must you? Show your knave’s visage, with a pox to you! Show
your sheep-biting face, and be hanged an hour! Will’t not off?
</p>

<p class="right">[<i>Pulls off the friar’s hood and discovers the
<span class="charname">Duke</span>.</i>]</p>

<p class="drama">
DUKE.<br>
Thou art the first knave that e’er mad’st a duke.<br>
First, Provost, let me bail these gentle three.<br>
[<i>To Lucio</i>.] Sneak not away, sir, for the friar and you<br>
Must have a word anon.—Lay hold on him.
</p>

<p class="drama">
LUCIO.<br>
This may prove worse than hanging.
</p>

<p class="drama">
DUKE.<br>
[<i>To Escalus</i>.] What you have spoke I pardon. Sit you down.<br>
We’ll borrow place of him. [<i>To Angelo</i>.] Sir, by your leave.<br>
Hast thou or word, or wit, or impudence,<br>
That yet can do thee office? If thou hast,<br>
Rely upon it till my tale be heard,<br>
And hold no longer out.
</p>

<p class="drama">
ANGELO.<br>
O my dread lord,<br>
I should be guiltier than my guiltiness<br>
To think I can be undiscernible,<br>
When I perceive your Grace, like power divine,<br>
Hath looked upon my passes. Then, good Prince,<br>
No longer session hold upon my shame,<br>
But let my trial be mine own confession.<br>
Immediate sentence then, and sequent death<br>
Is all the grace I beg.
</p>

<p class="drama">
DUKE.<br>
Come hither, Mariana.<br>
Say, wast thou e’er contracted to this woman?
</p>

<p class="drama">
ANGELO.<br>
I was, my lord.
</p>

<p class="drama">
DUKE.<br>
Go, take her hence and marry her instantly.<br>
Do you the office, friar; which consummate,<br>
Return him here again.—Go with him, Provost.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Angelo, Mariana, Friar Peter</span> and
<span class="charname">Provost</span>.</i>]
</p>

<p class="drama">
ESCALUS.<br>
My lord, I am more amazed at his dishonour<br>
Than at the strangeness of it.
</p>

<p class="drama">
DUKE.<br>
Come hither, Isabel.<br>
Your friar is now your prince. As I was then<br>
Advertising and holy to your business,<br>
Not changing heart with habit, I am still<br>
Attorneyed at your service.
</p>

<p class="drama">
ISABELLA.<br>
O, give me pardon,<br>
That I, your vassal, have employed and pained<br>
Your unknown sovereignty.
</p>

<p class="drama">
DUKE.<br>
You are pardoned, Isabel.<br>
And now, dear maid, be you as free to us.<br>
Your brother’s death, I know, sits at your heart,<br>
And you may marvel why I obscured myself,<br>
Labouring to save his life, and would not rather<br>
Make rash remonstrance of my hidden power<br>
Than let him so be lost. O most kind maid,<br>
It was the swift celerity of his death,<br>
Which I did think with slower foot came on,<br>
That brained my purpose. But peace be with him.<br>
That life is better life, past fearing death,<br>
Than that which lives to fear. Make it your comfort,<br>
So happy is your brother.
</p>

<p class="drama">
ISABELLA.<br>
I do, my lord.
</p>

<p class="scenedesc">
Enter <span class="charname">Angelo, Mariana, Friar Peter</span> and
<span class="charname">Provost</span>.
</p>

<p class="drama">
DUKE.<br>
For this new-married man approaching here,<br>
Whose salt imagination yet hath wronged<br>
Your well-defended honour, you must pardon<br>
For Mariana’s sake. But as he adjudged your brother,<br>
Being criminal in double violation<br>
Of sacred chastity and of promise-breach<br>
Thereon dependent, for your brother’s life,<br>
The very mercy of the law cries out<br>
Most audible, even from his proper tongue,<br>
“An Angelo for Claudio, death for death.”<br>
Haste still pays haste, and leisure answers leisure;<br>
Like doth quit like, and measure still for measure.<br>
Then, Angelo, thy fault’s thus manifested,<br>
Which, though thou wouldst deny, denies thee vantage.<br>
We do condemn thee to the very block<br>
Where Claudio stooped to death, and with like haste.<br>
Away with him.
</p>

<p class="drama">
MARIANA.<br>
O my most gracious lord,<br>
I hope you will not mock me with a husband.
</p>

<p class="drama">
DUKE.<br>
It is your husband mocked you with a husband.<br>
Consenting to the safeguard of your honour,<br>
I thought your marriage fit. Else imputation,<br>
For that he knew you, might reproach your life,<br>
And choke your good to come. For his possessions,<br>
Although by confiscation they are ours,<br>
We do instate and widow you with all<br>
To buy you a better husband.
</p>

<p class="drama">
MARIANA.<br>
O my dear lord,<br>
I crave no other, nor no better man.
</p>

<p class="drama">
DUKE.<br>
Never crave him; we are definitive.
</p>

<p class="drama">
MARIANA.<br>
[<i>Kneeling</i>.] Gentle my liege—
</p>

<p class="drama">
DUKE.<br>
You do but lose your labour.<br>
Away with him to death. [<i>To Lucio</i>.] Now, sir, to you.
</p>

<p class="drama">
MARIANA.<br>
O my good lord.—Sweet Isabel, take my part;<br>
Lend me your knees, and all my life to come<br>
I’ll lend you all my life to do you service.
</p>

<p class="drama">
DUKE.<br>
Against all sense you do importune her.<br>
Should she kneel down in mercy of this fact,<br>
Her brother’s ghost his paved bed would break,<br>
And take her hence in horror.
</p>

<p class="drama">
MARIANA.<br>
Isabel,<br>
Sweet Isabel, do yet but kneel by me;<br>
Hold up your hands, say nothing. I’ll speak all.<br>
They say best men are moulded out of faults,<br>
And, for the most, become much more the better<br>
For being a little bad. So may my husband.<br>
O Isabel, will you not lend a knee?
</p>

<p class="drama">
DUKE.<br>
He dies for Claudio’s death.
</p>

<p class="drama">
ISABELLA.<br>
[<i>Kneeling</i>.] Most bounteous sir,<br>
Look, if it please you, on this man condemned<br>
As if my brother lived. I partly think<br>
A due sincerity governed his deeds<br>
Till he did look on me. Since it is so,<br>
Let him not die. My brother had but justice,<br>
In that he did the thing for which he died.<br>
For Angelo,<br>
His act did not o’ertake his bad intent,<br>
And must be buried but as an intent<br>
That perished by the way. Thoughts are no subjects;<br>
Intents but merely thoughts.
</p>

<p class="drama">
MARIANA.<br>
Merely, my lord.
</p>

<p class="drama">
DUKE.<br>
Your suit’s unprofitable. Stand up, I say.<br>
I have bethought me of another fault.<br>
Provost, how came it Claudio was beheaded<br>
At an unusual hour?
</p>

<p class="drama">
PROVOST.<br>
It was commanded so.
</p>

<p class="drama">
DUKE.<br>
Had you a special warrant for the deed?
</p>

<p class="drama">
PROVOST.<br>
No, my good lord, it was by private message.
</p>

<p class="drama">
DUKE.<br>
For which I do discharge you of your office.<br>
Give up your keys.
</p>

<p class="drama">
PROVOST.<br>
Pardon me, noble lord.<br>
I thought it was a fault, but knew it not;<br>
Yet did repent me after more advice.<br>
For testimony whereof, one in the prison<br>
That should by private order else have died,<br>
I have reserved alive.
</p>

<p class="drama">
DUKE.<br>
What’s he?
</p>

<p class="drama">
PROVOST.<br>
His name is Barnardine.
</p>

<p class="drama">
DUKE.<br>
I would thou hadst done so by Claudio.<br>
Go fetch him hither, let me look upon him.
</p>

<p class="right">[<i>Exit <span class="charname">Provost</span>.</i>]</p>

<p class="drama">
ESCALUS.<br>
I am sorry one so learned and so wise<br>
As you, Lord Angelo, have still appeared,<br>
Should slip so grossly, both in the heat of blood<br>
And lack of tempered judgement afterward.
</p>

<p class="drama">
ANGELO.<br>
I am sorry that such sorrow I procure,<br>
And so deep sticks it in my penitent heart<br>
That I crave death more willingly than mercy;<br>
’Tis my deserving, and I do entreat it.
</p>

<p class="scenedesc">
Enter <span class="charname">Provost</span> with
<span class="charname">Barnardine, Claudio</span> (muffled) and
<span class="charname">Juliet</span>.
</p>

<p class="drama">
DUKE.<br>
Which is that Barnardine?
</p>

<p class="drama">
PROVOST.<br>
This, my lord.
</p>

<p class="drama">
DUKE.<br>
There was a friar told me of this man.<br>
Sirrah, thou art said to have a stubborn soul<br>
That apprehends no further than this world,<br>
And squar’st thy life according. Thou’rt condemned;<br>
But, for those earthly faults, I quit them all,<br>
And pray thee take this mercy to provide<br>
For better times to come. Friar, advise him;<br>
I leave him to your hand.—What muffled fellow’s that?
</p>

<p class="drama">
PROVOST.<br>
This is another prisoner that I saved,<br>
Who should have died when Claudio lost his head;<br>
As like almost to Claudio as himself.
</p>

<p class="right">[<i>Unmuffles <span class="charname">Claudio</span>.</i>]</p>

<p class="drama">
DUKE.<br>
[<i>To Isabella</i>.] If he be like your brother, for his sake<br>
Is he pardoned; and for your lovely sake,<br>
Give me your hand and say you will be mine.<br>
He is my brother too. But fitter time for that.<br>
By this Lord Angelo perceives he’s safe;<br>
Methinks I see a quick’ning in his eye.<br>
Well, Angelo, your evil quits you well.<br>
Look that you love your wife, her worth worth yours.<br>
I find an apt remission in myself.<br>
And yet here’s one in place I cannot pardon.<br>
[<i>To Lucio</i>.] You, sirrah, that knew me for a fool, a coward,<br>
One all of luxury, an ass, a madman.<br>
Wherein have I so deserved of you<br>
That you extol me thus?
</p>

<p class="drama">
LUCIO.<br>
Faith, my lord, I spoke it but according to the trick. If you will hang me for
it, you may, but I had rather it would please you I might be whipped.</p>

<p class="drama">
DUKE.<br>
Whipped first, sir, and hanged after.<br>
Proclaim it, Provost, round about the city,<br>
If any woman wronged by this lewd fellow,<br>
As I have heard him swear himself there’s one<br>
Whom he begot with child—let her appear,<br>
And he shall marry her. The nuptial finished,<br>
Let him be whipped and hanged.
</p>

<p class="drama">
LUCIO.<br>
I beseech your Highness, do not marry me to a whore. Your highness said even
now I made you a duke; good my lord, do not recompense me in making me a
cuckold.</p>

<p class="drama">
DUKE.<br>
Upon mine honour, thou shalt marry her.<br>
Thy slanders I forgive, and therewithal<br>
Remit thy other forfeits.—Take him to prison,<br>
And see our pleasure herein executed.
</p>

<p class="drama">
LUCIO.<br>
Marrying a punk, my lord, is pressing to death, whipping, and hanging.</p>

<p class="drama">
DUKE.<br>
Slandering a prince deserves it.
</p>

<p class="right">[<i>Exeunt Officers with <span class="charname">Lucio</span>.</i>]</p>

<p class="drama">
She, Claudio, that you wronged, look you restore.<br>
Joy to you, Mariana! Love her, Angelo.<br>
I have confessed her, and I know her virtue.<br>
Thanks, good friend Escalus, for thy much goodness;<br>
There’s more behind that is more gratulate.<br>
Thanks, Provost, for thy care and secrecy;<br>
We shall employ thee in a worthier place.<br>
Forgive him, Angelo, that brought you home<br>
The head of Ragozine for Claudio’s.<br>
Th’ offence pardons itself. Dear Isabel,<br>
I have a motion much imports your good;<br>
Whereto if you’ll a willing ear incline,<br>
What’s mine is yours, and what is yours is mine.<br>
So, bring us to our palace, where we’ll show<br>
What’s yet behind that’s meet you all should know.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

