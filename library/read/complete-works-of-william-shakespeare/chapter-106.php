<h2> <a id="sceneII_17.1"></a><b>ACT II</b></h2>

<h3> <b>SCENE I. Rome. Brutus’ orchard.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Brutus</span>.
</p>

<p class="drama">
BRUTUS.<br>
What, Lucius, ho!<br>
I cannot, by the progress of the stars,<br>
Give guess how near to day.—Lucius, I say!<br>
I would it were my fault to sleep so soundly.<br>
When, Lucius, when? Awake, I say! What, Lucius!
</p>

<p class="scenedesc">
Enter <span class="charname">Lucius</span>.
</p>

<p class="drama">
LUCIUS.<br>
Call’d you, my lord?
</p>

<p class="drama">
BRUTUS.<br>
Get me a taper in my study, Lucius:<br>
When it is lighted, come and call me here.
</p>

<p class="drama">
LUCIUS.<br>
I will, my lord.
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="drama">
BRUTUS.<br>
It must be by his death: and for my part,<br>
I know no personal cause to spurn at him,<br>
But for the general. He would be crown’d:<br>
How that might change his nature, there’s the question.<br>
It is the bright day that brings forth the adder,<br>
And that craves wary walking. Crown him?—that;<br>
And then, I grant, we put a sting in him,<br>
That at his will he may do danger with.<br>
Th’ abuse of greatness is, when it disjoins<br>
Remorse from power; and, to speak truth of Caesar,<br>
I have not known when his affections sway’d<br>
More than his reason. But ’tis a common proof,<br>
That lowliness is young ambition’s ladder,<br>
Whereto the climber-upward turns his face;<br>
But when he once attains the upmost round,<br>
He then unto the ladder turns his back,<br>
Looks in the clouds, scorning the base degrees<br>
By which he did ascend. So Caesar may;<br>
Then lest he may, prevent. And since the quarrel<br>
Will bear no colour for the thing he is,<br>
Fashion it thus: that what he is, augmented,<br>
Would run to these and these extremities:<br>
And therefore think him as a serpent’s egg<br>
Which hatch’d, would, as his kind grow mischievous;<br>
And kill him in the shell.
</p>

<p class="scenedesc">
Enter <span class="charname">Lucius</span>.
</p>

<p class="drama">
LUCIUS.<br>
The taper burneth in your closet, sir.<br>
Searching the window for a flint, I found<br>
This paper, thus seal’d up, and I am sure<br>
It did not lie there when I went to bed.
</p>

<p class="right">
[<i>Gives him the letter.</i>]
</p>

<p class="drama">
BRUTUS.<br>
Get you to bed again; it is not day.<br>
Is not tomorrow, boy, the Ides of March?
</p>

<p class="drama">
LUCIUS.<br>
I know not, sir.
</p>

<p class="drama">
BRUTUS.<br>
Look in the calendar, and bring me word.
</p>

<p class="drama">
LUCIUS.<br>
I will, sir.
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="drama">
BRUTUS.<br>
The exhalations, whizzing in the air<br>
Give so much light that I may read by them.
</p>

<p class="right">
[<i>Opens the letter and reads.</i>]
</p>

<p class="drama">
<i>Brutus, thou sleep’st: awake and see thyself.<br>
Shall Rome, &amp;c. Speak, strike, redress!</i><br>
“Brutus, thou sleep’st: awake!”<br>
Such instigations have been often dropp’d<br>
Where I have took them up.<br>
“Shall Rome, &amp;c.” Thus must I piece it out:<br>
Shall Rome stand under one man’s awe? What, Rome?<br>
My ancestors did from the streets of Rome<br>
The Tarquin drive, when he was call’d a king.<br>
“Speak, strike, redress!” Am I entreated<br>
To speak and strike? O Rome, I make thee promise,<br>
If the redress will follow, thou receivest<br>
Thy full petition at the hand of Brutus.
</p>

<p class="scenedesc">
Enter <span class="charname">Lucius</span>.
</p>

<p class="drama">
LUCIUS.<br>
Sir, March is wasted fifteen days.
</p>

<p class="right">
[<i>Knock within.</i>]
</p>

<p class="drama">
BRUTUS.<br>
’Tis good. Go to the gate, somebody knocks.
</p>

<p class="right">
[<i>Exit <span class="charname">Lucius</span>.</i>]
</p>

<p class="drama">
Since Cassius first did whet me against Caesar,<br>
I have not slept.<br>
Between the acting of a dreadful thing<br>
And the first motion, all the interim is<br>
Like a phantasma, or a hideous dream:<br>
The genius and the mortal instruments<br>
Are then in council; and the state of man,<br>
Like to a little kingdom, suffers then<br>
The nature of an insurrection.
</p>

<p class="scenedesc">
Enter <span class="charname">Lucius</span>.
</p>

<p class="drama">
LUCIUS.<br>
Sir, ’tis your brother Cassius at the door,<br>
Who doth desire to see you.
</p>

<p class="drama">
BRUTUS.<br>
Is he alone?
</p>

<p class="drama">
LUCIUS.<br>
No, sir, there are moe with him.
</p>

<p class="drama">
BRUTUS.<br>
Do you know them?
</p>

<p class="drama">
LUCIUS.<br>
No, sir, their hats are pluck’d about their ears,<br>
And half their faces buried in their cloaks,<br>
That by no means I may discover them<br>
By any mark of favour.
</p>

<p class="drama">
BRUTUS.<br>
Let ’em enter.
</p>

<p class="right">
[<i>Exit <span class="charname">Lucius</span>.</i>]
</p>

<p class="drama">
They are the faction. O conspiracy,<br>
Sham’st thou to show thy dangerous brow by night,<br>
When evils are most free? O, then, by day<br>
Where wilt thou find a cavern dark enough<br>
To mask thy monstrous visage? Seek none, conspiracy;<br>
Hide it in smiles and affability:<br>
For if thou path, thy native semblance on,<br>
Not Erebus itself were dim enough<br>
To hide thee from prevention.
</p>

<p class="scenedesc">
Enter <span class="charname">Cassius, Casca, Decius, Cinna, Metellus
Cimber</span> and <span class="charname">Trebonius</span>.
</p>

<p class="drama">
CASSIUS.<br>
I think we are too bold upon your rest:<br>
Good morrow, Brutus; do we trouble you?
</p>

<p class="drama">
BRUTUS.<br>
I have been up this hour, awake all night.<br>
Know I these men that come along with you?
</p>

<p class="drama">
CASSIUS.<br>
Yes, every man of them; and no man here<br>
But honours you; and everyone doth wish<br>
You had but that opinion of yourself<br>
Which every noble Roman bears of you.<br>
This is Trebonius.
</p>

<p class="drama">
BRUTUS.<br>
He is welcome hither.
</p>

<p class="drama">
CASSIUS.<br>
This Decius Brutus.
</p>

<p class="drama">
BRUTUS.<br>
He is welcome too.
</p>

<p class="drama">
CASSIUS.<br>
This, Casca; this, Cinna; and this, Metellus Cimber.
</p>

<p class="drama">
BRUTUS.<br>
They are all welcome.<br>
What watchful cares do interpose themselves<br>
Betwixt your eyes and night?
</p>

<p class="drama">
CASSIUS.<br>
Shall I entreat a word?
</p>

<p class="right">
[<i>They whisper.</i>]
</p>

<p class="drama">
DECIUS.<br>
Here lies the east: doth not the day break here?
</p>

<p class="drama">
CASCA.<br>
No.
</p>

<p class="drama">
CINNA.<br>
O, pardon, sir, it doth; and yon grey lines<br>
That fret the clouds are messengers of day.
</p>

<p class="drama">
CASCA.<br>
You shall confess that you are both deceiv’d.<br>
Here, as I point my sword, the Sun arises;<br>
Which is a great way growing on the South,<br>
Weighing the youthful season of the year.<br>
Some two months hence, up higher toward the North<br>
He first presents his fire; and the high East<br>
Stands, as the Capitol, directly here.
</p>

<p class="drama">
BRUTUS.<br>
Give me your hands all over, one by one.
</p>

<p class="drama">
CASSIUS.<br>
And let us swear our resolution.
</p>

<p class="drama">
BRUTUS.<br>
No, not an oath. If not the face of men,<br>
The sufferance of our souls, the time’s abuse—<br>
If these be motives weak, break off betimes,<br>
And every man hence to his idle bed.<br>
So let high-sighted tyranny range on,<br>
Till each man drop by lottery. But if these,<br>
As I am sure they do, bear fire enough<br>
To kindle cowards, and to steel with valour<br>
The melting spirits of women; then, countrymen,<br>
What need we any spur but our own cause<br>
To prick us to redress? what other bond<br>
Than secret Romans, that have spoke the word,<br>
And will not palter? and what other oath<br>
Than honesty to honesty engag’d,<br>
That this shall be, or we will fall for it?<br>
Swear priests and cowards, and men cautelous,<br>
Old feeble carrions, and such suffering souls<br>
That welcome wrongs; unto bad causes swear<br>
Such creatures as men doubt; but do not stain<br>
The even virtue of our enterprise,<br>
Nor th’ insuppressive mettle of our spirits,<br>
To think that or our cause or our performance<br>
Did need an oath; when every drop of blood<br>
That every Roman bears, and nobly bears,<br>
Is guilty of a several bastardy,<br>
If he do break the smallest particle<br>
Of any promise that hath pass’d from him.
</p>

<p class="drama">
CASSIUS.<br>
But what of Cicero? Shall we sound him?<br>
I think he will stand very strong with us.
</p>

<p class="drama">
CASCA.<br>
Let us not leave him out.
</p>

<p class="drama">
CINNA.<br>
No, by no means.
</p>

<p class="drama">
METELLUS.<br>
O, let us have him, for his silver hairs<br>
Will purchase us a good opinion,<br>
And buy men’s voices to commend our deeds.<br>
It shall be said, his judgement rul’d our hands;<br>
Our youths and wildness shall no whit appear,<br>
But all be buried in his gravity.
</p>

<p class="drama">
BRUTUS.<br>
O, name him not; let us not break with him;<br>
For he will never follow anything<br>
That other men begin.
</p>

<p class="drama">
CASSIUS.<br>
Then leave him out.
</p>

<p class="drama">
CASCA.<br>
Indeed, he is not fit.
</p>

<p class="drama">
DECIUS.<br>
Shall no man else be touch’d but only Caesar?
</p>

<p class="drama">
CASSIUS.<br>
Decius, well urg’d. I think it is not meet,<br>
Mark Antony, so well belov’d of Caesar,<br>
Should outlive Caesar: we shall find of him<br>
A shrewd contriver; and you know, his means,<br>
If he improve them, may well stretch so far<br>
As to annoy us all; which to prevent,<br>
Let Antony and Caesar fall together.
</p>

<p class="drama">
BRUTUS.<br>
Our course will seem too bloody, Caius Cassius,<br>
To cut the head off, and then hack the limbs,<br>
Like wrath in death, and envy afterwards;<br>
For Antony is but a limb of Caesar.<br>
Let us be sacrificers, but not butchers, Caius.<br>
We all stand up against the spirit of Caesar,<br>
And in the spirit of men there is no blood.<br>
O, that we then could come by Caesar’s spirit,<br>
And not dismember Caesar! But, alas,<br>
Caesar must bleed for it! And, gentle friends,<br>
Let’s kill him boldly, but not wrathfully;<br>
Let’s carve him as a dish fit for the gods,<br>
Not hew him as a carcass fit for hounds.<br>
And let our hearts, as subtle masters do,<br>
Stir up their servants to an act of rage,<br>
And after seem to chide ’em. This shall mark<br>
Our purpose necessary, and not envious;<br>
Which so appearing to the common eyes,<br>
We shall be call’d purgers, not murderers.<br>
And for Mark Antony, think not of him;<br>
For he can do no more than Caesar’s arm<br>
When Caesar’s head is off.
</p>

<p class="drama">
CASSIUS.<br>
Yet I fear him;<br>
For in the ingrafted love he bears to Caesar—
</p>

<p class="drama">
BRUTUS.<br>
Alas, good Cassius, do not think of him:<br>
If he love Caesar, all that he can do<br>
Is to himself; take thought and die for Caesar.<br>
And that were much he should; for he is given<br>
To sports, to wildness, and much company.
</p>

<p class="drama">
TREBONIUS.<br>
There is no fear in him; let him not die;<br>
For he will live, and laugh at this hereafter.
</p>

<p class="right">
[<i>Clock strikes.</i>]
</p>

<p class="drama">
BRUTUS.<br>
Peace! count the clock.
</p>

<p class="drama">
CASSIUS.<br>
The clock hath stricken three.
</p>

<p class="drama">
TREBONIUS.<br>
’Tis time to part.
</p>

<p class="drama">
CASSIUS.<br>
But it is doubtful yet<br>
Whether Caesar will come forth today or no;<br>
For he is superstitious grown of late,<br>
Quite from the main opinion he held once<br>
Of fantasy, of dreams, and ceremonies.<br>
It may be these apparent prodigies,<br>
The unaccustom’d terror of this night,<br>
And the persuasion of his augurers,<br>
May hold him from the Capitol today.
</p>

<p class="drama">
DECIUS.<br>
Never fear that: if he be so resolved,<br>
I can o’ersway him, for he loves to hear<br>
That unicorns may be betray’d with trees,<br>
And bears with glasses, elephants with holes,<br>
Lions with toils, and men with flatterers.<br>
But when I tell him he hates flatterers,<br>
He says he does, being then most flattered.<br>
Let me work;<br>
For I can give his humour the true bent,<br>
And I will bring him to the Capitol.
</p>

<p class="drama">
CASSIUS.<br>
Nay, we will all of us be there to fetch him.
</p>

<p class="drama">
BRUTUS.<br>
By the eighth hour: is that the uttermost?
</p>

<p class="drama">
CINNA.<br>
Be that the uttermost; and fail not then.
</p>

<p class="drama">
METELLUS.<br>
Caius Ligarius doth bear Caesar hard,<br>
Who rated him for speaking well of Pompey;<br>
I wonder none of you have thought of him.
</p>

<p class="drama">
BRUTUS.<br>
Now, good Metellus, go along by him:<br>
He loves me well, and I have given him reason;<br>
Send him but hither, and I’ll fashion him.
</p>

<p class="drama">
CASSIUS.<br>
The morning comes upon’s. We’ll leave you, Brutus.<br>
And, friends, disperse yourselves; but all remember<br>
What you have said, and show yourselves true Romans.
</p>

<p class="drama">
BRUTUS.<br>
Good gentlemen, look fresh and merrily;<br>
Let not our looks put on our purposes,<br>
But bear it as our Roman actors do,<br>
With untired spirits and formal constancy.<br>
And so, good morrow to you everyone.
</p>

<p class="right">
[<i>Exeunt all but <span class="charname">Brutus</span>.</i>]
</p>

<p class="drama">
Boy! Lucius! Fast asleep? It is no matter;<br>
Enjoy the honey-heavy dew of slumber:<br>
Thou hast no figures nor no fantasies,<br>
Which busy care draws in the brains of men;<br>
Therefore thou sleep’st so sound.
</p>

<p class="scenedesc">
Enter <span class="charname">Portia</span>.
</p>

<p class="drama">
PORTIA.<br>
Brutus, my lord.
</p>

<p class="drama">
BRUTUS.<br>
Portia, what mean you? Wherefore rise you now?<br>
It is not for your health thus to commit<br>
Your weak condition to the raw cold morning.
</p>

<p class="drama">
PORTIA.<br>
Nor for yours neither. Y’ have ungently, Brutus,<br>
Stole from my bed; and yesternight at supper,<br>
You suddenly arose, and walk’d about,<br>
Musing and sighing, with your arms across;<br>
And when I ask’d you what the matter was,<br>
You star’d upon me with ungentle looks.<br>
I urg’d you further; then you scratch’d your head,<br>
And too impatiently stamp’d with your foot;<br>
Yet I insisted, yet you answer’d not,<br>
But with an angry wafture of your hand<br>
Gave sign for me to leave you. So I did,<br>
Fearing to strengthen that impatience<br>
Which seem’d too much enkindled; and withal<br>
Hoping it was but an effect of humour,<br>
Which sometime hath his hour with every man.<br>
It will not let you eat, nor talk, nor sleep;<br>
And could it work so much upon your shape<br>
As it hath much prevail’d on your condition,<br>
I should not know you, Brutus. Dear my lord,<br>
Make me acquainted with your cause of grief.
</p>

<p class="drama">
BRUTUS.<br>
I am not well in health, and that is all.
</p>

<p class="drama">
PORTIA.<br>
Brutus is wise, and, were he not in health,<br>
He would embrace the means to come by it.
</p>

<p class="drama">
BRUTUS.<br>
Why, so I do. Good Portia, go to bed.
</p>

<p class="drama">
PORTIA.<br>
Is Brutus sick, and is it physical<br>
To walk unbraced and suck up the humours<br>
Of the dank morning? What, is Brutus sick,<br>
And will he steal out of his wholesome bed<br>
To dare the vile contagion of the night,<br>
And tempt the rheumy and unpurged air<br>
To add unto his sickness? No, my Brutus;<br>
You have some sick offence within your mind,<br>
Which, by the right and virtue of my place,<br>
I ought to know of: and, upon my knees,<br>
I charm you, by my once commended beauty,<br>
By all your vows of love, and that great vow<br>
Which did incorporate and make us one,<br>
That you unfold to me, your self, your half,<br>
Why you are heavy, and what men tonight<br>
Have had resort to you; for here have been<br>
Some six or seven, who did hide their faces<br>
Even from darkness.
</p>

<p class="drama">
BRUTUS.<br>
Kneel not, gentle Portia.
</p>

<p class="drama">
PORTIA.<br>
I should not need, if you were gentle Brutus.<br>
Within the bond of marriage, tell me, Brutus,<br>
Is it excepted I should know no secrets<br>
That appertain to you? Am I your self<br>
But, as it were, in sort or limitation,<br>
To keep with you at meals, comfort your bed,<br>
And talk to you sometimes? Dwell I but in the suburbs<br>
Of your good pleasure? If it be no more,<br>
Portia is Brutus’ harlot, not his wife.
</p>

<p class="drama">
BRUTUS.<br>
You are my true and honourable wife,<br>
As dear to me as are the ruddy drops<br>
That visit my sad heart.
</p>

<p class="drama">
PORTIA.<br>
If this were true, then should I know this secret.<br>
I grant I am a woman; but withal<br>
A woman that Lord Brutus took to wife;<br>
I grant I am a woman; but withal<br>
A woman well reputed, Cato’s daughter.<br>
Think you I am no stronger than my sex,<br>
Being so father’d and so husbanded?<br>
Tell me your counsels, I will not disclose ’em.<br>
I have made strong proof of my constancy,<br>
Giving myself a voluntary wound<br>
Here, in the thigh: can I bear that with patience<br>
And not my husband’s secrets?
</p>

<p class="drama">
BRUTUS.<br>
O ye gods,<br>
Render me worthy of this noble wife!
</p>

<p class="right">
[<i>Knock.</i>]
</p>

<p class="drama">
Hark, hark, one knocks. Portia, go in awhile;<br>
And by and by thy bosom shall partake<br>
The secrets of my heart.<br>
All my engagements I will construe to thee,<br>
All the charactery of my sad brows.<br>
Leave me with haste.
</p>

<p class="right">
[<i>Exit <span class="charname">Portia</span>.</i>]
</p>

<p class="scenedesc">
Enter <span class="charname">Lucius</span> with <span class="charname">Ligarius</span>.
</p>

<p class="drama">
Lucius, who’s that knocks?
</p>

<p class="drama">
LUCIUS.<br>
Here is a sick man that would speak with you.
</p>

<p class="drama">
BRUTUS.<br>
Caius Ligarius, that Metellus spake of.<br>
Boy, stand aside. Caius Ligarius, how?
</p>

<p class="drama">
LIGARIUS.<br>
Vouchsafe good-morrow from a feeble tongue.
</p>

<p class="drama">
BRUTUS.<br>
O, what a time have you chose out, brave Caius,<br>
To wear a kerchief! Would you were not sick!
</p>

<p class="drama">
LIGARIUS.<br>
I am not sick, if Brutus have in hand<br>
Any exploit worthy the name of honour.
</p>

<p class="drama">
BRUTUS.<br>
Such an exploit have I in hand, Ligarius,<br>
Had you a healthful ear to hear of it.
</p>

<p class="drama">
LIGARIUS.<br>
By all the gods that Romans bow before,<br>
I here discard my sickness. Soul of Rome!<br>
Brave son, derived from honourable loins!<br>
Thou, like an exorcist, hast conjur’d up<br>
My mortified spirit. Now bid me run,<br>
And I will strive with things impossible,<br>
Yea, get the better of them. What’s to do?
</p>

<p class="drama">
BRUTUS.<br>
A piece of work that will make sick men whole.
</p>

<p class="drama">
LIGARIUS.<br>
But are not some whole that we must make sick?
</p>

<p class="drama">
BRUTUS.<br>
That must we also. What it is, my Caius,<br>
I shall unfold to thee, as we are going,<br>
To whom it must be done.
</p>

<p class="drama">
LIGARIUS.<br>
Set on your foot,<br>
And with a heart new-fir’d I follow you,<br>
To do I know not what; but it sufficeth<br>
That Brutus leads me on.
</p>

<p class="right">
[<i>Thunder.</i>]
</p>

<p class="drama">
BRUTUS.<br>
Follow me then.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneII_17.2"></a><b>SCENE II. A room in Caesar’s palace.</b></h3>

<p class="scenedesc">
Thunder and lightning. Enter <span class="charname">Caesar,</span> in his
nightgown.
</p>

<p class="drama">
CAESAR.<br>
Nor heaven nor earth have been at peace tonight:<br>
Thrice hath Calphurnia in her sleep cried out,<br>
“Help, ho! They murder Caesar!” Who’s within?
</p>

<p class="scenedesc">
Enter a <span class="charname">Servant</span>.
</p>

<p class="drama">
SERVANT.<br>
My lord?
</p>

<p class="drama">
CAESAR.<br>
Go bid the priests do present sacrifice,<br>
And bring me their opinions of success.
</p>

<p class="drama">
SERVANT.<br>
I will, my lord.
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="scenedesc">
Enter <span class="charname">Calphurnia</span>.
</p>

<p class="drama">
CALPHURNIA.<br>
What mean you, Caesar? Think you to walk forth?<br>
You shall not stir out of your house today.
</p>

<p class="drama">
CAESAR.<br>
Caesar shall forth. The things that threaten’d me<br>
Ne’er look’d but on my back; when they shall see<br>
The face of Caesar, they are vanished.
</p>

<p class="drama">
CALPHURNIA.<br>
Caesar, I never stood on ceremonies,<br>
Yet now they fright me. There is one within,<br>
Besides the things that we have heard and seen,<br>
Recounts most horrid sights seen by the watch.<br>
A lioness hath whelped in the streets,<br>
And graves have yawn’d, and yielded up their dead;<br>
Fierce fiery warriors fight upon the clouds<br>
In ranks and squadrons and right form of war,<br>
Which drizzled blood upon the Capitol;<br>
The noise of battle hurtled in the air,<br>
Horses did neigh, and dying men did groan,<br>
And ghosts did shriek and squeal about the streets.<br>
O Caesar, these things are beyond all use,<br>
And I do fear them!
</p>

<p class="drama">
CAESAR.<br>
What can be avoided<br>
Whose end is purpos’d by the mighty gods?<br>
Yet Caesar shall go forth; for these predictions<br>
Are to the world in general as to Caesar.
</p>

<p class="drama">
CALPHURNIA.<br>
When beggars die, there are no comets seen;<br>
The heavens themselves blaze forth the death of princes.
</p>

<p class="drama">
CAESAR.<br>
Cowards die many times before their deaths;<br>
The valiant never taste of death but once.<br>
Of all the wonders that I yet have heard,<br>
It seems to me most strange that men should fear,<br>
Seeing that death, a necessary end,<br>
Will come when it will come.
</p>

<p class="scenedesc">
Enter <span class="charname">Servant</span>.
</p>

<p class="drama">
What say the augurers?
</p>

<p class="drama">
SERVANT.<br>
They would not have you to stir forth today.<br>
Plucking the entrails of an offering forth,<br>
They could not find a heart within the beast.
</p>

<p class="drama">
CAESAR.<br>
The gods do this in shame of cowardice:<br>
Caesar should be a beast without a heart<br>
If he should stay at home today for fear.<br>
No, Caesar shall not. Danger knows full well<br>
That Caesar is more dangerous than he.<br>
We are two lions litter’d in one day,<br>
And I the elder and more terrible,<br>
And Caesar shall go forth.
</p>

<p class="drama">
CALPHURNIA.<br>
Alas, my lord,<br>
Your wisdom is consum’d in confidence.<br>
Do not go forth today: call it my fear<br>
That keeps you in the house, and not your own.<br>
We’ll send Mark Antony to the Senate-house,<br>
And he shall say you are not well today.<br>
Let me upon my knee prevail in this.
</p>

<p class="drama">
CAESAR.<br>
Mark Antony shall say I am not well,<br>
And for thy humour, I will stay at home.
</p>

<p class="scenedesc">
Enter <span class="charname">Decius</span>.
</p>

<p class="drama">
Here’s Decius Brutus, he shall tell them so.
</p>

<p class="drama">
DECIUS.<br>
Caesar, all hail! Good morrow, worthy Caesar.<br>
I come to fetch you to the Senate-house.
</p>

<p class="drama">
CAESAR.<br>
And you are come in very happy time<br>
To bear my greeting to the Senators,<br>
And tell them that I will not come today.<br>
Cannot, is false; and that I dare not, falser:<br>
I will not come today. Tell them so, Decius.
</p>

<p class="drama">
CALPHURNIA.<br>
Say he is sick.
</p>

<p class="drama">
CAESAR.<br>
Shall Caesar send a lie?<br>
Have I in conquest stretch’d mine arm so far,<br>
To be afeard to tell grey-beards the truth?<br>
Decius, go tell them Caesar will not come.
</p>

<p class="drama">
DECIUS.<br>
Most mighty Caesar, let me know some cause,<br>
Lest I be laugh’d at when I tell them so.
</p>

<p class="drama">
CAESAR.<br>
The cause is in my will; I will not come.<br>
That is enough to satisfy the Senate.<br>
But for your private satisfaction,<br>
Because I love you, I will let you know:<br>
Calphurnia here, my wife, stays me at home.<br>
She dreamt tonight she saw my statue,<br>
Which like a fountain with an hundred spouts<br>
Did run pure blood; and many lusty Romans<br>
Came smiling, and did bathe their hands in it.<br>
And these does she apply for warnings and portents<br>
And evils imminent; and on her knee<br>
Hath begg’d that I will stay at home today.
</p>

<p class="drama">
DECIUS.<br>
This dream is all amiss interpreted:<br>
It was a vision fair and fortunate.<br>
Your statue spouting blood in many pipes,<br>
In which so many smiling Romans bath’d,<br>
Signifies that from you great Rome shall suck<br>
Reviving blood, and that great men shall press<br>
For tinctures, stains, relics, and cognizance.<br>
This by Calphurnia’s dream is signified.
</p>

<p class="drama">
CAESAR.<br>
And this way have you well expounded it.
</p>

<p class="drama">
DECIUS.<br>
I have, when you have heard what I can say;<br>
And know it now. The Senate have concluded<br>
To give this day a crown to mighty Caesar.<br>
If you shall send them word you will not come,<br>
Their minds may change. Besides, it were a mock<br>
Apt to be render’d, for someone to say,<br>
“Break up the Senate till another time,<br>
When Caesar’s wife shall meet with better dreams.”<br>
If Caesar hide himself, shall they not whisper<br>
“Lo, Caesar is afraid”?<br>
Pardon me, Caesar; for my dear dear love<br>
To your proceeding bids me tell you this,<br>
And reason to my love is liable.
</p>

<p class="drama">
CAESAR.<br>
How foolish do your fears seem now, Calphurnia!<br>
I am ashamed I did yield to them.<br>
Give me my robe, for I will go.
</p>

<p class="scenedesc">
Enter <span class="charname">Brutus, Ligarius, Metellus, Casca, Trebonius,
Cinna</span> and <span class="charname">Publius</span>.
</p>

<p class="drama">
And look where Publius is come to fetch me.
</p>

<p class="drama">
PUBLIUS.<br>
Good morrow, Caesar.
</p>

<p class="drama">
CAESAR.<br>
Welcome, Publius.<br>
What, Brutus, are you stirr’d so early too?<br>
Good morrow, Casca. Caius Ligarius,<br>
Caesar was ne’er so much your enemy<br>
As that same ague which hath made you lean.<br>
What is’t o’clock?
</p>

<p class="drama">
BRUTUS.<br>
Caesar, ’tis strucken eight.
</p>

<p class="drama">
CAESAR.<br>
I thank you for your pains and courtesy.
</p>

<p class="scenedesc">
Enter <span class="charname">Antony</span>.
</p>

<p class="drama">
See! Antony, that revels long a-nights,<br>
Is notwithstanding up. Good morrow, Antony.
</p>

<p class="drama">
ANTONY.<br>
So to most noble Caesar.
</p>

<p class="drama">
CAESAR.<br>
Bid them prepare within.<br>
I am to blame to be thus waited for.<br>
Now, Cinna; now, Metellus; what, Trebonius!<br>
I have an hour’s talk in store for you:<br>
Remember that you call on me today;<br>
Be near me, that I may remember you.
</p>

<p class="drama">
TREBONIUS.<br>
Caesar, I will. [<i>Aside.</i>] and so near will I be,<br>
That your best friends shall wish I had been further.
</p>

<p class="drama">
CAESAR.<br>
Good friends, go in, and taste some wine with me;<br>
And we, like friends, will straightway go together.
</p>

<p class="drama">
BRUTUS.<br>
[<i>Aside.</i>] That every like is not the same, O Caesar,<br>
The heart of Brutus yearns to think upon.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneII_17.3"></a><b>SCENE III. A street near the
Capitol.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Artemidorus,</span> reading a paper.
</p>

<p class="drama">
ARTEMIDORUS.<br>
<i>“Caesar, beware of Brutus; take heed of Cassius; come not near Casca; have
an eye to Cinna; trust not Trebonius; mark well Metellus Cimber; Decius Brutus
loves thee not; thou hast wrong’d Caius Ligarius. There is but one mind in all
these men, and it is bent against Caesar. If thou be’st not immortal, look
about you: security gives way to conspiracy. The mighty gods defend thee!<br>
Thy lover, Artemidorus.”</i><br> Here will I stand till Caesar pass along,<br> And as a suitor will I give him this.<br> My heart laments that virtue
cannot live<br> Out of the teeth of emulation.<br> If thou read this, O
Caesar, thou mayest live;<br> If not, the Fates with traitors do contrive.<br>
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<h3> <a id="sceneII_17.4"></a><b>SCENE IV. Another part of the same street,
before the house of Brutus.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Portia</span> and <span class="charname">Lucius</span>.
</p>

<p class="drama">
PORTIA.<br>
I pr’ythee, boy, run to the Senate-house;<br>
Stay not to answer me, but get thee gone.<br>
Why dost thou stay?
</p>

<p class="drama">
LUCIUS.<br>
To know my errand, madam.
</p>

<p class="drama">
PORTIA.<br>
I would have had thee there and here again,<br>
Ere I can tell thee what thou shouldst do there.<br>
[<i>Aside.</i>] O constancy, be strong upon my side,<br>
Set a huge mountain ’tween my heart and tongue!<br>
I have a man’s mind, but a woman’s might.<br>
How hard it is for women to keep counsel!<br>
Art thou here yet?
</p>

<p class="drama">
LUCIUS.<br>
Madam, what should I do?<br>
Run to the Capitol, and nothing else?<br>
And so return to you, and nothing else?
</p>

<p class="drama">
PORTIA.<br>
Yes, bring me word, boy, if thy lord look well,<br>
For he went sickly forth: and take good note<br>
What Caesar doth, what suitors press to him.<br>
Hark, boy, what noise is that?
</p>

<p class="drama">
LUCIUS.<br>
I hear none, madam.
</p>

<p class="drama">
PORTIA.<br>
Pr’ythee, listen well.<br>
I heard a bustling rumour, like a fray,<br>
And the wind brings it from the Capitol.
</p>

<p class="drama">
LUCIUS.<br>
Sooth, madam, I hear nothing.
</p>

<p class="scenedesc">
Enter <span class="charname">the Soothsayer</span>.
</p>

<p class="drama">
PORTIA.<br>
Come hither, fellow:<br>
Which way hast thou been?
</p>

<p class="drama">
SOOTHSAYER.<br>
At mine own house, good lady.
</p>

<p class="drama">
PORTIA.<br>
What is’t o’clock?
</p>

<p class="drama">
SOOTHSAYER.<br>
About the ninth hour, lady.
</p>

<p class="drama">
PORTIA.<br>
Is Caesar yet gone to the Capitol?
</p>

<p class="drama">
SOOTHSAYER.<br>
Madam, not yet. I go to take my stand,<br>
To see him pass on to the Capitol.
</p>

<p class="drama">
PORTIA.<br>
Thou hast some suit to Caesar, hast thou not?
</p>

<p class="drama">
SOOTHSAYER.<br>
That I have, lady, if it will please Caesar<br>
To be so good to Caesar as to hear me,<br>
I shall beseech him to befriend himself.
</p>

<p class="drama">
PORTIA.<br>
Why, know’st thou any harm’s intended towards him?
</p>

<p class="drama">
SOOTHSAYER.<br>
None that I know will be, much that I fear may chance.<br>
Good morrow to you. Here the street is narrow.<br>
The throng that follows Caesar at the heels,<br>
Of Senators, of Praetors, common suitors,<br>
Will crowd a feeble man almost to death:<br>
I’ll get me to a place more void, and there<br>
Speak to great Caesar as he comes along.
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="drama">
PORTIA.<br>
I must go in.<br>
[<i>Aside.</i>] Ay me, how weak a thing<br>
The heart of woman is! O Brutus,<br>
The heavens speed thee in thine enterprise!<br>
Sure, the boy heard me. Brutus hath a suit<br>
That Caesar will not grant. O, I grow faint.<br>
Run, Lucius, and commend me to my lord;<br>
Say I am merry; come to me again,<br>
And bring me word what he doth say to thee.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

