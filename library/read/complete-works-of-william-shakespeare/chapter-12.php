<h2> <a id="sceneI_3.1"></a><b>ACT I</b></h2>

<h3> <b>SCENE I. Alexandria. A Room in Cleopatra’s palace.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Demetrius</span> and <span class="charname">Philo</span>.
</p>

<p class="drama">
PHILO.<br>
Nay, but this dotage of our general’s<br>
O’erflows the measure. Those his goodly eyes,<br>
That o’er the files and musters of the war<br>
Have glowed like plated Mars, now bend, now turn<br>
The office and devotion of their view<br>
Upon a tawny front. His captain’s heart,<br>
Which in the scuffles of great fights hath burst<br>
The buckles on his breast, reneges all temper<br>
And is become the bellows and the fan<br>
To cool a gipsy’s lust.
</p>

<p class="scenedesc">
Flourish. Enter <span class="charname">Antony</span> and <span class="charname">Cleopatra,</span> her Ladies, the Train, with Eunuchs fanning
her.
</p>

<p class="drama">
Look where they come:<br>
Take but good note, and you shall see in him<br>
The triple pillar of the world transform’d<br>
Into a strumpet’s fool. Behold and see.
</p>

<p class="drama">
CLEOPATRA.<br>
If it be love indeed, tell me how much.
</p>

<p class="drama">
ANTONY.<br>
There’s beggary in the love that can be reckoned.
</p>

<p class="drama">
CLEOPATRA.<br>
I’ll set a bourn how far to be beloved.
</p>

<p class="drama">
ANTONY.<br>
Then must thou needs find out new heaven, new earth.
</p>

<p class="scenedesc">
Enter a <span class="charname">Messenger</span>.
</p>

<p class="drama">
MESSENGER.<br>
News, my good lord, from Rome.
</p>

<p class="drama">
ANTONY.<br>
Grates me, the sum.
</p>

<p class="drama">
CLEOPATRA.<br>
Nay, hear them, Antony.<br>
Fulvia perchance is angry; or who knows<br>
If the scarce-bearded Caesar have not sent<br>
His powerful mandate to you: “Do this or this;<br>
Take in that kingdom and enfranchise that.<br>
Perform’t, or else we damn thee.”
</p>

<p class="drama">
ANTONY.<br>
How, my love?
</p>

<p class="drama">
CLEOPATRA.<br>
Perchance! Nay, and most like.<br>
You must not stay here longer; your dismission<br>
Is come from Caesar; therefore hear it, Antony.<br>
Where’s Fulvia’s process?—Caesar’s I would say? Both?<br>
Call in the messengers. As I am Egypt’s queen,<br>
Thou blushest, Antony, and that blood of thine<br>
Is Caesar’s homager; else so thy cheek pays shame<br>
When shrill-tongued Fulvia scolds. The messengers!
</p>

<p class="drama">
ANTONY.<br>
Let Rome in Tiber melt, and the wide arch<br>
Of the ranged empire fall! Here is my space.<br>
Kingdoms are clay. Our dungy earth alike<br>
Feeds beast as man. The nobleness of life<br>
Is to do thus [<i>Embracing</i>]; when such a mutual pair<br>
And such a twain can do’t, in which I bind,<br>
On pain of punishment, the world to weet<br>
We stand up peerless.
</p>

<p class="drama">
CLEOPATRA.<br>
Excellent falsehood!<br>
Why did he marry Fulvia, and not love her?<br>
I’ll seem the fool I am not. Antony<br>
Will be himself.
</p>

<p class="drama">
ANTONY.<br>
But stirred by Cleopatra.<br>
Now, for the love of Love and her soft hours,<br>
Let’s not confound the time with conference harsh.<br>
There’s not a minute of our lives should stretch<br>
Without some pleasure now. What sport tonight?
</p>

<p class="drama">
CLEOPATRA.<br>
Hear the ambassadors.
</p>

<p class="drama">
ANTONY.<br>
Fie, wrangling queen!<br>
Whom everything becomes—to chide, to laugh,<br>
To weep; whose every passion fully strives<br>
To make itself, in thee fair and admired!<br>
No messenger but thine, and all alone<br>
Tonight we’ll wander through the streets and note<br>
The qualities of people. Come, my queen,<br>
Last night you did desire it. Speak not to us.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Antony</span> and <span class="charname">Cleopatra</span> with the Train.</i>]
</p>

<p class="drama">
DEMETRIUS.<br>
Is Caesar with Antonius prized so slight?
</p>

<p class="drama">
PHILO.<br>
Sir, sometimes when he is not Antony,<br>
He comes too short of that great property<br>
Which still should go with Antony.
</p>

<p class="drama">
DEMETRIUS.<br>
I am full sorry<br>
That he approves the common liar who<br>
Thus speaks of him at Rome, but I will hope<br>
Of better deeds tomorrow. Rest you happy!
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneI_3.2"></a><b>SCENE II. Alexandria. Another Room in
Cleopatra’s palace.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Enobarbus,</span> a <span class="charname">Soothsayer, Charmian, Iras, Mardian</span> and <span class="charname">Alexas</span>.
</p>

<p class="drama">
CHARMIAN.<br>
Lord Alexas, sweet Alexas, most anything Alexas, almost most absolute Alexas,
where’s the soothsayer that you praised so to th’ queen? O, that I knew this
husband which you say must charge his horns with garlands!
</p>

<p class="drama">
ALEXAS.<br>
Soothsayer!
</p>

<p class="drama">
SOOTHSAYER.<br>
Your will?
</p>

<p class="drama">
CHARMIAN.<br>
Is this the man? Is’t you, sir, that know things?
</p>

<p class="drama">
SOOTHSAYER.<br>
In nature’s infinite book of secrecy<br>
A little I can read.
</p>

<p class="drama">
ALEXAS.<br>
Show him your hand.
</p>

<p class="drama">
ENOBARBUS.<br>
Bring in the banquet quickly; wine enough<br>
Cleopatra’s health to drink.
</p>

<p class="drama">
CHARMIAN.<br>
Good, sir, give me good fortune.
</p>

<p class="drama">
SOOTHSAYER.<br>
I make not, but foresee.
</p>

<p class="drama">
CHARMIAN.<br>
Pray, then, foresee me one.
</p>

<p class="drama">
SOOTHSAYER.<br>
You shall be yet far fairer than you are.
</p>

<p class="drama">
CHARMIAN.<br>
He means in flesh.
</p>

<p class="drama">
IRAS.<br>
No, you shall paint when you are old.
</p>

<p class="drama">
CHARMIAN.<br>
Wrinkles forbid!
</p>

<p class="drama">
ALEXAS.<br>
Vex not his prescience. Be attentive.
</p>

<p class="drama">
CHARMIAN.<br>
Hush!
</p>

<p class="drama">
SOOTHSAYER.<br>
You shall be more beloving than beloved.
</p>

<p class="drama">
CHARMIAN.<br>
I had rather heat my liver with drinking.
</p>

<p class="drama">
ALEXAS.<br>
Nay, hear him.
</p>

<p class="drama">
CHARMIAN.<br>
Good now, some excellent fortune! Let me be married to three kings in a
forenoon and widow them all. Let me have a child at fifty, to whom Herod of
Jewry may do homage. Find me to marry me with Octavius Caesar, and companion me
with my mistress.
</p>

<p class="drama">
SOOTHSAYER.<br>
You shall outlive the lady whom you serve.
</p>

<p class="drama">
CHARMIAN.<br>
O, excellent! I love long life better than figs.
</p>

<p class="drama">
SOOTHSAYER.<br>
You have seen and proved a fairer former fortune<br>
Than that which is to approach.
</p>

<p class="drama">
CHARMIAN.<br>
Then belike my children shall have no names. Prithee, how many boys and wenches
must I have?
</p>

<p class="drama">
SOOTHSAYER.<br>
If every of your wishes had a womb,<br>
And fertile every wish, a million.
</p>

<p class="drama">
CHARMIAN.<br>
Out, fool! I forgive thee for a witch.
</p>

<p class="drama">
ALEXAS.<br>
You think none but your sheets are privy to your wishes.
</p>

<p class="drama">
CHARMIAN.<br>
Nay, come, tell Iras hers.
</p>

<p class="drama">
ALEXAS.<br>
We’ll know all our fortunes.
</p>

<p class="drama">
ENOBARBUS.<br>
Mine, and most of our fortunes tonight, shall be drunk to bed.
</p>

<p class="drama">
IRAS.<br>
There’s a palm presages chastity, if nothing else.
</p>

<p class="drama">
CHARMIAN.<br>
E’en as the o’erflowing Nilus presageth famine.
</p>

<p class="drama">
IRAS.<br>
Go, you wild bedfellow, you cannot soothsay.
</p>

<p class="drama">
CHARMIAN.<br>
Nay, if an oily palm be not a fruitful prognostication, I cannot scratch mine
ear. Prithee, tell her but workaday fortune.
</p>

<p class="drama">
SOOTHSAYER.<br>
Your fortunes are alike.
</p>

<p class="drama">
IRAS.<br>
But how, but how? give me particulars.
</p>

<p class="drama">
SOOTHSAYER.<br>
I have said.
</p>

<p class="drama">
IRAS.<br>
Am I not an inch of fortune better than she?
</p>

<p class="drama">
CHARMIAN.<br>
Well, if you were but an inch of fortune better than I, where would you choose
it?
</p>

<p class="drama">
IRAS.<br>
Not in my husband’s nose.
</p>

<p class="drama">
CHARMIAN.<br>
Our worser thoughts heavens mend! Alexas—come, his fortune! his fortune! O, let
him marry a woman that cannot go, sweet Isis, I beseech thee, and let her die
too, and give him a worse, and let worse follow worse, till the worst of all
follow him laughing to his grave, fiftyfold a cuckold! Good Isis, hear me this
prayer, though thou deny me a matter of more weight; good Isis, I beseech thee!
</p>

<p class="drama">
IRAS.<br>
Amen. Dear goddess, hear that prayer of the people! For, as it is a
heartbreaking to see a handsome man loose-wived, so it is a deadly sorrow to
behold a foul knave uncuckolded. Therefore, dear Isis, keep decorum and fortune
him accordingly!
</p>

<p class="drama">
CHARMIAN.<br>
Amen.
</p>

<p class="drama">
ALEXAS.<br>
Lo now, if it lay in their hands to make me a cuckold, they would make
themselves whores but they’d do’t!
</p>

<p class="scenedesc">
Enter <span class="charname">Cleopatra</span>.
</p>

<p class="drama">
ENOBARBUS.<br>
Hush, Here comes Antony.
</p>

<p class="drama">
CHARMIAN.<br>
Not he, the queen.
</p>

<p class="drama">
CLEOPATRA.<br>
Saw you my lord?
</p>

<p class="drama">
ENOBARBUS.<br>
No, lady.
</p>

<p class="drama">
CLEOPATRA.<br>
Was he not here?
</p>

<p class="drama">
CHARMIAN.<br>
No, madam.
</p>

<p class="drama">
CLEOPATRA.<br>
He was disposed to mirth; but on the sudden<br>
A Roman thought hath struck him. Enobarbus!
</p>

<p class="drama">
ENOBARBUS.<br>
Madam?
</p>

<p class="drama">
CLEOPATRA.<br>
Seek him and bring him hither. Where’s Alexas?
</p>

<p class="drama">
ALEXAS.<br>
Here, at your service. My lord approaches.
</p>

<p class="scenedesc">
Enter <span class="charname">Antony</span> with a <span class="charname">Messenger</span>.
</p>

<p class="drama">
CLEOPATRA.<br>
We will not look upon him. Go with us.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Cleopatra, Enobarbus, Charmian, Iras,
Alexas</span> and <span class="charname">Soothsayer</span>.</i>]
</p>

<p class="drama">
MESSENGER.<br>
Fulvia thy wife first came into the field.
</p>

<p class="drama">
ANTONY.<br>
Against my brother Lucius.
</p>

<p class="drama">
MESSENGER.<br>
Ay.<br>
But soon that war had end, and the time’s state<br>
Made friends of them, jointing their force ’gainst Caesar,<br>
Whose better issue in the war from Italy<br>
Upon the first encounter drave them.
</p>

<p class="drama">
ANTONY.<br>
Well, what worst?
</p>

<p class="drama">
MESSENGER.<br>
The nature of bad news infects the teller.
</p>

<p class="drama">
ANTONY.<br>
When it concerns the fool or coward. On.<br>
Things that are past are done with me. ’Tis thus:<br>
Who tells me true, though in his tale lie death,<br>
I hear him as he flattered.
</p>

<p class="drama">
MESSENGER.<br>
Labienus—<br>
This is stiff news—hath with his Parthian force<br>
Extended Asia from Euphrates<br>
His conquering banner shook from Syria<br>
To Lydia and to Ionia,<br>
Whilst—
</p>

<p class="drama">
ANTONY.<br>
“Antony”, thou wouldst say—
</p>

<p class="drama">
MESSENGER.<br>
O, my lord!
</p>

<p class="drama">
ANTONY.<br>
Speak to me home; mince not the general tongue.<br>
Name Cleopatra as she is called in Rome;<br>
Rail thou in Fulvia’s phrase, and taunt my faults<br>
With such full licence as both truth and malice<br>
Have power to utter. O, then we bring forth weeds<br>
When our quick minds lie still, and our ills told us<br>
Is as our earing. Fare thee well awhile.
</p>

<p class="drama">
MESSENGER.<br>
At your noble pleasure.
</p>

<p class="right">
[<i>Exit <span class="charname">Messenger</span>.</i>]
</p>

<p class="scenedesc">
Enter another <span class="charname">Messenger</span>.
</p>

<p class="drama">
ANTONY.<br>
From Sicyon, ho, the news? Speak there!
</p>

<p class="drama">
SECOND MESSENGER.<br>
The man from Sicyon—
</p>

<p class="drama">
ANTONY.<br>
Is there such a one?
</p>

<p class="drama">
SECOND MESSENGER.<br>
He stays upon your will.
</p>

<p class="drama">
ANTONY.<br>
Let him appear.<br>
</p>

<p class="right">
[<i>Exit second <span class="charname">Messenger</span>.</i>]
</p>

<p class="drama">
These strong Egyptian fetters I must break,<br>
Or lose myself in dotage.
</p>

<p class="scenedesc">
Enter another <span class="charname">Messenger</span> with a letter.
</p>

<p class="drama">
What are you?
</p>

<p class="drama">
THIRD MESSENGER.<br>
Fulvia thy wife is dead.
</p>

<p class="drama">
ANTONY.<br>
Where died she?
</p>

<p class="drama">
THIRD MESSENGER.<br>
In Sicyon:<br>
Her length of sickness, with what else more serious<br>
Importeth thee to know, this bears.
</p>

<p class="right">
[<i>Gives a letter.</i>]
</p>

<p class="drama">
ANTONY.<br>
Forbear me.
</p>

<p class="right">
[<i>Exit third <span class="charname">Messenger</span>.</i>]
</p>

<p class="drama">
There’s a great spirit gone! Thus did I desire it.<br>
What our contempts doth often hurl from us,<br>
We wish it ours again. The present pleasure,<br>
By revolution lowering, does become<br>
The opposite of itself. She’s good, being gone.<br>
The hand could pluck her back that shoved her on.<br>
I must from this enchanting queen break off.<br>
Ten thousand harms, more than the ills I know,<br>
My idleness doth hatch. How now, Enobarbus!
</p>

<p class="scenedesc">
Enter <span class="charname">Enobarbus</span>.
</p>

<p class="drama">
ENOBARBUS.<br>
What’s your pleasure, sir?
</p>

<p class="drama">
ANTONY.<br>
I must with haste from hence.
</p>

<p class="drama">
ENOBARBUS.<br>
Why then we kill all our women. We see how mortal an unkindness is to them. If
they suffer our departure, death’s the word.
</p>

<p class="drama">
ANTONY.<br>
I must be gone.
</p>

<p class="drama">
ENOBARBUS.<br>
Under a compelling occasion, let women die. It were pity to cast them away for
nothing, though, between them and a great cause they should be esteemed
nothing. Cleopatra, catching but the least noise of this, dies instantly. I
have seen her die twenty times upon far poorer moment. I do think there is
mettle in death which commits some loving act upon her, she hath such a
celerity in dying.
</p>

<p class="drama">
ANTONY.<br>
She is cunning past man’s thought.
</p>

<p class="drama">
ENOBARBUS.<br>
Alack, sir, no; her passions are made of nothing but the finest part of pure
love. We cannot call her winds and waters sighs and tears; they are greater
storms and tempests than almanacs can report. This cannot be cunning in her; if
it be, she makes a shower of rain as well as Jove.
</p>

<p class="drama">
ANTONY.<br>
Would I had never seen her!
</p>

<p class="drama">
ENOBARBUS.<br>
O, sir, you had then left unseen a wonderful piece of work, which not to have
been blest withal would have discredited your travel.
</p>

<p class="drama">
ANTONY.<br>
Fulvia is dead.
</p>

<p class="drama">
ENOBARBUS.<br>
Sir?
</p>

<p class="drama">
ANTONY.<br>
Fulvia is dead.
</p>

<p class="drama">
ENOBARBUS.<br>
Fulvia?
</p>

<p class="drama">
ANTONY.<br>
Dead.
</p>

<p class="drama">
ENOBARBUS.<br>
Why, sir, give the gods a thankful sacrifice. When it pleaseth their deities to
take the wife of a man from him, it shows to man the tailors of the earth;
comforting therein that when old robes are worn out, there are members to make
new. If there were no more women but Fulvia, then had you indeed a cut, and the
case to be lamented. This grief is crowned with consolation; your old smock
brings forth a new petticoat: and indeed the tears live in an onion that should
water this sorrow.
</p>

<p class="drama">
ANTONY.<br>
The business she hath broached in the state<br>
Cannot endure my absence.
</p>

<p class="drama">
ENOBARBUS.<br>
And the business you have broached here cannot be without you, especially that
of Cleopatra’s, which wholly depends on your abode.
</p>

<p class="drama">
ANTONY.<br>
No more light answers. Let our officers<br>
Have notice what we purpose. I shall break<br>
The cause of our expedience to the Queen,<br>
And get her leave to part. For not alone<br>
The death of Fulvia, with more urgent touches,<br>
Do strongly speak to us, but the letters too<br>
Of many our contriving friends in Rome<br>
Petition us at home. Sextus Pompeius<br>
Hath given the dare to Caesar, and commands<br>
The empire of the sea. Our slippery people,<br>
Whose love is never linked to the deserver<br>
Till his deserts are past, begin to throw<br>
Pompey the Great and all his dignities<br>
Upon his son, who, high in name and power,<br>
Higher than both in blood and life, stands up<br>
For the main soldier; whose quality, going on,<br>
The sides o’ th’ world may danger. Much is breeding<br>
Which, like the courser’s hair, hath yet but life<br>
And not a serpent’s poison. Say our pleasure<br>
To such whose place is under us, requires<br>
Our quick remove from hence.
</p>

<p class="drama">
ENOBARBUS.<br>
I shall do’t.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneI_3.3"></a><b>SCENE III. Alexandria. A Room in Cleopatra’s
palace.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Cleopatra, Charmian, Alexas</span> and <span class="charname">Iras</span>.
</p>

<p class="drama">
CLEOPATRA.<br>
Where is he?
</p>

<p class="drama">
CHARMIAN.<br>
I did not see him since.
</p>

<p class="drama">
CLEOPATRA.<br>
See where he is, who’s with him, what he does.<br>
I did not send you. If you find him sad,<br>
Say I am dancing; if in mirth, report<br>
That I am sudden sick. Quick, and return.
</p>

<p class="right">
[<i>Exit <span class="charname">Alexas</span>.</i>]
</p>

<p class="drama">
CHARMIAN.<br>
Madam, methinks, if you did love him dearly,<br>
You do not hold the method to enforce<br>
The like from him.
</p>

<p class="drama">
CLEOPATRA.<br>
What should I do I do not?
</p>

<p class="drama">
CHARMIAN.<br>
In each thing give him way; cross him in nothing.
</p>

<p class="drama">
CLEOPATRA.<br>
Thou teachest like a fool: the way to lose him.
</p>

<p class="drama">
CHARMIAN.<br>
Tempt him not so too far; I wish, forbear.<br>
In time we hate that which we often fear.<br>
But here comes Antony.
</p>

<p class="scenedesc">
Enter <span class="charname">Antony</span>.
</p>

<p class="drama">
CLEOPATRA.<br>
I am sick and sullen.
</p>

<p class="drama">
ANTONY.<br>
I am sorry to give breathing to my purpose—
</p>

<p class="drama">
CLEOPATRA.<br>
Help me away, dear Charmian! I shall fall.<br>
It cannot be thus long; the sides of nature<br>
Will not sustain it.
</p>

<p class="drama">
ANTONY.<br>
Now, my dearest queen—
</p>

<p class="drama">
CLEOPATRA.<br>
Pray you, stand farther from me.
</p>

<p class="drama">
ANTONY.<br>
What’s the matter?
</p>

<p class="drama">
CLEOPATRA.<br>
I know by that same eye there’s some good news.<br>
What, says the married woman you may go?<br>
Would she had never given you leave to come!<br>
Let her not say ’tis I that keep you here.<br>
I have no power upon you; hers you are.
</p>

<p class="drama">
ANTONY.<br>
The gods best know—
</p>

<p class="drama">
CLEOPATRA.<br>
O, never was there queen<br>
So mightily betrayed! Yet at the first<br>
I saw the treasons planted.
</p>

<p class="drama">
ANTONY.<br>
Cleopatra—
</p>

<p class="drama">
CLEOPATRA.<br>
Why should I think you can be mine and true,<br>
Though you in swearing shake the throned gods,<br>
Who have been false to Fulvia? Riotous madness,<br>
To be entangled with those mouth-made vows<br>
Which break themselves in swearing!
</p>

<p class="drama">
ANTONY.<br>
Most sweet queen—
</p>

<p class="drama">
CLEOPATRA.<br>
Nay, pray you seek no colour for your going,<br>
But bid farewell and go. When you sued staying,<br>
Then was the time for words. No going then,<br>
Eternity was in our lips and eyes,<br>
Bliss in our brows’ bent; none our parts so poor<br>
But was a race of heaven. They are so still,<br>
Or thou, the greatest soldier of the world,<br>
Art turned the greatest liar.
</p>

<p class="drama">
ANTONY.<br>
How now, lady!
</p>

<p class="drama">
CLEOPATRA.<br>
I would I had thy inches, thou shouldst know<br>
There were a heart in Egypt.
</p>

<p class="drama">
ANTONY.<br>
Hear me, queen:<br>
The strong necessity of time commands<br>
Our services awhile, but my full heart<br>
Remains in use with you. Our Italy<br>
Shines o’er with civil swords; Sextus Pompeius<br>
Makes his approaches to the port of Rome;<br>
Equality of two domestic powers<br>
Breed scrupulous faction; the hated, grown to strength,<br>
Are newly grown to love; the condemned Pompey,<br>
Rich in his father’s honour, creeps apace<br>
Into the hearts of such as have not thrived<br>
Upon the present state, whose numbers threaten;<br>
And quietness, grown sick of rest, would purge<br>
By any desperate change. My more particular,<br>
And that which most with you should safe my going,<br>
Is Fulvia’s death.
</p>

<p class="drama">
CLEOPATRA.<br>
Though age from folly could not give me freedom,<br>
It does from childishness. Can Fulvia die?
</p>

<p class="drama">
ANTONY.<br>
She’s dead, my queen.<br>
Look here, and at thy sovereign leisure read<br>
The garboils she awaked; at the last, best,<br>
See when and where she died.
</p>

<p class="drama">
CLEOPATRA.<br>
O most false love!<br>
Where be the sacred vials thou shouldst fill<br>
With sorrowful water? Now I see, I see,<br>
In Fulvia’s death how mine received shall be.
</p>

<p class="drama">
ANTONY.<br>
Quarrel no more, but be prepared to know<br>
The purposes I bear; which are, or cease,<br>
As you shall give th’ advice. By the fire<br>
That quickens Nilus’ slime, I go from hence<br>
Thy soldier, servant, making peace or war<br>
As thou affects.
</p>

<p class="drama">
CLEOPATRA.<br>
Cut my lace, Charmian, come!<br>
But let it be; I am quickly ill and well,<br>
So Antony loves.
</p>

<p class="drama">
ANTONY.<br>
My precious queen, forbear,<br>
And give true evidence to his love, which stands<br>
An honourable trial.
</p>

<p class="drama">
CLEOPATRA.<br>
So Fulvia told me.<br>
I prithee, turn aside and weep for her,<br>
Then bid adieu to me, and say the tears<br>
Belong to Egypt. Good now, play one scene<br>
Of excellent dissembling, and let it look<br>
Like perfect honour.
</p>

<p class="drama">
ANTONY.<br>
You’ll heat my blood. No more.
</p>

<p class="drama">
CLEOPATRA.<br>
You can do better yet, but this is meetly.
</p>

<p class="drama">
ANTONY.<br>
Now, by my sword—
</p>

<p class="drama">
CLEOPATRA.<br>
And target. Still he mends.<br>
But this is not the best. Look, prithee, Charmian,<br>
How this Herculean Roman does become<br>
The carriage of his chafe.
</p>

<p class="drama">
ANTONY.<br>
I’ll leave you, lady.
</p>

<p class="drama">
CLEOPATRA.<br>
Courteous lord, one word.<br>
Sir, you and I must part, but that’s not it;<br>
Sir, you and I have loved, but there’s not it;<br>
That you know well. Something it is I would—<br>
O, my oblivion is a very Antony,<br>
And I am all forgotten.
</p>

<p class="drama">
ANTONY.<br>
But that your royalty<br>
Holds idleness your subject, I should take you<br>
For idleness itself.
</p>

<p class="drama">
CLEOPATRA.<br>
’Tis sweating labour<br>
To bear such idleness so near the heart<br>
As Cleopatra this. But, sir, forgive me,<br>
Since my becomings kill me when they do not<br>
Eye well to you. Your honour calls you hence;<br>
Therefore be deaf to my unpitied folly,<br>
And all the gods go with you! Upon your sword<br>
Sit laurel victory, and smooth success<br>
Be strewed before your feet!
</p>

<p class="drama">
ANTONY.<br>
Let us go. Come.<br>
Our separation so abides and flies<br>
That thou, residing here, goes yet with me,<br>
And I, hence fleeting, here remain with thee.<br>
Away!
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneI_3.4"></a><b>SCENE IV. Rome. An Apartment in Caesar’s
House.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Octavius [Caesar], Lepidus</span> and their train.
</p>

<p class="drama">
CAESAR.<br>
You may see, Lepidus, and henceforth know,<br>
It is not Caesar’s natural vice to hate<br>
Our great competitor. From Alexandria<br>
This is the news: he fishes, drinks, and wastes<br>
The lamps of night in revel: is not more manlike<br>
Than Cleopatra, nor the queen of Ptolemy<br>
More womanly than he; hardly gave audience, or<br>
Vouchsafed to think he had partners. You shall find there<br>
A man who is the abstract of all faults<br>
That all men follow.
</p>

<p class="drama">
LEPIDUS.<br>
I must not think there are<br>
Evils enough to darken all his goodness.<br>
His faults in him seem as the spots of heaven,<br>
More fiery by night’s blackness; hereditary<br>
Rather than purchased; what he cannot change<br>
Than what he chooses.
</p>

<p class="drama">
CAESAR.<br>
You are too indulgent. Let’s grant it is not<br>
Amiss to tumble on the bed of Ptolemy,<br>
To give a kingdom for a mirth, to sit<br>
And keep the turn of tippling with a slave,<br>
To reel the streets at noon, and stand the buffet<br>
With knaves that smell of sweat. Say this becomes him—<br>
As his composure must be rare indeed<br>
Whom these things cannot blemish—yet must Antony<br>
No way excuse his foils when we do bear<br>
So great weight in his lightness. If he filled<br>
His vacancy with his voluptuousness,<br>
Full surfeits and the dryness of his bones<br>
Call on him for’t. But to confound such time<br>
That drums him from his sport, and speaks as loud<br>
As his own state and ours, ’tis to be chid<br>
As we rate boys who, being mature in knowledge,<br>
Pawn their experience to their present pleasure<br>
And so rebel to judgment.
</p>

<p class="scenedesc">
Enter a <span class="charname">Messenger</span>.
</p>

<p class="drama">
LEPIDUS.<br>
Here’s more news.
</p>

<p class="drama">
MESSENGER.<br>
Thy biddings have been done, and every hour,<br>
Most noble Caesar, shalt thou have report<br>
How ’tis abroad. Pompey is strong at sea,<br>
And it appears he is beloved of those<br>
That only have feared Caesar. To the ports<br>
The discontents repair, and men’s reports<br>
Give him much wronged.
</p>

<p class="drama">
CAESAR.<br>
I should have known no less.<br>
It hath been taught us from the primal state<br>
That he which is was wished until he were,<br>
And the ebbed man, ne’er loved till ne’er worth love,<br>
Comes deared by being lacked. This common body,<br>
Like to a vagabond flag upon the stream,<br>
Goes to and back, lackeying the varying tide,<br>
To rot itself with motion.
</p>

<p class="scenedesc">
Enter a second <span class="charname">Messenger</span>.
</p>

<p class="drama">
SECOND MESSENGER.<br>
Caesar, I bring thee word<br>
Menecrates and Menas, famous pirates,<br>
Make the sea serve them, which they ear and wound<br>
With keels of every kind. Many hot inroads<br>
They make in Italy—the borders maritime<br>
Lack blood to think on’t—and flush youth revolt.<br>
No vessel can peep forth but ’tis as soon<br>
Taken as seen; for Pompey’s name strikes more<br>
Than could his war resisted.
</p>

<p class="drama">
CAESAR.<br>
Antony,<br>
Leave thy lascivious wassails. When thou once<br>
Was beaten from Modena, where thou slew’st<br>
Hirtius and Pansa, consuls, at thy heel<br>
Did famine follow, whom thou fought’st against,<br>
Though daintily brought up, with patience more<br>
Than savages could suffer. Thou didst drink<br>
The stale of horses and the gilded puddle<br>
Which beasts would cough at. Thy palate then did deign<br>
The roughest berry on the rudest hedge.<br>
Yea, like the stag when snow the pasture sheets,<br>
The barks of trees thou browsed. On the Alps<br>
It is reported thou didst eat strange flesh<br>
Which some did die to look on. And all this—<br>
It wounds thine honour that I speak it now—<br>
Was borne so like a soldier that thy cheek<br>
So much as lanked not.
</p>

<p class="drama">
LEPIDUS.<br>
’Tis pity of him.
</p>

<p class="drama">
CAESAR.<br>
Let his shames quickly<br>
Drive him to Rome. ’Tis time we twain<br>
Did show ourselves i’ th’ field, and to that end<br>
Assemble we immediate council. Pompey<br>
Thrives in our idleness.
</p>

<p class="drama">
LEPIDUS.<br>
Tomorrow, Caesar,<br>
I shall be furnished to inform you rightly<br>
Both what by sea and land I can be able<br>
To front this present time.
</p>

<p class="drama">
CAESAR.<br>
Till which encounter<br>
It is my business too. Farewell.
</p>

<p class="drama">
LEPIDUS.<br>
Farewell, my lord. What you shall know meantime<br>
Of stirs abroad, I shall beseech you, sir,<br>
To let me be partaker.
</p>

<p class="drama">
CAESAR.<br>
Doubt not, sir.<br>
I knew it for my bond.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneI_3.5"></a><b>SCENE V. Alexandria. A Room in the
Palace.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Cleopatra, Charmian, Iras</span> and <span class="charname">Mardian</span>.
</p>

<p class="drama">
CLEOPATRA.<br>
Charmian!
</p>

<p class="drama">
CHARMIAN.<br>
Madam?
</p>

<p class="drama">
CLEOPATRA.<br>
Ha, ha!<br>
Give me to drink mandragora.
</p>

<p class="drama">
CHARMIAN.<br>
Why, madam?
</p>

<p class="drama">
CLEOPATRA.<br>
That I might sleep out this great gap of time<br>
My Antony is away.
</p>

<p class="drama">
CHARMIAN.<br>
You think of him too much.
</p>

<p class="drama">
CLEOPATRA.<br>
O, ’tis treason!
</p>

<p class="drama">
CHARMIAN.<br>
Madam, I trust not so.
</p>

<p class="drama">
CLEOPATRA.<br>
Thou, eunuch Mardian!
</p>

<p class="drama">
MARDIAN.<br>
What’s your highness’ pleasure?
</p>

<p class="drama">
CLEOPATRA.<br>
Not now to hear thee sing. I take no pleasure<br>
In aught an eunuch has. ’Tis well for thee<br>
That, being unseminared, thy freer thoughts<br>
May not fly forth of Egypt. Hast thou affections?
</p>

<p class="drama">
MARDIAN.<br>
Yes, gracious madam.
</p>

<p class="drama">
CLEOPATRA.<br>
Indeed?
</p>

<p class="drama">
MARDIAN.<br>
Not in deed, madam, for I can do nothing<br>
But what indeed is honest to be done.<br>
Yet have I fierce affections, and think<br>
What Venus did with Mars.
</p>

<p class="drama">
CLEOPATRA.<br>
O, Charmian,<br>
Where think’st thou he is now? Stands he, or sits he?<br>
Or does he walk? Or is he on his horse?<br>
O happy horse, to bear the weight of Antony!<br>
Do bravely, horse, for wot’st thou whom thou mov’st?<br>
The demi-Atlas of this earth, the arm<br>
And burgonet of men. He’s speaking now,<br>
Or murmuring “Where’s my serpent of old Nile?”<br>
For so he calls me. Now I feed myself<br>
With most delicious poison. Think on me<br>
That am with Phœbus’ amorous pinches black,<br>
And wrinkled deep in time? Broad-fronted Caesar,<br>
When thou wast here above the ground, I was<br>
A morsel for a monarch. And great Pompey<br>
Would stand and make his eyes grow in my brow;<br>
There would he anchor his aspect, and die<br>
With looking on his life.
</p>

<p class="scenedesc">
Enter <span class="charname">Alexas</span>.
</p>

<p class="drama">
ALEXAS.<br>
Sovereign of Egypt, hail!
</p>

<p class="drama">
CLEOPATRA.<br>
How much unlike art thou Mark Antony!<br>
Yet, coming from him, that great medicine hath<br>
With his tinct gilded thee.<br>
How goes it with my brave Mark Antony?
</p>

<p class="drama">
ALEXAS.<br>
Last thing he did, dear queen,<br>
He kissed—the last of many doubled kisses—<br>
This orient pearl. His speech sticks in my heart.
</p>

<p class="drama">
CLEOPATRA.<br>
Mine ear must pluck it thence.
</p>

<p class="drama">
ALEXAS.<br>
“Good friend,” quoth he,<br>
“Say, the firm Roman to great Egypt sends<br>
This treasure of an oyster; at whose foot,<br>
To mend the petty present, I will piece<br>
Her opulent throne with kingdoms. All the east,<br>
Say thou, shall call her mistress.” So he nodded<br>
And soberly did mount an arm-gaunt steed,<br>
Who neighed so high that what I would have spoke<br>
Was beastly dumbed by him.
</p>

<p class="drama">
CLEOPATRA.<br>
What, was he sad or merry?
</p>

<p class="drama">
ALEXAS.<br>
Like to the time o’ th’ year between the extremes<br>
Of hot and cold, he was nor sad nor merry.
</p>

<p class="drama">
CLEOPATRA.<br>
O well-divided disposition!—Note him,<br>
Note him, good Charmian, ’tis the man; but note him:<br>
He was not sad, for he would shine on those<br>
That make their looks by his; he was not merry,<br>
Which seemed to tell them his remembrance lay<br>
In Egypt with his joy; but between both.<br>
O heavenly mingle!—Be’st thou sad or merry,<br>
The violence of either thee becomes,<br>
So does it no man else.—Met’st thou my posts?
</p>

<p class="drama">
ALEXAS.<br>
Ay, madam, twenty several messengers.<br>
Why do you send so thick?
</p>

<p class="drama">
CLEOPATRA.<br>
Who’s born that day<br>
When I forget to send to Antony<br>
Shall die a beggar.—Ink and paper, Charmian.—<br>
Welcome, my good Alexas.—Did I, Charmian,<br>
Ever love Caesar so?
</p>

<p class="drama">
CHARMIAN.<br>
O that brave Caesar!
</p>

<p class="drama">
CLEOPATRA.<br>
Be choked with such another emphasis!<br>
Say “the brave Antony.”
</p>

<p class="drama">
CHARMIAN.<br>
The valiant Caesar!
</p>

<p class="drama">
CLEOPATRA.<br>
By Isis, I will give thee bloody teeth<br>
If thou with Caesar paragon again<br>
My man of men.
</p>

<p class="drama">
CHARMIAN.<br>
By your most gracious pardon,<br>
I sing but after you.
</p>

<p class="drama">
CLEOPATRA.<br>
My salad days,<br>
When I was green in judgment, cold in blood,<br>
To say as I said then. But come, away,<br>
Get me ink and paper.<br>
He shall have every day a several greeting,<br>
Or I’ll unpeople Egypt.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

