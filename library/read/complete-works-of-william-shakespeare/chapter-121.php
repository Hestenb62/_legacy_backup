<h2> <a id="sceneV_19.1"></a><b>ACT V</b></h2>

<h3> <b>SCENE I. The King of Navarre’s park</b></h3>

<p class="scenedesc">
Enter <span class="charname">Holofernes, Sir Nathaniel</span> and
<span class="charname">Dull</span>.
</p>

<p class="drama">
HOLOFERNES.<br>
<i>Satis quod sufficit.</i>
</p>

<p class="drama">
NATHANIEL.<br>
I praise God for you, sir. Your reasons at dinner have been sharp and
sententious, pleasant without scurrility, witty without affection, audacious
without impudency, learned without opinion, and strange without heresy. I did
converse this <i>quondam</i> day with a companion of the King’s, who is
intituled, nominated, or called, Don Adriano de Armado.
</p>

<p class="drama">
HOLOFERNES.<br>
<i>Novi hominem tanquam te.</i> His humour is lofty, his discourse peremptory,
his tongue filed, his eye ambitious, his gait majestical and his general
behaviour vain, ridiculous, and thrasonical. He is too picked, too spruce, too
affected, too odd, as it were, too peregrinate, as I may call it.
</p>

<p class="drama">
NATHANIEL.<br>
A most singular and choice epithet.
</p>

<p class="right">[<i>Draws out his table-book.</i>]</p>

<p class="drama">
HOLOFERNES.<br>
He draweth out the thread of his verbosity finer than the staple of his
argument. I abhor such fanatical phantasimes, such insociable and point-devise
companions, such rackers of orthography, as to speak “dout” <i>sine</i> “b”,
when he should say “doubt”, “det” when he should pronounce “debt”—<i>d, e, b,
t</i>, not <i>d, e, t</i>. He clepeth a calf “cauf”, half “hauf”; neighbour
<i>vocatur</i> “nebour”, neigh abbreviated “ne”. This is abhominable, which he
would call “abominable”. It insinuateth me of insanie. <i>Ne intelligis,
domine?</i> To make frantic, lunatic.
</p>

<p class="drama">
NATHANIEL.<br>
<i>Laus Deo, bone intelligo.</i>
</p>

<p class="drama">
HOLOFERNES.<br>
<i>Bone? Bone</i> for <i>bene?</i> Priscian a little scratched; ’twill serve.
</p>

<p class="scenedesc">
Enter <span class="charname">Armado, Moth</span> and
<span class="charname">Costard</span>.
</p>

<p class="drama">
NATHANIEL.<br>
<i>Videsne quis venit?</i>
</p>

<p class="drama">
HOLOFERNES.<br>
<i>Video, et gaudeo.</i>
</p>

<p class="drama">
ARMADO.<br>
<i>Chirrah!</i>
</p>

<p class="drama">
HOLOFERNES.<br>
<i>Quare</i> “chirrah”, not “sirrah”?
</p>

<p class="drama">
ARMADO.<br>
Men of peace, well encountered.
</p>

<p class="drama">
HOLOFERNES.<br>
Most military sir, salutation.
</p>

<p class="drama">
MOTH.<br>
[<i>Aside to Costard</i>.] They have been at a great feast of languages and
stolen the scraps.
</p>

<p class="drama">
COSTARD.<br>
O, they have lived long on the almsbasket of words. I marvel thy master hath
not eaten thee for a word, for thou art not so long by the head as
<i>honorificabilitudinitatibus</i>. Thou art easier swallowed than a
flap-dragon.
</p>

<p class="drama">
MOTH.<br>
Peace! The peal begins.
</p>

<p class="drama">
ARMADO.<br>
[<i>To Holofernes</i>.] Monsieur, are you not lettered?
</p>

<p class="drama">
MOTH.<br>
Yes, yes, he teaches boys the hornbook. What is <i>a, b</i>, spelt backward
with the horn on his head?
</p>

<p class="drama">
HOLOFERNES.<br>
<i>Ba, pueritia</i>, with a horn added.
</p>

<p class="drama">
MOTH.<br>
<i>Ba</i>, most silly sheep with a horn. You hear his learning.
</p>

<p class="drama">
HOLOFERNES.<br>
<i>Quis, quis</i>, thou consonant?
</p>

<p class="drama">
MOTH.<br>
The third of the five vowels, if you repeat them; or the fifth, if I.
</p>

<p class="drama">
HOLOFERNES.<br>
I will repeat them: <i>a, e, i</i>—
</p>

<p class="drama">
MOTH.<br>
The sheep. The other two concludes it: <i>o, u</i>.
</p>

<p class="drama">
ARMADO.<br>
Now, by the salt wave of the Mediterraneum, a sweet touch, a quick venue of
wit! Snip, snap, quick and home! It rejoiceth my intellect. True wit!
</p>

<p class="drama">
MOTH.<br>
Offered by a child to an old man—which is wit-old.
</p>

<p class="drama">
HOLOFERNES.<br>
What is the figure? What is the figure?
</p>

<p class="drama">
MOTH.<br>
Horns.
</p>

<p class="drama">
HOLOFERNES.<br>
Thou disputes like an infant. Go whip thy gig.
</p>

<p class="drama">
MOTH.<br>
Lend me your horn to make one, and I will whip about your infamy <i>unum cita</i>.
A gig of a cuckold’s horn.
</p>

<p class="drama">
COSTARD.<br>
An I had but one penny in the world, thou shouldst have it to buy gingerbread.
Hold, there is the very remuneration I had of thy master, thou halfpenny purse
of wit, thou pigeon-egg of discretion. O, an the heavens were so pleased that
thou wert but my bastard, what a joyful father wouldst thou make me! Go to,
thou hast it <i>ad dunghill</i>, at the fingers’ ends, as they say.
</p>

<p class="drama">
HOLOFERNES.<br>
O, I smell false Latin! <i>Dunghill</i> for <i>unguem</i>.
</p>

<p class="drama">
ARMADO.<br>
Arts-man, preambulate. We will be singuled from the barbarous. Do you not educate
youth at the charge-house on the top of the mountain?
</p>

<p class="drama">
HOLOFERNES.<br>
Or <i>mons</i>, the hill.
</p>

<p class="drama">
ARMADO.<br>
At your sweet pleasure, for the mountain.
</p>

<p class="drama">
HOLOFERNES.<br>
I do, <i>sans question</i>.
</p>

<p class="drama">
ARMADO.<br>
Sir, it is the King’s most sweet pleasure and affection to congratulate the
Princess at her pavilion in the posteriors of this day, which the rude
multitude call the afternoon.
</p>

<p class="drama">
HOLOFERNES.<br>
The posterior of the day, most generous sir, is liable, congruent, and
measurable for the afternoon. The word is well culled, chose, sweet, and apt,
I do assure you, sir, I do assure.
</p>

<p class="drama">
ARMADO.<br>
Sir, the King is a noble gentleman, and my familiar, I do assure ye, very good
friend. For what is inward between us, let it pass. I do beseech thee, remember
thy courtesy; I beseech thee, apparel thy head. And among other importunate and
most serious designs, and of great import indeed, too—but let that pass. For I
must tell thee it will please his Grace, by the world, sometime to lean upon my
poor shoulder and with his royal finger thus dally with my excrement, with my
mustachio. But, sweet heart, let that pass. By the world, I recount no fable!
Some certain special honours it pleaseth his greatness to impart to Armado, a
soldier, a man of travel, that hath seen the world. But let that pass. The very
all of all is—but, sweet heart, I do implore secrecy—that the King would have
me present the Princess, sweet chuck, with some delightful ostentation, or
show, or pageant, or antic, or firework. Now, understanding that the curate and
your sweet self are good at such eruptions and sudden breaking-out of mirth, as
it were, I have acquainted you withal, to the end to crave your assistance.
</p>

<p class="drama">
HOLOFERNES.<br>
Sir, you shall present before her the Nine Worthies. Sir Nathaniel, as
concerning some entertainment of time, some show in the posterior of this day,
to be rendered by our assistance, the King’s command, and this most gallant,
illustrate, and learned gentleman, before the Princess, I say, none so fit as
to present the Nine Worthies.
</p>

<p class="drama">
NATHANIEL.<br>
Where will you find men worthy enough to present them?
</p>

<p class="drama">
HOLOFERNES.<br>
Joshua, yourself; myself; and this gallant gentleman, Judas Maccabaeus.
This swain, because of his great limb or joint, shall pass Pompey the Great;
the page, Hercules.
</p>

<p class="drama">
ARMADO.<br>
Pardon, sir; error. He is not quantity enough for that Worthy’s thumb; he is
not so big as the end of his club.
</p>

<p class="drama">
HOLOFERNES.<br>
Shall I have audience? He shall present Hercules in minority. His enter and
exit shall be strangling a snake; and I will have an apology for that purpose.
</p>

<p class="drama">
MOTH.<br>
An excellent device! So, if any of the audience hiss, you may cry “Well done,
Hercules, now thou crushest the snake!” That is the way to make an offence
gracious, though few have the grace to do it.
</p>

<p class="drama">
ARMADO.<br>
For the rest of the Worthies?
</p>

<p class="drama">
HOLOFERNES.<br>
I will play three myself.
</p>

<p class="drama">
MOTH.<br>
Thrice-worthy gentleman!
</p>

<p class="drama">
ARMADO.<br>
Shall I tell you a thing?
</p>

<p class="drama">
HOLOFERNES.<br>
We attend.
</p>

<p class="drama">
ARMADO.<br>
We will have, if this fadge not, an antic. I beseech you, follow.
</p>

<p class="drama">
HOLOFERNES.<br>
<i>Via</i>, goodman Dull! Thou has spoken no word all this while.
</p>

<p class="drama">
DULL.<br>
Nor understood none neither, sir.
</p>

<p class="drama">
HOLOFERNES.<br>
<i>Allons!</i> we will employ thee.
</p>

<p class="drama">
DULL.<br>
I’ll make one in a dance, or so; or I will play on the tabor to the Worthies,
and let them dance the hay.
</p>

<p class="drama">
HOLOFERNES.<br>
Most dull, honest Dull! To our sport, away.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneV_19.2"></a><b>SCENE II. The same. Before the Princess’s pavilion</b></h3>

<p class="scenedesc">
Enter the <span class="charname">Princess, Rosaline, Katharine</span> and
<span class="charname">Maria</span>.
</p>

<p class="drama">
PRINCESS.<br>
Sweet hearts, we shall be rich ere we depart,<br>
If fairings come thus plentifully in.<br>
A lady walled about with diamonds!<br>
Look you what I have from the loving King.
</p>

<p class="drama">
ROSALINE.<br>
Madam, came nothing else along with that?
</p>

<p class="drama">
PRINCESS.<br>
Nothing but this? Yes, as much love in rhyme<br>
As would be crammed up in a sheet of paper<br>
Writ o’ both sides the leaf, margent and all,<br>
That he was fain to seal on Cupid’s name.
</p>

<p class="drama">
ROSALINE.<br>
That was the way to make his godhead wax,<br>
For he hath been five thousand years a boy.
</p>

<p class="drama">
KATHARINE.<br>
Ay, and a shrewd unhappy gallows too.
</p>

<p class="drama">
ROSALINE.<br>
You’ll ne’er be friends with him. He killed your sister.
</p>

<p class="drama">
KATHARINE.<br>
He made her melancholy, sad, and heavy;<br>
And so she died. Had she been light, like you,<br>
Of such a merry, nimble, stirring spirit,<br>
She might ha’ been a grandam ere she died.<br>
And so may you, for a light heart lives long.
</p>

<p class="drama">
ROSALINE.<br>
What’s your dark meaning, mouse, of this light word?
</p>

<p class="drama">
KATHARINE.<br>
A light condition in a beauty dark.
</p>

<p class="drama">
ROSALINE.<br>
We need more light to find your meaning out.
</p>

<p class="drama">
KATHARINE.<br>
You’ll mar the light by taking it in snuff;<br>
Therefore I’ll darkly end the argument.
</p>

<p class="drama">
ROSALINE.<br>
Look what you do, you do it still i’ th’ dark.
</p>

<p class="drama">
KATHARINE.<br>
So do not you, for you are a light wench.
</p>

<p class="drama">
ROSALINE.<br>
Indeed, I weigh not you, and therefore light.
</p>

<p class="drama">
KATHARINE.<br>
You weigh me not? O, that’s you care not for me.
</p>

<p class="drama">
ROSALINE.<br>
Great reason, for past cure is still past care.
</p>

<p class="drama">
PRINCESS.<br>
Well bandied both; a set of wit well played.<br>
But, Rosaline, you have a favour too.<br>
Who sent it? And what is it?
</p>

<p class="drama">
ROSALINE.<br>
I would you knew.<br>
An if my face were but as fair as yours,<br>
My favour were as great. Be witness this.<br>
Nay, I have verses too, I thank Berowne;<br>
The numbers true, and, were the numbering too,<br>
I were the fairest goddess on the ground.<br>
I am compared to twenty thousand fairs.<br>
O, he hath drawn my picture in his letter.
</p>

<p class="drama">
PRINCESS.<br>
Anything like?
</p>

<p class="drama">
ROSALINE.<br>
Much in the letters, nothing in the praise.
</p>

<p class="drama">
PRINCESS.<br>
Beauteous as ink: a good conclusion.
</p>

<p class="drama">
KATHARINE.<br>
Fair as a text B in a copy-book.
</p>

<p class="drama">
ROSALINE.<br>
’Ware pencils, how! Let me not die your debtor,<br>
My red dominical, my golden letter.<br>
O, that your face were not so full of O’s!
</p>

<p class="drama">
PRINCESS.<br>
A pox of that jest! And beshrew all shrews.<br>
But, Katharine, what was sent to you from fair Dumaine?
</p>

<p class="drama">
KATHARINE.<br>
Madam, this glove.
</p>

<p class="drama">
PRINCESS.<br>
Did he not send you twain?
</p>

<p class="drama">
KATHARINE.<br>
Yes, madam, and moreover,<br>
Some thousand verses of a faithful lover.<br>
A huge translation of hypocrisy,<br>
Vilely compiled, profound simplicity.
</p>

<p class="drama">
MARIA.<br>
This, and these pearls, to me sent Longaville.<br>
The letter is too long by half a mile.
</p>

<p class="drama">
PRINCESS.<br>
I think no less. Dost thou not wish in heart<br>
The chain were longer and the letter short?
</p>

<p class="drama">
MARIA.<br>
Ay, or I would these hands might never part.
</p>

<p class="drama">
PRINCESS.<br>
We are wise girls to mock our lovers so.
</p>

<p class="drama">
ROSALINE.<br>
They are worse fools to purchase mocking so.<br>
That same Berowne I’ll torture ere I go.<br>
O that I knew he were but in by th’ week!<br>
How I would make him fawn, and beg, and seek,<br>
And wait the season, and observe the times,<br>
And spend his prodigal wits in bootless rhymes,<br>
And shape his service wholly to my hests,<br>
And make him proud to make me proud that jests!<br>
So pair-taunt-like would I o’ersway his state,<br>
That he should be my fool, and I his fate.
</p>

<p class="drama">
PRINCESS.<br>
None are so surely caught, when they are catched,<br>
As wit turned fool. Folly, in wisdom hatched,<br>
Hath wisdom’s warrant and the help of school<br>
And wit’s own grace to grace a learned fool.
</p>

<p class="drama">
ROSALINE.<br>
The blood of youth burns not with such excess<br>
As gravity’s revolt to wantonness.
</p>

<p class="drama">
MARIA.<br>
Folly in fools bears not so strong a note<br>
As fool’ry in the wise when wit doth dote,<br>
Since all the power thereof it doth apply<br>
To prove, by wit, worth in simplicity.
</p>

<p class="scenedesc">
Enter <span class="charname">Boyet</span>.
</p>

<p class="drama">
PRINCESS.<br>
Here comes Boyet, and mirth is in his face.
</p>

<p class="drama">
BOYET.<br>
O, I am stabbed with laughter! Where’s her Grace?
</p>

<p class="drama">
PRINCESS.<br>
Thy news, Boyet?
</p>

<p class="drama">
BOYET.<br>
Prepare, madam, prepare!<br>
Arm, wenches, arm! Encounters mounted are<br>
Against your peace. Love doth approach disguised,<br>
Armed in arguments. You’ll be surprised.<br>
Muster your wits, stand in your own defence,<br>
Or hide your heads like cowards, and fly hence.
</p>

<p class="drama">
PRINCESS.<br>
Saint Denis to Saint Cupid! What are they<br>
That charge their breath against us? Say, scout, say.
</p>

<p class="drama">
BOYET.<br>
Under the cool shade of a sycamore<br>
I thought to close mine eyes some half an hour,<br>
When, lo, to interrupt my purposed rest,<br>
Toward that shade I might behold addressed<br>
The King and his companions. Warily<br>
I stole into a neighbour thicket by,<br>
And overheard what you shall overhear:<br>
That, by and by, disguised they will be here.<br>
Their herald is a pretty knavish page<br>
That well by heart hath conned his embassage.<br>
Action and accent did they teach him there:<br>
“Thus must thou speak,” and “thus thy body bear.”<br>
And ever and anon they made a doubt<br>
Presence majestical would put him out;<br>
“For,” quoth the King, “an angel shalt thou see;<br>
Yet fear not thou, but speak audaciously.”<br>
The boy replied “An angel is not evil;<br>
I should have feared her had she been a devil.”<br>
With that all laughed and clapped him on the shoulder,<br>
Making the bold wag by their praises bolder.<br>
One rubbed his elbow thus, and fleered, and swore<br>
A better speech was never spoke before.<br>
Another with his finger and his thumb<br>
Cried “<i>Via</i>, we will do ’t, come what will come.”<br>
The third he capered, and cried “All goes well!”<br>
The fourth turned on the toe, and down he fell.<br>
With that they all did tumble on the ground,<br>
With such a zealous laughter, so profound,<br>
That in this spleen ridiculous appears,<br>
To check their folly, passion’s solemn tears.
</p>

<p class="drama">
PRINCESS.<br>
But what, but what, come they to visit us?
</p>

<p class="drama">
BOYET.<br>
They do, they do, and are apparelled thus,<br>
Like Muscovites, or Russians, as I guess.<br>
Their purpose is to parley, court, and dance,<br>
And every one his love-feat will advance<br>
Unto his several mistress, which they’ll know<br>
By favours several which they did bestow.
</p>

<p class="drama">
PRINCESS.<br>
And will they so? The gallants shall be tasked;<br>
For, ladies, we will every one be masked,<br>
And not a man of them shall have the grace,<br>
Despite of suit, to see a lady’s face.<br>
Hold, Rosaline, this favour thou shalt wear,<br>
And then the King will court thee for his dear.<br>
Hold, take thou this, my sweet, and give me thine,<br>
So shall Berowne take me for Rosaline.<br>
And change you favours too; so shall your loves<br>
Woo contrary, deceived by these removes.
</p>

<p class="drama">
ROSALINE.<br>
Come on, then, wear the favours most in sight.
</p>

<p class="drama">
KATHARINE.<br>
But in this changing, what is your intent?
</p>

<p class="drama">
PRINCESS.<br>
The effect of my intent is to cross theirs.<br>
They do it but in mocking merriment,<br>
And mock for mock is only my intent.<br>
Their several counsels they unbosom shall<br>
To loves mistook, and so be mocked withal<br>
Upon the next occasion that we meet,<br>
With visages displayed to talk and greet.
</p>

<p class="drama">
ROSALINE.<br>
But shall we dance, if they desire us to’t?
</p>

<p class="drama">
PRINCESS.<br>
No, to the death we will not move a foot,<br>
Nor to their penned speech render we no grace,<br>
But while ’tis spoke each turn away her face.
</p>

<p class="drama">
BOYET.<br>
Why, that contempt will kill the speaker’s heart,<br>
And quite divorce his memory from his part.
</p>

<p class="drama">
PRINCESS.<br>
Therefore I do it, and I make no doubt<br>
The rest will ne’er come in, if he be out.<br>
There’s no such sport as sport by sport o’erthrown,<br>
To make theirs ours and ours none but our own.<br>
So shall we stay, mocking intended game,<br>
And they, well mocked, depart away with shame.
</p>

<p class="right">[<i>Sound trumpet, within.</i>]</p>

<p class="drama">
BOYET.<br>
The trumpet sounds. Be masked; the maskers come.
</p>

<p class="right">[<i>The <span class="charname">Ladies</span> mask.</i>]</p>

<p class="scenedesc">
Enter <span class="charname">Blackamoors</span> with music, <span class="charname">Moth,</span> with a speech, the <span class="charname">King, Berowne,
Longaville</span> and <span class="charname">Dumaine</span> disguised.
</p>

<p class="drama">
MOTH.<br>
<i>All hail, the richest beauties on the earth!</i>
</p>

<p class="drama">
BOYET.<br>
Beauties no richer than rich taffeta.
</p>

<p class="drama">
MOTH.<br>
<i>A holy parcel of the fairest dames</i>
</p>

<p class="right">[<i>The <span class="charname">Ladies</span> turn their backs to him.</i>]</p>

<p class="drama">
<i>That ever turned their</i>—backs—<i>to mortal views!</i>
</p>

<p class="drama">
BEROWNE.<br>
<i>Their eyes</i>, villain, <i>their eyes.</i>
</p>

<p class="drama">
MOTH.<br>
<i>That ever turned their eyes to mortal views.<br>
Out</i>—
</p>

<p class="drama">
BOYET.<br>
True; out indeed.
</p>

<p class="drama">
MOTH.<br>
<i>Out of your favours, heavenly spirits, vouchsafe<br>
Not to behold</i>—
</p>

<p class="drama">
BEROWNE.<br>
<i>Once to behold</i>, rogue!
</p>

<p class="drama">
MOTH.<br>
<i>Once to behold with your sun-beamed eyes—<br>
With your sun-beamed eyes</i>—
</p>

<p class="drama">
BOYET.<br>
They will not answer to that epithet.<br>
You were best call it “daughter-beamed eyes”.
</p>

<p class="drama">
MOTH.<br>
They do not mark me, and that brings me out.
</p>

<p class="drama">
BEROWNE.<br>
Is this your perfectness? Be gone, you rogue!
</p>

<p class="right">[<i>Exit <span class="charname">Moth</span>.</i>]</p>

<p class="drama">
ROSALINE.<br>
What would these strangers? Know their minds, Boyet.<br>
If they do speak our language, ’tis our will<br>
That some plain man recount their purposes.<br>
Know what they would.
</p>

<p class="drama">
BOYET.<br>
What would you with the Princess?
</p>

<p class="drama">
BEROWNE.<br>
Nothing but peace and gentle visitation.
</p>

<p class="drama">
ROSALINE.<br>
What would they, say they?
</p>

<p class="drama">
BOYET.<br>
Nothing but peace and gentle visitation.
</p>

<p class="drama">
ROSALINE.<br>
Why, that they have, and bid them so be gone.
</p>

<p class="drama">
BOYET.<br>
She says you have it, and you may be gone.
</p>

<p class="drama">
KING.<br>
Say to her we have measured many miles<br>
To tread a measure with her on this grass.
</p>

<p class="drama">
BOYET.<br>
They say that they have measured many a mile<br>
To tread a measure with you on this grass.
</p>

<p class="drama">
ROSALINE.<br>
It is not so. Ask them how many inches<br>
Is in one mile? If they have measured many,<br>
The measure then of one is easily told.
</p>

<p class="drama">
BOYET.<br>
If to come hither you have measured miles,<br>
And many miles, the Princess bids you tell<br>
How many inches doth fill up one mile.
</p>

<p class="drama">
BEROWNE.<br>
Tell her we measure them by weary steps.
</p>

<p class="drama">
BOYET.<br>
She hears herself.
</p>

<p class="drama">
ROSALINE.<br>
How many weary steps<br>
Of many weary miles you have o’ergone<br>
Are numbered in the travel of one mile?
</p>

<p class="drama">
BEROWNE.<br>
We number nothing that we spend for you.<br>
Our duty is so rich, so infinite,<br>
That we may do it still without account.<br>
Vouchsafe to show the sunshine of your face,<br>
That we, like savages, may worship it.
</p>

<p class="drama">
ROSALINE.<br>
My face is but a moon, and clouded too.
</p>

<p class="drama">
KING.<br>
Blessed are clouds, to do as such clouds do!<br>
Vouchsafe, bright moon, and these thy stars, to shine,<br>
Those clouds removed, upon our watery eyne.
</p>

<p class="drama">
ROSALINE.<br>
O vain petitioner! Beg a greater matter!<br>
Thou now requests but moonshine in the water.
</p>

<p class="drama">
KING.<br>
Then in our measure do but vouchsafe one change.<br>
Thou bidd’st me beg; this begging is not strange.
</p>

<p class="drama">
ROSALINE.<br>
Play, music, then! Nay, you must do it soon.
</p>

<p class="right">[<i>Music plays.</i>]</p>

<p class="drama">
Not yet? No dance! Thus change I like the moon.
</p>

<p class="drama">
KING.<br>
Will you not dance? How come you thus estranged?
</p>

<p class="drama">
ROSALINE.<br>
You took the moon at full, but now she’s changed.
</p>

<p class="drama">
KING.<br>
Yet still she is the moon, and I the man.<br>
The music plays, vouchsafe some motion to it.
</p>

<p class="drama">
ROSALINE.<br>
Our ears vouchsafe it.
</p>

<p class="drama">
KING.<br>
But your legs should do it.
</p>

<p class="drama">
ROSALINE.<br>
Since you are strangers and come here by chance,<br>
We’ll not be nice. Take hands. We will not dance.
</p>

<p class="drama">
KING.<br>
Why take we hands then?
</p>

<p class="drama">
ROSALINE.<br>
Only to part friends.<br>
Curtsy, sweet hearts, and so the measure ends.
</p>

<p class="drama">
KING.<br>
More measure of this measure! Be not nice.
</p>

<p class="drama">
ROSALINE.<br>
We can afford no more at such a price.
</p>

<p class="drama">
KING.<br>
Price you yourselves? What buys your company?
</p>

<p class="drama">
ROSALINE.<br>
Your absence only.
</p>

<p class="drama">
KING.<br>
That can never be.
</p>

<p class="drama">
ROSALINE.<br>
Then cannot we be bought. And so adieu—<br>
Twice to your visor, and half once to you!
</p>

<p class="drama">
KING.<br>
If you deny to dance, let’s hold more chat.
</p>

<p class="drama">
ROSALINE.<br>
In private then.
</p>

<p class="drama">
KING.<br>
I am best pleased with that.
</p>

<p class="right">[<i>They converse apart.</i>]</p>

<p class="drama">
BEROWNE.<br>
White-handed mistress, one sweet word with thee.
</p>

<p class="drama">
PRINCESS.<br>
Honey, and milk, and sugar: there is three.
</p>

<p class="drama">
BEROWNE.<br>
Nay, then, two treys, an if you grow so nice,<br>
Metheglin, wort, and malmsey. Well run, dice!<br>
There’s half a dozen sweets.
</p>

<p class="drama">
PRINCESS.<br>
Seventh sweet, adieu.<br>
Since you can cog, I’ll play no more with you.
</p>

<p class="drama">
BEROWNE.<br>
One word in secret.
</p>

<p class="drama">
PRINCESS.<br>
Let it not be sweet.
</p>

<p class="drama">
BEROWNE.<br>
Thou griev’st my gall.
</p>

<p class="drama">
PRINCESS.<br>
Gall! Bitter.
</p>

<p class="drama">
BEROWNE.<br>
Therefore meet.
</p>

<p class="right">[<i>They converse apart.</i>]</p>

<p class="drama">
DUMAINE.<br>
Will you vouchsafe with me to change a word?
</p>

<p class="drama">
MARIA.<br>
Name it.
</p>

<p class="drama">
DUMAINE.<br>
Fair lady—
</p>

<p class="drama">
MARIA.<br>
Say you so? Fair lord!<br>
Take that for your “fair lady”.
</p>

<p class="drama">
DUMAINE.<br>
Please it you,<br>
As much in private, and I’ll bid adieu.
</p>

<p class="right">[<i>They converse apart.</i>]</p>

<p class="drama">
KATHARINE.<br>
What, was your visor made without a tongue?
</p>

<p class="drama">
LONGAVILLE.<br>
I know the reason, lady, why you ask.
</p>

<p class="drama">
KATHARINE.<br>
O, for your reason! Quickly, sir, I long.
</p>

<p class="drama">
LONGAVILLE.<br>
You have a double tongue within your mask,<br>
And would afford my speechless visor half.
</p>

<p class="drama">
KATHARINE.<br>
“Veal”, quoth the Dutchman. Is not veal a calf?
</p>

<p class="drama">
LONGAVILLE.<br>
A calf, fair lady?
</p>

<p class="drama">
KATHARINE.<br>
No, a fair lord calf.
</p>

<p class="drama">
LONGAVILLE.<br>
Let’s part the word.
</p>

<p class="drama">
KATHARINE.<br>
No, I’ll not be your half.<br>
Take all and wean it; it may prove an ox.
</p>

<p class="drama">
LONGAVILLE.<br>
Look how you butt yourself in these sharp mocks.<br>
Will you give horns, chaste lady? Do not so.
</p>

<p class="drama">
KATHARINE.<br>
Then die a calf before your horns do grow.
</p>

<p class="drama">
LONGAVILLE.<br>
One word in private with you ere I die.
</p>

<p class="drama">
KATHARINE.<br>
Bleat softly, then; the butcher hears you cry.
</p>

<p class="right">[<i>They converse apart.</i>]</p>

<p class="drama">
BOYET.<br>
The tongues of mocking wenches are as keen<br>
    As is the razor’s edge invisible,<br>
Cutting a smaller hair than may be seen;<br>
    Above the sense of sense, so sensible<br>
Seemeth their conference. Their conceits have wings<br>
Fleeter than arrows, bullets, wind, thought, swifter things.
</p>

<p class="drama">
ROSALINE.<br>
Not one word more, my maids; break off, break off.
</p>

<p class="drama">
BEROWNE.<br>
By heaven, all dry-beaten with pure scoff!
</p>

<p class="drama">
KING.<br>
Farewell, mad wenches. You have simple wits.
</p>

<p class="right">[<i>Exeunt <span class="charname">King,</span> Lords and
Blackamoors.</i>]</p>

<p class="drama">
PRINCESS.<br>
Twenty adieus, my frozen Muscovites.<br>
Are these the breed of wits so wondered at?
</p>

<p class="drama">
BOYET.<br>
Tapers they are, with your sweet breaths puffed out.
</p>

<p class="drama">
ROSALINE.<br>
Well-liking wits they have; gross, gross; fat, fat.
</p>

<p class="drama">
PRINCESS.<br>
O poverty in wit, kingly-poor flout!<br>
Will they not, think you, hang themselves tonight?<br>
Or ever but in vizors show their faces?<br>
This pert Berowne was out of countenance quite.
</p>

<p class="drama">
ROSALINE.<br>
They were all in lamentable cases.<br>
The King was weeping-ripe for a good word.
</p>

<p class="drama">
PRINCESS.<br>
Berowne did swear himself out of all suit.
</p>

<p class="drama">
MARIA.<br>
Dumaine was at my service, and his sword.<br>
“<i>Non point</i>,” quoth I; my servant straight was mute.
</p>

<p class="drama">
KATHARINE.<br>
Lord Longaville said I came o’er his heart;<br>
And trow you what he called me?
</p>

<p class="drama">
PRINCESS.<br>
Qualm, perhaps.
</p>

<p class="drama">
KATHARINE.<br>
Yes, in good faith.
</p>

<p class="drama">
PRINCESS.<br>
Go, sickness as thou art!
</p>

<p class="drama">
ROSALINE.<br>
Well, better wits have worn plain statute-caps.<br>
But will you hear? The King is my love sworn.
</p>

<p class="drama">
PRINCESS.<br>
And quick Berowne hath plighted faith to me.
</p>

<p class="drama">
KATHARINE.<br>
And Longaville was for my service born.
</p>

<p class="drama">
MARIA.<br>
Dumaine is mine as sure as bark on tree.
</p>

<p class="drama">
BOYET.<br>
Madam, and pretty mistresses, give ear.<br>
Immediately they will again be here<br>
In their own shapes, for it can never be<br>
They will digest this harsh indignity.
</p>

<p class="drama">
PRINCESS.<br>
Will they return?
</p>

<p class="drama">
BOYET.<br>
They will, they will, God knows,<br>
And leap for joy, though they are lame with blows.<br>
Therefore, change favours and, when they repair,<br>
Blow like sweet roses in this summer air.
</p>

<p class="drama">
PRINCESS.<br>
How “blow”? How “blow”? Speak to be understood.
</p>

<p class="drama">
BOYET.<br>
Fair ladies masked are roses in their bud.<br>
Dismasked, their damask sweet commixture shown,<br>
Are angels vailing clouds, or roses blown.
</p>

<p class="drama">
PRINCESS.<br>
Avaunt, perplexity! What shall we do<br>
If they return in their own shapes to woo?
</p>

<p class="drama">
ROSALINE.<br>
Good madam, if by me you’ll be advised,<br>
Let’s mock them still, as well known as disguised.<br>
Let us complain to them what fools were here,<br>
Disguised like Muscovites in shapeless gear;<br>
And wonder what they were, and to what end<br>
Their shallow shows and prologue vilely penned,<br>
And their rough carriage so ridiculous,<br>
Should be presented at our tent to us.
</p>

<p class="drama">
BOYET.<br>
Ladies, withdraw. The gallants are at hand.
</p>

<p class="drama">
PRINCESS.<br>
Whip to our tents, as roes run o’er the land.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Princess, Rosaline, Katharine</span> and
<span class="charname">Maria</span>.</i>]
</p>

<p class="scenedesc">
Enter the <span class="charname">King, Berowne, Longaville</span> and
<span class="charname">Dumaine</span> as themselves.
</p>

<p class="drama">
KING.<br>
Fair sir, God save you. Where’s the Princess?
</p>

<p class="drama">
BOYET.<br>
Gone to her tent. Please it your Majesty<br>
Command me any service to her thither?
</p>

<p class="drama">
KING.<br>
That she vouchsafe me audience for one word.
</p>

<p class="drama">
BOYET.<br>
I will; and so will she, I know, my lord.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
BEROWNE.<br>
This fellow pecks up wit as pigeons peas<br>
And utters it again when God doth please.<br>
He is wit’s pedlar, and retails his wares<br>
At wakes and wassails, meetings, markets, fairs;<br>
And we that sell by gross, the Lord doth know,<br>
Have not the grace to grace it with such show.<br>
This gallant pins the wenches on his sleeve.<br>
Had he been Adam, he had tempted Eve.<br>
He can carve too, and lisp. Why, this is he<br>
That kissed his hand away in courtesy.<br>
This is the ape of form, Monsieur the Nice,<br>
That, when he plays at tables, chides the dice<br>
In honourable terms. Nay, he can sing<br>
A mean most meanly; and in ushering<br>
Mend him who can. The ladies call him sweet.<br>
The stairs, as he treads on them, kiss his feet.<br>
This is the flower that smiles on everyone,<br>
To show his teeth as white as whale’s bone;<br>
And consciences that will not die in debt<br>
Pay him the due of “honey-tongued Boyet”.
</p>

<p class="drama">
KING.<br>
A blister on his sweet tongue, with my heart,<br>
That put Armado’s page out of his part!
</p>

<p class="scenedesc">
Enter the <span class="charname">Princess, Rosaline, Maria, Katharine</span> with
<span class="charname">Boyet</span>.
</p>

<p class="drama">
BEROWNE.<br>
See where it comes! Behaviour, what wert thou<br>
Till this man showed thee, and what art thou now?
</p>

<p class="drama">
KING.<br>
All hail, sweet madam, and fair time of day.
</p>

<p class="drama">
PRINCESS.<br>
“Fair” in “all hail” is foul, as I conceive.
</p>

<p class="drama">
KING.<br>
Construe my speeches better, if you may.
</p>

<p class="drama">
PRINCESS.<br>
Then wish me better. I will give you leave.
</p>

<p class="drama">
KING.<br>
We came to visit you, and purpose now<br>
To lead you to our court. Vouchsafe it then.
</p>

<p class="drama">
PRINCESS.<br>
This field shall hold me, and so hold your vow.<br>
Nor God nor I delights in perjured men.
</p>

<p class="drama">
KING.<br>
Rebuke me not for that which you provoke.<br>
The virtue of your eye must break my oath.
</p>

<p class="drama">
PRINCESS.<br>
You nickname virtue: “vice” you should have spoke;<br>
For virtue’s office never breaks men’s troth.<br>
Now by my maiden honour, yet as pure<br>
As the unsullied lily, I protest,<br>
A world of torments though I should endure,<br>
I would not yield to be your house’s guest,<br>
So much I hate a breaking cause to be<br>
Of heavenly oaths, vowed with integrity.
</p>

<p class="drama">
KING.<br>
O, you have lived in desolation here,<br>
Unseen, unvisited, much to our shame.
</p>

<p class="drama">
PRINCESS.<br>
Not so, my lord. It is not so, I swear.<br>
We have had pastimes here and pleasant game.<br>
A mess of Russians left us but of late.
</p>

<p class="drama">
KING.<br>
How, madam? Russians?
</p>

<p class="drama">
PRINCESS.<br>
Ay, in truth, my lord.<br>
Trim gallants, full of courtship and of state.
</p>

<p class="drama">
ROSALINE.<br>
Madam, speak true. It is not so, my lord.<br>
My lady, to the manner of the days,<br>
In courtesy gives undeserving praise.<br>
We four indeed confronted were with four<br>
In Russian habit. Here they stayed an hour<br>
And talked apace; and in that hour, my lord,<br>
They did not bless us with one happy word.<br>
I dare not call them fools; but this I think,<br>
When they are thirsty, fools would fain have drink.
</p>

<p class="drama">
BEROWNE.<br>
This jest is dry to me. My gentle sweet,<br>
Your wit makes wise things foolish. When we greet,<br>
With eyes’ best seeing, heaven’s fiery eye,<br>
By light we lose light. Your capacity<br>
Is of that nature that to your huge store<br>
Wise things seem foolish and rich things but poor.
</p>

<p class="drama">
ROSALINE.<br>
This proves you wise and rich, for in my eye—
</p>

<p class="drama">
BEROWNE.<br>
I am a fool, and full of poverty.
</p>

<p class="drama">
ROSALINE.<br>
But that you take what doth to you belong,<br>
It were a fault to snatch words from my tongue.
</p>

<p class="drama">
BEROWNE.<br>
O, I am yours, and all that I possess.
</p>

<p class="drama">
ROSALINE.<br>
All the fool mine?
</p>

<p class="drama">
BEROWNE.<br>
I cannot give you less.
</p>

<p class="drama">
ROSALINE.<br>
Which of the visors was it that you wore?
</p>

<p class="drama">
BEROWNE.<br>
Where, when, what visor? Why demand you this?
</p>

<p class="drama">
ROSALINE.<br>
There, then, that visor; that superfluous case<br>
That hid the worse and showed the better face.
</p>

<p class="drama">
KING.<br>
We are descried. They’ll mock us now downright.
</p>

<p class="drama">
DUMAINE.<br>
Let us confess and turn it to a jest.
</p>

<p class="drama">
PRINCESS.<br>
Amazed, my lord? Why looks your Highness sad?
</p>

<p class="drama">
ROSALINE.<br>
Help! Hold his brows! He’ll swoon. Why look you pale?<br>
Seasick, I think, coming from Muscovy.
</p>

<p class="drama">
BEROWNE.<br>
Thus pour the stars down plagues for perjury.<br>
Can any face of brass hold longer out?<br>
Here stand I, lady; dart thy skill at me.<br>
Bruise me with scorn, confound me with a flout,<br>
Thrust thy sharp wit quite through my ignorance,<br>
Cut me to pieces with thy keen conceit,<br>
And I will wish thee never more to dance,<br>
Nor never more in Russian habit wait.<br>
O, never will I trust to speeches penned,<br>
Nor to the motion of a school-boy’s tongue,<br>
Nor never come in visor to my friend,<br>
Nor woo in rhyme like a blind harper’s song.<br>
Taffeta phrases, silken terms precise,<br>
Three-piled hyperboles, spruce affectation,<br>
Figures pedantical: these summer flies<br>
Have blown me full of maggot ostentation.<br>
I do forswear them, and I here protest,<br>
By this white glove—how white the hand, God knows!—<br>
Henceforth my wooing mind shall be expressed<br>
In russet yeas and honest kersey noes.<br>
And, to begin: wench, so God help me, law,<br>
My love to thee is sound, <i>sans</i> crack or flaw.
</p>

<p class="drama">
ROSALINE.<br>
<i>Sans</i> “<i>sans</i>,” I pray you.
</p>

<p class="drama">
BEROWNE.<br>
Yet I have a trick<br>
Of the old rage. Bear with me, I am sick;<br>
I’ll leave it by degrees. Soft, let us see:<br>
Write “Lord have mercy on us” on those three.<br>
They are infected; in their hearts it lies;<br>
They have the plague, and caught it of your eyes.<br>
These lords are visited. You are not free,<br>
For the Lord’s tokens on you do I see.
</p>

<p class="drama">
PRINCESS.<br>
No, they are free that gave these tokens to us.
</p>

<p class="drama">
BEROWNE.<br>
Our states are forfeit. Seek not to undo us.
</p>

<p class="drama">
ROSALINE.<br>
It is not so. For how can this be true,<br>
That you stand forfeit, being those that sue?
</p>

<p class="drama">
BEROWNE.<br>
Peace! for I will not have to do with you.
</p>

<p class="drama">
ROSALINE.<br>
Nor shall not, if I do as I intend.
</p>

<p class="drama">
BEROWNE.<br>
Speak for yourselves. My wit is at an end.
</p>

<p class="drama">
KING.<br>
Teach us, sweet madam, for our rude transgression<br>
Some fair excuse.
</p>

<p class="drama">
PRINCESS.<br>
The fairest is confession.<br>
Were not you here but even now, disguised?
</p>

<p class="drama">
KING.<br>
Madam, I was.
</p>

<p class="drama">
PRINCESS.<br>
And were you well advised?
</p>

<p class="drama">
KING.<br>
I was, fair madam.
</p>

<p class="drama">
PRINCESS.<br>
When you then were here,<br>
What did you whisper in your lady’s ear?
</p>

<p class="drama">
KING.<br>
That more than all the world I did respect her.
</p>

<p class="drama">
PRINCESS.<br>
When she shall challenge this, you will reject her.
</p>

<p class="drama">
KING.<br>
Upon mine honour, no.
</p>

<p class="drama">
PRINCESS.<br>
Peace, peace, forbear!<br>
Your oath once broke, you force not to forswear.
</p>

<p class="drama">
KING.<br>
Despise me when I break this oath of mine.
</p>

<p class="drama">
PRINCESS.<br>
I will; and therefore keep it. Rosaline,<br>
What did the Russian whisper in your ear?
</p>

<p class="drama">
ROSALINE.<br>
Madam, he swore that he did hold me dear<br>
As precious eyesight, and did value me<br>
Above this world; adding thereto, moreover,<br>
That he would wed me, or else die my lover.
</p>

<p class="drama">
PRINCESS.<br>
God give thee joy of him! The noble lord<br>
Most honourably doth uphold his word.
</p>

<p class="drama">
KING.<br>
What mean you, madam? By my life, my troth,<br>
I never swore this lady such an oath.
</p>

<p class="drama">
ROSALINE.<br>
By heaven, you did! And to confirm it plain,<br>
You gave me this. But take it, sir, again.
</p>

<p class="drama">
KING.<br>
My faith and this the Princess I did give.<br>
I knew her by this jewel on her sleeve.
</p>

<p class="drama">
PRINCESS.<br>
Pardon me, sir, this jewel did she wear,<br>
And Lord Berowne, I thank him, is my dear.<br>
What, will you have me, or your pearl again?
</p>

<p class="drama">
BEROWNE.<br>
Neither of either; I remit both twain.<br>
I see the trick on’t. Here was a consent,<br>
Knowing aforehand of our merriment,<br>
To dash it like a Christmas comedy.<br>
Some carry-tale, some please-man, some slight zany,<br>
Some mumble-news, some trencher-knight, some Dick,<br>
That smiles his cheek in years and knows the trick<br>
To make my lady laugh when she’s disposed,<br>
Told our intents before; which once disclosed,<br>
The ladies did change favours, and then we,<br>
Following the signs, wooed but the sign of she.<br>
Now, to our perjury to add more terror,<br>
We are again forsworn in will and error.<br>
Much upon this ’tis. [<i>To Boyet</i>.] And might not you<br>
Forestall our sport, to make us thus untrue?<br>
Do not you know my lady’s foot by th’ squier,<br>
And laugh upon the apple of her eye?<br>
And stand between her back, sir, and the fire,<br>
Holding a trencher, jesting merrily?<br>
You put our page out. Go, you are allowed;<br>
Die when you will, a smock shall be your shroud.<br>
You leer upon me, do you? There’s an eye<br>
Wounds like a leaden sword.
</p>

<p class="drama">
BOYET.<br>
Full merrily<br>
Hath this brave manage, this career, been run.
</p>

<p class="drama">
BEROWNE.<br>
Lo, he is tilting straight! Peace! I have done.
</p>

<p class="scenedesc">
Enter <span class="charname">Costard</span>.
</p>

<p class="drama">
Welcome, pure wit! Thou part’st a fair fray.
</p>

<p class="drama">
COSTARD.<br>
O Lord, sir, they would know<br>
Whether the three Worthies shall come in or no.
</p>

<p class="drama">
BEROWNE.<br>
What, are there but three?
</p>

<p class="drama">
COSTARD.<br>
No, sir; but it is vara fine,<br>
For every one pursents three.
</p>

<p class="drama">
BEROWNE.<br>
And three times thrice is nine.
</p>

<p class="drama">
COSTARD.<br>
Not so, sir, under correction, sir, I hope it is not so.<br>
You cannot beg us, sir, I can assure you, sir; we know what we know.<br>
I hope, sir, three times thrice, sir—
</p>

<p class="drama">
BEROWNE.<br>
Is not nine?
</p>

<p class="drama">
COSTARD.<br>
Under correction, sir, we know whereuntil it doth amount.
</p>

<p class="drama">
BEROWNE.<br>
By Jove, I always took three threes for nine.
</p>

<p class="drama">
COSTARD.<br>
O Lord, sir, it were pity you should get your living by reckoning, sir.
</p>

<p class="drama">
BEROWNE.<br>
How much is it?
</p>

<p class="drama">
COSTARD.<br>
O Lord, sir, the parties themselves, the actors, sir, will show whereuntil it
doth amount. For mine own part, I am, as they say, but to parfect one man in
one poor man—Pompion the Great, sir.
</p>

<p class="drama">
BEROWNE.<br>
Art thou one of the Worthies?
</p>

<p class="drama">
COSTARD.<br>
It pleased them to think me worthy of Pompey the Great. For mine own part, I
know not the degree of the Worthy, but I am to stand for him.
</p>

<p class="drama">
BEROWNE.<br>
Go bid them prepare.
</p>

<p class="drama">
COSTARD.<br>
We will turn it finely off, sir; we will take some care.
</p>

<p class="right">[<i>Exit <span class="charname">Costard</span>.</i>]</p>

<p class="drama">
KING.<br>
Berowne, they will shame us. Let them not approach.
</p>

<p class="drama">
BEROWNE.<br>
We are shame-proof, my lord, and ’tis some policy<br>
To have one show worse than the King’s and his company.
</p>

<p class="drama">
KING.<br>
I say they shall not come.
</p>

<p class="drama">
PRINCESS.<br>
Nay, my good lord, let me o’errule you now.<br>
That sport best pleases that doth least know how,<br>
Where zeal strives to content, and the contents<br>
Die in the zeal of that which it presents;<br>
Their form confounded makes most form in mirth,<br>
When great things labouring perish in their birth.
</p>

<p class="drama">
BEROWNE.<br>
A right description of our sport, my lord.
</p>

<p class="scenedesc">
Enter <span class="charname">Armado,</span> the Braggart.
</p>

<p class="drama">
ARMADO.<br>
Anointed, I implore so much expense of thy royal sweet breath as will utter a
brace of words.
</p>

<p class="right">[<i><span class="charname">Armado</span> and
<span class="charname">King</span> talk apart.</i>]</p>

<p class="drama">
PRINCESS.<br>
Doth this man serve God?
</p>

<p class="drama">
BEROWNE.<br>
Why ask you?
</p>

<p class="drama">
PRINCESS.<br>
He speaks not like a man of God his making.
</p>

<p class="drama">
ARMADO.<br>
That is all one, my fair, sweet, honey monarch; for, I protest, the
schoolmaster is exceeding fantastical; too, too vain, too, too vain. But we
will put it, as they say, to <i>fortuna de la guerra</i>. I wish you the peace
of mind, most royal couplement!
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
KING.<br>
Here is like to be a good presence of Worthies. He presents Hector of Troy; the
swain, Pompey the Great; the parish curate, Alexander; Armado’s page, Hercules;
the pedant, Judas Maccabaeus.<br>
<i>And if these four Worthies in their first show thrive,<br>
These four will change habits and present the other five.</i>
</p>

<p class="drama">
BEROWNE.<br>
There is five in the first show.
</p>

<p class="drama">
KING.<br>
You are deceived. ’Tis not so.
</p>

<p class="drama">
BEROWNE.<br>
The pedant, the braggart, the hedge-priest, the fool, and the boy.<br>
Abate throw at novum, and the whole world again<br>
Cannot pick out five such, take each one in his vein.
</p>

<p class="drama">
KING.<br>
The ship is under sail, and here she comes amain.
</p>

<p class="scenedesc">
Enter <span class="charname">Costard</span> as Pompey.
</p>

<p class="drama">
COSTARD.<br>
<i>I Pompey am</i>—
</p>

<p class="drama">
BEROWNE.<br>
You lie, you are not he.
</p>

<p class="drama">
COSTARD.<br>
<i>I Pompey am</i>—
</p>

<p class="drama">
BOYET.<br>
With leopard’s head on knee.
</p>

<p class="drama">
BEROWNE.<br>
Well said, old mocker. I must needs be friends with thee.
</p>

<p class="drama">
COSTARD.<br>
<i>I Pompey am, Pompey surnamed the Big.</i>
</p>

<p class="drama">
DUMAINE.<br>
The “Great”.
</p>

<p class="drama">
COSTARD.<br>
It is “Great”, sir; <i>Pompey surnamed the Great,<br>
That oft in field, with targe and shield, did make my foe to sweat.<br>
And travelling along this coast, I here am come by chance,<br>
And lay my arms before the legs of this sweet lass of France.</i><br>
If your ladyship would say, “Thanks, Pompey”, I had done.
</p>

<p class="drama">
PRINCESS.<br>
Great thanks, great Pompey.
</p>

<p class="drama">
COSTARD.<br>
’Tis not so much worth; but I hope I was perfect. I made a little fault in
“Great”.
</p>

<p class="drama">
BEROWNE.<br>
My hat to a halfpenny, Pompey proves the best Worthy.
</p>

<p class="scenedesc">
Enter <span class="charname">Nathaniel,</span> the Curate, for Alexander.
</p>

<p class="drama">
NATHANIEL.<br>
<i>When in the world I lived, I was the world’s commander;<br>
By east, west, north, and south, I spread my conquering might.<br>
My scutcheon plain declares that I am Alisander.</i>
</p>

<p class="drama">
BOYET.<br>
Your nose says, no, you are not; for it stands to right.
</p>

<p class="drama">
BEROWNE.<br>
Your nose smells “no” in this, most tender-smelling knight.
</p>

<p class="drama">
PRINCESS.<br>
The conqueror is dismayed. Proceed, good Alexander.
</p>

<p class="drama">
NATHANIEL.<br>
<i>When in the world I lived, I was the world’s commander</i>—
</p>

<p class="drama">
BOYET.<br>
Most true; ’tis right. You were so, Alisander.
</p>

<p class="drama">
BEROWNE.<br>
Pompey the Great—
</p>

<p class="drama">
COSTARD.<br>
Your servant, and Costard.
</p>

<p class="drama">
BEROWNE.<br>
Take away the conqueror, take away Alisander.
</p>

<p class="drama">
COSTARD.<br>
[<i>To Sir Nathaniel</i>.] O sir, you have overthrown Alisander the Conqueror.
You will be scraped out of the painted cloth for this. Your lion, that holds
his pole-axe sitting on a close-stool, will be given to Ajax. He will be the
ninth Worthy. A conqueror, and afeard to speak? Run away for shame, Alisander.
[<i>Nathaniel retires</i>.] There, an’t shall please you, a foolish mild man;
an honest man, look you, and soon dashed. He is a marvellous good neighbour,
faith, and a very good bowler; but for Alisander, alas you see how ’tis—a
little o’erparted. But there are Worthies a-coming will speak their mind in
some other sort.
</p>

<p class="drama">
PRINCESS.<br>
Stand aside, good Pompey.
</p>

<p class="scenedesc">
Enter <span class="charname">Holofernes,</span> the Pedant, as Judas, and
<span class="charname">Moth,</span> the Boy, as Hercules.
</p>

<p class="drama">
HOLOFERNES.<br>
<i>Great Hercules is presented by this imp,<br>
Whose club killed Cerberus, that three-headed</i> canus,<br>
<i>And when he was a babe, a child, a shrimp,<br>
Thus did he strangle serpents in his</i> manus.<br>
Quoniam <i>he seemeth in minority</i>,<br>
Ergo <i>I come with this apology.</i><br>
Keep some state in thy exit, and vanish.
</p>

<p class="right">[<i><span class="charname">Moth</span> retires.</i>]</p>

<p class="drama">
<i>Judas I am.</i>—
</p>

<p class="drama">
DUMAINE.<br>
A Judas!
</p>

<p class="drama">
HOLOFERNES.<br>
Not Iscariot, sir.<br>
<i>Judas I am, ycleped Maccabaeus.</i>
</p>

<p class="drama">
DUMAINE.<br>
Judas Maccabaeus clipped is plain Judas.
</p>

<p class="drama">
BEROWNE.<br>
A kissing traitor. How art thou proved Judas?
</p>

<p class="drama">
HOLOFERNES.<br>
<i>Judas I am</i>—
</p>

<p class="drama">
DUMAINE.<br>
The more shame for you, Judas.
</p>

<p class="drama">
HOLOFERNES.<br>
What mean you, sir?
</p>

<p class="drama">
BOYET.<br>
To make Judas hang himself.
</p>

<p class="drama">
HOLOFERNES.<br>
Begin, sir; you are my elder.
</p>

<p class="drama">
BEROWNE.<br>
Well followed. Judas was hanged on an elder.
</p>

<p class="drama">
HOLOFERNES.<br>
I will not be put out of countenance.
</p>

<p class="drama">
BEROWNE.<br>
Because thou hast no face.
</p>

<p class="drama">
HOLOFERNES.<br>
What is this?
</p>

<p class="drama">
BOYET.<br>
A cittern-head.
</p>

<p class="drama">
DUMAINE.<br>
The head of a bodkin.
</p>

<p class="drama">
BEROWNE.<br>
A death’s face in a ring.
</p>

<p class="drama">
LONGAVILLE.<br>
The face of an old Roman coin, scarce seen.
</p>

<p class="drama">
BOYET.<br>
The pommel of Caesar’s falchion.
</p>

<p class="drama">
DUMAINE.<br>
The carved-bone face on a flask.
</p>

<p class="drama">
BEROWNE.<br>
Saint George’s half-cheek in a brooch.
</p>

<p class="drama">
DUMAINE.<br>
Ay, and in a brooch of lead.
</p>

<p class="drama">
BEROWNE.<br>
Ay, and worn in the cap of a tooth-drawer.<br>
And now forward, for we have put thee in countenance.
</p>

<p class="drama">
HOLOFERNES.<br>
You have put me out of countenance.
</p>

<p class="drama">
BEROWNE.<br>
False. We have given thee faces.
</p>

<p class="drama">
HOLOFERNES.<br>
But you have outfaced them all.
</p>

<p class="drama">
BEROWNE.<br>
An thou wert a lion, we would do so.
</p>

<p class="drama">
BOYET.<br>
Therefore, as he is an ass, let him go.<br>
And so adieu, sweet Jude. Nay, why dost thou stay?
</p>

<p class="drama">
DUMAINE.<br>
For the latter end of his name.
</p>

<p class="drama">
BEROWNE.<br>
For the ass to the Jude? Give it him. Jud-as, away!
</p>

<p class="drama">
HOLOFERNES.<br>
This is not generous, not gentle, not humble.
</p>

<p class="drama">
BOYET.<br>
A light for Monsieur Judas! It grows dark; he may stumble.
</p>

<p class="right">[<i>Exit <span class="charname">Holofernes</span>.</i>]</p>

<p class="drama">
PRINCESS.<br>
Alas, poor Maccabaeus, how hath he been baited!
</p>

<p class="scenedesc">
Enter <span class="charname">Armado,</span> the Braggart, as Hector.
</p>

<p class="drama">
BEROWNE.<br>
Hide thy head, Achilles. Here comes Hector in arms.
</p>

<p class="drama">
DUMAINE.<br>
Though my mocks come home by me, I will now be merry.
</p>

<p class="drama">
KING.<br>
Hector was but a Trojan in respect of this.
</p>

<p class="drama">
BOYET.<br>
But is this Hector?
</p>

<p class="drama">
DUMAINE.<br>
I think Hector was not so clean-timbered.
</p>

<p class="drama">
LONGAVILLE.<br>
His leg is too big for Hector’s.
</p>

<p class="drama">
DUMAINE.<br>
More calf, certain.
</p>

<p class="drama">
BOYET.<br>
No, he is best endued in the small.
</p>

<p class="drama">
BEROWNE.<br>
This cannot be Hector.
</p>

<p class="drama">
DUMAINE.<br>
He’s a god or a painter, for he makes faces.
</p>

<p class="drama">
ARMADO.<br>
<i>The armipotent Mars, of lances the almighty,<br>
Gave Hector a gift</i>—
</p>

<p class="drama">
DUMAINE.<br>
A gilt nutmeg.
</p>

<p class="drama">
BEROWNE.<br>
A lemon.
</p>

<p class="drama">
LONGAVILLE.<br>
Stuck with cloves.
</p>

<p class="drama">
DUMAINE.<br>
No, cloven.
</p>

<p class="drama">
ARMADO.<br>
Peace!<br>
<i>The armipotent Mars, of lances the almighty,<br>
    Gave Hector a gift, the heir of Ilion;<br>
A man so breathed that certain he would fight, yea,<br>
    From morn till night, out of his pavilion.<br>
I am that flower</i>—
</p>

<p class="drama">
DUMAINE.<br>
That mint.
</p>

<p class="drama">
LONGAVILLE.<br>
That columbine.
</p>

<p class="drama">
ARMADO.<br>
Sweet Lord Longaville, rein thy tongue.
</p>

<p class="drama">
LONGAVILLE.<br>
I must rather give it the rein, for it runs against Hector.
</p>

<p class="drama">
DUMAINE.<br>
Ay, and Hector’s a greyhound.
</p>

<p class="drama">
ARMADO.<br>
The sweet war-man is dead and rotten. Sweet chucks, beat not the bones of the
buried. When he breathed, he was a man. But I will forward with my device.
[<i>To the Princess</i>.] Sweet royalty, bestow on me the sense of hearing.
</p>

<p class="drama">
PRINCESS.<br>
Speak, brave Hector; we are much delighted.
</p>

<p class="drama">
ARMADO.<br>
I do adore thy sweet Grace’s slipper.
</p>

<p class="drama">
BOYET.<br>
Loves her by the foot.
</p>

<p class="drama">
DUMAINE.<br>
He may not by the yard.
</p>

<p class="drama">
ARMADO.<br>
<i>This Hector far surmounted Hannibal.<br>
The party is gone</i>—
</p>

<p class="drama">
COSTARD.<br>
Fellow Hector, she is gone; she is two months on her way.
</p>

<p class="drama">
ARMADO.<br>
What meanest thou?
</p>

<p class="drama">
COSTARD.<br>
Faith, unless you play the honest Trojan, the poor wench is cast away. She’s
quick; the child brags in her belly already. ’Tis yours.
</p>

<p class="drama">
ARMADO.<br>
Dost thou infamonize me among potentates? Thou shalt die.
</p>

<p class="drama">
COSTARD.<br>
Then shall Hector be whipped for Jaquenetta that is quick by him, and hanged
for Pompey that is dead by him.
</p>

<p class="drama">
DUMAINE.<br>
Most rare Pompey!
</p>

<p class="drama">
BOYET.<br>
Renowned Pompey!
</p>

<p class="drama">
BEROWNE.<br>
Greater than  “Great”! Great, great, great Pompey! Pompey the Huge!
</p>

<p class="drama">
DUMAINE.<br>
Hector trembles.
</p>

<p class="drama">
BEROWNE.<br>
Pompey is moved. More Ates, more Ates! Stir them on, stir them on!
</p>

<p class="drama">
DUMAINE.<br>
Hector will challenge him.
</p>

<p class="drama">
BEROWNE.<br>
Ay, if he have no more man’s blood in his belly than will sup a flea.
</p>

<p class="drama">
ARMADO.<br>
By the north pole, I do challenge thee.
</p>

<p class="drama">
COSTARD.<br>
I will not fight with a pole, like a northern man. I’ll slash, I’ll do it by
the sword. I bepray you, let me borrow my arms again.
</p>

<p class="drama">
DUMAINE.<br>
Room for the incensed Worthies!
</p>

<p class="drama">
COSTARD.<br>
I’ll do it in my shirt.
</p>

<p class="drama">
DUMAINE.<br>
Most resolute Pompey!
</p>

<p class="drama">
MOTH.<br>
Master, let me take you a buttonhole lower. Do you not see Pompey is uncasing
for the combat? What mean you? You will lose your reputation.
</p>

<p class="drama">
ARMADO.<br>
Gentlemen and soldiers, pardon me. I will not combat in my shirt.
</p>

<p class="drama">
DUMAINE.<br>
You may not deny it. Pompey hath made the challenge.
</p>

<p class="drama">
ARMADO.<br>
Sweet bloods, I both may and will.
</p>

<p class="drama">
BEROWNE.<br>
What reason have you for ’t?
</p>

<p class="drama">
ARMADO.<br>
The naked truth of it is, I have no shirt. I go woolward for penance.
</p>

<p class="drama">
BOYET.<br>
True, and it was enjoined him in Rome for want of linen; since when, I’ll be
sworn, he wore none but a dishclout of Jaquenetta’s, and that he wears next
his heart for a favour.
</p>

<p class="scenedesc">
Enter a Messenger, <span class="charname">Monsieur Marcadé</span>.
</p>

<p class="drama">
MARCADÉ.<br>
God save you, madam.
</p>

<p class="drama">
PRINCESS.<br>
Welcome, Marcadé,<br>
But that thou interruptest our merriment.
</p>

<p class="drama">
MARCADÉ.<br>
I am sorry, madam, for the news I bring<br>
Is heavy in my tongue. The King your father—
</p>

<p class="drama">
PRINCESS.<br>
Dead, for my life!
</p>

<p class="drama">
MARCADÉ.<br>
Even so. My tale is told.
</p>

<p class="drama">
BEROWNE.<br>
Worthies away! The scene begins to cloud.
</p>

<p class="drama">
ARMADO.<br>
For mine own part, I breathe free breath. I have seen the day of wrong through
the little hole of discretion, and I will right myself like a soldier.
</p>

<p class="right">[<i>Exeunt <span class="charname">Worthies</span>.</i>]</p>

<p class="drama">
KING.<br>
How fares your Majesty?
</p>

<p class="drama">
PRINCESS.<br>
Boyet, prepare. I will away tonight.
</p>

<p class="drama">
KING.<br>
Madam, not so. I do beseech you stay.
</p>

<p class="drama">
PRINCESS.<br>
Prepare, I say. I thank you, gracious lords,<br>
For all your fair endeavours, and entreat,<br>
Out of a new-sad soul, that you vouchsafe<br>
In your rich wisdom to excuse or hide<br>
The liberal opposition of our spirits,<br>
If over-boldly we have borne ourselves<br>
In the converse of breath; your gentleness<br>
Was guilty of it. Farewell, worthy lord!<br>
A heavy heart bears not a nimble tongue.<br>
Excuse me so, coming too short of thanks<br>
For my great suit so easily obtained.
</p>

<p class="drama">
KING.<br>
The extreme parts of time extremely forms<br>
All causes to the purpose of his speed,<br>
And often at his very loose decides<br>
That which long process could not arbitrate.<br>
And though the mourning brow of progeny<br>
Forbid the smiling courtesy of love<br>
The holy suit which fain it would convince,<br>
Yet, since love’s argument was first on foot,<br>
Let not the cloud of sorrow jostle it<br>
From what it purposed; since to wail friends lost<br>
Is not by much so wholesome-profitable<br>
As to rejoice at friends but newly found.
</p>

<p class="drama">
PRINCESS.<br>
I understand you not. My griefs are double.
</p>

<p class="drama">
BEROWNE.<br>
Honest plain words best pierce the ear of grief;<br>
And by these badges understand the King.<br>
For your fair sakes have we neglected time,<br>
Played foul play with our oaths. Your beauty, ladies,<br>
Hath much deformed us, fashioning our humours<br>
Even to the opposed end of our intents;<br>
And what in us hath seemed ridiculous—<br>
As love is full of unbefitting strains,<br>
All wanton as a child, skipping and vain,<br>
Formed by the eye and therefore, like the eye,<br>
Full of strange shapes, of habits and of forms,<br>
Varying in subjects as the eye doth roll<br>
To every varied object in his glance;<br>
Which parti-coated presence of loose love<br>
Put on by us, if, in your heavenly eyes,<br>
Have misbecomed our oaths and gravities,<br>
Those heavenly eyes that look into these faults<br>
Suggested us to make. Therefore, ladies,<br>
Our love being yours, the error that love makes<br>
Is likewise yours. We to ourselves prove false<br>
By being once false for ever to be true<br>
To those that make us both—fair ladies, you.<br>
And even that falsehood, in itself a sin,<br>
Thus purifies itself and turns to grace.
</p>

<p class="drama">
PRINCESS.<br>
We have received your letters, full of love;<br>
Your favours, the ambassadors of love;<br>
And in our maiden council rated them<br>
At courtship, pleasant jest, and courtesy,<br>
As bombast and as lining to the time.<br>
But more devout than this in our respects<br>
Have we not been; and therefore met your loves<br>
In their own fashion, like a merriment.
</p>

<p class="drama">
DUMAINE.<br>
Our letters, madam, showed much more than jest.
</p>

<p class="drama">
LONGAVILLE.<br>
So did our looks.
</p>

<p class="drama">
ROSALINE.<br>
We did not quote them so.
</p>

<p class="drama">
KING.<br>
Now, at the latest minute of the hour,<br>
Grant us your loves.
</p>

<p class="drama">
PRINCESS.<br>
A time, methinks, too short<br>
To make a world-without-end bargain in.<br>
No, no, my lord, your Grace is perjured much,<br>
Full of dear guiltiness; and therefore this:<br>
If for my love—as there is no such cause—<br>
You will do aught, this shall you do for me:<br>
Your oath I will not trust, but go with speed<br>
To some forlorn and naked hermitage,<br>
Remote from all the pleasures of the world,<br>
There stay until the twelve celestial signs<br>
Have brought about the annual reckoning.<br>
If this austere insociable life<br>
Change not your offer made in heat of blood;<br>
If frosts and fasts, hard lodging and thin weeds,<br>
Nip not the gaudy blossoms of your love,<br>
But that it bear this trial, and last love;<br>
Then, at the expiration of the year,<br>
Come challenge me, challenge me by these deserts,<br>
And, by this virgin palm now kissing thine,<br>
I will be thine. And, till that instance, shut<br>
My woeful self up in a mournful house,<br>
Raining the tears of lamentation<br>
For the remembrance of my father’s death.<br>
If this thou do deny, let our hands part,<br>
Neither entitled in the other’s heart.
</p>

<p class="drama">
KING.<br>
If this, or more than this, I would deny,<br>
    To flatter up these powers of mine with rest,<br>
The sudden hand of death close up mine eye!<br>
    Hence hermit, then. My heart is in thy breast.
</p>

<p class="right">[<i>They converse apart</i>]</p>

<p class="drama">
DUMAINE.<br>
And what to me, my love? But what to me?<br>
A wife?
</p>

<p class="drama">
KATHARINE.<br>
A beard, fair health, and honesty;<br>
With threefold love I wish you all these three.
</p>

<p class="drama">
DUMAINE.<br>
O, shall I say, “I thank you, gentle wife”?
</p>

<p class="drama">
KATHARINE.<br>
No so, my lord. A twelvemonth and a day<br>
I’ll mark no words that smooth-faced wooers say.<br>
Come when the King doth to my lady come;<br>
Then, if I have much love, I’ll give you some.
</p>

<p class="drama">
DUMAINE.<br>
I’ll serve thee true and faithfully till then.
</p>

<p class="drama">
KATHARINE.<br>
Yet swear not, lest ye be forsworn again.
</p>

<p class="right">[<i>They converse apart</i>]</p>

<p class="drama">
LONGAVILLE.<br>
What says Maria?
</p>

<p class="drama">
MARIA.<br>
At the twelvemonth’s end<br>
I’ll change my black gown for a faithful friend.
</p>

<p class="drama">
LONGAVILLE.<br>
I’ll stay with patience, but the time is long.
</p>

<p class="drama">
MARIA.<br>
The liker you; few taller are so young.
</p>

<p class="right">[<i>They converse apart</i>]</p>

<p class="drama">
BEROWNE.<br>
Studies my lady? Mistress, look on me.<br>
Behold the window of my heart, mine eye,<br>
What humble suit attends thy answer there.<br>
Impose some service on me for thy love.
</p>

<p class="drama">
ROSALINE.<br>
Oft have I heard of you, my Lord Berowne,<br>
Before I saw you; and the world’s large tongue<br>
Proclaims you for a man replete with mocks,<br>
Full of comparisons and wounding flouts,<br>
Which you on all estates will execute<br>
That lie within the mercy of your wit.<br>
To weed this wormwood from your fruitful brain,<br>
And therewithal to win me, if you please,<br>
Without the which I am not to be won,<br>
You shall this twelvemonth term from day to day<br>
Visit the speechless sick, and still converse<br>
With groaning wretches; and your task shall be,<br>
With all the fierce endeavour of your wit<br>
To enforce the pained impotent to smile.
</p>

<p class="drama">
BEROWNE.<br>
To move wild laughter in the throat of death?<br>
It cannot be, it is impossible.<br>
Mirth cannot move a soul in agony.
</p>

<p class="drama">
ROSALINE.<br>
Why, that’s the way to choke a gibing spirit,<br>
Whose influence is begot of that loose grace<br>
Which shallow laughing hearers give to fools.<br>
A jest’s prosperity lies in the ear<br>
Of him that hears it, never in the tongue<br>
Of him that makes it. Then, if sickly ears,<br>
Deafed with the clamours of their own dear groans,<br>
Will hear your idle scorns, continue then,<br>
And I will have you and that fault withal;<br>
But if they will not, throw away that spirit,<br>
And I shall find you empty of that fault,<br>
Right joyful of your reformation.
</p>

<p class="drama">
BEROWNE.<br>
A twelvemonth? Well, befall what will befall,<br>
I’ll jest a twelvemonth in an hospital.
</p>

<p class="drama">
PRINCESS.<br>
[<i>To the King</i>.] Ay, sweet my lord, and so I take my leave.
</p>

<p class="drama">
KING.<br>
No, madam, we will bring you on your way.
</p>

<p class="drama">
BEROWNE.<br>
Our wooing doth not end like an old play.<br>
Jack hath not Jill. These ladies’ courtesy<br>
Might well have made our sport a comedy.
</p>

<p class="drama">
KING.<br>
Come, sir, it wants a twelvemonth and a day,<br>
And then ’twill end.
</p>

<p class="drama">
BEROWNE.<br>
That’s too long for a play.
</p>

<p class="scenedesc">
Enter <span class="charname">Armado,</span> the Braggart.
</p>

<p class="drama">
ARMADO.<br>
Sweet Majesty, vouchsafe me—
</p>

<p class="drama">
PRINCESS.<br>
Was not that Hector?
</p>

<p class="drama">
DUMAINE.<br>
The worthy knight of Troy.
</p>

<p class="drama">
ARMADO.<br>
I will kiss thy royal finger, and take leave. I am a votary; I have vowed to
Jaquenetta to hold the plough for her sweet love three year. But, most
esteemed Greatness, will you hear the dialogue that the two learned men have
compiled in praise of the owl and the cuckoo? It should have followed in the
end of our show.
</p>

<p class="drama">
KING.<br>
Call them forth quickly; we will do so.
</p>

<p class="drama">
ARMADO.<br>
Holla! Approach.
</p>

<p class="scenedesc">
Enter all.
</p>

<p class="drama">
This side is <i>Hiems</i>, Winter; this <i>Ver</i>, the Spring; the one
maintained by the owl, th’ other by the cuckoo. <i>Ver</i>, begin.
</p>

<h4>The Song</h4>

<p class="drama">
SPRING.<br>
When daisies pied and violets blue<br>
    And lady-smocks all silver-white<br>
And cuckoo-buds of yellow hue<br>
    Do paint the meadows with delight,<br>
The cuckoo then on every tree<br>
Mocks married men; for thus sings he:<br>
         “Cuckoo!<br>
Cuckoo, cuckoo!” O, word of fear,<br>
Unpleasing to a married ear.<br>
<br>
When shepherds pipe on oaten straws,<br>
    And merry larks are ploughmen’s clocks,<br>
When turtles tread, and rooks and daws,<br>
    And maidens bleach their summer smocks,<br>
The cuckoo then, on every tree,<br>
Mocks married men, for thus sings he:<br>
         “Cuckoo!<br>
Cuckoo, cuckoo!” O, word of fear,<br>
Unpleasing to a married ear.
</p>

<p class="drama">
WINTER.<br>
When icicles hang by the wall,<br>
    And Dick the shepherd blows his nail,<br>
And Tom bears logs into the hall,<br>
    And milk comes frozen home in pail,<br>
When blood is nipped, and ways be foul,<br>
  Then nightly sings the staring owl:<br>
“Tu-whit, Tu-whoo!” A merry note,<br>
While greasy Joan doth keel the pot.<br>
<br>
When all aloud the wind doth blow,<br>
    And coughing drowns the parson’s saw,<br>
And birds sit brooding in the snow,<br>
    And Marian’s nose looks red and raw,<br>
When roasted crabs hiss in the bowl,<br>
Then nightly sings the staring owl:<br>
“Tu-whit, Tu-whoo!” A merry note,<br>
While greasy Joan doth keel the pot.
</p>

<p class="drama">
ARMADO.<br>
The words of Mercury are harsh after the songs of Apollo.<br>
You that way, we this way.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

