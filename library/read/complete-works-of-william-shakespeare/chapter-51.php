<h2> <b>ACT IV</b></h2>

<h3> <a id="sceneIV_9.1"></a><b>SCENE I. The Rebel Camp near Shrewsbury.</b></h3>

<p class="scenedesc">Enter <span class="charname">Hotspur, Worcester</span> and
<span class="charname">Douglas</span>.
</p>

<p class="drama">
HOTSPUR.<br>
Well said, my noble Scot. If speaking truth<br>
In this fine age were not thought flattery,<br>
Such attribution should the Douglas have<br>
As not a soldier of this season’s stamp<br>
Should go so general current through the world.<br>
By God, I cannot flatter, I do defy<br>
The tongues of soothers, but a braver place<br>
In my heart’s love hath no man than yourself.<br>
Nay, task me to my word; approve me, lord.
</p>

<p class="drama">
DOUGLAS.<br>
Thou art the king of honour.<br>
No man so potent breathes upon the ground<br>
But I will beard him.
</p>

<p class="drama">
HOTSPUR.<br>
Do so, and ’tis well.
</p>

<p class="scenedesc">Enter a <span class="charname">Messenger</span> with letters.
</p>

<p class="drama">
What letters hast thou there? I can but thank you.
</p>

<p class="drama">
MESSENGER.<br>
These letters come from your father.
</p>

<p class="drama">
HOTSPUR.<br>
Letters from him! Why comes he not himself?
</p>

<p class="drama">
MESSENGER.<br>
He cannot come, my lord, he is grievous sick.
</p>

<p class="drama">
HOTSPUR.<br>
Zounds, how has he the leisure to be sick<br>
In such a justling time? Who leads his power?<br>
Under whose government come they along?
</p>

<p class="drama">
MESSENGER.<br>
His letters bear his mind, not I, my lord.
</p>

<p class="drama">
WORCESTER.<br>
I prithee, tell me, doth he keep his bed?
</p>

<p class="drama">
MESSENGER.<br>
He did, my lord, four days ere I set forth,<br>
And at the time of my departure thence<br>
He was much fear’d by his physicians.
</p>

<p class="drama">
WORCESTER.<br>
I would the state of time had first been whole<br>
Ere he by sickness had been visited.<br>
His health was never better worth than now.
</p>

<p class="drama">
HOTSPUR.<br>
Sick now? Droop now? This sickness doth infect<br>
The very life-blood of our enterprise;<br>
’Tis catching hither, even to our camp.<br>
He writes me here, that inward sickness—<br>
And that his friends by deputation could not<br>
So soon be drawn, nor did he think it meet<br>
To lay so dangerous and dear a trust<br>
On any soul removed but on his own.<br>
Yet doth he give us bold advertisement<br>
That with our small conjunction we should on,<br>
To see how fortune is disposed to us;<br>
For, as he writes, there is no quailing now,<br>
Because the King is certainly possess’d<br>
Of all our purposes. What say you to it?
</p>

<p class="drama">
WORCESTER.<br>
Your father’s sickness is a maim to us.
</p>

<p class="drama">
HOTSPUR.<br>
A perilous gash, a very limb lopp’d off—<br>
And yet, in faith, it is not! His present want<br>
Seems more than we shall find it. Were it good<br>
To set the exact wealth of all our states<br>
All at one cast? To set so rich a main<br>
On the nice hazard of one doubtful hour?<br>
It were not good, for therein should we read<br>
The very bottom and the soul of hope,<br>
The very list, the very utmost bound<br>
Of all our fortunes.
</p>

<p class="drama">
DOUGLAS.<br>
Faith, and so we should, where now remains<br>
A sweet reversion. We may boldly spend<br>
Upon the hope of what is to come in.<br>
A comfort of retirement lives in this.
</p>

<p class="drama">
HOTSPUR.<br>
A rendezvous, a home to fly unto,<br>
If that the devil and mischance look big<br>
Upon the maidenhead of our affairs.
</p>

<p class="drama">
WORCESTER.<br>
But yet I would your father had been here.<br>
The quality and hair of our attempt<br>
Brooks no division. It will be thought<br>
By some that know not why he is away,<br>
That wisdom, loyalty, and mere dislike<br>
Of our proceedings, kept the Earl from hence.<br>
And think how such an apprehension<br>
May turn the tide of fearful faction,<br>
And breed a kind of question in our cause.<br>
For well you know we of the off’ring side<br>
Must keep aloof from strict arbitrement,<br>
And stop all sight-holes, every loop from whence<br>
The eye of reason may pry in upon us.<br>
This absence of your father’s draws a curtain<br>
That shows the ignorant a kind of fear<br>
Before not dreamt of.
</p>

<p class="drama">
HOTSPUR.<br>
You strain too far.<br>
I rather of his absence make this use:<br>
It lends a lustre and more great opinion,<br>
A larger dare to our great enterprise,<br>
Than if the Earl were here; for men must think<br>
If we without his help can make a head<br>
To push against the kingdom, with his help<br>
We shall o’erturn it topsy-turvy down.<br>
Yet all goes well, yet all our joints are whole.
</p>

<p class="drama">
DOUGLAS.<br>
As heart can think. There is not such a word<br>
Spoke in Scotland as this term of fear.
</p>

<p class="scenedesc">Enter <span class="charname">Sir Richard Vernon</span>.
</p>

<p class="drama">
HOTSPUR.<br>
My cousin Vernon! Welcome, by my soul.
</p>

<p class="drama">
VERNON.<br>
Pray God my news be worth a welcome, lord.<br>
The Earl of Westmoreland, seven thousand strong,<br>
Is marching hitherwards, with him Prince John.
</p>

<p class="drama">
HOTSPUR.<br>
No harm, what more?
</p>

<p class="drama">
VERNON.<br>
And further, I have learn’d<br>
The King himself in person is set forth,<br>
Or hitherwards intended speedily,<br>
With strong and mighty preparation.
</p>

<p class="drama">
HOTSPUR.<br>
He shall be welcome too. Where is his son,<br>
The nimble-footed madcap Prince of Wales,<br>
And his comrades, that daffed the world aside<br>
And bid it pass?
</p>

<p class="drama">
VERNON.<br>
All furnish’d, all in arms;<br>
All plumed like estridges that with the wind<br>
Bated like eagles having lately bathed,<br>
Glittering in golden coats, like images,<br>
As full of spirit as the month of May,<br>
And gorgeous as the sun at midsummer;<br>
Wanton as youthful goats, wild as young bulls.<br>
I saw young Harry with his beaver on,<br>
His cuisses on his thighs, gallantly arm’d,<br>
Rise from the ground like feather’d Mercury,<br>
And vaulted with such ease into his seat<br>
As if an angel dropp’d down from the clouds,<br>
To turn and wind a fiery Pegasus,<br>
And witch the world with noble horsemanship.
</p>

<p class="drama">
HOTSPUR.<br>
No more, no more! Worse than the sun in March,<br>
This praise doth nourish agues. Let them come!<br>
They come like sacrifices in their trim,<br>
And to the fire-eyed maid of smoky war<br>
All hot and bleeding will we offer them.<br>
The mailed Mars shall on his altar sit<br>
Up to the ears in blood. I am on fire<br>
To hear this rich reprisal is so nigh,<br>
And yet not ours. Come, let me taste my horse,<br>
Who is to bear me like a thunderbolt<br>
Against the bosom of the Prince of Wales.<br>
Harry to Harry shall, hot horse to horse,<br>
Meet and ne’er part till one drop down a corse.<br>
O, that Glendower were come!
</p>

<p class="drama">
VERNON.<br>
There is more news.<br>
I learn’d in Worcester, as I rode along,<br>
He cannot draw his power this fourteen days.
</p>

<p class="drama">
DOUGLAS.<br>
That’s the worst tidings that I hear of yet.
</p>

<p class="drama">
WORCESTER.<br>
Ay, by my faith, that bears a frosty sound.
</p>

<p class="drama">
HOTSPUR.<br>
What may the King’s whole battle reach unto?
</p>

<p class="drama">
VERNON.<br>
To thirty thousand.
</p>

<p class="drama">
HOTSPUR.<br>
Forty let it be.<br>
My father and Glendower being both away,<br>
The powers of us may serve so great a day.<br>
Come, let us take a muster speedily.<br>
Doomsday is near; die all, die merrily.
</p>

<p class="drama">
DOUGLAS.<br>
Talk not of dying. I am out of fear<br>
Of death or death’s hand for this one half year.
</p>

<p class="right">[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneIV_9.2"></a><b>SCENE II. A public Road near Coventry.</b></h3>

<p class="scenedesc">Enter <span class="charname">Falstaff</span> and
<span class="charname">Bardolph</span>.
</p>

<p class="drama">
FALSTAFF.<br>
Bardolph, get thee before to Coventry; fill me a bottle of sack. Our soldiers
shall march through; we’ll to Sutton Co’fil’ tonight.
</p>

<p class="drama">
BARDOLPH.<br>
Will you give me money, captain?
</p>

<p class="drama">
FALSTAFF.<br>
Lay out, lay out.
</p>

<p class="drama">
BARDOLPH.<br>
This bottle makes an angel.
</p>

<p class="drama">
FALSTAFF.<br>
An if it do, take it for thy labour. An if it make twenty, take them all,
I’ll answer the coinage. Bid my lieutenant Peto meet me at town’s
end.
</p>

<p class="drama">
BARDOLPH.<br>
I will, captain: farewell.
</p>

<p class="right">[<i>Exit.</i>]
</p>

<p class="drama">
FALSTAFF.<br>
If I be not ashamed of my soldiers, I am a soused gurnet. I have misused the
King’s press damnably. I have got, in exchange of a hundred and fifty
soldiers, three hundred and odd pounds. I press me none but good householders,
yeomen’s sons, inquire me out contracted bachelors, such as had been
asked twice on the banns, such a commodity of warm slaves as had as lief hear
the devil as a drum, such as fear the report of a caliver worse than a struck
fowl or a hurt wild duck. I pressed me none but such toasts-and-butter, with
hearts in their bellies no bigger than pins’ heads, and they have bought
out their services; and now my whole charge consists of ancients, corporals,
lieutenants, gentlemen of companies—slaves as ragged as Lazarus in the
painted cloth, where the glutton’s dogs licked his sores; and such as
indeed were never soldiers, but discarded unjust servingmen, younger sons to
younger brothers, revolted tapsters, and ostlers trade-fallen; the cankers of a
calm world and a long peace, ten times more dishonourable-ragged than an old
fazed ancient; and such have I to fill up the rooms of them that have bought
out their services, that you would think that I had a hundred and fifty
tattered prodigals lately come from swine-keeping, from eating draff and husks.
A mad fellow met me on the way, and told me I had unloaded all the gibbets and
pressed the dead bodies. No eye hath seen such scarecrows. I’ll not march
through Coventry with them, that’s flat. Nay, and the villains march wide
betwixt the legs as if they had gyves on, for indeed I had the most of them out
of prison. There’s not a shirt and a half in all my company, and the half
shirt is two napkins tacked together and thrown over the shoulders like a
herald’s coat without sleeves; and the shirt, to say the truth, stolen
from my host at Saint Albans, or the red-nose innkeeper of Daventry. But
that’s all one; they’ll find linen enough on every hedge.
</p>

<p class="scenedesc">Enter <span class="charname">Prince Henry</span> and the
<span class="charname">Lord of Westmoreland</span>.
</p>

<p class="drama">
PRINCE.<br>
How now, blown Jack? How now, quilt?
</p>

<p class="drama">
FALSTAFF.<br>
What, Hal! How now, mad wag? What a devil dost thou in Warwickshire? My
good Lord of Westmoreland, I cry you mercy. I thought your honour had already
been at Shrewsbury.
</p>

<p class="drama">
WESTMORELAND.<br>
Faith, Sir John, ’tis more than time that I were there, and you too, but
my powers are there already. The King, I can tell you, looks for us all. We
must away all night.
</p>

<p class="drama">
FALSTAFF.<br>
Tut, never fear me. I am as vigilant as a cat to steal cream.
</p>

<p class="drama">
PRINCE.<br>
I think, to steal cream indeed, for thy theft hath already made thee butter.
But tell me, Jack, whose fellows are these that come after?
</p>

<p class="drama">
FALSTAFF.<br>
Mine, Hal, mine.
</p>

<p class="drama">
PRINCE.<br>
I did never see such pitiful rascals.
</p>

<p class="drama">
FALSTAFF.<br>
Tut, tut, good enough to toss; food for powder, food for powder, they’ll
fill a pit as well as better. Tush, man, mortal men, mortal men.
</p>

<p class="drama">
WESTMORELAND.<br>
Ay, but, Sir John, methinks they are exceeding poor and bare, too beggarly.
</p>

<p class="drama">
FALSTAFF.<br>
Faith, for their poverty, I know not where they had that; and for their
bareness, I am sure they never learned that of me.
</p>

<p class="drama">
PRINCE.<br>
No, I’ll be sworn, unless you call three fingers on the ribs bare. But,
sirrah, make haste. Percy is already in the field.
</p>

<p class="right">[<i>Exit.</i>]
</p>

<p class="drama">
FALSTAFF.<br>
What, is the King encamped?
</p>

<p class="drama">
WESTMORELAND.<br>
He is, Sir John. I fear we shall stay too long.
</p>

<p class="right">[<i>Exit.</i>]
</p>

<p class="drama">
FALSTAFF.<br>
Well,<br>
To the latter end of a fray and the beginning of a feast<br>
Fits a dull fighter and a keen guest.
</p>

<p class="right">[<i>Exit.</i>]
</p>

<h3> <a id="sceneIV_9.3"></a><b>SCENE III. The Rebel Camp near Shrewsbury.</b></h3>

<p class="scenedesc">Enter <span class="charname">Hotspur, Worcester, Douglas</span> and
<span class="charname">Vernon</span>.
</p>

<p class="drama">
HOTSPUR.<br>
We’ll fight with him tonight.
</p>

<p class="drama">
WORCESTER.<br>
It may not be.
</p>

<p class="drama">
DOUGLAS.<br>
You give him then advantage.
</p>

<p class="drama">
VERNON.<br>
Not a whit.
</p>

<p class="drama">
HOTSPUR.<br>
Why say you so? Looks he not for supply?
</p>

<p class="drama">
VERNON.<br>
So do we.
</p>

<p class="drama">
HOTSPUR.<br>
His is certain, ours is doubtful.
</p>

<p class="drama">
WORCESTER.<br>
Good cousin, be advised, stir not tonight.
</p>

<p class="drama">
VERNON.<br>
Do not, my lord.
</p>

<p class="drama">
DOUGLAS.<br>
You do not counsel well.<br>
You speak it out of fear and cold heart.
</p>

<p class="drama">
VERNON.<br>
Do me no slander, Douglas; by my life,<br>
And I dare well maintain it with my life,<br>
If well-respected honour bid me on,<br>
I hold as little counsel with weak fear<br>
As you, my lord, or any Scot that this day lives.<br>
Let it be seen tomorrow in the battle<br>
Which of us fears.
</p>

<p class="drama">
DOUGLAS.<br>
Yea, or tonight.
</p>

<p class="drama">
VERNON.<br>
Content.
</p>

<p class="drama">
HOTSPUR.<br>
Tonight, say I.
</p>

<p class="drama">
VERNON.<br>
Come, come, it may not be. I wonder much,<br>
Being men of such great leading as you are,<br>
That you foresee not what impediments<br>
Drag back our expedition. Certain horse<br>
Of my cousin Vernon’s are not yet come up.<br>
Your uncle Worcester’s horse came but today,<br>
And now their pride and mettle is asleep,<br>
Their courage with hard labour tame and dull,<br>
That not a horse is half the half himself.
</p>

<p class="drama">
HOTSPUR.<br>
So are the horses of the enemy<br>
In general, journey-bated and brought low.<br>
The better part of ours are full of rest.
</p>

<p class="drama">
WORCESTER.<br>
The number of the King exceedeth ours.<br>
For God’s sake, cousin, stay till all come in.
</p>

<p class="right">[<i>The trumpet sounds a parley.</i>]
</p>

<p class="scenedesc">Enter <span class="charname">Sir Walter Blunt</span>.
</p>

<p class="drama">
BLUNT.<br>
I come with gracious offers from the King,<br>
If you vouchsafe me hearing and respect.
</p>

<p class="drama">
HOTSPUR.<br>
Welcome, Sir Walter Blunt, and would to God<br>
You were of our determination!<br>
Some of us love you well, and even those some<br>
Envy your great deservings and good name,<br>
Because you are not of our quality,<br>
But stand against us like an enemy.
</p>

<p class="drama">
BLUNT.<br>
And God defend but still I should stand so,<br>
So long as out of limit and true rule<br>
You stand against anointed majesty.<br>
But to my charge. The King hath sent to know<br>
The nature of your griefs, and whereupon<br>
You conjure from the breast of civil peace<br>
Such bold hostility, teaching his duteous land<br>
Audacious cruelty. If that the King<br>
Have any way your good deserts forgot,<br>
Which he confesseth to be manifold,<br>
He bids you name your griefs, and with all speed<br>
You shall have your desires with interest<br>
And pardon absolute for yourself and these<br>
Herein misled by your suggestion.
</p>

<p class="drama">
HOTSPUR.<br>
The King is kind, and well we know the King<br>
Knows at what time to promise, when to pay.<br>
My father and my uncle and myself<br>
Did give him that same royalty he wears,<br>
And when he was not six-and-twenty strong,<br>
Sick in the world’s regard, wretched and low,<br>
A poor unminded outlaw sneaking home,<br>
My father gave him welcome to the shore:<br>
And when he heard him swear and vow to God<br>
He came but to be Duke of Lancaster,<br>
To sue his livery, and beg his peace<br>
With tears of innocence and terms of zeal,<br>
My father, in kind heart and pity moved,<br>
Swore him assistance, and performed it too.<br>
Now, when the lords and barons of the realm<br>
Perceived Northumberland did lean to him,<br>
The more and less came in with cap and knee,<br>
Met him in boroughs, cities, villages,<br>
Attended him on bridges, stood in lanes,<br>
Laid gifts before him, proffer’d him their oaths,<br>
Give him their heirs as pages, follow’d him<br>
Even at the heels in golden multitudes.<br>
He presently, as greatness knows itself,<br>
Steps me a little higher than his vow<br>
Made to my father while his blood was poor<br>
Upon the naked shore at Ravenspurgh;<br>
And now forsooth takes on him to reform<br>
Some certain edicts and some strait decrees<br>
That lie too heavy on the commonwealth;<br>
Cries out upon abuses, seems to weep<br>
Over his country’s wrongs; and by this face,<br>
This seeming brow of justice, did he win<br>
The hearts of all that he did angle for;<br>
Proceeded further—cut me off the heads<br>
Of all the favourites that the absent King<br>
In deputation left behind him here<br>
When he was personal in the Irish war.
</p>

<p class="drama">
BLUNT.<br>
Tut, I came not to hear this.
</p>

<p class="drama">
HOTSPUR.<br>
Then to the point.<br>
In short time after, he deposed the King,<br>
Soon after that deprived him of his life,<br>
And, in the neck of that, task’d the whole state.<br>
To make that worse, suffer’d his kinsman March<br>
(Who is, if every owner were well placed,<br>
Indeed his king) to be engaged in Wales,<br>
There without ransom to lie forfeited;<br>
Disgraced me in my happy victories,<br>
Sought to entrap me by intelligence,<br>
Rated mine uncle from the Council-board,<br>
In rage dismiss’d my father from the court,<br>
Broke oath on oath, committed wrong on wrong,<br>
And in conclusion drove us to seek out<br>
This head of safety, and withal to pry<br>
Into his title, the which now we find<br>
Too indirect for long continuance.
</p>

<p class="drama">
BLUNT.<br>
Shall I return this answer to the King?
</p>

<p class="drama">
HOTSPUR.<br>
Not so, Sir Walter. We’ll withdraw awhile.<br>
Go to the King, and let there be impawn’d<br>
Some surety for a safe return again,<br>
And in the morning early shall my uncle<br>
Bring him our purposes. And so, farewell.
</p>

<p class="drama">
BLUNT.<br>
I would you would accept of grace and love.
</p>

<p class="drama">
HOTSPUR.<br>
And maybe so we shall.
</p>

<p class="drama">
BLUNT.<br>
Pray God you do.
</p>

<p class="right">[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneIV_9.4"></a><b>SCENE IV. York. A Room in the Archbishop’s Palace.</b></h3>

<p class="scenedesc">Enter the <span class="charname">Archbishop of York</span> and
<span class="charname">Sir Michael</span>.
</p>

<p class="drama">
ARCHBISHOP.<br>
Hie, good Sir Michael; bear this sealed brief<br>
With winged haste to the Lord Marshal,<br>
This to my cousin Scroop, and all the rest<br>
To whom they are directed. If you knew<br>
How much they do import, you would make haste.
</p>

<p class="drama">
SIR MICHAEL.<br>
My good lord,<br>
I guess their tenour.
</p>

<p class="drama">
ARCHBISHOP.<br>
Like enough you do.<br>
Tomorrow, good Sir Michael, is a day<br>
Wherein the fortune of ten thousand men<br>
Must bide the touch; for, sir, at Shrewsbury,<br>
As I am truly given to understand,<br>
The King with mighty and quick-raised power<br>
Meets with Lord Harry. And, I fear, Sir Michael,<br>
What with the sickness of Northumberland,<br>
Whose power was in the first proportion,<br>
And what with Owen Glendower’s absence thence,<br>
Who with them was a rated sinew too,<br>
And comes not in, o’er-rul’d by prophecies,<br>
I fear the power of Percy is too weak<br>
To wage an instant trial with the King.
</p>

<p class="drama">
SIR MICHAEL.<br>
Why, my good lord, you need not fear,<br>
There is Douglas and Lord Mortimer.
</p>

<p class="drama">
ARCHBISHOP.<br>
No, Mortimer is not there.
</p>

<p class="drama">
SIR MICHAEL.<br>
But there is Mordake, Vernon, Lord Harry Percy,<br>
And there is my Lord of Worcester, and a head<br>
Of gallant warriors, noble gentlemen.
</p>

<p class="drama">
ARCHBISHOP.<br>
And so there is. But yet the King hath drawn<br>
The special head of all the land together:<br>
The Prince of Wales, Lord John of Lancaster,<br>
The noble Westmoreland, and warlike Blunt,<br>
And many more corrivals and dear men<br>
Of estimation and command in arms.
</p>

<p class="drama">
SIR MICHAEL.<br>
Doubt not, my lord, they shall be well opposed.
</p>

<p class="drama">
ARCHBISHOP.<br>
I hope no less, yet needful ’tis to fear;<br>
And to prevent the worst, Sir Michael, speed.<br>
For if Lord Percy thrive not, ere the King<br>
Dismiss his power he means to visit us,<br>
For he hath heard of our confederacy,<br>
And ’tis but wisdom to make strong against him.<br>
Therefore make haste. I must go write again<br>
To other friends; and so, farewell, Sir Michael.
</p>

<p class="right">[<i>Exeunt.</i>]
</p>

