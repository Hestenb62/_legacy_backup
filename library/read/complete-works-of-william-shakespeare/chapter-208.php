<h2> <a id="sceneIV_33.1"></a><b>ACT IV</b></h2>

<h3> <b>SCENE I. Without the walls of Athens</b></h3>

<p class="scenedesc">
Enter <span class="charname">Timon</span>.
</p>

<p class="drama">
TIMON.<br>
Let me look back upon thee. O thou wall<br>
That girdles in those wolves, dive in the earth<br>
And fence not Athens! Matrons, turn incontinent!<br>
Obedience fail in children! Slaves and fools,<br>
Pluck the grave wrinkled senate from the bench<br>
And minister in their steads! To general filths<br>
Convert, o’ th’ instant, green virginity,<br>
Do’t in your parents’ eyes! Bankrupts, hold fast;<br>
Rather than render back, out with your knives<br>
And cut your trusters’ throats! Bound servants, steal!<br>
Large-handed robbers your grave masters are,<br>
And pill by law. Maid, to thy master’s bed,<br>
Thy mistress is o’ th’ brothel. Son of sixteen,<br>
Pluck the lined crutch from thy old limping sire,<br>
With it beat out his brains! Piety and fear,<br>
Religion to the gods, peace, justice, truth,<br>
Domestic awe, night-rest and neighbourhood,<br>
Instruction, manners, mysteries and trades,<br>
Degrees, observances, customs and laws,<br>
Decline to your confounding contraries,<br>
And let confusion live! Plagues incident to men,<br>
Your potent and infectious fevers heap<br>
On Athens, ripe for stroke! Thou cold sciatica,<br>
Cripple our senators, that their limbs may halt<br>
As lamely as their manners! Lust and liberty,<br>
Creep in the minds and marrows of our youth,<br>
That ’gainst the stream of virtue they may strive<br>
And drown themselves in riot! Itches, blains,<br>
Sow all th’ Athenian bosoms, and their crop<br>
Be general leprosy! Breath infect breath,<br>
That their society, as their friendship, may<br>
Be merely poison! Nothing I’ll bear from thee<br>
But nakedness, thou detestable town!<br>
Take thou that too, with multiplying bans!<br>
Timon will to the woods, where he shall find<br>
Th’ unkindest beast more kinder than mankind.<br>
The gods confound—hear me, you good gods all!—<br>
Th’ Athenians both within and out that wall,<br>
And grant, as Timon grows, his hate may grow<br>
To the whole race of mankind, high and low!<br>
Amen.
</p>

<p class="right">[<i>Exit.</i>]</p>

<h3> <a id="sceneIV_33.2"></a><b>SCENE II. Athens. A room in Timon’s house</b></h3>

<p class="scenedesc">
Enter <span class="charname">Flavius</span> with two or three
<span class="charname">Servants</span>.
</p>

<p class="drama">
FIRST SERVANT.<br>
Hear you, Master Steward, where’s our master?<br>
Are we undone, cast off, nothing remaining?
</p>

<p class="drama">
FLAVIUS.<br>
Alack, my fellows, what should I say to you?<br>
Let me be recorded by the righteous gods,<br>
I am as poor as you.
</p>

<p class="drama">
FIRST SERVANT.<br>
Such a house broke?<br>
So noble a master fall’n? All gone, and not<br>
One friend to take his fortune by the arm<br>
And go along with him?
</p>

<p class="drama">
SECOND SERVANT.<br>
As we do turn our backs<br>
From our companion, thrown into his grave,<br>
So his familiars to his buried fortunes<br>
Slink all away, leave their false vows with him,<br>
Like empty purses picked; and his poor self,<br>
A dedicated beggar to the air,<br>
With his disease of all-shunned poverty,<br>
Walks, like contempt, alone.—More of our fellows.
</p>

<p class="scenedesc">
Enter other <span class="charname">Servants</span>.
</p>

<p class="drama">
FLAVIUS.<br>
All broken implements of a ruined house.
</p>

<p class="drama">
THIRD SERVANT.<br>
Yet do our hearts wear Timon’s livery.<br>
That see I by our faces. We are fellows still,<br>
Serving alike in sorrow. Leaked is our bark,<br>
And we, poor mates, stand on the dying deck,<br>
Hearing the surges threat. We must all part<br>
Into this sea of air.
</p>

<p class="drama">
FLAVIUS.<br>
Good fellows all,<br>
The latest of my wealth I’ll share amongst you.<br>
Wherever we shall meet, for Timon’s sake<br>
Let’s yet be fellows. Let’s shake our heads and say,<br>
As ’twere a knell unto our master’s fortune,<br>
“We have seen better days.” Let each take some.
</p>

<p class="right">[<i>Offering them money.</i>]</p>

<p class="drama">
Nay, put out all your hands. Not one word more.<br>
Thus part we rich in sorrow, parting poor.
</p>

<p class="right">[<i>They embrace and part several ways.</i>]</p>

<p class="drama">
O, the fierce wretchedness that glory brings us!<br>
Who would not wish to be from wealth exempt,<br>
Since riches point to misery and contempt?<br>
Who would be so mocked with glory, or to live<br>
But in a dream of friendship,<br>
To have his pomp and all what state compounds<br>
But only painted, like his varnished friends?<br>
Poor honest lord, brought low by his own heart,<br>
Undone by goodness! Strange, unusual blood<br>
When man’s worst sin is he does too much good!<br>
Who then dares to be half so kind again?<br>
For bounty, that makes gods, does still mar men.<br>
My dearest lord, blessed to be most accursed,<br>
Rich only to be wretched, thy great fortunes<br>
Are made thy chief afflictions. Alas, kind lord,<br>
He’s flung in rage from this ingrateful seat<br>
Of monstrous friends;<br>
Nor has he with him to supply his life,<br>
Or that which can command it.<br>
I’ll follow and inquire him out.<br>
I’ll ever serve his mind with my best will.<br>
Whilst I have gold, I’ll be his steward still.
</p>

<p class="right">[<i>Exit.</i>]</p>

<h3> <a id="sceneIV_33.3"></a><b>SCENE III. Woods and caves near the sea-shore</b></h3>

<p class="scenedesc">
Enter <span class="charname">Timon</span> in the woods.
</p>

<p class="drama">
TIMON.<br>
O blessed breeding sun, draw from the earth<br>
Rotten humidity, below thy sister’s orb<br>
Infect the air! Twinned brothers of one womb,<br>
Whose procreation, residence and birth<br>
Scarce is dividant, touch them with several fortunes,<br>
The greater scorns the lesser. Not nature,<br>
To whom all sores lay siege, can bear great fortune<br>
But by contempt of nature.<br>
Raise me this beggar, and deny’t that lord;<br>
The senator shall bear contempt hereditary,<br>
The beggar native honour.<br>
It is the pasture lards the rother’s sides,<br>
The want that makes him lean. Who dares, who dares<br>
In purity of manhood stand upright<br>
And say, “This man’s a flatterer”? If one be,<br>
So are they all, for every grece of fortune<br>
Is smoothed by that below. The learned pate<br>
Ducks to the golden fool. All’s obliquy.<br>
There’s nothing level in our cursed natures<br>
But direct villainy. Therefore be abhorred<br>
All feasts, societies, and throngs of men!<br>
His semblable, yea, himself, Timon disdains.<br>
Destruction fang mankind! Earth, yield me roots!
</p>

<p class="right">[<i>Digs in the earth.</i>]</p>

<p class="drama">
Who seeks for better of thee, sauce his palate<br>
With thy most operant poison! What is here?<br>
Gold? Yellow, glittering, precious gold?<br>
No, gods, I am no idle votarist.<br>
Roots, you clear heavens! Thus much of this will make<br>
Black white, foul fair, wrong right,<br>
Base noble, old young, coward valiant.<br>
Ha, you gods, why this? What this, you gods? Why, this<br>
Will lug your priests and servants from your sides,<br>
Pluck stout men’s pillows from below their heads.<br>
This yellow slave<br>
Will knit and break religions, bless th’ accursed,<br>
Make the hoar leprosy adored, place thieves<br>
And give them title, knee, and approbation<br>
With senators on the bench. This is it<br>
That makes the wappened widow wed again;<br>
She whom the spittle-house and ulcerous sores<br>
Would cast the gorge at, this embalms and spices<br>
To th’ April day again. Come, damned earth,<br>
Thou common whore of mankind, that puts odds<br>
Among the rout of nations, I will make thee<br>
Do thy right nature.
</p>

<p class="right">[<i>March afar off.</i>]</p>

<p class="drama">
Ha? A drum? Thou’rt quick,<br>
But yet I’ll bury thee. Thou’lt go, strong thief,<br>
When gouty keepers of thee cannot stand.<br>
Nay, stay thou out for earnest.
</p>

<p class="right">[<i>Keeping some gold.</i>]</p>

<p class="scenedesc">
Enter <span class="charname">Alcibiades</span> with drum and fife, in warlike
manner, and <span class="charname">Phrynia</span> and
<span class="charname">Timandra</span>.
</p>

<p class="drama">
ALCIBIADES.<br>
What art thou there? Speak.
</p>

<p class="drama">
TIMON.<br>
A beast, as thou art. The canker gnaw thy heart<br>
For showing me again the eyes of man!
</p>

<p class="drama">
ALCIBIADES.<br>
What is thy name? Is man so hateful to thee<br>
That art thyself a man?
</p>

<p class="drama">
TIMON.<br>
I am Misanthropos and hate mankind.<br>
For thy part, I do wish thou wert a dog,<br>
That I might love thee something.
</p>

<p class="drama">
ALCIBIADES.<br>
I know thee well,<br>
But in thy fortunes am unlearned and strange.
</p>

<p class="drama">
TIMON.<br>
I know thee too, and more than that I know thee<br>
I not desire to know. Follow thy drum,<br>
With man’s blood paint the ground gules, gules.<br>
Religious canons, civil laws are cruel,<br>
Then what should war be? This fell whore of thine<br>
Hath in her more destruction than thy sword,<br>
For all her cherubin look.
</p>

<p class="drama">
PHRYNIA.<br>
Thy lips rot off!
</p>

<p class="drama">
TIMON.<br>
I will not kiss thee, then the rot returns<br>
To thine own lips again.
</p>

<p class="drama">
ALCIBIADES.<br>
How came the noble Timon to this change?
</p>

<p class="drama">
TIMON.<br>
As the moon does, by wanting light to give.<br>
But then renew I could not like the moon;<br>
There were no suns to borrow of.
</p>

<p class="drama">
ALCIBIADES.<br>
Noble Timon,<br>
What friendship may I do thee?
</p>

<p class="drama">
TIMON.<br>
None, but to maintain my opinion.
</p>

<p class="drama">
ALCIBIADES.<br>
What is it, Timon?
</p>

<p class="drama">
TIMON.<br>
Promise me friendship, but perform none. If thou wilt not promise, the gods
plague thee, for thou art a man. If thou dost perform, confound thee, for thou
art a man.
</p>

<p class="drama">
ALCIBIADES.<br>
I have heard in some sort of thy miseries.
</p>

<p class="drama">
TIMON.<br>
Thou saw’st them when I had prosperity.
</p>

<p class="drama">
ALCIBIADES.<br>
I see them now; then was a blessed time.
</p>

<p class="drama">
TIMON.<br>
As thine is now, held with a brace of harlots.
</p>

<p class="drama">
TIMANDRA.<br>
Is this th’ Athenian minion whom the world<br>
Voiced so regardfully?
</p>

<p class="drama">
TIMON.<br>
Art thou Timandra?
</p>

<p class="drama">
TIMANDRA.<br>
Yes.
</p>

<p class="drama">
TIMON.<br>
Be a whore still, they love thee not that use thee;<br>
Give them diseases, leaving with thee their lust.<br>
Make use of thy salt hours. Season the slaves<br>
For tubs and baths, bring down rose-cheeked youth<br>
To the tub-fast and the diet.
</p>

<p class="drama">
TIMANDRA.<br>
Hang thee, monster!
</p>

<p class="drama">
ALCIBIADES.<br>
Pardon him, sweet Timandra, for his wits<br>
Are drowned and lost in his calamities.<br>
I have but little gold of late, brave Timon,<br>
The want whereof doth daily make revolt<br>
In my penurious band. I have heard and grieved<br>
How cursed Athens, mindless of thy worth,<br>
Forgetting thy great deeds when neighbour states,<br>
But for thy sword and fortune, trod upon them—
</p>

<p class="drama">
TIMON.<br>
I prithee, beat thy drum and get thee gone.
</p>

<p class="drama">
ALCIBIADES.<br>
I am thy friend and pity thee, dear Timon.
</p>

<p class="drama">
TIMON.<br>
How dost thou pity him whom thou dost trouble?<br>
I had rather be alone.
</p>

<p class="drama">
ALCIBIADES.<br>
Why, fare thee well.<br>
Here is some gold for thee.
</p>

<p class="drama">
TIMON.<br>
Keep it, I cannot eat it.
</p>

<p class="drama">
ALCIBIADES.<br>
When I have laid proud Athens on a heap—
</p>

<p class="drama">
TIMON.<br>
Warr’st thou ’gainst Athens?
</p>

<p class="drama">
ALCIBIADES.<br>
Ay, Timon, and have cause.
</p>

<p class="drama">
TIMON.<br>
The gods confound them all in thy conquest,<br>
And thee after, when thou hast conquered!
</p>

<p class="drama">
ALCIBIADES.<br>
Why me, Timon?
</p>

<p class="drama">
TIMON.<br>
That by killing of villains<br>
Thou wast born to conquer my country.<br>
Put up thy gold. Go on, here’s gold, go on.<br>
Be as a planetary plague when Jove<br>
Will o’er some high-viced city hang his poison<br>
In the sick air. Let not thy sword skip one.<br>
Pity not honoured age for his white beard;<br>
He is an usurer. Strike me the counterfeit matron;<br>
It is her habit only that is honest,<br>
Herself’s a bawd. Let not the virgin’s cheek<br>
Make soft thy trenchant sword, for those milk paps<br>
That through the window-bars bore at men’s eyes,<br>
Are not within the leaf of pity writ,<br>
But set them down horrible traitors. Spare not the babe,<br>
Whose dimpled smiles from fools exhaust their mercy;<br>
Think it a bastard whom the oracle<br>
Hath doubtfully pronounced thy throat shall cut,<br>
And mince it sans remorse. Swear against objects;<br>
Put armour on thine ears and on thine eyes,<br>
Whose proof nor yells of mothers, maids, nor babes,<br>
Nor sight of priests in holy vestments bleeding,<br>
Shall pierce a jot. There’s gold to pay thy soldiers.<br>
Make large confusion and, thy fury spent,<br>
Confounded be thyself! Speak not, be gone.
</p>

<p class="drama">
ALCIBIADES.<br>
Hast thou gold yet? I’ll take the gold thou giv’st me,<br>
Not all thy counsel.
</p>

<p class="drama">
TIMON.<br>
Dost thou or dost thou not, heaven’s curse upon thee!
</p>

<p class="drama">
PHRYNIA AND TIMANDRA.<br>
Give us some gold, good Timon.<br>
Hast thou more?
</p>

<p class="drama">
TIMON.<br>
Enough to make a whore forswear her trade,<br>
And to make whores a bawd. Hold up, you sluts,<br>
Your aprons mountant. You are not oathable,<br>
Although I know you’ll swear—terribly swear<br>
Into strong shudders and to heavenly agues<br>
Th’ immortal gods that hear you. Spare your oaths,<br>
I’ll trust to your conditions. Be whores still,<br>
And he whose pious breath seeks to convert you,<br>
Be strong in whore, allure him, burn him up;<br>
Let your close fire predominate his smoke,<br>
And be no turncoats. Yet may your pains six months,<br>
Be quite contrary. And thatch your poor thin roofs<br>
With burdens of the dead—some that were hanged,<br>
No matter; wear them, betray with them. Whore still,<br>
Paint till a horse may mire upon your face.<br>
A pox of wrinkles!
</p>

<p class="drama">
PHRYNIA AND TIMANDRA.<br>
Well, more gold. What then?<br>
Believe’t that we’ll do anything for gold.
</p>

<p class="drama">
TIMON.<br>
Consumptions sow<br>
In hollow bones of man; strike their sharp shins,<br>
And mar men’s spurring. Crack the lawyer’s voice,<br>
That he may never more false title plead<br>
Nor sound his quillets shrilly. Hoar the flamen,<br>
That scolds against the quality of flesh<br>
And not believes himself. Down with the nose,<br>
Down with it flat, take the bridge quite away<br>
Of him that, his particular to foresee,<br>
Smells from the general weal. Make curled-pate ruffians bald,<br>
And let the unscarred braggarts of the war<br>
Derive some pain from you. Plague all,<br>
That your activity may defeat and quell<br>
The source of all erection. There’s more gold.<br>
Do you damn others, and let this damn you,<br>
And ditches grave you all!
</p>

<p class="drama">
PHRYNIA AND TIMANDRA.<br>
More counsel with more money, bounteous Timon.
</p>

<p class="drama">
TIMON.<br>
More whore, more mischief first! I have given you earnest.
</p>

<p class="drama">
ALCIBIADES.<br>
Strike up the drum towards Athens. Farewell, Timon.<br>
If I thrive well, I’ll visit thee again.
</p>

<p class="drama">
TIMON.<br>
If I hope well, I’ll never see thee more.
</p>

<p class="drama">
ALCIBIADES.<br>
I never did thee harm.
</p>

<p class="drama">
TIMON.<br>
Yes, thou spok’st well of me.
</p>

<p class="drama">
ALCIBIADES.<br>
Call’st thou that harm?
</p>

<p class="drama">
TIMON.<br>
Men daily find it. Get thee away, and take<br>
Thy beagles with thee.
</p>

<p class="drama">
ALCIBIADES.<br>
We but offend him. Strike.
</p>

<p class="right">[<i>Drum beats. Exeunt all but <span class="charname">Timon</span>.</i>]</p>

<p class="drama">
TIMON.<br>
That nature, being sick of man’s unkindness,<br>
Should yet be hungry! [<i>He digs</i>.] Common mother, thou,<br>
Whose womb unmeasurable and infinite breast<br>
Teems and feeds all; whose selfsame mettle<br>
Whereof thy proud child, arrogant man, is puffed,<br>
Engenders the black toad and adder blue,<br>
The gilded newt and eyeless venomed worm,<br>
With all the abhorred births below crisp heaven<br>
Whereon Hyperion’s quickening fire doth shine:<br>
Yield him who all thy human sons doth hate,<br>
From forth thy plenteous bosom, one poor root!<br>
Ensear thy fertile and conceptious womb,<br>
Let it no more bring out ingrateful man.<br>
Go great with tigers, dragons, wolves, and bears;<br>
Teem with new monsters, whom thy upward face<br>
Hath to the marbled mansion all above<br>
Never presented. O, a root, dear thanks!<br>
Dry up thy marrows, vines and plough-torn leas,<br>
Whereof ingrateful man, with liquorish draughts<br>
And morsels unctuous greases his pure mind,<br>
That from it all consideration slips—
</p>

<p class="scenedesc">
Enter <span class="charname">Apemantus</span>.
</p>

<p class="drama">
More man? Plague, plague!</p>

<p class="drama">
APEMANTUS.<br>
I was directed hither. Men report<br>
Thou dost affect my manners and dost use them.
</p>

<p class="drama">
TIMON.<br>
’Tis, then, because thou dost not keep a dog<br>
Whom I would imitate. Consumption catch thee!
</p>

<p class="drama">
APEMANTUS.<br>
This is in thee a nature but infected,<br>
A poor unmanly melancholy sprung<br>
From change of fortune. Why this spade, this place?<br>
This slave-like habit and these looks of care?<br>
Thy flatterers yet wear silk, drink wine, lie soft,<br>
Hug their diseased perfumes, and have forgot<br>
That ever Timon was. Shame not these woods<br>
By putting on the cunning of a carper.<br>
Be thou a flatterer now, and seek to thrive<br>
By that which has undone thee. Hinge thy knee<br>
And let his very breath whom thou’lt observe<br>
Blow off thy cap; praise his most vicious strain,<br>
And call it excellent. Thou wast told thus;<br>
Thou gav’st thine ears, like tapsters that bade welcome,<br>
To knaves and all approachers. ’Tis most just<br>
That thou turn rascal; had’st thou wealth again,<br>
Rascals should have’t. Do not assume my likeness.
</p>

<p class="drama">
TIMON.<br>
Were I like thee, I’d throw away myself.
</p>

<p class="drama">
APEMANTUS.<br>
Thou hast cast away thyself, being like thyself<br>
A madman so long, now a fool. What, think’st<br>
That the bleak air, thy boisterous chamberlain,<br>
Will put thy shirt on warm? Will these mossed trees,<br>
That have outlived the eagle, page thy heels<br>
And skip when thou point’st out? Will the cold brook,<br>
Candied with ice, caudle thy morning taste<br>
To cure thy o’ernight’s surfeit? Call the creatures<br>
Whose naked natures live in all the spite<br>
Of wreakful heaven, whose bare unhoused trunks,<br>
To the conflicting elements exposed,<br>
Answer mere nature, bid them flatter thee.<br>
O, thou shalt find—
</p>

<p class="drama">
TIMON.<br>
A fool of thee. Depart.
</p>

<p class="drama">
APEMANTUS.<br>
I love thee better now than e’er I did.
</p>

<p class="drama">
TIMON.<br>
I hate thee worse.
</p>

<p class="drama">
APEMANTUS.<br>
Why?
</p>

<p class="drama">
TIMON.<br>
Thou flatter’st misery.
</p>

<p class="drama">
APEMANTUS.<br>
I flatter not, but say thou art a caitiff.
</p>

<p class="drama">
TIMON.<br>
Why dost thou seek me out?
</p>

<p class="drama">
APEMANTUS.<br>
To vex thee.
</p>

<p class="drama">
TIMON.<br>
Always a villain’s office or a fool’s.<br>
Dost please thyself in’t?
</p>

<p class="drama">
APEMANTUS.<br>
Ay.
</p>

<p class="drama">
TIMON.<br>
What, a knave too?
</p>

<p class="drama">
APEMANTUS.<br>
If thou didst put this sour cold habit on<br>
To castigate thy pride, ’twere well; but thou<br>
Dost it enforcedly. Thou’dst courtier be again<br>
Wert thou not beggar. Willing misery<br>
Outlives incertain pomp, is crowned before;<br>
The one is filling still, never complete,<br>
The other, at high wish. Best state, contentless,<br>
Hath a distracted and most wretched being,<br>
Worse than the worst, content.<br>
Thou shouldst desire to die, being miserable.
</p>

<p class="drama">
TIMON.<br>
Not by his breath that is more miserable.<br>
Thou art a slave whom Fortune’s tender arm<br>
With favour never clasped, but bred a dog.<br>
Hadst thou, like us from our first swath, proceeded<br>
The sweet degrees that this brief world affords<br>
To such as may the passive drugs of it<br>
Freely command, thou wouldst have plunged thyself<br>
In general riot, melted down thy youth<br>
In different beds of lust and never learned<br>
The icy precepts of respect, but followed<br>
The sugared game before thee. But myself—<br>
Who had the world as my confectionary,<br>
The mouths, the tongues, the eyes and hearts of men<br>
At duty, more than I could frame employment,<br>
That numberless upon me stuck as leaves<br>
Do on the oak, have with one winter’s brush<br>
Fell from their boughs and left me open, bare<br>
For every storm that blows—I to bear this,<br>
That never knew but better, is some burden.<br>
Thy nature did commence in sufferance, time<br>
Hath made thee hard in’t. Why shouldst thou hate men?<br>
They never flattered thee. What hast thou given?<br>
If thou wilt curse, thy father, that poor rag,<br>
Must be thy subject, who in spite put stuff<br>
To some she-beggar and compounded thee<br>
Poor rogue hereditary. Hence, be gone!<br>
If thou hadst not been born the worst of men,<br>
Thou hadst been a knave and flatterer.
</p>

<p class="drama">
APEMANTUS.<br>
Art thou proud yet?
</p>

<p class="drama">
TIMON.<br>
Ay, that I am not thee.
</p>

<p class="drama">
APEMANTUS.<br>
I, that I was no prodigal.
</p>

<p class="drama">
TIMON.<br>
I, that I am one now.<br>
Were all the wealth I have shut up in thee,<br>
I’d give thee leave to hang it. Get thee gone.<br>
That the whole life of Athens were in this!<br>
Thus would I eat it.
</p>

<p class="right">[<i>Eats a root.</i>]</p>

<p class="drama">
APEMANTUS.<br>
Here, I will mend thy feast.
</p>

<p class="drama">
TIMON.<br>
First mend my company, take away thyself.
</p>

<p class="drama">
APEMANTUS.<br>
So I shall mend mine own, by th’ lack of thine.
</p>

<p class="drama">
TIMON.<br>
’Tis not well mended so, it is but botched.<br>
If not, I would it were.
</p>

<p class="drama">
APEMANTUS.<br>
What wouldst thou have to Athens?
</p>

<p class="drama">
TIMON.<br>
Thee thither in a whirlwind. If thou wilt,<br>
Tell them there I have gold. Look, so I have.
</p>

<p class="drama">
APEMANTUS.<br>
Here is no use for gold.
</p>

<p class="drama">
TIMON.<br>
The best and truest,<br>
For here it sleeps and does no hired harm.
</p>

<p class="drama">
APEMANTUS.<br>
Where liest a-nights, Timon?
</p>

<p class="drama">
TIMON.<br>
Under that’s above me. Where feed’st thou a-days, Apemantus?
</p>

<p class="drama">
APEMANTUS.<br>
Where my stomach finds meat, or rather where I eat it.
</p>

<p class="drama">
TIMON.<br>
Would poison were obedient and knew my mind!
</p>

<p class="drama">
APEMANTUS.<br>
Where wouldst thou send it?
</p>

<p class="drama">
TIMON.<br>
To sauce thy dishes.
</p>

<p class="drama">
APEMANTUS.<br>
The middle of humanity thou never knewest, but the extremity of both ends. When
thou wast in thy gilt and thy perfume, they mocked thee for too much curiosity;
in thy rags thou know’st none, but art despised for the contrary. There’s a
medlar for thee. Eat it.
</p>

<p class="drama">
TIMON.<br>
On what I hate I feed not.
</p>

<p class="drama">
APEMANTUS.<br>
Dost hate a medlar?
</p>

<p class="drama">
TIMON.<br>
Ay, though it look like thee.
</p>

<p class="drama">
APEMANTUS.<br>
An thou’dst hated medlars sooner, thou shouldst have loved thyself better
now. What man didst thou ever know unthrift that was beloved after his
means?</p>

<p class="drama">
TIMON.<br>
Who, without those means thou talk’st of, didst thou ever know beloved?</p>

<p class="drama">
APEMANTUS.<br>
Myself.
</p>

<p class="drama">
TIMON.<br>
I understand thee. Thou hadst some means to keep a dog.
</p>

<p class="drama">
APEMANTUS.<br>
What things in the world canst thou nearest compare to thy flatterers?</p>

<p class="drama">
TIMON.<br>
Women nearest; but men—men are the things themselves. What wouldst thou do
with the world, Apemantus, if it lay in thy power?</p>

<p class="drama">
APEMANTUS.<br>
Give it the beasts, to be rid of the men.
</p>

<p class="drama">
TIMON.<br>
Wouldst thou have thyself fall in the confusion of men and remain a beast with
the beasts?
</p>

<p class="drama">
APEMANTUS.<br>
Ay, Timon.
</p>

<p class="drama">
TIMON.<br>
A beastly ambition, which the gods grant thee t’ attain to. If thou wert the
lion, the fox would beguile thee; if thou wert the lamb, the fox would eat
thee; if thou wert the fox, the lion would suspect thee when peradventure
thou wert accused by the ass; if thou wert the ass, thy dulness would torment
thee, and still thou lived’st but as a breakfast to the wolf; if thou wert the
wolf, thy greediness would afflict thee, and oft thou shouldst hazard thy life
for thy dinner. Wert thou the unicorn, pride and wrath would confound thee and
make thine own self the conquest of thy fury; wert thou a bear, thou wouldst be
killed by the horse; wert thou a horse, thou wouldst be seized by the leopard;
wert thou a leopard, thou wert germane to the lion, and the spots of thy kindred
were jurors on thy life. All thy safety were remotion, and thy defence absence.
What beast couldst thou be that were not subject to a beast? And what beast art
thou already that seest not thy loss in transformation!
</p>

<p class="drama">
APEMANTUS.<br>
If thou couldst please me with speaking to me, thou mightst have hit upon it
here. The commonwealth of Athens is become a forest of beasts.</p>

<p class="drama">
TIMON.<br>
How has the ass broke the wall, that thou art out of the city?</p>

<p class="drama">
APEMANTUS.<br>
Yonder comes a poet and a painter. The plague of company light upon thee! I
will fear to catch it, and give way. When I know not what else to do,
I’ll see thee again.</p>

<p class="drama">
TIMON.<br>
When there is nothing living but thee, thou shalt be welcome. I had rather be a
beggar’s dog than Apemantus.</p>

<p class="drama">
APEMANTUS.<br>
Thou art the cap of all the fools alive.
</p>

<p class="drama">
TIMON.<br>
Would thou wert clean enough to spit upon!
</p>

<p class="drama">
APEMANTUS.<br>
A plague on thee! Thou art too bad to curse.
</p>

<p class="drama">
TIMON.<br>
All villains that do stand by thee are pure.
</p>

<p class="drama">
APEMANTUS.<br>
There is no leprosy but what thou speak’st.
</p>

<p class="drama">
TIMON.<br>
If I name thee,<br>
I’ll beat thee, but I should infect my hands.
</p>

<p class="drama">
APEMANTUS.<br>
I would my tongue could rot them off!
</p>

<p class="drama">
TIMON.<br>
Away, thou issue of a mangy dog!<br>
Choler does kill me that thou art alive.<br>
I swoon to see thee.
</p>

<p class="drama">
APEMANTUS.<br>
Would thou wouldst burst!
</p>

<p class="drama">
TIMON.<br>
Away, thou tedious rogue!<br>
I am sorry I shall lose a stone by thee.
</p>

<p class="right">[<i>Throws a stone at him.</i>]</p>

<p class="drama">
APEMANTUS.<br>
Beast!
</p>

<p class="drama">
TIMON.<br>
Slave!
</p>

<p class="drama">
APEMANTUS.<br>
Toad!
</p>

<p class="drama">
TIMON.<br>
Rogue, rogue, rogue!<br>
I am sick of this false world, and will love nought<br>
But even the mere necessities upon’t.<br>
Then, Timon, presently prepare thy grave.<br>
Lie where the light foam of the sea may beat<br>
Thy gravestone daily. Make thine epitaph,<br>
That death in me at others’ lives may laugh.<br>
[<i>To the gold.</i>] O thou sweet king-killer and dear divorce<br>
’Twixt natural son and sire; thou bright defiler<br>
Of Hymen’s purest bed, thou valiant Mars;<br>
Thou ever young, fresh, loved, and delicate wooer,<br>
Whose blush doth thaw the consecrated snow<br>
That lies on Dian’s lap; thou visible god,<br>
That solder’st close impossibilities<br>
And mak’st them kiss, that speak’st with every tongue<br>
To every purpose! O thou touch of hearts,<br>
Think thy slave man rebels, and by thy virtue<br>
Set them into confounding odds, that beasts<br>
May have the world in empire!
</p>

<p class="drama">
APEMANTUS.<br>
Would ’twere so!<br>
But not till I am dead. I’ll say thou’st gold;<br>
Thou wilt be thronged to shortly.
</p>

<p class="drama">
TIMON.<br>
Thronged to?
</p>

<p class="drama">
APEMANTUS.<br>
Ay.
</p>

<p class="drama">
TIMON.<br>
Thy back, I prithee.
</p>

<p class="drama">
APEMANTUS.<br>
Live and love thy misery.
</p>

<p class="drama">
TIMON.<br>
Long live so, and so die! I am quit.
</p>

<p class="drama">
APEMANTUS.<br>
More things like men. Eat, Timon, and abhor them.
</p>

<p class="right">[<i>Exit <span class="charname">Apemantus</span>.</i>]</p>

<p class="scenedesc">
Enter <span class="charname">Banditti</span>.
</p>

<p class="drama">
FIRST BANDIT.<br>
Where should he have this gold? It is some poor fragment, some slender ort of
his remainder. The mere want of gold and the falling-from of his friends
drove him into this melancholy.</p>

<p class="drama">
SECOND BANDIT.<br>
It is noised he hath a mass of treasure.
</p>

<p class="drama">
THIRD BANDIT.<br>
Let us make the assay upon him. If he care not for’t, he will supply us
easily; if he covetously reserve it, how shall’s get it?</p>

<p class="drama">
SECOND BANDIT.<br>
True, for he bears it not about him. ’Tis hid.
</p>

<p class="drama">
FIRST BANDIT.<br>
Is not this he?
</p>

<p class="drama">
BANDITTI.<br>
Where?
</p>

<p class="drama">
SECOND BANDIT.<br>
’Tis his description.
</p>

<p class="drama">
THIRD BANDIT.<br>
He; I know him.
</p>

<p class="drama">
BANDITTI.<br>
Save thee, Timon!
</p>

<p class="drama">
TIMON.<br>
Now, thieves?
</p>

<p class="drama">
BANDITTI.<br>
Soldiers, not thieves.
</p>

<p class="drama">
TIMON.<br>
Both too, and women’s sons.
</p>

<p class="drama">
BANDITTI.<br>
We are not thieves, but men that much do want.
</p>

<p class="drama">
TIMON.<br>
Your greatest want is, you want much of meat.<br>
Why should you want? Behold, the earth hath roots,<br>
Within this mile break forth a hundred springs,<br>
The oaks bear mast, the briars scarlet hips,<br>
The bounteous housewife Nature on each bush<br>
Lays her full mess before you. Want? Why want?
</p>

<p class="drama">
FIRST BANDIT.<br>
We cannot live on grass, on berries, water,<br>
As beasts and birds and fishes.
</p>

<p class="drama">
TIMON.<br>
Nor on the beasts themselves, the birds, and fishes;<br>
You must eat men. Yet thanks I must you con<br>
That you are thieves professed, that you work not<br>
In holier shapes, for there is boundless theft<br>
In limited professions. Rascal thieves,<br>
Here’s gold. Go, suck the subtle blood o’ th’ grape<br>
Till the high fever seethe your blood to froth,<br>
And so scape hanging. Trust not the physician;<br>
His antidotes are poison, and he slays<br>
More than you rob. Take wealth and lives together,<br>
Do villainy, do, since you protest to do’t,<br>
Like workmen. I’ll example you with thievery.<br>
The sun’s a thief and with his great attraction<br>
Robs the vast sea; the moon’s an arrant thief,<br>
And her pale fire she snatches from the sun;<br>
The sea’s a thief, whose liquid surge resolves<br>
The moon into salt tears; the earth’s a thief,<br>
That feeds and breeds by a composture stol’n<br>
From general excrement. Each thing’s a thief.<br>
The laws, your curb and whip, in their rough power<br>
Has unchecked theft. Love not yourselves; away!<br>
Rob one another. There’s more gold. Cut throats,<br>
All that you meet are thieves. To Athens go,<br>
Break open shops, nothing can you steal<br>
But thieves do lose it. Steal no less for this I give you,<br>
And gold confound you howsoe’er! Amen.
</p>

<p class="drama">
THIRD BANDIT.<br>
Has almost charmed me from my profession by persuading me to it.</p>

<p class="drama">
FIRST BANDIT.<br>
’Tis in the malice of mankind that he thus advises us, not to have us
thrive in our mystery.</p>

<p class="drama">
SECOND BANDIT.<br>
I’ll believe him as an enemy and give over my trade.
</p>

<p class="drama">
FIRST BANDIT.<br>
Let us first see peace in Athens. There is no time so miserable but a man may
be true.</p>

<p class="right">[<i>Exeunt <span class="charname">Banditti</span>.</i>]</p>

<p class="scenedesc">
Enter <span class="charname">Flavius</span>.
</p>

<p class="drama">
FLAVIUS.<br>
O you gods!<br>
Is yond despised and ruinous man my lord?<br>
Full of decay and failing? O monument<br>
And wonder of good deeds evilly bestowed!<br>
What an alteration of honour has desperate want made!<br>
What viler thing upon the earth than friends<br>
Who can bring noblest minds to basest ends!<br>
How rarely does it meet with this time’s guise,<br>
When man was wished to love his enemies!<br>
Grant I may ever love, and rather woo<br>
Those that would mischief me than those that do!<br>
He has caught me in his eye. I will present<br>
My honest grief unto him and as my lord<br>
Still serve him with my life.—My dearest master!
</p>

<p class="drama">
TIMON.<br>
Away! What art thou?
</p>

<p class="drama">
FLAVIUS.<br>
Have you forgot me, sir?
</p>

<p class="drama">
TIMON.<br>
Why dost ask that? I have forgot all men.<br>
Then, if thou grant’st thou’rt a man, I have forgot thee.
</p>

<p class="drama">
FLAVIUS.<br>
An honest poor servant of yours.
</p>

<p class="drama">
TIMON.<br>
Then I know thee not.<br>
I never had honest man about me. I; all<br>
I kept were knaves to serve in meat to villains.
</p>

<p class="drama">
FLAVIUS.<br>
The gods are witness,<br>
Ne’er did poor steward wear a truer grief<br>
For his undone lord than mine eyes for you.
</p>

<p class="drama">
TIMON.<br>
What, dost thou weep? Come nearer then. I love thee<br>
Because thou art a woman and disclaim’st<br>
Flinty mankind, whose eyes do never give<br>
But thorough lust and laughter. Pity’s sleeping.<br>
Strange times that weep with laughing, not with weeping!
</p>

<p class="drama">
FLAVIUS.<br>
I beg of you to know me, good my lord,<br>
T’ accept my grief, and whilst this poor wealth lasts<br>
To entertain me as your steward still.
</p>

<p class="drama">
TIMON.<br>
Had I a steward<br>
So true, so just, and now so comfortable?<br>
It almost turns my dangerous nature mild.<br>
Let me behold thy face. Surely this man<br>
Was born of woman.<br>
Forgive my general and exceptless rashness,<br>
You perpetual sober gods! I do proclaim<br>
One honest man, mistake me not, but one;<br>
No more, I pray, and he’s a steward.<br>
How fain would I have hated all mankind,<br>
And thou redeem’st thyself. But all, save thee,<br>
I fell with curses.<br>
Methinks thou art more honest now than wise,<br>
For by oppressing and betraying me<br>
Thou mightst have sooner got another service;<br>
For many so arrive at second masters<br>
Upon their first lord’s neck. But tell me true—<br>
For I must ever doubt, though ne’er so sure—<br>
Is not thy kindness subtle, covetous,<br>
A usuring kindness and as rich men deal gifts,<br>
Expecting in return twenty for one?
</p>

<p class="drama">
FLAVIUS.<br>
No, my most worthy master, in whose breast<br>
Doubt and suspect, alas, are placed too late.<br>
You should have feared false times when you did feast,<br>
Suspect still comes where an estate is least.<br>
That which I show, heaven knows, is merely love,<br>
Duty and zeal to your unmatched mind,<br>
Care of your food and living. And believe it,<br>
My most honoured lord,<br>
For any benefit that points to me,<br>
Either in hope or present, I’d exchange<br>
For this one wish, that you had power and wealth<br>
To requite me by making rich yourself.
</p>

<p class="drama">
TIMON.<br>
Look thee, ’tis so! Thou singly honest man,<br>
Here, take. The gods out of my misery<br>
Have sent thee treasure. Go, live rich and happy,<br>
But thus conditioned: thou shalt build from men;<br>
Hate all, curse all, show charity to none,<br>
But let the famished flesh slide from the bone<br>
Ere thou relieve the beggar; give to dogs<br>
What thou deniest to men; let prisons swallow ’em,<br>
Debts wither ’em to nothing; be men like blasted woods,<br>
And may diseases lick up their false bloods!<br>
And so farewell and thrive.
</p>

<p class="drama">
FLAVIUS.<br>
O, let me stay<br>
And comfort you, my master.
</p>

<p class="drama">
TIMON.<br>
If thou hat’st curses,<br>
Stay not. Fly whilst thou’rt blest and free.<br>
Ne’er see thou man, and let me ne’er see thee.
</p>

<p class="right">[<i>Exeunt severally.</i>]</p>

