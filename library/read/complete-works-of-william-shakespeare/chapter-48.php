<h2> <b>ACT I</b></h2>

<h3> <a id="sceneI_9.1"></a><b>SCENE I. London. A Room in the Palace.</b></h3>

<p class="scenedesc">Enter the <span class="charname">King, Lord John of
Lancaster, Earl of Westmoreland</span> with others.
</p>

<p class="drama">
KING.<br>
So shaken as we are, so wan with care,<br>
Find we a time for frighted peace to pant,<br>
And breathe short-winded accents of new broils<br>
To be commenced in strands afar remote.<br>
No more the thirsty entrance of this soil<br>
Shall daub her lips with her own children’s blood,<br>
No more shall trenching war channel her fields,<br>
Nor bruise her flow’rets with the armed hoofs<br>
Of hostile paces: those opposed eyes,<br>
Which, like the meteors of a troubled heaven,<br>
All of one nature, of one substance bred,<br>
Did lately meet in the intestine shock<br>
And furious close of civil butchery,<br>
Shall now, in mutual well-beseeming ranks,<br>
March all one way, and be no more opposed<br>
Against acquaintance, kindred, and allies.<br>
The edge of war, like an ill-sheathed knife,<br>
No more shall cut his master. Therefore, friends,<br>
As far as to the sepulchre of Christ—<br>
Whose soldier now, under whose blessed cross<br>
We are impressed and engaged to fight—<br>
Forthwith a power of English shall we levy,<br>
Whose arms were molded in their mothers’ womb<br>
To chase these pagans in those holy fields<br>
Over whose acres walked those blessed feet<br>
Which fourteen hundred years ago were nailed<br>
For our advantage on the bitter cross.<br>
But this our purpose now is twelve month old,<br>
And bootless ’tis to tell you we will go;<br>
Therefore we meet not now. Then let me hear<br>
Of you, my gentle cousin Westmoreland,<br>
What yesternight our Council did decree<br>
In forwarding this dear expedience.
</p>

<p class="drama">
WESTMORELAND.<br>
My liege, this haste was hot in question,<br>
And many limits of the charge set down<br>
But yesternight, when all athwart there came<br>
A post from Wales loaden with heavy news,<br>
Whose worst was that the noble Mortimer,<br>
Leading the men of Herefordshire to fight<br>
Against the irregular and wild Glendower,<br>
Was by the rude hands of that Welshman taken,<br>
A thousand of his people butchered,<br>
Upon whose dead corpse there was such misuse,<br>
Such beastly shameless transformation,<br>
By those Welshwomen done, as may not be<br>
Without much shame retold or spoken of.
</p>

<p class="drama">
KING.<br>
It seems then that the tidings of this broil<br>
Brake off our business for the Holy Land.
</p>

<p class="drama">
WESTMORELAND.<br>
This, matched with other did, my gracious lord,<br>
For more uneven and unwelcome news<br>
Came from the North, and thus it did import:<br>
On Holy-rood day the gallant Hotspur there,<br>
Young Harry Percy, and brave Archibald,<br>
That ever-valiant and approved Scot,<br>
At Holmedon met, where they did spend<br>
A sad and bloody hour;<br>
As by discharge of their artillery,<br>
And shape of likelihood, the news was told;<br>
For he that brought them, in the very heat<br>
And pride of their contention did take horse,<br>
Uncertain of the issue any way.
</p>

<p class="drama">
KING.<br>
Here is a dear and true-industrious friend,<br>
Sir Walter Blunt, new lighted from his horse,<br>
Stained with the variation of each soil<br>
Betwixt that Holmedon and this seat of ours;<br>
And he hath brought us smooth and welcome news.<br>
The Earl of Douglas is discomfited;<br>
Ten thousand bold Scots, two-and-twenty knights,<br>
Balked in their own blood, did Sir Walter see<br>
On Holmedon’s plains; of prisoners Hotspur took<br>
Mordake, Earl of Fife and eldest son<br>
To beaten Douglas, and the Earl of Athol,<br>
Of Murray, Angus, and Menteith.<br>
And is not this an honourable spoil,<br>
A gallant prize? Ha, cousin, is it not?
</p>

<p class="drama">
WESTMORELAND.<br>
In faith, it is a conquest for a prince to boast of.
</p>

<p class="drama">
KING.<br>
Yea, there thou mak’st me sad, and mak’st me sin<br>
In envy that my Lord Northumberland<br>
Should be the father to so blest a son,<br>
A son who is the theme of honour’s tongue,<br>
Amongst a grove the very straightest plant,<br>
Who is sweet Fortune’s minion and her pride;<br>
Whilst I, by looking on the praise of him,<br>
See riot and dishonour stain the brow<br>
Of my young Harry. O, that it could be proved<br>
That some night-tripping fairy had exchanged<br>
In cradle-clothes our children where they lay,<br>
And called mine Percy, his Plantagenet!<br>
Then would I have his Harry, and he mine:<br>
But let him from my thoughts. What think you, coz,<br>
Of this young Percy’s pride? The prisoners,<br>
Which he in this adventure hath surprised<br>
To his own use he keeps, and sends me word<br>
I shall have none but Mordake, Earl of Fife.
</p>

<p class="drama">
WESTMORELAND.<br>
This is his uncle’s teaching, this is Worcester,<br>
Malevolent to you in all aspects,<br>
Which makes him prune himself, and bristle up<br>
The crest of youth against your dignity.
</p>

<p class="drama">
KING.<br>
But I have sent for him to answer this;<br>
And for this cause awhile we must neglect<br>
Our holy purpose to Jerusalem.<br>
Cousin, on Wednesday next our Council we<br>
Will hold at Windsor, so inform the lords:<br>
But come yourself with speed to us again,<br>
For more is to be said and to be done<br>
Than out of anger can be uttered.
</p>

<p class="drama">
WESTMORELAND.<br>
I will, my liege.
</p>

<p class="right">[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneI_9.2"></a><b>SCENE II. The same. An Apartment of Prince Henry’s.</b></h3>

<p class="scenedesc">Enter <span class="charname">Prince Henry</span> and
<span class="charname">Sir John Falstaff</span>.
</p>

<p class="drama">
FALSTAFF.<br>
Now, Hal, what time of day is it, lad?
</p>

<p class="drama">
PRINCE.<br>
Thou art so fat-witted, with drinking of old sack, and unbuttoning thee after
supper, and sleeping upon benches after noon, that thou hast forgotten to
demand that truly which thou wouldst truly know. What a devil hast thou to do
with the time of the day? Unless hours were cups of sack, and minutes capons,
and clocks the tongues of bawds, and dials the signs of leaping-houses, and the
blessed sun himself a fair hot wench in flame-coloured taffeta, I see no reason
why thou shouldst be so superfluous to demand the time of the day.
</p>

<p class="drama">
FALSTAFF.<br>
Indeed, you come near me now, Hal, for we that take purses go by the moon and
the seven stars, and not by Phœbus, he, that wand’ring knight so fair.
And I prithee, sweet wag, when thou art king, as God save thy
Grace—Majesty I should say, for grace thou wilt have none—
</p>

<p class="drama">
PRINCE.<br>
What, none?
</p>

<p class="drama">
FALSTAFF.<br>
No, by my troth, not so much as will serve to be prologue to an egg and butter.
</p>

<p class="drama">
PRINCE.<br>
Well, how then? Come, roundly, roundly.
</p>

<p class="drama">
FALSTAFF.<br>
Marry then, sweet wag, when thou art king, let not us that are squires of the
night’s body be called thieves of the day’s beauty: let us be
Diana’s foresters, gentlemen of the shade, minions of the moon; and let
men say we be men of good government, being governed, as the sea is, by our
noble and chaste mistress the moon, under whose countenance we steal.
</p>

<p class="drama">
PRINCE.<br>
Thou sayest well, and it holds well too, for the fortune of us that are the
moon’s men doth ebb and flow like the sea, being governed, as the sea is,
by the moon. As for proof now: a purse of gold most resolutely snatched on
Monday night, and most dissolutely spent on Tuesday morning, got with swearing
“Lay by” and spent with crying “Bring in”; now in as
low an ebb as the foot of the ladder, and by and by in as high a flow as the
ridge of the gallows.
</p>

<p class="drama">
FALSTAFF.<br>
By the Lord, thou say’st true, lad. And is not my hostess of the tavern a
most sweet wench?
</p>

<p class="drama">
PRINCE.<br>
As the honey of Hybla, my old lad of the castle. And is not a buff jerkin a
most sweet robe of durance?
</p>

<p class="drama">
FALSTAFF.<br>
How now, how now, mad wag? What, in thy quips and thy quiddities? What a plague
have I to do with a buff jerkin?
</p>

<p class="drama">
PRINCE.<br>
Why, what a pox have I to do with my hostess of the tavern?
</p>

<p class="drama">
FALSTAFF.<br>
Well, thou hast called her to a reckoning many a time and oft.
</p>

<p class="drama">
PRINCE.<br>
Did I ever call for thee to pay thy part?
</p>

<p class="drama">
FALSTAFF.<br>
No, I’ll give thee thy due, thou hast paid all there.
</p>

<p class="drama">
PRINCE.<br>
Yea, and elsewhere, so far as my coin would stretch, and where it would not, I
have used my credit.
</p>

<p class="drama">
FALSTAFF.<br>
Yea, and so used it that were it not here apparent that thou art heir
apparent—But I prithee sweet wag, shall there be gallows standing
in England when thou art king? And resolution thus fubbed as it is with
the rusty curb of old father Antic the law? Do not thou, when thou art king,
hang a thief.
</p>

<p class="drama">
PRINCE.<br>
No, thou shalt.
</p>

<p class="drama">
FALSTAFF.<br>
Shall I? O rare! By the Lord, I’ll be a brave judge.
</p>

<p class="drama">
PRINCE.<br>
Thou judgest false already, I mean thou shalt have the hanging of the thieves,
and so become a rare hangman.
</p>

<p class="drama">
FALSTAFF.<br>
Well, Hal, well; and in some sort it jumps with my humour, as well as waiting
in the court, I can tell you.
</p>

<p class="drama">
PRINCE.<br>
For obtaining of suits?
</p>

<p class="drama">
FALSTAFF.<br>
Yea, for obtaining of suits, whereof the hangman hath no lean wardrobe.
’Sblood, I am as melancholy as a gib cat or a lugged bear.
</p>

<p class="drama">
PRINCE.<br>
Or an old lion, or a lover’s lute.
</p>

<p class="drama">
FALSTAFF.<br>
Yea, or the drone of a Lincolnshire bagpipe.
</p>

<p class="drama">
PRINCE.<br>
What sayest thou to a hare, or the melancholy of Moor-ditch?
</p>

<p class="drama">
FALSTAFF.<br>
Thou hast the most unsavoury similes, and art indeed the most comparative,
rascalliest, sweet young prince. But, Hal, I prithee trouble me no more with
vanity. I would to God thou and I knew where a commodity of good names were to
be bought. An old lord of the Council rated me the other day in the street
about you, sir, but I marked him not, and yet he talked very wisely, but I
regarded him not, and yet he talked wisely, and in the street too.
</p>

<p class="drama">
PRINCE.<br>
Thou didst well, for wisdom cries out in the streets and no man regards it.
</p>

<p class="drama">
FALSTAFF.<br>
O, thou hast damnable iteration, and art indeed able to corrupt a saint. Thou
hast done much harm upon me, Hal, God forgive thee for it. Before I knew thee,
Hal, I knew nothing, and now am I, if a man should speak truly, little better
than one of the wicked. I must give over this life, and I will give it over. By
the Lord, an I do not, I am a villain. I’ll be damned for never a
king’s son in Christendom.
</p>

<p class="drama">
PRINCE.<br>
Where shall we take a purse tomorrow, Jack?
</p>

<p class="drama">
FALSTAFF.<br>
Zounds, where thou wilt, lad, I’ll make one. An I do not, call me
villain and baffle me.
</p>

<p class="drama">
PRINCE.<br>
I see a good amendment of life in thee, from praying to purse-taking.
</p>

<p class="drama">
FALSTAFF.<br>
Why, Hal, ’tis my vocation, Hal, ’tis no sin for a man to labour in
his vocation.
</p>

<p class="scenedesc">Enter <span class="charname">Poins</span>.
</p>

<p class="drama">
Poins!—Now shall we know if Gadshill have set a match. O, if men were to
be saved by merit, what hole in hell were hot enough for him? This is the most
omnipotent villain that ever cried “Stand!” to a true man.
</p>

<p class="drama">
PRINCE.<br>
Good morrow, Ned.
</p>

<p class="drama">
POINS.<br>
Good morrow, sweet Hal.—What says Monsieur Remorse? What says Sir John
Sack-and-sugar? Jack, how agrees the devil and thee about thy soul, that thou
soldest him on Good Friday last for a cup of Madeira and a cold capon’s
leg?
</p>

<p class="drama">
PRINCE.<br>
Sir John stands to his word, the devil shall have his bargain, for he was
never yet a breaker of proverbs. He will give the devil his due.
</p>

<p class="drama">
POINS.<br>
Then art thou damned for keeping thy word with the devil.
</p>

<p class="drama">
PRINCE.<br>
Else he had been damned for cozening the devil.
</p>

<p class="drama">
POINS.<br>
But, my lads, my lads, tomorrow morning, by four o’clock early at
Gad’s Hill, there are pilgrims going to Canterbury with rich offerings,
and traders riding to London with fat purses. I have visards for you all; you
have horses for yourselves. Gadshill lies tonight in Rochester. I have bespoke
supper tomorrow night in Eastcheap. We may do it as secure as sleep. If you
will go, I will stuff your purses full of crowns. If you will not, tarry at
home and be hanged.
</p>

<p class="drama">
FALSTAFF.<br>
Hear ye, Yedward, if I tarry at home and go not, I’ll hang you for going.
</p>

<p class="drama">
POINS.<br>
You will, chops?
</p>

<p class="drama">
FALSTAFF.<br>
Hal, wilt thou make one?
</p>

<p class="drama">
PRINCE.<br>
Who, I rob? I a thief? Not I, by my faith.
</p>

<p class="drama">
FALSTAFF.<br>
There’s neither honesty, manhood, nor good fellowship in thee, nor thou
cam’st not of the blood royal, if thou darest not stand for ten shillings.
</p>

<p class="drama">
PRINCE.<br>
Well then, once in my days I’ll be a madcap.
</p>

<p class="drama">
FALSTAFF.<br>
Why, that’s well said.
</p>

<p class="drama">
PRINCE.<br>
Well, come what will, I’ll tarry at home.
</p>

<p class="drama">
FALSTAFF.<br>
By the Lord, I’ll be a traitor then, when thou art king.
</p>

<p class="drama">
PRINCE.<br>
I care not.
</p>

<p class="drama">
POINS.<br>
Sir John, I prithee, leave the Prince and me alone. I will lay him down
such reasons for this adventure, that he shall go.
</p>

<p class="drama">
FALSTAFF.<br>
Well, God give thee the spirit of persuasion, and him the ears of profiting,
that what thou speakest may move, and what he hears may be believed, that the
true prince may, for recreation sake, prove a false thief, for the poor abuses
of the time want countenance. Farewell, you shall find me in Eastcheap.
</p>

<p class="drama">
PRINCE.<br>
Farewell, thou latter spring! Farewell, All-hallown summer!
</p>

<p class="right">[<i>Exit <span class="charname">Falstaff</span>.</i>]
</p>

<p class="drama">
POINS.<br>
Now, my good sweet honey lord, ride with us tomorrow. I have a jest to execute
that I cannot manage alone. Falstaff, Bardolph, Peto, and Gadshill shall rob
those men that we have already waylaid. Yourself and I will not be there. And
when they have the booty, if you and I do not rob them, cut this head off from
my shoulders.
</p>

<p class="drama">
PRINCE.<br>
But how shall we part with them in setting forth?
</p>

<p class="drama">
POINS.<br>
Why, we will set forth before or after them, and appoint them a place of
meeting, wherein it is at our pleasure to fail; and then will they adventure
upon the exploit themselves, which they shall have no sooner achieved but
we’ll set upon them.
</p>

<p class="drama">
PRINCE.<br>
Yea, but ’tis like that they will know us by our horses, by our habits,
and by every other appointment, to be ourselves.
</p>

<p class="drama">
POINS.<br>
Tut, our horses they shall not see, I’ll tie them in the wood; our
visards we will change after we leave them; and, sirrah, I have cases of
buckram for the nonce, to immask our noted outward garments.
</p>

<p class="drama">
PRINCE.<br>
Yea, but I doubt they will be too hard for us.
</p>

<p class="drama">
POINS.<br>
Well, for two of them, I know them to be as true-bred cowards as ever
turned back; and for the third, if he fight longer than he sees reason,
I’ll forswear arms. The virtue of this jest will be the incomprehensible
lies that this same fat rogue will tell us when we meet at supper: how thirty
at least he fought with, what wards, what blows, what extremities he endured;
and in the reproof of this lives the jest.
</p>

<p class="drama">
PRINCE.<br>
Well, I’ll go with thee. Provide us all things necessary and meet me
tomorrow night in Eastcheap; there I’ll sup. Farewell.
</p>

<p class="drama">
POINS.<br>
Farewell, my lord.
</p>

<p class="right">[<i>Exit.</i>]
</p>

<p class="drama">
PRINCE.<br>
I know you all, and will awhile uphold<br>
The unyok’d humour of your idleness.<br>
Yet herein will I imitate the sun,<br>
Who doth permit the base contagious clouds<br>
To smother up his beauty from the world,<br>
That, when he please again to be himself,<br>
Being wanted, he may be more wonder’d at,<br>
By breaking through the foul and ugly mists<br>
Of vapours that did seem to strangle him.<br>
If all the year were playing holidays,<br>
To sport would be as tedious as to work;<br>
But, when they seldom come, they wish’d-for come,<br>
And nothing pleaseth but rare accidents.<br>
So when this loose behaviour I throw off,<br>
And pay the debt I never promised,<br>
By how much better than my word I am,<br>
By so much shall I falsify men’s hopes;<br>
And, like bright metal on a sullen ground,<br>
My reformation, glitt’ring o’er my fault,<br>
Shall show more goodly and attract more eyes<br>
Than that which hath no foil to set it off.<br>
I’ll so offend, to make offence a skill,<br>
Redeeming time, when men think least I will.
</p>

<p class="right">[<i>Exit.</i>]
</p>

<h3> <a id="sceneI_9.3"></a><b>SCENE III. The Same. A Room in the Palace.</b></h3>

<p class="scenedesc">Enter <span class="charname">King Henry, Northumberland, Worcester, Hotspur, Sir Walter Blunt</span> and
others.
</p>

<p class="drama">
KING.<br>
My blood hath been too cold and temperate,<br>
Unapt to stir at these indignities,<br>
And you have found me, for accordingly<br>
You tread upon my patience: but be sure<br>
I will from henceforth rather be myself,<br>
Mighty and to be fear’d, than my condition,<br>
Which hath been smooth as oil, soft as young down,<br>
And therefore lost that title of respect<br>
Which the proud soul ne’er pays but to the proud.
</p>

<p class="drama">
WORCESTER.<br>
Our house, my sovereign liege, little deserves<br>
The scourge of greatness to be used on it,<br>
And that same greatness too which our own hands<br>
Have holp to make so portly.
</p>

<p class="drama">
NORTHUMBERLAND.<br>
My lord,—
</p>

<p class="drama">
KING.<br>
Worcester, get thee gone, for I do see<br>
Danger and disobedience in thine eye:<br>
O, sir, your presence is too bold and peremptory,<br>
And majesty might never yet endure<br>
The moody frontier of a servant brow.<br>
You have good leave to leave us. When we need<br>
Your use and counsel, we shall send for you.
</p>

<p class="right">[<i>Exit <span class="charname">Worcester</span>.</i>]
</p>

<p class="drama">
[<i>To Northumberland.</i>]
</p>

<p class="drama">
You were about to speak.
</p>

<p class="drama">
NORTHUMBERLAND.<br>
Yea, my good lord.<br>
Those prisoners in your Highness’ name demanded,<br>
Which Harry Percy here at Holmedon took,<br>
Were, as he says, not with such strength denied<br>
As is deliver’d to your Majesty.<br>
Either envy, therefore, or misprision<br>
Is guilty of this fault, and not my son.
</p>

<p class="drama">
HOTSPUR.<br>
My liege, I did deny no prisoners.<br>
But I remember, when the fight was done,<br>
When I was dry with rage and extreme toil,<br>
Breathless and faint, leaning upon my sword,<br>
Came there a certain lord, neat and trimly dress’d,<br>
Fresh as a bridegroom, and his chin new reap’d<br>
Show’d like a stubble-land at harvest-home.<br>
He was perfumed like a milliner,<br>
And ’twixt his finger and his thumb he held<br>
A pouncet-box, which ever and anon<br>
He gave his nose, and took’t away again,<br>
Who therewith angry, when it next came there,<br>
Took it in snuff; and still he smiled and talk’d.<br>
And as the soldiers bore dead bodies by,<br>
He call’d them untaught knaves, unmannerly,<br>
To bring a slovenly unhandsome corse<br>
Betwixt the wind and his nobility.<br>
With many holiday and lady terms<br>
He question’d me, amongst the rest demanded<br>
My prisoners in your Majesty’s behalf.<br>
I then, all smarting with my wounds being cold,<br>
Out of my grief and my impatience<br>
To be so pester’d with a popinjay,<br>
Answer’d neglectingly, I know not what,<br>
He should, or he should not; for he made me mad<br>
To see him shine so brisk and smell so sweet,<br>
And talk so like a waiting-gentlewoman<br>
Of guns and drums and wounds, God save the mark!<br>
And telling me the sovereignest thing on Earth<br>
Was parmacety for an inward bruise,<br>
And that it was great pity, so it was,<br>
This villainous saltpetre should be digg’d<br>
Out of the bowels of the harmless earth,<br>
Which many a good tall fellow had destroy’d<br>
So cowardly, and but for these vile guns,<br>
He would himself have been a soldier.<br>
This bald unjointed chat of his, my lord,<br>
I answered indirectly, as I said,<br>
And I beseech you, let not his report<br>
Come current for an accusation<br>
Betwixt my love and your high Majesty.
</p>

<p class="drama">
BLUNT.<br>
The circumstance consider’d, good my lord,<br>
Whatever Harry Percy then had said<br>
To such a person, and in such a place,<br>
At such a time, with all the rest retold,<br>
May reasonably die, and never rise<br>
To do him wrong, or any way impeach<br>
What then he said, so he unsay it now.
</p>

<p class="drama">
KING.<br>
Why, yet he doth deny his prisoners,<br>
But with proviso and exception,<br>
That we at our own charge shall ransom straight<br>
His brother-in-law, the foolish Mortimer,<br>
Who, on my soul, hath wilfully betray’d<br>
The lives of those that he did lead to fight<br>
Against that great magician, damn’d Glendower,<br>
Whose daughter, as we hear, the Earl of March<br>
Hath lately married. Shall our coffers then<br>
Be emptied to redeem a traitor home?<br>
Shall we buy treason and indent with fears<br>
When they have lost and forfeited themselves?<br>
No, on the barren mountains let him starve;<br>
For I shall never hold that man my friend<br>
Whose tongue shall ask me for one penny cost<br>
To ransom home revolted Mortimer.
</p>

<p class="drama">
HOTSPUR.<br>
Revolted Mortimer!<br>
He never did fall off, my sovereign liege,<br>
But by the chance of war. To prove that true<br>
Needs no more but one tongue for all those wounds,<br>
Those mouthed wounds, which valiantly he took,<br>
When on the gentle Severn’s sedgy bank,<br>
In single opposition hand to hand,<br>
He did confound the best part of an hour<br>
In changing hardiment with great Glendower.<br>
Three times they breathed, and three times did they drink,<br>
Upon agreement, of swift Severn’s flood,<br>
Who then, affrighted with their bloody looks,<br>
Ran fearfully among the trembling reeds,<br>
And hid his crisp head in the hollow bank<br>
Blood-stained with these valiant combatants.<br>
Never did bare and rotten policy<br>
Colour her working with such deadly wounds,<br>
Nor never could the noble Mortimer<br>
Receive so many, and all willingly.<br>
Then let not him be slander’d with revolt.
</p>

<p class="drama">
KING.<br>
Thou dost belie him, Percy, thou dost belie him,<br>
He never did encounter with Glendower.<br>
I tell thee, he durst as well have met the devil alone<br>
As Owen Glendower for an enemy.<br>
Art not ashamed? But, sirrah, henceforth<br>
Let me not hear you speak of Mortimer.<br>
Send me your prisoners with the speediest means,<br>
Or you shall hear in such a kind from me<br>
As will displease you.—My Lord Northumberland,<br>
We license your departure with your son.—<br>
Send us your prisoners, or you’ll hear of it.
</p>

<p class="right">[<i>Exit <span class="charname">King Henry, Blunt</span> and train.</i>]
</p>

<p class="drama">
HOTSPUR.<br>
An if the devil come and roar for them,<br>
I will not send them. I will after straight<br>
And tell him so, for I will ease my heart,<br>
Albeit I make a hazard of my head.
</p>

<p class="drama">
NORTHUMBERLAND.<br>
What, drunk with choler? Stay, and pause awhile.<br>
Here comes your uncle.
</p>

<p class="scenedesc">Enter <span class="charname">Worcester</span>.
</p>

<p class="drama">
HOTSPUR.<br>
Speak of Mortimer?<br>
Zounds, I will speak of him, and let my soul<br>
Want mercy if I do not join with him.<br>
Yea, on his part I’ll empty all these veins,<br>
And shed my dear blood drop by drop in the dust,<br>
But I will lift the down-trod Mortimer<br>
As high in the air as this unthankful King,<br>
As this ingrate and canker’d Bolingbroke.
</p>

<p class="drama">
NORTHUMBERLAND.<br>
[<i>To Worcester.</i>]<br>
Brother, the King hath made your nephew mad.
</p>

<p class="drama">
WORCESTER.<br>
Who struck this heat up after I was gone?
</p>

<p class="drama">
HOTSPUR.<br>
He will forsooth have all my prisoners,<br>
And when I urged the ransom once again<br>
Of my wife’s brother, then his cheek look’d pale,<br>
And on my face he turn’d an eye of death,<br>
Trembling even at the name of Mortimer.
</p>

<p class="drama">
WORCESTER.<br>
I cannot blame him. Was not he proclaim’d<br>
By Richard that dead is, the next of blood?
</p>

<p class="drama">
NORTHUMBERLAND.<br>
He was; I heard the proclamation.<br>
And then it was when the unhappy King—<br>
Whose wrongs in us God pardon!—did set forth<br>
Upon his Irish expedition;<br>
From whence he, intercepted, did return<br>
To be deposed, and shortly murdered.
</p>

<p class="drama">
WORCESTER.<br>
And for whose death we in the world’s wide mouth<br>
Live scandalized and foully spoken of.
</p>

<p class="drama">
HOTSPUR.<br>
But soft, I pray you, did King Richard then<br>
Proclaim my brother Edmund Mortimer<br>
Heir to the crown?
</p>

<p class="drama">
NORTHUMBERLAND.<br>
He did; myself did hear it.
</p>

<p class="drama">
HOTSPUR.<br>
Nay, then I cannot blame his cousin King,<br>
That wish’d him on the barren mountains starve.<br>
But shall it be that you that set the crown<br>
Upon the head of this forgetful man,<br>
And for his sake wear the detested blot<br>
Of murderous subornation—shall it be,<br>
That you a world of curses undergo,<br>
Being the agents, or base second means,<br>
The cords, the ladder, or the hangman rather?<br>
O, pardon me, that I descend so low,<br>
To show the line and the predicament<br>
Wherein you range under this subtle King.<br>
Shall it for shame be spoken in these days,<br>
Or fill up chronicles in time to come,<br>
That men of your nobility and power<br>
Did gage them both in an unjust behalf<br>
(As both of you, God pardon it, have done)<br>
To put down Richard, that sweet lovely rose,<br>
And plant this thorn, this canker, Bolingbroke?<br>
And shall it in more shame be further spoken,<br>
That you are fool’d, discarded, and shook off<br>
By him for whom these shames ye underwent?<br>
No, yet time serves wherein you may redeem<br>
Your banish’d honours, and restore yourselves<br>
Into the good thoughts of the world again:<br>
Revenge the jeering and disdain’d contempt<br>
Of this proud King, who studies day and night<br>
To answer all the debt he owes to you<br>
Even with the bloody payment of your deaths.<br>
Therefore, I say—
</p>

<p class="drama">
WORCESTER.<br>
Peace, cousin, say no more.<br>
And now I will unclasp a secret book,<br>
And to your quick-conceiving discontents<br>
I’ll read you matter deep and dangerous,<br>
As full of peril and adventurous spirit<br>
As to o’er-walk a current roaring loud<br>
On the unsteadfast footing of a spear.
</p>

<p class="drama">
HOTSPUR.<br>
If we fall in, good night, or sink or swim!<br>
Send danger from the east unto the west,<br>
So honour cross it from the north to south,<br>
And let them grapple. O, the blood more stirs<br>
To rouse a lion than to start a hare!
</p>

<p class="drama">
NORTHUMBERLAND.<br>
Imagination of some great exploit<br>
Drives him beyond the bounds of patience.
</p>

<p class="drama">
HOTSPUR.<br>
By Heaven, methinks it were an easy leap<br>
To pluck bright honour from the pale-faced moon,<br>
Or dive into the bottom of the deep,<br>
Where fathom-line could never touch the ground,<br>
And pluck up drowned honour by the locks,<br>
So he that doth redeem her thence might wear<br>
Without corrival all her dignities.<br>
But out upon this half-faced fellowship!
</p>

<p class="drama">
WORCESTER.<br>
He apprehends a world of figures here,<br>
But not the form of what he should attend.—<br>
Good cousin, give me audience for a while.
</p>

<p class="drama">
HOTSPUR.<br>
I cry you mercy.
</p>

<p class="drama">
WORCESTER.<br>
Those same noble Scots<br>
That are your prisoners—
</p>

<p class="drama">
HOTSPUR.<br>
I’ll keep them all;<br>
By God, he shall not have a Scot of them,<br>
No, if a Scot would save his soul, he shall not.<br>
I’ll keep them, by this hand!
</p>

<p class="drama">
WORCESTER.<br>
You start away,<br>
And lend no ear unto my purposes:<br>
Those prisoners you shall keep—
</p>

<p class="drama">
HOTSPUR.<br>
Nay, I will: that’s flat.<br>
He said he would not ransom Mortimer,<br>
Forbade my tongue to speak of Mortimer,<br>
But I will find him when he lies asleep,<br>
And in his ear I’ll holla “Mortimer!”<br>
Nay, I’ll have a starling shall be taught to speak<br>
Nothing but “Mortimer”, and give it him,<br>
To keep his anger still in motion.
</p>

<p class="drama">
WORCESTER.<br>
Hear you, cousin, a word.
</p>

<p class="drama">
HOTSPUR.<br>
All studies here I solemnly defy,<br>
Save how to gall and pinch this Bolingbroke:<br>
And that same sword-and-buckler Prince of Wales,<br>
But that I think his father loves him not,<br>
And would be glad he met with some mischance—<br>
I would have him poison’d with a pot of ale.
</p>

<p class="drama">
WORCESTER.<br>
Farewell, kinsman. I will talk to you<br>
When you are better temper’d to attend.
</p>

<p class="drama">
NORTHUMBERLAND.<br>
Why, what a wasp-stung and impatient fool<br>
Art thou to break into this woman’s mood,<br>
Tying thine ear to no tongue but thine own!
</p>

<p class="drama">
HOTSPUR.<br>
Why, look you, I am whipp’d and scourged with rods,<br>
Nettled, and stung with pismires, when I hear<br>
Of this vile politician, Bolingbroke.<br>
In Richard’s time—what do you call the place?<br>
A plague upon’t! It is in Gloucestershire.<br>
’Twas where the madcap Duke his uncle kept,<br>
His uncle York, where I first bow’d my knee<br>
Unto this king of smiles, this Bolingbroke,<br>
’Sblood, when you and he came back from Ravenspurgh.
</p>

<p class="drama">
NORTHUMBERLAND.<br>
At Berkeley castle.
</p>

<p class="drama">
HOTSPUR.<br>
You say true.<br>
Why, what a candy deal of courtesy<br>
This fawning greyhound then did proffer me!<br>
“Look, when his infant fortune came to age,”<br>
And, “Gentle Harry Percy,” and “kind cousin.”<br>
O, the devil take such cozeners!—God forgive me!<br>
Good uncle, tell your tale. I have done.
</p>

<p class="drama">
WORCESTER.<br>
Nay, if you have not, to it again,<br>
We will stay your leisure.
</p>

<p class="drama">
HOTSPUR.<br>
I have done, i’faith.
</p>

<p class="drama">
WORCESTER.<br>
Then once more to your Scottish prisoners;<br>
Deliver them up without their ransom straight,<br>
And make the Douglas’ son your only mean<br>
For powers in Scotland, which, for divers reasons<br>
Which I shall send you written, be assured<br>
Will easily be granted.—[<i>To Northumberland.</i>] You, my lord,<br>
Your son in Scotland being thus employ’d,<br>
Shall secretly into the bosom creep<br>
Of that same noble prelate well beloved,<br>
The Archbishop.
</p>

<p class="drama">
HOTSPUR.<br>
Of York, is it not?
</p>

<p class="drama">
WORCESTER.<br>
True, who bears hard<br>
His brother’s death at Bristol, the Lord Scroop.<br>
I speak not this in estimation,<br>
As what I think might be, but what I know<br>
Is ruminated, plotted, and set down,<br>
And only stays but to behold the face<br>
Of that occasion that shall bring it on.
</p>

<p class="drama">
HOTSPUR.<br>
I smell it. Upon my life it will do well.
</p>

<p class="drama">
NORTHUMBERLAND.<br>
Before the game is afoot thou still let’st slip.
</p>

<p class="drama">
HOTSPUR.<br>
Why, it cannot choose but be a noble plot;<br>
And then the power of Scotland and of York<br>
To join with Mortimer, ha?
</p>

<p class="drama">
WORCESTER.<br>
And so they shall.
</p>

<p class="drama">
HOTSPUR.<br>
In faith, it is exceedingly well aim’d.
</p>

<p class="drama">
WORCESTER.<br>
And ’tis no little reason bids us speed,<br>
To save our heads by raising of a head;<br>
For, bear ourselves as even as we can,<br>
The King will always think him in our debt,<br>
And think we think ourselves unsatisfied,<br>
Till he hath found a time to pay us home:<br>
And see already how he doth begin<br>
To make us strangers to his looks of love.
</p>

<p class="drama">
HOTSPUR.<br>
He does, he does, we’ll be revenged on him.
</p>

<p class="drama">
WORCESTER.<br>
Cousin, farewell. No further go in this<br>
Than I by letters shall direct your course.<br>
When time is ripe, which will be suddenly,<br>
I’ll steal to Glendower and Lord Mortimer,<br>
Where you and Douglas, and our powers at once,<br>
As I will fashion it, shall happily meet,<br>
To bear our fortunes in our own strong arms,<br>
Which now we hold at much uncertainty.
</p>

<p class="drama">
NORTHUMBERLAND.<br>
Farewell, good brother; we shall thrive, I trust.
</p>

<p class="drama">
HOTSPUR.<br>
Uncle, adieu. O, let the hours be short,<br>
Till fields and blows and groans applaud our sport!
</p>

<p class="right">[<i>Exeunt.</i>]
</p>

