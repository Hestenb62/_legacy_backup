<h2><a id="sceneII_13.1"></a>ACT II</h2>

<h3> <b>SCENE I. Saint Albans</b></h3>

<p class="scenedesc">Enter the <span class="charname">King, Queen, Gloucester,
Cardinal</span> and <span class="charname">Suffolk</span> with <span class="charname">Falconers</span> hallooing.</p>

<p class="drama">
QUEEN MARGARET.<br>
Believe me, lords, for flying at the brook<br>
I saw not better sport these seven years’ day;<br>
Yet, by your leave, the wind was very high,<br>
And, ten to one, old Joan had not gone out.
</p>

<p class="drama">
KING HENRY.<br>
But what a point, my lord, your falcon made,<br>
And what a pitch she flew above the rest!<br>
To see how God in all His creatures works!<br>
Yea, man and birds are fain of climbing high.
</p>

<p class="drama">
SUFFOLK.<br>
No marvel, an it like your majesty,<br>
My Lord Protector’s hawks do tower so well;<br>
They know their master loves to be aloft,<br>
And bears his thoughts above his falcon’s pitch.
</p>

<p class="drama">
GLOUCESTER.<br>
My lord, ’tis but a base ignoble mind<br>
That mounts no higher than a bird can soar.
</p>

<p class="drama">
CARDINAL.<br>
I thought as much. He would be above the clouds.
</p>

<p class="drama">
GLOUCESTER.<br>
Ay, my Lord Cardinal, how think you by that?<br>
Were it not good your grace could fly to heaven?
</p>

<p class="drama">
KING HENRY.<br>
The treasury of everlasting joy.
</p>

<p class="drama">
CARDINAL.<br>
Thy heaven is on earth; thine eyes and thoughts<br>
Beat on a crown, the treasure of thy heart,<br>
Pernicious Protector, dangerous peer,<br>
That smooth’st it so with king and commonweal!
</p>

<p class="drama">
GLOUCESTER.<br>
What, cardinal, is your priesthood grown peremptory?<br>
<i>Tantaene animis coelestibus irae?</i><br>
Churchmen so hot? Good uncle, hide such malice.<br>
With such holiness can you do it?
</p>

<p class="drama">
SUFFOLK.<br>
No malice, sir; no more than well becomes<br>
So good a quarrel and so bad a peer.
</p>

<p class="drama">
GLOUCESTER.<br>
As who, my lord?
</p>

<p class="drama">
SUFFOLK.<br>
Why, as you, my lord,<br>
An ’t like your lordly Lord Protectorship.
</p>

<p class="drama">
GLOUCESTER.<br>
Why, Suffolk, England knows thine insolence.
</p>

<p class="drama">
QUEEN MARGARET.<br>
And thy ambition, Gloucester.
</p>

<p class="drama">
KING HENRY.<br>
I prithee, peace, good queen,<br>
And whet not on these furious peers;<br>
For blessed are the peacemakers on earth.
</p>

<p class="drama">
CARDINAL.<br>
Let me be blessed for the peace I make<br>
Against this proud Protector, with my sword!
</p>

<p class="drama">
GLOUCESTER.<br>
[<i>Aside to Cardinal</i>.] Faith, holy uncle, would ’twere come to that!
</p>

<p class="drama">
CARDINAL.<br>
[<i>Aside to Gloucester</i>.] Marry, when thou dar’st.
</p>

<p class="drama">
GLOUCESTER.<br>
[<i>Aside to Cardinal</i>.] Make up no factious numbers for the matter,<br>
In thine own person answer thy abuse.
</p>

<p class="drama">
CARDINAL.<br>
[<i>Aside to Gloucester</i>.] Ay, where thou dar’st not peep; an if thou dar’st,<br>
This evening, on the east side of the grove.
</p>

<p class="drama">
KING HENRY.<br>
How now, my lords?
</p>

<p class="drama">
CARDINAL.<br>
Believe me, cousin Gloucester,<br>
Had not your man put up the fowl so suddenly,<br>
We had had more sport.—[<i>Aside to Gloucester</i>.]<br>
Come with thy two-hand sword.
</p>

<p class="drama">
GLOUCESTER.<br>
True, uncle.<br>
[<i>Aside to Cardinal</i>.] Are ye advised? The east side of the grove?
</p>

<p class="drama">
CARDINAL.<br>
[<i>Aside to Gloucester</i>.] I am with you.
</p>

<p class="drama">
KING HENRY.<br>
Why, how now, uncle Gloucester?
</p>

<p class="drama">
GLOUCESTER.<br>
Talking of hawking; nothing else, my lord.<br>
[<i>Aside to Cardinal</i>.] Now, by God’s mother, priest,<br>
I’ll shave your crown for this,<br>
Or all my fence shall fail.
</p>

<p class="drama">
CARDINAL.<br>
[<i>Aside to Gloucester</i>.] <i>Medice, teipsum.</i>—<br>
Protector, see to ’t well, protect yourself.
</p>

<p class="drama">
KING HENRY.<br>
The winds grow high; so do your stomachs, lords.<br>
How irksome is this music to my heart!<br>
When such strings jar, what hope of harmony?<br>
I pray, my lords, let me compound this strife.
</p>

<p class="scenedesc">Enter a <span class="charname">Townsman</span> of Saint
Albans, crying, “A miracle!”</p>

<p class="drama">
GLOUCESTER.<br>
What means this noise?<br>
Fellow, what miracle dost thou proclaim?
</p>

<p class="drama">
TOWNSMAN.<br>
A miracle! A miracle!
</p>

<p class="drama">
SUFFOLK.<br>
Come to the King, and tell him what miracle.
</p>

<p class="drama">
TOWNSMAN.<br>
Forsooth, a blind man at Saint Alban’s shrine,<br>
Within this half hour, hath received his sight,<br>
A man that ne’er saw in his life before.
</p>

<p class="drama">
KING HENRY.<br>
Now, God be praised, that to believing souls<br>
Gives light in darkness, comfort in despair!
</p>

<p class="scenedesc">Enter the <span class="charname">Mayor</span> of Saint
Albans and his brethren, bearing <span class="charname">Simpcox</span> between
two in a chair, <span class="charname">Simpcox’s Wife</span> following.</p>

<p class="drama">
CARDINAL.<br>
Here comes the townsmen on procession,<br>
To present your highness with the man.
</p>

<p class="drama">
KING HENRY.<br>
Great is his comfort in this earthly vale,<br>
Although by his sight his sin be multiplied.
</p>

<p class="drama">
GLOUCESTER.<br>
Stand by, my masters. Bring him near the King.<br>
His highness’ pleasure is to talk with him.
</p>

<p class="drama">
KING HENRY.<br>
Good fellow, tell us here the circumstance,<br>
That we for thee may glorify the Lord.<br>
What, hast thou been long blind and now restored?
</p>

<p class="drama">
SIMPCOX.<br>
Born blind, an ’t please your grace.
</p>

<p class="drama">
WIFE.<br>
Ay, indeed, was he.
</p>

<p class="drama">
SUFFOLK.<br>
What woman is this?
</p>

<p class="drama">
WIFE.<br>
His wife, an ’t like your worship.
</p>

<p class="drama">
GLOUCESTER.<br>
Hadst thou been his mother, thou couldst have better told.
</p>

<p class="drama">
KING HENRY.<br>
Where wert thou born?
</p>

<p class="drama">
SIMPCOX.<br>
At Berwick in the north, an ’t like your grace.
</p>

<p class="drama">
KING HENRY.<br>
Poor soul, God’s goodness hath been great to thee.<br>
Let never day nor night unhallowed pass,<br>
But still remember what the Lord hath done.
</p>

<p class="drama">
QUEEN MARGARET.<br>
Tell me, good fellow, cam’st thou here by chance,<br>
Or of devotion, to this holy shrine?
</p>

<p class="drama">
SIMPCOX.<br>
God knows, of pure devotion; being called<br>
A hundred times and oftener, in my sleep,<br>
By good Saint Alban, who said “Simpcox, come,<br>
Come, offer at my shrine, and I will help thee.”
</p>

<p class="drama">
WIFE.<br>
Most true, forsooth; and many time and oft<br>
Myself have heard a voice to call him so.
</p>

<p class="drama">
CARDINAL.<br>
What, art thou lame?
</p>

<p class="drama">
SIMPCOX.<br>
Ay, God Almighty help me!
</p>

<p class="drama">
SUFFOLK.<br>
How cam’st thou so?
</p>

<p class="drama">
SIMPCOX.<br>
A fall off of a tree.
</p>

<p class="drama">
WIFE.<br>
A plum-tree, master.
</p>

<p class="drama">
GLOUCESTER.<br>
How long hast thou been blind?
</p>

<p class="drama">
SIMPCOX.<br>
O, born so, master.
</p>

<p class="drama">
GLOUCESTER.<br>
What, and wouldst climb a tree?
</p>

<p class="drama">
SIMPCOX.<br>
But that in all my life, when I was a youth.
</p>

<p class="drama">
WIFE.<br>
Too true; and bought his climbing very dear.
</p>

<p class="drama">
GLOUCESTER.<br>
Mass, thou lov’dst plums well, that wouldst venture so.
</p>

<p class="drama">
SIMPCOX.<br>
Alas, good master, my wife desired some damsons,<br>
And made me climb, with danger of my life.
</p>

<p class="drama">
GLOUCESTER.<br>
A subtle knave! But yet it shall not serve.—<br>
Let me see thine eyes. Wink now. Now open them.<br>
In my opinion yet thou seest not well.
</p>

<p class="drama">
SIMPCOX.<br>
Yes, master, clear as day, I thank God and Saint Alban.
</p>

<p class="drama">
GLOUCESTER.<br>
Sayst thou me so? What colour is this cloak of?
</p>

<p class="drama">
SIMPCOX.<br>
Red, master, red as blood.
</p>

<p class="drama">
GLOUCESTER.<br>
Why, that’s well said. What colour is my gown of?
</p>

<p class="drama">
SIMPCOX.<br>
Black, forsooth, coal-black as jet.
</p>

<p class="drama">
KING HENRY.<br>
Why, then, thou know’st what colour jet is of?
</p>

<p class="drama">
SUFFOLK.<br>
And yet, I think, jet did he never see.
</p>

<p class="drama">
GLOUCESTER.<br>
But cloaks and gowns before this day, a many.
</p>

<p class="drama">
WIFE.<br>
Never before this day in all his life.
</p>

<p class="drama">
GLOUCESTER.<br>
Tell me, sirrah, what’s my name?
</p>

<p class="drama">
SIMPCOX.<br>
Alas, master, I know not.
</p>

<p class="drama">
GLOUCESTER.<br>
What’s his name?
</p>

<p class="drama">
SIMPCOX.<br>
I know not.
</p>

<p class="drama">
GLOUCESTER.<br>
Nor his?
</p>

<p class="drama">
SIMPCOX.<br>
No, indeed, master.
</p>

<p class="drama">
GLOUCESTER.<br>
What’s thine own name?
</p>

<p class="drama">
SIMPCOX.<br>
Sander Simpcox, an if it please you, master.
</p>

<p class="drama">
GLOUCESTER.<br>
Then, Sander, sit there, the lyingest knave in Christendom. If thou hadst been
born blind, thou mightst as well have known all our names as thus to name the
several colours we do wear. Sight may distinguish of colours; but suddenly to
nominate them all, it is impossible.—My lords, Saint Alban here hath done
a miracle; and would ye not think his cunning to be great that could restore
this cripple to his legs again?
</p>

<p class="drama">
SIMPCOX.<br>
O master, that you could!
</p>

<p class="drama">
GLOUCESTER.<br>
My masters of Saint Albans, have you not beadles in your town, and
things called whips?
</p>

<p class="drama">
MAYOR.<br>
Yes, my lord, if it please your grace.
</p>

<p class="drama">
GLOUCESTER.<br>
Then send for one presently.
</p>

<p class="drama">
MAYOR.<br>
Sirrah, go fetch the beadle hither straight.
</p>

<p class="right">[<i>Exit a <span class="charname">Townsman</span>.</i>]</p>

<p class="drama">
GLOUCESTER.<br>
Now fetch me a stool hither by and by.—Now, sirrah, if you mean to save
yourself from whipping, leap me over this stool and run away.
</p>

<p class="drama">
SIMPCOX.<br>
Alas, master, I am not able to stand alone.<br>
You go about to torture me in vain.
</p>

<p class="scenedesc">Enter a <span class="charname">Beadle</span> with whips.</p>

<p class="drama">
GLOUCESTER.<br>
Well, sir, we must have you find your legs.<br>
Sirrah beadle, whip him till he leap over that same stool.
</p>

<p class="drama">
BEADLE.<br>
I will, my lord.—Come on, sirrah; off with your doublet quickly.
</p>

<p class="drama">
SIMPCOX.<br>
Alas, master, what shall I do? I am not able to stand.
</p>

<p class="right">[<i>After the <span class="charname">Beadle</span> hath hit
him once, he leaps over the stool and runs away; and they follow and cry, “A
miracle!”</i>]</p>

<p class="drama">
KING HENRY.<br>
O God, seest Thou this, and bearest so long?
</p>

<p class="drama">
QUEEN MARGARET.<br>
It made me laugh to see the villain run.
</p>

<p class="drama">
GLOUCESTER.<br>
Follow the knave, and take this drab away.
</p>

<p class="drama">
WIFE.<br>
Alas, sir, we did it for pure need.
</p>

<p class="drama">
GLOUCESTER.<br>
Let them be whipped through every market town<br>
Till they come to Berwick, from
whence they came.
</p>

<p class="right">[<i>Exeunt <span class="charname">Wife, Beadle, Mayor</span>, etc.</i>]</p>

<p class="drama">
CARDINAL.<br>
Duke Humphrey has done a miracle today.
</p>

<p class="drama">
SUFFOLK.<br>
True, made the lame to leap and fly away.
</p>

<p class="drama">
GLOUCESTER.<br>
But you have done more miracles than I.<br>
You made in a day, my lord, whole towns to fly.
</p>

<p class="scenedesc">Enter <span class="charname">Buckingham</span>.</p>

<p class="drama">
KING HENRY.<br>
What tidings with our cousin Buckingham?
</p>

<p class="drama">
BUCKINGHAM.<br>
Such as my heart doth tremble to unfold.<br>
A sort of naughty persons, lewdly bent,<br>
Under the countenance and confederacy<br>
Of Lady Eleanor, the Protector’s wife,<br>
The ringleader and head of all this rout,<br>
Have practised dangerously against your state,<br>
Dealing with witches and with conjurers,<br>
Whom we have apprehended in the fact,<br>
Raising up wicked spirits from under ground,<br>
Demanding of King Henry’s life and death,<br>
And other of your highness’ Privy Council,<br>
As more at large your Grace shall understand.
</p>

<p class="drama">
CARDINAL.<br>
[<i>Aside to Gloucester</i>.] And so, my Lord Protector, by this means<br>
Your lady is forthcoming yet at London.<br>
This news, I think, hath turned your weapon’s edge;<br>
’Tis like, my lord, you will not keep your hour.
</p>

<p class="drama">
GLOUCESTER.<br>
Ambitious churchman, leave to afflict my heart.<br>
Sorrow and grief have vanquished all my powers,<br>
And, vanquished as I am, I yield to thee,<br>
Or to the meanest groom.
</p>

<p class="drama">
KING HENRY.<br>
O God, what mischiefs work the wicked ones,<br>
Heaping confusion on their own heads thereby!
</p>

<p class="drama">
QUEEN MARGARET.<br>
Gloucester, see here the tainture of thy nest,<br>
And look thyself be faultless, thou wert best.
</p>

<p class="drama">
GLOUCESTER.<br>
Madam, for myself, to heaven I do appeal<br>
How I have loved my king and commonweal;<br>
And, for my wife, I know not how it stands.<br>
Sorry I am to hear what I have heard.<br>
Noble she is; but if she have forgot<br>
Honour and virtue, and conversed with such<br>
As like to pitch defile nobility,<br>
I banish her my bed and company<br>
And give her as a prey to law and shame<br>
That hath dishonoured Gloucester’s honest name.
</p>

<p class="drama">
KING HENRY.<br>
Well, for this night we will repose us here;<br>
Tomorrow toward London back again,<br>
To look into this business thoroughly,<br>
And call these foul offenders to their answers,<br>
And poise the cause in Justice’ equal scales,<br>
Whose beam stands sure, whose rightful cause prevails.
</p>

<p class="right">[<i>Flourish. Exeunt.</i>]</p>

<h3> <a id="sceneII_13.2"></a><b>SCENE II. London. The Duke of York’s Garden</b></h3>

<p class="scenedesc">Enter <span class="charname">York, Salisbury</span> and
<span class="charname">Warwick</span>.</p>

<p class="drama">
YORK.<br>
Now, my good Lords of Salisbury and Warwick,<br>
Our simple supper ended, give me leave<br>
In this close walk to satisfy myself<br>
In craving your opinion of my title,<br>
Which is infallible, to England’s crown.
</p>

<p class="drama">
SALISBURY.<br>
My lord, I long to hear it at full.
</p>

<p class="drama">
WARWICK.<br>
Sweet York, begin; and if thy claim be good,<br>
The Nevilles are thy subjects to command.
</p>

<p class="drama">
YORK.<br>
Then thus:<br>
Edward the Third, my lords, had seven sons:<br>
The first, Edward the Black Prince, Prince of Wales;<br>
The second, William of Hatfield; and the third,<br>
Lionel, Duke of Clarence; next to whom<br>
Was John of Gaunt, the Duke of Lancaster;<br>
The fifth was Edmund Langley, Duke of York;<br>
The sixth was Thomas of Woodstock, Duke of Gloucester;<br>
William of Windsor was the seventh and last.<br>
Edward the Black Prince died before his father<br>
And left behind him Richard, his only son,<br>
Who after Edward the Third’s death reigned as king,<br>
Till Henry Bolingbroke, Duke of Lancaster,<br>
The eldest son and heir of John of Gaunt,<br>
Crowned by the name of Henry the Fourth,<br>
Seized on the realm, deposed the rightful king,<br>
Sent his poor queen to France, from whence she came,<br>
And him to Pomfret; where, as all you know,<br>
Harmless Richard was murdered traitorously.
</p>

<p class="drama">
WARWICK.<br>
Father, the Duke hath told the truth;<br>
Thus got the house of Lancaster the crown.
</p>

<p class="drama">
YORK.<br>
Which now they hold by force and not by right;<br>
For Richard, the first son’s heir, being dead,<br>
The issue of the next son should have reigned.
</p>

<p class="drama">
SALISBURY.<br>
But William of Hatfield died without an heir.
</p>

<p class="drama">
YORK.<br>
The third son, Duke of Clarence, from whose line<br>
I claim the crown, had issue, Philippa, a daughter,<br>
Who married Edmund Mortimer, Earl of March.<br>
Edmund had issue, Roger, Earl of March;<br>
Roger had issue, Edmund, Anne, and Eleanor.
</p>

<p class="drama">
SALISBURY.<br>
This Edmund, in the reign of Bolingbroke,<br>
As I have read, laid claim unto the crown<br>
And, but for Owen Glendower, had been king,<br>
Who kept him in captivity till he died.<br>
But to the rest.
</p>

<p class="drama">
YORK.<br>
His eldest sister, Anne,<br>
My mother, being heir unto the crown,<br>
Married Richard Earl of Cambridge, who was son<br>
To Edmund Langley, Edward the Third’s fifth son.<br>
By her I claim the kingdom; she was heir<br>
To Roger, Earl of March, who was the son<br>
Of Edmund Mortimer, who married Philippa,<br>
Sole daughter unto Lionel, Duke of Clarence.<br>
So, if the issue of the elder son<br>
Succeed before the younger, I am king.
</p>

<p class="drama">
WARWICK.<br>
What plain proceeding is more plain than this?<br>
Henry doth claim the crown from John of Gaunt,<br>
The fourth son; York claims it from the third.<br>
Till Lionel’s issue fails, his should not reign;<br>
It fails not yet, but flourishes in thee<br>
And in thy sons, fair slips of such a stock.<br>
Then, father Salisbury, kneel we together,<br>
And in this private plot be we the first<br>
That shall salute our rightful sovereign<br>
With honour of his birthright to the crown.
</p>

<p class="drama">
BOTH.<br>
Long live our sovereign Richard, England’s king!
</p>

<p class="drama">
YORK.<br>
We thank you, lords. But I am not your king<br>
Till I be crowned, and that my sword be stained<br>
With heart-blood of the house of Lancaster;<br>
And that’s not suddenly to be performed,<br>
But with advice and silent secrecy.<br>
Do you as I do in these dangerous days—<br>
Wink at the Duke of Suffolk’s insolence,<br>
At Beaufort’s pride, at Somerset’s ambition,<br>
At Buckingham, and all the crew of them,<br>
Till they have snared the shepherd of the flock,<br>
That virtuous prince, the good Duke Humphrey.<br>
’Tis that they seek; and they, in seeking that,<br>
Shall find their deaths, if York can prophesy.
</p>

<p class="drama">
SALISBURY.<br>
My lord, break we off; we know your mind at full.
</p>

<p class="drama">
WARWICK.<br>
My heart assures me that the Earl of Warwick<br>
Shall one day make the Duke of York a king.
</p>

<p class="drama">
YORK.<br>
And, Neville, this I do assure myself:<br>
Richard shall live to make the Earl of Warwick<br>
The greatest man in England but the king.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneII_13.3"></a><b>SCENE III. A Hall of Justice</b></h3>

<p class="scenedesc">Sound trumpets. Enter the <span class="charname">King, the
Queen, Gloucester, York, Suffolk</span> and <span class="charname">Salisbury;
the Duchess of Gloucester, Margery Jourdain, Southwell, Hume</span> and <span class="charname">Bolingbroke</span> under guard.</p>

<p class="drama">
KING HENRY.<br>
Stand forth, Dame Eleanor Cobham, Gloucester’s wife.<br>
In sight of God and us, your guilt is great;<br>
Receive the sentence of the law for sins<br>
Such as by God’s book are adjudged to death.<br>
You four, from hence to prison back again;<br>
From thence unto the place of execution.<br>
The witch in Smithfield shall be burnt to ashes,<br>
And you three shall be strangled on the gallows.<br>
You, madam, for you are more nobly born,<br>
Despoiled of your honour in your life,<br>
Shall, after three days’ open penance done,<br>
Live in your country here in banishment,<br>
With Sir John Stanley in the Isle of Man.
</p>

<p class="drama">
ELEANOR.<br>
Welcome is banishment; welcome were my death.
</p>

<p class="drama">
GLOUCESTER.<br>
Eleanor, the law, thou seest, hath judged thee.<br>
I cannot justify whom the law condemns.
</p>

<p class="right">[<i>Exeunt <span class="charname">Duchess</span> and the other
prisoners, guarded.</i>]</p>

<p class="drama">
Mine eyes are full of tears, my heart of grief.<br>
Ah, Humphrey, this dishonour in thine age<br>
Will bring thy head with sorrow to the ground!—<br>
I beseech your majesty, give me leave to go;<br>
Sorrow would solace, and mine age would ease.
</p>

<p class="drama">
KING HENRY.<br>
Stay, Humphrey Duke of Gloucester. Ere thou go,<br>
Give up thy staff. Henry will to himself<br>
Protector be; and God shall be my hope,<br>
My stay, my guide, and lantern to my feet.<br>
And go in peace, Humphrey, no less beloved<br>
Than when thou wert Protector to thy king.
</p>

<p class="drama">
QUEEN MARGARET.<br>
I see no reason why a king of years<br>
Should be to be protected like a child.<br>
God and King Henry govern England’s realm!<br>
Give up your staff, sir, and the King his realm.
</p>

<p class="drama">
GLOUCESTER.<br>
My staff? Here, noble Henry, is my staff.<br>
As willingly do I the same resign<br>
As e’er thy father Henry made it mine;<br>
And even as willingly at thy feet I leave it<br>
As others would ambitiously receive it.<br>
Farewell, good King. When I am dead and gone,<br>
May honourable peace attend thy throne.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
QUEEN MARGARET.<br>
Why, now is Henry King and Margaret Queen,<br>
And Humphrey Duke of Gloucester scarce himself,<br>
That bears so shrewd a maim. Two pulls at once;<br>
His lady banished, and a limb lopped off.<br>
This staff of honour raught, there let it stand<br>
Where it best fits to be, in Henry’s hand.
</p>

<p class="drama">
SUFFOLK.<br>
Thus droops this lofty pine and hangs his sprays;<br>
Thus Eleanor’s pride dies in her youngest days.
</p>

<p class="drama">
YORK.<br>
Lords, let him go.—Please it your majesty,<br>
This is the day appointed for the combat,<br>
And ready are the appellant and defendant,<br>
The armourer and his man, to enter the lists,<br>
So please your highness to behold the fight.
</p>

<p class="drama">
QUEEN MARGARET.<br>
Ay, good my lord; for purposely therefore<br>
Left I the court to see this quarrel tried.
</p>

<p class="drama">
KING HENRY.<br>
I’ God’s name, see the lists and all things fit.<br>
Here let them end it, and God defend the right!
</p>

<p class="drama">
YORK.<br>
I never saw a fellow worse bested,<br>
Or more afraid to fight, than is the appellant,<br>
The servant of his armourer, my lords.
</p>

<p class="scenedesc">Enter at one door <span class="charname">Horner</span> the
armourer, and his <span class="charname">Neighbours</span>, drinking to him so
much that he is drunk; and he enters with a drum before him and his staff with
a sandbag fastened to it; and at the other door <span class="charname">Peter</span>, his man, with a drum and sandbag, and
<span class="charname">Prentices</span>  drinking to him.</p>

<p class="drama">
1 NEIGHBOUR.<br>
Here, neighbour Horner, I drink to you in a cup of sack; and fear not,
neighbour, you shall do well enough.
</p>

<p class="drama">
2 NEIGHBOUR.<br>
And here, neighbour, here’s a cup of charneco.
</p>

<p class="drama">
3 NEIGHBOUR.<br>
And here’s a pot of good double beer, neighbour. Drink, and fear not your
man.
</p>

<p class="drama">
HORNER.<br>
Let it come, i’ faith, and I’ll pledge you all; and a fig for
Peter!
</p>

<p class="drama">
1 PRENTICE.<br>
Here, Peter, I drink to thee, and be not afraid.
</p>

<p class="drama">
2 PRENTICE.<br>
Be merry, Peter, and fear not thy master. Fight for credit of the
prentices.
</p>

<p class="drama">
PETER.<br>
I thank you all. Drink, and pray for me, I pray you, for I think I have taken
my last draught in this world. Here, Robin, an if I die, I give thee my
apron; and, Will, thou shalt have my hammer; and here, Tom, take all the money
that I have. O Lord bless me! I pray God, for I am never able to deal with my
master, he hath learnt so much fence already.
</p>

<p class="drama">
SALISBURY.<br>
Come, leave your drinking and fall to blows.<br>
Sirrah, what’s thy name?
</p>

<p class="drama">
PETER.<br>
Peter, forsooth.
</p>

<p class="drama">
SALISBURY.<br>
Peter? What more?
</p>

<p class="drama">
PETER.<br>
Thump.
</p>

<p class="drama">
SALISBURY.<br>
Thump! Then see thou thump thy master well.
</p>

<p class="drama">
HORNER.<br>
Masters, I am come hither, as it were, upon my man’s instigation, to
prove him a knave and myself an honest man; and touching the Duke of York, I
will take my death I never meant him any ill, nor the King, nor the
Queen; and therefore, Peter, have at thee with a downright blow!
</p>

<p class="drama">
YORK.<br>
Dispatch! This knave’s tongue begins to double.<br>
Sound, trumpets. Alarum to the combatants!
</p>

<p class="right">[<i>They fight, and <span class="charname">Peter</span>
strikes him down.</i>]</p>

<p class="drama">
HORNER.<br>
Hold, Peter, hold! I confess, I confess treason.
</p>

<p class="right">[<i>Dies.</i>]</p>

<p class="drama">
YORK.<br>
Take away his weapon.—Fellow, thank God and the good wine in thy master’s way.
</p>

<p class="drama">
PETER.<br>
O God, have I overcome mine enemies in this presence? O Peter, thou hast
prevailed in right!
</p>

<p class="drama">
KING HENRY.<br>
Go, take hence that traitor from our sight,<br>
For by his death we do perceive his guilt.<br>
And God in justice hath revealed to us<br>
The truth and innocence of this poor fellow,<br>
Which he had thought to have murdered wrongfully.<br>
Come, fellow, follow us for thy reward.
</p>

<p class="right">[<i>Sound a flourish. Exeunt.</i>]</p>

<h3> <a id="sceneII_13.4"></a><b>SCENE IV. A Street</b></h3>

<p class="scenedesc">Enter <span class="charname">Gloucester</span> and his
<span class="charname">Servingmen</span> in mourning cloaks.</p>

<p class="drama">
GLOUCESTER.<br>
Thus sometimes hath the brightest day a cloud,<br>
And after summer evermore succeeds<br>
Barren winter, with his wrathful nipping cold;<br>
So cares and joys abound, as seasons fleet.<br>
Sirs, what’s o’clock?
</p>

<p class="drama">
SERVINGMEN.<br>
Ten, my lord.
</p>

<p class="drama">
GLOUCESTER.<br>
Ten is the hour that was appointed me<br>
To watch the coming of my punished duchess.<br>
Uneath may she endure the flinty streets,<br>
To tread them with her tender-feeling feet.<br>
Sweet Nell, ill can thy noble mind abrook<br>
The abject people gazing on thy face<br>
With envious looks, laughing at thy shame,<br>
That erst did follow thy proud chariot wheels<br>
When thou didst ride in triumph through the streets.<br>
But, soft! I think she comes; and I’ll prepare<br>
My tear-stained eyes to see her miseries.
</p>

<p class="scenedesc">Enter the <span class="charname">Duchess of
Gloucester</span> in a white sheet, and a taper burning in her hand; with <span class="charname">Sir John Stanley</span>, the Sheriff, and Officers.</p>

<p class="drama">
SERVINGMEN.<br>
So please your Grace, we’ll take her from the sheriff.
</p>

<p class="drama">
GLOUCESTER.<br>
No, stir not for your lives; let her pass by.
</p>

<p class="drama">
ELEANOR.<br>
Come you, my lord, to see my open shame?<br>
Now thou dost penance too. Look how they gaze!<br>
See how the giddy multitude do point,<br>
And nod their heads, and throw their eyes on thee.<br>
Ah, Gloucester, hide thee from their hateful looks,<br>
And, in thy closet pent up, rue my shame,<br>
And ban thine enemies, both mine and thine!
</p>

<p class="drama">
GLOUCESTER.<br>
Be patient, gentle Nell, forget this grief.
</p>

<p class="drama">
ELEANOR.<br>
Ah, Gloucester, teach me to forget myself!<br>
For whilst I think I am thy married wife<br>
And thou a prince, Protector of this land,<br>
Methinks I should not thus be led along,<br>
Mailed up in shame, with papers on my back,<br>
And followed with a rabble that rejoice<br>
To see my tears and hear my deep-fet groans.<br>
The ruthless flint doth cut my tender feet,<br>
And when I start, the envious people laugh<br>
And bid me be advised how I tread.<br>
Ah, Humphrey, can I bear this shameful yoke?<br>
Trowest thou that e’er I’ll look upon the world,<br>
Or count them happy that enjoy the sun?<br>
No, dark shall be my light and night my day;<br>
To think upon my pomp shall be my hell.<br>
Sometimes I’ll say, I am Duke Humphrey’s wife,<br>
And he a prince and ruler of the land;<br>
Yet so he ruled and such a prince he was<br>
As he stood by whilst I, his forlorn duchess,<br>
Was made a wonder and a pointing-stock<br>
To every idle rascal follower.<br>
But be thou mild and blush not at my shame,<br>
Nor stir at nothing till the axe of death<br>
Hang over thee, as, sure, it shortly will.<br>
For Suffolk, he that can do all in all<br>
With her that hateth thee and hates us all,<br>
And York and impious Beaufort, that false priest,<br>
Have all limed bushes to betray thy wings;<br>
And fly thou how thou canst, they’ll tangle thee.<br>
But fear not thou until thy foot be snared,<br>
Nor never seek prevention of thy foes.
</p>

<p class="drama">
GLOUCESTER.<br>
Ah, Nell, forbear! Thou aimest all awry.<br>
I must offend before I be attainted;<br>
And had I twenty times so many foes,<br>
And each of them had twenty times their power,<br>
All these could not procure me any scathe<br>
So long as I am loyal, true, and crimeless.<br>
Wouldst have me rescue thee from this reproach?<br>
Why, yet thy scandal were not wiped away,<br>
But I in danger for the breach of law.<br>
Thy greatest help is quiet, gentle Nell.<br>
I pray thee, sort thy heart to patience;<br>
These few days’ wonder will be quickly worn.
</p>

<p class="scenedesc">Enter a <span class="charname">Herald</span>.</p>

<p class="drama">
HERALD.<br>
I summon your grace to his majesty’s parliament,<br>
Holden at Bury the first of this next month.
</p>

<p class="drama">
GLOUCESTER.<br>
And my consent ne’er asked herein before?<br>
This is close dealing. Well, I will be there.
</p>

<p class="right">[<i>Exit <span class="charname">Herald</span>.</i>]</p>

<p class="drama">
My Nell, I take my leave; and, master sheriff,<br>
Let not her penance exceed the King’s commission.
</p>

<p class="drama">
SHERIFF.<br>
An ’t please your grace, here my commission stays,<br>
And Sir John Stanley is appointed now<br>
To take her with him to the Isle of Man.
</p>

<p class="drama">
GLOUCESTER.<br>
Must you, Sir John, protect my lady here?
</p>

<p class="drama">
STANLEY.<br>
So am I given in charge, may ’t please your grace.
</p>

<p class="drama">
GLOUCESTER.<br>
Entreat her not the worse in that I pray<br>
You use her well. The world may laugh again,<br>
And I may live to do you kindness if<br>
You do it her. And so, Sir John, farewell.
</p>

<p class="drama">
ELEANOR.<br>
What, gone, my lord, and bid me not farewell?
</p>

<p class="drama">
GLOUCESTER.<br>
Witness my tears, I cannot stay to speak.
</p>

<p class="right">[<i>Exeunt <span class="charname">Gloucester</span> and
<span class="charname">Servingmen</span>.</i>]</p>

<p class="drama">
ELEANOR.<br>
Art thou gone too? All comfort go with thee,<br>
For none abides with me; my joy is death;<br>
Death, at whose name I oft have been afeard,<br>
Because I wished this world’s eternity.<br>
Stanley, I prithee, go, and take me hence,<br>
I care not whither, for I beg no favour,<br>
Only convey me where thou art commanded.
</p>

<p class="drama">
STANLEY.<br>
Why, madam, that is to the Isle of Man,<br>
There to be used according to your state.
</p>

<p class="drama">
ELEANOR.<br>
That’s bad enough, for I am but reproach;<br>
And shall I then be used reproachfully?
</p>

<p class="drama">
STANLEY.<br>
Like to a duchess, and Duke Humphrey’s lady;<br>
According to that state you shall be used.
</p>

<p class="drama">
ELEANOR.<br>
Sheriff, farewell, and better than I fare,<br>
Although thou hast been conduct of my shame.
</p>

<p class="drama">
SHERIFF.<br>
It is my office; and, madam, pardon me.
</p>

<p class="drama">
ELEANOR.<br>
Ay, ay, farewell; thy office is discharged.<br>
Come, Stanley, shall we go?
</p>

<p class="drama">
STANLEY.<br>
Madam, your penance done, throw off this sheet,<br>
And go we to attire you for our journey.
</p>

<p class="drama">
ELEANOR.<br>
My shame will not be shifted with my sheet,<br>
No, it will hang upon my richest robes<br>
And show itself, attire me how I can.<br>
Go, lead the way, I long to see my prison.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

