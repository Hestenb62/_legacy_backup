<h2> <a id="sceneV_11.0"></a><b>ACT V</b></h2>

<p class="scenedesc"> Enter <span class="charname">Chorus</span>.</p>

<p>CHORUS.<br>
Vouchsafe to those that have not read the story,<br>
That I may prompt them; and of such as have,<br>
I humbly pray them to admit the excuse<br>
Of time, of numbers, and due course of things,<br>
Which cannot in their huge and proper life<br>
Be here presented. Now we bear the King<br>
Toward Calais; grant him there; there seen,<br>
Heave him away upon your winged thoughts<br>
Athwart the sea. Behold, the English beach<br>
Pales in the flood with men, with wives and boys,<br>
Whose shouts and claps out-voice the deep-mouth’d sea,<br>
Which like a mighty whiffler ’fore the King<br>
Seems to prepare his way. So let him land,<br>
And solemnly see him set on to London.<br>
So swift a pace hath thought that even now<br>
You may imagine him upon Blackheath,<br>
Where that his lords desire him to have borne<br>
His bruised helmet and his bended sword<br>
Before him through the city. He forbids it,<br>
Being free from vainness and self-glorious pride;<br>
Giving full trophy, signal, and ostent<br>
Quite from himself to God. But now behold,<br>
In the quick forge and working-house of thought,<br>
How London doth pour out her citizens!<br>
The mayor and all his brethren in best sort,<br>
Like to the senators of th’ antique Rome,<br>
With the plebeians swarming at their heels,<br>
Go forth and fetch their conquering Caesar in;<br>
As, by a lower but loving likelihood,<br>
Were now the general of our gracious empress,<br>
As in good time he may, from Ireland coming,<br>
Bringing rebellion broached on his sword,<br>
How many would the peaceful city quit,<br>
To welcome him! Much more, and much more cause,<br>
Did they this Harry. Now in London place him;<br>
As yet the lamentation of the French<br>
Invites the King of England’s stay at home,<br>
The Emperor’s coming in behalf of France,<br>
To order peace between them;—and omit<br>
All the occurrences, whatever chanc’d,<br>
Till Harry’s back-return again to France.<br>
There must we bring him; and myself have play’d<br>
The interim, by rememb’ring you ’tis past.<br>
Then brook abridgement, and your eyes advance<br>
After your thoughts, straight back again to France.
</p>

<p class="right"> [<i>Exit.</i>]</p>

<h3> <a id="sceneV_11.1"></a><b>SCENE I. France. The English camp.</b></h3>

<p class="scenedesc"> Enter <span class="charname">Fluellen</span> and <span class="charname">Gower</span>.</p>

<p>GOWER.<br>
Nay, that’s right; but why wear you your leek today?<br>
Saint Davy’s day is past.
</p>

<p>FLUELLEN.<br>
There is occasions and causes why and wherefore in all things. I will tell you
ass my friend, Captain Gower. The rascally, scald, beggarly, lousy, pragging
knave, Pistol, which you and yourself and all the world know to be no petter
than a fellow, look you now, of no merits, he is come to me and prings me pread
and salt yesterday, look you, and bid me eat my leek. It was in a place where I
could not breed no contention with him; but I will be so bold as to wear it in
my cap till I see him once again, and then I will tell him a little piece of my
desires.
</p>

<p class="scenedesc"> Enter <span class="charname">Pistol</span>.</p>

<p>GOWER.<br>
Why, here he comes, swelling like a turkey-cock.
</p>

<p>FLUELLEN.<br>
’Tis no matter for his swellings nor his turkey-cocks. God pless you,
Anchient Pistol! you scurvy, lousy knave, God pless you!
</p>

<p>PISTOL.<br>
Ha! art thou bedlam? Dost thou thirst, base Trojan,<br>
To have me fold up Parca’s fatal web?<br>
Hence! I am qualmish at the smell of leek.
</p>

<p>FLUELLEN.<br>
I peseech you heartily, scurfy, lousy knave, at my desires, and my requests,
and my petitions, to eat, look you, this leek. Because, look you, you do not
love it, nor your affections and your appetites and your digestions does not
agree with it, I would desire you to eat it.
</p>

<p>PISTOL.<br>
Not for Cadwallader and all his goats.
</p>

<p>FLUELLEN.<br>
There is one goat for you. [<i>Strikes him.</i>] Will you be so good, scald
knave, as eat it?
</p>

<p>PISTOL.<br>
Base Trojan, thou shalt die.
</p>

<p>FLUELLEN.<br>
You say very true, scald knave, when God’s will is. I will desire you to
live in the mean time, and eat your victuals. Come, there is sauce for it.
[<i>Strikes him.</i>] You call’d me yesterday mountain-squire; but I will
make you today a squire of low degree. I pray you, fall to; if you can mock a
leek, you can eat a leek.
</p>

<p>GOWER.<br>
Enough, captain; you have astonish’d him.
</p>

<p>FLUELLEN.<br>
I say, I will make him eat some part of my leek, or I will peat his pate four
days. Bite, I pray you; it is good for your green wound and your ploody
coxcomb.
</p>

<p>PISTOL.<br>
Must I bite?
</p>

<p>FLUELLEN.<br>
Yes, certainly, and out of doubt and out of question too, and ambiguities.
</p>

<p>PISTOL.<br>
By this leek, I will most horribly revenge. I eat and eat, I swear—
</p>

<p>FLUELLEN.<br>
Eat, I pray you. Will you have some more sauce to your leek? There is not
enough leek to swear by.
</p>

<p>PISTOL.<br>
Quiet thy cudgel; thou dost see I eat.
</p>

<p>FLUELLEN.<br>
Much good do you, scald knave, heartily. Nay, pray you, throw none away; the
skin is good for your broken coxcomb. When you take occasions to see leeks
hereafter, I pray you, mock at ’em; that is all.
</p>

<p>PISTOL.<br>
Good.
</p>

<p>FLUELLEN.<br>
Ay, leeks is good. Hold you, there is a groat to heal your pate.
</p>

<p>PISTOL.<br>
Me a groat!
</p>

<p>FLUELLEN.<br>
Yes, verily and in truth you shall take it; or I have another leek in my
pocket, which you shall eat.
</p>

<p>PISTOL.<br>
I take thy groat in earnest of revenge.
</p>

<p>FLUELLEN.<br>
If I owe you anything I will pay you in cudgels. You shall be a woodmonger, and
buy nothing of me but cudgels. God be wi’ you, and keep you, and heal
your pate.
</p>

<p class="right"> [<i>Exit.</i>]</p>

<p>PISTOL.<br>
All hell shall stir for this.
</p>

<p>GOWER.<br>
Go, go; you are a couterfeit cowardly knave. Will you mock at an ancient
tradition, begun upon an honourable respect, and worn as a memorable trophy of
predeceased valour, and dare not avouch in your deeds any of your words? I have
seen you gleeking and galling at this gentleman twice or thrice. You thought,
because he could not speak English in the native garb, he could not therefore
handle an English cudgel. You find it otherwise; and henceforth let a Welsh
correction teach you a good English condition. Fare ye well.
</p>

<p class="right"> [<i>Exit.</i>]</p>

<p>PISTOL.<br>
Doth Fortune play the huswife with me now?<br>
News have I, that my Doll is dead i’ the spital<br>
Of malady of France;<br>
And there my rendezvous is quite cut off.<br>
Old I do wax; and from my weary limbs<br>
Honour is cudgell’d. Well, bawd I’ll turn,<br>
And something lean to cutpurse of quick hand.<br>
To England will I steal, and there I’ll steal;<br>
And patches will I get unto these cudgell’d scars,<br>
And swear I got them in the Gallia wars.
</p>

<p class="right"> [<i>Exit.</i>]</p>

<h3> <a id="sceneV_11.2"></a><b>SCENE II. France. A royal palace.</b></h3>

<p class="scenedesc"> Enter at one door, <span class="charname">King Henry,
Exeter, Bedford, Warwick, Gloucester, Westmorland, Clarence, Huntingdon</span>
and other Lords. At another, <span class="charname">Queen Isabel,</span> the
<span class="charname">French King,</span> the Princess <span class="charname">Katharine, Alice,</span> and other Ladies; the <span class="charname">Duke of Burgundy</span> and other French.</p>

<p>KING HENRY.<br>
Peace to this meeting, wherefore we are met!<br>
Unto our brother France, and to our sister,<br>
Health and fair time of day; joy and good wishes<br>
To our most fair and princely cousin Katharine;<br>
And, as a branch and member of this royalty,<br>
By whom this great assembly is contriv’d,<br>
We do salute you, Duke of Burgundy;<br>
And, princes French, and peers, health to you all!
</p>

<p>FRENCH KING.<br>
Right joyous are we to behold your face,<br>
Most worthy brother England; fairly met!<br>
So are you, princes English, every one.
</p>

<p>QUEEN ISABEL.<br>
So happy be the issue, brother England,<br>
Of this good day and of this gracious meeting<br>
As we are now glad to behold your eyes;<br>
Your eyes, which hitherto have borne in them<br>
Against the French that met them in their bent<br>
The fatal balls of murdering basilisks.<br>
The venom of such looks, we fairly hope,<br>
Have lost their quality; and that this day<br>
Shall change all griefs and quarrels into love.
</p>

<p>KING HENRY.<br>
To cry amen to that, thus we appear.
</p>

<p>QUEEN ISABEL.<br>
You English princes all, I do salute you.
</p>

<p>BURGUNDY.<br>
My duty to you both, on equal love,<br>
Great Kings of France and England! That I have labour’d,<br>
With all my wits, my pains, and strong endeavours,<br>
To bring your most imperial Majesties<br>
Unto this bar and royal interview,<br>
Your mightiness on both parts best can witness.<br>
Since then my office hath so far prevail’d<br>
That, face to face and royal eye to eye,<br>
You have congreeted, let it not disgrace me<br>
If I demand, before this royal view,<br>
What rub or what impediment there is,<br>
Why that the naked, poor, and mangled Peace,<br>
Dear nurse of arts, plenties, and joyful births,<br>
Should not in this best garden of the world,<br>
Our fertile France, put up her lovely visage?<br>
Alas, she hath from France too long been chas’d,<br>
And all her husbandry doth lie on heaps,<br>
Corrupting in it own fertility.<br>
Her vine, the merry cheerer of the heart,<br>
Unpruned dies; her hedges even-pleach’d,<br>
Like prisoners wildly overgrown with hair,<br>
Put forth disorder’d twigs; her fallow leas<br>
The darnel, hemlock, and rank fumitory,<br>
Doth root upon, while that the coulter rusts<br>
That should deracinate such savagery;<br>
The even mead, that erst brought sweetly forth<br>
The freckled cowslip, burnet, and green clover,<br>
Wanting the scythe, all uncorrected, rank,<br>
Conceives by idleness, and nothing teems<br>
But hateful docks, rough thistles, kecksies, burs,<br>
Losing both beauty and utility;<br>
And as our vineyards, fallows, meads, and hedges,<br>
Defective in their natures, grow to wildness.<br>
Even so our houses and ourselves and children<br>
Have lost, or do not learn for want of time,<br>
The sciences that should become our country;<br>
But grow like savages,—as soldiers will<br>
That nothing do but meditate on blood,—<br>
To swearing and stern looks, diffus’d attire,<br>
And everything that seems unnatural.<br>
Which to reduce into our former favour<br>
You are assembled; and my speech entreats<br>
That I may know the let, why gentle Peace<br>
Should not expel these inconveniences<br>
And bless us with her former qualities.
</p>

<p>KING HENRY.<br>
If, Duke of Burgundy, you would the peace,<br>
Whose want gives growth to the imperfections<br>
Which you have cited, you must buy that peace<br>
With full accord to all our just demands;<br>
Whose tenours and particular effects<br>
You have enschedul’d briefly in your hands.
</p>

<p>BURGUNDY.<br>
The King hath heard them; to the which as yet<br>
There is no answer made.
</p>

<p>KING HENRY.<br>
Well, then, the peace,<br>
Which you before so urg’d, lies in his answer.
</p>

<p>FRENCH KING.<br>
I have but with a cursorary eye<br>
O’erglanc’d the articles. Pleaseth your Grace<br>
To appoint some of your council presently<br>
To sit with us once more, with better heed<br>
To re-survey them, we will suddenly<br>
Pass our accept and peremptory answer.
</p>

<p>KING HENRY.<br>
Brother, we shall. Go, uncle Exeter,<br>
And brother Clarence, and you, brother Gloucester,<br>
Warwick, and Huntington, go with the King;<br>
And take with you free power to ratify,<br>
Augment, or alter, as your wisdoms best<br>
Shall see advantageable for our dignity,<br>
Anything in or out of our demands,<br>
And we’ll consign thereto. Will you, fair sister,<br>
Go with the princes, or stay here with us?
</p>

<p>QUEEN ISABEL.<br>
Our gracious brother, I will go with them.<br>
Haply a woman’s voice may do some good,<br>
When articles too nicely urg’d be stood on.
</p>

<p>KING HENRY.<br>
Yet leave our cousin Katharine here with us:<br>
She is our capital demand, compris’d<br>
Within the fore-rank of our articles.
</p>

<p>QUEEN ISABEL.<br>
She hath good leave.
</p>

<p class="right"> [<i>Exeunt all except <span class="charname">Henry,
Katharine</span> and <span class="charname">Alice</span>.</i>]</p>

<p>KING HENRY.<br>
Fair Katharine, and most fair,<br>
Will you vouchsafe to teach a soldier terms<br>
Such as will enter at a lady’s ear<br>
And plead his love-suit to her gentle heart?
</p>

<p>KATHARINE.<br>
Your Majesty shall mock me; I cannot speak your England.
</p>

<p>KING HENRY.<br>
O fair Katharine, if you will love me soundly with your French heart, I will be
glad to hear you confess it brokenly with your English tongue. Do you like me,
Kate?
</p>

<p>KATHARINE.<br>
<i>Pardonnez-moi</i>, I cannot tell wat is “like me.”
</p>

<p>KING HENRY.<br>
An angel is like you, Kate, and you are like an angel.
</p>

<p>KATHARINE.<br>
<i>Que dit-il? Que je suis semblable à les anges?</i>
</p>

<p>ALICE.<br>
<i>Oui, vraiment, sauf votre Grâce, ainsi dit-il.</i>
</p>

<p>KING HENRY.<br>
I said so, dear Katharine; and I must not blush to affirm it.
</p>

<p>KATHARINE.<br>
<i>O bon Dieu! les langues des hommes sont pleines de tromperies.</i>
</p>

<p>KING HENRY.<br>
What says she, fair one? That the tongues of men are full of deceits?
</p>

<p>ALICE.<br>
<i>Oui</i>, dat de tongues of de mans is be full of deceits: dat is de
Princess.
</p>

<p>KING HENRY.<br>
The Princess is the better Englishwoman. I’ faith, Kate, my wooing is fit
for thy understanding. I am glad thou canst speak no better English; for if
thou couldst, thou wouldst find me such a plain king that thou wouldst think I
had sold my farm to buy my crown. I know no ways to mince it in love, but
directly to say, “I love you”; then if you urge me farther than to
say, “Do you in faith?” I wear out my suit. Give me your answer;
i’ faith, do; and so clap hands and a bargain. How say you, lady?
</p>

<p>KATHARINE.<br>
<i>Sauf votre honneur</i>, me understand well.
</p>

<p>KING HENRY.<br>
Marry, if you would put me to verses, or to dance for your sake, Kate, why you
undid me; for the one, I have neither words nor measure, and for the other I
have no strength in measure, yet a reasonable measure in strength. If I could
win a lady at leap-frog, or by vaulting into my saddle with my armour on my
back, under the correction of bragging be it spoken, I should quickly leap into
a wife. Or if I might buffet for my love, or bound my horse for her favours, I
could lay on like a butcher and sit like a jack-an-apes, never off. But, before
God, Kate, I cannot look greenly, nor gasp out my eloquence, nor I have no
cunning in protestation; only downright oaths, which I never use till
urg’d, nor never break for urging. If thou canst love a fellow of this
temper, Kate, whose face is not worth sunburning, that never looks in his glass
for love of anything he sees there, let thine eye be thy cook. I speak to thee
plain soldier. If thou canst love me for this, take me; if not, to say to thee
that I shall die, is true; but for thy love, by the Lord, no; yet I love thee
too. And while thou liv’st, dear Kate, take a fellow of plain and
uncoined constancy; for he perforce must do thee right, because he hath not the
gift to woo in other places; for these fellows of infinite tongue, that can
rhyme themselves into ladies’ favours, they do always reason themselves
out again. What! a speaker is but a prater: a rhyme is but a ballad. A good leg
will fall; a straight back will stoop; a black beard will turn white; a
curl’d pate will grow bald; a fair face will wither; a full eye will wax
hollow; but a good heart, Kate, is the sun and the moon; or rather the sun and
not the moon; for it shines bright and never changes, but keeps his course
truly. If thou would have such a one, take me; and take me, take a soldier;
take a soldier, take a king. And what say’st thou then to my love? Speak,
my fair, and fairly, I pray thee.
</p>

<p>KATHARINE.<br>
Is it possible dat I should love de enemy of France?
</p>

<p>KING HENRY.<br>
No; it is not possible you should love the enemy of France, Kate; but, in
loving me, you should love the friend of France; for I love France so well that
I will not part with a village of it, I will have it all mine; and, Kate, when
France is mine and I am yours, then yours is France and you are mine.
</p>

<p>KATHARINE.<br>
I cannot tell wat is dat.
</p>

<p>KING HENRY.<br>
No, Kate? I will tell thee in French; which I am sure will hang upon my tongue
like a new-married wife about her husband’s neck, hardly to be shook off.
<i>Je quand sur le possession de France, et quand vous avez le possession de
moi</i>,—let me see, what then? Saint Denis be my speed!—<i>donc
votre est France, et vous êtes mienne.</i> It is as easy for me, Kate, to
conquer the kingdom as to speak so much more French. I shall never move thee in
French, unless it be to laugh at me.
</p>

<p>KATHARINE.<br>
<i>Sauf votre honneur, le français que vous parlez, il est meilleur que
l’anglais lequel je parle.</i>
</p>

<p>KING HENRY.<br>
No, faith, is’t not, Kate; but thy speaking of my tongue, and I thine,
most truly-falsely, must needs be granted to be much at one. But, Kate, dost
thou understand thus much English: canst thou love me?
</p>

<p>KATHARINE.<br>
I cannot tell.
</p>

<p>KING HENRY.<br>
Can any of your neighbours tell, Kate? I’ll ask them. Come, I know thou
lovest me; and at night, when you come into your closet, you’ll question
this gentlewoman about me; and I know, Kate, you will to her dispraise those
parts in me that you love with your heart. But, good Kate, mock me mercifully;
the rather, gentle princess, because I love thee cruelly. If ever thou beest
mine, Kate, as I have a saving faith within me tells me thou shalt, I get thee
with scambling, and thou must therefore needs prove a good soldier-breeder.
Shall not thou and I, between Saint Denis and Saint George, compound a boy,
half French, half English, that shall go to Constantinople and take the Turk by
the beard? Shall we not? What say’st thou, my fair flower-de-luce?
</p>

<p>KATHARINE.<br>
I do not know dat.
</p>

<p>KING HENRY.<br>
No; ’tis hereafter to know, but now to promise. Do but now promise, Kate,
you will endeavour for your French part of such a boy; and for my English
moiety, take the word of a king and a bachelor. How answer you, <i>la plus
belle Katherine du monde, mon très cher et divin déesse?</i>
</p>

<p>KATHARINE.<br>
Your Majestee ’ave <i>fausse</i> French enough to deceive de most <i>sage
demoiselle</i> dat is <i>en France</i>.
</p>

<p>KING HENRY.<br>
Now, fie upon my false French! By mine honour, in true English, I love thee,
Kate; by which honour I dare not swear thou lovest me; yet my blood begins to
flatter me that thou dost, notwithstanding the poor and untempering effect of
my visage. Now, beshrew my father’s ambition! He was thinking of civil
wars when he got me; therefore was I created with a stubborn outside, with an
aspect of iron, that, when I come to woo ladies, I fright them. But, in faith,
Kate, the elder I wax, the better I shall appear. My comfort is, that old age,
that ill layer up of beauty, can do no more spoil upon my face. Thou hast me,
if thou hast me, at the worst; and thou shalt wear me, if thou wear me, better
and better; and therefore tell me, most fair Katharine, will you have me? Put
off your maiden blushes; avouch the thoughts of your heart with the looks of an
empress; take me by the hand, and say, Harry of England, I am thine; which word
thou shalt no sooner bless mine ear withal, but I will tell thee aloud, England
is thine, Ireland is thine, France is thine, and Henry Plantagenet is thine;
who, though I speak it before his face, if he be not fellow with the best king,
thou shalt find the best king of good fellows. Come, your answer in broken
music; for thy voice is music and thy English broken; therefore, queen of all,
Katharine, break thy mind to me in broken English. Wilt thou have me?
</p>

<p>KATHARINE.<br>
Dat is as it shall please <i>le roi mon père</i>.
</p>

<p>KING HENRY.<br>
Nay, it will please him well, Kate; it shall please him, Kate.
</p>

<p>KATHARINE.<br>
Den it sall also content me.
</p>

<p>KING HENRY.<br>
Upon that I kiss your hand, and call you my queen.
</p>

<p>KATHARINE.<br>
<i>Laissez, mon seigneur, laissez, laissez! Ma foi, je ne veux point que vous
abaissiez votre grandeur en baisant la main d’une—Notre
Seigneur!—indigne serviteur. Excusez-moi, je vous supplie, mon
très-puissant seigneur.</i>
</p>

<p>KING HENRY.<br>
Then I will kiss your lips, Kate.
</p>

<p>KATHARINE.<br>
<i>Les dames et demoiselles pour être baisées devant leurs noces, il
n’est pas la coutume de France.</i>
</p>

<p>KING HENRY.<br>
Madame my interpreter, what says she?
</p>

<p>ALICE.<br>
Dat it is not be de fashion <i>pour les</i> ladies of France,—I cannot
tell wat is <i>baiser en</i> Anglish.
</p>

<p>KING HENRY.<br>
To kiss.
</p>

<p>ALICE.<br>
Your Majestee <i>entend</i> bettre <i>que moi</i>.
</p>

<p>KING HENRY.<br>
It is not a fashion for the maids in France to kiss before they are married,
would she say?
</p>

<p>ALICE.<br>
<i>Oui, vraiment.</i>
</p>

<p>KING HENRY.<br>
O Kate, nice customs curtsy to great kings. Dear Kate, you and I cannot be
confined within the weak list of a country’s fashion. We are the makers
of manners, Kate; and the liberty that follows our places stops the mouth of
all find-faults, as I will do yours, for upholding the nice fashion of your
country in denying me a kiss; therefore, patiently and yielding. [<i>Kissing
her.</i>] You have witchcraft in your lips, Kate; there is more eloquence in a
sugar touch of them than in the tongues of the French council; and they should
sooner persuade Harry of England than a general petition of monarchs. Here
comes your father.
</p>

<p class="scenedesc"> Enter the <span class="charname">French Power</span> and
the <span class="charname">English Lords</span>.</p>

<p>BURGUNDY.<br>
God save your Majesty! My royal cousin, teach you our princess English?
</p>

<p>KING HENRY.<br>
I would have her learn, my fair cousin, how perfectly I love her; and that is
good English.
</p>

<p>BURGUNDY.<br>
Is she not apt?
</p>

<p>KING HENRY.<br>
Our tongue is rough, coz, and my condition is not smooth; so that, having
neither the voice nor the heart of flattery about me, I cannot so conjure up
the spirit of love in her, that he will appear in his true likeness.
</p>

<p>BURGUNDY.<br>
Pardon the frankness of my mirth, if I answer you for that. If you would
conjure in her, you must make a circle; if conjure up Love in her in his true
likeness, he must appear naked and blind. Can you blame her then, being a maid
yet ros’d over with the virgin crimson of modesty, if she deny the
appearance of a naked blind boy in her naked seeing self? It were, my lord, a
hard condition for a maid to consign to.
</p>

<p>KING HENRY.<br>
Yet they do wink and yield, as love is blind and enforces.
</p>

<p>BURGUNDY.<br>
They are then excus’d, my lord, when they see not what they do.
</p>

<p>KING HENRY.<br>
Then, good my lord, teach your cousin to consent winking.
</p>

<p>BURGUNDY.<br>
I will wink on her to consent, my lord, if you will teach her to know my
meaning; for maids, well summer’d and warm kept, are like flies at
Bartholomew-tide, blind, though they have their eyes; and then they will endure
handling, which before would not abide looking on.
</p>

<p>KING HENRY.<br>
This moral ties me over to time and a hot summer; and so I shall catch the fly,
your cousin, in the latter end, and she must be blind too.
</p>

<p>BURGUNDY.<br>
As love is, my lord, before it loves.
</p>

<p>KING HENRY.<br>
It is so; and you may, some of you, thank love for my blindness, who cannot see
many a fair French city for one fair French maid that stands in my way.
</p>

<p>FRENCH KING.<br>
Yes, my lord, you see them perspectively, the cities turn’d into a maid;
for they are all girdled with maiden walls that no war hath entered.
</p>

<p>KING HENRY.<br>
Shall Kate be my wife?
</p>

<p>FRENCH KING.<br>
So please you.
</p>

<p>KING HENRY.<br>
I am content, so the maiden cities you talk of may wait on her; so the maid
that stood in the way for my wish shall show me the way to my will.
</p>

<p>FRENCH KING.<br>
We have consented to all terms of reason.
</p>

<p>KING HENRY.<br>
Is’t so, my lords of England?
</p>

<p>WESTMORLAND.<br>
The king hath granted every article;<br>
His daughter first, and then in sequel all,<br>
According to their firm proposed natures.
</p>

<p>EXETER.<br>
Only he hath not yet subscribed this: where your Majesty demands, that the King
of France, having any occasion to write for matter of grant, shall name your
Highness in this form and with this addition, in French, <i>Notre très-cher
fils Henri, Roi d’Angleterre, Héritier de France</i>; and thus in Latin,
<i>Praeclarissimus filius noster Henricus, rex Angliae et haeres Franciae.</i>
</p>

<p>FRENCH KING.<br>
Nor this I have not, brother, so denied<br>
But our request shall make me let it pass.
</p>

<p>KING HENRY.<br>
I pray you then, in love and dear alliance,<br>
Let that one article rank with the rest;<br>
And thereupon give me your daughter.
</p>

<p>FRENCH KING.<br>
Take her, fair son, and from her blood raise up<br>
Issue to me; that the contending kingdoms<br>
Of France and England, whose very shores look pale<br>
With envy of each other’s happiness,<br>
May cease their hatred; and this dear conjunction<br>
Plant neighbourhood and Christian-like accord<br>
In their sweet bosoms, that never war advance<br>
His bleeding sword ’twixt England and fair France.
</p>

<p>LORDS.<br>
Amen!
</p>

<p>KING HENRY.<br>
Now, welcome, Kate; and bear me witness all,<br>
That here I kiss her as my sovereign queen.
</p>

<p class="right"> [<i>Flourish.</i>]</p>

<p>QUEEN ISABEL.<br>
God, the best maker of all marriages,<br>
Combine your hearts in one, your realms in one!<br>
As man and wife, being two, are one in love,<br>
So be there ’twixt your kingdoms such a spousal,<br>
That never may ill office, or fell jealousy,<br>
Which troubles oft the bed of blessed marriage,<br>
Thrust in between the paction of these kingdoms,<br>
To make divorce of their incorporate league;<br>
That English may as French, French Englishmen,<br>
Receive each other. God speak this Amen!
</p>

<p>ALL.<br>
Amen!
</p>

<p>KING HENRY.<br>
Prepare we for our marriage; on which day,<br>
My Lord of Burgundy, we’ll take your oath,<br>
And all the peers’, for surety of our leagues,<br>
Then shall I swear to Kate, and you to me;<br>
And may our oaths well kept and prosperous be!
</p>

<p class="right"> [<i>Sennet. Exeunt.</i>]</p>

<h3> <a id="sceneV_11.3"></a><b>EPILOGUE.</b></h3>

<p class="scenedesc"> Enter <span class="charname">Chorus</span>.</p>

<p>CHORUS.<br>
Thus far, with rough and all-unable pen,<br>
Our bending author hath pursu’d the story,<br>
In little room confining mighty men,<br>
Mangling by starts the full course of their glory.<br>
Small time, but in that small most greatly lived<br>
This star of England. Fortune made his sword,<br>
By which the world’s best garden he achieved,<br>
And of it left his son imperial lord.<br>
Henry the Sixth, in infant bands crown’d King<br>
Of France and England, did this king succeed;<br>
Whose state so many had the managing,<br>
That they lost France and made his England bleed:<br>
Which oft our stage hath shown; and, for their sake,<br>
In your fair minds let this acceptance take.
</p>

<p class="right"> [<i>Exit.</i>]</p>

