<h2> <a id="sceneIII_19.1"></a><b>ACT III</b></h2>

<h3> <b>SCENE I. The King of Navarre’s park</b></h3>

<p class="scenedesc">
Enter <span class="charname">Armado</span> the Braggart and
<span class="charname">Moth</span> his Boy.
</p>

<p class="drama">
ARMADO.<br>
Warble, child, make passionate my sense of hearing.
</p>

<p class="drama">
MOTH.<br>
[<i>Singing</i>.]<br>
Concolinel.
</p>

<p class="drama">
ARMADO.<br>
Sweet air! Go, tenderness of years, take this key, give enlargement to the
swain, bring him festinately hither. I must employ him in a letter to my love.
</p>

<p class="drama">
MOTH.<br>
Master, will you win your love with a French brawl?
</p>

<p class="drama">
ARMADO.<br>
How meanest thou? Brawling in French?
</p>

<p class="drama">
MOTH.<br>
No, my complete master; but to jig off a tune at the tongue’s end, canary to it
with your feet, humour it with turning up your eyelids, sigh a note and sing a
note, sometime through the throat, as if you swallowed love with singing love,
sometime through the nose, as if you snuffed up love by smelling love; with
your hat penthouse-like o’er the shop of your eyes, with your arms crossed on
your thin-belly doublet like a rabbit on a spit; or your hands in your pocket
like a man after the old painting; and keep not too long in one tune, but a
snip and away. These are compliments, these are humours; these betray nice
wenches that would be betrayed without these; and make them men of note—do
you note me?—that most are affected to these.
</p>

<p class="drama">
ARMADO.<br>
How hast thou purchased this experience?
</p>

<p class="drama">
MOTH.<br>
By my penny of observation.
</p>

<p class="drama">
ARMADO.<br>
But O—but O—
</p>

<p class="drama">
MOTH.<br>
“The hobby-horse is forgot.”
</p>

<p class="drama">
ARMADO.<br>
Call’st thou my love “hobby-horse”?
</p>

<p class="drama">
MOTH.<br>
No, master. The hobby-horse is but a colt, and your love perhaps a hackney.
But have you forgot your love?
</p>

<p class="drama">
ARMADO.<br>
Almost I had.
</p>

<p class="drama">
MOTH.<br>
Negligent student! Learn her by heart.
</p>

<p class="drama">
ARMADO.<br>
By heart and in heart, boy.
</p>

<p class="drama">
MOTH.<br>
And out of heart, master. All those three I will prove.
</p>

<p class="drama">
ARMADO.<br>
What wilt thou prove?
</p>

<p class="drama">
MOTH.<br>
A man, if I live; and this, “by, in, and without,” upon the instant: “by” heart
you love her, because your heart cannot come by her; “in” heart you love her,
because your heart is in love with her; and “out” of heart you love her, being
out of heart that you cannot enjoy her.
</p>

<p class="drama">
ARMADO.<br>
I am all these three.
</p>

<p class="drama">
MOTH.<br>
And three times as much more, and yet nothing at all.
</p>

<p class="drama">
ARMADO.<br>
Fetch hither the swain. He must carry me a letter.
</p>

<p class="drama">
MOTH.<br>
A message well sympathized: a horse to be ambassador for an ass.
</p>

<p class="drama">
ARMADO.<br>
Ha, ha, what sayest thou?
</p>

<p class="drama">
MOTH.<br>
Marry, sir, you must send the ass upon the horse, for he is very slow-gaited.
But I go.
</p>

<p class="drama">
ARMADO.<br>
The way is but short. Away!
</p>

<p class="drama">
MOTH.<br>
As swift as lead, sir.
</p>

<p class="drama">
ARMADO.<br>
The meaning, pretty ingenious?<br>
Is not lead a metal heavy, dull, and slow?
</p>

<p class="drama">
MOTH.<br>
<i>Minime</i>, honest master; or rather, master, no.
</p>

<p class="drama">
ARMADO.<br>
I say lead is slow.
</p>

<p class="drama">
MOTH.<br>
You are too swift, sir, to say so.<br>
Is that lead slow which is fired from a gun?
</p>

<p class="drama">
ARMADO.<br>
Sweet smoke of rhetoric!<br>
He reputes me a cannon; and the bullet, that’s he.<br>
I shoot thee at the swain.
</p>

<p class="drama">
MOTH.<br>
Thump then, and I flee.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
ARMADO.<br>
A most acute juvenal, voluble and free of grace!<br>
By thy favour, sweet welkin, I must sigh in thy face.<br>
Most rude melancholy, valour gives thee place.<br>
My herald is returned.
</p>

<p class="scenedesc">
Enter <span class="charname">Moth</span> and
<span class="charname">Costard</span>.
</p>

<p class="drama">
MOTH.<br>
A wonder, master! Here’s a costard broken in a shin.
</p>

<p class="drama">
ARMADO.<br>
Some enigma, some riddle. Come, thy <i>l’envoi</i> begin.
</p>

<p class="drama">
COSTARD.<br>
No egma, no riddle, no <i>l’envoi</i>, no salve in the mail, sir. O, sir,
plantain, a plain plantain! No <i>l’envoi</i>, no <i>l’envoi</i>, no salve,
sir, but a plantain.
</p>

<p class="drama">
ARMADO.<br>
By virtue, thou enforcest laughter; thy silly thought, my spleen; the heaving
of my lungs provokes me to ridiculous smiling. O, pardon me, my stars! Doth the
inconsiderate take <i>salve</i> for <i>l’envoi</i>, and the word <i>l’envoi</i>
for a <i>salve?</i>
</p>

<p class="drama">
MOTH.<br>
Do the wise think them other? Is not <i>l’envoi</i> a <i>salve?</i>
</p>

<p class="drama">
ARMADO.<br>
No, page; it is an epilogue or discourse to make plain<br>
Some obscure precedence that hath tofore been sain.<br>
I will example it:<br>
    The fox, the ape, and the humble-bee<br>
    Were still at odds, being but three.<br>
There’s the moral. Now the <i>l’envoi</i>.
</p>

<p class="drama">
MOTH.<br>
I will add the <i>l’envoi</i>. Say the moral again.
</p>

<p class="drama">
ARMADO.<br>
    The fox, the ape, and the humble-bee<br>
    Were still at odds, being but three.
</p>

<p class="drama">
MOTH.<br>
    Until the goose came out of door,<br>
    And stayed the odds by adding four.<br>
Now will I begin your moral, and do you follow with my <i>l’envoi</i>.<br>
    The fox, the ape, and the humble-bee<br>
    Were still at odds, being but three.
</p>

<p class="drama">
ARMADO.<br>
    Until the goose came out of door,<br>
    Staying the odds by adding four.
</p>

<p class="drama">
MOTH.<br>
A good <i>l’envoi</i>, ending in the goose. Would you desire more?
</p>

<p class="drama">
COSTARD.<br>
The boy hath sold him a bargain, a goose, that’s flat.<br>
Sir, your pennyworth is good, an your goose be fat.<br>
To sell a bargain well is as cunning as fast and loose.<br>
Let me see: a fat <i>l’envoi</i>—ay, that’s a fat goose.
</p>

<p class="drama">
ARMADO.<br>
Come hither, come hither. How did this argument begin?
</p>

<p class="drama">
MOTH.<br>
By saying that a costard was broken in a shin.<br>
Then called you for the <i>l’envoi</i>.
</p>

<p class="drama">
COSTARD.<br>
True, and I for a plantain. Thus came your argument in. Then the boy’s fat
<i>l’envoi</i>, the goose that you bought; and he ended the market.
</p>

<p class="drama">
ARMADO.<br>
But tell me, how was there a costard broken in a shin?
</p>

<p class="drama">
MOTH.<br>
I will tell you sensibly.
</p>

<p class="drama">
COSTARD.<br>
Thou hast no feeling of it, Moth. I will speak that <i>l’envoi</i>.<br>
    I, Costard, running out, that was safely within,<br>
    Fell over the threshold and broke my shin.
</p>

<p class="drama">
ARMADO.<br>
We will talk no more of this matter.
</p>

<p class="drama">
COSTARD.<br>
Till there be more matter in the shin.
</p>

<p class="drama">
ARMADO.<br>
Sirrah Costard, I will enfranchise thee.
</p>

<p class="drama">
COSTARD.<br>
O, marry me to one Frances! I smell some <i>l’envoi</i>, some goose, in this.
</p>

<p class="drama">
ARMADO.<br>
By my sweet soul, I mean setting thee at liberty, enfreedoming thy person. Thou
wert immured, restrained, captivated, bound.
</p>

<p class="drama">
COSTARD.<br>
True, true; and now you will be my purgation, and let me loose.
</p>

<p class="drama">
ARMADO.<br>
I give thee thy liberty, set thee from durance, and, in lieu thereof, impose on
thee nothing but this: [<i>Giving him a letter</i>.] bear this significant to the
country maid Jaquenetta. [<i>Giving money</i>.] There is remuneration for the
best ward of mine honour is rewarding my dependents. Moth, follow.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
MOTH.<br>
Like the sequel, I. Signior Costard, adieu.
</p>

<p class="right">[<i>Exit <span class="charname">Moth</span>.</i>]</p>

<p class="drama">
COSTARD.<br>
My sweet ounce of man’s flesh, my incony Jew!<br>
Now will I look to his remuneration. “Remuneration”! O, that’s the Latin word
for three farthings. Three farthings—<i>remuneration</i>. “What’s the price of
this inkle?” “One penny.” “No, I’ll give you a remuneration.” Why, it carries
it! <i>Remuneration</i>. Why, it is a fairer name than French crown. I will
never buy and sell out of this word.
</p>

<p class="scenedesc">
Enter <span class="charname">Berowne</span>.
</p>

<p class="drama">
BEROWNE.<br>
My good knave Costard, exceedingly well met.
</p>

<p class="drama">
COSTARD.<br>
Pray you, sir, how much carnation ribbon may a man buy for a remuneration?
</p>

<p class="drama">
BEROWNE.<br>
What is a remuneration?
</p>

<p class="drama">
COSTARD.<br>
Marry, sir, halfpenny farthing.
</p>

<p class="drama">
BEROWNE.<br>
Why, then, three-farthing worth of silk.
</p>

<p class="drama">
COSTARD.<br>
I thank your worship. God be wi’ you.
</p>

<p class="drama">
BEROWNE.<br>
Stay, slave. I must employ thee.<br>
As thou wilt win my favour, good my knave,<br>
Do one thing for me that I shall entreat.
</p>

<p class="drama">
COSTARD.<br>
When would you have it done, sir?
</p>

<p class="drama">
BEROWNE.<br>
This afternoon.
</p>

<p class="drama">
COSTARD.<br>
Well, I will do it, sir. Fare you well.
</p>

<p class="drama">
BEROWNE.<br>
Thou knowest not what it is.
</p>

<p class="drama">
COSTARD.<br>
I shall know, sir, when I have done it.
</p>

<p class="drama">
BEROWNE.<br>
Why, villain, thou must know first.
</p>

<p class="drama">
COSTARD.<br>
I will come to your worship tomorrow morning.
</p>

<p class="drama">
BEROWNE.<br>
It must be done this afternoon. Hark, slave, it is but this:<br>
The Princess comes to hunt here in the park,<br>
And in her train there is a gentle lady;<br>
When tongues speak sweetly, then they name her name,<br>
And Rosaline they call her. Ask for her<br>
And to her white hand see thou do commend<br>
This sealed-up counsel.
</p>

<p class="right">[<i>Gives him money.</i>]</p>

<p class="drama">
There’s thy guerdon. Go.
</p>

<p class="drama">
COSTARD.<br>
Gardon, O sweet gardon! Better than remuneration, a ’levenpence farthing
better. Most sweet gardon! I will do it, sir, in print. Gardon! Remuneration!
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
BEROWNE.<br>
And I, forsooth, in love! I, that have been love’s whip,<br>
A very beadle to a humorous sigh,<br>
A critic, nay, a night-watch constable,<br>
A domineering pedant o’er the boy,<br>
Than whom no mortal so magnificent!<br>
This wimpled, whining, purblind, wayward boy,<br>
This Signior Junior, giant-dwarf, Dan Cupid,<br>
Regent of love-rhymes, lord of folded arms,<br>
Th’ anointed sovereign of sighs and groans,<br>
Liege of all loiterers and malcontents,<br>
Dread prince of plackets, king of codpieces,<br>
Sole imperator, and great general<br>
Of trotting paritors—O my little heart!<br>
And I to be a corporal of his field<br>
And wear his colours like a tumbler’s hoop!<br>
What? I love, I sue, I seek a wife?<br>
A woman, that is like a German clock,<br>
Still a-repairing, ever out of frame,<br>
And never going aright, being a watch,<br>
But being watched that it may still go right!<br>
Nay, to be perjured, which is worst of all;<br>
And, among three, to love the worst of all,<br>
A whitely wanton with a velvet brow,<br>
With two pitch-balls stuck in her face for eyes;<br>
Ay, and, by heaven, one that will do the deed<br>
Though Argus were her eunuch and her guard.<br>
And I to sigh for her, to watch for her,<br>
To pray for her! Go to, it is a plague<br>
That Cupid will impose for my neglect<br>
Of his almighty dreadful little might.<br>
Well, I will love, write, sigh, pray, sue, and groan.<br>
Some men must love my lady, and some Joan.
</p>

<p class="right">[<i>Exit.</i>]</p>

