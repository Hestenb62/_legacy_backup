<h2> <a id="sceneV_6.1"></a><b>ACT V</b></h2>

<h3> <b>SCENE I. Rome. A public place</b></h3>

<p class="scenedesc">
Enter <span class="charname">Menenius, Cominius, Sicinius, Brutus</span> (the
two Tribunes), with others.
</p>

<p class="drama">
MENENIUS.<br>
No, I’ll not go. You hear what he hath said<br>
Which was sometime his general, who loved him<br>
In a most dear particular. He called me father,<br>
But what o’ that? Go you that banished him;<br>
A mile before his tent, fall down, and knee<br>
The way into his mercy. Nay, if he coyed<br>
To hear Cominius speak, I’ll keep at home.
</p>

<p class="drama">
COMINIUS.<br>
He would not seem to know me.
</p>

<p class="drama">
MENENIUS.<br>
Do you hear?
</p>

<p class="drama">
COMINIUS.<br>
Yet one time he did call me by my name.<br>
I urged our old acquaintance, and the drops<br>
That we have bled together. “Coriolanus”<br>
He would not answer to, forbade all names.<br>
He was a kind of nothing, titleless,<br>
Till he had forged himself a name i’ th’ fire<br>
Of burning Rome.
</p>

<p class="drama">
MENENIUS.<br>
Why, so; you have made good work!<br>
A pair of tribunes that have wracked Rome<br>
To make coals cheap! A noble memory!
</p>

<p class="drama">
COMINIUS.<br>
I minded him how royal ’twas to pardon<br>
When it was less expected. He replied<br>
It was a bare petition of a state<br>
To one whom they had punished.
</p>

<p class="drama">
MENENIUS.<br>
Very well.<br>
Could he say less?
</p>

<p class="drama">
COMINIUS.<br>
I offered to awaken his regard<br>
For’s private friends. His answer to me was<br>
He could not stay to pick them in a pile<br>
Of noisome musty chaff. He said ’twas folly<br>
For one poor grain or two to leave unburnt<br>
And still to nose th’ offence.
</p>

<p class="drama">
MENENIUS.<br>
For one poor grain or two!<br>
I am one of those! His mother, wife, his child,<br>
And this brave fellow too, we are the grains;<br>
You are the musty chaff, and you are smelt<br>
Above the moon. We must be burnt for you.
</p>

<p class="drama">
SICINIUS.<br>
Nay, pray, be patient. If you refuse your aid<br>
In this so-never-needed help, yet do not<br>
Upbraid’s with our distress. But sure, if you<br>
Would be your country’s pleader, your good tongue,<br>
More than the instant army we can make,<br>
Might stop our countryman.
</p>

<p class="drama">
MENENIUS.<br>
No, I’ll not meddle.
</p>

<p class="drama">
SICINIUS.<br>
Pray you, go to him.
</p>

<p class="drama">
MENENIUS.<br>
What should I do?
</p>

<p class="drama">
BRUTUS.<br>
Only make trial what your love can do<br>
For Rome, towards Martius.
</p>

<p class="drama">
MENENIUS.<br>
Well, and say that Martius<br>
Return me, as Cominius is returned, unheard,<br>
What then? But as a discontented friend,<br>
Grief-shot with his unkindness? Say’t be so?
</p>

<p class="drama">
SICINIUS.<br>
Yet your good will<br>
Must have that thanks from Rome after the measure<br>
As you intended well.
</p>

<p class="drama">
MENENIUS.<br>
I’ll undertake’t.<br>
I think he’ll hear me. Yet to bite his lip<br>
And hum at good Cominius much unhearts me.<br>
He was not taken well; he had not dined.<br>
The veins unfilled, our blood is cold, and then<br>
We pout upon the morning, are unapt<br>
To give or to forgive; but when we have stuffed<br>
These pipes and these conveyances of our blood<br>
With wine and feeding, we have suppler souls<br>
Than in our priestlike fasts. Therefore I’ll watch him<br>
Till he be dieted to my request,<br>
And then I’ll set upon him.
</p>

<p class="drama">
BRUTUS.<br>
You know the very road into his kindness<br>
And cannot lose your way.
</p>

<p class="drama">
MENENIUS.<br>
Good faith, I’ll prove him,<br>
Speed how it will. I shall ere long have knowledge<br>
Of my success.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
COMINIUS.<br>
He’ll never hear him.
</p>

<p class="drama">
SICINIUS.<br>
Not?
</p>

<p class="drama">
COMINIUS.<br>
I tell you, he does sit in gold, his eye<br>
Red as ’twould burn Rome; and his injury<br>
The jailer to his pity. I kneeled before him;<br>
’Twas very faintly he said “Rise”; dismissed me<br>
Thus with his speechless hand. What he would do<br>
He sent in writing after me; what he<br>
Would not, bound with an oath to yield to his<br>
Conditions. So that all hope is vain<br>
Unless his noble mother and his wife,<br>
Who, as I hear, mean to solicit him<br>
For mercy to his country. Therefore let’s hence<br>
And with our fair entreaties haste them on.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneV_6.2"></a><b>SCENE II. An Advanced post of the Volscian camp before Rome.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Menenius</span> to the Watch, or Guard.
</p>

<p class="drama">
FIRST WATCH.<br>
Stay! Whence are you?
</p>

<p class="drama">
SECOND WATCH.<br>
Stand, and go back.
</p>

<p class="drama">
MENENIUS.<br>
You guard like men; ’tis well. But by your leave,<br>
I am an officer of state and come<br>
To speak with Coriolanus.
</p>

<p class="drama">
FIRST WATCH.<br>
From whence?
</p>

<p class="drama">
MENENIUS.<br>
From Rome.
</p>

<p class="drama">
FIRST WATCH.<br>
You may not pass; you must return. Our general<br>
Will no more hear from thence.
</p>

<p class="drama">
SECOND WATCH.<br>
You’ll see your Rome embraced with fire before<br>
You’ll speak with Coriolanus.
</p>

<p class="drama">
MENENIUS.<br>
Good my friends,<br>
If you have heard your general talk of Rome<br>
And of his friends there, it is lots to blanks<br>
My name hath touched your ears. It is Menenius.
</p>

<p class="drama">
FIRST WATCH.<br>
Be it so; go back. The virtue of your name<br>
Is not here passable.
</p>

<p class="drama">
MENENIUS.<br>
I tell thee, fellow,<br>
Thy general is my lover. I have been<br>
The book of his good acts, whence men have read<br>
His fame unparalleled happily amplified;<br>
For I have ever verified my friends—<br>
Of whom he’s chief—with all the size that verity<br>
Would without lapsing suffer. Nay, sometimes,<br>
Like to a bowl upon a subtle ground,<br>
I have tumbled past the throw, and in his praise<br>
Have almost stamped the leasing. Therefore, fellow,<br>
I must have leave to pass.
</p>

<p class="drama">
FIRST WATCH.<br>
Faith, sir, if you had told as many lies in his behalf as you have uttered
words in your own, you should not pass here, no, though it were as virtuous to
lie as to live chastely. Therefore, go back.
</p>

<p class="drama">
MENENIUS.<br>
Prithee, fellow, remember my name is Menenius, always factionary on the party
of your general.
</p>

<p class="drama">
SECOND WATCH.<br>
Howsoever you have been his liar, as you say you have, I am one that, telling
true under him, must say you cannot pass. Therefore go back.
</p>

<p class="drama">
MENENIUS.<br>
Has he dined, can’st thou tell? For I would not speak with him till after
dinner.
</p>

<p class="drama">
FIRST WATCH.<br>
You are a Roman, are you?
</p>

<p class="drama">
MENENIUS.<br>
I am, as thy general is.
</p>

<p class="drama">
FIRST WATCH.<br>
Then you should hate Rome as he does. Can you, when you have pushed out your
gates the very defender of them, and, in a violent popular ignorance given your
enemy your shield, think to front his revenges with the easy groans of old
women, the virginal palms of your daughters, or with the palsied intercession
of such a decayed dotant as you seem to be? Can you think to blow out the
intended fire your city is ready to flame in with such weak breath as this?
No, you are deceived. Therefore back to Rome and prepare for your execution.
You are condemned. Our general has sworn you out of reprieve and pardon.
</p>

<p class="drama">
MENENIUS.<br>
Sirrah, if thy captain knew I were here, he would use me with estimation.
</p>

<p class="drama">
SECOND WATCH.<br>
Come, my captain knows you not.
</p>

<p class="drama">
MENENIUS.<br>
I mean thy general.
</p>

<p class="drama">
FIRST WATCH.<br>
My general cares not for you. Back, I say, go, lest I let forth your half pint
of blood. Back! That’s the utmost of your having. Back!
</p>

<p class="drama">
MENENIUS.<br>
Nay, but fellow, fellow—
</p>

<p class="scenedesc">
Enter <span class="charname">Coriolanus</span> with
<span class="charname">Aufidius</span>.
</p>

<p class="drama">
CORIOLANUS.<br>
What’s the matter?
</p>

<p class="drama">
MENENIUS.<br>
Now, you companion, I’ll say an errand for you. You shall know now that I am in
estimation; you shall perceive that a Jack guardant cannot office me from my
son Coriolanus. Guess but by my entertainment with him if thou stand’st not i’
th’ state of hanging or of some death more long in spectatorship and crueller
in suffering; behold now presently, and swoon for what’s to come upon thee.
[<i>to Coriolanus</i>.] The glorious gods sit in hourly synod about thy
particular prosperity and love thee no worse than thy old father Menenius
does! O my son, my son! Thou art preparing fire for us; look thee, here’s water
to quench it. I was hardly moved to come to thee; but being assured none but
myself could move thee, I have been blown out of your gates with sighs, and
conjure thee to pardon Rome and thy petitionary countrymen. The good gods
assuage thy wrath and turn the dregs of it upon this varlet here, this, who,
like a block, hath denied my access to thee.
</p>

<p class="drama">
CORIOLANUS.<br>
Away!
</p>

<p class="drama">
MENENIUS.<br>
How? Away?
</p>

<p class="drama">
CORIOLANUS.<br>
Wife, mother, child, I know not. My affairs<br>
Are servanted to others. Though I owe<br>
My revenge properly, my remission lies<br>
In Volscian breasts. That we have been familiar,<br>
Ingrate forgetfulness shall poison rather<br>
Than pity note how much. Therefore begone.<br>
Mine ears against your suits are stronger than<br>
Your gates against my force. Yet, for I loved thee,<br>
Take this along; I writ it for thy sake,
</p>

<p class="right">[<i>He gives <span class="charname">Menenius</span> a paper.</i>]</p>

<p class="drama">
And would have sent it. Another word, Menenius,<br>
I will not hear thee speak.—This man, Aufidius,<br>
Was my beloved in Rome; yet thou behold’st.
</p>

<p class="drama">
AUFIDIUS.<br>
You keep a constant temper.
</p>

<p class="right">[<i>They exit.</i>]</p>

<p class="right">
[<i>The <span class="charname">Guard</span> and
<span class="charname">Menenius</span> remain.</i>]
</p>

<p class="drama">
FIRST WATCH.<br>
Now, sir, is your name Menenius?
</p>

<p class="drama">
SECOND WATCH.<br>
’Tis a spell, you see, of much power. You know the way home again.
</p>

<p class="drama">
FIRST WATCH.<br>
Do you hear how we are shent for keeping your Greatness back?
</p>

<p class="drama">
SECOND WATCH.<br>
What cause do you think I have to swoon?
</p>

<p class="drama">
MENENIUS.<br>
I neither care for th’ world nor your general. For such things as you, I can
scarce think there’s any, you’re so slight. He that hath a will to die by
himself fears it not from another. Let your general do his worst. For you, be
that you are, long; and your misery increase with your age! I say to you, as I
was said to, away!
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
FIRST WATCH.<br>
A noble fellow, I warrant him.
</p>

<p class="drama">
SECOND WATCH.<br>
The worthy fellow is our general. He is the rock, the oak not to be
wind-shaken.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneV_6.3"></a><b>SCENE III. The tent of Coriolanus</b></h3>

<p class="scenedesc">
Enter <span class="charname">Coriolanus</span> and
<span class="charname">Aufidius</span>.
</p>

<p class="drama">
CORIOLANUS.<br>
We will before the walls of Rome tomorrow<br>
Set down our host. My partner in this action,<br>
You must report to th’ Volscian lords how plainly<br>
I have borne this business.
</p>

<p class="drama">
AUFIDIUS.<br>
Only their ends<br>
You have respected, stopped your ears against<br>
The general suit of Rome; never admitted<br>
A private whisper, no, not with such friends<br>
That thought them sure of you.
</p>

<p class="drama">
CORIOLANUS.<br>
This last old man,<br>
Whom with cracked heart I have sent to Rome,<br>
Loved me above the measure of a father,<br>
Nay, godded me indeed. Their latest refuge<br>
Was to send him, for whose old love I have—<br>
Though I showed sourly to him—once more offered<br>
The first conditions, which they did refuse<br>
And cannot now accept, to grace him only<br>
That thought he could do more. A very little<br>
I have yielded to. Fresh embassies and suits,<br>
Nor from the state nor private friends, hereafter<br>
Will I lend ear to.
</p>

<p class="right">[<i>Shout within.</i>]</p>

<p class="drama">
Ha? What shout is this?<br>
Shall I be tempted to infringe my vow<br>
In the same time ’tis made? I will not.
</p>

<p class="scenedesc">
Enter <span class="charname">Virgilia, Volumnia, Valeria,</span>
young <span class="charname">Martius</span> with attendants.
</p>

<p class="drama">
My wife comes foremost, then the honoured mold<br>
Wherein this trunk was framed, and in her hand<br>
The grandchild to her blood. But out, affection!<br>
All bond and privilege of nature, break!<br>
Let it be virtuous to be obstinate.<br>
What is that curtsy worth? Or those doves’ eyes,<br>
Which can make gods forsworn? I melt and am not<br>
Of stronger earth than others. My mother bows,<br>
As if Olympus to a molehill should<br>
In supplication nod; and my young boy<br>
Hath an aspect of intercession which<br>
Great Nature cries “Deny not!” Let the Volsces<br>
Plough Rome and harrow Italy, I’ll never<br>
Be such a gosling to obey instinct, but stand<br>
As if a man were author of himself,<br>
And knew no other kin.
</p>

<p class="drama">
VIRGILIA.<br>
My lord and husband.
</p>

<p class="drama">
CORIOLANUS.<br>
These eyes are not the same I wore in Rome.
</p>

<p class="drama">
VIRGILIA.<br>
The sorrow that delivers us thus changed<br>
Makes you think so.
</p>

<p class="drama">
CORIOLANUS.<br>
Like a dull actor now,<br>
I have forgot my part, and I am out,<br>
Even to a full disgrace. Best of my flesh,<br>
Forgive my tyranny, but do not say<br>
For that, “Forgive our Romans.”
</p>

<p class="right">[<i>They kiss.</i>]</p>

<p class="drama">
O, a kiss<br>
Long as my exile, sweet as my revenge!<br>
Now, by the jealous queen of heaven, that kiss<br>
I carried from thee, dear, and my true lip<br>
Hath virgined it e’er since. You gods! I prate<br>
And the most noble mother of the world<br>
Leave unsaluted. Sink, my knee, i’ th’ earth;
</p>

<p class="right">[<i>Kneels.</i>]</p>

<p class="drama">
Of thy deep duty more impression show<br>
Than that of common sons.
</p>

<p class="drama">
VOLUMNIA.<br>
O, stand up blest,
</p>

<p class="right">[<i>He rises</i>.]</p>

<p class="drama">
Whilst with no softer cushion than the flint<br>
I kneel before thee and unproperly<br>
Show duty, as mistaken all this while<br>
Between the child and parent.
</p>

<p class="right">[<i>She kneels.</i>]</p>

<p class="drama">
CORIOLANUS.<br>
What is this?<br>
Your knees to me? To your corrected son?
</p>

<p class="right">[<i>He raises her up.</i>]</p>

<p class="drama">
Then let the pebbles on the hungry beach<br>
Fillip the stars! Then let the mutinous winds<br>
Strike the proud cedars ’gainst the fiery sun,<br>
Murdering impossibility to make<br>
What cannot be slight work.
</p>

<p class="drama">
VOLUMNIA.<br>
Thou art my warrior;<br>
I holp to frame thee. Do you know this lady?
</p>

<p class="drama">
CORIOLANUS.<br>
The noble sister of Publicola,<br>
The moon of Rome, chaste as the icicle<br>
That’s curdied by the frost from purest snow<br>
And hangs on Dian’s temple!—Dear Valeria.
</p>

<p class="drama">
VOLUMNIA.<br>
This is a poor epitome of yours,<br>
Which by th’ interpretation of full time<br>
May show like all yourself.
</p>

<p class="drama">
CORIOLANUS.<br>
The god of soldiers,<br>
With the consent of supreme Jove, inform<br>
Thy thoughts with nobleness, that thou mayst prove<br>
To shame unvulnerable, and stick i’ th’ wars<br>
Like a great seamark standing every flaw<br>
And saving those that eye thee.
</p>

<p class="drama">
VOLUMNIA.<br>
[<i>To young Martius</i>.] Your knee, sirrah.
</p>

<p class="right">[<i>He kneels.</i>]</p>

<p class="drama">
CORIOLANUS.<br>
That’s my brave boy!
</p>

<p class="drama">
VOLUMNIA.<br>
Even he, your wife, this lady, and myself<br>
Are suitors to you.
</p>

<p class="right">[<i>Young <span class="charname">Martius</span> rises.</i>]</p>

<p class="drama">
CORIOLANUS.<br>
I beseech you, peace;<br>
Or, if you’d ask, remember this before:<br>
The thing I have forsworn to grant may never<br>
Be held by you denials. Do not bid me<br>
Dismiss my soldiers or capitulate<br>
Again with Rome’s mechanics. Tell me not<br>
Wherein I seem unnatural; desire not<br>
T’ allay my rages and revenges with<br>
Your colder reasons.
</p>

<p class="drama">
VOLUMNIA.<br>
O, no more, no more!<br>
You have said you will not grant us anything;<br>
For we have nothing else to ask but that<br>
Which you deny already. Yet we will ask,<br>
That if you fail in our request, the blame<br>
May hang upon your hardness. Therefore hear us.
</p>

<p class="drama">
CORIOLANUS.<br>
Aufidius, and you Volsces, mark, for we’ll<br>
Hear naught from Rome in private. Your request?
</p>

<p class="drama">
VOLUMNIA.<br>
Should we be silent and not speak, our raiment<br>
And state of bodies would bewray what life<br>
We have led since thy exile. Think with thyself<br>
How more unfortunate than all living women<br>
Are we come hither; since that thy sight, which should<br>
Make our eyes flow with joy, hearts dance with comforts,<br>
Constrains them weep and shake with fear and sorrow,<br>
Making the mother, wife, and child to see<br>
The son, the husband, and the father tearing<br>
His country’s bowels out. And to poor we<br>
Thine enmity’s most capital. Thou barr’st us<br>
Our prayers to the gods, which is a comfort<br>
That all but we enjoy. For how can we—<br>
Alas, how can we—for our country pray,<br>
Whereto we are bound, together with thy victory,<br>
Whereto we are bound? Alack, or we must lose<br>
The country, our dear nurse, or else thy person,<br>
Our comfort in the country. We must find<br>
An evident calamity, though we had<br>
Our wish, which side should win, for either thou<br>
Must as a foreign recreant be led<br>
With manacles through our streets, or else<br>
Triumphantly tread on thy country’s ruin<br>
And bear the palm for having bravely shed<br>
Thy wife and children’s blood. For myself, son,<br>
I purpose not to wait on fortune till<br>
These wars determine. If I cannot persuade thee<br>
Rather to show a noble grace to both parts<br>
Than seek the end of one, thou shalt no sooner<br>
March to assault thy country than to tread—<br>
Trust to’t, thou shalt not—on thy mother’s womb<br>
That brought thee to this world.
</p>

<p class="drama">
VIRGILIA.<br>
Ay, and mine,<br>
That brought you forth this boy to keep your name<br>
Living to time.
</p>

<p class="drama">
YOUNG MARTIUS.<br>
He shall not tread on me.<br>
I’ll run away till I am bigger, but then I’ll fight.
</p>

<p class="drama">
CORIOLANUS.<br>
Not of a woman’s tenderness to be<br>
Requires nor child nor woman’s face to see.—<br>
I have sat too long.
</p>

<p class="right">[<i>He rises.</i>]</p>

<p class="drama">
VOLUMNIA.<br>
Nay, go not from us thus.<br>
If it were so, that our request did tend<br>
To save the Romans, thereby to destroy<br>
The Volsces whom you serve, you might condemn us<br>
As poisonous of your honour. No, our suit<br>
Is that you reconcile them, while the Volsces<br>
May say “This mercy we have showed,” the Romans<br>
“This we received,” and each in either side<br>
Give the all-hail to thee and cry, “Be blessed<br>
For making up this peace!” Thou know’st, great son,<br>
The end of war’s uncertain, but this certain,<br>
That, if thou conquer Rome, the benefit<br>
Which thou shalt thereby reap is such a name<br>
Whose repetition will be dogged with curses,<br>
Whose chronicle thus writ: “The man was noble,<br>
But with his last attempt he wiped it out;<br>
Destroyed his country, and his name remains<br>
To th’ ensuing age abhorred.” Speak to me, son.<br>
Thou hast affected the fine strains of honour<br>
To imitate the graces of the gods,<br>
To tear with thunder the wide cheeks o’ th’ air<br>
And yet to charge thy sulphur with a bolt<br>
That should but rive an oak. Why dost not speak?<br>
Think’st thou it honourable for a noble man<br>
Still to remember wrongs?—Daughter, speak you.<br>
He cares not for your weeping.—Speak thou, boy.<br>
Perhaps thy childishness will move him more<br>
Than can our reasons.—There’s no man in the world<br>
More bound to’s mother, yet here he lets me prate<br>
Like one i’ th’ stocks. Thou hast never in thy life<br>
Showed thy dear mother any courtesy<br>
When she, poor hen, fond of no second brood,<br>
Has clucked thee to the wars and safely home,<br>
Loaden with honour. Say my request’s unjust<br>
And spurn me back; but if it be not so,<br>
Thou art not honest, and the gods will plague thee<br>
That thou restrain’st from me the duty which<br>
To a mother’s part belongs.—He turns away.—<br>
Down, ladies! Let us shame him with our knees.<br>
To his surname Coriolanus ’longs more pride<br>
Than pity to our prayers. Down! An end.
</p>

<p class="right">[<i>They kneel.</i>]</p>

<p class="drama">
This is the last. So we will home to Rome<br>
And die among our neighbours.—Nay, behold’s.<br>
This boy that cannot tell what he would have,<br>
But kneels and holds up hands for fellowship,<br>
Does reason our petition with more strength<br>
Than thou hast to deny’t.—Come, let us go.
</p>

<p class="right">[<i>They rise.</i>]</p>

<p class="drama">
This fellow had a Volscian to his mother,<br>
His wife is in Corioles, and his child<br>
Like him by chance.—Yet give us our dispatch.<br>
I am hushed until our city be afire,<br>
And then I’ll speak a little.
</p>

<p class="right">[<i>He holds her by the hand, silent.</i>]</p>

<p class="drama">
CORIOLANUS.<br>
O mother, mother!<br>
What have you done? Behold, the heavens do ope,<br>
The gods look down, and this unnatural scene<br>
They laugh at. O my mother, mother, O!<br>
You have won a happy victory to Rome,<br>
But, for your son—believe it, O, believe it!—<br>
Most dangerously you have with him prevailed,<br>
If not most mortal to him. But let it come.—<br>
Aufidius, though I cannot make true wars,<br>
I’ll frame convenient peace. Now, good Aufidius,<br>
Were you in my stead, would you have heard<br>
A mother less? Or granted less, Aufidius?
</p>

<p class="drama">
AUFIDIUS.<br>
I was moved withal.
</p>

<p class="drama">
CORIOLANUS.<br>
I dare be sworn you were.<br>
And, sir, it is no little thing to make<br>
Mine eyes to sweat compassion. But, good sir,<br>
What peace you’ll make, advise me. For my part,<br>
I’ll not to Rome, I’ll back with you; and pray you,<br>
Stand to me in this cause.—O mother!—Wife!
</p>

<p class="right">[<i>He speaks with them aside.</i>]</p>

<p class="drama">
AUFIDIUS.<br>
[<i>Aside</i>.] I am glad thou hast set thy mercy and thy honour<br>
At difference in thee. Out of that I’ll work<br>
Myself a former fortune.
</p>

<p class="drama">
CORIOLANUS.<br>
[<i>To the Women</i>.] Ay, by and by;<br>
But we’ll drink together, and you shall bear<br>
A better witness back than words, which we,<br>
On like conditions, will have countersealed.<br>
Come, enter with us. Ladies, you deserve<br>
To have a temple built you. All the swords<br>
In Italy, and her confederate arms,<br>
Could not have made this peace.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneV_6.4"></a><b>SCENE IV. Rome. A public place</b></h3>

<p class="scenedesc">
Enter <span class="charname">Menenius</span> and
<span class="charname">Sicinius</span>.
</p>

<p class="drama">
MENENIUS.<br>
See you yond coign o’ the Capitol, yond cornerstone?
</p>

<p class="drama">
SICINIUS.<br>
Why, what of that?
</p>

<p class="drama">
MENENIUS.<br>
If it be possible for you to displace it with your little finger, there is some
hope the ladies of Rome, especially his mother, may prevail with him. But I say
there is no hope in’t. Our throats are sentenced and stay upon execution.
</p>

<p class="drama">
SICINIUS.<br>
Is’t possible that so short a time can alter the condition of a man?
</p>

<p class="drama">
MENENIUS.<br>
There is differency between a grub and a butterfly, yet your butterfly was a
grub. This Martius is grown from man to dragon. He has wings; he’s more than a
creeping thing.
</p>

<p class="drama">
SICINIUS.<br>
He loved his mother dearly.
</p>

<p class="drama">
MENENIUS.<br>
So did he me; and he no more remembers his mother now than an eight-year-old
horse. The tartness of his face sours ripe grapes. When he walks, he moves like
an engine, and the ground shrinks before his treading. He is able to pierce a
corslet with his eye, talks like a knell, and his hum is a battery. He sits in
his state as a thing made for Alexander. What he bids be done is finished with
his bidding. He wants nothing of a god but eternity and a heaven to throne in.
</p>

<p class="drama">
SICINIUS.<br>
Yes, mercy, if you report him truly.
</p>

<p class="drama">
MENENIUS.<br>
I paint him in the character. Mark what mercy his mother shall bring from him.
There is no more mercy in him than there is milk in a male tiger. That shall
our poor city find, and all this is long of you.
</p>

<p class="drama">
SICINIUS.<br>
The gods be good unto us.
</p>

<p class="drama">
MENENIUS.<br>
No, in such a case the gods will not be good unto us. When we banished him, we
respected not them; and he returning to break our necks, they respect not us.
</p>

<p class="scenedesc">
Enter a <span class="charname">Messenger</span>.
</p>

<p class="drama">
MESSENGER.<br>
Sir, if you’d save your life, fly to your house.<br>
The plebeians have got your fellow tribune<br>
And hale him up and down, all swearing if<br>
The Roman ladies bring not comfort home,<br>
They’ll give him death by inches.
</p>

<p class="scenedesc">
Enter another <span class="charname">Messenger</span>.
</p>

<p class="drama">
SICINIUS.<br>
What’s the news?
</p>

<p class="drama">
SECOND MESSENGER.<br>
Good news, good news! The ladies have prevailed.<br>
The Volscians are dislodged and Martius gone.<br>
A merrier day did never yet greet Rome,<br>
No, not th’ expulsion of the Tarquins.
</p>

<p class="drama">
SICINIUS.<br>
Friend,<br>
Art thou certain this is true? Is’t most certain?
</p>

<p class="drama">
SECOND MESSENGER.<br>
As certain as I know the sun is fire.<br>
Where have you lurked that you make doubt of it?<br>
Ne’er through an arch so hurried the blown tide<br>
As the recomforted through th’ gates. Why, hark you!
</p>

<p class="right">[<i>Trumpets, hautboys, drums beat, all together.</i>]</p>

<p class="drama">
The trumpets, sackbuts, psalteries, and fifes,<br>
Tabors and cymbals, and the shouting Romans<br>
Make the sun dance. Hark you!
</p>

<p class="right">[<i>A shout within.</i>]</p>

<p class="drama">
MENENIUS.<br>
This is good news.<br>
I will go meet the ladies. This Volumnia<br>
Is worth of consuls, senators, patricians<br>
A city full; of tribunes such as you<br>
A sea and land full. You have prayed well today.<br>
This morning for ten thousand of your throats<br>
I’d not have given a doit. Hark, how they joy!
</p>

<p class="right">[<i>Sound still with the shouts.</i>]</p>

<p class="drama">
SICINIUS.<br>
First, the gods bless you for your tidings; next, accept my thankfulness.
</p>

<p class="drama">
SECOND MESSENGER.<br>
Sir, we have all great cause to give great thanks.
</p>

<p class="drama">
SICINIUS.<br>
They are near the city?
</p>

<p class="drama">
MESSENGER.<br>
Almost at point to enter.
</p>

<p class="drama">
SICINIUS.<br>
We’ll meet them, and help the joy.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneV_6.5"></a><b>SCENE V. Rome. A street near the gate</b></h3>

<p class="scenedesc">
Enter two Senators, with Ladies <span class="charname">(Volumnia, Virgilia,
Valeria)</span> passing over the stage, with other Lords.
</p>

<p class="drama">
SENATOR.<br>
Behold our patroness, the life of Rome!<br>
Call all your tribes together, praise the gods,<br>
And make triumphant fires. Strew flowers before them,<br>
Unshout the noise that banished Martius,<br>
Repeal him with the welcome of his mother.<br>
Cry “Welcome, ladies, welcome!”
</p>

<p class="drama">
ALL.<br>
Welcome, ladies, welcome!
</p>

<p class="right">[<i>A flourish with drums and trumpets.</i>]</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneV_6.6"></a><b>SCENE VI. Antium. A public place</b></h3>

<p class="scenedesc">
Enter <span class="charname">Tullus Aufidius</span> with Attendants.
</p>

<p class="drama">
AUFIDIUS.<br>
Go tell the lords o’ th’ city I am here.<br>
Deliver them this paper.
</p>

<p class="right">[<i>He gives them a paper</i>.]</p>

<p class="drama">
Having read it,<br>
Bid them repair to th’ marketplace, where I,<br>
Even in theirs and in the commons’ ears,<br>
Will vouch the truth of it. Him I accuse<br>
The city ports by this hath entered and<br>
Intends t’ appear before the people, hoping<br>
To purge himself with words. Dispatch.
</p>

<p class="right">[<i>Exeunt Attendants.</i>]</p>

<p class="scenedesc">
Enter three or four <span class="charname">Conspirators</span> of
<span class="charname">Aufidius’s</span> faction.
</p>

<p class="drama">
Most welcome!
</p>

<p class="drama">
FIRST CONSPIRATOR.<br>
How is it with our general?
</p>

<p class="drama">
AUFIDIUS.<br>
Even so<br>
As with a man by his own alms empoisoned<br>
And with his charity slain.
</p>

<p class="drama">
SECOND CONSPIRATOR.<br>
Most noble sir,<br>
If you do hold the same intent wherein<br>
You wished us parties, we’ll deliver you<br>
Of your great danger.
</p>

<p class="drama">
AUFIDIUS.<br>
Sir, I cannot tell.<br>
We must proceed as we do find the people.
</p>

<p class="drama">
THIRD CONSPIRATOR.<br>
The people will remain uncertain whilst<br>
’Twixt you there’s difference, but the fall of either<br>
Makes the survivor heir of all.
</p>

<p class="drama">
AUFIDIUS.<br>
I know it,<br>
And my pretext to strike at him admits<br>
A good construction. I raised him, and I pawned<br>
Mine honour for his truth, who being so heightened,<br>
He watered his new plants with dews of flattery,<br>
Seducing so my friends; and to this end,<br>
He bowed his nature, never known before<br>
But to be rough, unswayable, and free.
</p>

<p class="drama">
THIRD CONSPIRATOR.<br>
Sir, his stoutness<br>
When he did stand for consul, which he lost<br>
By lack of stooping—
</p>

<p class="drama">
AUFIDIUS.<br>
That I would have spoke of.<br>
Being banished for’t, he came unto my hearth,<br>
Presented to my knife his throat. I took him,<br>
Made him joint servant with me, gave him way<br>
In all his own desires; nay, let him choose<br>
Out of my files, his projects to accomplish,<br>
My best and freshest men; served his designments<br>
In mine own person; holp to reap the fame<br>
Which he did end all his; and took some pride<br>
To do myself this wrong; till at the last<br>
I seemed his follower, not partner; and<br>
He waged me with his countenance as if<br>
I had been mercenary.
</p>

<p class="drama">
FIRST CONSPIRATOR.<br>
So he did, my lord.<br>
The army marvelled at it, and, in the last,<br>
When he had carried Rome and that we looked<br>
For no less spoil than glory—
</p>

<p class="drama">
AUFIDIUS.<br>
There was it<br>
For which my sinews shall be stretched upon him.<br>
At a few drops of women’s rheum, which are<br>
As cheap as lies, he sold the blood and labour<br>
Of our great action. Therefore shall he die,<br>
And I’ll renew me in his fall. But, hark!
</p>

<p class="right">[<i>Drums and trumpets sound, with great shouts of the people.</i>]</p>

<p class="drama">
FIRST CONSPIRATOR.<br>
Your native town you entered like a post<br>
And had no welcomes home, but he returns<br>
Splitting the air with noise.
</p>

<p class="drama">
SECOND CONSPIRATOR.<br>
And patient fools,<br>
Whose children he hath slain, their base throats tear<br>
With giving him glory.
</p>

<p class="drama">
THIRD CONSPIRATOR.<br>
Therefore at your vantage,<br>
Ere he express himself or move the people<br>
With what he would say, let him feel your sword,<br>
Which we will second. When he lies along,<br>
After your way his tale pronounced shall bury<br>
His reasons with his body.
</p>

<p class="drama">
AUFIDIUS.<br>
Say no more.<br>
Here come the lords.
</p>

<p class="scenedesc">
Enter the <span class="charname">Lords</span> of the city.
</p>

<p class="drama">
ALL LORDS.<br>
You are most welcome home.
</p>

<p class="drama">
AUFIDIUS.<br>
I have not deserved it.<br>
But, worthy lords, have you with heed perused<br>
What I have written to you?
</p>

<p class="drama">
ALL LORDS.<br>
We have.
</p>

<p class="drama">
FIRST LORD.<br>
And grieve to hear’t.<br>
What faults he made before the last, I think<br>
Might have found easy fines, but there to end<br>
Where he was to begin and give away<br>
The benefit of our levies, answering us<br>
With our own charge, making a treaty where<br>
There was a yielding—this admits no excuse.
</p>

<p class="scenedesc">
Enter <span class="charname">Coriolanus</span> marching with Drum and Colours, the
Commoners being with him.
</p>

<p class="drama">
AUFIDIUS.<br>
He approaches. You shall hear him.
</p>

<p class="drama">
CORIOLANUS.<br>
Hail, lords! I am returned your soldier,<br>
No more infected with my country’s love<br>
Than when I parted hence, but still subsisting<br>
Under your great command. You are to know<br>
That prosperously I have attempted, and<br>
With bloody passage led your wars even to<br>
The gates of Rome. Our spoils we have brought home<br>
Doth more than counterpoise a full third part<br>
The charges of the action. We have made peace<br>
With no less honour to the Antiates<br>
Than shame to th’ Romans, and we here deliver,<br>
Subscribed by th’ Consuls and patricians,<br>
Together with the seal o’ th’ Senate, what<br>
We have compounded on.
</p>

<p class="right">[<i>He offers the lords a paper.</i>]</p>

<p class="drama">
AUFIDIUS.<br>
Read it not, noble lords,<br>
But tell the traitor in the highest degree<br>
He hath abused your powers.
</p>

<p class="drama">
CORIOLANUS.<br>
“Traitor?” How now?
</p>

<p class="drama">
AUFIDIUS.<br>
Ay, traitor, Martius.
</p>

<p class="drama">
CORIOLANUS.<br>
Martius?
</p>

<p class="drama">
AUFIDIUS.<br>
Ay, Martius, Caius Martius. Dost thou think<br>
I’ll grace thee with that robbery, thy stol’n name<br>
Coriolanus, in Corioles?<br>
You lords and heads o’ th’ state, perfidiously<br>
He has betrayed your business and given up<br>
For certain drops of salt your city Rome—<br>
I say your city—to his wife and mother,<br>
Breaking his oath and resolution like<br>
A twist of rotten silk, never admitting<br>
Counsel o’ th’ war, but at his nurse’s tears<br>
He whined and roared away your victory,<br>
That pages blushed at him and men of heart<br>
Looked wond’ring each at other.
</p>

<p class="drama">
CORIOLANUS.<br>
Hear’st thou, Mars?
</p>

<p class="drama">
AUFIDIUS.<br>
Name not the god, thou boy of tears.
</p>

<p class="drama">
CORIOLANUS.<br>
Ha?
</p>

<p class="drama">
AUFIDIUS.<br>
No more.
</p>

<p class="drama">
CORIOLANUS.<br>
Measureless liar, thou hast made my heart<br>
Too great for what contains it. “Boy”? O slave!—<br>
Pardon me, lords, ’tis the first time that ever<br>
I was forced to scold. Your judgments, my grave lords,<br>
Must give this cur the lie; and his own notion—<br>
Who wears my stripes impressed upon him, that<br>
Must bear my beating to his grave—shall join<br>
To thrust the lie unto him.
</p>

<p class="drama">
FIRST LORD.<br>
Peace, both, and hear me speak.
</p>

<p class="drama">
CORIOLANUS.<br>
Cut me to pieces, Volsces. Men and lads,<br>
Stain all your edges on me. “Boy”? False hound!<br>
If you have writ your annals true, ’tis there,<br>
That like an eagle in a dovecote, I<br>
Fluttered your Volscians in Corioles,<br>
Alone I did it. “Boy”!
</p>

<p class="drama">
AUFIDIUS.<br>
Why, noble lords,<br>
Will you be put in mind of his blind fortune,<br>
Which was your shame, by this unholy braggart,<br>
’Fore your own eyes and ears?
</p>

<p class="drama">
ALL CONSPIRATORS.<br>
Let him die for’t.
</p>

<p class="drama">
ALL PEOPLE<br>
Tear him to pieces! Do it presently! He killed my son! My daughter! He killed
my cousin Marcus! He killed my father!
</p>

<p class="drama">
SECOND LORD.<br>
Peace, ho! No outrage! Peace!<br>
The man is noble, and his fame folds in<br>
This orb o’ th’ Earth. His last offences to us<br>
Shall have judicious hearing. Stand, Aufidius,<br>
And trouble not the peace.
</p>

<p class="drama">
CORIOLANUS.<br>
O that I had him,<br>
With six Aufidiuses, or more, his tribe,<br>
To use my lawful sword.
</p>

<p class="drama">
AUFIDIUS.<br>
Insolent villain!
</p>

<p class="drama">
ALL CONSPIRATORS.<br>
Kill, kill, kill, kill, kill him!
</p>


<p class="right">
[<i>Draw the <span class="charname">Conspirators</span>, and kills <span class="charname">Martius</span>, who falls. <span class="charname">Aufidius</span> stands on him.</i>]
</p>

<p class="drama">
LORDS.<br>
Hold, hold, hold, hold!
</p>

<p class="drama">
AUFIDIUS.<br>
My noble masters, hear me speak.
</p>

<p class="drama">
FIRST LORD.<br>
O Tullus!
</p>

<p class="drama">
SECOND LORD.<br>
Thou hast done a deed whereat valour will weep.
</p>

<p class="drama">
THIRD LORD.<br>
Tread not upon him.—Masters, all be quiet.—<br>
Put up your swords.
</p>

<p class="drama">
AUFIDIUS.<br>
My lords, when you shall know—as in this rage,<br>
Provoked by him, you cannot—the great danger<br>
Which this man’s life did owe you, you’ll rejoice<br>
That he is thus cut off. Please it your Honours<br>
To call me to your senate, I’ll deliver<br>
Myself your loyal servant, or endure<br>
Your heaviest censure.
</p>

<p class="drama">
FIRST LORD.<br>
Bear from hence his body,<br>
And mourn you for him. Let him be regarded<br>
As the most noble corse that ever herald<br>
Did follow to his urn.
</p>

<p class="drama">
SECOND LORD.<br>
His own impatience<br>
Takes from Aufidius a great part of blame.<br>
Let’s make the best of it.
</p>

<p class="drama">
AUFIDIUS.<br>
My rage is gone,<br>
And I am struck with sorrow.—Take him up.<br>
Help, three o’ th’ chiefest soldiers; I’ll be one.—<br>
Beat thou the drum that it speak mournfully.—<br>
Trail your steel pikes. Though in this city he<br>
Hath widowed and unchilded many a one,<br>
Which to this hour bewail the injury,<br>
Yet he shall have a noble memory.<br>
Assist.
</p>

<p class="right">[<i>Exeunt, bearing the body of
<span class="charname">Martius</span>. A dead march sounded.</i>]</p>

