<h2> <a id="sceneIV_21.1"></a><b>ACT IV</b></h2>

<h3> <b>SCENE I. A room in Mariana’s house.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Mariana</span> and a
<span class="charname">Boy</span> singing.
</p>

<p class="drama">
                SONG<br>
<i>  Take, O take those lips away,<br>
      That so sweetly were forsworn,<br>
  And those eyes, the break of day,<br>
      Lights that do mislead the morn.<br>
  But my kisses bring again,<br>
                Bring again;<br>
  Seals of love, but sealed in vain,<br>
                Sealed in vain.</i>
</p>

<p class="scenedesc">
Enter <span class="charname">Duke</span> as a Friar.
</p>

<p class="drama">
MARIANA.<br>
Break off thy song, and haste thee quick away;<br>
Here comes a man of comfort, whose advice<br>
Hath often stilled my brawling discontent.
</p>

<p class="right">[<i>Exit <span class="charname">Boy</span>.</i>]</p>

<p class="drama">
I cry you mercy, sir, and well could wish<br>
You had not found me here so musical.<br>
Let me excuse me, and believe me so,<br>
My mirth it much displeased, but pleased my woe.
</p>

<p class="drama">
DUKE.<br>
’Tis good; though music oft hath such a charm<br>
To make bad good and good provoke to harm.<br>
I pray you tell me, hath anybody inquired for me here today? Much upon this
time have I promised here to meet.
</p>

<p class="drama">
MARIANA.<br>
You have not been inquired after. I have sat here all day.
</p>

<p class="scenedesc">
Enter <span class="charname">Isabella</span>.
</p>

<p class="drama">
DUKE.<br>
I do constantly believe you. The time is come even now. I shall crave your
forbearance a little. Maybe I will call upon you anon for some advantage to
yourself.
</p>

<p class="drama">
MARIANA.<br>
I am always bound to you.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
DUKE.<br>
Very well met, and welcome.<br>
What is the news from this good deputy?
</p>

<p class="drama">
ISABELLA.<br>
He hath a garden circummured with brick,<br>
Whose western side is with a vineyard backed;<br>
And to that vineyard is a planched gate<br>
That makes his opening with this bigger key.<br>
This other doth command a little door<br>
Which from the vineyard to the garden leads;<br>
There have I made my promise, upon the<br>
Heavy middle of the night to call on him.
</p>

<p class="drama">
DUKE.<br>
But shall you on your knowledge find this way?
</p>

<p class="drama">
ISABELLA.<br>
I have ta’en a due and wary note upon’t;<br>
With whispering and most guilty diligence,<br>
In action all of precept, he did show me<br>
The way twice o’er.
</p>

<p class="drama">
DUKE.<br>
Are there no other tokens<br>
Between you ’greed concerning her observance?
</p>

<p class="drama">
ISABELLA.<br>
No, none, but only a repair i’ th’ dark,<br>
And that I have possessed him my most stay<br>
Can be but brief, for I have made him know<br>
I have a servant comes with me along,<br>
That stays upon me; whose persuasion is<br>
I come about my brother.
</p>

<p class="drama">
DUKE.<br>
’Tis well borne up.<br>
I have not yet made known to Mariana<br>
A word of this.—What ho, within! Come forth.
</p>

<p class="scenedesc">
Enter <span class="charname">Mariana</span>.
</p>

<p class="drama">
I pray you be acquainted with this maid;<br>
She comes to do you good.
</p>

<p class="drama">
ISABELLA.<br>
I do desire the like.
</p>

<p class="drama">
DUKE.<br>
Do you persuade yourself that I respect you?
</p>

<p class="drama">
MARIANA.<br>
Good friar, I know you do, and have found it.
</p>

<p class="drama">
DUKE.<br>
Take, then, this your companion by the hand,<br>
Who hath a story ready for your ear.<br>
I shall attend your leisure; but make haste.<br>
The vaporous night approaches.
</p>

<p class="drama">
MARIANA.<br>
Will’t please you walk aside?
</p>

<p class="right">
[<i>Exeunt <span class="charname">Mariana</span> and
<span class="charname">Isabella</span>.</i>]
</p>

<p class="drama">
DUKE.<br>
O place and greatness, millions of false eyes<br>
Are stuck upon thee; volumes of report<br>
Run with these false, and most contrarious quest<br>
Upon thy doings; thousand escapes of wit<br>
Make thee the father of their idle dream<br>
And rack thee in their fancies.
</p>

<p class="scenedesc">
Enter <span class="charname">Mariana</span> and
<span class="charname">Isabella</span>.
</p>

<p class="drama">
Welcome; how agreed?
</p>

<p class="drama">
ISABELLA.<br>
She’ll take the enterprise upon her, father,<br>
If you advise it.
</p>

<p class="drama">
DUKE.<br>
It is not my consent,<br>
But my entreaty too.
</p>

<p class="drama">
ISABELLA.<br>
Little have you to say<br>
When you depart from him, but, soft and low,<br>
“Remember now my brother.”
</p>

<p class="drama">
MARIANA.<br>
Fear me not.
</p>

<p class="drama">
DUKE.<br>
Nor, gentle daughter, fear you not at all.<br>
He is your husband on a pre-contract.<br>
To bring you thus together ’tis no sin,<br>
Sith that the justice of your title to him<br>
Doth flourish the deceit. Come, let us go;<br>
Our corn’s to reap, for yet our tithe’s to sow.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneIV_21.2"></a><b>SCENE II. A room in the prison.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Provost</span> and
<span class="charname">Pompey</span>.
</p>

<p class="drama">
PROVOST.<br>
Come hither, sirrah. Can you cut off a man’s head?
</p>

<p class="drama">
POMPEY.<br>
If the man be a bachelor, sir, I can; but if he be a married man, he’s
his wife’s head, and I can never cut off a woman’s head.
</p>

<p class="drama">
PROVOST.<br>
Come, sir, leave me your snatches, and yield me a direct answer. Tomorrow
morning are to die Claudio and Barnardine. Here is in our prison a common
executioner, who in his office lacks a helper; if you will take it on you to
assist him, it shall redeem you from your gyves; if not, you shall have your
full time of imprisonment, and your deliverance with an unpitied whipping; for
you have been a notorious bawd.
</p>

<p class="drama">
POMPEY.<br>
Sir, I have been an unlawful bawd time out of mind, but yet I will be content
to be a lawful hangman. I would be glad to receive some instruction from my
fellow-partner.
</p>

<p class="drama">
PROVOST.<br>
What ho, Abhorson! Where’s Abhorson, there?
</p>

<p class="scenedesc">
Enter <span class="charname">Abhorson</span>.
</p>

<p class="drama">
ABHORSON.<br>
Do you call, sir?
</p>

<p class="drama">
PROVOST.<br>
Sirrah, here’s a fellow will help you tomorrow in your execution. If you think
it meet, compound with him by the year, and let him abide here with you; if
not, use him for the present, and dismiss him. He cannot plead his estimation
with you; he hath been a bawd.
</p>

<p class="drama">
ABHORSON.<br>
A bawd, sir? Fie upon him, he will discredit our mystery.
</p>

<p class="drama">
PROVOST.<br>
Go to, sir; you weigh equally. A feather will turn the scale.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
POMPEY.<br>
Pray, sir, by your good favour—for surely, sir, a good favour you have, but
that you have a hanging look—do you call, sir, your occupation a mystery?
</p>

<p class="drama">
ABHORSON.<br>
Ay, sir, a mystery.
</p>

<p class="drama">
POMPEY.<br>
Painting, sir, I have heard say, is a mystery; and your whores, sir, being
members of my occupation, using painting, do prove my occupation a mystery. But
what mystery there should be in hanging, if I should be hanged, I cannot
imagine.
</p>

<p class="drama">
ABHORSON.<br>
Sir, it is a mystery.
</p>

<p class="drama">
POMPEY.<br>
Proof.
</p>

<p class="drama">
ABHORSON.<br>
Every true man’s apparel fits your thief. If it be too little for your thief,
your true man thinks it big enough; if it be too big for your thief, your thief
thinks it little enough. So every true man’s apparel fits your thief.
</p>

<p class="scenedesc">
Enter <span class="charname">Provost</span>.
</p>

<p class="drama">
PROVOST.<br>
Are you agreed?
</p>

<p class="drama">
POMPEY.<br>
Sir, I will serve him; for I do find your hangman is a more penitent trade than
your bawd. He doth oftener ask forgiveness.</p>

<p class="drama">
PROVOST.<br>
You, sirrah, provide your block and your axe tomorrow four o’clock.</p>

<p class="drama">
ABHORSON.<br>
Come on, bawd. I will instruct thee in my trade. Follow.
</p>

<p class="drama">
POMPEY.<br>
I do desire to learn, sir; and I hope, if you have occasion to use me for your
own turn, you shall find me yare. For truly, sir, for your kindness I owe you a
good turn.</p>

<p class="drama">
PROVOST.<br>
Call hither Barnardine and Claudio.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Abhorson</span> and
<span class="charname">Pompey</span>.</i>]
</p>

<p class="drama">
Th’ one has my pity; not a jot the other,<br>
Being a murderer, though he were my brother.
</p>

<p class="scenedesc">
Enter <span class="charname">Claudio</span>.
</p>

<p class="drama">
Look, here’s the warrant, Claudio, for thy death.<br>
’Tis now dead midnight, and by eight tomorrow<br>
Thou must be made immortal. Where’s Barnardine?
</p>

<p class="drama">
CLAUDIO.<br>
As fast locked up in sleep as guiltless labour<br>
When it lies starkly in the traveller’s bones.<br>
He will not wake.
</p>

<p class="drama">
PROVOST.<br>
Who can do good on him?<br>
Well, go, prepare yourself. [<i>Knocking within</i>.] But hark, what noise?<br>
Heaven give your spirits comfort!
</p>

<p class="right">[<i>Exit <span class="charname">Claudio</span>. Knock within.</i>]</p>

<p class="drama">
By and by!—<br>
I hope it is some pardon or reprieve<br>
For the most gentle Claudio.
</p>

<p class="scenedesc">
Enter <span class="charname">Duke</span>.
</p>

<p class="drama">
Welcome, father.
</p>

<p class="drama">
DUKE.<br>
The best and wholesom’st spirits of the night<br>
Envelop you, good Provost! Who called here of late?
</p>

<p class="drama">
PROVOST.<br>
None, since the curfew rung.
</p>

<p class="drama">
DUKE.<br>
Not Isabel?
</p>

<p class="drama">
PROVOST.<br>
No.
</p>

<p class="drama">
DUKE.<br>
They will then, ere’t be long.
</p>

<p class="drama">
PROVOST.<br>
What comfort is for Claudio?
</p>

<p class="drama">
DUKE.<br>
There’s some in hope.
</p>

<p class="drama">
PROVOST.<br>
It is a bitter deputy.
</p>

<p class="drama">
DUKE.<br>
Not so, not so. His life is paralleled<br>
Even with the stroke and line of his great justice.<br>
He doth with holy abstinence subdue<br>
That in himself which he spurs on his power<br>
To qualify in others. Were he mealed with that<br>
Which he corrects, then were he tyrannous;<br>
But this being so, he’s just.
</p>

<p class="right">
[<i>Knocking within. <span class="charname">Provost</span> goes
to the door.</i>]</p>

<p class="drama">
Now are they come.<br>
This is a gentle provost. Seldom when<br>
The steeled gaoler is the friend of men.
</p>

<p class="right">
[<i>Knocking within</i>.]
</p>

<p class="drama">
How now? What noise? That spirit’s possessed with haste<br>
That wounds th’ unsisting postern with these strokes.
</p>

<p class="scenedesc">
<span class="charname">Provost</span> returns.
</p>

<p class="drama">
PROVOST.<br>
There he must stay until the officer<br>
Arise to let him in. He is called up.
</p>

<p class="drama">
DUKE.<br>
Have you no countermand for Claudio yet,<br>
But he must die tomorrow?
</p>

<p class="drama">
PROVOST.<br>
None, sir, none.
</p>

<p class="drama">
DUKE.<br>
As near the dawning, Provost, as it is,<br>
You shall hear more ere morning.
</p>

<p class="drama">
PROVOST.<br>
Happily<br>
You something know, yet I believe there comes<br>
No countermand. No such example have we.<br>
Besides, upon the very siege of justice<br>
Lord Angelo hath to the public ear<br>
Professed the contrary.
</p>

<p class="scenedesc">
Enter a <span class="charname">Messenger</span>.
</p>

<p class="drama">
This is his Lordship’s man.
</p>

<p class="drama">
DUKE.<br>
And here comes Claudio’s pardon.
</p>

<p class="drama">
MESSENGER.<br>
My lord hath sent you this note, and by me this further charge: that you swerve
not from the smallest article of it, neither in time, matter, or other
circumstance. Good morrow; for, as I take it, it is almost day.
</p>

<p class="drama">
PROVOST.<br>
I shall obey him.
</p>

<p class="right">[<i>Exit <span class="charname">Messenger</span>.</i>]</p>

<p class="drama">
DUKE.<br>
[<i>Aside</i>.] This is his pardon, purchased by such sin<br>
For which the pardoner himself is in.<br>
Hence hath offence his quick celerity,<br>
When it is borne in high authority.<br>
When vice makes mercy, mercy’s so extended<br>
That for the fault’s love is th’ offender friended.<br>
Now, sir, what news?
</p>

<p class="drama">
PROVOST.<br>
I told you: Lord Angelo, belike thinking me remiss in mine office, awakens me
with this unwonted putting-on; methinks strangely, for he hath not used it
before.</p>

<p class="drama">
DUKE.<br>
Pray you, let’s hear.
</p>

<p class="drama">
PROVOST.<br>
[<i>Reads</i>.] <i>Whatsoever you may hear to the contrary, let Claudio be
executed by four of the clock, and in the afternoon, Barnardine. For my better
satisfaction, let me have Claudio’s head sent me by five. Let this be
duly performed, with a thought that more depends on it than we must yet
deliver. Thus fail not to do your office, as you will answer it at your
peril.</i><br>
What say you to this, sir?</p>

<p class="drama">
DUKE.<br>
What is that Barnardine who is to be executed in th’ afternoon?
</p>

<p class="drama">
PROVOST.<br>
A Bohemian born, but here nursed up and bred; one that is a prisoner nine years
old.</p>

<p class="drama">
DUKE.<br>
How came it that the absent Duke had not either delivered him to his liberty,
or executed him? I have heard it was ever his manner to do so.</p>

<p class="drama">
PROVOST.<br>
His friends still wrought reprieves for him; and indeed, his fact till now in
the government of Lord Angelo, came not to an undoubtful proof.</p>

<p class="drama">
DUKE.<br>
It is now apparent?
</p>

<p class="drama">
PROVOST.<br>
Most manifest, and not denied by himself.
</p>

<p class="drama">
DUKE.<br>
Hath he borne himself penitently in prison? How seems he to be touched?</p>

<p class="drama">
PROVOST.<br>
A man that apprehends death no more dreadfully but as a drunken sleep;
careless, reckless, and fearless of what’s past, present, or to come;
insensible of mortality and desperately mortal.
</p>

<p class="drama">
DUKE.<br>
He wants advice.
</p>

<p class="drama">
PROVOST.<br>
He will hear none. He hath evermore had the liberty of the prison; give him
leave to escape hence, he would not. Drunk many times a day, if not many days
entirely drunk. We have very oft awaked him, as if to carry him to execution,
and showed him a seeming warrant for it. It hath not moved him at all.
</p>

<p class="drama">
DUKE.<br>
More of him anon. There is written in your brow, Provost, honesty and
constancy; if I read it not truly, my ancient skill beguiles me. But in the
boldness of my cunning I will lay myself in hazard. Claudio, whom here you have
warrant to execute, is no greater forfeit to the law than Angelo who hath
sentenced him. To make you understand this in a manifested effect, I crave but
four days’ respite, for the which you are to do me both a present and a
dangerous courtesy.
</p>

<p class="drama">
PROVOST.<br>
Pray, sir, in what?
</p>

<p class="drama">
DUKE.<br>
In the delaying death.
</p>

<p class="drama">
PROVOST.<br>
Alack, how may I do it? Having the hour limited, and an express command, under
penalty, to deliver his head in the view of Angelo? I may make my case as
Claudio’s, to cross this in the smallest.
</p>

<p class="drama">
DUKE.<br>
By the vow of mine order, I warrant you, if my instructions may be your guide.
Let this Barnardine be this morning executed, and his head borne to Angelo.</p>

<p class="drama">
PROVOST.<br>
Angelo hath seen them both, and will discover the favour.
</p>

<p class="drama">
DUKE.<br>
O, death’s a great disguiser, and you may add to it. Shave the head and
tie the beard, and say it was the desire of the penitent to be so bared before
his death. You know the course is common. If anything fall to you upon this,
more than thanks and good fortune, by the saint whom I profess, I will plead
against it with my life.
</p>

<p class="drama">
PROVOST.<br>
Pardon me, good father; it is against my oath.
</p>

<p class="drama">
DUKE.<br>
Were you sworn to the Duke, or to the Deputy?
</p>

<p class="drama">
PROVOST.<br>
To him and to his substitutes.
</p>

<p class="drama">
DUKE.<br>
You will think you have made no offence if the Duke avouch the justice of your
dealing?</p>

<p class="drama">
PROVOST.<br>
But what likelihood is in that?
</p>

<p class="drama">
DUKE.<br>
Not a resemblance, but a certainty. Yet since I see you fearful, that neither
my coat, integrity, nor persuasion, can with ease attempt you, I will go
further than I meant, to pluck all fears out of you. Look you, sir, here is the
hand and seal of the Duke. You know the character, I doubt not, and the signet
is not strange to you.
</p>

<p class="drama">
PROVOST.<br>
I know them both.
</p>

<p class="drama">
DUKE.<br>
The contents of this is the return of the Duke; you shall anon over-read it at
your pleasure, where you shall find within these two days he will be here. This
is a thing that Angelo knows not; for he this very day receives letters of
strange tenour, perchance of the Duke’s death, perchance entering into
some monastery; but, by chance, nothing of what is writ. Look, th’ unfolding
star calls up the shepherd. Put not yourself into amazement how these things
should be. All difficulties are but easy when they are known. Call your
executioner, and off with Barnardine’s head. I will give him a present
shrift, and advise him for a better place. Yet you are amazed; but this shall
absolutely resolve you. Come away; it is almost clear dawn.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneIV_21.3"></a><b>SCENE III. Another room in the same.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Pompey</span>.
</p>

<p class="drama">
POMPEY.<br>
I am as well acquainted here as I was in our house of profession. One would
think it were Mistress Overdone’s own house, for here be many of her old
customers. First, here’s young Master Rash; he’s in for a commodity of brown
paper and old ginger, nine score and seventeen pounds; of which he made five
marks ready money. Marry, then ginger was not much in request, for the old
women were all dead. Then is there here one Master Caper, at the suit of Master
Three-pile the mercer, for some four suits of peach-coloured satin, which now
peaches him a beggar. Then have we here young Dizie, and young Master Deep-vow,
and Master Copperspur, and Master Starve-lackey, the rapier and dagger man, and
young Drop-heir that killed lusty Pudding, and Master Forthright the tilter,
and brave Master Shoe-tie the great traveller, and wild Half-can that stabbed
Pots, and I think forty more, all great doers in our trade, and are now “for
the Lord’s sake.”
</p>

<p class="scenedesc">
Enter <span class="charname">Abhorson</span>.
</p>

<p class="drama">
ABHORSON.<br>
Sirrah, bring Barnardine hither.
</p>

<p class="drama">
POMPEY.<br>
Master Barnardine! You must rise and be hanged, Master Barnardine.
</p>

<p class="drama">
ABHORSON.<br>
What ho, Barnardine!
</p>

<p class="drama">
BARNARDINE.<br>
[<i>Within</i>.] A pox o’ your throats! Who makes that noise there? What are
you?</p>

<p class="drama">
POMPEY.<br>
Your friends, sir; the hangman. You must be so good, sir, to rise and be put to
death.</p>

<p class="drama">
BARNARDINE.<br>
[<i>Within</i>.] Away, you rogue, away; I am sleepy.
</p>

<p class="drama">
ABHORSON.<br>
Tell him he must awake, and that quickly too.
</p>

<p class="drama">
POMPEY.<br>
Pray, Master Barnardine, awake till you are executed, and sleep afterwards.
</p>

<p class="drama">
ABHORSON.<br>
Go in to him, and fetch him out.
</p>

<p class="drama">
POMPEY.<br>
He is coming, sir, he is coming. I hear his straw rustle.
</p>

<p class="scenedesc">
Enter <span class="charname">Barnardine</span>.
</p>

<p class="drama">
ABHORSON.<br>
Is the axe upon the block, sirrah?
</p>

<p class="drama">
POMPEY.<br>
Very ready, sir.
</p>

<p class="drama">
BARNARDINE.<br>
How now, Abhorson? What’s the news with you?
</p>

<p class="drama">
ABHORSON.<br>
Truly, sir, I would desire you to clap into your prayers; for, look you, the
warrant’s come.
</p>

<p class="drama">
BARNARDINE.<br>
You rogue, I have been drinking all night; I am not fitted for’t.
</p>

<p class="drama">
POMPEY.<br>
O, the better, sir; for he that drinks all night and is hanged betimes in the
morning may sleep the sounder all the next day.
</p>

<p class="scenedesc">
Enter <span class="charname">Duke</span>.
</p>

<p class="drama">
ABHORSON.<br>
Look you, sir, here comes your ghostly father. Do we jest now, think you?
</p>

<p class="drama">
DUKE.<br>
Sir, induced by my charity, and hearing how hastily you are to depart, I am
come to advise you, comfort you, and pray with you.</p>

<p class="drama">
BARNARDINE.<br>
Friar, not I. I have been drinking hard all night, and I will have more time to
prepare me, or they shall beat out my brains with billets. I will not consent
to die this day, that’s certain.</p>

<p class="drama">
DUKE.<br>
O, sir, you must; and therefore I beseech you<br>
Look forward on the journey you shall go.
</p>

<p class="drama">
BARNARDINE.<br>
I swear I will not die today for any man’s persuasion.
</p>

<p class="drama">
DUKE.<br>
But hear you—
</p>

<p class="drama">
BARNARDINE.<br>
Not a word. If you have anything to say to me, come to my ward, for thence will
not I today.</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
DUKE.<br>
Unfit to live or die. O gravel heart!<br>
After him, fellows; bring him to the block.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Abhorson</span> and
<span class="charname">Pompey</span>.</i>]
</p>

<p class="scenedesc">
Enter <span class="charname">Provost</span>.
</p>

<p class="drama">
PROVOST.<br>
Now, sir, how do you find the prisoner?
</p>

<p class="drama">
DUKE.<br>
A creature unprepared, unmeet for death;<br>
And to transport him in the mind he is<br>
Were damnable.
</p>

<p class="drama">
PROVOST.<br>
Here in the prison, father,<br>
There died this morning of a cruel fever<br>
One Ragozine, a most notorious pirate,<br>
A man of Claudio’s years; his beard and head<br>
Just of his colour. What if we do omit<br>
This reprobate till he were well inclined,<br>
And satisfy the Deputy with the visage<br>
Of Ragozine, more like to Claudio?
</p>

<p class="drama">
DUKE.<br>
O, ’tis an accident that heaven provides!<br>
Dispatch it presently; the hour draws on<br>
Prefixed by Angelo. See this be done,<br>
And sent according to command, whiles I<br>
Persuade this rude wretch willingly to die.
</p>

<p class="drama">
PROVOST.<br>
This shall be done, good father, presently.<br>
But Barnardine must die this afternoon;<br>
And how shall we continue Claudio,<br>
To save me from the danger that might come<br>
If he were known alive?
</p>

<p class="drama">
DUKE.<br>
Let this be done:<br>
Put them in secret holds, both Barnardine and Claudio.<br>
Ere twice the sun hath made his journal greeting<br>
To yonder generation, you shall find<br>
Your safety manifested.
</p>

<p class="drama">
PROVOST.<br>
I am your free dependant.
</p>

<p class="drama">
DUKE.<br>
Quick, dispatch, and send the head to Angelo.
</p>

<p class="right">[<i>Exit <span class="charname">Provost</span>.</i>]</p>

<p class="drama">
Now will I write letters to Angelo,<br>
The Provost, he shall bear them, whose contents<br>
Shall witness to him I am near at home;<br>
And that by great injunctions I am bound<br>
To enter publicly. Him I’ll desire<br>
To meet me at the consecrated fount,<br>
A league below the city; and from thence,<br>
By cold gradation and well-balanced form.<br>
We shall proceed with Angelo.
</p>

<p class="scenedesc">
Enter <span class="charname">Provost</span>.
</p>

<p class="drama">
PROVOST.<br>
Here is the head; I’ll carry it myself.
</p>

<p class="drama">
DUKE.<br>
Convenient is it. Make a swift return;<br>
For I would commune with you of such things<br>
That want no ear but yours.
</p>

<p class="drama">
PROVOST.<br>
I’ll make all speed.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
ISABELLA.<br>
[<i>Within</i>.] Peace, ho, be here!
</p>

<p class="drama">
DUKE.<br>
The tongue of Isabel. She’s come to know<br>
If yet her brother’s pardon be come hither.<br>
But I will keep her ignorant of her good,<br>
To make her heavenly comforts of despair<br>
When it is least expected.
</p>

<p class="scenedesc">
Enter <span class="charname">Isabella</span>.
</p>

<p class="drama">
ISABELLA.<br>
Ho, by your leave!
</p>

<p class="drama">
DUKE.<br>
Good morning to you, fair and gracious daughter.
</p>

<p class="drama">
ISABELLA.<br>
The better, given me by so holy a man.<br>
Hath yet the Deputy sent my brother’s pardon?
</p>

<p class="drama">
DUKE.<br>
He hath released him, Isabel, from the world.<br>
His head is off, and sent to Angelo.
</p>

<p class="drama">
ISABELLA.<br>
Nay, but it is not so.
</p>

<p class="drama">
DUKE.<br>
It is no other.<br>
Show your wisdom, daughter, in your close patience.
</p>

<p class="drama">
ISABELLA.<br>
O, I will to him and pluck out his eyes!
</p>

<p class="drama">
DUKE.<br>
You shall not be admitted to his sight.
</p>

<p class="drama">
ISABELLA.<br>
Unhappy Claudio! Wretched Isabel!<br>
Injurious world! Most damned Angelo!
</p>

<p class="drama">
DUKE.<br>
This nor hurts him nor profits you a jot.<br>
Forbear it, therefore; give your cause to heaven.<br>
Mark what I say, which you shall find<br>
By every syllable a faithful verity.<br>
The Duke comes home tomorrow;—nay, dry your eyes.<br>
One of our convent, and his confessor,<br>
Gives me this instance. Already he hath carried<br>
Notice to Escalus and Angelo,<br>
Who do prepare to meet him at the gates,<br>
There to give up their power. If you can, pace your wisdom<br>
In that good path that I would wish it go,<br>
And you shall have your bosom on this wretch,<br>
Grace of the Duke, revenges to your heart,<br>
And general honour.
</p>

<p class="drama">
ISABELLA.<br>
I am directed by you.
</p>

<p class="drama">
DUKE.<br>
This letter, then, to Friar Peter give;<br>
’Tis that he sent me of the Duke’s return.<br>
Say, by this token, I desire his company<br>
At Mariana’s house tonight. Her cause and yours<br>
I’ll perfect him withal, and he shall bring you<br>
Before the Duke; and to the head of Angelo<br>
Accuse him home and home. For my poor self,<br>
I am combined by a sacred vow,<br>
And shall be absent. Wend you with this letter.<br>
Command these fretting waters from your eyes<br>
With a light heart; trust not my holy order,<br>
If I pervert your course.—Who’s here?
</p>

<p class="scenedesc">
Enter <span class="charname">Lucio</span>.
</p>

<p class="drama">
LUCIO.<br>
Good even. Friar, where is the Provost?
</p>

<p class="drama">
DUKE.<br>
Not within, sir.
</p>

<p class="drama">
LUCIO.<br>
O pretty Isabella, I am pale at mine heart to see thine eyes so red. Thou must
be patient. I am fain to dine and sup with water and bran. I dare not for my
head fill my belly. One fruitful meal would set me to’t. But they say the
Duke will be here tomorrow. By my troth, Isabel, I loved thy brother. If the
old fantastical duke of dark corners had been at home, he had lived.
</p>

<p class="right">[<i>Exit <span class="charname">Isabella</span>.</i>]</p>

<p class="drama">
DUKE.<br>
Sir, the Duke is marvellous little beholding to your reports; but the best is,
he lives not in them.</p>

<p class="drama">
LUCIO.<br>
Friar, thou knowest not the Duke so well as I do. He’s a better woodman
than thou tak’st him for.
</p>

<p class="drama">
DUKE.<br>
Well, you’ll answer this one day. Fare ye well.
</p>

<p class="drama">
LUCIO.<br>
Nay, tarry, I’ll go along with thee. I can tell thee pretty tales of the Duke.
</p>

<p class="drama">
DUKE.<br>
You have told me too many of him already, sir, if they be true; if not true,
none were enough.</p>

<p class="drama">
LUCIO.<br>
I was once before him for getting a wench with child.
</p>

<p class="drama">
DUKE.<br>
Did you such a thing?
</p>

<p class="drama">
LUCIO.<br>
Yes, marry, did I; but I was fain to forswear it. They would else have married
me to the rotten medlar.</p>

<p class="drama">
DUKE.<br>
Sir, your company is fairer than honest. Rest you well.
</p>

<p class="drama">
LUCIO.<br>
By my troth, I’ll go with thee to the lane’s end. If bawdy talk
offend you, we’ll have very little of it. Nay, friar, I am a kind of
burr; I shall stick.</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneIV_21.4"></a><b>SCENE IV. A room in Angelo’s house.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Angelo</span> and
<span class="charname">Escalus</span>.
</p>

<p class="drama">
ESCALUS.<br>
Every letter he hath writ hath disvouched other.
</p>

<p class="drama">
ANGELO.<br>
In most uneven and distracted manner. His actions show much like to madness;
pray heaven his wisdom be not tainted. And why meet him at the gates and
redeliver our authorities there?
</p>

<p class="drama">
ESCALUS.<br>
I guess not.
</p>

<p class="drama">
ANGELO.<br>
And why should we proclaim it in an hour before his entering, that if any crave
redress of injustice, they should exhibit their petitions in the street?
</p>

<p class="drama">
ESCALUS.<br>
He shows his reason for that: to have a dispatch of complaints, and to deliver
us from devices hereafter, which shall then have no power to stand against
us.</p>

<p class="drama">
ANGELO.<br>
Well, I beseech you, let it be proclaimed.<br>
Betimes i’ th’ morn I’ll call you at your house.<br>
Give notice to such men of sort and suit<br>
As are to meet him.
</p>

<p class="drama">
ESCALUS.<br>
I shall, sir. Fare you well.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
ANGELO.<br>
Good night.<br>
This deed unshapes me quite, makes me unpregnant<br>
And dull to all proceedings. A deflowered maid;<br>
And by an eminent body that enforced<br>
The law against it! But that her tender shame<br>
Will not proclaim against her maiden loss,<br>
How might she tongue me! Yet reason dares her no,<br>
For my authority bears so credent bulk<br>
That no particular scandal once can touch<br>
But it confounds the breather. He should have lived,<br>
Save that his riotous youth, with dangerous sense,<br>
Might in the times to come have ta’en revenge<br>
By so receiving a dishonoured life<br>
With ransom of such shame. Would yet he had lived.<br>
Alack, when once our grace we have forgot,<br>
Nothing goes right; we would, and we would not.
</p>

<p class="right">[<i>Exit.</i>]</p>

<h3> <a id="sceneIV_21.5"></a><b>SCENE V. Fields without the town.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Duke,</span> in his own habit, and
<span class="charname">Friar Peter</span>.
</p>

<p class="drama">
DUKE.<br>
These letters at fit time deliver me.<br>
The Provost knows our purpose and our plot.<br>
The matter being afoot, keep your instruction<br>
And hold you ever to our special drift,<br>
Though sometimes you do blench from this to that<br>
As cause doth minister. Go call at Flavius’ house,<br>
And tell him where I stay. Give the like notice<br>
To Valencius, Rowland, and to Crassus,<br>
And bid them bring the trumpets to the gate.<br>
But send me Flavius first.
</p>

<p class="drama">
FRIAR PETER.<br>
It shall be speeded well.
</p>

<p class="right">[<i>Exit <span class="charname">Friar Peter</span>.</i>]</p>

<p class="scenedesc">
Enter <span class="charname">Varrius</span>.
</p>

<p class="drama">
DUKE.<br>
I thank thee, Varrius, thou hast made good haste.<br>
Come, we will walk. There’s other of our friends<br>
Will greet us here anon. My gentle Varrius.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneIV_21.6"></a><b>SCENE VI. Street near the city gate.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Isabella</span> and
<span class="charname">Mariana</span>.
</p>

<p class="drama">
ISABELLA.<br>
To speak so indirectly I am loath;<br>
I would say the truth, but to accuse him so<br>
That is your part; yet I am advised to do it,<br>
He says, to veil full purpose.
</p>

<p class="drama">
MARIANA.<br>
Be ruled by him.
</p>

<p class="drama">
ISABELLA.<br>
Besides, he tells me that, if peradventure<br>
He speak against me on the adverse side,<br>
I should not think it strange, for ’tis a physic<br>
That’s bitter to sweet end.
</p>

<p class="drama">
MARIANA.<br>
I would Friar Peter—
</p>

<p class="scenedesc">
Enter <span class="charname">Friar Peter</span>.
</p>

<p class="drama">
ISABELLA.<br>
O, peace, the friar is come.
</p>

<p class="drama">
FRIAR PETER.<br>
Come, I have found you out a stand most fit,<br>
Where you may have such vantage on the Duke<br>
He shall not pass you. Twice have the trumpets sounded.<br>
The generous and gravest citizens<br>
Have hent the gates, and very near upon<br>
The Duke is entering. Therefore hence, away.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

