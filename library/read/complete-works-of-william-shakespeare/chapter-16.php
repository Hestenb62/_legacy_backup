<h2> <a id="sceneV_3.1"></a><b>ACT V</b></h2>

<h3> <b>SCENE I. Caesar’s Camp before Alexandria.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Caesar, Agrippa, Dolabella, Maecenas, Gallus,
Proculeius</span> with his council of war.
</p>

<p class="drama">
CAESAR.<br>
Go to him, Dolabella, bid him yield.<br>
Being so frustrate, tell him, he mocks<br>
The pauses that he makes.
</p>

<p class="drama">
DOLABELLA.<br>
Caesar, I shall.
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="scenedesc">
Enter <span class="charname">Dercetus</span> with the sword of <span class="charname">Antony</span>.
</p>

<p class="drama">
CAESAR.<br>
Wherefore is that? And what art thou that dar’st<br>
Appear thus to us?
</p>

<p class="drama">
DERCETUS.<br>
I am called Dercetus.<br>
Mark Antony I served, who best was worthy<br>
Best to be served. Whilst he stood up and spoke,<br>
He was my master, and I wore my life<br>
To spend upon his haters. If thou please<br>
To take me to thee, as I was to him<br>
I’ll be to Caesar; if thou pleasest not,<br>
I yield thee up my life.
</p>

<p class="drama">
CAESAR.<br>
What is’t thou say’st?
</p>

<p class="drama">
DERCETUS.<br>
I say, O Caesar, Antony is dead.
</p>

<p class="drama">
CAESAR.<br>
The breaking of so great a thing should make<br>
A greater crack. The round world<br>
Should have shook lions into civil streets,<br>
And citizens to their dens. The death of Antony<br>
Is not a single doom; in the name lay<br>
A moiety of the world.
</p>

<p class="drama">
DERCETUS.<br>
He is dead, Caesar,<br>
Not by a public minister of justice,<br>
Nor by a hired knife, but that self hand<br>
Which writ his honour in the acts it did<br>
Hath, with the courage which the heart did lend it,<br>
Splitted the heart. This is his sword.<br>
I robbed his wound of it. Behold it stained<br>
With his most noble blood.
</p>

<p class="drama">
CAESAR.<br>
Look you sad, friends?<br>
The gods rebuke me, but it is tidings<br>
To wash the eyes of kings.
</p>

<p class="drama">
AGRIPPA.<br>
And strange it is<br>
That nature must compel us to lament<br>
Our most persisted deeds.
</p>

<p class="drama">
MAECENAS.<br>
His taints and honours<br>
Waged equal with him.
</p>

<p class="drama">
AGRIPPA.<br>
A rarer spirit never<br>
Did steer humanity, but you gods will give us<br>
Some faults to make us men. Caesar is touched.
</p>

<p class="drama">
MAECENAS.<br>
When such a spacious mirror’s set before him,<br>
He needs must see himself.
</p>

<p class="drama">
CAESAR.<br>
O Antony,<br>
I have followed thee to this, but we do lance<br>
Diseases in our bodies. I must perforce<br>
Have shown to thee such a declining day<br>
Or look on thine. We could not stall together<br>
In the whole world. But yet let me lament<br>
With tears as sovereign as the blood of hearts,<br>
That thou, my brother, my competitor<br>
In top of all design, my mate in empire,<br>
Friend and companion in the front of war,<br>
The arm of mine own body, and the heart<br>
Where mine his thoughts did kindle, that our stars,<br>
Unreconciliable, should divide<br>
Our equalness to this. Hear me, good friends—
</p>

<p class="scenedesc">
Enter an <span class="charname">Egyptian</span>.
</p>

<p class="drama">
But I will tell you at some meeter season.<br>
The business of this man looks out of him;<br>
We’ll hear him what he says. Whence are you?
</p>

<p class="drama">
EGYPTIAN.<br>
A poor Egyptian yet. The queen, my mistress,<br>
Confined in all she has, her monument,<br>
Of thy intents desires instruction,<br>
That she preparedly may frame herself<br>
To the way she’s forced to.
</p>

<p class="drama">
CAESAR.<br>
Bid her have good heart.<br>
She soon shall know of us, by some of ours,<br>
How honourable and how kindly we<br>
Determine for her. For Caesar cannot lean<br>
To be ungentle.
</p>

<p class="drama">
EGYPTIAN.<br>
So the gods preserve thee!
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="drama">
CAESAR.<br>
Come hither, Proculeius. Go and say<br>
We purpose her no shame. Give her what comforts<br>
The quality of her passion shall require,<br>
Lest, in her greatness, by some mortal stroke<br>
She do defeat us, for her life in Rome<br>
Would be eternal in our triumph. Go,<br>
And with your speediest bring us what she says<br>
And how you find of her.
</p>

<p class="drama">
PROCULEIUS.<br>
Caesar, I shall.
</p>

<p class="right">
[<i>Exit <span class="charname">Proculeius</span>.</i>]
</p>

<p class="drama">
CAESAR.<br>
Gallus, go you along.
</p>

<p class="right">
[<i>Exit <span class="charname">Gallus</span>.</i>]
</p>

<p class="drama">
Where’s Dolabella, to second Proculeius?
</p>

<p class="drama">
ALL.<br>
Dolabella!
</p>

<p class="drama">
CAESAR.<br>
Let him alone, for I remember now<br>
How he’s employed. He shall in time be ready.<br>
Go with me to my tent, where you shall see<br>
How hardly I was drawn into this war,<br>
How calm and gentle I proceeded still<br>
In all my writings. Go with me and see<br>
What I can show in this.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneV_3.2"></a><b>SCENE II. Alexandria. A Room in the
Monument.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Cleopatra, Charmian</span> and <span class="charname">Iras</span>.
</p>

<p class="drama">
CLEOPATRA.<br>
My desolation does begin to make<br>
A better life. ’Tis paltry to be Caesar;<br>
Not being Fortune, he’s but Fortune’s knave,<br>
A minister of her will. And it is great<br>
To do that thing that ends all other deeds,<br>
Which shackles accidents and bolts up change,<br>
Which sleeps and never palates more the dung,<br>
The beggar’s nurse and Caesar’s.
</p>

<p class="scenedesc">
Enter <span class="charname">Proculeius</span>.
</p>

<p class="drama">
PROCULEIUS.<br>
Caesar sends greetings to the queen of Egypt,<br>
And bids thee study on what fair demands<br>
Thou mean’st to have him grant thee.
</p>

<p class="drama">
CLEOPATRA.<br>
What’s thy name?
</p>

<p class="drama">
PROCULEIUS.<br>
My name is Proculeius.
</p>

<p class="drama">
CLEOPATRA.<br>
Antony<br>
Did tell me of you, bade me trust you, but<br>
I do not greatly care to be deceived<br>
That have no use for trusting. If your master<br>
Would have a queen his beggar, you must tell him<br>
That majesty, to keep decorum, must<br>
No less beg than a kingdom. If he please<br>
To give me conquered Egypt for my son,<br>
He gives me so much of mine own as I<br>
Will kneel to him with thanks.
</p>

<p class="drama">
PROCULEIUS.<br>
Be of good cheer.<br>
You are fallen into a princely hand; fear nothing.<br>
Make your full reference freely to my lord,<br>
Who is so full of grace that it flows over<br>
On all that need. Let me report to him<br>
Your sweet dependency, and you shall find<br>
A conqueror that will pray in aid for kindness<br>
Where he for grace is kneeled to.
</p>

<p class="drama">
CLEOPATRA.<br>
Pray you tell him<br>
I am his fortune’s vassal and I send him<br>
The greatness he has got. I hourly learn<br>
A doctrine of obedience, and would gladly<br>
Look him i’ th’ face.
</p>

<p class="drama">
PROCULEIUS.<br>
This I’ll report, dear lady.<br>
Have comfort, for I know your plight is pitied<br>
Of him that caused it.
</p>

<p class="scenedesc">
Enter <span class="charname">Gallus</span> and Roman Soldiers.
</p>

<p class="drama">
You see how easily she may be surprised.<br>
Guard her till Caesar come.
</p>

<p class="drama">
IRAS.<br>
Royal queen!
</p>

<p class="drama">
CHARMIAN.<br>
O Cleopatra, thou art taken, queen!
</p>

<p class="drama">
CLEOPATRA.<br>
Quick, quick, good hands.
</p>

<p class="right">
[<i>Drawing a dagger.</i>]
</p>

<p class="drama">
PROCULEIUS.<br>
Hold, worthy lady, hold!
</p>

<p class="right">
[<i>Seizes and disarms her.</i>]
</p>

<p class="drama">
Do not yourself such wrong, who are in this<br>
Relieved, but not betrayed.
</p>

<p class="drama">
CLEOPATRA.<br>
What, of death too,<br>
That rids our dogs of languish?
</p>

<p class="drama">
PROCULEIUS.<br>
Cleopatra,<br>
Do not abuse my master’s bounty by<br>
Th’ undoing of yourself. Let the world see<br>
His nobleness well acted, which your death<br>
Will never let come forth.
</p>

<p class="drama">
CLEOPATRA.<br>
Where art thou, Death?<br>
Come hither, come! Come, come, and take a queen<br>
Worth many babes and beggars!
</p>

<p class="drama">
PROCULEIUS.<br>
O, temperance, lady!
</p>

<p class="drama">
CLEOPATRA.<br>
Sir, I will eat no meat; I’ll not drink, sir;<br>
If idle talk will once be necessary,<br>
I’ll not sleep neither. This mortal house I’ll ruin,<br>
Do Caesar what he can. Know, sir, that I<br>
Will not wait pinioned at your master’s court,<br>
Nor once be chastised with the sober eye<br>
Of dull Octavia. Shall they hoist me up<br>
And show me to the shouting varletry<br>
Of censuring Rome? Rather a ditch in Egypt<br>
Be gentle grave unto me! Rather on Nilus’ mud<br>
Lay me stark-naked, and let the water-flies<br>
Blow me into abhorring! Rather make<br>
My country’s high pyramides my gibbet<br>
And hang me up in chains!
</p>

<p class="drama">
PROCULEIUS.<br>
You do extend<br>
These thoughts of horror further than you shall<br>
Find cause in Caesar.
</p>

<p class="scenedesc">
Enter <span class="charname">Dolabella</span>.
</p>

<p class="drama">
DOLABELLA.<br>
Proculeius,<br>
What thou hast done thy master Caesar knows,<br>
And he hath sent for thee. For the queen,<br>
I’ll take her to my guard.
</p>

<p class="drama">
PROCULEIUS.<br>
So, Dolabella,<br>
It shall content me best. Be gentle to her.<br>
[<i>To Cleopatra.</i>] To Caesar I will speak what you shall please,<br>
If you’ll employ me to him.
</p>

<p class="drama">
CLEOPATRA.<br>
Say I would die.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Proculeius</span> and Soldiers.</i>]
</p>

<p class="drama">
DOLABELLA.<br>
Most noble empress, you have heard of me?
</p>

<p class="drama">
CLEOPATRA.<br>
I cannot tell.
</p>

<p class="drama">
DOLABELLA.<br>
Assuredly you know me.
</p>

<p class="drama">
CLEOPATRA.<br>
No matter, sir, what I have heard or known.<br>
You laugh when boys or women tell their dreams;<br>
Is’t not your trick?
</p>

<p class="drama">
DOLABELLA.<br>
I understand not, madam.
</p>

<p class="drama">
CLEOPATRA.<br>
I dreamt there was an Emperor Antony.<br>
O, such another sleep, that I might see<br>
But such another man!
</p>

<p class="drama">
DOLABELLA.<br>
If it might please you—
</p>

<p class="drama">
CLEOPATRA.<br>
His face was as the heavens, and therein stuck<br>
A sun and moon, which kept their course, and lighted<br>
The little O, the earth.
</p>

<p class="drama">
DOLABELLA.<br>
Most sovereign creature—
</p>

<p class="drama">
CLEOPATRA.<br>
His legs bestrid the ocean; his reared arm<br>
Crested the world; his voice was propertied<br>
As all the tuned spheres, and that to friends;<br>
But when he meant to quail and shake the orb,<br>
He was as rattling thunder. For his bounty,<br>
There was no winter in’t; an autumn ’twas<br>
That grew the more by reaping. His delights<br>
Were dolphin-like; they showed his back above<br>
The element they lived in. In his livery<br>
Walked crowns and crownets; realms and islands were<br>
As plates dropped from his pocket.
</p>

<p class="drama">
DOLABELLA.<br>
Cleopatra—
</p>

<p class="drama">
CLEOPATRA.<br>
Think you there was or might be such a man<br>
As this I dreamt of?
</p>

<p class="drama">
DOLABELLA.<br>
Gentle madam, no.
</p>

<p class="drama">
CLEOPATRA.<br>
You lie up to the hearing of the gods!<br>
But if there be nor ever were one such,<br>
It’s past the size of dreaming. Nature wants stuff<br>
To vie strange forms with fancy; yet t’ imagine<br>
An Antony were nature’s piece ’gainst fancy,<br>
Condemning shadows quite.
</p>

<p class="drama">
DOLABELLA.<br>
Hear me, good madam.<br>
Your loss is, as yourself, great; and you bear it<br>
As answering to the weight. Would I might never<br>
O’ertake pursued success, but I do feel,<br>
By the rebound of yours, a grief that smites<br>
My very heart at root.
</p>

<p class="drama">
CLEOPATRA.<br>
I thank you, sir.<br>
Know you what Caesar means to do with me?
</p>

<p class="drama">
DOLABELLA.<br>
I am loath to tell you what I would you knew.
</p>

<p class="drama">
CLEOPATRA.<br>
Nay, pray you, sir.
</p>

<p class="drama">
DOLABELLA.<br>
Though he be honourable—
</p>

<p class="drama">
CLEOPATRA.<br>
He’ll lead me, then, in triumph.
</p>

<p class="drama">
DOLABELLA.<br>
Madam, he will. I know it.
</p>

<p class="scenedesc">
Flourish. Enter <span class="charname">Caesar, Proculeius, Gallus,
Maecenas</span> and others of his train.
</p>

<p class="drama">
ALL.<br>
Make way there! Caesar!
</p>

<p class="drama">
CAESAR.<br>
Which is the Queen of Egypt?
</p>

<p class="drama">
DOLABELLA.<br>
It is the Emperor, madam.
</p>

<p class="right">
[<i><span class="charname">Cleopatra</span> kneels.</i>]
</p>

<p class="drama">
CAESAR.<br>
Arise, you shall not kneel.<br>
I pray you, rise. Rise, Egypt.
</p>

<p class="drama">
CLEOPATRA.<br>
Sir, the gods<br>
Will have it thus. My master and my lord<br>
I must obey.
</p>

<p class="drama">
CAESAR.<br>
Take to you no hard thoughts.<br>
The record of what injuries you did us,<br>
Though written in our flesh, we shall remember<br>
As things but done by chance.
</p>

<p class="drama">
CLEOPATRA.<br>
Sole sir o’ th’ world,<br>
I cannot project mine own cause so well<br>
To make it clear, but do confess I have<br>
Been laden with like frailties which before<br>
Have often shamed our sex.
</p>

<p class="drama">
CAESAR.<br>
Cleopatra, know<br>
We will extenuate rather than enforce.<br>
If you apply yourself to our intents,<br>
Which towards you are most gentle, you shall find<br>
A benefit in this change; but if you seek<br>
To lay on me a cruelty by taking<br>
Antony’s course, you shall bereave yourself<br>
Of my good purposes, and put your children<br>
To that destruction which I’ll guard them from<br>
If thereon you rely. I’ll take my leave.
</p>

<p class="drama">
CLEOPATRA.<br>
And may, through all the world. ’Tis yours, and we,<br>
Your scutcheons and your signs of conquest, shall<br>
Hang in what place you please. Here, my good lord.
</p>

<p class="drama">
CAESAR.<br>
You shall advise me in all for Cleopatra.
</p>

<p class="drama">
CLEOPATRA.<br>
This is the brief of money, plate, and jewels<br>
I am possessed of. ’Tis exactly valued,<br>
Not petty things admitted. Where’s Seleucus?
</p>

<p class="scenedesc">
Enter <span class="charname">Seleucus</span>.
</p>

<p class="drama">
SELEUCUS.<br>
Here, madam.
</p>

<p class="drama">
CLEOPATRA.<br>
This is my treasurer. Let him speak, my lord,<br>
Upon his peril, that I have reserved<br>
To myself nothing. Speak the truth, Seleucus.
</p>

<p class="drama">
SELEUCUS.<br>
Madam, I had rather seal my lips<br>
Than to my peril speak that which is not.
</p>

<p class="drama">
CLEOPATRA.<br>
What have I kept back?
</p>

<p class="drama">
SELEUCUS.<br>
Enough to purchase what you have made known.
</p>

<p class="drama">
CAESAR.<br>
Nay, blush not, Cleopatra. I approve<br>
Your wisdom in the deed.
</p>

<p class="drama">
CLEOPATRA.<br>
See, Caesar! O, behold,<br>
How pomp is followed! Mine will now be yours<br>
And should we shift estates, yours would be mine.<br>
The ingratitude of this Seleucus does<br>
Even make me wild. O slave, of no more trust<br>
Than love that’s hired! What, goest thou back? Thou shalt<br>
Go back, I warrant thee! But I’ll catch thine eyes<br>
Though they had wings. Slave, soulless villain, dog!<br>
O rarely base!
</p>

<p class="drama">
CAESAR.<br>
Good queen, let us entreat you.
</p>

<p class="drama">
CLEOPATRA.<br>
O Caesar, what a wounding shame is this,<br>
That thou vouchsafing here to visit me,<br>
Doing the honour of thy lordliness<br>
To one so meek, that mine own servant should<br>
Parcel the sum of my disgraces by<br>
Addition of his envy! Say, good Caesar,<br>
That I some lady trifles have reserved,<br>
Immoment toys, things of such dignity<br>
As we greet modern friends withal; and say<br>
Some nobler token I have kept apart<br>
For Livia and Octavia, to induce<br>
Their mediation, must I be unfolded<br>
With one that I have bred? The gods! It smites me<br>
Beneath the fall I have.<br>
[<i>To Seleucus</i>.] Prithee go hence,<br>
Or I shall show the cinders of my spirits<br>
Through th’ ashes of my chance. Wert thou a man,<br>
Thou wouldst have mercy on me.
</p>

<p class="drama">
CAESAR.<br>
Forbear, Seleucus.
</p>

<p class="right">
[<i>Exit <span class="charname">Seleucus</span>.</i>]
</p>

<p class="drama">
CLEOPATRA.<br>
Be it known that we, the greatest, are misthought<br>
For things that others do; and when we fall,<br>
We answer others’ merits in our name,<br>
Are therefore to be pitied.
</p>

<p class="drama">
CAESAR.<br>
Cleopatra,<br>
Not what you have reserved nor what acknowledged<br>
Put we i’ th’ roll of conquest. Still be’t yours;<br>
Bestow it at your pleasure, and believe<br>
Caesar’s no merchant to make prize with you<br>
Of things that merchants sold. Therefore be cheered;<br>
Make not your thoughts your prisons. No, dear queen;<br>
For we intend so to dispose you as<br>
Yourself shall give us counsel. Feed and sleep.<br>
Our care and pity is so much upon you<br>
That we remain your friend; and so, adieu.
</p>

<p class="drama">
CLEOPATRA.<br>
My master and my lord!
</p>

<p class="drama">
CAESAR.<br>
Not so. Adieu.
</p>

<p class="right">
[<i>Flourish. Exeunt <span class="charname">Caesar</span> and his train.</i>]
</p>

<p class="drama">
CLEOPATRA.<br>
He words me, girls, he words me, that I should not<br>
Be noble to myself. But hark thee, Charmian!
</p>

<p class="right">
[<i>Whispers to <span class="charname">Charmian</span>.</i>]
</p>

<p class="drama">
IRAS.<br>
Finish, good lady. The bright day is done,<br>
And we are for the dark.
</p>

<p class="drama">
CLEOPATRA.<br>
Hie thee again.<br>
I have spoke already, and it is provided.<br>
Go put it to the haste.
</p>

<p class="drama">
CHARMIAN.<br>
Madam, I will.
</p>

<p class="scenedesc">
Enter <span class="charname">Dolabella</span>.
</p>

<p class="drama">
DOLABELLA.<br>
Where’s the Queen?
</p>

<p class="drama">
CHARMIAN.<br>
Behold, sir.
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="drama">
CLEOPATRA.<br>
Dolabella!
</p>

<p class="drama">
DOLABELLA.<br>
Madam, as thereto sworn by your command,<br>
Which my love makes religion to obey,<br>
I tell you this: Caesar through Syria<br>
Intends his journey, and within three days<br>
You with your children will he send before.<br>
Make your best use of this. I have performed<br>
Your pleasure and my promise.
</p>

<p class="drama">
CLEOPATRA.<br>
Dolabella,<br>
I shall remain your debtor.
</p>

<p class="drama">
DOLABELLA.<br>
I your servant.<br>
Adieu, good queen. I must attend on Caesar.
</p>

<p class="drama">
CLEOPATRA.<br>
Farewell, and thanks.
</p>

<p class="right">
[<i>Exit <span class="charname">Dolabella</span>.</i>]
</p>

<p class="drama">
Now, Iras, what think’st thou?<br>
Thou an Egyptian puppet shall be shown<br>
In Rome as well as I. Mechanic slaves<br>
With greasy aprons, rules, and hammers shall<br>
Uplift us to the view. In their thick breaths,<br>
Rank of gross diet, shall we be enclouded,<br>
And forced to drink their vapour.
</p>

<p class="drama">
IRAS.<br>
The gods forbid!
</p>

<p class="drama">
CLEOPATRA.<br>
Nay, ’tis most certain, Iras. Saucy lictors<br>
Will catch at us like strumpets, and scald rhymers<br>
Ballad us out o’ tune. The quick comedians<br>
Extemporally will stage us and present<br>
Our Alexandrian revels; Antony<br>
Shall be brought drunken forth, and I shall see<br>
Some squeaking Cleopatra boy my greatness<br>
I’ th’ posture of a whore.
</p>

<p class="drama">
IRAS.<br>
O the good gods!
</p>

<p class="drama">
CLEOPATRA.<br>
Nay, that’s certain.
</p>

<p class="drama">
IRAS.<br>
I’ll never see’t, for I am sure mine nails<br>
Are stronger than mine eyes.
</p>

<p class="drama">
CLEOPATRA.<br>
Why, that’s the way<br>
To fool their preparation and to conquer<br>
Their most absurd intents.
</p>

<p class="scenedesc">
Enter <span class="charname">Charmian</span>.
</p>

<p class="drama">
Now, Charmian!<br>
Show me, my women, like a queen. Go fetch<br>
My best attires. I am again for Cydnus<br>
To meet Mark Antony. Sirrah, Iras, go.<br>
Now, noble Charmian, we’ll dispatch indeed,<br>
And when thou hast done this chare, I’ll give thee leave<br>
To play till doomsday. Bring our crown and all.
</p>

<p class="right">
[<i>Exit <span class="charname">Iras.</span> A noise within.</i>]
</p>

<p class="drama">
Wherefore’s this noise?
</p>

<p class="scenedesc">
Enter a <span class="charname">Guardsman</span>.
</p>

<p class="drama">
GUARDSMAN.<br>
Here is a rural fellow<br>
That will not be denied your highness’ presence.<br>
He brings you figs.
</p>

<p class="drama">
CLEOPATRA.<br>
Let him come in.
</p>

<p class="right">
[<i>Exit <span class="charname">Guardsman</span>.</i>]
</p>

<p class="drama">
What poor an instrument<br>
May do a noble deed! He brings me liberty.<br>
My resolution’s placed, and I have nothing<br>
Of woman in me. Now from head to foot<br>
I am marble-constant. Now the fleeting moon<br>
No planet is of mine.
</p>

<p class="scenedesc">
Enter <span class="charname">Guardsman</span> and <span class="charname">Clown</span> with a basket.
</p>

<p class="drama">
GUARDSMAN.<br>
This is the man.
</p>

<p class="drama">
CLEOPATRA.<br>
Avoid, and leave him.
</p>

<p class="right">
[<i>Exit <span class="charname">Guardsman</span>.</i>]
</p>

<p class="drama">
Hast thou the pretty worm of Nilus there<br>
That kills and pains not?
</p>

<p class="drama">
CLOWN.<br>
Truly, I have him, but I would not be the party that should desire you to touch
him, for his biting is immortal. Those that do die of it do seldom or never
recover.
</p>

<p class="drama">
CLEOPATRA.<br>
Remember’st thou any that have died on’t?
</p>

<p class="drama">
CLOWN.<br>
Very many, men and women too. I heard of one of them no longer than yesterday—a
very honest woman, but something given to lie; as a woman should not do but in
the way of honesty—how she died of the biting of it, what pain she felt. Truly
she makes a very good report o’ th’ worm; but he that will believe all that
they say shall never be saved by half that they do. But this is most falliable,
the worm’s an odd worm.
</p>

<p class="drama">
CLEOPATRA.<br>
Get thee hence. Farewell.
</p>

<p class="drama">
CLOWN.<br>
I wish you all joy of the worm.
</p>

<p class="right">
[<i>Sets down the basket.</i>]
</p>

<p class="drama">
CLEOPATRA.<br>
Farewell.
</p>

<p class="drama">
CLOWN.<br>
You must think this, look you, that the worm will do his kind.
</p>

<p class="drama">
CLEOPATRA.<br>
Ay, ay, farewell.
</p>

<p class="drama">
CLOWN.<br>
Look you, the worm is not to be trusted but in the keeping of wise people; for
indeed there is no goodness in the worm.
</p>

<p class="drama">
CLEOPATRA.<br>
Take thou no care; it shall be heeded.
</p>

<p class="drama">
CLOWN.<br>
Very good. Give it nothing, I pray you, for it is not worth the feeding.
</p>

<p class="drama">
CLEOPATRA.<br>
Will it eat me?
</p>

<p class="drama">
CLOWN.<br>
You must not think I am so simple but I know the devil himself will not eat a
woman. I know that a woman is a dish for the gods if the devil dress her not.
But truly, these same whoreson devils do the gods great harm in their women,
for in every ten that they make, the devils mar five.
</p>

<p class="drama">
CLEOPATRA.<br>
Well, get thee gone. Farewell.
</p>

<p class="drama">
CLOWN.<br>
Yes, forsooth. I wish you joy o’ th’ worm.
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="scenedesc">
Enter <span class="charname">Iras</span> with a robe, crown, &amp;c.
</p>

<p class="drama">
CLEOPATRA.<br>
Give me my robe. Put on my crown. I have<br>
Immortal longings in me. Now no more<br>
The juice of Egypt’s grape shall moist this lip.<br>
Yare, yare, good Iras; quick. Methinks I hear<br>
Antony call. I see him rouse himself<br>
To praise my noble act. I hear him mock<br>
The luck of Caesar, which the gods give men<br>
To excuse their after wrath. Husband, I come!<br>
Now to that name my courage prove my title!<br>
I am fire and air; my other elements<br>
I give to baser life.—So, have you done?<br>
Come then, and take the last warmth of my lips.<br>
Farewell, kind Charmian. Iras, long farewell.
</p>

<p class="right">
[<i>Kisses them. <span class="charname">Iras</span> falls and dies.</i>]
</p>

<p class="drama">
Have I the aspic in my lips? Dost fall?<br>
If thou and nature can so gently part,<br>
The stroke of death is as a lover’s pinch,<br>
Which hurts and is desired. Dost thou lie still?<br>
If thus thou vanishest, thou tell’st the world<br>
It is not worth leave-taking.
</p>

<p class="drama">
CHARMIAN.<br>
Dissolve, thick cloud, and rain, that I may say<br>
The gods themselves do weep!
</p>

<p class="drama">
CLEOPATRA.<br>
This proves me base.<br>
If she first meet the curled Antony,<br>
He’ll make demand of her, and spend that kiss<br>
Which is my heaven to have.—Come, thou mortal wretch,
</p>

<p class="right">
[<i>To an asp, which she applies to her breast.</i>]
</p>

<p class="drama">
With thy sharp teeth this knot intrinsicate<br>
Of life at once untie. Poor venomous fool,<br>
Be angry and dispatch. O couldst thou speak,<br>
That I might hear thee call great Caesar ass<br>
Unpolicied!
</p>

<p class="drama">
CHARMIAN.<br>
O eastern star!
</p>

<p class="drama">
CLEOPATRA.<br>
Peace, peace!<br>
Dost thou not see my baby at my breast<br>
That sucks the nurse asleep?
</p>

<p class="drama">
CHARMIAN.<br>
O, break! O, break!
</p>

<p class="drama">
CLEOPATRA.<br>
As sweet as balm, as soft as air, as gentle—<br>
O Antony!—Nay, I will take thee too.
</p>

<p class="right">
[<i>Applying another asp to her arm.</i>]
</p>

<p class="drama">
What should I stay—
</p>

<p class="right">
[<i>Dies.</i>]
</p>

<p class="drama">
CHARMIAN.<br>
In this vile world? So, fare thee well.<br>
Now boast thee, Death, in thy possession lies<br>
A lass unparalleled. Downy windows, close,<br>
And golden Phœbus never be beheld<br>
Of eyes again so royal! Your crown’s awry;<br>
I’ll mend it and then play.
</p>

<p class="scenedesc">
Enter the <span class="charname">Guard</span> rustling in.
</p>

<p class="drama">
FIRST GUARD.<br>
Where’s the queen?
</p>

<p class="drama">
CHARMIAN.<br>
Speak softly. Wake her not.
</p>

<p class="drama">
FIRST GUARD.<br>
Caesar hath sent—
</p>

<p class="drama">
CHARMIAN.<br>
Too slow a messenger.
</p>

<p class="right">
[<i>Applies an asp.</i>]
</p>

<p class="drama">
O, come apace, dispatch! I partly feel thee.
</p>

<p class="drama">
FIRST GUARD.<br>
Approach, ho! All’s not well. Caesar’s beguiled.
</p>

<p class="drama">
SECOND GUARD.<br>
There’s Dolabella sent from Caesar. Call him.
</p>

<p class="drama">
FIRST GUARD.<br>
What work is here, Charmian? Is this well done?
</p>

<p class="drama">
CHARMIAN.<br>
It is well done, and fitting for a princess<br>
Descended of so many royal kings.<br>
Ah, soldier!
</p>

<p class="right">
[<i><span class="charname">Charmian</span> dies.</i>]
</p>

<p class="scenedesc">
Enter <span class="charname">Dolabella</span>.
</p>

<p class="drama">
DOLABELLA.<br>
How goes it here?
</p>

<p class="drama">
SECOND GUARD.<br>
All dead.
</p>

<p class="drama">
DOLABELLA.<br>
Caesar, thy thoughts<br>
Touch their effects in this. Thyself art coming<br>
To see performed the dreaded act which thou<br>
So sought’st to hinder.
</p>

<p class="scenedesc">
Enter <span class="charname">Caesar</span> and all his train, marching.
</p>

<p class="drama">
ALL.<br>
A way there, a way for Caesar!
</p>

<p class="drama">
DOLABELLA.<br>
O sir, you are too sure an augurer:<br>
That you did fear is done.
</p>

<p class="drama">
CAESAR.<br>
Bravest at the last,<br>
She levelled at our purposes and, being royal,<br>
Took her own way. The manner of their deaths?<br>
I do not see them bleed.
</p>

<p class="drama">
DOLABELLA.<br>
Who was last with them?
</p>

<p class="drama">
FIRST GUARD.<br>
A simple countryman that brought her figs.<br>
This was his basket.
</p>

<p class="drama">
CAESAR.<br>
Poisoned then.
</p>

<p class="drama">
FIRST GUARD.<br>
O Caesar,<br>
This Charmian lived but now; she stood and spake.<br>
I found her trimming up the diadem<br>
On her dead mistress; tremblingly she stood,<br>
And on the sudden dropped.
</p>

<p class="drama">
CAESAR.<br>
O noble weakness!<br>
If they had swallowed poison ’twould appear<br>
By external swelling; but she looks like sleep,<br>
As she would catch another Antony<br>
In her strong toil of grace.
</p>

<p class="drama">
DOLABELLA.<br>
Here on her breast<br>
There is a vent of blood, and something blown.<br>
The like is on her arm.
</p>

<p class="drama">
FIRST GUARD.<br>
This is an aspic’s trail, and these fig leaves<br>
Have slime upon them, such as th’ aspic leaves<br>
Upon the caves of Nile.
</p>

<p class="drama">
CAESAR.<br>
Most probable<br>
That so she died, for her physician tells me<br>
She hath pursued conclusions infinite<br>
Of easy ways to die. Take up her bed,<br>
And bear her women from the monument.<br>
She shall be buried by her Antony.<br>
No grave upon the earth shall clip in it<br>
A pair so famous. High events as these<br>
Strike those that make them; and their story is<br>
No less in pity than his glory which<br>
Brought them to be lamented. Our army shall<br>
In solemn show attend this funeral,<br>
And then to Rome. Come, Dolabella, see<br>
High order in this great solemnity.
</p>

<p class="right">
[<i>Exeunt omnes.</i>]
</p>

