<h2> <a id="sceneI_21.1"></a><b>ACT I</b></h2>

<h3> <b>SCENE I. An apartment in the Duke’s palace.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Duke, Escalus,</span> Lords and Attendants.
</p>

<p class="drama">
DUKE.<br>
Escalus.
</p>

<p class="drama">
ESCALUS.<br>
My lord.
</p>

<p class="drama">
DUKE.<br>
Of government the properties to unfold<br>
Would seem in me t’ affect speech and discourse,<br>
Since I am put to know that your own science<br>
Exceeds, in that, the lists of all advice<br>
My strength can give you. Then no more remains<br>
But that, to your sufficiency, as your worth is able,<br>
And let them work. The nature of our people,<br>
Our city’s institutions, and the terms<br>
For common justice, you’re as pregnant in<br>
As art and practice hath enriched any<br>
That we remember. There is our commission,<br>
From which we would not have you warp.—Call hither,<br>
I say, bid come before us, Angelo.
</p>

<p class="right">[<i>Exit an <span class="charname">Attendant</span>.</i>]</p>

<p class="drama">
What figure of us think you he will bear?<br>
For you must know we have with special soul<br>
Elected him our absence to supply;<br>
Lent him our terror, drest him with our love,<br>
And given his deputation all the organs<br>
Of our own power. What think you of it?
</p>

<p class="drama">
ESCALUS.<br>
If any in Vienna be of worth<br>
To undergo such ample grace and honour,<br>
It is Lord Angelo.
</p>

<p class="scenedesc">
Enter <span class="charname">Angelo</span>.
</p>

<p class="drama">
DUKE.<br>
Look where he comes.
</p>

<p class="drama">
ANGELO.<br>
Always obedient to your Grace’s will,<br>
I come to know your pleasure.
</p>

<p class="drama">
DUKE.<br>
Angelo,<br>
There is a kind of character in thy life<br>
That to th’ observer doth thy history<br>
Fully unfold. Thyself and thy belongings<br>
Are not thine own so proper as to waste<br>
Thyself upon thy virtues, they on thee.<br>
Heaven doth with us as we with torches do,<br>
Not light them for themselves; for if our virtues<br>
Did not go forth of us, ’twere all alike<br>
As if we had them not. Spirits are not finely touched<br>
But to fine issues; nor nature never lends<br>
The smallest scruple of her excellence<br>
But, like a thrifty goddess, she determines<br>
Herself the glory of a creditor,<br>
Both thanks and use. But I do bend my speech<br>
To one that can my part in him advertise.<br>
Hold, therefore, Angelo.<br>
In our remove be thou at full ourself.<br>
Mortality and mercy in Vienna<br>
Live in thy tongue and heart. Old Escalus,<br>
Though first in question, is thy secondary.<br>
Take thy commission.
</p>

<p class="drama">
ANGELO.<br>
Now, good my lord,<br>
Let there be some more test made of my metal,<br>
Before so noble and so great a figure<br>
Be stamped upon it.
</p>

<p class="drama">
DUKE.<br>
No more evasion.<br>
We have with a leavened and prepared choice<br>
Proceeded to you; therefore take your honours.<br>
Our haste from hence is of so quick condition<br>
That it prefers itself, and leaves unquestioned<br>
Matters of needful value. We shall write to you,<br>
As time and our concernings shall importune,<br>
How it goes with us; and do look to know<br>
What doth befall you here. So, fare you well.<br>
To th’ hopeful execution do I leave you<br>
Of your commissions.
</p>

<p class="drama">
ANGELO.<br>
Yet give leave, my lord,<br>
That we may bring you something on the way.
</p>

<p class="drama">
DUKE.<br>
My haste may not admit it;<br>
Nor need you, on mine honour, have to do<br>
With any scruple. Your scope is as mine own,<br>
So to enforce or qualify the laws<br>
As to your soul seems good. Give me your hand;<br>
I’ll privily away. I love the people,<br>
But do not like to stage me to their eyes.<br>
Though it do well, I do not relish well<br>
Their loud applause and <i>Aves</i> vehement;<br>
Nor do I think the man of safe discretion<br>
That does affect it. Once more, fare you well.
</p>

<p class="drama">
ANGELO.<br>
The heavens give safety to your purposes!
</p>

<p class="drama">
ESCALUS.<br>
Lead forth and bring you back in happiness.
</p>

<p class="drama">
DUKE.<br>
I thank you. Fare you well.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
ESCALUS.<br>
I shall desire you, sir, to give me leave<br>
To have free speech with you; and it concerns me<br>
To look into the bottom of my place.<br>
A power I have, but of what strength and nature<br>
I am not yet instructed.
</p>

<p class="drama">
ANGELO.<br>
’Tis so with me. Let us withdraw together,<br>
And we may soon our satisfaction have<br>
Touching that point.
</p>

<p class="drama">
ESCALUS.<br>
I’ll wait upon your honour.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneI_21.2"></a><b>SCENE II. A street.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Lucio</span> and two other
<span class="charname">Gentlemen</span>.
</p>

<p class="drama">
LUCIO.<br>
If the Duke, with the other dukes, come not to composition with the King of
Hungary, why then all the dukes fall upon the King.
</p>

<p class="drama">
FIRST GENTLEMAN.<br>
Heaven grant us its peace, but not the King of Hungary’s!
</p>

<p class="drama">
SECOND GENTLEMAN.<br>
Amen.
</p>

<p class="drama">
LUCIO.<br>
Thou conclud’st like the sanctimonious pirate that went to sea with the ten
commandments, but scraped one out of the table.
</p>

<p class="drama">
SECOND GENTLEMAN.<br>
“Thou shalt not steal”?
</p>

<p class="drama">
LUCIO.<br>
Ay, that he razed.
</p>

<p class="drama">
FIRST GENTLEMAN.<br>
Why, ’twas a commandment to command the captain and all the rest from
their functions! They put forth to steal. There’s not a soldier of us all
that, in the thanksgiving before meat, do relish the petition well that prays
for peace.</p>

<p class="drama">
SECOND GENTLEMAN.<br>
I never heard any soldier dislike it.
</p>

<p class="drama">
LUCIO.<br>
I believe thee; for I think thou never wast where grace was said.
</p>

<p class="drama">
SECOND GENTLEMAN.<br>
No? A dozen times at least.
</p>

<p class="drama">
FIRST GENTLEMAN.<br>
What? In metre?
</p>

<p class="drama">
LUCIO.<br>
In any proportion or in any language.
</p>

<p class="drama">
FIRST GENTLEMAN.<br>
I think, or in any religion.
</p>

<p class="drama">
LUCIO.<br>
Ay, why not? Grace is grace, despite of all controversy; as, for
example, thou thyself art a wicked villain, despite of all grace.</p>

<p class="drama">
FIRST GENTLEMAN.<br>
Well, there went but a pair of shears between us.
</p>

<p class="drama">
LUCIO.<br>
I grant, as there may between the lists and the velvet. Thou art the list.</p>

<p class="drama">
FIRST GENTLEMAN.<br>
And thou the velvet. Thou art good velvet; thou’rt a three-piled piece, I
warrant thee. I had as lief be a list of an English kersey as be piled, as thou
art piled, for a French velvet. Do I speak feelingly now?</p>

<p class="drama">
LUCIO.<br>
I think thou dost, and indeed, with most painful feeling of thy speech. I
will, out of thine own confession, learn to begin thy health; but, whilst I
live, forget to drink after thee.</p>

<p class="drama">
FIRST GENTLEMAN.<br>
I think I have done myself wrong, have I not?
</p>

<p class="drama">
SECOND GENTLEMAN.<br>
Yes, that thou hast, whether thou art tainted or free.
</p>

<p class="scenedesc">
Enter Mistress <span class="charname">Overdone</span>, a Bawd.
</p>

<p class="drama">
LUCIO.<br>
Behold, behold, where Madam Mitigation comes! I have purchased as many diseases
under her roof as come to—</p>

<p class="drama">
SECOND GENTLEMAN.<br>
To what, I pray?
</p>

<p class="drama">
FIRST GENTLEMAN.<br>
Judge.
</p>

<p class="drama">
SECOND GENTLEMAN.<br>
To three thousand dolours a year.
</p>

<p class="drama">
FIRST GENTLEMAN.<br>
Ay, and more.
</p>

<p class="drama">
LUCIO.<br>
A French crown more.
</p>

<p class="drama">
FIRST GENTLEMAN.<br>
Thou art always figuring diseases in me, but thou art full of error; I am
sound.</p>

<p class="drama">
LUCIO.<br>
Nay, not, as one would say, healthy, but so sound as things that are hollow.
Thy bones are hollow. Impiety has made a feast of thee.</p>

<p class="drama">
FIRST GENTLEMAN.<br>
How now, which of your hips has the most profound sciatica?
</p>

<p class="drama">
BAWD.<br>
Well, well! There’s one yonder arrested and carried to prison was worth
five thousand of you all.</p>

<p class="drama">
FIRST GENTLEMAN.<br>
Who’s that, I pray thee?
</p>

<p class="drama">
BAWD.<br>
Marry, sir, that’s Claudio, Signior Claudio.
</p>

<p class="drama">
FIRST GENTLEMAN.<br>
Claudio to prison? ’Tis not so.
</p>

<p class="drama">
BAWD.<br>
Nay, but I know ’tis so. I saw him arrested, saw him carried away; and,
which is more, within these three days his head to be chopped off.</p>

<p class="drama">
LUCIO.<br>
But, after all this fooling, I would not have it so. Art thou sure of this?</p>

<p class="drama">
BAWD.<br>
I am too sure of it. And it is for getting Madam Julietta with child.</p>

<p class="drama">
LUCIO.<br>
Believe me, this may be. He promised to meet me two hours since, and he was
ever precise in promise-keeping.</p>

<p class="drama">
SECOND GENTLEMAN.<br>
Besides, you know, it draws something near to the speech we had to such a
purpose.</p>

<p class="drama">
FIRST GENTLEMAN.<br>
But most of all agreeing with the proclamation.
</p>

<p class="drama">
LUCIO.<br>
Away! Let’s go learn the truth of it.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Lucio</span> and
<span class="charname">Gentlemen</span>.</i>]
</p>

<p class="drama">
BAWD.<br>
Thus, what with the war, what with the sweat, what with the gallows, and what
with poverty, I am custom-shrunk.
</p>

<p class="scenedesc">
Enter <span class="charname">Pompey</span>.
</p>

<p class="drama">
How now? What’s the news with you?
</p>

<p class="drama">
POMPEY.<br>
Yonder man is carried to prison.
</p>

<p class="drama">
BAWD.<br>
Well, what has he done?
</p>

<p class="drama">
POMPEY.<br>
A woman.
</p>

<p class="drama">
BAWD.<br>
But what’s his offence?
</p>

<p class="drama">
POMPEY.<br>
Groping for trouts in a peculiar river.
</p>

<p class="drama">
BAWD.<br>
What? Is there a maid with child by him?
</p>

<p class="drama">
POMPEY.<br>
No, but there’s a woman with maid by him. You have not heard of the
proclamation, have you?</p>

<p class="drama">
BAWD.<br>
What proclamation, man?
</p>

<p class="drama">
POMPEY.<br>
All houses in the suburbs of Vienna must be plucked down.
</p>

<p class="drama">
BAWD.<br>
And what shall become of those in the city?
</p>

<p class="drama">
POMPEY.<br>
They shall stand for seed. They had gone down too, but that a wise burgher put
in for them.</p>

<p class="drama">
BAWD.<br>
But shall all our houses of resort in the suburbs be pulled down?
</p>

<p class="drama">
POMPEY.<br>
To the ground, mistress.
</p>

<p class="drama">
BAWD.<br>
Why, here’s a change indeed in the commonwealth! What shall become of
me?</p>

<p class="drama">
POMPEY.<br>
Come, fear not you. Good counsellors lack no clients. Though you change your
place, you need not change your trade. I’ll be your tapster still.
Courage, there will be pity taken on you. You that have worn your eyes almost
out in the service, you will be considered.</p>

<p class="scenedesc">
Enter <span class="charname">Provost, Claudio, Juliet</span> and Officers.
</p>

<p class="drama">
BAWD.<br>
What’s to do here, Thomas Tapster? Let’s withdraw.
</p>

<p class="drama">
POMPEY.<br>
Here comes Signior Claudio, led by the Provost to prison. And there’s
Madam Juliet.</p>

<p class="right">
[<i>Exeunt <span class="charname">Bawd</span> and
<span class="charname">Pompey</span>.</i>]
</p>

<p class="drama">
CLAUDIO.<br>
Fellow, why dost thou show me thus to the world?<br>
Bear me to prison, where I am committed.
</p>

<p class="drama">
PROVOST.<br>
I do it not in evil disposition,<br>
But from Lord Angelo by special charge.
</p>

<p class="drama">
CLAUDIO.<br>
Thus can the demi-god Authority<br>
Make us pay down for our offence by weight.<br>
The words of heaven; on whom it will, it will;<br>
On whom it will not, so; yet still ’tis just.
</p>

<p class="scenedesc">
Enter <span class="charname">Lucio</span> and two
<span class="charname">Gentlemen</span>.
</p>

<p class="drama">
LUCIO.<br>
Why, how now, Claudio? Whence comes this restraint?
</p>

<p class="drama">
CLAUDIO.<br>
From too much liberty, my Lucio, liberty.<br>
As surfeit is the father of much fast,<br>
So every scope by the immoderate use<br>
Turns to restraint. Our natures do pursue,<br>
Like rats that ravin down their proper bane,<br>
A thirsty evil; and when we drink, we die.
</p>

<p class="drama">
LUCIO.<br>
If I could speak so wisely under an arrest, I would send for certain of my
creditors; and yet, to say the truth, I had as lief have the foppery of freedom
as the morality of imprisonment. What’s thy offence, Claudio?
</p>

<p class="drama">
CLAUDIO.<br>
What but to speak of would offend again.
</p>

<p class="drama">
LUCIO.<br>
What, is’t murder?
</p>

<p class="drama">
CLAUDIO.<br>
No.
</p>

<p class="drama">
LUCIO.<br>
Lechery?
</p>

<p class="drama">
CLAUDIO.<br>
Call it so.
</p>

<p class="drama">
PROVOST.<br>
Away, sir; you must go.
</p>

<p class="drama">
CLAUDIO.<br>
One word, good friend.—Lucio, a word with you.
</p>

<p class="drama">
LUCIO.<br>
A hundred, if they’ll do you any good. Is lechery so looked after?</p>

<p class="drama">
CLAUDIO.<br>
Thus stands it with me: upon a true contract<br>
I got possession of Julietta’s bed.<br>
You know the lady; she is fast my wife,<br>
Save that we do the denunciation lack<br>
Of outward order. This we came not to<br>
Only for propagation of a dower<br>
Remaining in the coffer of her friends,<br>
From whom we thought it meet to hide our love<br>
Till time had made them for us. But it chances<br>
The stealth of our most mutual entertainment<br>
With character too gross is writ on Juliet.
</p>

<p class="drama">
LUCIO.<br>
With child, perhaps?
</p>

<p class="drama">
CLAUDIO.<br>
Unhappily, even so.<br>
And the new deputy now for the Duke—<br>
Whether it be the fault and glimpse of newness,<br>
Or whether that the body public be<br>
A horse whereon the governor doth ride,<br>
Who, newly in the seat, that it may know<br>
He can command, lets it straight feel the spur;<br>
Whether the tyranny be in his place,<br>
Or in his eminence that fills it up,<br>
I stagger in—but this new governor<br>
Awakes me all the enrolled penalties<br>
Which have, like unscoured armour, hung by th’ wall<br>
So long that nineteen zodiacs have gone round,<br>
And none of them been worn; and for a name<br>
Now puts the drowsy and neglected act<br>
Freshly on me. ’Tis surely for a name.
</p>

<p class="drama">
LUCIO.<br>
I warrant it is. And thy head stands so tickle on thy shoulders that a
milkmaid, if she be in love, may sigh it off. Send after the Duke, and appeal
to him.</p>

<p class="drama">
CLAUDIO.<br>
I have done so, but he’s not to be found.<br>
I prithee, Lucio, do me this kind service:<br>
This day my sister should the cloister enter,<br>
And there receive her approbation.<br>
Acquaint her with the danger of my state;<br>
Implore her, in my voice, that she make friends<br>
To the strict deputy; bid herself assay him.<br>
I have great hope in that. For in her youth<br>
There is a prone and speechless dialect<br>
Such as moves men; beside, she hath prosperous art<br>
When she will play with reason and discourse,<br>
And well she can persuade.
</p>

<p class="drama">
LUCIO.<br>
I pray she may, as well for the encouragement of the like, which else would
stand under grievous imposition, as for the enjoying of thy life, who I would
be sorry should be thus foolishly lost at a game of tick-tack. I’ll to
her.</p>

<p class="drama">
CLAUDIO.<br>
I thank you, good friend Lucio.
</p>

<p class="drama">
LUCIO.<br>
Within two hours.
</p>

<p class="drama">
CLAUDIO.<br>
Come, officer, away.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneI_21.3"></a><b>SCENE III. A monastery.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Duke</span> and
<span class="charname">Friar Thomas</span>.
</p>

<p class="drama">
DUKE.<br>
No, holy father, throw away that thought;<br>
Believe not that the dribbling dart of love<br>
Can pierce a complete bosom. Why I desire thee<br>
To give me secret harbour hath a purpose<br>
More grave and wrinkled than the aims and ends<br>
Of burning youth.
</p>

<p class="drama">
FRIAR THOMAS.<br>
May your Grace speak of it?
</p>

<p class="drama">
DUKE.<br>
My holy sir, none better knows than you<br>
How I have ever loved the life removed,<br>
And held in idle price to haunt assemblies<br>
Where youth, and cost, a witless bravery keeps.<br>
I have delivered to Lord Angelo,<br>
A man of stricture and firm abstinence,<br>
My absolute power and place here in Vienna,<br>
And he supposes me travelled to Poland;<br>
For so I have strewed it in the common ear,<br>
And so it is received. Now, pious sir,<br>
You will demand of me why I do this?
</p>

<p class="drama">
FRIAR THOMAS.<br>
Gladly, my lord.
</p>

<p class="drama">
DUKE.<br>
We have strict statutes and most biting laws,<br>
The needful bits and curbs to headstrong weeds,<br>
Which for this fourteen years we have let slip,<br>
Even like an o’ergrown lion in a cave<br>
That goes not out to prey. Now, as fond fathers,<br>
Having bound up the threat’ning twigs of birch,<br>
Only to stick it in their children’s sight<br>
For terror, not to use, in time the rod<br>
Becomes more mocked than feared: so our decrees,<br>
Dead to infliction, to themselves are dead,<br>
And liberty plucks justice by the nose,<br>
The baby beats the nurse, and quite athwart<br>
Goes all decorum.
</p>

<p class="drama">
FRIAR THOMAS.<br>
It rested in your Grace<br>
To unloose this tied-up justice when you pleased;<br>
And it in you more dreadful would have seemed<br>
Than in Lord Angelo.
</p>

<p class="drama">
DUKE.<br>
I do fear, too dreadful.<br>
Sith ’twas my fault to give the people scope,<br>
’Twould be my tyranny to strike and gall them<br>
For what I bid them do; for we bid this be done<br>
When evil deeds have their permissive pass<br>
And not the punishment. Therefore, indeed, my father,<br>
I have on Angelo imposed the office;<br>
Who may in th’ ambush of my name strike home,<br>
And yet my nature never in the fight<br>
To do in slander. And to behold his sway,<br>
I will, as ’twere a brother of your order,<br>
Visit both prince and people. Therefore, I prithee,<br>
Supply me with the habit, and instruct me<br>
How I may formally in person bear<br>
Like a true friar. Moe reasons for this action<br>
At our more leisure shall I render you;<br>
Only, this one: Lord Angelo is precise;<br>
Stands at a guard with envy; scarce confesses<br>
That his blood flows or that his appetite<br>
Is more to bread than stone. Hence shall we see,<br>
If power change purpose, what our seemers be.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneI_21.4"></a><b>SCENE IV. A nunnery.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Isabella</span> and 
<span class="charname">Francisca,</span> a Nun.
</p>

<p class="drama">
ISABELLA.<br>
And have you nuns no farther privileges?
</p>

<p class="drama">
FRANCISCA.<br>
Are not these large enough?
</p>

<p class="drama">
ISABELLA.<br>
Yes, truly; I speak not as desiring more,<br>
But rather wishing a more strict restraint<br>
Upon the sisterhood, the votarists of Saint Clare.
</p>

<p class="drama">
LUCIO.<br>
[<i>Within</i>.] Ho! Peace be in this place!
</p>

<p class="drama">
ISABELLA.<br>
Who’s that which calls?
</p>

<p class="drama">
FRANCISCA.<br>
It is a man’s voice. Gentle Isabella,<br>
Turn you the key, and know his business of him;<br>
You may, I may not; you are yet unsworn.<br>
When you have vowed, you must not speak with men<br>
But in the presence of the prioress;<br>
Then, if you speak, you must not show your face;<br>
Or if you show your face, you must not speak.<br>
He calls again. I pray you answer him.
</p>

<p class="right">[<i>Exit <span class="charname">Francisca</span>.</i>]</p>

<p class="drama">
ISABELLA.<br>
Peace and prosperity! Who is’t that calls?
</p>

<p class="scenedesc">
Enter <span class="charname">Lucio</span>.
</p>

<p class="drama">
LUCIO.<br>
Hail, virgin, if you be, as those cheek-roses<br>
Proclaim you are no less. Can you so stead me<br>
As bring me to the sight of Isabella,<br>
A novice of this place, and the fair sister<br>
To her unhappy brother Claudio?
</p>

<p class="drama">
ISABELLA.<br>
Why “her unhappy brother”? let me ask,<br>
The rather for I now must make you know<br>
I am that Isabella, and his sister.
</p>

<p class="drama">
LUCIO.<br>
Gentle and fair, your brother kindly greets you.<br>
Not to be weary with you, he’s in prison.
</p>

<p class="drama">
ISABELLA.<br>
Woe me! For what?
</p>

<p class="drama">
LUCIO.<br>
For that which, if myself might be his judge,<br>
He should receive his punishment in thanks:<br>
He hath got his friend with child.
</p>

<p class="drama">
ISABELLA.<br>
Sir, make me not your story.
</p>

<p class="drama">
LUCIO.<br>
’Tis true.<br>
I would not, though ’tis my familiar sin<br>
With maids to seem the lapwing, and to jest,<br>
Tongue far from heart, play with all virgins so.<br>
I hold you as a thing enskied and sainted<br>
By your renouncement an immortal spirit,<br>
And to be talked with in sincerity,<br>
As with a saint.
</p>

<p class="drama">
ISABELLA.<br>
You do blaspheme the good in mocking me.
</p>

<p class="drama">
LUCIO.<br>
Do not believe it. Fewness and truth, ’tis thus:<br>
Your brother and his lover have embraced;<br>
As those that feed grow full, as blossoming time<br>
That from the seedness the bare fallow brings<br>
To teeming foison, even so her plenteous womb<br>
Expresseth his full tilth and husbandry.
</p>

<p class="drama">
ISABELLA.<br>
Someone with child by him? My cousin Juliet?
</p>

<p class="drama">
LUCIO.<br>
Is she your cousin?
</p>

<p class="drama">
ISABELLA.<br>
Adoptedly, as school-maids change their names<br>
By vain though apt affection.
</p>

<p class="drama">
LUCIO.<br>
She it is.
</p>

<p class="drama">
ISABELLA.<br>
O, let him marry her!
</p>

<p class="drama">
LUCIO.<br>
This is the point.<br>
The Duke is very strangely gone from hence;<br>
Bore many gentlemen, myself being one,<br>
In hand, and hope of action; but we do learn,<br>
By those that know the very nerves of state,<br>
His givings-out were of an infinite distance<br>
From his true-meant design. Upon his place,<br>
And with full line of his authority,<br>
Governs Lord Angelo; a man whose blood<br>
Is very snow-broth; one who never feels<br>
The wanton stings and motions of the sense;<br>
But doth rebate and blunt his natural edge<br>
With profits of the mind, study and fast.<br>
He, to give fear to use and liberty,<br>
Which have for long run by the hideous law<br>
As mice by lions, hath picked out an act,<br>
Under whose heavy sense your brother’s life<br>
Falls into forfeit. He arrests him on it,<br>
And follows close the rigour of the statute<br>
To make him an example. All hope is gone,<br>
Unless you have the grace by your fair prayer<br>
To soften Angelo. And that’s my pith of business<br>
’Twixt you and your poor brother.
</p>

<p class="drama">
ISABELLA.<br>
Doth he so<br>
Seek his life?
</p>

<p class="drama">
LUCIO.<br>
Has censured him already; <br>
And, as I hear, the Provost hath a warrant<br>
For’s execution.
</p>

<p class="drama">
ISABELLA.<br>
Alas, what poor ability’s in me<br>
To do him good?
</p>

<p class="drama">
LUCIO.<br>
Assay the power you have.
</p>

<p class="drama">
ISABELLA.<br>
My power? Alas, I doubt.
</p>

<p class="drama">
LUCIO.<br>
Our doubts are traitors,<br>
And make us lose the good we oft might win<br>
By fearing to attempt. Go to Lord Angelo,<br>
And let him learn to know, when maidens sue,<br>
Men give like gods; but when they weep and kneel,<br>
All their petitions are as freely theirs<br>
As they themselves would owe them.
</p>

<p class="drama">
ISABELLA.<br>
I’ll see what I can do.
</p>

<p class="drama">
LUCIO.<br>
But speedily.
</p>

<p class="drama">
ISABELLA.<br>
I will about it straight;<br>
No longer staying but to give the Mother<br>
Notice of my affair. I humbly thank you.<br>
Commend me to my brother. Soon at night<br>
I’ll send him certain word of my success.
</p>

<p class="drama">
LUCIO.<br>
I take my leave of you.
</p>

<p class="drama">
ISABELLA.<br>
Good sir, adieu.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

