<h2> <a id="sceneIII_32.1"></a><b>ACT III</b></h2>

<h3> <b>SCENE I. Before Prospero’s cell.</b></h3>

<p class="scenedesc">Enter <span class="charname">Ferdinand</span> bearing a
log.
</p>

<p class="drama">
FERDINAND.<br>
There be some sports are painful, and their labour<br>
Delight in them sets off: some kinds of baseness<br>
Are nobly undergone; and most poor matters<br>
Point to rich ends. This my mean task<br>
Would be as heavy to me as odious, but<br>
The mistress which I serve quickens what’s dead,<br>
And makes my labours pleasures: O, she is<br>
Ten times more gentle than her father’s crabbed,<br>
And he’s compos’d of harshness. I must remove<br>
Some thousands of these logs, and pile them up,<br>
Upon a sore injunction: my sweet mistress<br>
Weeps when she sees me work, and says such baseness<br>
Had never like executor. I forget:<br>
But these sweet thoughts do even refresh my labours,<br>
Most busy, least when I do it.
</p>

<p class="scenedesc">Enter <span class="charname">Miranda</span> and
<span class="charname">Prospero</span> behind.</p>

<p class="drama">
MIRANDA.<br>
Alas now, pray you,<br>
Work not so hard: I would the lightning had<br>
Burnt up those logs that you are enjoin’d to pile!<br>
Pray, set it down and rest you. When this burns,<br>
’Twill weep for having wearied you. My father<br>
Is hard at study; pray, now, rest yourself:<br>
He’s safe for these three hours.
</p>

<p class="drama">
FERDINAND.<br>
O most dear mistress,<br>
The sun will set, before I shall discharge<br>
What I must strive to do.
</p>

<p class="drama">
MIRANDA.<br>
If you’ll sit down,<br>
I’ll bear your logs the while. Pray give me that;<br>
I’ll carry it to the pile.
</p>

<p class="drama">
FERDINAND.<br>
No, precious creature;<br>
I had rather crack my sinews, break my back,<br>
Than you should such dishonour undergo,<br>
While I sit lazy by.
</p>

<p class="drama">
MIRANDA.<br>
It would become me<br>
As well as it does you: and I should do it<br>
With much more ease; for my good will is to it,<br>
And yours it is against.
</p>

<p class="drama">
PROSPERO.<br>
[<i>Aside.</i>] Poor worm! thou art infected.<br>
This visitation shows it.
</p>

<p class="drama">
MIRANDA.<br>
You look wearily.
</p>

<p class="drama">
FERDINAND.<br>
No, noble mistress; ’tis fresh morning with me<br>
When you are by at night. I do beseech you—<br>
Chiefly that I might set it in my prayers—<br>
What is your name?
</p>

<p class="drama">
MIRANDA.<br>
Miranda—O my father!<br>
I have broke your hest to say so.
</p>

<p class="drama">
FERDINAND.<br>
Admir’d Miranda!<br>
Indeed, the top of admiration; worth<br>
What’s dearest to the world! Full many a lady<br>
I have ey’d with best regard, and many a time<br>
Th’ harmony of their tongues hath into bondage<br>
Brought my too diligent ear: for several virtues<br>
Have I lik’d several women; never any<br>
With so full soul but some defect in her<br>
Did quarrel with the noblest grace she ow’d,<br>
And put it to the foil: but you, O you,<br>
So perfect and so peerless, are created<br>
Of every creature’s best.
</p>

<p class="drama">
MIRANDA.<br>
I do not know<br>
One of my sex; no woman’s face remember,<br>
Save, from my glass, mine own; nor have I seen<br>
More that I may call men than you, good friend,<br>
And my dear father: how features are abroad,<br>
I am skilless of; but, by my modesty,<br>
The jewel in my dower, I would not wish<br>
Any companion in the world but you;<br>
Nor can imagination form a shape,<br>
Besides yourself, to like of. But I prattle<br>
Something too wildly, and my father’s precepts<br>
I therein do forget.
</p>

<p class="drama">
FERDINAND.<br>
I am, in my condition,<br>
A prince, Miranda; I do think, a King;<br>
I would not so!—and would no more endure<br>
This wooden slavery than to suffer<br>
The flesh-fly blow my mouth. Hear my soul speak:<br>
The very instant that I saw you, did<br>
My heart fly to your service; there resides,<br>
To make me slave to it; and for your sake<br>
Am I this patient log-man.
</p>

<p class="drama">
MIRANDA.<br>
Do you love me?
</p>

<p class="drama">
FERDINAND.<br>
O heaven, O earth, bear witness to this sound,<br>
And crown what I profess with kind event,<br>
If I speak true; if hollowly, invert<br>
What best is boded me to mischief! I,<br>
Beyond all limit of what else i’ the world,<br>
Do love, prize, honour you.
</p>

<p class="drama">
MIRANDA.<br>
I am a fool<br>
To weep at what I am glad of.
</p>

<p class="drama">
PROSPERO.<br>
[<i>Aside.</i>] Fair encounter<br>
Of two most rare affections! Heavens rain grace<br>
On that which breeds between ’em!
</p>

<p class="drama">
FERDINAND.<br>
Wherefore weep you?
</p>

<p class="drama">
MIRANDA.<br>
At mine unworthiness, that dare not offer<br>
What I desire to give; and much less take<br>
What I shall die to want. But this is trifling;<br>
And all the more it seeks to hide itself,<br>
The bigger bulk it shows. Hence, bashful cunning!<br>
And prompt me, plain and holy innocence!<br>
I am your wife if you will marry me;<br>
If not, I’ll die your maid: to be your fellow<br>
You may deny me; but I’ll be your servant,<br>
Whether you will or no.
</p>

<p class="drama">
FERDINAND.<br>
My mistress, dearest;<br>
And I thus humble ever.
</p>

<p class="drama">
MIRANDA.<br>
My husband, then?
</p>

<p class="drama">
FERDINAND.<br>
Ay, with a heart as willing<br>
As bondage e’er of freedom: here’s my hand.
</p>

<p class="drama">
MIRANDA.<br>
And mine, with my heart in ’t: and now farewell<br>
Till half an hour hence.
</p>

<p class="drama">
FERDINAND.<br>
A thousand thousand!
</p>

<p class="right"> [<i>Exeunt <span class="charname">Ferdinand</span> and <span class="charname">Miranda</span> severally.</i>]</p>

<p class="drama">
PROSPERO.<br>
So glad of this as they, I cannot be,<br>
Who are surpris’d withal; but my rejoicing<br>
At nothing can be more. I’ll to my book;<br>
For yet, ere supper time, must I perform<br>
Much business appertaining.
</p>

<p class="right"> [<i>Exit.</i>]</p>

<h3> <a id="sceneIII_32.2"></a><b>SCENE II. Another part of the island.</b></h3>

<p class="scenedesc">Enter <span class="charname">Caliban</span> with a bottle,
<span class="charname">Stephano</span> and <span class="charname">Trinculo</span>.</p>

<p class="drama">
STEPHANO.<br>
Tell not me:—when the butt is out we will drink water; not a drop before:
therefore bear up, and board ’em. Servant-monster, drink to me.
</p>

<p class="drama">
TRINCULO.<br>
Servant-monster! The folly of this island! They say there’s but five upon
this isle; we are three of them; if th’ other two be brained like us, the
state totters.
</p>

<p class="drama">
STEPHANO.<br>
Drink, servant-monster, when I bid thee: thy eyes are almost set in thy head.
</p>

<p class="drama">
TRINCULO.<br>
Where should they be set else? He were a brave monster indeed, if they were set
in his tail.
</p>

<p class="drama">
STEPHANO.<br>
My man-monster hath drown’d his tongue in sack: for my part, the sea
cannot drown me; I swam, ere I could recover the shore, five-and-thirty
leagues, off and on, by this light. Thou shalt be my lieutenant, monster, or my
standard.
</p>

<p class="drama">
TRINCULO.<br>
Your lieutenant, if you list; he’s no standard.
</p>

<p class="drama">
STEPHANO.<br>
We’ll not run, Monsieur monster.
</p>

<p class="drama">
TRINCULO.<br>
Nor go neither. But you’ll lie like dogs, and yet say nothing neither.
</p>

<p class="drama">
STEPHANO.<br>
Moon-calf, speak once in thy life, if thou beest a good moon-calf.
</p>

<p class="drama">
CALIBAN.<br>
How does thy honour? Let me lick thy shoe. I’ll not serve him, he is not
valiant.
</p>

<p class="drama">
TRINCULO.<br>
Thou liest, most ignorant monster: I am in case to justle a constable. Why,
thou deboshed fish thou, was there ever man a coward that hath drunk so much
sack as I today? Wilt thou tell a monstrous lie, being but half a fish and half
a monster?
</p>

<p class="drama">
CALIBAN.<br>
Lo, how he mocks me! wilt thou let him, my lord?
</p>

<p class="drama">
TRINCULO.<br>
“Lord” quoth he! That a monster should be such a natural!
</p>

<p class="drama">
CALIBAN.<br>
Lo, lo again! bite him to death, I prithee.
</p>

<p class="drama">
STEPHANO.<br>
Trinculo, keep a good tongue in your head: if you prove a mutineer, the next
tree! The poor monster’s my subject, and he shall not suffer indignity.
</p>

<p class="drama">
CALIBAN.<br>
I thank my noble lord. Wilt thou be pleas’d to hearken once again to the
suit I made to thee?
</p>

<p class="drama">
STEPHANO.<br>
Marry. will I. Kneel and repeat it. I will stand, and so shall Trinculo.
</p>

<p class="scenedesc">Enter <span class="charname">Ariel,</span> invisible.
</p>

<p class="drama">
CALIBAN.<br>
As I told thee before, I am subject to a tyrant, a sorcerer, that by his
cunning hath cheated me of the island.
</p>

<p class="drama">
ARIEL.<br>
Thou liest.
</p>

<p class="drama">
CALIBAN.<br>
Thou liest, thou jesting monkey, thou;<br>
I would my valiant master would destroy thee;<br>
I do not lie.
</p>

<p class="drama">
STEPHANO.<br>
Trinculo, if you trouble him any more in his tale, by this hand, I will
supplant some of your teeth.
</p>

<p class="drama">
TRINCULO.<br>
Why, I said nothing.
</p>

<p class="drama">
STEPHANO.<br>
Mum, then, and no more. Proceed.
</p>

<p class="drama">
CALIBAN.<br>
I say, by sorcery he got this isle;<br>
From me he got it. If thy greatness will,<br>
Revenge it on him,—for I know thou dar’st;<br>
But this thing dare not,—
</p>

<p class="drama">
STEPHANO.<br>
That’s most certain.
</p>

<p class="drama">
CALIBAN.<br>
Thou shalt be lord of it and I’ll serve thee.
</p>

<p class="drama">
STEPHANO.<br>
How now shall this be compassed? Canst thou bring me to the party?
</p>

<p class="drama">
CALIBAN.<br>
Yea, yea, my lord: I’ll yield him thee asleep,<br>
Where thou mayst knock a nail into his head.
</p>

<p class="drama">
ARIEL.<br>
Thou liest. Thou canst not.
</p>

<p class="drama">
CALIBAN.<br>
What a pied ninny’s this! Thou scurvy patch!<br>
I do beseech thy greatness, give him blows,<br>
And take his bottle from him: when that’s gone<br>
He shall drink nought but brine; for I’ll not show him<br>
Where the quick freshes are.
</p>

<p class="drama">
STEPHANO.<br>
Trinculo, run into no further danger: interrupt the monster one word further,
and by this hand, I’ll turn my mercy out o’ doors, and make a
stock-fish of thee.
</p>

<p class="drama">
TRINCULO.<br>
Why, what did I? I did nothing. I’ll go farther off.
</p>

<p class="drama">
STEPHANO.<br>
Didst thou not say he lied?
</p>

<p class="drama">
ARIEL.<br>
Thou liest.
</p>

<p class="drama">
STEPHANO.<br>
Do I so? Take thou that.
</p>

<p class="right"> [<i>Strikes Trinculo.</i>]</p>

<p class="drama">
As you like this, give me the lie another time.
</p>

<p class="drama">
TRINCULO.<br>
I did not give the lie. Out o’ your wits and hearing too? A pox o’
your bottle! this can sack and drinking do. A murrain on your monster, and the
devil take your fingers!
</p>

<p class="drama">
CALIBAN.<br>
Ha, ha, ha!
</p>

<p class="drama">
STEPHANO.<br>
Now, forward with your tale.—Prithee stand further off.
</p>

<p class="drama">
CALIBAN.<br>
Beat him enough: after a little time,<br>
I’ll beat him too.
</p>

<p class="drama">
STEPHANO.<br>
Stand farther.—Come, proceed.
</p>

<p class="drama">
CALIBAN.<br>
Why, as I told thee, ’tis a custom with him<br>
I’ th’ afternoon to sleep: there thou mayst brain him,<br>
Having first seiz’d his books; or with a log<br>
Batter his skull, or paunch him with a stake,<br>
Or cut his wezand with thy knife. Remember<br>
First to possess his books; for without them<br>
He’s but a sot, as I am, nor hath not<br>
One spirit to command: they all do hate him<br>
As rootedly as I. Burn but his books.<br>
He has brave utensils,—for so he calls them,—<br>
Which, when he has a house, he’ll deck withal.<br>
And that most deeply to consider is<br>
The beauty of his daughter; he himself<br>
Calls her a nonpareil: I never saw a woman<br>
But only Sycorax my dam and she;<br>
But she as far surpasseth Sycorax<br>
As great’st does least.
</p>

<p class="drama">
STEPHANO.<br>
Is it so brave a lass?
</p>

<p class="drama">
CALIBAN.<br>
Ay, lord, she will become thy bed, I warrant,<br>
And bring thee forth brave brood.
</p>

<p class="drama">
STEPHANO.<br>
Monster, I will kill this man. His daughter and I will be king and
queen,—save our graces!—and Trinculo and thyself shall be viceroys.
Dost thou like the plot, Trinculo?
</p>

<p class="drama">
TRINCULO.<br>
Excellent.
</p>

<p class="drama">
STEPHANO.<br>
Give me thy hand: I am sorry I beat thee; but while thou liv’st, keep a
good tongue in thy head.
</p>

<p class="drama">
CALIBAN.<br>
Within this half hour will he be asleep.<br>
Wilt thou destroy him then?
</p>

<p class="drama">
STEPHANO.<br>
Ay, on mine honour.
</p>

<p class="drama">
ARIEL.<br>
This will I tell my master.
</p>

<p class="drama">
CALIBAN.<br>
Thou mak’st me merry. I am full of pleasure.<br>
Let us be jocund: will you troll the catch<br>
You taught me but while-ere?
</p>

<p class="drama">
STEPHANO.<br>
At thy request, monster, I will do reason, any reason. Come on, Trinculo, let
us sing.
</p>

<p class="drama">
[<i>Sings.</i>]</p>

<p class="drama">
<i>Flout ’em and cout ’em,<br>
and scout ’em and flout ’em:<br>
    Thought is free.</i>
</p>

<p class="drama">
CALIBAN.<br>
That’s not the tune.
</p>

<p class="right"> [<i><span class="charname">Ariel</span> plays the tune on a
tabor and pipe.</i>]</p>

<p class="drama">
STEPHANO.<br>
What is this same?
</p>

<p class="drama">
TRINCULO.<br>
This is the tune of our catch, played by the picture of Nobody.
</p>

<p class="drama">
STEPHANO.<br>
If thou beest a man, show thyself in thy likeness: if thou beest a devil,
take ’t as thou list.
</p>

<p class="drama">
TRINCULO.<br>
O, forgive me my sins!
</p>

<p class="drama">
STEPHANO.<br>
He that dies pays all debts: I defy thee. Mercy upon us!
</p>

<p class="drama">
CALIBAN.<br>
Art thou afeard?
</p>

<p class="drama">
STEPHANO.<br>
No, monster, not I.
</p>

<p class="drama">
CALIBAN.<br>
Be not afeard. The isle is full of noises,<br>
Sounds, and sweet airs, that give delight, and hurt not.<br>
Sometimes a thousand twangling instruments<br>
Will hum about mine ears; and sometimes voices,<br>
That, if I then had wak’d after long sleep,<br>
Will make me sleep again: and then, in dreaming,<br>
The clouds methought would open and show riches<br>
Ready to drop upon me; that, when I wak’d,<br>
I cried to dream again.
</p>

<p class="drama">
STEPHANO.<br>
This will prove a brave kingdom to me, where I shall have my music for nothing.
</p>

<p class="drama">
CALIBAN.<br>
When Prospero is destroyed.
</p>

<p class="drama">
STEPHANO.<br>
That shall be by and by: I remember the story.
</p>

<p class="drama">
TRINCULO.<br>
The sound is going away. Let’s follow it, and after do our work.
</p>

<p class="drama">
STEPHANO.<br>
Lead, monster: we’ll follow. I would I could see this taborer! he lays it
on. Wilt come?
</p>

<p class="drama">
TRINCULO.<br>
I’ll follow, Stephano.
</p>

<p class="right"> [<i>Exeunt.</i>]</p>

<h3> <a id="sceneIII_32.3"></a><b>SCENE III. Another part of the island.</b></h3>

<p class="scenedesc">Enter <span class="charname">Alonso, Sebastian, Antonio,
Gonzalo, Adrian, Francisco,</span> &amp;c.</p>

<p class="drama">
GONZALO.<br>
By ’r lakin, I can go no further, sir;<br>
My old bones ache: here’s a maze trod, indeed,<br>
Through forth-rights and meanders! By your patience,<br>
I needs must rest me.
</p>

<p class="drama">
ALONSO.<br>
Old lord, I cannot blame thee,<br>
Who am myself attach’d with weariness<br>
To th’ dulling of my spirits: sit down, and rest.<br>
Even here I will put off my hope, and keep it<br>
No longer for my flatterer: he is drown’d<br>
Whom thus we stray to find; and the sea mocks<br>
Our frustrate search on land. Well, let him go.
</p>

<p class="drama">
ANTONIO.<br>
[<i>Aside to Sebastian.</i>] I am right glad that he’s<br>
so out of hope.<br>
Do not, for one repulse, forgo the purpose<br>
That you resolv’d to effect.
</p>

<p class="drama">
SEBASTIAN.<br>
[<i>Aside to Antonio.</i>] The next advantage<br>
Will we take throughly.
</p>

<p class="drama">
ANTONIO.<br>
[<i>Aside to Sebastian.</i>] Let it be tonight;<br>
For, now they are oppress’d with travel, they<br>
Will not, nor cannot, use such vigilance<br>
As when they are fresh.
</p>

<p class="drama">
SEBASTIAN.<br>
[<i>Aside to Antonio.</i>] I say, tonight: no more.
</p>

<p class="scenedesc">Solemn and strange music: and <span class="charname">Prospero</span> above, invisible. Enter several strange
Shapes, bringing in a banquet: they dance about it with gentle actions of
salutation; and inviting the <span class="charname">King</span> &amp;c., to
eat, they depart.</p>

<p class="drama">
ALONSO.<br>
What harmony is this? My good friends, hark!
</p>

<p class="drama">
GONZALO.<br>
Marvellous sweet music!
</p>

<p class="drama">
ALONSO.<br>
Give us kind keepers, heavens! What were these?
</p>

<p class="drama">
SEBASTIAN.<br>
A living drollery. Now I will believe<br>
That there are unicorns; that in Arabia<br>
There is one tree, the phoenix’ throne; one phoenix<br>
At this hour reigning there.
</p>

<p class="drama">
ANTONIO.<br>
I’ll believe both;<br>
And what does else want credit, come to me,<br>
And I’ll be sworn ’tis true: travellers ne’er did lie,<br>
Though fools at home condemn them.
</p>

<p class="drama">
GONZALO.<br>
If in Naples<br>
I should report this now, would they believe me?<br>
If I should say, I saw such islanders,—<br>
For, certes, these are people of the island,—<br>
Who, though, they are of monstrous shape, yet, note,<br>
Their manners are more gentle, kind, than of<br>
Our human generation you shall find<br>
Many, nay, almost any.
</p>

<p class="drama">
PROSPERO.<br>
[<i>Aside.</i>] Honest lord,<br>
Thou hast said well; for some of you there present<br>
Are worse than devils.
</p>

<p class="drama">
ALONSO.<br>
I cannot too much muse<br>
Such shapes, such gesture, and such sound, expressing—<br>
Although they want the use of tongue—a kind<br>
Of excellent dumb discourse.
</p>

<p class="drama">
PROSPERO.<br>
[<i>Aside.</i>] Praise in departing.
</p>

<p class="drama">
FRANCISCO.<br>
They vanish’d strangely.
</p>

<p class="drama">
SEBASTIAN.<br>
No matter, since<br>
They have left their viands behind; for we have stomachs.—<br>
Will’t please you taste of what is here?
</p>

<p class="drama">
ALONSO.<br>
Not I.
</p>

<p class="drama">
GONZALO.<br>
Faith, sir, you need not fear. When we were boys,<br>
Who would believe that there were mountaineers<br>
Dewlapp’d like bulls, whose throats had hanging at ’em<br>
Wallets of flesh? Or that there were such men<br>
Whose heads stood in their breasts? which now we find<br>
Each putter-out of five for one will bring us<br>
Good warrant of.
</p>

<p class="drama">
ALONSO.<br>
I will stand to, and feed,<br>
Although my last, no matter, since I feel<br>
The best is past. Brother, my lord the duke,<br>
Stand to, and do as we.
</p>

<p class="scenedesc">Thunder and lightning. Enter <span class="charname">Ariel</span> like a Harpy; claps his wings upon the table;
and, with a quaint device, the banquet vanishes.
</p>

<p class="drama">
ARIEL.<br>
You are three men of sin, whom Destiny,<br>
That hath to instrument this lower world<br>
And what is in’t,—the never-surfeited sea<br>
Hath caused to belch up you; and on this island<br>
Where man doth not inhabit; you ’mongst men<br>
Being most unfit to live. I have made you mad;<br>
And even with such-like valour men hang and drown<br>
Their proper selves.
</p>

<p class="right"> [<i>Seeing <span class="charname">Alonso, Sebastian</span>
&amp;c., draw their swords.</i>]</p>

<p class="drama">
You fools! I and my fellows<br>
Are ministers of Fate: the elements<br>
Of whom your swords are temper’d may as well<br>
Wound the loud winds, or with bemock’d-at stabs<br>
Kill the still-closing waters, as diminish<br>
One dowle that’s in my plume. My fellow-ministers<br>
Are like invulnerable. If you could hurt,<br>
Your swords are now too massy for your strengths,<br>
And will not be uplifted. But, remember—<br>
For that’s my business to you,—that you three<br>
From Milan did supplant good Prospero;<br>
Expos’d unto the sea, which hath requit it,<br>
Him and his innocent child: for which foul deed<br>
The powers, delaying, not forgetting, have<br>
Incens’d the seas and shores, yea, all the creatures,<br>
Against your peace. Thee of thy son, Alonso,<br>
They have bereft; and do pronounce, by me<br>
Ling’ring perdition,—worse than any death<br>
Can be at once,—shall step by step attend<br>
You and your ways; whose wraths to guard you from—<br>
Which here, in this most desolate isle, else falls<br>
Upon your heads,—is nothing but heart-sorrow,<br>
And a clear life ensuing.
</p>

<p class="right"> [<i>He vanishes in thunder: then, to soft music, enter the
Shapes again, and dance, with mocks and mows, and carry out the table.</i>]</p>

<p class="drama">
PROSPERO.<br>
[<i>Aside.</i>] Bravely the figure of this Harpy hast thou<br>
Perform’d, my Ariel; a grace it had, devouring.<br>
Of my instruction hast thou nothing bated<br>
In what thou hadst to say: so, with good life<br>
And observation strange, my meaner ministers<br>
Their several kinds have done. My high charms work,<br>
And these mine enemies are all knit up<br>
In their distractions; they now are in my power;<br>
And in these fits I leave them, while I visit<br>
Young Ferdinand,—whom they suppose is drown’d,—<br>
And his and mine lov’d darling.
</p>

<p class="right"> [<i>Exit above.</i>]</p>

<p class="drama">
GONZALO.<br>
I’ the name of something holy, sir, why stand you<br>
In this strange stare?
</p>

<p class="drama">
ALONSO.<br>
O, it is monstrous! monstrous!<br>
Methought the billows spoke, and told me of it;<br>
The winds did sing it to me; and the thunder,<br>
That deep and dreadful organ-pipe, pronounc’d<br>
The name of Prosper: it did bass my trespass.<br>
Therefore my son i’ th’ ooze is bedded; and<br>
I’ll seek him deeper than e’er plummet sounded,<br>
And with him there lie mudded.
</p>

<p class="right"> [<i>Exit.</i>]</p>

<p class="drama">
SEBASTIAN.<br>
But one fiend at a time,<br>
I’ll fight their legions o’er.
</p>

<p class="drama">
ANTONIO.<br>
I’ll be thy second.
</p>

<p class="right"> [<i>Exeunt <span class="charname">Sebastian</span> and <span class="charname">Antonio</span>.</i>]</p>

<p class="drama">
GONZALO.<br>
All three of them are desperate: their great guilt,<br>
Like poison given to work a great time after,<br>
Now ’gins to bite the spirits. I do beseech you<br>
That are of suppler joints, follow them swiftly<br>
And hinder them from what this ecstasy<br>
May now provoke them to.
</p>

<p class="drama">
ADRIAN.<br>
Follow, I pray you.
</p>

<p class="right"> [<i>Exeunt.</i>]</p>

