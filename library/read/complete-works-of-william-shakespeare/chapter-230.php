<h2> <a id="sceneI_37.1"></a><b>ACT I</b></h2>

<h3> <b>SCENE I. Verona. An open place</b></h3>

<p class="scenedesc">
Enter <span class="charname">Valentine</span> and
<span class="charname">Proteus</span>.
</p>

<p class="drama">
VALENTINE.<br>
Cease to persuade, my loving Proteus.<br>
Home-keeping youth have ever homely wits.<br>
Were’t not affection chains thy tender days<br>
To the sweet glances of thy honoured love,<br>
I rather would entreat thy company<br>
To see the wonders of the world abroad<br>
Than, living dully sluggardized at home,<br>
Wear out thy youth with shapeless idleness.<br>
But since thou lov’st, love still, and thrive therein,<br>
Even as I would when I to love begin.
</p>

<p class="drama">
PROTEUS.<br>
Wilt thou be gone? Sweet Valentine, adieu.<br>
Think on thy Proteus when thou haply seest<br>
Some rare noteworthy object in thy travel.<br>
Wish me partaker in thy happiness<br>
When thou dost meet good hap; and in thy danger,<br>
If ever danger do environ thee,<br>
Commend thy grievance to my holy prayers,<br>
For I will be thy headsman, Valentine.
</p>

<p class="drama">
VALENTINE.<br>
And on a love-book pray for my success?
</p>

<p class="drama">
PROTEUS.<br>
Upon some book I love I’ll pray for thee.
</p>

<p class="drama">
VALENTINE.<br>
That’s on some shallow story of deep love,<br>
How young Leander crossed the Hellespont.
</p>

<p class="drama">
PROTEUS.<br>
That’s a deep story of a deeper love,<br>
For he was more than over shoes in love.
</p>

<p class="drama">
VALENTINE.<br>
’Tis true; for you are over boots in love,<br>
And yet you never swam the Hellespont.
</p>

<p class="drama">
PROTEUS.<br>
Over the boots? Nay, give me not the boots.
</p>

<p class="drama">
VALENTINE.<br>
No, I will not, for it boots thee not.
</p>

<p class="drama">
PROTEUS.<br>
What?
</p>

<p class="drama">
VALENTINE.<br>
To be in love, where scorn is bought with groans,<br>
Coy looks with heart-sore sighs, one fading moment’s mirth<br>
With twenty watchful, weary, tedious nights.<br>
If haply won, perhaps a hapless gain;<br>
If lost, why then a grievous labour won;<br>
However, but a folly bought with wit,<br>
Or else a wit by folly vanquished.
</p>

<p class="drama">
PROTEUS.<br>
So, by your circumstance, you call me fool.
</p>

<p class="drama">
VALENTINE.<br>
So, by your circumstance, I fear you’ll prove.
</p>

<p class="drama">
PROTEUS.<br>
’Tis love you cavil at. I am not Love.
</p>

<p class="drama">
VALENTINE.<br>
Love is your master, for he masters you;<br>
And he that is so yoked by a fool<br>
Methinks should not be chronicled for wise.
</p>

<p class="drama">
PROTEUS.<br>
Yet writers say, as in the sweetest bud<br>
The eating canker dwells, so eating love<br>
Inhabits in the finest wits of all.
</p>

<p class="drama">
VALENTINE.<br>
And writers say, as the most forward bud<br>
Is eaten by the canker ere it blow,<br>
Even so by love the young and tender wit<br>
Is turned to folly, blasting in the bud,<br>
Losing his verdure even in the prime,<br>
And all the fair effects of future hopes.<br>
But wherefore waste I time to counsel thee<br>
That art a votary to fond desire?<br>
Once more adieu. My father at the road<br>
Expects my coming, there to see me shipped.
</p>

<p class="drama">
PROTEUS.<br>
And thither will I bring thee, Valentine.
</p>

<p class="drama">
VALENTINE.<br>
Sweet Proteus, no. Now let us take our leave.<br>
To Milan let me hear from thee by letters<br>
Of thy success in love, and what news else<br>
Betideth here in absence of thy friend;<br>
And I likewise will visit thee with mine.
</p>

<p class="drama">
PROTEUS.<br>
All happiness bechance to thee in Milan.
</p>

<p class="drama">
VALENTINE.<br>
As much to you at home, and so farewell.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
PROTEUS.<br>
He after honour hunts, I after love.<br>
He leaves his friends to dignify them more;<br>
I leave myself, my friends, and all for love.<br>
Thou, Julia, thou hast metamorphosed me,<br>
Made me neglect my studies, lose my time,<br>
War with good counsel, set the world at nought;<br>
Made wit with musing weak, heart sick with thought.
</p>

<p class="scenedesc">
Enter <span class="charname">Speed</span>.
</p>

<p class="drama">
SPEED.<br>
Sir Proteus, ’save you. Saw you my master?
</p>

<p class="drama">
PROTEUS.<br>
But now he parted hence to embark for Milan.
</p>

<p class="drama">
SPEED.<br>
Twenty to one, then, he is shipped already,<br>
And I have played the sheep in losing him.
</p>

<p class="drama">
PROTEUS.<br>
Indeed a sheep doth very often stray,<br>
An if the shepherd be a while away.
</p>

<p class="drama">
SPEED.<br>
You conclude that my master is a shepherd then, and I a sheep?
</p>

<p class="drama">
PROTEUS.<br>
I do.
</p>

<p class="drama">
SPEED.<br>
Why then, my horns are his horns, whether I wake or sleep.
</p>

<p class="drama">
PROTEUS.<br>
A silly answer, and fitting well a sheep.
</p>

<p class="drama">
SPEED.<br>
This proves me still a sheep.
</p>

<p class="drama">
PROTEUS.<br>
True, and thy master a shepherd.
</p>

<p class="drama">
SPEED.<br>
Nay, that I can deny by a circumstance.
</p>

<p class="drama">
PROTEUS.<br>
It shall go hard but I’ll prove it by another.
</p>

<p class="drama">
SPEED.<br>
The shepherd seeks the sheep, and not the sheep the shepherd; but I seek my
master, and my master seeks not me. Therefore I am no sheep.
</p>

<p class="drama">
PROTEUS.<br>
The sheep for fodder follow the shepherd; the shepherd for food follows not the
sheep. Thou for wages followest thy master; thy master for wages follows not
thee. Therefore thou art a sheep.
</p>

<p class="drama">
SPEED.<br>
Such another proof will make me cry “baa”.
</p>

<p class="drama">
PROTEUS.<br>
But dost thou hear? Gav’st thou my letter to Julia?
</p>

<p class="drama">
SPEED.<br>
Ay, sir. I, a lost mutton, gave your letter to her, a laced mutton, and she, a
laced mutton, gave me, a lost mutton, nothing for my labour.
</p>

<p class="drama">
PROTEUS.<br>
Here’s too small a pasture for such store of muttons.
</p>

<p class="drama">
SPEED.<br>
If the ground be overcharged, you were best stick her.
</p>

<p class="drama">
PROTEUS.<br>
Nay, in that you are astray; ’twere best pound you.
</p>

<p class="drama">
SPEED.<br>
Nay, sir, less than a pound shall serve me for carrying your letter.
</p>

<p class="drama">
PROTEUS.<br>
You mistake; I mean the pound, a pinfold.
</p>

<p class="drama">
SPEED.<br>
From a pound to a pin? Fold it over and over,<br>
’Tis threefold too little for carrying a letter to your lover.
</p>

<p class="drama">
PROTEUS.<br>
But what said she?
</p>

<p class="drama">
SPEED.<br>
[<i>Nods his head</i>.] Ay.
</p>

<p class="drama">
PROTEUS.<br>
Nod—“Ay”. Why, that’s “noddy”.
</p>

<p class="drama">
SPEED.<br>
You mistook, sir. I say she did nod, and you ask me if she did nod; and I say
“Ay”.
</p>

<p class="drama">
PROTEUS.<br>
And that set together is “noddy”.
</p>

<p class="drama">
SPEED.<br>
Now you have taken the pains to set it together, take it for your pains.
</p>

<p class="drama">
PROTEUS.<br>
No, no, you shall have it for bearing the letter.
</p>

<p class="drama">
SPEED.<br>
Well, I perceive I must be fain to bear with you.
</p>

<p class="drama">
PROTEUS.<br>
Why, sir, how do you bear with me?
</p>

<p class="drama">
SPEED.<br>
Marry, sir, the letter, very orderly, having nothing but the word “noddy” for
my pains.
</p>

<p class="drama">
PROTEUS.<br>
Beshrew me, but you have a quick wit.
</p>

<p class="drama">
SPEED.<br>
And yet it cannot overtake your slow purse.
</p>

<p class="drama">
PROTEUS.<br>
Come, come, open the matter; in brief, what said she?
</p>

<p class="drama">
SPEED.<br>
Open your purse, that the money and the matter may be both at once delivered.
</p>

<p class="drama">
PROTEUS.<br>
[<i>Giving him a coin</i>.] Well, sir, here is for your pains. What said she?
</p>

<p class="drama">
SPEED.<br>
Truly, sir, I think you’ll hardly win her.
</p>

<p class="drama">
PROTEUS.<br>
Why? Couldst thou perceive so much from her?
</p>

<p class="drama">
SPEED.<br>
Sir, I could perceive nothing at all from her; no, not so much as a ducat for
delivering your letter. And being so hard to me that brought your mind, I fear
she’ll prove as hard to you in telling your mind. Give her no token but stones,
for she’s as hard as steel.
</p>

<p class="drama">
PROTEUS.<br>
What said she, nothing?
</p>

<p class="drama">
SPEED.<br>
No, not so much as “Take this for thy pains.” To testify your bounty, I thank
you, you have testerned me; in requital whereof, henceforth carry your letters
yourself. And so, sir, I’ll commend you to my master.
</p>

<p class="drama">
PROTEUS.<br>
Go, go, begone, to save your ship from wrack,<br>
Which cannot perish having thee aboard,<br>
Being destined to a drier death on shore.
</p>

<p class="right">[<i>Exit <span class="charname">Speed</span>.</i>]</p>


<p class="drama">
I must go send some better messenger.<br>
I fear my Julia would not deign my lines,<br>
Receiving them from such a worthless post.
</p>

<p class="right">[<i>Exit.</i>]</p>

<h3> <a id="sceneI_37.2"></a><b>SCENE II. The same. The garden of Julia’s house</b></h3>

<p class="scenedesc">
Enter <span class="charname">Julia</span> and
<span class="charname">Lucetta</span>.
</p>

<p class="drama">
JULIA.<br>
But say, Lucetta, now we are alone,<br>
Wouldst thou then counsel me to fall in love?
</p>

<p class="drama">
LUCETTA.<br>
Ay, madam, so you stumble not unheedfully.
</p>

<p class="drama">
JULIA.<br>
Of all the fair resort of gentlemen<br>
That every day with parle encounter me,<br>
In thy opinion which is worthiest love?
</p>

<p class="drama">
LUCETTA.<br>
Please you, repeat their names, I’ll show my mind<br>
According to my shallow simple skill.
</p>

<p class="drama">
JULIA.<br>
What think’st thou of the fair Sir Eglamour?
</p>

<p class="drama">
LUCETTA.<br>
As of a knight well-spoken, neat, and fine;<br>
But, were I you, he never should be mine.
</p>

<p class="drama">
JULIA.<br>
What think’st thou of the rich Mercatio?
</p>

<p class="drama">
LUCETTA.<br>
Well of his wealth; but of himself, so-so.
</p>

<p class="drama">
JULIA.<br>
What think’st thou of the gentle Proteus?
</p>

<p class="drama">
LUCETTA.<br>
Lord, Lord, to see what folly reigns in us!
</p>

<p class="drama">
JULIA.<br>
How now? What means this passion at his name?
</p>

<p class="drama">
LUCETTA.<br>
Pardon, dear madam, ’tis a passing shame<br>
That I, unworthy body as I am,<br>
Should censure thus on lovely gentlemen.
</p>

<p class="drama">
JULIA.<br>
Why not on Proteus, as of all the rest?
</p>

<p class="drama">
LUCETTA.<br>
Then thus: of many good I think him best.
</p>

<p class="drama">
JULIA.<br>
Your reason?
</p>

<p class="drama">
LUCETTA.<br>
I have no other but a woman’s reason:<br>
I think him so because I think him so.
</p>

<p class="drama">
JULIA.<br>
And wouldst thou have me cast my love on him?
</p>

<p class="drama">
LUCETTA.<br>
Ay, if you thought your love not cast away.
</p>

<p class="drama">
JULIA.<br>
Why, he of all the rest hath never moved me.
</p>

<p class="drama">
LUCETTA.<br>
Yet he of all the rest I think best loves ye.
</p>

<p class="drama">
JULIA.<br>
His little speaking shows his love but small.
</p>

<p class="drama">
LUCETTA.<br>
Fire that’s closest kept burns most of all.
</p>

<p class="drama">
JULIA.<br>
They do not love that do not show their love.
</p>

<p class="drama">
LUCETTA.<br>
O, they love least that let men know their love.
</p>

<p class="drama">
JULIA.<br>
I would I knew his mind.
</p>

<p class="drama">
LUCETTA.<br>
Peruse this paper, madam.
</p>

<p class="right">[<i>Gives her a letter.</i>]</p>

<p class="drama">
JULIA.<br>
<i>To Julia</i>—Say, from whom?
</p>

<p class="drama">
LUCETTA.<br>
That the contents will show.
</p>

<p class="drama">
JULIA.<br>
Say, say, who gave it thee?
</p>

<p class="drama">
LUCETTA.<br>
Sir Valentine’s page, and sent, I think, from Proteus.<br>
He would have given it you, but I, being in the way,<br>
Did in your name receive it. Pardon the fault, I pray.
</p>

<p class="drama">
JULIA.<br>
Now, by my modesty, a goodly broker!<br>
Dare you presume to harbour wanton lines?<br>
To whisper and conspire against my youth?<br>
Now trust me, ’tis an office of great worth,<br>
And you an officer fit for the place.<br>
There, take the paper; see it be returned,<br>
Or else return no more into my sight.
</p>

<p class="drama">
LUCETTA.<br>
To plead for love deserves more fee than hate.
</p>

<p class="drama">
JULIA.<br>
Will ye be gone?
</p>

<p class="drama">
LUCETTA.<br>
That you may ruminate.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
JULIA.<br>
And yet I would I had o’erlooked the letter.<br>
It were a shame to call her back again<br>
And pray her to a fault for which I chid her.<br>
What fool is she, that knows I am a maid<br>
And would not force the letter to my view,<br>
Since maids in modesty say “No” to that<br>
Which they would have the profferer construe “Ay”.<br>
Fie, fie, how wayward is this foolish love<br>
That like a testy babe will scratch the nurse<br>
And presently, all humbled, kiss the rod!<br>
How churlishly I chid Lucetta hence,<br>
When willingly I would have had her here!<br>
How angerly I taught my brow to frown,<br>
When inward joy enforced my heart to smile!<br>
My penance is to call Lucetta back<br>
And ask remission for my folly past.<br>
What ho! Lucetta!
</p>

<p class="scenedesc">
Enter <span class="charname">Lucetta</span>.
</p>

<p class="drama">
LUCETTA.<br>
What would your ladyship?
</p>

<p class="drama">
JULIA.<br>
Is ’t near dinner time?
</p>

<p class="drama">
LUCETTA.<br>
I would it were,<br>
That you might kill your stomach on your meat<br>
And not upon your maid.
</p>

<p class="right">[<i>Drops and picks up the letter.</i>]</p>

<p class="drama">
JULIA.<br>
What is’t that you took up so gingerly?
</p>

<p class="drama">
LUCETTA.<br>
Nothing.
</p>

<p class="drama">
JULIA.<br>
Why didst thou stoop, then?
</p>

<p class="drama">
LUCETTA.<br>
To take a paper up that I let fall.
</p>

<p class="drama">
JULIA.<br>
And is that paper nothing?
</p>

<p class="drama">
LUCETTA.<br>
Nothing concerning me.
</p>

<p class="drama">
JULIA.<br>
Then let it lie for those that it concerns.
</p>

<p class="drama">
LUCETTA.<br>
Madam, it will not lie where it concerns,<br>
Unless it have a false interpreter.
</p>

<p class="drama">
JULIA.<br>
Some love of yours hath writ to you in rhyme.
</p>

<p class="drama">
LUCETTA.<br>
That I might sing it, madam, to a tune.<br>
Give me a note. Your ladyship can set—
</p>

<p class="drama">
JULIA.<br>
As little by such toys as may be possible.<br>
Best sing it to the tune of “Light o’ Love”.
</p>

<p class="drama">
LUCETTA.<br>
It is too heavy for so light a tune.
</p>

<p class="drama">
JULIA.<br>
Heavy? Belike it hath some burden then?
</p>

<p class="drama">
LUCETTA.<br>
Ay, and melodious were it, would you sing it.
</p>

<p class="drama">
JULIA.<br>
And why not you?
</p>

<p class="drama">
LUCETTA.<br>
I cannot reach so high.
</p>

<p class="drama">
JULIA.<br>
Let’s see your song. [<i>Taking the letter</i>.]<br>
How now, minion!
</p>

<p class="drama">
LUCETTA.<br>
Keep tune there still, so you will sing it out.<br>
And yet methinks I do not like this tune.
</p>

<p class="drama">
JULIA.<br>
You do not?
</p>

<p class="drama">
LUCETTA.<br>
No, madam, it is too sharp.
</p>

<p class="drama">
JULIA.<br>
You, minion, are too saucy.
</p>

<p class="drama">
LUCETTA.<br>
Nay, now you are too flat<br>
And mar the concord with too harsh a descant.<br>
There wanteth but a mean to fill your song.
</p>

<p class="drama">
JULIA.<br>
The mean is drowned with your unruly bass.
</p>

<p class="drama">
LUCETTA.<br>
Indeed, I bid the base for Proteus.
</p>

<p class="drama">
JULIA.<br>
This babble shall not henceforth trouble me.<br>
Here is a coil with protestation! [<i>Tears the letter</i>.]<br>
Go, get you gone, and let the papers lie.<br>
You would be fingering them to anger me.
</p>

<p class="drama">
LUCETTA.<br>
She makes it strange, but she would be best pleased<br>
To be so angered with another letter.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
JULIA.<br>
Nay, would I were so angered with the same!<br>
O hateful hands, to tear such loving words!<br>
Injurious wasps, to feed on such sweet honey<br>
And kill the bees that yield it with your stings!<br>
I’ll kiss each several paper for amends.<br>
Look, here is writ <i>kind Julia</i>. Unkind Julia!<br>
As in revenge of thy ingratitude,<br>
I throw thy name against the bruising stones,<br>
Trampling contemptuously on thy disdain.<br>
And here is writ <i>love-wounded Proteus</i>.<br>
Poor wounded name, my bosom as a bed<br>
Shall lodge thee till thy wound be throughly healed;<br>
And thus I search it with a sovereign kiss.<br>
But twice or thrice was <i>Proteus</i> written down.<br>
Be calm, good wind, blow not a word away<br>
Till I have found each letter in the letter<br>
Except mine own name. That some whirlwind bear<br>
Unto a ragged, fearful, hanging rock,<br>
And throw it thence into the raging sea.<br>
Lo, here in one line is his name twice writ:<br>
<i>Poor forlorn Proteus, passionate Proteus,<br>
To the sweet Julia.</i> That I’ll tear away;<br>
And yet I will not, sith so prettily<br>
He couples it to his complaining names.<br>
Thus will I fold them one upon another.<br>
Now kiss, embrace, contend, do what you will.
</p>

<p class="scenedesc">
Enter <span class="charname">Lucetta</span>.
</p>

<p class="drama">
LUCETTA.<br>
Madam, dinner is ready, and your father stays.
</p>

<p class="drama">
JULIA.<br>
Well, let us go.
</p>

<p class="drama">
LUCETTA.<br>
What, shall these papers lie like tell-tales here?
</p>

<p class="drama">
JULIA.<br>
If you respect them, best to take them up.
</p>

<p class="drama">
LUCETTA.<br>
Nay, I was taken up for laying them down.<br>
Yet here they shall not lie, for catching cold.
</p>

<p class="right">[<i>Picks up pieces of the letter.</i>]</p>

<p class="drama">
JULIA.<br>
I see you have a month’s mind to them.
</p>

<p class="drama">
LUCETTA.<br>
Ay, madam, you may say what sights you see;<br>
I see things too, although you judge I wink.
</p>

<p class="drama">
JULIA.<br>
Come, come, will’t please you go?
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneI_37.3"></a><b>SCENE III. The same. A room in Antonio’s house</b></h3>

<p class="scenedesc">
Enter <span class="charname">Antonio</span> and
<span class="charname">Pantino</span>.
</p>

<p class="drama">
ANTONIO.<br>
Tell me, Pantino, what sad talk was that<br>
Wherewith my brother held you in the cloister?
</p>

<p class="drama">
PANTINO.<br>
’Twas of his nephew Proteus, your son.
</p>

<p class="drama">
ANTONIO.<br>
Why, what of him?
</p>

<p class="drama">
PANTINO.<br>
He wondered that your lordship<br>
Would suffer him to spend his youth at home<br>
While other men, of slender reputation,<br>
Put forth their sons to seek preferment out:<br>
Some to the wars to try their fortune there;<br>
Some to discover islands far away;<br>
Some to the studious universities.<br>
For any or for all these exercises<br>
He said that Proteus your son was meet,<br>
And did request me to importune you<br>
To let him spend his time no more at home,<br>
Which would be great impeachment to his age<br>
In having known no travel in his youth.
</p>

<p class="drama">
ANTONIO.<br>
Nor need’st thou much importune me to that<br>
Whereon this month I have been hammering.<br>
I have considered well his loss of time,<br>
And how he cannot be a perfect man,<br>
Not being tried and tutored in the world.<br>
Experience is by industry achieved<br>
And perfected by the swift course of time.<br>
Then tell me whither were I best to send him?
</p>

<p class="drama">
PANTINO.<br>
I think your lordship is not ignorant<br>
How his companion, youthful Valentine,<br>
Attends the Emperor in his royal court.
</p>

<p class="drama">
ANTONIO.<br>
I know it well.
</p>

<p class="drama">
PANTINO.<br>
’Twere good, I think, your lordship sent him thither.<br>
There shall he practise tilts and tournaments,<br>
Hear sweet discourse, converse with noblemen,<br>
And be in eye of every exercise<br>
Worthy his youth and nobleness of birth.
</p>

<p class="drama">
ANTONIO.<br>
I like thy counsel; well hast thou advised,<br>
And that thou mayst perceive how well I like it,<br>
The execution of it shall make known.<br>
Even with the speediest expedition<br>
I will dispatch him to the Emperor’s court.
</p>

<p class="drama">
PANTINO.<br>
Tomorrow, may it please you, Don Alphonso<br>
With other gentlemen of good esteem<br>
Are journeying to salute the Emperor<br>
And to commend their service to his will.
</p>

<p class="drama">
ANTONIO.<br>
Good company. With them shall Proteus go.
</p>

<p class="scenedesc">
Enter <span class="charname">Proteus</span> reading a letter.
</p>

<p class="drama">
And in good time! Now will we break with him.
</p>

<p class="drama">
PROTEUS.<br>
Sweet love, sweet lines, sweet life!<br>
Here is her hand, the agent of her heart;<br>
Here is her oath for love, her honour’s pawn.<br>
O, that our fathers would applaud our loves<br>
To seal our happiness with their consents.<br>
O heavenly Julia!
</p>

<p class="drama">
ANTONIO.<br>
How now? What letter are you reading there?
</p>

<p class="drama">
PROTEUS.<br>
May’t please your lordship, ’tis a word or two<br>
Of commendations sent from Valentine,<br>
Delivered by a friend that came from him.
</p>

<p class="drama">
ANTONIO.<br>
Lend me the letter. Let me see what news.
</p>

<p class="drama">
PROTEUS.<br>
There is no news, my lord, but that he writes<br>
How happily he lives, how well beloved<br>
And daily graced by the Emperor,<br>
Wishing me with him, partner of his fortune.
</p>

<p class="drama">
ANTONIO.<br>
And how stand you affected to his wish?
</p>

<p class="drama">
PROTEUS.<br>
As one relying on your lordship’s will,<br>
And not depending on his friendly wish.
</p>

<p class="drama">
ANTONIO.<br>
My will is something sorted with his wish.<br>
Muse not that I thus suddenly proceed,<br>
For what I will, I will, and there an end.<br>
I am resolved that thou shalt spend some time<br>
With Valentinus in the Emperor’s court.<br>
What maintenance he from his friends receives,<br>
Like exhibition thou shalt have from me.<br>
Tomorrow be in readiness to go.<br>
Excuse it not, for I am peremptory.
</p>

<p class="drama">
PROTEUS.<br>
My lord, I cannot be so soon provided;<br>
Please you deliberate a day or two.
</p>

<p class="drama">
ANTONIO.<br>
Look what thou want’st shall be sent after thee.<br>
No more of stay. Tomorrow thou must go.<br>
Come on, Pantino, you shall be employed<br>
To hasten on his expedition.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Antonio</span> and
<span class="charname">Pantino</span>.</i>]
</p>

<p class="drama">
PROTEUS.<br>
Thus have I shunned the fire for fear of burning<br>
And drenched me in the sea, where I am drowned.<br>
I feared to show my father Julia’s letter<br>
Lest he should take exceptions to my love,<br>
And with the vantage of mine own excuse<br>
Hath he excepted most against my love.<br>
O, how this spring of love resembleth<br>
The uncertain glory of an April day,<br>
Which now shows all the beauty of the sun,<br>
And by an by a cloud takes all away.
</p>

<p class="scenedesc">
Enter <span class="charname">Pantino</span>.
</p>

<p class="drama">
PANTINO.<br>
Sir Proteus, your father calls for you.<br>
He is in haste. Therefore, I pray you, go.
</p>

<p class="drama">
PROTEUS.<br>
Why, this it is: my heart accords thereto,<br>
And yet a thousand times it answers “No”.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

