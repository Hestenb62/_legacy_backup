<h2> <a id="sceneII_12.1"></a><b>ACT II</b></h2>

<h3> <b>SCENE I. Before Orleans.</b></h3>

<p class="scenedesc">Enter a <span class="charname">Sergeant</span> of a band,
with two <span class="charname">Sentinels</span>.</p>

<p class="drama">
SERGEANT.<br>
Sirs, take your places and be vigilant.<br>
If any noise or soldier you perceive<br>
Near to the walls, by some apparent sign<br>
Let us have knowledge at the court of guard.
</p>

<p class="drama">
FIRST SENTINEL.<br>
Sergeant, you shall.
</p>

<p class="right">[<i>Exit <span class="charname">Sergeant</span>.</i>]</p>

<p class="drama">
Thus are poor servitors,<br>
When others sleep upon their quiet beds,<br>
Constrain’d to watch in darkness, rain, and cold.
</p>

<p class="scenedesc">Enter <span class="charname">Talbot, Bedford,
Burgundy</span>, and forces, with scaling-ladders.
</p>

<p class="drama">
TALBOT.<br>
Lord Regent, and redoubted Burgundy,<br>
By whose approach the regions of Artois,<br>
Walloon and Picardy are friends to us,<br>
This happy night the Frenchmen are secure,<br>
Having all day caroused and banqueted.<br>
Embrace we then this opportunity,<br>
As fitting best to quittance their deceit<br>
Contriv’d by art and baleful sorcery.
</p>

<p class="drama">
BEDFORD.<br>
Coward of France, how much he wrongs his fame,<br>
Despairing of his own arm’s fortitude,<br>
To join with witches and the help of hell!
</p>

<p class="drama">
BURGUNDY.<br>
Traitors have never other company.<br>
But what’s that Pucelle whom they term so pure?
</p>

<p class="drama">
TALBOT.<br>
A maid, they say.
</p>

<p class="drama">
BEDFORD.<br>
A maid! And be so martial!
</p>

<p class="drama">
BURGUNDY.<br>
Pray God she prove not masculine ere long,<br>
If underneath the standard of the French<br>
She carry armour as she hath begun.
</p>

<p class="drama">
TALBOT.<br>
Well, let them practice and converse with spirits.<br>
God is our fortress, in whose conquering name<br>
Let us resolve to scale their flinty bulwarks.
</p>

<p class="drama">
BEDFORD.<br>
Ascend, brave Talbot; we will follow thee.
</p>

<p class="drama">
TALBOT.<br>
Not all together. Better far, I guess,<br>
That we do make our entrance several ways,<br>
That if it chance the one of us do fail,<br>
The other yet may rise against their force.
</p>

<p class="drama">
BEDFORD.<br>
Agreed. I’ll to yond corner.
</p>

<p class="drama">
BURGUNDY.<br>
And I to this.
</p>

<p class="drama">
TALBOT.<br>
And here will Talbot mount, or make his grave.<br>
Now, Salisbury, for thee, and for the right<br>
Of English Henry, shall this night appear<br>
How much in duty I am bound to both.
</p>

<p class="drama">
SENTINEL.<br>
Arm! Arm! The enemy doth make assault!
</p>

<p class="right">[<i>Cry: “St George,” “A Talbot!”</i>]</p>

<p class="scenedesc">The French leap over the walls in their shirts. Enter
several ways the  <span class="charname">Bastard of Orleans, Alençon</span>
and <span class="charname">Reignier</span>, half ready and half unready.</p>

<p class="drama">
ALENÇON.<br>
How now, my lords? What, all unready so?
</p>

<p class="drama">
BASTARD.<br>
Unready! Ay, and glad we ’scap’d so well.
</p>

<p class="drama">
REIGNIER.<br>
’Twas time, I trow, to wake and leave our beds,<br>
Hearing alarums at our chamber-doors.
</p>

<p class="drama">
ALENÇON.<br>
Of all exploits since first I follow’d arms<br>
Ne’er heard I of a warlike enterprise<br>
More venturous or desperate than this.
</p>

<p class="drama">
BASTARD.<br>
I think this Talbot be a fiend of hell.
</p>

<p class="drama">
REIGNIER.<br>
If not of hell, the heavens, sure, favour him.
</p>

<p class="drama">
ALENÇON.<br>
Here cometh Charles. I marvel how he sped.
</p>

<p class="scenedesc">Enter <span class="charname">Charles</span> and
<span class="charname">La Pucelle</span>.</p>

<p class="drama">
BASTARD.<br>
Tut, holy Joan was his defensive guard.
</p>

<p class="drama">
CHARLES.<br>
Is this thy cunning, thou deceitful dame?<br>
Didst thou at first, to flatter us withal,<br>
Make us partakers of a little gain,<br>
That now our loss might be ten times so much?
</p>

<p class="drama">
PUCELLE.<br>
Wherefore is Charles impatient with his friend?<br>
At all times will you have my power alike?<br>
Sleeping or waking, must I still prevail,<br>
Or will you blame and lay the fault on me?<br>
Improvident soldiers, had your watch been good,<br>
This sudden mischief never could have fall’n.
</p>

<p class="drama">
CHARLES.<br>
Duke of Alençon, this was your default,<br>
That, being captain of the watch tonight,<br>
Did look no better to that weighty charge.
</p>

<p class="drama">
ALENÇON.<br>
Had all your quarters been as safely kept<br>
As that whereof I had the government,<br>
We had not been thus shamefully surprised.
</p>

<p class="drama">
BASTARD.<br>
Mine was secure.
</p>

<p class="drama">
REIGNIER.<br>
And so was mine, my lord.
</p>

<p class="drama">
CHARLES.<br>
And for myself, most part of all this night,<br>
Within her quarter and mine own precinct<br>
I was employ’d in passing to and fro<br>
About relieving of the sentinels.<br>
Then how or which way should they first break in?
</p>

<p class="drama">
PUCELLE.<br>
Question, my lords, no further of the case,<br>
How or which way; ’tis sure they found some place<br>
But weakly guarded, where the breach was made.<br>
And now there rests no other shift but this:<br>
To gather our soldiers, scattered and dispersed,<br>
And lay new platforms to endamage them.
</p>

<p class="scenedesc">Alarum. Enter an  <span class="charname">English
Soldier</span>, crying “A Talbot! A Talbot!” They fly, leaving their clothes
behind.</p>

<p class="drama">
SOLDIER.<br>
I’ll be so bold to take what they have left.<br>
The cry of “Talbot” serves me for a sword;<br>
For I have loaden me with many spoils,<br>
Using no other weapon but his name.
</p>

<p class="right">[<i>Exit.</i>]</p>

<h3> <a id="sceneII_12.2"></a><b>SCENE II. Orleans. Within the town.</b></h3>

<p class="scenedesc">Enter <span class="charname">Talbot, Bedford, Burgundy, a
Captain</span> and others.</p>

<p class="drama">
BEDFORD.<br>
The day begins to break, and night is fled,<br>
Whose pitchy mantle over-veil’d the earth.<br>
Here sound retreat and cease our hot pursuit.
</p>

<p class="right">[<i>Retreat sounded.</i>]</p>

<p class="drama">
TALBOT.<br>
Bring forth the body of old Salisbury,<br>
And here advance it in the market-place,<br>
The middle centre of this cursed town.
</p>

<p class="scenedesc">Dead March. Enter with the body of <span class="charname">Salisbury</span>.</p>

<p class="drama">
Now have I paid my vow unto his soul;<br>
For every drop of blood was drawn from him<br>
There hath at least five Frenchmen died tonight.<br>
And that hereafter ages may behold<br>
What ruin happen’d in revenge of him,<br>
Within their chiefest temple I’ll erect<br>
A tomb, wherein his corpse shall be interr’d;<br>
Upon the which, that everyone may read,<br>
Shall be engraved the sack of Orleans,<br>
The treacherous manner of his mournful death<br>
And what a terror he had been to France.
</p>

<p class="right">[<i>Exit Funeral.</i>]</p>

<p class="drama">
But, lords, in all our bloody massacre,<br>
I muse we met not with the Dauphin’s grace,<br>
His new-come champion, virtuous Joan of Arc,<br>
Nor any of his false confederates.
</p>

<p class="drama">
BEDFORD.<br>
’Tis thought, Lord Talbot, when the fight began,<br>
Rous’d on the sudden from their drowsy beds,<br>
They did amongst the troops of armed men<br>
Leap o’er the walls for refuge in the field.
</p>

<p class="drama">
BURGUNDY.<br>
Myself, as far as I could well discern<br>
For smoke and dusky vapors of the night,<br>
Am sure I scared the Dauphin and his trull,<br>
When arm in arm they both came swiftly running,<br>
Like to a pair of loving turtle-doves<br>
That could not live asunder day or night.<br>
After that things are set in order here,<br>
We’ll follow them with all the power we have.
</p>

<p class="scenedesc">Enter a <span class="charname">Messenger</span>.</p>

<p class="drama">
MESSENGER.<br>
All hail, my lords! Which of this princely train<br>
Call ye the warlike Talbot, for his acts<br>
So much applauded through the realm of France?
</p>

<p class="drama">
TALBOT.<br>
Here is the Talbot. Who would speak with him?
</p>

<p class="drama">
MESSENGER.<br>
The virtuous lady, Countess of Auvergne,<br>
With modesty admiring thy renown,<br>
By me entreats, great lord, thou wouldst vouchsafe<br>
To visit her poor castle where she lies,<br>
That she may boast she hath beheld the man<br>
Whose glory fills the world with loud report.
</p>

<p class="drama">
BURGUNDY.<br>
Is it even so? Nay, then I see our wars<br>
Will turn unto a peaceful comic sport,<br>
When ladies crave to be encounter’d with.<br>
You may not, my lord, despise her gentle suit.
</p>

<p class="drama">
TALBOT.<br>
Ne’er trust me then; for when a world of men<br>
Could not prevail with all their oratory,<br>
Yet hath a woman’s kindness over-ruled.<br>
And therefore tell her I return great thanks,<br>
And in submission will attend on her.<br>
Will not your honours bear me company?
</p>

<p class="drama">
BEDFORD.<br>
No, truly, it is more than manners will;<br>
And I have heard it said, unbidden guests<br>
Are often welcomest when they are gone.
</p>

<p class="drama">
TALBOT.<br>
Well then, alone, since there’s no remedy,<br>
I mean to prove this lady’s courtesy.<br>
Come hither, Captain. [<i>Whispers</i>.] You perceive my mind?
</p>

<p class="drama">
CAPTAIN.<br>
I do, my lord, and mean accordingly.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneII_12.3"></a><b>SCENE III. Auvergne. The Countess’s castle.</b></h3>

<p class="scenedesc">Enter the <span class="charname">Countess</span> and her
<span class="charname">Porter</span>.</p>

<p class="drama">
COUNTESS.<br>
Porter, remember what I gave in charge;<br>
And when you have done so, bring the keys to me.
</p>

<p class="drama">
PORTER.<br>
Madam, I will.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
COUNTESS.<br>
The plot is laid. If all things fall out right,<br>
I shall as famous be by this exploit<br>
As Scythian Tomyris by Cyrus’ death.<br>
Great is the rumour of this dreadful knight,<br>
And his achievements of no less account.<br>
Fain would mine eyes be witness with mine ears,<br>
To give their censure of these rare reports.
</p>

<p class="scenedesc">Enter <span class="charname">Messenger</span> and
<span class="charname">Talbot</span>.</p>

<p class="drama">
MESSENGER.<br>
Madam, according as your ladyship desired,<br>
By message craved, so is Lord Talbot come.
</p>

<p class="drama">
COUNTESS.<br>
And he is welcome. What, is this the man?
</p>

<p class="drama">
MESSENGER.<br>
Madam, it is.
</p>

<p class="drama">
COUNTESS.<br>
Is this the scourge of France?<br>
Is this the Talbot, so much fear’d abroad<br>
That with his name the mothers still their babes?<br>
I see report is fabulous and false.<br>
I thought I should have seen some Hercules,<br>
A second Hector, for his grim aspect,<br>
And large proportion of his strong-knit limbs.<br>
Alas, this is a child, a silly dwarf!<br>
It cannot be this weak and writhled shrimp<br>
Should strike such terror to his enemies.
</p>

<p class="drama">
TALBOT.<br>
Madam, I have been bold to trouble you;<br>
But since your ladyship is not at leisure,<br>
I’ll sort some other time to visit you.
</p>

<p class="drama">
COUNTESS.<br>
What means he now? Go ask him whither he goes.
</p>

<p class="drama">
MESSENGER.<br>
Stay, my Lord Talbot, for my lady craves<br>
To know the cause of your abrupt departure.
</p>

<p class="drama">
TALBOT.<br>
Marry, for that she’s in a wrong belief,<br>
I go to certify her Talbot’s here.
</p>

<p class="scenedesc">Enter <span class="charname">Porter</span> with keys.</p>

<p class="drama">
COUNTESS.<br>
If thou be he, then art thou prisoner.
</p>

<p class="drama">
TALBOT.<br>
Prisoner! To whom?
</p>

<p class="drama">
COUNTESS.<br>
To me, blood-thirsty lord;<br>
And for that cause I train’d thee to my house.<br>
Long time thy shadow hath been thrall to me,<br>
For in my gallery thy picture hangs.<br>
But now the substance shall endure the like,<br>
And I will chain these legs and arms of thine,<br>
That hast by tyranny these many years<br>
Wasted our country, slain our citizens,<br>
And sent our sons and husbands captivate.
</p>

<p class="drama">
TALBOT.<br>
Ha, ha, ha!
</p>

<p class="drama">
COUNTESS.<br>
Laughest thou, wretch? Thy mirth shall turn to moan.
</p>

<p class="drama">
TALBOT.<br>
I laugh to see your ladyship so fond<br>
To think that you have aught but Talbot’s shadow<br>
Whereon to practice your severity.
</p>

<p class="drama">
COUNTESS.<br>
Why, art not thou the man?
</p>

<p class="drama">
TALBOT.<br>
I am indeed.
</p>

<p class="drama">
COUNTESS.<br>
Then have I substance too.
</p>

<p class="drama">
TALBOT.<br>
No, no, I am but shadow of myself.<br>
You are deceived, my substance is not here;<br>
For what you see is but the smallest part<br>
And least proportion of humanity.<br>
I tell you, madam, were the whole frame here,<br>
It is of such a spacious lofty pitch<br>
Your roof were not sufficient to contain ’t.
</p>

<p class="drama">
COUNTESS.<br>
This is a riddling merchant for the nonce;<br>
He will be here, and yet he is not here.<br>
How can these contrarieties agree?
</p>

<p class="drama">
TALBOT.<br>
That will I show you presently.
</p>

<p class="scenedesc">Winds his horn. Drums strike up; a peal of ordnance. Enter
<span class="charname">Soldiers</span>.</p>

<p class="drama">
How say you, madam? Are you now persuaded<br>
That Talbot is but shadow of himself?<br>
These are his substance, sinews, arms and strength,<br>
With which he yoketh your rebellious necks,<br>
Razeth your cities and subverts your towns,<br>
And in a moment makes them desolate.
</p>

<p class="drama">
COUNTESS.<br>
Victorious Talbot, pardon my abuse.<br>
I find thou art no less than fame hath bruited,<br>
And more than may be gather’d by thy shape.<br>
Let my presumption not provoke thy wrath,<br>
For I am sorry that with reverence<br>
I did not entertain thee as thou art.
</p>

<p class="drama">
TALBOT.<br>
Be not dismay’d, fair lady, nor misconster<br>
The mind of Talbot, as you did mistake<br>
The outward composition of his body.<br>
What you have done hath not offended me;<br>
Nor other satisfaction do I crave<br>
But only, with your patience, that we may<br>
Taste of your wine and see what cates you have,<br>
For soldiers’ stomachs always serve them well.
</p>

<p class="drama">
COUNTESS.<br>
With all my heart, and think me honoured<br>
To feast so great a warrior in my house.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneII_12.4"></a><b>SCENE IV. London. The Temple Garden.</b></h3>

<p class="scenedesc">Enter the Earls of <span class="charname">Somerset,
Suffolk</span>, and <span class="charname">Warwick; Richard Plantagenet,
Vernon</span> and another <span class="charname">Lawyer</span>.</p>

<p class="drama">
PLANTAGENET.<br>
Great lords and gentlemen, what means this silence?<br>
Dare no man answer in a case of truth?
</p>

<p class="drama">
SUFFOLK.<br>
Within the Temple Hall we were too loud;<br>
The garden here is more convenient.
</p>

<p class="drama">
PLANTAGENET.<br>
Then say at once if I maintain’d the truth;<br>
Or else was wrangling Somerset in th’ error?
</p>

<p class="drama">
SUFFOLK.<br>
Faith, I have been a truant in the law<br>
And never yet could frame my will to it;<br>
And therefore frame the law unto my will.
</p>

<p class="drama">
SOMERSET.<br>
Judge you, my Lord of Warwick, then, between us.
</p>

<p class="drama">
WARWICK.<br>
Between two hawks, which flies the higher pitch;<br>
Between two dogs, which hath the deeper mouth;<br>
Between two blades, which bears the better temper;<br>
Between two horses, which doth bear him best;<br>
Between two girls, which hath the merriest eye;<br>
I have perhaps some shallow spirit of judgement;<br>
But in these nice sharp quillets of the law,<br>
Good faith, I am no wiser than a daw.
</p>

<p class="drama">
PLANTAGENET.<br>
Tut, tut, here is a mannerly forbearance!<br>
The truth appears so naked on my side<br>
That any purblind eye may find it out.
</p>

<p class="drama">
SOMERSET.<br>
And on my side it is so well apparell’d,<br>
So clear, so shining and so evident,<br>
That it will glimmer through a blind man’s eye.
</p>

<p class="drama">
PLANTAGENET.<br>
Since you are tongue-tied and so loath to speak,<br>
In dumb significants proclaim your thoughts:<br>
Let him that is a true-born gentleman<br>
And stands upon the honour of his birth,<br>
If he suppose that I have pleaded truth,<br>
From off this brier pluck a white rose with me.
</p>

<p class="drama">
SOMERSET.<br>
Let him that is no coward nor no flatterer,<br>
But dare maintain the party of the truth,<br>
Pluck a red rose from off this thorn with me.
</p>

<p class="drama">
WARWICK.<br>
I love no colours, and without all colour<br>
Of base insinuating flattery<br>
I pluck this white rose with Plantagenet.
</p>

<p class="drama">
SUFFOLK.<br>
I pluck this red rose with young Somerset,<br>
And say withal I think he held the right.
</p>

<p class="drama">
VERNON.<br>
Stay, lords and gentlemen, and pluck no more<br>
Till you conclude that he upon whose side<br>
The fewest roses are cropp’d from the tree<br>
Shall yield the other in the right opinion.
</p>

<p class="drama">
SOMERSET.<br>
Good Master Vernon, it is well objected:<br>
If I have fewest, I subscribe in silence.
</p>

<p class="drama">
PLANTAGENET.<br>
And I.
</p>

<p class="drama">
VERNON.<br>
Then for the truth and plainness of the case,<br>
I pluck this pale and maiden blossom here,<br>
Giving my verdict on the white rose side.
</p>

<p class="drama">
SOMERSET.<br>
Prick not your finger as you pluck it off,<br>
Lest, bleeding, you do paint the white rose red,<br>
And fall on my side so against your will.
</p>

<p class="drama">
VERNON.<br>
If I, my lord, for my opinion bleed,<br>
Opinion shall be surgeon to my hurt<br>
And keep me on the side where still I am.
</p>

<p class="drama">
SOMERSET.<br>
Well, well, come on, who else?
</p>

<p class="drama">
LAWYER.<br>
Unless my study and my books be false,
</p>

<p class="right">[<i>To <span class="charname">Somerset</span>.</i>]</p>

<p class="drama">
The argument you held was wrong in law;<br>
In sign whereof I pluck a white rose too.
</p>

<p class="drama">
PLANTAGENET.<br>
Now, Somerset, where is your argument?
</p>

<p class="drama">
SOMERSET.<br>
Here in my scabbard, meditating that<br>
Shall dye your white rose in a bloody red.
</p>

<p class="drama">
PLANTAGENET.<br>
Meantime your cheeks do counterfeit our roses;<br>
For pale they look with fear, as witnessing<br>
The truth on our side.
</p>

<p class="drama">
SOMERSET.<br>
No, Plantagenet,<br>
’Tis not for fear but anger that thy cheeks<br>
Blush for pure shame to counterfeit our roses,<br>
And yet thy tongue will not confess thy error.
</p>

<p class="drama">
PLANTAGENET.<br>
Hath not thy rose a canker, Somerset?
</p>

<p class="drama">
SOMERSET.<br>
Hath not thy rose a thorn, Plantagenet?
</p>

<p class="drama">
PLANTAGENET.<br>
Ay, sharp and piercing, to maintain his truth;<br>
Whiles thy consuming canker eats his falsehood.
</p>

<p class="drama">
SOMERSET.<br>
Well, I’ll find friends to wear my bleeding roses,<br>
That shall maintain what I have said is true,<br>
Where false Plantagenet dare not be seen.
</p>

<p class="drama">
PLANTAGENET.<br>
Now, by this maiden blossom in my hand,<br>
I scorn thee and thy fashion, peevish boy.
</p>

<p class="drama">
SUFFOLK.<br>
Turn not thy scorns this way, Plantagenet.
</p>

<p class="drama">
PLANTAGENET.<br>
Proud Pole, I will, and scorn both him and thee.
</p>

<p class="drama">
SUFFOLK.<br>
I’ll turn my part thereof into thy throat.
</p>

<p class="drama">
SOMERSET.<br>
Away, away, good William de la Pole!<br>
We grace the yeoman by conversing with him.
</p>

<p class="drama">
WARWICK.<br>
Now, by God’s will, thou wrong’st him, Somerset;<br>
His grandfather was Lionel Duke of Clarence,<br>
Third son to the third Edward King of England.<br>
Spring crestless yeomen from so deep a root?
</p>

<p class="drama">
PLANTAGENET.<br>
He bears him on the place’s privilege,<br>
Or durst not for his craven heart, say thus.
</p>

<p class="drama">
SOMERSET.<br>
By Him that made me, I’ll maintain my words<br>
On any plot of ground in Christendom.<br>
Was not thy father, Richard Earl of Cambridge,<br>
For treason executed in our late king’s days?<br>
And, by his treason, stand’st not thou attainted,<br>
Corrupted, and exempt from ancient gentry?<br>
His trespass yet lives guilty in thy blood;<br>
And, till thou be restored, thou art a yeoman.
</p>

<p class="drama">
PLANTAGENET.<br>
My father was attached, not attainted,<br>
Condemn’d to die for treason, but no traitor;<br>
And that I’ll prove on better men than Somerset,<br>
Were growing time once ripen’d to my will.<br>
For your partaker Pole and you yourself,<br>
I’ll note you in my book of memory,<br>
To scourge you for this apprehension.<br>
Look to it well, and say you are well warn’d.
</p>

<p class="drama">
SOMERSET.<br>
Ah, thou shalt find us ready for thee still;<br>
And know us by these colours for thy foes,<br>
For these my friends in spite of thee shall wear.
</p>

<p class="drama">
PLANTAGENET.<br>
And, by my soul, this pale and angry rose,<br>
As cognizance of my blood-drinking hate,<br>
Will I for ever and my faction wear,<br>
Until it wither with me to my grave,<br>
Or flourish to the height of my degree.
</p>

<p class="drama">
SUFFOLK.<br>
Go forward, and be chok’d with thy ambition!<br>
And so farewell until I meet thee next.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
SOMERSET.<br>
Have with thee, Pole. Farewell, ambitious Richard.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
PLANTAGENET.<br>
How I am braved and must perforce endure it!
</p>

<p class="drama">
WARWICK.<br>
This blot that they object against your house<br>
Shall be wiped out in the next parliament<br>
Call’d for the truce of Winchester and Gloucester;<br>
And if thou be not then created York,<br>
I will not live to be accounted Warwick.<br>
Meantime, in signal of my love to thee,<br>
Against proud Somerset and William Pole,<br>
Will I upon thy party wear this rose.<br>
And here I prophesy: this brawl today,<br>
Grown to this faction in the Temple Garden,<br>
Shall send between the Red Rose and the White<br>
A thousand souls to death and deadly night.
</p>

<p class="drama">
PLANTAGENET.<br>
Good Master Vernon, I am bound to you,<br>
That you on my behalf would pluck a flower.
</p>

<p class="drama">
VERNON.<br>
In your behalf still will I wear the same.
</p>

<p class="drama">
LAWYER.<br>
And so will I.
</p>

<p class="drama">
PLANTAGENET.<br>
Thanks, gentlemen.<br>
Come, let us four to dinner. I dare say<br>
This quarrel will drink blood another day.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneII_12.5"></a><b>SCENE V. The Tower of London.</b></h3>

<p class="scenedesc">Enter <span class="charname">Mortimer</span>, brought in a chair, and 
<span class="charname">Jailers</span>.</p>

<p class="drama">
MORTIMER.<br>
Kind keepers of my weak decaying age,<br>
Let dying Mortimer here rest himself.<br>
Even like a man new haled from the rack,<br>
So fare my limbs with long imprisonment;<br>
And these gray locks, the pursuivants of death,<br>
Nestor-like aged in an age of care,<br>
Argue the end of Edmund Mortimer.<br>
These eyes, like lamps whose wasting oil is spent,<br>
Wax dim, as drawing to their exigent;<br>
Weak shoulders, overborne with burdening grief,<br>
And pithless arms, like to a wither’d vine<br>
That droops his sapless branches to the ground.<br>
Yet are these feet, whose strengthless stay is numb,<br>
Unable to support this lump of clay,<br>
Swift-winged with desire to get a grave,<br>
As witting I no other comfort have.<br>
But tell me, keeper, will my nephew come?
</p>

<p class="drama">
FIRST JAILER.<br>
Richard Plantagenet, my lord, will come.<br>
We sent unto the Temple, unto his chamber,<br>
And answer was return’d that he will come.
</p>

<p class="drama">
MORTIMER.<br>
Enough. My soul shall then be satisfied.<br>
Poor gentleman, his wrong doth equal mine.<br>
Since Henry Monmouth first began to reign,<br>
Before whose glory I was great in arms,<br>
This loathsome sequestration have I had;<br>
And even since then hath Richard been obscured,<br>
Deprived of honour and inheritance.<br>
But now the arbitrator of despairs,<br>
Just Death, kind umpire of men’s miseries,<br>
With sweet enlargement doth dismiss me hence.<br>
I would his troubles likewise were expired,<br>
That so he might recover what was lost.
</p>

<p class="scenedesc">Enter <span class="charname">Richard Plantagenet</span>.</p>

<p class="drama">
FIRST JAILER.<br>
My lord, your loving nephew now is come.
</p>

<p class="drama">
MORTIMER.<br>
Richard Plantagenet, my friend, is he come?
</p>

<p class="drama">
PLANTAGENET.<br>
Ay, noble uncle, thus ignobly used,<br>
Your nephew, late despised Richard, comes.
</p>

<p class="drama">
MORTIMER.<br>
Direct mine arms I may embrace his neck<br>
And in his bosom spend my latter gasp.<br>
O, tell me when my lips do touch his cheeks,<br>
That I may kindly give one fainting kiss.<br>
And now declare, sweet stem from York’s great stock,<br>
Why didst thou say of late thou wert despised?
</p>

<p class="drama">
PLANTAGENET.<br>
First, lean thine aged back against mine arm,<br>
And, in that ease, I’ll tell thee my disease.<br>
This day, in argument upon a case,<br>
Some words there grew ’twixt Somerset and me;<br>
Among which terms he used his lavish tongue<br>
And did upbraid me with my father’s death;<br>
Which obloquy set bars before my tongue,<br>
Else with the like I had requited him.<br>
Therefore, good uncle, for my father’s sake,<br>
In honour of a true Plantagenet,<br>
And for alliance’ sake, declare the cause<br>
My father, Earl of Cambridge, lost his head.
</p>

<p class="drama">
MORTIMER.<br>
That cause, fair nephew, that imprison’d me<br>
And hath detain’d me all my flowering youth<br>
Within a loathsome dungeon, there to pine,<br>
Was cursed instrument of his decease.
</p>

<p class="drama">
PLANTAGENET.<br>
Discover more at large what cause that was,<br>
For I am ignorant and cannot guess.
</p>

<p class="drama">
MORTIMER.<br>
I will, if that my fading breath permit<br>
And death approach not ere my tale be done.<br>
Henry the Fourth, grandfather to this king,<br>
Deposed his nephew Richard, Edward’s son,<br>
The first-begotten and the lawful heir<br>
Of Edward king, the third of that descent;<br>
During whose reign the Percies of the north,<br>
Finding his usurpation most unjust,<br>
Endeavour’d my advancement to the throne.<br>
The reason moved these warlike lords to this<br>
Was, for that—young King Richard thus removed,<br>
Leaving no heir begotten of his body—<br>
I was the next by birth and parentage;<br>
For by my mother I derived am<br>
From Lionel Duke of Clarence, third son<br>
To King Edward the Third; whereas he<br>
From John of Gaunt doth bring his pedigree,<br>
Being but fourth of that heroic line.<br>
But mark: as in this haughty great attempt<br>
They labored to plant the rightful heir,<br>
I lost my liberty and they their lives.<br>
Long after this, when Henry the Fifth,<br>
Succeeding his father Bolingbroke, did reign,<br>
Thy father, Earl of Cambridge then, derived<br>
From famous Edmund Langley, Duke of York,<br>
Marrying my sister that thy mother was,<br>
Again, in pity of my hard distress.<br>
Levied an army, weening to redeem<br>
And have install’d me in the diadem.<br>
But, as the rest, so fell that noble earl<br>
And was beheaded. Thus the Mortimers,<br>
In whom the title rested, were suppress’d.
</p>

<p class="drama">
PLANTAGENET.<br>
Of which, my lord, your honour is the last.
</p>

<p class="drama">
MORTIMER.<br>
True; and thou seest that I no issue have,<br>
And that my fainting words do warrant death.<br>
Thou art my heir; the rest I wish thee gather.<br>
But yet be wary in thy studious care.
</p>

<p class="drama">
PLANTAGENET.<br>
Thy grave admonishments prevail with me.<br>
But yet methinks, my father’s execution<br>
Was nothing less than bloody tyranny.
</p>

<p class="drama">
MORTIMER.<br>
With silence, nephew, be thou politic;<br>
Strong-fixed is the house of Lancaster,<br>
And like a mountain, not to be removed.<br>
But now thy uncle is removing hence,<br>
As princes do their courts when they are cloy’d<br>
With long continuance in a settled place.
</p>

<p class="drama">
PLANTAGENET.<br>
O uncle, would some part of my young years<br>
Might but redeem the passage of your age!
</p>

<p class="drama">
MORTIMER.<br>
Thou dost then wrong me, as that slaughterer doth<br>
Which giveth many wounds when one will kill.<br>
Mourn not, except thou sorrow for my good;<br>
Only give order for my funeral.<br>
And so farewell, and fair be all thy hopes,<br>
And prosperous be thy life in peace and war!
</p>

<p class="right">[<i>Dies.</i>]</p>

<p class="drama">
PLANTAGENET.<br>
And peace, no war, befall thy parting soul!<br>
In prison hast thou spent a pilgrimage,<br>
And like a hermit overpass’d thy days.<br>
Well, I will lock his counsel in my breast;<br>
And what I do imagine, let that rest.<br>
Keepers, convey him hence; and I myself<br>
Will see his burial better than his life.
</p>

<p class="right">[<i>Exeunt <span class="charname">Jailers</span>, bearing out the body of
<span class="charname">Mortimer</span>.</i>]</p>

<p class="drama">
Here dies the dusky torch of Mortimer,<br>
Choked with ambition of the meaner sort.<br>
And for those wrongs, those bitter injuries,<br>
Which Somerset hath offer’d to my house,<br>
I doubt not but with honour to redress;<br>
And therefore haste I to the Parliament,<br>
Either to be restored to my blood,<br>
Or make mine ill th’ advantage of my good.
</p>

<p class="right">[<i>Exit.</i>]</p>

