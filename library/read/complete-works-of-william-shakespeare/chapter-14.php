<h2> <a id="sceneIII_3.1"></a><b>ACT III</b></h2>

<h3> <b>SCENE I. A plain in Syria.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Ventidius</span> as it were in triumph, with <span class="charname">Silius</span> and other Romans, Officers and Soldiers; the
dead body of <span class="charname">Pacorus</span> borne before him.
</p>

<p class="drama">
VENTIDIUS.<br>
Now, darting Parthia, art thou struck, and now<br>
Pleased Fortune does of Marcus Crassus’ death<br>
Make me revenger. Bear the king’s son’s body<br>
Before our army. Thy Pacorus, Orodes,<br>
Pays this for Marcus Crassus.
</p>

<p class="drama">
SILIUS.<br>
Noble Ventidius,<br>
Whilst yet with Parthian blood thy sword is warm,<br>
The fugitive Parthians follow. Spur through Media,<br>
Mesopotamia, and the shelters whither<br>
The routed fly. So thy grand captain Antony<br>
Shall set thee on triumphant chariots, and<br>
Put garlands on thy head.
</p>

<p class="drama">
VENTIDIUS.<br>
O Silius, Silius,<br>
I have done enough. A lower place, note well,<br>
May make too great an act. For learn this, Silius:<br>
Better to leave undone than by our deed<br>
Acquire too high a fame when him we serve’s away.<br>
Caesar and Antony have ever won<br>
More in their officer, than person. Sossius,<br>
One of my place in Syria, his lieutenant,<br>
For quick accumulation of renown,<br>
Which he achieved by th’ minute, lost his favour.<br>
Who does i’ th’ wars more than his captain can<br>
Becomes his captain’s captain; and ambition,<br>
The soldier’s virtue, rather makes choice of loss<br>
Than gain which darkens him.<br>
I could do more to do Antonius good,<br>
But ’twould offend him, and in his offence<br>
Should my performance perish.
</p>

<p class="drama">
SILIUS.<br>
Thou hast, Ventidius, that<br>
Without the which a soldier and his sword<br>
Grants scarce distinction. Thou wilt write to Antony?
</p>

<p class="drama">
VENTIDIUS.<br>
I’ll humbly signify what in his name,<br>
That magical word of war, we have effected;<br>
How, with his banners, and his well-paid ranks,<br>
The ne’er-yet-beaten horse of Parthia<br>
We have jaded out o’ th’ field.
</p>

<p class="drama">
SILIUS.<br>
Where is he now?
</p>

<p class="drama">
VENTIDIUS.<br>
He purposeth to Athens, whither, with what haste<br>
The weight we must convey with ’s will permit,<br>
We shall appear before him.—On there, pass along!
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneIII_3.2"></a><b>SCENE II. Rome. An Ante-chamber in Caesar’s
house.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Agrippa</span> at one door, <span class="charname">Enobarbus</span> at another.
</p>

<p class="drama">
AGRIPPA.<br>
What, are the brothers parted?
</p>

<p class="drama">
ENOBARBUS.<br>
They have dispatched with Pompey; he is gone.<br>
The other three are sealing. Octavia weeps<br>
To part from Rome. Caesar is sad, and Lepidus,<br>
Since Pompey’s feast, as Menas says, is troubled<br>
With the greensickness.
</p>

<p class="drama">
AGRIPPA.<br>
’Tis a noble Lepidus.
</p>

<p class="drama">
ENOBARBUS.<br>
A very fine one. O, how he loves Caesar!
</p>

<p class="drama">
AGRIPPA.<br>
Nay, but how dearly he adores Mark Antony!
</p>

<p class="drama">
ENOBARBUS.<br>
Caesar? Why he’s the Jupiter of men.
</p>

<p class="drama">
AGRIPPA.<br>
What’s Antony? The god of Jupiter.
</p>

<p class="drama">
ENOBARBUS.<br>
Spake you of Caesar? How, the nonpareil!
</p>

<p class="drama">
AGRIPPA.<br>
O, Antony! O thou Arabian bird!
</p>

<p class="drama">
ENOBARBUS.<br>
Would you praise Caesar, say “Caesar”. Go no further.
</p>

<p class="drama">
AGRIPPA.<br>
Indeed, he plied them both with excellent praises.
</p>

<p class="drama">
ENOBARBUS.<br>
But he loves Caesar best, yet he loves Antony.<br>
Hoo! Hearts, tongues, figures, scribes, bards, poets, cannot<br>
Think, speak, cast, write, sing, number—hoo!—<br>
His love to Antony. But as for Caesar,<br>
Kneel down, kneel down, and wonder.
</p>

<p class="drama">
AGRIPPA.<br>
Both he loves.
</p>

<p class="drama">
ENOBARBUS.<br>
They are his shards, and he their beetle.
</p>

<p class="right">
[<i>Trumpets within.</i>]
</p>

<p class="drama">
So,<br>
This is to horse. Adieu, noble Agrippa.
</p>

<p class="drama">
AGRIPPA.<br>
Good fortune, worthy soldier, and farewell.
</p>

<p class="scenedesc">
Enter <span class="charname">Caesar, Antony, Lepidus</span> and <span class="charname">Octavia</span>.
</p>

<p class="drama">
ANTONY.<br>
No further, sir.
</p>

<p class="drama">
CAESAR.<br>
You take from me a great part of myself.<br>
Use me well in’t. Sister, prove such a wife<br>
As my thoughts make thee, and as my farthest bond<br>
Shall pass on thy approof. Most noble Antony,<br>
Let not the piece of virtue which is set<br>
Betwixt us, as the cement of our love<br>
To keep it builded, be the ram to batter<br>
The fortress of it. For better might we<br>
Have loved without this mean, if on both parts<br>
This be not cherished.
</p>

<p class="drama">
ANTONY.<br>
Make me not offended<br>
In your distrust.
</p>

<p class="drama">
CAESAR.<br>
I have said.
</p>

<p class="drama">
ANTONY.<br>
You shall not find,<br>
Though you be therein curious, the least cause<br>
For what you seem to fear. So the gods keep you,<br>
And make the hearts of Romans serve your ends.<br>
We will here part.
</p>

<p class="drama">
CAESAR.<br>
Farewell, my dearest sister, fare thee well.<br>
The elements be kind to thee, and make<br>
Thy spirits all of comfort! Fare thee well.
</p>

<p class="drama">
OCTAVIA.<br>
My noble brother!
</p>

<p class="drama">
ANTONY.<br>
The April’s in her eyes. It is love’s spring,<br>
And these the showers to bring it on.—Be cheerful.
</p>

<p class="drama">
OCTAVIA.<br>
Sir, look well to my husband’s house, and—
</p>

<p class="drama">
CAESAR.<br>
What, Octavia?
</p>

<p class="drama">
OCTAVIA.<br>
I’ll tell you in your ear.
</p>

<p class="drama">
ANTONY.<br>
Her tongue will not obey her heart, nor can<br>
Her heart inform her tongue—the swan’s-down feather,<br>
That stands upon the swell at the full of tide,<br>
And neither way inclines.
</p>

<p class="drama">
ENOBARBUS.<br>
[<i>Aside to Agrippa</i>.] Will Caesar weep?
</p>

<p class="drama">
AGRIPPA.<br>
[<i>Aside to Enobarbus</i>.] He has a cloud in ’s face.
</p>

<p class="drama">
ENOBARBUS.<br>
[<i>Aside to Agrippa</i>.] He were the worse for that were he a horse;<br>
So is he, being a man.
</p>

<p class="drama">
AGRIPPA.<br>
[<i>Aside to Enobarbus</i>.] Why, Enobarbus,<br>
When Antony found Julius Caesar dead,<br>
He cried almost to roaring, and he wept<br>
When at Philippi he found Brutus slain.
</p>

<p class="drama">
ENOBARBUS.<br>
[<i>Aside to Agrippa</i>.] That year, indeed, he was troubled with a
rheum;<br>
What willingly he did confound he wailed,<br>
Believe ’t, till I weep too.
</p>

<p class="drama">
CAESAR.<br>
No, sweet Octavia,<br>
You shall hear from me still. The time shall not<br>
Outgo my thinking on you.
</p>

<p class="drama">
ANTONY.<br>
Come, sir, come,<br>
I’ll wrestle with you in my strength of love.<br>
Look, here I have you, thus I let you go,<br>
And give you to the gods.
</p>

<p class="drama">
CAESAR.<br>
Adieu, be happy!
</p>

<p class="drama">
LEPIDUS.<br>
Let all the number of the stars give light<br>
To thy fair way!
</p>

<p class="drama">
CAESAR.<br>
Farewell, farewell!
</p>

<p class="right">
[<i>Kisses <span class="charname">Octavia</span>.</i>]
</p>

<p class="drama">
ANTONY.<br>
Farewell!
</p>

<p class="right">
[<i>Trumpets sound. Exeunt.</i>]
</p>

<h3> <a id="sceneIII_3.3"></a><b>SCENE III. Alexandria. A Room in the
Palace.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Cleopatra, Charmian, Iras</span> and <span class="charname">Alexas</span>.
</p>

<p class="drama">
CLEOPATRA.<br>
Where is the fellow?
</p>

<p class="drama">
ALEXAS.<br>
Half afeared to come.
</p>

<p class="drama">
CLEOPATRA.<br>
Go to, go to.
</p>

<p class="scenedesc">
Enter a <span class="charname">Messenger</span> as before.
</p>

<p class="drama">
Come hither, sir.
</p>

<p class="drama">
ALEXAS.<br>
Good majesty,<br>
Herod of Jewry dare not look upon you<br>
But when you are well pleased.
</p>

<p class="drama">
CLEOPATRA.<br>
That Herod’s head<br>
I’ll have! But how, when Antony is gone,<br>
Through whom I might command it?—Come thou near.
</p>

<p class="drama">
MESSENGER.<br>
Most gracious majesty!
</p>

<p class="drama">
CLEOPATRA.<br>
Didst thou behold Octavia?
</p>

<p class="drama">
MESSENGER.<br>
Ay, dread queen.
</p>

<p class="drama">
CLEOPATRA.<br>
Where?
</p>

<p class="drama">
MESSENGER.<br>
Madam, in Rome<br>
I looked her in the face, and saw her led<br>
Between her brother and Mark Antony.
</p>

<p class="drama">
CLEOPATRA.<br>
Is she as tall as me?
</p>

<p class="drama">
MESSENGER.<br>
She is not, madam.
</p>

<p class="drama">
CLEOPATRA.<br>
Didst hear her speak? Is she shrill-tongued or low?
</p>

<p class="drama">
MESSENGER.<br>
Madam, I heard her speak. She is low-voiced.
</p>

<p class="drama">
CLEOPATRA.<br>
That’s not so good. He cannot like her long.
</p>

<p class="drama">
CHARMIAN.<br>
Like her? O Isis! ’Tis impossible.
</p>

<p class="drama">
CLEOPATRA.<br>
I think so, Charmian: dull of tongue and dwarfish!<br>
What majesty is in her gait? Remember,<br>
If e’er thou look’dst on majesty.
</p>

<p class="drama">
MESSENGER.<br>
She creeps.<br>
Her motion and her station are as one.<br>
She shows a body rather than a life,<br>
A statue than a breather.
</p>

<p class="drama">
CLEOPATRA.<br>
Is this certain?
</p>

<p class="drama">
MESSENGER.<br>
Or I have no observance.
</p>

<p class="drama">
CHARMIAN.<br>
Three in Egypt<br>
Cannot make better note.
</p>

<p class="drama">
CLEOPATRA.<br>
He’s very knowing;<br>
I do perceive’t. There’s nothing in her yet.<br>
The fellow has good judgment.
</p>

<p class="drama">
CHARMIAN.<br>
Excellent.
</p>

<p class="drama">
CLEOPATRA.<br>
Guess at her years, I prithee.
</p>

<p class="drama">
MESSENGER.<br>
Madam,<br>
She was a widow.
</p>

<p class="drama">
CLEOPATRA.<br>
Widow! Charmian, hark!
</p>

<p class="drama">
MESSENGER.<br>
And I do think she’s thirty.
</p>

<p class="drama">
CLEOPATRA.<br>
Bear’st thou her face in mind? Is’t long or round?
</p>

<p class="drama">
MESSENGER.<br>
Round even to faultiness.
</p>

<p class="drama">
CLEOPATRA.<br>
For the most part, too, they are foolish that are so.<br>
Her hair, what colour?
</p>

<p class="drama">
MESSENGER.<br>
Brown, madam, and her forehead<br>
As low as she would wish it.
</p>

<p class="drama">
CLEOPATRA.<br>
There’s gold for thee.<br>
Thou must not take my former sharpness ill.<br>
I will employ thee back again; I find thee<br>
Most fit for business. Go make thee ready;<br>
Our letters are prepared.
</p>

<p class="right">
[<i>Exit <span class="charname">Messenger</span>.</i>]
</p>

<p class="drama">
CHARMIAN.<br>
A proper man.
</p>

<p class="drama">
CLEOPATRA.<br>
Indeed, he is so. I repent me much<br>
That so I harried him. Why, methinks, by him,<br>
This creature’s no such thing.
</p>

<p class="drama">
CHARMIAN.<br>
Nothing, madam.
</p>

<p class="drama">
CLEOPATRA.<br>
The man hath seen some majesty, and should know.
</p>

<p class="drama">
CHARMIAN.<br>
Hath he seen majesty? Isis else defend,<br>
And serving you so long!
</p>

<p class="drama">
CLEOPATRA.<br>
I have one thing more to ask him yet, good Charmian.<br>
But ’tis no matter; thou shalt bring him to me<br>
Where I will write. All may be well enough.
</p>

<p class="drama">
CHARMIAN.<br>
I warrant you, madam.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneIII_3.4"></a><b>SCENE IV. Athens. A Room in Antony’s
House.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Antony</span> and <span class="charname">Octavia</span>.
</p>

<p class="drama">
ANTONY.<br>
Nay, nay, Octavia, not only that—<br>
That were excusable, that and thousands more<br>
Of semblable import—but he hath waged<br>
New wars ’gainst Pompey; made his will, and read it<br>
To public ear;<br>
Spoke scantly of me; when perforce he could not<br>
But pay me terms of honour, cold and sickly<br>
He vented them; most narrow measure lent me;<br>
When the best hint was given him, he not took ’t,<br>
Or did it from his teeth.
</p>

<p class="drama">
OCTAVIA.<br>
O, my good lord,<br>
Believe not all, or if you must believe,<br>
Stomach not all. A more unhappy lady,<br>
If this division chance, ne’er stood between,<br>
Praying for both parts.<br>
The good gods will mock me presently<br>
When I shall pray “O, bless my lord and husband!”<br>
Undo that prayer by crying out as loud<br>
“O, bless my brother!” Husband win, win brother,<br>
Prays and destroys the prayer; no midway<br>
’Twixt these extremes at all.
</p>

<p class="drama">
ANTONY.<br>
Gentle Octavia,<br>
Let your best love draw to that point which seeks<br>
Best to preserve it. If I lose mine honour,<br>
I lose myself; better I were not yours<br>
Than yours so branchless. But, as you requested,<br>
Yourself shall go between’s. The meantime, lady,<br>
I’ll raise the preparation of a war<br>
Shall stain your brother. Make your soonest haste,<br>
So your desires are yours.
</p>

<p class="drama">
OCTAVIA.<br>
Thanks to my lord.<br>
The Jove of power make me, most weak, most weak,<br>
Your reconciler! Wars ’twixt you twain would be<br>
As if the world should cleave, and that slain men<br>
Should solder up the rift.
</p>

<p class="drama">
ANTONY.<br>
When it appears to you where this begins,<br>
Turn your displeasure that way, for our faults<br>
Can never be so equal that your love<br>
Can equally move with them. Provide your going;<br>
Choose your own company, and command what cost<br>
Your heart has mind to.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneIII_3.5"></a><b>SCENE V. Athens. Another Room in Antony’s
House.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Enobarbus</span> and <span class="charname">Eros</span> meeting.
</p>

<p class="drama">
ENOBARBUS.<br>
How now, friend Eros?
</p>

<p class="drama">
EROS.<br>
There’s strange news come, sir.
</p>

<p class="drama">
ENOBARBUS.<br>
What, man?
</p>

<p class="drama">
EROS.<br>
Caesar and Lepidus have made wars upon Pompey.
</p>

<p class="drama">
ENOBARBUS.<br>
This is old. What is the success?
</p>

<p class="drama">
EROS.<br>
Caesar, having made use of him in the wars ’gainst Pompey, presently denied him
rivality; would not let him partake in the glory of the action, and, not
resting here, accuses him of letters he had formerly wrote to Pompey; upon his
own appeal, seizes him. So the poor third is up, till death enlarge his
confine.
</p>

<p class="drama">
ENOBARBUS.<br>
Then, world, thou hast a pair of chaps, no more,<br>
And throw between them all the food thou hast,<br>
They’ll grind the one the other. Where’s Antony?
</p>

<p class="drama">
EROS.<br>
He’s walking in the garden, thus, and spurns<br>
The rush that lies before him; cries “Fool Lepidus!”<br>
And threats the throat of that his officer<br>
That murdered Pompey.
</p>

<p class="drama">
ENOBARBUS.<br>
Our great navy’s rigged.
</p>

<p class="drama">
EROS.<br>
For Italy and Caesar. More, Domitius:<br>
My lord desires you presently. My news<br>
I might have told hereafter.
</p>

<p class="drama">
ENOBARBUS.<br>
’Twill be naught,<br>
But let it be. Bring me to Antony.
</p>

<p class="drama">
EROS.<br>
Come, sir.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneIII_3.6"></a><b>SCENE VI. Rome. A Room in Caesar’s
House.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Agrippa, Maecenas</span> and <span class="charname">Caesar</span>.
</p>

<p class="drama">
CAESAR.<br>
Contemning Rome, he has done all this, and more<br>
In Alexandria. Here’s the manner of ’t:<br>
I’ th’ market-place, on a tribunal silvered,<br>
Cleopatra and himself in chairs of gold<br>
Were publicly enthroned. At the feet sat<br>
Caesarion, whom they call my father’s son,<br>
And all the unlawful issue that their lust<br>
Since then hath made between them. Unto her<br>
He gave the stablishment of Egypt; made her<br>
Of lower Syria, Cyprus, Lydia,<br>
Absolute queen.
</p>

<p class="drama">
MAECENAS.<br>
This in the public eye?
</p>

<p class="drama">
CAESAR.<br>
I’ th’ common showplace where they exercise.<br>
His sons he there proclaimed the kings of kings:<br>
Great Media, Parthia, and Armenia<br>
He gave to Alexander; to Ptolemy he assigned<br>
Syria, Cilicia, and Phoenicia. She<br>
In th’ habiliments of the goddess Isis<br>
That day appeared, and oft before gave audience,<br>
As ’tis reported, so.
</p>

<p class="drama">
MAECENAS.<br>
Let Rome be thus informed.
</p>

<p class="drama">
AGRIPPA.<br>
Who, queasy with his insolence already,<br>
Will their good thoughts call from him.
</p>

<p class="drama">
CAESAR.<br>
The people knows it and have now received<br>
His accusations.
</p>

<p class="drama">
AGRIPPA.<br>
Who does he accuse?
</p>

<p class="drama">
CAESAR.<br>
Caesar, and that, having in Sicily<br>
Sextus Pompeius spoiled, we had not rated him<br>
His part o’ th’ isle. Then does he say he lent me<br>
Some shipping, unrestored. Lastly, he frets<br>
That Lepidus of the triumvirate<br>
Should be deposed and, being, that we detain<br>
All his revenue.
</p>

<p class="drama">
AGRIPPA.<br>
Sir, this should be answered.
</p>

<p class="drama">
CAESAR.<br>
’Tis done already, and messenger gone.<br>
I have told him Lepidus was grown too cruel,<br>
That he his high authority abused,<br>
And did deserve his change. For what I have conquered<br>
I grant him part; but then in his Armenia<br>
And other of his conquered kingdoms, I<br>
Demand the like.
</p>

<p class="drama">
MAECENAS.<br>
He’ll never yield to that.
</p>

<p class="drama">
CAESAR.<br>
Nor must not then be yielded to in this.
</p>

<p class="scenedesc">
Enter <span class="charname">Octavia</span> with her train.
</p>

<p class="drama">
OCTAVIA.<br>
Hail, Caesar, and my lord! Hail, most dear Caesar!
</p>

<p class="drama">
CAESAR.<br>
That ever I should call thee castaway!
</p>

<p class="drama">
OCTAVIA.<br>
You have not called me so, nor have you cause.
</p>

<p class="drama">
CAESAR.<br>
Why have you stolen upon us thus? You come not<br>
Like Caesar’s sister. The wife of Antony<br>
Should have an army for an usher, and<br>
The neighs of horse to tell of her approach<br>
Long ere she did appear. The trees by th’ way<br>
Should have borne men, and expectation fainted,<br>
Longing for what it had not. Nay, the dust<br>
Should have ascended to the roof of heaven,<br>
Raised by your populous troops. But you are come<br>
A market-maid to Rome, and have prevented<br>
The ostentation of our love, which, left unshown,<br>
Is often left unloved. We should have met you<br>
By sea and land, supplying every stage<br>
With an augmented greeting.
</p>

<p class="drama">
OCTAVIA.<br>
Good my lord,<br>
To come thus was I not constrained, but did it<br>
On my free will. My lord, Mark Antony,<br>
Hearing that you prepared for war, acquainted<br>
My grieved ear withal, whereon I begged<br>
His pardon for return.
</p>

<p class="drama">
CAESAR.<br>
Which soon he granted,<br>
Being an abstract ’tween his lust and him.
</p>

<p class="drama">
OCTAVIA.<br>
Do not say so, my lord.
</p>

<p class="drama">
CAESAR.<br>
I have eyes upon him,<br>
And his affairs come to me on the wind.<br>
Where is he now?
</p>

<p class="drama">
OCTAVIA.<br>
My lord, in Athens.
</p>

<p class="drama">
CAESAR.<br>
No, my most wronged sister. Cleopatra<br>
Hath nodded him to her. He hath given his empire<br>
Up to a whore, who now are levying<br>
The kings o’ th’ earth for war. He hath assembled<br>
Bocchus, the king of Libya; Archelaus<br>
Of Cappadocia; Philadelphos, king<br>
Of Paphlagonia; the Thracian king, Adallas;<br>
King Manchus of Arabia; King of Pont;<br>
Herod of Jewry; Mithridates, king<br>
Of Comagene; Polemon and Amyntas,<br>
The kings of Mede and Lycaonia,<br>
With a more larger list of sceptres.
</p>

<p class="drama">
OCTAVIA.<br>
Ay me, most wretched,<br>
That have my heart parted betwixt two friends<br>
That does afflict each other!
</p>

<p class="drama">
CAESAR.<br>
Welcome hither.<br>
Your letters did withhold our breaking forth<br>
Till we perceived both how you were wrong led<br>
And we in negligent danger. Cheer your heart.<br>
Be you not troubled with the time, which drives<br>
O’er your content these strong necessities,<br>
But let determined things to destiny<br>
Hold unbewailed their way. Welcome to Rome,<br>
Nothing more dear to me. You are abused<br>
Beyond the mark of thought, and the high gods,<br>
To do you justice, make their ministers<br>
Of us and those that love you. Best of comfort,<br>
And ever welcome to us.
</p>

<p class="drama">
AGRIPPA.<br>
Welcome, lady.
</p>

<p class="drama">
MAECENAS.<br>
Welcome, dear madam.<br>
Each heart in Rome does love and pity you.<br>
Only th’ adulterous Antony, most large<br>
In his abominations, turns you off<br>
And gives his potent regiment to a trull<br>
That noises it against us.
</p>

<p class="drama">
OCTAVIA.<br>
Is it so, sir?
</p>

<p class="drama">
CAESAR.<br>
Most certain. Sister, welcome. Pray you<br>
Be ever known to patience. My dear’st sister!
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneIII_3.7"></a><b>SCENE VII. Antony’s Camp near the Promontory
of Actium.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Cleopatra</span> and <span class="charname">Enobarbus</span>.
</p>

<p class="drama">
CLEOPATRA.<br>
I will be even with thee, doubt it not.
</p>

<p class="drama">
ENOBARBUS.<br>
But why, why, why?
</p>

<p class="drama">
CLEOPATRA.<br>
Thou hast forspoke my being in these wars<br>
And say’st it is not fit.
</p>

<p class="drama">
ENOBARBUS.<br>
Well, is it, is it?
</p>

<p class="drama">
CLEOPATRA.<br>
Is ’t not denounced against us? Why should not we<br>
Be there in person?
</p>

<p class="drama">
ENOBARBUS.<br>
Well, I could reply:<br>
If we should serve with horse and mares together,<br>
The horse were merely lost. The mares would bear<br>
A soldier and his horse.
</p>

<p class="drama">
CLEOPATRA.<br>
What is’t you say?
</p>

<p class="drama">
ENOBARBUS.<br>
Your presence needs must puzzle Antony,<br>
Take from his heart, take from his brain, from ’s time,<br>
What should not then be spared. He is already<br>
Traduced for levity, and ’tis said in Rome<br>
That Photinus, an eunuch, and your maids<br>
Manage this war.
</p>

<p class="drama">
CLEOPATRA.<br>
Sink Rome, and their tongues rot<br>
That speak against us! A charge we bear i’ th’ war,<br>
And, as the president of my kingdom, will<br>
Appear there for a man. Speak not against it.<br>
I will not stay behind.
</p>

<p class="scenedesc">
Enter <span class="charname">Antony</span> and <span class="charname">Canidius</span>.
</p>

<p class="drama">
ENOBARBUS.<br>
Nay, I have done.<br>
Here comes the Emperor.
</p>

<p class="drama">
ANTONY.<br>
Is it not strange, Canidius,<br>
That from Tarentum and Brundusium<br>
He could so quickly cut the Ionian sea<br>
And take in Toryne?—You have heard on ’t, sweet?
</p>

<p class="drama">
CLEOPATRA.<br>
Celerity is never more admired<br>
Than by the negligent.
</p>

<p class="drama">
ANTONY.<br>
A good rebuke,<br>
Which might have well becomed the best of men<br>
To taunt at slackness.—Canidius, we<br>
Will fight with him by sea.
</p>

<p class="drama">
CLEOPATRA.<br>
By sea, what else?
</p>

<p class="drama">
CANIDIUS.<br>
Why will my lord do so?
</p>

<p class="drama">
ANTONY.<br>
For that he dares us to ’t.
</p>

<p class="drama">
ENOBARBUS.<br>
So hath my lord dared him to single fight.
</p>

<p class="drama">
CANIDIUS.<br>
Ay, and to wage this battle at Pharsalia,<br>
Where Caesar fought with Pompey. But these offers,<br>
Which serve not for his vantage, he shakes off,<br>
And so should you.
</p>

<p class="drama">
ENOBARBUS.<br>
Your ships are not well manned,<br>
Your mariners are muleteers, reapers, people<br>
Engrossed by swift impress. In Caesar’s fleet<br>
Are those that often have ’gainst Pompey fought.<br>
Their ships are yare, yours heavy. No disgrace<br>
Shall fall you for refusing him at sea,<br>
Being prepared for land.
</p>

<p class="drama">
ANTONY.<br>
By sea, by sea.
</p>

<p class="drama">
ENOBARBUS.<br>
Most worthy sir, you therein throw away<br>
The absolute soldiership you have by land;<br>
Distract your army, which doth most consist<br>
Of war-marked footmen; leave unexecuted<br>
Your own renowned knowledge; quite forgo<br>
The way which promises assurance; and<br>
Give up yourself merely to chance and hazard<br>
From firm security.
</p>

<p class="drama">
ANTONY.<br>
I’ll fight at sea.
</p>

<p class="drama">
CLEOPATRA.<br>
I have sixty sails, Caesar none better.
</p>

<p class="drama">
ANTONY.<br>
Our overplus of shipping will we burn,<br>
And with the rest full-manned, from th’ head of Actium<br>
Beat th’ approaching Caesar. But if we fail,<br>
We then can do ’t at land.
</p>

<p class="scenedesc">
Enter a <span class="charname">Messenger</span>.
</p>

<p class="drama">
Thy business?
</p>

<p class="drama">
MESSENGER.<br>
The news is true, my lord; he is descried.<br>
Caesar has taken Toryne.
</p>

<p class="drama">
ANTONY.<br>
Can he be there in person? ’Tis impossible;<br>
Strange that his power should be. Canidius,<br>
Our nineteen legions thou shalt hold by land,<br>
And our twelve thousand horse. We’ll to our ship.<br>
Away, my Thetis!
</p>

<p class="scenedesc">
Enter a <span class="charname">Soldier</span>.
</p>

<p class="drama">
How now, worthy soldier?
</p>

<p class="drama">
SOLDIER.<br>
O noble emperor, do not fight by sea.<br>
Trust not to rotten planks. Do you misdoubt<br>
This sword and these my wounds? Let th’ Egyptians<br>
And the Phoenicians go a-ducking. We<br>
Have used to conquer standing on the earth<br>
And fighting foot to foot.
</p>

<p class="drama">
ANTONY.<br>
Well, well, away.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Antony, Cleopatra</span> and <span class="charname">Enobarbus</span>.</i>]
</p>

<p class="drama">
SOLDIER.<br>
By Hercules, I think I am i’ th’ right.
</p>

<p class="drama">
CANIDIUS.<br>
Soldier, thou art. But his whole action grows<br>
Not in the power on ’t. So our leader’s led,<br>
And we are women’s men.
</p>

<p class="drama">
SOLDIER.<br>
You keep by land<br>
The legions and the horse whole, do you not?
</p>

<p class="drama">
CANIDIUS.<br>
Marcus Octavius, Marcus Justeius,<br>
Publicola, and Caelius are for sea,<br>
But we keep whole by land. This speed of Caesar’s<br>
Carries beyond belief.
</p>

<p class="drama">
SOLDIER.<br>
While he was yet in Rome,<br>
His power went out in such distractions as<br>
Beguiled all spies.
</p>

<p class="drama">
CANIDIUS.<br>
Who’s his lieutenant, hear you?
</p>

<p class="drama">
SOLDIER.<br>
They say one Taurus.
</p>

<p class="drama">
CANIDIUS.<br>
Well I know the man.
</p>

<p class="scenedesc">
Enter a <span class="charname">Messenger</span>.
</p>

<p class="drama">
MESSENGER.<br>
The Emperor calls Canidius.
</p>

<p class="drama">
CANIDIUS.<br>
With news the time’s with labour, and throes forth<br>
Each minute some.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneIII_3.8"></a><b>SCENE VIII. A plain near Actium.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Caesar</span> with his army and <span class="charname">Taurus</span> marching.
</p>

<p class="drama">
CAESAR.<br>
Taurus!
</p>

<p class="drama">
TAURUS.<br>
My lord?
</p>

<p class="drama">
CAESAR.<br>
Strike not by land; keep whole; provoke not battle<br>
Till we have done at sea. Do not exceed<br>
The prescript of this scroll. Our fortune lies<br>
Upon this jump.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneIII_3.9"></a><b>SCENE IX. Another part of the Plain.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Antony</span> and <span class="charname">Enobarbus</span>.
</p>

<p class="drama">
ANTONY.<br>
Set we our squadrons on yon side o’ th’ hill<br>
In eye of Caesar’s battle, from which place<br>
We may the number of the ships behold<br>
And so proceed accordingly.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneIII_3.10"></a><b>SCENE X. Another part of the Plain.</b></h3>

<p class="scenedesc">
<span class="charname">Canidius</span> marching with his land army one way over
the stage, and <span class="charname">Taurus,</span> the Lieutenant of <span class="charname">Caesar,</span> with his Army, the other way. After their going
in, is heard the noise of a sea fight.
</p>

<p class="scenedesc">
Alarum. Enter <span class="charname">Enobarbus</span>.
</p>

<p class="drama">
ENOBARBUS.<br>
Naught, naught, all naught! I can behold no longer.<br>
Th’ Antoniad, the Egyptian admiral,<br>
With all their sixty, fly and turn the rudder.<br>
To see ’t mine eyes are blasted.
</p>

<p class="scenedesc">
Enter <span class="charname">Scarus</span>.
</p>

<p class="drama">
SCARUS.<br>
Gods and goddesses,<br>
All the whole synod of them!
</p>

<p class="drama">
ENOBARBUS.<br>
What’s thy passion?
</p>

<p class="drama">
SCARUS.<br>
The greater cantle of the world is lost<br>
With very ignorance. We have kissed away<br>
Kingdoms and provinces.
</p>

<p class="drama">
ENOBARBUS.<br>
How appears the fight?
</p>

<p class="drama">
SCARUS.<br>
On our side, like the tokened pestilence,<br>
Where death is sure. Yon ribaudred nag of Egypt,<br>
Whom leprosy o’ertake, i’ th’ midst o’ th’ fight,<br>
When vantage like a pair of twins appeared,<br>
Both as the same—or, rather, ours the elder—<br>
The breeze upon her, like a cow in June,<br>
Hoists sails and flies.
</p>

<p class="drama">
ENOBARBUS.<br>
That I beheld.<br>
Mine eyes did sicken at the sight and could not<br>
Endure a further view.
</p>

<p class="drama">
SCARUS.<br>
She once being loofed,<br>
The noble ruin of her magic, Antony,<br>
Claps on his sea-wing and, like a doting mallard,<br>
Leaving the fight in height, flies after her.<br>
I never saw an action of such shame.<br>
Experience, manhood, honour, ne’er before<br>
Did violate so itself.
</p>

<p class="drama">
ENOBARBUS.<br>
Alack, alack!
</p>

<p class="scenedesc">
Enter <span class="charname">Canidius</span>.
</p>

<p class="drama">
CANIDIUS.<br>
Our fortune on the sea is out of breath<br>
And sinks most lamentably. Had our general<br>
Been what he knew himself, it had gone well.<br>
O, he has given example for our flight<br>
Most grossly by his own!
</p>

<p class="drama">
ENOBARBUS.<br>
Ay, are you thereabouts?<br>
Why, then, good night indeed.
</p>

<p class="drama">
CANIDIUS.<br>
Toward Peloponnesus are they fled.
</p>

<p class="drama">
SCARUS.<br>
’Tis easy to’t, and there I will attend<br>
What further comes.
</p>

<p class="drama">
CANIDIUS.<br>
To Caesar will I render<br>
My legions and my horse. Six kings already<br>
Show me the way of yielding.
</p>

<p class="drama">
ENOBARBUS.<br>
I’ll yet follow<br>
The wounded chance of Antony, though my reason<br>
Sits in the wind against me.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneIII_3.11"></a><b>SCENE XI. Alexandria. A Room in the
Palace.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Antony</span> with attendants.
</p>

<p class="drama">
ANTONY.<br>
Hark, the land bids me tread no more upon’t.<br>
It is ashamed to bear me. Friends, come hither.<br>
I am so lated in the world that I<br>
Have lost my way for ever. I have a ship<br>
Laden with gold. Take that, divide it. Fly,<br>
And make your peace with Caesar.
</p>

<p class="drama">
ALL.<br>
Fly? Not we.
</p>

<p class="drama">
ANTONY.<br>
I have fled myself, and have instructed cowards<br>
To run and show their shoulders. Friends, be gone.<br>
I have myself resolved upon a course<br>
Which has no need of you. Be gone.<br>
My treasure’s in the harbour. Take it. O,<br>
I followed that I blush to look upon.<br>
My very hairs do mutiny, for the white<br>
Reprove the brown for rashness, and they them<br>
For fear and doting. Friends, be gone. You shall<br>
Have letters from me to some friends that will<br>
Sweep your way for you. Pray you, look not sad,<br>
Nor make replies of loathness. Take the hint<br>
Which my despair proclaims. Let that be left<br>
Which leaves itself. To the sea-side straightway.<br>
I will possess you of that ship and treasure.<br>
Leave me, I pray, a little—pray you, now,<br>
Nay, do so; for indeed I have lost command.<br>
Therefore I pray you. I’ll see you by and by.
</p>

<p class="right">
[<i>Sits down.</i>]
</p>

<p class="scenedesc">
Enter <span class="charname">Cleopatra</span> led by <span class="charname">Charmian, Iras</span> and <span class="charname">Eros</span>.
</p>

<p class="drama">
EROS.<br>
Nay, gentle madam, to him! Comfort him.
</p>

<p class="drama">
IRAS.<br>
Do, most dear queen.
</p>

<p class="drama">
CHARMIAN.<br>
Do! Why, what else?
</p>

<p class="drama">
CLEOPATRA.<br>
Let me sit down. O Juno!
</p>

<p class="drama">
ANTONY.<br>
No, no, no, no, no.
</p>

<p class="drama">
EROS.<br>
See you here, sir?
</p>

<p class="drama">
ANTONY.<br>
O, fie, fie, fie!
</p>

<p class="drama">
CHARMIAN.<br>
Madam.
</p>

<p class="drama">
IRAS.<br>
Madam, O good empress!
</p>

<p class="drama">
EROS.<br>
Sir, sir!
</p>

<p class="drama">
ANTONY.<br>
Yes, my lord, yes. He at Philippi kept<br>
His sword e’en like a dancer, while I struck<br>
The lean and wrinkled Cassius, and ’twas I<br>
That the mad Brutus ended. He alone<br>
Dealt on lieutenantry, and no practice had<br>
In the brave squares of war. Yet now—no matter.
</p>

<p class="drama">
CLEOPATRA.<br>
Ah, stand by.
</p>

<p class="drama">
EROS.<br>
The Queen, my lord, the Queen!
</p>

<p class="drama">
IRAS.<br>
Go to him, madam; speak to him.<br>
He is unqualitied with very shame.
</p>

<p class="drama">
CLEOPATRA.<br>
Well then, sustain me. O!
</p>

<p class="drama">
EROS.<br>
Most noble sir, arise. The Queen approaches.<br>
Her head’s declined, and death will seize her but<br>
Your comfort makes the rescue.
</p>

<p class="drama">
ANTONY.<br>
I have offended reputation,<br>
A most unnoble swerving.
</p>

<p class="drama">
EROS.<br>
Sir, the Queen.
</p>

<p class="drama">
ANTONY.<br>
O, whither hast thou led me, Egypt? See<br>
How I convey my shame out of thine eyes<br>
By looking back what I have left behind<br>
’Stroyed in dishonour.
</p>

<p class="drama">
CLEOPATRA.<br>
O my lord, my lord,<br>
Forgive my fearful sails! I little thought<br>
You would have followed.
</p>

<p class="drama">
ANTONY.<br>
Egypt, thou knew’st too well<br>
My heart was to thy rudder tied by th’ strings,<br>
And thou shouldst tow me after. O’er my spirit<br>
Thy full supremacy thou knew’st, and that<br>
Thy beck might from the bidding of the gods<br>
Command me.
</p>

<p class="drama">
CLEOPATRA.<br>
O, my pardon!
</p>

<p class="drama">
ANTONY.<br>
Now I must<br>
To the young man send humble treaties, dodge<br>
And palter in the shifts of lowness, who<br>
With half the bulk o’ th’ world played as I pleased,<br>
Making and marring fortunes. You did know<br>
How much you were my conqueror, and that<br>
My sword, made weak by my affection, would<br>
Obey it on all cause.
</p>

<p class="drama">
CLEOPATRA.<br>
Pardon, pardon!
</p>

<p class="drama">
ANTONY.<br>
Fall not a tear, I say; one of them rates<br>
All that is won and lost. Give me a kiss.<br>
Even this repays me.<br>
We sent our schoolmaster. Is he come back?<br>
Love, I am full of lead. Some wine<br>
Within there, and our viands! Fortune knows<br>
We scorn her most when most she offers blows.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneIII_3.12"></a><b>SCENE XII. Caesar’s camp in Egypt.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Caesar, Agrippa, Dolabella </span> with others.
</p>

<p class="drama">
CAESAR.<br>
Let him appear that’s come from Antony.<br>
Know you him?
</p>

<p class="drama">
DOLABELLA.<br>
Caesar, ’tis his schoolmaster—<br>
An argument that he is plucked, when hither<br>
He sends so poor a pinion of his wing,<br>
Which had superfluous kings for messengers<br>
Not many moons gone by.
</p>

<p class="scenedesc">
Enter <span class="charname">Ambassador</span> from Anthony.
</p>

<p class="drama">
CAESAR.<br>
Approach, and speak.
</p>

<p class="drama">
AMBASSADOR.<br>
Such as I am, I come from Antony.<br>
I was of late as petty to his ends<br>
As is the morn-dew on the myrtle leaf<br>
To his grand sea.
</p>

<p class="drama">
CAESAR.<br>
Be’t so. Declare thine office.
</p>

<p class="drama">
AMBASSADOR.<br>
Lord of his fortunes he salutes thee, and<br>
Requires to live in Egypt, which not granted,<br>
He lessens his requests, and to thee sues<br>
To let him breathe between the heavens and earth,<br>
A private man in Athens. This for him.<br>
Next, Cleopatra does confess thy greatness,<br>
Submits her to thy might, and of thee craves<br>
The circle of the Ptolemies for her heirs,<br>
Now hazarded to thy grace.
</p>

<p class="drama">
CAESAR.<br>
For Antony,<br>
I have no ears to his request. The queen<br>
Of audience nor desire shall fail, so she<br>
From Egypt drive her all-disgraced friend,<br>
Or take his life there. This if she perform,<br>
She shall not sue unheard. So to them both.
</p>

<p class="drama">
AMBASSADOR.<br>
Fortune pursue thee!
</p>

<p class="drama">
CAESAR.<br>
Bring him through the bands.
</p>

<p class="right">
[<i>Exit <span class="charname">Ambassador</span>, attended.</i>]
</p>

<p class="drama">
[<i>To Thidias</i>.] To try thy eloquence now ’tis time. Dispatch.<br>
From Antony win Cleopatra. Promise,<br>
And in our name, what she requires; add more,<br>
From thine invention, offers. Women are not<br>
In their best fortunes strong, but want will perjure<br>
The ne’er-touch’d vestal. Try thy cunning, Thidias;<br>
Make thine own edict for thy pains, which we<br>
Will answer as a law.
</p>

<p class="drama">
THIDIAS.<br>
Caesar, I go.
</p>

<p class="drama">
CAESAR.<br>
Observe how Antony becomes his flaw,<br>
And what thou think’st his very action speaks<br>
In every power that moves.
</p>

<p class="drama">
THIDIAS.<br>
Caesar, I shall.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneIII_3.13"></a><b>SCENE XIII. Alexandria. A Room in the
Palace.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Cleopatra, Enobarbus, Charmian</span> and <span class="charname">Iras</span>.
</p>

<p class="drama">
CLEOPATRA.<br>
What shall we do, Enobarbus?
</p>

<p class="drama">
ENOBARBUS.<br>
Think, and die.
</p>

<p class="drama">
CLEOPATRA.<br>
Is Antony or we in fault for this?
</p>

<p class="drama">
ENOBARBUS.<br>
Antony only, that would make his will<br>
Lord of his reason. What though you fled<br>
From that great face of war, whose several ranges<br>
Frighted each other? Why should he follow?<br>
The itch of his affection should not then<br>
Have nicked his captainship, at such a point,<br>
When half to half the world opposed, he being<br>
The mered question. ’Twas a shame no less<br>
Than was his loss, to course your flying flags<br>
And leave his navy gazing.
</p>

<p class="drama">
CLEOPATRA.<br>
Prithee, peace.
</p>

<p class="scenedesc">
Enter the <span class="charname">Ambassador</span> with <span class="charname">Antony</span>.
</p>

<p class="drama">
ANTONY.<br>
Is that his answer?
</p>

<p class="drama">
AMBASSADOR.<br>
Ay, my lord.
</p>

<p class="drama">
ANTONY.<br>
The Queen shall then have courtesy, so she<br>
Will yield us up.
</p>

<p class="drama">
AMBASSADOR.<br>
He says so.
</p>

<p class="drama">
ANTONY.<br>
Let her know’t.—<br>
To the boy Caesar send this grizzled head,<br>
And he will fill thy wishes to the brim<br>
With principalities.
</p>

<p class="drama">
CLEOPATRA.<br>
That head, my lord?
</p>

<p class="drama">
ANTONY.<br>
To him again. Tell him he wears the rose<br>
Of youth upon him, from which the world should note<br>
Something particular: his coin, ships, legions,<br>
May be a coward’s; whose ministers would prevail<br>
Under the service of a child as soon<br>
As i’ th’ command of Caesar. I dare him therefore<br>
To lay his gay comparisons apart,<br>
And answer me declined, sword against sword,<br>
Ourselves alone. I’ll write it. Follow me.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Antony</span> and <span class="charname">Ambassador</span>.</i>]
</p>

<p class="drama">
ENOBARBUS.<br>
Yes, like enough high-battled Caesar will<br>
Unstate his happiness, and be staged to th’ show<br>
Against a sworder! I see men’s judgments are<br>
A parcel of their fortunes, and things outward<br>
Do draw the inward quality after them<br>
To suffer all alike. That he should dream,<br>
Knowing all measures, the full Caesar will<br>
Answer his emptiness! Caesar, thou hast subdued<br>
His judgment too.
</p>

<p class="scenedesc">
Enter a <span class="charname">Servant</span>.
</p>

<p class="drama">
SERVANT.<br>
A messenger from Caesar.
</p>

<p class="drama">
CLEOPATRA.<br>
What, no more ceremony? See, my women,<br>
Against the blown rose may they stop their nose<br>
That kneeled unto the buds. Admit him, sir.
</p>

<p class="right">
[<i>Exit <span class="charname">Servant</span>.</i>]
</p>

<p class="drama">
ENOBARBUS.<br>
[<i>Aside</i>.] Mine honesty and I begin to square.<br>
The loyalty well held to fools does make<br>
Our faith mere folly. Yet he that can endure<br>
To follow with allegiance a fallen lord<br>
Does conquer him that did his master conquer,<br>
And earns a place i’ th’ story.
</p>

<p class="scenedesc">
Enter <span class="charname">Thidias</span>.
</p>

<p class="drama">
CLEOPATRA.<br>
Caesar’s will?
</p>

<p class="drama">
THIDIAS.<br>
Hear it apart.
</p>

<p class="drama">
CLEOPATRA.<br>
None but friends. Say boldly.
</p>

<p class="drama">
THIDIAS.<br>
So haply are they friends to Antony.
</p>

<p class="drama">
ENOBARBUS.<br>
He needs as many, sir, as Caesar has,<br>
Or needs not us. If Caesar please, our master<br>
Will leap to be his friend. For us, you know<br>
Whose he is we are, and that is Caesar’s.
</p>

<p class="drama">
THIDIAS.<br>
So.—<br>
Thus then, thou most renowned: Caesar entreats<br>
Not to consider in what case thou stand’st<br>
Further than he is Caesar.
</p>

<p class="drama">
CLEOPATRA.<br>
Go on; right royal.
</p>

<p class="drama">
THIDIAS.<br>
He knows that you embrace not Antony<br>
As you did love, but as you feared him.
</p>

<p class="drama">
CLEOPATRA.<br>
O!
</p>

<p class="drama">
THIDIAS.<br>
The scars upon your honour, therefore, he<br>
Does pity as constrained blemishes,<br>
Not as deserved.
</p>

<p class="drama">
CLEOPATRA.<br>
He is a god and knows<br>
What is most right. Mine honour was not yielded,<br>
But conquered merely.
</p>

<p class="drama">
ENOBARBUS.<br>
[<i>Aside</i>.] To be sure of that,<br>
I will ask Antony. Sir, sir, thou art so leaky<br>
That we must leave thee to thy sinking, for<br>
Thy dearest quit thee.
</p>

<p class="right">
[<i>Exit <span class="charname">Enobarbus</span>.</i>]
</p>

<p class="drama">
THIDIAS.<br>
Shall I say to Caesar<br>
What you require of him? For he partly begs<br>
To be desired to give. It much would please him<br>
That of his fortunes you should make a staff<br>
To lean upon. But it would warm his spirits<br>
To hear from me you had left Antony,<br>
And put yourself under his shroud,<br>
The universal landlord.
</p>

<p class="drama">
CLEOPATRA.<br>
What’s your name?
</p>

<p class="drama">
THIDIAS.<br>
My name is Thidias.
</p>

<p class="drama">
CLEOPATRA.<br>
Most kind messenger,<br>
Say to great Caesar this in deputation:<br>
I kiss his conqu’ring hand. Tell him I am prompt<br>
To lay my crown at’s feet, and there to kneel.<br>
Tell him, from his all-obeying breath I hear<br>
The doom of Egypt.
</p>

<p class="drama">
THIDIAS.<br>
’Tis your noblest course.<br>
Wisdom and fortune combating together,<br>
If that the former dare but what it can,<br>
No chance may shake it. Give me grace to lay<br>
My duty on your hand.
</p>

<p class="drama">
CLEOPATRA.<br>
Your Caesar’s father oft,<br>
When he hath mused of taking kingdoms in,<br>
Bestowed his lips on that unworthy place<br>
As it rained kisses.
</p>

<p class="scenedesc">
Enter <span class="charname">Antony</span> and <span class="charname">Enobarbus</span>.
</p>

<p class="drama">
ANTONY.<br>
Favours, by Jove that thunders!<br>
What art thou, fellow?
</p>

<p class="drama">
THIDIAS.<br>
One that but performs<br>
The bidding of the fullest man and worthiest<br>
To have command obeyed.
</p>

<p class="drama">
ENOBARBUS.<br>
[<i>Aside</i>.] You will be whipped.
</p>

<p class="drama">
ANTONY.<br>
Approach there.—Ah, you kite!—Now, gods and devils,<br>
Authority melts from me. Of late when I cried “Ho!”<br>
Like boys unto a muss, kings would start forth<br>
And cry “Your will?” Have you no ears? I am<br>
Antony yet.
</p>

<p class="scenedesc">
Enter <span class="charname">Servants</span>.
</p>

<p class="drama">
Take hence this jack and whip him.
</p>

<p class="drama">
ENOBARBUS.<br>
’Tis better playing with a lion’s whelp<br>
Than with an old one dying.
</p>

<p class="drama">
ANTONY.<br>
Moon and stars!<br>
Whip him. Were’t twenty of the greatest tributaries<br>
That do acknowledge Caesar, should I find them<br>
So saucy with the hand of she here—what’s her name<br>
Since she was Cleopatra? Whip him, fellows,<br>
Till like a boy you see him cringe his face<br>
And whine aloud for mercy. Take him hence.
</p>

<p class="drama">
THIDIAS.<br>
Mark Antony—
</p>

<p class="drama">
ANTONY.<br>
Tug him away. Being whipp’d,<br>
Bring him again. This jack of Caesar’s shall<br>
Bear us an errand to him.
</p>

<p class="right">
[<i>Exeunt Servants with <span class="charname">Thidias</span>.</i>]
</p>

<p class="drama">
You were half blasted ere I knew you. Ha!<br>
Have I my pillow left unpressed in Rome,<br>
Forborne the getting of a lawful race,<br>
And by a gem of women, to be abused<br>
By one that looks on feeders?
</p>

<p class="drama">
CLEOPATRA.<br>
Good my lord—
</p>

<p class="drama">
ANTONY.<br>
You have been a boggler ever.<br>
But when we in our viciousness grow hard—<br>
O misery on’t!—the wise gods seal our eyes,<br>
In our own filth drop our clear judgments, make us<br>
Adore our errors, laugh at’s while we strut<br>
To our confusion.
</p>

<p class="drama">
CLEOPATRA.<br>
O, is’t come to this?
</p>

<p class="drama">
ANTONY.<br>
I found you as a morsel cold upon<br>
Dead Caesar’s trencher; nay, you were a fragment<br>
Of Gneius Pompey’s, besides what hotter hours,<br>
Unregistered in vulgar fame, you have<br>
Luxuriously pick’d out. For I am sure,<br>
Though you can guess what temperance should be,<br>
You know not what it is.
</p>

<p class="drama">
CLEOPATRA.<br>
Wherefore is this?
</p>

<p class="drama">
ANTONY.<br>
To let a fellow that will take rewards<br>
And say “God quit you!” be familiar with<br>
My playfellow, your hand, this kingly seal<br>
And plighter of high hearts! O that I were<br>
Upon the hill of Basan, to outroar<br>
The horned herd! For I have savage cause,<br>
And to proclaim it civilly were like<br>
A haltered neck which does the hangman thank<br>
For being yare about him.
</p>

<p class="scenedesc">
Enter a <span class="charname">Servant</span> with <span class="charname">Thidias</span>.
</p>

<p class="drama">
Is he whipped?
</p>

<p class="drama">
SERVANT.<br>
Soundly, my lord.
</p>

<p class="drama">
ANTONY.<br>
Cried he? And begged he pardon?
</p>

<p class="drama">
SERVANT.<br>
He did ask favour.
</p>

<p class="drama">
ANTONY.<br>
If that thy father live, let him repent<br>
Thou wast not made his daughter; and be thou sorry<br>
To follow Caesar in his triumph, since<br>
Thou hast been whipped for following him. Henceforth<br>
The white hand of a lady fever thee;<br>
Shake thou to look on’t. Get thee back to Caesar;<br>
Tell him thy entertainment. Look thou say<br>
He makes me angry with him; for he seems<br>
Proud and disdainful, harping on what I am,<br>
Not what he knew I was. He makes me angry,<br>
And at this time most easy ’tis to do’t,<br>
When my good stars that were my former guides<br>
Have empty left their orbs and shot their fires<br>
Into th’ abysm of hell. If he mislike<br>
My speech and what is done, tell him he has<br>
Hipparchus, my enfranched bondman, whom<br>
He may at pleasure whip, or hang, or torture,<br>
As he shall like, to quit me. Urge it thou.<br>
Hence with thy stripes, be gone.
</p>

<p class="right">
[<i>Exit <span class="charname">Thidias</span>.</i>]
</p>

<p class="drama">
CLEOPATRA.<br>
Have you done yet?
</p>

<p class="drama">
ANTONY.<br>
Alack, our terrene moon is now eclipsed,<br>
And it portends alone the fall of Antony.
</p>

<p class="drama">
CLEOPATRA.<br>
I must stay his time.
</p>

<p class="drama">
ANTONY.<br>
To flatter Caesar, would you mingle eyes<br>
With one that ties his points?
</p>

<p class="drama">
CLEOPATRA.<br>
Not know me yet?
</p>

<p class="drama">
ANTONY.<br>
Cold-hearted toward me?
</p>

<p class="drama">
CLEOPATRA.<br>
Ah, dear, if I be so,<br>
From my cold heart let heaven engender hail<br>
And poison it in the source, and the first stone<br>
Drop in my neck; as it determines, so<br>
Dissolve my life! The next Caesarion smite,<br>
Till, by degrees the memory of my womb,<br>
Together with my brave Egyptians all,<br>
By the discandying of this pelleted storm,<br>
Lie graveless, till the flies and gnats of Nile<br>
Have buried them for prey!
</p>

<p class="drama">
ANTONY.<br>
I am satisfied.<br>
Caesar sits down in Alexandria, where<br>
I will oppose his fate. Our force by land<br>
Hath nobly held; our severed navy too<br>
Have knit again, and fleet, threat’ning most sea-like.<br>
Where hast thou been, my heart? Dost thou hear, lady?<br>
If from the field I shall return once more<br>
To kiss these lips, I will appear in blood.<br>
I and my sword will earn our chronicle.<br>
There’s hope in’t yet.
</p>

<p class="drama">
CLEOPATRA.<br>
That’s my brave lord!
</p>

<p class="drama">
ANTONY.<br>
I will be treble-sinewed, hearted, breathed,<br>
And fight maliciously. For when mine hours<br>
Were nice and lucky, men did ransom lives<br>
Of me for jests. But now I’ll set my teeth<br>
And send to darkness all that stop me. Come,<br>
Let’s have one other gaudy night. Call to me<br>
All my sad captains. Fill our bowls once more<br>
Let’s mock the midnight bell.
</p>

<p class="drama">
CLEOPATRA.<br>
It is my birthday.<br>
I had thought t’have held it poor, but since my lord<br>
Is Antony again, I will be Cleopatra.
</p>

<p class="drama">
ANTONY.<br>
We will yet do well.
</p>

<p class="drama">
CLEOPATRA.<br>
Call all his noble captains to my lord.
</p>

<p class="drama">
ANTONY.<br>
Do so; we’ll speak to them; and tonight I’ll force<br>
The wine peep through their scars. Come on, my queen,<br>
There’s sap in’t yet. The next time I do fight<br>
I’ll make Death love me, for I will contend<br>
Even with his pestilent scythe.
</p>

<p class="right">
[<i>Exeunt all but <span class="charname">Enobarbus</span>.</i>]
</p>

<p class="drama">
ENOBARBUS.<br>
Now he’ll outstare the lightning. To be furious<br>
Is to be frighted out of fear, and in that mood<br>
The dove will peck the estridge; and I see still<br>
A diminution in our captain’s brain<br>
Restores his heart. When valour preys on reason,<br>
It eats the sword it fights with. I will seek<br>
Some way to leave him.
</p>

<p class="right">
[<i>Exit.</i>]
</p>

