<h2> <a id="sceneII_33.1"></a><b>ACT II</b></h2>

<h3> <b>SCENE I. Athens. A room in a senator’s house</b></h3>

<p class="scenedesc">
Enter a <span class="charname">Senator</span> with papers.
</p>

<p class="drama">
SENATOR.<br>
And late five thousand. To Varro and to Isidore<br>
He owes nine thousand, besides my former sum,<br>
Which makes it five-and-twenty. Still in motion<br>
Of raging waste! It cannot hold; it will not.<br>
If I want gold, steal but a beggar’s dog<br>
And give it Timon, why, the dog coins gold.<br>
If I would sell my horse, and buy twenty more<br>
Better than he, why, give my horse to Timon—<br>
Ask nothing, give it him—it foals me straight,<br>
And able horses. No porter at his gate,<br>
But rather one that smiles and still invites<br>
All that pass by. It cannot hold; no reason<br>
Can sound his state in safety. Caphis, ho!<br>
Caphis, I say!
</p>

<p class="scenedesc">
Enter <span class="charname">Caphis</span>.
</p>

<p class="drama">
CAPHIS.<br>
Here, sir, what is your pleasure?
</p>

<p class="drama">
SENATOR.<br>
Get on your cloak and haste you to Lord Timon.<br>
Importune him for my moneys; be not ceased<br>
With slight denial, nor then silenced when<br>
“Commend me to your master”, and the cap<br>
Plays in the right hand, thus; but tell him,<br>
My uses cry to me, I must serve my turn<br>
Out of mine own, his days and times are past,<br>
And my reliances on his fracted dates<br>
Have smit my credit. I love and honour him,<br>
But must not break my back to heal his finger.<br>
Immediate are my needs, and my relief<br>
Must not be tossed and turned to me in words,<br>
But find supply immediate. Get you gone.<br>
Put on a most importunate aspect,<br>
A visage of demand, for I do fear<br>
When every feather sticks in his own wing,<br>
Lord Timon will be left a naked gull,<br>
Which flashes now a phoenix. Get you gone.
</p>

<p class="drama">
CAPHIS.<br>
I go, sir.
</p>

<p class="drama">
SENATOR.<br>
Take the bonds along with you,<br>
And have the dates in. Come.
</p>

<p class="drama">
CAPHIS.<br>
I will, sir.
</p>

<p class="drama">
SENATOR.<br>
Go.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneII_33.2"></a><b>SCENE II. The same. A hall in Timon’s house</b></h3>

<p class="scenedesc">
Enter <span class="charname">Flavius</span> with many bills in his hand.
</p>

<p class="drama">
FLAVIUS.<br>
No care, no stop, so senseless of expense,<br>
That he will neither know how to maintain it<br>
Nor cease his flow of riot. Takes no account<br>
How things go from him, nor resumes no care<br>
Of what is to continue. Never mind<br>
Was to be so unwise, to be so kind.<br>
What shall be done? He will not hear till feel.<br>
I must be round with him, now he comes from hunting.<br>
Fie, fie, fie, fie!
</p>

<p class="scenedesc">
Enter <span class="charname">Caphis</span> and the
<span class="charname">Servants</span> of <span class="charname">Isidore</span> and
<span class="charname">Varro</span>.
</p>

<p class="drama">
CAPHIS.<br>
Good even, Varro. What, you come for money?
</p>

<p class="drama">
VARRO’S SERVANT.<br>
Is’t not your business too?
</p>

<p class="drama">
CAPHIS.<br>
It is. And yours too, Isidore?
</p>

<p class="drama">
ISIDORE’S SERVANT.<br>
It is so.
</p>

<p class="drama">
CAPHIS.<br>
Would we were all discharged!
</p>

<p class="drama">
VARRO’S SERVANT.<br>
I fear it.
</p>

<p class="drama">
CAPHIS.<br>
Here comes the lord.
</p>

<p class="scenedesc">
Enter <span class="charname">Timon</span> and his train with
<span class="charname">Alcibiades</span>
</p>

<p class="drama">
TIMON.<br>
So soon as dinner’s done, we’ll forth again,<br>
My Alcibiades. With me? What is your will?
</p>

<p class="drama">
CAPHIS.<br>
My lord, here is a note of certain dues.
</p>

<p class="drama">
TIMON.<br>
Dues? Whence are you?
</p>

<p class="drama">
CAPHIS.<br>
Of Athens here, my lord.
</p>

<p class="drama">
TIMON.<br>
Go to my steward.
</p>

<p class="drama">
CAPHIS.<br>
Please it your lordship, he hath put me off<br>
To the succession of new days this month.<br>
My master is awaked by great occasion<br>
To call upon his own and humbly prays you<br>
That with your other noble parts you’ll suit<br>
In giving him his right.
</p>

<p class="drama">
TIMON.<br>
Mine honest friend,<br>
I prithee but repair to me next morning.
</p>

<p class="drama">
CAPHIS.<br>
Nay, good my lord—
</p>

<p class="drama">
TIMON.<br>
Contain thyself, good friend.
</p>

<p class="drama">
VARRO’S SERVANT.<br>
One Varro’s servant, my good lord—
</p>

<p class="drama">
ISIDORE’S SERVANT.<br>
From Isidore. He humbly prays your speedy payment.
</p>

<p class="drama">
CAPHIS.<br>
If you did know, my lord, my master’s wants—
</p>

<p class="drama">
VARRO’S SERVANT.<br>
’Twas due on forfeiture, my lord, six weeks and past.
</p>

<p class="drama">
ISIDORE’S SERVANT.<br>
Your steward puts me off, my lord, and I<br>
Am sent expressly to your lordship.
</p>

<p class="drama">
TIMON.<br>
Give me breath.<br>
I do beseech you, good my lords, keep on,<br>
I’ll wait upon you instantly.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Alcibiades</span> and Timon’s train.</i>]
</p>

<p class="drama">
[<i>To Flavius</i>.] Come hither. Pray you,<br>
How goes the world, that I am thus encountered<br>
With clamorous demands of debt, broken bonds,<br>
And the detention of long-since-due debts<br>
Against my honour?
</p>

<p class="drama">
FLAVIUS.<br>
Please you, gentlemen,<br>
The time is unagreeable to this business.<br>
Your importunacy cease till after dinner,<br>
That I may make his lordship understand<br>
Wherefore you are not paid.
</p>

<p class="drama">
TIMON.<br>
Do so, my friends.<br>
See them well entertained.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
FLAVIUS.<br>
Pray, draw near.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="scenedesc">
Enter <span class="charname">Apemantus</span> and
<span class="charname">Fool</span>.
</p>

<p class="drama">
CAPHIS.<br>
Stay, stay, here comes the fool with Apemantus.<br>
Let’s ha’ some sport with ’em.
</p>

<p class="drama">
VARRO’S SERVANT.<br>
Hang him, he’ll abuse us.
</p>

<p class="drama">
ISIDORE’S SERVANT.<br>
A plague upon him, dog!
</p>

<p class="drama">
VARRO’S SERVANT.<br>
How dost, fool?
</p>

<p class="drama">
APEMANTUS.<br>
Dost dialogue with thy shadow?
</p>

<p class="drama">
VARRO’S SERVANT.<br>
I speak not to thee.
</p>

<p class="drama">
APEMANTUS.<br>
No, ’tis to thyself.<br>
[<i>To the Fool</i>.] Come away.
</p>

<p class="drama">
ISIDORE’S SERVANT.<br>
[<i>To Varro’s servant</i>.] There’s the fool hangs on your back already.
</p>

<p class="drama">
APEMANTUS.<br>
No, thou stand’st single; thou’rt not on him yet.
</p>

<p class="drama">
CAPHIS.<br>
Where’s the fool now?
</p>

<p class="drama">
APEMANTUS.<br>
He last asked the question. Poor rogues and usurers’ men, bawds between gold
and want.
</p>

<p class="drama">
ALL SERVANTS.<br>
What are we, Apemantus?
</p>

<p class="drama">
APEMANTUS.<br>
Asses.
</p>

<p class="drama">
ALL SERVANTS.<br>
Why?
</p>

<p class="drama">
APEMANTUS.<br>
That you ask me what you are, and do not know yourselves. Speak to ’em,
fool.</p>

<p class="drama">
FOOL.<br>
How do you, gentlemen?
</p>

<p class="drama">
ALL SERVANTS.<br>
Gramercies, good fool. How does your mistress?
</p>

<p class="drama">
FOOL.<br>
She’s e’en setting on water to scald such chickens as you are. Would we could
see you at Corinth!
</p>

<p class="drama">
APEMANTUS.<br>
Good, gramercy.
</p>

<p class="scenedesc">
Enter <span class="charname">Page</span>.
</p>

<p class="drama">
FOOL.<br>
Look you, here comes my mistress’ page.
</p>

<p class="drama">
PAGE.<br>
[<i>To the Fool</i>.] Why, how now, captain? What do you in this wise company?
How dost thou, Apemantus?
</p>

<p class="drama">
APEMANTUS.<br>
Would I had a rod in my mouth, that I might answer thee profitably.</p>

<p class="drama">
PAGE.<br>
Prithee, Apemantus, read me the superscription of these letters. I know not
which is which.
</p>

<p class="drama">
APEMANTUS.<br>
Canst not read?
</p>

<p class="drama">
PAGE.<br>
No.
</p>

<p class="drama">
APEMANTUS.<br>
There will little learning die, then, that day thou art hanged. This is to Lord
Timon, this to Alcibiades. Go, thou wast born a bastard, and thou’lt die
a bawd.</p>

<p class="drama">
PAGE.<br>
Thou wast whelped a dog, and thou shalt famish a dog’s death. Answer not; I am
gone.
</p>

<p class="right">[<i>Exit <span class="charname">Page</span>.</i>]</p>

<p class="drama">
APEMANTUS.<br>
E’en so thou outrunn’st grace. Fool, I will go with you to Lord Timon’s.
</p>

<p class="drama">
FOOL.<br>
Will you leave me there?
</p>

<p class="drama">
APEMANTUS.<br>
If Timon stay at home.—You three serve three usurers?
</p>

<p class="drama">
ALL SERVANTS.<br>
Ay, would they served us!
</p>

<p class="drama">
APEMANTUS.<br>
So would I—as good a trick as ever hangman served thief.
</p>

<p class="drama">
FOOL.<br>
Are you three usurers’ men?
</p>

<p class="drama">
ALL SERVANTS.<br>
Ay, fool.
</p>

<p class="drama">
FOOL.<br>
I think no usurer but has a fool to his servant. My mistress is one, and I am
her fool. When men come to borrow of your masters, they approach sadly and go
away merry, but they enter my mistress’s house merrily and go away sadly. The
reason of this?
</p>

<p class="drama">
VARRO’S SERVANT.<br>
I could render one.
</p>

<p class="drama">
APEMANTUS.<br>
Do it then, that we may account thee a whoremaster and a knave, which
notwithstanding, thou shalt be no less esteemed.
</p>

<p class="drama">
VARRO’S SERVANT.<br>
What is a whoremaster, fool?
</p>

<p class="drama">
FOOL.<br>
A fool in good clothes, and something like thee. ’Tis a spirit; sometime ’t
appears like a lord, sometime like a lawyer, sometime like a philosopher, with
two stones more than’s artificial one. He is very often like a knight; and
generally, in all shapes that man goes up and down in from fourscore to
thirteen, this spirit walks in.
</p>

<p class="drama">
VARRO’S SERVANT.<br>
Thou art not altogether a fool.
</p>

<p class="drama">
FOOL.<br>
Nor thou altogether a wise man. As much foolery as I have, so much wit thou
lack’st.
</p>

<p class="drama">
APEMANTUS.<br>
That answer might have become Apemantus.
</p>

<p class="drama">
VARRO’S SERVANT.<br>
Aside, aside, here comes Lord Timon.
</p>

<p class="scenedesc">
Enter <span class="charname">Timon</span> and
<span class="charname">Flavius</span>.
</p>

<p class="drama">
APEMANTUS.<br>
Come with me, fool, come.
</p>

<p class="drama">
FOOL.<br>
I do not always follow lover, elder brother, and woman; sometime the
philosopher.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Apemantus</span> and
<span class="charname">Fool</span>.</i>]
</p>

<p class="drama">
FLAVIUS.<br>
Pray you walk near. I’ll speak with you anon.
</p>

<p class="right">[<i>Exeunt <span class="charname">Servants</span>.</i>]</p>

<p class="drama">
TIMON.<br>
You make me marvel wherefore ere this time<br>
Had you not fully laid my state before me,<br>
That I might so have rated my expense<br>
As I had leave of means.
</p>

<p class="drama">
FLAVIUS.<br>
You would not hear me,<br>
At many leisures I proposed.
</p>

<p class="drama">
TIMON.<br>
Go to.<br>
Perchance some single vantages you took<br>
When my indisposition put you back,<br>
And that unaptness made your minister<br>
Thus to excuse yourself.
</p>

<p class="drama">
FLAVIUS.<br>
O my good lord,<br>
At many times I brought in my accounts,<br>
Laid them before you; you would throw them off<br>
And say you found them in mine honesty.<br>
When for some trifling present you have bid me<br>
Return so much, I have shook my head and wept,<br>
Yea, ’gainst th’ authority of manners, prayed you<br>
To hold your hand more close. I did endure<br>
Not seldom nor no slight checks, when I have<br>
Prompted you in the ebb of your estate<br>
And your great flow of debts. My loved lord,<br>
Though you hear now, too late, yet now’s a time.<br>
The greatest of your having lacks a half<br>
To pay your present debts.
</p>

<p class="drama">
TIMON.<br>
Let all my land be sold.
</p>

<p class="drama">
FLAVIUS.<br>
’Tis all engaged, some forfeited and gone,<br>
And what remains will hardly stop the mouth<br>
Of present dues; the future comes apace.<br>
What shall defend the interim? And at length<br>
How goes our reckoning?
</p>

<p class="drama">
TIMON.<br>
To Lacedaemon did my land extend.
</p>

<p class="drama">
FLAVIUS.<br>
O my good lord, the world is but a word;<br>
Were it all yours to give it in a breath,<br>
How quickly were it gone!
</p>

<p class="drama">
TIMON.<br>
You tell me true.
</p>

<p class="drama">
FLAVIUS.<br>
If you suspect my husbandry or falsehood,<br>
Call me before th’ exactest auditors<br>
And set me on the proof. So the gods bless me,<br>
When all our offices have been oppressed<br>
With riotous feeders, when our vaults have wept<br>
With drunken spilth of wine, when every room<br>
Hath blazed with lights and brayed with minstrelsy,<br>
I have retired me to a wasteful cock<br>
And set mine eyes at flow.
</p>

<p class="drama">
TIMON.<br>
Prithee, no more.
</p>

<p class="drama">
FLAVIUS.<br>
Heavens, have I said, the bounty of this lord!<br>
How many prodigal bits have slaves and peasants<br>
This night englutted? Who is not Timon’s?<br>
What heart, head, sword, force, means, but is Lord Timon’s?<br>
Great Timon, noble, worthy, royal Timon!<br>
Ah, when the means are gone that buy this praise,<br>
The breath is gone whereof this praise is made.<br>
Feast-won, fast-lost; one cloud of winter showers,<br>
These flies are couched.
</p>

<p class="drama">
TIMON.<br>
Come, sermon me no further.<br>
No villainous bounty yet hath passed my heart;<br>
Unwisely, not ignobly, have I given.<br>
Why dost thou weep? Canst thou the conscience lack<br>
To think I shall lack friends? Secure thy heart.<br>
If I would broach the vessels of my love<br>
And try the argument of hearts by borrowing,<br>
Men and men’s fortunes could I frankly use<br>
As I can bid thee speak.
</p>

<p class="drama">
FLAVIUS.<br>
Assurance bless your thoughts!
</p>

<p class="drama">
TIMON.<br>
And in some sort these wants of mine are crowned,<br>
That I account them blessings. For by these<br>
Shall I try friends. You shall perceive how you<br>
Mistake my fortunes. I am wealthy in my friends.<br>
Within there! Flaminius! Servilius!
</p>

<p class="scenedesc">
Enter <span class="charname">Flaminius, Servilius</span> and a third
<span class="charname">Servant</span>.
</p>

<p class="drama">
SERVANTS.<br>
My lord, my lord.
</p>

<p class="drama">
TIMON.<br>
I will dispatch you severally. [<i>To Servilius</i>.] You to Lord Lucius;
[<i>To Flaminius</i>.] to Lord Lucullus you, I hunted with his honour today;
[<i>To the third Servant</i>.] you to Sempronius. Commend me to their loves;
and I am proud, say, that my occasions have found time to use ’em toward a
supply of money. Let the request be fifty talents.
</p>

<p class="drama">
FLAMINIUS.<br>
As you have said, my lord.
</p>

<p class="right">[<i>Exeunt <span class="charname">Servants</span>.</i>]</p>

<p class="drama">
FLAVIUS.<br>
[<i>Aside</i>.] Lord Lucius and Lucullus? Humh!
</p>

<p class="drama">
TIMON.<br>
Go you, sir, to the senators,<br>
Of whom, even to the state’s best health, I have<br>
Deserved this hearing, Bid ’em send o’ th’ instant<br>
A thousand talents to me.
</p>

<p class="drama">
FLAVIUS.<br>
I have been bold—<br>
For that I knew it the most general way—<br>
To them to use your signet and your name,<br>
But they do shake their heads, and I am here<br>
No richer in return.
</p>

<p class="drama">
TIMON.<br>
Is’t true? Can’t be?
</p>

<p class="drama">
FLAVIUS.<br>
They answer in a joint and corporate voice<br>
That now they are at fall, want treasure, cannot<br>
Do what they would, are sorry. You are honourable,<br>
But yet they could have wished—they know not—<br>
Something hath been amiss—a noble nature<br>
May catch a wrench—would all were well—’tis pity.<br>
And so, intending other serious matters,<br>
After distasteful looks and these hard fractions,<br>
With certain half-caps and cold-moving nods<br>
They froze me into silence.
</p>

<p class="drama">
TIMON.<br>
You gods, reward them!<br>
Prithee, man, look cheerly. These old fellows<br>
Have their ingratitude in them hereditary.<br>
Their blood is caked, ’tis cold, it seldom flows;<br>
’Tis lack of kindly warmth they are not kind;<br>
And nature, as it grows again toward earth,<br>
Is fashioned for the journey, dull and heavy.<br>
Go to Ventidius. Prithee, be not sad,<br>
Thou art true and honest, ingenuously I speak,<br>
No blame belongs to thee. Ventidius lately<br>
Buried his father, by whose death he’s stepped<br>
Into a great estate. When he was poor,<br>
Imprisoned and in scarcity of friends,<br>
I cleared him with five talents. Greet him from me,<br>
Bid him suppose some good necessity<br>
Touches his friend, which craves to be remembered<br>
With those five talents. That had, give’t these fellows<br>
To whom ’tis instant due. Ne’er speak, or think<br>
That Timon’s fortunes ’mong his friends can sink.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
FLAVIUS.<br>
I would I could not think it.<br>
That thought is bounty’s foe;<br>
Being free itself, it thinks all others so.
</p>

<p class="right">[<i>Exit.</i>]</p>

