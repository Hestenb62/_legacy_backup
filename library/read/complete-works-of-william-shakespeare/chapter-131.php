<h2> <a id="sceneIII_21.1"></a><b>ACT III</b></h2>

<h3> <b>SCENE I. A room in the prison.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Duke, Claudio</span> and
<span class="charname">Provost</span>.
</p>

<p class="drama">
DUKE.<br>
So then you hope of pardon from Lord Angelo?
</p>

<p class="drama">
CLAUDIO.<br>
The miserable have no other medicine<br>
But only hope.<br>
I have hope to live, and am prepared to die.
</p>

<p class="drama">
DUKE.<br>
Be absolute for death. Either death or life<br>
Shall thereby be the sweeter. Reason thus with life:<br>
If I do lose thee, I do lose a thing<br>
That none but fools would keep. A breath thou art,<br>
Servile to all the skyey influences<br>
That dost this habitation where thou keep’st<br>
Hourly afflict. Merely, thou art death’s fool;<br>
For him thou labour’st by thy flight to shun,<br>
And yet runn’st toward him still. Thou art not noble;<br>
For all th’ accommodations that thou bear’st<br>
Are nursed by baseness. Thou’rt by no means valiant;<br>
For thou dost fear the soft and tender fork<br>
Of a poor worm. Thy best of rest is sleep,<br>
And that thou oft provok’st, yet grossly fear’st<br>
Thy death, which is no more. Thou art not thyself;<br>
For thou exists on many a thousand grains<br>
That issue out of dust. Happy thou art not;<br>
For what thou hast not, still thou striv’st to get,<br>
And what thou hast, forget’st. Thou art not certain;<br>
For thy complexion shifts to strange effects<br>
After the moon. If thou art rich, thou’rt poor;<br>
For, like an ass whose back with ingots bows,<br>
Thou bear’st thy heavy riches but a journey,<br>
And death unloads thee. Friend hast thou none;<br>
For thine own bowels which do call thee sire,<br>
The mere effusion of thy proper loins,<br>
Do curse the gout, serpigo, and the rheum<br>
For ending thee no sooner. Thou hast nor youth nor age,<br>
But as it were an after-dinner’s sleep<br>
Dreaming on both; for all thy blessed youth<br>
Becomes as aged, and doth beg the alms<br>
Of palsied eld; and when thou art old and rich,<br>
Thou hast neither heat, affection, limb, nor beauty<br>
To make thy riches pleasant. What’s yet in this<br>
That bears the name of life? Yet in this life<br>
Lie hid more thousand deaths; yet death we fear,<br>
That makes these odds all even.
</p>

<p class="drama">
CLAUDIO.<br>
I humbly thank you.<br>
To sue to live, I find I seek to die,<br>
And seeking death, find life. Let it come on.
</p>

<p class="drama">
ISABELLA.<br>
[<i>Within</i>.] What ho! Peace here; grace and good company!
</p>

<p class="drama">
PROVOST.<br>
Who’s there? Come in. The wish deserves a welcome.
</p>

<p class="drama">
DUKE.<br>
Dear sir, ere long I’ll visit you again.
</p>

<p class="drama">
CLAUDIO.<br>
Most holy sir, I thank you.
</p>

<p class="scenedesc">
Enter <span class="charname">Isabella</span>.
</p>

<p class="drama">
ISABELLA.<br>
My business is a word or two with Claudio.
</p>

<p class="drama">
PROVOST.<br>
And very welcome. Look, signior, here’s your sister.
</p>

<p class="drama">
DUKE.<br>
Provost, a word with you.
</p>

<p class="drama">
PROVOST.<br>
As many as you please.
</p>

<p class="drama">
DUKE.<br>
Bring me to hear them speak, where I may be concealed.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Duke</span> and
<span class="charname">Provost</span>.</i>]
</p>

<p class="drama">
CLAUDIO.<br>
Now, sister, what’s the comfort?
</p>

<p class="drama">
ISABELLA.<br>
Why,<br>
As all comforts are, most good, most good indeed.<br>
Lord Angelo, having affairs to heaven,<br>
Intends you for his swift ambassador,<br>
Where you shall be an everlasting leiger.<br>
Therefore your best appointment make with speed;<br>
Tomorrow you set on.
</p>

<p class="drama">
CLAUDIO.<br>
Is there no remedy?
</p>

<p class="drama">
ISABELLA.<br>
None, but such remedy as, to save a head,<br>
To cleave a heart in twain.
</p>

<p class="drama">
CLAUDIO.<br>
But is there any?
</p>

<p class="drama">
ISABELLA.<br>
Yes, brother, you may live.<br>
There is a devilish mercy in the judge,<br>
If you’ll implore it, that will free your life,<br>
But fetter you till death.
</p>

<p class="drama">
CLAUDIO.<br>
Perpetual durance?
</p>

<p class="drama">
ISABELLA.<br>
Ay, just; perpetual durance; a restraint,<br>
Though all the world’s vastidity you had,<br>
To a determined scope.
</p>

<p class="drama">
CLAUDIO.<br>
But in what nature?
</p>

<p class="drama">
ISABELLA.<br>
In such a one as, you consenting to’t,<br>
Would bark your honour from that trunk you bear,<br>
And leave you naked.
</p>

<p class="drama">
CLAUDIO.<br>
Let me know the point.
</p>

<p class="drama">
ISABELLA.<br>
O, I do fear thee, Claudio, and I quake,<br>
Lest thou a feverous life shouldst entertain,<br>
And six or seven winters more respect<br>
Than a perpetual honour. Dar’st thou die?<br>
The sense of death is most in apprehension;<br>
And the poor beetle that we tread upon<br>
In corporal sufferance finds a pang as great<br>
As when a giant dies.
</p>

<p class="drama">
CLAUDIO.<br>
Why give you me this shame?<br>
Think you I can a resolution fetch<br>
From flowery tenderness? If I must die,<br>
I will encounter darkness as a bride<br>
And hug it in mine arms.
</p>

<p class="drama">
ISABELLA.<br>
There spake my brother! There my father’s grave<br>
Did utter forth a voice. Yes, thou must die.<br>
Thou art too noble to conserve a life<br>
In base appliances. This outward-sainted deputy,<br>
Whose settled visage and deliberate word<br>
Nips youth i’ th’ head, and follies doth enew<br>
As falcon doth the fowl, is yet a devil.<br>
His filth within being cast, he would appear<br>
A pond as deep as hell.
</p>

<p class="drama">
CLAUDIO.<br>
The precise Angelo?
</p>

<p class="drama">
ISABELLA.<br>
O, ’tis the cunning livery of hell<br>
The damned’st body to invest and cover<br>
In precise guards! Dost thou think, Claudio,<br>
If I would yield him my virginity<br>
Thou mightst be freed?
</p>

<p class="drama">
CLAUDIO.<br>
O heavens, it cannot be.
</p>

<p class="drama">
ISABELLA.<br>
Yes, he would give it thee, from this rank offence,<br>
So to offend him still. This night’s the time<br>
That I should do what I abhor to name,<br>
Or else thou diest tomorrow.
</p>

<p class="drama">
CLAUDIO.<br>
Thou shalt not do’t.
</p>

<p class="drama">
ISABELLA.<br>
O, were it but my life,<br>
I’d throw it down for your deliverance<br>
As frankly as a pin.
</p>

<p class="drama">
CLAUDIO.<br>
Thanks, dear Isabel.
</p>

<p class="drama">
ISABELLA.<br>
Be ready, Claudio, for your death tomorrow.
</p>

<p class="drama">
CLAUDIO.<br>
Yes. Has he affections in him<br>
That thus can make him bite the law by th’ nose<br>
When he would force it? Sure it is no sin;<br>
Or of the deadly seven it is the least.
</p>

<p class="drama">
ISABELLA.<br>
Which is the least?
</p>

<p class="drama">
CLAUDIO.<br>
If it were damnable, he being so wise,<br>
Why would he for the momentary trick<br>
Be perdurably fined? O Isabel!
</p>

<p class="drama">
ISABELLA.<br>
What says my brother?
</p>

<p class="drama">
CLAUDIO.<br>
Death is a fearful thing.
</p>

<p class="drama">
ISABELLA.<br>
And shamed life a hateful.
</p>

<p class="drama">
CLAUDIO.<br>
Ay, but to die, and go we know not where;<br>
To lie in cold obstruction, and to rot;<br>
This sensible warm motion to become<br>
A kneaded clod; and the delighted spirit<br>
To bathe in fiery floods, or to reside<br>
In thrilling regions of thick-ribbed ice;<br>
To be imprisoned in the viewless winds<br>
And blown with restless violence round about<br>
The pendent world; or to be worse than worst<br>
Of those that lawless and incertain thought<br>
Imagine howling—’tis too horrible.<br>
The weariest and most loathed worldly life<br>
That age, ache, penury, and imprisonment<br>
Can lay on nature is a paradise<br>
To what we fear of death.
</p>

<p class="drama">
ISABELLA.<br>
Alas, alas!
</p>

<p class="drama">
CLAUDIO.<br>
Sweet sister, let me live.<br>
What sin you do to save a brother’s life,<br>
Nature dispenses with the deed so far<br>
That it becomes a virtue.
</p>

<p class="drama">
ISABELLA.<br>
O, you beast!<br>
O faithless coward! O dishonest wretch!<br>
Wilt thou be made a man out of my vice?<br>
Is’t not a kind of incest to take life<br>
From thine own sister’s shame? What should I think?<br>
Heaven shield my mother played my father fair,<br>
For such a warped slip of wilderness<br>
Ne’er issued from his blood. Take my defiance,<br>
Die, perish! Might but my bending down<br>
Reprieve thee from thy fate, it should proceed.<br>
I’ll pray a thousand prayers for thy death,<br>
No word to save thee.
</p>

<p class="drama">
CLAUDIO.<br>
Nay, hear me, Isabel.
</p>

<p class="drama">
ISABELLA.<br>
O fie, fie, fie!<br>
Thy sin’s not accidental, but a trade.<br>
Mercy to thee would prove itself a bawd.<br>
’Tis best that thou diest quickly.
</p>

<p class="right">[<i>Going.</i>]</p>

<p class="drama">
CLAUDIO.<br>
O, hear me, Isabella.
</p>

<p class="scenedesc">
Enter <span class="charname">Duke</span> as a Friar.
</p>

<p class="drama">
DUKE.<br>
Vouchsafe a word, young sister, but one word.
</p>

<p class="drama">
ISABELLA.<br>
What is your will?
</p>

<p class="drama">
DUKE.<br>
Might you dispense with your leisure, I would by and by have some speech with
you. The satisfaction I would require is likewise your own benefit.</p>

<p class="drama">
ISABELLA.<br>
I have no superfluous leisure, my stay must be stolen out of other affairs, but
I will attend you a while.
</p>

<p class="drama">
DUKE.<br>
[<i>To Claudio aside</i>.] Son, I have overheard what hath passed between you
and your sister. Angelo had never the purpose to corrupt her; only he hath made
an assay of her virtue, to practise his judgement with the disposition of
natures. She, having the truth of honour in her, hath made him that gracious
denial which he is most glad to receive. I am confessor to Angelo, and I know
this to be true; therefore prepare yourself to death. Do not satisfy your
resolution with hopes that are fallible. Tomorrow you must die; go to your
knees and make ready.
</p>

<p class="drama">
CLAUDIO.<br>
Let me ask my sister pardon. I am so out of love with life that I will sue to
be rid of it.
</p>

<p class="drama">
DUKE.<br>
Hold you there. Farewell.
</p>

<p class="right">[<i>Exit <span class="charname">Claudio</span>.</i>]</p>

<p class="scenedesc">
Enter <span class="charname">Provost</span>.
</p>

<p class="drama">
Provost, a word with you.</p>

<p class="drama">
PROVOST.<br>
What’s your will, father?
</p>

<p class="drama">
DUKE.<br>
That, now you are come, you will be gone. Leave me a while with the maid; my
mind promises with my habit no loss shall touch her by my company.</p>

<p class="drama">
PROVOST.<br>
In good time.
</p>

<p class="right">[<i>Exit <span class="charname">Provost</span>.</i>]</p>

<p class="drama">
DUKE.<br>
The hand that hath made you fair hath made you good. The goodness that is cheap
in beauty makes beauty brief in goodness; but grace, being the soul of your
complexion, shall keep the body of it ever fair. The assault that Angelo hath
made to you, fortune hath conveyed to my understanding; and, but that frailty
hath examples for his falling, I should wonder at Angelo. How will you do to
content this substitute, and to save your brother?</p>

<p class="drama">
ISABELLA.<br>
I am now going to resolve him. I had rather my brother die by the law than my
son should be unlawfully born. But, O, how much is the good Duke deceived in
Angelo! If ever he return, and I can speak to him, I will open my lips in vain,
or discover his government.
</p>

<p class="drama">
DUKE.<br>
That shall not be much amiss. Yet, as the matter now stands, he will avoid your
accusation: he made trial of you only. Therefore fasten your ear on my
advisings, to the love I have in doing good, a remedy presents itself. I do make
myself believe that you may most uprighteously do a poor wronged lady a merited
benefit; redeem your brother from the angry law; do no stain to your own
gracious person; and much please the absent Duke, if peradventure he shall ever
return to have hearing of this business.</p>

<p class="drama">
ISABELLA.<br>
Let me hear you speak farther. I have spirit to do anything that appears not
foul in the truth of my spirit.
</p>

<p class="drama">
DUKE.<br>
Virtue is bold, and goodness never fearful. Have you not heard speak of
Mariana, the sister of Frederick, the great soldier who miscarried at sea?</p>

<p class="drama">
ISABELLA.<br>
I have heard of the lady, and good words went with her name.
</p>

<p class="drama">
DUKE.<br>
She should this Angelo have married, was affianced to her oath, and the nuptial
appointed. Between which time of the contract and limit of the solemnity, her
brother Frederick was wrecked at sea, having in that perished vessel the dowry
of his sister. But mark how heavily this befell to the poor gentlewoman. There
she lost a noble and renowned brother, in his love toward her ever most kind
and natural; with him, the portion and sinew of her fortune, her marriage
dowry; with both, her combinate husband, this well-seeming Angelo.
</p>

<p class="drama">
ISABELLA.<br>
Can this be so? Did Angelo so leave her?
</p>

<p class="drama">
DUKE.<br>
Left her in her tears, and dried not one of them with his comfort, swallowed
his vows whole, pretending in her discoveries of dishonour; in few,
bestowed her on her own lamentation, which she yet wears for his sake;
and he, a marble to her tears, is washed with them, but relents not.</p>

<p class="drama">
ISABELLA.<br>
What a merit were it in death to take this poor maid from the world! What
corruption in this life, that it will let this man live! But how out of this
can she avail?
</p>

<p class="drama">
DUKE.<br>
It is a rupture that you may easily heal, and the cure of it not only saves
your brother, but keeps you from dishonour in doing it.</p>

<p class="drama">
ISABELLA.<br>
Show me how, good father.
</p>

<p class="drama">
DUKE.<br>
This forenamed maid hath yet in her the continuance of her first affection. His
unjust unkindness, that in all reason should have quenched her love, hath, like
an impediment in the current, made it more violent and unruly. Go you to
Angelo; answer his requiring with a plausible obedience; agree with his demands
to the point. Only refer yourself to this advantage: first, that your
stay with him may not be long; that the time may have all shadow and silence in
it; and the place answer to convenience. This being granted in course, and now
follows all. We shall advise this wronged maid to stead up your appointment, go
in your place. If the encounter acknowledge itself hereafter, it may compel him
to her recompense; and here, by this, is your brother saved, your honour
untainted, the poor Mariana advantaged, and the corrupt deputy scaled. The maid
will I frame and make fit for his attempt. If you think well to carry this as
you may, the doubleness of the benefit defends the deceit from reproof. What
think you of it?</p>

<p class="drama">
ISABELLA.<br>
The image of it gives me content already, and I trust it will grow to a most
prosperous perfection.
</p>

<p class="drama">
DUKE.<br>
It lies much in your holding up. Haste you speedily to Angelo; if for this
night he entreat you to his bed, give him promise of satisfaction. I will
presently to Saint Luke’s; there at the moated grange resides this dejected
Mariana. At that place call upon me; and dispatch with Angelo, that it may be
quickly.
</p>

<p class="drama">
ISABELLA.<br>
I thank you for this comfort. Fare you well, good father.
</p>

<p class="right">[<i>Exit <span class="charname">Isabella</span>.</i>]</p>

<h3> <a id="sceneIII_21.2"></a><b>SCENE II. The street before the prison.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Elbow, Pompey</span> and Officers.
</p>

<p class="drama">
ELBOW.<br>
Nay, if there be no remedy for it, but that you will needs buy and sell men and
women like beasts, we shall have all the world drink brown and white
bastard.</p>

<p class="drama">
DUKE.<br>
O heavens, what stuff is here?
</p>

<p class="drama">
POMPEY.<br>
’Twas never merry world since, of two usuries, the merriest was put down,
and the worser allowed by order of law a furred gown to keep him warm; and
furred with fox on lambskins too, to signify that craft, being richer than
innocency, stands for the facing.
</p>

<p class="drama">
ELBOW.<br>
Come your way, sir.—Bless you, good father friar.
</p>

<p class="drama">
DUKE.<br>
And you, good brother father. What offence hath this man made you, sir?</p>

<p class="drama">
ELBOW.<br>
Marry, sir, he hath offended the law; and, sir, we take him to be a thief too,
sir; for we have found upon him, sir, a strange picklock, which we have sent to
the deputy.</p>

<p class="drama">
DUKE.<br>
Fie, sirrah, a bawd, a wicked bawd;<br>
The evil that thou causest to be done,<br>
That is thy means to live. Do thou but think<br>
What ’tis to cram a maw or clothe a back<br>
From such a filthy vice. Say to thyself,<br>
From their abominable and beastly touches<br>
I drink, I eat, array myself, and live.<br>
Canst thou believe thy living is a life,<br>
So stinkingly depending? Go mend, go mend.
</p>

<p class="drama">
POMPEY.<br>
Indeed, it does stink in some sort, sir. But yet, sir, I would prove—</p>

<p class="drama">
DUKE.<br>
Nay, if the devil have given thee proofs for sin,<br>
Thou wilt prove his. Take him to prison, officer.<br>
Correction and instruction must both work<br>
Ere this rude beast will profit.
</p>

<p class="drama">
ELBOW.<br>
He must before the deputy, sir; he has given him warning. The deputy cannot
abide a whoremaster. If he be a whoremonger and comes before him, he were as
good go a mile on his errand.
</p>

<p class="drama">
DUKE.<br>
That we were all, as some would seem to be,<br>
Free from our faults, as faults from seeming, free!
</p>

<p class="drama">
ELBOW.<br>
His neck will come to your waist—a cord, sir.
</p>

<p class="scenedesc">
Enter <span class="charname">Lucio</span>.
</p>

<p class="drama">
POMPEY.<br>
I spy comfort, I cry bail! Here’s a gentleman, and a friend of mine.</p>

<p class="drama">
LUCIO.<br>
How now, noble Pompey? What, at the wheels of Caesar? Art thou led in triumph?
What, is there none of Pygmalion’s images, newly made woman, to be had now, for
putting the hand in the pocket and extracting it clutched? What reply, ha? What
say’st thou to this tune, matter, and method? Is’t not drowned i’ th’ last
rain, ha? What say’st thou, trot? Is the world as it was, man? Which is the way?
Is it sad and few words? Or how? The trick of it?
</p>

<p class="drama">
DUKE.<br>
Still thus, and thus; still worse!
</p>

<p class="drama">
LUCIO.<br>
How doth my dear morsel, thy mistress? Procures she still, ha?
</p>

<p class="drama">
POMPEY.<br>
Troth, sir, she hath eaten up all her beef, and she is herself in the tub.</p>

<p class="drama">
LUCIO.<br>
Why, ’tis good. It is the right of it. It must be so. Ever your fresh
whore and your powdered bawd; an unshunned consequence; it must be so.
Art going to prison, Pompey?</p>

<p class="drama">
POMPEY.<br>
Yes, faith, sir.
</p>

<p class="drama">
LUCIO.<br>
Why, ’tis not amiss, Pompey. Farewell. Go, say I sent thee thither. For
debt, Pompey? Or how?</p>

<p class="drama">
ELBOW.<br>
For being a bawd, for being a bawd.
</p>

<p class="drama">
LUCIO.<br>
Well, then, imprison him. If imprisonment be the due of a bawd, why, ’tis
his right. Bawd is he doubtless, and of antiquity, too. Bawd born. Farewell,
good Pompey. Commend me to the prison, Pompey. You will turn good husband now,
Pompey; you will keep the house.</p>

<p class="drama">
POMPEY.<br>
I hope, sir, your good worship will be my bail.
</p>

<p class="drama">
LUCIO.<br>
No, indeed, will I not, Pompey; it is not the wear. I will pray, Pompey, to
increase your bondage. If you take it not patiently, why, your mettle is the
more. Adieu, trusty Pompey.—Bless you, friar.</p>

<p class="drama">
DUKE.<br>
And you.
</p>

<p class="drama">
LUCIO.<br>
Does Bridget paint still, Pompey, ha?
</p>

<p class="drama">
ELBOW.<br>
Come your ways, sir, come.
</p>

<p class="drama">
POMPEY.<br>
You will not bail me then, sir?
</p>

<p class="drama">
LUCIO.<br>
Then, Pompey, nor now.—What news abroad, friar? What news?
</p>

<p class="drama">
ELBOW.<br>
Come your ways, sir, come.
</p>

<p class="drama">
LUCIO.<br>
Go to kennel, Pompey, go.
</p>

<p class="right">[<i>Exeunt <span class="charname">Elbow, Pompey</span>
and Officers.</i>]</p>

<p class="drama">
What news, friar, of the Duke?</p>

<p class="drama">
DUKE.<br>
I know none. Can you tell me of any?
</p>

<p class="drama">
LUCIO.<br>
Some say he is with the Emperor of Russia; other some, he is in Rome. But where
is he, think you?
</p>

<p class="drama">
DUKE.<br>
I know not where, but wheresoever, I wish him well.
</p>

<p class="drama">
LUCIO.<br>
It was a mad fantastical trick of him to steal from the state and usurp the
beggary he was never born to. Lord Angelo dukes it well in his absence. He puts
transgression to’t.
</p>

<p class="drama">
DUKE.<br>
He does well in’t.
</p>

<p class="drama">
LUCIO.<br>
A little more lenity to lechery would do no harm in him. Something too crabbed
that way, friar.</p>

<p class="drama">
DUKE.<br>
It is too general a vice, and severity must cure it.
</p>

<p class="drama">
LUCIO.<br>
Yes, in good sooth, the vice is of a great kindred; it is well allied; but it
is impossible to extirp it quite, friar, till eating and drinking be put down.
They say this Angelo was not made by man and woman after this downright way of
creation. Is it true, think you?</p>

<p class="drama">
DUKE.<br>
How should he be made, then?
</p>

<p class="drama">
LUCIO.<br>
Some report a sea-maid spawned him; some, that he was begot between two
stockfishes. But it is certain that when he makes water, his urine is
congealed ice; that I know to be true. And he is a motion ungenerative;
that’s infallible.</p>

<p class="drama">
DUKE.<br>
You are pleasant, sir, and speak apace.
</p>

<p class="drama">
LUCIO.<br>
Why, what a ruthless thing is this in him, for the rebellion of a codpiece to
take away the life of a man! Would the Duke that is absent have done this? Ere
he would have hanged a man for the getting a hundred bastards, he would have
paid for the nursing a thousand. He had some feeling of the sport; he knew the
service, and that instructed him to mercy.</p>

<p class="drama">
DUKE.<br>
I never heard the absent Duke much detected for women; he was not inclined that
way.</p>

<p class="drama">
LUCIO.<br>
O, sir, you are deceived.
</p>

<p class="drama">
DUKE.<br>
’Tis not possible.
</p>

<p class="drama">
LUCIO.<br>
Who, not the Duke? Yes, your beggar of fifty; and his use was to put a ducat in
her clack-dish. The Duke had crotchets in him. He would be drunk too, that let
me inform you.
</p>

<p class="drama">
DUKE.<br>
You do him wrong, surely.
</p>

<p class="drama">
LUCIO.<br>
Sir, I was an inward of his. A shy fellow was the Duke; and I believe I know
the cause of his withdrawing.</p>

<p class="drama">
DUKE.<br>
What, I prithee, might be the cause?
</p>

<p class="drama">
LUCIO.<br>
No, pardon. ’Tis a secret must be locked within the teeth and the lips. But
this I can let you understand: the greater file of the subject held the Duke to
be wise.
</p>

<p class="drama">
DUKE.<br>
Wise? Why, no question but he was.
</p>

<p class="drama">
LUCIO.<br>
A very superficial, ignorant, unweighing fellow.
</p>

<p class="drama">
DUKE.<br>
Either this is envy in you, folly, or mistaking. The very stream of his life,
and the business he hath helmed, must upon a warranted need give him a better
proclamation. Let him be but testimonied in his own bringings-forth, and he
shall appear to the envious a scholar, a statesman, and a soldier. Therefore
you speak unskilfully. Or, if your knowledge be more, it is much darkened in
your malice.</p>

<p class="drama">
LUCIO.<br>
Sir, I know him, and I love him.
</p>

<p class="drama">
DUKE.<br>
Love talks with better knowledge, and knowledge with dearer love.
</p>

<p class="drama">
LUCIO.<br>
Come, sir, I know what I know.
</p>

<p class="drama">
DUKE.<br>
I can hardly believe that, since you know not what you speak. But, if ever the
Duke return, as our prayers are he may, let me desire you to make your answer
before him. If it be honest you have spoke, you have courage to maintain it. I
am bound to call upon you, and I pray you your name?
</p>

<p class="drama">
LUCIO.<br>
Sir, my name is Lucio, well known to the Duke.
</p>

<p class="drama">
DUKE.<br>
He shall know you better, sir, if I may live to report you.
</p>

<p class="drama">
LUCIO.<br>
I fear you not.
</p>

<p class="drama">
DUKE.<br>
O, you hope the Duke will return no more; or you imagine me too unhurtful an
opposite. But indeed, I can do you little harm. You’ll forswear this again.
</p>

<p class="drama">
LUCIO.<br>
I’ll be hanged first! Thou art deceived in me, friar. But no more of
this. Canst thou tell if Claudio die tomorrow or no?</p>

<p class="drama">
DUKE.<br>
Why should he die, sir?
</p>

<p class="drama">
LUCIO.<br>
Why? For filling a bottle with a tun-dish. I would the Duke we talk of were
returned again. This ungenitured agent will unpeople the province with
continency. Sparrows must not build in his house-eaves because they are
lecherous. The Duke yet would have dark deeds darkly answered. He would never
bring them to light. Would he were returned! Marry, this Claudio is condemned
for untrussing. Farewell, good friar, I prithee pray for me. The Duke, I say to
thee again, would eat mutton on Fridays. He’s now past it; yet, and, I say to
thee, he would mouth with a beggar though she smelt brown bread and garlic. Say
that I said so. Farewell.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
DUKE.<br>
No might nor greatness in mortality<br>
Can censure ’scape. Back-wounding calumny<br>
The whitest virtue strikes. What king so strong<br>
Can tie the gall up in the slanderous tongue?<br>
But who comes here?
</p>

<p class="scenedesc">
Enter <span class="charname">Escalus, Provost</span> and Officers with
<span class="charname">Mistress Overdone</span>, a Bawd.
</p>

<p class="drama">
ESCALUS.<br>
Go, away with her to prison.
</p>

<p class="drama">
BAWD.<br>
Good my lord, be good to me. Your honour is accounted a merciful man, good my
lord.</p>

<p class="drama">
ESCALUS.<br>
Double and treble admonition, and still forfeit in the same kind? This would
make mercy swear and play the tyrant.
</p>

<p class="drama">
PROVOST.<br>
A bawd of eleven years’ continuance, may it please your honour.
</p>

<p class="drama">
BAWD.<br>
My lord, this is one Lucio’s information against me. Mistress Kate
Keepdown was with child by him in the Duke’s time; he promised her
marriage. His child is a year and a quarter old come Philip and Jacob. I have
kept it myself; and see how he goes about to abuse me.</p>

<p class="drama">
ESCALUS.<br>
That fellow is a fellow of much license. Let him be called before
us. Away with her to prison. Go to, no more words.</p>

<p class="right">[<i>Exeunt Officers with <span class="charname">Bawd</span>.</i>]</p>

<p class="drama">
Provost, my brother Angelo will not be altered; Claudio must die tomorrow.
Let him be furnished with divines, and have all charitable preparation. If my
brother wrought by my pity, it should not be so with him.
</p>

<p class="drama">
PROVOST.<br>
So please you, this friar hath been with him, and advised him for th’
entertainment of death.
</p>

<p class="drama">
ESCALUS.<br>
Good even, good father.
</p>

<p class="drama">
DUKE.<br>
Bliss and goodness on you!
</p>

<p class="drama">
ESCALUS.<br>
Of whence are you?
</p>

<p class="drama">
DUKE.<br>
Not of this country, though my chance is now<br>
To use it for my time. I am a brother<br>
Of gracious order, late come from the See<br>
In special business from his Holiness.
</p>

<p class="drama">
ESCALUS.<br>
What news abroad i’ th’ world?
</p>

<p class="drama">
DUKE.<br>
None, but that there is so great a fever on goodness that the dissolution of
it must cure it. Novelty is only in request, and as it is as dangerous to be
aged in any kind of course as it is virtuous to be constant in any undertaking.
There is scarce truth enough alive to make societies secure; but security
enough to make fellowships accursed. Much upon this riddle runs the wisdom of
the world. This news is old enough, yet it is every day’s news. I pray
you, sir, of what disposition was the Duke?
</p>

<p class="drama">
ESCALUS.<br>
One that, above all other strifes, contended especially to know himself.</p>

<p class="drama">
DUKE.<br>
What pleasure was he given to?
</p>

<p class="drama">
ESCALUS.<br>
Rather rejoicing to see another merry, than merry at anything which professed
to make him rejoice. A gentleman of all temperance. But leave we him to his
events, with a prayer they may prove prosperous, and let me desire to know how
you find Claudio prepared. I am made to understand that you have lent him
visitation.</p>

<p class="drama">
DUKE.<br>
He professes to have received no sinister measure from his judge, but most
willingly humbles himself to the determination of justice. Yet had he framed to
himself, by the instruction of his frailty, many deceiving promises of life,
which I, by my good leisure, have discredited to him, and now he is resolved to
die.</p>

<p class="drama">
ESCALUS.<br>
You have paid the heavens your function, and the prisoner the very debt of your
calling. I have laboured for the poor gentleman to the extremest shore of my
modesty, but my brother justice have I found so severe that he hath forced me
to tell him he is indeed Justice.
</p>

<p class="drama">
DUKE.<br>
If his own life answer the straitness of his proceeding, it shall become him
well; wherein if he chance to fail, he hath sentenced himself.
</p>

<p class="drama">
ESCALUS.<br>
I am going to visit the prisoner. Fare you well.
</p>

<p class="drama">
DUKE.<br>
Peace be with you.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Escalus</span> and
<span class="charname">Provost</span>.</i>]
</p>

<p class="drama">
He who the sword of heaven will bear<br>
Should be as holy as severe,<br>
Pattern in himself to know,<br>
Grace to stand, and virtue go;<br>
More nor less to others paying<br>
Than by self-offences weighing.<br>
Shame to him whose cruel striking<br>
Kills for faults of his own liking!<br>
Twice treble shame on Angelo,<br>
To weed my vice, and let his grow!<br>
O, what may man within him hide,<br>
Though angel on the outward side!<br>
How may likeness, made in crimes,<br>
Make practice on the times,<br>
To draw with idle spiders’ strings<br>
Most ponderous and substantial things!<br>
Craft against vice I must apply.<br>
With Angelo tonight shall lie<br>
His old betrothed but despised.<br>
So disguise shall, by th’ disguised,<br>
Pay with falsehood false exacting,<br>
And perform an old contracting.
</p>

<p class="right">[<i>Exit.</i>]</p>

