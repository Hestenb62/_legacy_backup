<h2> <a id="sceneV_17.1"></a><b>ACT V</b></h2>

<h3> <b>SCENE I. The plains of Philippi.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Octavius, Antony</span> and their Army.
</p>

<p class="drama">
OCTAVIUS.<br>
Now, Antony, our hopes are answered.<br>
You said the enemy would not come down,<br>
But keep the hills and upper regions.<br>
It proves not so; their battles are at hand,<br>
They mean to warn us at Philippi here,<br>
Answering before we do demand of them.
</p>

<p class="drama">
ANTONY.<br>
Tut, I am in their bosoms, and I know<br>
Wherefore they do it. They could be content<br>
To visit other places, and come down<br>
With fearful bravery, thinking by this face<br>
To fasten in our thoughts that they have courage;<br>
But ’tis not so.
</p>

<p class="scenedesc">
Enter a <span class="charname">Messenger</span>.
</p>

<p class="drama">
MESSENGER.<br>
Prepare you, generals.<br>
The enemy comes on in gallant show;<br>
Their bloody sign of battle is hung out,<br>
And something to be done immediately.
</p>

<p class="drama">
ANTONY.<br>
Octavius, lead your battle softly on<br>
Upon the left hand of the even field.
</p>

<p class="drama">
OCTAVIUS.<br>
Upon the right hand I. Keep thou the left.
</p>

<p class="drama">
ANTONY.<br>
Why do you cross me in this exigent?
</p>

<p class="drama">
OCTAVIUS.<br>
I do not cross you; but I will do so.
</p>

<p class="right">
[<i>March.</i>]
</p>

<p class="scenedesc">
Drum. Enter <span class="charname">Brutus, Cassius</span> and their Army; <span class="charname">Lucilius, Titinius, Messala</span> and others.
</p>

<p class="drama">
BRUTUS.<br>
They stand, and would have parley.
</p>

<p class="drama">
CASSIUS.<br>
Stand fast, Titinius; we must out and talk.
</p>

<p class="drama">
OCTAVIUS.<br>
Mark Antony, shall we give sign of battle?
</p>

<p class="drama">
ANTONY.<br>
No, Caesar, we will answer on their charge.<br>
Make forth; the generals would have some words.
</p>

<p class="drama">
OCTAVIUS.<br>
Stir not until the signal.
</p>

<p class="drama">
BRUTUS.<br>
Words before blows: is it so, countrymen?
</p>

<p class="drama">
OCTAVIUS.<br>
Not that we love words better, as you do.
</p>

<p class="drama">
BRUTUS.<br>
Good words are better than bad strokes, Octavius.
</p>

<p class="drama">
ANTONY.<br>
In your bad strokes, Brutus, you give good words;<br>
Witness the hole you made in Caesar’s heart,<br>
Crying, “Long live! Hail, Caesar!”
</p>

<p class="drama">
CASSIUS.<br>
Antony,<br>
The posture of your blows are yet unknown;<br>
But for your words, they rob the Hybla bees,<br>
And leave them honeyless.
</p>

<p class="drama">
ANTONY.<br>
Not stingless too.
</p>

<p class="drama">
BRUTUS.<br>
O yes, and soundless too,<br>
For you have stol’n their buzzing, Antony,<br>
And very wisely threat before you sting.
</p>

<p class="drama">
ANTONY.<br>
Villains, you did not so when your vile daggers<br>
Hack’d one another in the sides of Caesar:<br>
You show’d your teeth like apes, and fawn’d like hounds,<br>
And bow’d like bondmen, kissing Caesar’s feet;<br>
Whilst damned Casca, like a cur, behind<br>
Struck Caesar on the neck. O you flatterers!
</p>

<p class="drama">
CASSIUS.<br>
Flatterers! Now, Brutus, thank yourself.<br>
This tongue had not offended so today,<br>
If Cassius might have rul’d.
</p>

<p class="drama">
OCTAVIUS.<br>
Come, come, the cause. If arguing makes us sweat,<br>
The proof of it will turn to redder drops.<br>
Look, I draw a sword against conspirators.<br>
When think you that the sword goes up again?<br>
Never, till Caesar’s three and thirty wounds<br>
Be well aveng’d; or till another Caesar<br>
Have added slaughter to the sword of traitors.
</p>

<p class="drama">
BRUTUS.<br>
Caesar, thou canst not die by traitors’ hands,<br>
Unless thou bring’st them with thee.
</p>

<p class="drama">
OCTAVIUS.<br>
So I hope.<br>
I was not born to die on Brutus’ sword.
</p>

<p class="drama">
BRUTUS.<br>
O, if thou wert the noblest of thy strain,<br>
Young man, thou couldst not die more honourable.
</p>

<p class="drama">
CASSIUS.<br>
A peevish school-boy, worthless of such honour,<br>
Join’d with a masker and a reveller.
</p>

<p class="drama">
ANTONY.<br>
Old Cassius still!
</p>

<p class="drama">
OCTAVIUS.<br>
Come, Antony; away!<br>
Defiance, traitors, hurl we in your teeth.<br>
If you dare fight today, come to the field;<br>
If not, when you have stomachs.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Octavius, Antony</span> and their Army.</i>]
</p>

<p class="drama">
CASSIUS.<br>
Why now, blow wind, swell billow, and swim bark!<br>
The storm is up, and all is on the hazard.
</p>

<p class="drama">
BRUTUS.<br>
Ho, Lucilius! Hark, a word with you.
</p>

<p class="drama">
LUCILIUS.<br>
My lord?
</p>

<p class="right">
[<i><span class="charname">Brutus</span> and <span class="charname">Lucilius</span> talk apart.</i>]
</p>

<p class="drama">
CASSIUS.<br>
Messala.
</p>

<p class="drama">
MESSALA.<br>
What says my General?
</p>

<p class="drama">
CASSIUS.<br>
Messala,<br>
This is my birth-day; as this very day<br>
Was Cassius born. Give me thy hand, Messala:<br>
Be thou my witness that against my will<br>
As Pompey was, am I compell’d to set<br>
Upon one battle all our liberties.<br>
You know that I held Epicurus strong,<br>
And his opinion. Now I change my mind,<br>
And partly credit things that do presage.<br>
Coming from Sardis, on our former ensign<br>
Two mighty eagles fell, and there they perch’d,<br>
Gorging and feeding from our soldiers’ hands,<br>
Who to Philippi here consorted us.<br>
This morning are they fled away and gone,<br>
And in their steads do ravens, crows, and kites<br>
Fly o’er our heads, and downward look on us,<br>
As we were sickly prey: their shadows seem<br>
A canopy most fatal, under which<br>
Our army lies, ready to give up the ghost.
</p>

<p class="drama">
MESSALA.<br>
Believe not so.
</p>

<p class="drama">
CASSIUS.<br>
I but believe it partly,<br>
For I am fresh of spirit, and resolv’d<br>
To meet all perils very constantly.
</p>

<p class="drama">
BRUTUS.<br>
Even so, Lucilius.
</p>

<p class="drama">
CASSIUS.<br>
Now, most noble Brutus,<br>
The gods today stand friendly, that we may,<br>
Lovers in peace, lead on our days to age!<br>
But, since the affairs of men rest still incertain,<br>
Let’s reason with the worst that may befall.<br>
If we do lose this battle, then is this<br>
The very last time we shall speak together:<br>
What are you then determined to do?
</p>

<p class="drama">
BRUTUS.<br>
Even by the rule of that philosophy<br>
By which I did blame Cato for the death<br>
Which he did give himself, I know not how,<br>
But I do find it cowardly and vile,<br>
For fear of what might fall, so to prevent<br>
The time of life, arming myself with patience<br>
To stay the providence of some high powers<br>
That govern us below.
</p>

<p class="drama">
CASSIUS.<br>
Then, if we lose this battle,<br>
You are contented to be led in triumph<br>
Thorough the streets of Rome?
</p>

<p class="drama">
BRUTUS.<br>
No, Cassius, no: think not, thou noble Roman,<br>
That ever Brutus will go bound to Rome;<br>
He bears too great a mind. But this same day<br>
Must end that work the Ides of March begun;<br>
And whether we shall meet again I know not.<br>
Therefore our everlasting farewell take.<br>
For ever, and for ever, farewell, Cassius.<br>
If we do meet again, why, we shall smile;<br>
If not, why then this parting was well made.
</p>

<p class="drama">
CASSIUS.<br>
For ever and for ever farewell, Brutus.<br>
If we do meet again, we’ll smile indeed;<br>
If not, ’tis true this parting was well made.
</p>

<p class="drama">
BRUTUS.<br>
Why then, lead on. O, that a man might know<br>
The end of this day’s business ere it come!<br>
But it sufficeth that the day will end,<br>
And then the end is known. Come, ho! away!
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneV_17.2"></a><b>SCENE II. The same. The field of
battle.</b></h3>

<p class="scenedesc">
Alarum. Enter <span class="charname">Brutus</span> and <span class="charname">Messala</span>.
</p>

<p class="drama">
BRUTUS.<br>
Ride, ride, Messala, ride, and give these bills<br>
Unto the legions on the other side.
</p>

<p class="right">
[<i>Loud alarum.</i>]
</p>

<p class="drama">
Let them set on at once; for I perceive<br>
But cold demeanor in Octavius’ wing,<br>
And sudden push gives them the overthrow.<br>
Ride, ride, Messala; let them all come down.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneV_17.3"></a><b>SCENE III. Another part of the field.</b></h3>

<p class="scenedesc">
Alarum. Enter <span class="charname">Cassius</span> and <span class="charname">Titinius</span>.
</p>

<p class="drama">
CASSIUS.<br>
O, look, Titinius, look, the villains fly!<br>
Myself have to mine own turn’d enemy:<br>
This ensign here of mine was turning back;<br>
I slew the coward, and did take it from him.
</p>

<p class="drama">
TITINIUS.<br>
O Cassius, Brutus gave the word too early,<br>
Who, having some advantage on Octavius,<br>
Took it too eagerly: his soldiers fell to spoil,<br>
Whilst we by Antony are all enclos’d.
</p>

<p class="scenedesc">
Enter <span class="charname">Pindarus</span>.
</p>

<p class="drama">
PINDARUS.<br>
Fly further off, my lord, fly further off;<br>
Mark Antony is in your tents, my lord.<br>
Fly, therefore, noble Cassius, fly far off.
</p>

<p class="drama">
CASSIUS.<br>
This hill is far enough. Look, look, Titinius;<br>
Are those my tents where I perceive the fire?
</p>

<p class="drama">
TITINIUS.<br>
They are, my lord.
</p>

<p class="drama">
CASSIUS.<br>
Titinius, if thou lovest me,<br>
Mount thou my horse and hide thy spurs in him,<br>
Till he have brought thee up to yonder troops<br>
And here again, that I may rest assur’d<br>
Whether yond troops are friend or enemy.
</p>

<p class="drama">
TITINIUS.<br>
I will be here again, even with a thought.
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="drama">
CASSIUS.<br>
Go, Pindarus, get higher on that hill,<br>
My sight was ever thick. Regard Titinius,<br>
And tell me what thou notest about the field.
</p>

<p class="right">
[<i><span class="charname">Pindarus</span> goes up.</i>]
</p>

<p class="drama">
This day I breathed first. Time is come round,<br>
And where I did begin, there shall I end.<br>
My life is run his compass. Sirrah, what news?
</p>

<p class="drama">
PINDARUS.<br>
[<i>Above.</i>] O my lord!
</p>

<p class="drama">
CASSIUS.<br>
What news?
</p>

<p class="drama">
PINDARUS.<br>
[<i>Above.</i>] Titinius is enclosed round about<br>
With horsemen, that make to him on the spur,<br>
Yet he spurs on. Now they are almost on him.<br>
Now, Titinius! Now some light. O, he lights too.<br>
He’s ta’en!
</p>

<p class="right">
[<i>Shout.</i>]
</p>

<p class="drama">
And, hark! they shout for joy.
</p>

<p class="drama">
CASSIUS.<br>
Come down; behold no more.<br>
O, coward that I am, to live so long,<br>
To see my best friend ta’en before my face!
</p>

<p class="right">
[<i><span class="charname">Pindarus</span> descends.</i>]
</p>

<p class="drama">
Come hither, sirrah.<br>
In Parthia did I take thee prisoner;<br>
And then I swore thee, saving of thy life,<br>
That whatsoever I did bid thee do,<br>
Thou shouldst attempt it. Come now, keep thine oath.<br>
Now be a freeman; and with this good sword,<br>
That ran through Caesar’s bowels, search this bosom.<br>
Stand not to answer. Here, take thou the hilts;<br>
And when my face is cover’d, as ’tis now,<br>
Guide thou the sword.—Caesar, thou art reveng’d,<br>
Even with the sword that kill’d thee.
</p>

<p class="right">
[<i>Dies.</i>]
</p>

<p class="drama">
PINDARUS.<br>
So, I am free, yet would not so have been,<br>
Durst I have done my will. O Cassius!<br>
Far from this country Pindarus shall run,<br>
Where never Roman shall take note of him.
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="scenedesc">
Enter <span class="charname">Titinius</span> with <span class="charname">Messala</span>.
</p>

<p class="drama">
MESSALA.<br>
It is but change, Titinius; for Octavius<br>
Is overthrown by noble Brutus’ power,<br>
As Cassius’ legions are by Antony.
</p>

<p class="drama">
TITINIUS.<br>
These tidings would well comfort Cassius.
</p>

<p class="drama">
MESSALA.<br>
Where did you leave him?
</p>

<p class="drama">
TITINIUS.<br>
All disconsolate,<br>
With Pindarus his bondman, on this hill.
</p>

<p class="drama">
MESSALA.<br>
Is not that he that lies upon the ground?
</p>

<p class="drama">
TITINIUS.<br>
He lies not like the living. O my heart!
</p>

<p class="drama">
MESSALA.<br>
Is not that he?
</p>

<p class="drama">
TITINIUS.<br>
No, this was he, Messala,<br>
But Cassius is no more. O setting sun,<br>
As in thy red rays thou dost sink to night,<br>
So in his red blood Cassius’ day is set.<br>
The sun of Rome is set. Our day is gone;<br>
Clouds, dews, and dangers come; our deeds are done.<br>
Mistrust of my success hath done this deed.
</p>

<p class="drama">
MESSALA.<br>
Mistrust of good success hath done this deed.<br>
O hateful Error, Melancholy’s child!<br>
Why dost thou show to the apt thoughts of men<br>
The things that are not? O Error, soon conceiv’d,<br>
Thou never com’st unto a happy birth,<br>
But kill’st the mother that engender’d thee!
</p>

<p class="drama">
TITINIUS.<br>
What, Pindarus! where art thou, Pindarus?
</p>

<p class="drama">
MESSALA.<br>
Seek him, Titinius, whilst I go to meet<br>
The noble Brutus, thrusting this report<br>
Into his ears. I may say thrusting it;<br>
For piercing steel and darts envenomed<br>
Shall be as welcome to the ears of Brutus<br>
As tidings of this sight.
</p>

<p class="drama">
TITINIUS.<br>
Hie you, Messala,<br>
And I will seek for Pindarus the while.
</p>

<p class="right">
[<i>Exit <span class="charname">Messala</span>.</i>]
</p>

<p class="drama">
Why didst thou send me forth, brave Cassius?<br>
Did I not meet thy friends? And did not they<br>
Put on my brows this wreath of victory,<br>
And bid me give it thee? Didst thou not hear their shouts?<br>
Alas, thou hast misconstrued everything!<br>
But, hold thee, take this garland on thy brow;<br>
Thy Brutus bid me give it thee, and I<br>
Will do his bidding. Brutus, come apace,<br>
And see how I regarded Caius Cassius.<br>
By your leave, gods. This is a Roman’s part.<br>
Come, Cassius’ sword, and find Titinius’ heart.
</p>

<p class="right">
[<i>Dies.</i>]
</p>

<p class="scenedesc">
Alarum. Enter <span class="charname">Brutus, Messala, young Cato, Strato,
Volumnius</span> and <span class="charname">Lucilius</span>.
</p>

<p class="drama">
BRUTUS.<br>
Where, where, Messala, doth his body lie?
</p>

<p class="drama">
MESSALA.<br>
Lo, yonder, and Titinius mourning it.
</p>

<p class="drama">
BRUTUS.<br>
Titinius’ face is upward.
</p>

<p class="drama">
CATO.<br>
He is slain.
</p>

<p class="drama">
BRUTUS.<br>
O Julius Caesar, thou art mighty yet!<br>
Thy spirit walks abroad, and turns our swords<br>
In our own proper entrails.
</p>

<p class="right">
[<i>Low alarums.</i>]
</p>

<p class="drama">
CATO.<br>
Brave Titinius!<br>
Look whether he have not crown’d dead Cassius!
</p>

<p class="drama">
BRUTUS.<br>
Are yet two Romans living such as these?<br>
The last of all the Romans, fare thee well!<br>
It is impossible that ever Rome<br>
Should breed thy fellow. Friends, I owe more tears<br>
To this dead man than you shall see me pay.<br>
I shall find time, Cassius, I shall find time.<br>
Come therefore, and to Thassos send his body.<br>
His funerals shall not be in our camp,<br>
Lest it discomfort us. Lucilius, come;<br>
And come, young Cato; let us to the field.<br>
Labeo and Flavius, set our battles on.<br>
’Tis three o’clock; and Romans, yet ere night<br>
We shall try fortune in a second fight.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneV_17.4"></a><b>SCENE IV. Another part of the field.</b></h3>

<p class="scenedesc">
Alarum. Enter fighting soldiers of both armies; then <span class="charname">Brutus, Messala, young Cato, Lucilius, Flavius</span> and
others.
</p>

<p class="drama">
BRUTUS.<br>
Yet, countrymen, O, yet hold up your heads!
</p>

<p class="drama">
CATO.<br>
What bastard doth not? Who will go with me?<br>
I will proclaim my name about the field.<br>
I am the son of Marcus Cato, ho!<br>
A foe to tyrants, and my country’s friend.<br>
I am the son of Marcus Cato, ho!
</p>

<p class="right">
[<i>Charges the enemy.</i>]
</p>

<p class="drama">
LUCILIUS.<br>
And I am Brutus, Marcus Brutus, I;<br>
Brutus, my country’s friend; know me for Brutus!
</p>

<p class="right">
[<i>Exit, charging the enemy. <span class="charname">Cato</span> is
overpowered, and falls.</i>]
</p>

<p class="drama">
LUCILIUS.<br>
O young and noble Cato, art thou down?<br>
Why, now thou diest as bravely as Titinius,<br>
And mayst be honour’d, being Cato’s son.
</p>

<p class="drama">
FIRST SOLDIER.<br>
Yield, or thou diest.
</p>

<p class="drama">
LUCILIUS.<br>
Only I yield to die:<br>
There is so much that thou wilt kill me straight;
</p>

<p class="right">
[<i>Offering money</i>]
</p>

<p class="drama">
Kill Brutus, and be honour’d in his death.
</p>

<p class="drama">
FIRST SOLDIER.<br>
We must not. A noble prisoner!
</p>

<p class="drama">
SECOND SOLDIER.<br>
Room, ho! Tell Antony, Brutus is ta’en.
</p>

<p class="drama">
FIRST SOLDIER.<br>
I’ll tell the news. Here comes the General.
</p>

<p class="scenedesc">
Enter <span class="charname">Antony</span>.
</p>

<p class="drama">
Brutus is ta’en, Brutus is ta’en, my lord.
</p>

<p class="drama">
ANTONY.<br>
Where is he?
</p>

<p class="drama">
LUCILIUS.<br>
Safe, Antony; Brutus is safe enough.<br>
I dare assure thee that no enemy<br>
Shall ever take alive the noble Brutus.<br>
The gods defend him from so great a shame!<br>
When you do find him, or alive or dead,<br>
He will be found like Brutus, like himself.
</p>

<p class="drama">
ANTONY.<br>
This is not Brutus, friend; but, I assure you,<br>
A prize no less in worth. Keep this man safe,<br>
Give him all kindness. I had rather have<br>
Such men my friends than enemies. Go on,<br>
And see whether Brutus be alive or dead;<br>
And bring us word unto Octavius’ tent<br>
How everything is chanc’d.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneV_17.5"></a><b>SCENE V. Another part of the field.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Brutus, Dardanius, Clitus, Strato</span> and <span class="charname">Volumnius</span>.
</p>

<p class="drama">
BRUTUS.<br>
Come, poor remains of friends, rest on this rock.
</p>

<p class="drama">
CLITUS.<br>
Statilius show’d the torch-light; but, my lord,<br>
He came not back: he is or ta’en or slain.
</p>

<p class="drama">
BRUTUS.<br>
Sit thee down, Clitus. Slaying is the word;<br>
It is a deed in fashion. Hark thee, Clitus.
</p>

<p class="right">
[<i>Whispering.</i>]
</p>

<p class="drama">
CLITUS.<br>
What, I, my lord? No, not for all the world.
</p>

<p class="drama">
BRUTUS.<br>
Peace then, no words.
</p>

<p class="drama">
CLITUS.<br>
I’ll rather kill myself.
</p>

<p class="drama">
BRUTUS.<br>
Hark thee, Dardanius.
</p>

<p class="right">
[<i>Whispers him.</i>]
</p>

<p class="drama">
DARDANIUS.<br>
Shall I do such a deed?
</p>

<p class="drama">
CLITUS.<br>
O Dardanius!
</p>

<p class="drama">
DARDANIUS.<br>
O Clitus!
</p>

<p class="drama">
CLITUS.<br>
What ill request did Brutus make to thee?
</p>

<p class="drama">
DARDANIUS.<br>
To kill him, Clitus. Look, he meditates.
</p>

<p class="drama">
CLITUS.<br>
Now is that noble vessel full of grief,<br>
That it runs over even at his eyes.
</p>

<p class="drama">
BRUTUS.<br>
Come hither, good Volumnius; list a word.
</p>

<p class="drama">
VOLUMNIUS.<br>
What says my lord?
</p>

<p class="drama">
BRUTUS.<br>
Why, this, Volumnius:<br>
The ghost of Caesar hath appear’d to me<br>
Two several times by night; at Sardis once,<br>
And this last night here in Philippi fields.<br>
I know my hour is come.
</p>

<p class="drama">
VOLUMNIUS.<br>
Not so, my lord.
</p>

<p class="drama">
BRUTUS.<br>
Nay I am sure it is, Volumnius.<br>
Thou seest the world, Volumnius, how it goes;<br>
Our enemies have beat us to the pit.
</p>

<p class="right">
[<i>Low alarums.</i>]
</p>

<p class="drama">
It is more worthy to leap in ourselves<br>
Than tarry till they push us. Good Volumnius,<br>
Thou know’st that we two went to school together;<br>
Even for that our love of old, I pr’ythee<br>
Hold thou my sword-hilts, whilst I run on it.
</p>

<p class="drama">
VOLUMNIUS.<br>
That’s not an office for a friend, my lord.
</p>

<p class="right">
[<i>Alarums still.</i>]
</p>

<p class="drama">
CLITUS.<br>
Fly, fly, my lord! there is no tarrying here.
</p>

<p class="drama">
BRUTUS.<br>
Farewell to you; and you; and you, Volumnius.<br>
Strato, thou hast been all this while asleep;<br>
Farewell to thee too, Strato.—Countrymen,<br>
My heart doth joy, that yet in all my life<br>
I found no man but he was true to me.<br>
I shall have glory by this losing day<br>
More than Octavius and Mark Antony<br>
By this vile conquest shall attain unto.<br>
So fare you well at once; for Brutus’ tongue<br>
Hath almost ended his life’s history.<br>
Night hangs upon mine eyes; my bones would rest,<br>
That have but labour’d to attain this hour.
</p>

<p class="right">
[<i>Alarums. Cry within, “Fly, fly, fly!”.</i>]
</p>

<p class="drama">
CLITUS.<br>
Fly, my lord, fly!
</p>

<p class="drama">
BRUTUS.<br>
Hence! I will follow.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Clitus, Dardanius</span> and <span class="charname">Volumnius</span>.</i>]
</p>

<p class="drama">
I pr’ythee, Strato, stay thou by thy lord.<br>
Thou art a fellow of a good respect;<br>
Thy life hath had some smatch of honour in it.<br>
Hold then my sword, and turn away thy face,<br>
While I do run upon it. Wilt thou, Strato?
</p>

<p class="drama">
STRATO.<br>
Give me your hand first. Fare you well, my lord.
</p>

<p class="drama">
BRUTUS.<br>
Farewell, good Strato.—Caesar, now be still:<br>
I kill’d not thee with half so good a will.
</p>

<p class="right">
[<i>He runs on his sword, and dies.</i>]
</p>

<p class="scenedesc">
Alarum. Retreat. Enter <span class="charname">Antony, Octavius, Messala,
Lucilius</span> and the Army.
</p>

<p class="drama">
OCTAVIUS.<br>
What man is that?
</p>

<p class="drama">
MESSALA.<br>
My master’s man. Strato, where is thy master?
</p>

<p class="drama">
STRATO.<br>
Free from the bondage you are in, Messala.<br>
The conquerors can but make a fire of him;<br>
For Brutus only overcame himself,<br>
And no man else hath honour by his death.
</p>

<p class="drama">
LUCILIUS.<br>
So Brutus should be found. I thank thee, Brutus,<br>
That thou hast prov’d Lucilius’ saying true.
</p>

<p class="drama">
OCTAVIUS.<br>
All that serv’d Brutus, I will entertain them.<br>
Fellow, wilt thou bestow thy time with me?
</p>

<p class="drama">
STRATO.<br>
Ay, if Messala will prefer me to you.
</p>

<p class="drama">
OCTAVIUS.<br>
Do so, good Messala.
</p>

<p class="drama">
MESSALA.<br>
How died my master, Strato?
</p>

<p class="drama">
STRATO.<br>
I held the sword, and he did run on it.
</p>

<p class="drama">
MESSALA.<br>
Octavius, then take him to follow thee,<br>
That did the latest service to my master.
</p>

<p class="drama">
ANTONY.<br>
This was the noblest Roman of them all.<br>
All the conspirators save only he,<br>
Did that they did in envy of great Caesar;<br>
He only, in a general honest thought<br>
And common good to all, made one of them.<br>
His life was gentle, and the elements<br>
So mix’d in him that Nature might stand up<br>
And say to all the world, “This was a man!”
</p>

<p class="drama">
OCTAVIUS.<br>
According to his virtue let us use him<br>
With all respect and rites of burial.<br>
Within my tent his bones tonight shall lie,<br>
Most like a soldier, order’d honourably.<br>
So call the field to rest, and let’s away,<br>
To part the glories of this happy day.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

