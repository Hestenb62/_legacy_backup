<h2> <a id="sceneII_37.1"></a><b>ACT II</b></h2>

<h3> <b>SCENE I. Milan. A room in the Duke’s palace</b></h3>

<p class="scenedesc">
Enter <span class="charname">Valentine</span> and
<span class="charname">Speed</span>.
</p>

<p class="drama">
SPEED.<br>
Sir, your glove.
</p>

<p class="drama">
VALENTINE.<br>
Not mine. My gloves are on.
</p>

<p class="drama">
SPEED.<br>
Why, then, this may be yours, for this is but one.
</p>

<p class="drama">
VALENTINE.<br>
Ha? Let me see. Ay, give it me, it’s mine.<br>
Sweet ornament that decks a thing divine!<br>
Ah, Silvia, Silvia!
</p>

<p class="drama">
SPEED.<br>
[<i>Calling</i>.] Madam Silvia! Madam Silvia!
</p>

<p class="drama">
VALENTINE.<br>
How now, sirrah?
</p>

<p class="drama">
SPEED.<br>
She is not within hearing, sir.
</p>

<p class="drama">
VALENTINE.<br>
Why, sir, who bade you call her?
</p>

<p class="drama">
SPEED.<br>
Your worship, sir, or else I mistook.
</p>

<p class="drama">
VALENTINE.<br>
Well, you’ll still be too forward.
</p>

<p class="drama">
SPEED.<br>
And yet I was last chidden for being too slow.
</p>

<p class="drama">
VALENTINE.<br>
Go to, sir. Tell me, do you know Madam Silvia?
</p>

<p class="drama">
SPEED.<br>
She that your worship loves?
</p>

<p class="drama">
VALENTINE.<br>
Why, how know you that I am in love?
</p>

<p class="drama">
SPEED.<br>
Marry, by these special marks: first, you have learned, like Sir Proteus, to
wreathe your arms like a malcontent; to relish a love-song, like a robin
redbreast; to walk alone, like one that had the pestilence; to sigh, like a
schoolboy that had lost his ABC; to weep, like a young wench that had buried
her grandam; to fast, like one that takes diet; to watch, like one that fears
robbing; to speak puling, like a beggar at Hallowmas. You were wont, when you
laughed, to crow like a cock; when you walked, to walk like one of the lions;
when you fasted, it was presently after dinner; when you looked sadly, it was
for want of money. And now you are metamorphosed with a mistress, that, when I
look on you, I can hardly think you my master.
</p>

<p class="drama">
VALENTINE.<br>
Are all these things perceived in me?
</p>

<p class="drama">
SPEED.<br>
They are all perceived without ye.
</p>

<p class="drama">
VALENTINE.<br>
Without me? They cannot.
</p>

<p class="drama">
SPEED.<br>
Without you? Nay, that’s certain, for without you were so simple, none else
would. But you are so without these follies, that these follies are within you,
and shine through you like the water in an urinal, that not an eye that sees
you but is a physician to comment on your malady.
</p>

<p class="drama">
VALENTINE.<br>
But tell me, dost thou know my lady Silvia?
</p>

<p class="drama">
SPEED.<br>
She that you gaze on so as she sits at supper?
</p>

<p class="drama">
VALENTINE.<br>
Hast thou observed that? Even she I mean.
</p>

<p class="drama">
SPEED.<br>
Why, sir, I know her not.
</p>

<p class="drama">
VALENTINE.<br>
Dost thou know her by my gazing on her, and yet know’st her not?
</p>

<p class="drama">
SPEED.<br>
Is she not hard-favoured, sir?
</p>

<p class="drama">
VALENTINE.<br>
Not so fair, boy, as well-favoured.
</p>

<p class="drama">
SPEED.<br>
Sir, I know that well enough.
</p>

<p class="drama">
VALENTINE.<br>
What dost thou know?
</p>

<p class="drama">
SPEED.<br>
That she is not so fair as, of you, well-favoured.
</p>

<p class="drama">
VALENTINE.<br>
I mean that her beauty is exquisite but her favour infinite.
</p>

<p class="drama">
SPEED.<br>
That’s because the one is painted, and the other out of all count.
</p>

<p class="drama">
VALENTINE.<br>
How painted? And how out of count?
</p>

<p class="drama">
SPEED.<br>
Marry, sir, so painted to make her fair, that no man counts of her beauty.
</p>

<p class="drama">
VALENTINE.<br>
How esteem’st thou me? I account of her beauty.
</p>

<p class="drama">
SPEED.<br>
You never saw her since she was deformed.
</p>

<p class="drama">
VALENTINE.<br>
How long hath she been deformed?
</p>

<p class="drama">
SPEED.<br>
Ever since you loved her.
</p>

<p class="drama">
VALENTINE.<br>
I have loved her ever since I saw her, and still I see her beautiful.
</p>

<p class="drama">
SPEED.<br>
If you love her, you cannot see her.
</p>

<p class="drama">
VALENTINE.<br>
Why?
</p>

<p class="drama">
SPEED.<br>
Because Love is blind. O, that you had mine eyes, or your own eyes had the
lights they were wont to have when you chid at Sir Proteus for going
ungartered!
</p>

<p class="drama">
VALENTINE.<br>
What should I see then?
</p>

<p class="drama">
SPEED.<br>
Your own present folly and her passing deformity; for he, being in love, could
not see to garter his hose; and you, being in love, cannot see to put on your
hose.
</p>

<p class="drama">
VALENTINE.<br>
Belike, boy, then you are in love, for last morning you could not see to wipe
my shoes.
</p>

<p class="drama">
SPEED.<br>
True, sir, I was in love with my bed. I thank you, you swinged me for my love,
which makes me the bolder to chide you for yours.
</p>

<p class="drama">
VALENTINE.<br>
In conclusion, I stand affected to her.
</p>

<p class="drama">
SPEED.<br>
I would you were set, so your affection would cease.
</p>

<p class="drama">
VALENTINE.<br>
Last night she enjoined me to write some lines to one she loves.
</p>

<p class="drama">
SPEED.<br>
And have you?
</p>

<p class="drama">
VALENTINE.<br>
I have.
</p>

<p class="drama">
SPEED.<br>
Are they not lamely writ?
</p>

<p class="drama">
VALENTINE.<br>
No, boy, but as well as I can do them.<br>
Peace, here she comes.
</p>

<p class="scenedesc">
Enter <span class="charname">Silvia</span>.
</p>

<p class="drama">
SPEED.<br>
[<i>Aside</i>.] O excellent motion! O exceeding puppet!<br>
Now will he interpret to her.
</p>

<p class="drama">
VALENTINE.<br>
Madam and mistress, a thousand good-morrows.
</p>

<p class="drama">
SPEED.<br>
[<i>Aside</i>.] O, give ye good e’en! Here’s a million of manners.
</p>

<p class="drama">
SILVIA.<br>
Sir Valentine and servant, to you two thousand.
</p>

<p class="drama">
SPEED.<br>
[<i>Aside</i>.] He should give her interest, and she gives it him.
</p>

<p class="drama">
VALENTINE.<br>
As you enjoined me, I have writ your letter<br>
Unto the secret nameless friend of yours,<br>
Which I was much unwilling to proceed in<br>
But for my duty to your ladyship.
</p>

<p class="right">[<i>Gives her a letter.</i>]</p>

<p class="drama">
SILVIA.<br>
I thank you, gentle servant, ’tis very clerkly done.
</p>

<p class="drama">
VALENTINE.<br>
Now trust me, madam, it came hardly off,<br>
For, being ignorant to whom it goes,<br>
I writ at random, very doubtfully.
</p>

<p class="drama">
SILVIA.<br>
Perchance you think too much of so much pains?
</p>

<p class="drama">
VALENTINE.<br>
No, madam; so it stead you, I will write,<br>
Please you command, a thousand times as much.<br>
And yet—
</p>

<p class="drama">
SILVIA.<br>
A pretty period. Well, I guess the sequel;<br>
And yet I will not name it. And yet I care not.<br>
And yet take this again.
</p>

<p class="right">[<i>Offers him the letter.</i>]</p>

<p class="drama">
And yet I thank you,<br>
Meaning henceforth to trouble you no more.
</p>

<p class="drama">
SPEED.<br>
[<i>Aside</i>.] And yet you will; and yet another “yet”.
</p>

<p class="drama">
VALENTINE.<br>
What means your ladyship? Do you not like it?
</p>

<p class="drama">
SILVIA.<br>
Yes, yes, the lines are very quaintly writ,<br>
But, since unwillingly, take them again.<br>
Nay, take them.
</p>

<p class="right">[<i>Offers the letter again.</i>]</p>

<p class="drama">
VALENTINE.<br>
Madam, they are for you.
</p>

<p class="drama">
SILVIA.<br>
Ay, ay, you writ them, sir, at my request,<br>
But I will none of them. They are for you.<br>
I would have had them writ more movingly.
</p>

<p class="drama">
VALENTINE.<br>
Please you, I’ll write your ladyship another.
</p>

<p class="drama">
SILVIA.<br>
And when it’s writ, for my sake read it over,<br>
And if it please you, so; if not, why, so.
</p>

<p class="drama">
VALENTINE.<br>
If it please me, madam? What then?
</p>

<p class="drama">
SILVIA.<br>
Why, if it please you, take it for your labour.<br>
And so good morrow, servant.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
SPEED.<br>
[<i>Aside</i>.] O jest unseen, inscrutable, invisible,<br>
As a nose on a man’s face, or a weathercock on a steeple!<br>
My master sues to her, and she hath taught her suitor,<br>
He being her pupil, to become her tutor.<br>
O excellent device! Was there ever heard a better?<br>
That my master, being scribe, to himself should write the letter?
</p>

<p class="drama">
VALENTINE.<br>
How now, sir? What are you reasoning with yourself?
</p>

<p class="drama">
SPEED.<br>
Nay, I was rhyming. ’Tis you that have the reason.
</p>

<p class="drama">
VALENTINE.<br>
To do what?
</p>

<p class="drama">
SPEED.<br>
To be a spokesman from Madam Silvia.
</p>

<p class="drama">
VALENTINE.<br>
To whom?
</p>

<p class="drama">
SPEED.<br>
To yourself. Why, she woos you by a figure.
</p>

<p class="drama">
VALENTINE.<br>
What figure?
</p>

<p class="drama">
SPEED.<br>
By a letter, I should say.
</p>

<p class="drama">
VALENTINE.<br>
Why, she hath not writ to me.
</p>

<p class="drama">
SPEED.<br>
What need she, when she hath made you write to yourself? Why, do you not
perceive the jest?
</p>

<p class="drama">
VALENTINE.<br>
No, believe me.
</p>

<p class="drama">
SPEED.<br>
No believing you indeed, sir. But did you perceive her earnest?
</p>

<p class="drama">
VALENTINE.<br>
She gave me none, except an angry word.
</p>

<p class="drama">
SPEED.<br>
Why, she hath given you a letter.
</p>

<p class="drama">
VALENTINE.<br>
That’s the letter I writ to her friend.
</p>

<p class="drama">
SPEED.<br>
And that letter hath she delivered, and there an end.
</p>

<p class="drama">
VALENTINE.<br>
I would it were no worse.
</p>

<p class="drama">
SPEED.<br>
I’ll warrant you, ’tis as well.<br>
For often have you writ to her, and she, in modesty<br>
Or else for want of idle time, could not again reply,<br>
Or fearing else some messenger that might her mind discover,<br>
Herself hath taught her love himself to write unto her lover.<br>
All this I speak in print, for in print I found it. Why muse you, sir? ’Tis
dinner time.
</p>

<p class="drama">
VALENTINE.<br>
I have dined.
</p>

<p class="drama">
SPEED.<br>
Ay, but hearken, sir, though the chameleon Love can feed on the air, I am one
that am nourished by my victuals, and would fain have meat. O, be not like your
mistress! Be moved, be moved.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneII_37.2"></a><b>SCENE II. Verona. A room in Julia’s house</b></h3>

<p class="scenedesc">
Enter <span class="charname">Proteus</span> and
<span class="charname">Julia</span>.
</p>

<p class="drama">
PROTEUS.<br>
Have patience, gentle Julia.
</p>

<p class="drama">
JULIA.<br>
I must, where is no remedy.
</p>

<p class="drama">
PROTEUS.<br>
When possibly I can, I will return.
</p>

<p class="drama">
JULIA.<br>
If you turn not, you will return the sooner.<br>
Keep this remembrance for thy Julia’s sake.
</p>

<p class="right">[<i>Gives him a ring.</i>]</p>

<p class="drama">
PROTEUS.<br>
Why, then we’ll make exchange. Here, take you this.
</p>

<p class="right">[<i>Gives her a ring.</i>]</p>

<p class="drama">
JULIA.<br>
And seal the bargain with a holy kiss.
</p>

<p class="drama">
PROTEUS.<br>
Here is my hand for my true constancy.<br>
And when that hour o’erslips me in the day<br>
Wherein I sigh not, Julia, for thy sake,<br>
The next ensuing hour some foul mischance<br>
Torment me for my love’s forgetfulness.<br>
My father stays my coming; answer not.<br>
The tide is now—nay, not thy tide of tears,<br>
That tide will stay me longer than I should.<br>
Julia, farewell.
</p>

<p class="right">[<i>Exit <span class="charname">Julia</span>.</i>]</p>

<p class="drama">
What, gone without a word?<br>
Ay, so true love should do. It cannot speak,<br>
For truth hath better deeds than words to grace it.
</p>

<p class="scenedesc">
Enter <span class="charname">Pantino</span>.
</p>

<p class="drama">
PANTINO.<br>
Sir Proteus, you are stayed for.
</p>

<p class="drama">
PROTEUS.<br>
Go, I come, I come.<br>
Alas, this parting strikes poor lovers dumb.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneII_37.3"></a><b>SCENE III. The same. A street</b></h3>

<p class="scenedesc">
Enter <span class="charname">Lance</span> with his dog Crab.
</p>

<p class="drama">
LANCE.<br>
Nay, ’twill be this hour ere I have done weeping; all the kind of the Lances
have this very fault. I have received my proportion, like the prodigious son,
and am going with Sir Proteus to the Imperial’s court. I think Crab my dog be
the sourest-natured dog that lives: my mother weeping, my father wailing, my
sister crying, our maid howling, our cat wringing her hands, and all our house
in a great perplexity, yet did not this cruel-hearted cur shed one tear. He is
a stone, a very pebblestone, and has no more pity in him than a dog. A Jew
would have wept to have seen our parting. Why, my grandam, having no eyes, look
you, wept herself blind at my parting. Nay, I’ll show you the manner of it.
This shoe is my father. No, this left shoe is my father; no, no, this left shoe
is my mother. Nay, that cannot be so neither. Yes, it is so, it is so; it hath
the worser sole. This shoe with the hole in it is my mother, and this my
father. A vengeance on ’t, there ’tis. Now, sir, this staff is my sister, for,
look you, she is as white as a lily and as small as a wand. This hat is Nan,
our maid. I am the dog. No, the dog is himself, and I am the dog. O, the dog is
me, and I am myself. Ay, so, so. Now come I to my father: “Father, your
blessing.” Now should not the shoe speak a word for weeping. Now should I kiss
my father. Well, he weeps on. Now come I to my mother. O, that she could speak
now like a wood woman! Well, I kiss her. Why there ’tis; here’s my mother’s
breath up and down. Now come I to my sister. Mark the moan she makes. Now the
dog all this while sheds not a tear nor speaks a word; but see how I lay the
dust with my tears.
</p>

<p class="scenedesc">
Enter <span class="charname">Pantino</span>.
</p>

<p class="drama">
PANTINO.<br>
Lance, away, away! Aboard! Thy master is shipped, and thou art to post after
with oars. What’s the matter? Why weep’st thou, man? Away, ass. You’ll lose the
tide if you tarry any longer.
</p>

<p class="drama">
LANCE.<br>
It is no matter if the tied were lost, for it is the unkindest tied that ever
any man tied.
</p>

<p class="drama">
PANTINO.<br>
What’s the unkindest tide?
</p>

<p class="drama">
LANCE.<br>
Why, he that’s tied here, Crab, my dog.
</p>

<p class="drama">
PANTINO.<br>
Tut, man, I mean thou’lt lose the flood, and, in losing the flood, lose thy
voyage, and, in losing thy voyage, lose thy master, and, in losing thy master,
lose thy service, and, in losing thy service—why dost thou stop my mouth?
</p>

<p class="drama">
LANCE.<br>
For fear thou shouldst lose thy tongue.
</p>

<p class="drama">
PANTINO.<br>
Where should I lose my tongue?
</p>

<p class="drama">
LANCE.<br>
In thy tale.
</p>

<p class="drama">
PANTINO.<br>
In thy tail!
</p>

<p class="drama">
LANCE.<br>
Lose the tide, and the voyage, and the master, and the service, and the tied?
Why, man, if the river were dry, I am able to fill it with my tears; if the
wind were down, I could drive the boat with my sighs.
</p>

<p class="drama">
PANTINO.<br>
Come, come away, man. I was sent to call thee.
</p>

<p class="drama">
LANCE.<br>
Sir, call me what thou dar’st.
</p>

<p class="drama">
PANTINO.<br>
Will thou go?
</p>

<p class="drama">
LANCE.<br>
Well, I will go.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneII_37.4"></a><b>SCENE IV. Milan. A room in the Duke’s palace</b></h3>

<p class="scenedesc">
Enter <span class="charname">Valentine, Silvia, Thurio</span> and
<span class="charname">Speed</span>.
</p>

<p class="drama">
SILVIA.<br>
Servant!
</p>

<p class="drama">
VALENTINE.<br>
Mistress?
</p>

<p class="drama">
SPEED.<br>
Master, Sir Thurio frowns on you.
</p>

<p class="drama">
VALENTINE.<br>
Ay, boy, it’s for love.
</p>

<p class="drama">
SPEED.<br>
Not of you.
</p>

<p class="drama">
VALENTINE.<br>
Of my mistress, then.
</p>

<p class="drama">
SPEED.<br>
’Twere good you knocked him.
</p>

<p class="drama">
SILVIA.<br>
Servant, you are sad.
</p>

<p class="drama">
VALENTINE.<br>
Indeed, madam, I seem so.
</p>

<p class="drama">
THURIO.<br>
Seem you that you are not?
</p>

<p class="drama">
VALENTINE.<br>
Haply I do.
</p>

<p class="drama">
THURIO.<br>
So do counterfeits.
</p>

<p class="drama">
VALENTINE.<br>
So do you.
</p>

<p class="drama">
THURIO.<br>
What seem I that I am not?
</p>

<p class="drama">
VALENTINE.<br>
Wise.
</p>

<p class="drama">
THURIO.<br>
What instance of the contrary?
</p>

<p class="drama">
VALENTINE.<br>
Your folly.
</p>

<p class="drama">
THURIO.<br>
And how quote you my folly?
</p>

<p class="drama">
VALENTINE.<br>
I quote it in your jerkin.
</p>

<p class="drama">
THURIO.<br>
My jerkin is a doublet.
</p>

<p class="drama">
VALENTINE.<br>
Well, then, I’ll double your folly.
</p>

<p class="drama">
THURIO.<br>
How!
</p>

<p class="drama">
SILVIA.<br>
What, angry, Sir Thurio? Do you change colour?
</p>

<p class="drama">
VALENTINE.<br>
Give him leave, madam, he is a kind of chameleon.
</p>

<p class="drama">
THURIO.<br>
That hath more mind to feed on your blood than live in your air.
</p>

<p class="drama">
VALENTINE.<br>
You have said, sir.
</p>

<p class="drama">
THURIO.<br>
Ay, sir, and done too, for this time.
</p>

<p class="drama">
VALENTINE.<br>
I know it well, sir. You always end ere you begin.
</p>

<p class="drama">
SILVIA.<br>
A fine volley of words, gentlemen, and quickly shot off.
</p>

<p class="drama">
VALENTINE.<br>
’Tis indeed, madam, we thank the giver.
</p>

<p class="drama">
SILVIA.<br>
Who is that, servant?
</p>

<p class="drama">
VALENTINE.<br>
Yourself, sweet lady, for you gave the fire. Sir Thurio borrows his wit from
your ladyship’s looks, and spends what he borrows kindly in your company.
</p>

<p class="drama">
THURIO.<br>
Sir, if you spend word for word with me, I shall make your wit bankrupt.
</p>

<p class="drama">
VALENTINE.<br>
I know it well, sir. You have an exchequer of words and, I think, no other
treasure to give your followers, for it appears by their bare liveries that
they live by your bare words.
</p>

<p class="drama">
SILVIA.<br>
No more, gentlemen, no more. Here comes my father.
</p>

<p class="scenedesc">
Enter <span class="charname">Duke</span>.
</p>

<p class="drama">
DUKE.<br>
Now, daughter Silvia, you are hard beset.<br>
Sir Valentine, your father is in good health.<br>
What say you to a letter from your friends<br>
Of much good news?
</p>

<p class="drama">
VALENTINE.<br>
My lord, I will be thankful<br>
To any happy messenger from thence.
</p>

<p class="drama">
DUKE.<br>
Know ye Don Antonio, your countryman?
</p>

<p class="drama">
VALENTINE.<br>
Ay, my good lord, I know the gentleman<br>
To be of worth and worthy estimation,<br>
And not without desert so well reputed.
</p>

<p class="drama">
DUKE.<br>
Hath he not a son?
</p>

<p class="drama">
VALENTINE.<br>
Ay, my good lord, a son that well deserves<br>
The honour and regard of such a father.
</p>

<p class="drama">
DUKE.<br>
You know him well?
</p>

<p class="drama">
VALENTINE.<br>
I knew him as myself, for from our infancy<br>
We have conversed and spent our hours together.<br>
And though myself have been an idle truant,<br>
Omitting the sweet benefit of time<br>
To clothe mine age with angel-like perfection,<br>
Yet hath Sir Proteus, for that’s his name,<br>
Made use and fair advantage of his days:<br>
His years but young, but his experience old;<br>
His head unmellowed, but his judgement ripe;<br>
And in a word, for far behind his worth<br>
Comes all the praises that I now bestow,<br>
He is complete in feature and in mind,<br>
With all good grace to grace a gentleman.
</p>

<p class="drama">
DUKE.<br>
Beshrew me, sir, but if he make this good,<br>
He is as worthy for an empress’ love<br>
As meet to be an emperor’s counsellor.<br>
Well, sir, this gentleman is come to me<br>
With commendation from great potentates,<br>
And here he means to spend his time awhile.<br>
I think ’tis no unwelcome news to you.
</p>

<p class="drama">
VALENTINE.<br>
Should I have wished a thing, it had been he.
</p>

<p class="drama">
DUKE.<br>
Welcome him then according to his worth.<br>
Silvia, I speak to you, and you, Sir Thurio.<br>
For Valentine, I need not cite him to it.<br>
I will send him hither to you presently.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
VALENTINE.<br>
This is the gentleman I told your ladyship<br>
Had come along with me but that his mistresss<br>
Did hold his eyes locked in her crystal looks.
</p>

<p class="drama">
SILVIA.<br>
Belike that now she hath enfranchised them<br>
Upon some other pawn for fealty.
</p>

<p class="drama">
VALENTINE.<br>
Nay, sure, I think she holds them prisoners still.
</p>

<p class="drama">
SILVIA.<br>
Nay, then, he should be blind, and being blind<br>
How could he see his way to seek out you?
</p>

<p class="drama">
VALENTINE.<br>
Why, lady, Love hath twenty pair of eyes.
</p>

<p class="drama">
THURIO.<br>
They say that Love hath not an eye at all.
</p>

<p class="drama">
VALENTINE.<br>
To see such lovers, Thurio, as yourself.<br>
Upon a homely object, Love can wink.
</p>

<p class="drama">
SILVIA.<br>
Have done, have done. Here comes the gentleman.
</p>

<p class="scenedesc">
Enter <span class="charname">Proteus</span>.
</p>

<p class="drama">
VALENTINE.<br>
Welcome, dear Proteus! Mistress, I beseech you<br>
Confirm his welcome with some special favour.
</p>

<p class="drama">
SILVIA.<br>
His worth is warrant for his welcome hither,<br>
If this be he you oft have wished to hear from.
</p>

<p class="drama">
VALENTINE.<br>
Mistress, it is. Sweet lady, entertain him<br>
To be my fellow-servant to your ladyship.
</p>

<p class="drama">
SILVIA.<br>
Too low a mistress for so high a servant.
</p>

<p class="drama">
PROTEUS.<br>
Not so, sweet lady, but too mean a servant<br>
To have a look of such a worthy mistress.
</p>

<p class="drama">
VALENTINE.<br>
Leave off discourse of disability.<br>
Sweet lady, entertain him for your servant.
</p>

<p class="drama">
PROTEUS.<br>
My duty will I boast of, nothing else.
</p>

<p class="drama">
SILVIA.<br>
And duty never yet did want his meed.<br>
Servant, you are welcome to a worthless mistress.
</p>

<p class="drama">
PROTEUS.<br>
I’ll die on him that says so but yourself.
</p>

<p class="drama">
SILVIA.<br>
That you are welcome?
</p>

<p class="drama">
PROTEUS.<br>
That you are worthless.
</p>

<p class="scenedesc">
Enter <span class="charname">Servant</span>.
</p>

<p class="drama">
SERVANT.<br>
Madam, my lord your father would speak with you.
</p>

<p class="drama">
SILVIA.<br>
I wait upon his pleasure.
</p>

<p class="right">[<i>Exit <span class="charname">Servant</span>.</i>]</p>

<p class="drama">
Come, Sir Thurio,<br>
Go with me.—Once more, new servant, welcome.<br>
I’ll leave you to confer of home affairs;<br>
When you have done, we look to hear from you.
</p>

<p class="drama">
PROTEUS.<br>
We’ll both attend upon your ladyship.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Silvia</span> and
<span class="charname">Thurio</span>.</i>]
</p>

<p class="drama">
VALENTINE.<br>
Now, tell me, how do all from whence you came?
</p>

<p class="drama">
PROTEUS.<br>
Your friends are well and have them much commended.
</p>

<p class="drama">
VALENTINE.<br>
And how do yours?
</p>

<p class="drama">
PROTEUS.<br>
I left them all in health.
</p>

<p class="drama">
VALENTINE.<br>
How does your lady? And how thrives your love?
</p>

<p class="drama">
PROTEUS.<br>
My tales of love were wont to weary you;<br>
I know you joy not in a love-discourse.
</p>

<p class="drama">
VALENTINE.<br>
Ay, Proteus, but that life is altered now.<br>
I have done penance for contemning Love,<br>
Whose high imperious thoughts have punished me<br>
With bitter fasts, with penitential groans,<br>
With nightly tears, and daily heart-sore sighs;<br>
For in revenge of my contempt of love,<br>
Love hath chased sleep from my enthralled eyes<br>
And made them watchers of mine own heart’s sorrow.<br>
O gentle Proteus, Love’s a mighty lord,<br>
And hath so humbled me as I confess<br>
There is no woe to his correction,<br>
Nor to his service no such joy on earth.<br>
Now, no discourse, except it be of love;<br>
Now can I break my fast, dine, sup, and sleep<br>
Upon the very naked name of love.
</p>

<p class="drama">
PROTEUS.<br>
Enough; I read your fortune in your eye.<br>
Was this the idol that you worship so?
</p>

<p class="drama">
VALENTINE.<br>
Even she; and is she not a heavenly saint?
</p>

<p class="drama">
PROTEUS.<br>
No, but she is an earthly paragon.
</p>

<p class="drama">
VALENTINE.<br>
Call her divine.
</p>

<p class="drama">
PROTEUS.<br>
I will not flatter her.
</p>

<p class="drama">
VALENTINE.<br>
O, flatter me, for love delights in praises.
</p>

<p class="drama">
PROTEUS.<br>
When I was sick, you gave me bitter pills,<br>
And I must minister the like to you.
</p>

<p class="drama">
VALENTINE.<br>
Then speak the truth by her; if not divine,<br>
Yet let her be a principality,<br>
Sovereign to all the creatures on the earth.
</p>

<p class="drama">
PROTEUS.<br>
Except my mistress.
</p>

<p class="drama">
VALENTINE.<br>
Sweet, except not any,<br>
Except thou wilt except against my love.
</p>

<p class="drama">
PROTEUS.<br>
Have I not reason to prefer mine own?
</p>

<p class="drama">
VALENTINE.<br>
And I will help thee to prefer her too:<br>
She shall be dignified with this high honour,<br>
To bear my lady’s train, lest the base earth<br>
Should from her vesture chance to steal a kiss,<br>
And, of so great a favour growing proud,<br>
Disdain to root the summer-swelling flower<br>
And make rough winter everlastingly.
</p>

<p class="drama">
PROTEUS.<br>
Why, Valentine, what braggartism is this?
</p>

<p class="drama">
VALENTINE.<br>
Pardon me, Proteus, all I can is nothing<br>
To her, whose worth makes other worthies nothing;<br>
She is alone.
</p>

<p class="drama">
PROTEUS.<br>
Then let her alone.
</p>

<p class="drama">
VALENTINE.<br>
Not for the world! Why, man, she is mine own,<br>
And I as rich in having such a jewel<br>
As twenty seas, if all their sand were pearl,<br>
The water nectar, and the rocks pure gold.<br>
Forgive me that I do not dream on thee,<br>
Because thou seest me dote upon my love.<br>
My foolish rival, that her father likes<br>
Only for his possessions are so huge,<br>
Is gone with her along, and I must after,<br>
For love, thou know’st, is full of jealousy.
</p>

<p class="drama">
PROTEUS.<br>
But she loves you?
</p>

<p class="drama">
VALENTINE.<br>
Ay, and we are betrothed; nay more, our marriage hour,<br>
With all the cunning manner of our flight,<br>
Determined of: how I must climb her window,<br>
The ladder made of cords, and all the means<br>
Plotted and ’greed on for my happiness.<br>
Good Proteus, go with me to my chamber,<br>
In these affairs to aid me with thy counsel.
</p>

<p class="drama">
PROTEUS.<br>
Go on before; I shall enquire you forth.<br>
I must unto the road to disembark<br>
Some necessaries that I needs must use,<br>
And then I’ll presently attend you.
</p>

<p class="drama">
VALENTINE.<br>
Will you make haste?
</p>

<p class="drama">
PROTEUS.<br>
I will.
</p>

<p class="right">[<i>Exit <span class="charname">Valentine</span>.</i>]</p>

<p class="drama">
Even as one heat another heat expels,<br>
Or as one nail by strength drives out another,<br>
So the remembrance of my former love<br>
Is by a newer object quite forgotten.<br>
Is it mine eye, or Valentine’s praise,<br>
Her true perfection, or my false transgression,<br>
That makes me reasonless to reason thus?<br>
She is fair; and so is Julia that I love—<br>
That I did love, for now my love is thawed,<br>
Which like a waxen image ’gainst a fire<br>
Bears no impression of the thing it was.<br>
Methinks my zeal to Valentine is cold,<br>
And that I love him not as I was wont.<br>
O, but I love his lady too too much,<br>
And that’s the reason I love him so little.<br>
How shall I dote on her with more advice<br>
That thus without advice begin to love her?<br>
’Tis but her picture I have yet beheld,<br>
And that hath dazzled my reason’s light;<br>
But when I look on her perfections,<br>
There is no reason but I shall be blind.<br>
If I can check my erring love, I will;<br>
If not, to compass her I’ll use my skill.
</p>

<p class="right">[<i>Exit.</i>]</p>

<h3> <a id="sceneII_37.5"></a><b>SCENE V. The same. A street</b></h3>

<p class="scenedesc">
Enter <span class="charname">Speed</span> and
<span class="charname">Lance</span> with his dog Crab.
</p>

<p class="drama">
SPEED.<br>
Lance, by mine honesty, welcome to Milan!
</p>

<p class="drama">
LANCE.<br>
Forswear not thyself, sweet youth, for I am not welcome. I reckon this always,
that a man is never undone till he be hanged, nor never welcome to a place till
some certain shot be paid and the hostess say “Welcome”.
</p>

<p class="drama">
SPEED.<br>
Come on, you madcap. I’ll to the alehouse with you presently, where, for one
shot of five pence, thou shalt have five thousand welcomes. But, sirrah, how
did thy master part with Madam Julia?
</p>

<p class="drama">
LANCE.<br>
Marry, after they closed in earnest, they parted very fairly in jest.
</p>

<p class="drama">
SPEED.<br>
But shall she marry him?
</p>

<p class="drama">
LANCE.<br>
No.
</p>

<p class="drama">
SPEED.<br>
How then? Shall he marry her?
</p>

<p class="drama">
LANCE.<br>
No, neither.
</p>

<p class="drama">
SPEED.<br>
What, are they broken?
</p>

<p class="drama">
LANCE.<br>
No, they are both as whole as a fish.
</p>

<p class="drama">
SPEED.<br>
Why then, how stands the matter with them?
</p>

<p class="drama">
LANCE.<br>
Marry, thus: when it stands well with him, it stands well with her.
</p>

<p class="drama">
SPEED.<br>
What an ass art thou! I understand thee not.
</p>

<p class="drama">
LANCE.<br>
What a block art thou that thou canst not! My staff understands me.
</p>

<p class="drama">
SPEED.<br>
What thou sayst?
</p>

<p class="drama">
LANCE.<br>
Ay, and what I do too. Look thee, I’ll but lean, and my staff understands me.
</p>

<p class="drama">
SPEED.<br>
It stands under thee indeed.
</p>

<p class="drama">
LANCE.<br>
Why, stand-under and under-stand is all one.
</p>

<p class="drama">
SPEED.<br>
But tell me true, will’t be a match?
</p>

<p class="drama">
LANCE.<br>
Ask my dog. If he say “Ay”, it will; if he say “No”, it will; if he shake his tail
and say nothing, it will.
</p>

<p class="drama">
SPEED.<br>
The conclusion is, then, that it will.
</p>

<p class="drama">
LANCE.<br>
Thou shalt never get such a secret from me but by a parable.
</p>

<p class="drama">
SPEED.<br>
’Tis well that I get it so. But, Lance, how sayst thou that my master is
become a notable lover?
</p>

<p class="drama">
LANCE.<br>
I never knew him otherwise.
</p>

<p class="drama">
SPEED.<br>
Than how?
</p>

<p class="drama">
LANCE.<br>
A notable lubber, as thou reportest him to be.
</p>

<p class="drama">
SPEED.<br>
Why, thou whoreson ass, thou mistak’st me.
</p>

<p class="drama">
LANCE.<br>
Why, fool, I meant not thee, I meant thy master.
</p>

<p class="drama">
SPEED.<br>
I tell thee, my master is become a hot lover.
</p>

<p class="drama">
LANCE.<br>
Why, I tell thee, I care not though he burn himself in love. If thou wilt, go
with me to the alehouse; if not, thou art an Hebrew, a Jew, and not worth the
name of a Christian.
</p>

<p class="drama">
SPEED.<br>
Why?
</p>

<p class="drama">
LANCE.<br>
Because thou hast not so much charity in thee as to go to the ale with a
Christian. Wilt thou go?
</p>

<p class="drama">
SPEED.<br>
At thy service.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneII_37.6"></a><b>SCENE VI. The same. The Duke’s palace</b></h3>

<p class="scenedesc">
Enter <span class="charname">Proteus</span> alone.
</p>

<p class="drama">
PROTEUS.<br>
To leave my Julia, shall I be forsworn;<br>
To love fair Silvia, shall I be forsworn;<br>
To wrong my friend, I shall be much forsworn.<br>
And e’en that power which gave me first my oath<br>
Provokes me to this threefold perjury.<br>
Love bade me swear, and Love bids me forswear.<br>
O sweet-suggesting Love, if thou hast sinned,<br>
Teach me, thy tempted subject, to excuse it.<br>
At first I did adore a twinkling star,<br>
But now I worship a celestial sun.<br>
Unheedful vows may heedfully be broken,<br>
And he wants wit that wants resolved will<br>
To learn his wit t’ exchange the bad for better.<br>
Fie, fie, unreverend tongue, to call her bad<br>
Whose sovereignty so oft thou hast preferred<br>
With twenty thousand soul-confirming oaths.<br>
I cannot leave to love, and yet I do;<br>
But there I leave to love where I should love.<br>
Julia I lose, and Valentine I lose;<br>
If I keep them, I needs must lose myself;<br>
If I lose them, thus find I by their loss,<br>
For Valentine, myself; for Julia, Silvia.<br>
I to myself am dearer than a friend,<br>
For love is still most precious in itself,<br>
And Silvia—witness heaven that made her fair—<br>
Shows Julia but a swarthy Ethiope.<br>
I will forget that Julia is alive,<br>
Remembering that my love to her is dead;<br>
And Valentine I’ll hold an enemy,<br>
Aiming at Silvia as a sweeter friend.<br>
I cannot now prove constant to myself<br>
Without some treachery used to Valentine.<br>
This night he meaneth with a corded ladder<br>
To climb celestial Silvia’s chamber window,<br>
Myself in counsel, his competitor.<br>
Now presently I’ll give her father notice<br>
Of their disguising and pretended flight,<br>
Who, all enraged, will banish Valentine,<br>
For Thurio he intends shall wed his daughter.<br>
But Valentine being gone, I’ll quickly cross<br>
By some sly trick blunt Thurio’s dull proceeding.<br>
Love, lend me wings to make my purpose swift,<br>
As thou hast lent me wit to plot this drift.
</p>

<p class="right">[<i>Exit.</i>]</p>

<h3> <a id="sceneII_37.7"></a><b>SCENE VII. Verona. A room in Julia’s house</b></h3>

<p class="scenedesc">
Enter <span class="charname">Julia</span> and
<span class="charname">Lucetta</span>.
</p>

<p class="drama">
JULIA.<br>
Counsel, Lucetta; gentle girl, assist me,<br>
And ev’n in kind love I do conjure thee,<br>
Who art the table wherein all my thoughts<br>
Are visibly charactered and engraved,<br>
To lesson me and tell me some good mean<br>
How with my honour I may undertake<br>
A journey to my loving Proteus.
</p>

<p class="drama">
LUCETTA.<br>
Alas, the way is wearisome and long.
</p>

<p class="drama">
JULIA.<br>
A true-devoted pilgrim is not weary<br>
To measure kingdoms with his feeble steps;<br>
Much less shall she that hath Love’s wings to fly,<br>
And when the flight is made to one so dear,<br>
Of such divine perfection, as Sir Proteus.
</p>

<p class="drama">
LUCETTA.<br>
Better forbear till Proteus make return.
</p>

<p class="drama">
JULIA.<br>
O, know’st thou not his looks are my soul’s food?<br>
Pity the dearth that I have pined in<br>
By longing for that food so long a time.<br>
Didst thou but know the inly touch of love<br>
Thou wouldst as soon go kindle fire with snow<br>
As seek to quench the fire of love with words.
</p>

<p class="drama">
LUCETTA.<br>
I do not seek to quench your love’s hot fire,<br>
But qualify the fire’s extreme rage,<br>
Lest it should burn above the bounds of reason.
</p>

<p class="drama">
JULIA.<br>
The more thou damm’st it up, the more it burns.<br>
The current that with gentle murmur glides,<br>
Thou know’st, being stopped, impatiently doth rage;<br>
But when his fair course is not hindered,<br>
He makes sweet music with th’ enamelled stones,<br>
Giving a gentle kiss to every sedge<br>
He overtaketh in his pilgrimage;<br>
And so by many winding nooks he strays<br>
With willing sport to the wild ocean.<br>
Then let me go and hinder not my course.<br>
I’ll be as patient as a gentle stream<br>
And make a pastime of each weary step<br>
Till the last step have brought me to my love,<br>
And there I’ll rest as after much turmoil<br>
A blessed soul doth in Elysium.
</p>

<p class="drama">
LUCETTA.<br>
But in what habit will you go along?
</p>

<p class="drama">
JULIA.<br>
Not like a woman, for I would prevent<br>
The loose encounters of lascivious men.<br>
Gentle Lucetta, fit me with such weeds<br>
As may beseem some well-reputed page.
</p>

<p class="drama">
LUCETTA.<br>
Why then, your ladyship must cut your hair.
</p>

<p class="drama">
JULIA.<br>
No, girl, I’ll knit it up in silken strings<br>
With twenty odd-conceited true-love knots.<br>
To be fantastic may become a youth<br>
Of greater time than I shall show to be.
</p>

<p class="drama">
LUCETTA.<br>
What fashion, madam, shall I make your breeches?
</p>

<p class="drama">
JULIA.<br>
That fits as well as “Tell me, good my lord,<br>
What compass will you wear your farthingale?”<br>
Why e’en what fashion thou best likes, Lucetta.
</p>

<p class="drama">
LUCETTA.<br>
You must needs have them with a codpiece, madam.
</p>

<p class="drama">
JULIA.<br>
Out, out, Lucetta, that will be ill-favoured.
</p>

<p class="drama">
LUCETTA.<br>
A round hose, madam, now’s not worth a pin<br>
Unless you have a codpiece to stick pins on.
</p>

<p class="drama">
JULIA.<br>
Lucetta, as thou lov’st me, let me have<br>
What thou think’st meet and is most mannerly.<br>
But tell me, wench, how will the world repute me<br>
For undertaking so unstaid a journey?<br>
I fear me it will make me scandalized.
</p>

<p class="drama">
LUCETTA.<br>
If you think so, then stay at home and go not.
</p>

<p class="drama">
JULIA.<br>
Nay, that I will not.
</p>

<p class="drama">
LUCETTA.<br>
Then never dream on infamy, but go.<br>
If Proteus like your journey when you come,<br>
No matter who’s displeased when you are gone.<br>
I fear me he will scarce be pleased withal.
</p>

<p class="drama">
JULIA.<br>
That is the least, Lucetta, of my fear.<br>
A thousand oaths, an ocean of his tears,<br>
And instances of infinite of love,<br>
Warrant me welcome to my Proteus.
</p>

<p class="drama">
LUCETTA.<br>
All these are servants to deceitful men.
</p>

<p class="drama">
JULIA.<br>
Base men that use them to so base effect!<br>
But truer stars did govern Proteus’ birth.<br>
His words are bonds, his oaths are oracles,<br>
His love sincere, his thoughts immaculate,<br>
His tears pure messengers sent from his heart,<br>
His heart as far from fraud as heaven from earth.
</p>

<p class="drama">
LUCETTA.<br>
Pray heav’n he prove so when you come to him.
</p>

<p class="drama">
JULIA.<br>
Now, as thou lov’st me, do him not that wrong<br>
To bear a hard opinion of his truth.<br>
Only deserve my love by loving him.<br>
And presently go with me to my chamber<br>
To take a note of what I stand in need of<br>
To furnish me upon my longing journey.<br>
All that is mine I leave at thy dispose,<br>
My goods, my lands, my reputation;<br>
Only, in lieu thereof, dispatch me hence.<br>
Come, answer not, but to it presently.<br>
I am impatient of my tarriance.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

