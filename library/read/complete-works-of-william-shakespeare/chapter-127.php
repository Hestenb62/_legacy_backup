<h2><a id="sceneV_20.1"></a>
<b>ACT V</b></h2>

<h3> <b>SCENE I. Dunsinane. A Room in the Castle.</b></h3>

<p class="scenedesc">Enter a <span class="charname">Doctor of Physic</span> and a
<span class="charname">Waiting-Gentlewoman</span>.</p>

<p class="drama">
DOCTOR.<br>
I have two nights watched with you, but can perceive no truth in your report.
When was it she last walked?
</p>

<p class="drama">
GENTLEWOMAN.<br>
Since his Majesty went into the field, I have seen her rise from her bed, throw
her nightgown upon her, unlock her closet, take forth paper, fold it, write
upon’t, read it, afterwards seal it, and again return to bed; yet all
this while in a most fast sleep.
</p>

<p class="drama">
DOCTOR.<br>
A great perturbation in nature, to receive at once the benefit of sleep, and do
the effects of watching. In this slumbery agitation, besides her walking and
other actual performances, what, at any time, have you heard her say?
</p>

<p class="drama">
GENTLEWOMAN.<br>
That, sir, which I will not report after her.
</p>

<p class="drama">
DOCTOR.<br>
You may to me; and ’tis most meet you should.
</p>

<p class="drama">
GENTLEWOMAN.<br>
Neither to you nor anyone; having no witness to confirm my speech.
</p>

<p class="scenedesc">Enter <span class="charname">Lady Macbeth</span> with a taper.</p>

<p class="drama">
Lo you, here she comes! This is her very guise; and, upon my life, fast
asleep. Observe her; stand close.
</p>

<p class="drama">
DOCTOR.<br>
How came she by that light?
</p>

<p class="drama">
GENTLEWOMAN.<br>
Why, it stood by her: she has light by her continually; ’tis her command.
</p>

<p class="drama">
DOCTOR.<br>
You see, her eyes are open.
</p>

<p class="drama">
GENTLEWOMAN.<br>
Ay, but their sense are shut.
</p>

<p class="drama">
DOCTOR.<br>
What is it she does now? Look how she rubs her hands.
</p>

<p class="drama">
GENTLEWOMAN.<br>
It is an accustomed action with her, to seem thus washing her hands. I have
known her continue in this a quarter of an hour.
</p>

<p class="drama">
LADY MACBETH.<br>
Yet here’s a spot.
</p>

<p class="drama">
DOCTOR.<br>
Hark, she speaks. I will set down what comes from her, to satisfy my
remembrance the more strongly.
</p>

<p class="drama">
LADY MACBETH.<br>
Out, damned spot! out, I say! One; two. Why, then ’tis time to
do’t. Hell is murky! Fie, my lord, fie! a soldier, and afeard? What need
we fear who knows it, when none can call our power to account? Yet who would
have thought the old man to have had so much blood in him?
</p>

<p class="drama">
DOCTOR.<br>
Do you mark that?
</p>

<p class="drama">
LADY MACBETH.<br>
The Thane of Fife had a wife. Where is she now?—What, will these hands
ne’er be clean? No more o’ that, my lord, no more o’ that:
you mar all with this starting.
</p>

<p class="drama">
DOCTOR.<br>
Go to, go to. You have known what you should not.
</p>

<p class="drama">
GENTLEWOMAN.<br>
She has spoke what she should not, I am sure of that: heaven knows what she has
known.
</p>

<p class="drama">
LADY MACBETH.<br>
Here’s the smell of the blood still: all the perfumes of Arabia will not
sweeten this little hand. Oh, oh, oh!
</p>

<p class="drama">
DOCTOR.<br>
What a sigh is there! The heart is sorely charged.
</p>

<p class="drama">
GENTLEWOMAN.<br>
I would not have such a heart in my bosom for the dignity of the whole body.
</p>

<p class="drama">
DOCTOR.<br>
Well, well, well.
</p>

<p class="drama">
GENTLEWOMAN.<br>
Pray God it be, sir.
</p>

<p class="drama">
DOCTOR.<br>
This disease is beyond my practice: yet I have known those which have walked in
their sleep, who have died holily in their beds.
</p>

<p class="drama">
LADY MACBETH.<br>
Wash your hands, put on your nightgown; look not so pale. I tell you yet again,
Banquo’s buried; he cannot come out on’s grave.
</p>

<p class="drama">
DOCTOR.<br>
Even so?
</p>

<p class="drama">
LADY MACBETH.<br>
To bed, to bed. There’s knocking at the gate. Come, come, come, come,
give me your hand. What’s done cannot be undone. To bed, to bed, to bed.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
DOCTOR.<br>
Will she go now to bed?
</p>

<p class="drama">
GENTLEWOMAN.<br>
Directly.
</p>

<p class="drama">
DOCTOR.<br>
Foul whisp’rings are abroad. Unnatural deeds<br>
Do breed unnatural troubles: infected minds<br>
To their deaf pillows will discharge their secrets.<br>
More needs she the divine than the physician.—<br>
God, God, forgive us all! Look after her;<br>
Remove from her the means of all annoyance,<br>
And still keep eyes upon her. So, good night:<br>
My mind she has mated, and amaz’d my sight.<br>
I think, but dare not speak.
</p>

<p class="drama">
GENTLEWOMAN.<br>
Good night, good doctor.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3><a id="sceneV_20.2"></a>
<b>SCENE II. The Country near Dunsinane.</b></h3>

<p class="scenedesc">Enter, with drum and colours <span class="charname">Menteith,
Caithness, Angus, Lennox</span> and Soldiers.</p>

<p class="drama">
MENTEITH.<br>
The English power is near, led on by Malcolm,<br>
His uncle Siward, and the good Macduff.<br>
Revenges burn in them; for their dear causes<br>
Would to the bleeding and the grim alarm<br>
Excite the mortified man.
</p>

<p class="drama">
ANGUS.<br>
Near Birnam wood<br>
Shall we well meet them. That way are they coming.
</p>

<p class="drama">
CAITHNESS.<br>
Who knows if Donalbain be with his brother?
</p>

<p class="drama">
LENNOX.<br>
For certain, sir, he is not. I have a file<br>
Of all the gentry: there is Siward’s son<br>
And many unrough youths, that even now<br>
Protest their first of manhood.
</p>

<p class="drama">
MENTEITH.<br>
What does the tyrant?
</p>

<p class="drama">
CAITHNESS.<br>
Great Dunsinane he strongly fortifies.<br>
Some say he’s mad; others, that lesser hate him,<br>
Do call it valiant fury: but, for certain,<br>
He cannot buckle his distemper’d cause<br>
Within the belt of rule.
</p>

<p class="drama">
ANGUS.<br>
Now does he feel<br>
His secret murders sticking on his hands;<br>
Now minutely revolts upbraid his faith-breach;<br>
Those he commands move only in command,<br>
Nothing in love: now does he feel his title<br>
Hang loose about him, like a giant’s robe<br>
Upon a dwarfish thief.
</p>

<p class="drama">
MENTEITH.<br>
Who, then, shall blame<br>
His pester’d senses to recoil and start,<br>
When all that is within him does condemn<br>
Itself for being there?
</p>

<p class="drama">
CAITHNESS.<br>
Well, march we on,<br>
To give obedience where ’tis truly ow’d:<br>
Meet we the med’cine of the sickly weal;<br>
And with him pour we, in our country’s purge,<br>
Each drop of us.
</p>

<p class="drama">
LENNOX.<br>
Or so much as it needs<br>
To dew the sovereign flower, and drown the weeds.<br>
Make we our march towards Birnam.
</p>

<p class="right">[<i>Exeunt, marching.</i>]</p>

<h3><a id="sceneV_20.3"></a>
<b>SCENE III. Dunsinane. A Room in the Castle.</b></h3>

<p class="scenedesc">Enter <span class="charname">Macbeth, Doctor</span> and
Attendants.</p>

<p class="drama">
MACBETH.<br>
Bring me no more reports; let them fly all:<br>
Till Birnam wood remove to Dunsinane<br>
I cannot taint with fear. What’s the boy Malcolm?<br>
Was he not born of woman? The spirits that know<br>
All mortal consequences have pronounc’d me thus:<br>
“Fear not, Macbeth; no man that’s born of woman<br>
Shall e’er have power upon thee.”—Then fly, false
thanes,<br>
And mingle with the English epicures:<br>
The mind I sway by, and the heart I bear,<br>
Shall never sag with doubt nor shake with fear.
</p>

<p class="scenedesc">Enter a <span class="charname">Servant</span>.</p>

<p class="drama">
The devil damn thee black, thou cream-fac’d loon!<br>
Where gott’st thou that goose look?
</p>

<p class="drama">
SERVANT.<br>
There is ten thousand—
</p>

<p class="drama">
MACBETH.<br>
Geese, villain?
</p>

<p class="drama">
SERVANT.<br>
Soldiers, sir.
</p>

<p class="drama">
MACBETH.<br>
Go prick thy face and over-red thy fear,<br>
Thou lily-liver’d boy. What soldiers, patch?<br>
Death of thy soul! those linen cheeks of thine<br>
Are counsellors to fear. What soldiers, whey-face?
</p>

<p class="drama">
SERVANT.<br>
The English force, so please you.
</p>

<p class="drama">
MACBETH.<br>
Take thy face hence.
</p>

<p class="right">[<i>Exit Servant.</i>]</p>

<p class="drama">
Seyton!—I am sick at heart,<br>
When I behold—Seyton, I say!—This push<br>
Will cheer me ever or disseat me now.<br>
I have liv’d long enough: my way of life<br>
Is fall’n into the sere, the yellow leaf;<br>
And that which should accompany old age,<br>
As honour, love, obedience, troops of friends,<br>
I must not look to have; but, in their stead,<br>
Curses, not loud but deep, mouth-honour, breath,<br>
Which the poor heart would fain deny, and dare not.<br>
Seyton!—
</p>

<p class="scenedesc">Enter <span class="charname">Seyton</span>.</p>

<p class="drama">
SEYTON.<br>
What’s your gracious pleasure?
</p>

<p class="drama">
MACBETH.<br>
What news more?
</p>

<p class="drama">
SEYTON.<br>
All is confirm’d, my lord, which was reported.
</p>

<p class="drama">
MACBETH.<br>
I’ll fight till from my bones my flesh be hack’d.<br>
Give me my armour.
</p>

<p class="drama">
SEYTON.<br>
’Tis not needed yet.
</p>

<p class="drama">
MACBETH.<br>
I’ll put it on.<br>
Send out more horses, skirr the country round;<br>
Hang those that talk of fear. Give me mine armour.—<br>
How does your patient, doctor?
</p>

<p class="drama">
DOCTOR.<br>
Not so sick, my lord,<br>
As she is troubled with thick-coming fancies,<br>
That keep her from her rest.
</p>

<p class="drama">
MACBETH.<br>
Cure her of that:<br>
Canst thou not minister to a mind diseas’d,<br>
Pluck from the memory a rooted sorrow,<br>
Raze out the written troubles of the brain,<br>
And with some sweet oblivious antidote<br>
Cleanse the stuff’d bosom of that perilous stuff<br>
Which weighs upon the heart?
</p>

<p class="drama">
DOCTOR.<br>
Therein the patient<br>
Must minister to himself.
</p>

<p class="drama">
MACBETH.<br>
Throw physic to the dogs, I’ll none of it.<br>
Come, put mine armour on; give me my staff:<br>
Seyton, send out.—Doctor, the Thanes fly from me.—<br>
Come, sir, despatch.—If thou couldst, doctor, cast<br>
The water of my land, find her disease,<br>
And purge it to a sound and pristine health,<br>
I would applaud thee to the very echo,<br>
That should applaud again.—Pull’t off, I say.—<br>
What rhubarb, senna, or what purgative drug,<br>
Would scour these English hence? Hear’st thou of them?
</p>

<p class="drama">
DOCTOR.<br>
Ay, my good lord. Your royal preparation<br>
Makes us hear something.
</p>

<p class="drama">
MACBETH.<br>
Bring it after me.—<br>
I will not be afraid of death and bane,<br>
Till Birnam forest come to Dunsinane.
</p>

<p class="right">[<i>Exeunt all except <span class="charname">Doctor</span>.</i>]</p>

<p class="drama">
DOCTOR.<br>
Were I from Dunsinane away and clear,<br>
Profit again should hardly draw me here.
</p>

<p class="right">[<i>Exit.</i>]</p>

<h3><a id="sceneV_20.4"></a>
<b>SCENE IV. Country near Dunsinane: a Wood in view.</b></h3>

<p class="scenedesc">Enter, with drum and colours <span class="charname">Malcolm,
old Siward</span> and his Son, <span class="charname">Macduff, Menteith, Caithness,
Angus, Lennox, Ross</span> and Soldiers, marching.</p>

<p class="drama">
MALCOLM.<br>
Cousins, I hope the days are near at hand<br>
That chambers will be safe.
</p>

<p class="drama">
MENTEITH.<br>
We doubt it nothing.
</p>

<p class="drama">
SIWARD.<br>
What wood is this before us?
</p>

<p class="drama">
MENTEITH.<br>
The wood of Birnam.
</p>

<p class="drama">
MALCOLM.<br>
Let every soldier hew him down a bough,<br>
And bear’t before him. Thereby shall we shadow<br>
The numbers of our host, and make discovery<br>
Err in report of us.
</p>

<p class="drama">
SOLDIERS.<br>
It shall be done.
</p>

<p class="drama">
SIWARD.<br>
We learn no other but the confident tyrant<br>
Keeps still in Dunsinane, and will endure<br>
Our setting down before’t.
</p>

<p class="drama">
MALCOLM.<br>
’Tis his main hope;<br>
For where there is advantage to be given,<br>
Both more and less have given him the revolt,<br>
And none serve with him but constrained things,<br>
Whose hearts are absent too.
</p>

<p class="drama">
MACDUFF.<br>
Let our just censures<br>
Attend the true event, and put we on<br>
Industrious soldiership.
</p>

<p class="drama">
SIWARD.<br>
The time approaches,<br>
That will with due decision make us know<br>
What we shall say we have, and what we owe.<br>
Thoughts speculative their unsure hopes relate,<br>
But certain issue strokes must arbitrate;<br>
Towards which advance the war.
</p>

<p class="right">[<i>Exeunt, marching.</i>]</p>

<h3><a id="sceneV_20.5"></a>
<b>SCENE V. Dunsinane. Within the castle.</b></h3>

<p class="scenedesc">Enter with drum and colours, <span class="charname">Macbeth,
Seyton </span>and Soldiers.</p>

<p class="drama">
MACBETH.<br>
Hang out our banners on the outward walls;<br>
The cry is still, “They come!” Our castle’s strength<br>
Will laugh a siege to scorn: here let them lie<br>
Till famine and the ague eat them up.<br>
Were they not forc’d with those that should be ours,<br>
We might have met them dareful, beard to beard,<br>
And beat them backward home.
</p>

<p class="right">[<i>A cry of women within.</i>]</p>

<p class="drama">
What is that noise?
</p>

<p class="drama">
SEYTON.<br>
It is the cry of women, my good lord.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
MACBETH.<br>
I have almost forgot the taste of fears.<br>
The time has been, my senses would have cool’d<br>
To hear a night-shriek; and my fell of hair<br>
Would at a dismal treatise rouse and stir<br>
As life were in’t. I have supp’d full with horrors;<br>
Direness, familiar to my slaughterous thoughts,<br>
Cannot once start me.
</p>

<p class="scenedesc">Enter <span class="charname">Seyton</span>.</p>

<p class="drama">
Wherefore was that cry?
</p>

<p class="drama">
SEYTON.<br>
The Queen, my lord, is dead.
</p>

<p class="drama">
MACBETH.<br>
She should have died hereafter.<br>
There would have been a time for such a word.<br>
Tomorrow, and tomorrow, and tomorrow,<br>
Creeps in this petty pace from day to day,<br>
To the last syllable of recorded time;<br>
And all our yesterdays have lighted fools<br>
The way to dusty death. Out, out, brief candle!<br>
Life’s but a walking shadow; a poor player,<br>
That struts and frets his hour upon the stage,<br>
And then is heard no more: it is a tale<br>
Told by an idiot, full of sound and fury,<br>
Signifying nothing.
</p>

<p class="scenedesc">Enter a <span class="charname">Messenger</span>.</p>

<p class="drama">
Thou com’st to use thy tongue; thy story quickly.
</p>

<p class="drama">
MESSENGER.<br>
Gracious my lord,<br>
I should report that which I say I saw,<br>
But know not how to do’t.
</p>

<p class="drama">
MACBETH.<br>
Well, say, sir.
</p>

<p class="drama">
MESSENGER.<br>
As I did stand my watch upon the hill,<br>
I look’d toward Birnam, and anon, methought,<br>
The wood began to move.
</p>

<p class="drama">
MACBETH.<br>
Liar, and slave!
</p>

<p class="drama">
MESSENGER.<br>
Let me endure your wrath, if’t be not so.<br>
Within this three mile may you see it coming;<br>
I say, a moving grove.
</p>

<p class="drama">
MACBETH.<br>
If thou speak’st false,<br>
Upon the next tree shalt thou hang alive,<br>
Till famine cling thee: if thy speech be sooth,<br>
I care not if thou dost for me as much.—<br>
I pull in resolution; and begin<br>
To doubt th’ equivocation of the fiend,<br>
That lies like truth. “Fear not, till Birnam wood<br>
Do come to Dunsinane;” and now a wood<br>
Comes toward Dunsinane.—Arm, arm, and out!—<br>
If this which he avouches does appear,<br>
There is nor flying hence nor tarrying here.<br>
I ’gin to be aweary of the sun,<br>
And wish th’ estate o’ th’ world were now undone.—<br>
Ring the alarum bell!—Blow, wind! come, wrack!<br>
At least we’ll die with harness on our back.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3><a id="sceneV_20.6"></a>
<b>SCENE VI. The same. A Plain before the Castle.</b></h3>

<p class="scenedesc">Enter, with drum and colours, <span class="charname">Malcolm,
old Siward, Macduff</span> and their Army, with boughs.</p>

<p class="drama">
MALCOLM.<br>
Now near enough. Your leafy screens throw down,<br>
And show like those you are.—You, worthy uncle,<br>
Shall with my cousin, your right noble son,<br>
Lead our first battle: worthy Macduff and we<br>
Shall take upon’s what else remains to do,<br>
According to our order.
</p>

<p class="drama">
SIWARD.<br>
Fare you well.—<br>
Do we but find the tyrant’s power tonight,<br>
Let us be beaten, if we cannot fight.
</p>

<p class="drama">
MACDUFF.<br>
Make all our trumpets speak; give them all breath,<br>
Those clamorous harbingers of blood and death.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3><a id="sceneV_20.7"></a>
<b>SCENE VII. The same. Another part of the Plain.</b></h3>

<p class="scenedesc">Alarums. Enter <span class="charname">Macbeth</span>.</p>

<p class="drama">
MACBETH.<br>
They have tied me to a stake. I cannot fly,<br>
But, bear-like I must fight the course.—What’s he<br>
That was not born of woman? Such a one<br>
Am I to fear, or none.
</p>

<p class="scenedesc">Enter young <span class="charname">Siward</span>.</p>

<p class="drama">
YOUNG SIWARD.<br>
What is thy name?
</p>

<p class="drama">
MACBETH.<br>
Thou’lt be afraid to hear it.
</p>

<p class="drama">
YOUNG SIWARD.<br>
No; though thou call’st thyself a hotter name<br>
Than any is in hell.
</p>

<p class="drama">
MACBETH.<br>
My name’s Macbeth.
</p>

<p class="drama">
YOUNG SIWARD.<br>
The devil himself could not pronounce a title<br>
More hateful to mine ear.
</p>

<p class="drama">
MACBETH.<br>
No, nor more fearful.
</p>

<p class="drama">
YOUNG SIWARD.<br>
Thou liest, abhorred tyrant. With my sword<br>
I’ll prove the lie thou speak’st.
</p>

<p class="right">[<i>They fight, and young <span class="charname">Siward</span>
is slain.</i>]</p>

<p class="drama">
MACBETH.<br>
Thou wast born of woman.<br>
But swords I smile at, weapons laugh to scorn,<br>
Brandish’d by man that’s of a woman born.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="scenedesc">Alarums. Enter <span class="charname">Macduff</span>.</p>

<p class="drama">
MACDUFF.<br>
That way the noise is.—Tyrant, show thy face!<br>
If thou be’st slain and with no stroke of mine,<br>
My wife and children’s ghosts will haunt me still.<br>
I cannot strike at wretched kerns, whose arms<br>
Are hired to bear their staves. Either thou, Macbeth,<br>
Or else my sword, with an unbatter’d edge,<br>
I sheathe again undeeded. There thou shouldst be;<br>
By this great clatter, one of greatest note<br>
Seems bruited. Let me find him, Fortune!<br>
And more I beg not.
</p>

<p class="right">[<i>Exit. Alarums.</i>]</p>

<p class="scenedesc">Enter <span class="charname">Malcolm</span> and old
<span class="charname">Siward</span>.</p>

<p class="drama">
SIWARD.<br>
This way, my lord;—the castle’s gently render’d:<br>
The tyrant’s people on both sides do fight;<br>
The noble thanes do bravely in the war,<br>
The day almost itself professes yours,<br>
And little is to do.
</p>

<p class="drama">
MALCOLM.<br>
We have met with foes<br>
That strike beside us.
</p>

<p class="drama">
SIWARD.<br>
Enter, sir, the castle.
</p>

<p class="right">[<i>Exeunt. Alarums.</i>]</p>

<h3><a id="sceneV_20.8"></a>
<b>SCENE VIII. The same. Another part of the field.</b></h3>

<p class="scenedesc">Enter <span class="charname">Macbeth</span>.</p>

<p class="drama">
MACBETH.<br>
Why should I play the Roman fool, and die<br>
On mine own sword? whiles I see lives, the gashes<br>
Do better upon them.
</p>

<p class="scenedesc">Enter <span class="charname">Macduff</span>.</p>

<p class="drama">
MACDUFF.<br>
Turn, hell-hound, turn!
</p>

<p class="drama">
MACBETH.<br>
Of all men else I have avoided thee:<br>
But get thee back; my soul is too much charg’d<br>
With blood of thine already.
</p>

<p class="drama">
MACDUFF.<br>
I have no words;<br>
My voice is in my sword: thou bloodier villain<br>
Than terms can give thee out!
</p>

<p class="right">[<i>They fight.</i>]</p>

<p class="drama">
MACBETH.<br>
Thou losest labour:<br>
As easy mayst thou the intrenchant air<br>
With thy keen sword impress, as make me bleed:<br>
Let fall thy blade on vulnerable crests;<br>
I bear a charmed life, which must not yield<br>
To one of woman born.
</p>

<p class="drama">
MACDUFF.<br>
Despair thy charm;<br>
And let the angel whom thou still hast serv’d<br>
Tell thee, Macduff was from his mother’s womb<br>
Untimely ripp’d.
</p>

<p class="drama">
MACBETH.<br>
Accursed be that tongue that tells me so,<br>
For it hath cow’d my better part of man!<br>
And be these juggling fiends no more believ’d,<br>
That palter with us in a double sense;<br>
That keep the word of promise to our ear,<br>
And break it to our hope!—I’ll not fight with thee.
</p>

<p class="drama">
MACDUFF.<br>
Then yield thee, coward,<br>
And live to be the show and gaze o’ th’ time.<br>
We’ll have thee, as our rarer monsters are,<br>
Painted upon a pole, and underwrit,<br>
“Here may you see the tyrant.”
</p>

<p class="drama">
MACBETH.<br>
I will not yield,<br>
To kiss the ground before young Malcolm’s feet,<br>
And to be baited with the rabble’s curse.<br>
Though Birnam wood be come to Dunsinane,<br>
And thou oppos’d, being of no woman born,<br>
Yet I will try the last. Before my body<br>
I throw my warlike shield: lay on, Macduff;<br>
And damn’d be him that first cries, “Hold, enough!”
</p>

<p class="right">[<i>Exeunt fighting. Alarums.</i>]</p>

<p class="scenedesc">Retreat. Flourish. Enter, with drum and colours,
<span class="charname">Malcolm, old Siward, Ross,</span> Thanes and Soldiers.</p>

<p class="drama">
MALCOLM.<br>
I would the friends we miss were safe arriv’d.
</p>

<p class="drama">
SIWARD.<br>
Some must go off; and yet, by these I see,<br>
So great a day as this is cheaply bought.
</p>

<p class="drama">
MALCOLM.<br>
Macduff is missing, and your noble son.
</p>

<p class="drama">
ROSS.<br>
Your son, my lord, has paid a soldier’s debt:<br>
He only liv’d but till he was a man;<br>
The which no sooner had his prowess confirm’d<br>
In the unshrinking station where he fought,<br>
But like a man he died.
</p>

<p class="drama">
SIWARD.<br>
Then he is dead?
</p>

<p class="drama">
ROSS.<br>
Ay, and brought off the field. Your cause of sorrow<br>
Must not be measur’d by his worth, for then<br>
It hath no end.
</p>

<p class="drama">
SIWARD.<br>
Had he his hurts before?
</p>

<p class="drama">
ROSS.<br>
Ay, on the front.
</p>

<p class="drama">
SIWARD.<br>
Why then, God’s soldier be he!<br>
Had I as many sons as I have hairs,<br>
I would not wish them to a fairer death:<br>
And so his knell is knoll’d.
</p>

<p class="drama">
MALCOLM.<br>
He’s worth more sorrow,<br>
And that I’ll spend for him.
</p>

<p class="drama">
SIWARD.<br>
He’s worth no more.<br>
They say he parted well and paid his score:<br>
And so, God be with him!—Here comes newer comfort.
</p>

<p class="scenedesc">Enter <span class="charname">Macduff</span> with
Macbeth’s head.</p>

<p class="drama">
MACDUFF.<br>
Hail, King, for so thou art. Behold, where stands<br>
Th’ usurper’s cursed head: the time is free.<br>
I see thee compass’d with thy kingdom’s pearl,<br>
That speak my salutation in their minds;<br>
Whose voices I desire aloud with mine,—<br>
Hail, King of Scotland!
</p>

<p class="drama">
ALL.<br>
Hail, King of Scotland!
</p>

<p class="right">[<i>Flourish.</i>]</p>

<p class="drama">
MALCOLM.<br>
We shall not spend a large expense of time<br>
Before we reckon with your several loves,<br>
And make us even with you. My thanes and kinsmen,<br>
Henceforth be earls, the first that ever Scotland<br>
In such an honour nam’d. What’s more to do,<br>
Which would be planted newly with the time,—<br>
As calling home our exil’d friends abroad,<br>
That fled the snares of watchful tyranny;<br>
Producing forth the cruel ministers<br>
Of this dead butcher, and his fiend-like queen,<br>
Who, as ’tis thought, by self and violent hands<br>
Took off her life;—this, and what needful else<br>
That calls upon us, by the grace of Grace,<br>
We will perform in measure, time, and place.<br>
So thanks to all at once, and to each one,<br>
Whom we invite to see us crown’d at Scone.
</p>

<p class="right">[<i>Flourish. Exeunt.</i>]</p>

