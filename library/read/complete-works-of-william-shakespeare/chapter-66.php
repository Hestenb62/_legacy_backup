<h2> <a id="sceneIV_11.0"></a><b>ACT IV</b></h2>

<p class="scenedesc"> Enter <span class="charname">Chorus</span>.</p>

<p>CHORUS.<br>
Now entertain conjecture of a time<br>
When creeping murmur and the poring dark<br>
Fills the wide vessel of the universe.<br>
From camp to camp through the foul womb of night<br>
The hum of either army stilly sounds,<br>
That the fix’d sentinels almost receive<br>
The secret whispers of each other’s watch;<br>
Fire answers fire, and through their paly flames<br>
Each battle sees the other’s umber’d face;<br>
Steed threatens steed, in high and boastful neighs<br>
Piercing the night’s dull ear; and from the tents<br>
The armourers, accomplishing the knights,<br>
With busy hammers closing rivets up,<br>
Give dreadful note of preparation.<br>
The country cocks do crow, the clocks do toll,<br>
And the third hour of drowsy morning name.<br>
Proud of their numbers and secure in soul,<br>
The confident and over-lusty French<br>
Do the low-rated English play at dice;<br>
And chide the cripple tardy-gaited Night<br>
Who, like a foul and ugly witch, doth limp<br>
So tediously away. The poor condemned English,<br>
Like sacrifices, by their watchful fires<br>
Sit patiently and inly ruminate<br>
The morning’s danger; and their gesture sad,<br>
Investing lank-lean cheeks and war-worn coats,<br>
Presented them unto the gazing moon<br>
So many horrid ghosts. O now, who will behold<br>
The royal captain of this ruin’d band<br>
Walking from watch to watch, from tent to tent,<br>
Let him cry, “Praise and glory on his head!”<br>
For forth he goes and visits all his host,<br>
Bids them good morrow with a modest smile,<br>
And calls them brothers, friends, and countrymen.<br>
Upon his royal face there is no note<br>
How dread an army hath enrounded him;<br>
Nor doth he dedicate one jot of colour<br>
Unto the weary and all-watched night,<br>
But freshly looks, and over-bears attaint<br>
With cheerful semblance and sweet majesty;<br>
That every wretch, pining and pale before,<br>
Beholding him, plucks comfort from his looks.<br>
A largess universal like the sun<br>
His liberal eye doth give to everyone,<br>
Thawing cold fear, that mean and gentle all<br>
Behold, as may unworthiness define,<br>
A little touch of Harry in the night.<br>
And so our scene must to the battle fly,<br>
Where—O for pity!—we shall much disgrace<br>
With four or five most vile and ragged foils,<br>
Right ill-dispos’d in brawl ridiculous,<br>
The name of Agincourt. Yet sit and see,<br>
Minding true things by what their mock’ries be.
</p>

<p class="right"> [<i>Exit.</i>]</p>

<h3> <a id="sceneIV_11.1"></a><b>SCENE I. The English camp at Agincourt.</b></h3>

<p class="scenedesc"> Enter <span class="charname">King Henry, Bedford</span>
and <span class="charname">Gloucester</span>.</p>

<p>KING HENRY.<br>
Gloucester, ’tis true that we are in great danger;<br>
The greater therefore should our courage be.<br>
Good morrow, brother Bedford. God Almighty!<br>
There is some soul of goodness in things evil,<br>
Would men observingly distil it out;<br>
For our bad neighbour makes us early stirrers,<br>
Which is both healthful and good husbandry.<br>
Besides, they are our outward consciences,<br>
And preachers to us all, admonishing<br>
That we should dress us fairly for our end.<br>
Thus may we gather honey from the weed,<br>
And make a moral of the devil himself.
</p>

<p class="scenedesc"> Enter <span class="charname">Erpingham</span>.</p>

<p>Good morrow, old Sir Thomas Erpingham:<br>
A good soft pillow for that good white head<br>
Were better than a churlish turf of France.
</p>

<p>ERPINGHAM.<br>
Not so, my liege; this lodging likes me better,<br>
Since I may say, “Now lie I like a king.”
</p>

<p>KING HENRY.<br>
’Tis good for men to love their present pains<br>
Upon example; so the spirit is eased;<br>
And when the mind is quick’ned, out of doubt,<br>
The organs, though defunct and dead before,<br>
Break up their drowsy grave and newly move,<br>
With casted slough and fresh legerity.<br>
Lend me thy cloak, Sir Thomas. Brothers both,<br>
Commend me to the princes in our camp;<br>
Do my good morrow to them, and anon<br>
Desire them all to my pavilion.
</p>

<p>GLOUCESTER.<br>
We shall, my liege.
</p>

<p>ERPINGHAM.<br>
Shall I attend your Grace?
</p>

<p>KING HENRY.<br>
No, my good knight;<br>
Go with my brothers to my lords of England.<br>
I and my bosom must debate a while,<br>
And then I would no other company.
</p>

<p>ERPINGHAM.<br>
The Lord in heaven bless thee, noble Harry!
</p>

<p class="right"> [<i>Exeunt all but <span class="charname">King</span>.</i>]</p>

<p>KING HENRY.<br>
God-a-mercy, old heart! thou speak’st cheerfully.
</p>

<p class="scenedesc"> Enter <span class="charname">Pistol</span>.</p>

<p>PISTOL.<br>
<i>Qui vous là?</i>
</p>

<p>KING HENRY.<br>
A friend.
</p>

<p>PISTOL.<br>
Discuss unto me; art thou officer?<br>
Or art thou base, common, and popular?
</p>

<p>KING HENRY.<br>
I am a gentleman of a company.
</p>

<p>PISTOL.<br>
Trail’st thou the puissant pike?
</p>

<p>KING HENRY.<br>
Even so. What are you?
</p>

<p>PISTOL.<br>
As good a gentleman as the Emperor.
</p>

<p>KING HENRY.<br>
Then you are a better than the King.
</p>

<p>PISTOL.<br>
The King’s a bawcock, and a heart of gold,<br>
A lad of life, an imp of fame;<br>
Of parents good, of fist most valiant.<br>
I kiss his dirty shoe, and from heart-string<br>
I love the lovely bully. What is thy name?
</p>

<p>KING HENRY.<br>
Harry le Roy.
</p>

<p>PISTOL.<br>
Le Roy! a Cornish name. Art thou of Cornish crew?
</p>

<p>KING HENRY.<br>
No, I am a Welshman.
</p>

<p>PISTOL.<br>
Know’st thou Fluellen?
</p>

<p>KING HENRY.<br>
Yes.
</p>

<p>PISTOL.<br>
Tell him I’ll knock his leek about his pate<br>
Upon Saint Davy’s day.
</p>

<p>KING HENRY.<br>
Do not you wear your dagger in your cap that day, lest he knock that about
yours.
</p>

<p>PISTOL.<br>
Art thou his friend?
</p>

<p>KING HENRY.<br>
And his kinsman too.
</p>

<p>PISTOL.<br>
The <i>fico</i> for thee, then!
</p>

<p>KING HENRY.<br>
I thank you. God be with you!
</p>

<p>PISTOL.<br>
My name is Pistol call’d.
</p>

<p class="right"> [<i>Exit.</i>]</p>

<p>KING HENRY.<br>
It sorts well with your fierceness.
</p>

<p class="scenedesc"> Enter <span class="charname">Fluellen</span> and <span class="charname">Gower</span>.</p>

<p>GOWER.<br>
Captain Fluellen!
</p>

<p>FLUELLEN.<br>
So! in the name of Jesu Christ, speak lower. It is the greatest admiration in
the universal world, when the true and anchient prerogatifes and laws of the
wars is not kept. If you would take the pains but to examine the wars of Pompey
the Great, you shall find, I warrant you, that there is no tiddle taddle nor
pibble pabble in Pompey’s camp. I warrant you, you shall find the
ceremonies of the wars, and the cares of it, and the forms of it, and the
sobriety of it, and the modesty of it, to be otherwise.
</p>

<p>GOWER.<br>
Why, the enemy is loud; you hear him all night.
</p>

<p>FLUELLEN.<br>
If the enemy is an ass and a fool and a prating coxcomb, is it meet, think you,
that we should also, look you, be an ass and a fool and a prating coxcomb? In
your own conscience, now?
</p>

<p>GOWER.<br>
I will speak lower.
</p>

<p>FLUELLEN.<br>
I pray you and beseech you that you will.
</p>

<p class="right"> [<i>Exeunt <span class="charname">Gower</span> and <span class="charname">Fluellen</span>.</i>]</p>

<p>KING HENRY.<br>
Though it appear a little out of fashion,<br>
There is much care and valour in this Welshman.
</p>

<p class="scenedesc"> Enter three soldiers, <span class="charname">John Bates,
Alexander Court</span> and <span class="charname">Michael Williams</span>.</p>

<p>COURT.<br>
Brother John Bates, is not that the morning which breaks yonder?
</p>

<p>BATES.<br>
I think it be; but we have no great cause to desire the approach of day.
</p>

<p>WILLIAMS.<br>
We see yonder the beginning of the day, but I think we shall never see the end
of it. Who goes there?
</p>

<p>KING HENRY.<br>
A friend.
</p>

<p>WILLIAMS.<br>
Under what captain serve you?
</p>

<p>KING HENRY.<br>
Under Sir Thomas Erpingham.
</p>

<p>WILLIAMS.<br>
A good old commander and a most kind gentleman. I pray you, what thinks he of
our estate?
</p>

<p>KING HENRY.<br>
Even as men wreck’d upon a sand, that look to be wash’d off the
next tide.
</p>

<p>BATES.<br>
He hath not told his thought to the King?
</p>

<p>KING HENRY.<br>
No; nor it is not meet he should. For though I speak it to you, I think the
King is but a man as I am. The violet smells to him as it doth to me; the
element shows to him as it doth to me; all his senses have but human
conditions. His ceremonies laid by, in his nakedness he appears but a man; and
though his affections are higher mounted than ours, yet, when they stoop, they
stoop with the like wing. Therefore, when he sees reason of fears as we do, his
fears, out of doubt, be of the same relish as ours are; yet, in reason, no man
should possess him with any appearance of fear, lest he, by showing it, should
dishearten his army.
</p>

<p>BATES.<br>
He may show what outward courage he will; but I believe, as cold a night as
’tis, he could wish himself in Thames up to the neck; and so I would he
were, and I by him, at all adventures, so we were quit here.
</p>

<p>KING HENRY.<br>
By my troth, I will speak my conscience of the King: I think he would not wish
himself anywhere but where he is.
</p>

<p>BATES.<br>
Then I would he were here alone; so should he be sure to be ransomed, and a
many poor men’s lives saved.
</p>

<p>KING HENRY.<br>
I dare say you love him not so ill, to wish him here alone, howsoever you speak
this to feel other men’s minds. Methinks I could not die anywhere so
contented as in the King’s company, his cause being just and his quarrel
honourable.
</p>

<p>WILLIAMS.<br>
That’s more than we know.
</p>

<p>BATES.<br>
Ay, or more than we should seek after; for we know enough, if we know we are
the King’s subjects. If his cause be wrong, our obedience to the King
wipes the crime of it out of us.
</p>

<p>WILLIAMS.<br>
But if the cause be not good, the King himself hath a heavy reckoning to make,
when all those legs and arms and heads, chopp’d off in a battle, shall
join together at the latter day and cry all, “We died at such a
place”; some swearing, some crying for a surgeon, some upon their wives
left poor behind them, some upon the debts they owe, some upon their children
rawly left. I am afeard there are few die well that die in a battle; for how
can they charitably dispose of anything, when blood is their argument? Now, if
these men do not die well, it will be a black matter for the King that led them
to it; who to disobey were against all proportion of subjection.
</p>

<p>KING HENRY.<br>
So, if a son that is by his father sent about merchandise do sinfully miscarry
upon the sea, the imputation of his wickedness, by your rule, should be imposed
upon his father that sent him; or if a servant, under his master’s
command transporting a sum of money, be assailed by robbers and die in many
irreconcil’d iniquities, you may call the business of the master the
author of the servant’s damnation. But this is not so. The King is not
bound to answer the particular endings of his soldiers, the father of his son,
nor the master of his servant; for they purpose not their death, when they
purpose their services. Besides, there is no king, be his cause never so
spotless, if it come to the arbitrement of swords, can try it out with all
unspotted soldiers. Some peradventure have on them the guilt of premeditated
and contrived murder; some, of beguiling virgins with the broken seals of
perjury; some, making the wars their bulwark, that have before gored the gentle
bosom of Peace with pillage and robbery. Now, if these men have defeated the
law and outrun native punishment, though they can outstrip men, they have no
wings to fly from God. War is his beadle, war is his vengeance; so that here
men are punish’d for before-breach of the King’s laws in now the
King’s quarrel. Where they feared the death, they have borne life away;
and where they would be safe, they perish. Then if they die unprovided, no more
is the King guilty of their damnation than he was before guilty of those
impieties for the which they are now visited. Every subject’s duty is the
King’s; but every subject’s soul is his own. Therefore should every
soldier in the wars do as every sick man in his bed, wash every mote out of his
conscience; and dying so, death is to him advantage; or not dying, the time was
blessedly lost wherein such preparation was gained; and in him that escapes, it
were not sin to think that, making God so free an offer, He let him outlive
that day to see His greatness and to teach others how they should prepare.
</p>

<p>WILLIAMS.<br>
’Tis certain, every man that dies ill, the ill upon his own head, the
King is not to answer for it.
</p>

<p>BATES.<br>
I do not desire he should answer for me; and yet I determine to fight lustily
for him.
</p>

<p>KING HENRY.<br>
I myself heard the King say he would not be ransom’d.
</p>

<p>WILLIAMS.<br>
Ay, he said so, to make us fight cheerfully; but when our throats are cut, he
may be ransom’d, and we ne’er the wiser.
</p>

<p>KING HENRY.<br>
If I live to see it, I will never trust his word after.
</p>

<p>WILLIAMS.<br>
You pay him then. That’s a perilous shot out of an elder-gun, that a poor
and a private displeasure can do against a monarch! You may as well go about to
turn the sun to ice with fanning in his face with a peacock’s feather.
You’ll never trust his word after! Come, ’tis a foolish saying.
</p>

<p>KING HENRY.<br>
Your reproof is something too round. I should be angry with you, if the time
were convenient.
</p>

<p>WILLIAMS.<br>
Let it be a quarrel between us if you live.
</p>

<p>KING HENRY.<br>
I embrace it.
</p>

<p>WILLIAMS.<br>
How shall I know thee again?
</p>

<p>KING HENRY.<br>
Give me any gage of thine, and I will wear it in my bonnet; then, if ever thou
dar’st acknowledge it, I will make it my quarrel.
</p>

<p>WILLIAMS.<br>
Here’s my glove; give me another of thine.
</p>

<p>KING HENRY.<br>
There.
</p>

<p>WILLIAMS.<br>
This will I also wear in my cap. If ever thou come to me and say, after
tomorrow, “This is my glove,” by this hand I will take thee a box
on the ear.
</p>

<p>KING HENRY.<br>
If ever I live to see it, I will challenge it.
</p>

<p>WILLIAMS.<br>
Thou dar’st as well be hang’d.
</p>

<p>KING HENRY.<br>
Well, I will do it, though I take thee in the King’s company.
</p>

<p>WILLIAMS.<br>
Keep thy word; fare thee well.
</p>

<p>BATES.<br>
Be friends, you English fools, be friends. We have French quarrels enough, if
you could tell how to reckon.
</p>

<p>KING HENRY.<br>
Indeed, the French may lay twenty French crowns to one they will beat us, for
they bear them on their shoulders; but it is no English treason to cut French
crowns, and tomorrow the King himself will be a clipper.
</p>

<p class="right"> [<i>Exeunt soldiers.</i>]</p>

<p> Upon the King! Let us our lives, our souls,<br>
Our debts, our careful wives,<br>
Our children, and our sins lay on the King!<br>
We must bear all. O hard condition,<br>
Twin-born with greatness, subject to the breath<br>
Of every fool, whose sense no more can feel<br>
But his own wringing! What infinite heart’s ease<br>
Must kings neglect, that private men enjoy!<br>
And what have kings, that privates have not too,<br>
Save ceremony, save general ceremony?<br>
And what art thou, thou idol Ceremony?<br>
What kind of god art thou, that suffer’st more<br>
Of mortal griefs than do thy worshippers?<br>
What are thy rents? What are thy comings in?<br>
O Ceremony, show me but thy worth!<br>
What is thy soul of adoration?<br>
Art thou aught else but place, degree, and form,<br>
Creating awe and fear in other men?<br>
Wherein thou art less happy being fear’d<br>
Than they in fearing.<br>
What drink’st thou oft, instead of homage sweet,<br>
But poison’d flattery? O, be sick, great greatness,<br>
And bid thy Ceremony give thee cure!<br>
Think’st thou the fiery fever will go out<br>
With titles blown from adulation?<br>
Will it give place to flexure and low bending?<br>
Canst thou, when thou command’st the beggar’s knee,<br>
Command the health of it? No, thou proud dream,<br>
That play’st so subtly with a king’s repose;<br>
I am a king that find thee, and I know<br>
’Tis not the balm, the sceptre, and the ball,<br>
The sword, the mace, the crown imperial,<br>
The intertissued robe of gold and pearl,<br>
The farced title running ’fore the King,<br>
The throne he sits on, nor the tide of pomp<br>
That beats upon the high shore of this world,<br>
No, not all these, thrice-gorgeous Ceremony,—<br>
Not all these, laid in bed majestical,<br>
Can sleep so soundly as the wretched slave,<br>
Who with a body fill’d and vacant mind<br>
Gets him to rest, cramm’d with distressful bread,<br>
Never sees horrid night, the child of hell,<br>
But, like a lackey, from the rise to set<br>
Sweats in the eye of Phoebus, and all night<br>
Sleeps in Elysium; next day after dawn,<br>
Doth rise and help Hyperion to his horse,<br>
And follows so the ever-running year,<br>
With profitable labour, to his grave:<br>
And, but for ceremony, such a wretch,<br>
Winding up days with toil and nights with sleep,<br>
Had the fore-hand and vantage of a king.<br>
The slave, a member of the country’s peace,<br>
Enjoys it, but in gross brain little wots<br>
What watch the King keeps to maintain the peace,<br>
Whose hours the peasant best advantages.
</p>

<p class="scenedesc"> Enter <span class="charname">Erpingham</span>.</p>

<p>ERPINGHAM.<br>
My lord, your nobles, jealous of your absence,<br>
Seek through your camp to find you.
</p>

<p>KING HENRY.<br>
Good old knight,<br>
Collect them all together at my tent.<br>
I’ll be before thee.
</p>

<p>ERPINGHAM.<br>
I shall do’t, my lord.
</p>

<p class="right"> [<i>Exit.</i>]</p>

<p>KING HENRY.<br>
O God of battles! steel my soldiers’ hearts.<br>
Possess them not with fear. Take from them now<br>
The sense of reckoning, if the opposed numbers<br>
Pluck their hearts from them. Not today, O Lord,<br>
O, not today, think not upon the fault<br>
My father made in compassing the crown!<br>
I Richard’s body have interred new,<br>
And on it have bestow’d more contrite tears<br>
Than from it issued forced drops of blood.<br>
Five hundred poor I have in yearly pay,<br>
Who twice a day their wither’d hands hold up<br>
Toward heaven, to pardon blood; and I have built<br>
Two chantries, where the sad and solemn priests<br>
Sing still for Richard’s soul. More will I do;<br>
Though all that I can do is nothing worth,<br>
Since that my penitence comes after all,<br>
Imploring pardon.
</p>

<p class="scenedesc"> Enter <span class="charname">Gloucester</span>.</p>

<p>GLOUCESTER.<br>
My liege!
</p>

<p>KING HENRY.<br>
My brother Gloucester’s voice? Ay;<br>
I know thy errand, I will go with thee.<br>
The day, my friends, and all things stay for me.
</p>

<p class="right"> [<i>Exeunt.</i>]</p>

<h3> <a id="sceneIV_11.2"></a><b>SCENE II. The French camp.</b></h3>

<p class="scenedesc"> Enter the <span class="charname">Dauphin, Orleans,
Rambures</span> and others.</p>

<p>ORLEANS.<br>
The sun doth gild our armour; up, my lords!
</p>

<p>DAUPHIN.<br>
<i>Monte à cheval!</i> My horse, <i>varlet! laquais</i>, ha!
</p>

<p>ORLEANS.<br>
O brave spirit!
</p>

<p>DAUPHIN.<br>
<i>Via, les eaux et terre!</i>
</p>

<p>ORLEANS.<br>
<i>Rien puis? L’air et feu?</i>
</p>

<p>DAUPHIN.<br>
<i>Cieux</i>, cousin Orleans.
</p>

<p class="scenedesc"> Enter <span class="charname">Constable</span>.</p>

<p>Now, my Lord Constable!
</p>

<p>CONSTABLE.<br>
Hark, how our steeds for present service neigh!
</p>

<p>DAUPHIN.<br>
Mount them, and make incision in their hides,<br>
That their hot blood may spin in English eyes,<br>
And dout them with superfluous courage, ha!
</p>

<p>RAMBURES.<br>
What, will you have them weep our horses’ blood?<br>
How shall we, then, behold their natural tears?
</p>

<p class="scenedesc"> Enter a <span class="charname">Messenger</span>.</p>

<p>MESSENGER.<br>
The English are embattl’d, you French peers.
</p>

<p>CONSTABLE.<br>
To horse, you gallant princes! straight to horse!<br>
Do but behold yon poor and starved band,<br>
And your fair show shall suck away their souls,<br>
Leaving them but the shales and husks of men.<br>
There is not work enough for all our hands;<br>
Scarce blood enough in all their sickly veins<br>
To give each naked curtle-axe a stain,<br>
That our French gallants shall today draw out,<br>
And sheathe for lack of sport. Let us but blow on them,<br>
The vapour of our valour will o’erturn them.<br>
’Tis positive ’gainst all exceptions, lords,<br>
That our superfluous lackeys and our peasants,<br>
Who in unnecessary action swarm<br>
About our squares of battle, were enough<br>
To purge this field of such a hilding foe,<br>
Though we upon this mountain’s basis by<br>
Took stand for idle speculation,<br>
But that our honours must not. What’s to say?<br>
A very little little let us do,<br>
And all is done. Then let the trumpets sound<br>
The tucket sonance and the note to mount;<br>
For our approach shall so much dare the field<br>
That England shall crouch down in fear and yield.
</p>

<p class="scenedesc"> Enter <span class="charname">Grandpré</span>.</p>

<p>GRANDPRÉ.<br>
Why do you stay so long, my lords of France?<br>
Yond island carrions, desperate of their bones,<br>
Ill-favouredly become the morning field.<br>
Their ragged curtains poorly are let loose,<br>
And our air shakes them passing scornfully.<br>
Big Mars seems bankrupt in their beggar’d host,<br>
And faintly through a rusty beaver peeps;<br>
The horsemen sit like fixed candlesticks<br>
With torch-staves in their hand; and their poor jades<br>
Lob down their heads, drooping the hides and hips,<br>
The gum down-roping from their pale-dead eyes,<br>
And in their pale dull mouths the gimmal bit<br>
Lies foul with chew’d grass, still, and motionless;<br>
And their executors, the knavish crows,<br>
Fly o’er them, all impatient for their hour.<br>
Description cannot suit itself in words<br>
To demonstrate the life of such a battle,<br>
In life so lifeless as it shows itself.
</p>

<p>CONSTABLE.<br>
They have said their prayers, and they stay for death.
</p>

<p>DAUPHIN.<br>
Shall we go send them dinners and fresh suits<br>
And give their fasting horses provender,<br>
And after fight with them?
</p>

<p>CONSTABLE.<br>
I stay but for my guard; on to the field!<br>
I will the banner from a trumpet take,<br>
And use it for my haste. Come, come, away!<br>
The sun is high, and we outwear the day.
</p>

<p class="right"> [<i>Exeunt.</i>]</p>

<h3> <a id="sceneIV_11.3"></a><b>SCENE III. The English camp.</b></h3>

<p class="scenedesc"> Enter <span class="charname">Gloucester, Bedford, Exeter,
Erpingham,</span> with all his host: <span class="charname">Salisbury</span>
and <span class="charname">Westmorland</span>.</p>

<p>GLOUCESTER.<br>
Where is the King?
</p>

<p>BEDFORD.<br>
The King himself is rode to view their battle.
</p>

<p>WESTMORLAND.<br>
Of fighting men they have full three-score thousand.
</p>

<p>EXETER.<br>
There’s five to one; besides, they all are fresh.
</p>

<p>SALISBURY.<br>
God’s arm strike with us! ’tis a fearful odds.<br>
God be wi’ you, princes all; I’ll to my charge.<br>
If we no more meet till we meet in heaven,<br>
Then, joyfully, my noble Lord of Bedford,<br>
My dear Lord Gloucester, and my good Lord Exeter,<br>
And my kind kinsman, warriors all, adieu!
</p>

<p>BEDFORD.<br>
Farewell, good Salisbury, and good luck go with thee!
</p>

<p>EXETER.<br>
Farewell, kind lord; fight valiantly today!<br>
And yet I do thee wrong to mind thee of it,<br>
For thou art fram’d of the firm truth of valour.
</p>

<p class="right"> [<i>Exit <span class="charname">Salisbury</span>.</i>]</p>

<p>BEDFORD.<br>
He is as full of valour as of kindness,<br>
Princely in both.
</p>

<p class="scenedesc"> Enter the <span class="charname">King</span>.</p>

<p>WESTMORLAND.<br>
O that we now had here<br>
But one ten thousand of those men in England<br>
That do no work today!
</p>

<p>KING.<br>
What’s he that wishes so?<br>
My cousin Westmorland? No, my fair cousin.<br>
If we are mark’d to die, we are enough<br>
To do our country loss; and if to live,<br>
The fewer men, the greater share of honour.<br>
God’s will! I pray thee, wish not one man more.<br>
By Jove, I am not covetous for gold,<br>
Nor care I who doth feed upon my cost;<br>
It yearns me not if men my garments wear;<br>
Such outward things dwell not in my desires;<br>
But if it be a sin to covet honour,<br>
I am the most offending soul alive.<br>
No, faith, my coz, wish not a man from England.<br>
God’s peace! I would not lose so great an honour<br>
As one man more, methinks, would share from me<br>
For the best hope I have. O, do not wish one more!<br>
Rather proclaim it, Westmorland, through my host,<br>
That he which hath no stomach to this fight,<br>
Let him depart. His passport shall be made,<br>
And crowns for convoy put into his purse.<br>
We would not die in that man’s company<br>
That fears his fellowship to die with us.<br>
This day is call’d the feast of Crispian.<br>
He that outlives this day, and comes safe home,<br>
Will stand a tip-toe when this day is named,<br>
And rouse him at the name of Crispian.<br>
He that shall live this day, and see old age,<br>
Will yearly on the vigil feast his neighbours,<br>
And say, “Tomorrow is Saint Crispian.”<br>
Then will he strip his sleeve and show his scars,<br>
And say, “These wounds I had on Crispian’s day.”<br>
Old men forget; yet all shall be forgot,<br>
But he’ll remember with advantages<br>
What feats he did that day. Then shall our names,<br>
Familiar in his mouth as household words,<br>
Harry the King, Bedford, and Exeter,<br>
Warwick and Talbot, Salisbury and Gloucester,<br>
Be in their flowing cups freshly remembered.<br>
This story shall the good man teach his son;<br>
And Crispin Crispian shall ne’er go by,<br>
From this day to the ending of the world,<br>
But we in it shall be remembered,<br>
We few, we happy few, we band of brothers.<br>
For he today that sheds his blood with me<br>
Shall be my brother; be he ne’er so vile,<br>
This day shall gentle his condition;<br>
And gentlemen in England now abed<br>
Shall think themselves accurs’d they were not here,<br>
And hold their manhoods cheap whiles any speaks<br>
That fought with us upon Saint Crispin’s day.
</p>

<p class="scenedesc"> Enter <span class="charname">Salisbury</span>.</p>

<p>SALISBURY.<br>
My sovereign lord, bestow yourself with speed.<br>
The French are bravely in their battles set,<br>
And will with all expedience charge on us.
</p>

<p>KING HENRY.<br>
All things are ready, if our minds be so.
</p>

<p>WESTMORLAND.<br>
Perish the man whose mind is backward now!
</p>

<p>KING HENRY.<br>
Thou dost not wish more help from England, coz?
</p>

<p>WESTMORLAND.<br>
God’s will! my liege, would you and I alone,<br>
Without more help, could fight this royal battle!
</p>

<p>KING HENRY.<br>
Why, now thou hast unwish’d five thousand men,<br>
Which likes me better than to wish us one.<br>
You know your places. God be with you all!
</p>

<p class="scenedesc"> Tucket. Enter <span class="charname">Montjoy</span>.</p>

<p>MONTJOY.<br>
Once more I come to know of thee, King Harry,<br>
If for thy ransom thou wilt now compound,<br>
Before thy most assured overthrow;<br>
For certainly thou art so near the gulf,<br>
Thou needs must be englutted. Besides, in mercy,<br>
The Constable desires thee thou wilt mind<br>
Thy followers of repentance; that their souls<br>
May make a peaceful and a sweet retire<br>
From off these fields, where, wretches, their poor bodies<br>
Must lie and fester.
</p>

<p>KING HENRY.<br>
Who hath sent thee now?
</p>

<p>MONTJOY.<br>
The Constable of France.
</p>

<p>KING HENRY.<br>
I pray thee, bear my former answer back:<br>
Bid them achieve me and then sell my bones.<br>
Good God! why should they mock poor fellows thus?<br>
The man that once did sell the lion’s skin<br>
While the beast liv’d, was kill’d with hunting him.<br>
A many of our bodies shall no doubt<br>
Find native graves, upon the which, I trust,<br>
Shall witness live in brass of this day’s work;<br>
And those that leave their valiant bones in France,<br>
Dying like men, though buried in your dunghills,<br>
They shall be fam’d; for there the sun shall greet them,<br>
And draw their honours reeking up to heaven;<br>
Leaving their earthly parts to choke your clime,<br>
The smell whereof shall breed a plague in France.<br>
Mark then abounding valour in our English,<br>
That being dead, like to the bullet’s grazing,<br>
Break out into a second course of mischief,<br>
Killing in relapse of mortality.<br>
Let me speak proudly: tell the Constable<br>
We are but warriors for the working-day.<br>
Our gayness and our gilt are all besmirch’d<br>
With rainy marching in the painful field;<br>
There’s not a piece of feather in our host—<br>
Good argument, I hope, we will not fly—<br>
And time hath worn us into slovenry;<br>
But, by the mass, our hearts are in the trim;<br>
And my poor soldiers tell me, yet ere night<br>
They’ll be in fresher robes, or they will pluck<br>
The gay new coats o’er the French soldiers’ heads<br>
And turn them out of service. If they do this—<br>
As, if God please, they shall,—my ransom then<br>
Will soon be levied. Herald, save thou thy labour.<br>
Come thou no more for ransom, gentle herald.<br>
They shall have none, I swear, but these my joints;<br>
Which if they have as I will leave ’em them,<br>
Shall yield them little, tell the Constable.
</p>

<p>MONTJOY.<br>
I shall, King Harry. And so fare thee well;<br>
Thou never shalt hear herald any more.
</p>

<p class="right"> [<i>Exit.</i>]</p>

<p>KING HENRY.<br>
I fear thou’lt once more come again for ransom.
</p>

<p class="scenedesc"> Enter <span class="charname">York</span>.</p>

<p>YORK.<br>
My lord, most humbly on my knee I beg<br>
The leading of the vaward.
</p>

<p>KING HENRY.<br>
Take it, brave York. Now, soldiers, march away;<br>
And how thou pleasest, God, dispose the day!
</p>

<p class="right"> [<i>Exeunt.</i>]</p>

<h3> <a id="sceneIV_11.4"></a><b>SCENE IV. The field of battle.</b></h3>

<p class="scenedesc"> Alarum. Excursions. Enter <span class="charname">Pistol,
French Soldier</span> and <span class="charname">Boy</span>.</p>

<p>PISTOL.<br>
Yield, cur!
</p>

<p>FRENCH SOLDIER.<br>
<i>Je pense que vous êtes le gentilhomme de bonne qualité.</i>
</p>

<p>PISTOL.<br>
<i>Qualité? Caleno custore me!</i><br>
Art thou a gentleman?<br>
What is thy name? Discuss.
</p>

<p>FRENCH SOLDIER.<br>
<i>O Seigneur Dieu!</i>
</p>

<p>PISTOL.<br>
O, Signieur Dew should be a gentleman.<br>
Perpend my words, O Signieur Dew, and mark:<br>
O Signieur Dew, thou diest on point of fox,<br>
Except, O signieur, thou do give to me<br>
Egregious ransom.
</p>

<p>FRENCH SOLDIER.<br>
<i>O, prenez miséricorde! Ayez pitié de moi!</i>
</p>

<p>PISTOL.<br>
Moy shall not serve; I will have forty moys,<br>
Or I will fetch thy rim out at thy throat<br>
In drops of crimson blood.
</p>

<p>FRENCH SOLDIER.<br>
<i>Est-il impossible d’échapper la force de ton bras?</i>
</p>

<p>PISTOL.<br>
Brass, cur!<br>
Thou damned and luxurious mountain goat,<br>
Offer’st me brass?
</p>

<p>FRENCH SOLDIER.<br>
<i>O pardonnez-moi!</i>
</p>

<p>PISTOL.<br>
Say’st thou me so? Is that a ton of moys?<br>
Come hither, boy; ask me this slave in French<br>
What is his name.
</p>

<p>BOY.<br>
<i>Écoutez. Comment êtes-vous appelé?</i>
</p>

<p>FRENCH SOLDIER.<br>
<i>Monsieur le Fer.</i>
</p>

<p>BOY.<br>
He says his name is Master Fer.
</p>

<p>PISTOL.<br>
Master Fer! I’ll fer him, and firk him, and ferret him.<br>
Discuss the same in French unto him.
</p>

<p>BOY.<br>
I do not know the French for fer, and ferret, and firk.
</p>

<p>PISTOL.<br>
Bid him prepare; for I will cut his throat.
</p>

<p>FRENCH SOLDIER.<br>
<i>Que dit-il, monsieur?</i>
</p>

<p>BOY.<br>
<i>Il me commande à vous dire que vous faites vous prêt, car ce soldat ici est
disposé tout à cette heure de couper votre gorge.</i>
</p>

<p>PISTOL.<br>
Owy, cuppele gorge, permafoy,<br>
Peasant, unless thou give me crowns, brave crowns;<br>
Or mangled shalt thou be by this my sword.
</p>

<p>FRENCH SOLDIER.<br>
<i>O, je vous supplie, pour l’amour de Dieu, me pardonner! Je suis le
gentilhomme de bonne maison; gardez ma vie, et je vous donnerai deux cents
écus.</i>
</p>

<p>PISTOL.<br>
What are his words?
</p>

<p>BOY.<br>
He prays you to save his life. He is a gentleman of a good house; and for his
ransom he will give you two hundred crowns.
</p>

<p>PISTOL.<br>
Tell him my fury shall abate, and I<br>
The crowns will take.
</p>

<p>FRENCH SOLDIER.<br>
<i>Petit monsieur, que dit-il?</i>
</p>

<p>BOY.<br>
<i>Encore qu’il est contre son jurement de pardonner aucun prisonnier;
néanmoins, pour les écus que vous lui avez promis, il est content à vous
donner la liberté, le franchisement.</i>
</p>

<p>FRENCH SOLDIER.<br>
<i>Sur mes genoux je vous donne mille remerciements; et je m’estime
heureux que je suis tombé entre les mains d’un chevalier, je pense, le
plus brave, vaillant, et très distingué seigneur d’Angleterre.</i>
</p>

<p>PISTOL.<br>
Expound unto me, boy.
</p>

<p>BOY.<br>
He gives you upon his knees, a thousand thanks; and he esteems himself happy
that he hath fallen into the hands of one, as he thinks, the most brave,
valorous, and thrice-worthy <i>seigneur</i> of England.
</p>

<p>PISTOL.<br>
As I suck blood, I will some mercy show.<br>
Follow me!
</p>

<p>BOY.<br>
<i>Suivez-vous le grand capitaine.</i>
</p>

<p class="right"> [<i>Exeunt <span class="charname">Pistol</span> and <span class="charname">French Soldier</span>.</i>]</p>

<p>I did never know so full a voice issue from so empty a heart; but the saying
is true, “The empty vessel makes the greatest sound.” Bardolph and
Nym had ten times more valour than this roaring devil i’ the old play,
that everyone may pare his nails with a wooden dagger; and they are both
hang’d; and so would this be, if he durst steal anything adventurously. I
must stay with the lackeys with the luggage of our camp. The French might have
a good prey of us, if he knew of it; for there is none to guard it but
boys.
</p>

<p class="right"> [<i>Exit.</i>]</p>

<h3> <a id="sceneIV_11.5"></a><b>SCENE V. Another part of the field.</b></h3>

<p class="scenedesc"> Enter <span class="charname">Constable, Orleans, Bourbon,
Dauphin</span> and <span class="charname">Rambures</span>.</p>

<p>CONSTABLE.<br>
<i>O diable!</i>
</p>

<p>ORLEANS.<br>
<i>O Seigneur! le jour est perdu, tout est perdu!</i>
</p>

<p>DAUPHIN.<br>
<i>Mort de ma vie!</i> all is confounded, all!<br>
Reproach and everlasting shame<br>
Sits mocking in our plumes.
</p>

<p class="right"> [<i>A short alarum.</i>]</p>

<p><i>O méchante Fortune!</i> Do not run away.
</p>

<p>CONSTABLE.<br>
Why, all our ranks are broke.
</p>

<p>DAUPHIN.<br>
O perdurable shame! Let’s stab ourselves,<br>
Be these the wretches that we play’d at dice for?
</p>

<p>ORLEANS.<br>
Is this the king we sent to for his ransom?
</p>

<p>BOURBON.<br>
Shame and eternal shame, nothing but shame!<br>
Let’s die in honour! Once more back again!<br>
And he that will not follow Bourbon now,<br>
Let him go hence, and with his cap in hand,<br>
Like a base pandar, hold the chamber door<br>
Whilst by a slave, no gentler than my dog,<br>
His fairest daughter is contaminated.
</p>

<p>CONSTABLE.<br>
Disorder, that hath spoil’d us, friend us now!<br>
Let us on heaps go offer up our lives.
</p>

<p>ORLEANS.<br>
We are enough yet living in the field<br>
To smother up the English in our throngs,<br>
If any order might be thought upon.
</p>

<p>BOURBON.<br>
The devil take order now! I’ll to the throng.<br>
Let life be short, else shame will be too long.
</p>

<p class="right"> [<i>Exeunt.</i>]</p>

<h3> <a id="sceneIV_11.6"></a><b>SCENE VI. Another part of the field.</b></h3>

<p class="scenedesc"> Alarum. Enter <span class="charname">King Henry</span>
and his train, with prisoners.</p>

<p>KING HENRY.<br>
Well have we done, thrice valiant countrymen.<br>
But all’s not done; yet keep the French the field.
</p>

<p>EXETER.<br>
The Duke of York commends him to your Majesty.
</p>

<p>KING HENRY.<br>
Lives he, good uncle? Thrice within this hour<br>
I saw him down; thrice up again, and fighting.<br>
From helmet to the spur all blood he was.
</p>

<p>EXETER.<br>
In which array, brave soldier, doth he lie,<br>
Larding the plain; and by his bloody side,<br>
Yoke-fellow to his honour-owing wounds,<br>
The noble Earl of Suffolk also lies.<br>
Suffolk first died; and York, all haggled over,<br>
Comes to him, where in gore he lay insteeped,<br>
And takes him by the beard; kisses the gashes<br>
That bloodily did yawn upon his face.<br>
He cries aloud, “Tarry, my cousin Suffolk!<br>
My soul shall thine keep company to heaven;<br>
Tarry, sweet soul, for mine, then fly abreast,<br>
As in this glorious and well-foughten field<br>
We kept together in our chivalry.”<br>
Upon these words I came and cheer’d him up.<br>
He smil’d me in the face, raught me his hand,<br>
And, with a feeble gripe, says, “Dear my lord,<br>
Commend my service to my sovereign.”<br>
So did he turn and over Suffolk’s neck<br>
He threw his wounded arm and kiss’d his lips;<br>
And so espous’d to death, with blood he seal’d<br>
A testament of noble-ending love.<br>
The pretty and sweet manner of it forc’d<br>
Those waters from me which I would have stopp’d;<br>
But I had not so much of man in me,<br>
And all my mother came into mine eyes<br>
And gave me up to tears.
</p>

<p>KING HENRY.<br>
I blame you not;<br>
For, hearing this, I must perforce compound<br>
With mistful eyes, or they will issue too.
</p>

<p class="right"> [<i>Alarum.</i>]</p>

<p>But hark! what new alarum is this same?<br>
The French have reinforc’d their scatter’d men.<br>
Then every soldier kill his prisoners;<br>
Give the word through.
</p>

<p class="right"> [<i>Exeunt.</i>]</p>

<h3> <a id="sceneIV_11.7"></a><b>SCENE VII. Another part of the field.</b></h3>

<p class="scenedesc"> Enter <span class="charname">Fluellen</span> and <span class="charname">Gower</span>.</p>

<p>FLUELLEN.<br>
Kill the poys and the luggage! ’Tis expressly against the law of arms.
’Tis as arrant a piece of knavery, mark you now, as can be offer’t;
in your conscience, now, is it not?
</p>

<p>GOWER.<br>
’Tis certain there’s not a boy left alive; and the cowardly rascals
that ran from the battle ha’ done this slaughter. Besides, they have
burned and carried away all that was in the King’s tent; wherefore the
King, most worthily, hath caus’d every soldier to cut his
prisoner’s throat. O, ’tis a gallant king!
</p>

<p>FLUELLEN.<br>
Ay, he was porn at Monmouth, Captain Gower. What call you the town’s name
where Alexander the Pig was born?
</p>

<p>GOWER.<br>
Alexander the Great.
</p>

<p>FLUELLEN.<br>
Why, I pray you, is not pig great? The pig, or the great, or the mighty, or the
huge, or the magnanimous, are all one reckonings, save the phrase is a little
variations.
</p>

<p>GOWER.<br>
I think Alexander the Great was born in Macedon. His father was called Philip
of Macedon, as I take it.
</p>

<p>FLUELLEN.<br>
I think it is in Macedon where Alexander is porn. I tell you, Captain, if you
look in the maps of the ’orld, I warrant you sall find, in the
comparisons between Macedon and Monmouth, that the situations, look you, is
both alike. There is a river in Macedon; and there is also moreover a river at
Monmouth; it is call’d Wye at Monmouth; but it is out of my prains what
is the name of the other river; but ’tis all one, ’tis alike as my
fingers is to my fingers, and there is salmons in both. If you mark
Alexander’s life well, Harry of Monmouth’s life is come after it
indifferent well; for there is figures in all things. Alexander, God knows, and
you know, in his rages, and his furies, and his wraths, and his cholers, and
his moods, and his displeasures, and his indignations, and also being a little
intoxicates in his prains, did, in his ales and his angers, look you, kill his
best friend, Cleitus.
</p>

<p>GOWER.<br>
Our King is not like him in that. He never kill’d any of his friends.
</p>

<p>FLUELLEN.<br>
It is not well done, mark you now, to take the tales out of my mouth, ere it is
made and finished. I speak but in the figures and comparisons of it. As
Alexander kill’d his friend Cleitus, being in his ales and his cups; so
also Harry Monmouth, being in his right wits and his good judgements,
turn’d away the fat knight with the great belly doublet. He was full of
jests, and gipes, and knaveries, and mocks; I have forgot his name.
</p>

<p>GOWER.<br>
Sir John Falstaff.
</p>

<p>FLUELLEN.<br>
That is he. I’ll tell you there is good men porn at Monmouth.
</p>

<p>GOWER.<br>
Here comes his Majesty.
</p>

<p class="scenedesc"> Alarum. Enter <span class="charname">King Henry</span>
and forces; <span class="charname">Warwick, Gloucester, Exeter</span> with
prisoners. Flourish.</p>

<p>KING HENRY.<br>
I was not angry since I came to France<br>
Until this instant. Take a trumpet, herald;<br>
Ride thou unto the horsemen on yond hill.<br>
If they will fight with us, bid them come down,<br>
Or void the field; they do offend our sight.<br>
If they’ll do neither, we will come to them,<br>
And make them skirr away, as swift as stones<br>
Enforced from the old Assyrian slings.<br>
Besides, we’ll cut the throats of those we have,<br>
And not a man of them that we shall take<br>
Shall taste our mercy. Go and tell them so.
</p>

<p class="scenedesc"> Enter <span class="charname">Montjoy</span>.</p>

<p>EXETER.<br>
Here comes the herald of the French, my liege.
</p>

<p>GLOUCESTER.<br>
His eyes are humbler than they us’d to be.
</p>

<p>KING HENRY.<br>
How now! what means this, herald? Know’st thou not<br>
That I have fin’d these bones of mine for ransom?<br>
Com’st thou again for ransom?
</p>

<p>MONTJOY.<br>
No, great King;<br>
I come to thee for charitable license,<br>
That we may wander o’er this bloody field<br>
To book our dead, and then to bury them;<br>
To sort our nobles from our common men.<br>
For many of our princes—woe the while!—<br>
Lie drown’d and soak’d in mercenary blood;<br>
So do our vulgar drench their peasant limbs<br>
In blood of princes; and their wounded steeds<br>
Fret fetlock deep in gore, and with wild rage<br>
Yerk out their armed heels at their dead masters,<br>
Killing them twice. O, give us leave, great King,<br>
To view the field in safety, and dispose<br>
Of their dead bodies!
</p>

<p>KING HENRY.<br>
I tell thee truly, herald,<br>
I know not if the day be ours or no;<br>
For yet a many of your horsemen peer<br>
And gallop o’er the field.
</p>

<p>MONTJOY.<br>
The day is yours.
</p>

<p>KING HENRY.<br>
Praised be God, and not our strength, for it!<br>
What is this castle call’d that stands hard by?
</p>

<p>MONTJOY.<br>
They call it Agincourt.
</p>

<p>KING HENRY.<br>
Then call we this the field of Agincourt,<br>
Fought on the day of Crispin Crispianus.
</p>

<p>FLUELLEN.<br>
Your grandfather of famous memory, an’t please your Majesty, and your
great-uncle Edward the Plack Prince of Wales, as I have read in the chronicles,
fought a most prave pattle here in France.
</p>

<p>KING HENRY.<br>
They did, Fluellen.
</p>

<p>FLUELLEN.<br>
Your Majesty says very true. If your Majesties is rememb’red of it, the
Welshmen did good service in garden where leeks did grow, wearing leeks in
their Monmouth caps; which, your Majesty know, to this hour is an honourable
badge of the service; and I do believe your Majesty takes no scorn to wear the
leek upon Saint Tavy’s day.
</p>

<p>KING HENRY.<br>
I wear it for a memorable honour;<br>
For I am Welsh, you know, good countryman.
</p>

<p>FLUELLEN.<br>
All the water in Wye cannot wash your Majesty’s Welsh plood out of your
pody, I can tell you that. Got pless it and preserve it, as long as it pleases
His grace, and His majesty too!
</p>

<p>KING HENRY.<br>
Thanks, good my countryman.
</p>

<p>FLUELLEN.<br>
By Jeshu, I am your Majesty’s countryman, I care not who know it. I will
confess it to all the ’orld. I need not be asham’d of your Majesty,
praised be God, so long as your Majesty is an honest man.
</p>

<p>KING HENRY.<br>
God keep me so!
</p>

<p class="scenedesc"> Enter <span class="charname">Williams</span>.</p>

<p>Our heralds go with him;<br>
Bring me just notice of the numbers dead<br>
On both our parts. Call yonder fellow hither.
</p>

<p class="right"> [<i>Exeunt <span class="charname">Heralds</span> with <span class="charname">Montjoy</span>.</i>]</p>

<p>EXETER.<br>
Soldier, you must come to the King.
</p>

<p>KING HENRY.<br>
Soldier, why wear’st thou that glove in thy cap?
</p>

<p>WILLIAMS.<br>
An’t please your Majesty, ’tis the gage of one that I should fight
withal, if he be alive.
</p>

<p>KING HENRY.<br>
An Englishman?
</p>

<p>WILLIAMS.<br>
An’t please your Majesty, a rascal that swagger’d with me last
night; who, if alive and ever dare to challenge this glove, I have sworn to
take him a box o’ the ear; or if I can see my glove in his cap, which he
swore, as he was a soldier, he would wear if alive, I will strike it out
soundly.
</p>

<p>KING HENRY.<br>
What think you, Captain Fluellen, is it fit this soldier keep his oath?
</p>

<p>FLUELLEN.<br>
He is a craven and a villain else, an’t please your Majesty, in my
conscience.
</p>

<p>KING HENRY.<br>
It may be his enemy is a gentlemen of great sort, quite from the answer of his
degree.
</p>

<p>FLUELLEN.<br>
Though he be as good a gentleman as the devil is, as Lucifier and Belzebub
himself, it is necessary, look your Grace, that he keep his vow and his oath.
If he be perjur’d, see you now, his reputation is as arrant a villain and
a Jacksauce, as ever his black shoe trod upon God’s ground and His earth,
in my conscience, la!
</p>

<p>KING HENRY.<br>
Then keep thy vow, sirrah, when thou meet’st the fellow.
</p>

<p>WILLIAMS.<br>
So I will, my liege, as I live.
</p>

<p>KING HENRY.<br>
Who serv’st thou under?
</p>

<p>WILLIAMS.<br>
Under Captain Gower, my liege.
</p>

<p>FLUELLEN.<br>
Gower is a good captain, and is good knowledge and literatured in the wars.
</p>

<p>KING HENRY.<br>
Call him hither to me, soldier.
</p>

<p>WILLIAMS.<br>
I will, my liege.
</p>

<p class="right"> [<i>Exit.</i>]</p>

<p>KING HENRY.<br>
Here, Fluellen; wear thou this favour for me and stick it in thy cap. When
Alençon and myself were down together, I pluck’d this glove from his
helm. If any man challenge this, he is a friend to Alençon, and an enemy to our
person. If thou encounter any such, apprehend him, an thou dost me love.
</p>

<p>FLUELLEN.<br>
Your Grace does me as great honours as can be desir’d in the hearts of
his subjects. I would fain see the man, that has but two legs, that shall find
himself aggrief’d at this glove; that is all. But I would fain see it
once, an please God of His grace that I might see.
</p>

<p>KING HENRY.<br>
Know’st thou Gower?
</p>

<p>FLUELLEN.<br>
He is my dear friend, an please you.
</p>

<p>KING HENRY.<br>
Pray thee, go seek him, and bring him to my tent.
</p>

<p>FLUELLEN.<br>
I will fetch him.
</p>

<p class="right"> [<i>Exit.</i>]</p>

<p>KING HENRY.<br>
My Lord of Warwick, and my brother Gloucester,<br>
Follow Fluellen closely at the heels.<br>
The glove which I have given him for a favour<br>
May haply purchase him a box o’ the ear.<br>
It is the soldier’s; I by bargain should<br>
Wear it myself. Follow, good cousin Warwick.<br>
If that the soldier strike him, as I judge<br>
By his blunt bearing he will keep his word,<br>
Some sudden mischief may arise of it;<br>
For I do know Fluellen valiant<br>
And, touch’d with choler, hot as gunpowder,<br>
And quickly will return an injury.<br>
Follow, and see there be no harm between them.<br>
Go you with me, uncle of Exeter.
</p>

<p class="right"> [<i>Exeunt.</i>]</p>

<h3> <a id="sceneIV_11.8"></a><b>SCENE VIII. Before King Henry’s pavilion.</b></h3>

<p class="scenedesc"> Enter <span class="charname">Gower</span> and <span class="charname">Williams</span>.</p>

<p>WILLIAMS.<br>
I warrant it is to knight you, Captain.
</p>

<p class="scenedesc"> Enter <span class="charname">Fluellen</span>.</p>

<p>FLUELLEN.<br>
God’s will and his pleasure, captain, I beseech you now, come apace to
the King. There is more good toward you peradventure than is in your knowledge
to dream of.
</p>

<p>WILLIAMS.<br>
Sir, know you this glove?
</p>

<p>FLUELLEN.<br>
Know the glove! I know the glove is a glove.
</p>

<p>WILLIAMS.<br>
I know this; and thus I challenge it.
</p>

<p class="right"> [<i>Strikes him.</i>]</p>

<p>FLUELLEN.<br>
’Sblood! an arrant traitor as any is in the universal world, or in
France, or in England!
</p>

<p>GOWER.<br>
How now, sir! you villain!
</p>

<p>WILLIAMS.<br>
Do you think I’ll be forsworn?
</p>

<p>FLUELLEN.<br>
Stand away, Captain Gower. I will give treason his payment into plows, I
warrant you.
</p>

<p>WILLIAMS.<br>
I am no traitor.
</p>

<p>FLUELLEN.<br>
That’s a lie in thy throat. I charge you in his Majesty’s name,
apprehend him; he’s a friend of the Duke Alençon’s.
</p>

<p class="scenedesc"> Enter <span class="charname">Warwick</span> and <span class="charname">Gloucester</span>.</p>

<p>WARWICK.<br>
How now, how now! what’s the matter?
</p>

<p>FLUELLEN.<br>
My lord of Warwick, here is—praised be God for it!—a most
contagious treason come to light, look you, as you shall desire in a
summer’s day. Here is his Majesty.
</p>

<p class="scenedesc"> Enter <span class="charname">King Henry</span> and <span class="charname">Exeter</span>.</p>

<p>KING HENRY.<br>
How now! what’s the matter?
</p>

<p>FLUELLEN.<br>
My liege, here is a villain and a traitor, that, look your Grace, has struck
the glove which your Majesty is take out of the helmet of Alençon.
</p>

<p>WILLIAMS.<br>
My liege, this was my glove; here is the fellow of it; and he that I gave it to
in change promis’d to wear it in his cap. I promis’d to strike him,
if he did. I met this man with my glove in his cap, and I have been as good as
my word.
</p>

<p>FLUELLEN.<br>
Your Majesty hear now, saving your Majesty’s manhood, what an arrant,
rascally, beggarly, lousy knave it is. I hope your Majesty is pear me testimony
and witness, and will avouchment, that this is the glove of Alençon that your
Majesty is give me; in your conscience, now?
</p>

<p>KING HENRY.<br>
Give me thy glove, soldier. Look, here is the fellow of it.<br>
’Twas I, indeed, thou promisedst to strike;<br>
And thou hast given me most bitter terms.
</p>

<p>FLUELLEN.<br>
An it please your Majesty, let his neck answer for it, if there is any martial
law in the world.
</p>

<p>KING HENRY.<br>
How canst thou make me satisfaction?
</p>

<p>WILLIAMS.<br>
All offences, my lord, come from the heart. Never came any from mine that might
offend your Majesty.
</p>

<p>KING HENRY.<br>
It was ourself thou didst abuse.
</p>

<p>WILLIAMS.<br>
Your Majesty came not like yourself. You appear’d to me but as a common
man; witness the night, your garments, your lowliness; and what your Highness
suffer’d under that shape, I beseech you take it for your own fault and
not mine; for had you been as I took you for, I made no offence; therefore, I
beseech your Highness, pardon me.
</p>

<p>KING HENRY.<br>
Here, uncle Exeter, fill this glove with crowns,<br>
And give it to this fellow. Keep it, fellow;<br>
And wear it for an honour in thy cap<br>
Till I do challenge it. Give him his crowns;<br>
And, captain, you must needs be friends with him.
</p>

<p>FLUELLEN.<br>
By this day and this light, the fellow has mettle enough in his belly. Hold,
there is twelve pence for you; and I pray you to serve God, and keep you out of
prawls, and prabbles, and quarrels, and dissensions, and, I warrant you, it is
the better for you.
</p>

<p>WILLIAMS.<br>
I will none of your money.
</p>

<p>FLUELLEN.<br>
It is with a good will; I can tell you, it will serve you to mend your shoes.
Come, wherefore should you be so pashful? Your shoes is not so good. ’Tis
a good silling, I warrant you, or I will change it.
</p>

<p class="scenedesc"> Enter an English <span class="charname">Herald</span>.</p>

<p>KING HENRY.<br>
Now, herald, are the dead numb’red?
</p>

<p>HERALD.<br>
Here is the number of the slaught’red French.
</p>

<p>KING HENRY.<br>
What prisoners of good sort are taken, uncle?
</p>

<p>EXETER.<br>
Charles Duke of Orleans, nephew to the King;<br>
John Duke of Bourbon, and Lord Boucicault:<br>
Of other lords and barons, knights and squires,<br>
Full fifteen hundred, besides common men.
</p>

<p>KING HENRY.<br>
This note doth tell me of ten thousand French<br>
That in the field lie slain; of princes, in this number,<br>
And nobles bearing banners, there lie dead<br>
One hundred twenty-six; added to these,<br>
Of knights, esquires, and gallant gentlemen,<br>
Eight thousand and four hundred; of the which,<br>
Five hundred were but yesterday dubb’d knights;<br>
So that, in these ten thousand they have lost,<br>
There are but sixteen hundred mercenaries;<br>
The rest are princes, barons, lords, knights, squires,<br>
And gentlemen of blood and quality.<br>
The names of those their nobles that lie dead:<br>
Charles Delabreth, High Constable of France;<br>
Jacques of Chatillon, Admiral of France;<br>
The master of the Crossbows, Lord Rambures;<br>
Great Master of France, the brave Sir Guichard Dauphin,<br>
John, Duke of Alençon, Anthony, Duke of Brabant,<br>
The brother to the Duke of Burgundy,<br>
And Edward, Duke of Bar; of lusty earls,<br>
Grandpré and Roussi, Fauconbridge and Foix,<br>
Beaumont and Marle, Vaudemont and Lestrale.<br>
Here was a royal fellowship of death!<br>
Where is the number of our English dead?
</p>

<p class="right"> [<i>Herald gives him another paper.</i>]</p>

<p>Edward the Duke of York, the Earl of Suffolk,<br>
Sir Richard Ketly, Davy Gam, esquire;<br>
None else of name; and of all other men<br>
But five and twenty.—O God, thy arm was here;<br>
And not to us, but to thy arm alone,<br>
Ascribe we all! When, without stratagem,<br>
But in plain shock and even play of battle,<br>
Was ever known so great and little loss<br>
On one part and on the other? Take it, God,<br>
For it is none but thine!
</p>

<p>EXETER.<br>
’Tis wonderful!
</p>

<p>KING HENRY.<br>
Come, go we in procession to the village;<br>
And be it death proclaimed through our host<br>
To boast of this or take that praise from God<br>
Which is His only.
</p>

<p>FLUELLEN.<br>
Is it not lawful, an please your Majesty, to tell how many is kill’d?
</p>

<p>KING HENRY.<br>
Yes, Captain; but with this acknowledgment,<br>
That God fought for us.
</p>

<p>FLUELLEN.<br>
Yes, my conscience, He did us great good.
</p>

<p>KING HENRY.<br>
Do we all holy rites.<br>
Let there be sung <i>Non nobis</i> and <i>Te Deum</i>,<br>
The dead with charity enclos’d in clay,<br>
And then to Calais; and to England then,<br>
Where ne’er from France arriv’d more happy men.
</p>

<p class="right"> [<i>Exeunt.</i>]</p>

