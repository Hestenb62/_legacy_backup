<h2> <a id="sceneII_21.1"></a><b>ACT II</b></h2>

<h3> <b>SCENE I. A hall in Angelo’s house.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Angelo, Escalus,</span> Servants, and a
<span class="charname">Justice</span>.
</p>

<p class="drama">
ANGELO.<br>
We must not make a scarecrow of the law,<br>
Setting it up to fear the birds of prey,<br>
And let it keep one shape till custom make it<br>
Their perch, and not their terror.
</p>

<p class="drama">
ESCALUS.<br>
Ay, but yet<br>
Let us be keen, and rather cut a little<br>
Than fall and bruise to death. Alas, this gentleman,<br>
Whom I would save, had a most noble father.<br>
Let but your honour know,<br>
Whom I believe to be most strait in virtue,<br>
That, in the working of your own affections,<br>
Had time cohered with place, or place with wishing,<br>
Or that the resolute acting of your blood<br>
Could have attained th’ effect of your own purpose,<br>
Whether you had not sometime in your life<br>
Erred in this point which now you censure him,<br>
And pulled the law upon you.
</p>

<p class="drama">
ANGELO.<br>
’Tis one thing to be tempted, Escalus,<br>
Another thing to fall. I not deny<br>
The jury passing on the prisoner’s life<br>
May in the sworn twelve have a thief or two<br>
Guiltier than him they try. What’s open made to justice,<br>
That justice seizes. What knows the laws<br>
That thieves do pass on thieves? ’Tis very pregnant,<br>
The jewel that we find, we stoop and take ’t,<br>
Because we see it; but what we do not see,<br>
We tread upon, and never think of it.<br>
You may not so extenuate his offence<br>
For I have had such faults; but rather tell me,<br>
When I that censure him do so offend,<br>
Let mine own judgement pattern out my death,<br>
And nothing come in partial. Sir, he must die.
</p>

<p class="scenedesc">
Enter <span class="charname">Provost</span>.
</p>

<p class="drama">
ESCALUS.<br>
Be it as your wisdom will.
</p>

<p class="drama">
ANGELO.<br>
Where is the Provost?
</p>

<p class="drama">
PROVOST.<br>
Here, if it like your honour.
</p>

<p class="drama">
ANGELO.<br>
See that Claudio<br>
Be executed by nine tomorrow morning.<br>
Bring him his confessor, let him be prepared,<br>
For that’s the utmost of his pilgrimage.
</p>

<p class="right">[<i>Exit <span class="charname">Provost</span>.</i>]</p>

<p class="drama">
ESCALUS.<br>
Well, heaven forgive him; and forgive us all.<br>
Some rise by sin, and some by virtue fall.<br>
Some run from brakes of vice, and answer none,<br>
And some condemned for a fault alone.
</p>

<p class="scenedesc">
Enter <span class="charname">Elbow</span> and Officers with
<span class="charname">Froth</span> and <span class="charname">Pompey</span>.
</p>

<p class="drama">
ELBOW.<br>
Come, bring them away. If these be good people in a commonweal that do nothing
but use their abuses in common houses, I know no law. Bring them away.</p>

<p class="drama">
ANGELO.<br>
How now, sir, what’s your name? And what’s the matter?
</p>

<p class="drama">
ELBOW.<br>
If it please your honour, I am the poor Duke’s constable, and my name is
Elbow. I do lean upon justice, sir, and do bring in here before your good
honour two notorious benefactors.</p>

<p class="drama">
ANGELO.<br>
Benefactors? Well, what benefactors are they? Are they not malefactors?</p>

<p class="drama">
ELBOW.<br>
If it please your honour, I know not well what they are, but precise villains
they are, that I am sure of, and void of all profanation in the world that good
Christians ought to have.
</p>

<p class="drama">
ESCALUS.<br>
This comes off well. Here’s a wise officer.
</p>

<p class="drama">
ANGELO.<br>
Go to. What quality are they of? Elbow is your name? Why dost thou not
speak, Elbow?
</p>

<p class="drama">
POMPEY.<br>
He cannot, sir. He’s out at elbow.
</p>

<p class="drama">
ANGELO.<br>
What are you, sir?
</p>

<p class="drama">
ELBOW.<br>
He, sir? A tapster, sir; parcel bawd; one that serves a bad woman; whose house,
sir, was, as they say, plucked down in the suburbs; and now she professes a
hot-house, which, I think is a very ill house too.
</p>

<p class="drama">
ESCALUS.<br>
How know you that?
</p>

<p class="drama">
ELBOW.<br>
My wife, sir, whom I detest before heaven and your honour—
</p>

<p class="drama">
ESCALUS.<br>
How? Thy wife?
</p>

<p class="drama">
ELBOW.<br>
Ay, sir, whom I thank heaven is an honest woman—
</p>

<p class="drama">
ESCALUS.<br>
Dost thou detest her therefore?
</p>

<p class="drama">
ELBOW.<br>
I say, sir, I will detest myself also, as well as she, that this house, if it
be not a bawd’s house, it is pity of her life, for it is a naughty house.
</p>

<p class="drama">
ESCALUS.<br>
How dost thou know that, constable?
</p>

<p class="drama">
ELBOW.<br>
Marry, sir, by my wife, who, if she had been a woman cardinally given, might
have been accused in fornication, adultery, and all uncleanliness there.
</p>

<p class="drama">
ESCALUS.<br>
By the woman’s means?
</p>

<p class="drama">
ELBOW.<br>
Ay, sir, by Mistress Overdone’s means; but as she spit in his face, so
she defied him.
</p>

<p class="drama">
POMPEY.<br>
Sir, if it please your honour, this is not so.
</p>

<p class="drama">
ELBOW.<br>
Prove it before these varlets here, thou honourable man, prove it.</p>

<p class="drama">
ESCALUS.<br>
[<i>To Angelo</i>.] Do you hear how he misplaces?
</p>

<p class="drama">
POMPEY.<br>
Sir, she came in great with child; and longing, saving your honour’s reverence,
for stewed prunes; sir, we had but two in the house, which at that very distant
time stood, as it were, in a fruit dish, a dish of some threepence; your
honours have seen such dishes; they are not china dishes, but very good dishes—
</p>

<p class="drama">
ESCALUS.<br>
Go to, go to. No matter for the dish, sir.
</p>

<p class="drama">
POMPEY.<br>
No, indeed, sir, not of a pin; you are therein in the right. But to the point.
As I say, this Mistress Elbow, being, as I say, with child, and being
great-bellied, and longing, as I said, for prunes; and having but two in the
dish, as I said, Master Froth here, this very man, having eaten the rest, as I
said, and, as I say, paying for them very honestly; for, as you know, Master
Froth, I could not give you threepence again—
</p>

<p class="drama">
FROTH.<br>
No, indeed.
</p>

<p class="drama">
POMPEY.<br>
Very well. You being then, if you be remembered, cracking the stones of the
foresaid prunes—
</p>

<p class="drama">
FROTH.<br>
Ay, so I did indeed.
</p>

<p class="drama">
POMPEY.<br>
Why, very well. I telling you then, if you be remembered, that such a one and
such a one were past cure of the thing you wot of, unless they kept very good
diet, as I told you—
</p>

<p class="drama">
FROTH.<br>
All this is true.
</p>

<p class="drama">
POMPEY.<br>
Why, very well then—
</p>

<p class="drama">
ESCALUS.<br>
Come, you are a tedious fool. To the purpose. What was done to Elbow’s wife
that he hath cause to complain of? Come me to what was done to her.
</p>

<p class="drama">
POMPEY.<br>
Sir, your honour cannot come to that yet.
</p>

<p class="drama">
ESCALUS.<br>
No, sir, nor I mean it not.
</p>

<p class="drama">
POMPEY.<br>
Sir, but you shall come to it, by your honour’s leave. And I beseech you, look
into Master Froth here, sir, a man of fourscore pound a year; whose father died
at Hallowmas—was’t not at Hallowmas, Master Froth?
</p>

<p class="drama">
FROTH.<br>
All-hallond Eve.
</p>

<p class="drama">
POMPEY.<br>
Why, very well. I hope here be truths. He, sir, sitting, as I say, in a lower
chair, sir—’twas in the Bunch of Grapes, where, indeed, you have a delight to
sit, have you not?
</p>

<p class="drama">
FROTH.<br>
I have so, because it is an open room, and good for winter.
</p>

<p class="drama">
POMPEY.<br>
Why, very well then. I hope here be truths.
</p>

<p class="drama">
ANGELO.<br>
This will last out a night in Russia<br>
When nights are longest there. I’ll take my leave,<br>
And leave you to the hearing of the cause;<br>
Hoping you’ll find good cause to whip them all.
</p>

<p class="drama">
ESCALUS.<br>
I think no less. Good morrow to your lordship.
</p>

<p class="right">[<i>Exit <span class="charname">Angelo</span>.</i>]</p>

<p class="drama">
Now, sir, come on. What was done to Elbow’s wife, once more?</p>

<p class="drama">
POMPEY.<br>
Once, sir? There was nothing done to her once.
</p>

<p class="drama">
ELBOW.<br>
I beseech you, sir, ask him what this man did to my wife.
</p>

<p class="drama">
POMPEY.<br>
I beseech your honour, ask me.
</p>

<p class="drama">
ESCALUS.<br>
Well, sir, what did this gentleman to her?
</p>

<p class="drama">
POMPEY.<br>
I beseech you, sir, look in this gentleman’s face. Good Master Froth, look upon
his honour; ’tis for a good purpose.—Doth your honour mark his face?
</p>

<p class="drama">
ESCALUS.<br>
Ay, sir, very well.
</p>

<p class="drama">
POMPEY.<br>
Nay, I beseech you, mark it well.
</p>

<p class="drama">
ESCALUS.<br>
Well, I do so.
</p>

<p class="drama">
POMPEY.<br>
Doth your honour see any harm in his face?
</p>

<p class="drama">
ESCALUS.<br>
Why, no.
</p>

<p class="drama">
POMPEY.<br>
I’ll be supposed upon a book, his face is the worst thing about him. Good,
then, if his face be the worst thing about him, how could Master Froth do the
constable’s wife any harm? I would know that of your honour.
</p>

<p class="drama">
ESCALUS.<br>
He’s in the right. Constable. What say you to it?
</p>

<p class="drama">
ELBOW.<br>
First, an it like you, the house is a respected house; next, this is a
respected fellow; and his mistress is a respected woman.
</p>

<p class="drama">
POMPEY.<br>
By this hand, sir, his wife is a more respected person than any of us all.
</p>

<p class="drama">
ELBOW.<br>
Varlet, thou liest; thou liest, wicked varlet! The time is yet to come that she
was ever respected with man, woman, or child.
</p>

<p class="drama">
POMPEY.<br>
Sir, she was respected with him before he married with her.
</p>

<p class="drama">
ESCALUS.<br>
Which is the wiser here, Justice or Iniquity? Is this true?
</p>

<p class="drama">
ELBOW.<br>
O thou caitiff! O thou varlet! O thou wicked Hannibal! I respected with her
before I was married to her? If ever I was respected with her, or she with me,
let not your worship think me the poor Duke’s officer. Prove this, thou wicked
Hannibal, or I’ll have mine action of battery on thee.
</p>

<p class="drama">
ESCALUS.<br>
If he took you a box o’ th’ ear, you might have your action of
slander too.</p>

<p class="drama">
ELBOW.<br>
Marry, I thank your good worship for it. What is’t your worship’s pleasure I
shall do with this wicked caitiff?
</p>

<p class="drama">
ESCALUS.<br>
Truly, officer, because he hath some offences in him that thou wouldst discover
if thou couldst, let him continue in his courses till thou know’st what they
are.</p>

<p class="drama">
ELBOW.<br>
Marry, I thank your worship for it.—Thou seest, thou wicked varlet, now, what’s
come upon thee. Thou art to continue now, thou varlet, thou art to continue.
</p>

<p class="drama">
ESCALUS.<br>
[<i>To Froth</i>.] Where were you born, friend?
</p>

<p class="drama">
FROTH.<br>
Here in Vienna, sir.
</p>

<p class="drama">
ESCALUS.<br>
Are you of fourscore pounds a year?
</p>

<p class="drama">
FROTH.<br>
Yes, an’t please you, sir.
</p>

<p class="drama">
ESCALUS.<br>
So. [<i>To Pompey</i>.] What trade are you of, sir?
</p>

<p class="drama">
POMPEY.<br>
A tapster, a poor widow’s tapster.
</p>

<p class="drama">
ESCALUS.<br>
Your mistress’ name?
</p>

<p class="drama">
POMPEY.<br>
Mistress Overdone.
</p>

<p class="drama">
ESCALUS.<br>
Hath she had any more than one husband?
</p>

<p class="drama">
POMPEY.<br>
Nine, sir; Overdone by the last.
</p>

<p class="drama">
ESCALUS.<br>
Nine?—Come hither to me, Master Froth. Master Froth, I would not have you
acquainted with tapsters; they will draw you, Master Froth, and you will hang
them. Get you gone, and let me hear no more of you.
</p>

<p class="drama">
FROTH.<br>
I thank your worship. For mine own part, I never come into any room in a
taphouse but I am drawn in.
</p>

<p class="drama">
ESCALUS.<br>
Well, no more of it, Master Froth. Farewell.
</p>

<p class="right">[<i>Exit <span class="charname">Froth</span>.</i>]</p>

<p class="drama">
Come you hither to me, Master tapster. What’s your name, Master tapster?
</p>

<p class="drama">
POMPEY.<br>
Pompey.
</p>

<p class="drama">
ESCALUS.<br>
What else?
</p>

<p class="drama">
POMPEY.<br>
Bum, sir.
</p>

<p class="drama">
ESCALUS.<br>
Troth, and your bum is the greatest thing about you; so that, in the beastliest
sense, you are Pompey the great. Pompey, you are partly a bawd, Pompey,
howsoever you colour it in being a tapster, are you not? Come, tell me true, it
shall be the better for you.
</p>

<p class="drama">
POMPEY.<br>
Truly, sir, I am a poor fellow that would live.
</p>

<p class="drama">
ESCALUS.<br>
How would you live, Pompey? By being a bawd? What do you think of the trade,
Pompey? Is it a lawful trade?
</p>

<p class="drama">
POMPEY.<br>
If the law would allow it, sir.
</p>

<p class="drama">
ESCALUS.<br>
But the law will not allow it, Pompey; nor it shall not be allowed in
Vienna.</p>

<p class="drama">
POMPEY.<br>
Does your worship mean to geld and splay all the youth of the city?</p>

<p class="drama">
ESCALUS.<br>
No, Pompey.
</p>

<p class="drama">
POMPEY.<br>
Truly, sir, in my poor opinion, they will to’t then. If your worship will
take order for the drabs and the knaves, you need not to fear the bawds.</p>

<p class="drama">
ESCALUS.<br>
There is pretty orders beginning, I can tell you. It is but heading and
hanging.</p>

<p class="drama">
POMPEY.<br>
If you head and hang all that offend that way but for ten year together,
you’ll be glad to give out a commission for more heads. If this law hold
in Vienna ten year, I’ll rent the fairest house in it after threepence a
bay. If you live to see this come to pass, say Pompey told you so.
</p>

<p class="drama">
ESCALUS.<br>
Thank you, good Pompey; and, in requital of your prophecy, hark you: I advise
you, let me not find you before me again upon any complaint whatsoever; no, not
for dwelling where you do. If I do, Pompey, I shall beat you to your tent, and
prove a shrewd Caesar to you. In plain dealing, Pompey, I shall have you
whipped. So for this time, Pompey, fare you well.
</p>

<p class="drama">
POMPEY.<br>
I thank your worship for your good counsel. [<i>Aside</i>.] But I shall follow
it as the flesh and fortune shall better determine.<br>
Whip me? No, no; let carman whip his jade;<br>
The valiant heart’s not whipped out of his trade.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
ESCALUS.<br>
Come hither to me, Master Elbow. Come hither, Master Constable. How long have
you been in this place of constable?
</p>

<p class="drama">
ELBOW.<br>
Seven year and a half, sir.
</p>

<p class="drama">
ESCALUS.<br>
I thought, by the readiness in the office, you had continued in it sometime.
You say seven years together?
</p>

<p class="drama">
ELBOW.<br>
And a half, sir.
</p>

<p class="drama">
ESCALUS.<br>
Alas, it hath been great pains to you. They do you wrong to put you so
oft upon’t. Are there not men in your ward sufficient to serve it?
</p>

<p class="drama">
ELBOW.<br>
Faith, sir, few of any wit in such matters. As they are chosen, they are glad
to choose me for them; I do it for some piece of money, and go through with
all.</p>

<p class="drama">
ESCALUS.<br>
Look you bring me in the names of some six or seven, the most sufficient of
your parish.
</p>

<p class="drama">
ELBOW.<br>
To your worship’s house, sir?
</p>

<p class="drama">
ESCALUS.<br>
To my house. Fare you well.
</p>

<p class="right">[<i>Exit <span class="charname">Elbow</span>.</i>]</p>

<p class="drama">
What’s o’clock, think you?</p>

<p class="drama">
JUSTICE.<br>
Eleven, sir.
</p>

<p class="drama">
ESCALUS.<br>
I pray you home to dinner with me.
</p>

<p class="drama">
JUSTICE.<br>
I humbly thank you.
</p>

<p class="drama">
ESCALUS.<br>
It grieves me for the death of Claudio,<br>
But there’s no remedy.
</p>

<p class="drama">
JUSTICE.<br>
Lord Angelo is severe.
</p>

<p class="drama">
ESCALUS.<br>
It is but needful.<br>
Mercy is not itself that oft looks so;<br>
Pardon is still the nurse of second woe.<br>
But yet, Poor Claudio! There’s no remedy.<br>
Come, sir.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneII_21.2"></a><b>SCENE II. Another room in the same.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Provost</span> and a
<span class="charname">Servant</span>.
</p>

<p class="drama">
SERVANT.<br>
He’s hearing of a cause. He will come straight.<br>
I’ll tell him of you.
</p>

<p class="drama">
PROVOST.<br>
Pray you do.
</p>

<p class="right">[<i>Exit <span class="charname">Servant</span>.</i>]</p>

<p class="drama">
I’ll know<br>
His pleasure, may be he will relent. Alas,<br>
He hath but as offended in a dream;<br>
All sects, all ages, smack of this vice, and he<br>
To die for ’t!
</p>

<p class="scenedesc">
Enter <span class="charname">Angelo</span>.
</p>

<p class="drama">
ANGELO.<br>
Now, what’s the matter, Provost?
</p>

<p class="drama">
PROVOST.<br>
Is it your will Claudio shall die tomorrow?
</p>

<p class="drama">
ANGELO.<br>
Did not I tell thee yea? Hadst thou not order?<br>
Why dost thou ask again?
</p>

<p class="drama">
PROVOST.<br>
Lest I might be too rash.<br>
Under your good correction, I have seen<br>
When, after execution, judgement hath<br>
Repented o’er his doom.
</p>

<p class="drama">
ANGELO.<br>
Go to; let that be mine.<br>
Do you your office, or give up your place,<br>
And you shall well be spared.
</p>

<p class="drama">
PROVOST.<br>
I crave your honour’s pardon.<br>
What shall be done, sir, with the groaning Juliet?<br>
She’s very near her hour.
</p>

<p class="drama">
ANGELO.<br>
Dispose of her<br>
To some more fitter place; and that with speed.
</p>

<p class="scenedesc">
Enter <span class="charname">Servant</span>.
</p>

<p class="drama">
SERVANT.<br>
Here is the sister of the man condemned<br>
Desires access to you.
</p>

<p class="drama">
ANGELO.<br>
Hath he a sister?
</p>

<p class="drama">
PROVOST.<br>
Ay, my good lord, a very virtuous maid,<br>
And to be shortly of a sisterhood,<br>
If not already.
</p>

<p class="drama">
ANGELO.<br>
Well, let her be admitted.
</p>

<p class="right">[<i>Exit <span class="charname">Servant</span>.</i>]</p>

<p class="drama">
See you the fornicatress be removed;<br>
Let her have needful but not lavish means;<br>
There shall be order for it.
</p>

<p class="scenedesc">
Enter <span class="charname">Lucio</span> and
<span class="charname">Isabella</span>.
</p>

<p class="drama">
PROVOST.<br>
[<i>Offering to retire</i>.] Save your honour!
</p>

<p class="drama">
ANGELO.<br>
Stay a little while. [<i>To Isabella</i>.] You are welcome. What’s your
will?</p>

<p class="drama">
ISABELLA.<br>
I am a woeful suitor to your honour,<br>
Please but your honour hear me.
</p>

<p class="drama">
ANGELO.<br>
Well, what’s your suit?
</p>

<p class="drama">
ISABELLA.<br>
There is a vice that most I do abhor,<br>
And most desire should meet the blow of justice;<br>
For which I would not plead, but that I must;<br>
For which I must not plead, but that I am<br>
At war ’twixt will and will not.
</p>

<p class="drama">
ANGELO.<br>
Well, the matter?
</p>

<p class="drama">
ISABELLA.<br>
I have a brother is condemned to die;<br>
I do beseech you, let it be his fault,<br>
And not my brother.
</p>

<p class="drama">
PROVOST.<br>
Heaven give thee moving graces.
</p>

<p class="drama">
ANGELO.<br>
Condemn the fault, and not the actor of it?<br>
Why, every fault’s condemned ere it be done.<br>
Mine were the very cipher of a function<br>
To find the faults whose fine stands in record,<br>
And let go by the actor.
</p>

<p class="drama">
ISABELLA.<br>
O just but severe law!<br>
I had a brother, then. Heaven keep your honour!
</p>

<p class="right">[<i>Going.</i>]</p>

<p class="drama">
LUCIO.<br>
[<i>To Isabella</i>.] Give’t not o’er so. To him again, entreat him,<br>
Kneel down before him, hang upon his gown;<br>
You are too cold. If you should need a pin,<br>
You could not with more tame a tongue desire it.<br>
To him, I say.
</p>

<p class="drama">
ISABELLA.<br>
Must he needs die?
</p>

<p class="drama">
ANGELO.<br>
Maiden, no remedy.
</p>

<p class="drama">
ISABELLA.<br>
Yes, I do think that you might pardon him,<br>
And neither heaven nor man grieve at the mercy.
</p>

<p class="drama">
ANGELO.<br>
I will not do’t.
</p>

<p class="drama">
ISABELLA.<br>
But can you if you would?
</p>

<p class="drama">
ANGELO.<br>
Look, what I will not, that I cannot do.
</p>

<p class="drama">
ISABELLA.<br>
But might you do’t, and do the world no wrong,<br>
If so your heart were touched with that remorse<br>
As mine is to him?
</p>

<p class="drama">
ANGELO.<br>
He’s sentenced, ’tis too late.
</p>

<p class="drama">
LUCIO.<br>
[<i>To Isabella</i>.] You are too cold.
</p>

<p class="drama">
ISABELLA.<br>
Too late? Why, no. I that do speak a word<br>
May call it back again. Well, believe this:<br>
No ceremony that to great ones longs,<br>
Not the king’s crown, nor the deputed sword,<br>
The marshal’s truncheon, nor the judge’s robe,<br>
Become them with one half so good a grace<br>
As mercy does.<br>
If he had been as you, and you as he,<br>
You would have slipped like him, but he like you<br>
Would not have been so stern.
</p>

<p class="drama">
ANGELO.<br>
Pray you be gone.
</p>

<p class="drama">
ISABELLA.<br>
I would to heaven I had your potency,<br>
And you were Isabel! Should it then be thus?<br>
No; I would tell what ’twere to be a judge<br>
And what a prisoner.
</p>

<p class="drama">
LUCIO.<br>
[<i>Aside</i>.] Ay, touch him; there’s the vein.
</p>

<p class="drama">
ANGELO.<br>
Your brother is a forfeit of the law,<br>
And you but waste your words.
</p>

<p class="drama">
ISABELLA.<br>
Alas, alas!<br>
Why, all the souls that were were forfeit once,<br>
And He that might the vantage best have took<br>
Found out the remedy. How would you be<br>
If He, which is the top of judgement, should<br>
But judge you as you are? O, think on that,<br>
And mercy then will breathe within your lips,<br>
Like man new made.
</p>

<p class="drama">
ANGELO.<br>
Be you content, fair maid.<br>
It is the law, not I, condemns your brother.<br>
Were he my kinsman, brother, or my son,<br>
It should be thus with him. He must die tomorrow.
</p>

<p class="drama">
ISABELLA.<br>
Tomorrow? O, that’s sudden! Spare him, spare him!<br>
He’s not prepared for death. Even for our kitchens<br>
We kill the fowl of season. Shall we serve heaven<br>
With less respect than we do minister<br>
To our gross selves? Good, good my lord, bethink you.<br>
Who is it that hath died for this offence?<br>
There’s many have committed it.
</p>

<p class="drama">
LUCIO.<br>
Ay, well said.
</p>

<p class="drama">
ANGELO.<br>
The law hath not been dead, though it hath slept.<br>
Those many had not dared to do that evil<br>
If the first that did th’ edict infringe<br>
Had answered for his deed. Now ’tis awake,<br>
Takes note of what is done, and, like a prophet,<br>
Looks in a glass that shows what future evils,<br>
Either now, or by remissness new conceived,<br>
And so in progress to be hatched and born,<br>
Are now to have no successive degrees,<br>
But, where they live, to end.
</p>

<p class="drama">
ISABELLA.<br>
Yet show some pity.
</p>

<p class="drama">
ANGELO.<br>
I show it most of all when I show justice;<br>
For then I pity those I do not know,<br>
Which a dismissed offence would after gall,<br>
And do him right that, answering one foul wrong,<br>
Lives not to act another. Be satisfied;<br>
Your brother dies tomorrow; be content.
</p>

<p class="drama">
ISABELLA.<br>
So you must be the first that gives this sentence,<br>
And he that suffers. O, it is excellent<br>
To have a giant’s strength; but it is tyrannous<br>
To use it like a giant.
</p>

<p class="drama">
LUCIO.<br>
That’s well said.
</p>

<p class="drama">
ISABELLA.<br>
Could great men thunder<br>
As Jove himself does, Jove would ne’er be quiet,<br>
For every pelting petty officer<br>
Would use his heaven for thunder.<br>
Nothing but thunder. Merciful Heaven,<br>
Thou rather with thy sharp and sulphurous bolt<br>
Splits the unwedgeable and gnarled oak,<br>
Than the soft myrtle. But man, proud man,<br>
Dressed in a little brief authority,<br>
Most ignorant of what he’s most assured,<br>
His glassy essence, like an angry ape<br>
Plays such fantastic tricks before high heaven<br>
As makes the angels weep; who, with our spleens,<br>
Would all themselves laugh mortal.
</p>

<p class="drama">
LUCIO.<br>
O, to him, to him, wench! He will relent;<br>
He’s coming. I perceive ’t.
</p>

<p class="drama">
PROVOST.<br>
Pray heaven she win him.
</p>

<p class="drama">
ISABELLA.<br>
We cannot weigh our brother with ourself.<br>
Great men may jest with saints; ’tis wit in them,<br>
But in the less, foul profanation.
</p>

<p class="drama">
LUCIO.<br>
Thou’rt i’ th’ right, girl; more o’ that.
</p>

<p class="drama">
ISABELLA.<br>
That in the captain’s but a choleric word<br>
Which in the soldier is flat blasphemy.
</p>

<p class="drama">
LUCIO.<br>
Art advised o’ that? More on’t.
</p>

<p class="drama">
ANGELO.<br>
Why do you put these sayings upon me?
</p>

<p class="drama">
ISABELLA.<br>
Because authority, though it err like others,<br>
Hath yet a kind of medicine in itself<br>
That skins the vice o’ th’ top. Go to your bosom,<br>
Knock there, and ask your heart what it doth know<br>
That’s like my brother’s fault. If it confess<br>
A natural guiltiness such as is his,<br>
Let it not sound a thought upon your tongue<br>
Against my brother’s life.
</p>

<p class="drama">
ANGELO.<br>
She speaks, and ’tis such sense<br>
That my sense breeds with it. [<i>Going</i>.]<br>
Fare you well.
</p>

<p class="drama">
ISABELLA.<br>
Gentle my lord, turn back.
</p>

<p class="drama">
ANGELO.<br>
I will bethink me. Come again tomorrow.
</p>

<p class="drama">
ISABELLA.<br>
Hark how I’ll bribe you. Good my lord, turn back.
</p>

<p class="drama">
ANGELO.<br>
How? Bribe me?
</p>

<p class="drama">
ISABELLA.<br>
Ay, with such gifts that heaven shall share with you.
</p>

<p class="drama">
LUCIO.<br>
You had marred all else.
</p>

<p class="drama">
ISABELLA.<br>
Not with fond shekels of the tested gold,<br>
Or stones, whose rates are either rich or poor<br>
As fancy values them, but with true prayers,<br>
That shall be up at heaven and enter there<br>
Ere sunrise, prayers from preserved souls,<br>
From fasting maids, whose minds are dedicate<br>
To nothing temporal.
</p>

<p class="drama">
ANGELO.<br>
Well; come to me tomorrow.
</p>

<p class="drama">
LUCIO.<br>
[<i>Aside to Isabella</i>.] Go to, ’tis well; away.
</p>

<p class="drama">
ISABELLA.<br>
Heaven keep your honour safe.
</p>

<p class="drama">
ANGELO.<br>
[<i>Aside</i>.] Amen.<br>
For I am that way going to temptation,<br>
Where prayers cross.
</p>

<p class="drama">
ISABELLA.<br>
At what hour tomorrow<br>
Shall I attend your lordship?
</p>

<p class="drama">
ANGELO.<br>
At any time ’fore noon.
</p>

<p class="drama">
ISABELLA.<br>
Save your honour.
</p>

<p class="right">[<i>Exeunt <span class="charname">Isabella, Lucio</span> and
<span class="charname">Provost</span>.</i>]
</p>

<p class="drama">
ANGELO.<br>
From thee, even from thy virtue!<br>
What’s this? What’s this? Is this her fault or mine?<br>
The tempter or the tempted, who sins most, ha?<br>
Not she; nor doth she tempt; but it is I<br>
That, lying by the violet in the sun,<br>
Do as the carrion does, not as the flower,<br>
Corrupt with virtuous season. Can it be<br>
That modesty may more betray our sense<br>
Than woman’s lightness? Having waste ground enough,<br>
Shall we desire to raze the sanctuary<br>
And pitch our evils there? O, fie, fie, fie!<br>
What dost thou, or what art thou, Angelo?<br>
Dost thou desire her foully for those things<br>
That make her good? O, let her brother live.<br>
Thieves for their robbery have authority<br>
When judges steal themselves. What, do I love her,<br>
That I desire to hear her speak again<br>
And feast upon her eyes? What is’t I dream on?<br>
O cunning enemy, that, to catch a saint,<br>
With saints dost bait thy hook! Most dangerous<br>
Is that temptation that doth goad us on<br>
To sin in loving virtue. Never could the strumpet<br>
With all her double vigour, art, and nature,<br>
Once stir my temper, but this virtuous maid<br>
Subdues me quite. Ever till now<br>
When men were fond, I smiled and wondered how.
</p>

<p class="right">[<i>Exit.</i>]</p>

<h3> <a id="sceneII_21.3"></a><b>SCENE III. A room in a prison.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Duke</span> disguised as a Friar, and
<span class="charname">Provost</span>.
</p>

<p class="drama">
DUKE.<br>
Hail to you, Provost, so I think you are.
</p>

<p class="drama">
PROVOST.<br>
I am the Provost. What’s your will, good friar?
</p>

<p class="drama">
DUKE.<br>
Bound by my charity and my blessed order,<br>
I come to visit the afflicted spirits<br>
Here in the prison. Do me the common right<br>
To let me see them, and to make me know<br>
The nature of their crimes, that I may minister<br>
To them accordingly.
</p>

<p class="drama">
PROVOST.<br>
I would do more than that, if more were needful.
</p>

<p class="scenedesc">
Enter <span class="charname">Juliet</span>.
</p>

<p class="drama">
Look, here comes one, a gentlewoman of mine,<br>
Who, falling in the flaws of her own youth,<br>
Hath blistered her report. She is with child,<br>
And he that got it, sentenced: a young man<br>
More fit to do another such offence<br>
Than die for this.
</p>

<p class="drama">
DUKE.<br>
When must he die?
</p>

<p class="drama">
PROVOST.<br>
As I do think, tomorrow.<br>
[<i>To Juliet</i>.] I have provided for you; stay a while<br>
And you shall be conducted.
</p>

<p class="drama">
DUKE.<br>
Repent you, fair one, of the sin you carry?
</p>

<p class="drama">
JULIET.<br>
I do; and bear the shame most patiently.
</p>

<p class="drama">
DUKE.<br>
I’ll teach you how you shall arraign your conscience,<br>
And try your penitence, if it be sound<br>
Or hollowly put on.
</p>

<p class="drama">
JULIET.<br>
I’ll gladly learn.
</p>

<p class="drama">
DUKE.<br>
Love you the man that wronged you?
</p>

<p class="drama">
JULIET.<br>
Yes, as I love the woman that wronged him.
</p>

<p class="drama">
DUKE.<br>
So then it seems your most offenceful act<br>
Was mutually committed?
</p>

<p class="drama">
JULIET.<br>
Mutually.
</p>

<p class="drama">
DUKE.<br>
Then was your sin of heavier kind than his.
</p>

<p class="drama">
JULIET.<br>
I do confess it, and repent it, father.
</p>

<p class="drama">
DUKE.<br>
’Tis meet so, daughter; but lest you do repent<br>
As that the sin hath brought you to this shame,<br>
Which sorrow is always toward ourselves, not heaven,<br>
Showing we would not spare heaven as we love it,<br>
But as we stand in fear—
</p>

<p class="drama">
JULIET.<br>
I do repent me as it is an evil,<br>
And take the shame with joy.
</p>

<p class="drama">
DUKE.<br>
There rest.<br>
Your partner, as I hear, must die tomorrow,<br>
And I am going with instruction to him.<br>
Grace go with you! <i>Benedicite!</i>
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
JULIET.<br>
Must die tomorrow? O, injurious love<br>
That respites me a life, whose very comfort<br>
Is still a dying horror!
</p>

<p class="drama">
PROVOST.<br>
’Tis pity of him.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneII_21.4"></a><b>SCENE IV. A room in Angelo’s house.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Angelo</span>.
</p>

<p class="drama">
ANGELO.<br>
When I would pray and think, I think and pray<br>
To several subjects. Heaven hath my empty words,<br>
Whilst my invention, hearing not my tongue,<br>
Anchors on Isabel. Heaven in my mouth,<br>
As if I did but only chew his name,<br>
And in my heart the strong and swelling evil<br>
Of my conception. The state whereon I studied<br>
Is, like a good thing being often read,<br>
Grown sere and tedious; yea, my gravity,<br>
Wherein—let no man hear me—I take pride,<br>
Could I with boot change for an idle plume<br>
Which the air beats for vain. O place, O form,<br>
How often dost thou with thy case, thy habit,<br>
Wrench awe from fools, and tie the wiser souls<br>
To thy false seeming! Blood, thou art blood.<br>
Let’s write good angel on the devil’s horn.<br>
’Tis not the devil’s crest.
</p>

<p class="right">[<i>Knock within.</i>]</p>

<p class="drama">
How now, who’s there?</p>

<p class="scenedesc">
Enter <span class="charname">Servant</span>.
</p>

<p class="drama">
SERVANT.<br>
One Isabel, a sister, desires access to you.
</p>

<p class="drama">
ANGELO.<br>
Teach her the way.
</p>

<p class="right">[<i>Exit <span class="charname">Servant</span>.</i>]</p>

<p class="drama">
O heavens,<br>
Why does my blood thus muster to my heart,<br>
Making both it unable for itself<br>
And dispossessing all my other parts<br>
Of necessary fitness?<br>
So play the foolish throngs with one that swoons,<br>
Come all to help him, and so stop the air<br>
By which he should revive. And even so<br>
The general subject to a well-wished king<br>
Quit their own part, and in obsequious fondness<br>
Crowd to his presence, where their untaught love<br>
Must needs appear offence.
</p>

<p class="scenedesc">
Enter <span class="charname">Isabella</span>.
</p>

<p class="drama">
How now, fair maid?</p>

<p class="drama">
ISABELLA.<br>
I am come to know your pleasure.
</p>

<p class="drama">
ANGELO.<br>
That you might know it, would much better please me<br>
Than to demand what ’tis. Your brother cannot live.
</p>

<p class="drama">
ISABELLA.<br>
Even so. Heaven keep your honour.
</p>

<p class="drama">
ANGELO.<br>
Yet may he live a while. And, it may be,<br>
As long as you or I. Yet he must die.
</p>

<p class="drama">
ISABELLA.<br>
Under your sentence?
</p>

<p class="drama">
ANGELO.<br>
Yea.
</p>

<p class="drama">
ISABELLA.<br>
When, I beseech you? That in his reprieve,<br>
Longer or shorter, he may be so fitted<br>
That his soul sicken not.
</p>

<p class="drama">
ANGELO.<br>
Ha! Fie, these filthy vices! It were as good<br>
To pardon him that hath from nature stolen<br>
A man already made, as to remit<br>
Their saucy sweetness that do coin heaven’s image<br>
In stamps that are forbid. ’Tis all as easy<br>
Falsely to take away a life true made<br>
As to put metal in restrained means<br>
To make a false one.
</p>

<p class="drama">
ISABELLA.<br>
’Tis set down so in heaven, but not in earth.
</p>

<p class="drama">
ANGELO.<br>
Say you so? Then I shall pose you quickly.<br>
Which had you rather, that the most just law<br>
Now took your brother’s life; or, to redeem him,<br>
Give up your body to such sweet uncleanness<br>
As she that he hath stained?
</p>

<p class="drama">
ISABELLA.<br>
Sir, believe this:<br>
I had rather give my body than my soul.
</p>

<p class="drama">
ANGELO.<br>
I talk not of your soul. Our compelled sins<br>
Stand more for number than for accompt.
</p>

<p class="drama">
ISABELLA.<br>
How say you?
</p>

<p class="drama">
ANGELO.<br>
Nay, I’ll not warrant that, for I can speak<br>
Against the thing I say. Answer to this:<br>
I, now the voice of the recorded law,<br>
Pronounce a sentence on your brother’s life.<br>
Might there not be a charity in sin<br>
To save this brother’s life?
</p>

<p class="drama">
ISABELLA.<br>
Please you to do’t,<br>
I’ll take it as a peril to my soul;<br>
It is no sin at all, but charity.
</p>

<p class="drama">
ANGELO.<br>
Pleased you to do’t at peril of your soul,<br>
Were equal poise of sin and charity.
</p>

<p class="drama">
ISABELLA.<br>
That I do beg his life, if it be sin,<br>
Heaven let me bear it. You granting of my suit,<br>
If that be sin, I’ll make it my morn prayer<br>
To have it added to the faults of mine,<br>
And nothing of your answer.
</p>

<p class="drama">
ANGELO.<br>
Nay, but hear me.<br>
Your sense pursues not mine. Either you are ignorant,<br>
Or seem so, crafty; and that’s not good.
</p>

<p class="drama">
ISABELLA.<br>
Let me be ignorant, and in nothing good,<br>
But graciously to know I am no better.
</p>

<p class="drama">
ANGELO.<br>
Thus wisdom wishes to appear most bright<br>
When it doth tax itself, as these black masks<br>
Proclaim an enshield beauty ten times louder<br>
Than beauty could, displayed. But mark me;<br>
To be received plain, I’ll speak more gross.<br>
Your brother is to die.
</p>

<p class="drama">
ISABELLA.<br>
So.
</p>

<p class="drama">
ANGELO.<br>
And his offence is so, as it appears,<br>
Accountant to the law upon that pain.
</p>

<p class="drama">
ISABELLA.<br>
True.
</p>

<p class="drama">
ANGELO.<br>
Admit no other way to save his life—<br>
As I subscribe not that, nor any other,<br>
But, in the loss of question, that you, his sister,<br>
Finding yourself desired of such a person<br>
Whose credit with the judge, or own great place,<br>
Could fetch your brother from the manacles<br>
Of the all-binding law; and that there were<br>
No earthly mean to save him but that either<br>
You must lay down the treasures of your body<br>
To this supposed, or else to let him suffer,<br>
What would you do?
</p>

<p class="drama">
ISABELLA.<br>
As much for my poor brother as myself.<br>
That is, were I under the terms of death,<br>
Th’ impression of keen whips I’d wear as rubies,<br>
And strip myself to death as to a bed<br>
That longing have been sick for, ere I’d yield<br>
My body up to shame.
</p>

<p class="drama">
ANGELO.<br>
Then must your brother die.
</p>

<p class="drama">
ISABELLA.<br>
And ’twere the cheaper way.<br>
Better it were a brother died at once<br>
Than that a sister, by redeeming him,<br>
Should die for ever.
</p>

<p class="drama">
ANGELO.<br>
Were not you then as cruel as the sentence<br>
That you have slandered so?
</p>

<p class="drama">
ISABELLA.<br>
Ignominy in ransom and free pardon<br>
Are of two houses. Lawful mercy<br>
Is nothing kin to foul redemption.
</p>

<p class="drama">
ANGELO.<br>
You seemed of late to make the law a tyrant,<br>
And rather proved the sliding of your brother<br>
A merriment than a vice.
</p>

<p class="drama">
ISABELLA.<br>
O, pardon me, my lord. It oft falls out,<br>
To have what we would have, we speak not what we mean.<br>
I something do excuse the thing I hate<br>
For his advantage that I dearly love.
</p>

<p class="drama">
ANGELO.<br>
We are all frail.
</p>

<p class="drama">
ISABELLA.<br>
Else let my brother die,<br>
If not a feodary but only he<br>
Owe and succeed by weakness.
</p>

<p class="drama">
ANGELO.<br>
Nay, women are frail too.
</p>

<p class="drama">
ISABELLA.<br>
Ay, as the glasses where they view themselves,<br>
Which are as easy broke as they make forms.<br>
Women?—Help, heaven! Men their creation mar<br>
In profiting by them. Nay, call us ten times frail;<br>
For we are soft as our complexions are,<br>
And credulous to false prints.
</p>

<p class="drama">
ANGELO.<br>
I think it well.<br>
And from this testimony of your own sex,<br>
Since I suppose we are made to be no stronger<br>
Than faults may shake our frames, let me be bold.<br>
I do arrest your words. Be that you are,<br>
That is, a woman. If you be more, you’re none.<br>
If you be one, as you are well expressed<br>
By all external warrants, show it now<br>
By putting on the destined livery.
</p>

<p class="drama">
ISABELLA.<br>
I have no tongue but one. Gentle my lord,<br>
Let me intreat you speak the former language.
</p>

<p class="drama">
ANGELO.<br>
Plainly conceive, I love you.
</p>

<p class="drama">
ISABELLA.<br>
My brother did love Juliet,<br>
And you tell me that he shall die for ’t.
</p>

<p class="drama">
ANGELO.<br>
He shall not, Isabel, if you give me love.
</p>

<p class="drama">
ISABELLA.<br>
I know your virtue hath a license in’t,<br>
Which seems a little fouler than it is,<br>
To pluck on others.
</p>

<p class="drama">
ANGELO.<br>
Believe me, on mine honour,<br>
My words express my purpose.
</p>

<p class="drama">
ISABELLA.<br>
Ha! Little honour to be much believed,<br>
And most pernicious purpose! Seeming, seeming!<br>
I will proclaim thee, Angelo, look for’t.<br>
Sign me a present pardon for my brother<br>
Or with an outstretched throat I’ll tell the world aloud<br>
What man thou art.
</p>

<p class="drama">
ANGELO.<br>
Who will believe thee, Isabel?<br>
My unsoiled name, th’ austereness of my life,<br>
My vouch against you, and my place i’ th’ state<br>
Will so your accusation overweigh<br>
That you shall stifle in your own report,<br>
And smell of calumny. I have begun,<br>
And now I give my sensual race the rein.<br>
Fit thy consent to my sharp appetite;<br>
Lay by all nicety and prolixious blushes<br>
That banish what they sue for. Redeem thy brother<br>
By yielding up thy body to my will;<br>
Or else he must not only die the death,<br>
But thy unkindness shall his death draw out<br>
To ling’ring sufferance. Answer me tomorrow,<br>
Or, by the affection that now guides me most,<br>
I’ll prove a tyrant to him. As for you,<br>
Say what you can, my false o’erweighs your true.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
ISABELLA.<br>
To whom should I complain? Did I tell this,<br>
Who would believe me? O perilous mouths,<br>
That bear in them one and the self-same tongue<br>
Either of condemnation or approof,<br>
Bidding the law make curtsy to their will,<br>
Hooking both right and wrong to th’ appetite,<br>
To follow as it draws! I’ll to my brother.<br>
Though he hath fall’n by prompture of the blood,<br>
Yet hath he in him such a mind of honour<br>
That, had he twenty heads to tender down<br>
On twenty bloody blocks, he’d yield them up<br>
Before his sister should her body stoop<br>
To such abhorred pollution.<br>
Then, Isabel, live chaste, and, brother, die.<br>
More than our brother is our chastity.<br>
I’ll tell him yet of Angelo’s request,<br>
And fit his mind to death, for his soul’s rest.
</p>

<p class="right">[<i>Exit.</i>]</p>

