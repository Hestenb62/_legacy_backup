<h2> <a id="sceneIV_3.1"></a><b>ACT IV</b></h2>

<h3> <b>SCENE I. Caesar’s Camp at Alexandria.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Caesar, Agrippa,</span> and <span class="charname">Maecenas,</span> with his army.<br>
<span class="charname">Caesar</span> reading a letter.
</p>

<p class="drama">
CAESAR.<br>
He calls me boy, and chides as he had power<br>
To beat me out of Egypt. My messenger<br>
He hath whipped with rods; dares me to personal combat,<br>
Caesar to Antony. Let the old ruffian know<br>
I have many other ways to die; meantime<br>
Laugh at his challenge.
</p>

<p class="drama">
MAECENAS.<br>
Caesar must think,<br>
When one so great begins to rage, he’s hunted<br>
Even to falling. Give him no breath, but now<br>
Make boot of his distraction. Never anger<br>
Made good guard for itself.
</p>

<p class="drama">
CAESAR.<br>
Let our best heads<br>
Know that tomorrow the last of many battles<br>
We mean to fight. Within our files there are,<br>
Of those that served Mark Antony but late,<br>
Enough to fetch him in. See it done,<br>
And feast the army; we have store to do’t,<br>
And they have earned the waste. Poor Antony!
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneIV_3.2"></a><b>SCENE II. Alexandria. A Room in the
Palace.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Antony, Cleopatra, Enobarbus, Charmian, Iras,
Alexas</span> with others.
</p>

<p class="drama">
ANTONY.<br>
He will not fight with me, Domitius?
</p>

<p class="drama">
ENOBARBUS.<br>
No.
</p>

<p class="drama">
ANTONY.<br>
Why should he not?
</p>

<p class="drama">
ENOBARBUS.<br>
He thinks, being twenty times of better fortune,<br>
He is twenty men to one.
</p>

<p class="drama">
ANTONY.<br>
Tomorrow, soldier,<br>
By sea and land I’ll fight. Or I will live,<br>
Or bathe my dying honour in the blood<br>
Shall make it live again. Woo’t thou fight well?
</p>

<p class="drama">
ENOBARBUS.<br>
I’ll strike, and cry “Take all.”
</p>

<p class="drama">
ANTONY.<br>
Well said. Come on.<br>
Call forth my household servants. Let’s tonight<br>
Be bounteous at our meal.—
</p>

<p class="scenedesc">
Enter <span class="charname">Servants</span>.
</p>

<p class="drama">
Give me thy hand.<br>
Thou has been rightly honest; so hast thou,<br>
Thou, and thou, and thou. You have served me well,<br>
And kings have been your fellows.
</p>

<p class="drama">
CLEOPATRA.<br>
[<i>Aside to Enobarbus</i>.] What means this?
</p>

<p class="drama">
ENOBARBUS.<br>
[<i>Aside to Cleopatra</i>.] ’Tis one of those odd tricks which sorrow
shoots<br>
Out of the mind.
</p>

<p class="drama">
ANTONY.<br>
And thou art honest too.<br>
I wish I could be made so many men,<br>
And all of you clapped up together in<br>
An Antony, that I might do you service<br>
So good as you have done.
</p>

<p class="drama">
ALL THE SERVANTS.<br>
The gods forbid!
</p>

<p class="drama">
ANTONY.<br>
Well, my good fellows, wait on me tonight.<br>
Scant not my cups, and make as much of me<br>
As when mine empire was your fellow too<br>
And suffered my command.
</p>

<p class="drama">
CLEOPATRA.<br>
[<i>Aside to Enobarbus</i>.] What does he mean?
</p>

<p class="drama">
ENOBARBUS.<br>
[<i>Aside to Cleopatra</i>.] To make his followers weep.
</p>

<p class="drama">
ANTONY.<br>
Tend me tonight;<br>
May be it is the period of your duty.<br>
Haply you shall not see me more, or if,<br>
A mangled shadow. Perchance tomorrow<br>
You’ll serve another master. I look on you<br>
As one that takes his leave. Mine honest friends,<br>
I turn you not away, but, like a master<br>
Married to your good service, stay till death.<br>
Tend me tonight two hours, I ask no more,<br>
And the gods yield you for’t!
</p>

<p class="drama">
ENOBARBUS.<br>
What mean you, sir,<br>
To give them this discomfort? Look, they weep,<br>
And I, an ass, am onion-eyed. For shame,<br>
Transform us not to women.
</p>

<p class="drama">
ANTONY.<br>
Ho, ho, ho!<br>
Now the witch take me if I meant it thus!<br>
Grace grow where those drops fall! My hearty friends,<br>
You take me in too dolorous a sense,<br>
For I spake to you for your comfort, did desire you<br>
To burn this night with torches. Know, my hearts,<br>
I hope well of tomorrow, and will lead you<br>
Where rather I’ll expect victorious life<br>
Than death and honour. Let’s to supper, come,<br>
And drown consideration.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneIV_3.3"></a><b>SCENE III. Alexandria. Before the
Palace.</b></h3>

<p class="scenedesc">
Enter a Company of <span class="charname">Soldiers</span>.
</p>

<p class="drama">
FIRST SOLDIER.<br>
Brother, good night. Tomorrow is the day.
</p>

<p class="drama">
SECOND SOLDIER.<br>
It will determine one way. Fare you well.<br>
Heard you of nothing strange about the streets?
</p>

<p class="drama">
FIRST SOLDIER.<br>
Nothing. What news?
</p>

<p class="drama">
SECOND SOLDIER.<br>
Belike ’tis but a rumour. Good night to you.
</p>

<p class="drama">
FIRST SOLDIER.<br>
Well, sir, good night.
</p>

<p class="scenedesc">
Enter two other <span class="charname">Soldiers</span>.
</p>

<p class="drama">
SECOND SOLDIER.<br>
Soldiers, have careful watch.
</p>

<p class="drama">
THIRD SOLDIER.<br>
And you. Good night, good night.
</p>

<p class="right">
[<i>They place themselves in every corner of the stage.</i>]
</p>

<p class="drama">
SECOND SOLDIER.<br>
Here we. And if tomorrow<br>
Our navy thrive, I have an absolute hope<br>
Our landmen will stand up.
</p>

<p class="drama">
FIRST SOLDIER.<br>
’Tis a brave army, and full of purpose.
</p>

<p class="right">
[<i>Music of the hautboys under the stage.</i>]
</p>

<p class="drama">
SECOND SOLDIER.<br>
Peace, what noise?
</p>

<p class="drama">
FIRST SOLDIER.<br>
List, list!
</p>

<p class="drama">
SECOND SOLDIER.<br>
Hark!
</p>

<p class="drama">
FIRST SOLDIER.<br>
Music i’ th’ air.
</p>

<p class="drama">
THIRD SOLDIER.<br>
Under the earth.
</p>

<p class="drama">
FOURTH SOLDIER.<br>
It signs well, does it not?
</p>

<p class="drama">
THIRD SOLDIER.<br>
No.
</p>

<p class="drama">
FIRST SOLDIER.<br>
Peace, I say! What should this mean?
</p>

<p class="drama">
SECOND SOLDIER.<br>
’Tis the god Hercules, whom Antony loved,<br>
Now leaves him.
</p>

<p class="drama">
FIRST SOLDIER.<br>
Walk. Let’s see if other watchmen<br>
Do hear what we do.
</p>

<p class="right">
[<i>They advance to another post.</i>]
</p>

<p class="drama">
SECOND SOLDIER.<br>
How now, masters!
</p>

<p class="drama">
ALL.<br>
How now! How now! Do you hear this?
</p>

<p class="drama">
FIRST SOLDIER.<br>
Ay. Is’t not strange?
</p>

<p class="drama">
THIRD SOLDIER.<br>
Do you hear, masters? Do you hear?
</p>

<p class="drama">
FIRST SOLDIER.<br>
Follow the noise so far as we have quarter.<br>
Let’s see how it will give off.
</p>

<p class="drama">
ALL.<br>
Content. ’Tis strange.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneIV_3.4"></a><b>SCENE IV. Alexandria. A Room in the
Palace.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Antony</span> and <span class="charname">Cleopatra</span> with others.
</p>

<p class="drama">
ANTONY.<br>
Eros! Mine armour, Eros!
</p>

<p class="drama">
CLEOPATRA.<br>
Sleep a little.
</p>

<p class="drama">
ANTONY.<br>
No, my chuck.—Eros! Come, mine armour, Eros!
</p>

<p class="scenedesc">
Enter <span class="charname">Eros</span> with armour.
</p>

<p class="drama">
Come, good fellow, put thine iron on.<br>
If fortune be not ours today, it is<br>
Because we brave her. Come.
</p>

<p class="drama">
CLEOPATRA.<br>
Nay, I’ll help too.<br>
What’s this for?
</p>

<p class="drama">
ANTONY.<br>
Ah, let be, let be! Thou art<br>
The armourer of my heart. False, false. This, this!
</p>

<p class="drama">
CLEOPATRA.<br>
Sooth, la, I’ll help. Thus it must be.
</p>

<p class="drama">
ANTONY.<br>
Well, well,<br>
We shall thrive now. Seest thou, my good fellow?<br>
Go put on thy defences.
</p>

<p class="drama">
EROS.<br>
Briefly, sir.
</p>

<p class="drama">
CLEOPATRA.<br>
Is not this buckled well?
</p>

<p class="drama">
ANTONY.<br>
Rarely, rarely.<br>
He that unbuckles this, till we do please<br>
To daff’t for our repose, shall hear a storm.<br>
Thou fumblest, Eros, and my queen’s a squire<br>
More tight at this than thou. Dispatch. O love,<br>
That thou couldst see my wars today, and knew’st<br>
The royal occupation, thou shouldst see<br>
A workman in’t.
</p>

<p class="scenedesc">
Enter an <span class="charname">Officer,</span> armed.
</p>

<p class="drama">
Good morrow to thee. Welcome.<br>
Thou look’st like him that knows a warlike charge.<br>
To business that we love we rise betime<br>
And go to’t with delight.
</p>

<p class="drama">
OFFICER.<br>
A thousand, sir,<br>
Early though’t be, have on their riveted trim<br>
And at the port expect you.
</p>

<p class="right">
[<i>Shout. Trumpets flourish.</i>]
</p>

<p class="scenedesc">
Enter other <span class="charname">Captains</span> and Soldiers.
</p>

<p class="drama">
CAPTAIN.<br>
The morn is fair. Good morrow, general.
</p>

<p class="drama">
ALL.<br>
Good morrow, general.
</p>

<p class="drama">
ANTONY.<br>
’Tis well blown, lads.<br>
This morning, like the spirit of a youth<br>
That means to be of note, begins betimes.<br>
So, so. Come, give me that. This way. Well said.<br>
Fare thee well, dame.<br>
Whate’er becomes of me,<br>
This is a soldier’s kiss. [<i>Kisses her.</i>] Rebukeable<br>
And worthy shameful check it were, to stand<br>
On more mechanic compliment. I’ll leave thee<br>
Now like a man of steel.—You that will fight,<br>
Follow me close, I’ll bring you to’t. Adieu.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Antony, Eros,</span> Captains and
Soldiers.</i>]
</p>

<p class="drama">
CHARMIAN.<br>
Please you, retire to your chamber.
</p>

<p class="drama">
CLEOPATRA.<br>
Lead me.<br>
He goes forth gallantly. That he and Caesar might<br>
Determine this great war in single fight!<br>
Then Antony—but now—. Well, on.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneIV_3.5"></a><b>SCENE V. Antony’s camp near
Alexandria.</b></h3>

<p class="scenedesc">
Trumpets sound. Enter <span class="charname">Antony</span> and <span class="charname">Eros,</span> a <span class="charname">Soldier</span> meeting
them.
</p>

<p class="drama">
SOLDIER.<br>
The gods make this a happy day to Antony!
</p>

<p class="drama">
ANTONY.<br>
Would thou and those thy scars had once prevailed<br>
To make me fight at land!
</p>

<p class="drama">
SOLDIER.<br>
Hadst thou done so,<br>
The kings that have revolted and the soldier<br>
That has this morning left thee would have still<br>
Followed thy heels.
</p>

<p class="drama">
ANTONY.<br>
Who’s gone this morning?
</p>

<p class="drama">
SOLDIER.<br>
Who?<br>
One ever near thee. Call for Enobarbus,<br>
He shall not hear thee, or from Caesar’s camp<br>
Say “I am none of thine.”
</p>

<p class="drama">
ANTONY.<br>
What sayest thou?
</p>

<p class="drama">
SOLDIER.<br>
Sir,<br>
He is with Caesar.
</p>

<p class="drama">
EROS.<br>
Sir, his chests and treasure<br>
He has not with him.
</p>

<p class="drama">
ANTONY.<br>
Is he gone?
</p>

<p class="drama">
SOLDIER.<br>
Most certain.
</p>

<p class="drama">
ANTONY.<br>
Go, Eros, send his treasure after. Do it.<br>
Detain no jot, I charge thee. Write to him—<br>
I will subscribe—gentle adieus and greetings.<br>
Say that I wish he never find more cause<br>
To change a master. O, my fortunes have<br>
Corrupted honest men! Dispatch.—Enobarbus!
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneIV_3.6"></a><b>SCENE VI. Alexandria. Caesar’s camp.</b></h3>

<p class="scenedesc">
Flourish. Enter <span class="charname">Agrippa, Caesar</span> with <span class="charname">Enobarbus</span> and <span class="charname">Dolabella</span>.
</p>

<p class="drama">
CAESAR.<br>
Go forth, Agrippa, and begin the fight.<br>
Our will is Antony be took alive;<br>
Make it so known.
</p>

<p class="drama">
AGRIPPA.<br>
Caesar, I shall.
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="drama">
CAESAR.<br>
The time of universal peace is near.<br>
Prove this a prosp’rous day, the three-nooked world<br>
Shall bear the olive freely.
</p>

<p class="scenedesc">
Enter a <span class="charname">Messenger</span>.
</p>

<p class="drama">
MESSENGER.<br>
Antony<br>
Is come into the field.
</p>

<p class="drama">
CAESAR.<br>
Go charge Agrippa<br>
Plant those that have revolted in the van<br>
That Antony may seem to spend his fury<br>
Upon himself.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Caesar</span> and his Train.</i>]
</p>

<p class="drama">
ENOBARBUS.<br>
Alexas did revolt and went to Jewry on<br>
Affairs of Antony; there did dissuade<br>
Great Herod to incline himself to Caesar<br>
And leave his master Antony. For this pains<br>
Caesar hath hanged him. Canidius and the rest<br>
That fell away have entertainment but<br>
No honourable trust. I have done ill,<br>
Of which I do accuse myself so sorely<br>
That I will joy no more.
</p>

<p class="scenedesc">
Enter a <span class="charname">Soldier</span> of Caesar’s.
</p>

<p class="drama">
SOLDIER.<br>
Enobarbus, Antony<br>
Hath after thee sent all thy treasure, with<br>
His bounty overplus. The messenger<br>
Came on my guard, and at thy tent is now<br>
Unloading of his mules.
</p>

<p class="drama">
ENOBARBUS.<br>
I give it you.
</p>

<p class="drama">
SOLDIER.<br>
Mock not, Enobarbus.<br>
I tell you true. Best you safed the bringer<br>
Out of the host. I must attend mine office,<br>
Or would have done’t myself. Your emperor<br>
Continues still a Jove.
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="drama">
ENOBARBUS.<br>
I am alone the villain of the earth,<br>
And feel I am so most. O Antony,<br>
Thou mine of bounty, how wouldst thou have paid<br>
My better service, when my turpitude<br>
Thou dost so crown with gold! This blows my heart.<br>
If swift thought break it not, a swifter mean<br>
Shall outstrike thought, but thought will do’t, I feel.<br>
I fight against thee! No, I will go seek<br>
Some ditch wherein to die; the foul’st best fits<br>
My latter part of life.
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<h3> <a id="sceneIV_3.7"></a><b>SCENE VII. Field of battle between the
Camps.</b></h3>

<p class="scenedesc">
Alarum. Drums and Trumpets. Enter <span class="charname">Agrippa</span> and
others.
</p>

<p class="drama">
AGRIPPA.<br>
Retire! We have engaged ourselves too far.<br>
Caesar himself has work, and our oppression<br>
Exceeds what we expected.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<p class="scenedesc">
Alarums. Enter <span class="charname">Antony</span> and <span class="charname">Scarus</span> wounded.
</p>

<p class="drama">
SCARUS.<br>
O my brave emperor, this is fought indeed!<br>
Had we done so at first, we had droven them home<br>
With clouts about their heads.
</p>

<p class="drama">
ANTONY.<br>
Thou bleed’st apace.
</p>

<p class="drama">
SCARUS.<br>
I had a wound here that was like a T,<br>
But now ’tis made an H.
</p>

<p class="right">
<i>Sounds retreat far off.</i>
</p> <p class="drama">
ANTONY.<br>
They do retire.
</p>

<p class="drama">
SCARUS.<br>
We’ll beat ’em into bench-holes. I have yet<br>
Room for six scotches more.
</p>

<p class="scenedesc">
Enter <span class="charname">Eros</span>.
</p>

<p class="drama">
EROS.<br>
They are beaten, sir, and our advantage serves<br>
For a fair victory.
</p>

<p class="drama">
SCARUS.<br>
Let us score their backs<br>
And snatch ’em up as we take hares, behind.<br>
’Tis sport to maul a runner.
</p>

<p class="drama">
ANTONY.<br>
I will reward thee<br>
Once for thy sprightly comfort, and tenfold<br>
For thy good valour. Come thee on.
</p>

<p class="drama">
SCARUS.<br>
I’ll halt after.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneIV_3.8"></a><b>SCENE VIII. Under the Walls of
Alexandria.</b></h3>

<p class="scenedesc">
Alarum. Enter <span class="charname">Antony</span> again in a march; <span class="charname">Scarus</span> with others.
</p>

<p class="drama">
ANTONY.<br>
We have beat him to his camp. Run one before<br>
And let the Queen know of our gests.<br>
Tomorrow,<br>
Before the sun shall see’s, we’ll spill the blood<br>
That has today escaped. I thank you all,<br>
For doughty-handed are you, and have fought<br>
Not as you served the cause, but as’t had been<br>
Each man’s like mine. You have shown all Hectors.<br>
Enter the city, clip your wives, your friends,<br>
Tell them your feats; whilst they with joyful tears<br>
Wash the congealment from your wounds and kiss<br>
The honoured gashes whole.
</p>

<p class="scenedesc">
Enter <span class="charname">Cleopatra</span>.
</p>

<p class="drama">
[<i>To Scarus</i>.] Give me thy hand.<br>
To this great fairy I’ll commend thy acts,<br>
Make her thanks bless thee. O thou day o’ th’ world,<br>
Chain mine armed neck. Leap thou, attire and all,<br>
Through proof of harness to my heart, and there<br>
Ride on the pants triumphing.
</p>

<p class="drama">
CLEOPATRA.<br>
Lord of lords!<br>
O infinite virtue, com’st thou smiling from<br>
The world’s great snare uncaught?
</p>

<p class="drama">
ANTONY.<br>
Mine nightingale,<br>
We have beat them to their beds. What, girl! Though grey<br>
Do something mingle with our younger brown, yet ha’ we<br>
A brain that nourishes our nerves and can<br>
Get goal for goal of youth. Behold this man.<br>
Commend unto his lips thy favouring hand.—<br>
Kiss it, my warrior. He hath fought today<br>
As if a god, in hate of mankind, had<br>
Destroyed in such a shape.
</p>

<p class="drama">
CLEOPATRA.<br>
I’ll give thee, friend,<br>
An armour all of gold. It was a king’s.
</p>

<p class="drama">
ANTONY.<br>
He has deserved it, were it carbuncled<br>
Like holy Phœbus’ car. Give me thy hand.<br>
Through Alexandria make a jolly march;<br>
Bear our hacked targets like the men that owe them.<br>
Had our great palace the capacity<br>
To camp this host, we all would sup together<br>
And drink carouses to the next day’s fate,<br>
Which promises royal peril.—Trumpeters,<br>
With brazen din blast you the city’s ear;<br>
Make mingle with our rattling tabourines,<br>
That heaven and earth may strike their sounds together,<br>
Applauding our approach.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneIV_3.9"></a><b>SCENE IX. Caesar’s camp.</b></h3>

<p class="scenedesc">
Enter a <span class="charname">Sentry</span> and his company. <span class="charname">Enobarbus</span> follows.
</p>

<p class="drama">
SENTRY.<br>
If we be not relieved within this hour,<br>
We must return to th’ court of guard. The night<br>
Is shiny, and they say we shall embattle<br>
By th’ second hour i’ th’ morn.
</p>

<p class="drama">
FIRST WATCH.<br>
This last day was a shrewd one to’s.
</p>

<p class="drama">
ENOBARBUS.<br>
O, bear me witness, night.—
</p>

<p class="drama">
SECOND WATCH.<br>
What man is this?
</p>

<p class="drama">
FIRST WATCH.<br>
Stand close and list him.
</p>

<p class="drama">
ENOBARBUS.<br>
Be witness to me, O thou blessed moon,<br>
When men revolted shall upon record<br>
Bear hateful memory, poor Enobarbus did<br>
Before thy face repent.
</p>

<p class="drama">
SENTRY.<br>
Enobarbus?
</p>

<p class="drama">
SECOND WATCH.<br>
Peace! Hark further.
</p>

<p class="drama">
ENOBARBUS.<br>
O sovereign mistress of true melancholy,<br>
The poisonous damp of night disponge upon me,<br>
That life, a very rebel to my will,<br>
May hang no longer on me. Throw my heart<br>
Against the flint and hardness of my fault,<br>
Which, being dried with grief, will break to powder<br>
And finish all foul thoughts. O Antony,<br>
Nobler than my revolt is infamous,<br>
Forgive me in thine own particular,<br>
But let the world rank me in register<br>
A master-leaver and a fugitive.<br>
O Antony! O Antony!
</p>

<p class="right">
[<i>Dies.</i>]
</p>

<p class="drama">
FIRST WATCH.<br>
Let’s speak to him.
</p>

<p class="drama">
SENTRY.<br>
Let’s hear him, for the things he speaks may concern Caesar.
</p>

<p class="drama">
SECOND WATCH.<br>
Let’s do so. But he sleeps.
</p>

<p class="drama">
SENTRY.<br>
Swoons rather, for so bad a prayer as his<br>
Was never yet for sleep.
</p>

<p class="drama">
FIRST WATCH.<br>
Go we to him.
</p>

<p class="drama">
SECOND WATCH.<br>
Awake, sir, awake! Speak to us.
</p>

<p class="drama">
FIRST WATCH.<br>
Hear you, sir?
</p>

<p class="drama">
SENTRY.<br>
The hand of death hath raught him.
</p>

<p class="right">
[<i>Drums afar off.</i>]
</p>

<p class="drama">
Hark! The drums<br>
Demurely wake the sleepers. Let us bear him<br>
To th’ court of guard; he is of note. Our hour<br>
Is fully out.
</p>

<p class="drama">
SECOND WATCH.<br>
Come on, then. He may recover yet.
</p>

<p class="right">
[<i>Exeunt with the body.</i>]
</p>

<h3> <a id="sceneIV_3.10"></a><b>SCENE X. Ground between the two
Camps.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Antony</span> and <span class="charname">Scarus</span> with their army.
</p>

<p class="drama">
ANTONY.<br>
Their preparation is today by sea;<br>
We please them not by land.
</p>

<p class="drama">
SCARUS.<br>
For both, my lord.
</p>

<p class="drama">
ANTONY.<br>
I would they’d fight i’ th’ fire or i’ th’ air;<br>
We’d fight there too. But this it is: our foot<br>
Upon the hills adjoining to the city<br>
Shall stay with us—order for sea is given;<br>
They have put forth the haven—<br>
Where their appointment we may best discover<br>
And look on their endeavour.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneIV_3.11"></a><b>SCENE XI. Another part of the
Ground.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Caesar</span> and his army.
</p>

<p class="drama">
CAESAR.<br>
But being charged, we will be still by land,<br>
Which, as I take’t, we shall, for his best force<br>
Is forth to man his galleys. To the vales,<br>
And hold our best advantage.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneIV_3.12"></a><b>SCENE XII. Another part of the
Ground.</b></h3>

<p class="scenedesc">
Alarum afar off, as at a sea fight. Enter <span class="charname">Antony</span>
and <span class="charname">Scarus</span>.
</p>

<p class="drama">
ANTONY.<br>
Yet they are not joined. Where yond pine does stand<br>
I shall discover all. I’ll bring thee word<br>
Straight how ’tis like to go.
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="drama">
SCARUS.<br>
Swallows have built<br>
In Cleopatra’s sails their nests. The augurs<br>
Say they know not, they cannot tell; look grimly,<br>
And dare not speak their knowledge. Antony<br>
Is valiant and dejected, and by starts<br>
His fretted fortunes give him hope and fear<br>
Of what he has and has not.
</p>

<p class="scenedesc">
Enter <span class="charname">Antony</span>.
</p>

<p class="drama">
ANTONY.<br>
All is lost!<br>
This foul Egyptian hath betrayed me.<br>
My fleet hath yielded to the foe, and yonder<br>
They cast their caps up and carouse together<br>
Like friends long lost. Triple-turned whore! ’Tis thou<br>
Hast sold me to this novice, and my heart<br>
Makes only wars on thee. Bid them all fly;<br>
For when I am revenged upon my charm,<br>
I have done all. Bid them all fly! Be gone!
</p>

<p class="right">
[<i>Exit <span class="charname">Scarus</span>.</i>]
</p>

<p class="drama">
O sun, thy uprise shall I see no more.<br>
Fortune and Antony part here; even here<br>
Do we shake hands. All come to this! The hearts<br>
That spanieled me at heels, to whom I gave<br>
Their wishes, do discandy, melt their sweets<br>
On blossoming Caesar, and this pine is barked<br>
That overtopped them all. Betray’d I am:<br>
O this false soul of Egypt! This grave charm,<br>
Whose eye becked forth my wars and called them home,<br>
Whose bosom was my crownet, my chief end,<br>
Like a right gypsy hath at fast and loose<br>
Beguiled me to the very heart of loss.<br>
What, Eros, Eros!
</p>

<p class="scenedesc">
Enter <span class="charname">Cleopatra</span>.
</p>

<p class="drama">
Ah, thou spell! Avaunt!
</p>

<p class="drama">
CLEOPATRA.<br>
Why is my lord enraged against his love?
</p>

<p class="drama">
ANTONY.<br>
Vanish, or I shall give thee thy deserving<br>
And blemish Caesar’s triumph. Let him take thee<br>
And hoist thee up to the shouting plebeians!<br>
Follow his chariot, like the greatest spot<br>
Of all thy sex; most monster-like be shown<br>
For poor’st diminutives, for dolts, and let<br>
Patient Octavia plough thy visage up<br>
With her prepared nails.
</p>

<p class="right">
[<i>Exit <span class="charname">Cleopatra</span>.</i>]
</p>

<p class="drama">
’Tis well thou’rt gone,<br>
If it be well to live; but better ’twere<br>
Thou fell’st into my fury, for one death<br>
Might have prevented many.—Eros, ho!—<br>
The shirt of Nessus is upon me. Teach me,<br>
Alcides, thou mine ancestor, thy rage.<br>
Let me lodge Lichas on the horns o’ th’ moon,<br>
And with those hands that grasped the heaviest club<br>
Subdue my worthiest self. The witch shall die.<br>
To the young Roman boy she hath sold me, and I fall<br>
Under this plot. She dies for’t.—Eros, ho!
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<h3> <a id="sceneIV_3.13"></a><b>SCENE XIII. Alexandria. A Room in the
Palace.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Cleopatra, Charmian, Iras</span> and <span class="charname">Mardian</span>.
</p>

<p class="drama">
CLEOPATRA.<br>
Help me, my women! O, he is more mad<br>
Than Telamon for his shield; the boar of Thessaly<br>
Was never so embossed.
</p>

<p class="drama">
CHARMIAN.<br>
To th’ monument!<br>
There lock yourself and send him word you are dead.<br>
The soul and body rive not more in parting<br>
Than greatness going off.
</p>

<p class="drama">
CLEOPATRA.<br>
To th’ monument!<br>
Mardian, go tell him I have slain myself.<br>
Say that the last I spoke was “Antony”,<br>
And word it, prithee, piteously. Hence, Mardian,<br>
And bring me how he takes my death.—To th’ monument!
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneIV_3.14"></a><b>SCENE XIV. Alexandria. Another Room.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Antony</span> and <span class="charname">Eros</span>.
</p>

<p class="drama">
ANTONY.<br>
Eros, thou yet behold’st me?
</p>

<p class="drama">
EROS.<br>
Ay, noble lord.
</p>

<p class="drama">
ANTONY.<br>
Sometime we see a cloud that’s dragonish,<br>
A vapour sometime like a bear or lion,<br>
A towered citadel, a pendant rock,<br>
A forked mountain, or blue promontory<br>
With trees upon’t, that nod unto the world<br>
And mock our eyes with air. Thou hast seen these signs.<br>
They are black vesper’s pageants.
</p>

<p class="drama">
EROS.<br>
Ay, my lord.
</p>

<p class="drama">
ANTONY.<br>
That which is now a horse, even with a thought<br>
The rack dislimns and makes it indistinct<br>
As water is in water.
</p>

<p class="drama">
EROS.<br>
It does, my lord.
</p>

<p class="drama">
ANTONY.<br>
My good knave Eros, now thy captain is<br>
Even such a body. Here I am Antony,<br>
Yet cannot hold this visible shape, my knave.<br>
I made these wars for Egypt, and the Queen,<br>
Whose heart I thought I had, for she had mine,<br>
Which, whilst it was mine, had annexed unto’t<br>
A million more, now lost—she, Eros, has<br>
Packed cards with Caesar, and false-played my glory<br>
Unto an enemy’s triumph.<br>
Nay, weep not, gentle Eros. There is left us<br>
Ourselves to end ourselves.
</p>

<p class="scenedesc">
Enter <span class="charname">Mardian</span>.
</p>

<p class="drama">
O, thy vile lady!<br>
She has robbed me of my sword.
</p>

<p class="drama">
MARDIAN.<br>
No, Antony,<br>
My mistress loved thee and her fortunes mingled<br>
With thine entirely.
</p>

<p class="drama">
ANTONY.<br>
Hence, saucy eunuch! Peace!<br>
She hath betrayed me and shall die the death.
</p>

<p class="drama">
MARDIAN.<br>
Death of one person can be paid but once,<br>
And that she has discharged. What thou wouldst do<br>
Is done unto thy hand. The last she spake<br>
Was “Antony! Most noble Antony!”<br>
Then in the midst a tearing groan did break<br>
The name of Antony; it was divided<br>
Between her heart and lips. She rendered life,<br>
Thy name so buried in her.
</p>

<p class="drama">
ANTONY.<br>
Dead, then?
</p>

<p class="drama">
MARDIAN.<br>
Dead.
</p>

<p class="drama">
ANTONY.<br>
Unarm, Eros. The long day’s task is done,<br>
And we must sleep.—That thou depart’st hence safe<br>
Does pay thy labour richly. Go.
</p>

<p class="right">
[<i>Exit <span class="charname">Mardian</span>.</i>]
</p>

<p class="drama">
Off, pluck off!<br>
The sevenfold shield of Ajax cannot keep<br>
The battery from my heart. O, cleave, my sides!<br>
Heart, once be stronger than thy continent;<br>
Crack thy frail case! Apace, Eros, apace!<br>
No more a soldier. Bruised pieces, go;<br>
You have been nobly borne. From me awhile.
</p>

<p class="right">
[<i>Exit <span class="charname">Eros</span>.</i>]
</p>

<p class="drama">
I will o’ertake thee, Cleopatra, and<br>
Weep for my pardon. So it must be, for now<br>
All length is torture. Since the torch is out,<br>
Lie down, and stray no farther. Now all labour<br>
Mars what it does; yea, very force entangles<br>
Itself with strength. Seal then, and all is done.<br>
Eros!—I come, my queen.—Eros!—Stay for me.<br>
Where souls do couch on flowers, we’ll hand in hand,<br>
And with our sprightly port make the ghosts gaze.<br>
Dido and her Aeneas shall want troops,<br>
And all the haunt be ours.—Come, Eros, Eros!
</p>

<p class="scenedesc">
Enter <span class="charname">Eros</span>.
</p>

<p class="drama">
EROS.<br>
What would my lord?
</p>

<p class="drama">
ANTONY.<br>
Since Cleopatra died,<br>
I have lived in such dishonour that the gods<br>
Detest my baseness. I, that with my sword<br>
Quartered the world, and o’er green Neptune’s back<br>
With ships made cities, condemn myself to lack<br>
The courage of a woman; less noble mind<br>
Than she which, by her death, our Caesar tells<br>
“I am conqueror of myself.” Thou art sworn, Eros,<br>
That when the exigent should come, which now<br>
Is come indeed, when I should see behind me<br>
Th’ inevitable prosecution of<br>
Disgrace and horror, that on my command<br>
Thou then wouldst kill me. Do’t. The time is come.<br>
Thou strik’st not me; ’tis Caesar thou defeat’st.<br>
Put colour in thy cheek.
</p>

<p class="drama">
EROS.<br>
The gods withhold me!<br>
Shall I do that which all the Parthian darts,<br>
Though enemy, lost aim and could not?
</p>

<p class="drama">
ANTONY.<br>
Eros,<br>
Wouldst thou be windowed in great Rome and see<br>
Thy master thus with pleached arms, bending down<br>
His corrigible neck, his face subdued<br>
To penetrative shame, whilst the wheeled seat<br>
Of fortunate Caesar, drawn before him, branded<br>
His baseness that ensued?
</p>

<p class="drama">
EROS.<br>
I would not see’t.
</p>

<p class="drama">
ANTONY.<br>
Come, then, for with a wound I must be cured.<br>
Draw that thy honest sword, which thou hast worn<br>
Most useful for thy country.
</p>

<p class="drama">
EROS.<br>
O, sir, pardon me!
</p>

<p class="drama">
ANTONY.<br>
When I did make thee free, swor’st thou not then<br>
To do this when I bade thee? Do it at once,<br>
Or thy precedent services are all<br>
But accidents unpurposed. Draw, and come.
</p>

<p class="drama">
EROS.<br>
Turn from me then that noble countenance<br>
Wherein the worship of the whole world lies.
</p>

<p class="drama">
ANTONY.<br>
Lo thee!
</p>

<p class="right">
[<i>Turning from him.</i>]
</p>

<p class="drama">
EROS.<br>
My sword is drawn.
</p>

<p class="drama">
ANTONY.<br>
Then let it do at once<br>
The thing why thou hast drawn it.
</p>

<p class="drama">
EROS.<br>
My dear master,<br>
My captain and my emperor, let me say,<br>
Before I strike this bloody stroke, farewell.
</p>

<p class="drama">
ANTONY.<br>
’Tis said, man, and farewell.
</p>

<p class="drama">
EROS.<br>
Farewell, great chief. Shall I strike now?
</p>

<p class="drama">
ANTONY.<br>
Now, Eros.
</p>

<p class="drama">
EROS.<br>
Why, there then! [<i>kills himself</i>]<br>
Thus do I escape the sorrow<br>
Of Antony’s death.
</p>

<p class="right">
[<i>Dies.</i>]
</p>

<p class="drama">
ANTONY.<br>
Thrice nobler than myself!<br>
Thou teachest me, O valiant Eros, what<br>
I should and thou couldst not. My queen and Eros<br>
Have by their brave instruction got upon me<br>
A nobleness in record. But I will be<br>
A bridegroom in my death and run into’t<br>
As to a lover’s bed. Come then, and, Eros,<br>
Thy master dies thy scholar. To do thus
</p>

<p class="right">
[<i>Falling on his sword.</i>]
</p>

<p class="drama">
I learned of thee. How? Not dead? Not dead?<br>
The guard, ho! O, dispatch me!
</p>

<p class="scenedesc">
Enter a company of the <span class="charname">Guard,</span> one of them <span class="charname">Dercetus</span>.
</p>

<p class="drama">
FIRST GUARD.<br>
What’s the noise?
</p>

<p class="drama">
ANTONY.<br>
I have done my work ill, friends. O, make an end<br>
Of what I have begun.
</p>

<p class="drama">
SECOND GUARD.<br>
The star is fallen.
</p>

<p class="drama">
FIRST GUARD.<br>
And time is at his period.
</p>

<p class="drama">
ALL.<br>
Alas, and woe!
</p>

<p class="drama">
ANTONY.<br>
Let him that loves me strike me dead.
</p>

<p class="drama">
FIRST GUARD.<br>
Not I.
</p>

<p class="drama">
SECOND GUARD.<br>
Nor I.
</p>

<p class="drama">
THIRD GUARD.<br>
Nor anyone.
</p>

<p class="right">
[<i>Exeunt guard.</i>]
</p>

<p class="drama">
DERCETUS.<br>
Thy death and fortunes bid thy followers fly.<br>
This sword but shown to Caesar with this tidings,<br>
Shall enter me with him.
</p>

<p class="scenedesc">
Enter <span class="charname">Diomedes</span>.
</p>

<p class="drama">
DIOMEDES.<br>
Where’s Antony?
</p>

<p class="drama">
DERCETUS.<br>
There, Diomed, there.
</p>

<p class="drama">
DIOMEDES.<br>
Lives he? Wilt thou not answer, man?
</p>

<p class="right">
[<i>Exit <span class="charname">Dercetus</span>.</i>]
</p>

<p class="drama">
ANTONY.<br>
Art thou there, Diomed? Draw thy sword and give me<br>
Sufficing strokes for death.
</p>

<p class="drama">
DIOMEDES.<br>
Most absolute lord,<br>
My mistress Cleopatra sent me to thee.
</p>

<p class="drama">
ANTONY.<br>
When did she send thee?
</p>

<p class="drama">
DIOMEDES.<br>
Now, my lord.
</p>

<p class="drama">
ANTONY.<br>
Where is she?
</p>

<p class="drama">
DIOMEDES.<br>
Locked in her monument. She had a prophesying fear<br>
Of what hath come to pass. For when she saw—<br>
Which never shall be found—you did suspect<br>
She had disposed with Caesar, and that your rage<br>
Would not be purged, she sent you word she was dead;<br>
But fearing since how it might work, hath sent<br>
Me to proclaim the truth, and I am come,<br>
I dread, too late.
</p>

<p class="drama">
ANTONY.<br>
Too late, good Diomed. Call my guard, I prithee.
</p>

<p class="drama">
DIOMEDES.<br>
What, ho! The emperor’s guard! The guard, what ho!<br>
Come, your lord calls!
</p>

<p class="scenedesc">
Enter four or five of the <span class="charname">Guard</span> of Antony.
</p>

<p class="drama">
ANTONY.<br>
Bear me, good friends, where Cleopatra bides.<br>
’Tis the last service that I shall command you.
</p>

<p class="drama">
FIRST GUARD.<br>
Woe, woe are we, sir, you may not live to wear<br>
All your true followers out.
</p>

<p class="drama">
ALL.<br>
Most heavy day!
</p>

<p class="drama">
ANTONY.<br>
Nay, good my fellows, do not please sharp fate<br>
To grace it with your sorrows. Bid that welcome<br>
Which comes to punish us, and we punish it,<br>
Seeming to bear it lightly. Take me up.<br>
I have led you oft; carry me now, good friends,<br>
And have my thanks for all.
</p>

<p class="right">
[<i>Exeunt, bearing <span class="charname">Antony</span>.</i>]
</p>

<h3> <a id="sceneIV_3.15"></a><b>SCENE XV. Alexandria. A monument.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Cleopatra</span> and her maids aloft, with <span class="charname">Charmian</span> and <span class="charname">Iras</span>.
</p>

<p class="drama">
CLEOPATRA.<br>
O Charmian, I will never go from hence.
</p>

<p class="drama">
CHARMIAN.<br>
Be comforted, dear madam.
</p>

<p class="drama">
CLEOPATRA.<br>
No, I will not.<br>
All strange and terrible events are welcome,<br>
But comforts we despise. Our size of sorrow,<br>
Proportioned to our cause, must be as great<br>
As that which makes it.
</p>

<p class="scenedesc">
Enter, below <span class="charname">Diomedes</span>.
</p>

<p class="drama">
How now! Is he dead?
</p>

<p class="drama">
DIOMEDES.<br>
His death’s upon him, but not dead.<br>
Look out o’ th’ other side your monument;<br>
His guard have brought him thither.
</p>

<p class="scenedesc">
Enter, below <span class="charname">Antony</span> borne by the Guard.
</p>

<p class="drama">
CLEOPATRA.<br>
O sun,<br>
Burn the great sphere thou mov’st in! Darkling stand<br>
The varying shore o’ th’ world. O Antony,<br>
Antony, Antony! Help, Charmian! Help, Iras, help!<br>
Help, friends below! Let’s draw him hither.
</p>

<p class="drama">
ANTONY.<br>
Peace!<br>
Not Caesar’s valour hath o’erthrown Antony,<br>
But Antony’s hath triumphed on itself.
</p>

<p class="drama">
CLEOPATRA.<br>
So it should be, that none but Antony<br>
Should conquer Antony, but woe ’tis so!
</p>

<p class="drama">
ANTONY.<br>
I am dying, Egypt, dying. Only<br>
I here importune death awhile until<br>
Of many thousand kisses the poor last<br>
I lay upon thy lips.
</p>

<p class="drama">
CLEOPATRA.<br>
I dare not, dear<br>
Dear my lord, pardon. I dare not,<br>
Lest I be taken. Not th’ imperious show<br>
Of the full-fortuned Caesar ever shall<br>
Be brooched with me; if knife, drugs, serpents, have<br>
Edge, sting, or operation, I am safe.<br>
Your wife Octavia, with her modest eyes<br>
And still conclusion, shall acquire no honour<br>
Demuring upon me. But come, come, Antony—<br>
Help me, my women—we must draw thee up.<br>
Assist, good friends.
</p>

<p class="drama">
ANTONY.<br>
O, quick, or I am gone.
</p>

<p class="drama">
CLEOPATRA.<br>
Here’s sport indeed! How heavy weighs my lord!<br>
Our strength is all gone into heaviness;<br>
That makes the weight. Had I great Juno’s power,<br>
The strong-winged Mercury should fetch thee up<br>
And set thee by Jove’s side. Yet come a little;<br>
Wishers were ever fools. O come, come come,
</p>

<p class="right">
[<i>They heave <span class="charname">Antony</span> aloft to <span class="charname">Cleopatra.</span></i>]
</p>

<p class="drama">
And welcome, welcome! Die where thou hast lived;<br>
Quicken with kissing. Had my lips that power,<br>
Thus would I wear them out.
</p>

<p class="drama">
ALL.<br>
A heavy sight!
</p>

<p class="drama">
ANTONY.<br>
I am dying, Egypt, dying.<br>
Give me some wine, and let me speak a little.
</p>

<p class="drama">
CLEOPATRA.<br>
No, let me speak, and let me rail so high<br>
That the false huswife Fortune break her wheel,<br>
Provoked by my offence.
</p>

<p class="drama">
ANTONY.<br>
One word, sweet queen:<br>
Of Caesar seek your honour, with your safety. O!
</p>

<p class="drama">
CLEOPATRA.<br>
They do not go together.
</p>

<p class="drama">
ANTONY.<br>
Gentle, hear me.<br>
None about Caesar trust but Proculeius.
</p>

<p class="drama">
CLEOPATRA.<br>
My resolution and my hands I’ll trust;<br>
None about Caesar.
</p>

<p class="drama">
ANTONY.<br>
The miserable change now at my end<br>
Lament nor sorrow at, but please your thoughts<br>
In feeding them with those my former fortunes<br>
Wherein I lived the greatest prince o’ th’ world,<br>
The noblest; and do now not basely die,<br>
Not cowardly put off my helmet to<br>
My countryman; a Roman by a Roman<br>
Valiantly vanquished. Now my spirit is going;<br>
I can no more.
</p>

<p class="drama">
CLEOPATRA.<br>
Noblest of men, woo’t die?<br>
Hast thou no care of me? Shall I abide<br>
In this dull world, which in thy absence is<br>
No better than a sty? O, see, my women,
</p>

<p class="right">
[<i> <span class="charname">Antony</span> dies.</i>]
</p>

<p class="drama">
The crown o’ th’ earth doth melt.—My lord!<br>
O, withered is the garland of the war,<br>
The soldier’s pole is fallen; young boys and girls<br>
Are level now with men. The odds is gone,<br>
And there is nothing left remarkable<br>
Beneath the visiting moon.
</p>

<p class="right">
[<i>Faints.</i>]
</p>

<p class="drama">
CHARMIAN.<br>
O, quietness, lady!
</p>

<p class="drama">
IRAS.<br>
She is dead too, our sovereign.
</p>

<p class="drama">
CHARMIAN.<br>
Lady!
</p>

<p class="drama">
IRAS.<br>
Madam!
</p>

<p class="drama">
CHARMIAN.<br>
O madam, madam, madam!
</p>

<p class="drama">
IRAS.<br>
Royal Egypt, Empress!
</p>

<p class="drama">
CHARMIAN.<br>
Peace, peace, Iras!
</p>

<p class="drama">
CLEOPATRA.<br>
No more but e’en a woman, and commanded<br>
By such poor passion as the maid that milks<br>
And does the meanest chares. It were for me<br>
To throw my sceptre at the injurious gods,<br>
To tell them that this world did equal theirs<br>
Till they had stolen our jewel. All’s but naught;<br>
Patience is sottish, and impatience does<br>
Become a dog that’s mad. Then is it sin<br>
To rush into the secret house of death<br>
Ere death dare come to us? How do you, women?<br>
What, what! good cheer! Why, how now, Charmian?<br>
My noble girls! Ah, women, women! Look,<br>
Our lamp is spent, it’s out! Good sirs, take heart.<br>
We’ll bury him; and then, what’s brave, what’s noble,<br>
Let’s do it after the high Roman fashion<br>
And make death proud to take us. Come, away.<br>
This case of that huge spirit now is cold.<br>
Ah, women, women! Come, we have no friend<br>
But resolution and the briefest end.
</p>

<p class="right">
[<i>Exeunt, bearing off <span class="charname">Antony’s</span> body.</i>]
</p>

