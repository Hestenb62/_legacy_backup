<h3> <a id="sceneII_9.4"></a><b>SCENE IV. Eastcheap. A Room in the Boar’s Head Tavern.</b></h3>

<p class="scenedesc">Enter <span class="charname">Prince Henry</span>.
</p>

<p class="drama">
PRINCE.<br>
Ned, prithee, come out of that fat room, and lend me thy hand to laugh a
little.
</p>

<p class="scenedesc">Enter <span class="charname">Poins</span>.
</p>

<p class="drama">
POINS.<br>
Where hast been, Hal?
</p>

<p class="drama">
PRINCE.<br>
With three or four loggerheads amongst three or fourscore hogsheads. I have
sounded the very base-string of humility. Sirrah, I am sworn brother to a leash
of drawers, and can call them all by their Christian names, as Tom, Dick, and
Francis. They take it already upon their salvation, that though I be but Prince
of Wales, yet I am the king of courtesy, and tell me flatly I am no proud Jack,
like Falstaff, but a Corinthian, a lad of mettle, a good boy,—by the
Lord, so they call me—and when I am King of England, I shall command all
the good lads in Eastcheap. They call drinking deep, “dyeing
scarlet,” and when you breathe in your watering, they cry
“Hem!” and bid you “Play it off!” To conclude, I am so
good a proficient in one quarter of an hour, that I can drink with any tinker
in his own language during my life. I tell thee, Ned, thou hast lost much
honour that thou wert not with me in this action; but, sweet Ned—to
sweeten which name of Ned, I give thee this pennyworth of sugar, clapped even
now into my hand by an underskinker, one that never spake other English in his
life than “Eight shillings and sixpence,” and “You are
welcome,” with this shrill addition, “Anon, anon, sir! Score a pint
of bastard in the Half-moon,” or so. But, Ned, to drive away the time
till Falstaff come, I prithee, do thou stand in some by-room, while I question
my puny drawer to what end he gave me the sugar, and do thou never leave
calling “Francis,” that his tale to me may be nothing but
“Anon.” Step aside, and I’ll show thee a precedent.
</p>

<p class="right">[<i>Exit <span class="charname">Poins</span>.</i>]
</p>

<p class="drama">
POINS.<br>
[<i>Within</i>] Francis!
</p>

<p class="drama">
PRINCE.<br>
Thou art perfect.
</p>

<p class="drama">
POINS.<br>
[<i>Within</i>] Francis!
</p>

<p class="scenedesc">Enter <span class="charname">Francis</span>.
</p>

<p class="drama">
FRANCIS.<br>
Anon, anon, sir.—Look down into the Pomegarnet, Ralph.
</p>

<p class="drama">
PRINCE.<br>
Come hither, Francis.
</p>

<p class="drama">
FRANCIS.<br>
My lord?
</p>

<p class="drama">
PRINCE.<br>
How long hast thou to serve, Francis?
</p>

<p class="drama">
FRANCIS.<br>
Forsooth, five years, and as much as to—
</p>

<p class="drama">
POINS.<br>
[<i>within.</i>] Francis!
</p>

<p class="drama">
FRANCIS.<br>
Anon, anon, sir.
</p>

<p class="drama">
PRINCE.<br>
Five year! By’r Lady, a long lease for the clinking of pewter! But,
Francis, darest thou be so valiant as to play the coward with thy indenture,
and show it a fair pair of heels, and run from it?
</p>

<p class="drama">
FRANCIS.<br>
O Lord, sir, I’ll be sworn upon all the books in England, I could find in
my heart—
</p>

<p class="drama">
POINS.<br>
[<i>within.</i>] Francis!
</p>

<p class="drama">
FRANCIS.<br>
Anon, sir.
</p>

<p class="drama">
PRINCE.<br>
How old art thou, Francis?
</p>

<p class="drama">
FRANCIS.<br>
Let me see, about Michaelmas next I shall be—
</p>

<p class="drama">
POINS.<br>
[<i>within.</i>] Francis!
</p>

<p class="drama">
FRANCIS.<br>
Anon, sir.—Pray, stay a little, my lord.
</p>

<p class="drama">
PRINCE.<br>
Nay, but hark you, Francis, for the sugar thou gavest me, ’twas a
pennyworth, was’t not?
</p>

<p class="drama">
FRANCIS.<br>
O Lord, I would it had been two!
</p>

<p class="drama">
PRINCE.<br>
I will give thee for it a thousand pound. Ask me when thou wilt, and thou shalt
have it.
</p>

<p class="drama">
POINS.<br>
[<i>within.</i>] Francis!
</p>

<p class="drama">
FRANCIS.<br>
Anon, anon.
</p>

<p class="drama">
PRINCE.<br>
Anon, Francis? No, Francis, but tomorrow, Francis; or, Francis, a Thursday; or
indeed, Francis, when thou wilt. But, Francis,—
</p>

<p class="drama">
FRANCIS.<br>
My lord?
</p>

<p class="drama">
PRINCE.<br>
Wilt thou rob this leathern-jerkin, crystal-button, not-pated, agate-ring,
puke-stocking, caddis-garter, smooth-tongue, Spanish-pouch—
</p>

<p class="drama">
FRANCIS.<br>
O Lord, sir, who do you mean?
</p>

<p class="drama">
PRINCE.<br>
Why, then, your brown bastard is your only drink, for look you, Francis, your
white canvas doublet will sully. In Barbary, sir, it cannot come to so
much.
</p>

<p class="drama">
FRANCIS.<br>
What, sir?
</p>

<p class="drama">
POINS.<br>
[<i>within.</i>] Francis!
</p>

<p class="drama">
PRINCE.<br>
Away, you rogue! Dost thou not hear them call?
</p>

<p class="right">[<i>Here they both call him; the Drawer stands amazed, not
knowing which way to go.</i>]
</p>

<p class="scenedesc">Enter <span class="charname">Vintner</span>.
</p>

<p class="drama">
VINTNER.<br>
What, stand’st thou still, and hear’st such a calling? Look to the
guests within.
</p>

<p class="right">[<i>Exit <span class="charname">Francis</span>.</i>]
</p>

<p class="drama">
My lord, old Sir John with half-a-dozen more are at the door. Shall I let
them in?
</p>

<p class="drama">
PRINCE.<br>
Let them alone awhile, and then open the door.
</p>

<p class="right">[<i>Exit <span class="charname">Vintner</span>.</i>]
</p>

<p class="drama">
Poins!
</p>

<p class="scenedesc">Enter <span class="charname">Poins</span>.
</p>

<p class="drama">
POINS.<br>
Anon, anon, sir.
</p>

<p class="drama">
PRINCE.<br>
Sirrah, Falstaff and the rest of the thieves are at the door; shall we be
merry?
</p>

<p class="drama">
POINS.<br>
As merry as crickets, my lad. But hark ye, what cunning match have you made
with this jest of the drawer? Come, what’s the issue?
</p>

<p class="drama">
PRINCE.<br>
I am now of all humours that have showed themselves humours since the old days
of goodman Adam to the pupil age of this present twelve o’clock at
midnight.
</p>

<p class="scenedesc">Enter <span class="charname">Francis</span>.
</p>

<p class="drama">
What’s o’clock, Francis?
</p>

<p class="drama">
FRANCIS.<br>
Anon, anon, sir.
</p>

<p class="right">[<i>Exit <span class="charname">Francis</span>.</i>]
</p>

<p class="drama">
PRINCE.<br>
That ever this fellow should have fewer words than a parrot, and yet the son of
a woman! His industry is upstairs and downstairs; his eloquence the parcel of a
reckoning. I am not yet of Percy’s mind, the Hotspur of the north, he
that kills me some six or seven dozen of Scots at a breakfast, washes his
hands, and says to his wife, “Fie upon this quiet life! I want
work.” “O my sweet Harry,” says she, “how many hast
thou killed today?” “Give my roan horse a drench,” says he;
and answers, “Some fourteen,” an hour after; “a trifle, a
trifle.” I prithee, call in Falstaff. I’ll play Percy, and that
damned brawn shall play Dame Mortimer his wife. <i>Rivo!</i> says the drunkard.
Call in Ribs, call in Tallow.
</p>

<p class="scenedesc">Enter <span class="charname">Falstaff, Gadshill,
Bardolph</span> and <span class="charname">Peto;</span> followed by
<span class="charname">Francis</span> with wine.
</p>

<p class="drama">
POINS.<br>
Welcome, Jack. Where hast thou been?
</p>

<p class="drama">
FALSTAFF.<br>
A plague of all cowards, I say, and a vengeance too! Marry, and amen! Give me a
cup of sack, boy. Ere I lead this life long, I’ll sew nether-stocks, and
mend them and foot them too. A plague of all cowards! Give me a cup of sack,
rogue. Is there no virtue extant?
</p>

<p class="right">[<i>Drinks.</i>]
</p>

<p class="drama">
PRINCE.<br>
Didst thou never see Titan kiss a dish of butter (pitiful-hearted Titan!), that
melted at the sweet tale of the sun’s? If thou didst, then behold that
compound.
</p>

<p class="drama">
FALSTAFF.<br>
You rogue, here’s lime in this sack too: there is nothing but roguery to
be found in villainous man, yet a coward is worse than a cup of sack with lime
in it. A villanous coward! Go thy ways, old Jack. Die when thou wilt, if
manhood, good manhood, be not forgot upon the face of the Earth, then am I a
shotten herring. There lives not three good men unhanged in England, and
one of them is fat, and grows old, God help the while, a bad world, I say. I
would I were a weaver; I could sing psalms or anything. A plague of all
cowards, I say still.
</p>

<p class="drama">
PRINCE.<br>
How now, wool-sack, what mutter you?
</p>

<p class="drama">
FALSTAFF.<br>
A king’s son! If I do not beat thee out of thy kingdom with a dagger of
lath, and drive all thy subjects afore thee like a flock of wild-geese,
I’ll never wear hair on my face more. You, Prince of Wales!
</p>

<p class="drama">
PRINCE.<br>
Why, you whoreson round man, what’s the matter?
</p>

<p class="drama">
FALSTAFF.<br>
Are not you a coward? Answer me to that—and Poins there?
</p>

<p class="drama">
POINS.<br>
Zounds, ye fat paunch, an ye call me coward, by the Lord, I’ll stab
thee.
</p>

<p class="drama">
FALSTAFF.<br>
I call thee coward? I’ll see thee damned ere I call thee coward,
but I would give a thousand pound I could run as fast as thou canst. You are
straight enough in the shoulders, you care not who sees your back. Call you
that backing of your friends? A plague upon such backing! Give me them that
will face me.—Give me a cup of sack. I am a rogue if I drunk today.
</p>

<p class="drama">
PRINCE.<br>
O villain! Thy lips are scarce wiped since thou drunk’st last.
</p>

<p class="drama">
FALSTAFF.<br>
All is one for that. A plague of all cowards, still say I.
</p>

<p class="right">[<i>Drinks.</i>]
</p>

<p class="drama">
PRINCE.<br>
What’s the matter?
</p>

<p class="drama">
FALSTAFF.<br>
What’s the matter? There be four of us here have ta’en a thousand
pound this day morning.
</p>

<p class="drama">
PRINCE.<br>
Where is it, Jack, where is it?
</p>

<p class="drama">
FALSTAFF.<br>
Where is it? Taken from us it is: a hundred upon poor four of us.
</p>

<p class="drama">
PRINCE.<br>
What, a hundred, man?
</p>

<p class="drama">
FALSTAFF.<br>
I am a rogue if I were not at half-sword with a dozen of them two hours
together. I have ’scaped by miracle. I am eight times thrust through the
doublet, four through the hose, my buckler cut through and through, my sword
hacked like a handsaw. <i>Ecce signum!</i> I never dealt better since I
was a man: all would not do. A plague of all cowards! Let them speak. If they
speak more or less than truth, they are villains, and the sons of darkness.
</p>

<p class="drama">
PRINCE.<br>
Speak, sirs, how was it?
</p>

<p class="drama">
GADSHILL.<br>
We four set upon some dozen.
</p>

<p class="drama">
FALSTAFF.<br>
Sixteen at least, my lord.
</p>

<p class="drama">
GADSHILL.<br>
And bound them.
</p>

<p class="drama">
PETO.<br>
No, no, they were not bound.
</p>

<p class="drama">
FALSTAFF.<br>
You rogue, they were bound, every man of them, or I am a Jew else, an Ebrew
Jew.
</p>

<p class="drama">
GADSHILL.<br>
As we were sharing, some six or seven fresh men set upon us.
</p>

<p class="drama">
FALSTAFF.<br>
And unbound the rest, and then come in the other.
</p>

<p class="drama">
PRINCE.<br>
What, fought you with them all?
</p>

<p class="drama">
FALSTAFF.<br>
All? I know not what you call all, but if I fought not with fifty of them I am
a bunch of radish. If there were not two or three and fifty upon poor old Jack,
then am I no two-legged creature.
</p>

<p class="drama">
PRINCE.<br>
Pray God you have not murdered some of them.
</p>

<p class="drama">
FALSTAFF.<br>
Nay, that’s past praying for. I have peppered two of them. Two I am
sure I have paid, two rogues in buckram suits. I tell thee what, Hal, if I tell
thee a lie, spit in my face, call me horse. Thou knowest my old ward. Here I
lay, and thus I bore my point. Four rogues in buckram let drive at me.
</p>

<p class="drama">
PRINCE.<br>
What, four? Thou saidst but two even now.
</p>

<p class="drama">
FALSTAFF.<br>
Four, Hal, I told thee four.
</p>

<p class="drama">
POINS.<br>
Ay, ay, he said four.
</p>

<p class="drama">
FALSTAFF.<br>
These four came all afront, and mainly thrust at me. I made me no more ado, but
took all their seven points in my target, thus.
</p>

<p class="drama">
PRINCE.<br>
Seven? Why, there were but four even now.
</p>

<p class="drama">
FALSTAFF.<br>
In buckram?
</p>

<p class="drama">
POINS.<br>
Ay, four, in buckram suits.
</p>

<p class="drama">
FALSTAFF.<br>
Seven, by these hilts, or I am a villain else.
</p>

<p class="drama">
PRINCE.<br>
[<i>aside to Poins.</i>] Prithee let him alone, we shall have more anon.
</p>

<p class="drama">
FALSTAFF.<br>
Dost thou hear me, Hal?
</p>

<p class="drama">
PRINCE.<br>
Ay, and mark thee too, Jack.
</p>

<p class="drama">
FALSTAFF.<br>
Do so, for it is worth the listening to. These nine in buckram that I told thee
of—
</p>

<p class="drama">
PRINCE.<br>
So, two more already.
</p>

<p class="drama">
FALSTAFF.<br>
Their points being broken—
</p>

<p class="drama">
POINS.<br>
Down fell their hose.
</p>

<p class="drama">
FALSTAFF.<br>
Began to give me ground; but I followed me close, came in foot and hand,
and with a thought seven of the eleven I paid.
</p>

<p class="drama">
PRINCE.<br>
O monstrous! Eleven buckram men grown out of two!
</p>

<p class="drama">
FALSTAFF.<br>
But as the devil would have it, three misbegotten knaves in Kendal green came
at my back and let drive at me, for it was so dark, Hal, that thou couldst not
see thy hand.
</p>

<p class="drama">
PRINCE.<br>
These lies are like the father that begets them, gross as a mountain, open,
palpable. Why, thou clay-brained guts, thou knotty-pated fool, thou whoreson,
obscene greasy tallow-catch—
</p>

<p class="drama">
FALSTAFF.<br>
What, art thou mad? Art thou mad? Is not the truth the truth?
</p>

<p class="drama">
PRINCE.<br>
Why, how couldst thou know these men in Kendal green, when it was so dark thou
couldst not see thy hand? Come, tell us your reason. What sayest thou to
this?
</p>

<p class="drama">
POINS.<br>
Come, your reason, Jack, your reason.
</p>

<p class="drama">
FALSTAFF.<br>
What, upon compulsion? Zounds, an I were at the strappado, or all the racks in the
world, I would not tell you on compulsion. Give you a reason on compulsion! If
reasons were as plentiful as blackberries, I would give no man a reason upon
compulsion, I.
</p>

<p class="drama">
PRINCE.<br>
I’ll be no longer guilty of this sin. This sanguine coward, this
bed-presser, this horse-back-breaker, this huge hill of flesh—
</p>

<p class="drama">
FALSTAFF.<br>
’Sblood, you starveling, you eel-skin, you dried neat’s-tongue, you
bull’s pizzle, you stock-fish—O, for breath to utter what is like
thee! You tailor’s-yard, you sheath, you bow-case, you vile standing
tuck—
</p>

<p class="drama">
PRINCE.<br>
Well, breathe awhile, and then to it again, and when thou hast tired thyself
in base comparisons, hear me speak but this.
</p>

<p class="drama">
POINS.<br>
Mark, Jack.
</p>

<p class="drama">
PRINCE.<br>
We two saw you four set on four, and bound them and were masters of their
wealth. Mark now how a plain tale shall put you down. Then did we two set on
you four, and, with a word, outfaced you from your prize, and have it, yea, and
can show it you here in the house. And, Falstaff, you carried your guts away as
nimbly, with as quick dexterity, and roared for mercy, and still ran and
roared, as ever I heard bull-calf. What a slave art thou to hack thy
sword as thou hast done, and then say it was in fight! What trick, what device,
what starting-hole canst thou now find out to hide thee from this open and
apparent shame?
</p>

<p class="drama">
POINS.<br>
Come, let’s hear, Jack, what trick hast thou now?
</p>

<p class="drama">
FALSTAFF.<br>
By the Lord, I knew ye as well as he that made ye. Why, hear you, my masters,
was it for me to kill the heir-apparent? Should I turn upon the true prince?
Why, thou knowest I am as valiant as Hercules: but beware instinct. The lion
will not touch the true prince. Instinct is a great matter. I was now a coward
on instinct. I shall think the better of myself, and thee, during my
life—I for a valiant lion, and thou for a true prince. But, by the Lord,
lads, I am glad you have the money.—Hostess, clap to the doors. Watch
tonight, pray tomorrow. Gallants, lads, boys, hearts of gold, all the titles of
good fellowship come to you! What, shall we be merry? Shall we have a play
extempore?
</p>

<p class="drama">
PRINCE.<br>
Content; and the argument shall be thy running away.
</p>

<p class="drama">
FALSTAFF.<br>
Ah, no more of that, Hal, an thou lovest me!
</p>

<p class="scenedesc">Enter the <span class="charname">Hostess</span>.
</p>

<p class="drama">
HOSTESS.<br>
O Jesu, my lord the Prince—
</p>

<p class="drama">
PRINCE.<br>
How now, my lady the hostess! What say’st thou to me?
</p>

<p class="drama">
HOSTESS.<br>
Marry, my lord, there is a nobleman of the court at door would speak with you:
he says he comes from your father.
</p>

<p class="drama">
PRINCE.<br>
Give him as much as will make him a royal man, and send him back again to my
mother.
</p>

<p class="drama">
FALSTAFF.<br>
What manner of man is he?
</p>

<p class="drama">
HOSTESS.<br>
An old man.
</p>

<p class="drama">
FALSTAFF.<br>
What doth gravity out of his bed at midnight? Shall I give him his answer?
</p>

<p class="drama">
PRINCE.<br>
Prithee do, Jack.
</p>

<p class="drama">
FALSTAFF.<br>
Faith, and I’ll send him packing.
</p>

<p class="right">[<i>Exit.</i>]
</p>

<p class="drama">
PRINCE.<br>
Now, sirs: by’r Lady, you fought fair, so did you, Peto. So did
you, Bardolph. You are lions, too, you ran away upon instinct, you will
not touch the true prince, no, fie!
</p>

<p class="drama">
BARDOLPH.<br>
Faith, I ran when I saw others run.
</p>

<p class="drama">
PRINCE.<br>
Faith, tell me now in earnest, how came Falstaff’s sword so hacked?
</p>

<p class="drama">
PETO.<br>
Why, he hacked it with his dagger, and said he would swear truth out of
England but he would make you believe it was done in fight, and
persuaded us to do the like.
</p>

<p class="drama">
BARDOLPH.<br>
Yea, and to tickle our noses with spear-grass to make them bleed, and then to
beslubber our garments with it, and swear it was the blood of true men. I did
that I did not this seven year before: I blushed to hear his monstrous
devices.
</p>

<p class="drama">
PRINCE.<br>
O villain, thou stolest a cup of sack eighteen years ago, and wert taken with
the manner, and ever since thou hast blushed extempore. Thou hadst fire
and sword on thy side, and yet thou ran’st away. What instinct hadst
thou for it?
</p>

<p class="drama">
BARDOLPH.<br>
My lord, do you see these meteors? Do you behold these exhalations?
</p>

<p class="drama">
PRINCE.<br>
I do.
</p>

<p class="drama">
BARDOLPH.<br>
What think you they portend?
</p>

<p class="drama">
PRINCE.<br>
Hot livers and cold purses.
</p>

<p class="drama">
BARDOLPH.<br>
Choler, my lord, if rightly taken.
</p>

<p class="drama">
PRINCE.<br>
No, if rightly taken, halter.
</p>

<p class="scenedesc">Enter <span class="charname">Falstaff</span>.
</p>

<p class="drama">
Here comes lean Jack, here comes bare-bone. How now, my sweet creature of
bombast? How long is’t ago, Jack, since thou sawest thine own knee?
</p>

<p class="drama">
FALSTAFF.<br>
My own knee? When I was about thy years, Hal, I was not an eagle’s talon
in the waist. I could have crept into any alderman’s thumb-ring: a plague
of sighing and grief! It blows a man up like a bladder. There’s villanous
news abroad: here was Sir John Bracy from your father; you must to the court in
the morning. That same mad fellow of the north, Percy, and he of Wales that
gave Amamon the bastinado, and made Lucifer cuckold, and swore the devil his
true liegeman upon the cross of a Welsh hook—what a plague call you him?
</p>

<p class="drama">
POINS.<br>
O, Glendower.
</p>

<p class="drama">
FALSTAFF.<br>
Owen, Owen, the same; and his son-in-law Mortimer, and old Northumberland, and
that sprightly Scot of Scots, Douglas, that runs a-horseback up a hill
perpendicular—
</p>

<p class="drama">
PRINCE.<br>
He that rides at high speed, and with his pistol kills a sparrow flying.
</p>

<p class="drama">
FALSTAFF.<br>
You have hit it.
</p>

<p class="drama">
PRINCE.<br>
So did he never the sparrow.
</p>

<p class="drama">
FALSTAFF.<br>
Well, that rascal hath good metal in him, he will not run.
</p>

<p class="drama">
PRINCE.<br>
Why, what a rascal art thou then, to praise him so for running!
</p>

<p class="drama">
FALSTAFF.<br>
A-horseback, ye cuckoo, but afoot he will not budge a foot.
</p>

<p class="drama">
PRINCE.<br>
Yes, Jack, upon instinct.
</p>

<p class="drama">
FALSTAFF.<br>
I grant ye, upon instinct. Well, he is there too, and one Mordake, and a
thousand blue-caps more. Worcester is stolen away tonight; thy father’s
beard is turned white with the news. You may buy land now as cheap as
stinking mackerel.
</p>

<p class="drama">
PRINCE.<br>
Why then, it is like if there come a hot June, and this civil buffeting hold,
we shall buy maidenheads as they buy hobnails, by the hundreds.
</p>

<p class="drama">
FALSTAFF.<br>
By the mass, lad, thou sayest true. It is like we shall have good trading that
way. But tell me, Hal, art not thou horrible afeard? Thou being heir-apparent,
could the world pick thee out three such enemies again as that fiend Douglas,
that spirit Percy, and that devil Glendower? Art thou not horribly afraid? Doth
not thy blood thrill at it?
</p>

<p class="drama">
PRINCE.<br>
Not a whit, i’faith. I lack some of thy instinct.
</p>

<p class="drama">
FALSTAFF.<br>
Well, thou wilt be horribly chid tomorrow when thou comest to thy father. If
thou love me practise an answer.
</p>

<p class="drama">
PRINCE.<br>
Do thou stand for my father and examine me upon the particulars of my life.
</p>

<p class="drama">
FALSTAFF.<br>
Shall I? Content! This chair shall be my state, this dagger my sceptre, and
this cushion my crown.
</p>

<p class="drama">
PRINCE.<br>
Thy state is taken for a joint-stool, thy golden sceptre for a leaden dagger,
and thy precious rich crown for a pitiful bald crown.
</p>

<p class="drama">
FALSTAFF.<br>
Well, an the fire of grace be not quite out of thee, now shalt thou be
moved. Give me a cup of sack to make my eyes look red, that it may be
thought I have wept, for I must speak in passion, and I will do it in King
Cambyses’ vein.
</p>

<p class="drama">
PRINCE.<br>
Well, here is my leg.
</p>

<p class="drama">
FALSTAFF.<br>
And here is my speech. Stand aside, nobility.
</p>

<p class="drama">
HOSTESS.<br>
O Jesu, this is excellent sport, i faith!
</p>

<p class="drama">
FALSTAFF.<br>
Weep not, sweet Queen, for trickling tears are vain.
</p>

<p class="drama">
HOSTESS.<br>
O, the Father, how he holds his countenance!
</p>

<p class="drama">
FALSTAFF.<br>
For God’s sake, lords, convey my tristful Queen,<br>
For tears do stop the floodgates of her eyes.
</p>

<p class="drama">
HOSTESS.<br>
O Jesu, he doth it as like one of these harlotry players as ever I see!
</p>

<p class="drama">
FALSTAFF.<br>
Peace, good pint-pot; peace, good tickle-brain.—Harry, I do not only
marvel where thou spendest thy time, but also how thou art accompanied. For
though the camomile, the more it is trodden on, the faster it grows, yet youth,
the more it is wasted, the sooner it wears. That thou art my son I have partly
thy mother’s word, partly my own opinion, but chiefly a villainous trick
of thine eye, and a foolish hanging of thy nether lip, that doth warrant me.
If then thou be son to me, here lies the point: why, being son to me, art
thou so pointed at? Shall the blessed sun of heaven prove a micher, and eat
blackberries? A question not to be asked. Shall the son of England prove
a thief, and take purses? A question to be asked. There is a thing,
Harry, which thou hast often heard of, and it is known to many in our land by
the name of pitch. This pitch, as ancient writers do report, doth defile; so
doth the company thou keepest. For, Harry, now I do not speak to thee in drink,
but in tears; not in pleasure, but in passion; not in words only, but in woes
also. And yet there is a virtuous man whom I have often noted in thy company,
but I know not his name.
</p>

<p class="drama">
PRINCE.<br>
What manner of man, an it like your Majesty?
</p>

<p class="drama">
FALSTAFF.<br>
A goodly portly man, i’faith, and a corpulent; of a cheerful look, a
pleasing eye, and a most noble carriage; and, as I think, his age some fifty,
or, by’r Lady, inclining to threescore; and now I remember me, his name
is Falstaff. If that man should be lewdly given, he deceiveth me; for, Harry, I
see virtue in his looks. If then the tree may be known by the fruit, as the
fruit by the tree, then peremptorily I speak it, there is virtue in that
Falstaff; him keep with, the rest banish. And tell me now, thou naughty varlet,
tell me where hast thou been this month?
</p>

<p class="drama">
PRINCE.<br>
Dost thou speak like a king? Do thou stand for me, and I’ll play my
father.
</p>

<p class="drama">
FALSTAFF.<br>
Depose me? If thou dost it half so gravely, so majestically, both in word and
matter, hang me up by the heels for a rabbit-sucker or a poulter’s
hare.
</p>

<p class="drama">
PRINCE.<br>
Well, here I am set.
</p>

<p class="drama">
FALSTAFF.<br>
And here I stand. Judge, my masters.
</p>

<p class="drama">
PRINCE.<br>
Now, Harry, whence come you?
</p>

<p class="drama">
FALSTAFF.<br>
My noble lord, from Eastcheap.
</p>

<p class="drama">
PRINCE.<br>
The complaints I hear of thee are grievous.
</p>

<p class="drama">
FALSTAFF.<br>
’Sblood, my lord, they are false.—Nay, I’ll tickle ye for a
young prince, i’faith.
</p>

<p class="drama">
PRINCE.<br>
Swearest thou, ungracious boy? Henceforth ne’er look on me. Thou art
violently carried away from grace. There is a devil haunts thee in the likeness
of an old fat man. A tun of man is thy companion. Why dost thou converse with
that trunk of humours, that bolting-hutch of beastliness, that swollen parcel
of dropsies, that huge bombard of sack, that stuffed cloak-bag of guts, that
roasted Manningtree ox with the pudding in his belly, that reverend Vice, that
grey iniquity, that father ruffian, that vanity in years? Wherein is he good,
but to taste sack and drink it? Wherein neat and cleanly, but to carve a capon
and eat it? Wherein cunning, but in craft? Wherein crafty, but in villany?
Wherein villainous, but in all things? Wherein worthy, but in nothing?
</p>

<p class="drama">
FALSTAFF.<br>
I would your Grace would take me with you. Whom means your Grace?
</p>

<p class="drama">
PRINCE.<br>
That villainous abominable misleader of youth, Falstaff, that old white-bearded
Satan.
</p>

<p class="drama">
FALSTAFF.<br>
My lord, the man I know.
</p>

<p class="drama">
PRINCE.<br>
I know thou dost.
</p>

<p class="drama">
FALSTAFF.<br>
But to say I know more harm in him than in myself were to say more than I know.
That he is old, the more the pity, his white hairs do witness it. But that he
is, saving your reverence, a whoremaster, that I utterly deny. If sack and
sugar be a fault, God help the wicked! If to be old and merry be a sin, then
many an old host that I know is damned. If to be fat be to be hated, then
Pharaoh’s lean kine are to be loved. No, my good lord, banish Peto,
banish Bardolph, banish Poins, but for sweet Jack Falstaff, kind Jack Falstaff,
true Jack Falstaff, valiant Jack Falstaff, and therefore more valiant, being as
he is old Jack Falstaff, banish not him thy Harry’s company, banish not
him thy Harry’s company. Banish plump Jack, and banish all the world.
</p>

<p class="drama">
PRINCE.<br>
I do, I will.
</p>

<p class="right">[<i>A knocking heard.</i>]
</p>

<p class="right">[<i>Exeunt <span class="charname">Hostess, Francis</span> and
<span class="charname">Bardolph</span>.</i>]
</p>

<p class="scenedesc">Enter <span class="charname">Bardolph,</span> running.
</p>

<p class="drama">
BARDOLPH.<br>
O, my lord, my lord, the sheriff with a most monstrous watch is at the
door.
</p>

<p class="drama">
FALSTAFF.<br>
Out, ye rogue! Play out the play. I have much to say in the behalf of
that Falstaff.
</p>

<p class="scenedesc">Enter the <span class="charname">Hostess,</span> hastily.
</p>

<p class="drama">
HOSTESS.<br>
O Jesu, my lord, my lord—
</p>

<p class="drama">
PRINCE.<br>
Heigh, heigh, the devil rides upon a fiddlestick. What’s the matter?
</p>

<p class="drama">
HOSTESS.<br>
The sheriff and all the watch are at the door. They are come to search the
house. Shall I let them in?
</p>

<p class="drama">
FALSTAFF.<br>
Dost thou hear, Hal? Never call a true piece of gold a counterfeit: thou art
essentially made without seeming so.
</p>

<p class="drama">
PRINCE.<br>
And thou a natural coward without instinct.
</p>

<p class="drama">
FALSTAFF.<br>
I deny your major. If you will deny the sheriff, so; if not, let him enter. If
I become not a cart as well as another man, a plague on my bringing up! I hope
I shall as soon be strangled with a halter as another.
</p>

<p class="drama">
PRINCE.<br>
Go hide thee behind the arras. The rest walk up above. Now, my masters,
for a true face and good conscience.
</p>

<p class="drama">
FALSTAFF.<br>
Both which I have had, but their date is out, and therefore I’ll hide
me.
</p>

<p class="drama">
PRINCE.<br>
Call in the sheriff.
</p>

<p class="right">[<i>Exeunt all but the <span class="charname">Prince</span> and
<span class="charname">Peto</span>.</i>]
</p>

<p class="scenedesc">Enter <span class="charname">Sheriff</span> and the
<span class="charname">Carrier</span>.
</p>

<p class="drama">
Now, master sheriff, what is your will with me?
</p>

<p class="drama">
SHERIFF.<br>
First, pardon me, my lord. A hue and cry<br>
Hath followed certain men unto this house.
</p>

<p class="drama">
PRINCE.<br>
What men?
</p>

<p class="drama">
SHERIFF.<br>
One of them is well known, my gracious lord,<br>
A gross fat man.
</p>

<p class="drama">
CARRIER.<br>
As fat as butter.
</p>

<p class="drama">
PRINCE.<br>
The man I do assure you is not here,<br>
For I myself at this time have employ’d him.<br>
And, sheriff, I will engage my word to thee,<br>
That I will by tomorrow dinner-time,<br>
Send him to answer thee, or any man,<br>
For anything he shall be charged withal.<br>
And so let me entreat you leave the house.
</p>

<p class="drama">
SHERIFF.<br>
I will, my lord. There are two gentlemen<br>
Have in this robbery lost three hundred marks.
</p>

<p class="drama">
PRINCE.<br>
It may be so. If he have robb’d these men,<br>
He shall be answerable; and so, farewell.
</p>

<p class="drama">
SHERIFF.<br>
Good night, my noble lord.
</p>

<p class="drama">
PRINCE.<br>
I think it is good morrow, is it not?
</p>

<p class="drama">
SHERIFF.<br>
Indeed, my lord, I think it be two o’clock.
</p>

<p class="right">[<i>Exit <span class="charname">Sheriff</span> with the <span class="charname">Carrier</span>.</i>]
</p>

<p class="drama">
PRINCE.<br>
This oily rascal is known as well as Paul’s. Go, call him forth.
</p>

<p class="drama">
PETO.<br>
Falstaff!—Fast asleep behind the arras, and snorting like a horse.
</p>

<p class="drama">
PRINCE.<br>
Hark, how hard he fetches breath. Search his pockets.
</p>

<p class="right">[<i>He searcheth his pocket, and findeth certain papers.</i>]
</p>

<p class="drama">
What hast thou found?
</p>

<p class="drama">
PETO.<br>
Nothing but papers, my lord.
</p>

<p class="drama">
PRINCE.<br>
Let’s see what they be. Read them.
</p>

<p class="drama">
PETO.<br>
[<i>reads</i>]<br>
Item, a capon, . . . . . . . . . . . 2s. 2d.<br>
Item, sauce, . . . . . . . . . . . . . . . 4d.<br>
Item, sack, two gallons, . . . 5s. 8d.<br>
Item, anchovies and sack after supper, 2s. 6d.<br>
Item, bread, . . . . . . . . . . . . . . . ob.
</p>

<p class="drama">
PRINCE.<br>
O monstrous! But one halfpennyworth of bread to this intolerable deal of sack!
What there is else, keep close. We’ll read it at more advantage. There
let him sleep till day. I’ll to the court in the morning. We must all to
the wars, and thy place shall be honourable. I’ll procure this fat rogue
a charge of foot, and I know his death will be a march of twelve score. The
money shall be paid back again with advantage. Be with me betimes in the
morning; and so, good morrow, Peto.
</p>

<p class="drama">
PETO.<br>
Good morrow, good my lord.
</p>

<p class="right">[<i>Exeunt.</i>]
</p>

