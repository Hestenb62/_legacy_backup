<h2> <b>ACT II</b></h2>

<h3> <a id="sceneII_9.1"></a><b>SCENE I. Rochester. An Inn-Yard.</b></h3>

<p class="scenedesc">Enter a <span class="charname">Carrier</span> with a lantern in his hand.
</p>

<p class="drama">
FIRST CARRIER.<br>
Heigh-ho! an it be not four by the day, I’ll be hang’d.
Charles’ wain is over the new chimney, and yet our horse not
pack’d.—What, ostler!
</p>

<p class="drama">
OSTLER.<br>
[<i>within.</i>] Anon, anon.
</p>

<p class="drama">
FIRST CARRIER.<br>
I prithee, Tom, beat Cut’s saddle, put a few flocks in the point;
poor jade is wrung in the withers out of all cess.
</p>

<p class="scenedesc">Enter another <span class="charname">Carrier</span>.
</p>

<p class="drama">
SECOND CARRIER.<br>
Peas and beans are as dank here as a dog, and that is the next way to give poor
jades the bots. This house is turned upside down since Robin ostler died.
</p>

<p class="drama">
FIRST CARRIER.<br>
Poor fellow never joyed since the price of oats rose, it was the death of him.
</p>

<p class="drama">
SECOND CARRIER.<br>
I think this be the most villainous house in all London road for fleas. I am
stung like a tench.
</p>

<p class="drama">
FIRST CARRIER.<br>
Like a tench! By the Mass, there is ne’er a king christen could be
better bit than I have been since the first cock.
</p>

<p class="drama">
SECOND CARRIER.<br>
Why, they will allow us ne’er a jordan, and then we leak in your chimney,
and your chamber-lye breeds fleas like a loach.
</p>

<p class="drama">
FIRST CARRIER.<br>
What, ostler! Come away and be hanged, come away.
</p>

<p class="drama">
SECOND CARRIER.<br>
I have a gammon of bacon and two razes of ginger, to be delivered as far as
Charing Cross.
</p>

<p class="drama">
FIRST CARRIER.<br>
God’s body! The turkeys in my pannier are quite starved.—What,
ostler! A plague on thee! Hast thou never an eye in thy head? Canst not hear?
An ’twere not as good deed as drink to break the pate on thee, I am a
very villain. Come, and be hanged. Hast no faith in thee?
</p>

<p class="scenedesc">Enter <span class="charname">Gadshill</span>.
</p>

<p class="drama">
GADSHILL.<br>
Good morrow, carriers. What’s o’clock?
</p>

<p class="drama">
FIRST CARRIER.<br>
I think it be two o’clock.
</p>

<p class="drama">
GADSHILL.<br>
I prithee, lend me thy lantern, to see my gelding in the stable.
</p>

<p class="drama">
FIRST CARRIER.<br>
Nay, by God, soft! I know a trick worth two of that, i’faith.
</p>

<p class="drama">
GADSHILL.<br>
I pray thee, lend me thine.
</p>

<p class="drama">
SECOND CARRIER.<br>
Ay, when? Canst tell? “Lend me thy lantern,” quoth he! Marry,
I’ll see thee hanged first.
</p>

<p class="drama">
GADSHILL.<br>
Sirrah carrier, what time do you mean to come to London?
</p>

<p class="drama">
SECOND CARRIER.<br>
Time enough to go to bed with a candle, I warrant thee. Come, neighbour
Mugs, we’ll call up the gentlemen. They will along with company, for
they have great charge.
</p>

<p class="right">[<i>Exeunt <span class="charname">Carriers</span>.</i>]
</p>

<p class="drama">
GADSHILL.<br>
What, ho! Chamberlain!
</p>

<p class="scenedesc">Enter <span class="charname">Chamberlain</span>.
</p>

<p class="drama">
CHAMBERLAIN.<br>
At hand, quoth pick-purse.
</p>

<p class="drama">
GADSHILL.<br>
That’s even as fair as “at hand, quoth the chamberlain,” for thou
variest no more from picking of purses than giving direction doth from
labouring; thou layest the plot how.
</p>

<p class="drama">
CHAMBERLAIN.<br>
Good morrow, Master Gadshill. It holds current that I told you yesternight:
there’s a franklin in the Wild of Kent hath brought three hundred marks
with him in gold. I heard him tell it to one of his company last night at
supper; a kind of auditor, one that hath abundance of charge too, God knows
what. They are up already, and call for eggs and butter. They will away
presently.
</p>

<p class="drama">
GADSHILL.<br>
Sirrah, if they meet not with Saint Nicholas’ clerks, I’ll give
thee this neck.
</p>

<p class="drama">
CHAMBERLAIN.<br>
No, I’ll none of it. I pray thee, keep that for the hangman, for I
know thou worshippest Saint Nicholas as truly as a man of falsehood may.
</p>

<p class="drama">
GADSHILL.<br>
What talkest thou to me of the hangman? If I hang, I’ll make a fat pair
of gallows; for, if I hang, old Sir John hangs with me, and thou knowest
he is no starveling. Tut, there are other Troyans that thou dream’st not of,
the which for sport sake are content to do the profession some grace, that
would, if matters should be looked into, for their own credit sake make
all whole. I am joined with no foot-land-rakers, no long-staff sixpenny
strikers, none of these mad mustachio purple-hued malt-worms, but with nobility
and tranquillity, burgomasters and great oneyers, such as can hold in, such as
will strike sooner than speak, and speak sooner than drink, and drink sooner
than pray: and yet, zounds, I lie, for they pray continually to their saint
the commonwealth, or rather not pray to her, but prey on her, for they ride
up and down on her, and make her their boots.
</p>

<p class="drama">
CHAMBERLAIN.<br>
What, the commonwealth their boots? Will she hold out water in foul way?
</p>

<p class="drama">
GADSHILL.<br>
She will, she will; justice hath liquored her. We steal as in a castle,
cock-sure; we have the receipt of fern-seed, we walk invisible.
</p>

<p class="drama">
CHAMBERLAIN.<br>
Nay, by my faith, I think you are more beholding to the night than to fern-seed
for your walking invisible.
</p>

<p class="drama">
GADSHILL.<br>
Give me thy hand. Thou shalt have a share in our purchase, as I am a true man.
</p>

<p class="drama">
CHAMBERLAIN.<br>
Nay, rather let me have it, as you are a false thief.
</p>

<p class="drama">
GADSHILL.<br>
Go to; <i>homo</i> is a common name to all men. Bid the ostler bring my gelding
out of the stable. Farewell, you muddy knave.
</p>

<p class="right">[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneII_9.2"></a><b>SCENE II. The Road by Gads-hill.</b></h3>

<p class="scenedesc">Enter <span class="charname">Prince Henry</span> and
<span class="charname">Poins; Bardolph</span> and
<span class="charname">Peto</span> at some distance.
</p>

<p class="drama">
POINS.<br>
Come, shelter, shelter! I have removed Falstaff’s horse, and he
frets like a gummed velvet.
</p>

<p class="drama">
PRINCE.<br>
Stand close.
</p>

<p class="right">[<i>They retire.</i>]
</p>

<p class="scenedesc">Enter <span class="charname">Falstaff</span>.
</p>

<p class="drama">
FALSTAFF.<br>
Poins! Poins, and be hanged! Poins!
</p>

<p class="drama">
PRINCE.<br>
[<i>Coming forward.</i>]<br>
Peace, ye fat-kidneyed rascal! What a brawling dost thou keep!
</p>

<p class="drama">
FALSTAFF.<br>
Where’s Poins, Hal?
</p>

<p class="drama">
PRINCE.<br>
He is walked up to the top of the hill. I’ll go seek him.
</p>

<p class="right">[<i>Retires.</i>]
</p>

<p class="drama">
FALSTAFF.<br>
I am accursed to rob in that thief’s company. The rascal hath removed my
horse and tied him I know not where. If I travel but four foot by the square
further afoot, I shall break my wind. Well, I doubt not but to die a fair death
for all this, if I ’scape hanging for killing that rogue. I have forsworn
his company hourly any time this two-and-twenty years, and yet I am bewitched
with the rogue’s company. If the rascal have not given me medicines to
make me love him, I’ll be hanged. It could not be else: I have drunk
medicines. Poins! Hal! A plague upon you both! Bardolph! Peto! I’ll
starve ere I’ll rob a foot further. An ’twere not as good a deed as
drink, to turn true man, and to leave these rogues, I am the veriest varlet
that ever chewed with a tooth. Eight yards of uneven ground is threescore and
ten miles afoot with me, and the stony-hearted villains know it well enough. A
plague upon it when thieves cannot be true one to another! [<i>They
whistle.</i>] Whew! A plague upon you all! Give me my horse, you rogues, give
me my horse and be hanged!
</p>

<p class="drama">
PRINCE.<br>
[<i>Coming forward.</i>] Peace, you fat guts, lie down, lay thine ear close to
the ground, and list if thou canst hear the tread of travellers.
</p>

<p class="drama">
FALSTAFF.<br>
Have you any levers to lift me up again, being down? ’Sblood, I’ll
not bear my own flesh so far afoot again for all the coin in thy
father’s exchequer. What a plague mean ye to colt me thus?
</p>

<p class="drama">
PRINCE.<br>
Thou liest, thou art not colted, thou art uncolted.
</p>

<p class="drama">
FALSTAFF.<br>
I prithee, good Prince Hal, help me to my horse, good king’s son.
</p>

<p class="drama">
PRINCE.<br>
Out, ye rogue! Shall I be your ostler?
</p>

<p class="drama">
FALSTAFF.<br>
Hang thyself in thine own heir-apparent garters! If I be ta’en,
I’ll peach for this. An I have not ballads made on you all, and sung to
filthy tunes, let a cup of sack be my poison—when a jest is so forward, and
afoot too! I hate it.
</p>

<p class="scenedesc">Enter <span class="charname">Gadshill</span>.
</p>

<p class="drama">
GADSHILL.<br>
Stand!
</p>

<p class="drama">
FALSTAFF.<br>
So I do, against my will.
</p>

<p class="drama">
POINS.<br>
O, ’tis our setter. I know his voice.
</p>

<p class="scenedesc">Comes forward with <span class="charname">Bardolph</span> and
<span class="charname">Peto</span>.
</p>

<p class="drama">
BARDOLPH.<br>
What news?
</p>

<p class="drama">
GADSHILL.<br>
Case ye, case ye, on with your visards. There’s money of the King’s
coming down the hill, ’tis going to the King’s exchequer.
</p>

<p class="drama">
FALSTAFF.<br>
You lie, ye rogue, ’tis going to the King’s tavern.
</p>

<p class="drama">
GADSHILL.<br>
There’s enough to make us all.
</p>

<p class="drama">
FALSTAFF.<br>
To be hanged.
</p>

<p class="drama">
PRINCE.<br>
Sirs, you four shall front them in the narrow lane. Ned Poins and I will walk
lower; if they ’scape from your encounter, then they light on us.
</p>

<p class="drama">
PETO.<br>
How many be there of them?
</p>

<p class="drama">
GADSHILL.<br>
Some eight or ten.
</p>

<p class="drama">
FALSTAFF.<br>
Zounds, will they not rob us?
</p>

<p class="drama">
PRINCE.<br>
What, a coward, Sir John Paunch?
</p>

<p class="drama">
FALSTAFF.<br>
Indeed, I am not John of Gaunt, your grandfather, but yet no coward, Hal.
</p>

<p class="drama">
PRINCE.<br>
Well, we leave that to the proof.
</p>

<p class="drama">
POINS.<br>
Sirrah Jack, thy horse stands behind the hedge. When thou need’st him,
there thou shalt find him. Farewell, and stand fast.
</p>

<p class="drama">
FALSTAFF.<br>
Now cannot I strike him, if I should be hanged.
</p>

<p class="drama">
PRINCE.<br>
[<i>aside to Poins.</i>] Ned, where are our disguises?
</p>

<p class="drama">
POINS.<br>
[<i>aside to Prince Henry.</i>] Here, hard by. Stand close.
</p>

<p class="right">[<i>Exeunt <span class="charname">Prince</span> and
<span class="charname">Poins</span>.</i>]
</p>

<p class="drama">
FALSTAFF.<br>
Now, my masters, happy man be his dole, say I. Every man to his business.
</p>

<p class="scenedesc">Enter the <span class="charname">Travellers</span>.
</p>

<p class="drama">
FIRST TRAVELLER.<br>
Come, neighbour, the boy shall lead our horses down the hill; we’ll walk
afoot awhile and ease our legs.
</p>

<p class="drama">
THIEVES.<br>
Stand!
</p>

<p class="drama">
SECOND TRAVELLER.<br>
Jesu bless us!
</p>

<p class="drama">
FALSTAFF.<br>
Strike, down with them, cut the villains’ throats! Ah, whoreson
caterpillars, bacon-fed knaves, they hate us youth. Down with them, fleece
them!
</p>

<p class="drama">
FIRST TRAVELLER.<br>
O, we are undone, both we and ours for ever!
</p>

<p class="drama">
FALSTAFF.<br>
Hang ye, gorbellied knaves, are ye undone? No, ye fat chuffs, I would your
store were here! On, bacons, on! What, ye knaves! young men must live. You are
grandjurors, are ye? We’ll jure ye, faith.
</p>

<p class="right">[<i>Here they rob them and bind them. Exeunt</i>]
</p>

<p class="scenedesc">Enter <span class="charname">Prince Henry</span> and
<span class="charname">Poins</span> in buckram suits.
</p>

<p class="drama">
PRINCE.<br>
The thieves have bound the true men. Now could thou and I rob the thieves, and
go merrily to London, it would be argument for a week, laughter for a month,
and a good jest for ever.
</p>

<p class="drama">
POINS.<br>
Stand close, I hear them coming.
</p>

<p class="right">[<i>They retire.</i>]
</p>

<p class="scenedesc">Enter the <span class="charname">Thieves</span> again.
</p>

<p class="drama">
FALSTAFF.<br>
Come, my masters, let us share, and then to horse before day. An the Prince and
Poins be not two arrant cowards, there’s no equity stirring.
There’s no more valour in that Poins than in a wild duck.
</p>

<p class="right">[<i>As they are sharing, the Prince and Poins set upon them.</i>]
</p>

<p class="drama">
PRINCE.<br>
Your money!
</p>

<p class="drama">
POINS.<br>
Villains!
</p>

<p class="right">[<i><span class="charname">Falstaff</span> after a blow or
two, and the others run away, leaving the booty behind them.</i>]
</p>

<p class="drama">
PRINCE.<br>
Got with much ease. Now merrily to horse.<br>
The thieves are all scatter’d, and possess’d with fear<br>
So strongly that they dare not meet each other;<br>
Each takes his fellow for an officer.<br>
Away, good Ned. Falstaff sweats to death,<br>
And lards the lean earth as he walks along.<br>
Were’t not for laughing, I should pity him.
</p>

<p class="drama">
POINS.<br>
How the fat rogue roared!
</p>

<p class="right">[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneII_9.3"></a><b>SCENE III. Warkworth. A Room in the Castle.</b></h3>

<p class="scenedesc">Enter <span class="charname">Hotspur,</span> reading a letter.
</p>

<p class="drama">
HOTSPUR.<br>
“But, for mine own part, my lord, I could be well contented to be there,
in respect of the love I bear your house.” He could be contented; why is
he not, then? In respect of the love he bears our house—he shows in
this, he loves his own barn better than he loves our house. Let me see some
more. “The purpose you undertake is dangerous”—Why, that’s certain.
’Tis dangerous to take a cold, to sleep, to drink; but I tell you, my
lord fool, out of this nettle, danger, we pluck this flower, safety. “The
purpose you undertake is dangerous, the friends you have named uncertain, the
time itself unsorted, and your whole plot too light for the counterpoise of so
great an opposition.” Say you so, say you so? I say unto you again, you
are a shallow, cowardly hind, and you lie. What a lack-brain is this! By the
Lord, our plot is a good plot as ever was laid, our friends true and constant:
a good plot, good friends, and full of expectation; an excellent plot, very
good friends. What a frosty-spirited rogue is this! Why, my Lord of York
commends the plot and the general course of the action. Zounds, an I were now
by this rascal, I could brain him with his lady’s fan. Is there not my
father, my uncle, and myself? Lord Edmund Mortimer, my Lord of York, and Owen
Glendower? Is there not besides the Douglas? Have I not all their letters to
meet me in arms by the ninth of the next month, and are they not some of them
set forward already? What a pagan rascal is this, an infidel! Ha! You shall see
now, in very sincerity of fear and cold heart, will he to the King, and lay
open all our proceedings. O, I could divide myself, and go to buffets, for
moving such a dish of skim milk with so honourable an action! Hang
him, let him tell the King, we are prepared. I will set forward
tonight.—
</p>

<p class="scenedesc">Enter <span class="charname">Lady Percy</span>.
</p>

<p class="drama">
How now, Kate! I must leave you within these two hours.
</p>

<p class="drama">
LADY PERCY.<br>
O my good lord, why are you thus alone?<br>
For what offence have I this fortnight been<br>
A banish’d woman from my Harry’s bed?<br>
Tell me, sweet lord, what is’t that takes from thee<br>
Thy stomach, pleasure, and thy golden sleep?<br>
Why dost thou bend thine eyes upon the earth,<br>
And start so often when thou sit’st alone?<br>
Why hast thou lost the fresh blood in thy cheeks,<br>
And given my treasures and my rights of thee<br>
To thick-eyed musing and curst melancholy?<br>
In thy faint slumbers I by thee have watch’d,<br>
And heard thee murmur tales of iron wars,<br>
Speak terms of manage to thy bounding steed,<br>
Cry “Courage! To the field!” And thou hast talk’d<br>
Of sallies and retires, of trenches, tents,<br>
Of palisadoes, frontiers, parapets,<br>
Of basilisks, of cannon, culverin,<br>
Of prisoners’ ransom, and of soldiers slain,<br>
And all the currents of a heady fight.<br>
Thy spirit within thee hath been so at war,<br>
And thus hath so bestirr’d thee in thy sleep,<br>
That beads of sweat have stood upon thy brow<br>
Like bubbles in a late-disturbed stream,<br>
And in thy face strange motions have appear’d,<br>
Such as we see when men restrain their breath<br>
On some great sudden hest. O, what portents are these?<br>
Some heavy business hath my lord in hand,<br>
And I must know it, else he loves me not.
</p>

<p class="drama">
HOTSPUR.<br>
What, ho!
</p>

<p class="scenedesc">Enter a <span class="charname">Servant</span>.
</p>

<p class="drama">
Is Gilliams with the packet gone?
</p>

<p class="drama">
SERVANT.<br>
He is, my lord, an hour ago.
</p>

<p class="drama">
HOTSPUR.<br>
Hath Butler brought those horses from the sheriff?
</p>

<p class="drama">
SERVANT.<br>
One horse, my lord, he brought even now.
</p>

<p class="drama">
HOTSPUR.<br>
What horse? A roan, a crop-ear, is it not?
</p>

<p class="drama">
SERVANT.<br>
It is, my lord.
</p>

<p class="drama">
HOTSPUR.<br>
That roan shall be my throne.<br>
Well, I will back him straight. O Esperance!<br>
Bid Butler lead him forth into the park.
</p>

<p class="right">[<i>Exit <span class="charname">Servant</span>.</i>]
</p>

<p class="drama">
LADY PERCY.<br>
But hear you, my lord.
</p>

<p class="drama">
HOTSPUR.<br>
What say’st thou, my lady?
</p>

<p class="drama">
LADY PERCY.<br>
What is it carries you away?
</p>

<p class="drama">
HOTSPUR.<br>
Why, my horse, my love, my horse.
</p>

<p class="drama">
LADY PERCY.<br>
Out, you mad-headed ape!<br>
A weasel hath not such a deal of spleen<br>
As you are toss’d with. In faith,<br>
I’ll know your business, Harry, that I will.<br>
I fear my brother Mortimer doth stir<br>
About his title, and hath sent for you<br>
To line his enterprise. But if you go—
</p>

<p class="drama">
HOTSPUR.<br>
So far afoot, I shall be weary, love.
</p>

<p class="drama">
LADY PERCY.<br>
Come, come, you paraquito, answer me<br>
Directly unto this question that I ask.<br>
In faith, I’ll break thy little finger, Harry,<br>
If thou wilt not tell me all things true.
</p>

<p class="drama">
HOTSPUR.<br>
Away,<br>
Away, you trifler! Love, I love thee not,<br>
I care not for thee, Kate. This is no world<br>
To play with mammets and to tilt with lips.<br>
We must have bloody noses and crack’d crowns,<br>
And pass them current too.—Gods me, my horse!—<br>
What say’st thou, Kate? What wouldst thou have with me?
</p>

<p class="drama">
LADY PERCY.<br>
Do you not love me? Do you not indeed?<br>
Well, do not, then, for since you love me not,<br>
I will not love myself. Do you not love me?<br>
Nay, tell me if you speak in jest or no.
</p>

<p class="drama">
HOTSPUR.<br>
Come, wilt thou see me ride?<br>
And when I am a-horseback I will swear<br>
I love thee infinitely. But hark you, Kate,<br>
I must not have you henceforth question me<br>
Whither I go, nor reason whereabout.<br>
Whither I must, I must; and, to conclude,<br>
This evening must I leave you, gentle Kate.<br>
I know you wise, but yet no farther wise<br>
Than Harry Percy’s wife; constant you are,<br>
But yet a woman; and for secrecy,<br>
No lady closer, for I well believe<br>
Thou wilt not utter what thou dost not know;<br>
And so far will I trust thee, gentle Kate.
</p>

<p class="drama">
LADY PERCY.<br>
How? So far?
</p>

<p class="drama">
HOTSPUR.<br>
Not an inch further. But hark you, Kate,<br>
Whither I go, thither shall you go too.<br>
Today will I set forth, tomorrow you.<br>
Will this content you, Kate?
</p>

<p class="drama">
LADY PERCY.<br>
It must, of force.
</p>

