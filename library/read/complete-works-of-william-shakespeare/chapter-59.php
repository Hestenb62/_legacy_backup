<h2><a id="sceneV_10.1"></a>ACT V</h2>

<h3> <b>SCENE I. Gloucestershire. Shallow’s house.</b></h3>

<p class="scenedesc">Enter <span class="charname">Shallow, Falstaff,
Bardolph</span> and <span class="charname">Page</span>.</p>

<p class="drama">
SHALLOW.<br>
By cock and pie, sir, you shall not away tonight.<br>
What, Davy, I say!
</p>

<p class="drama">
FALSTAFF.<br>
You must excuse me, Master Robert Shallow.
</p>

<p class="drama">
SHALLOW.<br>
I will not excuse you, you shall not be excused. Excuses shall not be admitted,
there is no excuse shall serve, you shall not be excused. Why, Davy!
</p>

<p class="scenedesc">Enter <span class="charname">Davy</span>.</p>

<p class="drama">
DAVY.<br>
Here, sir.
</p>

<p class="drama">
SHALLOW.<br>
Davy, Davy, Davy, Davy, let me see, Davy, let me see, Davy, let me see. Yea,
marry, William cook, bid him come hither. Sir John, you shall not be excused.
</p>

<p class="drama">
DAVY.<br>
Marry, sir, thus: those precepts cannot be served; and again, sir—shall
we sow the hade land with wheat?
</p>

<p class="drama">
SHALLOW.<br>
With red wheat, Davy. But for William cook, are there no young pigeons?
</p>

<p class="drama">
DAVY.<br>
Yes, sir. Here is now the smith’s note for shoeing and plough-irons.
</p>

<p class="drama">
SHALLOW.<br>
Let it be cast and paid. Sir John, you shall not be excused.
</p>

<p class="drama">
DAVY.<br>
Now, sir, a new link to the bucket must needs be had. And, sir, do you mean to
stop any of William’s wages, about the sack he lost the other day at
Hinckley fair?
</p>

<p class="drama">
SHALLOW.<br>
He shall answer it. Some pigeons, Davy, a couple of short-legged hens, a joint
of mutton, and any pretty little tiny kickshaws, tell William cook.
</p>

<p class="drama">
DAVY.<br>
Doth the man of war stay all night, sir?
</p>

<p class="drama">
SHALLOW.<br>
Yea, Davy, I will use him well: a friend i’ th’ court is better
than a penny in purse. Use his men well, Davy, for they are arrant knaves, and
will backbite.
</p>

<p class="drama">
DAVY.<br>
No worse than they are backbitten, sir, for they have marvellous foul linen.
</p>

<p class="drama">
SHALLOW.<br>
Well conceited, Davy. About thy business, Davy.
</p>

<p class="drama">
DAVY.<br>
I beseech you, sir, to countenance William Visor of Woncot against Clement
Perkes o’ th’ hill.
</p>

<p class="drama">
SHALLOW.<br>
There is many complaints, Davy, against that Visor. That Visor is an arrant
knave, on my knowledge.
</p>

<p class="drama">
DAVY.<br>
I grant your worship that he is a knave, sir, but yet, God forbid, sir, but a
knave should have some countenance at his friend’s request. An honest
man, sir, is able to speak for himself, when a knave is not. I have served your
worship truly, sir, this eight years; and if I cannot once or twice in a
quarter bear out a knave against an honest man, I have but a very little credit
with your worship. The knave is mine honest friend, sir; therefore I beseech
your worship let him be countenanced.
</p>

<p class="drama">
SHALLOW.<br>
Go to; I say he shall have no wrong. Look about, Davy.
</p>

<p class="right"> [<i>Exit <span class="charname">Davy</span>.</i>]</p>

<p class="drama">
Where are you, Sir John? Come, come, come, off with your boots.<br>
Give me your hand, Master Bardolph.
</p>

<p class="drama">
BARDOLPH.<br>
I am glad to see your worship.
</p>

<p class="drama">
SHALLOW.<br>
I thank thee with all my heart, kind Master Bardolph; and welcome, my tall
fellow [<i>to the Page</i>]. Come, Sir John.
</p>

<p class="drama">
FALSTAFF.<br>
I’ll follow you, good Master Robert Shallow.
</p>

<p class="right"> [<i>Exit <span class="charname">Shallow</span>.</i>]</p>

<p class="drama">
Bardolph, look to our horses.
</p>

<p class="right"> [<i>Exeunt <span class="charname">Bardolph</span> and
<span class="charname">Page</span>.</i>]</p>

<p class="drama">
If I were sawed into quantities, I should make four dozen of such bearded
hermits’ staves as Master Shallow. It is a wonderful thing to see the
semblable coherence of his men’s spirits and his. They, by observing of
him, do bear themselves like foolish justices: he, by conversing with them, is
turned into a justice-like serving-man. Their spirits are so married in
conjunction with the participation of society that they flock together in
consent, like so many wild-geese. If I had a suit to Master Shallow, I would
humour his men with the imputation of being near their master: if to his men, I
would curry with Master Shallow that no man could better command his servants.
It is certain that either wise bearing or ignorant carriage is caught, as men
take diseases, one of another. Therefore let men take heed of their company. I
will devise matter enough out of this Shallow to keep Prince Harry in continual
laughter the wearing out of six fashions, which is four terms, or two actions,
and he shall laugh without intervallums. O, it is much that a lie with a slight
oath and a jest with a sad brow will do with a fellow that never had the ache
in his shoulders! O, you shall see him laugh till his face be like a wet cloak
ill laid up!
</p>

<p class="drama">
SHALLOW.<br>
[<i>Within</i>.] Sir John!
</p>

<p class="drama">
FALSTAFF.<br>
I come, Master Shallow, I come, Master Shallow.
</p>

<p class="right"> [<i>Exit.</i>]</p>

<h3> <a id="sceneV_10.2"></a><b>SCENE II. Westminster. The palace.</b></h3>

<p class="scenedesc">Enter <span class="charname">Warwick</span> and the
<span class="charname">Lord Chief Justice</span>, meeting.</p>

<p class="drama">
WARWICK.<br>
How now, my Lord Chief Justice, whither away?
</p>

<p class="drama">
CHIEF JUSTICE.<br>
How doth the King?
</p>

<p class="drama">
WARWICK.<br>
Exceeding well. His cares are now all ended.
</p>

<p class="drama">
CHIEF JUSTICE.<br>
I hope, not dead.
</p>

<p class="drama">
WARWICK.<br>
He’s walk’d the way of nature,<br>
And to our purposes he lives no more.
</p>

<p class="drama">
CHIEF JUSTICE.<br>
I would his Majesty had call’d me with him.<br>
The service that I truly did his life<br>
Hath left me open to all injuries.
</p>

<p class="drama">
WARWICK.<br>
Indeed I think the young King loves you not.
</p>

<p class="drama">
CHIEF JUSTICE.<br>
I know he doth not, and do arm myself<br>
To welcome the condition of the time,<br>
Which cannot look more hideously upon me<br>
Than I have drawn it in my fantasy.
</p>

<p class="scenedesc">Enter <span class="charname">Lancaster, Clarence,
Gloucester</span> and others.</p>

<p class="drama">
WARWICK.<br>
Here comes the heavy issue of dead Harry.<br>
O that the living Harry had the temper<br>
Of he the worst of these three gentlemen!<br>
How many nobles then should hold their places,<br>
That must strike sail to spirits of vile sort!
</p>

<p class="drama">
CHIEF JUSTICE.<br>
O God, I fear all will be overturn’d.
</p>

<p class="drama">
LANCASTER.<br>
Good morrow, cousin Warwick, good morrow.
</p>

<p class="drama">
GLOUCESTER &amp; CLARENCE.<br>
Good morrow, cousin.
</p>

<p class="drama">
LANCASTER.<br>
We meet like men that had forgot to speak.
</p>

<p class="drama">
WARWICK.<br>
We do remember, but our argument<br>
Is all too heavy to admit much talk.
</p>

<p class="drama">
LANCASTER.<br>
Well, peace be with him that hath made us heavy!
</p>

<p class="drama">
CHIEF JUSTICE.<br>
Peace be with us, lest we be heavier!
</p>

<p class="drama">
GLOUCESTER.<br>
O, good my lord, you have lost a friend indeed;<br>
And I dare swear you borrow not that face<br>
Of seeming sorrow; it is sure your own.
</p>

<p class="drama">
LANCASTER.<br>
Though no man be assured what grace to find,<br>
You stand in coldest expectation.<br>
I am the sorrier; would ’twere otherwise.
</p>

<p class="drama">
CLARENCE.<br>
Well, you must now speak Sir John Falstaff fair,<br>
Which swims against your stream of quality.
</p>

<p class="drama">
CHIEF JUSTICE.<br>
Sweet Princes, what I did I did in honour,<br>
Led by th’ impartial conduct of my soul;<br>
And never shall you see that I will beg<br>
A ragged and forestall’d remission.<br>
If truth and upright innocency fail me,<br>
I’ll to the King my master that is dead,<br>
And tell him who hath sent me after him.
</p>

<p class="drama">
WARWICK.<br>
Here comes the Prince.
</p>

<p class="scenedesc">Enter <span class="charname">King Henry the Fifth</span>, attended.</p>

<p class="drama">
CHIEF JUSTICE.<br>
Good morrow, and God save your Majesty!
</p>

<p class="drama">
KING.<br>
This new and gorgeous garment, majesty,<br>
Sits not so easy on me as you think.<br>
Brothers, you mix your sadness with some fear.<br>
This is the English, not the Turkish court;<br>
Not Amurath an Amurath succeeds,<br>
But Harry Harry. Yet be sad, good brothers,<br>
For, by my faith, it very well becomes you.<br>
Sorrow so royally in you appears<br>
That I will deeply put the fashion on<br>
And wear it in my heart. Why then, be sad;<br>
But entertain no more of it, good brothers,<br>
Than a joint burden laid upon us all.<br>
For me, by heaven, I bid you be assured,<br>
I’ll be your father and your brother too;<br>
Let me but bear your love, I’ll bear your cares.<br>
Yet weep that Harry’s dead, and so will I;<br>
But Harry lives, that shall convert those tears<br>
By number into hours of happiness.
</p>

<p class="drama">
PRINCES.<br>
We hope no otherwise from your Majesty.
</p>

<p class="drama">
KING.<br>
You all look strangely on me. And you most;<br>
You are, I think, assured I love you not.
</p>

<p class="drama">
CHIEF JUSTICE.<br>
I am assured, if I be measured rightly,<br>
Your Majesty hath no just cause to hate me.
</p>

<p class="drama">
KING.<br>
No?<br>
How might a prince of my great hopes forget<br>
So great indignities you laid upon me?<br>
What! rate, rebuke, and roughly send to prison<br>
Th’ immediate heir of England? Was this easy?<br>
May this be wash’d in Lethe and forgotten?
</p>

<p class="drama">
CHIEF JUSTICE.<br>
I then did use the person of your father;<br>
The image of his power lay then in me;<br>
And in the administration of his law,<br>
Whiles I was busy for the commonwealth,<br>
Your Highness pleased to forget my place,<br>
The majesty and power of law and justice,<br>
The image of the King whom I presented,<br>
And struck me in my very seat of judgement;<br>
Whereon, as an offender to your father,<br>
I gave bold way to my authority<br>
And did commit you. If the deed were ill,<br>
Be you contented, wearing now the garland,<br>
To have a son set your decrees at nought?<br>
To pluck down justice from your awful bench?<br>
To trip the course of law and blunt the sword<br>
That guards the peace and safety of your person?<br>
Nay more, to spurn at your most royal image,<br>
And mock your workings in a second body?<br>
Question your royal thoughts, make the case yours;<br>
Be now the father and propose a son,<br>
Hear your own dignity so much profaned,<br>
See your most dreadful laws so loosely slighted,<br>
Behold yourself so by a son disdain’d,<br>
And then imagine me taking your part<br>
And in your power soft silencing your son.<br>
After this cold considerance, sentence me;<br>
And, as you are a king, speak in your state<br>
What I have done that misbecame my place,<br>
My person, or my liege’s sovereignty.
</p>

<p class="drama">
KING.<br>
You are right, justice, and you weigh this well.<br>
Therefore still bear the balance and the sword.<br>
And I do wish your honours may increase<br>
Till you do live to see a son of mine<br>
Offend you and obey you, as I did.<br>
So shall I live to speak my father’s words:<br>
“Happy am I, that have a man so bold<br>
That dares do justice on my proper son;<br>
And not less happy, having such a son<br>
That would deliver up his greatness so<br>
Into the hands of justice.” You did commit me,<br>
For which I do commit into your hand<br>
Th’ unstained sword that you have used to bear,<br>
With this remembrance: that you use the same<br>
With the like bold, just, and impartial spirit<br>
As you have done ’gainst me. There is my hand.<br>
You shall be as a father to my youth,<br>
My voice shall sound as you do prompt mine ear,<br>
And I will stoop and humble my intents<br>
To your well-practised wise directions.<br>
And, princes all, believe me, I beseech you,<br>
My father is gone wild into his grave,<br>
For in his tomb lie my affections;<br>
And with his spirit sadly I survive<br>
To mock the expectation of the world,<br>
To frustrate prophecies, and to raze out<br>
Rotten opinion, who hath writ me down<br>
After my seeming. The tide of blood in me<br>
Hath proudly flow’d in vanity till now.<br>
Now doth it turn and ebb back to the sea,<br>
Where it shall mingle with the state of floods,<br>
And flow henceforth in formal majesty.<br>
Now call we our high court of parliament,<br>
And let us choose such limbs of noble counsel<br>
That the great body of our state may go<br>
In equal rank with the best-govern’d nation;<br>
That war, or peace, or both at once, may be<br>
As things acquainted and familiar to us;<br>
In which you, father, shall have foremost hand.<br>
Our coronation done, we will accite,<br>
As I before remember’d, all our state:<br>
And, God consigning to my good intents,<br>
No prince nor peer shall have just cause to say,<br>
God shorten Harry’s happy life one day!
</p>

<p class="right"> [<i>Exeunt.</i>]</p>

<h3> <a id="sceneV_10.3"></a><b>SCENE III. Gloucestershire. Shallow’s orchard.</b></h3>

<p class="scenedesc">Enter <span class="charname">Falstaff, Shallow, Silence,
Davy, Bardolph</span> and the <span class="charname">Page</span>.</p>

<p class="drama">
SHALLOW.<br>
Nay, you shall see my orchard, where, in an arbour, we will eat a last
year’s pippin of mine own graffing, with a dish of caraways, and so
forth. Come, cousin Silence. And then to bed.
</p>

<p class="drama">
FALSTAFF.<br>
Fore God, you have here a goodly dwelling, and a rich.
</p>

<p class="drama">
SHALLOW.<br>
Barren, barren, barren; beggars all, beggars all, Sir John. Marry, good air.
Spread, Davy, spread, Davy. Well said, Davy.
</p>

<p class="drama">
FALSTAFF.<br>
This Davy serves you for good uses; he is your serving-man and your husband.
</p>

<p class="drama">
SHALLOW.<br>
A good varlet, a good varlet, a very good varlet, Sir John. By the mass, I have
drunk too much sack at supper. A good varlet. Now sit down, now sit down. Come,
cousin.
</p>

<p class="drama">
SILENCE.<br>
Ah, sirrah! quoth-a, we shall
[<i>Singing.</i>]
</p>

<p class="drama">
    <i>Do nothing but eat, and make good cheer,<br>
    And praise God for the merry year,<br>
    When flesh is cheap and females dear,<br>
    And lusty lads roam here and there<br>
    So merrily,<br>
    And ever among so merrily.</i>
</p>

<p class="drama">
FALSTAFF.<br>
There’s a merry heart! Good Master Silence, I’ll give you a health
for that anon.
</p>

<p class="drama">
SHALLOW.<br>
Give Master Bardolph some wine, Davy.
</p>

<p class="drama">
DAVY.<br>
Sweet sir, sit. I’ll be with you anon. Most sweet sir, sit. Master page,
good master page, sit. Proface! What you want in meat, we’ll have in
drink, but you must bear; the heart’s all.
</p>

<p class="right"> [<i>Exit.</i>]</p>

<p class="drama">
SHALLOW.<br>
Be merry, Master Bardolph, and, my little soldier there, be merry.
</p>

<p class="drama">
SILENCE.<br>
[<i>Singing.</i>]
</p>

<p class="drama">
    <i>Be merry, be merry, my wife has all,<br>
    For women are shrews, both short and tall.<br>
    ’Tis merry in hall when beards wag all,<br>
    And welcome merry Shrove-tide.<br>
    Be merry, be merry.</i>
</p>

<p class="drama">
FALSTAFF.<br>
I did not think Master Silence had been a man of this mettle.
</p>

<p class="drama">
SILENCE.<br>
Who, I? I have been merry twice and once ere now.
</p>

<p class="scenedesc">Enter <span class="charname">Davy</span>.</p>

<p class="drama">
DAVY.<br>
[<i>To Bardolph</i>.] There’s a dish of leather-coats for you.
</p>

<p class="drama">
SHALLOW.<br>
Davy!
</p>

<p class="drama">
DAVY.<br>
Your worship? I’ll be with you straight.<br>
[<i>To Bardolph</i>] A cup of wine, sir?
</p>

<p class="drama">
SILENCE.<br>
[<i>Singing.</i>]
</p>

<p class="drama">
    <i>A cup of wine that’s brisk and fine,<br>
    And drink unto thee, leman mine,<br>
    And a merry heart lives long-a.</i>
</p>

<p class="drama">
FALSTAFF.<br>
Well said, Master Silence.
</p>

<p class="drama">
SILENCE.<br>
An we shall be merry, now comes in the sweet o’ th’ night.
</p>

<p class="drama">
FALSTAFF.<br>
Health and long life to you, Master Silence.
</p>

<p class="drama">
SILENCE.<br>
[<i>Singing.</i>]
</p>

<p class="drama">
    <i>Fill the cup, and let it come,<br>
    I’ll pledge you a mile to th’ bottom.</i>
</p>

<p class="drama">
SHALLOW.<br>
Honest Bardolph, welcome! If thou want’st anything and wilt not call,
beshrew thy heart. Welcome, my little tiny thief, [<i>to the Page</i>] and
welcome indeed too. I’ll drink to Master Bardolph, and to all the
cabileros about London.
</p>

<p class="drama">
DAVY.<br>
I hope to see London once ere I die.
</p>

<p class="drama">
BARDOLPH.<br>
An I might see you there, Davy,—
</p>

<p class="drama">
SHALLOW.<br>
By the mass, you’ll crack a quart together, ha! will you not, Master
Bardolph?
</p>

<p class="drama">
BARDOLPH.<br>
Yea, sir, in a pottle-pot.
</p>

<p class="drama">
SHALLOW.<br>
By God’s liggens, I thank thee. The knave will stick by thee, I can
assure thee that. He will not out, he. ’Tis true bred.
</p>

<p class="drama">
BARDOLPH.<br>
And I’ll stick by him, sir.
</p>

<p class="drama">
SHALLOW.<br>
Why, there spoke a king. Lack nothing! Be merry.
</p>

<p class="right"> [<i>Knocking within.</i>]</p>

<p class="drama">
Look who’s at door there, ho! Who knocks?
</p>

<p class="right"> [<i>Exit <span class="charname">Davy</span>.</i>]</p>

<p class="drama">
FALSTAFF.<br>
[<i>To Silence, seeing him take off a bumper</i>.] Why, now you have done me
right.
</p>

<p class="drama">
SILENCE.<br>
[<i>Singing.</i>]
</p>

<p class="drama">
    <i>Do me right,<br>
    And dub me knight:<br>
    Samingo.</i></p>

<p class="drama">
Is’t not so?
</p>

<p class="drama">
FALSTAFF.<br>
’Tis so.
</p>

<p class="drama">
SILENCE.<br>
Is’t so? Why then, say an old man can do somewhat.
</p>

<p class="scenedesc">Enter <span class="charname">Davy</span>.</p>

<p class="drama">
DAVY.<br>
An’t please your worship, there’s one Pistol come from the court
with news.
</p>

<p class="drama">
FALSTAFF.<br>
From the court? Let him come in.
</p>

<p class="scenedesc">Enter <span class="charname">Pistol</span>.</p>

<p class="drama">
How now, Pistol?
</p>

<p class="drama">
PISTOL.<br>
Sir John, God save you!
</p>

<p class="drama">
FALSTAFF.<br>
What wind blew you hither, Pistol?
</p>

<p class="drama">
PISTOL.<br>
Not the ill wind which blows no man to good. Sweet knight, thou art now one of
the greatest men in this realm.
</p>

<p class="drama">
SILENCE.<br>
By’r lady, I think he be, but goodman Puff of Barson.
</p>

<p class="drama">
PISTOL.<br>
Puff!<br>
Puff in thy teeth, most recreant coward base!<br>
Sir John, I am thy Pistol and thy friend,<br>
And helter-skelter have I rode to thee,<br>
And tidings do I bring and lucky joys,<br>
And golden times, and happy news of price.
</p>

<p class="drama">
FALSTAFF.<br>
I pray thee now, deliver them like a man of this world.
</p>

<p class="drama">
PISTOL.<br>
A foutre for the world and worldlings base!<br>
I speak of Africa and golden joys.
</p>

<p class="drama">
FALSTAFF.<br>
O base Assyrian knight, what is thy news?<br>
Let King Cophetua know the truth thereof.
</p>

<p class="drama">
SILENCE.<br>
[<i>Singing</i>.] <i>And Robin Hood, Scarlet, and John.</i>
</p>

<p class="drama">
PISTOL.<br>
Shall dunghill curs confront the Helicons?<br>
And shall good news be baffled?<br>
Then, Pistol, lay thy head in Furies’ lap.
</p>

<p class="drama">
SHALLOW.<br>
Honest gentleman, I know not your breeding.
</p>

<p class="drama">
PISTOL.<br>
Why then, lament therefor.
</p>

<p class="drama">
SHALLOW.<br>
Give me pardon, sir. If, sir, you come with news from the court, I take it
there’s but two ways, either to utter them, or conceal them. I am, sir,
under the King, in some authority.
</p>

<p class="drama">
PISTOL.<br>
Under which king, Besonian? Speak, or die.
</p>

<p class="drama">
SHALLOW.<br>
Under King Harry.
</p>

<p class="drama">
PISTOL.<br>
Harry the Fourth, or Fifth?
</p>

<p class="drama">
SHALLOW.<br>
Harry the Fourth.
</p>

<p class="drama">
PISTOL.<br>
A foutre for thine office!<br>
Sir John, thy tender lambkin now is King;<br>
Harry the Fifth’s the man. I speak the truth.<br>
When Pistol lies, do this, and fig me, like<br>
The bragging Spaniard.
</p>

<p class="drama">
FALSTAFF.<br>
What, is the old King dead?
</p>

<p class="drama">
PISTOL.<br>
As nail in door. The things I speak are just.
</p>

<p class="drama">
FALSTAFF.<br>
Away, Bardolph, saddle my horse. Master Robert Shallow, choose what office thou
wilt in the land, ’tis thine. Pistol, I will double-charge thee with
dignities.
</p>

<p class="drama">
BARDOLPH.<br>
O joyful day!<br>
I would not take a knighthood for my fortune.
</p>

<p class="drama">
PISTOL.<br>
What! I do bring good news.
</p>

<p class="drama">
FALSTAFF.<br>
Carry Master Silence to bed. Master Shallow, my Lord Shallow, be what thou
wilt; I am Fortune’s steward! Get on thy boots, we’ll ride all
night. O sweet Pistol! Away, Bardolph!
</p>

<p class="right"> [<i>Exit <span class="charname">Bardolph</span>.</i>]</p>

<p class="drama">
Come, Pistol, utter more to me; and withal devise something to do thyself
good. Boot, boot, Master Shallow. I know the young King is sick for me. Let us
take any man’s horses. The laws of England are at my commandment. Blessed
are they that have been my friends, and woe to my Lord Chief Justice!
</p>

<p class="drama">
PISTOL.<br>
Let vultures vile seize on his lungs also!<br>
“Where is the life that late I led?” say they:<br>
Why, here it is; welcome these pleasant days!
</p>

<p class="right"> [<i>Exeunt.</i>]</p>

<h3> <a id="sceneV_10.4"></a><b>SCENE IV. London. A street.</b></h3>

<p class="scenedesc">Enter <span class="charname">Beadles</span>, dragging in
<span class="charname">Hostess Quickly</span> and
<span class="charname">Doll Tearsheet</span>.</p>

<p class="drama">
HOSTESS.<br>
No, thou arrant knave. I would to God that I might die, that I might have thee
hanged. Thou hast drawn my shoulder out of joint.
</p>

<p class="drama">
FIRST BEADLE.<br>
The constables have delivered her over to me, and she shall have whipping-cheer
enough, I warrant her. There hath been a man or two lately killed about her.
</p>

<p class="drama">
DOLL.<br>
Nut-hook, nut-hook, you lie! Come on, I’ll tell thee what, thou damned
tripe-visaged rascal, an the child I now go with do miscarry, thou wert better
thou hadst struck thy mother, thou paper-faced villain.
</p>

<p class="drama">
HOSTESS.<br>
O the Lord, that Sir John were come! He would make this a bloody day to
somebody. But I pray God the fruit of her womb miscarry!
</p>

<p class="drama">
FIRST BEADLE.<br>
If it do, you shall have a dozen of cushions again; you have but eleven now.
Come, I charge you both go with me, for the man is dead that you and Pistol
beat amongst you.
</p>

<p class="drama">
DOLL.<br>
I’ll tell you what, you thin man in a censer, I will have you as soundly
swinged for this, you bluebottle rogue, you filthy famished correctioner, if
you be not swinged, I’ll forswear half-kirtles.
</p>

<p class="drama">
FIRST BEADLE.<br>
Come, come, you she knight-errant, come.
</p>

<p class="drama">
HOSTESS.<br>
O God, that right should thus overcome might! Well, of sufferance comes ease.
</p>

<p class="drama">
DOLL.<br>
Come, you rogue, come, bring me to a justice.
</p>

<p class="drama">
HOSTESS.<br>
Ay, come, you starved bloodhound.
</p>

<p class="drama">
DOLL.<br>
Goodman death, goodman bones!
</p>

<p class="drama">
HOSTESS.<br>
Thou atomy, thou!
</p>

<p class="drama">
DOLL.<br>
Come, you thin thing, come, you rascal!
</p>

<p class="drama">
FIRST BEADLE.<br>
Very well.
</p>

<p class="right"> [<i>Exeunt.</i>]</p>

<h3> <a id="sceneV_10.5"></a><b>SCENE V. A public place near Westminster Abbey.</b></h3>

<p class="scenedesc">Enter two <span class="charname">Grooms</span>, strewing rushes.</p>

<p class="drama">
FIRST GROOM.<br>
More rushes, more rushes.
</p>

<p class="drama">
SECOND GROOM.<br>
The trumpets have sounded twice.
</p>

<p class="drama">
FIRST GROOM.<br>
’Twill be two o’clock ere they come from the coronation. Dispatch, dispatch.
</p>

<p class="right"> [<i>Exeunt.</i>]</p>

<p class="scenedesc">Trumpets sound, and the <span class="charname">King</span>
and his train pass over the stage. Enter <span class="charname">Falstaff,
Shallow, Pistol, Bardolph</span> and <span class="charname">Page</span>.
</p>

<p class="drama">
FALSTAFF.<br>
Stand here by me, Master Robert Shallow. I will make the King do you grace. I
will leer upon him as he comes by, and do but mark the countenance that he will
give me.
</p>

<p class="drama">
PISTOL.<br>
God bless thy lungs, good knight!
</p>

<p class="drama">
FALSTAFF.<br>
Come here, Pistol, stand behind me. O, if I had had time to have made new
liveries, I would have bestowed the thousand pound I borrowed of you. But
’tis no matter, this poor show doth better. This doth infer the zeal I
had to see him.
</p>

<p class="drama">
SHALLOW.<br>
It doth so.
</p>

<p class="drama">
FALSTAFF.<br>
It shows my earnestness of affection—
</p>

<p class="drama">
SHALLOW.<br>
It doth so.
</p>

<p class="drama">
FALSTAFF.<br>
My devotion—
</p>

<p class="drama">
SHALLOW.<br>
It doth, it doth, it doth.
</p>

<p class="drama">
FALSTAFF.<br>
As it were, to ride day and night, and not to deliberate, not to remember, not
to have patience to shift me—
</p>

<p class="drama">
SHALLOW.<br>
It is best, certain.
</p>

<p class="drama">
FALSTAFF.<br>
But to stand stained with travel, and sweating with desire to see him, thinking
of nothing else, putting all affairs else in oblivion, as if there were nothing
else to be done but to see him.
</p>

<p class="drama">
PISTOL.<br>
’Tis <i>semper idem</i>, for <i>obsque hoc nihil est;</i> ’tis all
in every part.
</p>

<p class="drama">
SHALLOW.<br>
’Tis so, indeed.
</p>

<p class="drama">
PISTOL.<br>
My knight, I will inflame thy noble liver,<br>
And make thee rage.<br>
Thy Doll, and Helen of thy noble thoughts,<br>
Is in base durance and contagious prison,<br>
Haled thither<br>
By most mechanical and dirty hand.<br>
Rouse up revenge from ebon den with fell Alecto’s snake,<br>
For Doll is in. Pistol speaks nought but truth.
</p>

<p class="drama">
FALSTAFF.<br>
I will deliver her.
</p>

<p class="right"> [<i>Shouts within. The trumpets sound.</i>]</p>

<p class="drama">
PISTOL.<br>
There roar’d the sea, and trumpet-clangor sounds.
</p>

<p class="scenedesc">Enter the <span class="charname">King</span> and his
train, the <span class="charname">Lord Chief Justice</span> among them.</p>

<p class="drama">
FALSTAFF.<br>
God save thy Grace, King Hal, my royal Hal!
</p>

<p class="drama">
PISTOL.<br>
The heavens thee guard and keep, most royal imp of fame!
</p>

<p class="drama">
FALSTAFF.<br>
God save thee, my sweet boy!
</p>

<p class="drama">
KING.<br>
My Lord Chief Justice, speak to that vain man.
</p>

<p class="drama">
CHIEF JUSTICE.<br>
Have you your wits? Know you what ’tis you speak?
</p>

<p class="drama">
FALSTAFF.<br>
My King! My Jove! I speak to thee, my heart!
</p>

<p class="drama">
KING.<br>
I know thee not, old man. Fall to thy prayers.<br>
How ill white hairs becomes a fool and jester!<br>
I have long dreamt of such a kind of man,<br>
So surfeit-swell’d, so old, and so profane;<br>
But, being awaked, I do despise my dream.<br>
Make less thy body hence, and more thy grace;<br>
Leave gormandizing; know the grave doth gape<br>
For thee thrice wider than for other men.<br>
Reply not to me with a fool-born jest.<br>
Presume not that I am the thing I was;<br>
For God doth know, so shall the world perceive,<br>
That I have turn’d away my former self;<br>
So will I those that kept me company.<br>
When thou dost hear I am as I have been,<br>
Approach me, and thou shalt be as thou wast,<br>
The tutor and the feeder of my riots.<br>
Till then I banish thee, on pain of death,<br>
As I have done the rest of my misleaders,<br>
Not to come near our person by ten mile.<br>
For competence of life I will allow you,<br>
That lack of means enforce you not to evils.<br>
And, as we hear you do reform yourselves,<br>
We will, according to your strengths and qualities,<br>
Give you advancement. Be it your charge, my lord,<br>
To see perform’d the tenor of our word.<br>
Set on.
</p>

<p class="right"> [<i>Exeunt <span class="charname">King</span> with his train.</i>]</p>

<p class="drama">
FALSTAFF.<br>
Master Shallow, I owe you a thousand pounds.
</p>

<p class="drama">
SHALLOW.<br>
Yea, marry, Sir John, which I beseech you to let me have home with me.
</p>

<p class="drama">
FALSTAFF.<br>
That can hardly be, Master Shallow. Do not you grieve at this; I shall be sent
for in private to him. Look you, he must seem thus to the world. Fear not your
advancements; I will be the man yet that shall make you great.
</p>

<p class="drama">
SHALLOW.<br>
I cannot perceive how, unless you give me your doublet and stuff me out with
straw. I beseech you, good Sir John, let me have five hundred of my thousand.
</p>

<p class="drama">
FALSTAFF.<br>
Sir, I will be as good as my word. This that you heard was but a colour.
</p>

<p class="drama">
SHALLOW.<br>
A colour that I fear you will die in, Sir John.
</p>

<p class="drama">
FALSTAFF.<br>
Fear no colours. Go with me to dinner. Come, Lieutenant Pistol; come, Bardolph.
I shall be sent for soon at night.
</p>

<p class="scenedesc">Enter <span class="charname">the Lord Chief Justice</span>
and <span class="charname">Prince John</span>, Officers with them.</p>

<p class="drama">
CHIEF JUSTICE.<br>
Go, carry Sir John Falstaff to the Fleet.<br>
Take all his company along with him.
</p>

<p class="drama">
FALSTAFF.<br>
My lord, my lord,—
</p>

<p class="drama">
CHIEF JUSTICE.<br>
I cannot now speak. I will hear you soon.<br>
Take them away.
</p>

<p class="drama">
PISTOL.<br>
<i>Si fortuna me tormenta, spero me contenta.</i>
</p>

<p class="right"> [<i>Exeunt all but <span class="charname">Prince John</span> and the
<span class="charname">Lord Chief Justice</span>.</i>]</p>

<p class="drama">
LANCASTER.<br>
I like this fair proceeding of the King’s.<br>
He hath intent his wonted followers<br>
Shall all be very well provided for,<br>
But all are banish’d till their conversations<br>
Appear more wise and modest to the world.
</p>

<p class="drama">
CHIEF JUSTICE.<br>
And so they are.
</p>

<p class="drama">
LANCASTER.<br>
The King hath call’d his parliament, my lord.
</p>

<p class="drama">
CHIEF JUSTICE.<br>
He hath.
</p>

<p class="drama">
LANCASTER.<br>
I will lay odds that, ere this year expire,<br>
We bear our civil swords and native fire<br>
As far as France. I heard a bird so sing,<br>
Whose music, to my thinking, pleased the King.<br>
Come, will you hence?
</p>

<p class="right"> [<i>Exeunt.</i>]</p>

