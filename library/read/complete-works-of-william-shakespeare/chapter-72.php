<h2> <a id="sceneIII_12.1"></a><b>ACT III</b></h2>

<h3> <b>SCENE I. London. The Parliament House.</b></h3>

<p class="scenedesc">Flourish. Enter <span class="charname">King, Exeter,
Gloucester, the Bishop of Winchester, Richard Plantagenet, Warwick</span>, and <span class="charname">Somerset, Suffolk</span>, and others. <span class="charname">Gloucester</span> offers to put up a bill.
<span class="charname">Winchester</span> snatches it, tears it.</p>

<p class="drama">
WINCHESTER.<br>
Com’st thou with deep premeditated lines,<br>
With written pamphlets studiously devised,<br>
Humphrey of Gloucester? If thou canst accuse<br>
Or aught intend’st to lay unto my charge,<br>
Do it without invention, suddenly;<br>
As I with sudden and extemporal speech<br>
Purpose to answer what thou canst object.
</p>

<p class="drama">
GLOUCESTER.<br>
Presumptuous priest, this place commands my patience,<br>
Or thou shouldst find thou hast dishonour’d me.<br>
Think not, although in writing I preferr’d<br>
The manner of thy vile outrageous crimes,<br>
That therefore I have forged, or am not able<br>
Verbatim to rehearse the method of my pen.<br>
No, prelate; such is thy audacious wickedness,<br>
Thy lewd, pestiferous, and dissentious pranks,<br>
As very infants prattle of thy pride.<br>
Thou art a most pernicious usurer,<br>
Froward by nature, enemy to peace;<br>
Lascivious, wanton, more than well beseems<br>
A man of thy profession and degree;<br>
And for thy treachery, what’s more manifest,<br>
In that thou laid’st a trap to take my life,<br>
As well at London Bridge as at the Tower?<br>
Beside, I fear me, if thy thoughts are sifted,<br>
The King, thy sovereign, is not quite exempt<br>
From envious malice of thy swelling heart.
</p>

<p class="drama">
WINCHESTER.<br>
Gloucester, I do defy thee. Lords, vouchsafe<br>
To give me hearing what I shall reply.<br>
If I were covetous, ambitious, or perverse,<br>
As he will have me, how am I so poor?<br>
Or how haps it I seek not to advance<br>
Or raise myself, but keep my wonted calling?<br>
And for dissension, who preferreth peace<br>
More than I do, except I be provoked?<br>
No, my good lords, it is not that offends;<br>
It is not that that hath incensed the Duke.<br>
It is because no one should sway but he,<br>
No one but he should be about the King;<br>
And that engenders thunder in his breast<br>
And makes him roar these accusations forth.<br>
But he shall know I am as good—
</p>

<p class="drama">
GLOUCESTER.<br>
As good!<br>
Thou bastard of my grandfather!
</p>

<p class="drama">
WINCHESTER.<br>
Ay, lordly sir; for what are you, I pray,<br>
But one imperious in another’s throne?
</p>

<p class="drama">
GLOUCESTER.<br>
Am I not Protector, saucy priest?
</p>

<p class="drama">
WINCHESTER.<br>
And am not I a prelate of the church?
</p>

<p class="drama">
GLOUCESTER.<br>
Yes, as an outlaw in a castle keeps,<br>
And useth it to patronage his theft.
</p>

<p class="drama">
WINCHESTER.<br>
Unreverent Gloucester!
</p>

<p class="drama">
GLOUCESTER.<br>
Thou art reverend<br>
Touching thy spiritual function, not thy life.
</p>

<p class="drama">
WINCHESTER.<br>
Rome shall remedy this.
</p>

<p class="drama">
GLOUCESTER.<br>
Roam thither, then.
</p>

<p class="drama">
WARWICK.<br>
My lord, it were your duty to forbear.
</p>

<p class="drama">
SOMERSET.<br>
Ay, so the bishop be not overborne.<br>
Methinks my lord should be religious,<br>
And know the office that belongs to such.
</p>

<p class="drama">
WARWICK.<br>
Methinks his lordship should be humbler;<br>
It fitteth not a prelate so to plead.
</p>

<p class="drama">
SOMERSET.<br>
Yes, when his holy state is touch’d so near.
</p>

<p class="drama">
WARWICK.<br>
State holy or unhallow’d, what of that?<br>
Is not his Grace Protector to the King?
</p>

<p class="drama">
PLANTAGENET.<br>
[<i>Aside</i>.] Plantagenet, I see, must hold his tongue,<br>
Lest it be said, “Speak, sirrah, when you should;<br>
Must your bold verdict enter talk with lords?”<br>
Else would I have a fling at Winchester.
</p>

<p class="drama">
KING HENRY.<br>
Uncles of Gloucester and of Winchester,<br>
The special watchmen of our English weal,<br>
I would prevail, if prayers might prevail,<br>
To join your hearts in love and amity.<br>
O, what a scandal is it to our crown<br>
That two such noble peers as ye should jar!<br>
Believe me, lords, my tender years can tell<br>
Civil dissension is a viperous worm<br>
That gnaws the bowels of the commonwealth.
</p>

<p class="right">[<i>A noise within, “Down with the tawny-coats!”.</i>]</p>

<p class="drama">
What tumult’s this?
</p>

<p class="drama">
WARWICK.<br>
An uproar, I dare warrant,<br>
Begun through malice of the Bishop’s men.
</p>

<p class="right">[<i>A noise again, “Stones! stones!”</i>]</p>

<p class="scenedesc">Enter <span class="charname">Mayor</span>.</p>

<p class="drama">
MAYOR.<br>
O, my good lords, and virtuous Henry,<br>
Pity the city of London, pity us!<br>
The Bishop and the Duke of Gloucester’s men,<br>
Forbidden late to carry any weapon,<br>
Have fill’d their pockets full of pebble stones<br>
And, banding themselves in contrary parts,<br>
Do pelt so fast at one another’s pate<br>
That many have their giddy brains knock’d out;<br>
Our windows are broke down in every street,<br>
And we for fear compell’d to shut our shops.
</p>

<p class="scenedesc">Enter <span class="charname">Servingmen</span> in
skirmish with bloody pates.</p>

<p class="drama">
KING HENRY.<br>
We charge you, on allegiance to ourself,<br>
To hold your slaughtering hands and keep the peace.<br>
Pray, uncle Gloucester, mitigate this strife.
</p>

<p class="drama">
FIRST SERVINGMAN.<br>
Nay, if we be forbidden stones, we’ll fall to it with our teeth.
</p>

<p class="drama">
SECOND SERVINGMAN.<br>
Do what ye dare, we are as resolute.
</p>

<p class="right">[<i>Skirmish again.</i>]</p>

<p class="drama">
GLOUCESTER.<br>
You of my household, leave this peevish broil,<br>
And set this unaccustom’d fight aside.
</p>

<p class="drama">
THIRD SERVINGMAN.<br>
My lord, we know your Grace to be a man<br>
Just and upright, and, for your royal birth,<br>
Inferior to none but to his Majesty;<br>
And ere that we will suffer such a prince,<br>
So kind a father of the commonweal,<br>
To be disgraced by an inkhorn mate,<br>
We and our wives and children all will fight<br>
And have our bodies slaughter’d by thy foes.
</p>

<p class="drama">
FIRST SERVINGMAN.<br>
Ay, and the very parings of our nails<br>
Shall pitch a field when we are dead.
</p>

<p class="right">[<i>Begin again.</i>]</p>

<p class="drama">
GLOUCESTER.<br>
Stay, stay, I say!<br>
And if you love me, as you say you do,<br>
Let me persuade you to forbear awhile.
</p>

<p class="drama">
KING HENRY.<br>
O, how this discord doth afflict my soul!<br>
Can you, my Lord of Winchester, behold<br>
My sighs and tears, and will not once relent?<br>
Who should be pitiful, if you be not?<br>
Or who should study to prefer a peace<br>
If holy churchmen take delight in broils?
</p>

<p class="drama">
WARWICK.<br>
Yield, my Lord Protector; yield, Winchester;<br>
Except you mean with obstinate repulse<br>
To slay your sovereign and destroy the realm.<br>
You see what mischief and what murder too,<br>
Hath been enacted through your enmity;<br>
Then be at peace, except ye thirst for blood.
</p>

<p class="drama">
WINCHESTER.<br>
He shall submit, or I will never yield.
</p>

<p class="drama">
GLOUCESTER.<br>
Compassion on the King commands me stoop,<br>
Or I would see his heart out, ere the priest<br>
Should ever get that privilege of me.
</p>

<p class="drama">
WARWICK.<br>
Behold, my Lord of Winchester, the Duke<br>
Hath banish’d moody discontented fury,<br>
As by his smoothed brows it doth appear.<br>
Why look you still so stern and tragical?
</p>

<p class="drama">
GLOUCESTER.<br>
Here, Winchester, I offer thee my hand.
</p>

<p class="drama">
KING HENRY.<br>
Fie, uncle Beaufort! I have heard you preach<br>
That malice was a great and grievous sin;<br>
And will not you maintain the thing you teach,<br>
But prove a chief offender in the same?
</p>

<p class="drama">
WARWICK.<br>
Sweet King! The bishop hath a kindly gird.<br>
For shame, my Lord of Winchester, relent!<br>
What, shall a child instruct you what to do?
</p>

<p class="drama">
WINCHESTER.<br>
Well, Duke of Gloucester, I will yield to thee;<br>
Love for thy love and hand for hand I give.
</p>

<p class="drama">
GLOUCESTER.<br>
[<i>Aside</i>.] Ay, but, I fear me, with a hollow heart.—<br>
See here, my friends and loving countrymen,<br>
This token serveth for a flag of truce<br>
Betwixt ourselves and all our followers,<br>
So help me God, as I dissemble not!
</p>

<p class="drama">
WINCHESTER.<br>
[<i>Aside</i>.] So help me God, as I intend it not!
</p>

<p class="drama">
KING HENRY.<br>
O loving uncle, kind Duke of Gloucester,<br>
How joyful am I made by this contract!<br>
Away, my masters, trouble us no more,<br>
But join in friendship, as your lords have done.
</p>

<p class="drama">
FIRST SERVINGMAN.<br>
Content. I’ll to the surgeon’s.
</p>

<p class="drama">
SECOND SERVINGMAN.<br>
And so will I.
</p>

<p class="drama">
THIRD SERVINGMAN.<br>
And I will see what physic the tavern affords.
</p>

<p class="right">[<i>Exeunt <span class="charname">Servingmen, Mayor</span>, &amp;c.</i>]</p>

<p class="drama">
WARWICK.<br>
Accept this scroll, most gracious sovereign,<br>
Which in the right of Richard Plantagenet<br>
We do exhibit to your Majesty.
</p>

<p class="drama">
GLOUCESTER.<br>
Well urged, my Lord of Warwick. For, sweet prince,<br>
An if your Grace mark every circumstance,<br>
You have great reason to do Richard right,<br>
Especially for those occasions<br>
At Eltham Place I told your Majesty.
</p>

<p class="drama">
KING HENRY.<br>
And those occasions, uncle, were of force;<br>
Therefore, my loving lords, our pleasure is<br>
That Richard be restored to his blood.
</p>

<p class="drama">
WARWICK.<br>
Let Richard be restored to his blood;<br>
So shall his father’s wrongs be recompensed.
</p>

<p class="drama">
WINCHESTER.<br>
As will the rest, so willeth Winchester.
</p>

<p class="drama">
KING HENRY.<br>
If Richard will be true, not that alone<br>
But all the whole inheritance I give<br>
That doth belong unto the house of York,<br>
From whence you spring by lineal descent.
</p>

<p class="drama">
PLANTAGENET.<br>
Thy humble servant vows obedience<br>
And humble service till the point of death.
</p>

<p class="drama">
KING HENRY.<br>
Stoop then and set your knee against my foot;<br>
And in reguerdon of that duty done<br>
I girt thee with the valiant sword of York.<br>
Rise, Richard, like a true Plantagenet,<br>
And rise created princely Duke of York.
</p>

<p class="drama">
PLANTAGENET.<br>
And so thrive Richard as thy foes may fall!<br>
And as my duty springs, so perish they<br>
That grudge one thought against your Majesty!
</p>

<p class="drama">
ALL.<br>
Welcome, high prince, the mighty Duke of York!
</p>

<p class="drama">
SOMERSET.<br>
[<i>Aside</i>.] Perish, base prince, ignoble Duke of York!
</p>

<p class="drama">
GLOUCESTER.<br>
Now will it best avail your Majesty<br>
To cross the seas and to be crown’d in France.<br>
The presence of a king engenders love<br>
Amongst his subjects and his loyal friends,<br>
As it disanimates his enemies.
</p>

<p class="drama">
KING HENRY.<br>
When Gloucester says the word, King Henry goes;<br>
For friendly counsel cuts off many foes.
</p>

<p class="drama">
GLOUCESTER.<br>
Your ships already are in readiness.
</p>

<p class="right">[<i>Sennet. Flourish. Exeunt all but <span class="charname">Exeter</span>.</i>]</p>

<p class="drama">
EXETER.<br>
Ay, we may march in England or in France,<br>
Not seeing what is likely to ensue.<br>
This late dissension grown betwixt the peers<br>
Burns under feigned ashes of forged love,<br>
And will at last break out into a flame;<br>
As festered members rot but by degree<br>
Till bones and flesh and sinews fall away,<br>
So will this base and envious discord breed.<br>
And now I fear that fatal prophecy<br>
Which in the time of Henry named the Fifth<br>
Was in the mouth of every sucking babe:<br>
That Henry born at Monmouth should win all,<br>
And Henry born at Windsor lose all,<br>
Which is so plain that Exeter doth wish<br>
His days may finish ere that hapless time.
</p>

<p class="right">[<i>Exit.</i>]</p>

<h3> <a id="sceneIII_12.2"></a><b>SCENE II. France. Before Rouen.</b></h3>

<p class="scenedesc">Enter <span class="charname">La Pucelle</span> with four
<span class="charname">Soldiers</span> with sacks upon their backs.</p>

<p class="drama">
PUCELLE.<br>
These are the city gates, the gates of Rouen,<br>
Through which our policy must make a breach.<br>
Take heed, be wary how you place your words;<br>
Talk like the vulgar sort of market men<br>
That come to gather money for their corn.<br>
If we have entrance, as I hope we shall,<br>
And that we find the slothful watch but weak,<br>
I’ll by a sign give notice to our friends,<br>
That Charles the Dauphin may encounter them.
</p>

<p class="drama">
FIRST SOLDIER.<br>
Our sacks shall be a mean to sack the city,<br>
And we be lords and rulers over Rouen;<br>
Therefore we’ll knock. [<i>Knocks.</i>]
</p>

<p class="drama">
WATCH.<br>
[<i>Within</i>.] <i>Qui est la?</i>
</p>

<p class="drama">
PUCELLE.<br>
<i>Paysans, la pauvres gens de France:</i><br>
Poor market folks that come to sell their corn.
</p>

<p class="drama">
WATCH.<br>
Enter, go in; the market bell is rung.
</p>

<p class="drama">
PUCELLE.<br>
Now, Rouen, I’ll shake thy bulwarks to the ground.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<p class="scenedesc">Enter <span class="charname">Charles, the Bastard of
Orleans, Alençon, Reignier</span> and forces.</p>

<p class="drama">
CHARLES.<br>
Saint Denis bless this happy stratagem,<br>
And once again we’ll sleep secure in Rouen.
</p>

<p class="drama">
BASTARD.<br>
Here enter’d Pucelle and her practisants;<br>
Now she is there, how will she specify<br>
Here is the best and safest passage in?
</p>

<p class="drama">
REIGNIER.<br>
By thrusting out a torch from yonder tower,<br>
Which, once discern’d, shows that her meaning is:<br>
No way to that, for weakness, which she enter’d.
</p>

<p class="scenedesc">Enter <span class="charname">La Pucelle</span>, on the
top, thrusting out a torch burning.</p>

<p class="drama">
PUCELLE.<br>
Behold, this is the happy wedding torch<br>
That joineth Rouen unto her countrymen,<br>
But burning fatal to the Talbonites.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
BASTARD.<br>
See, noble Charles, the beacon of our friend;<br>
The burning torch, in yonder turret stands.
</p>

<p class="drama">
CHARLES.<br>
Now shine it like a comet of revenge,<br>
A prophet to the fall of all our foes!
</p>

<p class="drama">
REIGNIER.<br>
Defer no time, delays have dangerous ends;<br>
Enter and cry, “The Dauphin!” presently,<br>
And then do execution on the watch.
</p>

<p class="right">[<i>Alarum. Exeunt.</i>]</p>

<p class="scenedesc">An alarum. Enter <span class="charname">Talbot</span> in
an excursion.</p>

<p class="drama">
TALBOT.<br>
France, thou shalt rue this treason with thy tears,<br>
If Talbot but survive thy treachery.<br>
Pucelle, that witch, that damned sorceress,<br>
Hath wrought this hellish mischief unawares,<br>
That hardly we escaped the pride of France.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="scenedesc">An alarum. Excursions. <span class="charname">Bedford</span>, brought in sick in a chair. Enter <span class="charname">Talbot</span> and <span class="charname">Burgundy</span>
without: within, <span class="charname">La Pucelle, Charles, Bastard,
Alençon</span>, and <span class="charname">Reignier</span> on the walls.</p>

<p class="drama">
PUCELLE.<br>
Good morrow, gallants! Want ye corn for bread?<br>
I think the Duke of Burgundy will fast<br>
Before he’ll buy again at such a rate.<br>
’Twas full of darnel. Do you like the taste?
</p>

<p class="drama">
BURGUNDY.<br>
Scoff on, vile fiend and shameless courtezan!<br>
I trust ere long to choke thee with thine own,<br>
And make thee curse the harvest of that corn.
</p>

<p class="drama">
CHARLES.<br>
Your Grace may starve, perhaps, before that time.
</p>

<p class="drama">
BEDFORD.<br>
O, let no words, but deeds, revenge this treason!
</p>

<p class="drama">
PUCELLE.<br>
What will you do, good graybeard? Break a lance<br>
And run a tilt at Death within a chair?
</p>

<p class="drama">
TALBOT.<br>
Foul fiend of France and hag of all despite,<br>
Encompass’d with thy lustful paramours,<br>
Becomes it thee to taunt his valiant age<br>
And twit with cowardice a man half dead?<br>
Damsel, I’ll have a bout with you again,<br>
Or else let Talbot perish with this shame.
</p>

<p class="drama">
PUCELLE.<br>
Are ye so hot? Yet, Pucelle, hold thy peace;<br>
If Talbot do but thunder, rain will follow.
</p>

<p class="right">[<i>The English whisper together in council.</i>]</p>

<p class="drama">
God speed the Parliament! Who shall be the Speaker?
</p>

<p class="drama">
TALBOT.<br>
Dare ye come forth and meet us in the field?
</p>

<p class="drama">
PUCELLE.<br>
Belike your lordship takes us then for fools,<br>
To try if that our own be ours or no.
</p>

<p class="drama">
TALBOT.<br>
I speak not to that railing Hecate,<br>
But unto thee, Alençon, and the rest;<br>
Will ye, like soldiers, come and fight it out?
</p>

<p class="drama">
ALENÇON.<br>
Seignieur, no.
</p>

<p class="drama">
TALBOT.<br>
Seignieur, hang! Base muleteers of France!<br>
Like peasant foot-boys do they keep the walls,<br>
And dare not take up arms like gentlemen.
</p>

<p class="drama">
PUCELLE.<br>
Away, captains! Let’s get us from the walls,<br>
For Talbot means no goodness by his looks.<br>
Goodbye, my lord; we came but to tell you<br>
That we are here.
</p>

<p class="right">[<i>Exeunt from the walls.</i>]</p>

<p class="drama">
TALBOT.<br>
And there will we be too, ere it be long,<br>
Or else reproach be Talbot’s greatest fame!<br>
Vow, Burgundy, by honour of thy house,<br>
Prick’d on by public wrongs sustain’d in France,<br>
Either to get the town again or die.<br>
And I, as sure as English Henry lives,<br>
And as his father here was conqueror,<br>
As sure as in this late-betrayed town<br>
Great Coeur-de-lion’s heart was buried,<br>
So sure I swear to get the town or die.
</p>

<p class="drama">
BURGUNDY.<br>
My vows are equal partners with thy vows.
</p>

<p class="drama">
TALBOT.<br>
But, ere we go, regard this dying prince,<br>
The valiant Duke of Bedford. Come, my lord,<br>
We will bestow you in some better place,<br>
Fitter for sickness and for crazy age.
</p>

<p class="drama">
BEDFORD.<br>
Lord Talbot, do not so dishonour me.<br>
Here will I sit before the walls of Rouen,<br>
And will be partner of your weal or woe.
</p>

<p class="drama">
BURGUNDY.<br>
Courageous Bedford, let us now persuade you.
</p>

<p class="drama">
BEDFORD.<br>
Not to be gone from hence; for once I read<br>
That stout Pendragon in his litter sick<br>
Came to the field and vanquished his foes.<br>
Methinks I should revive the soldiers’ hearts,<br>
Because I ever found them as myself.
</p>

<p class="drama">
TALBOT.<br>
Undaunted spirit in a dying breast!<br>
Then be it so. Heavens keep old Bedford safe!<br>
And now no more ado, brave Burgundy,<br>
But gather we our forces out of hand<br>
And set upon our boasting enemy.
</p>

<p class="right">[<i>Exeunt all but <span class="charname">Bedford</span> and Attendants.</i>]</p>

<p class="scenedesc">An alarum. Excursions. Enter <span class="charname">Sir John Fastolf</span> and a
<span class="charname">Captain</span>.</p>

<p class="drama">
CAPTAIN.<br>
Whither away, Sir John Fastolf, in such haste?
</p>

<p class="drama">
FASTOLF.<br>
Whither away? To save myself by flight.<br>
We are like to have the overthrow again.
</p>

<p class="drama">
CAPTAIN.<br>
What! Will you fly, and leave Lord Talbot?
</p>

<p class="drama">
FASTOLF.<br>
Ay,<br>
All the Talbots in the world, to save my life.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
CAPTAIN.<br>
Cowardly knight, ill fortune follow thee!
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="scenedesc">Retreat. Excursions. <span class="charname">La Pucelle,
Alençon</span> and <span class="charname">Charles</span> fly.</p>

<p class="drama">
BEDFORD.<br>
Now, quiet soul, depart when heaven please,<br>
For I have seen our enemies’ overthrow.<br>
What is the trust or strength of foolish man?<br>
They that of late were daring with their scoffs<br>
Are glad and fain by flight to save themselves.
</p>

<p class="right">[<i><span class="charname">Bedford</span> dies, and is carried in by two in his chair.</i>]</p>

<p class="scenedesc">An alarum. Enter <span class="charname">Talbot, Burgundy</span> and the rest.</p>

<p class="drama">
TALBOT.<br>
Lost, and recover’d in a day again!<br>
This is a double honour, Burgundy.<br>
Yet heavens have glory for this victory!
</p>

<p class="drama">
BURGUNDY.<br>
Warlike and martial Talbot, Burgundy<br>
Enshrines thee in his heart, and there erects<br>
Thy noble deeds as valour’s monuments.
</p>

<p class="drama">
TALBOT.<br>
Thanks, gentle Duke. But where is Pucelle now?<br>
I think her old familiar is asleep.<br>
Now where’s the Bastard’s braves, and Charles his gleeks?<br>
What, all amort? Rouen hangs her head for grief<br>
That such a valiant company are fled.<br>
Now will we take some order in the town,<br>
Placing therein some expert officers,<br>
And then depart to Paris to the King,<br>
For there young Henry with his nobles lie.
</p>

<p class="drama">
BURGUNDY.<br>
What wills Lord Talbot pleaseth Burgundy.
</p>

<p class="drama">
TALBOT.<br>
But yet, before we go, let’s not forget<br>
The noble Duke of Bedford late deceased,<br>
But see his exequies fulfill’d in Rouen.<br>
A braver soldier never couched lance,<br>
A gentler heart did never sway in court;<br>
But kings and mightiest potentates must die,<br>
For that’s the end of human misery.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneIII_12.3"></a><b>SCENE III. The plains near Rouen.</b></h3>

<p class="scenedesc">Enter <span class="charname">Charles, the Bastard of
Orleans, Alençon, La Pucelle</span> and forces.</p>

<p class="drama">
PUCELLE.<br>
Dismay not, princes, at this accident,<br>
Nor grieve that Rouen is so recovered.<br>
Care is no cure, but rather corrosive,<br>
For things that are not to be remedied.<br>
Let frantic Talbot triumph for a while<br>
And like a peacock sweep along his tail;<br>
We’ll pull his plumes and take away his train,<br>
If Dauphin and the rest will be but ruled.
</p>

<p class="drama">
CHARLES.<br>
We have been guided by thee hitherto,<br>
And of thy cunning had no diffidence.<br>
One sudden foil shall never breed distrust
</p>

<p class="drama">
BASTARD.<br>
Search out thy wit for secret policies,<br>
And we will make thee famous through the world.
</p>

<p class="drama">
ALENÇON.<br>
We’ll set thy statue in some holy place,<br>
And have thee reverenced like a blessed saint.<br>
Employ thee then, sweet virgin, for our good.
</p>

<p class="drama">
PUCELLE.<br>
Then thus it must be; this doth Joan devise:<br>
By fair persuasions mix’d with sugar’d words<br>
We will entice the Duke of Burgundy<br>
To leave the Talbot and to follow us.
</p>

<p class="drama">
CHARLES.<br>
Ay, marry, sweeting, if we could do that,<br>
France were no place for Henry’s warriors;<br>
Nor should that nation boast it so with us,<br>
But be extirped from our provinces.
</p>

<p class="drama">
ALENÇON.<br>
For ever should they be expulsed from France,<br>
And not have title of an earldom here.
</p>

<p class="drama">
PUCELLE.<br>
Your honours shall perceive how I will work<br>
To bring this matter to the wished end.
</p>

<p class="right">[<i>Drum sounds afar off.</i>]</p>

<p class="drama">
Hark! By the sound of drum you may perceive<br>
Their powers are marching unto Paris-ward.
</p>

<p class="right">[<i>Here sound an English march.</i>]</p>

<p class="drama">
There goes the Talbot, with his colours spread,<br>
And all the troops of English after him.
</p>

<p class="right">[<i>French march.</i>]</p>

<p class="drama">
Now in the rearward comes the Duke and his.<br>
Fortune in favour makes him lag behind.<br>
Summon a parley; we will talk with him.
</p>

<p class="right">[<i>Trumpets sound a parley.</i>]</p>

<p class="drama">
CHARLES.<br>
A parley with the Duke of Burgundy!
</p>

<p class="scenedesc">Enter <span class="charname">Burgundy</span>.</p>

<p class="drama">
BURGUNDY.<br>
Who craves a parley with the Burgundy?
</p>

<p class="drama">
PUCELLE.<br>
The princely Charles of France, thy countryman.
</p>

<p class="drama">
BURGUNDY.<br>
What say’st thou, Charles? for I am marching hence.
</p>

<p class="drama">
CHARLES.<br>
Speak, Pucelle, and enchant him with thy words.
</p>

<p class="drama">
PUCELLE.<br>
Brave Burgundy, undoubted hope of France,<br>
Stay, let thy humble handmaid speak to thee.
</p>

<p class="drama">
BURGUNDY.<br>
Speak on, but be not over-tedious.
</p>

<p class="drama">
PUCELLE.<br>
Look on thy country, look on fertile France,<br>
And see the cities and the towns defaced<br>
By wasting ruin of the cruel foe.<br>
As looks the mother on her lowly babe<br>
When death doth close his tender dying eyes,<br>
See, see the pining malady of France;<br>
Behold the wounds, the most unnatural wounds,<br>
Which thou thyself hast given her woeful breast.<br>
O, turn thy edged sword another way;<br>
Strike those that hurt, and hurt not those that help.<br>
One drop of blood drawn from thy country’s bosom<br>
Should grieve thee more than streams of foreign gore.<br>
Return thee therefore with a flood of tears,<br>
And wash away thy country’s stained spots.
</p>

<p class="drama">
BURGUNDY.<br>
Either she hath bewitch’d me with her words,<br>
Or nature makes me suddenly relent.
</p>

<p class="drama">
PUCELLE.<br>
Besides, all French and France exclaims on thee,<br>
Doubting thy birth and lawful progeny.<br>
Who join’st thou with but with a lordly nation<br>
That will not trust thee but for profit’s sake?<br>
When Talbot hath set footing once in France,<br>
And fashion’d thee that instrument of ill,<br>
Who then but English Henry will be lord,<br>
And thou be thrust out like a fugitive?<br>
Call we to mind, and mark but this for proof:<br>
Was not the Duke of Orleans thy foe?<br>
And was he not in England prisoner?<br>
But when they heard he was thine enemy,<br>
They set him free without his ransom paid,<br>
In spite of Burgundy and all his friends.<br>
See then, thou fight’st against thy countrymen,<br>
And join’st with them will be thy slaughtermen.<br>
Come, come, return; return, thou wandering lord;<br>
Charles and the rest will take thee in their arms.
</p>

<p class="drama">
BURGUNDY.<br>
I am vanquished; these haughty words of hers<br>
Have batter’d me like roaring cannon-shot,<br>
And made me almost yield upon my knees.<br>
Forgive me, country, and sweet countrymen!<br>
And, lords, accept this hearty kind embrace.<br>
My forces and my power of men are yours.<br>
So, farewell, Talbot; I’ll no longer trust thee.
</p>

<p class="drama">
PUCELLE.<br>
[<i>Aside</i>.] Done like a Frenchman: turn and turn again.
</p>

<p class="drama">
CHARLES.<br>
Welcome, brave Duke! Thy friendship makes us fresh.
</p>

<p class="drama">
BASTARD.<br>
And doth beget new courage in our breasts.
</p>

<p class="drama">
ALENÇON.<br>
Pucelle hath bravely play’d her part in this,<br>
And doth deserve a coronet of gold.
</p>

<p class="drama">
CHARLES.<br>
Now let us on, my lords, and join our powers,<br>
And seek how we may prejudice the foe.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneIII_12.4"></a><b>SCENE IV. Paris. The Palace.</b></h3>

<p class="scenedesc">Enter the <span class="charname">King, Gloucester, Bishop
of Winchester, Exeter, York, Warwick</span> and <span class="charname">Vernon;
Suffolk, Somerset, Basset</span> and others. To them, with his soldiers, <span class="charname">Talbot</span>.</p>

<p class="drama">
TALBOT.<br>
My gracious Prince, and honourable peers,<br>
Hearing of your arrival in this realm,<br>
I have awhile given truce unto my wars<br>
To do my duty to my sovereign;<br>
In sign whereof, this arm, that hath reclaim’d<br>
To your obedience fifty fortresses,<br>
Twelve cities and seven walled towns of strength,<br>
Beside five hundred prisoners of esteem,<br>
Lets fall his sword before your Highness’ feet,<br>
And with submissive loyalty of heart<br>
Ascribes the glory of his conquest got<br>
First to my God, and next unto your Grace. [<i>Kneels</i>.]
</p>

<p class="drama">
KING HENRY.<br>
Is this the Lord Talbot, uncle Gloucester,<br>
That hath so long been resident in France?
</p>

<p class="drama">
GLOUCESTER.<br>
Yes, if it please your Majesty, my liege.
</p>

<p class="drama">
KING HENRY.<br>
Welcome, brave captain and victorious lord!<br>
When I was young, as yet I am not old,<br>
I do remember how my father said<br>
A stouter champion never handled sword.<br>
Long since we were resolved of your truth,<br>
Your faithful service, and your toil in war;<br>
Yet never have you tasted our reward,<br>
Or been reguerdon’d with so much as thanks.<br>
Because till now we never saw your face.<br>
Therefore, stand up; and for these good deserts<br>
We here create you Earl of Shrewsbury;<br>
And in our coronation take your place.
</p>

<p class="right">[<i>Sennet. Flourish. Exeunt all but <span class="charname">Vernon</span> and
<span class="charname">Basset</span>.</i>]</p>

<p class="drama">
VERNON.<br>
Now, sir, to you that were so hot at sea,<br>
Disgracing of these colours that I wear<br>
In honour of my noble Lord of York,<br>
Dar’st thou maintain the former words thou spak’st?
</p>

<p class="drama">
BASSET.<br>
Yes, sir, as well as you dare patronage<br>
The envious barking of your saucy tongue<br>
Against my lord the Duke of Somerset.
</p>

<p class="drama">
VERNON.<br>
Sirrah, thy lord I honour as he is.
</p>

<p class="drama">
BASSET.<br>
Why, what is he? As good a man as York.
</p>

<p class="drama">
VERNON.<br>
Hark ye; not so: in witness, take ye that.
</p>

<p class="right">[<i>Strikes him.</i>]</p>

<p class="drama">
BASSET.<br>
Villain, thou knowest the law of arms is such<br>
That whoso draws a sword, ’tis present death,<br>
Or else this blow should broach thy dearest blood.<br>
But I’ll unto his Majesty, and crave<br>
I may have liberty to venge this wrong;<br>
When thou shalt see I’ll meet thee to thy cost.
</p>

<p class="drama">
VERNON.<br>
Well, miscreant, I’ll be there as soon as you;<br>
And, after, meet you sooner than you would.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

