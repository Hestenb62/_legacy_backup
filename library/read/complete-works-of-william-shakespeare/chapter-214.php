<h2> <a id="sceneIV_34.1"></a><b>ACT IV</b></h2>

<h3> <b>SCENE I. Rome. Before Titus’s House</b></h3>

<p class="scenedesc">
Enter <span class="charname">Young Lucius</span> and <span class="charname">Lavinia</span> running after him, and the boy flies from her
with his books under his arm. Enter <span class="charname">Titus</span> and
<span class="charname">Marcus</span>.
</p>

<p class="drama">
YOUNG LUCIUS.<br>
Help, grandsire, help! My aunt Lavinia<br>
Follows me everywhere, I know not why.<br>
Good uncle Marcus, see how swift she comes!<br>
Alas, sweet aunt, I know not what you mean.
</p>

<p class="drama">
MARCUS.<br>
Stand by me, Lucius. Do not fear thine aunt.
</p>

<p class="drama">
TITUS.<br>
She loves thee, boy, too well to do thee harm.
</p>

<p class="drama">
YOUNG LUCIUS<br>
Ay, when my father was in Rome she did.
</p>

<p class="drama">
MARCUS.<br>
What means my niece Lavinia by these signs?
</p>

<p class="drama">
TITUS.<br>
Fear her not, Lucius. Somewhat doth she mean.<br>
See, Lucius, see how much she makes of thee.<br>
Somewhither would she have thee go with her.<br>
Ah, boy, Cornelia never with more care<br>
Read to her sons than she hath read to thee<br>
Sweet poetry and Tully’s <i>Orator</i>.
</p>

<p class="drama">
MARCUS.<br>
Canst thou not guess wherefore she plies thee thus?
</p>

<p class="drama">
YOUNG LUCIUS.<br>
My lord, I know not, I, nor can I guess,<br>
Unless some fit or frenzy do possess her;<br>
For I have heard my grandsire say full oft,<br>
Extremity of griefs would make men mad;<br>
And I have read that Hecuba of Troy<br>
Ran mad for sorrow. That made me to fear,<br>
Although, my lord, I know my noble aunt<br>
Loves me as dear as e’er my mother did,<br>
And would not, but in fury, fright my youth;<br>
Which made me down to throw my books, and fly,<br>
Causeless, perhaps. But pardon me, sweet aunt.<br>
And, madam, if my uncle Marcus go,<br>
I will most willingly attend your ladyship.
</p>

<p class="drama">
MARCUS.<br>
Lucius, I will.
</p>

<p class="right">[<i><span class="charname">Lavinia</span> turns over with her
stumps the books which Lucius has let fall.</i>]</p>

<p class="drama">
TITUS.<br>
How now, Lavinia? Marcus, what means this?<br>
Some book there is that she desires to see.<br>
Which is it, girl, of these? Open them, boy.<br>
But thou art deeper read and better skilled.<br>
Come and take choice of all my library,<br>
And so beguile thy sorrow, till the heavens<br>
Reveal the damned contriver of this deed.<br>
Why lifts she up her arms in sequence thus?
</p>

<p class="drama">
MARCUS.<br>
I think she means that there were more than one<br>
Confederate in the fact. Ay, more there was,<br>
Or else to heaven she heaves them for revenge.
</p>

<p class="drama">
TITUS.<br>
Lucius, what book is that she tosseth so?
</p>

<p class="drama">
YOUNG LUCIUS.<br>
Grandsire, ’tis Ovid’s <i>Metamorphosis</i>.<br>
My mother gave it me.
</p>

<p class="drama">
MARCUS.<br>
For love of her that’s gone,<br>
Perhaps, she culled it from among the rest.
</p>

<p class="drama">
TITUS.<br>
Soft! So busily she turns the leaves!<br>
Help her! What would she find? Lavinia, shall I read?<br>
This is the tragic tale of Philomel,<br>
And treats of Tereus’ treason and his rape;<br>
And rape, I fear, was root of thy annoy.
</p>

<p class="drama">
MARCUS.<br>
See, brother, see! Note how she quotes the leaves.
</p>

<p class="drama">
TITUS.<br>
Lavinia, wert thou thus surprised, sweet girl,<br>
Ravished and wronged, as Philomela was,<br>
Forced in the ruthless, vast, and gloomy woods?<br>
See, see!<br>
Ay, such a place there is where we did hunt,—<br>
O, had we never, never hunted there!—<br>
Patterned by that the poet here describes,<br>
By nature made for murders and for rapes.
</p>

<p class="drama">
MARCUS.<br>
O, why should nature build so foul a den,<br>
Unless the gods delight in tragedies?
</p>

<p class="drama">
TITUS.<br>
Give signs, sweet girl, for here are none but friends,<br>
What Roman lord it was durst do the deed.<br>
Or slunk not Saturnine, as Tarquin erst,<br>
That left the camp to sin in Lucrece’ bed?
</p>

<p class="drama">
MARCUS.<br>
Sit down, sweet niece. Brother, sit down by me.<br>
Apollo, Pallas, Jove, or Mercury,<br>
Inspire me, that I may this treason find!<br>
My lord, look here. Look here, Lavinia.<br>
This sandy plot is plain; guide, if thou canst,<br>
This after me. I have writ my name
</p>

<p class="right">[<i>He writes his name with his staff and guides it with feet
and mouth.</i>]</p>

<p class="drama">
Without the help of any hand at all.<br>
Cursed be that heart that forced us to this shift!<br>
Write thou, good niece, and here display at last<br>
What God will have discovered for revenge.<br>
Heaven guide thy pen to print thy sorrows plain,<br>
That we may know the traitors and the truth!
</p>

<p class="right">[<i>She takes the staff in her mouth, and guides it with her
stumps and writes.</i>]</p>

<p class="drama">
O, do ye read, my lord, what she hath writ?
</p>

<p class="drama">
TITUS.<br>
“<i>Stuprum</i>. Chiron. Demetrius.”
</p>

<p class="drama">
MARCUS.<br>
What, what! The lustful sons of Tamora<br>
Performers of this heinous bloody deed?
</p>

<p class="drama">
TITUS.<br>
<i>Magni Dominator poli,<br>
Tam lentus audis scelera, tam lentus vides?</i>
</p>

<p class="drama">
MARCUS.<br>
O, calm thee, gentle lord, although I know<br>
There is enough written upon this earth<br>
To stir a mutiny in the mildest thoughts<br>
And arm the minds of infants to exclaims.<br>
My lord, kneel down with me; Lavinia, kneel;<br>
And kneel, sweet boy, the Roman Hector’s hope;<br>
And swear with me, as, with the woeful fere<br>
And father of that chaste dishonoured dame,<br>
Lord Junius Brutus sware for Lucrece’ rape,<br>
That we will prosecute, by good advice<br>
Mortal revenge upon these traitorous Goths,<br>
And see their blood, or die with this reproach.
</p>

<p class="drama">
TITUS.<br>
’Tis sure enough, an you knew how.<br>
But if you hunt these bear-whelps, then beware;<br>
The dam will wake, and if she wind you once.<br>
She’s with the lion deeply still in league,<br>
And lulls him whilst she playeth on her back,<br>
And when he sleeps will she do what she list.<br>
You are a young huntsman, Marcus; let alone;<br>
And come, I will go get a leaf of brass,<br>
And with a gad of steel will write these words,<br>
And lay it by. The angry northern wind<br>
Will blow these sands like Sibyl’s leaves abroad,<br>
And where’s our lesson, then? Boy, what say you?
</p>

<p class="drama">
YOUNG LUCIUS.<br>
I say, my lord, that if I were a man,<br>
Their mother’s bedchamber should not be safe<br>
For these base bondmen to the yoke of Rome.
</p>

<p class="drama">
MARCUS.<br>
Ay, that’s my boy! Thy father hath full oft<br>
For his ungrateful country done the like.
</p>

<p class="drama">
YOUNG LUCIUS.<br>
And, uncle, so will I, an if I live.
</p>

<p class="drama">
TITUS.<br>
Come, go with me into mine armoury.<br>
Lucius, I’ll fit thee; and withal, my boy,<br>
Shall carry from me to the empress’ sons<br>
Presents that I intend to send them both.<br>
Come, come; thou’lt do my message, wilt thou not?
</p>

<p class="drama">
YOUNG LUCIUS.<br>
Ay, with my dagger in their bosoms, grandsire.
</p>

<p class="drama">
TITUS.<br>
No, boy, not so. I’ll teach thee another course.<br>
Lavinia, come. Marcus, look to my house.<br>
Lucius and I’ll go brave it at the court;<br>
Ay, marry, will we, sir; and we’ll be waited on.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Titus, Lavinia</span> and
<span class="charname">Young Lucius</span>.</i>]
</p>

<p class="drama">
MARCUS.<br>
O heavens, can you hear a good man groan<br>
And not relent, or not compassion him?<br>
Marcus, attend him in his ecstasy,<br>
That hath more scars of sorrow in his heart<br>
Than foemen’s marks upon his battered shield,<br>
But yet so just that he will not revenge.<br>
Revenge ye heavens for old Andronicus!
</p>

<p class="right">[<i>Exit.</i>]</p>

<h3> <a id="sceneIV_34.2"></a><b>SCENE II. Rome. A Room in the Palace</b></h3>

<p class="scenedesc">
Enter <span class="charname">Aaron, Chiron</span> and <span class="charname">Demetrius</span> at one door, and at the other door <span class="charname">Young Lucius</span> and another, with a bundle of
weapons and verses writ upon them.
</p>

<p class="drama">
CHIRON.<br>
Demetrius, here’s the son of Lucius;<br>
He hath some message to deliver us.
</p>

<p class="drama">
AARON.<br>
Ay, some mad message from his mad grandfather.
</p>

<p class="drama">
YOUNG LUCIUS.<br>
My lords, with all the humbleness I may,<br>
I greet your honours from Andronicus;<br>
[<i>Aside</i>.] And pray the Roman gods confound you both.
</p>

<p class="drama">
DEMETRIUS.<br>
Gramercy, lovely Lucius. What’s the news?
</p>

<p class="drama">
YOUNG LUCIUS.<br>
[<i>Aside</i>.] That you are both deciphered, that’s the news,<br>
For villains marked with rape. [<i>Aloud</i>.] May it please you,<br>
My grandsire, well advised, hath sent by me<br>
The goodliest weapons of his armoury<br>
To gratify your honourable youth,<br>
The hope of Rome; for so he bid me say;<br>
And so I do, and with his gifts present<br>
Your lordships, that, whenever you have need,<br>
You may be armed and appointed well.<br>
And so I leave you both, [<i>Aside</i>.] like bloody villains.
</p>

<p class="right">[<i>Exeunt <span class="charname">Young Lucius</span> and Attendant.</i>]</p>

<p class="drama">
DEMETRIUS.<br>
What’s here? A scroll; and written round about?<br>
Let’s see:<br>
[<i>Reads</i>.] <i>Integer vitae, scelerisque purus,<br>
Non eget Mauri iaculis, nec arcu.</i>
</p>

<p class="drama">
CHIRON.<br>
O, ’tis a verse in Horace; I know it well.<br>
I read it in the grammar long ago.
</p>

<p class="drama">
AARON.<br>
Ay, just; a verse in Horace; right, you have it.<br>
[<i>Aside</i>.] Now, what a thing it is to be an ass!<br>
Here’s no sound jest! The old man hath found their guilt,<br>
And sends them weapons wrapped about with lines,<br>
That wound, beyond their feeling, to the quick.<br>
But were our witty empress well afoot,<br>
She would applaud Andronicus’ conceit.<br>
But let her rest in her unrest awhile.—<br>
And now, young lords, was’t not a happy star<br>
Led us to Rome, strangers, and more than so,<br>
Captives, to be advanced to this height?<br>
It did me good before the palace gate<br>
To brave the tribune in his brother’s hearing.
</p>

<p class="drama">
DEMETRIUS.<br>
But me more good to see so great a lord<br>
Basely insinuate and send us gifts.
</p>

<p class="drama">
AARON.<br>
Had he not reason, Lord Demetrius?<br>
Did you not use his daughter very friendly?
</p>

<p class="drama">
DEMETRIUS.<br>
I would we had a thousand Roman dames<br>
At such a bay, by turn to serve our lust.
</p>

<p class="drama">
CHIRON.<br>
A charitable wish, and full of love.
</p>

<p class="drama">
AARON.<br>
Here lacks but your mother for to say amen.
</p>

<p class="drama">
CHIRON.<br>
And that would she for twenty thousand more.
</p>

<p class="drama">
DEMETRIUS.<br>
Come, let us go and pray to all the gods<br>
For our beloved mother in her pains.
</p>

<p class="drama">
AARON.<br>
[<i>Aside</i>.] Pray to the devils; the gods have given us over.
</p>

<p class="right">[<i>Trumpets sound.</i>]</p>

<p class="drama">
DEMETRIUS.<br>
Why do the emperor’s trumpets flourish thus?
</p>

<p class="drama">
CHIRON.<br>
Belike for joy the emperor hath a son.
</p>

<p class="drama">
DEMETRIUS.<br>
Soft, who comes here?
</p>

<p class="scenedesc">
Enter <span class="charname">Nurse</span> with a blackamoor
<span class="charname">Child</span> in her arms.
</p>

<p class="drama">
NURSE.<br>
Good morrow, lords.<br>
O, tell me, did you see Aaron the Moor?
</p>

<p class="drama">
AARON.<br>
Well, more or less, or ne’er a whit at all,<br>
Here Aaron is; and what with Aaron now?
</p>

<p class="drama">
NURSE.<br>
O gentle Aaron, we are all undone!<br>
Now help, or woe betide thee evermore!
</p>

<p class="drama">
AARON.<br>
Why, what a caterwauling dost thou keep!<br>
What dost thou wrap and fumble in thy arms?
</p>

<p class="drama">
NURSE.<br>
O, that which I would hide from heaven’s eye,<br>
Our empress’ shame and stately Rome’s disgrace.<br>
She is delivered, lords, she is delivered.
</p>

<p class="drama">
AARON.<br>
To whom?
</p>

<p class="drama">
NURSE.<br>
I mean, she’s brought a-bed.
</p>

<p class="drama">
AARON.<br>
Well, God give her good rest! What hath he sent her?
</p>

<p class="drama">
NURSE.<br>
A devil.
</p>

<p class="drama">
AARON.<br>
Why, then she is the devil’s dam. A joyful issue.
</p>

<p class="drama">
NURSE.<br>
A joyless, dismal, black, and sorrowful issue.<br>
Here is the babe, as loathsome as a toad<br>
Amongst the fair-faced breeders of our clime.<br>
The empress sends it thee, thy stamp, thy seal,<br>
And bids thee christen it with thy dagger’s point.
</p>

<p class="drama">
AARON.<br>
Zounds, ye whore, is black so base a hue?<br>
Sweet blowse, you are a beauteous blossom sure.
</p>

<p class="drama">
DEMETRIUS.<br>
Villain, what hast thou done?
</p>

<p class="drama">
AARON.<br>
That which thou canst not undo.
</p>

<p class="drama">
CHIRON.<br>
Thou hast undone our mother.
</p>

<p class="drama">
AARON.<br>
Villain, I have done thy mother.
</p>

<p class="drama">
DEMETRIUS.<br>
And therein, hellish dog, thou hast undone her.<br>
Woe to her chance, and damned her loathed choice!<br>
Accursed the offspring of so foul a fiend!
</p>

<p class="drama">
CHIRON.<br>
It shall not live.
</p>

<p class="drama">
AARON.<br>
It shall not die.
</p>

<p class="drama">
NURSE.<br>
Aaron, it must; the mother wills it so.
</p>

<p class="drama">
AARON.<br>
What, must it, nurse? Then let no man but I<br>
Do execution on my flesh and blood.
</p>

<p class="drama">
DEMETRIUS.<br>
I’ll broach the tadpole on my rapier’s point.<br>
Nurse, give it me; my sword shall soon dispatch it.
</p>

<p class="drama">
AARON.<br>
Sooner this sword shall plough thy bowels up.
</p>

<p class="right">
[<i>Taking the baby.</i>]
</p>

<p class="drama">
Stay, murderous villains, will you kill your brother?<br>
Now, by the burning tapers of the sky<br>
That shone so brightly when this boy was got,<br>
He dies upon my scimitar’s sharp point<br>
That touches this my first-born son and heir.<br>
I tell you, younglings, not Enceladus,<br>
With all his threatening band of Typhon’s brood,<br>
Nor great Alcides, nor the god of war,<br>
Shall seize this prey out of his father’s hands.<br>
What, what, ye sanguine, shallow-hearted boys!<br>
Ye white-limed walls, ye alehouse-painted signs!<br>
Coal-black is better than another hue<br>
In that it scorns to bear another hue;<br>
For all the water in the ocean<br>
Can never turn the swan’s black legs to white,<br>
Although she lave them hourly in the flood.<br>
Tell the empress from me, I am of age<br>
To keep mine own, excuse it how she can.
</p>

<p class="drama">
DEMETRIUS.<br>
Wilt thou betray thy noble mistress thus?
</p>

<p class="drama">
AARON.<br>
My mistress is my mistress; this my self;<br>
The vigour and the picture of my youth.<br>
This before all the world do I prefer;<br>
This maugre all the world will I keep safe,<br>
Or some of you shall smoke for it in Rome.
</p>

<p class="drama">
DEMETRIUS.<br>
By this our mother is for ever shamed.
</p>

<p class="drama">
CHIRON.<br>
Rome will despise her for this foul escape.
</p>

<p class="drama">
NURSE.<br>
The emperor in his rage will doom her death.
</p>

<p class="drama">
CHIRON.<br>
I blush to think upon this ignomy.
</p>

<p class="drama">
AARON.<br>
Why, there’s the privilege your beauty bears.<br>
Fie, treacherous hue, that will betray with blushing<br>
The close enacts and counsels of thy heart!<br>
Here’s a young lad framed of another leer.<br>
Look how the black slave smiles upon the father,<br>
As who should say “Old lad, I am thine own.”<br>
He is your brother, lords, sensibly fed<br>
Of that self blood that first gave life to you;<br>
And from your womb where you imprisoned were<br>
He is enfranchised and come to light.<br>
Nay, he is your brother by the surer side,<br>
Although my seal be stamped in his face.
</p>

<p class="drama">
NURSE.<br>
Aaron, what shall I say unto the empress?
</p>

<p class="drama">
DEMETRIUS.<br>
Advise thee, Aaron, what is to be done,<br>
And we will all subscribe to thy advice.<br>
Save thou the child, so we may all be safe.
</p>

<p class="drama">
AARON.<br>
Then sit we down, and let us all consult.<br>
My son and I will have the wind of you.<br>
Keep there. Now talk at pleasure of your safety.
</p>

<p class="right">[<i>They sit.</i>]</p>

<p class="drama">
DEMETRIUS.<br>
How many women saw this child of his?
</p>

<p class="drama">
AARON.<br>
Why, so, brave lords! When we join in league,<br>
I am a lamb; but if you brave the Moor,<br>
The chafed boar, the mountain lioness,<br>
The ocean swells not so as Aaron storms.<br>
But say again, how many saw the child?
</p>

<p class="drama">
NURSE.<br>
Cornelia the midwife and myself,<br>
And no one else but the delivered empress.
</p>

<p class="drama">
AARON.<br>
The empress, the midwife, and yourself.<br>
Two may keep counsel when the third’s away.<br>
Go to the empress; tell her this I said.
</p>

<p class="right">[<i>He kills her.</i>]</p>

<p class="drama">
“Wheak, wheak!” So cries a pig prepared to the spit.
</p>

<p class="drama">
DEMETRIUS.<br>
What mean’st thou, Aaron? Wherefore didst thou this?
</p>

<p class="drama">
AARON.<br>
O Lord, sir, ’tis a deed of policy.<br>
Shall she live to betray this guilt of ours,<br>
A long-tongued babbling gossip? No, lords, no.<br>
And now be it known to you my full intent.<br>
Not far, one Muliteus lives, my countryman;<br>
His wife but yesternight was brought to bed.<br>
His child is like to her, fair as you are.<br>
Go pack with him, and give the mother gold,<br>
And tell them both the circumstance of all,<br>
And how by this their child shall be advanced,<br>
And be received for the emperor’s heir,<br>
And substituted in the place of mine,<br>
To calm this tempest whirling in the court;<br>
And let the emperor dandle him for his own.<br>
Hark ye, lords; ye see I have given her physic,
</p>

<p class="right">[<i>Indicating the <span class="charname">Nurse</span>.</i>]</p>

<p class="drama">
And you must needs bestow her funeral;<br>
The fields are near, and you are gallant grooms.<br>
This done, see that you take no longer days,<br>
But send the midwife presently to me.<br>
The midwife and the nurse well made away,<br>
Then let the ladies tattle what they please.
</p>

<p class="drama">
CHIRON.<br>
Aaron, I see thou wilt not trust the air<br>
With secrets.
</p>

<p class="drama">
DEMETRIUS.<br>
For this care of Tamora,<br>
Herself and hers are highly bound to thee.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Demetrius</span> and
<span class="charname">Chiron,</span> carrying the
<span class="charname">Nurse’s</span> body.</i>]
</p>

<p class="drama">
AARON.<br>
Now to the Goths, as swift as swallow flies,<br>
There to dispose this treasure in mine arms,<br>
And secretly to greet the empress’ friends.<br>
Come on, you thick-lipped slave, I’ll bear you hence;<br>
For it is you that puts us to our shifts.<br>
I’ll make you feed on berries and on roots,<br>
And feed on curds and whey, and suck the goat,<br>
And cabin in a cave, and bring you up<br>
To be a warrior and command a camp.
</p>

<p class="right">[<i>Exit.</i>]</p>

<h3> <a id="sceneIV_34.3"></a><b>SCENE III. Rome. A public Place</b></h3>

<p class="scenedesc">
Enter <span class="charname">Titus,</span> old <span class="charname">Marcus,</span> his son <span class="charname">Publius, Young
Lucius,</span> and other gentlemen with bows, and <span class="charname">Titus</span> bears the arrows with letters on the ends of
them.
</p>

<p class="drama">
TITUS.<br>
Come, Marcus, come. Kinsmen, this is the way.<br>
Sir boy, let me see your archery.<br>
Look ye draw home enough, and ’tis there straight.<br>
<i>Terras Astraea reliquit.</i><br>
Be you remembered, Marcus, she’s gone, she’s fled.<br>
Sirs, take you to your tools. You, cousins, shall<br>
Go sound the ocean and cast your nets;<br>
Happily you may catch her in the sea;<br>
Yet there’s as little justice as at land.<br>
No; Publius and Sempronius, you must do it;<br>
’Tis you must dig with mattock and with spade,<br>
And pierce the inmost centre of the earth.<br>
Then, when you come to Pluto’s region,<br>
I pray you, deliver him this petition;<br>
Tell him it is for justice and for aid,<br>
And that it comes from old Andronicus,<br>
Shaken with sorrows in ungrateful Rome.<br>
Ah, Rome! Well, well, I made thee miserable<br>
What time I threw the people’s suffrages<br>
On him that thus doth tyrannize o’er me.<br>
Go, get you gone; and pray be careful all,<br>
And leave you not a man-of-war unsearched.<br>
This wicked emperor may have shipped her hence;<br>
And, kinsmen, then we may go pipe for justice.
</p>

<p class="drama">
MARCUS.<br>
O Publius, is not this a heavy case,<br>
To see thy noble uncle thus distract?
</p>

<p class="drama">
PUBLIUS.<br>
Therefore, my lords, it highly us concerns<br>
By day and night to attend him carefully,<br>
And feed his humour kindly as we may,<br>
Till time beget some careful remedy.
</p>

<p class="drama">
MARCUS.<br>
Kinsmen, his sorrows are past remedy,<br>
But . . . . <br>
Join with the Goths, and with revengeful war<br>
Take wreak on Rome for this ingratitude,<br>
And vengeance on the traitor Saturnine.
</p>

<p class="drama">
TITUS.<br>
Publius, how now? How now, my masters?<br>
What, have you met with her?
</p>

<p class="drama">
PUBLIUS.<br>
No, my good lord; but Pluto sends you word,<br>
If you will have Revenge from hell, you shall.<br>
Marry, for Justice, she is so employed,<br>
He thinks, with Jove in heaven, or somewhere else,<br>
So that perforce you must needs stay a time.
</p>

<p class="drama">
TITUS.<br>
He doth me wrong to feed me with delays.<br>
I’ll dive into the burning lake below,<br>
And pull her out of Acheron by the heels.<br>
Marcus, we are but shrubs, no cedars we,<br>
No big-boned men framed of the Cyclops’ size;<br>
But metal, Marcus, steel to the very back,<br>
Yet wrung with wrongs more than our backs can bear;<br>
And sith there’s no justice in earth nor hell,<br>
We will solicit heaven and move the gods<br>
To send down Justice for to wreak our wrongs.<br>
Come, to this gear. You are a good archer, Marcus.
</p>

<p class="right">[<i>He gives them the arrows.</i>]</p>

<p class="drama">
“<i>Ad Jovem,</i>” that’s for you; here, “<i>Ad Apollinem</i>”;<br>
“<i>Ad Martem,</i>” that’s for myself;<br>
Here, boy, “to Pallas”; here, “to Mercury”;<br>
“To Saturn,” Caius, not to Saturnine;<br>
You were as good to shoot against the wind.<br>
To it, boy.—Marcus, loose when I bid.—<br>
Of my word, I have written to effect;<br>
There’s not a god left unsolicited.
</p>

<p class="drama">
MARCUS.<br>
Kinsmen, shoot all your shafts into the court.<br>
We will afflict the emperor in his pride.
</p>

<p class="drama">
TITUS.<br>
Now, masters, draw. [<i>They shoot</i>.] O, well said, Lucius!<br>
Good boy, in Virgo’s lap! Give it Pallas.
</p>

<p class="drama">
MARCUS.<br>
My lord, I aim a mile beyond the moon.<br>
Your letter is with Jupiter by this.
</p>

<p class="drama">
TITUS.<br>
Ha! ha! Publius, Publius, what hast thou done?<br>
See, see, thou hast shot off one of Taurus’ horns.
</p>

<p class="drama">
MARCUS.<br>
This was the sport, my lord; when Publius shot,<br>
The Bull, being galled, gave Aries such a knock<br>
That down fell both the Ram’s horns in the court;<br>
And who should find them but the empress’ villain?<br>
She laughed, and told the Moor he should not choose<br>
But give them to his master for a present.
</p>

<p class="drama">
TITUS.<br>
Why, there it goes. God give his lordship joy!
</p>

<p class="scenedesc">
Enter the <span class="charname">Clown</span> with a basket and two pigeons in it.
</p>

<p class="drama">
News, news from heaven! Marcus, the post is come.<br>
Sirrah, what tidings? Have you any letters?<br>
Shall I have justice? What says Jupiter?
</p>

<p class="drama">
CLOWN.<br>
Ho, the gibbet-maker? He says that he hath taken them down again, for the man
must not be hanged till the next week.
</p>

<p class="drama">
TITUS.<br>
But what says Jupiter, I ask thee?
</p>

<p class="drama">
CLOWN.<br>
Alas, sir, I know not Jubiter; I never drank with him in all my life.
</p>

<p class="drama">
TITUS.<br>
Why, villain, art not thou the carrier?
</p>

<p class="drama">
CLOWN.<br>
Ay, of my pigeons, sir; nothing else.
</p>

<p class="drama">
TITUS.<br>
Why, didst thou not come from heaven?
</p>

<p class="drama">
CLOWN.<br>
From heaven? Alas, sir, I never came there. God forbid I should be so bold to
press to heaven in my young days. Why, I am going with my pigeons to the
tribunal plebs, to take up a matter of brawl betwixt my uncle and one of the
emperal’s men.
</p>

<p class="drama">
MARCUS.<br>
Why, sir, that is as fit as can be to serve for your oration; and let him
deliver the pigeons to the emperor from you.
</p>

<p class="drama">
TITUS.<br>
Tell me, can you deliver an oration to the emperor with a grace?
</p>

<p class="drama">
CLOWN.<br>
Nay, truly, sir, I could never say grace in all my life.
</p>

<p class="drama">
TITUS.<br>
Sirrah, come hither. Make no more ado,<br>
But give your pigeons to the emperor.<br>
By me thou shalt have justice at his hands.<br>
Hold, hold; meanwhile here’s money for thy charges.<br>
Give me pen and ink.<br>
Sirrah, can you with a grace deliver up a supplication?
</p>

<p class="drama">
CLOWN.<br>
Ay, sir.
</p>

<p class="drama">
TITUS.<br>
Then here is a supplication for you. And when you come to him, at the first
approach you must kneel; then kiss his foot; then deliver up your pigeons; and
then look for your reward. I’ll be at hand, sir; see you do it bravely.
</p>

<p class="drama">
CLOWN.<br>
I warrant you, sir; let me alone.
</p>

<p class="drama">
TITUS.<br>
Sirrah, hast thou a knife? Come let me see it.<br>
Here, Marcus, fold it in the oration;<br>
For thou hast made it like a humble suppliant.<br>
And when thou hast given it to the emperor,<br>
Knock at my door, and tell me what he says.
</p>

<p class="drama">
CLOWN.<br>
God be with you, sir; I will.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
TITUS.<br>
Come, Marcus, let us go. Publius, follow me.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneIV_34.4"></a><b>SCENE IV. Rome. Before the Palace</b></h3>

<p class="scenedesc">
Enter Emperor <span class="charname">Saturninus</span> and Empress <span class="charname">Tamora</span> and her two sons <span class="charname">Chiron</span> and <span class="charname">Demetrius,</span>
with Attendants. The Emperor brings the arrows in his hand that <span class="charname">Titus</span> shot at him.
</p>

<p class="drama">
SATURNINUS.<br>
Why, lords, what wrongs are these! Was ever seen<br>
An emperor in Rome thus overborne,<br>
Troubled, confronted thus; and, for the extent<br>
Of legal justice, used in such contempt?<br>
My lords, you know, as know the mightful gods,<br>
However these disturbers of our peace<br>
Buzz in the people’s ears, there naught hath passed<br>
But even with law against the wilful sons<br>
Of old Andronicus. And what an if<br>
His sorrows have so overwhelmed his wits?<br>
Shall we be thus afflicted in his wreaks,<br>
His fits, his frenzy, and his bitterness?<br>
And now he writes to heaven for his redress!<br>
See, here’s “to Jove,” and this “to Mercury,”<br>
This “to Apollo,” this to the god of war.<br>
Sweet scrolls to fly about the streets of Rome!<br>
What’s this but libelling against the senate,<br>
And blazoning our injustice everywhere?<br>
A goodly humour, is it not, my lords?<br>
As who would say, in Rome no justice were.<br>
But if I live, his feigned ecstasies<br>
Shall be no shelter to these outrages;<br>
But he and his shall know that justice lives<br>
In Saturninus’ health; whom, if she sleep,<br>
He’ll so awake as he in fury shall<br>
Cut off the proud’st conspirator that lives.
</p>

<p class="drama">
TAMORA.<br>
My gracious lord, my lovely Saturnine,<br>
Lord of my life, commander of my thoughts,<br>
Calm thee, and bear the faults of Titus’ age,<br>
Th’ effects of sorrow for his valiant sons,<br>
Whose loss hath pierced him deep and scarred his heart;<br>
And rather comfort his distressed plight<br>
Than prosecute the meanest or the best<br>
For these contempts. [<i>Aside</i>.] Why, thus it shall become<br>
High-witted Tamora to gloze with all.<br>
But, Titus, I have touched thee to the quick;<br>
Thy life-blood out, if Aaron now be wise,<br>
Then is all safe, the anchor in the port.
</p>

<p class="scenedesc">
Enter <span class="charname">Clown</span>.
</p>

<p class="drama">
How now, good fellow, wouldst thou speak with us?
</p>

<p class="drama">
CLOWN.<br>
Yes, forsooth, an your mistresship be emperial.
</p>

<p class="drama">
TAMORA.<br>
Empress I am, but yonder sits the emperor.
</p>

<p class="drama">
CLOWN.<br>
’Tis he. God and Saint Stephen give you good e’en. I have brought you a letter
and a couple of pigeons here.
</p>

<p class="right">[<i><span class="charname">Saturninus</span> reads the letter.</i>]</p>

<p class="drama">
SATURNINUS.<br>
Go take him away, and hang him presently.
</p>

<p class="drama">
CLOWN.<br>
How much money must I have?
</p>

<p class="drama">
TAMORA.<br>
Come, sirrah, you must be hanged.
</p>

<p class="drama">
CLOWN.<br>
Hanged! by’r Lady, then I have brought up a neck to a fair end.
</p>

<p class="right">[<i>Exit guarded.</i>]</p>

<p class="drama">
SATURNINUS.<br>
Despiteful and intolerable wrongs!<br>
Shall I endure this monstrous villainy?<br>
I know from whence this same device proceeds.<br>
May this be borne as if his traitorous sons,<br>
That died by law for murder of our brother,<br>
Have by my means been butchered wrongfully?<br>
Go, drag the villain hither by the hair;<br>
Nor age nor honour shall shape privilege.<br>
For this proud mock I’ll be thy slaughterman,<br>
Sly frantic wretch, that holp’st to make me great,<br>
In hope thyself should govern Rome and me.
</p>

<p class="scenedesc">
Enter <span class="charname">Aemilius</span>.
</p>

<p class="drama">
What news with thee, Aemilius?
</p>

<p class="drama">
AEMILIUS.<br>
Arm, my lord! Rome never had more cause.<br>
The Goths have gathered head, and with a power<br>
Of high-resolved men, bent to the spoil,<br>
They hither march amain, under conduct<br>
Of Lucius, son to old Andronicus;<br>
Who threats, in course of this revenge, to do<br>
As much as ever Coriolanus did.
</p>

<p class="drama">
SATURNINUS.<br>
Is warlike Lucius general of the Goths?<br>
These tidings nip me, and I hang the head<br>
As flowers with frost, or grass beat down with storms.<br>
Ay, now begins our sorrows to approach.<br>
’Tis he the common people love so much;<br>
Myself hath often overheard them say,<br>
When I have walked like a private man,<br>
That Lucius’ banishment was wrongfully,<br>
And they have wished that Lucius were their emperor.
</p>

<p class="drama">
TAMORA.<br>
Why should you fear? Is not your city strong?
</p>

<p class="drama">
SATURNINUS.<br>
Ay, but the citizens favour Lucius,<br>
And will revolt from me to succour him.
</p>

<p class="drama">
TAMORA.<br>
King, be thy thoughts imperious like thy name.<br>
Is the sun dimmed, that gnats do fly in it?<br>
The eagle suffers little birds to sing,<br>
And is not careful what they mean thereby,<br>
Knowing that with the shadow of his wings<br>
He can at pleasure stint their melody;<br>
Even so mayest thou the giddy men of Rome.<br>
Then cheer thy spirit; for know, thou emperor,<br>
I will enchant the old Andronicus<br>
With words more sweet, and yet more dangerous,<br>
Than baits to fish or honey-stalks to sheep,<br>
Whenas the one is wounded with the bait,<br>
The other rotted with delicious feed.
</p>

<p class="drama">
SATURNINUS.<br>
But he will not entreat his son for us.
</p>

<p class="drama">
TAMORA.<br>
If Tamora entreat him, then he will,<br>
For I can smooth and fill his aged ears<br>
With golden promises, that, were his heart<br>
Almost impregnable, his old ears deaf,<br>
Yet should both ear and heart obey my tongue.<br>
[<i>to Aemilius</i>] Go thou before, be our ambassador.<br>
Say that the emperor requests a parley<br>
Of warlike Lucius, and appoint the meeting<br>
Even at his father’s house, the old Andronicus.
</p>

<p class="drama">
SATURNINUS.<br>
Aemilius, do this message honourably,<br>
And if he stand on hostage for his safety,<br>
Bid him demand what pledge will please him best.
</p>

<p class="drama">
AEMILIUS.<br>
Your bidding shall I do effectually.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
TAMORA.<br>
Now will I to that old Andronicus,<br>
And temper him with all the art I have,<br>
To pluck proud Lucius from the warlike Goths.<br>
And now, sweet emperor, be blithe again,<br>
And bury all thy fear in my devices.
</p>

<p class="drama">
SATURNINUS.<br>
Then go successantly, and plead to him.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

