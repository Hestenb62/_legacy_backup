<h2> <a id="sceneIV_19.1"></a><b>ACT IV</b></h2>

<h3> <b>SCENE I. The King of Navarre’s park</b></h3>

<p class="scenedesc">
Enter the <span class="charname">Princess,</span> a <span class="charname">Forester,
Rosaline, Maria, Katharine, Boyet</span> and other Lords.
</p>

<p class="drama">
PRINCESS.<br>
Was that the King that spurred his horse so hard<br>
Against the steep uprising of the hill?
</p>

<p class="drama">
BOYET.<br>
I know not, but I think it was not he.
</p>

<p class="drama">
PRINCESS.<br>
Whoe’er he was, he showed a mounting mind.<br>
Well, lords, today we shall have our dispatch;<br>
On Saturday we will return to France.<br>
Then, forester, my friend, where is the bush<br>
That we must stand and play the murderer in?
</p>

<p class="drama">
FORESTER.<br>
Hereby, upon the edge of yonder coppice,<br>
A stand where you may make “the fairest shoot”.
</p>

<p class="drama">
PRINCESS.<br>
I thank my beauty, I am fair that shoot,<br>
And thereupon thou speak’st the fairest shoot.
</p>

<p class="drama">
FORESTER.<br>
Pardon me, madam, for I meant not so.
</p>

<p class="drama">
PRINCESS.<br>
What, what? First praise me, and again say no?<br>
O short-lived pride! Not fair? Alack for woe!
</p>

<p class="drama">
FORESTER.<br>
Yes, madam, fair.
</p>

<p class="drama">
PRINCESS.<br>
Nay, never paint me now.<br>
Where fair is not, praise cannot mend the brow.<br>
Here, good my glass, take this for telling true:
</p>

<p class="right">[<i>She gives him money.</i>]</p>

<p class="drama">
Fair payment for foul words is more than due.
</p>

<p class="drama">
FORESTER.<br>
Nothing but fair is that which you inherit.
</p>

<p class="drama">
PRINCESS.<br>
See, see, my beauty will be saved by merit.<br>
O heresy in fair, fit for these days!<br>
A giving hand, though foul, shall have fair praise.<br>
But come, the bow. Now mercy goes to kill,<br>
And shooting well is then accounted ill.<br>
Thus will I save my credit in the shoot:<br>
Not wounding, pity would not let me do’t;<br>
If wounding, then it was to show my skill,<br>
That more for praise than purpose meant to kill.<br>
And out of question so it is sometimes,<br>
Glory grows guilty of detested crimes,<br>
When, for fame’s sake, for praise, an outward part,<br>
We bend to that the working of the heart;<br>
As I for praise alone now seek to spill<br>
The poor deer’s blood, that my heart means no ill.
</p>

<p class="drama">
BOYET.<br>
Do not curst wives hold that self-sovereignty<br>
Only for praise’ sake, when they strive to be<br>
Lords o’er their lords?
</p>

<p class="drama">
PRINCESS.<br>
Only for praise; and praise we may afford<br>
To any lady that subdues a lord.
</p>

<p class="scenedesc">
Enter <span class="charname">Costard</span>.
</p>

<p class="drama">
BOYET.<br>
Here comes a member of the commonwealth.
</p>

<p class="drama">
COSTARD.<br>
God dig-you-den all! Pray you, which is the head lady?
</p>

<p class="drama">
PRINCESS.<br>
Thou shalt know her, fellow, by the rest that have no heads.
</p>

<p class="drama">
COSTARD.<br>
Which is the greatest lady, the highest?
</p>

<p class="drama">
PRINCESS.<br>
The thickest and the tallest.
</p>

<p class="drama">
COSTARD.<br>
The thickest and the tallest. It is so, truth is truth.<br>
An your waist, mistress, were as slender as my wit,<br>
One o’ these maids’ girdles for your waist should be fit.<br>
Are not you the chief woman? You are the thickest here.
</p>

<p class="drama">
PRINCESS.<br>
What’s your will, sir? What’s your will?
</p>

<p class="drama">
COSTARD.<br>
I have a letter from Monsieur Berowne to one Lady Rosaline.
</p>

<p class="drama">
PRINCESS.<br>
O, thy letter, thy letter! He’s a good friend of mine.<br>
Stand aside, good bearer. Boyet, you can carve.<br>
Break up this capon.
</p>

<p class="drama">
BOYET.<br>
I am bound to serve.<br>
This letter is mistook; it importeth none here.<br>
It is writ to Jaquenetta.
</p>

<p class="drama">
PRINCESS.<br>
We will read it, I swear.<br>
Break the neck of the wax, and everyone give ear.
</p>

<p class="drama">
BOYET.<br>
[<i>Reads</i>.] <i>By heaven, that thou art fair is most infallible; true that
thou art beauteous; truth itself that thou art lovely. More fairer than fair,
beautiful than beauteous, truer than truth itself, have commiseration on thy
heroical vassal. The magnanimous and most illustrate King Cophetua set eye upon
the pernicious and indubitate beggar Zenelophon, and he it was that might
rightly say,</i> “Veni, vidi, vici,” <i>which to annothanize in the vulgar—O
base and obscure vulgar!</i>—videlicet, <i>He came, see, and overcame. He came,
one; see, two; overcame, three. Who came? The King. Why did he come? To see.
Why did he see? To overcome. To whom came he? To the beggar. What saw he? The
beggar. Who overcame he? The beggar. The conclusion is victory. On whose side?
The King’s. The captive is enriched. On whose side? The beggar’s. The
catastrophe is a nuptial. On whose side? The King’s? No, on both in one, or one
in both. I am the King, for so stands the comparison; thou the beggar, for so
witnesseth thy lowliness. Shall I command thy love? I may. Shall I enforce thy
love? I could. Shall I entreat thy love? I will. What shalt thou exchange for
rags? Robes. For tittles? Titles. For thyself? Me. Thus expecting thy reply, I
profane my lips on thy foot, my eyes on thy picture, and my heart on thy every
part.<br>
          Thine in the dearest design of industry,<br>
                    Don Adriano de Armado.<br><br>
Thus dost thou hear the Nemean lion roar<br>
    ’Gainst thee, thou lamb, that standest as his prey.<br>
Submissive fall his princely feet before,<br>
    And he from forage will incline to play.<br>
But if thou strive, poor soul, what are thou then?<br>
Food for his rage, repasture for his den.</i>
</p>

<p class="drama">
PRINCESS.<br>
What plume of feathers is he that indited this letter?<br>
What vane? What weathercock? Did you ever hear better?
</p>

<p class="drama">
BOYET.<br>
I am much deceived but I remember the style.
</p>

<p class="drama">
PRINCESS.<br>
Else your memory is bad, going o’er it erewhile.
</p>

<p class="drama">
BOYET.<br>
This Armado is a Spaniard that keeps here in court,<br>
A phantasime, a Monarcho, and one that makes sport<br>
To the Prince and his book-mates.
</p>

<p class="drama">
PRINCESS.<br>
Thou, fellow, a word.<br>
Who gave thee this letter?
</p>

<p class="drama">
COSTARD.<br>
I told you: my lord.
</p>

<p class="drama">
PRINCESS.<br>
To whom shouldst thou give it?
</p>

<p class="drama">
COSTARD.<br>
From my lord to my lady.
</p>

<p class="drama">
PRINCESS.<br>
From which lord to which lady?
</p>

<p class="drama">
COSTARD.<br>
From my Lord Berowne, a good master of mine,<br>
To a lady of France that he called Rosaline.
</p>

<p class="drama">
PRINCESS.<br>
Thou hast mistaken his letter. Come, lords, away.<br>
Here, sweet, put up this: ’twill be thine another day.
</p>

<p class="right">[<i>Exeunt all but <span class="charname">Boyet, Rosaline,
Maria</span> and <span class="charname">Costard</span>.</i>]</p>

<p class="drama">
BOYET.<br>
Who is the shooter? Who is the shooter?
</p>

<p class="drama">
ROSALINE.<br>
Shall I teach you to know?
</p>

<p class="drama">
BOYET.<br>
Ay, my continent of beauty.
</p>

<p class="drama">
ROSALINE.<br>
Why, she that bears the bow.<br>
Finely put off!
</p>

<p class="drama">
BOYET.<br>
My lady goes to kill horns, but if thou marry,<br>
Hang me by the neck if horns that year miscarry.<br>
Finely put on!
</p>

<p class="drama">
ROSALINE.<br>
Well, then, I am the shooter.
</p>

<p class="drama">
BOYET.<br>
And who is your deer?
</p>

<p class="drama">
ROSALINE.<br>
If we choose by the horns, yourself come not near.<br>
Finely put on indeed!
</p>

<p class="drama">
MARIA.<br>
You still wrangle with her, Boyet, and she strikes at the brow.
</p>

<p class="drama">
BOYET.<br>
But she herself is hit lower. Have I hit her now?
</p>

<p class="drama">
ROSALINE.<br>
Shall I come upon thee with an old saying, that was a man when King Pepin of
France was a little boy, as touching the hit it?
</p>

<p class="drama">
BOYET.<br>
So I may answer thee with one as old, that was a woman when Queen Guinevere of
Britain was a little wench, as touching the hit it.
</p>

<p class="drama">
ROSALINE.<br>
    Thou canst not hit it, hit it, hit it,<br>
    Thou canst not hit it, my good man.
</p>

<p class="drama">
BOYET.<br>
    An I cannot, cannot, cannot,<br>
    An I cannot, another can.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Rosaline</span>.</i>]
</p>

<p class="drama">
COSTARD.<br>
By my troth, most pleasant. How both did fit it!
</p>

<p class="drama">
MARIA.<br>
A mark marvellous well shot, for they both did hit it.
</p>

<p class="drama">
BOYET.<br>
A mark! O, mark but that mark! A mark, says my lady!<br>
Let the mark have a prick in’t, to mete at, if it may be.
</p>

<p class="drama">
MARIA.<br>
Wide o’ the bow hand! I’ faith, your hand is out.
</p>

<p class="drama">
COSTARD.<br>
Indeed, a’ must shoot nearer, or he’ll ne’er hit the clout.
</p>

<p class="drama">
BOYET.<br>
An if my hand be out, then belike your hand is in.
</p>

<p class="drama">
COSTARD.<br>
Then will she get the upshoot by cleaving the pin.
</p>

<p class="drama">
MARIA.<br>
Come, come, you talk greasily, your lips grow foul.
</p>

<p class="drama">
COSTARD.<br>
She’s too hard for you at pricks, sir. Challenge her to bowl.
</p>

<p class="drama">
BOYET.<br>
I fear too much rubbing. Good night, my good owl.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Boyet</span> and
<span class="charname">Maria</span>.</i>]
</p>

<p class="drama">
COSTARD.<br>
By my soul, a swain, a most simple clown!<br>
Lord, Lord, how the ladies and I have put him down!<br>
O’ my troth, most sweet jests, most incony vulgar wit,<br>
When it comes so smoothly off, so obscenely, as it were, so fit.<br>
Armado, o’ the one side, O, a most dainty man!<br>
To see him walk before a lady and to bear her fan!<br>
To see him kiss his hand and how most sweetly he will swear!<br>
And his page o’ t’other side, that handful of wit!<br>
Ah, heavens, it is a most pathetical nit.
</p>

<p class="right">[<i>Shout within.</i>]</p>

<p class="drama">
Sola, sola!
</p>

<p class="right">[<i>Exit.</i>]</p>

<h3> <a id="sceneIV_19.2"></a><b>SCENE II. The same</b></h3>

<p class="scenedesc">
Enter <span class="charname">Dull, Holofernes,</span> the Pedant and
<span class="charname">Nathaniel</span>.
</p>

<p class="drama">
NATHANIEL.<br>
Very reverend sport, truly, and done in the testimony of a good conscience.
</p>

<p class="drama">
HOLOFERNES.<br>
The deer was, as you know, <i>sanguis</i>, in blood, ripe as the pomewater, who
now hangeth like a jewel in the ear of <i>caelo</i>, the sky, the welkin, the
heaven, and anon falleth like a crab on the face of <i>terra</i>, the soil, the
land, the earth.
</p>

<p class="drama">
NATHANIEL.<br>
Truly, Master Holofernes, the epithets are sweetly varied, like a scholar at
the least. But, sir, I assure ye it was a buck of the first head.
</p>

<p class="drama">
HOLOFERNES.<br>
Sir Nathaniel, <i>haud credo</i>.
</p>

<p class="drama">
DULL.<br>
’Twas not a “auld grey doe”, ’twas a pricket.
</p>

<p class="drama">
HOLOFERNES.<br>
Most barbarous intimation! Yet a kind of insinuation, as it were, <i>in
via</i>, in way, of explication; <i>facere</i>, as it were, replication, or
rather, <i>ostentare</i>, to show, as it were, his inclination, after his
undressed, unpolished, uneducated, unpruned, untrained, or rather, unlettered,
or ratherest, unconfirmed fashion, to insert again my <i>haud credo</i> for a
deer.
</p>

<p class="drama">
DULL.<br>
I said the deer was not a “auld grey doe”, ’twas a pricket.
</p>

<p class="drama">
HOLOFERNES.<br>
Twice-sod simplicity, <i>bis coctus!</i><br>
O, thou monster Ignorance, how deformed dost thou look!
</p>

<p class="drama">
NATHANIEL.<br>
Sir, he hath never fed of the dainties that are bred of a book.<br>
He hath not eat paper, as it were; he hath not drunk ink.<br>
His intellect is not replenished; he is only an animal, only sensible in the duller parts.<br>
And such barren plants are set before us that we thankful should be—<br>
Which we of taste and feeling are—for those parts that do fructify in us more than he.<br>
For as it would ill become me to be vain, indiscreet, or a fool,<br>
So, were there a patch set on learning, to see him in a school.<br>
But, <i>omne bene</i>, say I, being of an old father’s mind;<br>
Many can brook the weather that love not the wind.
</p>

<p class="drama">
DULL.<br>
You two are bookmen. Can you tell me by your wit<br>
What was a month old at Cain’s birth, that’s not five weeks old as yet?
</p>

<p class="drama">
HOLOFERNES.<br>
Dictynna, goodman Dull. Dictynna, goodman Dull.
</p>

<p class="drama">
DULL.<br>
What is Dictynna?
</p>

<p class="drama">
NATHANIEL.<br>
A title to Phoebe, to Luna, to the moon.
</p>

<p class="drama">
HOLOFERNES.<br>
The moon was a month old when Adam was no more,<br>
And raught not to five weeks when he came to five-score.<br>
Th’ allusion holds in the exchange.
</p>

<p class="drama">
DULL.<br>
’Tis true, indeed. The collusion holds in the exchange.
</p>

<p class="drama">
HOLOFERNES.<br>
God comfort thy capacity! I say, th’ allusion holds in the exchange.
</p>

<p class="drama">
DULL.<br>
And I say the pollution holds in the exchange, for the moon is never but a
month old; and I say beside that ’twas a pricket that the Princess killed.
</p>

<p class="drama">
HOLOFERNES.<br>
Sir Nathaniel, will you hear an extemporal epitaph on the death of the deer?
And, to humour the ignorant, call I the deer the Princess killed a pricket.
</p>

<p class="drama">
NATHANIEL.<br>
<i>Perge</i>, good Master Holofernes, <i>perge</i>, so it shall please you to
abrogate scurrility.
</p>

<p class="drama">
HOLOFERNES.<br>
I will something affect the letter; for it argues facility.<br>
The preyful Princess pierced and pricked a pretty pleasing pricket;<br>
Some say a sore; but not a sore till now made sore with shooting.<br>
The dogs did yell, put “l” to sore, then sorel jumps from thicket;<br>
Or pricket sore, or else sorel, the people fall a-hooting.<br>
If sore be sore, then “L” to “sore” makes fifty sores o’ sorel.<br>
Of one sore I an hundred make, by adding but one more “L”.
</p>

<p class="drama">
NATHANIEL.<br>
A rare talent!
</p>

<p class="drama">
DULL.<br>
[<i>Aside</i>.] If a talent be a claw, look how he claws him with a talent.
</p>

<p class="drama">
HOLOFERNES.<br>
This is a gift that I have, simple, simple; a foolish extravagant spirit, full
of forms, figures, shapes, objects, ideas, apprehensions, motions, revolutions.
These are begot in the ventricle of memory, nourished in the womb of <i>pia
mater</i>, and delivered upon the mellowing of occasion. But the gift is good
in those in whom it is acute, and I am thankful for it.
</p>

<p class="drama">
NATHANIEL.<br>
Sir, I praise the Lord for you, and so may my parishioners, for their sons are
well tutored by you, and their daughters profit very greatly under you. You are
a good member of the commonwealth.
</p>

<p class="drama">
HOLOFERNES.<br>
<i>Mehercle!</i> If their sons be ingenious, they shall want no instruction; if
their daughters be capable, I will put it to them. But, <i>vir sapit qui pauca
loquitur</i>. A soul feminine saluteth us.
</p>

<p class="scenedesc">
Enter <span class="charname">Jaquenetta</span> and
<span class="charname">Costard</span>.
</p>

<p class="drama">
JAQUENETTA.<br>
God give you good morrow, Master Person.
</p>

<p class="drama">
HOLOFERNES.<br>
Master Person, <i>quasi</i> pierce one. And if one should be pierced, which is
the one?
</p>

<p class="drama">
COSTARD.<br>
Marry, Master schoolmaster, he that is likest to a hogshead.
</p>

<p class="drama">
HOLOFERNES.<br>
Of piercing a hogshead! A good lustre or conceit in a turf of earth; fire
enough for a flint, pearl enough for a swine. ’Tis pretty; it is well.
</p>

<p class="drama">
JAQUENETTA.<br>
Good Master Parson, be so good as read me this letter. It was given me by
Costard, and sent me from Don Armado. I beseech you read it.
</p>

<p class="right">[<i>Giving a letter to <span class="charname">Nathaniel</span>.</i>]</p>

<p class="drama">
HOLOFERNES.<br>
<i>Fauste precor, gelida quando pecus omne sub umbra Ruminat</i>—<br>
and so forth. Ah, good old Mantuan, I may speak of thee as the traveller doth
of Venice:<br>
    <i>Venetia, Venetia,<br>
    Chi non ti vede, non ti pretia.</i><br>
Old Mantuan, old Mantuan! Who understandeth thee not, loves thee not.<br>
[<i>He sings</i>.]<br>
    Ut, re, sol, la, mi, fa.<br>
Under pardon, sir, what are the contents? Or rather as Horace says in his—What,
my soul, verses?
</p>

<p class="drama">
NATHANIEL.<br>
Ay, sir, and very learned.
</p>

<p class="drama">
HOLOFERNES.<br>
Let me hear a staff, a stanze, a verse,<br>
    <i>Lege, domine</i>.
</p>

<p class="drama">
NATHANIEL.<br>
[<i>Reads</i>.]<br>
<i>If love make me forsworn, how shall I swear to love?<br>
    Ah, never faith could hold, if not to beauty vowed.<br>
Though to myself forsworn, to thee I’ll faithful prove.<br>
    Those thoughts to me were oaks, to thee like osiers bowed.<br>
Study his bias leaves, and makes his book thine eyes,<br>
    Where all those pleasures live that art would comprehend.<br>
If knowledge be the mark, to know thee shall suffice.<br>
    Well learned is that tongue that well can thee commend,<br>
All ignorant that soul that sees thee without wonder;<br>
    Which is to me some praise, that I thy parts admire.<br>
Thy eye Jove’s lightning bears, thy voice his dreadful thunder,<br>
    Which, not to anger bent, is music and sweet fire.<br>
Celestial as thou art, O, pardon love this wrong,<br>
That sings heaven’s praise with such an earthly tongue.</i>
</p>

<p class="drama">
HOLOFERNES.<br>
You find not the apostrophus, and so miss the accent. Let me supervise the
canzonet. [<i>He takes the letter</i>.] Here are only numbers ratified, but,
for the elegancy, facility, and golden cadence of poesy, <i>caret</i>. Ovidius
Naso was the man. And why indeed “Naso,” but for smelling out the odoriferous
flowers of fancy, the jerks of invention? <i>Imitari</i> is nothing: so doth
the hound his master, the ape his keeper, the tired horse his rider. But,
damosella virgin, was this directed to you?
</p>

<p class="drama">
JAQUENETTA.<br>
Ay, sir, from one Monsieur Berowne, one of the strange queen’s lords.
</p>

<p class="drama">
HOLOFERNES.<br>
I will overglance the superscript: <i>To the snow-white hand of the most
beauteous Lady Rosaline.</i> I will look again on the intellect of the letter, for
the nomination of the party writing to the person written unto: <i>Your
Ladyship’s in all desired employment, Berowne.</i> Sir Nathaniel, this Berowne is
one of the votaries with the King, and here he hath framed a letter to a
sequent of the stranger queen’s, which accidentally, or by the way of
progression, hath miscarried. Trip and go, my sweet, deliver this paper into
the royal hand of the King. It may concern much. Stay not thy compliment. I
forgive thy duty. Adieu.
</p>

<p class="drama">
JAQUENETTA.<br>
Good Costard, go with me. Sir, God save your life.
</p>

<p class="drama">
COSTARD.<br>
Have with thee, my girl.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Costard</span> and
<span class="charname">Jaquenetta</span>.</i>]
</p>

<p class="drama">
NATHANIEL.<br>
Sir, you have done this in the fear of God, very religiously; and, as a certain
Father saith—
</p>

<p class="drama">
HOLOFERNES.<br>
Sir, tell not me of the Father, I do fear colourable colours. But to return to
the verses: did they please you, Sir Nathaniel?
</p>

<p class="drama">
NATHANIEL.<br>
Marvellous well for the pen.
</p>

<p class="drama">
HOLOFERNES.<br>
I do dine today at the father’s of a certain pupil of mine, where if, before
repast, it shall please you to gratify the table with a grace, I will, on my
privilege I have with the parents of the foresaid child or pupil, undertake
your <i>ben venuto;</i> where I will prove those verses to be very unlearned,
neither savouring of poetry, wit, nor invention. I beseech your society.
</p>

<p class="drama">
NATHANIEL.<br>
And thank you too; for society, saith the text, is the happiness of life.
</p>

<p class="drama">
HOLOFERNES.<br>
And certes, the text most infallibly concludes it. [<i>To Dull</i>.] Sir, I do
invite you too. You shall not say me nay. <i>Pauca verba</i>. Away! The gentles
are at their game, and we will to our recreation.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneIV_19.3"></a><b>SCENE III. The same</b></h3>

<p class="scenedesc">
Enter <span class="charname">Berowne</span> with a paper in his hand, alone.
</p>

<p class="drama">
BEROWNE.<br>
The King, he is hunting the deer; I am coursing myself. They have pitched a
toil; I am toiling in a pitch, pitch that defiles. Defile! A foul word! Well,
set thee down, sorrow, for so they say the fool said, and so say I, and I
the fool. Well proved, wit! By the Lord, this love is as mad as Ajax. It kills
sheep, it kills me, I a sheep. Well proved again, o’ my side! I will not love;
if I do, hang me! I’ faith, I will not. O, but her eye! By this light, but for
her eye, I would not love her; yes, for her two eyes. Well, I do nothing in the
world but lie, and lie in my throat. By heaven, I do love, and it hath taught
me to rhyme, and to be melancholy. And here is part of my rhyme, and here my
melancholy. Well, she hath one o’ my sonnets already. The clown bore it, the
fool sent it, and the lady hath it. Sweet clown, sweeter fool, sweetest lady!
By the world, I would not care a pin if the other three were in. Here comes one
with a paper. God give him grace to groan!
</p>

<p class="right">[<i>He stands aside.</i>]</p>

<p class="scenedesc">
Enter the <span class="charname">King</span> with a paper.
</p>

<p class="drama">
KING.<br>
Ay me!
</p>

<p class="drama">
BEROWNE.<br>
[<i>Aside</i>.] Shot, by heaven! Proceed, sweet Cupid, thou hast thumped him
with thy birdbolt under the left pap. In faith, secrets!
</p>

<p class="drama">
KING.<br>
[<i>Reads</i>.] [<i>So sweet a kiss the golden sun gives not<br>
    To those fresh morning drops upon the rose,<br>
As thy eye-beams, when their fresh rays have smote<br>
    The night of dew that on my cheeks down flows.<br>
Nor shines the silver moon one half so bright<br>
    Through the transparent bosom of the deep<br>
As doth thy face, through tears of mine give light.<br>
    Thou shin’st in every tear that I do weep.<br>
No drop but as a coach doth carry thee;<br>
    So ridest thou triumphing in my woe.<br>
Do but behold the tears that swell in me,<br>
    And they thy glory through my grief will show.<br>
But do not love thyself; then thou wilt keep<br>
My tears for glasses, and still make me weep.<br>
O queen of queens, how far dost thou excel<br>
No thought can think, nor tongue of mortal tell.</i><br>
How shall she know my griefs? I’ll drop the paper.<br>
Sweet leaves, shade folly. Who is he comes here?
</p>

<p class="right">[<i>Steps aside.</i>]</p>

<p class="drama">
What, Longaville, and reading! Listen, ear.
</p>

<p class="scenedesc">
Enter <span class="charname">Longaville</span> with a paper.
</p>

<p class="drama">
BEROWNE.<br>
[<i>Aside</i>.] Now, in thy likeness, one more fool appear!
</p>

<p class="drama">
LONGAVILLE.<br>
Ay me! I am forsworn.
</p>

<p class="drama">
BEROWNE.<br>
Why, he comes in like a perjure, wearing papers.
</p>

<p class="drama">
KING.<br>
In love, I hope. Sweet fellowship in shame.
</p>

<p class="drama">
BEROWNE.<br>
One drunkard loves another of the name.
</p>

<p class="drama">
LONGAVILLE.<br>
Am I the first that have been perjured so?
</p>

<p class="drama">
BEROWNE.<br>
I could put thee in comfort: not by two that I know.<br>
Thou makest the triumviry, the corner-cap of society,<br>
The shape of love’s Tyburn, that hangs up simplicity.
</p>

<p class="drama">
LONGAVILLE.<br>
I fear these stubborn lines lack power to move.<br>
O sweet Maria, empress of my love,<br>
These numbers will I tear, and write in prose.
</p>

<p class="drama">
BEROWNE.<br>
O, rhymes are guards on wanton Cupid’s hose.<br>
Disfigure not his shop.
</p>

<p class="drama">
LONGAVILLE.<br>
This same shall go.
</p>

<p class="right">[<i>He reads the sonnet.</i>]</p>

<p class="drama">
<i>Did not the heavenly rhetoric of thine eye,<br>
    ’Gainst whom the world cannot hold argument,<br>
Persuade my heart to this false perjury?<br>
    Vows for thee broke deserve not punishment.<br>
A woman I forswore, but I will prove,<br>
    Thou being a goddess, I forswore not thee.<br>
My vow was earthly, thou a heavenly love;<br>
    Thy grace being gained, cures all disgrace in me.<br>
Vows are but breath, and breath a vapour is.<br>
    Then thou, fair sun, which on my earth dost shine,<br>
Exhal’st this vapour-vow; in thee it is.<br>
    If broken then, it is no fault of mine;<br>
If by me broke, what fool is not so wise<br>
To lose an oath to win a paradise?</i>
</p>

<p class="drama">
BEROWNE.<br>
This is the liver vein, which makes flesh a deity,<br>
A green goose a goddess. Pure, pure idolatry.<br>
God amend us, God amend! We are much out o’ th’ way.
</p>

<p class="drama">
LONGAVILLE.<br>
By whom shall I send this?—Company! Stay.
</p>

<p class="right">[<i>He steps aside.</i>]</p>

<p class="scenedesc">
Enter <span class="charname">Dumaine</span> with a paper.
</p>

<p class="drama">
BEROWNE.<br>
All hid, all hid, an old infant play.<br>
Like a demigod here sit I in the sky,<br>
And wretched fools’ secrets heedfully o’er-eye.<br>
More sacks to the mill. O heavens, I have my wish.<br>
Dumaine transformed! Four woodcocks in a dish!
</p>

<p class="drama">
DUMAINE.<br>
O most divine Kate!
</p>

<p class="drama">
BEROWNE.<br>
O most profane coxcomb!
</p>

<p class="drama">
DUMAINE.<br>
By heaven, the wonder in a mortal eye!
</p>

<p class="drama">
BEROWNE.<br>
By earth, she is but corporal. There you lie.
</p>

<p class="drama">
DUMAINE.<br>
Her amber hairs for foul hath amber quoted.
</p>

<p class="drama">
BEROWNE.<br>
An amber-coloured raven was well noted.
</p>

<p class="drama">
DUMAINE.<br>
As upright as the cedar.
</p>

<p class="drama">
BEROWNE.<br>
Stoop, I say.<br>
Her shoulder is with child.
</p>

<p class="drama">
DUMAINE.<br>
As fair as day.
</p>

<p class="drama">
BEROWNE.<br>
Ay, as some days, but then no sun must shine.
</p>

<p class="drama">
DUMAINE.<br>
O, that I had my wish!
</p>

<p class="drama">
LONGAVILLE.<br>
And I had mine!
</p>

<p class="drama">
KING.<br>
And I mine too, good Lord!
</p>

<p class="drama">
BEROWNE.<br>
Amen, so I had mine. Is not that a good word?
</p>

<p class="drama">
DUMAINE.<br>
I would forget her; but a fever she<br>
Reigns in my blood, and will remembered be.
</p>

<p class="drama">
BEROWNE.<br>
A fever in your blood? Why, then incision<br>
Would let her out in saucers. Sweet misprision!
</p>

<p class="drama">
DUMAINE.<br>
Once more I’ll read the ode that I have writ.
</p>

<p class="drama">
BEROWNE.<br>
Once more I’ll mark how love can vary wit.
</p>

<p class="drama">
DUMAINE.<br>
[<i>Dumaine reads his sonnet</i>.]<br>
    <i>On a day—alack the day!—<br>
    Love, whose month is ever May,<br>
    Spied a blossom passing fair<br>
    Playing in the wanton air.<br>
    Through the velvet leaves the wind,<br>
    All unseen, can passage find;<br>
    That the lover, sick to death,<br>
    Wished himself the heaven’s breath.<br>
    “Air,” quoth he, “thy cheeks may blow;<br>
    Air, would I might triumph so!”<br>
    But, alack, my hand is sworn<br>
    Ne’er to pluck thee from thy thorn.<br>
    Vow, alack, for youth unmeet,<br>
    Youth so apt to pluck a sweet.<br>
    Do not call it sin in me,<br>
    That I am forsworn for thee;<br>
    Thou for whom Jove would swear<br>
    Juno but an Ethiope were,<br>
    And deny himself for Jove,<br>
    Turning mortal for thy love.</i><br>
This will I send, and something else more plain,<br>
That shall express my true love’s fasting pain.<br>
O, would the King, Berowne and Longaville<br>
Were lovers too! Ill, to example ill,<br>
Would from my forehead wipe a perjured note,<br>
For none offend where all alike do dote.
</p>

<p class="drama">
LONGAVILLE.<br>
[<i>Comes forward</i>.] Dumaine, thy love is far from charity,<br>
That in love’s grief desir’st society.<br>
You may look pale, but I should blush, I know,<br>
To be o’erheard and taken napping so.
</p>

<p class="drama">
KING.<br>
[<i>Comes forward</i>.] Come, sir, you blush. As his, your case is such.<br>
You chide at him, offending twice as much.<br>
You do not love Maria? Longaville<br>
Did never sonnet for her sake compile,<br>
Nor never lay his wreathed arms athwart<br>
His loving bosom to keep down his heart.<br>
I have been closely shrouded in this bush,<br>
And marked you both, and for you both did blush.<br>
I heard your guilty rhymes, observed your fashion,<br>
Saw sighs reek from you, noted well your passion.<br>
“Ay, me!” says one. “O Jove!” the other cries.<br>
One, her hairs were gold; crystal the other’s eyes.<br>
[<i>To Longaville</i>.] You would for paradise break faith and troth;<br>
[<i>To Dumaine</i>.] And Jove, for your love would infringe an oath.<br>
What will Berowne say when that he shall hear<br>
Faith infringed which such zeal did swear?<br>
How will he scorn, how will he spend his wit!<br>
How will he triumph, leap, and laugh at it!<br>
For all the wealth that ever I did see,<br>
I would not have him know so much by me.
</p>

<p class="drama">
BEROWNE.<br>
[<i>Comes forward</i>.]<br>
Now step I forth to whip hypocrisy.<br>
Ah, good my liege, I pray thee pardon me.<br>
Good heart, what grace hast thou thus to reprove<br>
These worms for loving, that art most in love?<br>
Your eyes do make no coaches; in your tears<br>
There is no certain princess that appears.<br>
You’ll not be perjured, ’tis a hateful thing:<br>
Tush, none but minstrels like of sonneting!<br>
But are you not ashamed? Nay, are you not,<br>
All three of you, to be thus much o’ershot?<br>
You found his mote, the King your mote did see;<br>
But I a beam do find in each of three.<br>
O, what a scene of foolery have I seen,<br>
Of sighs, of groans, of sorrow, and of teen!<br>
O me, with what strict patience have I sat,<br>
To see a king transformed to a gnat!<br>
To see great Hercules whipping a gig,<br>
And profound Solomon to tune a jig,<br>
And Nestor play at push-pin with the boys,<br>
And critic Timon laugh at idle toys.<br>
Where lies thy grief, O, tell me, good Dumaine?<br>
And, gentle Longaville, where lies thy pain?<br>
And where my liege’s? All about the breast?<br>
A caudle, ho!
</p>

<p class="drama">
KING.<br>
Too bitter is thy jest.<br>
Are we betrayed thus to thy over-view?
</p>

<p class="drama">
BEROWNE.<br>
Not you to me, but I betrayed by you.<br>
I that am honest, I that hold it sin<br>
To break the vow I am engaged in.<br>
I am betrayed by keeping company<br>
With men like you, men of inconstancy.<br>
When shall you see me write a thing in rhyme?<br>
Or groan for Joan? Or spend a minute’s time<br>
In pruning me? When shall you hear that I<br>
Will praise a hand, a foot, a face, an eye,<br>
A gait, a state, a brow, a breast, a waist,<br>
A leg, a limb—
</p>

<p class="drama">
KING.<br>
Soft! Whither away so fast?<br>
A true man, or a thief, that gallops so?
</p>

<p class="drama">
BEROWNE.<br>
I post from love. Good lover, let me go.
</p>

<p class="scenedesc">
Enter <span class="charname">Jaquenetta,</span> with a letter, and
<span class="charname">Costard</span>.
</p>

<p class="drama">
JAQUENETTA.<br>
God bless the King!
</p>

<p class="drama">
KING.<br>
What present hast thou there?
</p>

<p class="drama">
COSTARD.<br>
Some certain treason.
</p>

<p class="drama">
KING.<br>
What makes treason here?
</p>

<p class="drama">
COSTARD.<br>
Nay, it makes nothing, sir.
</p>

<p class="drama">
KING.<br>
If it mar nothing neither,<br>
The treason and you go in peace away together.
</p>

<p class="drama">
JAQUENETTA.<br>
I beseech your Grace, let this letter be read.<br>
Our person misdoubts it; ’twas treason, he said.
</p>

<p class="drama">
KING.<br>
Berowne, read it over.
</p>

<p class="right">[<i><span class="charname">Berowne</span> reads the letter.</i>]</p>

<p class="drama">
Where hadst thou it?
</p>

<p class="drama">
JAQUENETTA.<br>
Of Costard.
</p>

<p class="drama">
KING.<br>
Where hadst thou it?
</p>

<p class="drama">
COSTARD.<br>
Of Dun Adramadio, Dun Adramadio.
</p>

<p class="right">[<i><span class="charname">Berowne</span> tears the letter.</i>]</p>

<p class="drama">
KING.<br>
How now, what is in you? Why dost thou tear it?
</p>

<p class="drama">
BEROWNE.<br>
A toy, my liege, a toy. Your Grace needs not fear it.
</p>

<p class="drama">
LONGAVILLE.<br>
It did move him to passion, and therefore let’s hear it.
</p>

<p class="drama">
DUMAINE.<br>
[<i>Picking up the pieces</i>.]<br>
It is Berowne’s writing, and here is his name.
</p>

<p class="drama">
BEROWNE.<br>
[<i>To Costard</i>.] Ah, you whoreson loggerhead, you were born to do me shame.<br>
Guilty, my lord, guilty. I confess, I confess.
</p>

<p class="drama">
KING.<br>
What?
</p>

<p class="drama">
BEROWNE.<br>
That you three fools lacked me fool to make up the mess.<br>
He, he, and you—and you, my liege—and I<br>
Are pick-purses in love, and we deserve to die.<br>
O, dismiss this audience, and I shall tell you more.
</p>

<p class="drama">
DUMAINE.<br>
Now the number is even.
</p>

<p class="drama">
BEROWNE.<br>
True, true, we are four.<br>
Will these turtles be gone?
</p>

<p class="drama">
KING.<br>
Hence, sirs, away!
</p>

<p class="drama">
COSTARD.<br>
Walk aside the true folk, and let the traitors stay.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Costard</span> and
<span class="charname">Jaquenetta</span>.</i>]
</p>

<p class="drama">
BEROWNE.<br>
Sweet lords, sweet lovers, O, let us embrace!<br>
    As true we are as flesh and blood can be.<br>
The sea will ebb and flow, heaven show his face;<br>
    Young blood doth not obey an old decree.<br>
We cannot cross the cause why we were born;<br>
Therefore of all hands must we be forsworn.
</p>

<p class="drama">
KING.<br>
What, did these rent lines show some love of thine?
</p>

<p class="drama">
BEROWNE.<br>
“Did they?” quoth you? Who sees the heavenly Rosaline<br>
That, like a rude and savage man of Ind,<br>
At the first op’ning of the gorgeous east,<br>
Bows not his vassal head and, strucken blind,<br>
Kisses the base ground with obedient breast?<br>
What peremptory eagle-sighted eye<br>
Dares look upon the heaven of her brow<br>
That is not blinded by her majesty?
</p>

<p class="drama">
KING.<br>
What zeal, what fury hath inspired thee now?<br>
My love, her mistress, is a gracious moon;<br>
She, an attending star, scarce seen a light.
</p>

<p class="drama">
BEROWNE.<br>
My eyes are then no eyes, nor I Berowne.<br>
O, but for my love, day would turn to night!<br>
Of all complexions the culled sovereignty<br>
Do meet as at a fair in her fair cheek,<br>
Where several worthies make one dignity,<br>
Where nothing wants that want itself doth seek.<br>
Lend me the flourish of all gentle tongues—<br>
Fie, painted rhetoric! O, she needs it not.<br>
To things of sale a seller’s praise belongs.<br>
She passes praise; then praise too short doth blot.<br>
A withered hermit, five-score winters worn,<br>
Might shake off fifty, looking in her eye.<br>
Beauty doth varnish age, as if new born,<br>
And gives the crutch the cradle’s infancy.<br>
O, ’tis the sun that maketh all things shine!
</p>

<p class="drama">
KING.<br>
By heaven, thy love is black as ebony.
</p>

<p class="drama">
BEROWNE.<br>
Is ebony like her? O word divine!<br>
A wife of such wood were felicity.<br>
O, who can give an oath? Where is a book?<br>
That I may swear beauty doth beauty lack<br>
If that she learn not of her eye to look.<br>
No face is fair that is not full so black.
</p>

<p class="drama">
KING.<br>
O paradox! Black is the badge of hell,<br>
The hue of dungeons and the school of night;<br>
And beauty’s crest becomes the heavens well.
</p>

<p class="drama">
BEROWNE.<br>
Devils soonest tempt, resembling spirits of light.<br>
O, if in black my lady’s brows be decked,<br>
It mourns that painting and usurping hair<br>
Should ravish doters with a false aspect;<br>
And therefore is she born to make black fair.<br>
Her favour turns the fashion of the days,<br>
For native blood is counted painting now;<br>
And therefore red, that would avoid dispraise,<br>
Paints itself black, to imitate her brow.
</p>

<p class="drama">
DUMAINE.<br>
To look like her are chimney-sweepers black.
</p>

<p class="drama">
LONGAVILLE.<br>
And since her time are colliers counted bright.
</p>

<p class="drama">
KING.<br>
And Ethiopes of their sweet complexion crack.
</p>

<p class="drama">
DUMAINE.<br>
Dark needs no candles now, for dark is light.
</p>

<p class="drama">
BEROWNE.<br>
Your mistresses dare never come in rain,<br>
For fear their colours should be washed away.
</p>

<p class="drama">
KING.<br>
’Twere good yours did; for, sir, to tell you plain,<br>
I’ll find a fairer face not washed today.
</p>

<p class="drama">
BEROWNE.<br>
I’ll prove her fair, or talk till doomsday here.
</p>

<p class="drama">
KING.<br>
No devil will fright thee then so much as she.
</p>

<p class="drama">
DUMAINE.<br>
I never knew man hold vile stuff so dear.
</p>

<p class="drama">
LONGAVILLE.<br>
[<i>Showing his shoe</i>.]<br>
Look, here’s thy love, my foot and her face see.
</p>

<p class="drama">
BEROWNE.<br>
O, if the streets were paved with thine eyes,<br>
Her feet were much too dainty for such tread.
</p>

<p class="drama">
DUMAINE.<br>
O vile! Then, as she goes, what upward lies<br>
The street should see as she walked over head.
</p>

<p class="drama">
KING.<br>
But what of this? Are we not all in love?
</p>

<p class="drama">
BEROWNE.<br>
Nothing so sure, and thereby all forsworn.
</p>

<p class="drama">
KING.<br>
Then leave this chat, and, good Berowne, now prove<br>
Our loving lawful, and our faith not torn.
</p>

<p class="drama">
DUMAINE.<br>
Ay, marry, there; some flattery for this evil.
</p>

<p class="drama">
LONGAVILLE.<br>
O, some authority how to proceed.<br>
Some tricks, some quillets, how to cheat the devil.
</p>

<p class="drama">
DUMAINE.<br>
Some salve for perjury.
</p>

<p class="drama">
BEROWNE.<br>
O, ’tis more than need.<br>
Have at you, then, affection’s men-at-arms.<br>
Consider what you first did swear unto:<br>
To fast, to study, and to see no woman—<br>
Flat treason ’gainst the kingly state of youth.<br>
Say, can you fast? Your stomachs are too young,<br>
And abstinence engenders maladies.<br>
O, we have made a vow to study, lords,<br>
And in that vow we have forsworn our books;<br>
For when would you, my liege, or you, or you,<br>
In leaden contemplation have found out<br>
Such fiery numbers as the prompting eyes<br>
Of beauty’s tutors have enriched you with?<br>
Other slow arts entirely keep the brain,<br>
And therefore, finding barren practisers,<br>
Scarce show a harvest of their heavy toil;<br>
But love, first learned in a lady’s eyes,<br>
Lives not alone immured in the brain,<br>
But with the motion of all elements<br>
Courses as swift as thought in every power,<br>
And gives to every power a double power,<br>
Above their functions and their offices.<br>
It adds a precious seeing to the eye.<br>
A lover’s eyes will gaze an eagle blind.<br>
A lover’s ear will hear the lowest sound,<br>
When the suspicious head of theft is stopped.<br>
Love’s feeling is more soft and sensible<br>
Than are the tender horns of cockled snails.<br>
Love’s tongue proves dainty Bacchus gross in taste.<br>
For valour, is not Love a Hercules,<br>
Still climbing trees in the Hesperides?<br>
Subtle as Sphinx, as sweet and musical<br>
As bright Apollo’s lute, strung with his hair.<br>
And when Love speaks, the voice of all the gods<br>
Make heaven drowsy with the harmony.<br>
Never durst poet touch a pen to write<br>
Until his ink were tempered with Love’s sighs.<br>
O, then his lines would ravish savage ears<br>
And plant in tyrants mild humility.<br>
From women’s eyes this doctrine I derive.<br>
They sparkle still the right Promethean fire;<br>
They are the books, the arts, the academes,<br>
That show, contain, and nourish, all the world;<br>
Else none at all in aught proves excellent.<br>
Then fools you were these women to forswear,<br>
Or, keeping what is sworn, you will prove fools.<br>
For wisdom’s sake, a word that all men love,<br>
Or for love’s sake, a word that loves all men,<br>
Or for men’s sake, the authors of these women,<br>
Or women’s sake, by whom we men are men,<br>
Let us once lose our oaths to find ourselves,<br>
Or else we lose ourselves to keep our oaths.<br>
It is religion to be thus forsworn,<br>
For charity itself fulfils the law,<br>
And who can sever love from charity?
</p>

<p class="drama">
KING.<br>
Saint Cupid, then, and, soldiers, to the field!
</p>

<p class="drama">
BEROWNE.<br>
Advance your standards, and upon them, lords!<br>
Pell-mell, down with them! But be first advised<br>
In conflict that you get the sun of them.
</p>

<p class="drama">
LONGAVILLE.<br>
Now to plain dealing. Lay these glozes by.<br>
Shall we resolve to woo these girls of France?
</p>

<p class="drama">
KING.<br>
And win them too. Therefore let us devise<br>
Some entertainment for them in their tents.
</p>

<p class="drama">
BEROWNE.<br>
First, from the park let us conduct them thither.<br>
Then homeward every man attach the hand<br>
Of his fair mistress. In the afternoon<br>
We will with some strange pastime solace them,<br>
Such as the shortness of the time can shape;<br>
For revels, dances, masques, and merry hours<br>
Forerun fair Love, strewing her way with flowers.
</p>

<p class="drama">
KING.<br>
Away, away! No time shall be omitted<br>
That will betime and may by us be fitted.
</p>

<p class="drama">
BEROWNE.<br>
<i>Allons! allons!</i> Sowed cockle reaped no corn,<br>
And justice always whirls in equal measure.<br>
Light wenches may prove plagues to men forsworn;<br>
If so, our copper buys no better treasure.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

