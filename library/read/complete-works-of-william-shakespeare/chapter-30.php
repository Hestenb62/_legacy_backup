<h2> <a id="sceneI_6.1"></a><b>ACT I</b></h2>

<h3> <b>SCENE I. Rome. A street</b></h3>

<p class="scenedesc">
Enter a company of mutinous Citizens, with staves, clubs, and other weapons.
</p>

<p class="drama">
FIRST CITIZEN.<br>
Before we proceed any further, hear me speak.
</p>

<p class="drama">
ALL.<br>
Speak, speak!
</p>

<p class="drama">
FIRST CITIZEN.<br>
You are all resolved rather to die than to famish?
</p>

<p class="drama">
ALL.<br>
Resolved, resolved!
</p>

<p class="drama">
FIRST CITIZEN.<br>
First, you know Caius Martius is chief enemy to the people.
</p>

<p class="drama">
ALL.<br>
We know’t, we know’t!
</p>

<p class="drama">
FIRST CITIZEN.<br>
Let us kill him, and we’ll have corn at our own price. Is’t a verdict?
</p>

<p class="drama">
ALL.<br>
No more talking on’t; let it be done. Away, away!
</p>

<p class="drama">
SECOND CITIZEN.<br>
One word, good citizens.
</p>

<p class="drama">
FIRST CITIZEN.<br>
We are accounted poor citizens, the patricians good. What authority surfeits on
would relieve us. If they would yield us but the superfluity while it were
wholesome, we might guess they relieved us humanely. But they think we are too
dear. The leanness that afflicts us, the object of our misery, is as an
inventory to particularize their abundance; our sufferance is a gain to
them. Let us revenge this with our pikes ere we become rakes; for the gods know
I speak this in hunger for bread, not in thirst for revenge.
</p>

<p class="drama">
SECOND CITIZEN.<br>
Would you proceed especially against Caius Martius?
</p>

<p class="drama">
FIRST CITIZEN.<br>
Against him first. He’s a very dog to the commonalty.
</p>

<p class="drama">
SECOND CITIZEN.<br>
Consider you what services he has done for his country?
</p>

<p class="drama">
FIRST CITIZEN.<br>
Very well, and could be content to give him good report for’t, but that he pays
himself with being proud.
</p>

<p class="drama">
SECOND CITIZEN.<br>
Nay, but speak not maliciously.
</p>

<p class="drama">
FIRST CITIZEN.<br>
I say unto you, what he hath done famously he did it to that end. Though
soft-conscienced men can be content to say it was for his country, he did it to
please his mother and to be partly proud, which he is, even to the altitude of
his virtue.
</p>

<p class="drama">
SECOND CITIZEN.<br>
What he cannot help in his nature you account a vice in him. You must in no way
say he is covetous.
</p>

<p class="drama">
FIRST CITIZEN.<br>
If I must not, I need not be barren of accusations. He hath faults, with
surplus, to tire in repetition. [<i>Shouts within</i>.] What shouts are these?
The other side o’ th’ city is risen. Why stay we prating here? To th’ Capitol!
</p>

<p class="drama">
ALL.<br>
Come, come!
</p>

<p class="scenedesc">
Enter <span class="charname">Menenius Agrippa</span>.
</p>

<p class="drama">
FIRST CITIZEN.<br>
Soft, who comes here?
</p>

<p class="drama">
SECOND CITIZEN.<br>
Worthy Menenius Agrippa, one that hath always loved the people.
</p>

<p class="drama">
FIRST CITIZEN.<br>
He’s one honest enough. Would all the rest were so!
</p>

<p class="drama">
MENENIUS.<br>
What work’s, my countrymen, in hand? Where go you<br>
With bats and clubs? The matter? Speak, I pray you.
</p>

<p class="drama">
FIRST CITIZEN.<br>
Our business is not unknown to th’ Senate. They have had inkling this fortnight
what we intend to do, which now we’ll show ’em in deeds. They say poor suitors
have strong breaths; they shall know we have strong arms too.
</p>

<p class="drama">
MENENIUS.<br>
Why, masters, my good friends, mine honest neighbours,<br>
Will you undo yourselves?
</p>

<p class="drama">
FIRST CITIZEN.<br>
We cannot, sir; we are undone already.
</p>

<p class="drama">
MENENIUS.<br>
I tell you, friends, most charitable care<br>
Have the patricians of you. For your wants,<br>
Your suffering in this dearth, you may as well<br>
Strike at the heaven with your staves as lift them<br>
Against the Roman state, whose course will on<br>
The way it takes, cracking ten thousand curbs<br>
Of more strong link asunder than can ever<br>
Appear in your impediment. For the dearth,<br>
The gods, not the patricians, make it, and<br>
Your knees to them, not arms, must help. Alack,<br>
You are transported by calamity<br>
Thither where more attends you, and you slander<br>
The helms o’ th’ state, who care for you like fathers,<br>
When you curse them as enemies.
</p>

<p class="drama">
FIRST CITIZEN.<br>
Care for us? True, indeed! They ne’er cared for us yet. Suffer us to famish,
and their storehouses crammed with grain; make edicts for usury to support
usurers; repeal daily any wholesome act established against the rich, and
provide more piercing statutes daily to chain up and restrain the poor. If the
wars eat us not up, they will; and there’s all the love they bear us.
</p>

<p class="drama">
MENENIUS.<br>
Either you must confess yourselves wondrous malicious<br>
Or be accused of folly. I shall tell you<br>
A pretty tale. It may be you have heard it,<br>
But since it serves my purpose, I will venture<br>
To stale’t a little more.
</p>

<p class="drama">
FIRST CITIZEN.<br>
Well, I’ll hear it, sir; yet you must not think to fob off our disgrace with a
tale. But, an’t please you, deliver.
</p>

<p class="drama">
MENENIUS.<br>
There was a time when all the body’s members<br>
Rebelled against the belly, thus accused it:<br>
That only like a gulf it did remain<br>
I’ th’ midst o’ th’ body, idle and unactive,<br>
Still cupboarding the viand, never bearing<br>
Like labour with the rest, where th’ other instruments<br>
Did see and hear, devise, instruct, walk, feel,<br>
And, mutually participate, did minister<br>
Unto the appetite and affection common<br>
Of the whole body. The belly answered—
</p>

<p class="drama">
FIRST CITIZEN.<br>
Well, sir, what answer made the belly?
</p>

<p class="drama">
MENENIUS.<br>
Sir, I shall tell you. With a kind of smile,<br>
Which ne’er came from the lungs, but even thus—<br>
For, look you, I may make the belly smile<br>
As well as speak—it tauntingly replied<br>
To th’ discontented members, the mutinous parts<br>
That envied his receipt; even so most fitly<br>
As you malign our senators for that<br>
They are not such as you.
</p>

<p class="drama">
FIRST CITIZEN.<br>
Your belly’s answer—what?<br>
The kingly crowned head, the vigilant eye,<br>
The counsellor heart, the arm our soldier,<br>
Our steed the leg, the tongue our trumpeter,<br>
With other muniments and petty helps<br>
Is this our fabric, if that they—
</p>

<p class="drama">
MENENIUS.<br>
What then?<br>
’Fore me, this fellow speaks. What then? What then?
</p>

<p class="drama">
FIRST CITIZEN.<br>
Should by the cormorant belly be restrained,<br>
Who is the sink o’ th’ body—
</p>

<p class="drama">
MENENIUS.<br>
Well, what then?
</p>

<p class="drama">
FIRST CITIZEN.<br>
The former agents, if they did complain,<br>
What could the belly answer?
</p>

<p class="drama">
MENENIUS.<br>
I will tell you,<br>
If you’ll bestow a small—of what you have little—<br>
Patience awhile, you’st hear the belly’s answer.
</p>

<p class="drama">
FIRST CITIZEN.<br>
You are long about it.
</p>

<p class="drama">
MENENIUS.<br>
Note me this, good friend;<br>
Your most grave belly was deliberate,<br>
Not rash like his accusers, and thus answered:<br>
“True is it, my incorporate friends,” quoth he,<br>
“That I receive the general food at first<br>
Which you do live upon; and fit it is,<br>
Because I am the storehouse and the shop<br>
Of the whole body. But, if you do remember,<br>
I send it through the rivers of your blood<br>
Even to the court, the heart, to th’ seat o’ th’ brain;<br>
And, through the cranks and offices of man,<br>
The strongest nerves and small inferior veins<br>
From me receive that natural competency<br>
Whereby they live. And though that all at once,<br>
You, my good friends”—this says the belly, mark me—
</p>

<p class="drama">
FIRST CITIZEN.<br>
Ay, sir, well, well.
</p>

<p class="drama">
MENENIUS.<br>
“Though all at once cannot<br>
See what I do deliver out to each,<br>
Yet I can make my audit up, that all<br>
From me do back receive the flour of all,<br>
And leave me but the bran.” What say you to’t?
</p>

<p class="drama">
FIRST CITIZEN.<br>
It was an answer. How apply you this?
</p>

<p class="drama">
MENENIUS.<br>
The senators of Rome are this good belly,<br>
And you the mutinous members. For examine<br>
Their counsels and their cares, digest things rightly<br>
Touching the weal o’ th’ common, you shall find<br>
No public benefit which you receive<br>
But it proceeds or comes from them to you<br>
And no way from yourselves. What do you think,<br>
You, the great toe of this assembly?
</p>

<p class="drama">
FIRST CITIZEN.<br>
I the great toe? Why the great toe?
</p>

<p class="drama">
MENENIUS.<br>
For that, being one o’ th’ lowest, basest, poorest,<br>
Of this most wise rebellion, thou goest foremost.<br>
Thou rascal, that art worst in blood to run,<br>
Lead’st first to win some vantage.<br>
But make you ready your stiff bats and clubs.<br>
Rome and her rats are at the point of battle;<br>
The one side must have bale.
</p>

<p class="scenedesc">
Enter <span class="charname">Caius Martius</span>.
</p>

<p class="drama">
Hail, noble Martius.
</p>

<p class="drama">
MARTIUS.<br>
Thanks.—What’s the matter, you dissentious rogues,<br>
That, rubbing the poor itch of your opinion,<br>
Make yourselves scabs?
</p>

<p class="drama">
FIRST CITIZEN.<br>
We have ever your good word.
</p>

<p class="drama">
MARTIUS.<br>
He that will give good words to thee will flatter<br>
Beneath abhorring. What would you have, you curs,<br>
That like nor peace nor war? The one affrights you;<br>
The other makes you proud. He that trusts to you,<br>
Where he should find you lions, finds you hares;<br>
Where foxes, geese. You are no surer, no,<br>
Than is the coal of fire upon the ice<br>
Or hailstone in the sun. Your virtue is<br>
To make him worthy whose offence subdues him,<br>
And curse that justice did it. Who deserves greatness<br>
Deserves your hate; and your affections are<br>
A sick man’s appetite, who desires most that<br>
Which would increase his evil. He that depends<br>
Upon your favours swims with fins of lead,<br>
And hews down oaks with rushes. Hang ye! Trust ye?<br>
With every minute you do change a mind<br>
And call him noble that was now your hate,<br>
Him vile that was your garland. What’s the matter,<br>
That in these several places of the city<br>
You cry against the noble senate, who,<br>
Under the gods, keep you in awe, which else<br>
Would feed on one another?—What’s their seeking?
</p>

<p class="drama">
MENENIUS.<br>
For corn at their own rates, whereof they say<br>
The city is well stored.
</p>

<p class="drama">
MARTIUS.<br>
Hang ’em! They say?<br>
They’ll sit by th’ fire and presume to know<br>
What’s done i’ th’ Capitol, who’s like to rise,<br>
Who thrives and who declines; side factions and give out<br>
Conjectural marriages, making parties strong<br>
And feebling such as stand not in their liking<br>
Below their cobbled shoes. They say there’s grain enough?<br>
Would the nobility lay aside their ruth<br>
And let me use my sword, I’d make a quarry<br>
With thousands of these quartered slaves as high<br>
As I could pick my lance.
</p>

<p class="drama">
MENENIUS.<br>
Nay, these are almost thoroughly persuaded;<br>
For though abundantly they lack discretion,<br>
Yet are they passing cowardly. But I beseech you,<br>
What says the other troop?
</p>

<p class="drama">
MARTIUS.<br>
They are dissolved. Hang ’em!<br>
They said they were an-hungry, sighed forth proverbs<br>
That hunger broke stone walls, that dogs must eat,<br>
That meat was made for mouths, that the gods sent not<br>
Corn for the rich men only. With these shreds<br>
They vented their complainings, which being answered<br>
And a petition granted them—a strange one,<br>
To break the heart of generosity<br>
And make bold power look pale—they threw their caps<br>
As they would hang them on the horns o’ th’ moon,<br>
Shouting their emulation.
</p>

<p class="drama">
MENENIUS.<br>
What is granted them?
</p>

<p class="drama">
MARTIUS.<br>
Five tribunes to defend their vulgar wisdoms,<br>
Of their own choice. One’s Junius Brutus,<br>
Sicinius Velutus, and I know not. ’Sdeath!<br>
The rabble should have first unroofed the city<br>
Ere so prevailed with me. It will in time<br>
Win upon power and throw forth greater themes<br>
For insurrection’s arguing.
</p>

<p class="drama">
MENENIUS.<br>
This is strange.
</p>

<p class="drama">
MARTIUS.<br>
Go get you home, you fragments.
</p>

<p class="scenedesc">
Enter a <span class="charname">Messenger</span> hastily.
</p>

<p class="drama">
MESSENGER.<br>
Where’s Caius Martius?
</p>

<p class="drama">
MARTIUS.<br>
Here. What’s the matter?
</p>

<p class="drama">
MESSENGER.<br>
The news is, sir, the Volsces are in arms.
</p>

<p class="drama">
MARTIUS.<br>
I am glad on’t. Then we shall ha’ means to vent<br>
Our musty superfluity.
</p>

<p class="scenedesc">
Enter <span class="charname">Sicinius Velutus, Junius Brutus</span>, two
Tribunes; <span class="charname">Cominius, Titus Lartius</span> with other
Senators.
</p>

<p class="drama">
See, our best elders.
</p>

<p class="drama">
FIRST SENATOR.<br>
Martius, ’tis true that you have lately told us:<br>
The Volsces are in arms.
</p>

<p class="drama">
MARTIUS.<br>
They have a leader,<br>
Tullus Aufidius, that will put you to’t.<br>
I sin in envying his nobility,<br>
And, were I anything but what I am,<br>
I would wish me only he.
</p>

<p class="drama">
COMINIUS.<br>
You have fought together.
</p>

<p class="drama">
MARTIUS.<br>
Were half to half the world by th’ ears and he<br>
Upon my party, I’d revolt, to make<br>
Only my wars with him. He is a lion<br>
That I am proud to hunt.
</p>

<p class="drama">
FIRST SENATOR.<br>
Then, worthy Martius,<br>
Attend upon Cominius to these wars.
</p>

<p class="drama">
COMINIUS.<br>
It is your former promise.
</p>

<p class="drama">
MARTIUS.<br>
Sir, it is,<br>
And I am constant.—Titus Lartius, thou<br>
Shalt see me once more strike at Tullus’ face.<br>
What, art thou stiff? Stand’st out?
</p>

<p class="drama">
TITUS LARTIUS.<br>
No, Caius Martius,<br>
I’ll lean upon one crutch and fight with th’ other<br>
Ere stay behind this business.
</p>

<p class="drama">
MENENIUS.<br>
O, true bred!
</p>

<p class="drama">
FIRST SENATOR.<br>
Your company to th’ Capitol, where I know<br>
Our greatest friends attend us.
</p>

<p class="drama">
TITUS LARTIUS.<br>
Lead you on.<br>
Follow Cominius. We must follow you;<br>
Right worthy your priority.
</p>

<p class="drama">
COMINIUS.<br>
Noble Martius.
</p>

<p class="drama">
FIRST SENATOR.<br>
[<i>To the Citizens</i>.]<br>
Hence to your homes, begone.
</p>

<p class="drama">
MARTIUS.<br>
Nay, let them follow.<br>
The Volsces have much corn; take these rats thither<br>
To gnaw their garners. Worshipful mutineers,<br>
Your valour puts well forth. Pray follow.
</p>

<p class="right">
[<i>Exeunt. <span class="charname">Sicinius</span> and
<span class="charname">Brutus</span> remain</i>.]
</p>

<p class="drama">
SICINIUS.<br>
Was ever man so proud as is this Martius?
</p>

<p class="drama">
BRUTUS.<br>
He has no equal.
</p>

<p class="drama">
SICINIUS.<br>
When we were chosen tribunes for the people—
</p>

<p class="drama">
BRUTUS.<br>
Marked you his lip and eyes?
</p>

<p class="drama">
SICINIUS.<br>
Nay, but his taunts.
</p>

<p class="drama">
BRUTUS.<br>
Being moved, he will not spare to gird the gods.
</p>

<p class="drama">
SICINIUS.<br>
Bemock the modest moon.
</p>

<p class="drama">
BRUTUS.<br>
The present wars devour him! He is grown<br>
Too proud to be so valiant.
</p>

<p class="drama">
SICINIUS.<br>
Such a nature,<br>
Tickled with good success, disdains the shadow<br>
Which he treads on at noon. But I do wonder<br>
His insolence can brook to be commanded<br>
Under Cominius.
</p>

<p class="drama">
BRUTUS.<br>
Fame, at the which he aims,<br>
In whom already he’s well graced, cannot<br>
Better be held nor more attained than by<br>
A place below the first; for what miscarries<br>
Shall be the General’s fault, though he perform<br>
To th’ utmost of a man, and giddy censure<br>
Will then cry out of Martius “O, if he<br>
Had borne the business!”
</p>

<p class="drama">
SICINIUS.<br>
Besides, if things go well,<br>
Opinion that so sticks on Martius shall<br>
Of his demerits rob Cominius.
</p>

<p class="drama">
BRUTUS.<br>
Come.<br>
Half all Cominius’ honours are to Martius,<br>
Though Martius earned them not, and all his faults<br>
To Martius shall be honours, though indeed<br>
In aught he merit not.
</p>

<p class="drama">
SICINIUS.<br>
Let’s hence and hear<br>
How the dispatch is made, and in what fashion,<br>
More than in singularity, he goes<br>
Upon this present action.
</p>

<p class="drama">
BRUTUS.<br>
Let’s along.
</p>


<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneI_6.2"></a><b>SCENE II. Corioles. The Senate House</b></h3>

<p class="scenedesc">
Enter <span class="charname">Tullus Aufidius</span> with Senators of Corioles.
</p>

<p class="drama">
FIRST SENATOR.<br>
So, your opinion is, Aufidius,<br>
That they of Rome are entered in our counsels<br>
And know how we proceed.
</p>

<p class="drama">
AUFIDIUS.<br>
Is it not yours?<br>
What ever have been thought on in this state<br>
That could be brought to bodily act ere Rome<br>
Had circumvention? ’Tis not four days gone<br>
Since I heard thence. These are the words—I think<br>
I have the letter here. Yes, here it is.<br>
[<i>Reads</i>.] <i>They have pressed a power, but it is not known<br>
Whether for east or west. The dearth is great.<br>
The people mutinous; and, it is rumoured,<br>
Cominius, Martius your old enemy,<br>
Who is of Rome worse hated than of you,—<br>
And Titus Lartius, a most valiant Roman,<br>
These three lead on this preparation<br>
Whither ’tis bent. Most likely ’tis for you.<br>
Consider of it.</i>
</p>

<p class="drama">
FIRST SENATOR.<br>
Our army’s in the field.<br>
We never yet made doubt but Rome was ready<br>
To answer us.
</p>

<p class="drama">
AUFIDIUS.<br>
Nor did you think it folly<br>
To keep your great pretences veiled till when<br>
They needs must show themselves, which, in the hatching,<br>
It seemed, appeared to Rome. By the discovery<br>
We shall be shortened in our aim, which was<br>
To take in many towns ere almost Rome<br>
Should know we were afoot.
</p>

<p class="drama">
SECOND SENATOR.<br>
Noble Aufidius,<br>
Take your commission; hie you to your bands.<br>
Let us alone to guard Corioles.<br>
If they set down before’s, for the remove<br>
Bring up your army. But I think you’ll find<br>
They’ve not prepared for us.
</p>

<p class="drama">
AUFIDIUS.<br>
O, doubt not that;<br>
I speak from certainties. Nay, more,<br>
Some parcels of their power are forth already,<br>
And only hitherward. I leave your Honours.<br>
If we and Caius Martius chance to meet,<br>
’Tis sworn between us we shall ever strike<br>
Till one can do no more.
</p>

<p class="drama">
ALL.<br>
The gods assist you!
</p>

<p class="drama">
AUFIDIUS.<br>
And keep your Honours safe!
</p>

<p class="drama">
FIRST SENATOR.<br>
Farewell.
</p>

<p class="drama">
SECOND SENATOR.<br>
Farewell.
</p>

<p class="drama">
ALL.<br>
Farewell.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneI_6.3"></a><b>SCENE III. Rome. An apartment in Martius’ house</b></h3>

<p class="scenedesc">
Enter <span class="charname">Volumnia</span> and <span class="charname">Virgilia</span>, mother and wife to Martius. They set them
down on two low stools and sew.
</p>

<p class="drama">
VOLUMNIA.<br>
I pray you, daughter, sing, or express yourself in a more comfortable sort. If
my son were my husband, I should freelier rejoice in that absence wherein he
won honour than in the embracements of his bed where he would show most love.
When yet he was but tender-bodied and the only son of my womb, when youth with
comeliness plucked all gaze his way, when for a day of kings’ entreaties a
mother should not sell him an hour from her beholding, I, considering how
honour would become such a person—that it was no better than picture-like to
hang by th’ wall, if renown made it not stir—was pleased to let him seek danger
where he was like to find fame. To a cruel war I sent him, from whence he
returned, his brows bound with oak. I tell thee, daughter, I sprang not more in
joy at first hearing he was a man-child than now in first seeing he had proved
himself a man.
</p>

<p class="drama">
VIRGILIA.<br>
But had he died in the business, madam, how then?
</p>

<p class="drama">
VOLUMNIA.<br>
Then his good report should have been my son; I therein would have found issue.
Hear me profess sincerely: had I a dozen sons, each in my love alike and none
less dear than thine and my good Martius, I had rather had eleven die nobly for
their country than one voluptuously surfeit out of action.
</p>

<p class="scenedesc">
Enter a <span class="charname">Gentlewoman</span>.
</p>

<p class="drama">
GENTLEWOMAN.<br>
Madam, the Lady Valeria is come to visit you.
</p>

<p class="drama">
VIRGILIA.<br>
Beseech you, give me leave to retire myself.
</p>

<p class="drama">
VOLUMNIA.<br>
Indeed you shall not.<br>
Methinks I hear hither your husband’s drum,<br>
See him pluck Aufidius down by th’ hair;<br>
As children from a bear, the Volsces shunning him.<br>
Methinks I see him stamp thus and call thus:<br>
“Come on, you cowards! You were got in fear,<br>
Though you were born in Rome.” His bloody brow<br>
With his mailed hand then wiping, forth he goes<br>
Like to a harvestman that’s tasked to mow<br>
Or all or lose his hire.
</p>

<p class="drama">
VIRGILIA.<br>
His bloody brow? O Jupiter, no blood!
</p>

<p class="drama">
VOLUMNIA.<br>
Away, you fool! It more becomes a man<br>
Than gilt his trophy. The breasts of Hecuba,<br>
When she did suckle Hector, looked not lovelier<br>
Than Hector’s forehead when it spit forth blood<br>
At Grecian sword, contemning.—Tell Valeria<br>
We are fit to bid her welcome.
</p>

<p class="right">[<i>Exit <span class="charname">Gentlewoman</span>.</i>]</p>

<p class="drama">
VIRGILIA.<br>
Heavens bless my lord from fell Aufidius!
</p>

<p class="drama">
VOLUMNIA.<br>
He’ll beat Aufidius’ head below his knee<br>
And tread upon his neck.
</p>

<p class="scenedesc">
Enter <span class="charname">Valeria</span> with an Usher and a
<span class="charname">Gentlewoman</span>.
</p>

<p class="drama">
VALERIA.<br>
My ladies both, good day to you.
</p>

<p class="drama">
VOLUMNIA.<br>
Sweet madam.
</p>

<p class="drama">
VIRGILIA.<br>
I am glad to see your Ladyship.
</p>

<p class="drama">
VALERIA.<br>
How do you both? You are manifest housekeepers. What are you sewing here? A
fine spot, in good faith. How does your little son?
</p>

<p class="drama">
VIRGILIA.<br>
I thank your Ladyship; well, good madam.
</p>

<p class="drama">
VOLUMNIA.<br>
He had rather see the swords and hear a drum than look upon his schoolmaster.
</p>

<p class="drama">
VALERIA.<br>
O’ my word, the father’s son! I’ll swear ’tis a very pretty boy. O’ my troth, I
looked upon him o’ Wednesday half an hour together. H’as such a confirmed
countenance. I saw him run after a gilded butterfly, and when he caught it, he
let it go again, and after it again, and over and over he comes, and up again,
catched it again. Or whether his fall enraged him or how ’twas, he did so set
his teeth and tear it. O, I warrant how he mammocked it!
</p>

<p class="drama">
VOLUMNIA.<br>
One on’s father’s moods.
</p>

<p class="drama">
VALERIA.<br>
Indeed, la, ’tis a noble child.
</p>

<p class="drama">
VIRGILIA.<br>
A crack, madam.
</p>

<p class="drama">
VALERIA.<br>
Come, lay aside your stitchery. I must have you play the idle huswife with me
this afternoon.
</p>

<p class="drama">
VIRGILIA.<br>
No, good madam, I will not out of doors.
</p>

<p class="drama">
VALERIA.<br>
Not out of doors?
</p>

<p class="drama">
VOLUMNIA.<br>
She shall, she shall.
</p>

<p class="drama">
VIRGILIA.<br>
Indeed, no, by your patience. I’ll not over the threshold till my lord return
from the wars.
</p>

<p class="drama">
VALERIA.<br>
Fie, you confine yourself most unreasonably. Come, you must go visit the good
lady that lies in.
</p>

<p class="drama">
VIRGILIA.<br>
I will wish her speedy strength and visit her with my prayers, but I cannot go
thither.
</p>

<p class="drama">
VOLUMNIA.<br>
Why, I pray you?
</p>

<p class="drama">
VIRGILIA.<br>
’Tis not to save labour, nor that I want love.
</p>

<p class="drama">
VALERIA.<br>
You would be another Penelope. Yet they say all the yarn she spun in Ulysses’
absence did but fill Ithaca full of moths. Come, I would your cambric were
sensible as your finger, that you might leave pricking it for pity. Come, you
shall go with us.
</p>

<p class="drama">
VIRGILIA.<br>
No, good madam, pardon me; indeed, I will not forth.
</p>

<p class="drama">
VALERIA.<br>
In truth, la, go with me, and I’ll tell you excellent news of your husband.
</p>

<p class="drama">
VIRGILIA.<br>
O, good madam, there can be none yet.
</p>

<p class="drama">
VALERIA.<br>
Verily, I do not jest with you. There came news from him last night.
</p>

<p class="drama">
VIRGILIA.<br>
Indeed, madam!
</p>

<p class="drama">
VALERIA.<br>
In earnest, it’s true. I heard a senator speak it. Thus it is: the Volsces have
an army forth, against whom Cominius the General is gone with one part of our
Roman power. Your lord and Titus Lartius are set down before their city
Corioles. They nothing doubt prevailing, and to make it brief wars. This is
true, on mine honour, and so, I pray, go with us.
</p>

<p class="drama">
VIRGILIA.<br>
Give me excuse, good madam. I will obey you in everything hereafter.
</p>

<p class="drama">
VOLUMNIA.<br>
Let her alone, lady. As she is now, she will but disease our better mirth.
</p>

<p class="drama">
VALERIA.<br>
In troth, I think she would.—Fare you well, then.—Come, good sweet
lady.—Prithee, Virgilia, turn thy solemness out o’ door, and go along with us.
</p>

<p class="drama">
VIRGILIA.<br>
No, at a word, madam. Indeed I must not. I wish you much mirth.
</p>

<p class="drama">
VALERIA.<br>
Well then, farewell.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneI_6.4"></a><b>SCENE IV. Before Corioles</b></h3>

<p class="scenedesc">
Enter <span class="charname">Martius, Titus Lartius</span>, with drum and
colours, with Captains and Soldiers, as before the city of Corioles. To them a
<span class="charname">Messenger</span>.
</p>

<p class="drama">
MARTIUS.<br>
Yonder comes news. A wager they have met.
</p>

<p class="drama">
LARTIUS.<br>
My horse to yours, no.
</p>

<p class="drama">
MARTIUS.<br>
’Tis done.
</p>

<p class="drama">
LARTIUS.<br>
Agreed.
</p>

<p class="drama">
MARTIUS.<br>
[<i>To Messenger</i>.] Say, has our general met the enemy?
</p>

<p class="drama">
MESSENGER.<br>
They lie in view but have not spoke as yet.
</p>

<p class="drama">
LARTIUS.<br>
So the good horse is mine.
</p>

<p class="drama">
MARTIUS.<br>
I’ll buy him of you.
</p>

<p class="drama">
LARTIUS.<br>
No, I’ll nor sell nor give him. Lend you him I will<br>
For half a hundred years.—Summon the town.
</p>

<p class="drama">
MARTIUS.<br>
How far off lie these armies?
</p>

<p class="drama">
MESSENGER.<br>
Within this mile and half.
</p>

<p class="drama">
MARTIUS.<br>
Then shall we hear their ’larum, and they ours.<br>
Now, Mars, I prithee, make us quick in work,<br>
That we with smoking swords may march from hence<br>
To help our fielded friends!—Come, blow thy blast.
</p>

<p class="right">
[<i>They sound a parley.</i>]
</p>

<p class="scenedesc">
Enter two <span class="charname">Senators</span> with others on the walls of Corioles.
</p>

<p class="drama">
Tullus Aufidius, is he within your walls?
</p>

<p class="drama">
FIRST SENATOR.<br>
No, nor a man that fears you less than he:<br>
That’s lesser than a little.<br>
[<i>Drum afar off</i>.]<br>
Hark, our drums<br>
Are bringing forth our youth. We’ll break our walls<br>
Rather than they shall pound us up. Our gates,<br>
Which yet seem shut, we have but pinned with rushes.<br>
They’ll open of themselves.<br>
[<i>Alarum far off</i>.]<br>
Hark you, far off!<br>
There is Aufidius. List what work he makes<br>
Amongst your cloven army.
</p>

<p class="drama">
MARTIUS.<br>
O, they are at it!
</p>

<p class="drama">
LARTIUS.<br>
Their noise be our instruction.—Ladders, ho!
</p>

<p class="scenedesc">
Enter the Army of the <span class="charname">Volsces</span> as through the city gates.
</p>

<p class="drama">
MARTIUS.<br>
They fear us not but issue forth their city.—<br>
Now put your shields before your hearts, and fight<br>
With hearts more proof than shields.—Advance, brave Titus.<br>
They do disdain us much beyond our thoughts,<br>
Which makes me sweat with wrath.—Come on, my fellows!<br>
He that retires, I’ll take him for a Volsce,<br>
And he shall feel mine edge.
</p>

<p class="right">[<i>Alarums. The Romans are beat back to their trenches. They
exit, with the <span class="charname">Volsces</span> following</i>.]</p>

<p class="scenedesc">
Enter <span class="charname">Martius</span> cursing, with Roman soldiers.
</p>

<p class="drama">
MARTIUS.<br>
All the contagion of the south light on you,<br>
You shames of Rome! You herd of—Boils and plagues<br>
Plaster you o’er, that you may be abhorred<br>
Farther than seen, and one infect another<br>
Against the wind a mile! You souls of geese,<br>
That bear the shapes of men, how have you run<br>
From slaves that apes would beat! Pluto and hell!<br>
All hurt behind. Backs red, and faces pale<br>
With flight and agued fear! Mend, and charge home,<br>
Or, by the fires of heaven, I’ll leave the foe<br>
And make my wars on you. Look to’t. Come on!<br>
If you’ll stand fast we’ll beat them to their wives,<br>
As they us to our trenches. Follow’s!
</p>

<p class="right">
[<i>Another alarum. The Volsces re-enter and are driven back to the gates of
Corioles, which open to admit them.</i>]
</p>

<p class="drama">
So, now the gates are ope. Now prove good seconds!<br>
’Tis for the followers fortune widens them,<br>
Not for the fliers. Mark me, and do the like.
</p>

<p class="right">[<i><span class="charname">Martius</span> follows the fleeing
Volsces through the gates, and is shut in.</i>]</p>

<p class="drama">
FIRST SOLDIER.<br>
Foolhardiness, not I.
</p>

<p class="drama">
SECOND SOLDIER.<br>
Nor I.
</p>

<p class="drama">
FIRST SOLDIER.<br>
See, they have shut him in.
</p>

<p class="right">[<i>Alarum continues.</i>]</p>

<p class="drama">
ALL.<br>
To th’ pot, I warrant him.
</p>

<p class="scenedesc">
Enter <span class="charname">Titus Lartius</span>.
</p>

<p class="drama">
LARTIUS.<br>
What is become of Martius?
</p>

<p class="drama">
ALL.<br>
Slain, sir, doubtless.
</p>

<p class="drama">
FIRST SOLDIER.<br>
Following the fliers at the very heels,<br>
With them he enters, who upon the sudden<br>
Clapped to their gates. He is himself alone,<br>
To answer all the city.
</p>

<p class="drama">
LARTIUS.<br>
O noble fellow,<br>
Who sensibly outdares his senseless sword,<br>
And when it bows, stand’st up! Thou art left, Martius.<br>
A carbuncle entire, as big as thou art,<br>
Were not so rich a jewel. Thou wast a soldier<br>
Even to Cato’s wish, not fierce and terrible<br>
Only in strokes, but with thy grim looks and<br>
The thunderlike percussion of thy sounds<br>
Thou mad’st thine enemies shake, as if the world<br>
Were feverous and did tremble.
</p>

<p class="scenedesc">
Enter <span class="charname">Martius</span>, bleeding, assaulted by the enemy.
</p>

<p class="drama">
FIRST SOLDIER.<br>
Look, sir.
</p>

<p class="drama">
LARTIUS.<br>
O, ’tis Martius!<br>
Let’s fetch him off or make remain alike.
</p>

<p class="right">[<i>They fight, and all enter the city.</i>]</p>

<h3> <a id="sceneI_6.5"></a><b>SCENE V. Within Corioles. A street</b></h3>

<p class="scenedesc">
Enter certain <span class="charname">Romans</span>, with spoils.
</p>

<p class="drama">
FIRST ROMAN.<br>
This will I carry to Rome.
</p>

<p class="drama">
SECOND ROMAN.<br>
And I this.
</p>

<p class="drama">
THIRD ROMAN.<br>
A murrain on’t! I took this for silver.
</p>

<p class="scenedesc">
Enter <span class="charname">Martius</span> and
<span class="charname">Titus Lartius</span> with a Trumpet.
</p>

<p class="drama">
MARTIUS.<br>
See here these movers that do prize their hours<br>
At a cracked drachma. Cushions, leaden spoons,<br>
Irons of a doit, doublets that hangmen would<br>
Bury with those that wore them, these base slaves,<br>
Ere yet the fight be done, pack up. Down with them!
</p>

<p class="right">[<i>Exit the Romans with spoils.</i>]</p>

<p class="right">[<i>Alarum continues still afar off.</i>]</p>

<p class="drama">
And hark, what noise the General makes! To him!<br>
There is the man of my soul’s hate, Aufidius,<br>
Piercing our Romans. Then, valiant Titus, take<br>
Convenient numbers to make good the city,<br>
Whilst I, with those that have the spirit, will haste<br>
To help Cominius.
</p>

<p class="drama">
LARTIUS.<br>
Worthy sir, thou bleed’st.<br>
Thy exercise hath been too violent<br>
For a second course of fight.
</p>

<p class="drama">
MARTIUS.<br>
Sir, praise me not.<br>
My work hath yet not warmed me. Fare you well.<br>
The blood I drop is rather physical<br>
Than dangerous to me. To Aufidius thus<br>
I will appear and fight.
</p>

<p class="drama">
LARTIUS.<br>
Now the fair goddess Fortune<br>
Fall deep in love with thee, and her great charms<br>
Misguide thy opposers’ swords! Bold gentleman,<br>
Prosperity be thy page!
</p>

<p class="drama">
MARTIUS.<br>
Thy friend no less<br>
Than those she placeth highest! So farewell.
</p>

<p class="drama">
LARTIUS.<br>
Thou worthiest Martius!
</p>

<p class="right">[<i>Exit <span class="charname">Martius</span>.</i>]</p>

<p class="drama">
Go sound thy trumpet in the marketplace.<br>
Call thither all the officers o’ th’ town,<br>
Where they shall know our mind. Away!
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneI_6.6"></a><b>SCENE VI. Near the camp of Cominius</b></h3>

<p class="scenedesc">
Enter <span class="charname">Cominius</span> as it were in retire, with Soldiers.
</p>

<p class="drama">
COMINIUS.<br>
Breathe you, my friends. Well fought! We are come off<br>
Like Romans, neither foolish in our stands<br>
Nor cowardly in retire. Believe me, sirs,<br>
We shall be charged again. Whiles we have struck,<br>
By interims and conveying gusts we have heard<br>
The charges of our friends. The Roman gods<br>
Lead their successes as we wish our own,<br>
That both our powers, with smiling fronts encount’ring,<br>
May give you thankful sacrifice!
</p>

<p class="scenedesc">
Enter a <span class="charname">Messenger</span>.
</p>

<p class="drama">
Thy news?
</p>

<p class="drama">
MESSENGER.<br>
The citizens of Corioles have issued,<br>
And given to Lartius and to Martius battle.<br>
I saw our party to their trenches driven,<br>
And then I came away.
</p>

<p class="drama">
COMINIUS.<br>
Though thou speakest truth,<br>
Methinks thou speak’st not well. How long is’t since?
</p>

<p class="drama">
MESSENGER.<br>
Above an hour, my lord.
</p>

<p class="drama">
COMINIUS.<br>
’Tis not a mile; briefly we heard their drums.<br>
How couldst thou in a mile confound an hour<br>
And bring thy news so late?
</p>

<p class="drama">
MESSENGER.<br>
Spies of the Volsces<br>
Held me in chase, that I was forced to wheel<br>
Three or four miles about; else had I, sir,<br>
Half an hour since brought my report.
</p>

<p class="right">[<i>Exit <span class="charname">Messenger</span>.</i>]</p>

<p class="scenedesc">
Enter <span class="charname">Martius</span>, bloody.
</p>

<p class="drama">
COMINIUS.<br>
Who’s yonder,<br>
That does appear as he were flayed? O gods,<br>
He has the stamp of Martius, and I have<br>
Before-time seen him thus.
</p>

<p class="drama">
MARTIUS.<br>
Come I too late?
</p>

<p class="drama">
COMINIUS.<br>
The shepherd knows not thunder from a tabor<br>
More than I know the sound of Martius’ tongue<br>
From every meaner man.
</p>

<p class="drama">
MARTIUS.<br>
Come I too late?
</p>

<p class="drama">
COMINIUS.<br>
Ay, if you come not in the blood of others,<br>
But mantled in your own.
</p>

<p class="drama">
MARTIUS.<br>
O, let me clip you<br>
In arms as sound as when I wooed, in heart<br>
As merry as when our nuptial day was done<br>
And tapers burned to bedward!
</p>

<p class="drama">
COMINIUS.<br>
Flower of warriors, how is’t with Titus Lartius?
</p>

<p class="drama">
MARTIUS.<br>
As with a man busied about decrees,<br>
Condemning some to death and some to exile;<br>
Ransoming him or pitying, threat’ning the other;<br>
Holding Corioles in the name of Rome<br>
Even like a fawning greyhound in the leash,<br>
To let him slip at will.
</p>

<p class="drama">
COMINIUS.<br>
Where is that slave<br>
Which told me they had beat you to your trenches?<br>
Where’s he? Call him hither.
</p>

<p class="drama">
MARTIUS.<br>
Let him alone.<br>
He did inform the truth. But for our gentlemen,<br>
The common file—a plague! Tribunes for them!—<br>
The mouse ne’er shunned the cat as they did budge<br>
From rascals worse than they.
</p>

<p class="drama">
COMINIUS.<br>
But how prevailed you?
</p>

<p class="drama">
MARTIUS.<br>
Will the time serve to tell? I do not think.<br>
Where is the enemy? Are you lords o’ th’ field?<br>
If not, why cease you till you are so?
</p>

<p class="drama">
COMINIUS.<br>
Martius, we have at disadvantage fought,<br>
And did retire to win our purpose.
</p>

<p class="drama">
MARTIUS.<br>
How lies their battle? Know you on which side<br>
They have placed their men of trust?
</p>

<p class="drama">
COMINIUS.<br>
As I guess, Martius,<br>
Their bands i’ th’ vaward are the Antiates,<br>
Of their best trust; o’er them Aufidius,<br>
Their very heart of hope.
</p>

<p class="drama">
MARTIUS.<br>
I do beseech you,<br>
By all the battles wherein we have fought,<br>
By th’ blood we have shed together, by th’ vows we have made<br>
To endure friends, that you directly set me<br>
Against Aufidius and his Antiates,<br>
And that you not delay the present, but,<br>
Filling the air with swords advanced and darts,<br>
We prove this very hour.
</p>

<p class="drama">
COMINIUS.<br>
Though I could wish<br>
You were conducted to a gentle bath<br>
And balms applied to you, yet dare I never<br>
Deny your asking. Take your choice of those<br>
That best can aid your action.
</p>

<p class="drama">
MARTIUS.<br>
Those are they<br>
That most are willing. If any such be here—<br>
As it were sin to doubt—that love this painting<br>
Wherein you see me smeared; if any fear<br>
Lesser his person than an ill report;<br>
If any think brave death outweighs bad life,<br>
And that his country’s dearer than himself;<br>
Let him alone, or so many so minded,<br>
Wave thus to express his disposition<br>
And follow Martius.
</p>

<p class="right">
[<i>He waves his sword.</i>]
</p>

<p class="right">
[<i>They all shout and wave their swords, take him up in their arms, and cast
up their caps.</i>]
</p>

<p class="drama">
O, me alone! Make you a sword of me?<br>
If these shows be not outward, which of you<br>
But is four Volsces? None of you but is<br>
Able to bear against the great Aufidius<br>
A shield as hard as his. A certain number,<br>
Though thanks to all, must I select from all.<br>
The rest shall bear the business in some other fight,<br>
As cause will be obeyed. Please you to march,<br>
And I shall quickly draw out my command,<br>
Which men are best inclined.
</p>

<p class="drama">
COMINIUS.<br>
March on, my fellows.<br>
Make good this ostentation, and you shall<br>
Divide in all with us.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneI_6.7"></a><b>SCENE VII. The gates of Corioles</b></h3>

<p class="scenedesc">
<span class="charname">Titus Lartius</span>, having set a guard upon Corioles,
going with drum and trumpet toward <span class="charname">Cominius</span> and
<span class="charname">Caius Martius</span>, enters with a <span class="charname">Lieutenant</span>, other Soldiers, and a Scout.
</p>

<p class="drama">
LARTIUS.<br>
So, let the ports be guarded. Keep your duties<br>
As I have set them down. If I do send, dispatch<br>
Those centuries to our aid; the rest will serve<br>
For a short holding. If we lose the field,<br>
We cannot keep the town.
</p>

<p class="drama">
LIEUTENANT.<br>
Fear not our care, sir.
</p>

<p class="drama">
LARTIUS.<br>
Hence, and shut your gates upon’s.<br>
Our guider, come. To th’ Roman camp conduct us.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneI_6.8"></a><b>SCENE VIII. A field of battle between the Roman and the Volscian camps</b></h3>

<p class="scenedesc">
Alarum, as in battle. Enter <span class="charname">Martius</span> and
<span class="charname">Aufidius</span> at several doors.
</p>

<p class="drama">
MARTIUS.<br>
I’ll fight with none but thee, for I do hate thee<br>
Worse than a promise-breaker.
</p>

<p class="drama">
AUFIDIUS.<br>
We hate alike.<br>
Not Afric owns a serpent I abhor<br>
More than thy fame and envy. Fix thy foot.
</p>

<p class="drama">
MARTIUS.<br>
Let the first budger die the other’s slave,<br>
And the gods doom him after!
</p>

<p class="drama">
AUFIDIUS.<br>
If I fly, Martius,<br>
Hollo me like a hare.
</p>

<p class="drama">
MARTIUS.<br>
Within these three hours, Tullus,<br>
Alone I fought in your Corioles’ walls,<br>
And made what work I pleased. ’Tis not my blood<br>
Wherein thou seest me masked. For thy revenge<br>
Wrench up thy power to th’ highest.
</p>

<p class="drama">
AUFIDIUS.<br>
Wert thou the Hector<br>
That was the whip of your bragged progeny,<br>
Thou shouldst not scape me here.
</p>

<p class="right">[<i>Here they fight, and certain Volsces come to the aid of
<span class="charname">Aufidius</span>.</i>]</p>

<p class="drama">
Officious and not valiant, you have shamed me<br>
In your condemned seconds.
</p>

<p class="right">
[<i><span class="charname">Martius</span> fights till they be driven in
breathless. <span class="charname">Aufidius</span> and <span class="charname">Martius</span> exit, separately.</i>]
</p>

<h3> <a id="sceneI_6.9"></a><b>SCENE IX. The Roman camp</b></h3>

<p class="scenedesc">
Alarum. A retreat is sounded. Flourish. Enter, at one door, <span class="charname">Cominius</span> with the Romans; at another door, <span class="charname">Martius</span>, with his arm in a scarf.
</p>

<p class="drama">
COMINIUS.<br>
If I should tell thee o’er this thy day’s work,<br>
Thou’t not believe thy deeds. But I’ll report it<br>
Where senators shall mingle tears with smiles;<br>
Where great patricians shall attend and shrug,<br>
I’ th’ end admire; where ladies shall be frighted<br>
And, gladly quaked, hear more; where the dull tribunes,<br>
That with the fusty plebeians hate thine honours,<br>
Shall say against their hearts “We thank the gods<br>
Our Rome hath such a soldier.”<br>
Yet cam’st thou to a morsel of this feast,<br>
Having fully dined before.
</p>

<p class="scenedesc">
Enter <span class="charname">Titus Lartius</span> with his power, from the pursuit.
</p>

<p class="drama">
LARTIUS.<br>
O general,<br>
Here is the steed, we the caparison.<br>
Hadst thou beheld—
</p>

<p class="drama">
MARTIUS.<br>
Pray now, no more. My mother,<br>
Who has a charter to extol her blood,<br>
When she does praise me grieves me. I have done<br>
As you have done—that’s what I can;<br>
Induced as you have been—that’s for my country.<br>
He that has but effected his good will<br>
Hath overta’en mine act.
</p>

<p class="drama">
COMINIUS.<br>
You shall not be<br>
The grave of your deserving. Rome must know<br>
The value of her own. ’Twere a concealment<br>
Worse than a theft, no less than a traducement,<br>
To hide your doings and to silence that<br>
Which, to the spire and top of praises vouched,<br>
Would seem but modest. Therefore, I beseech you—<br>
In sign of what you are, not to reward<br>
What you have done—before our army hear me.
</p>

<p class="drama">
MARTIUS.<br>
I have some wounds upon me, and they smart<br>
To hear themselves remembered.
</p>

<p class="drama">
COMINIUS.<br>
Should they not,<br>
Well might they fester ’gainst ingratitude<br>
And tent themselves with death. Of all the horses—<br>
Whereof we have ta’en good and good store—of all<br>
The treasure in this field achieved and city,<br>
We render you the tenth, to be ta’en forth<br>
Before the common distribution<br>
At your only choice.
</p>

<p class="drama">
MARTIUS.<br>
I thank you, general,<br>
But cannot make my heart consent to take<br>
A bribe to pay my sword. I do refuse it;<br>
And stand upon my common part with those<br>
That have beheld the doing.
</p>

<p class="right">
[<i>A long flourish. They all cry “Martius, Martius!” and cast up their caps and
lances. <span class="charname">Cominius</span> and <span class="charname">Lartius</span> stand bare.</i>]
</p>

<p class="drama">
May these same instruments which, you profane,<br>
Never sound more! When drums and trumpets shall<br>
I’ th’ field prove flatterers, let courts and cities be<br>
Made all of false-faced soothing! When steel grows soft<br>
Soft as the parasite’s silk, let him be made<br>
An ovator for the wars! No more, I say.<br>
For that I have not washed my nose that bled,<br>
Or foiled some debile wretch—which, without note,<br>
Here’s many else have done—you shout me forth<br>
In acclamations hyperbolical,<br>
As if I loved my little should be dieted<br>
In praises sauced with lies.
</p>

<p class="drama">
COMINIUS.<br>
Too modest are you,<br>
More cruel to your good report than grateful<br>
To us that give you truly. By your patience,<br>
If ’gainst yourself you be incensed, we’ll put you,<br>
Like one that means his proper harm, in manacles,<br>
Then reason safely with you. Therefore be it known,<br>
As to us to all the world, that Caius Martius<br>
Wears this war’s garland, in token of the which<br>
My noble steed, known to the camp, I give him,<br>
With all his trim belonging. And from this time,<br>
For what he did before Corioles, call him,<br>
With all th’ applause and clamour of the host,<br>
Caius Martius Coriolanus! Bear<br>
Th’ addition nobly ever!
</p>

<p class="right">[<i>Flourish. Trumpets sound, and drums.</i>]</p>

<p class="drama">
ALL.<br>
Caius Martius Coriolanus!
</p>

<p class="drama">
CORIOLANUS.<br>
I will go wash;<br>
And when my face is fair, you shall perceive<br>
Whether I blush or no. Howbeit, I thank you.<br>
I mean to stride your steed and at all times<br>
To undercrest your good addition<br>
To th’ fairness of my power.
</p>

<p class="drama">
COMINIUS.<br>
So, to our tent,<br>
Where, ere we do repose us, we will write<br>
To Rome of our success.—You, Titus Lartius,<br>
Must to Corioles back. Send us to Rome<br>
The best, with whom we may articulate<br>
For their own good and ours.
</p>

<p class="drama">
LARTIUS.<br>
I shall, my lord.
</p>

<p class="drama">
CORIOLANUS.<br>
The gods begin to mock me. I, that now<br>
Refused most princely gifts, am bound to beg<br>
Of my lord general.
</p>

<p class="drama">
COMINIUS.<br>
Take’t, ’tis yours. What is’t?
</p>

<p class="drama">
CORIOLANUS.<br>
I sometime lay here in Corioles<br>
At a poor man’s house; he used me kindly.<br>
He cried to me; I saw him prisoner;<br>
But then Aufidius was within my view,<br>
And wrath o’erwhelmed my pity. I request you<br>
To give my poor host freedom.
</p>

<p class="drama">
COMINIUS.<br>
O, well begged!<br>
Were he the butcher of my son, he should<br>
Be free as is the wind.—Deliver him, Titus.
</p>

<p class="drama">
LARTIUS.<br>
Martius, his name?
</p>

<p class="drama">
CORIOLANUS.<br>
By Jupiter, forgot!<br>
I am weary; yea, my memory is tired.<br>
Have we no wine here?
</p>

<p class="drama">
COMINIUS.<br>
Go we to our tent.<br>
The blood upon your visage dries; ’tis time<br>
It should be looked to. Come.
</p>

<p class="right">[<i>A flourish of cornets. Exeunt.</i>]</p>

<h3> <a id="sceneI_6.10"></a><b>SCENE X. The camp of the Volsces</b></h3>

<p class="scenedesc">
A flourish. Cornets. Enter <span class="charname">Tullus Aufidius</span>,
bloody, with two or three soldiers.
</p>

<p class="drama">
AUFIDIUS.<br>
The town is ta’en.
</p>

<p class="drama">
SOLDIER.<br>
’Twill be delivered back on good condition.
</p>

<p class="drama">
AUFIDIUS.<br>
Condition?<br>
I would I were a Roman, for I cannot,<br>
Being a Volsce, be that I am. Condition?<br>
What good condition can a treaty find<br>
I’ th’ part that is at mercy? Five times, Martius,<br>
I have fought with thee; so often hast thou beat me<br>
And wouldst do so, I think, should we encounter<br>
As often as we eat. By th’ elements,<br>
If e’er again I meet him beard to beard,<br>
He’s mine or I am his. Mine emulation<br>
Hath not that honour in’t it had; for where<br>
I thought to crush him in an equal force,<br>
True sword to sword, I’ll potch at him some way,<br>
Or wrath or craft may get him.
</p>

<p class="drama">
SOLDIER.<br>
He’s the devil.
</p>

<p class="drama">
AUFIDIUS.<br>
Bolder, though not so subtle. My valour’s poisoned<br>
With only suff’ring stain by him; for him<br>
Shall fly out of itself. Nor sleep nor sanctuary,<br>
Being naked, sick, nor fane nor Capitol,<br>
The prayers of priests nor times of sacrifice,<br>
Embarquements all of fury, shall lift up<br>
Their rotten privilege and custom ’gainst<br>
My hate to Martius. Where I find him, were it<br>
At home, upon my brother’s guard, even there,<br>
Against the hospitable canon, would I<br>
Wash my fierce hand in’s heart. Go you to th’ city;<br>
Learn how ’tis held and what they are that must<br>
Be hostages for Rome.
</p>

<p class="drama">
SOLDIER.<br>
Will not you go?
</p>

<p class="drama">
AUFIDIUS.<br>
I am attended at the cypress grove. I pray you—<br>
’Tis south the city mills,—bring me word thither<br>
How the world goes, that to the pace of it<br>
I may spur on my journey.
</p>

<p class="drama">
SOLDIER.<br>
I shall, sir.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

