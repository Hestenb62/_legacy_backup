<h2> <a id="sceneV_33.1"></a><b>ACT V</b></h2>

<h3> <b>SCENE I. The woods. Before Timon’s cave</b></h3>

<p class="scenedesc">
Enter <span class="charname">Poet</span> and
<span class="charname">Painter</span>.
</p>

<p class="drama">
PAINTER.<br>
As I took note of the place, it cannot be far where he abides.</p>

<p class="drama">
POET.<br>
What’s to be thought of him? Does the rumour hold for true that he is so
full of gold?</p>

<p class="drama">
PAINTER.<br>
Certain. Alcibiades reports it; Phrynia and Timandra had gold of him. He
likewise enriched poor straggling soldiers with great quantity. ’Tis said
he gave unto his steward a mighty sum.
</p>

<p class="drama">
POET.<br>
Then this breaking of his has been but a try for his friends?
</p>

<p class="drama">
PAINTER.<br>
Nothing else. You shall see him a palm in Athens again, and flourish with the
highest. Therefore ’tis not amiss we tender our loves to him in this
supposed distress of his. It will show honestly in us and is very likely to
load our purposes with what they travail for, if it be a just and true report
that goes of his having.</p>

<p class="drama">
POET.<br>
What have you now to present unto him?
</p>

<p class="drama">
PAINTER.<br>
Nothing at this time but my visitation; only I will promise him an excellent
piece.</p>

<p class="drama">
POET.<br>
I must serve him so too, tell him of an intent that’s coming toward
him.</p>

<p class="drama">
PAINTER.<br>
Good as the best. Promising is the very air o’ th’ time; it opens the
eyes of expectation. Performance is ever the duller for his act and, but in
the plainer and simpler kind of people, the deed of saying is quite out of use.
To promise is most courtly and fashionable; performance is a kind of will or
testament which argues a great sickness in his judgment that makes it.</p>

<p class="scenedesc">
Enter <span class="charname">Timon</span> from his cave.
</p>

<p class="drama">
TIMON.<br>
[<i>Aside</i>.] Excellent workman! Thou canst not paint a man so bad as is
thyself.</p>

<p class="drama">
POET.<br>
I am thinking what I shall say I have provided for him. It must be a
personating of himself, a satire against the softness of prosperity, with a
discovery of the infinite flatteries that follow youth and opulency.</p>

<p class="drama">
TIMON.<br>
[<i>Aside</i>.] Must thou needs stand for a villain in thine own work? Wilt
thou whip thine own faults in other men? Do so, I have gold for thee.
</p>

<p class="drama">
POET.<br>
Nay, let’s seek him.<br>
Then do we sin against our own estate<br>
When we may profit meet and come too late.
</p>

<p class="drama">
PAINTER.<br>
True.<br>
When the day serves, before black-cornered night,<br>
Find what thou want’st by free and offered light.<br>
Come.
</p>

<p class="drama">
TIMON.<br>
[<i>Aside</i>.] I’ll meet you at the turn. What a god’s gold,<br>
That he is worshipped in a baser temple<br>
Than where swine feed!<br>
’Tis thou that rigg’st the bark and plough’st the foam,<br>
Settlest admired reverence in a slave.<br>
To thee be worship, and thy saints for aye<br>
Be crowned with plagues, that thee alone obey!<br>
Fit I meet them.
</p>

<p class="right">[<i>He comes forward.</i>]</p>

<p class="drama">
POET.<br>
Hail, worthy Timon!
</p>

<p class="drama">
PAINTER.<br>
Our late noble master!
</p>

<p class="drama">
TIMON.<br>
Have I once lived to see two honest men?
</p>

<p class="drama">
POET.<br>
Sir,<br>
Having often of your open bounty tasted,<br>
Hearing you were retired, your friends fall’n off,<br>
Whose thankless natures—O abhorred spirits!<br>
Not all the whips of heaven are large enough—<br>
What, to you,<br>
Whose star-like nobleness gave life and influence<br>
To their whole being? I am rapt and cannot cover<br>
The monstrous bulk of this ingratitude<br>
With any size of words.
</p>

<p class="drama">
TIMON.<br>
Let it go naked. Men may see’t the better.<br>
You that are honest, by being what you are,<br>
Make them best seen and known.
</p>

<p class="drama">
PAINTER.<br>
He and myself<br>
Have travailed in the great shower of your gifts,<br>
And sweetly felt it.
</p>

<p class="drama">
TIMON.<br>
Ay, you are honest men.
</p>

<p class="drama">
PAINTER.<br>
We are hither come to offer you our service.
</p>

<p class="drama">
TIMON.<br>
Most honest men! Why, how shall I requite you?<br>
Can you eat roots and drink cold water? No?
</p>

<p class="drama">
BOTH.<br>
What we can do we’ll do, to do you service.
</p>

<p class="drama">
TIMON.<br>
Ye’re honest men. Ye’ve heard that I have gold,<br>
I am sure you have. Speak truth, you’re honest men.
</p>

<p class="drama">
PAINTER.<br>
So it is said, my noble lord; but therefore<br>
Came not my friend nor I.
</p>

<p class="drama">
TIMON.<br>
Good honest men! [<i>To Painter</i>.] Thou draw’st a counterfeit<br>
Best in all Athens. Thou’rt indeed the best,<br>
Thou counterfeit’st most lively.
</p>

<p class="drama">
PAINTER.<br>
So so, my lord.
</p>

<p class="drama">
TIMON.<br>
E’en so, sir, as I say. [<i>To the Poet</i>.] And for thy fiction,<br>
Why, thy verse swells with stuff so fine and smooth<br>
That thou art even natural in thine art.<br>
But for all this, my honest-natured friends,<br>
I must needs say you have a little fault.<br>
Marry, ’tis not monstrous in you, neither wish I<br>
You take much pains to mend.
</p>

<p class="drama">
BOTH.<br>
Beseech your honour<br>
To make it known to us.
</p>

<p class="drama">
TIMON.<br>
You’ll take it ill.
</p>

<p class="drama">
BOTH.<br>
Most thankfully, my lord.
</p>

<p class="drama">
TIMON.<br>
Will you indeed?
</p>

<p class="drama">
BOTH.<br>
Doubt it not, worthy lord.
</p>

<p class="drama">
TIMON.<br>
There’s never a one of you but trusts a knave<br>
That mightily deceives you.
</p>

<p class="drama">
BOTH.<br>
Do we, my lord?
</p>

<p class="drama">
TIMON.<br>
Ay, and you hear him cog, see him dissemble,<br>
Know his gross patchery, love him, feed him,<br>
Keep in your bosom, yet remain assured<br>
That he’s a made-up villain.
</p>

<p class="drama">
PAINTER.<br>
I know not such, my lord.
</p>

<p class="drama">
POET.<br>
Nor I.
</p>

<p class="drama">
TIMON.<br>
Look you, I love you well. I’ll give you gold.<br>
Rid me these villains from your companies,<br>
Hang them or stab them, drown them in a draught,<br>
Confound them by some course, and come to me,<br>
I’ll give you gold enough.
</p>

<p class="drama">
BOTH.<br>
Name them, my lord, let’s know them.
</p>

<p class="drama">
TIMON.<br>
You that way, and you this, but two in company.<br>
Each man apart, all single and alone,<br>
Yet an arch-villain keeps him company.<br>
[<i>To one</i>.] If where thou art, two villians shall not be,<br>
Come not near him. [<i>To the other</i>.] If thou wouldst not reside<br>
But where one villain is, then him abandon.<br>
Hence, pack! There’s gold. You came for gold, ye slaves.<br>
[<i>To one</i>.] You have work for me, there’s payment, hence!<br>
[<i>To the other</i>.] You are an alchemist; make gold of that.<br>
Out, rascal dogs!
</p>

<p class="right">[<i><span class="charname">Timon</span> drives them out and
then retires to his cave</i>]</p>

<h3> <a id="sceneV_33.2"></a><b>SCENE II. The same</b></h3>

<p class="scenedesc">
Enter <span class="charname">Flavius</span> and two
<span class="charname">Senators</span>.
</p>

<p class="drama">
FLAVIUS.<br>
It is vain that you would speak with Timon.<br>
For he is set so only to himself<br>
That nothing but himself which looks like man<br>
Is friendly with him.
</p>

<p class="drama">
FIRST SENATOR.<br>
Bring us to his cave.<br>
It is our part and promise to th’ Athenians<br>
To speak with Timon.
</p>

<p class="drama">
SECOND SENATOR.<br>
At all times alike<br>
Men are not still the same: ’twas time and griefs<br>
That framed him thus. Time, with his fairer hand,<br>
Offering the fortunes of his former days,<br>
The former man may make him. Bring us to him<br>
And chance it as it may.
</p>

<p class="drama">
FLAVIUS.<br>
Here is his cave.<br>
Peace and content be here! Lord Timon! Timon,<br>
Look out and speak to friends. The Athenians<br>
By two of their most reverend senate greet thee.<br>
Speak to them, noble Timon.
</p>

<p class="scenedesc">
Enter <span class="charname">Timon</span> out of his cave.
</p>

<p class="drama">
TIMON.<br>
Thou sun that comforts, burn! Speak and be hanged!<br>
For each true word, a blister, and each false<br>
Be as a cantherizing to the root o’ th’ tongue,<br>
Consuming it with speaking.
</p>

<p class="drama">
FIRST SENATOR.<br>
Worthy Timon—
</p>

<p class="drama">
TIMON.<br>
Of none but such as you, and you of Timon.
</p>

<p class="drama">
FIRST SENATOR.<br>
The senators of Athens greet thee, Timon.
</p>

<p class="drama">
TIMON.<br>
[<i>Aside</i>.] I thank them and would send them back the plague,<br>
Could I but catch it for them.
</p>

<p class="drama">
FIRST SENATOR.<br>
O, forget<br>
What we are sorry for ourselves in thee.<br>
The senators with one consent of love<br>
Entreat thee back to Athens, who have thought<br>
On special dignities, which vacant lie<br>
For thy best use and wearing.
</p>

<p class="drama">
SECOND SENATOR.<br>
They confess<br>
Toward thee forgetfulness too general gross,<br>
Which now the public body, which doth seldom<br>
Play the recanter, feeling in itself<br>
A lack of Timon’s aid, hath sense withal<br>
Of its own fall, restraining aid to Timon,<br>
And send forth us to make their sorrowed render,<br>
Together with a recompense more fruitful<br>
Than their offence can weigh down by the dram,<br>
Ay, even such heaps and sums of love and wealth,<br>
As shall to thee blot out what wrongs were theirs,<br>
And write in thee the figures of their love,<br>
Ever to read them thine.
</p>

<p class="drama">
TIMON.<br>
You witch me in it,<br>
Surprise me to the very brink of tears.<br>
Lend me a fool’s heart and a woman’s eyes<br>
And I’ll beweep these comforts, worthy senators.
</p>

<p class="drama">
FIRST SENATOR.<br>
Therefore so please thee to return with us,<br>
And of our Athens, thine and ours, to take<br>
The captainship, thou shalt be met with thanks,<br>
Allowed with absolute power, and thy good name<br>
Live with authority. So soon we shall drive back<br>
Of Alcibiades th’ approaches wild,<br>
Who like a boar too savage doth root up<br>
His country’s peace.
</p>

<p class="drama">
SECOND SENATOR.<br>
And shakes his threatening sword<br>
Against the walls of Athens.
</p>

<p class="drama">
FIRST SENATOR.<br>
Therefore, Timon—
</p>

<p class="drama">
TIMON.<br>
Well, sir, I will. Therefore I will, sir, thus:<br>
If Alcibiades kill my countrymen,<br>
Let Alcibiades know this of Timon,<br>
That Timon cares not. But if he sack fair Athens<br>
And take our goodly aged men by th’ beards,<br>
Giving our holy virgins to the stain<br>
Of contumelious, beastly, mad-brained war,<br>
Then let him know, and tell him Timon speaks it,<br>
In pity of our aged and our youth,<br>
I cannot choose but tell him that I care not;<br>
And—let him take’t at worst—for their knives care not<br>
While you have throats to answer. For myself,<br>
There’s not a whittle in th’ unruly camp<br>
But I do prize it at my love before<br>
The reverend’st throat in Athens. So I leave you<br>
To the protection of the prosperous gods,<br>
As thieves to keepers.
</p>

<p class="drama">
FLAVIUS.<br>
Stay not, all’s in vain.
</p>

<p class="drama">
TIMON.<br>
Why, I was writing of my epitaph;<br>
It will be seen tomorrow. My long sickness<br>
Of health and living now begins to mend<br>
And nothing brings me all things. Go, live still,<br>
Be Alcibiades your plague, you his,<br>
And last so long enough.
</p>

<p class="drama">
FIRST SENATOR.<br>
We speak in vain.
</p>

<p class="drama">
TIMON.<br>
But yet I love my country and am not<br>
One that rejoices in the common wrack,<br>
As common bruit doth put it.
</p>

<p class="drama">
FIRST SENATOR.<br>
That’s well spoke.
</p>

<p class="drama">
TIMON.<br>
Commend me to my loving countrymen.
</p>

<p class="drama">
FIRST SENATOR.<br>
These words become your lips as they pass through them.</p>

<p class="drama">
SECOND SENATOR.<br>
And enter in our ears like great triumphers<br>
In their applauding gates.
</p>

<p class="drama">
TIMON.<br>
Commend me to them,<br>
And tell them that to ease them of their griefs,<br>
Their fears of hostile strokes, their aches, losses,<br>
Their pangs of love, with other incident throes<br>
That nature’s fragile vessel doth sustain<br>
In life’s uncertain voyage, I will some kindness do them;<br>
I’ll teach them to prevent wild Alcibiades’ wrath.
</p>

<p class="drama">
FIRST SENATOR.<br>
[<i>Aside</i>.] I like this well, he will return again.
</p>

<p class="drama">
TIMON.<br>
I have a tree which grows here in my close<br>
That mine own use invites me to cut down,<br>
And shortly must I fell it. Tell my friends,<br>
Tell Athens, in the sequence of degree<br>
From high to low throughout, that whoso please<br>
To stop affliction, let him take his haste,<br>
Come hither ere my tree hath felt the axe<br>
And hang himself. I pray you do my greeting.
</p>

<p class="drama">
FLAVIUS.<br>
Trouble him no further; thus you still shall find him.
</p>

<p class="drama">
TIMON.<br>
Come not to me again, but say to Athens<br>
Timon hath made his everlasting mansion<br>
Upon the beached verge of the salt flood,<br>
Who once a day with his embossed froth<br>
The turbulent surge shall cover; thither come,<br>
And let my gravestone be your oracle.<br>
Lips, let sour words go by, and language end:<br>
What is amiss, plague and infection mend;<br>
Graves only be men’s works and death their gain,<br>
Sun, hide thy beams, Timon hath done his reign.
</p>

<p class="right">[<i>Exit <span class="charname">Timon</span> into his cave.</i>]</p>

<p class="drama">
FIRST SENATOR.<br>
His discontents are unremovably<br>
Coupled to nature.
</p>

<p class="drama">
SECOND SENATOR.<br>
Our hope in him is dead. Let us return<br>
And strain what other means is left unto us<br>
In our dear peril.
</p>

<p class="drama">
FIRST SENATOR.<br>
It requires swift foot.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneV_33.3"></a><b>SCENE III. Before the walls of Athens</b></h3>

<p class="scenedesc">
Enter two other <span class="charname">Senators,</span> with a
<span class="charname">Messenger</span>.
</p>

<p class="drama">
FIRST SENATOR.<br>
Thou hast painfully discovered. Are his files<br>
As full as thy report?
</p>

<p class="drama">
MESSENGER.<br>
I have spoke the least.<br>
Besides, his expedition promises<br>
Present approach.
</p>

<p class="drama">
SECOND SENATOR.<br>
We stand much hazard if they bring not Timon.
</p>

<p class="drama">
MESSENGER.<br>
I met a courier, one mine ancient friend,<br>
Whom, though in general part we were opposed,<br>
Yet our old love made a particular force<br>
And made us speak like friends. This man was riding<br>
From Alcibiades to Timon’s cave<br>
With letters of entreaty, which imported<br>
His fellowship i’ th’ cause against your city,<br>
In part for his sake moved.
</p>

<p class="scenedesc">
Enter the other <span class="charname">Senators</span> from
<span class="charname">Timon</span>.
</p>

<p class="drama">
THIRD SENATOR.<br>
Here come our brothers.
</p>

<p class="drama">
FIRST SENATOR.<br>
No talk of Timon, nothing of him expect.<br>
The enemy’s drum is heard, and fearful scouring<br>
Doth choke the air with dust. In, and prepare.<br>
Ours is the fall, I fear, our foe’s the snare.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneV_33.4"></a><b>SCENE IV. The woods. Timon’s cave, and a rude tomb seen</b></h3>

<p class="scenedesc">
Enter a <span class="charname">Soldier</span> in the woods, seeking
<span class="charname">Timon</span>.
</p>

<p class="drama">
SOLDIER.<br>
By all description this should be the place.<br>
Who’s here? Speak, ho! No answer? What is this?<br>
<i>Timon is dead, who hath outstretched his span.<br>
Some beast read this; there does not live a man.</i><br>
Dead, sure, and this his grave. What’s on this tomb<br>
I cannot read. The character I’ll take with wax.<br>
Our captain hath in every figure skill,<br>
An aged interpreter, though young in days.<br>
Before proud Athens he’s set down by this,<br>
Whose fall the mark of his ambition is.
</p>

<p class="right">[<i>Exit.</i>]</p>

<h3> <a id="sceneV_33.5"></a><b>SCENE V. Before the walls of Athens</b></h3>

<p class="scenedesc">
Trumpets sound. Enter <span class="charname">Alcibiades</span> with his powers
before Athens.
</p>

<p class="drama">
ALCIBIADES.<br>
Sound to this coward and lascivious town<br>
Our terrible approach.
</p>

<p class="right">[<i>A parley sounds.</i>]</p>

<p class="scenedesc">
The <span class="charname">Senators</span> appear upon the walls.
</p>

<p class="drama">
Till now you have gone on and filled the time<br>
With all licentious measure, making your wills<br>
The scope of justice. Till now myself and such<br>
As slept within the shadow of your power<br>
Have wandered with our traversed arms, and breathed<br>
Our sufferance vainly. Now the time is flush,<br>
When crouching marrow, in the bearer strong<br>
Cries of itself, “No more!” Now breathless wrong<br>
Shall sit and pant in your great chairs of ease,<br>
And pursy insolence shall break his wind<br>
With fear and horrid flight.
</p>

<p class="drama">
FIRST SENATOR.<br>
Noble and young,<br>
When thy first griefs were but a mere conceit,<br>
Ere thou hadst power or we had cause of fear,<br>
We sent to thee to give thy rages balm,<br>
To wipe out our ingratitude with loves<br>
Above their quantity.
</p>

<p class="drama">
SECOND SENATOR.<br>
So did we woo<br>
Transformed Timon to our city’s love<br>
By humble message and by promised means.<br>
We were not all unkind, nor all deserve<br>
The common stroke of war.
</p>

<p class="drama">
FIRST SENATOR.<br>
These walls of ours<br>
Were not erected by their hands from whom<br>
You have received your griefs; nor are they such<br>
That these great towers, trophies, and schools should fall<br>
For private faults in them.
</p>

<p class="drama">
SECOND SENATOR.<br>
Nor are they living<br>
Who were the motives that you first went out.<br>
Shame, that they wanted cunning, in excess<br>
Hath broke their hearts. March, noble lord,<br>
Into our city with thy banners spread.<br>
By decimation and a tithed death,<br>
If thy revenges hunger for that food<br>
Which nature loathes, take thou the destined tenth,<br>
And by the hazard of the spotted die<br>
Let die the spotted.
</p>

<p class="drama">
FIRST SENATOR.<br>
All have not offended.<br>
For those that were, it is not square to take,<br>
On those that are, revenge. Crimes, like lands,<br>
Are not inherited. Then, dear countryman,<br>
Bring in thy ranks but leave without thy rage;<br>
Spare thy Athenian cradle and those kin<br>
Which in the bluster of thy wrath must fall<br>
With those that have offended. Like a shepherd<br>
Approach the fold and cull th’ infected forth,<br>
But kill not all together.
</p>

<p class="drama">
SECOND SENATOR.<br>
What thou wilt,<br>
Thou rather shalt enforce it with thy smile<br>
Than hew to ’t with thy sword.
</p>

<p class="drama">
FIRST SENATOR.<br>
Set but thy foot<br>
Against our rampired gates and they shall ope,<br>
So thou wilt send thy gentle heart before<br>
To say thou’lt enter friendly.
</p>

<p class="drama">
SECOND SENATOR.<br>
Throw thy glove,<br>
Or any token of thine honour else,<br>
That thou wilt use the wars as thy redress<br>
And not as our confusion, all thy powers<br>
Shall make their harbour in our town till we<br>
Have sealed thy full desire.
</p>

<p class="drama">
ALCIBIADES.<br>
Then there’s my glove;<br>
Descend and open your uncharged ports.<br>
Those enemies of Timon’s and mine own<br>
Whom you yourselves shall set out for reproof<br>
Fall, and no more. And, to atone your fears<br>
With my more noble meaning, not a man<br>
Shall pass his quarter or offend the stream<br>
Of regular justice in your city’s bounds,<br>
But shall be remedied to your public laws<br>
At heaviest answer.
</p>

<p class="drama">
BOTH.<br>
’Tis most nobly spoken.
</p>

<p class="drama">
ALCIBIADES.<br>
Descend, and keep your words.
</p>

<p class="right">[<i>The <span class="charname">Senators</span> descend.</i>]</p>

<p class="scenedesc">
Enter a <span class="charname">Soldier</span>.
</p>

<p class="drama">
SOLDIER.<br>
My noble general, Timon is dead,<br>
Entombed upon the very hem o’ th’ sea,<br>
And on his gravestone this insculpture, which<br>
With wax I brought away, whose soft impression<br>
Interprets for my poor ignorance.
</p>

<p class="drama">
ALCIBIADES.<br>
[<i>Reads the Epitaph.</i>] <i>Here lies a wretched corse, of wretched soul bereft.<br>
Seek not my name. A plague consume you, wicked caitiffs left!<br>
Here lie I, Timon, who alive all living men did hate.<br>
Pass by and curse thy fill, but pass and stay not here thy gait.</i><br>
These well express in thee thy latter spirits.<br>
Though thou abhorred’st in us our human griefs,<br>
Scorned’st our brains’ flow and those our droplets which<br>
From niggard nature fall, yet rich conceit<br>
Taught thee to make vast Neptune weep for aye<br>
On thy low grave, on faults forgiven. Dead<br>
Is noble Timon, of whose memory<br>
Hereafter more. Bring me into your city,<br>
And I will use the olive with my sword,<br>
Make war breed peace, make peace stint war, make each<br>
Prescribe to other, as each other’s leech.<br>
Let our drums strike.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

