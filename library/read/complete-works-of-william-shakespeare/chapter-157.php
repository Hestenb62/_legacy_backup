<h2> <a id="sceneV_25.1"></a><b>ACT V</b></h2>

<h3> <b>SCENE I. Before Leonato’s House.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Leonato</span> and <span class="charname">Antonio</span>.
</p>

<p class="drama">
ANTONIO.<br>
If you go on thus, you will kill yourself<br>
And ’tis not wisdom thus to second grief<br>
Against yourself.
</p>

<p class="drama">
LEONATO.<br>
I pray thee, cease thy counsel,<br>
Which falls into mine ears as profitless<br>
As water in a sieve: give not me counsel;<br>
Nor let no comforter delight mine ear<br>
But such a one whose wrongs do suit with mine:<br>
Bring me a father that so lov’d his child,<br>
Whose joy of her is overwhelm’d like mine,<br>
And bid him speak of patience;<br>
Measure his woe the length and breadth of mine,<br>
And let it answer every strain for strain,<br>
As thus for thus and such a grief for such,<br>
In every lineament, branch, shape, and form:<br>
If such a one will smile, and stroke his beard;<br>
Bid sorrow wag, cry ‘hem’ when he should groan,<br>
Patch grief with proverbs; make misfortune drunk<br>
With candle-wasters; bring him yet to me,<br>
And I of him will gather patience.<br>
But there is no such man; for, brother, men<br>
Can counsel and speak comfort to that grief<br>
Which they themselves not feel; but, tasting it,<br>
Their counsel turns to passion, which before<br>
Would give preceptial medicine to rage,<br>
Fetter strong madness in a silken thread,<br>
Charm ache with air and agony with words.<br>
No, no; ’tis all men’s office to speak patience<br>
To those that wring under the load of sorrow,<br>
But no man’s virtue nor sufficiency<br>
To be so moral when he shall endure<br>
The like himself. Therefore give me no counsel:<br>
My griefs cry louder than advertisement.
</p>

<p class="drama">
ANTONIO.<br>
Therein do men from children nothing differ.
</p>

<p class="drama">
LEONATO.<br>
I pray thee peace! I will be flesh and blood;<br>
For there was never yet philosopher<br>
That could endure the toothache patiently,<br>
However they have writ the style of gods<br>
And made a push at chance and sufferance.
</p>

<p class="drama">
ANTONIO.<br>
Yet bend not all the harm upon yourself;<br>
Make those that do offend you suffer too.
</p>

<p class="drama">
LEONATO.<br>
There thou speak’st reason: nay, I will do so.<br>
My soul doth tell me Hero is belied;<br>
And that shall Claudio know; so shall the Prince,<br>
And all of them that thus dishonour her.
</p>

<p class="drama">
ANTONIO.<br>
Here comes the Prince and Claudio hastily.
</p>

<p class="scenedesc">
Enter <span class="charname">Don Pedro</span> and <span class="charname">Claudio</span>.
</p>

<p class="drama">
DON PEDRO.<br>
Good den, good den.
</p>

<p class="drama">
CLAUDIO.<br>
Good day to both of you.
</p>

<p class="drama">
LEONATO.<br>
Hear you, my lords,—
</p>

<p class="drama">
DON PEDRO.<br>
We have some haste, Leonato.
</p>

<p class="drama">
LEONATO.<br>
Some haste, my lord! well, fare you well, my lord:<br>
Are you so hasty now?—well, all is one.
</p>

<p class="drama">
DON PEDRO.<br>
Nay, do not quarrel with us, good old man.
</p>

<p class="drama">
ANTONIO.<br>
If he could right himself with quarrelling,<br>
Some of us would lie low.
</p>

<p class="drama">
CLAUDIO.<br>
Who wrongs him?
</p>

<p class="drama">
LEONATO.<br>
Marry, thou dost wrong me; thou dissembler, thou.<br>
Nay, never lay thy hand upon thy sword;<br>
I fear thee not.
</p>

<p class="drama">
CLAUDIO.<br>
Marry, beshrew my hand,<br>
If it should give your age such cause of fear.<br>
In faith, my hand meant nothing to my sword.
</p>

<p class="drama">
LEONATO.<br>
Tush, tush, man! never fleer and jest at me:<br>
I speak not like a dotard nor a fool,<br>
As, under privilege of age, to brag<br>
What I have done being young, or what would do,<br>
Were I not old. Know, Claudio, to thy head,<br>
Thou hast so wrong’d mine innocent child and me<br>
That I am forc’d to lay my reverence by,<br>
And, with grey hairs and bruise of many days,<br>
Do challenge thee to trial of a man.<br>
I say thou hast belied mine innocent child:<br>
Thy slander hath gone through and through her heart,<br>
And she lies buried with her ancestors;<br>
O! in a tomb where never scandal slept,<br>
Save this of hers, fram’d by thy villainy!
</p>

<p class="drama">
CLAUDIO.<br>
My villainy?
</p>

<p class="drama">
LEONATO.<br>
Thine, Claudio; thine, I say.
</p>

<p class="drama">
DON PEDRO.<br>
You say not right, old man.
</p>

<p class="drama">
LEONATO.<br>
My lord, my lord,<br> I’ll prove it on his body, if he dare,<br>
Despite his nice fence and his active practice,<br>
His May of youth and bloom of lustihood.
</p>

<p class="drama">
CLAUDIO.<br>
Away! I will not have to do with you.
</p>

<p class="drama">
LEONATO.<br>
Canst thou so daff me? Thou hast kill’d my child;<br>
If thou kill’st me, boy, thou shalt kill a man.
</p>

<p class="drama">
ANTONIO.<br>
He shall kill two of us, and men indeed:<br>
But that’s no matter; let him kill one first:<br>
Win me and wear me; let him answer me.<br>
Come, follow me, boy; come, sir boy, come, follow me.<br>
Sir boy, I’ll whip you from your foining fence;<br>
Nay, as I am a gentleman, I will.
</p>

<p class="drama">
LEONATO.<br>
Brother,—
</p>

<p class="drama">
ANTONIO.<br>
Content yourself. God knows I lov’d my niece;<br>
And she is dead, slander’d to death by villains,<br>
That dare as well answer a man indeed<br>
As I dare take a serpent by the tongue.<br>
Boys, apes, braggarts, Jacks, milksops!
</p>

<p class="drama">
LEONATO.<br>
Brother Anthony,—
</p>

<p class="drama">
ANTONIO.<br>
Hold you content. What, man! I know them, yea,<br>
And what they weigh, even to the utmost scruple,<br>
Scambling, out-facing, fashion-monging boys,<br>
That lie and cog and flout, deprave and slander,<br>
Go antickly, show outward hideousness,<br>
And speak off half a dozen dangerous words,<br>
How they might hurt their enemies, if they durst;<br>
And this is all!
</p>

<p class="drama">
LEONATO.<br>
But, brother Anthony,—
</p>

<p class="drama">
ANTONIO.<br>
Come, ’tis no matter:<br>
Do not you meddle, let me deal in this.
</p>

<p class="drama">
DON PEDRO.<br>
Gentlemen both, we will not wake your patience.<br>
My heart is sorry for your daughter’s death;<br>
But, on my honour, she was charg’d with nothing<br>
But what was true and very full of proof.
</p>

<p class="drama">
LEONATO.<br>
My lord, my lord—
</p>

<p class="drama">
DON PEDRO.<br>
I will not hear you.
</p>

<p class="drama">
LEONATO.<br>
No? Come, brother, away. I will be heard.—
</p>

<p class="drama">
ANTONIO.<br>
And shall, or some of us will smart for it.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Leonato</span> and <span class="charname">Antonio.</span></i>]
</p>

<p class="scenedesc">
Enter <span class="charname">Benedick</span>.
</p>

<p class="drama">
DON PEDRO.<br>
See, see; here comes the man we went to seek.
</p>

<p class="drama">
CLAUDIO.<br>
Now, signior, what news?
</p>

<p class="drama">
BENEDICK.<br>
Good day, my lord.
</p>

<p class="drama">
DON PEDRO.<br>
Welcome, signior: you are almost come to part almost a fray.
</p>

<p class="drama">
CLAUDIO.<br>
We had like to have had our two noses snapped off with two old men without
teeth.
</p>

<p class="drama">
DON PEDRO.<br>
Leonato and his brother. What think’st thou? Had we fought, I doubt we
should have been too young for them.
</p>

<p class="drama">
BENEDICK.<br>
In a false quarrel there is no true valour. I came to seek you both.
</p>

<p class="drama">
CLAUDIO.<br>
We have been up and down to seek thee; for we are high-proof melancholy, and
would fain have it beaten away. Wilt thou use thy wit?
</p>

<p class="drama">
BENEDICK.<br>
It is in my scabbard; shall I draw it?
</p>

<p class="drama">
DON PEDRO.<br>
Dost thou wear thy wit by thy side?
</p>

<p class="drama">
CLAUDIO.<br>
Never any did so, though very many have been beside their wit. I will bid thee
draw, as we do the minstrels; draw, to pleasure us.
</p>

<p class="drama">
DON PEDRO.<br>
As I am an honest man, he looks pale. Art thou sick, or angry?
</p>

<p class="drama">
CLAUDIO.<br>
What, courage, man! What though care killed a cat, thou hast mettle enough in
thee to kill care.
</p>

<p class="drama">
BENEDICK.<br>
Sir, I shall meet your wit in the career, and you charge it against me. I pray
you choose another subject.
</p>

<p class="drama">
CLAUDIO.<br>
Nay then, give him another staff: this last was broke cross.
</p>

<p class="drama">
DON PEDRO.<br>
By this light, he changes more and more: I think he be angry indeed.
</p>

<p class="drama">
CLAUDIO.<br>
If he be, he knows how to turn his girdle.
</p>

<p class="drama">
BENEDICK.<br>
Shall I speak a word in your ear?
</p>

<p class="drama">
CLAUDIO.<br>
God bless me from a challenge!
</p>

<p class="drama">
BENEDICK.<br>
[<i>Aside to Claudio.</i>] You are a villain, I jest not: I will make it good
how you dare, with what you dare, and when you dare. Do me right, or I will
protest your cowardice. You have killed a sweet lady, and her death shall fall
heavy on you. Let me hear from you.
</p>

<p class="drama">
CLAUDIO.<br>
Well I will meet you, so I may have good cheer.
</p>

<p class="drama">
DON PEDRO.<br>
What, a feast, a feast?
</p>

<p class="drama">
CLAUDIO.<br>
I’ faith, I thank him; he hath bid me to a calf’s-head and a capon,
the which if I do not carve most curiously, say my knife’s naught. Shall
I not find a woodcock too?
</p>

<p class="drama">
BENEDICK.<br>
Sir, your wit ambles well; it goes easily.
</p>

<p class="drama">
DON PEDRO.<br>
I’ll tell thee how Beatrice praised thy wit the other day. I said, thou
hadst a fine wit. ‘True,’ says she, ‘a fine little
one.’ ‘No,’ said I, ‘a great wit.’
‘Right,’ said she, ‘a great gross one.’
‘Nay,’ said I, ‘a good wit.’ ‘Just,’ said
she, ‘it hurts nobody.’ ‘Nay,’ said I, ‘the
gentleman is wise.’ ‘Certain,’ said she, ‘a wise
gentleman.’ ‘Nay,’ said I, ‘he hath the tongues.’
‘That I believe’ said she, ‘for he swore a thing to me on
Monday night, which he forswore on Tuesday morning: there’s a double
tongue; there’s two tongues.’ Thus did she, an hour together,
trans-shape thy particular virtues; yet at last she concluded with a sigh, thou
wast the properest man in Italy.
</p>

<p class="drama">
CLAUDIO.<br>
For the which she wept heartily and said she cared not.
</p>

<p class="drama">
DON PEDRO.<br>
Yea, that she did; but yet, for all that, an if she did not hate him deadly,
she would love him dearly. The old man’s daughter told us all.
</p>

<p class="drama">
CLAUDIO.<br>
All, all; and moreover, God saw him when he was hid in the garden.
</p>

<p class="drama">
DON PEDRO.<br>
But when shall we set the savage bull’s horns on the sensible
Benedick’s head?
</p>

<p class="drama">
CLAUDIO.<br>
Yea, and text underneath, ‘Here dwells Benedick the married man!’
</p>

<p class="drama">
BENEDICK.<br>
Fare you well, boy: you know my mind. I will leave you now to your gossip-like
humour; you break jests as braggarts do their blades, which, God be thanked,
hurt not. My lord, for your many courtesies I thank you: I must discontinue
your company. Your brother the bastard is fled from Messina: you have, among
you, killed a sweet and innocent lady. For my Lord Lack-beard there, he and I
shall meet; and till then, peace be with him.
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="drama">
DON PEDRO.<br>
He is in earnest.
</p>

<p class="drama">
CLAUDIO.<br>
In most profound earnest; and, I’ll warrant you, for the love of
Beatrice.
</p>

<p class="drama">
DON PEDRO.<br>
And hath challenged thee?
</p>

<p class="drama">
CLAUDIO.<br>
Most sincerely.
</p>

<p class="drama">
DON PEDRO.<br>
What a pretty thing man is when he goes in his doublet and hose and leaves off
his wit!
</p>

<p class="drama">
CLAUDIO.<br>
He is then a giant to an ape; but then is an ape a doctor to such a man.
</p>

<p class="drama">
DON PEDRO.<br>
But, soft you; let me be: pluck up, my heart, and be sad! Did he not say my
brother was fled?
</p>

<p class="scenedesc">
Enter <span class="charname">Dogberry, Verges, </span> and the Watch, with
<span class="charname">Conrade</span> and <span class="charname">Borachio</span>.
</p>

<p class="drama">
DOGBERRY.<br>
Come you, sir: if justice cannot tame you, she shall ne’er weigh more
reasons in her balance. Nay, an you be a cursing hypocrite once, you must be
looked to.
</p>

<p class="drama">
DON PEDRO.<br>
How now! two of my brother’s men bound! Borachio, one!
</p>

<p class="drama">
CLAUDIO.<br>
Hearken after their offence, my lord.
</p>

<p class="drama">
DON PEDRO.<br>
Officers, what offence have these men done?
</p>

<p class="drama">
DOGBERRY.<br>
Marry, sir, they have committed false report; moreover, they have spoken
untruths; secondarily, they are slanders; sixth and lastly, they have belied a
lady; thirdly, they have verified unjust things; and to conclude, they are
lying knaves.
</p>

<p class="drama">
DON PEDRO.<br>
First, I ask thee what they have done; thirdly, I ask thee what’s their
offence; sixth and lastly, why they are committed; and, to conclude, what you
lay to their charge?
</p>

<p class="drama">
CLAUDIO.<br>
Rightly reasoned, and in his own division; and, by my troth, there’s one
meaning well suited.
</p>

<p class="drama">
DON PEDRO.<br>
Who have you offended, masters, that you are thus bound to your answer? This
learned constable is too cunning to be understood. What’s your offence?
</p>

<p class="drama">
BORACHIO.<br>
Sweet Prince, let me go no farther to mine answer: do you hear me, and let this
Count kill me. I have deceived even your very eyes: what your wisdoms could not
discover, these shallow fools have brought to light; who, in the night
overheard me confessing to this man how Don John your brother incensed me to
slander the Lady Hero; how you were brought into the orchard and saw me court
Margaret in Hero’s garments; how you disgraced her, when you should marry
her. My villainy they have upon record; which I had rather seal with my death
than repeat over to my shame. The lady is dead upon mine and my master’s
false accusation; and, briefly, I desire nothing but the reward of a villain.
</p>

<p class="drama">
DON PEDRO.<br>
Runs not this speech like iron through your blood?
</p>

<p class="drama">
CLAUDIO.<br>
I have drunk poison whiles he utter’d it.
</p>

<p class="drama">
DON PEDRO.<br>
But did my brother set thee on to this?
</p>

<p class="drama">
BORACHIO.<br>
Yea; and paid me richly for the practice of it.
</p>

<p class="drama">
DON PEDRO.<br>
He is compos’d and fram’d of treachery: And fled he is upon this
villainy.
</p>

<p class="drama">
CLAUDIO.<br>
Sweet Hero! now thy image doth appear<br>
In the rare semblance that I lov’d it first.
</p>

<p class="drama">
DOGBERRY.<br>
Come, bring away the plaintiffs: by this time our sexton hath reformed Signior
Leonato of the matter. And masters, do not forget to specify, when time and
place shall serve, that I am an ass.
</p>

<p class="drama">
VERGES.<br>
Here, here comes Master Signior Leonato, and the sexton too.
</p>

<p class="scenedesc">
Re-enter <span class="charname">Leonato, Antonio</span> and the Sexton.
</p>

<p class="drama">
LEONATO.<br>
Which is the villain? Let me see his eyes,<br>
That, when I note another man like him,<br>
I may avoid him. Which of these is he?
</p>

<p class="drama">
BORACHIO.<br>
If you would know your wronger, look on me.
</p>

<p class="drama">
LEONATO.<br>
Art thou the slave that with thy breath hast kill’d<br>
Mine innocent child?
</p>

<p class="drama">
BORACHIO.<br>
Yea, even I alone.
</p>

<p class="drama">
LEONATO.<br>
No, not so, villain; thou beliest thyself:<br>
Here stand a pair of honourable men;<br>
A third is fled, that had a hand in it.<br>
I thank you, princes, for my daughter’s death:<br>
Record it with your high and worthy deeds.<br>
’Twas bravely done, if you bethink you of it.
</p>

<p class="drama">
CLAUDIO.<br>
I know not how to pray your patience;<br>
Yet I must speak. Choose your revenge yourself;<br>
Impose me to what penance your invention<br>
Can lay upon my sin: yet sinn’d I not<br>
But in mistaking.
</p>

<p class="drama">
DON PEDRO.<br>
By my soul, nor I:<br>
And yet, to satisfy this good old man,<br>
I would bend under any heavy weight<br>
That he’ll enjoin me to.
</p>

<p class="drama">
LEONATO.<br>
I cannot bid you bid my daughter live;<br>
That were impossible; but, I pray you both,<br>
Possess the people in Messina here<br>
How innocent she died; and if your love<br>
Can labour aught in sad invention,<br>
Hang her an epitaph upon her tomb,<br>
And sing it to her bones: sing it tonight.<br>
Tomorrow morning come you to my house,<br>
And since you could not be my son-in-law,<br>
Be yet my nephew. My brother hath a daughter,<br>
Almost the copy of my child that’s dead,<br>
And she alone is heir to both of us:<br>
Give her the right you should have given her cousin,<br>
And so dies my revenge.
</p>

<p class="drama">
CLAUDIO.<br>
O noble sir,<br>
Your over-kindness doth wring tears from me!<br>
I do embrace your offer; and dispose<br>
For henceforth of poor Claudio.
</p>

<p class="drama">
LEONATO.<br>
Tomorrow then I will expect your coming;<br>
Tonight I take my leave. This naughty man<br>
Shall face to face be brought to Margaret,<br>
Who, I believe, was pack’d in all this wrong,<br>
Hir’d to it by your brother.
</p>

<p class="drama">
BORACHIO.<br>
No, by my soul she was not;<br>
Nor knew not what she did when she spoke to me;<br>
But always hath been just and virtuous<br>
In anything that I do know by her.
</p>

<p class="drama">
DOGBERRY.<br>
Moreover, sir,—which, indeed, is not under white and black,— this plaintiff
here, the offender, did call me ass: I beseech you, let it be remembered in his
punishment. And also, the watch heard them talk of one Deformed: they say he
wears a key in his ear and a lock hanging by it, and borrows money in
God’s name, the which he hath used so long and never paid, that now men
grow hard-hearted, and will lend nothing for God’s sake. Pray you,
examine him upon that point.
</p>

<p class="drama">
LEONATO.<br>
I thank thee for thy care and honest pains.
</p>

<p class="drama">
DOGBERRY.<br>
Your worship speaks like a most thankful and reverent youth, and I praise God
for you.
</p>

<p class="drama">
LEONATO.<br>
There’s for thy pains.
</p>

<p class="drama">
DOGBERRY.<br>
God save the foundation!
</p>

<p class="drama">
LEONATO.<br>
Go, I discharge thee of thy prisoner, and I thank thee.
</p>

<p class="drama">
DOGBERRY.<br>
I leave an arrant knave with your worship; which I beseech your worship to
correct yourself, for the example of others. God keep your worship! I wish your
worship well; God restore you to health! I humbly give you leave to depart, and
if a merry meeting may be wished, God prohibit it! Come, neighbour.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Dogberry</span> and <span class="charname">Verges.</span></i>]
</p>

<p class="drama">
LEONATO.<br>
Until tomorrow morning, lords, farewell.
</p>

<p class="drama">
ANTONIO.<br>
Farewell, my lords: we look for you tomorrow.
</p>

<p class="drama">
DON PEDRO.<br>
We will not fail.
</p>

<p class="drama">
CLAUDIO.<br>
Tonight I’ll mourn with Hero.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Don Pedro</span> and <span class="charname">Claudio.</span></i>]
</p>

<p class="drama">
LEONATO.<br>
[<i>To the Watch.</i>] Bring you these fellows on. We’ll talk with
Margaret,<br>
How her acquaintance grew with this lewd fellow.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneV_25.2"></a><b>SCENE II. Leonato’s
Garden.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Benedick</span> and <span class="charname">Margaret</span>, meeting.
</p>

<p class="drama">
BENEDICK.<br>
Pray thee, sweet Mistress Margaret, deserve well at my hands by helping me to
the speech of Beatrice.
</p>

<p class="drama">
MARGARET.<br>
Will you then write me a sonnet in praise of my beauty?
</p>

<p class="drama">
BENEDICK.<br>
In so high a style, Margaret, that no man living shall come over it; for, in
most comely truth, thou deservest it.
</p>

<p class="drama">
MARGARET.<br>
To have no man come over me! why, shall I always keep below stairs?
</p>

<p class="drama">
BENEDICK.<br>
Thy wit is as quick as the greyhound’s mouth; it catches.
</p>

<p class="drama">
MARGARET.<br>
And yours as blunt as the fencer’s foils, which hit, but hurt not.
</p>

<p class="drama">
BENEDICK.<br>
A most manly wit, Margaret; it will not hurt a woman: and so, I pray thee, call
Beatrice. I give thee the bucklers.
</p>

<p class="drama">
MARGARET.<br>
Give us the swords, we have bucklers of our own.
</p>

<p class="drama">
BENEDICK.<br>
If you use them, Margaret, you must put in the pikes with a vice; and they are
dangerous weapons for maids.
</p>

<p class="drama">
MARGARET.<br>
Well, I will call Beatrice to you, who I think hath legs.
</p>

<p class="drama">
BENEDICK.<br>
And therefore will come.
</p>

<p class="right">
[<i>Exit <span class="charname">Margaret</span>.</i>]
</p>

<p class="drama">
    The god of love,<br>
    That sits above,<br>
 And knows me, and knows me,<br>
   How pitiful I deserve,—
</p>

<p class="drama">
I mean, in singing: but in loving, Leander the good swimmer, Troilus the first
employer of panders, and a whole book full of these quondam carpet-mongers,
whose names yet run smoothly in the even road of a blank verse, why, they were
never so truly turned over and over as my poor self in love. Marry, I cannot
show it in rime; I have tried: I can find out no rime to ‘lady’ but
‘baby’, an innocent rime; for ‘scorn,’
‘horn’, a hard rime; for ‘school’, ‘fool’,
a babbling rime; very ominous endings: no, I was not born under a riming
planet, nor I cannot woo in festival terms.
</p>

<p class="scenedesc">
Enter <span class="charname">Beatrice</span>.
</p>

<p class="drama">
Sweet Beatrice, wouldst thou come when I called thee?
</p>

<p class="drama">
BEATRICE.<br>
Yea, signior; and depart when you bid me.
</p>

<p class="drama">
BENEDICK.<br>
O, stay but till then!
</p>

<p class="drama">
BEATRICE.<br>
‘Then’ is spoken; fare you well now: and yet, ere I go, let me go
with that I came for; which is, with knowing what hath passed between you and
Claudio.
</p>

<p class="drama">
BENEDICK.<br>
Only foul words; and thereupon I will kiss thee.
</p>

<p class="drama">
BEATRICE.<br>
Foul words is but foul wind, and foul wind is but foul breath, and foul breath
is noisome; therefore I will depart unkissed.
</p>

<p class="drama">
BENEDICK.<br>
Thou hast frighted the word out of his right sense, so forcible is thy wit. But
I must tell thee plainly, Claudio undergoes my challenge, and either I must
shortly hear from him, or I will subscribe him a coward. And, I pray thee now,
tell me, for which of my bad parts didst thou first fall in love with me?
</p>

<p class="drama">
BEATRICE.<br>
For them all together; which maintained so politic a state of evil that they
will not admit any good part to intermingle with them. But for which of my good
parts did you first suffer love for me?
</p>

<p class="drama">
BENEDICK.<br>
‘Suffer love,’ a good epithet! I do suffer love indeed, for I love
thee against my will.
</p>

<p class="drama">
BEATRICE.<br>
In spite of your heart, I think. Alas, poor heart! If you spite it for my sake,
I will spite it for yours; for I will never love that which my friend hates.
</p>

<p class="drama">
BENEDICK.<br>
Thou and I are too wise to woo peaceably.
</p>

<p class="drama">
BEATRICE.<br>
It appears not in this confession: there’s not one wise man among twenty
that will praise himself.
</p>

<p class="drama">
BENEDICK.<br>
An old, an old instance, Beatrice, that lived in the time of good neighbours.
If a man do not erect in this age his own tomb ere he dies, he shall live no
longer in monument than the bell rings and the widow weeps.
</p>

<p class="drama">
BEATRICE.<br> And how long is that think you?
</p>

<p class="drama">
BENEDICK.<br>
Question: why, an hour in clamour and a quarter in rheum: therefore is it most
expedient for the wise,—if Don Worm, his conscience, find no impediment to the
contrary,—to be the trumpet of his own virtues, as I am to myself. So much for
praising myself, who, I myself will bear witness, is praiseworthy. And now tell
me, how doth your cousin?
</p>

<p class="drama">
BEATRICE.<br>
Very ill.
</p>

<p class="drama">
BENEDICK.<br>
And how do you?
</p>

<p class="drama">
BEATRICE.<br>
Very ill too.
</p>

<p class="drama">
BENEDICK.<br>
Serve God, love me, and mend. There will I leave you too, for here comes one in
haste.
</p>

<p class="scenedesc">
Enter <span class="charname">Ursula</span>.
</p>

<p class="drama">
URSULA.<br>
Madam, you must come to your uncle. Yonder’s old coil at home: it is
proved, my Lady Hero hath been falsely accused, the Prince and Claudio mightily
abused; and Don John is the author of all, who is fled and gone. Will you come
presently?
</p>

<p class="drama">
BEATRICE.<br>
Will you go hear this news, signior?
</p>

<p class="drama">
BENEDICK.<br>
I will live in thy heart, die in thy lap, and be buried in thy eyes; and
moreover I will go with thee to thy uncle’s.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneV_25.3"></a><b>SCENE III. The Inside of a
Church.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Don Pedro, Claudio</span> and Attendants, with
music and tapers.
</p>

<p class="drama">
CLAUDIO.<br>
Is this the monument of Leonato?
</p>

<p class="drama">
A LORD.<br>
It is, my lord.
</p>

<p class="drama">
CLAUDIO.<br>
[<i>Reads from a scroll.</i>]
</p>

<p class="scenedesc">
Epitaph.
</p>

<p class="drama">
  Done to death by slanderous tongues<br>
    Was the Hero that here lies:<br>
  Death, in guerdon of her wrongs,<br>
    Gives her fame which never dies.<br>
  So the life that died with shame<br>
  Lives in death with glorious fame.
</p>

<p class="drama">
Hang thou there upon the tomb,<br>
</p>

<p class="drama">
Praising her when I am dumb.<br>
Now, music, sound, and sing your solemn hymn.
</p>

<p class="scenedesc">
Song.
</p>

<p class="drama">
 Pardon, goddess of the night,<br>
  Those that slew thy virgin knight;<br>
  For the which, with songs of woe,<br>
  Round about her tomb they go.<br>
     Midnight, assist our moan;<br>
     Help us to sigh and groan,<br>
        Heavily, heavily:<br>
     Graves, yawn and yield your dead,<br>
     Till death be uttered,<br>
        Heavily, heavily.
</p>

<p class="drama">
CLAUDIO.<br>
Now, unto thy bones good night!<br>
Yearly will I do this rite.
</p>

<p class="drama">
DON PEDRO.<br>
Good morrow, masters: put your torches out.<br>
The wolves have prey’d; and look, the gentle day,<br>
Before the wheels of Phoebus, round about<br>
Dapples the drowsy East with spots of grey.<br>
Thanks to you all, and leave us: fare you well.
</p>

<p class="drama">
CLAUDIO.<br>
Good morrow, masters: each his several way.
</p>

<p class="drama">
DON PEDRO.<br>
Come, let us hence, and put on other weeds;<br>
And then to Leonato’s we will go.
</p>

<p class="drama">
CLAUDIO.<br>
And Hymen now with luckier issue speed’s,<br>
Than this for whom we rend’red up this woe!
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneV_25.4"></a><b>SCENE IV. A Room in Leonato’s
House.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Leonato, Antonio, Benedick, Beatrice, Margaret,
Ursula, Friar Francis</span> and <span class="charname">Hero</span>.
</p>

<p class="drama">
FRIAR.<br>
Did I not tell you she was innocent?
</p>

<p class="drama">
LEONATO.<br>
So are the Prince and Claudio, who accus’d her<br>
Upon the error that you heard debated:<br>
But Margaret was in some fault for this,<br>
Although against her will, as it appears<br>
In the true course of all the question.
</p>

<p class="drama">
ANTONIO.<br>
Well, I am glad that all things sort so well.
</p>

<p class="drama">
BENEDICK.<br>
And so am I, being else by faith enforc’d<br>
To call young Claudio to a reckoning for it.
</p>

<p class="drama">
LEONATO.<br>
Well, daughter, and you gentlewomen all,<br>
Withdraw into a chamber by yourselves,<br>
And when I send for you, come hither mask’d:<br>
The Prince and Claudio promis’d by this hour<br>
To visit me.
</p>

<p class="right">
[<i>Exeunt Ladies.</i>]
</p>

<p class="drama">
You know your office, brother;<br>
You must be father to your brother’s daughter,<br>
And give her to young Claudio.
</p>

<p class="drama">
ANTONIO.<br>
Which I will do with confirm’d countenance.
</p>

<p class="drama">
BENEDICK.<br>
Friar, I must entreat your pains, I think.
</p>

<p class="drama">
FRIAR.<br>
To do what, signior?
</p>

<p class="drama">
BENEDICK.<br>
To bind me, or undo me; one of them.<br>
Signior Leonato, truth it is, good signior,<br>
Your niece regards me with an eye of favour.
</p>

<p class="drama">
LEONATO.<br>
That eye my daughter lent her. ’Tis most true.
</p>

<p class="drama">
BENEDICK.<br>
And I do with an eye of love requite her.
</p>

<p class="drama">
LEONATO.<br>
The sight whereof I think, you had from me,<br>
From Claudio, and the Prince. But what’s your will?
</p>

<p class="drama">
BENEDICK.<br>
Your answer, sir, is enigmatical:<br>
But, for my will, my will is your good will<br>
May stand with ours, this day to be conjoin’d<br>
In the state of honourable marriage:<br>
In which, good friar, I shall desire your help.
</p>

<p class="drama">
LEONATO.<br>
My heart is with your liking.
</p>

<p class="drama">
FRIAR.<br>
And my help. Here comes the Prince and Claudio.
</p>

<p class="scenedesc">
Enter <span class="charname">Don Pedro</span> and <span class="charname">Claudio</span>, with Attendants.
</p>

<p class="drama">
DON PEDRO.<br>
Good morrow to this fair assembly.
</p>

<p class="drama">
LEONATO.<br>
Good morrow, Prince; good morrow, Claudio:<br>
We here attend you. Are you yet determin’d<br>
Today to marry with my brother’s daughter?
</p>

<p class="drama">
CLAUDIO.<br>
I’ll hold my mind, were she an Ethiope.
</p>

<p class="drama">
LEONATO.<br>
Call her forth, brother: here’s the friar ready.
</p>

<p class="right">
[<i>Exit <span class="charname">Antonio</span>.</i>]
</p>

<p class="drama">
DON PEDRO.<br>
Good morrow, Benedick. Why, what’s the matter,<br>
That you have such a February face,<br>
So full of frost, of storm and cloudiness?
</p>

<p class="drama">
CLAUDIO.<br>
I think he thinks upon the savage bull.<br>
Tush! fear not, man, we’ll tip thy horns with gold,<br>
And all Europa shall rejoice at thee,<br>
As once Europa did at lusty Jove,<br>
When he would play the noble beast in love.
</p>

<p class="drama">
BENEDICK.<br>
Bull Jove, sir, had an amiable low:<br>
And some such strange bull leap’d your father’s cow,<br>
And got a calf in that same noble feat,<br>
Much like to you, for you have just his bleat.
</p>

<p class="drama">
CLAUDIO.<br>
For this I owe you: here comes other reckonings.
</p>

<p class="scenedesc">
Re-enter <span class="charname">Antonio</span>, with the ladies masked.
</p>

<p class="drama">
Which is the lady I must seize upon?
</p>

<p class="drama">
ANTONIO.<br>
This same is she, and I do give you her.
</p>

<p class="drama">
CLAUDIO.<br>
Why then, she’s mine. Sweet, let me see your face.
</p>

<p class="drama">
LEONATO.<br>
No, that you shall not, till you take her hand<br>
Before this friar, and swear to marry her.
</p>

<p class="drama">
CLAUDIO.<br>
Give me your hand: before this holy friar,<br>
I am your husband, if you like of me.
</p>

<p class="drama">
HERO.<br>
And when I liv’d, I was your other wife:<br>
[<i>Unmasking.</i>] And when you lov’d, you were my other husband.
</p>

<p class="drama">
CLAUDIO.<br>
Another Hero!
</p>

<p class="drama">
HERO.<br>
Nothing certainer:<br>
One Hero died defil’d, but I do live,<br>
And surely as I live, I am a maid.
</p>

<p class="drama">
DON PEDRO.<br>
The former Hero! Hero that is dead!
</p>

<p class="drama">
LEONATO.<br>
She died, my lord, but whiles her slander liv’d.
</p>

<p class="drama">
FRIAR.<br>
All this amazement can I qualify:<br>
When after that the holy rites are ended,<br>
I’ll tell you largely of fair Hero’s death:<br>
Meantime, let wonder seem familiar,<br>
And to the chapel let us presently.
</p>

<p class="drama">
BENEDICK.<br>
Soft and fair, friar. Which is Beatrice?
</p>

<p class="drama">
BEATRICE.<br>
[<i>Unmasking.</i>] I answer to that name. What is your will?
</p>

<p class="drama">
BENEDICK.<br>
Do not you love me?
</p>

<p class="drama">
BEATRICE.<br>
Why, no; no more than reason.
</p>

<p class="drama">
BENEDICK.<br>
Why, then, your uncle and the Prince and Claudio<br>
Have been deceived; for they swore you did.
</p>

<p class="drama">
BEATRICE.<br>
Do not you love me?
</p>

<p class="drama">
BENEDICK.<br>
Troth, no; no more than reason.
</p>

<p class="drama">
BEATRICE.<br>
Why, then my cousin, Margaret, and Ursula,<br>
Are much deceiv’d; for they did swear you did.
</p>

<p class="drama">
BENEDICK.<br>
They swore that you were almost sick for me.
</p>

<p class="drama">
BEATRICE.<br>
They swore that you were well-nigh dead for me.
</p>

<p class="drama">
BENEDICK.<br>
’Tis no such matter. Then you do not love me?
</p>

<p class="drama">
BEATRICE.<br>
No, truly, but in friendly recompense.
</p>

<p class="drama">
LEONATO.<br>
Come, cousin, I am sure you love the gentleman.
</p>

<p class="drama">
CLAUDIO.<br>
And I’ll be sworn upon ’t that he loves her;<br>
For here’s a paper written in his hand,<br>
A halting sonnet of his own pure brain,<br>
Fashion’d to Beatrice.
</p>

<p class="drama">
HERO.<br>
And here’s another,<br>
Writ in my cousin’s hand, stolen from her pocket,<br>
Containing her affection unto Benedick.
</p>

<p class="drama">
BENEDICK.<br>
A miracle! here’s our own hands against our hearts. Come, I will have
thee; but, by this light, I take thee for pity.
</p>

<p class="drama">
BEATRICE.<br>
I would not deny you; but, by this good day, I yield upon great persuasion, and
partly to save your life, for I was told you were in a consumption.
</p>

<p class="drama">
BENEDICK.<br>
Peace! I will stop your mouth. [<i>Kisses her.</i>]
</p>

<p class="drama">
DON PEDRO.<br>
How dost thou, Benedick, the married man?
</p>

<p class="drama">
BENEDICK.<br>
I’ll tell thee what, Prince; a college of witcrackers cannot flout me out of my
humour. Dost thou think I care for a satire or an epigram? No; if man will be
beaten with brains, a’ shall wear nothing handsome about him. In brief, since I
do purpose to marry, I will think nothing to any purpose that the world can say
against it; and therefore never flout at me for what I have said against it,
for man is a giddy thing, and this is my conclusion. For thy part, Claudio, I
did think to have beaten thee; but, in that thou art like to be my kinsman,
live unbruised, and love my cousin.
</p>

<p class="drama">
CLAUDIO.<br>
I had well hoped thou wouldst have denied Beatrice, that I might have cudgelled
thee out of thy single life, to make thee a double-dealer; which, out of
question, thou wilt be, if my cousin do not look exceeding narrowly to thee.
</p>

<p class="drama">
BENEDICK.<br>
Come, come, we are friends. Let’s have a dance ere we are married, that
we may lighten our own hearts and our wives’ heels.
</p>

<p class="drama">
LEONATO.<br>
We’ll have dancing afterward.
</p>

<p class="drama">
BENEDICK.<br>
First, of my word; therefore play, music! Prince, thou art sad; get thee a
wife, get thee a wife: there is no staff more reverent than one tipped with
horn.
</p>

<p class="scenedesc">
Enter <span class="charname">Messenger</span>.
</p>

<p class="drama">
MESSENGER.<br>
My lord, your brother John is ta’en in flight,<br>
And brought with armed men back to Messina.
</p>

<p class="drama">
BENEDICK.<br>
Think not on him till tomorrow: I’ll devise thee brave punishments for
him. Strike up, pipers!
</p>

<p class="right">
[<i>Dance. Exeunt.</i>]
</p>

