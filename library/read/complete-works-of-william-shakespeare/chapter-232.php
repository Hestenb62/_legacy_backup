<h2> <a id="sceneIII_37.1"></a><b>ACT III</b></h2>

<h3> <b>SCENE I. Milan. An anteroom in the Duke’s palace</b></h3>

<p class="scenedesc">
Enter <span class="charname">Duke, Thurio</span> and
<span class="charname">Proteus</span>.
</p>

<p class="drama">
DUKE.<br>
Sir Thurio, give us leave, I pray, awhile;<br>
We have some secrets to confer about.
</p>

<p class="right">[<i>Exit <span class="charname">Thurio</span>.</i>]</p>

<p class="drama">
Now tell me, Proteus, what’s your will with me?
</p>

<p class="drama">
PROTEUS.<br>
My gracious lord, that which I would discover<br>
The law of friendship bids me to conceal,<br>
But when I call to mind your gracious favours<br>
Done to me, undeserving as I am,<br>
My duty pricks me on to utter that<br>
Which else no worldly good should draw from me.<br>
Know, worthy prince, Sir Valentine my friend<br>
This night intends to steal away your daughter;<br>
Myself am one made privy to the plot.<br>
I know you have determined to bestow her<br>
On Thurio, whom your gentle daughter hates,<br>
And should she thus be stol’n away from you,<br>
It would be much vexation to your age.<br>
Thus, for my duty’s sake, I rather chose<br>
To cross my friend in his intended drift<br>
Than, by concealing it, heap on your head<br>
A pack of sorrows which would press you down,<br>
Being unprevented, to your timeless grave.
</p>

<p class="drama">
DUKE.<br>
Proteus, I thank thee for thine honest care,<br>
Which to requite command me while I live.<br>
This love of theirs myself have often seen,<br>
Haply when they have judged me fast asleep,<br>
And oftentimes have purposed to forbid<br>
Sir Valentine her company and my court.<br>
But fearing lest my jealous aim might err<br>
And so, unworthily, disgrace the man—<br>
A rashness that I ever yet have shunned—<br>
I gave him gentle looks, thereby to find<br>
That which thyself hast now disclosed to me.<br>
And that thou mayst perceive my fear of this,<br>
Knowing that tender youth is soon suggested,<br>
I nightly lodge her in an upper tower,<br>
The key whereof myself have ever kept;<br>
And thence she cannot be conveyed away.
</p>

<p class="drama">
PROTEUS.<br>
Know, noble lord, they have devised a mean<br>
How he her chamber-window will ascend<br>
And with a corded ladder fetch her down;<br>
For which the youthful lover now is gone,<br>
And this way comes he with it presently,<br>
Where, if it please you, you may intercept him.<br>
But, good my lord, do it so cunningly<br>
That my discovery be not aimed at;<br>
For love of you, not hate unto my friend,<br>
Hath made me publisher of this pretence.
</p>

<p class="drama">
DUKE.<br>
Upon mine honour, he shall never know<br>
That I had any light from thee of this.
</p>

<p class="drama">
PROTEUS.<br>
Adieu, my lord, Sir Valentine is coming.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="scenedesc">
Enter <span class="charname">Valentine</span>.
</p>

<p class="drama">
DUKE.<br>
Sir Valentine, whither away so fast?
</p>

<p class="drama">
VALENTINE.<br>
Please it your Grace, there is a messenger<br>
That stays to bear my letters to my friends,<br>
And I am going to deliver them.
</p>

<p class="drama">
DUKE.<br>
Be they of much import?
</p>

<p class="drama">
VALENTINE.<br>
The tenor of them doth but signify<br>
My health and happy being at your court.
</p>

<p class="drama">
DUKE.<br>
Nay then, no matter. Stay with me awhile;<br>
I am to break with thee of some affairs<br>
That touch me near, wherein thou must be secret.<br>
’Tis not unknown to thee that I have sought<br>
To match my friend Sir Thurio to my daughter.
</p>

<p class="drama">
VALENTINE.<br>
I know it well, my lord, and sure the match<br>
Were rich and honourable. Besides, the gentleman<br>
Is full of virtue, bounty, worth, and qualities<br>
Beseeming such a wife as your fair daughter.<br>
Cannot your grace win her to fancy him?
</p>

<p class="drama">
DUKE.<br>
No, trust me, she is peevish, sullen, froward,<br>
Proud, disobedient, stubborn, lacking duty,<br>
Neither regarding that she is my child<br>
Nor fearing me as if I were her father;<br>
And, may I say to thee, this pride of hers,<br>
Upon advice, hath drawn my love from her,<br>
And where I thought the remnant of mine age<br>
Should have been cherished by her childlike duty,<br>
I now am full resolved to take a wife<br>
And turn her out to who will take her in.<br>
Then let her beauty be her wedding dower,<br>
For me and my possessions she esteems not.
</p>

<p class="drama">
VALENTINE.<br>
What would your Grace have me to do in this?
</p>

<p class="drama">
DUKE.<br>
There is a lady of Verona here<br>
Whom I affect; but she is nice, and coy,<br>
And nought esteems my aged eloquence.<br>
Now therefore would I have thee to my tutor—<br>
For long agone I have forgot to court;<br>
Besides, the fashion of the time is changed—<br>
How and which way I may bestow myself<br>
To be regarded in her sun-bright eye.
</p>

<p class="drama">
VALENTINE.<br>
Win her with gifts if she respect not words;<br>
Dumb jewels often in their silent kind<br>
More than quick words do move a woman’s mind.
</p>

<p class="drama">
DUKE.<br>
But she did scorn a present that I sent her.
</p>

<p class="drama">
VALENTINE.<br>
A woman sometime scorns what best contents her.<br>
Send her another; never give her o’er,<br>
For scorn at first makes after-love the more.<br>
If she do frown, ’tis not in hate of you,<br>
But rather to beget more love in you.<br>
If she do chide, ’tis not to have you gone,<br>
Forwhy the fools are mad if left alone.<br>
Take no repulse, whatever she doth say;<br>
For “Get you gone” she doth not mean “Away!”<br>
Flatter and praise, commend, extol their graces;<br>
Though ne’er so black, say they have angels’ faces.<br>
That man that hath a tongue, I say, is no man<br>
If with his tongue he cannot win a woman.
</p>

<p class="drama">
DUKE.<br>
But she I mean is promised by her friends<br>
Unto a youthful gentleman of worth,<br>
And kept severely from resort of men,<br>
That no man hath access by day to her.
</p>

<p class="drama">
VALENTINE.<br>
Why then, I would resort to her by night.
</p>

<p class="drama">
DUKE.<br>
Ay, but the doors be locked and keys kept safe,<br>
That no man hath recourse to her by night.
</p>

<p class="drama">
VALENTINE.<br>
What lets but one may enter at her window?
</p>

<p class="drama">
DUKE.<br>
Her chamber is aloft, far from the ground,<br>
And built so shelving that one cannot climb it<br>
Without apparent hazard of his life.
</p>

<p class="drama">
VALENTINE.<br>
Why, then a ladder quaintly made of cords<br>
To cast up with a pair of anchoring hooks,<br>
Would serve to scale another Hero’s tower,<br>
So bold Leander would adventure it.
</p>

<p class="drama">
DUKE.<br>
Now, as thou art a gentleman of blood,<br>
Advise me where I may have such a ladder.
</p>

<p class="drama">
VALENTINE.<br>
When would you use it? Pray, sir, tell me that.
</p>

<p class="drama">
DUKE.<br>
This very night; for Love is like a child<br>
That longs for everything that he can come by.
</p>

<p class="drama">
VALENTINE.<br>
By seven o’clock I’ll get you such a ladder.
</p>

<p class="drama">
DUKE.<br>
But, hark thee: I will go to her alone;<br>
How shall I best convey the ladder thither?
</p>

<p class="drama">
VALENTINE.<br>
It will be light, my lord, that you may bear it<br>
Under a cloak that is of any length.
</p>

<p class="drama">
DUKE.<br>
A cloak as long as thine will serve the turn?
</p>

<p class="drama">
VALENTINE.<br>
Ay, my good lord.
</p>

<p class="drama">
DUKE.<br>
Then let me see thy cloak;<br>
I’ll get me one of such another length.
</p>

<p class="drama">
VALENTINE.<br>
Why, any cloak will serve the turn, my lord.
</p>

<p class="drama">
DUKE.<br>
How shall I fashion me to wear a cloak?<br>
I pray thee, let me feel thy cloak upon me.
</p>

<p class="right">[<i>Takes <span class="charname">Valentine’s</span> cloak and
finds a letter and a rope ladder concealed under it.</i>]</p>

<p class="drama">
What letter is this same? What’s here?—<i>To Silvia?</i><br>
And here an engine fit for my proceeding.<br>
I’ll be so bold to break the seal for once.
</p>

<p class="drama">
[<i>Reads</i>.] <i>My thoughts do harbour with my Silvia nightly,<br>
    And slaves they are to me that send them flying.<br>
O, could their master come and go as lightly,<br>
    Himself would lodge where, senseless, they are lying.<br>
My herald thoughts in thy pure bosom rest them,<br>
    While I, their king, that thither them importune,<br>
Do curse the grace that with such grace hath blest them,<br>
    Because myself do want my servants’ fortune.<br>
I curse myself, for they are sent by me,<br>
That they should harbour where their lord should be.</i><br>
What’s here?<br>
[<i>Reads</i>.] <i>Silvia, this night I will enfranchise thee.</i><br>
’Tis so; and here’s the ladder for the purpose.<br>
Why, Phaëthon—for thou art Merops’ son—<br>
Wilt thou aspire to guide the heavenly car,<br>
And with thy daring folly burn the world?<br>
Wilt thou reach stars because they shine on thee?<br>
Go, base intruder, overweening slave,<br>
Bestow thy fawning smiles on equal mates,<br>
And think my patience, more than thy desert,<br>
Is privilege for thy departure hence.<br>
Thank me for this more than for all the favours<br>
Which, all too much, I have bestowed on thee.<br>
But if thou linger in my territories<br>
Longer than swiftest expedition<br>
Will give thee time to leave our royal court,<br>
By heaven, my wrath shall far exceed the love<br>
I ever bore my daughter or thyself.<br>
Begone, I will not hear thy vain excuse,<br>
But, as thou lov’st thy life, make speed from hence.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
VALENTINE.<br>
And why not death, rather than living torment?<br>
To die is to be banished from myself,<br>
And Silvia is myself; banished from her<br>
Is self from self—a deadly banishment.<br>
What light is light, if Silvia be not seen?<br>
What joy is joy, if Silvia be not by?<br>
Unless it be to think that she is by<br>
And feed upon the shadow of perfection.<br>
Except I be by Silvia in the night,<br>
There is no music in the nightingale.<br>
Unless I look on Silvia in the day,<br>
There is no day for me to look upon.<br>
She is my essence, and I leave to be<br>
If I be not by her fair influence<br>
Fostered, illumined, cherished, kept alive.<br>
I fly not death, to fly his deadly doom:<br>
Tarry I here, I but attend on death,<br>
But fly I hence, I fly away from life.
</p>

<p class="scenedesc">
Enter <span class="charname">Proteus</span> and
<span class="charname">Lance</span>.
</p>

<p class="drama">
PROTEUS.<br>
Run, boy, run, run, seek him out.
</p>

<p class="drama">
LANCE.<br>
So-ho, so-ho!
</p>

<p class="drama">
PROTEUS.<br>
What seest thou?
</p>

<p class="drama">
LANCE.<br>
Him we go to find. There’s not a hair on ’s head but ’tis a Valentine.
</p>

<p class="drama">
PROTEUS.<br>
Valentine?
</p>

<p class="drama">
VALENTINE.<br>
No.
</p>

<p class="drama">
PROTEUS.<br>
Who then? His spirit?
</p>

<p class="drama">
VALENTINE.<br>
Neither.
</p>

<p class="drama">
PROTEUS.<br>
What then?
</p>

<p class="drama">
VALENTINE.<br>
Nothing.
</p>

<p class="drama">
LANCE.<br>
Can nothing speak? Master, shall I strike?
</p>

<p class="drama">
PROTEUS.<br>
Who wouldst thou strike?
</p>

<p class="drama">
LANCE.<br>
Nothing.
</p>

<p class="drama">
PROTEUS.<br>
Villain, forbear.
</p>

<p class="drama">
LANCE.<br>
Why, sir, I’ll strike nothing. I pray you—
</p>

<p class="drama">
PROTEUS.<br>
Sirrah, I say, forbear.—Friend Valentine, a word.
</p>

<p class="drama">
VALENTINE.<br>
My ears are stopped and cannot hear good news,<br>
So much of bad already hath possessed them.
</p>

<p class="drama">
PROTEUS.<br>
Then in dumb silence will I bury mine,<br>
For they are harsh, untuneable, and bad.
</p>

<p class="drama">
VALENTINE.<br>
Is Silvia dead?
</p>

<p class="drama">
PROTEUS.<br>
No, Valentine.
</p>

<p class="drama">
VALENTINE.<br>
No Valentine indeed for sacred Silvia.<br>
Hath she forsworn me?
</p>

<p class="drama">
PROTEUS.<br>
No, Valentine.
</p>

<p class="drama">
VALENTINE.<br>
No Valentine, if Silvia have forsworn me.<br>
What is your news?
</p>

<p class="drama">
LANCE.<br>
Sir, there is a proclamation that you are vanished.
</p>

<p class="drama">
PROTEUS.<br>
That thou art banished—O, that’s the news—<br>
From hence, from Silvia, and from me thy friend.
</p>

<p class="drama">
VALENTINE.<br>
O, I have fed upon this woe already,<br>
And now excess of it will make me surfeit.<br>
Doth Silvia know that I am banished?
</p>

<p class="drama">
PROTEUS.<br>
Ay, ay; and she hath offered to the doom—<br>
Which unreversed stands in effectual force—<br>
A sea of melting pearl, which some call tears;<br>
Those at her father’s churlish feet she tendered,<br>
With them, upon her knees, her humble self,<br>
Wringing her hands, whose whiteness so became them<br>
As if but now they waxed pale for woe.<br>
But neither bended knees, pure hands held up,<br>
Sad sighs, deep groans, nor silver-shedding tears<br>
Could penetrate her uncompassionate sire;<br>
But Valentine, if he be ta’en, must die.<br>
Besides, her intercession chafed him so,<br>
When she for thy repeal was suppliant,<br>
That to close prison he commanded her,<br>
With many bitter threats of biding there.
</p>

<p class="drama">
VALENTINE.<br>
No more, unless the next word that thou speak’st<br>
Have some malignant power upon my life.<br>
If so, I pray thee breathe it in mine ear,<br>
As ending anthem of my endless dolour.
</p>

<p class="drama">
PROTEUS.<br>
Cease to lament for that thou canst not help,<br>
And study help for that which thou lament’st.<br>
Time is the nurse and breeder of all good.<br>
Here if thou stay, thou canst not see thy love;<br>
Besides, thy staying will abridge thy life.<br>
Hope is a lover’s staff; walk hence with that<br>
And manage it against despairing thoughts.<br>
Thy letters may be here, though thou art hence,<br>
Which, being writ to me, shall be delivered<br>
Even in the milk-white bosom of thy love.<br>
The time now serves not to expostulate.<br>
Come, I’ll convey thee through the city-gate,<br>
And, ere I part with thee, confer at large<br>
Of all that may concern thy love affairs.<br>
As thou lov’st Silvia, though not for thyself,<br>
Regard thy danger, and along with me.
</p>

<p class="drama">
VALENTINE.<br>
I pray thee, Lance, an if thou seest my boy,<br>
Bid him make haste and meet me at the North Gate.
</p>

<p class="drama">
PROTEUS.<br>
Go, sirrah, find him out. Come, Valentine.
</p>

<p class="drama">
VALENTINE.<br>
O, my dear Silvia! Hapless Valentine!
</p>

<p class="right">
[<i>Exeunt <span class="charname">Valentine</span> and
<span class="charname">Proteus</span>.</i>]
</p>

<p class="drama">
LANCE.<br>
I am but a fool, look you, and yet I have the wit to think my master is a kind
of a knave; but that’s all one if he be but one knave. He lives not now that
knows me to be in love, yet I am in love, but a team of horse shall not pluck
that from me, nor who ’tis I love; and yet ’tis a woman, but what woman I will
not tell myself; and yet ’tis a milkmaid; yet ’tis not a maid, for she hath had
gossips; yet ’tis a maid, for she is her master’s maid and serves for wages.
She hath more qualities than a water-spaniel, which is much in a bare Christian.
[<i>Pulls out a paper</i>.] Here is the cate-log of her condition. <i>Imprimis,
She can fetch and carry</i>. Why, a horse can do no more; nay, a horse cannot
fetch but only carry; therefore is she better than a jade. <i>Item, She can
milk</i>. Look you, a sweet virtue in a maid with clean hands.
</p>

<p class="scenedesc">
Enter <span class="charname">Speed</span>.
</p>

<p class="drama">
SPEED.<br>
How now, Signior Lance? What news with your mastership?
</p>

<p class="drama">
LANCE.<br>
With my master’s ship? Why, it is at sea.
</p>

<p class="drama">
SPEED.<br>
Well, your old vice still: mistake the word. What news, then, in your paper?
</p>

<p class="drama">
LANCE.<br>
The blackest news that ever thou heard’st.
</p>

<p class="drama">
SPEED.<br>
Why, man? How black?
</p>

<p class="drama">
LANCE.<br>
Why, as black as ink.
</p>

<p class="drama">
SPEED.<br>
Let me read them.
</p>

<p class="drama">
LANCE.<br>
Fie on thee, jolt-head, thou canst not read.
</p>

<p class="drama">
SPEED.<br>
Thou liest. I can.
</p>

<p class="drama">
LANCE.<br>
I will try thee. Tell me this, who begot thee?
</p>

<p class="drama">
SPEED.<br>
Marry, the son of my grandfather.
</p>

<p class="drama">
LANCE.<br>
O, illiterate loiterer! It was the son of thy grandmother.<br>
This proves that thou canst not read.
</p>

<p class="drama">
SPEED.<br>
Come, fool, come; try me in thy paper.
</p>

<p class="drama">
LANCE.<br>
[<i>Gives him the paper</i>.] There; and Saint Nicholas be thy speed.
</p>

<p class="drama">
SPEED.<br>
<i>Imprimis, She can milk.</i>
</p>

<p class="drama">
LANCE.<br>
Ay, that she can.
</p>

<p class="drama">
SPEED.<br>
<i>Item, She brews good ale.</i>
</p>

<p class="drama">
LANCE.<br>
And thereof comes the proverb, “Blessing of your heart, you brew good ale.”
</p>

<p class="drama">
SPEED.<br>
<i>Item, She can sew.</i>
</p>

<p class="drama">
LANCE.<br>
That’s as much as to say, “Can she so?”
</p>

<p class="drama">
SPEED.<br>
<i>Item, She can knit.</i>
</p>

<p class="drama">
LANCE.<br>
What need a man care for a stock with a wench, when she can knit him a stock?
</p>

<p class="drama">
SPEED.<br>
<i>Item, She can wash and scour.</i>
</p>

<p class="drama">
LANCE.<br>
A special virtue, for then she need not be washed and scoured.
</p>

<p class="drama">
SPEED.<br>
<i>Item, She can spin.</i>
</p>

<p class="drama">
LANCE.<br>
Then may I set the world on wheels, when she can spin for her living.
</p>

<p class="drama">
SPEED.<br>
<i>Item, She hath many nameless virtues.</i>
</p>

<p class="drama">
LANCE.<br>
That’s as much as to say, “bastard virtues”, that indeed know not their fathers,
and therefore have no names.
</p>

<p class="drama">
SPEED.<br>
Here follow her vices.
</p>

<p class="drama">
LANCE.<br>
Close at the heels of her virtues.
</p>

<p class="drama">
SPEED.<br>
<i>Item, She is not to be kissed fasting in respect of her breath.</i>
</p>

<p class="drama">
LANCE.<br>
Well, that fault may be mended with a breakfast.<br>
Read on.
</p>

<p class="drama">
SPEED.<br>
<i>Item, She hath a sweet mouth.</i>
</p>

<p class="drama">
LANCE.<br>
That makes amends for her sour breath.
</p>

<p class="drama">
SPEED.<br>
<i>Item, She doth talk in her sleep.</i>
</p>

<p class="drama">
LANCE.<br>
It’s no matter for that, so she sleep not in her talk.
</p>

<p class="drama">
SPEED.<br>
<i>Item, She is slow in words.</i>
</p>

<p class="drama">
LANCE.<br>
O villain, that set this down among her vices! To be slow in words is a woman’s
only virtue. I pray thee, out with’t, and place it for her chief virtue.
</p>

<p class="drama">
SPEED.<br>
<i>Item, She is proud.</i>
</p>

<p class="drama">
LANCE.<br>
Out with that too; it was Eve’s legacy and cannot be ta’en from her.
</p>

<p class="drama">
SPEED.<br>
<i>Item, She hath no teeth.</i>
</p>

<p class="drama">
LANCE.<br>
I care not for that neither, because I love crusts.
</p>

<p class="drama">
SPEED.<br>
<i>Item, She is curst.</i>
</p>

<p class="drama">
LANCE.<br>
Well, the best is, she hath no teeth to bite.
</p>

<p class="drama">
SPEED.<br>
<i>Item, She will often praise her liquor.</i>
</p>

<p class="drama">
LANCE.<br>
If her liquor be good, she shall; if she will not, I will, for good things
should be praised.
</p>

<p class="drama">
SPEED.<br>
<i>Item, She is too liberal.</i>
</p>

<p class="drama">
LANCE.<br>
Of her tongue she cannot, for that’s writ down she is slow of; of her purse she
shall not, for that I’ll keep shut. Now, of another thing she may, and that
cannot I help. Well, proceed.
</p>

<p class="drama">
SPEED.<br>
<i>Item, She hath more hair than wit, and more faults than hairs, and more
wealth than faults.</i>
</p>

<p class="drama">
LANCE.<br>
Stop there; I’ll have her. She was mine and not mine twice or thrice in that
last article. Rehearse that once more.
</p>

<p class="drama">
SPEED.<br>
<i>Item, She hath more hair than wit</i>—
</p>

<p class="drama">
LANCE.<br>
More hair than wit. It may be; I’ll prove it: the cover of the salt hides the
salt, and therefore it is more than the salt; the hair that covers the wit is
more than the wit, for the greater hides the less. What’s next?
</p>

<p class="drama">
SPEED.<br>
<i>And more faults than hairs.</i>
</p>

<p class="drama">
LANCE.<br>
That’s monstrous! O, that that were out!
</p>

<p class="drama">
SPEED.<br>
<i>And more wealth than faults.</i>
</p>

<p class="drama">
LANCE.<br>
Why, that word makes the faults gracious. Well, I’ll have her; an if it be a
match, as nothing is impossible—
</p>

<p class="drama">
SPEED.<br>
What then?
</p>

<p class="drama">
LANCE.<br>
Why, then will I tell thee that thy master stays for thee at the North Gate.
</p>

<p class="drama">
SPEED.<br>
For me?
</p>

<p class="drama">
LANCE.<br>
For thee? Ay, who art thou? He hath stayed for a better man than thee.
</p>

<p class="drama">
SPEED.<br>
And must I go to him?
</p>

<p class="drama">
LANCE.<br>
Thou must run to him, for thou hast stayed so long that going will scarce serve
the turn.
</p>

<p class="drama">
SPEED.<br>
Why didst not tell me sooner? Pox of your love letters!
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
LANCE.<br>
Now will he be swinged for reading my letter; an unmannerly slave, that will
thrust himself into secrets. I’ll after, to rejoice in the boy’s correction.
</p>

<p class="right">[<i>Exit.</i>]</p>

<h3> <a id="sceneIII_37.2"></a><b>SCENE II. The same. A room in the Duke’s palace</b></h3>

<p class="scenedesc">
Enter <span class="charname">Duke</span> and
<span class="charname">Thurio</span>.
</p>

<p class="drama">
DUKE.<br>
Sir Thurio, fear not but that she will love you<br>
Now Valentine is banished from her sight.
</p>

<p class="drama">
THURIO.<br>
Since his exile she hath despised me most,<br>
Forsworn my company and railed at me,<br>
That I am desperate of obtaining her.
</p>

<p class="drama">
DUKE.<br>
This weak impress of love is as a figure<br>
Trenched in ice, which with an hour’s heat<br>
Dissolves to water and doth lose his form.<br>
A little time will melt her frozen thoughts,<br>
And worthless Valentine shall be forgot.
</p>

<p class="scenedesc">
Enter <span class="charname">Proteus</span>.
</p>

<p class="drama">
How now, Sir Proteus? Is your countryman,<br>
According to our proclamation, gone?
</p>

<p class="drama">
PROTEUS.<br>
Gone, my good lord.
</p>

<p class="drama">
DUKE.<br>
My daughter takes his going grievously.
</p>

<p class="drama">
PROTEUS.<br>
A little time, my lord, will kill that grief.
</p>

<p class="drama">
DUKE.<br>
So I believe, but Thurio thinks not so.<br>
Proteus, the good conceit I hold of thee,<br>
For thou hast shown some sign of good desert,<br>
Makes me the better to confer with thee.
</p>

<p class="drama">
PROTEUS.<br>
Longer than I prove loyal to your Grace<br>
Let me not live to look upon your Grace.
</p>

<p class="drama">
DUKE.<br>
Thou know’st how willingly I would effect<br>
The match between Sir Thurio and my daughter?
</p>

<p class="drama">
PROTEUS.<br>
I do, my lord.
</p>

<p class="drama">
DUKE.<br>
And also, I think, thou art not ignorant<br>
How she opposes her against my will?
</p>

<p class="drama">
PROTEUS.<br>
She did, my lord, when Valentine was here.
</p>

<p class="drama">
DUKE.<br>
Ay, and perversely she persevers so.<br>
What might we do to make the girl forget<br>
The love of Valentine, and love Sir Thurio?
</p>

<p class="drama">
PROTEUS.<br>
The best way is to slander Valentine<br>
With falsehood, cowardice, and poor descent,<br>
Three things that women highly hold in hate.
</p>

<p class="drama">
DUKE.<br>
Ay, but she’ll think that it is spoke in hate.
</p>

<p class="drama">
PROTEUS.<br>
Ay, if his enemy deliver it;<br>
Therefore it must with circumstance be spoken<br>
By one whom she esteemeth as his friend.
</p>

<p class="drama">
DUKE.<br>
Then you must undertake to slander him.
</p>

<p class="drama">
PROTEUS.<br>
And that, my lord, I shall be loath to do.<br>
’Tis an ill office for a gentleman,<br>
Especially against his very friend.
</p>

<p class="drama">
DUKE.<br>
Where your good word cannot advantage him,<br>
Your slander never can endamage him;<br>
Therefore the office is indifferent,<br>
Being entreated to it by your friend.
</p>

<p class="drama">
PROTEUS.<br>
You have prevailed, my lord. If I can do it<br>
By aught that I can speak in his dispraise,<br>
She shall not long continue love to him.<br>
But say this weed her love from Valentine,<br>
It follows not that she will love Sir Thurio.
</p>

<p class="drama">
THURIO.<br>
Therefore, as you unwind her love from him,<br>
Lest it should ravel and be good to none,<br>
You must provide to bottom it on me,<br>
Which must be done by praising me as much<br>
As you in worth dispraise Sir Valentine.
</p>

<p class="drama">
DUKE.<br>
And, Proteus, we dare trust you in this kind<br>
Because we know, on Valentine’s report,<br>
You are already Love’s firm votary<br>
And cannot soon revolt and change your mind.<br>
Upon this warrant shall you have access<br>
Where you with Silvia may confer at large—<br>
For she is lumpish, heavy, melancholy,<br>
And, for your friend’s sake, will be glad of you—<br>
Where you may temper her by your persuasion<br>
To hate young Valentine and love my friend.
</p>

<p class="drama">
PROTEUS.<br>
As much as I can do I will effect.<br>
But you, Sir Thurio, are not sharp enough.<br>
You must lay lime to tangle her desires<br>
By wailful sonnets, whose composed rhymes<br>
Should be full-fraught with serviceable vows.
</p>

<p class="drama">
DUKE.<br>
Ay, much is the force of heaven-bred poesy.
</p>

<p class="drama">
PROTEUS.<br>
Say that upon the altar of her beauty<br>
You sacrifice your tears, your sighs, your heart.<br>
Write till your ink be dry, and with your tears<br>
Moist it again, and frame some feeling line<br>
That may discover such integrity.<br>
For Orpheus’ lute was strung with poets’ sinews,<br>
Whose golden touch could soften steel and stones,<br>
Make tigers tame, and huge leviathans<br>
Forsake unsounded deeps to dance on sands.<br>
After your dire-lamenting elegies,<br>
Visit by night your lady’s chamber-window<br>
With some sweet consort; to their instruments<br>
Tune a deploring dump; the night’s dead silence<br>
Will well become such sweet-complaining grievance.<br>
This, or else nothing, will inherit her.
</p>

<p class="drama">
DUKE.<br>
This discipline shows thou hast been in love.
</p>

<p class="drama">
THURIO.<br>
And thy advice this night I’ll put in practice.<br>
Therefore, sweet Proteus, my direction-giver,<br>
Let us into the city presently<br>
To sort some gentlemen well skilled in music.<br>
I have a sonnet that will serve the turn<br>
To give the onset to thy good advice.
</p>

<p class="drama">
DUKE.<br>
About it, gentlemen!
</p>

<p class="drama">
PROTEUS.<br>
We’ll wait upon your Grace till after supper,<br>
And afterward determine our proceedings.
</p>

<p class="drama">
DUKE.<br>
Even now about it! I will pardon you.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

