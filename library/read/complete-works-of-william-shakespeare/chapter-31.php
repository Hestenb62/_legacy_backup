<h2> <a id="sceneII_6.1"></a><b>ACT II</b></h2>

<h3> <b>SCENE I. Rome. A public place</b></h3>

<p class="scenedesc">
Enter <span class="charname">Menenius</span> with the two Tribunes of the people,
<span class="charname">Sicinius</span> and <span class="charname">Brutus</span>.
</p>

<p class="drama">
MENENIUS.<br>
The augurer tells me we shall have news tonight.
</p>

<p class="drama">
BRUTUS.<br>
Good or bad?
</p>

<p class="drama">
MENENIUS.<br>
Not according to the prayer of the people, for they love not Martius.
</p>

<p class="drama">
SICINIUS.<br>
Nature teaches beasts to know their friends.
</p>

<p class="drama">
MENENIUS.<br>
Pray you, who does the wolf love?
</p>

<p class="drama">
SICINIUS.<br>
The lamb.
</p>

<p class="drama">
MENENIUS.<br>
Ay, to devour him, as the hungry plebeians would the noble Martius.
</p>

<p class="drama">
BRUTUS.<br>
He’s a lamb indeed, that baas like a bear.
</p>

<p class="drama">
MENENIUS.<br>
He’s a bear indeed, that lives like a lamb. You two are old men; tell me one
thing that I shall ask you.
</p>

<p class="drama">
BOTH TRIBUNES.<br>
Well, sir.
</p>

<p class="drama">
MENENIUS.<br>
In what enormity is Martius poor in, that you two have not in abundance?
</p>

<p class="drama">
BRUTUS.<br>
He’s poor in no one fault, but stored with all.
</p>

<p class="drama">
SICINIUS.<br>
Especially in pride.
</p>

<p class="drama">
BRUTUS.<br>
And topping all others in boasting.
</p>

<p class="drama">
MENENIUS.<br>
This is strange now. Do you two know how you are censured here in the city, I
mean of us o’ th’ right-hand file, do you?
</p>

<p class="drama">
BOTH TRIBUNES.<br>
Why, how are we censured?
</p>

<p class="drama">
MENENIUS.<br>
Because you talk of pride now, will you not be angry?
</p>

<p class="drama">
BOTH TRIBUNES.<br>
Well, well, sir, well?
</p>

<p class="drama">
MENENIUS.<br>
Why, ’tis no great matter; for a very little thief of occasion will rob you of
a great deal of patience. Give your dispositions the reins, and be angry at
your pleasures, at the least, if you take it as a pleasure to you in being so.
You blame Martius for being proud.
</p>

<p class="drama">
BRUTUS.<br>
We do it not alone, sir.
</p>

<p class="drama">
MENENIUS.<br>
I know you can do very little alone, for your helps are many, or else your
actions would grow wondrous single. Your abilities are too infantlike for
doing much alone. You talk of pride. O that you could turn your eyes toward the
napes of your necks and make but an interior survey of your good selves! O,
that you could!
</p>

<p class="drama">
BOTH TRIBUNES.<br>
What then, sir?
</p>

<p class="drama">
MENENIUS.<br>
Why, then you should discover a brace of unmeriting, proud, violent, testy
magistrates, alias fools, as any in Rome.
</p>

<p class="drama">
SICINIUS.<br>
Menenius, you are known well enough, too.
</p>

<p class="drama">
MENENIUS.<br>
I am known to be a humorous patrician and one that loves a cup of hot wine
with not a drop of allaying Tiber in’t; said to be something imperfect in
favouring the first complaint, hasty and tinder-like upon too trivial motion;
one that converses more with the buttock of the night than with the forehead of
the morning. What I think I utter, and spend my malice in my breath. Meeting
two such wealsmen as you are—I cannot call you Lycurguses—if the drink you
give me touch my palate adversely, I make a crooked face at it. I cannot say
your Worships have delivered the matter well when I find the ass in compound
with the major part of your syllables. And though I must be content to bear
with those that say you are reverend grave men, yet they lie deadly that tell
you have good faces. If you see this in the map of my microcosm, follows it
that I am known well enough too? What harm can your bisson conspectuities glean
out of this character, if I be known well enough, too?
</p>

<p class="drama">
BRUTUS.<br>
Come, sir, come; we know you well enough.
</p>

<p class="drama">
MENENIUS.<br>
You know neither me, yourselves, nor anything. You are ambitious for poor
knaves’ caps and legs. You wear out a good wholesome forenoon in hearing a
cause between an orange-wife and a faucet-seller, and then rejourn the
controversy of threepence to a second day of audience. When you are hearing a
matter between party and party, if you chance to be pinched with the colic, you
make faces like mummers, set up the bloody flag against all patience, and, in
roaring for a chamber pot, dismiss the controversy bleeding, the more entangled
by your hearing. All the peace you make in their cause is calling both the
parties knaves. You are a pair of strange ones.
</p>

<p class="drama">
BRUTUS.<br>
Come, come. You are well understood to be a perfecter giber for the table than
a necessary bencher in the Capitol.
</p>

<p class="drama">
MENENIUS.<br>
Our very priests must become mockers if they shall encounter such ridiculous
subjects as you are. When you speak best unto the purpose, it is not worth the
wagging of your beards, and your beards deserve not so honourable a grave as to
stuff a botcher’s cushion or to be entombed in an ass’s packsaddle. Yet you
must be saying Martius is proud, who, in a cheap estimation, is worth all your
predecessors since Deucalion, though peradventure some of the best of ’em were
hereditary hangmen. Good e’en to your Worships. More of your conversation would
infect my brain, being the herdsmen of the beastly plebeians. I will be bold to
take my leave of you.
</p>

<p class="right">
[<i>He begins to exit. <span class="charname">Brutus</span> and
<span class="charname">Sicinius</span> stand aside.</i>]
</p>

<p class="scenedesc">
Enter <span class="charname">Volumnia, Virgilia</span> and
<span class="charname">Valeria</span>
</p>

<p class="drama">
How now, my as fair as noble ladies—and the moon, were she earthly, no
nobler—whither do you follow your eyes so fast?
</p>

<p class="drama">
VOLUMNIA.<br>
Honourable Menenius, my boy Martius approaches. For the love of Juno, let’s go!
</p>

<p class="drama">
MENENIUS.<br>
Ha? Martius coming home?
</p>

<p class="drama">
VOLUMNIA.<br>
Ay, worthy Menenius, and with most prosperous approbation.
</p>

<p class="drama">
MENENIUS.<br>
Take my cap, Jupiter, and I thank thee! Hoo! Martius coming home?
</p>

<p class="drama">
VALERIA, VIRGILIA.<br>
Nay, ’tis true.
</p>

<p class="drama">
VOLUMNIA.<br>
Look, here’s a letter from him. The state hath another, his wife another, and I
think there’s one at home for you.
</p>

<p class="drama">
MENENIUS.<br>
I will make my very house reel tonight. A letter for me?
</p>

<p class="drama">
VIRGILIA.<br>
Yes, certain, there’s a letter for you; I saw it.
</p>

<p class="drama">
MENENIUS.<br>
A letter for me? It gives me an estate of seven years’ health, in which time I
will make a lip at the physician. The most sovereign prescription in Galen is
but empiricutic and, to this preservative, of no better report than a
horse drench. Is he not wounded? He was wont to come home wounded.
</p>

<p class="drama">
VIRGILIA.<br>
O, no, no, no!
</p>

<p class="drama">
VOLUMNIA.<br>
O, he is wounded, I thank the gods for’t.
</p>

<p class="drama">
MENENIUS.<br>
So do I too, if it be not too much. Brings he victory in his pocket, the wounds
become him.
</p>

<p class="drama">
VOLUMNIA.<br>
On’s brows, Menenius. He comes the third time home with the oaken garland.
</p>

<p class="drama">
MENENIUS.<br>
Has he disciplined Aufidius soundly?
</p>

<p class="drama">
VOLUMNIA.<br>
Titus Lartius writes they fought together, but Aufidius got off.
</p>

<p class="drama">
MENENIUS.<br>
And ’twas time for him too, I’ll warrant him that. An he had stayed by him, I
would not have been so ’fidiused for all the chests in Corioles and the gold
that’s in them. Is the Senate possessed of this?
</p>

<p class="drama">
VOLUMNIA.<br>
Good ladies, let’s go.—Yes, yes, yes. The Senate has letters from the General,
wherein he gives my son the whole name of the war. He hath in this action
outdone his former deeds doubly.
</p>

<p class="drama">
VALERIA.<br>
In troth, there’s wondrous things spoke of him.
</p>

<p class="drama">
MENENIUS.<br>
Wondrous? Ay, I warrant you, and not without his true purchasing.
</p>

<p class="drama">
VIRGILIA.<br>
The gods grant them true.
</p>

<p class="drama">
VOLUMNIA.<br>
True? Pow, waw!
</p>

<p class="drama">
MENENIUS.<br>
True? I’ll be sworn they are true. Where is he wounded? [<i>To the
Tribunes</i>.] God save your good Worships! Martius is coming home; he has more
cause to be proud.—Where is he wounded?
</p>

<p class="drama">
VOLUMNIA.<br>
I’ th’ shoulder and i’ th’ left arm. There will be large cicatrices to show the
people when he shall stand for his place. He received in the repulse of Tarquin
seven hurts i’ th’ body.
</p>

<p class="drama">
MENENIUS.<br>
One i’ th’ neck and two i’ th’ thigh—there’s nine that I know.
</p>

<p class="drama">
VOLUMNIA.<br>
He had, before this last expedition, twenty-five wounds upon him.
</p>

<p class="drama">
MENENIUS.<br>
Now it’s twenty-seven. Every gash was an enemy’s grave.<br>
</p>

<p class="right">
[<i>A shout and flourish</i>.]
</p>

<p class="drama">
Hark, the trumpets!
</p>

<p class="drama">
VOLUMNIA.<br>
These are the ushers of Martius: before him he carries noise, and behind him he
leaves tears.<br>
Death, that dark spirit, in’s nervy arm doth lie,<br>
Which, being advanced, declines, and then men die.
</p>

<p class="right">
[<i>A sennet</i>.]
</p>

<p class="scenedesc">
Enter <span class="charname">Cominius</span> the General and <span class="charname">Titus Lartius</span>, between them <span class="charname">Coriolanus</span> crowned with an oaken garland, with <span class="charname">Captains</span> and Soldiers and a <span class="charname">Herald</span>. Trumpets sound.
</p>

<p class="drama">
HERALD.<br>
Know, Rome, that all alone Martius did fight<br>
Within Corioles’ gates, where he hath won,<br>
With fame, a name to Caius Martius; these<br>
In honour follows “Coriolanus.”<br>
Welcome to Rome, renowned Coriolanus.
</p>

<p class="right">[<i>Sound flourish.</i>]</p>

<p class="drama">
ALL.<br>
Welcome to Rome, renowned Coriolanus!
</p>

<p class="drama">
CORIOLANUS.<br>
No more of this, it does offend my heart.<br>
Pray now, no more.
</p>

<p class="drama">
COMINIUS.<br>
Look, sir, your mother.
</p>

<p class="drama">
CORIOLANUS.<br>
O,<br>
You have, I know, petitioned all the gods<br>
For my prosperity.
</p>

<p class="right">[<i>Kneels.</i>]</p>

<p class="drama">
VOLUMNIA.<br>
Nay, my good soldier, up.
</p>

<p class="right">[<i>He stands.</i>]</p>

<p class="drama">
My gentle Martius, worthy Caius, and<br>
By deed-achieving honour newly named—<br>
What is it? Coriolanus must I call thee?<br>
But, O, thy wife—
</p>

<p class="drama">
CORIOLANUS.<br>
My gracious silence, hail.<br>
Wouldst thou have laughed had I come coffined home,<br>
That weep’st to see me triumph? Ah, my dear,<br>
Such eyes the widows in Corioles wear<br>
And mothers that lack sons.
</p>

<p class="drama">
MENENIUS.<br>
Now the gods crown thee!
</p>

<p class="drama">
CORIOLANUS.<br>
And live you yet? [<i>To Valeria</i>] O my sweet lady, pardon.
</p>

<p class="drama">
VOLUMNIA.<br>
I know not where to turn. O, welcome home!<br>
And welcome, general.—And you’re welcome all.
</p>

<p class="drama">
MENENIUS.<br>
A hundred thousand welcomes! I could weep,<br>
And I could laugh; I am light and heavy. Welcome.<br>
A curse begin at very root on’s heart<br>
That is not glad to see thee! You are three<br>
That Rome should dote on; yet, by the faith of men,<br>
We have some old crab trees here at home that will not<br>
Be grafted to your relish. Yet welcome, warriors!<br>
We call a nettle but a nettle, and<br>
The faults of fools but folly.
</p>

<p class="drama">
COMINIUS.<br>
Ever right.
</p>

<p class="drama">
CORIOLANUS.<br>
Menenius ever, ever.
</p>

<p class="drama">
HERALD.<br>
Give way there, and go on!
</p>

<p class="drama">
CORIOLANUS.<br>
[<i>To Volumnia and Virgilia</i>.] Your hand, and yours.<br>
Ere in our own house I do shade my head,<br>
The good patricians must be visited,<br>
From whom I have received not only greetings,<br>
But with them change of honours.
</p>

<p class="drama">
VOLUMNIA.<br>
I have lived<br>
To see inherited my very wishes<br>
And the buildings of my fancy. Only<br>
There’s one thing wanting, which I doubt not but<br>
Our Rome will cast upon thee.
</p>

<p class="drama">
CORIOLANUS.<br>
Know, good mother,<br>
I had rather be their servant in my way<br>
Than sway with them in theirs.
</p>

<p class="drama">
COMINIUS.<br>
On, to the Capitol.
</p>

<p class="right">[<i>Flourish of cornets. Exeunt in state, as before.</i>]</p>

<p class="scenedesc">
<span class="charname">Brutus</span> and
<span class="charname">Sicinius</span> come forward.
</p>

<p class="drama">
BRUTUS.<br>
All tongues speak of him, and the bleared sights<br>
Are spectacled to see him. Your prattling nurse<br>
Into a rapture lets her baby cry<br>
While she chats him. The kitchen malkin pins<br>
Her richest lockram ’bout her reechy neck,<br>
Clamb’ring the walls to eye him. Stalls, bulks, windows<br>
Are smothered up, leads filled, and ridges horsed<br>
With variable complexions, all agreeing<br>
In earnestness to see him. Seld-shown flamens<br>
Do press among the popular throngs and puff<br>
To win a vulgar station. Our veiled dames<br>
Commit the war of white and damask in<br>
Their nicely-gauded cheeks to th’ wanton spoil<br>
Of Phoebus’ burning kisses. Such a pother,<br>
As if that whatsoever god who leads him<br>
Were slyly crept into his human powers<br>
And gave him graceful posture.
</p>

<p class="drama">
SICINIUS.<br>
On the sudden<br>
I warrant him consul.
</p>

<p class="drama">
BRUTUS.<br>
Then our office may,<br>
During his power, go sleep.
</p>

<p class="drama">
SICINIUS.<br>
He cannot temp’rately transport his honours<br>
From where he should begin and end, but will<br>
Lose those he hath won.
</p>

<p class="drama">
BRUTUS.<br>
In that there’s comfort.
</p>

<p class="drama">
SICINIUS.<br>
Doubt not the commoners, for whom we stand,<br>
But they, upon their ancient malice will forget<br>
With the least cause these his new honours—which<br>
That he will give them make as little question<br>
As he is proud to do’t.
</p>

<p class="drama">
BRUTUS.<br>
I heard him swear,<br>
Were he to stand for consul, never would he<br>
Appear i’ th’ marketplace nor on him put<br>
The napless vesture of humility,<br>
Nor showing, as the manner is, his wounds<br>
To th’ people, beg their stinking breaths.
</p>

<p class="drama">
SICINIUS.<br>
’Tis right.
</p>

<p class="drama">
BRUTUS.<br>
It was his word. O, he would miss it rather<br>
Than carry it but by the suit of the gentry to him<br>
And the desire of the nobles.
</p>

<p class="drama">
SICINIUS.<br>
I wish no better<br>
Than have him hold that purpose and to put it<br>
In execution.
</p>

<p class="drama">
BRUTUS.<br>
’Tis most like he will.
</p>

<p class="drama">
SICINIUS.<br>
It shall be to him then, as our good wills,<br>
A sure destruction.
</p>

<p class="drama">
BRUTUS.<br>
So it must fall out<br>
To him, or our authorities for an end.<br>
We must suggest the people in what hatred<br>
He still hath held them; that to’s power he would<br>
Have made them mules, silenced their pleaders, and<br>
Dispropertied their freedoms; holding them<br>
In human action and capacity<br>
Of no more soul nor fitness for the world<br>
Than camels in their war, who have their provand<br>
Only for bearing burdens, and sore blows<br>
For sinking under them.
</p>

<p class="drama">
SICINIUS.<br>
This, as you say, suggested<br>
At some time when his soaring insolence<br>
Shall touch the people—which time shall not want<br>
If it be put upon’t, and that’s as easy<br>
As to set dogs on sheep—will be his fire<br>
To kindle their dry stubble, and their blaze<br>
Shall darken him for ever.
</p>

<p class="scenedesc">
Enter a <span class="charname">Messenger</span>.
</p>

<p class="drama">
BRUTUS.<br>
What’s the matter?
</p>

<p class="drama">
MESSENGER.<br>
You are sent for to the Capitol. ’Tis thought<br>
That Martius shall be consul. I have seen<br>
The dumb men throng to see him, and the blind<br>
to hear him speak; matrons flung gloves,<br>
Ladies and maids their scarves and handkerchiefs,<br>
Upon him as he passed; the nobles bended<br>
As to Jove’s statue, and the Commons made<br>
A shower and thunder with their caps and shouts.<br>
I never saw the like.
</p>

<p class="drama">
BRUTUS.<br>
Let’s to the Capitol;<br>
And carry with us ears and eyes for th’ time,<br>
But hearts for the event.
</p>

<p class="drama">
SICINIUS.<br>
Have with you.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneII_6.2"></a><b>SCENE II. Rome. The Capitol</b></h3>

<p class="scenedesc">
Enter two <span class="charname">Officers</span>, to lay cushions, as it were
in the Capitol.
</p>

<p class="drama">
FIRST OFFICER.<br>
Come, come. They are almost here. How many stand for consulships?
</p>

<p class="drama">
SECOND OFFICER.<br>
Three, they say; but ’tis thought of everyone Coriolanus will carry it.
</p>

<p class="drama">
FIRST OFFICER.<br>
That’s a brave fellow, but he’s vengeance proud and loves not the common
people.
</p>

<p class="drama">
SECOND OFFICER.<br>
’Faith, there have been many great men that have flattered the people who ne’er
loved them; and there be many that they have loved they know not wherefore; so
that, if they love they know not why, they hate upon no better a ground.
Therefore, for Coriolanus neither to care whether they love or hate him
manifests the true knowledge he has in their disposition and, out of his noble
carelessness, lets them plainly see’t.
</p>

<p class="drama">
FIRST OFFICER.<br>
If he did not care whether he had their love or no, he waved indifferently
’twixt doing them neither good nor harm; but he seeks their hate with greater
devotion than they can render it him and leaves nothing undone that may fully
discover him their opposite. Now, to seem to affect the malice and displeasure
of the people is as bad as that which he dislikes, to flatter them for their
love.
</p>

<p class="drama">
SECOND OFFICER.<br>
He hath deserved worthily of his country, and his ascent is not by such easy
degrees as those who, having been supple and courteous to the people,
bonnetted, without any further deed to have them at all into their estimation
and report; but he hath so planted his honours in their eyes and his actions
in their hearts that for their tongues to be silent and not confess so much
were a kind of ingrateful injury. To report otherwise were a malice that,
giving itself the lie, would pluck reproof and rebuke from every ear that heard
it.
</p>

<p class="drama">
FIRST OFFICER.<br>
No more of him; he’s a worthy man. Make way. They are coming.
</p>

<p class="scenedesc">
A sennet. Enter the Patricians and the Tribunes of the people, Lictors before
them; <span class="charname">Coriolanus, Menenius, Cominius</span> the consul.
The Patricians sit.  <span class="charname">Sicinius</span> and <span class="charname">Brutus</span> take their places by themselves. <span class="charname">Coriolanus</span> stands.
</p>

<p class="drama">
MENENIUS.<br>
Having determined of the Volsces and<br>
To send for Titus Lartius, it remains,<br>
As the main point of this our after-meeting,<br>
To gratify his noble service that<br>
Hath thus stood for his country. Therefore please you,<br>
Most reverend and grave elders, to desire<br>
The present consul and last general<br>
In our well-found successes to report<br>
A little of that worthy work performed<br>
By Martius Caius Coriolanus, whom<br>
We met here both to thank and to remember<br>
With honours like himself.
</p>

<p class="right">[<i><span class="charname">Coriolanus</span> sits.</i>]</p>

<p class="drama">
FIRST SENATOR.<br>
Speak, good Cominius.<br>
Leave nothing out for length, and make us think<br>
Rather our state’s defective for requital,<br>
Than we to stretch it out. Masters o’ th’ people,<br>
We do request your kindest ears and, after,<br>
Your loving motion toward the common body<br>
To yield what passes here.
</p>

<p class="drama">
SICINIUS.<br>
We are convented<br>
Upon a pleasing treaty and have hearts<br>
Inclinable to honour and advance<br>
The theme of our assembly.
</p>

<p class="drama">
BRUTUS.<br>
Which the rather<br>
We shall be blest to do if he remember<br>
A kinder value of the people than<br>
He hath hereto prized them at.
</p>

<p class="drama">
MENENIUS.<br>
That’s off, that’s off!<br>
I would you rather had been silent. Please you<br>
To hear Cominius speak?
</p>

<p class="drama">
BRUTUS.<br>
Most willingly.<br>
But yet my caution was more pertinent<br>
Than the rebuke you give it.
</p>

<p class="drama">
MENENIUS.<br>
He loves your people,<br>
But tie him not to be their bedfellow.—<br>
Worthy Cominius, speak.
</p>

<p class="right">[<i><span class="charname">Coriolanus</span> rises, and offers
to go away.</i>]</p>

<p class="drama">
Nay, keep your place.
</p>

<p class="drama">
FIRST SENATOR.<br>
Sit, Coriolanus. Never shame to hear<br>
What you have nobly done.
</p>

<p class="drama">
CORIOLANUS.<br>
Your Honours, pardon.<br>
I had rather have my wounds to heal again<br>
Than hear say how I got them.
</p>

<p class="drama">
BRUTUS.<br>
Sir, I hope<br>
My words disbenched you not?
</p>

<p class="drama">
CORIOLANUS.<br>
No, sir. Yet oft,<br>
When blows have made me stay, I fled from words.<br>
You soothed not, therefore hurt not; but your people,<br>
I love them as they weigh.
</p>

<p class="drama">
MENENIUS.<br>
Pray now, sit down.
</p>

<p class="drama">
CORIOLANUS.<br>
I had rather have one scratch my head i’ th’ sun<br>
When the alarum were struck than idly sit<br>
To hear my nothings monstered.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
MENENIUS.<br>
Masters of the people,<br>
Your multiplying spawn how can he flatter—<br>
That’s thousand to one good one—when you now see<br>
He had rather venture all his limbs for honour<br>
Than one on’s ears to hear it?—Proceed, Cominius.
</p>

<p class="drama">
COMINIUS.<br>
I shall lack voice. The deeds of Coriolanus<br>
Should not be uttered feebly. It is held<br>
That valour is the chiefest virtue and<br>
Most dignifies the haver; if it be,<br>
The man I speak of cannot in the world<br>
Be singly counterpoised. At sixteen years,<br>
When Tarquin made a head for Rome, he fought<br>
Beyond the mark of others. Our then dictator,<br>
Whom with all praise I point at, saw him fight<br>
When with his Amazonian chin he drove<br>
The bristled lips before him. He bestrid<br>
An o’erpressed Roman and i’ th’ Consul’s view<br>
Slew three opposers. Tarquin’s self he met<br>
And struck him on his knee. In that day’s feats,<br>
When he might act the woman in the scene,<br>
He proved best man i’ th’ field and for his meed<br>
Was brow-bound with the oak. His pupil age<br>
Man-entered thus, he waxed like a sea,<br>
And in the brunt of seventeen battles since<br>
He lurched all swords of the garland. For this last,<br>
Before and in Corioles, let me say,<br>
I cannot speak him home. He stopped the flyers<br>
And by his rare example made the coward<br>
Turn terror into sport. As weeds before<br>
A vessel under sail, so men obeyed<br>
And fell below his stem. His sword, Death’s stamp,<br>
Where it did mark, it took; from face to foot<br>
He was a thing of blood, whose every motion<br>
Was timed with dying cries. Alone he entered<br>
The mortal gate o’ th’ city, which he painted<br>
With shunless destiny; aidless came off<br>
And with a sudden reinforcement struck<br>
Corioles like a planet. Now all’s his,<br>
When by and by the din of war gan pierce<br>
His ready sense; then straight his doubled spirit<br>
Requickened what in flesh was fatigate,<br>
And to the battle came he, where he did<br>
Run reeking o’er the lives of men as if<br>
’Twere a perpetual spoil; and till we called<br>
Both field and city ours, he never stood<br>
To ease his breast with panting.
</p>

<p class="drama">
MENENIUS.<br>
Worthy man!
</p>

<p class="drama">
FIRST SENATOR.<br>
He cannot but with measure fit the honours<br>
Which we devise him.
</p>

<p class="drama">
COMINIUS.<br>
Our spoils he kicked at;<br>
And looked upon things precious as they were<br>
The common muck of the world. He covets less<br>
Than misery itself would give, rewards<br>
His deeds with doing them, and is content<br>
To spend the time to end it.
</p>

<p class="drama">
MENENIUS.<br>
He’s right noble.<br>
Let him be called for.
</p>

<p class="drama">
FIRST SENATOR.<br>
Call Coriolanus.
</p>

<p class="drama">
OFFICER.<br>
He doth appear.
</p>

<p class="scenedesc">
Enter <span class="charname">Coriolanus</span>.
</p>

<p class="drama">
MENENIUS.<br>
The Senate, Coriolanus, are well pleased<br>
To make thee consul.
</p>

<p class="drama">
CORIOLANUS.<br>
I do owe them still<br>
My life and services.
</p>

<p class="drama">
MENENIUS.<br>
It then remains<br>
That you do speak to the people.
</p>

<p class="drama">
CORIOLANUS.<br>
I do beseech you<br>
Let me o’erleap that custom, for I cannot<br>
Put on the gown, stand naked, and entreat them<br>
For my wounds’ sake to give their suffrage. Please you<br>
That I may pass this doing.
</p>

<p class="drama">
SICINIUS.<br>
Sir, the people<br>
Must have their voices; neither will they bate<br>
One jot of ceremony.
</p>

<p class="drama">
MENENIUS.<br>
Put them not to’t.<br>
Pray you, go fit you to the custom, and<br>
Take to you, as your predecessors have,<br>
Your honour with your form.
</p>

<p class="drama">
CORIOLANUS.<br>
It is a part<br>
That I shall blush in acting, and might well<br>
Be taken from the people.
</p>

<p class="drama">
BRUTUS.<br>
Mark you that?
</p>

<p class="drama">
CORIOLANUS.<br>
To brag unto them, “thus I did, and thus!”<br>
Show them th’ unaching scars which I should hide,<br>
As if I had received them for the hire<br>
Of their breath only!
</p>

<p class="drama">
MENENIUS.<br>
Do not stand upon’t.—<br>
We recommend to you, tribunes of the people,<br>
Our purpose to them, and to our noble consul<br>
Wish we all joy and honour.
</p>

<p class="drama">
SENATORS.<br>
To Coriolanus come all joy and honour!
</p>

<p class="right">
[<i>Flourish cornets. Exeunt all but <span class="charname">Sicinius</span> and
<span class="charname">Brutus</span>.</i>]
</p>

<p class="drama">
BRUTUS.<br>
You see how he intends to use the people.
</p>

<p class="drama">
SICINIUS.<br>
May they perceive’s intent! He will require them<br>
As if he did contemn what he requested<br>
Should be in them to give.
</p>

<p class="drama">
BRUTUS.<br>
Come, we’ll inform them<br>
Of our proceedings here. On th’ marketplace<br>
I know they do attend us.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneII_6.3"></a><b>SCENE III. Rome. The Forum</b></h3>

<p class="scenedesc">
Enter seven or eight Citizens.
</p>

<p class="drama">
FIRST CITIZEN.<br>
Once, if he do require our voices, we ought not to deny him.
</p>

<p class="drama">
SECOND CITIZEN.<br>
We may, sir, if we will.
</p>

<p class="drama">
THIRD CITIZEN.<br>
We have power in ourselves to do it, but it is a power that we have no power to
do; for, if he show us his wounds and tell us his deeds, we are to put our
tongues into those wounds and speak for them. So, if he tell us his noble
deeds, we must also tell him our noble acceptance of them. Ingratitude is
monstrous, and for the multitude to be ingrateful were to make a monster of the
multitude, of the which we being members, should bring ourselves to be
monstrous members.
</p>

<p class="drama">
FIRST CITIZEN.<br>
And to make us no better thought of, a little help will serve; for once we
stood up about the corn, he himself stuck not to call us the many-headed
multitude.
</p>

<p class="drama">
THIRD CITIZEN.<br>
We have been called so of many; not that our heads are some brown, some black,
some auburn, some bald, but that our wits are so diversely coloured; and truly
I think if all our wits were to issue out of one skull, they would fly east,
west, north, south, and their consent of one direct way should be at once to
all the points o’ th’ compass.
</p>

<p class="drama">
SECOND CITIZEN.<br>
Think you so? Which way do you judge my wit would fly?
</p>

<p class="drama">
THIRD CITIZEN.<br>
Nay, your wit will not so soon out as another man’s will; ’tis strongly wedged
up in a blockhead. But if it were at liberty, ’twould, sure, southward.
</p>

<p class="drama">
SECOND CITIZEN.<br>
Why that way?
</p>

<p class="drama">
THIRD CITIZEN.<br>
To lose itself in a fog, where being three parts melted away with rotten dews,
the fourth would return for conscience’ sake, to help to get thee a wife.
</p>

<p class="drama">
SECOND CITIZEN.<br>
You are never without your tricks. You may, you may.
</p>

<p class="drama">
THIRD CITIZEN.<br>
Are you all resolved to give your voices? But that’s no matter; the greater
part carries it. I say, if he would incline to the people, there was never a
worthier man.
</p>

<p class="scenedesc">
Enter <span class="charname">Coriolanus</span> in a gown of humility, with
<span class="charname">Menenius</span>.
</p>

<p class="drama">
Here he comes, and in the gown of humility. Mark his behaviour.
We are not to stay all together, but to come by him where he stands, by ones,
by twos, and by threes. He’s to make his requests by particulars, wherein
everyone of us has a single honour in giving him our own voices with our own
tongues. Therefore follow me, and I’ll direct you how you shall go by him.
</p>

<p class="drama">
ALL.<br>
Content, content.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<p class="drama">
MENENIUS.<br>
O sir, you are not right. Have you not known<br>
The worthiest men have done’t?
</p>

<p class="drama">
CORIOLANUS.<br>
What must I say?<br>
“I pray, sir”—plague upon’t! I cannot bring<br>
My tongue to such a pace. “Look, sir, my wounds!<br>
I got them in my country’s service when<br>
Some certain of your brethren roared and ran<br>
From th’ noise of our own drums.”
</p>

<p class="drama">
MENENIUS.<br>
O me, the gods!<br>
You must not speak of that. You must desire them<br>
To think upon you.
</p>

<p class="drama">
CORIOLANUS.<br>
Think upon me! Hang ’em!<br>
I would they would forget me, like the virtues<br>
Which our divines lose by ’em.
</p>

<p class="drama">
MENENIUS.<br>
You’ll mar all.<br>
I’ll leave you. Pray you speak to ’em, I pray you,<br>
In wholesome manner.
</p>

<p class="right">[<i>Exit <span class="charname">Menenius</span>.</i>]</p>

<p class="drama">
CORIOLANUS.<br>
Bid them wash their faces<br>
And keep their teeth clean.
</p>

<p class="scenedesc">
Enter three of the Citizens.
</p>

<p class="drama">
So, here comes a brace.<br>
You know the cause, sirs, of my standing here.
</p>

<p class="drama">
THIRD CITIZEN.<br>
We do, sir. Tell us what hath brought you to’t.
</p>

<p class="drama">
CORIOLANUS.<br>
Mine own desert.
</p>

<p class="drama">
SECOND CITIZEN.<br>
Your own desert?
</p>

<p class="drama">
CORIOLANUS.<br>
Ay, but not mine own desire.
</p>

<p class="drama">
THIRD CITIZEN.<br>
How, not your own desire?
</p>

<p class="drama">
CORIOLANUS.<br>
No, sir, ’twas never my desire yet to trouble the poor with begging.
</p>

<p class="drama">
THIRD CITIZEN.<br>
You must think if we give you anything, we hope to gain by you.
</p>

<p class="drama">
CORIOLANUS.<br>
Well then, I pray, your price o’ th’ consulship?
</p>

<p class="drama">
FIRST CITIZEN.<br>
The price is to ask it kindly.
</p>

<p class="drama">
CORIOLANUS.<br>
Kindly, sir, I pray, let me ha’t. I have wounds to show you, which shall be
yours in private.—Your good voice, sir. What say you?
</p>

<p class="drama">
SECOND CITIZEN.<br>
You shall ha’ it, worthy sir.
</p>

<p class="drama">
CORIOLANUS.<br>
A match, sir. There’s in all two worthy voices begged. I have your alms. Adieu.
</p>

<p class="drama">
THIRD CITIZEN.<br>
But this is something odd.
</p>

<p class="drama">
SECOND CITIZEN.<br>
An ’twere to give again—but ’tis no matter.
</p>

<p class="right">[<i>Exeunt two citizens.</i>]</p>

<p class="scenedesc">
Enter two other Citizens.
</p>

<p class="drama">
CORIOLANUS.<br>
Pray you now, if it may stand with the tune of your voices that I may be
consul, I have here the customary gown.
</p>

<p class="drama">
FOURTH CITIZEN.<br>
You have deserved nobly of your country, and you have not deserved nobly.
</p>

<p class="drama">
CORIOLANUS.<br>
Your enigma?
</p>

<p class="drama">
FOURTH CITIZEN.<br>
You have been a scourge to her enemies; you have been a rod to her friends. You
have not indeed loved the common people.
</p>

<p class="drama">
CORIOLANUS.<br>
You should account me the more virtuous that I have not been common in my
love. I will, sir, flatter my sworn brother, the people, to earn a dearer
estimation of them; ’tis a condition they account gentle. And since the wisdom
of their choice is rather to have my hat than my heart, I will practise the
insinuating nod and be off to them most counterfeitly. That is, sir, I will
counterfeit the bewitchment of some popular man and give it bountiful to the
desirers. Therefore, beseech you, I may be consul.
</p>

<p class="drama">
FIFTH CITIZEN.<br>
We hope to find you our friend, and therefore give you our voices heartily.
</p>

<p class="drama">
FOURTH CITIZEN.<br>
You have received many wounds for your country.
</p>

<p class="drama">
CORIOLANUS.<br>
I will not seal your knowledge with showing them. I will make much of your
voices and so trouble you no farther.
</p>

<p class="drama">
BOTH CITIZENS.<br>
The gods give you joy, sir, heartily.
</p>

<p class="right">[<i>Exeunt citizens.</i>]</p>

<p class="drama">
CORIOLANUS.<br>
Most sweet voices!<br>
Better it is to die, better to starve,<br>
Than crave the hire which first we do deserve.<br>
Why in this wolvish toge should I stand here<br>
To beg of Hob and Dick that does appear<br>
Their needless vouches? Custom calls me to’t.<br>
What custom wills, in all things should we do’t?<br>
The dust on antique time would lie unswept<br>
And mountainous error be too highly heaped<br>
For truth to o’erpeer. Rather than fool it so,<br>
Let the high office and the honour go<br>
To one that would do thus. I am half through;<br>
The one part suffered, the other will I do.<br>
</p>

<p class="scenedesc">
Enter three Citizens more.
</p>

<p class="drama">
Here come more voices.<br>
Your voices! For your voices I have fought;<br>
Watched for your voices; for your voices bear<br>
Of wounds two dozen odd. Battles thrice six<br>
I have seen and heard of; for your voices have<br>
Done many things, some less, some more. Your voices!<br>
Indeed, I would be consul.
</p>

<p class="drama">
SIXTH CITIZEN.<br>
He has done nobly, and cannot go without any honest man’s voice.
</p>

<p class="drama">
SEVENTH CITIZEN.<br>
Therefore let him be consul. The gods give him joy, and make him good friend to
the people!
</p>

<p class="drama">
ALL THREE CITIZENS.<br>
Amen, amen. God save thee, noble consul.
</p>

<p class="right">[<i>Exeunt citizens.</i>]</p>

<p class="drama">
CORIOLANUS.<br>
Worthy voices!
</p>

<p class="scenedesc">
Enter <span class="charname">Menenius</span> with
<span class="charname">Brutus</span> and <span class="charname">Sicinius</span>.
</p>

<p class="drama">
MENENIUS.<br>
You have stood your limitation, and the Tribunes<br>
Endue you with the people’s voice. Remains<br>
That in th’ official marks invested, you<br>
Anon do meet the Senate.
</p>

<p class="drama">
CORIOLANUS.<br>
Is this done?
</p>

<p class="drama">
SICINIUS.<br>
The custom of request you have discharged.<br>
The people do admit you, and are summoned<br>
To meet anon upon your approbation.
</p>

<p class="drama">
CORIOLANUS.<br>
Where? At the Senate House?
</p>

<p class="drama">
SICINIUS.<br>
There, Coriolanus.
</p>

<p class="drama">
CORIOLANUS.<br>
May I change these garments?
</p>

<p class="drama">
SICINIUS.<br>
You may, sir.
</p>

<p class="drama">
CORIOLANUS.<br>
That I’ll straight do and, knowing myself again,<br>
Repair to th’ Senate House.
</p>

<p class="drama">
MENENIUS.<br>
I’ll keep you company.—Will you along?
</p>

<p class="drama">
BRUTUS.<br>
We stay here for the people.
</p>

<p class="drama">
SICINIUS.<br>
Fare you well.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Coriolanus</span> and
<span class="charname">Menenius</span>.</i>]
</p>

<p class="drama">
He has it now; and by his looks, methinks,<br>
’Tis warm at his heart.
</p>

<p class="drama">
BRUTUS.<br>
With a proud heart he wore<br>
His humble weeds. Will you dismiss the people?
</p>

<p class="scenedesc">
Enter the Pebleians.
</p>

<p class="drama">
SICINIUS.<br>
How now, my masters, have you chose this man?
</p>

<p class="drama">
FIRST CITIZEN.<br>
He has our voices, sir.
</p>

<p class="drama">
BRUTUS.<br>
We pray the gods he may deserve your loves.
</p>

<p class="drama">
SECOND CITIZEN.<br>
Amen, sir. To my poor unworthy notice,<br>
He mocked us when he begged our voices.
</p>

<p class="drama">
THIRD CITIZEN.<br>
Certainly, he flouted us downright.
</p>

<p class="drama">
FIRST CITIZEN.<br>
No, ’tis his kind of speech. He did not mock us.
</p>

<p class="drama">
SECOND CITIZEN.<br>
Not one amongst us, save yourself, but says<br>
He used us scornfully. He should have showed us<br>
His marks of merit, wounds received for’s country.
</p>

<p class="drama">
SICINIUS.<br>
Why, so he did, I am sure.
</p>

<p class="drama">
ALL.<br>
No, no. No man saw ’em.
</p>

<p class="drama">
THIRD CITIZEN.<br>
He said he had wounds, which he could show in private,<br>
And with his hat, thus waving it in scorn,<br>
“I would be consul,” says he; “aged custom,<br>
But by your voices, will not so permit me;<br>
Your voices therefore.” When we granted that,<br>
Here was “I thank you for your voices. Thank you.<br>
Your most sweet voices! Now you have left your voices,<br>
I have no further with you.” Was not this mockery?
</p>

<p class="drama">
SICINIUS.<br>
Why either were you ignorant to see’t<br>
Or, seeing it, of such childish friendliness<br>
To yield your voices?
</p>

<p class="drama">
BRUTUS.<br>
Could you not have told him<br>
As you were lessoned? When he had no power,<br>
But was a petty servant to the state,<br>
He was your enemy, ever spake against<br>
Your liberties and the charters that you bear<br>
I’ th’ body of the weal; and, now arriving<br>
A place of potency and sway o’ th’ state,<br>
If he should still malignantly remain<br>
Fast foe to th’ plebeii, your voices might<br>
Be curses to yourselves. You should have said<br>
That as his worthy deeds did claim no less<br>
Than what he stood for, so his gracious nature<br>
Would think upon you for your voices, and<br>
Translate his malice towards you into love,<br>
Standing your friendly lord.
</p>

<p class="drama">
SICINIUS.<br>
Thus to have said,<br>
As you were fore-advised, had touched his spirit<br>
And tried his inclination; from him plucked<br>
Either his gracious promise, which you might,<br>
As cause had called you up, have held him to;<br>
Or else it would have galled his surly nature,<br>
Which easily endures not article<br>
Tying him to aught. So putting him to rage,<br>
You should have ta’en th’ advantage of his choler<br>
And passed him unelected.
</p>

<p class="drama">
BRUTUS.<br>
Did you perceive<br>
He did solicit you in free contempt<br>
When he did need your loves, and do you think<br>
That his contempt shall not be bruising to you<br>
When he hath power to crush? Why, had your bodies<br>
No heart among you? Or had you tongues to cry<br>
Against the rectorship of judgment?
</p>

<p class="drama">
SICINIUS.<br>
Have you ere now denied the asker, and now<br>
Again, of him that did not ask but mock,<br>
Bestow your sued-for tongues?
</p>

<p class="drama">
THIRD CITIZEN.<br>
He’s not confirmed.<br>
We may deny him yet.
</p>

<p class="drama">
SECOND CITIZEN.<br>
And will deny him.<br>
I’ll have five hundred voices of that sound.
</p>

<p class="drama">
FIRST CITIZEN.<br>
I twice five hundred, and their friends to piece ’em.
</p>

<p class="drama">
BRUTUS.<br>
Get you hence instantly, and tell those friends<br>
They have chose a consul that will from them take<br>
Their liberties, make them of no more voice<br>
Than dogs that are as often beat for barking<br>
As therefore kept to do so.
</p>

<p class="drama">
SICINIUS.<br>
Let them assemble<br>
And, on a safer judgment, all revoke<br>
Your ignorant election. Enforce his pride<br>
And his old hate unto you. Besides, forget not<br>
With what contempt he wore the humble weed,<br>
How in his suit he scorned you; but your loves,<br>
Thinking upon his services, took from you<br>
Th’ apprehension of his present portance,<br>
Which most gibingly, ungravely, he did fashion<br>
After the inveterate hate he bears you.
</p>

<p class="drama">
BRUTUS.<br>
Lay<br>
A fault on us, your tribunes, that we laboured,<br>
No impediment between, but that you must<br>
Cast your election on him.
</p>

<p class="drama">
SICINIUS.<br>
Say you chose him<br>
More after our commandment than as guided<br>
By your own true affections, and that your minds,<br>
Preoccupied with what you rather must do<br>
Than what you should, made you against the grain<br>
To voice him consul. Lay the fault on us.
</p>

<p class="drama">
BRUTUS.<br>
Ay, spare us not. Say we read lectures to you,<br>
How youngly he began to serve his country,<br>
How long continued, and what stock he springs of,<br>
The noble house o’ th’ Martians, from whence came<br>
That Ancus Martius, Numa’s daughter’s son,<br>
Who, after great Hostilius here was king,<br>
Of the same house Publius and Quintus were,<br>
That our best water brought by conduits hither;<br>
And Censorinus, that was so surnamed,<br>
And nobly named so, twice being censor,<br>
Was his great ancestor.
</p>

<p class="drama">
SICINIUS.<br>
One thus descended,<br>
That hath beside well in his person wrought<br>
To be set high in place, we did commend<br>
To your remembrances; but you have found,<br>
Scaling his present bearing with his past,<br>
That he’s your fixed enemy, and revoke<br>
Your sudden approbation.
</p>

<p class="drama">
BRUTUS.<br>
Say you ne’er had done’t—<br>
Harp on that still—but by our putting on.<br>
And presently when you have drawn your number,<br>
Repair to th’ Capitol.
</p>

<p class="drama">
ALL.<br>
We will so. Almost all<br>
Repent in their election.
</p>

<p class="right">[<i>Exeunt Plebeians.</i>]</p>

<p class="drama">
BRUTUS.<br>
Let them go on.<br>
This mutiny were better put in hazard<br>
Than stay, past doubt, for greater.<br>
If, as his nature is, he fall in rage<br>
With their refusal, both observe and answer<br>
The vantage of his anger.
</p>

<p class="drama">
SICINIUS.<br>
To th’ Capitol, come.<br>
We will be there before the stream o’ th’ people,<br>
And this shall seem, as partly ’tis, their own,<br>
Which we have goaded onward.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

