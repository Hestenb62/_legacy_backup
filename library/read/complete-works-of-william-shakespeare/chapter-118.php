<h2> <a id="sceneII_19.1"></a><b>ACT II</b></h2>

<h3> <b>SCENE I. The King of Navarre’s park. A pavilion and tents at a
distance</b></h3>

<p class="scenedesc">
Enter the <span class="charname">Princess of France,</span> with three attending Ladies: <span class="charname">Rosaline, Maria, Katharine</span>
and three Lords: <span class="charname">Boyet,</span> and two others.
</p>

<p class="drama">
BOYET.<br>
Now, madam, summon up your dearest spirits.<br>
Consider who the King your father sends,<br>
To whom he sends, and what’s his embassy.<br>
Yourself, held precious in the world’s esteem,<br>
To parley with the sole inheritor<br>
Of all perfections that a man may owe,<br>
Matchless Navarre; the plea of no less weight<br>
Than Aquitaine, a dowry for a queen.<br>
Be now as prodigal of all dear grace<br>
As Nature was in making graces dear<br>
When she did starve the general world beside<br>
And prodigally gave them all to you.
</p>

<p class="drama">
PRINCESS.<br>
Good Lord Boyet, my beauty, though but mean,<br>
Needs not the painted flourish of your praise.<br>
Beauty is bought by judgement of the eye,<br>
Not uttered by base sale of chapmen’s tongues.<br>
I am less proud to hear you tell my worth<br>
Than you much willing to be counted wise<br>
In spending your wit in the praise of mine.<br>
But now to task the tasker: good Boyet,<br>
You are not ignorant, all-telling fame<br>
Doth noise abroad Navarre hath made a vow,<br>
Till painful study shall outwear three years,<br>
No woman may approach his silent court.<br>
Therefore to’s seemeth it a needful course,<br>
Before we enter his forbidden gates,<br>
To know his pleasure; and in that behalf,<br>
Bold of your worthiness, we single you<br>
As our best-moving fair solicitor.<br>
Tell him the daughter of the King of France,<br>
On serious business craving quick dispatch,<br>
Importunes personal conference with his Grace.<br>
Haste, signify so much, while we attend,<br>
Like humble-visaged suitors, his high will.
</p>

<p class="drama">
BOYET.<br>
Proud of employment, willingly I go.
</p>

<p class="drama">
PRINCESS.<br>
All pride is willing pride, and yours is so.
</p>

<p class="right">[<i>Exit <span class="charname">Boyet</span>.</i>]</p>

<p class="drama">
Who are the votaries, my loving lords,<br>
That are vow-fellows with this virtuous Duke?
</p>

<p class="drama">
LORD.<br>
Lord Longaville is one.
</p>

<p class="drama">
PRINCESS.<br>
Know you the man?
</p>

<p class="drama">
MARIA.<br>
I know him, madam. At a marriage feast<br>
Between Lord Perigort and the beauteous heir<br>
Of Jaques Falconbridge, solemnized<br>
In Normandy, saw I this Longaville.<br>
A man of sovereign parts, he is esteemed,<br>
Well fitted in arts, glorious in arms.<br>
Nothing becomes him ill that he would well.<br>
The only soil of his fair virtue’s gloss,<br>
If virtue’s gloss will stain with any soil,<br>
Is a sharp wit matched with too blunt a will,<br>
Whose edge hath power to cut, whose will still wills<br>
It should none spare that come within his power.
</p>

<p class="drama">
PRINCESS.<br>
Some merry mocking lord, belike. Is’t so?
</p>

<p class="drama">
MARIA.<br>
They say so most that most his humours know.
</p>

<p class="drama">
PRINCESS.<br>
Such short-lived wits do wither as they grow.<br>
Who are the rest?
</p>

<p class="drama">
KATHARINE.<br>
The young Dumaine, a well-accomplished youth,<br>
Of all that virtue love for virtue loved;<br>
Most power to do most harm, least knowing ill,<br>
For he hath wit to make an ill shape good,<br>
And shape to win grace though he had no wit.<br>
I saw him at the Duke Alençon’s once;<br>
And much too little of that good I saw<br>
Is my report to his great worthiness.
</p>

<p class="drama">
ROSALINE.<br>
Another of these students at that time<br>
Was there with him, if I have heard a truth.<br>
Berowne they call him, but a merrier man,<br>
Within the limit of becoming mirth,<br>
I never spent an hour’s talk withal.<br>
His eye begets occasion for his wit,<br>
For every object that the one doth catch<br>
The other turns to a mirth-moving jest,<br>
Which his fair tongue, conceit’s expositor,<br>
Delivers in such apt and gracious words<br>
That aged ears play truant at his tales,<br>
And younger hearings are quite ravished,<br>
So sweet and voluble is his discourse.
</p>

<p class="drama">
PRINCESS.<br>
God bless my ladies! Are they all in love,<br>
That every one her own hath garnished<br>
With such bedecking ornaments of praise?
</p>

<p class="drama">
LORD.<br>
Here comes Boyet.
</p>

<p class="scenedesc">
Enter <span class="charname">Boyet</span>.
</p>

<p class="drama">
PRINCESS.<br>
Now, what admittance, lord?
</p>

<p class="drama">
BOYET.<br>
Navarre had notice of your fair approach,<br>
And he and his competitors in oath<br>
Were all addressed to meet you, gentle lady,<br>
Before I came. Marry, thus much I have learned:<br>
He rather means to lodge you in the field,<br>
Like one that comes here to besiege his court,<br>
Than seek a dispensation for his oath,<br>
To let you enter his unpeopled house.
</p>

<p class="scenedesc">
Enter <span class="charname">King of Navarre, Longaville, Dumaine, Berowne</span> and
Attendants.
</p>

<p class="drama">
Here comes Navarre.
</p>

<p class="drama">
KING.<br>
Fair Princess, welcome to the court of Navarre.
</p>

<p class="drama">
PRINCESS.<br>
“Fair” I give you back again, and “welcome” I have not yet. The roof of this
court is too high to be yours, and welcome to the wide fields too base to be
mine.
</p>

<p class="drama">
KING.<br>
You shall be welcome, madam, to my court.
</p>

<p class="drama">
PRINCESS.<br>
I will be welcome then. Conduct me thither.
</p>

<p class="drama">
KING.<br>
Hear me, dear lady. I have sworn an oath.
</p>

<p class="drama">
PRINCESS.<br>
Our Lady help my lord! He’ll be forsworn.
</p>

<p class="drama">
KING.<br>
Not for the world, fair madam, by my will.
</p>

<p class="drama">
PRINCESS.<br>
Why, will shall break it; will, and nothing else.
</p>

<p class="drama">
KING.<br>
Your ladyship is ignorant what it is.
</p>

<p class="drama">
PRINCESS.<br>
Were my lord so, his ignorance were wise,<br>
Where now his knowledge must prove ignorance.<br>
I hear your Grace hath sworn out housekeeping.<br>
’Tis deadly sin to keep that oath, my lord,<br>
And sin to break it.<br>
But pardon me, I am too sudden bold.<br>
To teach a teacher ill beseemeth me.<br>
Vouchsafe to read the purpose of my coming,<br>
And suddenly resolve me in my suit.
</p>

<p class="right">[<i>She gives him a paper.</i>]</p>

<p class="drama">
KING.<br>
Madam, I will, if suddenly I may.
</p>

<p class="drama">
PRINCESS.<br>
You will the sooner that I were away,<br>
For you’ll prove perjured if you make me stay.
</p>

<p class="right">[<i>The King reads the paper.</i>]</p>

<p class="drama">
BEROWNE.<br>
[<i>To Rosaline</i>.] Did not I dance with you in Brabant once?
</p>

<p class="drama">
ROSALINE.<br>
Did not I dance with you in Brabant once?
</p>

<p class="drama">
BEROWNE.<br>
I know you did.
</p>

<p class="drama">
ROSALINE.<br>
How needless was it then<br>
To ask the question!
</p>

<p class="drama">
BEROWNE.<br>
You must not be so quick.
</p>

<p class="drama">
ROSALINE.<br>
’Tis long of you that spur me with such questions.
</p>

<p class="drama">
BEROWNE.<br>
Your wit’s too hot, it speeds too fast, ’twill tire.
</p>

<p class="drama">
ROSALINE.<br>
Not till it leave the rider in the mire.
</p>

<p class="drama">
BEROWNE.<br>
What time o’ day?
</p>

<p class="drama">
ROSALINE.<br>
The hour that fools should ask.
</p>

<p class="drama">
BEROWNE.<br>
Now fair befall your mask.
</p>

<p class="drama">
ROSALINE.<br>
Fair fall the face it covers.
</p>

<p class="drama">
BEROWNE.<br>
And send you many lovers!
</p>

<p class="drama">
ROSALINE.<br>
Amen, so you be none.
</p>

<p class="drama">
BEROWNE.<br>
Nay, then will I be gone.
</p>

<p class="drama">
KING.<br>
Madam, your father here doth intimate<br>
The payment of a hundred thousand crowns,<br>
Being but the one half of an entire sum<br>
Disbursed by my father in his wars.<br>
But say that he or we, as neither have,<br>
Received that sum, yet there remains unpaid<br>
A hundred thousand more, in surety of the which<br>
One part of Aquitaine is bound to us,<br>
Although not valued to the money’s worth.<br>
If then the King your father will restore<br>
But that one half which is unsatisfied,<br>
We will give up our right in Aquitaine,<br>
And hold fair friendship with his majesty.<br>
But that, it seems, he little purposeth;<br>
For here he doth demand to have repaid<br>
A hundred thousand crowns, and not demands,<br>
On payment of a hundred thousand crowns,<br>
To have his title live in Aquitaine,<br>
Which we much rather had depart withal,<br>
And have the money by our father lent,<br>
Than Aquitaine, so gelded as it is.<br>
Dear Princess, were not his requests so far<br>
From reason’s yielding, your fair self should make<br>
A yielding ’gainst some reason in my breast,<br>
And go well satisfied to France again.
</p>

<p class="drama">
PRINCESS.<br>
You do the King my father too much wrong,<br>
And wrong the reputation of your name,<br>
In so unseeming to confess receipt<br>
Of that which hath so faithfully been paid.
</p>

<p class="drama">
KING.<br>
I do protest I never heard of it;<br>
And, if you prove it, I’ll repay it back<br>
Or yield up Aquitaine.
</p>

<p class="drama">
PRINCESS.<br>
We arrest your word.<br>
Boyet, you can produce acquittances<br>
For such a sum from special officers<br>
Of Charles his father.
</p>

<p class="drama">
KING.<br>
Satisfy me so.
</p>

<p class="drama">
BOYET.<br>
So please your Grace, the packet is not come<br>
Where that and other specialties are bound.<br>
Tomorrow you shall have a sight of them.
</p>

<p class="drama">
KING.<br>
It shall suffice me; at which interview<br>
All liberal reason I will yield unto.<br>
Meantime receive such welcome at my hand<br>
As honour, without breach of honour, may<br>
Make tender of to thy true worthiness.<br>
You may not come, fair Princess, in my gates,<br>
But here without you shall be so received<br>
As you shall deem yourself lodged in my heart,<br>
Though so denied fair harbour in my house.<br>
Your own good thoughts excuse me, and farewell.<br>
Tomorrow shall we visit you again.
</p>

<p class="drama">
PRINCESS.<br>
Sweet health and fair desires consort your Grace.
</p>

<p class="drama">
KING.<br>
Thy own wish wish I thee in every place.
</p>

<p class="right">
[<i>Exeunt the <span class="charname">King, Longaville</span> and
<span class="charname">Dumaine</span>.</i>]
</p>

<p class="drama">
BEROWNE.<br>
Lady, I will commend you to mine own heart.
</p>

<p class="drama">
ROSALINE.<br>
Pray you, do my commendations; I would be glad to see it.
</p>

<p class="drama">
BEROWNE.<br>
I would you heard it groan.
</p>

<p class="drama">
ROSALINE.<br>
Is the fool sick?
</p>

<p class="drama">
BEROWNE.<br>
Sick at the heart.
</p>

<p class="drama">
ROSALINE.<br>
Alack, let it blood.
</p>

<p class="drama">
BEROWNE.<br>
Would that do it good?
</p>

<p class="drama">
ROSALINE.<br>
My physic says “ay”.
</p>

<p class="drama">
BEROWNE.<br>
Will you prick’t with your eye?
</p>

<p class="drama">
ROSALINE.<br>
<i>Non point</i>, with my knife.
</p>

<p class="drama">
BEROWNE.<br>
Now, God save thy life.
</p>

<p class="drama">
ROSALINE.<br>
And yours from long living.
</p>

<p class="drama">
BEROWNE.<br>
I cannot stay thanksgiving.
</p>

<p class="right">[<i>He exits.</i>]</p>

<p class="scenedesc">
Enter <span class="charname">Dumaine</span>.
</p>

<p class="drama">
DUMAINE.<br>
Sir, I pray you, a word. What lady is that same?
</p>

<p class="drama">
BOYET.<br>
The heir of Alençon, Katharine her name.
</p>

<p class="drama">
DUMAINE.<br>
A gallant lady. Monsieur, fare you well.
</p>

<p class="right">[<i>He exits.</i>]</p>

<p class="scenedesc">
Enter <span class="charname">Longaville</span>.
</p>

<p class="drama">
LONGAVILLE.<br>
I beseech you a word. What is she in the white?
</p>

<p class="drama">
BOYET.<br>
A woman sometimes, an you saw her in the light.
</p>

<p class="drama">
LONGAVILLE.<br>
Perchance light in the light. I desire her name.
</p>

<p class="drama">
BOYET.<br>
She hath but one for herself; to desire that were a shame.
</p>

<p class="drama">
LONGAVILLE.<br>
Pray you, sir, whose daughter?
</p>

<p class="drama">
BOYET.<br>
Her mother’s, I have heard.
</p>

<p class="drama">
LONGAVILLE.<br>
God’s blessing on your beard!
</p>

<p class="drama">
BOYET.<br>
Good sir, be not offended.<br>
She is an heir of Falconbridge.
</p>

<p class="drama">
LONGAVILLE.<br>
Nay, my choler is ended.<br>
She is a most sweet lady.
</p>

<p class="drama">
BOYET.<br>
Not unlike, sir; that may be.
</p>

<p class="right">[<i>Exit <span class="charname">Longaville</span>.</i>]</p>

<p class="scenedesc">
Enter <span class="charname">Berowne</span>.
</p>

<p class="drama">
BEROWNE.<br>
What’s her name in the cap?
</p>

<p class="drama">
BOYET.<br>
Rosaline, by good hap.
</p>

<p class="drama">
BEROWNE.<br>
Is she wedded or no?
</p>

<p class="drama">
BOYET.<br>
To her will, sir, or so.
</p>

<p class="drama">
BEROWNE.<br>
You are welcome, sir. Adieu.
</p>

<p class="drama">
BOYET.<br>
Farewell to me, sir, and welcome to you.
</p>

<p class="right">[<i>Exit <span class="charname">Berowne</span>.</i>]</p>

<p class="drama">
MARIA.<br>
That last is Berowne, the merry madcap lord.<br>
Not a word with him but a jest.
</p>

<p class="drama">
BOYET.<br>
And every jest but a word.
</p>

<p class="drama">
PRINCESS.<br>
It was well done of you to take him at his word.
</p>

<p class="drama">
BOYET.<br>
I was as willing to grapple as he was to board.
</p>

<p class="drama">
KATHARINE.<br>
Two hot sheeps, marry!
</p>

<p class="drama">
BOYET.<br>
And wherefore not ships?<br>
No sheep, sweet lamb, unless we feed on your lips.
</p>

<p class="drama">
KATHARINE.<br>
You sheep and I pasture. Shall that finish the jest?
</p>

<p class="drama">
BOYET.<br>
So you grant pasture for me.
</p>

<p class="right">[<i>He tries to kiss her.</i>]</p>

<p class="drama">
KATHARINE.<br>
Not so, gentle beast.<br>
My lips are no common, though several they be.
</p>

<p class="drama">
BOYET.<br>
Belonging to whom?
</p>

<p class="drama">
KATHARINE.<br>
To my fortunes and me.
</p>

<p class="drama">
PRINCESS.<br>
Good wits will be jangling; but, gentles, agree.<br>
This civil war of wits were much better used<br>
On Navarre and his bookmen, for here ’tis abused.
</p>

<p class="drama">
BOYET.<br>
If my observation, which very seldom lies,<br>
By the heart’s still rhetoric disclosed with eyes,<br>
Deceive me not now, Navarre is infected.
</p>

<p class="drama">
PRINCESS.<br>
With what?
</p>

<p class="drama">
BOYET.<br>
With that which we lovers entitle “affected”.
</p>

<p class="drama">
PRINCESS.<br>
Your reason.
</p>

<p class="drama">
BOYET.<br>
Why, all his behaviours did make their retire<br>
To the court of his eye, peeping thorough desire.<br>
His heart, like an agate, with your print impressed,<br>
Proud with his form, in his eye pride expressed.<br>
His tongue, all impatient to speak and not see,<br>
Did stumble with haste in his eyesight to be;<br>
All senses to that sense did make their repair,<br>
To feel only looking on fairest of fair.<br>
Methought all his senses were locked in his eye,<br>
As jewels in crystal for some prince to buy;<br>
Who, tend’ring their own worth from where they were glassed,<br>
Did point you to buy them, along as you passed.<br>
His face’s own margent did quote such amazes<br>
That all eyes saw his eyes enchanted with gazes.<br>
I’ll give you Aquitaine, and all that is his,<br>
An you give him for my sake but one loving kiss.
</p>

<p class="drama">
PRINCESS.<br>
Come, to our pavilion. Boyet is disposed.
</p>

<p class="drama">
BOYET.<br>
But to speak that in words which his eye hath disclosed.<br>
I only have made a mouth of his eye<br>
By adding a tongue which I know will not lie.
</p>

<p class="drama">
ROSALINE.<br>
Thou art an old love-monger, and speakest skilfully.
</p>

<p class="drama">
MARIA.<br>
He is Cupid’s grandfather, and learns news of him.
</p>

<p class="drama">
ROSALINE.<br>
Then was Venus like her mother; for her father is but grim.
</p>

<p class="drama">
BOYET.<br>
Do you hear, my mad wenches?
</p>

<p class="drama">
MARIA.<br>
No.
</p>

<p class="drama">
BOYET.<br>
What, then, do you see?
</p>

<p class="drama">
ROSALINE.<br>
Ay, our way to be gone.
</p>

<p class="drama">
BOYET.<br>
You are too hard for me.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

