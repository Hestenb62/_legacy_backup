<h2> <b>ACT V</b></h2>

<h3> <a id="sceneV_9.1"></a><b>SCENE I. The King’s Camp near Shrewsbury.</b></h3>

<p class="scenedesc">Enter <span class="charname">King Henry, Prince Henry, Lancaster, Sir Walter Blunt</span> and
<span class="charname">Sir John Falstaff</span>.
</p>

<p class="drama">
KING.<br>
How bloodily the sun begins to peer<br>
Above yon bulky hill! The day looks pale<br>
At his distemp’rature.
</p>

<p class="drama">
PRINCE.<br>
The southern wind<br>
Doth play the trumpet to his purposes,<br>
And by his hollow whistling in the leaves<br>
Foretells a tempest and a blust’ring day.
</p>

<p class="drama">
KING.<br>
Then with the losers let it sympathize,<br>
For nothing can seem foul to those that win.
</p>

<p class="right">[<i>The trumpet sounds</i>.]
</p>

<p class="scenedesc">Enter <span class="charname">Worcester</span> and
<span class="charname">Vernon</span>.
</p>

<p class="drama">
How, now, my Lord of Worcester! ’Tis not well<br>
That you and I should meet upon such terms<br>
As now we meet. You have deceived our trust,<br>
And made us doff our easy robes of peace,<br>
To crush our old limbs in ungentle steel.<br>
This is not well, my lord, this is not well.<br>
What say you to it? Will you again unknit<br>
This churlish knot of all-abhorred war,<br>
And move in that obedient orb again<br>
Where you did give a fair and natural light,<br>
And be no more an exhaled meteor,<br>
A prodigy of fear, and a portent<br>
Of broached mischief to the unborn times?
</p>

<p class="drama">
WORCESTER.<br>
Hear me, my liege:<br>
For mine own part, I could be well content<br>
To entertain the lag end of my life<br>
With quiet hours. For I do protest<br>
I have not sought the day of this dislike.
</p>

<p class="drama">
KING.<br>
You have not sought it? How comes it, then?
</p>

<p class="drama">
FALSTAFF.<br>
Rebellion lay in his way, and he found it.
</p>

<p class="drama">
PRINCE.<br>
Peace, chewet, peace!
</p>

<p class="drama">
WORCESTER.<br>
It pleased your Majesty to turn your looks<br>
Of favour from myself and all our house;<br>
And yet I must remember you, my lord,<br>
We were the first and dearest of your friends.<br>
For you my staff of office did I break<br>
In Richard’s time, and posted day and night<br>
To meet you on the way, and kiss your hand,<br>
When yet you were in place and in account<br>
Nothing so strong and fortunate as I.<br>
It was myself, my brother, and his son,<br>
That brought you home, and boldly did outdare<br>
The dangers of the time. You swore to us,<br>
And you did swear that oath at Doncaster,<br>
That you did nothing purpose ’gainst the state,<br>
Nor claim no further than your new-fall’n right,<br>
The seat of Gaunt, dukedom of Lancaster.<br>
To this we swore our aid. But in short space<br>
It rain’d down fortune show’ring on your head,<br>
And such a flood of greatness fell on you,<br>
What with our help, what with the absent King,<br>
What with the injuries of a wanton time,<br>
The seeming sufferances that you had borne,<br>
And the contrarious winds that held the King<br>
So long in his unlucky Irish wars<br>
That all in England did repute him dead:<br>
And from this swarm of fair advantages<br>
You took occasion to be quickly woo’d<br>
To gripe the general sway into your hand,<br>
Forgot your oath to us at Doncaster;<br>
And, being fed by us, you used us so<br>
As that ungentle gull, the cuckoo’s bird,<br>
Useth the sparrow—did oppress our nest,<br>
Grew by our feeding to so great a bulk<br>
That even our love durst not come near your sight<br>
For fear of swallowing; but with nimble wing<br>
We were enforced, for safety sake to fly<br>
Out of your sight, and raise this present head,<br>
Whereby we stand opposed by such means<br>
As you yourself have forged against yourself,<br>
By unkind usage, dangerous countenance,<br>
And violation of all faith and troth<br>
Sworn to us in your younger enterprise.
</p>

<p class="drama">
KING.<br>
These things, indeed, you have articulate,<br>
Proclaim’d at market crosses, read in churches,<br>
To face the garment of rebellion<br>
With some fine colour that may please the eye<br>
Of fickle changelings and poor discontents,<br>
Which gape and rub the elbow at the news<br>
Of hurlyburly innovation.<br>
And never yet did insurrection want<br>
Such water-colours to impaint his cause,<br>
Nor moody beggars starving for a time<br>
Of pellmell havoc and confusion.
</p>

<p class="drama">
PRINCE.<br>
In both your armies there is many a soul<br>
Shall pay full dearly for this encounter<br>
If once they join in trial. Tell your nephew,<br>
The Prince of Wales doth join with all the world<br>
In praise of Henry Percy. By my hopes,<br>
This present enterprise set off his head,<br>
I do not think a braver gentleman,<br>
More active-valiant or more valiant-young,<br>
More daring or more bold, is now alive<br>
To grace this latter age with noble deeds.<br>
For my part, I may speak it to my shame,<br>
I have a truant been to chivalry,<br>
And so I hear he doth account me too.<br>
Yet this before my father’s Majesty—<br>
I am content that he shall take the odds<br>
Of his great name and estimation,<br>
And will, to save the blood on either side,<br>
Try fortune with him in a single fight.
</p>

<p class="drama">
KING.<br>
And, Prince of Wales, so dare we venture thee,<br>
Albeit considerations infinite<br>
Do make against it.—No, good Worcester, no.<br>
We love our people well, even those we love<br>
That are misled upon your cousin’s part,<br>
And, will they take the offer of our grace,<br>
Both he, and they, and you, yea, every man<br>
Shall be my friend again, and I’ll be his.<br>
So tell your cousin, and then bring me word<br>
What he will do. But if he will not yield,<br>
Rebuke and dread correction wait on us,<br>
And they shall do their office. So, be gone;<br>
We will not now be troubled with reply.<br>
We offer fair, take it advisedly.
</p>

<p class="right">[<i>Exit <span class="charname">Worcester</span> with <span class="charname">Vernon</span>.</i>]
</p>

<p class="drama">
PRINCE.<br>
It will not be accepted, on my life.<br>
The Douglas and the Hotspur both together<br>
Are confident against the world in arms.
</p>

<p class="drama">
KING.<br>
Hence, therefore, every leader to his charge;<br>
For on their answer, will we set on them,<br>
And God befriend us as our cause is just!
</p>

<p class="right">[<i>Exeunt the <span class="charname">King, Blunt</span> and
<span class="charname">Prince John</span>.</i>]
</p>

<p class="drama">
FALSTAFF.<br>
Hal, if thou see me down in the battle and bestride me, so; ’tis a point
of friendship.
</p>

<p class="drama">
PRINCE.<br>
Nothing but a colossus can do thee that friendship.<br>
Say thy prayers, and farewell.
</p>

<p class="drama">
FALSTAFF.<br>
I would ’twere bedtime, Hal, and all well.
</p>

<p class="drama">
PRINCE.<br>
Why, thou owest God a death.
</p>

<p class="right">[<i>Exit.</i>]
</p>

<p class="drama">
FALSTAFF.<br>
’Tis not due yet, I would be loth to pay Him before His day. What need I
be so forward with Him that calls not on me? Well, ’tis no matter, honour
pricks me on. Yea, but how if honour prick me off when I come on? How then? Can
honor set to a leg? No. Or an arm? No. Or take away the grief of a wound? No.
Honour hath no skill in surgery then? No. What is honour? A word. What is in
that word, “honour”? What is that “honour”? Air. A trim
reckoning! Who hath it? He that died o’ Wednesday. Doth he feel it? No.
Doth be hear it? No. ’Tis insensible, then? Yea, to the dead. But will it
not live with the living? No. Why? Detraction will not suffer it. Therefore
I’ll none of it. Honour is a mere scutcheon. And so ends my catechism.
</p>

<p class="right">[<i>Exit.</i>]
</p>

<h3> <a id="sceneV_9.2"></a><b>SCENE II. The Rebel Camp.</b></h3>

<p class="scenedesc">Enter <span class="charname">Worcester</span> and
<span class="charname">Vernon</span>.
</p>

<p class="drama">
WORCESTER.<br>
O no, my nephew must not know, Sir Richard,<br>
The liberal and kind offer of the King.
</p>

<p class="drama">
VERNON.<br>
’Twere best he did.
</p>

<p class="drama">
WORCESTER.<br>
Then are we all undone.<br>
It is not possible, it cannot be,<br>
The King should keep his word in loving us;<br>
He will suspect us still, and find a time<br>
To punish this offence in other faults.<br>
Suspicion all our lives shall be stuck full of eyes,<br>
For treason is but trusted like the fox,<br>
Who, ne’er so tame, so cherish’d and lock’d up,<br>
Will have a wild trick of his ancestors.<br>
Look how we can, or sad or merrily,<br>
Interpretation will misquote our looks,<br>
And we shall feed like oxen at a stall,<br>
The better cherish’d still the nearer death.<br>
My nephew’s trespass may be well forgot,<br>
It hath the excuse of youth and heat of blood,<br>
And an adopted name of privilege—<br>
A hare-brain’d Hotspur, govern’d by a spleen.<br>
All his offences live upon my head<br>
And on his father’s. We did train him on,<br>
And, his corruption being ta’en from us,<br>
We as the spring of all shall pay for all.<br>
Therefore, good cousin, let not Harry know<br>
In any case the offer of the King.
</p>

<p class="drama">
VERNON.<br>
Deliver what you will, I’ll say ’tis so.<br>
Here comes your cousin.
</p>

<p class="scenedesc">Enter <span class="charname">Hotspur</span> and
<span class="charname">Douglas;</span> Officers and Soldiers behind.
</p>

<p class="drama">
HOTSPUR.<br>
My uncle is return’d.<br>
Deliver up my Lord of Westmoreland.<br>
Uncle, what news?
</p>

<p class="drama">
WORCESTER.<br>
The King will bid you battle presently.
</p>

<p class="drama">
DOUGLAS.<br>
Defy him by the Lord Of Westmoreland.
</p>

<p class="drama">
HOTSPUR.<br>
Lord Douglas, go you and tell him so.
</p>

<p class="drama">
DOUGLAS.<br>
Marry, I shall, and very willingly.
</p>

<p class="right">[<i>Exit.</i>]
</p>

<p class="drama">
WORCESTER.<br>
There is no seeming mercy in the King.
</p>

<p class="drama">
HOTSPUR.<br>
Did you beg any? God forbid!
</p>

<p class="drama">
WORCESTER.<br>
I told him gently of our grievances,<br>
Of his oath-breaking; which he mended thus,<br>
By now forswearing that he is forsworn.<br>
He calls us rebels, traitors, and will scourge<br>
With haughty arms this hateful name in us.
</p>

<p class="scenedesc">Enter <span class="charname">Douglas</span>.
</p>

<p class="drama">
DOUGLAS.<br>
Arm, gentlemen; to arms! For I have thrown<br>
A brave defiance in King Henry’s teeth,<br>
And Westmoreland, that was engaged, did bear it,<br>
Which cannot choose but bring him quickly on.
</p>

<p class="drama">
WORCESTER.<br>
The Prince of Wales stepp’d forth before the King,<br>
And, nephew, challenged you to single fight.
</p>

<p class="drama">
HOTSPUR.<br>
O, would the quarrel lay upon our heads,<br>
And that no man might draw short breath today<br>
But I and Harry Monmouth! Tell me, tell me,<br>
How show’d his tasking? Seem’d it in contempt?
</p>

<p class="drama">
VERNON.<br>
No, by my soul. I never in my life<br>
Did hear a challenge urged more modestly,<br>
Unless a brother should a brother dare<br>
To gentle exercise and proof of arms.<br>
He gave you all the duties of a man,<br>
Trimm’d up your praises with a princely tongue,<br>
Spoke your deservings like a chronicle,<br>
Making you ever better than his praise<br>
By still dispraising praise valued with you,<br>
And, which became him like a prince indeed,<br>
He made a blushing cital of himself,<br>
And chid his truant youth with such a grace<br>
As if he master’d there a double spirit<br>
Of teaching and of learning instantly.<br>
There did he pause: but let me tell the world,<br>
If he outlive the envy of this day,<br>
England did never owe so sweet a hope<br>
So much misconstrued in his wantonness.
</p>

<p class="drama">
HOTSPUR.<br>
Cousin, I think thou art enamoured<br>
Upon his follies. Never did I hear<br>
Of any prince so wild a liberty.<br>
But be he as he will, yet once ere night<br>
I will embrace him with a soldier’s arm,<br>
That he shall shrink under my courtesy.<br>
Arm, arm with speed! And, fellows, soldiers, friends,<br>
Better consider what you have to do<br>
Than I that have not well the gift of tongue<br>
Can lift your blood up with persuasion.
</p>

<p class="scenedesc">Enter a <span class="charname">Messenger</span>.
</p>

<p class="drama">
MESSENGER.<br>
My lord, here are letters for you.
</p>

<p class="drama">
HOTSPUR.<br>
I cannot read them now.—<br>
O gentlemen, the time of life is short!<br>
To spend that shortness basely were too long<br>
If life did ride upon a dial’s point,<br>
Still ending at the arrival of an hour.<br>
And if we live, we live to tread on kings;<br>
If die, brave death, when princes die with us!<br>
Now, for our consciences, the arms are fair<br>
When the intent of bearing them is just.
</p>

<p class="scenedesc">Enter another <span class="charname">Messenger</span>.
</p>

<p class="drama">
MESSENGER.<br>
My lord, prepare. The King comes on apace.
</p>

<p class="drama">
HOTSPUR.<br>
I thank him that he cuts me from my tale,<br>
For I profess not talking. Only this:<br>
Let each man do his best. And here draw I<br>
A sword whose temper I intend to stain<br>
With the best blood that I can meet withal<br>
In the adventure of this perilous day.<br>
Now, Esperance! Percy! And set on.<br>
Sound all the lofty instruments of war,<br>
And by that music let us all embrace,<br>
For, Heaven to Earth, some of us never shall<br>
A second time do such a courtesy.
</p>

<p class="right">[<i>The trumpets sound. They embrace, and exeunt.</i>]
</p>

<h3> <a id="sceneV_9.3"></a><b>SCENE III. Plain between the Camps.</b></h3>

<p class="scenedesc">The <span class="charname">King</span> enters with his
power. Alarum to the battle.<br> Then enter <span class="charname">Douglas</span> and <span class="charname">Sir Walter
Blunt</span>.
</p>

<p class="drama">
BLUNT.<br>
What is thy name that in the battle thus<br>
Thou crossest me? What honour dost thou seek<br>
Upon my head?
</p>

<p class="drama">
DOUGLAS.<br>
Know then my name is Douglas,<br>
And I do haunt thee in the battle thus<br>
Because some tell me that thou art a king.
</p>

<p class="drama">
BLUNT.<br>
They tell thee true.
</p>

<p class="drama">
DOUGLAS.<br>
The Lord of Stafford dear today hath bought<br>
Thy likeness, for instead of thee, King Harry,<br>
This sword hath ended him. So shall it thee,<br>
Unless thou yield thee as my prisoner.
</p>

<p class="drama">
BLUNT.<br>
I was not born a yielder, thou proud Scot,<br>
And thou shalt find a king that will revenge<br>
Lord Stafford’s death.
</p>

<p class="right">[<i>They fight, and <span class="charname">Blunt</span> is
slain.</i>]
</p>

<p class="scenedesc">Enter <span class="charname">Hotspur</span>.
</p>

<p class="drama">
HOTSPUR.<br>
O Douglas, hadst thou fought at Holmedon thus,<br>
I never had triumphed upon a Scot.
</p>

<p class="drama">
DOUGLAS.<br>
All’s done, all’s won; here breathless lies the King.
</p>

<p class="drama">
HOTSPUR.<br>
Where?
</p>

<p class="drama">
DOUGLAS.<br>
Here.
</p>

<p class="drama">
HOTSPUR.<br>
This, Douglas? No, I know this face full well.<br>
A gallant knight he was, his name was Blunt,<br>
Semblably furnish’d like the King himself.
</p>

<p class="drama">
DOUGLAS.<br>
A fool go with thy soul, whither it goes!<br>
A borrow’d title hast thou bought too dear.<br>
Why didst thou tell me that thou wert a king?
</p>

<p class="drama">
HOTSPUR.<br>
The King hath many marching in his coats.
</p>

<p class="drama">
DOUGLAS.<br>
Now, by my sword, I will kill all his coats;<br>
I’ll murder all his wardrobe, piece by piece,<br>
Until I meet the King.
</p>

<p class="drama">
HOTSPUR.<br>
Up, and away!<br>
Our soldiers stand full fairly for the day.
</p>

<p class="right">[<i>Exeunt.</i>]
</p>

<p class="scenedesc">Alarums. Enter <span class="charname">Falstaff</span> solus.
</p>

<p class="drama">
FALSTAFF.<br>
Though I could scape shot-free at London, I fear the shot here.
Here’s no scoring but upon the pate.—Soft! who are you? Sir Walter
Blunt. There’s honour for you. Here’s no vanity. I am as hot as
molten lead, and as heavy too. God keep lead out of me, I need no more weight
than mine own bowels. I have led my ragamuffins where they are peppered.
There’s not three of my hundred and fifty left alive, and they are for
the town’s end, to beg during life. But who comes here?
</p>

<p class="scenedesc">Enter <span class="charname">Prince Henry</span>.
</p>

<p class="drama">
PRINCE.<br>
What, stand’st thou idle here? Lend me thy sword.<br>
Many a nobleman lies stark and stiff<br>
Under the hoofs of vaunting enemies,<br>
Whose deaths are yet unrevenged. I prithee<br>
Lend me thy sword.
</p>

<p class="drama">
FALSTAFF.<br>
O Hal, I prithee give me leave to breathe awhile. Turk Gregory never did such
deeds in arms as I have done this day. I have paid Percy, I have made him sure.
</p>

<p class="drama">
PRINCE.<br>
He is indeed, and living to kill thee.<br>
I prithee, lend me thy sword.
</p>

<p class="drama">
FALSTAFF.<br>
Nay, before God, Hal, if Percy be alive, thou gett’st not my sword; but
take my pistol, if thou wilt.
</p>

<p class="drama">
PRINCE.<br>
Give it me. What, is it in the case?
</p>

<p class="drama">
FALSTAFF.<br>
Ay, Hal, ’tis hot, ’tis hot. There’s that will sack a city.
</p>

<p class="right">[<i>The <span class="charname">Prince</span> draws out a
bottle of sack.</i>]
</p>

<p class="drama">
PRINCE.<br>
What, is it a time to jest and dally now?
</p>

<p class="right">[<i>Throws it at him, and exit.</i>]
</p>

<p class="drama">
FALSTAFF.<br>
Well, if Percy be alive, I’ll pierce him. If he do come in my way, so; if
he do not, if I come in his willingly, let him make a carbonado of me. I like
not such grinning honour as Sir Walter hath. Give me life, which if I can save,
so: if not, honour comes unlooked for, and there’s an end.
</p>

<p class="right">[<i>Exit.</i>]
</p>

<h3> <a id="sceneV_9.4"></a><b>SCENE IV. Another Part of the Field.</b></h3>

<p class="scenedesc">Alarums. Excursions. Enter <span class="charname">King
Henry, Prince Henry, Lancaster</span> and <span class="charname">Westmoreland</span>.
</p>

<p class="drama">
KING.<br>
I prithee, Harry, withdraw thyself, thou bleedest too much.<br>
Lord John of Lancaster, go you with him.
</p>

<p class="drama">
LANCASTER.<br>
Not I, my lord, unless I did bleed too.
</p>

<p class="drama">
PRINCE.<br>
I do beseech your Majesty, make up,<br>
Lest your retirement do amaze your friends.
</p>

<p class="drama">
KING.<br>
I will do so. My Lord of Westmoreland,<br>
Lead him to his tent.
</p>

<p class="drama">
WESTMORELAND.<br>
Come, my lord, I’ll lead you to your tent.
</p>

<p class="drama">
PRINCE.<br>
Lead me, my lord? I do not need your help,<br>
And God forbid a shallow scratch should drive<br>
The Prince of Wales from such a field as this,<br>
Where stain’d nobility lies trodden on,<br>
And rebels’ arms triumph in massacres!
</p>

<p class="drama">
LANCASTER.<br>
We breathe too long. Come, cousin Westmoreland,<br>
Our duty this way lies. For God’s sake, come.
</p>

<p class="right">[<i>Exeunt <span class="charname">Lancaster</span> and
<span class="charname">Westmoreland</span>.</i>]
</p>

<p class="drama">
PRINCE.<br>
By Heaven, thou hast deceived me, Lancaster,<br>
I did not think thee lord of such a spirit.<br>
Before, I loved thee as a brother, John,<br>
But now I do respect thee as my soul.
</p>

<p class="drama">
KING.<br>
I saw him hold Lord Percy at the point<br>
With lustier maintenance than I did look for<br>
Of such an ungrown warrior.
</p>

<p class="drama">
PRINCE.<br>
O, this boy<br>
Lends mettle to us all!
</p>

<p class="right">[<i>Exit.</i>]
</p>

<p class="scenedesc">Enter <span class="charname">Douglas</span>.
</p>

<p class="drama">
DOUGLAS.<br>
Another king! They grow like Hydra’s heads.<br>
I am the Douglas, fatal to all those<br>
That wear those colours on them. What art thou<br>
That counterfeit’st the person of a king?
</p>

<p class="drama">
KING.<br>
The King himself, who, Douglas, grieves at heart<br>
So many of his shadows thou hast met,<br>
And not the very King. I have two boys<br>
Seek Percy and thyself about the field,<br>
But, seeing thou fall’st on me so luckily,<br>
I will assay thee, and defend thyself.
</p>

<p class="drama">
DOUGLAS.<br>
I fear thou art another counterfeit,<br>
And yet, in faith, thou bearest thee like a king.<br>
But mine I am sure thou art, whoe’er thou be,<br>
And thus I win thee.
</p>

<p class="scenedesc">They fight; the <span class="charname">King</span> being
in danger, enter <span class="charname">Prince Henry</span>.
</p>

<p class="drama">
PRINCE.<br>
Hold up thy head, vile Scot, or thou art like<br>
Never to hold it up again! The spirits<br>
Of valiant Shirley, Stafford, Blunt are in my arms.<br>
It is the Prince of Wales that threatens thee,<br>
Who never promiseth but he means to pay.
</p>

<p class="right">[<i>They fight. <span class="charname">Douglas</span> flies.</i>]
</p>

<p class="drama">
Cheerly, my lord. How fares your Grace?<br>
Sir Nicholas Gawsey hath for succour sent,<br>
And so hath Clifton. I’ll to Clifton straight.
</p>

<p class="drama">
KING.<br>
Stay and breathe awhile.<br>
Thou hast redeem’d thy lost opinion,<br>
And show’d thou mak’st some tender of my life,<br>
In this fair rescue thou hast brought to me.
</p>

<p class="drama">
PRINCE.<br>
O God, they did me too much injury<br>
That ever said I hearken’d for your death.<br>
If it were so, I might have let alone<br>
The insulting hand of Douglas over you,<br>
Which would have been as speedy in your end<br>
As all the poisonous potions in the world,<br>
And saved the treacherous labour of your son.
</p>

<p class="drama">
KING.<br>
Make up to Clifton. I’ll to Sir Nicholas Gawsey.
</p>

<p class="right">[<i>Exit.</i>]
</p>

<p class="scenedesc">Enter <span class="charname">Hotspur</span>.
</p>

<p class="drama">
HOTSPUR.<br>
If I mistake not, thou art Harry Monmouth.
</p>

<p class="drama">
PRINCE.<br>
Thou speak’st as if I would deny my name.
</p>

<p class="drama">
HOTSPUR.<br>
My name is Harry Percy.
</p>

<p class="drama">
PRINCE.<br>
Why then I see<br>
A very valiant rebel of the name.<br>
I am the Prince of Wales; and think not, Percy,<br>
To share with me in glory any more.<br>
Two stars keep not their motion in one sphere,<br>
Nor can one England brook a double reign,<br>
Of Harry Percy and the Prince of Wales.
</p>

<p class="drama">
HOTSPUR.<br>
Nor shall it, Harry, for the hour is come<br>
To end the one of us, and would to God<br>
Thy name in arms were now as great as mine!
</p>

<p class="drama">
PRINCE.<br>
I’ll make it greater ere I part from thee,<br>
And all the budding honours on thy crest<br>
I’ll crop to make a garland for my head.
</p>

<p class="drama">
HOTSPUR.<br>
I can no longer brook thy vanities.
</p>

<p class="right">[<i>They fight.</i>]
</p>

<p class="scenedesc">Enter <span class="charname">Falstaff</span>.
</p>

<p class="drama">
FALSTAFF.<br>
Well said, Hal! To it, Hal! Nay, you shall find no boy’s play here, I can
tell you.
</p>

<p class="scenedesc">Enter <span class="charname">Douglas.</span> He fights with
<span class="charname">Falstaff,</span> who falls down as if he were dead, and exit
<span class="charname">Douglas.</span> The <span class="charname">Prince</span>
kills <span class="charname">Hotspur</span>.
</p>

<p class="drama">
HOTSPUR.<br>
O Harry, thou hast robb’d me of my youth!<br>
I better brook the loss of brittle life<br>
Than those proud titles thou hast won of me;<br>
They wound my thoughts worse than thy sword my flesh.<br>
But thoughts, the slaves of life, and life, time’s fool,<br>
And time, that takes survey of all the world,<br>
Must have a stop. O, I could prophesy,<br>
But that the earthy and cold hand of death<br>
Lies on my tongue. No, Percy, thou art dust,<br>
And food for—
</p>

<p class="right">[<i>Dies.</i>]
</p>

<p class="drama">
PRINCE.<br>
For worms, brave Percy. Fare thee well, great heart!<br>
Ill-weaved ambition, how much art thou shrunk!<br>
When that this body did contain a spirit,<br>
A kingdom for it was too small a bound;<br>
But now two paces of the vilest earth<br>
Is room enough. This earth that bears thee dead<br>
Bears not alive so stout a gentleman.<br>
If thou wert sensible of courtesy,<br>
I should not make so dear a show of zeal.<br>
But let my favours hide thy mangled face;<br>
And even in thy behalf I’ll thank myself<br>
For doing these fair rites of tenderness.<br>
Adieu, and take thy praise with thee to heaven!<br>
Thy ignominy sleep with thee in the grave,<br>
But not remember’d in thy epitaph!
</p>

<p class="right">[<i>Sees <span class="charname">Falstaff</span> on the ground.</i>]
</p>

<p class="drama">
What, old acquaintance, could not all this flesh<br>
Keep in a little life? Poor Jack, farewell!<br>
I could have better spared a better man.<br>
O, I should have a heavy miss of thee<br>
If I were much in love with vanity.<br>
Death hath not struck so fat a deer today,<br>
Though many dearer, in this bloody fray.<br>
Embowell’d will I see thee by and by,<br>
Till then in blood by noble Percy lie.
</p>

<p class="right">[<i>Exit.</i>]
</p>

<p class="scenedesc"><span class="charname">Falstaff</span> rises up.
</p>

<p class="drama">
FALSTAFF.<br>
Embowell’d! If thou embowel me today, I’ll give you leave to powder
me and eat me too tomorrow. ’Sblood, ’twas time to counterfeit, or
that hot termagant Scot had paid me scot and lot too. Counterfeit? I lie, I am
no counterfeit. To die, is to be a counterfeit, for he is but the counterfeit
of a man who hath not the life of a man: but to counterfeit dying, when a man
thereby liveth, is to be no counterfeit, but the true and perfect image of life
indeed. The better part of valour is discretion, in the which better part I
have saved my life. Zounds, I am afraid of this gunpowder Percy, though
he be dead. How if he should counterfeit too, and rise? By my faith, I am
afraid he would prove the better counterfeit. Therefore I’ll make him
sure, yea, and I’ll swear I killed him. Why may not he rise as well
as I? Nothing confutes me but eyes, and nobody sees me. Therefore, sirrah, with
a new wound in your thigh, come you along with me.
</p>

<p class="right">[<i>Takes <span class="charname">Hotspur</span> on his back.</i>]
</p>

<p class="scenedesc">Enter <span class="charname">Prince Henry</span> and
<span class="charname">Lancaster</span>.
</p>

<p class="drama">
PRINCE.<br>
Come, brother John, full bravely hast thou flesh’d<br>
Thy maiden sword.
</p>

<p class="drama">
LANCASTER.<br>
But soft, whom have we here?<br>
Did you not tell me this fat man was dead?
</p>

<p class="drama">
PRINCE.<br>
I did; I saw him dead,<br>
Breathless and bleeding on the ground.—Art thou alive?<br>
Or is it fantasy that plays upon our eyesight?<br>
I prithee, speak, we will not trust our eyes<br>
Without our ears. Thou art not what thou seem’st.
</p>

<p class="drama">
FALSTAFF.<br>
No, that’s certain, I am not a double man. But if I be not Jack Falstaff,
then am I a Jack. There is Percy! [<i>Throwing the body down.</i>] If your
father will do me any honour, so; if not, let him kill the next Percy himself.
I look to be either earl or duke, I can assure you.
</p>

<p class="drama">
PRINCE.<br>
Why, Percy I kill’d myself, and saw thee dead.
</p>

<p class="drama">
FALSTAFF.<br>
Didst thou? Lord, Lord, how this world is given to lying! I grant you I was
down and out of breath, and so was he, but we rose both at an instant, and
fought a long hour by Shrewsbury clock. If I may be believed, so; if not, let
them that should reward valour bear the sin upon their own heads. I’ll
take it upon my death, I gave him this wound in the thigh. If the man were
alive, and would deny it, zounds, I would make him eat a piece of my sword.
</p>

<p class="drama">
LANCASTER.<br>
This is the strangest tale that ever I heard.
</p>

<p class="drama">
PRINCE.<br>
This is the strangest fellow, brother John.—<br>
Come, bring your luggage nobly on your back.<br>
For my part, if a lie may do thee grace,<br>
I’ll gild it with the happiest terms I have.
</p>

<p class="right">[<i>A retreat is sounded.</i>]
</p>

<p class="drama">
The trumpet sounds retreat; the day is ours.<br>
Come, brother, let us to the highest of the field,<br>
To see what friends are living, who are dead.
</p>

<p class="right">[<i>Exeunt <span class="charname">Prince Henry</span> and
<span class="charname">Lancaster</span>.</i>]
</p>

<p class="drama">
FALSTAFF.<br>
I’ll follow, as they say, for reward. He that rewards me, God reward him!
If I do grow great, I’ll grow less, for I’ll purge, and leave sack,
and live cleanly as a nobleman should do.
</p>

<p class="right">[<i>Exit, bearing off the body.</i>]
</p>

<h3> <a id="sceneV_9.5"></a><b>SCENE V. Another Part of the Field.</b></h3>

<p class="scenedesc">The trumpets sound. Enter <span class="charname">King
Henry, Prince Henry, Lancaster, Westmoreland</span> and others, with
<span class="charname">Worcester</span> and <span class="charname">Vernon</span>
prisoners.
</p>

<p class="drama">
KING.<br>
Thus ever did rebellion find rebuke.<br>
Ill-spirited Worcester, did not we send grace,<br>
Pardon, and terms of love to all of you?<br>
And wouldst thou turn our offers contrary?<br>
Misuse the tenour of thy kinsman’s trust?<br>
Three knights upon our party slain today,<br>
A noble earl, and many a creature else,<br>
Had been alive this hour,<br>
If, like a Christian, thou hadst truly borne<br>
Betwixt our armies true intelligence.
</p>

<p class="drama">
WORCESTER.<br>
What I have done my safety urged me to;<br>
And I embrace this fortune patiently,<br>
Since not to be avoided it falls on me.
</p>

<p class="drama">
KING.<br>
Bear Worcester to the death, and Vernon too.<br>
Other offenders we will pause upon.
</p>

<p class="right">[<i>Exeunt <span class="charname">Worcester</span> and
<span class="charname">Vernon,</span> guarded.</i>]
</p>

<p class="drama">
How goes the field?
</p>

<p class="drama">
PRINCE.<br>
The noble Scot, Lord Douglas, when he saw<br>
The fortune of the day quite turn’d from him,<br>
The noble Percy slain, and all his men<br>
Upon the foot of fear, fled with the rest,<br>
And, falling from a hill, he was so bruised<br>
That the pursuers took him. At my tent<br>
The Douglas is, and I beseech your Grace<br>
I may dispose of him.
</p>

<p class="drama">
KING.<br>
With all my heart.
</p>

<p class="drama">
PRINCE.<br>
Then, brother John of Lancaster, to you<br>
This honourable bounty shall belong.<br>
Go to the Douglas and deliver him<br>
Up to his pleasure, ransomless and free.<br>
His valours shown upon our crests today<br>
Hath taught us how to cherish such high deeds,<br>
Even in the bosom of our adversaries.
</p>

<p class="drama">
LANCASTER.<br>
I thank your Grace for this high courtesy,<br>
Which I shall give away immediately.
</p>

<p class="drama">
KING.<br>
Then this remains, that we divide our power.<br>
You, son John, and my cousin Westmoreland,<br>
Towards York shall bend you with your dearest speed<br>
To meet Northumberland and the prelate Scroop,<br>
Who, as we hear, are busily in arms.<br>
Myself and you, son Harry, will towards Wales,<br>
To fight with Glendower and the Earl of March.<br>
Rebellion in this land shall lose his sway,<br>
Meeting the check of such another day,<br>
And since this business so fair is done,<br>
Let us not leave till all our own be won.
</p>

<p class="right">[<i>Exeunt.</i>]
</p>

