<h2> <a id="sceneI_33.1"></a><b>ACT I</b></h2>

<h3> <b>SCENE I. Athens. A hall in Timon’s house</b></h3>

<p class="scenedesc">
Enter <span class="charname">Poet, Painter, Jeweller</span> and
<span class="charname">Merchant</span> at several doors.
</p>

<p class="drama">
POET.<br>
Good day, sir.
</p>

<p class="drama">
PAINTER.<br>
I am glad you’re well.
</p>

<p class="drama">
POET.<br>
I have not seen you long. How goes the world?
</p>

<p class="drama">
PAINTER.<br>
It wears, sir, as it grows.
</p>

<p class="drama">
POET.<br>
Ay, that’s well known.<br>
But what particular rarity? What strange,<br>
Which manifold record not matches? See,<br>
Magic of bounty, all these spirits thy power<br>
Hath conjured to attend! I know the merchant.
</p>

<p class="drama">
PAINTER.<br>
I know them both. Th’ other’s a jeweller.
</p>

<p class="drama">
MERCHANT.<br>
O, ’tis a worthy lord!
</p>

<p class="drama">
JEWELLER.<br>
Nay, that’s most fixed.
</p>

<p class="drama">
MERCHANT.<br>
A most incomparable man, breathed, as it were,<br>
To an untirable and continuate goodness.<br>
He passes.
</p>

<p class="drama">
JEWELLER.<br>
I have a jewel here—
</p>

<p class="drama">
MERCHANT.<br>
O, pray let’s see’t. For the Lord Timon, sir?
</p>

<p class="drama">
JEWELLER.<br>
If he will touch the estimate. But for that—
</p>

<p class="drama">
POET.<br>
When we for recompense have praised the vile,<br>
It stains the glory in that happy verse<br>
Which aptly sings the good.
</p>

<p class="drama">
MERCHANT.<br>
[<i>Looking at the jewel</i>.]<br>
’Tis a good form.
</p>

<p class="drama">
JEWELLER.<br>
And rich. Here is a water, look ye.
</p>

<p class="drama">
PAINTER.<br>
You are rapt, sir, in some work, some dedication<br>
To the great lord.
</p>

<p class="drama">
POET.<br>
A thing slipped idly from me.<br>
Our poesy is as a gum which oozes<br>
From whence ’tis nourished. The fire i’ th’ flint<br>
Shows not till it be struck; our gentle flame<br>
Provokes itself and, like the current, flies<br>
Each bound it chases. What have you there?
</p>

<p class="drama">
PAINTER.<br>
A picture, sir. When comes your book forth?
</p>

<p class="drama">
POET.<br>
Upon the heels of my presentment, sir.<br>
Let’s see your piece.
</p>

<p class="drama">
PAINTER.<br>
’Tis a good piece.
</p>

<p class="drama">
POET.<br>
So ’tis. This comes off well and excellent.
</p>

<p class="drama">
PAINTER.<br>
Indifferent.
</p>

<p class="drama">
POET.<br>
Admirable! How this grace<br>
Speaks his own standing! What a mental power<br>
This eye shoots forth! How big imagination<br>
Moves in this lip! To th’ dumbness of the gesture<br>
One might interpret.
</p>

<p class="drama">
PAINTER.<br>
It is a pretty mocking of the life.<br>
Here is a touch. Is’t good?
</p>

<p class="drama">
POET.<br>
I’ll say of it,<br>
It tutors nature. Artificial strife<br>
Lives in these touches livelier than life.
</p>

<p class="scenedesc">
Enter certain <span class="charname">Senators,</span> who pass over the stage.
</p>

<p class="drama">
PAINTER.<br>
How this lord is followed!
</p>

<p class="drama">
POET.<br>
The senators of Athens, happy men!
</p>

<p class="drama">
PAINTER.<br>
Look, more!
</p>

<p class="drama">
POET.<br>
You see this confluence, this great flood of visitors.<br>
I have in this rough work shaped out a man<br>
Whom this beneath world doth embrace and hug<br>
With amplest entertainment. My free drift<br>
Halts not particularly, but moves itself<br>
In a wide sea of wax. No levelled malice<br>
Infects one comma in the course I hold,<br>
But flies an eagle flight, bold and forth on,<br>
Leaving no tract behind.
</p>

<p class="drama">
PAINTER.<br>
How shall I understand you?
</p>

<p class="drama">
POET.<br>
I will unbolt to you.<br>
You see how all conditions, how all minds,<br>
As well of glib and slipp’ry creatures as<br>
Of grave and austere quality, tender down<br>
Their services to Lord Timon. His large fortune,<br>
Upon his good and gracious nature hanging,<br>
Subdues and properties to his love and tendance<br>
All sorts of hearts; yea, from the glass-faced flatterer<br>
To Apemantus, that few things loves better<br>
Than to abhor himself; even he drops down<br>
The knee before him and returns in peace<br>
Most rich in Timon’s nod.
</p>

<p class="drama">
PAINTER.<br>
I saw them speak together.
</p>

<p class="drama">
POET.<br>
Sir, I have upon a high and pleasant hill<br>
Feigned Fortune to be throned. The base o’ th’ mount<br>
Is ranked with all deserts, all kind of natures<br>
That labour on the bosom of this sphere<br>
To propagate their states. Amongst them all<br>
Whose eyes are on this sovereign lady fixed,<br>
One do I personate of Lord Timon’s frame,<br>
Whom Fortune with her ivory hand wafts to her,<br>
Whose present grace to present slaves and servants<br>
Translates his rivals.
</p>

<p class="drama">
PAINTER.<br>
’Tis conceived to scope.<br>
This throne, this Fortune, and this hill, methinks,<br>
With one man beckoned from the rest below,<br>
Bowing his head against the steepy mount<br>
To climb his happiness, would be well expressed<br>
In our condition.
</p>

<p class="drama">
POET.<br>
Nay, sir, but hear me on.<br>
All those which were his fellows but of late,<br>
Some better than his value, on the moment<br>
Follow his strides, his lobbies fill with tendance,<br>
Rain sacrificial whisperings in his ear,<br>
Make sacred even his stirrup, and through him<br>
Drink the free air.
</p>

<p class="drama">
PAINTER.<br>
Ay, marry, what of these?
</p>

<p class="drama">
POET.<br>
When Fortune in her shift and change of mood<br>
Spurns down her late beloved, all his dependants,<br>
Which laboured after him to the mountain’s top<br>
Even on their knees and hands, let him slip down,<br>
Not one accompanying his declining foot.
</p>

<p class="drama">
PAINTER.<br>
’Tis common.<br>
A thousand moral paintings I can show<br>
That shall demonstrate these quick blows of Fortune’s<br>
More pregnantly than words. Yet you do well<br>
To show Lord Timon that mean eyes have seen<br>
The foot above the head.
</p>

<p class="scenedesc">
Trumpets sound. Enter <span class="charname">Lord Timon,</span> addressing
himself courteously to every suitor. He is accompanied by a <span class="charname">Messenger;</span> <span class="charname">Lucilius</span> and
other servants follow.
</p>

<p class="drama">
TIMON.<br>
Imprisoned is he, say you?
</p>

<p class="drama">
MESSENGER.<br>
Ay, my good lord. Five talents is his debt,<br>
His means most short, his creditors most strait.<br>
Your honourable letter he desires<br>
To those have shut him up, which, failing,<br>
Periods his comfort.
</p>

<p class="drama">
TIMON.<br>
Noble Ventidius. Well,<br>
I am not of that feather to shake off<br>
My friend when he must need me. I do know him<br>
A gentleman that well deserves a help,<br>
Which he shall have. I’ll pay the debt and free him.
</p>

<p class="drama">
MESSENGER.<br>
Your lordship ever binds him.
</p>

<p class="drama">
TIMON.<br>
Commend me to him, I will send his ransom;<br>
And, being enfranchised, bid him come to me.<br>
’Tis not enough to help the feeble up,<br>
But to support him after. Fare you well.
</p>

<p class="drama">
MESSENGER.<br>
All happiness to your honour.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="scenedesc">
Enter an <span class="charname">Old Athenian</span>.
</p>

<p class="drama">
OLD ATHENIAN.<br>
Lord Timon, hear me speak.
</p>

<p class="drama">
TIMON.<br>
Freely, good father.
</p>

<p class="drama">
OLD ATHENIAN.<br>
Thou hast a servant named Lucilius.
</p>

<p class="drama">
TIMON.<br>
I have so. What of him?
</p>

<p class="drama">
OLD ATHENIAN.<br>
Most noble Timon, call the man before thee.
</p>

<p class="drama">
TIMON.<br>
Attends he here or no? Lucilius!
</p>

<p class="drama">
LUCILIUS.<br>
Here, at your lordship’s service.
</p>

<p class="drama">
OLD ATHENIAN.<br>
This fellow here, Lord Timon, this thy creature,<br>
By night frequents my house. I am a man<br>
That from my first have been inclined to thrift,<br>
And my estate deserves an heir more raised<br>
Than one which holds a trencher.
</p>

<p class="drama">
TIMON.<br>
Well, what further?
</p>

<p class="drama">
OLD ATHENIAN.<br>
One only daughter have I, no kin else,<br>
On whom I may confer what I have got.<br>
The maid is fair, o’ th’ youngest for a bride,<br>
And I have bred her at my dearest cost<br>
In qualities of the best. This man of thine<br>
Attempts her love. I prithee, noble lord,<br>
Join with me to forbid him her resort;<br>
Myself have spoke in vain.
</p>

<p class="drama">
TIMON.<br>
The man is honest.
</p>

<p class="drama">
OLD ATHENIAN.<br>
Therefore he will be, Timon.<br>
His honesty rewards him in itself;<br>
It must not bear my daughter.
</p>

<p class="drama">
TIMON.<br>
Does she love him?
</p>

<p class="drama">
OLD ATHENIAN.<br>
She is young and apt.<br>
Our own precedent passions do instruct us<br>
What levity’s in youth.
</p>

<p class="drama">
TIMON.<br>
[<i>To Lucilius</i>.] Love you the maid?
</p>

<p class="drama">
LUCILIUS.<br>
Ay, my good lord, and she accepts of it.
</p>

<p class="drama">
OLD ATHENIAN.<br>
If in her marriage my consent be missing,<br>
I call the gods to witness, I will choose<br>
Mine heir from forth the beggars of the world<br>
And dispossess her all.
</p>

<p class="drama">
TIMON.<br>
How shall she be endowed,<br>
If she be mated with an equal husband?
</p>

<p class="drama">
OLD ATHENIAN.<br>
Three talents on the present; in future, all.
</p>

<p class="drama">
TIMON.<br>
This gentleman of mine hath served me long.<br>
To build his fortune I will strain a little,<br>
For ’tis a bond in men. Give him thy daughter.<br>
What you bestow, in him I’ll counterpoise,<br>
And make him weigh with her.
</p>

<p class="drama">
OLD ATHENIAN.<br>
Most noble lord,<br>
Pawn me to this your honour, she is his.
</p>

<p class="drama">
TIMON.<br>
My hand to thee; mine honour on my promise.
</p>

<p class="drama">
LUCILIUS.<br>
Humbly I thank your lordship. Never may<br>
That state or fortune fall into my keeping<br>
Which is not owed to you.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Lucilius</span> and
<span class="charname">Old Athenian</span>.</i>]
</p>

<p class="drama">
POET.<br>
[<i>Presenting his poem</i>.]<br>
Vouchsafe my labour, and long live your lordship.
</p>

<p class="drama">
TIMON.<br>
I thank you, you shall hear from me anon.<br>
Go not away.—What have you there, my friend?
</p>

<p class="drama">
PAINTER.<br>
A piece of painting, which I do beseech<br>
Your lordship to accept.
</p>

<p class="drama">
TIMON.<br>
Painting is welcome.<br>
The painting is almost the natural man,<br>
For since dishonour traffics with man’s nature,<br>
He is but outside; these pencilled figures are<br>
Even such as they give out. I like your work,<br>
And you shall find I like it. Wait attendance<br>
Till you hear further from me.
</p>

<p class="drama">
PAINTER.<br>
The gods preserve you.
</p>

<p class="drama">
TIMON.<br>
Well fare you, gentleman. Give me your hand.<br>
We must needs dine together. Sir, your jewel<br>
Hath suffered under praise.
</p>

<p class="drama">
JEWELLER.<br>
What, my lord, dispraise?
</p>

<p class="drama">
TIMON.<br>
A mere satiety of commendations.<br>
If I should pay you for ’t as ’tis extolled,<br>
It would unclew me quite.
</p>

<p class="drama">
JEWELLER.<br>
My lord, ’tis rated<br>
As those which sell would give. But you well know<br>
Things of like value, differing in the owners,<br>
Are prized by their masters. Believe’t, dear lord,<br>
You mend the jewel by the wearing it.
</p>

<p class="drama">
TIMON.<br>
Well mocked.
</p>

<p class="drama">
MERCHANT.<br>
No, my good lord, he speaks the common tongue,<br>
Which all men speak with him.
</p>

<p class="scenedesc">
Enter <span class="charname">Apemantus</span>.
</p>

<p class="drama">
TIMON.<br>
Look who comes here. Will you be chid?
</p>

<p class="drama">
JEWELLER.<br>
We’ll bear, with your lordship.
</p>

<p class="drama">
MERCHANT.<br>
He’ll spare none.
</p>

<p class="drama">
TIMON.<br>
Good morrow to thee, gentle Apemantus.
</p>

<p class="drama">
APEMANTUS.<br>
Till I be gentle, stay thou for thy good morrow—<br>
When thou art Timon’s dog, and these knaves honest.
</p>

<p class="drama">
TIMON.<br>
Why dost thou call them knaves? Thou know’st them not.
</p>

<p class="drama">
APEMANTUS.<br>
Are they not Athenians?
</p>

<p class="drama">
TIMON.<br>
Yes.
</p>

<p class="drama">
APEMANTUS.<br>
Then I repent not.
</p>

<p class="drama">
JEWELLER.<br>
You know me, Apemantus?
</p>

<p class="drama">
APEMANTUS.<br>
Thou know’st I do, I called thee by thy name.
</p>

<p class="drama">
TIMON.<br>
Thou art proud, Apemantus.
</p>

<p class="drama">
APEMANTUS.<br>
Of nothing so much as that I am not like Timon.
</p>

<p class="drama">
TIMON.<br>
Whither art going?
</p>

<p class="drama">
APEMANTUS.<br>
To knock out an honest Athenian’s brains.
</p>

<p class="drama">
TIMON.<br>
That’s a deed thou’lt die for.
</p>

<p class="drama">
APEMANTUS.<br>
Right, if doing nothing be death by th’ law.
</p>

<p class="drama">
TIMON.<br>
How lik’st thou this picture, Apemantus?
</p>

<p class="drama">
APEMANTUS.<br>
The best, for the innocence.
</p>

<p class="drama">
TIMON.<br>
Wrought he not well that painted it?
</p>

<p class="drama">
APEMANTUS.<br>
He wrought better that made the painter, and yet he’s but a filthy piece
of work.</p>

<p class="drama">
PAINTER.<br>
You’re a dog.
</p>

<p class="drama">
APEMANTUS.<br>
Thy mother’s of my generation. What’s she, if I be a dog?
</p>

<p class="drama">
TIMON.<br>
Wilt dine with me, Apemantus?
</p>

<p class="drama">
APEMANTUS.<br>
No, I eat not lords.
</p>

<p class="drama">
TIMON.<br>
An thou shouldst, thou’dst anger ladies.
</p>

<p class="drama">
APEMANTUS.<br>
O, they eat lords. So they come by great bellies.
</p>

<p class="drama">
TIMON.<br>
That’s a lascivious apprehension.
</p>

<p class="drama">
APEMANTUS.<br>
So thou apprehend’st it, take it for thy labour.
</p>

<p class="drama">
TIMON.<br>
How dost thou like this jewel, Apemantus?
</p>

<p class="drama">
APEMANTUS.<br>
Not so well as plain-dealing, which will not cost a man a doit.</p>

<p class="drama">
TIMON.<br>
What dost thou think ’tis worth?
</p>

<p class="drama">
APEMANTUS.<br>
Not worth my thinking. How now, poet?
</p>

<p class="drama">
POET.<br>
How now, philosopher?
</p>

<p class="drama">
APEMANTUS.<br>
Thou liest.
</p>

<p class="drama">
POET.<br>
Art not one?
</p>

<p class="drama">
APEMANTUS.<br>
Yes.
</p>

<p class="drama">
POET.<br>
Then I lie not.
</p>

<p class="drama">
APEMANTUS.<br>
Art not a poet?
</p>

<p class="drama">
POET.<br>
Yes.
</p>

<p class="drama">
APEMANTUS.<br>
Then thou liest. Look in thy last work, where thou hast feigned him a worthy
fellow.</p>

<p class="drama">
POET.<br>
That’s not feigned, he is so.
</p>

<p class="drama">
APEMANTUS.<br>
Yes, he is worthy of thee, and to pay thee for thy labour. He that loves to be
flattered is worthy o’ th’ flatterer. Heavens, that I were a lord!
</p>

<p class="drama">
TIMON.<br>
What wouldst do then, Apemantus?
</p>

<p class="drama">
APEMANTUS.<br>
E’en as Apemantus does now, hate a lord with my heart.
</p>

<p class="drama">
TIMON.<br>
What, thyself?
</p>

<p class="drama">
APEMANTUS.<br>
Ay.
</p>

<p class="drama">
TIMON.<br>
Wherefore?
</p>

<p class="drama">
APEMANTUS.<br>
That I had no angry wit to be a lord. Art not thou a merchant?
</p>

<p class="drama">
MERCHANT.<br>
Ay, Apemantus.
</p>

<p class="drama">
APEMANTUS.<br>
Traffic confound thee, if the gods will not.
</p>

<p class="drama">
MERCHANT.<br>
If traffic do it, the gods do it.
</p>

<p class="drama">
APEMANTUS.<br>
Traffic’s thy god, and thy god confound thee!
</p>

<p class="scenedesc">
Trumpet sounds. Enter a <span class="charname">Messenger</span>.
</p>

<p class="drama">
TIMON.<br>
What trumpet’s that?
</p>

<p class="drama">
MESSENGER.<br>
’Tis Alcibiades, and some twenty horse,<br>
All of companionship.
</p>

<p class="drama">
TIMON.<br>
Pray entertain them, give them guide to us.
</p>

<p class="right">[<i>Exeunt some <span class="charname">Attendants</span>.</i>]</p>

<p class="drama">
You must needs dine with me. Go not you hence<br>
Till I have thanked you; when dinner’s done,<br>
Show me this piece. I am joyful of your sights.
</p>

<p class="scenedesc">
Enter <span class="charname">Alcibiades</span> with his company.
</p>

<p class="drama">
Most welcome, sir.</p>

<p class="right">[<i>They bow to each other.</i>]</p>

<p class="drama">
APEMANTUS.<br>
[<i>Aside</i>.] So, so, there!<br>
Aches contract and starve your supple joints!<br>
That there should be small love amongst these sweet knaves,<br>
And all this courtesy! The strain of man’s bred out<br>
Into baboon and monkey.
</p>

<p class="drama">
ALCIBIADES.<br>
Sir, you have saved my longing, and I feed<br>
Most hungerly on your sight.
</p>

<p class="drama">
TIMON.<br>
Right welcome, sir!<br>
Ere we depart we’ll share a bounteous time<br>
In different pleasures. Pray you, let us in.
</p>

<p class="right">[<i>Exeunt all but <span class="charname">Apemantus</span>.</i>]</p>

<p class="scenedesc">
Enter two <span class="charname">Lords</span>.
</p>

<p class="drama">
FIRST LORD.<br>
What time o’ day is’t, Apemantus?
</p>

<p class="drama">
APEMANTUS.<br>
Time to be honest.
</p>

<p class="drama">
FIRST LORD.<br>
That time serves still.
</p>

<p class="drama">
APEMANTUS.<br>
The more accursed thou, that still omitt’st it.
</p>

<p class="drama">
SECOND LORD.<br>
Thou art going to Lord Timon’s feast?
</p>

<p class="drama">
APEMANTUS.<br>
Ay, to see meat fill knaves and wine heat fools.
</p>

<p class="drama">
SECOND LORD.<br>
Fare thee well, fare thee well.
</p>

<p class="drama">
APEMANTUS.<br>
Thou art a fool to bid me farewell twice.
</p>

<p class="drama">
SECOND LORD.<br>
Why, Apemantus?
</p>

<p class="drama">
APEMANTUS.<br>
Shouldst have kept one to thyself, for I mean to give thee none.
</p>

<p class="drama">
FIRST LORD.<br>
Hang thyself!
</p>

<p class="drama">
APEMANTUS.<br>
No, I will do nothing at thy bidding. Make thy requests to thy friend.</p>

<p class="drama">
SECOND LORD.<br>
Away, unpeaceable dog, or I’ll spurn thee hence.
</p>

<p class="drama">
APEMANTUS.<br>
I will fly, like a dog, the heels o’ th’ ass.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
FIRST LORD.<br>
He’s opposite to humanity. Come, shall we in<br>
And taste Lord Timon’s bounty? He outgoes<br>
The very heart of kindness.
</p>

<p class="drama">
SECOND LORD.<br>
He pours it out; Plutus, the god of gold,<br>
Is but his steward. No meed but he repays<br>
Sevenfold above itself, no gift to him<br>
But breeds the giver a return exceeding<br>
All use of quittance.
</p>

<p class="drama">
FIRST LORD.<br>
The noblest mind he carries<br>
That ever governed man.
</p>

<p class="drama">
SECOND LORD.<br>
Long may he live in fortunes. Shall we in?
</p>

<p class="drama">
FIRST LORD.<br>
I’ll keep you company.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneI_33.2"></a><b>SCENE II. The Same. A room of state in Timon’s
house</b></h3>

<p class="scenedesc">
Hautboys playing loud music. A great banquet served in, <span class="charname">Flavius</span> and others attending; and then enter <span class="charname">Lord Timon, </span> the Senators, the Athenian Lords, <span class="charname">Alcibiades,</span> and <span class="charname">Ventidius,</span> which Timon redeemded from prison. Then
comes, dropping after all, <span class="charname">Apemantus,</span>
discontentedly, like himself.
</p>

<p class="drama">
VENTIDIUS.<br>
Most honoured Timon,<br>
It hath pleased the gods to remember my father’s age<br>
And call him to long peace.<br>
He is gone happy and has left me rich.<br>
Then, as in grateful virtue I am bound<br>
To your free heart, I do return those talents,<br>
Doubled with thanks and service, from whose help<br>
I derived liberty.
</p>

<p class="drama">
TIMON.<br>
O, by no means,<br>
Honest Ventidius. You mistake my love.<br>
I gave it freely ever, and there’s none<br>
Can truly say he gives if he receives.<br>
If our betters play at that game, we must not dare<br>
To imitate them; faults that are rich are fair.
</p>

<p class="drama">
VENTIDIUS.<br>
A noble spirit!
</p>

<p class="drama">
TIMON.<br>
Nay, my lords, ceremony was but devised at first<br>
To set a gloss on faint deeds, hollow welcomes,<br>
Recanting goodness, sorry ere ’tis shown;<br>
But where there is true friendship there needs none.<br>
Pray, sit, more welcome are ye to my fortunes<br>
Than my fortunes to me.
</p>

<p class="right">[<i>They sit.</i>]</p>

<p class="drama">
FIRST LORD.<br>
My lord, we always have confessed it.
</p>

<p class="drama">
APEMANTUS.<br>
Ho, ho, confessed it? Hanged it, have you not?
</p>

<p class="drama">
TIMON.<br>
O Apemantus, you are welcome.
</p>

<p class="drama">
APEMANTUS.<br>
No,<br>
You shall not make me welcome.<br>
I come to have thee thrust me out of doors.
</p>

<p class="drama">
TIMON.<br>
Fie, thou’rt a churl, ye’ve got a humour there<br>
Does not become a man; ’tis much to blame.<br>
They say, my lords, <i>ira furor brevis est</i>,<br>
But yond man is ever angry.<br>
Go, let him have a table by himself,<br>
For he does neither affect company,<br>
Nor is he fit for it indeed.
</p>

<p class="drama">
APEMANTUS.<br>
Let me stay at thine apperil, Timon.<br>
I come to observe; I give thee warning on’t.
</p>

<p class="drama">
TIMON.<br>
I take no heed of thee. Thou’rt an Athenian, therefore, welcome. I myself would
have no power; prithee; let my meat make thee silent.
</p>

<p class="drama">
APEMANTUS.<br>
I scorn thy meat, ’twould choke me, for I should ne’er flatter thee. O you
gods, what a number of men eats Timon, and he sees ’em not! It grieves me to
see so many dip their meat in one man’s blood; and all the madness is, he
cheers them up too.<br>
I wonder men dare trust themselves with men.<br>
Methinks they should invite them without knives.<br>
Good for their meat, and safer for their lives.<br>
There’s much example for ’t. The fellow that sits next him, now parts bread
with him, pledges the breath of him in a divided draft, is the readiest man
to kill him. ’T has been proved. If I were a huge man, I should fear to drink
at meals,<br>
Lest they should spy my wind-pipe’s dangerous notes.<br>
Great men should drink with harness on their throats.
</p>

<p class="drama">
TIMON.<br>
My lord, in heart, and let the health go round.
</p>

<p class="drama">
SECOND LORD.<br>
Let it flow this way, my good lord.
</p>

<p class="drama">
APEMANTUS.<br>
Flow this way? A brave fellow! He keeps his tides well. Those healths will make
thee and thy state look ill, Timon.<br>
Here’s that which is too weak to be a sinner,<br>
Honest water, which ne’er left man i’ the mire.<br>
This and my food are equals, there’s no odds.<br>
Feasts are too proud to give thanks to the gods.
</p>

<p class="center">
<i>Apemantus’ grace</i>
</p>

<p class="drama">
    Immortal gods, I crave no pelf,<br>
    I pray for no man but myself.<br>
    Grant I may never prove so fond<br>
    To trust man on his oath or bond,<br>
    Or a harlot for her weeping,<br>
    Or a dog that seems a-sleeping,<br>
    Or a keeper with my freedom,<br>
    Or my friends if I should need ’em.<br>
        Amen. So fall to’t.<br>
        Rich men sin, and I eat root.
</p>

<p class="right">[<i>He eats and drinks.</i>]</p>

<p class="drama">
Much good dich thy good heart, Apemantus!</p>

<p class="drama">
TIMON.<br>
Captain Alcibiades, your heart’s in the field now.
</p>

<p class="drama">
ALCIBIADES.<br>
My heart is ever at your service, my lord.
</p>

<p class="drama">
TIMON.<br>
You had rather be at a breakfast of enemies than a dinner of friends.
</p>

<p class="drama">
ALCIBIADES.<br>
So they were bleeding new, my lord, there’s no meat like ’em. I could wish my
best friend at such a feast.
</p>

<p class="drama">
APEMANTUS.<br>
Would all those flatterers were thine enemies then, that then thou
mightst kill ’em, and bid me to ’em.</p>

<p class="drama">
FIRST LORD.<br>
Might we but have that happiness, my lord, that you would once use our hearts,
whereby we might express some part of our zeals, we should think ourselves for
ever perfect.</p>

<p class="drama">
TIMON.<br>
O, no doubt, my good friends, but the gods themselves have provided that I
shall have much help from you. How had you been my friends else? Why have you
that charitable title from thousands, did not you chiefly belong to my heart? I
have told more of you to myself than you can with modesty speak in your own
behalf. And thus far I confirm you. O you gods, think I, what need we have any
friends if we should ne’er have need of ’em? They were the most needless
creatures living, should we ne’er have use for ’em, and would most resemble
sweet instruments hung up in cases, that keep their sounds to themselves. Why,
I have often wished myself poorer that I might come nearer to you. We are born
to do benefits, and what better or properer can we call our own than the riches
of our friends? O, what a precious comfort ’tis to have so many, like brothers,
commanding one another’s fortunes. O joy’s e’en made away ere’t can be born!
Mine eyes cannot hold out water, methinks. To forget their faults, I drink to
you.
</p>

<p class="drama">
APEMANTUS.<br>
Thou weep’st to make them drink, Timon.
</p>

<p class="drama">
SECOND LORD.<br>
Joy had the like conception in our eyes<br>
And, at that instant like a babe sprung up.
</p>

<p class="drama">
APEMANTUS.<br>
Ho, ho! I laugh to think that babe a bastard.
</p>

<p class="drama">
THIRD LORD.<br>
I promise you, my lord, you moved me much.
</p>

<p class="drama">
APEMANTUS.<br>
Much!
</p>

<p class="right">[<i>A tucket sounds.</i>]</p>

<p class="drama">
TIMON.<br>
What means that trump?
</p>

<p class="scenedesc">
Enter a <span class="charname">Servant</span>.
</p>

<p class="drama">
How now?</p>

<p class="drama">
SERVANT.<br>
Please you, my lord, there are certain ladies most desirous of admittance.
</p>

<p class="drama">
TIMON.<br>
Ladies? What are their wills?
</p>

<p class="drama">
SERVANT.<br>
There comes with them a forerunner, my lord, which bears that office, to
signify their pleasures.</p>

<p class="drama">
TIMON.<br>
I pray, let them be admitted.
</p>

<p class="right">[<i>Exit <span class="charname">Servant</span>.</i>]</p>

<p class="scenedesc">
Enter <span class="charname">Cupid</span>.
</p>

<p class="drama">
CUPID.<br>
Hail to thee, worthy Timon, and to all<br>
That of his bounties taste! The five best senses<br>
Acknowledge thee their patron and come freely<br>
To gratulate thy plenteous bosom. There<br>
Taste, touch, all, pleased from thy table rise;<br>
They only now come but to feast thine eyes.
</p>

<p class="drama">
TIMON.<br>
They’re welcome all, let ’em have kind admittance.<br>
Music, make their welcome!
</p>

<p class="drama">
FIRST LORD.<br>
You see, my lord, how ample you’re beloved.
</p>

<p class="scenedesc">
Music. Enter a masque of <span class="charname">Ladies</span> as Amazons, with
lutes in their hands, dancing and playing.
</p>

<p class="drama">
APEMANTUS.<br>
Hoy-day!<br>
What a sweep of vanity comes this way.<br>
They dance? They are madwomen.<br>
Like madness is the glory of this life,<br>
As this pomp shows to a little oil and root.<br>
We make ourselves fools to disport ourselves,<br>
And spend our flatteries to drink those men<br>
Upon whose age we void it up again<br>
With poisonous spite and envy.<br>
Who lives that’s not depraved or depraves?<br>
Who dies that bears not one spurn to their graves<br>
Of their friend’s gift?<br>
I should fear those that dance before me now<br>
Would one day stamp upon me. ’T has been done.<br>
Men shut their doors against a setting sun.
</p>

<p class="right">
[<i>The <span class="charname">Lords</span> rise from table, with much adoring
of <span class="charname">Timon,</span> and to show their loves each singles
out an Amazon, and all dance, men with women, a lofty strain or two to the
hautboys, and cease.</i>]
</p>

<p class="drama">
TIMON.<br>
You have done our pleasures much grace, fair ladies,<br>
Set a fair fashion on our entertainment,<br>
Which was not half so beautiful and kind.<br>
You have added worth unto ’t and lustre,<br>
And entertained me with mine own device.<br>
I am to thank you for ’t.
</p>

<p class="drama">
FIRST LADY.<br>
My lord, you take us even at the best.
</p>

<p class="drama">
APEMANTUS.<br>
Faith, for the worst is filthy and would not hold taking, I doubt me.</p>

<p class="drama">
TIMON.<br>
Ladies, there is an idle banquet attends you,<br>
Please you to dispose yourselves.
</p>

<p class="drama">
ALL LADIES.<br>
Most thankfully, my lord.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Cupid</span> and
<span class="charname">Ladies</span>.</i>]
</p>

<p class="drama">
TIMON.<br>
Flavius!
</p>

<p class="drama">
FLAVIUS.<br>
My lord?
</p>

<p class="drama">
TIMON.<br>
The little casket bring me hither.
</p>

<p class="drama">
FLAVIUS.<br>
Yes, my lord. [<i>Aside</i>.] More jewels yet?<br>
There is no crossing him in ’s humour;<br>
Else I should tell him well, i’ faith, I should,<br>
When all’s spent, he’d be crossed then, an he could.<br>
’Tis pity bounty had not eyes behind,<br>
That man might ne’er be wretched for his mind.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
FIRST LORD.<br>
Where be our men?
</p>

<p class="drama">
SERVANT.<br>
Here, my lord, in readiness.
</p>

<p class="drama">
SECOND LORD.<br>
Our horses!
</p>

<p class="scenedesc">
Enter <span class="charname">Flavius</span> with the casket.
</p>

<p class="drama">
TIMON.<br>
O, my friends, I have one word<br>
To say to you. Look you, my good lord,<br>
I must entreat you, honour me so much<br>
As to advance this jewel. Accept it and wear it,<br>
Kind my lord.
</p>

<p class="drama">
FIRST LORD.<br>
I am so far already in your gifts—
</p>

<p class="drama">
ALL.<br>
So are we all.
</p>

<p class="scenedesc">
Enter a <span class="charname">Servant</span>.
</p>

<p class="drama">
SERVANT.<br>
My lord, there are certain nobles of the Senate<br>
Newly alighted and come to visit you.
</p>

<p class="drama">
TIMON.<br>
They are fairly welcome.
</p>

<p class="right">[<i>Exit <span class="charname">Servant</span>.</i>]</p>

<p class="drama">
FLAVIUS.<br>
I beseech your honour,<br>
Vouchsafe me a word. It does concern you near.
</p>

<p class="drama">
TIMON.<br>
Near? Why then, another time I’ll hear thee.<br>
I prithee let’s be provided to show them entertainment.
</p>

<p class="drama">
FLAVIUS.<br>
[<i>Aside</i>.] I scarce know how.
</p>

<p class="scenedesc">
Enter another <span class="charname">Servant</span>.
</p>

<p class="drama">
SECOND SERVANT.<br>
May it please your honour, Lord Lucius,<br>
Out of his free love, hath presented to you<br>
Four milk-white horses, trapped in silver.
</p>

<p class="drama">
TIMON.<br>
I shall accept them fairly; let the presents<br>
Be worthily entertained.
</p>

<p class="right">[<i>Exit <span class="charname">Servant</span>.</i>]</p>

<p class="scenedesc">
Enter a third <span class="charname">Servant</span>.
</p>

<p class="drama">
How now? What news?</p>

<p class="drama">
THIRD SERVANT.<br>
Please you, my lord, that honourable gentleman, Lord Lucullus, entreats your
company tomorrow to hunt with him and has sent your honour two brace of
greyhounds.</p>

<p class="drama">
TIMON.<br>
I’ll hunt with him; and let them be received,<br>
Not without fair reward.
</p>

<p class="right">[<i>Exit <span class="charname">Servant</span>.</i>]</p>

<p class="drama">
FLAVIUS.<br>
[<i>Aside</i>.] What will this come to?<br>
He commands us to provide, and give great gifts,<br>
And all out of an empty coffer;<br>
Nor will he know his purse or yield me this:<br>
To show him what a beggar his heart is,<br>
Being of no power to make his wishes good.<br>
His promises fly so beyond his state<br>
That what he speaks is all in debt; he owes<br>
For every word. He is so kind that he now<br>
Pays interest for ’t; his land’s put to their books.<br>
Well, would I were gently put out of office<br>
Before I were forced out.<br>
Happier is he that has no friend to feed<br>
Than such that do e’en enemies exceed.<br>
I bleed inwardly for my lord.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
TIMON.<br>
You do yourselves much wrong,<br>
You bate too much of your own merits.<br>
Here, my lord, a trifle of our love.
</p>

<p class="drama">
SECOND LORD.<br>
With more than common thanks I will receive it.
</p>

<p class="drama">
THIRD LORD.<br>
O, he’s the very soul of bounty!
</p>

<p class="drama">
TIMON.<br>
And now I remember, my lord, you gave good words the other day of a bay courser
I rode on. ’Tis yours because you liked it.
</p>

<p class="drama">
THIRD LORD.<br>
O, I beseech you, pardon me, my lord, in that.
</p>

<p class="drama">
TIMON.<br>
You may take my word, my lord. I know no man<br>
Can justly praise but what he does affect.<br>
I weigh my friend’s affection with mine own.<br>
I’ll tell you true, I’ll call to you.
</p>

<p class="drama">
ALL LORDS.<br>
O, none so welcome!
</p>

<p class="drama">
TIMON.<br>
I take all and your several visitations<br>
So kind to heart, ’tis not enough to give;<br>
Methinks I could deal kingdoms to my friends,<br>
And ne’er be weary. Alcibiades,<br>
Thou art a soldier, therefore seldom rich.<br>
It comes in charity to thee, for all thy living<br>
Is ’mongst the dead, and all the lands thou hast<br>
Lie in a pitched field.
</p>

<p class="drama">
ALCIBIADES.<br>
Ay, defiled land, my lord.
</p>

<p class="drama">
FIRST LORD.<br>
We are so virtuously bound—
</p>

<p class="drama">
TIMON.<br>
And so am I to you.
</p>

<p class="drama">
SECOND LORD.<br>
So infinitely endeared—
</p>

<p class="drama">
TIMON.<br>
All to you. Lights, more lights!
</p>

<p class="drama">
FIRST LORD.<br>
The best of happiness, honour, and fortunes keep with you, Lord Timon.
</p>

<p class="drama">
TIMON.<br>
Ready for his friends.
</p>

<p class="right">[<i>Exeunt all but <span class="charname">Apemantus</span> and
<span class="charname">Timon</span>.</i>]</p>

<p class="drama">
APEMANTUS.<br>
What a coil’s here!<br>
Serving of becks and jutting out of bums!<br>
I doubt whether their legs be worth the sums<br>
That are given for ’em. Friendship’s full of dregs.<br>
Methinks false hearts should never have sound legs.<br>
Thus honest fools lay out their wealth on curtsies.
</p>

<p class="drama">
TIMON.<br>
Now, Apemantus, if thou wert not sullen,<br>
I would be good to thee.
</p>

<p class="drama">
APEMANTUS.<br>
No, I’ll nothing, for if I should be bribed too, there would be none left
to rail upon thee, and then thou wouldst sin the faster. Thou giv’st so long,
Timon, I fear me thou wilt give away thyself in paper shortly. What needs these
feasts, pomps, and vainglories?</p>

<p class="drama">
TIMON.<br>
Nay, an you begin to rail on society once, I am sworn not to give regard to
you. Farewell, and come with better music.</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
APEMANTUS.<br>
So. Thou wilt not hear me now, thou shalt not then.<br>
I’ll lock thy heaven from thee.<br>
O, that men’s ears should be<br>
To counsel deaf, but not to flattery!
</p>

<p class="right">[<i>Exit.</i>]</p>

