<h2> <a id="sceneV_8.1"></a><b>ACT V</b></h2>

<h3> <b>SCENE I. A churchyard.</b></h3>

<p class="scenedesc">
Enter two <span class="charname">Clowns</span> with spades, &amp;c.
</p>

<p class="drama">
FIRST CLOWN.<br>
Is she to be buried in Christian burial, when she wilfully seeks her own
salvation?
</p>

<p class="drama">
SECOND CLOWN.<br>
I tell thee she is, and therefore make her grave straight. The crowner hath sat
on her, and finds it Christian burial.
</p>

<p class="drama">
FIRST CLOWN.<br>
How can that be, unless she drowned herself in her own defence?
</p>

<p class="drama">
SECOND CLOWN.<br>
Why, ’tis found so.
</p>

<p class="drama">
FIRST CLOWN.<br>
It must be <i>se offendendo</i>, it cannot be else. For here lies the point: if
I drown myself wittingly, it argues an act: and an act hath three branches. It
is to act, to do, and to perform: argal, she drowned herself wittingly.
</p>

<p class="drama">
SECOND CLOWN.<br>
Nay, but hear you, goodman delver,—
</p>

<p class="drama">
FIRST CLOWN.<br>
Give me leave. Here lies the water; good. Here stands the man; good. If the man
go to this water and drown himself, it is, will he nill he, he goes,—mark you
that. But if the water come to him and drown him, he drowns not himself. Argal,
he that is not guilty of his own death shortens not his own life.
</p>

<p class="drama">
SECOND CLOWN.<br>
But is this law?
</p>

<p class="drama">
FIRST CLOWN.<br>
Ay, marry, is’t, crowner’s quest law.
</p>

<p class="drama">
SECOND CLOWN.<br>
Will you ha’ the truth on’t? If this had not been a gentlewoman, she should
have been buried out o’ Christian burial.
</p>

<p class="drama">
FIRST CLOWN.<br>
Why, there thou say’st. And the more pity that great folk should have
countenance in this world to drown or hang themselves more than their even
Christian. Come, my spade. There is no ancient gentlemen but gardeners,
ditchers, and grave-makers: they hold up Adam’s profession.
</p>

<p class="drama">
SECOND CLOWN.<br>
Was he a gentleman?
</p>

<p class="drama">
FIRST CLOWN.<br>
He was the first that ever bore arms.
</p>

<p class="drama">
SECOND CLOWN.<br>
Why, he had none.
</p>

<p class="drama">
FIRST CLOWN.<br>
What, art a heathen? How dost thou understand the Scripture? The Scripture says
Adam digg’d. Could he dig without arms? I’ll put another question to thee. If
thou answerest me not to the purpose, confess thyself—
</p>

<p class="drama">
SECOND CLOWN.<br>
Go to.
</p>

<p class="drama">
FIRST CLOWN.<br>
What is he that builds stronger than either the mason, the shipwright, or the
carpenter?
</p>

<p class="drama">
SECOND CLOWN.<br>
The gallows-maker; for that frame outlives a thousand tenants.
</p>

<p class="drama">
FIRST CLOWN.<br>
I like thy wit well in good faith, the gallows does well. But how does it well?
It does well to those that do ill. Now, thou dost ill to say the gallows is
built stronger than the church; argal, the gallows may do well to thee. To’t
again, come.
</p>

<p class="drama">
SECOND CLOWN.<br>
Who builds stronger than a mason, a shipwright, or a carpenter?
</p>

<p class="drama">
FIRST CLOWN.<br>
Ay, tell me that, and unyoke.
</p>

<p class="drama">
SECOND CLOWN.<br>
Marry, now I can tell.
</p>

<p class="drama">
FIRST CLOWN.<br>
To’t.
</p>

<p class="drama">
SECOND CLOWN.<br>
Mass, I cannot tell.
</p>

<p class="scenedesc">
Enter <span class="charname">Hamlet</span> and <span class="charname">Horatio</span>, at a distance.
</p>

<p class="drama">
FIRST CLOWN.<br>
Cudgel thy brains no more about it, for your dull ass will not mend his pace
with beating; and when you are asked this question next, say ‘a grave-maker’.
The houses he makes last till doomsday. Go, get thee to Yaughan; fetch me a
stoup of liquor.
</p>

<p class="right">
[<i>Exit <span class="charname">Second Clown</span>.</i>]
</p>

<p class="drama">
[<i>Digs and sings.</i>]
</p>

<p class="drama">
   In youth when I did love, did love,<br>
     Methought it was very sweet;<br>
   To contract, O, the time for, a, my behove,<br>
     O methought there was nothing meet.<br>
</p>

<p class="drama">
HAMLET.<br>
Has this fellow no feeling of his business, that he sings at grave-making?
</p>

<p class="drama">
HORATIO.<br>
Custom hath made it in him a property of easiness.<br>
</p>

<p class="drama">
HAMLET.<br>
’Tis e’en so; the hand of little employment hath the daintier sense.
</p>

<p class="drama">
FIRST CLOWN.<br>
[<i>Sings.</i>]<br>
   But age with his stealing steps<br>
     Hath claw’d me in his clutch,<br>
   And hath shipp’d me into the land,<br>
     As if I had never been such.<br>
</p>

<p class="right">
[<i>Throws up a skull.</i>]
</p>

<p class="drama">
HAMLET.<br>
That skull had a tongue in it, and could sing once. How the knave jowls it to
th’ ground, as if ’twere Cain’s jawbone, that did the first murder! This might
be the pate of a politician which this ass now o’er-offices, one that would
circumvent God, might it not?
</p>

<p class="drama">
HORATIO.<br>
It might, my lord.<br>
</p>

<p class="drama">
HAMLET.<br>
Or of a courtier, which could say ‘Good morrow, sweet lord! How dost thou, good
lord?’ This might be my lord such-a-one, that praised my lord such-a-one’s
horse when he meant to beg it, might it not?
</p>

<p class="drama">
HORATIO.<br>
Ay, my lord.<br>
</p>

<p class="drama">
HAMLET.<br>
Why, e’en so: and now my Lady Worm’s; chapless, and knocked about the mazard
with a sexton’s spade. Here’s fine revolution, an we had the trick to see’t.
Did these bones cost no more the breeding but to play at loggets with ’em? Mine
ache to think on’t.
</p>

<p class="drama">
FIRST CLOWN.<br>
[<i>Sings.</i>]<br>
   A pickaxe and a spade, a spade,<br>
     For and a shrouding-sheet;<br>
   O, a pit of clay for to be made<br>
     For such a guest is meet.<br>
</p>

<p class="right">
[<i>Throws up another skull.</i>]
</p>

<p class="drama">
HAMLET.<br>
There’s another. Why may not that be the skull of a lawyer? Where be his
quiddits now, his quillets, his cases, his tenures, and his tricks? Why does he
suffer this rude knave now to knock him about the sconce with a dirty shovel,
and will not tell him of his action of battery? Hum. This fellow might be in’s
time a great buyer of land, with his statutes, his recognizances, his fines,
his double vouchers, his recoveries. Is this the fine of his fines, and the
recovery of his recoveries, to have his fine pate full of fine dirt? Will his
vouchers vouch him no more of his purchases, and double ones too, than the
length and breadth of a pair of indentures? The very conveyances of his lands
will scarcely lie in this box; and must the inheritor himself have no more, ha?
</p>

<p class="drama">
HORATIO.<br>
Not a jot more, my lord.<br>
</p>

<p class="drama">
HAMLET.<br>
Is not parchment made of sheep-skins?<br>
</p>

<p class="drama">
HORATIO.<br>
Ay, my lord, and of calf-skins too.<br>
</p>

<p class="drama">
HAMLET.<br>
They are sheep and calves which seek out assurance in that. I will speak to
this fellow.—Whose grave’s this, sir?
</p>

<p class="drama">
FIRST CLOWN.<br>
Mine, sir.<br>
[<i>Sings.</i>]<br>
   O, a pit of clay for to be made<br>
     For such a guest is meet.<br>
</p>

<p class="drama">
HAMLET.<br>
I think it be thine indeed, for thou liest in’t.<br>
</p>

<p class="drama">
FIRST CLOWN.<br>
You lie out on’t, sir, and therefore ’tis not yours.<br>
For my part, I do not lie in’t, yet it is mine.<br>
</p>

<p class="drama">
HAMLET.<br>
Thou dost lie in’t, to be in’t and say it is thine. ’Tis for the dead, not for
the quick; therefore thou liest.
</p>

<p class="drama">
FIRST CLOWN.<br>
’Tis a quick lie, sir; ’t will away again from me to you.
</p>

<p class="drama">
HAMLET.<br>
What man dost thou dig it for?<br>
</p>

<p class="drama">
FIRST CLOWN.<br>
For no man, sir.
</p>

<p class="drama">
HAMLET.<br>
What woman then?<br>
</p>

<p class="drama">
FIRST CLOWN.<br>
For none neither.
</p>

<p class="drama">
HAMLET.<br>
Who is to be buried in’t?<br>
</p>

<p class="drama">
FIRST CLOWN.<br>
One that was a woman, sir; but, rest her soul, she’s dead.
</p>

<p class="drama">
HAMLET.<br>
How absolute the knave is! We must speak by the card, or equivocation will undo
us. By the Lord, Horatio, these three years I have taken note of it, the age is
grown so picked that the toe of the peasant comes so near the heel of the
courtier he galls his kibe.—How long hast thou been a grave-maker?
</p>

<p class="drama">
FIRST CLOWN.<br>
Of all the days i’ th’ year, I came to’t that day that our last King Hamlet
o’ercame Fortinbras.
</p>

<p class="drama">
HAMLET.<br>
How long is that since?<br>
</p>

<p class="drama">
FIRST CLOWN.<br>
Cannot you tell that? Every fool can tell that. It was the very day that young
Hamlet was born,—he that is mad, and sent into England.
</p>

<p class="drama">
HAMLET.<br>
Ay, marry, why was he sent into England?<br>
</p>

<p class="drama">
FIRST CLOWN.<br>
Why, because he was mad; he shall recover his wits there; or if he do not, it’s
no great matter there.
</p>

<p class="drama">
HAMLET.<br>
Why?<br>
</p>

<p class="drama">
FIRST CLOWN.<br>
’Twill not be seen in him there; there the men are as mad as he.
</p>

<p class="drama">
HAMLET.<br>
How came he mad?<br>
</p>

<p class="drama">
FIRST CLOWN.<br>
Very strangely, they say.
</p>

<p class="drama">
HAMLET.<br>
How strangely?<br>
</p>

<p class="drama">
FIRST CLOWN.<br>
Faith, e’en with losing his wits.
</p>

<p class="drama">
HAMLET.<br>
Upon what ground?<br>
</p>

<p class="drama">
FIRST CLOWN.<br>
Why, here in Denmark. I have been sexton here, man and boy, thirty years.
</p>

<p class="drama">
HAMLET.<br>
How long will a man lie i’ th’earth ere he rot?<br>
</p>

<p class="drama">
FIRST CLOWN.<br>
Faith, if he be not rotten before he die,—as we have many pocky corses nowadays
that will scarce hold the laying in,—he will last you some eight year or nine
year. A tanner will last you nine year.
</p>

<p class="drama">
HAMLET.<br>
Why he more than another?<br>
</p>

<p class="drama">
FIRST CLOWN.<br>
Why, sir, his hide is so tann’d with his trade that he will keep out water a
great while. And your water is a sore decayer of your whoreson dead body.
Here’s a skull now; this skull hath lain in the earth three-and-twenty years.
</p>

<p class="drama">
HAMLET.<br>
Whose was it?<br>
</p>

<p class="drama">
FIRST CLOWN.<br>
A whoreson, mad fellow’s it was. Whose do you think it was?
</p>

<p class="drama">
HAMLET.<br>
Nay, I know not.<br>
</p>

<p class="drama">
FIRST CLOWN.<br>
A pestilence on him for a mad rogue! A pour’d a flagon of Rhenish on my head
once. This same skull, sir, was Yorick’s skull, the King’s jester.
</p>

<p class="drama">
HAMLET.<br>
This?<br>
</p>

<p class="drama">
FIRST CLOWN.<br>
E’en that.
</p>

<p class="drama">
HAMLET.<br>
Let me see. [<i>Takes the skull.</i>] Alas, poor Yorick. I knew him, Horatio, a
fellow of infinite jest, of most excellent fancy. He hath borne me on his back
a thousand times; and now, how abhorred in my imagination it is! My gorge rises
at it. Here hung those lips that I have kiss’d I know not how oft. Where be
your gibes now? your gambols? your songs? your flashes of merriment, that were
wont to set the table on a roar? Not one now, to mock your own grinning? Quite
chop-fallen? Now get you to my lady’s chamber, and tell her, let her paint an
inch thick, to this favour she must come. Make her laugh at that.—Prithee,
Horatio, tell me one thing.
</p>

<p class="drama">
HORATIO.<br>
What’s that, my lord?<br>
</p>

<p class="drama">
HAMLET.<br>
Dost thou think Alexander looked o’ this fashion i’ th’earth?<br>
</p>

<p class="drama">
HORATIO.<br>
E’en so.<br>
</p>

<p class="drama">
HAMLET.<br>
And smelt so? Pah!<br>
</p>

<p class="right">
[<i>Throws down the skull.</i>]
</p>

<p class="drama">
HORATIO.<br>
E’en so, my lord.<br>
</p>

<p class="drama">
HAMLET.<br>
To what base uses we may return, Horatio! Why may not imagination trace the
noble dust of Alexander till he find it stopping a bung-hole?
</p>

<p class="drama">
HORATIO.<br>
’Twere to consider too curiously to consider so.<br>
</p>

<p class="drama">
HAMLET.<br>
No, faith, not a jot. But to follow him thither with modesty enough, and
likelihood to lead it; as thus. Alexander died, Alexander was buried, Alexander
returneth into dust; the dust is earth; of earth we make loam; and why of that
loam whereto he was converted might they not stop a beer-barrel?<br>
Imperious Caesar, dead and turn’d to clay,<br>
Might stop a hole to keep the wind away.<br>
O, that that earth which kept the world in awe<br>
Should patch a wall t’expel the winter’s flaw.<br>
But soft! but soft! aside! Here comes the King.<br>
</p>

<p class="scenedesc">
Enter <span class="charname">priests, &amp;c,</span> in procession; the corpse
of <span class="charname">Ophelia, Laertes</span> and <span class="charname">Mourners</span> following; <span class="charname">King,
Queen,</span> their Trains, &amp;c.
</p>

<p class="drama">
The Queen, the courtiers. Who is that they follow?<br>
And with such maimed rites? This doth betoken<br>
The corse they follow did with desperate hand<br>
Fordo it own life. ’Twas of some estate.<br>
Couch we awhile and mark.<br>
</p>

<p class="right">
[<i>Retiring with <span class="charname">Horatio</span>.</i>]
</p>

<p class="drama">
LAERTES.<br>
What ceremony else?<br>
</p>

<p class="drama">
HAMLET.<br>
That is Laertes, a very noble youth. Mark.
</p>

<p class="drama">
LAERTES.<br>
What ceremony else?<br>
</p>

<p class="drama">
PRIEST.<br>
Her obsequies have been as far enlarg’d<br>
As we have warranties. Her death was doubtful;<br>
And but that great command o’ersways the order,<br>
She should in ground unsanctified have lodg’d<br>
Till the last trumpet. For charitable prayers,<br>
Shards, flints, and pebbles should be thrown on her.<br>
Yet here she is allowed her virgin rites,<br>
Her maiden strewments, and the bringing home<br>
Of bell and burial.<br>
</p>

<p class="drama">
LAERTES.<br>
Must there no more be done?<br>
</p>

<p class="drama">
PRIEST.<br>
No more be done.<br>
We should profane the service of the dead<br>
To sing sage requiem and such rest to her<br>
As to peace-parted souls.<br>
</p>

<p class="drama">
LAERTES.<br>
Lay her i’ th’earth,<br>
And from her fair and unpolluted flesh<br>
May violets spring. I tell thee, churlish priest,<br>
A minist’ring angel shall my sister be<br>
When thou liest howling.<br>
</p>

<p class="drama">
HAMLET.<br>
What, the fair Ophelia?<br>
</p>

<p class="drama">
QUEEN.<br>
[<i>Scattering flowers.</i>] Sweets to the sweet. Farewell.<br>
I hop’d thou shouldst have been my Hamlet’s wife;<br>
I thought thy bride-bed to have deck’d, sweet maid,<br>
And not have strew’d thy grave.<br>
</p>

<p class="drama">
LAERTES.<br>
O, treble woe<br>
Fall ten times treble on that cursed head<br>
Whose wicked deed thy most ingenious sense<br>
Depriv’d thee of. Hold off the earth a while,<br>
Till I have caught her once more in mine arms.<br>
[<i>Leaps into the grave.</i>]<br>
Now pile your dust upon the quick and dead,<br>
Till of this flat a mountain you have made,<br>
To o’ertop old Pelion or the skyish head<br>
Of blue Olympus.<br>
</p>

<p class="drama">
HAMLET.<br>
[<i>Advancing.</i>]<br>
What is he whose grief<br>
Bears such an emphasis? whose phrase of sorrow<br>
Conjures the wand’ring stars, and makes them stand<br>
Like wonder-wounded hearers? This is I,<br>
Hamlet the Dane.<br>
[<i>Leaps into the grave.</i>]<br>
</p>

<p class="drama">
LAERTES.<br>
[<i>Grappling with him.</i>] The devil take thy soul!
</p>

<p class="drama">
HAMLET.<br>
Thou pray’st not well.<br>
I prithee take thy fingers from my throat;<br>
For though I am not splenative and rash,<br>
Yet have I in me something dangerous,<br>
Which let thy wiseness fear. Away thy hand!<br>
</p>

<p class="drama">
KING.<br>
Pluck them asunder.<br>
</p>

<p class="drama">
QUEEN.<br>
Hamlet! Hamlet!<br>
</p>

<p class="drama">
All.<br>
Gentlemen!<br>
</p>

<p class="drama">
HORATIO.<br>
Good my lord, be quiet.<br>
</p>

<p class="right">
[<i>The <span class="charname">Attendants</span> part them, and they come out
of the grave.</i>]
</p>

<p class="drama">
HAMLET.<br>
Why, I will fight with him upon this theme<br>
Until my eyelids will no longer wag.<br>
</p>

<p class="drama">
QUEEN.<br>
O my son, what theme?<br>
</p>

<p class="drama">
HAMLET.<br>
I lov’d Ophelia; forty thousand brothers<br>
Could not, with all their quantity of love,<br>
Make up my sum. What wilt thou do for her?<br>
</p>

<p class="drama">
KING.<br>
O, he is mad, Laertes.<br>
</p>

<p class="drama">
QUEEN.<br>
For love of God forbear him!<br>
</p>

<p class="drama">
HAMLET.<br>
’Swounds, show me what thou’lt do:<br>
Woul’t weep? woul’t fight? woul’t fast? woul’t tear thyself?<br>
Woul’t drink up eisel? eat a crocodile?<br>
I’ll do’t. Dost thou come here to whine?<br>
To outface me with leaping in her grave?<br>
Be buried quick with her, and so will I.<br>
And if thou prate of mountains, let them throw<br>
Millions of acres on us, till our ground,<br>
Singeing his pate against the burning zone,<br>
Make Ossa like a wart. Nay, an thou’lt mouth,<br>
I’ll rant as well as thou.<br>
</p>

<p class="drama">
QUEEN.<br>
This is mere madness:<br>
And thus awhile the fit will work on him;<br>
Anon, as patient as the female dove,<br>
When that her golden couplets are disclos’d,<br>
His silence will sit drooping.<br>
</p>

<p class="drama">
HAMLET.<br>
Hear you, sir;<br>
What is the reason that you use me thus?<br>
I lov’d you ever. But it is no matter.<br>
Let Hercules himself do what he may,<br>
The cat will mew, and dog will have his day.<br>
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="drama">
KING.<br>
I pray thee, good Horatio, wait upon him.<br>
</p>

<p class="right">
[<i>Exit <span class="charname">Horatio</span>.</i>]
</p>

<p class="drama">
[<i>To Laertes</i>]<br>
Strengthen your patience in our last night’s speech;<br>
We’ll put the matter to the present push.—<br>
Good Gertrude, set some watch over your son.<br>
This grave shall have a living monument.<br>
An hour of quiet shortly shall we see;<br>
Till then in patience our proceeding be.<br>
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3><a id="sceneV_8.2"></a> <b>SCENE II. A hall in the
Castle.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Hamlet</span> and <span class="charname">Horatio</span>.
</p>

<p class="drama">
HAMLET.<br>
So much for this, sir. Now let me see the other;<br>
You do remember all the circumstance?<br>
</p>

<p class="drama">
HORATIO.<br>
Remember it, my lord!<br>
</p>

<p class="drama">
HAMLET.<br>
Sir, in my heart there was a kind of fighting<br>
That would not let me sleep. Methought I lay<br>
Worse than the mutinies in the bilboes. Rashly,<br>
And prais’d be rashness for it,—let us know,<br>
Our indiscretion sometime serves us well,<br>
When our deep plots do pall; and that should teach us<br>
There’s a divinity that shapes our ends,<br>
Rough-hew them how we will.<br>
</p>

<p class="drama">
HORATIO.<br>
That is most certain.<br>
</p>

<p class="drama">
HAMLET.<br>
Up from my cabin,<br>
My sea-gown scarf’d about me, in the dark<br>
Grop’d I to find out them; had my desire,<br>
Finger’d their packet, and in fine, withdrew<br>
To mine own room again, making so bold,<br>
My fears forgetting manners, to unseal<br>
Their grand commission; where I found, Horatio,<br>
Oh royal knavery! an exact command,<br>
Larded with many several sorts of reasons,<br>
Importing Denmark’s health, and England’s too,<br>
With ho! such bugs and goblins in my life,<br>
That on the supervise, no leisure bated,<br>
No, not to stay the grinding of the axe,<br>
My head should be struck off.<br>
</p>

<p class="drama">
HORATIO.<br>
Is’t possible?<br>
</p>

<p class="drama">
HAMLET.<br>
Here’s the commission, read it at more leisure.<br>
But wilt thou hear me how I did proceed?<br>
</p>

<p class="drama">
HORATIO.<br>
I beseech you.<br>
</p>

<p class="drama">
HAMLET.<br>
Being thus benetted round with villanies,—<br>
Or I could make a prologue to my brains,<br>
They had begun the play,—I sat me down,<br>
Devis’d a new commission, wrote it fair:<br>
I once did hold it, as our statists do,<br>
A baseness to write fair, and labour’d much<br>
How to forget that learning; but, sir, now<br>
It did me yeoman’s service. Wilt thou know<br>
The effect of what I wrote?<br>
</p>

<p class="drama">
HORATIO.<br>
Ay, good my lord.<br>
</p>

<p class="drama">
HAMLET.<br>
An earnest conjuration from the King,<br>
As England was his faithful tributary,<br>
As love between them like the palm might flourish,<br>
As peace should still her wheaten garland wear<br>
And stand a comma ’tween their amities,<br>
And many such-like ‘as’es of great charge,<br>
That on the view and know of these contents,<br>
Without debatement further, more or less,<br>
He should the bearers put to sudden death,<br>
Not shriving-time allow’d.<br>
</p>

<p class="drama">
HORATIO.<br>
How was this seal’d?<br>
</p>

<p class="drama">
HAMLET.<br>
Why, even in that was heaven ordinant.<br>
I had my father’s signet in my purse,<br>
Which was the model of that Danish seal:<br>
Folded the writ up in the form of the other,<br>
Subscrib’d it: gave’t th’impression; plac’d it safely,<br>
The changeling never known. Now, the next day<br>
Was our sea-fight, and what to this was sequent<br>
Thou know’st already.<br>
</p>

<p class="drama">
HORATIO.<br>
So Guildenstern and Rosencrantz go to’t.<br>
</p>

<p class="drama">
HAMLET.<br>
Why, man, they did make love to this employment.<br>
They are not near my conscience; their defeat<br>
Does by their own insinuation grow.<br>
’Tis dangerous when the baser nature comes<br>
Between the pass and fell incensed points<br>
Of mighty opposites.<br>
</p>

<p class="drama">
HORATIO.<br>
Why, what a king is this!<br>
</p>

<p class="drama">
HAMLET.<br>
Does it not, thinks’t thee, stand me now upon,—<br>
He that hath kill’d my king, and whor’d my mother,<br>
Popp’d in between th’election and my hopes,<br>
Thrown out his angle for my proper life,<br>
And with such cozenage—is’t not perfect conscience<br>
To quit him with this arm? And is’t not to be damn’d<br>
To let this canker of our nature come<br>
In further evil?<br>
</p>

<p class="drama">
HORATIO.<br>
It must be shortly known to him from England<br>
What is the issue of the business there.<br>
</p>

<p class="drama">
HAMLET.<br>
It will be short. The interim is mine;<br>
And a man’s life’s no more than to say ‘One’.<br>
But I am very sorry, good Horatio,<br>
That to Laertes I forgot myself;<br>
For by the image of my cause I see<br>
The portraiture of his. I’ll court his favours.<br>
But sure the bravery of his grief did put me<br>
Into a tow’ring passion.<br>
</p>

<p class="drama">
HORATIO.<br>
Peace, who comes here?<br>
</p>

<p class="scenedesc">
Enter <span class="charname">Osric</span>.
</p>

<p class="drama">
OSRIC.<br>
Your lordship is right welcome back to Denmark.<br>
</p>

<p class="drama">
HAMLET.<br>
I humbly thank you, sir. Dost know this waterfly?<br>
</p>

<p class="drama">
HORATIO.<br>
No, my good lord.<br>
</p>

<p class="drama">
HAMLET.<br>
Thy state is the more gracious; for ’tis a vice to know him. He hath much land,
and fertile; let a beast be lord of beasts, and his crib shall stand at the
king’s mess; ’tis a chough; but, as I say, spacious in the possession of dirt.
</p>

<p class="drama">
OSRIC.<br>
Sweet lord, if your lordship were at leisure, I should impart a thing to you
from his Majesty.
</p>

<p class="drama">
HAMLET.<br>
I will receive it with all diligence of spirit. Put your bonnet to his right
use; ’tis for the head.
</p>

<p class="drama">
OSRIC.<br>
I thank your lordship, ’tis very hot.<br>
</p>

<p class="drama">
HAMLET.<br>
No, believe me, ’tis very cold, the wind is northerly.<br>
</p>

<p class="drama">
OSRIC.<br>
It is indifferent cold, my lord, indeed.<br>
</p>

<p class="drama">
HAMLET.<br>
Methinks it is very sultry and hot for my complexion.<br>
</p>

<p class="drama">
OSRIC.<br>
Exceedingly, my lord; it is very sultry,—as ’twere—I cannot tell how. But, my
lord, his Majesty bade me signify to you that he has laid a great wager on your
head. Sir, this is the matter,—
</p>

<p class="drama">
HAMLET.<br>
I beseech you, remember,—
</p>

<p class="right">
[<i><span class="charname">Hamlet</span> moves him to put on his hat.</i>]
</p>

<p class="drama">
OSRIC.<br>
Nay, in good faith; for mine ease, in good faith. Sir, here is newly come to
court Laertes; believe me, an absolute gentleman, full of most excellent
differences, of very soft society and great showing. Indeed, to speak feelingly
of him, he is the card or calendar of gentry; for you shall find in him the
continent of what part a gentleman would see.
</p>

<p class="drama">
HAMLET.<br>
Sir, his definement suffers no perdition in you, though I know, to divide him
inventorially would dizzy th’arithmetic of memory, and yet but yaw neither, in
respect of his quick sail. But, in the verity of extolment, I take him to be a
soul of great article and his infusion of such dearth and rareness as, to make
true diction of him, his semblable is his mirror and who else would trace him
his umbrage, nothing more.
</p>

<p class="drama">
OSRIC.<br>
Your lordship speaks most infallibly of him.<br>
</p>

<p class="drama">
HAMLET.<br>
The concernancy, sir? Why do we wrap the gentleman in our more rawer breath?
</p>

<p class="drama">
OSRIC.<br>
Sir?<br>
</p>

<p class="drama">
HORATIO.<br>
Is’t not possible to understand in another tongue? You will do’t, sir, really.
</p>

<p class="drama">
HAMLET.<br>
What imports the nomination of this gentleman?<br>
</p>

<p class="drama">
OSRIC.<br>
Of Laertes?<br>
</p>

<p class="drama">
HORATIO.<br>
His purse is empty already, all’s golden words are spent.<br>
</p>

<p class="drama">
HAMLET.<br>
Of him, sir.<br>
</p>

<p class="drama">
OSRIC.<br>
I know you are not ignorant,—<br>
</p>

<p class="drama">
HAMLET.<br>
I would you did, sir; yet in faith if you did, it would not much approve me.
Well, sir?
</p>

<p class="drama">
OSRIC.<br>
You are not ignorant of what excellence Laertes is,—<br>
</p>

<p class="drama">
HAMLET.<br>
I dare not confess that, lest I should compare with him in excellence; but to
know a man well were to know himself.
</p>

<p class="drama">
OSRIC.<br>
I mean, sir, for his weapon; but in the imputation laid on him, by them in his
meed he’s unfellowed.
</p>

<p class="drama">
HAMLET.<br>
What’s his weapon?<br>
</p>

<p class="drama">
OSRIC.<br>
Rapier and dagger.<br>
</p>

<p class="drama">
HAMLET.<br>
That’s two of his weapons. But well.<br>
</p>

<p class="drama">
OSRIC.<br>
The King, sir, hath wager’d with him six Barbary horses, against the which he
has imponed, as I take it, six French rapiers and poniards, with their assigns,
as girdle, hangers, and so. Three of the carriages, in faith, are very dear to
fancy, very responsive to the hilts, most delicate carriages, and of very
liberal conceit.
</p>

<p class="drama">
HAMLET.<br>
What call you the carriages?<br>
</p>

<p class="drama">
HORATIO.<br>
I knew you must be edified by the margin ere you had done.<br>
</p>

<p class="drama">
OSRIC.<br>
The carriages, sir, are the hangers.<br>
</p>

<p class="drama">
HAMLET.<br>
The phrase would be more german to the matter if we could carry cannon by our
sides. I would it might be hangers till then. But on. Six Barbary horses
against six French swords, their assigns, and three liberal conceited
carriages: that’s the French bet against the Danish. Why is this all imponed,
as you call it?
</p>

<p class="drama">
OSRIC.<br>
The King, sir, hath laid that in a dozen passes between you and him, he shall
not exceed you three hits. He hath laid on twelve for nine. And it would come
to immediate trial if your lordship would vouchsafe the answer.
</p>

<p class="drama">
HAMLET.<br>
How if I answer no?<br>
</p>

<p class="drama">
OSRIC.<br>
I mean, my lord, the opposition of your person in trial.<br>
</p>

<p class="drama">
HAMLET.<br>
Sir, I will walk here in the hall. If it please his Majesty, it is the
breathing time of day with me. Let the foils be brought, the gentleman willing,
and the King hold his purpose, I will win for him if I can; if not, I will gain
nothing but my shame and the odd hits.
</p>

<p class="drama">
OSRIC.<br>
Shall I re-deliver you e’en so?<br>
</p>

<p class="drama">
HAMLET.<br>
To this effect, sir; after what flourish your nature will.<br>
</p>

<p class="drama">
OSRIC.<br>
I commend my duty to your lordship.<br>
</p>

<p class="drama">
HAMLET.<br>
Yours, yours.<br>
</p>

<p class="right">
[<i>Exit <span class="charname">Osric</span>.</i>]
</p>

<p class="drama">
He does well to commend it himself, there are no tongues else for’s turn.
</p>

<p class="drama">
HORATIO.<br>
This lapwing runs away with the shell on his head.<br>
</p>

<p class="drama">
HAMLET.<br>
He did comply with his dug before he suck’d it. Thus has he,—and many more of
the same bevy that I know the drossy age dotes on,— only got the tune of the
time and outward habit of encounter; a kind of yeasty collection, which carries
them through and through the most fanned and winnowed opinions; and do but blow
them to their trial, the bubbles are out.
</p>

<p class="scenedesc">
Enter a <span class="charname">Lord</span>.
</p>

<p class="drama">
LORD.<br>
My lord, his Majesty commended him to you by young Osric, who brings back to
him that you attend him in the hall. He sends to know if your pleasure hold to
play with Laertes or that you will take longer time.
</p>

<p class="drama">
HAMLET.<br>
I am constant to my purposes, they follow the King’s pleasure. If his fitness
speaks, mine is ready. Now or whensoever, provided I be so able as now.
</p>

<p class="drama">
LORD.<br>
The King and Queen and all are coming down.<br>
</p>

<p class="drama">
HAMLET.<br>
In happy time.<br>
</p>

<p class="drama">
LORD.<br>
The Queen desires you to use some gentle entertainment to Laertes before you
fall to play.
</p>

<p class="drama">
HAMLET.<br>
She well instructs me.<br>
</p>

<p class="right">
[<i>Exit <span class="charname">Lord</span>.</i>]
</p>

<p class="drama">
HORATIO.<br>
You will lose this wager, my lord.<br>
</p>

<p class="drama">
HAMLET.<br>
I do not think so. Since he went into France, I have been in continual
practice. I shall win at the odds. But thou wouldst not think how ill all’s
here about my heart: but it is no matter.
</p>

<p class="drama">
HORATIO.<br>
Nay, good my lord.<br>
</p>

<p class="drama">
HAMLET.<br>
It is but foolery; but it is such a kind of gain-giving as would perhaps
trouble a woman.
</p>

<p class="drama">
HORATIO.<br>
If your mind dislike anything, obey it. I will forestall their repair hither,
and say you are not fit.
</p>

<p class="drama">
HAMLET.<br>
Not a whit, we defy augury. There’s a special providence in the fall of a
sparrow. If it be now, ’tis not to come; if it be not to come, it will be now;
if it be not now, yet it will come. The readiness is all. Since no man has
aught of what he leaves, what is’t to leave betimes?
</p>

<p class="scenedesc">
Enter <span class="charname">King, Queen, Laertes, Lords, Osric</span> and
<span class="charname">Attendants</span> with foils &amp;c.
</p>

<p class="drama">
KING.<br>
Come, Hamlet, come, and take this hand from me.<br>
</p>

<p class="right">
[<i>The <span class="charname">King</span> puts <span class="charname">Laertes’s</span> hand into <span class="charname">Hamlet’s</span>.</i>]
</p>

<p class="drama">
HAMLET.<br>
Give me your pardon, sir. I have done you wrong;<br>
But pardon’t as you are a gentleman.<br>
This presence knows, and you must needs have heard,<br>
How I am punish’d with sore distraction.<br>
What I have done<br>
That might your nature, honour, and exception<br>
Roughly awake, I here proclaim was madness.<br>
Was’t Hamlet wrong’d Laertes? Never Hamlet.<br>
If Hamlet from himself be ta’en away,<br>
And when he’s not himself does wrong Laertes,<br>
Then Hamlet does it not, Hamlet denies it.<br>
Who does it, then? His madness. If’t be so,<br>
Hamlet is of the faction that is wrong’d;<br>
His madness is poor Hamlet’s enemy.<br>
Sir, in this audience,<br>
Let my disclaiming from a purpos’d evil<br>
Free me so far in your most generous thoughts<br>
That I have shot my arrow o’er the house<br>
And hurt my brother.<br>
</p>

<p class="drama">
LAERTES.<br>
I am satisfied in nature,<br>
Whose motive in this case should stir me most<br>
To my revenge. But in my terms of honour<br>
I stand aloof, and will no reconcilement<br>
Till by some elder masters of known honour<br>
I have a voice and precedent of peace<br>
To keep my name ungor’d. But till that time<br>
I do receive your offer’d love like love,<br>
And will not wrong it.<br>
</p>

<p class="drama">
HAMLET.<br>
I embrace it freely,<br>
And will this brother’s wager frankly play.—<br>
Give us the foils; come on.<br>
</p>

<p class="drama">
LAERTES.<br>
Come, one for me.<br>
</p>

<p class="drama">
HAMLET.<br>
I’ll be your foil, Laertes; in mine ignorance<br>
Your skill shall like a star i’ th’ darkest night,<br>
Stick fiery off indeed.<br>
</p>

<p class="drama">
LAERTES.<br>
You mock me, sir.<br>
</p>

<p class="drama">
HAMLET.<br>
No, by this hand.<br>
</p>

<p class="drama">
KING.<br>
Give them the foils, young Osric. Cousin Hamlet,<br>
You know the wager?<br>
</p>

<p class="drama">
HAMLET.<br>
Very well, my lord.<br>
Your Grace has laid the odds o’ the weaker side.<br>
</p>

<p class="drama">
KING.<br>
I do not fear it. I have seen you both;<br>
But since he is better’d, we have therefore odds.<br>
</p>

<p class="drama">
LAERTES.<br>
This is too heavy. Let me see another.<br>
</p>

<p class="drama">
HAMLET.<br>
This likes me well. These foils have all a length?<br>
</p>

<p class="right">
[<i>They prepare to play.</i>]
</p>

<p class="drama">
OSRIC.<br>
Ay, my good lord.<br>
</p>

<p class="drama">
KING.<br>
Set me the stoups of wine upon that table.<br>
If Hamlet give the first or second hit,<br>
Or quit in answer of the third exchange,<br>
Let all the battlements their ordnance fire;<br>
The King shall drink to Hamlet’s better breath,<br>
And in the cup an union shall he throw<br>
Richer than that which four successive kings<br>
In Denmark’s crown have worn. Give me the cups;<br>
And let the kettle to the trumpet speak,<br>
The trumpet to the cannoneer without,<br>
The cannons to the heavens, the heavens to earth,<br>
‘Now the King drinks to Hamlet.’ Come, begin.<br>
And you, the judges, bear a wary eye.<br>
</p>

<p class="drama">
HAMLET.<br>
Come on, sir.<br>
</p>

<p class="drama">
LAERTES.<br>
Come, my lord.<br>
</p>

<p class="right">
[<i>They play.</i>]
</p>

<p class="drama">
HAMLET.<br>
One.<br>
</p>

<p class="drama">
LAERTES.<br>
No.<br>
</p>

<p class="drama">
HAMLET.<br>
Judgement.<br>
</p>

<p class="drama">
OSRIC.<br>
A hit, a very palpable hit.<br>
</p>

<p class="drama">
LAERTES.<br>
Well; again.<br>
</p>

<p class="drama">
KING.<br>
Stay, give me drink. Hamlet, this pearl is thine;<br>
Here’s to thy health.<br>
</p>

<p class="right">
[<i>Trumpets sound, and cannon shot off within.</i>]
</p>

<p class="drama">
Give him the cup.
</p>

<p class="drama">
HAMLET.<br>
I’ll play this bout first; set it by awhile.
</p>

<p class="right">
[<i>They play.</i>]
</p>

<p class="drama">
Come. Another hit; what say you?<br>
</p>

<p class="drama">
LAERTES.<br>
A touch, a touch, I do confess.<br>
</p>

<p class="drama">
KING.<br>
Our son shall win.<br>
</p>

<p class="drama">
QUEEN.<br>
He’s fat, and scant of breath.<br>
Here, Hamlet, take my napkin, rub thy brows.<br>
The Queen carouses to thy fortune, Hamlet.<br>
</p>

<p class="drama">
HAMLET.<br>
Good madam.<br>
</p>

<p class="drama">
KING.<br>
Gertrude, do not drink.<br>
</p>

<p class="drama">
QUEEN.<br>
I will, my lord; I pray you pardon me.<br>
</p>

<p class="drama">
KING.<br>
[<i>Aside.</i>] It is the poison’d cup; it is too late.<br>
</p>

<p class="drama">
HAMLET.<br>
I dare not drink yet, madam. By and by.<br>
</p>

<p class="drama">
QUEEN.<br>
Come, let me wipe thy face.<br>
</p>

<p class="drama">
LAERTES.<br>
My lord, I’ll hit him now.<br>
</p>

<p class="drama">
KING.<br>
I do not think’t.<br>
</p>

<p class="drama">
LAERTES.<br>
[<i>Aside.</i>] And yet ’tis almost ’gainst my conscience.<br>
</p>

<p class="drama">
HAMLET.<br>
Come for the third, Laertes. You do but dally.<br>
I pray you pass with your best violence.<br>
I am afeard you make a wanton of me.<br>
</p>

<p class="drama">
LAERTES.<br>
Say you so? Come on.<br>
</p>

<p class="right">
[<i>They play.</i>]
</p>

<p class="drama">
OSRIC.<br>
Nothing neither way.<br>
</p>

<p class="drama">
LAERTES.<br>
Have at you now.<br>
</p>

<p class="right">
[<i><span class="charname">Laertes</span> wounds <span class="charname">Hamlet;</span> then, in scuffling, they change rapiers, and
<span class="charname">Hamlet</span> wounds <span class="charname">Laertes</span>.</i>]
</p>

<p class="drama">
KING.<br>
Part them; they are incens’d.<br>
</p>

<p class="drama">
HAMLET.<br>
Nay, come again!<br>
</p>

<p class="right">
[<i>The <span class="charname">Queen</span> falls.</i>]
</p>

<p class="drama">
OSRIC.<br>
Look to the Queen there, ho!<br>
</p>

<p class="drama">
HORATIO.<br>
They bleed on both sides. How is it, my lord?<br>
</p>

<p class="drama">
OSRIC.<br>
How is’t, Laertes?<br>
</p>

<p class="drama">
LAERTES.<br>
Why, as a woodcock to my own springe, Osric.<br>
I am justly kill’d with mine own treachery.<br>
</p>

<p class="drama">
HAMLET.<br>
How does the Queen?<br>
</p>

<p class="drama">
KING.<br>
She swoons to see them bleed.<br>
</p>

<p class="drama">
QUEEN.<br>
No, no, the drink, the drink! O my dear Hamlet!<br>
The drink, the drink! I am poison’d.<br>
</p>

<p class="right">
[<i>Dies.</i>]
</p>

<p class="drama">
HAMLET.<br>
O villany! Ho! Let the door be lock’d:<br>
Treachery! Seek it out.<br>
</p>

<p class="right">
[<i><span class="charname">Laertes</span> falls.</i>]
</p>

<p class="drama">
LAERTES.<br>
It is here, Hamlet. Hamlet, thou art slain.<br>
No medicine in the world can do thee good.<br>
In thee there is not half an hour of life;<br>
The treacherous instrument is in thy hand,<br>
Unbated and envenom’d. The foul practice<br>
Hath turn’d itself on me. Lo, here I lie,<br>
Never to rise again. Thy mother’s poison’d.<br>
I can no more. The King, the King’s to blame.<br>
</p>

<p class="drama">
HAMLET.<br>
The point envenom’d too!<br>
Then, venom, to thy work.<br>
</p>

<p class="right">
[<i>Stabs the <span class="charname">King</span>.</i>]
</p>

<p class="drama">
OSRIC and LORDS.<br>
Treason! treason!<br>
</p>

<p class="drama">
KING.<br>
O yet defend me, friends. I am but hurt.<br>
</p>

<p class="drama">
HAMLET.<br>
Here, thou incestuous, murderous, damned Dane,<br>
Drink off this potion. Is thy union here?<br>
Follow my mother.<br>
</p>

<p class="right">
[<i><span class="charname">King</span> dies.</i>]
</p>

<p class="drama">
LAERTES.<br>
He is justly serv’d.<br>
It is a poison temper’d by himself.<br>
Exchange forgiveness with me, noble Hamlet.<br>
Mine and my father’s death come not upon thee,<br>
Nor thine on me.<br>
</p>

<p class="right">
[<i>Dies.</i>]
</p>

<p class="drama">
HAMLET.<br>
Heaven make thee free of it! I follow thee.<br>
I am dead, Horatio. Wretched Queen, adieu.<br>
You that look pale and tremble at this chance,<br>
That are but mutes or audience to this act,<br>
Had I but time,—as this fell sergeant, death,<br>
Is strict in his arrest,—O, I could tell you,—<br>
But let it be. Horatio, I am dead,<br>
Thou liv’st; report me and my cause aright<br>
To the unsatisfied.<br>
</p>

<p class="drama">
HORATIO.<br>
Never believe it.<br>
I am more an antique Roman than a Dane.<br>
Here’s yet some liquor left.<br>
</p>

<p class="drama">
HAMLET.<br>
As th’art a man,<br>
Give me the cup. Let go; by Heaven, I’ll have’t.<br>
O good Horatio, what a wounded name,<br>
Things standing thus unknown, shall live behind me.<br>
If thou didst ever hold me in thy heart,<br>
Absent thee from felicity awhile,<br>
And in this harsh world draw thy breath in pain,<br>
To tell my story.<br>
</p>

<p class="right">
[<i>March afar off, and shot within.</i>]
</p>

<p class="drama">
What warlike noise is this?
</p>

<p class="drama">
OSRIC.<br>
Young Fortinbras, with conquest come from Poland,<br>
To the ambassadors of England gives<br>
This warlike volley.<br>
</p>

<p class="drama">
HAMLET.<br>
O, I die, Horatio.<br>
The potent poison quite o’er-crows my spirit:<br>
I cannot live to hear the news from England,<br>
But I do prophesy th’election lights<br>
On Fortinbras. He has my dying voice.<br>
So tell him, with the occurrents more and less,<br>
Which have solicited. The rest is silence.<br>
</p>

<p class="right">
[<i>Dies.</i>]
</p>

<p class="drama">
HORATIO.<br>
Now cracks a noble heart. Good night, sweet prince,<br>
And flights of angels sing thee to thy rest.<br>
Why does the drum come hither?<br>
</p>

<p class="right">
[<i>March within.</i>]
</p>

<p class="scenedesc">
Enter <span class="charname">Fortinbras, the English Ambassadors</span> and
others.
</p>

<p class="drama">
FORTINBRAS.<br>
Where is this sight?<br>
</p>

<p class="drama">
HORATIO.<br>
What is it you would see?<br>
If aught of woe or wonder, cease your search.<br>
</p>

<p class="drama">
FORTINBRAS.<br>
This quarry cries on havoc. O proud death,<br>
What feast is toward in thine eternal cell,<br>
That thou so many princes at a shot<br>
So bloodily hast struck?<br>
</p>

<p class="drama">
FIRST AMBASSADOR.<br>
The sight is dismal;<br>
And our affairs from England come too late.<br>
The ears are senseless that should give us hearing,<br>
To tell him his commandment is fulfill’d,<br>
That Rosencrantz and Guildenstern are dead.<br>
Where should we have our thanks?<br>
</p>

<p class="drama">
HORATIO.<br>
Not from his mouth,<br>
Had it th’ability of life to thank you.<br>
He never gave commandment for their death.<br>
But since, so jump upon this bloody question,<br>
You from the Polack wars, and you from England<br>
Are here arriv’d, give order that these bodies<br>
High on a stage be placed to the view,<br>
And let me speak to th’ yet unknowing world<br>
How these things came about. So shall you hear<br>
Of carnal, bloody and unnatural acts,<br>
Of accidental judgements, casual slaughters,<br>
Of deaths put on by cunning and forc’d cause,<br>
And, in this upshot, purposes mistook<br>
Fall’n on the inventors’ heads. All this can I<br>
Truly deliver.<br>
</p>

<p class="drama">
FORTINBRAS.<br>
Let us haste to hear it,<br>
And call the noblest to the audience.<br>
For me, with sorrow I embrace my fortune.<br>
I have some rights of memory in this kingdom,<br>
Which now to claim my vantage doth invite me.<br>
</p>

<p class="drama">
HORATIO.<br>
Of that I shall have also cause to speak,<br>
And from his mouth whose voice will draw on more.<br>
But let this same be presently perform’d,<br>
Even while men’s minds are wild, lest more mischance<br>
On plots and errors happen.<br>
</p>

<p class="drama">
FORTINBRAS.<br>
Let four captains<br>
Bear Hamlet like a soldier to the stage,<br>
For he was likely, had he been put on,<br>
To have prov’d most royally; and for his passage,<br>
The soldiers’ music and the rites of war<br>
Speak loudly for him.<br>
Take up the bodies. Such a sight as this<br>
Becomes the field, but here shows much amiss.<br>
Go, bid the soldiers shoot.<br>
</p>

<p class="right">
[<i>A dead march.</i>]
</p>

<p class="right">
[<i>Exeunt, bearing off the bodies, after which a peal of ordnance is shot
off.</i>]
</p>

