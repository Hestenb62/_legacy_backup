<h2> <a id="sceneIII_17.1"></a><b>ACT III</b></h2>

<h3> <b>SCENE I. Rome. Before the Capitol; the Senate sitting.</b></h3>

<p class="scenedesc">
A crowd of people in the street leading to the Capitol. Flourish. Enter <span class="charname">Caesar, Brutus, Cassius, Casca, Decius, Metellus, Trebonius,
Cinna, Antony, Lepidus, Artemidorus, Publius, Popilius</span> and the <span class="charname">Soothsayer</span>.
</p>

<p class="drama">
CAESAR.<br>
The Ides of March are come.
</p>

<p class="drama">
SOOTHSAYER.<br>
Ay, Caesar; but not gone.
</p>

<p class="drama">
ARTEMIDORUS.<br>
Hail, Caesar! Read this schedule.
</p>

<p class="drama">
DECIUS.<br>
Trebonius doth desire you to o’er-read,<br>
At your best leisure, this his humble suit.
</p>

<p class="drama">
ARTEMIDORUS.<br>
O Caesar, read mine first; for mine’s a suit<br>
That touches Caesar nearer. Read it, great Caesar.
</p>

<p class="drama">
CAESAR.<br>
What touches us ourself shall be last serv’d.
</p>

<p class="drama">
ARTEMIDORUS.<br>
Delay not, Caesar. Read it instantly.
</p>

<p class="drama">
CAESAR.<br>
What, is the fellow mad?
</p>

<p class="drama">
PUBLIUS.<br>
Sirrah, give place.
</p>

<p class="drama">
CASSIUS.<br>
What, urge you your petitions in the street?<br>
Come to the Capitol.
</p>

<p class="scenedesc">
<span class="charname">Caesar</span> enters the Capitol, the rest following.
All the Senators rise.
</p>

<p class="drama">
POPILIUS.<br>
I wish your enterprise today may thrive.
</p>

<p class="drama">
CASSIUS.<br>
What enterprise, Popilius?
</p>

<p class="drama">
POPILIUS.<br>
Fare you well.
</p>

<p class="right">
[<i>Advances to <span class="charname">Caesar</span>.</i>]
</p>

<p class="drama">
BRUTUS.<br>
What said Popilius Lena?
</p>

<p class="drama">
CASSIUS.<br>
He wish’d today our enterprise might thrive.<br>
I fear our purpose is discovered.
</p>

<p class="drama">
BRUTUS.<br>
Look how he makes to Caesar: mark him.
</p>

<p class="drama">
CASSIUS.<br>
Casca, be sudden, for we fear prevention.<br>
Brutus, what shall be done? If this be known,<br>
Cassius or Caesar never shall turn back,<br>
For I will slay myself.
</p>

<p class="drama">
BRUTUS.<br>
Cassius, be constant:<br>
Popilius Lena speaks not of our purposes;<br>
For look, he smiles, and Caesar doth not change.
</p>

<p class="drama">
CASSIUS.<br>
Trebonius knows his time, for look you, Brutus,<br>
He draws Mark Antony out of the way.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Antony</span> and <span class="charname">Trebonius. Caesar</span> and the Senators take their
seats.</i>]
</p>

<p class="drama">
DECIUS.<br>
Where is Metellus Cimber? Let him go,<br>
And presently prefer his suit to Caesar.
</p>

<p class="drama">
BRUTUS.<br>
He is address’d; press near and second him.
</p>

<p class="drama">
CINNA.<br>
Casca, you are the first that rears your hand.
</p>

<p class="drama">
CAESAR.<br>
Are we all ready? What is now amiss<br>
That Caesar and his Senate must redress?
</p>

<p class="drama">
METELLUS.<br>
Most high, most mighty, and most puissant Caesar,<br>
Metellus Cimber throws before thy seat<br>
An humble heart.
</p>

<p class="right">
[<i>Kneeling.</i>]
</p>

<p class="drama">
CAESAR.<br>
I must prevent thee, Cimber.<br>
These couchings and these lowly courtesies<br>
Might fire the blood of ordinary men,<br>
And turn pre-ordinance and first decree<br>
Into the law of children. Be not fond,<br>
To think that Caesar bears such rebel blood<br>
That will be thaw’d from the true quality<br>
With that which melteth fools; I mean sweet words,<br>
Low-crooked curtsies, and base spaniel fawning.<br>
Thy brother by decree is banished:<br>
If thou dost bend, and pray, and fawn for him,<br>
I spurn thee like a cur out of my way.<br>
Know, Caesar dost not wrong, nor without cause<br>
Will he be satisfied.
</p>

<p class="drama">
METELLUS.<br>
Is there no voice more worthy than my own,<br>
To sound more sweetly in great Caesar’s ear<br>
For the repealing of my banish’d brother?
</p>

<p class="drama">
BRUTUS.<br>
I kiss thy hand, but not in flattery, Caesar;<br>
Desiring thee that Publius Cimber may<br>
Have an immediate freedom of repeal.
</p>

<p class="drama">
CAESAR.<br>
What, Brutus?
</p>

<p class="drama">
CASSIUS.<br>
Pardon, Caesar; Caesar, pardon:<br>
As low as to thy foot doth Cassius fall,<br>
To beg enfranchisement for Publius Cimber.
</p>

<p class="drama">
CAESAR.<br>
I could be well mov’d, if I were as you;<br>
If I could pray to move, prayers would move me:<br>
But I am constant as the northern star,<br>
Of whose true-fix’d and resting quality<br>
There is no fellow in the firmament.<br>
The skies are painted with unnumber’d sparks,<br>
They are all fire, and every one doth shine;<br>
But there’s but one in all doth hold his place.<br>
So in the world; ’tis furnish’d well with men,<br>
And men are flesh and blood, and apprehensive;<br>
Yet in the number I do know but one<br>
That unassailable holds on his rank,<br>
Unshak’d of motion: and that I am he,<br>
Let me a little show it, even in this,<br>
That I was constant Cimber should be banish’d,<br>
And constant do remain to keep him so.
</p>

<p class="drama">
CINNA.<br>
O Caesar,—
</p>

<p class="drama">
CAESAR.<br>
Hence! wilt thou lift up Olympus?
</p>

<p class="drama">
DECIUS.<br>
Great Caesar,—
</p>

<p class="drama">
CAESAR.<br>
Doth not Brutus bootless kneel?
</p>

<p class="drama">
CASCA.<br>
Speak, hands, for me!
</p>

<p class="right">
[<i><span class="charname">Casca</span> stabs <span class="charname">Caesar</span> in the neck. <span class="charname">Caesar</span> catches hold of his arm. He is then stabbed by
several other Conspirators, and at last by <span class="charname">Marcus
Brutus</span>.</i>]
</p>

<p class="drama">
CAESAR.<br>
<i>Et tu, Brute?</i>—Then fall, Caesar!
</p>

<p class="right">
[<i>Dies. The Senators and People retire in confusion.</i>]
</p>

<p class="drama">
CINNA.<br>
Liberty! Freedom! Tyranny is dead!<br>
Run hence, proclaim, cry it about the streets.
</p>

<p class="drama">
CASSIUS.<br>
Some to the common pulpits and cry out,<br>
“Liberty, freedom, and enfranchisement!”
</p>

<p class="drama">
BRUTUS.<br>
People and Senators, be not affrighted.<br>
Fly not; stand still; ambition’s debt is paid.
</p>

<p class="drama">
CASCA.<br>
Go to the pulpit, Brutus.
</p>

<p class="drama">
DECIUS.<br>
And Cassius too.
</p>

<p class="drama">
BRUTUS.<br>
Where’s Publius?
</p>

<p class="drama">
CINNA.<br>
Here, quite confounded with this mutiny.
</p>

<p class="drama">
METELLUS.<br>
Stand fast together, lest some friend of Caesar’s<br>
Should chance—
</p>

<p class="drama">
BRUTUS.<br>
Talk not of standing. Publius, good cheer!<br>
There is no harm intended to your person,<br>
Nor to no Roman else. So tell them, Publius.
</p>

<p class="drama">
CASSIUS.<br>
And leave us, Publius; lest that the people<br>
Rushing on us, should do your age some mischief.
</p>

<p class="drama">
BRUTUS.<br>
Do so; and let no man abide this deed<br>
But we the doers.
</p>

<p class="scenedesc">
Enter <span class="charname">Trebonius</span>.
</p>

<p class="drama">
CASSIUS.<br>
Where’s Antony?
</p>

<p class="drama">
TREBONIUS.<br>
Fled to his house amaz’d.<br>
Men, wives, and children stare, cry out, and run,<br>
As it were doomsday.
</p>

<p class="drama">
BRUTUS.<br>
Fates, we will know your pleasures.<br>
That we shall die, we know; ’tis but the time<br>
And drawing days out, that men stand upon.
</p>

<p class="drama">
CASCA.<br>
Why, he that cuts off twenty years of life<br>
Cuts off so many years of fearing death.
</p>

<p class="drama">
BRUTUS.<br>
Grant that, and then is death a benefit:<br>
So are we Caesar’s friends, that have abridg’d<br>
His time of fearing death. Stoop, Romans, stoop,<br>
And let us bathe our hands in Caesar’s blood<br>
Up to the elbows, and besmear our swords:<br>
Then walk we forth, even to the market-place,<br>
And waving our red weapons o’er our heads,<br>
Let’s all cry, “Peace, freedom, and liberty!”
</p>

<p class="drama">
CASSIUS.<br>
Stoop then, and wash. How many ages hence<br>
Shall this our lofty scene be acted over<br>
In States unborn, and accents yet unknown!
</p>

<p class="drama">
BRUTUS.<br>
How many times shall Caesar bleed in sport,<br>
That now on Pompey’s basis lies along,<br>
No worthier than the dust!
</p>

<p class="drama">
CASSIUS.<br>
So oft as that shall be,<br>
So often shall the knot of us be call’d<br>
The men that gave their country liberty.
</p>

<p class="drama">
DECIUS.<br>
What, shall we forth?
</p>

<p class="drama">
CASSIUS.<br>
Ay, every man away.<br>
Brutus shall lead; and we will grace his heels<br>
With the most boldest and best hearts of Rome.
</p>

<p class="scenedesc">
Enter a <span class="charname">Servant</span>.
</p>

<p class="drama">
BRUTUS.<br>
Soft, who comes here? A friend of Antony’s.
</p>

<p class="drama">
SERVANT.<br>
Thus, Brutus, did my master bid me kneel;<br>
Thus did Mark Antony bid me fall down;<br>
And, being prostrate, thus he bade me say:<br>
Brutus is noble, wise, valiant, and honest;<br>
Caesar was mighty, bold, royal, and loving;<br>
Say I love Brutus and I honour him;<br>
Say I fear’d Caesar, honour’d him, and lov’d him.<br>
If Brutus will vouchsafe that Antony<br>
May safely come to him, and be resolv’d<br>
How Caesar hath deserv’d to lie in death,<br>
Mark Antony shall not love Caesar dead<br>
So well as Brutus living; but will follow<br>
The fortunes and affairs of noble Brutus<br>
Thorough the hazards of this untrod state,<br>
With all true faith. So says my master Antony.
</p>

<p class="drama">
BRUTUS.<br>
Thy master is a wise and valiant Roman;<br>
I never thought him worse.<br>
Tell him, so please him come unto this place,<br>
He shall be satisfied and, by my honour,<br>
Depart untouch’d.
</p>

<p class="drama">
SERVANT.<br>
I’ll fetch him presently.
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="drama">
BRUTUS.<br>
I know that we shall have him well to friend.
</p>

<p class="drama">
CASSIUS.<br>
I wish we may: but yet have I a mind<br>
That fears him much; and my misgiving still<br>
Falls shrewdly to the purpose.
</p>

<p class="scenedesc">
Enter <span class="charname">Antony</span>.
</p>

<p class="drama">
BRUTUS.<br>
But here comes Antony. Welcome, Mark Antony.
</p>

<p class="drama">
ANTONY.<br>
O mighty Caesar! Dost thou lie so low?<br>
Are all thy conquests, glories, triumphs, spoils,<br>
Shrunk to this little measure? Fare thee well.<br>
I know not, gentlemen, what you intend,<br>
Who else must be let blood, who else is rank:<br>
If I myself, there is no hour so fit<br>
As Caesar’s death’s hour; nor no instrument<br>
Of half that worth as those your swords, made rich<br>
With the most noble blood of all this world.<br>
I do beseech ye, if you bear me hard,<br>
Now, whilst your purpled hands do reek and smoke,<br>
Fulfill your pleasure. Live a thousand years,<br>
I shall not find myself so apt to die.<br>
No place will please me so, no means of death,<br>
As here by Caesar, and by you cut off,<br>
The choice and master spirits of this age.
</p>

<p class="drama">
BRUTUS.<br>
O Antony, beg not your death of us.<br>
Though now we must appear bloody and cruel,<br>
As by our hands and this our present act<br>
You see we do; yet see you but our hands<br>
And this the bleeding business they have done.<br>
Our hearts you see not; they are pitiful;<br>
And pity to the general wrong of Rome—<br>
As fire drives out fire, so pity pity—<br>
Hath done this deed on Caesar. For your part,<br>
To you our swords have leaden points, Mark Antony;<br>
Our arms in strength of malice, and our hearts<br>
Of brothers’ temper, do receive you in<br>
With all kind love, good thoughts, and reverence.
</p>

<p class="drama">
CASSIUS.<br>
Your voice shall be as strong as any man’s<br>
In the disposing of new dignities.
</p>

<p class="drama">
BRUTUS.<br>
Only be patient till we have appeas’d<br>
The multitude, beside themselves with fear,<br>
And then we will deliver you the cause<br>
Why I, that did love Caesar when I struck him,<br>
Have thus proceeded.
</p>

<p class="drama">
ANTONY.<br>
I doubt not of your wisdom.<br>
Let each man render me his bloody hand.<br>
First, Marcus Brutus, will I shake with you;<br>
Next, Caius Cassius, do I take your hand.<br>
Now, Decius Brutus, yours; now yours, Metellus;<br>
Yours, Cinna; and, my valiant Casca, yours;<br>
Though last, not least in love, yours, good Trebonius.<br>
Gentlemen all—alas, what shall I say?<br>
My credit now stands on such slippery ground,<br>
That one of two bad ways you must conceit me,<br>
Either a coward or a flatterer.<br>
That I did love thee, Caesar, O, ’tis true:<br>
If then thy spirit look upon us now,<br>
Shall it not grieve thee dearer than thy death,<br>
To see thy Antony making his peace,<br>
Shaking the bloody fingers of thy foes,<br>
Most noble, in the presence of thy corse?<br>
Had I as many eyes as thou hast wounds,<br>
Weeping as fast as they stream forth thy blood,<br>
It would become me better than to close<br>
In terms of friendship with thine enemies.<br>
Pardon me, Julius! Here wast thou bay’d, brave hart;<br>
Here didst thou fall; and here thy hunters stand,<br>
Sign’d in thy spoil, and crimson’d in thy lethe.<br>
O world, thou wast the forest to this hart;<br>
And this indeed, O world, the heart of thee.<br>
How like a deer strucken by many princes,<br>
Dost thou here lie!
</p>

<p class="drama">
CASSIUS.<br>
Mark Antony,—
</p>

<p class="drama">
ANTONY.<br>
Pardon me, Caius Cassius:<br>
The enemies of Caesar shall say this;<br>
Then, in a friend, it is cold modesty.
</p>

<p class="drama">
CASSIUS.<br>
I blame you not for praising Caesar so;<br>
But what compact mean you to have with us?<br>
Will you be prick’d in number of our friends,<br>
Or shall we on, and not depend on you?
</p>

<p class="drama">
ANTONY.<br>
Therefore I took your hands; but was indeed<br>
Sway’d from the point, by looking down on Caesar.<br>
Friends am I with you all, and love you all,<br>
Upon this hope, that you shall give me reasons<br>
Why, and wherein, Caesar was dangerous.
</p>

<p class="drama">
BRUTUS.<br>
Or else were this a savage spectacle.<br>
Our reasons are so full of good regard<br>
That were you, Antony, the son of Caesar,<br>
You should be satisfied.
</p>

<p class="drama">
ANTONY.<br>
That’s all I seek,<br>
And am moreover suitor that I may<br>
Produce his body to the market-place;<br>
And in the pulpit, as becomes a friend,<br>
Speak in the order of his funeral.
</p>

<p class="drama">
BRUTUS.<br>
You shall, Mark Antony.
</p>

<p class="drama">
CASSIUS.<br>
Brutus, a word with you.<br>
[<i>Aside to Brutus.</i>] You know not what you do. Do not consent<br>
That Antony speak in his funeral.<br>
Know you how much the people may be mov’d<br>
By that which he will utter?
</p>

<p class="drama">
BRUTUS.<br>
[<i>Aside to Cassius.</i>] By your pardon:<br>
I will myself into the pulpit first,<br>
And show the reason of our Caesar’s death.<br>
What Antony shall speak, I will protest<br>
He speaks by leave and by permission;<br>
And that we are contented Caesar shall<br>
Have all true rights and lawful ceremonies.<br>
It shall advantage more than do us wrong.
</p>

<p class="drama">
CASSIUS.<br>
[<i>Aside to Brutus.</i>] I know not what may fall; I like it not.
</p>

<p class="drama">
BRUTUS.<br>
Mark Antony, here, take you Caesar’s body.<br>
You shall not in your funeral speech blame us,<br>
But speak all good you can devise of Caesar,<br>
And say you do’t by our permission;<br>
Else shall you not have any hand at all<br>
About his funeral. And you shall speak<br>
In the same pulpit whereto I am going,<br>
After my speech is ended.
</p>

<p class="drama">
ANTONY.<br>
Be it so;<br>
I do desire no more.
</p>

<p class="drama">
BRUTUS.<br>
Prepare the body, then, and follow us.
</p>

<p class="right">
[<i>Exeunt all but <span class="charname">Antony</span>.</i>]
</p>

<p class="drama">
ANTONY.<br>
O, pardon me, thou bleeding piece of earth,<br>
That I am meek and gentle with these butchers.<br>
Thou art the ruins of the noblest man<br>
That ever lived in the tide of times.<br>
Woe to the hand that shed this costly blood!<br>
Over thy wounds now do I prophesy,<br>
Which, like dumb mouths do ope their ruby lips<br>
To beg the voice and utterance of my tongue,<br>
A curse shall light upon the limbs of men;<br>
Domestic fury and fierce civil strife<br>
Shall cumber all the parts of Italy;<br>
Blood and destruction shall be so in use,<br>
And dreadful objects so familiar,<br>
That mothers shall but smile when they behold<br>
Their infants quartered with the hands of war;<br>
All pity chok’d with custom of fell deeds:<br>
And Caesar’s spirit, ranging for revenge,<br>
With Ate by his side come hot from Hell,<br>
Shall in these confines with a monarch’s voice<br>
Cry havoc and let slip the dogs of war,<br>
That this foul deed shall smell above the earth<br>
With carrion men, groaning for burial.
</p>

<p class="scenedesc">
Enter a <span class="charname">Servant</span>.
</p>

<p class="drama">
You serve Octavius Caesar, do you not?
</p>

<p class="drama">
SERVANT.<br>
I do, Mark Antony.
</p>

<p class="drama">
ANTONY.<br>
Caesar did write for him to come to Rome.
</p>

<p class="drama">
SERVANT.<br>
He did receive his letters, and is coming,<br>
And bid me say to you by word of mouth,—<br>
[<i>Seeing the body.</i>] O Caesar!
</p>

<p class="drama">
ANTONY.<br>
Thy heart is big, get thee apart and weep.<br>
Passion, I see, is catching; for mine eyes,<br>
Seeing those beads of sorrow stand in thine,<br>
Began to water. Is thy master coming?
</p>

<p class="drama">
SERVANT.<br>
He lies tonight within seven leagues of Rome.
</p>

<p class="drama">
ANTONY.<br>
Post back with speed, and tell him what hath chanc’d.<br>
Here is a mourning Rome, a dangerous Rome,<br>
No Rome of safety for Octavius yet.<br>
Hie hence, and tell him so. Yet stay awhile;<br>
Thou shalt not back till I have borne this corse<br>
Into the market-place: there shall I try,<br>
In my oration, how the people take<br>
The cruel issue of these bloody men;<br>
According to the which thou shalt discourse<br>
To young Octavius of the state of things.<br>
Lend me your hand.
</p>

<p class="right">
[<i>Exeunt with <span class="charname">Caesar’s</span> body.</i>]
</p>

<h3> <a id="sceneIII_17.2"></a><b>SCENE II. The same. The Forum.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Brutus</span> and goes into the pulpit, and <span class="charname">Cassius</span>, with a throng of <span class="charname">Citizens</span>.
</p>

<p class="drama">
CITIZENS.<br>
We will be satisfied; let us be satisfied.
</p>

<p class="drama">
BRUTUS.<br>
Then follow me, and give me audience, friends.<br>
Cassius, go you into the other street<br>
And part the numbers.<br>
Those that will hear me speak, let ’em stay here;<br>
Those that will follow Cassius, go with him;<br>
And public reasons shall be rendered<br>
Of Caesar’s death.
</p>

<p class="drama">
FIRST CITIZEN.<br>
I will hear Brutus speak.
</p>

<p class="drama">
SECOND CITIZEN.<br>
I will hear Cassius; and compare their reasons,<br>
When severally we hear them rendered.
</p>

<p class="right">
[<i>Exit <span class="charname">Cassius,</span> with some of the <span class="charname">Citizens. Brutus</span> goes into the rostrum.</i>]
</p>

<p class="drama">
THIRD CITIZEN.<br>
The noble Brutus is ascended: silence!
</p>

<p class="drama">
BRUTUS.<br>
Be patient till the last.<br>
Romans, countrymen, and lovers, hear me for my cause; and be silent, that you
may hear. Believe me for mine honour, and have respect to mine honour, that you
may believe. Censure me in your wisdom, and awake your senses, that you may the
better judge. If there be any in this assembly, any dear friend of Caesar’s, to
him I say that Brutus’ love to Caesar was no less than his. If then that friend
demand why Brutus rose against Caesar, this is my answer: Not that I loved
Caesar less, but that I loved Rome more. Had you rather Caesar were living, and
die all slaves, than that Caesar were dead, to live all free men? As Caesar
loved me, I weep for him; as he was fortunate, I rejoice at it; as he was
valiant, I honour him; but, as he was ambitious, I slew him. There is tears,
for his love; joy for his fortune; honour for his valour; and death, for his
ambition. Who is here so base, that would be a bondman? If any, speak; for him
have I offended. Who is here so rude, that would not be a Roman? If any, speak;
for him have I offended. Who is here so vile, that will not love his country?
If any, speak; for him have I offended. I pause for a reply.
</p>

<p class="drama">
CITIZENS.<br>
None, Brutus, none.
</p>

<p class="drama">
BRUTUS.<br>
Then none have I offended. I have done no more to Caesar than you shall do to
Brutus. The question of his death is enroll’d in the Capitol, his glory not
extenuated, wherein he was worthy; nor his offences enforc’d, for which he
suffered death.
</p>

<p class="scenedesc">
Enter <span class="charname">Antony</span> and others, with <span class="charname">Caesar’s</span> body.
</p>

<p class="drama">
Here comes his body, mourned by Mark Antony, who, though he had no hand in his
death, shall receive the benefit of his dying, a place in the commonwealth; as
which of you shall not? With this I depart, that, as I slew my best lover for
the good of Rome, I have the same dagger for myself, when it shall please my
country to need my death.
</p>

<p class="drama">
CITIZENS.<br>
Live, Brutus! live, live!
</p>

<p class="drama">
FIRST CITIZEN.<br>
Bring him with triumph home unto his house.
</p>

<p class="drama">
SECOND CITIZEN.<br>
Give him a statue with his ancestors.
</p>

<p class="drama">
THIRD CITIZEN.<br>
Let him be Caesar.
</p>

<p class="drama">
FOURTH CITIZEN.<br>
Caesar’s better parts<br>
Shall be crown’d in Brutus.
</p>

<p class="drama">
FIRST CITIZEN.<br>
We’ll bring him to his house with shouts and clamours.
</p>

<p class="drama">
BRUTUS.<br>
My countrymen,—
</p>

<p class="drama">
SECOND CITIZEN.<br>
Peace! Silence! Brutus speaks.
</p>

<p class="drama">
FIRST CITIZEN.<br>
Peace, ho!
</p>

<p class="drama">
BRUTUS.<br>
Good countrymen, let me depart alone,<br>
And, for my sake, stay here with Antony.<br>
Do grace to Caesar’s corpse, and grace his speech<br>
Tending to Caesar’s glories, which Mark Antony,<br>
By our permission, is allow’d to make.<br>
I do entreat you, not a man depart,<br>
Save I alone, till Antony have spoke.
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="drama">
FIRST CITIZEN.<br>
Stay, ho! and let us hear Mark Antony.
</p>

<p class="drama">
THIRD CITIZEN.<br>
Let him go up into the public chair.<br>
We’ll hear him. Noble Antony, go up.
</p>

<p class="drama">
ANTONY.<br>
For Brutus’ sake, I am beholding to you.
</p>

<p class="right">
[<i>Goes up.</i>]
</p>

<p class="drama">
FOURTH CITIZEN.<br>
What does he say of Brutus?
</p>

<p class="drama">
THIRD CITIZEN.<br>
He says, for Brutus’ sake<br>
He finds himself beholding to us all.
</p>

<p class="drama">
FOURTH CITIZEN.<br>
’Twere best he speak no harm of Brutus here!
</p>

<p class="drama">
FIRST CITIZEN.<br>
This Caesar was a tyrant.
</p>

<p class="drama">
THIRD CITIZEN.<br>
Nay, that’s certain.<br>
We are blest that Rome is rid of him.
</p>

<p class="drama">
SECOND CITIZEN.<br>
Peace! let us hear what Antony can say.
</p>

<p class="drama">
ANTONY.<br>
You gentle Romans,—
</p>

<p class="drama">
CITIZENS.<br>
Peace, ho! let us hear him.
</p>

<p class="drama">
ANTONY.<br>
Friends, Romans, countrymen, lend me your ears;<br>
I come to bury Caesar, not to praise him.<br>
The evil that men do lives after them,<br>
The good is oft interred with their bones;<br>
So let it be with Caesar. The noble Brutus<br>
Hath told you Caesar was ambitious.<br>
If it were so, it was a grievous fault,<br>
And grievously hath Caesar answer’d it.<br>
Here, under leave of Brutus and the rest,<br>
For Brutus is an honourable man,<br>
So are they all, all honourable men,<br>
Come I to speak in Caesar’s funeral.<br>
He was my friend, faithful and just to me;<br>
But Brutus says he was ambitious,<br>
And Brutus is an honourable man.<br>
He hath brought many captives home to Rome,<br>
Whose ransoms did the general coffers fill:<br>
Did this in Caesar seem ambitious?<br>
When that the poor have cried, Caesar hath wept;<br>
Ambition should be made of sterner stuff:<br>
Yet Brutus says he was ambitious;<br>
And Brutus is an honourable man.<br>
You all did see that on the Lupercal<br>
I thrice presented him a kingly crown,<br>
Which he did thrice refuse. Was this ambition?<br>
Yet Brutus says he was ambitious;<br>
And sure he is an honourable man.<br>
I speak not to disprove what Brutus spoke,<br>
But here I am to speak what I do know.<br>
You all did love him once, not without cause;<br>
What cause withholds you then to mourn for him?<br>
O judgement, thou art fled to brutish beasts,<br>
And men have lost their reason. Bear with me.<br>
My heart is in the coffin there with Caesar,<br>
And I must pause till it come back to me.
</p>

<p class="drama">
FIRST CITIZEN.<br>
Methinks there is much reason in his sayings.
</p>

<p class="drama">
SECOND CITIZEN.<br>
If thou consider rightly of the matter,<br>
Caesar has had great wrong.
</p>

<p class="drama">
THIRD CITIZEN.<br>
Has he, masters?<br>
I fear there will a worse come in his place.
</p>

<p class="drama">
FOURTH CITIZEN.<br>
Mark’d ye his words? He would not take the crown;<br>
Therefore ’tis certain he was not ambitious.
</p>

<p class="drama">
FIRST CITIZEN.<br>
If it be found so, some will dear abide it.
</p>

<p class="drama">
SECOND CITIZEN.<br>
Poor soul, his eyes are red as fire with weeping.
</p>

<p class="drama">
THIRD CITIZEN.<br>
There’s not a nobler man in Rome than Antony.
</p>

<p class="drama">
FOURTH CITIZEN.<br>
Now mark him; he begins again to speak.
</p>

<p class="drama">
ANTONY.<br>
But yesterday the word of Caesar might<br>
Have stood against the world; now lies he there,<br>
And none so poor to do him reverence.<br>
O masters! If I were dispos’d to stir<br>
Your hearts and minds to mutiny and rage,<br>
I should do Brutus wrong and Cassius wrong,<br>
Who, you all know, are honourable men.<br>
I will not do them wrong; I rather choose<br>
To wrong the dead, to wrong myself and you,<br>
Than I will wrong such honourable men.<br>
But here’s a parchment with the seal of Caesar,<br>
I found it in his closet; ’tis his will:<br>
Let but the commons hear this testament,<br>
Which, pardon me, I do not mean to read,<br>
And they would go and kiss dead Caesar’s wounds,<br>
And dip their napkins in his sacred blood;<br>
Yea, beg a hair of him for memory,<br>
And, dying, mention it within their wills,<br>
Bequeathing it as a rich legacy<br>
Unto their issue.
</p>

<p class="drama">
FOURTH CITIZEN.<br>
We’ll hear the will. Read it, Mark Antony.
</p>

<p class="drama">
CITIZENS.<br>
The will, the will! We will hear Caesar’s will.
</p>

<p class="drama">
ANTONY.<br>
Have patience, gentle friends, I must not read it.<br>
It is not meet you know how Caesar loved you.<br>
You are not wood, you are not stones, but men;<br>
And being men, hearing the will of Caesar,<br>
It will inflame you, it will make you mad.<br>
’Tis good you know not that you are his heirs;<br>
For if you should, O, what would come of it?
</p>

<p class="drama">
FOURTH CITIZEN.<br>
Read the will! We’ll hear it, Antony;<br>
You shall read us the will, Caesar’s will!
</p>

<p class="drama">
ANTONY.<br>
Will you be patient? Will you stay awhile?<br>
I have o’ershot myself to tell you of it.<br>
I fear I wrong the honourable men<br>
Whose daggers have stabb’d Caesar; I do fear it.
</p>

<p class="drama">
FOURTH CITIZEN.<br>
They were traitors. Honourable men!
</p>

<p class="drama">
CITIZENS.<br>
The will! The testament!
</p>

<p class="drama">
SECOND CITIZEN.<br>
They were villains, murderers. The will! Read the will!
</p>

<p class="drama">
ANTONY.<br>
You will compel me then to read the will?<br>
Then make a ring about the corpse of Caesar,<br>
And let me show you him that made the will.<br>
Shall I descend? and will you give me leave?
</p>

<p class="drama">
CITIZENS.<br>
Come down.
</p>

<p class="drama">
SECOND CITIZEN.<br>
Descend.
</p>

<p class="right">
[<i>He comes down.</i>]
</p>

<p class="drama">
THIRD CITIZEN.<br>
You shall have leave.
</p>

<p class="drama">
FOURTH CITIZEN.<br>
A ring! Stand round.
</p>

<p class="drama">
FIRST CITIZEN.<br>
Stand from the hearse, stand from the body.
</p>

<p class="drama">
SECOND CITIZEN.<br>
Room for Antony, most noble Antony!
</p>

<p class="drama">
ANTONY.<br>
Nay, press not so upon me; stand far off.
</p>

<p class="drama">
CITIZENS.<br>
Stand back; room! bear back.
</p>

<p class="drama">
ANTONY.<br>
If you have tears, prepare to shed them now.<br>
You all do know this mantle. I remember<br>
The first time ever Caesar put it on;<br>
’Twas on a Summer’s evening, in his tent,<br>
That day he overcame the Nervii.<br>
Look, in this place ran Cassius’ dagger through:<br>
See what a rent the envious Casca made:<br>
Through this the well-beloved Brutus stabb’d;<br>
And as he pluck’d his cursed steel away,<br>
Mark how the blood of Caesar follow’d it,<br>
As rushing out of doors, to be resolv’d<br>
If Brutus so unkindly knock’d, or no;<br>
For Brutus, as you know, was Caesar’s angel.<br>
Judge, O you gods, how dearly Caesar lov’d him.<br>
This was the most unkindest cut of all;<br>
For when the noble Caesar saw him stab,<br>
Ingratitude, more strong than traitors’ arms,<br>
Quite vanquish’d him: then burst his mighty heart;<br>
And in his mantle muffling up his face,<br>
Even at the base of Pompey’s statue<br>
Which all the while ran blood, great Caesar fell.<br>
O, what a fall was there, my countrymen!<br>
Then I, and you, and all of us fell down,<br>
Whilst bloody treason flourish’d over us.<br>
O, now you weep; and I perceive you feel<br>
The dint of pity. These are gracious drops.<br>
Kind souls, what weep you when you but behold<br>
Our Caesar’s vesture wounded? Look you here,<br>
Here is himself, marr’d, as you see, with traitors.
</p>

<p class="drama">
FIRST CITIZEN.<br>
O piteous spectacle!
</p>

<p class="drama">
SECOND CITIZEN.<br>
O noble Caesar!
</p>

<p class="drama">
THIRD CITIZEN.<br>
O woeful day!
</p>

<p class="drama">
FOURTH CITIZEN.<br>
O traitors, villains!
</p>

<p class="drama">
FIRST CITIZEN.<br>
O most bloody sight!
</p>

<p class="drama">
SECOND CITIZEN.<br>
We will be revenged.
</p>

<p class="drama">
CITIZENS.<br>
Revenge,—about,—seek,—burn,—fire,—kill,—slay,—let not a traitor live!
</p>

<p class="drama">
ANTONY.<br>
Stay, countrymen.
</p>

<p class="drama">
FIRST CITIZEN.<br>
Peace there! Hear the noble Antony.
</p>

<p class="drama">
SECOND CITIZEN.<br>
We’ll hear him, we’ll follow him, we’ll die with him.
</p>

<p class="drama">
ANTONY.<br>
Good friends, sweet friends, let me not stir you up<br>
To such a sudden flood of mutiny.<br>
They that have done this deed are honourable.<br>
What private griefs they have, alas, I know not,<br>
That made them do it. They’re wise and honourable,<br>
And will, no doubt, with reasons answer you.<br>
I come not, friends, to steal away your hearts.<br>
I am no orator, as Brutus is;<br>
But, as you know me all, a plain blunt man,<br>
That love my friend; and that they know full well<br>
That gave me public leave to speak of him.<br>
For I have neither wit, nor words, nor worth,<br>
Action, nor utterance, nor the power of speech,<br>
To stir men’s blood. I only speak right on.<br>
I tell you that which you yourselves do know,<br>
Show you sweet Caesar’s wounds, poor poor dumb mouths,<br>
And bid them speak for me. But were I Brutus,<br>
And Brutus Antony, there were an Antony<br>
Would ruffle up your spirits, and put a tongue<br>
In every wound of Caesar, that should move<br>
The stones of Rome to rise and mutiny.
</p>

<p class="drama">
CITIZENS.<br>
We’ll mutiny.
</p>

<p class="drama">
FIRST CITIZEN.<br>
We’ll burn the house of Brutus.
</p>

<p class="drama">
THIRD CITIZEN.<br>
Away, then! come, seek the conspirators.
</p>

<p class="drama">
ANTONY.<br>
Yet hear me, countrymen; yet hear me speak.
</p>

<p class="drama">
CITIZENS.<br>
Peace, ho! Hear Antony; most noble Antony.
</p>

<p class="drama">
ANTONY.<br>
Why, friends, you go to do you know not what.<br>
Wherein hath Caesar thus deserved your loves?<br>
Alas, you know not; I must tell you then.<br>
You have forgot the will I told you of.
</p>

<p class="drama">
CITIZENS.<br>
Most true; the will!—let’s stay, and hear the will.
</p>

<p class="drama">
ANTONY.<br>
Here is the will, and under Caesar’s seal.<br>
To every Roman citizen he gives,<br>
To every several man, seventy-five drachmas.
</p>

<p class="drama">
SECOND CITIZEN.<br>
Most noble Caesar! We’ll revenge his death.
</p>

<p class="drama">
THIRD CITIZEN.<br>
O, royal Caesar!
</p>

<p class="drama">
ANTONY.<br>
Hear me with patience.
</p>

<p class="drama">
CITIZENS.<br>
Peace, ho!
</p>

<p class="drama">
ANTONY.<br>
Moreover, he hath left you all his walks,<br>
His private arbors, and new-planted orchards,<br>
On this side Tiber; he hath left them you,<br>
And to your heirs forever; common pleasures,<br>
To walk abroad, and recreate yourselves.<br>
Here was a Caesar! when comes such another?
</p>

<p class="drama">
FIRST CITIZEN.<br>
Never, never. Come, away, away!<br>
We’ll burn his body in the holy place,<br>
And with the brands fire the traitors’ houses.<br>
Take up the body.
</p>

<p class="drama">
SECOND CITIZEN.<br>
Go, fetch fire.
</p>

<p class="drama">
THIRD CITIZEN.<br>
Pluck down benches.
</p>

<p class="drama">
FOURTH CITIZEN.<br>
Pluck down forms, windows, anything.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Citizens,</span> with the body.</i>]
</p>

<p class="drama">
ANTONY.<br>
Now let it work. Mischief, thou art afoot,<br>
Take thou what course thou wilt!
</p>

<p class="scenedesc">
Enter a <span class="charname">Servant</span>.
</p>

<p class="drama">
How now, fellow?
</p>

<p class="drama">
SERVANT.<br>
Sir, Octavius is already come to Rome.
</p>

<p class="drama">
ANTONY.<br>
Where is he?
</p>

<p class="drama">
SERVANT.<br>
He and Lepidus are at Caesar’s house.
</p>

<p class="drama">
ANTONY.<br>
And thither will I straight to visit him.<br>
He comes upon a wish. Fortune is merry,<br>
And in this mood will give us anything.
</p>

<p class="drama">
SERVANT.<br>
I heard him say Brutus and Cassius<br>
Are rid like madmen through the gates of Rome.
</p>

<p class="drama">
ANTONY.<br>
Belike they had some notice of the people,<br>
How I had moved them. Bring me to Octavius.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneIII_17.3"></a><b>SCENE III. The same. A street.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Cinna,</span> the poet, and after him the
citizens.
</p>

<p class="drama">
CINNA.<br>
I dreamt tonight that I did feast with Caesar,<br>
And things unluckily charge my fantasy.<br>
I have no will to wander forth of doors,<br>
Yet something leads me forth.
</p>

<p class="drama">
FIRST CITIZEN.<br>
What is your name?
</p>

<p class="drama">
SECOND CITIZEN.<br>
Whither are you going?
</p>

<p class="drama">
THIRD CITIZEN.<br>
Where do you dwell?
</p>

<p class="drama">
FOURTH CITIZEN.<br>
Are you a married man or a bachelor?
</p>

<p class="drama">
SECOND CITIZEN.<br>
Answer every man directly.
</p>

<p class="drama">
FIRST CITIZEN.<br>
Ay, and briefly.
</p>

<p class="drama">
FOURTH CITIZEN.<br>
Ay, and wisely.
</p>

<p class="drama">
THIRD CITIZEN.<br>
Ay, and truly, you were best.
</p>

<p class="drama">
CINNA.<br>
What is my name? Whither am I going? Where do I dwell? Am I a married man or a
bachelor? Then, to answer every man directly and briefly, wisely and truly.
Wisely I say I am a bachelor.
</p>

<p class="drama">
SECOND CITIZEN.<br>
That’s as much as to say they are fools that marry; you’ll bear me a bang for
that, I fear. Proceed, directly.
</p>

<p class="drama">
CINNA.<br>
Directly, I am going to Caesar’s funeral.
</p>

<p class="drama">
FIRST CITIZEN.<br>
As a friend, or an enemy?
</p>

<p class="drama">
CINNA.<br>
As a friend.
</p>

<p class="drama">
SECOND CITIZEN.<br>
That matter is answered directly.
</p>

<p class="drama">
FOURTH CITIZEN.<br>
For your dwelling, briefly.
</p>

<p class="drama">
CINNA.<br>
Briefly, I dwell by the Capitol.
</p>

<p class="drama">
THIRD CITIZEN.<br>
Your name, sir, truly.
</p>

<p class="drama">
CINNA.<br>
Truly, my name is Cinna.
</p>

<p class="drama">
FIRST CITIZEN.<br>
Tear him to pieces! He’s a conspirator.
</p>

<p class="drama">
CINNA.<br>
I am Cinna the poet, I am Cinna the poet.
</p>

<p class="drama">
FOURTH CITIZEN.<br>
Tear him for his bad verses, tear him for his bad verses.
</p>

<p class="drama">
CINNA.<br>
I am not Cinna the conspirator.
</p>

<p class="drama">
FOURTH CITIZEN.<br>
It is no matter, his name’s Cinna; pluck but his name out of his heart, and
