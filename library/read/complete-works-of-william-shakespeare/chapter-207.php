<h2> <a id="sceneIII_33.1"></a><b>ACT III</b></h2>

<h3> <b>SCENE I. Athens. A room in Lucullus’ house</b></h3>

<p class="scenedesc">
<span class="charname">Flaminius</span> waiting to speak with Lucullus from his
master.
</p>

<p class="scenedesc">
Enter a <span class="charname">Servant</span> to him.
</p>

<p class="drama">
SERVANT.<br>
I have told my lord of you; he is coming down to you.
</p>

<p class="drama">
FLAMINIUS.<br>
I thank you, sir.
</p>

<p class="scenedesc">
Enter <span class="charname">Lucullus</span>.
</p>

<p class="drama">
SERVANT.<br>
Here’s my lord.
</p>

<p class="drama">
LUCULLUS.<br>
[<i>Aside</i>.] One of Lord Timon’s men? A gift, I warrant. Why, this hits
right. I dreamt of a silver basin and ewer tonight.—Flaminius, honest
Flaminius, you are very respectively welcome, sir. Fill me some wine.
</p>

<p class="right">[<i>Exit <span class="charname">Servant</span>.</i>]</p>

<p class="drama">
And how does that honourable, complete, free-hearted gentleman of Athens, thy
very bountiful good lord and master?</p>

<p class="drama">
FLAMINIUS.<br>
His health is well, sir.
</p>

<p class="drama">
LUCULLUS.<br>
I am right glad that his health is well, sir. And what hast thou there under
thy cloak, pretty Flaminius?</p>

<p class="drama">
FLAMINIUS.<br>
Faith, nothing but an empty box, sir, which in my lord’s behalf I come
to entreat your honour to supply; who, having great and instant occasion to use
fifty talents, hath sent to your lordship to furnish him, nothing doubting your
present assistance therein.</p>

<p class="drama">
LUCULLUS.<br>
La, la, la, la! Nothing doubting, says he? Alas, good lord! A noble gentleman
’tis, if he would not keep so good a house. Many a time and often I ha’ dined
with him, and told him on’t, and come again to supper to him of purpose to have
him spend less, and yet he would embrace no counsel, take no warning by my
coming. Every man has his fault, and honesty is his. I ha’ told him on’t, but I
could ne’er get him from ’t.
</p>

<p class="scenedesc">
Enter <span class="charname">Servant</span> with wine.
</p>

<p class="drama">
SERVANT.<br>
Please your lordship, here is the wine.
</p>

<p class="drama">
LUCULLUS.<br>
Flaminius, I have noted thee always wise. Here’s to thee.
</p>

<p class="drama">
FLAMINIUS.<br>
Your lordship speaks your pleasure.
</p>

<p class="drama">
LUCULLUS.<br>
I have observed thee always for a towardly prompt spirit, give thee thy due,
and one that knows what belongs to reason, and canst use the time well, if the
time use thee well. Good parts in thee. [<i>To Servant</i>.] Get you gone,
sirrah.—</p>

<p class="right">[<i>Exit <span class="charname">Servant</span>.</i>]</p>

<p class="drama">
Draw nearer, honest Flaminius. Thy lord’s a bountiful gentleman, but
thou art wise and thou know’st well enough, although thou com’st to me,
that this is no time to lend money, especially upon bare friendship
without security. Here’s three solidares for thee. Good boy, wink at
me, and say thou saw’st me not. Fare thee well.
</p>

<p class="drama">
FLAMINIUS.<br>
Is’t possible the world should so much differ,<br>
And we alive that lived? Fly, damned baseness,<br>
To him that worships thee.
</p>

<p class="right">[<i>Throws the money back.</i>]</p>

<p class="drama">
LUCULLUS.<br>
Ha! Now I see thou art a fool and fit for thy master.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
FLAMINIUS.<br>
May these add to the number that may scald thee!<br>
Let molten coin be thy damnation,<br>
Thou disease of a friend, and not himself!<br>
Has friendship such a faint and milky heart<br>
It turns in less than two nights? O you gods,<br>
I feel my master’s passion. This slave<br>
Unto his honour has my lord’s meat in him.<br>
Why should it thrive and turn to nutriment<br>
When he is turned to poison?<br>
O, may diseases only work upon’t,<br>
And when he’s sick to death, let not that part of nature<br>
Which my lord paid for be of any power<br>
To expel sickness, but prolong his hour.
</p>

<p class="right">[<i>Exit.</i>]</p>

<h3> <a id="sceneIII_33.2"></a><b>SCENE II. A public place</b></h3>

<p class="scenedesc">
Enter <span class="charname">Lucius</span> with three
<span class="charname">Strangers</span>.
</p>

<p class="drama">
LUCIUS.<br>
Who, the Lord Timon? He is my very good friend and an honourable gentleman.
</p>

<p class="drama">
FIRST STRANGER.<br>
We know him for no less, though we are but strangers to him. But I can tell you
one thing, my lord, and which I hear from common rumours: now Lord Timon’s
happy hours are done and past, and his estate shrinks from him.
</p>

<p class="drama">
LUCIUS.<br>
Fie, no, do not believe it; he cannot want for money.
</p>

<p class="drama">
SECOND STRANGER.<br>
But believe you this, my lord, that, not long ago one of his men was with the
Lord Lucullus to borrow so many talents, nay, urged extremely for’t, and showed
what necessity belonged to’t, and yet was denied.
</p>

<p class="drama">
LUCIUS.<br>
How?
</p>

<p class="drama">
SECOND STRANGER.<br>
I tell you, denied, my lord.
</p>

<p class="drama">
LUCIUS.<br>
What a strange case was that! Now, before the gods, I am ashamed on’t. Denied
that honourable man? There was very little honour showed in’t. For my own part,
I must needs confess, I have received some small kindnesses from him, as money,
plate, jewels, and such like trifles, nothing comparing to his; yet had he
mistook him, and sent to me, I should ne’er have denied his occasion so many
talents.
</p>

<p class="scenedesc">
Enter <span class="charname">Servilius</span>.
</p>

<p class="drama">
SERVILIUS.<br>
See, by good hap, yonder’s my lord; I have sweat to see his honour. [<i>To
Lucius</i>.] My honoured lord!
</p>

<p class="drama">
LUCIUS.<br>
Servilius? You are kindly met, sir. Fare thee well. Commend me to thy
honourable virtuous lord, my very exquisite friend.</p>

<p class="drama">
SERVILIUS.<br>
May it please your honour, my lord hath sent—
</p>

<p class="drama">
LUCIUS.<br>
Ha! What has he sent? I am so much endeared to that lord; he’s ever sending.
How shall I thank him, thinkest thou? And what has he sent now?
</p>

<p class="drama">
SERVILIUS.<br>
Has only sent his present occasion now, my lord, requesting your lordship to
supply his instant use with so many talents.
</p>

<p class="drama">
LUCIUS.<br>
I know his lordship is but merry with me;<br>
He cannot want fifty-five hundred talents.
</p>

<p class="drama">
SERVILIUS.<br>
But in the meantime he wants less, my lord.<br>
If his occasion were not virtuous,<br>
I should not urge it half so faithfully.
</p>

<p class="drama">
LUCIUS.<br>
Dost thou speak seriously, Servilius?
</p>

<p class="drama">
SERVILIUS.<br>
Upon my soul, ’tis true, sir.
</p>

<p class="drama">
LUCIUS.<br>
What a wicked beast was I to disfurnish myself against such a good time, when I
might ha’ shown myself honourable! How unluckily it happened that I should
purchase the day before for a little part, and undo a great deal of honour!
Servilius, now before the gods, I am not able to do—the more beast, I say—I
was sending to use Lord Timon myself, these gentlemen can witness; but I would
not for the wealth of Athens I had done it now. Commend me bountifully to his
good lordship, and I hope his honour will conceive the fairest of me, because I
have no power to be kind. And tell him this from me: I count it one of my
greatest afflictions, say, that I cannot pleasure such an honourable gentleman.
Good Servilius, will you befriend me so far as to use mine own words to him?
</p>

<p class="drama">
SERVILIUS.<br>
Yes, sir, I shall.
</p>

<p class="drama">
LUCIUS.<br>
I’ll look you out a good turn, Servilius.
</p>

<p class="right">[<i>Exit <span class="charname">Servilius</span>.</i>]</p>

<p class="drama">
True, as you said, Timon is shrunk indeed,<br>
And he that’s once denied will hardly speed.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
FIRST STRANGER.<br>
Do you observe this, Hostilius?
</p>

<p class="drama">
SECOND STRANGER.<br>
Ay, too well.
</p>

<p class="drama">
FIRST STRANGER.<br>
Why, this is the world’s soul, and just of the same piece<br>
Is every flatterer’s spirit. Who can call him his friend<br>
That dips in the same dish? For, in my knowing,<br>
Timon has been this lord’s father<br>
And kept his credit with his purse,<br>
Supported his estate, nay, Timon’s money<br>
Has paid his men their wages. He ne’er drinks<br>
But Timon’s silver treads upon his lip,<br>
And yet—O, see the monstrousness of man<br>
When he looks out in an ungrateful shape—<br>
He does deny him, in respect of his,<br>
What charitable men afford to beggars.
</p>

<p class="drama">
THIRD STRANGER.<br>
Religion groans at it.
</p>

<p class="drama">
FIRST STRANGER.<br>
For mine own part,<br>
I never tasted Timon in my life,<br>
Nor came any of his bounties over me<br>
To mark me for his friend. Yet I protest,<br>
For his right noble mind, illustrious virtue,<br>
And honourable carriage,<br>
Had his necessity made use of me,<br>
I would have put my wealth into donation,<br>
And the best half should have returned to him,<br>
So much I love his heart. But I perceive<br>
Men must learn now with pity to dispense,<br>
For policy sits above conscience.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneIII_33.3"></a><b>SCENE III. The same. A room in Sempronius’ house</b></h3>

<p class="scenedesc">
Enter a Third <span class="charname">Servant </span> of Timon’s with
<span class="charname">Sempronius,</span> another of Timon’s friends.
</p>

<p class="drama">
SEMPRONIUS.<br>
Must he needs trouble me in’t? Hum! ’Bove all others?<br>
He might have tried Lord Lucius or Lucullus;<br>
And now Ventidius is wealthy too,<br>
Whom he redeemed from prison. All these<br>
Owe their estates unto him.
</p>

<p class="drama">
SERVANT.<br>
My lord,<br>
They have all been touched and found base metal,<br>
For they have all denied him.
</p>

<p class="drama">
SEMPRONIUS.<br>
How? Have they denied him?<br>
Has Ventidius and Lucullus denied him<br>
And does he send to me? Three? Humh!<br>
It shows but little love or judgment in him.<br>
Must I be his last refuge? His friends, like physicians,<br>
Thrive, give him over. Must I take th’ cure upon me?<br>
Has much disgraced me in’t. I’m angry at him,<br>
That might have known my place. I see no sense for’t<br>
But his occasions might have wooed me first;<br>
For, in my conscience, I was the first man<br>
That e’er received gift from him.<br>
And does he think so backwardly of me now<br>
That I’ll requite it last? No.<br>
So it may prove an argument of laughter<br>
To th’ rest, and I ’mongst lords be thought a fool.<br>
I’d rather than the worth of thrice the sum<br>
Had sent to me first, but for my mind’s sake;<br>
I’d such a courage to do him good. But now return,<br>
And with their faint reply this answer join:<br>
Who bates mine honour shall not know my coin.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
SERVANT.<br>
Excellent! Your lordship’s a goodly villain. The devil knew not what he
did when he made man politic; he crossed himself by’t, and I cannot think
but, in the end the villainies of man will set him clear. How fairly this lord
strives to appear foul! Takes virtuous copies to be wicked, like those that
under hot ardent zeal would set whole realms on fire.<br>
Of such a nature is his politic love.<br>
This was my lord’s best hope, now all are fled<br>
Save only the gods. Now his friends are dead,<br>
Doors that were ne’er acquainted with their wards<br>
Many a bounteous year must be employed<br>
Now to guard sure their master.<br>
And this is all a liberal course allows,<br>
Who cannot keep his wealth must keep his house.
</p>

<p class="right">[<i>Exit.</i>]</p>

<h3> <a id="sceneIII_33.4"></a><b>SCENE IV. A hall in Timon’s house</b></h3>

<p class="scenedesc">
Enter two of Varro’s <span class="charname">Servants</span> meeting <span class="charname">Titus</span> and <span class="charname">Hortensius</span> and
then <span class="charname">Lucius,</span> all Servants of Timon’s creditors,
to wait for his coming out.
</p>

<p class="drama">
FIRST VARRO’S SERVANT.<br>
Well met, good morrow, Titus and Hortensius.
</p>

<p class="drama">
TITUS.<br>
The like to you, kind Varro.
</p>

<p class="drama">
HORTENSIUS.<br>
Lucius!<br>
What, do we meet together?
</p>

<p class="drama">
LUCIUS.<br>
Ay, and I think<br>
One business does command us all;<br>
For mine is money.</p>

<p class="drama">
TITUS.<br>
So is theirs and ours.
</p>

<p class="scenedesc">
Enter <span class="charname">Philotus</span>.
</p>

<p class="drama">
LUCIUS.<br>
And, sir, Philotus too!
</p>

<p class="drama">
PHILOTUS.<br>
Good day at once.
</p>

<p class="drama">
LUCIUS.<br>
Welcome, good brother.<br>
What do you think the hour?
</p>

<p class="drama">
PHILOTUS.<br>
Labouring for nine.
</p>

<p class="drama">
LUCIUS.<br>
So much?
</p>

<p class="drama">
PHILOTUS.<br>
Is not my lord seen yet?
</p>

<p class="drama">
LUCIUS.<br>
Not yet.
</p>

<p class="drama">
PHILOTUS.<br>
I wonder on’t, he was wont to shine at seven.
</p>

<p class="drama">
LUCIUS.<br>
Ay, but the days are waxed shorter with him.<br>
You must consider that a prodigal course<br>
Is like the sun’s, but not like his recoverable.<br>
I fear ’tis deepest winter in Lord Timon’s purse:<br>
That is, one may reach deep enough, and yet<br>
Find little.
</p>

<p class="drama">
PHILOTUS.<br>
I am of your fear for that.
</p>

<p class="drama">
TITUS.<br>
I’ll show you how t’ observe a strange event.<br>
Your lord sends now for money?
</p>

<p class="drama">
HORTENSIUS.<br>
Most true, he does.
</p>

<p class="drama">
TITUS.<br>
And he wears jewels now of Timon’s gift,<br>
For which I wait for money.
</p>

<p class="drama">
HORTENSIUS.<br>
It is against my heart.
</p>

<p class="drama">
LUCIUS.<br>
Mark how strange it shows,<br>
Timon in this should pay more than he owes,<br>
And e’en as if your lord should wear rich jewels<br>
And send for money for ’em.
</p>

<p class="drama">
HORTENSIUS.<br>
I’m weary of this charge, the gods can witness.<br>
I know my lord hath spent of Timon’s wealth,<br>
And now ingratitude makes it worse than stealth.
</p>

<p class="drama">
FIRST VARRO’S SERVANT.<br>
Yes, mine’s three thousand crowns. What’s yours?
</p>

<p class="drama">
LUCIUS.<br>
Five thousand mine.
</p>

<p class="drama">
FIRST VARRO’S SERVANT.<br>
’Tis much deep, and it should seem by th’ sum<br>
Your master’s confidence was above mine,<br>
Else surely his had equalled.
</p>

<p class="scenedesc">
Enter <span class="charname">Flaminius</span>.
</p>

<p class="drama">
TITUS.<br>
One of Lord Timon’s men.
</p>

<p class="drama">
LUCIUS.<br>
Flaminius? Sir, a word. Pray, is my lord ready to come forth?</p>

<p class="drama">
FLAMINIUS.<br>
No, indeed he is not.
</p>

<p class="drama">
TITUS.<br>
We attend his lordship; pray, signify so much.
</p>

<p class="drama">
FLAMINIUS.<br>
I need not tell him that, he knows you are too diligent.
</p>

<p class="right">[<i>Exit <span class="charname">Flaminius</span>.</i>]</p>

<p class="scenedesc">
Enter <span class="charname">Flavius</span> in a cloak, muffled.
</p>

<p class="drama">
LUCIUS.<br>
Ha, is not that his steward muffled so?<br>
He goes away in a cloud. Call him, call him.
</p>

<p class="drama">
TITUS.<br>
Do you hear, sir?
</p>

<p class="drama">
SECOND VARRO’S SERVANT.<br>
By your leave, sir.
</p>

<p class="drama">
FLAVIUS.<br>
What do you ask of me, my friend?
</p>

<p class="drama">
TITUS.<br>
We wait for certain money here, sir.
</p>

<p class="drama">
FLAVIUS.<br>
Ay,<br>
If money were as certain as your waiting,<br>
’Twere sure enough.<br>
Why then preferred you not your sums and bills<br>
When your false masters eat of my lord’s meat?<br>
Then they could smile and fawn upon his debts,<br>
And take down th’ interest into their gluttonous maws.<br>
You do yourselves but wrong to stir me up,<br>
Let me pass quietly.<br>
Believe’t, my lord and I have made an end,<br>
I have no more to reckon, he to spend.
</p>

<p class="drama">
LUCIUS.<br>
Ay, but this answer will not serve.
</p>

<p class="drama">
FLAVIUS.<br>
If ’twill not serve, ’tis not so base as you,<br>
For you serve knaves.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
FIRST VARRO’S SERVANT.<br>
How? What does his cashiered worship mutter?
</p>

<p class="drama">
SECOND VARRO’S SERVANT.<br>
No matter what, he’s poor, and that’s revenge enough. Who can speak broader
than he that has no house to put his head in? Such may rail against great
buildings.
</p>

<p class="scenedesc">
Enter <span class="charname">Servilius</span>.
</p>

<p class="drama">
TITUS.<br>
O, here’s Servilius; now we shall know some answer.
</p>

<p class="drama">
SERVILIUS.<br>
If I might beseech you, gentlemen, to repair some other hour, I should derive
much from’t. For take’t of my soul, my lord leans wondrously to discontent.
His comfortable temper has forsook him, he’s much out of health and keeps his
chamber.
</p>

<p class="drama">
LUCIUS.<br>
Many do keep their chambers are not sick.<br>
And if it be so far beyond his health,<br>
Methinks he should the sooner pay his debts<br>
And make a clear way to the gods.
</p>

<p class="drama">
SERVILIUS.<br>
Good gods!
</p>

<p class="drama">
TITUS.<br>
We cannot take this for answer, sir.
</p>

<p class="drama">
FLAMINIUS.<br>
[<i>Within</i>.] Servilius, help! My lord, my lord!
</p>

<p class="scenedesc">
Enter <span class="charname">Timon</span> in a rage.
</p>

<p class="drama">
TIMON.<br>
What, are my doors opposed against my passage?<br>
Have I been ever free, and must my house<br>
Be my retentive enemy, my jail?<br>
The place which I have feasted, does it now,<br>
Like all mankind, show me an iron heart?
</p>

<p class="drama">
LUCIUS.<br>
Put in now, Titus.
</p>

<p class="drama">
TITUS.<br>
My lord, here is my bill.
</p>

<p class="drama">
LUCIUS.<br>
Here’s mine.
</p>

<p class="drama">
HORTENSIUS.<br>
And mine, my lord.
</p>

<p class="drama">
BOTH VARRO’S SERVANTS.<br>
And ours, my lord.
</p>

<p class="drama">
PHILOTUS.<br>
All our bills.
</p>

<p class="drama">
TIMON.<br>
Knock me down with ’em! Cleave me to the girdle.
</p>

<p class="drama">
LUCIUS.<br>
Alas, my lord—
</p>

<p class="drama">
TIMON.<br>
Cut my heart in sums!
</p>

<p class="drama">
TITUS.<br>
Mine, fifty talents.
</p>

<p class="drama">
TIMON.<br>
Tell out my blood.
</p>

<p class="drama">
LUCIUS.<br>
Five thousand crowns, my lord.
</p>

<p class="drama">
TIMON.<br>
Five thousand drops pays that. What yours, and yours?
</p>

<p class="drama">
FIRST VARRO’S SERVANT.<br>
My lord—
</p>

<p class="drama">
SECOND VARRO’S SERVANT.<br>
My lord—
</p>

<p class="drama">
TIMON.<br>
Tear me, take me, and the gods fall upon you!
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
HORTENSIUS.<br>
Faith, I perceive our masters may throw their caps at their money. These debts
may well be called desperate ones, for a madman owes ’em.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<p class="scenedesc">
Enter <span class="charname">Timon</span> and
<span class="charname">Flavius</span>.
</p>

<p class="drama">
TIMON.<br>
They have e’en put my breath from me, the slaves.<br>
Creditors? Devils!
</p>

<p class="drama">
FLAVIUS.<br>
My dear lord—
</p>

<p class="drama">
TIMON.<br>
What if it should be so?
</p>

<p class="drama">
FLAVIUS.<br>
My lord—
</p>

<p class="drama">
TIMON.<br>
I’ll have it so.—My steward!
</p>

<p class="drama">
FLAVIUS.<br>
Here, my lord.
</p>

<p class="drama">
TIMON.<br>
So fitly? Go, bid all my friends again,<br>
Lucius, Lucullus, and Sempronius, all.<br>
I’ll once more feast the rascals.
</p>

<p class="drama">
FLAVIUS.<br>
O my lord,<br>
You only speak from your distracted soul;<br>
There is not so much left to furnish out<br>
A moderate table.
</p>

<p class="drama">
TIMON.<br>
Be it not in thy care. Go,<br>
I charge thee, invite them all. Let in the tide<br>
Of knaves once more. My cook and I’ll provide.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneIII_33.5"></a><b>SCENE V. The same. The senate house</b></h3>

<p class="scenedesc">
Enter three <span class="charname">Senators</span> at one door,
<span class="charname">Alcibiades</span> meeting them, with Attendants.
</p>

<p class="drama">
FIRST SENATOR.<br>
My lord, you have my voice to ’t. The fault’s<br>
Bloody. ’Tis necessary he should die.<br>
Nothing emboldens sin so much as mercy.
</p>

<p class="drama">
SECOND SENATOR.<br>
Most true, the law shall bruise ’em.
</p>

<p class="drama">
ALCIBIADES.<br>
Honour, health, and compassion to the senate!
</p>

<p class="drama">
FIRST SENATOR.<br>
Now, captain?
</p>

<p class="drama">
ALCIBIADES.<br>
I am a humble suitor to your virtues,<br>
For pity is the virtue of the law,<br>
And none but tyrants use it cruelly.<br>
It pleases time and fortune to lie heavy<br>
Upon a friend of mine, who in hot blood<br>
Hath stepped into the law, which is past depth<br>
To those that without heed do plunge into’t.<br>
He is a man, setting his fate aside,<br>
Of comely virtues,<br>
Nor did he soil the fact with cowardice—<br>
An honour in him which buys out his fault—<br>
But with a noble fury and fair spirit,<br>
Seeing his reputation touched to death,<br>
He did oppose his foe;<br>
And with such sober and unnoted passion<br>
He did behave his anger, ere ’twas spent,<br>
As if he had but proved an argument.
</p>

<p class="drama">
FIRST SENATOR.<br>
You undergo too strict a paradox,<br>
Striving to make an ugly deed look fair.<br>
Your words have took such pains as if they laboured<br>
To bring manslaughter into form and set quarrelling<br>
Upon the head of valour, which indeed<br>
Is valour misbegot and came into the world<br>
When sects and factions were newly born.<br>
He’s truly valiant that can wisely suffer<br>
The worst that man can breathe, and make his wrongs<br>
His outsides to wear them like his raiment, carelessly,<br>
And ne’er prefer his injuries to his heart,<br>
To bring it into danger.<br>
If wrongs be evils and enforce us kill,<br>
What folly ’tis to hazard life for ill!
</p>

<p class="drama">
ALCIBIADES.<br>
My lord—
</p>

<p class="drama">
FIRST SENATOR.<br>
You cannot make gross sins look clear.<br>
To revenge is no valour, but to bear.
</p>

<p class="drama">
ALCIBIADES.<br>
My lords, then, under favour, pardon me<br>
If I speak like a captain.<br>
Why do fond men expose themselves to battle<br>
And not endure all threats? Sleep upon’t,<br>
And let the foes quietly cut their throats<br>
Without repugnancy? If there be<br>
Such valour in the bearing, what make we<br>
Abroad? Why, then, women are more valiant<br>
That stay at home, if bearing carry it,<br>
And the ass more captain than the lion, the felon<br>
Loaden with irons wiser than the judge,<br>
If wisdom be in suffering. O my lords,<br>
As you are great, be pitifully good.<br>
Who cannot condemn rashness in cold blood?<br>
To kill, I grant, is sin’s extremest gust,<br>
But in defence, by mercy, ’tis most just.<br>
To be in anger is impiety,<br>
But who is man that is not angry?<br>
Weigh but the crime with this.
</p>

<p class="drama">
SECOND SENATOR.<br>
You breathe in vain.
</p>

<p class="drama">
ALCIBIADES.<br>
In vain? His service done<br>
At Lacedaemon and Byzantium<br>
Were a sufficient briber for his life.
</p>

<p class="drama">
FIRST SENATOR.<br>
What’s that?
</p>

<p class="drama">
ALCIBIADES.<br>
Why, I say, my lords, has done fair service<br>
And slain in fight many of your enemies.<br>
How full of valour did he bear himself<br>
In the last conflict, and made plenteous wounds!
</p>

<p class="drama">
SECOND SENATOR.<br>
He has made too much plenty with ’em.<br>
He’s a sworn rioter. He has a sin<br>
That often drowns him and takes his valour prisoner.<br>
If there were no foes, that were enough<br>
To overcome him. In that beastly fury,<br>
He has been known to commit outrages<br>
And cherish factions. ’Tis inferred to us<br>
His days are foul and his drink dangerous.
</p>

<p class="drama">
FIRST SENATOR.<br>
He dies.
</p>

<p class="drama">
ALCIBIADES.<br>
Hard fate! He might have died in war.<br>
My lords, if not for any parts in him,<br>
Though his right arm might purchase his own time<br>
And be in debt to none, yet, more to move you,<br>
Take my deserts to his and join ’em both.<br>
And, for I know your reverend ages love<br>
Security, I’ll pawn my victories, all<br>
My honour, to you upon his good returns.<br>
If by this crime he owes the law his life,<br>
Why, let the war receive’t in valiant gore,<br>
For law is strict, and war is nothing more.
</p>

<p class="drama">
FIRST SENATOR.<br>
We are for law. He dies. Urge it no more,<br>
On height of our displeasure. Friend or brother,<br>
He forfeits his own blood that spills another.
</p>

<p class="drama">
ALCIBIADES.<br>
Must it be so? It must not be.<br>
My lords, I do beseech you, know me.
</p>

<p class="drama">
SECOND SENATOR.<br>
How?
</p>

<p class="drama">
ALCIBIADES.<br>
Call me to your remembrances.
</p>

<p class="drama">
THIRD SENATOR.<br>
What?
</p>

<p class="drama">
ALCIBIADES.<br>
I cannot think but your age has forgot me,<br>
It could not else be I should prove so base<br>
To sue and be denied such common grace.<br>
My wounds ache at you.
</p>

<p class="drama">
FIRST SENATOR.<br>
Do you dare our anger?<br>
’Tis in few words, but spacious in effect:<br>
We banish thee for ever.
</p>

<p class="drama">
ALCIBIADES.<br>
Banish me?<br>
Banish your dotage, banish usury,<br>
That makes the Senate ugly.
</p>

<p class="drama">
FIRST SENATOR.<br>
If, after two days’ shine, Athens contain thee,<br>
Attend our weightier judgment.<br>
And, not to swell our spirit,<br>
He shall be executed presently.
</p>

<p class="right">[<i>Exeunt <span class="charname">Senators</span>.</i>]</p>

<p class="drama">
ALCIBIADES.<br>
Now the gods keep you old enough, that you may live<br>
Only in bone, that none may look on you!<br>
I’m worse than mad. I have kept back their foes<br>
While they have told their money and let out<br>
Their coin upon large interest, I myself<br>
Rich only in large hurts. All those for this?<br>
Is this the balsam that the usuring senate<br>
Pours into captains’ wounds? Banishment.<br>
It comes not ill. I hate not to be banished.<br>
It is a cause worthy my spleen and fury,<br>
That I may strike at Athens. I’ll cheer up<br>
My discontented troops and lay for hearts.<br>
’Tis honour with most lands to be at odds.<br>
Soldiers should brook as little wrongs as gods.
</p>

<p class="right">[<i>Exit.</i>]</p>

<h3> <a id="sceneIII_33.6"></a><b>SCENE VI. A room of state in Timon’s house</b></h3>

<p class="scenedesc">
Music. Enter divers <span class="charname">Friends</span> at several doors.
</p>

<p class="drama">
FIRST FRIEND.<br>
The good time of day to you, sir.
</p>

<p class="drama">
SECOND FRIEND.<br>
I also wish it to you. I think this honourable lord did but try us this other
day.</p>

<p class="drama">
FIRST FRIEND.<br>
Upon that were my thoughts tiring when we encountered. I hope it is not so low
with him as he made it seem in the trial of his several friends.
</p>

<p class="drama">
SECOND FRIEND.<br>
It should not be, by the persuasion of his new feasting.
</p>

<p class="drama">
FIRST FRIEND.<br>
I should think so. He hath sent me an earnest inviting, which many my near
occasions did urge me to put off; but he hath conjured me beyond them, and I
must needs appear.</p>

<p class="drama">
SECOND FRIEND.<br>
In like manner was I in debt to my importunate business, but he would not hear
my excuse. I am sorry, when he sent to borrow of me, that my provision was
out.</p>

<p class="drama">
FIRST FRIEND.<br>
I am sick of that grief too, as I understand how all things go.
</p>

<p class="drama">
SECOND FRIEND.<br>
Every man here’s so. What would he have borrowed you?
</p>

<p class="drama">
FIRST FRIEND.<br>
A thousand pieces.
</p>

<p class="drama">
SECOND FRIEND.<br>
A thousand pieces!
</p>

<p class="drama">
FIRST FRIEND.<br>
What of you?
</p>

<p class="drama">
SECOND FRIEND.<br>
He sent to me, sir—here he comes.
</p>

<p class="scenedesc">
Enter <span class="charname">Timon</span> and Attendants.
</p>

<p class="drama">
TIMON.<br>
With all my heart, gentlemen both! And how fare you?
</p>

<p class="drama">
FIRST FRIEND.<br>
Ever at the best, hearing well of your lordship.
</p>

<p class="drama">
SECOND FRIEND.<br>
The swallow follows not summer more willing than we your lordship.</p>

<p class="drama">
TIMON.<br>
[<i>Aside</i>.] Nor more willingly leaves winter, such summer birds are men.
Gentlemen, our dinner will not recompense this long stay. Feast your ears with
the music awhile, if they will fare so harshly o’ th’ trumpet’s sound; we shall
to’t presently.
</p>

<p class="drama">
FIRST FRIEND.<br>
I hope it remains not unkindly with your lordship that I returned you an empty
messenger.
</p>

<p class="drama">
TIMON.<br>
O, sir, let it not trouble you.
</p>

<p class="drama">
SECOND FRIEND.<br>
My noble lord—
</p>

<p class="drama">
TIMON.<br>
Ah, my good friend, what cheer?
</p>

<p class="drama">
SECOND FRIEND.<br>
My most honourable lord, I am e’en sick of shame that when your lordship
this other day sent to me I was so unfortunate a beggar.
</p>

<p class="drama">
TIMON.<br>
Think not on’t, sir.
</p>

<p class="drama">
SECOND FRIEND.<br>
If you had sent but two hours before—
</p>

<p class="drama">
TIMON.<br>
Let it not cumber your better remembrance.
</p>

<p class="right">[<i>The banquet brought in.</i>]</p>

<p class="drama">
Come, bring in all together.</p>

<p class="drama">
SECOND FRIEND.<br>
All covered dishes!
</p>

<p class="drama">
FIRST FRIEND.<br>
Royal cheer, I warrant you.
</p>

<p class="drama">
THIRD FRIEND.<br>
Doubt not that, if money and the season can yield it.
</p>

<p class="drama">
FIRST FRIEND.<br>
How do you? What’s the news?
</p>

<p class="drama">
THIRD FRIEND.<br>
Alcibiades is banished. Hear you of it?
</p>

<p class="drama">
FIRST AND SECOND FRIENDS.<br>
Alcibiades banished?
</p>

<p class="drama">
THIRD FRIEND.<br>
’Tis so, be sure of it.
</p>

<p class="drama">
FIRST FRIEND.<br>
How, how?
</p>

<p class="drama">
SECOND FRIEND.<br>
I pray you, upon what?
</p>

<p class="drama">
TIMON.<br>
My worthy friends, will you draw near?
</p>

<p class="drama">
THIRD FRIEND.<br>
I’ll tell you more anon. Here’s a noble feast toward.
</p>

<p class="drama">
SECOND FRIEND.<br>
This is the old man still.
</p>

<p class="drama">
THIRD FRIEND.<br>
Will’t hold, will’t hold?
</p>

<p class="drama">
SECOND FRIEND.<br>
It does, but time will—and so—
</p>

<p class="drama">
THIRD FRIEND.<br>
I do conceive.
</p>

<p class="drama">
TIMON.<br>
Each man to his stool with that spur as he would to the lip of his mistress.
Your diet shall be in all places alike. Make not a city feast of it, to let the
meat cool ere we can agree upon the first place. Sit, sit. The gods require our
thanks:<br>
You great benefactors, sprinkle our society with thankfulness. For your own
gifts make yourselves praised, but reserve still to give, lest your deities be
despised. Lend to each man enough, that one need not lend to another; for, were
your godheads to borrow of men, men would forsake the gods. Make the meat be
beloved more than the man that gives it. Let no assembly of twenty be without a
score of villains. If there sit twelve women at the table, let a dozen of them
be as they are. The rest of your foes, O gods, the senators of Athens, together
with the common lag of people, what is amiss in them, you gods, make suitable
for destruction. For these my present friends, as they are to me nothing, so in
nothing bless them, and to nothing are they welcome.<br>
Uncover, dogs, and lap.
</p>

<p class="right">[<i>The dishes  are uncovered and prove to be full of lukewarm
water.</i>]</p>

<p class="drama">
SOME SPEAK.<br>
What does his lordship mean?
</p>

<p class="drama">
SOME OTHER.<br>
I know not.
</p>

<p class="drama">
TIMON.<br>
May you a better feast never behold,<br>
You knot of mouth-friends! Smoke and lukewarm water<br>
Is your perfection. This is Timon’s last,<br>
Who, stuck and spangled with your flatteries,<br>
Washes it off and sprinkles in your faces<br>
Your reeking villainy.
</p>

<p class="right">[<i>Throws water in their faces.</i>]</p>

<p class="drama">
Live loathed, and long,<br>
Most smiling, smooth, detested parasites,<br>
Courteous destroyers, affable wolves, meek bears,<br>
You fools of fortune, trencher-friends, time’s flies,<br>
Cap-and-knee slaves, vapours, and minute-jacks!<br>
Of man and beast the infinite malady<br>
Crust you quite o’er! [<i>They stand</i>.] What, dost thou go?<br>
Soft! Take thy physic first; thou too, and thou!<br>
Stay, I will lend thee money, borrow none.
</p>

<p class="right">[<i>He attacks them and forces them out.</i>]</p>

<p class="drama">
What, all in motion? Henceforth be no feast<br>
Whereat a villain’s not a welcome guest.<br>
Burn, house! Sink Athens! Henceforth hated be<br>
Of Timon man and all humanity!
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="scenedesc">
Enter Timon’s <span class="charname">Friends,</span> the Senators with other
Lords.
</p>

<p class="drama">
FIRST FRIEND.<br>
How now, my lords?
</p>

<p class="drama">
SECOND FRIEND.<br>
Know you the quality of Lord Timon’s fury?
</p>

<p class="drama">
THIRD FRIEND.<br>
Push! Did you see my cap?
</p>

<p class="drama">
FOURTH FRIEND.<br>
I have lost my gown.
</p>

<p class="drama">
FIRST FRIEND.<br>
He’s but a mad lord, and nought but humours sways him. He gave me a jewel th’
other day, and now he has beat it out of my hat. Did you see my jewel?
</p>

<p class="drama">
THIRD FRIEND.<br>
Did you see my cap?
</p>

<p class="drama">
SECOND FRIEND.<br>
Here ’tis.
</p>

<p class="drama">
FOURTH FRIEND.<br>
Here lies my gown.
</p>

<p class="drama">
FIRST FRIEND.<br>
Let’s make no stay.
</p>

<p class="drama">
SECOND FRIEND.<br>
Lord Timon’s mad.
</p>

<p class="drama">
THIRD FRIEND.<br>
I feel’t upon my bones.
</p>

<p class="drama">
FOURTH FRIEND.<br>
One day he gives us diamonds, next day stones.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

