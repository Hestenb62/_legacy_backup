<h2><a id="sceneI_10.0"></a>INDUCTION</h2>

<p class="center">
Warkworth. Before the castle.
</p>

<p class="scenedesc">Enter <span class="charname">Rumour</span>, painted full
of tongues.</p>

<p class="drama">
RUMOUR.<br>
Open your ears; for which of you will stop<br>
The vent of hearing when loud Rumour speaks?<br>
I, from the orient to the drooping west,<br>
Making the wind my post-horse, still unfold<br>
The acts commenced on this ball of earth.<br>
Upon my tongues continual slanders ride,<br>
The which in every language I pronounce,<br>
Stuffing the ears of men with false reports.<br>
I speak of peace, while covert enmity<br>
Under the smile of safety wounds the world.<br>
And who but Rumour, who but only I,<br>
Make fearful musters and prepared defence,<br>
Whiles the big year, swoln with some other grief,<br>
Is thought with child by the stern tyrant war,<br>
And no such matter? Rumour is a pipe<br>
Blown by surmises, jealousies, conjectures,<br>
And of so easy and so plain a stop<br>
That the blunt monster with uncounted heads,<br>
The still-discordant wav’ring multitude,<br>
Can play upon it. But what need I thus<br>
My well-known body to anatomize<br>
Among my household? Why is Rumour here?<br>
I run before King Harry’s victory,<br>
Who in a bloody field by Shrewsbury<br>
Hath beaten down young Hotspur and his troops,<br>
Quenching the flame of bold rebellion<br>
Even with the rebels’ blood. But what mean I<br>
To speak so true at first? My office is<br>
To noise abroad that Harry Monmouth fell<br>
Under the wrath of noble Hotspur’s sword,<br>
And that the King before the Douglas’ rage<br>
Stoop’d his anointed head as low as death.<br>
This have I rumour’d through the peasant towns<br>
Between that royal field of Shrewsbury<br>
And this worm-eaten hold of ragged stone,<br>
Where Hotspur’s father, old Northumberland,<br>
Lies crafty-sick. The posts come tiring on,<br>
And not a man of them brings other news<br>
Than they have learnt of me. From Rumour’s tongues<br>
They bring smooth comforts false, worse than true wrongs.
</p>

<p class="right"> [<i>Exit.</i>]</p>

