<h2> <a id="sceneI_32.1"></a><b>ACT I</b></h2>

<h3> <b>SCENE I. On a ship at sea; a tempestuous noise of thunder and lightning
heard.</b></h3>

<p class="scenedesc">Enter a <span class="charname">Shipmaster</span> and a
<span class="charname">Boatswain</span> severally.
</p>

<p class="drama">
MASTER.<br>
Boatswain!
</p>

<p class="drama">
BOATSWAIN.<br>
Here, master: what cheer?
</p>

<p class="drama">
MASTER.<br>
Good! Speak to the mariners: fall to ’t yarely, or we run ourselves
aground: bestir, bestir.
</p>

<p class="right"> [<i>Exit.</i>]</p>

<p class="scenedesc">Enter <span class="charname">Mariners</span>.
</p>

<p class="drama">
BOATSWAIN.<br>
Heigh, my hearts! cheerly, cheerly, my hearts! yare, yare! Take in the topsail.
Tend to th’ master’s whistle. Blow till thou burst thy wind, if
room enough.
</p>

<p class="scenedesc">Enter <span class="charname">Alonso, Sebastian, Antonio,
Ferdinand, Gonzalo</span> and others.
</p>

<p class="drama">
ALONSO.<br>
Good boatswain, have care. Where’s the master?<br>
Play the men.
</p>

<p class="drama">
BOATSWAIN.<br>
I pray now, keep below.
</p>

<p class="drama">
ANTONIO.<br>
Where is the master, boson?
</p>

<p class="drama">
BOATSWAIN.<br>
Do you not hear him? You mar our labour: keep your cabins: you do assist the
storm.
</p>

<p class="drama">
GONZALO.<br>
Nay, good, be patient.
</p>

<p class="drama">
BOATSWAIN.<br>
When the sea is. Hence! What cares these roarers for the name of king? To
cabin! silence! Trouble us not.
</p>

<p class="drama">
GONZALO.<br>
Good, yet remember whom thou hast aboard.
</p>

<p class="drama">
BOATSWAIN.<br>
None that I more love than myself. You are a counsellor: if you can command
these elements to silence, and work the peace of the present, we will not hand
a rope more. Use your authority: if you cannot, give thanks you have lived so
long, and make yourself ready in your cabin for the mischance of the hour, if
it so hap.—Cheerly, good hearts!—Out of our way, I say.
</p>

<p class="right"> [<i>Exit.</i>]</p>

<p class="drama">
GONZALO.<br>
I have great comfort from this fellow. Methinks he hath no drowning mark upon
him. His complexion is perfect gallows. Stand fast, good Fate, to his hanging!
Make the rope of his destiny our cable, for our own doth little advantage! If
he be not born to be hang’d, our case is miserable.
</p>

<p class="right"> [<i>Exeunt.</i>]</p>

<p class="scenedesc">Re-enter <span class="charname">Boatswain</span>.
</p>

<p class="drama">
BOATSWAIN.<br>
Down with the topmast! yare! lower, lower! Bring her to try wi’ th’
maincourse.
</p>

<p class="right"> [<i>A cry within.</i>]</p>

<p class="drama">
 A plague upon this howling! They are louder than the weather or our
office.
</p>

<p class="scenedesc">Enter <span class="charname">Sebastian, Antonio</span> and
<span class="charname">Gonzalo</span>.</p>

<p class="drama">
Yet again! What do you here? Shall we give o’er, and drown? Have you a
mind to sink?
</p>

<p class="drama">
SEBASTIAN.<br>
A pox o’ your throat, you bawling, blasphemous, incharitable dog!
</p>

<p class="drama">
BOATSWAIN.<br>
Work you, then.
</p>

<p class="drama">
ANTONIO.<br>
Hang, cur, hang, you whoreson, insolent noisemaker! We are less afraid to be
drowned than thou art.
</p>

<p class="drama">
GONZALO.<br>
I’ll warrant him for drowning, though the ship were no stronger than a
nutshell, and as leaky as an unstanched wench.
</p>

<p class="drama">
BOATSWAIN.<br>
Lay her a-hold, a-hold! Set her two courses: off to sea again: lay her off.
</p>

<p class="scenedesc">Enter <span class="charname">Mariners,</span> wet.
</p>

<p class="drama">
MARINERS.<br>
All lost! to prayers, to prayers! all lost!
</p>

<p class="right"> [<i>Exeunt.</i>]</p>

<p class="drama">
BOATSWAIN.<br>
What, must our mouths be cold?
</p>

<p class="drama">
GONZALO.<br>
The King and Prince at prayers! Let’s assist them,<br>
For our case is as theirs.
</p>

<p class="drama">
SEBASTIAN.<br>
I am out of patience.
</p>

<p class="drama">
ANTONIO.<br>
We are merely cheated of our lives by drunkards.<br>
This wide-chapp’d rascal—would thou might’st lie drowning<br>
The washing of ten tides!
</p>

<p class="drama">
GONZALO.<br>
He’ll be hang’d yet,<br>
Though every drop of water swear against it,<br>
And gape at wid’st to glut him.
</p>

<p class="drama">
<i>A confused noise within: </i>“Mercy on us!”—<br>
“We split, we split!”—“Farewell, my wife and children!”—<br>
“Farewell, brother!”—“We split, we split, we split!”
</p>

<p class="drama">
ANTONIO.<br>
Let’s all sink wi’ th’ King.
</p>

<p class="right"> [<i>Exit.</i>]</p>

<p class="drama">
SEBASTIAN.<br>
Let’s take leave of him.
</p>

<p class="right"> [<i>Exit.</i>]</p>

<p class="drama">
GONZALO.<br>
Now would I give a thousand furlongs of sea for an acre of barren ground. Long
heath, brown furze, anything. The wills above be done! but I would fain die a
dry death.
</p>

<p class="right"> [<i>Exit.</i>]</p>

<h3> <a id="sceneI_32.2"></a><b>SCENE II. The Island. Before the cell of Prospero.</b></h3>

<p class="scenedesc">Enter <span class="charname">Prospero</span> and
<span class="charname">Miranda</span>.</p>

<p class="drama">
MIRANDA.<br>
If by your art, my dearest father, you have<br>
Put the wild waters in this roar, allay them.<br>
The sky, it seems, would pour down stinking pitch,<br>
But that the sea, mounting to th’ welkin’s cheek,<br>
Dashes the fire out. O! I have suffered<br>
With those that I saw suffer! A brave vessel,<br>
Who had, no doubt, some noble creature in her,<br>
Dash’d all to pieces. O, the cry did knock<br>
Against my very heart. Poor souls, they perish’d.<br>
Had I been any god of power, I would<br>
Have sunk the sea within the earth, or ere<br>
It should the good ship so have swallow’d and<br>
The fraughting souls within her.
</p>

<p class="drama">
PROSPERO.<br>
Be collected:<br>
No more amazement: tell your piteous heart<br>
There’s no harm done.
</p>

<p class="drama">
MIRANDA.<br>
O, woe the day!
</p>

<p class="drama">
PROSPERO.<br>
No harm.<br>
I have done nothing but in care of thee,<br>
Of thee, my dear one, thee, my daughter, who<br>
Art ignorant of what thou art, nought knowing<br>
Of whence I am, nor that I am more better<br>
Than Prospero, master of a full poor cell,<br>
And thy no greater father.
</p>

<p class="drama">
MIRANDA.<br>
More to know<br>
Did never meddle with my thoughts.
</p>

<p class="drama">
PROSPERO.<br>
’Tis time<br>
I should inform thee farther. Lend thy hand,<br>
And pluck my magic garment from me.—So:
</p>

<p class="right"> [<i>Lays down his mantle.</i>]</p>

<p class="drama">
Lie there my art. Wipe thou thine eyes; have comfort.<br>
The direful spectacle of the wrack, which touch’d<br>
The very virtue of compassion in thee,<br>
I have with such provision in mine art<br>
So safely ordered that there is no soul—<br>
No, not so much perdition as an hair<br>
Betid to any creature in the vessel<br>
Which thou heard’st cry, which thou saw’st sink. Sit down;<br>
For thou must now know farther.
</p>

<p class="drama">
MIRANDA.<br>
You have often<br>
Begun to tell me what I am, but stopp’d,<br>
And left me to a bootless inquisition,<br>
Concluding “Stay; not yet.”
</p>

<p class="drama">
PROSPERO.<br>
The hour’s now come,<br>
The very minute bids thee ope thine ear;<br>
Obey, and be attentive. Canst thou remember<br>
A time before we came unto this cell?<br>
I do not think thou canst, for then thou wast not<br>
Out three years old.
</p>

<p class="drama">
MIRANDA.<br>
Certainly, sir, I can.
</p>

<p class="drama">
PROSPERO.<br>
By what? By any other house, or person?<br>
Of anything the image, tell me, that<br>
Hath kept with thy remembrance.
</p>

<p class="drama">
MIRANDA.<br>
’Tis far off,<br>
And rather like a dream than an assurance<br>
That my remembrance warrants. Had I not<br>
Four or five women once that tended me?
</p>

<p class="drama">
PROSPERO.<br>
Thou hadst, and more, Miranda. But how is it<br>
That this lives in thy mind? What seest thou else<br>
In the dark backward and abysm of time?<br>
If thou rememb’rest aught ere thou cam’st here,<br>
How thou cam’st here, thou mayst.
</p>

<p class="drama">
MIRANDA.<br>
But that I do not.
</p>

<p class="drama">
PROSPERO.<br>
Twelve year since, Miranda, twelve year since,<br>
Thy father was the Duke of Milan, and<br>
A prince of power.
</p>

<p class="drama">
MIRANDA.<br>
Sir, are not you my father?
</p>

<p class="drama">
PROSPERO.<br>
Thy mother was a piece of virtue, and<br>
She said thou wast my daughter. And thy father<br>
Was Duke of Milan, and his only heir<br>
And princess, no worse issued.
</p>

<p class="drama">
MIRANDA.<br>
O, the heavens!<br>
What foul play had we that we came from thence?<br>
Or blessed was’t we did?
</p>

<p class="drama">
PROSPERO.<br>
Both, both, my girl.<br>
By foul play, as thou say’st, were we heav’d thence;<br>
But blessedly holp hither.
</p>

<p class="drama">
MIRANDA.<br>
O, my heart bleeds<br>
To think o’ th’ teen that I have turn’d you to,<br>
Which is from my remembrance. Please you, farther.
</p>

<p class="drama">
PROSPERO.<br>
My brother and thy uncle, call’d Antonio—<br>
I pray thee, mark me, that a brother should<br>
Be so perfidious!—he whom next thyself<br>
Of all the world I lov’d, and to him put<br>
The manage of my state; as at that time<br>
Through all the signories it was the first,<br>
And Prospero the prime duke, being so reputed<br>
In dignity, and for the liberal arts,<br>
Without a parallel: those being all my study,<br>
The government I cast upon my brother,<br>
And to my state grew stranger, being transported<br>
And rapt in secret studies. Thy false uncle—<br>
Dost thou attend me?
</p>

<p class="drama">
MIRANDA.<br>
Sir, most heedfully.
</p>

<p class="drama">
PROSPERO.<br>
Being once perfected how to grant suits,<br>
How to deny them, who t’ advance, and who<br>
To trash for over-topping, new created<br>
The creatures that were mine, I say, or chang’d ’em,<br>
Or else new form’d ’em: having both the key<br>
Of officer and office, set all hearts i’ th’ state<br>
To what tune pleas’d his ear: that now he was<br>
The ivy which had hid my princely trunk,<br>
And suck’d my verdure out on ’t. Thou attend’st not.
</p>

<p class="drama">
MIRANDA.<br>
O, good sir! I do.
</p>

<p class="drama">
PROSPERO.<br>
I pray thee, mark me.<br>
I, thus neglecting worldly ends, all dedicated<br>
To closeness and the bettering of my mind<br>
With that which, but by being so retir’d,<br>
O’er-priz’d all popular rate, in my false brother<br>
Awak’d an evil nature; and my trust,<br>
Like a good parent, did beget of him<br>
A falsehood in its contrary as great<br>
As my trust was; which had indeed no limit,<br>
A confidence sans bound. He being thus lorded,<br>
Not only with what my revenue yielded,<br>
But what my power might else exact, like one<br>
Who having into truth, by telling of it,<br>
Made such a sinner of his memory,<br>
To credit his own lie, he did believe<br>
He was indeed the Duke; out o’ the substitution,<br>
And executing th’ outward face of royalty,<br>
With all prerogative. Hence his ambition growing—<br>
Dost thou hear?
</p>

<p class="drama">
MIRANDA.<br>
Your tale, sir, would cure deafness.
</p>

<p class="drama">
PROSPERO.<br>
To have no screen between this part he play’d<br>
And him he play’d it for, he needs will be<br>
Absolute Milan. Me, poor man, my library<br>
Was dukedom large enough: of temporal royalties<br>
He thinks me now incapable; confederates,<br>
So dry he was for sway, wi’ th’ King of Naples<br>
To give him annual tribute, do him homage,<br>
Subject his coronet to his crown, and bend<br>
The dukedom, yet unbow’d—alas, poor Milan!—<br>
To most ignoble stooping.
</p>

<p class="drama">
MIRANDA.<br>
O the heavens!
</p>

<p class="drama">
PROSPERO.<br>
Mark his condition, and the event; then tell me<br>
If this might be a brother.
</p>

<p class="drama">
MIRANDA.<br>
I should sin<br>
To think but nobly of my grandmother:<br>
Good wombs have borne bad sons.
</p>

<p class="drama">
PROSPERO.<br>
Now the condition.<br>
This King of Naples, being an enemy<br>
To me inveterate, hearkens my brother’s suit;<br>
Which was, that he, in lieu o’ th’ premises<br>
Of homage and I know not how much tribute,<br>
Should presently extirpate me and mine<br>
Out of the dukedom, and confer fair Milan,<br>
With all the honours on my brother: whereon,<br>
A treacherous army levied, one midnight<br>
Fated to th’ purpose, did Antonio open<br>
The gates of Milan; and, i’ th’ dead of darkness,<br>
The ministers for th’ purpose hurried thence<br>
Me and thy crying self.
</p>

<p class="drama">
MIRANDA.<br>
Alack, for pity!<br>
I, not rememb’ring how I cried out then,<br>
Will cry it o’er again: it is a hint<br>
That wrings mine eyes to ’t.
</p>

<p class="drama">
PROSPERO.<br>
Hear a little further,<br>
And then I’ll bring thee to the present business<br>
Which now’s upon us; without the which this story<br>
Were most impertinent.
</p>

<p class="drama">
MIRANDA.<br>
Wherefore did they not<br>
That hour destroy us?
</p>

<p class="drama">
PROSPERO.<br>
Well demanded, wench:<br>
My tale provokes that question. Dear, they durst not,<br>
So dear the love my people bore me, nor set<br>
A mark so bloody on the business; but<br>
With colours fairer painted their foul ends.<br>
In few, they hurried us aboard a bark,<br>
Bore us some leagues to sea, where they prepared<br>
A rotten carcass of a butt, not rigg’d,<br>
Nor tackle, sail, nor mast; the very rats<br>
Instinctively have quit it. There they hoist us,<br>
To cry to th’ sea, that roar’d to us; to sigh<br>
To th’ winds, whose pity, sighing back again,<br>
Did us but loving wrong.
</p>

<p class="drama">
MIRANDA.<br>
Alack, what trouble<br>
Was I then to you!
</p>

<p class="drama">
PROSPERO.<br>
O, a cherubin<br>
Thou wast that did preserve me. Thou didst smile,<br>
Infused with a fortitude from heaven,<br>
When I have deck’d the sea with drops full salt,<br>
Under my burden groan’d: which rais’d in me<br>
An undergoing stomach, to bear up<br>
Against what should ensue.
</p>

<p class="drama">
MIRANDA.<br>
How came we ashore?
</p>

<p class="drama">
PROSPERO.<br>
By Providence divine.<br>
Some food we had and some fresh water that<br>
A noble Neapolitan, Gonzalo,<br>
Out of his charity, who being then appointed<br>
Master of this design, did give us, with<br>
Rich garments, linens, stuffs, and necessaries,<br>
Which since have steaded much: so, of his gentleness,<br>
Knowing I lov’d my books, he furnish’d me<br>
From mine own library with volumes that<br>
I prize above my dukedom.
</p>

<p class="drama">
MIRANDA.<br>
Would I might<br>
But ever see that man!
</p>

<p class="drama">
PROSPERO.<br>
Now I arise.<br>
Sit still, and hear the last of our sea-sorrow.<br>
Here in this island we arriv’d; and here<br>
Have I, thy schoolmaster, made thee more profit<br>
Than other princes can, that have more time<br>
For vainer hours, and tutors not so careful.
</p>

<p class="drama">
MIRANDA.<br>
Heavens thank you for ’t! And now, I pray you, sir,<br>
For still ’tis beating in my mind, your reason<br>
For raising this sea-storm?
</p>

<p class="drama">
PROSPERO.<br>
Know thus far forth.<br>
By accident most strange, bountiful Fortune,<br>
Now my dear lady, hath mine enemies<br>
Brought to this shore; and by my prescience<br>
I find my zenith doth depend upon<br>
A most auspicious star, whose influence<br>
If now I court not but omit, my fortunes<br>
Will ever after droop. Here cease more questions;<br>
Thou art inclin’d to sleep; ’tis a good dulness,<br>
And give it way. I know thou canst not choose.
</p>

<p class="right"> [<i><span class="charname">Miranda</span> sleeps.</i>]</p>

<p class="drama">
Come away, servant, come! I am ready now.<br>
Approach, my Ariel. Come!
</p>

<p class="scenedesc">Enter <span class="charname">Ariel</span>.
</p>

<p class="drama">
ARIEL.<br>
All hail, great master! grave sir, hail! I come<br>
To answer thy best pleasure; be’t to fly,<br>
To swim, to dive into the fire, to ride<br>
On the curl’d clouds, to thy strong bidding task<br>
Ariel and all his quality.
</p>

<p class="drama">
PROSPERO.<br>
Hast thou, spirit,<br>
Perform’d to point the tempest that I bade thee?
</p>

<p class="drama">
ARIEL.<br>
To every article.<br>
I boarded the King’s ship; now on the beak,<br>
Now in the waist, the deck, in every cabin,<br>
I flam’d amazement; sometime I’d divide,<br>
And burn in many places; on the topmast,<br>
The yards, and bowsprit, would I flame distinctly,<br>
Then meet and join. Jove’s lightning, the precursors<br>
O’ th’ dreadful thunder-claps, more momentary<br>
And sight-outrunning were not: the fire and cracks<br>
Of sulphurous roaring the most mighty Neptune<br>
Seem to besiege and make his bold waves tremble,<br>
Yea, his dread trident shake.
</p>

<p class="drama">
PROSPERO.<br>
My brave spirit!<br>
Who was so firm, so constant, that this coil<br>
Would not infect his reason?
</p>

<p class="drama">
ARIEL.<br>
Not a soul<br>
But felt a fever of the mad, and play’d<br>
Some tricks of desperation. All but mariners<br>
Plunged in the foaming brine and quit the vessel,<br>
Then all afire with me: the King’s son, Ferdinand,<br>
With hair up-staring—then like reeds, not hair—<br>
Was the first man that leapt; cried “Hell is empty,<br>
And all the devils are here.”
</p>

<p class="drama">
PROSPERO.<br>
Why, that’s my spirit!<br>
But was not this nigh shore?
</p>

<p class="drama">
ARIEL.<br>
Close by, my master.
</p>

<p class="drama">
PROSPERO.<br>
But are they, Ariel, safe?
</p>

<p class="drama">
ARIEL.<br>
Not a hair perish’d;<br>
On their sustaining garments not a blemish,<br>
But fresher than before: and, as thou bad’st me,<br>
In troops I have dispers’d them ’bout the isle.<br>
The King’s son have I landed by himself,<br>
Whom I left cooling of the air with sighs<br>
In an odd angle of the isle, and sitting,<br>
His arms in this sad knot.
</p>

<p class="drama">
PROSPERO.<br>
Of the King’s ship<br>
The mariners, say how thou hast dispos’d,<br>
And all the rest o’ th’ fleet?
</p>

<p class="drama">
ARIEL.<br>
Safely in harbour<br>
Is the King’s ship; in the deep nook, where once<br>
Thou call’dst me up at midnight to fetch dew<br>
From the still-vex’d Bermoothes; there she’s hid:<br>
The mariners all under hatches stowed;<br>
Who, with a charm join’d to their suff’red labour,<br>
I have left asleep: and for the rest o’ th’ fleet,<br>
Which I dispers’d, they all have met again,<br>
And are upon the Mediterranean flote<br>
Bound sadly home for Naples,<br>
Supposing that they saw the King’s ship wrack’d,<br>
And his great person perish.
</p>

<p class="drama">
PROSPERO.<br>
Ariel, thy charge<br>
Exactly is perform’d; but there’s more work.<br>
What is the time o’ th’ day?
</p>

<p class="drama">
ARIEL.<br>
Past the mid season.
</p>

<p class="drama">
PROSPERO.<br>
At least two glasses. The time ’twixt six and now<br>
Must by us both be spent most preciously.
</p>

<p class="drama">
ARIEL.<br>
Is there more toil? Since thou dost give me pains,<br>
Let me remember thee what thou hast promis’d,<br>
Which is not yet perform’d me.
</p>

<p class="drama">
PROSPERO.<br>
How now! moody?<br>
What is’t thou canst demand?
</p>

<p class="drama">
ARIEL.<br>
My liberty.
</p>

<p class="drama">
PROSPERO.<br>
Before the time be out? No more!
</p>

<p class="drama">
ARIEL.<br>
I prithee,<br>
Remember I have done thee worthy service;<br>
Told thee no lies, made no mistakings, serv’d<br>
Without or grudge or grumblings: thou didst promise<br>
To bate me a full year.
</p>

<p class="drama">
PROSPERO.<br>
Dost thou forget<br>
From what a torment I did free thee?
</p>

<p class="drama">
ARIEL.<br>
No.
</p>

<p class="drama">
PROSPERO.<br>
Thou dost, and think’st it much to tread the ooze<br>
Of the salt deep,<br>
To run upon the sharp wind of the north,<br>
To do me business in the veins o’ th’ earth<br>
When it is bak’d with frost.
</p>

<p class="drama">
ARIEL.<br>
I do not, sir.
</p>

<p class="drama">
PROSPERO.<br>
Thou liest, malignant thing! Hast thou forgot<br>
The foul witch Sycorax, who with age and envy<br>
Was grown into a hoop? Hast thou forgot her?
</p>

<p class="drama">
ARIEL.<br>
No, sir.
</p>

<p class="drama">
PROSPERO.<br>
Thou hast. Where was she born? Speak; tell me.
</p>

<p class="drama">
ARIEL.<br>
Sir, in Argier.
</p>

<p class="drama">
PROSPERO.<br>
O, was she so? I must<br>
Once in a month recount what thou hast been,<br>
Which thou forget’st. This damn’d witch Sycorax,<br>
For mischiefs manifold, and sorceries terrible<br>
To enter human hearing, from Argier,<br>
Thou know’st, was banish’d: for one thing she did<br>
They would not take her life. Is not this true?
</p>

<p class="drama">
ARIEL.<br>
Ay, sir.
</p>

<p class="drama">
PROSPERO.<br>
This blue-ey’d hag was hither brought with child,<br>
And here was left by th’ sailors. Thou, my slave,<br>
As thou report’st thyself, wast then her servant;<br>
And, for thou wast a spirit too delicate<br>
To act her earthy and abhorr’d commands,<br>
Refusing her grand hests, she did confine thee,<br>
By help of her more potent ministers,<br>
And in her most unmitigable rage,<br>
Into a cloven pine; within which rift<br>
Imprison’d, thou didst painfully remain<br>
A dozen years; within which space she died,<br>
And left thee there, where thou didst vent thy groans<br>
As fast as mill-wheels strike. Then was this island—<br>
Save for the son that she did litter here,<br>
A freckl’d whelp, hag-born—not honour’d with<br>
A human shape.
</p>

<p class="drama">
ARIEL.<br>
Yes, Caliban her son.
</p>

<p class="drama">
PROSPERO.<br>
Dull thing, I say so; he, that Caliban,<br>
Whom now I keep in service. Thou best know’st<br>
What torment I did find thee in; thy groans<br>
Did make wolves howl, and penetrate the breasts<br>
Of ever-angry bears: it was a torment<br>
To lay upon the damn’d, which Sycorax<br>
Could not again undo; it was mine art,<br>
When I arriv’d and heard thee, that made gape<br>
The pine, and let thee out.
</p>

<p class="drama">
ARIEL.<br>
I thank thee, master.
</p>

<p class="drama">
PROSPERO.<br>
If thou more murmur’st, I will rend an oak<br>
And peg thee in his knotty entrails till<br>
Thou hast howl’d away twelve winters.
</p>

<p class="drama">
ARIEL.<br>
Pardon, master:<br>
I will be correspondent to command,<br>
And do my spriting gently.
</p>

<p class="drama">
PROSPERO.<br>
Do so; and after two days<br>
I will discharge thee.
</p>

<p class="drama">
ARIEL.<br>
That’s my noble master!<br>
What shall I do? Say what? What shall I do?
</p>

<p class="drama">
PROSPERO.<br>
Go make thyself like a nymph o’ th’ sea. Be subject<br>
To no sight but thine and mine; invisible<br>
To every eyeball else. Go, take this shape,<br>
And hither come in ’t. Go, hence with diligence!
</p>

<p class="right"> [<i>Exit <span class="charname">Ariel</span>.</i>]</p>

<p class="drama">
Awake, dear heart, awake! thou hast slept well;<br>
Awake!
</p>

<p class="drama">
MIRANDA.<br>
[<i>Waking.</i>] The strangeness of your story put<br>
Heaviness in me.
</p>

<p class="drama">
PROSPERO.<br>
Shake it off. Come on;<br>
We’ll visit Caliban my slave, who never<br>
Yields us kind answer.
</p>

<p class="drama">
MIRANDA.<br>
’Tis a villain, sir,<br>
I do not love to look on.
</p>

<p class="drama">
PROSPERO.<br>
But as ’tis,<br>
We cannot miss him: he does make our fire,<br>
Fetch in our wood; and serves in offices<br>
That profit us. What ho! slave! Caliban!<br>
Thou earth, thou! Speak.
</p>

<p class="drama">
CALIBAN.<br>
[<i>Within.</i>] There’s wood enough within.
</p>

<p class="drama">
PROSPERO.<br>
Come forth, I say; there’s other business for thee.<br>
Come, thou tortoise! when?
</p>

<p class="scenedesc">Re-enter <span class="charname">Ariel</span> like a
water-nymph.</p>

<p class="drama">
Fine apparition! My quaint Ariel,<br>
Hark in thine ear.
</p>

<p class="drama">
ARIEL.<br>
My lord, it shall be done.
</p>

<p class="right"> [<i>Exit.</i>]</p>

<p class="drama">
PROSPERO.<br>
Thou poisonous slave, got by the devil himself<br>
Upon thy wicked dam, come forth!
</p>

<p class="scenedesc">Enter <span class="charname">Caliban</span>.
</p>

<p class="drama">
CALIBAN.<br>
As wicked dew as e’er my mother brush’d<br>
With raven’s feather from unwholesome fen<br>
Drop on you both! A south-west blow on ye,<br>
And blister you all o’er!
</p>

<p class="drama">
PROSPERO.<br>
For this, be sure, tonight thou shalt have cramps,<br>
Side-stitches that shall pen thy breath up; urchins<br>
Shall forth at vast of night that they may work<br>
All exercise on thee. Thou shalt be pinch’d<br>
As thick as honeycomb, each pinch more stinging<br>
Than bees that made them.
</p>

<p class="drama">
CALIBAN.<br>
I must eat my dinner.<br>
This island’s mine, by Sycorax my mother,<br>
Which thou tak’st from me. When thou cam’st first,<br>
Thou strok’st me and made much of me; wouldst give me<br>
Water with berries in ’t; and teach me how<br>
To name the bigger light, and how the less,<br>
That burn by day and night: and then I lov’d thee,<br>
And show’d thee all the qualities o’ th’ isle,<br>
The fresh springs, brine-pits, barren place, and fertile.<br>
Curs’d be I that did so! All the charms<br>
Of Sycorax, toads, beetles, bats, light on you!<br>
For I am all the subjects that you have,<br>
Which first was mine own King; and here you sty me<br>
In this hard rock, whiles you do keep from me<br>
The rest o’ th’ island.
</p>

<p class="drama">
PROSPERO.<br>
Thou most lying slave,<br>
Whom stripes may move, not kindness! I have us’d thee,<br>
Filth as thou art, with human care, and lodg’d thee<br>
In mine own cell, till thou didst seek to violate<br>
The honour of my child.
</p>

<p class="drama">
CALIBAN.<br>
Oh ho! Oh ho! Would ’t had been done!<br>
Thou didst prevent me; I had peopled else<br>
This isle with Calibans.
</p>

<p class="drama">
PROSPERO.<br>
Abhorred slave,<br>
Which any print of goodness wilt not take,<br>
Being capable of all ill! I pitied thee,<br>
Took pains to make thee speak, taught thee each hour<br>
One thing or other: when thou didst not, savage,<br>
Know thine own meaning, but wouldst gabble like<br>
A thing most brutish, I endow’d thy purposes<br>
With words that made them known. But thy vile race,<br>
Though thou didst learn, had that in ’t which good natures<br>
Could not abide to be with; therefore wast thou<br>
Deservedly confin’d into this rock,<br>
Who hadst deserv’d more than a prison.
</p>

<p class="drama">
CALIBAN.<br>
You taught me language, and my profit on ’t<br>
Is, I know how to curse. The red plague rid you,<br>
For learning me your language!
</p>

<p class="drama">
PROSPERO.<br>
Hag-seed, hence!<br>
Fetch us in fuel; and be quick, thou ’rt best,<br>
To answer other business. Shrug’st thou, malice?<br>
If thou neglect’st, or dost unwillingly<br>
What I command, I’ll rack thee with old cramps,<br>
Fill all thy bones with aches, make thee roar,<br>
That beasts shall tremble at thy din.
</p>

<p class="drama">
CALIBAN.<br>
No, pray thee.<br>
[<i>Aside.</i>] I must obey. His art is of such power,<br>
It would control my dam’s god, Setebos,<br>
And make a vassal of him.
</p>

<p class="drama">
PROSPERO.<br>
So, slave, hence!
</p>

<p class="right"> [<i>Exit <span class="charname">Caliban</span>.</i>]</p>

<p class="scenedesc">Re-enter <span class="charname">Ariel,</span> playing and
singing; <span class="charname">Ferdinand</span> following.</p>

<p class="letter">
ARIEL’S SONG.
</p>

<p class="drama">
<i>Come unto these yellow sands,<br>
    And then take hands:<br>
Curtsied when you have, and kiss’d<br>
    The wild waves whist.<br>
Foot it featly here and there,<br>
    And sweet sprites bear<br>
The burden. Hark, hark!</i><br>
    Burden dispersedly. <i>Bow-wow.<br>
The watch dogs bark.</i><br>
    [Burden dispersedly.] <i>Bow-wow.<br>
Hark, hark! I hear<br>
The strain of strutting chanticleer<br>
    Cry cock-a-diddle-dow.</i>
</p>

<p class="drama">
FERDINAND.<br>
Where should this music be? i’ th’ air or th’ earth?<br>
It sounds no more; and sure it waits upon<br>
Some god o’ th’ island. Sitting on a bank,<br>
Weeping again the King my father’s wrack,<br>
This music crept by me upon the waters,<br>
Allaying both their fury and my passion<br>
With its sweet air: thence I have follow’d it,<br>
Or it hath drawn me rather,—but ’tis gone.<br>
No, it begins again.
</p>

<p class="drama">
ARIEL.<br>
[<i>Sings.</i>]<br>
<i>Full fathom five thy father lies.<br>
    Of his bones are coral made.<br>
Those are pearls that were his eyes.<br>
    Nothing of him that doth fade<br>
But doth suffer a sea-change<br>
Into something rich and strange.<br>
Sea-nymphs hourly ring his knell:</i><br>
    Burden: <i>Ding-dong.<br>
Hark! now I hear them: ding-dong, bell.</i>
</p>

<p class="drama">
FERDINAND.<br>
The ditty does remember my drown’d father.<br>
This is no mortal business, nor no sound<br>
That the earth owes:—I hear it now above me.
</p>

<p class="drama">
PROSPERO.<br>
The fringed curtains of thine eye advance,<br>
And say what thou seest yond.
</p>

<p class="drama">
MIRANDA.<br>
What is’t? a spirit?<br>
Lord, how it looks about! Believe me, sir,<br>
It carries a brave form. But ’tis a spirit.
</p>

<p class="drama">
PROSPERO.<br>
No, wench; it eats and sleeps and hath such senses<br>
As we have, such. This gallant which thou seest<br>
Was in the wrack; and, but he’s something stain’d<br>
With grief,—that’s beauty’s canker,—thou mightst call him<br>
A goodly person: he hath lost his fellows<br>
And strays about to find ’em.
</p>

<p class="drama">
MIRANDA.<br>
I might call him<br>
A thing divine; for nothing natural<br>
I ever saw so noble.
</p>

<p class="drama">
PROSPERO.<br>
[<i>Aside.</i>] It goes on, I see,<br>
As my soul prompts it. Spirit, fine spirit! I’ll free thee<br>
Within two days for this.
</p>

<p class="drama">
FERDINAND.<br>
Most sure, the goddess<br>
On whom these airs attend! Vouchsafe, my prayer<br>
May know if you remain upon this island;<br>
And that you will some good instruction give<br>
How I may bear me here: my prime request,<br>
Which I do last pronounce, is, O you wonder!<br>
If you be maid or no?
</p>

<p class="drama">
MIRANDA.<br>
No wonder, sir;<br>
But certainly a maid.
</p>

<p class="drama">
FERDINAND.<br>
My language! Heavens!<br>
I am the best of them that speak this speech,<br>
Were I but where ’tis spoken.
</p>

<p class="drama">
PROSPERO.<br>
How! the best?<br>
What wert thou, if the King of Naples heard thee?
</p>

<p class="drama">
FERDINAND.<br>
A single thing, as I am now, that wonders<br>
To hear thee speak of Naples. He does hear me;<br>
And that he does I weep: myself am Naples,<br>
Who with mine eyes, never since at ebb, beheld<br>
The King my father wrack’d.
</p>

<p class="drama">
MIRANDA.<br>
Alack, for mercy!
</p>

<p class="drama">
FERDINAND.<br>
Yes, faith, and all his lords, the Duke of Milan,<br>
And his brave son being twain.
</p>

<p class="drama">
PROSPERO.<br>
[<i>Aside.</i>] The Duke of Milan<br>
And his more braver daughter could control thee,<br>
If now ’twere fit to do’t. At the first sight<br>
They have changed eyes. Delicate Ariel,<br>
I’ll set thee free for this. [<i>To Ferdinand.</i>] A word, good sir.<br>
I fear you have done yourself some wrong: a word.
</p>

<p class="drama">
MIRANDA.<br>
Why speaks my father so ungently? This<br>
Is the third man that e’er I saw; the first<br>
That e’er I sigh’d for. Pity move my father<br>
To be inclin’d my way!
</p>

<p class="drama">
FERDINAND.<br>
O! if a virgin,<br>
And your affection not gone forth, I’ll make you<br>
The Queen of Naples.
</p>

<p class="drama">
PROSPERO.<br>
Soft, sir; one word more.<br>
[<i>Aside.</i>] They are both in either’s powers. But this swift business<br>
I must uneasy make, lest too light winning<br>
Make the prize light. [<i>To Ferdinand.</i>] One word more. I charge thee<br>
That thou attend me. Thou dost here usurp<br>
The name thou ow’st not; and hast put thyself<br>
Upon this island as a spy, to win it<br>
From me, the lord on ’t.
</p>

<p class="drama">
FERDINAND.<br>
No, as I am a man.
</p>

<p class="drama">
MIRANDA.<br>
There’s nothing ill can dwell in such a temple:<br>
If the ill spirit have so fair a house,<br>
Good things will strive to dwell with ’t.
</p>

<p class="drama">
PROSPERO.<br>
[<i>To Ferdinand.</i>] Follow me.—<br>
[<i>To Miranda.</i>] Speak not you for him; he’s a traitor.<br>
[<i>To Ferdinand.</i>] Come;<br>
I’ll manacle thy neck and feet together:<br>
Sea-water shalt thou drink; thy food shall be<br>
The fresh-brook mussels, wither’d roots, and husks<br>
Wherein the acorn cradled. Follow.
</p>

<p class="drama">
FERDINAND.<br>
No;<br>
I will resist such entertainment till<br>
Mine enemy has more power.
</p>

<p class="right"> [<i>He draws, and is charmed from moving.</i>]</p>

<p class="drama">
MIRANDA.<br>
O dear father!<br>
Make not too rash a trial of him, for<br>
He’s gentle, and not fearful.
</p>

<p class="drama">
PROSPERO.<br>
What! I say,<br>
My foot my tutor? Put thy sword up, traitor;<br>
Who mak’st a show, but dar’st not strike, thy conscience<br>
Is so possess’d with guilt: come from thy ward,<br>
For I can here disarm thee with this stick<br>
And make thy weapon drop.
</p>

<p class="drama">
MIRANDA.<br>
Beseech you, father!
</p>

<p class="drama">
PROSPERO.<br>
Hence! Hang not on my garments.
</p>

<p class="drama">
MIRANDA.<br>
Sir, have pity;<br>
I’ll be his surety.
</p>

<p class="drama">
PROSPERO.<br>
Silence! One word more<br>
Shall make me chide thee, if not hate thee. What!<br>
An advocate for an impostor? hush!<br>
Thou think’st there is no more such shapes as he,<br>
Having seen but him and Caliban: foolish wench!<br>
To th’ most of men this is a Caliban,<br>
And they to him are angels.
</p>

<p class="drama">
MIRANDA.<br>
My affections<br>
Are then most humble; I have no ambition<br>
To see a goodlier man.
</p>

<p class="drama">
PROSPERO.<br>
[<i>To Ferdinand.</i>] Come on; obey:<br>
Thy nerves are in their infancy again,<br>
And have no vigour in them.
</p>

<p class="drama">
FERDINAND.<br>
So they are:<br>
My spirits, as in a dream, are all bound up.<br>
My father’s loss, the weakness which I feel,<br>
The wrack of all my friends, nor this man’s threats,<br>
To whom I am subdued, are but light to me,<br>
Might I but through my prison once a day<br>
Behold this maid: all corners else o’ th’ earth<br>
Let liberty make use of; space enough<br>
Have I in such a prison.
</p>

<p class="drama">
PROSPERO.<br>
[<i>Aside.</i>] It works. [<i>To Ferdinand.</i>] Come on.<br>
Thou hast done well, fine Ariel! [<i>To Ferdinand.</i>] Follow me.<br>
[<i>To Ariel.</i>] Hark what thou else shalt do me.
</p>

<p class="drama">
MIRANDA.<br>
Be of comfort;<br>
My father’s of a better nature, sir,<br>
Than he appears by speech: this is unwonted<br>
Which now came from him.
</p>

<p class="drama">
PROSPERO.<br>
Thou shalt be as free<br>
As mountain winds; but then exactly do<br>
All points of my command.
</p>

<p class="drama">
ARIEL.<br>
To th’ syllable.
</p>

<p class="drama">
PROSPERO.<br>
[<i>To Ferdinand.</i>] Come, follow. Speak not for him.
</p>

<p class="right"> [<i>Exeunt.</i>]</p>

