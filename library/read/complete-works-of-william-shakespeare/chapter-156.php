<h2> <a id="sceneIV_25.1"></a><b>ACT IV</b></h2>

<h3> <b>SCENE I. The Inside of a Church.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Don Pedro, Don John, Leonato, Friar Francis,
Claudio, Benedick, Hero, Beatrice</span> &amp;c.
</p>

<p class="drama">
LEONATO.<br>
Come, Friar Francis, be brief: only to the plain form of marriage, and you
shall recount their particular duties afterwards.
</p>

<p class="drama">
FRIAR.<br>
You come hither, my lord, to marry this lady?
</p>

<p class="drama">
CLAUDIO.<br>
No.
</p>

<p class="drama">
LEONATO.<br>
To be married to her, friar; you come to marry her.
</p>

<p class="drama">
FRIAR.<br>
Lady, you come hither to be married to this Count?
</p>

<p class="drama">
HERO.<br>
I do.
</p>

<p class="drama">
FRIAR.<br>
If either of you know any inward impediment, why you should not be conjoined, I
charge you, on your souls, to utter it.
</p>

<p class="drama">
CLAUDIO.<br>
Know you any, Hero?
</p>

<p class="drama">
HERO.<br>
None, my lord.
</p>

<p class="drama">
FRIAR.<br>
Know you any, Count?
</p>

<p class="drama">
LEONATO.<br>
I dare make his answer; none.
</p>

<p class="drama">
CLAUDIO.<br>
O! what men dare do! what men may do! what men daily do, not knowing what they
do!
</p>

<p class="drama">
BENEDICK.<br>
How now! Interjections? Why then, some be of laughing, as ah! ha! he!
</p>

<p class="drama">
CLAUDIO.<br>
Stand thee by, Friar. Father, by your leave:<br>
Will you with free and unconstrained soul<br>
Give me this maid, your daughter?
</p>

<p class="drama">
LEONATO.<br>
As freely, son, as God did give her me.
</p>

<p class="drama">
CLAUDIO.<br>
And what have I to give you back whose worth<br>
May counterpoise this rich and precious gift?
</p>

<p class="drama">
DON PEDRO.<br>
Nothing, unless you render her again.
</p>

<p class="drama">
CLAUDIO.<br>
Sweet Prince, you learn me noble thankfulness.<br>
There, Leonato, take her back again:<br>
Give not this rotten orange to your friend;<br>
She’s but the sign and semblance of her honour.<br>
Behold! how like a maid she blushes here.<br>
O! what authority and show of truth<br>
Can cunning sin cover itself withal.<br>
Comes not that blood as modest evidence<br>
To witness simple virtue? Would you not swear,<br>
All you that see her, that she were a maid,<br>
By these exterior shows? But she is none:<br>
She knows the heat of a luxurious bed;<br>
Her blush is guiltiness, not modesty.
</p>

<p class="drama">
LEONATO.<br>
What do you mean, my lord?
</p>

<p class="drama">
CLAUDIO.<br>
Not to be married,<br>
Not to knit my soul to an approved wanton.
</p>

<p class="drama">
LEONATO.<br>
Dear my lord, if you, in your own proof,<br>
Have vanquish’d the resistance of her youth,<br>
And made defeat of her virginity,—
</p>

<p class="drama">
CLAUDIO.<br>
I know what you would say: if I have known her,<br>
You will say she did embrace me as a husband,<br>
And so extenuate the forehand sin: No, Leonato,<br>
I never tempted her with word too large;<br>
But as a brother to his sister show’d<br>
Bashful sincerity and comely love.
</p>

<p class="drama">
HERO.<br>
And seem’d I ever otherwise to you?
</p>

<p class="drama">
CLAUDIO.<br>
Out on thee! Seeming! I will write against it:<br>
You seem to me as Dian in her orb,<br>
As chaste as is the bud ere it be blown;<br>
But you are more intemperate in your blood<br>
Than Venus, or those pamper’d animals<br>
That rage in savage sensuality.
</p>

<p class="drama">
HERO.<br>
Is my lord well, that he doth speak so wide?
</p>

<p class="drama">
LEONATO.<br>
Sweet Prince, why speak not you?
</p>

<p class="drama">
DON PEDRO.<br>
What should I speak?<br>
I stand dishonour’d, that have gone about<br>
To link my dear friend to a common stale.
</p>

<p class="drama">
LEONATO.<br>
Are these things spoken, or do I but dream?
</p>

<p class="drama">
DON JOHN.<br>
Sir, they are spoken, and these things are true.
</p>

<p class="drama">
BENEDICK.<br>
This looks not like a nuptial.
</p>

<p class="drama">
HERO.<br>
True! O God!
</p>

<p class="drama">
CLAUDIO.<br>
Leonato, stand I here?<br>
Is this the Prince? Is this the Prince’s brother?<br>
Is this face Hero’s? Are our eyes our own?
</p>

<p class="drama">
LEONATO.<br>
All this is so; but what of this, my lord?
</p>

<p class="drama">
CLAUDIO.<br>
Let me but move one question to your daughter,<br>
And by that fatherly and kindly power<br>
That you have in her, bid her answer truly.
</p>

<p class="drama">
LEONATO.<br>
I charge thee do so, as thou art my child.
</p>

<p class="drama">
HERO.<br>
O, God defend me! how am I beset!<br>
What kind of catechizing call you this?
</p>

<p class="drama">
CLAUDIO.<br>
To make you answer truly to your name.
</p>

<p class="drama">
HERO.<br>
Is it not Hero? Who can blot that name<br>
With any just reproach?
</p>

<p class="drama">
CLAUDIO.<br>
Marry, that can Hero:<br>
Hero itself can blot out Hero’s virtue.<br>
What man was he talk’d with you yesternight<br>
Out at your window, betwixt twelve and one?<br>
Now, if you are a maid, answer to this.
</p>

<p class="drama">
HERO.<br>
I talk’d with no man at that hour, my lord.
</p>

<p class="drama">
DON PEDRO.<br>
Why, then are you no maiden.<br>
Leonato, I am sorry you must hear: upon my honour,<br>
Myself, my brother, and this grieved Count,<br>
Did see her, hear her, at that hour last night,<br>
Talk with a ruffian at her chamber window;<br>
Who hath indeed, most like a liberal villain,<br>
Confess’d the vile encounters they have had<br>
A thousand times in secret.
</p>

<p class="drama">
DON JOHN.<br>
Fie, fie! they are not to be nam’d, my lord,<br>
Not to be spoke of;<br>
There is not chastity enough in language<br>
Without offence to utter them. Thus, pretty lady,<br>
I am sorry for thy much misgovernment.
</p>

<p class="drama">
CLAUDIO.<br>
O Hero! what a Hero hadst thou been,<br>
If half thy outward graces had been plac’d<br>
About thy thoughts and counsels of thy heart!<br>
But fare thee well, most foul, most fair! farewell,<br>
Thou pure impiety, and impious purity!<br>
For thee I’ll lock up all the gates of love,<br>
And on my eyelids shall conjecture hang,<br>
To turn all beauty into thoughts of harm,<br>
And never shall it more be gracious.
</p>

<p class="drama">
LEONATO.<br>
Hath no man’s dagger here a point for me?
</p>

<p class="right">
[<i><span class="charname">Hero</span> swoons.</i>]
</p>

<p class="drama">
BEATRICE.<br>
Why, how now, cousin! wherefore sink you down?
</p>

<p class="drama">
DON JOHN.<br>
Come, let us go. These things, come thus to light,<br>
Smother her spirits up.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Don Pedro, Don John</span> and <span class="charname">Claudio.</span></i>]
</p>

<p class="drama">
BENEDICK.<br>
How doth the lady?
</p>

<p class="drama">
BEATRICE.<br>
Dead, I think! Help, uncle! Hero! why, Hero! Uncle! Signior Benedick! Friar!
</p>

<p class="drama">
LEONATO.<br>
O Fate! take not away thy heavy hand:<br>
Death is the fairest cover for her shame<br>
That may be wish’d for.
</p>

<p class="drama">
BEATRICE.<br>
How now, cousin Hero?
</p>

<p class="drama">
FRIAR.<br>
Have comfort, lady.
</p>

<p class="drama">
LEONATO.<br>
Dost thou look up?
</p>

<p class="drama">
FRIAR.<br>
Yea; wherefore should she not?
</p>

<p class="drama">
LEONATO.<br>
Wherefore! Why, doth not every earthly thing<br>
Cry shame upon her? Could she here deny<br>
The story that is printed in her blood?<br>
Do not live, Hero; do not ope thine eyes;<br>
For, did I think thou wouldst not quickly die,<br>
Thought I thy spirits were stronger than thy shames,<br>
Myself would, on the rearward of reproaches,<br>
Strike at thy life. Griev’d I, I had but one?<br>
Chid I for that at frugal Nature’s frame?<br>
O! one too much by thee. Why had I one?<br>
Why ever wast thou lovely in my eyes?<br>
Why had I not with charitable hand<br>
Took up a beggar’s issue at my gates,<br>
Who smirched thus, and mir’d with infamy,<br>
I might have said, ‘No part of it is mine;<br>
This shame derives itself from unknown loins?’<br>
But mine, and mine I lov’d, and mine I prais’d,<br>
And mine that I was proud on, mine so much<br>
That I myself was to myself not mine,<br>
Valuing of her; why, she—O! she is fallen<br>
Into a pit of ink, that the wide sea<br>
Hath drops too few to wash her clean again,<br>
And salt too little which may season give<br>
To her foul tainted flesh.
</p>

<p class="drama">
BENEDICK.<br>
Sir, sir, be patient.<br>
For my part, I am so attir’d in wonder,<br>
I know not what to say.
</p>

<p class="drama">
BEATRICE.<br>
O! on my soul, my cousin is belied!
</p>

<p class="drama">
BENEDICK.<br>
Lady, were you her bedfellow last night?
</p>

<p class="drama">
BEATRICE.<br>
No, truly, not; although, until last night,<br>
I have this twelvemonth been her bedfellow.
</p>

<p class="drama">
LEONATO.<br>
Confirm’d, confirm’d! O! that is stronger made,<br>
Which was before barr’d up with ribs of iron.<br>
Would the two princes lie? and Claudio lie,<br>
Who lov’d her so, that, speaking of her foulness,<br>
Wash’d it with tears? Hence from her! let her die.
</p>

<p class="drama">
FRIAR.<br>
Hear me a little;<br>
For I have only been silent so long,<br>
And given way unto this course of fortune,<br>
By noting of the lady: I have mark’d<br>
A thousand blushing apparitions<br>
To start into her face; a thousand innocent shames<br>
In angel whiteness bear away those blushes;<br>
And in her eye there hath appear’d a fire,<br>
To burn the errors that these princes hold<br>
Against her maiden truth. Call me a fool;<br>
Trust not my reading nor my observations,<br>
Which with experimental seal doth warrant<br>
The tenure of my book; trust not my age,<br>
My reverence, calling, nor divinity,<br>
If this sweet lady lie not guiltless here<br>
Under some biting error.
</p>

<p class="drama">
LEONATO.<br>
Friar, it cannot be.<br>
Thou seest that all the grace that she hath left<br>
Is that she will not add to her damnation<br>
A sin of perjury: she not denies it.<br>
Why seek’st thou then to cover with excuse<br>
That which appears in proper nakedness?
</p>

<p class="drama">
FRIAR.<br>
Lady, what man is he you are accus’d of?
</p>

<p class="drama">
HERO.<br>
They know that do accuse me, I know none;<br>
If I know more of any man alive<br>
Than that which maiden modesty doth warrant,<br>
Let all my sins lack mercy! O, my father!<br>
Prove you that any man with me convers’d<br>
At hours unmeet, or that I yesternight<br>
Maintain’d the change of words with any creature,<br>
Refuse me, hate me, torture me to death.
</p>

<p class="drama">
FRIAR.<br>
There is some strange misprision in the princes.
</p>

<p class="drama">
BENEDICK.<br>
Two of them have the very bent of honour;<br>
And if their wisdoms be misled in this,<br>
The practice of it lives in John the bastard,<br>
Whose spirits toil in frame of villainies.
</p>

<p class="drama">
LEONATO.<br>
I know not. If they speak but truth of her,<br>
These hands shall tear her; if they wrong her honour,<br>
The proudest of them shall well hear of it.<br>
Time hath not yet so dried this blood of mine,<br>
Nor age so eat up my invention,<br>
Nor fortune made such havoc of my means,<br>
Nor my bad life reft me so much of friends,<br>
But they shall find, awak’d in such a kind,<br>
Both strength of limb and policy of mind,<br>
Ability in means and choice of friends,<br>
To quit me of them throughly.
</p>

<p class="drama">
FRIAR.<br>
Pause awhile,<br>
And let my counsel sway you in this case.<br>
Your daughter here the princes left for dead;<br>
Let her awhile be secretly kept in,<br>
And publish it that she is dead indeed:<br>
Maintain a mourning ostentation;<br>
And on your family’s old monument<br>
Hang mournful epitaphs and do all rites<br>
That appertain unto a burial.
</p>

<p class="drama">
LEONATO.<br>
What shall become of this? What will this do?
</p>

<p class="drama">
FRIAR.<br>
Marry, this well carried shall on her behalf<br>
Change slander to remorse; that is some good.<br>
But not for that dream I on this strange course,<br>
But on this travail look for greater birth.<br>
She dying, as it must be so maintain’d,<br>
Upon the instant that she was accus’d,<br>
Shall be lamented, pitied and excus’d<br>
Of every hearer; for it so falls out<br>
That what we have we prize not to the worth<br>
Whiles we enjoy it, but being lack’d and lost,<br>
Why, then we rack the value, then we find<br>
The virtue that possession would not show us<br>
Whiles it was ours. So will it fare with Claudio:<br>
When he shall hear she died upon his words,<br>
The idea of her life shall sweetly creep<br>
Into his study of imagination,<br>
And every lovely organ of her life<br>
Shall come apparell’d in more precious habit,<br>
More moving, delicate, and full of life<br>
Into the eye and prospect of his soul,<br>
Than when she liv’d indeed: then shall he mourn,—<br>
If ever love had interest in his liver,—<br>
And wish he had not so accused her,<br>
No, though he thought his accusation true.<br>
Let this be so, and doubt not but success<br>
Will fashion the event in better shape<br>
Than I can lay it down in likelihood.<br>
But if all aim but this be levell’d false,<br>
The supposition of the lady’s death<br>
Will quench the wonder of her infamy:<br>
And if it sort not well, you may conceal her,—<br>
As best befits her wounded reputation,—<br>
In some reclusive and religious life,<br>
Out of all eyes, tongues, minds, and injuries.
</p>

<p class="drama">
BENEDICK.<br>
Signior Leonato, let the friar advise you:<br>
And though you know my inwardness and love<br>
Is very much unto the Prince and Claudio,<br>
Yet, by mine honour, I will deal in this<br>
As secretly and justly as your soul<br>
Should with your body.
</p>

<p class="drama">
LEONATO.<br>
Being that I flow in grief,<br>
The smallest twine may lead me.
</p>

<p class="drama">
FRIAR.<br>
’Tis well consented: presently away;<br>
For to strange sores strangely they strain the cure.<br>
Come, lady, die to live: this wedding day<br>
Perhaps is but prolong’d: have patience and endure.<br>
</p>

<p class="right">
[<i>Exeunt <span class="charname">Friar, Hero</span> and <span class="charname">Leonato.</span></i>]
</p>

<p class="drama">
BENEDICK.<br>
Lady Beatrice, have you wept all this while?
</p>

<p class="drama">
BEATRICE.<br>
Yea, and I will weep a while longer.
</p>

<p class="drama">
BENEDICK.<br>
I will not desire that.
</p>

<p class="drama">
BEATRICE.<br>
You have no reason; I do it freely.
</p>

<p class="drama">
BENEDICK.<br>
Surely I do believe your fair cousin is wronged.
</p>

<p class="drama">
BEATRICE.<br>
Ah! how much might the man deserve of me that would right her.
</p>

<p class="drama">
BENEDICK.<br>
Is there any way to show such friendship?
</p>

<p class="drama">
BEATRICE.<br>
A very even way, but no such friend.
</p>

<p class="drama">
BENEDICK.<br>
May a man do it?
</p>

<p class="drama">
BEATRICE.<br>
It is a man’s office, but not yours.
</p>

<p class="drama">
BENEDICK.<br>
I do love nothing in the world so well as you: is not that strange?
</p>

<p class="drama">
BEATRICE.<br>
As strange as the thing I know not. It were as possible for me to say I loved
nothing so well as you; but believe me not, and yet I lie not; I confess
nothing, nor I deny nothing. I am sorry for my cousin.
</p>

<p class="drama">
BENEDICK.<br>
By my sword, Beatrice, thou lovest me.
</p>

<p class="drama">
BEATRICE.<br>
Do not swear by it, and eat it.
</p>

<p class="drama">
BENEDICK.<br>
I will swear by it that you love me; and I will make him eat it that says I
love not you.
</p>

<p class="drama">
BEATRICE.<br>
Will you not eat your word?
</p>

<p class="drama">
BENEDICK.<br>
With no sauce that can be devised to it. I protest I love thee.
</p>

<p class="drama">
BEATRICE.<br>
Why then, God forgive me!
</p>

<p class="drama">
BENEDICK.<br>
What offence, sweet Beatrice?
</p>

<p class="drama">
BEATRICE.<br>
You have stayed me in a happy hour: I was about to protest I loved you.
</p>

<p class="drama">
BENEDICK.<br>
And do it with all thy heart.
</p>

<p class="drama">
BEATRICE.<br>
I love you with so much of my heart that none is left to protest.
</p>

<p class="drama">
BENEDICK.<br>
Come, bid me do anything for thee.
</p>

<p class="drama">
BEATRICE.<br>
Kill Claudio.
</p>

<p class="drama">
BENEDICK.<br>
Ha! not for the wide world.
</p>

<p class="drama">
BEATRICE.<br>
You kill me to deny it. Farewell.
</p>

<p class="drama">
BENEDICK.<br>
Tarry, sweet Beatrice.
</p>

<p class="drama">
BEATRICE.<br>
I am gone, though I am here: there is no love in you: nay, I pray you, let me
go.
</p>

<p class="drama">
BENEDICK.<br>
Beatrice,—
</p>

<p class="drama">
BEATRICE.<br>
In faith, I will go.
</p>

<p class="drama">
BENEDICK.<br>
We’ll be friends first.
</p>

<p class="drama">
BEATRICE.<br>
You dare easier be friends with me than fight with mine enemy.
</p>

<p class="drama">
BENEDICK.<br>
Is Claudio thine enemy?
</p>

<p class="drama">
BEATRICE.<br>
Is he not approved in the height a villain, that hath slandered, scorned,
dishonoured my kinswoman? O! that I were a man. What! bear her in hand until
they come to take hands, and then, with public accusation, uncovered slander,
unmitigated rancour,—O God, that I were a man! I would eat his heart in the
market-place.
</p>

<p class="drama">
BENEDICK.<br>
Hear me, Beatrice,—
</p>

<p class="drama">
BEATRICE.<br>
Talk with a man out at a window! a proper saying!
</p>

<p class="drama">
BENEDICK.<br>
Nay, but Beatrice,—
</p>

<p class="drama">
BEATRICE.<br>
Sweet Hero! she is wronged, she is slandered, she is undone.
</p>

<p class="drama">
BENEDICK.<br>
Beat—
</p>

<p class="drama">
BEATRICE.<br>
Princes and Counties! Surely, a princely testimony, a goodly Count Comfect; a
sweet gallant, surely! O! that I were a man for his sake, or that I had any
friend would be a man for my sake! But manhood is melted into curtsies, valour
into compliment, and men are only turned into tongue, and trim ones too: he is
now as valiant as Hercules, that only tells a lie and swears it. I cannot be a
man with wishing, therefore I will die a woman with grieving.
</p>

<p class="drama">
BENEDICK.<br>
Tarry, good Beatrice. By this hand, I love thee.
</p>

<p class="drama">
BEATRICE.<br>
Use it for my love some other way than swearing by it.
</p>

<p class="drama">
BENEDICK.<br>
Think you in your soul the Count Claudio hath wronged Hero?
</p>

<p class="drama">
BEATRICE.<br>
Yea, as sure is I have a thought or a soul.
</p>

<p class="drama">
BENEDICK.<br>
Enough! I am engaged, I will challenge him. I will kiss your hand, and so leave
you. By this hand, Claudio shall render me a dear account. As you hear of me,
so think of me. Go, comfort your cousin: I must say she is dead; and so,
farewell.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneIV_25.2"></a><b>Scene II. A Prison.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Dogberry, Verges</span>, and <span class="charname">Sexton</span>, in gowns; and the Watch, with <span class="charname">Conrade</span> and <span class="charname">Borachio</span>.
</p>

<p class="drama">
DOGBERRY.<br>
Is our whole dissembly appeared?
</p>

<p class="drama">
VERGES.<br>
O! a stool and a cushion for the sexton.
</p>

<p class="drama">
SEXTON.<br>
Which be the malefactors?
</p>

<p class="drama">
DOGBERRY.<br>
Marry, that am I and my partner.
</p>

<p class="drama">
VERGES.<br>
Nay, that’s certain: we have the exhibition to examine.
</p>

<p class="drama">
SEXTON.<br>
But which are the offenders that are to be examined? let them come before
Master Constable.
</p>

<p class="drama">
DOGBERRY.<br>
Yea, marry, let them come before me. What is your name, friend?
</p>

<p class="drama">
BORACHIO.<br>
Borachio.
</p>

<p class="drama">
DOGBERRY.<br>
Pray write down Borachio. Yours, sirrah?
</p>

<p class="drama">
CONRADE.<br>
I am a gentleman, sir, and my name is Conrade.
</p>

<p class="drama">
DOGBERRY.<br>
Write down Master gentleman Conrade. Masters, do you serve God?
</p>

<p class="drama">
BOTH.<br>
Yea, sir, we hope.
</p>

<p class="drama">
DOGBERRY.<br>
Write down that they hope they serve God: and write God first; for God defend
but God should go before such villains! Masters, it is proved already that you
are little better than false knaves, and it will go near to be thought so
shortly. How answer you for yourselves?
</p>

<p class="drama">
CONRADE.<br>
Marry, sir, we say we are none.
</p>

<p class="drama">
DOGBERRY.<br>
A marvellous witty fellow, I assure you; but I will go about with him. Come you
hither, sirrah; a word in your ear: sir, I say to you, it is thought you are
false knaves.
</p>

<p class="drama">
BORACHIO.<br>
Sir, I say to you we are none.
</p>

<p class="drama">
DOGBERRY.<br>
Well, stand aside. Fore God, they are both in a tale. Have you writ down, that
they are none?
</p>

<p class="drama">
SEXTON.<br>
Master Constable, you go not the way to examine: you must call forth the watch
that are their accusers.
</p>

<p class="drama">
DOGBERRY.<br>
Yea, marry, that’s the eftest way. Let the watch come forth. Masters, I
charge you, in the Prince’s name, accuse these men.
</p>

<p class="drama">
FIRST WATCH.<br>
This man said, sir, that Don John, the Prince’s brother, was a villain.
</p>

<p class="drama">
DOGBERRY.<br>
Write down Prince John a villain. Why, this is flat perjury, to call a
Prince’s brother villain.
</p>

<p class="drama">
BORACHIO.<br>
Master Constable,—
</p>

<p class="drama">
DOGBERRY.<br>
Pray thee, fellow, peace: I do not like thy look, I promise thee.
</p>

<p class="drama">
SEXTON.<br>
What heard you him say else?
</p>

<p class="drama">
SECOND WATCH.<br>
Marry, that he had received a thousand ducats of Don John for accusing the Lady
Hero wrongfully.
</p>

<p class="drama">
DOGBERRY.<br>
Flat burglary as ever was committed.
</p>

<p class="drama">
VERGES.<br>
Yea, by the mass, that it is.
</p>

<p class="drama">
SEXTON.<br>
What else, fellow?
</p>

<p class="drama">
FIRST WATCH.<br>
And that Count Claudio did mean, upon his words, to disgrace Hero before the
whole assembly, and not marry her.
</p>

<p class="drama">
DOGBERRY.<br>
O villain! thou wilt be condemned into everlasting redemption for this.
</p>

<p class="drama">
SEXTON.<br>
What else?
</p>

<p class="drama">
SECOND WATCH.<br>
This is all.
</p>

<p class="drama">
SEXTON.<br>
And this is more, masters, than you can deny. Prince John is this morning
secretly stolen away: Hero was in this manner accused, in this manner refused,
and, upon the grief of this, suddenly died. Master Constable, let these men be
bound, and brought to Leonato’s: I will go before and show him their
examination.
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="drama">
DOGBERRY.<br>
Come, let them be opinioned.
</p>

<p class="drama">
VERGES.<br>
Let them be in the hands—
</p>

<p class="drama">
CONRADE.<br>
Off, coxcomb!
</p>

<p class="drama">
DOGBERRY.<br>
God’s my life! where’s the sexton? let him write down the
Prince’s officer coxcomb. Come, bind them. Thou naughty varlet!
</p>

<p class="drama">
CONRADE.<br>
Away! you are an ass; you are an ass.
</p>

<p class="drama">
DOGBERRY.<br>
Dost thou not suspect my place? Dost thou not suspect my years? O that he were
here to write me down an ass! but, masters, remember that I am an ass; though
it be not written down, yet forget not that I am an ass. No, thou villain, thou
art full of piety, as shall be proved upon thee by good witness. I am a wise
fellow; and, which is more, an officer; and, which is more, a householder; and,
which is more, as pretty a piece of flesh as any in Messina; and one that knows
the law, go to; and a rich fellow enough, go to; and a fellow that hath had
losses; and one that hath two gowns, and everything handsome about him. Bring
him away. O that I had been writ down an ass!
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

