<h2> <a id="sceneIV_26.1"></a><b>ACT IV</b></h2>

<h3> <b>SCENE I. Cyprus. Before the Castle.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Othello</span> and <span class="charname">Iago</span>.
</p>

<p class="drama">
IAGO.<br>
Will you think so?
</p>

<p class="drama">
OTHELLO.<br>
Think so, Iago?
</p>

<p class="drama">
IAGO.<br>
What,<br>
To kiss in private?
</p>

<p class="drama">
OTHELLO.<br>
An unauthoriz’d kiss.
</p>

<p class="drama">
IAGO.<br>
Or to be naked with her friend in bed<br>
An hour or more, not meaning any harm?
</p>

<p class="drama">
OTHELLO.<br>
Naked in bed, Iago, and not mean harm?<br>
It is hypocrisy against the devil:<br>
They that mean virtuously and yet do so,<br>
The devil their virtue tempts, and they tempt heaven.
</p>

<p class="drama">
IAGO.<br>
So they do nothing, ’tis a venial slip.<br>
But if I give my wife a handkerchief—
</p>

<p class="drama">
OTHELLO.<br>
What then?
</p>

<p class="drama">
IAGO.<br>
Why then, ’tis hers, my lord, and being hers,<br>
She may, I think, bestow’t on any man.
</p>

<p class="drama">
OTHELLO.<br>
She is protectress of her honour too.<br>
May she give that?
</p>

<p class="drama">
IAGO.<br>
Her honour is an essence that’s not seen;<br>
They have it very oft that have it not:<br>
But for the handkerchief—
</p>

<p class="drama">
OTHELLO.<br>
By heaven, I would most gladly have forgot it.<br>
Thou said’st (O, it comes o’er my memory,<br>
As doth the raven o’er the infected house,<br>
Boding to all) he had my handkerchief.
</p>

<p class="drama">
IAGO.<br>
Ay, what of that?
</p>

<p class="drama">
OTHELLO.<br>
That’s not so good now.
</p>

<p class="drama">
IAGO.<br>
What<br>
If I had said I had seen him do you wrong?<br>
Or heard him say (as knaves be such abroad,<br>
Who having, by their own importunate suit,<br>
Or voluntary dotage of some mistress,<br>
Convinced or supplied them, cannot choose<br>
But they must blab.)
</p>

<p class="drama">
OTHELLO.<br>
Hath he said anything?
</p>

<p class="drama">
IAGO.<br>
He hath, my lord, but be you well assur’d,<br>
No more than he’ll unswear.
</p>

<p class="drama">
OTHELLO.<br>
What hath he said?
</p>

<p class="drama">
IAGO.<br>
Faith, that he did—I know not what he did.
</p>

<p class="drama">
OTHELLO.<br>
What? What?
</p>

<p class="drama">
IAGO.<br>
Lie.
</p>

<p class="drama">
OTHELLO.<br>
With her?
</p>

<p class="drama">
IAGO.<br>
With her, on her, what you will.
</p>

<p class="drama">
OTHELLO.<br>
Lie with her! lie on her!—We say lie on her when they belie her.—Lie with her!
that’s fulsome. Handkerchief—confessions—handkerchief! To confess, and be
hanged for his labour. First, to be hanged, and then to confess. I tremble at
it. Nature would not invest herself in such shadowing passion without some
instruction. It is not words that shake me thus. Pish! Noses, ears, and lips.
Is’t possible?—Confess?—handkerchief?—O devil!—
</p>

<p class="right">
[<i>Falls in a trance.</i>]
</p>

<p class="drama">
IAGO.<br>
Work on,<br>
My medicine, work! Thus credulous fools are caught,<br>
And many worthy and chaste dames even thus,<br>
All guiltless, meet reproach. What, ho! my lord!<br>
My lord, I say! Othello!
</p>

<p class="scenedesc">
Enter <span class="charname">Cassio</span>.
</p>

<p class="drama">
How now, Cassio!
</p>

<p class="drama">
CASSIO.<br>
What’s the matter?
</p>

<p class="drama">
IAGO.<br>
My lord is fallen into an epilepsy.<br>
This is his second fit. He had one yesterday.
</p>

<p class="drama">
CASSIO.<br>
Rub him about the temples.
</p>

<p class="drama">
IAGO.<br>
No, forbear;<br>
The lethargy must have his quiet course.<br>
If not, he foams at mouth, and by and by<br>
Breaks out to savage madness. Look, he stirs:<br>
Do you withdraw yourself a little while,<br>
He will recover straight. When he is gone,<br>
I would on great occasion speak with you.
</p>

<p class="right">
[<i>Exit <span class="charname">Cassio</span>.</i>]
</p>

<p class="drama">
How is it, general? Have you not hurt your head?
</p>

<p class="drama">
OTHELLO.<br>
Dost thou mock me?
</p>

<p class="drama">
IAGO.<br>
I mock you? No, by heaven.<br>
Would you would bear your fortune like a man!
</p>

<p class="drama">
OTHELLO.<br>
A horned man’s a monster and a beast.
</p>

<p class="drama">
IAGO.<br>
There’s many a beast, then, in a populous city,<br>
And many a civil monster.
</p>

<p class="drama">
OTHELLO.<br>
Did he confess it?
</p>

<p class="drama">
IAGO.<br>
Good sir, be a man.<br>
Think every bearded fellow that’s but yok’d<br>
May draw with you. There’s millions now alive<br>
That nightly lie in those unproper beds<br>
Which they dare swear peculiar: your case is better.<br>
O, ’tis the spite of hell, the fiend’s arch-mock,<br>
To lip a wanton in a secure couch,<br>
And to suppose her chaste! No, let me know,<br>
And knowing what I am, I know what she shall be.
</p>

<p class="drama">
OTHELLO.<br>
O, thou art wise, ’tis certain.
</p>

<p class="drama">
IAGO.<br>
Stand you awhile apart,<br>
Confine yourself but in a patient list.<br>
Whilst you were here o’erwhelmed with your grief,<br>
(A passion most unsuiting such a man)<br>
Cassio came hither. I shifted him away,<br>
And laid good ’scuse upon your ecstasy,<br>
Bade him anon return, and here speak with me,<br>
The which he promis’d. Do but encave yourself,<br>
And mark the fleers, the gibes, and notable scorns,<br>
That dwell in every region of his face;<br>
For I will make him tell the tale anew,<br>
Where, how, how oft, how long ago, and when<br>
He hath, and is again to cope your wife:<br>
I say, but mark his gesture. Marry, patience,<br>
Or I shall say you are all in all in spleen,<br>
And nothing of a man.
</p>

<p class="drama">
OTHELLO.<br>
Dost thou hear, Iago?<br>
I will be found most cunning in my patience;<br>
But,—dost thou hear?—most bloody.
</p>

<p class="drama">
IAGO.<br>
That’s not amiss.<br>
But yet keep time in all. Will you withdraw?
</p>

<p class="right">
[<i><span class="charname">Othello</span> withdraws.</i>]
</p>

<p class="drama">
Now will I question Cassio of Bianca,<br>
A housewife that by selling her desires<br>
Buys herself bread and clothes: it is a creature<br>
That dotes on Cassio, (as ’tis the strumpet’s plague<br>
To beguile many and be beguil’d by one.)<br>
He, when he hears of her, cannot refrain<br>
From the excess of laughter. Here he comes.
</p>

<p class="scenedesc">
Enter <span class="charname">Cassio</span>.
</p>

<p class="drama">
As he shall smile Othello shall go mad,<br>
And his unbookish jealousy must construe<br>
Poor Cassio’s smiles, gestures, and light behaviour<br>
Quite in the wrong. How do you now, lieutenant?
</p>

<p class="drama">
CASSIO.<br>
The worser that you give me the addition<br>
Whose want even kills me.
</p>

<p class="drama">
IAGO.<br>
Ply Desdemona well, and you are sure on’t.<br>
[<i>Speaking lower.</i>] Now, if this suit lay in Bianca’s power,<br>
How quickly should you speed!
</p>

<p class="drama">
CASSIO.<br>
Alas, poor caitiff!
</p>

<p class="drama">
OTHELLO.<br>
[<i>Aside.</i>] Look how he laughs already!
</p>

<p class="drama">
IAGO.<br>
I never knew a woman love man so.
</p>

<p class="drama">
CASSIO.<br>
Alas, poor rogue! I think, i’ faith, she loves me.
</p>

<p class="drama">
OTHELLO.<br>
[<i>Aside.</i>] Now he denies it faintly and laughs it out.
</p>

<p class="drama">
IAGO.<br>
Do you hear, Cassio?
</p>

<p class="drama">
OTHELLO.<br>
Now he importunes him<br>
To tell it o’er. Go to, well said, well said.
</p>

<p class="drama">
IAGO.<br>
She gives it out that you shall marry her.<br>
Do you intend it?
</p>

<p class="drama">
CASSIO.<br>
Ha, ha, ha!
</p>

<p class="drama">
OTHELLO.<br>
Do you triumph, Roman? Do you triumph?
</p>

<p class="drama">
CASSIO.<br>
I marry her? What? A customer? I prithee, bear some charity to my wit, do not
think it so unwholesome. Ha, ha, ha!
</p>

<p class="drama">
OTHELLO.<br>
So, so, so, so. They laugh that wins.
</p>

<p class="drama">
IAGO.<br>
Faith, the cry goes that you shall marry her.
</p>

<p class="drama">
CASSIO.<br>
Prithee say true.
</p>

<p class="drama">
IAGO.<br>
I am a very villain else.
</p>

<p class="drama">
OTHELLO.<br>
Have you scored me? Well.
</p>

<p class="drama">
CASSIO.<br>
This is the monkey’s own giving out. She is persuaded I will marry her, out of
her own love and flattery, not out of my promise.
</p>

<p class="drama">
OTHELLO.<br>
Iago beckons me. Now he begins the story.
</p>

<p class="drama">
CASSIO.<br>
She was here even now. She haunts me in every place. I was the other day
talking on the sea-bank with certain Venetians, and thither comes the bauble,
and falls thus about my neck.
</p>

<p class="drama">
OTHELLO.<br>
Crying, “O dear Cassio!” as it were: his gesture imports it.
</p>

<p class="drama">
CASSIO.<br>
So hangs, and lolls, and weeps upon me; so hales and pulls me. Ha, ha, ha!
</p>

<p class="drama">
OTHELLO.<br>
Now he tells how she plucked him to my chamber. O, I see that nose of yours,
but not that dog I shall throw it to.
</p>

<p class="drama">
CASSIO.<br>
Well, I must leave her company.
</p>

<p class="drama">
IAGO.<br>
Before me! look where she comes.
</p>

<p class="scenedesc">
Enter <span class="charname">Bianca</span>.
</p>

<p class="drama">
CASSIO.<br>
’Tis such another fitchew! Marry, a perfum’d one.<br>
What do you mean by this haunting of me?
</p>

<p class="drama">
BIANCA.<br>
Let the devil and his dam haunt you! What did you mean by that same
handkerchief you gave me even now? I was a fine fool to take it. I must take
out the work? A likely piece of work, that you should find it in your chamber
and not know who left it there! This is some minx’s token, and I must take out
the work? There, give it your hobby-horse. Wheresoever you had it, I’ll take
out no work on’t.
</p>

<p class="drama">
CASSIO.<br>
How now, my sweet Bianca? How now, how now?
</p>

<p class="drama">
OTHELLO.<br>
By heaven, that should be my handkerchief!
</p>

<p class="drama">
BIANCA.<br>
If you’ll come to supper tonight, you may. If you will not, come when you are
next prepared for.
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="drama">
IAGO.<br>
After her, after her.
</p>

<p class="drama">
CASSIO.<br>
Faith, I must; she’ll rail in the street else.
</p>

<p class="drama">
IAGO.<br>
Will you sup there?
</p>

<p class="drama">
CASSIO.<br>
Faith, I intend so.
</p>

<p class="drama">
IAGO.<br>
Well, I may chance to see you, for I would very fain speak with you.
</p>

<p class="drama">
CASSIO.<br>
Prithee come, will you?
</p>

<p class="drama">
IAGO.<br>
Go to; say no more.
</p>

<p class="right">
[<i>Exit <span class="charname">Cassio</span>.</i>]
</p>

<p class="drama">
OTHELLO.<br>
[<i>Coming forward.</i>] How shall I murder him, Iago?
</p>

<p class="drama">
IAGO.<br>
Did you perceive how he laughed at his vice?
</p>

<p class="drama">
OTHELLO.<br>
O Iago!
</p>

<p class="drama">
IAGO.<br>
And did you see the handkerchief?
</p>

<p class="drama">
OTHELLO.<br>
Was that mine?
</p>

<p class="drama">
IAGO.<br>
Yours, by this hand: and to see how he prizes the foolish woman your wife! she
gave it him, and he hath given it his whore.
</p>

<p class="drama">
OTHELLO.<br>
I would have him nine years a-killing. A fine woman, a fair woman, a sweet
woman!
</p>

<p class="drama">
IAGO.<br>
Nay, you must forget that.
</p>

<p class="drama">
OTHELLO.<br>
Ay, let her rot, and perish, and be damned tonight, for she shall not live. No,
my heart is turned to stone; I strike it, and it hurts my hand. O, the world
hath not a sweeter creature. She might lie by an emperor’s side, and command
him tasks.
</p>

<p class="drama">
IAGO.<br>
Nay, that’s not your way.
</p>

<p class="drama">
OTHELLO.<br>
Hang her, I do but say what she is. So delicate with her needle, an admirable
musician! O, she will sing the savageness out of a bear! Of so high and
plenteous wit and invention!
</p>

<p class="drama">
IAGO.<br>
She’s the worse for all this.
</p>

<p class="drama">
OTHELLO.<br>
O, a thousand, a thousand times: and then of so gentle a condition!
</p>

<p class="drama">
IAGO.<br>
Ay, too gentle.
</p>

<p class="drama">
OTHELLO.<br>
Nay, that’s certain. But yet the pity of it, Iago! O Iago, the pity of it,
Iago!
</p>

<p class="drama">
IAGO.<br>
If you are so fond over her iniquity, give her patent to offend, for if it
touch not you, it comes near nobody.
</p>

<p class="drama">
OTHELLO.<br>
I will chop her into messes. Cuckold me!
</p>

<p class="drama">
IAGO.<br>
O, ’tis foul in her.
</p>

<p class="drama">
OTHELLO.<br>
With mine officer!
</p>

<p class="drama">
IAGO.<br>
That’s fouler.
</p>

<p class="drama">
OTHELLO.<br>
Get me some poison, Iago; this night. I’ll not expostulate with her, lest her
body and beauty unprovide my mind again. This night, Iago.
</p>

<p class="drama">
IAGO.<br>
Do it not with poison, strangle her in her bed, even the bed she hath
contaminated.
</p>

<p class="drama">
OTHELLO.<br>
Good, good. The justice of it pleases. Very good.
</p>

<p class="drama">
IAGO.<br>
And for Cassio, let me be his undertaker. You shall hear more by midnight.
</p>

<p class="drama">
OTHELLO.<br>
Excellent good. [<i>A trumpet within.</i>] What trumpet is that same?
</p>

<p class="scenedesc">
Enter <span class="charname">Lodovico, Desdemona</span> and Attendant.
</p>

<p class="drama">
IAGO.<br>
Something from Venice, sure. ’Tis Lodovico<br>
Come from the duke. See, your wife is with him.
</p>

<p class="drama">
LODOVICO.<br>
Save you, worthy general!
</p>

<p class="drama">
OTHELLO.<br>
With all my heart, sir.
</p>

<p class="drama">
LODOVICO.<br>
The duke and senators of Venice greet you.
</p>

<p class="right">
[<i>Gives him a packet.</i>]
</p>

<p class="drama">
OTHELLO.<br>
I kiss the instrument of their pleasures.
</p>

<p class="right">
[<i>Opens the packet and reads.</i>]
</p>

<p class="drama">
DESDEMONA.<br>
And what’s the news, good cousin Lodovico?
</p>

<p class="drama">
IAGO.<br>
I am very glad to see you, signior.<br>
Welcome to Cyprus.
</p>

<p class="drama">
LODOVICO.<br>
I thank you. How does Lieutenant Cassio?
</p>

<p class="drama">
IAGO.<br>
Lives, sir.
</p>

<p class="drama">
DESDEMONA.<br>
Cousin, there’s fall’n between him and my lord<br>
An unkind breach, but you shall make all well.
</p>

<p class="drama">
OTHELLO.<br>
Are you sure of that?
</p>

<p class="drama">
DESDEMONA.<br>
My lord?
</p>

<p class="drama">
OTHELLO.<br>
[<i>Reads.</i>] “This fail you not to do, as you will—”
</p>

<p class="drama">
LODOVICO.<br>
He did not call; he’s busy in the paper.<br>
Is there division ’twixt my lord and Cassio?
</p>

<p class="drama">
DESDEMONA.<br>
A most unhappy one. I would do much<br>
To atone them, for the love I bear to Cassio.
</p>

<p class="drama">
OTHELLO.<br>
Fire and brimstone!
</p>

<p class="drama">
DESDEMONA.<br>
My lord?
</p>

<p class="drama">
OTHELLO.<br>
Are you wise?
</p>

<p class="drama">
DESDEMONA.<br>
What, is he angry?
</p>

<p class="drama">
LODOVICO.<br>
May be the letter mov’d him;<br>
For, as I think, they do command him home,<br>
Deputing Cassio in his government.
</p>

<p class="drama">
DESDEMONA.<br>
Trust me, I am glad on’t.
</p>

<p class="drama">
OTHELLO.<br>
Indeed!
</p>

<p class="drama">
DESDEMONA.<br>
My lord?
</p>

<p class="drama">
OTHELLO.<br>
I am glad to see you mad.
</p>

<p class="drama">
DESDEMONA.<br>
Why, sweet Othello?
</p>

<p class="drama">
OTHELLO.<br>
Devil!
</p>

<p class="right">
[<i>Striking her.</i>]
</p>

<p class="drama">
DESDEMONA.<br>
I have not deserv’d this.
</p>

<p class="drama">
LODOVICO.<br>
My lord, this would not be believ’d in Venice,<br>
Though I should swear I saw’t: ’tis very much.<br>
Make her amends. She weeps.
</p>

<p class="drama">
OTHELLO.<br>
O devil, devil!<br>
If that the earth could teem with woman’s tears,<br>
Each drop she falls would prove a crocodile.<br>
Out of my sight!
</p>

<p class="drama">
DESDEMONA.<br>
I will not stay to offend you.
</p>

<p class="right">
[<i>Going.</i>]
</p>

<p class="drama">
LODOVICO.<br>
Truly, an obedient lady.<br>
I do beseech your lordship, call her back.
</p>

<p class="drama">
OTHELLO.<br>
Mistress!
</p>

<p class="drama">
DESDEMONA.<br>
My lord?
</p>

<p class="drama">
OTHELLO.<br>
What would you with her, sir?
</p>

<p class="drama">
LODOVICO.<br>
Who, I, my lord?
</p>

<p class="drama">
OTHELLO.<br>
Ay, you did wish that I would make her turn.<br>
Sir, she can turn, and turn, and yet go on,<br>
And turn again. And she can weep, sir, weep;<br>
And she’s obedient, as you say, obedient,<br>
Very obedient. Proceed you in your tears.<br>
Concerning this, sir,—O well-painted passion!<br>
I am commanded home.—Get you away;<br>
I’ll send for you anon.—Sir, I obey the mandate,<br>
And will return to Venice.—Hence, avaunt!
</p>

<p class="right">
[<i>Exit <span class="charname">Desdemona</span>.</i>]
</p>

<p class="drama">
Cassio shall have my place. And, sir, tonight,<br>
I do entreat that we may sup together.<br>
You are welcome, sir, to Cyprus. Goats and monkeys!
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="drama">
LODOVICO.<br>
Is this the noble Moor, whom our full senate<br>
Call all in all sufficient? Is this the nature<br>
Whom passion could not shake? whose solid virtue<br>
The shot of accident nor dart of chance<br>
Could neither graze nor pierce?
</p>

<p class="drama">
IAGO.<br>
He is much chang’d.
</p>

<p class="drama">
LODOVICO.<br>
Are his wits safe? Is he not light of brain?
</p>

<p class="drama">
IAGO.<br>
He’s that he is. I may not breathe my censure<br>
What he might be. If what he might he is not,<br>
I would to heaven he were!
</p>

<p class="drama">
LODOVICO.<br>
What, strike his wife?
</p>

<p class="drama">
IAGO.<br>
Faith, that was not so well; yet would I knew<br>
That stroke would prove the worst!
</p>

<p class="drama">
LODOVICO.<br>
Is it his use?<br>
Or did the letters work upon his blood,<br>
And new-create this fault?
</p>

<p class="drama">
IAGO.<br>
Alas, alas!<br>
It is not honesty in me to speak<br>
What I have seen and known. You shall observe him,<br>
And his own courses will denote him so<br>
That I may save my speech: do but go after,<br>
And mark how he continues.
</p>

<p class="drama">
LODOVICO.<br>
I am sorry that I am deceiv’d in him.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneIV_26.2"></a><b>SCENE II. Cyprus. A Room in the
Castle.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Othello</span> and <span class="charname">Emilia</span>.
</p>

<p class="drama">
OTHELLO.<br>
You have seen nothing, then?
</p>

<p class="drama">
EMILIA.<br>
Nor ever heard, nor ever did suspect.
</p>

<p class="drama">
OTHELLO.<br>
Yes, you have seen Cassio and she together.
</p>

<p class="drama">
EMILIA.<br>
But then I saw no harm, and then I heard<br>
Each syllable that breath made up between them.
</p>

<p class="drama">
OTHELLO.<br>
What, did they never whisper?
</p>

<p class="drama">
EMILIA.<br>
Never, my lord.
</p>

<p class="drama">
OTHELLO.<br>
Nor send you out o’ the way?
</p>

<p class="drama">
EMILIA.<br>
Never.
</p>

<p class="drama">
OTHELLO.<br>
To fetch her fan, her gloves, her mask, nor nothing?
</p>

<p class="drama">
EMILIA.<br>
Never, my lord.
</p>

<p class="drama">
OTHELLO.<br>
That’s strange.
</p>

<p class="drama">
EMILIA.<br>
I durst, my lord, to wager she is honest,<br>
Lay down my soul at stake: if you think other,<br>
Remove your thought, it doth abuse your bosom.<br>
If any wretch have put this in your head,<br>
Let heaven requite it with the serpent’s curse,<br>
For if she be not honest, chaste, and true,<br>
There’s no man happy. The purest of their wives<br>
Is foul as slander.
</p>

<p class="drama">
OTHELLO.<br>
Bid her come hither. Go.
</p>

<p class="right">
[<i>Exit <span class="charname">Emilia</span>.</i>]
</p>

<p class="drama">
She says enough. Yet she’s a simple bawd<br>
That cannot say as much. This is a subtle whore,<br>
A closet lock and key of villainous secrets.<br>
And yet she’ll kneel and pray. I have seen her do ’t.
</p>

<p class="scenedesc">
Enter <span class="charname">Desdemona</span> and <span class="charname">Emilia</span>.
</p>

<p class="drama">
DESDEMONA.<br>
My lord, what is your will?
</p>

<p class="drama">
OTHELLO.<br>
Pray, chuck, come hither.
</p>

<p class="drama">
DESDEMONA.<br>
What is your pleasure?
</p>

<p class="drama">
OTHELLO.<br>
Let me see your eyes.<br>
Look in my face.
</p>

<p class="drama">
DESDEMONA.<br>
What horrible fancy’s this?
</p>

<p class="drama">
OTHELLO.<br>
[<i>To Emilia.</i>] Some of your function, mistress, <br>
Leave procreants alone, and shut the door.<br>
Cough, or cry hem, if anybody come.<br>
Your mystery, your mystery. Nay, dispatch.
</p>

<p class="right">
[<i>Exit <span class="charname">Emilia</span>.</i>]
</p>

<p class="drama">
DESDEMONA.<br>
Upon my knees, what doth your speech import?<br>
I understand a fury in your words,<br>
But not the words.
</p>

<p class="drama">
OTHELLO.<br>
Why, what art thou?
</p>

<p class="drama">
DESDEMONA.<br>
Your wife, my lord, your true and loyal wife.
</p>

<p class="drama">
OTHELLO.<br>
Come, swear it, damn thyself,<br>
Lest, being like one of heaven, the devils themselves<br>
Should fear to seize thee. Therefore be double-damn’d.<br>
Swear thou art honest.
</p>

<p class="drama">
DESDEMONA.<br>
Heaven doth truly know it.
</p>

<p class="drama">
OTHELLO.<br>
Heaven truly knows that thou art false as hell.
</p>

<p class="drama">
DESDEMONA.<br>
To whom, my lord? With whom? How am I false?
</p>

<p class="drama">
OTHELLO.<br>
O Desdemona, away! away! away!
</p>

<p class="drama">
DESDEMONA.<br>
Alas the heavy day, why do you weep?<br>
Am I the motive of these tears, my lord?<br>
If haply you my father do suspect<br>
An instrument of this your calling back,<br>
Lay not your blame on me. If you have lost him,<br>
Why, I have lost him too.
</p>

<p class="drama">
OTHELLO.<br>
Had it pleas’d heaven<br>
To try me with affliction, had they rain’d<br>
All kinds of sores and shames on my bare head,<br>
Steep’d me in poverty to the very lips,<br>
Given to captivity me and my utmost hopes,<br>
I should have found in some place of my soul<br>
A drop of patience. But, alas, to make me<br>
A fixed figure for the time of scorn<br>
To point his slow unmoving finger at.<br>
Yet could I bear that too, well, very well:<br>
But there, where I have garner’d up my heart,<br>
Where either I must live or bear no life,<br>
The fountain from the which my current runs,<br>
Or else dries up, to be discarded thence,<br>
Or keep it as a cistern for foul toads<br>
To knot and gender in!—turn thy complexion there,<br>
Patience, thou young and rose-lipp’d cherubin,<br>
Ay, there, look grim as hell!
</p>

<p class="drama">
DESDEMONA.<br>
I hope my noble lord esteems me honest.
</p>

<p class="drama">
OTHELLO.<br>
O, ay, as summer flies are in the shambles,<br>
That quicken even with blowing. O thou weed,<br>
Who art so lovely fair, and smell’st so sweet,<br>
That the sense aches at thee,<br>
Would thou hadst ne’er been born!
</p>

<p class="drama">
DESDEMONA.<br>
Alas, what ignorant sin have I committed?
</p>

<p class="drama">
OTHELLO.<br>
Was this fair paper, this most goodly book,<br>
Made to write “whore” upon? What committed?<br>
Committed! O thou public commoner!<br>
I should make very forges of my cheeks,<br>
That would to cinders burn up modesty,<br>
Did I but speak thy deeds. What committed!<br>
Heaven stops the nose at it, and the moon winks;<br>
The bawdy wind, that kisses all it meets,<br>
Is hush’d within the hollow mine of earth,<br>
And will not hear it. What committed!<br>
Impudent strumpet!
</p>

<p class="drama">
DESDEMONA.<br>
By heaven, you do me wrong.
</p>

<p class="drama">
OTHELLO.<br>
Are not you a strumpet?
</p>

<p class="drama">
DESDEMONA.<br>
No, as I am a Christian:<br>
If to preserve this vessel for my lord<br>
From any other foul unlawful touch<br>
Be not to be a strumpet, I am none.
</p>

<p class="drama">
OTHELLO.<br>
What, not a whore?
</p>

<p class="drama">
DESDEMONA.<br>
No, as I shall be sav’d.
</p>

<p class="drama">
OTHELLO.<br>
Is’t possible?
</p>

<p class="drama">
DESDEMONA.<br>
O, heaven forgive us!
</p>

<p class="drama">
OTHELLO.<br>
I cry you mercy then.<br>
I took you for that cunning whore of Venice<br>
That married with Othello.—You, mistress,
</p>

<p class="scenedesc">
Enter <span class="charname">Emilia</span>.
</p>

<p class="drama">
That have the office opposite to Saint Peter,<br>
And keeps the gate of hell. You, you, ay, you!<br>
We have done our course; there’s money for your pains.<br>
I pray you turn the key, and keep our counsel.
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="drama">
EMILIA.<br>
Alas, what does this gentleman conceive?<br>
How do you, madam? How do you, my good lady?
</p>

<p class="drama">
DESDEMONA.<br>
Faith, half asleep.
</p>

<p class="drama">
EMILIA.<br>
Good madam, what’s the matter with my lord?
</p>

<p class="drama">
DESDEMONA.<br>
With who?
</p>

<p class="drama">
EMILIA.<br>
Why, with my lord, madam.
</p>

<p class="drama">
DESDEMONA.<br>
Who is thy lord?
</p>

<p class="drama">
EMILIA.<br>
He that is yours, sweet lady.
</p>

<p class="drama">
DESDEMONA.<br>
I have none. Do not talk to me, Emilia,<br>
I cannot weep, nor answer have I none<br>
But what should go by water. Prithee, tonight<br>
Lay on my bed my wedding sheets, remember,<br>
And call thy husband hither.
</p>

<p class="drama">
EMILIA.<br>
Here’s a change indeed!
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="drama">
DESDEMONA.<br>
’Tis meet I should be us’d so, very meet.<br>
How have I been behav’d, that he might stick<br>
The small’st opinion on my least misuse?
</p>

<p class="scenedesc">
Enter <span class="charname">Iago</span> and <span class="charname">Emilia</span>.
</p>

<p class="drama">
IAGO.<br>
What is your pleasure, madam? How is’t with you?
</p>

<p class="drama">
DESDEMONA.<br>
I cannot tell. Those that do teach young babes<br>
Do it with gentle means and easy tasks.<br>
He might have chid me so, for, in good faith,<br>
I am a child to chiding.
</p>

<p class="drama">
IAGO.<br>
What’s the matter, lady?
</p>

<p class="drama">
EMILIA.<br>
Alas, Iago, my lord hath so bewhor’d her,<br>
Thrown such despite and heavy terms upon her,<br>
As true hearts cannot bear.
</p>

<p class="drama">
DESDEMONA.<br>
Am I that name, Iago?
</p>

<p class="drama">
IAGO.<br>
What name, fair lady?
</p>

<p class="drama">
DESDEMONA.<br>
Such as she says my lord did say I was.
</p>

<p class="drama">
EMILIA.<br>
He call’d her whore: a beggar in his drink<br>
Could not have laid such terms upon his callet.
</p>

<p class="drama">
IAGO.<br>
Why did he so?
</p>

<p class="drama">
DESDEMONA.<br>
I do not know. I am sure I am none such.
</p>

<p class="drama">
IAGO.<br>
Do not weep, do not weep: alas the day!
</p>

<p class="drama">
EMILIA.<br>
Hath she forsook so many noble matches,<br>
Her father, and her country, and her friends,<br>
To be call’d whore? would it not make one weep?
</p>

<p class="drama">
DESDEMONA.<br>
It is my wretched fortune.
</p>

<p class="drama">
IAGO.<br>
Beshrew him for’t!<br>
How comes this trick upon him?
</p>

<p class="drama">
DESDEMONA.<br>
Nay, heaven doth know.
</p>

<p class="drama">
EMILIA.<br>
I will be hang’d, if some eternal villain,<br>
Some busy and insinuating rogue,<br>
Some cogging, cozening slave, to get some office,<br>
Have not devis’d this slander. I’ll be hang’d else.
</p>

<p class="drama">
IAGO.<br>
Fie, there is no such man. It is impossible.
</p>

<p class="drama">
DESDEMONA.<br>
If any such there be, heaven pardon him!
</p>

<p class="drama">
EMILIA.<br>
A halter pardon him, and hell gnaw his bones!<br>
Why should he call her whore? who keeps her company?<br>
What place? what time? what form? what likelihood?<br>
The Moor’s abused by some most villainous knave,<br>
Some base notorious knave, some scurvy fellow.<br>
O heaven, that such companions thou’dst unfold,<br>
And put in every honest hand a whip<br>
To lash the rascals naked through the world<br>
Even from the east to the west!
</p>

<p class="drama">
IAGO.<br>
Speak within door.
</p>

<p class="drama">
EMILIA.<br>
O, fie upon them! Some such squire he was<br>
That turn’d your wit the seamy side without,<br>
And made you to suspect me with the Moor.
</p>

<p class="drama">
IAGO.<br>
You are a fool. Go to.
</p>

<p class="drama">
DESDEMONA.<br>
Alas, Iago,<br>
What shall I do to win my lord again?<br>
Good friend, go to him. For by this light of heaven,<br>
I know not how I lost him. Here I kneel.<br>
If e’er my will did trespass ’gainst his love,<br>
Either in discourse of thought or actual deed,<br>
Or that mine eyes, mine ears, or any sense,<br>
Delighted them in any other form,<br>
Or that I do not yet, and ever did,<br>
And ever will, (though he do shake me off<br>
To beggarly divorcement) love him dearly,<br>
Comfort forswear me! Unkindness may do much;<br>
And his unkindness may defeat my life,<br>
But never taint my love. I cannot say “whore,”<br>
It does abhor me now I speak the word;<br>
To do the act that might the addition earn<br>
Not the world’s mass of vanity could make me.
</p>

<p class="drama">
IAGO.<br>
I pray you, be content. ’Tis but his humour.<br>
The business of the state does him offence,<br>
And he does chide with you.
</p>

<p class="drama">
DESDEMONA.<br>
If ’twere no other,—
</p>

<p class="drama">
IAGO.<br>
’Tis but so, I warrant.
</p>

<p class="right">
[<i>Trumpets within.</i>]
</p>

<p class="drama">
Hark, how these instruments summon to supper.<br>
The messengers of Venice stay the meat.<br>
Go in, and weep not. All things shall be well.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Desdemona</span> and <span class="charname">Emilia</span>.</i>]
</p>

<p class="scenedesc">
Enter <span class="charname">Roderigo</span>.
</p>

<p class="drama">
How now, Roderigo?
</p>

<p class="drama">
RODERIGO.<br>
I do not find that thou dealest justly with me.
</p>

<p class="drama">
IAGO.<br>
What in the contrary?
</p>

<p class="drama">
RODERIGO.<br>
Every day thou daffest me with some device, Iago, and rather, as it seems to me
now, keepest from me all conveniency than suppliest me with the least advantage
of hope. I will indeed no longer endure it. Nor am I yet persuaded to put up in
peace what already I have foolishly suffered.
</p>

<p class="drama">
IAGO.<br>
Will you hear me, Roderigo?
</p>

<p class="drama">
RODERIGO.<br>
Faith, I have heard too much, for your words and performances are no kin
together.
</p>

<p class="drama">
IAGO.<br>
You charge me most unjustly.
</p>

<p class="drama">
RODERIGO.<br>
With naught but truth. I have wasted myself out of my means. The jewels you
have had from me to deliver to Desdemona would half have corrupted a votarist:
you have told me she hath received them, and returned me expectations and
comforts of sudden respect and acquaintance, but I find none.
</p>

<p class="drama">
IAGO.<br>
Well, go to, very well.
</p>

<p class="drama">
RODERIGO.<br>
Very well, go to, I cannot go to, man, nor ’tis not very well. Nay, I say ’tis
very scurvy, and begin to find myself fopped in it.
</p>

<p class="drama">
IAGO.<br>
Very well.
</p>

<p class="drama">
RODERIGO.<br>
I tell you ’tis not very well. I will make myself known to Desdemona. If she
will return me my jewels, I will give over my suit and repent my unlawful
solicitation. If not, assure yourself I will seek satisfaction of you.
</p>

<p class="drama">
IAGO.<br>
You have said now.
</p>

<p class="drama">
RODERIGO.<br>
Ay, and said nothing but what I protest intendment of doing.
</p>

<p class="drama">
IAGO.<br>
Why, now I see there’s mettle in thee, and even from this instant do build on
thee a better opinion than ever before. Give me thy hand, Roderigo. Thou hast
taken against me a most just exception, but yet I protest, I have dealt most
directly in thy affair.
</p>

<p class="drama">
RODERIGO.<br>
It hath not appeared.
</p>

<p class="drama">
IAGO.<br>
I grant indeed it hath not appeared, and your suspicion is not without wit and
judgement. But, Roderigo, if thou hast that in thee indeed, which I have
greater reason to believe now than ever,—I mean purpose, courage, and
valour,—this night show it. If thou the next night following enjoy not
Desdemona, take me from this world with treachery and devise engines for my
life.
</p>

<p class="drama">
RODERIGO.<br>
Well, what is it? Is it within reason and compass?
</p>

<p class="drama">
IAGO.<br>
Sir, there is especial commission come from Venice to depute Cassio in
Othello’s place.
</p>

<p class="drama">
RODERIGO.<br>
Is that true? Why then Othello and Desdemona return again to Venice.
</p>

<p class="drama">
IAGO.<br>
O, no; he goes into Mauritania, and takes away with him the fair Desdemona,
unless his abode be lingered here by some accident: wherein none can be so
determinate as the removing of Cassio.
</p>

<p class="drama">
RODERIGO.<br>
How do you mean “removing” of him?
</p>

<p class="drama">
IAGO.<br>
Why, by making him uncapable of Othello’s place: knocking out his brains.
</p>

<p class="drama">
RODERIGO.<br>
And that you would have me to do?
</p>

<p class="drama">
IAGO.<br>
Ay, if you dare do yourself a profit and a right. He sups tonight with a
harlotry, and thither will I go to him. He knows not yet of his honourable
fortune. If you will watch his going thence, which I will fashion to fall out
between twelve and one, you may take him at your pleasure: I will be near to
second your attempt, and he shall fall between us. Come, stand not amazed at
it, but go along with me. I will show you such a necessity in his death that
you shall think yourself bound to put it on him. It is now high supper-time,
and the night grows to waste. About it.
</p>

<p class="drama">
RODERIGO.<br>
I will hear further reason for this.
</p>

<p class="drama">
IAGO.<br>
And you shall be satisfied.
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3> <a id="sceneIV_26.3"></a><b>SCENE III. Cyprus. Another Room in the
Castle.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Othello, Lodovico, Desdemona, Emilia</span> and
Attendants.
</p>

<p class="drama">
LODOVICO.<br>
I do beseech you, sir, trouble yourself no further.
</p>

<p class="drama">
OTHELLO.<br>
O, pardon me; ’twill do me good to walk.
</p>

<p class="drama">
LODOVICO.<br>
Madam, good night. I humbly thank your ladyship.
</p>

<p class="drama">
DESDEMONA.<br>
Your honour is most welcome.
</p>

<p class="drama">
OTHELLO.<br>
Will you walk, sir?—<br>
O, Desdemona,—
</p>

<p class="drama">
DESDEMONA.<br>
My lord?
</p>

<p class="drama">
OTHELLO.<br>
Get you to bed on th’ instant, I will be return’d forthwith. Dismiss your
attendant there. Look ’t be done.
</p>

<p class="drama">
DESDEMONA.<br>
I will, my lord.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Othello, Lodovico</span> and Attendants.</i>]
</p>

<p class="drama">
EMILIA.<br>
How goes it now? He looks gentler than he did.
</p>

<p class="drama">
DESDEMONA.<br>
He says he will return incontinent,<br>
He hath commanded me to go to bed,<br>
And bade me to dismiss you.
</p>

<p class="drama">
EMILIA.<br>
Dismiss me?
</p>

<p class="drama">
DESDEMONA.<br>
It was his bidding. Therefore, good Emilia,<br>
Give me my nightly wearing, and adieu.<br>
We must not now displease him.
</p>

<p class="drama">
EMILIA.<br>
I would you had never seen him!
</p>

<p class="drama">
DESDEMONA.<br>
So would not I. My love doth so approve him,<br>
That even his stubbornness, his checks, his frowns,—<br>
Prithee, unpin me,—have grace and favour in them.
</p>

<p class="drama">
EMILIA.<br>
I have laid those sheets you bade me on the bed.
</p>

<p class="drama">
DESDEMONA.<br>
All’s one. Good faith, how foolish are our minds!<br>
If I do die before thee, prithee, shroud me<br>
In one of those same sheets.
</p>

<p class="drama">
EMILIA.<br>
Come, come, you talk.
</p>

<p class="drama">
DESDEMONA.<br>
My mother had a maid call’d Barbary,<br>
She was in love, and he she lov’d prov’d mad<br>
And did forsake her. She had a song of “willow”,<br>
An old thing ’twas, but it express’d her fortune,<br>
And she died singing it. That song tonight<br>
Will not go from my mind. I have much to do<br>
But to go hang my head all at one side<br>
And sing it like poor Barbary. Prithee dispatch.
</p>

<p class="drama">
EMILIA.<br>
Shall I go fetch your night-gown?
</p>

<p class="drama">
DESDEMONA.<br>
No, unpin me here.<br>
This Lodovico is a proper man.
</p>

<p class="drama">
EMILIA.<br>
A very handsome man.
</p>

<p class="drama">
DESDEMONA.<br>
He speaks well.
</p>

<p class="drama">
EMILIA.<br>
I know a lady in Venice would have walked barefoot to Palestine for a touch of
his nether lip.
</p>

<p class="drama">
DESDEMONA.<br>
[<i>Singing.</i>]<br>
    <i>The poor soul sat sighing by a sycamore tree,<br>
        Sing all a green willow.<br>
    Her hand on her bosom, her head on her knee,<br>
        Sing willow, willow, willow.<br>
    The fresh streams ran by her, and murmur’d her moans,<br>
        Sing willow, willow, willow;<br>
    Her salt tears fell from her, and soften’d the stones;—</i>
</p>

<p class="drama">
Lay by these:—
</p>

<p class="drama">
[<i>Sings.</i>]<br>
        <i>Sing willow, willow, willow.</i>
</p>

<p class="drama">
Prithee hie thee. He’ll come anon.
</p>

<p class="drama">
[<i>Sings.</i>]<br>
    <i>Sing all a green willow must be my garland.<br>
Let nobody blame him, his scorn I approve,—</i>
</p>

<p class="drama">
Nay, that’s not next. Hark! who is’t that knocks?
</p>

<p class="drama">
EMILIA.<br>
It’s the wind.
</p>

<p class="drama">
DESDEMONA.<br>
[<i>Sings.</i>]<br>
    <i>I call’d my love false love; but what said he then?<br>
        Sing willow, willow, willow:<br>
    If I court mo women, you’ll couch with mo men.</i>
</p>

<p class="drama">
So get thee gone; good night. Mine eyes do itch;<br>
Doth that bode weeping?
</p>

<p class="drama">
EMILIA.<br>
’Tis neither here nor there.
</p>

<p class="drama">
DESDEMONA.<br>
I have heard it said so. O, these men, these men!<br>
Dost thou in conscience think,—tell me, Emilia,—<br>
That there be women do abuse their husbands<br>
In such gross kind?
</p>

<p class="drama">
EMILIA.<br>
There be some such, no question.
</p>

<p class="drama">
DESDEMONA.<br>
Wouldst thou do such a deed for all the world?
</p>

<p class="drama">
EMILIA.<br>
Why, would not you?
</p>

<p class="drama">
DESDEMONA.<br>
No, by this heavenly light!
</p>

<p class="drama">
EMILIA.<br>
Nor I neither by this heavenly light,<br>
I might do’t as well i’ the dark.
</p>

<p class="drama">
DESDEMONA.<br>
Wouldst thou do such a deed for all the world?
</p>

<p class="drama">
EMILIA.<br>
The world’s a huge thing. It is a great price<br>
For a small vice.
</p>

<p class="drama">
DESDEMONA.<br>
In troth, I think thou wouldst not.
</p>

<p class="drama">
EMILIA.<br>
In troth, I think I should, and undo’t when I had done. Marry, I would not do
such a thing for a joint-ring, nor for measures of lawn, nor for gowns,
petticoats, nor caps, nor any petty exhibition; but, for the whole world—why,
who would not make her husband a cuckold to make him a monarch? I should
venture purgatory for ’t.
</p>

<p class="drama">
DESDEMONA.<br>
Beshrew me, if I would do such a wrong for the whole world.
</p>

<p class="drama">
EMILIA.<br>
Why, the wrong is but a wrong i’ the world; and having the world for your
labour, ’tis a wrong in your own world, and you might quickly make it right.
</p>

<p class="drama">
DESDEMONA.<br>
I do not think there is any such woman.
</p>

<p class="drama">
EMILIA.<br>
Yes, a dozen; and as many to the vantage as would store the world they played
for.<br>
But I do think it is their husbands’ faults<br>
If wives do fall: say that they slack their duties,<br>
And pour our treasures into foreign laps;<br>
Or else break out in peevish jealousies,<br>
Throwing restraint upon us. Or say they strike us,<br>
Or scant our former having in despite.<br>
Why, we have galls; and though we have some grace,<br>
Yet have we some revenge. Let husbands know<br>
Their wives have sense like them: they see, and smell<br>
And have their palates both for sweet and sour,<br>
As husbands have. What is it that they do<br>
When they change us for others? Is it sport?<br>
I think it is. And doth affection breed it?<br>
I think it doth. Is’t frailty that thus errs?<br>
It is so too. And have not we affections,<br>
Desires for sport, and frailty, as men have?<br>
Then let them use us well: else let them know,<br>
The ills we do, their ills instruct us so.
</p>

<p class="drama">
DESDEMONA.<br>
Good night, good night. Heaven me such usage send,<br>
Not to pick bad from bad, but by bad mend!
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

