<h2> <a id="sceneIV_37.1"></a><b>ACT IV</b></h2>

<h3> <b>SCENE I. A forest between Milan and Verona</b></h3>

<p class="scenedesc">
Enter certain <span class="charname">Outlaws</span>.
</p>

<p class="drama">
FIRST OUTLAW.<br>
Fellows, stand fast. I see a passenger.
</p>

<p class="drama">
SECOND OUTLAW.<br>
If there be ten, shrink not, but down with ’em.
</p>

<p class="scenedesc">
Enter <span class="charname">Valentine</span> and
<span class="charname">Speed</span>.
</p>

<p class="drama">
THIRD OUTLAW.<br>
Stand, sir, and throw us that you have about ye.<br>
If not, we’ll make you sit, and rifle you.
</p>

<p class="drama">
SPEED.<br>
Sir, we are undone: these are the villains<br>
That all the travellers do fear so much.
</p>

<p class="drama">
VALENTINE.<br>
My friends—
</p>

<p class="drama">
FIRST OUTLAW.<br>
That’s not so, sir. We are your enemies.
</p>

<p class="drama">
SECOND OUTLAW.<br>
Peace! We’ll hear him.
</p>

<p class="drama">
THIRD OUTLAW.<br>
Ay, by my beard, will we, for he is a proper man.
</p>

<p class="drama">
VALENTINE.<br>
Then know that I have little wealth to lose.<br>
A man I am crossed with adversity;<br>
My riches are these poor habiliments,<br>
Of which if you should here disfurnish me,<br>
You take the sum and substance that I have.
</p>

<p class="drama">
SECOND OUTLAW.<br>
Whither travel you?
</p>

<p class="drama">
VALENTINE.<br>
To Verona.
</p>

<p class="drama">
FIRST OUTLAW.<br>
Whence came you?
</p>

<p class="drama">
VALENTINE.<br>
From Milan.
</p>

<p class="drama">
THIRD OUTLAW.<br>
Have you long sojourned there?
</p>

<p class="drama">
VALENTINE.<br>
Some sixteen months, and longer might have stayed<br>
If crooked fortune had not thwarted me.
</p>

<p class="drama">
FIRST OUTLAW.<br>
What, were you banished thence?
</p>

<p class="drama">
VALENTINE.<br>
I was.
</p>

<p class="drama">
SECOND OUTLAW.<br>
For what offence?
</p>

<p class="drama">
VALENTINE.<br>
For that which now torments me to rehearse;<br>
I killed a man, whose death I much repent,<br>
But yet I slew him manfully in fight,<br>
Without false vantage or base treachery.
</p>

<p class="drama">
FIRST OUTLAW.<br>
Why, ne’er repent it, if it were done so.<br>
But were you banished for so small a fault?
</p>

<p class="drama">
VALENTINE.<br>
I was, and held me glad of such a doom.
</p>

<p class="drama">
SECOND OUTLAW.<br>
Have you the tongues?
</p>

<p class="drama">
VALENTINE.<br>
My youthful travel therein made me happy,<br>
Or else I often had been miserable.
</p>

<p class="drama">
THIRD OUTLAW.<br>
By the bare scalp of Robin Hood’s fat friar,<br>
This fellow were a king for our wild faction.
</p>

<p class="drama">
FIRST OUTLAW.<br>
We’ll have him. Sirs, a word.
</p>

<p class="drama">
SPEED.<br>
Master, be one of them. It’s an honourable kind of thievery.
</p>

<p class="drama">
VALENTINE.<br>
Peace, villain.
</p>

<p class="drama">
SECOND OUTLAW.<br>
Tell us this: have you anything to take to?
</p>

<p class="drama">
VALENTINE.<br>
Nothing but my fortune.
</p>

<p class="drama">
THIRD OUTLAW.<br>
Know then that some of us are gentlemen,<br>
Such as the fury of ungoverned youth<br>
Thrust from the company of awful men.<br>
Myself was from Verona banished<br>
For practising to steal away a lady,<br>
An heir, and near allied unto the Duke.
</p>

<p class="drama">
SECOND OUTLAW.<br>
And I from Mantua, for a gentleman<br>
Who, in my mood, I stabbed unto the heart.
</p>

<p class="drama">
FIRST OUTLAW.<br>
And I for suchlike petty crimes as these.<br>
But to the purpose, for we cite our faults,<br>
That they may hold excused our lawless lives;<br>
And partly, seeing you are beautified<br>
With goodly shape, and by your own report<br>
A linguist, and a man of such perfection<br>
As we do in our quality much want—
</p>

<p class="drama">
SECOND OUTLAW.<br>
Indeed because you are a banished man,<br>
Therefore, above the rest, we parley to you.<br>
Are you content to be our general?<br>
To make a virtue of necessity<br>
And live as we do in this wilderness?
</p>

<p class="drama">
THIRD OUTLAW.<br>
What sayst thou? Wilt thou be of our consort?<br>
Say “Ay”, and be the captain of us all,<br>
We’ll do thee homage and be ruled by thee,<br>
Love thee as our commander and our king.
</p>

<p class="drama">
FIRST OUTLAW.<br>
But if thou scorn our courtesy, thou diest.
</p>

<p class="drama">
SECOND OUTLAW.<br>
Thou shalt not live to brag what we have offered.
</p>

<p class="drama">
VALENTINE.<br>
I take your offer and will live with you,<br>
Provided that you do no outrages<br>
On silly women or poor passengers.
</p>

<p class="drama">
THIRD OUTLAW.<br>
No, we detest such vile base practices.<br>
Come, go with us; we’ll bring thee to our crews<br>
And show thee all the treasure we have got,<br>
Which, with ourselves, all rest at thy dispose.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneIV_37.2"></a><b>SCENE II. Milan. The court of the Duke’s palace</b></h3>

<p class="scenedesc">
Enter <span class="charname">Proteus</span>.
</p>

<p class="drama">
PROTEUS.<br>
Already have I been false to Valentine,<br>
And now I must be as unjust to Thurio.<br>
Under the colour of commending him,<br>
I have access my own love to prefer.<br>
But Silvia is too fair, too true, too holy<br>
To be corrupted with my worthless gifts.<br>
When I protest true loyalty to her,<br>
She twits me with my falsehood to my friend;<br>
When to her beauty I commend my vows,<br>
She bids me think how I have been forsworn<br>
In breaking faith with Julia, whom I loved;<br>
And notwithstanding all her sudden quips,<br>
The least whereof would quell a lover’s hope,<br>
Yet, spaniel-like, the more she spurns my love,<br>
The more it grows and fawneth on her still.<br>
But here comes Thurio. Now must we to her window,<br>
And give some evening music to her ear.
</p>

<p class="scenedesc">
Enter <span class="charname">Thurio</span> and Musicians.
</p>

<p class="drama">
THURIO.<br>
How now, Sir Proteus, are you crept before us?
</p>

<p class="drama">
PROTEUS.<br>
Ay, gentle Thurio, for you know that love<br>
Will creep in service where it cannot go.
</p>

<p class="drama">
THURIO.<br>
Ay, but I hope, sir, that you love not here.
</p>

<p class="drama">
PROTEUS.<br>
Sir, but I do, or else I would be hence.
</p>

<p class="drama">
THURIO.<br>
Who? Silvia?
</p>

<p class="drama">
PROTEUS.<br>
Ay, Silvia, for your sake.
</p>

<p class="drama">
THURIO.<br>
I thank you for your own. Now, gentlemen,<br>
Let’s tune, and to it lustily awhile.
</p>

<p class="scenedesc">
Enter <span class="charname">Host</span> and
<span class="charname">Julia</span> in boy’s clothes, as Sebastian.
</p>

<p class="drama">
HOST.<br>
Now, my young guest, methinks you’re allycholly. I pray you, why is it?
</p>

<p class="drama">
JULIA.<br>
Marry, mine host, because I cannot be merry.
</p>

<p class="drama">
HOST.<br>
Come, we’ll have you merry. I’ll bring you where you shall hear music, and see
the gentleman that you asked for.
</p>

<p class="drama">
JULIA.<br>
But shall I hear him speak?
</p>

<p class="drama">
HOST.<br>
Ay, that you shall.
</p>

<p class="drama">
JULIA.<br>
That will be music.
</p>

<p class="right">[<i>Music plays.</i>]</p>

<p class="drama">
HOST.<br>
Hark, hark!
</p>

<p class="drama">
JULIA.<br>
Is he among these?
</p>

<p class="drama">
HOST.<br>
Ay; but peace, let’s hear ’em.
</p>

<h4>SONG</h4>

<p class="drama">
PROTEUS.<br>
    Who is Silvia? What is she,<br>
      That all our swains commend her?<br>
    Holy, fair, and wise is she;<br>
      The heaven such grace did lend her,<br>
    That she might admired be.
</p>

<p class="drama">
    Is she kind as she is fair?<br>
      For beauty lives with kindness.<br>
    Love doth to her eyes repair,<br>
      To help him of his blindness;<br>
    And, being helped, inhabits there.
</p>

<p class="drama">
    Then to Silvia let us sing,<br>
      That Silvia is excelling;<br>
    She excels each mortal thing<br>
      Upon the dull earth dwelling.<br>
    To her let us garlands bring.
</p>

<p class="drama">
HOST.<br>
How now, are you sadder than you were before?<br>
How do you, man? The music likes you not.
</p>

<p class="drama">
JULIA.<br>
You mistake; the musician likes me not.
</p>

<p class="drama">
HOST.<br>
Why, my pretty youth?
</p>

<p class="drama">
JULIA.<br>
He plays false, father.
</p>

<p class="drama">
HOST.<br>
How, out of tune on the strings?
</p>

<p class="drama">
JULIA.<br>
Not so; but yet so false that he grieves my very heart-strings.
</p>

<p class="drama">
HOST.<br>
You have a quick ear.
</p>

<p class="drama">
JULIA.<br>
Ay, I would I were deaf; it makes me have a slow heart.
</p>

<p class="drama">
HOST.<br>
I perceive you delight not in music.
</p>

<p class="drama">
JULIA.<br>
Not a whit, when it jars so.
</p>

<p class="drama">
HOST.<br>
Hark, what fine change is in the music!
</p>

<p class="drama">
JULIA.<br>
Ay, that change is the spite.
</p>

<p class="drama">
HOST.<br>
You would have them always play but one thing?
</p>

<p class="drama">
JULIA.<br>
I would always have one play but one thing.<br>
But, host, doth this Sir Proteus, that we talk on,<br>
Often resort unto this gentlewoman?
</p>

<p class="drama">
HOST.<br>
I tell you what Lance, his man, told me: he loved her out of all nick.
</p>

<p class="drama">
JULIA.<br>
Where is Lance?
</p>

<p class="drama">
HOST.<br>
Gone to seek his dog, which tomorrow, by his master’s command, he must carry
for a present to his lady.
</p>

<p class="drama">
JULIA.<br>
Peace, stand aside. The company parts.
</p>

<p class="drama">
PROTEUS.<br>
Sir Thurio, fear not you; I will so plead<br>
That you shall say my cunning drift excels.
</p>

<p class="drama">
THURIO.<br>
Where meet we?
</p>

<p class="drama">
PROTEUS.<br>
At Saint Gregory’s well.
</p>

<p class="drama">
THURIO.<br>
Farewell.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Thurio</span> and
<span class="charname">Musicians</span>.</i>]
</p>

<p class="scenedesc">
Enter <span class="charname">Silvia</span> above.
</p>

<p class="drama">
PROTEUS.<br>
Madam, good even to your ladyship.
</p>

<p class="drama">
SILVIA.<br>
I thank you for your music, gentlemen.<br>
Who is that that spake?
</p>

<p class="drama">
PROTEUS.<br>
One, lady, if you knew his pure heart’s truth,<br>
You would quickly learn to know him by his voice.
</p>

<p class="drama">
SILVIA.<br>
Sir Proteus, as I take it.
</p>

<p class="drama">
PROTEUS.<br>
Sir Proteus, gentle lady, and your servant.
</p>

<p class="drama">
SILVIA.<br>
What’s your will?
</p>

<p class="drama">
PROTEUS.<br>
That I may compass yours.
</p>

<p class="drama">
SILVIA.<br>
You have your wish. My will is even this,<br>
That presently you hie you home to bed.<br>
Thou subtle, perjured, false, disloyal man,<br>
Think’st thou I am so shallow, so conceitless,<br>
To be seduced by thy flattery,<br>
That hast deceived so many with thy vows?<br>
Return, return, and make thy love amends.<br>
For me, by this pale queen of night I swear,<br>
I am so far from granting thy request<br>
That I despise thee for thy wrongful suit,<br>
And by and by intend to chide myself<br>
Even for this time I spend in talking to thee.
</p>

<p class="drama">
PROTEUS.<br>
I grant, sweet love, that I did love a lady,<br>
But she is dead.
</p>

<p class="drama">
JULIA.<br>
[<i>Aside</i>.] ’Twere false, if I should speak it,<br>
For I am sure she is not buried.
</p>

<p class="drama">
SILVIA.<br>
Say that she be; yet Valentine thy friend<br>
Survives, to whom, thyself art witness,<br>
I am betrothed. And art thou not ashamed<br>
To wrong him with thy importunacy?
</p>

<p class="drama">
PROTEUS.<br>
I likewise hear that Valentine is dead.
</p>

<p class="drama">
SILVIA.<br>
And so suppose am I, for in his grave,<br>
Assure thyself, my love is buried.
</p>

<p class="drama">
PROTEUS.<br>
Sweet lady, let me rake it from the earth.
</p>

<p class="drama">
SILVIA.<br>
Go to thy lady’s grave and call hers thence,<br>
Or, at the least, in hers sepulchre thine.
</p>

<p class="drama">
JULIA.<br>
[<i>Aside</i>.] He heard not that.
</p>

<p class="drama">
PROTEUS.<br>
Madam, if your heart be so obdurate,<br>
Vouchsafe me yet your picture for my love,<br>
The picture that is hanging in your chamber;<br>
To that I’ll speak, to that I’ll sigh and weep;<br>
For since the substance of your perfect self<br>
Is else devoted, I am but a shadow;<br>
And to your shadow will I make true love.
</p>

<p class="drama">
JULIA.<br>
[<i>Aside</i>.] If ’twere a substance you would sure deceive it<br>
And make it but a shadow, as I am.
</p>

<p class="drama">
SILVIA.<br>
I am very loath to be your idol, sir;<br>
But since your falsehood shall become you well<br>
To worship shadows and adore false shapes,<br>
Send to me in the morning, and I’ll send it.<br>
And so, good rest.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
PROTEUS.<br>
As wretches have o’ernight<br>
That wait for execution in the morn.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
JULIA.<br>
Host, will you go?
</p>

<p class="drama">
HOST.<br>
By my halidom, I was fast asleep.
</p>

<p class="drama">
JULIA.<br>
Pray you, where lies Sir Proteus?
</p>

<p class="drama">
HOST.<br>
Marry, at my house. Trust me, I think ’tis almost day.
</p>

<p class="drama">
JULIA.<br>
Not so; but it hath been the longest night<br>
That e’er I watched, and the most heaviest.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneIV_37.3"></a><b>SCENE III. The same</b></h3>

<p class="scenedesc">
Enter <span class="charname">Eglamour</span>.
</p>

<p class="drama">
EGLAMOUR.<br>
This is the hour that Madam Silvia<br>
Entreated me to call and know her mind;<br>
There’s some great matter she’d employ me in.<br>
Madam, madam!
</p>

<p class="scenedesc">
Enter <span class="charname">Silvia</span> above.
</p>

<p class="drama">
SILVIA.<br>
Who calls?
</p>

<p class="drama">
EGLAMOUR.<br>
Your servant and your friend;<br>
One that attends your ladyship’s command.
</p>

<p class="drama">
SILVIA.<br>
Sir Eglamour, a thousand times good morrow.
</p>

<p class="drama">
EGLAMOUR.<br>
As many, worthy lady, to yourself.<br>
According to your ladyship’s impose,<br>
I am thus early come to know what service<br>
It is your pleasure to command me in.
</p>

<p class="drama">
SILVIA.<br>
O Eglamour, thou art a gentleman—<br>
Think not I flatter, for I swear I do not—<br>
Valiant, wise, remorseful, well accomplished.<br>
Thou art not ignorant what dear good will<br>
I bear unto the banished Valentine,<br>
Nor how my father would enforce me marry<br>
Vain Thurio, whom my very soul abhorred.<br>
Thyself hast loved, and I have heard thee say<br>
No grief did ever come so near thy heart<br>
As when thy lady and thy true love died,<br>
Upon whose grave thou vowed’st pure chastity.<br>
Sir Eglamour, I would to Valentine,<br>
To Mantua, where I hear he makes abode;<br>
And for the ways are dangerous to pass,<br>
I do desire thy worthy company,<br>
Upon whose faith and honour I repose.<br>
Urge not my father’s anger, Eglamour,<br>
But think upon my grief, a lady’s grief,<br>
And on the justice of my flying hence<br>
To keep me from a most unholy match,<br>
Which heaven and fortune still rewards with plagues.<br>
I do desire thee, even from a heart<br>
As full of sorrows as the sea of sands,<br>
To bear me company and go with me;<br>
If not, to hide what I have said to thee,<br>
That I may venture to depart alone.
</p>

<p class="drama">
EGLAMOUR.<br>
Madam, I pity much your grievances,<br>
Which, since I know they virtuously are placed,<br>
I give consent to go along with you,<br>
Recking as little what betideth me<br>
As much I wish all good befortune you.<br>
When will you go?
</p>

<p class="drama">
SILVIA.<br>
This evening coming.
</p>

<p class="drama">
EGLAMOUR.<br>
Where shall I meet you?
</p>

<p class="drama">
SILVIA.<br>
At Friar Patrick’s cell,<br>
Where I intend holy confession.
</p>

<p class="drama">
EGLAMOUR.<br>
I will not fail your ladyship. Good morrow, gentle lady.
</p>

<p class="drama">
SILVIA.<br>
Good morrow, kind Sir Eglamour.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneIV_37.4"></a><b>SCENE IV. The same</b></h3>

<p class="scenedesc">
Enter <span class="charname">Lance</span> with his dog Crab.
</p>

<p class="drama">
LANCE.<br>
When a man’s servant shall play the cur with him, look you, it goes hard: one
that I brought up of a puppy; one that I saved from drowning when three or four
of his blind brothers and sisters went to it. I have taught him even as one
would say precisely, “Thus I would teach a dog.” I was sent to deliver him as a
present to Mistress Silvia from my master; and I came no sooner into the
dining-chamber but he steps me to her trencher and steals her capon’s leg. O,
’tis a foul thing when a cur cannot keep himself in all companies! I would
have, as one should say, one that takes upon him to be a dog indeed, to be, as
it were, a dog at all things. If I had not had more wit than he, to take a
fault upon me that he did, I think verily he had been hanged for’t; sure as I
live, he had suffered for’t. You shall judge. He thrusts me himself into the
company of three or four gentleman-like dogs under the Duke’s table; he had not
been there—bless the mark!—a pissing-while but all the chamber smelt him. “Out
with the dog!” says one; “What cur is that?” says another; “Whip him out”, says
the third; “Hang him up”, says the Duke. I, having been acquainted with the
smell before, knew it was Crab, and goes me to the fellow that whips the dogs.
“Friend,” quoth I, “you mean to whip the dog?” “Ay, marry do I,” quoth he. “You
do him the more wrong,” quoth I. “’Twas I did the thing you wot of.” He makes
me no more ado but whips me out of the chamber. How many masters would do this
for his servant? Nay, I’ll be sworn I have sat in the stock for puddings he
hath stolen, otherwise he had been executed. I have stood on the pillory for
geese he hath killed, otherwise he had suffered for’t. [<i>To Crab</i>.] Thou
think’st not of this now. Nay, I remember the trick you served me when I took
my leave of Madam Silvia. Did not I bid thee still mark me, and do as I do?
When didst thou see me heave up my leg and make water against a gentlewoman’s
farthingale? Didst thou ever see me do such a trick?
</p>

<p class="scenedesc">
Enter <span class="charname">Proteus</span> and
<span class="charname">Julia</span> disguised as Sebastian.
</p>

<p class="drama">
PROTEUS.<br>
Sebastian is thy name? I like thee well,<br>
And will employ thee in some service presently.
</p>

<p class="drama">
JULIA.<br>
In what you please; I’ll do what I can.
</p>

<p class="drama">
PROTEUS.<br>
I hope thou wilt. [<i>To Lance</i>.] How now, you whoreson peasant,<br>
Where have you been these two days loitering?
</p>

<p class="drama">
LANCE.<br>
Marry, sir, I carried Mistress Silvia the dog you bade me.
</p>

<p class="drama">
PROTEUS.<br>
And what says she to my little jewel?
</p>

<p class="drama">
LANCE.<br>
Marry, she says your dog was a cur, and tells you currish thanks is good enough
for such a present.
</p>

<p class="drama">
PROTEUS.<br>
But she received my dog?
</p>

<p class="drama">
LANCE.<br>
No, indeed, did she not. Here have I brought him back again.
</p>

<p class="drama">
PROTEUS.<br>
What, didst thou offer her this from me?
</p>

<p class="drama">
LANCE.<br>
Ay, sir, the other squirrel was stolen from me by the hangman’s boys in the
market-place, and then I offered her mine own, who is a dog as big as ten of
yours, and therefore the gift the greater.
</p>

<p class="drama">
PROTEUS.<br>
Go, get thee hence, and find my dog again,<br>
Or ne’er return again into my sight.<br>
Away, I say. Stayest thou to vex me here?<br>
A slave that still an end turns me to shame.
</p>

<p class="right">[<i>Exit <span class="charname">Lance</span> with Crab.</i>]</p>

<p class="drama">
Sebastian, I have entertained thee<br>
Partly that I have need of such a youth<br>
That can with some discretion do my business—<br>
For ’tis no trusting to yond foolish lout—<br>
But chiefly for thy face and thy behaviour,<br>
Which, if my augury deceive me not,<br>
Witness good bringing up, fortune, and truth.<br>
Therefore, know thou, for this I entertain thee.<br>
Go presently, and take this ring with thee,<br>
Deliver it to Madam Silvia.<br>
She loved me well delivered it to me.
</p>

<p class="drama">
JULIA.<br>
It seems you loved not her, to leave her token.<br>
She’s dead belike?
</p>

<p class="drama">
PROTEUS.<br>
Not so; I think she lives.
</p>

<p class="drama">
JULIA.<br>
Alas!
</p>

<p class="drama">
PROTEUS.<br>
Why dost thou cry “Alas”?
</p>

<p class="drama">
JULIA.<br>
I cannot choose<br>
But pity her.
</p>

<p class="drama">
PROTEUS.<br>
Wherefore shouldst thou pity her?
</p>

<p class="drama">
JULIA.<br>
Because methinks that she loved you as well<br>
As you do love your lady Silvia.<br>
She dreams on him that has forgot her love;<br>
You dote on her that cares not for your love.<br>
’Tis pity love should be so contrary;<br>
And thinking on it makes me cry “Alas.”
</p>

<p class="drama">
PROTEUS.<br>
Well, give her that ring, and therewithal<br>
This letter. That’s her chamber. Tell my lady<br>
I claim the promise for her heavenly picture.<br>
Your message done, hie home unto my chamber,<br>
Where thou shalt find me sad and solitary.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
JULIA.<br>
How many women would do such a message?<br>
Alas, poor Proteus, thou hast entertained<br>
A fox to be the shepherd of thy lambs.<br>
Alas, poor fool, why do I pity him<br>
That with his very heart despiseth me?<br>
Because he loves her, he despiseth me;<br>
Because I love him, I must pity him.<br>
This ring I gave him when he parted from me,<br>
To bind him to remember my good will;<br>
And now am I, unhappy messenger,<br>
To plead for that which I would not obtain,<br>
To carry that which I would have refused,<br>
To praise his faith, which I would have dispraised.<br>
I am my master’s true confirmed love,<br>
But cannot be true servant to my master<br>
Unless I prove false traitor to myself.<br>
Yet will I woo for him, but yet so coldly<br>
As, heaven it knows, I would not have him speed.
</p>

<p class="scenedesc">
Enter <span class="charname">Silvia</span> attended.
</p>

<p class="drama">
Gentlewoman, good day. I pray you be my mean<br>
To bring me where to speak with Madam Silvia.
</p>

<p class="drama">
SILVIA.<br>
What would you with her, if that I be she?
</p>

<p class="drama">
JULIA.<br>
If you be she, I do entreat your patience<br>
To hear me speak the message I am sent on.
</p>

<p class="drama">
SILVIA.<br>
From whom?
</p>

<p class="drama">
JULIA.<br>
From my master, Sir Proteus, madam.
</p>

<p class="drama">
SILVIA.<br>
O, he sends you for a picture?
</p>

<p class="drama">
JULIA.<br>
Ay, madam.
</p>

<p class="drama">
SILVIA.<br>
Ursula, bring my picture there.
</p>

<p class="right">[<i>She is brought the picture.</i>]</p>

<p class="drama">
Go, give your master this. Tell him from me,<br>
One Julia, that his changing thoughts forget,<br>
Would better fit his chamber than this shadow.
</p>

<p class="drama">
JULIA.<br>
Madam, please you peruse this letter.
</p>

<p class="right">[<i>Gives her a letter.</i>]</p>

<p class="drama">
Pardon me, madam, I have unadvised<br>
Delivered you a paper that I should not.<br>
This is the letter to your ladyship.
</p>

<p class="right">[<i>Takes back the letter and gives her another.</i>]</p>

<p class="drama">
SILVIA.<br>
I pray thee, let me look on that again.
</p>

<p class="drama">
JULIA.<br>
It may not be. Good madam, pardon me.
</p>

<p class="drama">
SILVIA.<br>
There, hold.<br>
I will not look upon your master’s lines.<br>
I know they are stuffed with protestations<br>
And full of new-found oaths, which he will break<br>
As easily as I do tear his paper.
</p>

<p class="right">[<i>She tears the second letter.</i>]</p>

<p class="drama">
JULIA.<br>
Madam, he sends your ladyship this ring.
</p>

<p class="drama">
SILVIA.<br>
The more shame for him that he sends it me;<br>
For I have heard him say a thousand times<br>
His Julia gave it him at his departure.<br>
Though his false finger have profaned the ring,<br>
Mine shall not do his Julia so much wrong.
</p>

<p class="drama">
JULIA.<br>
She thanks you.
</p>

<p class="drama">
SILVIA.<br>
What sayst thou?
</p>

<p class="drama">
JULIA.<br>
I thank you, madam, that you tender her.<br>
Poor gentlewoman, my master wrongs her much.
</p>

<p class="drama">
SILVIA.<br>
Dost thou know her?
</p>

<p class="drama">
JULIA.<br>
Almost as well as I do know myself.<br>
To think upon her woes, I do protest<br>
That I have wept a hundred several times.
</p>

<p class="drama">
SILVIA.<br>
Belike she thinks that Proteus hath forsook her?
</p>

<p class="drama">
JULIA.<br>
I think she doth, and that’s her cause of sorrow.
</p>

<p class="drama">
SILVIA.<br>
Is she not passing fair?
</p>

<p class="drama">
JULIA.<br>
She hath been fairer, madam, than she is.<br>
When she did think my master loved her well,<br>
She, in my judgement, was as fair as you.<br>
But since she did neglect her looking-glass<br>
And threw her sun-expelling mask away,<br>
The air hath starved the roses in her cheeks<br>
And pinched the lily-tincture of her face,<br>
That now she is become as black as I.
</p>

<p class="drama">
SILVIA.<br>
How tall was she?
</p>

<p class="drama">
JULIA.<br>
About my stature; for at Pentecost,<br>
When all our pageants of delight were played,<br>
Our youth got me to play the woman’s part,<br>
And I was trimmed in Madam Julia’s gown,<br>
Which served me as fit, by all men’s judgements,<br>
As if the garment had been made for me;<br>
Therefore I know she is about my height.<br>
And at that time I made her weep agood,<br>
For I did play a lamentable part.<br>
Madam, ’twas Ariadne, passioning<br>
For Theseus’ perjury and unjust flight,<br>
Which I so lively acted with my tears<br>
That my poor mistress, moved therewithal,<br>
Wept bitterly; and would I might be dead<br>
If I in thought felt not her very sorrow.
</p>

<p class="drama">
SILVIA.<br>
She is beholding to thee, gentle youth.<br>
Alas, poor lady, desolate and left!<br>
I weep myself to think upon thy words.<br>
Here, youth, there is my purse. I give thee this<br>
For thy sweet mistress’ sake, because thou lov’st her.<br>
Farewell.
</p>

<p class="drama">
JULIA.<br>
And she shall thank you for’t, if e’er you know her.
</p>

<p class="right">
[<i>Exeunt <span class="charname">Silvia</span> and
<span class="charname">Attendants</span>.</i>]
</p>

<p class="drama">
A virtuous gentlewoman, mild and beautiful.<br>
I hope my master’s suit will be but cold,<br>
Since she respects my mistress’ love so much.<br>
Alas, how love can trifle with itself!<br>
Here is her picture; let me see. I think<br>
If I had such a tire, this face of mine<br>
Were full as lovely as is this of hers;<br>
And yet the painter flattered her a little,<br>
Unless I flatter with myself too much.<br>
Her hair is auburn, mine is perfect yellow;<br>
If that be all the difference in his love,<br>
I’ll get me such a coloured periwig.<br>
Her eyes are grey as glass, and so are mine.<br>
Ay, but her forehead’s low, and mine’s as high.<br>
What should it be that he respects in her<br>
But I can make respective in myself,<br>
If this fond Love were not a blinded god?<br>
Come, shadow, come, and take this shadow up,<br>
For ’tis thy rival. O thou senseless form,<br>
Thou shalt be worshipped, kissed, loved, and adored;<br>
And were there sense in his idolatry,<br>
My substance should be statue in thy stead.<br>
I’ll use thee kindly for thy mistress’ sake,<br>
That used me so; or else, by Jove I vow,<br>
I should have scratched out your unseeing eyes<br>
To make my master out of love with thee.
</p>

<p class="right">[<i>Exit.</i>]</p>

