<h2> <a id="sceneII_8.1"></a><b>ACT II</b></h2>

<h3> <b>SCENE I. A room in Polonius’s house.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Polonius</span> and <span class="charname">Reynaldo</span>.
</p>

<p class="drama">
POLONIUS.<br>
Give him this money and these notes, Reynaldo.<br>
</p>

<p class="drama">
REYNALDO.<br>
I will, my lord.<br>
</p>

<p class="drama">
POLONIUS.<br>
You shall do marvellous wisely, good Reynaldo,<br>
Before you visit him, to make inquiry<br>
Of his behaviour.<br>
</p>

<p class="drama">
REYNALDO.<br>
My lord, I did intend it.<br>
</p>

<p class="drama">
POLONIUS.<br>
Marry, well said; very well said. Look you, sir,<br>
Enquire me first what Danskers are in Paris;<br>
And how, and who, what means, and where they keep,<br>
What company, at what expense; and finding<br>
By this encompassment and drift of question,<br>
That they do know my son, come you more nearer<br>
Than your particular demands will touch it.<br>
Take you as ’twere some distant knowledge of him,<br>
As thus, ‘I know his father and his friends,<br>
And in part him’—do you mark this, Reynaldo?<br>
</p>

<p class="drama">
REYNALDO.<br>
Ay, very well, my lord.<br>
</p>

<p class="drama">
POLONIUS.<br>
‘And in part him, but,’ you may say, ‘not well;<br>
But if’t be he I mean, he’s very wild;<br>
Addicted so and so;’ and there put on him<br>
What forgeries you please; marry, none so rank<br>
As may dishonour him; take heed of that;<br>
But, sir, such wanton, wild, and usual slips<br>
As are companions noted and most known<br>
To youth and liberty.<br>
</p>

<p class="drama">
REYNALDO.<br>
As gaming, my lord?<br>
</p>

<p class="drama">
POLONIUS.<br>
Ay, or drinking, fencing, swearing,<br>
Quarrelling, drabbing. You may go so far.<br>
</p>

<p class="drama">
REYNALDO.<br>
My lord, that would dishonour him.<br>
</p>

<p class="drama">
POLONIUS.<br>
Faith no, as you may season it in the charge.<br>
You must not put another scandal on him,<br>
That he is open to incontinency;<br>
That’s not my meaning: but breathe his faults so quaintly<br>
That they may seem the taints of liberty;<br>
The flash and outbreak of a fiery mind,<br>
A savageness in unreclaimed blood,<br>
Of general assault.<br>
</p>

<p class="drama">
REYNALDO.<br>
But my good lord—<br>
</p>

<p class="drama">
POLONIUS.<br>
Wherefore should you do this?<br>
</p>

<p class="drama">
REYNALDO.<br>
Ay, my lord, I would know that.<br>
</p>

<p class="drama">
POLONIUS.<br>
Marry, sir, here’s my drift,<br>
And I believe it is a fetch of warrant.<br>
You laying these slight sullies on my son,<br>
As ’twere a thing a little soil’d i’ th’ working,<br>
Mark you,<br>
Your party in converse, him you would sound,<br>
Having ever seen in the prenominate crimes<br>
The youth you breathe of guilty, be assur’d<br>
He closes with you in this consequence;<br>
‘Good sir,’ or so; or ‘friend,’ or ‘gentleman’—<br>
According to the phrase or the addition<br>
Of man and country.<br>
</p>

<p class="drama">
REYNALDO.<br>
Very good, my lord.<br>
</p>

<p class="drama">
POLONIUS.<br>
And then, sir, does he this,—<br>
He does—What was I about to say?<br>
By the mass, I was about to say something. Where did I leave?<br>
</p>

<p class="drama">
REYNALDO.<br>
At ‘closes in the consequence.’<br>
At ‘friend or so,’ and ‘gentleman.’
</p>

<p class="drama">
POLONIUS.<br>
At ‘closes in the consequence’ ay, marry!<br>
He closes with you thus: ‘I know the gentleman,<br>
I saw him yesterday, or t’other day,<br>
Or then, or then, with such and such; and, as you say,<br>
There was he gaming, there o’ertook in’s rouse,<br>
There falling out at tennis’: or perchance,<br>
‘I saw him enter such a house of sale’—<br>
<i>Videlicet</i>, a brothel, or so forth. See you now;<br>
Your bait of falsehood takes this carp of truth;<br>
And thus do we of wisdom and of reach,<br>
With windlasses, and with assays of bias,<br>
By indirections find directions out.<br>
So by my former lecture and advice<br>
Shall you my son. You have me, have you not?<br>
</p>

<p class="drama">
REYNALDO.<br>
My lord, I have.<br>
</p>

<p class="drama">
POLONIUS.<br>
God b’ wi’ you, fare you well.<br>
</p>

<p class="drama">
REYNALDO.<br>
Good my lord.<br>
</p>

<p class="drama">
POLONIUS.<br>
Observe his inclination in yourself.<br>
</p>

<p class="drama">
REYNALDO.<br>
I shall, my lord.<br>
</p>

<p class="drama">
POLONIUS.<br>
And let him ply his music.<br>
</p>

<p class="drama">
REYNALDO.<br>
Well, my lord.<br>
</p>

<p class="drama">
POLONIUS.<br>
Farewell.<br>
</p>

<p class="right">
[<i>Exit <span class="charname">Reynaldo</span>.</i>]
</p>

<p class="scenedesc">
Enter <span class="charname">Ophelia</span>.
</p>

<p class="drama">
How now, Ophelia, what’s the matter?
</p>

<p class="drama">
OPHELIA.<br>
Alas, my lord, I have been so affrighted.<br>
</p>

<p class="drama">
POLONIUS.<br>
With what, in the name of God?<br>
</p>

<p class="drama">
OPHELIA.<br>
My lord, as I was sewing in my chamber,<br>
Lord Hamlet, with his doublet all unbrac’d,<br>
No hat upon his head, his stockings foul’d,<br>
Ungart’red, and down-gyved to his ankle,<br>
Pale as his shirt, his knees knocking each other,<br>
And with a look so piteous in purport<br>
As if he had been loosed out of hell<br>
To speak of horrors, he comes before me.<br>
</p>

<p class="drama">
POLONIUS.<br>
Mad for thy love?<br>
</p>

<p class="drama">
OPHELIA.<br>
My lord, I do not know, but truly I do fear it.<br>
</p>

<p class="drama">
POLONIUS.<br>
What said he?<br>
</p>

<p class="drama">
OPHELIA.<br>
He took me by the wrist and held me hard;<br>
Then goes he to the length of all his arm;<br>
And with his other hand thus o’er his brow,<br>
He falls to such perusal of my face<br>
As he would draw it. Long stay’d he so,<br>
At last,—a little shaking of mine arm,<br>
And thrice his head thus waving up and down,<br>
He rais’d a sigh so piteous and profound<br>
As it did seem to shatter all his bulk<br>
And end his being. That done, he lets me go,<br>
And with his head over his shoulder turn’d<br>
He seem’d to find his way without his eyes,<br>
For out o’ doors he went without their help,<br>
And to the last bended their light on me.<br>
</p>

<p class="drama">
POLONIUS.<br>
Come, go with me. I will go seek the King.<br>
This is the very ecstasy of love,<br>
Whose violent property fordoes itself,<br>
And leads the will to desperate undertakings,<br>
As oft as any passion under heaven<br>
That does afflict our natures. I am sorry,—<br>
What, have you given him any hard words of late?<br>
</p>

<p class="drama">
OPHELIA.<br>
No, my good lord; but as you did command,<br>
I did repel his letters and denied<br>
His access to me.<br>
</p>

<p class="drama">
POLONIUS.<br>
That hath made him mad.<br>
I am sorry that with better heed and judgement<br>
I had not quoted him. I fear’d he did but trifle,<br>
And meant to wreck thee. But beshrew my jealousy!<br>
It seems it is as proper to our age<br>
To cast beyond ourselves in our opinions<br>
As it is common for the younger sort<br>
To lack discretion. Come, go we to the King.<br>
This must be known, which, being kept close, might move<br>
More grief to hide than hate to utter love.<br>
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3><a id="sceneII_8.2"></a> <b>SCENE II. A room in the
Castle.</b></h3>

<p class="scenedesc">
Enter <span class="charname">King, Queen, Rosencrantz, Guildenstern</span> and
<span class="charname">Attendants</span>.
</p>

<p class="drama">
KING.<br>
Welcome, dear Rosencrantz and Guildenstern.<br>
Moreover that we much did long to see you,<br>
The need we have to use you did provoke<br>
Our hasty sending. Something have you heard<br>
Of Hamlet’s transformation; so I call it,<br>
Since nor th’exterior nor the inward man<br>
Resembles that it was. What it should be,<br>
More than his father’s death, that thus hath put him<br>
So much from th’understanding of himself,<br>
I cannot dream of. I entreat you both<br>
That, being of so young days brought up with him,<br>
And since so neighbour’d to his youth and humour,<br>
That you vouchsafe your rest here in our court<br>
Some little time, so by your companies<br>
To draw him on to pleasures and to gather,<br>
So much as from occasion you may glean,<br>
Whether aught to us unknown afflicts him thus<br>
That, open’d, lies within our remedy.<br>
</p>

<p class="drama">
QUEEN.<br>
Good gentlemen, he hath much talk’d of you,<br>
And sure I am, two men there are not living<br>
To whom he more adheres. If it will please you<br>
To show us so much gentry and good will<br>
As to expend your time with us awhile,<br>
For the supply and profit of our hope,<br>
Your visitation shall receive such thanks<br>
As fits a king’s remembrance.<br>
</p>

<p class="drama">
ROSENCRANTZ.<br>
Both your majesties<br>
Might, by the sovereign power you have of us,<br>
Put your dread pleasures more into command<br>
Than to entreaty.<br>
</p>

<p class="drama">
GUILDENSTERN.<br>
We both obey,<br>
And here give up ourselves, in the full bent,<br>
To lay our service freely at your feet<br>
To be commanded.<br>
</p>

<p class="drama">
KING.<br>
Thanks, Rosencrantz and gentle Guildenstern.<br>
</p>

<p class="drama">
QUEEN.<br>
Thanks, Guildenstern and gentle Rosencrantz.<br>
And I beseech you instantly to visit<br>
My too much changed son. Go, some of you,<br>
And bring these gentlemen where Hamlet is.<br>
</p>

<p class="drama">
GUILDENSTERN.<br>
Heavens make our presence and our practices<br>
Pleasant and helpful to him.<br>
</p>

<p class="drama">
QUEEN.<br>
Ay, amen.<br>
</p>

<p class="right">
[<i>Exeunt <span class="charname">Rosencrantz, Guildenstern</span> and some
<span class="charname">Attendants</span>.</i>]
</p>

<p class="scenedesc">
Enter <span class="charname">Polonius</span>.
</p>

<p class="drama">
POLONIUS.<br>
Th’ambassadors from Norway, my good lord,<br>
Are joyfully return’d.<br>
</p>

<p class="drama">
KING.<br>
Thou still hast been the father of good news.<br>
</p>

<p class="drama">
POLONIUS.<br>
Have I, my lord? Assure you, my good liege,<br>
I hold my duty, as I hold my soul,<br>
Both to my God and to my gracious King:<br>
And I do think,—or else this brain of mine<br>
Hunts not the trail of policy so sure<br>
As it hath us’d to do—that I have found<br>
The very cause of Hamlet’s lunacy.<br>
</p>

<p class="drama">
KING.<br>
O speak of that, that do I long to hear.<br>
</p>

<p class="drama">
POLONIUS.<br>
Give first admittance to th’ambassadors;<br>
My news shall be the fruit to that great feast.<br>
</p>

<p class="drama">
KING.<br>
Thyself do grace to them, and bring them in.<br>
</p>

<p class="right">
[<i>Exit <span class="charname">Polonius</span>.</i>]
</p>

<p class="drama">
He tells me, my sweet queen, that he hath found<br>
The head and source of all your son’s distemper.<br>
</p>

<p class="drama">
QUEEN.<br>
I doubt it is no other but the main,<br>
His father’s death and our o’erhasty marriage.<br>
</p>

<p class="drama">
KING.<br>
Well, we shall sift him.<br>
</p>

<p class="scenedesc">
Enter <span class="charname">Polonius</span> with <span class="charname">Voltemand</span> and <span class="charname">Cornelius</span>.
</p>

<p class="drama">
Welcome, my good friends!<br>
Say, Voltemand, what from our brother Norway?<br>
</p>

<p class="drama">
VOLTEMAND.<br>
Most fair return of greetings and desires.<br>
Upon our first, he sent out to suppress<br>
His nephew’s levies, which to him appear’d<br>
To be a preparation ’gainst the Polack;<br>
But better look’d into, he truly found<br>
It was against your Highness; whereat griev’d,<br>
That so his sickness, age, and impotence<br>
Was falsely borne in hand, sends out arrests<br>
On Fortinbras; which he, in brief, obeys,<br>
Receives rebuke from Norway; and in fine,<br>
Makes vow before his uncle never more<br>
To give th’assay of arms against your Majesty.<br>
Whereon old Norway, overcome with joy,<br>
Gives him three thousand crowns in annual fee,<br>
And his commission to employ those soldiers<br>
So levied as before, against the Polack:<br>
With an entreaty, herein further shown,<br>
[<i>Gives a paper.</i>]<br>
That it might please you to give quiet pass<br>
Through your dominions for this enterprise,<br>
On such regards of safety and allowance<br>
As therein are set down.<br>
</p>

<p class="drama">
KING.<br>
It likes us well;<br>
And at our more consider’d time we’ll read,<br>
Answer, and think upon this business.<br>
Meantime we thank you for your well-took labour.<br>
Go to your rest, at night we’ll feast together:.<br>
Most welcome home.<br>
</p>

<p class="right">
[<i>Exeunt <span class="charname">Voltemand</span> and <span class="charname">Cornelius</span>.</i>]
</p>

<p class="drama">
POLONIUS.<br>
This business is well ended.<br>
My liege and madam, to expostulate<br>
What majesty should be, what duty is,<br>
Why day is day, night night, and time is time<br>
Were nothing but to waste night, day and time.<br>
Therefore, since brevity is the soul of wit,<br>
And tediousness the limbs and outward flourishes,<br>
I will be brief. Your noble son is mad.<br>
Mad call I it; for to define true madness,<br>
What is’t but to be nothing else but mad?<br>
But let that go.<br>
</p>

<p class="drama">
QUEEN.<br>
More matter, with less art.<br>
</p>

<p class="drama">
POLONIUS.<br>
Madam, I swear I use no art at all.<br>
That he is mad, ’tis true: ’tis true ’tis pity;<br>
And pity ’tis ’tis true. A foolish figure,<br>
But farewell it, for I will use no art.<br>
Mad let us grant him then. And now remains<br>
That we find out the cause of this effect,<br>
Or rather say, the cause of this defect,<br>
For this effect defective comes by cause.<br>
Thus it remains, and the remainder thus. Perpend,<br>
I have a daughter—have whilst she is mine—<br>
Who in her duty and obedience, mark,<br>
Hath given me this. Now gather, and surmise.<br>
[<i>Reads.</i>]<br>
<i>To the celestial, and my soul’s idol, the most beautified Ophelia</i>—<br>
That’s an ill phrase, a vile phrase; ‘beautified’ is a vile<br>
phrase: but you shall hear.<br>
[<i>Reads.</i>]<br>
<i>these; in her excellent white bosom, these, &amp;c.</i><br>
</p>

<p class="drama">
QUEEN.<br>
Came this from Hamlet to her?<br>
</p>

<p class="drama">
POLONIUS.<br>
Good madam, stay awhile; I will be faithful.<br>
[<i>Reads.</i>]<br>
  <i>Doubt thou the stars are fire,<br>
     Doubt that the sun doth move,<br>
   Doubt truth to be a liar,<br>
     But never doubt I love.<br>
O dear Ophelia, I am ill at these numbers. I have not art to reckon my groans.
But that I love thee best, O most best, believe it. Adieu.<br>
  Thine evermore, most dear lady, whilst this machine is to him,<br>
     HAMLET.</i><br>
This in obedience hath my daughter show’d me;<br>
And more above, hath his solicitings,<br>
As they fell out by time, by means, and place,<br>
All given to mine ear.<br>
</p>

<p class="drama">
KING.<br>
But how hath she receiv’d his love?<br>
</p>

<p class="drama">
POLONIUS.<br>
What do you think of me?<br>
</p>

<p class="drama">
KING.<br>
As of a man faithful and honourable.<br>
</p>

<p class="drama">
POLONIUS.<br>
I would fain prove so. But what might you think,<br>
When I had seen this hot love on the wing,<br>
As I perceiv’d it, I must tell you that,<br>
Before my daughter told me, what might you,<br>
Or my dear Majesty your queen here, think,<br>
If I had play’d the desk or table-book,<br>
Or given my heart a winking, mute and dumb,<br>
Or look’d upon this love with idle sight,<br>
What might you think? No, I went round to work,<br>
And my young mistress thus I did bespeak:<br>
‘Lord Hamlet is a prince, out of thy star.<br>
This must not be.’ And then I precepts gave her,<br>
That she should lock herself from his resort,<br>
Admit no messengers, receive no tokens.<br>
Which done, she took the fruits of my advice,<br>
And he, repulsed,—a short tale to make—<br>
Fell into a sadness, then into a fast,<br>
Thence to a watch, thence into a weakness,<br>
Thence to a lightness, and, by this declension,<br>
Into the madness wherein now he raves,<br>
And all we wail for.<br>
</p>

<p class="drama">
KING.<br>
Do you think ’tis this?<br>
</p>

<p class="drama">
QUEEN.<br>
It may be, very likely.<br>
</p>

<p class="drama">
POLONIUS.<br>
Hath there been such a time, I’d fain know that,<br>
That I have positively said ‘’Tis so,’<br>
When it prov’d otherwise?<br>
</p>

<p class="drama">
KING.<br>
Not that I know.<br>
</p>

<p class="drama">
POLONIUS.<br>
Take this from this, if this be otherwise.<br>
[<i>Points to his head and shoulder.</i>]<br>
If circumstances lead me, I will find<br>
Where truth is hid, though it were hid indeed<br>
Within the centre.<br>
</p>

<p class="drama">
KING.<br>
How may we try it further?<br>
</p>

<p class="drama">
POLONIUS.<br>
You know sometimes he walks four hours together<br>
Here in the lobby.<br>
</p>

<p class="drama">
QUEEN.<br>
So he does indeed.<br>
</p>

<p class="drama">
POLONIUS.<br>
At such a time I’ll loose my daughter to him.<br>
Be you and I behind an arras then,<br>
Mark the encounter. If he love her not,<br>
And be not from his reason fall’n thereon,<br>
Let me be no assistant for a state,<br>
But keep a farm and carters.<br>
</p>

<p class="drama">
KING.<br>
We will try it.<br>
</p>

<p class="scenedesc">
Enter <span class="charname">Hamlet,</span> reading.
</p>

<p class="drama">
QUEEN.<br>
But look where sadly the poor wretch comes reading.<br>
</p>

<p class="drama">
POLONIUS.<br>
Away, I do beseech you, both away<br>
I’ll board him presently. O, give me leave.<br>
</p>

<p class="right">
[<i>Exeunt <span class="charname">King, Queen</span> and <span class="charname">Attendants</span>.</i>]
</p>

<p class="drama">
How does my good Lord Hamlet?
</p>

<p class="drama">
HAMLET.<br>
Well, God-a-mercy.<br>
</p>

<p class="drama">
POLONIUS.<br>
Do you know me, my lord?<br>
</p>

<p class="drama">
HAMLET.<br>
Excellent well. You are a fishmonger.<br>
</p>

<p class="drama">
POLONIUS.<br>
Not I, my lord.<br>
</p>

<p class="drama">
HAMLET.<br>
Then I would you were so honest a man.<br>
</p>

<p class="drama">
POLONIUS.<br>
Honest, my lord?<br>
</p>

<p class="drama">
HAMLET.<br>
Ay sir, to be honest, as this world goes, is to be one man picked out of ten
thousand.
</p>

<p class="drama">
POLONIUS.<br>
That’s very true, my lord.<br>
</p>

<p class="drama">
HAMLET.<br>
For if the sun breed maggots in a dead dog, being a good kissing carrion,—<br>
Have you a daughter?
</p>

<p class="drama">
POLONIUS.<br>
I have, my lord.<br>
</p>

<p class="drama">
HAMLET.<br>
Let her not walk i’ th’ sun. Conception is a blessing, but not as your daughter
may conceive. Friend, look to’t.
</p>

<p class="drama">
POLONIUS.<br>
How say you by that? [<i>Aside.</i>] Still harping on my daughter. Yet he knew
me not at first; he said I was a fishmonger. He is far gone, far gone. And
truly in my youth I suffered much extremity for love; very near this. I’ll
speak to him again.—What do you read, my lord?
</p>

<p class="drama">
HAMLET.<br>
Words, words, words.<br>
</p>

<p class="drama">
POLONIUS.<br>
What is the matter, my lord?<br>
</p>

<p class="drama">
HAMLET.<br>
Between who?<br>
</p>

<p class="drama">
POLONIUS.<br>
I mean the matter that you read, my lord.<br>
</p>

<p class="drama">
HAMLET.<br>
Slanders, sir. For the satirical slave says here that old men have grey beards;
that their faces are wrinkled; their eyes purging thick amber and plum-tree
gum; and that they have a plentiful lack of wit, together with most weak hams.
All which, sir, though I most powerfully and potently believe, yet I hold it
not honesty to have it thus set down. For you yourself, sir, should be old as I
am, if like a crab you could go backward.
</p>

<p class="drama">
POLONIUS.<br>
[<i>Aside.</i>] Though this be madness, yet there is method in’t.—<br>
Will you walk out of the air, my lord?<br>
</p>

<p class="drama">
HAMLET.<br>
Into my grave?<br>
</p>

<p class="drama">
POLONIUS.<br>
Indeed, that is out o’ the air. [<i>Aside.</i>] How pregnant sometimes his
replies are! A happiness that often madness hits on, which reason and sanity
could not so prosperously be delivered of. I will leave him and suddenly
contrive the means of meeting between him and my daughter.<br>
My honourable lord, I will most humbly take my leave of you.
</p>

<p class="drama">
HAMLET.<br>
You cannot, sir, take from me anything that I will more willingly part withal,
except my life, except my life, except my life.
</p>

<p class="drama">
POLONIUS.<br>
Fare you well, my lord.<br>
</p>

<p class="drama">
HAMLET.<br>
These tedious old fools.<br>
</p>

<p class="scenedesc">
Enter <span class="charname">Rosencrantz</span> and <span class="charname">Guildenstern</span>.
</p>

<p class="drama">
POLONIUS.<br>
You go to seek the Lord Hamlet; there he is.<br>
</p>

<p class="drama">
ROSENCRANTZ.<br>
[<i>To Polonius.</i>] God save you, sir.<br>
</p>

<p class="right">
[<i>Exit <span class="charname">Polonius</span>.</i>]
</p>

<p class="drama">
GUILDENSTERN.<br>
My honoured lord!<br>
</p>

<p class="drama">
ROSENCRANTZ.<br>
My most dear lord!<br>
</p>

<p class="drama">
HAMLET.<br>
My excellent good friends! How dost thou, Guildenstern? Ah, Rosencrantz. Good
lads, how do ye both?
</p>

<p class="drama">
ROSENCRANTZ.<br>
As the indifferent children of the earth.<br>
</p>

<p class="drama">
GUILDENSTERN.<br>
Happy in that we are not over-happy;<br>
On Fortune’s cap we are not the very button.<br>
</p>

<p class="drama">
HAMLET.<br>
Nor the soles of her shoe?<br>
</p>

<p class="drama">
ROSENCRANTZ.<br>
Neither, my lord.<br>
</p>

<p class="drama">
HAMLET.<br>
Then you live about her waist, or in the middle of her favours?
</p>

<p class="drama">
GUILDENSTERN.<br>
Faith, her privates we.<br>
</p>

<p class="drama">
HAMLET.<br>
In the secret parts of Fortune? O, most true; she is a strumpet. What’s the
news?
</p>

<p class="drama">
ROSENCRANTZ.<br>
None, my lord, but that the world’s grown honest.<br>
</p>

<p class="drama">
HAMLET.<br>
Then is doomsday near. But your news is not true. Let me question more in
particular. What have you, my good friends, deserved at the hands of Fortune,
that she sends you to prison hither?
</p>

<p class="drama">
GUILDENSTERN.<br>
Prison, my lord?<br>
</p>

<p class="drama">
HAMLET.<br>
Denmark’s a prison.<br>
</p>

<p class="drama">
ROSENCRANTZ.<br>
Then is the world one.<br>
</p>

<p class="drama">
HAMLET.<br>
A goodly one; in which there are many confines, wards, and dungeons, Denmark
being one o’ th’ worst.
</p>

<p class="drama">
ROSENCRANTZ.<br>
We think not so, my lord.<br>
</p>

<p class="drama">
HAMLET.<br>
Why, then ’tis none to you; for there is nothing either good or bad but
thinking makes it so. To me it is a prison.
</p>

<p class="drama">
ROSENCRANTZ.<br>
Why, then your ambition makes it one; ’tis too narrow for your mind.
</p>

<p class="drama">
HAMLET.<br>
O God, I could be bounded in a nutshell, and count myself a king of infinite
space, were it not that I have bad dreams.
</p>

<p class="drama">
GUILDENSTERN.<br>
Which dreams, indeed, are ambition; for the very substance of the ambitious is
merely the shadow of a dream.
</p>

<p class="drama">
HAMLET.<br>
A dream itself is but a shadow.<br>
</p>

<p class="drama">
ROSENCRANTZ.<br>
Truly, and I hold ambition of so airy and light a quality that it is but a
shadow’s shadow.
</p>

<p class="drama">
HAMLET.<br>
Then are our beggars bodies, and our monarchs and outstretch’d heroes the
beggars’ shadows. Shall we to th’ court? For, by my fay, I cannot reason.
</p>

<p class="drama">
ROSENCRANTZ and GUILDENSTERN.<br>
We’ll wait upon you.<br>
</p>

<p class="drama">
HAMLET.<br>
No such matter. I will not sort you with the rest of my servants; for, to speak
to you like an honest man, I am most dreadfully attended. But, in the beaten
way of friendship, what make you at Elsinore?
</p>

<p class="drama">
ROSENCRANTZ.<br>
To visit you, my lord, no other occasion.<br>
</p>

<p class="drama">
HAMLET.<br>
Beggar that I am, I am even poor in thanks; but I thank you. And sure, dear
friends, my thanks are too dear a halfpenny. Were you not sent for? Is it your
own inclining? Is it a free visitation? Come, deal justly with me. Come, come;
nay, speak.
</p>

<p class="drama">
GUILDENSTERN.<br>
What should we say, my lord?<br>
</p>

<p class="drama">
HAMLET.<br>
Why, anything. But to the purpose. You were sent for; and there is a kind of
confession in your looks, which your modesties have not craft enough to colour.
I know the good King and Queen have sent for you.
</p>

<p class="drama">
ROSENCRANTZ.<br>
To what end, my lord?<br>
</p>

<p class="drama">
HAMLET.<br>
That you must teach me. But let me conjure you, by the rights of our
fellowship, by the consonancy of our youth, by the obligation of our
ever-preserved love, and by what more dear a better proposer could charge you
withal, be even and direct with me, whether you were sent for or no.
</p>

<p class="drama">
ROSENCRANTZ.<br>
[<i>To Guildenstern.</i>] What say you?<br>
</p>

<p class="drama">
HAMLET.<br>
[<i>Aside.</i>] Nay, then I have an eye of you. If you love me, hold not off.
</p>

<p class="drama">
GUILDENSTERN.<br>
My lord, we were sent for.<br>
</p>

<p class="drama">
HAMLET.<br>
I will tell you why; so shall my anticipation prevent your discovery, and your
secrecy to the King and Queen moult no feather. I have of late, but wherefore I
know not, lost all my mirth, forgone all custom of exercises; and indeed, it
goes so heavily with my disposition that this goodly frame the earth, seems to
me a sterile promontory; this most excellent canopy the air, look you, this
brave o’erhanging firmament, this majestical roof fretted with golden fire,
why, it appears no other thing to me than a foul and pestilent congregation of
vapours. What a piece of work is man, how noble in reason, how infinite in
faculties, in form and moving, how express and admirable; in action how like an
angel, in apprehension, how like a god: the beauty of the world, the paragon of
animals. And yet, to me, what is this quintessence of dust? Man delights not
me; no, nor woman neither, though by your smiling you seem to say so.
</p>

<p class="drama">
ROSENCRANTZ.<br>
My lord, there was no such stuff in my thoughts.<br>
</p>

<p class="drama">
HAMLET.<br>
Why did you laugh then, when I said ‘Man delights not me’?<br>
</p>

<p class="drama">
ROSENCRANTZ.<br>
To think, my lord, if you delight not in man, what Lenten entertainment the
players shall receive from you. We coted them on the way, and hither are they
coming to offer you service.
</p>

<p class="drama">
HAMLET.<br>
He that plays the king shall be welcome,—his Majesty shall have tribute of me;
the adventurous knight shall use his foil and target; the lover shall not sigh
gratis, the humorous man shall end his part in peace; the clown shall make
those laugh whose lungs are tickle o’ th’ sere; and the lady shall say her mind
freely, or the blank verse shall halt for’t. What players are they?
</p>

<p class="drama">
ROSENCRANTZ.<br>
Even those you were wont to take such delight in—the tragedians of the city.
</p>

<p class="drama">
HAMLET.<br>
How chances it they travel? Their residence, both in reputation and profit, was
better both ways.
</p>

<p class="drama">
ROSENCRANTZ.<br>
I think their inhibition comes by the means of the late innovation.
</p>

<p class="drama">
HAMLET.<br>
Do they hold the same estimation they did when I was in the city? Are they so
followed?
</p>

<p class="drama">
ROSENCRANTZ.<br>
No, indeed, they are not.<br>
</p>

<p class="drama">
HAMLET.<br>
How comes it? Do they grow rusty?<br>
</p>

<p class="drama">
ROSENCRANTZ.<br>
Nay, their endeavour keeps in the wonted pace; but there is, sir, an aerie of
children, little eyases, that cry out on the top of question, and are most
tyrannically clapped for’t. These are now the fashion, and so berattle the
common stages—so they call them—that many wearing rapiers are afraid of
goose-quills and dare scarce come thither.
</p>

<p class="drama">
HAMLET.<br>
What, are they children? Who maintains ’em? How are they escoted? Will they
pursue the quality no longer than they can sing? Will they not say afterwards,
if they should grow themselves to common players—as it is most like, if their
means are no better—their writers do them wrong to make them exclaim against
their own succession?
</p>

<p class="drama">
ROSENCRANTZ.<br>
Faith, there has been much to do on both sides; and the nation holds it no sin
to tarre them to controversy. There was for a while, no money bid for argument
unless the poet and the player went to cuffs in the question.
</p>

<p class="drama">
HAMLET.<br>
Is’t possible?<br>
</p>

<p class="drama">
GUILDENSTERN.<br>
O, there has been much throwing about of brains.<br>
</p>

<p class="drama">
HAMLET.<br>
Do the boys carry it away?<br>
</p>

<p class="drama">
ROSENCRANTZ.<br>
Ay, that they do, my lord. Hercules and his load too.<br>
</p>

<p class="drama">
HAMLET.<br>
It is not very strange; for my uncle is King of Denmark, and those that would
make mouths at him while my father lived, give twenty, forty, fifty, a hundred
ducats apiece for his picture in little. ’Sblood, there is something in this
more than natural, if philosophy could find it out.
</p>

<p class="right">
[<i>Flourish of trumpets within.</i>]
</p>

<p class="drama">
GUILDENSTERN.<br>
There are the players.<br>
</p>

<p class="drama">
HAMLET.<br>
Gentlemen, you are welcome to Elsinore. Your hands, come. The appurtenance of
welcome is fashion and ceremony. Let me comply with you in this garb, lest my
extent to the players, which I tell you must show fairly outward, should more
appear like entertainment than yours. You are welcome. But my uncle-father and
aunt-mother are deceived.
</p>

<p class="drama">
GUILDENSTERN.<br>
In what, my dear lord?<br>
</p>

<p class="drama">
HAMLET.<br>
I am but mad north-north-west. When the wind is southerly, I know a hawk from a
handsaw.
</p>

<p class="scenedesc">
Enter <span class="charname">Polonius</span>.
</p>

<p class="drama">
POLONIUS.<br>
Well be with you, gentlemen.<br>
</p>

<p class="drama">
HAMLET.<br>
Hark you, Guildenstern, and you too, at each ear a hearer. That great baby you
see there is not yet out of his swaddling clouts.
</p>

<p class="drama">
ROSENCRANTZ.<br>
Happily he’s the second time come to them; for they say an old man is twice a
child.
</p>

<p class="drama">
HAMLET.<br>
I will prophesy he comes to tell me of the players. Mark it.—You say right,
sir: for a Monday morning ’twas so indeed.
</p>

<p class="drama">
POLONIUS.<br>
My lord, I have news to tell you.<br>
</p>

<p class="drama">
HAMLET.<br>
My lord, I have news to tell you. When Roscius was an actor in Rome—<br>
</p>

<p class="drama">
POLONIUS.<br>
The actors are come hither, my lord.<br>
</p>

<p class="drama">
HAMLET.<br>
Buzz, buzz.<br>
</p>

<p class="drama">
POLONIUS.<br>
Upon my honour.<br>
</p>

<p class="drama">
HAMLET.<br>
Then came each actor on his ass—<br>
</p>

<p class="drama">
POLONIUS.<br>
The best actors in the world, either for tragedy, comedy, history, pastoral,
pastoral-comical, historical-pastoral, tragical-historical,
tragical-comical-historical-pastoral, scene individable, or poem unlimited.
Seneca cannot be too heavy, nor Plautus too light, for the law of writ and the
liberty. These are the only men.
</p>

<p class="drama">
HAMLET.<br>
O Jephthah, judge of Israel, what a treasure hadst thou!<br>
</p>

<p class="drama">
POLONIUS.<br>
What treasure had he, my lord?<br>
</p>

<p class="drama">
HAMLET.<br>
Why—<br>
   ’One fair daughter, and no more,<br>
   The which he loved passing well.’<br>
</p>

<p class="drama">
POLONIUS.<br>
[<i>Aside.</i>] Still on my daughter.<br>
</p>

<p class="drama">
HAMLET.<br>
Am I not i’ th’ right, old Jephthah?<br>
</p>

<p class="drama">
POLONIUS.<br>
If you call me Jephthah, my lord, I have a daughter that I love passing well.
</p>

<p class="drama">
HAMLET.<br>
Nay, that follows not.<br>
</p>

<p class="drama">
POLONIUS.<br>
What follows then, my lord?<br>
</p>

<p class="drama">
HAMLET.<br>
Why,<br>
   As by lot, God wot,<br>
and then, you know,<br>
   It came to pass, as most like it was.<br>
The first row of the pious chanson will show you more. For look where my
abridgement comes.
</p>

<p class="scenedesc">
Enter four or five <span class="charname">Players</span>.
</p>

<p class="drama">
You are welcome, masters, welcome all. I am glad to see thee well. Welcome,
good friends. O, my old friend! Thy face is valanc’d since I saw thee last.
Com’st thou to beard me in Denmark? What, my young lady and mistress! By’r
lady, your ladyship is nearer to heaven than when I saw you last, by the
altitude of a chopine. Pray God your voice, like a piece of uncurrent gold, be
not cracked within the ring. Masters, you are all welcome. We’ll e’en to’t like
French falconers, fly at anything we see. We’ll have a speech straight. Come,
give us a taste of your quality. Come, a passionate speech.
</p>

<p class="drama">
FIRST PLAYER.<br>
What speech, my lord?<br>
</p>

<p class="drama">
HAMLET.<br>
I heard thee speak me a speech once, but it was never acted, or if it was, not
above once, for the play, I remember, pleased not the million, ’twas caviare to
the general. But it was—as I received it, and others, whose judgements in such
matters cried in the top of mine—an excellent play, well digested in the
scenes, set down with as much modesty as cunning. I remember one said there
were no sallets in the lines to make the matter savoury, nor no matter in the
phrase that might indite the author of affectation, but called it an honest
method, as wholesome as sweet, and by very much more handsome than fine. One
speech in it, I chiefly loved. ’Twas Aeneas’ tale to Dido, and thereabout of it
especially where he speaks of Priam’s slaughter. If it live in your memory,
begin at this line, let me see, let me see:<br>
   <i>The rugged Pyrrhus, like th’ Hyrcanian beast,—</i><br>
It is not so: it begins with Pyrrhus—<br>
   <i>The rugged Pyrrhus, he whose sable arms,<br>
   Black as his purpose, did the night resemble<br>
   When he lay couched in the ominous horse,<br>
   Hath now this dread and black complexion smear’d<br>
   With heraldry more dismal. Head to foot<br>
   Now is he total gules, horridly trick’d<br>
   With blood of fathers, mothers, daughters, sons,<br>
   Bak’d and impasted with the parching streets,<br>
   That lend a tyrannous and a damned light<br>
   To their vile murders. Roasted in wrath and fire,<br>
   And thus o’ersized with coagulate gore,<br>
   With eyes like carbuncles, the hellish Pyrrhus<br>
   Old grandsire Priam seeks.</i><br>
So, proceed you.
</p>

<p class="drama">
POLONIUS.<br>
’Fore God, my lord, well spoken, with good accent and good discretion.
</p>

<p class="drama">
FIRST PLAYER.<br>
   <i>Anon he finds him,<br>
   Striking too short at Greeks. His antique sword,<br>
   Rebellious to his arm, lies where it falls,<br>
   Repugnant to command. Unequal match’d,<br>
   Pyrrhus at Priam drives, in rage strikes wide;<br>
   But with the whiff and wind of his fell sword<br>
   Th’unnerved father falls. Then senseless Ilium,<br>
   Seeming to feel this blow, with flaming top<br>
   Stoops to his base, and with a hideous crash<br>
   Takes prisoner Pyrrhus’ ear. For lo, his sword,<br>
   Which was declining on the milky head<br>
   Of reverend Priam, seem’d i’ th’air to stick.<br>
   So, as a painted tyrant, Pyrrhus stood,<br>
   And like a neutral to his will and matter,<br>
   Did nothing.<br>
   But as we often see against some storm,<br>
   A silence in the heavens, the rack stand still,<br>
   The bold winds speechless, and the orb below<br>
   As hush as death, anon the dreadful thunder<br>
   Doth rend the region; so after Pyrrhus’ pause,<br>
   Aroused vengeance sets him new a-work,<br>
   And never did the Cyclops’ hammers fall<br>
   On Mars’s armour, forg’d for proof eterne,<br>
   With less remorse than Pyrrhus’ bleeding sword<br>
   Now falls on Priam.<br>
   Out, out, thou strumpet Fortune! All you gods,<br>
   In general synod, take away her power;<br>
   Break all the spokes and fellies from her wheel,<br>
   And bowl the round nave down the hill of heaven,<br>
   As low as to the fiends.</i><br>
</p>

<p class="drama">
POLONIUS.<br>
This is too long.<br>
</p>

<p class="drama">
HAMLET.<br>
It shall to the barber’s, with your beard.—Prithee say on.<br>
He’s for a jig or a tale of bawdry, or he sleeps.<br>
Say on; come to Hecuba.<br>
</p>

<p class="drama">
FIRST PLAYER.<br>
   <i>But who, O who, had seen the mobled queen,—</i><br>
</p>

<p class="drama">
HAMLET.<br>
‘The mobled queen’?<br>
</p>

<p class="drama">
POLONIUS.<br>
That’s good! ‘Mobled queen’ is good.<br>
</p>

<p class="drama">
FIRST PLAYER.<br>
   <i>Run barefoot up and down, threat’ning the flames<br>
   With bisson rheum. A clout upon that head<br>
   Where late the diadem stood, and for a robe,<br>
   About her lank and all o’erteemed loins,<br>
   A blanket, in th’alarm of fear caught up—<br>
   Who this had seen, with tongue in venom steep’d,<br>
   ’Gainst Fortune’s state would treason have pronounc’d.<br>
   But if the gods themselves did see her then,<br>
   When she saw Pyrrhus make malicious sport<br>
   In mincing with his sword her husband’s limbs,<br>
   The instant burst of clamour that she made,—<br>
   Unless things mortal move them not at all,—<br>
   Would have made milch the burning eyes of heaven,<br>
   And passion in the gods.</i><br>
</p>

<p class="drama">
POLONIUS.<br>
Look, where he has not turn’d his colour, and has tears in’s eyes. Pray you, no
more.
</p>

<p class="drama">
HAMLET.<br>
’Tis well. I’ll have thee speak out the rest of this soon.—Good my lord, will
you see the players well bestowed? Do you hear, let them be well used; for they
are the abstracts and brief chronicles of the time. After your death you were
better have a bad epitaph than their ill report while you live.
</p>

<p class="drama">
POLONIUS.<br>
My lord, I will use them according to their desert.<br>
</p>

<p class="drama">
HAMLET.<br>
God’s bodikin, man, much better. Use every man after his desert, and who should
’scape whipping? Use them after your own honour and dignity. The less they
deserve, the more merit is in your bounty. Take them in.
</p>

<p class="drama">
POLONIUS.<br>
Come, sirs.<br>
</p>

<p class="drama">
HAMLET.<br>
Follow him, friends. We’ll hear a play tomorrow.<br>
</p>

<p class="right">
[<i>Exeunt <span class="charname">Polonius</span> with all the <span class="charname">Players</span> but the First.</i>]
</p>

<p class="drama">
Dost thou hear me, old friend? Can you play <i>The Murder of Gonzago</i>?<br>
</p>

<p class="drama">
FIRST PLAYER.<br>
Ay, my lord.<br>
</p>

<p class="drama">
HAMLET.<br>
We’ll ha’t tomorrow night. You could for a need study a speech of some dozen or
sixteen lines, which I would set down and insert in’t, could you not?
</p>

<p class="drama">
FIRST PLAYER.<br>
Ay, my lord.<br>
</p>

<p class="drama">
HAMLET.<br>
Very well. Follow that lord, and look you mock him not.<br>
</p>

<p class="right">
[<i>Exit <span class="charname">First Player</span>.</i>]
</p>

<p class="drama">
[<i>To Rosencrantz and Guildenstern</i>] My good friends, I’ll leave you till
night. You are welcome to Elsinore.
</p>

<p class="drama">
ROSENCRANTZ.<br>
Good my lord.<br>
</p>

<p class="right">
[<i>Exeunt <span class="charname">Rosencrantz</span> and <span class="charname">Guildenstern</span>.</i>]
</p>

<p class="drama">
HAMLET.<br>
Ay, so, God b’ wi’ ye. Now I am alone.<br>
O what a rogue and peasant slave am I!<br>
Is it not monstrous that this player here,<br>
But in a fiction, in a dream of passion,<br>
Could force his soul so to his own conceit<br>
That from her working all his visage wan’d;<br>
Tears in his eyes, distraction in’s aspect,<br>
A broken voice, and his whole function suiting<br>
With forms to his conceit? And all for nothing!<br>
For Hecuba?<br>
What’s Hecuba to him, or he to Hecuba,<br>
That he should weep for her? What would he do,<br>
Had he the motive and the cue for passion<br>
That I have? He would drown the stage with tears<br>
And cleave the general ear with horrid speech;<br>
Make mad the guilty, and appal the free,<br>
Confound the ignorant, and amaze indeed,<br>
The very faculties of eyes and ears. Yet I,<br>
A dull and muddy-mettled rascal, peak<br>
Like John-a-dreams, unpregnant of my cause,<br>
And can say nothing. No, not for a king<br>
Upon whose property and most dear life<br>
A damn’d defeat was made. Am I a coward?<br>
Who calls me villain, breaks my pate across?<br>
Plucks off my beard and blows it in my face?<br>
Tweaks me by the nose, gives me the lie i’ th’ throat<br>
As deep as to the lungs? Who does me this?<br>
Ha! ’Swounds, I should take it: for it cannot be<br>
But I am pigeon-liver’d, and lack gall<br>
To make oppression bitter, or ere this<br>
I should have fatted all the region kites<br>
With this slave’s offal. Bloody, bawdy villain!<br>
Remorseless, treacherous, lecherous, kindless villain!<br>
Oh vengeance!<br>
Why, what an ass am I! This is most brave,<br>
That I, the son of a dear father murder’d,<br>
Prompted to my revenge by heaven and hell,<br>
Must, like a whore, unpack my heart with words<br>
And fall a-cursing like a very drab,<br>
A scullion! Fie upon’t! Foh!<br>
About, my brain! I have heard<br>
That guilty creatures sitting at a play,<br>
Have by the very cunning of the scene,<br>
Been struck so to the soul that presently<br>
They have proclaim’d their malefactions.<br>
For murder, though it have no tongue, will speak<br>
With most miraculous organ. I’ll have these players<br>
Play something like the murder of my father<br>
Before mine uncle. I’ll observe his looks;<br>
I’ll tent him to the quick. If he but blench,<br>
I know my course. The spirit that I have seen<br>
May be the devil, and the devil hath power<br>
T’assume a pleasing shape, yea, and perhaps<br>
Out of my weakness and my melancholy,<br>
As he is very potent with such spirits,<br>
Abuses me to damn me. I’ll have grounds<br>
More relative than this. The play’s the thing<br>
Wherein I’ll catch the conscience of the King.<br>
</p>

<p class="right">
[<i>Exit.</i>]
</p>

