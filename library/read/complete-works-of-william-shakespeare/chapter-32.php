<h2> <a id="sceneIII_6.1"></a><b>ACT III</b></h2>

<h3> <b>SCENE I. Rome. A street</b></h3>

<p class="scenedesc">
Cornets. Enter <span class="charname">Coriolanus, Menenius,</span> all the
Gentry, <span class="charname">Cominius, Titus Lartius</span> and other
Senators.
</p>

<p class="drama">
CORIOLANUS.<br>
Tullus Aufidius then had made new head?
</p>

<p class="drama">
LARTIUS.<br>
He had, my lord, and that it was which caused<br>
Our swifter composition.
</p>

<p class="drama">
CORIOLANUS.<br>
So then the Volsces stand but as at first,<br>
Ready, when time shall prompt them, to make road<br>
Upon’s again.
</p>

<p class="drama">
COMINIUS.<br>
They are worn, lord consul, so<br>
That we shall hardly in our ages see<br>
Their banners wave again.
</p>

<p class="drama">
CORIOLANUS.<br>
Saw you Aufidius?
</p>

<p class="drama">
LARTIUS.<br>
On safeguard he came to me, and did curse<br>
Against the Volsces, for they had so vilely<br>
Yielded the town. He is retired to Antium.
</p>

<p class="drama">
CORIOLANUS.<br>
Spoke he of me?
</p>

<p class="drama">
LARTIUS.<br>
He did, my lord.
</p>

<p class="drama">
CORIOLANUS.<br>
How? What?
</p>

<p class="drama">
LARTIUS.<br>
How often he had met you sword to sword;<br>
That of all things upon the earth he hated<br>
Your person most; that he would pawn his fortunes<br>
To hopeless restitution, so he might<br>
Be called your vanquisher.
</p>

<p class="drama">
CORIOLANUS.<br>
At Antium lives he?
</p>

<p class="drama">
LARTIUS.<br>
At Antium.
</p>

<p class="drama">
CORIOLANUS.<br>
I wish I had a cause to seek him there,<br>
To oppose his hatred fully. Welcome home.
</p>

<p class="scenedesc">
Enter <span class="charname">Sicinius</span> and
<span class="charname">Brutus</span>.
</p>

<p class="drama">
Behold, these are the tribunes of the people,<br>
The tongues o’ th’ common mouth. I do despise them,<br>
For they do prank them in authority<br>
Against all noble sufferance.
</p>

<p class="drama">
SICINIUS.<br>
Pass no further.
</p>

<p class="drama">
CORIOLANUS.<br>
Ha? What is that?
</p>

<p class="drama">
BRUTUS.<br>
It will be dangerous to go on. No further.
</p>

<p class="drama">
CORIOLANUS.<br>
What makes this change?
</p>

<p class="drama">
MENENIUS.<br>
The matter?
</p>

<p class="drama">
COMINIUS.<br>
Hath he not passed the noble and the common?
</p>

<p class="drama">
BRUTUS.<br>
Cominius, no.
</p>

<p class="drama">
CORIOLANUS.<br>
Have I had children’s voices?
</p>

<p class="drama">
FIRST SENATOR.<br>
Tribunes, give way. He shall to the marketplace.
</p>

<p class="drama">
BRUTUS.<br>
The people are incensed against him.
</p>

<p class="drama">
SICINIUS.<br>
Stop,<br>
Or all will fall in broil.
</p>

<p class="drama">
CORIOLANUS.<br>
Are these your herd?<br>
Must these have voices, that can yield them now<br>
And straight disclaim their tongues? What are your offices?<br>
You being their mouths, why rule you not their teeth?<br>
Have you not set them on?
</p>

<p class="drama">
MENENIUS.<br>
Be calm, be calm.
</p>

<p class="drama">
CORIOLANUS.<br>
It is a purposed thing, and grows by plot,<br>
To curb the will of the nobility.<br>
Suffer’t, and live with such as cannot rule<br>
Nor ever will be ruled.
</p>

<p class="drama">
BRUTUS.<br>
Call’t not a plot.<br>
The people cry you mocked them; and, of late,<br>
When corn was given them gratis, you repined,<br>
Scandaled the suppliants for the people, called them<br>
Timepleasers, flatterers, foes to nobleness.
</p>

<p class="drama">
CORIOLANUS.<br>
Why, this was known before.
</p>

<p class="drama">
BRUTUS.<br>
Not to them all.
</p>

<p class="drama">
CORIOLANUS.<br>
Have you informed them sithence?
</p>

<p class="drama">
BRUTUS.<br>
How? I inform them?
</p>

<p class="drama">
COMINIUS.<br>
You are like to do such business.
</p>

<p class="drama">
BRUTUS.<br>
Not unlike, each way, to better yours.
</p>

<p class="drama">
CORIOLANUS.<br>
Why then should I be consul? By yond clouds,<br>
Let me deserve so ill as you, and make me<br>
Your fellow tribune.
</p>

<p class="drama">
SICINIUS.<br>
You show too much of that<br>
For which the people stir. If you will pass<br>
To where you are bound, you must inquire your way,<br>
Which you are out of, with a gentler spirit,<br>
Or never be so noble as a consul,<br>
Nor yoke with him for tribune.
</p>

<p class="drama">
MENENIUS.<br>
Let’s be calm.
</p>

<p class="drama">
COMINIUS.<br>
The people are abused, set on. This palt’ring<br>
Becomes not Rome, nor has Coriolanus<br>
Deserved this so dishonoured rub, laid falsely<br>
I’ th’ plain way of his merit.
</p>

<p class="drama">
CORIOLANUS.<br>
Tell me of corn?<br>
This was my speech, and I will speak’t again.
</p>

<p class="drama">
MENENIUS.<br>
Not now, not now.
</p>

<p class="drama">
FIRST SENATOR.<br>
Not in this heat, sir, now.
</p>

<p class="drama">
CORIOLANUS.<br>
Now, as I live, I will.<br>
My nobler friends, I crave their pardons. For<br>
The mutable, rank-scented many, let them<br>
Regard me, as I do not flatter, and<br>
Therein behold themselves. I say again,<br>
In soothing them we nourish ’gainst our senate<br>
The cockle of rebellion, insolence, sedition,<br>
Which we ourselves have ploughed for, sowed, and scattered<br>
By mingling them with us, the honoured number,<br>
Who lack not virtue, no, nor power, but that<br>
Which they have given to beggars.
</p>

<p class="drama">
MENENIUS.<br>
Well, no more.
</p>

<p class="drama">
FIRST SENATOR.<br>
No more words, we beseech you.
</p>

<p class="drama">
CORIOLANUS.<br>
How? No more?<br>
As for my country I have shed my blood,<br>
Not fearing outward force, so shall my lungs<br>
Coin words till their decay against those measles<br>
Which we disdain should tetter us, yet sought<br>
The very way to catch them.
</p>

<p class="drama">
BRUTUS.<br>
You speak o’ th’ people<br>
As if you were a god to punish, not<br>
A man of their infirmity.
</p>

<p class="drama">
SICINIUS.<br>
’Twere well<br>
We let the people know’t.
</p>

<p class="drama">
MENENIUS.<br>
What, what? His choler?
</p>

<p class="drama">
CORIOLANUS.<br>
Choler?<br>
Were I as patient as the midnight sleep,<br>
By Jove, ’twould be my mind.
</p>

<p class="drama">
SICINIUS.<br>
It is a mind<br>
That shall remain a poison where it is,<br>
Not poison any further.
</p>

<p class="drama">
CORIOLANUS.<br>
“Shall remain”?<br>
Hear you this Triton of the minnows? Mark you<br>
His absolute “shall”?
</p>

<p class="drama">
COMINIUS.<br>
’Twas from the canon.
</p>

<p class="drama">
CORIOLANUS.<br>
“Shall”?<br>
O good but most unwise patricians, why,<br>
You grave but reckless senators, have you thus<br>
Given Hydra leave to choose an officer,<br>
That with his peremptory “shall,” being but<br>
The horn and noise o’ th’ monster’s, wants not spirit<br>
To say he’ll turn your current in a ditch<br>
And make your channel his? If he have power,<br>
Then vail your ignorance; if none, awake<br>
Your dangerous lenity. If you are learned,<br>
Be not as common fools; if you are not,<br>
Let them have cushions by you. You are plebeians,<br>
If they be senators; and they are no less<br>
When, both your voices blended, the great’st taste<br>
Most palates theirs. They choose their magistrate,<br>
And such a one as he, who puts his “shall,”<br>
His popular “shall,” against a graver bench<br>
Than ever frowned in Greece. By Jove himself,<br>
It makes the consuls base! And my soul aches<br>
To know, when two authorities are up,<br>
Neither supreme, how soon confusion<br>
May enter ’twixt the gap of both and take<br>
The one by th’ other.
</p>

<p class="drama">
COMINIUS.<br>
Well, on to th’ marketplace.
</p>

<p class="drama">
CORIOLANUS.<br>
Whoever gave that counsel to give forth<br>
The corn o’ th’ storehouse gratis, as ’twas used<br>
Sometime in Greece—
</p>

<p class="drama">
MENENIUS.<br>
Well, well, no more of that.
</p>

<p class="drama">
CORIOLANUS.<br>
Though there the people had more absolute power,<br>
I say they nourished disobedience, fed<br>
The ruin of the state.
</p>

<p class="drama">
BRUTUS.<br>
Why shall the people give<br>
One that speaks thus their voice?
</p>

<p class="drama">
CORIOLANUS.<br>
I’ll give my reasons,<br>
More worthier than their voices. They know the corn<br>
Was not our recompense, resting well assured<br>
They ne’er did service for’t. Being pressed to th’ war,<br>
Even when the navel of the state was touched,<br>
They would not thread the gates. This kind of service<br>
Did not deserve corn gratis. Being i’ th’ war,<br>
Their mutinies and revolts, wherein they showed<br>
Most valour, spoke not for them. Th’ accusation<br>
Which they have often made against the Senate,<br>
All cause unborn, could never be the native<br>
Of our so frank donation. Well, what then?<br>
How shall this bosom multitude digest<br>
The senate’s courtesy? Let deeds express<br>
What’s like to be their words: “We did request it;<br>
We are the greater poll, and in true fear<br>
They gave us our demands.” Thus we debase<br>
The nature of our seats and make the rabble<br>
Call our cares fears, which will in time<br>
Break ope the locks o’ th’ Senate and bring in<br>
The crows to peck the eagles.
</p>

<p class="drama">
MENENIUS.<br>
Come, enough.
</p>

<p class="drama">
BRUTUS.<br>
Enough, with over-measure.
</p>

<p class="drama">
CORIOLANUS.<br>
No, take more!<br>
What may be sworn by, both divine and human,<br>
Seal what I end withal! This double worship—<br>
Where one part does disdain with cause, the other<br>
Insult without all reason, where gentry, title, wisdom<br>
Cannot conclude but by the yea and no<br>
Of general ignorance—it must omit<br>
Real necessities and give way the while<br>
To unstable slightness. Purpose so barred, it follows<br>
Nothing is done to purpose. Therefore, beseech you—<br>
You that will be less fearful than discreet,<br>
That love the fundamental part of state<br>
More than you doubt the change on’t, that prefer<br>
A noble life before a long, and wish<br>
To jump a body with a dangerous physic<br>
That’s sure of death without it—at once pluck out<br>
The multitudinous tongue; let them not lick<br>
The sweet which is their poison. Your dishonour<br>
Mangles true judgment and bereaves the state<br>
Of that integrity which should become’t,<br>
Not having the power to do the good it would<br>
For th’ ill which doth control’t.
</p>

<p class="drama">
BRUTUS.<br>
’Has said enough.
</p>

<p class="drama">
SICINIUS.<br>
’Has spoken like a traitor, and shall answer<br>
As traitors do.
</p>

<p class="drama">
CORIOLANUS.<br>
Thou wretch, despite o’erwhelm thee!<br>
What should the people do with these bald tribunes,<br>
On whom depending, their obedience fails<br>
To th’ greater bench. In a rebellion,<br>
When what’s not meet but what must be was law,<br>
Then were they chosen. In a better hour,<br>
Let what is meet be said it must be meet,<br>
And throw their power i’ th’ dust.
</p>

<p class="drama">
BRUTUS.<br>
Manifest treason.
</p>

<p class="drama">
SICINIUS.<br>
This a consul? No.
</p>

<p class="drama">
BRUTUS.<br>
The aediles, ho! Let him be apprehended.
</p>

<p class="scenedesc">
Enter an <span class="charname">Aedile</span>.
</p>

<p class="drama">
SICINIUS.<br>
Go call the people;
</p>

<p class="right">[<i>Exit <span class="charname">Aedile</span>.</i>]</p>

<p class="drama">
in whose name myself<br>
Attach thee as a traitorous innovator,<br>
A foe to th’ public weal. Obey, I charge thee,<br>
And follow to thine answer.
</p>

<p class="drama">
CORIOLANUS.<br>
Hence, old goat.
</p>

<p class="drama">
ALL PATRICIANS.<br>
We’ll surety him.
</p>

<p class="drama">
COMINIUS.<br>
[<i>to Sicinius</i>.] Aged sir, hands off.
</p>

<p class="drama">
CORIOLANUS.<br>
[<i>to Sicinius</i>.] Hence, rotten thing, or I shall shake thy bones<br>
Out of thy garments.
</p>

<p class="drama">
SICINIUS.<br>
Help, ye citizens!
</p>

<p class="scenedesc">
Enter a rabble of Plebeians with the <span class="charname">Aediles</span>.
</p>

<p class="drama">
MENENIUS.<br>
On both sides more respect!
</p>

<p class="drama">
SICINIUS.<br>
Here’s he that would take from you all your power.
</p>

<p class="drama">
BRUTUS.<br>
Seize him, aediles.
</p>

<p class="drama">
ALL PLEBEIANS.<br>
Down with him, down with him!
</p>

<p class="drama">
SECOND SENATOR.<br>
Weapons, weapons, weapons!
</p>

<p class="right">[<i>They all bustle about <span class="charname">Coriolanus</span>.</i>]</p>

<p class="drama">
Tribunes, patricians, citizens, what, ho!<br>
Sicinius, Brutus, Coriolanus, citizens!
</p>

<p class="drama">
ALL.<br>
Peace, peace, peace! Stay, hold, peace!
</p>

<p class="drama">
MENENIUS.<br>
What is about to be? I am out of breath.<br>
Confusion’s near. I cannot speak. You tribunes<br>
To th’ people!—Coriolanus, patience!—<br>
Speak, good Sicinius.
</p>

<p class="drama">
SICINIUS.<br>
Hear me, people! Peace!
</p>

<p class="drama">
ALL PLEBEIANS.<br>
Let’s hear our tribune. Peace! Speak, speak, speak.
</p>

<p class="drama">
SICINIUS.<br>
You are at point to lose your liberties.<br>
Martius would have all from you, Martius,<br>
Whom late you have named for consul.
</p>

<p class="drama">
MENENIUS.<br>
Fie, fie, fie!<br>
This is the way to kindle, not to quench.
</p>

<p class="drama">
FIRST SENATOR.<br>
To unbuild the city and to lay all flat.
</p>

<p class="drama">
SICINIUS.<br>
What is the city but the people?
</p>

<p class="drama">
ALL PLEBEIANS.<br>
True,<br>
The people are the city.
</p>

<p class="drama">
BRUTUS.<br>
By the consent of all, we were established<br>
The people’s magistrates.
</p>

<p class="drama">
ALL PLEBEIANS.<br>
You so remain.
</p>

<p class="drama">
MENENIUS.<br>
And so are like to do.
</p>

<p class="drama">
COMINIUS.<br>
That is the way to lay the city flat,<br>
To bring the roof to the foundation<br>
And bury all which yet distinctly ranges<br>
In heaps and piles of ruin.
</p>

<p class="drama">
SICINIUS.<br>
This deserves death.
</p>

<p class="drama">
BRUTUS.<br>
Or let us stand to our authority<br>
Or let us lose it. We do here pronounce,<br>
Upon the part o’ th’ people, in whose power<br>
We were elected theirs, Martius is worthy<br>
Of present death.
</p>

<p class="drama">
SICINIUS.<br>
Therefore lay hold of him,<br>
Bear him to th’ rock Tarpeian, and from thence<br>
Into destruction cast him.
</p>

<p class="drama">
BRUTUS.<br>
Aediles, seize him!
</p>

<p class="drama">
ALL PLEBEIANS.<br>
Yield, Martius, yield!
</p>

<p class="drama">
MENENIUS.<br>
Hear me one word.<br>
Beseech you, tribunes, hear me but a word.
</p>

<p class="drama">
AEDILES.<br>
Peace, peace!
</p>

<p class="drama">
MENENIUS.<br>
Be that you seem, truly your country’s friend,<br>
And temp’rately proceed to what you would<br>
Thus violently redress.
</p>

<p class="drama">
BRUTUS.<br>
Sir, those cold ways,<br>
That seem like prudent helps, are very poisonous<br>
Where the disease is violent.—Lay hands upon him,<br>
And bear him to the rock.
</p>

<p class="right">[<i><span class="charname">Coriolanus</span> draws his sword.</i>]</p>

<p class="drama">
CORIOLANUS.<br>
No; I’ll die here.<br>
There’s some among you have beheld me fighting.<br>
Come, try upon yourselves what you have seen me.
</p>

<p class="drama">
MENENIUS.<br>
Down with that sword!—Tribunes, withdraw awhile.
</p>

<p class="drama">
BRUTUS.<br>
Lay hands upon him!
</p>

<p class="drama">
MENENIUS.<br>
Help Martius, help!<br>
You that be noble, help him, young and old!
</p>

<p class="drama">
ALL PLEBEIANS.<br>
Down with him, down with him!
</p>

<p class="right">
[<i>In this mutiny the <span class="charname">Tribunes</span>, the
<span class="charname">Aediles</span> and the People are beat in.</i>]
</p>

<p class="drama">
MENENIUS.<br>
Go, get you to your house. Begone, away.<br>
All will be naught else.
</p>

<p class="drama">
SECOND SENATOR.<br>
Get you gone.
</p>

<p class="drama">
CORIOLANUS.<br>
Stand fast!<br>
We have as many friends as enemies.
</p>

<p class="drama">
MENENIUS.<br>
Shall it be put to that?
</p>

<p class="drama">
FIRST SENATOR.<br>
The gods forbid!<br>
I prithee, noble friend, home to thy house;<br>
Leave us to cure this cause.
</p>

<p class="drama">
MENENIUS.<br>
For ’tis a sore upon us<br>
You cannot tent yourself. Begone, beseech you.
</p>

<p class="drama">
COMINIUS.<br>
Come, sir, along with us.
</p>

<p class="drama">
CORIOLANUS.<br>
I would they were barbarians, as they are,<br>
Though in Rome littered, not Romans, as they are not,<br>
Though calved i’ th’ porch o’ th’ Capitol.
</p>

<p class="drama">
MENENIUS.<br>
Begone!<br>
Put not your worthy rage into your tongue.<br>
One time will owe another.
</p>

<p class="drama">
CORIOLANUS.<br>
On fair ground<br>
I could beat forty of them.
</p>

<p class="drama">
MENENIUS.<br>
I could myself<br>
Take up a brace o’ th’ best of them, yea, the two tribunes.
</p>

<p class="drama">
COMINIUS.<br>
But now ’tis odds beyond arithmetic,<br>
And manhood is called foolery when it stands<br>
Against a falling fabric. Will you hence,<br>
Before the tag return, whose rage doth rend<br>
Like interrupted waters, and o’erbear<br>
What they are used to bear?
</p>

<p class="drama">
MENENIUS.<br>
Pray you, begone.<br>
I’ll try whether my old wit be in request<br>
With those that have but little. This must be patched<br>
With cloth of any colour.
</p>

<p class="drama">
COMINIUS.<br>
Nay, come away.
</p>

<p class="right">[<i>Exeunt <span class="charname">Coriolanus</span> and
<span class="charname">Cominius</span>.</i>]</p>

<p class="drama">
PATRICIAN.<br>
This man has marred his fortune.
</p>

<p class="drama">
MENENIUS.<br>
His nature is too noble for the world.<br>
He would not flatter Neptune for his trident<br>
Or Jove for’s power to thunder. His heart’s his mouth;<br>
What his breast forges, that his tongue must vent,<br>
And, being angry, does forget that ever<br>
He heard the name of death.
</p>

<p class="right">[<i>A noise within.</i>]</p>

<p class="drama">
Here’s goodly work.
</p>

<p class="drama">
PATRICIAN.<br>
I would they were abed!
</p>

<p class="drama">
MENENIUS.<br>
I would they were in Tiber! What the vengeance,<br>
Could he not speak ’em fair?
</p>

<p class="scenedesc">
Enter <span class="charname">Brutus</span> and
<span class="charname">Sicinius</span> with the rabble again.
</p>

<p class="drama">
SICINIUS.<br>
Where is this viper<br>
That would depopulate the city and<br>
Be every man himself?
</p>

<p class="drama">
MENENIUS.<br>
You worthy tribunes—
</p>

<p class="drama">
SICINIUS.<br>
He shall be thrown down the Tarpeian rock<br>
With rigorous hands. He hath resisted law,<br>
And therefore law shall scorn him further trial<br>
Than the severity of the public power<br>
Which he so sets at naught.
</p>

<p class="drama">
FIRST CITIZEN.<br>
He shall well know<br>
The noble tribunes are the people’s mouths,<br>
And we their hands.
</p>

<p class="drama">
ALL PLEBEIANS.<br>
He shall, sure on’t.
</p>

<p class="drama">
MENENIUS.<br>
Sir, sir—
</p>

<p class="drama">
SICINIUS.<br>
Peace!
</p>

<p class="drama">
MENENIUS.<br>
Do not cry havoc where you should but hunt<br>
With modest warrant.
</p>

<p class="drama">
SICINIUS.<br>
Sir, how comes’t that you<br>
Have holp to make this rescue?
</p>

<p class="drama">
MENENIUS.<br>
Hear me speak.<br>
As I do know the Consul’s worthiness,<br>
So can I name his faults.
</p>

<p class="drama">
SICINIUS.<br>
Consul? What consul?
</p>

<p class="drama">
MENENIUS.<br>
The consul Coriolanus.
</p>

<p class="drama">
BRUTUS.<br>
He consul?
</p>

<p class="drama">
ALL PLEBEIANS.<br>
No, no, no, no, no!
</p>

<p class="drama">
MENENIUS.<br>
If, by the Tribunes’ leave, and yours, good people,<br>
I may be heard, I would crave a word or two,<br>
The which shall turn you to no further harm<br>
Than so much loss of time.
</p>

<p class="drama">
SICINIUS.<br>
Speak briefly then,<br>
For we are peremptory to dispatch<br>
This viperous traitor. To eject him hence<br>
Were but one danger, and to keep him here<br>
Our certain death. Therefore it is decreed<br>
He dies tonight.
</p>

<p class="drama">
MENENIUS.<br>
Now the good gods forbid<br>
That our renowned Rome, whose gratitude<br>
Towards her deserved children is enrolled<br>
In Jove’s own book, like an unnatural dam<br>
Should now eat up her own.
</p>

<p class="drama">
SICINIUS.<br>
He’s a disease that must be cut away.
</p>

<p class="drama">
MENENIUS.<br>
O, he’s a limb that has but a disease—<br>
Mortal to cut it off; to cure it easy.<br>
What has he done to Rome that’s worthy death?<br>
Killing our enemies, the blood he hath lost—<br>
Which I dare vouch is more than that he hath<br>
By many an ounce—he dropt it for his country;<br>
And what is left, to lose it by his country<br>
Were to us all, that do’t and suffer it<br>
A brand to th’ end o’ th’ world.
</p>

<p class="drama">
SICINIUS.<br>
This is clean cam.
</p>

<p class="drama">
BRUTUS.<br>
Merely awry. When he did love his country,<br>
It honoured him.
</p>

<p class="drama">
MENENIUS.<br>
The service of the foot,<br>
Being once gangrened, is not then respected<br>
For what before it was.
</p>

<p class="drama">
BRUTUS.<br>
We’ll hear no more.<br>
Pursue him to his house, and pluck him thence,<br>
Lest his infection, being of catching nature,<br>
Spread further.
</p>

<p class="drama">
MENENIUS.<br>
One word more, one word!<br>
This tiger-footed rage, when it shall find<br>
The harm of unscanned swiftness, will too late,<br>
Tie leaden pounds to’s heels. Proceed by process,<br>
Lest parties—as he is beloved—break out<br>
And sack great Rome with Romans.
</p>

<p class="drama">
BRUTUS.<br>
If it were so—
</p>

<p class="drama">
SICINIUS.<br>
What do ye talk?<br>
Have we not had a taste of his obedience?<br>
Our aediles smote! Ourselves resisted? Come.
</p>

<p class="drama">
MENENIUS.<br>
Consider this: he has been bred i’ th’ wars<br>
Since he could draw a sword, and is ill schooled<br>
In bolted language; meal and bran together<br>
He throws without distinction. Give me leave,<br>
I’ll go to him and undertake to bring him<br>
Where he shall answer by a lawful form,<br>
In peace, to his utmost peril.
</p>

<p class="drama">
FIRST SENATOR.<br>
Noble tribunes,<br>
It is the humane way: the other course<br>
Will prove too bloody, and the end of it<br>
Unknown to the beginning.
</p>

<p class="drama">
SICINIUS.<br>
Noble Menenius,<br>
Be you then as the people’s officer.—<br>
Masters, lay down your weapons.
</p>

<p class="drama">
BRUTUS.<br>
Go not home.
</p>

<p class="drama">
SICINIUS.<br>
Meet on the marketplace. We’ll attend you there,<br>
Where if you bring not Martius, we’ll proceed<br>
In our first way.
</p>

<p class="drama">
MENENIUS.<br>
I’ll bring him to you.<br>
[<i>To Senators</i>.] Let me desire your company. He must come,<br>
Or what is worst will follow.
</p>

<p class="drama">
FIRST SENATOR.<br>
Pray you, let’s to him.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneIII_6.2"></a><b>SCENE II. Rome. A room in Coriolanus’s house</b></h3>

<p class="scenedesc">
Enter <span class="charname">Coriolanus</span> with Nobles.
</p>

<p class="drama">
CORIOLANUS.<br>
Let them pull all about mine ears, present me<br>
Death on the wheel or at wild horses’ heels,<br>
Or pile ten hills on the Tarpeian rock,<br>
That the precipitation might down stretch<br>
Below the beam of sight, yet will I still<br>
Be thus to them.
</p>

<p class="drama">
FIRST PATRICIAN.<br>
You do the nobler.
</p>

<p class="drama">
CORIOLANUS.<br>
I muse my mother<br>
Does not approve me further, who was wont<br>
To call them woollen vassals, things created<br>
To buy and sell with groats, to show bare heads<br>
In congregations, to yawn, be still, and wonder<br>
When one but of my ordinance stood up<br>
To speak of peace or war.
</p>

<p class="scenedesc">
Enter <span class="charname">Volumnia</span>.
</p>

<p class="drama">
I talk of you.<br>
Why did you wish me milder? Would you have me<br>
False to my nature? Rather say I play<br>
The man I am.
</p>

<p class="drama">
VOLUMNIA.<br>
O, sir, sir, sir,<br>
I would have had you put your power well on<br>
Before you had worn it out.
</p>

<p class="drama">
CORIOLANUS.<br>
Let go.
</p>

<p class="drama">
VOLUMNIA.<br>
You might have been enough the man you are<br>
With striving less to be so. Lesser had been<br>
The thwartings of your dispositions if<br>
You had not showed them how ye were disposed<br>
Ere they lacked power to cross you.
</p>

<p class="drama">
CORIOLANUS.<br>
Let them hang!
</p>

<p class="drama">
VOLUMNIA.<br>
Ay, and burn too.
</p>

<p class="scenedesc">
Enter <span class="charname">Menenius</span> with the
<span class="charname">Senators</span>.
</p>

<p class="drama">
MENENIUS.<br>
Come, come, you have been too rough, something too rough.<br>
You must return and mend it.
</p>

<p class="drama">
FIRST SENATOR.<br>
There’s no remedy,<br>
Unless, by not so doing, our good city<br>
Cleave in the midst and perish.
</p>

<p class="drama">
VOLUMNIA.<br>
Pray be counselled.<br>
I have a heart as little apt as yours,<br>
But yet a brain that leads my use of anger<br>
To better vantage.
</p>

<p class="drama">
MENENIUS.<br>
Well said, noble woman.<br>
Before he should thus stoop to th’ herd—but that<br>
The violent fit o’ th’ time craves it as physic<br>
For the whole state—I would put mine armour on,<br>
Which I can scarcely bear.
</p>

<p class="drama">
CORIOLANUS.<br>
What must I do?
</p>

<p class="drama">
MENENIUS.<br>
Return to th’ Tribunes.
</p>

<p class="drama">
CORIOLANUS.<br>
Well, what then? What then?
</p>

<p class="drama">
MENENIUS.<br>
Repent what you have spoke.
</p>

<p class="drama">
CORIOLANUS.<br>
For them? I cannot do it to the gods.<br>
Must I then do’t to them?
</p>

<p class="drama">
VOLUMNIA.<br>
You are too absolute,<br>
Though therein you can never be too noble<br>
But when extremities speak. I have heard you say<br>
Honour and policy, like unsevered friends,<br>
I’ th’ war do grow together. Grant that, and tell me<br>
In peace what each of them by th’ other lose<br>
That they combine not there.
</p>

<p class="drama">
CORIOLANUS.<br>
Tush, tush!
</p>

<p class="drama">
MENENIUS.<br>
A good demand.
</p>

<p class="drama">
VOLUMNIA.<br>
If it be honour in your wars to seem<br>
The same you are not, which for your best ends<br>
You adopt your policy, how is it less or worse<br>
That it shall hold companionship in peace<br>
With honour as in war, since that to both<br>
It stands in like request?
</p>

<p class="drama">
CORIOLANUS.<br>
Why force you this?
</p>

<p class="drama">
VOLUMNIA.<br>
Because that now it lies you on to speak<br>
To th’ people, not by your own instruction,<br>
Nor by th’ matter which your heart prompts you,<br>
But with such words that are but rooted in<br>
Your tongue, though but bastards and syllables<br>
Of no allowance to your bosom’s truth.<br>
Now, this no more dishonours you at all<br>
Than to take in a town with gentle words,<br>
Which else would put you to your fortune and<br>
The hazard of much blood.<br>
I would dissemble with my nature where<br>
My fortunes and my friends at stake required<br>
I should do so in honour. I am in this<br>
Your wife, your son, these senators, the nobles;<br>
And you will rather show our general louts<br>
How you can frown than spend a fawn upon ’em<br>
For the inheritance of their loves and safeguard<br>
Of what that want might ruin.
</p>

<p class="drama">
MENENIUS.<br>
Noble lady!—<br>
Come, go with us; speak fair. You may salve so,<br>
Not what is dangerous present, but the loss<br>
Of what is past.
</p>

<p class="drama">
VOLUMNIA.<br>
I prithee now, my son,<br>
Go to them with this bonnet in thy hand,<br>
And thus far having stretched it—here be with them—<br>
Thy knee bussing the stones—for in such busines<br>
Action is eloquence, and the eyes of th’ ignorant<br>
More learned than the ears—waving thy head,<br>
Which often thus correcting thy stout heart,<br>
Now humble as the ripest mulberry<br>
That will not hold the handling. Or say to them<br>
Thou art their soldier and, being bred in broils,<br>
Hast not the soft way, which thou dost confess<br>
Were fit for thee to use, as they to claim,<br>
In asking their good loves; but thou wilt frame<br>
Thyself, forsooth, hereafter theirs, so far<br>
As thou hast power and person.
</p>

<p class="drama">
MENENIUS.<br>
This but done<br>
Even as she speaks, why, their hearts were yours;<br>
For they have pardons, being asked, as free<br>
As words to little purpose.
</p>

<p class="drama">
VOLUMNIA.<br>
Prithee now,<br>
Go, and be ruled; although I know thou hadst rather<br>
Follow thine enemy in a fiery gulf<br>
Than flatter him in a bower.
</p>

<p class="scenedesc">
Enter <span class="charname">Cominius</span>.
</p>

<p class="drama">
Here is Cominius.
</p>

<p class="drama">
COMINIUS.<br>
I have been i’ th’ marketplace; and, sir, ’tis fit<br>
You make strong party or defend yourself<br>
By calmness or by absence. All’s in anger.
</p>

<p class="drama">
MENENIUS.<br>
Only fair speech.
</p>

<p class="drama">
COMINIUS.<br>
I think ’twill serve, if he<br>
Can thereto frame his spirit.
</p>

<p class="drama">
VOLUMNIA.<br>
He must, and will.—<br>
Prithee, now, say you will, and go about it.
</p>

<p class="drama">
CORIOLANUS.<br>
Must I go show them my unbarbed sconce? Must I<br>
With my base tongue give to my noble heart<br>
A lie that it must bear? Well, I will do’t.<br>
Yet, were there but this single plot to lose,<br>
This mould of Martius, they to dust should grind it<br>
And throw’t against the wind. To th’ marketplace!<br>
You have put me now to such a part which never<br>
I shall discharge to th’ life.
</p>

<p class="drama">
COMINIUS.<br>
Come, come, we’ll prompt you.
</p>

<p class="drama">
VOLUMNIA.<br>
I prithee now, sweet son, as thou hast said<br>
My praises made thee first a soldier, so,<br>
To have my praise for this, perform a part<br>
Thou hast not done before.
</p>

<p class="drama">
CORIOLANUS.<br>
Well, I must do’t.<br>
Away, my disposition, and possess me<br>
Some harlot’s spirit! My throat of war be turned,<br>
Which choired with my drum, into a pipe<br>
Small as an eunuch or the virgin voice<br>
That babies lulls asleep! The smiles of knaves<br>
Tent in my cheeks, and schoolboys’ tears take up<br>
The glasses of my sight! A beggar’s tongue<br>
Make motion through my lips, and my armed knees,<br>
Who bowed but in my stirrup, bend like his<br>
That hath received an alms! I will not do’t,<br>
Lest I surcease to honour mine own truth<br>
And, by my body’s action, teach my mind<br>
A most inherent baseness.
</p>

<p class="drama">
VOLUMNIA.<br>
At thy choice, then.<br>
To beg of thee, it is my more dishonour<br>
Than thou of them. Come all to ruin. Let<br>
Thy mother rather feel thy pride than fear<br>
Thy dangerous stoutness, for I mock at death<br>
With as big heart as thou. Do as thou list.<br>
Thy valiantness was mine; thou suck’dst it from me,<br>
But owe thy pride thyself.
</p>

<p class="drama">
CORIOLANUS.<br>
Pray, be content.<br>
Mother, I am going to the marketplace.<br>
Chide me no more. I’ll mountebank their loves,<br>
Cog their hearts from them, and come home beloved<br>
Of all the trades in Rome. Look, I am going.<br>
Commend me to my wife. I’ll return consul,<br>
Or never trust to what my tongue can do<br>
I’ th’ way of flattery further.
</p>

<p class="drama">
VOLUMNIA.<br>
Do your will.
</p>

<p class="right">[<i>Exit <span class="charname">Volumnia</span>.</i>]</p>

<p class="drama">
COMINIUS.<br>
Away! The Tribunes do attend you. Arm yourself<br>
To answer mildly, for they are prepared<br>
With accusations, as I hear, more strong<br>
Than are upon you yet.
</p>

<p class="drama">
CORIOLANUS.<br>
The word is “mildly.” Pray you, let us go.<br>
Let them accuse me by invention, I<br>
Will answer in mine honour.
</p>

<p class="drama">
MENENIUS.<br>
Ay, but mildly.
</p>

<p class="drama">
CORIOLANUS.<br>
Well, mildly be it, then. Mildly.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneIII_6.3"></a><b>SCENE III. Rome. The Forum</b></h3>

<p class="scenedesc">
Enter <span class="charname">Sicinius</span> and
<span class="charname">Brutus</span>.
</p>

<p class="drama">
BRUTUS.<br>
In this point charge him home, that he affects<br>
Tyrannical power. If he evade us there,<br>
Enforce him with his envy to the people,<br>
And that the spoil got on the Antiates<br>
Was ne’er distributed.
</p>

<p class="scenedesc">
Enter an <span class="charname">Aedile</span>.
</p>

<p class="drama">
What, will he come?
</p>

<p class="drama">
AEDILE.<br>
He’s coming.
</p>

<p class="drama">
BRUTUS.<br>
How accompanied?
</p>

<p class="drama">
AEDILE.<br>
With old Menenius, and those senators<br>
That always favoured him.
</p>

<p class="drama">
SICINIUS.<br>
Have you a catalogue<br>
Of all the voices that we have procured,<br>
Set down by th’ poll?
</p>

<p class="drama">
AEDILE.<br>
I have. ’Tis ready.
</p>

<p class="drama">
SICINIUS.<br>
Have you collected them by tribes?
</p>

<p class="drama">
AEDILE.<br>
I have.
</p>

<p class="drama">
SICINIUS.<br>
Assemble presently the people hither;<br>
And when they hear me say “It shall be so<br>
I’ th’ right and strength o’ th’ commons,” be it either<br>
For death, for fine, or banishment, then let them<br>
If I say “Fine,” cry “Fine,” if “Death,” cry “Death,”<br>
Insisting on the old prerogative<br>
And power i’ th’ truth o’ th’ cause.
</p>

<p class="drama">
AEDILE.<br>
I shall inform them.
</p>

<p class="drama">
BRUTUS.<br>
And when such time they have begun to cry,<br>
Let them not cease, but with a din confused<br>
Enforce the present execution<br>
Of what we chance to sentence.
</p>

<p class="drama">
AEDILE.<br>
Very well.
</p>

<p class="drama">
SICINIUS.<br>
Make them be strong and ready for this hint<br>
When we shall hap to give’t them.
</p>

<p class="drama">
BRUTUS.<br>
Go about it.
</p>

<p class="right">[<i>Exit <span class="charname">Aedile</span>.</i>]</p>

<p class="drama">
Put him to choler straight. He hath been used<br>
Ever to conquer and to have his worth<br>
Of contradiction. Being once chafed, he cannot<br>
Be reined again to temperance; then he speaks<br>
What’s in his heart; and that is there which looks<br>
With us to break his neck.
</p>

<p class="scenedesc">
Enter <span class="charname">Coriolanus, Menenius</span> and
<span class="charname">Cominius</span> with other Senators.
</p>

<p class="drama">
SICINIUS.<br>
Well, here he comes.
</p>

<p class="drama">
MENENIUS.<br>
Calmly, I do beseech you.
</p>

<p class="drama">
CORIOLANUS.<br>
Ay, as an ostler, that for th’ poorest piece<br>
Will bear the knave by th’ volume.—Th’ honoured gods<br>
Keep Rome in safety and the chairs of justice<br>
Supplied with worthy men! Plant love among’s!<br>
Throng our large temples with the shows of peace<br>
And not our streets with war!
</p>

<p class="drama">
FIRST SENATOR.<br>
Amen, amen.
</p>

<p class="drama">
MENENIUS.<br>
A noble wish.
</p>

<p class="scenedesc">
Enter the <span class="charname">Aedile</span> with the Plebeians.
</p>

<p class="drama">
SICINIUS.<br>
Draw near, ye people.
</p>

<p class="drama">
AEDILE.<br>
List to your tribunes. Audience! Peace, I say!
</p>

<p class="drama">
CORIOLANUS.<br>
First, hear me speak.
</p>

<p class="drama">
BOTH TRIBUNES.<br>
Well, say.—Peace, ho!
</p>

<p class="drama">
CORIOLANUS.<br>
Shall I be charged no further than this present?<br>
Must all determine here?
</p>

<p class="drama">
SICINIUS.<br>
I do demand<br>
If you submit you to the people’s voices,<br>
Allow their officers, and are content<br>
To suffer lawful censure for such faults<br>
As shall be proved upon you.
</p>

<p class="drama">
CORIOLANUS.<br>
I am content.
</p>

<p class="drama">
MENENIUS.<br>
Lo, citizens, he says he is content.<br>
The warlike service he has done, consider. Think<br>
Upon the wounds his body bears, which show<br>
Like graves i’ th’ holy churchyard.
</p>

<p class="drama">
CORIOLANUS.<br>
Scratches with briars,<br>
Scars to move laughter only.
</p>

<p class="drama">
MENENIUS.<br>
Consider further,<br>
That when he speaks not like a citizen,<br>
You find him like a soldier. Do not take<br>
His rougher accents for malicious sounds,<br>
But, as I say, such as become a soldier<br>
Rather than envy you.
</p>

<p class="drama">
COMINIUS.<br>
Well, well, no more.
</p>

<p class="drama">
CORIOLANUS.<br>
What is the matter,<br>
That, being passed for consul with full voice,<br>
I am so dishonoured that the very hour<br>
You take it off again?
</p>

<p class="drama">
SICINIUS.<br>
Answer to us.
</p>

<p class="drama">
CORIOLANUS.<br>
Say then. ’Tis true, I ought so.
</p>

<p class="drama">
SICINIUS.<br>
We charge you that you have contrived to take<br>
From Rome all seasoned office and to wind<br>
Yourself into a power tyrannical,<br>
For which you are a traitor to the people.
</p>

<p class="drama">
CORIOLANUS.<br>
How? Traitor?
</p>

<p class="drama">
MENENIUS.<br>
Nay, temperately! Your promise.
</p>

<p class="drama">
CORIOLANUS.<br>
The fires i’ th’ lowest hell fold in the people!<br>
Call me their traitor? Thou injurious tribune!<br>
Within thine eyes sat twenty thousand deaths,<br>
In thy hands clutched as many millions, in<br>
Thy lying tongue both numbers, I would say<br>
“Thou liest” unto thee with a voice as free<br>
As I do pray the gods.
</p>

<p class="drama">
SICINIUS.<br>
Mark you this, people?
</p>

<p class="drama">
ALL PLEBEIANS.<br>
To th’ rock, to th’ rock with him!
</p>

<p class="drama">
SICINIUS.<br>
Peace!<br>
We need not put new matter to his charge.<br>
What you have seen him do and heard him speak,<br>
Beating your officers, cursing yourselves,<br>
Opposing laws with strokes, and here defying<br>
Those whose great power must try him—even this,<br>
So criminal and in such capital kind,<br>
Deserves th’ extremest death.
</p>

<p class="drama">
BRUTUS.<br>
But since he hath<br>
Served well for Rome—
</p>

<p class="drama">
CORIOLANUS.<br>
What do you prate of service?
</p>

<p class="drama">
BRUTUS.<br>
I talk of that that know it.
</p>

<p class="drama">
CORIOLANUS.<br>
You?
</p>

<p class="drama">
MENENIUS.<br>
Is this the promise that you made your mother?
</p>

<p class="drama">
COMINIUS.<br>
Know, I pray you—
</p>

<p class="drama">
CORIOLANUS.<br>
I’ll know no further.<br>
Let them pronounce the steep Tarpeian death,<br>
Vagabond exile, flaying, pent to linger<br>
But with a grain a day, I would not buy<br>
Their mercy at the price of one fair word,<br>
Nor check my courage for what they can give,<br>
To have’t with saying “Good morrow.”
</p>

<p class="drama">
SICINIUS.<br>
For that he has,<br>
As much as in him lies, from time to time<br>
Envied against the people, seeking means<br>
To pluck away their power, as now at last<br>
Given hostile strokes, and that not in the presence<br>
Of dreaded justice, but on the ministers<br>
That do distribute it, in the name o’ th’ people<br>
And in the power of us the Tribunes, we,<br>
Even from this instant, banish him our city<br>
In peril of precipitation<br>
From off the rock Tarpeian, never more<br>
To enter our Rome gates. I’ th’ people’s name,<br>
I say it shall be so.
</p>

<p class="drama">
ALL PLEBEIANS.<br>
It shall be so, it shall be so! Let him away!<br>
He’s banished, and it shall be so.
</p>

<p class="drama">
COMINIUS.<br>
Hear me, my masters and my common friends—
</p>

<p class="drama">
SICINIUS.<br>
He’s sentenced. No more hearing.
</p>

<p class="drama">
COMINIUS.<br>
Let me speak.<br>
I have been consul and can show for Rome<br>
Her enemies’ marks upon me. I do love<br>
My country’s good with a respect more tender,<br>
More holy and profound, than mine own life,<br>
My dear wife’s estimate, her womb’s increase,<br>
And treasure of my loins. Then if I would<br>
Speak that—
</p>

<p class="drama">
SICINIUS.<br>
We know your drift. Speak what?
</p>

<p class="drama">
BRUTUS.<br>
There’s no more to be said, but he is banished<br>
As enemy to the people and his country.<br>
It shall be so.
</p>

<p class="drama">
ALL PLEBEIANS.<br>
It shall be so, it shall be so!
</p>

<p class="drama">
CORIOLANUS.<br>
You common cry of curs, whose breath I hate<br>
As reek o’ th’ rotten fens, whose loves I prize<br>
As the dead carcasses of unburied men<br>
That do corrupt my air, I banish you!<br>
And here remain with your uncertainty;<br>
Let every feeble rumour shake your hearts;<br>
Your enemies, with nodding of their plumes,<br>
Fan you into despair! Have the power still<br>
To banish your defenders, till at length<br>
Your ignorance—which finds not till it feels,<br>
Making but reservation of yourselves,<br>
Still your own foes—deliver you,<br>
As most abated captives to some nation<br>
That won you without blows! Despising<br>
For you the city, thus I turn my back.<br>
There is a world elsewhere.
</p>

<p class="right">[<i>Exeunt <span class="charname">Coriolanus, Cominius,</span>
with other Senators.</i>]</p>

<p class="drama">
AEDILE.<br>
The people’s enemy is gone, is gone.
</p>

<p class="drama">
ALL PLEBEIANS.<br>
Our enemy is banished; he is gone. Hoo, hoo!
</p>

<p class="right">[<i>They all shout and throw up their caps.</i>]</p>

<p class="drama">
SICINIUS.<br>
Go see him out at gates, and follow him,<br>
As he hath followed you, with all despite.<br>
Give him deserved vexation. Let a guard<br>
Attend us through the city.
</p>

<p class="drama">
ALL PLEBEIANS.<br>
Come, come, let’s see him out at gates! Come!<br>
The gods preserve our noble tribunes! Come.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

