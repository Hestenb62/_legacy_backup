<h2> <a id="sceneIV_8.1"></a><b>ACT IV</b></h2>

<h3> <b>SCENE I. A room in the Castle.</b></h3>

<p class="scenedesc">
Enter <span class="charname">King, Queen, Rosencrantz</span> and <span class="charname">Guildenstern</span>.
</p>

<p class="drama">
KING.<br>
There’s matter in these sighs. These profound heaves<br>
You must translate; ’tis fit we understand them.<br>
Where is your son?<br>
</p>

<p class="drama">
QUEEN.<br>
Bestow this place on us a little while.<br>
</p>

<p class="right">
[<i>To <span class="charname">Rosencrantz</span> and <span class="charname">Guildenstern,</span> who go out.</i>]
</p>

<p class="drama">
Ah, my good lord, what have I seen tonight!
</p>

<p class="drama">
KING.<br>
What, Gertrude? How does Hamlet?<br>
</p>

<p class="drama">
QUEEN.<br>
Mad as the sea and wind, when both contend<br>
Which is the mightier. In his lawless fit<br>
Behind the arras hearing something stir,<br>
Whips out his rapier, cries ‘A rat, a rat!’<br>
And in this brainish apprehension kills<br>
The unseen good old man.<br>
</p>

<p class="drama">
KING.<br>
O heavy deed!<br>
It had been so with us, had we been there.<br>
His liberty is full of threats to all;<br>
To you yourself, to us, to everyone.<br>
Alas, how shall this bloody deed be answer’d?<br>
It will be laid to us, whose providence<br>
Should have kept short, restrain’d, and out of haunt<br>
This mad young man. But so much was our love<br>
We would not understand what was most fit,<br>
But like the owner of a foul disease,<br>
To keep it from divulging, let it feed<br>
Even on the pith of life. Where is he gone?<br>
</p>

<p class="drama">
QUEEN.<br>
To draw apart the body he hath kill’d,<br>
O’er whom his very madness, like some ore<br>
Among a mineral of metals base,<br>
Shows itself pure. He weeps for what is done.<br>
</p>

<p class="drama">
KING.<br>
O Gertrude, come away!<br>
The sun no sooner shall the mountains touch<br>
But we will ship him hence, and this vile deed<br>
We must with all our majesty and skill<br>
Both countenance and excuse.—Ho, Guildenstern!<br>
</p>

<p class="scenedesc">
Re-enter <span class="charname">Rosencrantz</span> and <span class="charname">Guildenstern</span>.
</p>

<p class="drama">
Friends both, go join you with some further aid:<br>
Hamlet in madness hath Polonius slain,<br>
And from his mother’s closet hath he dragg’d him.<br>
Go seek him out, speak fair, and bring the body<br>
Into the chapel. I pray you haste in this.<br>
</p>

<p class="right">
[<i>Exeunt <span class="charname">Rosencrantz</span> and <span class="charname">Guildenstern</span>.</i>]
</p>

<p class="drama">
Come, Gertrude, we’ll call up our wisest friends,<br>
And let them know both what we mean to do<br>
And what’s untimely done, so haply slander,<br>
Whose whisper o’er the world’s diameter,<br>
As level as the cannon to his blank,<br>
Transports his poison’d shot, may miss our name,<br>
And hit the woundless air. O, come away!<br>
My soul is full of discord and dismay.<br>
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3><a id="sceneIV_8.2"></a> <b>SCENE II. Another room in
the Castle.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Hamlet</span>.
</p>

<p class="drama">
HAMLET.<br>
Safely stowed.<br>
</p>

<p class="drama">
ROSENCRANTZ and GUILDENSTERN.<br>
[<i>Within.</i>] Hamlet! Lord Hamlet!<br>
</p>

<p class="drama">
HAMLET.<br>
What noise? Who calls on Hamlet? O, here they come.<br>
</p>

<p class="scenedesc">
Enter <span class="charname">Rosencrantz</span> and <span class="charname">Guildenstern</span>.
</p>

<p class="drama">
ROSENCRANTZ.<br>
What have you done, my lord, with the dead body?<br>
</p>

<p class="drama">
HAMLET.<br>
Compounded it with dust, whereto ’tis kin.<br>
</p>

<p class="drama">
ROSENCRANTZ.<br>
Tell us where ’tis, that we may take it thence,<br>
And bear it to the chapel.<br>
</p>

<p class="drama">
HAMLET.<br>
Do not believe it.<br>
</p>

<p class="drama">
ROSENCRANTZ.<br>
Believe what?<br>
</p>

<p class="drama">
HAMLET.<br>
That I can keep your counsel, and not mine own. Besides, to be demanded of a
sponge—what replication should be made by the son of a king?
</p>

<p class="drama">
ROSENCRANTZ.<br>
Take you me for a sponge, my lord?<br>
</p>

<p class="drama">
HAMLET.<br>
Ay, sir; that soaks up the King’s countenance, his rewards, his authorities.
But such officers do the King best service in the end: he keeps them, like an
ape, in the corner of his jaw; first mouthed, to be last swallowed: when he
needs what you have gleaned, it is but squeezing you, and, sponge, you shall be
dry again.
</p>

<p class="drama">
ROSENCRANTZ.<br>
I understand you not, my lord.<br>
</p>

<p class="drama">
HAMLET.<br>
I am glad of it. A knavish speech sleeps in a foolish ear.<br>
</p>

<p class="drama">
ROSENCRANTZ.<br>
My lord, you must tell us where the body is and go with us to the King.
</p>

<p class="drama">
HAMLET.<br>
The body is with the King, but the King is not with the body. The King is a
thing—
</p>

<p class="drama">
GUILDENSTERN.<br>
A thing, my lord!<br>
</p>

<p class="drama">
HAMLET.<br>
Of nothing. Bring me to him. Hide fox, and all after.<br>
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3><a id="sceneIV_8.3"></a> <b>SCENE III. Another room in
the Castle.</b></h3>

<p class="scenedesc">
Enter <span class="charname">King,</span> attended.
</p>

<p class="drama">
KING.<br>
I have sent to seek him and to find the body.<br>
How dangerous is it that this man goes loose!<br>
Yet must not we put the strong law on him:<br>
He’s lov’d of the distracted multitude,<br>
Who like not in their judgement, but their eyes;<br>
And where ’tis so, th’offender’s scourge is weigh’d,<br>
But never the offence. To bear all smooth and even,<br>
This sudden sending him away must seem<br>
Deliberate pause. Diseases desperate grown<br>
By desperate appliance are reliev’d,<br>
Or not at all.<br>
</p>

<p class="scenedesc">
Enter <span class="charname">Rosencrantz</span>.
</p>

<p class="drama">
How now? What hath befall’n?
</p>

<p class="drama">
ROSENCRANTZ.<br>
Where the dead body is bestow’d, my lord,<br>
We cannot get from him.<br>
</p>

<p class="drama">
KING.<br>
But where is he?<br>
</p>

<p class="drama">
ROSENCRANTZ.<br>
Without, my lord, guarded, to know your pleasure.<br>
</p>

<p class="drama">
KING.<br>
Bring him before us.<br>
</p>

<p class="drama">
ROSENCRANTZ.<br>
Ho, Guildenstern! Bring in my lord.<br>
</p>

<p class="scenedesc">
Enter <span class="charname">Hamlet</span> and <span class="charname">Guildenstern</span>.
</p>

<p class="drama">
KING.<br>
Now, Hamlet, where’s Polonius?<br>
</p>

<p class="drama">
HAMLET.<br>
At supper.<br>
</p>

<p class="drama">
KING.<br>
At supper? Where?<br>
</p>

<p class="drama">
HAMLET.<br>
Not where he eats, but where he is eaten. A certain convocation of politic
worms are e’en at him. Your worm is your only emperor for diet. We fat all
creatures else to fat us, and we fat ourselves for maggots. Your fat king and
your lean beggar is but variable service,—two dishes, but to one table. That’s
the end.
</p>

<p class="drama">
KING.<br>
Alas, alas!<br>
</p>

<p class="drama">
HAMLET.<br>
A man may fish with the worm that hath eat of a king, and eat of the fish that
hath fed of that worm.
</p>

<p class="drama">
KING.<br>
What dost thou mean by this?<br>
</p>

<p class="drama">
HAMLET.<br>
Nothing but to show you how a king may go a progress through the guts of a
beggar.
</p>

<p class="drama">
KING.<br>
Where is Polonius?<br>
</p>

<p class="drama">
HAMLET.<br>
In heaven. Send thither to see. If your messenger find him not there, seek him
i’ th’other place yourself. But indeed, if you find him not within this month,
you shall nose him as you go up the stairs into the lobby.
</p>

<p class="drama">
KING.<br>
[<i>To some Attendants.</i>] Go seek him there.<br>
</p>

<p class="drama">
HAMLET.<br>
He will stay till you come.<br>
</p>

<p class="right">
[<i>Exeunt <span class="charname">Attendants</span>.</i>]
</p>

<p class="drama">
KING.<br>
Hamlet, this deed, for thine especial safety,—<br>
Which we do tender, as we dearly grieve<br>
For that which thou hast done,—must send thee hence<br>
With fiery quickness. Therefore prepare thyself;<br>
The bark is ready, and the wind at help,<br>
Th’associates tend, and everything is bent<br>
For England.<br>
</p>

<p class="drama">
HAMLET.<br>
For England?<br>
</p>

<p class="drama">
KING.<br>
Ay, Hamlet.<br>
</p>

<p class="drama">
HAMLET.<br>
Good.<br>
</p>

<p class="drama">
KING.<br>
So is it, if thou knew’st our purposes.<br>
</p>

<p class="drama">
HAMLET.<br>
I see a cherub that sees them. But, come; for England! Farewell, dear mother.
</p>

<p class="drama">
KING.<br>
Thy loving father, Hamlet.<br>
</p>

<p class="drama">
HAMLET.<br>
My mother. Father and mother is man and wife; man and wife is one flesh; and
so, my mother. Come, for England.
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="drama">
KING.<br>
Follow him at foot. Tempt him with speed aboard;<br>
Delay it not; I’ll have him hence tonight.<br>
Away, for everything is seal’d and done<br>
That else leans on th’affair. Pray you make haste.<br>
</p>

<p class="right">
[<i>Exeunt <span class="charname">Rosencrantz</span> and <span class="charname">Guildenstern</span>.</i>]
</p>

<p class="drama">
And England, if my love thou hold’st at aught,—<br>
As my great power thereof may give thee sense,<br>
Since yet thy cicatrice looks raw and red<br>
After the Danish sword, and thy free awe<br>
Pays homage to us,—thou mayst not coldly set<br>
Our sovereign process, which imports at full,<br>
By letters conjuring to that effect,<br>
The present death of Hamlet. Do it, England;<br>
For like the hectic in my blood he rages,<br>
And thou must cure me. Till I know ’tis done,<br>
Howe’er my haps, my joys were ne’er begun.<br>
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<h3><a id="sceneIV_8.4"></a> <b>SCENE IV. A plain in
Denmark.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Fortinbras</span> and <span class="charname">Forces</span> marching.
</p>

<p class="drama">
FORTINBRAS.<br>
Go, Captain, from me greet the Danish king.<br>
Tell him that by his license, Fortinbras<br>
Craves the conveyance of a promis’d march<br>
Over his kingdom. You know the rendezvous.<br>
If that his Majesty would aught with us,<br>
We shall express our duty in his eye;<br>
And let him know so.<br>
</p>

<p class="drama">
CAPTAIN.<br>
I will do’t, my lord.<br>
</p>

<p class="drama">
FORTINBRAS.<br>
Go softly on.<br>
</p>

<p class="right">
[<i>Exeunt all but the <span class="charname">Captain</span>.</i>]
</p>

<p class="scenedesc">
Enter <span class="charname">Hamlet, Rosencrantz, Guildenstern &amp;c</span>.
</p>

<p class="drama">
HAMLET.<br>
Good sir, whose powers are these?<br>
</p>

<p class="drama">
CAPTAIN.<br>
They are of Norway, sir.<br>
</p>

<p class="drama">
HAMLET.<br>
How purpos’d, sir, I pray you?<br>
</p>

<p class="drama">
CAPTAIN.<br>
Against some part of Poland.<br>
</p>

<p class="drama">
HAMLET.<br>
Who commands them, sir?<br>
</p>

<p class="drama">
CAPTAIN.<br>
The nephew to old Norway, Fortinbras.<br>
</p>

<p class="drama">
HAMLET.<br>
Goes it against the main of Poland, sir,<br>
Or for some frontier?<br>
</p>

<p class="drama">
CAPTAIN.<br>
Truly to speak, and with no addition,<br>
We go to gain a little patch of ground<br>
That hath in it no profit but the name.<br>
To pay five ducats, five, I would not farm it;<br>
Nor will it yield to Norway or the Pole<br>
A ranker rate, should it be sold in fee.<br>
</p>

<p class="drama">
HAMLET.<br>
Why, then the Polack never will defend it.<br>
</p>

<p class="drama">
CAPTAIN.<br>
Yes, it is already garrison’d.<br>
</p>

<p class="drama">
HAMLET.<br>
Two thousand souls and twenty thousand ducats<br>
Will not debate the question of this straw!<br>
This is th’imposthume of much wealth and peace,<br>
That inward breaks, and shows no cause without<br>
Why the man dies. I humbly thank you, sir.<br>
</p>

<p class="drama">
CAPTAIN.<br>
God b’ wi’ you, sir.<br>
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="drama">
ROSENCRANTZ.<br>
Will’t please you go, my lord?<br>
</p>

<p class="drama">
HAMLET.<br>
I’ll be with you straight. Go a little before.<br>
</p>

<p class="right">
[<i>Exeunt all but <span class="charname">Hamlet</span>.</i>]
</p>

<p class="drama">
How all occasions do inform against me,<br>
And spur my dull revenge. What is a man<br>
If his chief good and market of his time<br>
Be but to sleep and feed? A beast, no more.<br>
Sure he that made us with such large discourse,<br>
Looking before and after, gave us not<br>
That capability and godlike reason<br>
To fust in us unus’d. Now whether it be<br>
Bestial oblivion, or some craven scruple<br>
Of thinking too precisely on th’event,—<br>
A thought which, quarter’d, hath but one part wisdom<br>
And ever three parts coward,—I do not know<br>
Why yet I live to say this thing’s to do,<br>
Sith I have cause, and will, and strength, and means<br>
To do’t. Examples gross as earth exhort me,<br>
Witness this army of such mass and charge,<br>
Led by a delicate and tender prince,<br>
Whose spirit, with divine ambition puff’d,<br>
Makes mouths at the invisible event,<br>
Exposing what is mortal and unsure<br>
To all that fortune, death, and danger dare,<br>
Even for an eggshell. Rightly to be great<br>
Is not to stir without great argument,<br>
But greatly to find quarrel in a straw<br>
When honour’s at the stake. How stand I then,<br>
That have a father kill’d, a mother stain’d,<br>
Excitements of my reason and my blood,<br>
And let all sleep, while to my shame I see<br>
The imminent death of twenty thousand men<br>
That, for a fantasy and trick of fame,<br>
Go to their graves like beds, fight for a plot<br>
Whereon the numbers cannot try the cause,<br>
Which is not tomb enough and continent<br>
To hide the slain? O, from this time forth,<br>
My thoughts be bloody or be nothing worth.<br>
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<h3><a id="sceneIV_8.5"></a> <b>SCENE V. Elsinore. A room in
the Castle.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Queen, Horatio</span> and a <span class="charname">Gentleman</span>.
</p>

<p class="drama">
QUEEN.<br>
I will not speak with her.<br>
</p>

<p class="drama">
GENTLEMAN.<br>
She is importunate, indeed distract.<br>
Her mood will needs be pitied.<br>
</p>

<p class="drama">
QUEEN.<br>
What would she have?<br>
</p>

<p class="drama">
GENTLEMAN.<br>
She speaks much of her father; says she hears<br>
There’s tricks i’ th’ world, and hems, and beats her heart,<br>
Spurns enviously at straws, speaks things in doubt,<br>
That carry but half sense. Her speech is nothing,<br>
Yet the unshaped use of it doth move<br>
The hearers to collection; they aim at it,<br>
And botch the words up fit to their own thoughts,<br>
Which, as her winks, and nods, and gestures yield them,<br>
Indeed would make one think there might be thought,<br>
Though nothing sure, yet much unhappily.<br>
’Twere good she were spoken with, for she may strew<br>
Dangerous conjectures in ill-breeding minds.<br>
</p>

<p class="drama">
QUEEN.<br>
Let her come in.<br>
</p>

<p class="right">
[<i>Exit <span class="charname">Gentleman</span>.</i>]
</p>

<p class="drama">
To my sick soul, as sin’s true nature is,<br>
Each toy seems prologue to some great amiss.<br>
So full of artless jealousy is guilt,<br>
It spills itself in fearing to be spilt.<br>
</p>

<p class="scenedesc">
Enter <span class="charname">Ophelia</span>.
</p>

<p class="drama">
OPHELIA.<br>
Where is the beauteous Majesty of Denmark?<br>
</p>

<p class="drama">
QUEEN.<br>
How now, Ophelia?<br>
</p>

<p class="drama">
OPHELIA.<br>
[<i>Sings.</i>]<br>
   How should I your true love know<br>
     From another one?<br>
   By his cockle hat and staff<br>
     And his sandal shoon.<br>
</p>

<p class="drama">
QUEEN.<br>
Alas, sweet lady, what imports this song?<br>
</p>

<p class="drama">
OPHELIA.<br>
Say you? Nay, pray you mark.<br>
[<i>Sings.</i>]<br>
   He is dead and gone, lady,<br>
     He is dead and gone,<br>
   At his head a grass green turf,<br>
     At his heels a stone.<br>
</p>

<p class="drama">
QUEEN.<br>
Nay, but Ophelia—<br>
</p>

<p class="drama">
OPHELIA.<br>
Pray you mark.<br>
[<i>Sings.</i>]<br>
   White his shroud as the mountain snow.<br>
</p>

<p class="scenedesc">
Enter <span class="charname">King</span>.
</p>

<p class="drama">
QUEEN.<br>
Alas, look here, my lord!<br>
</p>

<p class="drama">
OPHELIA.<br>
[<i>Sings.</i>]<br>
     Larded all with sweet flowers;<br>
   Which bewept to the grave did not go<br>
     With true-love showers.<br>
</p>

<p class="drama">
KING.<br>
How do you, pretty lady?<br>
</p>

<p class="drama">
OPHELIA.<br>
Well, God dild you! They say the owl was a baker’s daughter. Lord, we know what
we are, but know not what we may be. God be at your table!
</p>

<p class="drama">
KING.<br>
Conceit upon her father.<br>
</p>

<p class="drama">
OPHELIA.<br>
Pray you, let’s have no words of this; but when they ask you what it means, say
you this:<br>
[<i>Sings.</i>]<br>
   Tomorrow is Saint Valentine’s day,<br>
     All in the morning betime,<br>
   And I a maid at your window,<br>
     To be your Valentine.<br>
</p>

<p class="drama">
   Then up he rose and donn’d his clothes,<br>
     And dupp’d the chamber door,<br>
   Let in the maid, that out a maid<br>
     Never departed more.<br>
</p>

<p class="drama">
KING.<br>
Pretty Ophelia!<br>
</p>

<p class="drama">
OPHELIA.<br>
Indeed la, without an oath, I’ll make an end on’t.<br>
[<i>Sings.</i>]<br>
   By Gis and by Saint Charity,<br>
     Alack, and fie for shame!<br>
   Young men will do’t if they come to’t;<br>
     By Cock, they are to blame.<br>
</p>

<p class="drama">
   Quoth she, before you tumbled me,<br>
     You promis’d me to wed.<br>
   So would I ha’ done, by yonder sun,<br>
     An thou hadst not come to my bed.<br>
</p>

<p class="drama">
KING.<br>
How long hath she been thus?<br>
</p>

<p class="drama">
OPHELIA.<br>
I hope all will be well. We must be patient. But I cannot choose but weep, to
think they would lay him i’ th’ cold ground. My brother shall know of it. And
so I thank you for your good counsel. Come, my coach! Good night, ladies; good
night, sweet ladies; good night, good night.
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="drama">
KING.<br>
Follow her close; give her good watch, I pray you.<br>
</p>

<p class="right">
[<i>Exit <span class="charname">Horatio</span>.</i>]
</p>

<p class="drama">
O, this is the poison of deep grief; it springs<br>
All from her father’s death. O Gertrude, Gertrude,<br>
When sorrows come, they come not single spies,<br>
But in battalions. First, her father slain;<br>
Next, your son gone; and he most violent author<br>
Of his own just remove; the people muddied,<br>
Thick, and unwholesome in their thoughts and whispers<br>
For good Polonius’ death; and we have done but greenly<br>
In hugger-mugger to inter him. Poor Ophelia<br>
Divided from herself and her fair judgement,<br>
Without the which we are pictures or mere beasts.<br>
Last, and as much containing as all these,<br>
Her brother is in secret come from France,<br>
Feeds on his wonder, keeps himself in clouds,<br>
And wants not buzzers to infect his ear<br>
With pestilent speeches of his father’s death,<br>
Wherein necessity, of matter beggar’d,<br>
Will nothing stick our person to arraign<br>
In ear and ear. O my dear Gertrude, this,<br>
Like to a murdering piece, in many places<br>
Gives me superfluous death.<br>
</p>

<p class="right">
[<i>A noise within.</i>]
</p>

<p class="drama">
QUEEN.<br>
Alack, what noise is this?<br>
</p>

<p class="drama">
KING.<br>
Where are my Switzers? Let them guard the door.
</p>

<p class="scenedesc">
Enter a <span class="charname">Gentleman</span>.
</p>

<p class="drama">
What is the matter?
</p>

<p class="drama">
GENTLEMAN.<br>
Save yourself, my lord.<br>
The ocean, overpeering of his list,<br>
Eats not the flats with more impetuous haste<br>
Than young Laertes, in a riotous head,<br>
O’erbears your offices. The rabble call him lord,<br>
And, as the world were now but to begin,<br>
Antiquity forgot, custom not known,<br>
The ratifiers and props of every word,<br>
They cry ‘Choose we! Laertes shall be king!’<br>
Caps, hands, and tongues applaud it to the clouds,<br>
‘Laertes shall be king, Laertes king.’<br>
</p>

<p class="drama">
QUEEN.<br>
How cheerfully on the false trail they cry.<br>
O, this is counter, you false Danish dogs.<br>
</p>

<p class="right">
[<i>A noise within.</i>]
</p>

<p class="drama">
KING.<br>
The doors are broke.<br>
</p>

<p class="scenedesc">
Enter <span class="charname">Laertes,</span> armed; <span class="charname">Danes</span> following.
</p>

<p class="drama">
LAERTES.<br>
Where is this king?—Sirs, stand you all without.<br>
</p>

<p class="drama">
Danes.<br>
No, let’s come in.<br>
</p>

<p class="drama">
LAERTES.<br>
I pray you, give me leave.<br>
</p>

<p class="drama">
DANES.<br>
We will, we will.<br>
</p>

<p class="right">
[<i>They retire without the door.</i>]
</p>

<p class="drama">
LAERTES.<br>
I thank you. Keep the door. O thou vile king,<br>
Give me my father.<br>
</p>

<p class="drama">
QUEEN.<br>
Calmly, good Laertes.<br>
</p>

<p class="drama">
LAERTES.<br>
That drop of blood that’s calm proclaims me bastard;<br>
Cries cuckold to my father, brands the harlot<br>
Even here between the chaste unsmirched brow<br>
Of my true mother.<br>
</p>

<p class="drama">
KING.<br>
What is the cause, Laertes,<br>
That thy rebellion looks so giant-like?—<br>
Let him go, Gertrude. Do not fear our person.<br>
There’s such divinity doth hedge a king,<br>
That treason can but peep to what it would,<br>
Acts little of his will.—Tell me, Laertes,<br>
Why thou art thus incens’d.—Let him go, Gertrude:—<br>
Speak, man.<br>
</p>

<p class="drama">
LAERTES.<br>
Where is my father?<br>
</p>

<p class="drama">
KING.<br>
Dead.<br>
</p>

<p class="drama">
QUEEN.<br>
But not by him.<br>
</p>

<p class="drama">
KING.<br>
Let him demand his fill.<br>
</p>

<p class="drama">
LAERTES.<br>
How came he dead? I’ll not be juggled with.<br>
To hell, allegiance! Vows, to the blackest devil!<br>
Conscience and grace, to the profoundest pit!<br>
I dare damnation. To this point I stand,<br>
That both the worlds, I give to negligence,<br>
Let come what comes; only I’ll be reveng’d<br>
Most throughly for my father.<br>
</p>

<p class="drama">
KING.<br>
Who shall stay you?<br>
</p>

<p class="drama">
LAERTES.<br>
My will, not all the world.<br>
And for my means, I’ll husband them so well,<br>
They shall go far with little.<br>
</p>

<p class="drama">
KING.<br>
Good Laertes,<br>
If you desire to know the certainty<br>
Of your dear father’s death, is’t writ in your revenge<br>
That, sweepstake, you will draw both friend and foe,<br>
Winner and loser?<br>
</p>

<p class="drama">
LAERTES.<br>
None but his enemies.<br>
</p>

<p class="drama">
KING.<br>
Will you know them then?<br>
</p>

<p class="drama">
LAERTES.<br>
To his good friends thus wide I’ll ope my arms;<br>
And, like the kind life-rendering pelican,<br>
Repast them with my blood.<br>
</p>

<p class="drama">
KING.<br>
Why, now you speak<br>
Like a good child and a true gentleman.<br>
That I am guiltless of your father’s death,<br>
And am most sensibly in grief for it,<br>
It shall as level to your judgement ’pear<br>
As day does to your eye.<br>
</p>

<p class="drama">
DANES.<br>
[<i>Within.</i>] Let her come in.<br>
</p>

<p class="drama">
LAERTES.<br>
How now! What noise is that?<br>
</p>

<p class="scenedesc">
Re-enter <span class="charname">Ophelia,</span> fantastically dressed with
straws and flowers.
</p>

<p class="drama">
O heat, dry up my brains. Tears seven times salt,<br>
Burn out the sense and virtue of mine eye.<br>
By heaven, thy madness shall be paid by weight,<br>
Till our scale turn the beam. O rose of May!<br>
Dear maid, kind sister, sweet Ophelia!<br>
O heavens, is’t possible a young maid’s wits<br>
Should be as mortal as an old man’s life?<br>
Nature is fine in love, and where ’tis fine,<br>
It sends some precious instance of itself<br>
After the thing it loves.<br>
</p>

<p class="drama">
OPHELIA.<br>
[<i>Sings.</i>]<br>
   They bore him barefac’d on the bier,<br>
   Hey non nonny, nonny, hey nonny<br>
   And on his grave rain’d many a tear.—<br>
   Fare you well, my dove!
</p>

<p class="drama">
LAERTES.<br>
Hadst thou thy wits, and didst persuade revenge,<br>
It could not move thus.<br>
</p>

<p class="drama">
OPHELIA.<br>
You must sing ‘Down a-down, and you call him a-down-a.’ O, how the wheel
becomes it! It is the false steward that stole his master’s daughter.
</p>

<p class="drama">
LAERTES.<br>
This nothing’s more than matter.<br>
</p>

<p class="drama">
OPHELIA.<br>
There’s rosemary, that’s for remembrance; pray love, remember. And there is
pansies, that’s for thoughts.
</p>

<p class="drama">
LAERTES.<br>
A document in madness, thoughts and remembrance fitted.<br>
</p>

<p class="drama">
OPHELIA.<br>
There’s fennel for you, and columbines. There’s rue for you; and here’s some
for me. We may call it herb of grace o’ Sundays. O you must wear your rue with
a difference. There’s a daisy. I would give you some violets, but they wither’d
all when my father died. They say he made a good end.<br>
[<i>Sings.</i>]<br>
   For bonny sweet Robin is all my joy.
</p>

<p class="drama">
LAERTES.<br>
Thought and affliction, passion, hell itself<br>
She turns to favour and to prettiness.<br>
</p>

<p class="drama">
OPHELIA.<br>
[<i>Sings.</i>]<br>
   And will he not come again?<br>
   And will he not come again?<br>
     No, no, he is dead,<br>
     Go to thy death-bed,<br>
   He never will come again.<br>
</p>

<p class="drama">
   His beard was as white as snow,<br>
   All flaxen was his poll.<br>
     He is gone, he is gone,<br>
     And we cast away moan.<br>
   God ha’ mercy on his soul.<br>
</p>

<p class="drama">
And of all Christian souls, I pray God. God b’ wi’ ye.
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="drama">
LAERTES.<br>
Do you see this, O God?<br>
</p>

<p class="drama">
KING.<br>
Laertes, I must commune with your grief,<br>
Or you deny me right. Go but apart,<br>
Make choice of whom your wisest friends you will,<br>
And they shall hear and judge ’twixt you and me.<br>
If by direct or by collateral hand<br>
They find us touch’d, we will our kingdom give,<br>
Our crown, our life, and all that we call ours<br>
To you in satisfaction; but if not,<br>
Be you content to lend your patience to us,<br>
And we shall jointly labour with your soul<br>
To give it due content.<br>
</p>

<p class="drama">
LAERTES.<br>
Let this be so;<br>
His means of death, his obscure burial,—<br>
No trophy, sword, nor hatchment o’er his bones,<br>
No noble rite, nor formal ostentation,—<br>
Cry to be heard, as ’twere from heaven to earth,<br>
That I must call’t in question.<br>
</p>

<p class="drama">
KING.<br>
So you shall.<br>
And where th’offence is let the great axe fall.<br>
I pray you go with me.<br>
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3><a id="sceneIV_8.6"></a> <b>SCENE VI. Another room in
the Castle.</b></h3>

<p class="scenedesc">
Enter <span class="charname">Horatio</span> and a <span class="charname">Servant</span>.
</p>

<p class="drama">
HORATIO.<br>
What are they that would speak with me?<br>
</p>

<p class="drama">
SERVANT.<br>
Sailors, sir. They say they have letters for you.<br>
</p>

<p class="drama">
HORATIO.<br>
Let them come in.<br>
</p>

<p class="right">
[<i>Exit <span class="charname">Servant</span>.</i>]
</p>

<p class="drama">
I do not know from what part of the world<br>
I should be greeted, if not from Lord Hamlet.<br>
</p>

<p class="scenedesc">
Enter <span class="charname">Sailors</span>.
</p>

<p class="drama">
FIRST SAILOR.<br>
God bless you, sir.<br>
</p>

<p class="drama">
HORATIO.<br>
Let him bless thee too.<br>
</p>

<p class="drama">
FIRST SAILOR.<br>
He shall, sir, and’t please him. There’s a letter for you, sir. It comes from
th’ambassador that was bound for England; if your name be Horatio, as I am let
to know it is.
</p>

<p class="drama">
HORATIO.<br>
[<i>Reads.</i>] ‘Horatio, when thou shalt have overlooked this, give these
fellows some means to the King. They have letters for him. Ere we were two days
old at sea, a pirate of very warlike appointment gave us chase. Finding
ourselves too slow of sail, we put on a compelled valour, and in the grapple I
boarded them. On the instant they got clear of our ship, so I alone became
their prisoner. They have dealt with me like thieves of mercy. But they knew
what they did; I am to do a good turn for them. Let the King have the letters I
have sent, and repair thou to me with as much haste as thou wouldst fly death.
I have words to speak in thine ear will make thee dumb; yet are they much too
light for the bore of the matter. These good fellows will bring thee where I
am. Rosencrantz and Guildenstern hold their course for England: of them I have
much to tell thee. Farewell.<br>
     He that thou knowest thine,<br>
     HAMLET.’
</p>

<p class="drama">
Come, I will give you way for these your letters,<br>
And do’t the speedier, that you may direct me<br>
To him from whom you brought them.<br>
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

<h3><a id="sceneIV_8.7"></a> <b>SCENE VII. Another room in
the Castle.</b></h3>

<p class="scenedesc">
Enter <span class="charname">King</span> and <span class="charname">Laertes</span>.
</p>

<p class="drama">
KING.<br>
Now must your conscience my acquittance seal,<br>
And you must put me in your heart for friend,<br>
Sith you have heard, and with a knowing ear,<br>
That he which hath your noble father slain<br>
Pursu’d my life.<br>
</p>

<p class="drama">
LAERTES.<br>
It well appears. But tell me<br>
Why you proceeded not against these feats,<br>
So crimeful and so capital in nature,<br>
As by your safety, wisdom, all things else,<br>
You mainly were stirr’d up.<br>
</p>

<p class="drama">
KING.<br>
O, for two special reasons,<br>
Which may to you, perhaps, seem much unsinew’d,<br>
But yet to me they are strong. The Queen his mother<br>
Lives almost by his looks; and for myself,—<br>
My virtue or my plague, be it either which,—<br>
She’s so conjunctive to my life and soul,<br>
That, as the star moves not but in his sphere,<br>
I could not but by her. The other motive,<br>
Why to a public count I might not go,<br>
Is the great love the general gender bear him,<br>
Who, dipping all his faults in their affection,<br>
Would like the spring that turneth wood to stone,<br>
Convert his gyves to graces; so that my arrows,<br>
Too slightly timber’d for so loud a wind,<br>
Would have reverted to my bow again,<br>
And not where I had aim’d them.<br>
</p>

<p class="drama">
LAERTES.<br>
And so have I a noble father lost,<br>
A sister driven into desperate terms,<br>
Whose worth, if praises may go back again,<br>
Stood challenger on mount of all the age<br>
For her perfections. But my revenge will come.<br>
</p>

<p class="drama">
KING.<br>
Break not your sleeps for that. You must not think<br>
That we are made of stuff so flat and dull<br>
That we can let our beard be shook with danger,<br>
And think it pastime. You shortly shall hear more.<br>
I lov’d your father, and we love ourself,<br>
And that, I hope, will teach you to imagine—<br>
</p>

<p class="scenedesc">
Enter a <span class="charname">Messenger</span>.
</p>

<p class="drama">
How now? What news?
</p>

<p class="drama">
MESSENGER.<br>
Letters, my lord, from Hamlet.<br>
This to your Majesty; this to the Queen.<br>
</p>

<p class="drama">
KING.<br>
From Hamlet! Who brought them?<br>
</p>

<p class="drama">
MESSENGER.<br>
Sailors, my lord, they say; I saw them not.<br>
They were given me by Claudio. He receiv’d them<br>
Of him that brought them.<br>
</p>

<p class="drama">
KING.<br>
Laertes, you shall hear them.<br>
Leave us.<br>
</p>

<p class="right">
[<i>Exit <span class="charname">Messenger</span>.</i>]
</p>

<p class="drama">
[<i>Reads.</i>] ‘High and mighty, you shall know I am set naked on your
kingdom. Tomorrow shall I beg leave to see your kingly eyes. When I shall,
first asking your pardon thereunto, recount the occasions of my sudden and more
strange return.<br>
     HAMLET.’
</p>

<p class="drama">
What should this mean? Are all the rest come back?<br>
Or is it some abuse, and no such thing?<br>
</p>

<p class="drama">
LAERTES.<br>
Know you the hand?<br>
</p>

<p class="drama">
KING.<br>
’Tis Hamlet’s character. ‘Naked!’<br>
And in a postscript here he says ‘alone.’<br>
Can you advise me?<br>
</p>

<p class="drama">
LAERTES.<br>
I am lost in it, my lord. But let him come,<br>
It warms the very sickness in my heart<br>
That I shall live and tell him to his teeth,<br>
‘Thus diest thou.’<br>
</p>

<p class="drama">
KING.<br>
If it be so, Laertes,—<br>
As how should it be so? How otherwise?—<br>
Will you be rul’d by me?<br>
</p>

<p class="drama">
LAERTES.<br>
Ay, my lord;<br>
So you will not o’errule me to a peace.<br>
</p>

<p class="drama">
KING.<br>
To thine own peace. If he be now return’d,<br>
As checking at his voyage, and that he means<br>
No more to undertake it, I will work him<br>
To an exploit, now ripe in my device,<br>
Under the which he shall not choose but fall;<br>
And for his death no wind shall breathe,<br>
But even his mother shall uncharge the practice<br>
And call it accident.<br>
</p>

<p class="drama">
LAERTES.<br>
My lord, I will be rul’d;<br>
The rather if you could devise it so<br>
That I might be the organ.<br>
</p>

<p class="drama">
KING.<br>
It falls right.<br>
You have been talk’d of since your travel much,<br>
And that in Hamlet’s hearing, for a quality<br>
Wherein they say you shine. Your sum of parts<br>
Did not together pluck such envy from him<br>
As did that one, and that, in my regard,<br>
Of the unworthiest siege.<br>
</p>

<p class="drama">
LAERTES.<br>
What part is that, my lord?<br>
</p>

<p class="drama">
KING.<br>
A very riband in the cap of youth,<br>
Yet needful too, for youth no less becomes<br>
The light and careless livery that it wears<br>
Than settled age his sables and his weeds,<br>
Importing health and graveness. Two months since<br>
Here was a gentleman of Normandy,—<br>
I’ve seen myself, and serv’d against, the French,<br>
And they can well on horseback, but this gallant<br>
Had witchcraft in’t. He grew unto his seat,<br>
And to such wondrous doing brought his horse,<br>
As had he been incorps’d and demi-natur’d<br>
With the brave beast. So far he topp’d my thought<br>
That I in forgery of shapes and tricks,<br>
Come short of what he did.<br>
</p>

<p class="drama">
LAERTES.<br>
A Norman was’t?<br>
</p>

<p class="drama">
KING.<br>
A Norman.<br>
</p>

<p class="drama">
LAERTES.<br>
Upon my life, Lamord.<br>
</p>

<p class="drama">
KING.<br>
The very same.<br>
</p>

<p class="drama">
LAERTES.<br>
I know him well. He is the brooch indeed<br>
And gem of all the nation.<br>
</p>

<p class="drama">
KING.<br>
He made confession of you,<br>
And gave you such a masterly report<br>
For art and exercise in your defence,<br>
And for your rapier most especially,<br>
That he cried out ’twould be a sight indeed<br>
If one could match you. The scrimers of their nation<br>
He swore had neither motion, guard, nor eye,<br>
If you oppos’d them. Sir, this report of his<br>
Did Hamlet so envenom with his envy<br>
That he could nothing do but wish and beg<br>
Your sudden coming o’er to play with him.<br>
Now, out of this,—<br>
</p>

<p class="drama">
LAERTES.<br>
What out of this, my lord?<br>
</p>

<p class="drama">
KING.<br>
Laertes, was your father dear to you?<br>
Or are you like the painting of a sorrow,<br>
A face without a heart?<br>
</p>

<p class="drama">
LAERTES.<br>
Why ask you this?<br>
</p>

<p class="drama">
KING.<br>
Not that I think you did not love your father,<br>
But that I know love is begun by time,<br>
And that I see, in passages of proof,<br>
Time qualifies the spark and fire of it.<br>
There lives within the very flame of love<br>
A kind of wick or snuff that will abate it;<br>
And nothing is at a like goodness still,<br>
For goodness, growing to a pleurisy,<br>
Dies in his own too much. That we would do,<br>
We should do when we would; for this ‘would’ changes,<br>
And hath abatements and delays as many<br>
As there are tongues, are hands, are accidents;<br>
And then this ‘should’ is like a spendthrift sigh<br>
That hurts by easing. But to the quick o’ th’ulcer:<br>
Hamlet comes back: what would you undertake<br>
To show yourself your father’s son in deed,<br>
More than in words?<br>
</p>

<p class="drama">
LAERTES.<br>
To cut his throat i’ th’ church.<br>
</p>

<p class="drama">
KING.<br>
No place, indeed, should murder sanctuarize;<br>
Revenge should have no bounds. But good Laertes,<br>
Will you do this, keep close within your chamber.<br>
Hamlet return’d shall know you are come home:<br>
We’ll put on those shall praise your excellence,<br>
And set a double varnish on the fame<br>
The Frenchman gave you, bring you in fine together<br>
And wager on your heads. He, being remiss,<br>
Most generous, and free from all contriving,<br>
Will not peruse the foils; so that with ease,<br>
Or with a little shuffling, you may choose<br>
A sword unbated, and in a pass of practice,<br>
Requite him for your father.<br>
</p>

<p class="drama">
LAERTES.<br>
I will do’t.<br>
And for that purpose I’ll anoint my sword.<br>
I bought an unction of a mountebank<br>
So mortal that, but dip a knife in it,<br>
Where it draws blood no cataplasm so rare,<br>
Collected from all simples that have virtue<br>
Under the moon, can save the thing from death<br>
This is but scratch’d withal. I’ll touch my point<br>
With this contagion, that if I gall him slightly,<br>
It may be death.<br>
</p>

<p class="drama">
KING.<br>
Let’s further think of this,<br>
Weigh what convenience both of time and means<br>
May fit us to our shape. If this should fail,<br>
And that our drift look through our bad performance.<br>
’Twere better not assay’d. Therefore this project<br>
Should have a back or second, that might hold<br>
If this did blast in proof. Soft, let me see.<br>
We’ll make a solemn wager on your cunnings,—<br>
I ha’t! When in your motion you are hot and dry,<br>
As make your bouts more violent to that end,<br>
And that he calls for drink, I’ll have prepar’d him<br>
A chalice for the nonce; whereon but sipping,<br>
If he by chance escape your venom’d stuck,<br>
Our purpose may hold there.<br>
</p>

<p class="scenedesc">
Enter <span class="charname">Queen</span>.
</p>

<p class="drama">
How now, sweet Queen?
</p>

<p class="drama">
QUEEN.<br>
One woe doth tread upon another’s heel,<br>
So fast they follow. Your sister’s drown’d, Laertes.<br>
</p>

<p class="drama">
LAERTES.<br>
Drown’d! O, where?<br>
</p>

<p class="drama">
QUEEN.<br>
There is a willow grows aslant a brook,<br>
That shows his hoary leaves in the glassy stream.<br>
There with fantastic garlands did she make<br>
Of crow-flowers, nettles, daisies, and long purples,<br>
That liberal shepherds give a grosser name,<br>
But our cold maids do dead men’s fingers call them.<br>
There on the pendant boughs her coronet weeds<br>
Clamb’ring to hang, an envious sliver broke,<br>
When down her weedy trophies and herself<br>
Fell in the weeping brook. Her clothes spread wide,<br>
And mermaid-like, awhile they bore her up,<br>
Which time she chaunted snatches of old tunes,<br>
As one incapable of her own distress,<br>
Or like a creature native and indued<br>
Unto that element. But long it could not be<br>
Till that her garments, heavy with their drink,<br>
Pull’d the poor wretch from her melodious lay<br>
To muddy death.<br>
</p>

<p class="drama">
LAERTES.<br>
Alas, then she is drown’d?<br>
</p>

<p class="drama">
QUEEN.<br>
Drown’d, drown’d.<br>
</p>

<p class="drama">
LAERTES.<br>
Too much of water hast thou, poor Ophelia,<br>
And therefore I forbid my tears. But yet<br>
It is our trick; nature her custom holds,<br>
Let shame say what it will. When these are gone,<br>
The woman will be out. Adieu, my lord,<br>
I have a speech of fire, that fain would blaze,<br>
But that this folly douts it.<br>
</p>

<p class="right">
[<i>Exit.</i>]
</p>

<p class="drama">
KING.<br>
Let’s follow, Gertrude;<br>
How much I had to do to calm his rage!<br>
Now fear I this will give it start again;<br>
Therefore let’s follow.<br>
</p>

<p class="right">
[<i>Exeunt.</i>]
</p>

