<h2> <a id="sceneIV_6.1"></a><b>ACT IV</b></h2>

<h3> <b>SCENE I. Rome. Before a gate of the city</b></h3>

<p class="scenedesc">
Enter <span class="charname">Coriolanus, Volumnia, Virgilia, Menenius,
Cominius</span> with the young nobility of Rome.
</p>

<p class="drama">
CORIOLANUS.<br>
Come, leave your tears. A brief farewell. The beast<br>
With many heads butts me away. Nay, mother,<br>
Where is your ancient courage? You were used<br>
To say extremities was the trier of spirits;<br>
That common chances common men could bear;<br>
That when the sea was calm, all boats alike<br>
Showed mastership in floating; fortune’s blows<br>
When most struck home, being gentle wounded craves<br>
A noble cunning. You were used to load me<br>
With precepts that would make invincible<br>
The heart that conned them.
</p>

<p class="drama">
VIRGILIA.<br>
O heavens! O heavens!
</p>

<p class="drama">
CORIOLANUS.<br>
Nay, I prithee, woman—
</p>

<p class="drama">
VOLUMNIA.<br>
Now the red pestilence strike all trades in Rome,<br>
And occupations perish!
</p>

<p class="drama">
CORIOLANUS.<br>
What, what, what!<br>
I shall be loved when I am lacked. Nay, mother,<br>
Resume that spirit when you were wont to say<br>
If you had been the wife of Hercules,<br>
Six of his labours you’d have done and saved<br>
Your husband so much sweat.—Cominius,<br>
Droop not. Adieu.—Farewell, my wife, my mother.<br>
I’ll do well yet.—Thou old and true Menenius,<br>
Thy tears are salter than a younger man’s<br>
And venomous to thine eyes.—My sometime general,<br>
I have seen thee stern, and thou hast oft beheld<br>
Heart-hard’ning spectacles. Tell these sad women<br>
’Tis fond to wail inevitable strokes<br>
As ’tis to laugh at ’em.—My mother, you wot well<br>
My hazards still have been your solace, and—<br>
Believe’t not lightly—though I go alone,<br>
Like to a lonely dragon that his fen<br>
Makes feared and talked of more than seen, your son<br>
Will or exceed the common or be caught<br>
With cautelous baits and practice.
</p>

<p class="drama">
VOLUMNIA.<br>
My first son,<br>
Whither wilt thou go? Take good Cominius<br>
With thee awhile. Determine on some course<br>
More than a wild exposture to each chance<br>
That starts i’ th’ way before thee.
</p>

<p class="drama">
VIRGILIA.<br>
O the gods!
</p>

<p class="drama">
COMINIUS.<br>
I’ll follow thee a month, devise with thee<br>
Where thou shalt rest, that thou mayst hear of us<br>
And we of thee; so if the time thrust forth<br>
A cause for thy repeal, we shall not send<br>
O’er the vast world to seek a single man<br>
And lose advantage, which doth ever cool<br>
I’ th’ absence of the needer.
</p>

<p class="drama">
CORIOLANUS.<br>
Fare ye well.<br>
Thou hast years upon thee, and thou art too full<br>
Of the wars’ surfeits to go rove with one<br>
That’s yet unbruised. Bring me but out at gate.—<br>
Come, my sweet wife, my dearest mother, and<br>
My friends of noble touch. When I am forth,<br>
Bid me farewell, and smile. I pray you, come.<br>
While I remain above the ground, you shall<br>
Hear from me still, and never of me aught<br>
But what is like me formerly.
</p>

<p class="drama">
MENENIUS.<br>
That’s worthily<br>
As any ear can hear. Come, let’s not weep.<br>
If I could shake off but one seven years<br>
From these old arms and legs, by the good gods,<br>
I’d with thee every foot.
</p>

<p class="drama">
CORIOLANUS.<br>
Give me thy hand.<br>
Come.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneIV_6.2"></a><b>SCENE II. Rome. A street near the gate</b></h3>

<p class="scenedesc">
Enter two Tribunes, <span class="charname">Sicinius, Brutus</span> with the
<span class="charname">Aedile</span>.
</p>

<p class="drama">
SICINIUS.<br>
Bid them all home. He’s gone, and we’ll no further.<br>
The nobility are vexed, whom we see have sided<br>
In his behalf.
</p>

<p class="drama">
BRUTUS.<br>
Now we have shown our power,<br>
Let us seem humbler after it is done<br>
Than when it was a-doing.
</p>

<p class="drama">
SICINIUS.<br>
Bid them home.<br>
Say their great enemy is gone, and they<br>
Stand in their ancient strength.
</p>

<p class="drama">
BRUTUS.<br>
Dismiss them home.
</p>

<p class="right">[<i>Exit <span class="charname">Aedile</span>.</i>]</p>

<p class="drama">
Here comes his mother.
</p>

<p class="scenedesc">
Enter <span class="charname">Volumnia, Virgilia</span> and
<span class="charname">Menenius</span>.
</p>

<p class="drama">
SICINIUS.<br>
Let’s not meet her.
</p>

<p class="drama">
BRUTUS.<br>
Why?
</p>

<p class="drama">
SICINIUS.<br>
They say she’s mad.
</p>

<p class="drama">
BRUTUS.<br>
They have ta’en note of us. Keep on your way.
</p>

<p class="drama">
VOLUMNIA.<br>
O, you’re well met. The hoarded plague o’ th’ gods<br>
Requite your love!
</p>

<p class="drama">
MENENIUS.<br>
Peace, peace! Be not so loud.
</p>

<p class="drama">
VOLUMNIA.<br>
If that I could for weeping, you should hear—<br>
Nay, and you shall hear some. [<i>To Sicinius</i>.] Will you be gone?
</p>

<p class="drama">
VIRGILIA.<br>
[<i>To Brutus</i>.] You shall stay too. I would I had the power<br>
To say so to my husband.
</p>

<p class="drama">
SICINIUS.<br>
Are you mankind?
</p>

<p class="drama">
VOLUMNIA.<br>
Ay, fool, is that a shame? Note but this, fool.<br>
Was not a man my father? Hadst thou foxship<br>
To banish him that struck more blows for Rome<br>
Than thou hast spoken words?
</p>

<p class="drama">
SICINIUS.<br>
O blessed heavens!
</p>

<p class="drama">
VOLUMNIA.<br>
More noble blows than ever thou wise words,<br>
And for Rome’s good. I’ll tell thee what—yet go.<br>
Nay, but thou shalt stay too. I would my son<br>
Were in Arabia and thy tribe before him,<br>
His good sword in his hand.
</p>

<p class="drama">
SICINIUS.<br>
What then?
</p>

<p class="drama">
VIRGILIA.<br>
What then?<br>
He’d make an end of thy posterity.
</p>

<p class="drama">
VOLUMNIA.<br>
Bastards and all.<br>
Good man, the wounds that he does bear for Rome!
</p>

<p class="drama">
MENENIUS.<br>
Come, come, peace.
</p>

<p class="drama">
SICINIUS.<br>
I would he had continued to his country<br>
As he began, and not unknit himself<br>
The noble knot he made.
</p>

<p class="drama">
BRUTUS.<br>
I would he had.
</p>

<p class="drama">
VOLUMNIA.<br>
“I would he had?” ’Twas you incensed the rabble.<br>
Cats, that can judge as fitly of his worth<br>
As I can of those mysteries which heaven<br>
Will not have Earth to know.
</p>

<p class="drama">
BRUTUS.<br>
Pray, let’s go.
</p>

<p class="drama">
VOLUMNIA.<br>
Now, pray, sir, get you gone.<br>
You have done a brave deed. Ere you go, hear this:<br>
As far as doth the Capitol exceed<br>
The meanest house in Rome, so far my son—<br>
This lady’s husband here, this, do you see?—<br>
Whom you have banished, does exceed you all.
</p>

<p class="drama">
BRUTUS.<br>
Well, well, we’ll leave you.
</p>

<p class="drama">
SICINIUS.<br>
Why stay we to be baited<br>
With one that wants her wits?
</p>

<p class="right">[<i>Exeunt <span class="charname">Tribunes</span>.</i>]</p>

<p class="drama">
VOLUMNIA.<br>
Take my prayers with you.<br>
I would the gods had nothing else to do<br>
But to confirm my curses. Could I meet ’em<br>
But once a day, it would unclog my heart<br>
Of what lies heavy to’t.
</p>

<p class="drama">
MENENIUS.<br>
You have told them home,<br>
And, by my troth, you have cause. You’ll sup with me?
</p>

<p class="drama">
VOLUMNIA.<br>
Anger’s my meat. I sup upon myself<br>
And so shall starve with feeding. Come, let’s go.<br>
Leave this faint puling, and lament as I do,<br>
In anger, Juno-like. Come, come, come.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<p class="drama">
MENENIUS.<br>
Fie, fie, fie!
</p>

<p class="right">[<i>Exit <span class="charname">Menenius</span>.</i>]</p>

<h3> <a id="sceneIV_6.3"></a><b>SCENE III. A highway between Rome and Antium</b></h3>

<p class="scenedesc">
Enter a <span class="charname">Roman</span> and a
<span class="charname">Volsce</span>.
</p>

<p class="drama">
ROMAN.<br>
I know you well, sir, and you know me. Your name I think is Adrian.
</p>

<p class="drama">
VOLSCE.<br>
It is so, sir. Truly, I have forgot you.
</p>

<p class="drama">
ROMAN.<br>
I am a Roman, and my services are, as you are, against ’em. Know you me yet?
</p>

<p class="drama">
VOLSCE.<br>
Nicanor, no?
</p>

<p class="drama">
ROMAN.<br>
The same, sir.
</p>

<p class="drama">
VOLSCE.<br>
You had more beard when I last saw you, but your favour is well approved by
your tongue. What’s the news in Rome? I have a note from the Volscian state to
find you out there. You have well saved me a day’s journey.
</p>

<p class="drama">
ROMAN.<br>
There hath been in Rome strange insurrections, the people against the senators,
patricians, and nobles.
</p>

<p class="drama">
VOLSCE.<br>
Hath been? Is it ended, then? Our state thinks not so. They are in a most
warlike preparation and hope to come upon them in the heat of their division.
</p>

<p class="drama">
ROMAN.<br>
The main blaze of it is past, but a small thing would make it flame again; for
the nobles receive so to heart the banishment of that worthy Coriolanus that
they are in a ripe aptness to take all power from the people and to pluck from
them their tribunes for ever. This lies glowing, I can tell you, and is almost
mature for the violent breaking out.
</p>

<p class="drama">
VOLSCE.<br>
Coriolanus banished?
</p>

<p class="drama">
ROMAN.<br>
Banished, sir.
</p>

<p class="drama">
VOLSCE.<br>
You will be welcome with this intelligence, Nicanor.
</p>

<p class="drama">
ROMAN.<br>
The day serves well for them now. I have heard it said the fittest time to
corrupt a man’s wife is when she’s fallen out with her husband. Your noble
Tullus Aufidius will appear well in these wars, his great opposer Coriolanus
being now in no request of his country.
</p>

<p class="drama">
VOLSCE.<br>
He cannot choose. I am most fortunate thus accidentally to encounter you. You
have ended my business, and I will merrily accompany you home.
</p>

<p class="drama">
ROMAN.<br>
I shall between this and supper tell you most strange things from Rome, all
tending to the good of their adversaries. Have you an army ready, say you?
</p>

<p class="drama">
VOLSCE.<br>
A most royal one. The centurions and their charges, distinctly billeted,
already in th’ entertainment, and to be on foot at an hour’s warning.
</p>

<p class="drama">
ROMAN.<br>
I am joyful to hear of their readiness and am the man, I think, that shall set
them in present action. So, sir, heartily well met, and most glad of your
company.
</p>

<p class="drama">
VOLSCE.<br>
You take my part from me, sir. I have the most cause to be glad of yours.
</p>

<p class="drama">
ROMAN.<br>
Well, let us go together.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneIV_6.4"></a><b>SCENE IV. Antium. Before Aufidius’s house</b></h3>

<p class="scenedesc">
Enter <span class="charname">Coriolanus</span> in mean apparel, disguised and
muffled.
</p>

<p class="drama">
CORIOLANUS.<br>
A goodly city is this Antium. City,<br>
’Tis I that made thy widows. Many an heir<br>
Of these fair edifices ’fore my wars<br>
Have I heard groan and drop. Then know me not,<br>
Lest that thy wives with spits and boys with stones<br>
In puny battle slay me.
</p>

<p class="scenedesc">
Enter a <span class="charname">Citizen</span>.
</p>

<p class="drama">
Save you, sir.
</p>

<p class="drama">
CITIZEN.<br>
And you.
</p>

<p class="drama">
CORIOLANUS.<br>
Direct me, if it be your will,<br>
Where great Aufidius lies. Is he in Antium?
</p>

<p class="drama">
CITIZEN.<br>
He is, and feasts the nobles of the state<br>
At his house this night.
</p>

<p class="drama">
CORIOLANUS.<br>
Which is his house, beseech you?
</p>

<p class="drama">
CITIZEN.<br>
This here before you.
</p>

<p class="drama">
CORIOLANUS.<br>
Thank you, sir. Farewell.
</p>

<p class="right">[<i>Exit <span class="charname">Citizen</span>.</i>]</p>

<p class="drama">
O world, thy slippery turns! Friends now fast sworn,<br>
Whose double bosoms seems to wear one heart,<br>
Whose hours, whose bed, whose meal and exercise<br>
Are still together, who twin, as ’twere, in love<br>
Unseparable, shall within this hour,<br>
On a dissension of a doit, break out<br>
To bitterest enmity; so fellest foes,<br>
Whose passions and whose plots have broke their sleep<br>
To take the one the other, by some chance,<br>
Some trick not worth an egg, shall grow dear friends<br>
And interjoin their issues. So with me:<br>
My birthplace hate I, and my love’s upon<br>
This enemy town. I’ll enter. If he slay me,<br>
He does fair justice; if he give me way,<br>
I’ll do his country service.
</p>

<p class="right">[<i>Exit.</i>]</p>

<h3> <a id="sceneIV_6.5"></a><b>SCENE V. Antium. A hall in Aufidius’s house</b></h3>

<p class="scenedesc">
Music plays. Enter a <span class="charname">Servingman</span>.
</p>

<p class="drama">
FIRST SERVINGMAN.<br>
Wine, wine, wine! What service is here? I think our fellows are asleep.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="scenedesc">
Enter another <span class="charname">Servingman</span>.
</p>

<p class="drama">
SECOND SERVINGMAN.<br>
Where’s Cotus? My master calls for him. Cotus!
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="scenedesc">
Enter <span class="charname">Coriolanus</span>.
</p>

<p class="drama">
CORIOLANUS.<br>
A goodly house. The feast smells well, but I<br>
Appear not like a guest.
</p>

<p class="scenedesc">
Enter the First <span class="charname">Servingman</span>.
</p>

<p class="drama">
FIRST SERVINGMAN.<br>
What would you have, friend? Whence are you? Here’s no place for you. Pray go
to the door.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
CORIOLANUS.<br>
I have deserved no better entertainment<br>
In being Coriolanus.
</p>

<p class="scenedesc">
Enter Second <span class="charname">Servingman</span>.
</p>

<p class="drama">
SECOND SERVINGMAN.<br>
Whence are you, sir?—Has the porter his eyes in his head, that he gives
entrance to such companions?—Pray, get you out.
</p>

<p class="drama">
CORIOLANUS.<br>
Away!
</p>

<p class="drama">
SECOND SERVINGMAN.<br>
Away? Get you away.
</p>

<p class="drama">
CORIOLANUS.<br>
Now th’ art troublesome.
</p>

<p class="drama">
SECOND SERVINGMAN.<br>
Are you so brave? I’ll have you talked with anon.
</p>

<p class="scenedesc">
Enter Third  <span class="charname">Servingman;</span> the First, entering,
meets him.
</p>

<p class="drama">
THIRD SERVINGMAN.<br>
What fellow’s this?
</p>

<p class="drama">
FIRST SERVINGMAN.<br>
A strange one as ever I looked on. I cannot get him out o’ th’ house. Prithee
call my master to him.
</p>

<p class="drama">
THIRD SERVINGMAN.<br>
What have you to do here, fellow? Pray you, avoid the house.
</p>

<p class="drama">
CORIOLANUS.<br>
Let me but stand. I will not hurt your hearth.
</p>

<p class="drama">
THIRD SERVINGMAN.<br>
What are you?
</p>

<p class="drama">
CORIOLANUS.<br>
A gentleman.
</p>

<p class="drama">
THIRD SERVINGMAN.<br>
A marv’llous poor one.
</p>

<p class="drama">
CORIOLANUS.<br>
True, so I am.
</p>

<p class="drama">
THIRD SERVINGMAN.<br>
Pray you, poor gentleman, take up some other station. Here’s no place for you.
Pray you, avoid. Come.
</p>

<p class="drama">
CORIOLANUS.<br>
Follow your function, go, and batten on cold bits.
</p>

<p class="right">[<i>Pushes him away from him</i>.]</p>

<p class="drama">
THIRD SERVINGMAN.<br>
What, you will not?—Prithee, tell my master what a strange guest he has here.
</p>

<p class="drama">
SECOND SERVINGMAN.<br>
And I shall.
</p>

<p class="right">[<i>Exit.</i>]</p>

<p class="drama">
THIRD SERVINGMAN.<br>
Where dwell’st thou?
</p>

<p class="drama">
CORIOLANUS.<br>
Under the canopy.
</p>

<p class="drama">
THIRD SERVINGMAN.<br>
Under the canopy?
</p>

<p class="drama">
CORIOLANUS.<br>
Ay.
</p>

<p class="drama">
THIRD SERVINGMAN.<br>
Where’s that?
</p>

<p class="drama">
CORIOLANUS.<br>
I’ th’ city of kites and crows.
</p>

<p class="drama">
THIRD SERVINGMAN.<br>
I’ th’ city of kites and crows? What an ass it is! Then thou dwell’st with daws
too?
</p>

<p class="drama">
CORIOLANUS.<br>
No, I serve not thy master.
</p>

<p class="drama">
THIRD SERVINGMAN.<br>
How, sir? Do you meddle with my master?
</p>

<p class="drama">
CORIOLANUS.<br>
Ay, ’tis an honester service than to meddle with thy mistress. Thou prat’st and
prat’st. Serve with thy trencher, hence!
</p>

<p class="right">[<i>Beats him away</i>.]</p>

<p class="right">[<i>Exit <span class="charname">Third Servingman</span>.</i>]</p>

<p class="scenedesc">
Enter <span class="charname">Aufidius</span> with the Second
<span class="charname">Servingman</span>.
</p>

<p class="drama">
AUFIDIUS.<br>
Where is this fellow?
</p>

<p class="drama">
SECOND SERVINGMAN.<br>
Here, sir. I’d have beaten him like a dog, but for disturbing the lords within.
</p>

<p class="drama">
AUFIDIUS.<br>
Whence com’st thou? What wouldst thou?<br>
Thy name? Why speak’st not? Speak, man. What’s thy name?
</p>

<p class="drama">
CORIOLANUS.<br>
[<i>Removing his muffler</i>.] If, Tullus,<br>
Not yet thou know’st me, and, seeing me, dost not<br>
Think me for the man I am, necessity<br>
Commands me name myself.
</p>

<p class="drama">
AUFIDIUS.<br>
What is thy name?
</p>

<p class="drama">
CORIOLANUS.<br>
A name unmusical to the Volscians’ ears<br>
And harsh in sound to thine.
</p>

<p class="drama">
AUFIDIUS.<br>
Say, what’s thy name?<br>
Thou has a grim appearance, and thy face<br>
Bears a command in’t. Though thy tackle’s torn,<br>
Thou show’st a noble vessel. What’s thy name?
</p>

<p class="drama">
CORIOLANUS.<br>
Prepare thy brow to frown. Know’st thou me yet?
</p>

<p class="drama">
AUFIDIUS.<br>
I know thee not. Thy name?
</p>

<p class="drama">
CORIOLANUS.<br>
My name is Caius Martius, who hath done<br>
To thee particularly and to all the Volsces<br>
Great hurt and mischief; thereto witness may<br>
My surname Coriolanus. The painful service,<br>
The extreme dangers, and the drops of blood<br>
Shed for my thankless country are requited<br>
But with that surname, a good memory<br>
And witness of the malice and displeasure<br>
Which thou shouldst bear me. Only that name remains.<br>
The cruelty and envy of the people,<br>
Permitted by our dastard nobles, who<br>
Have all forsook me, hath devoured the rest,<br>
And suffered me by th’ voice of slaves to be<br>
Whooped out of Rome. Now this extremity<br>
Hath brought me to thy hearth, not out of hope—<br>
Mistake me not—to save my life; for if<br>
I had feared death, of all the men i’ th’ world<br>
I would have ’voided thee, but in mere spite,<br>
To be full quit of those my banishers,<br>
Stand I before thee here. Then if thou hast<br>
A heart of wreak in thee, that wilt revenge<br>
Thine own particular wrongs and stop those maims<br>
Of shame seen through thy country, speed thee straight<br>
And make my misery serve thy turn. So use it<br>
That my revengeful services may prove<br>
As benefits to thee, for I will fight<br>
Against my cankered country with the spleen<br>
Of all the under fiends. But if so be<br>
Thou dar’st not this, and that to prove more fortunes<br>
Thou ’rt tired, then, in a word, I also am<br>
Longer to live most weary, and present<br>
My throat to thee and to thy ancient malice,<br>
Which not to cut would show thee but a fool,<br>
Since I have ever followed thee with hate,<br>
Drawn tuns of blood out of thy country’s breast,<br>
And cannot live but to thy shame, unless<br>
It be to do thee service.
</p>

<p class="drama">
AUFIDIUS.<br>
O Martius, Martius,<br>
Each word thou hast spoke hath weeded from my heart<br>
A root of ancient envy. If Jupiter<br>
Should from yond cloud speak divine things<br>
And say ’tis true, I’d not believe them more<br>
Than thee, all-noble Martius. Let me twine<br>
Mine arms about that body, whereagainst<br>
My grained ash an hundred times hath broke<br>
And scarred the moon with splinters. Here I clip<br>
The anvil of my sword and do contest<br>
As hotly and as nobly with thy love<br>
As ever in ambitious strength I did<br>
Contend against thy valour. Know thou first,<br>
I loved the maid I married; never man<br>
Sighed truer breath. But that I see thee here,<br>
Thou noble thing, more dances my rapt heart<br>
Than when I first my wedded mistress saw<br>
Bestride my threshold. Why, thou Mars, I tell thee<br>
We have a power on foot, and I had purpose<br>
Once more to hew thy target from thy brawn<br>
Or lose mine arm for’t. Thou hast beat me out<br>
Twelve several times, and I have nightly since<br>
Dreamt of encounters ’twixt thyself and me;<br>
We have been down together in my sleep,<br>
Unbuckling helms, fisting each other’s throat,<br>
And waked half dead with nothing. Worthy Martius,<br>
Had we no other quarrel else to Rome but that<br>
Thou art thence banished, we would muster all<br>
From twelve to seventy and, pouring war<br>
Into the bowels of ungrateful Rome,<br>
Like a bold flood o’erbear ’t. O, come, go in,<br>
And take our friendly senators by th’ hands,<br>
Who now are here, taking their leaves of me,<br>
Who am prepared against your territories,<br>
Though not for Rome itself.
</p>

<p class="drama">
CORIOLANUS.<br>
You bless me, gods!
</p>

<p class="drama">
AUFIDIUS.<br>
Therefore, most absolute sir, if thou wilt have<br>
The leading of thine own revenges, take<br>
Th’ one half of my commission and set down—<br>
As best thou art experienced, since thou know’st<br>
Thy country’s strength and weakness—thine own ways,<br>
Whether to knock against the gates of Rome,<br>
Or rudely visit them in parts remote<br>
To fright them ere destroy. But come in.<br>
Let me commend thee first to those that shall<br>
Say yea to thy desires. A thousand welcomes!<br>
And more a friend than e’er an enemy—<br>
Yet, Martius, that was much. Your hand. Most welcome!
</p>

<p class="right">
[<i>Exeunt <span class="charname">Coriolanus</span> and
<span class="charname">Aufidius</span>.</i>]
</p>

<p class="scenedesc">
Two of the <span class="charname">Servingmen</span> come forward.
</p>

<p class="drama">
FIRST SERVINGMAN.<br>
Here’s a strange alteration!
</p>

<p class="drama">
SECOND SERVINGMAN.<br>
By my hand, I had thought to have strucken him with a cudgel, and yet my mind
gave me his clothes made a false report of him.
</p>

<p class="drama">
FIRST SERVINGMAN.<br>
What an arm he has! He turned me about with his finger and his thumb as one
would set up a top.
</p>

<p class="drama">
SECOND SERVINGMAN.<br>
Nay, I knew by his face that there was something in him. He had, sir, a kind of
face, methought—I cannot tell how to term it.
</p>

<p class="drama">
FIRST SERVINGMAN.<br>
He had so, looking as it were—Would I were hanged, but I thought there was
more in him than I could think.
</p>

<p class="drama">
SECOND SERVINGMAN.<br>
So did I, I’ll be sworn. He is simply the rarest man i’ th’ world.
</p>

<p class="drama">
FIRST SERVINGMAN.<br>
I think he is. But a greater soldier than he you wot one.
</p>

<p class="drama">
SECOND SERVINGMAN.<br>
Who, my master?
</p>

<p class="drama">
FIRST SERVINGMAN.<br>
Nay, it’s no matter for that.
</p>

<p class="drama">
SECOND SERVINGMAN.<br>
Worth six on him.
</p>

<p class="drama">
FIRST SERVINGMAN.<br>
Nay, not so neither. But I take him to be the greater soldier.
</p>

<p class="drama">
SECOND SERVINGMAN.<br>
Faith, look you, one cannot tell how to say that. For the defence of a town our
general is excellent.
</p>

<p class="drama">
FIRST SERVINGMAN.<br>
Ay, and for an assault too.
</p>

<p class="scenedesc">
Enter the Third <span class="charname">Servingman</span>.
</p>

<p class="drama">
THIRD SERVINGMAN.<br>
O slaves, I can tell you news, news, you rascals!
</p>

<p class="drama">
FIRST and SECOND SERVINGMAN.<br>
What, what, what? Let’s partake.
</p>

<p class="drama">
THIRD SERVINGMAN.<br>
I would not be a Roman, of all nations; I had as lief be a condemned man.
</p>

<p class="drama">
FIRST and SECOND SERVINGMAN.<br>
Wherefore? Wherefore?
</p>

<p class="drama">
THIRD SERVINGMAN.<br>
Why, here’s he that was wont to thwack our general, Caius Martius.
</p>

<p class="drama">
FIRST SERVINGMAN.<br>
Why do you say, “thwack our general”?
</p>

<p class="drama">
THIRD SERVINGMAN.<br>
I do not say “thwack our general,” but he was always good enough for him.
</p>

<p class="drama">
SECOND SERVINGMAN.<br>
Come, we are fellows and friends. He was ever too hard for him; I have heard
him say so himself.
</p>

<p class="drama">
FIRST SERVINGMAN.<br>
He was too hard for him directly, to say the troth on’t, before Corioles; he
scotched him and notched him like a carbonado.
</p>

<p class="drama">
SECOND SERVINGMAN.<br>
An he had been cannibally given, he might have boiled and eaten him too.
</p>

<p class="drama">
FIRST SERVINGMAN.<br>
But, more of thy news?
</p>

<p class="drama">
THIRD SERVINGMAN.<br>
Why, he is so made on here within as if he were son and heir to Mars; set at
upper end o’ th’ table; no question asked him by any of the senators but they
stand bald before him. Our general himself makes a mistress of him, sanctifies
himself with’s hand, and turns up the white o’ th’ eye to his discourse. But
the bottom of the news is, our general is cut i’ th’ middle and but one half
of what he was yesterday, for the other has half, by the entreaty and grant of
the whole table. He’ll go, he says, and sowl the porter of Rome gates by th’
ears. He will mow all down before him and leave his passage polled.
</p>

<p class="drama">
SECOND SERVINGMAN.<br>
And he’s as like to do’t as any man I can imagine.
</p>

<p class="drama">
THIRD SERVINGMAN.<br>
Do’t? He will do’t! For look you, sir, he has as many friends as enemies, which
friends, sir, as it were, durst not, look you, sir, show themselves, as we term
it, his friends whilest he’s in directitude.
</p>

<p class="drama">
FIRST SERVINGMAN.<br>
Directitude? What’s that?
</p>

<p class="drama">
THIRD SERVINGMAN.<br>
But when they shall see, sir, his crest up again, and the man in blood, they
will out of their burrows like coneys after rain, and revel all with him.
</p>

<p class="drama">
FIRST SERVINGMAN.<br>
But when goes this forward?
</p>

<p class="drama">
THIRD SERVINGMAN.<br>
Tomorrow, today, presently. You shall have the drum struck up this afternoon.
’Tis as it were parcel of their feast, and to be executed ere they wipe their
lips.
</p>

<p class="drama">
SECOND SERVINGMAN.<br>
Why then, we shall have a stirring world again. This peace is nothing but to
rust iron, increase tailors, and breed ballad-makers.
</p>

<p class="drama">
FIRST SERVINGMAN.<br>
Let me have war, say I. It exceeds peace as far as day does night. It’s
sprightly walking, audible, and full of vent. Peace is a very apoplexy,
lethargy; mulled, deaf, sleepy, insensible; a getter of more bastard children
than war’s a destroyer of men.
</p>

<p class="drama">
SECOND SERVINGMAN.<br>
’Tis so, and as war in some sort, may be said to be a ravisher, so it cannot be
denied but peace is a great maker of cuckolds.
</p>

<p class="drama">
FIRST SERVINGMAN.<br>
Ay, and it makes men hate one another.
</p>

<p class="drama">
THIRD SERVINGMAN.<br>
Reason: because they then less need one another. The wars for my money! I hope
to see Romans as cheap as Volscians. They are rising; they are rising.
</p>

<p class="drama">
ALL.<br>
In, in, in, in!
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneIV_6.6"></a><b>SCENE VI. Rome. A public place</b></h3>

<p class="scenedesc">
Enter the two Tribunes. <span class="charname">Sicinius</span> and
<span class="charname">Brutus</span>.
</p>

<p class="drama">
SICINIUS.<br>
We hear not of him, neither need we fear him.<br>
His remedies are tame—the present peace,<br>
And quietness of the people, which before<br>
Were in wild hurry. Here do we make his friends<br>
Blush that the world goes well, who rather had,<br>
Though they themselves did suffer by’t, behold<br>
Dissentious numbers pest’ring streets than see<br>
Our tradesmen singing in their shops and going<br>
About their functions friendly.
</p>

<p class="drama">
BRUTUS.<br>
We stood to’t in good time.
</p>

<p class="scenedesc">
Enter <span class="charname">Menenius</span>.
</p>

<p class="drama">
Is this Menenius?
</p>

<p class="drama">
SICINIUS.<br>
’Tis he, ’tis he. O, he is grown most kind<br>
Of late.—Hail, sir!
</p>

<p class="drama">
MENENIUS.<br>
Hail to you both.
</p>

<p class="drama">
SICINIUS.<br>
Your Coriolanus is not much missed<br>
But with his friends. The commonwealth doth stand,<br>
And so would do were he more angry at it.
</p>

<p class="drama">
MENENIUS.<br>
All’s well, and might have been much better if<br>
He could have temporized.
</p>

<p class="drama">
SICINIUS.<br>
Where is he, hear you?
</p>

<p class="drama">
MENENIUS.<br>
Nay, I hear nothing;<br>
His mother and his wife hear nothing from him.
</p>

<p class="scenedesc">
Enter three or four <span class="charname">Citizens</span>.
</p>

<p class="drama">
ALL CITIZENS.<br>
The gods preserve you both!
</p>

<p class="drama">
SICINIUS.<br>
Good e’en, our neighbours.
</p>

<p class="drama">
BRUTUS.<br>
Good e’en to you all, good e’en to you all.
</p>

<p class="drama">
FIRST CITIZEN.<br>
Ourselves, our wives, and children, on our knees<br>
Are bound to pray for you both.
</p>

<p class="drama">
SICINIUS.<br>
Live and thrive!
</p>

<p class="drama">
BRUTUS.<br>
Farewell, kind neighbours. We wished Coriolanus<br>
Had loved you as we did.
</p>

<p class="drama">
CITIZENS.<br>
Now the gods keep you!
</p>

<p class="drama">
BOTH TRIBUNES.<br>
Farewell, farewell.
</p>

<p class="right">[<i>Exeunt <span class="charname">Citizens</span>.</i>]</p>

<p class="drama">
SICINIUS.<br>
This is a happier and more comely time<br>
Than when these fellows ran about the streets<br>
Crying confusion.
</p>

<p class="drama">
BRUTUS.<br>
Caius Martius was<br>
A worthy officer i’ th’ war, but insolent,<br>
O’ercome with pride, ambitious, past all thinking<br>
Self-loving.
</p>

<p class="drama">
SICINIUS.<br>
And affecting one sole throne, without assistance.
</p>

<p class="drama">
MENENIUS.<br>
I think not so.
</p>

<p class="drama">
SICINIUS.<br>
We should by this, to all our lamentation,<br>
If he had gone forth consul, found it so.
</p>

<p class="drama">
BRUTUS.<br>
The gods have well prevented it, and Rome<br>
Sits safe and still without him.
</p>

<p class="scenedesc">
Enter an <span class="charname">Aedile</span>.
</p>

<p class="drama">
AEDILE.<br>
Worthy tribunes,<br>
There is a slave, whom we have put in prison,<br>
Reports the Volsces with two several powers<br>
Are entered in the Roman territories,<br>
And with the deepest malice of the war<br>
Destroy what lies before ’em.
</p>

<p class="drama">
MENENIUS.<br>
’Tis Aufidius,<br>
Who, hearing of our Martius’ banishment,<br>
Thrusts forth his horns again into the world,<br>
Which were inshelled when Martius stood for Rome,<br>
And durst not once peep out.
</p>

<p class="drama">
SICINIUS.<br>
Come, what talk you of Martius?
</p>

<p class="drama">
BRUTUS.<br>
Go see this rumourer whipped. It cannot be<br>
The Volsces dare break with us.
</p>

<p class="drama">
MENENIUS.<br>
Cannot be?<br>
We have record that very well it can,<br>
And three examples of the like hath been<br>
Within my age. But reason with the fellow<br>
Before you punish him, where he heard this,<br>
Lest you shall chance to whip your information<br>
And beat the messenger who bids beware<br>
Of what is to be dreaded.
</p>

<p class="drama">
SICINIUS.<br>
Tell not me.<br>
I know this cannot be.
</p>

<p class="drama">
BRUTUS.<br>
Not possible.
</p>

<p class="scenedesc">
Enter a <span class="charname">Messenger</span>.
</p>

<p class="drama">
MESSENGER.<br>
The nobles in great earnestness are going<br>
All to the Senate House. Some news is coming<br>
That turns their countenances.
</p>

<p class="drama">
SICINIUS.<br>
’Tis this slave—<br>
Go whip him ’fore the people’s eyes—his raising,<br>
Nothing but his report.
</p>

<p class="drama">
MESSENGER.<br>
Yes, worthy sir,<br>
The slave’s report is seconded, and more,<br>
More fearful, is delivered.
</p>

<p class="drama">
SICINIUS.<br>
What more fearful?
</p>

<p class="drama">
MESSENGER.<br>
It is spoke freely out of many mouths—<br>
How probable I do not know—that Martius,<br>
Joined with Aufidius, leads a power ’gainst Rome<br>
And vows revenge as spacious as between<br>
The young’st and oldest thing.
</p>

<p class="drama">
SICINIUS.<br>
This is most likely!
</p>

<p class="drama">
BRUTUS.<br>
Raised only that the weaker sort may wish<br>
Good Martius home again.
</p>

<p class="drama">
SICINIUS.<br>
The very trick on ’t.
</p>

<p class="drama">
MENENIUS.<br>
This is unlikely;<br>
He and Aufidius can no more atone<br>
Than violent’st contrariety.
</p>

<p class="scenedesc">
Enter a Second <span class="charname">Messenger</span>.
</p>

<p class="drama">
SECOND MESSENGER.<br>
You are sent for to the Senate.<br>
A fearful army, led by Caius Martius<br>
Associated with Aufidius, rages<br>
Upon our territories, and have already<br>
O’erborne their way, consumed with fire and took<br>
What lay before them.
</p>

<p class="scenedesc">
Enter <span class="charname">Cominius</span>.
</p>

<p class="drama">
COMINIUS.<br>
O, you have made good work!
</p>

<p class="drama">
MENENIUS.<br>
What news? What news?
</p>

<p class="drama">
COMINIUS.<br>
You have holp to ravish your own daughters and<br>
To melt the city leads upon your pates,<br>
To see your wives dishonoured to your noses—
</p>

<p class="drama">
MENENIUS.<br>
What’s the news? What’s the news?
</p>

<p class="drama">
COMINIUS.<br>
Your temples burned in their cement, and<br>
Your franchises, whereon you stood, confined<br>
Into an auger’s bore.
</p>

<p class="drama">
MENENIUS.<br>
Pray now, your news?—<br>
You have made fair work, I fear me.—Pray, your news?<br>
If Martius should be joined with Volscians—
</p>

<p class="drama">
COMINIUS.<br>
If?<br>
He is their god; he leads them like a thing<br>
Made by some other deity than Nature,<br>
That shapes man better; and they follow him<br>
Against us brats with no less confidence<br>
Than boys pursuing summer butterflies<br>
Or butchers killing flies.
</p>

<p class="drama">
MENENIUS.<br>
You have made good work,<br>
You and your apron-men, you that stood so much<br>
Upon the voice of occupation and<br>
The breath of garlic eaters!
</p>

<p class="drama">
COMINIUS.<br>
He’ll shake your Rome about your ears.
</p>

<p class="drama">
MENENIUS.<br>
As Hercules did shake down mellow fruit.<br>
You have made fair work.
</p>

<p class="drama">
BRUTUS.<br>
But is this true, sir?
</p>

<p class="drama">
COMINIUS.<br>
Ay, and you’ll look pale<br>
Before you find it other. All the regions<br>
Do smilingly revolt, and who resists<br>
Are mocked for valiant ignorance<br>
And perish constant fools. Who is’t can blame him?<br>
Your enemies and his find something in him.
</p>

<p class="drama">
MENENIUS.<br>
We are all undone unless<br>
The noble man have mercy.
</p>

<p class="drama">
COMINIUS.<br>
Who shall ask it?<br>
The Tribunes cannot do’t for shame; the people<br>
Deserve such pity of him as the wolf<br>
Does of the shepherds. For his best friends, if they<br>
Should say “Be good to Rome,” they charged him even<br>
As those should do that had deserved his hate<br>
And therein showed like enemies.
</p>

<p class="drama">
MENENIUS.<br>
’Tis true.<br>
If he were putting to my house the brand<br>
That should consume it, I have not the face<br>
To say “Beseech you, cease.”—You have made fair hands,<br>
You and your crafts! You have crafted fair!
</p>

<p class="drama">
COMINIUS.<br>
You have brought<br>
A trembling upon Rome such as was never<br>
S’ incapable of help.
</p>

<p class="drama">
TRIBUNES.<br>
Say not we brought it.
</p>

<p class="drama">
MENENIUS.<br>
How? Was it we? We loved him, but like beasts<br>
And cowardly nobles, gave way unto your clusters,<br>
Who did hoot him out o’ th’ city.
</p>

<p class="drama">
COMINIUS.<br>
But I fear<br>
They’ll roar him in again. Tullus Aufidius,<br>
The second name of men, obeys his points<br>
As if he were his officer. Desperation<br>
Is all the policy, strength, and defence<br>
That Rome can make against them.
</p>

<p class="scenedesc">
Enter a troop of <span class="charname">Citizens</span>.
</p>

<p class="drama">
MENENIUS.<br>
Here comes the clusters.—<br>
And is Aufidius with him? You are they<br>
That made the air unwholesome when you cast<br>
Your stinking, greasy caps in hooting at<br>
Coriolanus’ exile. Now he’s coming,<br>
And not a hair upon a soldier’s head<br>
Which will not prove a whip. As many coxcombs<br>
As you threw caps up will he tumble down<br>
And pay you for your voices. ’Tis no matter.<br>
If he could burn us all into one coal<br>
We have deserved it.
</p>

<p class="drama">
ALL CITIZENS.<br>
Faith, we hear fearful news.
</p>

<p class="drama">
FIRST CITIZEN.<br>
For mine own part,<br>
When I said banish him, I said ’twas pity.
</p>

<p class="drama">
SECOND CITIZEN.<br>
And so did I.
</p>

<p class="drama">
THIRD CITIZEN.<br>
And so did I. And, to say the truth, so did very many of us. That we did we
did for the best; and though we willingly consented to his banishment, yet it
was against our will.
</p>

<p class="drama">
COMINIUS.<br>
You are goodly things, you voices!
</p>

<p class="drama">
MENENIUS.<br>
You have made good work, you and your cry!—<br>
Shall’s to the Capitol?
</p>

<p class="drama">
COMINIUS.<br>
O, ay, what else?
</p>

<p class="right">
[<i>Exeunt <span class="charname">Cominius</span> and
<span class="charname">Menenius</span>.</i>]
</p>

<p class="drama">
SICINIUS.<br>
Go, masters, get you home. Be not dismayed.<br>
These are a side that would be glad to have<br>
This true which they so seem to fear. Go home,<br>
And show no sign of fear.
</p>

<p class="drama">
FIRST CITIZEN.<br>
The gods be good to us! Come, masters, let’s home. I ever said we were i’ th’
wrong when we banished him.
</p>

<p class="drama">
SECOND CITIZEN.<br>
So did we all. But, come, let’s home.
</p>

<p class="right">[<i>Exeunt <span class="charname">Citizens</span>.</i>]</p>

<p class="drama">
BRUTUS.<br>
I do not like this news.
</p>

<p class="drama">
SICINIUS.<br>
Nor I.
</p>

<p class="drama">
BRUTUS.<br>
Let’s to the Capitol. Would half my wealth<br>
Would buy this for a lie!
</p>

<p class="drama">
SICINIUS.<br>
Pray let’s go.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

<h3> <a id="sceneIV_6.7"></a><b>SCENE VII. A camp at a short distance from Rome</b></h3>

<p class="scenedesc">
Enter <span class="charname">Aufidius</span> with his
<span class="charname">Lieutenant</span>.
</p>

<p class="drama">
AUFIDIUS.<br>
Do they still fly to th’ Roman?
</p>

<p class="drama">
LIEUTENANT.<br>
I do not know what witchcraft’s in him, but<br>
Your soldiers use him as the grace ’fore meat,<br>
Their talk at table, and their thanks at end;<br>
And you are dark’ned in this action, sir,<br>
Even by your own.
</p>

<p class="drama">
AUFIDIUS.<br>
I cannot help it now,<br>
Unless by using means I lame the foot<br>
Of our design. He bears himself more proudlier,<br>
Even to my person, than I thought he would<br>
When first I did embrace him. Yet his nature<br>
In that’s no changeling, and I must excuse<br>
What cannot be amended.
</p>

<p class="drama">
LIEUTENANT.<br>
Yet I wish, sir—<br>
I mean for your particular—you had not<br>
Joined in commission with him, but either<br>
Had borne the action of yourself or else<br>
To him had left it solely.
</p>

<p class="drama">
AUFIDIUS.<br>
I understand thee well, and be thou sure,<br>
When he shall come to his account, he knows not<br>
What I can urge against him, although it seems,<br>
And so he thinks and is no less apparent<br>
To th’ vulgar eye, that he bears all things fairly,<br>
And shows good husbandry for the Volscian state,<br>
Fights dragonlike, and does achieve as soon<br>
As draw his sword; yet he hath left undone<br>
That which shall break his neck or hazard mine<br>
Whene’er we come to our account.
</p>

<p class="drama">
LIEUTENANT.<br>
Sir, I beseech you, think you he’ll carry Rome?
</p>

<p class="drama">
AUFIDIUS.<br>
All places yield to him ere he sits down,<br>
And the nobility of Rome are his;<br>
The Senators and Patricians love him too.<br>
The Tribunes are no soldiers, and their people<br>
Will be as rash in the repeal as hasty<br>
To expel him thence. I think he’ll be to Rome<br>
As is the osprey to the fish, who takes it<br>
By sovereignty of nature. First, he was<br>
A noble servant to them, but he could not<br>
Carry his honours even. Whether ’twas pride,<br>
Which out of daily fortune ever taints<br>
The happy man; whether defect of judgment,<br>
To fail in the disposing of those chances<br>
Which he was lord of; or whether nature,<br>
Not to be other than one thing, not moving<br>
From th’ casque to th’ cushion, but commanding peace<br>
Even with the same austerity and garb<br>
As he controlled the war; but one of these—<br>
As he hath spices of them all—not all,<br>
For I dare so far free him—made him feared,<br>
So hated, and so banished. But he has a merit<br>
To choke it in the utt’rance. So our virtues<br>
Lie in th’ interpretation of the time,<br>
And power, unto itself most commendable,<br>
Hath not a tomb so evident as a chair<br>
T’ extol what it hath done.<br>
One fire drives out one fire, one nail one nail;<br>
Rights by rights falter; strengths by strengths do fail.<br>
Come, let’s away. When, Caius, Rome is thine,<br>
Thou art poor’st of all; then shortly art thou mine.
</p>

<p class="right">[<i>Exeunt.</i>]</p>

