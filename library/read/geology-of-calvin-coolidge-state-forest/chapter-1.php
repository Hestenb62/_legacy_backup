<p>The third basic principle to command is known as the Law of Faunal
Succession. In generalized form this law states that each stratum of
rock contains its own distinct group of animal or plant remains, termed
fossils, and that these same remains can be recognized throughout the
world wherever they occur. Since plants and animals changed through
time and because their remains are found throughout the world, it is
possible to erect a worldwide time scale based upon animal and plant
evolution. In short, the fossils found in particular rock are characteristic
representatives of the life at the time that rock originated and the fossils
<span class="pb" id="Page_6">6</span>
found could have been entombed only at that time. One stratum, therefore,
would have a total fossil assemblage quite different from the
stratum above or below. Without this time reference chart it would be
impossible to reconstruct what did happen during any one time interval
in the past.</p>
<p>In addition to these three basic laws it is necessary to mention the
rudiments of rock classification. The geologist divides <i>rocks</i><a class="fn pginternal" href="#fn_1" id="fr_1">[1]</a> into three
major groups which are termed Igneous, Sedimentary and Metamorphic
rocks. Igneous rocks are those formed by the solidification of molten
material. This molten material was thrust into the outer crust of the
earth from below and after cooling became a solid igneous rock such as
granite, or in other cases it flowed out over the surface of the earth in the
form of volcanic lava. Some small igneous bodies, termed dikes, can
readily be seen along State Highway 100A adjacent to Calvin Coolidge
State Forest Park (See photograph, <a href="#fig1" class="pginternal">Fig. 1</a>).</p>
<p>Sedimentary rocks are formed in quite a different manner and differ
in general appearance. These are what might be considered second-hand
rocks. They are composed of particles derived from other rocks, igneous,
metamorphic or older sedimentary, which have been carried by streams,
wind or ice to a place of rest and there cemented into rock. Perhaps you
can visualize a river which, throughout its course, runs over rocks of
many types. This river would pick up particles of rock from its bed and
banks and transport these to a lake or perhaps the sea, where the various
transported materials would settle to the bottom in distinct layers. The
first layer deposited would become buried under thousands of tons of
overlying layers of sediment whose weight and resultant pressure,
together with the presence of adequate rock-cementing material such
as calcium carbonate or silica, would cause the bottom layer to harden
into rock. The layered appearance of sedimentary rocks is one of their
most characteristic features and these rocks are said to be bedded or
composed of many individual beds of sedimentary rock. Sandstone,
composed of sand size particles; shale, originally mud; and limestone,
once lime-rich mud, are examples of sedimentary rocks.</p>
<div class="pb" id="Page_7">7</div>
<p>Metamorphic rocks result when igneous or sedimentary rocks are
subjected to abnormal heat and pressure. Folding or <i>faulting</i><a class="fn pginternal" href="#fn_2" id="fr_2">[2]</a> of rocks
within the earth’s crust or deep burial beneath overlying rocks or sediments
commonly produce metamorphism. The introduction of hot fluids
during folding and faulting greatly increase the speed and degree of
metamorphic conversion. When igneous or sedimentary rocks are subjected
to metamorphism they tend to lose their original appearance as
some minerals are completely changed or altered into new minerals and
most of the original minerals are oriented in one or more preferred
directions. The degree of heat and pressure, type and amount of hot
fluids provided and the type of rock undergoing metamorphism will
determine the nature of the metamorphic rock to develop. Perhaps the
most unfortunate effect caused by the metamorphism of sedimentary
rocks, especially when considering the history recorded in the rocks, is
that in the majority of cases all fossils originally present are either
destroyed or distorted beyond recognition. The absence of fossils makes
age determination quite difficult and hinders definition of previous
environments.</p>
<p>The rocks seen in and adjacent to Coolidge State Forest Park, with
very few exceptions, are metamorphic rocks which were originally sedimentary
rocks. Luckily the metamorphism is slight and several pages of
geologic history can still be read. Schists, phyllites and <i>quartzites</i><a class="fn pginternal" href="#fn_3" id="fr_3">[3]</a>, all
metamorphic rocks, are well displayed in the Forest Park region.</p>
<p>The parallel arrangement of mica plates and segregation of the darker
minerals into distinct layers in the schists and phyllites together with
the inherited sedimentary layering in the quartzites, impart a distinctly
visible orientation to the rocks seen in the Forest Park. The parallelism
<span class="pb" id="Page_8">8</span>
of the mica and segregation of the darker minerals in the schists and
phyllites is directly related to metamorphic processes and the measurable
orientation is called foliation. The original sedimentary layering of the
quartzites, little changed through the metamorphism, is referred to as
bedding. From all indications the foliation and bedding are practically
parallel in this region and since most of the rocks represented are of the
metamorphic type, all orientation features will be referred to as foliation.</p>
