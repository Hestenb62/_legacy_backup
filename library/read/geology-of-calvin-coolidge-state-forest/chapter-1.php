<h2 id="c1"> <span class="small"><b>INTRODUCTION</b></span></h2>
<p>Each summer hundreds of eager campers, picnickers, hikers and
sportsmen visit the Pinney Hollow-Bradley Hill recreational area of the
Calvin Coolidge State Forest Park. This area is located a few miles
north of Plymouth, Vermont, and is easily reached via State Route 100A
from either Plymouth or Bridgewater Corners (See index map of Vermont,
<a href="#imgx2" class="pginternal">geological map</a>). The excellent camping and recreational facilities
coupled with the natural scenic beauty of this region provide many
visitors with an irresistible urge to return, summer after summer, to
this same spot. This pamphlet is designed for all those who visit Coolidge
Forest Park and especially for those who possess questioning minds and a
general desire to learn more about the world around them.</p>
<h2 id="c2"> <span class="small"><b>GEOLOGY</b></span></h2>
<p>Have you ever wondered why the present mountains and valleys are
where they are and how and when they got there? Has the thought passed
through your mind that the very rocks on which you stand or see nearby
have a definite story to tell? The geologist not only wonders about such
things, but through his training attempts to answer questions of this
nature. His everyday job includes the reconstruction of ancient land
and sea areas through a careful study of the rock record. He looks at the
rock layers as you might the pages of a history book. The professional
geologist, however, commands many basic geological principles and
“tools of the trade” which permit him to read more accurately the
records preserved in stone.</p>
<p>First, the basic geological principles will be explained and you will
be given the proper “tools” for your adventure. Then, you are invited
to travel back through 550 million years of time to see just why Coolidge
State Forest Park is as it is today and what it was like in the distant past.</p>
