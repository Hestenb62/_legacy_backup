<h2 id="c3"> <span class="small"><b>BASIC PRINCIPLES AND “TOOLS”</b></span></h2>
<p>To many of you rocks are just “rocks” and very little thought has
been given to any history which might be gained from their study.
Probably even fewer of you realize that literally billions of years of
Earth history can be derived directly from the rock record. Most geologists
consider the Earth to be nearly four billion years old with man entering
the picture a mere million or so years ago. No human was present to
record the events of billions of years of changing land and seas, violent
earth movements or the gradual evolution of life through the last 500
million years. The study of rocks and their contained evidence of past
life offers the only clarification for the extremely long past history of the
Earth. In order to unravel this past history the geologist accepts, with
some reservations, three basic principles or laws.</p>
<p>The Law of Uniformitarianism provides an extremely important link
with the past. This law states that the physical and chemical forces
which are attacking or building up the surface of the earth today have
operated in much the same way during past geological time. This means
that our observations of present day environments, such as streams,
deltas, lakes and oceans can be applied, after slight modification, to the
past as recorded in the rocks. For example, study of present day deltas,
such as the Nile or Mississippi River delta, has led to the discovery of
many past deltaic deposits now preserved as layers and lenses of rock.
This distribution pattern of sands and muds, the nature of the life forms
within each environment and many other such criteria aid the geologist
in his interpretations.</p>
<p>The Law of Superposition provides a physical order to the many
layers of rock which form the geological record. Compare, for the
moment, the vast numbers of rock layers (strata) with the layers of a
layercake. As a layercake is built up each individual layer is placed one
over another, with the bottom or base layer the first to be positioned and
followed by successively overlying layers. If you think of the development
of this cake in terms of time, the base layer is the oldest, the uppermost
the youngest. The Law of Superposition follows this example and
states that the lowermost stratum in a sequence of rock strata is the
oldest or the first to form, while the stratum above is younger and formed
at a later time. Some reservations do exist; however, in the Forest Park
under immediate consideration this general law does apply.</p>
