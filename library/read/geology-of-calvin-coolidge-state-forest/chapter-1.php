<p>The geologist uses the terms dip and strike to describe foliation and
uses conventional symbols for plotting purposes (See <a href="#imgx2" class="pginternal">geologic map</a>). The
dip of the foliation is the angle between an imaginary horizontal line
and the tilt or downward slope of the foliation. The strike is the compass
direction of a line formed by the dipping foliation plane and its intersection
with an imaginary horizontal plane (See block diagram, <a href="#fig2" class="pginternal">Fig. 2</a>).
A glance at the geological map will show that the rocks of the Park
area consistently strike north to northwest and dip to the east. If you
look at the foliation symbols which are plotted on the <a href="#imgx2" class="pginternal">geologic map</a>, the
straight line of the symbol indicates the strike and the black triangle
points in the direction of the dip. The angles of dip have not been included
on the map; however, they average forty-five degrees down from
the horizontal and toward the east or right margin of the <a href="#imgx2" class="pginternal">geological map</a>.</p>
