<p>No fossils have been found in the Pinney Hollow formation of this
region: however, evidence from other parts of Vermont indicate that
<span class="pb" id="Page_13">13</span>
these rocks are of Cambrian or perhaps <i>Ordovician</i><a class="fn pginternal" href="#fn_6" id="fr_6">[6]</a> age. This dates these
rocks as approximately 500 million years old.</p>
<p>The <i>Ottauquechee formation</i>, next above the Pinney Hollow formation
and therefore younger in age, was named for the Ottauquechee River
along which this formation is well exposed and was first studied in detail.
The Ottauquechee River is located just north of Calvin Coolidge State
Forest Park where it flows through the towns of Bridgewater and Bridgewater
Corners. You can see this formation along State Highway 100A
approximately nine-tenths of a mile north of the Park entrance road.
Here, the formation crops out on the west side of the road, or on your
left if traveling toward Bridgewater Corners (See photograph, <a href="#fig4" class="pginternal">Fig. 4</a>). A
hike along the recently diamond-blazed Coolidge Forest trail, which leads
from behind the Ranger’s cabin to the Picnic area, affords an almost
continuous view of this formation. The highly resistant quartzite layers
within the Ottauquechee formation are very conspicuous features along
this trail as they form several ridges trending across the footpath.</p>
<p>The Ottauquechee formation, estimated to be 3,000 feet thick, contains
rocks which contrast sharply with the underlying pale-green schists. The
formation consists of alternating black phyllite and layers, up to several
feet thick, of dark- to light-colored quartzite. The black carbonaceous
color of the phyllites and dark quartzites indicate the presence of life,
either animal or plant, during the original deposition of the sediments
forming these rocks. The phyllite was, before metamorphism, a black
shale which formed from black muds rich in organic matter. From studies
done in areas where black muds are accumulating today it seems quite
probable that the ocean waters of Ottauquechee time were of a restricted
nature, that is to say, the waters were stagnant due to the lack of oxygen.
Pinney Hollow shallow marine water conditions remained, but for some
reason, such as a barrier of islands or shallow water sand bars, the
circulation of ocean waters was hindered, leading to the accumulation
of stagnant organic matter on the ocean bottom. This organic matter
gives the Ottauquechee phyllite and some quartzites a dark to black
color.</p>
<p>No fossils have been found in the Ottauquechee formation of the
<span class="pb" id="Page_14">14</span>
Coolidge Forest Park, but, as with the Pinney Hollow formation,
evidence from other areas indicates a Cambrian or perhaps Ordovician
age for this formation.</p>
