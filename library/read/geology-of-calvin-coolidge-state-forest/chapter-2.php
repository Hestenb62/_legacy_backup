<h2 id="c4"> <span class="small"><b>THE ROCKS OF CALVIN COOLIDGE STATE FOREST PARK AND THE STORY THEY TELL</b></span></h2>
<p>The rocks of Calvin Coolidge State Forest Park can be divided into
four distinct units or <i>formations</i><a class="fn pginternal" href="#fn_4" id="fr_4">[4]</a>. The <a href="#imgx2" class="pginternal">geologic map</a> shows these formations
as distinct bands, each band representing a different formation and
its intersection with the ground surface. Each formation is, so to speak,
stacked upon the next older with the oldest forming the western band
and the youngest on the east. Remember that these metamorphic rock
formations were originally sedimentary in nature and were deposited
in a nearly horizontal position on the floor on an ancient sea. The fact
that they are now tilted indicates that earth movements have taken place
sometime after the sedimentary rocks hardened but before the present
time.</p>
<p>The <i>Pinney Hollow formation</i>, the oldest formation of rocks seen in
the Forest Park, was named for the excellent exposures of this formation
in Pinney Hollow, a valley located along the western border of Coolidge
Forest. You can readily see this formation, in its most typical development,
along State Highway 100A about three-tenths of a mile south
of the Park entrance road. Here, a historical monument which commemorates
the naming of Pinney Hollow, is embedded in this formation
(See photograph, <a href="#fig3" class="pginternal">Fig. 3</a>). The lean-to, tent platform and picnic
areas are situated on this formation and its rocks are easily observed.
It is interesting to note that some of the Pinney Hollow rocks seen
in these camping and picnicking spots differ from the typical rocks
seen along State Highway 100A. In fact, some of the rocks which are
dark and are classed as phyllites, can be confused with the overlying
Ottauquechee rocks. A transition zone, several hundred feet wide, exists
between these two formations and in which the two distinct rock types
are intermingled. This “mixture” zone indicates that there was no break
in the original deposition of these two formations and therefore the rock
record during this time is complete.</p>
