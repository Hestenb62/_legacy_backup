<p>The Pinney Hollow formation, which is an estimated 2,300 or more
feet thick, is primarily composed of pale-green <i>schist</i><a class="fn pginternal" href="#fn_5" id="fr_5">[5]</a> with abundant
white quartz layers and lenses sandwiched between the dominantly
greenish colored rock. Originally these metamorphic rocks were sand,
mud and sandy mud deposited on a relatively shallow sea floor. After
burial these sediments hardened into thin layers and lenses of sandstone,
shale, and sandy shale. Metamorphism has since converted many of the
shale minerals into mica flakes and some of the sandy shales produced
crystals of the mineral garnet. The pale-green color of the Pinney Hollow
schist is caused by the presence of the green mica-like mineral, chlorite,
which developed during the process of metamorphism.</p>
