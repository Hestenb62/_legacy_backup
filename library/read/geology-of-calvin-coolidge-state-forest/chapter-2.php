<p>Above the Ottauquechee rocks lie those of the <i>Bethel formation</i>.
Approximately 2,000 feet thick, this formation is composed mainly of
pale-green schist with interlaminated thin layers of white to greenish
quartzite. The rock presents a distinct banded appearance and contains
conspicuous crystals of garnet and the black mica, biotite. The best
view of this schist is found along State Highway 100A and slightly over
two miles north of the Park entrance road. The relatively steep rock
cliffs which line the west side of this road are composed of the resistant
Bethel formation. In the northeast portion of Coolidge Forest Park
several excellent exposures of this formation in contact with the underlying
Ottauquechee formation can be seen, but, to reach these areas you
would have to leave the beaten trail. If you are interested in visiting
these contact locations it would be best to consult the geologic map for
approximate directions.</p>
