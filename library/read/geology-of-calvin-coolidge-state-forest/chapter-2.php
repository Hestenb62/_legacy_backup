<p>The conditions under which the Bethel formation was originally
deposited are similar to those which existed during Pinney Hollow time.
Shale, sandy shale and thin-bedded sandstones formed under shallow
water marine conditions; however, restriction with accompanied organic
accumulation did not occur. This formation is thought to be of either
Cambrian or Ordovician age.</p>
<p>The easternmost, and therefore youngest formation to be found in
the Park area is known as the <i>Missisquoi formation</i>. This formation,
which is only partially represented here, is made up of dark phyllite,
light blue-gray schist with conspicuous crystals of garnet and biotite,
and gray quartzite. The rocks of this formation can be seen along Broad
Brook which flows north along the eastern border of Coolidge State
Forest Park.</p>
<p>This formation is considered Ordovician in age with the conditions of
deposition being quite similar to those which existed during Ottauquechee
time. Once again the ocean waters were restricted and organic-rich black
muds accumulated in quantity on the ocean floor.</p>
