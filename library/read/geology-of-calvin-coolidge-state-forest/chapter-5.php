<h2 id="c11"> <span class="small">Footnotes</span></h2>
<div class="fnblock"><div class="fndef"><a class="fn pginternal" href="#fr_1" id="fn_1">[1]</a>A rock, for those desiring a more technical definition, is any relatively hard,
naturally occurring, combination of minerals which form an essential part of the
earth. Minerals are composed of one or more chemical elements, such as oxygen or
silicon, that form in nature.
</div><div class="fndef"><a class="fn pginternal" href="#fr_2" id="fn_2">[2]</a>A fault is a break or fracture in the rocks of the earth’s crust where one side of
the fracture moves in some direction relative to the other side. Some recent earthquakes
in California and Nevada have produced visible faults where, for instance,
roads were cut and one side displaced several yards from the other.
</div><div class="fndef"><a class="fn pginternal" href="#fr_3" id="fn_3">[3]</a>Most of the mineral grains which make up a schist, a metamorphosed shale or
sandy shale, can be seen with the naked eye, and the parallel to subparallel arrangement
of platy or flaky minerals, such as the abundant mica, is the most obvious
feature. In bright sunlight a schist presents a very shiny, almost silvery appearance
which is caused by the reflection of sunlight from the many parallel mica plates. A
phyllite has much the same mineral composition as that of a schist; however, the
individual mineral grains are too small to be seen without the aid of a magnifying
glass. As with the schist, a phyllite when viewed in direct sunlight, appears shiny.
Quartzites are metamorphosed sandstones which have been fused into great hardness
through the application of heat and pressure.
</div><div class="fndef"><a class="fn pginternal" href="#fr_4" id="fn_4">[4]</a>A geologic formation consists of a group of similar rocks, or sequence of rocks,
which can be easily distinguished from adjacent rocks and whose distribution can
be plotted on a map.
</div><div class="fndef"><a class="fn pginternal" href="#fr_5" id="fn_5">[5]</a>More technically this schist is termed a chlorite-sericite-quartz schist.
</div><div class="fndef"><a class="fn pginternal" href="#fr_6" id="fn_6">[6]</a>The geologist divides geologic time into four major sections, designated Eras.
These Eras are in turn subdivided into Geologic Periods which are of shorter time
duration. The Cambrian Period is the oldest of the Paleozoic Era and began some
550 million years ago. The Ordovician Period is the next oldest of the Paleozoic Era
and started about 440 million years ago and ended close to 360 million years ago.
