<h2 id="c5"> <span class="small"><b>THE GEOLOGIC HISTORY</b></span></h2>
<p>The early geologic history of Calvin Coolidge State Forest Park is
known from the rock formations discussed in the previous section of
this pamphlet. The Pinney Hollow, Ottauquechee, Bethel and Missisquoi
formations of Cambrian and Ordovician age were deposited, essentially
horizontally, from the shallow seas which covered this area 550 to 450
million years ago (See cross section A, <a href="#fig5" class="pginternal">Fig. 5</a>). During some of this time
these seas were at least partially restricted as evidenced by the Ottauquechee
and Missisquoi black phyllites. Other Ordovician formations
were deposited on top of these four formations, but have been completely
stripped away by erosion during the millions of years since their
deposition. Some of these later Ordovician sediments contain great
<span class="pb" id="Page_17">17</span>
thicknesses of volcanic rocks which probably covered the Coolidge Park
area.</p>
<p>Sometime after these later Ordovician rocks formed, great stresses
within the earth’s crust folded and in some places faulted these older
rocks. The pressure and resultant heat created during these earth movements
converted the rocks into metamorphic schists, phyllites and
quartzites which are seen today (See cross section B, <a href="#fig5" class="pginternal">Fig. 5</a>). Exactly
when these diastropic events took place is still open to question, but they
probably occurred near the end of Ordovician time or perhaps millions
of years later during the last phases of the Devonian Period.</p>
<p>Probably since late Paleozoic time the Coolidge Park area has been
subjected to breaking-down rather than building-up processes. Eventually
this whole region was reduced to a flat plane with only a few hills,
called monadnocks, rising above the general flatness of the landscape.
Still later in the history of Coolidge State Forest Park this flat plane
was lifted high above its former position and streams began to shape the
land into its present form. The more resistant rocks were lowered by the
forces of erosion at a much slower rate than the less resistant types. The
hills and valleys which you see today are primarily the result of this
general uplift followed by the wearing away of the softer rocks at a
more rapid rate than the harder rock types. Since the formations trend
in a north-north-west direction, the hills and valleys are also oriented
in this general direction, as the different resistive qualities of the rocks
are presented in this pattern.</p>
<p>The story is not complete without mention of the last modifying
influence to affect this region. Approximately one million years ago the
first of perhaps three glacial advances began. These large glacial masses,
termed continental glaciers, slowly advanced southward over the
northern sections of the United States and covered a vast region with a
thick sheet of ice. As these ice masses rode over the Coolidge Park region
they tended to round-off irregular features of the landscape and to fill in
certain low regions with their transported rock debris. The rather smooth
outlines of the hills in Coolidge Forest Park and the sand and gravel
deposits so apparent adjacent to nearby streams tell the story of these
glacial advances and subsequent withdrawals. Other evidence of the
overriding ice is seen in the presence of scratch marks, termed glacial
striae, which were produced by fragments of rock as they were dragged
by the moving ice across the underlying rocks. Along the east bank of
Broad Brook and approximately two hundred yards south of the bridge
<span class="pb" id="Page_18">18</span>
at Five Corners, abundant glacial striae are clearly displayed. The
orientation of these striae indicates that the glacier producing them
moved from north north-west to the south south-east.</p>
<p>Since the recession of the last ice sheet, which took place several
thousand years ago, the general appearance of the Coolidge Park region
has changed very little. The streams have cut their valleys somewhat
deeper and some of the glacial sands and gravels have been redistributed.
A few thousand years ago Coolidge State Forest Park looked quite the
same as it does today (See cross section C, <a href="#fig5" class="pginternal">Fig. 5</a>).</p>
