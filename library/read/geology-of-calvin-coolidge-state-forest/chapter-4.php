<h2 id="c6"> <span class="small"><b>SIDE TRIPS OF GEOLOGICAL INTEREST</b></span></h2>
<h3 id="c7"> <b><i>Gold Panning</i></b></h3>
<p>There are several locations immediately adjacent to the Calvin
Coolidge State Forest Park where some gold can still be obtained from
stream sands and gravels. The abandoned town of Five Corners offers
the park visitor ample chance to “try his luck.” In fact, several local
people still obtain small gold nuggets and a good deal of gold dust from
the streams in the vicinity of Five Corners (See <a href="#imgx2" class="pginternal">geologic map</a> for geographic
location). Other possible “panning” locations would include
Reading Pond Brook, Buffalo Brook and Kingdom Brook. The gold
which is found is probably derived from nearby gold-bearing quartz
veins.</p>
<p>The equipment needed for an afternoon of panning is relatively simple
to obtain. A wide, rather shallow pan with gently sloping sides is really
all that is needed. Gravel and sand, which you find concentrated on the
upstream side of natural rock riffles in the stream bed should be placed
together with water in your pan. Then the pan should be rotated and the
lighter rock materials decanted. The heavy gold will be concentrated
in the bottom of the pan.</p>
<h3 id="c8"> <b><i>Asbestos and Talc</i></b></h3>
<p>For you who might be interested in mineral collecting it is suggested
that a trip to an old pit near Five Corners might prove rewarding. Walk
down Broad Brook from the bridge at Five Corners until you locate the
first small tributary entering on your left. Turn left up this tributary
and continue to walk for approximately one hundred yards. On your
left you will see the remains of a pit dug into the side of the stream bank
which, at this location, is lined with rocks of the Ottauquechee formation.
<span class="pb" id="Page_19">19</span>
You will quickly note the fibrous asbestos in the walls of this pit; however,
if you wish to collect specimens of this mineral be extremely careful
and avoid standing beneath any overhanging rock material. Talc, which
feels “soapy” to the touch, is also abundant in this immediate area.
This asbestos and talc occur in a lenticular-shaped body which is perhaps
eight hundred feet wide and of an undetermined length. It is not certain
when these minerals formed; however, it was probably in the early
history of the region.</p>
<h3 id="c9"> <b><i>Garnet</i></b></h3>
<p>Good specimens of garnet can be found in the rocks of the Bethel
formation. These garnets are not of gem quality but still offer good
collecting for the amateur mineralogist. Good collecting localities exist
along State Highway 100A and at several different spots within the Park
itself. A hike along the northern boundary of the Park would intersect
several excellent collecting spots.</p>
<h3 id="c10"> <b><i>Vermont Marble Company Exhibit, Proctor, Vermont</i></b></h3>
<p>If time permits, or a rainy day arrives, a visit to the Vermont Marble
Company Exhibit in Proctor, Vermont, is highly recommended. Marble
is a metamorphic rock which was originally sedimentary in nature.
Lime muds hardened into limestones and then, converted by metamorphism,
became marble. The marble exhibit at Proctor, termed “The
largest Marble Exhibit in the World,” displays over 100 varieties of
marble and igneous rock, granite. Fossils can be seen in some of the
varieties of marble, which demonstrates that under certain conditions
recognizable fossils do occur in metamorphic rocks. Most of the marble
seen in this exhibit is quarried nearby; however, for safety reasons visitors
are not allowed to enter the quarries. It is interesting to note that these
marbles are about the same age as the rocks seen in Coolidge State
Forest Park.</p>
