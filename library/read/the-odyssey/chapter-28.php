    As for the ῥῶγες of line 143, no commentator
ancient or modern has been able to say what was intended—but whatever they
were, Melanthius could never carry twelve shields, twelve helmets, and twelve
spears. Moreover, where he could go the others could go also. If a dozen
suitors had followed Melanthius into the house they could have attacked Ulysses
in the rear, in which case, unless Minerva had intervened promptly, the
“Odyssey” would have had a different ending. But throughout the scene we are in
a region of extravagance rather than of true fiction—it cannot be taken
seriously by any but the very serious, until we come to the episode of Phemius
and Medon, where the writer begins to be at home again.]
