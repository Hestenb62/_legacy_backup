<h2><a id="pref02"></a>
PREFACE TO SECOND EDITION</h2>
<p>
Butler’s Translation of the “Odyssey” appeared originally in 1900, and The
Authoress of the Odyssey in 1897. In the preface to the new edition of “The
Authoress”, which is published simultaneously with this new edition of the
Translation, I have given some account of the genesis of the two books.
</p>
<p>
The size of the original page has been reduced so as to make both books uniform
with Butler’s other works; and, fortunately, it has been possible, by using a
smaller type, to get the same number of words into each page, so that the
references remain good, and, with the exception of a few minor alterations and
rearrangements now to be enumerated so far as they affect the Translation, the
new editions are faithful reprints of the original editions, with misprints and
obvious errors corrected—no attempt having been made to edit them or to bring
them up to date.
</p>
<p>
(a) The Index has been revised.
</p>
<p>
(b) Owing to the reduction in the size of the page it has been necessary to
shorten some of the headlines, and here advantage has been taken of various
corrections of and additions to the headlines and shoulder-notes made by Butler
in his own copies of the two books.
</p>
<p>
(c) For the most part each of the illustrations now occupies a page, whereas in
the original editions they generally appeared two on the page. It has been
necessary to reduce the plan of the House of Ulysses.
</p>
<p>
On page 153 of “The Authoress” Butler says: “No great poet would compare his
hero to a paunch full of blood and fat, cooking before the fire (xx, 24-28).”
This passage is not given in the abridged Story of the “Odyssey” at the
beginning of the book, but in the Translation it occurs in these words:
</p>
<p>
“Thus he chided with his heart, and checked it into endurance, but he tossed
about as one who turns a paunch full of blood and fat in front of a hot fire,
doing it first on one side then on the other, that he may get it cooked as soon
as possible; even so did he turn himself about from side to side, thinking all
the time how, single-handed as he was, he should contrive to kill so large a
body of men as the wicked suitors.”
</p>
<p>
It looks as though in the interval between the publication of “The Authoress”
(1897) and of the Translation (1900) Butler had changed his mind; for in the
first case the comparison is between Ulysses and a paunch full, etc., and in
the second it is between Ulysses and a man who turns a paunch full, etc. The
second comparison is perhaps one which a great poet might make.
</p>
<p>
In seeing the works through the press I have had the invaluable assistance of
Mr. A. T. Bartholomew of the University Library, Cambridge, and of Mr. Donald
S. Robertson, Fellow of Trinity College, Cambridge. To both these friends I
give my most cordial thanks for the care and skill exercised by them. Mr.
Robertson has found time for the labour of checking and correcting all the
quotations from and references to the “Iliad” and “Odyssey,” and I believe that
it could not have been better performed. It was, I know, a pleasure for him;
and it would have been a pleasure also for Butler if he could have known that
his work was being shepherded by the son of his old friend, Mr. H. R.
Robertson, who more than half a century ago was a fellow-student with him at
Cary’s School of Art in Streatham Street, Bloomsbury.
</p>
