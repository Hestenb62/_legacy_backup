<p>Original printed spelling and grammar are retained, with exceptions
noted below. Small caps <span class="smcaps">L<span>OOK</span></span>
<span class="smcaps">L<span>IKE</span></span> <span class="smmaj">THIS.</span> The changes recommended in the <a href="#idaddenda" class="pginternal">ADDENDA AND CORRIGENDA</a> section have been applied.
The transcriber created the
cover image, and assigns it to the public domain.</p>

<p>It is impossible to render verse indents quite accurately in this
electronic edition, which permits font-family and font-size and many
other parameters to vary whimsically.
Therefore verse indents are coded herein in
terms of percentages of screen width. An original printed indent of
22em has been converted herein to 71.25% of total verse width, and
an original indent of 2em is converted to 6.25%. Other indents are
proportional.</p>

<p id="transnoteln">Linenotes in the original printed book resided on the page with the
line referenced. In this edition, linenotes have been converted to
footnotes and have been moved to the ends of the respective plays.
The footnote labels are
shown with play number (in this book), Act number, and Scene
number prefixed, coded a–f, a–e, and a–w, respectively. Thus a
hypothetical line/footnote coded <i>feb065</i> designates line 65 in the
sixth play (<i>King Richard III</i>), Act 5, Scene 2. These codes are
also inserted into the Scene headings, to aid the reader in navigation
of the book. The original table of contents was modified, eliminating the
original page numbers, not used in this edition, and adding links to the
line/footnotes.</p>

