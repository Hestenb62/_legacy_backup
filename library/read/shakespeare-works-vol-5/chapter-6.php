<h3 class="h3main">
<span class="smcaps">N<span>OTE</span></span> I.</h3>

<div class="right toppada"><small><a href="#idtoc" class="pginternal">toc</a></small></div>

<p>
 <span class="nowrap"><a href="#ikh6-dp" class="pginternal"><span class="smcaps">D<span>RAMATIS</span></span>
 <span class="smcaps">P<span>ERSONÆ</span></span></a>.</span>
Mr G. R. French writes to us: ‘In 1 Henry VI., it
is generally said of the Duke of York: “Richard Plantagenet, <i>eldest</i>
son of Richard, late Earl of Cambridge.” But he was an <i>only</i> son.
“Eldest” should therefore be left out.’</p>

<p>We have made other changes in the ‘Dramatis Personæ’ of the following
plays, in accordance with suggestions from Mr French, to whom we beg to
repeat our acknowledgements.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> II.</h3>

<p><span class="nowrap"><a href="#lnum-aaa060" class="pginternal"><span class="smmaj">I.</span> 1. 60</a>.</span>
The word Rheims, spelt ‘Rheimes’ in the Folios, must be
pronounced as a dissyllable, otherwise the metre halts. Capell’s
interpolation, the credit of which is claimed as usual by Steevens
derives some support from the fact that <i>Roan</i>, i.e. <i>Rouen</i>, is
mentioned by Gloucester in line 65. Possibly we should read <i>Rheimes</i>
for <i>Roan</i> in the latter passage.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> III.</h3>

<p><span class="nowrap"><a href="#lnum-aac059" class="pginternal"><span class="smmaj">I.</span> 3. 59</a>.</span>
The insertion made by the Editor of the second Folio for
the sake of the metre shows that a change had already taken place in
the pronunciation of the word ‘Mayor,’ which in Shakespeare’s day was
sometimes written and pronounced ‘Major.’ See <i>1 Henry IV</i>. <span class="smmaj">II.</span> 4.
473: ‘I deny your major; if you will deny the Sheriff, so; let him
enter.’ In line 84 of the present scene, however, the ‘Maior’ of the
first Folio becomes ‘Major’ in the second—probably from inadvertence.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> IV.</h3>

<p><span class="nowrap"><a href="#lnum-aad016" class="pginternal"><span class="smmaj">I.</span> 4. 16–18</a>.</span>
We leave this corrupt passage
as it stands in the first Folio. In the second Folio, which is followed
as usual by the third and fourth, it is thus given:
</p>

<div class="poembox">
<div class="dverseq">‘And fully even these three dayes have I watcht,</div>
<div class="dverse">If I could see them. Now Boy doe thou watch,</div>
<div class="dverse">For I can stay no longer.’</div>
</div>

<p>Pope omits the words ‘For...longer.’</p>

<p>Malone has:</p>

<div class="poembox">
<div class="dverseq">‘And even these three days have I watched,</div>
<div class="dverse">If I could see them.</div>
<div class="dverse">Now do thou watch, for I can stay no longer.’</div></div>

<p>Mr Collier:</p>

<div class="poembox">
<div class="dverseq">‘And even these three days have I watch’d, if I</div>
<div class="dverse">Could see them.</div>
<div class="dverse">Now, do thou watch, for I can stay no longer.’</div></div>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> V.</h3>

<p><span class="nowrap"><a href="#lnum-acb017" class="pginternal"><span class="smmaj">III.</span> 2. 17</a>.</span>
All editors previous to Capell, except Hanmer, follow
the Folios in making Reignier speak without having brought him on the
stage, and all subsequent editors follow Capell in giving Reignier’s
speeches to Alençon, without noting that he had made any change. Hanmer
altered Alençon to Reignier in the stage-direction, line 16, and
Reignier to Alençon in the stage-direction, line 40.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> VI.</h3>

<p><span class="nowrap"><a href="#lnum-aea017" class="pginternal"><span class="smmaj">V.</span> 1. 17</a>.</span>
However plausible the emendation <i>kin</i> may seem, we leave
<i>knit</i>, the reading of the Folios, as the conceit suggested by the
‘knot of amity,’ in the preceding line, is not alien from the author’s
manner. Mr Collier, in a note to his second edition, says: “Mr Singer
is obliged to admit that it has been proposed to read ‘near <i>kin</i> to
Charles.’ Where has it been so proposed? In the corrected Folio, 1632,
which Mr Singer has always such a wish to ignore. The emendation was
never suggested (not even in Mr Singer’s corrected Folio, 1632) until
it appeared in our volume of ‘Notes and emendations,’ p. 277.”</p>

<p>In fact, it was first suggested by Pope, and adopted by Theobald,
Hanmer, Warburton, and Johnson. Capell restored <i>knit</i>, in which he was
followed by Steevens and Malone.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> VII.</h3>

<p><span class="nowrap"><a href="#lnum-aec075" class="pginternal"><span class="smmaj">V.</span>
 <span class="smmaj">III.</span> 75</a>.</span>
This and other speeches which follow are marked by Pope
and subsequent editors as spoken aside, but this is so obvious that
we have not thought it necessary to encumber our pages with marginal
directions.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> VIII.</h3>

<p><span class="nowrap"><a href="#lnum-aed121" class="pginternal"><span class="smmaj">V.</span> 4. 121</a>.</span>
Malone, followed by Singer, Mr Collier, and Herr Delius,
attributes the emendation ‘prison’d’ for ‘poison’d’ to Pope. Mr
Staunton rightly assigns it to Theobald.</p>
