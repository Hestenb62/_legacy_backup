<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> IV.</h3>

<p><span class="nowrap">
<a href="#lnum-dar037" class="pginternal"><span class="smmaj">XVIII</span>. 37, 38.</a></span>
On the line ‘Thou ridest on a foot-cloth doest thou not?’ Mr Halliwell remarks, ‘This passage, though completely necessary for the sense, is entirely omitted in the edition of 1619 and by Mr Knight.’ It is indeed omitted by Mr Knight, who follows Steevens, but it is found in Capell’s copy of the edition of 1619, ‘Thou ridest on a foot-cloth, dost thou not?’ We take this opportunity of remarking that, in all cases where the readings given by us from the edition of 1619 differ from those quoted by Mr Halliwell, we have given them as they stand in Capell’s copy. Mr Halliwell appears to quote from Mr Knight’s reprint. Instances of these variations occur in Scene <span class="smmaj">III</span>. line 6, where Steevens and Mr Knight print ‘They’ for ‘That,’ the reading of all the Quartos: in Scene <span class="smmaj">IV.</span> line 41, where they have ‘treason’ for ‘treasons:’ in Scene <span class="smmaj">VII.</span> line 3, where they have ‘against’ for ‘gainst.’ In Scene <span class="smmaj">X.</span> line 76, Mr Halliwell says the edition of 1619 reads ‘with the vnbloody beake’: in Capell’s copy it is ‘With vnbloody beake.’ In <span class="smmaj">XX.</span> 16 he quotes ‘Yet if I do not’ as the reading of the edition of 1619 where Capell’s copy has ‘Yet if do not,’ the former being the reading of Steevens’s reprint. In <span class="smmaj">XX.</span> 28 ‘hand’ is the reading of all the Quartos, while Steevens has ‘hands.’ It is possible that these variations may be found in other copies of the ed. of 1619.</p>

