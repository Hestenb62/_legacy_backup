NOTES TO<br>III KING HENRY VI.</h2></div>

<h3 class="h3main">
<span class="smcaps">N<span>OTE</span></span> I.</h3>

<div class="right toppada"><small><a href="#idtoc" class="pginternal">toc</a></small></div>

<p><span class="nowrap">
<a href="#lnum-cba095" class="pginternal"><span class="smmaj">II.</span> 1. 95.</a>
</span> Pope and Hanmer make no new scene here, although they
evidently intended to do so, as the next scene is marked as Scene III.
In Theobald, as usual, the scenes are not numbered.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> II.</h3>

<p><span class="nowrap">
<a href="#lnum-cbb089" class="pginternal"><span class="smmaj">II.</span> 2. 89.</a>
</span>
In this passage the lines 89–92 are given to ‘Cla.’ in the
first Folio, and to ‘George’ in the Quartos; but it is evident that
Shakespeare, by altering ‘his brother’ in line 92 to ‘me,’ intended the
whole to be spoken by Edward. This is another instance of Shakespeare’s
haste in remodelling the older plays.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> III.</h3>

<p><span class="nowrap">
<a href="#lnum-cbe092" class="pginternal"><span class="smmaj">II.</span> 5. 92, 93.</a>
</span> Capell follows Hanmer in adopting the reading of the
Quartos. We retain the reading of the Folios, because the alteration
merely transfers the difficulty of explanation from one line to another.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> IV.</h3>

<p><span class="nowrap">
<a href="#lnum-cca001" class="pginternal"><span class="smmaj">III.</span> 1.</a>
</span> As Sinklo is certainly the name of an Actor, who is mentioned
in the stage directions in the <i>Taming of the Shrew</i> (Ind. I. 86), and
in <i>Henry IV.</i> Pt. <span class="smmaj">II.</span> (Act <span class="smmaj">IV.</span> Sc. 4), there is great probability
that Humfrey is the name of another Actor, perhaps, as Malone suggests,
Humfrey Jeaffes. Neither of these is mentioned in the list of
‘Principal Actors’ prefixed to the first Folio.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> V.</h3>

<p><span class="nowrap">
<a href="#lnum-cda020" class="pginternal"><span class="smmaj">IV.</span> 1. 20–23.</a>
</span>
The following is the arrangement of these lines in the
Folios:</p>

<div class="poembox">
<div class="dverseq">‘Not I: no:</div>
<div class="dverse">God forbid, that I should wish them seuer’d,</div>
<div class="dverse">Whom God hath ioyn’d together:</div>
<div class="dverse">I, and ’twere pittie, to sunder them,</div>
<div class="dverse">That yoake so well together.’</div></div>

<p>Pope reads:</p>

<div class="poembox">
<div class="dverseq">‘Not I; no: God forbid that I should wish</div>
<div class="dverse">Them severed whom God hath join’d together.</div>
<div class="dverse">Pity to sunder them, that yoak so well.’</div></div>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> VI.</h3>

<p><span class="nowrap">
<a href="#lnum-cdb013" class="pginternal"><span class="smmaj">IV.</span> 2. 13.</a>
</span> The reading ‘overture’ first appears in Warburton’s
edition, being probably a misprint. Johnson adopts it, but suggests
the true reading ‘coverture,’ without giving any indication that
this was the reading in all the Folios and in all the editions
before Warburton’s. We give this as one of the many instances of the
carelessness with which Johnson’s work was done.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> VII.</h3>

<p><span class="nowrap">
<a href="#lnum-cdh001" class="pginternal"><span class="smmaj">IV.</span> 8.</a>
</span> In the Folios, Somerset
is introduced in the stage direction, though he had gone with
young Richmond into Brittany. The mistake arose from the Quartos
in which Scene <span class="smmaj">VI.</span> and Scene <span class="smmaj">VIII.</span> form but one.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> VIII.</h3>

<p><span class="nowrap">
<a href="#lnum-cea044" class="pginternal"><span class="smmaj">V.</span> 1. 44.</a>
</span> This conjecture of Warburton’s, which as he does not
mention it in his edition we have marked ‘withdrawn,’ is found in a
series of unpublished letters from Theobald to Warburton recently added
to the treasures of the British Museum. The first of these letters is
dated Feb. 10, 1729, and the last Sep. 4, 1736. That in which allusion
is made to the passage in question is dated March 10, 1732. Theobald
rejects Warburton’s suggestion, for, he says, ‘Deck’ is ‘a county
dialect,’ meaning the same thing. Among the MSS. recently acquired by
the Museum is a series of letters from Hanmer to Warburton beginning
Dec. 24, 1735, and ending May 25, 1739. In a letter dated July 27,
1737, Hanmer mentions his conjectural reading ‘truss’ for ‘cost’ which
he afterwards inserted in the text of his edition. He defends it thus:
‘when a hawk raiseth a fowl aloft and soaring upwards with it at length
seizeth it in the air, she is said to <i>truss</i> the fowl, which I imagine
is the word which the poor desponding king was made here to apply to
his crown.’</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> IX.</h3>

<p><span class="nowrap">
<a href="#lnum-ceb048" class="pginternal"><span class="smmaj">V.</span> 2. 48.</a>
</span> The first Folio, which the later Folios copy <i>verbatim</i> but
not <i>literatim</i>, reads as follows:</p>

<div class="poembox">
<div class="dverseq">‘Oh farewell <i>Warwicke</i>.</div>
<div class="dverse"><i>Warw.</i> Sweet rest his Soule:</div>
<div class="dverse">Flye Lords, and saue your selues,</div>
<div class="dverse">For <i>Warwicke</i> bids you all farewell, to meet in Heauen.’</div></div>

<p class="continue">Pope reads:</p>

<div class="poembox">
<div class="dverseq">‘O farewel Warwick.</div>
<div class="dverse"><i>War.</i> Sweetly rest his soul!</div>
<div class="dverse">Fly lords and save your selves, for Warwick bids</div>
<div class="dverse">You all farewel, to meet again in heaven.’</div></div>

<p class="continue">Capell:</p>

<div class="poembox">
<div class="dverseq">‘O, farewel, Warwick!</div>
<div class="dverse"><i>War.</i> Sweet rest his soul!—Fly, lords, and save yourselves;</div>
<div class="dverse">For Warwick bids farewel, to meet in heaven.’</div></div>

<p class="continue">Rann:</p>

<div class="poembox">
<div class="dverseq">‘O, farewel, Warwick!</div>
<div class="dverse"><i>War.</i> Sweet rest his soul!—</div>
<div class="dverse">Fly, lords, and save yourselves; Warwick bids you</div>
<div class="dverse">All farewel—to meet in heaven.’</div></div>

<p>In his edition of 1778 Steevens followed Pope’s arrangement; restoring,
however, ‘Sweet’ for ‘Sweetly’ and omitting ‘again.’</p>

<p>Steevens in later editions gives:</p>

<div class="poembox">
<div class="dverseq">‘O, farewell, Warwick!</div>
<div class="dverse"><i>War.</i> Sweet rest to his soul!—</div>
<div class="dverse">Fly, lords, and save yourselves; for Warwick bids</div>
<div class="dverse">You all farewell to meet again in heaven.’</div></div>

<p>The arrangement which we have adopted is exactly that of the Quartos.
Mr Collier was the first of modern editors to introduce it in his text.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> X.</h3>

<p><span class="nowrap">
<a href="#lnum-cee001" class="pginternal"><span class="smmaj">V.</span> 5.</a>
</span> We have adhered in the stage directions as nearly as possible
to the Folios, which throughout the play mark no division of the
scenes, except at the end of an Act. Rowe first omitted the <i>Exeunt.</i>
Theobald, who also continued the scene, gave <i>Alarm. Retreat.
Excursions. Both Parties go out. Re-enter King Edward</i>, &amp;c.</p>

<p>Capell first made a new scene here and, altering the relative position
of the stage directions, gave <i>Exeunt both the Armies.</i>
<span class="smcaps">S<span>C.</span></span> <span class="smmaj">V.</span>
<i>Alarums; Excursions; afterwards a Retreat. Then, Enter, as from
Conquest, King Edward, &amp;c.</i></p>

<p>Capell’s arrangement has, as usual, been followed by subsequent
editors.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> XI.</h3>

<p><span class="nowrap">
<a href="#lnum-cee077" class="pginternal"><span class="smmaj">V.</span> 5. 77, 78.</a></span></p>

<div class="poembox">
<div class="dverseq"><span class="i10"> </span> ‘Where is that devil’s butcher,</div>
<div class="dverse">Hard-favour’d Richard? Richard, where art thou?’</div></div>

<p>The reading we have given in the text is that of Steevens, which
appears to be nearest the corresponding passage of the Quartos.</p>

<p>The first Folio has:</p>

<div class="poembox">
<div class="dverseq"><span class="i06"> </span> ‘Where is that diuels butcher <i>Richard</i>?</div>
<div class="dverse">Hard fauor’d <i>Richard</i>? <i>Richard</i>, where art thou?’</div></div>

<p>The second Folio:</p>

<div class="poembox">
<div class="dverseq"><span class="i06"> </span> ‘Where is that divels butcher <i>Richard</i></div>
<div class="dverse">Hard favor’d <i>Richard</i>? <i>Richard</i>, where art thou?’</div></div>

<p>The third and fourth put a comma after the first ‘<i>Richard</i>,’ the third
reading ‘devils,’ the fourth ‘devil’s.’ Rowe follows the Folios.</p>

<p>Pope has:</p>

<div class="poembox">
<div class="dverse"><span class="i09"> </span> ‘where is that Devil’s butcher,</div>
<div class="dverse">Richard? hard-favour’d Richard, where art thou?’</div></div>

<p>Theobald:</p>

<div class="poembox">
<div class="dverseq"><span class="i10"> </span> ‘where is that Devil-butcher,</div>
<div class="dverse">Richard? hard-favour’d Richard, where art thou?’</div></div>

<p>Capell:</p>

<div class="poembox">
<div class="dverseq"><span class="i10"> </span> ‘Where is that butcher, Richard?</div>
<div class="dverse">Hard-favour’d Richard? Richard, where art thou?’</div></div>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> XII.</h3>

<p><span class="nowrap">
<a href="#lnum-cef001" class="pginternal"><span class="smmaj">V.</span> 6.</a>
</span> We have retained the stage direction of the Folios ‘on the
walls’ instead of adopting Capell’s alteration ‘a Room in the Tower’,
as it seems likely that the mistake lies in the expression ‘another
room’ which was retained from the older play, the author forgetting
that he had changed the scene to the walls.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> XIII.</h3>

<p><span class="nowrap">
<a href="#lnum-ceg025" class="pginternal"><span class="smmaj">V.</span> 7. 25.</a>
</span> The copy of the first Folio belonging to Lord Ellesmere has
in this place ‘add’ for ‘and.’ In line 27, the same copy reads ‘’tis’
for ‘kis,’ which latter is the word found so far as we know in all
other copies.</p>

