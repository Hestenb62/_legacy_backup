<h2 class="nobreak" title="Preface." id="idpreface">PREFACE.</h2></div>

<div class="right toppada"><small><a href="#idtoc" class="pginternal">toc</a></small></div>

<p class="first">
<i>The First Part of King Henry the Sixth</i> was printed for
the first time, so far as we know, in the Folio of 1623.
The same edition contained also for the first time in their
present form, ‘The second Part of King Henry the Sixt,
with the death of the Good Duke Humfrey,’ and ‘The
third Part of King Henry the Sixt, with the death of the
Duke of Yorke.’</p>

<p>The play upon which the Second part of Henry the
Sixth was founded was first printed in quarto (Q<sub>1</sub>), in 1594,
with the following title:</p>

<div class="blockquot">
<p>The | First part of the <span class="nowrap">Con- tention</span> betwixt the two famous
houses of Yorke | and Lancaster, with the death of the good |
Duke Humphrey: | And the banishment and death of the Duke
of | <i>Suffolke</i>, and the Tragicall end of the proud Cardinall | of
<i>Winchester</i>, with the notable Rebellion | of <i>Iacke Cade:</i> | <i>And the
Duke of Yorkes first claime vnto the</i> | <i>Crowne</i>. | LONDON | Printed
by Thomas Creed, for Thomas Millington, | and are to be sold
at his shop vnder Saint Peters | Church in Cornwall. |
<span class="nowrap">1594. |</span></p>
</div>

<p>The only copy known of this edition is in the Bodleian
Library (Malone, Add. 870), and is probably the same
which was once in Malone’s possession, and which he collated
with the second Quarto printed in 1600. Mr Halliwell,
in the preface to ‘The first sketches of the second
and third parts of King Henry the Sixth,’ edited by him
for the Shakespeare Society, is inclined to doubt this, on
the ground that Malone quotes, from the copy in his possession,
a reading which does not exist in that now in the
Bodleian. The passage in question is in Scene <span class="smmaj">IX.</span> line 12,
p. 370 of the present volume, ‘Honouring him as if he were
their king:’ on which Mr Halliwell in his note observes,
‘Malone, who has collated his copy of the edition of 1600,
“printed by W. W.,” with a copy of the 1594 edition formerly
in his possession, distinctly writes—
</p>

<div class="blockquot">
“<i>Thinking</i> him as if he were their king,”
</div>

<p class="continue">as the reading of his copy of the first edition. If so, it
must have been a different copy from that now in the
Bodleian, from which the present text is reprinted, and
another instance of the curious variations in different
copies of the same editions, which were first discovered
by Steevens (Boswell’s <i>Malone</i>, Vol. <span class="smmaj">X.</span> p. 73), and recently
applied to good use by Mr Collier.’ Mr Halliwell has here
inadvertently fallen into error. Malone’s collation is made
in a copy of the edition of 1600, in which the line stands
thus:</p>

<div class="blockquot">
‘Honouring him as if he were <i>a king</i>.’
</div>

<p>At the foot of the page he wrote ‘their king,’ which is
the reading of the edition of 1594 for the two last words,
but which Mr Halliwell misread ‘thinking’ and regarded
as a various reading for ‘Honouring.’ It is still possible,
therefore, that Malone’s copy and that at present in the
Bodleian may be identical.</p>

<p>The second edition (<span class="nowrap">Q<sub>2</sub></span>) of the First Part of the Contention
appeared in quarto in 1600, with the following
title:</p>

<div class="blockquot">
<p>The | First part of the Con-|tention betwixt the two famous
hou-|<i>ses of Yorke and Lancaster, with the</i> | death of the good Duke |
Humphrey: | And the banishment and death of the Duke of |
Suffolke, and the Tragical end of the prowd Cardinall | <i>of
Winchester, with the notable Rebellion of</i> | <i>Iacke Cade</i>: | <i>And the
Duke of Yorkes first clayme to the</i> | <i>Crowne</i>. | <span class="smcaps">L<span>ONDON</span></span> | Printed
by Valentine Simmes for Thomas Millington, and | are to be
sold at his shop vnder S. Peters church | in Cornewall. |
<span class="nowrap">1600. |</span></p>
</div>

<p>Copies with this title are in the Library of the Duke of
Devonshire, and in the Bodleian (Malone, 867). An imperfect
copy, wanting the last seven leaves, is in the Capell
collection. Another impression bearing the same date,
‘Printed by W. W. for Thomas Millington,’ is said to
exist, but we have been unable to find it. The MS. title
quoted by Mr Halliwell from a copy in the Bodleian (Malone,
36) is prefixed to what appears to us unquestionably
the same edition as the above. The minute correspondence
of misplaced and defective letters between this copy and
Capell’s, with which, as well as with the other copy in the
Bodleian, we have compared it, proves beyond question that
all three must have been printed from the same form, and
that the MS. title inserted in Malone’s copy is out of place.
So far therefore from Capell’s imperfect copy of this edition
being unique, as Mr Halliwell states, there are at least two
other perfect copies in existence, besides one which only
wants the title-page. In Lowndes’s <i>Bibliographer’s Manual</i>
(ed. Bohn, p. 2281), another is said to be in the possession
of Mr Tite. The late Mr George Daniel is stated, on the
same authority, to have had the editions printed by Valentine
Simmes and by W. W. in one volume, but they were
not sold at his sale, and we have been unable to trace
them.</p>

<p>In 1619, a third edition (<span class="nowrap">Q<sub>3</sub></span>) without date, printed by
Isaac Jaggard, and including also ‘The True Tragedy of
Richard Duke of York,’ appeared with the following title:</p>

<div class="blockquot">
<p>The | Whole Contention | betweene the two Famous Houses,
<span class="smcaps">L<span>ANCASTER</span></span> and | <span class="smcaps">Y<span>ORKE</span>.</span> | <i>With the Tragicall ends of the good
Duke</i> | Humfrey, Richard Duke of Yorke, | <i>and King Henrie
the</i> | <i>sixt</i>. | Diuided into two Parts: And newly corrected and |
enlarged. Written by <i>William Shake-</i>|<i>speare</i>, Gent. | Printed at
<span class="smcaps">L<span>ONDON</span>,</span> for
<span class="nowrap">T. P. |</span></p>
</div>

<p>On the title-page of his copy of this edition, Capell has
added in MS. the date ‘1619.—at the same time with the
Pericles that follows; as appears by the continuation of
the signatures.’ The signatures of ‘The whole Contention’
are from A to Q in fours, while in <i>Pericles</i>, ‘Printed for
T. P. 1619,’ the first page has signature R, which shows
that the two must have formed part of the same volume.</p>

<p>‘The True Tragedy of Richard Duke of York,’ which
formed the ground-work of The Third part of King Henry
the Sixth, was first printed in small 8vo. in 1595, with the
following title:</p>

<div class="blockquot">
<p>The | true Tragedie of Richard | <i>Duke of Yorke, and the death
of</i> | good King Henrie the Sixt, | <i>With the whole contention betweene</i>
| the two Houses Lancaster | and Yorke, as it was sundrie
times | acted by the Right Honoura-|ble the Earle of Pem-|brooke
his seruants. | Printed at London by P. S. for Thomas Milling-|<i>ton,
and are to be sold at his shoppe vnder</i> | <i>Saint Peters Church
in</i> | <i>Cornwal</i>,
<span class="nowrap">1595. |</span></p>
</div>

<p>A unique copy of this edition is in the Bodleian Library
(Malone, 876). Although printed in 8vo. we have quoted it
as <span class="nowrap">Q<sub>1</sub></span>, in order to avoid introducing a new notation.</p>

<p>The second edition (<span class="nowrap">Q<sub>2</sub></span>) was printed in 1600, with the
following title:</p>

<div class="blockquot">
<p>The | True Tragedie of | Richarde Duke of | Yorke, and the
death of good | King Henrie the sixt: | With the whole contention
betweene the two | Houses, Lancaster and Yorke; as it was |
sundry times acted by the Right | Honourable the Earle | of
Pembrooke his | seruantes. | Printed at London by <i>W. W.</i> for
<i>Thomas Millington</i>, | and are to be sold at his shoppe vnder
Saint | Peters Church in Cornewall. |
<span class="nowrap">1600. |</span></p>
</div>

<p>Copies of this edition are in the Duke of Devonshire’s
Library, the Bodleian (Malone, 36), and the British Museum.
In Malone’s Shakespeare (ed. 1790, Vol. I. Pt. I.
p. 235), among the ‘Dramatick Pieces on which plays were
formed by Shakespeare,’ an edition of The True Tragedy
is mentioned, bearing date ‘1600, V. S. for Thomas Millington,’
but in a note to the ‘Third Part of King Henry
VI.’ (Vol. <span class="smmaj">VI</span>. p. 261) he confesses, ‘I have never seen the
quarto copy of the <i>Second</i> part of The whole Contention,
&amp;c. printed by <i>Valentine Simmes</i> for Thomas Millington,
1600;’ and it is extremely doubtful whether such a one
exists. A copy of The True Tragedy, and not, as stated in
Bohn’s Lowndes, of The First Part of the Contention,
printed by W. W. 1600, was sold at Rhodes’s sale in 1825
(No. 2113). The only authority therefore for the existence
of an edition of The First Part of the Contention, printed
by W. W. in 1600, is the MS. title-page of Malone’s copy
in the Bodleian Library. Capell merely quotes it on the
authority of Pope, and all that Pope says in the Table at
the end of his first edition, after giving the title of The
Whole Contention printed in 1619, is, ‘Since Printed under
the same Title by <i>W. W.</i> for <i>Tho. Millington</i>, with the
true Tragedy of <i>Richard</i> D. of <i>York</i>, and the Death of
good King <i>Henry</i> the 6th, acted by the Earl of Pembroke
his servants 1600.’ This clearly refers to the second Quarto
of The True Tragedy, not to that of The First Part of the
Contention, and appears to us to be the origin of the
<span class="nowrap">error†.</span></p>

<p class="footnote"> <span class="fnline"> </span>
 † This view is further confirmed by a manuscript note at the back
 of the title-page of Steevens’s copy of The True Tragedy, ed. 1600,
 now in the British Museum. It shews that Pope is the only authority
 for the statement, and is as follows: ‘This is only the <i>third</i> part
 of K. Henry VI. The <i>second</i> part, according to Pope, was likewise
 printed in 1600, by W. W. for Thos. Millington. MALONE.’</p>

<p>The third edition (<span class="nowrap">Q<sub>3</sub></span>) of The
True Tragedy formed the second part of The Whole Contention described
above. It has no separate title-page, but merely the heading:</p>

<div class="blockquot">
<p>The Second Part. | Containing the Tragedie of | Richard
Duke of Yorke, and the | <i>good King Henrie the</i> |
<span class="nowrap">Sixt. |</span></p>
</div>

<p>We have reprinted the text of The First Part of the
Contention and of The True Tragedy from the first edition
of each, giving in notes at the foot of the page the various
readings of the second and third editions. For this purpose
we collated Mr Halliwell’s reprint for the Shakespeare
Society with the originals in the Bodleian Library. The
accuracy of Mr Halliwell’s work materially facilitated our
labours, and we can only hope that the errors of our own
reprint may be as few and as unimportant as those we
have discovered in his. For the readings of the second
Quartos of The First Part of the Contention and The
True Tragedy we collated the copies in the Bodleian and
the Duke of Devonshire’s Library, using also for the former
the imperfect copy in the Capell collection. The readings
of The Whole Contention (<span class="nowrap">Q<sub>3</sub></span>) have been given from Capell’s
copy verified by reference to that in the Devonshire
Library.</p>

<p>With regard to the authorship of The First Part of the
Contention and The True Tragedy, while we cannot agree
with Malone on the one hand that they contain nothing of
Shakespeare’s, nor with Mr Knight on the other that they
are entirely his work, there are so many internal proofs of
his having had a considerable share in their composition,
that, in accordance with our principle, we have reprinted
them in a smaller type.</p>

<p>The first edition of <span class="smcaps">K<span>ING</span></span> <span class="smcaps">R<span>ICHARD</span></span> is a Quarto printed
in 1597, with the following title-page:</p>

<div class="blockquot">
<p>The Tragedy of | King Richard the third. | Containing, | His
treacherous Plots against his brother Clarence: | the pittiefull
murther of his innocent nephewes: | his tyrannicall vsurpation:
with the whole course | of his detested life, and most deserued
death. | As it hath beene lately Acted by the | Right honourable
the Lord Chamber-|laine his seruants. | AT LONDON | Printed
by Valentine Sims, for Andrew Wise, | dwelling in Paules
Church-yard, at the | Sign of the Angell. |
<span class="nowrap">1597. |</span></p>
</div>

<p>This edition is referred to, in our notes, as <span class="nowrap">Q<sub>1</sub>.</span></p>

<p>We have collated a complete copy belonging to the
Duke of Devonshire and also an imperfect copy formerly
belonging to Malone and now in the Bodleian. Malone
had supplied the missing leaves by the insertion of some
from the second <span class="nowrap">Quarto†.</span> There is no copy in the Capell
collection.</p>

<p class="footnote"> <span class="fnline"> </span>
 † He says in a MS. note: ‘This copy of the original edition of King
 Richard III. was imperfect, when I purchased it, wanting signat.
 C 1 and 2, D 4, L 4, and M 1, 2, and 3. These seven leaves I have
 supplied from a later copy (that of 1598), and have collated with
 the edition of 1597. The variations are set down in the margin.’ He
 adds: ‘Mr Penn Ashton Curzon and Mr Kemble are possessed of copies
 of this original edition of this play: I know of no other, except
 that in this volume.’ Mr Kemble’s copy is now in the Devonshire
 Library, and Mr Curzon’s is probably the same which was sold at
 Mr Daniel’s sale and is now in the possession of Mr Huth. Besides
 the leaves of Malone’s copy which are missing, signatures C 3 and
 C 4 are imperfect, the upper half of each being supplied from the
 edition of 1598.</p>

<p>The second edition, also in Quarto, which we call <span class="nowrap">Q<sub>2</sub>,</span>
was published in the following year, with the name of the
author. It is in other respects a reprint of the first. The
title-page is as follows:</p>

<div class="blockquot">
<p>THE | TRAGEDIE | of King Richard | the third. | Conteining
his treacherous Plots against his | brother <i>Clarence</i>: the
pitiful murther of his innocent | Nephewes: his tyrannicall vsurpation:
with | the whole course of his detested life, and most |
<i>deserued death</i>. | <i>As it hath beene lately Acted by the Right honourable</i>|
<i>the Lord Chamberlaine his seruants</i>. | <i>By</i> William Shakespeare.|
LONDON | Printed by Thomas Creede, for Andrew
Wise, | dwelling in Paules Church-yard, at the signe | of the
Angell.
<span class="nowrap">1598. |</span></p>
</div>

<p>The third Quarto, our <span class="nowrap">Q<sub>3</sub>,</span> has the following title-page:</p>

<div class="blockquot">
<p>THE | TRAGEDIE | of King Richard | the third. | <i>Conteining
his treacherous Plots against his brother</i> | <i>Clarence</i>: the
pittifull murther of his innocent Ne-|phewes: his tyrannicall
vsurpation: with the | whole course of his detested life, and |
most deserued death. | <i>As it hath bene lately Acted by the Right
Honourable</i> | <i>the Lord Chamberlaine his seruants</i>. | Newly augmented,|
By <i>William Shakespeare</i>. | LONDON | Printed by
Thomas Creede, for Andrew Wise, dwelling | in Paules Churchyard,
at the signe of the | Angell.
<span class="nowrap">1602.|</span></p>
</div>

<p>Notwithstanding the words ‘newly augmented,’ this
edition contains nothing that is not found in the second
Quarto, from which it is reprinted, except some additional
errors of the press.</p>

<p>The fourth Quarto, our <span class="nowrap">Q<sub>4</sub>,</span> was printed from the third,
by the same printer for a different bookseller, as appears
by the title-page:</p>

<div class="blockquot">
<p>THE | TRAGEDIE | of King Richard | the third. | <i>Conteining
his treacherous Plots against his brother | Clarence</i>: the pittifull
murther of his innocent Ne-|phewes: his tyrannicall vsurpation:
with the | whole course of his detested life, and | most deserued
death. | <i>As it hath bin lately Acted by the Right Honourable | the
Lord Chamberlaine his seruants</i>. | Newly augmented, | By <i>William
Shake-speare</i>. | <span class="smcaps">L<span>ONDON</span>,</span> | Printed by Thomas Creede, and
are to be sold by <i>Mathew | Lawe</i>, dwelling in Paules Church-yard,
at the Signe | of the Foxe, neare S. Austins gate,
<span class="nowrap">1605. |</span></p>
</div>

<p>There is no copy of <span class="nowrap">Q<sub>4</sub></span> in the Capell collection. We
have collated one in the Bodleian which formerly belonged
to Malone. It is numbered 880.</p>

<p>The fifth Quarto, <span class="nowrap">Q<sub>5</sub>,</span> was printed in 1612, not from its
immediate predecessor, but from the Quarto of 1602,
although it was printed by the same printer and for the
same bookseller as that of 1605. The title-page of <span class="nowrap">Q<sub>5</sub></span>
is as follows:</p>

<div class="blockquot">
<p>THE | TRAGEDIE | of King Richard | the third. | <i>Containing
his treacherous Plots against his brother | Clarence</i>: the
pittifull murther of his innocent Ne-phewes: his tyrannicall
vsurpation: with the | whole course of his detested life, and |
most deserued death. | <i>As it hath beene lately Acted by the Kings
Maiesties | seruants</i>. | Newly augmented, | By <i>William Shake-speare</i>.
| <span class="smcaps">L<span>ONDON</span>,</span> | Printed by Thomas Creede, and are to be
sold by Mathew | Lawe, dwelling in Pauls Church-yard, at the
Signe | of the Foxe, neare S. Austins gate,
<span class="nowrap">1612. |</span></p>
</div>

<p>The edition of 1622 is so rare that its very existence
has been called in <span class="nowrap">question†.</span> There is however a copy
in the Capell collection, of which the title-page is as
follows:</p>

<p class="footnote"> <span class="fnline"> </span>
 † ‘An impression of 1622 is mentioned in some lists, but the
 existence of a copy of that date is more than doubtful.’ Collier,
 Ed. 2, Vol. iv. p. 217.</p>

<div class="blockquot">
