NOTES to<br> II KING HENRY VI.</h2></div>

<h3 class="h3main">
<span class="smcaps">N<span>OTE</span></span> I.</h3>

<div class="right toppada"><small><a href="#idtoc" class="pginternal">toc</a></small></div>

<p><span class="nowrap">
<a href="#lnum-baa062" class="pginternal"><span class="smmaj">I</span>. 1. 62.</a>
</span>
This passage, which is printed as prose in the Quartos,
is arranged and read by Capell thus:</p>

<div class="poembox">
<div class="dverseq">‘And girt thee with the sword.—</div>
<div class="dverse">Cousin of York, we here discharge your grace</div>
<div class="dverse">From being regent in the parts of France,</div>
<div class="dverse">’Till term of eighteen months be full expir’d.—</div>
<div class="dverse">Thanks, uncle Winchester, Gloster, York, and Buckingham,</div>
<div class="dverse">Somerset, Salisbury, and Warwick, thanks:</div>
<div class="dverse">We thank you, &amp;c.’</div></div>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> II.</h3>

<p><span class="nowrap">
<a href="#lnum-bac208" class="pginternal"><span class="smmaj">I</span>. 3. 208.</a>
</span>
Theobald inserts here two lines from the old play: </p>

<div class="poembox">
<div class="dverseq"><i>‘K. Hen.</i> Then be it so: My Lord of Somerset,</div>
<div class="dverse"> <span class="i05"> </span> We make your Grace Regent over the French.’</div></div>

<p class="continue">We have omitted them, agreeing with Capell, Malone, Mr Knight, Mr
Collier, and Mr Grant White, that their insertion is not absolutely
necessary. Besides Shakespeare would hardly have left so lame a line
as the second unaltered. It is possible that some such line as the
following may have dropped out:</p>

<div class="poembox">
<div class="dverseq"><i>‘King.</i> Then be it so: this is King Henry’s
doom.’</div></div>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> III.</h3>

<p><span class="nowrap">
<a href="#lnum-sc4" class="pginternal"><span class="smmaj">I</span>. 4.</a>
</span> At the commencement of this scene Rowe, and Pope in his first
edition, inserted the stage direction ‘Flourish’ which belongs to the
end of the previous scene. Pope, in his second edition, omitted it
altogether, and Theobald restored it to its right place.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> IV.</h3>

<p><span class="nowrap">
<a href="#lnum-bba084" class="pginternal"><span class="smmaj">II</span>. 1. 84.</a>
</span> Having recorded up to this point throughout the scene
all the cases in which the arrangement of the lines in the Folios is
defective, we have thought it unnecessary to do so any more, except
where there is any doubt as to what the true arrangement should be. The
restoration of the metre is, in almost all instances, due to Pope.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> V.</h3>

<p><span class="nowrap">
<a href="#lnum-bba125" class="pginternal"><span class="smmaj">II</span>. 1. 125–132.</a>
</span> In the first Folio this passage
stands as follows:</p>

<div class="poembox">
<div class="dverseq">‘Then Saunder, sit there,</div>
<div class="dverse">The lying’st Knave in Christendome.</div>
<div class="dverse">If thou hadst beene borne blind,</div>
<div class="dverse">Thou might’st as well haue knowne all our Names,</div>
<div class="dverse">As thus to name the seuerall Colours we doe weare.</div>
<div class="dverse">Sight may distinguish of Colours:</div>
<div class="dverse">But suddenly to nominate them all,</div>
<div class="dverse">It is impossible.</div>
<div class="dverse">My Lords, Saint <i>Albone</i> here hath done a Miracle:</div>
<div class="dverse">And would ye not thinke it, Cunning to be great,</div>
<div class="dverse">That could restore this Cripple to his Legges againe.’</div></div>

<p class="continue">Pope alters the first four lines thus:</p>

<div class="poembox">
<div class="dverseq">‘Saunder, sit there, the lying’st knave in christendom.</div>
<div class="dverse">If thou hadst been born blind,</div>
<div class="dverse">Thou might’st as well know all our names, as thus</div>
<div class="dverse">To know the several colours we do wear.’</div></div>

<p class="continue">The following is Hanmer’s reading of the first six lines:</p>

<div class="poembox">
<div class="dverseq">‘Then, Saunder, sit thou there, the lying’st knave</div>
<div class="dverse">In christendom. If thou hadst been born blind,</div>
<div class="dverse">Thou might’st as well know all our names, as thus</div>
<div class="dverse">To know the several colours we do wear.</div>
<div class="dverse">Sight may distinguish colours: true, but suddenly</div>
<div class="dverse">To nominate them all, it is impossible.’</div></div>

<p class="continue">In the rest of the scene several arbitrary changes have been made by
different editors for the sake of the metre.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> VI.</h3>

<p><span class="nowrap">
<a href="#lnum-bbb045" class="pginternal"><span class="smmaj">II</span>. 2. 45, 46.</a>
</span> The first Folio has the whole passage thus:</p>

<div class="poembox">
<div class="dverseq">‘His eldest Sister, <i>Anne</i>,</div>
<div class="dverse">My Mother being Heire vnto the Crowne,</div>
<div class="dverse">Marryed <i>Richard</i>, Earle of Cambridge,</div>
<div class="dverse">Who was to <i>Edmond Langley</i>,</div>
<div class="dverse"><i>Edward</i> the thirds fift Sonnes Sonne;</div>
<div class="dverse">By her I clayme the Kingdome:</div>
<div class="dverse">She was Heire to <i>Roger</i>, Earle of March,</div>
<div class="dverse">Who was the Sonne of <i>Edmond Mortimer</i></div>
<div class="dverse">Who marryed <i>Phillip</i>, sole Daughter</div>
<div class="dverse">Vnto <i>Lionel</i>, Duke of Clarence.’</div></div>

<p class="continue">The later Folios follow the first, except that in the seventh line they
read ‘She then was’ for ‘She was.’</p>

<p>Rowe read, ‘Who was son to Edmond Langley,’ but made no other change;
and Pope followed him.</p>

<p>Theobald read:</p>

<div class="poembox">
<div class="dverseq">‘Who was the son to Edmond Langley,</div>
<div class="dverse">Edward the Third’s fifth son.’—</div></div>

<p class="continue">and arranged the following lines as they are found in our
text.</p>

<p>Hanmer:</p>

<div class="poembox">
<div class="dverseq">‘Who was the son of Edmund Langley,</div>
<div class="dverse">Edward the Third’s fifth son’s son, and by her</div>
<div class="dverse">I claim the kingdom, for she then was heir</div>
<div class="dverse">To Roger &amp;c.’</div></div>

<p class="continue">It was Capell who arranged the earlier lines of the speech as we
have given them. Steevens, as usual, adopted his arrangement without
acknowledging the obligation.</p>

<p>Mr Collier, in his first edition, read:</p>

<div class="poembox">
<div class="dverseq">‘Married Richard Earl of Cambridge; who was</div>
<div class="dverse">To Edmond Langley Edward the third’s fifth son, son.’</div></div>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> VII.</h3>

<p><span class="nowrap">
<a href="#lnum-bca001" class="pginternal"><span class="smmaj">III</span>. 1.</a>
</span> We retain here Salisbury and Warwick among the persons who
enter to the parliament, because they are found both in the Folios and
Quartos. In the latter their ‘exeunt’ is also marked. Capell was the
first to omit them because they do not speak throughout the scene.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> VIII.</h3>

<p><span class="nowrap">
<a href="#lnum-bcb011" class="pginternal"><span class="smmaj">III</span>. 2. 11.</a>
</span> The murderer’s answer <i>’Tis</i>, which Rowe changed to <i>Yes</i>
without authority, shows that we ought to retain the <i>Is</i> of the first
Folio notwithstanding the grammatical inaccuracy. In the Quartos the
murderer says, ‘All things <i>is</i> hansome now my Lord.’</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> IX.</h3>

<p><span class="nowrap">
<a href="#lnum-bcb026" class="pginternal"><span class="smmaj">III</span>. 2. 26.</a>
</span>
We have left ‘Nell’ in the
text as the mistake is, in all probability, Shakespeare’s own. He was
thinking of the Duchess of Gloucester. Oddly enough neither Rowe nor
Pope discovered the blunder. Shakespeare again wrote ‘Elianor’ or
‘Elinor’ for ‘Margaret’ in the 79th, the 100th, and 120th lines of this
scene. In <i>Henry V.</i> <span class="smmaj">V.</span> 1. the author has
made a similar mistake and written ‘Doll’ for ‘Nell.’ See also note
<span class="smmaj">VII</span> on <i>The Two Gentlemen of Verona</i>.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> X.</h3>

<p><span class="nowrap">
<a href="#lnum-bcb182" class="pginternal"><span class="smmaj">III</span>. 2. 182.</a>
</span> This is a striking example of the way in which
corrections were made in the successive Folios; <i>i.e.</i> by mere
guess-work, without reference to the first. The true reading escaped
the notice of all editors before Capell.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> XI.</h3>

<p><span class="nowrap">
<a href="#lnum-bdj014" class="pginternal"><span class="smmaj">IV</span>. 10. 14.</a>
</span> By comparing this scene as it stands in the Quartos with
that of the Folios it will appear that Shakespeare, in remodelling it,
intended that Iden should be alone when he encountered Cade, as his
first speech is evidently a soliloquy; and after he has killed Cade he
disposes of the body with his own hands. Shakespeare omitted, however,
to strike out the reference to the ‘five men’ in line 36.</p>

<p>Steevens who brought the servants on the stage forgot to send them off
it. The mistake remained uncorrected down to Mr Dyce’s first edition.</p>

<p>Another example of Shakespeare’s incomplete alteration of the Quarto
has been pointed out by Malone at <span class="smmaj">V.</span> 1. 56.</p>

