<h2 class="nobreak" title="NOTES to King Richard III." id="idfn">
NOTES TO<br> KING RICHARD III.</h2></div>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> I.</h3>

<div class="right toppada"><small><a href="#idtoc" class="pginternal">toc</a></small></div>

<p>The first and second Folios give the title of this play as follows:
‘The Tragedy of Richard the Third: with the Landing of Earle Richmond,
and the Battell at Bosworth Field.’ The third and fourth Folios give
the same except that for ‘Earle Richmond,’ they have ‘the Earl of
Richmond.’ The running title in all is: ‘The Life and Death of Richard
the Third.’</p>

<p>The Acts and Scenes are marked throughout in the Folios, but not in the
Quartos.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> II.</h3>

<p><span class="nowrap">
<a href="#lnum-faa098" class="pginternal"><span class="smmaj">I.</span> 1. 98–100.</a></span>
Pope reconstructed the whole passage thus:</p>

<div class="poembox">
<div class="dverseq">‘What, fellow? nought to do with mistress <i>Shore?</i></div>
<div class="dverse">I tell you Sir, he that doth naught with her,</div>
<div class="dverse">Excepting one, were best to do it secretly.’</div></div>

<p>Steevens rejecting the word ‘alone,’ as an interpolation would arrange
the last and the following lines thus:</p>

<div class="poembox">
<div class="dverseq">‘Were best to do it secretly.</div>
<div class="dverse1"><span class="sd-cn">Bra.</span>
 <span class="i13">What</span> one</div>
<div class="dverse">My lord?</div>
<div class="dverse1"><span class="sd-cn">Glou.</span>
<span class="i01">Her</span> husband, knave:—Wouldst thou betray me?’</div></div>

<p class="continue">Capell also had omitted ‘alone,’ but made an Alexandrine by continuing
the line to ‘my lord.’</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> III.</h3>

<p><span class="nowrap">
<a href="#lnum-fac016" class="pginternal"><span class="smmaj">I.</span> 3. 16.</a>
</span> Theobald substitutes ‘Stanley’ for ‘Derby’ throughout,
observing, ‘This is a blunder of inadvertence, which has run thro’
the whole chain of impressions. It could not well be original in
Shakespeare, who was most minutely acquainted with his history and the
intermarriages of the nobility...Thomas Lord Stanley was not created
Earl of Derby till after the accession of that prince (i.e. Henry
VII.); and, accordingly, afterwards in the fourth and fifth Acts of
this play, before the battel of Bosworth-field, he is every where
call’d Lord Stanley. This sufficiently justifies the change I have made
in his title.’</p>

<p>This statement is not quite correct. He is called ‘Derby’ (the word
being, of course, variously spelt) throughout the first and second
Acts. He is called ‘Lord Stanley’ for the first time in Act <span class="smmaj">III.</span>
Scene 2. In Act <span class="smmaj">III.</span> Scene 4 he is called ‘Derby’ in the stage
directions and ‘Stanley’ in the text. He is ‘Stanley’ in Act <span class="smmaj">IV.</span>
Scene 1. In Act <span class="smmaj">IV.</span> Scenes 2 and 3, we find in the Folio ‘Stanley’
both in the stage directions and the text. In the Quarto it is ‘Derby,’
in the stage directions, the name not occurring in the text. In Act
<span class="smmaj">IV.</span> Scene 4, he is called ‘Derby’ in the stage directions. In Act
<span class="smmaj">V.</span> Scene 2, Richmond speaks of him as ‘my father Stanley,’ and in the
next scene he is called ‘Derby’ in the stage directions, and ‘Stanley’
in the text.</p>

<p>The error must have been due to the author, who would not have written
‘my lord of Stanley,’ and therefore we have retained ‘Derby’ wherever
both Quarto and Folio agree in reading it. ‘An editor,’ says Mr Grant
White, ‘is not justifiable in substituting what his author should have
written for what he did write.’</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> IV.</h3>

<p><span class="nowrap">
<a href="#lnum-fac322" class="pginternal"><span class="smmaj">I.</span> 3. 322.</a>
</span> In Capell’s copy of the seventh Quarto an old MS.
corrector has converted ‘we come’ into ‘welcome.’</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> V.</h3>

<p><span class="nowrap">
<a href="#lnum-fad075" class="pginternal"><span class="smmaj">I.</span> 4. 75.</a>
</span> After this line which is assigned to ‘<i>Keep.</i>’ like
the foregoing lines, the Folios insert the stage direction, ‘Enter
Brackenbury the Lieutenant,’ and then prefix ‘<i>Bra.</i>’ to the next
line, as if Brackenbury and the keeper had been two different persons,
instead of being identical as they are in the Quartos. Pope restored
the reading of the Quartos. Mr Grant White defends the stage directions
of the Folios thus: ‘It was a violation of all propriety to make Sir
Robert Brakenbury, Lieutenant of the Tower, go about with a bunch of
ponderous keys at his girdle or in his hand. These keys were evidently
carried by the keeper, a higher sort of gaoler, but a person of rank
much inferior to that of Brakenbury, the commander of the Tower. The
stage direction and the prefixes of the quarto are probably the result
of the limited number of actors in Shakespeare’s company when the
play was first produced, which caused the easily merged parts of the
<i>Keeper</i> and <i>Brakenbury</i> to be assigned to one performer.’</p>

<p>But Clarence was no common prisoner, and there would be no degradation
in Brakenbury’s acting in person as keeper to a prince of the blood,
at a time when even menial offices were rendered by gentlemen of
good birth not only to royal personages but also to others. We may
observe—though this is of little weight—that the corrector has
omitted to provide for the <i>exit</i> of the Keeper.</p>

<p>On the whole we have decided to adhere to the Quartos, as they
undoubtedly give what Shakespeare originally wrote, and the alteration
found in the Folios is not of such obvious propriety that we should
unhesitatingly attribute it to the hand of the author.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> VI.</h3>

<p><span class="nowrap">
<a href="#lnum-fad110" class="pginternal"><span class="smmaj">I.</span> 4. 110.</a>
</span> The speeches in this part of the scene, which are
obviously prose, are printed in the Quartos and Folios as lines of
verse of various lengths.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> VII.</h3>

<p><span class="nowrap">
<a href="#lnum-fad255" class="pginternal"><span class="smmaj">I.</span> 4. 255–264.</a>
</span> This passage, including the lines immed­iate­ly
preceding, stands thus in the first Quarto, which is followed by the
rest, substantially:</p>

<div class="poembox">
<div class="dverse1">‘<span class="sd-cn">2</span> What shall we doe?</div>
<div class="dverse1"><span class="sd-cn">Cla.</span> Relent, and saue your soules.</div>
<div class="dverse1"><span class="sd-cn">1</span> Relent, tis cowardly and womanish.</div>
<div class="dverse1"><span class="sd-cn">Cla.</span> Not to relent, is beastly, sauage, diuelish,</div>
<div class="dverse">My friend, I spie some pitty in thy lookes:</div>
<div class="dverse">Oh if thy eye be not a flatterer,</div>
<div class="dverse">Come thou on my side, and intreat for me,</div>
<div class="dverse">A begging Prince, what begger pitties not?’</div></div>

<p class="continue">It is thus amplified in the Folios:</p>

<div class="poembox">
<div class="dverse1">‘<span class="sd-cn">2</span> What shall we do?</div>
<div class="dverse1"><span class="sd-cn">Clar.</span> Relent, and saue your soules:</div>
<div class="dverse">Which of you, if you were a Princes Sonne,</div>
<div class="dverse">Being pent from Liberty, as I am now,</div>
<div class="dverse">If two such murtherers as your selues came to you,</div>
<div class="dverse">Would not intreat for life, as you would begge</div>
<div class="dverse">Were you in my distresse.</div>
<div class="dverse1"><span class="sd-cn">1</span> Relent? no: ’Tis cowardly and womanish.</div>
<div class="dverse1"><span class="sd-cn">Cla.</span> Not to relent, is beastly, sauage, diuellish:</div>
<div class="dverse">My Friend, I spy some pitty in thy lookes:</div>
<div class="dverse">O, if thine eye be not a Flatterer,</div>
<div class="dverse">Come thou on my side, and intreate for mee,</div>
<div class="dverse">A begging Prince, what begger pitties not.</div>
<div class="dverse1"><span class="sd-cn">2</span> Looke behind you, my Lord.’</div></div>

<p>Pope adopted the reading of the Quartos, rejecting the last line ‘a
begging...not?’ He was followed by Hanmer and Capell. Theobald followed
the Folios, reading <i>for life? Ah! you...distress.</i> Johnson, who gives
in his text the arrangement which Warburton had borrowed from Theobald,
says, in a note: ‘I cannot but suspect that the lines, which Mr Pope
observed not to be in the old edition, are now misplaced, and should be
inserted here, somewhat after this manner.</p>

<div class="poembox">
<div class="dverseq">“<span class="sd-cn">Clar.</span> A begging...pities not?</div>
<div class="dverse"><span class="sd-cn">Vil.</span> A begging prince!</div>
<div class="dverse"><span class="sd-cn">Clar.</span> Which of you if you were
 a prince’s son, &amp;c.”</div></div>

<p class="continue">Upon this provocation the villain naturally strikes him.’</p>

<p>The arrangement which we have adopted was first suggested by Tyrwhitt
and introduced into the text by Steevens, 1793. It involves a rather
violent transposition, but we see no better remedy. As the lines
omitted in the Quarto have all the appearance of being Shakespeare’s
own, we cannot leave them out of the text. We think, however, that they
are out of their right place in the Folio, and that the transposition
suggested by Johnson does not yield a satisfactory sense.</p>

<p>Mr Grant White says: ‘Mr Knight, Mr Collier, Mr Verplanck, and Mr
Hudson follow the Folio; the last only attaining a tolerable sense, by
supposing <i>Clarence’s</i> question, as it appears in the folio, to end at
“would not intreat for life,” and the <i>Murderer</i> to interrupt him in
the beginning of a new sentence, thus:—</p>

<div class="poembox">
<div class="dverseq">‘Which of you, &amp;c........</div>
<div class="dverse">Would not entreat for life? As you would beg,</div>
<div class="dverse">Were you in my distress,—</div>
<div class="dverse1"><span class="sd-cn">1 Murd.</span> Relent!’
 &amp;c.—</div></div>

<p class="continue">presuming, I suppose, the Duke to be about to say, ‘As you would beg,
&amp;c., <i>so I beg</i>,’ &amp;c. I am unable to look so far into <i>Clarence’s</i>
intentions as to decide upon the merits of this reading.’</p>

<p>The punctuation proposed by Mr Hudson had suggested itself
independently to Mr Spedding. The chief objection however to the
reading of the Folio still remains, viz. the awkwardness of the
murderer’s taking up Clarence’s word ‘Relent’ after so long an
interval. If, as we suppose, Shakespeare wrote those additional lines
in the margin of his original MS., nothing is more likely than that
a copyist should have misplaced them. In <span class="smmaj">IV.</span> 3, 52, 53, two lines
undoubtedly added by Shakespeare are thus misplaced in the Folio:</p>

<div class="poembox">
<div class="dverseq">‘That reignes in gauled eyes of weeping soules:</div>
<div class="dverse">That excellent grand Tyrant of the earth.’</div></div>

<p>Similarly in Act <span class="smmaj">II.</span> Scene 1, the line</p>

<div class="poembox">
<div class="dverseq">‘Of you Lord Wooduill, and Lord Scales of you,’</div></div>

<p class="continue">which the corrector intended to follow 66, is placed in the Folio after
67. We have not introduced this line into the text, because Shakespeare
would not have introduced it after line 66 as it stands in the Quarto,
nor have altered that line as it is altered in the Folio.</p>

<p>See also <span class="nowrap"><span class="smmaj">IV.</span> 4, 100–104,</span>
where, in correcting one mistake of
transposition, another has been made.</p>

<p>See also Note (<span class="smmaj">XIX</span>).</p>

<p>Mr Collier in his second edition, following in other respects the
Folio, inserts three words suggested by his old MS. corrector, thus:</p>

<div class="poembox">
<div class="dverse">‘Would not entreat for life? As you would beg</div>
<div class="dverse">Were you in my distress, <i>so pity me</i>.’</div></div>

<p>Mr Knight’s arrangement (ed. 1839), in which he says he has followed
‘the Folio, instead of adopting the arbitrary regulations of the modern
editors,’ is this:</p>

<div class="poembox">
<div class="dverseq">‘<span class="sd-cn">Clar.</span> Not...................devilish.</div>
<div class="dverse"> <span class="i04"> </span>My friend................</div>
<div class="dverse">  ...............pities not?</div>
<div class="dverse">  Which of you..................</div>
<div class="dverse">  ............distress?’</div></div>

<p>Here perhaps the printer has mistaken Mr Knight’s marginal directions.
If such an error can escape the notice of so careful an editor, how
likely is it to occur in the Folio which could hardly be said to have
an editor at all!</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> VIII.</h3>

<p><span class="nowrap">
<a href="#lnum-fbc012" class="pginternal"><span class="smmaj">II.</span> 3. 12.</a></span>
Johnson supposed that a line had been lost between lines
12 and 13 after ‘government.’ Malone conjectured that one had been lost
after ‘council under him,’ line 13.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> IX.</h3>

<p><span class="nowrap">
<a href="#lnum-fbd001" class="pginternal"><span class="smmaj">II.</span> 4. 1, 2.</a></span>
The Quarto here reads:</p>

<div class="poembox">
<div class="dverseq">‘Last night I heare they lay at Northhampton.</div>
<div class="dverse">At Stonistratford will they be to night.’</div></div>

<p class="continue">The Folio:</p>

<div class="poembox">
<div class="dverseq">‘Last night I heard they lay at Stony Stratford,</div>
<div class="dverse">And at Northampton they do rest to night.’</div></div>

<p class="continue">Pope:</p>

<div class="poembox">
<div class="dverseq">‘I heard they lay the last night at Northampton,</div>
<div class="dverse">At Stony-Stratford they do rest to-night.’</div></div>

<p class="continue">Capell:</p>

<div class="poembox">
<div class="dverseq">‘Last night, I hear, they rested at Northampton;</div>
<div class="dverse">At Stony-stratford they do lye to-night.’</div></div>

<p>The correction found in the Folio was probably made, as Malone says,
simply for the sake of the metre. The Folio reading accidentally
coincides with the statement of Hall’s Chronicle, but (what is of more
consequence) it is inconsistent with the next line of the Archbishop’s
speech.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> X.</h3>

<p><span class="nowrap">
<a href="#lnum-fbd037" class="pginternal"><span class="smmaj">II.</span> 4. 37.</a></span>
We have followed the Folios in reading ‘Enter a Messenger’
and in assigning the speeches that follow to him rather than to the
Marquess Dorset as is the case in the Quartos. The change must have
been deliberate, and as the Queen does not greet the person who brings
the intelligence, and expresses no anxiety for his safety when she
herself is going to sanctuary, it seems more proper that the messenger
should be one of inferior rank than one so nearly connected with the
Queen. His ignorance of the cause of the arrest of the nobles and the
terms in which he speaks of them are in keeping with the character
of a messenger. In Act <span class="smmaj">IV.</span> Scene 1, the Queen, apparently, meets
Dorset for the first time since Richard’s designs were disclosed, and
passionately urges his escape.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> XI.</h3>

<p><span class="nowrap">
<a href="#lnum-fca169" class="pginternal"><span class="smmaj">III.</span> 1. 169, &amp;c.</a>
</span> The reading of the first Quarto is:</p>

<div class="poembox">
<div class="dverseq">‘Well then no more but this:</div>
<div class="dverse">Go gentle Catesby, and as it were a farre off,</div>
<div class="dverse">Sound thou Lo: Hastings, how he stands affected</div>
<div class="dverse">Vnto our purpose, if he be willing,</div>
<div class="dverse">Encourage him &amp;c.’</div></div>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> XII.</h3>

<p><span class="nowrap">
<a href="#lnum-fcb091" class="pginternal"><span class="smmaj">III.</span> 2. 91–93.</a>
</span> In the first Quarto the
passage reads thus:</p>

<div class="poembox">
<div class="dverseq">‘But come my Lo: shall we to the tower?</div>
<div class="dverse1"><span class="sd-cn">Hast.</span> I go: but stay, heare you not the newes.</div>
<div class="dverse">This day those men you talkt of, are beheaded.’</div></div>

<p class="continue">The reading of the Folios, which we have retained, is not satisfactory,
and looks like an attempt of the editors to amend the defective metre
of the Quartos. The scene opens at four in the morning, and yet Stanley
is made to say, ‘the day is spent.’</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> XIII.</h3>

<p><span class="nowrap">
<a href="#lnum-fcd005" class="pginternal"><span class="smmaj">III.</span> 4. 5.</a>
</span> We retain here the reading in which both the earliest
Quartos and the Folios agree. It doubtless came from the pen of the
author, and is after all a pardonable inaccuracy, such as may easily
escape from the pen of a rapid writer or the tongue of a ready talker.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> XIV.</h3>

<p><span class="nowrap">
<a href="#lnum-fcd010" class="pginternal"><span class="smmaj">III.</span> 4. 10–13.</a></span>
We keep the reading of the Quartos but have made a
change in the arrangement of the lines. This is the text of the Quartos:</p>

<div class="poembox">
<div class="dverse1">‘<span class="sd-cn">Buc.</span> Who I my Lo? we know each others faces:</div>
<div class="dverse">But for our harts, he knowes no more of mine,</div>
<div class="dverse">Then I of yours: nor I no more of his, then you of mine:’</div></div>

<p class="continue">The Folio reads:</p>

<div class="poembox">
<div class="dverse1">‘<span class="sd-cn">Buck.</span> We know each others Faces: for our Hearts,</div>
<div class="dverse">He knowes no more of mine, then I of yours,</div>
<div class="dverse">Or I of his, my Lord, then you of mine.’</div></div>

<p class="continue">Pope follows the Folios, but reads
‘Nor’ for ‘Or’ in the last line.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> XV.</h3>

<p><span class="nowrap">
<a href="#lnum-fcd078" class="pginternal"><span class="smmaj">III.</span> 4. 78–80.</a></span>
The first Folio reads:</p>

<div class="poembox">
<div class="dverseq">‘Off with his Head; now by Saint <i>Paul</i> I sweare,</div>
<div class="dverse">I will not dine, untill I see the same.</div>
<div class="dverse">Lovell and Ratcliffe, looke that it be done.’</div></div>

<p class="continue">The first Quarto has:</p>

<div class="poembox">
<div class="dverseq">‘Off with his head. Now by Saint Paule,</div>
<div class="dverse">I will not dine to day I sweare,</div>
<div class="dverse">Vntill I see the same, some see it done.’</div></div>

<p>Theobald altered Ratcliffe to Catesby, observing in his note, ‘The
scene is here in the Tower: and Lord Hastings was cut off on that very
day, when Rivers, Gray and Vaughan suffered at Pomfret. How then could
Ratcliff at the same instant be both in Yorkshire and the Tower? In
the very scene preceding this we find him conducting those gentlemen to
the block. The players in their edition first made the blunder, as to
Ratcliff attending Lord Hastings to death: for, in the old Quarto, we
find it rightly;—Exeunt: Manet Catesby with Hastings.’ But in the next
scene Theobald, while he makes Lovell and Catesby bring in the head
of Hastings, allows Gloucester, just before their entrance, to say,
‘Catesby, o’erlook the walls.’ Hanmer corrected this inconsistency by
reading, ‘Some one o’erlook the walls.’ We have followed the Folios,
for the difficulties could not be removed entirely without applying
more violence to the text than an editor is justified in using.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> XVI.</h3>

<p><span class="nowrap">
<a href="#lnum-fce010" class="pginternal"><span class="smmaj">III.</span> 5. 10–21.</a>
</span> In the first Quarto this
passage stands as follows:</p>

<div class="poembox">
<div class="dverse">And both are ready in their offices</div>
<div class="dverse">To grace my stratagems.
 <span class="sd-verseend"><i>Enter Maior.</i></span></div>
<div class="dverse1"><span class="sd-cn">Glo.</span> Here comes the Maior.</div>
<div class="dverse1"><span class="sd-cn">Buc.</span> Let me alone to entertaine him. Lo: Maior,</div>
<div class="dverse1"><span class="sd-cn">Glo.</span> Looke to the drawbridge there.</div>
<div class="dverse1"><span class="sd-cn">Buc.</span> The reason we have sent for you.</div>
<div class="dverse1"><span class="sd-cn">Glo.</span> Catesby ouerlooke the wals.</div>
<div class="dverse1"><span class="sd-cn">Buck.</span> Harke, I heare a drumme.</div>
<div class="dverse1"><span class="sd-cn">Glo.</span> Looke backe, defend thee, here are enemies.</div>
<div class="dverse1"><span class="sd-cn">Buc.</span> God and our innocence defend vs.
 <span class="sd-verseend"><i>Enter Catesby with Hast. head.</i></span></div>
<div class="dverse1"><span class="sd-cn">Glo.</span> O, O, be quiet, it is Catesby.
</div></div>

<p class="continue">In the last line <span class="nowrap">Q<sub>3</sub></span> has <i>G, O, be quiet,</i> &amp;c. Instead of lines 12–14,
<i>But what......Lord mayor,</i> Theobald read with the Quartos.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> XVII.</h3>

<p><span class="nowrap">
<a href="#lnum-fda092" class="pginternal"><span class="smmaj">IV.</span> 1. 92–94.</a>
</span> In the second Folio there is a curious mistake here. In
the margin of the first Folio, from which the second was printed, some
one had inserted the stage directions, ‘to Dorset,’ ‘to Anne,’ ‘to the
Queene,’ which the printer mistook and gave as part of the text thus:</p>

<div class="blockquot">
<p>‘<span class="sd-cn">Duc. Yorke.</span> Go to Richmond, to Dorset, to Anne, to the Queene, and
 good fortune guide thee, &amp;c.’</p>
</div>

<p>The error is repeated in the third Folio and, strange to say, corrected
in the fourth, where the stage directions are inserted in their proper
places. It also inserts the word ‘thou,’ which had been omitted in the
second and third Folios.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> XVIII.</h3>

<p><span class="nowrap">
<a href="#lnum-fdb047" class="pginternal"><span class="smmaj">IV.</span> 2. 47 sqq.</a>
</span> In this passage we have followed substantially the
reading of the Quartos in preference to that of the Folios.</p>

<p>The first Quarto reads:</p>

<div class="poembox">
<div class="dverse1">‘<span class="sd-cn">Darby.</span> My Lord, I heare the Marques Dorset</div>
<div class="dverse">Is fled to Richmond, in those partes beyond the seas where he abides.</div>
<div class="dverse1"><span class="sd-cn">King.</span> Catesby.    <span class="sd-cn">Cat.</span> My Lord.</div>
<div class="dverse1"><span class="sd-cn">King.</span> Rumor it abroad</div>
<div class="dverse">That Anne my wife is sicke and like to die, &amp;c.’</div></div>

<p class="continue">In the seventh and eighth Quartos the second line of Darby’s speech is
divided ‘...seas where he abides.’</p>

<p>The first Folio has:</p>

<div class="poembox">
<div class="dverse1">‘<span class="sd-cn">Stanley.</span> Know my louing Lord, the Marquesse <i>Dorset</i></div>
<div class="dverse">As I heare, is fled to <i>Richmond</i>,</div>
<div class="dverse">In the parts where he abides.</div>
<div class="dverse1"><span class="sd-cn">Rich.</span> Come hither <i>Catesby</i>, rumor it abroad,</div>
<div class="dverse">That <i>Anne</i> my Wife is very grieuous sicke &amp;c.’</div></div>

<p>Pope follows the Folios and Rowe, except that for ‘Know, my loving
Lord,’ he substitutes ‘my lord,’ ending the next line at <i>fled</i>.
Steevens retains the reading of the Folios, but in other respects
adopts Pope’s arrangement, assigning it, more suo, to Sir Thomas Hanmer.</p>

<p>Mr Staunton follows Steevens as regards Stanley’s speech, and then
reads with the Quartos. In the preceding line he reads with the
Quartos: ‘How now what news with you?’</p>

<p>Mr Collier suspects that ‘What’s the news?’ in line 46, is an
interpolation and that the true reading is,</p>

<div class="poembox">
<div class="dverseq">‘How now, Lord Stanley?</div>
<div class="dverse1"><span class="sd-cn">Stan.</span> Know, my loving lord,</div>
<div class="dverse">The Marquess Dorset, as I hear, is fled &amp;c.’</div></div>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> XIX.</h3>

<p><span class="nowrap">
<a href="#lnum-fdd365" class="pginternal"><span class="smmaj">IV.</span> 4, 365, 366.</a>
</span> The first Quarto alone preserves the proper order of
the lines here. Its words are:</p>

<div class="poembox">
<div class="dverseq">‘<span class="sd-cn">King.</span> Harpe not one that string Madam that is past.</div>
<div class="dverse"><span class="sd-cn">Qu.</span> Harpe on it still shall I till hartstrings breake.’</div></div>

<p>The second Quarto omits the first line and gives the second to the King,
thus:</p>

<div class="poembox">
<div class="dverseq">‘<span class="sd-cn">King.</span> Harpe on it still shal I, till hartstrings breake.</div>
<div class="dverse"><span class="sd-cn">King.</span> Now by my George &amp;c.’</div></div>

<p>The third follows the second in omitting the first line, but it
continues the second to the Queen. All the remaining Quartos read with
the third.</p>

<p>The Folios give both lines, but in reverse order, thus:</p>

<div class="poembox">
<div class="dverseq"> <span class="i15"> </span>..............‘graves,</div>
<div class="dverse">Harpe on it still shall I, till heart-strings breake.</div>
<div class="dverse1"><span class="sd-cn">Rich.</span> Harpe not on that string Madam, that is past.</div>
<div class="dverse">Now by my George &amp;c.’</div></div>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> XX.</h3>

<p><span class="nowrap">
<a href="#lnum-fdd444" class="pginternal"><span class="smmaj">IV.</span> 4. 444.</a>
</span> We have here followed the reading of the Quartos, in
preference to that of the Folios, in which the passage stands as
follows:</p>

<div class="poembox">
<div class="dverseq">‘<span class="sd-cn">Rich.</span> <i>Catesby,</i> flye to the Duke.</div>
<div class="dverse"><span class="sd-cn">Cat.</span> I will, my Lord, with all convenient haste.</div>
<div class="dverse"><span class="sd-cn">Rich.</span> <i>Catesby</i> come hither, poste to Salisbury:’</div></div>

<p class="continue">This seems to show that the text of the Quartos has been amended in the
Folios by no very skilful hand. Rowe endeavoured to amend the passage
by reading in the last line ‘Ratcliff, come hither,’ and in this has
been followed by most succeeding editors.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> XXI.</h3>

<p><span class="nowrap">
<a href="#lnum-fdd512" class="pginternal"><span class="smmaj">IV.</span> 4. 512–517.</a>
</span> The Quartos here read:</p>

<div class="poembox">
<div class="dverse1">‘<span class="sd-cn">Mes.</span> Your grace mistakes, the newes I bring is good</div>
<div class="dverse">My newes is that by sudden floud, and fall of water,</div>
<div class="dverse">The Duke of Buckinghams armie is disperst and scattered,</div>
<div class="dverse">And he himselfe fled, no man knowes whether.</div>
<div class="dverse1"><span class="sd-cn">King.</span> O I crie you mercie, I did mistake,</div>
<div class="dverse">Ratcliffe reward him, for the blow I gaue him.’</div></div>

<p class="continue">By substituting ‘’Tis’ for ‘My newes is’ in the second line, and
‘Buckingham’s’ for ‘The Duke of Buckinghams’ in the third, the reading
of the Quartos might be retained.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> XXII.</h3>

<p><span class="nowrap">
<a href="#lnum-fde006" class="pginternal"><span class="smmaj">IV.</span> 5. 6–20.</a></span>
We have followed the Quartos in the arrangement of the
lines of this scene. The Folios insert after line 5:</p>

<div class="poembox">
<div class="dverseq">‘So get thee gone: commend me to thy Lord.</div>
<div class="dverse">Withall say, that the Oueene hath heartily consented</div>
<div class="dverse">He should espouse <i>Elizabeth</i> hir daughter.’</div></div>

<p class="continue">And in Derby’s last speech they read:</p>

<div class="poembox">
<div class="dverseq">‘Well hye thee to thy Lord: I kisse his hand,</div>
<div class="dverse">My Letter will resolue him of my minde.</div>
<div class="dverse">Farewell.’</div></div>

<p>Pope follows the Folios, except that for ‘Withall say, that’ he reads
‘Say too.’ Capell adopts the arrangement of the Quartos, but reads,
‘Well, hie thee to thy lord’ instead of ‘Return unto thy lord.’</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> XXIII.</h3>

<p><span class="nowrap">
<a href="#lnum-fec023" class="pginternal"><span class="smmaj">V.</span> 3. 23–26.</a>
</span> In the Quartos these lines are omitted in the present
speech of Richmond, but inserted a few lines lower down, as will be
seen from the following quotation from the first Quarto:</p>

<div class="poembox">
<div class="dverse1">‘<span class="sd-cn">Blunt.</span> Vpon my life my Lord, Ile vndertake it.</div>
<div class="dverse1"> <span class="sd-cn">Rich.</span> Farewell good Blunt.</div>
<div class="dverse">Give me some inke, and paper, in my tent,</div>
<div class="dverse">Ile draw the forme, and modle of our battel,</div>
<div class="dverse">Limit each leader to his seuerall charge,</div>
<div class="dverse">And part in iust proportion our small strength,</div>
<div class="dverse">Come, let vs consult vpon to morrowes busines,</div>
<div class="dverse">In to our tent, the aire is rawe and cold.’</div></div>

<p class="continue">As the Quartos omit entirely lines 27, 28 and 43, we have followed the
arrangement of the Folios.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> XXIV.</h3>

<p><span class="nowrap">
<a href="#lnum-fec145" class="pginternal"><span class="smmaj">V.</span> 3. 145.</a>
</span> In the first and second Quartos the Ghosts of the two
young Princes enter and speak before the Ghost of Hastings. The Folios
and the other Quartos make the Ghost of Hastings enter first. As a
chronological order is observed in the appearance of the other Ghosts
we have thought it best in this case to follow the latter authorities.</p>

<p>This discrepancy between the two earliest editions and the rest seems
to have escaped the notice of Capell and of all other editors.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> XXV.</h3>

<p><span class="nowrap">
<a href="#lnum-fec179" class="pginternal"><span class="smmaj">V.</span> 3. 179.</a>
</span> Warburton says: The players, among their other innumerable
absurdities, in the representation of this tragedy, make Richard say
instead of ‘O coward conscience,’ ‘O <i>tyrant</i> conscience!’</p>

<p>He refers to Colley Cibber’s adaptation of Shakespeare’s play: ‘The
Tragical History of King Richard III. Altered from Shakespear. By
Colley Cibber Esq.’</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> XXVI.</h3>

<p><span class="nowrap">
<a href="#lnum-fec204" class="pginternal"><span class="smmaj">V.</span> 3. 204–206.</a>
</span> Johnson says: ‘These lines stand with so little
propriety at the end of this speech that I cannot but suspect them to
be misplaced. Where then shall they be inserted? Perhaps after these
words, <i>Fool do not flatter</i> (i.e. line 192).’</p>

<p>Rann, following Mason’s suggestion, inserted them after ‘I fear, I
fear’ (line 214), and then, says Mason, Ratcliffe’s reply bidding
the King not be afraid of shadows, would be natural. Mr Grant White
would insert them either after line 178, ‘Soft I did but dream,’ or
after 212, ‘I have dream’d a fearful dream.’ As the Folios omit lines
212, 213, Ratcliffe’s allusion to the shadows, of which he has heard
nothing, <i>is</i> rendered absurd. Yet the absurdity escaped the notice of
all editors before Capell.</p>

<h3 class="h3main"><span class="smcaps">N<span>OTE</span></span> XXVII.</h3>

<p><span class="nowrap">
<a href="#lnum-fee001" class="pginternal"><span class="smmaj">V.</span> 5.</a>
</span> We have retained the stage direction of the Quartos and
Folios, ‘they fight. Richard is slain,’ in preference to ‘they fight,
and exeunt fighting’ of Mr Dyce, because it is probable from Derby’s
speech, ‘From the dead temples of <i>this</i> bloody wretch,’ that Richard’s
body is lying where he fell, in view of the audience.</p>

