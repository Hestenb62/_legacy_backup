<h2><a name="No1_a2" id="No1_a2"></a>
ELIZABETH BARRETT BROWNING AND THE NEGRO</h2>

<p>Elizabeth Barrett Browning was a poetic artist who was intensely
concerned with the large human movements of the world and the age into
which she was thrown. Her whole life was one great heart-throb. While
the condition of her health and the nature of her early training were
such as to cultivate her rather bookish and romantic temperament, she
followed with eagerness the great social reforms in England in the
reign of William IV and the early years of Victoria; and <i>The Cry of
the Children</i> and <i>The Cry of the Human</i> indicated what was to be one
of her chief lines of interest. In her later years she threw herself
heart and soul into the cause of Italian independence and unity,
welcoming Napoleon III as a benefactor. Her political judgment was not
always sound: her distinguished husband could not possibly follow her
in her admiration for Napoleon, whom he regarded as to some extent at
least a charlatan, and Cavour simply represented his countrymen in his
amazement and chagrin at the terms of the Peace of Villafranca;
nevertheless the great heart of Elizabeth Barrett Browning was ever
moved by the demands of liberty, whether the immediate impulse was a
child in the sweatshops of England, an Italian wishing to be free of
Austria, or the exiled Victor Hugo, and there was no exaggeration in
the tribute placed on the wall of Casa Guidi after her death:</p>

<blockquote><p class="center">
Qui scrisse e mori<br />
Elizabetta Barrett Browning<br />
che in cuore di donna conciliava<br />
scienza di dotto e spirito di poeta<br />
e fece del suo verso aureo anello<br />
fra Italia e Inghilterra<br />
pone questa lapide<br />
Firenze grata<br />
1861<a name="FNanchor_8_8" id="FNanchor_8_8"></a><a href="#Footnote_8_8" class="fnanchor">[8]</a>
</p>
</blockquote>

<p><span class='pagenum'><a name="Page_23" id="Page_23">[Pg 23]</a></span></p>

<p>To such a woman the Negro, held in slavery in a great free republic,
made a ready appeal. The first concrete connection, however, was one
directly affecting the fortunes of the Barrett family. For some years
Mr. Barrett had made his home at a beautiful estate in Herefordshire
known as Hope End. He had inherited from his maternal grandfather a
large estate in Jamaica, where the families of both his parents had
been established for two or three generations. The abolition of
slavery in the British colonies in 1833 inflicted great financial
embarrassment upon him, as a result of which he was forced to sell
Hope End and to remove his family, first to Sidmouth in Devonshire,
and subsequently to London. Elizabeth Barrett foreshadowed this change
of fortunes in a letter to her friend Mrs. Martin dated Sidmouth, May
27, 1833:</p>

<blockquote><p>The West Indians are irreparably ruined if the Bill passes. Papa
says that in the case of its passing, nobody in his senses would
think of even attempting the culture of sugar, and that they had
better hang weights to the sides of the island of Jamaica and
sink it at once.<a name="FNanchor_9_9" id="FNanchor_9_9"></a><a href="#Footnote_9_9" class="fnanchor">[9]</a></p></blockquote>

<p>In September of the same year she wrote from Sidmouth to the same
friend as follows:</p>

<blockquote><p>Of course you know that the late Bill has ruined the West
Indians. That is settled. The consternation here is very great.
Nevertheless I am glad, and always shall be, that the Negroes
are&mdash;virtually&mdash;free.<a name="FNanchor_10_10" id="FNanchor_10_10"></a><a href="#Footnote_10_10" class="fnanchor">[10]</a></p></blockquote>

<p>It is some years before we find another reference so definite. Miss
Barrett in the meantime became Mrs. Browning and under the inspiration
of love and Italy gave herself<span class='pagenum'><a name="Page_24" id="Page_24">[Pg 24]</a></span> anew to her work. The feeling for
liberty was constantly with her, as was to be seen from <i>Casa Guidi
Windows</i> and <i>Poems before Congress</i>. About 1855, when she was on a
visit to England, through the work of Daniel D. Home, a notorious
American exponent of spiritualism, Mrs. Browning became interested in
the current fad, and gave to it vastly more serious attention than
most other initiates. Browning himself, while patient, was intolerably
irritated with those whom he regarded as imposing on his wife's
credulity, and delivered himself on the subject in <i>Mr. Sludge, 'the
Medium</i>.' Spiritualism, however, was a topic of never-failing interest
between Mrs. Browning and her American friend, Harriet Beecher Stowe,
whom she entertained in Italy. <i>Uncle Tom's Cabin</i> made a profound
impression upon her. In 1853 this book was still in the great flush of
its first success. On April 12, 1853, Mrs. Browning wrote from
Florence to Mrs. Jameson as follows:</p>

<blockquote><p>Not read Mrs. Stowe's book! <i>But you must</i>. Her book is quite a
sign of the times, and has otherwise and intrinsically
considerable power. For myself, I rejoice in the success, both as
a woman and a human being. Oh, and is it possible that you think
a woman has no business with questions like the question of
slavery? Then she had better use a pen no more. She had better
subside into slavery and concubinage herself, I think, as in the
times of old, shut herself up with the Penelopes in the "women's
apartment," and take no rank among thinkers and speakers.
Certainly you are not in earnest in these things. A difficult
question&mdash;yes! All virtue is difficult. England found it
difficult. France found it difficult. But we did not make
ourselves an armchair of our sins. As for America, I honor
America in much; but I would not be an American for the world
while she wears that shameful scar upon her brow. The address of
the new president<a name="FNanchor_11_11" id="FNanchor_11_11"></a><a href="#Footnote_11_11" class="fnanchor">[11]</a> exasperates me. Observe, I am an
abolitionist, not to the fanatical degree, because I hold that
compensation should be given by the North to the South, as in
England. The states should unite in buying off this national
disgrace.<a name="FNanchor_12_12" id="FNanchor_12_12"></a><a href="#Footnote_12_12" class="fnanchor">[12]</a></p></blockquote><p><span class='pagenum'><a name="Page_25" id="Page_25">[Pg 25]</a></span></p>

<p>Under date Florence, December 11, 1854, Mrs. Browning wrote to Miss
Mitford as follows:</p>

<blockquote><p>I am reading now Mrs. Stowe's <i>Sunny Memories</i>, and like the
naturalness and simplicity of the book much, in spite of the
provincialism of the tone of mind and education, and the really
wretched writing. It's quite wonderful that a woman who has
written a book to make the world ring should write so
abominably.<a name="FNanchor_13_13" id="FNanchor_13_13"></a><a href="#Footnote_13_13" class="fnanchor">[13]</a></p></blockquote>

<p>More and more as the Civil War approached was Mrs. Browning depressed
by the thought of the impending conflict. Between June 7, 1860, and
July 25, 1861, she contributed to the recently established
<i>Independent</i> eleven poems, chiefly on subjects of Italian liberty.
Sometimes, however, especially in the letters accompanying her poems,
she touched on themes somewhat closer to the American people. For the
issue of March 21, 1861, she wrote to the editor as follows:</p>

<blockquote><p>My partiality for frenzies is not so absorbing, believe me, as to
exclude very painful consideration on the dissolution of your
great Union. But my serious fear has been, and is, not for the
dissolution of the body but the death of the soul&mdash;not of a
rupture of states and civil war, but at reconciliation and peace
at the expense of a deadly compromise of principle. Nothing will
destroy the Republic but what corrupts its conscience and
disturbs its fame&mdash;for the stain upon the honor must come off
upon the flag. <i>If, on the other hand, the North stands fast on
the moral ground, no glory will be like your glory</i>.... What
surprises me is that the slaves don't rise.</p></blockquote>

<p>On this great subject Mrs. Browning found her husband in full sympathy
with her. Browning himself declared in a letter to an American,
September 11, 1861:</p>

<blockquote><p>I have lost the explanation of American affairs, but I assure you
of my belief in the justice and my confidence in the triumph of
the great cause. For the righteousness of the principle I want no
information. God prosper it and its defenders.<a name="FNanchor_14_14" id="FNanchor_14_14"></a><a href="#Footnote_14_14" class="fnanchor">[14]</a></p></blockquote><p><span class='pagenum'><a name="Page_26" id="Page_26">[Pg 26]</a></span></p>

<p>Two poems by Mrs. Browning at least have to do directly with the Negro
and American affairs. One was <i>A Curse for a Nation</i> contributed to
the <i>Poems before Congress</i> volume. The poet begins somewhat
self-consciously:</p>

<div class="poem"><div class="stanza">
<span class="i0">I heard an angel speak last night,<br /></span>
<span class="i4">And he said "Write!<br /></span>
<span class="i0">Write a Nation's curse for me,<br /></span>
<span class="i0">And send it over the Western Sea."<br /></span>
</div></div>

<p>She protests her unwillingness to execute such a commission, for, she
says,</p>

<div class="poem"><div class="stanza">
<span class="i1">I am bound by gratitude<br /></span>
<span class="i4">By love and blood,<br /></span>
<span class="i0">To brothers of mine across the sea,<br /></span>
<span class="i0">Who stretch out kindly hands to me.<br /></span>
</div></div>

<p>The angel, however, beats down this unwillingness and the curse
follows, the second stanza reading:</p>

<div class="poem"><div class="stanza">
<span class="i0">Because yourselves are standing straight<br /></span>
<span class="i2">In the state<br /></span>
<span class="i0">Of Freedom's foremost acolyte,<br /></span>
<span class="i0">Yet keep calm footing all the time<br /></span>
<span class="i0">On writhing bond-slaves,&mdash;for this crime<br /></span>
<span class="i2">This is the curse. Write.<br /></span>
</div></div>

<p>At best, however, <i>A Curse for a Nation</i> can hardly help impressing
one as a little forced. In rather higher poetic vein is the other
poem, <i>The Runaway Slave at Pilgrim's Point</i>. This was contributed to
<i>The Liberty Bell</i>, a publication issued by the Boston Anti-Slavery
Bazar in 1848. Mrs. Browning feared that the poem might be "too
ferocious for the Americans to publish." The composition is
undoubtedly a strong one. It undertakes to give the story of a young
Negro woman who was bound in slavery, whose lover was crushed before
her face, who was forced to submit to personal violation, who killed
her child that so much reminded her of her white master's face, and
who at last at Pilgrim's Point defied her pursuers. With<span class='pagenum'><a name="Page_27" id="Page_27">[Pg 27]</a></span> unusual
earnestness the poet has entered sympathetically into the subject. The
following stanzas are typical:</p>

<div class="poem"><div class="stanza">
<span class="i0">But <i>we</i> who are dark, we are dark<br /></span>
<span class="i2">Ah God, we have no stars!<br /></span>
<span class="i0">About our souls in care and cark<br /></span>
<span class="i2">Our blackness shuts like prison-bars;<br /></span>
<span class="i0">The poor souls crouch so far behind<br /></span>
<span class="i0">That never a comfort can they find<br /></span>
<span class="i2">By reaching through the prison-bars.<br /></span>
</div><div class="stanza">
<span class="i0">* * * * * * * * * * * * * * * * * * *<br /></span>
</div><div class="stanza">
<span class="i0">Why, in that single glance I had<br /></span>
<span class="i2">Of my child's face, ... I tell you all,<br /></span>
<span class="i0">I saw a look that made me mad<br /></span>
<span class="i2">The <i>master's</i> look, that used to fall<br /></span>
<span class="i0">On my soul like his lash ... or worse<br /></span>
<span class="i0">And so, to save it from my curse,<br /></span>
<span class="i2">I twisted it round in my shawl.<br /></span>
</div><div class="stanza">
<span class="i0">* * * * * * * * * * * * * * * * * * *<br /></span>
</div><div class="stanza">
<span class="i0">From the white man's house, and the black man's hut,<br /></span>
<span class="i2">I carried the little body on;<br /></span>
<span class="i0">The forest's arm did round us shut,<br /></span>
<span class="i2">And silence through the trees did run:<br /></span>
<span class="i0">They asked no question as I went,<br /></span>
<span class="i0">They stood too high for astonishment,<br /></span>
<span class="i2">They could see God sit on his throne.<br /></span>
</div><div class="stanza">
<span class="i0">* * * * * * * * * * * * * * * * * * *<br /></span>
</div><div class="stanza">
<span class="i0">(Man, drop that stone you dared to lift!&mdash;)<br /></span>
<span class="i2">I wish you who stand there five abreast,<br /></span>
<span class="i0">Each, for his own wife's joy and gift,<br /></span>
<span class="i2">A little corpse as safely at rest<br /></span>
<span class="i0">As mine in the mangoes: Yes, but <i>she</i><br /></span>
<span class="i0">My keep live babies on her knee,<br /></span>
<span class="i2">And sing the song she likes the best.<br /></span>
</div></div>

<p>In such a review as this of the connections between Mrs. Browning and
the Negro one can not help coming face to face with the question
whether her famous husband was not himself connected by blood with the
Negro race. The strain is hardly so pronounced as in men like
Alexandre Dumas<span class='pagenum'><a name="Page_28" id="Page_28">[Pg 28]</a></span> or Leigh Hunt, and as in the case of Alexander
Hamilton, the point still seems to be waiting for final proof. The
assertion is persistent, however, and there can be little doubt that
such is the case. The standard life of Browning,<a name="FNanchor_15_15" id="FNanchor_15_15"></a><a href="#Footnote_15_15" class="fnanchor">[15]</a> after wrestling
in vain with the problem, dismisses it as follows:</p>

<blockquote><p>Dr. Furnivall has originated a theory, and maintains it as a
conviction, that Mr. Browning's grandmother was more than a
Creole in the strict sense of the term, that of a person born of
white parents in the West Indies, and that an unmistakable dash
of dark blood passed from her to her son and grandson. Such an
occurrence was, on the face of it, not impossible, and would be
absolutely unimportant to my mind, and, I think I may add, to
that of Mr. Browning's sister and son. The poet and his father
were what we know them, and if Negro blood had any part in their
composition, it was no worse for them, and so much the better for
the Negro.</p></blockquote>

<p>Aside from this last point, from the evidence that has been given,
while this of course has its limitations, we may safely assert that
with her large humanity and her enthusiasm for liberty, Elizabeth
Barrett Browning was one of the sturdiest defenders in England of the
cause of the American Negro at the time of the beginning of the Civil
War. It is to be regretted that she did not live to read the
Emancipation Proclamation and to see the Negro started on an era of
self-reliance and progress.</p>

<p class="author">Benjamin Brawley</p>

