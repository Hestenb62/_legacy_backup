<div class="footnote"><p><a name="Footnote_527_527" id="Footnote_527_527"></a><a href="#FNanchor_527_527"><span class="label">[527]</span></a> Professor Miller is a product of Howard and one of her
most distinguished sons. He was graduated from Preparatory Department
in 1882 and from College in 1886 after which he pursued advanced
studies at Johns Hopkins University. He is one of the most conspicuous
publicists of the race, being the author of several books and numerous
pamphlets, beside making frequent contributions to periodicals, both
in America and abroad. His most important books are <i>Race Adjustment</i>
and <i>Out of the House of Bondage. The Disgrace of Democracy</i>, an open
letter to President Wilson, published in 1917, has been pronounced one
of the most important documents produced by the great war.</p></div>

<div class="footnote"><p><a name="Footnote_528_528" id="Footnote_528_528"></a><a href="#FNanchor_528_528"><span class="label">[528]</span></a> Dr. Newman was graduated from Bowdoin College, the alma
