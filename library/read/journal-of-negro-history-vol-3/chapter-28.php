finishing in 1871. He served as pastor in Taunton, Massachusetts,
Ripon, Wisconsin and the First Congregational Church of Washington,
District of Columbia. He was president of Eastern College, Fort Royal,
Virginia, 1908-9, and Kee Mar College for Women, Hagerstown, Maryland,
1909-11. He is a member of a number of learned societies and a
distinguished pulpit orator.</p></div>

