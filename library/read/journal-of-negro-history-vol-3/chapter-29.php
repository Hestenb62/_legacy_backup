<p>On the question to postpone, it passed in the negative (Ayes&mdash;5;
noes&mdash;5;)</p>

<p>It was moved and seconded to agree to the first clause of the
resolution namely.</p>

<p>"That in order to ascertain the alterations that may happen in
the population and wealth of the several States a "Census shall
be taken of each State"</p>

<p>which passed in the affirmative (Ayes&mdash;6; noes&mdash;4.)</p>

<p>(To adjourn. Ayes&mdash;1; noes&mdash;9.)</p>

<p>It was moved and seconded to agree to the following clause of the
resolution, namely</p>

<p>"and three fifths of the inhabitants of other description"</p>

<p>which passed in the negative. (Ayes&mdash;4; noes&mdash;6.)</p>

<p>It was moved and seconded to agree to the following clause of the
resolution, namely</p>

<p>"On the first year after this form of government shall "have been
