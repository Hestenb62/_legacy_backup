<p>which passed unanimously in the affirmative (Ayes&mdash;10; noes&mdash;0.)<span class='pagenum'><a name="Page_392" id="Page_392">[Pg 392]</a></span>
On the question to agree to the resolution as amended it passed
unanimously in the negative. (Ayes&mdash;0; noes&mdash;10.) and then the
House adjourned till tomorrow at 11 o'clock A.M.<a name="FNanchor_545_545" id="FNanchor_545_545"></a><a href="#Footnote_545_545" class="fnanchor">[545]</a></p></blockquote>

<p>Taking up the question, Mr. Williamson urged again on the eleventh of
July the counting of five Negroes as three white persons.</p>

<blockquote><p>Mr. Williamson was for making it the duty of the Legislature to
do what was right &amp; not leaving it at liberty to do or not do it.
He moved that Mr. Randolph's proposition be postponed, in order
to consider the following "that in order to ascertain the
alterations that may happen in the population &amp; wealth of the
several States, a census shall be taken of the free white
inhabitants and 3/5ths of those of other descriptions on the 1st
year (after this Government shall have been adopted) and every
year thereafter; and that the Representation be regulated
accordingly.<a name="FNanchor_546_546" id="FNanchor_546_546"></a><a href="#Footnote_546_546" class="fnanchor">[546]</a></p></blockquote>

<hr class="short" />

<blockquote><p>Mr. Butler &amp; Genl. Pinkney insisted that blacks be included in
