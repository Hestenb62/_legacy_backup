noes&mdash;0.)</p>

<p>It was moved and seconded to add after the words fifteen years
the words "at least"</p>

<p>which passed in the negative (Ayes&mdash;5; noes&mdash;5.)</p>

<p>It was moved and seconded to agree to the following clause of the
resolution namely</p>

<p>"and the Legislature shall alter or augment the representation
