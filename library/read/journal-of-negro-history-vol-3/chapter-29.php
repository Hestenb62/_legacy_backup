<h3><a name="No4_a6" id="No4_a6"></a>
WHAT THE FRAMERS OF THE FEDERAL CONSTITUTION THOUGHT OF THE NEGRO</h3>


<p>The first important discussion in the Convention of 1787 to reflect
the attitude of the framers of the Federal Constitution toward the
Negro, was whether or not slaves should be considered a part of the
population in apportioning representation in Congress on that basis. A
precedent had been set in the Articles of Confederation in the
provision for counting five slaves as three whites to determine the
rate of taxation on the population basis. The free States contended
that only the free inhabitants should be counted, but the slave States
urged the recognition of slaves as a part of the population to secure
to the South the power which it wielded until the Civil War.<a name="FNanchor_530_530" id="FNanchor_530_530"></a><a href="#Footnote_530_530" class="fnanchor">[530]</a></p>

<p>Taking up this important question soon after the convention assembled,</p>

<blockquote><p>The following resolution was then moved by Mr. Randolph, Resolved
that the rights of suffrage in the national legislature ought to
be proportioned to the quotas of contribution, or to the number
of free inhabitants, as the one or the other rule may seem best
in different cases.</p>

<p>It was moved by Mr. Hamilton seconded by Mr. Spaight that the
resolution be altered so as to read</p>

<p>Resolved that the rights of suffrage in the national legislature
ought to be proportioned to the number of free inhabitants</p>

<p>It was moved and seconded that the resolution be postponed&mdash;and
on the question to postpone it passed in the affirmative</p>

<p>The following resolution was moved by Mr. Randolph seconded by Mr
Madison<span class='pagenum'><a name="Page_382" id="Page_382">[Pg 382]</a></span> Resolved that the rights of suffrage in the national
legislature ought to be proportioned&mdash;it was moved and seconded
to add the words "and not according to the present system"&mdash;On
the question to agree to the amendment it passed in the
affirmative. (Ayes&mdash;7 noes&mdash;0.)<a name="FNanchor_531_531" id="FNanchor_531_531"></a><a href="#Footnote_531_531" class="fnanchor">[531]</a></p>

<p>It was then moved and seconded so to alter the resolution that it
should read</p>

<p>Resolved that the rights of suffrage in the national legislature
ought not to be according</p>

<p>It was then moved and seconded to postpone the consideration of
the last resolution&mdash;And, on the question to postpone, it passed
in the affirmative The following resolution was then moved by Mr
Madison seconded by Mr. G Morris.</p>

<p>Resolved that the equality of suffrage established by the
articles of confederation ought not to prevail in the national
legislature and that an equitable ratio of representation ought
to be substituted.</p>

<p>It was moved and seconded to postpone the consideration of the
last resolution.</p>

<p>(The following Resolution being the 2d. of those proposed by Mr.
Randolph was taken up. viz&mdash;"that the rights of suffrage in the
National Legislature ought to be proportioned to the quotas of
contribution, or to the number of free inhabitants, as the one or
the other rule may seem best in different cases.")</p>

<p>Mr. M(adison) observing that the words ("<i>or to the number of</i>)
<i>free inhabitants</i>." might occasion debates which would divert
the Committee from the general question whether the principle of
representation should be changed, moved that they might be struck
out.</p>

<p>Mr King observed that the quotas of contribution which would
alone remain as the measure of representation, would not answer;
because waving every other view of the matter, the revenue might
hereafter be so collected by the general Govt. that the sums
respectively drawn from the States would (not) appear; and would
besides be continually varying.</p>

<p>Mr. Madison admitted the propriety of the observation, and that
some better rule ought to be found.</p>

<p>Col. Hamilton moved to alter the resolution so as to read "that
the rights of suffrage in the national Legislature ought to be
proportioned<span class='pagenum'><a name="Page_383" id="Page_383">[Pg 383]</a></span> to the number of free inhabitants. Mr. Spaight
2ded. the motion.</p>

<p>It was then moved that the Resolution be postponed, which was
agreed to.</p>

<p>Mr. Randolph and Mr. Madison then moved the following
resolution&mdash;"that the rights of suffrage in the national
Legislature ought to be proportioned."</p>

<p>It was moved and 2ded to amend it by adding "and not according to
the present system"&mdash;which was agreed to.</p>

<p>It was then moved and 2ded. to alter the resolution so as to read
"that the rights of suffrage in the national Legislature ought
not to be according to the present system."</p>

<p>It was then moved &amp; 2ded. to postpone the Resolution moved by Mr.
Randolph &amp; Mr. Madison, which being agreed to;</p>

<p>Mr. Madison, moved, in order to get over the difficulties, the
following resolution&mdash;"that the equality of suffrage established
by the articles of Confederation ought not to prevail in the
national Legislature, and that an equitable ratio of
representation ought to be submitted" This was 2ded. by Mr. Govr.
Morris, (and being generally relished, would have been agreed to
when,)</p>

<p>Mr. Reed moved that the whole clause relating to the point of
Representation be postponed; reminding the Come. that the
deputies from Delaware were restrained by their commission from
assenting to any change of the rule of suffrage, and in case a
change should be fixed on, it might become their duty to retire
from the Convention.</p>

<p>Mr. Govr. Morris observed that the valuable assistance of those
members could not be lost without real concern, and that so early
a proof of discord in the convention as a secession of a State,
would add much to the regret; that the change proposed was
however so fundamental an article in a national Govt. that it
could not be dispensed with.</p>

<p>Mr. M(adison) observed that whatever reason might have existed
for the equality of suffrage when the Union was a federal one
among sovereign States, it must cease when a national Governt.
should be put into the place. In the former case, the acts of
Congs. depended so much for their efficacy on the cooperation of
the States, that these had a weight both within &amp; without
Congress, nearly in proportion to their extent and importance. In
the latter case, as the acts of the Genl. Govt. would take effect
without the<span class='pagenum'><a name="Page_384" id="Page_384">[Pg 384]</a></span> intervention of the State legislatures, a vote from
a small State wd. have the same efficacy &amp; importance as (a vote)
from a large one, and there was the same reason for (different
numbers) of representatives from different States, as from
Counties of different extents within particular States. He
suggested as an expedient for at once taking the sense of the
members on this point and saving the Delaware deputies from
embarrassment, that the question should be taken in Committee,
and the clause on report to the House (be postponed without a
question there). This however did not appear to satisfy Mr. Read.</p>

<p>By several it was observed that no just construction of the Act
of Delaware, could require or justify a secession of her
deputies, even if the resolution were to be carried thro' the
House as well as the Committee. It was finally agreed however
that the clause should be postponed: it being understood that in
the event the proposed change of representation would certainly
be agreed to, no objection or difficulty being started from any
other quarter (than from Delaware).</p>

<p>The motion of Mr. Read to postpone being agreed to</p>

<p>The Committee then rose. The chairman reported progress, and the
House having resolved to resume the subject in Committee
tomorrow,<a name="FNanchor_532_532" id="FNanchor_532_532"></a><a href="#Footnote_532_532" class="fnanchor">[532]</a></p>

<p class="center">(Adjourned to 10 OClock)</p>
</blockquote>

<hr class="short" />

<p>The next question was on the following resolve:</p>

<blockquote><p>In substance that the mode of the present representation was
unjust&mdash;the suffrage ought to be in proportion to number or
property.</p>

<p>To this Delaware objected, in consequence of the restrictions in
their credentials, and moved to have the consideration thereof
postponed, to which the house agreed.<a name="FNanchor_533_533" id="FNanchor_533_533"></a><a href="#Footnote_533_533" class="fnanchor">[533]</a></p></blockquote>

<p>McHenry records for the thirtieth of May that the Committee then
proceeded to consider the second resolution in Mr. Randolph's paper.</p>

<blockquote><p>That the rights of suffrage in the national legislature ought to
be proportioned to the quotas of contribution or to the number
of<span class='pagenum'><a name="Page_385" id="Page_385">[Pg 385]</a></span> free inhabitants as the one or the other rule may seem best
in different cases.</p>

<p>As this gave the large States the most absolute controul over the
lesser ones it met with opposition which produced an adjournment
without any determination.<a name="FNanchor_534_534" id="FNanchor_534_534"></a><a href="#Footnote_534_534" class="fnanchor">[534]</a></p></blockquote>

<p>After frequent discussion and the failure to reach an agreement to
safeguard the interests of the small States while giving due weight to
the population of the large the effort to apportion representation in
the national legislature assumed this form in the Committee of the
Whole:</p>

<blockquote><p>It was moved by Mr. King, seconded by Mr Rutledge to agree to the
following resolution, namely:</p>

<p>Resolved that the right of suffrage in the first branch of the
national Legislature ought not to be according to the rule
established in the articles of confederation; but according to
some equitable ratio of representation</p>

<p>And on the question to agree to the same</p>

<p>it passed in the affirmative (Ayes&mdash;7; noes&mdash;3; divided&mdash;1.)</p>

<p>It was then moved by Mr. Rutledge seconded by Mr Butler to add
the following words to the last resolution</p>

<p>"namely, according to the quotas of contribution"</p>

<p>It was moved by Mr Wilson seconded by Mr C. Pinckney to postpone
the consideration of the last motion in order to introduce the
following words, after the words "equitable ratio of
representation" namely.</p>

<p>"in proportion to the whole number of white and other 'free
Citizens' and inhabitants of every age, sex and condition,
'including those bound to servitude for a term of years', and
three fifths of all other persons not comprehended in the
foregoing description, except Indians, not paying taxes 'in each
State.'"</p>

<p>On the question to postpone</p>

<p>it passed in the affirmative. (Ayes&mdash;10; noes&mdash;1.)</p>

<p>On the question to agree to Mr Wilson's motion</p>

<p>It passed in the affirmative (Ayes&mdash;9; noes&mdash;2.)</p>

<p>It was then moved by Mr Wilson seconded by Mr Hamilton to adopt
the following resolution, namely,</p>

<p>"resolved that the right of suffrage in the second branch "of the
national Legislature ought to be according to the rule
"established for the first"<span class='pagenum'><a name="Page_386" id="Page_386">[Pg 386]</a></span></p>

<p>On the question to agree to the same it passed in the affirmative
(Ayes&mdash;6; noes&mdash;5.)<a name="FNanchor_535_535" id="FNanchor_535_535"></a><a href="#Footnote_535_535" class="fnanchor">[535]</a></p></blockquote>

<p>In the Committee of the Whole on the eleventh of June:</p>

<blockquote><p>It was then moved by Mr. Rutlidge 2ded. by Mr. Butler to add to
the words "equitable ratio of representation" at the end of the
motion just agreed to, the words "according to the quotas of
Contribution. On motion of</p>

<p><i>Mr. Wilson</i> seconded by Mr. C. Pinckney, this was postponed; in
order to add, after, after the words "equitable ratio of
representation" the words following "in proportion to the whole
number of white &amp; other free Citizens &amp; inhabitants of every age
sex &amp; condition including those bound to servitude for a term of
years and three fifths of all other persons not comprehended in
the foregoing description, except Indians not paying taxes, in
each State." this being the rule in the Act of Congress agreed to
by eleven States, for apportioning quotas of revenue on the
States, and requiring a census only every 5&mdash;7, or 10 years.</p>

<p>Mr. Gerry thought property not the rule of representation. Why
then shd, the blacks, who were property in the South be in the
rule of representation more than the cattle &amp; horses of the
North.</p>

<p>On the question.</p>

<p>Mass: Con: N. Y. Pen: Maryd. Virga. N. C. S. C. and Geo: were in
the affirmative: N. J. &amp; Del: in the negative. (Ayes&mdash;9;
noes&mdash;2.) Mr. Sherman moved that a question be taken whether each
State shall have (one) vote in the 2d. branch. Every thing he
said depended on this. The smaller States would never agree to
the plan on any other principle (than an equality of suffrage in
this branch. Mr. Ellsworth seconded the motion.) On the question
for allowing each State (one) vote in the 2d. branch.</p>

<p>Massts, no. Cont, ay. N. Y. ay. N. J. ay. Pa. no. Del. ay Md. ay.
Va. no. N. C. no. S. C. no. Geo. no. (Ayes&mdash;5; noes&mdash;6.)</p>

<p>(Mr. Wilson &amp; Mr. Hamilton moved that the right of suffrage in
the 2d. branch ought to be according to the same rule as in the
1st. branch.)</p>

<p>On this question for making the ratio of representation the same
in the 2d. as in the 1st. branch (it passed in the affirmative:)
Massts. ay. Cont. no. N. Y. no. N. J. no. Pa. ay. Del. no. Md.
no. Va. ay. N. C. ay. S. C. ay. Geo. ay. (Ayes&mdash;6; noes&mdash;5.)<a name="FNanchor_536_536" id="FNanchor_536_536"></a><a href="#Footnote_536_536" class="fnanchor">[536]</a></p></blockquote><p><span class='pagenum'><a name="Page_387" id="Page_387">[Pg 387]</a></span></p>

<p>On the same day</p>

<blockquote><p>Mr. Wilson was of opinion, and therefore moved, <i>that the mode of
representation of each of the states ought to be from the number
of its free inhabitants, and of every other description three
fifths to one free inhabitant</i>. He supposed that the impost will
not be the only revenue&mdash;the post office he supposes would be
another substantial source of revenue. He observed further, that
this mode had already received the approbation of eleven states
in their acquiescence to the quota made by congress. He admitted
that this resolve would require further restrictions, for where
numbers determined the representation a census at different
periods of 5, 7 or 10 years, ought to be taken.</p>

<p>Mr. Gerry. The idea of property ought not to be the rule of
representation. Blacks are property, and are used to the
southward as horses and cattle to the northward; and why should
their representation be increased to the southward on account of
the number of slaves, than horses or oxen to the north?</p>

<p>Mr. Madison was of opinion at present, to fix the standard of
representation, and let the detail be the business of a
sub-committee.</p>

<p>Mr. Rutledge's motion was postponed.<a name="FNanchor_537_537" id="FNanchor_537_537"></a><a href="#Footnote_537_537" class="fnanchor">[537]</a></p></blockquote>

<p>Discussing whether the apportionment should be according to taxation
or numbers, Wilson considered</p>

<blockquote><p>Either Rule good&mdash;by Numbers best to ascertain the Right of
Representn. this agreeably to the Sentiments of 11 States&mdash;Impost
alone will not be sufficient to answer the national
Exigencies&mdash;Revenues arising from Postage&mdash;The present Quota not
a lasting Rule&mdash;People to be numbered at fixed Periods&mdash;A Rule
arising from Property and Numbers&mdash;</p>

<p>Gerry. Rule of Taxation not the Rule of Representation&mdash;4 might
then have more Voices than ten&mdash;Slaves not to be put upon the
Footing of freemen&mdash;Freemen of Massts. not to be put upon a
Footing with the Slaves of other States&mdash;Horses and Cattle ought
to have the Right of Representn. Negroes&mdash;Whites&mdash;<a name="FNanchor_538_538" id="FNanchor_538_538"></a><a href="#Footnote_538_538" class="fnanchor">[538]</a></p></blockquote>

<p>On the thirteenth of June Randolph submitted another resolution agreed
to in the Committee of the Whole.<span class='pagenum'><a name="Page_388" id="Page_388">[Pg 388]</a></span></p>

<blockquote><p>Resolved that the right of suffrage in the first branch of the
national Legislature ought not to be according to the rule
established in the articles of confederation; but according to
some equitable ratio of representation&mdash;namely in proportion to
the whole number of whites and other free citizens and
inhabitants, of every age, sex and condition, including those
bound to servitude for a term of years and three fifths of all
other persons not comprehended in the foregoing description,
except Indians, not paying taxes in each State.<a name="FNanchor_539_539" id="FNanchor_539_539"></a><a href="#Footnote_539_539" class="fnanchor">[539]</a></p></blockquote>

<p>The following propositions from New Jersey moved by Patterson closely
connected the apportionment of requisitions with that of
representation:</p>

<blockquote><p>3. Resd. that whenever requisitions shall be necessary, instead
of the rule for making requisitions mentioned in the articles of
Confederation, the United States in Congs. be authorized to make
such requisitions in proportion to the whole number of white &amp;
other free citizens &amp; inhabitants of every age sex and condition
including those bound to servitude for a term of years &amp; three
fifths of all other persons not comprehended in the foregoing
description, except Indians not paying taxes; that if such
requisitions be not compiled with, in the time specified therein,
to direct the collection thereof in the non complying States &amp;
for that purpose to devise and pass acts directing &amp; authorizing
the same; provided that none of the powers hereby vested in the
U. States in Congs. shall be exercised without the consent of at
least<a name="FNanchor_540_540" id="FNanchor_540_540"></a><a href="#Footnote_540_540" class="fnanchor">[540]</a></p></blockquote>

<p>Again on the fifteenth of June it was suggested that</p>

<blockquote><p>3. The rule of apportioning Requis: on the States shall be the
Whites 3/5 of all others&mdash;if the Req. is in arrear in any State,
Congress shall have authority to devise &amp; pass acts remedial in
such case.</p></blockquote>

<p>On the fifth of July the committee considering the question of
representation reported on the 40,000 basis which repeatedly came
before the Convention. It provided:</p>

<blockquote><p>That in the first branch of the legislature, each of the states
now in the union, be allowed one member for every 40,000
inhabitants,<span class='pagenum'><a name="Page_389" id="Page_389">[Pg 389]</a></span> of the description reported in the seventh
resolution of the committee of the whole house&mdash;That each state,
not containing that number, shall be allowed one member.<a name="FNanchor_541_541" id="FNanchor_541_541"></a><a href="#Footnote_541_541" class="fnanchor">[541]</a></p></blockquote>

<p>Reporting on this question the fifth of July, the Committee of the
Whole decided to submit:</p>

<blockquote><p>That the subsequent propositions be recommended to the
Convention, on condition that both shall be generally adopted.</p>

<p>1st That in the first branch of the Legislature each of the
States now in the Union be allowed one Member for every forty
thousand inhabitants of the description reported in the seventh
resolution of the Committee of the whole House. That each State
not containing that number shall be allowed one Member&mdash;That all
Bills for raising or appropriating money and for fixing the
salaries of the Officers of the Government of the United States,
shall originate in the first Branch of the Legislature, and shall
not be altered or amended by the second Branch and that no money
shall be drawn from the public Treasury but in pursuance of
appropriations to be originated by the first Branch. 2ndly That
in the second Branch of the Legislature each State shall have an
equal Veto.</p></blockquote>

<p>Discussing this question on the sixth of July:</p>

<blockquote><p>Mr. Pinkney saw no good reason for committing. The value of land
had been found on full investigation to be an impracticable rule.
The contributions of revenue including imports &amp; exports, must be
too changeable in their amount; too difficult to be adjusted; and
too injurious to the non-commercial States. The number of
inhabitants appeared to him the only just &amp; practicable rule. He
thought the blacks ought to stand on an equality with whites: But
wd.&mdash;agree to the ratio settled by Congs. He contended that
Congs. had no right under the articles of Confederation to
authorize the admission of new States; no such cases having been
provided for.<a name="FNanchor_542_542" id="FNanchor_542_542"></a><a href="#Footnote_542_542" class="fnanchor">[542]</a></p></blockquote>

<p>On the ninth of July, according to Madison, Mr. Gorham said:</p>

<blockquote><p>Some provision of this sort was necessary in the outset. The
number of blacks &amp; whites with some regard to supposed wealth<span class='pagenum'><a name="Page_390" id="Page_390">[Pg 390]</a></span>
was the general guide. Fractions could not be observed. The
Legislre. is to make alterations from time to time as justice &amp;
propriety may require. Two objections prevailed agst. the rate of
1 member for every 40,000 inhts. The 1st. was that the
Representation would soon be too numerous: the 2d. that the
Western States who may have a different interest, might if
admitted on that principal by degrees, out-vote the Atlantic.
Both these objections are removed. The number will be small in
the first instance and maybe continued so, and the Atlantic
States having ye Govt. in their own hands, may take care of their
own interest by dealing out the right of Representation in safe
proportions to the Western States. These were the views of the
Committee.<a name="FNanchor_543_543" id="FNanchor_543_543"></a><a href="#Footnote_543_543" class="fnanchor">[543]</a></p></blockquote>

<p>On the tenth of July the following interesting comment was made.</p>

<blockquote><p>Mr. Dayton observed that the line between the Northn. &amp; Southern
interest had been improperly drawn: that Pa. was the dividing
State, there being six on each side of her.</p>

<p>Genl. Pinkney urged the reduction, dwelt on the superior wealth
of the Southern States, and insisted on its having its due weight
in the Government.</p>

<p>Mr. Govr. Morris regretted the turn of the debate. The States he
found had many Representatives on the floor. Few he fears were to
be deemed the Representatives of America. He thought the Southern
States have by the report more than their share of
representation. Property ought to have its weight; but not all
the weight. If the (Southn. States are to) supply money. The
Northn. States are to spill their blood. Besides, the probable
Revenue to be expected from the S. States has been greatly
overrated. He was agst. reducing N. Hampshire.<a name="FNanchor_544_544" id="FNanchor_544_544"></a><a href="#Footnote_544_544" class="fnanchor">[544]</a></p></blockquote>

