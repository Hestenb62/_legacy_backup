<p><i>German East Africa</i>, by A. F. Calvert, has been published by Werner
Laurie, London.</p>

<p>Messrs. Routledge, of London, will soon bring out a volume of <i>Select
Constitutional Documents Illustrating the History of South Africa</i>.</p>

<p>Dr. H. K. W. Kumm's history of modern missionary work has appeared
with imprint of MacMillan with the title <i>African Missionary Heroes
and Heroines</i>.</p>

<p>Doubleday, Page and Company announce the appearance of <i>Education and
Life</i>, by Doctor Francis Greenwood Peabody, of Harvard University.
This is a short history of Hampton Institute during the last fifty
years, prepared at the request of the trustees.</p>


