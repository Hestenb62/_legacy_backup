<p class="hang"><i>Fifty Years and Other Poems.</i> By <span class="smcap">James Weldon Johnson</span>. With an
Introduction by <span class="smcap">Brander Matthews</span>. The Cornhill Co., Boston, 1917. Pp.
xiv, 92.</p>

<p>From time to time for the last fifteen years Mr. James Weldon Johnson
has been remarked as one of the literary men of the race. He has now
brought together his verses in a little volume, <i>Fifty Years and Other
Poems</i>, an introduction to which has been written by Professor Brander
Matthews, of Columbia University. The task was eminently worth while.</p>

<p>The book falls into two parts. The first is made up of poems in the
commonly accepted forms, though there are one or two<span class='pagenum'><a name="Page_203" id="Page_203">[Pg 203]</a></span> examples of
<i>vers libre</i>; and the second is entitled <i>Jingles and Croons</i>. This
second division consists of dialect verses, especially the songs that
have been set to music, most frequently by the poet's brother, Mr. J.
Rosamond Johnson. Outstanding are the very first lines, <i>Since you
went away</i>. It is well that these pieces have been brought together.
For artistic achievement, however, attention will naturally be fixed
upon the first division. <i>Fifty Years</i> was written in honor of the
fiftieth anniversary of the emancipation of the race. Professor
Matthews speaks of it as "one of the noblest commemorative poems yet
written by any American&mdash;a poem sonorous in its diction, vigorous in
its workmanship, elevated in its imagination, and sincere in its
emotion." This is high praise, and yet it may reasonably be asked if
there are not in the book at least four pieces of finer poetic
quality. These are, first of all, the two poems that originally
appeared in the Century, <i>Mother Night</i> and <i>O Black and Unknown
Bards</i>, and <i>The White Witch</i> and <i>The Young Warrior</i>. The first of
these four poems is a sonnet well rounded out. The second gains merit
by reason of its strong first and last two stanzas. <i>The White Witch</i>
chooses a delicate and difficult theme, but contains some very strong
stanzas. <i>The Young Warrior</i> is a poem of rugged strength and one that
deserves all the popularity it has achieved with Mr. Burleigh's
musical setting. Mr. Johnson is strongest in the simple, direct, and
sometimes sensuous expression that characterizes these latter poems,
and it is to be hoped that he may have the time and the inclination to
write many more like them.</p>

<p class="author">Benjamin Brawley.</p>

