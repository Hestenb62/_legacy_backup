operations of the bureau brought upon General Howard charges of
malfeasance, which led to two investigations, it should be said here
that both of the official investigations, one civil, the other
military, completely exonerated him.&mdash;See <i>Report of Special Committee
of the Trustees of Howard University upon Certain Charges</i>, etc.,
1873, and <i>Act of March 3, 1865, establishing the Bureau of Refugees,
Freedmen and Abandoned Lands</i>.</p></div>

