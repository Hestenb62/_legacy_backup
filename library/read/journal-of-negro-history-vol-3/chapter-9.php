<h2><a name="No1_a10" id="No1_a10"></a>
NOTES</h2>


<p>The local club of the Association for the Study of Negro Life and
History is now making a serious study of Negro American History under
the direction of Dr. Carter G. Woodson. The work was begun in November
and will be completed in February. The phases of history to be
considered are: <i>The Negro in Africa</i>, <i>The Enslavement of the Negro</i>,
<i>Patriarchal Slavery in America</i>, <i>Slavery and the Rights of Man</i>,
<i>The Reaction against the Negro</i>, <i>Slavery as an Economic
Institution</i>, <i>The Free Negro in the United States</i>, <i>The Abolition
Movement</i>, <i>The Colonization Project</i>, <i>Slavery and the Constitution</i>,
<i>The Negro in the Civil War</i>, <i>The Reconstruction of the Southern
States</i>, <i>The Negro in Freedom</i>, <i>The Negro and Social Justice</i>.</p>

<p>Dodd, Mead and Company will soon publish for Professor Benjamin G.
Brawley a work entitled <i>The Genius of the Negro</i>. The aim of the book
will be to set forth what the Negro has done in literature, art and
the like.</p>

<p>Longmans, Green and Company have published <i>The Education of the
African Native</i>. This will throw light on the much mooted question as
to what the Europeans have done to promote the mental development of
the native of the dark continent.</p>

<p>In the seventh volume of the <i>Documentos para la Historia Argentina</i>
are found materials bearing on the <i>Comercio de Indias, Consualdo,
Comercio de Negros y Extranjeros</i>, 1791-1809.</p>

<p>The June number of the <i>Political Science Quarterly</i> contained an
article <i>The Negro Vote in Old New York</i> by D. E. Fox.</p>

