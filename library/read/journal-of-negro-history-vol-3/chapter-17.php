<p>Dean Benjamin P. Brawley, of Morehouse College, has brought out a new
work entitled <i>The Negro in Literature and Art</i>, published by Duffield
and Company, New York City. It was incorrectly reported in our last
issue that this work was to be published by Dodd, Mead and Company.</p>

<hr class="short" />

<p>Dean Brawley contributed to the <i>Sewanee Review</i> for January an
article entitled <i>Richard le Gallienne and the Tradition of Beauty</i>.
This is a literary study of merit.</p>

<hr class="short" />

<p>Dr. James H. Dillard contributed to <i>School and Society</i> an article
entitled <i>County Machinery for Colored Schools in the South</i>. It
contains information both helpful and valuable to persons interested
in the education of the Negro.</p>

